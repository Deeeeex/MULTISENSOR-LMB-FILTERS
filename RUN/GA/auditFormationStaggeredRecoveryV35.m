function [reportPath, audit] = ...
    auditFormationStaggeredRecoveryV35(options)
% AUDITFORMATIONSTAGGEREDRECOVERYV35 Freeze the primary v35 finding.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v35', 'staggered_recovery', 't72', 'screen', ...
    ['FORMATION_STAGGERED_RECOVERY_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'FORMATION_STAGGERED_RECOVERY_V35_AUDIT_20260802.md'));
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V35Audit:MissingScreen', ...
        'Frozen v35 primary screen is unavailable.');
end
screen = loaded.screen;
assertScreenProvenance(screen);

referenceIdx = screen.referenceSubsetIndex;
candidateIdx = setdiff(1:numel(screen.records), referenceIdx);
if numel(candidateIdx) ~= 1
    error('V35Audit:UnexpectedArmCount', ...
        'The frozen v35 screen must contain one candidate arm.');
end
reference = screen.outcomes(referenceIdx);
candidate = screen.outcomes(candidateIdx);
record = screen.records(candidateIdx);
trackingReferenceByTime = mean( ...
    reference.eospaBySensorTime, 1);
trackingCandidateByTime = mean( ...
    candidate.eospaBySensorTime, 1);
trackingGainByTimePercent = relativeGain( ...
    trackingReferenceByTime, trackingCandidateByTime);
consensusGainByTimePercent = relativeGain( ...
    reference.consensusOspaByTime, ...
    candidate.consensusOspaByTime);
attemptedByteSavingByTimePercent = relativeGain( ...
    reference.attemptedBytesByTime, ...
    candidate.attemptedBytesByTime);

audit = struct();
audit.contractVersion = ...
    'formation-staggered-recovery-v35-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourcePreflightGenerationCommit = ...
    screen.sourcePreflightGenerationCommit;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.returnTimes = screen.returnTimes;
audit.referenceIndex = referenceIdx;
audit.candidateIndex = candidateIdx;
audit.runtimeSelectedFormationIdsByTime = ...
    candidate.retentionDebtSelectedFormationIdsByTime;
audit.runtimeReleasedFormationIdsByTime = ...
    candidate.retentionDebtProjectionRemovalOrderByTime;
audit.meanGainPercent = record.meanGainPercent;
audit.worstSensorGainPercent = record.worstGainPercent;
audit.formationGainPercent = record.formationGainPercent;
audit.minimumFormationGainPercent = ...
    record.minimumFormationGainPercent;
audit.windowConsensusGainPercent = record.consensusGainPercent;
audit.terminalConsensusGainPercent = ...
    record.terminalConsensusGainPercent;
audit.attemptedByteSavingPercent = ...
    record.attemptedByteSavingPercent;
audit.referenceMeanCardinalityError = ...
    reference.meanCardinalityError;
audit.candidateMeanCardinalityError = ...
    candidate.meanCardinalityError;
audit.trackingReferenceByTime = trackingReferenceByTime;
audit.trackingCandidateByTime = trackingCandidateByTime;
audit.trackingGainByTimePercent = trackingGainByTimePercent;
audit.consensusReferenceByTime = ...
    reference.consensusOspaByTime;
audit.consensusCandidateByTime = ...
    candidate.consensusOspaByTime;
audit.consensusGainByTimePercent = ...
    consensusGainByTimePercent;
audit.referenceAttemptedBytesByTime = ...
    reference.attemptedBytesByTime;
audit.candidateAttemptedBytesByTime = ...
    candidate.attemptedBytesByTime;
audit.attemptedByteSavingByTimePercent = ...
    attemptedByteSavingByTimePercent;
audit.causalTraceAttested = ...
    screen.causalStaggeredRecoveryAttested;
audit.strongCandidateCount = ...
    screen.strictStrongCandidateCount;
audit.strongGatePassed = screen.strongCandidateFound;
audit.allNumericalGatesPassed = all([ ...
    record.meanGainPercent >= ...
        screen.protocol.meanTrackingGainThresholdPercent, ...
    record.minimumFormationGainPercent >= ...
        screen.protocol.minimumFormationGainThresholdPercent, ...
    record.worstGainPercent >= ...
        screen.protocol.worstSensorGainThresholdPercent, ...
    record.consensusGainPercent >= ...
        screen.protocol.windowConsensusGainThresholdPercent, ...
    record.terminalConsensusGainPercent >= ...
        screen.protocol.terminalConsensusGainThresholdPercent, ...
    record.attemptedByteSavingPercent >= ...
        screen.protocol.minimumAttemptedByteSavingPercent]);
audit.v30MeanGainPercent = 4.3409;
audit.v30TerminalConsensusGainPercent = -1.5947;
audit.v30WindowConsensusGainPercent = 15.6057;
audit.v30AttemptedByteSavingPercent = 3.5878;
audit.terminalConsensusRepairPercentPoints = ...
    audit.terminalConsensusGainPercent - ...
        audit.v30TerminalConsensusGainPercent;
audit.additionalOpenedM24StateAuthorized = true;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This audit freezes one paired result on the already-opened ', ...
    'M24 seed-211 t=72 state. It establishes local causal headroom ', ...
    'for the fixed v35 controller and authorizes a separately frozen ', ...
    'source-only preflight on additional already-opened M24 ', ...
    'development states. It does not authorize GNN training, X36, ', ...
    'X48, reserved seeds, validation, or paper-level generalization.'];

assertMechanism(audit, screen, candidate);
writeReport(reportPath, audit);
fprintf('V35 staggered-recovery audit: %s\n', reportPath);
end

function assertScreenProvenance(screen)
if ~strcmp(screen.contractVersion, ...
        'formation-staggered-recovery-v35-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            '00a0634ca9fa84c5ab3d933501353dc1740d3c7c') || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.sourcePreflightGenerationCommit, ...
            '00a0634ca9fa84c5ab3d933501353dc1740d3c7c') || ...
        ~strcmp(screen.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(screen.presetName, 'm24-formation-fov') || ...
        screen.seed ~= 211 || screen.currentTime ~= 72 || ...
        ~isequal(screen.returnTimes, [72, 73, 74]) || ...
        ~screen.causalStaggeredRecoveryAttested || ...
        screen.strictStrongCandidateCount ~= 1 || ...
        ~screen.strongCandidateFound || ...
        ~screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V35Audit:ProvenanceMismatch', ...
        'Frozen v35 screen provenance or gate decision changed.');
end
end

function assertMechanism(audit, screen, candidate)
protocol = screen.protocol;
if ~audit.causalTraceAttested || ...
        ~audit.strongGatePassed || ...
        audit.strongCandidateCount ~= 1 || ...
        ~audit.allNumericalGatesPassed || ...
        ~isequal(audit.runtimeSelectedFormationIdsByTime, ...
            protocol.expectedRuntimeSelectedFormationIdsByTime) || ...
        ~isequal(audit.runtimeReleasedFormationIdsByTime, ...
            protocol.expectedRuntimeReleasedFormationIdsByTime) || ...
        candidate.truthUseCount ~= 0 || ...
        candidate.repairCount ~= 0 || ...
        candidate.payloadEmergencyCount ~= 0 || ...
        candidate.infeasibleCount ~= 0 || ...
        ~all(candidate.selectedSensorB3Pass) || ...
        ~all(candidate.selectedFormationB3Pass) || ...
        audit.terminalConsensusRepairPercentPoints <= 0 || ...
        audit.meanGainPercent < 4 || ...
        audit.terminalConsensusGainPercent <= 0 || ...
        audit.attemptedByteSavingPercent <= 0 || ...
        ~audit.additionalOpenedM24StateAuthorized || ...
        audit.gnnTrainingAuthorized || audit.x36Opened || ...
        audit.x48Opened || audit.validationClaimAllowed
    error('V35Audit:UnexpectedMechanism', ...
        'Frozen v35 causal mechanism or gate outcome changed.');
end
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('V35Audit:WriteFailed', ...
        'Could not open v35 audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V35 debt-coverage staggered-recovery audit\n\n');
fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    '**The frozen v35 primary gate passes with `1/1` strong ', ...
    'candidate.** The causal runtime trace is ', ...
    '`[2,3,4] -> [2,4] -> [3]`; all registered tracking, tail, ', ...
    'consensus, communication, execution, and rolling-connectivity ', ...
    'gates pass.\n\n']);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Source preflight commit: `%s`\n', ...
    audit.sourcePreflightGenerationCommit);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- Preset / seed / times: `%s / %d / %s`\n\n', ...
    audit.presetName, audit.seed, mat2str(audit.returnTimes));

fprintf(fid, '## Aggregate result\n\n');
fprintf(fid, [ ...
    '| Mean tracking | Worst sensor | Formation gains | Window consensus ', ...
    '| Terminal consensus | Byte saving | Mean card. error |\n']);
fprintf(fid, '|--:|--:|:--|--:|--:|--:|--:|\n');
fprintf(fid, [ ...
    '| %+.4f%% | %+.4f%% | `%s` | %+.4f%% | %+.4f%% | %+.4f%% ', ...
    '| %.6f -> %.6f |\n\n'], ...
    audit.meanGainPercent, audit.worstSensorGainPercent, ...
    mat2str(audit.formationGainPercent, 5), ...
    audit.windowConsensusGainPercent, ...
    audit.terminalConsensusGainPercent, ...
    audit.attemptedByteSavingPercent, ...
    audit.referenceMeanCardinalityError, ...
    audit.candidateMeanCardinalityError);

fprintf(fid, '## Temporal mechanism\n\n');
fprintf(fid, [ ...
    '| Time | Selected suspension | Reference tracking | Candidate ', ...
    'tracking | Tracking gain | Reference consensus | Candidate ', ...
    'consensus | Consensus gain | Byte saving |\n']);
fprintf(fid, '|--:|:--|--:|--:|--:|--:|--:|--:|--:|\n');
for timeIdx = 1:numel(audit.returnTimes)
    fprintf(fid, [ ...
        '| %d | `%s` | %.6f | %.6f | %+.3f%% | %.6f | %.6f ', ...
        '| %+.3f%% | %+.3f%% |\n'], ...
        audit.returnTimes(timeIdx), ...
        mat2str(audit. ...
            runtimeSelectedFormationIdsByTime{timeIdx}), ...
        audit.trackingReferenceByTime(timeIdx), ...
        audit.trackingCandidateByTime(timeIdx), ...
        audit.trackingGainByTimePercent(timeIdx), ...
        audit.consensusReferenceByTime(timeIdx), ...
        audit.consensusCandidateByTime(timeIdx), ...
        audit.consensusGainByTimePercent(timeIdx), ...
        audit.attemptedByteSavingByTimePercent(timeIdx));
end

fprintf(fid, '\n## Comparison with v30\n\n');
fprintf(fid, [ ...
    'V30 kept formations 2, 3, and 4 suspended for two steps and then ', ...
    'returned abruptly, giving `%+.4f%%` terminal-consensus gain. V35 ', ...
    'restores formation 3 at t=73, restores the older f2/f4 inputs at ', ...
    't=74, and lets the live debt rule protect f3 again. Terminal ', ...
    'consensus becomes `%+.4f%%`, a `%+.4f` percentage-point repair, ', ...
    'while mean tracking remains `%+.4f%%` and attempted-byte saving ', ...
    'remains `%+.4f%%`.\n\n'], ...
    audit.v30TerminalConsensusGainPercent, ...
    audit.terminalConsensusGainPercent, ...
    audit.terminalConsensusRepairPercentPoints, ...
    audit.meanGainPercent, audit.attemptedByteSavingPercent);

fprintf(fid, '## Next decision\n\n');
fprintf(fid, [ ...
    'A separate clean protocol may now preflight and screen additional ', ...
    'already-opened M24 development states under the unchanged v35 ', ...
    'controller. Do not train a GNN or open X36/X48 until the causal ', ...
    'headroom recurs beyond this single state.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) ./ max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
