function [datasetPath, dataset] = ...
    mergeStructuredProposalDistillationDataset(options)
% MERGESTRUCTUREDPROPOSALDISTILLATIONDATASET Merge v1 base and v2 shards.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeStructuredProposalProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official structured proposal merge requires clean source.');
end
validateFrozenFile(protocol.baseDatasetPath, ...
    protocol.baseDatasetSha256, 'base proposal dataset');
baseLoaded = load(protocol.baseDatasetPath, 'dataset');
base = baseLoaded.dataset;
if ~isequal(base.seeds, protocol.baseDatasetSeeds) || ...
        base.featuresUseTruth || base.behaviorTruthUsed || ...
        ~base.teacherTargetsUseTruth || ...
        base.teacherTargetsUseFutureOutcome
    error('Structured proposal base dataset violates contract.');
end

shardDirectory = getField(options, 'shardDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'datasets', ...
    'structured_proposal_shards'));
shards = cell(1, numel(protocol.extensionSeeds));
shardPaths = cell(size(shards));
shardSha256 = cell(size(shards));
for shardIdx = 1:numel(protocol.extensionSeeds)
    seed = protocol.extensionSeeds(shardIdx);
    shardPaths{shardIdx} = fullfile(shardDirectory, sprintf( ...
        ['rolling_safe_structured_proposal_', ...
         'm24_hard_t75_t83_seed%d_v2.mat'], seed));
    if exist(shardPaths{shardIdx}, 'file') ~= 2
        error('Missing structured proposal shard for seed %d.', seed);
    end
    shardSha256{shardIdx} = ...
        computeFileSha256(shardPaths{shardIdx});
    loaded = load(shardPaths{shardIdx}, 'dataset');
    shard = loaded.dataset;
    validateShard(shard, seed, protocol);
    shards{shardIdx} = shard;
end

dataset = base;
dataset.protocolId = protocol.id;
dataset.contractVersion = ...
    protocol.datasetContractVersion;
dataset.generatedAt = datestr(now, 31);
dataset.seeds = protocol.datasetSeeds;
dataset.designSeeds = protocol.datasetSeeds;
dataset.actionCodeSequences = ...
    protocol.actionCodeSequences;
dataset.blocks = repmat(base.blocks(1), ...
    1, protocol.expectedBlockCount);
dataset.teacherBlocks = repmat(base.teacherBlocks(1), ...
    1, protocol.expectedBlockCount);
dataset.outcomes = repmat(base.outcomes(1), ...
    1, numel(protocol.datasetSeeds));
dataset.behaviorCacheRecords = repmat( ...
    base.behaviorCacheRecords(1), ...
    1, numel(protocol.datasetSeeds));
blockCursor = 0;
for seedIdx = 1:numel(protocol.datasetSeeds)
    seed = protocol.datasetSeeds(seedIdx);
    [source, sourceSeedIdx] = ...
        sourceForSeed(base, shards, seed);
    sourceBlockIndices = find( ...
        [source.blocks.seed] == seed);
    sourceTeacherIndices = find( ...
        [source.teacherBlocks.seed] == seed);
    if numel(sourceBlockIndices) ~= ...
            numel(protocol.snapshotTimes) || ...
            numel(sourceTeacherIndices) ~= ...
                numel(protocol.snapshotTimes)
        error('Structured proposal source seed grid is incomplete.');
    end
    targetIndices = ...
        blockCursor + (1:numel(protocol.snapshotTimes));
    dataset.blocks(targetIndices) = ...
        source.blocks(sourceBlockIndices);
    dataset.teacherBlocks(targetIndices) = ...
        source.teacherBlocks(sourceTeacherIndices);
    dataset.outcomes(seedIdx) = ...
        source.outcomes( ...
            [source.outcomes.seed] == seed);
    dataset.behaviorCacheRecords(seedIdx) = ...
        source.behaviorCacheRecords(sourceSeedIdx);
    blockCursor = targetIndices(end);
end
for blockIdx = 1:numel(dataset.teacherBlocks)
    dataset.teacherBlocks(blockIdx).behaviorBlockIndex = blockIdx;
end
dataset.behaviorCacheSha256 = ...
    {dataset.behaviorCacheRecords.sha256};
if ~isequal(dataset.behaviorCacheSha256, ...
        protocol.behaviorCacheSha256)
    error('Structured proposal cache manifest changed.');
end
dataset.totalTeacherTargetCount = ...
    sum([dataset.teacherBlocks.targetCount]);
dataset.minimumTeacherTargetsPerBlock = ...
    min([dataset.teacherBlocks.targetCount]);
dataset.maximumTeacherTargetsPerBlock = ...
    max([dataset.teacherBlocks.targetCount]);
dataset.completeOfficialGrid = true;
dataset.shardSeedSubset = protocol.datasetSeeds;
dataset.sourceBaseDatasetPath = ...
    protocol.baseDatasetPath;
dataset.sourceBaseDatasetSha256 = ...
    protocol.baseDatasetSha256;
dataset.sourceExtensionShardPaths = shardPaths;
dataset.sourceExtensionShardSha256 = shardSha256;
dataset.sourceExtensionShardSetSha256 = ...
    computeTextSha256(strjoin(shardSha256, char(31)));
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.proposalModelTrained = false;
dataset.valueReturnEvaluated = false;
dataset.criticTrainingAuthorized = false;
dataset.x36Authorized = false;
dataset.evidenceBoundary = [ ...
    'The v2 M24 development dataset combines the frozen six-seed ', ...
    'truth-free-behavior artifact with three additional registered ', ...
    'design seeds. Observable features, executed behavior and ', ...
    'selected histories use no truth or future outcomes. Current-', ...
    'truth safe teacher graphs remain offline nondeployable labels. ', ...
    'No future validation seed or X36 result is included.'];

datasetPath = getField(options, ...
    'outputPath', protocol.datasetPath);
reportPath = getField(options, ...
    'reportPath', protocol.reportPath);
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
validateMergedDataset(dataset, protocol);
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Structured proposal dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);
end

function [source, sourceSeedIdx] = ...
        sourceForSeed(base, shards, seed)
if any(base.seeds == seed)
    source = base;
    sourceSeedIdx = find(base.seeds == seed, 1);
    return
end
source = struct();
sourceSeedIdx = [];
for shardIdx = 1:numel(shards)
    if isequal(shards{shardIdx}.seeds, seed)
        source = shards{shardIdx};
        sourceSeedIdx = 1;
        return
    end
end
error('No structured proposal source for seed %d.', seed);
end

function validateShard(shard, seed, protocol)
seedIdx = find(protocol.datasetSeeds == seed, 1);
if ~strcmp(shard.protocolId, protocol.id) || ...
        ~strcmp(shard.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~isequal(shard.seeds, seed) || ...
        numel(shard.blocks) ~= numel(protocol.snapshotTimes) || ...
        numel(shard.teacherBlocks) ~= ...
            numel(protocol.snapshotTimes) || ...
        ~isequal([shard.blocks.currentTime], ...
            protocol.snapshotTimes) || ...
        ~strcmp(shard.behaviorCacheSha256{1}, ...
            protocol.behaviorCacheSha256{seedIdx}) || ...
        shard.generationTrackedWorktreeDirty || ...
        shard.generationResearchWorktreeDirty || ...
        ~isempty(shard.generationUntrackedSourceFiles) || ...
        shard.featuresUseTruth || shard.behaviorTruthUsed || ...
        ~shard.teacherTargetsUseTruth || ...
        shard.teacherTargetsUseFutureOutcome
    error('Structured proposal shard %d violates contract.', seed);
end
end

function validateMergedDataset(dataset, protocol)
expectedPairs = zeros(protocol.expectedBlockCount, 2);
cursor = 0;
for seed = protocol.datasetSeeds
    for currentTime = protocol.snapshotTimes
        cursor = cursor + 1;
        expectedPairs(cursor, :) = [seed, currentTime];
    end
end
blockPairs = [[dataset.blocks.seed]', ...
    [dataset.blocks.currentTime]'];
teacherPairs = [[dataset.teacherBlocks.seed]', ...
    [dataset.teacherBlocks.currentTime]'];
if numel(dataset.blocks) ~= protocol.expectedBlockCount || ...
        numel(dataset.teacherBlocks) ~= ...
            protocol.expectedBlockCount || ...
        ~isequal(blockPairs, expectedPairs) || ...
        ~isequal(teacherPairs, expectedPairs) || ...
        dataset.minimumTeacherTargetsPerBlock < ...
            protocol.minimumTargetsPerBlock || ...
        dataset.maximumTeacherTargetsPerBlock > ...
            protocol.maximumTargetsPerBlock || ...
        dataset.featuresUseTruth || dataset.behaviorTruthUsed || ...
        ~dataset.teacherTargetsUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome || ...
        dataset.generationTrackedWorktreeDirty || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles)
    error('Structured proposal merged dataset is invalid.');
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open structured proposal dataset report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Structured proposal distillation dataset: M24 v2\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Base dataset SHA-256: `%s`\n', ...
    dataset.sourceBaseDatasetSha256);
fprintf(fid, '- Extension shard-set SHA-256: `%s`\n', ...
    dataset.sourceExtensionShardSetSha256);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%d:%d`\n', ...
    dataset.snapshotTimes(1), dataset.snapshotTimes(end));
fprintf(fid, '- State blocks / teacher targets: `%d / %d`\n', ...
    numel(dataset.blocks), dataset.totalTeacherTargetCount);
fprintf(fid, '- Targets per block min/max: `%d / %d`\n', ...
    dataset.minimumTeacherTargetsPerBlock, ...
    dataset.maximumTeacherTargetsPerBlock);
fprintf(fid, '- Behavior/feature truth used: `%d / %d`\n', ...
    dataset.behaviorTruthUsed, dataset.featuresUseTruth);
fprintf(fid, '- Teacher truth/future used: `%d / %d`\n', ...
    dataset.teacherTargetsUseTruth, ...
    dataset.teacherTargetsUseFutureOutcome);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, '| Seed | Blocks | Targets | Behavior E-OSPA | Worst node |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|\n');
for seed = dataset.seeds
    blockMask = [dataset.blocks.seed] == seed;
    teacherMask = [dataset.teacherBlocks.seed] == seed;
    outcome = dataset.outcomes( ...
        [dataset.outcomes.seed] == seed);
    fprintf(fid, '| %d | %d | %d | %.4f | %.4f |\n', ...
        seed, nnz(blockMask), ...
        sum([dataset.teacherBlocks(teacherMask).targetCount]), ...
        outcome.meanEospa, outcome.worstSensorEospa);
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
