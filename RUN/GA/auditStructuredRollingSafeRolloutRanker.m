function [reportPath, result] = ...
    auditStructuredRollingSafeRolloutRanker(datasetPath, options)
% AUDITSTRUCTUREDROLLINGSAFEROLLOUTRANKER Test edge-ranking learnability.
%
% This diagnostic supplies the recorded target cardinality to a linear,
% block-weighted structured edge ranker, then replays the exact online
% rolling-B3 projector. It isolates edge-ranking generalization from the
% still under-supported cardinality problem. Oracle-k makes the resulting
% model non-deployable by construction.

if nargin < 1 || isempty(datasetPath)
    datasetPath = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'datasets', ...
        'rolling_safe_rollout_imitation_m24_hard_t75.mat');
end
if nargin < 2 || isempty(options)
    options = struct();
end
loaded = load(datasetPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Structured rolling-safe audit dataset is missing.');
end
dataset = loaded.dataset;
protocol = getRollingSafeRolloutProtocol();
validateDataset(dataset, protocol);

requestedFeatureContext = lower(strrep(char(getField( ...
    options, 'featureContextMode', ...
    protocol.featureContextMode)), '_', '-'));
[blocks, featureNames, featureContextMode] = ...
    prepareFeatureContext(dataset, requestedFeatureContext);
excludedNames = reshape(getField( ...
    options, 'excludedFeatureNames', ...
    protocol.excludedFeatureNames), 1, []);
if ~isempty(setdiff(excludedNames, dataset.featureNames))
    error('Structured rolling-safe audit has unknown exclusions.');
end
[featureMask, expandedExcludedNames] = ...
    buildFeatureMask(featureNames, excludedNames);
if ~any(featureMask)
    error('Structured rolling-safe audit retained no features.');
end
trainingSeeds = protocol.trainingSeeds;
auditSeeds = protocol.auditSeeds;
lambdaGrid = reshape(getField( ...
    options, 'lambdaGrid', [0.001, 0.01]), 1, []);
epochCount = max(1, round(getField( ...
    options, 'epochCount', 30)));
learningRate = getField(options, 'learningRate', 0.25);
lossScale = getField(options, 'lossScale', 1);
if isempty(lambdaGrid) || any(~isfinite(lambdaGrid)) || ...
        any(lambdaGrid < 0)
    error('Structured rolling-safe lambda grid is invalid.');
end

candidates = repmat(emptyCandidate(), 1, numel(lambdaGrid));
for lambdaIdx = 1:numel(lambdaGrid)
    foldMetrics = repmat( ...
        emptySplitMetrics(), 1, numel(trainingSeeds));
    for foldIdx = 1:numel(trainingSeeds)
        heldoutSeed = trainingSeeds(foldIdx);
        fitSeeds = setdiff( ...
            trainingSeeds, heldoutSeed, 'stable');
        model = fitStructuredRollingSafeRolloutRanker( ...
            selectBlocks(blocks, fitSeeds), ...
            fitOptions(featureMask, dataset, lambdaGrid(lambdaIdx), ...
                epochCount, learningRate, lossScale));
        foldMetrics(foldIdx) = evaluateBlocks( ...
            selectBlocks(blocks, heldoutSeed), ...
            model, dataset);
    end
    candidates(lambdaIdx) = summarizeCandidate( ...
        lambdaGrid(lambdaIdx), foldMetrics);
end
[~, order] = sortrows(vertcat(candidates.selectionKey));
candidates = candidates(order);
selected = candidates(1);

trainingBlocks = selectBlocks( ...
    blocks, trainingSeeds);
model = fitStructuredRollingSafeRolloutRanker( ...
    trainingBlocks, fitOptions( ...
        featureMask, dataset, selected.lambda, ...
        epochCount, learningRate, lossScale));
model.protocolId = protocol.id;
model.featureContextMode = featureContextMode;
model.allFeatureNames = featureNames;
model.excludedFeatureNames = expandedExcludedNames;
model.trainingSeeds = trainingSeeds;
model.auditSeeds = auditSeeds;
model.datasetSeeds = dataset.seeds;
model.featuresUseTruth = dataset.featuresUseTruth;
model.edgeLabelsUseTruth = dataset.labelsUseTruth;
model.cardinalityUsesTruth = true;
model.deployable = false;
model.frozen = false;
model.datasetPath = datasetPath;
model.datasetSha256 = computeFileSha256(datasetPath);
gitState = resolveResearchGitState();
model.trainingGitCommit = gitState.commit;
model.trainingWorktreeDirty = gitState.researchWorktreeDirty;

trainingMetrics = evaluateBlocks( ...
    trainingBlocks, model, dataset);
auditMetrics = emptySplitMetrics();
if ~isempty(auditSeeds)
    auditMetrics = evaluateBlocks( ...
        selectBlocks(blocks, auditSeeds), ...
        model, dataset);
end
ceilingPassed = ...
    selected.minimumHeldoutSeedF1 >= ...
        protocol.minimumSeedProjectedEdgeF1 - 1e-12 && ...
    selected.meanHeldoutF1 >= ...
        protocol.minimumMeanProjectedEdgeF1 - 1e-12 && ...
    selected.minimumHeldoutBlockF1 >= ...
        protocol.minimumBlockProjectedEdgeF1 - 1e-12 && ...
    selected.minimumHeldoutSeedExactFraction >= ...
        protocol.minimumSeedProjectedExactGraphFraction - 1e-12 && ...
    selected.meanHeldoutExactFraction >= ...
        protocol.minimumMeanProjectedExactGraphFraction - 1e-12;

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'STRUCTURED_ROLLING_SAFE_ORACLE_K_AUDIT.md'));
modelPath = getField(options, 'modelPath', fullfile( ...
    outputDirectory, 'models', ...
    'structured_rolling_safe_oracle_k_m24_t75.mat'));
modelDirectory = fileparts(modelPath);
if ~exist(modelDirectory, 'dir')
    mkdir(modelDirectory);
end

result = struct();
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.datasetPath = datasetPath;
result.datasetSha256 = model.datasetSha256;
result.modelPath = modelPath;
result.reportPath = reportPath;
result.trainingSeeds = trainingSeeds;
result.auditSeeds = auditSeeds;
result.lambdaGrid = lambdaGrid;
result.epochCount = epochCount;
result.learningRate = learningRate;
result.lossScale = lossScale;
result.featureContextMode = featureContextMode;
result.allFeatureNames = featureNames;
result.excludedFeatureNames = expandedExcludedNames;
result.retainedFeatureNames = featureNames(featureMask);
result.candidates = candidates;
result.selectedCandidate = selected;
result.trainingMetrics = trainingMetrics;
result.auditMetrics = auditMetrics;
result.model = model;
result.edgeRankingCeilingPassed = ceilingPassed;
result.deployable = false;
result.cardinalityUsesTruth = true;
result.trainingGitCommit = gitState.commit;
result.trainingWorktreeDirty = gitState.researchWorktreeDirty;
result.evidenceBoundary = [ ...
    'Oracle-k supplies each recorded target cross-edge count to the ', ...
    'exact rolling-B3 projector. The audit isolates edge-ranking ', ...
    'learnability and cannot be deployed or used as closed-loop ', ...
    'tracking evidence. Hyperparameters use only leave-one-training-', ...
    'seed-out graph imitation; seed 7 remains design-seen audit data.'];
save('-mat7-binary', modelPath, 'model', 'result');
writeReport(reportPath, result);
fprintf('Model: %s\nReport: %s\n', modelPath, reportPath);
end

function options = fitOptions( ...
        featureMask, dataset, lambda, ...
        epochCount, learningRate, lossScale)
options = struct( ...
    'featureMask', featureMask, ...
    'sourceWeight', dataset.sourceWeight, ...
    'payloadToleranceFraction', ...
        dataset.payloadToleranceFraction, ...
    'lambda', lambda, ...
    'epochCount', epochCount, ...
    'learningRate', learningRate, ...
    'lossScale', lossScale);
end

function selected = selectBlocks(blocks, seeds)
selected = blocks(ismember([blocks.seed], seeds));
if isempty(selected)
    error('Structured rolling-safe split selected no blocks.');
end
end

function metrics = evaluateBlocks(blocks, model, dataset)
blockMetrics = repmat( ...
    emptyBlockMetrics(), 1, numel(blocks));
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    truth = logical(reshape( ...
        block.selectedCrossMask, [], 1));
    cardinality = nnz(truth);
    scores = scoreStructuredRollingSafeRolloutRanker( ...
        model, block.features);
    scores = normalizeFixedCardinalityScores(scores);
    projectionOptions = struct( ...
        'minimumCurrentCrossEdges', cardinality, ...
        'maximumCurrentCrossEdges', cardinality);
    [adjacency, details] = ...
        replayRollingSafeRolloutProjection( ...
            block, scores, dataset.sourceWeight, ...
            dataset.payloadToleranceFraction, ...
            projectionOptions);
    predicted = extractMask(block, adjacency);
    [precision, recall, f1] = ...
        binaryMetrics(predicted, truth);
    metric = emptyBlockMetrics();
    metric.seed = block.seed;
    metric.currentTime = block.currentTime;
    metric.actionCode = block.actionCode;
    metric.cardinality = cardinality;
    metric.precision = precision;
    metric.recall = recall;
    metric.f1 = f1;
    metric.exactGraph = isequal( ...
        logical(adjacency), ...
        logical(block.selectedAdjacency));
    metric.repairTriggered = details.repairTriggered;
    metric.topologyInfeasible = details.topologyInfeasible;
    blockMetrics(blockIdx) = metric;
end
seeds = unique([blockMetrics.seed], 'stable');
seedF1 = zeros(1, numel(seeds));
seedExact = zeros(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    mask = [blockMetrics.seed] == seeds(seedIdx);
    seedF1(seedIdx) = mean([blockMetrics(mask).f1]);
    seedExact(seedIdx) = mean( ...
        [blockMetrics(mask).exactGraph]);
end
metrics = emptySplitMetrics();
metrics.seeds = seeds;
metrics.blockMetrics = blockMetrics;
metrics.meanF1 = mean([blockMetrics.f1]);
metrics.minimumSeedF1 = min(seedF1);
metrics.minimumBlockF1 = min([blockMetrics.f1]);
metrics.meanExactFraction = mean( ...
    [blockMetrics.exactGraph]);
metrics.minimumSeedExactFraction = min(seedExact);
metrics.repairRate = mean([blockMetrics.repairTriggered]);
metrics.infeasibleRate = mean( ...
    [blockMetrics.topologyInfeasible]);
end

function normalized = normalizeFixedCardinalityScores(scores)
scores = reshape(scores, [], 1);
location = mean(scores);
scale = max(abs(scores - location));
if ~isfinite(scale) || scale <= eps
    scale = 1;
end
normalized = (scores - location) / scale;
end

function mask = extractMask(block, adjacency)
nodeCount = numel(block.groupIds);
indices = sub2ind( ...
    [nodeCount, nodeCount], block.receiverIndices, ...
    block.senderIndices);
mask = reshape(logical(adjacency(indices)), [], 1);
end

function [precision, recall, f1] = ...
        binaryMetrics(predicted, truth)
truePositive = nnz(predicted & truth);
predictedPositive = nnz(predicted);
truthPositive = nnz(truth);
if predictedPositive == 0
    precision = double(truthPositive == 0);
else
    precision = truePositive / predictedPositive;
end
if truthPositive == 0
    recall = double(predictedPositive == 0);
else
    recall = truePositive / truthPositive;
end
if precision + recall <= eps
    f1 = 0;
else
    f1 = 2 * precision * recall / (precision + recall);
end
end

function candidate = summarizeCandidate(lambda, folds)
candidate = emptyCandidate();
candidate.lambda = lambda;
candidate.foldMetrics = folds;
candidate.minimumHeldoutSeedF1 = min( ...
    [folds.minimumSeedF1]);
candidate.meanHeldoutF1 = mean([folds.meanF1]);
candidate.minimumHeldoutBlockF1 = min( ...
    [folds.minimumBlockF1]);
candidate.minimumHeldoutSeedExactFraction = min( ...
    [folds.minimumSeedExactFraction]);
candidate.meanHeldoutExactFraction = mean( ...
    [folds.meanExactFraction]);
candidate.selectionKey = [ ...
    -candidate.minimumHeldoutSeedF1, ...
    -candidate.meanHeldoutF1, ...
    -candidate.minimumHeldoutBlockF1, ...
    -candidate.minimumHeldoutSeedExactFraction, ...
    -candidate.meanHeldoutExactFraction, lambda];
end

function [blocks, featureNames, mode] = ...
        prepareFeatureContext(dataset, mode)
blocks = dataset.blocks;
datasetMode = lower(strrep( ...
    char(dataset.featureContextMode), '_', '-'));
if strcmp(mode, datasetMode)
    featureNames = reshape(dataset.featureNames, 1, []);
    return;
end
if ~strcmp(datasetMode, 'raw') || ...
        ~strcmp(mode, 'graph-context')
    error(['Unsupported structured rolling-safe feature conversion: ', ...
        '%s -> %s.'], datasetMode, mode);
end
featureNames = {};
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    [converted, names] = buildFormationTreeContextFeatures( ...
        block.features, dataset.featureNames, ...
        block.receiverIndices, block.senderIndices, ...
        reshape(block.groupIds, 1, []), mode);
    if isempty(featureNames)
        featureNames = reshape(names, 1, []);
    elseif ~isequal(featureNames, reshape(names, 1, []))
        error('Structured rolling-safe context names differ.');
    end
    blocks(blockIdx).features = converted;
    blocks(blockIdx).featureNames = featureNames;
end
end

function [featureMask, expandedExcludedNames] = ...
        buildFeatureMask(featureNames, baseExcludedNames)
featureMask = true(1, numel(featureNames));
prefixes = {'', 'receiver_rel_', ...
    'formation_pair_rel_', 'block_rel_'};
for excludedIdx = 1:numel(baseExcludedNames)
    for prefixIdx = 1:numel(prefixes)
        featureMask = featureMask & ~strcmp( ...
            featureNames, [prefixes{prefixIdx}, ...
                baseExcludedNames{excludedIdx}]);
    end
end
expandedExcludedNames = featureNames(~featureMask);
end

function validateDataset(dataset, protocol)
required = { ...
    'protocolId', 'presetName', 'seeds', ...
    'sourceWeight', 'payloadToleranceFraction', ...
    'generationResearchWorktreeDirty', ...
    'featureContextMode', 'featureNames', 'blocks', ...
    'featuresUseTruth', 'labelsUseTruth'};
if ~isstruct(dataset) || ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.presetName, protocol.presetName) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        dataset.generationResearchWorktreeDirty || ...
        dataset.featuresUseTruth || ~dataset.labelsUseTruth || ...
        ~strcmp(dataset.featureContextMode, 'raw')
    error('Structured rolling-safe dataset contract is invalid.');
end
if numel(dataset.blocks) ~= ...
        numel(dataset.seeds) * 3
    error('Structured rolling-safe dataset block count is invalid.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('Unable to write structured rolling-safe report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
selected = result.selectedCandidate;
fprintf(fid, '# Structured rolling-safe oracle-k audit\n\n');
fprintf(fid, '- Generated: %s\n', result.generatedAt);
fprintf(fid, '- Protocol: `%s`\n', result.protocolId);
fprintf(fid, '- Dataset SHA-256: `%s`\n', result.datasetSha256);
fprintf(fid, '- Training seeds: `%s`\n', ...
    mat2str(result.trainingSeeds));
fprintf(fid, '- Audit seeds: `%s`\n', ...
    mat2str(result.auditSeeds));
fprintf(fid, '- Feature context: `%s`\n', ...
    result.featureContextMode);
fprintf(fid, '- Retained linear features: %d / %d\n', ...
    numel(result.retainedFeatureNames), ...
    numel(result.allFeatureNames));
fprintf(fid, '- Lambda grid: `%s`\n', ...
    mat2str(result.lambdaGrid));
fprintf(fid, '- Selected lambda: %.6g\n', selected.lambda);
fprintf(fid, '- Epochs: %d\n', result.epochCount);
fprintf(fid, '- Oracle cardinality used: `1`\n');
fprintf(fid, '- Deployable: `0`\n');
fprintf(fid, '- Edge-ranking ceiling passed: `%d`\n', ...
    result.edgeRankingCeilingPassed);
fprintf(fid, '- Training git commit: `%s`\n', ...
    result.trainingGitCommit);
fprintf(fid, '- Training worktree dirty: `%d`\n', ...
    result.trainingWorktreeDirty);
fprintf(fid, '- Evidence boundary: %s\n', ...
    result.evidenceBoundary);

fprintf(fid, '\n## Leave-one-training-seed-out selection\n\n');
fprintf(fid, ['| Lambda | Min seed F1 | Mean F1 | Min block F1 | ', ...
    'Min seed exact | Mean exact |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|\n');
for candidateIdx = 1:numel(result.candidates)
    candidate = result.candidates(candidateIdx);
    fprintf(fid, '| %.6g | %.4f | %.4f | %.4f | %.4f | %.4f |\n', ...
        candidate.lambda, ...
        candidate.minimumHeldoutSeedF1, ...
        candidate.meanHeldoutF1, ...
        candidate.minimumHeldoutBlockF1, ...
        candidate.minimumHeldoutSeedExactFraction, ...
        candidate.meanHeldoutExactFraction);
end

writeMetricsTable(fid, 'Training replay', ...
    result.trainingMetrics);
writeMetricsTable(fid, 'Design-seen audit replay', ...
    result.auditMetrics);
end

function writeMetricsTable(fid, titleText, metrics)
fprintf(fid, '\n## %s\n\n', titleText);
fprintf(fid, ['| Seed | Time | Code | Oracle k | Precision | Recall | ', ...
    'F1 | Exact graph | Repair | Infeasible |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for metricIdx = 1:numel(metrics.blockMetrics)
    metric = metrics.blockMetrics(metricIdx);
    fprintf(fid, ...
        '| %d | %d | %02d | %d | %.4f | %.4f | %.4f | %d | %d | %d |\n', ...
        metric.seed, metric.currentTime, ...
        metric.actionCode, metric.cardinality, ...
        metric.precision, metric.recall, metric.f1, ...
        metric.exactGraph, metric.repairTriggered, ...
        metric.topologyInfeasible);
end
end

function candidate = emptyCandidate()
candidate = struct( ...
    'lambda', NaN, ...
    'foldMetrics', repmat(emptySplitMetrics(), 1, 0), ...
    'minimumHeldoutSeedF1', NaN, ...
    'meanHeldoutF1', NaN, ...
    'minimumHeldoutBlockF1', NaN, ...
    'minimumHeldoutSeedExactFraction', NaN, ...
    'meanHeldoutExactFraction', NaN, ...
    'selectionKey', nan(1, 6));
end

function metrics = emptySplitMetrics()
metrics = struct( ...
    'seeds', [], ...
    'blockMetrics', repmat(emptyBlockMetrics(), 1, 0), ...
    'meanF1', NaN, ...
    'minimumSeedF1', NaN, ...
    'minimumBlockF1', NaN, ...
    'meanExactFraction', NaN, ...
    'minimumSeedExactFraction', NaN, ...
    'repairRate', NaN, ...
    'infeasibleRate', NaN);
end

function metric = emptyBlockMetrics()
metric = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'actionCode', NaN, ...
    'cardinality', NaN, ...
    'precision', NaN, ...
    'recall', NaN, ...
    'f1', NaN, ...
    'exactGraph', false, ...
    'repairTriggered', false, ...
    'topologyInfeasible', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
