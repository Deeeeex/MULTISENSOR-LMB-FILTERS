    '`min(E, R, C, byte, weakest-formation-E + 2, ', ...
    'weakest-formation-R + 2)`. The reference maps exactly to zero. ', ...
    'A non-reference gateway is used only when its predicted utility ', ...
    'exceeds the frozen threshold; otherwise the selector abstains.\n\n']);

