function [reportPath, result] = ...
        buildDecoupledSemanticShortcutCandidateBankV220(options)
% BUILDDECOUPLEDSEMANTICSHORTCUTCANDIDATEBANKV220 Causal semantic bank.
%
% Reconstruct the current post-fusion label bank from a captured donor-only
% arm.  Beneficiaries are independent of the communication donor.  Candidate
% features use current posterior/graph state only; the paired H=3 donor return
% is retained strictly as an offline stage-1 target.

if nargin < 1 || isempty(options)
    options = struct();
end
sourceScreenPath = char(getField(options, 'sourceScreenPath', ''));
donorFormationId = getField(options, 'donorFormationId', 0);
beneficiaryFormationIds = reshape(getField( ...
    options, 'beneficiaryFormationIds', zeros(1, 0)), 1, []);
pageIndex = getField(options, 'pageIndex', 1);
topPerMode = getField(options, 'topPerMode', 1);
maximumBeneficiaries = getField(options, 'maximumBeneficiaries', 2);
if isempty(sourceScreenPath) || exist(sourceScreenPath, 'file') ~= 2 || ...
        ~validPositiveInteger(donorFormationId) || ...
        ~validPositiveInteger(pageIndex) || ...
        ~validPositiveInteger(topPerMode) || ...
        ~validPositiveInteger(maximumBeneficiaries)
    error('DecoupledSemanticShortcutV220:InvalidCandidateBankRequest', ...
        'A captured donor screen and valid bank limits are required.');
end
loaded = load(sourceScreenPath, 'screen');
screen = loaded.screen;
requiredScreenFields = {'presetName', 'seed', 'currentTime', ...
    'returnTimes', 'sensorGroupIds', 'records', 'outcomes', ...
    'referenceSubsetIndex', 'bank', 'cachePath'};
if ~isstruct(screen) || ~isscalar(screen) || ...
        any(~isfield(screen, requiredScreenFields)) || ...
        pageIndex > numel(screen.returnTimes)
    error('DecoupledSemanticShortcutV220:CapturedScreenContract', ...
        'The donor capture screen is malformed.');
end
groupIds = reshape(screen.sensorGroupIds, 1, []);
formationIds = unique(groupIds, 'stable');
if ~ismember(donorFormationId, formationIds) || ...
        (~isempty(beneficiaryFormationIds) && ...
         (any(~ismember(beneficiaryFormationIds, formationIds)) || ...
          numel(unique(beneficiaryFormationIds)) ~= ...
              numel(beneficiaryFormationIds)))
    error('DecoupledSemanticShortcutV220:FormationScope', ...
        'The requested donor or beneficiary formation is invalid.');
end
donorName = sprintf( ...
    'v214-withhold-full-posterior-f%d-one-page', donorFormationId);
donorOutcomeIndex = find(strcmp( ...
    {screen.records.actionName}, donorName));
if numel(donorOutcomeIndex) ~= 1
    error('DecoupledSemanticShortcutV220:DonorArm', ...
        'The captured screen must contain exactly one donor-only arm.');
end
referenceOutcomeIndex = screen.referenceSubsetIndex;
if ~validPositiveInteger(referenceOutcomeIndex) || ...
        referenceOutcomeIndex > numel(screen.outcomes)
    error('DecoupledSemanticShortcutV220:ReferenceArm', ...
        'The captured reference arm is invalid.');
end
donorOutcome = screen.outcomes(donorOutcomeIndex);
referenceOutcome = screen.outcomes(referenceOutcomeIndex);
requiredOutcomeFields = {'localPosteriorSnapshotsByTime', ...
    'fusedPosteriorSnapshotsByTime', 'attemptedBytesByTime'};
if any(~isfield(donorOutcome, requiredOutcomeFields)) || ...
        ~iscell(donorOutcome.localPosteriorSnapshotsByTime) || ...
        ~iscell(donorOutcome.fusedPosteriorSnapshotsByTime) || ...
        numel(donorOutcome.localPosteriorSnapshotsByTime) < pageIndex || ...
        numel(donorOutcome.fusedPosteriorSnapshotsByTime) < pageIndex || ...
        isempty(donorOutcome.localPosteriorSnapshotsByTime{pageIndex}) || ...
        isempty(donorOutcome.fusedPosteriorSnapshotsByTime{pageIndex}) || ...
        numel(referenceOutcome.attemptedBytesByTime) < pageIndex || ...
        numel(donorOutcome.attemptedBytesByTime) < pageIndex
    error('DecoupledSemanticShortcutV220:MissingCapture', ...
        'The donor arm lacks current local/fused posterior capture.');
end

protocol = getDecoupledSemanticShortcutV220Protocol();
inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
currentTime = screen.returnTimes(pageIndex);
if currentTime ~= screen.currentTime + pageIndex - 1 || ...
        ~isequal(reshape(inputs.config.sensorGroupIds, 1, []), groupIds)
    error('DecoupledSemanticShortcutV220:ScenarioDrift', ...
        'The regenerated truth-free scenario differs from the capture.');
end
physical = logical(inputs.graphData.physicalAdjacency(:, :, currentTime));
if inputs.commConfig.forceDelivery
    delivered = physical;
else
    delivered = physical & ...
        (inputs.commConfig.linkUniforms(:, :, currentTime) >= ...
         inputs.commConfig.pDropByEdge(:, :, currentTime));
end
availableSourceAdjacency = physical & delivered';
localPosteriorBySensor = reshape( ...
    donorOutcome.localPosteriorSnapshotsByTime{pageIndex}, 1, []);
fusedPosteriorBySensor = reshape( ...
    donorOutcome.fusedPosteriorSnapshotsByTime{pageIndex}, 1, []);
if numel(localPosteriorBySensor) ~= numel(groupIds) || ...
        numel(fusedPosteriorBySensor) ~= numel(groupIds)
    error('DecoupledSemanticShortcutV220:PosteriorCaptureDrift', ...
        'The captured posterior sensor count changed.');
end

formationNeed = resolveFormationNeed(screen.bank, formationIds);
if isempty(beneficiaryFormationIds)
    eligibleBeneficiaries = formationIds(formationIds ~= donorFormationId);
    eligibleNeed = formationNeed(ismember(formationIds, ...
        eligibleBeneficiaries));
    [~, order] = sort(eligibleNeed, 'descend');
    beneficiaryFormationIds = eligibleBeneficiaries(order( ...
        1:min(maximumBeneficiaries, numel(order))));
end
referencePageBytes = referenceOutcome.attemptedBytesByTime(pageIndex);
donorPageBytes = donorOutcome.attemptedBytesByTime(pageIndex);
admissionNetSavingBytes = max( ...
    referencePageBytes - donorPageBytes, 0);
records = repmat(emptyRecord(), 1, 0);
beneficiaryDetails = repmat(emptyBeneficiaryDetails(), ...
    1, numel(beneficiaryFormationIds));
for beneficiaryPosition = 1:numel(beneficiaryFormationIds)
    beneficiaryFormationId = ...
        beneficiaryFormationIds(beneficiaryPosition);
    receivers = find(groupIds == beneficiaryFormationId);
    commonSources = find(all( ...
        availableSourceAdjacency(receivers, :), 1));
    synopsisSensorIds = unique( ...
        [reshape(receivers, 1, []), ...
         reshape(commonSources, 1, [])], 'stable');
    cache = buildFormationRepairLightSynopsisCacheV188( ...
        fusedPosteriorBySensor, localPosteriorBySensor, ...
        inputs.model, currentTime, struct( ...
            'localParticipatingSensorIds', synopsisSensorIds, ...
            'fusedParticipatingSensorIds', receivers, ...
            'recordMode', 'v216-risk-only'));
    [creditAfterSynopsis, synopsisDecision] = ...
        preflightBudgetRecycledRepairSynopsisV188( ...
            [], admissionNetSavingBytes, ...
            cache.totalAttemptedBytes, referencePageBytes);
    [fullCandidates, enumerationDetails] = ...
        enumerateFormationCommonLabelRepairCandidatesV190( ...
            cache, availableSourceAdjacency, groupIds, struct( ...
                'receiverPresenceThreshold', ...
                    protocol.candidateReceiverPresenceThreshold));
    fullCandidates = fullCandidates( ...
        [fullCandidates.formationId] == beneficiaryFormationId);
    [positionSafeCandidates, positionProjection] = ...
        projectFormationLabelCandidatesByPositionSupportV217( ...
            fullCandidates, struct());
    [shortlist, shortlistDetails] = ...
        selectModeDiversePositionSafeRepairCandidatesV217( ...
            positionSafeCandidates, struct('topPerMode', topPerMode));

    detail = emptyBeneficiaryDetails();
    detail.formationId = beneficiaryFormationId;
    detail.need = formationNeed(formationIds == ...
        beneficiaryFormationId);
    detail.receiverIds = receivers;
    detail.commonSourceIds = commonSources;
    detail.synopsisSensorIds = synopsisSensorIds;
    detail.synopsisBytes = cache.totalAttemptedBytes;
    detail.synopsisAuthorized = ...
        synopsisDecision.lightSynopsisAuthorized;
    detail.spendableCreditAfterSynopsis = ...
        creditAfterSynopsis.spendableCreditBytes;
    detail.fullCandidateCount = numel(fullCandidates);
    detail.positionSafeCandidateCount = ...
        numel(positionSafeCandidates);
    detail.shortlistedCandidateCount = numel(shortlist);
    detail.enumerationDetails = enumerationDetails;
    detail.positionProjection = positionProjection;
    detail.shortlistDetails = shortlistDetails;

    feasibleCount = 0;
    for shortlistRow = 1:numel(shortlist)
        candidate = shortlist(shortlistRow);
        [proposal, payloadDetails] = ...
            resolveFormationRepairCandidatePayloadV190( ...
                candidate, localPosteriorBySensor, ...
                availableSourceAdjacency, inputs.model, struct());
        creditFeasible = synopsisDecision.lightSynopsisAuthorized && ...
            proposal.safetyPassed && ...
            proposal.rollingConnectivityPassed && ...
            proposal.attemptedBytes <= ...
                creditAfterSynopsis.spendableCreditBytes + 1e-9;
        item = emptyRecord();
        item.recordIndex = numel(records) + 1;
        item.donorFormationId = donorFormationId;
        item.beneficiaryFormationId = beneficiaryFormationId;
        item.beneficiaryNeed = detail.need;
        item.sourceId = candidate.sourceId;
        item.label = candidate.label;
        item.originalCandidateIndex = candidate.candidateIndex;
        item.candidate = candidate;
        item.proposal = proposal;
        item.payloadDetails = payloadDetails;
        item.selectedModes = shortlistDetails.modeNames( ...
            shortlistDetails.selectedByMode(shortlistRow, :));
        item.modeScores = shortlistDetails.modeScores( ...
            shortlistRow, :);
        item.synopsisBytes = cache.totalAttemptedBytes;
        item.payloadAttemptedBytes = proposal.attemptedBytes;
        item.spendableCreditAfterSynopsis = ...
            creditAfterSynopsis.spendableCreditBytes;
        item.creditFeasible = creditFeasible;
        item.truthUsed = false;
        item.futureInformationUsed = false;
        records(end + 1) = item; %#ok<AGROW>
        feasibleCount = feasibleCount + double(creditFeasible);
    end
    detail.creditFeasibleCandidateCount = feasibleCount;
    beneficiaryDetails(beneficiaryPosition) = detail;
end

result = struct();
result.contractVersion = ...
    'decoupled-semantic-shortcut-candidate-bank-v220-v1';
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.sourceScreenPath = sourceScreenPath;
result.presetName = screen.presetName;
result.seed = screen.seed;
result.currentTime = currentTime;
result.pageIndex = pageIndex;
result.donorFormationId = donorFormationId;
result.beneficiaryFormationIds = beneficiaryFormationIds;
result.formationIds = formationIds;
result.formationNeed = formationNeed;
result.referencePageBytes = referencePageBytes;
result.donorPageBytes = donorPageBytes;
result.admissionNetSavingBytes = admissionNetSavingBytes;
result.donorRecord = screen.records(donorOutcomeIndex);
result.donorSafetyLabel = donorSafetyLabel( ...
    screen.records(donorOutcomeIndex));
result.donorStrictPositiveLabel = donorStrictPositiveLabel( ...
    screen.records(donorOutcomeIndex));
result.records = records;
result.candidateCount = numel(records);
result.creditFeasibleMask = reshape( ...
    [records.creditFeasible], 1, []);
result.creditFeasibleCount = nnz(result.creditFeasibleMask);
result.beneficiaryDetails = beneficiaryDetails;
result.topPerMode = topPerMode;
result.maximumBeneficiaries = maximumBeneficiaries;
result.availableSourceAdjacency = availableSourceAdjacency;
result.truthUsedForCandidateFeatures = false;
result.futureInformationUsedForCandidateFeatures = false;
result.truthUsedForDonorSafetyTarget = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'semantic_candidate_bank', ...
    sprintf('%s_seed%d_t%d_donor_f%d', ...
        strrep(screen.presetName, '-', '_'), screen.seed, ...
        currentTime, donorFormationId))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'DECOUPLED_SEMANTIC_SHORTCUT_CANDIDATE_BANK_V220.mat');
reportPath = fullfile(outputRoot, ...
    'DECOUPLED_SEMANTIC_SHORTCUT_CANDIDATE_BANK_V220.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V220 decoupled semantic candidate bank: %s\n', reportPath);
end

function need = resolveFormationNeed(bank, formationIds)
if ~isstruct(bank) || ~isscalar(bank) || ...
        ~isfield(bank, 'referencePolicyDetails') || ...
        ~isstruct(bank.referencePolicyDetails) || ...
        ~isfield(bank.referencePolicyDetails, ...
            'hierarchicalFormationIds') || ...
        ~isfield(bank.referencePolicyDetails, ...
            'hierarchicalFormationNeedByFormation')
    error('DecoupledSemanticShortcutV220:MissingFormationNeed', ...
        'The donor screen lacks the observable formation-need vector.');
end
details = bank.referencePolicyDetails;
registeredIds = reshape(details.hierarchicalFormationIds, 1, []);
registeredNeed = reshape( ...
    details.hierarchicalFormationNeedByFormation, 1, []);
if ~isequal(registeredIds, formationIds) || ...
        numel(registeredNeed) ~= numel(formationIds) || ...
        any(~isfinite(registeredNeed))
    error('DecoupledSemanticShortcutV220:FormationNeedDrift', ...
        'The observable formation-need vector changed.');
end
need = registeredNeed;
end

function passed = donorSafetyLabel(record)
v213 = getHierarchicalDelayedValueControllerV213Protocol();
names = v213.risk.targetNames;
tolerance = v213.risk.tolerancePercent;
passed = record.meanGainPercent >= -1e-10 && ...
    record.rmseGainPercent >= -1e-10 && ...
    record.consensusGainPercent >= 0 && ...
    record.terminalConsensusGainPercent >= 0 && ...
    record.attemptedByteSavingPercent > 0 && ...
    record.selectedB3Passed && ...
    record.worstGainPercent >= threshold( ...
        names, tolerance, 'worst_sensor_eospa_gain_percent') && ...
    record.worstRmseGainPercent >= threshold( ...
        names, tolerance, 'worst_sensor_rmse_gain_percent') && ...
    record.minimumFormationGainPercent >= threshold( ...
        names, tolerance, 'minimum_formation_eospa_gain_percent') && ...
    record.minimumFormationRmseGainPercent >= threshold( ...
        names, tolerance, 'minimum_formation_rmse_gain_percent');
end

function passed = donorStrictPositiveLabel(record)
passed = donorSafetyLabel(record) && ...
    record.meanGainPercent > 0 && ...
    record.rmseGainPercent > 0 && ...
    record.consensusGainPercent > 0 && ...
    record.terminalConsensusGainPercent > 0;
end

function value = threshold(names, values, requested)
idx = find(strcmp(names, requested));
if numel(idx) ~= 1
    error('DecoupledSemanticShortcutV220:RiskContractDrift', ...
        'The V213 risk target is missing: %s.', requested);
end
value = values(idx);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('DecoupledSemanticShortcutV220:WriteReport', ...
        'Could not write the V220 candidate-bank report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V220 decoupled semantic shortcut candidate bank\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Donor formation / donor safety target: `F%d / %d`\n', ...
    result.donorFormationId, result.donorSafetyLabel);
fprintf(fid, '- Donor strict-positive target: `%d`\n', ...
    result.donorStrictPositiveLabel);
fprintf(fid, '- Beneficiary formations: `%s`\n', ...
    mat2str(result.beneficiaryFormationIds));
fprintf(fid, '- Reference / donor page bytes: `%d / %d`\n', ...
    result.referencePageBytes, result.donorPageBytes);
fprintf(fid, '- Exact admission saving: `%d B`\n', ...
    result.admissionNetSavingBytes);
fprintf(fid, '- Shortlisted / credit-feasible: `%d / %d`\n\n', ...
    result.candidateCount, result.creditFeasibleCount);
fprintf(fid, ['| Row | Donor -> beneficiary | Need | Source | Label | ', ...
    'Modes | Synopsis | Payload | Spendable after synopsis | Feasible |\n']);
fprintf(fid, ['|--:|:--|--:|--:|:--|:--|--:|--:|--:|:--:|\n']);
for record = result.records
    fprintf(fid, ...
        '| %d | F%d -> F%d | %.6f | %d | `[%d,%d]` | %s | %d | %.0f | %.1f | %d |\n', ...
        record.recordIndex, record.donorFormationId, ...
        record.beneficiaryFormationId, record.beneficiaryNeed, ...
        record.sourceId, record.label(1), record.label(2), ...
        strjoin(record.selectedModes, ', '), ...
        record.synopsisBytes, record.payloadAttemptedBytes, ...
        record.spendableCreditAfterSynopsis, ...
        record.creditFeasible);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'recordIndex', 0, ...
    'donorFormationId', 0, ...
    'beneficiaryFormationId', 0, ...
    'beneficiaryNeed', 0, ...
    'sourceId', 0, ...
    'label', zeros(2, 1), ...
    'originalCandidateIndex', 0, ...
    'candidate', [], ...
    'proposal', [], ...
    'payloadDetails', [], ...
    'selectedModes', {cell(1, 0)}, ...
    'modeScores', zeros(1, 3), ...
    'synopsisBytes', 0, ...
    'payloadAttemptedBytes', 0, ...
    'spendableCreditAfterSynopsis', 0, ...
    'creditFeasible', false, ...
    'truthUsed', false, ...
    'futureInformationUsed', false);
end

function value = emptyBeneficiaryDetails()
value = struct( ...
    'formationId', 0, ...
    'need', 0, ...
    'receiverIds', zeros(1, 0), ...
    'commonSourceIds', zeros(1, 0), ...
    'synopsisSensorIds', zeros(1, 0), ...
    'synopsisBytes', 0, ...
    'synopsisAuthorized', false, ...
    'spendableCreditAfterSynopsis', 0, ...
    'fullCandidateCount', 0, ...
    'positionSafeCandidateCount', 0, ...
    'shortlistedCandidateCount', 0, ...
    'creditFeasibleCandidateCount', 0, ...
    'enumerationDetails', [], ...
    'positionProjection', [], ...
    'shortlistDetails', []);
end

function valid = validPositiveInteger(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value >= 1 && value == round(value);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
