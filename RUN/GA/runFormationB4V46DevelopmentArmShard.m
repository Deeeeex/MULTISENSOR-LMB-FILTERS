function [shard, outputPath] = ...
    runFormationB4V46DevelopmentArmShard( ...
        caseOrdinal, armId, outputPath)
% RUNFORMATIONB4V46DEVELOPMENTARMSHARD One non-overwriting raw arm shard.
%
% The runner materializes only an accepted development runtime input at its
% public boundary, executes one explicitly permitted arm, and publishes raw
% state estimates and a diagnostic whitelist.  It never reconstructs truth
% after filtering and cannot score or compare the two arms.

if nargin < 3
    requestedOutputPath = '';
else
    requestedOutputPath = outputPath;
end
[pathResolution, invocationEvidence] = ...
    bootstrapV46DevelopmentExecutionSurface( ...
        caseOrdinal, armId, requestedOutputPath);
permit = loadFormationB4V46DevelopmentArmPermit(caseOrdinal, armId);
manifest = buildFormationB4V46DevelopmentExecutionSurfaceManifest();
if ~strcmp(manifest.canonicalSha256, ...
        permit.executionSurfaceManifestSha256)
    error('FormationB4V46DevelopmentShard:ExecutionSurfaceDrift', ...
        'The current executable surface is not the permitted surface.');
end
gitState = validateFormationB4V46DevelopmentExecutionGitState( ...
    permit.executionSurfaceCommit);

if nargin < 3 || isempty(outputPath)
    repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    outputDirectory = fullfile(repoRoot, 'RUN', 'GA', ...
        'dynamic_topology', 'evidence', ...
        'formation_b4_v46_development_arm_shards', ...
        gitState.headCommit);
    outputPath = fullfile(outputDirectory, sprintf( ...
        'case_%02d__arm_%02d.mat', ...
        permit.caseOrdinal, permit.armOrdinal));
else
    if ~ischar(outputPath) || ~isrow(outputPath) || isempty(outputPath)
        error('FormationB4V46DevelopmentShard:InvalidOutputPath', ...
            'The shard output path must be one nonempty row string.');
    end
    outputDirectory = fileparts(outputPath);
    if isempty(outputDirectory)
        outputDirectory = pwd;
        outputPath = fullfile(outputDirectory, outputPath);
    end
end
if exist(outputPath, 'file') ~= 0 || exist(outputPath, 'dir') ~= 0
    error('FormationB4V46DevelopmentShard:OutputExists', ...
        'The development arm runner refuses to overwrite a shard path.');
end
if exist(outputDirectory, 'dir') == 0
    [created, message] = mkdir(outputDirectory);
    if ~created
        error('FormationB4V46DevelopmentShard:OutputCreateFailed', ...
            'Could not create the shard directory: %s', message);
    end
end

startedAt = datestr(now, 31);
timerId = tic;
initialRngState = rng();
restoreRng = onCleanup(@() rng(initialRngState));
runtime = materializeFormationB4V46DevelopmentRuntimeInput(caseOrdinal);
triggerConfig = buildFormationB4V46FixedTriggerConfig( ...
    armId, permit.numberOfSensors);
executionContext = ...
    buildFormationB4V46DevelopmentArmExecutionContext( ...
        caseOrdinal, armId);
filterSeed = 47000000 + 100 * caseOrdinal + permit.armOrdinal;
rng(filterSeed, 'twister');
[stateEstimatesBySensor, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        runtime.model, runtime.measurements, ...
        runtime.sensorTrajectories, runtime.neighborMap, ...
        runtime.commConfig, triggerConfig, executionContext);

endingManifest = ...
    buildFormationB4V46DevelopmentExecutionSurfaceManifest();
endingGitState = validateFormationB4V46DevelopmentExecutionGitState( ...
    permit.executionSurfaceCommit);
if ~strcmp(endingManifest.canonicalSha256, manifest.canonicalSha256) || ...
        ~strcmp(endingGitState.headCommit, gitState.headCommit)
    error('FormationB4V46DevelopmentShard:ExecutionStateChanged', ...
        'The executable or Git state changed during arm execution.');
end
executionEvidence = struct();
executionEvidence.contractVersion = ...
    'formation-b4-v46-development-arm-execution-evidence-v1';
executionEvidence.executionHeadCommit = gitState.headCommit;
executionEvidence.executionSurfaceCommit = ...
    permit.executionSurfaceCommit;
executionEvidence.executionSurfaceManifestSha256 = ...
    manifest.canonicalSha256;
executionEvidence.pathResolutionCanonicalSha256 = ...
    pathResolution.canonicalSha256;
executionEvidence.invocationEvidence = invocationEvidence;
executionEvidence.filterSeed = filterSeed;
executionEvidence.startedAt = startedAt;
executionEvidence.completedAt = datestr(now, 31);
executionEvidence.elapsedSeconds = toc(timerId);
executionEvidence.trackedWorktreeCleanBeforeAndAfter = true;
executionEvidence.dataOnlyActivationVerifiedBeforeAndAfter = true;
executionEvidence.runtimeInputFingerprintVerified = strcmp( ...
    runtime.runtimeFingerprint.canonicalSha256, ...
    permit.runtimeFilterProjectionCanonicalSha256);
executionEvidence.registeredDeliveryRecomputedExactly = isequal( ...
    logical(diagnostics.delivered), ...
    logical(diagnostics.attempted) & ...
        (runtime.commConfig.linkUniforms >= ...
         runtime.commConfig.pDropByEdge));
executionEvidence.filterReceivedGroundTruth = false;
executionEvidence.trackingOutcomeScored = false;
shard = buildFormationB4V46DevelopmentArmShardPrivate( ...
    stateEstimatesBySensor, diagnostics, permit, ...
    runtime.runtimeFingerprint, executionEvidence);

temporaryPath = [tempname(outputDirectory), '.mat'];
temporaryCleanup = onCleanup(@() deleteIfPresent(temporaryPath));
save('-mat7-binary', temporaryPath, 'shard');
publicationManifest = ...
    buildFormationB4V46DevelopmentExecutionSurfaceManifest();
publicationGitState = ...
    validateFormationB4V46DevelopmentExecutionGitState( ...
        permit.executionSurfaceCommit);
if ~strcmp(publicationManifest.canonicalSha256, ...
        manifest.canonicalSha256) || ...
        ~strcmp(publicationGitState.headCommit, gitState.headCommit)
    error('FormationB4V46DevelopmentShard:ExecutionStateChanged', ...
        'The executable or Git state changed during shard publication.');
end
if exist(outputPath, 'file') ~= 0 || exist(outputPath, 'dir') ~= 0
    error('FormationB4V46DevelopmentShard:OutputExists', ...
        'The shard output path appeared during execution.');
end
publishFormationB4V46DevelopmentArmShardNoReplace( ...
    temporaryPath, outputPath);
clear temporaryCleanup restoreRng runtime diagnostics ...
    stateEstimatesBySensor;
fprintf('V46 development arm shard: %s\n', outputPath);
fprintf('V46 development arm shard SHA-256: %s\n', ...
    shard.canonicalSha256);
end

function deleteIfPresent(path)
if exist(path, 'file') ~= 0
    try
        delete(path);
    catch errorInfo
        warning( ...
            'FormationB4V46DevelopmentShard:TemporaryCleanupFailed', ...
            'Could not remove a temporary shard file: %s', ...
            errorInfo.message);
    end
end
end

function [resolution, invocationEvidence] = ...
    bootstrapV46DevelopmentExecutionSurface( ...
        caseOrdinal, armId, requestedOutputPath)
runnerPath = [mfilename('fullpath'), '.m'];
repoRoot = fileparts(fileparts(fileparts(runnerPath)));
expectedRunnerPath = fullfile(repoRoot, 'RUN', 'GA', ...
    'runFormationB4V46DevelopmentArmShard.m');
expectedCheckerPath = fullfile(repoRoot, 'common', ...
    'assertFormationB4V46DevelopmentCriticalFunctionPaths.m');
runnerInfo = builtin('functions', @runFormationB4V46DevelopmentArmShard);
checkerHandle = @assertFormationB4V46DevelopmentCriticalFunctionPaths;
checkerInfo = builtin('functions', checkerHandle);
if ~isfield(runnerInfo, 'file') || ...
        ~strcmp(runnerInfo.file, expectedRunnerPath) || ...
        ~isfield(checkerInfo, 'file') || ...
        ~strcmp(checkerInfo.file, expectedCheckerPath)
    error('FormationB4V46DevelopmentPermit:BootstrapPathShadowed', ...
        'The V46 runner or its first path checker was shadowed.');
end
resolution = checkerHandle();

expectedInvocationContract = ...
    'formation-b4-v46-development-invocation-v1';
expectedLauncherPath = fullfile(repoRoot, 'RUN', 'GA', ...
    'launchFormationB4V46DevelopmentArmShard.sh');
expectedProgramPath = ...
    ['/opt/homebrew/Cellar/octave/11.1.0/libexec/octave/11.1.0/', ...
     'exec/aarch64-apple-darwin25.2.0/octave-gui'];
expectedPointerSha256 = ...
    '3aa13c93b0e6f821363acd2337a72205843f9ea06be6c411b747c5afc9ef0ef0';
expectedEvalSha256 = ...
    '32763b84a99355bfb5561ca4f613af9bb23d536be5bc6dd53ca432be7c6e0272';
invocationArguments = reshape(builtin('argv'), 1, []);
expectedArgumentPrefix = { ...
    '--quiet', '--no-gui', '--no-init-all', '--eval'};
environmentCaseOrdinal = str2double(getenv( ...
    'FORMATION_B4_V46_CASE_ORDINAL'));
if numel(invocationArguments) ~= 5 || ...
        ~isequal(invocationArguments(1:4), expectedArgumentPrefix) || ...
        ~strcmp(computeTextSha256(invocationArguments{5}), ...
            expectedEvalSha256) || ...
        ~strcmp(getenv('FORMATION_B4_V46_INVOCATION_CONTRACT'), ...
            expectedInvocationContract) || ...
        ~strcmp(getenv('FORMATION_B4_V46_LAUNCHER_PATH'), ...
            expectedLauncherPath) || ...
        ~strcmp(getenv('FORMATION_B4_V46_REPO_ROOT'), repoRoot) || ...
        ~strcmp(getenv('FORMATION_B4_V46_INIT_FILES_DISABLED'), 'true') || ...
        ~strcmp(getenv( ...
            'FORMATION_B4_V46_PREFLIGHT_GIT_IDENTITY_VERIFIED'), 'true') || ...
        ~strcmp(getenv( ...
            'FORMATION_B4_V46_PREFLIGHT_TRACKED_CLEAN'), 'true') || ...
        ~strcmp(getenv( ...
            ['FORMATION_B4_V46_PREFLIGHT_UNTRACKED_', ...
             'EXECUTABLES_ABSENT']), 'true') || ...
        ~strcmp(getenv( ...
            'FORMATION_B4_V46_PREFLIGHT_GIT_POINTER_SHA256'), ...
            expectedPointerSha256) || ...
        environmentCaseOrdinal ~= caseOrdinal || ...
        ~strcmp(getenv('FORMATION_B4_V46_ARM_ID'), armId) || ...
        ~strcmp(getenv('FORMATION_B4_V46_OUTPUT_PATH'), ...
            requestedOutputPath) || ...
        ~strcmp(builtin('program_invocation_name'), expectedProgramPath) || ...
        ~strcmp(builtin('version'), '11.1.0') || ...
        ~isSanitizedRuntimePath(getenv('PATH')) || ...
        ~isExactTrackedMatlabPath(getenv( ...
            'FORMATION_B4_V46_TRACKED_MATLAB_PATH'), ...
            resolution, repoRoot) || ...
        ~strcmp(pwd, repoRoot)
    error('FormationB4V46DevelopmentPermit:LauncherRequired', ...
        'V46 execution requires the exact sanitized launcher contract.');
end
invocationPayload = struct();
invocationPayload.contractVersion = expectedInvocationContract;
invocationPayload.supportedLauncherPath = expectedLauncherPath;
invocationPayload.repoRoot = repoRoot;
invocationPayload.interpreterProgramPath = expectedProgramPath;
invocationPayload.interpreterVersion = '11.1.0';
invocationPayload.gitPointerSha256 = expectedPointerSha256;
invocationPayload.gitWorktreeIdentityVerified = true;
invocationPayload.initFilesDisabledVerified = true;
invocationPayload.officialEvalSha256 = expectedEvalSha256;
invocationPayload.interpreterArgvCanonicalSha256 = ...
    computeCanonicalValueSha256(invocationArguments);
invocationPayload.sanitizedRuntimePathVerified = true;
invocationPayload.trackedMatlabPathVerified = true;
invocationEvidence = invocationPayload;
invocationEvidence.canonicalSha256 = ...
    computeCanonicalValueSha256(invocationPayload);
end

function valid = isSanitizedRuntimePath(runtimePath)
entries = regexp(runtimePath, pathsep, 'split');
fixedEntries = { ...
    '/opt/homebrew/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin'};
valid = numel(entries) >= numel(fixedEntries) && ...
    isequal(entries(1:numel(fixedEntries)), fixedEntries);
octavePrefix = '/opt/homebrew/Cellar/octave/11.1.0/';
for entryIdx = numel(fixedEntries) + 1:numel(entries)
    valid = valid && strncmp(entries{entryIdx}, octavePrefix, ...
        numel(octavePrefix));
end
end

function valid = isExactTrackedMatlabPath( ...
        runtimePath, resolution, repoRoot)
actualDirectories = regexp(runtimePath, pathsep, 'split');
expectedDirectories = cell(size(resolution.relativePaths));
for pathIdx = 1:numel(resolution.relativePaths)
    directory = fileparts(resolution.relativePaths{pathIdx});
    if isempty(directory)
        expectedDirectories{pathIdx} = repoRoot;
    else
        expectedDirectories{pathIdx} = fullfile(repoRoot, ...
            strrep(directory, '/', filesep));
    end
end
valid = isequal(unique(sort(actualDirectories)), ...
    unique(sort(expectedDirectories)));
end
