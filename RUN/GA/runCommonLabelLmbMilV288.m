function [reportPath, result] = runCommonLabelLmbMilV288(options)
% Paired V288 fusion-family control; reuse the recorded V242/V282 filter arm.
loaded = load(options.baselineTracePath, 'trace'); baseline = loaded.trace;
T = getField(options, 'maximumTime', 40);
assert(isscalar(T) && T == round(T) && T >= 1 && T <= baseline.maximumTime);
assert(strcmp(baseline.presetName, ...
    'x36-formation-fov-temporal-coupled-formation-braid') && baseline.seed == 1301);
out = options.outputRoot;
if exist(out, 'dir') ~= 7, mkdir(out); end
rawPath = fullfile(out, 'COMMON_LABEL_MIL_V288_RAW.mat');
if exist(rawPath, 'file') == 2
    loaded = load(rawPath, 'run'); run = loaded.run;
    assert(strcmp(run.contractVersion, 'common-label-mil-v288-v1') && ...
        run.maximumTime == T && strcmp(run.baselineTracePath, options.baselineTracePath));
else
    % Generating only T steps changes measurement randomness. Generate all first.
    inputs = generateDynamicTopologyScenarioInputs(baseline.presetName, baseline.seed);
    assert(inputs.config.simulationLength == baseline.originalTimeCount);
    inputs = cropInputs(inputs, T);
    model = removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
    config = buildCausalMinimumFormationBackboneV242Config(inputs.config);
    config.lmbFusionRule = 'mil-common-label';
    config.missingLabelFusionMode = 'strict-common-label';
    config.diagnosticsProgressInterval = 5;
    assert(strcmp(config.fusionWeightMode, 'metropolis') && ...
        config.mixtureAwareMaxFusedComponents == 8);
    context = buildCausalMinimumFormationBackboneV242ExecutionContext( ...
        baseline.presetName, baseline.seed, T);
    protocol = getCausalMinimumFormationBackboneV242Protocol();
    [~, commit] = system('git rev-parse HEAD');
    rng(baseline.seed + protocol.filterSeedOffset, 'twister');
    fprintf('V288 shared-label MIL: %s, seed %d, prefix 1:%d of %d.\n', ...
        baseline.presetName, baseline.seed, T, baseline.originalTimeCount);
    started = tic;
    [estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
        model, inputs.measurements, inputs.sensorTrajectories, ...
        inputs.neighborMap, inputs.commConfig, config, context);
    run = struct('contractVersion', 'common-label-mil-v288-v1', ...
        'generationGitCommit', strtrim(commit), ...
        'baselineTracePath', options.baselineTracePath, ...
        'baselineGenerationGitCommit', baseline.generationGitCommit, ...
        'presetName', baseline.presetName, 'seed', baseline.seed, ...
        'maximumTime', T, 'originalTimeCount', baseline.originalTimeCount, ...
        'elapsedSeconds', toc(started), 'completedAt', datestr(now, 31), ...
        'fusionRule', config.lmbFusionRule, 'maximumFusedComponents', 8, ...
        'config', inputs.config, 'groundTruthRfs', inputs.groundTruthRfs, ...
        'estimates', {estimates}, 'attempted', diagnostics.attempted, ...
        'delivered', diagnostics.delivered, ...
        'attemptedPayloadBytes', diagnostics.attemptedPayloadBytes, ...
        'milFusedLabelCount', diagnostics.missingLabelFusedLabelCount, ...
        'milMissingSourceCount', diagnostics.missingLabelSourceCount, ...
        'milAffectedLabelCount', diagnostics.missingLabelAffectedLabelCount, ...
        'milTruncatedLabelCount', diagnostics.milTruncatedLabelCount, ...
        'milDiscardedSpatialMassSum', diagnostics.milDiscardedSpatialMassSum, ...
        'milMaximumDiscardedSpatialMass', diagnostics.milMaximumDiscardedSpatialMass, ...
        'developmentEvidenceOnly', true);
    % Do not save live model/config function handles into MAT7.
    save('-mat7-binary', [rawPath, '.partial'], 'run');
    movefile([rawPath, '.partial'], rawPath);
    fprintf('V288 raw output saved after %.1f seconds: %s\n', run.elapsedSeconds, rawPath);
end
reference = summarizePrefix(baseline, run.groundTruthRfs, run.config, T);
candidate = summarizePrefix(run, run.groundTruthRfs, run.config, T);
common = isfinite(reference.rmseBySensorTime) & isfinite(candidate.rmseBySensorTime);
commonReference = finiteMean(reference.rmseBySensorTime(common));
commonCandidate = finiteMean(candidate.rmseBySensorTime(common));
formationChange = 100 * (candidate.perFormationEospa ./ reference.perFormationEospa - 1);
zeroExtendedCounts = getField(run, 'milMissingSourceCount', NaN);
affectedLabelCounts = getField(run, 'milAffectedLabelCount', NaN);
result = struct('contractVersion', 'common-label-mil-v288-analysis-v1', ...
    'rawPath', rawPath, 'generationGitCommit', run.generationGitCommit, ...
    'maximumTime', T, 'seed', run.seed, 'presetName', run.presetName, ...
    'reference', reference, 'candidate', candidate, ...
    'elapsedSeconds', run.elapsedSeconds, 'commonFiniteCellCount', nnz(common), ...
    'commonReferenceRmse', commonReference, 'commonCandidateRmse', commonCandidate, ...
    'attemptedRouteDifferences', nnz(xor(run.attempted, baseline.attempted(:, :, 1:T))), ...
    'deliveredRouteDifferences', nnz(xor(run.delivered, baseline.delivered(:, :, 1:T))), ...
    'eospaImprovementPercent', 100 * (1 - candidate.eospa / reference.eospa), ...
    'commonRmseChangePercent', 100 * (commonCandidate / commonReference - 1), ...
    'attemptedByteRatio', candidate.attemptedBytes / reference.attemptedBytes, ...
    'formationEospaChangePercent', formationChange, ...
    'fusedLabelCount', sum(run.milFusedLabelCount(:)), ...
    'zeroExtendedSourceLabelCount', sum(zeroExtendedCounts(:)), ...
    'labelsAffectedByZeroExtension', sum(affectedLabelCounts(:)), ...
    'truncatedLabelCount', sum(run.milTruncatedLabelCount(:)), ...
    'meanDiscardedSpatialMass', sum(run.milDiscardedSpatialMassSum(:)) / ...
        max(1, sum(run.milFusedLabelCount(:))), ...
    'maximumDiscardedSpatialMass', max(run.milMaximumDiscardedSpatialMass(:)), ...
    'screenEvaluated', T == 40, 'developmentEvidenceOnly', true);
result.screenPassed = result.screenEvaluated && result.eospaImprovementPercent >= 1 && ...
    candidate.countError < reference.countError && ...
    candidate.representativeDisagreement <= reference.representativeDisagreement && ...
    isfinite(result.commonRmseChangePercent) && result.commonRmseChangePercent <= 1 && ...
    result.attemptedByteRatio <= 1.05 && max(formationChange) <= 1 && ...
    result.attemptedRouteDifferences == 0 && result.deliveredRouteDifferences == 0;
save('-mat7-binary', fullfile(out, 'COMMON_LABEL_MIL_V288.mat'), 'result');
reportPath = fullfile(out, 'COMMON_LABEL_MIL_V288_REPORT.md');
writeReport(reportPath, result);
writeCsv(out, result, run.config);
fprintf('V288 prefix %d: E-OSPA %.6f -> %.6f (%+.3f%% gain), RMSE %.6f -> %.6f, bytes ratio %.4f, screen evaluated %d / passed %d.\n', ...
    T, reference.eospa, candidate.eospa, result.eospaImprovementPercent, ...
    reference.conditionalRmse, candidate.conditionalRmse, result.attemptedByteRatio, ...
    result.screenEvaluated, result.screenPassed);
end

function summary = summarizePrefix(data, truth, config, T)
N = numel(data.estimates);
eospa = zeros(N, T); countError = eospa; rmse = nan(N, T);
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable'); representatives = zeros(1, numel(groups));
for g = 1:numel(groups), representatives(g) = find(groupIds == groups(g), 1); end
for n = 1:N
    rmse(n, :) = computeSetRmseOverTime(data.estimates{n}, truth);
    for t = 1:T
        c = computePositionEuclideanOspa(truth.x{t}, data.estimates{n}.mu{t}, ...
            config.ospaPositionCutoff, 2, [1, 2]);
        eospa(n, t) = c(1);
        countError(n, t) = abs(numel(data.estimates{n}.mu{t}) - numel(truth.x{t}));
    end
end
disagreement = zeros(1, T);
for t = 1:T
    values = zeros(1, nchoosek(numel(representatives), 2)); k = 0;
    for a = 1:numel(representatives)-1
        for b = a+1:numel(representatives)
            k = k + 1;
            c = computePositionEuclideanOspa(data.estimates{representatives(a)}.mu{t}, ...
                data.estimates{representatives(b)}.mu{t}, config.ospaPositionCutoff, 2, [1, 2]);
            values(k) = c(1);
        end
    end
    disagreement(t) = mean(values);
end
nodeEospa = mean(eospa, 2); nodeRmse = nan(N, 1);
for n = 1:N, nodeRmse(n) = finiteMean(rmse(n, :)); end
groupEospa = zeros(1, numel(groups));
for g = 1:numel(groups), groupEospa(g) = mean(nodeEospa(groupIds == groups(g))); end
bytes = data.attemptedPayloadBytes(:, :, 1:T);
attempted = data.attempted(:, :, 1:T); delivered = data.delivered(:, :, 1:T);
summary = struct('eospa', mean(eospa(:)), 'conditionalRmse', finiteMean(rmse(:)), ...
    'countError', mean(countError(:)), 'representativeDisagreement', mean(disagreement), ...
    'finiteRmseFraction', nnz(isfinite(rmse)) / numel(rmse), ...
    'attemptedBytes', sum(bytes(:)), 'deliveredBytes', sum(bytes(logical(delivered))), ...
    'attemptedMessages', nnz(attempted), 'deliveredMessages', nnz(delivered), ...
    'eospaBySensorTime', eospa, 'rmseBySensorTime', rmse, ...
    'countErrorBySensorTime', countError, 'disagreementByTime', disagreement, ...
    'perSensorEospa', nodeEospa, 'perSensorRmse', nodeRmse, ...
    'perFormationEospa', groupEospa, 'worstSensorEospa', max(nodeEospa), ...
    'representatives', representatives);
end

function writeReport(path, r)
fid = fopen(path, 'w'); assert(fid >= 0); cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# V288 common-label LMB-MIL: paired prefix\n\n');
fprintf(fid, 'X36, seed 1301, steps 1--%d of the original 160-step scene. Source `%s`.\n\n', ...
    r.maximumTime, r.generationGitCommit);
fprintf(fid, 'Development evidence; self-check only. Reference filter reused from V282. MIL changes the fusion family, not the V242 route or shared labels.\n\n');
fprintf(fid, '| Metric (lower is better) | V242 KLA reference | V288 reduced-GM MIL |\n| --- | ---: | ---: |\n');
names = {'E-OSPA', 'Absolute count error', 'Conditional matched RMSE', ...
    'Representative disagreement, entire prefix', 'Worst-node E-OSPA', ...
    'Attempted payload bytes', 'Delivered payload bytes', 'Attempted messages', 'Delivered messages'};
fields = {'eospa', 'countError', 'conditionalRmse', 'representativeDisagreement', ...
    'worstSensorEospa', 'attemptedBytes', 'deliveredBytes', 'attemptedMessages', 'deliveredMessages'};
for k = 1:numel(fields)
    fprintf(fid, '| %s | %.6f | %.6f |\n', names{k}, r.reference.(fields{k}), r.candidate.(fields{k}));
end
fprintf(fid, '\nCommon-finite-cell RMSE: %.6f -> %.6f, %d cells, change %+.3f%%.\n', ...
    r.commonReferenceRmse, r.commonCandidateRmse, r.commonFiniteCellCount, r.commonRmseChangePercent);
fprintf(fid, 'Finite RMSE coverage: %.6f -> %.6f; this is not an accuracy metric.\n', ...
    r.reference.finiteRmseFraction, r.candidate.finiteRmseFraction);
fprintf(fid, 'Attempted / delivered route differences: %d / %d. Runtime %.1f seconds.\n\n', ...
    r.attemptedRouteDifferences, r.deliveredRouteDifferences, r.elapsedSeconds);
fprintf(fid, 'Eight-component spatial reduction: %d / %d fused labels truncated; mean discarded conditional mass %.9f, maximum %.9f.\n\n', ...
    r.truncatedLabelCount, r.fusedLabelCount, r.meanDiscardedSpatialMass, r.maximumDiscardedSpatialMass);
fprintf(fid, 'Zero-extended missing source-label cases: %.0f across %.0f label pools. The earlier two-step integration did not retain these two counters.\n\n', ...
    r.zeroExtendedSourceLabelCount, r.labelsAffectedByZeroExtension);
fprintf(fid, '| Formation | V242 E-OSPA | V288 E-OSPA | Change (%%) |\n| --- | ---: | ---: | ---: |\n');
for g = 1:numel(r.formationEospaChangePercent)
    fprintf(fid, '| %d | %.6f | %.6f | %+.3f |\n', g, r.reference.perFormationEospa(g), ...
        r.candidate.perFormationEospa(g), r.formationEospaChangePercent(g));
end
fprintf(fid, '\nScreen evaluated: %d. Screen passed: %d. Two steps are integration only.\n', ...
    r.screenEvaluated, r.screenPassed);
fprintf(fid, 'This is not a full-episode, held-out, label-matching or complete different-FoV MIL reproduction result. No routing improvement may be attributed to a cross-fusion comparison.\n');
end

function writeCsv(out, r, config)
fid = fopen(fullfile(out, 'V288_JOINT_METRICS.csv'), 'w'); assert(fid >= 0);
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, 'metric,reference,candidate\n');
fields = {'eospa', 'conditionalRmse', 'countError', 'representativeDisagreement', ...
    'attemptedBytes', 'deliveredBytes', 'attemptedMessages', 'deliveredMessages', ...
    'finiteRmseFraction', 'worstSensorEospa'};
for k = 1:numel(fields)
    fprintf(fid, '%s,%.12g,%.12g\n', fields{k}, r.reference.(fields{k}), r.candidate.(fields{k}));
end
clear cleanup;
fid = fopen(fullfile(out, 'V288_SENSOR_METRICS.csv'), 'w'); assert(fid >= 0);
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, 'sensor,formation,reference_eospa,candidate_eospa,reference_conditional_rmse,candidate_conditional_rmse\n');
for n = 1:numel(r.reference.perSensorEospa)
    fprintf(fid, '%d,%d,%.12g,%.12g,%.12g,%.12g\n', n, config.sensorGroupIds(n), ...
        r.reference.perSensorEospa(n), r.candidate.perSensorEospa(n), ...
        r.reference.perSensorRmse(n), r.candidate.perSensorRmse(n));
end
clear cleanup;
fid = fopen(fullfile(out, 'V288_TIME_SERIES.csv'), 'w'); assert(fid >= 0);
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, 'time,reference_eospa,candidate_eospa,reference_rmse,candidate_rmse,reference_count_error,candidate_count_error,reference_disagreement,candidate_disagreement\n');
for t = 1:r.maximumTime
    fprintf(fid, '%d,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g\n', t, ...
        mean(r.reference.eospaBySensorTime(:, t)), mean(r.candidate.eospaBySensorTime(:, t)), ...
        finiteMean(r.reference.rmseBySensorTime(:, t)), finiteMean(r.candidate.rmseBySensorTime(:, t)), ...
        mean(r.reference.countErrorBySensorTime(:, t)), mean(r.candidate.countErrorBySensorTime(:, t)), ...
        r.reference.disagreementByTime(t), r.candidate.disagreementByTime(t));
end
end

function inputs = cropInputs(inputs, T)
inputs.measurements = inputs.measurements(:, 1:T);
inputs.config.simulationLength = T; inputs.model.simulationLength = T;
inputs.model.dynamicTopologyScenario.config.simulationLength = T;
for n = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{n} = inputs.sensorTrajectories{n}(:, 1:T);
end
for name = {'x', 'mu', 'Sigma'}
    inputs.groundTruthRfs.(name{1}) = inputs.groundTruthRfs.(name{1})(1:T);
end
inputs.groundTruthRfs.cardinality = inputs.groundTruthRfs.cardinality(1:T);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = inputs.commConfig.pDropByEdge(:, :, 1:T);
end
if isfield(inputs.commConfig, 'linkUniforms') && ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = inputs.commConfig.linkUniforms(:, :, 1:T);
end
inputs.graphData.physicalAdjacency = inputs.graphData.physicalAdjacency(:, :, 1:T);
inputs.graphData.positions = inputs.graphData.positions(:, :, 1:T);
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = mean(values); end
end

function value = getField(s, name, fallback)
if isfield(s, name), value = s.(name); else, value = fallback; end
end
