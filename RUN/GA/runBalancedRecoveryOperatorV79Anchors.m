function [reportPath, result] = ...
    runBalancedRecoveryOperatorV79Anchors(options)
% RUNBALANCEDRECOVERYOPERATORV79ANCHORS Source-only CBB replay.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBalancedRecoveryOperatorV79Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('BalancedRecoveryV79:DirtySource', ...
        'The V79 replay requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    [rebuiltAdjacency, referenceDetails] = ...
        selectPhysicalFormationTreeResidualTourPolicy( ...
            state.context, struct( ...
                'dominantWeight', protocol.dominantWeight, ...
                'residualWeight', protocol.residualWeight));
    if ~isequal(rebuiltAdjacency, referenceAdjacency) || ...
            max(abs(referenceDetails.fusionWeightMatrix(:) - ...
                referenceWeights(:))) > 1e-12
        error('BalancedRecoveryV79:ReferenceMismatch', ...
            'The rebuilt physical reference differs from V73.');
    end
    sequence = buildBalancedRecoverySequenceV79( ...
        state.context, referenceAdjacency, referenceDetails, struct( ...
            'dominantWeight', protocol.dominantWeight, ...
            'residualWeight', protocol.residualWeight, ...
            'nominalDoubleStochasticTolerance', ...
                protocol.nominalDoubleStochasticTolerance));
    referenceTrajectory = buildReferenceTrajectory( ...
        state, referenceAdjacency, referenceWeights, protocol);
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, historicalApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            alignedTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    historical = replayRoute( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, historicalAdjacency, historicalWeights, ...
        historicalApplied, sequence, protocol);
    aligned = replayRoute( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, alignedAdjacency, alignedWeights, ...
        alignedApplied, sequence, protocol);
    record = emptyCaseRecord();
    record.presetName = state.presetName;
    record.seed = state.seed;
    record.currentTime = state.currentTime;
    record.nodeCount = numel(state.groupIds);
    record.formationCount = numel(unique( ...
        state.groupIds, 'stable'));
    record.directSafeFormationIds = ...
        reshape(caseInfo.directSafeFormationIds, 1, []);
    record.sequence = sequence;
    record.historical = historical;
    record.aligned = aligned;
    records(caseIdx) = record;
    fprintf(['V79 %s t=%d phases=%s bound=%.4f/%.4f ', ...
        'historical=%s aligned=%s\n'], ...
        state.presetName, state.currentTime, ...
        mat2str(sequence.selectedPhasePair), ...
        sequence.selectedPeakCenteredLinearBound, ...
        sequence.selectedTerminalCenteredLinearBound, ...
        formatReplay(historical), formatReplay(aligned));
end

allHistoricalMonotone = true;
allAlignedMonotone = true;
for caseIdx = 1:numel(records)
    allHistoricalMonotone = allHistoricalMonotone && ...
        records(caseIdx).historical.balanced. ...
            centeredMonotoneNonincreasing;
    allAlignedMonotone = allAlignedMonotone && ...
        records(caseIdx).aligned.balanced. ...
            centeredMonotoneNonincreasing;
end
result = struct();
result.contractVersion = ...
    'balanced-recovery-operator-v79-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allHistoricalBalancedMonotone = allHistoricalMonotone;
result.allAlignedBalancedMonotone = allAlignedMonotone;
result.sourceMechanismGatePassed = ...
    allHistoricalMonotone && allAlignedMonotone;
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'BALANCED_RECOVERY_OPERATOR_V79_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'BALANCED_RECOVERY_OPERATOR_V79_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V79 balanced recovery operator: %s\n', reportPath);
end

function trajectory = buildReferenceTrajectory( ...
        state, adjacency, weights, protocol)
posteriors = state.context.localPosteriorBySensor;
trajectory = cell(1, protocol.totalFusionRounds);
options = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
for roundIdx = 1:protocol.totalFusionRounds
    [posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
        posteriors, adjacency, weights, state.context.model, ...
        state.context.commConfig, state.currentTime, ...
        protocol.fusionConfig, options);
    trajectory{roundIdx} = posteriors;
end
end

function replay = replayRoute( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, candidateAdjacency, candidateWeights, ...
        appliedTriples, sequence, protocol)
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
modeOptions = struct( ...
    'covarianceRegularization', protocol.covarianceRegularization);
rieOptions = struct( ...
    'conditionalEnergyLimit', protocol.recoveryCandidateRieLimit, ...
    'covarianceRegularization', protocol.covarianceRegularization);
initial = state.context.localPosteriorBySensor;
rie = computeReplacementInnovationEnergyV75( ...
    initial, appliedTriples, state.groupIds, ...
    state.context.model, state.context.commConfig, ...
    state.currentTime, rieOptions);
round1 = fuseRound(initial, candidateAdjacency, ...
    candidateWeights, state, protocol, fusionOptions);
round1Modes = scoreModes(referenceTrajectory{1}, ...
    round1, state.context.model, modeOptions);

referenceRounds = repmat(emptyRoundRecord(), 1, 3);
balancedRounds = repmat(emptyRoundRecord(), 1, 3);
referenceRounds(1) = makeRoundRecord(round1Modes);
balancedRounds(1) = makeRoundRecord(round1Modes);
referencePosteriors = round1;
balancedPosteriors = round1;
for recoveryIdx = 1:2
    roundIdx = recoveryIdx + 1;
    referencePosteriors = fuseRound( ...
        referencePosteriors, referenceAdjacency, ...
        referenceWeights, state, protocol, fusionOptions);
    balancedPosteriors = fuseRound( ...
        balancedPosteriors, ...
        sequence.recoveryAdjacencyByRound{recoveryIdx}, ...
        sequence.recoveryFusionWeightsByRound{recoveryIdx}, ...
        state, protocol, fusionOptions);
    referenceRounds(roundIdx) = makeRoundRecord(scoreModes( ...
        referenceTrajectory{roundIdx}, referencePosteriors, ...
        state.context.model, modeOptions));
    balancedRounds(roundIdx) = makeRoundRecord(scoreModes( ...
        referenceTrajectory{roundIdx}, balancedPosteriors, ...
        state.context.model, modeOptions));
end
replay = struct();
replay.appliedSlotTriples = appliedTriples;
replay.maximumRound1Rie = max( ...
    [rie.formationRecords.maximumConditionalEnergy]);
replay.round1RieSafe = rie.allFormationsSafe;
replay.reference = summarizeRounds(referenceRounds);
replay.balanced = summarizeRounds(balancedRounds);
replay.peakCenteredFactorImprovement = ...
    replay.reference.peakCenteredExpansionFactor - ...
        replay.balanced.peakCenteredExpansionFactor;
replay.terminalCenteredFactorImprovement = ...
    replay.reference.terminalCenteredFactor - ...
        replay.balanced.terminalCenteredFactor;
replay.truthUsed = false;
replay.futureMeasurementUsed = false;
end

function summary = summarizeRounds(rounds)
centered = [rounds.centeredEnergy];
summary = struct();
summary.rounds = rounds;
summary.centeredEnergyByRound = centered;
summary.existenceCenteredEnergyByRound = ...
    [rounds.existenceCenteredEnergy];
summary.spatialCenteredEnergyByRound = ...
    [rounds.spatialCenteredEnergy];
summary.commonEnergyByRound = [rounds.commonEnergy];
summary.peakCenteredExpansionFactor = ...
    max(centered(2:end)) / max(centered(1), eps);
summary.terminalCenteredFactor = ...
    centered(end) / max(centered(1), eps);
summary.centeredMonotoneNonincreasing = ...
    all(diff(centered) <= 1e-12);
end

function aggregate = scoreModes( ...
        referencePosteriors, candidatePosteriors, model, options)
modes = computeLmbArmPerturbationModesV77( ...
    referencePosteriors, candidatePosteriors, model, options);
aggregate = modes.aggregate;
end

function record = makeRoundRecord(aggregate)
record = emptyRoundRecord();
fields = fieldnames(aggregate);
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    if isfield(record, fieldName)
        record.(fieldName) = aggregate.(fieldName);
    end
end
end

function posteriors = fuseRound( ...
        posteriors, adjacency, weights, state, protocol, options)
[posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
    posteriors, adjacency, weights, state.context.model, ...
    state.context.commConfig, state.currentTime, ...
    protocol.fusionConfig, options);
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('BalancedRecoveryV79:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('BalancedRecoveryV79:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        nnz(adjacency) ~= nnz(referenceAdjacency)
    error('BalancedRecoveryV79:BudgetDrift', ...
        'Candidate replacement changed row sums or message count.');
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BalancedRecoveryV79:WriteFailed', ...
        'Cannot open V79 report for writing.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V79 balanced recovery operator\n\n');
fprintf(fid, '- Source mechanism gate passed: `%d`\n', ...
    result.sourceMechanismGatePassed);
fprintf(fid, '- Tracking outcome available: `0`\n\n');
for caseIdx = 1:numel(result.records)
    record = result.records(caseIdx);
    sequence = record.sequence;
    fprintf(fid, '## %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    fprintf(fid, '- Nodes / formations: `%d / %d`\n', ...
        record.nodeCount, record.formationCount);
    fprintf(fid, '- Selected balanced phase pair: `%s`\n', ...
        mat2str(sequence.selectedPhasePair));
    fprintf(fid, ['- Reference centered norm / column deviation: ', ...
        '`%.6f / %.6f`\n'], ...
        sequence.referenceMetrics.centeredSpectralNorm, ...
        sequence.referenceMetrics.effectiveColumnDeviation);
    fprintf(fid, ['- Balanced peak / terminal linear bound: ', ...
        '`%.6f / %.6f`\n'], ...
        sequence.selectedPeakCenteredLinearBound, ...
        sequence.selectedTerminalCenteredLinearBound);
    fprintf(fid, '- Exact message-count parity: `%d`\n\n', ...
        sequence.exactMessageCountParity);
    writeRouteTable(fid, 'Historical exact V71/V72 route', ...
        record.historical);
    writeRouteTable(fid, 'Prospective exact V73 route', ...
        record.aligned);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeRouteTable(fid, titleText, replay)
fprintf(fid, '### %s\n\n', titleText);
fprintf(fid, '- Applied slot triples: `%s`\n', ...
    mat2str(replay.appliedSlotTriples));
fprintf(fid, '- Round-1 RIE safe / maximum: `%d / %.6f`\n\n', ...
    replay.round1RieSafe, replay.maximumRound1Rie);
fprintf(fid, ['| Recovery | Centered energy by round | ', ...
    'Existence-centered | Spatial-centered | Common energy | ', ...
    'Peak | Terminal | Monotone |\n']);
fprintf(fid, ['|:--|:--|:--|:--|:--|--:|--:|:--:|\n']);
writeSummaryRow(fid, 'CRR', replay.reference);
writeSummaryRow(fid, 'CBB', replay.balanced);
fprintf(fid, '\n- CBB peak / terminal factor improvement: ');
fprintf(fid, '`%+.6f / %+.6f`\n\n', ...
    replay.peakCenteredFactorImprovement, ...
    replay.terminalCenteredFactorImprovement);
end

function writeSummaryRow(fid, name, summary)
fprintf(fid, '| %s | `%s` | `%s` | `%s` | `%s` | ', ...
    name, formatVector(summary.centeredEnergyByRound), ...
    formatVector(summary.existenceCenteredEnergyByRound), ...
    formatVector(summary.spatialCenteredEnergyByRound), ...
    formatVector(summary.commonEnergyByRound));
fprintf(fid, '%.6f | %.6f | %d |\n', ...
    summary.peakCenteredExpansionFactor, ...
    summary.terminalCenteredFactor, ...
    summary.centeredMonotoneNonincreasing);
end

function text = formatVector(values)
text = strtrim(sprintf('%.8g ', values));
text = ['[', text, ']'];
end

function text = formatReplay(replay)
text = sprintf('CBB peak=%.3f terminal=%.3f monotone=%d', ...
    replay.balanced.peakCenteredExpansionFactor, ...
    replay.balanced.terminalCenteredFactor, ...
    replay.balanced.centeredMonotoneNonincreasing);
end

function record = emptyRoundRecord()
record = struct( ...
    'labelCount', 0, ...
    'existenceCommonEnergy', 0, ...
    'existenceCenteredEnergy', 0, ...
    'spatialCommonEnergy', 0, ...
    'spatialCenteredEnergy', 0, ...
    'commonEnergy', 0, ...
    'centeredEnergy', 0, ...
    'totalEnergy', 0, ...
    'commonEnergyFraction', 0, ...
    'centeredEnergyFraction', 0);
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'nodeCount', 0, ...
    'formationCount', 0, ...
    'directSafeFormationIds', zeros(1, 0), ...
    'sequence', struct(), ...
    'historical', struct(), ...
    'aligned', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
