function [reportPath, result] = ...
    runTimeExpandedEffectiveKlaV87PrimarySourceProbe(options)
% RUNTIMEEXPANDEDEFFECTIVEKLAV87PRIMARYSOURCEPROBE Two-hop source gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getTimeExpandedEffectiveKlaGraphV87Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('TimeExpandedEffectiveKlaV87:DirtySource', ...
        'The V87 source probe requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    if numel(state.groupIds) ~= caseInfo.expectedNodeCount || ...
            numel(unique(state.groupIds)) ~= ...
                caseInfo.expectedFormationCount
        error('TimeExpandedEffectiveKlaV87:CaseDrift', ...
            'A V87 primary case no longer matches its frozen scale.');
    end
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds, struct( ...
            'referenceMode', 'current-physical-tree'));
    metrics = computeTimeExpandedEffectiveKlaPathsV87( ...
        state.context, control, state.groupIds, caseInfo, protocol);
    records(caseIdx) = makeRecord(caseInfo, metrics);
    fprintf([ ...
        'V87 %s t=%d source=%d gateway=%d paths=%d/%d ', ...
        'existence=%+.6f%% state=%+.6f%% survival=%.3f%% gate=%d\n'], ...
        records(caseIdx).presetName, records(caseIdx).currentTime, ...
        records(caseIdx).sourceIdx, records(caseIdx).gatewayIdx, ...
        records(caseIdx).enabledPathCount, ...
        records(caseIdx).candidatePathCount, ...
        100 * records(caseIdx).aggregateExistenceNetFraction, ...
        100 * records(caseIdx).aggregateStateNetFraction, ...
        100 * records(caseIdx).maximumSurvivalRatio, ...
        records(caseIdx).sourceGatePassed);
end

result = struct();
result.contractVersion = ...
    'time-expanded-effective-kla-primary-source-v87-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.bothScalesSourceGatePassed = ...
    all([records.sourceGatePassed]);
result.routeExecutionAuthorized = false;
result.trackingOutcomeRead = false;
result.trackingOutcomeScoringAuthorized = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'TIME_EXPANDED_EFFECTIVE_KLA_V87_PRIMARY_SOURCE.mat');
reportPath = fullfile(outputRoot, ...
    'TIME_EXPANDED_EFFECTIVE_KLA_V87_PRIMARY_SOURCE.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V87 time-expanded effective KLA source probe: %s\n', ...
    reportPath);
end

function record = makeRecord(caseInfo, metrics)
paths = metrics.pathRecords;
record = emptyRecord();
record.presetName = caseInfo.presetName;
record.seed = caseInfo.seed;
record.currentTime = caseInfo.currentTime;
record.sourceIdx = metrics.sourceIdx;
record.gatewayIdx = metrics.gatewayIdx;
record.receiverFormationId = metrics.receiverFormationId;
record.candidatePathCount = numel(paths);
record.enabledPathCount = metrics.enabledPathCount;
record.enabledReceiverIndices = metrics.enabledReceiverIndices;
record.enabledCoverageFraction = ...
    metrics.enabledReceiverCoverageFraction;
record.gatewayExistenceGainFraction = ...
    metrics.gatewayExistenceGainFraction;
record.gatewayExistenceHarmFraction = ...
    metrics.gatewayExistenceHarmFraction;
record.aggregateExistenceNetFraction = ...
    metrics.aggregateDownstreamExistenceNetFraction;
record.aggregateStateNetFraction = ...
    metrics.aggregateStateAlignmentNetFraction;
record.maximumSurvivalRatio = finiteMax( ...
    [paths.existenceSurvivalRatio]);
record.downwardCrossingCount = sum( ...
    [paths.downwardCrossingCount]);
record.sourceGatePassed = metrics.enabledPathCount > 0 && ...
    record.aggregateExistenceNetFraction > 0 && ...
    record.aggregateStateNetFraction >= -1e-12 && ...
    record.downwardCrossingCount == 0;
record.metrics = metrics;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('TimeExpandedEffectiveKlaV87:WriteFailed', ...
        'Could not create the V87 source report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V87 time-expanded effective KLA primary source gate\n\n');
for record = result.records
    fprintf(fid, '## %s / seed %d / t=%d\n\n', ...
        record.presetName, record.seed, record.currentTime);
    fprintf(fid, ...
        '- Source--gateway: `%d -> %d`; receiver formation: `%d`.\n', ...
        record.sourceIdx, record.gatewayIdx, ...
        record.receiverFormationId);
    fprintf(fid, ...
        '- Gateway existence gain/harm: `%+.6f%% / %+.6f%%`.\n', ...
        100 * record.gatewayExistenceGainFraction, ...
        100 * record.gatewayExistenceHarmFraction);
    fprintf(fid, ['- Enabled paths: `%d/%d`; coverage: `%.1f%%`; ', ...
        'scene gate: `%d`.\n\n'], ...
        record.enabledPathCount, record.candidatePathCount, ...
        100 * record.enabledCoverageFraction, ...
        record.sourceGatePassed);
    fprintf(fid, ['| Receiver | Displaced | Removed | Exist gain | ', ...
        'Exist harm | Exist net | Survival | State gain | ', ...
        'State harm | State net | Down crossings | Enabled |\n']);
    fprintf(fid, ...
        '|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
    for value = record.metrics.pathRecords
        fprintf(fid, ['| %d | %d | %d | %+.6f%% | %+.6f%% | ', ...
            '%+.6f%% | %.3f%% | %+.6f%% | %+.6f%% | ', ...
            '%+.6f%% | %d | %d |\n'], ...
            value.receiverIdx, value.displacedDominantSenderIdx, ...
            value.removedResidualSenderIdx, ...
            100 * value.downstreamExistenceGainFraction, ...
            100 * value.downstreamExistenceHarmFraction, ...
            100 * value.downstreamExistenceNetFraction, ...
            100 * value.existenceSurvivalRatio, ...
            100 * value.stateAlignmentGainFraction, ...
            100 * value.stateAlignmentHarmFraction, ...
            100 * value.stateAlignmentNetFraction, ...
            value.downwardCrossingCount, value.pathEnabled);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '- Both scales pass the source gate: `%d`\n', ...
    result.bothScalesSourceGatePassed);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route execution authorized: `0`\n');
fprintf(fid, '- Model training authorized: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'sourceIdx', NaN, ...
    'gatewayIdx', NaN, ...
    'receiverFormationId', NaN, ...
    'candidatePathCount', 0, ...
    'enabledPathCount', 0, ...
    'enabledReceiverIndices', zeros(1, 0), ...
    'enabledCoverageFraction', 0, ...
    'gatewayExistenceGainFraction', NaN, ...
    'gatewayExistenceHarmFraction', NaN, ...
    'aggregateExistenceNetFraction', 0, ...
    'aggregateStateNetFraction', 0, ...
    'maximumSurvivalRatio', 0, ...
    'downwardCrossingCount', 0, ...
    'sourceGatePassed', false, ...
    'metrics', struct());
end

function value = finiteMax(values)
values = reshape(values, 1, []);
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = max(values);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
