function [reportPath, result] = ...
        runInformationCoupledFormationBraidV245FullEpisode(options)
% RUNINFORMATIONCOUPLEDFORMATIONBRAIDV245FULLEPISODE Three-arm M24 study.

if nargin < 1 || isempty(options)
    options = struct();
end
presetName = 'm24-formation-fov-coupled-formation-braid';
seed = getField(options, 'seed', 1301);
resume = logical(getField(options, 'resume', true));
if ~isscalar(seed) || ~isfinite(seed) || seed ~= 1301 || ...
        ~islogical(resume) || ~isscalar(resume)
    error('CoupledFormationBraidV245:InvalidOptions', ...
        'V245 is frozen to M24 seed 1301 and a scalar resume flag.');
end

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v245', ...
    'm24_information_coupled_formation_braid_seed1301')));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

fullRouteRoot = fullfile(outputRoot, 'fixed_and_full_causal');
[fullReportPath, fullResult] = ...
    runFormationBraidRoutingComparisonV241FullEpisode(struct( ...
        'presetName', presetName, 'seed', seed, ...
        'armNames', {{'static-dropout', 'causal'}}, ...
        'resume', resume, 'outputRoot', fullRouteRoot));
fullMatPath = fullfile(fullRouteRoot, ...
    'FORMATION_BRAID_ROUTING_COMPARISON_V241_FULL_EPISODE.mat');
if ~logical(fullResult.causalStaticPairAvailable)
    error('CoupledFormationBraidV245:MissingFullPair', ...
        'The fixed-tree/full-causal pair is incomplete.');
end

sparseRoot = fullfile(outputRoot, 'minimum_causal_backbone');
[sparseReportPath, sparseResult] = ...
    runCausalMinimumFormationBackboneV242FullEpisode(struct( ...
        'presetName', presetName, 'seed', seed, ...
        'referenceResultPath', fullMatPath, ...
        'requirePositiveReference', false, ...
        'resume', resume, 'outputRoot', sparseRoot));
if ~isfield(sparseResult, 'candidate') || ...
        ~isstruct(sparseResult.candidate) || ...
        ~isfield(sparseResult.candidate, 'fullHorizonPositionEospa')
    error('CoupledFormationBraidV245:MissingSparseArm', ...
        'The minimum-backbone arm is incomplete.');
end

gitState = resolveResearchGitState();
result = struct();
result.contractVersion = ...
    'information-coupled-formation-braid-v245-result-v1';
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = presetName;
result.seed = seed;
result.fullRouteReportPath = fullReportPath;
result.sparseReportPath = sparseReportPath;
result.fixedTree = fullResult.staticDropout;
result.fullCausal = fullResult.causal;
result.minimumBackbone = sparseResult.candidate;
result.fullCausalOverFixed = fullResult.causalOverStaticDropout;
result.minimumBackboneOverFixed = ...
    sparseResult.candidateOverFixedTree;
result.minimumBackboneOverFullCausal = ...
    sparseResult.candidateOverFullCausal;
result.balancedDirectionPassed = ...
    result.minimumBackboneOverFixed.meanDirectionPassed && ...
    result.minimumBackboneOverFixed.attemptedByteSavingPercent > 0;
result.paperThresholdPassed = sparseResult.paperThresholdPassed;
result.nextMethodDecision = decideNextMethod(result);
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.evidenceBoundary = [ ...
    'V245 is a three-arm paired result on one opened M24 seed. It can ', ...
    'attribute the effect of aligning target handoffs with failed ', ...
    'formation-tree cuts and choose the next development method, but it ', ...
    'does not establish held-out, cross-scale, or paper-level benefit.'];

matPath = fullfile(outputRoot, ...
    'INFORMATION_COUPLED_FORMATION_BRAID_V245_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'INFORMATION_COUPLED_FORMATION_BRAID_V245_FULL_EPISODE.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V245 result: %s\n', reportPath);
end

function decision = decideNextMethod(result)
if result.balancedDirectionPassed
    decision = [ ...
        'retain-minimum-backbone-and-test-whether-information-valued-', ...
        'residual-edges-close-the-remaining-tail'];
elseif result.fullCausalOverFixed.meanDirectionPassed
    decision = [ ...
        'minimum-backbone-removed-useful-information-add-selective-', ...
        'residual-edges'];
else
    decision = [ ...
        'topology-repair-alone-insufficient-use-posterior-visibility-', ...
        'aware-residual-edge-selection'];
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CoupledFormationBraidV245:ReportOpenFailed', ...
        'Unable to write %s.', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fixed = result.fixedTree;
full = result.fullCausal;
sparse = result.minimumBackbone;
fullGain = result.fullCausalOverFixed;
sparseGain = result.minimumBackboneOverFixed;
fprintf(fid, '# V245 coupled formation-braid routing comparison\n\n');
fprintf(fid, '- Preset: `%s`\n', result.presetName);
fprintf(fid, '- Seed: `%d`\n', result.seed);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Balanced direction passed: `%d`\n', ...
    result.balancedDirectionPassed);
fprintf(fid, '- Paper threshold passed: `%d`\n', ...
    result.paperThresholdPassed);
fprintf(fid, '- Next method decision: `%s`\n\n', ...
    result.nextMethodDecision);
fprintf(fid, [ ...
    '| Arm | Full E-OSPA | Full RMSE | Focus consistency | ', ...
    'Attempted bytes | Messages / step |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|\n');
writeArmRow(fid, 'Fixed formation tree', fixed);
writeArmRow(fid, 'Full causal repair', full);
writeArmRow(fid, 'Minimum causal backbone', sparse);
fprintf(fid, '\n| Candidate over fixed | E-OSPA | RMSE | Focus ', ...
    'consistency | Attempted-byte saving | Weakest formation E / RMSE |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|\n');
writeGainRow(fid, 'Full causal repair', fullGain);
writeGainRow(fid, 'Minimum causal backbone', sparseGain);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeArmRow(fid, name, arm)
fprintf(fid, '| %s | %.3f | %.3f | %.3f | %.0f | %d--%d |\n', ...
    name, arm.fullHorizonPositionEospa, ...
    arm.fullHorizonPositionRmse, ...
    arm.focusInterFormationPositionOspa, ...
    arm.attemptedPayloadBytes, arm.routeMessageCountMinimum, ...
    arm.routeMessageCountMaximum);
end

function writeGainRow(fid, name, gain)
fprintf(fid, '| %s | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
    name, gain.fullHorizonEospaGainPercent, ...
    gain.fullHorizonRmseGainPercent, ...
    gain.focusConsensusGainPercent, ...
    gain.attemptedByteSavingPercent);
fprintf(fid, '%+.3f%% / %+.3f%% |\n', ...
    gain.minimumFormationEospaGainPercent, ...
    gain.minimumFormationRmseGainPercent);
end

function absolute = isAbsolutePath(path)
if ispc
    absolute = numel(path) >= 3 && isletter(path(1)) && ...
        path(2) == ':' && any(path(3) == ['\\', '/']);
else
    absolute = ~isempty(path) && path(1) == '/';
end
end

function value = getField(structure, name, defaultValue)
if isstruct(structure) && isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
