function [preflight, matPath, reportPath] = ...
    runFormationBackboneBundleM24SourcePosteriorPreflight( ...
        outputDirectory)
% RUNFORMATIONBACKBONEBUNDLEM24SOURCEPOSTERIORPREFLIGHT Fifteen caches.
%
% This runner executes only the registered fixed-reference arm.  It saves
% predecision posterior/history caches and source provenance; it neither
% receives target truth at the filter boundary nor computes a tracking score.

if nargin < 1 || isempty(outputDirectory)
    repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    outputDirectory = fullfile(repoRoot, 'RUN', 'GA', ...
        'dynamic_topology', ...
        'formation_backbone_bundle_m24_source_v1');
end
pathResolution = ...
    assertFormationBackboneBundleM24CriticalFunctionPaths();
protocol = getFormationBackboneBundleM24DevelopmentProtocol();
assertProtocolFrozenForExecution(protocol);
if exist(outputDirectory, 'dir') ~= 0 || ...
        exist(outputDirectory, 'file') ~= 0
    error('FormationBundleSourcePreflight:OutputExists', ...
        'The source preflight refuses to overwrite an existing path.');
end
mkdir(outputDirectory);
initialGitState = ...
    validateFormationBackboneBundleM24ExecutableGitState( ...
        protocol.executableSourceCommit);
initialSourceManifest = ...
    buildFormationBackboneBundleM24ExecutableSourceManifest();
if ~strcmp(initialSourceManifest.canonicalSha256, ...
        protocol.executableSourceManifestSha256)
    error('FormationBundleSourcePreflight:ExecutableSourceDrift', ...
        'The current executable manifest is not the frozen source.');
end

caseRecordCells = cell(1, protocol.caseCount);
for caseIdx = 1:protocol.caseCount
    caseContract = protocol.cases(caseIdx);
    timerId = tic;
    source = prepareFormationBackboneBundleM24SourceCaseInputs( ...
        caseContract.presetName, caseContract.seed);
    if ~isequaln(source.inputFingerprint, ...
            caseContract.sourceInputFingerprint)
        error('FormationBundleSourcePreflight:SourceInputDrift', ...
            'Case %s no longer reproduces its frozen input.', ...
            caseContract.id);
    end
    triggerConfig = ...
        buildFormationBackboneBundleM24SourceTriggerConfig( ...
            caseContract.presetName);
    executionContext = ...
        buildFormationBackboneBundleM24SourceExecutionContext( ...
            caseContract.presetName, caseContract.seed);
    rng(caseContract.seed + protocol.filterSeedOffset);
    [~, diagnostics] = ...
        runEventTriggeredDistributedLmbFilter( ...
            source.model, source.measurements, ...
            source.sensorTrajectories, source.neighborMap, ...
            source.commConfig, triggerConfig, executionContext);
    auditReferenceDiagnostics( ...
        protocol, caseContract, diagnostics);
    permit = getFormationBackboneBundleM24SourceCasePermit( ...
        caseContract.presetName, caseContract.seed);
    cache = buildFormationBackboneBundleM24SourceCache( ...
        protocol, permit, source, diagnostics);
    cacheName = sprintf('case_%02d_%s.mat', ...
        caseContract.ordinal, sanitizeFileComponent(caseContract.id));
    cachePath = fullfile(outputDirectory, cacheName);
    temporaryCachePath = [tempname(outputDirectory), '.mat'];
    temporaryCleanup = onCleanup(@() ...
        deleteIfPresent(temporaryCachePath));
    save('-mat7-binary', temporaryCachePath, 'cache');
    if exist(cachePath, 'file') ~= 0
        error('FormationBundleSourcePreflight:OutputExists', ...
            'A registered source-cache path already exists.');
    end
    movefile(temporaryCachePath, cachePath, 'f');
    clear temporaryCleanup;
    assertExecutionStateUnchanged( ...
        initialGitState, initialSourceManifest, ...
        sprintf('after case %d', caseIdx));

    record = struct();
    record.ordinal = caseContract.ordinal;
    record.caseId = caseContract.id;
    record.caseCanonicalSha256 = ...
        caseContract.caseCanonicalSha256;
    record.presetName = caseContract.presetName;
    record.seed = caseContract.seed;
    record.filterSeed = caseContract.seed + ...
        protocol.filterSeedOffset;
    record.focusWindow = caseContract.focusWindow;
    record.sourceWindow = caseContract.sourceWindow;
    record.inputFingerprint = source.inputFingerprint;
    record.cacheFileName = cacheName;
    record.cacheFileSha256 = computeFileSha256(cachePath);
    record.cachePayloadCanonicalSha256 = ...
        cache.cachePayloadCanonicalSha256;
    record.referenceDirectedMessageCount = 48;
    record.referenceCrossFormationMessageCount = ...
        expectedCrossFormationMessageCount(caseContract.sceneId);
    record.sourceExecutionSeconds = toc(timerId);
    record.trackingOutcomeScored = false;
    record.groundTruthPassedToFilter = false;
    record.topologyPolicyFutureOutcomeUsed = false;
    record.validationClaimMade = false;
    caseRecordCells{caseIdx} = record;
    fprintf('Source posterior %d/%d: %s\n', ...
        caseIdx, protocol.caseCount, caseContract.id);
end
caseRecords = [caseRecordCells{:}];
assertExecutionStateUnchanged( ...
    initialGitState, initialSourceManifest, 'before publication');

payload = struct();
payload.contractVersion = ...
    'formation-backbone-bundle-m24-source-preflight-v1';
payload.protocolId = protocol.id;
payload.protocolCanonicalSha256 = protocol.canonicalSha256;
payload.executableSourceCommit = ...
    protocol.executableSourceCommit;
payload.executionHeadCommit = initialGitState.headCommit;
payload.executableSourceManifestSha256 = ...
    initialSourceManifest.canonicalSha256;
payload.pathResolutionCanonicalSha256 = ...
    pathResolution.canonicalSha256;
payload.caseOrdering = protocol.caseOrdering;
payload.caseCount = protocol.caseCount;
payload.cases = caseRecords;
payload.sourceArm = protocol.sourceArm;
payload.trackingOutcomeScoringAuthorized = false;
payload.groundTruthAccessAuthorized = false;
payload.groundTruthPassedToFilter = false;
payload.futureOutcomeAccessAuthorized = false;
payload.validationClaimAllowed = false;
payload.pairedTrackingAuthorized = false;
payload.candidateContinuationAuthorized = false;
payload.complete = true;
payload.evidenceBoundary = [ ...
    'This artifact contains fifteen fixed-reference, source-only ', ...
    'posterior caches. It contains no tracking score and does not ', ...
    'authorize candidate continuation, paired outcomes, X36 claims, ', ...
    'or validation claims.'];
preflight = payload;
preflight.canonicalSha256 = computeCanonicalValueSha256(payload);

matPath = fullfile(outputDirectory, ...
    'formation_backbone_bundle_m24_source_preflight_v1.mat');
reportPath = fullfile(outputDirectory, ...
    'formation_backbone_bundle_m24_source_preflight_v1.md');
completionPath = fullfile(outputDirectory, ...
    'formation_backbone_bundle_m24_source_preflight_v1.complete');
temporaryMatPath = [tempname(outputDirectory), '.mat'];
temporaryReportPath = [tempname(outputDirectory), '.md'];
temporaryCompletionPath = [tempname(outputDirectory), '.complete'];
publicationCleanup = onCleanup(@() cleanupTemporaryArtifacts( ...
    temporaryMatPath, temporaryReportPath, ...
    temporaryCompletionPath));
save('-mat7-binary', temporaryMatPath, 'preflight');
writeReport(temporaryReportPath, preflight);
writeCompletionMarker(temporaryCompletionPath, preflight);
assertExecutionStateUnchanged( ...
    initialGitState, initialSourceManifest, 'during publication');
movefile(temporaryMatPath, matPath, 'f');
movefile(temporaryReportPath, reportPath, 'f');
movefile(temporaryCompletionPath, completionPath, 'f');
clear publicationCleanup;
fprintf('M24 source-only preflight: %s\n', reportPath);
end

function assertProtocolFrozenForExecution(protocol)
if ~protocol.executableSourceFrozen || ...
        isempty(protocol.executableSourceCommit) || ...
        isempty(protocol.executableSourceManifestSha256) || ...
        ~protocol.sourceInputFingerprintsFrozen || ...
        ~protocol.sourcePosteriorAuthorized || ...
        protocol.candidateContinuationAuthorized || ...
        protocol.pairedTrackingAuthorized || ...
        protocol.trackingOutcomeScoringAuthorized || ...
        protocol.groundTruthAccessAuthorized || ...
        protocol.futureOutcomeAccessAuthorized || ...
        protocol.validationClaimAllowed || ...
        numel(protocol.cases) ~= 15
    error('FormationBundleSourcePreflight:ProtocolNotFrozen', ...
        'The exact source protocol is not frozen for execution.');
end
for caseIdx = 1:numel(protocol.cases)
    if isempty(protocol.cases(caseIdx). ...
            sourceInputFingerprint.canonicalSha256)
        error('FormationBundleSourcePreflight:ProtocolNotFrozen', ...
            'A registered source input fingerprint is empty.');
    end
end
end

function auditReferenceDiagnostics(protocol, caseContract, diagnostics)
times = caseContract.sourceWindow(1):caseContract.sourceWindow(2);
expectedCrossCount = ...
    expectedCrossFormationMessageCount(caseContract.sceneId);
authorization = diagnostics.dynamicTopologyExecutionAuthorization;
expectedBackboneMode = ...
    'fixed-index-plus-registered-formation-backbone-residual-tour';
if ~strcmp(authorization.protocolCanonicalSha256, ...
            protocol.canonicalSha256) || ...
        ~strcmp(authorization.caseId, caseContract.id) || ...
        authorization.trackingOutcomeScoringAuthorized || ...
        authorization.groundTruthAccessAuthorized || ...
        authorization.futureOutcomeAccessAuthorized || ...
        authorization.validationClaimAllowed || ...
        any(~diagnostics.topologyFeasible(times)) || ...
        any(diagnostics.topologyDirectedMessageCount(times) ~= 48) || ...
        any(diagnostics.topologyPolicyCrossFormationMessageCount( ...
            times) ~= expectedCrossCount) || ...
        any(diagnostics.topologyPolicyPosteriorContentUsed(times)) || ...
        any(diagnostics.topologyPolicyTruthUsed(times)) || ...
        any(diagnostics.topologyPolicyFutureOutcomeUsed(times)) || ...
        any(diagnostics.topologyPolicyCurrentLinkReliabilityUsed(times)) || ...
        any(~diagnostics.topologyPolicyObservableContextOnly(times)) || ...
        any(~isfinite(diagnostics.topologyPolicySeconds(times))) || ...
        any(diagnostics.topologyPolicyRepairTriggered(times)) || ...
        any(diagnostics.topologyPolicyPayloadEmergencyUsed(times)) || ...
        ~all(cellfun(@(value) strcmp(value, expectedBackboneMode), ...
            diagnostics.topologyPolicyBackboneMode(times)))
    error('FormationBundleSourcePreflight:ReferenceAuditFailed', ...
        'The registered fixed-reference runtime contract failed.');
end
snapshotTime = caseContract.continuationSnapshotTime;
if isempty(diagnostics.topologyLocalPosteriorSnapshot{snapshotTime})
    error('FormationBundleSourcePreflight:ReferenceAuditFailed', ...
        'The registered predecision posterior snapshot is absent.');
end
end

function count = expectedCrossFormationMessageCount(sceneId)
if strcmp(sceneId, 'radial')
    count = 8;
elseif any(strcmp(sceneId, {'convoy', 'relay'}))
    count = 6;
else
    error('FormationBundleSourcePreflight:UnknownScene', ...
        'A source scene lacks a registered cross-message count.');
end
end

function assertExecutionStateUnchanged(initialGitState, ...
        initialManifest, stageLabel)
currentGitState = ...
    validateFormationBackboneBundleM24ExecutableGitState( ...
        initialGitState.expectedExecutableCommit);
currentManifest = ...
    buildFormationBackboneBundleM24ExecutableSourceManifest();
if ~strcmp(currentGitState.headCommit, initialGitState.headCommit) || ...
        ~strcmp(currentManifest.canonicalSha256, ...
            initialManifest.canonicalSha256)
    error('FormationBundleSourcePreflight:SourceChangedDuringRun', ...
        'Executable source changed %s.', stageLabel);
end
end

function value = sanitizeFileComponent(value)
value = regexprep(value, '[^A-Za-z0-9_.-]', '_');
end

function deleteIfPresent(path)
if exist(path, 'file') ~= 0
    delete(path);
end
end

function cleanupTemporaryArtifacts(varargin)
for pathIdx = 1:nargin
    deleteIfPresent(varargin{pathIdx});
end
end

function writeReport(path, preflight)
fid = fopen(path, 'w');
if fid < 0
    error('FormationBundleSourcePreflight:ReportWriteFailed', ...
        'The source-only report could not be created.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation-backbone M24 source-only preflight\n\n');
fprintf(fid, '- Protocol SHA-256: `%s`\n', ...
    preflight.protocolCanonicalSha256);
fprintf(fid, '- Executable commit: `%s`\n', ...
    preflight.executableSourceCommit);
fprintf(fid, '- Execution HEAD: `%s`\n', ...
    preflight.executionHeadCommit);
fprintf(fid, '- Executable manifest SHA-256: `%s`\n', ...
    preflight.executableSourceManifestSha256);
fprintf(fid, '- Preflight SHA-256: `%s`\n\n', ...
    preflight.canonicalSha256);
fprintf(fid, ['| # | Preset | Seed | Window | Input SHA-256 | ', ...
    'Cache payload SHA-256 | Seconds |\n']);
fprintf(fid, '|--:|:--|--:|:--|:--|:--|--:|\n');
for caseIdx = 1:numel(preflight.cases)
    record = preflight.cases(caseIdx);
    fprintf(fid, '| %d | `%s` | %d | `%s` | `%s` | `%s` | %.2f |\n', ...
        record.ordinal, record.presetName, record.seed, ...
        mat2str(record.sourceWindow), ...
        record.inputFingerprint.canonicalSha256, ...
        record.cachePayloadCanonicalSha256, ...
        record.sourceExecutionSeconds);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function writeCompletionMarker(path, preflight)
fid = fopen(path, 'w');
if fid < 0
    error('FormationBundleSourcePreflight:MarkerWriteFailed', ...
        'The source-only completion marker could not be created.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, 'contract=%s\n', preflight.contractVersion);
fprintf(fid, 'preflight_sha256=%s\n', preflight.canonicalSha256);
fprintf(fid, 'case_count=%d\n', preflight.caseCount);
fprintf(fid, 'tracking_outcome_scored=0\n');
fprintf(fid, 'ground_truth_passed_to_filter=0\n');
fprintf(fid, 'validation_claim_made=0\n');
end
