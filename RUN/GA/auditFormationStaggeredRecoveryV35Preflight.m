function [reportPath, preflight] = ...
    auditFormationStaggeredRecoveryV35Preflight(options)
% AUDITFORMATIONSTAGGEREDRECOVERYV35PREFLIGHT Source-only t=73 probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationStaggeredRecoveryProbeProtocol();
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v35 preflight requires a clean tracked and ', ...
        'MATLAB/Octave source state.']);
end
sourceScreenPath = getField(options, 'sourceScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v30', 'causal_isolate_reconnect', ...
    't72', 'screen', ...
    ['FORMATION_ISOLATE_RECONNECT_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
sourcePreflightPath = getField(options, ...
    'sourcePreflightPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'formation_value_v30', 'causal_isolate_reconnect', ...
        'preflight', ...
        ['FORMATION_CAUSAL_ISOLATE_RECONNECT_V30_', ...
         'PREFLIGHT.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_STAGGERED_RECOVERY_V35_', ...
     'PREFLIGHT_20260802.md']));
matPath = getField(options, 'matPath', fullfile( ...
    protocol.outputRoot, 'preflight', ...
    'FORMATION_STAGGERED_RECOVERY_V35_PREFLIGHT.mat'));

loadedScreen = load(sourceScreenPath, 'screen');
loadedPreflight = load(sourcePreflightPath, 'preflight');
if ~isfield(loadedScreen, 'screen') || ...
        ~isfield(loadedPreflight, 'preflight')
    error('V35Preflight:MissingSource', ...
        'Frozen v30 source evidence is unavailable.');
end
sourceScreen = loadedScreen.screen;
sourcePreflight = loadedPreflight.preflight;
assertSourceProvenance( ...
    sourceScreen, sourcePreflight, protocol);

replayTimer = tic;
[context, replay] = ...
    replayFormationRetentionDebtV30SourceTrajectory( ...
        sourceScreen, sourcePreflight, protocol, ...
        protocol.staggerTime);
replaySeconds = toc(replayTimer);
assertReplayMatchesFrozenPrefix(replay, sourceScreen, protocol);

controlTimer = tic;
control = buildFormationStaggeredRecoveryControl(context);
controlSeconds = toc(controlTimer);
assertControlContract(control, protocol);

cleanSource = ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles);
preflight = struct();
preflight.contractVersion = ...
    'formation-staggered-recovery-v35-preflight-v1';
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.protocol = protocol;
preflight.sourceScreenPath = sourceScreenPath;
preflight.sourcePreflightPath = sourcePreflightPath;
preflight.sourceScreenGenerationCommit = ...
    sourceScreen.generationGitCommit;
preflight.sourceCachePath = sourceScreen.cachePath;
preflight.sourceCacheSha256 = sourceScreen.cacheSha256;
preflight.presetName = sourceScreen.presetName;
preflight.seed = sourceScreen.seed;
preflight.anchorTime = protocol.anchorTime;
preflight.staggerTime = protocol.staggerTime;
preflight.sourceTrajectoryReplaySeconds = replaySeconds;
preflight.controlConstructionSeconds = controlSeconds;
preflight.sourceTrajectoryReplay = replay;
preflight.staggeredRecoveryControl = control;
preflight.baseSelectedFormationIds = ...
    control.incumbentFormationIds;
preflight.suspensionAgeByFormation = ...
    control.suspensionAgeByFormation;
preflight.matureFormationIds = ...
    control.releaseSchedule.matureFormationIds;
preflight.releaseOrder = control.releaseSchedule.releaseOrder;
preflight.candidateRetainedFormationIds = ...
    control.releaseSchedule.candidateRetainedFormationIds;
preflight.candidateRetainedDebtCoverage = ...
    control.releaseSchedule.candidateRetainedDebtCoverage;
preflight.candidateSafetyMask = control.candidateSafetyMask;
preflight.candidateEligibilityMask = ...
    control.candidateEligibilityMask;
preflight.candidateDisagreementImprovementFraction = ...
    control.candidateDisagreementImprovementFraction;
preflight.selectedFormationIds = control.selectedFormationIds;
preflight.releasedFormationIds = control.releasedFormationIds;
preflight.selectedDebtCoverageFraction = ...
    control.selectedDebtCoverageFraction;
preflight.selectedDisagreementImprovementFraction = ...
    control.selectedDisagreementImprovementFraction;
preflight.selectedActionName = control.selectedActionName;
preflight.staggeredReleaseUsed = ...
    control.staggeredReleaseUsed;
preflight.referenceFallbackUsed = ...
    control.referenceFallbackUsed;
preflight.sourceTrajectoryUsesTruth = false;
preflight.sourceTrajectoryUsesFutureOutcome = false;
preflight.trackingOutcomeScored = false;
preflight.newTrackingStateOpened = false;
preflight.additionalM24StateAuthorized = false;
preflight.gnnTrainingAuthorized = false;
preflight.x36Opened = false;
preflight.x48Opened = false;
preflight.validationClaimAllowed = false;
preflight.trackingOutcomeRerunAuthorized = ...
    protocol.trackingOutcomeRerunAuthorized && ...
    cleanSource && control.staggeredReleaseUsed && ...
    ~control.referenceFallbackUsed && ...
    control.selectedScore.safe && ...
    control.selectedDebtCoverageFraction >= protocol. ...
        minimumRetainedDebtCoverageFraction - 1e-12 && ...
    control.selectedDisagreementImprovementFraction >= protocol. ...
        minimumIncumbentDisagreementImprovementFraction - 1e-12 && ...
    control.messageSavingCount >= ...
        protocol.minimumMessageSavingCount && ...
    all(control.selectedRollingB3SensorPass) && ...
    all(control.selectedRollingB3FormationPass);
preflight.evidenceBoundary = protocol.evidenceBoundary;

if exist(fileparts(matPath), 'dir') ~= 7
    mkdir(fileparts(matPath));
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('V35 staggered-recovery preflight: %s\n', reportPath);
end

function assertSourceProvenance(screen, preflight, protocol)
if ~strcmp(screen.contractVersion, ...
        'formation-causal-isolate-reconnect-v30-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            protocol.sourceV30ScreenGenerationCommit) || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.cacheSha256, protocol.sourceCacheSha256) || ...
        ~strcmp(screen.presetName, protocol.presetName) || ...
        screen.seed ~= protocol.seed || ...
        screen.currentTime ~= protocol.anchorTime || ...
        screen.strictStrongCandidateCount ~= 0 || ...
        screen.strongCandidateFound || ...
        screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed || ...
        ~strcmp(preflight.contractVersion, ...
            'formation-causal-isolate-reconnect-v30-preflight-v1') || ...
        ~preflight.primaryTrackingScreenAuthorized || ...
        preflight.selectedInitialActionIndex ~= 15 || ...
        ~isequal(preflight.selectedFormationIdsAtAnchor, [2, 3, 4])
    error('V35Preflight:SourceProvenance', ...
        'Frozen v30 source provenance changed.');
end
end

function assertReplayMatchesFrozenPrefix(replay, screen, protocol)
candidateIdx = setdiff( ...
    1:numel(screen.outcomes), screen.referenceSubsetIndex);
if numel(candidateIdx) ~= 1
    error('V35Preflight:ReplayDrift', ...
        'Frozen v30 candidate is ambiguous.');
end
source = screen.outcomes(candidateIdx);
prefixCount = protocol.staggerTime - protocol.anchorTime + 1;
if ~isequal(replay.returnTimes, ...
        screen.returnTimes(1:prefixCount)) || ...
        ~isequal(replay.selectedAdjacency, ...
            source.selectedAdjacency(:, :, 1:prefixCount)) || ...
        ~isequal(replay.attemptedBytesByTime, ...
            source.attemptedBytesByTime(1:prefixCount)) || ...
        ~isequaln(replay.retentionDebtFractionByTime, ...
            source.retentionDebtFractionByTime(1:prefixCount)) || ...
        ~isequal(replay. ...
            retentionDebtSelectedFormationIdsByTime, ...
            source.retentionDebtSelectedFormationIdsByTime( ...
                1:prefixCount)) || ...
        ~all(replay.posteriorContentUsedByTime) || ...
        ~all(replay.currentLinkReliabilityUsedByTime) || ...
        replay.truthUsed || replay.futureOutcomeUsed || ...
        replay.trackingOutcomeScored
    error('V35Preflight:ReplayDrift', ...
        'Source-only replay differs from the frozen v30 prefix.');
end
end

function assertControlContract(control, protocol)
schedule = control.releaseSchedule;
if ~strcmp(control.contractVersion, ...
        'formation-staggered-recovery-control-v1') || ...
        ~strcmp(control.protocolId, protocol.id) || ...
        control.nodeCount ~= protocol.expectedNodeCount || ...
        control.formationCount ~= protocol.expectedFormationCount || ...
        control.evaluatedRouteCount > ...
            protocol.maximumControlRouteEvaluations || ...
        ~isequal(control.incumbentFormationIds, ...
            protocol.expectedBaseSelectedFormationIds) || ...
        ~isequal(schedule.matureFormationIds, ...
            protocol.expectedMatureFormationIds) || ...
        ~isequal(schedule.releaseOrder, ...
            protocol.expectedReleaseOrder) || ...
        ~isequal(schedule.candidateRetainedFormationIds, ...
            protocol.expectedCandidateRetainedFormationIds) || ...
        ~isequal(control.candidateSafetyMask, ...
            protocol.expectedCandidateSafetyMask) || ...
        ~isequal(control.candidateEligibilityMask, ...
            protocol.expectedCandidateEligibilityMask) || ...
        ~isequal(control.selectedFormationIds, ...
            protocol.expectedSelectedFormationIds) || ...
        control.referenceFallbackUsed ~= ...
            protocol.expectedReferenceFallback || ...
        control.staggeredReleaseUsed ~= ...
            protocol.expectedStaggeredReleaseUsed || ...
        abs(control.selectedDebtCoverageFraction - ...
            protocol.expectedRetainedDebtCoverageFraction) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.incumbentScore.networkRisk - ...
            protocol.expectedIncumbentNetworkRisk) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.networkRisk - ...
            protocol.expectedSelectedNetworkRisk) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedDisagreementImprovementFraction - ...
            protocol.expectedDisagreementImprovementFraction) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.retentionRisk - ...
            protocol.expectedSelectedRetentionRisk) > ...
                protocol.sourceMetricTolerance || ...
        ~control.referenceScore.safe || ...
        ~control.incumbentScore.safe || ...
        ~control.selectedScore.safe || ...
        control.selectedDebtCoverageFraction < protocol. ...
            minimumRetainedDebtCoverageFraction - 1e-12 || ...
        control.selectedDisagreementImprovementFraction < protocol. ...
            minimumIncumbentDisagreementImprovementFraction - 1e-12 || ...
        control.messageSavingCount < ...
            protocol.minimumMessageSavingCount || ...
        ~all(control.selectedRollingB3SensorPass) || ...
        ~all(control.selectedRollingB3FormationPass) || ...
        ~control.selectionUsesCurrentPosterior || ...
        ~control.selectionUsesCurrentLinkReliability || ...
        ~control.selectionUsesSelectedTopologyHistory || ...
        control.truthUsed || control.futureOutcomeUsed || ...
        control.validationClaimAllowed
    error('V35Preflight:ControlContract', ...
        'Staggered-recovery controller violated a frozen invariant.');
end
end

function writeReport(path, preflight)
control = preflight.staggeredRecoveryControl;
schedule = control.releaseSchedule;
fid = fopen(path, 'w');
if fid < 0
    error('V35Preflight:WriteFailed', ...
        'Could not open v35 preflight report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V35 debt-coverage staggered-recovery preflight\n\n');
fprintf(fid, '- Contract / generation commit: `%s / %s`\n', ...
    preflight.contractVersion, preflight.generationGitCommit);
fprintf(fid, '- Tracked dirty / untracked source: `%d / %d`\n', ...
    preflight.generationTrackedWorktreeDirty, ...
    numel(preflight.generationUntrackedSourceFiles));
fprintf(fid, '- Preset / seed / decision time: `%s / %d / %d`\n', ...
    preflight.presetName, preflight.seed, preflight.staggerTime);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    preflight.sourceCacheSha256);
fprintf(fid, '- Incumbent / selected suspension: `%s / %s`\n', ...
    mat2str(preflight.baseSelectedFormationIds), ...
    mat2str(preflight.selectedFormationIds));
fprintf(fid, '- Released formation(s): `%s`\n', ...
    mat2str(preflight.releasedFormationIds));
fprintf(fid, '- Retained debt coverage: `%.4f%%`\n', ...
    100 * preflight.selectedDebtCoverageFraction);
fprintf(fid, '- Incumbent disagreement: `%.9f`\n', ...
    control.incumbentScore.networkRisk);
fprintf(fid, '- Selected disagreement: `%.9f`\n', ...
    control.selectedScore.networkRisk);
fprintf(fid, '- Relative disagreement improvement: `%+.4f%%`\n', ...
    100 * preflight.selectedDisagreementImprovementFraction);
fprintf(fid, '- Tracking scored / authorized: `%d / %d`\n', ...
    preflight.trackingOutcomeScored, ...
    preflight.trackingOutcomeRerunAuthorized);
fprintf(fid, '- Replay / control construction: `%.2f / %.2f s`\n\n', ...
    preflight.sourceTrajectoryReplaySeconds, ...
    preflight.controlConstructionSeconds);

fprintf(fid, '## Source-only candidate table\n\n');
fprintf(fid, [ ...
    '| Released | Retained | Debt coverage | Disagreement improvement ', ...
    '| Retention risk | Min label retention | Drops | Safe | Eligible |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|--:|--:|:--:|:--:|\n');
for candidateIdx = 1:schedule.candidateCount
    score = control.candidateScores{candidateIdx};
    fprintf(fid, [ ...
        '| `%s` | `%s` | %.3f%% | %+.4f%% | %.6f | %.6f ', ...
        '| %d | %d | %d |\n'], ...
        mat2str(schedule. ...
            candidateReleasedFormationIds{candidateIdx}), ...
        mat2str(schedule. ...
            candidateRetainedFormationIds{candidateIdx}), ...
        100 * schedule. ...
            candidateRetainedDebtCoverage(candidateIdx), ...
        100 * control. ...
            candidateDisagreementImprovementFraction(candidateIdx), ...
        score.retentionRisk, ...
        score.minimumSupportedLabelRetentionRatio, ...
        score.decisionThresholdCrossingCount, ...
        control.candidateSafetyMask(candidateIdx), ...
        control.candidateEligibilityMask(candidateIdx));
end

fprintf(fid, '\n## Decision\n\n');
if preflight.trackingOutcomeRerunAuthorized
    fprintf(fid, [ ...
        'The clean source-only gate selects `%s`: formation 3 is ', ...
        'restored at t=73 while formations 2 and 4 remain protected. ', ...
        'One paired H=3 tracking rerun on the already-opened t=72 ', ...
        'state is authorized.\n\n'], preflight.selectedActionName);
else
    fprintf(fid, [ ...
        'No clean eligible staggered route is available. Stop before ', ...
        'tracking or opening another state.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
