function [reportPath, result] = ...
        runSinglePassSemanticInputRoutingH3V221(options)
% RUNSINGLEPASSSEMANTICINPUTROUTINGH3V221 Frozen one-pass KLA screens.

if nargin < 1 || isempty(options)
    options = struct();
end
etaProjectionEnabled = getField(options, ...
    'etaProjectionEnabled', false);
weightMode = lower(strrep(char(getField(options, ...
    'inputRouteWeightMode', 'proportional-share')), '_', '-'));
if ~validBoolean(etaProjectionEnabled)
    error('SinglePassSemanticInputRoutingV221:InvalidProjectionMode', ...
        'The eta-projection mode flag must be Boolean.');
end
etaProjectionEnabled = logical(etaProjectionEnabled);
dominantEdgeReplacementEnabled = ...
    strcmp(weightMode, 'dominant-nonself-transfer');
if dominantEdgeReplacementEnabled && ~etaProjectionEnabled
    error('SinglePassSemanticInputRoutingV221:UnsafeReplacementMode', ...
        'Dominant-edge replacement requires the V223 eta projection.');
end
if dominantEdgeReplacementEnabled
    protocol = getEtaSafeDominantEdgeReplacementV225Protocol();
elseif etaProjectionEnabled
    protocol = getEtaSafeSemanticInputRoutingV223Protocol();
else
    protocol = getSinglePassSemanticInputRoutingV221Protocol();
end
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
synopsisBytesOverride = getField(options, ...
    'inputRouteSynopsisBytesOverride', NaN);
sourceWeights = reshape(getField(options, 'sourceWeights', ...
    protocol.repairSourceWeight), ...
    1, []);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices) || ...
        isempty(sourceWeights) || any(~isfinite(sourceWeights)) || ...
        any(sourceWeights <= 0) || any(sourceWeights >= 1) || ...
        numel(unique(sourceWeights)) ~= numel(sourceWeights) || ...
        ~isscalar(synopsisBytesOverride) || ...
        ~ismember(weightMode, { ...
            'proportional-share', 'dominant-nonself-transfer'}) || ...
        (~isnan(synopsisBytesOverride) && ...
         (~isfinite(synopsisBytesOverride) || synopsisBytesOverride < 0))
    error('SinglePassSemanticInputRoutingV221:InvalidRunRequest', ...
        'The V221 candidate bank, rows, or source shares are invalid.');
end

loaded = load(candidateBankPath, 'result');
bankResult = loaded.result;
if ~isstruct(bankResult) || ~isscalar(bankResult) || ...
        ~isfield(bankResult, 'contractVersion') || ...
        ~strcmp(bankResult.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        bankResult.truthUsedForCandidateFeatures || ...
        bankResult.futureInformationUsedForCandidateFeatures
    error('SinglePassSemanticInputRoutingV221:CandidateBankContract', ...
        'V221 requires one causal V220 candidate bank.');
end
if isempty(recordIndices)
    selectedRows = find(bankResult.creditFeasibleMask);
else
    [present, selectedRows] = ismember(recordIndices, ...
        [bankResult.records.recordIndex]);
    if ~all(present) || ...
            (isnan(synopsisBytesOverride) && ...
             any(~bankResult.creditFeasibleMask(selectedRows)))
        error('SinglePassSemanticInputRoutingV221:RecordIndices', ...
            ['Every selected row must be credit-feasible under the ', ...
             'registered synopsis or supply an explicit synopsis override.']);
    end
end

sourceLoaded = load(bankResult.sourceScreenPath, 'screen');
sourceScreen = sourceLoaded.screen;
sourceCachePath = resolveSourcePath( ...
    bankResult.sourceScreenPath, sourceScreen.cachePath);
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'single_pass_h3', ...
    sprintf('%s_seed%d_t%d_donor_f%d', ...
        strrep(bankResult.presetName, '-', '_'), bankResult.seed, ...
        bankResult.currentTime, bankResult.donorFormationId))));
records = repmat(emptyRecord(), 1, ...
    numel(selectedRows) * numel(sourceWeights));
recordPosition = 0;
for row = reshape(selectedRows, 1, [])
    bankRecord = bankResult.records(row);
    for sourceWeight = sourceWeights
        recordPosition = recordPosition + 1;
        leaf = sprintf('r%03d_b%d_s%d_l%d-%d_w%03d', ...
            bankRecord.recordIndex, bankRecord.beneficiaryFormationId, ...
            bankRecord.sourceId, bankRecord.label(1), ...
            bankRecord.label(2), round(100 * sourceWeight));
        screenRoot = fullfile(outputRoot, leaf, 'screen');
        screenOptions = struct();
        screenOptions.horizonSteps = protocol.horizonSteps;
        screenOptions.interventionDurationSteps = 1;
        screenOptions.filterSeedOffset = protocol.filterSeedOffset;
        screenOptions.cacheRoot = fileparts(sourceCachePath);
        if dominantEdgeReplacementEnabled
            screenOptions.interventionBankType = ...
                'eta-safe-dominant-edge-replacement-v225';
        elseif etaProjectionEnabled
            screenOptions.interventionBankType = ...
                'eta-safe-semantic-input-routing-v223';
        else
            screenOptions.interventionBankType = ...
                'single-pass-semantic-input-routing-v221';
        end
        screenOptions.trackingAlignedExecutionProfile = ...
            'v214-direct-graph-payload-repair';
        screenOptions.receiverMode = protocol.receiverMode;
        screenOptions.directGraphSplitName = 'training';
        if isnan(synopsisBytesOverride)
            inputRouteSynopsisBytes = bankRecord.synopsisBytes;
        else
            inputRouteSynopsisBytes = synopsisBytesOverride;
        end
        screenOptions.singlePassSemanticInputRoutingBankOptions = struct( ...
            'donorFormationId', bankRecord.donorFormationId, ...
            'beneficiaryFormationId', ...
                bankRecord.beneficiaryFormationId, ...
            'referenceAttemptedBytes', ...
                bankResult.referencePageBytes, ...
            'repairSourceWeight', sourceWeight, ...
            'repairIdealDeliveryTeacherMode', true, ...
            'repairForcedSourceId', bankRecord.sourceId, ...
            'repairForcedLabel', bankRecord.label, ...
            'inputRouteSynopsisBytes', inputRouteSynopsisBytes, ...
            'inputRouteUtilityLowerBound', ...
                bankRecord.candidate.minimumRiskReduction, ...
            'inputRouteWeightMode', weightMode, ...
            'inputRouteEtaProjectionEnabled', ...
                etaProjectionEnabled, ...
            'inputRouteMinimumMapExistence', getField(protocol, ...
                'minimumMapExistence', 0.50), ...
            'inputRouteMaximumReferenceLogOddsDrop', ...
                getField(protocol, ...
                    'maximumReferenceLogOddsDrop', 0), ...
            'inputRouteEtaIdentityTolerance', getField(protocol, ...
                'identityTolerance', 1e-8));
        screenOptions.referenceOutcomeScreenPath = ...
            bankResult.sourceScreenPath;
        screenOptions.outputDirectory = screenRoot;
        screenOptions.writeReport = true;
        screenOptions.capturePosteriorSnapshotsEnabled = false;
        screenOptions.captureFusedPosteriorSnapshotsEnabled = false;
        [~, candidateScreen] = runFormationModeOpenedReturnScreen( ...
            bankResult.presetName, bankResult.seed, ...
            bankResult.currentTime, screenOptions);

        nonreferenceIdx = find([candidateScreen.records.actionIndex] ~= ...
            candidateScreen.bank.referenceActionIndex);
        if numel(nonreferenceIdx) ~= 1
            error('SinglePassSemanticInputRoutingV221:CandidateArm', ...
                'Every V221 screen must contain one semantic route arm.');
        end
        candidateOutcome = candidateScreen.outcomes(nonreferenceIdx);
        referenceOutcome = candidateScreen.outcomes( ...
            candidateScreen.referenceSubsetIndex);
        appliedActionCount = candidateOutcome. ...
            budgetRecycledFormationRepairAppliedActionCountByTime(1);
        if (~etaProjectionEnabled && appliedActionCount ~= 1) || ...
                (etaProjectionEnabled && ...
                 ~ismember(appliedActionCount, [0, 1]))
            error('SinglePassSemanticInputRoutingV221:ActionNotApplied', ...
                'The label-input route execution count is inconsistent.');
        end
        routePageDetails = candidateOutcome. ...
            budgetRecycledFormationRepairDetailsByTime{1};
        donorIdx = find(strcmp({sourceScreen.records.actionName}, ...
            bankResult.donorRecord.actionName), 1);
        donorOutcome = sourceScreen.outcomes(donorIdx);
        jointGain = buildGainVector(referenceOutcome, candidateOutcome, ...
            candidateScreen.sensorGroupIds, ...
            bankRecord.beneficiaryFormationId);
        incrementalGain = buildGainVector(donorOutcome, candidateOutcome, ...
            candidateScreen.sensorGroupIds, ...
            bankRecord.beneficiaryFormationId);
        screenRecord = candidateScreen.records(nonreferenceIdx);

        item = emptyRecord();
        item.recordIndex = bankRecord.recordIndex;
        item.sourceWeight = sourceWeight;
        item.inputRouteWeightMode = weightMode;
        item.donorFormationId = bankRecord.donorFormationId;
        item.beneficiaryFormationId = ...
            bankRecord.beneficiaryFormationId;
        item.sourceId = bankRecord.sourceId;
        item.label = bankRecord.label;
        item.inputRouteSynopsisBytes = inputRouteSynopsisBytes;
        item.screenPath = candidateScreen.matPath;
        item.jointGainVectorPercent = jointGain;
        item.incrementalGainVectorPercent = incrementalGain;
        item.meanEospaGainPercent = jointGain(1);
        item.meanRmseGainPercent = jointGain(2);
        item.consensusGainPercent = jointGain(3);
        item.terminalConsensusGainPercent = jointGain(4);
        item.incrementalEospaGainPercent = incrementalGain(1);
        item.incrementalRmseGainPercent = incrementalGain(2);
        item.incrementalConsensusGainPercent = incrementalGain(3);
        item.incrementalTerminalConsensusGainPercent = incrementalGain(4);
        item.incrementalBeneficiaryEospaGainPercent = incrementalGain(5);
        item.incrementalBeneficiaryRmseGainPercent = incrementalGain(6);
        item.attemptedByteSavingPercent = ...
            screenRecord.attemptedByteSavingPercent;
        item.jointCorePositive = all(jointGain(1:4) > 0);
        item.incrementalCorePositive = all(incrementalGain(1:4) > 0);
        item.byteConservationPassed = ...
            item.attemptedByteSavingPercent > 0;
        item.etaProjectionEnabled = etaProjectionEnabled;
        item.etaProjectionAppliedActionCount = appliedActionCount;
        item.etaProjectionEvaluatedReceiverIds = reshape(getField( ...
            routePageDetails, 'etaProjectionEvaluatedReceiverIds', ...
            zeros(1, 0)), 1, []);
        item.etaProjectionAllowedReceiverIds = reshape(getField( ...
            routePageDetails, 'etaProjectionAllowedReceiverIds', ...
            zeros(1, 0)), 1, []);
        item.etaProjectionRejectedReceiverIds = reshape(getField( ...
            routePageDetails, 'etaProjectionRejectedReceiverIds', ...
            zeros(1, 0)), 1, []);
        [item.replacedSourceIdsByReceiver, ...
         item.transferredTopologyWeightByReceiver] = ...
            summarizeDominantEdgeTransfers(routePageDetails, ...
                numel(candidateScreen.sensorGroupIds));
        records(recordPosition) = item;
    end
end

result = struct();
if dominantEdgeReplacementEnabled
    result.contractVersion = ...
        'eta-safe-dominant-edge-replacement-h3-v225-v1';
elseif etaProjectionEnabled
    result.contractVersion = ...
        'eta-safe-semantic-input-routing-h3-v223-v1';
else
    result.contractVersion = ...
        'single-pass-semantic-input-routing-h3-v221-v1';
end
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.sourceScreenPath = bankResult.sourceScreenPath;
result.presetName = bankResult.presetName;
result.seed = bankResult.seed;
result.currentTime = bankResult.currentTime;
result.donorFormationId = bankResult.donorFormationId;
result.sourceWeights = sourceWeights;
result.inputRouteSynopsisBytesOverride = synopsisBytesOverride;
result.inputRouteWeightMode = weightMode;
result.records = records;
result.candidateCount = numel(records);
result.jointCorePositiveCount = nnz([records.jointCorePositive]);
result.incrementalCorePositiveCount = nnz([records.incrementalCorePositive]);
result.etaProjectionEnabled = etaProjectionEnabled;
result.dominantEdgeReplacementEnabled = ...
    dominantEdgeReplacementEnabled;
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.truthUsedForH3Targets = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
if dominantEdgeReplacementEnabled
    stem = 'ETA_SAFE_DOMINANT_EDGE_REPLACEMENT_H3_V225';
elseif etaProjectionEnabled
    stem = 'ETA_SAFE_SEMANTIC_INPUT_ROUTING_H3_V223';
else
    stem = 'SINGLE_PASS_SEMANTIC_INPUT_ROUTING_H3_V221';
end
matPath = fullfile(outputRoot, [stem, '.mat']);
reportPath = fullfile(outputRoot, [stem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
if dominantEdgeReplacementEnabled
    fprintf('V225 eta-safe dominant-edge replacement H=3: %s\n', ...
        reportPath);
elseif etaProjectionEnabled
    fprintf('V223 eta-safe semantic input routing H=3: %s\n', reportPath);
else
    fprintf('V221 single-pass semantic input routing H=3: %s\n', reportPath);
end
end

function gains = buildGainVector( ...
        reference, candidate, groupIds, beneficiaryFormationId)
receiverIds = find(groupIds == beneficiaryFormationId);
formationIds = unique(groupIds, 'stable');
beneficiaryRow = find(formationIds == beneficiaryFormationId, 1);
sensorEospaGain = relativeGainVector( ...
    reference.sensorMeanEospa, candidate.sensorMeanEospa);
sensorRmseGain = relativeGainVector( ...
    reference.sensorMeanRmse, candidate.sensorMeanRmse);
formationEospaGain = relativeGainVector( ...
    reference.formationMeanEospa, candidate.formationMeanEospa);
formationRmseGain = relativeGainVector( ...
    reference.formationMeanRmse, candidate.formationMeanRmse);
gains = [ ...
    relativeGain(reference.meanEospa, candidate.meanEospa), ...
    relativeGain(reference.meanRmse, candidate.meanRmse), ...
    relativeGain(reference.consensusOspa, candidate.consensusOspa), ...
    relativeGain(reference.terminalConsensusOspa, ...
        candidate.terminalConsensusOspa), ...
    formationEospaGain(beneficiaryRow), ...
    formationRmseGain(beneficiaryRow), ...
    min(sensorEospaGain(receiverIds)), ...
    min(sensorRmseGain(receiverIds)), ...
    relativeGain(reference.worstSensorEospa, candidate.worstSensorEospa), ...
    relativeGain(reference.worstSensorRmse, candidate.worstSensorRmse), ...
    min(formationEospaGain), min(formationRmseGain)];
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('SinglePassSemanticInputRoutingV221:WriteReport', ...
        'Could not write the V221 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
if result.dominantEdgeReplacementEnabled
    fprintf(fid, '# V225 eta-safe dominant-edge replacement H=3\n\n');
elseif result.etaProjectionEnabled
    fprintf(fid, '# V223 eta-safe semantic input routing H=3\n\n');
else
    fprintf(fid, '# V221 single-pass semantic input routing H=3\n\n');
end
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Donor formation: `F%d`\n', result.donorFormationId);
fprintf(fid, '- Evaluated / joint-positive / donor-increment-positive: `%d / %d / %d`\n\n', ...
    result.candidateCount, result.jointCorePositiveCount, ...
    result.incrementalCorePositiveCount);
if result.dominantEdgeReplacementEnabled
    fprintf(fid, ['| Row | Transfer min / median / max | ', ...
        'Donor -> beneficiary | Source | Label | ', ...
        'Joint E / R / C / terminal | ', ...
        'Increment over donor E / R / C / terminal | ', ...
        'Beneficiary increment E / R | Byte saving | ', ...
        'Joint+ / Increment+ |\n']);
else
    fprintf(fid, ['| Row | Weight | Donor -> beneficiary | Source | ', ...
        'Label | Joint E / R / C / terminal | ', ...
        'Increment over donor E / R / C / terminal | ', ...
        'Beneficiary increment E / R | Byte saving | ', ...
        'Joint+ / Increment+ |\n']);
end
fprintf(fid, '|--:|:--|:--|--:|:--|:--|:--|:--|--:|:--:|\n');
for record = result.records
    if result.dominantEdgeReplacementEnabled
        weightText = formatTransferRange( ...
            record.transferredTopologyWeightByReceiver);
    else
        weightText = sprintf('%.3f', record.sourceWeight);
    end
    fprintf(fid, ...
        ['| %d | %s | F%d -> F%d | %d | `[%d,%d]` | ', ...
         '`%+.3f / %+.3f / %+.3f / %+.3f%%` | ', ...
         '`%+.3f / %+.3f / %+.3f / %+.3f%%` | ', ...
         '`%+.3f / %+.3f%%` | %+.3f%% | %d / %d |\n'], ...
        record.recordIndex, weightText, ...
        record.donorFormationId, record.beneficiaryFormationId, ...
        record.sourceId, record.label(1), record.label(2), ...
        record.meanEospaGainPercent, record.meanRmseGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.incrementalEospaGainPercent, ...
        record.incrementalRmseGainPercent, ...
        record.incrementalConsensusGainPercent, ...
        record.incrementalTerminalConsensusGainPercent, ...
        record.incrementalBeneficiaryEospaGainPercent, ...
        record.incrementalBeneficiaryRmseGainPercent, ...
        record.attemptedByteSavingPercent, ...
        record.jointCorePositive, record.incrementalCorePositive);
end
if result.etaProjectionEnabled
    fprintf(fid, '\n## Eta projection decisions\n\n');
    fprintf(fid, '| Row | Weight | Evaluated receivers | Allowed | Rejected | Applied action |\n');
    fprintf(fid, '|--:|--:|:--|:--|:--|--:|\n');
    for record = result.records
        fprintf(fid, '| %d | %.3f | `%s` | `%s` | `%s` | %d |\n', ...
            record.recordIndex, record.sourceWeight, ...
            formatIds(record.etaProjectionEvaluatedReceiverIds), ...
            formatIds(record.etaProjectionAllowedReceiverIds), ...
            formatIds(record.etaProjectionRejectedReceiverIds), ...
            record.etaProjectionAppliedActionCount);
    end
end
if result.dominantEdgeReplacementEnabled
    fprintf(fid, '\n## Replaced effective label edges\n\n');
    fprintf(fid, '| Row | Replaced source IDs by receiver | Transferred topology weights |\n');
    fprintf(fid, '|--:|:--|:--|\n');
    for record = result.records
        fprintf(fid, '| %d | `%s` | `%s` |\n', ...
            record.recordIndex, ...
            formatSourceIdVector( ...
                record.replacedSourceIdsByReceiver), ...
            formatFloatVector( ...
                record.transferredTopologyWeightByReceiver));
    end
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function path = resolveSourcePath(sourceScreenPath, referencedPath)
if referencedPath(1) == filesep
    path = referencedPath;
else
    marker = [filesep, 'RUN', filesep, 'GA', filesep];
    positions = strfind(sourceScreenPath, marker);
    root = sourceScreenPath(1:(positions(end) - 1));
    path = fullfile(root, referencedPath);
end
if exist(path, 'file') ~= 2
    error('SinglePassSemanticInputRoutingV221:MissingSourceCache', ...
        'The source continuation cache is unavailable: %s.', path);
end
end

function [sourceIds, transferredWeights] = ...
        summarizeDominantEdgeTransfers(pageDetails, sensorCount)
sourceIds = zeros(1, 0);
transferredWeights = nan(1, 0);
if ~isstruct(pageDetails) || ...
        ~isfield(pageDetails, 'etaProjectionEvaluatedReceiverIds') || ...
        ~isfield(pageDetails, 'etaProjectionByReceiver')
    return;
end
receiverIds = reshape( ...
    pageDetails.etaProjectionEvaluatedReceiverIds, 1, []);
if any(receiverIds < 1) || any(receiverIds > sensorCount)
    error('SinglePassSemanticInputRoutingV221:TransferDiagnostics', ...
        'The receiver-specific route diagnostics are malformed.');
end
sourceIds = zeros(1, numel(receiverIds));
transferredWeights = nan(1, numel(receiverIds));
for receiverPosition = 1:numel(receiverIds)
    receiverIdx = receiverIds(receiverPosition);
    detail = pageDetails.etaProjectionByReceiver{receiverIdx};
    if ~isstruct(detail) || ...
            ~isfield(detail, 'routingOverride') || ...
            isempty(detail.routingOverride)
        continue;
    end
    override = detail.routingOverride;
    if ~isscalar(override) || ...
            ~isfield(override, 'mode') || ...
            ~strcmp(lower(strrep(override.mode, '_', '-')), ...
                'dominant-nonself-transfer') || ...
            ~isfield(override, 'replacedSourceId') || ...
            ~isfield(override, 'transferredTopologyWeight')
        continue;
    end
    sourceIds(receiverPosition) = override.replacedSourceId;
    transferredWeights(receiverPosition) = ...
        override.transferredTopologyWeight;
end
end

function value = emptyRecord()
value = struct( ...
    'recordIndex', 0, 'sourceWeight', 0, ...
    'inputRouteWeightMode', '', ...
    'donorFormationId', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), 'screenPath', '', ...
    'inputRouteSynopsisBytes', 0, ...
    'jointGainVectorPercent', zeros(1, 12), ...
    'incrementalGainVectorPercent', zeros(1, 12), ...
    'meanEospaGainPercent', 0, 'meanRmseGainPercent', 0, ...
    'consensusGainPercent', 0, 'terminalConsensusGainPercent', 0, ...
    'incrementalEospaGainPercent', 0, ...
    'incrementalRmseGainPercent', 0, ...
    'incrementalConsensusGainPercent', 0, ...
    'incrementalTerminalConsensusGainPercent', 0, ...
    'incrementalBeneficiaryEospaGainPercent', 0, ...
    'incrementalBeneficiaryRmseGainPercent', 0, ...
    'attemptedByteSavingPercent', 0, ...
    'jointCorePositive', false, 'incrementalCorePositive', false, ...
    'byteConservationPassed', false, ...
    'etaProjectionEnabled', false, ...
    'etaProjectionAppliedActionCount', 0, ...
    'etaProjectionEvaluatedReceiverIds', zeros(1, 0), ...
    'etaProjectionAllowedReceiverIds', zeros(1, 0), ...
    'etaProjectionRejectedReceiverIds', zeros(1, 0), ...
    'replacedSourceIdsByReceiver', zeros(1, 0), ...
    'transferredTopologyWeightByReceiver', nan(1, 0));
end

function textValue = formatIds(ids)
ids = reshape(ids, 1, []);
if isempty(ids)
    textValue = '-';
else
    textValue = strtrim(sprintf('%d ', ids));
end
end

function textValue = formatTransferRange(values)
values = reshape(values, 1, []);
values = values(isfinite(values) & values > 0);
if isempty(values)
    textValue = '-';
else
    textValue = sprintf('`%.3f / %.3f / %.3f`', ...
        min(values), median(values), max(values));
end
end

function textValue = formatFloatVector(values)
values = reshape(values, 1, []);
parts = cell(1, numel(values));
for valueIdx = 1:numel(values)
    if isfinite(values(valueIdx)) && values(valueIdx) > 0
        parts{valueIdx} = sprintf('%.3f', values(valueIdx));
    else
        parts{valueIdx} = '-';
    end
end
if isempty(parts)
    textValue = '-';
else
    textValue = strjoin(parts, ' ');
end
end

function textValue = formatSourceIdVector(values)
values = reshape(values, 1, []);
parts = cell(1, numel(values));
for valueIdx = 1:numel(values)
    if isfinite(values(valueIdx)) && values(valueIdx) >= 1 && ...
            values(valueIdx) == round(values(valueIdx))
        parts{valueIdx} = sprintf('%d', values(valueIdx));
    else
        parts{valueIdx} = '-';
    end
end
if isempty(parts)
    textValue = '-';
else
    textValue = strjoin(parts, ' ');
end
end

function valid = validBoolean(value)
valid = isscalar(value) && ...
    (islogical(value) || ...
    (isnumeric(value) && isfinite(value) && (value == 0 || value == 1)));
end

function values = relativeGainVector(reference, candidate)
values = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
