function [reportPath, screen] = ...
    runFormationIsolateReconnectOpenedScreen(options)
% RUNFORMATIONISOLATERECONNECTOPENEDSCREEN Frozen v30 H=3 screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationIsolateReconnectProbeProtocol();
currentTime = getField(options, ...
    'currentTime', protocol.primarySnapshotTime);
if ~isscalar(currentTime) || ...
        ~ismember(currentTime, protocol.openedSnapshotTimes)
    error('FormationRecovery:InvalidProtocol', ...
        'v30 may use only preregistered opened states.');
end
preflight = assertPreflightAuthorized(protocol);
if currentTime ~= protocol.primarySnapshotTime
    assertSecondaryStateAuthorized(protocol);
end
writeReportEnabled = logical(getField(options, ...
    'writeReport', true));
outputDirectory = getField(options, ...
    'outputDirectory', fullfile(protocol.outputRoot, ...
        sprintf('t%d', currentTime), 'screen'));

executorOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', ...
        protocol.isolationDurationSteps, ...
    'cacheRoot', protocol.cacheRoot, ...
    'interventionBankType', ...
        'formation-isolate-reconnect', ...
    'actionIndices', [ ...
        preflight.initialBank.referenceActionIndex, ...
        preflight.selectedInitialActionIndex], ...
    'writeReport', false, ...
    'allowDirtySource', logical(getField( ...
        options, 'allowDirtySource', false)));
[~, screen] = runFormationModeOpenedReturnScreen( ...
    protocol.presetName, protocol.seed, currentTime, ...
    executorOptions);
assertCacheProvenance(screen.cachePath, protocol);
assertScreenContract(screen, protocol);

recordCount = numel(screen.records);
referenceIdx = screen.referenceSubsetIndex;
strictStrongMask = false(1, recordCount);
for recordIdx = 1:recordCount
    record = screen.records(recordIdx);
    outcome = screen.outcomes(recordIdx);
    strictStrongMask(recordIdx) = ...
        recordIdx ~= referenceIdx && ...
        record.posteriorProxyAllowed && ...
        outcome.firstActionExact && ...
        outcome.firstFusionWeightsExact && ...
        outcome.laterActionsDynamicallyRecomputed && ...
        all(outcome.posteriorContentUsedByTime) && ...
        all(outcome.currentLinkReliabilityUsedByTime) && ...
        hasCausalRetentionDebtTrace( ...
            outcome, protocol.expectedFormationCount) && ...
        record.meanGainPercent >= ...
            protocol.meanTrackingGainThresholdPercent - 1e-12 && ...
        record.minimumFormationGainPercent >= ...
            protocol.minimumFormationGainThresholdPercent - 1e-12 && ...
        record.worstGainPercent >= ...
            protocol.worstSensorGainThresholdPercent - 1e-12 && ...
        record.consensusGainPercent >= ...
            protocol.windowConsensusGainThresholdPercent - 1e-12 && ...
        record.terminalConsensusGainPercent >= ...
            protocol.terminalConsensusGainThresholdPercent - 1e-12 && ...
        record.attemptedByteSavingPercent >= ...
            protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
        record.selectedB3Passed;
end

screen.contractVersion = ...
    'formation-causal-isolate-reconnect-v30-screen-v1';
screen.protocol = protocol;
screen.strictStrongMask = strictStrongMask;
screen.strictStrongCandidateCount = nnz(strictStrongMask);
screen.strongCandidateFound = any(strictStrongMask);
screen.bestStrictStrongMeanGainPercent = maximumOrNaN( ...
    [screen.records(strictStrongMask).meanGainPercent]);
screen.bestStrictStrongRecordIndex = bestRecordIndex( ...
    screen.records, strictStrongMask);
screen.primaryOpenedState = ...
    currentTime == protocol.primarySnapshotTime;
screen.posteriorSafetyProjectedInitialActionCount = ...
    screen.bank.safeNonreferenceActionCount;
screen.executedOnlyPosteriorSafeInitialActions = all( ...
    screen.bank.actionPosteriorSafetyMask(screen.actionIndices));
screen.causalRetentionDebtPolicyAttested = ...
    allCausalRetentionDebtAttested( ...
        screen, referenceIdx, protocol.expectedFormationCount);
screen.terminalConsensusGateEnabled = true;
screen.selectedRollingB3Required = true;
screen.outcomeRankingUsesTruth = true;
screen.additionalOpenedStateScreenAuthorized = ...
    screen.primaryOpenedState && screen.strongCandidateFound;
screen.teacherCollectionAllowed = false;
screen.gnnTrainingAuthorized = false;
screen.x36OutcomeOpeningAuthorized = false;
screen.x48OutcomeOpeningAuthorized = false;
screen.validationClaimAllowed = false;
screen.evidenceBoundary = protocol.evidenceBoundary;

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    stem = sprintf( ...
        'FORMATION_ISOLATE_RECONNECT_H3_%s_SEED%d_T%d', ...
        upper(strrep(protocol.presetName, '-', '_')), ...
        protocol.seed, currentTime);
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    screen.reportPath = reportPath;
    screen.matPath = matPath;
    save('-mat7-binary', matPath, 'screen');
    writeReport(reportPath, screen);
    fprintf('Causal isolate-reconnect screen: %s\n', ...
        reportPath);
end
end

function preflight = assertPreflightAuthorized(protocol)
path = fullfile(protocol.outputRoot, 'preflight', ...
    'FORMATION_CAUSAL_ISOLATE_RECONNECT_V30_PREFLIGHT.mat');
if exist(path, 'file') ~= 2
    error('FormationRecovery:PreflightRequired', ...
        'The frozen v30 preflight artifact is unavailable.');
end
loaded = load(path, 'preflight');
if ~isfield(loaded, 'preflight')
    error('FormationRecovery:PreflightRequired', ...
        'The frozen v30 preflight structure is unavailable.');
end
preflight = loaded.preflight;
if ~strcmp(preflight.contractVersion, ...
        'formation-causal-isolate-reconnect-v30-preflight-v1') || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        ~preflight.primaryTrackingScreenAuthorized || ...
        preflight.trackingContinuationExecuted || ...
        preflight.newStateOpened || ...
        preflight.gnnTrainingAuthorized || ...
        preflight.x36Opened || preflight.x48Opened || ...
        preflight.validationClaimAllowed
    error('FormationRecovery:PreflightRequired', ...
        'The frozen v30 preflight did not authorize the primary screen.');
end
end

function assertSecondaryStateAuthorized(protocol)
stem = sprintf( ...
    'FORMATION_ISOLATE_RECONNECT_H3_%s_SEED%d_T%d.mat', ...
    upper(strrep(protocol.presetName, '-', '_')), ...
    protocol.seed, protocol.primarySnapshotTime);
path = fullfile(protocol.outputRoot, ...
    sprintf('t%d', protocol.primarySnapshotTime), 'screen', stem);
if exist(path, 'file') ~= 2
    error('FormationRecovery:PrimaryGateRequired', ...
        'v30 primary screen evidence is unavailable.');
end
loaded = load(path, 'screen');
if ~isfield(loaded, 'screen') || ...
        ~strcmp(loaded.screen.contractVersion, ...
            'formation-causal-isolate-reconnect-v30-screen-v1') || ...
        ~loaded.screen.primaryOpenedState || ...
        ~loaded.screen.strongCandidateFound || ...
        loaded.screen.validationClaimAllowed || ...
        loaded.screen.gnnTrainingAuthorized
    error('FormationRecovery:PrimaryGateRequired', ...
        'v30 primary screen did not authorize another opened state.');
end
end

function assertCacheProvenance(cachePath, protocol)
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('FormationRecovery:CacheProvenance', ...
        'Opened cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
if ~isfield(bundle, 'protocolId') || ...
        ~strcmp(bundle.protocolId, protocol.cacheProtocolId) || ...
        ~isfield(bundle, 'generationGitCommit') || ...
        ~strcmp(bundle.generationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~isfield(bundle, 'openedDevelopmentEvidenceOnly') || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        ~isfield(bundle, 'validationClaimAllowed') || ...
        bundle.validationClaimAllowed
    error('FormationRecovery:CacheProvenance', ...
        'Opened cache provenance differs from frozen v30 protocol.');
end
end

function assertScreenContract(screen, protocol)
bank = screen.bank;
expectedActionCount = 2^protocol.expectedFormationCount;
expectedExecutedActions = [ ...
    bank.referenceActionIndex, ...
    findInitialActionIndex( ...
        bank, protocol.expectedPrimarySelectedFormationIds)];
if screen.horizonSteps ~= protocol.horizonSteps || ...
        screen.interventionDurationSteps ~= ...
            protocol.isolationDurationSteps || ...
        screen.currentTime ~= screen.returnTimes(1) || ...
        bank.nodeCount ~= protocol.expectedNodeCount || ...
        bank.formationCount ~= protocol.expectedFormationCount || ...
        bank.actionCount ~= expectedActionCount || ...
        ~bank.posteriorSafetyScored || ...
        bank.safeNonreferenceActionCount < 1 || ...
        ~isequal(screen.actionIndices, expectedExecutedActions) || ...
        any(~bank.actionPosteriorSafetyMask(screen.actionIndices)) || ...
        ~bank.allPhysical || ~bank.allRowStochastic || ...
        ~bank.allMessageCountsNoGreaterThanReference || ...
        ~bank.allRollingB3SensorStrongConnected || ...
        ~bank.allRollingB3FormationStrongConnected || ...
        bank.truthUsed || bank.futureOutcomeUsed || ...
        ~screen.runtimeRecoveryPolicyEnabled || ...
        ~strcmp(screen.runtimePolicyContractVersion, ...
            'formation-isolate-reconnect-runtime-policy-v1') || ...
        any([screen.outcomes.truthUseCount] ~= 0) || ...
        any([screen.outcomes.repairCount] ~= 0) || ...
        any([screen.outcomes.payloadEmergencyCount] ~= 0) || ...
        any([screen.outcomes.infeasibleCount] ~= 0) || ...
        ~all([screen.outcomes.firstActionExact]) || ...
        ~all([screen.outcomes.firstFusionWeightsExact])
    error('FormationRecovery:ScreenContract', ...
        'The v30 screen violated a frozen runtime invariant.');
end
end

function actionIdx = findInitialActionIndex(bank, formationIds)
matches = false(1, bank.actionCount);
formationIds = reshape(formationIds, 1, []);
for candidateIdx = 1:bank.actionCount
    matches(candidateIdx) = isequal(reshape( ...
        bank.actionSuspendedFormationIds{candidateIdx}, 1, []), ...
        formationIds);
end
actionIdx = find(matches);
if numel(actionIdx) ~= 1
    error('FormationRecovery:ScreenContract', ...
        'The frozen primary formation subset is not unique.');
end
end

function value = allCausalRetentionDebtAttested( ...
        screen, referenceIdx, formationCount)
value = true;
for recordIdx = 1:numel(screen.outcomes)
    if recordIdx == referenceIdx
        continue;
    end
    outcome = screen.outcomes(recordIdx);
    value = value && ...
        outcome.laterActionsDynamicallyRecomputed && ...
        all(outcome.posteriorContentUsedByTime) && ...
        all(outcome.currentLinkReliabilityUsedByTime) && ...
        hasCausalRetentionDebtTrace(outcome, formationCount) && ...
        all(isfinite(outcome.recoveryReferenceRiskByTime)) && ...
        all(isfinite(outcome.recoverySelectedRiskByTime)) && ...
        all(outcome.recoveryEvaluatedActionCountByTime >= 1) && ...
        all(outcome.recoverySafeActionCountByTime >= 1);
end
end

function value = hasCausalRetentionDebtTrace( ...
        outcome, formationCount)
timeCount = numel(outcome.posteriorContentUsedByTime);
value = ...
    numel(outcome.retentionDebtFractionByTime) == timeCount && ...
    numel(outcome.retentionDebtThresholdByTime) == timeCount && ...
    numel(outcome.retentionDebtSingleAvailableMaskByTime) == ...
        timeCount && ...
    numel(outcome.retentionDebtSingleSafetyMaskByTime) == timeCount;
if ~value
    return;
end
for timeIdx = 1:timeCount
    debt = outcome.retentionDebtFractionByTime{timeIdx};
    threshold = outcome.retentionDebtThresholdByTime{timeIdx};
    available = logical(outcome. ...
        retentionDebtSingleAvailableMaskByTime{timeIdx});
    safe = logical(outcome. ...
        retentionDebtSingleSafetyMaskByTime{timeIdx});
    value = value && isnumeric(debt) && ...
        numel(debt) == formationCount && ...
        isnumeric(threshold) && ...
        numel(threshold) == formationCount && ...
        numel(available) == formationCount && ...
        numel(safe) == formationCount && ...
        all(isfinite(debt(available))) && ...
        all(isnan(debt(~available))) && ...
        all(isfinite(threshold)) && ...
        all(~safe | available);
end
end

function writeReport(path, screen)
fid = fopen(path, 'w');
if fid < 0
    error('FormationRecovery:WriteFailed', ...
        'Could not open v30 screen report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V30 causal retention-debt H=3 screen\n\n');
fprintf(fid, '- Contract: `%s`\n', screen.contractVersion);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    screen.presetName, screen.seed, screen.currentTime);
fprintf(fid, '- Return times: `%s`\n', ...
    mat2str(screen.returnTimes));
fprintf(fid, '- Source-only control updates: `3` steps\n');
fprintf(fid, '- Generation commit: `%s`\n', ...
    screen.generationGitCommit);
fprintf(fid, '- Cache SHA-256: `%s`\n', screen.cacheSha256);
fprintf(fid, '- Structural / executed safe actions: `%d / %d`\n', ...
    screen.bank.actionCount, numel(screen.records));
fprintf(fid, '- Causal retention-debt trace attested: `%d`\n', ...
    screen.causalRetentionDebtPolicyAttested);
fprintf(fid, '- Strong candidates: `%d / %d`\n', ...
    screen.strictStrongCandidateCount, numel(screen.records) - 1);
fprintf(fid, '- Best strict mean gain: `%+.3f%%`\n\n', ...
    screen.bestStrictStrongMeanGainPercent);

fprintf(fid, [ ...
    '| Initial action | Suspended formations | Control t+1 | ', ...
    'Control t+2 | Mean gain | Worst gain | Min formation | ', ...
    'Window consensus | Final consensus | Byte saving | Strong |\n']);
fprintf(fid, [ ...
    '|:--|:--|:--|:--|--:|--:|--:|--:|--:|--:|:--:|\n']);
for recordIdx = 1:numel(screen.records)
    record = screen.records(recordIdx);
    outcome = screen.outcomes(recordIdx);
    modes = outcome.policyBackboneModeByTime;
    fprintf(fid, [ ...
        '| `%s` | `%s` | `%s` | `%s` | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        record.actionName, mat2str(record.formationIndices), ...
        modes{2}, modes{3}, record.meanGainPercent, ...
        record.worstGainPercent, ...
        record.minimumFormationGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent, ...
        screen.strictStrongMask(recordIdx));
end

fprintf(fid, '\n## Frozen strong gate\n\n');
fprintf(fid, [ ...
    'A strong nonreference initial action requires prior v29 posterior ', ...
    'safety, exact first-step graph and weights, causal current-posterior ', ...
    'recovery, mean tracking gain >= %.1f%%, minimum formation gain >= ', ...
    '%.1f%%, worst-sensor gain >= %.1f%%, window and terminal consensus ', ...
    'gain >= %.1f%%, attempted-byte saving >= %.1f%%, and selected ', ...
    'rolling-B3 passage.\n\n'], ...
    screen.protocol.meanTrackingGainThresholdPercent, ...
    screen.protocol.minimumFormationGainThresholdPercent, ...
    screen.protocol.worstSensorGainThresholdPercent, ...
    screen.protocol.windowConsensusGainThresholdPercent, ...
    screen.protocol.minimumAttemptedByteSavingPercent);

fprintf(fid, '## Gate decision\n\n');
if screen.strongCandidateFound
    fprintf(fid, [ ...
        'The primary screen contains a strong retention-debt action. A ', ...
        'secondary already-opened M24 state may be screened under the ', ...
        'same frozen protocol; GNN training and X36/X48 remain sealed.\n\n']);
else
    fprintf(fid, [ ...
        'The primary screen contains no strong retention-debt action. ', ...
        'The v30 protocol ', ...
        'stops before another M24 state, GNN training, or X36/X48.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    screen.evidenceBoundary);
end

function idx = bestRecordIndex(records, mask)
indices = find(mask);
if isempty(indices)
    idx = NaN;
    return;
end
[~, localIdx] = max([records(indices).meanGainPercent]);
idx = indices(localIdx);
end

function value = maximumOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
