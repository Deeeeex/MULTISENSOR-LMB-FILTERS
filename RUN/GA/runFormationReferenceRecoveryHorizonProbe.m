function [reportPath, probe] = ...
    runFormationReferenceRecoveryHorizonProbe(options)
% RUNFORMATIONREFERENCERECOVERYHORIZONPROBE Frozen H=4/H=5 recovery gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationReferenceRecoveryHorizonProbeProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official reference-recovery probe requires clean source.');
end
outputRoot = getField(options, 'outputDirectory', protocol.outputRoot);
probePath = fullfile(outputRoot, ...
    'formation_reference_recovery_horizon_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_REFERENCE_RECOVERY_HORIZON_V1.md');
probeExists = exist(probePath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(probeExists, reportExists)
    error('Reference-recovery probe artifacts are partial.');
elseif probeExists
    loaded = load(probePath, 'probe');
    if ~isfield(loaded, 'probe') || ...
            ~strcmp(loaded.probe.protocolId, protocol.id) || ...
            ~strcmp(loaded.probe.generationGitCommit, gitState.commit)
        error('Reference-recovery probe provenance mismatch.');
    end
    probe = loaded.probe;
    fprintf('Reused reference-recovery probe: %s\n', probePath);
    return;
end

candidateCount = numel(protocol.candidateModeSequences);
if candidateCount ~= protocol.expectedCandidateCount
    error('Reference-recovery candidate count changed.');
end
candidateActionPrefixes = zeros( ...
    candidateCount, protocol.activePrefixSteps);
for candidateIdx = 1:candidateCount
    modes = protocol.candidateModeSequences{candidateIdx};
    if ~isequal(size(modes), [ ...
            protocol.activePrefixSteps, protocol.formationCount])
        error('Reference-recovery mode-sequence shape changed.');
    end
    candidateActionPrefixes(candidateIdx, :) = ...
        formationModeVectorToActionIndex( ...
            modes, protocol.modeCount)';
end

horizonCount = numel(protocol.horizonSteps);
horizonResults = repmat(emptyHorizonResult(), 1, horizonCount);
anyStrong = false;
for horizonIdx = 1:horizonCount
    horizonSteps = protocol.horizonSteps(horizonIdx);
    sequences = repmat(protocol.referenceActionIndex, ...
        protocol.expectedSequenceCountPerHorizon, horizonSteps);
    sequences(2:end, 1:protocol.activePrefixSteps) = ...
        candidateActionPrefixes;
    if size(unique(sequences, 'rows'), 1) ~= size(sequences, 1)
        error('Reference-recovery sequence enumeration changed.');
    end

    screenDirectory = fullfile(outputRoot, ...
        sprintf('h%d', horizonSteps), 'screen');
    screenOptions = struct( ...
        'horizonSteps', horizonSteps, ...
        'cacheRoot', protocol.cacheRoot, ...
        'outputDirectory', screenDirectory, ...
        'interventionBankType', protocol.interventionBankType, ...
        'actionSequenceIndices', sequences, ...
        'writeReport', true);
    [screenReportPath, screen] = ...
        runFormationModeOpenedReturnScreen( ...
            protocol.presetName, protocol.seed, ...
            protocol.currentTime, screenOptions);
    expectedScreenContract = sprintf( ...
        ['formation-exhaustive-mode-vector-h%d-', ...
         'opened-return-screen-v1'], horizonSteps);
    if ~strcmp(screen.contractVersion, expectedScreenContract) || ...
            screen.horizonSteps ~= horizonSteps || ...
            screen.bank.actionCount ~= protocol.expectedActionCount || ...
            screen.referenceSubsetIndex ~= 1 || ...
            ~isequal(screen.actionSequenceIndices, sequences)
        error('Reference-recovery opened-screen contract changed.');
    end
    for candidateIdx = 1:candidateCount
        if ~isequal(screen.bank.actionModes( ...
                candidateActionPrefixes(candidateIdx, :), :), ...
                protocol.candidateModeSequences{candidateIdx})
            error('Reference-recovery action-bank mapping changed.');
        end
    end
    assertScreenRuntimeGate(screen);

    targets = targetMatrix(screen);
    prefixTargets = prefixTargetMatrix( ...
        screen, protocol.activePrefixSteps);
    prefixError = abs(prefixTargets(2:end, :) - ...
        protocol.expectedCandidateH3Targets);
    if any(abs(targets(1, :)) > 1e-12) || ...
            any(abs(prefixTargets(1, :)) > 1e-12) || ...
            max(prefixError(:)) > ...
                protocol.reproductionTolerancePercent
        error('Reference-recovery H=3 prefix reproduction failed.');
    end

    candidateTargets = targets(2:end, :);
    strict = all(candidateTargets >= -1e-12, 2);
    strong = strict & candidateTargets(:, 1) >= ...
        protocol.strongGainPercent - 1e-12;
    strongThresholds = [ ...
        protocol.strongGainPercent, zeros(1, 6)];
    normalizedDeficits = max( ...
        strongThresholds - candidateTargets, 0) ./ ...
        protocol.constraintScalesPercent;
    maximumDeficit = max(normalizedDeficits, [], 2);
    totalDeficit = sum(normalizedDeficits, 2);
    ranking = [ ...
        maximumDeficit, totalDeficit, ...
        -candidateTargets(:, 1), (1:candidateCount)'];
    [~, rankOrder] = sortrows(ranking, [1, 2, 3, 4]);

    result = emptyHorizonResult();
    result.horizonSteps = horizonSteps;
    result.sequences = sequences;
    result.targets = targets;
    result.prefixTargets = prefixTargets;
    result.maximumPrefixReproductionErrorPercent = ...
        max(prefixError(:));
    result.candidateTargets = candidateTargets;
    result.candidateStrictFeasible = strict;
    result.candidateStrongSafe = strong;
    result.candidateStrictFeasibleCount = nnz(strict);
    result.candidateStrongSafeCount = nnz(strong);
    result.candidateRankOrder = rankOrder;
    result.closestCandidateIndex = rankOrder(1);
    result.closestTargets = candidateTargets(rankOrder(1), :);
    [result.bestMeanGainPercent, result.bestMeanCandidateIndex] = ...
        max(candidateTargets(:, 1));
    result.screenContractVersion = screen.contractVersion;
    result.screenReportPath = screenReportPath;
    result.screenMatPath = screen.matPath;
    result.screenGenerationGitCommit = ...
        screen.generationGitCommit;
    horizonResults(horizonIdx) = result;
    anyStrong = anyStrong || any(strong);
end

probe = struct();
probe.contractVersion = ...
    'formation-reference-recovery-horizon-probe-result-v1';
probe.protocolId = protocol.id;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
probe.cacheProtocolId = protocol.cacheProtocolId;
probe.cacheGenerationGitCommit = ...
    protocol.cacheGenerationGitCommit;
probe.presetName = protocol.presetName;
probe.seed = protocol.seed;
probe.currentTime = protocol.currentTime;
probe.activePrefixSteps = protocol.activePrefixSteps;
probe.horizonSteps = protocol.horizonSteps;
probe.candidateRoles = protocol.candidateRoles;
probe.candidateModeSequences = protocol.candidateModeSequences;
probe.candidateActionPrefixes = candidateActionPrefixes;
probe.expectedCandidateH3Targets = ...
    protocol.expectedCandidateH3Targets;
probe.targetNames = protocol.targetNames;
probe.horizonResults = horizonResults;
probe.strongSafeRecoveryFound = anyStrong;
probe.teacherCollectionAuthorized = anyStrong;
probe.teacherModelTrainingAuthorized = false;
probe.currentTemporalRecoveryFamilyAuthorized = anyStrong;
probe.finalModelTrainingAuthorized = false;
probe.validationClaimAllowed = false;
probe.actionSelectionUsesTruth = protocol.actionSelectionUsesTruth;
probe.actionSelectionUsesFutureMeasurements = ...
    protocol.actionSelectionUsesFutureMeasurements;
probe.runtimePolicyUsesTruth = protocol.runtimePolicyUsesTruth;
probe.openedTrainingMechanismProbeOnly = true;
probe.evidenceBoundary = protocol.evidenceBoundary;
probe.probePath = probePath;
probe.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', probePath, 'probe');
writeReport(reportPath, probe);
fprintf('Reference-recovery horizon probe: %s\n', probePath);
fprintf(['Strong safe recovery=%d; teacher collection=%d; ', ...
    'model training=%d\n'], ...
    probe.strongSafeRecoveryFound, ...
    probe.teacherCollectionAuthorized, ...
    probe.teacherModelTrainingAuthorized);
end

function assertScreenRuntimeGate(screen)
if screen.featuresUseTruth || ...
        screen.featuresUseFutureMeasurements || ...
        screen.featuresUseFutureOutcome || ...
        screen.runtimePolicyUsesTruth || ...
        ~screen.targetsUseTruth || ...
        ~screen.targetsUseFutureMeasurements || ...
        screen.validationClaimAllowed || ...
        ~screen.openedDevelopmentEvidenceOnly
    error('Reference-recovery evidence boundary changed.');
end
for outcome = screen.outcomes
    if ~outcome.firstActionExact || ...
            ~outcome.interventionActionsExact || ...
            outcome.truthUseCount ~= 0 || ...
            outcome.repairCount ~= 0 || ...
            outcome.payloadEmergencyCount ~= 0 || ...
            outcome.infeasibleCount ~= 0 || ...
            ~all(outcome.selectedSensorB3Pass) || ...
            ~all(outcome.selectedFormationB3Pass)
        error('Reference-recovery runtime gate failed.');
    end
end
end

function targets = targetMatrix(screen)
records = screen.records;
outcomes = screen.outcomes;
reference = outcomes(screen.referenceSubsetIndex);
delivered = zeros(numel(outcomes), 1);
for idx = 1:numel(outcomes)
    delivered(idx) = relativeGainPercent( ...
        reference.deliveredBytes, outcomes(idx).deliveredBytes);
end
targets = [ ...
    reshape([records.meanGainPercent], [], 1), ...
    reshape([records.minimumFormationGainPercent], [], 1), ...
    reshape([records.worstGainPercent], [], 1), ...
    reshape([records.consensusGainPercent], [], 1), ...
    reshape([records.attemptedByteSavingPercent], [], 1), ...
    delivered, ...
    reshape([records.terminalConsensusGainPercent], [], 1)];
if any(~isfinite(targets(:)))
    error('Reference-recovery targets must be finite.');
end
end

function targets = prefixTargetMatrix(screen, prefixSteps)
outcomes = screen.outcomes;
reference = prefixMetrics( ...
    outcomes(screen.referenceSubsetIndex), ...
    screen.sensorGroupIds, prefixSteps);
targets = zeros(numel(outcomes), 6);
for idx = 1:numel(outcomes)
    candidate = prefixMetrics( ...
        outcomes(idx), screen.sensorGroupIds, prefixSteps);
    formationGain = 100 * ...
        (reference.formationMeanEospa - ...
         candidate.formationMeanEospa) ./ ...
        max(reference.formationMeanEospa, eps);
    targets(idx, :) = [ ...
        relativeGainPercent( ...
            reference.meanEospa, candidate.meanEospa), ...
        min(formationGain), ...
        relativeGainPercent( ...
            reference.worstSensorEospa, ...
            candidate.worstSensorEospa), ...
        relativeGainPercent( ...
            reference.consensusOspa, candidate.consensusOspa), ...
        relativeGainPercent( ...
            reference.attemptedBytes, candidate.attemptedBytes), ...
        relativeGainPercent( ...
            reference.deliveredBytes, candidate.deliveredBytes)];
end
if any(~isfinite(targets(:)))
    error('Reference-recovery prefix targets must be finite.');
end
end

function metrics = prefixMetrics(outcome, groupIds, prefixSteps)
eospa = outcome.eospaBySensorTime(:, 1:prefixSteps);
sensorMeans = mean(eospa, 2);
groups = unique(reshape(groupIds, 1, []), 'stable');
formationMeans = zeros(1, numel(groups));
for formationIdx = 1:numel(groups)
    formationMeans(formationIdx) = mean( ...
        sensorMeans(groupIds == groups(formationIdx)));
end
metrics = struct( ...
    'meanEospa', mean(eospa(:)), ...
    'worstSensorEospa', max(sensorMeans), ...
    'formationMeanEospa', formationMeans, ...
    'consensusOspa', finiteMean( ...
        outcome.consensusOspaByTime(1:prefixSteps)), ...
    'attemptedBytes', sum( ...
        outcome.attemptedBytesByTime(1:prefixSteps)), ...
    'deliveredBytes', sum( ...
        outcome.deliveredBytesByTime(1:prefixSteps)));
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function result = emptyHorizonResult()
result = struct( ...
    'horizonSteps', NaN, ...
    'sequences', zeros(0), ...
    'targets', zeros(0, 7), ...
    'prefixTargets', zeros(0, 6), ...
    'maximumPrefixReproductionErrorPercent', NaN, ...
    'candidateTargets', zeros(0, 7), ...
    'candidateStrictFeasible', false(0, 1), ...
    'candidateStrongSafe', false(0, 1), ...
    'candidateStrictFeasibleCount', 0, ...
    'candidateStrongSafeCount', 0, ...
    'candidateRankOrder', zeros(0, 1), ...
    'closestCandidateIndex', NaN, ...
    'closestTargets', zeros(1, 7), ...
    'bestMeanGainPercent', NaN, ...
    'bestMeanCandidateIndex', NaN, ...
    'screenContractVersion', '', ...
    'screenReportPath', '', ...
    'screenMatPath', '', ...
    'screenGenerationGitCommit', '');
end

function writeReport(path, probe)
fid = fopen(path, 'w');
if fid < 0
    error('Cannot write reference-recovery horizon report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation reference-recovery horizon probe\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    probe.contractVersion, probe.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    probe.generationGitCommit);
fprintf(fid, '- Cache protocol / commit: `%s / %s`\n', ...
    probe.cacheProtocolId, probe.cacheGenerationGitCommit);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    probe.presetName, probe.seed, probe.currentTime);
fprintf(fid, '- Active prefix / horizons: `H=%d / %s`\n', ...
    probe.activePrefixSteps, mat2str(probe.horizonSteps));
fprintf(fid, '- Strong safe recovery found: `%d`\n', ...
    probe.strongSafeRecoveryFound);
fprintf(fid, '- Broader teacher collection authorized: `%d`\n', ...
    probe.teacherCollectionAuthorized);
fprintf(fid, '- GNN training authorized: `%d`\n\n', ...
    probe.teacherModelTrainingAuthorized);

fprintf(fid, '## Frozen active prefixes\n\n');
fprintf(fid, '| Candidate | Role | Three-step mode sequence | H=3 targets |\n');
fprintf(fid, '|--:|:--|:--|:--|\n');
for candidateIdx = 1:numel(probe.candidateRoles)
    fprintf(fid, '| %d | `%s` | `%s` | `%s` |\n', ...
        candidateIdx, probe.candidateRoles{candidateIdx}, ...
        formatModeSequence( ...
            probe.candidateModeSequences{candidateIdx}), ...
        mat2str(probe.expectedCandidateH3Targets( ...
            candidateIdx, :), 7));
end

fprintf(fid, '\n## Equal-horizon results\n\n');
fprintf(fid, [ ...
    '| H | Candidate | Mean | Min. formation | Worst sensor | ', ...
    'Window cons. | Attempted | Delivered | Final-step cons. | ', ...
    'Strict | Strong |\n']);
fprintf(fid, ...
    '|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
for horizonResult = probe.horizonResults
    for candidateIdx = 1:numel(probe.candidateRoles)
        targets = horizonResult.candidateTargets(candidateIdx, :);
        fprintf(fid, [ ...
            '| %d | %d | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
            '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d | %d |\n'], ...
            horizonResult.horizonSteps, candidateIdx, ...
            targets(1), targets(2), targets(3), targets(4), ...
            targets(5), targets(6), targets(7), ...
            horizonResult.candidateStrictFeasible(candidateIdx), ...
            horizonResult.candidateStrongSafe(candidateIdx));
    end
end

fprintf(fid, '\n## Horizon summary\n\n');
fprintf(fid, [ ...
    '| H | Strict | Strong | Prefix reproduction max error | ', ...
    'Closest candidate | Closest targets |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--|\n');
for result = probe.horizonResults
    fprintf(fid, '| %d | %d/%d | %d/%d | %.3g | %d | `%s` |\n', ...
        result.horizonSteps, ...
        result.candidateStrictFeasibleCount, ...
        numel(result.candidateStrictFeasible), ...
        result.candidateStrongSafeCount, ...
        numel(result.candidateStrongSafe), ...
        result.maximumPrefixReproductionErrorPercent, ...
        result.closestCandidateIndex, ...
        mat2str(result.closestTargets, 7));
end

fprintf(fid, '\n## Metric meaning\n\n');
fprintf(fid, [ ...
    'The first six signed targets preserve the v21-v24 ordering: mean ', ...
    'tracking, minimum formation, worst sensor, consensus averaged over ', ...
    'the equal-length horizon, attempted bytes, and delivered bytes. ', ...
    'The seventh target compares consensus at the final step only. ', ...
    'Positive values are improvements over the all-reference trajectory ', ...
    'of the same horizon. Strict feasibility requires all seven values ', ...
    'to be nonnegative; strong safety additionally requires at least ', ...
    '3%% mean tracking gain.\n']);

fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    probe.evidenceBoundary);
end

function value = formatModeSequence(sequence)
parts = cell(1, size(sequence, 1));
for stepIdx = 1:size(sequence, 1)
    parts{stepIdx} = mat2str(sequence(stepIdx, :));
end
value = strjoin(parts, ' -> ');
end

function value = getField(item, name, defaultValue)
if isfield(item, name)
    value = item.(name);
else
    value = defaultValue;
end
end
