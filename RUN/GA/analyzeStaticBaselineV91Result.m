function [reportPath, result] = analyzeStaticBaselineV91Result()
% ANALYZESTATICBASELINEV91RESULT Reinterpret V89 against static routing.

protocol = getStaticVsDynamicRoutingV91Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('StaticBaselineV91:DirtySource', ...
        'The V91 baseline result requires clean frozen source.');
end
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
v89Path = fullfile(repoRoot, 'RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v89', ...
    'multi_gateway_handover_full_episode', ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_FULL_EPISODE.mat');
if exist(v89Path, 'file') ~= 2
    error('StaticBaselineV91:MissingV89Result', ...
        'The complete V89 paired result is required.');
end
loaded = load(v89Path, 'result');
v89 = loaded.result;
if ~isfield(v89, 'records') || ...
        numel(v89.records) ~= numel(protocol.presets)
    error('StaticBaselineV91:IncompleteV89Result', ...
        'The V89 result does not contain both frozen scales.');
end

outputRoot = fullfile(repoRoot, protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
records = repmat(emptyRecord(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    presetName = protocol.presets{presetIdx};
    sourceIdx = find(strcmp({v89.records.presetName}, presetName), 1);
    if isempty(sourceIdx)
        error('StaticBaselineV91:MissingScale', ...
            'The V89 result is missing %s.', presetName);
    end
    inputs = generateDynamicTopologyScenarioInputs( ...
        presetName, protocol.allSeeds);
    certificate = certifyPhysicalTreeReferenceStaticV91(inputs);
    if ~certificate.referenceFunctionallyStatic
        error('StaticBaselineV91:ReferenceNotStatic', [ ...
            'The %s physical-tree reference is not functionally static; ', ...
            'a new frozen-route full-filter arm is required.'], presetName);
    end
    source = v89.records(sourceIdx);
    record = emptyRecord();
    record.presetName = presetName;
    record.seed = source.seed;
    record.certificate = certificate;
    record.static = source.reference;
    record.dynamicCandidate = source.candidate;
    record.dynamicOverStatic = source.improvement;
    record.dynamicMethodImprovedTracking = ...
        source.improvement.fullHorizonMeanGainPercent > 0 && ...
        source.improvement.focusWindowMeanGainPercent > 0;
    record.dynamicMethodStrongGatePassed = ...
        source.improvement.strongGatePassed;
    records(presetIdx) = record;
end

result = struct();
result.contractVersion = ...
    'static-baseline-v91-result-v1';
result.protocol = protocol;
result.generationGitCommit = gitState.commit;
result.sourceV89GenerationGitCommit = v89.generationGitCommit;
result.completedAt = datestr(now, 31);
result.records = records;
result.bothReferencesFunctionallyStatic = all(arrayfun( ...
    @(record) record.certificate.referenceFunctionallyStatic, records));
result.bothDynamicCandidatesImproveTracking = all( ...
    [records.dynamicMethodImprovedTracking]);
result.bothDynamicCandidatesStrongGatePassed = all( ...
    [records.dynamicMethodStrongGatePassed]);
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
matPath = fullfile(outputRoot, 'STATIC_BASELINE_V91_RESULT.mat');
reportPath = fullfile(outputRoot, 'STATIC_BASELINE_V91_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V91 static-baseline result: %s\n', reportPath);
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'certificate', struct(), ...
    'static', struct(), ...
    'dynamicCandidate', struct(), ...
    'dynamicOverStatic', struct(), ...
    'dynamicMethodImprovedTracking', false, ...
    'dynamicMethodStrongGatePassed', false);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('StaticBaselineV91:ReportWriteFailed', ...
        'Could not create the V91 baseline report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V91 static-routing baseline result\n\n');
fprintf(fid, ['The V89 physical-tree reference is treated as static only ', ...
    'after proving that its physical graph, selected route and fusion ', ...
    'weights each have one unique page over the full episode. Positive ', ...
    'percentages mean the V89 adaptive candidate is better.\n\n']);
fprintf(fid, ['| Scale | Physical graphs | Static routes | Static E-OSPA | ', ...
    'Dynamic E-OSPA | Full gain | Focus gain | Worst | Formation | ', ...
    'Consensus | Cardinality | Bytes | Strong |\n']);
fprintf(fid, [ ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for record = result.records
    gain = record.dynamicOverStatic;
    fprintf(fid, ['| %s | %d | %d | %.3f | %.3f | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %d |\n'], ...
        record.presetName, ...
        record.certificate.physicalGraphUniqueCount, ...
        record.certificate.referenceRouteUniqueCount, ...
        record.static.fullHorizonPositionEospa, ...
        record.dynamicCandidate.fullHorizonPositionEospa, ...
        gain.fullHorizonMeanGainPercent, ...
        gain.focusWindowMeanGainPercent, ...
        gain.worstSensorGainPercent, ...
        gain.minimumFormationGainPercent, ...
        gain.focusConsensusGainPercent, ...
        gain.cardinalityGainPercent, ...
        gain.attemptedByteSavingPercent, ...
        gain.strongGatePassed);
end
fprintf(fid, '\n- Both references are functionally static: `%d`\n', ...
    result.bothReferencesFunctionallyStatic);
fprintf(fid, '- Both adaptive candidates improve tracking: `%d`\n', ...
    result.bothDynamicCandidatesImproveTracking);
fprintf(fid, '- Both adaptive candidates pass the strong gate: `%d`\n', ...
    result.bothDynamicCandidatesStrongGatePassed);
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Interpretation\n\n');
fprintf(fid, ['The physical-tree arm is the matched static baseline in ', ...
    'these rigid-translation braided scenes. Consequently the original ', ...
    'V89 improvement fields are exactly the adaptive dynamic-method gain ', ...
    'over static routing, not merely one dynamic method versus another.\n']);
end
