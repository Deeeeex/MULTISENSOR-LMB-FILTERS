function audit = auditFormationB4V46Full32Evidence()
% AUDITFORMATIONB4V46FULL32EVIDENCE Independent committed-artifact audit.

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
relativeDirectory = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'formation_value_v46', ...
    'causal_repair_preflight_e719fd6');
matRelativePath = fullfile(relativeDirectory, ...
    'FORMATION_B4_V46_CAUSAL_REPAIR_FULL32.mat');
reportRelativePath = fullfile(relativeDirectory, ...
    'FORMATION_B4_V46_CAUSAL_REPAIR_FULL32.md');
logRelativePath = fullfile(relativeDirectory, ...
    'FORMATION_B4_V46_CAUSAL_REPAIR_FULL32.log');

expected = struct( ...
    'generationCommit', ...
        'e719fd6475366400d462f1d65cdf3f4067068bbd', ...
    'artifactFreezeCommit', ...
        '20ca88f22ba16ad3c5e2fce4d5603a61690b6cbc', ...
    'protocolSha256', ...
        '01516bc9b58437b4c7436c1f160706cb313a6886b55b15f758f84fd78b64f848', ...
    'resultCanonicalSha256', ...
        'f26e0a96c6df78c32500ed05b1cf7f8a70e9b58ee83b3998181141f465aff42a', ...
    'matFileSha256', ...
        '1bbea7c1dd7e6aae242c977fda55942abcd36cdab890bc830e52b1753f4af7d7', ...
    'reportFileSha256', ...
        '8d138b44c9e9e8c9820ad6571c84ad8593964f49fb02622ec90f3fa534c52644', ...
    'logFileSha256', ...
        '5a146b67872f39918556102fe16949f30c8b2c87e144c62447a1483ec500922b');

artifactPaths = {matRelativePath, reportRelativePath, logRelativePath};
for pathIdx = 1:numel(artifactPaths)
    if exist(fullfile(repoRoot, artifactPaths{pathIdx}), 'file') ~= 2
        error('FormationB4V46Full32Audit:ArtifactMissing', ...
            'A frozen V46 full32 artifact is missing.');
    end
end
matPath = fullfile(repoRoot, matRelativePath);
reportPath = fullfile(repoRoot, reportRelativePath);
logPath = fullfile(repoRoot, logRelativePath);
matFileSha256 = computeFileSha256(matPath);
reportFileSha256 = computeFileSha256(reportPath);
logFileSha256 = computeFileSha256(logPath);
artifactFilesShaPinned = ...
    strcmp(matFileSha256, expected.matFileSha256) && ...
    strcmp(reportFileSha256, expected.reportFileSha256) && ...
    strcmp(logFileSha256, expected.logFileSha256);

variables = whos('-file', matPath);
variableNames = sort({variables.name});
matEnvelopePassed = numel(variables) == 2 && ...
    isequal(variableNames, {'result', 'runMetadata'});
loaded = load(matPath);
if ~matEnvelopePassed || ~isfield(loaded, 'result') || ...
        ~isfield(loaded, 'runMetadata') || ...
        ~isstruct(loaded.result) || ~isscalar(loaded.result) || ...
        ~isstruct(loaded.runMetadata) || ...
        ~isscalar(loaded.runMetadata)
    error('FormationB4V46Full32Audit:ArtifactMalformed', ...
        'The frozen V46 full32 MAT envelope is malformed.');
end
result = loaded.result;
runMetadata = loaded.runMetadata;
if ~isfield(result, 'canonicalSha256')
    error('FormationB4V46Full32Audit:ArtifactMalformed', ...
        'The V46 full32 result lacks a canonical identity.');
end
recomputedResultSha256 = computeCanonicalValueSha256( ...
    rmfield(result, 'canonicalSha256'));
resultCanonicalShaRecomputed = ...
    strcmp(recomputedResultSha256, result.canonicalSha256) && ...
    strcmp(result.canonicalSha256, expected.resultCanonicalSha256);

metadataFields = {'contractVersion', 'generationGitCommit', ...
    'generationGitClean', 'caseCount', 'resultCanonicalSha256'};
runMetadataPassed = exactFields(runMetadata, metadataFields) && ...
    strcmp(runMetadata.contractVersion, ...
        'formation-b4-v46-full32-run-metadata-v1') && ...
    strcmp(runMetadata.generationGitCommit, ...
        expected.generationCommit) && ...
    isExactLogical(runMetadata.generationGitClean, true) && ...
    runMetadata.caseCount == 32 && ...
    strcmp(runMetadata.resultCanonicalSha256, ...
        expected.resultCanonicalSha256);

protocol = getFormationCausalMinimalEditV46Protocol();
protocolCanonicalRecomputed = strcmp( ...
    computeCanonicalValueSha256(rmfield(protocol, 'canonicalSha256')), ...
    protocol.canonicalSha256);
protocolBindingPassed = protocolCanonicalRecomputed && ...
    strcmp(protocol.canonicalSha256, expected.protocolSha256) && ...
    strcmp(result.protocolId, protocol.id) && ...
    strcmp(result.protocolCanonicalSha256, expected.protocolSha256) && ...
    protocol.registeredCartesianCaseCount == 32 && ...
    protocol.full32FullHorizonRoutePreflightRequired && ...
    protocol.dynamicMatrixProductReauditRequired && ...
    ~protocol.runnerSelfAuthorizationAllowed && ...
    ~protocol.trackingAdvanceGatePresent && ...
    ~protocol.trackingOutcomeAuthorized && ...
    ~protocol.validationClaimAllowed;

generationCommitPinned = ...
    isAncestor(repoRoot, expected.generationCommit, ...
        expected.artifactFreezeCommit) && ...
    isAncestor(repoRoot, expected.artifactFreezeCommit, 'HEAD');
sourceRelativePaths = { ...
    fullfile('common', 'FormationB4V46CausalRepairPreflight.m'), ...
    fullfile('common', 'getFormationCausalMinimalEditV46Protocol.m'), ...
    fullfile('common', 'projectCausalMinimalEditFormationBackbone.m'), ...
    fullfile('common', 'buildFormationB4V46FixedRuntimeArm.m'), ...
    fullfile('common', 'buildFormationB4V46FixedTriggerConfig.m'), ...
    fullfile('common', 'selectFormationB4V46ReferenceRuntimePolicy.m'), ...
    fullfile('common', ...
        'selectFormationB4V46SynchronizedRuntimePolicy.m'), ...
    fullfile('common', ...
        'FormationB4V45BuildCausalRegisteredBaseGraph.m'), ...
    fullfile('common', 'computeStochasticMixingDiagnostics.m'), ...
    fullfile('common', 'buildDynamicTopologyScenarioConfig.m'), ...
    fullfile('common', 'generateMultiFormationTrajectories.m'), ...
    fullfile('common', 'buildDynamicTopologyLinkSchedule.m'), ...
    fullfile('common', ...
        'buildDynamicTopologyPhysicalIdentityRegistry.m')};
generationSourcesStillPinned = true;
for pathIdx = 1:numel(sourceRelativePaths)
    generationSourcesStillPinned = generationSourcesStillPinned && ...
        pathBlobMatchesCommitAndWorkingTree(repoRoot, ...
            sourceRelativePaths{pathIdx}, expected.generationCommit);
end

artifactCommitBindingPassed = true;
artifactsAbsentAtGenerationCommit = true;
for pathIdx = 1:numel(artifactPaths)
    artifactCommitBindingPassed = artifactCommitBindingPassed && ...
        trackedAndHeadMatched(repoRoot, artifactPaths{pathIdx}) && ...
        pathBlobMatchesCommitAndHead(repoRoot, ...
            artifactPaths{pathIdx}, expected.artifactFreezeCommit);
    artifactsAbsentAtGenerationCommit = ...
        artifactsAbsentAtGenerationCommit && ...
        ~pathExistsAtCommit(repoRoot, expected.generationCommit, ...
            artifactPaths{pathIdx});
end

caseAudit = auditCases(result, protocol);
resultBoundaryPassed = ...
    isequal(result.presets, protocol.registeredPresets) && ...
    isequal(result.seeds, protocol.registeredSeeds) && ...
    result.caseCount == 32 && ...
    result.requiredFull32CaseCount == 32 && ...
    isExactLogical(result.fullRegistryRequested, true) && ...
    isExactLogical(result.allCasesFullHorizonCovered, true) && ...
    isExactLogical(result.allStructuralChecksPassed, true) && ...
    isExactLogical(result.fullV43RouteCompositionPassed, true) && ...
    isExactLogical(result.dynamicMatrixProductAuditPerformed, true) && ...
    isExactLogical(result.full32CasePreflightPassed, true) && ...
    isExactLogical(result.routeReceivesCurrentPageOnly, true) && ...
    isExactLogical(result.registeredBaseImmutableAcrossEpisode, true) && ...
    allFalse(result, {'posteriorUsed', 'truthUsed', ...
        'measurementUsed', 'futurePagePassedToProjectionOrRoute', ...
        'realizedDeliveryUniformsUsed', 'trackingOutcomeScored', ...
        'trackingOutcomeAuthorized', 'validationClaimAllowed'}) && ...
    isExactLogical(result.developmentEvidenceOnly, true) && ...
    isempty(result.failureRecords) && isempty(result.testTamperMode);

reportText = fileread(reportPath);
logText = fileread(logPath);
reportIdentityMatched = ...
    hasText(reportText, expected.generationCommit) && ...
    hasText(reportText, expected.protocolSha256) && ...
    hasText(reportText, expected.resultCanonicalSha256) && ...
    hasText(reportText, 'Dobrushin coefficient') && ...
    hasText(reportText, 'does **not** establish single-cycle contraction');
logIdentityMatched = ...
    hasText(logText, ...
        'FormationB4V46 preflight case 32/32') && ...
    hasText(logText, ...
        ['FormationB4V46 preflight complete: cases=32 full32=1 ', ...
         'sha256=', expected.resultCanonicalSha256]);

auditRelativePath = fullfile('RUN', 'GA', ...
    'auditFormationB4V46Full32Evidence.m');
auditTestRelativePath = fullfile('tests', ...
    'test_formation_b4_v46_full32_evidence_audit.m');
auditSourcePaths = {auditRelativePath, auditTestRelativePath};
independentAuditCommitted = true;
auditorAbsentAtFreezeCommit = true;
for pathIdx = 1:numel(auditSourcePaths)
    independentAuditCommitted = independentAuditCommitted && ...
        trackedAndHeadMatched(repoRoot, auditSourcePaths{pathIdx});
    auditorAbsentAtFreezeCommit = auditorAbsentAtFreezeCommit && ...
        ~pathExistsAtCommit(repoRoot, expected.artifactFreezeCommit, ...
            auditSourcePaths{pathIdx});
end
auditSourceClean = isCleanWorktree(repoRoot);

postHocAuditPassed = artifactFilesShaPinned && ...
    matEnvelopePassed && resultCanonicalShaRecomputed && ...
    runMetadataPassed && protocolBindingPassed && ...
    generationCommitPinned && generationSourcesStillPinned && ...
    artifactCommitBindingPassed && artifactsAbsentAtGenerationCommit && ...
    caseAudit.passed && resultBoundaryPassed && ...
    reportIdentityMatched && logIdentityMatched && ...
    independentAuditCommitted && auditorAbsentAtFreezeCommit && ...
    auditSourceClean;

audit = struct();
audit.contractVersion = ...
    'formation-b4-v46-full32-posthoc-evidence-audit-v1';
audit.expected = expected;
audit.matRelativePath = matRelativePath;
audit.reportRelativePath = reportRelativePath;
audit.logRelativePath = logRelativePath;
audit.matFileSha256 = matFileSha256;
audit.reportFileSha256 = reportFileSha256;
audit.logFileSha256 = logFileSha256;
audit.recomputedResultCanonicalSha256 = recomputedResultSha256;
audit.artifactFilesShaPinned = artifactFilesShaPinned;
audit.matEnvelopePassed = matEnvelopePassed;
audit.resultCanonicalShaRecomputed = resultCanonicalShaRecomputed;
audit.runMetadataPassed = runMetadataPassed;
audit.protocolBindingPassed = protocolBindingPassed;
audit.generationCommitPinned = generationCommitPinned;
audit.generationSourcesStillPinned = generationSourcesStillPinned;
audit.artifactCommitBindingPassed = artifactCommitBindingPassed;
audit.artifactsAbsentAtGenerationCommit = ...
    artifactsAbsentAtGenerationCommit;
audit.caseAudit = caseAudit;
audit.resultBoundaryPassed = resultBoundaryPassed;
audit.reportIdentityMatched = reportIdentityMatched;
audit.logIdentityMatched = logIdentityMatched;
audit.independentAuditCommitted = independentAuditCommitted;
audit.auditorAbsentAtFreezeCommit = auditorAbsentAtFreezeCommit;
audit.auditSourceClean = auditSourceClean;
audit.postHocAuditPassed = postHocAuditPassed;
audit.full32StructuralAdvancePassed = postHocAuditPassed;
audit.trackingAdvancePassed = false;
audit.validationClaimAllowed = false;
audit.developmentEvidenceOnly = true;
audit.evidenceBoundary = [ ...
    'The committed full32 artifact establishes causal structural ', ...
    'execution and exact attempted-message counts only. It does not ', ...
    'establish single-cycle contraction, tracking non-inferiority, ', ...
    'delivered-byte savings, or validation.'];
audit.passed = audit.full32StructuralAdvancePassed && ...
    ~audit.trackingAdvancePassed && ~audit.validationClaimAllowed;
audit.canonicalSha256 = computeCanonicalValueSha256(audit);
if ~audit.passed
    error('FormationB4V46Full32Audit:Failed', ...
        'The committed V46 full32 post-hoc audit failed closed.');
end
fprintf(['V46 full32 post-hoc audit PASS: result=%s audit=%s ', ...
    'repairPages=%d spectralAboveOne=%d\n'], ...
    result.canonicalSha256, audit.canonicalSha256, ...
    caseAudit.repairPageCount, ...
    caseAudit.centeredSpectralAboveOneWindowCount);
end

function summary = auditCases(result, protocol)
passed = numel(result.cases) == ...
    protocol.registeredCartesianCaseCount;
allDobrushin = zeros(1, 0);
allCenteredSpectral = zeros(1, 0);
allCenteredRow = zeros(1, 0);
allWork = zeros(1, 0);
totalPages = 0;
totalWindows = 0;
totalCycles = 0;
repairCaseCount = 0;
repairPageCount = 0;
totalRemoved = 0;
totalAdded = 0;
cursor = 0;
for presetIdx = 1:numel(protocol.registeredPresets)
    for seedIdx = 1:numel(protocol.registeredSeeds)
        cursor = cursor + 1;
        item = result.cases(cursor);
        presetName = protocol.registeredPresets{presetIdx};
        seed = protocol.registeredSeeds(seedIdx);
        expectedCaseId = sprintf('%s__seed%d__v46-repaired-route', ...
            presetName, seed);
        nodeCount = item.nodeCount;
        passed = passed && strcmp(item.caseId, expectedCaseId) && ...
            strcmp(item.presetName, presetName) && item.seed == seed && ...
            item.simulationLength == 160 && ...
            isequal(item.auditedTimes, 1:160) && ...
            item.auditedTimeCount == 160 && ...
            isExactLogical(item.fullHorizonCovered, true) && ...
            item.rollingWindowCount == 157 && ...
            item.expectedRollingWindowCountForAuditedSpan == 157 && ...
            item.alignedCycleCount == 40 && ...
            abs(item.everyAlignedCycleSavingFraction - 3 / 8) < 1e-12 && ...
            isequal(item.referenceMessageCountByTime, ...
                2 * nodeCount * ones(1, 160)) && ...
            isequal(item.syncB4MessageCountByTime, ...
                repmat([2 * nodeCount, nodeCount, ...
                    nodeCount, nodeCount], 1, 40)) && ...
            isExactLogical(item.noOpPagesExactlyPreservedRegisteredBase, ...
                true) && ...
            isExactLogical(item.projectionBackboneCertificatePassed, true) && ...
            isExactLogical(item.fullV43RouteCompositionPassed, true) && ...
            isExactLogical(item.dynamicMatrixProductAuditPerformed, true) && ...
            isExactLogical(item.structuralChecksPassed, true) && ...
            isExactLogical(item.routeReceivesCurrentPageOnly, true) && ...
            isExactLogical(item.registeredBaseImmutableAcrossEpisode, true) && ...
            allFalse(item, {'posteriorUsed', 'truthUsed', ...
                'measurementUsed', ...
                'futurePagePassedToProjectionOrRoute', ...
                'realizedDeliveryUniformsUsed', ...
                'trackingOutcomeScored', 'trackingOutcomeAuthorized', ...
                'validationClaimAllowed'}) && ...
            isExactLogical(item.developmentEvidenceOnly, true) && ...
            verifyNestedHashes(item) && ...
            strcmp(computeCanonicalValueSha256( ...
                rmfield(item, 'canonicalSha256')), ...
                item.canonicalSha256);
        allDobrushin = [allDobrushin, ...
            item.rollingB4MatrixProductDobrushinByWindow]; %#ok<AGROW>
        allCenteredSpectral = [allCenteredSpectral, ...
            item.rollingB4MatrixProductCenteredSpectralNormByWindow]; %#ok<AGROW>
        allCenteredRow = [allCenteredRow, ...
            item.rollingB4MatrixProductMaximumCenteredRowL2ByWindow]; %#ok<AGROW>
        allWork = [allWork, ...
            item.projectionWorkUnitCountByTime]; %#ok<AGROW>
        totalPages = totalPages + item.auditedTimeCount;
        totalWindows = totalWindows + item.rollingWindowCount;
        totalCycles = totalCycles + item.alignedCycleCount;
        repairCaseCount = repairCaseCount + (item.repairPageCount > 0);
        repairPageCount = repairPageCount + item.repairPageCount;
        totalRemoved = totalRemoved + item.totalRegisteredRemovalCount;
        totalAdded = totalAdded + item.totalNonregisteredAdditionCount;
    end
end

[crossingPassed, crossingSummary] = ...
    auditCrossingRepairs(result.cases);
centeredSpectralAboveOneWindowCount = ...
    nnz(allCenteredSpectral > 1 + 1e-12);
aggregatePassed = totalPages == 5120 && ...
    totalWindows == 5024 && totalCycles == 1280 && ...
    repairCaseCount == 4 && repairPageCount == 14 && ...
    totalRemoved == 24 && totalAdded == 24 && ...
    numel(allDobrushin) == 5024 && ...
    all(abs(allDobrushin - 1) < 1e-12) && ...
    centeredSpectralAboveOneWindowCount == 392 && ...
    abs(max(allCenteredSpectral) - 1.00261042159217) < 1e-12 && ...
    abs(max(allCenteredRow) - 0.481732098849276) < 1e-12 && ...
    max(allWork) == 1626 && crossingPassed;

summary = struct();
summary.caseCount = numel(result.cases);
summary.totalPageCount = totalPages;
summary.rollingWindowCount = totalWindows;
summary.alignedCycleCount = totalCycles;
summary.repairCaseCount = repairCaseCount;
summary.repairPageCount = repairPageCount;
summary.totalRegisteredRemovalCount = totalRemoved;
summary.totalNonregisteredAdditionCount = totalAdded;
summary.allFourStepDobrushinExactlyOne = ...
    all(abs(allDobrushin - 1) < 1e-12);
summary.centeredSpectralAboveOneWindowCount = ...
    centeredSpectralAboveOneWindowCount;
summary.maximumCenteredSpectralNorm = max(allCenteredSpectral);
summary.maximumCenteredRowL2 = max(allCenteredRow);
summary.maximumProjectionWorkUnitCount = max(allWork);
summary.crossing = crossingSummary;
summary.passed = passed && aggregatePassed;
summary.canonicalSha256 = computeCanonicalValueSha256(summary);
end

function [passed, summary] = auditCrossingRepairs(cases)
seeds = [41, 43, 47, 53];
expectedTimes = {158:160, 157:160, 158:160, 157:160};
expectedCounts = {[1, 2, 3], [1, 1, 2, 3], ...
    [1, 2, 3], [1, 1, 1, 2]};
passed = true;
summary = repmat(struct('seed', NaN, 'repairTimes', zeros(1, 0), ...
    'removedCounts', zeros(1, 0), 'addedCounts', zeros(1, 0)), ...
    1, numel(seeds));
for seedIdx = 1:numel(seeds)
    matches = strcmp({cases.presetName}, ...
        'x36-formation-fov-crossing') & [cases.seed] == seeds(seedIdx);
    if nnz(matches) ~= 1
        passed = false;
        continue;
    end
    item = cases(matches);
    mask = item.projectionRegisteredRemovalCountByTime > 0 | ...
        item.projectionNonregisteredAdditionCountByTime > 0;
    actualTimes = item.auditedTimes(mask);
    removed = item.projectionRegisteredRemovalCountByTime(mask);
    added = item.projectionNonregisteredAdditionCountByTime(mask);
    passed = passed && isequal(actualTimes, expectedTimes{seedIdx}) && ...
        isequal(removed, expectedCounts{seedIdx}) && ...
        isequal(added, expectedCounts{seedIdx});
    summary(seedIdx).seed = seeds(seedIdx);
    summary(seedIdx).repairTimes = actualTimes;
    summary(seedIdx).removedCounts = removed;
    summary(seedIdx).addedCounts = added;
end
end

function passed = verifyNestedHashes(item)
hashFields = {'currentPageInputCanonicalSha256ByTime', ...
    'projectedBaseCanonicalSha256ByTime', ...
    'projectionEditCanonicalSha256ByTime', ...
    'selectedProjectionCandidateCanonicalSha256ByTime', ...
    'projectionCertificateCanonicalSha256ByTime', ...
    'referencePageCanonicalSha256ByTime', ...
    'syncB4PageCanonicalSha256ByTime'};
passed = true;
for fieldIdx = 1:numel(hashFields)
    values = item.(hashFields{fieldIdx});
    passed = passed && numel(values) == 160;
    for valueIdx = 1:numel(values)
        passed = passed && isSha256(values{valueIdx});
    end
end
values = item.rollingB4MatrixProductCanonicalSha256ByWindow;
passed = passed && numel(values) == 157;
for valueIdx = 1:numel(values)
    passed = passed && isSha256(values{valueIdx});
end
end

function passed = allFalse(value, fields)
passed = true;
for fieldIdx = 1:numel(fields)
    name = fields{fieldIdx};
    passed = passed && isfield(value, name) && ...
        isExactLogical(value.(name), false);
end
end

function passed = exactFields(value, expectedFields)
passed = isstruct(value) && isscalar(value) && ...
    isequal(sort(fieldnames(value)), ...
        sort(reshape(expectedFields, [], 1)));
end

function passed = isExactLogical(value, expected)
passed = islogical(value) && isscalar(value) && value == expected;
end

function passed = isSha256(value)
passed = ischar(value) && isrow(value) && numel(value) == 64 && ...
    all(ismember(lower(value), '0123456789abcdef'));
end

function passed = pathBlobMatchesCommitAndWorkingTree( ...
        repoRoot, relativePath, commit)
[commitStatus, commitBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "%s:%s"', commit, relativePath));
[headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "HEAD:%s"', relativePath));
[workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
    'hash-object -- "%s"', relativePath));
passed = commitStatus == 0 && headStatus == 0 && ...
    workingStatus == 0 && ...
    strcmp(strtrim(commitBlob), strtrim(headBlob)) && ...
    strcmp(strtrim(headBlob), strtrim(workingBlob));
end

function passed = pathBlobMatchesCommitAndHead( ...
        repoRoot, relativePath, commit)
[commitStatus, commitBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "%s:%s"', commit, relativePath));
[headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "HEAD:%s"', relativePath));
[workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
    'hash-object -- "%s"', relativePath));
passed = commitStatus == 0 && headStatus == 0 && ...
    workingStatus == 0 && ...
    strcmp(strtrim(commitBlob), strtrim(headBlob)) && ...
    strcmp(strtrim(headBlob), strtrim(workingBlob));
end

function passed = trackedAndHeadMatched(repoRoot, relativePath)
[trackedStatus, ~] = gitCommand(repoRoot, sprintf( ...
    'ls-files --error-unmatch -- "%s"', relativePath));
[workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
    'hash-object -- "%s"', relativePath));
[headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "HEAD:%s"', relativePath));
passed = trackedStatus == 0 && workingStatus == 0 && ...
    headStatus == 0 && ...
    strcmp(strtrim(workingBlob), strtrim(headBlob));
end

function exists = pathExistsAtCommit(repoRoot, commit, relativePath)
[status, ~] = gitCommand(repoRoot, sprintf( ...
    'cat-file -e "%s:%s"', commit, relativePath));
exists = status == 0;
end

function yes = isAncestor(repoRoot, ancestor, descendant)
[status, ~] = gitCommand(repoRoot, sprintf( ...
    'merge-base --is-ancestor %s %s', ancestor, descendant));
yes = status == 0;
end

function clean = isCleanWorktree(repoRoot)
[status, porcelain] = gitCommand(repoRoot, ...
    'status --porcelain --untracked-files=all');
clean = status == 0 && isempty(strtrim(porcelain));
end

function [status, output] = gitCommand(repoRoot, arguments)
environmentName = 'FORMATION_V46_FULL32_AUDIT_GIT_ROOT';
previousValue = getenv(environmentName);
cleanup = onCleanup(@() ...
    setenv(environmentName, previousValue)); %#ok<NASGU>
setenv(environmentName, repoRoot);
[status, output] = system(sprintf( ...
    'git -C "$%s" %s 2>/dev/null', environmentName, arguments));
end

function yes = hasText(text, pattern)
yes = ~isempty(strfind(text, pattern)); %#ok<STREMP>
end
