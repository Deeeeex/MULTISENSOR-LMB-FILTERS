function [reportPath, audit] = ...
    auditX36CertifiedOverlapScaleSignals(options)
% AUDITX36CERTIFIEDOVERLAPSCALESIGNALS Diagnose the opened X36 v4 miss.
%
% This is a development-only, post-validation audit.  It rebuilds the
% truth-free t=75 routing decision from the frozen behavior cache, records
% formation-wise score/payload/overlap signals, and joins them to the
% already-opened closed-loop X36 outcome.  It must not be used as fresh
% validation evidence.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
seeds = reshape(getField(options, 'seeds', ...
    protocol.adaptiveDominantCertifiedOverlapX36Seeds), 1, []);
currentTime = round(getField(options, 'currentTime', ...
    protocol.adaptiveDominantCertifiedOverlapX36Times(1)));
rootDirectory = getField(options, 'rootDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantCertifiedOverlapSelectedMarginToken), ...
    protocol.adaptiveDominantCertifiedOverlapX36PresetName));
cacheDirectory = getField(options, 'cacheDirectory', ...
    fullfile(rootDirectory, 'cache'));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'x36_scale_v5', 'failure_diagnosis'));
writeReportEnabled = logical(getField( ...
    options, 'writeReport', true));

rows = repmat(emptyRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    inputs = generateDynamicTopologyScenarioInputs( ...
        protocol.adaptiveDominantCertifiedOverlapX36PresetName, seed);
    cachePath = fullfile(cacheDirectory, sprintf( ...
        'x36_clean_scale_seed%d_n1_sig%d.mat', seed, currentTime));
    bundle = loadBehaviorBundle( ...
        cachePath, seed, currentTime, inputs.config);
    context = buildPolicyContext( ...
        inputs, bundle.posteriorSnapshots{currentTime}, currentTime);
    [~, details] = ...
        selectLabelSetAdaptiveDominantRoutingPolicy( ...
            context, ...
            'composite-balanced-certified-overlap-payload-aware', ...
            struct( ...
                'protocol', protocol, ...
                'payloadMarginFraction', protocol. ...
                    adaptiveDominantCertifiedOverlapSelectedMarginFraction));

    evidencePath = findSingleResult(rootDirectory, seed);
    loadedEvidence = load(evidencePath, 'summary');
    [reference, candidate] = findEvidenceArms( ...
        loadedEvidence.summary, protocol);
    times = protocol.adaptiveDominantCertifiedOverlapX36Times;
    timeGain = 100 * ( ...
        reference.meanEospaByTime(times) - ...
        candidate.meanEospaByTime(times)) ./ ...
        max(reference.meanEospaByTime(times), eps);

    row = emptyRow();
    row.seed = seed;
    row.cachePath = cachePath;
    row.evidencePath = evidencePath;
    row.observedGainPercent = relativeGain( ...
        reference.focusEospa, candidate.focusEospa);
    row.observedTimeGainPercent = timeGain;
    row.negativeTimeCount = sum(timeGain < 0);
    row.minimumObjectiveAdvantage = ...
        details.minimumDominantObjectiveAdvantage;
    row.meanObjectiveAdvantage = ...
        details.meanDominantObjectiveAdvantage;
    row.objectiveAdvantageByFormation = ...
        details.dominantObjectiveAdvantageByFormation;
    row.duplicateCountByFormation = ...
        details.dominantResidualDuplicateCountPerFormation;
    row.selectedIncrementalPayloadBytesByFormation = ...
        details.dominantProjection. ...
            selectedIncrementalPayloadBytesByFormation;
    row.referenceIncrementalPayloadBytesByFormation = ...
        details.dominantProjection. ...
            referenceIncrementalPayloadBytesByFormation;
    row.payloadDeltaPercent = ...
        100 * details.payloadDeltaFraction;
    row.messageCount = details.expectedSelectedMessageCount;
    row.scoreSpread = details.taskRiskSpread;
    [row.meanActiveLabelCount, row.meanExpectedCardinality, ...
        row.maximumActiveLabelCount] = posteriorScaleSummary( ...
            bundle.posteriorSnapshots{currentTime}, ...
            inputs.model.existenceThreshold);
    rows(seedIdx) = row;
    fprintf(['X36 seed %d: outcome %+.3f%%, objective min/mean ', ...
        '%+.3f/%+.3f, duplicates %s, bytes %+.3f%%\n'], ...
        seed, row.observedGainPercent, ...
        row.minimumObjectiveAdvantage, ...
        row.meanObjectiveAdvantage, ...
        mat2str(row.duplicateCountByFormation), ...
        row.payloadDeltaPercent);
end

gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'x36-certified-overlap-post-validation-signal-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.presetName = protocol. ...
    adaptiveDominantCertifiedOverlapX36PresetName;
audit.seeds = seeds;
audit.currentTime = currentTime;
audit.rows = rows;
audit.meanObservedGainPercent = ...
    mean([rows.observedGainPercent]);
audit.positiveSeedFraction = ...
    mean([rows.observedGainPercent] > 0);
audit.anyNegativePredictedFormation = ...
    any([rows.minimumObjectiveAdvantage] < 0);
audit.meanDuplicateCountPerFormation = mean( ...
    [rows.duplicateCountByFormation]);
audit.meanPayloadDeltaPercent = ...
    mean([rows.payloadDeltaPercent]);
audit.developmentEvidenceOnly = true;
audit.x36PairsAlreadyOpened = true;
audit.truthUsedByPolicy = false;
audit.outcomeUsedForDiagnosis = true;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'The five X36 pairs were already opened by the frozen v4 ', ...
    'zero-shot validation. Outcomes are joined only to diagnose and ', ...
    'redesign v5. Any future validation must use distinct preregistered ', ...
    'scenario-seed pairs and a frozen method.'];

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'X36_CERTIFIED_OVERLAP_V4_SCALE_SIGNAL_DIAGNOSIS.md');
    writeReport(reportPath, audit);
    matPath = strrep(reportPath, '.md', '.mat');
    save('-mat7-binary', matPath, 'audit');
    audit.reportPath = reportPath;
    audit.matPath = matPath;
    fprintf('X36 scale-signal audit: %s\n', reportPath);
end
end

function bundle = loadBehaviorBundle( ...
        path, seed, currentTime, config)
if exist(path, 'file') ~= 2
    error('Missing opened X36 behavior cache: %s', path);
end
loaded = load(path, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('X36 behavior cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.presetName, 'x36-clean-scale') || ...
        bundle.seed ~= seed || ...
        ~isequal(bundle.snapshotTimes, currentTime) || ...
        ~isequaln(bundle.configSnapshot, config) || ...
        numel(bundle.posteriorSnapshots) < currentTime || ...
        isempty(bundle.posteriorSnapshots{currentTime})
    error('Opened X36 behavior cache provenance mismatch.');
end
end

function context = buildPolicyContext( ...
        inputs, localPosteriors, currentTime)
sensorCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = localPosteriors;
context.model = inputs.model;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacency = inputs.graphData.staticAdjacency;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, currentTime);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * sensorCount;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, currentTime);
end
end

function path = findSingleResult(rootDirectory, seed)
matches = dir(fullfile(rootDirectory, ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one opened X36 result for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function [reference, candidate] = findEvidenceArms(summary, protocol)
referenceIdx = find(strcmp({summary.records.armMode}, ...
    protocol.adaptiveDominantFullWindowReferenceArmName), 1);
candidateIdx = find(strcmp({summary.records.armMode}, ...
    protocol.adaptiveDominantCertifiedOverlapSelectedArmName), 1);
if isempty(referenceIdx) || isempty(candidateIdx)
    error('Opened X36 result lacks the registered v4 pair.');
end
reference = summary.records(referenceIdx);
candidate = summary.records(candidateIdx);
end

function [meanActive, meanExpected, maximumActive] = ...
        posteriorScaleSummary(posteriors, threshold)
activeCounts = zeros(1, numel(posteriors));
expected = zeros(1, numel(posteriors));
for sensorIdx = 1:numel(posteriors)
    objects = posteriors{sensorIdx};
    if isempty(objects)
        continue;
    end
    existence = [objects.r];
    activeCounts(sensorIdx) = sum(existence > threshold);
    expected(sensorIdx) = sum(existence);
end
meanActive = mean(activeCounts);
meanExpected = mean(expected);
maximumActive = max(activeCounts);
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open X36 scale-signal report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# X36 v4 scale-signal diagnosis\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Preset: `%s`\n', audit.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(audit.seeds));
fprintf(fid, '- Decision time: `%d`\n', audit.currentTime);
fprintf(fid, '- Development evidence only: `%d`\n\n', ...
    audit.developmentEvidenceOnly);
fprintf(fid, ['| Seed | Closed-loop gain | Negative steps | ', ...
    'Min score advantage | Mean score advantage | Duplicates | ', ...
    'Policy byte delta | Active labels |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--|--:|--:|\n');
for row = audit.rows
    fprintf(fid, ...
        '| %d | %+.3f%% | %d | %+.3f | %+.3f | `%s` | %+.3f%% | %.2f |\n', ...
        row.seed, row.observedGainPercent, ...
        row.negativeTimeCount, ...
        row.minimumObjectiveAdvantage, ...
        row.meanObjectiveAdvantage, ...
        mat2str(row.duplicateCountByFormation), ...
        row.payloadDeltaPercent, row.meanActiveLabelCount);
end
fprintf(fid, '\n## Formation-level decision signals\n\n');
fprintf(fid, ['| Seed | Formation | Score advantage | Duplicates | ', ...
    'Selected incremental bytes | Reference incremental bytes |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|\n');
for row = audit.rows
    for formationIdx = 1:numel( ...
            row.objectiveAdvantageByFormation)
        fprintf(fid, '| %d | %d | %+.6f | %d | %.0f | %.0f |\n', ...
            row.seed, formationIdx, ...
            row.objectiveAdvantageByFormation(formationIdx), ...
            row.duplicateCountByFormation(formationIdx), ...
            row.selectedIncrementalPayloadBytesByFormation(formationIdx), ...
            row.referenceIncrementalPayloadBytesByFormation(formationIdx));
    end
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'cachePath', '', ...
    'evidencePath', '', ...
    'observedGainPercent', NaN, ...
    'observedTimeGainPercent', [], ...
    'negativeTimeCount', NaN, ...
    'minimumObjectiveAdvantage', NaN, ...
    'meanObjectiveAdvantage', NaN, ...
    'objectiveAdvantageByFormation', [], ...
    'duplicateCountByFormation', [], ...
    'selectedIncrementalPayloadBytesByFormation', [], ...
    'referenceIncrementalPayloadBytesByFormation', [], ...
    'payloadDeltaPercent', NaN, ...
    'messageCount', NaN, ...
    'scoreSpread', NaN, ...
    'meanActiveLabelCount', NaN, ...
    'meanExpectedCardinality', NaN, ...
    'maximumActiveLabelCount', NaN);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
