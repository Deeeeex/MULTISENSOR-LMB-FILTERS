function result = runFormationB4V48ContractionHeadroomProbe(options)
% RUNFORMATIONB4V48CONTRACTIONHEADROOMPROBE Cheap graph-only falsifier.

if nargin < 1 || isempty(options)
    options = struct();
end
presets = getField(options, 'presets', { ...
    'm24-formation-fov', 'x36-formation-fov'});
seeds = getField(options, 'seeds', 41);
maximumSweeps = getField(options, 'maximumCoordinateSweeps', 1);
records = repmat(emptyRecord(), 1, numel(presets) * numel(seeds));
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        presetName = presets{presetIdx};
        seed = seeds(seedIdx);
        fprintf('V48 headroom %d/%d: %s seed=%d\n', ...
            cursor, numel(records), presetName, seed);
        [context, metadata] = ...
            buildFormationIndexEquivariantGeometryDevelopmentContext( ...
                presetName, seed);
        [referenceAdjacency, referencePolicy] = ...
            selectIndexEquivariantFormationBackbonePolicy( ...
                context, struct('dominantWeight', 0.70, ...
                    'residualWeight', 0.05));
        reference = struct( ...
            'dominantAdjacency', ...
                logical(referencePolicy.dominantAdjacency), ...
            'residualAdjacency', ...
                logical(referencePolicy.residualAdjacency), ...
            'referenceAdjacency', logical(referenceAdjacency), ...
            'referenceFusionWeights', ...
                referencePolicy.fusionWeightMatrix);
        [context, contextContract] = ...
            buildFormationB4V48GraphOnlyContext(context);
        [~, ~, details] = ...
            buildFormationB4V48ContractionOptimizedSchedule( ...
                context, reference, struct( ...
                    'maximumCoordinateSweeps', maximumSweeps, ...
                    'minimumRelativeImprovementVsBestSynchronized', 0));
        item = emptyRecord();
        item.presetName = presetName;
        item.seed = seed;
        item.currentTime = metadata.currentTime;
        item.nodeCount = metadata.nodeCount;
        item.formationCount = metadata.formationCount;
        item.phaseOneSynchronizedSquaredFactor = ...
            details.phaseOneSynchronizedB4SquaredFactor;
        item.bestSynchronizedSquaredFactor = ...
            details.bestSynchronizedB4SquaredFactor;
        item.bestSynchronizedPulsePhase = ...
            details.bestSynchronizedPulsePhase;
        item.selectedSquaredFactor = details.selectedSquaredFactor;
        item.unconstrainedSelectedSquaredFactor = ...
            details.unconstrainedSelectedSquaredFactor;
        item.relativeSquaredFactorImprovementVsPhaseOne = ...
            details.relativeSquaredFactorImprovementVsPhaseOne;
        item.relativeSquaredFactorImprovementVsBestSynchronized = ...
            details.relativeSquaredFactorImprovementVsBestSynchronized;
        item.nontrivialScheduleSelected = ...
            numel(unique(details.selectedPhaseByPhysicalUid)) > 1;
        item.materialityGateDisabledForHeadroomMeasurement = ...
            details.minimumRelativeImprovementVsBestSynchronized == 0;
        item.messageCountByPhase = details.messageCountByPhase;
        item.evaluationCount = sum(details.evaluationCountBySeed);
        controlCost = ...
            estimateFormationB4V48ScheduleControlPlaneCost( ...
                metadata.nodeCount, metadata.formationCount, 1);
        item.idealizedScheduleControlLowerBoundBytes = ...
            controlCost.attemptedControlBytes;
        item.scheduleCanonicalSha256 = details.canonicalSha256;
        item.graphOnlyContextCanonicalSha256 = ...
            contextContract.canonicalSha256;
        records(cursor) = item;
        fprintf(['  sync=%.9g selected=%.9g gain=%+.3f%% ', ...
            ['messages=%s ideal-control-lower-bound=%dB ', ...
             'nontrivial=%d eval=%d\n']], ...
            item.bestSynchronizedSquaredFactor, ...
            item.selectedSquaredFactor, ...
            100 * item.relativeSquaredFactorImprovementVsBestSynchronized, ...
            mat2str(item.messageCountByPhase), ...
            item.idealizedScheduleControlLowerBoundBytes, ...
            item.nontrivialScheduleSelected, item.evaluationCount);
    end
end
payload = struct();
payload.contractVersion = ...
    'formation-b4-v48-contraction-headroom-probe-v1';
payload.presets = presets;
payload.seeds = seeds;
payload.maximumCoordinateSweeps = maximumSweeps;
payload.minimumRelativeImprovementVsBestSynchronized = 0;
payload.records = records;
payload.allNoWorseThanSynchronized = all( ...
    [records.selectedSquaredFactor] <= ...
        [records.bestSynchronizedSquaredFactor] + 1e-12);
payload.positiveHeadroomCaseCount = nnz( ...
    [records.relativeSquaredFactorImprovementVsBestSynchronized] > 1e-6);
payload.posteriorUsed = false;
payload.truthUsed = false;
payload.measurementUsed = false;
payload.futureOutcomeUsed = false;
payload.realizedDeliveryUniformsUsed = false;
payload.trackingOutcomeScored = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
result = payload;
fprintf('V48 headroom complete: positive=%d/%d sha256=%s\n', ...
    result.positiveHeadroomCaseCount, numel(records), ...
    result.canonicalSha256);
end

function item = emptyRecord()
item = struct('presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'nodeCount', NaN, 'formationCount', NaN, ...
    'phaseOneSynchronizedSquaredFactor', NaN, ...
    'bestSynchronizedSquaredFactor', NaN, ...
    'bestSynchronizedPulsePhase', NaN, ...
    'selectedSquaredFactor', NaN, ...
    'unconstrainedSelectedSquaredFactor', NaN, ...
    'relativeSquaredFactorImprovementVsPhaseOne', NaN, ...
    'relativeSquaredFactorImprovementVsBestSynchronized', NaN, ...
    'nontrivialScheduleSelected', false, ...
    'materialityGateDisabledForHeadroomMeasurement', false, ...
    'messageCountByPhase', [], 'evaluationCount', NaN, ...
    'idealizedScheduleControlLowerBoundBytes', NaN, ...
    'scheduleCanonicalSha256', '', ...
    'graphOnlyContextCanonicalSha256', '');
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
