function [reportPath, result] = runNodeDirectedRecoveryV82Anchors(options)
% RUNNODEDIRECTEDRECOVERYV82ANCHORS One-step propagation-node repair.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNodeDirectedRecoveryV82Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NodeDirectedRecoveryV82:DirtySource', ...
        'The V82 headroom screen requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    v80 = getReliabilityBalancedHomotopyV80Protocol();
    homotopy = buildReliabilityBalancedWeightHomotopyV80( ...
        state.context, referenceAdjacency, referenceWeights, ...
        v80.alphaGrid, struct( ...
            'sinkhornTolerance', protocol.sinkhornTolerance, ...
            'sinkhornMaximumIterations', ...
                protocol.sinkhornMaximumIterations, ...
            'effectiveWeightTolerance', ...
                protocol.effectiveWeightTolerance));
    [referenceRound1, referenceRound2] = buildReferenceRounds( ...
        state, referenceAdjacency, referenceWeights, protocol);
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, historicalApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            alignedTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    historical = evaluateHeadroom( ...
        state, referenceRound1, referenceRound2, ...
        referenceAdjacency, referenceWeights, ...
        historicalAdjacency, historicalWeights, ...
        historicalApplied, homotopy, protocol);
    aligned = evaluateHeadroom( ...
        state, referenceRound1, referenceRound2, ...
        referenceAdjacency, referenceWeights, ...
        alignedAdjacency, alignedWeights, alignedApplied, ...
        homotopy, protocol);
    record = emptyCaseRecord();
    record.presetName = state.presetName;
    record.seed = state.seed;
    record.currentTime = state.currentTime;
    record.nodeCount = numel(state.groupIds);
    record.formationCount = numel(unique( ...
        state.groupIds, 'stable'));
    record.groupIds = state.groupIds;
    record.historical = historical;
    record.aligned = aligned;
    records(caseIdx) = record;
    fprintf('V82 %s t=%d historical=%s aligned=%s\n', ...
        state.presetName, state.currentTime, ...
        formatHeadroom(historical), formatHeadroom(aligned));
end

allHistoricalContract = all(arrayfun(@(record) ...
    record.historical.selectedContractsFromPulse, records));
allAlignedContract = all(arrayfun(@(record) ...
    record.aligned.selectedContractsFromPulse, records));
result = struct();
result.contractVersion = ...
    'node-directed-recovery-v82-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allHistoricalSelectedContract = allHistoricalContract;
result.allAlignedSelectedContract = allAlignedContract;
result.oneStepHeadroomGatePassed = ...
    allHistoricalContract && allAlignedContract;
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'NODE_DIRECTED_RECOVERY_V82_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'NODE_DIRECTED_RECOVERY_V82_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V82 node-directed recovery: %s\n', reportPath);
end

function [round1, round2] = buildReferenceRounds( ...
        state, adjacency, weights, protocol)
options = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
round1 = fuseRound(state.context.localPosteriorBySensor, ...
    adjacency, weights, state, protocol, options);
round2 = fuseRound(round1, adjacency, weights, ...
    state, protocol, options);
end

function headroom = evaluateHeadroom( ...
        state, referenceRound1, referenceRound2, ...
        referenceAdjacency, referenceWeights, ...
        candidateAdjacency, candidateWeights, appliedTriples, ...
        homotopy, protocol)
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
modeOptions = struct( ...
    'covarianceRegularization', protocol.covarianceRegularization);
rieOptions = struct( ...
    'conditionalEnergyLimit', protocol.recoveryCandidateRieLimit, ...
    'covarianceRegularization', protocol.covarianceRegularization);
initial = state.context.localPosteriorBySensor;
rie = computeReplacementInnovationEnergyV75( ...
    initial, appliedTriples, state.groupIds, ...
    state.context.model, state.context.commConfig, ...
    state.currentTime, rieOptions);
candidateRound1 = fuseRound(initial, candidateAdjacency, ...
    candidateWeights, state, protocol, fusionOptions);
round1Modes = scoreModes(referenceRound1, candidateRound1, ...
    state.context.model, modeOptions);
round1Nodes = computeLmbArmNodePerturbationContributionsV82( ...
    referenceRound1, candidateRound1, ...
    state.context.model, modeOptions);
baselineNext = fuseRound(candidateRound1, referenceAdjacency, ...
    referenceWeights, state, protocol, fusionOptions);
baselineModes = scoreModes(referenceRound2, baselineNext, ...
    state.context.model, modeOptions);
baselineNodes = computeLmbArmNodePerturbationContributionsV82( ...
    referenceRound2, baselineNext, ...
    state.context.model, modeOptions);
if round1Nodes.closureError > ...
        protocol.nodeContributionClosureTolerance || ...
        baselineNodes.closureError > ...
            protocol.nodeContributionClosureTolerance
    error('NodeDirectedRecoveryV82:ContributionClosure', ...
        'Node contributions do not close to V77 energy.');
end
growth = baselineNodes.totalContributionByNode - ...
    round1Nodes.totalContributionByNode;
nominated = nominateReceivers( ...
    growth, protocol.maximumNominatedReceiverCount);
bank = buildActionBank( ...
    referenceAdjacency, referenceWeights, nominated, ...
    homotopy, protocol);
[responses, selectedIdx] = evaluateActions( ...
    candidateRound1, referenceRound2, baselineNext, bank, ...
    state, protocol, fusionOptions, modeOptions);
selected = responses(selectedIdx);
headroom = struct();
headroom.appliedSlotTriples = appliedTriples;
headroom.maximumRound1Rie = max( ...
    [rie.formationRecords.maximumConditionalEnergy]);
headroom.round1RieSafe = rie.allFormationsSafe;
headroom.round1Modes = round1Modes;
headroom.baselineModes = baselineModes;
headroom.round1NodeContribution = ...
    round1Nodes.totalContributionByNode;
headroom.baselineNodeContribution = ...
    baselineNodes.totalContributionByNode;
headroom.nodeContributionGrowth = growth;
headroom.nominatedReceiverIndices = nominated;
headroom.nominatedFormationIds = ...
    state.groupIds(nominated);
headroom.actionBank = stripWeights(bank);
headroom.responses = responses;
headroom.selectedActionIndex = selectedIdx;
headroom.selectedActionName = selected.actionName;
headroom.selectedActionType = selected.actionType;
headroom.selectedCenteredEnergy = selected.centeredEnergy;
headroom.selectedExistenceCenteredEnergy = ...
    selected.existenceCenteredEnergy;
headroom.selectedSpatialCenteredEnergy = ...
    selected.spatialCenteredEnergy;
headroom.selectedContractsFromPulse = ...
    selected.centeredEnergy <= round1Modes.centeredEnergy + 1e-12;
headroom.baselineContractsFromPulse = ...
    baselineModes.centeredEnergy <= round1Modes.centeredEnergy + 1e-12;
headroom.selectedImprovementOverBaselinePercent = 100 * ( ...
    baselineModes.centeredEnergy - selected.centeredEnergy) / ...
        max(baselineModes.centeredEnergy, eps);
headroom.truthUsed = false;
headroom.futureMeasurementUsed = false;
end

function nominated = nominateReceivers(growth, maximumCount)
positive = find(growth > 1e-15);
if isempty(positive)
    nominated = zeros(1, 0);
    return;
end
rows = [-growth(positive)', positive'];
rows = sortrows(rows, [1, 2]);
nominated = reshape(rows( ...
    1:min(maximumCount, size(rows, 1)), 2), 1, []);
end

function bank = buildActionBank( ...
        referenceAdjacency, referenceWeights, nominated, ...
        homotopy, protocol)
individualCount = numel(nominated) * ...
    numel(protocol.dominantDampingFactors);
jointCount = double(numel(nominated) > 1) * ...
    numel(protocol.dominantDampingFactors);
actionCount = 1 + numel(protocol.globalBalancingAlphas) + ...
    individualCount + jointCount;
bank = repmat(emptyAction(), 1, actionCount);
cursor = 1;
bank(cursor) = makeAction('R', 'reference', 0, zeros(1, 0), ...
    referenceAdjacency, referenceWeights, referenceWeights);
for alpha = protocol.globalBalancingAlphas
    pointIdx = find(abs([homotopy.points.alpha] - alpha) <= 1e-12, 1);
    cursor = cursor + 1;
    bank(cursor) = makeAction( ...
        sprintf('G%02d', round(100 * alpha)), ...
        'global-balance', alpha, zeros(1, 0), ...
        referenceAdjacency, ...
        homotopy.points(pointIdx).fusionWeights, ...
        referenceWeights);
end
for receiverIdx = nominated
    for factor = protocol.dominantDampingFactors
        damped = buildReceiverDominantDampingWeightsV82( ...
            referenceAdjacency, referenceWeights, ...
            receiverIdx, factor);
        cursor = cursor + 1;
        bank(cursor) = makeAction( ...
            sprintf('D%d-%02d', receiverIdx, round(100 * factor)), ...
            'single-node-dominant-damping', factor, receiverIdx, ...
            damped.adjacency, damped.fusionWeights, referenceWeights);
    end
end
if numel(nominated) > 1
    for factor = protocol.dominantDampingFactors
        damped = buildReceiverDominantDampingWeightsV82( ...
            referenceAdjacency, referenceWeights, ...
            nominated, factor);
        cursor = cursor + 1;
        bank(cursor) = makeAction( ...
            sprintf('J%s-%02d', strrep(mat2str(nominated), ' ', ','), ...
                round(100 * factor)), ...
            'joint-node-dominant-damping', factor, nominated, ...
            damped.adjacency, damped.fusionWeights, referenceWeights);
    end
end
if cursor ~= actionCount || ...
        any([bank.messageCount] ~= nnz(referenceAdjacency))
    error('NodeDirectedRecoveryV82:InvalidActionBank', ...
        'The node-directed bank violates message parity.');
end
end

function action = makeAction( ...
        name, type, parameter, receivers, adjacency, ...
        weights, referenceWeights)
action = emptyAction();
action.name = name;
action.type = type;
action.parameter = parameter;
action.receiverIndices = reshape(receivers, 1, []);
action.adjacency = logical(adjacency);
action.fusionWeights = weights;
action.interventionMagnitude = ...
    norm(weights - referenceWeights, 'fro');
action.messageCount = nnz(adjacency);
end

function [responses, selectedIdx] = evaluateActions( ...
        currentPosteriors, referencePosteriors, baselinePosteriors, ...
        bank, state, protocol, fusionOptions, modeOptions)
responses = repmat(emptyResponse(), 1, numel(bank));
for actionIdx = 1:numel(bank)
    action = bank(actionIdx);
    if strcmp(action.type, 'reference')
        posteriors = baselinePosteriors;
    else
        posteriors = fuseRound(currentPosteriors, ...
            action.adjacency, action.fusionWeights, ...
            state, protocol, fusionOptions);
    end
    modes = scoreModes(referencePosteriors, posteriors, ...
        state.context.model, modeOptions);
    response = emptyResponse();
    response.actionIndex = actionIdx;
    response.actionName = action.name;
    response.actionType = action.type;
    response.parameter = action.parameter;
    response.receiverIndices = action.receiverIndices;
    response.interventionMagnitude = ...
        action.interventionMagnitude;
    response.centeredEnergy = modes.centeredEnergy;
    response.existenceCenteredEnergy = ...
        modes.existenceCenteredEnergy;
    response.spatialCenteredEnergy = ...
        modes.spatialCenteredEnergy;
    response.commonEnergy = modes.commonEnergy;
    responses(actionIdx) = response;
end
score = [[responses.centeredEnergy]', ...
    [responses.interventionMagnitude]', ...
    [responses.actionIndex]'];
[~, order] = sortrows(score, [1, 2, 3]);
selectedIdx = order(1);
end

function aggregate = scoreModes( ...
        referencePosteriors, candidatePosteriors, model, options)
modes = computeLmbArmPerturbationModesV77( ...
    referencePosteriors, candidatePosteriors, model, options);
aggregate = modes.aggregate;
end

function posteriors = fuseRound( ...
        posteriors, adjacency, weights, state, protocol, options)
[posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
    posteriors, adjacency, weights, state.context.model, ...
    state.context.commConfig, state.currentTime, ...
    protocol.fusionConfig, options);
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('NodeDirectedRecoveryV82:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('NodeDirectedRecoveryV82:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function stripped = stripWeights(bank)
stripped = repmat(struct( ...
    'name', '', 'type', '', 'parameter', NaN, ...
    'receiverIndices', zeros(1, 0), ...
    'interventionMagnitude', NaN, 'messageCount', 0), ...
    1, numel(bank));
for idx = 1:numel(bank)
    stripped(idx).name = bank(idx).name;
    stripped(idx).type = bank(idx).type;
    stripped(idx).parameter = bank(idx).parameter;
    stripped(idx).receiverIndices = bank(idx).receiverIndices;
    stripped(idx).interventionMagnitude = ...
        bank(idx).interventionMagnitude;
    stripped(idx).messageCount = bank(idx).messageCount;
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NodeDirectedRecoveryV82:WriteFailed', ...
        'Cannot open V82 report for writing.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V82 node-directed recovery\n\n');
fprintf(fid, '- One-step headroom gate passed: `%d`\n', ...
    result.oneStepHeadroomGatePassed);
fprintf(fid, '- Tracking outcome available: `0`\n\n');
for caseIdx = 1:numel(result.records)
    record = result.records(caseIdx);
    fprintf(fid, '## %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    writeHeadroom(fid, 'Historical exact V71/V72 route', ...
        record.historical, record.groupIds);
    writeHeadroom(fid, 'Prospective exact V73 route', ...
        record.aligned, record.groupIds);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeHeadroom(fid, titleText, headroom, groupIds)
fprintf(fid, '### %s\n\n', titleText);
fprintf(fid, '- Applied slot triples: `%s`\n', ...
    mat2str(headroom.appliedSlotTriples));
fprintf(fid, '- Nominated receivers / formations: `%s / %s`\n', ...
    mat2str(headroom.nominatedReceiverIndices), ...
    mat2str(headroom.nominatedFormationIds));
fprintf(fid, '- Pulse / reference-recovery centered energy: `%.8g / %.8g`\n', ...
    headroom.round1Modes.centeredEnergy, ...
    headroom.baselineModes.centeredEnergy);
fprintf(fid, ['- Selected action / centered energy / contracts: ', ...
    '`%s / %.8g / %d`\n'], ...
    headroom.selectedActionName, headroom.selectedCenteredEnergy, ...
    headroom.selectedContractsFromPulse);
fprintf(fid, '- Improvement over reference recovery: `%+.4f%%`\n\n', ...
    headroom.selectedImprovementOverBaselinePercent);
growth = headroom.nodeContributionGrowth;
rows = [-growth(:), (1:numel(growth))'];
rows = sortrows(rows, [1, 2]);
fprintf(fid, '| Node | Formation | Pulse contribution | Reference-next | Growth |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|\n');
for rowIdx = 1:min(8, size(rows, 1))
    nodeIdx = rows(rowIdx, 2);
    fprintf(fid, '| %d | %d | %.8g | %.8g | %+.8g |\n', ...
        nodeIdx, groupIds(nodeIdx), ...
        headroom.round1NodeContribution(nodeIdx), ...
        headroom.baselineNodeContribution(nodeIdx), growth(nodeIdx));
end
fprintf(fid, '\n| Action | Type | Receivers | Parameter | Centered | Existence | Spatial |\n');
fprintf(fid, '|:--|:--|:--|--:|--:|--:|--:|\n');
for response = headroom.responses
    fprintf(fid, '| %s | %s | `%s` | %.3f | %.8g | %.8g | %.8g |\n', ...
        response.actionName, response.actionType, ...
        mat2str(response.receiverIndices), response.parameter, ...
        response.centeredEnergy, ...
        response.existenceCenteredEnergy, ...
        response.spatialCenteredEnergy);
end
fprintf(fid, '\n');
end

function text = formatHeadroom(headroom)
text = sprintf('%s center=%.4g contract=%d nodes=%s', ...
    headroom.selectedActionName, headroom.selectedCenteredEnergy, ...
    headroom.selectedContractsFromPulse, ...
    mat2str(headroom.nominatedReceiverIndices));
end

function action = emptyAction()
