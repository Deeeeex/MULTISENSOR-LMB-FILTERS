    'name', '', ...
    'type', '', ...
    'parameter', NaN, ...
    'receiverIndices', zeros(1, 0), ...
    'adjacency', false(0), ...
    'fusionWeights', zeros(0), ...
    'interventionMagnitude', NaN, ...
    'messageCount', 0);
end

function response = emptyResponse()
response = struct( ...
    'actionIndex', 0, ...
    'actionName', '', ...
    'actionType', '', ...
    'parameter', NaN, ...
    'receiverIndices', zeros(1, 0), ...
    'interventionMagnitude', NaN, ...
    'centeredEnergy', NaN, ...
    'existenceCenteredEnergy', NaN, ...
    'spatialCenteredEnergy', NaN, ...
    'commonEnergy', NaN);
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'nodeCount', 0, ...
    'formationCount', 0, ...
    'groupIds', zeros(1, 0), ...
    'historical', struct(), ...
    'aligned', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
