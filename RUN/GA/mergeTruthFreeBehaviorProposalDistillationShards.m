function [datasetPath, dataset] = ...
    mergeTruthFreeBehaviorProposalDistillationShards(options)
% MERGETRUTHFREEBEHAVIORPROPOSALDISTILLATIONSHARDS Merge six seed shards.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeProposalDistillationProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official proposal-distillation merge requires clean source.');
end
shardDirectory = getField(options, 'shardDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'datasets', ...
    'proposal_distillation_shards'));
shards = cell(1, numel(protocol.datasetSeeds));
shardPaths = cell(1, numel(protocol.datasetSeeds));
shardSha256 = cell(1, numel(protocol.datasetSeeds));
generationCommits = cell(1, numel(protocol.datasetSeeds));
for seedIdx = 1:numel(protocol.datasetSeeds)
    seed = protocol.datasetSeeds(seedIdx);
    shardPaths{seedIdx} = fullfile(shardDirectory, sprintf( ...
        ['rolling_safe_proposal_distillation_', ...
         'm24_hard_t75_t100_seed%d_v1.mat'], seed));
    if exist(shardPaths{seedIdx}, 'file') ~= 2
        error('Missing proposal-distillation shard for seed %d.', seed);
    end
    shardSha256{seedIdx} = ...
        computeFileSha256(shardPaths{seedIdx});
    loaded = load(shardPaths{seedIdx}, 'dataset');
    if ~isfield(loaded, 'dataset')
        error('Proposal-distillation shard lacks dataset.');
    end
    shard = loaded.dataset;
    validateShard(shard, seed, protocol);
    shards{seedIdx} = shard;
    generationCommits{seedIdx} = ...
        shard.generationGitCommit;
end
if numel(unique(generationCommits)) ~= 1
    error('Proposal-distillation shards have mixed source commits.');
end

dataset = shards{1};
dataset.generatedAt = datestr(now, 31);
dataset.seeds = protocol.datasetSeeds;
dataset.actionCodeSequences = ...
    protocol.actionCodeSequences;
dataset.blocks = [shards{1}.blocks];
dataset.teacherBlocks = [shards{1}.teacherBlocks];
dataset.outcomes = [shards{1}.outcomes];
dataset.behaviorCacheRecords = ...
    [shards{1}.behaviorCacheRecords];
for shardIdx = 2:numel(shards)
    shard = shards{shardIdx};
    dataset.blocks = [dataset.blocks, shard.blocks]; %#ok<AGROW>
    dataset.teacherBlocks = [ ...
        dataset.teacherBlocks, shard.teacherBlocks]; %#ok<AGROW>
    dataset.outcomes = [ ...
        dataset.outcomes, shard.outcomes]; %#ok<AGROW>
    dataset.behaviorCacheRecords = [ ...
        dataset.behaviorCacheRecords, ...
        shard.behaviorCacheRecords]; %#ok<AGROW>
end
for blockIdx = 1:numel(dataset.teacherBlocks)
    dataset.teacherBlocks(blockIdx).behaviorBlockIndex = blockIdx;
end
dataset.behaviorCacheSha256 = ...
    {dataset.behaviorCacheRecords.sha256};
dataset.totalTeacherTargetCount = ...
    sum([dataset.teacherBlocks.targetCount]);
dataset.minimumTeacherTargetsPerBlock = ...
    min([dataset.teacherBlocks.targetCount]);
dataset.maximumTeacherTargetsPerBlock = ...
    max([dataset.teacherBlocks.targetCount]);
dataset.completeOfficialGrid = true;
dataset.shardSeedSubset = protocol.datasetSeeds;
dataset.sourceShardPaths = shardPaths;
dataset.sourceShardSha256 = shardSha256;
dataset.sourceShardSetSha256 = computeTextSha256( ...
    strjoin(shardSha256, char(31)));
dataset.sourceShardGenerationCommit = ...
    generationCommits{1};
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'datasets'));
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    ['rolling_safe_proposal_distillation_', ...
     'm24_hard_t75_t100_v1.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    ['ROLLING_SAFE_PROPOSAL_DISTILLATION_', ...
     'M24_HARD_T75_T100_V1.md']));
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
validateMergedDataset(dataset, protocol);
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Merged proposal-distillation dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);
end

function validateShard(dataset, seed, protocol)
if ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~isequal(dataset.seeds, seed) || ...
        ~isequal(dataset.shardSeedSubset, seed) || ...
        dataset.completeOfficialGrid || ...
        numel(dataset.blocks) ~= ...
            numel(protocol.snapshotTimes) || ...
        numel(dataset.teacherBlocks) ~= ...
            numel(protocol.snapshotTimes) || ...
        ~isequal([dataset.blocks.currentTime], ...
            protocol.snapshotTimes) || ...
        ~isequal([dataset.teacherBlocks.currentTime], ...
            protocol.snapshotTimes) || ...
        any([dataset.blocks.actionTruthUsed]) || ...
        any([dataset.blocks.labelTruthUsed]) || ...
        dataset.behaviorTruthUsed || ...
        dataset.behaviorFutureOutcomeUsed || ...
        dataset.featuresUseTruth || ...
        ~dataset.teacherTargetsUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome || ...
        dataset.generationTrackedWorktreeDirty || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles)
    error('Proposal-distillation shard %d violates its contract.', seed);
end
end

function validateMergedDataset(dataset, protocol)
expectedPairs = zeros(protocol.expectedBlockCount, 2);
cursor = 0;
for seed = protocol.datasetSeeds
    for currentTime = protocol.snapshotTimes
        cursor = cursor + 1;
        expectedPairs(cursor, :) = [seed, currentTime];
    end
end
blockPairs = [[dataset.blocks.seed]', ...
    [dataset.blocks.currentTime]'];
teacherPairs = [[dataset.teacherBlocks.seed]', ...
    [dataset.teacherBlocks.currentTime]'];
if ~dataset.completeOfficialGrid || ...
        numel(dataset.blocks) ~= protocol.expectedBlockCount || ...
        numel(dataset.teacherBlocks) ~= ...
            protocol.expectedBlockCount || ...
        ~isequal(blockPairs, expectedPairs) || ...
        ~isequal(teacherPairs, expectedPairs) || ...
        dataset.minimumTeacherTargetsPerBlock < ...
            protocol.minimumTargetsPerBlock || ...
        dataset.maximumTeacherTargetsPerBlock > ...
            protocol.maximumTargetsPerBlock || ...
        any([dataset.blocks.actionTruthUsed]) || ...
        any([dataset.blocks.labelTruthUsed])
    error('Merged proposal-distillation dataset is incomplete.');
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open merged proposal-distillation report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# Truth-free-behavior proposal distillation: M24\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Merge commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Shard generation commit: `%s`\n', ...
    dataset.sourceShardGenerationCommit);
fprintf(fid, '- Shard-set SHA-256: `%s`\n', ...
    dataset.sourceShardSetSha256);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%d:%d`\n', ...
    dataset.snapshotTimes(1), dataset.snapshotTimes(end));
fprintf(fid, '- State blocks: `%d`\n', numel(dataset.blocks));
fprintf(fid, '- Teacher targets: `%d`\n', ...
    dataset.totalTeacherTargetCount);
fprintf(fid, '- Targets per block min/max: `%d / %d`\n', ...
    dataset.minimumTeacherTargetsPerBlock, ...
    dataset.maximumTeacherTargetsPerBlock);
fprintf(fid, '- Behavior/feature truth used: `%d / %d`\n', ...
    dataset.behaviorTruthUsed, dataset.featuresUseTruth);
fprintf(fid, '- Teacher truth/future used: `%d / %d`\n', ...
    dataset.teacherTargetsUseTruth, ...
    dataset.teacherTargetsUseFutureOutcome);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, '## Shards\n\n');
fprintf(fid, '| Seed | SHA-256 | Blocks | Targets |\n');
fprintf(fid, '|--:|:--|--:|--:|\n');
for seedIdx = 1:numel(dataset.seeds)
    seed = dataset.seeds(seedIdx);
    mask = [dataset.teacherBlocks.seed] == seed;
    fprintf(fid, '| %d | `%s` | %d | %d |\n', ...
        seed, dataset.sourceShardSha256{seedIdx}, ...
        nnz(mask), ...
        sum([dataset.teacherBlocks(mask).targetCount]));
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
