function [reportPath, audit] = ...
    auditX36ConsensusPayloadFeasibility(options)
% AUDITX36CONSENSUSPAYLOADFEASIBILITY
% Measure the one-step consensus/payload feasible-set gap on opened X36.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
seeds = reshape(getField(options, 'seeds', ...
    protocol.adaptiveDominantConsensusProjectedDevelopmentSeeds), 1, []);
currentTime = round(getField(options, 'currentTime', ...
    protocol.adaptiveDominantConsensusProjectedDevelopmentTimes(1)));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'x36_scale_v6', 'feasibility_audit'));
writeReportEnabled = logical(getField( ...
    options, 'writeReport', true));

rows = repmat(emptyRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    inputs = generateDynamicTopologyScenarioInputs( ...
        protocol. ...
            adaptiveDominantConsensusProjectedDevelopmentPresetName, ...
        seed);
    cachePath = fullfile( ...
        protocol.adaptiveDominantScaleRiskGatedBaselineRoot, ...
        'cache', sprintf( ...
            'x36_clean_scale_seed%d_n1_sig%d.mat', ...
            seed, currentTime));
    loaded = load(cachePath, 'behaviorBundle');
    if ~isfield(loaded, 'behaviorBundle') || ...
            loaded.behaviorBundle.seed ~= seed || ...
            ~isequal(loaded.behaviorBundle.snapshotTimes, currentTime)
        error('X36 consensus-feasibility cache provenance mismatch.');
    end
    context = buildContext( ...
        inputs, loaded.behaviorBundle. ...
            posteriorSnapshots{currentTime}, currentTime);
    timerId = tic;
    [~, details] = ...
        selectLabelSetAdaptiveDominantRoutingPolicy( ...
            context, ...
            ['composite-balanced-certified-overlap-', ...
             'scale-risk-consensus-projected-payload-aware'], ...
            struct( ...
                'protocol', protocol, ...
                'payloadMarginFraction', protocol. ...
                    adaptiveDominantScaleRiskGatedPayloadMarginFraction, ...
                'baseFormationRegretAllowance', protocol. ...
                    adaptiveDominantConsensusProjectedBaseRegretAllowance, ...
                'referenceFormationCount', protocol. ...
                    adaptiveDominantScaleRiskGatedReferenceFormationCount, ...
                'consensusRiskToleranceFraction', 0, ...
                'consensusAggregationMode', protocol. ...
                    adaptiveDominantConsensusProjectedAggregationMode, ...
                'consensusTailFraction', protocol. ...
                    adaptiveDominantConsensusProjectedTailFraction, ...
                'maximumConsensusProjectionFormationCount', protocol. ...
                    adaptiveDominantConsensusProjectedMaximumFormationCount));
    projection = details.consensusProjection;
    row = emptyRow();
    row.seed = seed;
    row.cachePath = cachePath;
    row.currentTime = currentTime;
    row.candidateRisk = projection.candidateRisk;
    row.referenceRisk = projection.referenceRisk;
    row.minimumPayloadFeasibleRisk = projection.selectedRisk;
    row.minimumRelativeRiskGapPercent = 100 * ...
        (projection.selectedRisk - projection.referenceRisk) / ...
            max(projection.referenceRisk, eps);
    row.candidatePayloadBytes = projection.candidatePayloadBytes;
    row.referencePayloadBytes = projection.referencePayloadBytes;
    row.payloadTargetBytes = projection.payloadTargetBytes;
    row.selectedPayloadBytes = projection.selectedPayloadBytes;
    row.selectedPayloadSavingPercent = 100 * ...
        (projection.referencePayloadBytes - ...
         projection.selectedPayloadBytes) / ...
            max(projection.referencePayloadBytes, eps);
    row.payloadFeasibleCandidateCount = ...
        projection.payloadFeasibleCandidateCount;
    row.strictFeasibleCandidateCount = ...
        projection.feasibleCandidateCount;
    row.selectedReferenceFormationMask = ...
        projection.selectedReferenceFormationMask;
    row.elapsedSeconds = toc(timerId);
    rows(seedIdx) = row;
    fprintf([ ...
        'X36 seed %d: min risk gap %+.3f%%, payload saving %.3f%%, ', ...
        'strict feasible %d/%d, %.2fs\n'], ...
        seed, row.minimumRelativeRiskGapPercent, ...
        row.selectedPayloadSavingPercent, ...
        row.strictFeasibleCandidateCount, ...
        row.payloadFeasibleCandidateCount, row.elapsedSeconds);
end

gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'x36-one-step-consensus-payload-feasibility-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.presetName = protocol. ...
    adaptiveDominantConsensusProjectedDevelopmentPresetName;
audit.seeds = seeds;
audit.currentTime = currentTime;
audit.rows = rows;
audit.maximumMinimumRelativeRiskGapPercent = ...
    max([rows.minimumRelativeRiskGapPercent]);
audit.minimumToleranceTokenCoveringAuditedStates = ...
    ceil(10 * max(0, ...
        audit.maximumMinimumRelativeRiskGapPercent));
audit.allStrictlyFeasible = ...
    all([rows.strictFeasibleCandidateCount] > 0);
audit.truthUsed = false;
audit.futureOutcomeUsed = false;
audit.openedDevelopmentEvidenceOnly = true;
audit.validationClaimAllowed = false;

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'X36_ONE_STEP_CONSENSUS_PAYLOAD_FEASIBILITY_AUDIT.md');
    writeReport(reportPath, audit);
    matPath = strrep(reportPath, '.md', '.mat');
    save('-mat7-binary', matPath, 'audit');
    audit.reportPath = reportPath;
    audit.matPath = matPath;
    fprintf('X36 consensus/payload feasibility audit: %s\n', ...
        reportPath);
end
end

function context = buildContext(inputs, posteriors, currentTime)
sensorCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = posteriors;
context.model = inputs.model;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacency = inputs.graphData.staticAdjacency;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, currentTime);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * sensorCount;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, currentTime);
end
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'cachePath', '', ...
    'currentTime', NaN, ...
    'candidateRisk', NaN, ...
    'referenceRisk', NaN, ...
    'minimumPayloadFeasibleRisk', NaN, ...
    'minimumRelativeRiskGapPercent', NaN, ...
    'candidatePayloadBytes', NaN, ...
    'referencePayloadBytes', NaN, ...
    'payloadTargetBytes', NaN, ...
    'selectedPayloadBytes', NaN, ...
    'selectedPayloadSavingPercent', NaN, ...
    'payloadFeasibleCandidateCount', 0, ...
    'strictFeasibleCandidateCount', 0, ...
    'selectedReferenceFormationMask', false(1, 0), ...
    'elapsedSeconds', NaN);
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open X36 consensus-feasibility report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# X36 one-step consensus/payload feasibility audit\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Preset: `%s`\n', audit.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(audit.seeds));
fprintf(fid, '- Decision time: `%d`\n', audit.currentTime);
fprintf(fid, '- Truth used: `%d`\n', audit.truthUsed);
fprintf(fid, '- Development evidence only: `%d`\n\n', ...
    audit.openedDevelopmentEvidenceOnly);
fprintf(fid, [ ...
    '| Seed | Candidate risk | Reference risk | Minimum feasible risk | ', ...
    'Minimum gap | Selected byte saving | Strict feasible | ', ...
    'Payload feasible | Reference formations | Time |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--|--:|\n');
for row = audit.rows
    fprintf(fid, [ ...
        '| %d | %.6f | %.6f | %.6f | %+.3f%% | %.3f%% | ', ...
        '%d | %d | `%s` | %.2fs |\n'], ...
        row.seed, row.candidateRisk, row.referenceRisk, ...
        row.minimumPayloadFeasibleRisk, ...
        row.minimumRelativeRiskGapPercent, ...
        row.selectedPayloadSavingPercent, ...
        row.strictFeasibleCandidateCount, ...
        row.payloadFeasibleCandidateCount, ...
        mat2str(row.selectedReferenceFormationMask), ...
        row.elapsedSeconds);
end
fprintf(fid, '\n## Frozen interpretation boundary\n\n');
fprintf(fid, [ ...
    '- Largest minimum relative risk gap: `%.6f%%`\n'], ...
    audit.maximumMinimumRelativeRiskGapPercent);
fprintf(fid, [ ...
    '- Smallest 0.1%% tolerance token covering these audited ', ...
    'states: `%03d`\n'], ...
    audit.minimumToleranceTokenCoveringAuditedStates);
fprintf(fid, '- All states strictly feasible: `%d`\n\n', ...
    audit.allStrictlyFeasible);
fprintf(fid, [ ...
    'This audit uses current posteriors and current link reliabilities ', ...
    'only. It quantifies the feasibility boundary on already-opened ', ...
    'development pairs and does not support an X36 validation claim.\n']);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
