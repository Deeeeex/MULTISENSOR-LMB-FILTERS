function [reportPath, result] = ...
    runNetworkBudgetReallocatedMultiSourceV95MatchedStaticHeadroom(options)
% RUNNETWORKBUDGETREALLOCATEDMULTISOURCEV95MATCHEDSTATICHEADROOM Four arms.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNetworkBudgetReallocatedMultiSourceV95Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NetworkBudgetV95:DirtySource', ...
        'V95 matched-static headroom requires clean frozen source.');
end
structural = loadStructuralGate(protocol);
if ~structural.crossScaleStructuralGatePassed || ...
        ~structural.matchedStaticHeadroomAuthorized
    error('NetworkBudgetV95:StructuralGateClosed', ...
        'The V95 four-arm tracking screen is not structurally authorized.');
end

outputRoot = getField(options, ...
    'outputRoot', protocol.headroomOutputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
records = repmat(emptyRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    sequences = buildFourArmSequences(entry.horizonSteps);
    screenRoot = fullfile(outputRoot, 'screens', ...
        lower(entry.scaleName), sprintf('t%d', entry.currentTime));
    screenOptions = struct( ...
        'horizonSteps', entry.horizonSteps, ...
        'interventionDurationSteps', 1, ...
        'filterSeedOffset', protocol.filterSeedOffset, ...
        'cacheRoot', entry.cacheRoot, ...
        'interventionBankType', ...
            'network-budget-reallocated-multi-source-v95', ...
        'trackingAlignedExecutionProfile', ...
            'v95-network-budget-reallocated-multi-source', ...
        'networkBudgetReallocationBankOptions', struct( ...
            'requiredTokenCount', entry.requiredTokenCount, ...
            'requiredTargetFormationCount', ...
                entry.requiredTargetFormationCount, ...
            'requiredSourceFormationCount', ...
                entry.requiredSourceFormationCount), ...
        'receiverMode', protocol.receiverMode, ...
        'actionSequenceIndices', sequences, ...
        'outputDirectory', screenRoot, ...
        'writeReport', true);
    [screenReportPath, screen] = ...
        runFormationModeOpenedReturnScreen( ...
            entry.presetName, entry.seed, entry.currentTime, ...
            screenOptions);
    records(caseIdx) = summarizeCase( ...
        screen, screenReportPath, entry, protocol, sequences);
end

result = struct();
result.contractVersion = ...
    'network-budget-reallocated-multi-source-v95-headroom-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.baselineName = protocol.baselineName;
result.receiverMode = protocol.receiverMode;
result.structuralResultPath = structural.reportPath;
result.records = records;
result.crossScaleMatchedStaticGatePassed = ...
    all([records.matchedStaticGatePassed]);
result.fullEpisodeTrackingAuthorized = ...
    result.crossScaleMatchedStaticGatePassed && ...
    protocol.fullEpisodeTrackingAuthorized;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_HEADROOM_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_HEADROOM_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V95 four-arm matched-static result: %s\n', reportPath);
end

function structural = loadStructuralGate(protocol)
path = fullfile(protocol.structuralOutputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_STRUCTURAL_RESULT.mat');
if exist(path, 'file') ~= 2
    error('NetworkBudgetV95:MissingStructuralGate', ...
        'Run the V95 structural gate before opening tracking outcomes.');
end
loaded = load(path, 'result');
if ~isfield(loaded, 'result') || ...
        ~isstruct(loaded.result) || ...
        ~isfield(loaded.result, 'protocol') || ...
        ~strcmp(loaded.result.protocol.id, protocol.id)
    error('NetworkBudgetV95:StructuralGateDrift', ...
        'The saved V95 structural result does not match the protocol.');
end
structural = loaded.result;
end

function value = summarizeCase( ...
        screen, screenReportPath, entry, protocol, sequences)
indices = zeros(1, size(sequences, 1));
for armIdx = 1:size(sequences, 1)
    match = all(bsxfun(@eq, ...
        screen.actionSequenceIndices, sequences(armIdx, :)), 2);
    if nnz(match) ~= 1
        error('NetworkBudgetV95:ArmSequenceDrift', ...
            'The V95 screen did not execute every frozen arm once.');
    end
    indices(armIdx) = find(match, 1);
end
static = screen.records(indices(1));
donorOnly = screen.records(indices(2));
candidate = screen.records(indices(3));
fixedCandidate = screen.records(indices(4));
gainOverFixed = relativeGainPercent( ...
    fixedCandidate.meanEospa, candidate.meanEospa);
gainOverDonorOnly = relativeGainPercent( ...
    donorOnly.meanEospa, candidate.meanEospa);
bank = screen.bank;
gate = bank.structuralGatePassed && ...
    bank.senderMessageParityPassed && ...
    bank.networkMessageParityPassed && ...
    candidate.meanGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    gainOverFixed >= protocol.minimumMeanGainPercent - 1e-12 && ...
    gainOverDonorOnly > ...
        protocol.minimumTransportGainOverDonorOnlyPercent + 1e-12 && ...
    candidate.worstGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    candidate.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    candidate.consensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    candidate.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    candidate.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    candidate.selectedB3Passed && fixedCandidate.selectedB3Passed;

value = emptyRecord();
value.scaleName = entry.scaleName;
value.presetName = entry.presetName;
value.seed = entry.seed;
value.currentTime = entry.currentTime;
value.horizonSteps = entry.horizonSteps;
value.staticMeanEospa = static.meanEospa;
value.donorOnlyMeanEospa = donorOnly.meanEospa;
value.candidateMeanEospa = candidate.meanEospa;
value.fixedCandidateMeanEospa = fixedCandidate.meanEospa;
value.meanGainOverStaticPercent = candidate.meanGainPercent;
value.meanGainOverFixedPercent = gainOverFixed;
value.meanGainOverDonorOnlyPercent = gainOverDonorOnly;
value.worstSensorGainPercent = candidate.worstGainPercent;
value.minimumFormationGainPercent = ...
    candidate.minimumFormationGainPercent;
value.windowConsensusGainPercent = candidate.consensusGainPercent;
value.terminalConsensusGainPercent = ...
    candidate.terminalConsensusGainPercent;
value.attemptedByteSavingPercent = ...
    candidate.attemptedByteSavingPercent;
value.selectedTokenCount = bank.selectedTokenCount;
value.requiredTokenCount = bank.requiredTokenCount;
value.senderMessageParityPassed = bank.senderMessageParityPassed;
value.networkMessageParityPassed = bank.networkMessageParityPassed;
value.matchedStaticGatePassed = gate;
value.screenReportPath = screenReportPath;
end

function sequences = buildFourArmSequences(horizonSteps)
reference = ones(1, horizonSteps);
donorOnly = reference;
candidate = reference;
donorOnly(1) = 2;
candidate(1) = 3;
fixedCandidate = 3 * ones(1, horizonSteps);
sequences = [reference; donorOnly; candidate; fixedCandidate];
end

function gain = relativeGainPercent(reference, candidate)
gain = 100 * (reference - candidate) / max(abs(reference), eps);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkBudgetV95:WriteFailed', ...
        'Could not create the V95 matched-static report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V95 four-arm matched-static headroom\n\n');
fprintf(fid, '- Baseline: `%s`\n', result.baselineName);
fprintf(fid, '- Receiver semantics: `%s`\n', result.receiverMode);
fprintf(fid, ['- Pairing: identical cached posterior, measurements, ', ...
    'link uniforms, filter RNG and horizon.\n\n']);
fprintf(fid, ['| Scale | H | Static | Donor only | Dynamic | Fixed ', ...
    'reallocation | Gain/static | Gain/fixed | Gain/donor | Worst ', ...
    'sensor | Min formation | Consensus | Bytes | Pass |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|:--:|\n']);
for record = result.records
    fprintf(fid, ['| %s | %d | %.6f | %.6f | %.6f | %.6f | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d |\n'], ...
        record.scaleName, record.horizonSteps, ...
        record.staticMeanEospa, record.donorOnlyMeanEospa, ...
        record.candidateMeanEospa, ...
        record.fixedCandidateMeanEospa, ...
        record.meanGainOverStaticPercent, ...
        record.meanGainOverFixedPercent, ...
        record.meanGainOverDonorOnlyPercent, ...
        record.worstSensorGainPercent, ...
        record.minimumFormationGainPercent, ...
        record.windowConsensusGainPercent, ...
        record.attemptedByteSavingPercent, ...
        record.matchedStaticGatePassed);
end
fprintf(fid, '\n- Cross-scale matched-static gate: `%d`\n', ...
    result.crossScaleMatchedStaticGatePassed);
fprintf(fid, '- Full-episode tracking authorized: `%d`\n\n', ...
    result.fullEpisodeTrackingAuthorized);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'horizonSteps', NaN, ...
    'staticMeanEospa', NaN, 'donorOnlyMeanEospa', NaN, ...
    'candidateMeanEospa', NaN, ...
    'fixedCandidateMeanEospa', NaN, ...
    'meanGainOverStaticPercent', NaN, ...
    'meanGainOverFixedPercent', NaN, ...
    'meanGainOverDonorOnlyPercent', NaN, ...
    'worstSensorGainPercent', NaN, ...
    'minimumFormationGainPercent', NaN, ...
    'windowConsensusGainPercent', NaN, ...
    'terminalConsensusGainPercent', NaN, ...
    'attemptedByteSavingPercent', NaN, ...
    'selectedTokenCount', 0, 'requiredTokenCount', 0, ...
    'senderMessageParityPassed', false, ...
    'networkMessageParityPassed', false, ...
    'matchedStaticGatePassed', false, 'screenReportPath', '');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
