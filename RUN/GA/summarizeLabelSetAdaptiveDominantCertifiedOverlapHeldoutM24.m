function [reportPath, validation] = ...
    summarizeLabelSetAdaptiveDominantCertifiedOverlapHeldoutM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTCERTIFIEDOVERLAPHELDOUTM24
% Evaluate the preregistered one-shot M24 held-out gate for frozen v4.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantCertifiedOverlapHeldoutM24Authorized || ...
        ~protocol.adaptiveDominantCertifiedOverlapHeldoutM24OneShot || ...
        protocol.adaptiveDominantCertifiedOverlapHeldoutM24ValidationClaimAllowed || ...
        protocol.adaptiveDominantCertifiedOverlapX36Authorized
    error('Certified-overlap one-shot M24 held-out gate is not authorized.');
end

seeds = protocol.adaptiveDominantCertifiedOverlapHeldoutM24Seeds;
rootDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantCertifiedOverlapSelectedMarginToken), ...
    'heldout'));
rows = repmat(emptyRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    evidencePath = findSingleEvidence(rootDirectory, seed);
    loaded = load(evidencePath, 'summary');
    summary = loaded.summary;
    validateSummary(summary, seed, protocol);
    baseline = findArm(summary.aggregate, protocol. ...
        adaptiveDominantFullWindowReferenceArmName);
    candidate = findArm(summary.aggregate, protocol. ...
        adaptiveDominantCertifiedOverlapSelectedArmName);
    row = emptyRow();
    row.seed = seed;
    row.runCommit = summary.generationGitCommit;
    row.evidencePath = evidencePath;
    row.baselineEospa = baseline.focusEospa;
    row.candidateEospa = candidate.focusEospa;
    row.gainPercent = relativeGain( ...
        row.baselineEospa, row.candidateEospa);
    row.baselineWorstEospa = baseline.focusWorstSensorEospa;
    row.candidateWorstEospa = candidate.focusWorstSensorEospa;
    row.baselineConsensusOspa = baseline.focusMapSetDisagreement;
    row.candidateConsensusOspa = candidate.focusMapSetDisagreement;
    row.baselineAttemptedBytes = baseline.focusAttemptedBytes;
    row.candidateAttemptedBytes = candidate.focusAttemptedBytes;
    row.byteDeltaPercent = 100 * ...
        (row.candidateAttemptedBytes - row.baselineAttemptedBytes) / ...
            max(row.baselineAttemptedBytes, eps);
    row.meanMessageCount = candidate.meanDirectedMessageCount;
    row.selectedSensorB3 = candidate. ...
        focusSelectedRollingB3SensorStrongFraction;
    row.selectedFormationB3 = candidate. ...
        focusSelectedRollingB3FormationStrongFraction;
    row.deliveredSensorB3 = candidate. ...
        focusDeliveredRollingB3SensorStrongFraction;
    row.truthUseFraction = candidate.policyTruthUseFraction;
    row.posteriorUseFraction = ...
        candidate.policyPosteriorContentUseFraction;
    row.payloadMetadataUseFraction = candidate. ...
        policyPosteriorPayloadMetadataUseFraction;
    row.currentLinkReliabilityUseFraction = candidate. ...
        policyCurrentLinkReliabilityUseFraction;
    row.payloadConstraintFraction = candidate. ...
        policyPayloadConstraintEnforcedFraction;
    row.payloadLimitPassFraction = candidate. ...
        policyPayloadLimitPassFraction;
    row.repairRate = candidate.policyRepairRate;
    row.payloadEmergencyRate = candidate.policyPayloadEmergencyRate;
    row.topologyInfeasibleRate = candidate.focusTopologyInfeasibleRate;
    row.distinctRouteMaps = ...
        candidate.focusDistinctDirectedRouteMapCount;
    row.hardSafetyPassed = hardSafetyPassed(row, protocol);
    rows(seedIdx) = row;
end

runCommits = unique({rows.runCommit}, 'stable');
if numel(runCommits) ~= 1
    error('Held-out M24 seeds were not run from one frozen commit.');
end
baselineMean = mean([rows.baselineEospa]);
candidateMean = mean([rows.candidateEospa]);
meanGain = relativeGain(baselineMean, candidateMean);
positiveFraction = mean([rows.gainPercent] > 0);
worstGain = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
consensusGain = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
baselineBytes = sum([rows.baselineAttemptedBytes]);
candidateBytes = sum([rows.candidateAttemptedBytes]);
aggregateByteSaving = 100 * ...
    (baselineBytes - candidateBytes) / max(baselineBytes, eps);
maximumPositiveByteDelta = max([0, [rows.byteDeltaPercent]]);
hardSafetyPassedAll = all([rows.hardSafetyPassed]);
trackingGatePassed = ...
    meanGain >= protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MinimumMeanGainPercent && ...
    positiveFraction >= protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MinimumPositiveSeedFraction;
tailGatePassed = ...
    (~protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24RequireNoAggregateWorstRegression || ...
        worstGain >= -1e-12) && ...
    (~protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24RequireNoAggregateConsensusRegression || ...
        consensusGain >= -1e-12);
communicationGatePassed = ...
    aggregateByteSaving >= protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MinimumByteSavingPercent && ...
    maximumPositiveByteDelta <= protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MaximumPositiveByteDeltaPercent + ...
            1e-12;
heldoutGatePassed = hardSafetyPassedAll && trackingGatePassed && ...
    tailGatePassed && communicationGatePassed;

gitState = resolveResearchGitState();
validation = struct();
validation.protocolId = protocol.id;
validation.contractVersion = protocol. ...
    adaptiveDominantCertifiedOverlapHeldoutM24ContractVersion;
validation.generatedAt = datestr(now, 31);
validation.generationGitCommit = gitState.commit;
validation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
validation.runGenerationGitCommit = runCommits{1};
validation.seeds = seeds;
validation.times = ...
    protocol.adaptiveDominantPayloadAwareScreenTimes;
validation.selectedMarginToken = protocol. ...
    adaptiveDominantCertifiedOverlapSelectedMarginToken;
validation.selectedMarginFraction = protocol. ...
    adaptiveDominantCertifiedOverlapSelectedMarginFraction;
validation.rows = rows;
validation.baselineMeanEospa = baselineMean;
validation.candidateMeanEospa = candidateMean;
validation.meanGainPercent = meanGain;
validation.positiveSeedFraction = positiveFraction;
validation.aggregateWorstGainPercent = worstGain;
validation.aggregateConsensusGainPercent = consensusGain;
validation.aggregateByteSavingPercent = aggregateByteSaving;
validation.maximumPositiveByteDeltaPercent = maximumPositiveByteDelta;
validation.hardSafetyPassed = hardSafetyPassedAll;
validation.trackingGatePassed = trackingGatePassed;
validation.tailGatePassed = tailGatePassed;
validation.communicationGatePassed = communicationGatePassed;
validation.heldoutGatePassed = heldoutGatePassed;
validation.allSeedsPreviouslyUnopened = true;
validation.oneShotProtocolRespected = true;
validation.validationClaimAllowed = heldoutGatePassed;
validation.heldoutM24Opened = true;
validation.x36Opened = false;
if heldoutGatePassed
    validation.nextDirection = ...
        'freeze-heldout-M24-evidence-and-preregister-X36-scale-validation';
else
    validation.nextDirection = ...
        'stop-without-opening-X36-or-retuning-on-heldout-results';
end
validation.evidenceBoundary = [ ...
    'These five M24 seeds were locked before v4 method selection and ', ...
    'were opened once only after the candidate, margin and gates were ', ...
    'frozen. The evidence is a paired conditional continuation over ', ...
    't=75:83 from a common cached prefix, not a full-episode estimate. ', ...
    'X36 remains unopened in this report.'];

outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    rootDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_CERTIFIED_OVERLAP_HELDOUT_M24_V4.md');
writeReport(reportPath, validation, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
validation.reportPath = reportPath;
validation.matPath = matPath;
fprintf('Certified-overlap held-out M24 summary: %s\n', reportPath);
end

function path = findSingleEvidence(rootDirectory, seed)
matches = dir(fullfile(rootDirectory, ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one held-out M24 MAT for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function validateSummary(summary, seed, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'heldout-validation') || ...
        summary.options.filterSeedOffset ~= protocol.filterSeedOffset || ...
        summary.options.continuationStartTime ~= protocol. ...
            adaptiveDominantPayloadAwareScreenTimes(1) || ...
        summary.options.maxTimeSteps ~= protocol. ...
            adaptiveDominantPayloadAwareScreenTimes(end) || ...
        ~any(strcmp({summary.aggregate.mode}, protocol. ...
            adaptiveDominantFullWindowReferenceArmName)) || ...
        ~any(strcmp({summary.aggregate.mode}, protocol. ...
            adaptiveDominantCertifiedOverlapSelectedArmName)) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Certified-overlap held-out M24 provenance contract failed.');
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Held-out M24 evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    row.meanMessageCount >= protocol. ...
        adaptiveDominantCertifiedOverlapMinimumMessageCount && ...
    row.meanMessageCount <= protocol. ...
        adaptiveDominantCertifiedOverlapMaximumMessageCount && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.payloadMetadataUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.payloadConstraintFraction == 1 && ...
    row.payloadLimitPassFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, 'runCommit', '', 'evidencePath', '', ...
    'baselineEospa', NaN, 'candidateEospa', NaN, ...
    'gainPercent', NaN, ...
    'baselineWorstEospa', NaN, 'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, 'candidateConsensusOspa', NaN, ...
    'baselineAttemptedBytes', NaN, 'candidateAttemptedBytes', NaN, ...
    'byteDeltaPercent', NaN, 'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, 'selectedFormationB3', NaN, ...
    'deliveredSensorB3', NaN, 'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'payloadMetadataUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'payloadConstraintFraction', NaN, ...
    'payloadLimitPassFraction', NaN, ...
    'repairRate', NaN, 'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, 'distinctRouteMaps', NaN, ...
    'hardSafetyPassed', false);
end

function writeReport(path, validation, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Unable to write certified-overlap held-out M24 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 certified-overlap one-shot held-out validation\n\n');
fprintf(fid, '- Contract: `%s`\n', validation.contractVersion);
fprintf(fid, '- Generated: %s\n', validation.generatedAt);
fprintf(fid, '- Run commit: `%s`\n', ...
    validation.runGenerationGitCommit);
fprintf(fid, '- Margin: `%.1f%%`\n', ...
    100 * validation.selectedMarginFraction);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seeds));
fprintf(fid, '- Window: `%s`\n\n', mat2str(validation.times));
fprintf(fid, ['| Seed | CCW E-OSPA | Candidate E-OSPA | Gain | ', ...
    'Byte delta | Msgs | Maps | Safe |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for row = validation.rows
    fprintf(fid, ...
        '| %d | %.6f | %.6f | %+.3f%% | %+.3f%% | %.2f | %.0f | %d |\n', ...
        row.seed, row.baselineEospa, row.candidateEospa, ...
        row.gainPercent, row.byteDeltaPercent, ...
        row.meanMessageCount, row.distinctRouteMaps, ...
        row.hardSafetyPassed);
end
fprintf(fid, '\n## Preregistered held-out gate\n\n');
fprintf(fid, '- Mean E-OSPA gain: `%+.3f%%`\n', ...
    validation.meanGainPercent);
fprintf(fid, '- Positive-seed fraction: `%.3f`\n', ...
    validation.positiveSeedFraction);
fprintf(fid, '- Aggregate worst-node gain: `%+.3f%%`\n', ...
    validation.aggregateWorstGainPercent);
fprintf(fid, '- Aggregate consensus gain: `%+.3f%%`\n', ...
    validation.aggregateConsensusGainPercent);
fprintf(fid, '- Aggregate attempted-byte saving: `%+.3f%%`\n', ...
    validation.aggregateByteSavingPercent);
fprintf(fid, '- Maximum positive byte delta: `%+.3f%%`\n', ...
    validation.maximumPositiveByteDeltaPercent);
fprintf(fid, '- Required minimum mean gain: `%.3f%%`\n', ...
    protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MinimumMeanGainPercent);
fprintf(fid, '- Required positive-seed fraction: `%.3f`\n', ...
    protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MinimumPositiveSeedFraction);
fprintf(fid, '- Required minimum byte saving: `%.3f%%`\n', ...
    protocol. ...
        adaptiveDominantCertifiedOverlapHeldoutM24MinimumByteSavingPercent);
fprintf(fid, '- Hard safety passed: `%d`\n', ...
    validation.hardSafetyPassed);
fprintf(fid, '- Tracking gate passed: `%d`\n', ...
    validation.trackingGatePassed);
fprintf(fid, '- Tail gate passed: `%d`\n', ...
    validation.tailGatePassed);
fprintf(fid, '- Communication gate passed: `%d`\n', ...
    validation.communicationGatePassed);
fprintf(fid, '- Held-out gate passed: `%d`\n', ...
    validation.heldoutGatePassed);
fprintf(fid, '- Fresh M24 validation claim allowed: `%d`\n', ...
    validation.validationClaimAllowed);
fprintf(fid, '- Next: `%s`\n\n', validation.nextDirection);
fprintf(fid, '%s\n', validation.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
