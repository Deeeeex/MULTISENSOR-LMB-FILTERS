function [reportPath, audit] = ...
    auditPrivilegedRollingSafeValueTargetDataset(options)
% AUDITPRIVILEGEDROLLINGSAFEVALUETARGETDATASET Formal M24 target audit.
%
% Replays the exact join between truth-free state features, privileged safe
% graphs and design-seen H=3 return labels. This audit authorizes only
% proposal-model development; it cannot turn offline labels into validation.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
datasetPath = getField(options, 'datasetPath', ...
    protocol.privilegedValueTargetDatasetRelativePath);
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
proposalPath = getField(options, 'proposalDatasetPath', ...
    protocol.privilegedProposalDatasetRelativePath);
returnAuditPath = getField(options, 'returnAuditPath', ...
    protocol.privilegedReturnV2AuditRelativePath);
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'PRIVILEGED_VALUE_TARGET_DATASET_PREFLIGHT_M24.md'));
auditPath = getField(options, 'auditPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'privileged_value_target_dataset_preflight_m24.mat'));

validateFrozenFile(datasetPath, ...
    protocol.privilegedValueTargetDatasetSha256, ...
    'value-target dataset');
validateFrozenFile(sourcePath, ...
    protocol.proposalSourceStateSha256, 'source state');
validateFrozenFile(proposalPath, ...
    protocol.privilegedProposalDatasetSha256, ...
    'privileged proposal dataset');
validateFrozenFile(returnAuditPath, ...
    protocol.privilegedReturnV2AuditSha256, ...
    'privileged v2 return audit');
datasetLoaded = load(datasetPath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
proposalLoaded = load(proposalPath, 'dataset');
returnLoaded = load(returnAuditPath, 'audit');
if ~isfield(datasetLoaded, 'dataset') || ...
        ~isfield(sourceLoaded, 'dataset') || ...
        ~isfield(proposalLoaded, 'dataset') || ...
        ~isfield(returnLoaded, 'audit')
    error('A value-target audit input lacks its expected payload.');
end
dataset = datasetLoaded.dataset;
source = sourceLoaded.dataset;
proposal = proposalLoaded.dataset;
returnAudit = returnLoaded.audit;
validateEnvelope( ...
    dataset, source, proposal, returnAudit, protocol);

expectedPairs = frozenSeedTimePairs(protocol);
observedPairs = [[dataset.blocks.seed]', ...
    [dataset.blocks.currentTime]'];
if ~isequal(observedPairs, expectedPairs)
    error('Value-target blocks do not follow the frozen grid.');
end

maximumEdgeFeatureReplayDifference = 0;
maximumJointFeatureReplayDifference = 0;
totalCandidateCount = 0;
totalTargetCount = 0;
targetStateCount = 0;
privilegedBehaviorStateCount = 0;
targetActionCodes = [];
blockRows = repmat(struct( ...
    'seed', NaN, 'currentTime', NaN, ...
    'candidateCount', NaN, 'v2FeasibleCount', NaN, ...
    'valueTargetCount', NaN, 'valueOracleActionCode', NaN, ...
    'valueOracleGainFraction', NaN), ...
    1, numel(dataset.blocks));
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    sourceBlock = source.blocks(block.sourceBlockIndex);
    proposalBlock = proposal.blocks( ...
        block.privilegedProposalBlockIndex);
    stateRow = findStateRow(returnAudit.stateRows, ...
        block.seed, block.currentTime);
    candidateRows = findCandidateRows( ...
        returnAudit.candidateRows, ...
        block.seed, block.currentTime);
    [~, order] = sort([candidateRows.candidateIndex]);
    candidateRows = candidateRows(order);

    validateBlockIdentity(block, sourceBlock, proposalBlock);
    privilegedBehaviorStateCount = privilegedBehaviorStateCount + ...
        double(sourceBlock.actionTruthUsed || ...
            sourceBlock.labelTruthUsed);
    maximumEdgeFeatureReplayDifference = max( ...
        maximumEdgeFeatureReplayDifference, ...
        maximumAbsoluteDifference( ...
            block.edgeFeatures, sourceBlock.features));
    maximumJointFeatureReplayDifference = max( ...
        maximumJointFeatureReplayDifference, ...
        maximumAbsoluteDifference( ...
            block.candidateJointFeatures, ...
            proposalBlock.jointFeatures));
    validateCandidateGraphReplay(block, proposalBlock);
    validateReturnReplay(block, stateRow, candidateRows);

    expectedTargetMask = logical( ...
        [candidateRows.repairMonitoredAdmissibleFivePercentGain]);
    expectedV2Feasible = logical( ...
        [candidateRows.repairMonitoredFeasible]);
    expectedHardFeasible = logical( ...
        [candidateRows.hardFeasible]);
    expectedHardTargets = logical( ...
        [candidateRows.admissibleFivePercentGain]);
    if ~isequal(block.candidateV2ValueTarget, ...
            expectedTargetMask) || ...
            ~isequal(block.candidateV2Feasible, ...
                expectedV2Feasible) || ...
            ~isequal(block.candidateHardFeasible, ...
                expectedHardFeasible) || ...
            ~isequal(block.candidateHardValueTarget, ...
                expectedHardTargets) || ...
            block.valueTargetCount ~= ...
                nnz(expectedTargetMask) || ...
            ~isequal(block.valueTargetCandidateIndices, ...
                find(expectedTargetMask)) || ...
            ~isequal(block.valueTargetCrossMasks, ...
                block.candidateCrossMasks(:, expectedTargetMask))
        error('Value-target masks do not replay from returns.');
    end
    if any(expectedTargetMask & ...
            (~expectedV2Feasible | ...
             [candidateRows.gainFraction] < ...
                protocol.minimumPrivilegedAdmissibleGain | ...
             ~[candidateRows.tailNondegrading] | ...
             [candidateRows.firstActionRepair] | ...
             ~[candidateRows.selectedRollingB3Passed] | ...
             [candidateRows.payloadEmergencyCount] > 0 | ...
             [candidateRows.infeasibleCount] > 0))
        error('A value target violates a frozen v2 gate.');
    end
    validateValueOracle(block, candidateRows, expectedTargetMask);
    if block.valueTargetCount > 0
        targetStateCount = targetStateCount + 1;
        targetActionCodes = [targetActionCodes, ...
            block.candidateActionCodes(expectedTargetMask)]; %#ok<AGROW>
    end
    totalCandidateCount = ...
        totalCandidateCount + block.candidateCount;
    totalTargetCount = ...
        totalTargetCount + block.valueTargetCount;
    blockRows(blockIdx) = struct( ...
        'seed', block.seed, ...
        'currentTime', block.currentTime, ...
        'candidateCount', block.candidateCount, ...
        'v2FeasibleCount', nnz(expectedV2Feasible), ...
        'valueTargetCount', block.valueTargetCount, ...
        'valueOracleActionCode', ...
            block.valueOracleActionCode, ...
        'valueOracleGainFraction', ...
            block.v2OracleGainFraction);
end

actionCodes = unique([proposal.blocks.candidateActionCodes]);
targetCountByActionCode = zeros(size(actionCodes));
for actionIdx = 1:numel(actionCodes)
    targetCountByActionCode(actionIdx) = ...
        nnz(targetActionCodes == actionCodes(actionIdx));
end
accepted = ...
    maximumEdgeFeatureReplayDifference <= 1e-12 && ...
    maximumJointFeatureReplayDifference <= 1e-12 && ...
    totalCandidateCount == ...
        protocol.privilegedProposalExpectedTargetCount && ...
    targetStateCount == ...
        protocol.privilegedReturnV2ExpectedTargetStateCount && ...
    totalTargetCount == ...
        protocol.privilegedReturnV2ExpectedValueTargetCount;
if ~accepted
    error('Value-target preflight failed frozen gates.');
end

gitState = resolveResearchGitState();
audit = struct();
audit.protocolId = protocol.id;
audit.contractVersion = ...
    protocol.privilegedValueTargetAuditContractVersion;
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.datasetPath = datasetPath;
audit.datasetSha256 = ...
    protocol.privilegedValueTargetDatasetSha256;
audit.datasetGenerationCommit = ...
    dataset.generationGitCommit;
audit.sourceStateSha256 = dataset.sourceStateSha256;
audit.privilegedProposalDatasetSha256 = ...
    dataset.privilegedProposalDatasetSha256;
audit.returnAuditSha256 = dataset.returnAuditSha256;
audit.blockCount = numel(dataset.blocks);
audit.totalCandidateCount = totalCandidateCount;
audit.targetStateCount = targetStateCount;
audit.totalValueTargetCount = totalTargetCount;
audit.privilegedBehaviorStateCount = ...
    privilegedBehaviorStateCount;
audit.targetActionCodes = actionCodes;
audit.targetCountByActionCode = ...
    targetCountByActionCode;
audit.maximumEdgeFeatureReplayDifference = ...
    maximumEdgeFeatureReplayDifference;
audit.maximumJointFeatureReplayDifference = ...
    maximumJointFeatureReplayDifference;
audit.blockRows = blockRows;
audit.truthFreeFeatureComputationReplayed = true;
audit.privilegedStateCollectionBehaviorConfirmed = ...
    privilegedBehaviorStateCount == numel(dataset.blocks);
audit.offlineTruthLabelUseConfirmed = true;
audit.futureOutcomeLabelUseConfirmed = true;
audit.designSeenConfirmed = true;
audit.acceptedForProposalModelDevelopment = accepted;
audit.acceptedForTopKCaptureClaim = false;
audit.acceptedForCriticTraining = false;
audit.acceptedForValidation = false;
audit.acceptedForX36 = false;
audit.evidenceBoundary = [ ...
    'PASS establishes an exact, provenance-frozen join between ', ...
    'edge features computed without truth/future outcomes and ', ...
    'offline truth/future-return labels. The state histories were ', ...
    'collected under outcome-selected privileged safe behavior, ', ...
    'so even seed-disjoint resampling of these 18 states is method ', ...
    'development rather than online generalization. A fresh ', ...
    'truth-free rollout distribution must establish top-K capture ', ...
    'before critic training, M24 validation or X36 transfer.'];
audit.reportPath = reportPath;
audit.auditPath = auditPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit, protocol);
fprintf(['Value-target preflight: %d/%d target graphs in ', ...
    '%d/%d states; edge replay %.3g; joint replay %.3g.\n', ...
    'Report: %s\nAudit: %s\n'], ...
    totalTargetCount, totalCandidateCount, targetStateCount, ...
    numel(dataset.blocks), maximumEdgeFeatureReplayDifference, ...
    maximumJointFeatureReplayDifference, reportPath, auditPath);
end

function validateEnvelope( ...
        dataset, source, proposal, returnAudit, protocol)
if ~strcmp(dataset.contractVersion, ...
        protocol.privilegedValueTargetDatasetContractVersion) || ...
        ~strcmp(dataset.generationGitCommit, ...
            protocol.privilegedValueTargetDatasetGenerationCommit) || ...
        dataset.generationTrackedWorktreeDirty || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        ~strcmp(dataset.sourceStateSha256, ...
            protocol.proposalSourceStateSha256) || ...
        ~strcmp(dataset.privilegedProposalDatasetSha256, ...
            protocol.privilegedProposalDatasetSha256) || ...
        ~strcmp(dataset.returnAuditSha256, ...
            protocol.privilegedReturnV2AuditSha256) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(dataset.snapshotTimes, protocol.snapshotTimes) || ...
        ~dataset.truthUsed || ~dataset.futureOutcomeUsed || ...
        dataset.deployable || ~dataset.designSeen || ...
        dataset.proposalModelTrained || ...
        dataset.topKCaptureEvaluated || ...
        dataset.criticTrainingAuthorized || ...
        dataset.x36Authorized || ...
        ~strcmp(source.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~strcmp(proposal.contractVersion, ...
            protocol.privilegedProposalDatasetContractVersion) || ...
        ~strcmp(returnAudit.contractVersion, ...
            protocol.privilegedReturnV2AuditContractVersion) || ...
        ~returnAudit.valueFilteredProposalDistillationAuthorized || ...
        returnAudit.validationClaimAllowed
    error('Value-target dataset envelope violates the protocol.');
end
end

function validateBlockIdentity(block, sourceBlock, proposalBlock)
if block.seed ~= sourceBlock.seed || ...
        block.currentTime ~= sourceBlock.currentTime || ...
        block.seed ~= proposalBlock.seed || ...
        block.currentTime ~= proposalBlock.currentTime || ...
        ~isequal(block.edgeFeatureNames, ...
            sourceBlock.featureNames) || ...
        ~isequal(block.receiverIndices, ...
            sourceBlock.receiverIndices) || ...
        ~isequal(block.senderIndices, sourceBlock.senderIndices) || ...
        ~isequal(block.groupIds, sourceBlock.groupIds) || ...
        ~isequal(block.physicalAdjacency, ...
            sourceBlock.physicalAdjacency) || ...
        ~isequal(block.previousAdjacencyHistory, ...
            sourceBlock.previousAdjacencyHistory) || ...
        ~isequal(block.previousAdjacencyHistoryTimes, ...
            sourceBlock.previousAdjacencyHistoryTimes) || ...
        sourceBlock.featureMetadata.truthUsed || ...
        sourceBlock.featureMetadata.groundTruthUsed || ...
        sourceBlock.featureMetadata.futureOutcomeUsed || ...
        block.candidateCount ~= proposalBlock.candidateCount
    error('Value-target state or truth-free input replay failed.');
end
end

function validateCandidateGraphReplay(block, proposalBlock)
if ~isequal(block.candidateActionCodes, ...
        proposalBlock.candidateActionCodes) || ...
        ~isequal(block.candidateGraphSha256, ...
            proposalBlock.candidateGraphSha256) || ...
        ~isequal(block.candidateAdjacency, ...
            proposalBlock.candidateAdjacency) || ...
        ~isequal(block.candidateCrossMasks, ...
            proposalBlock.candidateCrossMasks)
    error('Value-target privileged graph replay failed.');
end
end

function validateReturnReplay(block, stateRow, candidateRows)
if numel(candidateRows) ~= block.candidateCount || ...
        ~isequal([candidateRows.candidateIndex], ...
            1:block.candidateCount) || ...
        ~isequal([candidateRows.actionCode], ...
            block.candidateActionCodes) || ...
        ~isequal({candidateRows.graphSha256}, ...
            block.candidateGraphSha256) || ...
        ~isequal(block.candidateMeanEospa, ...
            [candidateRows.meanEospa]) || ...
        ~isequal(block.candidateWorstSensorEospa, ...
            [candidateRows.worstSensorEospa]) || ...
        ~isequal(block.candidateAttemptedBytes, ...
            [candidateRows.attemptedBytes]) || ...
        ~isequal(block.candidateDeliveredBytes, ...
            [candidateRows.deliveredBytes]) || ...
        ~isequal(block.candidateGainFraction, ...
            [candidateRows.gainFraction]) || ...
        ~isequal( ...
            block.candidateAttemptedByteDeviationFraction, ...
            [candidateRows.attemptedByteDeviationFraction]) || ...
        ~isequal(block.candidateTailNondegrading, ...
            logical([candidateRows.tailNondegrading])) || ...
        ~isequal(block.candidateAdditionalRepairCount, ...
            [candidateRows.additionalRepairCount]) || ...
        ~isequal(block.candidateFirstActionRepair, ...
            logical([candidateRows.firstActionRepair])) || ...
        ~isequal(block.candidatePayloadEmergencyCount, ...
            [candidateRows.payloadEmergencyCount]) || ...
        ~isequal(block.candidateInfeasibleCount, ...
            [candidateRows.infeasibleCount]) || ...
        ~isequal( ...
            block.candidateSelectedRollingB3Passed, ...
            logical([candidateRows.selectedRollingB3Passed])) || ...
        ~isequal( ...
            block.candidateDeliveredRollingB3Passed, ...
            logical([candidateRows.deliveredRollingB3Passed])) || ...
        block.referenceMeanEospa ~= ...
            stateRow.referenceMeanEospa || ...
        block.referenceWorstSensorEospa ~= ...
            stateRow.referenceWorstSensorEospa || ...
        block.referenceAttemptedBytes ~= ...
            stateRow.referenceAttemptedBytes || ...
        block.referenceDeliveredBytes ~= ...
            stateRow.referenceDeliveredBytes || ...
        block.v2OracleCandidateIndex ~= ...
            stateRow.repairMonitoredOracleCandidateIndex || ...
        block.v2OracleActionCode ~= ...
            stateRow.repairMonitoredOracleActionCode || ...
        block.v2OracleMeanEospa ~= ...
            stateRow.repairMonitoredOracleMeanEospa || ...
        block.v2OracleGainFraction ~= ...
            stateRow.repairMonitoredOracleGainFraction
    error('Value-target return labels do not replay exactly.');
end
end

function validateValueOracle(block, candidateRows, targetMask)
targetIndices = find(targetMask);
if isempty(targetIndices)
    if ~isnan(block.valueOracleCandidateIndex) || ...
            ~isnan(block.valueOracleActionCode) || ...
            ~isempty(block.valueOracleGraphSha256)
        error('Target-free state has a value-oracle witness.');
    end
    return
end
[~, localBest] = min( ...
    [candidateRows(targetIndices).meanEospa]);
expectedIndex = targetIndices(localBest);
if block.valueOracleCandidateIndex ~= expectedIndex || ...
        block.valueOracleActionCode ~= ...
            block.candidateActionCodes(expectedIndex) || ...
        ~strcmp(block.valueOracleGraphSha256, ...
            block.candidateGraphSha256{expectedIndex})
    error('Value-oracle witness is inconsistent.');
end
end

function row = findStateRow(rows, seed, currentTime)
indices = find([rows.seed] == seed & ...
    [rows.currentTime] == currentTime);
if numel(indices) ~= 1
    error('Return audit lacks a unique state row.');
end
row = rows(indices);
end

function rows = findCandidateRows(rows, seed, currentTime)
indices = find([rows.seed] == seed & ...
    [rows.currentTime] == currentTime);
rows = rows(indices);
if isempty(rows)
    error('Return audit lacks candidate rows.');
end
end

function pairs = frozenSeedTimePairs(protocol)
pairs = zeros(numel(protocol.datasetSeeds) * ...
    numel(protocol.snapshotTimes), 2);
cursor = 0;
for seed = protocol.datasetSeeds
    for currentTime = protocol.snapshotTimes
        cursor = cursor + 1;
        pairs(cursor, :) = [seed, currentTime];
    end
end
end

function difference = maximumAbsoluteDifference(left, right)
if ~isequal(size(left), size(right))
    error('Replay arrays have different dimensions.');
end
if isempty(left)
    difference = 0;
else
    difference = max(abs(double(left(:)) - double(right(:))));
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function writeReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open value-target audit report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# Privileged value-target dataset preflight: M24\n\n');
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Audit contract: `%s`\n', ...
    audit.contractVersion);
fprintf(fid, '- Dataset SHA-256: `%s`\n', ...
    audit.datasetSha256);
fprintf(fid, '- Dataset generation commit: `%s`\n', ...
    audit.datasetGenerationCommit);
fprintf(fid, '- Candidate graphs: `%d`\n', ...
    audit.totalCandidateCount);
fprintf(fid, '- Value-filtered targets: `%d`\n', ...
    audit.totalValueTargetCount);
fprintf(fid, '- Target-bearing states: `%d / %d`\n', ...
    audit.targetStateCount, audit.blockCount);
fprintf(fid, ...
    '- States collected under privileged behavior: `%d / %d`\n', ...
    audit.privilegedBehaviorStateCount, audit.blockCount);
fprintf(fid, '- Target counts by action code: `%s`\n', ...
    formatActionCounts(audit.targetActionCodes, ...
        audit.targetCountByActionCode));
fprintf(fid, '- Maximum edge-feature replay difference: `%.12g`\n', ...
    audit.maximumEdgeFeatureReplayDifference);
fprintf(fid, '- Maximum joint-feature replay difference: `%.12g`\n', ...
    audit.maximumJointFeatureReplayDifference);
fprintf(fid, '- Accepted for proposal development: `%d`\n', ...
    audit.acceptedForProposalModelDevelopment);
fprintf(fid, '- Accepted for top-K capture claim: `%d`\n', ...
    audit.acceptedForTopKCaptureClaim);
fprintf(fid, '- Accepted for critic training: `%d`\n', ...
    audit.acceptedForCriticTraining);
fprintf(fid, '- Accepted for validation/X36: `%d / %d`\n', ...
    audit.acceptedForValidation, audit.acceptedForX36);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    audit.evidenceBoundary);
fprintf(fid, '## State blocks\n\n');
fprintf(fid, ...
    ['| Seed | Time | Candidates | V2 feasible | ', ...
     'V2 targets | Value oracle | Oracle gain |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--|--:|\n');
for row = audit.blockRows
    fprintf(fid, '| %d | %d | %d | %d | %d | `%s` | %.3f%% |\n', ...
        row.seed, row.currentTime, row.candidateCount, ...
        row.v2FeasibleCount, row.valueTargetCount, ...
        formatOptionalCode(row.valueOracleActionCode), ...
        100 * row.valueOracleGainFraction);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, ['PASS: all 70 privileged graphs and return labels ', ...
    'join exactly; 34 graphs in 10/18 states pass the frozen v2 ', ...
    'five-percent value gate. Per-edge feature computation replays ', ...
    'without truth/future inputs, but all state histories come from ', ...
    'outcome-selected privileged behavior. Multi-solution proposal-', ...
    'head development may proceed; online top-K capture remains ', ...
    'unevaluated.\n']);
end

function token = formatActionCounts(actionCodes, counts)
parts = cell(1, numel(actionCodes));
for idx = 1:numel(actionCodes)
    parts{idx} = sprintf('%02d:%d', ...
        actionCodes(idx), counts(idx));
end
token = strjoin(parts, ', ');
end

function token = formatOptionalCode(actionCode)
if isfinite(actionCode)
    token = sprintf('%02d', actionCode);
else
    token = '-';
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
