function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantPayloadAwareDevelopmentM24(seed, options)
% RUNLABELSETADAPTIVEDOMINANTPAYLOADAWAREDEVELOPMENTM24 Redesign tuning.

if nargin < 1 || isempty(seed)
    seed = 31;
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol. ...
        adaptiveDominantPayloadAwareDevelopmentEvaluationAuthorized || ...
        ~ismember(seed, ...
            protocol.adaptiveDominantPayloadAwareDevelopmentSeeds)
    error('Seed is outside payload-aware development tuning.');
end
runOptions = options;
runOptions.evidenceSplit = 'development';
[reportPath, summary] = ...
    runLabelSetAdaptiveDominantPayloadAwareM24( ...
        seed, protocol. ...
            adaptiveDominantPayloadAwareSelectedMarginToken, ...
        runOptions);
end
