function [reportPath, audit] = ...
    auditFormationReferenceRecoveryMixing(options)
% AUDITFORMATIONREFERENCERECOVERYMIXING Topology-only v25 diagnosis.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationReferenceRecoveryMixingAuditProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official recovery-mixing audit requires clean source.');
end
sourcePath = getField(options, ...
    'sourceScreenPath', protocol.sourceScreenPath);
outputRoot = getField(options, ...
    'outputDirectory', protocol.outputRoot);
auditPath = fullfile(outputRoot, ...
    'formation_reference_recovery_mixing_audit_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_REFERENCE_RECOVERY_MIXING_AUDIT_V1.md');
auditExists = exist(auditPath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(auditExists, reportExists)
    error('Recovery-mixing audit artifacts are partial.');
elseif auditExists
    loaded = load(auditPath, 'audit');
    if ~isfield(loaded, 'audit') || ...
            ~strcmp(loaded.audit.protocolId, protocol.id) || ...
            ~strcmp(loaded.audit.generationGitCommit, gitState.commit)
        error('Recovery-mixing audit provenance mismatch.');
    end
    audit = loaded.audit;
    fprintf('Reused recovery-mixing audit: %s\n', auditPath);
    return;
end

loaded = load(sourcePath, 'screen');
if ~isfield(loaded, 'screen')
    error('Recovery-mixing source screen is missing.');
end
screen = loaded.screen;
validateSourceScreen(screen, protocol);
weightsByAction = screen.bank.actionFusionWeights;
groupIds = reshape(screen.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
actionCount = size(weightsByAction, 3);
formationWeightsByAction = zeros( ...
    numel(groups), numel(groups), actionCount);
maximumActionRowSumError = 0;
for actionIdx = 1:actionCount
    actionDiagnostics = computeStochasticMixingDiagnostics( ...
        weightsByAction(:, :, actionIdx));
    maximumActionRowSumError = max( ...
        maximumActionRowSumError, actionDiagnostics.rowSumError);
    formationWeightsByAction(:, :, actionIdx) = ...
        collapseFusionWeightsByGroup( ...
            weightsByAction(:, :, actionIdx), groupIds);
end
referenceFormationWeights = ...
    formationWeightsByAction(:, :, protocol.referenceActionIndex);
formationDifferences = abs( ...
    formationWeightsByAction - referenceFormationWeights);
formationAggregateMaximumDifference = max(formationDifferences(:));
referenceFormationCrossMass = ...
    1 - diag(referenceFormationWeights)';

analysisSteps = protocol.analysisSteps;
armCount = size(screen.actionSequenceIndices, 1);
stepCount = numel(analysisSteps);
sensorDobrushin = zeros(armCount, stepCount);
sensorCenteredSpectralNorm = sensorDobrushin;
sensorMaximumCenteredRowL2 = sensorDobrushin;
formationDobrushin = sensorDobrushin;
formationCenteredSpectralNorm = sensorDobrushin;
formationMaximumCenteredRowL2 = sensorDobrushin;
firstSensorNonsaturatedStep = zeros(armCount, 1);
for armIdx = 1:armCount
    sensorProduct = eye(protocol.expectedNodeCount);
    formationProduct = eye(protocol.expectedFormationCount);
    resultColumn = 0;
    for timeIdx = 1:max(analysisSteps)
        if timeIdx <= screen.horizonSteps
            actionIdx = screen.actionSequenceIndices(armIdx, timeIdx);
        else
            actionIdx = protocol.referenceActionIndex;
        end
        sensorProduct = weightsByAction(:, :, actionIdx) * ...
            sensorProduct;
        formationProduct = ...
            formationWeightsByAction(:, :, actionIdx) * ...
            formationProduct;
        sensorDiagnostics = ...
            computeStochasticMixingDiagnostics(sensorProduct);
        if firstSensorNonsaturatedStep(armIdx) == 0 && ...
                sensorDiagnostics.dobrushinCoefficient < ...
                    1 - protocol.comparisonTolerance
            firstSensorNonsaturatedStep(armIdx) = timeIdx;
        end
        if any(analysisSteps == timeIdx)
            resultColumn = resultColumn + 1;
            formationDiagnostics = ...
                computeStochasticMixingDiagnostics(formationProduct);
            sensorDobrushin(armIdx, resultColumn) = ...
                sensorDiagnostics.dobrushinCoefficient;
            sensorCenteredSpectralNorm(armIdx, resultColumn) = ...
                sensorDiagnostics.centeredSpectralNorm;
            sensorMaximumCenteredRowL2(armIdx, resultColumn) = ...
                sensorDiagnostics.maximumCenteredRowL2;
            formationDobrushin(armIdx, resultColumn) = ...
                formationDiagnostics.dobrushinCoefficient;
            formationCenteredSpectralNorm(armIdx, resultColumn) = ...
                formationDiagnostics.centeredSpectralNorm;
            formationMaximumCenteredRowL2(armIdx, resultColumn) = ...
                formationDiagnostics.maximumCenteredRowL2;
        end
    end
end

horizonColumn = find(analysisSteps == screen.horizonSteps, 1);
referenceRow = screen.referenceSubsetIndex;
candidateRows = [1:(referenceRow - 1), ...
    (referenceRow + 1):armCount];
windowConsensusTargets = reshape( ...
    [screen.records.consensusGainPercent], [], 1);
finalConsensusTargets = reshape( ...
    [screen.records.terminalConsensusGainPercent], [], 1);
spectralNoninferior = sensorCenteredSpectralNorm( ...
    candidateRows, horizonColumn) <= ...
    sensorCenteredSpectralNorm(referenceRow, horizonColumn) + ...
        protocol.comparisonTolerance;
rowDispersionNoninferior = sensorMaximumCenteredRowL2( ...
    candidateRows, horizonColumn) <= ...
    sensorMaximumCenteredRowL2(referenceRow, horizonColumn) + ...
        protocol.comparisonTolerance;
spectralCounterexampleCandidates = candidateRows( ...
    spectralNoninferior & finalConsensusTargets(candidateRows) < 0);
rowDispersionCounterexampleCandidates = candidateRows( ...
    rowDispersionNoninferior & finalConsensusTargets(candidateRows) < 0);
shortHorizonDobrushinError = abs( ...
    sensorDobrushin(:, analysisSteps <= screen.horizonSteps) - 1);
sensorDobrushinSaturatedThroughHorizon = all( ...
    shortHorizonDobrushinError(:) <= ...
        protocol.comparisonTolerance);
formationActionInvariant = ...
    formationAggregateMaximumDifference <= ...
        protocol.comparisonTolerance;
topologyOnlyShortHorizonSafetyRejected = ...
    sensorDobrushinSaturatedThroughHorizon && ...
    formationActionInvariant && ...
    ~isempty(spectralCounterexampleCandidates) && ...
    ~isempty(rowDispersionCounterexampleCandidates);

audit = struct();
audit.contractVersion = ...
    'formation-reference-recovery-mixing-audit-result-v1';
audit.protocolId = protocol.id;
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.sourceScreenPath = sourcePath;
audit.sourceScreenSha256 = computeFileSha256(sourcePath);
audit.sourceGenerationGitCommit = ...
    screen.generationGitCommit;
audit.sourceContractVersion = screen.contractVersion;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.horizonSteps = screen.horizonSteps;
audit.actionSequenceIndices = screen.actionSequenceIndices;
audit.analysisSteps = analysisSteps;
audit.maximumActionRowSumError = maximumActionRowSumError;
audit.referenceFormationWeights = referenceFormationWeights;
audit.referenceFormationCrossMass = referenceFormationCrossMass;
audit.formationAggregateMaximumDifference = ...
    formationAggregateMaximumDifference;
audit.formationActionInvariant = formationActionInvariant;
audit.sensorDobrushin = sensorDobrushin;
audit.sensorCenteredSpectralNorm = sensorCenteredSpectralNorm;
audit.sensorMaximumCenteredRowL2 = sensorMaximumCenteredRowL2;
audit.formationDobrushin = formationDobrushin;
audit.formationCenteredSpectralNorm = ...
    formationCenteredSpectralNorm;
audit.formationMaximumCenteredRowL2 = ...
    formationMaximumCenteredRowL2;
audit.firstSensorNonsaturatedStep = ...
    firstSensorNonsaturatedStep;
audit.windowConsensusGainPercent = windowConsensusTargets;
audit.finalConsensusGainPercent = finalConsensusTargets;
audit.sensorDobrushinSaturatedThroughHorizon = ...
    sensorDobrushinSaturatedThroughHorizon;
audit.spectralCounterexampleCandidates = ...
    spectralCounterexampleCandidates;
audit.rowDispersionCounterexampleCandidates = ...
    rowDispersionCounterexampleCandidates;
audit.topologyOnlyShortHorizonSafetyRejected = ...
    topologyOnlyShortHorizonSafetyRejected;
audit.stateConditionedActionRedesignRequired = ...
    topologyOnlyShortHorizonSafetyRejected;
audit.authorizesGnnTraining = false;
audit.validationClaimAllowed = false;
audit.posthocDiagnosticOnly = true;
audit.evidenceBoundary = protocol.evidenceBoundary;
audit.auditPath = auditPath;
audit.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Formation recovery-mixing audit: %s\n', auditPath);
fprintf(['Formation-invariant=%d; short-H Dobrushin saturated=%d; ', ...
    'topology-only safety rejected=%d\n'], ...
    audit.formationActionInvariant, ...
    audit.sensorDobrushinSaturatedThroughHorizon, ...
    audit.topologyOnlyShortHorizonSafetyRejected);
end

function validateSourceScreen(screen, protocol)
required = { ...
    'contractVersion', 'generationGitCommit', 'presetName', ...
    'seed', 'currentTime', 'horizonSteps', 'bank', ...
    'sensorGroupIds', 'actionSequenceIndices', 'records', ...
    'referenceSubsetIndex'};
if ~all(isfield(screen, required)) || ...
        ~strcmp(screen.contractVersion, ...
            protocol.expectedSourceContract) || ...
        ~strcmp(screen.generationGitCommit, ...
            protocol.expectedSourceGenerationGitCommit) || ...
        ~strcmp(screen.presetName, protocol.expectedPresetName) || ...
        screen.seed ~= protocol.expectedSeed || ...
        screen.currentTime ~= protocol.expectedCurrentTime || ...
        screen.horizonSteps ~= protocol.expectedHorizonSteps || ...
        size(screen.actionSequenceIndices, 1) ~= ...
            protocol.expectedArmCount || ...
        screen.bank.actionCount ~= protocol.expectedActionCount || ...
        numel(screen.sensorGroupIds) ~= protocol.expectedNodeCount || ...
        numel(unique(screen.sensorGroupIds, 'stable')) ~= ...
            protocol.expectedFormationCount || ...
        screen.referenceSubsetIndex ~= 1 || ...
        ~all(screen.actionSequenceIndices(1, :) == ...
            protocol.referenceActionIndex)
    error('Recovery-mixing source-screen contract failed.');
end
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Cannot write recovery-mixing audit report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation reference-recovery mixing audit\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    audit.contractVersion, audit.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Source commit / SHA-256: `%s / %s`\n', ...
    audit.sourceGenerationGitCommit, audit.sourceScreenSha256);
fprintf(fid, '- Preset / seed / time / horizon: `%s / %d / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime, ...
    audit.horizonSteps);
fprintf(fid, '- Maximum action row-sum error: `%.3g`\n', ...
    audit.maximumActionRowSumError);
fprintf(fid, '- Formation aggregate maximum action difference: `%.3g`\n', ...
    audit.formationAggregateMaximumDifference);
fprintf(fid, '- Formation action invariant: `%d`\n', ...
    audit.formationActionInvariant);
fprintf(fid, '- Sensor Dobrushin saturated through H=5: `%d`\n', ...
    audit.sensorDobrushinSaturatedThroughHorizon);
fprintf(fid, '- Topology-only short-horizon safety rejected: `%d`\n', ...
    audit.topologyOnlyShortHorizonSafetyRejected);
fprintf(fid, '- GNN training authorized: `%d`\n\n', ...
    audit.authorizesGnnTraining);

fprintf(fid, '## Reference formation-level fusion matrix\n\n');
fprintf(fid, '```text\n%s\n```\n\n', ...
    strtrim(evalc('disp(audit.referenceFormationWeights)')));
fprintf(fid, '- Cross-formation mass by receiver formation: `%s`\n', ...
    mat2str(audit.referenceFormationCrossMass, 8));
fprintf(fid, [ ...
    '- All 256 actions reproduce this matrix within `%.3g`; ', ...
    'they change sensor/gateway allocation but not coarse ', ...
    'formation-to-formation mixing mass.\n'], ...
    audit.formationAggregateMaximumDifference);

fprintf(fid, '\n## H=5 topology-only metrics versus realized consensus\n\n');
fprintf(fid, [ ...
    '| Arm | Sequence | Sensor tau | Centered spectral | ', ...
    'Max row dispersion | Window consensus | Final-step consensus | ', ...
    'First tau<1 |\n']);
fprintf(fid, '|--:|:--|--:|--:|--:|--:|--:|--:|\n');
horizonColumn = find(audit.analysisSteps == audit.horizonSteps, 1);
for armIdx = 1:size(audit.actionSequenceIndices, 1)
    fprintf(fid, [ ...
        '| %d | `%s` | %.6f | %.6f | %.6f | %+.3f%% | ', ...
        '%+.3f%% | %d |\n'], ...
        armIdx, mat2str(audit.actionSequenceIndices(armIdx, :)), ...
        audit.sensorDobrushin(armIdx, horizonColumn), ...
        audit.sensorCenteredSpectralNorm(armIdx, horizonColumn), ...
        audit.sensorMaximumCenteredRowL2(armIdx, horizonColumn), ...
        audit.windowConsensusGainPercent(armIdx), ...
        audit.finalConsensusGainPercent(armIdx), ...
        audit.firstSensorNonsaturatedStep(armIdx));
end

fprintf(fid, '\n## Weight-only reference-recovery extrapolation\n\n');
fprintf(fid, '| Arm |');
for step = audit.analysisSteps
    fprintf(fid, ' tau@%d |', step);
end
fprintf(fid, '\n|--:|');
for step = audit.analysisSteps %#ok<NASGU>
    fprintf(fid, '--:|');
end
fprintf(fid, '\n');
for armIdx = 1:size(audit.sensorDobrushin, 1)
    fprintf(fid, '| %d |', armIdx);
    for columnIdx = 1:numel(audit.analysisSteps)
        fprintf(fid, ' %.6f |', ...
            audit.sensorDobrushin(armIdx, columnIdx));
    end
    fprintf(fid, '\n');
end

fprintf(fid, '\n## Diagnostic conclusion\n\n');
fprintf(fid, [ ...
    'Rolling-B3 is non-discriminative for this action family. The ', ...
    'sensor-level Dobrushin coefficient remains exactly one throughout ', ...
    'the realized H=5 window, while the formation-level fusion matrix is ', ...
    'action invariant. Centered product norms also fail as sufficient ', ...
    'safety tests: candidates `%s` have no worse H=5 centered spectral ', ...
    'norm than reference but still have negative final-step consensus; ', ...
    'the corresponding row-dispersion counterexamples are `%s`.\n\n'], ...
    mat2str(audit.spectralCounterexampleCandidates), ...
    mat2str(audit.rowDispersionCounterexampleCandidates));
fprintf(fid, [ ...
    'The next action representation must change coarse cross-formation ', ...
    'mixing mass and must condition value/risk on posterior and ', ...
    'innovation heterogeneity. A graph-only contraction proxy cannot ', ...
    'authorize learning or deployment from this evidence.\n']);

fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(item, name, defaultValue)
if isfield(item, name)
    value = item.(name);
else
    value = defaultValue;
end
end
