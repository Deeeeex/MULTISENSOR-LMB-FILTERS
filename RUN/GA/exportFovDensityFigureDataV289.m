function exportFovDensityFigureDataV289(tracePath,analysisPath,outputPath)
% Export one explicitly selected diagnostic example, not a typical target.
a=load(analysisPath,'result'); rows=a.result.rows;
eligible=find(rows(:,6)>=.5);
[~,index]=max(abs(rows(eligible,11))); row=rows(eligible(index),:);
s=load(tracePath,'trace'); trace=s.trace;
objects=trace.predicted{row(1)}{row(2)};
k=find([objects.birthTime]==row(4) & [objects.birthLocation]==row(5),1);
o=objects(k); model=trace.model;
example=struct('selection','largest absolute pD discrepancy among r >= 0.5 stages', ...
    'time',row(1),'sensor',row(2),'formation',row(3), ...
    'label',[row(4),row(5)],'existence',row(6), ...
    'mean_pd',row(8),'density_pd',row(9), ...
    'coarse_density_pd',row(10),'weights',o.w(:)', ...
    'means',zeros(o.numberOfGmComponents,2), ...
    'covariances',zeros(o.numberOfGmComponents,4), ...
    'sensor_position',model.sensorTrajectories{row(2)}(1:2,row(1))', ...
    'sensor_heading_rad',model.sensorFovHeadingRad(row(2),row(1)), ...
    'fov_range_m',model.sensorFovRange(row(2)), ...
    'fov_half_angle_deg',model.sensorFovHalfAngleDeg(row(2)), ...
    'uses_target_truth',false);
for j=1:o.numberOfGmComponents
    example.means(j,:)=o.mu{j}(1:2)';
    covariance=o.Sigma{j}(1:2,1:2);
    example.covariances(j,:)=[covariance(1,:),covariance(2,:)];
end
fid=fopen(outputPath,'w'); assert(fid>=0); cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(example));
fprintf('V289 figure example: t=%d, sensor=%d, r=%.6f, pD %.6f -> %.6f.\n', ...
    row(1),row(2),row(6),row(8),row(9));
end
