function receipt = publishFusionSufficientBatchSuccessReceipt( ...
    batchPlanPath, completionToken, launcherCapability, testAuthorization)
% PUBLISHFUSIONSUFFICIENTBATCHSUCCESSRECEIPT Seal complete worker artifacts.

if nargin < 2
    completionToken = '';
end
if nargin < 3
    launcherCapability = '';
end
if nargin < 4
    testAuthorization = struct();
end

loaded = load(batchPlanPath);
if ~isfield(loaded, 'config') || ~isfield(loaded, 'parallelPlan')
    error('FusionSufficientSuccess:InvalidPlan', ...
        'Batch plan must contain config and parallelPlan.');
end
config = loaded.config;
plan = loaded.parallelPlan;
testMode = isFusionSufficientInternalTestAuthorization(testAuthorization);
validateExecutionMode(config, testMode);
if ~testMode
    assertFusionSufficientConfigProvenance(config);
end
assertFusionSufficientExecutionEnvironment(config);
expectedPlan = buildFusionSufficientParallelPlan(config);
if ~isequaln(orderfields(plan), orderfields(expectedPlan)) || ...
        ~strcmp(hashFusionSufficientConfig(config), config.configSha256)
    error('FusionSufficientSuccess:PlanMismatch', ...
        'Published batch plan differs from its frozen config.');
end
if ~strcmp(char(batchPlanPath), plan.batchPlanPath)
    error('FusionSufficientSuccess:PlanPath', ...
        'Receipt publisher was given a noncanonical plan path.');
end
if exist(plan.reservationReceiptPath, 'file') ~= 2 || ...
        exist(plan.attemptFailedTombstonePath, 'file') == 2 || ...
        exist(plan.workerFailedTombstonePath, 'file') == 2
    error('FusionSufficientSuccess:BurnedBatch', ...
        'Cannot publish success for an unreserved or failed batch.');
end
reservationValues = parseKeyValueFile(plan.reservationReceiptPath);
capabilitySha256 = requireHash( ...
    reservationValues, 'launcher_capability_sha256');
launcherCapability = char(launcherCapability);
if isempty(regexp(launcherCapability, '^[0-9a-f]{64}$', 'once'))
    error('FusionSufficientSuccess:LauncherCapability', ...
        ['Success seal requires the consumed one-time 256-bit ', ...
        'launcher capability.']);
end
providedCapabilitySha256 = ...
    fusionSufficientSha256Text(launcherCapability);
if ~strcmp(providedCapabilitySha256, capabilitySha256)
    error('FusionSufficientSuccess:LauncherCapabilityMismatch', ...
        ['Provided launcher capability does not match the stable ', ...
        'reservation receipt.']);
end
claimValues = parseKeyValueFile(plan.lifecycleClaimPath);
requireValue(claimValues, 'claim_schema', ...
    'fusion-sufficient-launch-claim-v2');
requireValue(claimValues, 'batch_identity', config.batchIdentity);
requireValue(claimValues, 'launcher_capability_sha256', ...
    providedCapabilitySha256);
exitValues = parseKeyValueFile(plan.exitLedgerPath);
requireValue(exitValues, 'exit_schema', ...
    'fusion-sufficient-worker-exits-v2');
requireValue(exitValues, 'batch_identity', config.batchIdentity);
requireValue(exitValues, 'launcher_capability_sha256', ...
    providedCapabilitySha256);
requireValue(exitValues, 'ordered_seeds', joinIntegers(plan.workerSeeds));
if numel(fieldnames(exitValues)) ~= 4 + numel(plan.workerSeeds)
    error('FusionSufficientSuccess:ExitLedgerFields', ...
        'Worker exit ledger contains missing or extra fields.');
end
completionValues = parseKeyValueFile(plan.completionAuthorizationPath);
requireValue(completionValues, 'completion_schema', ...
    'fusion-sufficient-completion-v2');
requireValue(completionValues, 'batch_identity', config.batchIdentity);
requireValue(completionValues, 'launcher_capability_sha256', ...
    capabilitySha256);
completionToken = char(completionToken);
if isempty(regexp(completionToken, '^[0-9a-f]{64}$', 'once'))
    error('FusionSufficientSuccess:CompletionToken', ...
        'Completion token must be a one-time 256-bit lowercase hex value.');
end
completionTokenSha256 = fusionSufficientSha256Text(completionToken);
requireValue(completionValues, 'completion_token_sha256', ...
    completionTokenSha256);
for seedIdx = 1:numel(plan.workerSeeds)
    requireValue(exitValues, sprintf('worker_%06d_exit', ...
        plan.workerSeeds(seedIdx)), '0');
end
if exist(plan.workerSuccessReceiptPath, 'file') == 2 || ...
        exist(plan.attemptSuccessReceiptPath, 'file') == 2
    error('FusionSufficientSuccess:ReceiptExists', ...
        'Refusing to overwrite an existing batch success receipt.');
end
assertExactWorkerSet(plan);

planHash = fusionSufficientSha256File(plan.batchPlanPath);
exitLedgerHash = fusionSufficientSha256File(plan.exitLedgerPath);
matHashes = cell(1, numel(plan.workerSeeds));
logHashes = cell(1, numel(plan.workerSeeds));
parts = {sprintf([ ...
    'receipt_schema=fusion-sufficient-batch-success-v2\n', ...
    'batch_identity=%s\n', ...
    'config_sha256=%s\n', ...
    'required_sources_sha256=%s\n', ...
    'launcher_capability_sha256=%s\n', ...
    'completion_token_sha256=%s\n', ...
    'plan_sha256=%s\n', ...
    'exit_ledger_sha256=%s\n', ...
    'ordered_seeds=%s\n', ...
    'max_workers=%d\n', ...
    'worker_count=%d\n'], ...
    config.batchIdentity, config.configSha256, ...
    config.requiredSourcesSha256, capabilitySha256, ...
    completionTokenSha256, planHash, exitLedgerHash, ...
    joinIntegers(plan.workerSeeds), plan.maxWorkers, ...
    numel(plan.workerSeeds))};
for seedIdx = 1:numel(plan.workerSeeds)
    seed = plan.workerSeeds(seedIdx);
    parts{end + 1} = sprintf( ...
        'worker_%06d_exit=0\n', seed); %#ok<AGROW>
    matHashes{seedIdx} = ...
        fusionSufficientSha256File(plan.workerMatPaths{seedIdx});
    logHashes{seedIdx} = ...
        fusionSufficientSha256File(plan.workerLogPaths{seedIdx});
    parts{end + 1} = sprintf( ...
        'worker_%06d_mat_sha256=%s\n', ...
        seed, matHashes{seedIdx}); %#ok<AGROW>
    parts{end + 1} = sprintf( ...
        'worker_%06d_log_sha256=%s\n', ...
        seed, logHashes{seedIdx}); %#ok<AGROW>
end
receiptText = [parts{:}];
temporaryPath = [tempname(plan.attemptDirectory), '.success'];
cleanup = onCleanup(@() deleteIfPresent(temporaryPath)); %#ok<NASGU>
writeText(temporaryPath, receiptText);
linkFusionSufficientFileNoClobber( ...
    temporaryPath, plan.workerSuccessReceiptPath);
linkFusionSufficientFileNoClobber( ...
    temporaryPath, plan.attemptSuccessReceiptPath);
receipt = struct( ...
    'schema', 'fusion-sufficient-batch-success-v2', ...
    'batchIdentity', config.batchIdentity, ...
    'configSha256', config.configSha256, ...
    'planSha256', planHash, ...
    'exitLedgerSha256', exitLedgerHash, ...
    'launcherCapabilitySha256', capabilitySha256, ...
    'completionTokenSha256', completionTokenSha256, ...
    'workerSeeds', plan.workerSeeds, ...
    'maxWorkers', plan.maxWorkers, ...
    'workerMatSha256', {matHashes}, ...
    'workerLogSha256', {logHashes}, ...
    'receiptSha256', fusionSufficientSha256File( ...
        plan.workerSuccessReceiptPath));
end

function value = requireHash(values, name)
if ~isfield(values, name) || isempty(regexp(values.(name), ...
        '^[0-9a-f]{64}$', 'once'))
    error('FusionSufficientSuccess:InvalidHash', ...
        'Required hash field %s is invalid.', name);
end
value = values.(name);
end

function validateExecutionMode(config, testMode)
if testMode
    valid = isfield(config, 'testOnly') && ...
        isequal(config.testOnly, true) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-test-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-test-v2') && ...
        strncmp(config.artifactStem, 'TEST_', 5) && ...
        strncmp(config.batchIdentity, 'test-', 5);
else
    valid = isfield(config, 'testOnly') && ...
        isequal(config.testOnly, false) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-v2');
end
if ~valid
    error('FusionSufficientSuccess:ExecutionMode', ...
        'Success publisher rejects mismatched production/test schema.');
end
end

function values = parseKeyValueFile(path)
if exist(path, 'file') ~= 2
    error('FusionSufficientSuccess:MissingExitLedger', ...
        'Worker exit ledger is missing.');
end
lines = strsplit(strtrim(fileread(path)), '\n');
values = struct();
for lineIdx = 1:numel(lines)
    token = regexp(lines{lineIdx}, '^([a-z0-9_]+)=(.*)$', ...
        'tokens', 'once');
    if isempty(token) || isfield(values, token{1})
        error('FusionSufficientSuccess:ExitLedgerSyntax', ...
            'Worker exit ledger has invalid or duplicate line %d.', ...
            lineIdx);
    end
    values.(token{1}) = token{2};
end
end

function requireValue(values, name, expected)
if ~isfield(values, name) || ~strcmp(values.(name), expected)
    error('FusionSufficientSuccess:ExitLedgerValue', ...
        'Worker exit ledger field %s differs from expected.', name);
end
end

function assertExactWorkerSet(plan)
expectedMat = cellfun(@basename, plan.workerMatPaths, ...
    'UniformOutput', false);
expectedLog = cellfun(@basename, plan.workerLogPaths, ...
    'UniformOutput', false);
actualMat = dir(fullfile(plan.workerDirectory, 'worker_seed_*.mat'));
actualLog = dir(fullfile(plan.workerDirectory, 'worker_seed_*.log'));
if ~isequal(sort({actualMat.name}), sort(expectedMat)) || ...
        ~isequal(sort({actualLog.name}), sort(expectedLog))
    error('FusionSufficientSuccess:IncompleteWorkers', ...
        'Worker MAT/log set is missing, extra, or incomplete.');
end
end

function value = basename(path)
[~, name, extension] = fileparts(path);
value = [name, extension];
end

function text = joinIntegers(values)
parts = arrayfun(@(value) sprintf('%d', value), values, ...
    'UniformOutput', false);
text = strjoin(parts, ',');
end

function writeText(path, value)
fid = fopen(path, 'wb');
if fid < 0
    error('FusionSufficientSuccess:WriteFailed', ...
        'Unable to create success receipt temporary file.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = uint8(value);
count = fwrite(fid, bytes, 'uint8');
if count ~= numel(bytes)
    error('FusionSufficientSuccess:WriteFailed', ...
        'Unable to write complete success receipt.');
end
end

function deleteIfPresent(path)
if exist(path, 'file') == 2
    delete(path);
end
end
