function [reportPath, result] = ...
    runBraidedHandoverH3V84PrimaryAnchors(options)
% RUNBRAIDEDHANDOVERH3V84PRIMARYANCHORS Paired M24/X36 outcome.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBraidedHandoverH3V84Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('BraidedHandoverH3V84:DirtySource', ...
        'The V84 paired H=3 outcome requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(protocol.cases));
screenPaths = cell(1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    screenOptions = struct( ...
        'horizonSteps', protocol.horizonSteps, ...
        'interventionDurationSteps', ...
            protocol.interventionDurationSteps, ...
        'filterSeedOffset', protocol.filterSeedOffset, ...
        'cacheRoot', cacheRoot, ...
        'interventionBankType', ...
            'braided-handover-transport-v84', ...
        'trackingAlignedExecutionProfile', ...
            'v84-braided-handover-primary-h3', ...
        'outputDirectory', fullfile(outputRoot, 'screen', ...
            caseInfo.presetName, sprintf('t%d', caseInfo.currentTime)), ...
        'writeReport', true);
    [screenPaths{caseIdx}, screen] = ...
        runFormationModeOpenedReturnScreen( ...
            caseInfo.presetName, caseInfo.seed, ...
            caseInfo.currentTime, screenOptions);
    records(caseIdx) = summarizeCase(screen, protocol);
    fprintf([ ...
        'V84 H3 %s t=%d mean=%+.3f%% worst=%+.3f%% ', ...
        'formation=%+.3f%% consensus=%+.3f%% strong=%d\n'], ...
        caseInfo.presetName, caseInfo.currentTime, ...
        records(caseIdx).meanGainPercent, ...
        records(caseIdx).worstSensorGainPercent, ...
        records(caseIdx).minimumFormationGainPercent, ...
        records(caseIdx).windowConsensusGainPercent, ...
        records(caseIdx).strongGatePassed);
end

result = struct();
result.contractVersion = ...
    'braided-handover-primary-h3-v84-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.screenPaths = screenPaths;
result.records = records;
result.bothScalesStrongGatePassed = ...
    all([records.strongGatePassed]);
result.trackingOutcomeRead = true;
result.secondaryAnchorScoringAuthorized = ...
    result.bothScalesStrongGatePassed;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'BRAIDED_HANDOVER_PRIMARY_H3_V84_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'BRAIDED_HANDOVER_PRIMARY_H3_V84_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V84 braided-handover primary H3: %s\n', reportPath);
end

function record = summarizeCase(screen, protocol)
referenceIdx = screen.referenceSubsetIndex;
candidateIdx = setdiff(1:numel(screen.records), referenceIdx);
if numel(candidateIdx) ~= 1
    error('BraidedHandoverH3V84:ScreenContract', ...
        'V84 requires exactly one reference and one candidate arm.');
end
candidate = screen.records(candidateIdx);
referenceOutcome = screen.outcomes(referenceIdx);
candidateOutcome = screen.outcomes(candidateIdx);
record = emptyRecord();
record.presetName = screen.presetName;
record.seed = screen.seed;
record.currentTime = screen.currentTime;
record.actionName = candidate.actionName;
record.selectedFormationIds = candidate.formationIndices;
record.meanGainPercent = candidate.meanGainPercent;
record.worstSensorGainPercent = candidate.worstGainPercent;
record.minimumFormationGainPercent = ...
    candidate.minimumFormationGainPercent;
record.formationGainPercent = candidate.formationGainPercent;
record.windowConsensusGainPercent = candidate.consensusGainPercent;
record.terminalConsensusGainPercent = ...
    candidate.terminalConsensusGainPercent;
record.attemptedByteSavingPercent = ...
    candidate.attemptedByteSavingPercent;
record.referenceMeanEospa = referenceOutcome.meanEospa;
record.candidateMeanEospa = candidateOutcome.meanEospa;
record.referenceWorstSensorEospa = ...
    referenceOutcome.worstSensorEospa;
record.candidateWorstSensorEospa = ...
    candidateOutcome.worstSensorEospa;
record.referenceAttemptedBytes = referenceOutcome.attemptedBytes;
record.candidateAttemptedBytes = candidateOutcome.attemptedBytes;
record.selectedB3Passed = candidate.selectedB3Passed;
record.messageParityPassed = ...
    screen.bank.actionMessageCounts(candidate.actionIndex) == ...
        screen.bank.actionMessageCounts( ...
            screen.records(referenceIdx).actionIndex);
record.strongGatePassed = ...
    record.meanGainPercent >= ...
        protocol.minimumMeanTrackingGainPercent - 1e-12 && ...
    record.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    record.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    record.windowConsensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    record.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    record.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    record.selectedB3Passed && record.messageParityPassed;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BraidedHandoverH3V84:WriteFailed', ...
        'Could not create the V84 H=3 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V84 braided-handover primary paired H=3 result\n\n');
fprintf(fid, ['| Scale | Time | Action | Mean tracking | Worst sensor | ', ...
    'Minimum formation | Window consensus | Terminal consensus | ', ...
    'Attempted bytes | B3 | Strong |\n']);
fprintf(fid, '|:--|--:|:--|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
for record = result.records
    fprintf(fid, ['| %s | %d | `%s` | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d | %d |\n'], ...
        record.presetName, record.currentTime, record.actionName, ...
        record.meanGainPercent, record.worstSensorGainPercent, ...
        record.minimumFormationGainPercent, ...
        record.windowConsensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent, ...
        record.selectedB3Passed, record.strongGatePassed);
end
fprintf(fid, '\n- Both scales pass the strong gate: `%d`\n', ...
    result.bothScalesStrongGatePassed);
fprintf(fid, '- Secondary anchor scoring authorized: `%d`\n', ...
    result.secondaryAnchorScoringAuthorized);
fprintf(fid, '- Model training authorized: `%d`\n', ...
    result.modelTrainingAuthorized);
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'actionName', '', ...
    'selectedFormationIds', zeros(1, 0), ...
    'meanGainPercent', NaN, ...
    'worstSensorGainPercent', NaN, ...
    'minimumFormationGainPercent', NaN, ...
    'formationGainPercent', zeros(1, 0), ...
    'windowConsensusGainPercent', NaN, ...
    'terminalConsensusGainPercent', NaN, ...
    'attemptedByteSavingPercent', NaN, ...
    'referenceMeanEospa', NaN, ...
    'candidateMeanEospa', NaN, ...
    'referenceWorstSensorEospa', NaN, ...
    'candidateWorstSensorEospa', NaN, ...
    'referenceAttemptedBytes', NaN, ...
    'candidateAttemptedBytes', NaN, ...
    'selectedB3Passed', false, ...
    'messageParityPassed', false, ...
    'strongGatePassed', false);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
