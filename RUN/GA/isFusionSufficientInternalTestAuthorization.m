function valid = isFusionSufficientInternalTestAuthorization(authorization)
% ISFUSIONSUFFICIENTINTERNALTESTAUTHORIZATION Validate explicit test gate.

valid = isstruct(authorization) && isscalar(authorization) && ...
    isfield(authorization, 'schema') && ...
    isfield(authorization, 'testOnly') && ...
    isfield(authorization, 'guard') && ...
    strcmp(authorization.schema, ...
    'fusion-sufficient-internal-test-authorization-v1') && ...
    isequal(authorization.testOnly, true) && ...
    strcmp(authorization.guard, ...
    'never-valid-for-production-evidence');
if valid
    stack = dbstack();
    valid = false;
    for frameIdx = 1:numel(stack)
        if ~isempty(regexp(stack(frameIdx).name, '^test_', 'once'))
            valid = true;
            break;
        end
    end
end
end
