function [reportPath, result] = ...
        analyzePairwiseEtaSafeSemanticCandidatesV224(options)
% ANALYZEPAIRWISEETASAFESEMANTICCANDIDATESV224 Cheap eta prefilter.
%
% The analysis fuses each ordinary receiver result with one complete source
% label using the proposed source share.  It is a screening approximation to
% the recursive multi-input V223 route: powered-GM truncation means pairwise
% refusion is not claimed to be exactly associative.

if nargin < 1 || isempty(options)
    options = struct();
end
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
sourceWeight = getField(options, 'sourceWeight', 0.10);
synopsisBytes = getField(options, 'queryFirstSynopsisBytes', 1976);
minimumMapExistence = getField(options, ...
    'minimumMapExistence', 0.50);
maximumReferenceLogOddsDrop = getField(options, ...
    'maximumReferenceLogOddsDrop', 0.25);
identityTolerance = getField(options, 'identityTolerance', 1e-8);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        ~isscalar(sourceWeight) || ~isfinite(sourceWeight) || ...
        sourceWeight <= 0 || sourceWeight >= 1 || ...
        ~validNonnegativeScalar(synopsisBytes) || ...
        ~validProbability(minimumMapExistence) || ...
        ~validNonnegativeScalar(maximumReferenceLogOddsDrop) || ...
        ~validNonnegativeScalar(identityTolerance)
    error('PairwiseEtaSafeCandidatesV224:InvalidRequest', ...
        'The candidate bank or eta-screen parameters are malformed.');
end

loaded = load(candidateBankPath, 'result');
bankResult = loaded.result;
requiredBankFields = {'contractVersion', 'sourceScreenPath', ...
    'presetName', 'seed', 'currentTime', 'pageIndex', ...
    'referencePageBytes', 'donorPageBytes', ...
    'admissionNetSavingBytes', 'donorRecord', 'records'};
if ~isstruct(bankResult) || ~isscalar(bankResult) || ...
        any(~isfield(bankResult, requiredBankFields)) || ...
        ~strcmp(bankResult.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        exist(bankResult.sourceScreenPath, 'file') ~= 2
    error('PairwiseEtaSafeCandidatesV224:CandidateBankContract', ...
        'A causal V220 candidate bank with donor capture is required.');
end
screenLoaded = load(bankResult.sourceScreenPath, 'screen');
screen = screenLoaded.screen;
donorOutcomeIdx = find(strcmp({screen.records.actionName}, ...
    bankResult.donorRecord.actionName));
if numel(donorOutcomeIdx) ~= 1
    error('PairwiseEtaSafeCandidatesV224:DonorArm', ...
        'The donor-only outcome could not be resolved uniquely.');
end
donorOutcome = screen.outcomes(donorOutcomeIdx);
pageIndex = bankResult.pageIndex;
if ~isfield(donorOutcome, 'localPosteriorSnapshotsByTime') || ...
        ~isfield(donorOutcome, 'fusedPosteriorSnapshotsByTime') || ...
        numel(donorOutcome.localPosteriorSnapshotsByTime) < pageIndex || ...
        numel(donorOutcome.fusedPosteriorSnapshotsByTime) < pageIndex
    error('PairwiseEtaSafeCandidatesV224:MissingCapture', ...
        'The donor outcome lacks current posterior snapshots.');
end
localBySensor = reshape( ...
    donorOutcome.localPosteriorSnapshotsByTime{pageIndex}, 1, []);
fusedBySensor = reshape( ...
    donorOutcome.fusedPosteriorSnapshotsByTime{pageIndex}, 1, []);
inputs = generateDynamicTopologyScenarioInputs( ...
    bankResult.presetName, bankResult.seed);
model = inputs.model;

[creditAfterSynopsis, synopsisDecision] = ...
    preflightBudgetRecycledRepairSynopsisV188( ...
        [], bankResult.admissionNetSavingBytes, synopsisBytes, ...
        bankResult.referencePageBytes);
records = repmat(emptyRecord(), 1, numel(bankResult.records));
projectionOptions = struct( ...
    'minimumMapExistence', minimumMapExistence, ...
    'maximumReferenceLogOddsDrop', maximumReferenceLogOddsDrop, ...
    'identityTolerance', identityTolerance);
for recordIdx = 1:numel(bankResult.records)
    candidateRecord = bankResult.records(recordIdx);
    receivers = reshape(candidateRecord.candidate.receiverIds, 1, []);
    sourceObject = findLabelObject( ...
        localBySensor{candidateRecord.sourceId}, candidateRecord.label);
    item = emptyRecord();
    item.recordIndex = candidateRecord.recordIndex;
    item.sourceId = candidateRecord.sourceId;
    item.label = reshape(candidateRecord.label, 2, 1);
    item.receiverIds = receivers;
    item.payloadAttemptedBytes = ...
        candidateRecord.payloadAttemptedBytes;
    item.queryFirstCreditFeasible = ...
        synopsisDecision.lightSynopsisAuthorized && ...
        candidateRecord.payloadAttemptedBytes <= ...
            creditAfterSynopsis.spendableCreditBytes + 1e-9;
    item.certifiedNetSavingBytes = ...
        bankResult.referencePageBytes - bankResult.donorPageBytes - ...
        synopsisBytes - candidateRecord.payloadAttemptedBytes;
    item.certifiedNetSavingPercent = 100 * ...
        item.certifiedNetSavingBytes / ...
        max(bankResult.referencePageBytes, eps);
    item.pairDetailsByReceiver = cell(1, numel(localBySensor));
    if isempty(sourceObject)
        item.rejectionReason = 'source-label-missing';
        records(recordIdx) = item;
        continue;
    end
    margins = nan(1, numel(receivers));
    normalizers = nan(1, numel(receivers));
    candidateExistence = nan(1, numel(receivers));
    for receiverPosition = 1:numel(receivers)
        receiverIdx = receivers(receiverPosition);
        receiverObject = findLabelObject( ...
            fusedBySensor{receiverIdx}, candidateRecord.label);
        if isempty(receiverObject)
            continue;
        end
        pair = computeCompleteLabelKlaPairDiagnosticsV217( ...
            receiverObject, sourceObject, model, ...
            struct('sourceWeight', sourceWeight));
        [allowed, etaProjection] = ...
            projectLabelKlaExistenceRetentionByEtaV223( ...
                [receiverObject.r, sourceObject.r], ...
                [1 - sourceWeight, sourceWeight], ...
                pair.spatialLogNormalizer, receiverObject.r, ...
                projectionOptions);
        detail = struct( ...
            'receiverId', receiverIdx, ...
            'allowed', allowed, ...
            'pairDiagnostics', pair, ...
            'etaProjection', etaProjection);
        item.pairDetailsByReceiver{receiverIdx} = detail;
        if allowed
            item.allowedReceiverIds(end + 1) = receiverIdx; %#ok<AGROW>
        else
            item.rejectedReceiverIds(end + 1) = receiverIdx; %#ok<AGROW>
        end
        margins(receiverPosition) = etaProjection.logEtaMargin;
        normalizers(receiverPosition) = etaProjection.spatialNormalizer;
        candidateExistence(receiverPosition) = ...
            etaProjection.candidateExistence;
    end
    missing = receivers(~ismember(receivers, ...
        [item.allowedReceiverIds, item.rejectedReceiverIds]));
    item.missingReceiverIds = missing;
    item.allowedReceiverFraction = ...
        numel(item.allowedReceiverIds) / max(numel(receivers), 1);
    item.minimumLogEtaMargin = minFinite(margins);
    item.medianLogEtaMargin = medianFinite(margins);
    item.minimumSpatialNormalizer = minFinite(normalizers);
    item.minimumCandidateExistence = minFinite(candidateExistence);
    item.allReceiversAllowed = ...
        isempty(missing) && numel(item.allowedReceiverIds) == numel(receivers);
    item.anyReceiverAllowed = ~isempty(item.allowedReceiverIds);
    if ~item.anyReceiverAllowed
        item.rejectionReason = 'no-pairwise-eta-safe-receiver';
    elseif ~item.queryFirstCreditFeasible
        item.rejectionReason = 'query-first-credit-infeasible';
    end
    records(recordIdx) = item;
end

result = struct();
result.contractVersion = ...
    'pairwise-eta-safe-semantic-candidate-analysis-v224-v1';
result.generatedAt = datestr(now, 31);
result.candidateBankPath = candidateBankPath;
result.presetName = bankResult.presetName;
result.seed = bankResult.seed;
result.currentTime = bankResult.currentTime;
result.sourceWeight = sourceWeight;
result.queryFirstSynopsisBytes = synopsisBytes;
result.minimumMapExistence = minimumMapExistence;
result.maximumReferenceLogOddsDrop = maximumReferenceLogOddsDrop;
result.identityTolerance = identityTolerance;
result.spendableCreditAfterSynopsis = ...
    creditAfterSynopsis.spendableCreditBytes;
result.records = records;
result.candidateCount = numel(records);
result.queryFirstCreditFeasibleCount = ...
    nnz([records.queryFirstCreditFeasible]);
result.anyReceiverAllowedCount = nnz([records.anyReceiverAllowed]);
result.allReceiversAllowedCount = nnz([records.allReceiversAllowed]);
result.truthUsed = false;
result.futureInformationUsed = false;
result.exactMultiInputRouteClaimed = false;
result.evidenceBoundary = [ ...
    'V224 is a truth-free current-page prefilter. It reuses the active ', ...
    'componentwise powered-GM operator, but fuses the ordinary receiver ', ...
    'result with the source label pairwise. Because powered-GM component ', ...
    'truncation is not exactly associative, only the recursive V223 screen ', ...
    'can establish actual route admission and H=3 tracking value.'];

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v224', 'pairwise_eta_prefilter', ...
    sprintf('%s_seed%d_t%d', strrep(result.presetName, '-', '_'), ...
        result.seed, result.currentTime))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'PAIRWISE_ETA_SAFE_SEMANTIC_CANDIDATES_V224.mat');
reportPath = fullfile(outputRoot, ...
    'PAIRWISE_ETA_SAFE_SEMANTIC_CANDIDATES_V224.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V224 pairwise eta-safe candidate analysis: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('PairwiseEtaSafeCandidatesV224:WriteReport', ...
        'Could not write the V224 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V224 pairwise eta-safe semantic candidate prefilter\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Source weight / query synopsis: `%.3f / %d B`\n', ...
    result.sourceWeight, result.queryFirstSynopsisBytes);
fprintf(fid, '- Candidates / byte-feasible / any-safe / all-safe: `%d / %d / %d / %d`\n\n', ...
    result.candidateCount, result.queryFirstCreditFeasibleCount, ...
    result.anyReceiverAllowedCount, result.allReceiversAllowedCount);
fprintf(fid, ['| Row | Source | Label | Allowed / rejected | ', ...
    'Min / median log-eta margin | Min eta | Min candidate r | ', ...
    'Net saving | Byte-feasible |\n']);
fprintf(fid, '|--:|--:|:--|:--|--:|--:|--:|--:|:--:|\n');
for record = result.records
    fprintf(fid, ...
        ['| %d | %d | `[%d,%d]` | `%s / %s` | ', ...
         '%+.3f / %+.3f | %.3f | %.3f | %+.3f%% | %d |\n'], ...
        record.recordIndex, record.sourceId, ...
        record.label(1), record.label(2), ...
        formatIds(record.allowedReceiverIds), ...
        formatIds(record.rejectedReceiverIds), ...
        record.minimumLogEtaMargin, record.medianLogEtaMargin, ...
        record.minimumSpatialNormalizer, ...
        record.minimumCandidateExistence, ...
        record.certifiedNetSavingPercent, ...
        record.queryFirstCreditFeasible);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function object = findLabelObject(objects, label)
object = [];
objects = reshape(objects, 1, []);
for objectIdx = 1:numel(objects)
    candidate = objects(objectIdx);
    if candidate.birthTime == label(1) && ...
            candidate.birthLocation == label(2)
        object = candidate;
        return;
    end
end
end

function value = emptyRecord()
value = struct( ...
    'recordIndex', 0, 'sourceId', 0, 'label', zeros(2, 1), ...
    'receiverIds', zeros(1, 0), ...
    'allowedReceiverIds', zeros(1, 0), ...
    'rejectedReceiverIds', zeros(1, 0), ...
    'missingReceiverIds', zeros(1, 0), ...
    'pairDetailsByReceiver', {cell(1, 0)}, ...
    'payloadAttemptedBytes', 0, ...
    'queryFirstCreditFeasible', false, ...
    'certifiedNetSavingBytes', 0, ...
    'certifiedNetSavingPercent', 0, ...
    'allowedReceiverFraction', 0, ...
    'minimumLogEtaMargin', -inf, ...
    'medianLogEtaMargin', -inf, ...
    'minimumSpatialNormalizer', 0, ...
    'minimumCandidateExistence', 0, ...
    'allReceiversAllowed', false, ...
    'anyReceiverAllowed', false, ...
    'rejectionReason', '');
end

function value = minFinite(values)
values = values(isfinite(values));
if isempty(values)
    value = -inf;
else
    value = min(values);
end
end

function value = medianFinite(values)
values = values(isfinite(values));
if isempty(values)
    value = -inf;
else
    value = median(values);
end
end

function textValue = formatIds(ids)
ids = reshape(ids, 1, []);
if isempty(ids)
    textValue = '-';
else
    textValue = strtrim(sprintf('%d ', ids));
end
end

function valid = validNonnegativeScalar(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value >= 0;
end

function valid = validProbability(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value > 0 && value < 1;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
