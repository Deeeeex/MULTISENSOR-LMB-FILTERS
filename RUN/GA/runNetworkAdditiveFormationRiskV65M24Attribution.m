function [reportPath, result] = ...
    runNetworkAdditiveFormationRiskV65M24Attribution(options)
% RUNNETWORKADDITIVEFORMATIONRISKV65M24ATTRIBUTION M24 feature check.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNetworkAdditiveFormationRiskV65Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NetworkAdditiveM24V65:DirtySource', ...
        'V65 M24 attribution requires a clean source checkout.');
end
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'm24_opened_attribution'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

targets = protocol.m24OpenedTrackingTargets;
records = repmat(emptyRecord(), 1, numel(targets));
for idx = 1:numel(targets)
    target = targets(idx);
    entry = resolveCase(protocol.m24Cases, ...
        target.presetName, target.seed);
    fprintf('V65 M24 observable attribution %d/%d: %s t=%d ...\n', ...
        idx, numel(targets), target.presetName, target.currentTime);
    state = loadFormationH3ObservableState( ...
        target.presetName, target.seed, target.currentTime, ...
        struct('cacheRoot', entry.cacheRoot));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds);
    metrics = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    selection = selectNetworkAdditiveFormationRiskSetV65( ...
        metrics, protocol);
    records(idx) = makeFeatureRecord(target, metrics, selection);
    fprintf('  risk=%.3f%% enabled=%d set=%s fallback=%s\n', ...
        100 * metrics.totalNetworkRescueFraction, ...
        selection.actionEnabled, ...
        mat2str(selection.selectedFormationIds), ...
        selection.fallbackReason);
end

% Join already-opened development outcomes only after every observable
% feature and selector decision has been constructed.
for idx = 1:numel(records)
    records(idx).priorKnownGainPercent = targets(idx).meanGainPercent;
    records(idx).priorKnownGainSource = targets(idx).source;
end
knownGain = [records.priorKnownGainPercent];
strongMask = knownGain >= protocol.strongGainPercent - 1e-12;
weakMask = knownGain < protocol.weakGainPercent - 1e-12;
enabled = arrayfun(@(record) record.selection.actionEnabled, records);
risk = [records.totalNetworkRescueFraction];

result = struct();
result.contractVersion = ...
    'network-additive-formation-risk-v65-m24-attribution-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.records = records;
result.strongRecordCount = nnz(strongMask);
result.weakRecordCount = nnz(weakMask);
result.strongTriggerRate = meanOrNaN(enabled(strongMask));
result.weakFallbackRate = meanOrNaN(~enabled(weakMask));
result.networkRiskSeparatesStrongWeak = ...
    any(strongMask) && any(weakMask) && ...
    min(risk(strongMask)) > max(risk(weakMask)) + 1e-12;
result.selectionUsesPriorKnownGain = false;
result.v65TrackingOutcomeScored = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V65 reuses current posterior caches from ten already-opened M24 ', ...
    'development states. All network-additive features and decisions are ', ...
    'computed before prior best-known H=3 gains are joined for ', ...
    'attribution. Those gains come from earlier action families and are ', ...
    'not V65 outcomes. No new tracking or validation claim is authorized.'];

matPath = fullfile(outputRoot, ...
    'NETWORK_ADDITIVE_FORMATION_RISK_V65_M24_ATTRIBUTION.mat');
reportPath = fullfile(outputRoot, ...
    'NETWORK_ADDITIVE_FORMATION_RISK_V65_M24_ATTRIBUTION.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V65 M24 attribution report: %s\n', reportPath);
end

function record = makeFeatureRecord(target, metrics, selection)
record = emptyRecord();
record.presetName = target.presetName;
record.seed = target.seed;
record.currentTime = target.currentTime;
record.totalNetworkRescueFraction = ...
    metrics.totalNetworkRescueFraction;
record.totalNetworkUsefulLossFraction = ...
    metrics.totalNetworkUsefulLossFraction;
record.rescueFractionByFormation = ...
    metrics.networkRescueFractionByFormation;
record.usefulLossFractionByFormation = ...
    metrics.networkUsefulLossFractionByFormation;
record.upwardCrossingsByFormation = ...
    metrics.receiverSupportedUpwardCrossingsByFormation;
record.downwardCrossingsByFormation = ...
    metrics.crossSupportedDownwardCrossingsByFormation;
record.selection = selection;
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'totalNetworkRescueFraction', NaN, ...
    'totalNetworkUsefulLossFraction', NaN, ...
    'rescueFractionByFormation', zeros(1, 0), ...
    'usefulLossFractionByFormation', zeros(1, 0), ...
    'upwardCrossingsByFormation', zeros(1, 0), ...
    'downwardCrossingsByFormation', zeros(1, 0), ...
    'selection', struct(), ...
    'priorKnownGainPercent', NaN, ...
    'priorKnownGainSource', '');
end

function entry = resolveCase(cases, presetName, seed)
mask = strcmp({cases.presetName}, presetName) & [cases.seed] == seed;
if nnz(mask) ~= 1
    error('NetworkAdditiveM24V65:MissingCase', ...
        'The M24 target does not have one registered cache case.');
end
entry = cases(find(mask, 1));
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkAdditiveM24V65:WriteFailed', ...
        'Could not create the V65 M24 attribution report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V65 M24 network-additive attribution\n\n');
fprintf(fid, '- Strong-state trigger rate: `%.3f`\n', ...
    result.strongTriggerRate);
fprintf(fid, '- Weak-state fallback rate: `%.3f`\n', ...
    result.weakFallbackRate);
fprintf(fid, '- Network risk separates strong/weak: `%d`\n\n', ...
    result.networkRiskSeparatesStrongWeak);
fprintf(fid, ['| Preset | Time | Network risk | Useful loss | Action | ', ...
    'Formations | Coverage | Prior best-known gain |\n']);
fprintf(fid, '|:--|--:|--:|--:|:--:|:--|--:|--:|\n');
for record = result.records
    selection = record.selection;
    fprintf(fid, '| `%s` | %d | %.3f%% | %.3f%% | %d | `%s` | %.3f%% | %+.3f%% |\n', ...
        record.presetName, record.currentTime, ...
        100 * record.totalNetworkRescueFraction, ...
        100 * record.totalNetworkUsefulLossFraction, ...
        selection.actionEnabled, ...
        mat2str(selection.selectedFormationIds), ...
        100 * selection.achievedCoverageFraction, ...
        record.priorKnownGainPercent);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = meanOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
