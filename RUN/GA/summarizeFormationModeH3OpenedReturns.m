function [reportPath, summary] = ...
    summarizeFormationModeH3OpenedReturns(options)
% SUMMARIZEFORMATIONMODEH3OPENEDRETURNS Aggregate v11 teacher headroom.
%
% This summary is restricted to the five already-opened M24 first-divergence
% states.  It decides whether the local action bank contains enough H=3
% tail-safe oracle headroom to justify fitting a value model.  It does not
% evaluate a learned policy or support a validation claim.

if nargin < 1 || isempty(options)
    options = struct();
end
presetName = getField(options, ...
    'presetName', 'm24-formation-fov');
seedTimes = getField(options, 'seedTimes', [ ...
    83, 71; 97, 71; 89, 72; 101, 72; 103, 73]);
rootDirectory = getField(options, 'rootDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_mode_h3_v11', 'opened_return_screen', presetName));
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(rootDirectory, 'summary'));
minimumPositiveStateCount = round(getField( ...
    options, 'minimumPositiveStateCount', 3));
minimumStrongStateCount = round(getField( ...
    options, 'minimumStrongStateCount', 2));
strongGainThresholdPercent = getField( ...
    options, 'strongGainThresholdPercent', 5);
minimumMeanTailSafeGainPercent = getField( ...
    options, 'minimumMeanTailSafeGainPercent', 2);
formationGainTolerancePercent = getField( ...
    options, 'formationGainTolerancePercent', 0);
writeReportEnabled = logical(getField(options, 'writeReport', true));
if ~ischar(presetName) || ...
        size(seedTimes, 2) ~= 2 || isempty(seedTimes) || ...
        any(~isfinite(seedTimes(:))) || ...
        any(seedTimes(:) ~= round(seedTimes(:))) || ...
        minimumPositiveStateCount < 1 || ...
        minimumStrongStateCount < 1 || ...
        ~isscalar(strongGainThresholdPercent) || ...
        ~isfinite(strongGainThresholdPercent) || ...
        strongGainThresholdPercent <= 0 || ...
        ~isscalar(minimumMeanTailSafeGainPercent) || ...
        ~isfinite(minimumMeanTailSafeGainPercent) || ...
        minimumMeanTailSafeGainPercent <= 0 || ...
        ~isscalar(formationGainTolerancePercent) || ...
        ~isfinite(formationGainTolerancePercent) || ...
        formationGainTolerancePercent < 0
    error('Formation-mode H=3 summary options are invalid.');
end

rows = repmat(emptyRow(), 1, size(seedTimes, 1));
generationCommits = cell(1, size(seedTimes, 1));
allProxyObjective = zeros(0, 1);
allMeanGain = zeros(0, 1);
proxyTruePositiveCount = 0;
proxyFalsePositiveCount = 0;
proxyFalseNegativeCount = 0;
proxyTrueNegativeCount = 0;
for caseIdx = 1:size(seedTimes, 1)
    seed = seedTimes(caseIdx, 1);
    currentTime = seedTimes(caseIdx, 2);
    stem = sprintf( ...
        'FORMATION_MODE_H3_%s_SEED%d_T%d.mat', ...
        upper(strrep(presetName, '-', '_')), seed, currentTime);
    path = fullfile(rootDirectory, ...
        sprintf('seed%d', seed), stem);
    loaded = load(path, 'screen');
    if ~isfield(loaded, 'screen')
        error('Formation-mode H=3 screen is missing: %s', path);
    end
    screen = loaded.screen;
    validateScreen(screen, presetName, seed, currentTime);
    generationCommits{caseIdx} = ...
        screen.generationGitCommit;
    records = screen.records;
    meanGain = [records.meanGainPercent];
    minimumFormationGain = ...
        [records.minimumFormationGainPercent];
    tailSafe = minimumFormationGain >= ...
        -formationGainTolerancePercent - 1e-12;
    [bestMeanGain, bestMeanIdx] = max(meanGain);
    tailSafeIndices = find(tailSafe);
    [bestTailSafeGain, localIdx] = ...
        max(meanGain(tailSafeIndices));
    bestTailSafeIdx = tailSafeIndices(localIdx);
    row = emptyRow();
    row.seed = seed;
    row.currentTime = currentTime;
    row.path = path;
    row.actionCount = numel(records);
    row.bestMeanAction = records(bestMeanIdx).actionName;
    row.bestMeanGainPercent = bestMeanGain;
    row.bestMeanMinimumFormationGainPercent = ...
        records(bestMeanIdx).minimumFormationGainPercent;
    row.bestTailSafeAction = ...
        records(bestTailSafeIdx).actionName;
    row.bestTailSafeGainPercent = bestTailSafeGain;
    row.bestTailSafeWorstGainPercent = ...
        records(bestTailSafeIdx).worstGainPercent;
    row.bestTailSafeConsensusGainPercent = ...
        records(bestTailSafeIdx).consensusGainPercent;
    row.bestTailSafeByteSavingPercent = ...
        records(bestTailSafeIdx).attemptedByteSavingPercent;
    row.proxyAgreementFraction = ...
        screen.proxyActionAgreementFraction;
    row.proxyFalsePositiveCount = ...
        screen.proxyFalsePositiveCount;
    row.proxyFalseNegativeCount = ...
        screen.proxyFalseNegativeCount;
    row.allRuntimeGatesPassed = ...
        all(arrayfun(@recordRuntimePassed, records));
    rows(caseIdx) = row;

    nonreference = [records.actionIndex] ~= ...
        screen.bank.referenceActionIndex;
    proxyAllowed = [records.posteriorProxyAllowed] & nonreference;
    realizedPositive = meanGain > 0 & nonreference;
    proxyTruePositiveCount = proxyTruePositiveCount + ...
        nnz(proxyAllowed & realizedPositive);
    proxyFalsePositiveCount = proxyFalsePositiveCount + ...
        nnz(proxyAllowed & ~realizedPositive & nonreference);
    proxyFalseNegativeCount = proxyFalseNegativeCount + ...
        nnz(~[records.posteriorProxyAllowed] & ...
            realizedPositive & nonreference);
    proxyTrueNegativeCount = proxyTrueNegativeCount + ...
        nnz(~[records.posteriorProxyAllowed] & ...
            ~realizedPositive & nonreference);
    allProxyObjective = [allProxyObjective; ...
        reshape([records(nonreference).posteriorProxyObjective], ...
            [], 1)]; %#ok<AGROW>
    allMeanGain = [allMeanGain; ...
        reshape(meanGain(nonreference), [], 1)]; %#ok<AGROW>
end
if numel(unique(generationCommits)) ~= 1
    error('Formation-mode H=3 screens use different source commits.');
end

bestTailSafeGains = [rows.bestTailSafeGainPercent];
positiveStateCount = nnz(bestTailSafeGains > 1e-12);
strongStateCount = nnz( ...
    bestTailSafeGains >= strongGainThresholdPercent - 1e-12);
meanTailSafeGainPercent = mean(bestTailSafeGains);
allRuntimeGatesPassed = all([rows.allRuntimeGatesPassed]);
headroomGatePassed = ...
    allRuntimeGatesPassed && ...
    positiveStateCount >= minimumPositiveStateCount && ...
    strongStateCount >= minimumStrongStateCount && ...
    meanTailSafeGainPercent >= ...
        minimumMeanTailSafeGainPercent - 1e-12;

summary = struct();
summary.contractVersion = ...
    'formation-local-h3-opened-headroom-summary-v1';
summary.generatedAt = datestr(now, 31);
summary.presetName = presetName;
summary.seedTimes = seedTimes;
summary.generationCommit = generationCommits{1};
summary.rows = rows;
summary.formationGainTolerancePercent = ...
    formationGainTolerancePercent;
summary.minimumPositiveStateCount = minimumPositiveStateCount;
summary.minimumStrongStateCount = minimumStrongStateCount;
summary.strongGainThresholdPercent = ...
    strongGainThresholdPercent;
summary.minimumMeanTailSafeGainPercent = ...
    minimumMeanTailSafeGainPercent;
summary.positiveStateCount = positiveStateCount;
summary.strongStateCount = strongStateCount;
summary.meanTailSafeGainPercent = meanTailSafeGainPercent;
summary.allRuntimeGatesPassed = allRuntimeGatesPassed;
summary.proxyTruePositiveCount = proxyTruePositiveCount;
summary.proxyFalsePositiveCount = proxyFalsePositiveCount;
summary.proxyFalseNegativeCount = proxyFalseNegativeCount;
summary.proxyTrueNegativeCount = proxyTrueNegativeCount;
summary.proxyAgreementFraction = ...
    (proxyTruePositiveCount + proxyTrueNegativeCount) / ...
    max(proxyTruePositiveCount + proxyFalsePositiveCount + ...
        proxyFalseNegativeCount + proxyTrueNegativeCount, 1);
summary.proxyPearsonCorrelation = ...
    pearsonCorrelation(allProxyObjective, allMeanGain);
summary.headroomGatePassed = headroomGatePassed;
summary.modelTrainingAuthorized = headroomGatePassed;
summary.openedDevelopmentEvidenceOnly = true;
summary.validationClaimAllowed = false;
summary.evidenceBoundary = [ ...
    'This summary selects whether an opened M24 formation-local H=3 ', ...
    'teacher bank has enough oracle headroom to justify value-model ', ...
    'development. It does not evaluate a learned selector and cannot ', ...
    'support fresh M24 or X36 tracking claims.'];

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'FORMATION_MODE_H3_OPENED_HEADROOM_SUMMARY_V1.md');
    matPath = strrep(reportPath, '.md', '.mat');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    save('-mat7-binary', matPath, 'summary');
    writeReport(reportPath, summary);
    fprintf('Formation-mode H=3 summary: %s\n', reportPath);
end
end

function validateScreen( ...
        screen, presetName, seed, currentTime)
required = { ...
    'contractVersion', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'presetName', 'seed', 'currentTime', 'horizonSteps', ...
    'bank', 'actionIndices', 'outcomes', 'records', ...
    'featuresUseTruth', 'featuresUseFutureMeasurements', ...
    'featuresUseFutureOutcome', 'targetsUseTruth', ...
    'targetsUseFutureMeasurements', 'runtimePolicyUsesTruth', ...
    'openedDevelopmentEvidenceOnly', 'validationClaimAllowed'};
if ~isstruct(screen) || ~all(isfield(screen, required)) || ...
        ~strcmp(screen.contractVersion, ...
            'formation-local-h3-opened-return-screen-v1') || ...
        ~strcmp(screen.presetName, presetName) || ...
        screen.seed ~= seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= 3 || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        screen.featuresUseTruth || ...
        screen.featuresUseFutureMeasurements || ...
        screen.featuresUseFutureOutcome || ...
        ~screen.targetsUseTruth || ...
        ~screen.targetsUseFutureMeasurements || ...
        screen.runtimePolicyUsesTruth || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed || ...
        ~isequal(screen.actionIndices, reshape(find( ...
            screen.bank.actionWithinReferencePayload), 1, [])) || ...
        numel(screen.records) ~= numel(screen.actionIndices) || ...
        numel(screen.outcomes) ~= numel(screen.actionIndices)
    error('Formation-mode H=3 screen contract failed.');
end
for recordIdx = 1:numel(screen.records)
    record = screen.records(recordIdx);
    outcome = screen.outcomes(recordIdx);
    if record.actionIndex ~= screen.actionIndices(recordIdx) || ...
            ~strcmp(record.actionName, ...
                screen.bank.actionNames{record.actionIndex}) || ...
            ~record.selectedB3Passed || ...
            ~outcome.firstActionExact || ...
            outcome.truthUseCount ~= 0 || ...
            outcome.repairCount ~= 0 || ...
            outcome.payloadEmergencyCount ~= 0 || ...
            outcome.infeasibleCount ~= 0 || ...
            ~all(outcome.selectedSensorB3Pass) || ...
            ~all(outcome.selectedFormationB3Pass)
        error('Formation-mode H=3 action runtime audit failed.');
    end
end
end

function passed = recordRuntimePassed(record)
passed = record.selectedB3Passed && ...
    isfinite(record.meanGainPercent) && ...
    isfinite(record.worstGainPercent) && ...
    isfinite(record.minimumFormationGainPercent) && ...
    isfinite(record.consensusGainPercent) && ...
    isfinite(record.attemptedByteSavingPercent);
end

function value = pearsonCorrelation(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
finite = isfinite(left) & isfinite(right);
left = left(finite);
right = right(finite);
if numel(left) < 2 || std(left, 1) <= eps || ...
        std(right, 1) <= eps
    value = NaN;
    return;
end
centeredLeft = left - mean(left);
centeredRight = right - mean(right);
value = sum(centeredLeft .* centeredRight) / sqrt( ...
    sum(centeredLeft .^ 2) * sum(centeredRight .^ 2));
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'path', '', ...
    'actionCount', 0, ...
    'bestMeanAction', '', ...
    'bestMeanGainPercent', NaN, ...
    'bestMeanMinimumFormationGainPercent', NaN, ...
    'bestTailSafeAction', '', ...
    'bestTailSafeGainPercent', NaN, ...
    'bestTailSafeWorstGainPercent', NaN, ...
    'bestTailSafeConsensusGainPercent', NaN, ...
    'bestTailSafeByteSavingPercent', NaN, ...
    'proxyAgreementFraction', NaN, ...
    'proxyFalsePositiveCount', 0, ...
    'proxyFalseNegativeCount', 0, ...
    'allRuntimeGatesPassed', false);
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation-mode H=3 summary report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation-local H=3 opened headroom summary\n\n');
fprintf(fid, '- Contract: `%s`\n', summary.contractVersion);
fprintf(fid, '- Preset: `%s`\n', summary.presetName);
fprintf(fid, '- Generation commit: `%s`\n', ...
    summary.generationCommit);
fprintf(fid, '- Tail tolerance: `%.3f%%`\n', ...
    summary.formationGainTolerancePercent);
fprintf(fid, '- Positive states: `%d / %d` (gate `%d`)\n', ...
    summary.positiveStateCount, numel(summary.rows), ...
    summary.minimumPositiveStateCount);
fprintf(fid, '- Strong states (gain >= %.1f%%): `%d / %d` (gate `%d`)\n', ...
    summary.strongGainThresholdPercent, summary.strongStateCount, ...
    numel(summary.rows), summary.minimumStrongStateCount);
fprintf(fid, '- Mean best tail-safe gain: `%+.3f%%` (gate `>= %.3f%%`)\n', ...
    summary.meanTailSafeGainPercent, ...
    summary.minimumMeanTailSafeGainPercent);
fprintf(fid, '- Proxy TP / FP / FN / TN: `%d / %d / %d / %d`\n', ...
    summary.proxyTruePositiveCount, ...
    summary.proxyFalsePositiveCount, ...
    summary.proxyFalseNegativeCount, ...
    summary.proxyTrueNegativeCount);
fprintf(fid, '- Proxy agreement / Pearson correlation: `%.3f / %.3f`\n', ...
    summary.proxyAgreementFraction, ...
    summary.proxyPearsonCorrelation);
fprintf(fid, '- Runtime gates / headroom gate: `%d / %d`\n\n', ...
    summary.allRuntimeGatesPassed, summary.headroomGatePassed);
fprintf(fid, [ ...
    '| Seed-time | Best mean action | Mean gain | Min form. | ', ...
    'Best tail-safe action | Tail-safe gain | Worst gain | ', ...
    'Consensus gain | Byte saving | Proxy agree | Runtime |\n']);
fprintf(fid, ...
    '|:--|:--|--:|--:|:--|--:|--:|--:|--:|--:|:--:|\n');
for row = summary.rows
    fprintf(fid, [ ...
        '| `%d-%d` | `%s` | %+.3f%% | %+.3f%% | `%s` | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %.3f | %d |\n'], ...
        row.seed, row.currentTime, row.bestMeanAction, ...
        row.bestMeanGainPercent, ...
        row.bestMeanMinimumFormationGainPercent, ...
        row.bestTailSafeAction, row.bestTailSafeGainPercent, ...
        row.bestTailSafeWorstGainPercent, ...
        row.bestTailSafeConsensusGainPercent, ...
        row.bestTailSafeByteSavingPercent, ...
        row.proxyAgreementFraction, row.allRuntimeGatesPassed);
end
fprintf(fid, '\n## Decision\n\n');
if summary.headroomGatePassed
    fprintf(fid, [ ...
        'The opened teacher bank passes the preregistered headroom ', ...
        'gate and authorizes value-model development only.\n']);
else
    fprintf(fid, [ ...
        'The opened teacher bank fails the headroom gate. Expand or ', ...
        'replace the action bank before fitting a value model.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
