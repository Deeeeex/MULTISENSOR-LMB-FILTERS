function [datasetPath, dataset] = ...
    generatePrivilegedRollingSafeJointActionProposalDataset(options)
% GENERATEPRIVILEGEDROLLINGSAFEJOINTACTIONPROPOSALDATASET Offline targets.
%
% Generates truth-labelled teacher/diverse safe graphs on the same 18 M24
% predecision states as the truth-free proposal bank.  The resulting
% complete-graph targets are for proposal coverage and distillation only.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
truthFreePath = getField(options, 'truthFreeProposalPath', ...
    protocol.proposalDatasetRelativePath);
validateFrozenFile(sourcePath, ...
    protocol.proposalSourceStateSha256, 'source state');
validateFrozenFile(truthFreePath, ...
    protocol.proposalDatasetSha256, 'truth-free proposal dataset');
sourceLoaded = load(sourcePath, 'dataset');
truthFreeLoaded = load(truthFreePath, 'dataset');
sourceDataset = sourceLoaded.dataset;
truthFreeDataset = truthFreeLoaded.dataset;
if ~strcmp(sourceDataset.contractVersion, ...
        protocol.datasetContractVersion) || ...
        ~strcmp(truthFreeDataset.contractVersion, ...
            protocol.proposalDatasetContractVersion)
    error('Privileged proposal source contracts are inconsistent.');
end

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'datasets'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    ['rolling_safe_privileged_joint_action_proposals_', ...
     'm24_hard_t75_v1.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    ['ROLLING_SAFE_PRIVILEGED_JOINT_ACTION_PROPOSALS_', ...
     'M24_HARD_T75_V1.md']));

blockCount = numel(sourceDataset.blocks);
blocks = repmat(emptyBlock(), 1, blockCount);
expectedJointFeatureNames = {};
inputBySeed = cell(1, numel(protocol.datasetSeeds));
for seedIdx = 1:numel(protocol.datasetSeeds)
    seed = protocol.datasetSeeds(seedIdx);
    inputBySeed{seedIdx} = ...
        generateDynamicTopologyScenarioInputs( ...
            protocol.presetName, seed);
end
for blockIdx = 1:blockCount
    sourceBlock = sourceDataset.blocks(blockIdx);
    truthFreeBlock = findBlock( ...
        truthFreeDataset.blocks, ...
        sourceBlock.seed, sourceBlock.currentTime);
    seedIdx = find(protocol.datasetSeeds == ...
        sourceBlock.seed, 1);
    inputs = inputBySeed{seedIdx};
    context = reconstructContext( ...
        inputs, sourceBlock, truthFreeBlock);
    [candidateAdjacency, candidateRecords, metadata] = ...
        buildPrivilegedRollingSafeJointActionProposalBank(context);
    candidateCount = size(candidateAdjacency, 3);
    referenceAdjacency = truthFreeBlock.candidateAdjacency( ...
        :, :, truthFreeBlock.referenceCandidateIndex);
    candidateKeys = sub2ind( ...
        [inputs.config.numberOfSensors, ...
         inputs.config.numberOfSensors], ...
        sourceBlock.receiverIndices, ...
        sourceBlock.senderIndices);
    referenceCrossMask = reshape(logical( ...
        referenceAdjacency(candidateKeys)), [], 1);
    candidateCrossMasks = false( ...
        numel(candidateKeys), candidateCount);
    jointFeatures = zeros(candidateCount, 0);
    jointFeatureMetadata = cell(1, candidateCount);
    capturedByTruthFreeBank = false(1, candidateCount);
    matchedTruthFreeCandidateIndex = ...
        nan(1, candidateCount);
    truthFreeGraphSha256 = ...
        truthFreeBlock.candidateGraphSha256;
    for candidateIdx = 1:candidateCount
        adjacency = candidateAdjacency(:, :, candidateIdx);
        actionMask = reshape(logical( ...
            adjacency(candidateKeys)), [], 1);
        featureOptions = struct( ...
            'referenceCrossMask', referenceCrossMask, ...
            'actionProposalTruthUsed', true, ...
            'actionProposalOutcomeSelected', false, ...
            'actionProposalSource', ...
                metadata.contractVersion);
        [features, featureNames, featureMetadata] = ...
            computeRollingSafeJointActionFeatures( ...
                sourceBlock, actionMask, featureOptions);
        if isempty(expectedJointFeatureNames)
            expectedJointFeatureNames = featureNames;
        elseif ~isequal(expectedJointFeatureNames, featureNames)
            error('Privileged joint-action feature names drifted.');
        end
        if candidateIdx == 1
            jointFeatures = zeros( ...
                candidateCount, numel(features));
        end
        candidateCrossMasks(:, candidateIdx) = actionMask;
        jointFeatures(candidateIdx, :) = features;
        jointFeatureMetadata{candidateIdx} = featureMetadata;
        matchIdx = find(strcmp( ...
            truthFreeGraphSha256, ...
            candidateRecords(candidateIdx).graphSha256), 1);
        if ~isempty(matchIdx)
            capturedByTruthFreeBank(candidateIdx) = true;
            matchedTruthFreeCandidateIndex(candidateIdx) = matchIdx;
        end
    end
    block = emptyBlock();
    block.seed = sourceBlock.seed;
    block.currentTime = sourceBlock.currentTime;
    block.sourceBlockIndex = blockIdx;
    block.truthFreeProposalBlockIndex = ...
        findBlockIndex(truthFreeDataset.blocks, ...
            sourceBlock.seed, sourceBlock.currentTime);
    block.candidateCount = candidateCount;
    block.distillationTargetCount = ...
        metadata.distillationTargetCount;
    block.candidateActionCodes = ...
        [candidateRecords.actionCode];
    block.candidateGraphSha256 = ...
        {candidateRecords.graphSha256};
    block.candidateAdjacency = candidateAdjacency;
    block.candidateCrossMasks = candidateCrossMasks;
    block.jointFeatures = jointFeatures;
    block.jointFeatureMetadata = ...
        jointFeatureMetadata;
    block.candidateRecords = candidateRecords;
    block.proposalMetadata = metadata;
    block.capturedByTruthFreeBank = ...
        capturedByTruthFreeBank;
    block.matchedTruthFreeCandidateIndex = ...
        matchedTruthFreeCandidateIndex;
    blocks(blockIdx) = block;
    fprintf(['privileged proposals seed %d t=%d: ', ...
        '%d distinct, %d targets, %d truth-free matches\n'], ...
        block.seed, block.currentTime, ...
        block.candidateCount, block.distillationTargetCount, ...
        nnz(block.capturedByTruthFreeBank));
end

gitState = resolveResearchGitState();
dataset = struct();
dataset.protocolId = protocol.id;
dataset.contractVersion = ...
    'rolling-safe-privileged-joint-action-proposals-m24-v1';
dataset.proposalBankContractVersion = ...
    'privileged-rolling-safe-joint-action-proposal-bank-v1';
dataset.generatedAt = datestr(now, 31);
dataset.presetName = protocol.presetName;
dataset.seeds = protocol.datasetSeeds;
dataset.snapshotTimes = protocol.snapshotTimes;
dataset.sourceWeight = protocol.sourceWeight;
dataset.payloadToleranceFraction = inf;
dataset.actionCodes = [0, 90:99];
dataset.sourceStatePath = sourcePath;
dataset.sourceStateSha256 = ...
    protocol.proposalSourceStateSha256;
dataset.truthFreeProposalPath = truthFreePath;
dataset.truthFreeProposalSha256 = ...
    protocol.proposalDatasetSha256;
dataset.jointFeatureNames = ...
    expectedJointFeatureNames;
dataset.blocks = blocks;
dataset.truthUsed = true;
dataset.futureOutcomeUsed = false;
dataset.deployable = false;
dataset.returnEvaluated = false;
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.evidenceBoundary = [ ...
    'This artifact is an offline truth-labelled proposal-coverage ', ...
    'denominator and proposal-distillation target. It does not ', ...
    'evaluate H=3 return, authorize deployment, train a proposal ', ...
    'model or critic, establish top-K capture, or support X36.'];
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Privileged proposal dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);
end

function context = reconstructContext( ...
        inputs, sourceBlock, truthFreeBlock)
sensorCount = inputs.config.numberOfSensors;
if sourceBlock.seed ~= inputs.model. ...
        dynamicTopologyScenario.seed || ...
        sensorCount ~= numel(sourceBlock.groupIds)
    error('Privileged proposal scenario/state mismatch.');
end
context = struct();
context.localPosteriorBySensor = ...
    truthFreeBlock.initialLocalPosteriorBySensor;
context.model = inputs.model;
context.sensorTrajectories = ...
    inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = ...
    buildMixtureAwareKlaReferenceConfig();
context.currentTime = sourceBlock.currentTime;
context.previousAdjacencyHistory = ...
    sourceBlock.previousAdjacencyHistory;
context.previousAdjacencyHistoryCount = ...
    size(sourceBlock.previousAdjacencyHistory, 3);
context.previousAdjacencyHistoryTimes = ...
    sourceBlock.previousAdjacencyHistoryTimes;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacency = ...
    sourceBlock.previousAdjacencyHistory(:, :, end);
context.baseAdjacency = ...
    inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency( ...
        :, :, sourceBlock.currentTime);
context.edgeScores = ...
    double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = sensorCount;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}( ...
            1:2, sourceBlock.currentTime);
end
end

function block = findBlock(blocks, seed, currentTime)
block = blocks(findBlockIndex(blocks, seed, currentTime));
end

function index = findBlockIndex(blocks, seed, currentTime)
index = find([blocks.seed] == seed & ...
    [blocks.currentTime] == currentTime);
if numel(index) ~= 1
    error('Dataset lacks a unique seed-time block.');
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open privileged proposal report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
counts = [dataset.blocks.candidateCount];
targets = [dataset.blocks.distillationTargetCount];
captured = arrayfun(@(block) nnz( ...
    block.capturedByTruthFreeBank & ...
    [block.candidateRecords.eligibleForProposalDistillation]), ...
    dataset.blocks);
fprintf(fid, ...
    '# Privileged rolling-safe proposal targets: M24\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Generation tracked source dirty: `%d`\n', ...
    dataset.generationTrackedWorktreeDirty);
fprintf(fid, '- Truth used: `%d`\n', dataset.truthUsed);
fprintf(fid, '- Deployable: `%d`\n', dataset.deployable);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%s`\n', ...
    mat2str(dataset.snapshotTimes));
fprintf(fid, '- Action codes: `%s`\n', ...
    mat2str(dataset.actionCodes));
fprintf(fid, '- Distinct graphs min/mean/max: `%d / %.2f / %d`\n', ...
    min(counts), mean(counts), max(counts));
fprintf(fid, ...
    '- Distillation targets min/mean/max: `%d / %.2f / %d`\n', ...
    min(targets), mean(targets), max(targets));
fprintf(fid, ...
    '- Exact truth-free-bank graph matches: `%d / %d`\n', ...
    sum(captured), sum(targets));
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, '## State blocks\n\n');
fprintf(fid, ...
    ['| Seed | Time | Distinct | Targets | ', ...
     'Truth-free exact matches | Codes |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--|\n');
for block = dataset.blocks
    targetMask = ...
        [block.candidateRecords.eligibleForProposalDistillation];
    fprintf(fid, '| %d | %d | %d | %d | %d | `%s` |\n', ...
        block.seed, block.currentTime, block.candidateCount, ...
        block.distillationTargetCount, ...
        nnz(block.capturedByTruthFreeBank & targetMask), ...
        formatActionCodes(block.candidateActionCodes));
end
end

function block = emptyBlock()
block = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'sourceBlockIndex', NaN, ...
    'truthFreeProposalBlockIndex', NaN, ...
    'candidateCount', 0, ...
    'distillationTargetCount', 0, ...
    'candidateActionCodes', [], ...
    'candidateGraphSha256', {cell(1, 0)}, ...
    'candidateAdjacency', false(0, 0, 0), ...
    'candidateCrossMasks', false(0, 0), ...
    'jointFeatures', zeros(0, 0), ...
    'jointFeatureMetadata', {cell(1, 0)}, ...
    'candidateRecords', repmat(struct(), 1, 0), ...
    'proposalMetadata', struct(), ...
    'capturedByTruthFreeBank', false(1, 0), ...
    'matchedTruthFreeCandidateIndex', []);
end

function token = formatActionCodes(actionCodes)
parts = arrayfun(@(code) sprintf('%02d', code), ...
    reshape(actionCodes, 1, []), 'UniformOutput', false);
token = strjoin(parts, '-');
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
