function [reportPath, dataset] = ...
        buildCausalTwoStageGraphValueDatasetV219( ...
            resultPaths, options)
% BUILDCAUSALTWOSTAGEGRAPHVALUEDATASETV219 Assemble trajectory groups.

if nargin < 2 || isempty(options)
    options = struct();
end
if ischar(resultPaths)
    resultPaths = {resultPaths};
end
if ~iscell(resultPaths) || isempty(resultPaths) || ...
        any(cellfun(@(path) ~ischar(path) || ...
            exist(path, 'file') ~= 2, resultPaths))
    error('CausalGraphValueDatasetV219:InvalidInput', ...
        'One or more completed V218 three-arm MAT files are required.');
end
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v219', 'training_dataset')));

precommunication = repmat(emptyPrecommunication(), 1, 0);
postfusion = repmat(emptyPostfusion(), 1, 0);
trajectoryKeys = cell(1, numel(resultPaths));
targetNames = cell(1, 0);
for trajectoryIdx = 1:numel(resultPaths)
    loaded = load(resultPaths{trajectoryIdx}, 'result');
    result = loaded.result;
    validateResult(result);
    if trajectoryIdx == 1
        targetNames = result.targetNames;
    elseif ~isequal(targetNames, result.targetNames)
        error('CausalGraphValueDatasetV219:TargetDrift', ...
            'V218 target names changed across trajectories.');
    end
    trajectoryKey = sprintf('%s|%s|seed=%d', ...
        result.splitName, result.presetName, result.seed);
    trajectoryKeys{trajectoryIdx} = trajectoryKey;
    for stateIdx = 1:numel(result.states)
        state = result.states(stateIdx);
        encoding = encodeDirectGraphFormationStateV219( ...
            state.formationGraph, state.targetFormationRow);
        withholding = state.actions(2);
        precommunication(end + 1) = buildPrecommunication( ...
            trajectoryIdx, trajectoryKey, result, state, ...
            encoding, withholding); %#ok<AGROW>
        for actionIdx = reshape( ...
                state.postfusionActionIndices(2:end), 1, [])
            action = state.actions(actionIdx);
            if ~strcmp(action.kind, ...
                    'withholding-plus-complete-label-kla')
                error('CausalGraphValueDatasetV219:RepairActionDrift', ...
                    'A post-fusion candidate is not a complete-label KLA.');
            end
            sourceEncoding = encodeDirectGraphFormationStateV219( ...
                state.formationGraph, action.sourceFormationRow);
            postfusion(end + 1) = buildPostfusion( ...
                trajectoryIdx, trajectoryKey, result, state, ...
                encoding, sourceEncoding, action); %#ok<AGROW>
        end
    end
end

if numel(unique(trajectoryKeys)) ~= numel(trajectoryKeys)
    error('CausalGraphValueDatasetV219:DuplicateTrajectory', ...
        'Each complete scene-seed trajectory may appear only once.');
end
dataset = struct();
dataset.contractVersion = ...
    'causal-two-stage-graph-value-dataset-v219-v1';
dataset.generatedAt = datestr(now, 31);
dataset.sourceResultPaths = resultPaths;
dataset.trajectoryKeys = trajectoryKeys;
dataset.trajectoryCount = numel(trajectoryKeys);
dataset.targetNames = targetNames;
dataset.precommunication = precommunication;
dataset.precommunicationExampleCount = numel(precommunication);
dataset.postfusion = postfusion;
dataset.postfusionExampleCount = numel(postfusion);
dataset.splitUnit = 'complete-scene-seed-trajectory';
dataset.randomStateLevelSplitAllowed = false;
dataset.numericSensorIdentifiersUsedAsFeatures = false;
dataset.numericFormationIdentifiersUsedAsFeatures = false;
dataset.truthUsedForFeatures = false;
dataset.futureInformationUsedForFeatures = false;
dataset.truthUsedForTargets = true;
dataset.validationClaimAllowed = false;
dataset.evidenceBoundary = [ ...
    'V219 groups every V218 state by complete scene-seed trajectory. ', ...
    'Precommunication examples predict withholding relative to no-op; ', ...
    'post-fusion examples predict one complete-label KLA relative to ', ...
    'the paired withholding result. Numeric identifiers are lookup ', ...
    'metadata only. State-level random splitting is forbidden.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'CAUSAL_TWO_STAGE_GRAPH_VALUE_DATASET_V219.mat');
reportPath = fullfile(outputRoot, ...
    'CAUSAL_TWO_STAGE_GRAPH_VALUE_DATASET_V219.md');
dataset.matPath = matPath;
dataset.reportPath = reportPath;
save('-mat7-binary', matPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('V219 causal two-stage dataset: %s\n', reportPath);
end

function item = buildPrecommunication( ...
        trajectoryIdx, trajectoryKey, result, state, ...
        encoding, withholding)
item = emptyPrecommunication();
item.trajectoryIndex = trajectoryIdx;
item.trajectoryKey = trajectoryKey;
item.presetName = result.presetName;
item.seed = result.seed;
item.stratumName = state.stratumName;
item.currentTime = state.currentTime;
item.formationCount = state.formationGraph.formationCount;
item.localFeatureNames = state.formationGraph.nodeFeatureNames;
item.localFeatureVector = state.formationGraph. ...
    nodeFeatures(state.targetFormationRow, :);
item.graphFeatureNames = encoding.featureNames;
item.graphFeatureVector = encoding.featureVector;
item.targetGainVectorPercent = withholding.gainVectorPercent;
item.targetAttemptedByteSavingPercent = ...
    withholding.attemptedByteSavingPercent;
item.riskPassed = withholding.riskPassed;
item.byteReservePassed = withholding.byteReservePassed;
item.causallyAdmissible = withholding.causallyAdmissible;
end

function item = buildPostfusion( ...
        trajectoryIdx, trajectoryKey, result, state, ...
        targetEncoding, sourceEncoding, action)
item = emptyPostfusion();
item.trajectoryIndex = trajectoryIdx;
item.trajectoryKey = trajectoryKey;
item.presetName = result.presetName;
item.seed = result.seed;
item.stratumName = state.stratumName;
item.currentTime = state.currentTime;
item.formationCount = state.formationGraph.formationCount;
item.graphFeatureNames = [ ...
    prefixNames(targetEncoding.featureNames, 'receiver_'), ...
    prefixNames(sourceEncoding.featureNames, 'source_'), ...
    prefixNames(state.repairActionFeatureNames, 'candidate_')];
item.graphFeatureVector = [ ...
    targetEncoding.featureVector, sourceEncoding.featureVector, ...
    action.actionFeatureVector];
item.candidateFeatureNames = state.repairActionFeatureNames;
item.candidateFeatureVector = action.actionFeatureVector;
item.targetIncrementalGainVectorPercent = ...
    action.incrementalFromWithholdingGainVectorPercent;
item.targetFinalGainVectorPercent = action.gainVectorPercent;
item.targetAttemptedByteSavingPercent = ...
    action.attemptedByteSavingPercent;
item.payloadAttemptedBytes = action.payloadAttemptedBytes;
item.creditFeasible = action.creditFeasible;
item.incrementalRiskPassed = action.incrementalRiskPassed;
item.causallyAdmissible = action.causallyAdmissible;
end

function validateResult(result)
required = {'contractVersion', 'presetName', 'seed', 'splitName', ...
    'targetNames', 'states', 'truthUsedAtRuntime', ...
    'futureInformationUsedAtRuntime', 'truthUsedForH3Targets', ...
    'causalTwoStageDecisionRequired', ...
    'withholdingMustBeSafeWithoutRepair', ...
    'repairMayAuthorizeUnsafeWithholding', ...
    'validationClaimAllowed'};
if ~isstruct(result) || ~isscalar(result) || ...
        any(~isfield(result, required)) || ...
        ~strcmp(result.contractVersion, ...
            'stratified-direct-graph-three-arm-h3-v218-v1') || ...
        result.truthUsedAtRuntime || ...
        result.futureInformationUsedAtRuntime || ...
        ~result.truthUsedForH3Targets || ...
        ~result.causalTwoStageDecisionRequired || ...
        ~result.withholdingMustBeSafeWithoutRepair || ...
        result.repairMayAuthorizeUnsafeWithholding || ...
        result.validationClaimAllowed
    error('CausalGraphValueDatasetV219:ResultContract', ...
        'A source V218 label result is malformed.');
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('CausalGraphValueDatasetV219:WriteReport', ...
        'Could not write the V219 dataset report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V219 causal two-stage graph-value dataset\n\n');
fprintf(fid, '- Complete trajectory groups: `%d`\n', ...
    dataset.trajectoryCount);
fprintf(fid, '- Precommunication examples: `%d`\n', ...
    dataset.precommunicationExampleCount);
fprintf(fid, '- Post-fusion repair examples: `%d`\n', ...
    dataset.postfusionExampleCount);
fprintf(fid, '- Random state-level split allowed: `0`\n\n');
fprintf(fid, '| Trajectory group | Precommunication | Post-fusion |\n');
fprintf(fid, '|:--|--:|--:|\n');
for idx = 1:dataset.trajectoryCount
    preCount = nnz([dataset.precommunication.trajectoryIndex] == idx);
    postCount = nnz([dataset.postfusion.trajectoryIndex] == idx);
    fprintf(fid, '| %s | %d | %d |\n', ...
        dataset.trajectoryKeys{idx}, preCount, postCount);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function item = emptyPrecommunication()
item = struct( ...
    'trajectoryIndex', 0, 'trajectoryKey', '', ...
    'presetName', '', 'seed', 0, 'stratumName', '', ...
    'currentTime', 0, 'formationCount', 0, ...
    'localFeatureNames', {cell(1, 0)}, ...
    'localFeatureVector', zeros(1, 0), ...
    'graphFeatureNames', {cell(1, 0)}, ...
    'graphFeatureVector', zeros(1, 0), ...
    'targetGainVectorPercent', zeros(1, 12), ...
    'targetAttemptedByteSavingPercent', 0, ...
    'riskPassed', false, 'byteReservePassed', false, ...
    'causallyAdmissible', false);
end

function item = emptyPostfusion()
item = struct( ...
    'trajectoryIndex', 0, 'trajectoryKey', '', ...
    'presetName', '', 'seed', 0, 'stratumName', '', ...
    'currentTime', 0, 'formationCount', 0, ...
    'graphFeatureNames', {cell(1, 0)}, ...
    'graphFeatureVector', zeros(1, 0), ...
    'candidateFeatureNames', {cell(1, 0)}, ...
    'candidateFeatureVector', zeros(1, 0), ...
    'targetIncrementalGainVectorPercent', zeros(1, 12), ...
    'targetFinalGainVectorPercent', zeros(1, 12), ...
    'targetAttemptedByteSavingPercent', 0, ...
    'payloadAttemptedBytes', 0, 'creditFeasible', false, ...
    'incrementalRiskPassed', false, ...
    'causallyAdmissible', false);
end

function output = prefixNames(names, prefix)
output = cell(size(names));
for idx = 1:numel(names)
    output{idx} = [prefix, names{idx}];
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
