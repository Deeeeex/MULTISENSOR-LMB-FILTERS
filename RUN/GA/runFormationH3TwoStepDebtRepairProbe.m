function [reportPath, probe] = ...
    runFormationH3TwoStepDebtRepairProbe(options)
% RUNFORMATIONH3TWOSTEPDEBTREPAIRPROBE Structured two-step teacher beam.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3TwoStepDebtRepairProbeProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official two-step debt-repair probe requires clean source.');
end
outputRoot = getField(options, 'outputDirectory', protocol.outputRoot);
probePath = fullfile(outputRoot, ...
    'formation_h3_two_step_debt_repair_beam_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_H3_TWO_STEP_DEBT_REPAIR_BEAM_V1.md');
probeExists = exist(probePath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(probeExists, reportExists)
    error('Two-step debt-repair probe artifacts are partial.');
elseif probeExists
    loaded = load(probePath, 'probe');
    if ~isfield(loaded, 'probe') || ...
            ~strcmp(loaded.probe.protocolId, protocol.id) || ...
            ~strcmp(loaded.probe.generationGitCommit, gitState.commit)
        error('Two-step debt-repair probe provenance mismatch.');
    end
    probe = loaded.probe;
    fprintf('Reused two-step debt-repair probe: %s\n', probePath);
    return;
end

prefixModes = protocol.prefixModeVectors;
prefixActions = formationModeVectorToActionIndex( ...
    prefixModes, protocol.modeCount);
[repairModes, repairActions] = ...
    enumerateFormationModeCartesianProduct( ...
        protocol.repairModeChoices, protocol.modeCount);
if size(prefixModes, 1) ~= protocol.expectedPrefixCount || ...
        size(repairModes, 1) ~= protocol.expectedRepairCount || ...
        ~isequal(repairModes(1, :), ...
            protocol.referenceModeVector) || ...
        repairActions(1) ~= protocol.referenceActionIndex
    error('Two-step debt-repair candidate contract changed.');
end

prefixCount = size(prefixModes, 1);
repairCount = size(repairModes, 1);
sequenceCount = prefixCount * repairCount;
sequences = zeros(sequenceCount, protocol.horizonSteps);
prefixIndexBySequence = zeros(sequenceCount, 1);
repairIndexBySequence = zeros(sequenceCount, 1);
for prefixIdx = 1:prefixCount
    rows = (prefixIdx - 1) * repairCount + (1:repairCount);
    sequences(rows, 1) = prefixActions(prefixIdx);
    sequences(rows, 2) = repairActions;
    sequences(rows, 3) = protocol.referenceActionIndex;
    prefixIndexBySequence(rows) = prefixIdx;
    repairIndexBySequence(rows) = (1:repairCount)';
end
if sequenceCount ~= protocol.expectedSequenceCount || ...
        size(unique(sequences, 'rows'), 1) ~= sequenceCount
    error('Two-step debt-repair sequence enumeration changed.');
end

screenDirectory = fullfile(outputRoot, 'screen');
screenOptions = struct( ...
    'cacheRoot', protocol.cacheRoot, ...
    'outputDirectory', screenDirectory, ...
    'interventionBankType', protocol.interventionBankType, ...
    'actionSequenceIndices', sequences, ...
    'writeReport', true);
[screenReportPath, screen] = ...
    runFormationModeH3OpenedReturnScreen( ...
        protocol.presetName, protocol.seed, ...
        protocol.currentTime, screenOptions);
if screen.bank.actionCount ~= protocol.expectedActionCount || ...
        ~isequal(screen.bank.actionModes(prefixActions, :), ...
            prefixModes) || ...
        ~isequal(screen.bank.actionModes(repairActions, :), ...
            repairModes)
    error('Two-step debt-repair action bank changed.');
end

targets = targetMatrix(screen);
prefixReferenceRows = find(repairIndexBySequence == 1);
reproductionError = abs(targets(prefixReferenceRows, :) - ...
    protocol.expectedPrefixTargets);
if numel(prefixReferenceRows) ~= prefixCount || ...
        max(reproductionError(:)) > ...
            protocol.reproductionTolerancePercent
    error('Two-step debt-repair prefix reproduction gate failed.');
end

referenceSequence = all(sequences == ...
    protocol.referenceActionIndex, 2);
nonreferenceSequence = ~referenceSequence;
strictFeasible = all(targets >= -1e-12, 2);
strongSafe = strictFeasible & ...
    targets(:, 1) >= protocol.strongGainPercent - 1e-12;
strictIndices = find(strictFeasible);
[strictGain, strictLocal] = max(targets(strictIndices, 1));
strictOracleIndex = strictIndices(strictLocal);
strongIndices = find(strongSafe);

strongThresholds = [protocol.strongGainPercent, zeros(1, 5)];
normalizedStrongDeficits = max( ...
    strongThresholds - targets, 0) ./ ...
        protocol.constraintScalesPercent;
maximumStrongDeficit = max(normalizedStrongDeficits, [], 2);
totalStrongDeficit = sum(normalizedStrongDeficits, 2);
ranking = [ ...
    maximumStrongDeficit, totalStrongDeficit, ...
    -targets(:, 1), prefixIndexBySequence, repairIndexBySequence];
[~, rankOrder] = sortrows(ranking, [1, 2, 3, 4, 5]);
closestIndex = rankOrder(1);
[bestMeanGain, bestMeanIndex] = max(targets(:, 1));

prefixSummary = buildPrefixSummary( ...
    prefixModes, prefixIndexBySequence, repairIndexBySequence, ...
    repairModes, targets, strictFeasible, strongSafe, ...
    maximumStrongDeficit, totalStrongDeficit);

probe = struct();
probe.contractVersion = ...
    'formation-h3-two-step-debt-repair-probe-result-v1';
probe.protocolId = protocol.id;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
probe.cacheProtocolId = protocol.cacheProtocolId;
probe.cacheGenerationGitCommit = ...
    protocol.cacheGenerationGitCommit;
probe.presetName = protocol.presetName;
probe.seed = protocol.seed;
probe.currentTime = protocol.currentTime;
probe.sequences = sequences;
probe.targets = targets;
probe.prefixModeVectors = prefixModes;
probe.prefixActionIndices = prefixActions;
probe.prefixRoles = protocol.prefixRoles;
probe.repairModeVectors = repairModes;
probe.repairActionIndices = repairActions;
probe.prefixIndexBySequence = prefixIndexBySequence;
probe.repairIndexBySequence = repairIndexBySequence;
probe.referenceSequence = referenceSequence;
probe.strictFeasible = strictFeasible;
probe.strongSafe = strongSafe;
probe.strictFeasibleSequenceCount = nnz(strictFeasible);
probe.strictFeasibleNonreferenceCount = ...
    nnz(strictFeasible & nonreferenceSequence);
probe.strongSafeSequenceCount = nnz(strongSafe);
probe.strongSafeSequenceFound = any(strongSafe);
probe.strictOracleIndex = strictOracleIndex;
probe.strictOraclePrefixModeVector = ...
    prefixModes(prefixIndexBySequence(strictOracleIndex), :);
probe.strictOracleRepairModeVector = ...
    repairModes(repairIndexBySequence(strictOracleIndex), :);
probe.strictOracleTargets = targets(strictOracleIndex, :);
probe.strictOracleGainPercent = strictGain;
if isempty(strongIndices)
    probe.strongOracleIndex = 0;
    probe.strongOraclePrefixModeVector = [];
    probe.strongOracleRepairModeVector = [];
    probe.strongOracleTargets = [];
else
    [~, strongLocal] = max(targets(strongIndices, 1));
    probe.strongOracleIndex = strongIndices(strongLocal);
    probe.strongOraclePrefixModeVector = prefixModes( ...
        prefixIndexBySequence(probe.strongOracleIndex), :);
    probe.strongOracleRepairModeVector = repairModes( ...
        repairIndexBySequence(probe.strongOracleIndex), :);
    probe.strongOracleTargets = targets( ...
        probe.strongOracleIndex, :);
end
probe.normalizedStrongConstraintDeficits = ...
    normalizedStrongDeficits;
probe.maximumStrongConstraintDeficit = maximumStrongDeficit;
probe.totalStrongConstraintDeficit = totalStrongDeficit;
probe.sequenceRankOrder = rankOrder;
probe.closestIndex = closestIndex;
probe.closestPrefixModeVector = ...
    prefixModes(prefixIndexBySequence(closestIndex), :);
probe.closestRepairModeVector = ...
    repairModes(repairIndexBySequence(closestIndex), :);
probe.closestTargets = targets(closestIndex, :);
probe.bestMeanIndex = bestMeanIndex;
probe.bestMeanPrefixModeVector = ...
    prefixModes(prefixIndexBySequence(bestMeanIndex), :);
probe.bestMeanRepairModeVector = ...
    repairModes(repairIndexBySequence(bestMeanIndex), :);
probe.bestMeanTargets = targets(bestMeanIndex, :);
probe.bestMeanGainPercent = bestMeanGain;
probe.prefixSummary = prefixSummary;
probe.screen = screen;
probe.screenReportPath = screenReportPath;
probe.actionSelectionUsesTruth = protocol.actionSelectionUsesTruth;
probe.actionSelectionUsesFutureMeasurements = ...
    protocol.actionSelectionUsesFutureMeasurements;
probe.runtimePolicyUsesTruth = protocol.runtimePolicyUsesTruth;
probe.openedTrainingMechanismProbeOnly = true;
probe.teacherModelTrainingAuthorized = ...
    probe.strongSafeSequenceFound;
probe.finalModelTrainingAuthorized = false;
probe.validationClaimAllowed = false;
probe.evidenceBoundary = protocol.evidenceBoundary;
probe.probePath = probePath;
probe.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', probePath, 'probe');
writeReport(reportPath, probe);
fprintf('Two-step debt-repair probe: %s\n', probePath);
fprintf(['Strict=%d/%d; strong=%d; strict oracle gain=%+.6f%%; ', ...
    'teacher-training-authorized=%d\n'], ...
    probe.strictFeasibleSequenceCount, ...
    sequenceCount, probe.strongSafeSequenceCount, ...
    probe.strictOracleGainPercent, ...
    probe.teacherModelTrainingAuthorized);
end

function summary = buildPrefixSummary( ...
        prefixModes, prefixIndexBySequence, repairIndexBySequence, ...
        repairModes, targets, strictFeasible, strongSafe, ...
        maximumStrongDeficit, totalStrongDeficit)
prefixCount = size(prefixModes, 1);
summary = repmat(struct( ...
    'prefixModeVector', [], ...
    'strictCount', 0, ...
    'strongCount', 0, ...
    'bestStrictMeanGainPercent', NaN, ...
    'closestRepairModeVector', [], ...
    'closestTargets', []), prefixCount, 1);
for prefixIdx = 1:prefixCount
    rows = find(prefixIndexBySequence == prefixIdx);
    strictRows = rows(strictFeasible(rows));
    if ~isempty(strictRows)
        summary(prefixIdx).bestStrictMeanGainPercent = ...
            max(targets(strictRows, 1));
    end
    localRanking = [ ...
        maximumStrongDeficit(rows), totalStrongDeficit(rows), ...
        -targets(rows, 1), repairIndexBySequence(rows)];
    [~, order] = sortrows(localRanking, [1, 2, 3, 4]);
    closestRow = rows(order(1));
    summary(prefixIdx).prefixModeVector = prefixModes(prefixIdx, :);
    summary(prefixIdx).strictCount = nnz(strictFeasible(rows));
    summary(prefixIdx).strongCount = nnz(strongSafe(rows));
    summary(prefixIdx).closestRepairModeVector = repairModes( ...
        repairIndexBySequence(closestRow), :);
    summary(prefixIdx).closestTargets = targets(closestRow, :);
end
end

function targets = targetMatrix(screen)
records = screen.records;
outcomes = screen.outcomes;
reference = outcomes(screen.referenceSubsetIndex);
delivered = zeros(numel(outcomes), 1);
for idx = 1:numel(outcomes)
    delivered(idx) = 100 * ...
        (reference.deliveredBytes - outcomes(idx).deliveredBytes) / ...
        max(reference.deliveredBytes, eps);
end
targets = [ ...
    reshape([records.meanGainPercent], [], 1), ...
    reshape([records.minimumFormationGainPercent], [], 1), ...
    reshape([records.worstGainPercent], [], 1), ...
    reshape([records.consensusGainPercent], [], 1), ...
    reshape([records.attemptedByteSavingPercent], [], 1), ...
    delivered];
end

function writeReport(path, probe)
fid = fopen(path, 'w');
if fid < 0
    error('Cannot write two-step debt-repair report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 two-step debt-repair beam\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    probe.contractVersion, probe.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    probe.generationGitCommit);
fprintf(fid, '- Cache protocol / commit: `%s / %s`\n', ...
    probe.cacheProtocolId, probe.cacheGenerationGitCommit);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    probe.presetName, probe.seed, probe.currentTime);
fprintf(fid, '- Strict feasible: `%d/%d`\n', ...
    probe.strictFeasibleSequenceCount, size(probe.sequences, 1));
fprintf(fid, '- Strict nonreference: `%d/%d`\n', ...
    probe.strictFeasibleNonreferenceCount, ...
    size(probe.sequences, 1) - 1);
fprintf(fid, '- Strong safe: `%d/%d`\n', ...
    probe.strongSafeSequenceCount, size(probe.sequences, 1));
fprintf(fid, '- Strict oracle prefix / repair / gain: `%s / %s / %+.6f%%`\n', ...
    mat2str(probe.strictOraclePrefixModeVector), ...
    mat2str(probe.strictOracleRepairModeVector), ...
    probe.strictOracleGainPercent);
if probe.strongSafeSequenceFound
    fprintf(fid, '- Strong oracle prefix / repair / targets: `%s / %s / %s`\n', ...
        mat2str(probe.strongOraclePrefixModeVector), ...
        mat2str(probe.strongOracleRepairModeVector), ...
        mat2str(probe.strongOracleTargets, 7));
else
    fprintf(fid, '- Strong oracle: `none`\n');
end
fprintf(fid, '- Closest prefix / repair / targets: `%s / %s / %s`\n', ...
    mat2str(probe.closestPrefixModeVector), ...
    mat2str(probe.closestRepairModeVector), ...
    mat2str(probe.closestTargets, 7));
fprintf(fid, '- Best-mean prefix / repair / targets: `%s / %s / %s`\n\n', ...
    mat2str(probe.bestMeanPrefixModeVector), ...
    mat2str(probe.bestMeanRepairModeVector), ...
    mat2str(probe.bestMeanTargets, 7));

fprintf(fid, '## Prefix summary\n\n');
fprintf(fid, ['| Prefix | Strict | Strong | Best strict mean | ', ...
    'Closest repair | Closest targets |\n']);
fprintf(fid, '|:--|--:|--:|--:|:--|:--|\n');
for idx = 1:numel(probe.prefixSummary)
    item = probe.prefixSummary(idx);
    fprintf(fid, '| `%s` | %d | %d | %s | `%s` | `%s` |\n', ...
        formatModeVector(item.prefixModeVector), item.strictCount, ...
        item.strongCount, formatPercent(item.bestStrictMeanGainPercent), ...
        formatModeVector(item.closestRepairModeVector), ...
        mat2str(item.closestTargets, 5));
end

fprintf(fid, '\n## Strong-constraint ranking\n\n');
fprintf(fid, ['| Rank | Prefix | Repair | Mean | Min. formation | ', ...
    'Worst sensor | Consensus | Attempted | Delivered | Strict | Strong |\n']);
fprintf(fid, '|--:|:--|:--|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
topCount = min(20, numel(probe.sequenceRankOrder));
for rankIdx = 1:topCount
    idx = probe.sequenceRankOrder(rankIdx);
    prefix = probe.prefixModeVectors( ...
        probe.prefixIndexBySequence(idx), :);
    repair = probe.repairModeVectors( ...
        probe.repairIndexBySequence(idx), :);
    targets = probe.targets(idx, :);
    fprintf(fid, ['| %d | `%s` | `%s` | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d | %d |\n'], ...
        rankIdx, formatModeVector(prefix), formatModeVector(repair), ...
        targets(1), targets(2), targets(3), targets(4), ...
        targets(5), targets(6), probe.strictFeasible(idx), ...
        probe.strongSafe(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    probe.evidenceBoundary);
end

function value = formatModeVector(modes)
value = strtrim(sprintf('%d ', reshape(modes, 1, [])));
end

function value = formatPercent(number)
if isnan(number)
    value = 'none';
else
    value = sprintf('%+.3f%%', number);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
