function outcome = runContinuation( ...
        inputs, truth, initialPosteriors, history, ...
        previousPolicyHistory, updateHistory, anchorTime, ...
        config, executionContext, seed, protocol)
returnTimes = anchorTime + (0:(executionContext.horizonSteps - 1));
runInputs = cropInputs(inputs, returnTimes(end));
config.topologyPosteriorCaptureTimes = returnTimes;
config.filterInitialLocalPosteriorBySensor = initialPosteriors;
config.filterInitialLocalPosteriorTime = anchorTime;
config.filterInitialPreviousAdjacencyHistory = previousPolicyHistory;
config.filterInitialPreviousAdjacencyTimes = history.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'v134-paired-reference-prefix';
config.filterInitialLocalUpdateHistoryTimes = updateHistory.times;
config.filterInitialLocalInnovationHistory = updateHistory.innovation;
config.filterInitialLocalAssociationConfidenceHistory = ...
    updateHistory.associationConfidence;
config.filterInitialLocalNisNormHistory = updateHistory.nisNorm;
config.filterInitialLocalNisDeviationHistory = updateHistory.nisDeviation;
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    runInputs.model, runInputs.measurements, ...
    runInputs.sensorTrajectories, runInputs.neighborMap, ...
    runInputs.commConfig, config, executionContext);
elapsedSeconds = toc(timerId);
auditRuntime(diagnostics, returnTimes);
outcome = scoreOutcome( ...
    runInputs.model, truth, estimates, diagnostics, ...
    runInputs.commConfig, returnTimes, elapsedSeconds);
end

function outcome = scoreOutcome( ...
        model, truth, estimates, diagnostics, commConfig, ...
        returnTimes, elapsedSeconds)
nodeCount = numel(estimates);
eospa = zeros(nodeCount, numel(returnTimes));
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, ~] = computeSimulationOspa( ...
        model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(returnTimes);
end
outcome = struct();
outcome.eospaBySensorTime = eospa;
outcome.posteriorConsensusByTime = reshape( ...
    diagnostics.posteriorConsensusCombined(returnTimes), 1, []);
outcome.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes(:, :, returnTimes), 1), 2), ...
    1, []);
outcome.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes(:, :, returnTimes), 1), 2), 1, []);
outcome.controlSynopsisBytesByTime = reshape( ...
    diagnostics.receiverSafeAttemptedControlSynopsisBytes( ...
        returnTimes), 1, []);
outcome.elapsedSeconds = elapsedSeconds;
outcome.selectedAdjacencyByTime = false( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.nominalFusionWeightsByTime = zeros( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.controlledAdmissionEdgeByTime = false( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.executedAbstentionEdgeByTime = false( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.executedAdmissionFactorByTime = ones( ...
    nodeCount, nodeCount, numel(returnTimes));
for timeIdx = 1:numel(returnTimes)
    currentTime = returnTimes(timeIdx);
    outcome.selectedAdjacencyByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge(:, :, currentTime));
    outcome.nominalFusionWeightsByTime(:, :, timeIdx) = ...
        diagnostics.topologyPolicyFusionWeightMatrix{currentTime};
    outcome.controlledAdmissionEdgeByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.receiverSafeSelectiveEdge( ...
                :, :, currentTime));
    outcome.executedAbstentionEdgeByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.receiverSafeAbstainFromFusionEdge( ...
                :, :, currentTime));
    outcome.executedAdmissionFactorByTime(:, :, timeIdx) = ...
        diagnostics.receiverSafeFusionTrustFactor( ...
            :, :, currentTime)';
end
outcome.pDropByEdgeByTime = commConfig.pDropByEdge( ...
    :, :, returnTimes);
outcome.attemptedEdgeByTime = logical( ...
    diagnostics.attempted(:, :, returnTimes));
outcome.deliveredEdgeByTime = logical( ...
    diagnostics.delivered(:, :, returnTimes));
end

function assertExecutedBinaryAdmission(outcome, groupIds, actionSpec)
required = {'controlledAdmissionEdgeByTime', ...
    'executedAbstentionEdgeByTime', ...
    'executedAdmissionFactorByTime'};
if ~all(isfield(outcome, required))
    error('V134SetTrustPilot:AdmissionTraceMissing', ...
        'The runtime omitted the binary-admission trace.');
end
controlled = outcome.controlledAdmissionEdgeByTime;
expectedFactors = ones(size(controlled));
expectedAbstention = false(size(controlled));
groupIds = reshape(groupIds, 1, []);
for timeIdx = 1:size(controlled, 3)
    formations = reshape( ...
        actionSpec.formationIdsByTime{timeIdx}, 1, []);
    factors = reshape(actionSpec.trustFactorsByTime{timeIdx}, 1, []);
    for formationIdx = 1:numel(formations)
        receiverMask = groupIds == formations(formationIdx);
        affected = controlled(:, :, timeIdx) & receiverMask(:);
        expectedFactors(:, :, timeIdx) = ...
            expectedFactors(:, :, timeIdx) .* (~affected) + ...
            factors(formationIdx) * affected;
        if factors(formationIdx) == 0
            expectedAbstention(:, :, timeIdx) = ...
                expectedAbstention(:, :, timeIdx) | affected;
        end
    end
end
actualFactors = outcome.executedAdmissionFactorByTime;
actualAbstention = outcome.executedAbstentionEdgeByTime;
if any(~ismember(actualFactors(controlled), [0, 1])) || ...
        max(abs(actualFactors(:) - expectedFactors(:))) > 1e-12 || ...
        ~isequal(actualAbstention, expectedAbstention)
    error('V134SetTrustPilot:AdmissionTraceDrift', ...
        'The runtime did not execute the registered binary action.');
end
end

function assertPairedContinuation(reference, candidate)
required = { ...
    'selectedAdjacencyByTime', 'nominalFusionWeightsByTime', ...
    'attemptedEdgeByTime', 'deliveredEdgeByTime'};
if ~all(isfield(reference, required)) || ...
        ~all(isfield(candidate, required)) || ...
        ~isequal(reference.selectedAdjacencyByTime, ...
            candidate.selectedAdjacencyByTime) || ...
        max(abs(reference.nominalFusionWeightsByTime(:) - ...
            candidate.nominalFusionWeightsByTime(:))) > 1e-12 || ...
        ~isequal(reference.attemptedEdgeByTime, ...
            candidate.attemptedEdgeByTime) || ...
        ~isequal(reference.deliveredEdgeByTime, ...
            candidate.deliveredEdgeByTime)
    error('V134SetTrustPilot:UnpairedContinuation', ...
        ['Reference and candidate must share route, nominal weights, ', ...
         'attempted opportunities and realized deliveries.']);
end
end

function [rankedFormationIds, records] = rankFormations( ...
        context, adjacency, weights, groupIds, formationIds)
v133 = getCounterfactualRegretGateV133Protocol();
referenceScore = computeReferenceScore( ...
    context, adjacency, weights, groupIds, v133);
records = repmat(struct( ...
    'formationId', 0, 'taskRiskChange', 0, ...
    'existenceRetentionRisk', 0, ...
    'networkDisagreementChange', 0), 1, numel(formationIds));
rankingTable = zeros(numel(formationIds), 4);
for formationIdx = 1:numel(formationIds)
    formationId = formationIds(formationIdx);
    score = scorePayloadAbstentionCounterfactualV133( ...
        context, adjacency, weights, groupIds, formationId, ...
        v133, referenceScore);
    records(formationIdx) = struct( ...
        'formationId', formationId, ...
        'taskRiskChange', score.taskRiskChange, ...
        'existenceRetentionRisk', score.existenceRetentionRisk, ...
        'networkDisagreementChange', ...
            score.networkDisagreementChange);
    rankingTable(formationIdx, :) = [ ...
        score.taskRiskChange, score.existenceRetentionRisk, ...
        score.networkDisagreementChange, formationId];
end
[~, order] = sortrows(rankingTable, [1, 2, 3, 4]);
rankedFormationIds = formationIds(order);
end

function score = computeReferenceScore( ...
        context, adjacency, weights, groupIds, protocol)
options = struct('maximumIncomingCount', ...
    protocol.maximumIncomingCountForOutcomeEnumeration);
[networkDisagreement, networkDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, adjacency, weights, options);
[taskRisk, taskRiskDetails] = ...
    computeExpectedLmbPosteriorTaskRiskV92( ...
        networkDetails, groupIds, context.model, protocol.riskOptions);
score = struct( ...
    'networkDisagreement', networkDisagreement, ...
    'networkDetails', networkDetails, ...
    'taskRisk', taskRisk, ...
    'taskRiskDetails', taskRiskDetails);
end

