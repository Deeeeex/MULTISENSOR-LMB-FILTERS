function state = validatePilotState( ...
        loaded, protocol, caseInfo, seed, anchorTime, gitState)
if ~isstruct(loaded) || ~isfield(loaded, 'pilotState') || ...
        ~isstruct(loaded.pilotState) || ...
        ~isscalar(loaded.pilotState)
    error('V134SetTrustPilot:InvalidState', ...
        'The V134 pilot state is absent or malformed.');
end
state = loaded.pilotState;
required = { ...
    'contractVersion', 'protocolId', 'scaleName', 'presetName', ...
    'seed', 'anchorTime', 'horizonSteps', ...
    'formationCycleDiameter', 'recoveryTailSteps', ...
    'referenceCarrierMode', ...
    'groupIds', 'rankedFormationIds', 'actionBank', ...
    'evaluatedActionIndices', ...
    'initialPosteriors', 'history', 'previousPolicyHistory', ...
    'updateHistory', 'referenceOutcome', 'generationGitCommit'};
if ~all(isfield(state, required)) || ...
        ~strcmp(state.contractVersion, ...
            'v134-binary-admission-pilot-state-v4') || ...
        ~strcmp(state.protocolId, protocol.id) || ...
        ~strcmp(state.scaleName, caseInfo.scaleName) || ...
        ~strcmp(state.presetName, caseInfo.presetName) || ...
        state.seed ~= seed || state.anchorTime ~= anchorTime || ...
        state.horizonSteps ~= caseInfo.horizonSteps || ...
        state.formationCycleDiameter ~= ...
            caseInfo.formationCycleDiameter || ...
        state.recoveryTailSteps ~= ...
            caseInfo.recoveryTailSteps || ...
        ~strcmp(state.generationGitCommit, gitState.commit) || ...
        ~ismember(state.referenceCarrierMode, ...
            protocol.referenceCarrierModes)
    error('V134SetTrustPilot:StateProvenanceDrift', ...
        'The V134 pilot state differs from this clean source.');
end
end

function metrics = attachRecoveryCertificate( ...
        metrics, certificate, protocol)
gate = protocol.preLearningGate;
metrics.recoveryCertificate = certificate;
metrics.recoverySquaredContractionFactor = ...
    certificate.candidateSquaredContractionFactor;
metrics.passesRecoveryCertificateGate = ...
    ~gate.requireRecoveryMeanSquareCertificate || ...
    certificate.passesRecoveryGate;
metrics.passesPreLearningGate = ...
    metrics.passesPreLearningGate && ...
    metrics.passesRecoveryCertificateGate;
end

function checkpoint = loadCheckpoint(path, state, actionIdx, gitState)
if exist(path, 'file') ~= 2
    error('V134SetTrustPilot:IncompleteActions', ...
        'Missing V134 action checkpoint: %s', path);
end
loaded = load(path, 'checkpoint');
if ~isfield(loaded, 'checkpoint') || ...
        ~isstruct(loaded.checkpoint) || ...
        ~isscalar(loaded.checkpoint) || ...
        ~isfield(loaded.checkpoint, 'contractVersion') || ...
        ~strcmp(loaded.checkpoint.contractVersion, ...
            'v134-binary-admission-pilot-action-checkpoint-v4')
    error('V134SetTrustPilot:InvalidCheckpoint', ...
        'The V134 action checkpoint is malformed: %s', path);
end
checkpoint = loaded.checkpoint;
if ~strcmp(checkpoint.protocolId, state.protocolId) || ...
        ~strcmp(checkpoint.presetName, state.presetName) || ...
        checkpoint.seed ~= state.seed || ...
        checkpoint.anchorTime ~= state.anchorTime || ...
        checkpoint.actionIndex ~= actionIdx || ...
        ~strcmp(checkpoint.actionSpec.name, ...
            state.actionBank.actions(actionIdx).name) || ...
        ~strcmp(checkpoint.generationGitCommit, gitState.commit)
    error('V134SetTrustPilot:CheckpointProvenanceDrift', ...
        'The V134 action checkpoint differs from the pilot state.');
end
end

function carrierMode = loadFrozenCarrierMode( ...
        protocol, caseInfo, options)
path = getField(options, 'baselineSelectionPath', fullfile( ...
    getCounterfactualRegretGateV133Protocol().outputRoot, ...
    'baseline_selection', 'FROZEN_REFERENCE_CARRIER_V133.mat'));
if exist(path, 'file') ~= 2
    error('V134SetTrustPilot:MissingFrozenCarrier', ...
        'The frozen strongest static carrier is missing: %s', path);
