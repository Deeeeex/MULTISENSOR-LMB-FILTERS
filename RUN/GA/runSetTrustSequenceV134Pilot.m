function [artifactPath, result] = ...
    runSetTrustSequenceV134Pilot(presetName, options)
% RUNSETTRUSTSEQUENCEV134PILOT Resumable paired action-space pilot.
%
% Modes:
%   prepare  - run one static prefix and paired static continuation;
%   worker   - evaluate a deterministic shard of nonreference actions;
%   finalize - aggregate every action checkpoint into one repository report;
%   all      - execute the three phases sequentially.

if nargin < 2 || isempty(options)
    options = struct();
end
mode = lower(strrep(char(getField(options, 'mode', 'all')), '_', '-'));
switch mode
    case 'prepare'
        [artifactPath, result] = preparePilot(presetName, options);
    case 'worker'
        [artifactPath, result] = runPilotWorker(presetName, options);
    case 'finalize'
        [artifactPath, result] = finalizePilot(presetName, options);
    case 'all'
        preparePilot(presetName, options);
        runPilotWorker(presetName, options);
        [artifactPath, result] = finalizePilot(presetName, options);
    otherwise
        error('V134SetTrustPilot:UnknownMode', ...
            'Mode must be prepare, worker, finalize, or all.');
end
end

function [statePath, pilotState] = preparePilot(presetName, options)
protocol = getSetTrustSequenceV134Protocol();
gitState = requireCleanSource();
caseInfo = resolveCase(protocol, presetName);
seed = resolvePilotSeed(options, protocol);
anchorTime = ...
    resolveSetTrustSequenceV134PilotAnchor(caseInfo, protocol);
outputDirectory = resolveOutputDirectory( ...
    presetName, seed, anchorTime, protocol, options);
statePath = fullfile(outputDirectory, 'PILOT_STATE_V134.mat');
overwrite = logical(getField(options, 'overwrite', false));
if exist(statePath, 'file') == 2 && ~overwrite
    loaded = load(statePath, 'pilotState');
    pilotState = validatePilotState( ...
        loaded, protocol, caseInfo, seed, anchorTime, gitState);
    fprintf('Reused V134 pilot state: %s\n', statePath);
    return;
end

carrierMode = loadFrozenCarrierMode( ...
    protocol, caseInfo, options);
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
truth = cropTrackingTruthRfs( ...
    inputs.groundTruthRfs, anchorTime + caseInfo.horizonSteps - 1);
inputs = isolateRuntimeInputs(inputs);
inputs = cropInputs(inputs, ...
    anchorTime + caseInfo.horizonSteps - 1);
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
formationIds = unique(groupIds, 'stable');
referenceAction = buildSetTrustSequenceCandidatesV134( ...
    formationIds, caseInfo.formationCycleDiameter, ...
    caseInfo.recoveryTailSteps).actions(1);

prefixContext = buildSetTrustSequenceV134ExecutionContext( ...
    presetName, seed, 'reference-prefix', anchorTime, ...
    carrierMode, referenceAction);
prefixConfig = buildRuntimeConfig( ...
    inputs.config, carrierMode, anchorTime, ...
    referenceAction, false, protocol);
prefixConfig.topologyPosteriorCaptureTimes = anchorTime;
prefixInputs = cropInputs(inputs, anchorTime);
rng(seed + protocol.filterSeedOffset);
prefixTimer = tic;
[~, prefixDiagnostics] = runEventTriggeredDistributedLmbFilter( ...
    prefixInputs.model, prefixInputs.measurements, ...
    prefixInputs.sensorTrajectories, prefixInputs.neighborMap, ...
    prefixInputs.commConfig, prefixConfig, prefixContext);
prefixSeconds = toc(prefixTimer);
auditRuntime(prefixDiagnostics, 1:anchorTime);

initialPosteriors = prefixDiagnostics. ...
    topologyLocalPosteriorSnapshot{anchorTime};
historyByTime = buildBehaviorContinuationHistoryRecords( ...
    prefixDiagnostics, anchorTime, 2);
history = historyByTime{anchorTime};
previousPolicyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
updateHistory = extractUpdateHistory(prefixDiagnostics, anchorTime);
observableContext = buildObservableContext( ...
    inputs, initialPosteriors, history, previousPolicyHistory, ...
    updateHistory, anchorTime, protocol);
[referenceAdjacency, referenceDetails] = ...
    selectBackboneResidualSplicedCyclePolicy( ...
        observableContext, carrierMode, protocol.routeWeights);
referenceWeights = referenceDetails.fusionWeightMatrix;
[rankedFormationIds, rankingRecords] = rankFormations( ...
    observableContext, referenceAdjacency, referenceWeights, ...
    groupIds, formationIds);
actionBank = buildSetTrustSequenceCandidatesV134( ...
    rankedFormationIds, caseInfo.formationCycleDiameter, ...
    caseInfo.recoveryTailSteps);
referenceAction = actionBank.actions(actionBank.referenceActionIndex);
evaluatedActionIndices = find([actionBank.actions.gateEligible]);
if protocol.pilotEvaluatesPersistentZeroCandidates
    evaluatedActionIndices = setdiff( ...
        2:actionBank.actionCount, actionBank.referenceActionIndex, ...
        'stable');
end

referenceContext = buildSetTrustSequenceV134ExecutionContext( ...
    presetName, seed, 'reference-continuation', anchorTime, ...
    carrierMode, referenceAction);
referenceConfig = buildRuntimeConfig( ...
    inputs.config, carrierMode, anchorTime, ...
    referenceAction, false, protocol);
referenceOutcome = runContinuation( ...
    inputs, truth, initialPosteriors, history, ...
    previousPolicyHistory, updateHistory, anchorTime, ...
    referenceConfig, referenceContext, seed, protocol);

pilotState = struct( ...
    'contractVersion', 'v134-binary-admission-pilot-state-v4', ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'anchorTime', anchorTime, ...
    'horizonSteps', caseInfo.horizonSteps, ...
    'formationCycleDiameter', caseInfo.formationCycleDiameter, ...
    'recoveryTailSteps', caseInfo.recoveryTailSteps, ...
    'referenceCarrierMode', carrierMode, ...
    'groupIds', groupIds, ...
    'rankedFormationIds', rankedFormationIds, ...
    'rankingRecords', rankingRecords, ...
    'referenceAdjacency', logical(referenceAdjacency), ...
    'referenceFusionWeights', referenceWeights, ...
    'actionBank', actionBank, ...
    'evaluatedActionIndices', evaluatedActionIndices, ...
    'initialPosteriors', {initialPosteriors}, ...
    'history', history, ...
    'previousPolicyHistory', previousPolicyHistory, ...
    'updateHistory', updateHistory, ...
    'referenceOutcome', referenceOutcome, ...
    'prefixSeconds', prefixSeconds, ...
    'generationGitCommit', gitState.commit, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', ...
        'repository-only-until-joint-cross-scale-gate-passes');
atomicSave(statePath, 'pilotState', pilotState);
fprintf([ ...
    'Prepared V134 %s seed %d t=%d %s, H=%d, actions=%d ', ...
    '(prefix %.1f s): %s\n'], ...
    caseInfo.scaleName, seed, anchorTime, carrierMode, ...
    caseInfo.horizonSteps, numel(evaluatedActionIndices), ...
    prefixSeconds, statePath);
end

function [outputDirectory, completedPaths] = ...
    runPilotWorker(presetName, options)
protocol = getSetTrustSequenceV134Protocol();
gitState = requireCleanSource();
caseInfo = resolveCase(protocol, presetName);
seed = resolvePilotSeed(options, protocol);
anchorTime = ...
    resolveSetTrustSequenceV134PilotAnchor(caseInfo, protocol);
outputDirectory = resolveOutputDirectory( ...
    presetName, seed, anchorTime, protocol, options);
statePath = fullfile(outputDirectory, 'PILOT_STATE_V134.mat');
loaded = load(statePath, 'pilotState');
state = validatePilotState( ...
    loaded, protocol, caseInfo, seed, anchorTime, gitState);
workerIndex = round(getField(options, 'workerIndex', 1));
workerCount = round(getField(options, 'workerCount', 1));
if ~isscalar(workerIndex) || ~isscalar(workerCount) || ...
        any(~isfinite([workerIndex, workerCount])) || ...
        workerIndex < 1 || workerIndex > workerCount
    error('V134SetTrustPilot:InvalidWorker', ...
        'workerIndex must be in 1:workerCount.');
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
truth = cropTrackingTruthRfs( ...
    inputs.groundTruthRfs, anchorTime + caseInfo.horizonSteps - 1);
inputs = isolateRuntimeInputs(inputs);
inputs = cropInputs(inputs, ...
    anchorTime + caseInfo.horizonSteps - 1);
candidateIndices = state.evaluatedActionIndices;
assigned = candidateIndices(workerIndex:workerCount:numel(candidateIndices));
completedPaths = cell(1, numel(assigned));
overwrite = logical(getField(options, 'overwrite', false));
for localIdx = 1:numel(assigned)
    actionIdx = assigned(localIdx);
    actionSpec = state.actionBank.actions(actionIdx);
    checkpointPath = actionCheckpointPath( ...
        outputDirectory, actionIdx, actionSpec.name);
    if exist(checkpointPath, 'file') == 2 && ~overwrite
        checkpoint = loadCheckpoint( ...
            checkpointPath, state, actionIdx, gitState);
        fprintf('Reused V134 action %02d: %s\n', ...
            actionIdx, checkpointPath);
    else
        context = buildSetTrustSequenceV134ExecutionContext( ...
            presetName, seed, 'candidate-continuation', anchorTime, ...
            state.referenceCarrierMode, actionSpec);
        config = buildRuntimeConfig( ...
            inputs.config, state.referenceCarrierMode, anchorTime, ...
            actionSpec, true, protocol);
        outcome = runContinuation( ...
            inputs, truth, state.initialPosteriors, state.history, ...
            state.previousPolicyHistory, state.updateHistory, ...
            anchorTime, config, context, seed, protocol);
        assertPairedContinuation(state.referenceOutcome, outcome);
        assertExecutedBinaryAdmission( ...
            outcome, state.groupIds, actionSpec);
        metrics = scoreSetTrustSequenceHeadroomV134( ...
            state.referenceOutcome, outcome, state.groupIds, ...
            caseInfo.recoveryTailSteps, protocol, actionSpec);
        recoveryCertificate = ...
            computeSetTrustSequenceV134RecoveryCertificate( ...
                outcome.selectedAdjacencyByTime, ...
                outcome.nominalFusionWeightsByTime, ...
                outcome.pDropByEdgeByTime, ...
                outcome.controlledAdmissionEdgeByTime, ...
                state.groupIds, actionSpec, ...
                caseInfo.recoveryTailSteps, protocol);
        metrics = attachRecoveryCertificate( ...
            metrics, recoveryCertificate, protocol);
        checkpoint = struct( ...
            'contractVersion', ...
                'v134-binary-admission-pilot-action-checkpoint-v4', ...
            'protocolId', protocol.id, ...
            'presetName', presetName, ...
            'seed', seed, ...
            'anchorTime', anchorTime, ...
            'actionIndex', actionIdx, ...
            'actionSpec', actionSpec, ...
            'outcome', outcome, ...
            'metrics', metrics, ...
            'generationGitCommit', gitState.commit, ...
            'developmentEvidenceOnly', true, ...
            'validationClaimAllowed', false);
        atomicSave(checkpointPath, 'checkpoint', checkpoint);
        fprintf([ ...
            'V134 %s action %02d %-32s intervention=%+.3f%% ', ...
            'full=%+.3f%% recovery=%+.3f%% rho=%.4f ', ...
            'bytes=%+.3f%% pass=%d\n'], ...
            caseInfo.scaleName, actionIdx, actionSpec.name, ...
            100 * metrics.interventionGainFraction, ...
            100 * metrics.meanGainFraction, ...
            100 * metrics.matureGainFraction, ...
            metrics.recoverySquaredContractionFactor, ...
            100 * metrics.attemptedByteSavingFraction, ...
            metrics.passesPreLearningGate);
    end
    completedPaths{localIdx} = checkpointPath;
end
fprintf('V134 pilot worker %d/%d completed %d actions.\n', ...
    workerIndex, workerCount, numel(completedPaths));
end

function [reportPath, pilot] = finalizePilot(presetName, options)
protocol = getSetTrustSequenceV134Protocol();
gitState = requireCleanSource();
caseInfo = resolveCase(protocol, presetName);
seed = resolvePilotSeed(options, protocol);
anchorTime = ...
    resolveSetTrustSequenceV134PilotAnchor(caseInfo, protocol);
outputDirectory = resolveOutputDirectory( ...
    presetName, seed, anchorTime, protocol, options);
statePath = fullfile(outputDirectory, 'PILOT_STATE_V134.mat');
loaded = load(statePath, 'pilotState');
state = validatePilotState( ...
    loaded, protocol, caseInfo, seed, anchorTime, gitState);

records = repmat(emptyRecord(), 1, ...
    numel(state.evaluatedActionIndices));
for recordIdx = 1:numel(state.evaluatedActionIndices)
    actionIdx = state.evaluatedActionIndices(recordIdx);
    actionSpec = state.actionBank.actions(actionIdx);
    checkpointPath = actionCheckpointPath( ...
        outputDirectory, actionIdx, actionSpec.name);
    checkpoint = loadCheckpoint( ...
        checkpointPath, state, actionIdx, gitState);
    records(recordIdx) = struct( ...
        'actionIndex', actionIdx, ...
        'actionName', actionSpec.name, ...
        'scheduleKind', actionSpec.scheduleKind, ...
        'formationSet', actionSpec.formationSet, ...
        'metrics', checkpoint.metrics, ...
        'elapsedSeconds', checkpoint.outcome.elapsedSeconds, ...
        'checkpointPath', checkpointPath);
end
passing = find(arrayfun( ...
    @(record) record.metrics.passesPreLearningGate, records));
robustScores = arrayfun(@(record) min([ ...
    record.metrics.interventionGainFraction, ...
    record.metrics.meanGainFraction, ...
    record.metrics.matureGainFraction, ...
    record.metrics.minimumInterventionSensorGainFraction, ...
    record.metrics.minimumSensorGainFraction, ...
    record.metrics.minimumMatureSensorGainFraction, ...
    record.metrics.minimumInterventionFormationGainFraction, ...
    record.metrics.minimumFormationGainFraction, ...
    record.metrics.minimumMatureFormationGainFraction]), records);
gateEligible = arrayfun(@(record) ...
    record.metrics.actionGateEligible && ...
    ~record.metrics.actionDiagnosticOnly && ...
    record.metrics.actionReturnsToFullTrust, records);
certificateEligible = arrayfun(@(record) ...
    record.metrics.passesRecoveryCertificateGate, records);
selectionEligible = gateEligible & certificateEligible;
robustScores(~selectionEligible) = -inf;
if any(selectionEligible)
    [~, bestLocalIdx] = max(robustScores);
    bestActionIdx = records(bestLocalIdx).actionIndex;
else
    bestLocalIdx = 0;
    bestActionIdx = 0;
end
pilot = struct( ...
    'contractVersion', 'v134-binary-admission-pilot-result-v4', ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'anchorTime', anchorTime, ...
    'referenceCarrierMode', state.referenceCarrierMode, ...
    'rankedFormationIds', state.rankedFormationIds, ...
    'evaluatedActionIndices', state.evaluatedActionIndices, ...
    'records', records, ...
    'passingRecordIndices', passing, ...
    'bestRobustRecordIndex', bestLocalIdx, ...
    'bestRobustActionIndex', bestActionIdx, ...
    'pilotScaleHeadroomObserved', ~isempty(passing), ...
    'jointCrossScaleGateClaimed', false, ...
    'generationGitCommit', gitState.commit, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', ...
        'repository-only-until-joint-cross-scale-gate-passes');
resultPath = fullfile(outputDirectory, 'PILOT_RESULT_V134.mat');
atomicSave(resultPath, 'pilot', pilot);
reportPath = fullfile(outputDirectory, 'PILOT_RESULT_V134.md');
writeReport(reportPath, pilot);
fprintf('Finalized V134 pilot: %s\n', reportPath);
end

