loaded = load(path, 'selection');
v133 = getCounterfactualRegretGateV133Protocol();
if ~isfield(loaded, 'selection') || ...
        ~strcmp(loaded.selection.protocolId, v133.id) || ...
        ~isfield(loaded.selection, 'cases')
    error('V134SetTrustPilot:InvalidFrozenCarrier', ...
        'The V133 carrier-selection artifact is invalid.');
