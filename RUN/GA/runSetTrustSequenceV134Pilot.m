function writeReport(path, pilot)
fileId = fopen(path, 'w');
if fileId < 0
    error('V134SetTrustPilot:ReportWriteFailed', ...
        'Could not open the V134 pilot report.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '# V134 binary posterior-admission pilot: %s\n\n', ...
    pilot.scaleName);
fprintf(fileId, ...
    ['Repository-only action-space evidence. This pilot does not ', ...
     'claim the joint cross-scale gate or validation.\n\n']);
fprintf(fileId, ...
    '- Seed / anchor: `%d` / `%d`\n', pilot.seed, pilot.anchorTime);
fprintf(fileId, '- Frozen static carrier: `%s`\n', ...
    pilot.referenceCarrierMode);
fprintf(fileId, '- Observable formation ranking: `%s`\n', ...
    mat2str(pilot.rankedFormationIds));
fprintf(fileId, '- Any candidate passes this scale pilot: `%d`\n\n', ...
    pilot.pilotScaleHeadroomObserved);
fprintf(fileId, ...
    ['| Action | Set | Intervention gain | Full-window gain | ', ...
     'Recovery gain | Intervention min sensor | Full min sensor | ', ...
     'Recovery min sensor | Intervention min formation | ', ...
     'Full min formation | Recovery min formation | ', ...
     'Intervention byte saving | Full byte saving | ', ...
     'Recovery factor | Gate eligible | Pass |\n']);
fprintf(fileId, ...
    ['|---|---|---:|---:|---:|---:|---:|---:|---:|---:|', ...
     '---:|---:|---:|---:|---:|---:|\n']);
for record = pilot.records
    metrics = record.metrics;
    fprintf(fileId, ...
        ['| `%s` | `%s` | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
         '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
         '%+.3f%% | %+.3f%% | %+.3f%% | %.4f | %d | %d |\n'], ...
        record.actionName, mat2str(record.formationSet), ...
        100 * metrics.interventionGainFraction, ...
        100 * metrics.meanGainFraction, ...
        100 * metrics.matureGainFraction, ...
        100 * metrics.minimumInterventionSensorGainFraction, ...
        100 * metrics.minimumSensorGainFraction, ...
        100 * metrics.minimumMatureSensorGainFraction, ...
        100 * metrics.minimumInterventionFormationGainFraction, ...
        100 * metrics.minimumFormationGainFraction, ...
        100 * metrics.minimumMatureFormationGainFraction, ...
        100 * metrics.interventionAttemptedByteSavingFraction, ...
        100 * metrics.attemptedByteSavingFraction, ...
        metrics.recoverySquaredContractionFactor, ...
        metrics.actionGateEligible && ...
            ~metrics.actionDiagnosticOnly && ...
            metrics.actionReturnsToFullTrust, ...
        metrics.passesPreLearningGate);
end
end

