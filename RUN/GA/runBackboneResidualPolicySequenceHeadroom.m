% RUNBACKBONERESIDUALPOLICYSEQUENCEHEADROOM
% Sharded M24 screen for the eight S/C three-step policy sequences.
%
% Example:
%   BATCH_INDEX=1 BATCH_COUNT=4 octave --quiet \
%     RUN/GA/runBackboneResidualPolicySequenceHeadroom.m

addpath(genpath(pwd));
protocol = getBackboneResidualPolicySequenceProtocol();
batchIndex = str2double(strtrim(getenv('BATCH_INDEX')));
batchCount = str2double(strtrim(getenv('BATCH_COUNT')));
if ~isscalar(batchIndex) || ~isfinite(batchIndex) || ...
        batchIndex < 1 || batchIndex ~= round(batchIndex) || ...
        ~isscalar(batchCount) || ~isfinite(batchCount) || ...
        batchCount < 1 || batchCount ~= round(batchCount) || ...
        batchIndex > batchCount
    error('BATCH_INDEX/BATCH_COUNT must define a valid shard.');
end

sequenceRows = batchIndex:batchCount: ...
    size(protocol.sequenceMasks, 1);
armNames = cell(1, numel(sequenceRows));
for idx = 1:numel(sequenceRows)
    mask = protocol.sequenceMasks(sequenceRows(idx), :);
    armNames{idx} = sprintf([ ...
        'oracle-backbone-residual-sequence-', ...
        't75-m%s-a70-e05'], mask);
end
if batchIndex == 1
    armNames = [{ ...
        'local', 'directed-fixed-index-w70', ...
        'backbone-residual-static-a70-e05', ...
        'backbone-residual-analytic-a70-e05'}, ...
        armNames];
end

outputDirectory = strtrim(getenv('OUTPUT_DIR'));
if isempty(outputDirectory)
    outputDirectory = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'backbone_residual_policy_sequence', ...
        sprintf('batch_%02d_of_%02d', ...
            batchIndex, batchCount));
end
options = struct();
options.maxTimeSteps = protocol.horizonTimes(end);
options.continuationStartTime = protocol.anchorTime;
options.behaviorCacheDirectory = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'cache');
options.outputDirectory = outputDirectory;
options.armNames = armNames;
options.primaryAttributionFamily = 'rolling-safe';
options.evidenceSplit = 'development';
options.rollingSafeBackboneMode = ...
    'fixed-balanced-cycle';
options.rollingPayloadProjectionToleranceFraction = ...
    protocol.payloadToleranceFraction;
options.generateMissingBehaviorCache = false;

runDynamicTopologyOracleGapScreen( ...
    protocol.presetName, protocol.seed, options);
