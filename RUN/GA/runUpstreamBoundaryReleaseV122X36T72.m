function [reportPath, result] = ...
        runUpstreamBoundaryReleaseV122X36T72(options)
% RUNUPSTREAMBOUNDARYRELEASEV122X36T72 Paired upstream-release screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getUpstreamBoundaryReleaseV122Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('UpstreamBoundaryReleaseV122:DirtySource', ...
        'The V122 screen requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
v113 = loadV113Screen(protocol, entry, currentTime);
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', protocol.executionProfile, ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', protocol.bankVariant, ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', 1:2, ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', protocol.v113ScreenPath, ...
    'capturePosteriorSnapshotsEnabled', false, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
screenMatPath = fullfile(screenOptions.outputDirectory, ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']);
if logical(getField(options, 'reuseCompletedCandidateScreen', true)) && ...
        exist(screenMatPath, 'file') == 2
    loaded = load(screenMatPath, 'screen');
    screen = loaded.screen;
    validateCandidateScreen(screen, protocol, entry, currentTime);
    screenReportPath = screen.reportPath;
    candidateScreenReused = true;
else
    [screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
        entry.presetName, entry.seed, currentTime, screenOptions);
    candidateScreenReused = false;
end
if ~screen.referenceOutcomeReused || ...
        ~strcmp(screen.cacheSha256, v113.cacheSha256) || ...
        ~isequal(screen.sensorGroupIds, v113.sensorGroupIds)
    error('UpstreamBoundaryReleaseV122:PairingDrift', ...
        'The V122 screen did not preserve the V113 paired baseline.');
end

[ccwFullRecord, ~] = findArm(v113, 'reference-full-payload');
[cwFullRecord, cwFullOutcome] = findArm( ...
    v113, protocol.clockwiseFullActionName);
[v113Record, v113Outcome] = findArm( ...
    v113, protocol.baseMechanismActionName);
[candidateRecord, candidateOutcome] = findArm( ...
    screen, protocol.candidateActionName);
groupIds = reshape(screen.sensorGroupIds, 1, []);
targetMembers = find(groupIds == protocol.targetFormationId);
targetGateway = protocol.boundaryReceiverSensorId;
targetPeers = setdiff(targetMembers, targetGateway, 'stable');
cwByTime = mean(cwFullOutcome.eospaBySensorTime, 1);
candidateByTime = mean(candidateOutcome.eospaBySensorTime, 1);
[formationGain, formationGainByTime] = formationGains( ...
    cwFullOutcome.eospaBySensorTime, ...
    candidateOutcome.eospaBySensorTime, groupIds);

metrics = struct();
metrics.meanEospa = candidateRecord.meanEospa;
metrics.meanGainPercent = relativeGainPercent( ...
    cwFullRecord.meanEospa, candidateRecord.meanEospa);
metrics.marginalVsV113Percent = relativeGainPercent( ...
    v113Record.meanEospa, candidateRecord.meanEospa);
metrics.gainPercentByTime = relativeGainPercent( ...
    cwByTime, candidateByTime);
metrics.minimumAfterMaturityGainPercent = min( ...
    metrics.gainPercentByTime(protocol.firstHandoffTimeIndex:end));
metrics.formationGainPercent = formationGain;
metrics.formationGainPercentByTime = formationGainByTime;
metrics.minimumFormationGainPercent = min(formationGain);
metrics.minimumTerminalFormationGainPercent = ...
    min(formationGainByTime(:, end));
metrics.upstreamFormationGainPercent = ...
    formationGain(protocol.upstreamFormationId);
metrics.targetFormationGainPercent = ...
    formationGain(protocol.targetFormationId);
metrics.targetPeerTerminalGainPercent = relativeGainPercent( ...
    mean(cwFullOutcome.eospaBySensorTime(targetPeers, end)), ...
    mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));
metrics.targetPeerRepairVsV113Percent = relativeGainPercent( ...
    mean(v113Outcome.eospaBySensorTime(targetPeers, end)), ...
    mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));
metrics.worstSensorGainPercent = relativeGainPercent( ...
    cwFullRecord.worstSensorEospa, candidateRecord.worstSensorEospa);
metrics.windowConsensusGainPercent = relativeGainPercent( ...
    cwFullRecord.consensusOspa, candidateRecord.consensusOspa);
metrics.terminalConsensusGainPercent = relativeGainPercent( ...
    cwFullRecord.terminalConsensusOspa, ...
    candidateRecord.terminalConsensusOspa);
metrics.attemptedByteSavingPercent = relativeGainPercent( ...
    cwFullRecord.attemptedBytes, candidateRecord.attemptedBytes);
metrics.selectedB3Passed = candidateRecord.selectedB3Passed;
metrics.gatePassed = passesGate(metrics, protocol);

result = struct();
result.contractVersion = protocol.resultContractVersion;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.referenceOutcomeReused = screen.referenceOutcomeReused;
result.v113BaselinesReused = true;
result.v122CandidateScreenReused = candidateScreenReused;
result.ccwFullRecord = ccwFullRecord;
result.clockwiseFullRecord = cwFullRecord;
result.v113MechanismRecord = v113Record;
result.candidateRecord = candidateRecord;
result.metrics = metrics;
result.anyGatePassed = metrics.gatePassed;
result.screenReportPath = screenReportPath;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, [protocol.resultFileStem, '.mat']);
reportPath = fullfile(outputRoot, [protocol.resultFileStem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('%s result: %s\n', protocol.runLabel, reportPath);
end

function passed = passesGate(metrics, protocol)
passed = metrics.meanGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    metrics.minimumAfterMaturityGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    metrics.minimumFormationGainPercent >= 0 && ...
    metrics.minimumTerminalFormationGainPercent >= 0 && ...
    metrics.targetPeerTerminalGainPercent >= 0 && ...
    metrics.worstSensorGainPercent >= 0 && ...
    metrics.windowConsensusGainPercent >= 0 && ...
    metrics.terminalConsensusGainPercent >= 0 && ...
    metrics.attemptedByteSavingPercent >= 0 && ...
    metrics.selectedB3Passed;
end

function validateCandidateScreen(screen, protocol, entry, currentTime)
valid = isstruct(screen) && isscalar(screen) && ...
    strcmp(screen.presetName, entry.presetName) && ...
    screen.seed == entry.seed && screen.currentTime == currentTime && ...
    screen.horizonSteps == protocol.horizonSteps && ...
    strcmp(screen.missingLabelFusionMode, protocol.receiverMode) && ...
    strcmp(screen.bank.bankVariant, protocol.bankVariant) && ...
    isequal(screen.bank.actionNames, ...
        {'reference-full-payload', protocol.candidateActionName}) && ...
    numel(screen.outcomes) == 2 && numel(screen.records) == 2 && ...
    ~screen.generationTrackedWorktreeDirty && ...
    isempty(screen.generationUntrackedSourceFiles) && ...
    screen.openedDevelopmentEvidenceOnly && ...
    ~screen.validationClaimAllowed;
if ~valid
    error('UpstreamBoundaryReleaseV122:CandidateScreenDrift', ...
        'The saved V122 candidate screen does not match the protocol.');
end
end

function screen = loadV113Screen(protocol, entry, currentTime)
loaded = load(protocol.v113ScreenPath, 'screen');
screen = loaded.screen;
if ~strcmp(screen.presetName, entry.presetName) || ...
        screen.seed ~= entry.seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= protocol.horizonSteps || ...
        ~strcmp(screen.missingLabelFusionMode, protocol.receiverMode) || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed
    error('UpstreamBoundaryReleaseV122:V113ProvenanceDrift', ...
        'The frozen V113 screen does not match V122.');
end
end

function [record, outcome] = findArm(screen, actionName)
idx = find(strcmp({screen.records.actionName}, actionName), 1);
if isempty(idx)
    error('UpstreamBoundaryReleaseV122:MissingArm', ...
        'Required arm %s is missing.', actionName);
end
record = screen.records(idx);
outcome = screen.outcomes(idx);
end

function [gain, gainByTime] = formationGains(reference, candidate, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
gain = zeros(1, numel(groups));
gainByTime = zeros(numel(groups), size(reference, 2));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    referenceValues = reference(mask, :);
    candidateValues = candidate(mask, :);
    gain(idx) = relativeGainPercent( ...
        mean(referenceValues(:)), mean(candidateValues(:)));
    gainByTime(idx, :) = relativeGainPercent( ...
        mean(referenceValues, 1), mean(candidateValues, 1));
end
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('UpstreamBoundaryReleaseV122:WriteFailed', ...
        'Could not create the V122 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
m = result.metrics;
fprintf(fid, '# %s\n\n', result.protocol.reportTitle);
fprintf(fid, '- V113 baselines reused: `1`\n');
fprintf(fid, '- V122 candidate screen reused: `%d`\n', ...
    result.v122CandidateScreenReused);
fprintf(fid, '- Gate passed: `%d`\n\n', m.gatePassed);
fprintf(fid, '| Arm | Mean E-OSPA | Gain vs CW | vs V113 | Mature min | Min form. | Terminal form. | F5 | F6 | F6 peers | Worst | Bytes | Gate |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
fprintf(fid, '| V122 release F5 | %.6f | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n', ...
    m.meanEospa, m.meanGainPercent, m.marginalVsV113Percent, ...
    m.minimumAfterMaturityGainPercent, ...
    m.minimumFormationGainPercent, ...
    m.minimumTerminalFormationGainPercent, ...
    m.upstreamFormationGainPercent, m.targetFormationGainPercent, ...
    m.targetPeerTerminalGainPercent, m.worstSensorGainPercent, ...
    m.attemptedByteSavingPercent, m.gatePassed);
fprintf(fid, '\n## Diagnostics\n\n');
fprintf(fid, '- Formation gains: `%s%%`\n', ...
    mat2str(m.formationGainPercent, 4));
fprintf(fid, '- Terminal formation gains: `%s%%`\n', ...
    mat2str(m.formationGainPercentByTime(:, end)', 4));
fprintf(fid, '- Per-page gains: `%s%%`\n', ...
    mat2str(m.gainPercentByTime, 4));
fprintf(fid, '- F6 peer repair vs V113: `%+.3f%%`\n', ...
    m.targetPeerRepairVsV113Percent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    m.windowConsensusGainPercent, m.terminalConsensusGainPercent);
fprintf(fid, '- Rolling B3: `%d`\n\n', m.selectedB3Passed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
