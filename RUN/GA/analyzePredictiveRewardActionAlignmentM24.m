function [analysisPath, analysis] = ...
    analyzePredictiveRewardActionAlignmentM24(options)
% ANALYZEPREDICTIVEREWARDACTIONALIGNMENTM24 Training-state reward gate.
%
% For every opened M24 state and receiving formation, this analysis
% compares the registered privileged teacher action with its best
% admissible true-task runner-up. Each action is evaluated using only the
% next observed measurement set and the predicted LMB measurement
% intensity. Current truth is read solely from the immutable audit target.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getPredictiveRewardActionAlignmentProtocol();
graphProtocol = getCvarResidualGraphPolicyDatasetProtocol();
bundle = loadCvarResidualGraphPolicyShards('training');
if ~isequal(bundle.seeds, protocol.trainingSeeds) || ...
        ~isequal(bundle.snapshotTimes, protocol.snapshotTimes) || ...
        bundle.developmentLabelsOpened || ...
        bundle.featuresUseTruth || ~bundle.targetsUseTruth
    error('Registered graph shards violate the action-alignment split.');
end
gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error('Official action-level reward analysis requires clean source.');
end

inputsBySeed = cell(1, numel(protocol.trainingSeeds));
for seedIdx = 1:numel(protocol.trainingSeeds)
    inputsBySeed{seedIdx} = ...
        generateDynamicTopologyScenarioInputs( ...
            protocol.presetName, ...
            protocol.trainingSeeds(seedIdx));
end

expectedRowCount = protocol.minimumFiniteActionCount;
rows = repmat(emptyRow(), 1, expectedRowCount);
rowCursor = 0;
blockSeen = false(1, numel(bundle.graphBlocks));
rolloutOptions = struct( ...
    'datasetVariant', graphProtocol.datasetVariant, ...
    'continuationStartTime', ...
        protocol.continuationStartTime, ...
    'sourceWeight', protocol.sourceWeight, ...
    'payloadToleranceFraction', ...
        protocol.payloadToleranceFraction, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'featureContextMode', protocol.featureContextMode, ...
    'proposalDistillationProtocol', graphProtocol, ...
    'blockObserverFcn', @captureActionPairs, ...
    'skipArtifactWrite', true);
[~, behaviorDataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        protocol.presetName, protocol.trainingSeeds, ...
        protocol.actionCodeSequences, rolloutOptions);
if any(~blockSeen) || rowCursor ~= expectedRowCount
    error(['Action-level predictive reward collection is ', ...
        'incomplete (%d/%d rows, %d/%d states).'], ...
        rowCursor, expectedRowCount, nnz(blockSeen), ...
        numel(blockSeen));
end
rows = rows(1:rowCursor);

scoreValues = [rows.scoreAdvantage];
taskValues = [rows.trueTaskAdvantage];
teacherMask = strcmp({rows.role}, 'teacher');
contrastMask = strcmp({rows.role}, 'runner-up');
globalSpearman = computeSpearman(scoreValues, taskValues);
teacherPositiveFraction = mean( ...
    scoreValues(teacherMask) > 0);
preferenceCorrect = false(1, nnz(teacherMask));
preferenceTies = false(size(preferenceCorrect));
pairCursor = 0;
pairIds = unique([rows.pairId], 'stable');
for pairId = pairIds
    pairRows = rows([rows.pairId] == pairId);
    if numel(pairRows) ~= 2 || ...
            nnz(strcmp({pairRows.role}, 'teacher')) ~= 1 || ...
            nnz(strcmp({pairRows.role}, 'runner-up')) ~= 1
        error('Action-alignment pair is malformed.');
    end
    trueDifference = ...
        pairRows(1).trueTaskAdvantage - ...
        pairRows(2).trueTaskAdvantage;
    scoreDifference = ...
        pairRows(1).scoreAdvantage - ...
        pairRows(2).scoreAdvantage;
    if ~strcmp(pairRows(1).role, 'teacher')
        trueDifference = -trueDifference;
        scoreDifference = -scoreDifference;
    end
    pairCursor = pairCursor + 1;
    preferenceTies(pairCursor) = ...
        abs(trueDifference) <= 1e-12;
    preferenceCorrect(pairCursor) = ...
        sign(scoreDifference) == sign(trueDifference);
end
nonTiePairs = ~preferenceTies;
pairwisePreferenceAccuracy = mean( ...
    preferenceCorrect(nonTiePairs));

perSeedSpearman = nan(1, numel(protocol.trainingSeeds));
for seedIdx = 1:numel(protocol.trainingSeeds)
    seedMask = [rows.seed] == ...
        protocol.trainingSeeds(seedIdx);
    perSeedSpearman(seedIdx) = computeSpearman( ...
        scoreValues(seedMask), taskValues(seedMask));
end
positivePerSeedSpearmanFraction = mean( ...
    perSeedSpearman > 0);

gates = struct();
gates.rowCount = numel(rows) >= ...
    protocol.minimumFiniteActionCount;
gates.teacherPositive = teacherPositiveFraction >= ...
    protocol.minimumTeacherPositiveScoreFraction;
gates.globalRank = isfinite(globalSpearman) && ...
    globalSpearman >= ...
        protocol.minimumGlobalScoreTaskSpearman;
gates.pairwisePreference = ...
    isfinite(pairwisePreferenceAccuracy) && ...
    pairwisePreferenceAccuracy >= ...
        protocol.minimumPairwisePreferenceAccuracy;
gates.perSeedRank = ...
    positivePerSeedSpearmanFraction >= ...
        protocol.minimumPositivePerSeedSpearmanFraction;
gates.provenance = validateBehaviorProvenance( ...
    behaviorDataset, protocol, graphProtocol) && ...
    graphProtocol.developmentOnly && ...
    isempty(intersect(protocol.trainingSeeds, ...
        graphProtocol.developmentValidationSeeds)) && ...
    isempty(intersect(protocol.trainingSeeds, ...
        graphProtocol.lockedHeldoutM24Seeds)) && ...
    ~bundle.developmentLabelsOpened && ...
    ~bundle.featuresUseTruth && bundle.targetsUseTruth;

analysis = struct();
analysis.contractVersion = ...
    'predictive-reward-action-alignment-m24-v1';
analysis.generatedAt = datestr(now, 31);
analysis.generationGitCommit = gitState.commit;
analysis.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
analysis.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
analysis.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
analysis.protocolId = protocol.id;
analysis.graphDatasetSetSha256 = ...
    bundle.datasetSetSha256;
analysis.trainingSeeds = protocol.trainingSeeds;
analysis.snapshotTimes = protocol.snapshotTimes;
analysis.scoreType = protocol.scoreType;
analysis.scoreTruthUsed = protocol.scoreTruthUsed;
analysis.targetTruthUsed = protocol.targetTruthUsed;
analysis.rows = rows;
analysis.teacherActionCount = nnz(teacherMask);
analysis.runnerUpActionCount = nnz(contrastMask);
analysis.teacherMeanScoreAdvantage = ...
    mean(scoreValues(teacherMask));
analysis.teacherPositiveScoreFraction = ...
    teacherPositiveFraction;
analysis.globalScoreTaskSpearman = globalSpearman;
analysis.pairwisePreferenceAccuracy = ...
    pairwisePreferenceAccuracy;
analysis.pairwiseNonTieCount = nnz(nonTiePairs);
analysis.perSeedSpearman = perSeedSpearman;
analysis.positivePerSeedSpearmanFraction = ...
    positivePerSeedSpearmanFraction;
analysis.gates = gates;
analysis.allGatesPassed = all(structfun( ...
    @(value) logical(value), gates));
analysis.fullActionRewardDatasetAuthorized = ...
    analysis.allGatesPassed;
analysis.banditImplementationAuthorized = false;
analysis.developmentEvaluationAuthorized = false;
analysis.heldoutM24Authorized = false;
analysis.x36PolicyRunAuthorized = false;
analysis.evidenceBoundary = [ ...
    'The reward uses next measurements and no target truth. ', ...
    'Registered current-truth task advantages are read only to audit ', ...
    'alignment on already-opened training states. A pass may authorize ', ...
    'a full observable reward dataset, but not bandit deployment, ', ...
    'development evaluation, held-out M24, or X36.'];

analysisPath = getField(options, ...
    'analysisPath', protocol.defaultOutputPath);
reportPath = getField(options, ...
    'reportPath', protocol.defaultReportPath);
analysis.analysisPath = analysisPath;
analysis.reportPath = reportPath;
save('-mat7-binary', analysisPath, 'analysis');
writeReport(reportPath, analysis);
fprintf('Predictive reward action alignment: %s\nReport: %s\n', ...
    analysisPath, reportPath);

    function captureActionPairs(context, behaviorBlock)
        if ~ismember(behaviorBlock.currentTime, ...
                protocol.snapshotTimes)
            return;
        end
        blockIdx = find( ...
            [bundle.graphBlocks.seed] == ...
                behaviorBlock.seed & ...
            [bundle.graphBlocks.currentTime] == ...
                behaviorBlock.currentTime);
        if numel(blockIdx) ~= 1 || blockSeen(blockIdx)
            error('Action-alignment graph block is missing or repeated.');
        end
        graphBlock = bundle.graphBlocks(blockIdx);
        validateContextBlock( ...
            context, behaviorBlock, graphBlock);
        seedIdx = find(protocol.trainingSeeds == ...
            behaviorBlock.seed);
        inputs = inputsBySeed{seedIdx};
        groupIds = reshape(behaviorBlock.groupIds, 1, []);
        receiverGroups = groupIds( ...
            graphBlock.receiverIndices);
        senderGroups = groupIds( ...
            graphBlock.senderIndices);
        groups = unique(groupIds, 'stable');
        groupCount = numel(groups);
        if groupCount ~= ...
                protocol.expectedReceivingFormationCount
            error('Action-alignment formation count changed.');
        end
        pairGroups = unique(receiverGroups, 'stable');
        if ~isequal(sort(pairGroups), sort(groups))
            error(['Action-alignment candidates do not cover every ', ...
                'receiving formation.']);
        end
        for group = reshape(pairGroups, 1, [])
            selected = findSelectedAction( ...
                graphBlock, receiverGroups, group);
            runnerUp = findRunnerUpAction( ...
                graphBlock, receiverGroups, ...
                senderGroups, group, groups, ...
                selected);
            if mod(rowCursor, 2) ~= 0
                error('Action-alignment pair cursor is misaligned.');
            end
            pairId = 1 + floor(rowCursor / 2);
            appendActionRow( ...
                selected, 'teacher', pairId, ...
                graphBlock, context, inputs);
            appendActionRow( ...
                runnerUp, 'runner-up', pairId, ...
                graphBlock, context, inputs);
        end
        blockSeen(blockIdx) = true;
    end

    function appendActionRow( ...
            action, role, pairId, graphBlock, context, inputs)
        receiverIdx = graphBlock.receiverIndices(action.rowIdx);
        senderIdx = graphBlock.senderIndices(action.rowIdx);
        residualWeight = ...
            graphBlock.residualWeightGrid(action.weightIdx);
        baselineSource = ...
            graphBlock.residualBaselineSourcesByReceiver(receiverIdx);
        dominantSource = ...
            graphBlock.dominantSourcesByReceiver(receiverIdx);
        nextMeasurements = ...
            inputs.measurements{receiverIdx, ...
                graphBlock.currentTime + 1};
        baselineScore = expectedReceiverNextScore( ...
            context, receiverIdx, dominantSource, ...
            baselineSource, protocol.dominantWeight, ...
            protocol.referenceResidualWeight, ...
            nextMeasurements);
        actionScore = expectedReceiverNextScore( ...
            context, receiverIdx, dominantSource, ...
            senderIdx, protocol.dominantWeight, ...
            residualWeight, nextMeasurements);
        rowCursor = rowCursor + 1;
        if rowCursor > numel(rows)
            error('Action-alignment row count exceeded protocol.');
        end
        row = emptyRow();
        row.pairId = pairId;
        row.seed = graphBlock.seed;
        row.currentTime = graphBlock.currentTime;
        row.receiverGroup = ...
            behaviorBlock.groupIds(receiverIdx);
        row.role = role;
        row.receiverIdx = receiverIdx;
        row.senderIdx = senderIdx;
        row.residualWeight = residualWeight;
        row.baselineScore = baselineScore;
        row.actionScore = actionScore;
        row.scoreAdvantage = ...
            actionScore - baselineScore;
        row.trueTaskAdvantage = ...
            graphBlock.edgeTaskAdvantageTarget( ...
                action.rowIdx, action.weightIdx);
        row.referenceSafe = ...
            graphBlock.edgeReferenceSafeTarget( ...
                action.rowIdx, action.weightIdx);
        if graphBlock.nodeCvarMaskTarget(receiverIdx) && ...
                ~row.referenceSafe
            error(['Protected-receiver action violates the ', ...
                'registered reference-safety target.']);
        end
        row.targetTruthUsed = true;
        row.scoreTruthUsed = false;
        if any(~isfinite([ ...
                row.baselineScore, row.actionScore, ...
                row.scoreAdvantage, row.trueTaskAdvantage]))
            error('Action-alignment row is non-finite.');
        end
        rows(rowCursor) = row;
    end
end

function validateContextBlock(context, behaviorBlock, graphBlock)
required = { ...
    'localPosteriorBySensor', 'model', 'commConfig', ...
    'triggerConfig', 'currentTime'};
if ~all(isfield(context, required)) || ...
        context.currentTime ~= graphBlock.currentTime || ...
        behaviorBlock.seed ~= graphBlock.seed || ...
        ~isequal(behaviorBlock.receiverIndices, ...
            graphBlock.receiverIndices) || ...
        ~isequal(behaviorBlock.senderIndices, ...
            graphBlock.senderIndices)
    error('Action-alignment replay context is misaligned.');
end
end

function action = findSelectedAction( ...
        block, receiverGroups, group)
mask = block.selectedEdgeWeightTarget & ...
    repmat(receiverGroups(:) == group, ...
        1, numel(block.residualWeightGrid));
[rowIdx, weightIdx] = find(mask);
if numel(rowIdx) ~= 1
    error('Expected one teacher action per receiving formation.');
end
action = struct('rowIdx', rowIdx, ...
    'weightIdx', weightIdx);
end

function action = findRunnerUpAction( ...
        block, receiverGroups, senderGroups, ...
        group, groups, selected)
groupCount = numel(groups);
groupPosition = find(groups == group);
if numel(groupPosition) ~= 1
    error('Receiving formation is not uniquely registered.');
end
previousGroup = groups(mod(groupPosition - 2, groupCount) + 1);
nextGroup = groups(mod(groupPosition, groupCount) + 1);
rowEligible = receiverGroups(:) == group & ...
    (senderGroups(:) == previousGroup | ...
     senderGroups(:) == nextGroup);
eligible = repmat(rowEligible, 1, ...
    numel(block.residualWeightGrid));
receiverProtected = block.nodeCvarMaskTarget( ...
    block.receiverIndices);
protectedMatrix = repmat( ...
    receiverProtected(:), 1, ...
    numel(block.residualWeightGrid));
eligible = eligible & ...
    (~protectedMatrix | block.edgeReferenceSafeTarget);
eligible(selected.rowIdx, selected.weightIdx) = false;
values = block.edgeTaskAdvantageTarget;
values(~eligible) = -Inf;
[bestValue, linearIdx] = max(values(:));
if ~isfinite(bestValue)
    error('No admissible runner-up action exists.');
end
[rowIdx, weightIdx] = ind2sub( ...
    size(values), linearIdx);
action = struct('rowIdx', rowIdx, ...
    'weightIdx', weightIdx);
end

function valid = validateBehaviorProvenance( ...
        dataset, protocol, graphProtocol)
required = { ...
    'protocolId', 'datasetVariant', 'seeds', ...
    'actionCodeSequences', 'continuationStartTime', ...
    'snapshotTimes', 'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty', ...
    'featuresUseTruth', 'labelsUseTruth', ...
    'labelSelectionUsesFutureOutcome'};
valid = isstruct(dataset) && ...
    all(isfield(dataset, required));
if ~valid
    return;
end
expectedSnapshotTimes = ...
    protocol.continuationStartTime + ...
        (0:(size(protocol.actionCodeSequences, 2) - 1));
valid = strcmp(dataset.protocolId, graphProtocol.id) && ...
    strcmp(dataset.datasetVariant, ...
        graphProtocol.datasetVariant) && ...
    isequal(dataset.seeds, protocol.trainingSeeds) && ...
    isequal(dataset.actionCodeSequences, ...
        protocol.actionCodeSequences) && ...
    dataset.continuationStartTime == ...
        protocol.continuationStartTime && ...
    isequal(dataset.snapshotTimes, ...
        expectedSnapshotTimes) && ...
    ~dataset.generationTrackedWorktreeDirty && ...
    isempty(dataset.generationUntrackedSourceFiles) && ...
    ~dataset.generationResearchWorktreeDirty && ...
    ~dataset.featuresUseTruth && ...
    ~dataset.labelsUseTruth && ...
    ~dataset.labelSelectionUsesFutureOutcome;
end

function score = expectedReceiverNextScore( ...
        context, receiverIdx, dominantSource, ...
        residualSource, dominantWeight, residualWeight, ...
        nextMeasurements)
selfWeight = 1 - dominantWeight - residualWeight;
sources = [dominantSource, residualSource];
weights = [dominantWeight, residualWeight];
if dominantSource == residualSource
    uniqueSources = dominantSource;
    uniqueWeights = dominantWeight + residualWeight;
else
    uniqueSources = sources;
    uniqueWeights = weights;
end
reliability = zeros(1, numel(uniqueSources));
for sourceIdx = 1:numel(uniqueSources)
    reliability(sourceIdx) = 1 - edgeDrop( ...
        context.commConfig, uniqueSources(sourceIdx), ...
        receiverIdx, context.currentTime);
end

score = 0;
for maskCode = 0:(2^numel(uniqueSources) - 1)
    delivered = logical(bitget( ...
        maskCode, 1:numel(uniqueSources)));
    probability = prod(reliability(delivered)) * ...
        prod(1 - reliability(~delivered));
    if probability <= 0
        continue;
    end
    if ~any(delivered)
        posterior = ...
            context.localPosteriorBySensor{receiverIdx};
    else
        selectedSources = uniqueSources(delivered);
        fusionInputs = [{ ...
            context.localPosteriorBySensor{receiverIdx}}, ...
            context.localPosteriorBySensor(selectedSources)];
        fusionWeights = [selfWeight, ...
            uniqueWeights(delivered)];
        fusionWeights = fusionWeights / ...
            sum(fusionWeights);
        fusionDetails = struct( ...
            'eventType', [0, 2 * ones( ...
                1, numel(selectedSources))]);
        posterior = fuseLmbPosteriorsByLabel( ...
            fusionInputs, fusionWeights, ...
            context.model, fusionWeights, ...
            fusionDetails, context.triggerConfig);
    end
    predicted = lmbPredictionStep( ...
        posterior, context.model, ...
        context.currentTime + 1);
    outcomeScore = ...
        computeLmbPoissonMeasurementLogScore( ...
            predicted, nextMeasurements, ...
            context.model, receiverIdx, ...
            context.currentTime + 1);
    score = score + probability * outcomeScore;
end
end

function probability = edgeDrop( ...
        config, senderIdx, receiverIdx, currentTime)
if isfield(config, 'pDropByEdge') && ...
        ~isempty(config.pDropByEdge)
    if ndims(config.pDropByEdge) >= 3
        timeIdx = min(currentTime, ...
            size(config.pDropByEdge, 3));
        probability = config.pDropByEdge( ...
            senderIdx, receiverIdx, timeIdx);
    else
        probability = config.pDropByEdge( ...
            senderIdx, receiverIdx);
    end
else
    probability = 0;
end
probability = min(max(probability, 0), 1);
end

function correlation = computeSpearman(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
valid = isfinite(left) & isfinite(right);
left = left(valid);
right = right(valid);
if numel(left) < 3 || numel(unique(left)) < 2 || ...
        numel(unique(right)) < 2
    correlation = NaN;
    return;
end
leftRanks = averageRanks(left);
rightRanks = averageRanks(right);
matrix = corrcoef(leftRanks, rightRanks);
correlation = matrix(1, 2);
end

function ranks = averageRanks(values)
[sortedValues, order] = sort(values);
ranks = zeros(size(values));
startIdx = 1;
while startIdx <= numel(values)
    endIdx = startIdx;
    while endIdx < numel(values) && ...
            sortedValues(endIdx + 1) == ...
                sortedValues(startIdx)
        endIdx = endIdx + 1;
    end
    ranks(order(startIdx:endIdx)) = ...
        0.5 * (startIdx + endIdx);
    startIdx = endIdx + 1;
end
end

function writeReport(path, analysis)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write action-alignment report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 predictive reward action alignment\n\n');
fprintf(fid, '- Generated: %s\n', analysis.generatedAt);
fprintf(fid, '- Commit: `%s`\n', ...
    analysis.generationGitCommit);
fprintf(fid, '- Protocol: `%s`\n', analysis.protocolId);
fprintf(fid, '- Training seeds: `%s`\n', ...
    mat2str(analysis.trainingSeeds));
fprintf(fid, '- Snapshot times: `%s`\n', ...
    mat2str(analysis.snapshotTimes));
fprintf(fid, '- Score truth used / target truth used: `%d / %d`\n', ...
    analysis.scoreTruthUsed, analysis.targetTruthUsed);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    analysis.evidenceBoundary);

fprintf(fid, '| Metric | Value |\n|:--|--:|\n');
fprintf(fid, '| Teacher actions | %d |\n', ...
    analysis.teacherActionCount);
fprintf(fid, '| Runner-up actions | %d |\n', ...
    analysis.runnerUpActionCount);
fprintf(fid, '| Teacher mean score advantage | %.6f |\n', ...
    analysis.teacherMeanScoreAdvantage);
fprintf(fid, '| Teacher positive-score fraction | %.4f |\n', ...
    analysis.teacherPositiveScoreFraction);
fprintf(fid, '| Global score-task Spearman | %.4f |\n', ...
    analysis.globalScoreTaskSpearman);
fprintf(fid, '| Pairwise preference accuracy | %.4f |\n', ...
    analysis.pairwisePreferenceAccuracy);
fprintf(fid, '| Non-tie pairs | %d |\n', ...
    analysis.pairwiseNonTieCount);
fprintf(fid, '| Positive per-seed Spearman fraction | %.4f |\n', ...
    analysis.positivePerSeedSpearmanFraction);

fprintf(fid, '\n| Seed | Score-task Spearman |\n|--:|--:|\n');
for seedIdx = 1:numel(analysis.trainingSeeds)
    fprintf(fid, '| %d | %.4f |\n', ...
        analysis.trainingSeeds(seedIdx), ...
        analysis.perSeedSpearman(seedIdx));
end
fprintf(fid, ['\n- Gates (row count / teacher positive / global rank / ', ...
    'pairwise preference / per-seed rank / provenance): ', ...
    '`%d / %d / %d / %d / %d / %d`\n'], ...
    analysis.gates.rowCount, ...
    analysis.gates.teacherPositive, ...
    analysis.gates.globalRank, ...
    analysis.gates.pairwisePreference, ...
    analysis.gates.perSeedRank, ...
    analysis.gates.provenance);
fprintf(fid, '- All gates passed: `%d`\n', ...
    analysis.allGatesPassed);
fprintf(fid, '- Full action reward dataset authorized: `%d`\n', ...
    analysis.fullActionRewardDatasetAuthorized);
fprintf(fid, ['- Bandit / development / held-out M24 / X36 ', ...
    'authorized: `%d / %d / %d / %d`\n'], ...
    analysis.banditImplementationAuthorized, ...
    analysis.developmentEvaluationAuthorized, ...
    analysis.heldoutM24Authorized, ...
    analysis.x36PolicyRunAuthorized);
end

function row = emptyRow()
row = struct( ...
    'pairId', NaN, ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'receiverGroup', NaN, ...
    'role', '', ...
    'receiverIdx', NaN, ...
    'senderIdx', NaN, ...
    'residualWeight', NaN, ...
    'baselineScore', NaN, ...
    'actionScore', NaN, ...
    'scoreAdvantage', NaN, ...
    'trueTaskAdvantage', NaN, ...
    'referenceSafe', false, ...
    'targetTruthUsed', true, ...
    'scoreTruthUsed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
