function [reportPath, analysis] = ...
        analyzeFormationCoordinatedPosteriorRepairV184(options)
% ANALYZEFORMATIONCOORDINATEDPOSTERIORREPAIRV184 Test a fixed formation rule.
%
% The rule searches for one exact (label, source) pair available to every
% receiver in a formation.  It uses only present-time observable features:
% the learned sign-safety probabilities, training-support membership,
% receiver label presence, Bayes-risk reduction and peer agreement.  Truth
% is read only after the action has been selected to diagnose its immediate
% E-OSPA/RMSE effect.

if nargin < 1 || isempty(options)
    options = struct();
end
datasetPaths = getField(options, 'datasetPaths', { ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v166', 'one_hop_action_value', ...
        'ONE_HOP_LABEL_ACTION_VALUE_DATASET_V166.mat'), ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v176', 'recursive_rollout_action_value', ...
        'RECURSIVE_ROLLOUT_LABEL_ACTION_VALUE_DATASET_V176.mat'), ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v180', 'recursive_rollout_action_value', ...
        'RECURSIVE_V179_ROLLOUT_ACTION_VALUE_DATASET_V180.mat')});
datasetNames = getField(options, 'datasetNames', { ...
    'V166 static state', 'V176 first rollout', 'V180 second rollout'});
modelPath = getField(options, 'modelPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v181', 'second_rollout_aware_model', ...
    'compact_scalar', 'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_MODEL.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v184', 'formation_coordinated_posterior_repair'));
formation = getField(options, 'formation', 5);
minimumSupportCount = getField(options, 'minimumSupportCount', 4);
minimumRiskReduction = getField(options, 'minimumRiskReduction', -0.05);
minimumReceiverPresence = getField(options, ...
    'minimumReceiverPresence', 0.5);
minimumSafetyProbability = getField(options, ...
    'minimumSafetyProbability', 0.60);
if ~iscell(datasetPaths) || isempty(datasetPaths) || ...
        ~iscell(datasetNames) || numel(datasetNames) ~= numel(datasetPaths) || ...
        exist(modelPath, 'file') ~= 2 || ...
        any(cellfun(@(path) exist(path, 'file') ~= 2, datasetPaths)) || ...
        ~isscalar(formation) || formation < 1 || ...
        ~isscalar(minimumSupportCount) || minimumSupportCount < 1 || ...
        ~isscalar(minimumRiskReduction) || ...
        ~isfinite(minimumRiskReduction) || ...
        ~isscalar(minimumReceiverPresence) || ...
        minimumReceiverPresence < 0 || minimumReceiverPresence > 1 || ...
        ~isscalar(minimumSafetyProbability) || ...
        minimumSafetyProbability < modelProbabilityFloor() || ...
        minimumSafetyProbability >= 1
    error('FormationLocalizationV184:InvalidInput', ...
        'The V184 analysis inputs are invalid.');
end
loadedModel = load(modelPath, 'model');
model = loadedModel.model;
validateModel(model);

contexts = repmat(emptyContext(), 1, 0);
contextIndex = 0;
for datasetIndex = 1:numel(datasetPaths)
    loadedDataset = load(datasetPaths{datasetIndex}, 'dataset');
    dataset = loadedDataset.dataset;
    validateDataset(dataset, model);
    formationCells = dataset.cells([dataset.cells.formation] == formation);
    times = unique([formationCells.time]);
    for currentTime = reshape(times, 1, [])
        cells = formationCells([formationCells.time] == currentTime);
        [~, order] = sort([cells.receiver]);
        cells = cells(order);
        if numel(cells) < minimumSupportCount
            error('FormationLocalizationV184:TooFewReceivers', ...
                'Formation %d at t=%d has too few receiver cells.', ...
                formation, currentTime);
        end
        contextIndex = contextIndex + 1;
        contexts(contextIndex) = analyzeContext( ...
            dataset, cells, datasetNames{datasetIndex}, datasetIndex, ...
            model, minimumSupportCount, minimumRiskReduction, ...
            minimumReceiverPresence, minimumSafetyProbability);
    end
end

analysis = struct();
analysis.contractVersion = ...
    'formation-coordinated-posterior-repair-analysis-v184-v1';
analysis.datasetPaths = datasetPaths;
analysis.datasetNames = datasetNames;
analysis.modelPath = modelPath;
analysis.formation = formation;
analysis.minimumSupportCount = minimumSupportCount;
analysis.minimumRiskReduction = minimumRiskReduction;
analysis.minimumReceiverPresence = minimumReceiverPresence;
analysis.minimumSafetyProbability = minimumSafetyProbability;
analysis.modelProbabilityThreshold = model.probabilityThreshold;
analysis.contexts = contexts;
analysis.eligibleContextCount = nnz([contexts.selected]);
selected = contexts([contexts.selected]);
if isempty(selected)
    analysis.safeContextCount = 0;
    analysis.totalEospaGain = 0;
    analysis.totalRmseGain = 0;
else
    analysis.safeContextCount = nnz([selected.harmfulNodeCount] == 0);
    analysis.totalEospaGain = sum([selected.totalEospaGain]);
    analysis.totalRmseGain = sum([selected.totalRmseGain]);
end
analysis.featuresUseTruth = false;
analysis.selectionUsesTruth = false;
analysis.truthUsedForDiagnosticReadout = true;
analysis.recursiveEvaluationRun = false;
analysis.deployable = false;
analysis.evidenceBoundary = [ ...
    'V184 is a fixed-rule, same-seed mechanism diagnostic over opened ', ...
    'V166/V176/V180 X36 states. Selection consumes only current ', ...
    'posterior-derived features and a V181 safety model; truth is read ', ...
    'only after selection. V180 t=78 is intentionally retained in the ', ...
    'table as a duplicate-state consistency check, not as independent ', ...
    'evidence. Even a clean result authorizes only a frozen recursive ', ...
    'development probe, not validation or a paper-facing claim.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_COORDINATED_POSTERIOR_REPAIR_V184_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_COORDINATED_POSTERIOR_REPAIR_V184.md');
analysis.matPath = matPath;
analysis.reportPath = reportPath;
save('-mat7-binary', matPath, 'analysis');
writeReport(reportPath, analysis);
fprintf('V184 formation-coordinated posterior repair: %s\n', reportPath);
end

function context = analyzeContext( ...
        dataset, cells, datasetName, datasetIndex, model, ...
        minimumSupportCount, minimumRiskReduction, ...
        minimumReceiverPresence, minimumSafetyProbability)
allRows = dataset.rows;
featureNames = reshape(dataset.featureNames, 1, []);
receiverPresentIdx = featureIndex(featureNames, 'receiver_present');
riskReductionIdx = featureIndex(featureNames, 'risk_reduction');
compatibilityIdx = featureIndex( ...
    featureNames, 'receiver_source_compatibility');
peerConsensusIdx = featureIndex(featureNames, 'peer_consensus_mean');
sourceEvidenceIdx = featureIndex(featureNames, 'source_evidence_quality');

cellRows = cell(1, numel(cells));
for idx = 1:numel(cells)
    cellRows{idx} = allRows([allRows.cellId] == cells(idx).cellId);
end
pairs = uniquePairs(cellRows{1});
commonCandidates = repmat(emptyCandidateReadout(), 1, 0);
for pairIdx = 1:size(pairs, 2)
    label = pairs(1:2, pairIdx);
    source = pairs(3, pairIdx);
    selectedRows = repmat(allRows(1), 1, 0);
    complete = true;
    for cellIdx = 1:numel(cellRows)
        rowIdx = findPair(cellRows{cellIdx}, label, source);
        if rowIdx == 0
            complete = false;
            break;
        end
        selectedRows(end + 1) = cellRows{cellIdx}(rowIdx); %#ok<AGROW>
    end
    if ~complete
        continue;
    end
    X = vertcat(selectedRows.features);
    [lowerProbability, inSupport] = predictSafety(model, X);
    observedMinimumSafetyProbability = min(lowerProbability(:));
    receiverPresence = X(:, receiverPresentIdx);
    riskReduction = X(:, riskReductionIdx);
    compatibility = X(:, compatibilityIdx);
    peerConsensus = X(:, peerConsensusIdx);
    sourceEvidence = X(:, sourceEvidenceIdx);
    rescueScoreByNode = peerConsensus .* ...
        max(1 - compatibility, 0) .* max(sourceEvidence, 0);
    candidate = emptyCandidateReadout();
    candidate.label = label;
    candidate.source = source;
    candidate.nodeCount = numel(selectedRows);
    candidate.supportCount = nnz(inSupport);
    candidate.minimumSafetyProbability = observedMinimumSafetyProbability;
    candidate.minimumRiskReduction = min(riskReduction);
    candidate.minimumReceiverPresence = min(receiverPresence);
    candidate.consensusRescueScore = median(rescueScoreByNode);
    candidate.eospaGainByNode = [selectedRows.eospaGain];
    candidate.rmseGainByNode = [selectedRows.rmseGain];
    candidate.totalEospaGain = sum(candidate.eospaGainByNode);
    candidate.totalRmseGain = sum(candidate.rmseGainByNode);
    candidate.minimumEospaGain = min(candidate.eospaGainByNode);
    candidate.minimumRmseGain = min(candidate.rmseGainByNode);
    candidate.harmfulNodeCount = nnz( ...
        candidate.eospaGainByNode < -1e-9 | ...
        candidate.rmseGainByNode <= 1e-9);
    candidate.eligible = ...
        candidate.supportCount >= minimumSupportCount && ...
        candidate.minimumSafetyProbability >= minimumSafetyProbability && ...
        candidate.minimumRiskReduction >= minimumRiskReduction && ...
        candidate.minimumReceiverPresence >= minimumReceiverPresence;
    commonCandidates(end + 1) = candidate; %#ok<AGROW>
end

eligible = commonCandidates([commonCandidates.eligible]);
context = emptyContext();
context.datasetName = datasetName;
context.datasetIndex = datasetIndex;
context.time = cells(1).time;
context.formation = cells(1).formation;
context.receivers = [cells.receiver];
context.commonCandidateCount = numel(commonCandidates);
context.eligibleCandidateCount = numel(eligible);
if isempty(eligible)
    return;
end
ranking = [[eligible.consensusRescueScore]', ...
    [eligible.minimumSafetyProbability]', ...
    [eligible.minimumRiskReduction]', ...
    -reshape([eligible.label], 2, [])', -[eligible.source]'];
[~, order] = sortrows(ranking, [-1, -2, -3, -4, -5, -6]);
winner = eligible(order(1));
context.selected = true;
fields = fieldnames(winner);
for idx = 1:numel(fields)
    context.(fields{idx}) = winner.(fields{idx});
end
end

function [lowerProbability, inSupport] = predictSafety(model, X)
X = X(:, model.featureMask);
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.featureMean), model.featureScale);
inSupport = all(bsxfun(@ge, Z, model.supportLower) & ...
    bsxfun(@le, Z, model.supportUpper), 2);
probabilityCube = zeros(size(Z, 1), 3, numel(model.members));
for memberIdx = 1:numel(model.members)
    member = model.members{memberIdx};
    hidden = tanh(bsxfun(@plus, ...
        Z * member.parameters{1}, member.parameters{2}));
    logits = bsxfun(@plus, ...
        hidden * member.parameters{3}, member.parameters{4});
    probabilityCube(:, :, memberIdx) = stableSigmoid(logits);
end
lowerProbability = mean(probabilityCube, 3) - ...
    model.uncertaintyPenalty * std(probabilityCube, 0, 3);
end

function pairs = uniquePairs(rows)
if isempty(rows)
    pairs = zeros(3, 0);
    return;
end
pairs = [[rows.label]; [rows.source]];
pairs = unique(pairs', 'rows', 'stable')';
end

function idx = findPair(rows, label, source)
idx = find([rows.source] == source & arrayfun(@(row) ...
    isequal(row.label, label), rows), 1);
if isempty(idx)
    idx = 0;
end
end

function validateModel(model)
required = {'contractVersion', 'featureContractVersion', ...
    'featureMask', 'featureMean', 'featureScale', 'supportLower', ...
    'supportUpper', 'members', 'uncertaintyPenalty', ...
    'probabilityThreshold', 'featuresUseTruth'};
if ~all(isfield(model, required)) || model.featuresUseTruth || ...
        isempty(model.members) || ...
        model.probabilityThreshold < 0.5 || ...
        model.probabilityThreshold >= 1
    error('FormationLocalizationV184:ModelContract', ...
        'The V181 safety-model contract is invalid.');
end
end

function validateDataset(dataset, model)
required = {'contractVersion', 'featureContractVersion', ...
    'featureNames', 'rows', 'cells', 'featuresUseTruth', ...
    'featuresUseFutureInformation', ...
    'numericLabelIdentifiersUsedAsFeatures'};
if ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.featureContractVersion, ...
            model.featureContractVersion) || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.numericLabelIdentifiersUsedAsFeatures
    error('FormationLocalizationV184:DatasetContract', ...
        'A source dataset violates the observable-feature contract.');
end
end

function idx = featureIndex(names, name)
idx = find(strcmp(names, name), 1);
if isempty(idx)
    error('FormationLocalizationV184:MissingFeature', ...
        'Required feature is missing: %s', name);
end
end

function value = stableSigmoid(value)
positive = value >= 0;
negative = ~positive;
result = zeros(size(value));
result(positive) = 1 ./ (1 + exp(-value(positive)));
exponential = exp(value(negative));
result(negative) = exponential ./ (1 + exponential);
value = result;
end

function context = emptyContext()
context = struct( ...
    'datasetName', '', 'datasetIndex', 0, 'time', 0, ...
    'formation', 0, 'receivers', zeros(1, 0), ...
    'commonCandidateCount', 0, 'eligibleCandidateCount', 0, ...
    'selected', false, 'eligible', false, ...
    'label', zeros(2, 1), 'source', 0, 'nodeCount', 0, ...
    'supportCount', 0, 'minimumSafetyProbability', NaN, ...
    'minimumRiskReduction', NaN, 'minimumReceiverPresence', NaN, ...
    'consensusRescueScore', NaN, ...
    'eospaGainByNode', zeros(1, 0), ...
    'rmseGainByNode', zeros(1, 0), ...
    'totalEospaGain', NaN, 'totalRmseGain', NaN, ...
    'minimumEospaGain', NaN, 'minimumRmseGain', NaN, ...
    'harmfulNodeCount', 0);
end

function candidate = emptyCandidateReadout()
candidate = struct( ...
    'eligible', false, 'label', zeros(2, 1), 'source', 0, ...
    'nodeCount', 0, 'supportCount', 0, ...
    'minimumSafetyProbability', NaN, ...
    'minimumRiskReduction', NaN, 'minimumReceiverPresence', NaN, ...
    'consensusRescueScore', NaN, ...
    'eospaGainByNode', zeros(1, 0), ...
    'rmseGainByNode', zeros(1, 0), ...
    'totalEospaGain', NaN, 'totalRmseGain', NaN, ...
    'minimumEospaGain', NaN, 'minimumRmseGain', NaN, ...
    'harmfulNodeCount', 0);
end

function writeReport(path, analysis)
fid = fopen(path, 'w');
if fid < 0
    error('FormationLocalizationV184:ReportOpenFailed', ...
        'Could not open the V184 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V184 formation-coordinated posterior-repair diagnostic\n\n');
fprintf(fid, '- Formation: `%d`\n', analysis.formation);
fprintf(fid, '- Common-action support requirement: `>= %d nodes`\n', ...
    analysis.minimumSupportCount);
fprintf(fid, '- Minimum safety probability: `%.3f`\n', ...
    analysis.minimumSafetyProbability);
fprintf(fid, '- Minimum observable risk reduction: `%.3f`\n', ...
    analysis.minimumRiskReduction);
fprintf(fid, ['- Action semantics: replace one already-present complete ', ...
    'single-label posterior; both existence and spatial density may change.\n']);
fprintf(fid, '- Eligible / truth-safe contexts: `%d / %d`\n\n', ...
    analysis.eligibleContextCount, analysis.safeContextCount);
fprintf(fid, ['| State | t | Common / eligible | Selected label <- source | ', ...
    'Support | Min P | Min risk | Rescue score | ', ...
    'E-OSPA / RMSE gain | Min node E / R | Harmful |\n']);
fprintf(fid, ['|:--|--:|:--|:--|:--|--:|--:|--:|--:|--:|--:|\n']);
for context = analysis.contexts
    if context.selected
        action = sprintf('[%d,%d] <- %d', ...
            context.label(1), context.label(2), context.source);
        fprintf(fid, ...
            ['| %s | %d | %d / %d | `%s` | %d/%d | %.3f | ', ...
             '%+.3f | %.4f | %+.3f / %+.3f | %+.3f / %+.3f | %d |\n'], ...
            context.datasetName, context.time, ...
            context.commonCandidateCount, ...
            context.eligibleCandidateCount, action, ...
            context.supportCount, context.nodeCount, ...
            context.minimumSafetyProbability, ...
            context.minimumRiskReduction, ...
            context.consensusRescueScore, ...
            context.totalEospaGain, context.totalRmseGain, ...
            context.minimumEospaGain, context.minimumRmseGain, ...
            context.harmfulNodeCount);
    else
        fprintf(fid, '| %s | %d | %d / 0 | abstain | - | - | - | - | - | - | - |\n', ...
            context.datasetName, context.time, ...
            context.commonCandidateCount);
    end
end
fprintf(fid, '\n## Per-node truth readout\n\n');
for context = analysis.contexts
    if ~context.selected
        continue;
    end
    fprintf(fid, '- %s, t=%d, `[%d,%d] <- %d`\n\n', ...
        context.datasetName, context.time, context.label(1), ...
        context.label(2), context.source);
    fprintf(fid, '| Receiver | E-OSPA gain | RMSE gain |\n');
    fprintf(fid, '|--:|--:|--:|\n');
    for idx = 1:numel(context.receivers)
        fprintf(fid, '| %d | %+.6f | %+.6f |\n', ...
            context.receivers(idx), context.eospaGainByNode(idx), ...
            context.rmseGainByNode(idx));
    end
    fprintf(fid, '\n');
end
fprintf(fid, '## Decision boundary\n\n%s\n', analysis.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

function value = modelProbabilityFloor()
value = 0.5;
end
