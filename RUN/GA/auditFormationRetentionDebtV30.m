function [reportPath, audit] = ...
    auditFormationRetentionDebtV30(options)
% AUDITFORMATIONRETENTIONDEBTV30 Frozen primary-screen audit.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v30', 'causal_isolate_reconnect', ...
    't72', 'screen', ...
    ['FORMATION_ISOLATE_RECONNECT_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'FORMATION_RETENTION_DEBT_V30_AUDIT_20260802.md'));
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V30Audit:MissingScreen', ...
        'Frozen v30 primary screen is unavailable.');
end
screen = loaded.screen;
assertScreenProvenance(screen);

referenceIdx = screen.referenceSubsetIndex;
candidateIdx = setdiff(1:numel(screen.records), referenceIdx);
if numel(candidateIdx) ~= 1
    error('V30Audit:UnexpectedArmCount', ...
        'The frozen v30 screen must contain one candidate arm.');
end
reference = screen.outcomes(referenceIdx);
candidate = screen.outcomes(candidateIdx);
record = screen.records(candidateIdx);
trackingReferenceByTime = mean( ...
    reference.eospaBySensorTime, 1);
trackingCandidateByTime = mean( ...
    candidate.eospaBySensorTime, 1);
trackingGainByTimePercent = relativeGain( ...
    trackingReferenceByTime, trackingCandidateByTime);
consensusGainByTimePercent = relativeGain( ...
    reference.consensusOspaByTime, ...
    candidate.consensusOspaByTime);
attemptedByteSavingByTimePercent = relativeGain( ...
    reference.attemptedBytesByTime, ...
    candidate.attemptedBytesByTime);
protocol = screen.protocol;
passesEveryNonterminalGate = ...
    record.posteriorProxyAllowed && ...
    candidate.firstActionExact && ...
    candidate.firstFusionWeightsExact && ...
    candidate.laterActionsDynamicallyRecomputed && ...
    all(candidate.posteriorContentUsedByTime) && ...
    all(candidate.currentLinkReliabilityUsedByTime) && ...
    record.meanGainPercent >= ...
        protocol.meanTrackingGainThresholdPercent - 1e-12 && ...
    record.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainThresholdPercent - 1e-12 && ...
    record.worstGainPercent >= ...
        protocol.worstSensorGainThresholdPercent - 1e-12 && ...
    record.consensusGainPercent >= ...
        protocol.windowConsensusGainThresholdPercent - 1e-12 && ...
    record.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    record.selectedB3Passed;
failsOnlyTerminalConsensus = ...
    passesEveryNonterminalGate && ...
    record.terminalConsensusGainPercent < ...
        protocol.terminalConsensusGainThresholdPercent - 1e-12;

audit = struct();
audit.contractVersion = ...
    'formation-retention-debt-v30-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.returnTimes = screen.returnTimes;
audit.referenceIndex = referenceIdx;
audit.candidateIndex = candidateIdx;
audit.candidateActionName = record.actionName;
audit.initialSuspendedFormationIds = record.formationIndices;
audit.meanGainPercent = record.meanGainPercent;
audit.worstSensorGainPercent = record.worstGainPercent;
audit.formationGainPercent = record.formationGainPercent;
audit.minimumFormationGainPercent = ...
    record.minimumFormationGainPercent;
audit.windowConsensusGainPercent = record.consensusGainPercent;
audit.terminalConsensusGainPercent = ...
    record.terminalConsensusGainPercent;
audit.attemptedByteSavingPercent = ...
    record.attemptedByteSavingPercent;
audit.referenceMeanCardinalityError = ...
    reference.meanCardinalityError;
audit.candidateMeanCardinalityError = ...
    candidate.meanCardinalityError;
audit.trackingReferenceByTime = trackingReferenceByTime;
audit.trackingCandidateByTime = trackingCandidateByTime;
audit.trackingGainByTimePercent = trackingGainByTimePercent;
audit.consensusReferenceByTime = ...
    reference.consensusOspaByTime;
audit.consensusCandidateByTime = ...
    candidate.consensusOspaByTime;
audit.consensusGainByTimePercent = ...
    consensusGainByTimePercent;
audit.referenceAttemptedBytesByTime = ...
    reference.attemptedBytesByTime;
audit.candidateAttemptedBytesByTime = ...
    candidate.attemptedBytesByTime;
audit.attemptedByteSavingByTimePercent = ...
    attemptedByteSavingByTimePercent;
audit.policyModeByTime = candidate.policyBackboneModeByTime;
audit.retentionDebtFractionByTime = ...
    candidate.retentionDebtFractionByTime;
audit.retentionDebtThresholdByTime = ...
    candidate.retentionDebtThresholdByTime;
audit.singleAvailableMaskByTime = ...
    candidate.retentionDebtSingleAvailableMaskByTime;
audit.singleSafetyMaskByTime = ...
    candidate.retentionDebtSingleSafetyMaskByTime;
audit.requestedFormationIdsByTime = ...
    candidate.retentionDebtRequestedFormationIdsByTime;
audit.selectedFormationIdsByTime = ...
    candidate.retentionDebtSelectedFormationIdsByTime;
audit.referenceFallbackCountByTime = ...
    candidate.recoveryFallbackCountByTime;
audit.controlRouteEvaluationCountByTime = ...
    candidate.recoveryEvaluatedActionCountByTime;
audit.safeRouteCountByTime = ...
    candidate.recoverySafeActionCountByTime;
audit.passesEveryNonterminalGate = ...
    passesEveryNonterminalGate;
audit.failsOnlyTerminalConsensus = ...
    failsOnlyTerminalConsensus;
audit.strongCandidateCount = ...
    screen.strictStrongCandidateCount;
audit.newTrackingStateOpened = false;
audit.additionalM24Authorized = false;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This audit reads only the frozen v30 primary M24 screen. It ', ...
    'cannot relax the terminal-consensus gate, open t=60 or another ', ...
    'M24 state, train a GNN, run X36/X48, or support validation and ', ...
    'generalization claims. The same opened t=72 trajectory may ', ...
    'motivate a separately frozen, source-only recovery controller.'];

assertMechanism(audit, screen);
writeReport(reportPath, audit);
fprintf('V30 retention-debt audit: %s\n', reportPath);
end

function assertScreenProvenance(screen)
if ~strcmp(screen.contractVersion, ...
        'formation-causal-isolate-reconnect-v30-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            '985120f7945205357a1643574d38e62feaf14063') || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(screen.presetName, 'm24-formation-fov') || ...
        screen.seed ~= 211 || screen.currentTime ~= 72 || ...
        ~isequal(screen.returnTimes, [72, 73, 74]) || ...
        numel(screen.records) ~= 2 || ...
        ~isequal(screen.actionIndices, [1, 15]) || ...
        ~screen.executedOnlyPosteriorSafeInitialActions || ...
        ~screen.causalRetentionDebtPolicyAttested || ...
        screen.strictStrongCandidateCount ~= 0 || ...
        screen.strongCandidateFound || ...
        screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V30Audit:ProvenanceMismatch', ...
        'Frozen v30 screen provenance or gate decision changed.');
end
end

function assertMechanism(audit, screen)
if ~audit.failsOnlyTerminalConsensus || ...
        ~strcmp(audit.candidateActionName, ...
            'suspend-f2-f3-f4') || ...
        ~isequal(audit.initialSuspendedFormationIds, [2, 3, 4]) || ...
        ~isequal(audit.selectedFormationIdsByTime{1}, [2, 3, 4]) || ...
        ~isequal(audit.selectedFormationIdsByTime{2}, [2, 3, 4]) || ...
        ~isempty(audit.selectedFormationIdsByTime{3}) || ...
        ~isequal(audit.singleAvailableMaskByTime{3}, ...
            logical([1, 0, 0, 0])) || ...
        ~isequal(audit.referenceFallbackCountByTime, [0, 0, 1]) || ...
        audit.trackingGainByTimePercent(1) <= 0 || ...
        audit.trackingGainByTimePercent(2) <= 0 || ...
        audit.trackingGainByTimePercent(3) >= 0 || ...
        audit.consensusGainByTimePercent(1) <= 0 || ...
        audit.consensusGainByTimePercent(2) <= 0 || ...
        audit.consensusGainByTimePercent(3) >= 0 || ...
        screen.outcomeRankingUsesTruth ~= true
    error('V30Audit:UnexpectedMechanism', ...
        'Frozen v30 mechanism or terminal failure changed.');
end
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('V30Audit:WriteFailed', ...
        'Could not open v30 audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V30 causal retention-debt audit\n\n');
fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    '**The frozen v30 primary gate fails with `0/1` strong ', ...
    'candidates.** The controller passes every registered gate except ', ...
    'terminal consensus, which changes by `%+.4f%%`. Do not open t=60, ', ...
    'train a GNN, or run X36/X48 under v30.\n\n'], ...
    audit.terminalConsensusGainPercent);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime);
fprintf(fid, '- Return times: `%s`\n', ...
    mat2str(audit.returnTimes));
fprintf(fid, '- New tracking state opened by audit: `0`\n\n');

fprintf(fid, '## Aggregate result\n\n');
fprintf(fid, [ ...
    '| Initial action | Mean tracking | Worst sensor | Formation gains ', ...
    '| Window consensus | Terminal consensus | Byte saving | ', ...
    'Mean card. error |\n']);
fprintf(fid, '|:--|--:|--:|:--|--:|--:|--:|--:|\n');
fprintf(fid, [ ...
    '| `%s` | %+.4f%% | %+.4f%% | `%s` | %+.4f%% | %+.4f%% | ', ...
    '%+.4f%% | %.6f -> %.6f |\n\n'], ...
    audit.candidateActionName, audit.meanGainPercent, ...
    audit.worstSensorGainPercent, ...
    mat2str(audit.formationGainPercent, 5), ...
    audit.windowConsensusGainPercent, ...
    audit.terminalConsensusGainPercent, ...
    audit.attemptedByteSavingPercent, ...
    audit.referenceMeanCardinalityError, ...
    audit.candidateMeanCardinalityError);
fprintf(fid, [ ...
    'The two-step adaptive suspension produces material tracking, ', ...
    'tail, cardinality, window-consensus, and communication gains. ', ...
    'The strict decision remains a failure because the final consensus ', ...
    'value is not allowed to regress.\n\n']);

fprintf(fid, '## Temporal result\n\n');
fprintf(fid, [ ...
    '| Time | Reference tracking | Controller tracking | Tracking gain ', ...
    '| Reference consensus | Controller consensus | Consensus gain ', ...
    '| Byte saving |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for timeIdx = 1:numel(audit.returnTimes)
    fprintf(fid, [ ...
        '| %d | %.6f | %.6f | %+.3f%% | %.6f | %.6f | %+.3f%% ', ...
        '| %+.3f%% |\n'], audit.returnTimes(timeIdx), ...
        audit.trackingReferenceByTime(timeIdx), ...
        audit.trackingCandidateByTime(timeIdx), ...
        audit.trackingGainByTimePercent(timeIdx), ...
        audit.consensusReferenceByTime(timeIdx), ...
        audit.consensusCandidateByTime(timeIdx), ...
        audit.consensusGainByTimePercent(timeIdx), ...
        audit.attemptedByteSavingByTimePercent(timeIdx));
end

fprintf(fid, '\n## Controller trace\n\n');
fprintf(fid, [ ...
    '| Time | Debt fractions | Thresholds | Available singles | ', ...
    'Requested | Selected | Reference fallback |\n']);
fprintf(fid, '|--:|:--|:--|:--|:--|:--|:--:|\n');
for timeIdx = 1:numel(audit.returnTimes)
    fprintf(fid, [ ...
        '| %d | `%s` | `%s` | `%s` | `%s` | `%s` | %d |\n'], ...
        audit.returnTimes(timeIdx), ...
        mat2str(audit.retentionDebtFractionByTime{timeIdx}, 5), ...
        mat2str(audit.retentionDebtThresholdByTime{timeIdx}, 5), ...
        mat2str(audit.singleAvailableMaskByTime{timeIdx}), ...
        mat2str(audit.requestedFormationIdsByTime{timeIdx}), ...
        mat2str(audit.selectedFormationIdsByTime{timeIdx}), ...
        audit.referenceFallbackCountByTime(timeIdx));
end
fprintf(fid, [ ...
    '\nAt t=73, the lower 1%% off-threshold keeps formations 2, 3, ', ...
    'and 4 suspended. At t=74, rolling-B3 makes those three single ', ...
    'suspensions unavailable, so the controller returns to reference. ', ...
    'Compared with v29, this reduces the terminal-consensus deficit ', ...
    'from -7.995%% to -1.595%%, but does not eliminate it.\n\n']);

fprintf(fid, '## Next admissible direction\n\n');
fprintf(fid, [ ...
    'Do not relax the terminal gate or open another state. A separate ', ...
    'v31 no-outcome preflight may use the same opened trajectory to ', ...
    'construct a bounded reconnect action at the forced t=74 return. ', ...
    'That action must be chosen from the then-current posterior, pass ', ...
    'the same label-retention and rolling-connectivity projection, ', ...
    'and keep reference fallback. Its route family and thresholds must ', ...
    'be frozen before the t=72 outcome is rerun.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) ./ max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
