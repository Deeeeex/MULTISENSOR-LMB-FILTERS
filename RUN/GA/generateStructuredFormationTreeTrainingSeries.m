function summary = generateStructuredFormationTreeTrainingSeries( ...
        seedList, snapshotTimes, options)
% GENERATESTRUCTUREDFORMATIONTREETRAININGSERIES Build M24 v4 data.
%
% This one-call entry point first ensures a fixed-topology posterior cache
% at the continuation anchor, then rolls out the privileged joint-tree v4
% behavior and writes truth-free action features plus privileged labels.

if nargin < 1 || isempty(seedList)
    seedList = [19, 23, 29, 31, 37];
end
if nargin < 2 || isempty(snapshotTimes)
    snapshotTimes = 75:80;
end
if nargin < 3 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
snapshotTimes = unique(round(reshape(snapshotTimes, 1, [])));
continuationStartTime = round(getField( ...
    options, 'continuationStartTime', min(snapshotTimes)));
cacheDirectory = getField(options, 'cacheDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'cache'));
sourceWeight = getField(options, 'sourceWeight', 0.70);
overwrite = logical(getField(options, 'overwrite', false));

cacheOptions = struct( ...
    'snapshotTimes', continuationStartTime, ...
    'behaviorCacheDirectory', cacheDirectory, ...
    'behaviorCacheOnly', true, ...
    'writeReport', false, ...
    'filterSeedOffset', getField( ...
        options, 'staticFilterSeedOffset', 200000));
[~, cacheSummary] = runDynamicTopologyTeacherSignalScreen( ...
    'm24-hard', seedList, cacheOptions);

teacherOptions = struct( ...
    'behaviorPolicy', 'oracle-tree-v4', ...
    'sourceWeight', sourceWeight, ...
    'continuationStartTime', continuationStartTime, ...
    'behaviorCacheDirectory', cacheDirectory, ...
    'outputDirectory', cacheDirectory, ...
    'overwrite', overwrite, ...
    'filterSeedOffset', getField( ...
        options, 'teacherFilterSeedOffset', 100000));
[datasetPaths, teacherSummary] = ...
    generateDirectedRoutingTeacherSeries( ...
        'm24-hard', seedList, snapshotTimes, teacherOptions);

summary = struct( ...
    'generatedAt', datestr(now, 31), ...
    'seedList', seedList, ...
    'snapshotTimes', snapshotTimes, ...
    'continuationStartTime', continuationStartTime, ...
    'sourceWeight', sourceWeight, ...
    'cacheDirectory', cacheDirectory, ...
    'datasetPaths', {datasetPaths}, ...
    'cacheSummary', cacheSummary, ...
    'teacherSummary', teacherSummary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
