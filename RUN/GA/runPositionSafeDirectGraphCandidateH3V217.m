function [reportPath, result] = ...
        runPositionSafeDirectGraphCandidateH3V217(options)
% RUNPOSITIONSAFEDIRECTGRAPHCANDIDATEH3V217 Label the bounded repair set.

if nargin < 1 || isempty(options)
    options = struct();
end
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
candidateIndices = reshape(getField( ...
    options, 'candidateIndices', zeros(1, 0)), 1, []);
reuseExistingScreens = logical(getField( ...
    options, 'reuseExistingScreens', true));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v217', 'candidate_h3')));
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2
    error('DirectGraphCandidateH3V217:MissingBank', ...
        'A completed V217 candidate bank is required.');
end
loaded = load(candidateBankPath, 'result');
bankResult = loaded.result;
if ~strcmp(bankResult.contractVersion, ...
        'position-safe-direct-graph-candidate-bank-v217-v1') || ...
        ~bankResult.exactLiveBankReconstructed || ...
        bankResult.truthUsed || bankResult.futureInformationUsed
    error('DirectGraphCandidateH3V217:BankContract', ...
        'The V217 candidate bank is malformed.');
end
feasibleRows = find(bankResult.creditFeasibleMask);
if isempty(candidateIndices)
    selectedRows = feasibleRows;
else
    if any(~isfinite(candidateIndices)) || ...
            any(candidateIndices ~= round(candidateIndices)) || ...
            numel(unique(candidateIndices)) ~= numel(candidateIndices)
        error('DirectGraphCandidateH3V217:CandidateIndices', ...
            'Requested candidate indices must be unique integers.');
    end
    [present, selectedRows] = ismember(candidateIndices, ...
        [bankResult.shortlist.candidateIndex]);
    if ~all(present) || any(~bankResult.creditFeasibleMask(selectedRows))
        error('DirectGraphCandidateH3V217:CandidateIndices', ...
            'Every requested candidate must be shortlisted and credit-feasible.');
    end
end

sourceLoaded = load(bankResult.sourceScreenPath, 'screen');
sourceScreen = sourceLoaded.screen;
referenceScreenPath = sourceScreen.referenceOutcomeScreenPath;
referenceLoaded = load(referenceScreenPath, 'screen');
referenceScreen = referenceLoaded.screen;
referenceRecord = referenceScreen.records( ...
    referenceScreen.referenceSubsetIndex);
withholdingName = sprintf( ...
    'v214-withhold-full-posterior-f%d-one-page', ...
    bankResult.targetFormationId);
withholdingIdx = find(strcmp( ...
    {referenceScreen.records.actionName}, withholdingName));
if numel(withholdingIdx) ~= 1
    error('DirectGraphCandidateH3V217:WithholdingReference', ...
        'The paired withholding-only action is missing.');
end
withholdingRecord = referenceScreen.records(withholdingIdx);

protocol = getDirectGraphCreditRepairControllerV216Protocol();
v213 = getHierarchicalDelayedValueControllerV213Protocol();
records = repmat(emptyRecord(), 1, numel(selectedRows));
for selectedPosition = 1:numel(selectedRows)
    shortlistRow = selectedRows(selectedPosition);
    candidate = bankResult.shortlist(shortlistRow);
    leaf = sprintf('c%03d_s%d_l%d-%d', ...
        candidate.candidateIndex, candidate.sourceId, ...
        candidate.label(1), candidate.label(2));
    screenRoot = fullfile(outputRoot, leaf, 'screen');
    screenStem = sprintf( ...
        'FORMATION_MODE_H3_%s_SEED%d_T%d', ...
        upper(strrep(bankResult.presetName, '-', '_')), ...
        bankResult.seed, bankResult.currentTime);
    screenPath = fullfile(screenRoot, [screenStem, '.mat']);
    if reuseExistingScreens && reusableCandidateScreen(screenPath)
        existing = load(screenPath, 'screen');
        candidateScreen = existing.screen;
    else
        screenOptions = struct();
        screenOptions.horizonSteps = protocol.horizonSteps;
        screenOptions.interventionDurationSteps = 1;
        screenOptions.filterSeedOffset = protocol.filterSeedOffset;
        screenOptions.cacheRoot = fileparts(sourceScreen.cachePath);
        screenOptions.interventionBankType = ...
            'direct-graph-payload-repair-v214';
        screenOptions.trackingAlignedExecutionProfile = ...
            'v214-direct-graph-payload-repair';
        screenOptions.receiverMode = protocol.receiverMode;
        screenOptions.directGraphSplitName = 'training';
        screenOptions.directGraphPayloadRepairBankOptions = struct( ...
            'actionMode', protocol.actionMode, ...
            'referenceAttemptedBytes', ...
                repairReferencePageBytes(sourceScreen), ...
            'repairSourceWeight', protocol.repairSourceWeight, ...
            'formationIds', bankResult.targetFormationId, ...
            'repairIdealDeliveryTeacherMode', true, ...
            'repairForcedSourceId', candidate.sourceId, ...
            'repairForcedLabel', candidate.label);
        screenOptions.referenceOutcomeScreenPath = referenceScreenPath;
        screenOptions.outputDirectory = screenRoot;
        screenOptions.writeReport = true;
        screenOptions.capturePosteriorSnapshotsEnabled = false;
        screenOptions.captureFusedPosteriorSnapshotsEnabled = false;
        [~, candidateScreen] = runFormationModeOpenedReturnScreen( ...
            bankResult.presetName, bankResult.seed, ...
            bankResult.currentTime, screenOptions);
    end
    nonreferenceIdx = find([candidateScreen.records.actionIndex] ~= ...
        candidateScreen.bank.referenceActionIndex);
    if numel(nonreferenceIdx) ~= 1
        error('DirectGraphCandidateH3V217:CandidateArm', ...
            'Each V217 teacher screen must contain one candidate arm.');
    end
    candidateRecord = candidateScreen.records(nonreferenceIdx);
    candidateOutcome = candidateScreen.outcomes(nonreferenceIdx);
    if candidateOutcome. ...
            budgetRecycledFormationRepairAppliedActionCountByTime(1) ~= 1
        error('DirectGraphCandidateH3V217:ActionNotApplied', ...
            'The forced complete-label KLA action did not execute once.');
    end
    referenceOutcome = candidateScreen.outcomes( ...
        candidateScreen.referenceSubsetIndex);
    gainVector = buildGainVector( ...
        referenceOutcome, candidateOutcome, ...
        candidateScreen.sensorGroupIds, ...
        bankResult.targetFormationId);
    riskPassed = all(gainVector >= ...
        v213.risk.tolerancePercent - 1e-10);
    byteReservePassed = candidateRecord.attemptedByteSavingPercent >= ...
        v213.risk.minimumStaticAttemptedByteSavingPercent - 1e-10;

    item = emptyRecord();
    item.candidateIndex = candidate.candidateIndex;
    item.shortlistRow = shortlistRow;
    item.sourceId = candidate.sourceId;
    item.label = candidate.label;
    item.screenPath = screenPath;
    item.gainVectorPercent = gainVector;
    item.meanEospaGainPercent = candidateRecord.meanGainPercent;
    item.meanRmseGainPercent = candidateRecord.rmseGainPercent;
    item.consensusGainPercent = candidateRecord.consensusGainPercent;
    item.terminalConsensusGainPercent = ...
        candidateRecord.terminalConsensusGainPercent;
    item.attemptedByteSavingPercent = ...
        candidateRecord.attemptedByteSavingPercent;
    item.repairVsWithholdingEospaGainPercent = relativeGain( ...
        withholdingRecord.meanEospa, candidateRecord.meanEospa);
    item.repairVsWithholdingRmseGainPercent = relativeGain( ...
        withholdingRecord.meanRmse, candidateRecord.meanRmse);
    item.repairVsWithholdingConsensusGainPercent = relativeGain( ...
        withholdingRecord.consensusOspa, candidateRecord.consensusOspa);
    item.riskPassed = riskPassed;
    item.byteReservePassed = byteReservePassed;
    item.admittedTeacherLabel = riskPassed && byteReservePassed;
    item.actionFeatureVector = candidate.featureVector;
    item.payloadAttemptedBytes = ...
        bankResult.payloadAttemptedBytes(shortlistRow);
    records(selectedPosition) = item;
end

result = struct();
result.contractVersion = ...
    'position-safe-direct-graph-candidate-h3-v217-v1';
result.generatedAt = datestr(now, 31);
result.candidateBankPath = candidateBankPath;
result.sourceScreenPath = bankResult.sourceScreenPath;
result.referenceScreenPath = referenceScreenPath;
result.presetName = bankResult.presetName;
result.seed = bankResult.seed;
result.currentTime = bankResult.currentTime;
result.targetFormationId = bankResult.targetFormationId;
result.targetNames = v213.risk.targetNames;
result.records = records;
result.candidateCount = numel(records);
result.admittedCandidateCount = nnz([records.admittedTeacherLabel]);
result.bestAdmittedRecordIndex = selectBest(records);
result.withholdingOnlyRecord = withholdingRecord;
result.referenceRecord = referenceRecord;
result.idealDeliveryTeacherMode = true;
result.actualDeliveryConditionedCandidateBank = true;
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.truthUsedForH3Targets = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V217 evaluates only the frozen position-safe, mode-diverse and ', ...
    'credit-feasible candidate keys from one causal training state. ', ...
    'Ideal delivery isolates conditional action value; the bank itself ', ...
    'was conditioned on the realized current delivery graph. Truth scores ', ...
    'the paired H=3 targets only.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'POSITION_SAFE_DIRECT_GRAPH_CANDIDATE_H3_V217.mat');
reportPath = fullfile(outputRoot, ...
    'POSITION_SAFE_DIRECT_GRAPH_CANDIDATE_H3_V217.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V217 position-safe candidate H=3: %s\n', reportPath);
end

function reusable = reusableCandidateScreen(screenPath)
reusable = false;
if exist(screenPath, 'file') ~= 2
    return;
end
loaded = load(screenPath, 'screen');
screen = loaded.screen;
nonreferenceIdx = find([screen.records.actionIndex] ~= ...
    screen.bank.referenceActionIndex);
if numel(nonreferenceIdx) ~= 1
    return;
end
applied = screen.outcomes(nonreferenceIdx). ...
    budgetRecycledFormationRepairAppliedActionCountByTime;
reusable = ~isempty(applied) && applied(1) == 1;
end

function bytes = repairReferencePageBytes(screen)
reference = screen.outcomes(screen.referenceSubsetIndex);
bytes = reference.attemptedBytesByTime(1);
end

function gains = buildGainVector( ...
        reference, candidate, groupIds, targetFormationId)
receiverIds = find(groupIds == targetFormationId);
formationIds = unique(groupIds, 'stable');
targetRow = find(formationIds == targetFormationId, 1);
sensorEospaGain = relativeGainVector( ...
    reference.sensorMeanEospa, candidate.sensorMeanEospa);
sensorRmseGain = relativeGainVector( ...
    reference.sensorMeanRmse, candidate.sensorMeanRmse);
formationEospaGain = relativeGainVector( ...
    reference.formationMeanEospa, candidate.formationMeanEospa);
formationRmseGain = relativeGainVector( ...
    reference.formationMeanRmse, candidate.formationMeanRmse);
gains = [ ...
    relativeGain(reference.meanEospa, candidate.meanEospa), ...
    relativeGain(reference.meanRmse, candidate.meanRmse), ...
    relativeGain(reference.consensusOspa, candidate.consensusOspa), ...
    relativeGain(reference.terminalConsensusOspa, ...
        candidate.terminalConsensusOspa), ...
    formationEospaGain(targetRow), ...
    formationRmseGain(targetRow), ...
    min(sensorEospaGain(receiverIds)), ...
    min(sensorRmseGain(receiverIds)), ...
    relativeGain(reference.worstSensorEospa, ...
        candidate.worstSensorEospa), ...
    relativeGain(reference.worstSensorRmse, ...
        candidate.worstSensorRmse), ...
    min(formationEospaGain), ...
    min(formationRmseGain)];
end

function idx = selectBest(records)
eligible = find([records.admittedTeacherLabel]);
if isempty(eligible)
    idx = 0;
    return;
end
score = arrayfun(@(record) min(record.gainVectorPercent), ...
    records(eligible));
tie = [[records(eligible).attemptedByteSavingPercent]', ...
    -[records(eligible).candidateIndex]'];
rows = [-score(:), -tie(:, 1), -tie(:, 2)];
[~, order] = sortrows(rows, [1, 2, 3]);
idx = eligible(order(1));
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('DirectGraphCandidateH3V217:WriteReport', ...
        'Could not write the V217 H3 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V217 position-safe direct-graph candidate H=3\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d / F%d`\n', ...
    result.presetName, result.seed, result.currentTime, ...
    result.targetFormationId);
fprintf(fid, '- Evaluated / admitted: `%d / %d`\n', ...
    result.candidateCount, result.admittedCandidateCount);
fprintf(fid, '- Best admitted record: `%d`\n\n', ...
    result.bestAdmittedRecordIndex);
fprintf(fid, '| Candidate | Source | Label | E-OSPA gain | RMSE gain | Consistency gain | Terminal consistency gain | Byte saving | Repair vs withholding E/R/C | Risk pass | Admit |\n');
fprintf(fid, '|--:|--:|:--|--:|--:|--:|--:|--:|:--|:--:|:--:|\n');
for record = result.records
    fprintf(fid, '| %d | %d | `[%d,%d]` | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | `%+.3f / %+.3f / %+.3f%%` | %d | %d |\n', ...
        record.candidateIndex, record.sourceId, ...
        record.label(1), record.label(2), ...
        record.meanEospaGainPercent, record.meanRmseGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent, ...
        record.repairVsWithholdingEospaGainPercent, ...
        record.repairVsWithholdingRmseGainPercent, ...
        record.repairVsWithholdingConsensusGainPercent, ...
        record.riskPassed, record.admittedTeacherLabel);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function record = emptyRecord()
record = struct( ...
    'candidateIndex', 0, 'shortlistRow', 0, 'sourceId', 0, ...
    'label', zeros(2, 1), 'screenPath', '', ...
    'gainVectorPercent', zeros(1, 12), ...
    'meanEospaGainPercent', 0, 'meanRmseGainPercent', 0, ...
    'consensusGainPercent', 0, ...
    'terminalConsensusGainPercent', 0, ...
    'attemptedByteSavingPercent', 0, ...
    'repairVsWithholdingEospaGainPercent', 0, ...
    'repairVsWithholdingRmseGainPercent', 0, ...
    'repairVsWithholdingConsensusGainPercent', 0, ...
    'riskPassed', false, 'byteReservePassed', false, ...
    'admittedTeacherLabel', false, ...
    'actionFeatureVector', zeros(1, 21), ...
    'payloadAttemptedBytes', 0);
end

function values = relativeGainVector(reference, candidate)
values = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
