function [reportPath, summaryPath, validation, summary] = ...
    runFullVsLightEquivalenceValidation( ...
        numberOfTrials, baseSeed, runExperiment, simulationLength)
% RUNFULLVSLIGHTEQUIVALENCEVALIDATION
% Verify that full GM-LMB payloads and light moment-matched payloads are
% equivalent for the current single-round moment-matched KLA fusion path.
%
% Dry run:
%   [~, ~, validation] = runFullVsLightEquivalenceValidation([], [], false);
%
% Default validation:
%   [reportPath, summaryPath, validation] = ...
%       runFullVsLightEquivalenceValidation();

if nargin < 1 || isempty(numberOfTrials)
    numberOfTrials = 3;
end
if nargin < 2 || isempty(baseSeed)
    baseSeed = 156;
end
if nargin < 3 || isempty(runExperiment)
    runExperiment = true;
end
if nargin < 4 || isempty(simulationLength)
    simulationLength = 50;
end

scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir)
    scriptDir = pwd;
end
projectRoot = resolveProjectRoot(scriptDir);
addpath(projectRoot);
addpath(scriptDir);
setPath;

config = struct();
config.numberOfTrials = numberOfTrials;
config.baseSeed = baseSeed;
config.useFixedSeed = true;
config.writeReport = true;
config.thresholdProfile = 'default';
config.simulationLength = simulationLength;
config.armSelection = { ...
    'Periodic full posterior', ...
    'Periodic light posterior on static topology'};
config.experimentOverrides = struct( ...
    'simulationLength', simulationLength, ...
    'calibration', buildCalibrationStub(), ...
    'pDropByEdge', zeros(8), ...
    'includeFinalPeriodicLightVariants', true, ...
    'enableFullLightEquivalenceDiagnostics', true, ...
    'storeDebugArtifacts', true);

reportPath = '';
summaryPath = '';
validation = buildEmptyValidation(config);
summary = [];

fprintf('\nFull-vs-light equivalence validation\n');
fprintf('Trials: %d, baseSeed: %d, seeds: %d:%d\n', ...
    config.numberOfTrials, config.baseSeed, ...
    config.baseSeed + 1, config.baseSeed + config.numberOfTrials);
fprintf('Simulation length: %d steps\n', config.simulationLength);
fprintf('Arms:\n');
for armIdx = 1:numel(config.armSelection)
    fprintf('  %d. %s\n', armIdx, config.armSelection{armIdx});
end

if ~runExperiment
    fprintf('Dry run only. No experiment was launched.\n');
    return;
end

[comparisonReportPath, summary] = ...
    runMultisensorFilters_formation_4plus4_DualThresholdEventTriggerCompare( ...
        config.numberOfTrials, config.baseSeed, config.useFixedSeed, ...
        config.writeReport, config.thresholdProfile, ...
        config.armSelection, config.experimentOverrides);

validation = buildValidationSummary(summary, comparisonReportPath, config);
timestamp = datestr(now, 'yyyymmdd_HHMMSS');
summaryPath = fullfile(scriptDir, sprintf( ...
    'full_vs_light_equivalence_n%d_seed%d_%s.mat', ...
    config.numberOfTrials, config.baseSeed, timestamp));
reportPath = fullfile(scriptDir, sprintf( ...
    'FULL_VS_LIGHT_EQUIVALENCE_N%d_SEED%d_%s.md', ...
    config.numberOfTrials, config.baseSeed, timestamp));
save(summaryPath, 'validation', 'summary', 'config', ...
    'comparisonReportPath');
writeValidationReport(reportPath, validation);

fprintf('\nFull-vs-light equivalence result\n');
fprintf('Payload max r diff: %.3e\n', ...
    validation.equivalence.maxPayloadExistenceAbsDiff);
fprintf('Payload max mean diff: %.3e\n', ...
    validation.equivalence.maxPayloadMeanNormDiff);
fprintf('Payload max covariance diff: %.3e\n', ...
    validation.equivalence.maxPayloadCovFroDiff);
fprintf('Fused max r diff: %.3e\n', ...
    validation.equivalence.maxFusedExistenceAbsDiff);
fprintf('Fused max mean diff: %.3e\n', ...
    validation.equivalence.maxFusedMeanNormDiff);
fprintf('Fused max covariance diff: %.3e\n', ...
    validation.equivalence.maxFusedCovFroDiff);
fprintf('Light bytes reduction: %.2f%%\n', ...
    validation.bytes.lightReductionPercent);
fprintf('Report: %s\n', reportPath);
fprintf('Summary: %s\n', summaryPath);
end

function validation = buildEmptyValidation(config)
validation = struct();
validation.config = config;
validation.comparisonReportPath = '';
validation.bytes = struct();
validation.equivalence = struct();
validation.metricDelta = struct();
end

function validation = buildValidationSummary( ...
    summary, comparisonReportPath, config)
fullIdx = find(strcmp(summary.armNames, 'Periodic full posterior'), 1);
lightIdx = find(strcmp(summary.armNames, ...
    'Periodic light posterior on static topology'), 1);
if isempty(fullIdx) || isempty(lightIdx)
    error('Required full/light arms are missing from the comparison summary.');
end

validation = buildEmptyValidation(config);
validation.comparisonReportPath = comparisonReportPath;
validation.armNames = summary.armNames([fullIdx, lightIdx]);
validation.trialSeeds = summary.trialSeeds;

fullBytes = summary.communication.payloadBytes(fullIdx);
lightBytes = summary.communication.payloadBytes(lightIdx);
fullScalars = summary.communication.payloadScalars(fullIdx);
lightScalars = summary.communication.payloadScalars(lightIdx);
validation.bytes = struct( ...
    'fullPayloadBytes', fullBytes, ...
    'lightPayloadBytes', lightBytes, ...
    'lightReductionPercent', percentReduction(fullBytes, lightBytes), ...
    'fullPayloadScalars', fullScalars, ...
    'lightPayloadScalars', lightScalars, ...
    'lightScalarReductionPercent', ...
        percentReduction(fullScalars, lightScalars));

validation.metricDelta = struct( ...
    'maxTrialSensorLocalEOspaAbsDiff', maxVector(abs( ...
        summary.trials.localEOspa(:, :, fullIdx) - ...
        summary.trials.localEOspa(:, :, lightIdx))), ...
    'maxTrialConsensusOspaAbsDiff', max(abs( ...
        summary.trials.consensusOspa(:, fullIdx) - ...
        summary.trials.consensusOspa(:, lightIdx))), ...
    'maxTrialPositionAbsDiff', max(abs( ...
        summary.trials.consensusPosition(:, fullIdx) - ...
        summary.trials.consensusPosition(:, lightIdx))), ...
    'maxTrialCardinalityAbsDiff', max(abs( ...
        summary.trials.consensusCardinality(:, fullIdx) - ...
        summary.trials.consensusCardinality(:, lightIdx))));

validation.equivalence = aggregateEquivalenceDiagnostics( ...
    summary, fullIdx);
end

function value = maxVector(values)
values = values(:);
if isempty(values)
    value = 0;
else
    value = max(values);
end
end

function aggregate = aggregateEquivalenceDiagnostics(summary, armIdx)
aggregate = initializeAggregate();
if ~isfield(summary, 'debugArtifacts')
    return;
end
for trialIdx = 1:summary.numberOfTrials
    artifact = summary.debugArtifacts{trialIdx, armIdx};
    if isempty(artifact) || ...
            ~isfield(artifact.communicationDiagnostics.summary, ...
            'fullLightEquivalence')
        continue;
    end
    trialStats = artifact.communicationDiagnostics.summary. ...
        fullLightEquivalence;
    aggregate.payloadComparisonCount = ...
        aggregate.payloadComparisonCount + ...
        trialStats.payloadComparisonCount;
    aggregate.payloadObjectCount = aggregate.payloadObjectCount + ...
        trialStats.payloadObjectCount;
    aggregate.payloadMissingLabelCount = ...
        aggregate.payloadMissingLabelCount + ...
        trialStats.payloadMissingLabelCount;
    aggregate.maxPayloadExistenceAbsDiff = max( ...
        aggregate.maxPayloadExistenceAbsDiff, ...
        trialStats.maxPayloadExistenceAbsDiff);
    aggregate.maxPayloadMeanNormDiff = max( ...
        aggregate.maxPayloadMeanNormDiff, ...
        trialStats.maxPayloadMeanNormDiff);
    aggregate.maxPayloadCovFroDiff = max( ...
        aggregate.maxPayloadCovFroDiff, ...
        trialStats.maxPayloadCovFroDiff);
    aggregate.fullPayloadBytes = aggregate.fullPayloadBytes + ...
        trialStats.fullPayloadBytes;
    aggregate.lightPayloadBytes = aggregate.lightPayloadBytes + ...
        trialStats.lightPayloadBytes;
    aggregate.fullPayloadScalars = aggregate.fullPayloadScalars + ...
        trialStats.fullPayloadScalars;
    aggregate.lightPayloadScalars = aggregate.lightPayloadScalars + ...
        trialStats.lightPayloadScalars;
    aggregate.fusionComparisonCount = ...
        aggregate.fusionComparisonCount + ...
        trialStats.fusionComparisonCount;
    aggregate.fusionObjectCount = aggregate.fusionObjectCount + ...
        trialStats.fusionObjectCount;
    aggregate.fusionMissingLabelCount = ...
        aggregate.fusionMissingLabelCount + ...
        trialStats.fusionMissingLabelCount;
    aggregate.fusionHeavyInputReplacementCount = ...
        aggregate.fusionHeavyInputReplacementCount + ...
        trialStats.fusionHeavyInputReplacementCount;
    aggregate.maxFusedExistenceAbsDiff = max( ...
        aggregate.maxFusedExistenceAbsDiff, ...
        trialStats.maxFusedExistenceAbsDiff);
    aggregate.maxFusedMeanNormDiff = max( ...
        aggregate.maxFusedMeanNormDiff, ...
        trialStats.maxFusedMeanNormDiff);
    aggregate.maxFusedCovFroDiff = max( ...
        aggregate.maxFusedCovFroDiff, ...
        trialStats.maxFusedCovFroDiff);
end
aggregate.hypotheticalLightBytesReduction = percentReduction( ...
    aggregate.fullPayloadBytes, aggregate.lightPayloadBytes);
aggregate.hypotheticalLightScalarsReduction = percentReduction( ...
    aggregate.fullPayloadScalars, aggregate.lightPayloadScalars);
end

function aggregate = initializeAggregate()
aggregate = struct( ...
    'payloadComparisonCount', 0, ...
    'payloadObjectCount', 0, ...
    'payloadMissingLabelCount', 0, ...
    'maxPayloadExistenceAbsDiff', 0, ...
    'maxPayloadMeanNormDiff', 0, ...
    'maxPayloadCovFroDiff', 0, ...
    'fullPayloadBytes', 0, ...
    'lightPayloadBytes', 0, ...
    'fullPayloadScalars', 0, ...
    'lightPayloadScalars', 0, ...
    'hypotheticalLightBytesReduction', NaN, ...
    'hypotheticalLightScalarsReduction', NaN, ...
    'fusionComparisonCount', 0, ...
    'fusionObjectCount', 0, ...
    'fusionMissingLabelCount', 0, ...
    'fusionHeavyInputReplacementCount', 0, ...
    'maxFusedExistenceAbsDiff', 0, ...
    'maxFusedMeanNormDiff', 0, ...
    'maxFusedCovFroDiff', 0);
end

function calibration = buildCalibrationStub()
calibration = struct();
calibration.multi.loose = [0.20, 0.40];
calibration.multi.default = [0.25, 0.60];
calibration.multi.strict = [0.35, 0.80];
calibration.information.loose = [0.20, 0.40];
calibration.information.default = [0.25, 0.60];
calibration.information.strict = [0.35, 0.80];
calibration.sampleCount.utility = 0;
calibration.sampleCount.informationGain = 0;
end

function writeValidationReport(reportPath, validation)
fid = fopen(reportPath, 'w');
if fid < 0
    error('Could not write report: %s', reportPath);
end
cleanup = onCleanup(@() fclose(fid));

fprintf(fid, '# Full-vs-light equivalence validation\n\n');
fprintf(fid, '- Trials: %d\n', validation.config.numberOfTrials);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.trialSeeds));
fprintf(fid, '- Simulation length: %d\n', ...
    validation.config.simulationLength);
fprintf(fid, '- Comparison report: `%s`\n\n', ...
    validation.comparisonReportPath);

fprintf(fid, '## Payload bytes\n\n');
fprintf(fid, '| Arm | Mean payload scalars | Mean payload bytes |\n');
fprintf(fid, '|:--|--:|--:|\n');
fprintf(fid, '| Periodic full posterior | %.0f | %.0f |\n', ...
    validation.bytes.fullPayloadScalars, ...
    validation.bytes.fullPayloadBytes);
fprintf(fid, '| Periodic light posterior on static topology | %.0f | %.0f |\n', ...
    validation.bytes.lightPayloadScalars, ...
    validation.bytes.lightPayloadBytes);
fprintf(fid, '| Light reduction | %.2f%% | %.2f%% |\n\n', ...
    validation.bytes.lightScalarReductionPercent, ...
    validation.bytes.lightReductionPercent);

fprintf(fid, '## Moment equivalence diagnostics\n\n');
fprintf(fid, '| Stage | Comparisons | Objects | Missing labels | Max existence diff | Max mean norm diff | Max covariance Fro diff |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
fprintf(fid, '| Payload: full moment-matched vs light payload | %d | %d | %d | %.3e | %.3e | %.3e |\n', ...
    validation.equivalence.payloadComparisonCount, ...
    validation.equivalence.payloadObjectCount, ...
    validation.equivalence.payloadMissingLabelCount, ...
    validation.equivalence.maxPayloadExistenceAbsDiff, ...
    validation.equivalence.maxPayloadMeanNormDiff, ...
    validation.equivalence.maxPayloadCovFroDiff);
fprintf(fid, '| Fused posterior: full-input KLA vs light-input KLA | %d | %d | %d | %.3e | %.3e | %.3e |\n\n', ...
    validation.equivalence.fusionComparisonCount, ...
    validation.equivalence.fusionObjectCount, ...
    validation.equivalence.fusionMissingLabelCount, ...
    validation.equivalence.maxFusedExistenceAbsDiff, ...
    validation.equivalence.maxFusedMeanNormDiff, ...
    validation.equivalence.maxFusedCovFroDiff);

fprintf(fid, '## End-to-end metric deltas\n\n');
fprintf(fid, '| Metric | Max absolute difference |\n');
fprintf(fid, '|:--|--:|\n');
fprintf(fid, '| Trial/sensor local E-OSPA | %.3e |\n', ...
    validation.metricDelta.maxTrialSensorLocalEOspaAbsDiff);
fprintf(fid, '| Trial consensus OSPA | %.3e |\n', ...
    validation.metricDelta.maxTrialConsensusOspaAbsDiff);
fprintf(fid, '| Trial position disagreement | %.3e |\n', ...
    validation.metricDelta.maxTrialPositionAbsDiff);
fprintf(fid, '| Trial cardinality dispersion | %.3e |\n\n', ...
    validation.metricDelta.maxTrialCardinalityAbsDiff);

fprintf(fid, '## Interpretation\n\n');
fprintf(fid, 'In the current single-round label-wise KLA implementation, ');
fprintf(fid, 'neighbor full GM-LMB payloads are moment-matched before fusion. ');
fprintf(fid, 'The light payload sends those same label-wise moments directly. ');
fprintf(fid, 'Therefore the full and light inputs produce numerically identical ');
fprintf(fid, 'KLA fused posteriors up to floating-point tolerance, while the ');
fprintf(fid, 'light payload reduces transmitted scalars and bytes.\n');
end

function reduction = percentReduction(referenceValue, candidateValue)
if referenceValue <= 0
    reduction = NaN;
else
    reduction = 100 * (referenceValue - candidateValue) / referenceValue;
end
end

function projectRoot = resolveProjectRoot(scriptDir)
projectRoot = scriptDir;
while ~exist(fullfile(projectRoot, 'setPath.m'), 'file')
    parentDir = fileparts(projectRoot);
    if strcmp(parentDir, projectRoot)
        error('Could not locate project root from %s.', scriptDir);
    end
    projectRoot = parentDir;
end
end
