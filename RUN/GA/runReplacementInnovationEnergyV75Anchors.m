function [reportPath, result] = ...
    runReplacementInnovationEnergyV75Anchors(options)
% RUNREPLACEMENTINNOVATIONENERGYV75ANCHORS Fast source-only V75 check.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReplacementInnovationEnergyV75Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReplacementInnovationV75:DirtySource', ...
        'The V75 innovation diagnosis requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocolFusionConfig()));
    alignedTriples = selectedSlotTriples(analysis);
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    historical = computeReplacementInnovationEnergyV75( ...
        state.context.localPosteriorBySensor, historicalTriples, ...
        state.groupIds, state.context.model, ...
        state.context.commConfig, state.currentTime, protocol);
    aligned = computeReplacementInnovationEnergyV75( ...
        state.context.localPosteriorBySensor, alignedTriples, ...
        state.groupIds, state.context.model, ...
        state.context.commConfig, state.currentTime, protocol);
    records(caseIdx) = makeCaseRecord( ...
        state, caseInfo, historical, aligned);
    fprintf('V75 %s t=%d historical=%s aligned=%s match=%d\n', ...
        caseInfo.presetName, caseInfo.currentTime, ...
        formatFormationRisk(historical.formationRecords), ...
        formatFormationRisk(aligned.formationRecords), ...
        records(caseIdx).retrospectiveDirectionMatch);
end

result = struct();
result.contractVersion = ...
    'replacement-innovation-energy-v75-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allRetrospectiveDirectionsMatch = ...
    all([records.retrospectiveDirectionMatch]);
result.allHistoricalSlotsCovered = ...
    all([records.historicalAllSlotsCovered]);
result.allAlignedSlotsCovered = ...
    all([records.alignedAllSlotsCovered]);
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'REPLACEMENT_INNOVATION_ENERGY_V75_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'REPLACEMENT_INNOVATION_ENERGY_V75_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V75 replacement innovation energy: %s\n', reportPath);
end

function config = protocolFusionConfig()
config = buildMixtureAwareKlaReferenceConfig();
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function record = makeCaseRecord( ...
        state, caseInfo, historical, aligned)
expectedIds = reshape( ...
    caseInfo.retrospectiveFormationIds, 1, []);
expectedSafe = logical(reshape( ...
    caseInfo.retrospectiveExpectedSafe, 1, []));
observedSafe = false(size(expectedSafe));
for idx = 1:numel(expectedIds)
    recordIdx = find([historical.formationRecords.formationId] == ...
        expectedIds(idx), 1);
    if isempty(recordIdx)
        error('ReplacementInnovationV75:MissingFormation', ...
            'Historical route lacks an expected formation.');
    end
    observedSafe(idx) = ...
        historical.formationRecords(recordIdx).safe;
end
record = emptyCaseRecord();
record.presetName = state.presetName;
record.seed = state.seed;
record.currentTime = state.currentTime;
record.expectedFormationIds = expectedIds;
record.expectedHistoricalSafe = expectedSafe;
record.observedHistoricalSafe = observedSafe;
record.retrospectiveDirectionMatch = ...
    historical.allSlotsCovered && isequal(observedSafe, expectedSafe);
record.historical = historical;
record.aligned = aligned;
record.historicalAllSlotsCovered = historical.allSlotsCovered;
record.alignedAllSlotsCovered = aligned.allSlotsCovered;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReplacementInnovationV75:WriteFailed', ...
        'Could not create the V75 result report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V75 replacement innovation-energy anchors\n\n');
fprintf(fid, '- Conditional energy limit: `%.9f`\n', ...
    result.protocol.conditionalEnergyLimit);
fprintf(fid, '- Limit chosen after opened-anchor inspection: `1`\n');
fprintf(fid, '- Validation preregistration: `0`\n\n');
for caseRecord = result.records
    fprintf(fid, '## %s / t=%d\n\n', ...
        caseRecord.presetName, caseRecord.currentTime);
    writeRouteTable(fid, 'Historical exact V71/V72 route', ...
        caseRecord.historical);
    fprintf(fid, '\n- Expected historical formation safety: `%s`\n', ...
        mat2str(caseRecord.expectedHistoricalSafe));
    fprintf(fid, '- Observed historical formation safety: `%s`\n', ...
        mat2str(caseRecord.observedHistoricalSafe));
    fprintf(fid, '- Retrospective direction match: `%d`\n\n', ...
        caseRecord.retrospectiveDirectionMatch);
    writeRouteTable(fid, 'Prospective exact V73 route', ...
        caseRecord.aligned);
    fprintf(fid, '\n- Prospective route tracking label available: `0`\n\n');
end
fprintf(fid, '## Summary\n\n');
fprintf(fid, '- All retrospective directions match: `%d`\n', ...
    result.allRetrospectiveDirectionsMatch);
fprintf(fid, '- All historical/aligned slots covered: `%d / %d`\n', ...
    result.allHistoricalSlotsCovered, result.allAlignedSlotsCovered);
fprintf(fid, '- Route executed / tracking read: `0 / 0`\n');
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeRouteTable(fid, title, route)
fprintf(fid, '### %s\n\n', title);
fprintf(fid, ['| Formation | Receiver | Incumbent | Candidate | Labels | ', ...
    'Conditional RIE | Reliability | Expected RIE | Safe |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for slot = route.slotRecords
    fprintf(fid, '| %d | %d | %d | %d | %d | %.6f | %.3f | %.6f | %d |\n', ...
        slot.formationId, slot.receiverIdx, ...
        slot.incumbentSenderIdx, slot.candidateSenderIdx, ...
        slot.eligibleLabelCount, slot.conditionalEnergy, ...
        slot.linkReliability, slot.reliabilityWeightedEnergy, ...
        slot.safe);
end
fprintf(fid, ['\n| Formation | Covered slots | Maximum conditional RIE | ', ...
    'Maximum expected RIE | Safe |\n']);
fprintf(fid, '|--:|--:|--:|--:|:--:|\n');
for formation = route.formationRecords
    fprintf(fid, '| %d | %d/%d | %.6f | %.6f | %d |\n', ...
        formation.formationId, formation.coveredSlotCount, ...
        formation.slotCount, formation.maximumConditionalEnergy, ...
        formation.maximumReliabilityWeightedEnergy, formation.safe);
end
end

function text = formatFormationRisk(records)
parts = cell(1, numel(records));
for idx = 1:numel(records)
    parts{idx} = sprintf('f%d:%.3f/%d', ...
        records(idx).formationId, ...
        records(idx).maximumConditionalEnergy, records(idx).safe);
end
text = strjoin(parts, ',');
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'expectedFormationIds', zeros(1, 0), ...
    'expectedHistoricalSafe', false(1, 0), ...
    'observedHistoricalSafe', false(1, 0), ...
    'retrospectiveDirectionMatch', false, ...
    'historical', struct(), ...
    'aligned', struct(), ...
    'historicalAllSlotsCovered', false, ...
    'alignedAllSlotsCovered', false);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
