function [reportPath, screen] = ...
    runFormationProjectedJointH3OpenedReturnScreen( ...
        presetName, seed, currentTime, options)
% RUNFORMATIONPROJECTEDJOINTH3OPENEDRETURNSCREEN Exact joint-action probe.

if nargin < 4 || isempty(options)
    options = struct();
end
if isfield(options, 'interventionBankType') && ...
        ~strcmpi(strrep(options.interventionBankType, '_', '-'), ...
            'formation-projected-joint')
    error('Formation joint wrapper bank type cannot be overridden.');
end
options.interventionBankType = 'formation-projected-joint';
[reportPath, screen] = ...
    runFormationModeH3OpenedReturnScreen( ...
        presetName, seed, currentTime, options);
end
