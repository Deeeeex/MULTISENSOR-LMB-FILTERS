function [bankStatePath, bankState] = ...
    prepareSpatialLabelSupportDebtRoutingV147Bank(presetName, options)
% PREPARESPATIALLABELSUPPORTDEBTROUTINGV147BANK Freeze current-only bank.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getSpatialLabelSupportDebtRoutingV147Protocol();
gitState = requireCleanSource();
caseInfo = resolveCase(protocol, presetName);
seed = getField(options, 'seed', protocol.pilotSeed);
if seed ~= protocol.pilotSeed
    error('SpatialDebtV147:UnsupportedSeed', ...
        'The first V147 bank is frozen to the registered pilot seed.');
end
anchorTime = resolveSetTrustSequenceV134PilotAnchor( ...
    caseInfo, protocol);
statePath = getField(options, 'v134PilotStatePath', '');
if isempty(statePath)
    statePath = defaultV134PilotStatePath( ...
        presetName, seed, anchorTime);
end
loaded = load(statePath, 'pilotState');
state = validateV134State( ...
    loaded, presetName, seed, anchorTime, caseInfo);

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
inputs = isolateRuntimeInputs(inputs);
context = buildSpatialLabelSupportDebtRoutingV147ObservableContext( ...
    inputs, state, protocol);
[registeredAdjacency, registeredDetails] = ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, state.referenceCarrierMode, protocol.routeWeights);
if ~isequal(logical(registeredAdjacency), ...
        logical(state.referenceAdjacency)) || ...
        max(abs(registeredDetails.fusionWeightMatrix(:) - ...
            state.referenceFusionWeights(:))) > 1e-12
    error('SpatialDebtV147:ReferenceCarrierDrift', ...
        'The current V147 reference does not match the frozen V134 state.');
end
timerId = tic;
bank = buildSpatialLabelSupportDebtRoutingV147ActionBank( ...
    context, state.referenceAdjacency, ...
    state.referenceFusionWeights, struct());
constructionSeconds = toc(timerId);

bankState = struct( ...
    'contractVersion', ...
        'v147-spatial-label-support-debt-routing-bank-state-v1', ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'anchorTime', anchorTime, ...
    'horizonSteps', caseInfo.horizonSteps, ...
    'recoveryTailSteps', caseInfo.recoveryTailSteps, ...
    'referenceCarrierMode', state.referenceCarrierMode, ...
    'groupIds', state.groupIds, ...
    'bank', bank, ...
    'v134PilotStatePath', statePath, ...
    'v134GenerationGitCommit', state.generationGitCommit, ...
    'generationGitCommit', gitState.commit, ...
    'constructionSeconds', constructionSeconds, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false);
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    protocol.outputRoot, 'pilot', strrep(presetName, '-', '_'), ...
    sprintf('seed%d_t%d', seed, anchorTime)));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
bankStatePath = fullfile(outputDirectory, 'BANK_STATE_V147.mat');
atomicSave(bankStatePath, 'bankState', bankState);
writeReport(fullfile(outputDirectory, 'BANK_STATE_V147.md'), bankState);
fprintf('Prepared V147 %s bank in %.2fs: %s\n', ...
    caseInfo.scaleName, constructionSeconds, bankStatePath);
end

function writeReport(path, state)
fid = fopen(path, 'w');
if fid < 0
    error('SpatialDebtV147:WriteFailed', ...
        'Could not create the V147 bank report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V147 spatial label-support debt routing bank\n\n');
fprintf(fid, '- Scale / seed / anchor: `%s / %d / %d`\n', ...
    state.scaleName, state.seed, state.anchorTime);
fprintf(fid, '- Reference carrier: `%s`\n', ...
    state.referenceCarrierMode);
fprintf(fid, '- Dominant / residual safe row candidates: `%d / %d`\n', ...
    numel(state.bank.dominantCandidates), ...
    numel(state.bank.residualCandidates));
fprintf(fid, ['- Dominant screened / positive-net / safe: ', ...
    '`%d / %d / %d`\n'], ...
    state.bank.candidateScreen.dominant.evaluatedCount, ...
    state.bank.candidateScreen.dominant.positiveNetGainCount, ...
    state.bank.candidateScreen.dominant.safeCount);
fprintf(fid, ['- Residual screened / positive-net / safe: ', ...
    '`%d / %d / %d`\n'], ...
    state.bank.candidateScreen.residual.evaluatedCount, ...
    state.bank.candidateScreen.residual.positiveNetGainCount, ...
    state.bank.candidateScreen.residual.safeCount);
fprintf(fid, '- Bank construction: `%.2f s`\n\n', ...
    state.constructionSeconds);
fprintf(fid, ['| Index | Action | Selected formations | Objective | ', ...
    'Initial bytes | Strong | Eligible |\n']);
fprintf(fid, '|--:|:--|:--|--:|--:|:--:|:--:|\n');
for action = state.bank.actions
    fprintf(fid, '| %d | %s | `%s` | %.6g | %+.3f%% | %d | %d |\n', ...
        action.index, action.name, ...
        mat2str(action.selectedFormationIds), action.objective, ...
        100 * action.initialByteDeltaFraction, ...
        action.instantStrongConnected, action.gateEligible);
end
fprintf(fid, ['\nThis artifact freezes a current-only, truth-free action ', ...
    'bank. It contains no tracking outcome and authorizes no ', ...
    'communication-method, validation or generalization claim.\n']);
end

function state = validateV134State( ...
        loaded, presetName, seed, anchorTime, caseInfo)
if ~isfield(loaded, 'pilotState') || ...
        ~isstruct(loaded.pilotState) || ...
        ~strcmp(loaded.pilotState.contractVersion, ...
            'v134-binary-admission-pilot-state-v4') || ...
        ~strcmp(loaded.pilotState.presetName, presetName) || ...
        loaded.pilotState.seed ~= seed || ...
        loaded.pilotState.anchorTime ~= anchorTime || ...
        loaded.pilotState.horizonSteps ~= caseInfo.horizonSteps
    error('SpatialDebtV147:InvalidV134State', ...
        'The frozen V134 state is malformed or mismatched.');
end
state = loaded.pilotState;
end

function path = defaultV134PilotStatePath(presetName, seed, anchorTime)
root = getenv('V134_PILOT_SOURCE_ROOT');
if isempty(root)
    error('SpatialDebtV147:MissingV134SourceRoot', ...
        'Set V134_PILOT_SOURCE_ROOT or pass v134PilotStatePath.');
end
path = fullfile(root, strrep(presetName, '-', '_'), ...
    sprintf('seed%d_t%d', seed, anchorTime), 'PILOT_STATE_V134.mat');
end

function inputs = isolateRuntimeInputs(inputs)
present = intersect( ...
    {'groundTruth', 'groundTruthRfs', 'targetTrajectories'}, ...
    fieldnames(inputs), 'stable');
if ~isempty(present)
    inputs = rmfield(inputs, present);
end
if isfield(inputs.model, 'explicitTargetTrajectories')
    inputs.model = rmfield(inputs.model, 'explicitTargetTrajectories');
end
if isfield(inputs.model, 'dynamicTopologyScenario')
    present = intersect({'targetTrajectories', 'target'}, ...
        fieldnames(inputs.model.dynamicTopologyScenario), 'stable');
    if ~isempty(present)
        inputs.model.dynamicTopologyScenario = rmfield( ...
            inputs.model.dynamicTopologyScenario, present);
    end
end
end

function gitState = requireCleanSource()
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('SpatialDebtV147:DirtySource', ...
        'Official V147 bank construction requires clean source.');
end
end

function caseInfo = resolveCase(protocol, presetName)
caseIdx = find(strcmp({protocol.scaleCases.presetName}, presetName), 1);
if isempty(caseIdx)
    error('SpatialDebtV147:InvalidPreset', ...
        'The preset is outside the V147 scale contract.');
end
caseInfo = protocol.scaleCases(caseIdx);
end

function atomicSave(path, variableName, value)
parent = fileparts(path);
if exist(parent, 'dir') ~= 7
    mkdir(parent);
end
temporary = [path, '.tmp'];
payload = struct();
payload.(variableName) = value;
save('-mat7-binary', temporary, '-struct', 'payload');
if exist(path, 'file') == 2
    delete(path);
end
[ok, message] = movefile(temporary, path, 'f');
if ~ok
    error('SpatialDebtV147:AtomicSaveFailed', '%s', message);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
