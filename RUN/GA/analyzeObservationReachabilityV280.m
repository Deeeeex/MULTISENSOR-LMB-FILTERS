function [reportPath,result] = analyzeObservationReachabilityV280()
% ANALYZEOBSERVATIONREACHABILITYV280 Geometry/packet opportunity, not tracking.
% Reuse the opened seed and metric files. Truth is used only by this offline
% observer; routing sees current geometry and its own past adjacency only.
% Perfect detection, lossless label retention and unlimited memory are assumed.
v279Path=fullfile('RUN','GA','dynamic_topology','evidence', ...
    'tracking_aligned_v279','set_error_budget_seed1301','SET_ERROR_BUDGET_V279.mat');
loaded=load(v279Path,'result'); budget=loaded.result;
result=struct('analysis','observation-reachability-v280-v1', ...
    'sourceBudgetPath',v279Path,'sourcePaths',{budget.sourcePaths}, ...
    'filterRerun',false,'postHoc',true,'idealRetention',true, ...
    'geometricDetectionOpportunityOnly',true,'horizons',[0,3,8,16]);
keys={'referenceFixedTree','referenceFullCausal','candidate'};
names={'Fixed tree','Full causal repair','Sparse causal repair'};
for sceneIdx=1:numel(budget.scenes)
    b=budget.scenes{sceneIdx}; saved=load(budget.sourcePaths{sceneIdx},'result');
    source=saved.result; inputs=generateDynamicTopologyScenarioInputs(b.preset,b.seed);
    cfg=inputs.config; n=cfg.numberOfSensors; q=cfg.numberOfTargets; T=cfg.simulationLength;
    identity=buildDynamicTopologyPhysicalIdentityRegistry(cfg);
    registration=buildInitialFormationBraidRouteV241Registration(inputs);
    visible=false(n,q,T); alive=false(q,T); pd=zeros(n,q,T);
    for t=1:T
        for target=1:q
            x=inputs.targetTrajectories{target}(:,t);
            if any(~isfinite(x)),continue;end
            alive(target,t)=true;
            for i=1:n
                [pd(i,target,t),~,quality]=evaluateSensorQuality(inputs.model,i,x,t);
                visible(i,target,t)=quality.inFov && pd(i,target,t)>0;
            end
        end
    end
    assert(isequal(sum(alive,1),reshape(b.truthCounts,1,[])));
    active3=repmat(reshape(alive,1,q,T),n,1,1);
    globalVisible=reshape(any(visible,1),q,T);
    expectedDetection=reshape(sum(pd,1),q,T);
    noDetectionProbability=reshape(prod(1-pd,1),q,T);
    scene=struct('preset',b.preset,'seed',b.seed,'sensorCount',n, ...
        'targetCount',q,'sourceCommit',source.generationGitCommit, ...
        'trueCountByTime',sum(alive,1), ...
        'globalBlackoutFraction',mean(~globalVisible(alive)), ...
        'meanExpectedDetectionsPerActiveTarget',mean(expectedDetection(alive)), ...
        'meanNoDetectionProbabilityPerActiveTarget',mean(noDetectionProbability(alive)), ...
        'meanLocalVisibleTargets',nnz(visible)/(n*T), ...
        'meanGlobalVisibleTargets',nnz(globalVisible)/T, ...
        'nominalDetectionProbability',cfg.detectionProbability, ...
        'nominalMeasurementNoiseStd',cfg.measurementNoiseStd, ...
        'sensorQuality',cfg.sensorQuality,'alive',alive,'visible',visible);
    fprintf('V280 %s: global blackout %.3f%%; local/global visible %.3f/%.3f; expected detections %.3f\n', ...
        b.preset,100*scene.globalBlackoutFraction,scene.meanLocalVisibleTargets, ...
        scene.meanGlobalVisibleTargets,scene.meanExpectedDetectionsPerActiveTarget);
    for armIdx=1:3
        history=false(n,n,0); times=[]; ages=inf(n,q); ageByTime=inf(n,q,T);
        messageCounts=zeros(1,T);
        for t=1:T
            context=struct('localPosteriorBySensor',{repmat({struct([])},1,n)}, ...
                'model',struct('dynamicTopologyScenario',struct('config',cfg, ...
                    'staticAdjacency',inputs.graphData.staticAdjacency)), ...
                'baseAdjacency',inputs.graphData.staticAdjacency, ...
                'physicalAdjacency',inputs.graphData.physicalAdjacency(:,:,t), ...
                'positions',inputs.graphData.positions(:,:,t),'currentTime',t, ...
                'commConfig',struct('pDropByEdge',inputs.commConfig.pDropByEdge(:,:,t)), ...
                'directedMessageBudget',2*n, ...
                'sensorPhysicalUids',identity.sensorPhysicalUids, ...
                'formationPhysicalUidsBySensor',identity.formationPhysicalUidsBySensor, ...
                'previousAdjacencyHistory',history,'previousAdjacencyHistoryTimes',times, ...
                'previousAdjacencyHistoryCount',size(history,3));
            switch armIdx
                case 1
                    adj=selectFrozenFormationBraidDropoutV241Policy(context,registration);
                case 2
                    adj=selectCausalMinimalEditFormationTreeV240Policy(context);
                case 3
                    adj=selectCausalMinimumFormationBackboneV242Policy(context);
            end
            messageCounts(t)=nnz(adj);
            delivered=logical(adj);
            if ~inputs.commConfig.forceDelivery
                delivered=delivered & (inputs.commConfig.linkUniforms(:,:,t)' >= ...
                    inputs.commConfig.pDropByEdge(:,:,t)');
            end
            % Synchronous round: all nodes update local information first,
            % then receive one-hop messages from the same pre-fusion snapshot.
            before=ages+1; before(visible(:,:,t))=0; before(:,~alive(:,t))=inf;
            for receiver=1:n
                senders=[receiver,find(delivered(receiver,:))];
                ages(receiver,:)=min(before(senders,:),[],1);
            end
            ageByTime(:,:,t)=ages;
            history=cat(3,history,logical(adj));times(end+1)=t; %#ok<AGROW>
            if size(history,3)>2,history=history(:,:,end-1:end);times=times(end-1:end);end
        end
        % Basic replay correspondence, not a new tracking validation gate.
        arm=source.(keys{armIdx});
        assert(isequal(messageCounts,reshape(arm.routeMessageCountByTime,1,[])));
        c=b.arms{armIdx}.inferredEstimateCount;
        d=arm.absoluteCardinalityErrorBySensorTime;
        truth=repmat(reshape(b.truthCounts,1,[]),n,1);
        countLo=c;countHi=c;ambiguous=~isfinite(c);
        countLo(ambiguous)=max(0,truth(ambiguous)-d(ambiguous));
        countHi(ambiguous)=truth(ambiguous)+d(ambiguous);
        rec=struct('name',names{armIdx},'ageBySensorTargetTime',ageByTime, ...
            'meanEstimateCountLower',mean(countLo(:)), ...
            'meanEstimateCountUpper',mean(countHi(:)), ...
            'neverReachableFraction',mean(~isfinite(ageByTime(active3))), ...
            'medianFiniteAge',median(ageByTime(active3 & isfinite(ageByTime))), ...
            'fractionWithinHorizon',zeros(size(result.horizons)), ...
            'meanReachableCountWithinHorizon',zeros(size(result.horizons)), ...
            'messageCounts',messageCounts);
        for h=1:numel(result.horizons)
            recent=active3 & ageByTime<=result.horizons(h);
            rec.fractionWithinHorizon(h)=nnz(recent)/nnz(active3);
            rec.meanReachableCountWithinHorizon(h)=nnz(recent)/(n*T);
        end
        allFresh=reshape(sum(active3 & ageByTime<=8,2),n,T)==truth;
        allFresh=allFresh & truth>0;
        rec.allTargetsWithinEightStepsFraction=mean(allFresh(:));
        rec.allFreshMeanEstimateCountLower=mean(countLo(allFresh));
        rec.allFreshMeanEstimateCountUpper=mean(countHi(allFresh));
        rec.allFreshMeanTrueCount=mean(truth(allFresh));
        scene.arms{armIdx}=rec;
        fprintf('  %s: geometric-path coverage age<=8 %.3f%%; never %.3f%%; output count %.3f--%.3f\n', ...
            rec.name,100*rec.fractionWithinHorizon(3),100*rec.neverReachableFraction, ...
            rec.meanEstimateCountLower,rec.meanEstimateCountUpper);
    end
    result.scenes{sceneIdx}=scene;
end
out=fullfile('RUN','GA','dynamic_topology','evidence','tracking_aligned_v280', ...
    'observation_reachability_seed1301');
if exist(out,'dir')~=7,mkdir(out);end
reportPath=fullfile(out,'OBSERVATION_REACHABILITY_V280.md');
save('-mat7-binary',fullfile(out,'OBSERVATION_REACHABILITY_V280.mat'),'result');
writeReport(reportPath,result);
end

function writeReport(path,result)
fid=fopen(path,'w');assert(fid>=0);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'# V280: geometric observation and causal packet reachability\n\n');
fprintf(fid,['Opened M24/X36 seed 1301 only. No filter is rerun, no scenario ', ...
    'parameter changes, and no new policy is selected.\n\n']);
fprintf(fid,'## Sensing opportunity, independent of routing\n\n');
fprintf(fid,'| Scale | Mean true count | Locally visible targets / sensor-time | Globally visible targets / time | Global blackout / active target-time | Expected detections / active target-time | Probability of no network detection |\n');
fprintf(fid,'|:--|--:|--:|--:|--:|--:|--:|\n');
for s=1:numel(result.scenes)
    a=result.scenes{s};
    fprintf(fid,'| N=%d | %.3f | %.3f | %.3f | %.3f%% | %.3f | %.3f%% |\n', ...
        a.sensorCount,mean(a.trueCountByTime),a.meanLocalVisibleTargets, ...
        a.meanGlobalVisibleTargets,100*a.globalBlackoutFraction, ...
        a.meanExpectedDetectionsPerActiveTarget,100*a.meanNoDetectionProbabilityPerActiveTarget);
end
fprintf(fid,['\nVisibility and detection probability use `evaluateSensorQuality`, ', ...
    'the same function as measurement generation. The nominal detection ', ...
    'probability/noise standard deviation are modified by range and off-axis ', ...
    'angle. No-network-detection probability is the product of per-sensor ', ...
    'miss probabilities, conditional on the deterministic target state; it ', ...
    'is not the realized detection count from the experiment.\n\n']);
fprintf(fid,'## Ideal geometric-evidence propagation over actual packet opportunities\n\n');
fprintf(fid,'| Scale | Arm | Age <=0 / <=3 / <=8 / <=16 steps | No prior reachable source | Mean possible target count within 8 steps | Inferred output count |\n');
fprintf(fid,'|:--|:--|:--|--:|--:|:--|\n');
for s=1:numel(result.scenes)
    a=result.scenes{s};
    for j=1:numel(a.arms)
        r=a.arms{j};v=100*r.fractionWithinHorizon;
        fprintf(fid,'| N=%d | %s | %.2f%% / %.2f%% / %.2f%% / %.2f%% | %.2f%% | %.3f | %.3f--%.3f |\n', ...
            a.sensorCount,r.name,v(1),v(2),v(3),v(4), ...
            100*r.neverReachableFraction,r.meanReachableCountWithinHorizon(3), ...
            r.meanEstimateCountLower,r.meanEstimateCountUpper);
    end
end
fprintf(fid,['\nA source is eligible when a true target has positive detection ', ...
    'probability at that sensor. We assume it is detected perfectly and ', ...
    'retained indefinitely. At each step, local evidence age increments, ', ...
    'currently eligible sources reset to age zero, and one synchronous ', ...
    'packet round propagates the youngest source age. Scheduled edges are ', ...
    'intersected with the same directed delivery uniforms. A new observation ', ...
    'can cross only one edge that step. Age zero includes directly visible ', ...
    'targets at self or a sender whose packet arrived.\n\n', ...
    'Coverage percentages use active sensor-target-time triples. Counts ', ...
    'average over sensor-time cells. Reachability is an optimistic ', ...
    'communication opportunity, not actual label availability, detector ', ...
    'recall, posterior quality, or a bound on tracking error. False labels, ', ...
    'association, negative evidence, pruning, density overlap and stale ', ...
    'motion uncertainty are not modeled.\n\n']);
fprintf(fid,'## Cells where every active target has an age <=8 geometric source path\n\n');
fprintf(fid,'| Scale | Arm | Sensor-time fraction | True count on these cells | Output-count interval on these cells |\n');
fprintf(fid,'|:--|:--|--:|--:|:--|\n');
for s=1:numel(result.scenes)
    a=result.scenes{s};
    for j=1:numel(a.arms)
        r=a.arms{j};
        fprintf(fid,'| N=%d | %s | %.3f%% | %.3f | %.3f--%.3f |\n',a.sensorCount,r.name, ...
            100*r.allTargetsWithinEightStepsFraction,r.allFreshMeanTrueCount, ...
            r.allFreshMeanEstimateCountLower,r.allFreshMeanEstimateCountUpper);
    end
end
fprintf(fid,['\nThe eight-step slice is descriptive, not a tuned selection gate. ', ...
    'The frozen horizons 0, 3, 8 and 16 are all reported. V279 count-sign ', ...
    'ambiguity is retained. A reachable true target is not necessarily ', ...
    'one of the emitted estimates, so these counts do not measure label recall.\n\n']);
fprintf(fid,'## Reproduction and decision boundary\n\n');
fprintf(fid,'`octave --no-gui --quiet --eval "addpath(genpath(pwd)); analyzeObservationReachabilityV280();"`\n\n');
fprintf(fid,['Route message counts are checked against the saved paired ', ...
    'metric artifacts. Self-check only. This offline diagnostic can expose ', ...
    'a gross sensing or temporal-path bottleneck, but cannot attribute ', ...
    'specific missing estimates to transport versus fusion. It does not ', ...
    'change the V278 stopping rule or authorize a new parameter sweep.\n\n']);
for s=1:numel(result.sourcePaths)
    fprintf(fid,'- `%s`\n',result.sourcePaths{s});
end
end
