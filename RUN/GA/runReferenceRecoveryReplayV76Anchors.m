function [reportPath, result] = ...
    runReferenceRecoveryReplayV76Anchors(options)
% RUNREFERENCERECOVERYREPLAYV76ANCHORS Source-only virtual KLA recovery.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReferenceRecoveryReplayV76Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReferenceRecoveryV76:DirtySource', ...
        'The V76 recovery replay requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, ...
        historicalAppliedTriples] = buildCandidateRoute( ...
            referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedAppliedTriples] = ...
        buildCandidateRoute( ...
            referenceAdjacency, referenceWeights, alignedTriples, ...
            state.groupIds, caseInfo.directSafeFormationIds);
    records(caseIdx) = makeCaseRecord( ...
        state, caseInfo, ...
        runReplay(state, referenceAdjacency, referenceWeights, ...
            historicalAdjacency, historicalWeights, ...
            historicalAppliedTriples, protocol), ...
        runReplay(state, referenceAdjacency, referenceWeights, ...
            alignedAdjacency, alignedWeights, ...
            alignedAppliedTriples, protocol));
    fprintf('V76 %s t=%d historical=%s aligned=%s\n', ...
        caseInfo.presetName, caseInfo.currentTime, ...
        formatReplay(records(caseIdx).historical), ...
        formatReplay(records(caseIdx).aligned));
end

result = struct();
result.contractVersion = ...
    'reference-recovery-replay-v76-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allHistoricalRecoverySafe = ...
    all(arrayfun(@(record) record.historical.recoverySafe, records));
result.allAlignedRecoverySafe = ...
    all(arrayfun(@(record) record.aligned.recoverySafe, records));
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.futureLinkPageUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'REFERENCE_RECOVERY_REPLAY_V76_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'REFERENCE_RECOVERY_REPLAY_V76_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V76 reference recovery replay: %s\n', reportPath);
end

function record = runReplay( ...
        state, referenceAdjacency, referenceWeights, ...
        candidateAdjacency, candidateWeights, appliedTriples, protocol)
referencePosteriors = state.context.localPosteriorBySensor;
candidatePosteriors = state.context.localPosteriorBySensor;
roundRecords = repmat(emptyRoundRecord(), ...
    1, protocol.totalFusionRounds);
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
for roundIdx = 1:protocol.totalFusionRounds
    [referencePosteriors, ~] = ...
        fuseLmbNetworkWithDirectedWeights( ...
            referencePosteriors, referenceAdjacency, ...
            referenceWeights, state.context.model, ...
            state.context.commConfig, state.currentTime, ...
            protocol.fusionConfig, fusionOptions);
    if roundIdx <= protocol.candidateRounds
        adjacency = candidateAdjacency;
        weights = candidateWeights;
    else
        adjacency = referenceAdjacency;
        weights = referenceWeights;
    end
    [candidatePosteriors, ~] = ...
        fuseLmbNetworkWithDirectedWeights( ...
            candidatePosteriors, adjacency, weights, ...
            state.context.model, state.context.commConfig, ...
            state.currentTime, protocol.fusionConfig, fusionOptions);
    roundRecords(roundIdx) = scoreRound( ...
        referencePosteriors, candidatePosteriors, ...
        state.groupIds, state.context.model, ...
        protocol.disagreementTailFraction);
    roundRecords(roundIdx).roundIndex = roundIdx;
end
meanGap = [roundRecords.meanArmGap];
tailGap = [roundRecords.tailArmGap];
meanMonotone = all(diff(meanGap) <= 1e-12);
tailMonotone = all(diff(tailGap) <= 1e-12);
record = struct();
record.appliedSlotTriples = appliedTriples;
record.rounds = roundRecords;
record.meanArmGapByRound = meanGap;
record.tailArmGapByRound = tailGap;
record.meanGapMonotoneNonincreasing = meanMonotone;
record.tailGapMonotoneNonincreasing = tailMonotone;
record.terminalMeanContractionFraction = contraction( ...
    meanGap(1), meanGap(end));
record.terminalTailContractionFraction = contraction( ...
    tailGap(1), tailGap(end));
record.recoverySafe = ...
    (~protocol.requireMonotoneMeanArmGapContraction || meanMonotone) && ...
    (~protocol.requireMonotoneTailArmGapContraction || tailMonotone);
record.expectedDeliveryWeighting = ...
    protocol.expectedDeliveryWeighting;
record.noPredictionOrMeasurement = true;
record.truthUsed = false;
record.futureMeasurementUsed = false;
record.futureLinkPageUsed = false;
end

function round = scoreRound( ...
        referencePosteriors, candidatePosteriors, ...
        groupIds, model, tailFraction)
nodeCount = numel(referencePosteriors);
referenceSummaries = cell(1, nodeCount);
candidateSummaries = cell(1, nodeCount);
nodeGap = zeros(1, nodeCount);
for nodeIdx = 1:nodeCount
    referenceSummaries{nodeIdx} = ...
        summarizeLmbPosteriorForDisagreement( ...
            referencePosteriors{nodeIdx}, model);
    candidateSummaries{nodeIdx} = ...
        summarizeLmbPosteriorForDisagreement( ...
            candidatePosteriors{nodeIdx}, model);
    pair = computeLmbPosteriorSummaryDisagreement( ...
        referenceSummaries{nodeIdx}, candidateSummaries{nodeIdx});
    nodeGap(nodeIdx) = pair.combined;
end
referencePairs = networkPairValues(referenceSummaries);
candidatePairs = networkPairValues(candidateSummaries);
groups = unique(groupIds, 'stable');
formationMeanGap = zeros(1, numel(groups));
formationTailGap = zeros(1, numel(groups));
for groupIdx = 1:numel(groups)
    selected = nodeGap(groupIds == groups(groupIdx));
    formationMeanGap(groupIdx) = mean(selected);
    formationTailGap(groupIdx) = upperTail(selected, tailFraction);
end
round = emptyRoundRecord();
round.meanArmGap = mean(nodeGap);
round.tailArmGap = upperTail(nodeGap, tailFraction);
round.maximumNodeArmGap = max(nodeGap);
round.formationIds = groups;
round.formationMeanArmGap = formationMeanGap;
round.formationTailArmGap = formationTailGap;
round.referenceMeanNetworkDisagreement = mean(referencePairs);
round.referenceTailNetworkDisagreement = ...
    upperTail(referencePairs, tailFraction);
round.candidateMeanNetworkDisagreement = mean(candidatePairs);
round.candidateTailNetworkDisagreement = ...
    upperTail(candidatePairs, tailFraction);
round.meanNetworkExcess = ...
    round.candidateMeanNetworkDisagreement - ...
        round.referenceMeanNetworkDisagreement;
round.tailNetworkExcess = ...
    round.candidateTailNetworkDisagreement - ...
        round.referenceTailNetworkDisagreement;
end

function values = networkPairValues(summaries)
nodeCount = numel(summaries);
values = zeros(1, nodeCount * (nodeCount - 1) / 2);
cursor = 0;
for leftIdx = 1:nodeCount-1
    for rightIdx = leftIdx+1:nodeCount
        cursor = cursor + 1;
        pair = computeLmbPosteriorSummaryDisagreement( ...
            summaries{leftIdx}, summaries{rightIdx});
        values(cursor) = pair.combined;
    end
end
end

function value = upperTail(values, fraction)
values = sort(reshape(values, 1, []), 'descend');
count = max(1, ceil(fraction * numel(values)));
value = mean(values(1:count));
end

function value = contraction(initial, terminal)
if initial <= eps
    value = double(terminal <= eps);
else
    value = (initial - terminal) / initial;
end
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('ReferenceRecoveryV76:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('ReferenceRecoveryV76:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        nnz(adjacency) ~= nnz(referenceAdjacency)
    error('ReferenceRecoveryV76:BudgetDrift', ...
        'Candidate replacement changed row sums or message count.');
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function record = makeCaseRecord( ...
        state, caseInfo, historical, aligned)
record = emptyCaseRecord();
record.presetName = state.presetName;
record.seed = state.seed;
record.currentTime = state.currentTime;
record.directSafeFormationIds = ...
    reshape(caseInfo.directSafeFormationIds, 1, []);
record.historical = historical;
record.aligned = aligned;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReferenceRecoveryV76:WriteFailed', ...
        'Could not create the V76 result report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V76 reference-recovery KLA replay\n\n');
fprintf(fid, '- Virtual fusion rounds: `%d`\n', ...
    result.protocol.totalFusionRounds);
fprintf(fid, '- Candidate / reference-recovery rounds: `%d / %d`\n', ...
    result.protocol.candidateRounds, ...
    result.protocol.referenceRecoveryRounds);
fprintf(fid, '- Prediction / new measurement / future link page: `0 / 0 / 0`\n');
fprintf(fid, '- Deterministic current-reliability weighting: `1`\n\n');
for caseRecord = result.records
    fprintf(fid, '## %s / t=%d\n\n', ...
        caseRecord.presetName, caseRecord.currentTime);
    fprintf(fid, '- Direct-safe formations replayed: `%s`\n\n', ...
        mat2str(caseRecord.directSafeFormationIds));
    writeReplayTable(fid, 'Historical exact V71/V72 route', ...
        caseRecord.historical);
    writeReplayTable(fid, 'Prospective exact V73 route', ...
        caseRecord.aligned);
end
fprintf(fid, '## Summary\n\n');
fprintf(fid, '- All historical routes recovery-safe: `%d`\n', ...
    result.allHistoricalRecoverySafe);
fprintf(fid, '- All aligned routes recovery-safe: `%d`\n', ...
    result.allAlignedRecoverySafe);
fprintf(fid, '- Route executed / tracking outcome read: `0 / 0`\n');
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeReplayTable(fid, title, replay)
fprintf(fid, '### %s\n\n', title);
fprintf(fid, '- Applied slot triples: `%s`\n\n', ...
    mat2str(replay.appliedSlotTriples));
fprintf(fid, ['| Round | Mean arm gap | Tail arm gap | Max node gap | ', ...
    'Reference network mean | Candidate network mean | Mean excess | ', ...
    'Tail excess |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for round = replay.rounds
    fprintf(fid, ['| %d | %.6f | %.6f | %.6f | %.6f | %.6f | ', ...
        '%+.6f | %+.6f |\n'], ...
        round.roundIndex, round.meanArmGap, round.tailArmGap, ...
        round.maximumNodeArmGap, ...
        round.referenceMeanNetworkDisagreement, ...
        round.candidateMeanNetworkDisagreement, ...
        round.meanNetworkExcess, round.tailNetworkExcess);
end
fprintf(fid, ['\n- Mean/tail gap monotone: `%d / %d`\n', ...
    '- Terminal mean/tail contraction: `%+.3f%% / %+.3f%%`\n', ...
    '- Recovery-safe: `%d`\n\n'], ...
    replay.meanGapMonotoneNonincreasing, ...
    replay.tailGapMonotoneNonincreasing, ...
    100 * replay.terminalMeanContractionFraction, ...
    100 * replay.terminalTailContractionFraction, ...
    replay.recoverySafe);
end

function text = formatReplay(replay)
text = sprintf('gap=%s/%s safe=%d', ...
    mat2str(replay.meanArmGapByRound, 4), ...
    mat2str(replay.tailArmGapByRound, 4), replay.recoverySafe);
end

function record = emptyRoundRecord()
record = struct( ...
    'roundIndex', NaN, ...
    'meanArmGap', NaN, ...
    'tailArmGap', NaN, ...
    'maximumNodeArmGap', NaN, ...
    'formationIds', zeros(1, 0), ...
    'formationMeanArmGap', zeros(1, 0), ...
    'formationTailArmGap', zeros(1, 0), ...
    'referenceMeanNetworkDisagreement', NaN, ...
    'referenceTailNetworkDisagreement', NaN, ...
    'candidateMeanNetworkDisagreement', NaN, ...
    'candidateTailNetworkDisagreement', NaN, ...
    'meanNetworkExcess', NaN, ...
    'tailNetworkExcess', NaN);
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'directSafeFormationIds', zeros(1, 0), ...
    'historical', struct(), ...
    'aligned', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
