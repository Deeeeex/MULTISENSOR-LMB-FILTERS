function [reportPath, screen] = ...
    runFormationStaggeredRecoveryM24V36Screen(options)
% RUNFORMATIONSTAGGEREDRECOVERYM24V36SCREEN Frozen three-state paired run.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = ...
    getFormationStaggeredRecoveryM24ReplicationProtocol();
preflight = assertPreflightAuthorized(protocol);
writeReportEnabled = logical(getField( ...
    options, 'writeReport', true));
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
outputDirectory = getField(options, ...
    'outputDirectory', fullfile(protocol.outputRoot, 'screen'));

gitState = resolveResearchGitState();
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v36 replication screen requires a clean ', ...
        'tracked and MATLAB/Octave source state.']);
end

stateCount = numel(protocol.anchorTimes);
stateScreens = cell(1, stateCount);
stateSummaries = repmat(emptyStateSummary(), 1, stateCount);
for stateIdx = 1:stateCount
    anchorTime = protocol.anchorTimes(stateIdx);
    initialActionIndex = ...
        protocol.expectedInitialActionIndices(stateIdx);
    fprintf('V36 state %d/%d: t=%d\n', ...
        stateIdx, stateCount, anchorTime);
    executorOptions = struct( ...
        'horizonSteps', protocol.horizonSteps, ...
        'interventionDurationSteps', 1, ...
        'cacheRoot', protocol.cacheRoot, ...
        'interventionBankType', ...
            'formation-staggered-recovery', ...
        'actionIndices', [1, initialActionIndex], ...
        'writeReport', false, ...
        'allowDirtySource', allowDirtySource);
    [~, stateScreen] = ...
        runFormationModeOpenedReturnScreen( ...
            protocol.presetName, protocol.seed, ...
            anchorTime, executorOptions);
    assertStateScreenContract( ...
        stateScreen, preflight.states(stateIdx), ...
        stateIdx, protocol, gitState);
    stateScreens{stateIdx} = stateScreen;
    stateSummaries(stateIdx) = buildStateSummary( ...
        stateScreen, stateIdx, protocol);
end

gate = evaluateFormationStaggeredRecoveryM24V36Gate( ...
    stateSummaries, protocol);
cleanSource = ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles);
formalGatePassed = cleanSource && gate.passed;

screen = struct();
screen.contractVersion = ...
    'formation-staggered-recovery-m24-v36-screen-v1';
screen.generatedAt = datestr(now, 31);
screen.generationGitCommit = gitState.commit;
screen.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
screen.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
screen.protocol = protocol;
screen.sourcePreflightPath = preflight.matPath;
screen.sourcePreflightSha256 = ...
    computeFileSha256(preflight.matPath);
screen.sourcePreflightGenerationCommit = ...
    preflight.generationGitCommit;
screen.presetName = protocol.presetName;
screen.seed = protocol.seed;
screen.anchorTimes = protocol.anchorTimes;
screen.stateScreens = stateScreens;
screen.stateSummaries = stateSummaries;
screen.replicationGate = gate;
screen.formalReplicationGatePassed = formalGatePassed;
screen.outcomeRankingUsesTruth = true;
screen.openedDevelopmentEvidenceOnly = true;
screen.x36SourceOnlyProtocolAuthorized = formalGatePassed;
screen.gnnTrainingAuthorized = false;
screen.x36OutcomeOpeningAuthorized = false;
screen.x48OutcomeOpeningAuthorized = false;
screen.validationClaimAllowed = false;
screen.evidenceBoundary = protocol.evidenceBoundary;

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    stem = ...
        'FORMATION_STAGGERED_RECOVERY_M24_V36_SCREEN';
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    screen.reportPath = reportPath;
    screen.matPath = matPath;
    save('-mat7-binary', matPath, 'screen');
    writeReport(reportPath, screen);
    fprintf('V36 M24 replication screen: %s\n', reportPath);
end
end

function preflight = assertPreflightAuthorized(protocol)
path = fullfile(protocol.outputRoot, 'preflight', ...
    protocol.replicationPreflightFile);
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), ...
            protocol.replicationPreflightSha256)
    error('V36Screen:PreflightRequired', ...
        'The frozen v36 source-only preflight is unavailable.');
end
loaded = load(path, 'preflight');
if ~isfield(loaded, 'preflight')
    error('V36Screen:PreflightRequired', ...
        'The frozen v36 preflight structure is unavailable.');
end
preflight = loaded.preflight;
if ~strcmp(preflight.contractVersion, ...
        'formation-staggered-recovery-m24-v36-preflight-v1') || ...
        ~strcmp(preflight.generationGitCommit, ...
            protocol.replicationPreflightGenerationCommit) || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        ~isequal(preflight.anchorTimes, protocol.anchorTimes) || ...
        ~all(preflight.trackingOutcomeAuthorizedMask) || ...
        preflight.authorizedStateCount ~= ...
            numel(protocol.anchorTimes) || ...
        preflight.trackingOutcomeScored || ...
        preflight.newPosteriorStateOpened || ...
        preflight.gnnTrainingAuthorized || ...
        preflight.x36Opened || preflight.x48Opened || ...
        preflight.validationClaimAllowed
    error('V36Screen:PreflightRequired', ...
        'The clean v36 preflight did not authorize all three states.');
end
for stateIdx = 1:numel(protocol.anchorTimes)
    state = preflight.states(stateIdx);
    if state.anchorTime ~= protocol.anchorTimes(stateIdx) || ...
            state.initialActionIndex ~= protocol. ...
                expectedInitialActionIndices(stateIdx) || ...
            ~strcmp(state.cacheSha256, ...
                protocol.expectedCacheSha256{stateIdx}) || ...
            ~state.runtimeReplayPassed || ...
            state.trackingOutcomeScored || state.truthUsed || ...
            state.futureOutcomeUsed
        error('V36Screen:PreflightRequired', ...
            'A frozen v36 state authorization drifted.');
    end
end
end

function assertStateScreenContract( ...
        stateScreen, sourceState, stateIdx, protocol, gitState)
anchorTime = protocol.anchorTimes(stateIdx);
expectedAction = ...
    protocol.expectedInitialActionIndices(stateIdx);
expectedSelected = protocol. ...
    expectedRuntimeSelectedFormationIdsByState{stateIdx};
expectedReleased = protocol. ...
    expectedRuntimeReleasedFormationIdsByState{stateIdx};
expectedFallback = protocol. ...
    expectedRuntimeReferenceFallbackCountByState{stateIdx};
expectedSequences = [ ...
    ones(1, protocol.horizonSteps); ...
    expectedAction, ones(1, protocol.horizonSteps - 1)];
referenceIdx = stateScreen.referenceSubsetIndex;
candidateIdx = setdiff( ...
    1:numel(stateScreen.records), referenceIdx);
if numel(candidateIdx) ~= 1
    error('V36Screen:StateContract', ...
        'Each v36 state must contain exactly two paired arms.');
end
reference = stateScreen.outcomes(referenceIdx);
candidate = stateScreen.outcomes(candidateIdx);
if ~strcmp(stateScreen.contractVersion, ...
        ['formation-staggered-recovery-h3-', ...
         'opened-return-screen-v1']) || ...
        ~strcmp(stateScreen.interventionBankType, ...
            'formation-staggered-recovery') || ...
        ~strcmp(stateScreen.generationGitCommit, gitState.commit) || ...
        stateScreen.currentTime ~= anchorTime || ...
        ~isequal(stateScreen.returnTimes, ...
            anchorTime + (0:protocol.horizonSteps - 1)) || ...
        stateScreen.horizonSteps ~= protocol.horizonSteps || ...
        stateScreen.referenceSubsetIndex ~= 1 || ...
        stateScreen.bank.referenceActionIndex ~= 1 || ...
        stateScreen.bank.nodeCount ~= protocol.expectedNodeCount || ...
        stateScreen.bank.formationCount ~= ...
            protocol.expectedFormationCount || ...
        ~isequal(stateScreen.actionIndices, [1, expectedAction]) || ...
        ~isequal(stateScreen.actionSequenceIndices, ...
            expectedSequences) || ...
        ~isequal(stateScreen.bank. ...
            actionSuspendedFormationIds{expectedAction}, ...
            protocol. ...
                expectedInitialFormationIdsByState{stateIdx}) || ...
        any(~stateScreen.bank.actionPosteriorSafetyMask( ...
            stateScreen.actionIndices)) || ...
        ~strcmp(stateScreen.cacheSha256, ...
            protocol.expectedCacheSha256{stateIdx}) || ...
        ~strcmp(stateScreen.cachePath, sourceState.cachePath) || ...
        ~stateScreen.runtimeRecoveryPolicyEnabled || ...
        ~strcmp(stateScreen.runtimePolicyContractVersion, ...
            'formation-staggered-recovery-runtime-policy-v1') || ...
        stateScreen.runtimePolicyUsesTruth || ...
        stateScreen.featuresUseTruth || ...
        stateScreen.featuresUseFutureMeasurements || ...
        stateScreen.featuresUseFutureOutcome || ...
        ~stateScreen.targetsUseTruth || ...
        ~stateScreen.openedDevelopmentEvidenceOnly || ...
        stateScreen.validationClaimAllowed || ...
        any([reference.truthUseCount, candidate.truthUseCount] ~= 0) || ...
        any([reference.repairCount, candidate.repairCount] ~= 0) || ...
        any([reference.payloadEmergencyCount, ...
             candidate.payloadEmergencyCount] ~= 0) || ...
        any([reference.infeasibleCount, candidate.infeasibleCount] ~= 0) || ...
        ~reference.firstActionExact || ...
        ~reference.firstFusionWeightsExact || ...
        ~candidate.firstActionExact || ...
        ~candidate.firstFusionWeightsExact || ...
        ~candidate.laterActionsDynamicallyRecomputed || ...
        ~all(candidate.posteriorContentUsedByTime) || ...
        ~all(candidate.currentLinkReliabilityUsedByTime) || ...
        ~all(reference.selectedSensorB3Pass) || ...
        ~all(reference.selectedFormationB3Pass) || ...
        ~all(candidate.selectedSensorB3Pass) || ...
        ~all(candidate.selectedFormationB3Pass) || ...
        ~isequal(candidate.selectedAdjacency, ...
            sourceState.runtimeReplay.selectedAdjacency) || ...
        ~isequal(candidate.attemptedBytesByTime, ...
            sourceState.runtimeReplay.attemptedBytesByTime) || ...
        ~isequal(candidate. ...
            retentionDebtSelectedFormationIdsByTime, ...
            expectedSelected) || ...
        ~isequal(candidate. ...
            retentionDebtProjectionRemovalOrderByTime, ...
            expectedReleased) || ...
        ~isequal(candidate.recoveryFallbackCountByTime, ...
            expectedFallback) || ...
        ~hasExpectedTrace(candidate, stateIdx, protocol)
    error('V36Screen:StateContract', ...
        'The paired runtime contract drifted at t=%d.', anchorTime);
end
end

function value = hasExpectedTrace(candidate, stateIdx, protocol)
expectedSelected = protocol. ...
    expectedRuntimeSelectedFormationIdsByState{stateIdx};
expectedReleased = protocol. ...
    expectedRuntimeReleasedFormationIdsByState{stateIdx};
expectedStaggered = protocol. ...
    expectedRuntimeStaggeredReleaseMaskByState{stateIdx};
value = numel(candidate.staggeredRecoveryScheduleByTime) == ...
    protocol.horizonSteps;
if ~value
    return;
end
for timeIdx = 1:protocol.horizonSteps
    schedule = candidate. ...
        staggeredRecoveryScheduleByTime{timeIdx};
    value = value && isstruct(schedule) && ...
        isfield(schedule, 'contractVersion') && ...
        strcmp(schedule.contractVersion, ...
            ['formation-staggered-recovery-', ...
             'runtime-schedule-v1']) && ...
        schedule.currentTime == ...
            protocol.anchorTimes(stateIdx) + timeIdx - 1 && ...
        schedule.staggeredReleaseUsed == ...
            expectedStaggered(timeIdx) && ...
        isequal(schedule.selectedFormationIds, ...
            expectedSelected{timeIdx}) && ...
        isequal(schedule.releasedFormationIds, ...
            expectedReleased{timeIdx}) && ...
        ~schedule.truthUsed && ~schedule.futureOutcomeUsed;
end
end

function summary = buildStateSummary(stateScreen, stateIdx, protocol)
referenceIdx = stateScreen.referenceSubsetIndex;
candidateIdx = setdiff( ...
    1:numel(stateScreen.records), referenceIdx);
reference = stateScreen.outcomes(referenceIdx);
candidate = stateScreen.outcomes(candidateIdx);
record = stateScreen.records(candidateIdx);
traceAttested = hasExpectedTrace( ...
    candidate, stateIdx, protocol);
strictStrong = ...
    record.posteriorProxyAllowed && ...
    candidate.firstActionExact && ...
    candidate.firstFusionWeightsExact && ...
    candidate.laterActionsDynamicallyRecomputed && ...
    all(candidate.posteriorContentUsedByTime) && ...
    all(candidate.currentLinkReliabilityUsedByTime) && ...
    traceAttested && ...
    record.meanGainPercent >= protocol. ...
        meanTrackingGainThresholdPercent - 1e-12 && ...
    record.minimumFormationGainPercent >= protocol. ...
        minimumFormationGainThresholdPercent - 1e-12 && ...
    record.worstGainPercent >= protocol. ...
        worstSensorGainThresholdPercent - 1e-12 && ...
    record.consensusGainPercent >= protocol. ...
        windowConsensusGainThresholdPercent - 1e-12 && ...
    record.terminalConsensusGainPercent >= protocol. ...
        terminalConsensusGainThresholdPercent - 1e-12 && ...
    record.attemptedByteSavingPercent >= protocol. ...
        minimumAttemptedByteSavingPercent - 1e-12 && ...
    record.selectedB3Passed;

summary = emptyStateSummary();
summary.anchorTime = protocol.anchorTimes(stateIdx);
summary.returnTimes = stateScreen.returnTimes;
summary.cacheSha256 = stateScreen.cacheSha256;
summary.referenceIndex = referenceIdx;
summary.candidateIndex = candidateIdx;
summary.traceAttested = traceAttested;
summary.strictStrong = strictStrong;
summary.meanGainPercent = record.meanGainPercent;
summary.worstSensorGainPercent = record.worstGainPercent;
summary.formationGainPercent = record.formationGainPercent;
summary.minimumFormationGainPercent = ...
    record.minimumFormationGainPercent;
summary.windowConsensusGainPercent = ...
    record.consensusGainPercent;
summary.terminalConsensusGainPercent = ...
    record.terminalConsensusGainPercent;
summary.attemptedByteSavingPercent = ...
    record.attemptedByteSavingPercent;
summary.referenceMeanCardinalityError = ...
    reference.meanCardinalityError;
summary.candidateMeanCardinalityError = ...
    candidate.meanCardinalityError;
summary.referenceTrackingByTime = mean( ...
    reference.eospaBySensorTime, 1);
summary.candidateTrackingByTime = mean( ...
    candidate.eospaBySensorTime, 1);
summary.trackingGainByTimePercent = relativeGain( ...
    summary.referenceTrackingByTime, ...
    summary.candidateTrackingByTime);
summary.referenceConsensusByTime = ...
    reference.consensusOspaByTime;
summary.candidateConsensusByTime = ...
    candidate.consensusOspaByTime;
summary.consensusGainByTimePercent = relativeGain( ...
    summary.referenceConsensusByTime, ...
    summary.candidateConsensusByTime);
summary.referenceAttemptedBytesByTime = ...
    reference.attemptedBytesByTime;
summary.candidateAttemptedBytesByTime = ...
    candidate.attemptedBytesByTime;
summary.attemptedByteSavingByTimePercent = relativeGain( ...
    summary.referenceAttemptedBytesByTime, ...
    summary.candidateAttemptedBytesByTime);
summary.runtimeSelectedFormationIdsByTime = ...
    candidate.retentionDebtSelectedFormationIdsByTime;
summary.runtimeReleasedFormationIdsByTime = ...
    candidate.retentionDebtProjectionRemovalOrderByTime;
end

function summary = emptyStateSummary()
summary = struct( ...
    'anchorTime', NaN, ...
    'returnTimes', [], ...
    'cacheSha256', '', ...
    'referenceIndex', NaN, ...
    'candidateIndex', NaN, ...
    'traceAttested', false, ...
    'strictStrong', false, ...
    'meanGainPercent', NaN, ...
    'worstSensorGainPercent', NaN, ...
    'formationGainPercent', [], ...
    'minimumFormationGainPercent', NaN, ...
    'windowConsensusGainPercent', NaN, ...
    'terminalConsensusGainPercent', NaN, ...
    'attemptedByteSavingPercent', NaN, ...
    'referenceMeanCardinalityError', NaN, ...
    'candidateMeanCardinalityError', NaN, ...
    'referenceTrackingByTime', [], ...
    'candidateTrackingByTime', [], ...
    'trackingGainByTimePercent', [], ...
    'referenceConsensusByTime', [], ...
    'candidateConsensusByTime', [], ...
    'consensusGainByTimePercent', [], ...
    'referenceAttemptedBytesByTime', [], ...
    'candidateAttemptedBytesByTime', [], ...
    'attemptedByteSavingByTimePercent', [], ...
    'runtimeSelectedFormationIdsByTime', {{}}, ...
    'runtimeReleasedFormationIdsByTime', {{}});
end

function writeReport(path, screen)
fid = fopen(path, 'w');
if fid < 0
    error('V36Screen:WriteFailed', ...
        'Could not open the v36 replication report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
gate = screen.replicationGate;
fprintf(fid, '# V36 multi-state M24 paired screen\n\n');
fprintf(fid, '- Contract / generation commit: `%s / %s`\n', ...
    screen.contractVersion, screen.generationGitCommit);
fprintf(fid, '- Source preflight commit / SHA-256: `%s / %s`\n', ...
    screen.sourcePreflightGenerationCommit, ...
    screen.sourcePreflightSha256);
fprintf(fid, '- Preset / seed / anchors: `%s / %d / %s`\n', ...
    screen.presetName, screen.seed, mat2str(screen.anchorTimes));
fprintf(fid, '- Formal replication gate: `%d`\n\n', ...
    screen.formalReplicationGatePassed);

fprintf(fid, '## Per-state results\n\n');
fprintf(fid, [ ...
    '| Anchor | Runtime suspension | Mean tracking | Worst sensor ', ...
    '| Formation gains | Window consensus | Terminal consensus ', ...
    '| Byte saving | Mean card. error | Strong |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|:--|--:|--:|--:|:--|:--:|\n');
for summary = screen.stateSummaries
    fprintf(fid, [ ...
        '| %d | `%s` | %+.4f%% | %+.4f%% | `%s` | %+.4f%% ', ...
        '| %+.4f%% | %+.4f%% | %.6f -> %.6f | %d |\n'], ...
        summary.anchorTime, ...
        formatTrace(summary.runtimeSelectedFormationIdsByTime), ...
        summary.meanGainPercent, summary.worstSensorGainPercent, ...
        mat2str(summary.formationGainPercent, 5), ...
        summary.windowConsensusGainPercent, ...
        summary.terminalConsensusGainPercent, ...
        summary.attemptedByteSavingPercent, ...
        summary.referenceMeanCardinalityError, ...
        summary.candidateMeanCardinalityError, ...
        summary.strictStrong);
end

fprintf(fid, '\n## Aggregate gate\n\n');
fprintf(fid, '- Strong states: `%d / %d` (required `%d`)\n', ...
    gate.strongStateCount, numel(screen.stateSummaries), ...
    screen.protocol.minimumStrongReplicationStateCount);
fprintf(fid, '- Median mean gain: `%+.4f%%` (required `>= %.2f%%`)\n', ...
    gate.medianMeanGainPercent, ...
    screen.protocol.minimumMedianMeanGainPercent);
fprintf(fid, '- Minimum state mean gain: `%+.4f%%` (required `>= %.2f%%`)\n', ...
    gate.minimumStateMeanGainPercent, ...
    screen.protocol.minimumStateMeanGainPercent);
fprintf(fid, '- Positive terminal states: `%d` (required `%d`)\n\n', ...
    gate.positiveTerminalConsensusStateCount, ...
    screen.protocol.minimumPositiveTerminalStateCount);

for summary = screen.stateSummaries
    fprintf(fid, '## Temporal result: t=%d\n\n', ...
        summary.anchorTime);
    fprintf(fid, [ ...
        '| Time | Reference tracking | Candidate tracking ', ...
        '| Tracking gain | Reference consensus | Candidate consensus ', ...
        '| Consensus gain | Byte saving | Selected suspension |\n']);
    fprintf(fid, ...
        '|--:|--:|--:|--:|--:|--:|--:|--:|:--|\n');
    for timeIdx = 1:numel(summary.returnTimes)
        fprintf(fid, [ ...
            '| %d | %.6f | %.6f | %+.3f%% | %.6f | %.6f ', ...
            '| %+.3f%% | %+.3f%% | `%s` |\n'], ...
            summary.returnTimes(timeIdx), ...
            summary.referenceTrackingByTime(timeIdx), ...
            summary.candidateTrackingByTime(timeIdx), ...
            summary.trackingGainByTimePercent(timeIdx), ...
            summary.referenceConsensusByTime(timeIdx), ...
            summary.candidateConsensusByTime(timeIdx), ...
            summary.consensusGainByTimePercent(timeIdx), ...
            summary.attemptedByteSavingByTimePercent(timeIdx), ...
            mat2str(summary. ...
                runtimeSelectedFormationIdsByTime{timeIdx}));
    end
    fprintf(fid, '\n');
end

fprintf(fid, '## Decision\n\n');
if screen.formalReplicationGatePassed
    fprintf(fid, [ ...
        'The frozen multi-state development gate passes. An X36 ', ...
        'source-only protocol may now be designed; X36 outcomes, GNN ', ...
        'training, reserved seeds, X48, and validation remain sealed.\n\n']);
else
    fprintf(fid, [ ...
        'The frozen multi-state development gate does not pass. No ', ...
        'X36 outcome, GNN, reserved seed, X48, or validation is ', ...
        'authorized from this screen.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    screen.evidenceBoundary);
end

function value = formatTrace(trace)
parts = cell(1, numel(trace));
for idx = 1:numel(trace)
    parts{idx} = mat2str(trace{idx});
end
value = strjoin(parts, ' -> ');
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) ./ max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
