function [modelPath, result] = ...
    trainLabelSetMessagePassingPolicy(options)
% TRAINLABELSETMESSAGEPASSINGPOLICY Truth-target initialization only.
%
% The shared label/node/base-edge encoders are initialized by the frozen
% pairwise DeepSets task diagnostic. Two directed message-passing rounds
% are then added, and only their final linear readout is fitted to the same
% opened M24 current-task pairs. This creates an initialization for later
% paired closed-loop return optimization; it is not a deployable or
% selected policy.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.messagePassingModelTrainingAuthorized || ...
        ~protocol.offlineTaskInitializationAuthorized || ...
        ~protocol.labelSetRepresentationAccepted
    error('Label-set message-passing initialization is not authorized.');
end
gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error(['Official label-set message-passing initialization ', ...
        'requires clean source.']);
end
[datasets, blocks, shardRecords] = ...
    loadRegisteredShards(protocol);
source = loadActionEvidence(protocol);
[actions, pairs] = assembleActions( ...
    source, datasets, blocks, protocol);

base = fitBaseDeepSet( ...
    actions, pairs, protocol, ...
    protocol.representationInitializationSeed);
model = buildMessagePassingModel( ...
    base, datasets(1), blocks(1), protocol);
[model.outputWeight, readoutMetrics] = ...
    fitMessageReadout( ...
        model, source.rows, datasets, blocks, ...
        pairs, protocol);
model.outputBias = 0;

model.generatedAt = datestr(now, 31);
model.protocolId = protocol.id;
model.trainingGitCommit = gitState.commit;
model.trainingTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
model.trainingUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
model.trainingResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
model.shardRecords = shardRecords;
model.actionEvidencePath = ...
    protocol.actionEvidencePath;
model.actionEvidenceSha256 = ...
    protocol.actionEvidenceSha256;
model.initializationTarget = ...
    protocol.representationDiagnosticTarget;
model.finalTrainingObjective = ...
    protocol.finalTrainingObjective;
model.modelSelectionObjective = ...
    protocol.modelSelectionObjective;
model.readoutTrainingMetrics = readoutMetrics;
model.featuresUseTruth = false;
model.featuresUseFutureOutcome = false;
model.initializationTargetsUseTruth = true;
model.initializationTargetsUseFutureOutcome = false;
model.numericLabelIdentifiersUsedAsFeatures = false;
model.safeProjectorRequired = true;
model.closedLoopReturnEvaluated = false;
model.closedLoopOptimized = false;
model.policySelected = false;
model.developmentEvaluated = false;
model.heldoutM24Evaluated = false;
model.x36Evaluated = false;
model.deployable = false;
model.evidenceBoundary = [ ...
    'This artifact is a current-task supervised initialization on ', ...
    'already-opened M24 training states. Its inputs are truth-free, ', ...
    'but its initialization targets use current tracking truth. ', ...
    'The two-round scorer must remain behind the deterministic safe ', ...
    'residual-cycle projector. No paired closed-loop return has been ', ...
    'optimized or evaluated, so the artifact is not a selected policy ', ...
    'and supports no M24 or X36 performance claim.'];

modelPath = getField(options, 'modelPath', ...
    protocol.defaultMessagePassingModelPath);
reportPath = getField(options, 'reportPath', ...
    protocol.defaultMessagePassingTrainingReportPath);
outputDirectory = fileparts(modelPath);
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
model.modelPath = modelPath;
model.reportPath = reportPath;
save('-mat7-binary', modelPath, 'model');
result = struct();
result.modelPath = modelPath;
result.reportPath = reportPath;
result.trainingPairCount = numel(pairs);
result.trainingMetrics = readoutMetrics;
result.closedLoopReturnEvaluated = false;
result.policySelected = false;
result.developmentEvaluated = false;
result.heldoutM24Evaluated = false;
result.x36Evaluated = false;
result.deployable = false;
writeReport(reportPath, model, result);
fprintf('Label-set message-passing init: %s\nReport: %s\n', ...
    modelPath, reportPath);
end

function [datasets, blocks, records] = loadRegisteredShards(protocol)
datasets = repmat(struct(), ...
    1, numel(protocol.registeredShardSeeds));
blocks = repmat(struct(), 1, 0);
records = repmat(struct( ...
    'seed', 0, 'path', '', 'sha256', '', ...
    'generationCommit', ''), ...
    1, numel(protocol.registeredShardSeeds));
for seedIdx = 1:numel(protocol.registeredShardSeeds)
    path = protocol.registeredShardPaths{seedIdx};
    expectedSha256 = ...
        protocol.registeredShardSha256{seedIdx};
    if exist(path, 'file') ~= 2 || ...
            ~strcmp(computeFileSha256(path), expectedSha256)
        error('Label-set training shard hash mismatch: %s', path);
    end
    loaded = load(path, 'dataset');
    dataset = loaded.dataset;
    expectedSeed = ...
        protocol.registeredShardSeeds(seedIdx);
    if ~strcmp(dataset.protocolId, protocol.id) || ...
            ~strcmp(dataset.contractVersion, ...
                protocol.datasetContractVersion) || ...
            ~strcmp(dataset.generationGitCommit, ...
                protocol.shardGenerationCommit) || ...
            dataset.generationResearchWorktreeDirty || ...
            dataset.seed ~= expectedSeed || ...
            ~isequal(dataset.labelTimes, ...
                protocol.snapshotTimes) || ...
            ~strcmp(dataset.featureContractSha256, ...
                protocol. ...
                    registeredFeatureContractSha256) || ...
            dataset.featuresUseTruth || ...
            dataset.featuresUseFutureOutcome || ...
            ~dataset.diagnosticTargetsUseTruth || ...
            dataset.diagnosticTargetsUseFutureOutcome || ...
            dataset.numericLabelIdentifiersUsedAsFeatures || ...
            dataset.policyModelTrained || ...
            dataset.closedLoopReturnEvaluated || ...
            dataset.developmentLabelsOpened || ...
            dataset.heldoutM24Opened || dataset.x36Opened
        error('Label-set training shard envelope is invalid.');
    end
    datasets(seedIdx) = dataset;
    blocks = [blocks, dataset.blocks]; %#ok<AGROW>
    records(seedIdx) = struct( ...
        'seed', expectedSeed, 'path', path, ...
        'sha256', expectedSha256, ...
        'generationCommit', ...
            dataset.generationGitCommit);
end
end

function source = loadActionEvidence(protocol)
if exist(protocol.actionEvidencePath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256( ...
            protocol.actionEvidencePath), ...
            protocol.actionEvidenceSha256)
    error('Label-set training action evidence hash mismatch.');
end
loaded = load(protocol.actionEvidencePath, 'analysis');
source = loaded.analysis;
if source.generationResearchWorktreeDirty || ...
        ~isequal(source.trainingSeeds, ...
            protocol.trainingSeeds) || ...
        ~isequal(source.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        source.scoreTruthUsed || ~source.targetTruthUsed || ...
        numel(source.rows) ~= 2 * protocol.expectedPairCount
    error('Label-set training action evidence is invalid.');
end
end

function [actions, pairs] = ...
        assembleActions(source, datasets, blocks, protocol)
actions = repmat(emptyAction(), 1, numel(source.rows));
for actionIdx = 1:numel(source.rows)
    row = source.rows(actionIdx);
    blockMask = [blocks.seed] == row.seed & ...
        [blocks.currentTime] == row.currentTime;
    if nnz(blockMask) ~= 1
        error('Label-set initialization state is missing.');
    end
    block = blocks(find(blockMask, 1));
    edgeIdx = find(block.receiverIndices == ...
        row.receiverIdx & ...
        block.senderIndices == row.senderIdx);
    weightIdx = find(abs(block.residualWeightGrid - ...
        row.residualWeight) <= 1e-12);
    if numel(edgeIdx) ~= 1 || numel(weightIdx) ~= 1 || ...
            abs(block. ...
                edgeTaskAdvantageDiagnosticTarget( ...
                    edgeIdx, weightIdx) - ...
                row.trueTaskAdvantage) > 1e-12
        error('Label-set initialization target join failed.');
    end
    datasetIdx = find([datasets.seed] == row.seed, 1);
    labelCount = block.labelCounts(edgeIdx);
    action = emptyAction();
    action.pairId = row.pairId;
    action.seed = row.seed;
    action.currentTime = row.currentTime;
    action.edge = reshape(block.edgeFeatures( ...
        edgeIdx, weightIdx, :), 1, []);
    action.receiverNode = ...
        block.nodeFeatures(row.receiverIdx, :);
    action.senderNode = ...
        block.nodeFeatures(row.senderIdx, :);
    action.labelSet = reshape(block.labelFeatures( ...
        edgeIdx, 1:labelCount, :), ...
        labelCount, numel(datasets(datasetIdx).featureNames));
    action.trueTaskAdvantage = row.trueTaskAdvantage;
    actions(actionIdx) = action;
end
pairIds = unique([actions.pairId], 'stable');
pairs = repmat(emptyPair(), 1, numel(pairIds));
for pairIdx = 1:numel(pairIds)
    actionIndices = find( ...
        [actions.pairId] == pairIds(pairIdx));
    if numel(actionIndices) ~= 2
        error('Label-set initialization pair is malformed.');
    end
    pair = emptyPair();
    pair.seed = actions(actionIndices(1)).seed;
    pair.actionA = actionIndices(1);
    pair.actionB = actionIndices(2);
    pair.trueTaskDifference = ...
        actions(pair.actionA).trueTaskAdvantage - ...
        actions(pair.actionB).trueTaskAdvantage;
    if pair.seed ~= actions(pair.actionB).seed || ...
            abs(pair.trueTaskDifference) <= 1e-12
        error('Label-set initialization pair target is invalid.');
    end
    pairs(pairIdx) = pair;
end
end

function base = fitBaseDeepSet( ...
        actions, pairs, protocol, initializationSeed)
edgeX = vertcat(actions.edge);
receiverX = vertcat(actions.receiverNode);
senderX = vertcat(actions.senderNode);
allLabelX = vertcat(actions.labelSet);
[edgeMean, edgeScale] = fitScaler(edgeX);
[nodeMean, nodeScale] = fitScaler([receiverX; senderX]);
[labelMean, labelScale] = fitScaler(allLabelX);
edgeZ = applyScaler(edgeX, edgeMean, edgeScale);
receiverZ = applyScaler(receiverX, nodeMean, nodeScale);
senderZ = applyScaler(senderX, nodeMean, nodeScale);
labelZ = cell(1, numel(actions));
for actionIdx = 1:numel(actions)
    labelZ{actionIdx} = applyScaler( ...
        actions(actionIdx).labelSet, ...
        labelMean, labelScale);
end
pairA = [pairs.actionA];
pairB = [pairs.actionB];
target = reshape([pairs.trueTaskDifference], [], 1);
targetScale = std(target);
if ~isfinite(targetScale) || targetScale <= eps
    targetScale = 1;
end
target = target / targetScale;

labelWidth = protocol.labelHiddenWidth;
nodeWidth = protocol.nodeHiddenWidth;
edgeWidth = protocol.edgeHiddenWidth;
oldInputWidth = size(edgeX, 2) + ...
    2 * labelWidth + 1 + 4 * nodeWidth;
rng(initializationSeed);
parameters = { ...
    randn(size(allLabelX, 2), labelWidth) / ...
        sqrt(size(allLabelX, 2)), ...
    zeros(1, labelWidth), ...
    randn(size(receiverX, 2), nodeWidth) / ...
        sqrt(size(receiverX, 2)), ...
    zeros(1, nodeWidth), ...
    randn(oldInputWidth, edgeWidth) / ...
        sqrt(oldInputWidth), ...
    zeros(1, edgeWidth), ...
    randn(edgeWidth, 1) / sqrt(edgeWidth), ...
    0};
[firstMoment, secondMoment] = initializeAdam(parameters);
lossHistory = nan(protocol.representationEpochCount, 2);
for epoch = 1:protocol.representationEpochCount
    [utility, cache] = forwardBase( ...
        parameters, edgeZ, receiverZ, senderZ, labelZ);
    difference = utility(pairA) - utility(pairB);
    [dataLoss, dDifference] = huberLossGradient( ...
        difference - target, ...
        protocol.representationHuberDelta);
    dDifference = dDifference / numel(target);
    dUtility = zeros(size(utility));
    for pairIdx = 1:numel(pairA)
        dUtility(pairA(pairIdx)) = ...
            dUtility(pairA(pairIdx)) + ...
                dDifference(pairIdx);
        dUtility(pairB(pairIdx)) = ...
            dUtility(pairB(pairIdx)) - ...
                dDifference(pairIdx);
    end
    [gradients, regularization] = backwardBase( ...
        parameters, cache, edgeZ, receiverZ, ...
        senderZ, labelZ, dUtility, ...
        protocol.representationWeightDecay);
    [parameters, firstMoment, secondMoment] = adamStep( ...
        parameters, gradients, firstMoment, ...
        secondMoment, epoch, ...
        protocol.representationLearningRate);
    lossHistory(epoch, :) = ...
        [dataLoss + regularization, regularization];
end
if any(~isfinite(lossHistory(:))) || ...
        any(cellfun(@(value) ...
            any(~isfinite(value(:))), parameters))
    error('Label-set base initialization became non-finite.');
end
base = struct( ...
    'parameters', {parameters}, ...
    'edgeMean', edgeMean, 'edgeScale', edgeScale, ...
    'nodeMean', nodeMean, 'nodeScale', nodeScale, ...
    'labelMean', labelMean, 'labelScale', labelScale, ...
    'targetScale', targetScale, ...
    'lossHistory', lossHistory);
end

function model = buildMessagePassingModel( ...
        base, firstDataset, firstBlock, protocol)
parameters = base.parameters;
edgeFeatureCount = size(firstBlock.edgeFeatures, 3);
labelWidth = protocol.labelHiddenWidth;
oldWeight = parameters{5};
newInputWidth = size(oldWeight, 1) + labelWidth;
newWeight = zeros(newInputWidth, size(oldWeight, 2));
prefixCount = edgeFeatureCount + 2 * labelWidth;
newWeight(1:prefixCount, :) = ...
    oldWeight(1:prefixCount, :);
% The registered DeepSets gate used mean and scaled-sum pooling. Insert a
% zero-initialized max-pooling channel before the count and node features.
newWeight(prefixCount + labelWidth + 1:end, :) = ...
    oldWeight(prefixCount + 1:end, :);

baseWidth = size(newWeight, 2);
messageWidth = protocol.messageHiddenWidth;
messageInputWidth = baseWidth + ...
    4 * (4 * baseWidth);
outputInputWidth = messageWidth + ...
    4 * (4 * messageWidth);
rng(protocol.representationInitializationSeed + 999);
model = struct();
model.kind = 'label-set-message-passing-policy';
model.contractVersion = ...
    protocol.messagePassingModelContractVersion;
model.edgeFeatureNames = ...
    reshape(firstBlock.edgeFeatureNames, 1, []);
model.nodeFeatureNames = ...
    reshape(firstBlock.nodeFeatureNames, 1, []);
model.labelFeatureNames = ...
    reshape(firstDataset.featureNames, 1, []);
model.edgeFeatureMean = base.edgeMean;
model.edgeFeatureScale = base.edgeScale;
model.nodeFeatureMean = base.nodeMean;
model.nodeFeatureScale = base.nodeScale;
model.labelFeatureMean = base.labelMean;
model.labelFeatureScale = base.labelScale;
model.labelEncoderWeight = parameters{1};
model.labelEncoderBias = parameters{2};
model.nodeEncoderWeight = parameters{3};
model.nodeEncoderBias = parameters{4};
model.baseEdgeEncoderWeight = newWeight;
model.baseEdgeEncoderBias = parameters{6};
model.messageEncoderWeight = ...
    randn(messageInputWidth, messageWidth) / ...
        sqrt(messageInputWidth);
model.messageEncoderBias = zeros(1, messageWidth);
model.outputWeight = zeros(outputInputWidth, 1);
model.outputBias = 0;
model.baseTrainingLossHistory = base.lossHistory;
model.featuresUseTruth = false;
model.numericLabelIdentifiersUsedAsFeatures = false;
end

function [weight, metrics] = fitMessageReadout( ...
        model, rows, datasets, blocks, pairs, protocol)
actionFeatures = zeros(numel(rows), ...
    size(model.outputWeight, 1));
actionSeen = false(1, numel(rows));
for blockIdx = 1:numel(blocks)
    block = makeScoringBlock( ...
        blocks(blockIdx), datasets( ...
            [datasets.seed] == blocks(blockIdx).seed));
    scores = scoreLabelSetMessagePassingPolicyModel( ...
        model, block);
    rowIndices = find([rows.seed] == block.seed & ...
        [rows.currentTime] == block.currentTime);
    for rowIdx = rowIndices
        edgeIdx = find(block.receiverIndices == ...
            rows(rowIdx).receiverIdx & ...
            block.senderIndices == ...
            rows(rowIdx).senderIdx);
        weightIdx = find(abs(block.residualWeightGrid - ...
            rows(rowIdx).residualWeight) <= 1e-12);
        if numel(edgeIdx) ~= 1 || numel(weightIdx) ~= 1
            error('Message readout action join failed.');
        end
        actionFeatures(rowIdx, :) = reshape( ...
            scores.outputFeatures( ...
                edgeIdx, weightIdx, :), 1, []);
        actionSeen(rowIdx) = true;
    end
end
if any(~actionSeen) || any(~isfinite(actionFeatures(:)))
    error('Message readout action features are incomplete.');
end
D = zeros(numel(pairs), size(actionFeatures, 2));
y = reshape([pairs.trueTaskDifference], [], 1);
for pairIdx = 1:numel(pairs)
    D(pairIdx, :) = ...
        actionFeatures(pairs(pairIdx).actionA, :) - ...
        actionFeatures(pairs(pairIdx).actionB, :);
end
targetScale = std(y);
if ~isfinite(targetScale) || targetScale <= eps
    targetScale = 1;
end
target = y / targetScale;
lambda = protocol.messageReadoutRidgeLambda;
if size(D, 2) <= size(D, 1)
    coefficient = (D' * D + ...
        lambda * eye(size(D, 2))) \ (D' * target);
else
    coefficient = D' * ((D * D' + ...
        lambda * eye(size(D, 1))) \ target);
end
weight = targetScale * coefficient;
prediction = D * weight;
metrics = struct();
metrics.pairCount = numel(pairs);
metrics.preferenceAccuracy = mean( ...
    sign(prediction) == sign(y));
metrics.differenceSpearman = ...
    computeSpearman(prediction, y);
metrics.meanAbsoluteDifferenceError = ...
    mean(abs(prediction - y));
metrics.targetTruthUsed = true;
metrics.futureOutcomeUsed = false;
end

function block = makeScoringBlock(source, dataset)
block = source;
block.labelFeatureNames = dataset.featureNames;
block.truthUsed = source.featuresUseTruth;
block.futureOutcomeUsed = ...
    source.featuresUseFutureOutcome;
block.numericLabelIdentifiersUsedAsFeatures = ...
    source.numericLabelIdentifiersUsedAsFeatures;
end

function [utility, cache] = forwardBase( ...
        parameters, edgeZ, receiverZ, senderZ, labelZ)
actionCount = size(edgeZ, 1);
labelWidth = size(parameters{1}, 2);
meanPool = zeros(actionCount, labelWidth);
scaledSumPool = zeros(actionCount, labelWidth);
logCount = zeros(actionCount, 1);
labelHidden = cell(1, actionCount);
for actionIdx = 1:actionCount
    hidden = tanh(bsxfun(@plus, ...
        labelZ{actionIdx} * parameters{1}, ...
        parameters{2}));
    labelHidden{actionIdx} = hidden;
    count = size(hidden, 1);
    meanPool(actionIdx, :) = mean(hidden, 1);
    scaledSumPool(actionIdx, :) = ...
        sum(hidden, 1) / sqrt(count);
    logCount(actionIdx) = log1p(count);
end
receiverHidden = tanh(bsxfun(@plus, ...
    receiverZ * parameters{3}, parameters{4}));
senderHidden = tanh(bsxfun(@plus, ...
    senderZ * parameters{3}, parameters{4}));
relational = [ ...
    edgeZ, meanPool, scaledSumPool, logCount, ...
    receiverHidden, senderHidden, ...
    receiverHidden - senderHidden, ...
    receiverHidden .* senderHidden];
edgeHidden = tanh(bsxfun(@plus, ...
    relational * parameters{5}, parameters{6}));
utility = edgeHidden * parameters{7} + parameters{8};
cache = struct( ...
    'labelHidden', {labelHidden}, ...
    'receiverHidden', receiverHidden, ...
    'senderHidden', senderHidden, ...
    'relational', relational, ...
    'edgeHidden', edgeHidden);
end

function [gradients, regularization] = backwardBase( ...
        parameters, cache, edgeZ, receiverZ, senderZ, ...
        labelZ, dUtility, weightDecay)
gradients = cellfun(@(value) zeros(size(value)), ...
    parameters, 'UniformOutput', false);
gradients{7} = cache.edgeHidden' * dUtility;
gradients{8} = sum(dUtility);
dEdgeActivation = (dUtility * parameters{7}') .* ...
    (1 - cache.edgeHidden.^2);
gradients{5} = cache.relational' * dEdgeActivation;
gradients{6} = sum(dEdgeActivation, 1);
dRelational = dEdgeActivation * parameters{5}';
edgeWidth = size(edgeZ, 2);
labelWidth = size(parameters{1}, 2);
nodeWidth = size(parameters{3}, 2);
cursor = edgeWidth;
dMean = dRelational(:, cursor + (1:labelWidth));
cursor = cursor + labelWidth;
dSum = dRelational(:, cursor + (1:labelWidth));
cursor = cursor + labelWidth + 1;
dReceiver = dRelational(:, cursor + (1:nodeWidth));
cursor = cursor + nodeWidth;
dSender = dRelational(:, cursor + (1:nodeWidth));
cursor = cursor + nodeWidth;
dDifference = dRelational(:, cursor + (1:nodeWidth));
cursor = cursor + nodeWidth;
dProduct = dRelational(:, cursor + (1:nodeWidth));
dReceiver = dReceiver + dDifference + ...
    dProduct .* cache.senderHidden;
dSender = dSender - dDifference + ...
    dProduct .* cache.receiverHidden;
dReceiver = dReceiver .* ...
    (1 - cache.receiverHidden.^2);
dSender = dSender .* ...
    (1 - cache.senderHidden.^2);
gradients{3} = receiverZ' * dReceiver + ...
    senderZ' * dSender;
gradients{4} = sum(dReceiver + dSender, 1);
for actionIdx = 1:numel(labelZ)
    count = size(labelZ{actionIdx}, 1);
    dHidden = repmat( ...
        dMean(actionIdx, :) / count + ...
        dSum(actionIdx, :) / sqrt(count), ...
        count, 1);
    dActivation = dHidden .* ...
        (1 - cache.labelHidden{actionIdx}.^2);
    gradients{1} = gradients{1} + ...
        labelZ{actionIdx}' * dActivation;
    gradients{2} = gradients{2} + ...
        sum(dActivation, 1);
end
regularized = [1, 3, 5, 7];
regularization = 0;
for parameterIdx = regularized
    regularization = regularization + ...
        0.5 * weightDecay * ...
            sum(parameters{parameterIdx}(:).^2);
    gradients{parameterIdx} = ...
        gradients{parameterIdx} + ...
            weightDecay * parameters{parameterIdx};
end
end

function [loss, gradient] = huberLossGradient(residual, delta)
absolute = abs(residual);
quadratic = absolute <= delta;
values = delta * absolute - 0.5 * delta^2;
values(quadratic) = 0.5 * residual(quadratic).^2;
gradient = delta * sign(residual);
gradient(quadratic) = residual(quadratic);
loss = mean(values);
end

function [meanValue, scaleValue] = fitScaler(X)
meanValue = mean(X, 1);
scaleValue = std(X, 0, 1);
scaleValue(~isfinite(scaleValue) | scaleValue <= eps) = 1;
end

function Z = applyScaler(X, meanValue, scaleValue)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, meanValue), scaleValue);
end

function [firstMoment, secondMoment] = initializeAdam(parameters)
firstMoment = cellfun(@(value) zeros(size(value)), ...
    parameters, 'UniformOutput', false);
secondMoment = cellfun(@(value) zeros(size(value)), ...
    parameters, 'UniformOutput', false);
end

function [parameters, firstMoment, secondMoment] = adamStep( ...
        parameters, gradients, firstMoment, secondMoment, ...
        epoch, learningRate)
gradients = clipGradients(gradients, 10);
for parameterIdx = 1:numel(parameters)
    firstMoment{parameterIdx} = ...
        0.9 * firstMoment{parameterIdx} + ...
        0.1 * gradients{parameterIdx};
    secondMoment{parameterIdx} = ...
        0.999 * secondMoment{parameterIdx} + ...
        0.001 * gradients{parameterIdx}.^2;
    correctedFirst = firstMoment{parameterIdx} / ...
        (1 - 0.9^epoch);
    correctedSecond = secondMoment{parameterIdx} / ...
        (1 - 0.999^epoch);
    parameters{parameterIdx} = ...
        parameters{parameterIdx} - learningRate * ...
        correctedFirst ./ ...
            (sqrt(correctedSecond) + 1e-8);
end
end

function gradients = clipGradients(gradients, maximumNorm)
squaredNorm = 0;
for gradient = gradients
    squaredNorm = squaredNorm + ...
        sum(gradient{1}(:).^2);
end
normValue = sqrt(squaredNorm);
if normValue > maximumNorm
    gradients = cellfun(@(value) ...
        value * maximumNorm / normValue, ...
        gradients, 'UniformOutput', false);
end
end

function correlation = computeSpearman(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
leftRanks = averageRanks(left);
rightRanks = averageRanks(right);
matrix = corrcoef(leftRanks, rightRanks);
correlation = matrix(1, 2);
end

function ranks = averageRanks(values)
[sortedValues, order] = sort(values);
ranks = zeros(size(values));
startIdx = 1;
while startIdx <= numel(values)
    endIdx = startIdx;
    while endIdx < numel(values) && ...
            sortedValues(endIdx + 1) == ...
                sortedValues(startIdx)
        endIdx = endIdx + 1;
    end
    ranks(order(startIdx:endIdx)) = ...
        0.5 * (startIdx + endIdx);
    startIdx = endIdx + 1;
end
end

function writeReport(path, model, result)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write message-passing initialization report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 label-set message-passing initialization\n\n');
fprintf(fid, '- Generated: %s\n', model.generatedAt);
fprintf(fid, '- Commit: `%s`\n', model.trainingGitCommit);
fprintf(fid, '- Protocol: `%s`\n', model.protocolId);
fprintf(fid, '- Contract: `%s`\n', model.contractVersion);
fprintf(fid, '- Training pairs: `%d`\n', ...
    result.trainingPairCount);
fprintf(fid, '- Training pair preference accuracy: `%.4f`\n', ...
    result.trainingMetrics.preferenceAccuracy);
fprintf(fid, '- Training difference Spearman: `%.4f`\n', ...
    result.trainingMetrics.differenceSpearman);
