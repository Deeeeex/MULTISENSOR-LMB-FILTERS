function [reportPath, summary] = ...
    summarizeLabelSetBehaviorDistributionShiftM24(options)
% SUMMARIZELABELSETBEHAVIORDISTRIBUTIONSHIFTM24 Audit CCC versus LLL.
%
% This summary combines the frozen CCW- and learned-behavior predecision
% distributions. Oracle selection is an offline diagnostic only; the
% function does not fit or evaluate a deployable option selector.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.macroActionDistributionShiftAuditRequired || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 behavior-distribution summary is not authorized.');
end
seeds = reshape(getField( ...
    options, 'seeds', protocol.trainingSeeds), 1, []);
times = reshape(getField( ...
    options, 'times', ...
        protocol.macroActionBehaviorSourceTimes), 1, []);
if isempty(seeds) || ...
        any(~ismember(seeds, protocol.trainingSeeds)) || ...
        numel(unique(seeds)) ~= numel(seeds)
    error('Summary seeds must be distinct registered training seeds.');
end
if isempty(times) || ...
        any(~ismember(times, ...
            protocol.macroActionBehaviorSourceTimes)) || ...
        numel(unique(times)) ~= numel(times)
    error('Summary times must be distinct registered source times.');
end
behaviors = {'ccw', 'learned'};
behaviorActions = protocol.macroActionBehaviorActions;
records = repmat(emptyRecord(), ...
    1, numel(seeds) * numel(times) * numel(behaviors));
recordIdx = 0;
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    for timeIdx = 1:numel(times)
        currentTime = times(timeIdx);
        inputDirectory = resolveInputDirectory( ...
            currentTime, options);
        for behaviorIdx = 1:numel(behaviors)
            behavior = behaviors{behaviorIdx};
            artifactPath = fullfile( ...
                inputDirectory, sprintf('seed%d', seed), ...
                sprintf([ ...
                    'label_set_causal_graph_option_h3_m24_', ...
                    'seed%d_t%d_%s_source.mat'], ...
                    seed, currentTime, behavior));
            loaded = load(artifactPath, 'preflight');
            if ~isfield(loaded, 'preflight')
                error('Distribution-shift artifact lacks preflight.');
            end
            preflight = loaded.preflight;
            validatePreflight( ...
                preflight, seed, currentTime, ...
                behaviorActions{behaviorIdx}, protocol);
            recordIdx = recordIdx + 1;
            records(recordIdx) = buildRecord( ...
                preflight, artifactPath, ...
                behavior, behaviorActions{behaviorIdx});
        end
    end
end

meanCcc = mean([records.cccMeanEospa]);
meanLll = mean([records.lllMeanEospa]);
meanOracle = mean([records.oracleMeanEospa]);
bestStatic = min(meanCcc, meanLll);
oracleGainVsCccPercent = relativeGain( ...
    meanCcc, meanOracle);
oracleGainVsBestStaticPercent = relativeGain( ...
    bestStatic, meanOracle);
seedRows = buildSeedRows(records, seeds);
perSeedStaticSum = sum( ...
    [seedRows.bestStaticMeanEospa]);
perSeedOracleSum = sum( ...
    [seedRows.oracleMeanEospa]);
oracleGainVsPerSeedStaticEnvelopePercent = ...
    relativeGain(perSeedStaticSum, perSeedOracleSum);
losoHeadroomPercent = zeros(1, numel(seeds));
for heldoutIdx = 1:numel(seeds)
    kept = [records.seed] ~= seeds(heldoutIdx);
    keptCcc = mean([records(kept).cccMeanEospa]);
    keptLll = mean([records(kept).lllMeanEospa]);
    keptOracle = mean([records(kept).oracleMeanEospa]);
    losoHeadroomPercent(heldoutIdx) = ...
        relativeGain(min(keptCcc, keptLll), keptOracle);
end
maxAbsByteDeviationPercent = max(abs( ...
    [records.lllByteDeviationVsCccPercent]));
allSafetyPassed = all([records.safetyPassed]);
allRestartEquivalencePassed = ...
    all([records.restartEquivalencePassed]);
oracleWorstMean = mean([records.oracleWorstSensorEospa]);
oracleConsensusMean = mean([records.oracleConsensusOspa]);
cccWorstMean = mean([records.cccWorstSensorEospa]);
lllWorstMean = mean([records.lllWorstSensorEospa]);
cccConsensusMean = mean([records.cccConsensusOspa]);
lllConsensusMean = mean([records.lllConsensusOspa]);

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-label-set-behavior-distribution-shift-summary-v1';
summary.auditContractVersion = ...
    protocol.macroActionDistributionShiftContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.seeds = seeds;
summary.times = times;
summary.behaviors = behaviors;
summary.records = records;
summary.seedRows = seedRows;
summary.meanCccEospa = meanCcc;
summary.meanLllEospa = meanLll;
summary.meanOracleEospa = meanOracle;
summary.oracleGainVsCccPercent = ...
    oracleGainVsCccPercent;
summary.oracleGainVsBestStaticPercent = ...
    oracleGainVsBestStaticPercent;
summary.oracleGainVsPerSeedStaticEnvelopePercent = ...
    oracleGainVsPerSeedStaticEnvelopePercent;
summary.losoHeadroomPercent = losoHeadroomPercent;
summary.minimumLosoHeadroomPercent = ...
    min(losoHeadroomPercent);
summary.learnedWinnerCount = ...
    nnz([records.learnedWins]);
summary.recordCount = numel(records);
summary.maxAbsByteDeviationPercent = ...
    maxAbsByteDeviationPercent;
summary.allSafetyPassed = allSafetyPassed;
summary.allRestartEquivalencePassed = ...
    allRestartEquivalencePassed;
summary.cccWorstSensorMean = cccWorstMean;
summary.lllWorstSensorMean = lllWorstMean;
summary.oracleWorstSensorMean = oracleWorstMean;
summary.cccConsensusMean = cccConsensusMean;
summary.lllConsensusMean = lllConsensusMean;
summary.oracleConsensusMean = oracleConsensusMean;
summary.actionHeadroomGatePassed = ...
    oracleGainVsBestStaticPercent >= ...
        protocol.macroActionFullGridMinimumOracleGainPercent && ...
    summary.minimumLosoHeadroomPercent >= ...
        protocol.macroActionFullGridMinimumLosoHeadroomPercent;
summary.hardAuditGatesPassed = ...
    allSafetyPassed && ...
    allRestartEquivalencePassed && ...
    maxAbsByteDeviationPercent <= ...
        protocol.macroActionMaximumByteDeviationPercent;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.evidenceBoundary = [ ...
    'This opened-training summary measures offline CCC-versus-LLL ', ...
    'H=3 oracle headroom over registered CCW and learned behavior ', ...
    'state distributions. It does not establish a learned selector, ', ...
    'development, held-out M24 or X36 performance.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'behavior_distribution_shift_summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = getField(options, 'artifactStem', ...
    'label_set_behavior_distribution_shift_m24_v1');
if ~ischar(stem) || ...
        isempty(regexp(stem, ...
            '^[A-Za-z0-9_-]+$', 'once'))
    error('artifactStem has invalid characters.');
end
matPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [stem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(stem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Distribution-shift summary already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary);
fprintf('Behavior-distribution summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function directory = resolveInputDirectory(currentTime, options)
if currentTime == 78
    directory = getField(options, ...
        'time78InputDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'evidence', ...
            'label_set_policy_m24_v1', ...
            'behavior_distribution_shift_t78'));
else
    directory = getField(options, ...
        'time79To81InputDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'evidence', ...
            'label_set_policy_m24_v1', ...
            'behavior_distribution_shift_t79_t81'));
end
end

function validatePreflight( ...
        preflight, seed, currentTime, ...
        behaviorAction, protocol)
if ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.auditMode, ...
            'behavior-distribution-shift') || ...
        ~strcmp(preflight.auditContractVersion, ...
            protocol. ...
                macroActionDistributionShiftContractVersion) || ...
        preflight.seed ~= seed || ...
        preflight.currentTime ~= currentTime || ...
        ~strcmp(preflight.sourceBehaviorAction, ...
            behaviorAction) || ...
        ~isequal(preflight.actionSequences, ...
            protocol.macroActionDistributionShiftSequences) || ...
        preflight.exploratoryActionSubsetUsed || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        preflight.runtimePolicyUsesTruth || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || preflight.x36Opened
    error('Distribution-shift preflight violates the contract.');
end
if ~strcmp(computeFileSha256(preflight.sourcePath), ...
        preflight.sourceSha256) || ...
        ~strcmp(computeFileSha256( ...
            preflight.lowLevelModelPath), ...
            preflight.lowLevelModelSha256)
    error('Distribution-shift source or model hash changed.');
end
for outcomeIdx = 1:numel(preflight.outcomes)
    outcome = preflight.outcomes(outcomeIdx);
    if outcome.truthUseCount ~= 0 || ...
            outcome.repairCount ~= 0 || ...
            outcome.payloadEmergencyCount ~= 0 || ...
            outcome.infeasibleCount ~= 0 || ...
            ~outcome.firstActionExact || ...
            ~all(outcome.selectedSensorB3Pass) || ...
            ~all(outcome.selectedFormationB3Pass) || ...
            any(outcome.messageCounts ~= ...
                protocol. ...
                    macroActionExpectedSelectedMessageCount)
        error('Distribution-shift outcome failed a hard gate.');
    end
end
end

function record = buildRecord( ...
        preflight, artifactPath, ...
        behavior, behaviorAction)
ccc = preflight.outcomes(1);
lll = preflight.outcomes(2);
learnedWins = ...
    lll.meanEospa < ccc.meanEospa;
if learnedWins
    oracle = lll;
    oracleAction = 'LLL';
else
    oracle = ccc;
    oracleAction = 'CCC';
end
record = emptyRecord();
record.seed = preflight.seed;
record.currentTime = preflight.currentTime;
record.behavior = behavior;
record.behaviorAction = behaviorAction;
record.artifactPath = artifactPath;
record.artifactSha256 = ...
    computeFileSha256(artifactPath);
record.sourceSha256 = preflight.sourceSha256;
record.cccMeanEospa = ccc.meanEospa;
record.lllMeanEospa = lll.meanEospa;
record.learnedAdvantage = ...
    ccc.meanEospa - lll.meanEospa;
record.learnedGainVsCccPercent = ...
    relativeGain(ccc.meanEospa, ...
        lll.meanEospa);
record.learnedWins = learnedWins;
record.oracleAction = oracleAction;
record.oracleMeanEospa = oracle.meanEospa;
record.cccWorstSensorEospa = ...
    ccc.worstSensorEospa;
record.lllWorstSensorEospa = ...
    lll.worstSensorEospa;
record.oracleWorstSensorEospa = ...
    oracle.worstSensorEospa;
record.cccConsensusOspa = ...
    ccc.consensusOspa;
record.lllConsensusOspa = ...
    lll.consensusOspa;
record.oracleConsensusOspa = ...
    oracle.consensusOspa;
record.cccAttemptedBytes = ...
    ccc.attemptedBytes;
record.lllAttemptedBytes = ...
    lll.attemptedBytes;
record.lllByteDeviationVsCccPercent = ...
    100 * (lll.attemptedBytes - ...
        ccc.attemptedBytes) / ...
        max(ccc.attemptedBytes, eps);
record.restartEquivalencePassed = ...
    preflight.restartEquivalencePassed;
record.safetyPassed = ...
    all([preflight.outcomes.truthUseCount] == 0) && ...
    all([preflight.outcomes.repairCount] == 0) && ...
    all([preflight.outcomes.payloadEmergencyCount] == 0) && ...
    all([preflight.outcomes.infeasibleCount] == 0) && ...
    all(arrayfun(@(outcome) ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass), ...
        preflight.outcomes));
end

function rows = buildSeedRows(records, seeds)
rows = repmat(emptySeedRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    selected = [records.seed] == seed;
    ccc = mean([records(selected).cccMeanEospa]);
    lll = mean([records(selected).lllMeanEospa]);
    oracle = mean([records(selected).oracleMeanEospa]);
    row = emptySeedRow();
    row.seed = seed;
    row.cccMeanEospa = ccc;
    row.lllMeanEospa = lll;
    row.bestStaticMeanEospa = min(ccc, lll);
    row.oracleMeanEospa = oracle;
    row.oracleGainVsBestStaticPercent = ...
        relativeGain(row.bestStaticMeanEospa, oracle);
    row.learnedWinnerCount = ...
        nnz([records(selected).learnedWins]);
    row.recordCount = nnz(selected);
    rows(seedIdx) = row;
end
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write distribution-shift report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 H=3 behavior-distribution shift audit\n\n');
fprintf(fid, '- Seeds / times: `%s / %s`\n', ...
    mat2str(summary.seeds), mat2str(summary.times));
fprintf(fid, '- Records: `%d`\n', summary.recordCount);
fprintf(fid, ['- Mean CCC / LLL / oracle E-OSPA: ', ...
    '`%.6f / %.6f / %.6f`\n'], ...
    summary.meanCccEospa, summary.meanLllEospa, ...
    summary.meanOracleEospa);
fprintf(fid, ['- Oracle gain vs CCC / best global static / ', ...
    'per-seed static envelope: `%.3f%% / %.3f%% / %.3f%%`\n'], ...
    summary.oracleGainVsCccPercent, ...
    summary.oracleGainVsBestStaticPercent, ...
    summary.oracleGainVsPerSeedStaticEnvelopePercent);
fprintf(fid, '- Minimum delete-one-seed headroom: `%.3f%%`\n', ...
    summary.minimumLosoHeadroomPercent);
fprintf(fid, '- LLL winners: `%d / %d`\n', ...
    summary.learnedWinnerCount, summary.recordCount);
fprintf(fid, '- Maximum absolute attempted-byte deviation: `%.3f%%`\n', ...
    summary.maxAbsByteDeviationPercent);
fprintf(fid, '- Hard audit / action headroom gates: `%d / %d`\n\n', ...
    summary.hardAuditGatesPassed, ...
    summary.actionHeadroomGatePassed);
fprintf(fid, '| Seed | CCC | LLL | Best static | Oracle | Oracle gain | L wins |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
for rowIdx = 1:numel(summary.seedRows)
    row = summary.seedRows(rowIdx);
    fprintf(fid, ...
        '| %d | %.6f | %.6f | %.6f | %.6f | %+.3f%% | %d/%d |\n', ...
        row.seed, row.cccMeanEospa, row.lllMeanEospa, ...
        row.bestStaticMeanEospa, row.oracleMeanEospa, ...
        row.oracleGainVsBestStaticPercent, ...
        row.learnedWinnerCount, row.recordCount);
end
fprintf(fid, ...
    '\n| Seed | Time | Source behavior | CCC | LLL | L advantage | L gain | Oracle | Byte dev. | Safe |\n');
fprintf(fid, ...
    '|--:|--:|:--|--:|--:|--:|--:|:--|--:|--:|\n');
for recordIdx = 1:numel(summary.records)
    row = summary.records(recordIdx);
    fprintf(fid, ...
        ['| %d | %d | %s | %.6f | %.6f | %+.6f | ', ...
         '%+.3f%% | %s | %+.3f%% | %d |\n'], ...
        row.seed, row.currentTime, row.behavior, ...
        row.cccMeanEospa, row.lllMeanEospa, ...
        row.learnedAdvantage, ...
        row.learnedGainVsCccPercent, ...
        row.oracleAction, ...
        row.lllByteDeviationVsCccPercent, ...
        row.safetyPassed && ...
            row.restartEquivalencePassed);
end
fprintf(fid, '\n## Boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function record = emptyRecord()
record = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behavior', '', ...
    'behaviorAction', '', ...
    'artifactPath', '', ...
    'artifactSha256', '', ...
    'sourceSha256', '', ...
    'cccMeanEospa', NaN, ...
    'lllMeanEospa', NaN, ...
    'learnedAdvantage', NaN, ...
    'learnedGainVsCccPercent', NaN, ...
    'learnedWins', false, ...
    'oracleAction', '', ...
    'oracleMeanEospa', NaN, ...
    'cccWorstSensorEospa', NaN, ...
    'lllWorstSensorEospa', NaN, ...
    'oracleWorstSensorEospa', NaN, ...
    'cccConsensusOspa', NaN, ...
    'lllConsensusOspa', NaN, ...
    'oracleConsensusOspa', NaN, ...
    'cccAttemptedBytes', NaN, ...
    'lllAttemptedBytes', NaN, ...
    'lllByteDeviationVsCccPercent', NaN, ...
    'restartEquivalencePassed', false, ...
    'safetyPassed', false);
end

function row = emptySeedRow()
row = struct( ...
    'seed', NaN, ...
    'cccMeanEospa', NaN, ...
    'lllMeanEospa', NaN, ...
    'bestStaticMeanEospa', NaN, ...
    'oracleMeanEospa', NaN, ...
    'oracleGainVsBestStaticPercent', NaN, ...
    'learnedWinnerCount', NaN, ...
    'recordCount', NaN);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / ...
    max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
