function [reportPath, summaryPath, summary, config] = ...
    runTopologyRecoveryStressValidation( ...
        numberOfTrials, baseSeed, runExperiment, simulationLength, ...
        useDiaryLog)
% RUNTOPOLOGYRECOVERYSTRESSVALIDATION
% Stress validation for topology recovery under targeted bridge-link failures.
%
% The scenario keeps the same 4+4 mobile-sensor benchmark, but makes the
% four static inter-group bridge edges unreliable while leaving alternate
% cross-group edges usable. Static topology must keep using the failed
% bridge edges; reliability-guarded dynamic topology can rewire within the
% same edge budget.
%
% Dry run:
%   [~, ~, ~, config] = runTopologyRecoveryStressValidation(5, 81, false);
%
% Short development run:
%   [reportPath, summaryPath, summary] = ...
%       runTopologyRecoveryStressValidation(5, 81, true);
%
% Fast smoke:
%   [reportPath, summaryPath, summary] = ...
%       runTopologyRecoveryStressValidation(1, 81, true, 20);
%
% Background/nohup runs should set useDiaryLog=false so stdout/stderr stay in
% the external shell log:
%   runTopologyRecoveryStressValidation(5, 81, true, 100, false);

if nargin < 1 || isempty(numberOfTrials)
    numberOfTrials = 5;
end
if nargin < 2 || isempty(baseSeed)
    baseSeed = 81;
end
if nargin < 3 || isempty(runExperiment)
    runExperiment = true;
end
if nargin < 4 || isempty(simulationLength)
    simulationLength = 100;
end
if nargin < 5 || isempty(useDiaryLog)
    useDiaryLog = true;
end

scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir)
    scriptDir = pwd;
end
projectRoot = resolveProjectRoot(scriptDir);
addpath(projectRoot);
addpath(scriptDir);
setPath;

config = buildStressConfig(numberOfTrials, baseSeed, simulationLength);
reportPath = '';
summaryPath = '';
summary = [];

fprintf('\nTopology recovery stress validation\n');
fprintf('Trials: %d, baseSeed: %d, fixed paired seeds: %d:%d\n', ...
    config.numberOfTrials, config.baseSeed, ...
    config.baseSeed + 1, config.baseSeed + config.numberOfTrials);
fprintf('Simulation length: %d steps\n', ...
    config.experimentOverrides.simulationLength);
fprintf('Static bridge drop: %.2f, alternate edge drop: %.2f\n', ...
    config.staticBridgeDrop, config.alternateEdgeDrop);
for armIdx = 1:numel(config.armSelection)
    fprintf('  Arm %d: %s\n', armIdx, config.armSelection{armIdx});
end

if ~runExperiment
    fprintf('Dry run only. No experiment was launched.\n');
    return;
end

timestamp = datestr(now, 'yyyymmdd_HHMMSS');
logPath = fullfile(scriptDir, sprintf( ...
    'topology_recovery_stress_n%d_seed%d_%s.log', ...
    config.numberOfTrials, config.baseSeed, timestamp));
summaryPath = fullfile(scriptDir, sprintf( ...
    'topology_recovery_stress_n%d_seed%d_%s.mat', ...
    config.numberOfTrials, config.baseSeed, timestamp));

if useDiaryLog
    fprintf('Diary log: %s\n', logPath);
    diary(logPath);
    cleanup = onCleanup(@() diary('off'));
else
    fprintf('Diary log disabled; capture stdout/stderr in the external shell log.\n');
end

[reportPath, summary] = ...
    runMultisensorFilters_formation_4plus4_DualThresholdEventTriggerCompare( ...
        config.numberOfTrials, config.baseSeed, config.useFixedSeed, ...
        config.writeReport, config.thresholdProfile, ...
        config.armSelection, config.experimentOverrides);

summary.topologyRecoveryStress = computeStressComparison(summary);
save(summaryPath, 'summary', 'reportPath', 'config');
appendStressReportSection(reportPath, summary);
printStressSummary(summary, reportPath, summaryPath);

if useDiaryLog
    clear cleanup;
    diary('off');
end
end

function config = buildStressConfig(numberOfTrials, baseSeed, simulationLength)
config = struct();
config.numberOfTrials = numberOfTrials;
config.baseSeed = baseSeed;
config.useFixedSeed = true;
config.writeReport = true;
config.thresholdProfile = 'default';
config.staticBridgeDrop = 0.97;
config.alternateEdgeDrop = 0.08;

pDropByEdge = buildBridgeFailureDropMatrix( ...
    8, config.staticBridgeDrop, config.alternateEdgeDrop);
config.experimentOverrides = struct( ...
    'simulationLength', simulationLength, ...
    'calibration', buildAlwaysLightCalibrationStub(), ...
    'pDropByEdge', pDropByEdge, ...
    'includeTopologyRecoveryStressVariants', true, ...
    'recoveryTopologyReliabilityWeight', 0.55, ...
    'recoveryTopologyOverlapWeight', 0.35, ...
    'recoveryTopologyComplementarityWeight', 0.10, ...
    'recoveryTopologyStaticEdgeBonus', 0.35, ...
    'recoveryTopologyPreviousEdgeBonus', 0.50, ...
    'recoveryTopologyMaxEdgeChangeFraction', 0.15, ...
    'recoveryBackbonePreviousEdgeBonus', 0, ...
    'recoveryNonStaticFusionWeightFactor', 0.65, ...
    'recoveryMaxNonStaticFusionWeight', 0.12, ...
    'recoveryTopologyBackboneGroups', {{1:4, 5:8}}, ...
    'recoveryModeAwareFusionWeights', false, ...
    'recoveryLightFusionWeightFactor', 1.0, ...
    'recoveryMaxSelfFusionWeight', 1.0, ...
    'recoveryTopologyFallbackToBase', true);

config.armSelection = { ...
    'Recovery stress: Periodic light static topology', ...
    'Recovery stress: Reliability-guarded dynamic topology', ...
    'Recovery stress: Stable reliability-only dynamic topology', ...
    'Recovery stress: Static-preserving reliability repair topology', ...
    'Recovery stress: Balanced reliability repair topology', ...
    'Recovery stress: Role-matched reliability repair topology', ...
    'Recovery stress: Distance-balanced reliability repair topology', ...
    'Recovery stress: Compatibility-balanced repair topology', ...
    'Recovery stress: Churn-aware dynamic topology', ...
    'Recovery stress: Risk-capped dynamic topology', ...
    'Recovery stress: Backbone-preserving dynamic topology'};
end

function calibration = buildAlwaysLightCalibrationStub()
% Stress arms use eventPolicy='alwaysLight', so threshold calibration is not
% part of the experiment. Supplying a stub avoids an expensive always-heavy
% calibration run before every stress validation.
calibration = struct();
calibration.multi.loose = [0.20, 0.40];
calibration.multi.default = [0.25, 0.60];
calibration.multi.strict = [0.35, 0.80];
calibration.information.loose = [0.20, 0.40];
calibration.information.default = [0.25, 0.60];
calibration.information.strict = [0.35, 0.80];
calibration.sampleCount.utility = 0;
calibration.sampleCount.informationGain = 0;
end

function pDropByEdge = buildBridgeFailureDropMatrix( ...
    numberOfSensors, bridgeDrop, defaultDrop)
pDropByEdge = defaultDrop * ones(numberOfSensors);
pDropByEdge(1:numberOfSensors+1:end) = 0;
staticBridgeEdges = [1 5; 2 6; 3 7; 4 8];
for edgeIdx = 1:size(staticBridgeEdges, 1)
    left = staticBridgeEdges(edgeIdx, 1);
    right = staticBridgeEdges(edgeIdx, 2);
    pDropByEdge(left, right) = bridgeDrop;
    pDropByEdge(right, left) = bridgeDrop;
end
end

function stress = computeStressComparison(summary)
staticIdx = find(strcmp(summary.armNames, ...
    'Recovery stress: Periodic light static topology'), 1);
recoveryIdx = find(strcmp(summary.armNames, ...
    'Recovery stress: Reliability-guarded dynamic topology'), 1);
if isempty(staticIdx) || isempty(recoveryIdx)
    stress = struct();
    return;
end

stress.staticArm = summary.armNames{staticIdx};
stress.recoveryArm = summary.armNames{recoveryIdx};
stress.payloadBytesChangePercent = percentChange( ...
    summary.communication.payloadBytes(staticIdx), ...
    summary.communication.payloadBytes(recoveryIdx));
stress.attemptCountChangePercent = percentChange( ...
    summary.communication.attemptCount(staticIdx), ...
    summary.communication.attemptCount(recoveryIdx));
stress.deliveryCountChangePercent = percentChange( ...
    summary.communication.deliveryCount(staticIdx), ...
    summary.communication.deliveryCount(recoveryIdx));
stress.deliveryRateChangePercent = percentChange( ...
    summary.communication.deliveryRate(staticIdx), ...
    summary.communication.deliveryRate(recoveryIdx));
stress.localEOspaChangePercent = percentChange( ...
    summary.local.meanAcrossSensors.eOspa(staticIdx), ...
    summary.local.meanAcrossSensors.eOspa(recoveryIdx));
stress.consensusOspaChangePercent = percentChange( ...
    summary.consensus.ospa(staticIdx), ...
    summary.consensus.ospa(recoveryIdx));
stress.positionDisagreementChangePercent = percentChange( ...
    summary.consensus.position(staticIdx), ...
    summary.consensus.position(recoveryIdx));
stress.cardinalityDispersionChangePercent = percentChange( ...
    summary.consensus.cardinality(staticIdx), ...
    summary.consensus.cardinality(recoveryIdx));
stress.effectiveWeightLambda2ChangePercent = percentChange( ...
    summary.effectiveGraph.effectiveWeightConnectivity(staticIdx), ...
    summary.effectiveGraph.effectiveWeightConnectivity(recoveryIdx));
stress.trialCount = summary.numberOfTrials;
stress.trialSeeds = summary.trialSeeds;
stress.equalAttemptBudget = all(abs( ...
    summary.trials.attemptCount(:, staticIdx) - ...
    summary.trials.attemptCount(:, recoveryIdx)) <= 1e-9);
stress.trialDeltas = computeTrialDeltas(summary, staticIdx, recoveryIdx);
stress.winCounts = computeRecoveryWinCounts(stress.trialDeltas);
stress.strictRecoveryGate = stress.equalAttemptBudget && ...
    stress.winCounts.delivery == stress.trialCount && ...
    stress.winCounts.localEOspa == stress.trialCount && ...
    stress.winCounts.consensusOspa == stress.trialCount && ...
    stress.winCounts.cardinality == stress.trialCount && ...
    stress.winCounts.effectiveWeightLambda2 == stress.trialCount;
stress.robustWinRateThreshold = 0.90;
stress.robustRequiredWins = ceil( ...
    stress.robustWinRateThreshold * stress.trialCount);
stress.robustRecoveryGate = stress.equalAttemptBudget && ...
    stress.deliveryCountChangePercent > 0 && ...
    stress.localEOspaChangePercent < 0 && ...
    stress.consensusOspaChangePercent < 0 && ...
    stress.cardinalityDispersionChangePercent < 0 && ...
    stress.effectiveWeightLambda2ChangePercent > 0 && ...
    stress.winCounts.delivery == stress.trialCount && ...
    stress.winCounts.effectiveWeightLambda2 == stress.trialCount && ...
    stress.winCounts.localEOspa >= stress.robustRequiredWins && ...
    stress.winCounts.consensusOspa >= stress.robustRequiredWins && ...
    stress.winCounts.cardinality >= stress.robustRequiredWins;
stress.truthRecoveryGate = stress.strictRecoveryGate;
stress.positionRisk = stress.winCounts.positionDisagreement < stress.trialCount;
stress.staticPassCount = getOptionalPassCount(summary, staticIdx);
stress.recoveryPassCount = getOptionalPassCount(summary, recoveryIdx);
end

function deltas = computeTrialDeltas(summary, staticIdx, recoveryIdx)
staticLocal = squeeze(mean(summary.trials.localEOspa(:, :, staticIdx), 2));
recoveryLocal = squeeze(mean(summary.trials.localEOspa(:, :, recoveryIdx), 2));
deltas.localEOspa = percentChangeSeries(staticLocal, recoveryLocal);
deltas.consensusOspa = percentChangeSeries( ...
    summary.trials.consensusOspa(:, staticIdx), ...
    summary.trials.consensusOspa(:, recoveryIdx));
deltas.positionDisagreement = percentChangeSeries( ...
    summary.trials.consensusPosition(:, staticIdx), ...
    summary.trials.consensusPosition(:, recoveryIdx));
deltas.cardinality = percentChangeSeries( ...
    summary.trials.consensusCardinality(:, staticIdx), ...
    summary.trials.consensusCardinality(:, recoveryIdx));
deltas.delivery = percentChangeSeries( ...
    summary.trials.deliveryCount(:, staticIdx), ...
    summary.trials.deliveryCount(:, recoveryIdx));
deltas.effectiveWeightLambda2 = percentChangeSeries( ...
    summary.trials.effectiveWeightConnectivity(:, staticIdx), ...
    summary.trials.effectiveWeightConnectivity(:, recoveryIdx));
end

function values = percentChangeSeries(baseline, candidate)
baseline = reshape(baseline, [], 1);
candidate = reshape(candidate, [], 1);
values = NaN(size(baseline));
valid = isfinite(baseline) & isfinite(candidate) & abs(baseline) > eps;
values(valid) = 100 * (candidate(valid) - baseline(valid)) ./ baseline(valid);
end

function counts = computeRecoveryWinCounts(deltas)
counts = struct();
counts.delivery = sum(deltas.delivery > 0);
counts.localEOspa = sum(deltas.localEOspa < 0);
counts.consensusOspa = sum(deltas.consensusOspa < 0);
counts.positionDisagreement = sum(deltas.positionDisagreement < 0);
counts.cardinality = sum(deltas.cardinality < 0);
counts.effectiveWeightLambda2 = sum(deltas.effectiveWeightLambda2 > 0);
end

function value = getOptionalPassCount(summary, armIdx)
value = NaN;
if ~isfield(summary, 'pairedDelta') || ...
        ~isfield(summary.pairedDelta, 'passCount')
    return;
end
passCount = summary.pairedDelta.passCount;
if isnumeric(passCount) && numel(passCount) >= armIdx
    value = passCount(armIdx);
elseif iscell(passCount) && numel(passCount) >= armIdx && ...
        isnumeric(passCount{armIdx})
    value = passCount{armIdx};
end
end

function printStressSummary(summary, reportPath, summaryPath)
fprintf('\nTopology recovery stress result\n');
fprintf('Report: %s\n', reportPath);
fprintf('Summary: %s\n', summaryPath);
fprintf('\nArm names:\n');
disp(summary.armNames');
fprintf('Payload bytes:\n');
disp(summary.communication.payloadBytes);
fprintf('Attempt counts:\n');
disp(summary.communication.attemptCount);
fprintf('Delivery counts:\n');
disp(summary.communication.deliveryCount);
fprintf('Local E-OSPA:\n');
disp(summary.local.meanAcrossSensors.eOspa);
fprintf('Consensus OSPA:\n');
disp(summary.consensus.ospa);
fprintf('Effective-weight lambda2:\n');
disp(summary.effectiveGraph.effectiveWeightConnectivity);
if isfield(summary, 'topologyRecoveryStress') && ...
        isfield(summary.topologyRecoveryStress, 'consensusOspaChangePercent')
    stress = summary.topologyRecoveryStress;
    fprintf('\nRecovery dynamic vs static-light baseline:\n');
    fprintf('  bytes change: %.2f%%\n', ...
        stress.payloadBytesChangePercent);
    fprintf('  attempt count change: %.2f%%\n', ...
        stress.attemptCountChangePercent);
    fprintf('  delivery count change: %.2f%%\n', ...
        stress.deliveryCountChangePercent);
    fprintf('  delivery rate change: %.2f%%\n', ...
        stress.deliveryRateChangePercent);
    fprintf('  local E-OSPA change: %.2f%%\n', ...
        stress.localEOspaChangePercent);
    fprintf('  consensus OSPA change: %.2f%%\n', ...
        stress.consensusOspaChangePercent);
    fprintf('  position disagreement change: %.2f%%\n', ...
        stress.positionDisagreementChangePercent);
    fprintf('  cardinality dispersion change: %.2f%%\n', ...
        stress.cardinalityDispersionChangePercent);
    fprintf('  effective-weight lambda2 change: %.2f%%\n', ...
        stress.effectiveWeightLambda2ChangePercent);
    fprintf('  equal attempted budget: %d\n', stress.equalAttemptBudget);
    fprintf('  strict recovery gate: %d\n', stress.strictRecoveryGate);
    fprintf('  robust recovery gate: %d (min wins %d/%d)\n', ...
        stress.robustRecoveryGate, stress.robustRequiredWins, ...
        stress.trialCount);
    fprintf('  position-risk flag: %d\n', stress.positionRisk);
    fprintf(['  win counts delivery/local/consensus/cardinality/' ...
        'effective/position: %d/%d, %d/%d, %d/%d, %d/%d, %d/%d, %d/%d\n'], ...
        stress.winCounts.delivery, stress.trialCount, ...
        stress.winCounts.localEOspa, stress.trialCount, ...
        stress.winCounts.consensusOspa, stress.trialCount, ...
        stress.winCounts.cardinality, stress.trialCount, ...
        stress.winCounts.effectiveWeightLambda2, stress.trialCount, ...
        stress.winCounts.positionDisagreement, stress.trialCount);
end
end

function appendStressReportSection(reportPath, summary)
if isempty(reportPath) || ~exist(reportPath, 'file') || ...
        ~isfield(summary, 'topologyRecoveryStress') || ...
        ~isfield(summary.topologyRecoveryStress, 'truthRecoveryGate')
    return;
end
stress = summary.topologyRecoveryStress;
fid = fopen(reportPath, 'a');
if fid < 0
    return;
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '\n## Topology Recovery Stress Gate\n\n');
fprintf(fid, ['This stress-specific gate compares recovery dynamic topology ' ...
    'against the static light graph under targeted bridge-link failures. ' ...
    'It uses attempted message count as the communication budget because ' ...
    'delivered payload bytes increase when the recovery topology successfully ' ...
    'routes around failed links.\n\n']);
fprintf(fid, '| Metric | Static | Recovery | Change | Win count |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|\n');
fprintf(fid, '| Attempt count | %.0f | %.0f | %.2f%% | equal=%d |\n', ...
    summary.communication.attemptCount(1), ...
    summary.communication.attemptCount(2), ...
    stress.attemptCountChangePercent, stress.equalAttemptBudget);
fprintf(fid, '| Delivery count | %.1f | %.1f | %.2f%% | %d/%d |\n', ...
    summary.communication.deliveryCount(1), ...
    summary.communication.deliveryCount(2), ...
    stress.deliveryCountChangePercent, ...
    stress.winCounts.delivery, stress.trialCount);
fprintf(fid, '| Local E-OSPA | %.4f | %.4f | %.2f%% | %d/%d |\n', ...
    summary.local.meanAcrossSensors.eOspa(1), ...
    summary.local.meanAcrossSensors.eOspa(2), ...
    stress.localEOspaChangePercent, ...
    stress.winCounts.localEOspa, stress.trialCount);
fprintf(fid, '| Consensus OSPA | %.4f | %.4f | %.2f%% | %d/%d |\n', ...
    summary.consensus.ospa(1), summary.consensus.ospa(2), ...
    stress.consensusOspaChangePercent, ...
    stress.winCounts.consensusOspa, stress.trialCount);
fprintf(fid, '| Position disagreement | %.4f | %.4f | %.2f%% | %d/%d |\n', ...
    summary.consensus.position(1), summary.consensus.position(2), ...
    stress.positionDisagreementChangePercent, ...
    stress.winCounts.positionDisagreement, stress.trialCount);
fprintf(fid, '| Cardinality dispersion | %.4f | %.4f | %.2f%% | %d/%d |\n', ...
    summary.consensus.cardinality(1), summary.consensus.cardinality(2), ...
    stress.cardinalityDispersionChangePercent, ...
    stress.winCounts.cardinality, stress.trialCount);
fprintf(fid, '| Effective-weight lambda2 | %.4f | %.4f | %.2f%% | %d/%d |\n', ...
    summary.effectiveGraph.effectiveWeightConnectivity(1), ...
    summary.effectiveGraph.effectiveWeightConnectivity(2), ...
    stress.effectiveWeightLambda2ChangePercent, ...
    stress.winCounts.effectiveWeightLambda2, stress.trialCount);
fprintf(fid, '\n- Strict all-trial recovery gate: `%d`\n', ...
    stress.strictRecoveryGate);
fprintf(fid, '- Robust recovery gate: `%d` (min wins `%d/%d`)\n', ...
    stress.robustRecoveryGate, stress.robustRequiredWins, ...
    stress.trialCount);
fprintf(fid, '- Position-risk flag: `%d`\n\n', stress.positionRisk);
fprintf(fid, '| Seed | Delivery | Local E-OSPA | Consensus OSPA | Position | Card. | Eff. lambda2 |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for trialIdx = 1:stress.trialCount
    fprintf(fid, '| %d | %.2f%% | %.2f%% | %.2f%% | %.2f%% | %.2f%% | %.2f%% |\n', ...
        stress.trialSeeds(trialIdx), ...
        stress.trialDeltas.delivery(trialIdx), ...
        stress.trialDeltas.localEOspa(trialIdx), ...
        stress.trialDeltas.consensusOspa(trialIdx), ...
        stress.trialDeltas.positionDisagreement(trialIdx), ...
        stress.trialDeltas.cardinality(trialIdx), ...
        stress.trialDeltas.effectiveWeightLambda2(trialIdx));
end
end

function value = percentChange(baseline, candidate)
if ~isfinite(baseline) || abs(baseline) <= eps || ~isfinite(candidate)
    value = NaN;
else
    value = 100 * (candidate - baseline) / baseline;
end
end

function projectRoot = resolveProjectRoot(scriptDir)
projectRoot = scriptDir;
while ~exist(fullfile(projectRoot, 'setPath.m'), 'file')
    parentDir = fileparts(projectRoot);
    if strcmp(parentDir, projectRoot)
        error('Could not locate project root from %s.', scriptDir);
    end
    projectRoot = parentDir;
end
end
