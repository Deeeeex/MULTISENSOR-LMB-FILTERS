function [reportPath, validation] = ...
    summarizeLabelSetAdaptiveDominantDevelopmentM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTDEVELOPMENTM24 Gate frozen D-B.
%
% The gate was registered before development evaluation: >=5% aggregate
% E-OSPA gain versus paired frozen CCW, positive gain on both seeds, no
% aggregate worst-node or consensus regression, <=2% attempted-byte
% mismatch per seed, and the same hard topology/observability contract.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantDevelopmentEvaluationAuthorized || ...
        protocol.adaptiveDominantHeldoutM24Authorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Adaptive-dominant development summary is not authorized.');
end
seeds = protocol.adaptiveDominantDevelopmentSeeds;
inputDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_balanced_development_v1'));
rows = repmat(emptyRow(), 1, numel(seeds));
runCommit = '';
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    path = findSingleEvidence(inputDirectory, seed);
    loaded = load(path, 'summary');
    summary = loaded.summary;
    validateSummary(summary, seed, protocol);
    if isempty(runCommit)
        runCommit = summary.generationGitCommit;
    elseif ~strcmp(runCommit, summary.generationGitCommit)
        error('Development runs use different commits.');
    end
    baseline = findArm(summary.aggregate, ...
        protocol.adaptiveDominantDevelopmentReferenceArmName);
    candidate = findArm(summary.aggregate, ...
        protocol.adaptiveDominantDevelopmentArmName);
    row = emptyRow();
    row.seed = seed;
    row.evidencePath = path;
    row.baselineEospa = baseline.focusEospa;
    row.candidateEospa = candidate.focusEospa;
    row.gainPercent = relativeGain( ...
        row.baselineEospa, row.candidateEospa);
    row.baselineWorstEospa = baseline.focusWorstSensorEospa;
    row.candidateWorstEospa = candidate.focusWorstSensorEospa;
    row.baselineConsensusOspa = ...
        baseline.focusMapSetDisagreement;
    row.candidateConsensusOspa = ...
        candidate.focusMapSetDisagreement;
    row.byteDeltaPercent = 100 * ...
        (candidate.focusAttemptedBytes - ...
         baseline.focusAttemptedBytes) / ...
        max(baseline.focusAttemptedBytes, eps);
    row.meanMessageCount = candidate.meanDirectedMessageCount;
    row.selectedSensorB3 = ...
        candidate.focusSelectedRollingB3SensorStrongFraction;
    row.selectedFormationB3 = ...
        candidate.focusSelectedRollingB3FormationStrongFraction;
    row.deliveredSensorB3 = ...
        candidate.focusDeliveredRollingB3SensorStrongFraction;
    row.truthUseFraction = candidate.policyTruthUseFraction;
    row.posteriorUseFraction = ...
        candidate.policyPosteriorContentUseFraction;
    row.currentLinkReliabilityUseFraction = ...
        candidate.policyCurrentLinkReliabilityUseFraction;
    row.repairRate = candidate.policyRepairRate;
    row.payloadEmergencyRate = ...
        candidate.policyPayloadEmergencyRate;
    row.topologyInfeasibleRate = ...
        candidate.focusTopologyInfeasibleRate;
    row.routeChangeFraction = ...
        candidate.focusWithinWindowRouteChangeFraction;
    row.distinctRouteMaps = ...
        candidate.focusDistinctDirectedRouteMapCount;
    row.hardSafetyPassed = hardSafetyPassed(row, protocol);
    rows(seedIdx) = row;
end

baselineMean = mean([rows.baselineEospa]);
candidateMean = mean([rows.candidateEospa]);
meanGain = relativeGain(baselineMean, candidateMean);
positiveFraction = mean([rows.gainPercent] > 0);
worstGain = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
consensusGain = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
maximumAbsoluteByteDelta = max(abs([rows.byteDeltaPercent]));
hardSafetyPassedAll = all([rows.hardSafetyPassed]);
trackingGatePassed = meanGain >= ...
    protocol.adaptiveDominantDevelopmentMinimumMeanGainPercent && ...
    positiveFraction >= ...
        protocol. ...
            adaptiveDominantDevelopmentMinimumPositiveSeedFraction;
tailGatePassed = ...
    (~protocol. ...
        adaptiveDominantDevelopmentRequireNoAggregateWorstRegression || ...
        worstGain >= -1e-12) && ...
    (~protocol. ...
        adaptiveDominantDevelopmentRequireNoAggregateConsensusRegression || ...
        consensusGain >= -1e-12);
communicationGatePassed = maximumAbsoluteByteDelta <= ...
    protocol.adaptiveDominantDevelopmentMaximumByteDeltaPercent + 1e-12;
developmentGatePassed = hardSafetyPassedAll && ...
    trackingGatePassed && tailGatePassed && communicationGatePassed;

gitState = resolveResearchGitState();
validation = struct();
validation.protocolId = protocol.id;
validation.contractVersion = ...
    protocol.adaptiveDominantDevelopmentContractVersion;
validation.generatedAt = datestr(now, 31);
validation.generationGitCommit = gitState.commit;
validation.runGenerationGitCommit = runCommit;
validation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
validation.seeds = seeds;
validation.times = protocol.adaptiveDominantDevelopmentTimes;
validation.rows = rows;
validation.baselineMeanEospa = baselineMean;
validation.candidateMeanEospa = candidateMean;
validation.meanGainPercent = meanGain;
validation.positiveSeedFraction = positiveFraction;
validation.aggregateWorstGainPercent = worstGain;
validation.aggregateConsensusGainPercent = consensusGain;
validation.maximumAbsoluteByteDeltaPercent = ...
    maximumAbsoluteByteDelta;
validation.hardSafetyPassed = hardSafetyPassedAll;
validation.trackingGatePassed = trackingGatePassed;
validation.tailGatePassed = tailGatePassed;
validation.communicationGatePassed = ...
    communicationGatePassed;
validation.developmentGatePassed = developmentGatePassed;
validation.trainingEvidenceFrozen = true;
validation.heldoutM24Opened = false;
validation.x36Opened = false;
if developmentGatePassed
    validation.nextDirection = ...
        'authorize-one-shot-heldout-M24-then-register-X36-scale-contract';
else
    validation.nextDirection = ...
        'stop-method-selection-without-opening-heldout-or-X36';
end
validation.evidenceBoundary = [ ...
    'This is the complete registered M24 development split. D-B was ', ...
    'frozen before these outcomes were opened. Passing this gate may ', ...
    'authorize a one-shot held-out M24 run; it is not itself held-out ', ...
    'or X36 evidence.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_DEVELOPMENT_M24_V1.md');
writeReport(reportPath, validation, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
validation.reportPath = reportPath;
validation.matPath = matPath;
fprintf('Adaptive-dominant development summary: %s\n', reportPath);
end

function path = findSingleEvidence(rootDirectory, seed)
matches = dir(fullfile( ...
    rootDirectory, sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected exactly one development MAT for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function validateSummary(summary, seed, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'development') || ...
        summary.options.continuationStartTime ~= ...
            protocol.adaptiveDominantDevelopmentTimes(1) || ...
        summary.options.maxTimeSteps ~= ...
            protocol.adaptiveDominantDevelopmentTimes(end) || ...
        ~all(ismember({ ...
            protocol.adaptiveDominantDevelopmentReferenceArmName, ...
            protocol.adaptiveDominantDevelopmentArmName}, ...
            {summary.aggregate.mode})) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Adaptive-dominant development provenance contract failed.');
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Development evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    abs(row.meanMessageCount - ...
        protocol.adaptiveDominantDevelopmentExpectedMessageCount) < 1e-12 && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'evidencePath', '', ...
    'baselineEospa', NaN, ...
    'candidateEospa', NaN, ...
    'gainPercent', NaN, ...
    'baselineWorstEospa', NaN, ...
    'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, ...
    'candidateConsensusOspa', NaN, ...
    'byteDeltaPercent', NaN, ...
    'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, ...
    'selectedFormationB3', NaN, ...
    'deliveredSensorB3', NaN, ...
    'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'repairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'routeChangeFraction', NaN, ...
    'distinctRouteMaps', NaN, ...
    'hardSafetyPassed', false);
end

function writeReport(path, validation, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write adaptive-dominant development report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 adaptive-dominant development gate\n\n');
fprintf(fid, '- Contract: `%s`\n', validation.contractVersion);
fprintf(fid, '- Generated: %s\n', validation.generatedAt);
fprintf(fid, '- Run commit: `%s`\n', ...
    validation.runGenerationGitCommit);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seeds));
fprintf(fid, '- Window: `%s`\n\n', mat2str(validation.times));
fprintf(fid, ['| Seed | CCW E-OSPA | D-B E-OSPA | Gain | CCW worst | ', ...
    'D-B worst | CCW consensus | D-B consensus | Byte delta | ', ...
    'Msgs | Selected B3 | Delivered B3 | Maps | Safe |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|--:|:--:|\n']);
for row = validation.rows
    fprintf(fid, ['| %d | %.6f | %.6f | %+.3f%% | %.6f | ', ...
        '%.6f | %.6f | %.6f | %+.3f%% | %.2f | %.3f | ', ...
        '%.3f | %.0f | %d |\n'], ...
        row.seed, row.baselineEospa, row.candidateEospa, ...
        row.gainPercent, row.baselineWorstEospa, ...
        row.candidateWorstEospa, row.baselineConsensusOspa, ...
        row.candidateConsensusOspa, row.byteDeltaPercent, ...
        row.meanMessageCount, row.selectedSensorB3, ...
        row.deliveredSensorB3, row.distinctRouteMaps, ...
        row.hardSafetyPassed);
end
fprintf(fid, '\n## Registered gate\n\n');
fprintf(fid, '- Mean CCW E-OSPA: `%.6f`\n', ...
    validation.baselineMeanEospa);
fprintf(fid, '- Mean D-B E-OSPA: `%.6f`\n', ...
    validation.candidateMeanEospa);
fprintf(fid, '- Mean gain: `%+.3f%%` (gate `>= %.3f%%`)\n', ...
    validation.meanGainPercent, ...
    protocol.adaptiveDominantDevelopmentMinimumMeanGainPercent);
fprintf(fid, '- Positive seeds: `%d/%d` (gate `2/2`)\n', ...
    nnz([validation.rows.gainPercent] > 0), ...
    numel(validation.rows));
fprintf(fid, '- Aggregate worst-node gain: `%+.3f%%`\n', ...
    validation.aggregateWorstGainPercent);
fprintf(fid, '- Aggregate consensus gain: `%+.3f%%`\n', ...
    validation.aggregateConsensusGainPercent);
fprintf(fid, ['- Maximum absolute attempted-byte delta: `%.3f%%` ', ...
    '(gate `<= %.3f%%`)\n'], ...
    validation.maximumAbsoluteByteDeltaPercent, ...
    protocol.adaptiveDominantDevelopmentMaximumByteDeltaPercent);
fprintf(fid, '- Hard safety passed: `%d`\n', ...
    validation.hardSafetyPassed);
fprintf(fid, '- Tracking gate passed: `%d`\n', ...
    validation.trackingGatePassed);
fprintf(fid, '- Tail gate passed: `%d`\n', ...
    validation.tailGatePassed);
fprintf(fid, '- Communication gate passed: `%d`\n', ...
    validation.communicationGatePassed);
fprintf(fid, '- Development gate passed: `%d`\n', ...
    validation.developmentGatePassed);
fprintf(fid, '- Next: `%s`\n\n', validation.nextDirection);
fprintf(fid, '%s\n', validation.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
