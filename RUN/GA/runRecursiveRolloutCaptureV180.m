function [reportPath, result] = runRecursiveRolloutCaptureV180(options)
% RUNRECURSIVEROLLOUTCAPTUREV180 Capture states visited by recursive V179.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRolloutAwareOneHopSafeLabelV179Protocol();
sourceScreenPath = getField(options, ...
    'referenceOutcomeScreenPath', fullfile( ...
        protocol.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
if exist(sourceScreenPath, 'file') ~= 2
    error('RecursiveRolloutCaptureV180:MissingReference', ...
        'The completed paired V179 screen is required for reference reuse.');
end
protocol.reuseFrozenReferenceOutcome = true;
protocol.referenceOutcomeScreenPath = sourceScreenPath;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v180', 'recursive_rollout_capture');
protocol.headroomOutputRoot = protocol.outputRoot;
protocol.reportTitle = ...
    'V180 recursive V179-rollout capture: X36 t72 H=8';
protocol.resultFileStem = ...
    'RECURSIVE_V179_ROLLOUT_CAPTURE_V180_X36_T72_RESULT';
protocol.resultContractVersion = ...
    'recursive-v179-rollout-capture-v180-x36-t72-result-v1';
protocol.evidenceBoundary = [ ...
    'V180 reruns only the frozen V179 candidate arm and captures its ', ...
    'pre-side-channel fused posterior at each return time. The completed ', ...
    'V179 static reference outcome is reused without recomputation. ', ...
    'Inference and communication accounting are unchanged from V179; ', ...
    'the additional snapshots are development instrumentation for a ', ...
    'second same-seed policy-iteration round, not validation evidence.'];
runOptions = struct( ...
    'protocolOverride', protocol, ...
    'outputRoot', getField(options, 'outputRoot', ...
        fullfile(protocol.headroomOutputRoot, 'x36_t72_h8')), ...
    'captureFusedPosteriorSnapshotsEnabled', true, ...
    'reuseCompletedCandidateScreen', getField(options, ...
        'reuseCompletedCandidateScreen', true));
[reportPath, result] = runProtectionOnlyH8V105X36T72(runOptions);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
