function [reportPath, probe] = runFormationH3DurationProbe(options)
% RUNFORMATIONH3DURATIONPROBE Persistent versus one-step opened probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3DurationProbeProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 duration probe requires clean source.');
end
outputRoot = getField(options, 'outputDirectory', ...
    protocol.outputRoot);
probePath = fullfile(outputRoot, ...
    'formation_h3_duration_probe_seed211_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_H3_DURATION_PROBE_SEED211_V1.md');
probeExists = exist(probePath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(probeExists, reportExists)
    error('Formation H=3 duration-probe artifacts are partial.');
elseif probeExists
    loaded = load(probePath, 'probe');
    if ~isfield(loaded, 'probe') || ...
            ~strcmp(loaded.probe.protocolId, protocol.id) || ...
            ~strcmp(loaded.probe.generationGitCommit, gitState.commit)
        error('Formation H=3 duration-probe provenance mismatch.');
    end
    probe = loaded.probe;
    fprintf('Reused formation H=3 duration probe: %s\n', probePath);
    return;
end

screens = cell(1, numel(protocol.snapshotTimes));
screenReports = screens;
audits = screens;
for timeIdx = 1:numel(protocol.snapshotTimes)
    currentTime = protocol.snapshotTimes(timeIdx);
    validateCache(currentTime, protocol);
    screenDirectory = fullfile( ...
        outputRoot, sprintf('t%d', currentTime));
    screenOptions = struct( ...
        'cacheRoot', protocol.cacheRoot, ...
        'outputDirectory', screenDirectory, ...
        'actionIndices', [1, protocol.actionIndices(timeIdx)], ...
        'interventionDurationSteps', ...
            protocol.interventionDurationSteps);
    switch protocol.bankTypes{timeIdx}
        case 'formation-local-single'
            [screenReports{timeIdx}, screens{timeIdx}] = ...
                runFormationModeH3OpenedReturnScreen( ...
                    protocol.presetName, protocol.seed, ...
                    currentTime, screenOptions);
        case 'formation-conservative-pair'
            [screenReports{timeIdx}, screens{timeIdx}] = ...
                runFormationPairH3OpenedReturnScreen( ...
                    protocol.presetName, protocol.seed, ...
                    currentTime, screenOptions);
        otherwise
            error('Unknown duration-probe bank type.');
    end
    audits{timeIdx} = strictAudit( ...
        screens{timeIdx}, protocol.actionNames{timeIdx});
end

durationGains = cellfun(@(item) item.oracleGainPercent, audits);
probe = struct();
probe.contractVersion = ...
    'formation-h3-duration-probe-result-v1';
probe.protocolId = protocol.id;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
probe.cacheProtocolId = protocol.cacheProtocolId;
probe.cacheGenerationGitCommit = ...
    protocol.cacheGenerationGitCommit;
probe.presetName = protocol.presetName;
probe.seed = protocol.seed;
probe.snapshotTimes = protocol.snapshotTimes;
probe.actionNames = protocol.actionNames;
probe.interventionDurationSteps = ...
    protocol.interventionDurationSteps;
probe.oneStepStrictGainsPercent = ...
    protocol.oneStepStrictGainsPercent;
probe.durationStrictOracleGainsPercent = durationGains;
probe.durationMinusOneStepGainPoints = ...
    durationGains - protocol.oneStepStrictGainsPercent;
probe.screens = screens;
probe.screenReports = screenReports;
probe.audits = audits;
probe.positiveDurationStateCount = nnz(durationGains > 1e-12);
probe.strongDurationStateCount = nnz(durationGains >= 3 - 1e-12);
probe.meanDurationStrictOracleGainPercent = mean(durationGains);
probe.meanOneStepStrictOracleGainPercent = ...
    mean(protocol.oneStepStrictGainsPercent);
probe.actionSelectionUsesTruth = true;
probe.actionSelectionUsesFutureMeasurements = true;
probe.runtimePolicyUsesTruth = false;
probe.openedTrainingMechanismProbeOnly = true;
probe.finalModelTrainingAuthorized = false;
probe.validationClaimAllowed = false;
probe.evidenceBoundary = protocol.evidenceBoundary;
probe.probePath = probePath;
probe.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', probePath, 'probe');
writeReport(reportPath, probe);
fprintf('Formation H=3 duration probe: %s\n', probePath);
end

function validateCache(currentTime, protocol)
cachePath = fullfile(protocol.cacheRoot, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', ...
    strrep(protocol.presetName, '-', '_'), ...
    protocol.seed, currentTime));
if exist(cachePath, 'file') ~= 2
    error('Duration-probe cache is missing: %s', cachePath);
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Duration-probe cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
required = { ...
    'protocolId', 'generationGitCommit', 'presetName', ...
    'seed', 'snapshotTimes', 'policyTruthUsed', ...
    'policyFutureOutcomeUsed', 'validationClaimAllowed'};
if ~all(isfield(bundle, required)) || ...
        ~strcmp(bundle.protocolId, protocol.cacheProtocolId) || ...
        ~strcmp(bundle.generationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~strcmp(bundle.presetName, protocol.presetName) || ...
        bundle.seed ~= protocol.seed || ...
        ~isequal(bundle.snapshotTimes, currentTime) || ...
        bundle.policyTruthUsed || bundle.policyFutureOutcomeUsed || ...
        bundle.validationClaimAllowed
    error('Duration-probe cache provenance mismatch.');
end
end

function audit = strictAudit(screen, expectedActionName)
if numel(screen.records) ~= 2 || ...
        numel(screen.outcomes) ~= 2 || ...
        screen.referenceSubsetIndex ~= 1 || ...
        screen.interventionDurationSteps ~= 3 || ...
        ~strcmp(screen.records(1).actionName, 'reference') || ...
        ~strcmp(screen.records(2).actionName, expectedActionName) || ...
        screen.outcomes(1).interventionDurationSteps ~= 1 || ...
        screen.outcomes(2).interventionDurationSteps ~= 3 || ...
        ~screen.outcomes(1).interventionActionsExact || ...
        ~screen.outcomes(2).interventionActionsExact
    error('Formation H=3 duration screen is invalid.');
end
reference = screen.outcomes(1);
candidate = screen.outcomes(2);
record = screen.records(2);
targets = [ ...
    record.meanGainPercent, ...
    record.minimumFormationGainPercent, ...
    record.worstGainPercent, ...
    record.consensusGainPercent, ...
    record.attemptedByteSavingPercent, ...
    100 * (reference.deliveredBytes - candidate.deliveredBytes) / ...
        max(reference.deliveredBytes, eps)];
candidateFeasible = all(targets >= -1e-12);
if candidateFeasible && targets(1) > 1e-12
    oracleActionName = expectedActionName;
    oracleGain = targets(1);
    oracleTargets = targets;
else
    oracleActionName = 'reference';
    oracleGain = 0;
    oracleTargets = zeros(1, 6);
end
audit = struct( ...
    'contractVersion', ...
        'formation-h3-duration-strict-audit-v1', ...
    'currentTime', screen.currentTime, ...
    'actionName', expectedActionName, ...
    'candidateTargets', targets, ...
    'candidateDeploymentFeasible', candidateFeasible, ...
    'oracleActionName', oracleActionName, ...
    'oracleGainPercent', oracleGain, ...
    'oracleTargets', oracleTargets);
end

function writeReport(path, probe)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 duration-probe report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 duration probe\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    probe.contractVersion, probe.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    probe.generationGitCommit);
fprintf(fid, '- Cache protocol / generation commit: `%s / %s`\n', ...
    probe.cacheProtocolId, probe.cacheGenerationGitCommit);
fprintf(fid, '- Preset / seed / times: `%s / %d / %s`\n', ...
    probe.presetName, probe.seed, mat2str(probe.snapshotTimes));
fprintf(fid, '- Candidate duration: `%d` steps\n', ...
    probe.interventionDurationSteps);
fprintf(fid, '- One-step strict gains: `%s`\n', ...
    mat2str(probe.oneStepStrictGainsPercent, 6));
fprintf(fid, '- Duration strict gains: `%s`\n', ...
    mat2str(probe.durationStrictOracleGainsPercent, 6));
fprintf(fid, '- Duration minus one-step: `%s` points\n\n', ...
    mat2str(probe.durationMinusOneStepGainPoints, 6));
fprintf(fid, '| Time | Action | One-step | Duration candidate targets | Duration strict |\n');
fprintf(fid, '|--:|:--|--:|:--|:--|\n');
for idx = 1:numel(probe.audits)
    audit = probe.audits{idx};
    fprintf(fid, '| %d | %s | %+.3f%% | `%s` | %s (%+.3f%%) |\n', ...
        audit.currentTime, audit.actionName, ...
        probe.oneStepStrictGainsPercent(idx), ...
        mat2str(audit.candidateTargets, 6), ...
        audit.oracleActionName, audit.oracleGainPercent);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    probe.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
