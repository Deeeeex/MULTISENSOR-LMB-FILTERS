function [reportPath, result] = runMissingPacketSelfWeightV278FullEpisode(options)
% RUNMISSINGPACKETSELFWEIGHTV278FULLEPISODE One controlled receiver ablation.
% Reuses a complete V242 result. Only missing-packet weight handling changes.
if nargin<1, options=struct(); end
referencePath=options.referenceResultPath;
loaded=load(referencePath,'result'); reference=loaded.result;
assert(isfield(reference,'candidate') && ...
    isfield(reference.candidate,'fullHorizonPositionEospa'));
assert(strcmp(reference.presetName, ...
    'x36-formation-fov-temporal-coupled-formation-braid'));
assert(reference.seed==1301);
gitState=resolveResearchGitState();
assert(~gitState.trackedWorktreeDirty && isempty(gitState.untrackedSourceFiles));
root=fullfile('RUN','GA','dynamic_topology','evidence','tracking_aligned_v278', ...
    'x36_missing_packet_self_seed1301');
if exist(root,'dir')~=7, mkdir(root); end
reportPath=fullfile(root,'MISSING_PACKET_SELF_WEIGHT_V278.md');
matPath=fullfile(root,'MISSING_PACKET_SELF_WEIGHT_V278.mat');
if exist(matPath,'file')==2
    loaded=load(matPath,'result'); result=loaded.result;
    assert(strcmp(result.generationGitCommit,gitState.commit));
    fprintf('V278 already complete: %s\n',reportPath); return;
end
inputs=generateDynamicTopologyScenarioInputs(reference.presetName,reference.seed);
model=removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
config=buildCausalMinimumFormationBackboneV242Config(inputs.config);
config.missingNeighborWeightMode='self';
context=buildCausalMinimumFormationBackboneV242ExecutionContext( ...
    reference.presetName,reference.seed,inputs.config.simulationLength);
protocol=getCausalMinimumFormationBackboneV242Protocol();
rng(reference.seed+protocol.filterSeedOffset,'twister');
fprintf('V278 X36 seed1301: same V242 route; missing packets return weight to self.\n');
started=tic;
[estimates,diagnostics]=runEventTriggeredDistributedLmbFilter( ...
    model,inputs.measurements,inputs.sensorTrajectories,inputs.neighborMap, ...
    inputs.commConfig,config,context);
groups=unique(inputs.config.sensorGroupIds,'stable');
representatives=zeros(1,numel(groups));
for k=1:numel(groups)
    representatives(k)=find(inputs.config.sensorGroupIds==groups(k),1);
end
window=struct('activationStartTime',inputs.config.focusWindow(1), ...
    'activationEndTime',inputs.config.focusWindow(end));
candidate=summarizeRepeatedMultiGatewayFullEpisodeArm( ...
    'v278-missing-packet-self-weight',estimates,diagnostics, ...
    inputs.groundTruthRfs,inputs.config,representatives,window,toc(started));
result=struct('contractVersion','missing-packet-self-weight-v278-v1', ...
    'generationGitCommit',gitState.commit,'referenceResultPath',referencePath, ...
    'referenceGenerationGitCommit',reference.generationGitCommit, ...
    'presetName',reference.presetName,'seed',reference.seed, ...
    'completedAt',datestr(now,31),'missingNeighborWeightMode','self', ...
    'reference',reference.candidate,'fixedTree',reference.referenceFixedTree, ...
    'candidate',candidate,'developmentEvidenceOnly',true, ...
    'validationClaimAllowed',false);
result.overReference=compare(candidate,result.reference);
result.overFixed=compare(candidate,result.fixedTree);
g=result.overReference;
result.promisingForM24=g.eospa>0 && g.consistency>=0 && ...
    g.cardinalityDelta<=0 && g.rmse>=-1 && ...
    result.overFixed.bytes>=5 && g.minimumFormationEospa>=-1;
save('-mat7-binary',matPath,'result');
fid=fopen(reportPath,'w'); assert(fid>=0);
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'# V278 missing-packet self-weight ablation\n\n');
fprintf(fid,'Source `%s`; reference `%s`; X36 seed1301, 160 steps.\n\n', ...
    gitState.commit,reference.generationGitCommit);
fprintf(fid,'| Arm | E-OSPA | Conditional RMSE | Focus consistency | Cardinality error | Attempted bytes |\n');
fprintf(fid,'|:--|--:|--:|--:|--:|--:|\n');
writeArm(fid,'Fixed tree',result.fixedTree);
writeArm(fid,'V242 packet renormalization',result.reference);
writeArm(fid,'V278 packet self-weight fallback',candidate);
fprintf(fid,'\n| Comparison | E gain | RMSE gain | Consistency gain | Byte saving | Cardinality error delta | Min formation E / RMSE gain |\n');
fprintf(fid,'|:--|--:|--:|--:|--:|--:|:--|\n');
writeGain(fid,'V278 over V242',result.overReference);
writeGain(fid,'V278 over fixed',result.overFixed);
fprintf(fid,'\nPromising for the paired M24 follow-up: `%d`.\n',result.promisingForM24);
fprintf(fid,['\nOnly the missing-neighbor weight rule changes; measurements, filter RNG, ', ...
    'planned topology, directed delivery uniforms and powered-GM settings are shared. ', ...
    'The rule applies to unavailable or empty neighbor inputs; label-level absence ', ...
    'handling stays unchanged. It costs no additional messages or metadata, but ', ...
    'recursive posterior sizes can change attempted payload bytes. This is a ', ...
    'single-seed development ablation, not multiseed or cross-scale validation.\n']);
fprintf('V278 complete: E %.3f; RMSE %.3f; consistency %.3f; card %.3f; bytes %.0f; M24 follow-up=%d\n', ...
    candidate.fullHorizonPositionEospa,candidate.fullHorizonPositionRmse, ...
    candidate.focusInterFormationPositionOspa,candidate.meanAbsoluteCardinalityError, ...
    candidate.attemptedPayloadBytes,result.promisingForM24);
end

function g=compare(a,b)
gain=@(x,y)100*(y-x)./max(abs(y),eps);
g=struct('eospa',gain(a.fullHorizonPositionEospa,b.fullHorizonPositionEospa), ...
    'rmse',gain(a.fullHorizonPositionRmse,b.fullHorizonPositionRmse), ...
    'consistency',gain(a.focusInterFormationPositionOspa,b.focusInterFormationPositionOspa), ...
    'bytes',gain(a.attemptedPayloadBytes,b.attemptedPayloadBytes), ...
    'cardinalityDelta',a.meanAbsoluteCardinalityError-b.meanAbsoluteCardinalityError, ...
    'minimumFormationEospa',min(gain(a.perFormationPositionEospa,b.perFormationPositionEospa)), ...
    'minimumFormationRmse',min(gain(a.perFormationPositionRmse,b.perFormationPositionRmse)));
end

function writeArm(fid,name,a)
fprintf(fid,'| %s | %.3f | %.3f | %.3f | %.3f | %.0f |\n',name, ...
    a.fullHorizonPositionEospa,a.fullHorizonPositionRmse, ...
    a.focusInterFormationPositionOspa,a.meanAbsoluteCardinalityError,a.attemptedPayloadBytes);
end

function writeGain(fid,name,g)
fprintf(fid,'| %s | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.6f | %+.3f%% / %+.3f%% |\n', ...
    name,g.eospa,g.rmse,g.consistency,g.bytes,g.cardinalityDelta, ...
    g.minimumFormationEospa,g.minimumFormationRmse);
end
