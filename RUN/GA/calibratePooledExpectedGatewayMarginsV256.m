function [reportPath, summary] = ...
        calibratePooledExpectedGatewayMarginsV256(options)
% CALIBRATEPOOLEDEXPECTEDGATEWAYMARGINSV256 Freeze empirical lower bounds.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getPooledExpectedGatewayV256Protocol();
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
modelPath = absolutePath(getField(options, 'modelSelectionPath', ...
    fullfile(repoRoot, protocol.outputRoot, 'ridge_model_selection', ...
        'V256_POOLED_EXPECTED_GATEWAY_RIDGE.mat')), repoRoot);
datasetPath = absolutePath(getField(options, 'calibrationDatasetPath', ...
    fullfile(repoRoot, protocol.outputRoot, 'calibration_dataset', ...
        'POOLED_EXPECTED_GATEWAY_V256_CALIBRATION_DATASET.mat')), ...
    repoRoot);
if exist(modelPath, 'file') ~= 2 || exist(datasetPath, 'file') ~= 2
    error('PooledExpectedGatewayV256:MissingCalibrationInput', ...
        'The frozen model selection or calibration dataset is unavailable.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('PooledExpectedGatewayV256:DirtyCalibrationSource', ...
        'Official V256 calibration requires clean source.');
end

modelEnvelope = load(modelPath, 'summary');
datasetEnvelope = load(datasetPath, 'dataset');
if ~isfield(modelEnvelope, 'summary') || ...
        ~isfield(datasetEnvelope, 'dataset')
    error('PooledExpectedGatewayV256:CalibrationEnvelope', ...
        'A V256 calibration input lacks its registered envelope.');
end
modelSelection = modelEnvelope.summary;
dataset = datasetEnvelope.dataset;
validateModelSelection(modelSelection, protocol);
validateCalibrationDataset(dataset, protocol, modelSelection.model);
model = modelSelection.model;

tracking = protocol.modelSelectionOutcomeIndices;
seedCount = numel(protocol.calibrationSeeds);
outcomeCount = numel(protocol.outcomeNames);
withinSeedMargins = zeros(seedCount, outcomeCount);
windowMaximumResiduals = cell(1, seedCount);
supportedWindowCount = zeros(1, seedCount);
for seedIdx = 1:seedCount
    seed = protocol.calibrationSeeds(seedIdx);
    seedRecords = dataset.records(cellfun( ...
        @(value) value.seed == seed, dataset.records));
    maxima = zeros(0, outcomeCount);
    for recordIdx = 1:numel(seedRecords)
        record = seedRecords{recordIdx};
        feasible = logical(reshape( ...
            record.communicationProjection.candidateFeasible, [], 1));
        if ~any(feasible)
            continue;
        end
        prediction = predictPooledExpectedGatewayRidgeV256( ...
            model, record.features);
        residual = prediction - record.targets;
        row = zeros(1, outcomeCount);
        row(tracking) = max(residual(feasible, tracking), [], 1);
        maxima(end + 1, :) = row; %#ok<AGROW>
    end
    if isempty(maxima)
        error('PooledExpectedGatewayV256:CalibrationSupport', ...
            'A calibration seed has no communication-feasible window.');
    end
    supportedWindowCount(seedIdx) = size(maxima, 1);
    windowMaximumResiduals{seedIdx} = maxima;
    for outcomeIdx = tracking
        withinSeedMargins(seedIdx, outcomeIdx) = nearestRankQuantile( ...
            maxima(:, outcomeIdx), ...
            protocol.calibrationWithinSeedQuantile);
    end
end

margins = zeros(1, outcomeCount);
for outcomeIdx = tracking
    margins(outcomeIdx) = max( ...
        protocol.calibrationMarginFloorPercent, ...
        nearestRankQuantile(withinSeedMargins(:, outcomeIdx), ...
            protocol.calibrationAcrossSeedQuantile));
end
[decisions, safeCountBySeed, selectedCount, unsafeCount] = ...
    evaluateCalibrationRecords(dataset.records, model, margins, protocol);
calibrationPassed = ...
    all(safeCountBySeed >= ...
        protocol.minimumCalibrationSafeSelectionCountPerSeed) && ...
    unsafeCount <= protocol.maximumCalibrationUnsafeSelectionCount;

calibratedModel = model;
calibratedModel.contractVersion = ...
    'pooled-expected-gateway-v256-calibrated-model-v1';
calibratedModel.oneSidedMarginByOutcome = margins;
calibratedModel.calibrationSeeds = protocol.calibrationSeeds;
calibratedModel.calibrationCandidateAggregation = ...
    protocol.calibrationCandidateAggregation;
calibratedModel.calibrationQuantileRule = ...
    protocol.calibrationQuantileRule;
calibratedModel.formalFiniteSampleCoverageClaimAllowed = false;

summary = struct();
summary.contractVersion = ...
    'pooled-expected-gateway-v256-calibration-summary-v1';
summary.protocol = protocol;
summary.calibrationGitCommit = gitState.commit;
summary.modelSelectionPath = modelPath;
summary.modelSelectionGitCommit = modelSelection.analysisGitCommit;
summary.calibrationDatasetPath = datasetPath;
summary.calibrationDatasetGitCommit = dataset.assemblyGitCommit;
summary.calibrationSeeds = protocol.calibrationSeeds;
summary.supportedWindowCountBySeed = supportedWindowCount;
summary.windowMaximumResidualsBySeed = windowMaximumResiduals;
summary.withinSeedMarginByOutcome = withinSeedMargins;
summary.oneSidedMarginByOutcome = margins;
summary.decisions = decisions;
summary.selectedActionCount = selectedCount;
summary.safeSelectionCountBySeed = safeCountBySeed;
summary.unsafeSelectionCount = unsafeCount;
summary.calibrationPassed = calibrationPassed;
summary.calibratedModel = calibratedModel;
summary.developmentHoldoutAuthorized = calibrationPassed;
summary.completeEpisodeAuthorized = false;
summary.gnnAuthorized = false;
summary.x36Authorized = false;
summary.validationClaimAllowed = false;
summary.developmentEvidenceOnly = true;
if calibrationPassed
    summary.nextDecision = ...
        'freeze-calibrated-selector-and-open-seed-1306-once';
else
    summary.nextDecision = ...
        'stop-v256-before-development-holdout';
end
summary.completedAt = datestr(now, 31);
summary.evidenceBoundary = protocol.evidenceBoundary;

outputRoot = absolutePath(getField(options, 'outputRoot', ...
    fullfile(repoRoot, protocol.outputRoot, 'calibration')), repoRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
reportPath = fullfile(outputRoot, ...
    'V256_POOLED_EXPECTED_GATEWAY_CALIBRATION.md');
matPath = fullfile(outputRoot, ...
    'V256_POOLED_EXPECTED_GATEWAY_CALIBRATION.mat');
summary.reportPath = reportPath;
summary.matPath = matPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary);
fprintf(['V256 calibration: selected %d; safe by seed %s; ', ...
    'unsafe %d; holdout=%d\n'], selectedCount, ...
    mat2str(safeCountBySeed), unsafeCount, ...
    summary.developmentHoldoutAuthorized);
fprintf('V256 calibration report: %s\n', reportPath);
end

function validateModelSelection(summary, protocol)
required = {'contractVersion', 'protocol', 'analysisGitCommit', ...
    'calibrationAuthorized', 'model'};
valid = isstruct(summary) && isscalar(summary) && ...
    all(isfield(summary, required)) && ...
    strcmp(summary.contractVersion, ...
        'pooled-expected-gateway-v256-model-selection-summary-v1') && ...
    strcmp(summary.protocol.id, protocol.id) && ...
    logical(summary.calibrationAuthorized) && ...
    strcmp(summary.model.protocolId, protocol.id);
if ~valid
    error('PooledExpectedGatewayV256:CalibrationNotAuthorized', ...
        'The frozen ridge result does not authorize calibration.');
end
end

function validateCalibrationDataset(dataset, protocol, model)
required = {'contractVersion', 'datasetRole', 'protocol', 'seeds', ...
    'featureNames', 'outcomeNames', 'records', 'recordCount', ...
    'actionRowsPerWindow', 'communicationAdmissionMode'};
valid = isstruct(dataset) && isscalar(dataset) && ...
    all(isfield(dataset, required)) && ...
    strcmp(dataset.contractVersion, ...
        'pooled-expected-gateway-v256-dataset-v3') && ...
    strcmp(dataset.datasetRole, 'calibration') && ...
    strcmp(dataset.protocol.id, protocol.id) && ...
    isequal(sort(dataset.seeds), sort(protocol.calibrationSeeds)) && ...
    dataset.recordCount == numel(protocol.calibrationSeeds) * ...
        numel(protocol.anchorTimes) && ...
    numel(dataset.records) == dataset.recordCount && ...
    isequal(dataset.featureNames, model.featureNames) && ...
    isequal(dataset.outcomeNames, model.outcomeNames) && ...
    strcmp(dataset.communicationAdmissionMode, ...
        protocol.communicationAdmissionMode) && ...
    all(cellfun(@validRecord, dataset.records));
if ~valid
    error('PooledExpectedGatewayV256:InvalidCalibrationDataset', ...
        'The V256 calibration dataset violates its frozen role.');
end
end

function valid = validRecord(record)
valid = isstruct(record) && isscalar(record) && ...
    isfield(record, 'features') && isfield(record, 'targets') && ...
    isfield(record, 'seed') && isfield(record, 'anchorTime') && ...
    isfield(record, 'candidateIndices') && ...
    isfield(record, 'communicationProjection') && ...
    size(record.features, 1) == size(record.targets, 1) && ...
    numel(record.candidateIndices) == size(record.features, 1) && ...
    isstruct(record.communicationProjection) && ...
    isscalar(record.communicationProjection) && ...
    isfield(record.communicationProjection, 'contractVersion') && ...
    strcmp(record.communicationProjection.contractVersion, ...
        'pooled-expected-gateway-v256-communication-projection-v1') && ...
    isfield(record.communicationProjection, ...
        'candidateRetainedDenseSavingFraction') && ...
    numel(record.communicationProjection.candidateFeasible) == ...
        size(record.features, 1) && ...
    numel(record.communicationProjection. ...
        candidateRetainedDenseSavingFraction) == ...
        size(record.features, 1) && ...
    all(isfinite(record.communicationProjection. ...
        candidateRetainedDenseSavingFraction(:)));
end

function [decisions, safeCountBySeed, selectedCount, unsafeCount] = ...
        evaluateCalibrationRecords(records, model, margins, protocol)
decisions = repmat(emptyDecision(), 1, numel(records));
safeCountBySeed = zeros(1, numel(protocol.calibrationSeeds));
selectedCount = 0;
unsafeCount = 0;
for recordIdx = 1:numel(records)
    record = records{recordIdx};
    prediction = predictPooledExpectedGatewayRidgeV256( ...
        model, record.features);
    lower = bsxfun(@minus, prediction, margins);
    communicationFeasible = logical(reshape( ...
        record.communicationProjection.candidateFeasible, [], 1));
    admissible = communicationFeasible & ...
        lower(:, 1) > protocol.minimumExpectedCoreGainPercent & ...
        lower(:, 2) > protocol.minimumExpectedCoreGainPercent & ...
        lower(:, 3) > protocol.minimumExpectedCoreGainPercent & ...
        lower(:, 5) >= -protocol.maximumFormationRegressionPercent & ...
        lower(:, 6) >= -protocol.maximumFormationRegressionPercent & ...
        lower(:, 7) >= ...
            protocol.receiverEospaMinimumLowerBoundPercent & ...
        lower(:, 8) > ...
            protocol.receiverRmseActivationLowerBoundPercent;
    score = lower(:, 8);
    score(~admissible) = -Inf;
    [bestScore, localIdx] = max(score);
    decision = emptyDecision();
    decision.seed = record.seed;
    decision.anchorTime = record.anchorTime;
    if isfinite(bestScore)
        outcome = record.targets(localIdx, :);
        safe = realizedSafe(outcome, protocol);
        decision.selected = true;
        decision.selectedLocalActionIndex = localIdx;
        decision.selectedCandidateIndex = ...
            record.candidateIndices(localIdx);
        decision.lowerReceiverRmseGainPercent = bestScore;
        decision.realizedOutcomes = outcome;
        decision.realizedSafe = safe;
        projection = record.communicationProjection;
        decision.retainedDenseSavingFraction = ...
            projection.candidateRetainedDenseSavingFraction(localIdx);
        selectedCount = selectedCount + 1;
        unsafeCount = unsafeCount + ~safe;
        seedIdx = find(protocol.calibrationSeeds == record.seed, 1);
        safeCountBySeed(seedIdx) = safeCountBySeed(seedIdx) + safe;
    end
    decisions(recordIdx) = decision;
end
end

function safe = realizedSafe(outcome, protocol)
safe = outcome(1) > protocol.minimumExpectedCoreGainPercent && ...
    outcome(2) > protocol.minimumExpectedCoreGainPercent && ...
    outcome(3) > protocol.minimumExpectedCoreGainPercent && ...
    outcome(5) >= -protocol.maximumFormationRegressionPercent && ...
    outcome(6) >= -protocol.maximumFormationRegressionPercent && ...
    outcome(7) >= protocol.receiverEospaMinimumLowerBoundPercent && ...
    outcome(8) > protocol.receiverRmseActivationLowerBoundPercent;
end

function value = nearestRankQuantile(values, probability)
values = sort(reshape(values, [], 1));
if isempty(values) || any(~isfinite(values)) || ...
        probability <= 0 || probability >= 1
    error('PooledExpectedGatewayV256:InvalidCalibrationQuantile', ...
        'The V256 nearest-rank quantile input is malformed.');
end
index = min(numel(values), max(1, ceil(probability * numel(values))));
value = values(index);
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('PooledExpectedGatewayV256:CalibrationReportOpen', ...
        'Could not write the V256 calibration report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V256 pooled expected gateway calibration\n\n');
fprintf(fid, '- Calibration commit: `%s`\n', ...
    summary.calibrationGitCommit);
fprintf(fid, '- Calibration seeds: `%s`\n', ...
    mat2str(summary.calibrationSeeds));
fprintf(fid, '- Supported windows by seed: `%s`\n', ...
    mat2str(summary.supportedWindowCountBySeed));
fprintf(fid, '- Selected actions: `%d/%d`\n', ...
    summary.selectedActionCount, numel(summary.decisions));
fprintf(fid, '- Realized-safe selections by seed: `%s`\n', ...
    mat2str(summary.safeSelectionCountBySeed));
fprintf(fid, '- Realized-unsafe selections: `%d`\n', ...
    summary.unsafeSelectionCount);
fprintf(fid, '- Development holdout authorized: `%d`\n', ...
    summary.developmentHoldoutAuthorized);
fprintf(fid, '- Next decision: `%s`\n\n', summary.nextDecision);
fprintf(fid, '| Outcome | Seed 1 margin | Seed 2 margin | Final margin |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
for outcomeIdx = summary.protocol.modelSelectionOutcomeIndices
    fprintf(fid, '| %s | %+.4f | %+.4f | %+.4f |\n', ...
        summary.protocol.outcomeNames{outcomeIdx}, ...
        summary.withinSeedMarginByOutcome(1, outcomeIdx), ...
        summary.withinSeedMarginByOutcome(2, outcomeIdx), ...
        summary.oneSidedMarginByOutcome(outcomeIdx));
end
fprintf(fid, ['\n| Seed | Anchor | Selected | Candidate | ', ...
    'Lower receiver RMSE | Realized receiver RMSE | Safe |\n']);
fprintf(fid, '|--:|--:|:--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(summary.decisions)
    row = summary.decisions(idx);
    fprintf(fid, '| %d | %d | %d | %d | %+.4f | %+.4f | %d |\n', ...
        row.seed, row.anchorTime, row.selected, ...
        row.selectedCandidateIndex, ...
        row.lowerReceiverRmseGainPercent, ...
        row.realizedOutcomes(8), row.realizedSafe);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', summary.evidenceBoundary);
end

function value = emptyDecision()
value = struct('seed', 0, 'anchorTime', 0, 'selected', false, ...
    'selectedLocalActionIndex', 0, 'selectedCandidateIndex', 0, ...
    'lowerReceiverRmseGainPercent', 0, ...
    'realizedOutcomes', zeros(1, 8), 'realizedSafe', false, ...
    'retainedDenseSavingFraction', 1);
end

function path = absolutePath(path, repoRoot)
path = char(path);
if isempty(path) || ~(path(1) == '/' || ...
        ~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once')))
    path = fullfile(repoRoot, path);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
