function reportText = renderFusionSufficientEvidenceReport( ...
    summaryPath, csvPath, summaryHash, csvHash, rows, aggregate, config)
% RENDERFUSIONSUFFICIENTEVIDENCEREPORT Canonical deterministic Markdown.

parts = {};
parts{end+1} = sprintf( ...
    '# Fusion-Sufficient Moment Exchange Evidence\n\n');
if config.testOnly
    parts{end+1} = sprintf([ ...
        '> **TEST-ONLY ARTIFACT:** isolated synthetic schema; ', ...
        'not admissible as paper evidence.\n\n']);
end
parts{end+1} = sprintf('- Evidence schema: `%s`\n', ...
    config.evidenceSchema);
parts{end+1} = sprintf('- Git commit: `%s`\n', config.gitCommit);
parts{end+1} = sprintf('- Immutable batch identity: `%s`\n', ...
    config.batchIdentity);
parts{end+1} = sprintf('- Wire schema version: `%d`\n', ...
    config.wireSchemaVersion);
parts{end+1} = sprintf([ ...
    '- Execution provenance (runtime only; not a paper contribution): ', ...
    '`%s`, Octave `%s`, fixed `maxWorkers=%d`.\n'], ...
    config.executionProtocol, config.octaveVersion, config.maxWorkers);
parts{end+1} = sprintf('- Frozen config SHA-256: `%s`\n', ...
    config.configSha256);
parts{end+1} = sprintf('- Required-source manifest SHA-256: `%s`\n', ...
    config.requiredSourcesSha256);
parts{end+1} = sprintf('- Trials and seeds: N=%d, `%d:%d`\n', ...
    config.numberOfTrials, config.firstSeed, config.lastSeed);
parts{end+1} = sprintf('- Arms: `%s` vs. `%s`\n', ...
    config.armSelection{1}, config.armSelection{2});
parts{end+1} = sprintf('- Changed variable: %s.\n', ...
    config.changedVariable);
parts{end+1} = sprintf('- Byte boundary: %s\n', config.byteSemantics);
parts{end+1} = sprintf('- MAT artifact: `%s`\n', summaryPath);
parts{end+1} = sprintf('- MAT SHA-256: `%s`\n', summaryHash);
parts{end+1} = sprintf('- CSV artifact: `%s`\n', csvPath);
parts{end+1} = sprintf('- CSV SHA-256: `%s`\n\n', csvHash);

parts{end+1} = sprintf('## Pre-registered primary result\n\n');
parts{end+1} = sprintf([ ...
    'The per-seed attempted-byte reduction averages ', ...
    '**%.6f%%** (min/median/max %.6f/%.6f/%.6f%%). ', ...
    'The paired percentile-bootstrap 95%% interval is ', ...
    '[%.6f, %.6f]%% (seed %d, %d resamples).\n\n'], ...
    aggregate.mean_attempted_reduction_percent, ...
    aggregate.min_attempted_reduction_percent, ...
    aggregate.median_attempted_reduction_percent, ...
    aggregate.max_attempted_reduction_percent, ...
    aggregate.bootstrap_ci_low_percent, ...
    aggregate.bootstrap_ci_high_percent, ...
    config.bootstrapSeed, config.bootstrapResamples);
parts{end+1} = sprintf([ ...
    'Attempted bytes (full/moment): %.0f / %.0f. ', ...
    'Delivered bytes (full/moment): %.0f / %.0f.\n\n'], ...
    aggregate.total_full_attempted_bytes, ...
    aggregate.total_moment_attempted_bytes, ...
    aggregate.total_full_delivered_bytes, ...
    aggregate.total_moment_delivered_bytes);

parts{end+1} = sprintf('## Equivalence audit\n\n');
parts{end+1} = sprintf([ ...
    'Compared labels: %.0f; compared snapshots: %.0f; ', ...
    'label-set mismatches: %.0f; missing labels: %.0f; ', ...
    'missing snapshots: %.0f.\n\n'], ...
    aggregate.total_comparison_count, aggregate.total_snapshot_count, ...
    aggregate.total_label_set_mismatch_count, ...
    aggregate.total_missing_label_count, ...
    aggregate.total_missing_snapshot_count);
parts{end+1} = sprintf([ ...
    'Maximum residuals `|delta r|`, `|delta mu|`, ', ...
    '`|delta Sigma|`: `%.17g`, `%.17g`, `%.17g`.\n\n'], ...
    aggregate.max_abs_r, aggregate.max_abs_mu, ...
    aggregate.max_abs_sigma);
parts{end+1} = sprintf([ ...
    'All exact: `%d`; attempted masks equal: `%d`; ', ...
    'delivered masks equal: `%d`.\n\n'], ...
    aggregate.all_exact_match, ...
    aggregate.all_attempted_masks_equal, ...
    aggregate.all_delivered_masks_equal);

parts{end+1} = sprintf('## Per-seed audit preview\n\n');
parts{end+1} = sprintf([ ...
    '| Seed | Attempted reduction (%%) | Max residual | Exact |\n']);
parts{end+1} = sprintf('|---:|---:|---:|:---:|\n');
for rowIdx = 1:size(rows, 1)
    parts{end+1} = sprintf('| %.0f | %.6f | %.17g | %d |\n', ...
        rows(rowIdx, 1), rows(rowIdx, 4), ...
        max(rows(rowIdx, 25:27)), rows(rowIdx, 28)); %#ok<AGROW>
end
parts{end+1} = sprintf( ...
    '\n## Regeneration\n\n```bash\n%s\n```\n\n', ...
    config.regenerationCommand);

parts{end+1} = sprintf( ...
    '<!-- FUSION_SUFFICIENT_EVIDENCE_MACHINE\n');
parts{end+1} = sprintf('evidence_schema=%s\n', config.evidenceSchema);
parts{end+1} = sprintf('test_only=%d\n', double(config.testOnly));
parts{end+1} = sprintf('git_commit=%s\n', config.gitCommit);
parts{end+1} = sprintf('batch_identity=%s\n', config.batchIdentity);
parts{end+1} = sprintf('artifact_stem=%s\n', config.artifactStem);
parts{end+1} = sprintf('wire_schema_version=%.17g\n', ...
    config.wireSchemaVersion);
parts{end+1} = sprintf('execution_protocol=%s\n', ...
    config.executionProtocol);
parts{end+1} = sprintf('octave_version=%s\n', config.octaveVersion);
parts{end+1} = sprintf('max_workers=%.17g\n', config.maxWorkers);
parts{end+1} = sprintf('config_sha256=%s\n', config.configSha256);
parts{end+1} = sprintf('required_sources_sha256=%s\n', ...
    config.requiredSourcesSha256);
parts{end+1} = sprintf('number_of_trials=%.17g\n', ...
    config.numberOfTrials);
parts{end+1} = sprintf('base_seed=%.17g\n', config.baseSeed);
parts{end+1} = sprintf('first_seed=%.17g\n', config.firstSeed);
parts{end+1} = sprintf('last_seed=%.17g\n', config.lastSeed);
parts{end+1} = sprintf('simulation_length=%.17g\n', ...
    config.simulationLength);
parts{end+1} = sprintf('bootstrap_seed=%.17g\n', ...
    config.bootstrapSeed);
parts{end+1} = sprintf('bootstrap_resamples=%.17g\n', ...
    config.bootstrapResamples);
parts{end+1} = sprintf('summary_sha256=%s\n', summaryHash);
parts{end+1} = sprintf('csv_sha256=%s\n', csvHash);
fields = sort(fieldnames(aggregate));
for fieldIdx = 1:numel(fields)
    parts{end+1} = sprintf('aggregate_%s=%.17g\n', ...
        fields{fieldIdx}, aggregate.(fields{fieldIdx})); %#ok<AGROW>
end
parts{end+1} = sprintf('-->\n');
reportText = [parts{:}];
end
