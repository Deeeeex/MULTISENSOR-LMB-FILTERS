function [reportPath, audit] = ...
    auditFormationConflictAwareMixingV28(options)
% AUDITFORMATIONCONFLICTAWAREMIXINGV28 Frozen primary-screen audit.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v28', 'conflict_aware_selective_mixing', ...
    't72', 'screen', ...
    ['FORMATION_CONFLICT_AWARE_MIXING_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_CONFLICT_AWARE_SELECTIVE_MIXING_V28_', ...
     'AUDIT_20260802.md']));
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V28Audit:MissingScreen', ...
        'Frozen v28 primary screen is unavailable.');
end
screen = loaded.screen;
assertScreenProvenance(screen);

records = screen.records;
outcomes = screen.outcomes;
referenceIdx = screen.referenceSubsetIndex;
referenceActionIdx = records(referenceIdx).actionIndex;
referenceNetworkRisk = ...
    screen.bank.networkDisagreementRisk(referenceActionIdx);
networkRiskChangePercent = 100 * ( ...
    screen.bank.networkDisagreementRisk([records.actionIndex]) - ...
        referenceNetworkRisk) / max(referenceNetworkRisk, eps);
meanGainPercent = [records.meanGainPercent];
consensusGainPercent = [records.consensusGainPercent];
terminalConsensusGainPercent = ...
    [records.terminalConsensusGainPercent];
worstGainPercent = [records.worstGainPercent];
minimumFormationGainPercent = ...
    [records.minimumFormationGainPercent];
attemptedByteSavingPercent = ...
    [records.attemptedByteSavingPercent];
meanCardinalityError = [outcomes.meanCardinalityError];
posteriorDisagreement = [outcomes.posteriorConsensus];
nonreference = true(1, numel(records));
nonreference(referenceIdx) = false;
jointDirectionImproved = nonreference & ...
    meanGainPercent > 0 & consensusGainPercent > 0 & ...
    meanCardinalityError < meanCardinalityError(referenceIdx);
networkRiskVsWindowConsensusCorrelation = pearsonCorrelation( ...
    networkRiskChangePercent(nonreference), ...
    consensusGainPercent(nonreference));

audit = struct();
audit.contractVersion = ...
    'formation-conflict-aware-selective-mixing-v28-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.returnTimes = screen.returnTimes;
audit.actionNames = {records.actionName};
audit.actionIndices = [records.actionIndex];
audit.networkRiskChangePercent = networkRiskChangePercent;
audit.meanGainPercent = meanGainPercent;
audit.consensusGainPercent = consensusGainPercent;
audit.terminalConsensusGainPercent = ...
    terminalConsensusGainPercent;
audit.worstGainPercent = worstGainPercent;
audit.minimumFormationGainPercent = ...
    minimumFormationGainPercent;
audit.attemptedByteSavingPercent = ...
    attemptedByteSavingPercent;
audit.meanCardinalityError = meanCardinalityError;
audit.posteriorDisagreement = posteriorDisagreement;
audit.jointDirectionImprovedMask = jointDirectionImproved;
audit.jointDirectionImprovedCount = ...
    nnz(jointDirectionImproved);
audit.bestMeanGainPercent = max(meanGainPercent(nonreference));
audit.bestConsensusGainPercent = ...
    max(consensusGainPercent(nonreference));
audit.strongCandidateCount = ...
    screen.strictStrongCandidateCount;
audit.networkRiskVsWindowConsensusCorrelation = ...
    networkRiskVsWindowConsensusCorrelation;
audit.truthUsedForActionConstruction = false;
audit.truthUsedForOutcomeScoring = true;
audit.futureOutcomeUsedForActionConstruction = false;
audit.newTrackingStateOpened = false;
audit.additionalM24Authorized = false;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This audit reuses only the frozen v28 primary M24 screen. It may ', ...
    'motivate a new action design but cannot relax the failed v28 gate, ', ...
    'authorize another opened state, or support validation.'];

writeReport(reportPath, audit, screen);
fprintf('V28 conflict-aware mixing audit: %s\n', reportPath);
end

function assertScreenProvenance(screen)
if ~strcmp(screen.contractVersion, ...
        'formation-conflict-aware-selective-mixing-v28-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            'bf641fec9f34f8a432daab4b91e259701fd2c7c2') || ...
        ~strcmp(screen.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(screen.presetName, 'm24-formation-fov') || ...
        screen.seed ~= 211 || screen.currentTime ~= 72 || ...
        ~isequal(screen.returnTimes, [72, 73, 74]) || ...
        ~screen.executedOnlyPosteriorSafeActions || ...
        screen.strictStrongCandidateCount ~= 0 || ...
        screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V28Audit:ProvenanceMismatch', ...
        'Frozen v28 screen provenance or gate decision changed.');
end
end

function correlation = pearsonCorrelation(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
left = left - mean(left);
right = right - mean(right);
denominator = sqrt(sum(left.^2) * sum(right.^2));
if denominator <= eps
    correlation = NaN;
else
    correlation = sum(left .* right) / denominator;
end
end

function writeReport(path, audit, screen)
fid = fopen(path, 'w');
if fid < 0
    error('V28Audit:WriteFailed', ...
        'Could not open v28 audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V28 conflict-aware selective-mixing audit\n\n');
fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    '**The v28 primary gate fails with `0/4` strong candidates.** ', ...
    'Do not open another M24 state, train a GNN, or run X36/X48 under ', ...
    'this protocol. The mechanism direction is retained, but persistent ', ...
    'single-edge damping is too weak to meet the paper-level target.\n\n']);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime);
fprintf(fid, '- Return times: `%s`\n', mat2str(audit.returnTimes));
fprintf(fid, '- New tracking state opened by audit: `0`\n\n');

fprintf(fid, [ ...
    '| Action | Predicted one-step disagreement change | Mean gain | ', ...
    'Worst gain | Min formation | Window consensus | Final consensus | ', ...
    'Mean card. error | Byte saving | Strong |\n']);
fprintf(fid, [ ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for recordIdx = 1:numel(audit.actionNames)
    fprintf(fid, [ ...
        '| `%s` | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %.6f | %+.3f%% | %d |\n'], ...
        audit.actionNames{recordIdx}, ...
        audit.networkRiskChangePercent(recordIdx), ...
        audit.meanGainPercent(recordIdx), ...
        audit.worstGainPercent(recordIdx), ...
        audit.minimumFormationGainPercent(recordIdx), ...
        audit.consensusGainPercent(recordIdx), ...
        audit.terminalConsensusGainPercent(recordIdx), ...
        audit.meanCardinalityError(recordIdx), ...
        audit.attemptedByteSavingPercent(recordIdx), ...
        screen.strictStrongMask(recordIdx));
end

fprintf(fid, '\n## What remains valid\n\n');
fprintf(fid, [ ...
    'Three of four nonreference actions improve mean tracking, window ', ...
    'consensus, terminal consensus, and mean cardinality error in the ', ...
    'same direction. The best mean gain is `%.3f%%`; the best window-', ...
    'consensus gain is `%.3f%%`. This supports selective conflict ', ...
    'attenuation as a mechanism, but the magnitude is below the frozen ', ...
    '2%% tracking threshold.\n\n'], ...
    audit.bestMeanGainPercent, audit.bestConsensusGainPercent);

fprintf(fid, '## Why the next action must change\n\n');
fprintf(fid, [ ...
    'The one-step disagreement guard predicts a risk increase for every ', ...
    'damping action, while three actions improve the realized H=3 ', ...
    'consensus. Across the four nonreference actions, predicted one-step ', ...
    'risk change versus realized window-consensus gain has Pearson ', ...
    '`r = %.6f`. This repeats the earlier warning: a current one-round ', ...
    'summary metric is not a recursive consensus certificate.\n\n'], ...
    audit.networkRiskVsWindowConsensusCorrelation);
fprintf(fid, [ ...
    'V29 should therefore test **one-step temporal suspension** of ', ...
    'reference cross-formation edges rather than persistent small weight ', ...
    'changes. Removing an incompatible payload can strengthen label ', ...
    'retention and directly save communication. The action returns to ', ...
    'the reference graph after one step, while rolling-B3—not one-step ', ...
    'strong connectivity—protects time-window information flow. Subset ', ...
    'actions can combine the three individually favorable formations ', ...
    'and may produce a material effect without adding messages. Label-', ...
    'retention, payload, physical, and rolling-connectivity constraints ', ...
    'remain hard; H-step consensus becomes a teacher/validation target ', ...
    'rather than a false analytic guarantee.\n\n']);

fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
