function [reportPath, result] = ...
        analyzeBudgetAdaptiveSourceOfferRecallV231(options)
% ANALYZEBUDGETADAPTIVESOURCEOFFERRECALLV231 Test byte-derived breadth.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBudgetAdaptiveSourceOfferProtocolV231();
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices)
    error('BudgetAdaptiveSourceOfferRecallV231:InvalidRequest', ...
        'A causal V220 bank and unique teacher rows are required.');
end

loaded = load(candidateBankPath, 'result');
bank = loaded.result;
required = {'contractVersion', 'presetName', 'seed', 'currentTime', ...
    'sourceScreenPath', 'referencePageBytes', ...
    'admissionNetSavingBytes', 'beneficiaryDetails', 'records'};
if ~isstruct(bank) || ~isscalar(bank) || ...
        any(~isfield(bank, required)) || ...
        ~strcmp(bank.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        getField(bank, 'truthUsedForCandidateFeatures', true) || ...
        getField(bank, 'futureInformationUsedForCandidateFeatures', true)
    error('BudgetAdaptiveSourceOfferRecallV231:BankContract', ...
        'The causal V220 candidate-bank contract is required.');
end
if isempty(recordIndices)
    selectedRows = 1:numel(bank.records);
else
    [present, selectedRows] = ismember( ...
        recordIndices, [bank.records.recordIndex]);
    if ~all(present)
        error('BudgetAdaptiveSourceOfferRecallV231:UnknownRecord', ...
            'A requested teacher row is absent from the bank.');
    end
end
teacherRows = bank.records(selectedRows);

screenLoaded = load(bank.sourceScreenPath, 'screen');
screen = screenLoaded.screen;
timeIndex = find(screen.returnTimes == bank.currentTime, 1);
if isempty(timeIndex) || ~screen.capturePosteriorSnapshotsEnabled || ...
        screen.referenceSubsetIndex < 1 || ...
        screen.referenceSubsetIndex > numel(screen.outcomes)
    error('BudgetAdaptiveSourceOfferRecallV231:SnapshotContract', ...
        'The same-state reference posterior snapshot is unavailable.');
end
reference = screen.outcomes(screen.referenceSubsetIndex);
posteriors = reference.localPosteriorSnapshotsByTime{timeIndex};
model = struct('xDimension', inferStateDimension(posteriors));

audits = repmat(emptyAudit(), 1, numel(teacherRows));
for auditIndex = 1:numel(teacherRows)
    teacher = teacherRows(auditIndex);
    sourceId = teacher.sourceId;
    receiverIds = reshape(teacher.candidate.receiverIds, 1, []);
    controlSourceIds = sourceIdsForFormation( ...
        bank, teacher.beneficiaryFormationId, receiverIds);
    bytePlan = planBudgetAdaptiveSourceOfferBreadthV231( ...
        controlSourceIds, teacher.payloadAttemptedBytes, ...
        bank.admissionNetSavingBytes, bank.referencePageBytes, struct());
    fullResult = rankBudgetAdaptiveSourceOffersV231( ...
        posteriors{sourceId}, posteriors(receiverIds), receiverIds, ...
        zeros(size(receiverIds)), 2 * ones(size(receiverIds)), ...
        model, bytePlan);
    teacherLabel = reshape(teacher.label, 2, 1);
    fullSelected = labelSelected(fullResult.selectedLabels, teacherLabel);
    singleSelected = false(1, numel(receiverIds));
    for receiverPosition = 1:numel(receiverIds)
        receiverId = receiverIds(receiverPosition);
        singleResult = rankBudgetAdaptiveSourceOffersV231( ...
            posteriors{sourceId}, {posteriors{receiverId}}, ...
            receiverId, 0, 2, model, bytePlan);
        singleSelected(receiverPosition) = labelSelected( ...
            singleResult.selectedLabels, teacherLabel);
    end
    audits(auditIndex) = struct( ...
        'recordIndex', teacher.recordIndex, ...
        'beneficiaryFormationId', teacher.beneficiaryFormationId, ...
        'sourceId', sourceId, 'label', teacherLabel, ...
        'receiverIds', receiverIds, ...
        'selectedLabels', fullResult.selectedLabels, ...
        'teacherSelected', fullSelected, ...
        'existenceRank', labelRank( ...
            fullResult.existenceRanking, teacherLabel), ...
        'spatialRank', labelRank( ...
            fullResult.spatialRanking, teacherLabel), ...
        'singleSensorTeacherSelected', singleSelected, ...
        'singleSensorRecallCount', nnz(singleSelected), ...
        'singleSensorRecallRate', mean(double(singleSelected)), ...
        'bytePlan', bytePlan);
end

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v231', 'budget_adaptive_source_offer_recall', ...
    sprintf('%s_seed%d_t%d', strrep(bank.presetName, '-', '_'), ...
        bank.seed, bank.currentTime))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
result = struct();
result.contractVersion = ...
    'budget-adaptive-source-offer-recall-v231-v1';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.presetName = bank.presetName;
result.seed = bank.seed;
result.currentTime = bank.currentTime;
result.bytePlans = {audits.bytePlan};
result.teacherAudits = audits;
result.teacherLabelCount = numel(audits);
result.recoveredTeacherLabelCount = nnz([audits.teacherSelected]);
result.teacherRecall = result.recoveredTeacherLabelCount / ...
    max(result.teacherLabelCount, 1);
result.allTeacherLabelsRecovered = ...
    result.recoveredTeacherLabelCount == result.teacherLabelCount;
result.minimumSingleSensorRecallRate = ...
    min([audits.singleSensorRecallRate]);
result.sameStateScreenPassed = ...
    result.allTeacherLabelsRecovered && ...
    all(cellfun(@(plan) all(plan.candidateFeasibleMask), ...
        result.bytePlans));
result.runtimeCachePersistenceAuthorized = ...
    result.sameStateScreenPassed;
result.actualRuntimeReceivedCacheUsed = false;
result.sameStateBeneficiaryPosteriorsUsedAsFreshCacheProxy = true;
result.truthUsedForRanking = false;
result.futureInformationUsedForRanking = false;
result.onlinePolicyImplemented = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'BUDGET_ADAPTIVE_SOURCE_OFFER_RECALL_V231.mat');
reportPath = fullfile(outputRoot, ...
    'BUDGET_ADAPTIVE_SOURCE_OFFER_RECALL_V231.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V231 budget-adaptive source-offer recall: %s\n', reportPath);
end

function ids = sourceIdsForFormation(bank, formationId, receiverIds)
match = find([bank.beneficiaryDetails.formationId] == formationId, 1);
if isempty(match) || ...
        ~isfield(bank.beneficiaryDetails(match), 'synopsisSensorIds')
    error('BudgetAdaptiveSourceOfferRecallV231:SourceSet', ...
        'The beneficiary common-source set is unavailable.');
end
participants = reshape( ...
    bank.beneficiaryDetails(match).synopsisSensorIds, 1, []);
ids = setdiff(participants, reshape(receiverIds, 1, []), 'stable');
if isempty(ids)
    error('BudgetAdaptiveSourceOfferRecallV231:SourceSet', ...
        'No remote source remains after removing beneficiary receivers.');
end
end

function rank = labelRank(labels, label)
match = find(all(labels == label, 1), 1);
if isempty(match)
    rank = inf;
else
    rank = match;
end
end

function present = labelSelected(labels, label)
present = ~isempty(labels) && any(all(labels == label, 1));
end

function dimension = inferStateDimension(posteriors)
dimension = 0;
for sensorIndex = 1:numel(posteriors)
    objects = posteriors{sensorIndex};
    for objectIndex = 1:numel(objects)
        if objects(objectIndex).numberOfGmComponents > 0 && ...
                ~isempty(objects(objectIndex).mu)
            dimension = numel(objects(objectIndex).mu{1});
            break;
        end
    end
    if dimension > 0
        break;
    end
end
if dimension < 2
    error('BudgetAdaptiveSourceOfferRecallV231:StateDimension', ...
        'A position-bearing Gaussian-mixture state is required.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BudgetAdaptiveSourceOfferRecallV231:WriteReport', ...
        'Could not write the V231 recall report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
p = result.bytePlans{1};
fprintf(fid, '# V231 budget-adaptive source-offer recall\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Sources / offers per source: `%d / %d`\n', ...
    p.sourceCount, p.offersPerSource);
fprintf(fid, '- Mode breadth: `%d existence + %d spatial`\n', ...
    p.existenceBreadthPerSource, p.spatialBreadthPerSource);
fprintf(fid, '- Control charge: `%d B`\n', p.controlAttemptedBytes);
payloadCharges = cellfun(@(plan) plan.candidatePayloadBytes(1), ...
    result.bytePlans);
netSavings = cellfun(@(plan) plan.certifiedNetSavingBytes(1), ...
    result.bytePlans);
fprintf(fid, '- Payload charges: `%s B`\n', numericText(payloadCharges));
fprintf(fid, '- Certified net savings: `%s B`\n', ...
    numericText(netSavings));
fprintf(fid, '- Teacher recall: `%d / %d = %.1f%%`\n', ...
    result.recoveredTeacherLabelCount, result.teacherLabelCount, ...
    100 * result.teacherRecall);
fprintf(fid, ['- Actual runtime received cache used: `%d` ', ...
    '(same-state proxy only)\n\n'], ...
    result.actualRuntimeReceivedCacheUsed);
fprintf(fid, ['| Row | Beneficiary | Source / label | ', ...
    'Rank E / spatial | Selected | Single-cache recall |\n']);
fprintf(fid, '|--:|--:|:--|:--|:--|:--|\n');
for audit = result.teacherAudits
    fprintf(fid, ['| %d | F%d | S%d / `[%d,%d]` | `%s / %s` | ', ...
        '`%d` | `%d/%d = %.1f%%` |\n'], ...
        audit.recordIndex, audit.beneficiaryFormationId, ...
        audit.sourceId, audit.label(1), audit.label(2), ...
        rankText(audit.existenceRank), rankText(audit.spatialRank), ...
        audit.teacherSelected, audit.singleSensorRecallCount, ...
        numel(audit.receiverIds), 100 * audit.singleSensorRecallRate);
end
fprintf(fid, '\n## Decision\n\n');
if result.sameStateScreenPassed
    fprintf(fid, ['The byte-derived proposal breadth recovers every ', ...
        'opened teacher row and preserves positive certified saving. ', ...
        'Persist and test the actual source-local runtime cache next; ', ...
        'do not train or claim tracking gain yet.\n']);
else
    fprintf(fid, ['The budget-derived proposal set does not recover every ', ...
        'teacher row with positive certified saving. Redesign before ', ...
        'runtime integration.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = numericText(values)
parts = arrayfun(@(x) sprintf('%.0f', x), ...
    reshape(values, 1, []), 'UniformOutput', false);
text = strjoin(parts, ', ');
end

function text = rankText(rank)
if isfinite(rank)
    text = sprintf('%d', rank);
else
    text = '-';
end
end

function value = emptyAudit()
value = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'receiverIds', zeros(1, 0), 'selectedLabels', zeros(2, 0), ...
    'teacherSelected', false, 'existenceRank', inf, ...
    'spatialRank', inf, ...
    'singleSensorTeacherSelected', false(1, 0), ...
    'singleSensorRecallCount', 0, 'singleSensorRecallRate', 0);
value.bytePlan = struct();
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
