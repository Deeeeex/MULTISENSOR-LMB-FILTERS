function assertInitialControl(control, stateIdx, protocol)
expectedDebt = ...
    protocol.expectedInitialDebtFractionByState{stateIdx};
if ~strcmp(control.contractVersion, ...
        'formation-staggered-recovery-control-v1') || ...
        ~strcmp(control.protocolId, ...
            'formation-staggered-recovery-v35-v1') || ...
        control.nodeCount ~= protocol.expectedNodeCount || ...
        control.formationCount ~= protocol.expectedFormationCount || ...
        ~isequal(control.selectedFormationIds, ...
            protocol. ...
                expectedInitialFormationIdsByState{stateIdx}) || ...
        control.referenceFallbackUsed || ...
        ~numericTraceMatches(control.baseControl. ...
            formationRetentionDebtFraction, expectedDebt, ...
            protocol.sourceMetricTolerance) || ...
        abs(control.referenceScore.networkRisk - ...
            protocol.expectedInitialReferenceRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.networkRisk - ...
            protocol.expectedInitialSelectedRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.retentionRisk - ...
            protocol.expectedInitialRetentionRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        control.messageSavingCount ~= ...
            protocol.expectedInitialMessageSavingCount(stateIdx) || ...
        ~control.selectedScore.safe || ...
        ~all(control.selectedRollingB3SensorPass) || ...
        ~all(control.selectedRollingB3FormationPass) || ...
        ~control.selectionUsesCurrentPosterior || ...
        ~control.selectionUsesCurrentLinkReliability || ...
        ~control.selectionUsesSelectedTopologyHistory || ...
        ~control.openedDevelopmentEvidenceOnly || ...
        control.validationClaimAllowed || ...
        control.truthUsed || control.futureOutcomeUsed
    error('V37Preflight:InitialControlDrift', ...
        'Initial v35 control drifted for X36 state %d.', stateIdx);
end
end

function actionIdx = findActionIndex(bank, formationIds)
matches = false(1, bank.actionCount);
for candidateIdx = 1:bank.actionCount
    matches(candidateIdx) = isequal(reshape( ...
        bank.actionSuspendedFormationIds{candidateIdx}, 1, []), ...
        reshape(formationIds, 1, []));
end
actionIdx = find(matches);
if numel(actionIdx) ~= 1
    error('V37Preflight:InitialActionDrift', ...
        'Initial formation subset does not map uniquely to the bank.');
end
end

function assertRuntimeReplay( ...
        replay, initialControl, stateIdx, protocol)
expectedSelected = protocol. ...
    expectedRuntimeSelectedFormationIdsByState{stateIdx};
expectedRequested = protocol. ...
    expectedRuntimeRequestedFormationIdsByState{stateIdx};
expectedReleased = protocol. ...
    expectedRuntimeReleasedFormationIdsByState{stateIdx};
expectedStaggered = protocol. ...
    expectedRuntimeStaggeredReleaseMaskByState{stateIdx};
expectedFallback = protocol. ...
    expectedRuntimeReferenceFallbackCountByState{stateIdx};
expectedBytes = protocol. ...
    expectedRuntimeAttemptedBytesByState{stateIdx};
expectedReferenceRisk = protocol. ...
    expectedRuntimeReferenceRiskByState{stateIdx};
expectedSelectedRisk = protocol. ...
    expectedRuntimeSelectedRiskByState{stateIdx};
if ~strcmp(replay.contractVersion, ...
        'formation-staggered-recovery-v35-source-replay-v1') || ...
        ~isequal(replay.returnTimes, ...
            protocol.anchorTimes(stateIdx) + ...
                (0:protocol.horizonSteps - 1)) || ...
        ~isequal(replay. ...
            retentionDebtSelectedFormationIdsByTime{1}, ...
            initialControl.selectedFormationIds) || ...
        ~isequal(replay. ...
            retentionDebtSelectedFormationIdsByTime, ...
            expectedSelected) || ...
        ~isequal(replay. ...
            retentionDebtRequestedFormationIdsByTime, ...
            expectedRequested) || ...
        ~isequal(replay. ...
            retentionDebtProjectionRemovalOrderByTime, ...
            expectedReleased) || ...
        ~isequal(replay.referenceFallbackCountByTime, ...
            expectedFallback) || ...
        ~isequal(replay.attemptedBytesByTime, expectedBytes) || ...
        ~numericTraceMatches(replay.referenceNetworkRiskByTime, ...
            expectedReferenceRisk, protocol.sourceMetricTolerance) || ...
        ~numericTraceMatches(replay.selectedNetworkRiskByTime, ...
            expectedSelectedRisk, protocol.sourceMetricTolerance) || ...
        ~all(replay.posteriorContentUsedByTime) || ...
        ~all(replay.currentLinkReliabilityUsedByTime) || ...
        ~all(replay.oneStepReservePassedByTime) || ...
        ~all(replay.selectedSensorB3Pass) || ...
        ~all(replay.selectedFormationB3Pass) || ...
        ~replay.firstActionExact || ...
        ~replay.firstFusionWeightsExact || ...
        ~strcmp(replay.runtimeFingerprint.contractVersion, ...
            ['formation-staggered-recovery-', ...
             'runtime-fingerprint-v1']) || ...
        ~strcmp(replay.runtimeFingerprintSha256, ...
            computeCanonicalValueSha256( ...
                replay.runtimeFingerprint)) || ...
        replay.truthUsed || replay.futureOutcomeUsed || ...
        replay.trackingOutcomeScored || replay.groundTruthAccessed
    error('V37Preflight:RuntimeReplayDrift', ...
        'Full runtime replay drifted for X36 state %d.', stateIdx);
end

expectedDebt = protocol. ...
    expectedRuntimeDebtFractionByState{stateIdx};
for timeIdx = 1:protocol.horizonSteps
    if ~numericTraceMatches( ...
            replay.retentionDebtFractionByTime{timeIdx}, ...
            expectedDebt{timeIdx}, protocol.sourceMetricTolerance)
        error('V37Preflight:RuntimeDebtDrift', ...
            'Runtime debt drifted for state %d step %d.', ...
            stateIdx, timeIdx);
    end
    schedule = replay.staggeredRecoveryScheduleByTime{timeIdx};
    if ~isstruct(schedule) || ...
            ~isfield(schedule, 'contractVersion') || ...
            ~strcmp(schedule.contractVersion, ...
                ['formation-staggered-recovery-', ...
                 'runtime-schedule-v1']) || ...
            schedule.currentTime ~= replay.returnTimes(timeIdx) || ...
            schedule.staggeredReleaseUsed ~= ...
                expectedStaggered(timeIdx) || ...
            ~isequal(schedule.selectedFormationIds, ...
                expectedSelected{timeIdx}) || ...
            ~isequal(schedule.releasedFormationIds, ...
                expectedReleased{timeIdx}) || ...
            schedule.truthUsed || schedule.futureOutcomeUsed
        error('V37Preflight:RuntimeScheduleDrift', ...
            'Runtime schedule drifted for state %d step %d.', ...
            stateIdx, timeIdx);
    end
end
end

function proposals = buildPairProposals(states, eligibilityMask, protocol)
stateCount = numel(states);
template = struct( ...
    'contractVersion', ...
        'formation-staggered-recovery-x36-pair-proposal-v1', ...
    'pairId', '', ...
    'eligible', false, ...
    'presetName', '', ...
    'seed', NaN, ...
    'anchorTime', NaN, ...
    'returnTimes', [], ...
    'horizonSteps', NaN, ...
    'blockageFormationPair', [], ...
    'cachePath', '', ...
    'cacheSha256', '', ...
    'referenceArmId', '', ...
    'referenceInitialActionIndex', NaN, ...
    'referenceNominalActionSequenceIndices', [], ...
    'candidateArmId', '', ...
    'candidateInitialActionIndex', NaN, ...
    'candidateNominalActionSequenceIndices', [], ...
    'candidateRuntimeFingerprintSha256', '', ...
    'maximumPairedRunCount', 0, ...
    'trackingOutcomeScored', false);
proposals = repmat(template, 1, stateCount);
for stateIdx = 1:stateCount
    state = states(stateIdx);
    proposal = template;
    proposal.pairId = sprintf( ...
        'x36-seed%d-t%d-reference-vs-v35-h%d', ...
        protocol.seed, state.anchorTime, protocol.horizonSteps);
    proposal.eligible = eligibilityMask(stateIdx);
    proposal.presetName = protocol.presetName;
    proposal.seed = protocol.seed;
    proposal.anchorTime = state.anchorTime;
    proposal.returnTimes = state.runtimeReplay.returnTimes;
    proposal.horizonSteps = protocol.horizonSteps;
    proposal.blockageFormationPair = state.blockageFormationPair;
    proposal.cachePath = state.cachePath;
    proposal.cacheSha256 = state.cacheSha256;
    proposal.referenceArmId = protocol.expectedReferenceArmName;
    proposal.referenceInitialActionIndex = 1;
    proposal.referenceNominalActionSequenceIndices = ...
        ones(1, protocol.horizonSteps);
    proposal.candidateArmId = ...
        'formation-staggered-recovery-v35-v1';
    proposal.candidateInitialActionIndex = state.initialActionIndex;
    proposal.candidateNominalActionSequenceIndices = [ ...
        state.initialActionIndex, ...
        ones(1, protocol.horizonSteps - 1)];
    proposal.candidateRuntimeFingerprintSha256 = ...
        state.runtimeFingerprintSha256;
    proposal.maximumPairedRunCount = double(proposal.eligible);
    proposals(stateIdx) = proposal;
end
end

function assertCommitAncestor(ancestor, descendant, label)
if isempty(regexp(ancestor, '^[0-9a-f]{40}$', 'once')) || ...
        isempty(regexp(descendant, '^[0-9a-f]{40}$', 'once'))
    error('V37Preflight:InvalidGitLineage', ...
        'Invalid commit in the %s lineage.', label);
end
[status, ~] = system(sprintf( ...
    'git merge-base --is-ancestor %s %s', ancestor, descendant));
if status ~= 0
    error('V37Preflight:InvalidGitLineage', ...
        '%s commit is not an ancestor of the current source.', label);
end
end

function matched = numericTraceMatches(actual, expected, tolerance)
matched = isequal(size(actual), size(expected)) && ...
    isequal(isnan(actual), isnan(expected));
if ~matched
    return;
end
finiteMask = ~isnan(expected);
if any(finiteMask(:))
    matched = all(isfinite(actual(finiteMask))) && ...
        max(abs(actual(finiteMask) - ...
            expected(finiteMask))) <= tolerance;
end
end

