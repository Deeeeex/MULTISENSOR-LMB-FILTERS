        (protocol.runtimeFingerprintFreezePending || ...
         any(cellfun(@isempty, ...
            protocol. ...
                expectedRuntimeFingerprintSha256ByStateArm(:))))
    error('V37Preflight:FingerprintNotFrozen', ...
        'Official v37 preflight requires frozen runtime fingerprints.');
