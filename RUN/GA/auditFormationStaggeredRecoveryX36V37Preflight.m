            mat2str(replay.retentionDebtFractionByTime{timeIdx}, 5), ...
            mat2str(replay. ...
                retentionDebtRequestedFormationIdsByTime{timeIdx}), ...
            mat2str(replay. ...
                retentionDebtSelectedFormationIdsByTime{timeIdx}), ...
            mat2str(replay. ...
                retentionDebtProjectionRemovalOrderByTime{timeIdx}), ...
            schedule.staggeredReleaseUsed, ...
            replay.oneStepReservePassedByTime(timeIdx), ...
            replay.attemptedBytesByTime(timeIdx));
    end
    fprintf(fid, '\n');
end

fprintf(fid, '## Method boundary\n\n');
fprintf(fid, [ ...
    'Each state freezes two distinct H=3 runtime traces. The reference ', ...
    'uses the registered fixed counter-clockwise routing rule and is ', ...
    'required not to adapt to posterior content or current link ', ...
    'probabilities. The candidate recomputes the retention-debt control ', ...
    'from the current posterior, current drop-probability page, current ', ...
    'sensor positions, and past topology/update history only. Neither ', ...
    'arm can receive target truth, complete scenario trajectories, link ', ...
    'realizations, future drop-probability pages, future sensor ', ...
    'trajectories, or future measurements through the policy callback. ', ...
    'The posterior is schema-projected, and every remaining field uses ', ...
    'a primitive container with a current-time shape contract. ', ...
    'Only t=100 performs an explicit mature-formation release inside ', ...
    'H=3; t=72 and t=128 rotate the protected formations. Staggered ', ...
    'release is therefore a state-dependent behavior of the broader ', ...
    'debt-aware protection-and-rotation mechanism.\n\n']);

fprintf(fid, '## Decision\n\n');
if preflight.fingerprintDiscoveryMode
    fprintf(fid, [ ...
        'This source-only run discovers six complete runtime ', ...
        'fingerprints: one reference and one candidate trace for each ', ...
        'of the three states. It authorizes no tracking outcome. The ', ...
        'hashes must first be frozen in source and reproduced from a ', ...
        'later clean commit.\n\n']);
elseif preflight.x36PairedOutcomePermitMayBeMinted
    fprintf(fid, [ ...
        'All three X36 states reproduce the frozen source metrics, ', ...
        'initial actions, all six complete H=3 runtime fingerprints, ', ...
        'current-observable input contracts, and ', ...
        'semantic cache provenance from clean source. The three ', ...
        'structured pair proposals are eligible for a separate hashed ', ...
        'outcome permit. This preflight itself authorizes no tracking ', ...
        'run.\n\n']);
else
    fprintf(fid, [ ...
        'The X36 paired outcome remains sealed. No outcome permit may ', ...
        'be minted from this artifact.\n\n']);
end
fprintf(fid, '## Outcome-permit boundary\n\n%s\n\n', ...
    preflight.outcomePermitBoundary);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

