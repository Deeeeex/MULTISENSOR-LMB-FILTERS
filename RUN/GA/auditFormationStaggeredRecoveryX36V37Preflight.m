    protocol.presetName, protocol.seed);
truthFields = { ...
    'groundTruth', 'groundTruthRfs', 'targetTrajectories'};
if ~all(isfield(inputs, truthFields))
    error('V37Preflight:TruthBoundary', ...
        'Scenario truth isolation cannot be attested.');
