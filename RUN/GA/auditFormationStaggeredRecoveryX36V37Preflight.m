function currentGitState = assertExecutionSourceStable( ...
        initialGitState, initialManifest, stageLabel)
currentGitState = resolveResearchGitState();
currentManifest = buildMatlabSourceManifest();
if ~strcmp(currentGitState.commit, initialGitState.commit) || ...
        currentGitState.trackedWorktreeDirty ~= ...
            initialGitState.trackedWorktreeDirty || ...
        ~isequal(sort(currentGitState.untrackedSourceFiles), ...
            sort(initialGitState.untrackedSourceFiles)) || ...
        ~strcmp(currentManifest.canonicalSha256, ...
            initialManifest.canonicalSha256)
    error('V37Preflight:SourceChangedDuringRun', ...
        'Execution source changed %s; discard this run.', stageLabel);
end
end

function manifest = buildMatlabSourceManifest()
[status, trackedListing] = system('git ls-files --cached');
if status ~= 0
    error('V37Preflight:SourceManifestFailed', ...
        'Could not enumerate registered repository files.');
end
[status, repositoryListing] = system([ ...
    'find . \( -type f -o -type l \) ', ...
    '\( -name ''*.m'' -o -name ''*.p'' ', ...
    '-o -name ''*.mlx'' -o -name ''*.oct'' ', ...
    '-o -name ''*.mex*'' \) ', ...
    '-not -path ''./.git/*'' -print']);
if status ~= 0
    error('V37Preflight:SourceManifestFailed', ...
        'Could not enumerate repository executable source files.');
end
trackedPaths = splitNonemptyLines(trackedListing);
trackedPaths = trackedPaths(cellfun( ...
    @isExecutableSourcePath, trackedPaths));
repositoryPaths = splitNonemptyLines(repositoryListing);
for pathIdx = 1:numel(repositoryPaths)
    if strncmp(repositoryPaths{pathIdx}, './', 2)
        repositoryPaths{pathIdx} = ...
            repositoryPaths{pathIdx}(3:end);
    end
end
trackedPaths = unique(sort(trackedPaths));
repositoryPaths = unique(sort(repositoryPaths));
unregisteredPaths = setdiff(repositoryPaths, trackedPaths);
if ~isempty(unregisteredPaths)
    error('V37Preflight:UnregisteredExecutableSource', ...
        ['Repository-local executable source is not registered in ', ...
         'Git: %s'], unregisteredPaths{1});
end
paths = trackedPaths;
sha256 = cell(size(paths));
for pathIdx = 1:numel(paths)
    if exist(paths{pathIdx}, 'file') == 0
        error('V37Preflight:SourceManifestFailed', ...
            'A registered executable source disappeared during hashing.');
    end
    sha256{pathIdx} = computeFileSha256(paths{pathIdx});
end
payload = struct( ...
    'contractVersion', ...
        'registered-executable-source-manifest-v2', ...
    'paths', {reshape(paths, 1, [])}, ...
    'sha256', {reshape(sha256, 1, [])}, ...
    'unregisteredExecutablePaths', ...
        {reshape(unregisteredPaths, 1, [])});
manifest = payload;
manifest.canonicalSha256 = ...
    computeCanonicalValueSha256(payload);
end

function result = isExecutableSourcePath(path)
result = ~isempty(regexp(lower(path), ...
    '\.(m|p|mlx|oct|mex[^/]*)$', 'once'));
end

function lines = splitNonemptyLines(value)
value = strtrim(value);
if isempty(value)
    lines = cell(1, 0);
else
    lines = regexp(value, '\r?\n', 'split');
    lines = reshape(lines, 1, []);
end
end

function model = removeExplicitTargetTruth(model)
if isfield(model, 'explicitTargetTrajectories')
    model = rmfield(model, 'explicitTargetTrajectories');
end
if isfield(model, 'dynamicTopologyScenario') && ...
        isstruct(model.dynamicTopologyScenario) && ...
        isscalar(model.dynamicTopologyScenario) && ...
        isfield(model.dynamicTopologyScenario, 'targetTrajectories')
    model.dynamicTopologyScenario = rmfield( ...
        model.dynamicTopologyScenario, 'targetTrajectories');
end
end

function value = validateLogicalOption(options, fieldName, defaultValue)
value = getField(options, fieldName, defaultValue);
if ~(islogical(value) || isa(value, 'double')) || ...
        ~isscalar(value) || ~isfinite(double(value)) || ...
        ~any(double(value) == [0, 1])
    error('V37Preflight:InvalidOption', ...
        '%s must be a logical scalar.', fieldName);
end
value = logical(value);
end

function assertSourceProtocolContract(protocol)
required = { ...
    'id', 'contractVersion', 'anchorTimes', 'runtimeArmIds', ...
    'runtimeArmOrdinals', 'runtimeSemantics', ...
    'policyContextSanitizerContractVersion', ...
    'runtimeFingerprintContractVersion', ...
    'publicationCompletionContractVersion', ...
    'publicationCompletionMarkerRequired', ...
    'sourceManifestContractVersion', ...
    'expectedRuntimeFingerprintSha256ByStateArm', ...
    'cacheGenerationAuthorized', 'sourceOnlyControlAuditAuthorized', ...
    'trackingOutcomeRerunAuthorized', 'x36OutcomeOpeningAuthorized', ...
    'gnnTrainingAuthorized', 'x48OutcomeOpeningAuthorized', ...
    'validationClaimAllowed'};
if ~isstruct(protocol) || ~isscalar(protocol) || ...
        ~all(isfield(protocol, required))
    error('V37Preflight:InvalidSourceProtocol', ...
        'The v3 causal source protocol contract is incomplete.');
end
expectedSize = [numel(protocol.anchorTimes), 2];
if ~strcmp(protocol.id, ...
        'formation-staggered-recovery-x36-source-v37-v3') || ...
        ~strcmp(protocol.contractVersion, ...
            'formation-staggered-recovery-x36-source-protocol-v3') || ...
        ~isequal(protocol.runtimeArmIds, { ...
            'formation-h3-fixed-ccw-reference-v1', ...
            'formation-staggered-recovery-v35-v1'}) || ...
        ~isequal(protocol.runtimeArmOrdinals, [1, 2]) || ...
        ~isequal(protocol.runtimeSemantics, { ...
            'fixed-reference', 'causal-staggered-recovery'}) || ...
        ~strcmp(protocol.policyContextSanitizerContractVersion, ...
            'topology-policy-observable-input-v2') || ...
        ~strcmp(protocol.runtimeFingerprintContractVersion, ...
            'formation-staggered-recovery-runtime-fingerprint-v2') || ...
        ~strcmp(protocol.publicationCompletionContractVersion, ...
            ['formation-staggered-recovery-source-', ...
             'publication-v1']) || ...
        ~protocol.publicationCompletionMarkerRequired || ...
        ~strcmp(protocol.sourceManifestContractVersion, ...
            'registered-executable-source-manifest-v2') || ...
        ~isequal(size(protocol. ...
            expectedRuntimeFingerprintSha256ByStateArm), ...
            expectedSize) || ...
        ~protocol.cacheGenerationAuthorized || ...
        ~protocol.sourceOnlyControlAuditAuthorized || ...
        protocol.trackingOutcomeRerunAuthorized || ...
        protocol.x36OutcomeOpeningAuthorized || ...
        protocol.gnnTrainingAuthorized || ...
        protocol.x48OutcomeOpeningAuthorized || ...
        protocol.validationClaimAllowed
    error('V37Preflight:InvalidSourceProtocol', ...
        'The v3 causal source protocol contract is malformed.');
end
end

function assertOutputSetAbsent( ...
        reportPath, matPath, completionMarkerPath)
if exist(reportPath, 'file') ~= 0 || ...
        exist(matPath, 'file') ~= 0 || ...
        exist(completionMarkerPath, 'file') ~= 0
    error('V37Preflight:OutputExists', ...
        ['The v3 source artifact already exists; refusing to ', ...
         'overwrite any member of the MAT/report/marker set.']);
end
end

function ensureParentDirectory(path)
parent = resolveParentDirectory(path);
if exist(parent, 'dir') ~= 7
    mkdir(parent);
end
end

function parent = resolveParentDirectory(path)
parent = fileparts(path);
if isempty(parent)
    parent = pwd;
end
end

function publishArtifactSet( ...
        temporaryMatPath, temporaryReportPath, ...
        temporaryMarkerPath, matPath, reportPath, ...
        completionMarkerPath, publicationMetadata, ...
        initialGitState, initialSourceManifest)
matPublished = false;
reportPublished = false;
markerPublished = false;
try
    assertOutputSetAbsent( ...
        reportPath, matPath, completionMarkerPath);
    [moved, message] = movefile(temporaryMatPath, matPath);
    if ~moved
        error('V37Preflight:PublishFailed', ...
            'Could not publish the preflight MAT file: %s', message);
    end
    matPublished = true;
    if exist(reportPath, 'file') ~= 0
        error('V37Preflight:OutputExists', ...
            'The preflight report appeared during publication.');
    end
    [moved, message] = movefile(temporaryReportPath, reportPath);
    if ~moved
        error('V37Preflight:PublishFailed', ...
            'Could not publish the preflight report: %s', message);
    end
    reportPublished = true;
    if exist(matPath, 'file') ~= 2 || exist(reportPath, 'file') ~= 2
        error('V37Preflight:PublishFailed', ...
            'The preflight MAT/report pair is incomplete.');
    end
    publication = publicationMetadata;
    publication.publishedAt = datestr(now, 31);
    publication.matPath = matPath;
    publication.reportPath = reportPath;
    publication.matSha256 = computeFileSha256(matPath);
    publication.reportSha256 = computeFileSha256(reportPath);
    publication.completionMarkerPath = completionMarkerPath;
    publication.completionMarkerWrittenLast = true;
    save('-mat7-binary', temporaryMarkerPath, 'publication');
    assertExecutionSourceStable(initialGitState, ...
        initialSourceManifest, 'before completion marker');
    if ~strcmp(publication.matSha256, computeFileSha256(matPath)) || ...
            ~strcmp(publication.reportSha256, ...
                computeFileSha256(reportPath))
        error('V37Preflight:PublishFailed', ...
            'The artifact pair changed before completion marking.');
    end
    if exist(completionMarkerPath, 'file') ~= 0
        error('V37Preflight:OutputExists', ...
            'The completion marker appeared during publication.');
    end
    [moved, message] = movefile( ...
        temporaryMarkerPath, completionMarkerPath);
    if ~moved
        error('V37Preflight:PublishFailed', ...
            'Could not publish the completion marker: %s', message);
    end
    markerPublished = true;
    if exist(completionMarkerPath, 'file') ~= 2
        error('V37Preflight:PublishFailed', ...
            'The completion marker was not published.');
    end
catch publicationError
    cleanupTemporaryArtifacts(temporaryMatPath, temporaryReportPath, ...
        temporaryMarkerPath);
    if markerPublished && exist(completionMarkerPath, 'file') == 2
        delete(completionMarkerPath);
    end
    if matPublished && exist(matPath, 'file') == 2
        delete(matPath);
    end
    if reportPublished && exist(reportPath, 'file') == 2
        delete(reportPath);
    end
    rethrow(publicationError);
end
end

function cleanupTemporaryArtifacts( ...
        temporaryMatPath, temporaryReportPath, temporaryMarkerPath)
if exist(temporaryMatPath, 'file') == 2
    delete(temporaryMatPath);
end
if exist(temporaryReportPath, 'file') == 2
    delete(temporaryReportPath);
end
if exist(temporaryMarkerPath, 'file') == 2
    delete(temporaryMarkerPath);
end
end

