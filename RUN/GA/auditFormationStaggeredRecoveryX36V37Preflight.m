function [reportPath, preflight] = ...
    auditFormationStaggeredRecoveryX36V37Preflight(options)
% AUDITFORMATIONSTAGGEREDRECOVERYX36V37PREFLIGHT Frozen source-only gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationStaggeredRecoveryX36SourceProtocol();
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v37 preflight requires a clean tracked and ', ...
        'MATLAB/Octave source state.']);
end

m24ScreenPath = getField(options, 'm24ScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v36', 'm24_replication', 'screen', ...
    'FORMATION_STAGGERED_RECOVERY_M24_V36_SCREEN.mat'));
sceneAuditPath = getField(options, 'sceneAuditPath', fullfile( ...
    protocol.outputRoot, 'scene', ...
    'FORMATION_STAGGERED_RECOVERY_X36_V37_SCENE.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_STAGGERED_RECOVERY_X36_V37_', ...
     'PREFLIGHT_20260802.md']));
matPath = getField(options, 'matPath', fullfile( ...
    protocol.outputRoot, 'preflight', ...
    'FORMATION_STAGGERED_RECOVERY_X36_V37_PREFLIGHT.mat'));

m24ScreenSha256 = computeFileSha256(m24ScreenPath);
if ~strcmp(m24ScreenSha256, protocol.sourceM24ScreenSha256)
    error('V37Preflight:M24ScreenDrift', ...
        'The frozen M24 replication screen hash changed.');
end
m24Loaded = load(m24ScreenPath, 'screen');
if ~isfield(m24Loaded, 'screen')
    error('V37Preflight:MissingM24Screen', ...
        'The frozen M24 replication screen is unavailable.');
end
assertM24Authorization(m24Loaded.screen, protocol);

sceneAuditSha256 = computeFileSha256(sceneAuditPath);
if ~strcmp(sceneAuditSha256, protocol.sceneAuditSha256)
    error('V37Preflight:SceneAuditDrift', ...
        'The frozen X36 scene-audit hash changed.');
end
sceneLoaded = load(sceneAuditPath, 'audit');
if ~isfield(sceneLoaded, 'audit')
    error('V37Preflight:MissingSceneAudit', ...
        'The frozen X36 scene audit is unavailable.');
end
assertSceneAuthorization(sceneLoaded.audit, protocol);

inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, protocol.seed);
if inputs.config.numberOfSensors ~= protocol.expectedNodeCount || ...
        inputs.config.numberOfTargets ~= protocol.expectedTargetCount || ...
        inputs.config.formationCount ~= ...
            protocol.expectedFormationCount
    error('V37Preflight:ScenarioDrift', ...
        'The registered X36 scenario dimensions changed.');
end

stateCount = numel(protocol.anchorTimes);
states = repmat(emptyState(), 1, stateCount);
for stateIdx = 1:stateCount
    anchorTime = protocol.anchorTimes(stateIdx);
    cachePath = fullfile(protocol.cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', ...
        strrep(protocol.presetName, '-', '_'), ...
        protocol.seed, anchorTime));
    cacheSha256 = computeFileSha256(cachePath);
    if ~strcmp(cacheSha256, ...
            protocol.expectedCacheSha256{stateIdx})
        error('V37Preflight:CacheDrift', ...
            'Frozen X36 cache hash changed at t=%d.', anchorTime);
    end
    [context, bundle] = buildOpenedContext( ...
        inputs, cachePath, anchorTime, protocol);

    controlTimer = tic;
    initialControl = ...
        buildFormationStaggeredRecoveryControl(context);
    controlSeconds = toc(controlTimer);
    assertInitialControl(initialControl, stateIdx, protocol);

    bank = buildTemporalCrossEdgeSuspensionActionBank( ...
        context, struct('scorePosteriorSafety', false));
    initialActionIdx = findActionIndex( ...
        bank, initialControl.selectedFormationIds);
    if initialActionIdx ~= ...
            protocol.expectedInitialActionIndices(stateIdx)
        error('V37Preflight:InitialActionDrift', ...
            'Initial action index changed at t=%d.', anchorTime);
    end

    sourceScreen = struct('cachePath', cachePath);
    sourcePreflight = struct( ...
        'initialBank', bank, ...
        'selectedInitialActionIndex', initialActionIdx);
    runtimeProtocol = protocol;
    runtimeProtocol.anchorTime = anchorTime;
    runtimeProtocol.reconnectTime = ...
        anchorTime + protocol.horizonSteps - 1;
    replayTimer = tic;
    replay = ...
        replayFormationStaggeredRecoveryV35SourceTrajectory( ...
            sourceScreen, sourcePreflight, runtimeProtocol);
    replaySeconds = toc(replayTimer);
    assertRuntimeReplay( ...
        replay, initialControl, stateIdx, protocol);

    state = emptyState();
    state.anchorTime = anchorTime;
    state.blockageFormationPair = ...
        protocol.blockageFormationPairs(stateIdx, :);
    state.cachePath = cachePath;
    state.cacheSha256 = cacheSha256;
    state.cacheGenerationGitCommit = ...
        bundle.generationGitCommit;
    state.initialControlConstructionSeconds = controlSeconds;
    state.runtimeReplaySeconds = replaySeconds;
    state.initialControl = initialControl;
    state.initialActionIndex = initialActionIdx;
    state.runtimeReplay = replay;
    state.explicitStaggeredReleaseCount = nnz( ...
        protocol. ...
            expectedRuntimeStaggeredReleaseMaskByState{stateIdx});
    state.runtimeReplayPassed = true;
    state.trackingOutcomeScored = false;
    state.truthUsed = false;
    state.futureOutcomeUsed = false;
    states(stateIdx) = state;
end

cleanSource = ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles);
authorizedMask = cleanSource & ...
    protocol.trackingOutcomeRerunAuthorized & ...
    [states.runtimeReplayPassed] & ...
    arrayfun(@(state) ...
        ~state.initialControl.referenceFallbackUsed && ...
        state.initialControl.selectedScore.safe && ...
        all(state.initialControl.selectedRollingB3SensorPass) && ...
        all(state.initialControl.selectedRollingB3FormationPass), ...
        states);

preflight = struct();
preflight.contractVersion = ...
    'formation-staggered-recovery-x36-v37-preflight-v1';
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.protocol = protocol;
preflight.m24ScreenPath = m24ScreenPath;
preflight.m24ScreenSha256 = m24ScreenSha256;
preflight.m24ScreenGenerationCommit = ...
    m24Loaded.screen.generationGitCommit;
preflight.sceneAuditPath = sceneAuditPath;
preflight.sceneAuditSha256 = sceneAuditSha256;
preflight.sceneAuditGenerationCommit = ...
    sceneLoaded.audit.generationGitCommit;
preflight.states = states;
preflight.anchorTimes = protocol.anchorTimes;
preflight.trackingOutcomeAuthorizedMask = authorizedMask;
preflight.authorizedStateCount = nnz(authorizedMask);
preflight.x36PairedOutcomeRerunAuthorized = ...
    all(authorizedMask);
preflight.maximumAuthorizedPairCount = ...
    nnz(authorizedMask);
preflight.trackingOutcomeScored = false;
preflight.newPosteriorStateOpened = false;
preflight.outcomeRankingUsesTruth = false;
preflight.gnnTrainingAuthorized = false;
preflight.x48Opened = false;
preflight.reservedSeedOpened = false;
preflight.validationClaimAllowed = false;
preflight.outcomeAuthorizationScope = [ ...
    'At most one fixed-CCW-reference versus frozen-v35 H=3 pair ', ...
    'at each authorized X36 state. No alternate controller, ', ...
    'threshold, horizon, anchor, seed, or scenario may be scored.'];
preflight.evidenceBoundary = protocol.evidenceBoundary;

if exist(fileparts(matPath), 'dir') ~= 7
    mkdir(fileparts(matPath));
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('V37 X36 source-only preflight: %s\n', reportPath);
end

function assertM24Authorization(screen, protocol)
if ~strcmp(screen.contractVersion, ...
        'formation-staggered-recovery-m24-v36-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            protocol.sourceM24ScreenGenerationCommit) || ...
        ~screen.formalReplicationGatePassed || ...
        ~screen.replicationGate.passed || ...
        ~screen.x36SourceOnlyProtocolAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V37Preflight:M24Authorization', ...
        'The frozen M24 result does not authorize X36 source work.');
end
end

function assertSceneAuthorization(audit, protocol)
if ~strcmp(audit.contractVersion, ...
        'formation-staggered-recovery-x36-v37-scene-audit-v1') || ...
        ~strcmp(audit.generationGitCommit, ...
            protocol.sceneAuditGenerationCommit) || ...
        ~audit.sceneGatePassed || ...
        ~audit.hardwareContractPassed || ...
        ~audit.cacheGenerationAuthorized || ...
        audit.trackingOutcomeScored || ...
        audit.posteriorGenerated || ...
        audit.trackingOutcomeRerunAuthorized || ...
        audit.gnnTrainingAuthorized || ...
        audit.x36OutcomeOpeningAuthorized || ...
        audit.x48OutcomeOpeningAuthorized || ...
        audit.validationClaimAllowed
    error('V37Preflight:SceneAuthorization', ...
        'The frozen scene audit does not authorize the X36 caches.');
end
end

function [context, bundle] = buildOpenedContext( ...
        inputs, cachePath, anchorTime, protocol)
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V37Preflight:MissingCache', ...
        'Frozen X36 cache is unavailable at t=%d.', anchorTime);
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.protocolId, protocol.id) || ...
        ~strcmp(bundle.generationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~strcmp(bundle.presetName, protocol.presetName) || ...
        bundle.seed ~= protocol.seed || ...
        ~isequal(bundle.snapshotTimes, anchorTime) || ...
        bundle.generationTrackedWorktreeDirty || ...
        ~isempty(bundle.generationUntrackedSourceFiles) || ...
        ~bundle.referenceReplayOnly || ...
        bundle.policyTruthUsed || ...
        bundle.policyFutureOutcomeUsed || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        bundle.validationClaimAllowed || ...
        numel(bundle.posteriorSnapshots) < anchorTime || ...
        isempty(bundle.posteriorSnapshots{anchorTime}) || ...
        numel(bundle.preDecisionTopologyHistoryByTime) < ...
            anchorTime || ...
        isempty(bundle.preDecisionTopologyHistoryByTime{anchorTime})
    error('V37Preflight:CacheProvenance', ...
        'Frozen X36 cache provenance changed at t=%d.', anchorTime);
end
history = bundle.preDecisionTopologyHistoryByTime{anchorTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
nodeCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{anchorTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = anchorTime;
context.previousAdjacencyHistory = previousHistory;
context.previousAdjacencyHistoryCount = ...
    size(previousHistory, 3);
context.previousAdjacencyHistoryTimes = history.times;
context.previousAdjacency = previousHistory(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, anchorTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = ...
    inputs.graphData.positions(:, :, anchorTime);
end

function assertInitialControl(control, stateIdx, protocol)
expectedDebt = ...
    protocol.expectedInitialDebtFractionByState{stateIdx};
if ~strcmp(control.contractVersion, ...
        'formation-staggered-recovery-control-v1') || ...
        ~strcmp(control.protocolId, ...
            'formation-staggered-recovery-v35-v1') || ...
        control.nodeCount ~= protocol.expectedNodeCount || ...
        control.formationCount ~= protocol.expectedFormationCount || ...
        ~isequal(control.selectedFormationIds, ...
            protocol. ...
                expectedInitialFormationIdsByState{stateIdx}) || ...
        control.referenceFallbackUsed || ...
        ~numericTraceMatches(control.baseControl. ...
            formationRetentionDebtFraction, expectedDebt, ...
            protocol.sourceMetricTolerance) || ...
        abs(control.referenceScore.networkRisk - ...
            protocol.expectedInitialReferenceRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.networkRisk - ...
            protocol.expectedInitialSelectedRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.retentionRisk - ...
            protocol.expectedInitialRetentionRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        control.messageSavingCount ~= ...
            protocol.expectedInitialMessageSavingCount(stateIdx) || ...
        ~control.selectedScore.safe || ...
        ~all(control.selectedRollingB3SensorPass) || ...
        ~all(control.selectedRollingB3FormationPass) || ...
        ~control.selectionUsesCurrentPosterior || ...
        ~control.selectionUsesCurrentLinkReliability || ...
        ~control.selectionUsesSelectedTopologyHistory || ...
        ~control.openedDevelopmentEvidenceOnly || ...
        control.validationClaimAllowed || ...
        control.truthUsed || control.futureOutcomeUsed
    error('V37Preflight:InitialControlDrift', ...
        'Initial v35 control drifted for X36 state %d.', stateIdx);
end
end

function actionIdx = findActionIndex(bank, formationIds)
matches = false(1, bank.actionCount);
for candidateIdx = 1:bank.actionCount
    matches(candidateIdx) = isequal(reshape( ...
        bank.actionSuspendedFormationIds{candidateIdx}, 1, []), ...
        reshape(formationIds, 1, []));
end
actionIdx = find(matches);
if numel(actionIdx) ~= 1
    error('V37Preflight:InitialActionDrift', ...
        'Initial formation subset does not map uniquely to the bank.');
end
end

function assertRuntimeReplay( ...
        replay, initialControl, stateIdx, protocol)
expectedSelected = protocol. ...
    expectedRuntimeSelectedFormationIdsByState{stateIdx};
expectedRequested = protocol. ...
    expectedRuntimeRequestedFormationIdsByState{stateIdx};
expectedReleased = protocol. ...
    expectedRuntimeReleasedFormationIdsByState{stateIdx};
expectedStaggered = protocol. ...
    expectedRuntimeStaggeredReleaseMaskByState{stateIdx};
expectedFallback = protocol. ...
    expectedRuntimeReferenceFallbackCountByState{stateIdx};
expectedBytes = protocol. ...
    expectedRuntimeAttemptedBytesByState{stateIdx};
expectedReferenceRisk = protocol. ...
    expectedRuntimeReferenceRiskByState{stateIdx};
expectedSelectedRisk = protocol. ...
    expectedRuntimeSelectedRiskByState{stateIdx};
if ~strcmp(replay.contractVersion, ...
        'formation-staggered-recovery-v35-source-replay-v1') || ...
        ~isequal(replay.returnTimes, ...
            protocol.anchorTimes(stateIdx) + ...
                (0:protocol.horizonSteps - 1)) || ...
        ~isequal(replay. ...
            retentionDebtSelectedFormationIdsByTime{1}, ...
            initialControl.selectedFormationIds) || ...
        ~isequal(replay. ...
            retentionDebtSelectedFormationIdsByTime, ...
            expectedSelected) || ...
        ~isequal(replay. ...
            retentionDebtRequestedFormationIdsByTime, ...
            expectedRequested) || ...
        ~isequal(replay. ...
            retentionDebtProjectionRemovalOrderByTime, ...
            expectedReleased) || ...
        ~isequal(replay.referenceFallbackCountByTime, ...
            expectedFallback) || ...
        ~isequal(replay.attemptedBytesByTime, expectedBytes) || ...
        ~numericTraceMatches(replay.referenceNetworkRiskByTime, ...
            expectedReferenceRisk, protocol.sourceMetricTolerance) || ...
        ~numericTraceMatches(replay.selectedNetworkRiskByTime, ...
            expectedSelectedRisk, protocol.sourceMetricTolerance) || ...
        ~all(replay.posteriorContentUsedByTime) || ...
        ~all(replay.currentLinkReliabilityUsedByTime) || ...
        ~all(replay.oneStepReservePassedByTime) || ...
        ~replay.firstActionExact || ...
        ~replay.firstFusionWeightsExact || ...
        replay.truthUsed || replay.futureOutcomeUsed || ...
        replay.trackingOutcomeScored || replay.groundTruthAccessed
    error('V37Preflight:RuntimeReplayDrift', ...
        'Full runtime replay drifted for X36 state %d.', stateIdx);
end

expectedDebt = protocol. ...
    expectedRuntimeDebtFractionByState{stateIdx};
for timeIdx = 1:protocol.horizonSteps
    if ~numericTraceMatches( ...
            replay.retentionDebtFractionByTime{timeIdx}, ...
            expectedDebt{timeIdx}, protocol.sourceMetricTolerance)
        error('V37Preflight:RuntimeDebtDrift', ...
            'Runtime debt drifted for state %d step %d.', ...
            stateIdx, timeIdx);
    end
    schedule = replay.staggeredRecoveryScheduleByTime{timeIdx};
    if ~isstruct(schedule) || ...
            ~isfield(schedule, 'contractVersion') || ...
            ~strcmp(schedule.contractVersion, ...
                ['formation-staggered-recovery-', ...
                 'runtime-schedule-v1']) || ...
            schedule.currentTime ~= replay.returnTimes(timeIdx) || ...
            schedule.staggeredReleaseUsed ~= ...
                expectedStaggered(timeIdx) || ...
            ~isequal(schedule.selectedFormationIds, ...
                expectedSelected{timeIdx}) || ...
            ~isequal(schedule.releasedFormationIds, ...
                expectedReleased{timeIdx}) || ...
            schedule.truthUsed || schedule.futureOutcomeUsed
        error('V37Preflight:RuntimeScheduleDrift', ...
            'Runtime schedule drifted for state %d step %d.', ...
            stateIdx, timeIdx);
    end
end
end

function matched = numericTraceMatches(actual, expected, tolerance)
matched = isequal(size(actual), size(expected)) && ...
    isequal(isnan(actual), isnan(expected));
if ~matched
    return;
end
finiteMask = ~isnan(expected);
if any(finiteMask(:))
    matched = all(isfinite(actual(finiteMask))) && ...
        max(abs(actual(finiteMask) - ...
            expected(finiteMask))) <= tolerance;
end
end

function state = emptyState()
state = struct( ...
    'anchorTime', NaN, ...
    'blockageFormationPair', zeros(1, 0), ...
    'cachePath', '', ...
    'cacheSha256', '', ...
    'cacheGenerationGitCommit', '', ...
    'initialControlConstructionSeconds', NaN, ...
    'runtimeReplaySeconds', NaN, ...
    'initialControl', struct(), ...
    'initialActionIndex', NaN, ...
    'runtimeReplay', struct(), ...
    'explicitStaggeredReleaseCount', NaN, ...
    'runtimeReplayPassed', false, ...
    'trackingOutcomeScored', false, ...
    'truthUsed', false, ...
    'futureOutcomeUsed', false);
end

function writeReport(path, preflight)
fid = fopen(path, 'w');
if fid < 0
    error('V37Preflight:WriteFailed', ...
        'Could not open the v37 preflight report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V37 X36 frozen source-only preflight\n\n');
fprintf(fid, '- Contract / generation commit: `%s / %s`\n', ...
    preflight.contractVersion, preflight.generationGitCommit);
fprintf(fid, '- Tracked dirty / untracked source: `%d / %d`\n', ...
    preflight.generationTrackedWorktreeDirty, ...
    numel(preflight.generationUntrackedSourceFiles));
fprintf(fid, '- M24 screen SHA-256: `%s`\n', ...
    preflight.m24ScreenSha256);
fprintf(fid, '- X36 scene SHA-256: `%s`\n', ...
    preflight.sceneAuditSha256);
fprintf(fid, '- Preset / seed / anchor times: `%s / %d / %s`\n', ...
    preflight.protocol.presetName, preflight.protocol.seed, ...
    mat2str(preflight.anchorTimes));
fprintf(fid, '- Tracking scored / truth used: `0 / 0`\n');
fprintf(fid, '- Authorized fixed pairs: `%d / %d`\n\n', ...
    preflight.authorizedStateCount, numel(preflight.states));

for stateIdx = 1:numel(preflight.states)
    state = preflight.states(stateIdx);
    replay = state.runtimeReplay;
    control = state.initialControl;
    fprintf(fid, '## t=%d, blockage pair %s\n\n', ...
        state.anchorTime, mat2str(state.blockageFormationPair));
    fprintf(fid, '- Cache SHA-256: `%s`\n', state.cacheSha256);
    fprintf(fid, '- Initial action / retained formations: `%d / %s`\n', ...
        state.initialActionIndex, ...
        mat2str(control.selectedFormationIds));
    fprintf(fid, '- Initial reference / selected risk: `%.12f / %.12f`\n', ...
        control.referenceScore.networkRisk, ...
        control.selectedScore.networkRisk);
    fprintf(fid, '- Initial retention risk / message saving: `%.12g / %d`\n', ...
        control.selectedScore.retentionRisk, ...
        control.messageSavingCount);
    fprintf(fid, '- Initial control / runtime replay: `%.2f / %.2f s`\n', ...
        state.initialControlConstructionSeconds, ...
        state.runtimeReplaySeconds);
    fprintf(fid, '- Explicit staggered releases / pair authorized: `%d / %d`\n\n', ...
        state.explicitStaggeredReleaseCount, ...
        preflight.trackingOutcomeAuthorizedMask(stateIdx));
    fprintf(fid, [ ...
        '| Time | Debt fractions | Requested | Retained | Released ', ...
        '| Stagger | Reserve | Attempted bytes |\n']);
    fprintf(fid, '|--:|:--|:--|:--|:--|:--:|:--:|--:|\n');
    for timeIdx = 1:numel(replay.returnTimes)
        schedule = replay.staggeredRecoveryScheduleByTime{timeIdx};
        fprintf(fid, ...
            '| %d | `%s` | `%s` | `%s` | `%s` | %d | %d | %d |\n', ...
            replay.returnTimes(timeIdx), ...
            mat2str(replay.retentionDebtFractionByTime{timeIdx}, 5), ...
            mat2str(replay. ...
                retentionDebtRequestedFormationIdsByTime{timeIdx}), ...
            mat2str(replay. ...
                retentionDebtSelectedFormationIdsByTime{timeIdx}), ...
            mat2str(replay. ...
                retentionDebtProjectionRemovalOrderByTime{timeIdx}), ...
            schedule.staggeredReleaseUsed, ...
            replay.oneStepReservePassedByTime(timeIdx), ...
            replay.attemptedBytesByTime(timeIdx));
    end
    fprintf(fid, '\n');
end

fprintf(fid, '## Method boundary\n\n');
fprintf(fid, [ ...
    'All three states use the same posterior- and link-aware, ', ...
    'retention-debt receding-horizon controller. Only t=100 performs ', ...
    'an explicit mature-formation release inside H=3; t=72 and t=128 ', ...
    'rotate the retained formations without invoking that release ', ...
    'schedule. The X36 test therefore evaluates debt-aware protection ', ...
    'and rotation as the general mechanism, with staggered release as ', ...
    'one state-dependent behavior rather than a universal step.\n\n']);

fprintf(fid, '## Decision\n\n');
if preflight.x36PairedOutcomeRerunAuthorized
    fprintf(fid, [ ...
        'All three X36 states exactly reproduce the frozen source ', ...
        'metrics, initial actions, and complete H=3 runtime traces ', ...
        'from clean source. Exactly one fixed-reference versus frozen-', ...
        'v35 paired outcome is authorized at each state. No alternative ', ...
        'controller, threshold, horizon, anchor, seed, or scenario may ', ...
        'be scored under this authorization.\n\n']);
else
    fprintf(fid, [ ...
        'The X36 paired outcome remains sealed because at least one ', ...
        'registered source state did not pass the clean exact replay ', ...
        'gate.\n\n']);
end
fprintf(fid, '## Outcome authorization scope\n\n%s\n\n', ...
    preflight.outcomeAuthorizationScope);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
