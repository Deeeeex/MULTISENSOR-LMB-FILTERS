    protocol.sceneAuditPath);
if fingerprintDiscoveryMode
    defaultReportPath = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', ...
        ['FORMATION_STAGGERED_RECOVERY_X36_V37_V3_', ...
         'FINGERPRINT_DISCOVERY_20260802.md']);
    defaultMatPath = fullfile(protocol.outputRoot, ...
        'fingerprint_discovery', ...
        ['FORMATION_STAGGERED_RECOVERY_X36_V37_V3_', ...
         'FINGERPRINT_DISCOVERY.mat']);
else
    defaultReportPath = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', ...
        ['FORMATION_STAGGERED_RECOVERY_X36_V37_V3_', ...
         'PREFLIGHT_20260802.md']);
    defaultMatPath = fullfile(protocol.outputRoot, 'preflight', ...
        'FORMATION_STAGGERED_RECOVERY_X36_V37_V3_PREFLIGHT.mat');
end
reportPath = getField(options, 'reportPath', defaultReportPath);
matPath = getField(options, 'matPath', defaultMatPath);
completionMarkerPath = [matPath, '.complete'];
assertOutputSetAbsent(reportPath, matPath, completionMarkerPath);

