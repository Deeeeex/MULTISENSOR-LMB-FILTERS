function [shardPath, shard] = ...
    runBackboneResidualReturnHeadroomShard( ...
        batchIndex, batchCount, options)
% RUNBACKBONERESIDUALRETURNHEADROOMSHARD Paired M24 H=3 replay shard.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getBackboneResidualReturnHeadroomProtocol();
batchIndex = validateInteger( ...
    batchIndex, 'batchIndex', 1);
batchCount = validateInteger( ...
    batchCount, 'batchCount', 1);
if batchIndex > batchCount
    error('batchIndex must not exceed batchCount.');
end
proposalPath = getField(options, ...
    'proposalDatasetPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'proposals', ...
        'backbone_residual_return_m24_t75_seed7_v1.mat'));
if exist(proposalPath, 'file') ~= 2
    error('Missing residual return proposal dataset: %s', ...
        proposalPath);
end
loaded = load(proposalPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Proposal artifact lacks dataset.');
end
dataset = loaded.dataset;
validateProposalDataset(dataset, protocol);
proposalSha256 = computeFileSha256(proposalPath);
[inputs, ~, sourceState] = ...
    loadBackboneResidualReturnHeadroomState();
if ~strcmp(sourceState.cacheSha256, ...
        dataset.sourceCacheSha256)
    error('Proposal and live continuation cache hashes differ.');
end
inputs = cropInputs(inputs, protocol.horizonTimes(end));

candidateCount = size(dataset.candidateAdjacency, 3);
candidateIndices = batchIndex:batchCount:candidateCount;
maximumCandidates = getField(options, ...
    'maximumCandidatesToRun', inf);
if isfinite(maximumCandidates)
    candidateIndices = candidateIndices( ...
        1:min(numel(candidateIndices), ...
            max(0, floor(maximumCandidates))));
end
if isempty(candidateIndices)
    error('Return-headroom shard has no candidates.');
end

controls = repmat(emptyArmResult(), 1, 0);
if batchIndex == 1
    controlSpecs = { ...
        'local', 'fixed-index-w70', ...
        'static-residual', 'scheduled-residual', ...
        'analytic-residual'};
    controls = repmat(emptyArmResult(), ...
        1, numel(controlSpecs));
    for controlIdx = 1:numel(controlSpecs)
        mode = controlSpecs{controlIdx};
        fprintf('Control %s...\n', mode);
        controls(controlIdx) = runArm( ...
            inputs, sourceState, protocol, ...
            mode, false(0), struct(), false);
        controls(controlIdx).mode = mode;
        fprintfOutcome(controls(controlIdx));
    end
end

candidateResults = repmat(emptyArmResult(), ...
    1, numel(candidateIndices));
for resultIdx = 1:numel(candidateIndices)
    candidateIdx = candidateIndices(resultIdx);
    record = dataset.candidateRecords(candidateIdx);
    fprintf('Candidate %d/%d index=%d %s...\n', ...
        resultIdx, numel(candidateIndices), ...
        candidateIdx, record.proposalId);
    result = runArm( ...
        inputs, sourceState, protocol, ...
        'frozen-first-action', ...
        dataset.candidateAdjacency(:, :, candidateIdx), ...
        record.policyDetails, ...
        record.offlineProposalTruthUsed);
    result.mode = 'return-candidate';
    result.candidateIndex = candidateIdx;
    result.proposalId = record.proposalId;
    result.proposalAliases = record.proposalAliases;
    result.family = record.family;
    result.graphSha256 = record.graphSha256;
    result.offlineProposalTruthUsed = ...
        record.offlineProposalTruthUsed;
    candidateResults(resultIdx) = result;
    fprintfOutcome(result);
end

gitState = resolveResearchGitState();
shard = struct();
shard.contractVersion = ...
    'backbone-residual-return-headroom-shard-v1';
shard.protocolId = protocol.id;
shard.generatedAt = datestr(now, 31);
shard.batchIndex = batchIndex;
shard.batchCount = batchCount;
shard.candidateCount = candidateCount;
shard.candidateIndices = candidateIndices;
shard.controlsIncluded = batchIndex == 1;
shard.controls = controls;
shard.candidateResults = candidateResults;
shard.proposalDatasetPath = proposalPath;
shard.proposalDatasetSha256 = proposalSha256;
shard.sourceCacheSha256 = sourceState.cacheSha256;
shard.generationGitCommit = gitState.commit;
shard.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
shard.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
shard.commonRandomNumbers = true;
shard.bestCandidateSelectionUsesFutureOutcome = true;
shard.deployable = false;

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'returns', ...
        'backbone_residual_headroom_m24_h3_v1'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
stem = sprintf( ...
    'backbone_residual_return_m24_h3_b%02dof%02d', ...
    batchIndex, batchCount);
shardPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
shard.reportPath = reportPath;
save('-mat7-binary', shardPath, 'shard');
writeShardReport(reportPath, shard);
fprintf('Shard: %s\n', shardPath);
end

function result = runArm( ...
        inputs, sourceState, protocol, mode, ...
        frozenAdjacency, frozenDetails, offlineTruthUsed)
config = buildMixtureAwareKlaReferenceConfig();
config.filterInitialLocalPosteriorBySensor = ...
    sourceState.localPosteriors;
config.filterInitialLocalPosteriorTime = ...
    protocol.currentTime;
config.filterInitialPreviousAdjacencyHistory = ...
    sourceState.previousAdjacencyHistory;
config.filterInitialPreviousAdjacencyTimes = ...
    sourceState.previousAdjacencyHistoryTimes;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'backbone-residual-return-source-state-v1';
config.dynamicTopologyEdgeBudget = ...
    inputs.config.edgeBudget;
switch mode
    case 'local'
        config.eventPolicy = 'none';
    case 'fixed-index-w70'
        config = makeDirectedConfig(config, ...
            inputs.config.numberOfSensors, mode);
        config.topologyPolicyFcn = ...
            @(context) ...
                selectRegisteredDirectedRoutingPolicy( ...
                    context, 'fixed-index-star', ...
                    struct('sourceWeight', 0.70));
    case 'static-residual'
        config = makeDirectedConfig(config, ...
            2 * inputs.config.numberOfSensors, mode);
        config.topologyPolicyFcn = ...
            @(context) ...
                selectBackbonePreservingResidualControl( ...
                    context, residualOptions(protocol));
    case 'scheduled-residual'
        config = makeDirectedConfig(config, ...
            2 * inputs.config.numberOfSensors, mode);
        config.topologyPolicyFcn = ...
            @(context) selectContinuationPolicy( ...
                context, protocol);
    case 'analytic-residual'
        config = makeDirectedConfig(config, ...
            2 * inputs.config.numberOfSensors, mode);
        policyOptions = residualOptions(protocol);
        policyOptions.payloadToleranceFraction = ...
            protocol.payloadToleranceFraction;
        config.topologyPolicyFcn = ...
            @(context) ...
                selectBackbonePreservingResidualRoutingPolicy( ...
                    context, 'posterior-analytic', ...
                    policyOptions);
    case 'frozen-first-action'
        config = makeDirectedConfig(config, ...
            2 * inputs.config.numberOfSensors, mode);
        config.topologyPolicyFcn = ...
            @(context) frozenThenContinuation( ...
                context, frozenAdjacency, frozenDetails, ...
                offlineTruthUsed, protocol);
    otherwise
        error('Unknown return-headroom arm: %s', mode);
end

rng(protocol.seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);
times = protocol.horizonTimes;
selected = false(inputs.config.numberOfSensors, ...
    inputs.config.numberOfSensors, numel(times));
delivered = selected;
for timeIdx = 1:numel(times)
    selected(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, times(timeIdx)));
    delivered(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered(:, :, times(timeIdx)));
end
if strcmp(mode, 'frozen-first-action') && ...
        ~isequal(selected(:, :, 1), ...
            logical(frozenAdjacency))
    error('Frozen return candidate was not executed exactly.');
end
[selectedSensorPass, selectedFormationPass] = ...
    computeRollingPass( ...
        sourceState.previousAdjacencyHistory, ...
        selected, sourceState.groupIds);
[deliveredSensorPass, deliveredFormationPass] = ...
    computeRollingPass( ...
        sourceState.previousDeliveredAdjacencyHistory, ...
        delivered, sourceState.groupIds);

sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(times));
for sensorIdx = 1:sensorCount
    sensorEospa = computeSimulationOspa( ...
        inputs.model, inputs.groundTruthRfs, ...
        estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(times);
end
sensorMeans = mean(eospa, 2);
result = emptyArmResult();
result.meanEospa = mean(eospa(:));
result.worstSensorEospa = max(sensorMeans);
result.sensorMeanEospa = reshape(sensorMeans, 1, []);
result.eospaBySensorTime = eospa;
result.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes(:, :, times), 1), 2), ...
    1, []);
result.attemptedBytes = sum( ...
    result.attemptedBytesByTime);
result.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes(:, :, times), 1), 2), 1, []);
result.deliveredBytes = sum(result.deliveredBytesByTime);
result.selectedAdjacency = selected;
result.deliveredAdjacency = delivered;
result.selectedSensorB3Pass = selectedSensorPass;
result.selectedFormationB3Pass = ...
    selectedFormationPass;
result.deliveredSensorB3Pass = deliveredSensorPass;
result.deliveredFormationB3Pass = ...
    deliveredFormationPass;
result.repairVector = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(times));
result.repairCount = nnz(result.repairVector);
result.payloadEmergencyVector = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(times));
result.payloadEmergencyCount = nnz( ...
    result.payloadEmergencyVector);
result.infeasibleVector = logical( ...
    ~diagnostics.topologyFeasible(times) | ...
    finiteLogical( ...
        diagnostics.topologyPolicyTopologyInfeasible(times)));
result.infeasibleCount = nnz(result.infeasibleVector);
result.runtimeTruthUseVector = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(times));
result.runtimeTruthUseCount = nnz( ...
    result.runtimeTruthUseVector);
result.offlineProposalTruthUsed = offlineTruthUsed;
result.firstActionExact = ...
    ~strcmp(mode, 'frozen-first-action') || ...
    isequal(selected(:, :, 1), ...
        logical(frozenAdjacency));
result.elapsedSeconds = elapsedSeconds;
end

function config = makeDirectedConfig( ...
        config, messageBudget, policyName)
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = messageBudget;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = policyName;
config.topologyMaxEdgeChangeFraction = inf;
end

function options = residualOptions(protocol)
options = struct( ...
    'dominantWeight', protocol.dominantWeight, ...
    'residualWeight', protocol.residualWeight, ...
    'sourceWeight', protocol.residualWeight);
end

function [adjacency, details] = ...
    selectContinuationPolicy(context, protocol)
options = residualOptions(protocol);
options.rootFormation = ...
    protocol.continuationRootFormation;
options.orientation = ...
    protocol.continuationOrientation;
options.temporalPhase = ...
    protocol.continuationTemporalPhase;
options.payloadToleranceFraction = ...
    protocol.payloadToleranceFraction;
[adjacency, details] = ...
    selectBackbonePreservingResidualRoutingPolicy( ...
        context, protocol.continuationMode, options);
end

function [adjacency, details] = frozenThenContinuation( ...
        context, frozenAdjacency, frozenDetails, ...
        offlineTruthUsed, protocol)
if context.currentTime == protocol.currentTime
    adjacency = logical(frozenAdjacency);
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:)))
        error('Frozen residual return graph is not physically valid.');
    end
    details = frozenDetails;
    details.mode = 'frozen-backbone-residual-first-action';
    details.selectionSeconds = 0;
    details.truthUsed = false;
    details.groundTruthUsed = false;
    details.futureOutcomeUsed = false;
    details.offlineProposalTruthUsed = offlineTruthUsed;
    details.runtimeFrozenGraphReplay = true;
else
    [adjacency, details] = ...
        selectContinuationPolicy(context, protocol);
    details.offlineProposalTruthUsed = false;
    details.runtimeFrozenGraphReplay = false;
end
end

function [sensorPass, formationPass] = ...
    computeRollingPass(previousHistory, executed, groupIds)
depth = 2;
history = logical(previousHistory);
if size(history, 3) > depth
    history = history(:, :, end-depth+1:end);
end
stepCount = size(executed, 3);
sensorPass = false(1, stepCount);
formationPass = false(1, stepCount);
for stepIdx = 1:stepCount
    pages = cat(3, history, executed(:, :, stepIdx));
    window = any(pages(:, :, ...
        max(1, end - depth):end), 3);
    sensorPass(stepIdx) = ...
        isStronglyConnected(window);
    formationPass(stepIdx) = ...
        isStronglyConnected( ...
            collapseToFormations(window, groupIds));
    history(:, :, end + 1) = executed(:, :, stepIdx);
    if size(history, 3) > depth
        history = history(:, :, end-depth+1:end);
    end
end
end

function formationAdjacency = ...
    collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
formationAdjacency = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formationAdjacency(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formationAdjacency(1:numel(groups)+1:end) = false;
end

function valid = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
valid = true;
for startNode = 1:nodeCount
    visited = false(1, nodeCount);
    visited(startNode) = true;
    while true
        next = visited | any(adjacency(visited, :), 1);
        if isequal(next, visited)
            break;
        end
        visited = next;
    end
    if ~all(visited)
        valid = false;
        return;
    end
end
end

function inputs = cropInputs(inputs, maxTime)
inputs.measurements = inputs.measurements(:, 1:maxTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maxTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maxTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maxTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maxTime);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maxTime);
inputs.model.simulationLength = maxTime;
end

function values = finiteLogical(values)
values = isfinite(values) & values ~= 0;
end

function writeShardReport(path, shard)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open return-headroom shard report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Backbone residual H=3 return shard\n\n');
fprintf(fid, '- Protocol: `%s`\n', shard.protocolId);
fprintf(fid, '- Batch: `%d/%d`\n', ...
    shard.batchIndex, shard.batchCount);
fprintf(fid, '- Proposal SHA-256: `%s`\n\n', ...
    shard.proposalDatasetSha256);
fprintf(fid, ...
    '| Kind | Index | Proposal | E-OSPA | Worst | Bytes | B3 | Repair |\n');
fprintf(fid, '|---|---:|---|---:|---:|---:|---:|---:|\n');
for idx = 1:numel(shard.controls)
    row = shard.controls(idx);
    writeRow(fid, 'control', NaN, row.mode, row);
end
for idx = 1:numel(shard.candidateResults)
    row = shard.candidateResults(idx);
    writeRow(fid, 'candidate', row.candidateIndex, ...
        row.proposalId, row);
end
end

function writeRow(fid, kind, index, name, row)
fprintf(fid, '| %s | %.0f | `%s` | %.4f | %.4f | %.0f | %d | %d |\n', ...
    kind, index, name, row.meanEospa, ...
    row.worstSensorEospa, row.attemptedBytes, ...
    all(row.selectedSensorB3Pass) && ...
        all(row.selectedFormationB3Pass), ...
    row.repairCount);
end

function fprintfOutcome(row)
fprintf(['  E-OSPA %.4f, worst %.4f, bytes %.0f, ', ...
    'B3=%d, repair=%d, %.2f s\n'], ...
    row.meanEospa, row.worstSensorEospa, ...
    row.attemptedBytes, ...
    all(row.selectedSensorB3Pass) && ...
        all(row.selectedFormationB3Pass), ...
    row.repairCount, row.elapsedSeconds);
end

function validateProposalDataset(dataset, protocol)
required = { ...
    'contractVersion', 'protocolId', 'presetName', ...
    'seed', 'currentTime', 'candidateAdjacency', ...
    'candidateRecords', 'sourceCacheSha256'};
if ~isstruct(dataset) || ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.presetName, protocol.presetName) || ...
        dataset.seed ~= protocol.seed || ...
        dataset.currentTime ~= protocol.currentTime || ...
        size(dataset.candidateAdjacency, 3) ~= ...
            numel(dataset.candidateRecords) || ...
        isempty(dataset.candidateRecords) || ...
        dataset.futureOutcomeUsed || ...
        dataset.candidateRankingPerformed
    error('Residual return proposal dataset violates protocol.');
end
end

function value = validateInteger(value, name, minimum)
if ~isscalar(value) || ~isfinite(value) || ...
        value < minimum || value ~= round(value)
    error('%s must be an integer >= %d.', name, minimum);
end
end

function row = emptyArmResult()
row = struct( ...
    'mode', '', ...
    'candidateIndex', NaN, ...
    'proposalId', '', ...
    'proposalAliases', {{}}, ...
    'family', '', ...
    'graphSha256', '', ...
    'meanEospa', NaN, ...
    'worstSensorEospa', NaN, ...
    'sensorMeanEospa', [], ...
    'eospaBySensorTime', [], ...
    'attemptedBytesByTime', [], ...
    'attemptedBytes', NaN, ...
    'deliveredBytesByTime', [], ...
    'deliveredBytes', NaN, ...
    'selectedAdjacency', false(0), ...
    'deliveredAdjacency', false(0), ...
    'selectedSensorB3Pass', false(1, 0), ...
    'selectedFormationB3Pass', false(1, 0), ...
    'deliveredSensorB3Pass', false(1, 0), ...
    'deliveredFormationB3Pass', false(1, 0), ...
    'repairVector', false(1, 0), ...
    'repairCount', NaN, ...
    'payloadEmergencyVector', false(1, 0), ...
    'payloadEmergencyCount', NaN, ...
    'infeasibleVector', false(1, 0), ...
    'infeasibleCount', NaN, ...
    'runtimeTruthUseVector', false(1, 0), ...
    'runtimeTruthUseCount', NaN, ...
    'offlineProposalTruthUsed', false, ...
    'firstActionExact', false, ...
    'elapsedSeconds', NaN);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
