function [cachePaths, summary] = ...
    generateFormationH3ReferenceStateCaches( ...
        presetName, seed, snapshotTimes, options)
% GENERATEFORMATIONH3REFERENCESTATECACHES Fixed-reference state trajectory.
%
% Runs one truth-free fixed-reference filter trajectory and writes one
% standard predecision cache per requested time.  Future truth is never
% exposed to the topology policy or later feature context.

if nargin < 4 || isempty(options)
    options = struct();
end
defaultProtocol = getFormationH3MultiscaleTeacherProtocol();
protocol = getField(options, 'protocol', defaultProtocol);
validateProtocol(protocol, defaultProtocol.id);
if nargin < 3 || isempty(snapshotTimes)
    snapshotTimes = protocol.snapshotTimes;
end
snapshotTimes = reshape(snapshotTimes, 1, []);
if ~ischar(presetName) || ...
        ~ismember(presetName, protocol.presets) || ...
        ~isscalar(seed) || ~ismember(seed, protocol.allSeeds) || ...
        isempty(snapshotTimes) || ~issorted(snapshotTimes) || ...
        numel(unique(snapshotTimes)) ~= numel(snapshotTimes) || ...
        any(~ismember(snapshotTimes, protocol.snapshotTimes))
    error('Formation H=3 reference-cache request violates protocol.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
overwrite = logical(getField(options, 'overwrite', false));
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 cache generation requires clean source.');
end
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
maximumTime = max(snapshotTimes);
if maximumTime > size(inputs.measurements, 2)
    error('Formation H=3 snapshot time exceeds scenario length.');
end
cachePaths = cell(1, numel(snapshotTimes));
existingMask = false(1, numel(snapshotTimes));
for idx = 1:numel(snapshotTimes)
    cachePaths{idx} = fullfile(cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', ...
        strrep(presetName, '-', '_'), seed, snapshotTimes(idx)));
    existingMask(idx) = exist(cachePaths{idx}, 'file') == 2;
end
if ~overwrite && any(existingMask)
    if ~all(existingMask)
        error([ ...
            'Formation H=3 cache set is partial. Remove the partial ', ...
            'set or request an explicit overwrite.']);
    end
    cacheSha256 = cell(1, numel(snapshotTimes));
    elapsedSeconds = NaN;
    for idx = 1:numel(snapshotTimes)
        loaded = load(cachePaths{idx}, 'behaviorBundle');
        if ~isfield(loaded, 'behaviorBundle')
            error('Formation H=3 cache lacks behaviorBundle.');
        end
        bundle = loaded.behaviorBundle;
        required = { ...
            'presetName', 'seed', 'snapshotTimes', ...
            'configSnapshot', 'generationGitCommit', ...
            'policyTruthUsed', 'policyFutureOutcomeUsed'};
        protocolMatches = ...
            (isfield(bundle, 'protocolId') && ...
             strcmp(bundle.protocolId, protocol.id)) || ...
            (~isfield(bundle, 'protocolId') && ...
             strcmp(protocol.id, defaultProtocol.id));
        if ~all(isfield(bundle, required)) || ...
                ~protocolMatches || ...
                ~strcmp(bundle.presetName, presetName) || ...
                bundle.seed ~= seed || ...
                ~isequal(bundle.snapshotTimes, snapshotTimes(idx)) || ...
                ~isequaln(bundle.configSnapshot, inputs.config) || ...
                ~strcmp(bundle.generationGitCommit, gitState.commit) || ...
                bundle.policyTruthUsed || ...
                bundle.policyFutureOutcomeUsed
            error('Formation H=3 existing cache provenance mismatch.');
        end
        [posteriors, history] = ...
            extractBehaviorContinuationSnapshot( ...
                bundle, snapshotTimes(idx), ...
                inputs.config.numberOfSensors);
        if numel(posteriors) ~= inputs.config.numberOfSensors || ...
                history.snapshotTime ~= snapshotTimes(idx)
            error('Formation H=3 existing cache failed readback.');
        end
        cacheSha256{idx} = computeFileSha256(cachePaths{idx});
        if idx == 1 && isfield(bundle, 'behaviorSeconds')
            elapsedSeconds = bundle.behaviorSeconds;
        end
    end
    summary = buildSummary( ...
        protocol, presetName, seed, snapshotTimes, cachePaths, ...
        cacheSha256, elapsedSeconds, gitState, true);
    fprintf('Reused formation H=3 cache set: %s seed %d\n', ...
        presetName, seed);
    return;
end

cropped = cropInputs(inputs, maximumTime);
config = buildReferenceConfig( ...
    cropped.config, snapshotTimes, protocol);
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    cropped.model, cropped.measurements, ...
    cropped.sensorTrajectories, cropped.neighborMap, ...
    cropped.commConfig, config);
elapsedSeconds = toc(timerId);
auditRuntime(diagnostics, snapshotTimes);

cacheContract = behaviorContinuationCacheContract();
configSnapshot = config;
if isfield(configSnapshot, 'topologyPolicyFcn')
    configSnapshot = rmfield(configSnapshot, 'topologyPolicyFcn');
end
if exist(cacheRoot, 'dir') ~= 7
    mkdir(cacheRoot);
end
cacheSha256 = cell(1, numel(snapshotTimes));
for idx = 1:numel(snapshotTimes)
    currentTime = snapshotTimes(idx);
    if numel(diagnostics.topologyLocalPosteriorSnapshot) < currentTime || ...
            isempty(diagnostics.topologyLocalPosteriorSnapshot{currentTime})
        error('Formation H=3 reference trajectory missed a posterior snapshot.');
    end
    historyByTime = buildBehaviorContinuationHistoryRecords( ...
        diagnostics, currentTime, cacheContract.topologyHistoryDepth);
    posteriorSnapshots = cell(1, currentTime);
    posteriorSnapshots{currentTime} = ...
        diagnostics.topologyLocalPosteriorSnapshot{currentTime};
    behaviorBundle = struct( ...
        'cacheContractVersion', cacheContract.version, ...
        'posteriorSnapshotConvention', ...
            cacheContract.posteriorSnapshotConvention, ...
        'topologyHistoryDepth', cacheContract.topologyHistoryDepth, ...
        'topologyHistoryConvention', ...
            cacheContract.topologyHistoryConvention, ...
        'protocolId', protocol.id, ...
        'presetName', presetName, 'seed', seed, ...
        'snapshotTimes', currentTime, ...
        'configSnapshot', inputs.config, ...
        'behaviorConfigSnapshot', configSnapshot, ...
        'behaviorSeconds', elapsedSeconds, ...
        'behaviorEospaByTime', [], ...
        'behaviorCardinalityErrorByTime', [], ...
        'posteriorSnapshots', {posteriorSnapshots}, ...
        'preDecisionTopologyHistoryByTime', {historyByTime}, ...
        'generationGitCommit', gitState.commit, ...
        'generationTrackedWorktreeDirty', ...
            gitState.trackedWorktreeDirty, ...
        'generationUntrackedSourceFiles', ...
            {gitState.untrackedSourceFiles}, ...
        'referenceArmName', ...
            'formation-h3-fixed-ccw-reference-v1', ...
        'referenceReplayOnly', true, ...
        'policyTruthUsed', false, ...
        'policyFutureOutcomeUsed', false, ...
        'openedDevelopmentEvidenceOnly', true, ...
        'validationClaimAllowed', false, ...
        'evidenceBoundary', protocol.evidenceBoundary);
    save(cachePaths{idx}, 'behaviorBundle', '-v7');
    cacheSha256{idx} = computeFileSha256(cachePaths{idx});
    [posteriors, history] = extractBehaviorContinuationSnapshot( ...
        behaviorBundle, currentTime, inputs.config.numberOfSensors);
    if numel(posteriors) ~= inputs.config.numberOfSensors || ...
            history.snapshotTime ~= currentTime
        error('Formation H=3 generated cache failed readback.');
    end
    fprintf('  formation H=3 cache %s t=%d sha=%s\n', ...
        presetName, currentTime, cacheSha256{idx});
end

summary = buildSummary( ...
    protocol, presetName, seed, snapshotTimes, cachePaths, ...
    cacheSha256, elapsedSeconds, gitState, false);
end

function summary = buildSummary( ...
        protocol, presetName, seed, snapshotTimes, cachePaths, ...
        cacheSha256, elapsedSeconds, gitState, reusedExisting)
summary = struct();
summary.contractVersion = ...
    'formation-h3-reference-state-cache-summary-v1';
summary.protocolId = protocol.id;
summary.presetName = presetName;
summary.seed = seed;
summary.snapshotTimes = snapshotTimes;
summary.cachePaths = cachePaths;
summary.cacheSha256 = cacheSha256;
summary.elapsedSeconds = elapsedSeconds;
summary.generationGitCommit = gitState.commit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.reusedExisting = logical(reusedExisting);
summary.policyTruthUsed = false;
summary.policyFutureOutcomeUsed = false;
summary.openedDevelopmentEvidenceOnly = true;
summary.validationClaimAllowed = false;
summary.evidenceBoundary = protocol.evidenceBoundary;
end

function config = buildReferenceConfig( ...
        scenarioConfig, snapshotTimes, protocol)
baseProtocol = getLabelSetSimulatorPolicyProtocol();
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * scenarioConfig.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'formation-h3-fixed-ccw-reference-v1';
config.topologyPosteriorCaptureTimes = snapshotTimes;
policyOptions = struct( ...
    'dominantWeight', baseProtocol. ...
        adaptiveDominantJointTrustStabilityReferenceWeight, ...
    'residualWeight', baseProtocol. ...
        adaptiveDominantJointTrustStabilityResidualWeight);
config.topologyPolicyFcn = @(context) ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, 'fixed-counter-clockwise', policyOptions);
if protocol.filterSeedOffset ~= 100000
    error('Formation H=3 filter RNG protocol changed.');
end
end

function auditRuntime(diagnostics, snapshotTimes)
maximumTime = max(snapshotTimes);
times = 1:maximumTime;
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(times));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(times));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(times));
infeasible = logical( ...
    ~diagnostics.topologyFeasible(times) | ...
    finiteLogical(diagnostics. ...
        topologyPolicyTopologyInfeasible(times)));
if any(truthUse) || any(repair) || any(emergency) || any(infeasible)
    error('Formation H=3 reference trajectory violated a runtime gate.');
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
if isfield(inputs.commConfig, 'linkUniforms') && ...
        ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = ...
        inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function values = finiteLogical(values)
values = isfinite(values) & values ~= 0;
end

function validateProtocol(protocol, defaultProtocolId)
required = { ...
    'id', 'presets', 'allSeeds', 'snapshotTimes', ...
    'filterSeedOffset', 'cacheRoot', 'evidenceBoundary'};
allowedIds = { ...
    defaultProtocolId, ...
    'formation-h3-event-conditioned-sentinel-v1', ...
    'formation-staggered-recovery-x36-source-v37-v1'};
if ~isstruct(protocol) || ~all(isfield(protocol, required)) || ...
        ~ischar(protocol.id) || ...
        ~ismember(protocol.id, allowedIds) || ...
        ~iscell(protocol.presets) || isempty(protocol.presets) || ...
        isempty(protocol.allSeeds) || ...
        isempty(protocol.snapshotTimes) || ...
        protocol.filterSeedOffset ~= 100000 || ...
        ~ischar(protocol.cacheRoot) || ...
        ~ischar(protocol.evidenceBoundary)
    error('Formation H=3 cache protocol is invalid.');
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
