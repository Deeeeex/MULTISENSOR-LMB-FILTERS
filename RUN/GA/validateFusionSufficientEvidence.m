function [low, high] = pairedBootstrapMeanInterval(values, seed, count)
values = reshape(values, [], 1);
if isempty(values) || any(~isfinite(values))
    error('Attempted-byte reductions must be finite for bootstrapping.');
end
previousState = rng;
cleanup = onCleanup(@() rng(previousState)); %#ok<NASGU>
rng(seed);
indices = randi(numel(values), numel(values), count);
bootstrapMeans = mean(values(indices), 1);
low = percentileScalar(bootstrapMeans, 0.025);
high = percentileScalar(bootstrapMeans, 0.975);
end

function value = percentileScalar(values, probability)
values = sort(reshape(values, 1, []));
position = 1 + probability * (numel(values) - 1);
lowerIdx = floor(position);
upperIdx = ceil(position);
if lowerIdx == upperIdx
    value = values(lowerIdx);
else
    fraction = position - lowerIdx;
    value = values(lowerIdx) * (1 - fraction) + ...
        values(upperIdx) * fraction;
end
end

function value = maxFiniteAbs(values)
values = abs(values(isfinite(values)));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function mismatch = firstNumericMismatch(actual, expected)
if ~isequal(size(actual), size(expected))
    mismatch = 0;
    return;
end
equal = (actual == expected) | (isnan(actual) & isnan(expected));
mismatch = find(~equal, 1);
if isempty(mismatch)
    mismatch = 0;
end
end

function assertMachineString(text, key, expected)
actual = readMachineValue(text, key);
if ~strcmp(actual, char(expected))
    error('Evidence report field %s does not match.', key);
end
end

function assertMachineNumber(text, key, expected)
actualText = readMachineValue(text, key);
actual = str2double(actualText);
if ~isequaln(actual, double(expected))
    error('Evidence report numeric field %s does not match.', key);
end
end

function value = readMachineValue(text, key)
lines = strsplit(text, '\n');
prefix = [key, '='];
matches = {};
for lineIdx = 1:numel(lines)
    line = strtrim(lines{lineIdx});
    if length(line) >= length(prefix) && ...
            strncmp(line, prefix, length(prefix))
        matches{end+1} = line(length(prefix) + 1:end); %#ok<AGROW>
    end
end
if numel(matches) ~= 1
    error('Evidence report must contain exactly one %s field.', key);
end
value = matches{1};
end

function hashValue = sha256File(path)
command = sprintf('shasum -a 256 %s', shellQuote(path));
[status, output] = system(command);
if status ~= 0
    error('Unable to hash evidence file: %s', path);
end
match = regexp(lower(strtrim(output)), '^[0-9a-f]{64}', 'match', 'once');
if isempty(match)
    error('Invalid SHA-256 output for %s.', path);
end
hashValue = match;
end

function quoted = shellQuote(value)
value = char(value);
quoted = ['''', strrep(value, '''', '''"''"'''), ''''];
end

function assertReadableFile(path)
if exist(path, 'file') ~= 2
    error('Evidence file does not exist: %s', path);
end
