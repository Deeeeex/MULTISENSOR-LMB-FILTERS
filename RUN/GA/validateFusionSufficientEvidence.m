function validation = validateFusionSufficientEvidence( ...
    summaryPath, csvPath, reportPath, testAuthorization)
% VALIDATEFUSIONSUFFICIENTEVIDENCE Recompute and verify evidence artifacts.

if nargin < 4
    testAuthorization = struct();
end

assertReadableFile(summaryPath);
assertReadableFile(csvPath);
assertReadableFile(reportPath);
loaded = load(summaryPath);
if ~isfield(loaded, 'summary') || ~isfield(loaded, 'config')
    error('Evidence MAT must contain summary and config.');
end
summary = loaded.summary;
config = loaded.config;
validateConfigAndSummary(summary, config, testAuthorization);

expectedRows = buildEvidenceRows(summary);
[actualHeaders, actualRows] = readEvidenceCsv(csvPath);
expectedHeaders = evidenceHeaders();
if ~isequal(actualHeaders, expectedHeaders)
    error('Evidence CSV header does not match schema.');
end
if ~isequaln(actualRows, expectedRows)
    mismatch = firstNumericMismatch(actualRows, expectedRows);
    if mismatch == 0
        error('Evidence CSV dimensions do not match expected rows.');
    end
    [rowIdx, columnIdx] = ind2sub(size(expectedRows), mismatch);
    error(['Evidence CSV mismatch at row %d column %d: ', ...
        'actual %.17g, expected %.17g.'], ...
        rowIdx, columnIdx, actualRows(rowIdx, columnIdx), ...
        expectedRows(rowIdx, columnIdx));
end

aggregate = computeAggregate(expectedRows, config);
reportText = fileread(reportPath);
actualSummaryHash = sha256File(summaryPath);
actualCsvHash = sha256File(csvPath);
stableSummaryPath = ['RUN/GA/', config.artifactStem, '.mat'];
stableCsvPath = ['RUN/GA/', config.artifactStem, '.csv'];
expectedReportText = renderFusionSufficientEvidenceReport( ...
    stableSummaryPath, stableCsvPath, actualSummaryHash, actualCsvHash, ...
    expectedRows, aggregate, config);
if ~isequal(uint8(reportText), uint8(expectedReportText))
    error(['Evidence Markdown differs from the canonical deterministic ', ...
        'report rendering.']);
end
assertMachineString(reportText, 'evidence_schema', ...
    config.evidenceSchema);
assertMachineNumber(reportText, 'test_only', double(config.testOnly));
assertMachineString(reportText, 'git_commit', config.gitCommit);
assertMachineString(reportText, 'batch_identity', config.batchIdentity);
assertMachineString(reportText, 'artifact_stem', config.artifactStem);
assertMachineNumber(reportText, 'wire_schema_version', ...
    config.wireSchemaVersion);
assertMachineString(reportText, 'execution_protocol', ...
    config.executionProtocol);
assertMachineString(reportText, 'octave_version', config.octaveVersion);
assertMachineNumber(reportText, 'max_workers', config.maxWorkers);
assertMachineString(reportText, 'config_sha256', config.configSha256);
assertMachineString(reportText, 'required_sources_sha256', ...
    config.requiredSourcesSha256);
assertMachineNumber(reportText, 'number_of_trials', ...
    config.numberOfTrials);
assertMachineNumber(reportText, 'base_seed', config.baseSeed);
assertMachineNumber(reportText, 'first_seed', config.firstSeed);
assertMachineNumber(reportText, 'last_seed', config.lastSeed);
assertMachineNumber(reportText, 'simulation_length', ...
    config.simulationLength);
assertMachineNumber(reportText, 'bootstrap_seed', config.bootstrapSeed);
assertMachineNumber(reportText, 'bootstrap_resamples', ...
    config.bootstrapResamples);
fields = fieldnames(aggregate);
for fieldIdx = 1:numel(fields)
    assertMachineNumber(reportText, ...
        ['aggregate_', fields{fieldIdx}], aggregate.(fields{fieldIdx}));
end

assertMachineString(reportText, 'summary_sha256', actualSummaryHash);
assertMachineString(reportText, 'csv_sha256', actualCsvHash);

validation = struct( ...
    'valid', true, ...
    'numberOfTrials', config.numberOfTrials, ...
    'gitCommit', config.gitCommit, ...
    'summarySha256', actualSummaryHash, ...
    'csvSha256', actualCsvHash, ...
    'aggregate', aggregate);
end

function validateConfigAndSummary(summary, config, testAuthorization)
requiredConfig = {'evidenceSchema', 'workerSchema', 'executionProtocol', ...
    'testOnly', ...
    'wireSchemaVersion', 'gitCommit', 'requiredSourcesSha256', ...
    'configSha256', 'batchIdentity', 'maxWorkers', 'octaveExecutable', ...
    'octaveVersion', 'executionLogicalCores', 'executionMemoryGiB', ...
    'estimatedSingleWorkerMemoryMiB', ...
    'numberOfTrials', 'baseSeed', 'firstSeed', 'lastSeed', ...
    'armSelection', 'internalArmSelectors', 'simulationLength', ...
    'includeDynamicTopologyVariants', ...
    'lightCovarianceInflationEnabled', 'modeAwareFusionWeights', ...
    'capturePosteriorSnapshots', 'skipCalibrationForStaticPair', ...
    'requiredMaxExistenceResidual', 'requiredMaxMeanResidual', ...
    'requiredMaxCovarianceResidual', 'bootstrapSeed', ...
    'bootstrapResamples', 'artifactStem', 'isSmoke', ...
    'includeFinalPeriodicLightVariants', 'primaryMetric', ...
    'byteSemantics', 'changedVariable'};
for fieldIdx = 1:numel(requiredConfig)
    if ~isfield(config, requiredConfig{fieldIdx})
        error('Evidence config is missing %s.', requiredConfig{fieldIdx});
    end
end
testMode = isFusionSufficientInternalTestAuthorization(testAuthorization);
if testMode
    validSchema = isequal(config.testOnly, true) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-test-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-test-v2') && ...
        strncmp(config.artifactStem, 'TEST_', 5) && ...
        strncmp(config.batchIdentity, 'test-', 5);
else
    validSchema = isequal(config.testOnly, false) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-v2');
end
if ~validSchema
    error('Unsupported or unauthorized evidence/test schema.');
end
if ~testMode
    assertFusionSufficientConfigProvenance(config);
end
if ~strcmp(config.executionProtocol, ...
        'deterministic-seed-subprocess-v2') || ...
        config.maxWorkers ~= 6 || ...
        ~strcmp(config.octaveExecutable, 'octave-cli') || ...
        ~strcmp(config.octaveVersion, '11.1.0') || ...
        config.executionLogicalCores ~= 10 || ...
        config.executionMemoryGiB ~= 16 || ...
        config.estimatedSingleWorkerMemoryMiB ~= 110
    error('Evidence execution environment differs from frozen v2.');
end
if isempty(regexp(config.requiredSourcesSha256, ...
        '^[0-9a-f]{64}$', 'once')) || ...
        isempty(regexp(config.configSha256, ...
        '^[0-9a-f]{64}$', 'once')) || ...
        ~strcmp(hashFusionSufficientConfig(config), config.configSha256)
    error('Evidence config/source SHA-256 is invalid.');
end
scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDir));
currentSourceHash = hashFusionSufficientRequiredSources(projectRoot);
if ~strcmp(currentSourceHash, config.requiredSourcesSha256)
    error(['Current required-source manifest differs from the evidence ', ...
        'provenance.']);
end
wireSchema = getLmbWireSchema();
if config.wireSchemaVersion ~= double(wireSchema.version)
    error('Wire schema version mismatch.');
end
if isempty(regexp(config.gitCommit, '^[0-9a-f]{40}$', 'once'))
    error('Invalid evidence Git commit.');
end
expectedArms = { ...
    'Periodic full GM fusion message', ...
    'Periodic moment message on static topology'};
expectedLegacyLookup = { ...
    'Periodic full posterior', ...
    'Periodic light posterior on static topology'};
if ~isequal(config.armSelection, expectedArms) || ...
        ~isequal(summary.armNames, expectedArms) || ...
        ~isequal(config.internalArmSelectors, expectedLegacyLookup)
    error('Evidence arms differ from the frozen pair.');
end
if config.numberOfTrials ~= summary.numberOfTrials || ...
        config.firstSeed ~= config.baseSeed + 1 || ...
        config.lastSeed ~= config.baseSeed + config.numberOfTrials || ...
        ~isequal(summary.trialSeeds, config.firstSeed:config.lastSeed)
    error('Evidence seed interval is inconsistent.');
end
if ~testMode && ...
        ~(config.numberOfTrials == 50 && config.baseSeed == 81) && ...
        ~(config.numberOfTrials == 5 && config.baseSeed == 1000)
    error('Evidence is neither the frozen N50 nor the permitted N5 smoke.');
end
isSmoke = config.numberOfTrials == 5;
if ~islogical(config.isSmoke) || ~isscalar(config.isSmoke)
    error('Evidence isSmoke must be a scalar logical.');
end
if testMode
    expectedStem = config.artifactStem;
    expectedBatchIdentity = config.batchIdentity;
elseif isSmoke
    expectedStem = ...
        'GA_FUSION_SUFFICIENT_MOMENT_EXCHANGE_V2_N5_SEEDS1001_1005';
    expectedBatchIdentity = 'smoke-seeds1001-1005-v2';
else
    expectedStem = ...
        'GA_FUSION_SUFFICIENT_MOMENT_EXCHANGE_N50_SEEDS82_131';
    expectedBatchIdentity = 'confirmatory-primary-seeds82-131-v2';
end
if logical(config.isSmoke) ~= isSmoke || ...
        ~strcmp(config.artifactStem, expectedStem) || ...
        ~strcmp(config.batchIdentity, expectedBatchIdentity)
    error('Evidence artifact stem does not match the frozen batch.');
end
if config.simulationLength ~= 100 || ...
        summary.scenarioConfig.simulationLength ~= 100 || ...
        summary.scenarioConfig.numberOfSensors ~= 8
    error('Evidence scenario must use eight sensors and 100 time steps.');
end
if ~config.includeFinalPeriodicLightVariants || ...
        config.includeDynamicTopologyVariants || ...
        config.lightCovarianceInflationEnabled || ...
        config.modeAwareFusionWeights || ...
        ~config.capturePosteriorSnapshots || ...
        ~config.skipCalibrationForStaticPair
    error('Evidence configuration violates the frozen isolation rules.');
end
if ~strcmp(config.primaryMetric, ...
        'paired attempted application-layer byte reduction per seed') || ...
        ~strcmp(config.changedVariable, ...
        'sender-side canonical moment projection before encoding') || ...
        isempty(strfind(config.byteSemantics, ...
        'Encoded application-layer bytes only')) %#ok<STREMP>
    error('Evidence metric or byte semantics differ from the protocol.');
end
if config.requiredMaxExistenceResidual ~= 0 || ...
        config.requiredMaxMeanResidual ~= 0 || ...
        config.requiredMaxCovarianceResidual ~= 0 || ...
        config.bootstrapSeed ~= 20270710 || ...
        config.bootstrapResamples ~= 10000
    error('Evidence residual or bootstrap settings are not frozen.');
end
if ~summary.equivalence.captured
    error('Posterior equivalence snapshots were not captured.');
end
validateExecution(summary, config);

requiredTrialFields = {'localEOspa', 'consensusOspa', ...
    'consensusPosition', 'consensusCardinality', ...
    'attemptedPayloadBytes', 'deliveredPayloadBytes', ...
    'attemptedMask', 'deliveredMask', ...
    'posteriorMissingSnapshotCount', ...
    'posteriorLabelSetMismatchCount', 'posteriorMissingLabelCount', ...
    'posteriorComparisonCount', 'posteriorSnapshotCount', ...
    'posteriorMaxAbsR', ...
    'posteriorMaxAbsMu', 'posteriorMaxAbsSigma', ...
    'posteriorExactMatch'};
for fieldIdx = 1:numel(requiredTrialFields)
    if ~isfield(summary.trials, requiredTrialFields{fieldIdx})
        error('Evidence trials are missing %s.', ...
            requiredTrialFields{fieldIdx});
    end
end
if ~isequal(size(summary.trials.localEOspa), ...
        [config.numberOfTrials, 8, 2])
    error('Evidence local E-OSPA array must be N-by-8-by-2.');
end
twoColumnFields = {'consensusOspa', 'consensusPosition', ...
    'consensusCardinality', 'attemptedPayloadBytes', ...
    'deliveredPayloadBytes', 'posteriorMissingSnapshotCount', ...
    'posteriorLabelSetMismatchCount', 'posteriorMissingLabelCount', ...
    'posteriorComparisonCount', 'posteriorSnapshotCount', ...
    'posteriorMaxAbsR', 'posteriorMaxAbsMu', ...
    'posteriorMaxAbsSigma', 'posteriorExactMatch'};
for fieldIdx = 1:numel(twoColumnFields)
    if ~isequal(size(summary.trials.(twoColumnFields{fieldIdx})), ...
            [config.numberOfTrials, 2])
        error('Evidence trial field %s must be N-by-2.', ...
            twoColumnFields{fieldIdx});
    end
end
finiteTrackingFields = {'localEOspa', 'consensusOspa', ...
    'consensusPosition', 'consensusCardinality'};
for fieldIdx = 1:numel(finiteTrackingFields)
    values = summary.trials.(finiteTrackingFields{fieldIdx});
    if ~isnumeric(values) || ~isreal(values) || ...
            any(~isfinite(values(:)))
        error('Evidence tracking field %s must be finite real numeric.', ...
            finiteTrackingFields{fieldIdx});
    end
end
if ~isequal(size(summary.trials.attemptedPayloadBytes), ...
        [config.numberOfTrials, 2]) || ...
        ~isequal(size(summary.trials.deliveredPayloadBytes), ...
        [config.numberOfTrials, 2])
    error('Evidence byte arrays have invalid dimensions.');
end
if ~iscell(summary.trials.attemptedMask) || ...
        ~iscell(summary.trials.deliveredMask) || ...
        ~isequal(size(summary.trials.attemptedMask), ...
        [config.numberOfTrials, 2]) || ...
        ~isequal(size(summary.trials.deliveredMask), ...
        [config.numberOfTrials, 2])
    error('Evidence delivery-mask cells have invalid dimensions.');
end
validateByteArrays(summary.trials.attemptedPayloadBytes, ...
    summary.trials.deliveredPayloadBytes);
attemptedReduction = 100 * ( ...
    summary.trials.attemptedPayloadBytes(:, 1) - ...
    summary.trials.attemptedPayloadBytes(:, 2)) ./ ...
    summary.trials.attemptedPayloadBytes(:, 1);
if any(~isfinite(attemptedReduction)) || any(attemptedReduction <= 0)
    error('Every seed must have a positive attempted-byte reduction.');
end

for armIdx = 1:2
    trigger = summary.arms(armIdx).triggerConfig;
    if ~trigger.capturePosteriorSnapshots || ...
            trigger.linkGateEnabled || ...
            trigger.forceInitialHeavy || ...
            trigger.forceLabelChangeHeavy || ...
            trigger.forceStaleHeavy || ...
            trigger.useStaleNeighborCache || ...
            trigger.labelHeartbeatEnabled || ...
            trigger.mixedPayloadEnabled || ...
            trigger.mixedPayloadLightForAllActiveLabels || ...
            trigger.dynamicTopologyEnabled || ...
            trigger.modeAwareFusionWeights || ...
            trigger.lightCovarianceInflationEnabled || ...
            trigger.lightFusionWeightFactor ~= ...
                trigger.heavyFusionWeightFactor
        error('An arm violates the frozen trigger configuration.');
    end
end
if ~strcmp(summary.arms(1).triggerConfig.eventPolicy, 'alwaysHeavy') || ...
        ~strcmp(summary.arms(2).triggerConfig.eventPolicy, 'alwaysLight')
    error('Frozen arms must be full alwaysHeavy and moment alwaysLight.');
end
fullTrigger = rmfield(summary.arms(1).triggerConfig, 'eventPolicy');
momentTrigger = rmfield(summary.arms(2).triggerConfig, 'eventPolicy');
if ~isequaln(orderfields(fullTrigger), orderfields(momentTrigger))
    error(['Frozen trigger configs must be structurally identical after ', ...
        'removing eventPolicy.']);
end
for trialIdx = 1:config.numberOfTrials
    validateMask(summary.trials.attemptedMask{trialIdx, 1}, ...
        summary.scenarioConfig, 'attempted', trialIdx, 1);
    validateMask(summary.trials.attemptedMask{trialIdx, 2}, ...
        summary.scenarioConfig, 'attempted', trialIdx, 2);
    validateMask(summary.trials.deliveredMask{trialIdx, 1}, ...
        summary.scenarioConfig, 'delivered', trialIdx, 1);
    validateMask(summary.trials.deliveredMask{trialIdx, 2}, ...
        summary.scenarioConfig, 'delivered', trialIdx, 2);
    if ~isequal(summary.trials.attemptedMask{trialIdx, 1}, ...
            summary.trials.attemptedMask{trialIdx, 2})
        error('Attempted masks differ at trial %d.', trialIdx);
    end
    if ~isequal(summary.trials.deliveredMask{trialIdx, 1}, ...
            summary.trials.deliveredMask{trialIdx, 2})
        error('Delivered masks differ at trial %d.', trialIdx);
    end
end
expectedSnapshotCount = summary.scenarioConfig.numberOfSensors * ...
    summary.scenarioConfig.simulationLength;
if any(summary.trials.posteriorSnapshotCount(:) ~= ...
        expectedSnapshotCount)
    error('Every arm/trial must compare exactly S*T posterior snapshots.');
end
if any(summary.trials.posteriorMissingSnapshotCount(:, 2) ~= 0) || ...
        any(summary.trials.posteriorLabelSetMismatchCount(:, 2) ~= 0) || ...
        any(summary.trials.posteriorMissingLabelCount(:, 2) ~= 0) || ...
        any(summary.trials.posteriorMaxAbsR(:, 2) ~= 0) || ...
        any(summary.trials.posteriorMaxAbsMu(:, 2) ~= 0) || ...
        any(summary.trials.posteriorMaxAbsSigma(:, 2) ~= 0) || ...
        ~all(summary.trials.posteriorExactMatch(:, 2))
    error('Posterior equivalence gate failed.');
end
validateStoredAggregate(summary);
end

function validateExecution(summary, config)
if ~isfield(summary, 'execution') || ~isstruct(summary.execution)
    error('Evidence summary lacks parallel execution provenance.');
end
execution = summary.execution;
required = {'protocol', 'workerSchema', 'maxWorkers', ...
    'octaveVersion', 'configSha256', 'requiredSourcesSha256', ...
    'batchIdentity', 'planSha256', 'exitLedgerSha256', ...
    'launcherCapabilitySha256', 'completionTokenSha256', ...
    'batchSuccessReceiptSha256', ...
    'receiptValidated', 'workerSeeds', 'workerMatSha256', ...
    'workerLogSha256'};
for fieldIdx = 1:numel(required)
    if ~isfield(execution, required{fieldIdx})
        error('Execution provenance is missing %s.', required{fieldIdx});
    end
end
if ~strcmp(execution.protocol, config.executionProtocol) || ...
        ~strcmp(execution.workerSchema, config.workerSchema) || ...
        execution.maxWorkers ~= config.maxWorkers || ...
        ~strcmp(execution.octaveVersion, config.octaveVersion) || ...
        ~strcmp(execution.configSha256, config.configSha256) || ...
        ~strcmp(execution.requiredSourcesSha256, ...
        config.requiredSourcesSha256) || ...
        ~strcmp(execution.batchIdentity, config.batchIdentity) || ...
        ~isequal(execution.receiptValidated, true) || ...
        ~isequal(execution.workerSeeds, ...
        config.firstSeed:config.lastSeed) || ...
        ~iscell(execution.workerMatSha256) || ...
        ~iscell(execution.workerLogSha256) || ...
        numel(execution.workerMatSha256) ~= config.numberOfTrials || ...
        numel(execution.workerLogSha256) ~= config.numberOfTrials
    error('Parallel execution provenance differs from frozen config.');
end
topHashes = {execution.planSha256, execution.exitLedgerSha256, ...
    execution.launcherCapabilitySha256, ...
    execution.completionTokenSha256, ...
    execution.batchSuccessReceiptSha256};
for hashIdx = 1:numel(topHashes)
    if isempty(regexp(topHashes{hashIdx}, '^[0-9a-f]{64}$', 'once'))
        error('Execution SHA-256 entry %d is invalid.', hashIdx);
    end
end
for hashIdx = 1:numel(execution.workerMatSha256)
    if isempty(regexp(execution.workerMatSha256{hashIdx}, ...
            '^[0-9a-f]{64}$', 'once')) || ...
            isempty(regexp(execution.workerLogSha256{hashIdx}, ...
            '^[0-9a-f]{64}$', 'once'))
        error('Worker artifact SHA-256 entry %d is invalid.', hashIdx);
    end
end
end

function validateByteArrays(attempted, delivered)
if ~isnumeric(attempted) || ~isnumeric(delivered) || ...
        ~isreal(attempted) || ~isreal(delivered) || ...
        any(~isfinite(attempted(:))) || any(~isfinite(delivered(:))) || ...
        any(attempted(:) < 0) || any(delivered(:) < 0) || ...
        any(attempted(:) ~= floor(attempted(:))) || ...
        any(delivered(:) ~= floor(delivered(:)))
    error(['Attempted and delivered bytes must be finite, nonnegative ', ...
        'integer-valued numeric arrays.']);
end
if any(attempted(:) <= 0)
    error('Both arms must attempt a positive number of bytes per seed.');
end
if any(delivered(:) > attempted(:))
    error('Delivered bytes exceed attempted bytes.');
end
end

function validateMask(mask, scenario, kind, trialIdx, armIdx)
expectedSize = [scenario.numberOfSensors, ...
    scenario.numberOfSensors, scenario.simulationLength];
if ~islogical(mask) || ~isequal(size(mask), expectedSize)
    error(['%s mask at trial %d arm %d must be a logical ', ...
        'S-by-S-by-T array.'], kind, trialIdx, armIdx);
end
end

function validateStoredAggregate(summary)
if ~strcmp(summary.equivalence.baselineArm, ...
        'Periodic full GM fusion message')
    error('Stored posterior aggregate has the wrong baseline arm.');
end
expectedMismatch = sum( ...
    summary.trials.posteriorLabelSetMismatchCount, 1);
expectedMissingSnapshots = sum( ...
    summary.trials.posteriorMissingSnapshotCount, 1);
expectedMissingLabels = sum( ...
    summary.trials.posteriorMissingLabelCount, 1);
expectedComparisons = sum(summary.trials.posteriorComparisonCount, 1);
expectedSnapshots = sum(summary.trials.posteriorSnapshotCount, 1);
expectedMaxR = max(summary.trials.posteriorMaxAbsR, [], 1);
expectedMaxMu = max(summary.trials.posteriorMaxAbsMu, [], 1);
expectedMaxSigma = max(summary.trials.posteriorMaxAbsSigma, [], 1);
expectedExact = all(summary.trials.posteriorExactMatch, 1);
if ~isequal(summary.equivalence.missingSnapshotCount, ...
        expectedMissingSnapshots) || ...
        ~isequal(summary.equivalence.labelSetMismatchCount, ...
        expectedMismatch) || ...
        ~isequal(summary.equivalence.missingLabelCount, ...
        expectedMissingLabels) || ...
        ~isequal(summary.equivalence.comparisonCount, ...
        expectedComparisons) || ...
        ~isequal(summary.equivalence.snapshotCount, ...
        expectedSnapshots) || ...
        ~isequal(summary.equivalence.maxAbsR, expectedMaxR) || ...
        ~isequal(summary.equivalence.maxAbsMu, expectedMaxMu) || ...
        ~isequal(summary.equivalence.maxAbsSigma, expectedMaxSigma) || ...
        ~isequal(summary.equivalence.exactMatch, expectedExact)
    error('Stored posterior aggregate is inconsistent with trials.');
end
end

function rows = buildEvidenceRows(summary)
numberOfTrials = summary.numberOfTrials;
rows = zeros(numberOfTrials, 30);
for trialIdx = 1:numberOfTrials
    fullAttempted = summary.trials.attemptedPayloadBytes(trialIdx, 1);
    momentAttempted = summary.trials.attemptedPayloadBytes(trialIdx, 2);
    fullDelivered = summary.trials.deliveredPayloadBytes(trialIdx, 1);
    momentDelivered = summary.trials.deliveredPayloadBytes(trialIdx, 2);
    if ~(isfinite(fullAttempted) && fullAttempted > 0)
        error('Full arm attempted bytes must be positive for every seed.');
    end
    localFull = mean(summary.trials.localEOspa(trialIdx, :, 1));
    localMoment = mean(summary.trials.localEOspa(trialIdx, :, 2));
    consensusFull = summary.trials.consensusOspa(trialIdx, 1);
    consensusMoment = summary.trials.consensusOspa(trialIdx, 2);
    positionFull = summary.trials.consensusPosition(trialIdx, 1);
    positionMoment = summary.trials.consensusPosition(trialIdx, 2);
    cardinalityFull = summary.trials.consensusCardinality(trialIdx, 1);
    cardinalityMoment = ...
        summary.trials.consensusCardinality(trialIdx, 2);
    rows(trialIdx, :) = [ ...
        summary.trialSeeds(trialIdx), ...
        fullAttempted, momentAttempted, ...
        percentReduction(fullAttempted, momentAttempted), ...
        fullDelivered, momentDelivered, ...
        percentReduction(fullDelivered, momentDelivered), ...
        localFull, localMoment, localMoment - localFull, ...
        consensusFull, consensusMoment, ...
        consensusMoment - consensusFull, ...
        positionFull, positionMoment, positionMoment - positionFull, ...
        cardinalityFull, cardinalityMoment, ...
        cardinalityMoment - cardinalityFull, ...
        summary.trials.posteriorMissingSnapshotCount(trialIdx, 2), ...
        summary.trials.posteriorLabelSetMismatchCount(trialIdx, 2), ...
        summary.trials.posteriorMissingLabelCount(trialIdx, 2), ...
        summary.trials.posteriorComparisonCount(trialIdx, 2), ...
        summary.trials.posteriorSnapshotCount(trialIdx, 2), ...
        summary.trials.posteriorMaxAbsR(trialIdx, 2), ...
        summary.trials.posteriorMaxAbsMu(trialIdx, 2), ...
        summary.trials.posteriorMaxAbsSigma(trialIdx, 2), ...
        double(summary.trials.posteriorExactMatch(trialIdx, 2)), ...
        double(isequal(summary.trials.attemptedMask{trialIdx, 1}, ...
            summary.trials.attemptedMask{trialIdx, 2})), ...
        double(isequal(summary.trials.deliveredMask{trialIdx, 1}, ...
            summary.trials.deliveredMask{trialIdx, 2}))];
end
end

function value = percentReduction(fullValue, momentValue)
if fullValue == 0
    if momentValue == 0
        value = 0;
    else
        value = NaN;
    end
else
    value = 100 * (fullValue - momentValue) / fullValue;
end
end

function [headers, rows] = readEvidenceCsv(path)
text = fileread(path);
lines = regexp(text, '\r?\n', 'split');
if isempty(lines) || isempty(lines{1})
    error('Evidence CSV is empty.');
end
headers = strsplit(strtrim(lines{1}), ',');
columnCount = numel(headers);
dataLines = lines(2:end);
while ~isempty(dataLines) && isempty(strtrim(dataLines{end}))
    dataLines(end) = [];
end
rows = zeros(numel(dataLines), columnCount);
for rowIdx = 1:numel(dataLines)
    tokens = strsplit(strtrim(dataLines{rowIdx}), ',');
    if numel(tokens) ~= columnCount
        error('Evidence CSV row %d has an invalid column count.', rowIdx);
    end
    for columnIdx = 1:columnCount
        value = str2double(tokens{columnIdx});
        if isnan(value) && ~strcmpi(strtrim(tokens{columnIdx}), 'nan')
            error('Evidence CSV row %d column %d is not numeric.', ...
                rowIdx, columnIdx);
        end
        rows(rowIdx, columnIdx) = value;
    end
end
end

function headers = evidenceHeaders()
headers = { ...
    'seed', ...
    'full_attempted_bytes', 'moment_attempted_bytes', ...
    'attempted_reduction_percent', ...
    'full_delivered_bytes', 'moment_delivered_bytes', ...
