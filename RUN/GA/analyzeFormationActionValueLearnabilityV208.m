function [reportPath, result] = ...
        analyzeFormationActionValueLearnabilityV208(options)
% ANALYZEFORMATIONACTIONVALUELEARNABILITYV208 Leave-one-page-out probe.
%
% Shared two-round graph encoders are randomly initialized and frozen.  A
% ridge readout is fitted on seven complete pages and evaluated on the
% eighth.  This asks whether the truth-free representation carries action
% value, not whether the final controller has been trained or validated.

if nargin < 1 || isempty(options)
    options = struct();
end
datasetPath = getField(options, 'datasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v208', ...
    'formation_label_kla_immediate_merged', ...
    'x36_seed211_t72_h8', ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208_MERGED.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v208', ...
    'formation_action_value_learnability', ...
    'x36_seed211_t72_h8'));
encoderSeeds = reshape(getField(options, ...
    'encoderSeeds', 2081:2085), 1, []);
hiddenWidth = getField(options, 'hiddenWidth', 16);
ridgeLambda = getField(options, 'ridgeLambda', 10);
uncertaintyMultiplier = getField( ...
    options, 'uncertaintyMultiplier', 0.5);
if exist(datasetPath, 'file') ~= 2 || ...
        isempty(encoderSeeds) || ...
        numel(unique(encoderSeeds)) ~= numel(encoderSeeds) || ...
        any(~isfinite(encoderSeeds)) || ...
        any(encoderSeeds ~= round(encoderSeeds)) || ...
        ~isscalar(hiddenWidth) || hiddenWidth < 2 || ...
        hiddenWidth ~= round(hiddenWidth) || ...
        ~isscalar(ridgeLambda) || ~isfinite(ridgeLambda) || ...
        ridgeLambda <= 0 || ...
        ~isscalar(uncertaintyMultiplier) || ...
        ~isfinite(uncertaintyMultiplier) || ...
        uncertaintyMultiplier < 0
    error('FormationActionLearnabilityV208:InvalidRequest', ...
        'A merged dataset and valid frozen-probe options are required.');
end

loaded = load(datasetPath, 'dataset');
dataset = loaded.dataset;
validateDataset(dataset);
predictionTargetIndices = [1, 2, 3, 5, 6, 7, 8, 9, 10];
predictionTargetNames = ...
    dataset.targetNames(predictionTargetIndices);
blockCount = dataset.blockCount;
folds = repmat(emptyFold(), 1, blockCount);
allPrediction = nan(dataset.rowCount, ...
    numel(predictionTargetIndices));
allScore = nan(dataset.rowCount, 1);
allStrict = false(dataset.rowCount, 1);

for heldoutBlock = 1:blockCount
    fprintf('V208 learnability fold %d/%d: hold t=%d ...\n', ...
        heldoutBlock, blockCount, ...
        dataset.blocks(heldoutBlock).currentTime);
    trainingBlocks = setdiff(1:blockCount, heldoutBlock);
    trainingMask = ismember( ...
        [dataset.rows.blockId], trainingBlocks);
    heldoutMask = [dataset.rows.blockId] == heldoutBlock;
    trainingRows = dataset.rows(trainingMask);
    heldoutRows = dataset.rows(heldoutMask);
    trainingTargets = vertcat(trainingRows.targets);
    trainingTargets = ...
        trainingTargets(:, predictionTargetIndices);
    heldoutTargetsFull = vertcat(heldoutRows.targets);
    heldoutTargets = ...
        heldoutTargetsFull(:, predictionTargetIndices);
    targetScale = std(trainingTargets, 0, 1);
    targetScale(~isfinite(targetScale) | targetScale <= eps) = 1;

    ensemblePrediction = zeros(numel(heldoutRows), ...
        numel(predictionTargetIndices), numel(encoderSeeds));
    for seedIdx = 1:numel(encoderSeeds)
        encoder = initializeEncoder(dataset, trainingBlocks, ...
            trainingRows, encoderSeeds(seedIdx), hiddenWidth);
        trainingFeatures = encodeBlocks( ...
            dataset, trainingBlocks, encoder);
        heldoutFeatures = encodeBlocks( ...
            dataset, heldoutBlock, encoder);
        model = fitRidgeReadout( ...
            trainingFeatures, trainingTargets, ridgeLambda);
        ensemblePrediction(:, :, seedIdx) = ...
            predictRidgeReadout(model, heldoutFeatures);
    end
    predictionMean = mean(ensemblePrediction, 3);
    predictionStd = std(ensemblePrediction, 0, 3);
    lowerBound = predictionMean - ...
        uncertaintyMultiplier * predictionStd;
    normalized = bsxfun(@rdivide, lowerBound, targetScale);
    score = min(normalized(:, 1:5), [], 2) + ...
        2 * min(min(normalized(:, 6:9), [], 2), 0);
    predictedAdmissible = ...
        all(lowerBound(:, 1:5) > 0, 2) & ...
        all(lowerBound(:, 6:9) >= 0, 2) & ...
        heldoutTargetsFull(:, 11) >= 0;
    trueStrict = strictTailPositive(heldoutTargetsFull);
    trueAggregate = heldoutTargetsFull(:, 1) > 0 & ...
        heldoutTargetsFull(:, 2) > 0 & ...
        heldoutTargetsFull(:, 3) >= 0 & ...
        heldoutTargetsFull(:, 11) >= 0;

    [~, ranking] = sort(score, 'descend');
    selectedLocal = 0;
    if any(predictedAdmissible)
        admissibleIndices = find(predictedAdmissible);
        [~, localBest] = max(score(admissibleIndices));
        selectedLocal = admissibleIndices(localBest);
    end
    bestStrictRank = NaN;
    if any(trueStrict)
        strictRanks = find(ismember(ranking, find(trueStrict)));
        bestStrictRank = min(strictRanks);
    end

    fold = emptyFold();
    fold.heldoutBlock = heldoutBlock;
    fold.currentTime = ...
        dataset.blocks(heldoutBlock).currentTime;
    fold.trainingRowCount = numel(trainingRows);
    fold.heldoutRowCount = numel(heldoutRows);
    fold.trueAggregatePositiveCount = nnz(trueAggregate);
    fold.trueStrictPositiveCount = nnz(trueStrict);
    fold.predictedAdmissibleCount = nnz(predictedAdmissible);
    fold.bestStrictRank = bestStrictRank;
    fold.topOneStrict = trueStrict(ranking(1));
    fold.topFiveContainsStrict = any( ...
        trueStrict(ranking(1:min(5, numel(ranking)))));
    fold.selectedLocalIndex = selectedLocal;
    fold.selected = selectedLocal > 0;
    if selectedLocal > 0
        fold.selectedRowId = heldoutRows(selectedLocal).rowId;
        fold.selectedFormationId = ...
            heldoutRows(selectedLocal).receiverFormationId;
        fold.selectedSourceId = heldoutRows(selectedLocal).sourceId;
        fold.selectedLabel = heldoutRows(selectedLocal).label;
        fold.selectedTrueTargets = ...
            heldoutTargetsFull(selectedLocal, :);
        fold.selectedTrueAggregatePositive = ...
            trueAggregate(selectedLocal);
        fold.selectedTrueStrictPositive = trueStrict(selectedLocal);
        fold.selectedPredictedScore = score(selectedLocal);
    end
    fold.predictionMean = predictionMean;
    fold.predictionStd = predictionStd;
    fold.lowerBound = lowerBound;
    fold.score = score;
    fold.trueStrictMask = trueStrict;
    folds(heldoutBlock) = fold;

    globalIndices = find(heldoutMask);
    allPrediction(globalIndices, :) = predictionMean;
    allScore(globalIndices) = score;
    allStrict(globalIndices) = trueStrict;
end

trueTargets = vertcat(dataset.rows.targets);
trueTargets = trueTargets(:, predictionTargetIndices);
targetSpearman = zeros(1, numel(predictionTargetIndices));
for targetIdx = 1:numel(predictionTargetIndices)
    targetSpearman(targetIdx) = computeSpearman( ...
        allPrediction(:, targetIdx), trueTargets(:, targetIdx));
end
strictAuc = binaryAuc(allScore, allStrict);
selectedMask = [folds.selected];
result = struct();
result.contractVersion = ...
    'formation-action-value-learnability-v208-v1';
result.generatedAt = datestr(now, 31);
result.datasetPath = datasetPath;
result.presetName = dataset.presetName;
result.seed = dataset.seed;
result.encoderSeeds = encoderSeeds;
result.hiddenWidth = hiddenWidth;
result.ridgeLambda = ridgeLambda;
result.uncertaintyMultiplier = uncertaintyMultiplier;
result.predictionTargetIndices = predictionTargetIndices;
result.predictionTargetNames = predictionTargetNames;
result.folds = folds;
result.targetSpearman = targetSpearman;
result.strictTailAuc = strictAuc;
result.pageCount = blockCount;
result.pageWithStrictActionCount = ...
    nnz([folds.trueStrictPositiveCount] > 0);
result.topOneStrictPageCount = nnz([folds.topOneStrict]);
result.topFiveStrictPageCount = ...
    nnz([folds.topFiveContainsStrict]);
result.selectedPageCount = nnz(selectedMask);
result.selectedAggregatePositiveCount = nnz( ...
    [folds(selectedMask).selectedTrueAggregatePositive]);
result.selectedStrictPositiveCount = nnz( ...
    [folds(selectedMask).selectedTrueStrictPositive]);
result.featuresUseTruth = false;
result.featuresUseFutureInformation = false;
result.targetsUseCurrentTruth = true;
result.targetsUseFutureInformation = false;
result.encoderWeightsTrained = false;
result.readoutWeightsTrained = true;
result.completePageHeldOut = true;
result.recursiveReturnEvaluated = false;
result.policySelected = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'This leave-one-page-out probe fits only a ridge readout over frozen ', ...
    'random two-round graph encoders on the already opened X36 seed-211 ', ...
    'immediate-action dataset. Complete pages are held out, but all pages ', ...
    'belong to one development trajectory. The probe measures whether ', ...
    'truth-free features carry action-value signal; it is not a trained ', ...
    'controller, recursive result, held-out seed, or performance claim.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_ACTION_VALUE_LEARNABILITY_V208.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_ACTION_VALUE_LEARNABILITY_V208.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V208 action-value learnability: %s\n', reportPath);
end

function validateDataset(dataset)
required = {'contractVersion', 'presetName', 'seed', ...
    'blocks', 'rows', 'blockCount', 'rowCount', ...
    'actionFeatureNames', 'targetNames', ...
    'featuresUseTruth', 'featuresUseFutureInformation', ...
    'targetsUseCurrentTruth', 'targetsUseFutureInformation', ...
    'recursiveTargetsIncluded', 'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-label-kla-immediate-dataset-v208-merged-v1') || ...
        dataset.blockCount < 4 || ...
        numel(dataset.blocks) ~= dataset.blockCount || ...
        numel(dataset.rows) ~= dataset.rowCount || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        ~dataset.targetsUseCurrentTruth || ...
        dataset.targetsUseFutureInformation || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed
    error('FormationActionLearnabilityV208:DatasetContract', ...
        'The merged V208 development dataset is invalid.');
end
end

function encoder = initializeEncoder( ...
        dataset, trainingBlocks, trainingRows, seed, width)
nodeX = zeros(0, numel(dataset.blocks(1).graph.nodeFeatureNames));
edgeX = zeros(0, numel(dataset.blocks(1).graph.edgeFeatureNames));
for blockIdx = reshape(trainingBlocks, 1, [])
    graph = dataset.blocks(blockIdx).graph;
    nodeX = [nodeX; graph.nodeFeatures]; %#ok<AGROW>
    edgeX = [edgeX; reshape(graph.edgeFeatures, ...
        [], size(graph.edgeFeatures, 3))]; %#ok<AGROW>
end
actionX = vertcat(trainingRows.features);
[nodeMean, nodeScale] = fitScaler(nodeX);
[edgeMean, edgeScale] = fitScaler(edgeX);
[actionMean, actionScale] = fitScaler(actionX);
nodeInputWidth = size(nodeX, 2);
edgeInputWidth = size(edgeX, 2);
rng(seed);
encoder = struct();
encoder.contractVersion = ...
    'formation-action-frozen-two-round-encoder-v208-v1';
encoder.nodeFeatureNames = ...
    dataset.blocks(1).graph.nodeFeatureNames;
encoder.edgeFeatureNames = ...
    dataset.blocks(1).graph.edgeFeatureNames;
encoder.actionFeatureNames = dataset.actionFeatureNames;
encoder.nodeFeatureMean = nodeMean;
encoder.nodeFeatureScale = nodeScale;
encoder.edgeFeatureMean = edgeMean;
encoder.edgeFeatureScale = edgeScale;
encoder.actionFeatureMean = actionMean;
encoder.actionFeatureScale = actionScale;
encoder.nodeWeight = randn(nodeInputWidth, width) / ...
    sqrt(nodeInputWidth);
encoder.nodeBias = zeros(1, width);
encoder.baseEdgeWeight = ...
    randn(edgeInputWidth + 4 * width, width) / ...
        sqrt(edgeInputWidth + 4 * width);
encoder.baseEdgeBias = zeros(1, width);
encoder.messageWeight = randn(17 * width, width) / ...
    sqrt(17 * width);
encoder.messageBias = zeros(1, width);
encoder.truthUsed = false;
encoder.futureInformationUsed = false;
end

function features = encodeBlocks(dataset, blockIndices, encoder)
features = zeros(0, 0);
for blockIdx = reshape(blockIndices, 1, [])
    rows = dataset.rows([dataset.rows.blockId] == blockIdx);
    current = encodeFormationGraphActionsV208( ...
        dataset.blocks(blockIdx).graph, rows, encoder);
    if isempty(features)
        features = current;
    else
        features = [features; current]; %#ok<AGROW>
    end
end
end

function model = fitRidgeReadout(X, Y, lambda)
[xMean, xScale] = fitScaler(X);
[yMean, yScale] = fitScaler(Y);
Z = applyScaler(X, xMean, xScale);
T = applyScaler(Y, yMean, yScale);
if size(Z, 2) <= size(Z, 1)
    weight = (Z' * Z + lambda * eye(size(Z, 2))) \ (Z' * T);
else
    weight = Z' * ((Z * Z' + ...
        lambda * eye(size(Z, 1))) \ T);
end
model = struct('xMean', xMean, 'xScale', xScale, ...
    'yMean', yMean, 'yScale', yScale, 'weight', weight);
end

function prediction = predictRidgeReadout(model, X)
Z = applyScaler(X, model.xMean, model.xScale);
prediction = bsxfun(@plus, ...
    bsxfun(@times, Z * model.weight, model.yScale), ...
    model.yMean);
end

function mask = strictTailPositive(targets)
mask = targets(:, 1) > 0 & targets(:, 2) > 0 & ...
    targets(:, 3) >= 0 & targets(:, 5) > 0 & ...
    targets(:, 6) > 0 & targets(:, 7) >= 0 & ...
    targets(:, 8) >= 0 & targets(:, 9) >= 0 & ...
    targets(:, 10) >= 0 & targets(:, 11) >= 0;
end

function [meanValue, scaleValue] = fitScaler(X)
meanValue = mean(X, 1);
scaleValue = std(X, 0, 1);
scaleValue(~isfinite(scaleValue) | scaleValue <= eps) = 1;
end

function Z = applyScaler(X, meanValue, scaleValue)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, meanValue), scaleValue);
end

function value = computeSpearman(left, right)
leftRanks = averageRanks(reshape(left, [], 1));
rightRanks = averageRanks(reshape(right, [], 1));
matrix = corrcoef(leftRanks, rightRanks);
if numel(matrix) < 4 || ~isfinite(matrix(1, 2))
    value = NaN;
else
    value = matrix(1, 2);
end
end

function ranks = averageRanks(values)
[sorted, order] = sort(values);
ranks = zeros(size(values));
startIdx = 1;
while startIdx <= numel(values)
    endIdx = startIdx;
    while endIdx < numel(values) && ...
            sorted(endIdx + 1) == sorted(startIdx)
        endIdx = endIdx + 1;
    end
    ranks(order(startIdx:endIdx)) = ...
        0.5 * (startIdx + endIdx);
    startIdx = endIdx + 1;
end
end

function value = binaryAuc(scores, labels)
scores = reshape(scores, [], 1);
labels = logical(reshape(labels, [], 1));
positive = scores(labels);
negative = scores(~labels);
if isempty(positive) || isempty(negative)
    value = NaN;
    return;
end
wins = 0;
for idx = 1:numel(positive)
    wins = wins + nnz(positive(idx) > negative) + ...
        0.5 * nnz(positive(idx) == negative);
end
value = wins / (numel(positive) * numel(negative));
end

function fold = emptyFold()
fold = struct( ...
    'heldoutBlock', 0, 'currentTime', 0, ...
    'trainingRowCount', 0, 'heldoutRowCount', 0, ...
    'trueAggregatePositiveCount', 0, ...
    'trueStrictPositiveCount', 0, ...
    'predictedAdmissibleCount', 0, ...
    'bestStrictRank', NaN, ...
    'topOneStrict', false, ...
    'topFiveContainsStrict', false, ...
    'selectedLocalIndex', 0, 'selected', false, ...
    'selectedRowId', 0, 'selectedFormationId', 0, ...
    'selectedSourceId', 0, ...
    'selectedLabel', zeros(2, 1), ...
    'selectedTrueTargets', nan(1, 11), ...
    'selectedTrueAggregatePositive', false, ...
    'selectedTrueStrictPositive', false, ...
    'selectedPredictedScore', NaN, ...
    'predictionMean', zeros(0, 9), ...
    'predictionStd', zeros(0, 9), ...
    'lowerBound', zeros(0, 9), ...
    'score', zeros(0, 1), ...
    'trueStrictMask', false(0, 1));
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FormationActionLearnabilityV208:ReportOpenFailed', ...
        'Could not write the V208 learnability report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V208 formation action-value learnability probe\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Complete-page folds: `%d`\n', result.pageCount);
fprintf(fid, '- Frozen encoder seeds / width: `%d / %d`\n', ...
    numel(result.encoderSeeds), result.hiddenWidth);
fprintf(fid, '- Ridge lambda / LCB multiplier: `%.3g / %.3g`\n', ...
    result.ridgeLambda, result.uncertaintyMultiplier);
fprintf(fid, '- Pages with a strict action: `%d / %d`\n', ...
    result.pageWithStrictActionCount, result.pageCount);
fprintf(fid, '- Top-1 / top-5 strict recovery: `%d / %d`\n', ...
    result.topOneStrictPageCount, result.topFiveStrictPageCount);
fprintf(fid, '- Strict-action row AUC: `%.4f`\n', ...
    result.strictTailAuc);
fprintf(fid, ['- Conservative selected / aggregate-positive / ', ...
    'strict-positive pages: `%d / %d / %d`\n\n'], ...
    result.selectedPageCount, ...
    result.selectedAggregatePositiveCount, ...
    result.selectedStrictPositiveCount);
fprintf(fid, ['| Time | Actions | Aggregate + | Strict + | ', ...
    'Predicted safe | Selection | True E / R / C | ', ...
    'Min tail | Strict? | Best strict rank |\n']);
fprintf(fid, ...
    '|--:|--:|--:|--:|--:|:--|:--|--:|:--:|--:|\n');
for fold = reshape(result.folds, 1, [])
    if fold.selected
        selection = sprintf('F%d<-S%d [%d,%d]', ...
            fold.selectedFormationId, fold.selectedSourceId, ...
            fold.selectedLabel(1), fold.selectedLabel(2));
        target = fold.selectedTrueTargets;
        targetText = sprintf('%+.3f / %+.3f / %+.3f', ...
            target(1), target(2), target(3));
        minTail = min(target([7, 8, 9, 10]));
        strictText = sprintf('%d', ...
            fold.selectedTrueStrictPositive);
    else
        selection = 'no-op';
        targetText = '--';
        minTail = NaN;
        strictText = '--';
    end
    fprintf(fid, ['| %d | %d | %d | %d | %d | %s | %s | ', ...
        '%+.3f | %s | %.0f |\n'], ...
        fold.currentTime, fold.heldoutRowCount, ...
        fold.trueAggregatePositiveCount, ...
        fold.trueStrictPositiveCount, ...
        fold.predictedAdmissibleCount, selection, targetText, ...
        minTail, strictText, fold.bestStrictRank);
end
fprintf(fid, '\n## Target rank correlation\n\n');
fprintf(fid, '| Target | Spearman |\n|:--|--:|\n');
for idx = 1:numel(result.predictionTargetNames)
    fprintf(fid, '| %s | %+.4f |\n', ...
        result.predictionTargetNames{idx}, ...
        result.targetSpearman(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
