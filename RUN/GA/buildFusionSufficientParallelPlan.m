function plan = buildFusionSufficientParallelPlan(config)
% BUILDFUSIONSUFFICIENTPARALLELPLAN Deterministic v2 worker command plan.

required = {'projectRoot', 'outputDirectory', 'artifactStem', ...
    'firstSeed', 'lastSeed', 'numberOfTrials', 'maxWorkers', ...
    'configSha256', 'batchIdentity'};
for fieldIdx = 1:numel(required)
    if ~isfield(config, required{fieldIdx})
        error('FusionSufficientParallelPlan:MissingConfig', ...
            'Config is missing %s.', required{fieldIdx});
    end
end
if config.maxWorkers ~= 6
    error('FusionSufficientParallelPlan:WorkerLimit', ...
        'The v2 protocol requires exactly maxWorkers=6.');
end
if isempty(regexp(config.batchIdentity, '^[a-z0-9-]+$', 'once'))
    error('FusionSufficientParallelPlan:BatchIdentity', ...
        'Batch identity must contain lowercase letters, digits, hyphens.');
end
seeds = config.firstSeed:config.lastSeed;
if numel(seeds) ~= config.numberOfTrials
    error('FusionSufficientParallelPlan:SeedInterval', ...
        'The configured seed interval is inconsistent.');
end
workerDirectory = fullfile(char(config.outputDirectory), ...
    '.fusion_sufficient_workers', char(config.artifactStem));
attemptRoot = fullfile(char(config.outputDirectory), ...
    '.fusion_sufficient_attempts');
attemptDirectory = fullfile(attemptRoot, ...
    [char(config.batchIdentity), '.reserved']);
workerMatPaths = cell(1, numel(seeds));
workerLogPaths = cell(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    workerMatPaths{seedIdx} = fullfile(workerDirectory, ...
        sprintf('worker_seed_%06d.mat', seeds(seedIdx)));
    workerLogPaths{seedIdx} = fullfile(workerDirectory, ...
        sprintf('worker_seed_%06d.log', seeds(seedIdx)));
end
launcherPath = fullfile(char(config.projectRoot), 'RUN', 'GA', ...
    'launchFusionSufficientMomentExchangeWorkers.sh');
batchPlanPath = fullfile(workerDirectory, 'batch_plan.mat');
lifecycleClaimPath = fullfile(workerDirectory, '.launch_claim');
exitLedgerPath = fullfile(workerDirectory, 'worker_exit_ledger.receipt');
launcherCapabilityPath = fullfile(workerDirectory, ...
    '.launcher.capability');
completionAuthorizationPath = fullfile(workerDirectory, ...
    'completion.authorization');
reservationReceiptPath = fullfile(attemptDirectory, ...
    'reservation.receipt');
workerSuccessReceiptPath = fullfile(workerDirectory, ...
    'batch_success.receipt');
attemptSuccessReceiptPath = fullfile(attemptDirectory, ...
    'batch_success.receipt');
workerFailedTombstonePath = fullfile(workerDirectory, ...
    'batch_failed.tombstone');
attemptFailedTombstonePath = fullfile(attemptDirectory, ...
    'batch_failed.tombstone');
publishClaimDirectory = fullfile(attemptDirectory, 'publish.claim');
publishOwnerReceiptPath = fullfile(publishClaimDirectory, ...
    'owner.receipt');
publishedReceiptPath = fullfile(attemptDirectory, ...
    'evidence_published.receipt');
finalPaths = { ...
    fullfile(char(config.outputDirectory), ...
        [char(config.artifactStem), '.mat']), ...
    fullfile(char(config.outputDirectory), ...
        [char(config.artifactStem), '.csv']), ...
    fullfile(char(config.outputDirectory), ...
        [char(config.artifactStem), '.md'])};
launchCommand = sprintf([ ...
    'bash %s %s %s %s %s %s %d %d %d %s %s %s'], ...
    shellQuote(launcherPath), ...
    shellQuote(char(config.projectRoot)), ...
    shellQuote(batchPlanPath), ...
    shellQuote(workerDirectory), ...
    shellQuote(char(config.outputDirectory)), ...
    shellQuote(char(config.artifactStem)), ...
    config.firstSeed, config.lastSeed, config.maxWorkers, ...
    shellQuote(char(config.batchIdentity)), ...
    shellQuote(char(config.configSha256)), ...
    shellQuote(attemptDirectory));

plan = struct( ...
    'schema', 'fusion-sufficient-parallel-plan-v2', ...
    'configSha256', config.configSha256, ...
    'batchIdentity', config.batchIdentity, ...
    'workerSeeds', seeds, ...
    'maxWorkers', config.maxWorkers, ...
    'launcherPath', launcherPath, ...
    'workerDirectory', workerDirectory, ...
    'attemptRoot', attemptRoot, ...
    'attemptDirectory', attemptDirectory, ...
    'batchPlanPath', batchPlanPath, ...
    'lifecycleClaimPath', lifecycleClaimPath, ...
    'exitLedgerPath', exitLedgerPath, ...
    'launcherCapabilityPath', launcherCapabilityPath, ...
    'completionAuthorizationPath', completionAuthorizationPath, ...
    'reservationReceiptPath', reservationReceiptPath, ...
    'workerSuccessReceiptPath', workerSuccessReceiptPath, ...
    'attemptSuccessReceiptPath', attemptSuccessReceiptPath, ...
    'workerFailedTombstonePath', workerFailedTombstonePath, ...
    'attemptFailedTombstonePath', attemptFailedTombstonePath, ...
    'publishClaimDirectory', publishClaimDirectory, ...
    'publishOwnerReceiptPath', publishOwnerReceiptPath, ...
    'publishedReceiptPath', publishedReceiptPath, ...
    'workerMatPaths', {workerMatPaths}, ...
    'workerLogPaths', {workerLogPaths}, ...
    'finalPaths', {finalPaths}, ...
    'launchCommand', launchCommand);
end

function quoted = shellQuote(value)
value = char(value);
quoted = ['''', strrep(value, '''', '''"''"'''), ''''];
end
