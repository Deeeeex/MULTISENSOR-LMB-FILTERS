fprintf(fid, '\n## Decision\n\n');
if summary.fullGridEvaluationAuthorized
    fprintf(fid, ['Persistent causal options pass the paired sentinel ', ...
        'and may advance to the opened-training full grid.\n\n']);
else
    fprintf(fid, ['Persistent causal options are rejected before ', ...
        'full-grid evaluation and selector fitting.\n\n']);
