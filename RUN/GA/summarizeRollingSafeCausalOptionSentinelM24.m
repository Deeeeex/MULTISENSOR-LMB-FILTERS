function [reportPath, summary] = ...
    summarizeRollingSafeCausalOptionSentinelM24(options)
% SUMMARIZEROLLINGSAFECAUSALOPTIONSENTINELM24 Compare H=3 with one-step.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.rollingSafeCausalOptionAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 causal option sentinel is not authorized.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error(['Official causal option summary requires a clean tracked ', ...
        'and MATLAB/Octave source state.']);
end

states = protocol.rollingSafeCausalOptionSentinelSeedTimes;
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        protocol.rollingSafeCausalOptionEvidenceNamespace));
artifactSuffix = getField(options, ...
    'artifactSuffix', protocol.rollingSafeCausalOptionArtifactSuffix);
if ~ischar(artifactSuffix) || ...
        isempty(regexp(artifactSuffix, ...
            '^[A-Za-z0-9_-]+$', 'once'))
    error('artifactSuffix is invalid.');
end

rows = repmat(emptyRow(), 1, size(states, 1));
allGenerationCommits = {};
for stateIdx = 1:size(states, 1)
    seed = states(stateIdx, 1);
    currentTime = states(stateIdx, 2);
    behavior = protocol. ...
        rollingSafeCausalOptionSentinelBehaviors{stateIdx};
    behaviorAction = protocol. ...
        rollingSafeCausalOptionSentinelBehaviorActions{stateIdx};
    persistentPath = artifactPath(inputDirectory, ...
        'persistent', seed, currentTime, artifactSuffix);
    oneStepPath = artifactPath(inputDirectory, ...
        'one_step', seed, currentTime, artifactSuffix);
    persistentPreflight = loadPreflight(persistentPath);
    oneStep = loadPreflight(oneStepPath);
    validatePreflight(persistentPreflight, 'causal-persistent', ...
        protocol.rollingSafeCausalOptionSequences, ...
        protocol.rollingSafeCausalOptionNames, ...
        seed, currentTime, behaviorAction, protocol);
    validatePreflight(oneStep, 'one-step-control', ...
        protocol.rollingSafeCausalOneStepControlSequences, ...
        protocol.rollingSafeCausalOneStepControlNames, ...
        seed, currentTime, behaviorAction, protocol);
    assertPairedReferenceEqual( ...
        persistentPreflight, oneStep, protocol);
    persistentStoredDerived = recomputeBankDerived( ...
        persistentPreflight, true(1, size( ...
            persistentPreflight.optionSequences, 1)), protocol);
    oneStepStoredDerived = recomputeBankDerived( ...
        oneStep, true(1, size(oneStep.optionSequences, 1)), protocol);
    assertStoredDerivedEqual( ...
        persistentPreflight, persistentStoredDerived, protocol);
    assertStoredDerivedEqual(oneStep, oneStepStoredDerived, protocol);
    pairedCompleted = persistentStoredDerived.completed & ...
        oneStepStoredDerived.completed;
    persistentDerived = recomputeBankDerived( ...
        persistentPreflight, pairedCompleted, protocol);
    oneStepDerived = recomputeBankDerived( ...
        oneStep, pairedCompleted, protocol);
    persistentBestIdx = persistentDerived.bestAdmissibleOptionIndex;
    oneStepBestIdx = oneStepDerived.bestAdmissibleOptionIndex;
    persistentBest = ...
        persistentPreflight.outcomes(persistentBestIdx);
    oneStepBest = oneStep.outcomes(oneStepBestIdx);
    row = emptyRow();
    row.seed = seed;
    row.currentTime = currentTime;
    row.behavior = behavior;
    row.behaviorAction = behaviorAction;
    row.persistentArtifactPath = persistentPath;
    row.oneStepArtifactPath = oneStepPath;
    row.sourceSha256 = persistentPreflight.sourceSha256;
    row.referenceMeanEospa = ...
        persistentDerived.referenceMeanEospa;
    row.oneStepBestMeanEospa = ...
        oneStepDerived.bestAdmissibleMeanEospa;
    row.persistentBestMeanEospa = ...
        persistentDerived.bestAdmissibleMeanEospa;
    row.oneStepBestOptionName = ...
        oneStep.optionNames{oneStepBestIdx};
    row.persistentBestOptionName = ...
        persistentPreflight.optionNames{persistentBestIdx};
    row.oneStepBestSequence = ...
        oneStep.optionSequences(oneStepBestIdx, :);
    row.persistentBestSequence = ...
        persistentPreflight.optionSequences(persistentBestIdx, :);
    row.oneStepGainVsReferencePercent = ...
        oneStepDerived.meanGainVsReferencePercent(oneStepBestIdx);
    row.persistentGainVsReferencePercent = ...
        persistentDerived.meanGainVsReferencePercent(persistentBestIdx);
    row.incrementalGainVsOneStepPercent = ...
        row.persistentGainVsReferencePercent - ...
        row.oneStepGainVsReferencePercent;
    row.persistentWorstGainVsReferencePercent = ...
        persistentDerived.worstGainVsReferencePercent( ...
            persistentBestIdx);
    row.persistentConsensusGainVsReferencePercent = ...
        persistentDerived.consensusGainVsReferencePercent( ...
            persistentBestIdx);
    row.persistentByteDeviationPercent = ...
        persistentDerived.attemptedByteDeviationPercent( ...
            persistentBestIdx);
    row.oneStepLaterPolicyReportedRepairCount = ...
        oneStepBest.laterPolicyReportedRepairCount;
    row.persistentLaterPolicyReportedRepairCount = ...
        persistentBest.laterPolicyReportedRepairCount;
    row.persistentDeliveredSensorB3PassFraction = ...
        mean(persistentBest.deliveredSensorB3Pass);
    row.persistentDeliveredFormationB3PassFraction = ...
        mean(persistentBest.deliveredFormationB3Pass);
    row.referenceLaterPolicyReportedRepairCount = ...
        persistentDerived.referenceLaterPolicyReportedRepairCount;
    row.oneStepAdmissibleOptionCount = ...
        nnz(oneStepDerived.admissibleForSelection);
    row.persistentAdmissibleOptionCount = ...
        nnz(persistentDerived.admissibleForSelection);
    row.pairedEvaluableOptionCount = nnz(pairedCompleted);
    row.persistentOnlyCompletedOptionCount = nnz( ...
        persistentStoredDerived.completed & ...
        ~oneStepStoredDerived.completed);
    row.oneStepOnlyCompletedOptionCount = nnz( ...
        oneStepStoredDerived.completed & ...
        ~persistentStoredDerived.completed);
    row.improvesOneStep = ...
        row.incrementalGainVsOneStepPercent > 1e-9;
    row.isExcludedOutlier = isequal( ...
        [seed, currentTime], ...
        protocol.rollingSafeCausalOptionExcludedOutlierSeedTime);
    row.isStrongNonOutlier = ...
        ~row.isExcludedOutlier && ...
        row.persistentGainVsReferencePercent >= ...
            protocol. ...
                rollingSafeCausalOptionMinimumNonOutlierGainPercent;
    row.oneStepSafetyPassed = oneStepStoredDerived.bankSafetyPassed;
    row.persistentSafetyPassed = ...
        persistentStoredDerived.bankSafetyPassed;
    row.safetyPassed = ...
        row.oneStepSafetyPassed && ...
        row.persistentSafetyPassed && ...
        row.persistentWorstGainVsReferencePercent >= -1e-9 && ...
        row.persistentConsensusGainVsReferencePercent >= -1e-9;
    rows(stateIdx) = row;
    allGenerationCommits = [allGenerationCommits, ...
        {persistentPreflight.generationGitCommit, ...
         oneStep.generationGitCommit}]; %#ok<AGROW>
end

generationCommits = unique(allGenerationCommits);
if numel(generationCommits) ~= 1
    error('Paired causal option artifacts use different code commits.');
end
if ~strcmp(gitState.commit, generationCommits{1})
    error(['Causal option summary must run on the same frozen commit ', ...
        'as all paired preflights.']);
end
meanReferenceEospa = mean([rows.referenceMeanEospa]);
meanOneStepBestEospa = mean([rows.oneStepBestMeanEospa]);
meanPersistentBestEospa = ...
    mean([rows.persistentBestMeanEospa]);
oneStepAggregateGainPercent = relativeGain( ...
    meanReferenceEospa, meanOneStepBestEospa);
persistentAggregateGainPercent = relativeGain( ...
    meanReferenceEospa, meanPersistentBestEospa);
incrementalVsOneStepPercent = ...
    persistentAggregateGainPercent - ...
    oneStepAggregateGainPercent;
improvedStateCount = nnz([rows.improvesOneStep]);
strongNonOutlierStateCount = nnz([rows.isStrongNonOutlier]);
hardAuditPassed = all([rows.safetyPassed]);
headroomGatePassed = ...
    improvedStateCount >= protocol. ...
        rollingSafeCausalOptionMinimumSentinelImprovedStateCount && ...
    strongNonOutlierStateCount >= 1 && ...
    incrementalVsOneStepPercent >= protocol. ...
        rollingSafeCausalOptionMinimumIncrementalVsOneStepPercent;
fullGridAuthorized = hardAuditPassed && headroomGatePassed;

summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-rolling-safe-causal-h3-paired-sentinel-summary-v2';
summary.optionContractVersion = ...
    protocol.rollingSafeCausalOptionContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.preflightGenerationGitCommit = generationCommits{1};
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.persistentOptionSequences = ...
    protocol.rollingSafeCausalOptionSequences;
summary.oneStepControlSequences = ...
    protocol.rollingSafeCausalOneStepControlSequences;
summary.rows = rows;
summary.meanReferenceEospa = meanReferenceEospa;
summary.meanOneStepBestEospa = meanOneStepBestEospa;
summary.meanPersistentBestEospa = meanPersistentBestEospa;
summary.oneStepAggregateGainPercent = ...
    oneStepAggregateGainPercent;
summary.persistentAggregateGainPercent = ...
    persistentAggregateGainPercent;
summary.incrementalGainVsOneStepPercent = ...
    incrementalVsOneStepPercent;
summary.improvedStateCount = improvedStateCount;
summary.strongNonOutlierStateCount = ...
    strongNonOutlierStateCount;
summary.meanPersistentDeliveredSensorB3PassFraction = ...
    mean([rows.persistentDeliveredSensorB3PassFraction]);
summary.meanPersistentDeliveredFormationB3PassFraction = ...
    mean([rows.persistentDeliveredFormationB3PassFraction]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.sentinelHeadroomGatePassed = headroomGatePassed;
summary.fullGridEvaluationAuthorized = fullGridAuthorized;
summary.optionBankRejected = ~fullGridAuthorized;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.evidenceBoundary = [ ...
    'This paired opened-training sentinel compares eight persistent ', ...
    'causal H=3 options against the same eight one-step-then-reference ', ...
    'controls on four registered t=78 behavior states. Oracle comparison ', ...
    'is restricted to the same paired-completed action rows after exact ', ...
    'first-graph and first-weight matching. Every completed arm is ', ...
    'truth-free and selects 24 messages per step; later policy-reported ', ...
    'repair may not exceed its paired reference. This flag is not a ', ...
    'universal proposal-to-selected rewrite diagnostic. Source behavior ', ...
    'restart hashes are replayed exactly. The source states ', ...
    'come from 40-message CCW or learned behavior trajectories, so this ', ...
    'does not establish steady-state 24-message performance, recursive ', ...
    'feasibility, or formation-FoV M24/X36/X48 gains. Centralized ', ...
    'coordinator metadata bytes are not included in communication cost.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = protocol.rollingSafeCausalOptionSummaryStem;
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Causal option summary already exists. Set overwrite=true ', ...
        'only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save(matPath, 'summary', '-v7');
writeReport(reportPath, summary, protocol);
fprintf('Causal option paired sentinel: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function path = artifactPath( ...
        directory, auditStem, seed, currentTime, suffix)
path = fullfile(directory, sprintf([ ...
    'rolling_safe_causal_h3_%s_m24_seed%d_t%d_%s.mat'], ...
    auditStem, seed, currentTime, suffix));
end

function preflight = loadPreflight(path)
loaded = load(path, 'preflight');
if ~isfield(loaded, 'preflight')
    error('Causal option artifact lacks preflight: %s', path);
end
preflight = loaded.preflight;
end

function validatePreflight( ...
        preflight, auditMode, expectedSequences, expectedNames, ...
        seed, currentTime, behaviorAction, protocol)
requiredFields = { ...
    'protocolId', 'contractVersion', 'auditMode', ...
    'generationGitCommit', 'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty', 'seed', 'currentTime', ...
    'returnTimes', 'optionSequences', 'optionNames', ...
    'optionSequenceSetSha256', 'optionStatus', ...
    'optionFailureIdentifier', 'optionFailureMessage', ...
    'optionExpectedUnavailable', 'firstActionGraphSha256', ...
    'firstActionFusionWeightSha256', 'referenceOptionIndex', ...
    'referenceMeanEospa', 'referenceWorstSensorEospa', ...
    'referenceConsensusOspa', ...
    'referenceLaterPolicyReportedRepairCount', 'outcomes', ...
    'meanGainVsReferencePercent', 'worstGainVsReferencePercent', ...
    'consensusGainVsReferencePercent', ...
    'attemptedByteDeviationPercent', 'hardRuntimeGatePassed', ...
    'admissibleForSelection', 'bestAdmissibleOptionIndex', ...
    'bestAdmissibleOptionName', 'bestAdmissibleSequence', ...
    'bestAdmissibleMeanEospa', ...
    'bestAdmissibleGainVsReferencePercent', ...
    'bestAdmissibleWorstGainVsReferencePercent', ...
    'bestAdmissibleConsensusGainVsReferencePercent', ...
    'bestAdmissibleAttemptedByteDeviationPercent', ...
    'completedOptionCount', ...
    'unavailableOptionCount', 'uniqueCompletedTrajectoryCount', ...
    'sourceSha256', ...
    'sourceBehaviorAction', 'sourceGenerationGitCommit', ...
    'sourceCacheSha256', 'sourceBehaviorModelSha256', ...
    'sourceHistoryLabel', 'restartReferenceOverallSha256', ...
    'restartObservedOverallSha256', 'restartEquivalencePassed', ...
    'commonRandomNumbers', 'firstActionGraphAndWeightsFrozen', ...
    'subsequentActionsCausal', 'livePosteriorAndHistoryRecomputed', ...
    'centralizedCoordinatorAssumed', ...
    'controlMetadataBytesAccounted', ...
    'exploratoryOptionSubsetUsed', 'runtimePolicyUsesTruth', ...
    'trainingOnlyDiagnostic', 'developmentOpened', ...
    'heldoutM24Opened', 'x36Opened'};
if ~isstruct(preflight) || ~all(isfield(preflight, requiredFields))
    error('Causal option preflight lacks required evidence fields.');
end
binaryScalarFields = { ...
    'generationTrackedWorktreeDirty', ...
    'generationResearchWorktreeDirty', 'restartEquivalencePassed', ...
    'commonRandomNumbers', 'firstActionGraphAndWeightsFrozen', ...
    'subsequentActionsCausal', 'livePosteriorAndHistoryRecomputed', ...
    'centralizedCoordinatorAssumed', 'controlMetadataBytesAccounted', ...
    'exploratoryOptionSubsetUsed', 'runtimePolicyUsesTruth', ...
    'trainingOnlyDiagnostic', 'developmentOpened', ...
    'heldoutM24Opened', 'x36Opened'};
for fieldIdx = 1:numel(binaryScalarFields)
    fieldName = binaryScalarFields{fieldIdx};
    requireFiniteBinaryDiagnostic( ...
        preflight.(fieldName), 1, fieldName);
end
requireFiniteBinaryDiagnostic( ...
    preflight.optionExpectedUnavailable, ...
    size(expectedSequences, 1), 'optionExpectedUnavailable');
if ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.contractVersion, ...
            protocol.rollingSafeCausalOptionContractVersion) || ...
        ~strcmp(preflight.auditMode, auditMode) || ...
        preflight.seed ~= seed || ...
        preflight.currentTime ~= currentTime || ...
        ~isequal(reshape(preflight.returnTimes, 1, []), ...
            currentTime + (0:(protocol.returnValueGateHorizon - 1))) || ...
        ~strcmp(preflight.sourceBehaviorAction, behaviorAction) || ...
        ~isequal(preflight.optionSequences, expectedSequences) || ...
        ~strcmp(preflight.optionSequenceSetSha256, ...
            computeTextSha256(sprintf('%02d,', expectedSequences(:)))) || ...
        ~isequal(preflight.optionNames, expectedNames) || ...
        numel(preflight.outcomes) ~= size(expectedSequences, 1) || ...
        ~preflight.restartEquivalencePassed || ...
        ~strcmp(preflight.restartReferenceOverallSha256, ...
            preflight.restartObservedOverallSha256) || ...
        isempty(preflight.sourceHistoryLabel) || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.commonRandomNumbers || ...
        ~preflight.firstActionGraphAndWeightsFrozen || ...
        ~preflight.subsequentActionsCausal || ...
        ~preflight.livePosteriorAndHistoryRecomputed || ...
        ~preflight.centralizedCoordinatorAssumed || ...
        preflight.controlMetadataBytesAccounted || ...
        preflight.exploratoryOptionSubsetUsed || ...
        preflight.runtimePolicyUsesTruth || ...
        ~preflight.trainingOnlyDiagnostic || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || preflight.x36Opened
    error('Causal option preflight violates the frozen contract.');
end
expectedReferenceIdx = find(all(expectedSequences == ...
    protocol.rollingSafeCausalOptionReferenceSequence, 2));
if numel(expectedReferenceIdx) ~= 1 || ...
        preflight.referenceOptionIndex ~= expectedReferenceIdx || ...
        numel(preflight.optionStatus) ~= size(expectedSequences, 1) || ...
        numel(preflight.optionFailureIdentifier) ~= ...
            size(expectedSequences, 1) || ...
        numel(preflight.optionFailureMessage) ~= ...
            size(expectedSequences, 1) || ...
        numel(preflight.optionExpectedUnavailable) ~= ...
            size(expectedSequences, 1) || ...
        ~iscell(preflight.firstActionGraphSha256) || ...
        ~iscell(preflight.firstActionFusionWeightSha256) || ...
        numel(preflight.firstActionGraphSha256) ~= ...
            size(expectedSequences, 1) || ...
        numel(preflight.firstActionFusionWeightSha256) ~= ...
            size(expectedSequences, 1) || ...
        ~strcmp(preflight.sourceHistoryLabel, ...
            expectedHistorySourceLabel(behaviorAction))
    error('Causal option preflight has an invalid reference index.');
end
completed = strcmp(preflight.optionStatus, 'completed');
for optionIdx = find(completed)
    if ~isValidSha256(preflight.firstActionGraphSha256{optionIdx}) || ...
            ~isValidSha256( ...
                preflight.firstActionFusionWeightSha256{optionIdx})
        error('Completed causal option lacks a valid first-action hash.');
    end
end
end

function label = expectedHistorySourceLabel(behaviorAction)
switch behaviorAction
    case 'fixed-counter-clockwise'
        token = 'fixed-counter-clockwise';
    case 'label-set-message-passing-safe-fixed-e05-a70'
        token = 'label-set-message-passing';
    otherwise
        error('Unknown causal option source behavior action.');
end
label = ['behavior-return-source-v1:', token];
end

function assertPairedReferenceEqual( ...
        persistentPreflight, oneStep, protocol)
assertRollingSafeCausalOptionPairedFirstActions( ...
    persistentPreflight, oneStep);
persistentOutcome = ...
    persistentPreflight.outcomes( ...
        persistentPreflight.referenceOptionIndex);
oneStepOutcome = oneStep.outcomes(oneStep.referenceOptionIndex);
tolerance = protocol.rollingSafeCausalOptionReferenceTolerance;
metrics = [ ...
    persistentOutcome.meanEospa, oneStepOutcome.meanEospa, ...
    persistentOutcome.worstSensorEospa, ...
        oneStepOutcome.worstSensorEospa, ...
    persistentOutcome.consensusOspa, oneStepOutcome.consensusOspa, ...
    persistentOutcome.attemptedBytes, oneStepOutcome.attemptedBytes, ...
    persistentOutcome.deliveredBytes, oneStepOutcome.deliveredBytes];
if any(~isfinite(metrics)) || ...
        ~strcmp(persistentPreflight.sourceSha256, ...
        oneStep.sourceSha256) || ...
        ~isequal(persistentPreflight.returnTimes, oneStep.returnTimes) || ...
        ~strcmp(persistentPreflight.sourceGenerationGitCommit, ...
            oneStep.sourceGenerationGitCommit) || ...
        ~strcmp(persistentPreflight.sourceCacheSha256, ...
            oneStep.sourceCacheSha256) || ...
        ~strcmp(persistentPreflight.sourceBehaviorModelSha256, ...
            oneStep.sourceBehaviorModelSha256) || ...
        ~strcmp(persistentPreflight.sourceHistoryLabel, ...
            oneStep.sourceHistoryLabel) || ...
        ~strcmp(persistentPreflight.restartReferenceOverallSha256, ...
            oneStep.restartReferenceOverallSha256) || ...
        ~strcmp(persistentPreflight.restartObservedOverallSha256, ...
            oneStep.restartObservedOverallSha256) || ...
        abs(persistentOutcome.meanEospa - ...
            oneStepOutcome.meanEospa) > tolerance || ...
        abs(persistentOutcome.worstSensorEospa - ...
            oneStepOutcome.worstSensorEospa) > tolerance || ...
        abs(persistentOutcome.consensusOspa - ...
            oneStepOutcome.consensusOspa) > tolerance || ...
        persistentOutcome.attemptedBytes ~= ...
            oneStepOutcome.attemptedBytes || ...
        persistentOutcome.deliveredBytes ~= ...
            oneStepOutcome.deliveredBytes || ...
        ~isequal(persistentOutcome.attemptedBytesByStep, ...
            oneStepOutcome.attemptedBytesByStep) || ...
        ~isequal(persistentOutcome.deliveredBytesByStep, ...
            oneStepOutcome.deliveredBytesByStep) || ...
        ~isequal(persistentOutcome.messageCounts, ...
            oneStepOutcome.messageCounts) || ...
        ~isequal(persistentOutcome.policyReportedRepairByStep, ...
            oneStepOutcome.policyReportedRepairByStep) || ...
        ~isequal(persistentOutcome.oneStepReserveChecked, ...
            oneStepOutcome.oneStepReserveChecked) || ...
        ~isequal(persistentOutcome.oneStepReservePassed, ...
            oneStepOutcome.oneStepReservePassed) || ...
        ~isequal(persistentOutcome.selectedSensorB3Pass, ...
            oneStepOutcome.selectedSensorB3Pass) || ...
        ~isequal(persistentOutcome.selectedFormationB3Pass, ...
            oneStepOutcome.selectedFormationB3Pass) || ...
        ~isequal(persistentOutcome.deliveredSensorB3Pass, ...
            oneStepOutcome.deliveredSensorB3Pass) || ...
        ~isequal(persistentOutcome.deliveredFormationB3Pass, ...
            oneStepOutcome.deliveredFormationB3Pass) || ...
        ~strcmp(persistentOutcome.trajectoryGraphSha256, ...
            oneStepOutcome.trajectoryGraphSha256) || ...
        ~strcmp(persistentOutcome.deliveredTrajectoryGraphSha256, ...
            oneStepOutcome.deliveredTrajectoryGraphSha256) || ...
        ~isfield(persistentOutcome.executionTrace, 'overallSha256') || ...
        ~isfield(oneStepOutcome.executionTrace, 'overallSha256') || ...
        ~strcmp(persistentOutcome.executionTrace.overallSha256, ...
            oneStepOutcome.executionTrace.overallSha256)
    error('Persistent and one-step paired references differ.');
end
end

function derived = recomputeBankDerived( ...
        preflight, eligibleMask, protocol)
optionCount = size(preflight.optionSequences, 1);
eligibleMask = logical(reshape(eligibleMask, 1, []));
if numel(eligibleMask) ~= optionCount
    error('Causal option eligible mask has the wrong size.');
end
completed = strcmp(preflight.optionStatus, 'completed');
unavailable = strcmp(preflight.optionStatus, 'unavailable');
if any(~completed & ~unavailable) || ...
        any(unavailable & ~preflight.optionExpectedUnavailable) || ...
        any(preflight.optionExpectedUnavailable & ~unavailable)
    error('Causal option artifact contains a non-registered failure state.');
end
for optionIdx = find(unavailable)
    if ~any(strcmp(preflight.optionFailureIdentifier{optionIdx}, ...
            protocol. ...
                rollingSafeCausalOptionExpectedUnavailableErrorIdentifiers))
        error('Causal option unavailable identifier is not registered.');
    end
end
referenceIdx = preflight.referenceOptionIndex;
if ~completed(referenceIdx)
    error('Causal option reference is not completed.');
end
reference = preflight.outcomes(referenceIdx);
validateCompletedOutcome(reference, protocol);
referenceLaterRepair = ...
    reference.laterPolicyReportedRepairCount;
meanGain = nan(1, optionCount);
worstGain = nan(1, optionCount);
consensusGain = nan(1, optionCount);
byteDeviation = nan(1, optionCount);
hardGate = false(1, optionCount);
for optionIdx = find(completed)
    outcome = preflight.outcomes(optionIdx);
    validateCompletedOutcome(outcome, protocol);
    meanGain(optionIdx) = relativeGain( ...
        reference.meanEospa, outcome.meanEospa);
    worstGain(optionIdx) = relativeGain( ...
        reference.worstSensorEospa, outcome.worstSensorEospa);
    consensusGain(optionIdx) = relativeGain( ...
        reference.consensusOspa, outcome.consensusOspa);
    byteDeviation(optionIdx) = 100 * abs( ...
        outcome.attemptedBytes - reference.attemptedBytes) / ...
        max(reference.attemptedBytes, eps);
    hardGate(optionIdx) = ...
        outcome.truthUseCount == 0 && ...
        outcome.payloadEmergencyCount == 0 && ...
        outcome.infeasibleCount == 0 && ...
        (~protocol. ...
            rollingSafeCausalOptionRequireNoInitialPolicyReportedRepair || ...
         outcome.initialPolicyReportedRepairCount == 0) && ...
        outcome.laterPolicyReportedRepairCount <= ...
            referenceLaterRepair + protocol. ...
                rollingSafeCausalOptionMaximumLaterPolicyReportedRepairExcess && ...
        all(outcome.oneStepReserveChecked) && ...
        all(outcome.oneStepReservePassed) && ...
        all(outcome.messageCounts == ...
            protocol.rollingSafeCausalOptionMessageBudget) && ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass) && ...
        outcome.firstActionExact && outcome.firstFusionWeightsExact;
end
admissible = completed & eligibleMask & hardGate & ...
    byteDeviation <= ...
        protocol.rollingSafeCausalOptionMaximumByteDeviationPercent;
if protocol.rollingSafeCausalOptionRequireWorstAndConsensusNonregression
    admissible = admissible & worstGain >= -1e-9 & ...
        consensusGain >= -1e-9;
end
admissibleIndices = find(admissible);
if isempty(admissibleIndices)
    error('Causal option bank has no admissible paired reference.');
end
[bestMean, localBestIdx] = min( ...
    [preflight.outcomes(admissibleIndices).meanEospa]);
bestIdx = admissibleIndices(localBestIdx);
completedHashes = ...
    {preflight.outcomes(completed).trajectoryGraphSha256};
derived = struct();
derived.completed = completed;
derived.unavailable = unavailable;
derived.meanGainVsReferencePercent = meanGain;
derived.worstGainVsReferencePercent = worstGain;
derived.consensusGainVsReferencePercent = consensusGain;
derived.attemptedByteDeviationPercent = byteDeviation;
derived.hardRuntimeGatePassed = hardGate;
derived.admissibleForSelection = admissible;
derived.referenceMeanEospa = reference.meanEospa;
derived.referenceWorstSensorEospa = reference.worstSensorEospa;
derived.referenceConsensusOspa = reference.consensusOspa;
derived.referenceLaterPolicyReportedRepairCount = referenceLaterRepair;
derived.bestAdmissibleOptionIndex = bestIdx;
derived.bestAdmissibleMeanEospa = bestMean;
derived.completedOptionCount = nnz(completed);
derived.unavailableOptionCount = nnz(unavailable);
derived.uniqueCompletedTrajectoryCount = ...
    numel(unique(completedHashes));
derived.bankSafetyPassed = hardGate(referenceIdx) && ...
    all(hardGate(completed)) && ...
    all(preflight.optionExpectedUnavailable(unavailable)) && ...
    any(admissible);
end

function validateCompletedOutcome(outcome, protocol)
horizon = protocol.returnValueGateHorizon;
scalarFields = { ...
    'meanEospa', 'worstSensorEospa', 'consensusOspa', ...
    'attemptedBytes', 'deliveredBytes', ...
    'truthUseCount', 'policyReportedRepairCount', ...
    'initialPolicyReportedRepairCount', ...
    'laterPolicyReportedRepairCount', ...
    'payloadEmergencyCount', 'infeasibleCount'};
for fieldIdx = 1:numel(scalarFields)
    fieldName = scalarFields{fieldIdx};
    if ~isfield(outcome, fieldName) || ...
            ~isscalar(outcome.(fieldName)) || ...
            ~isfinite(outcome.(fieldName)) || ...
            outcome.(fieldName) < 0
        error('Causal option outcome has an invalid scalar field.');
    end
end
numericVectors = { ...
    'messageCounts', 'attemptedBytesByStep', ...
    'deliveredBytesByStep'};
for fieldIdx = 1:numel(numericVectors)
    values = outcome.(numericVectors{fieldIdx});
    if ~isnumeric(values) || numel(values) ~= horizon || ...
            any(~isfinite(values(:))) || any(values(:) < 0)
        error('Causal option outcome has an invalid numeric trace.');
    end
end
binaryVectors = { ...
    'policyReportedRepairByStep', 'oneStepReserveChecked', ...
    'oneStepReservePassed', 'selectedSensorB3Pass', ...
    'selectedFormationB3Pass', 'deliveredSensorB3Pass', ...
    'deliveredFormationB3Pass'};
for fieldIdx = 1:numel(binaryVectors)
    requireFiniteBinaryDiagnostic( ...
        outcome.(binaryVectors{fieldIdx}), horizon, ...
        binaryVectors{fieldIdx});
end
firstActionExact = requireFiniteBinaryDiagnostic( ...
    outcome.firstActionExact, 1, 'firstActionExact');
firstFusionWeightsExact = requireFiniteBinaryDiagnostic( ...
    outcome.firstFusionWeightsExact, 1, ...
    'firstFusionWeightsExact');
if outcome.policyReportedRepairCount ~= ...
        nnz(outcome.policyReportedRepairByStep) || ...
        outcome.initialPolicyReportedRepairCount ~= ...
            nnz(outcome.policyReportedRepairByStep(1)) || ...
        outcome.laterPolicyReportedRepairCount ~= ...
            nnz(outcome.policyReportedRepairByStep(2:end)) || ...
        abs(outcome.attemptedBytes - ...
            sum(outcome.attemptedBytesByStep)) > 1e-9 || ...
        abs(outcome.deliveredBytes - ...
            sum(outcome.deliveredBytesByStep)) > 1e-9 || ...
        ~firstActionExact || ...
        ~firstFusionWeightsExact || ...
        ~isValidSha256(outcome.trajectoryGraphSha256) || ...
        ~isValidSha256(outcome.deliveredTrajectoryGraphSha256) || ...
        ~isstruct(outcome.executionTrace) || ...
        ~isfield(outcome.executionTrace, 'overallSha256') || ...
        ~isValidSha256(outcome.executionTrace.overallSha256)
    error('Causal option outcome trace is internally inconsistent.');
end
end

function assertStoredDerivedEqual(preflight, derived, protocol)
tolerance = protocol.rollingSafeCausalOptionReferenceTolerance;
if ~isequal(preflight.hardRuntimeGatePassed, ...
        derived.hardRuntimeGatePassed) || ...
        ~isequal(preflight.admissibleForSelection, ...
            derived.admissibleForSelection) || ...
        ~numericEqual(preflight.meanGainVsReferencePercent, ...
            derived.meanGainVsReferencePercent, tolerance) || ...
        ~numericEqual(preflight.worstGainVsReferencePercent, ...
            derived.worstGainVsReferencePercent, tolerance) || ...
        ~numericEqual(preflight.consensusGainVsReferencePercent, ...
            derived.consensusGainVsReferencePercent, tolerance) || ...
        ~numericEqual(preflight.attemptedByteDeviationPercent, ...
            derived.attemptedByteDeviationPercent, tolerance) || ...
        preflight.bestAdmissibleOptionIndex ~= ...
            derived.bestAdmissibleOptionIndex || ...
        ~strcmp(preflight.bestAdmissibleOptionName, ...
            preflight.optionNames{derived.bestAdmissibleOptionIndex}) || ...
        ~isequal(preflight.bestAdmissibleSequence, ...
            preflight.optionSequences( ...
                derived.bestAdmissibleOptionIndex, :)) || ...
        abs(preflight.bestAdmissibleMeanEospa - ...
            derived.bestAdmissibleMeanEospa) > tolerance || ...
        abs(preflight.bestAdmissibleGainVsReferencePercent - ...
            derived.meanGainVsReferencePercent( ...
                derived.bestAdmissibleOptionIndex)) > tolerance || ...
        abs(preflight.bestAdmissibleWorstGainVsReferencePercent - ...
            derived.worstGainVsReferencePercent( ...
                derived.bestAdmissibleOptionIndex)) > tolerance || ...
        abs(preflight.bestAdmissibleConsensusGainVsReferencePercent - ...
            derived.consensusGainVsReferencePercent( ...
                derived.bestAdmissibleOptionIndex)) > tolerance || ...
        abs(preflight.bestAdmissibleAttemptedByteDeviationPercent - ...
            derived.attemptedByteDeviationPercent( ...
                derived.bestAdmissibleOptionIndex)) > tolerance || ...
        preflight.completedOptionCount ~= derived.completedOptionCount || ...
        preflight.unavailableOptionCount ~= ...
            derived.unavailableOptionCount || ...
        preflight.uniqueCompletedTrajectoryCount ~= ...
            derived.uniqueCompletedTrajectoryCount || ...
        abs(preflight.referenceMeanEospa - ...
            derived.referenceMeanEospa) > tolerance || ...
        abs(preflight.referenceWorstSensorEospa - ...
            derived.referenceWorstSensorEospa) > tolerance || ...
        abs(preflight.referenceConsensusOspa - ...
            derived.referenceConsensusOspa) > tolerance || ...
        preflight.referenceLaterPolicyReportedRepairCount ~= ...
            derived.referenceLaterPolicyReportedRepairCount
    error('Stored causal option derived fields fail raw recomputation.');
end
end

function equal = numericEqual(left, right, tolerance)
equal = isequal(size(left), size(right));
if ~equal
    return;
end
bothNaN = isnan(left) & isnan(right);
finite = isfinite(left) & isfinite(right);
equal = all(bothNaN(:) | ...
    (finite(:) & abs(left(:) - right(:)) <= tolerance));
end

function valid = isValidSha256(value)
valid = ischar(value) && ...
    ~isempty(regexp(value, '^[0-9a-f]{64}$', 'once'));
end

