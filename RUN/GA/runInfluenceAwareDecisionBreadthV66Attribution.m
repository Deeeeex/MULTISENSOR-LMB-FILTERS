function [reportPath, result] = ...
    runInfluenceAwareDecisionBreadthV66Attribution(options)
% RUNINFLUENCEAWAREDECISIONBREADTHV66ATTRIBUTION Opened dev analysis.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getInfluenceAwareDecisionBreadthV66Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('InfluenceAwareAttributionV66:DirtySource', ...
        'V66 attribution requires a clean source checkout.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(protocol.cases));
v65 = getNetworkAdditiveFormationRiskV65Protocol();
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    fprintf('V66 influence attribution %d/%d: %s t=%d ...\n', ...
        caseIdx, numel(protocol.cases), ...
        entry.presetName, entry.currentTime);
    state = loadFormationH3ObservableState( ...
        entry.presetName, entry.seed, entry.currentTime, ...
        struct('cacheRoot', entry.cacheRoot));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds);
    baseMetrics = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    influenceMetrics = computeInfluenceAwareDecisionBreadthV66( ...
        control, state.context, state.groupIds, struct( ...
            'positiveSupportThreshold', ...
                protocol.positiveSupportThreshold, ...
            'horizonSteps', protocol.horizonSteps));
    selection = selectInfluenceAwareDecisionBreadthV66( ...
        baseMetrics, influenceMetrics, mergeOptions(v65, protocol));
    records(caseIdx) = makeRecord( ...
        entry, baseMetrics, selection);
    fprintf(['  risk=%.3f%% base=%s exposure=%.4f ', ...
        'crossings=%.0f V66=%d gain=%+.3f%%\n'], ...
        100 * baseMetrics.totalNetworkRescueFraction, ...
        mat2str(selection.baseSelectedFormationIds), ...
        selection.selectedNormalizedRobustMarginExposure, ...
        selection.selectedUpwardCrossings, ...
        selection.actionEnabled, entry.knownGainPercent);
end

strongMask = [records.knownGainPercent] >= ...
    v65.minimumMeanGainPercent - 1e-12;
weakMask = [records.knownGainPercent] < ...
    v65.weakGainPercent - 1e-12;
result = struct();
result.contractVersion = ...
    'influence-aware-decision-breadth-v66-attribution-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.records = records;
result.strongStatePassRate = mean([records(strongMask).actionEnabled]);
result.weakStateFallbackRate = mean(~[records(weakMask).actionEnabled]);
result.strictDevelopmentSeparation = ...
    all([records(strongMask).actionEnabled]) && ...
    all(~[records(weakMask).actionEnabled]);
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'INFLUENCE_AWARE_DECISION_BREADTH_V66_ATTRIBUTION.mat');
reportPath = fullfile(outputRoot, ...
    'INFLUENCE_AWARE_DECISION_BREADTH_V66_ATTRIBUTION.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V66 influence attribution: %s\n', reportPath);
end

function record = makeRecord(entry, baseMetrics, selection)
record = emptyRecord();
record.scaleName = entry.scaleName;
record.presetName = entry.presetName;
record.seed = entry.seed;
record.currentTime = entry.currentTime;
record.networkRiskFraction = ...
    baseMetrics.totalNetworkRescueFraction;
record.baseSelectedFormationIds = ...
    selection.baseSelectedFormationIds;
record.normalizedRobustMarginExposure = ...
    selection.selectedNormalizedRobustMarginExposure;
record.normalizedDecisionExposure = ...
    selection.selectedNormalizedDecisionExposure;
record.upwardCrossings = selection.selectedUpwardCrossings;
record.affectedReceiverCount = ...
    selection.selectedAffectedReceiverCount;
record.actionEnabled = selection.actionEnabled;
record.fallbackReason = selection.fallbackReason;
record.knownGainPercent = entry.knownGainPercent;
record.knownGainSource = entry.source;
end

function value = emptyRecord()
value = struct( ...
    'scaleName', '', ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'networkRiskFraction', NaN, ...
    'baseSelectedFormationIds', zeros(1, 0), ...
    'normalizedRobustMarginExposure', NaN, ...
    'normalizedDecisionExposure', NaN, ...
    'upwardCrossings', NaN, ...
    'affectedReceiverCount', NaN, ...
    'actionEnabled', false, ...
    'fallbackReason', '', ...
    'knownGainPercent', NaN, ...
    'knownGainSource', '');
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('InfluenceAwareAttributionV66:WriteFailed', ...
        'Could not create the V66 attribution report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V66 influence-aware decision-breadth attribution\n\n');
fprintf(fid, ['V66 keeps the complete V65 risk and useful-information ', ...
    'guards, then requires at least %.3f network-time-normalized ', ...
    'robust decision exposure.\n\n'], ...
    result.protocol.minimumNormalizedRobustMarginExposure);
fprintf(fid, ['| Scale / scene | Time | V65 risk | V65 set | ', ...
    'Robust exposure | Decision exposure | Crossings | Receivers | ', ...
    'V66 action | Known gain |\n']);
fprintf(fid, '|:--|--:|--:|:--|--:|--:|--:|--:|:--:|--:|\n');
for record = result.records
    fprintf(fid, ['| %s | %d | %.3f%% | `%s` | %.4f | %.4f | ', ...
        '%.0f | %.0f | %d | %+.3f%% |\n'], ...
        record.scaleName, record.currentTime, ...
        100 * record.networkRiskFraction, ...
        mat2str(record.baseSelectedFormationIds), ...
        record.normalizedRobustMarginExposure, ...
        record.normalizedDecisionExposure, ...
        record.upwardCrossings, record.affectedReceiverCount, ...
        record.actionEnabled, record.knownGainPercent);
end
fprintf(fid, '\n- Strong-state pass rate: `%.3f`\n', ...
    result.strongStatePassRate);
fprintf(fid, '- Weak-state fallback rate: `%.3f`\n', ...
    result.weakStateFallbackRate);
fprintf(fid, '- Strict development separation: `%d`\n', ...
    result.strictDevelopmentSeparation);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = mergeOptions(base, protocol)
value = base;
value.minimumNormalizedRobustMarginExposure = ...
    protocol.minimumNormalizedRobustMarginExposure;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
