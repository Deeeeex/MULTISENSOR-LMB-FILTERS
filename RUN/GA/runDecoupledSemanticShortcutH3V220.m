function [reportPath, result] = ...
        runDecoupledSemanticShortcutH3V220(options)
% RUNDECOUPLEDSEMANTICSHORTCUTH3V220 Label semantic shortcuts over H=3.
%
% Each arm reuses the same cached state and static-cycle reference.  The
% candidate is compared both with no-op and with its paired donor-only arm.

if nargin < 1 || isempty(options)
    options = struct();
end
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndicesProvided = isfield(options, 'recordIndices');
recordIndices = reshape(getField( ...
    options, 'recordIndices', zeros(1, 0)), 1, []);
reuseExistingScreens = logical(getField( ...
    options, 'reuseExistingScreens', true));
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2
    error('DecoupledSemanticShortcutV220:MissingCandidateBank', ...
        'A completed V220 semantic candidate bank is required.');
end
loaded = load(candidateBankPath, 'result');
bankResult = loaded.result;
if ~isstruct(bankResult) || ~isscalar(bankResult) || ...
        ~isfield(bankResult, 'contractVersion') || ...
        ~strcmp(bankResult.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        bankResult.truthUsedForCandidateFeatures || ...
        bankResult.futureInformationUsedForCandidateFeatures
    error('DecoupledSemanticShortcutV220:CandidateBankContract', ...
        'The V220 semantic candidate bank is malformed.');
end
feasibleRows = find(bankResult.creditFeasibleMask);
if ~recordIndicesProvided
    selectedRows = feasibleRows;
elseif isempty(recordIndices)
    selectedRows = zeros(1, 0);
else
    if any(~isfinite(recordIndices)) || ...
            any(recordIndices ~= round(recordIndices)) || ...
            numel(unique(recordIndices)) ~= numel(recordIndices)
        error('DecoupledSemanticShortcutV220:RecordIndices', ...
            'Requested record indices must be unique integers.');
    end
    [present, selectedRows] = ismember(recordIndices, ...
        [bankResult.records.recordIndex]);
    if ~all(present) || ...
            any(~bankResult.creditFeasibleMask(selectedRows))
        error('DecoupledSemanticShortcutV220:RecordIndices', ...
            'Every requested V220 record must be credit-feasible.');
    end
end

sourceLoaded = load(bankResult.sourceScreenPath, 'screen');
sourceScreen = sourceLoaded.screen;
referenceScreenPath = bankResult.sourceScreenPath;
sourceCachePath = resolveSourcePath( ...
    bankResult.sourceScreenPath, sourceScreen.cachePath);
protocol = getDecoupledSemanticShortcutV220Protocol();
v213 = getHierarchicalDelayedValueControllerV213Protocol();
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'semantic_h3', ...
    sprintf('%s_seed%d_t%d_donor_f%d', ...
        strrep(bankResult.presetName, '-', '_'), bankResult.seed, ...
        bankResult.currentTime, bankResult.donorFormationId))));
records = repmat(emptyRecord(), 1, numel(selectedRows));
for selectedPosition = 1:numel(selectedRows)
    row = selectedRows(selectedPosition);
    bankRecord = bankResult.records(row);
    leaf = sprintf('r%03d_b%d_s%d_l%d-%d', ...
        bankRecord.recordIndex, bankRecord.beneficiaryFormationId, ...
        bankRecord.sourceId, bankRecord.label(1), ...
        bankRecord.label(2));
    screenRoot = fullfile(outputRoot, leaf, 'screen');
    screenStem = sprintf( ...
        'FORMATION_MODE_H3_%s_SEED%d_T%d', ...
        upper(strrep(bankResult.presetName, '-', '_')), ...
        bankResult.seed, bankResult.currentTime);
    screenPath = fullfile(screenRoot, [screenStem, '.mat']);
    if reuseExistingScreens && reusableScreen( ...
            screenPath, bankResult, bankRecord)
        existing = load(screenPath, 'screen');
        candidateScreen = existing.screen;
    else
        screenOptions = struct();
        screenOptions.horizonSteps = protocol.horizonSteps;
        screenOptions.interventionDurationSteps = 1;
        screenOptions.filterSeedOffset = protocol.filterSeedOffset;
        screenOptions.cacheRoot = fileparts(sourceCachePath);
        screenOptions.interventionBankType = ...
            'decoupled-semantic-shortcut-v220';
        screenOptions.trackingAlignedExecutionProfile = ...
            'v214-direct-graph-payload-repair';
        screenOptions.receiverMode = protocol.receiverMode;
        screenOptions.directGraphSplitName = 'training';
        screenOptions.decoupledSemanticShortcutBankOptions = struct( ...
            'donorFormationId', bankRecord.donorFormationId, ...
            'beneficiaryFormationId', ...
                bankRecord.beneficiaryFormationId, ...
            'referenceAttemptedBytes', ...
                bankResult.referencePageBytes, ...
            'repairSourceWeight', protocol.repairSourceWeight, ...
            'repairIdealDeliveryTeacherMode', true, ...
            'repairForcedSourceId', bankRecord.sourceId, ...
            'repairForcedLabel', bankRecord.label);
        screenOptions.referenceOutcomeScreenPath = ...
            referenceScreenPath;
        screenOptions.outputDirectory = screenRoot;
        screenOptions.writeReport = true;
        screenOptions.capturePosteriorSnapshotsEnabled = false;
        screenOptions.captureFusedPosteriorSnapshotsEnabled = false;
        [~, candidateScreen] = runFormationModeOpenedReturnScreen( ...
            bankResult.presetName, bankResult.seed, ...
            bankResult.currentTime, screenOptions);
    end
    nonreferenceIdx = find([candidateScreen.records.actionIndex] ~= ...
        candidateScreen.bank.referenceActionIndex);
    if numel(nonreferenceIdx) ~= 1
        error('DecoupledSemanticShortcutV220:CandidateArm', ...
            'Each V220 screen must contain one semantic action.');
    end
    candidateRecord = candidateScreen.records(nonreferenceIdx);
    candidateOutcome = candidateScreen.outcomes(nonreferenceIdx);
    referenceOutcome = candidateScreen.outcomes( ...
        candidateScreen.referenceSubsetIndex);
    if candidateOutcome. ...
            budgetRecycledFormationRepairAppliedActionCountByTime(1) ~= 1
        error('DecoupledSemanticShortcutV220:ActionNotApplied', ...
            'The complete-label semantic shortcut did not execute once.');
    end
    donorRecord = bankResult.donorRecord;
    donorOutcome = sourceScreen.outcomes(find(strcmp( ...
        {sourceScreen.records.actionName}, ...
        donorRecord.actionName), 1));
    jointGainVector = buildGainVector( ...
        referenceOutcome, candidateOutcome, ...
        candidateScreen.sensorGroupIds, ...
        bankRecord.beneficiaryFormationId);
    incrementalGainVector = buildGainVector( ...
        donorOutcome, candidateOutcome, ...
        candidateScreen.sensorGroupIds, ...
        bankRecord.beneficiaryFormationId);
    jointRiskPassed = all(jointGainVector >= ...
        v213.risk.tolerancePercent - 1e-10);
    byteReservePassed = ...
        candidateRecord.attemptedByteSavingPercent >= ...
            v213.risk.minimumStaticAttemptedByteSavingPercent - 1e-10;
    incrementalCorePositive = ...
        incrementalGainVector(1) > 0 && ...
        incrementalGainVector(2) > 0 && ...
        incrementalGainVector(3) >= 0 && ...
        incrementalGainVector(4) >= 0;

    item = emptyRecord();
    item.recordIndex = bankRecord.recordIndex;
    item.donorFormationId = bankRecord.donorFormationId;
    item.beneficiaryFormationId = ...
        bankRecord.beneficiaryFormationId;
    item.sourceId = bankRecord.sourceId;
    item.label = bankRecord.label;
    item.screenPath = screenPath;
    item.jointGainVectorPercent = jointGainVector;
    item.incrementalGainVectorPercent = incrementalGainVector;
    item.meanEospaGainPercent = candidateRecord.meanGainPercent;
    item.meanRmseGainPercent = candidateRecord.rmseGainPercent;
    item.consensusGainPercent = ...
        candidateRecord.consensusGainPercent;
    item.terminalConsensusGainPercent = ...
        candidateRecord.terminalConsensusGainPercent;
    item.attemptedByteSavingPercent = ...
        candidateRecord.attemptedByteSavingPercent;
    item.incrementalEospaGainPercent = incrementalGainVector(1);
    item.incrementalRmseGainPercent = incrementalGainVector(2);
    item.incrementalConsensusGainPercent = ...
        incrementalGainVector(3);
    item.incrementalTerminalConsensusGainPercent = ...
        incrementalGainVector(4);
    item.incrementalBeneficiaryEospaGainPercent = ...
        incrementalGainVector(5);
    item.incrementalBeneficiaryRmseGainPercent = ...
        incrementalGainVector(6);
    item.donorSafetyLabel = bankResult.donorSafetyLabel;
    item.incrementalCorePositive = incrementalCorePositive;
    item.jointRiskPassed = jointRiskPassed;
    item.byteReservePassed = byteReservePassed;
    item.admittedTeacherLabel = ...
        item.donorSafetyLabel && incrementalCorePositive && ...
        jointRiskPassed && byteReservePassed;
    item.payloadAttemptedBytes = ...
        bankRecord.payloadAttemptedBytes;
    item.synopsisBytes = bankRecord.synopsisBytes;
    item.repairAttemptedBytes = sum(candidateOutcome. ...
        budgetRecycledFormationRepairAttemptedBytesByTime);
    records(selectedPosition) = item;
end

result = struct();
result.contractVersion = ...
    'decoupled-semantic-shortcut-h3-v220-v1';
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.sourceScreenPath = bankResult.sourceScreenPath;
result.presetName = bankResult.presetName;
result.seed = bankResult.seed;
result.currentTime = bankResult.currentTime;
result.donorFormationId = bankResult.donorFormationId;
result.donorSafetyLabel = bankResult.donorSafetyLabel;
result.records = records;
result.candidateCount = numel(records);
result.incrementalPositiveCount = ...
    nnz([records.incrementalCorePositive]);
result.admittedCandidateCount = ...
    nnz([records.admittedTeacherLabel]);
result.bestIncrementalRecordIndex = selectBest(records, false);
result.bestAdmittedRecordIndex = selectBest(records, true);
result.targetNames = v213.risk.targetNames;
result.idealDeliveryTeacherMode = true;
result.actualDeliveryConditionedCandidateBank = true;
result.donorAndBeneficiaryDecoupled = ...
    any([records.donorFormationId] ~= ...
        [records.beneficiaryFormationId]);
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.truthUsedForH3Targets = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'DECOUPLED_SEMANTIC_SHORTCUT_H3_V220.mat');
reportPath = fullfile(outputRoot, ...
    'DECOUPLED_SEMANTIC_SHORTCUT_H3_V220.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V220 decoupled semantic shortcut H=3: %s\n', reportPath);
end

function path = resolveSourcePath(sourceScreenPath, referencedPath)
if isempty(referencedPath)
    error('DecoupledSemanticShortcutV220:MissingSourceCache', ...
        'The captured donor screen does not identify its cache.');
end
if referencedPath(1) == filesep
    path = referencedPath;
else
    marker = [filesep, 'RUN', filesep, 'GA', filesep];
    positions = strfind(sourceScreenPath, marker);
    if isempty(positions)
        error('DecoupledSemanticShortcutV220:SourceRoot', ...
            'Could not resolve the donor-screen worktree root.');
    end
    root = sourceScreenPath(1:(positions(end) - 1));
    path = fullfile(root, referencedPath);
end
if exist(path, 'file') ~= 2
    error('DecoupledSemanticShortcutV220:MissingSourceCache', ...
        'The captured donor cache is unavailable: %s.', path);
end
end

function reusable = reusableScreen( ...
        screenPath, bankResult, bankRecord)
reusable = false;
if exist(screenPath, 'file') ~= 2
    return;
end
loaded = load(screenPath, 'screen');
screen = loaded.screen;
if ~isfield(screen, 'bank') || ...
        ~strcmp(screen.bank.bankVariant, ...
            'decoupled-semantic-shortcut-v220') || ...
        screen.bank.donorFormationId ~= ...
            bankRecord.donorFormationId || ...
        screen.bank.beneficiaryFormationId ~= ...
            bankRecord.beneficiaryFormationId || ...
        screen.bank.semanticShortcutSourceId ~= ...
            bankRecord.sourceId || ...
        ~isequal(screen.bank.semanticShortcutLabel, ...
            bankRecord.label)
    return;
end
nonreferenceIdx = find([screen.records.actionIndex] ~= ...
    screen.bank.referenceActionIndex);
if numel(nonreferenceIdx) ~= 1 || ...
        screen.outcomes(nonreferenceIdx). ...
            budgetRecycledFormationRepairAppliedActionCountByTime(1) ~= 1
    return;
end
details = screen.outcomes(nonreferenceIdx). ...
    budgetRecycledFormationRepairDetailsByTime{1};
reusable = details.targetFormationId == ...
    bankRecord.beneficiaryFormationId && ...
    details.forcedSourceId == bankRecord.sourceId && ...
    isequal(details.forcedLabel, bankRecord.label);
end

function gains = buildGainVector( ...
        reference, candidate, groupIds, beneficiaryFormationId)
receiverIds = find(groupIds == beneficiaryFormationId);
formationIds = unique(groupIds, 'stable');
beneficiaryRow = find(formationIds == ...
    beneficiaryFormationId, 1);
sensorEospaGain = relativeGainVector( ...
    reference.sensorMeanEospa, candidate.sensorMeanEospa);
sensorRmseGain = relativeGainVector( ...
    reference.sensorMeanRmse, candidate.sensorMeanRmse);
formationEospaGain = relativeGainVector( ...
    reference.formationMeanEospa, candidate.formationMeanEospa);
formationRmseGain = relativeGainVector( ...
    reference.formationMeanRmse, candidate.formationMeanRmse);
gains = [ ...
    relativeGain(reference.meanEospa, candidate.meanEospa), ...
    relativeGain(reference.meanRmse, candidate.meanRmse), ...
    relativeGain(reference.consensusOspa, candidate.consensusOspa), ...
    relativeGain(reference.terminalConsensusOspa, ...
        candidate.terminalConsensusOspa), ...
    formationEospaGain(beneficiaryRow), ...
    formationRmseGain(beneficiaryRow), ...
    min(sensorEospaGain(receiverIds)), ...
    min(sensorRmseGain(receiverIds)), ...
    relativeGain(reference.worstSensorEospa, ...
        candidate.worstSensorEospa), ...
    relativeGain(reference.worstSensorRmse, ...
        candidate.worstSensorRmse), ...
    min(formationEospaGain), ...
    min(formationRmseGain)];
end

function index = selectBest(records, admittedOnly)
index = 0;
if isempty(records)
    return;
end
eligible = 1:numel(records);
if admittedOnly
    eligible = find([records.admittedTeacherLabel]);
end
if isempty(eligible)
    return;
end
score = arrayfun(@(record) min([ ...
    record.incrementalEospaGainPercent, ...
    record.incrementalRmseGainPercent, ...
    record.incrementalConsensusGainPercent, ...
    record.incrementalTerminalConsensusGainPercent]), ...
    records(eligible));
[~, local] = max(score);
index = records(eligible(local)).recordIndex;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('DecoupledSemanticShortcutV220:WriteReport', ...
        'Could not write the V220 H=3 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V220 decoupled semantic shortcut H=3\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Donor formation / stage-1 safety: `F%d / %d`\n', ...
    result.donorFormationId, result.donorSafetyLabel);
fprintf(fid, '- Evaluated / incremental-positive / admitted: `%d / %d / %d`\n', ...
    result.candidateCount, result.incrementalPositiveCount, ...
    result.admittedCandidateCount);
fprintf(fid, '- Best incremental / admitted record: `%d / %d`\n\n', ...
    result.bestIncrementalRecordIndex, ...
    result.bestAdmittedRecordIndex);
fprintf(fid, ['| Row | Donor -> beneficiary | Source | Label | ', ...
    'Joint E / R / C / terminal | Increment over donor E / R / C / terminal | ', ...
    'Beneficiary increment E / R | Byte saving | Admit |\n']);
fprintf(fid, ['|--:|:--|--:|:--|:--|:--|:--|--:|:--:|\n']);
for record = result.records
    fprintf(fid, ...
        ['| %d | F%d -> F%d | %d | `[%d,%d]` | ', ...
         '`%+.3f / %+.3f / %+.3f / %+.3f%%` | ', ...
         '`%+.3f / %+.3f / %+.3f / %+.3f%%` | ', ...
         '`%+.3f / %+.3f%%` | %+.3f%% | %d |\n'], ...
        record.recordIndex, record.donorFormationId, ...
        record.beneficiaryFormationId, record.sourceId, ...
        record.label(1), record.label(2), ...
        record.meanEospaGainPercent, ...
        record.meanRmseGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.incrementalEospaGainPercent, ...
        record.incrementalRmseGainPercent, ...
        record.incrementalConsensusGainPercent, ...
        record.incrementalTerminalConsensusGainPercent, ...
        record.incrementalBeneficiaryEospaGainPercent, ...
        record.incrementalBeneficiaryRmseGainPercent, ...
        record.attemptedByteSavingPercent, ...
        record.admittedTeacherLabel);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'recordIndex', 0, ...
    'donorFormationId', 0, ...
    'beneficiaryFormationId', 0, ...
    'sourceId', 0, ...
    'label', zeros(2, 1), ...
    'screenPath', '', ...
    'jointGainVectorPercent', zeros(1, 12), ...
    'incrementalGainVectorPercent', zeros(1, 12), ...
    'meanEospaGainPercent', 0, ...
    'meanRmseGainPercent', 0, ...
    'consensusGainPercent', 0, ...
    'terminalConsensusGainPercent', 0, ...
    'attemptedByteSavingPercent', 0, ...
    'incrementalEospaGainPercent', 0, ...
    'incrementalRmseGainPercent', 0, ...
    'incrementalConsensusGainPercent', 0, ...
    'incrementalTerminalConsensusGainPercent', 0, ...
    'incrementalBeneficiaryEospaGainPercent', 0, ...
    'incrementalBeneficiaryRmseGainPercent', 0, ...
    'donorSafetyLabel', false, ...
    'incrementalCorePositive', false, ...
    'jointRiskPassed', false, ...
    'byteReservePassed', false, ...
    'admittedTeacherLabel', false, ...
    'payloadAttemptedBytes', 0, ...
    'synopsisBytes', 0, ...
    'repairAttemptedBytes', 0);
end

function values = relativeGainVector(reference, candidate)
values = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
