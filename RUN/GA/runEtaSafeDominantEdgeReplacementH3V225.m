function [reportPath, result] = ...
        runEtaSafeDominantEdgeReplacementH3V225(options)
% RUNETASAFEDOMINANTEDGEREPLACEMENTH3V225 Frozen label-edge screens.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getEtaSafeDominantEdgeReplacementV225Protocol();
options.etaProjectionEnabled = true;
options.inputRouteWeightMode = protocol.inputRouteWeightMode;
[reportPath, result] = ...
    runSinglePassSemanticInputRoutingH3V221(options);
if ~strcmp(result.contractVersion, ...
        'eta-safe-dominant-edge-replacement-h3-v225-v1') || ...
        ~result.etaProjectionEnabled || ...
        ~result.dominantEdgeReplacementEnabled || ...
        ~strcmp(result.inputRouteWeightMode, ...
            protocol.inputRouteWeightMode)
    error('EtaSafeDominantEdgeReplacementV225:WrapperDrift', ...
        'The V225 wrapper did not produce an eta-safe edge replacement.');
end
end
