function [reportPath, result] = ...
    runFovAwarePersistentRiskCoverageV94Headroom(options)
% RUNFOVAWAREPERSISTENTRISKCOVERAGEV94HEADROOM Paired static recheck.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFovAwarePersistentRiskCoverageV94Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('FovAwareV94:DirtySource', ...
        'V94 headroom requires a clean source checkout.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

anchorTemplate = struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'baselineName', protocol.baselineName, ...
    'referenceActionName', '', 'referenceMeanEospa', NaN, ...
    'candidateActionName', '', 'candidateMeanEospa', NaN, ...
    'strictCandidateCount', 0, 'meanGainPercent', 0, ...
    'worstSensorGainPercent', 0, ...
    'minimumFormationGainPercent', 0, ...
    'windowConsensusGainPercent', 0, ...
    'terminalConsensusGainPercent', 0, ...
    'attemptedByteSavingPercent', 0, ...
    'matchedStaticGatePassed', false, ...
    'screenReportPath', '');
anchors = repmat(anchorTemplate, 1, protocol.requiredAnchorPassCount);
anchorIdx = 0;
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    for currentTime = entry.anchorTimes
        anchorIdx = anchorIdx + 1;
        screenRoot = fullfile(outputRoot, 'screens', ...
            lower(entry.scaleName), sprintf('t%d', currentTime));
        screenOptions = struct( ...
            'horizonSteps', protocol.horizonSteps, ...
            'interventionDurationSteps', ...
                protocol.interventionDurationSteps, ...
            'filterSeedOffset', protocol.filterSeedOffset, ...
            'cacheRoot', entry.cacheRoot, ...
            'interventionBankType', ...
                'tracking-aligned-x36-schedule', ...
            'trackingAlignedExecutionProfile', ...
                'v65-network-additive-headroom', ...
            'trackingAlignedX36ScheduleBankOptions', struct( ...
                'positiveSupportThreshold', ...
                    protocol.positiveSupportThreshold, ...
                'bankVariant', 'network-additive-v65'), ...
            'receiverMode', protocol.receiverMode, ...
            'outputDirectory', screenRoot, ...
            'writeReport', true);
        [screenReportPath, screen] = ...
            runFormationModeOpenedReturnScreen( ...
                entry.presetName, entry.seed, currentTime, ...
                screenOptions);
        anchors(anchorIdx) = summarizeAnchor( ...
            screen, screenReportPath, entry, currentTime, protocol);
    end
end

result = struct();
result.contractVersion = ...
    'fov-aware-persistent-risk-coverage-v94-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.baselineName = protocol.baselineName;
result.missingLabelFusionMode = protocol.receiverMode;
result.anchors = anchors;
result.anchorPassCount = nnz([anchors.matchedStaticGatePassed]);
result.requiredAnchorPassCount = protocol.requiredAnchorPassCount;
result.crossScaleGatePassed = ...
    result.anchorPassCount == result.requiredAnchorPassCount;
result.fullEpisodeTrackingAuthorized = ...
    protocol.fullEpisodeTrackingAuthorized && ...
    result.crossScaleGatePassed;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'FOV_AWARE_PERSISTENT_RISK_COVERAGE_V94_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'FOV_AWARE_PERSISTENT_RISK_COVERAGE_V94_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V94 FoV-aware matched-static result: %s\n', reportPath);
end

function value = summarizeAnchor( ...
        screen, screenReportPath, entry, currentTime, protocol)
records = screen.records;
referenceIdx = screen.referenceSubsetIndex;
candidateMask = true(1, numel(records));
candidateMask(referenceIdx) = false;
strictMask = candidateMask & ...
    [records.posteriorProxyAllowed] & ...
    [records.selectedB3Passed] & ...
    [records.minimumFormationGainPercent] >= ...
        protocol.minimumFormationGainPercent - 1e-12 & ...
    [records.worstGainPercent] >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 & ...
    [records.consensusGainPercent] >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 & ...
    [records.terminalConsensusGainPercent] >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 & ...
    [records.attemptedByteSavingPercent] >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12;
candidateIndices = find(strictMask);
if isempty(candidateIndices)
    bestIdx = referenceIdx;
    bestGain = 0;
else
    [bestGain, localIdx] = max( ...
        [records(candidateIndices).meanGainPercent]);
    bestIdx = candidateIndices(localIdx);
end
value = struct( ...
    'scaleName', entry.scaleName, ...
    'presetName', entry.presetName, ...
    'seed', entry.seed, ...
    'currentTime', currentTime, ...
    'baselineName', protocol.baselineName, ...
    'referenceActionName', records(referenceIdx).actionName, ...
    'referenceMeanEospa', records(referenceIdx).meanEospa, ...
    'candidateActionName', records(bestIdx).actionName, ...
    'candidateMeanEospa', records(bestIdx).meanEospa, ...
    'strictCandidateCount', nnz(strictMask), ...
    'meanGainPercent', bestGain, ...
    'worstSensorGainPercent', records(bestIdx).worstGainPercent, ...
    'minimumFormationGainPercent', ...
        records(bestIdx).minimumFormationGainPercent, ...
    'windowConsensusGainPercent', ...
        records(bestIdx).consensusGainPercent, ...
    'terminalConsensusGainPercent', ...
        records(bestIdx).terminalConsensusGainPercent, ...
    'attemptedByteSavingPercent', ...
        records(bestIdx).attemptedByteSavingPercent, ...
    'matchedStaticGatePassed', ...
        nnz(strictMask) > 0 && ...
        bestGain >= protocol.minimumMeanGainPercent - 1e-12, ...
    'screenReportPath', screenReportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FovAwareV94:WriteFailed', ...
        'Could not create the V94 headroom report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V94 FoV-aware persistent risk coverage\n\n');
fprintf(fid, '- Matched baseline: `%s`\n', result.baselineName);
fprintf(fid, '- Receiver semantics: `%s`\n', ...
    result.missingLabelFusionMode);
fprintf(fid, ['- Pairing: same cached posterior, measurements, ', ...
    'link uniforms, filter RNG, horizon and communication constraints.\n']);
fprintf(fid, '- Frozen per-anchor gate: `mean E-OSPA gain >= %.1f%%`; ', ...
    result.protocol.minimumMeanGainPercent);
fprintf(fid, ['worst sensor, minimum formation, consensus and ', ...
    'attempted bytes must not regress.\n\n']);
fprintf(fid, ['| Scale | t | Static E-OSPA | Candidate E-OSPA | ', ...
    'Mean gain | Worst sensor | Min formation | Consensus | ', ...
    'Bytes | Pass |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(result.anchors)
    entry = result.anchors(idx);
    fprintf(fid, ['| %s | %d | %.6f | %.6f | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        entry.scaleName, entry.currentTime, ...
        entry.referenceMeanEospa, entry.candidateMeanEospa, ...
        entry.meanGainPercent, entry.worstSensorGainPercent, ...
        entry.minimumFormationGainPercent, ...
        entry.windowConsensusGainPercent, ...
        entry.attemptedByteSavingPercent, ...
        entry.matchedStaticGatePassed);
end
fprintf(fid, '\n- Cross-scale pass: `%d / %d`; gate `%d`.\n\n', ...
    result.anchorPassCount, result.requiredAnchorPassCount, ...
    result.crossScaleGatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
