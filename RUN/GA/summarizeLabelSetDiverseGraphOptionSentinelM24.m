function [reportPath, summary] = ...
    summarizeLabelSetDiverseGraphOptionSentinelM24(options)
% SUMMARIZELABELSETDIVERSEGRAPHOPTIONSENTINELM24 Gate persistent ranks.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.diverseGraphOptionImplementationAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 diverse graph-option sentinel is not authorized.');
end
states = struct( ...
    'seed', {11, 19, 23, 27}, ...
    'time', {78, 78, 78, 78}, ...
    'behavior', {'learned', 'ccw', 'ccw', 'learned'}, ...
    'behaviorAction', { ...
        'label-set-message-passing-safe-fixed-e05-a70', ...
        'fixed-counter-clockwise', ...
        'fixed-counter-clockwise', ...
        'label-set-message-passing-safe-fixed-e05-a70'});
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'diverse_graph_option_sentinel_v1'));
rows = repmat(emptyRow(), 1, numel(states));
for stateIdx = 1:numel(states)
    state = states(stateIdx);
    path = fullfile(inputDirectory, ...
        sprintf('seed%d', state.seed), sprintf([ ...
            'label_set_causal_graph_option_h3_m24_', ...
            'seed%d_t%d_%s_source.mat'], ...
            state.seed, state.time, state.behavior));
    loaded = load(path, 'preflight');
    if ~isfield(loaded, 'preflight')
        error('Diverse sentinel artifact lacks preflight.');
    end
    preflight = loaded.preflight;
    validatePreflight(preflight, state, protocol);
    risk = [preflight.outcomes.meanEospa];
    oldOracle = min(risk(1:2));
    [newOracle, bestIdx] = min(risk);
    row = emptyRow();
    row.seed = state.seed;
    row.currentTime = state.time;
    row.behavior = state.behavior;
    row.artifactPath = path;
    row.cccMeanEospa = risk(1);
    row.g1MeanEospa = risk(2);
    row.oldOracleMeanEospa = oldOracle;
    row.newOracleMeanEospa = newOracle;
    row.bestOption = preflight.actionSequenceNames{bestIdx};
    row.gainVsCccPercent = relativeGain(risk(1), newOracle);
    row.incrementalGainVsOldOraclePercent = ...
        relativeGain(oldOracle, newOracle);
    row.refreshesOldOracle = newOracle < oldOracle - 1e-12;
    row.attemptedByteDeviationPercent = max(abs( ...
        preflight.attemptedByteDeviationPercent));
    row.restartEquivalencePassed = ...
        preflight.restartEquivalencePassed;
    row.safetyPassed = ...
        ~preflight.runtimePolicyUsesTruth && ...
        all([preflight.outcomes.repairCount] == 0) && ...
        all([preflight.outcomes.payloadEmergencyCount] == 0) && ...
        all([preflight.outcomes.infeasibleCount] == 0) && ...
        all(arrayfun(@(outcome) ...
            all(outcome.messageCounts == ...
                protocol. ...
                    diverseGraphOptionExpectedSelectedMessageCount) && ...
            all(outcome.selectedSensorB3Pass) && ...
            all(outcome.selectedFormationB3Pass), ...
            preflight.outcomes));
    rows(stateIdx) = row;
end

meanCcc = mean([rows.cccMeanEospa]);
meanOldOracle = mean([rows.oldOracleMeanEospa]);
meanNewOracle = mean([rows.newOracleMeanEospa]);
aggregateIncrementalGainPercent = ...
    relativeGain(meanOldOracle, meanNewOracle);
improvedStateCount = nnz([rows.refreshesOldOracle]);
nonOutlierGainStateCount = nnz( ...
    [rows.gainVsCccPercent] >= ...
        protocol.diverseGraphOptionMinimumSentinelGainPercent);
hardAuditPassed = ...
    all([rows.restartEquivalencePassed]) && ...
    all([rows.safetyPassed]) && ...
    max([rows.attemptedByteDeviationPercent]) <= ...
        protocol.macroActionMaximumByteDeviationPercent;
sentinelHeadroomPassed = ...
    improvedStateCount >= ...
        protocol. ...
            diverseGraphOptionMinimumSentinelImprovedStateCount && ...
    nonOutlierGainStateCount >= ...
        protocol. ...
            diverseGraphOptionMinimumSentinelImprovedStateCount && ...
    aggregateIncrementalGainPercent >= ...
        protocol. ...
            diverseGraphOptionMinimumIncrementalOracleGainPercent;

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-label-set-diverse-persistent-rank-sentinel-summary-v1';
summary.auditContractVersion = ...
    protocol.diverseGraphOptionAuditContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.rows = rows;
summary.meanCccEospa = meanCcc;
summary.meanOldTwoOptionOracleEospa = meanOldOracle;
summary.meanDiverseOracleEospa = meanNewOracle;
summary.aggregateIncrementalOracleGainPercent = ...
    aggregateIncrementalGainPercent;
summary.improvedStateCount = improvedStateCount;
summary.nonOutlierGainStateCount = nonOutlierGainStateCount;
summary.maximumByteDeviationPercent = ...
    max([rows.attemptedByteDeviationPercent]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.sentinelHeadroomGatePassed = sentinelHeadroomPassed;
summary.persistentRankBankRejected = ~sentinelHeadroomPassed;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.nextMethodDirection = [ ...
    'causal-time-structured-h3-options-over-safe-diverse-ranks'];
summary.evidenceBoundary = [ ...
    'This opened-training sentinel measures offline oracle headroom ', ...
    'of six persistent safe GNN graph ranks on four adversarial M24 ', ...
    'behavior states. It does not establish a selector, development, ', ...
    'held-out M24 or X36 result.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = 'label_set_diverse_graph_option_sentinel_m24_v1';
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Diverse sentinel summary already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary, protocol);
fprintf('Diverse sentinel summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function validatePreflight(preflight, state, protocol)
if ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.auditMode, ...
            'diverse-proposal-headroom') || ...
        ~strcmp(preflight.auditContractVersion, ...
            protocol.diverseGraphOptionAuditContractVersion) || ...
        preflight.seed ~= state.seed || ...
        preflight.currentTime ~= state.time || ...
        ~strcmp(preflight.sourceBehaviorAction, ...
            state.behaviorAction) || ...
        ~isequal(preflight.actionSequences, ...
            protocol.diverseGraphOptionActionSequences) || ...
        preflight.exploratoryActionSubsetUsed || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || ...
        preflight.x36Opened
    error('Diverse sentinel preflight violates the frozen contract.');
end
end

function writeReport(path, summary, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write diverse sentinel report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 diverse persistent-rank H=3 sentinel\n\n');
fprintf(fid, '- States: `%d`\n', numel(summary.rows));
fprintf(fid, [ ...
    '- Mean CCC / old oracle / diverse oracle E-OSPA: ', ...
    '`%.6f / %.6f / %.6f`\n'], ...
    summary.meanCccEospa, ...
    summary.meanOldTwoOptionOracleEospa, ...
    summary.meanDiverseOracleEospa);
fprintf(fid, '- Incremental oracle gain: `%.3f%%` (gate `%.3f%%`)\n', ...
    summary.aggregateIncrementalOracleGainPercent, ...
    protocol.diverseGraphOptionMinimumIncrementalOracleGainPercent);
fprintf(fid, '- Refreshed old oracle states: `%d / %d`\n', ...
    summary.improvedStateCount, numel(summary.rows));
fprintf(fid, '- States with >=5%% gain versus CCC: `%d / %d`\n', ...
    summary.nonOutlierGainStateCount, numel(summary.rows));
fprintf(fid, '- Hard audit / sentinel headroom gates: `%d / %d`\n\n', ...
    summary.hardAuditGatesPassed, ...
    summary.sentinelHeadroomGatePassed);
fprintf(fid, ...
    ['| Seed | Source | CCC | G1 | Old oracle | Diverse oracle | ', ...
     'Best | Incremental | Gain vs CCC | Safe |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|--:|--:|:--|--:|--:|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, ...
        ['| %d | %s | %.6f | %.6f | %.6f | %.6f | `%s` | ', ...
         '%+.3f%% | %+.3f%% | %d |\n'], ...
        row.seed, row.behavior, row.cccMeanEospa, ...
        row.g1MeanEospa, row.oldOracleMeanEospa, ...
        row.newOracleMeanEospa, row.bestOption, ...
        row.incrementalGainVsOldOraclePercent, ...
        row.gainVsCccPercent, row.safetyPassed);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, ...
    ['The persistent-rank proposal bank is `%s`. The next opened ', ...
     'training-only method direction is `%s`.\n\n'], ...
    decisionText(summary.persistentRankBankRejected), ...
    summary.nextMethodDirection);
fprintf(fid, '## Boundary\n\n%s\n', summary.evidenceBoundary);
end

function text = decisionText(rejected)
if rejected
    text = 'rejected';
else
    text = 'accepted for full-grid auditing';
end
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behavior', '', ...
    'artifactPath', '', ...
    'cccMeanEospa', NaN, ...
    'g1MeanEospa', NaN, ...
    'oldOracleMeanEospa', NaN, ...
    'newOracleMeanEospa', NaN, ...
    'bestOption', '', ...
    'gainVsCccPercent', NaN, ...
    'incrementalGainVsOldOraclePercent', NaN, ...
    'refreshesOldOracle', false, ...
    'attemptedByteDeviationPercent', NaN, ...
    'restartEquivalencePassed', false, ...
    'safetyPassed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
