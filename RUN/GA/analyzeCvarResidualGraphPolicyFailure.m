function [analysisPath, analysis] = ...
    analyzeCvarResidualGraphPolicyFailure(options)
% ANALYZECVARRESIDUALGRAPHPOLICYFAILURE Training-only v2 decomposition.
%
% This analysis keeps whole-seed outer folds, leaves each fold's
% calibration seed unused for formation-risk fitting, and never opens the
% development split. It asks whether node-risk prediction or edge-value
% prediction dominates structured action failure, and whether an
% action-aligned formation abstraction is more predictable.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCvarResidualGraphPolicyDatasetProtocol();
if ~protocol.rejectedV2 || ...
        ~protocol.formationActionAlignedPivotAuthorized || ...
        protocol.developmentEvaluationAuthorized
    error('Formation-level failure analysis is not authorized.');
end
bundle = loadCvarResidualGraphPolicyShards('training');
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official failure decomposition requires clean source.');
end

actionRows = repmat(emptyActionRow(), 1, 0);
for foldIdx = 1:numel(protocol.outerLosoHeldoutSeeds)
    heldoutSeed = ...
        protocol.outerLosoHeldoutSeeds(foldIdx);
    calibrationSeed = ...
        protocol.outerLosoCalibrationSeeds(foldIdx);
    fitSeeds = setdiff(protocol.trainingSeeds, ...
        [heldoutSeed, calibrationSeed], 'stable');
    model = fitCvarResidualGraphPolicyModel( ...
        bundle.graphBlocks, fitSeeds, ...
        'ridge', protocol);
    calibration = ...
        calibrateCvarResidualGraphSafetyMargin( ...
            model, bundle.graphBlocks( ...
                [bundle.graphBlocks.seed] == ...
                    calibrationSeed), protocol);
    testMask = [bundle.graphBlocks.seed] == ...
        heldoutSeed;
    testGraphBlocks = bundle.graphBlocks(testMask);
    testBehaviorBlocks = bundle.behaviorBlocks(testMask);
    for blockIdx = 1:numel(testGraphBlocks)
        actionRows(end + 1) = evaluateActionCases( ... %#ok<AGROW>
            model, calibration, ...
            testGraphBlocks(blockIdx), ...
            testBehaviorBlocks(blockIdx), protocol);
    end
end
actionMetrics = summarizeActionRows(actionRows);

formationVariants = { ...
    'mean', 'mean-max', 'mean-max-min-std'};
formationRidgeLambdas = [1e-2, 1e-1, 1, 10, 100];
formationCandidates = repmat( ...
    emptyFormationCandidate(), 1, ...
    numel(formationVariants) * ...
        numel(formationRidgeLambdas));
candidateCursor = 0;
for variantIdx = 1:numel(formationVariants)
    variant = formationVariants{variantIdx};
    for lambda = formationRidgeLambdas
        rows = repmat(emptyFormationRow(), 1, 0);
        for foldIdx = 1:numel( ...
                protocol.outerLosoHeldoutSeeds)
            heldoutSeed = ...
                protocol.outerLosoHeldoutSeeds(foldIdx);
            calibrationSeed = ...
                protocol.outerLosoCalibrationSeeds(foldIdx);
            fitSeeds = setdiff(protocol.trainingSeeds, ...
                [heldoutSeed, calibrationSeed], 'stable');
            fitMask = ismember( ...
                [bundle.graphBlocks.seed], fitSeeds);
            testMask = [bundle.graphBlocks.seed] == ...
                heldoutSeed;
            training = buildFormationRows( ...
                bundle.graphBlocks(fitMask), ...
                bundle.behaviorBlocks(fitMask), ...
                variant);
            model = fitFormationRidge( ...
                training.X, training.y, lambda);
            test = buildFormationRows( ...
                bundle.graphBlocks(testMask), ...
                bundle.behaviorBlocks(testMask), ...
                variant);
            prediction = scoreFormationRidge( ...
                model, test.X);
            rows = [rows, evaluateFormationRows( ... %#ok<AGROW>
                test, prediction)];
        end
        candidateCursor = candidateCursor + 1;
        candidate = emptyFormationCandidate();
        candidate.variant = variant;
        candidate.lambda = lambda;
        candidate.rows = rows;
        candidate.metrics = ...
            summarizeFormationRows(rows);
        formationCandidates(candidateCursor) = candidate;
    end
end

analysis = struct();
analysis.contractVersion = ...
    'm24-cvar-graph-v2-training-failure-decomposition-v1';
analysis.generatedAt = datestr(now, 31);
analysis.generationGitCommit = gitState.commit;
analysis.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
analysis.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
analysis.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
analysis.protocolId = protocol.id;
analysis.datasetSetSha256 = ...
    protocol.fullShardDatasetSetSha256;
analysis.featureContractSha256 = ...
    protocol.fullShardFeatureContractSha256;
analysis.trainingSeeds = protocol.trainingSeeds;
analysis.developmentSeedsOpened = false;
analysis.actionRows = actionRows;
analysis.actionMetrics = actionMetrics;
analysis.formationCandidates = formationCandidates;
analysis.formationBestByTop1Accuracy = ...
    selectBestFormationCandidate( ...
        formationCandidates);
analysis.formationVariants = formationVariants;
analysis.formationRidgeLambdas = ...
    formationRidgeLambdas;
analysis.developmentEvaluationAuthorized = false;
analysis.heldoutM24Authorized = false;
analysis.x36Authorized = false;
analysis.evidenceBoundary = [ ...
    'This is an architecture-diagnosis analysis on the already-opened ', ...
    'training seeds only. Oracle substitutions localize error and are ', ...
    'not deployable policies. Formation candidates are exploratory ', ...
    'training-LOSO diagnostics and cannot select a final model or open ', ...
    'development labels.'];

analysisPath = getField(options, 'analysisPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'cvar_residual_graph_policy_failure_decomposition_m24.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'CVAR_RESIDUAL_GRAPH_POLICY_FAILURE_DECOMPOSITION_M24.md'));
analysis.analysisPath = analysisPath;
analysis.reportPath = reportPath;
save('-mat7-binary', analysisPath, 'analysis');
writeReport(reportPath, analysis);
fprintf('CVaR graph failure decomposition: %s\nReport: %s\n', ...
    analysisPath, reportPath);
end

function row = evaluateActionCases( ...
        model, calibration, block, behaviorBlock, protocol)
learned = scoreCvarResidualGraphPolicyModel( ...
    model, block);
oracleSafeScores = 2 * double( ...
    block.edgeReferenceSafeTarget) - 1;
cases = repmat(struct( ...
    'name', '', 'scores', struct(), ...
    'margin', 0), 1, 4);
cases(1) = struct('name', 'learned-node-learned-edge', ...
    'scores', learned, 'margin', calibration.margin);
oracleNode = learned;
oracleNode.nodeRisk = ...
    reshape(block.nodeRiskTarget, 1, []);
cases(2) = struct('name', 'oracle-node-learned-edge', ...
    'scores', oracleNode, 'margin', calibration.margin);
oracleEdge = learned;
oracleEdge.edgeTaskAdvantage = ...
    block.edgeTaskAdvantageTarget;
oracleEdge.edgeProtectionAdvantage = ...
    oracleSafeScores;
cases(3) = struct('name', 'learned-node-oracle-edge', ...
    'scores', oracleEdge, 'margin', 0);
oracleBoth = oracleEdge;
oracleBoth.nodeRisk = ...
    reshape(block.nodeRiskTarget, 1, []);
cases(4) = struct('name', 'oracle-node-oracle-edge', ...
    'scores', oracleBoth, 'margin', 0);

caseResults = repmat(emptyActionCase(), 1, numel(cases));
for caseIdx = 1:numel(cases)
    projection = projectCvarResidualGraphPolicyScores( ...
        cases(caseIdx).scores, block, behaviorBlock, ...
        cases(caseIdx).margin, protocol);
    selectedMask = ...
        projection.selectedEdgeWeightMask;
    trueTail = logical(reshape( ...
        block.nodeCvarMaskTarget, 1, []));
    selectedRows = find(any(selectedMask, 2));
    selectedTailRows = selectedRows( ...
        trueTail(block.receiverIndices(selectedRows)));
    selectedTailSafe = true;
    for rowIdx = reshape(selectedTailRows, 1, [])
        weightIdx = find(selectedMask(rowIdx, :), 1);
        selectedTailSafe = selectedTailSafe && ...
            block.edgeReferenceSafeTarget(rowIdx, weightIdx);
    end
    caseResult = emptyActionCase();
    caseResult.name = cases(caseIdx).name;
    caseResult.selectedTrueTaskAdvantage = sum( ...
        block.edgeTaskAdvantageTarget(selectedMask));
    caseResult.selectedTailSafe = selectedTailSafe;
    caseResult.fallbackUsed = projection.fallbackUsed;
    caseResult.selectedCrossEdgeCount = ...
        projection.crossFormationEdgeCount;
    caseResults(caseIdx) = caseResult;
end
oracleValue = caseResults(4).selectedTrueTaskAdvantage;
for caseIdx = 1:numel(caseResults)
    caseResults(caseIdx).oracleActionGap = ...
        oracleValue - ...
            caseResults(caseIdx).selectedTrueTaskAdvantage;
end
row = emptyActionRow();
row.seed = block.seed;
row.currentTime = block.currentTime;
row.cases = caseResults;
end

function metrics = summarizeActionRows(rows)
caseNames = {rows(1).cases.name};
caseMetrics = repmat(struct( ...
    'name', '', 'meanSelectedTaskAdvantage', NaN, ...
    'medianOracleActionGap', NaN, ...
    'p90OracleActionGap', NaN, ...
    'nonnegativeTaskFraction', NaN, ...
    'selectedTailSafeFraction', NaN, ...
    'fallbackCount', NaN), 1, numel(caseNames));
for caseIdx = 1:numel(caseNames)
    values = arrayfun(@(row) ...
        row.cases(caseIdx).selectedTrueTaskAdvantage, rows);
    gaps = arrayfun(@(row) ...
        row.cases(caseIdx).oracleActionGap, rows);
    safe = arrayfun(@(row) ...
        row.cases(caseIdx).selectedTailSafe, rows);
    fallback = arrayfun(@(row) ...
        row.cases(caseIdx).fallbackUsed, rows);
    caseMetrics(caseIdx) = struct( ...
        'name', caseNames{caseIdx}, ...
        'meanSelectedTaskAdvantage', mean(values), ...
        'medianOracleActionGap', median(gaps), ...
        'p90OracleActionGap', empiricalQuantile(gaps, 0.90), ...
        'nonnegativeTaskFraction', mean(values >= -1e-12), ...
        'selectedTailSafeFraction', mean(safe), ...
        'fallbackCount', nnz(fallback));
end
metrics = struct('stateCount', numel(rows), ...
    'caseMetrics', caseMetrics);
end

function data = buildFormationRows( ...
        graphBlocks, behaviorBlocks, variant)
X = zeros(0, 0);
y = zeros(0, 1);
tailMass = zeros(0, 1);
seed = zeros(0, 1);
currentTime = zeros(0, 1);
formation = zeros(0, 1);
state = zeros(0, 1);
stateCursor = 0;
for blockIdx = 1:numel(graphBlocks)
    graphBlock = graphBlocks(blockIdx);
    behaviorBlock = behaviorBlocks(blockIdx);
    if graphBlock.seed ~= behaviorBlock.seed || ...
            graphBlock.currentTime ~= behaviorBlock.currentTime
        error('Formation analysis graph/behavior order mismatch.');
    end
    groupIds = reshape(behaviorBlock.groupIds, 1, []);
    groups = unique(groupIds, 'stable');
    stateCursor = stateCursor + 1;
    baseByGroup = zeros(0, 0);
    for groupIdx = 1:numel(groups)
        members = groupIds == groups(groupIdx);
        base = aggregateFormationFeatures( ...
            graphBlock.nodeFeatures(members, :), ...
            variant);
        if isempty(baseByGroup)
            baseByGroup = zeros(numel(groups), numel(base));
        end
        baseByGroup(groupIdx, :) = base;
    end
    centered = bsxfun(@minus, ...
        baseByGroup, mean(baseByGroup, 1));
    stateX = [baseByGroup, centered];
    if isempty(X)
        X = zeros(0, size(stateX, 2));
    end
    X = [X; stateX]; %#ok<AGROW>
    for groupIdx = 1:numel(groups)
        members = groupIds == groups(groupIdx);
        y(end + 1, 1) = max( ... %#ok<AGROW>
            graphBlock.nodeRiskTarget(members));
        tailMass(end + 1, 1) = nnz( ... %#ok<AGROW>
            graphBlock.nodeCvarMaskTarget(members));
        seed(end + 1, 1) = graphBlock.seed; %#ok<AGROW>
        currentTime(end + 1, 1) = ...
            graphBlock.currentTime; %#ok<AGROW>
        formation(end + 1, 1) = groupIdx; %#ok<AGROW>
        state(end + 1, 1) = stateCursor; %#ok<AGROW>
    end
end
data = struct('X', X, 'y', y, ...
    'tailMass', tailMass, 'seed', seed, ...
    'currentTime', currentTime, ...
    'formation', formation, 'state', state);
end

function features = aggregateFormationFeatures(X, variant)
switch variant
    case 'mean'
        features = mean(X, 1);
    case 'mean-max'
        features = [mean(X, 1), max(X, [], 1)];
    case 'mean-max-min-std'
        features = [mean(X, 1), max(X, [], 1), ...
            min(X, [], 1), std(X, 0, 1)];
    otherwise
        error('Unknown formation feature variant.');
end
end

function model = fitFormationRidge(X, y, lambda)
[featureMean, featureScale] = fitScaler(X);
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, featureMean), featureScale);
targetMean = mean(y);
targetScale = std(y);
if targetScale <= eps
    targetScale = 1;
end
target = (y - targetMean) / targetScale;
if size(Z, 2) > size(Z, 1)
    % Z and target are centered on the fit split, so the unregularized
    % intercept is zero.  The dual form avoids a p-by-p solve.
    dual = (Z * Z' + ...
        lambda * eye(size(Z, 1))) \ target;
    coefficients = [0; Z' * dual];
else
    design = [ones(size(Z, 1), 1), Z];
    regularizer = diag([0, ones(1, size(Z, 2))]);
    coefficients = (design' * design + ...
        lambda * regularizer) \ ...
            (design' * target);
end
if any(~isfinite(coefficients))
    error('Formation ridge produced non-finite coefficients.');
end
model = struct('featureMean', featureMean, ...
    'featureScale', featureScale, ...
    'targetMean', targetMean, ...
    'targetScale', targetScale, ...
    'coefficients', coefficients);
end

function prediction = scoreFormationRidge(model, X)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.featureMean), ...
        model.featureScale);
prediction = model.targetMean + ...
    model.targetScale * ...
        ([ones(size(Z, 1), 1), Z] * ...
            model.coefficients);
end

function rows = evaluateFormationRows(data, prediction)
states = unique(data.state, 'stable');
rows = repmat(emptyFormationRow(), 1, numel(states));
for stateIdx = 1:numel(states)
    mask = data.state == states(stateIdx);
    truth = data.y(mask);
    scores = prediction(mask);
    tailMass = data.tailMass(mask);
    [~, predictedOrder] = sort(scores, 'descend');
    [~, truthOrder] = sort(truth, 'descend');
    top1Formation = predictedOrder(1);
    totalTail = max(sum(tailMass), 1);
    row = emptyFormationRow();
    row.seed = data.seed(find(mask, 1));
    row.currentTime = data.currentTime(find(mask, 1));
    row.top1Exact = top1Formation == truthOrder(1);
    row.top1TailCoverage = ...
        tailMass(top1Formation) / totalTail;
    row.top2TailCoverage = ...
        sum(tailMass(predictedOrder(1:2))) / totalTail;
    row.riskSpearman = rankCorrelation(scores, truth);
    denominator = max(truth) - min(truth);
    row.normalizedWorstFormationRegret = ...
        (max(truth) - truth(top1Formation)) / ...
            max(denominator, eps);
    rows(stateIdx) = row;
end
end

function metrics = summarizeFormationRows(rows)
seeds = unique([rows.seed], 'stable');
seedTop1 = arrayfun(@(seed) mean( ...
    [rows([rows.seed] == seed).top1Exact]), seeds);
metrics = struct();
metrics.stateCount = numel(rows);
metrics.top1Accuracy = mean([rows.top1Exact]);
metrics.minimumSeedTop1Accuracy = min(seedTop1);
metrics.top1TailCoverage = mean( ...
    [rows.top1TailCoverage]);
metrics.top2TailCoverage = mean( ...
    [rows.top2TailCoverage]);
metrics.riskSpearman = mean( ...
    [rows.riskSpearman]);
metrics.medianWorstFormationRegret = median( ...
    [rows.normalizedWorstFormationRegret]);
metrics.p90WorstFormationRegret = empiricalQuantile( ...
    [rows.normalizedWorstFormationRegret], 0.90);
end

function selected = ...
        selectBestFormationCandidate(candidates)
accuracy = arrayfun(@(candidate) ...
    candidate.metrics.top1Accuracy, candidates);
coverage = arrayfun(@(candidate) ...
    candidate.metrics.top1TailCoverage, candidates);
regret = arrayfun(@(candidate) ...
    candidate.metrics.medianWorstFormationRegret, candidates);
[~, order] = sortrows( ...
    [-accuracy(:), -coverage(:), regret(:)], ...
    [1, 2, 3]);
selected = struct( ...
    'candidateIndex', order(1), ...
    'variant', candidates(order(1)).variant, ...
    'lambda', candidates(order(1)).lambda, ...
    'metrics', candidates(order(1)).metrics, ...
    'selectionUse', ...
        'training-only-architecture-diagnosis');
end

function [featureMean, featureScale] = fitScaler(X)
featureMean = mean(X, 1);
featureScale = std(X, 0, 1);
featureScale(~isfinite(featureScale) | ...
    featureScale <= eps) = 1;
end

function correlation = rankCorrelation(first, second)
firstRanks = tiedRanks(first);
secondRanks = tiedRanks(second);
firstCentered = firstRanks - mean(firstRanks);
secondCentered = secondRanks - mean(secondRanks);
denominator = sqrt(sum(firstCentered.^2) * ...
    sum(secondCentered.^2));
if denominator <= eps
    correlation = 0;
else
    correlation = sum(firstCentered .* ...
        secondCentered) / denominator;
end
end

function ranks = tiedRanks(values)
values = reshape(values, [], 1);
[sorted, order] = sort(values);
ranks = zeros(size(values));
cursor = 1;
while cursor <= numel(values)
    last = cursor;
    while last < numel(values) && ...
            sorted(last + 1) == sorted(cursor)
        last = last + 1;
    end
    ranks(order(cursor:last)) = ...
        0.5 * (cursor + last);
    cursor = last + 1;
end
end

function value = empiricalQuantile(values, probability)
values = sort(reshape(values, 1, []));
position = 1 + (numel(values) - 1) * probability;
lowerIdx = floor(position);
upperIdx = ceil(position);
if lowerIdx == upperIdx
    value = values(lowerIdx);
else
    fraction = position - lowerIdx;
    value = (1 - fraction) * values(lowerIdx) + ...
        fraction * values(upperIdx);
end
end

function writeReport(path, analysis)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open failure decomposition report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 CVaR graph policy failure decomposition\n\n');
fprintf(fid, '- Generated: %s\n', analysis.generatedAt);
fprintf(fid, '- Commit: `%s`\n', ...
    analysis.generationGitCommit);
fprintf(fid, '- Dataset-set SHA-256: `%s`\n', ...
    analysis.datasetSetSha256);
fprintf(fid, '- Training seeds: `%s`\n', ...
    mat2str(analysis.trainingSeeds));
fprintf(fid, '- Development seeds opened: `%d`\n', ...
    analysis.developmentSeedsOpened);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    analysis.evidenceBoundary);

fprintf(fid, '## Structured action error decomposition\n\n');
fprintf(fid, ['| Node head | Edge heads | Mean task adv. | ', ...
    'Median oracle gap | P90 gap | Nonnegative | Tail safe | ', ...
    'Fallback |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|--:|--:|--:|\n');
for metric = analysis.actionMetrics.caseMetrics
    parts = strsplit(metric.name, '-');
    fprintf(fid, '| %s | %s | %.4f | %.4f | %.4f | %.3f | %.3f | %d |\n', ...
        parts{1}, parts{3}, ...
        metric.meanSelectedTaskAdvantage, ...
        metric.medianOracleActionGap, ...
        metric.p90OracleActionGap, ...
        metric.nonnegativeTaskFraction, ...
        metric.selectedTailSafeFraction, ...
        metric.fallbackCount);
end

fprintf(fid, '\n## Formation-risk LOSO diagnostics\n\n');
fprintf(fid, ['| Features | Lambda | Top-1 | Min seed | ', ...
    'Top-1 tail | Top-2 tail | Risk rho | Med regret | P90 |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for candidate = analysis.formationCandidates
    metric = candidate.metrics;
    fprintf(fid, ...
        '| %s | %.3g | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f |\n', ...
        candidate.variant, candidate.lambda, ...
        metric.top1Accuracy, ...
        metric.minimumSeedTop1Accuracy, ...
        metric.top1TailCoverage, ...
        metric.top2TailCoverage, ...
        metric.riskSpearman, ...
        metric.medianWorstFormationRegret, ...
        metric.p90WorstFormationRegret);
end
best = analysis.formationBestByTop1Accuracy;
fprintf(fid, ...
    ['\nBest training-only diagnostic: `%s`, lambda `%.3g`, ', ...
     'top-1 accuracy `%.3f`, top-1 tail coverage `%.3f`.\n'], ...
    best.variant, best.lambda, ...
    best.metrics.top1Accuracy, ...
    best.metrics.top1TailCoverage);
end

function row = emptyActionRow()
row = struct('seed', 0, 'currentTime', 0, ...
    'cases', repmat(emptyActionCase(), 1, 0));
end

function value = emptyActionCase()
value = struct('name', '', ...
    'selectedTrueTaskAdvantage', NaN, ...
    'oracleActionGap', NaN, ...
    'selectedTailSafe', false, ...
    'fallbackUsed', false, ...
    'selectedCrossEdgeCount', 0);
end

function row = emptyFormationRow()
row = struct('seed', 0, 'currentTime', 0, ...
    'top1Exact', false, ...
    'top1TailCoverage', NaN, ...
    'top2TailCoverage', NaN, ...
    'riskSpearman', NaN, ...
    'normalizedWorstFormationRegret', NaN);
end

function candidate = emptyFormationCandidate()
candidate = struct('variant', '', 'lambda', NaN, ...
    'rows', repmat(emptyFormationRow(), 1, 0), ...
    'metrics', struct());
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
