function value = emptyCaseResult()
value = struct( ...
    'name', '', 'presetName', '', 'seed', 0, 'currentTime', 0, ...
    'formationIds', zeros(1, 0), ...
    'candidateCount', 0, ...
    'candidateCountByFormation', zeros(1, 0), ...
    'shortlistCount', 0, ...
    'shortlistCountByFormation', zeros(1, 0), ...
    'richSynopsisBytes', 0, ...
    'richSynopsisReferenceFractionPercent', 0, ...
    'lightSynopsisBytes', 0, ...
    'referencePageBytes', 0, ...
    'shortlist', repmat(struct(), 1, 0), ...
    'selection', struct(), ...
    'v188SelectedCandidateRetained', false(1, 0));
end

function value = yesNo(flag)
if flag
    value = 'yes';
else
    value = 'no';
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
