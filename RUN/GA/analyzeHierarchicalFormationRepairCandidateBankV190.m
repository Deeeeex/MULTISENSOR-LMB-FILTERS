function [reportPath, result] = ...
        analyzeHierarchicalFormationRepairCandidateBankV190(options)
% ANALYZEHIERARCHICALFORMATIONREPAIRCANDIDATEBANKV190 Truth-free bank audit.

if nargin < 1 || isempty(options)
    options = struct();
end
cases = getField(options, 'cases', defaultCases());
shortlistOptions = getField(options, 'shortlistOptions', struct( ...
    'perCriterion', 2, 'maximumPerFormation', 12));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v190', 'hierarchical_candidate_bank')));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

caseResults = repmat(emptyCaseResult(), 1, numel(cases));
for caseIdx = 1:numel(cases)
    caseResults(caseIdx) = analyzeCase( ...
        cases(caseIdx), shortlistOptions);
end
result = struct();
result.contractVersion = ...
    'hierarchical-formation-repair-candidate-bank-v190-preflight-v1';
result.generatedAt = datestr(now, 31);
result.caseResults = caseResults;
result.f2DecisionContrast = buildF2DecisionContrast(caseResults);
result.truthUsed = false;
result.futureInformationUsed = false;
result.trackingPerformanceScored = false;
result.trainingAuthorized = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'This preflight uses the already charged current light synopsis and ', ...
    'current physical graph to retain a diverse source-label action bank. ', ...
    'It does not read truth, score tracking benefit, train a model, or ', ...
    'establish that any shortlisted candidate is recursively useful.'];

matPath = fullfile(outputRoot, ...
    'HIERARCHICAL_FORMATION_REPAIR_CANDIDATE_BANK_V190.mat');
reportPath = fullfile(outputRoot, ...
    'HIERARCHICAL_FORMATION_REPAIR_CANDIDATE_BANK_V190.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V190 hierarchical candidate bank: %s\n', reportPath);
end

function caseResult = analyzeCase(caseSpec, shortlistOptions)
loaded = load(caseSpec.analysisPath, 'analysis');
analysis = loaded.analysis;
loadedScreen = load(analysis.screenPath, 'screen');
screen = loadedScreen.screen;
names = {screen.records.actionName};
baseIdx = find(cellfun(@(name) strncmp( ...
    name, caseSpec.baseActionPrefix, ...
    numel(caseSpec.baseActionPrefix)), names), 1);
if isempty(baseIdx)
    error('HierarchicalCandidateBankV190:MissingBaseArm', ...
        'The V99 base arm is absent.');
end
baseOutcome = screen.outcomes(baseIdx);
localPosterior = ...
    baseOutcome.localPosteriorSnapshotsByTime{analysis.pageIndex};
fusedPosterior = ...
    baseOutcome.fusedPosteriorSnapshotsByTime{analysis.pageIndex};
inputs = generateDynamicTopologyScenarioInputs( ...
    analysis.presetName, analysis.seed);
model = inputs.model;
currentTime = analysis.currentTime;
groupIds = reshape(screen.sensorGroupIds, 1, []);
physical = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
physical = physical | physical';
physical(1:numel(groupIds)+1:end) = false;
cache = buildFormationRepairLightSynopsisCacheV188( ...
    fusedPosterior, localPosterior, model, currentTime, struct());
[candidates, bank] = ...
    enumerateFormationCommonLabelRepairCandidatesV190( ...
        cache, physical, groupIds, struct());
[shortlist, selection] = ...
    selectDiverseFormationRepairShortlistV190( ...
        candidates, shortlistOptions);
protocol = getBudgetRecycledFormationRepairV188Protocol();
richBytes = numel(shortlist) * ...
    protocol.richSynopsisBytesPerShortlistedLabel;
referencePageBytes = analysis.referencePageBytes;

caseResult = emptyCaseResult();
caseResult.name = caseSpec.name;
caseResult.presetName = analysis.presetName;
caseResult.seed = analysis.seed;
caseResult.currentTime = currentTime;
caseResult.formationIds = bank.formationIds;
caseResult.candidateCount = bank.candidateCount;
caseResult.candidateCountByFormation = ...
    bank.candidateCountByFormation;
caseResult.shortlistCount = numel(shortlist);
caseResult.shortlistCountByFormation = ...
    selection.selectedCountByFormation;
caseResult.richSynopsisBytes = richBytes;
caseResult.richSynopsisReferenceFractionPercent = ...
    100 * richBytes / max(referencePageBytes, eps);
caseResult.lightSynopsisBytes = cache.totalAttemptedBytes;
caseResult.referencePageBytes = referencePageBytes;
caseResult.shortlist = shortlist;
caseResult.selection = selection;
caseResult.v188SelectedCandidateRetained = ...
    retainedV188Selections(shortlist, analysis.proposals, ...
        analysis.projection.selectedProposalIndices);
end

function retained = retainedV188Selections( ...
        shortlist, proposals, selectedIndices)
retained = true(1, numel(selectedIndices));
for selectedPosition = 1:numel(selectedIndices)
    proposal = proposals(selectedIndices(selectedPosition));
    match = arrayfun(@(candidate) ...
        candidate.formationId == proposal.formationId && ...
        candidate.sourceId == proposal.sourceId && ...
        isequal(candidate.label, proposal.label), shortlist);
    retained(selectedPosition) = any(match);
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('HierarchicalCandidateBankV190:WriteFailed', ...
        'Cannot write %s.', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V190 hierarchical candidate-bank preflight\n\n');
fprintf(fid, ['The preflight retains a union of seven causal rankings ', ...
    'before any learned model is fitted. Rich synopsis bytes are charged ', ...
    'for every retained candidate.\n\n']);
fprintf(fid, ['| Case | Full candidates | By formation | Shortlist | ', ...
    'By formation | Light bytes | Rich Top-K bytes | Rich / reference | ', ...
    'V188 action retained |\n']);
fprintf(fid, '|:--|--:|:--|--:|:--|--:|--:|--:|:--|\n');
for caseIdx = 1:numel(result.caseResults)
    value = result.caseResults(caseIdx);
    fprintf(fid, '| %s | %d | `%s` | %d | `%s` | %d | %d | %.3f%% | %s |\n', ...
        value.name, value.candidateCount, ...
        mat2str(value.candidateCountByFormation), ...
        value.shortlistCount, ...
        mat2str(value.shortlistCountByFormation), ...
        value.lightSynopsisBytes, value.richSynopsisBytes, ...
        value.richSynopsisReferenceFractionPercent, ...
        yesNo(all(value.v188SelectedCandidateRetained)));
end
fprintf(fid, '\n');
writeF2DecisionContrast(fid, result.f2DecisionContrast);
for caseIdx = 1:numel(result.caseResults)
    value = result.caseResults(caseIdx);
    fprintf(fid, '## %s shortlist\n\n', value.name);
    fprintf(fid, ['| F | Source | Label | Opportunity | Min risk | ', ...
        'Source quality | Peer consensus | Disagreement | ', ...
        'Precision gain | Max distance / cutoff |\n']);
    fprintf(fid, '|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|\n');
    for candidateIdx = 1:numel(value.shortlist)
        candidate = value.shortlist(candidateIdx);
        fprintf(fid, ...
            '| %d | %d | `[%d,%d]` | %.5f | %.5f | %.5f | %.5f | %.5f | %.5f | %.5f |\n', ...
            candidate.formationId, candidate.sourceId, ...
            candidate.label(1), candidate.label(2), ...
            candidate.opportunityMedian, ...
            candidate.minimumRiskReduction, ...
            candidate.sourceQuality, ...
            candidate.peerConsensusMedian, ...
            candidate.receiverDisagreementMedian, ...
            candidate.precisionGainNormalized, ...
            candidate.positionDistanceMaximumNormalized);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function contrast = buildF2DecisionContrast(caseResults)
contrast = struct( ...
    'available', false, ...
    'currentCandidate', struct(), ...
    'alternativeCandidate', struct(), ...
    'repeatedTeacherAvailable', false, ...
    'repeatedIncrementalEospaGainPercent', nan, ...
    'repeatedIncrementalRmseGainPercent', nan, ...
    'repeatedIncrementalConsensusGainPercent', nan, ...
    'repeatedAttemptedByteSavingPercent', nan);
caseIdx = find(strcmp({caseResults.presetName}, ...
    'x36-formation-fov'), 1);
if isempty(caseIdx)
    return;
end
candidates = caseResults(caseIdx).shortlist;
currentIdx = findCandidate(candidates, 2, 20, [19; 16]);
alternativeIdx = findCandidate(candidates, 2, 19, [13; 12]);
if isempty(currentIdx) || isempty(alternativeIdx)
    return;
end
contrast.available = true;
contrast.currentCandidate = candidates(currentIdx);
contrast.alternativeCandidate = candidates(alternativeIdx);
repeatedPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v188', 'recursive_pilot', ...
    'x36_seed211_t72_h3_forced_f2_pages_0-1-2', ...
    'BUDGET_RECYCLED_REPAIR_V188_X36_RECURSIVE_PILOT.mat');
if exist(repeatedPath, 'file') ~= 2
    return;
end
loaded = load(repeatedPath, 'result');
teacher = loaded.result;
contrast.repeatedTeacherAvailable = true;
contrast.repeatedIncrementalEospaGainPercent = ...
    teacher.incrementalEospaGainPercent;
contrast.repeatedIncrementalRmseGainPercent = ...
    teacher.incrementalRmseGainPercent;
contrast.repeatedIncrementalConsensusGainPercent = ...
    teacher.incrementalConsensusGainPercent;
contrast.repeatedAttemptedByteSavingPercent = ...
    teacher.repairAttemptedByteSavingPercent;
end

function idx = findCandidate(candidates, formationId, sourceId, label)
idx = find(arrayfun(@(candidate) ...
    candidate.formationId == formationId && ...
    candidate.sourceId == sourceId && ...
    isequal(candidate.label, label), candidates), 1);
end

function writeF2DecisionContrast(fid, contrast)
if ~contrast.available
    return;
end
current = contrast.currentCandidate;
alternative = contrast.alternativeCandidate;
fprintf(fid, '## Decision-driving F2 contrast\n\n');
fprintf(fid, ['| Candidate | Opportunity | Minimum risk reduction | ', ...
    'Precision gain | Interpretation |\n']);
fprintf(fid, '|:--|--:|--:|--:|:--|\n');
fprintf(fid, ['| Current V188: source %d, label `[%d,%d]` | ', ...
    '%.5f | %.5f | %.5f | High proxy opportunity but almost no ', ...
    'common-receiver margin |\n'], ...
    current.sourceId, current.label(1), current.label(2), ...
    current.opportunityMedian, current.minimumRiskReduction, ...
    current.precisionGainNormalized);
fprintf(fid, ['| Alternative: source %d, label `[%d,%d]` | ', ...
    '%.5f | %.5f | %.5f | Distinct label with substantially larger ', ...
    'causal risk and precision margins |\n\n'], ...
    alternative.sourceId, alternative.label(1), alternative.label(2), ...
    alternative.opportunityMedian, ...
    alternative.minimumRiskReduction, ...
    alternative.precisionGainNormalized);
if contrast.repeatedTeacherAvailable
    fprintf(fid, ['Repeating the current action across all H=3 pages ', ...
        'changes V99-relative E-OSPA, RMSE and consensus by ', ...
        '`%+.3f%%`, `%+.3f%%` and `%+.3f%%`; static-relative byte ', ...
        'saving is `%.3f%%`.  The alternative row therefore earns a ', ...
        'single charged teacher evaluation.  The table does not ', ...
        'establish that the alternative improves tracking.\n\n'], ...
        contrast.repeatedIncrementalEospaGainPercent, ...
        contrast.repeatedIncrementalRmseGainPercent, ...
        contrast.repeatedIncrementalConsensusGainPercent, ...
        contrast.repeatedAttemptedByteSavingPercent);
else
    fprintf(fid, ['The alternative row earns a single charged teacher ', ...
        'evaluation.  The table does not establish that the alternative ', ...
        'improves tracking.\n\n']);
end
end

