function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantCertifiedOverlapProbeM24( ...
        payloadMarginToken, options)
% RUNLABELSETADAPTIVEDOMINANTCERTIFIEDOVERLAPPROBEM24 V4 seed-31 probe.
%
% The probe uses only the already-opened seed 31.  Tokens are evaluated in
% their registered ascending order outside this function.  Held-out M24 and
% X36 are not authorized here.

if nargin < 1 || isempty(payloadMarginToken)
    payloadMarginToken = 20;
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantCertifiedOverlapRedesignAuthorized || ...
        ~ismember(payloadMarginToken, protocol. ...
            adaptiveDominantCertifiedOverlapMarginTokens) || ...
        protocol.adaptiveDominantCertifiedOverlapConfirmationAuthorized || ...
        protocol.adaptiveDominantCertifiedOverlapHeldoutM24Authorized || ...
        protocol.adaptiveDominantCertifiedOverlapX36Authorized
    error('Certified-overlap M24 probe token is not authorized.');
end

seed = protocol.adaptiveDominantCertifiedOverlapProbeSeed;
candidateArm = sprintf([ ...
    'adaptive-dominant-composite-balanced-', ...
    'certified-overlap-payload-margin%03d-e05-a70'], ...
    payloadMarginToken);
rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', payloadMarginToken)));
screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(1), ...
    'armNames', {{candidateArm}}, ...
    'writeReport', true, ...
    'outputDirectory', fullfile( ...
        rootDirectory, 'development', sprintf('seed%d', seed)), ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'cache')), ...
    'generateMissingBehaviorCache', false, ...
    'evidenceSplit', 'development');
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    'm24-hard', seed, screenOptions);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
