function [reportPath, result] = analyzeExistenceLossLocalizationV281(options)
% One-round reference replay at saved M24 anchors; not a new tracking arm.
% No truth labels, selector training, threshold scan or recursive filter run.
if nargin < 1, options = struct(); end
if isfield(options, 'existingResultPath')
    loaded = load(options.existingResultPath, 'result'); result = loaded.result;
    reportPath = fullfile(fileparts(options.existingResultPath), 'EXISTENCE_LOSS_LOCALIZATION_V281.md');
    writeReport(reportPath, result);
    return; % Refresh prose from the saved trace without replaying fusion.
end
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
base = fileparts(root);
oraclePath = getField(options, 'oraclePath', fullfile(base, ...
    'v250-gateway-embedding', 'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v250', 'causal_gateway_embedding', ...
    'm24_seed1301_h3_oracle', 'CAUSAL_GATEWAY_EMBEDDING_V250_H3_ORACLE.mat'));
out = getField(options, 'outputRoot', fullfile(root, 'RUN', 'GA', ...
    'dynamic_topology', 'evidence', 'tracking_aligned_v281', ...
    'm24_existence_loss_seed1301'));
a = load(oraclePath, 'result'); oracle = a.result;
a = load(oracle.cachePath, 'behaviorBundle'); bundle = a.behaviorBundle;
assert(isequal(reshape(bundle.snapshotTimes, 1, []), [70, 84, 151]));
assert(strcmp(bundle.posteriorSnapshotConvention, ...
    'pre-topology-pre-fusion-local-posterior'));
inputs = generateDynamicTopologyScenarioInputs(oracle.presetName, oracle.seed);
model = removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
cfg = buildCausalMinimumFormationBackboneV242Config(inputs.config);
% These are the baseline collection defaults, inspected in the runtime.
assert(strcmp(cfg.eventPolicy, 'alwaysHeavy') && ~cfg.linkGateEnabled);
assert(strcmp(cfg.fusionWeightMode, 'metropolis'));
assert(~getField(cfg, 'useStaleNeighborCache', false));
assert(strcmp(getField(cfg, 'missingNeighborWeightMode', 'renormalize'), 'renormalize'));
assert(~getField(cfg, 'mixedPayloadEnabled', false));
assert(getField(cfg, 'heavyFusionWeightFactor', 1) == 1);
assert(getField(cfg, 'nonStaticFusionWeightFactor', 1) == 1);
assert(isinf(getField(cfg, 'maxSelfFusionWeight', inf)));
assert(isinf(getField(cfg, 'maxNonStaticFusionWeight', inf)));
assert(isempty(getField(inputs.commConfig, 'outageSchedule', [])));
cfg.captureLabelKlaDiagnosticsEnabled = true;
identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
n = inputs.config.numberOfSensors;
groups = reshape(inputs.config.sensorGroupIds, 1, []);
[~, commit] = system('git rev-parse HEAD');
result = struct('analysis', 'existence-loss-localization-v281-v1', ...
    'sourceCommit', strtrim(commit), 'oraclePath', oraclePath, ...
    'cachePath', oracle.cachePath, 'cacheGenerationGitCommit', bundle.generationGitCommit, ...
    'snapshotConvention', bundle.posteriorSnapshotConvention, ...
    'presetName', oracle.presetName, 'seed', oracle.seed, ...
    'anchorTimes', bundle.snapshotTimes, 'fullFilterRerun', false, ...
    'oneRoundReferenceReplay', true, 'truthMatchingUsed', false, ...
    'newPolicyEvaluated', false, 'independentValidation', false, ...
    'pruningThreshold', model.existenceThreshold, 'receivers', {{}}, ...
    'labelRecords', {{}}, 'diagnostics', {{}});
for w = 1:numel(oracle.windows)
    window = oracle.windows{w}; t = window.anchorTime;
    [local, history] = extractBehaviorContinuationSnapshot(bundle, t, n);
    context = makeContext(inputs, model, cfg, identity, local, history, t);
    ref = window.referenceCandidateIndex;
    [adj, route] = selectCausalGatewayEmbeddingV250Policy( ...
        context, window.candidateAssignments{ref});
    assert(nnz(adj) == n + 2 * (numel(unique(groups)) - 1));
    weights = route.fusionWeightMatrix;
    delivered = logical(adj);
    if ~inputs.commConfig.forceDelivery
        delivered = delivered & (inputs.commConfig.linkUniforms(:, :, t)' >= ...
            inputs.commConfig.pDropByEdge(:, :, t)');
    end
    payload = cell(1, n);
    for j = 1:n, payload{j} = activeObjects(local{j}, cfg.payloadExistenceThreshold); end
    networkLabels = labelsOfInputs(payload);
    for i = 1:n
        senders = find(adj(i, :));
        scheduledInputs = [{local{i}}, payload(senders)];
        fusionInputs = {local{i}}; sources = i; raw = weights(i, i);
        emptyDelivered = 0;
        for j = senders
            if ~delivered(i, j), continue; end
            if isempty(payload{j})
                emptyDelivered = emptyDelivered + 1;
                continue; % Runtime omits an empty packet, not a negative label input.
            end
            fusionInputs{end + 1} = payload{j}; %#ok<AGROW>
            sources(end + 1) = j; raw(end + 1) = weights(i, j); %#ok<AGROW>
        end
        rowWeights = raw / sum(raw);
        details = struct('sourceIndices', sources, 'isSelf', [true, false(1, numel(sources)-1)], ...
            'isStale', false(size(sources)), 'age', zeros(size(sources)), ...
            'eventType', 2 * ones(size(sources)), 'currentTime', t, ...
            'weights', rowWeights);
        [fused, diagnostic] = fuseLmbPosteriorsByLabel( ...
            fusionInputs, rowWeights, model, rowWeights, details, cfg);
        records = diagnostic.labelKlaRecords;
        retained = fused([fused.r] > model.existenceThreshold);
        [outputCount, selected] = mapReadout(retained);
        [localCount, ~] = mapReadout(activeObjects(local{i}, model.existenceThreshold));
        outputLabels = labelsOfInputs({retained(selected)});
        actualLabels = labelsOfInputs(fusionInputs);
        scheduledLabels = labelsOfInputs(scheduledInputs);
        a = struct('time', t, 'receiver', i, 'formation', groups(i), ...
            'networkPayloadLabelCount', size(networkLabels, 1), ...
            'localMapCount', localCount, 'scheduledIncoming', numel(senders), ...
            'lostIncoming', nnz(~delivered(i, senders)), ...
            'emptyDeliveredIncoming', emptyDelivered, ...
            'nonemptyReceivedIncoming', numel(sources)-1, ...
            'networkLabelsAbsentFromInputs', size(setdiff(networkLabels, actualLabels, 'rows'), 1), ...
            'scheduledLabelCount', size(scheduledLabels, 1), ...
            'transportUnavailableLabels', size(setdiff(scheduledLabels, actualLabels, 'rows'), 1), ...
            'inputUnionLabelCount', size(actualLabels, 1), ...
            'fusedLabelCount', numel(fused), 'retainedLabelCount', numel(retained), ...
            'outputMapCount', outputCount, 'weakBeforeEtaCount', 0, ...
            'etaCrossesHalfCount', 0, 'preEtaExistenceMass', 0, ...
            'fusedExistenceMass', sum([fused.r]), 'etaExistenceMassLoss', 0, ...
            'prunedExistenceMass', sum([fused.r]) - sum([retained.r]), ...
            'retainedNotOutputMass', sum([retained.r]) - sum([retained(selected).r]), ...
            'mixtureUsedLabelCount', 0, 'normalizerFallbackLabelCount', 0, ...
            'absentObservableSourceCount', diagnostic.observableCensoredSourceCount, ...
            'maxExistenceIdentityError', 0, 'medianNegativeLogEta', 0, ...
            'maxNegativeLogEta', 0);
        labelRows = repmat(struct(), 1, 0);
        for k = 1:numel(records)
            r = records(k);
            pre = stableLogistic(r.weightedInputLogOdds);
            after = r.fusedExistence;
            a.preEtaExistenceMass = a.preEtaExistenceMass + pre;
            a.weakBeforeEtaCount = a.weakBeforeEtaCount + (pre < 0.5);
            a.etaCrossesHalfCount = a.etaCrossesHalfCount + (pre >= 0.5 && after < 0.5);
            a.mixtureUsedLabelCount = a.mixtureUsedLabelCount + r.mixtureAwareSpatialUsed;
            a.normalizerFallbackLabelCount = a.normalizerFallbackLabelCount + ...
                strcmp(r.mixtureAwareFallbackReason, 'powered-gm-normalizer-exceeds-one');
            a.maxExistenceIdentityError = max(a.maxExistenceIdentityError, ...
                abs(after - stableLogistic(r.weightedInputLogOdds + r.spatialLogNormalizer)));
            row = struct('time', t, 'receiver', i, 'formation', groups(i), ...
                'birthTime', r.label(1), 'birthLocation', r.label(2), ...
                'weightedInputLogOdds', r.weightedInputLogOdds, ...
                'spatialLogNormalizer', r.spatialLogNormalizer, ...
                'preEtaExistence', pre, 'fusedExistence', after, ...
                'retained', after > model.existenceThreshold, ...
                'selectedForOutput', ismember(r.label', outputLabels, 'rows'), ...
                'mixtureUsed', r.mixtureAwareSpatialUsed, ...
                'fallbackReason', r.mixtureAwareFallbackReason);
            labelRows(end + 1) = row; %#ok<AGROW>
        end
        a.etaExistenceMassLoss = a.preEtaExistenceMass - a.fusedExistenceMass;
        if ~isempty(records)
            penalties = max(0, -[records.spatialLogNormalizer]);
            a.medianNegativeLogEta = median(penalties);
            a.maxNegativeLogEta = max(penalties);
        end
        result.receivers{end + 1} = a;
        result.labelRecords{end + 1} = labelRows;
        result.diagnostics{end + 1} = struct('sources', sources, 'weights', rowWeights, ...
            'fusion', diagnostic, 'scheduledLabels', scheduledLabels, ...
            'inputLabels', actualLabels, 'outputLabels', outputLabels);
    end
    rows = [result.receivers{:}]; rows = rows([rows.time] == t);
    fprintf('V281 t=%d: local MAP %.3f; input labels %.3f; pre-eta mass %.3f; fused mass %.3f; output MAP %.3f\n', ...
        t, mean([rows.localMapCount]), mean([rows.inputUnionLabelCount]), ...
        mean([rows.preEtaExistenceMass]), mean([rows.fusedExistenceMass]), mean([rows.outputMapCount]));
end
if exist(out, 'dir') ~= 7, mkdir(out); end
save('-mat7-binary', fullfile(out, 'EXISTENCE_LOSS_LOCALIZATION_V281.mat'), 'result');
writeCsv(fullfile(out, 'receiver_stages.csv'), [result.receivers{:}]);
writeCsv(fullfile(out, 'label_stages.csv'), [result.labelRecords{:}]);
reportPath = fullfile(out, 'EXISTENCE_LOSS_LOCALIZATION_V281.md');
writeReport(reportPath, result);
end

function context = makeContext(inputs, model, cfg, identity, local, history, t)
context = struct('localPosteriorBySensor', {local}, 'model', model, ...
    'baseAdjacency', logical(inputs.graphData.staticAdjacency), ...
    'physicalAdjacency', logical(inputs.graphData.physicalAdjacency(:, :, t)), ...
    'positions', inputs.graphData.positions(:, :, t), 'currentTime', t, ...
    'commConfig', inputs.commConfig, 'triggerConfig', cfg, ...
    'directedMessageBudget', cfg.topologyDirectedMessageBudget, ...
    'sensorPhysicalUids', identity.sensorPhysicalUids, ...
    'formationPhysicalUidsBySensor', identity.formationPhysicalUidsBySensor, ...
    'previousAdjacencyHistory', convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory), ...
    'previousAdjacencyHistoryTimes', history.times);
context.commConfig.pDropByEdge = inputs.commConfig.pDropByEdge(:, :, t);
context.previousAdjacencyHistoryCount = size(context.previousAdjacencyHistory, 3);
end

function selected = activeObjects(objects, threshold)
selected = objects;
if ~isempty(objects)
    selected = objects([objects.r] > threshold & [objects.numberOfGmComponents] > 0);
end
end

function labels = labelsOfInputs(inputs)
labels = zeros(0, 2);
for k = 1:numel(inputs)
    o = inputs{k};
    if ~isempty(o)
        labels = [labels; [reshape([o.birthTime], [], 1), reshape([o.birthLocation], [], 1)]]; %#ok<AGROW>
    end
end
labels = unique(labels, 'rows');
end

function [count, selected] = mapReadout(objects)
count = 0; selected = [];
if ~isempty(objects), [count, selected] = lmbMapCardinalityEstimate([objects.r]); end
end

function x = stableLogistic(z)
if z >= 0, x = 1 / (1 + exp(-z)); else, a = exp(z); x = a / (1 + a); end
end

function value = getField(s, field, fallback)
value = fallback;
if isfield(s, field), value = s.(field); end
end

function writeCsv(path, rows)
fid = fopen(path, 'w'); assert(fid >= 0); cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
if isempty(rows), return; end
names = fieldnames(rows); fprintf(fid, '%s\n', strjoin(names', ','));
for i = 1:numel(rows)
    fields = cell(size(names));
    for k = 1:numel(names)
        v = rows(i).(names{k});
        if ischar(v), fields{k} = v; else, fields{k} = sprintf('%.12g', v); end
    end
    fprintf(fid, '%s\n', strjoin(fields', ','));
end
end

function writeReport(path, result)
fid = fopen(path, 'w'); assert(fid >= 0); cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
rows = [result.receivers{:}];
fprintf(fid, '# V281: one-round existence-loss localization\n\n');
fprintf(fid, ['M24, opened seed 1301, saved pre-topology/pre-fusion local posteriors at ', ...
    't=70,84,151. Only the saved V242 reference gateway assignment is replayed. ', ...
    'No recursive filter, new policy, truth-label matching or parameter scan.\n\n']);
fprintf(fid, ['The scheduled graph and directed delivery uniforms are regenerated; ', ...
    'these are current-code one-round replays of cached local states, not ', ...
    'new full-episode measurements or an X36 causal explanation.\n\n']);
fprintf(fid, '## Stage means over 24 receivers per anchor\n\n');
fprintf(fid, '| Time | Local MAP count | Scheduled label union | Labels lost with packets | Actual input label union | Before-overlap existence mass | Fused existence mass | Retained labels | Output MAP count |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for t = result.anchorTimes
    r = rows([rows.time] == t);
    fprintf(fid, '| %d | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f |\n', ...
        t, mean([r.localMapCount]), mean([r.scheduledLabelCount]), ...
        mean([r.transportUnavailableLabels]), mean([r.inputUnionLabelCount]), ...
        mean([r.preEtaExistenceMass]), mean([r.fusedExistenceMass]), ...
        mean([r.retainedLabelCount]), mean([r.outputMapCount]));
end
fprintf(fid, '\n## Per-formation mechanisms (six receivers per row)\n\n');
fprintf(fid, '| Time | Formation | No-input network labels | Weak before overlap | Cross below 0.5 after overlap | Existence mass lost to overlap | Mass pruned | Retained but not output mass | Powered-GM used / fused labels | Normalizer fallback labels | Output MAP min / median / max |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--|--:|:--|\n');
for t = result.anchorTimes
    for g = unique([rows.formation])
        r = rows([rows.time] == t & [rows.formation] == g);
        fprintf(fid, '| %d | %d | %.3f | %.3f | %.3f | %.3f | %.5f | %.3f | %d / %d | %d | %d / %.1f / %d |\n', ...
            t, g, mean([r.networkLabelsAbsentFromInputs]), mean([r.weakBeforeEtaCount]), ...
            mean([r.etaCrossesHalfCount]), mean([r.etaExistenceMassLoss]), ...
            mean([r.prunedExistenceMass]), mean([r.retainedNotOutputMass]), ...
            sum([r.mixtureUsedLabelCount]), sum([r.fusedLabelCount]), ...
            sum([r.normalizerFallbackLabelCount]), ...
            min([r.outputMapCount]), median([r.outputMapCount]), max([r.outputMapCount]));
    end
end
weak = 0; strongInputButWeak = 0; censoredButWeak = 0;
for i = 1:numel(result.diagnostics)
    records = result.diagnostics{i}.fusion.labelKlaRecords;
    for k = 1:numel(records)
        r = records(k);
        if r.weightedInputLogOdds >= 0, continue; end
        weak = weak + 1;
        strongInputButWeak = strongInputButWeak + ...
            any(r.inputExistence(r.spatialParticipating) >= 0.9);
        censoredButWeak = censoredButWeak + ...
            any(r.existenceParticipating & ~r.spatialParticipating);
    end
end
fprintf(fid, '\n## What this narrows down\n\n');
fprintf(fid, ['Of %d fused label records, %d already have negative weighted ', ...
    'input log odds before the spatial term. Among those, %d have at least ', ...
    'one actual input with existence >=0.9; %d include a censored-absence ', ...
    'participant. These are descriptive thresholds, not an output rule.\n\n'], ...
    sum([rows.fusedLabelCount]), weak, strongInputButWeak, censoredButWeak);
fprintf(fid, ['The single-round spatial term removes mean existence mass ', ...
    '%.3f/%.3f/%.3f at the three anchors; pruning removes %.5f per ', ...
    'receiver snapshot overall. The pre-fusion local MAP readout is already ', ...
    'about six. This does not support making the final spatial term or ', ...
    'output threshold the first intervention. Trace earlier local updates ', ...
    'and propagation, while retaining the smaller input-weighting effect ', ...
    'as a distinct mechanism. Earlier compounded spatial losses remain possible.\n\n'], ...
    mean([rows([rows.time] == 70).etaExistenceMassLoss]), ...
    mean([rows([rows.time] == 84).etaExistenceMassLoss]), ...
    mean([rows([rows.time] == 151).etaExistenceMassLoss]), ...
    mean([rows.prunedExistenceMass]));
fprintf(fid, '\n## Interpretation boundaries\n\n');
fprintf(fid, ['- A label is a Bernoulli identifier, not a truth-matched target; ', ...
    'network label unions can contain duplicates of physical targets and false tracks.\n', ...
    '- Transport loss counts labels present in at least one scheduled payload ', ...
    'but absent from self and all nonempty delivered payloads. An absent individual ', ...
    'label inside a nonempty packet is handled by the unchanged FoV-censored fusion rule.\n', ...
    '- Before-overlap mass sums sigmoid(weighted input log odds), including ', ...
    'FoV-censored absence overrides. It is an algebraic diagnostic, not an ', ...
    'alternative fusion method or expected true-target recall.\n', ...
    '- The 0.5 crossing only locates changes in log-odds sign. Actual output ', ...
    'uses the unchanged existence pruning threshold and lmbMapCardinalityEstimate, ', ...
    'not a per-label 0.5 extractor. Unselected retained labels stay in memory.\n', ...
    '- Powered-GM normalizer fallback is counted separately. The current ', ...
    'fusion rejects powered-GM overlap greater than one and uses its moment-matched ', ...
    'fallback; this readout does not measure approximation error against exact KLA.\n', ...
    '- The cache is already after local updating. Earlier recursive transport, ', ...
    'measurement/association and local-update losses cannot be attributed by these anchors.\n\n']);
fprintf(fid, ['Collected %d receiver snapshots; %d lost incoming packets and %d ', ...
    'delivered empty inputs. Maximum probability-form existence identity residual: %.3g. ', ...
    'This is producing-agent self-check only.\n\n'], ...
    numel(rows), sum([rows.lostIncoming]), sum([rows.emptyDeliveredIncoming]), ...
    max([rows.maxExistenceIdentityError]));
fprintf(fid, '## Sources\n\n- Runtime source commit: `%s`\n- Cache source commit: `%s`\n- Oracle: `%s`\n- Cache: `%s`\n', ...
    result.sourceCommit, result.cacheGenerationGitCommit, result.oraclePath, result.cachePath);
fprintf(fid, ['\nDetailed distributions are retained in `receiver_stages.csv`, ', ...
    '`label_stages.csv`, and the MAT record (including all active weights and ', ...
    'per-source input existences).\n']);
end
