function [reportPath, result] = ...
        collectHierarchicalDelayedValueTrajectoryV213( ...
            presetName, seed, options)
% COLLECTHIERARCHICALDELAYEDVALUETRAJECTORYV213 Select causal windows.
%
% Pass one logs the V213 formation-need trajectory without retaining
% posterior objects.  Two separated local maxima are selected using only
% those causal scores.  Pass two resets the same RNG and captures only the
% selected predecision posteriors, then writes standard opened-state caches.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getHierarchicalDelayedValueControllerV213Protocol();
splitName = char(getField(options, 'splitName', 'training'));
[allowedPresets, allowedSeeds] = splitMembership(protocol, splitName);
if ~ischar(presetName) || ~ismember(presetName, allowedPresets) || ...
        ~isscalar(seed) || ~ismember(seed, allowedSeeds)
    error('HierarchicalDelayedValueV213:CollectionSplit', ...
        'The requested trajectory is outside the frozen V213 split.');
end

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('HierarchicalDelayedValueV213:DirtySource', ...
        'Official V213 trajectory collection requires clean source.');
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
scenario = inputs.config;
scanTimes = scenario.focusWindow(1): ...
    (scenario.focusWindow(end) - protocol.horizonSteps + 1);
if numel(scanTimes) < ...
        protocol.split.minimumDecisionWindowSeparation + 2
    error('HierarchicalDelayedValueV213:ShortFocusWindow', ...
        'The registered focus window cannot support two H=3 decisions.');
end
maximumTime = scanTimes(end);
inputs = cropInputs(inputs, maximumTime);
inputs.model = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'trajectory_collection', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
cacheRoot = char(getField(options, 'cacheRoot', ...
    fullfile(outputRoot, 'cache')));
overwrite = logical(getField(options, 'overwrite', false));
matPath = fullfile(outputRoot, ...
    'HIERARCHICAL_DELAYED_VALUE_TRAJECTORY_V213.mat');
reportPath = fullfile(outputRoot, ...
    'HIERARCHICAL_DELAYED_VALUE_TRAJECTORY_V213.md');
if ~overwrite && exist(matPath, 'file') == 2 && ...
        exist(reportPath, 'file') == 2
    loaded = load(matPath, 'result');
    result = loaded.result;
    validateExisting(result, protocol, presetName, seed, ...
        splitName, gitState.commit);
    fprintf('Reused V213 trajectory collection: %s\n', reportPath);
    return;
end

scanConfig = buildCollectionConfig( ...
    scenario, maximumTime, zeros(1, 0));
scanContext = ...
    buildHierarchicalDelayedValueCollectionV213ExecutionContext( ...
        presetName, seed, [splitName, '-trajectory-scan'], ...
        1, maximumTime, 'v213-causal-need-scan', ...
        true, true, struct());
rng(seed + 100000);
timerId = tic;
[~, scanDiagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, scanConfig, scanContext);
scanSeconds = toc(timerId);
auditNeedTrajectory(scanDiagnostics, scanTimes);

scores = scanDiagnostics. ...
    topologyPolicyHierarchicalMaximumFormationNeed(scanTimes);
selectedTimes = selectSeparatedLocalMaxima( ...
    scanTimes, scores, ...
    protocol.split.registeredDecisionWindowsPerTrajectory, ...
    protocol.split.minimumDecisionWindowSeparation);

captureConfig = buildCollectionConfig( ...
    scenario, maximumTime, selectedTimes);
captureContext = ...
    buildHierarchicalDelayedValueCollectionV213ExecutionContext( ...
        presetName, seed, [splitName, '-trajectory-capture'], ...
        1, maximumTime, 'v213-selected-state-capture', ...
        true, true, struct());
rng(seed + 100000);
timerId = tic;
[~, captureDiagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, captureConfig, ...
    captureContext);
captureSeconds = toc(timerId);
auditNeedTrajectory(captureDiagnostics, scanTimes);
if ~isequaln( ...
        scanDiagnostics. ...
            topologyPolicyHierarchicalMaximumFormationNeed(scanTimes), ...
        captureDiagnostics. ...
            topologyPolicyHierarchicalMaximumFormationNeed(scanTimes)) || ...
        ~isequal( ...
            scanDiagnostics.topologyActiveEdge(:, :, scanTimes), ...
            captureDiagnostics.topologyActiveEdge(:, :, scanTimes))
    error('HierarchicalDelayedValueV213:CaptureReplayDrift', ...
        'The selected-state replay changed the causal V99 trajectory.');
end

if exist(cacheRoot, 'dir') ~= 7
    mkdir(cacheRoot);
end
cachePaths = writeSelectedCaches( ...
    cacheRoot, presetName, seed, selectedTimes, inputs.config, ...
    captureConfig, captureDiagnostics, protocol, gitState, ...
    scanSeconds + captureSeconds);

selectedIndices = arrayfun( ...
    @(time) find(scanTimes == time, 1), selectedTimes);
formationIds = scanDiagnostics. ...
    topologyPolicyHierarchicalFormationIds(selectedTimes);
formationNeed = scanDiagnostics. ...
    topologyPolicyHierarchicalFormationNeedByFormation(selectedTimes);
baseSelectedFormationIds = scanDiagnostics. ...
    topologyPolicyRetentionDebtSelectedFormationIds(selectedTimes);
result = struct();
result.contractVersion = ...
    'hierarchical-delayed-value-trajectory-v213-v1';
result.protocolId = protocol.id;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = presetName;
result.seed = seed;
result.splitName = splitName;
result.scanTimes = scanTimes;
result.maximumFormationNeedByTime = scores;
result.localMaximumMask = localMaximumMask(scores);
result.selectedTimes = selectedTimes;
result.selectedScores = scores(selectedIndices);
result.selectedFormationIds = formationIds;
result.selectedFormationNeed = formationNeed;
result.baseSelectedFormationIds = baseSelectedFormationIds;
result.minimumDecisionWindowSeparation = ...
    protocol.split.minimumDecisionWindowSeparation;
result.cacheRoot = cacheRoot;
result.cachePaths = cachePaths;
result.scanSeconds = scanSeconds;
result.captureSeconds = captureSeconds;
result.featuresUseTruth = false;
result.featuresUseFutureInformation = false;
result.windowSelectionUsesTruth = false;
result.windowSelectionUsesFutureInformation = false;
result.captureReplayExact = true;
result.recursiveTargetsCollected = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'The V213 trajectory windows are selected from causal formation ', ...
    'need local maxima on a complete registered split trajectory. ', ...
    'Truth and future measurements do not enter the policy, score or ', ...
    'window selection. These caches authorize later H=3 target ', ...
    'collection only; they are not performance evidence.'];
result.matPath = matPath;
result.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V213 trajectory collection: %s\n', reportPath);
end

