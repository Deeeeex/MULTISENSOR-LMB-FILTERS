        scenario, maximumTime, captureTimes)
base = getOnlinePositiveNetAddressablePayloadV99Protocol();
layered = getTrackingAlignedLayeredLabelHeadroomV62Protocol();
config = buildMixtureAwareKlaReferenceConfig();
config.missingLabelFusionMode = base.receiverMode;
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenario.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = 2 * scenario.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicyName = base.outcomePolicyName;
config.topologyPolicyFcn = @(context) ...
    selectHierarchicalDelayedValueCollectionV213BasePolicy(context);
config.topologyPosteriorCaptureTimes = reshape(captureTimes, 1, []);
config.receiverSafeLabelFusionEnabled = true;
config.receiverSafeLabelFusionMode = ...
    'formation-supported-label-plan';
config.receiverSafeExternalActiveTimes = 1:maximumTime;
config.receiverSafeFormationConditionedTimes = 1:maximumTime;
config.receiverSafeFormationConditionedSchedule = ...
    repmat({[]}, 1, maximumTime);
config.receiverSafeFormationConditionedOnlinePolicyEnabled = true;
config.receiverSafeFormationConditionedPayloadMode = 'control-only';
config.receiverSafeExternalPositiveSupportThreshold = ...
    base.positiveSupportThreshold;
config.receiverSafeFormationConditionedHighExistenceThreshold = ...
    layered.highExistenceThreshold;
end

function selectedTimes = selectSeparatedLocalMaxima( ...
        times, scores, count, minimumSeparation)
mask = localMaximumMask(scores);
candidateTimes = times(mask);
candidateScores = scores(mask);
orderTable = [-candidateScores(:), candidateTimes(:)];
[~, order] = sortrows(orderTable, [1, 2]);
selectedTimes = zeros(1, 0);
for orderIdx = reshape(order, 1, [])
    time = candidateTimes(orderIdx);
    if isempty(selectedTimes) || ...
            all(abs(selectedTimes - time) >= minimumSeparation)
        selectedTimes(end + 1) = time; %#ok<AGROW>
    end
    if numel(selectedTimes) == count
        break;
    end
end
if numel(selectedTimes) ~= count
    error('HierarchicalDelayedValueV213:InsufficientLocalMaxima', ...
        'The trajectory lacks two sufficiently separated need maxima.');
end
selectedTimes = sort(selectedTimes);
end

function mask = localMaximumMask(scores)
scores = reshape(scores, 1, []);
mask = false(size(scores));
for idx = 1:numel(scores)
    leftPassed = idx == 1 || scores(idx) >= scores(idx - 1);
    rightPassed = idx == numel(scores) || ...
        scores(idx) >= scores(idx + 1);
    strictSide = (idx == 1 || scores(idx) > scores(idx - 1)) || ...
        (idx == numel(scores) || scores(idx) > scores(idx + 1));
    mask(idx) = leftPassed && rightPassed && strictSide;
end
end

function auditNeedTrajectory(diagnostics, times)
need = diagnostics. ...
    topologyPolicyHierarchicalMaximumFormationNeed(times);
vectors = diagnostics. ...
    topologyPolicyHierarchicalFormationNeedByFormation(times);
versions = diagnostics. ...
    topologyPolicyHierarchicalGraphContractVersion(times);
truthUse = diagnostics.topologyPolicyTruthUsed(times);
futureUse = diagnostics.topologyPolicyFutureOutcomeUsed(times);
if any(~isfinite(need)) || any(cellfun(@isempty, vectors)) || ...
        any(cellfun(@isempty, versions)) || ...
        any(isfinite(truthUse) & truthUse ~= 0) || ...
        any(isfinite(futureUse) & futureUse ~= 0) || ...
        any(~diagnostics.topologyFeasible(times))
    error('HierarchicalDelayedValueV213:NeedTrajectoryGate', ...
        'The V213 causal need trajectory failed its runtime gate.');
end
end

function cachePaths = writeSelectedCaches( ...
        cacheRoot, presetName, seed, selectedTimes, scenario, ...
        config, diagnostics, protocol, gitState, elapsedSeconds)
contract = behaviorContinuationCacheContract();
base = getOnlinePositiveNetAddressablePayloadV99Protocol();
configSnapshot = config;
if isfield(configSnapshot, 'topologyPolicyFcn')
    configSnapshot = rmfield(configSnapshot, 'topologyPolicyFcn');
end
cachePaths = cell(1, numel(selectedTimes));
for idx = 1:numel(selectedTimes)
    time = selectedTimes(idx);
    posterior = diagnostics.topologyLocalPosteriorSnapshot{time};
    if isempty(posterior)
        error('HierarchicalDelayedValueV213:MissingPosterior', ...
            'The selected V213 state was not captured.');
    end
    historyByTime = buildBehaviorContinuationHistoryRecords( ...
        diagnostics, time, contract.topologyHistoryDepth);
    posteriorSnapshots = cell(1, time);
    posteriorSnapshots{time} = posterior;
    behaviorBundle = struct( ...
        'cacheContractVersion', contract.version, ...
        'posteriorSnapshotConvention', ...
            contract.posteriorSnapshotConvention, ...
        'topologyHistoryDepth', contract.topologyHistoryDepth, ...
        'topologyHistoryConvention', ...
            contract.topologyHistoryConvention, ...
        'protocolId', protocol.id, ...
        'presetName', presetName, 'seed', seed, ...
        'snapshotTimes', time, ...
        'configSnapshot', scenario, ...
        'behaviorConfigSnapshot', configSnapshot, ...
        'behaviorSeconds', elapsedSeconds, ...
        'behaviorEospaByTime', [], ...
        'behaviorCardinalityErrorByTime', [], ...
        'posteriorSnapshots', {posteriorSnapshots}, ...
        'preDecisionTopologyHistoryByTime', {historyByTime}, ...
        'generationGitCommit', gitState.commit, ...
        'generationTrackedWorktreeDirty', ...
            gitState.trackedWorktreeDirty, ...
        'generationUntrackedSourceFiles', ...
            {gitState.untrackedSourceFiles}, ...
        'referenceArmName', ...
            'online-positive-net-addressable-payload-v99-v1', ...
        'referenceReplayOnly', false, ...
        'missingLabelFusionMode', base.receiverMode, ...
        'policyTruthUsed', false, ...
        'policyFutureOutcomeUsed', false, ...
        'openedDevelopmentEvidenceOnly', true, ...
        'validationClaimAllowed', false, ...
        'evidenceBoundary', protocol.evidenceBoundary);
    cachePaths{idx} = fullfile(cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
        seed, time));
    save(cachePaths{idx}, 'behaviorBundle', '-v7');
    [posteriors, history] = extractBehaviorContinuationSnapshot( ...
        behaviorBundle, time, scenario.numberOfSensors);
    if numel(posteriors) ~= scenario.numberOfSensors || ...
            history.snapshotTime ~= time
        error('HierarchicalDelayedValueV213:CacheReadback', ...
            'A selected V213 cache failed readback.');
    end
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
if isfield(inputs.commConfig, 'linkUniforms') && ...
        ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = ...
        inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function [presets, seeds] = splitMembership(protocol, splitName)
switch splitName
    case 'training'
        presets = protocol.split.mainPresets;
        seeds = protocol.split.trainingSeeds;
    case 'calibration'
        presets = protocol.split.mainPresets;
        seeds = protocol.split.calibrationSeeds;
    case 'evaluation'
        presets = protocol.split.mainPresets;
        seeds = protocol.split.evaluationSeeds;
    case 'stress'
        presets = protocol.split.stressPresets;
        seeds = protocol.split.stressSeeds;
    case 'scale-extrapolation'
        presets = protocol.split.scaleExtrapolationPresets;
        seeds = protocol.split.scaleExtrapolationSeeds;
    otherwise
        error('HierarchicalDelayedValueV213:UnknownSplit', ...
            'The V213 trajectory split is not registered.');
end
end

function validateExisting(result, protocol, presetName, seed, ...
        splitName, commit)
required = {'contractVersion', 'protocolId', 'presetName', 'seed', ...
    'splitName', 'generationGitCommit', 'selectedTimes', ...
    'cachePaths', 'captureReplayExact'};
if ~isstruct(result) || ~all(isfield(result, required)) || ...
        ~strcmp(result.protocolId, protocol.id) || ...
        ~strcmp(result.presetName, presetName) || ...
        result.seed ~= seed || ~strcmp(result.splitName, splitName) || ...
        ~strcmp(result.generationGitCommit, commit) || ...
        numel(result.selectedTimes) ~= ...
            protocol.split.registeredDecisionWindowsPerTrajectory || ...
        ~result.captureReplayExact || ...
        any(cellfun(@(path) exist(path, 'file') ~= 2, ...
            result.cachePaths))
    error('HierarchicalDelayedValueV213:ExistingArtifactDrift', ...
        'The existing V213 trajectory artifact does not match source.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('HierarchicalDelayedValueV213:WriteReport', ...
        'Could not write the V213 trajectory report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V213 causal trajectory collection\n\n');
fprintf(fid, '- Split / scene / seed: `%s / %s / %d`\n', ...
    result.splitName, result.presetName, result.seed);
fprintf(fid, '- Scan window: `%d:%d`\n', ...
    result.scanTimes(1), result.scanTimes(end));
fprintf(fid, '- Selected local maxima: `%s`\n', ...
    mat2str(result.selectedTimes));
fprintf(fid, '- Selected need scores: `%s`\n', ...
    mat2str(result.selectedScores, 6));
fprintf(fid, '- V99 selected formations: `%s`\n', ...
    formatCellVectors(result.baseSelectedFormationIds));
fprintf(fid, '- Minimum separation: `%d` pages\n', ...
    result.minimumDecisionWindowSeparation);
fprintf(fid, '- Scan / capture seconds: `%.1f / %.1f`\n', ...
    result.scanSeconds, result.captureSeconds);
fprintf(fid, '- Exact causal replay: `%d`\n', ...
    result.captureReplayExact);
fprintf(fid, '- Recursive targets collected: `%d`\n\n', ...
    result.recursiveTargetsCollected);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = formatCellVectors(vectors)
tokens = cellfun(@mat2str, vectors, 'UniformOutput', false);
value = strjoin(tokens, ' / ');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
