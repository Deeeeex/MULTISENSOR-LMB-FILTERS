function [reportPath, analysis] = ...
        analyzeCausalGatewayEmbeddingV250TailAwareOracle(options)
% ANALYZECAUSALGATEWAYEMBEDDINGV250TAILAWAREORACLE
% Re-select the completed V250 H=3 arms with a localization-tail teacher.

if nargin < 1 || isempty(options)
    options = struct();
end
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
protocol = getCausalGatewayEmbeddingV250Protocol();
checkpointPath = char(getField(options, 'checkpointPath', fullfile( ...
    repoRoot, protocol.oracleOutputRoot, ...
    'CAUSAL_GATEWAY_EMBEDDING_V250_H3_ORACLE.mat')));
if ~isAbsolutePath(checkpointPath)
    checkpointPath = fullfile(repoRoot, checkpointPath);
end
reportPath = char(getField(options, 'reportPath', fullfile( ...
    fileparts(checkpointPath), ...
    'V250_TAIL_AWARE_ORACLE_INTERPRETATION.md')));
if ~isAbsolutePath(reportPath)
    reportPath = fullfile(repoRoot, reportPath);
end
writeReport = logical(getField(options, 'writeReport', true));
if ~isscalar(writeReport)
    error('CausalGatewayEmbeddingV250:InvalidTailAwareRequest', ...
        'writeReport must be a scalar logical value.');
end

loaded = load(checkpointPath, 'result');
if ~isfield(loaded, 'result')
    error('CausalGatewayEmbeddingV250:MissingOracleResult', ...
        'The V250 checkpoint does not contain result.');
end
result = loaded.result;
validateResult(result, protocol);
gitState = resolveResearchGitState();

analysis = struct();
analysis.contractVersion = ...
    'causal-gateway-embedding-v250-tail-aware-analysis-v1';
analysis.protocolId = result.protocolId;
analysis.analysisGitCommit = gitState.commit;
analysis.oracleGenerationGitCommit = result.generationGitCommit;
analysis.checkpointPath = checkpointPath;
analysis.reportPath = reportPath;
analysis.presetName = result.presetName;
analysis.seed = result.seed;
analysis.numericalTolerancePercent = 1e-6;
analysis.windows = cell(1, numel(result.windows));
analysis.oldAlignedAnchorCount = 0;
analysis.tailAlignedAnchorCount = 0;

oldArms = cell(1, numel(result.windows));
tailAwareArms = cell(1, numel(result.windows));
referenceArms = cell(1, numel(result.windows));
for windowIdx = 1:numel(result.windows)
    window = result.windows{windowIdx};
    reference = window.arms{window.referenceCandidateIndex};
    [~, targetFormationIdx] = max( ...
        reference.perFormationPositionRmse);
    oldIdx = window.selectedCandidateIndex;
    oldComparison = window.comparisons{oldIdx};
    oldAligned = isTailAligned(oldComparison, ...
        targetFormationIdx, analysis.numericalTolerancePercent);
    [selectedIdx, selectedComparison] = selectTailAwareCandidate( ...
        window, targetFormationIdx, ...
        analysis.numericalTolerancePercent);

    record = struct();
    record.anchorTime = window.anchorTime;
    record.referenceCandidateIndex = window.referenceCandidateIndex;
    record.targetFormationIndex = targetFormationIdx;
    record.targetFormationReferenceRmse = ...
        reference.perFormationPositionRmse(targetFormationIdx);
    record.oldSelectedCandidateIndex = oldIdx;
    record.oldSelectedTailAligned = oldAligned;
    record.selectedCandidateIndex = selectedIdx;
    record.selectedCandidateType = ...
        window.candidateTypes{selectedIdx};
    record.selectedComparison = selectedComparison;
    record.selectedTargetFormationEospaGainPercent = ...
        selectedComparison.formationEospaGainPercent( ...
            targetFormationIdx);
    record.selectedTargetFormationRmseGainPercent = ...
        selectedComparison.formationRmseGainPercent( ...
            targetFormationIdx);
    record.changedAssignmentRows = find(any( ...
        window.candidateAssignments{selectedIdx} ~= ...
        window.candidateAssignments{window.referenceCandidateIndex}, ...
        2));
    analysis.windows{windowIdx} = record;
    analysis.oldAlignedAnchorCount = ...
        analysis.oldAlignedAnchorCount + oldAligned;
    analysis.tailAlignedAnchorCount = ...
        analysis.tailAlignedAnchorCount + ...
        (selectedIdx ~= window.referenceCandidateIndex);
    oldArms{windowIdx} = window.arms{oldIdx};
    tailAwareArms{windowIdx} = window.arms{selectedIdx};
    referenceArms{windowIdx} = reference;
end

analysis.oldAggregate = compareAggregate( ...
    aggregateArms(oldArms), aggregateArms(referenceArms), protocol);
analysis.tailAwareAggregate = compareAggregate( ...
    aggregateArms(tailAwareArms), ...
    aggregateArms(referenceArms), protocol);
analysis.teacherAuthorized = ...
    analysis.tailAlignedAnchorCount >= ...
        protocol.minimumJointPositiveAnchorCount && ...
    analysis.tailAwareAggregate.jointPositive;
analysis.ridgeTrainingAuthorized = analysis.teacherAuthorized;
analysis.gnnTrainingAuthorized = false;
analysis.completedAt = datestr(now, 31);

if writeReport
    writeReportFile(reportPath, analysis, protocol);
end
fprintf(['V250 tail-aware analysis complete: aligned old/new %d/%d ', ...
    'of %d; ridge authorized=%d\n'], ...
    analysis.oldAlignedAnchorCount, analysis.tailAlignedAnchorCount, ...
    numel(analysis.windows), analysis.ridgeTrainingAuthorized);
fprintf('V250 tail-aware report: %s\n', reportPath);
end

function [bestIdx, bestComparison] = selectTailAwareCandidate( ...
        window, targetFormationIdx, tolerance)
bestIdx = window.referenceCandidateIndex;
bestComparison = window.comparisons{bestIdx};
bestKey = [-Inf, -Inf, -Inf, -Inf, -Inf];
for candidateIdx = 1:window.candidateCount
    if candidateIdx == window.referenceCandidateIndex
        continue;
    end
    comparison = window.comparisons{candidateIdx};
    if ~isTailAligned(comparison, targetFormationIdx, tolerance)
        continue;
    end
    targetRmse = comparison.formationRmseGainPercent( ...
        targetFormationIdx);
    targetEospa = comparison.formationEospaGainPercent( ...
        targetFormationIdx);
    minimumCore = min([comparison.eospaGainPercent, ...
        comparison.rmseGainPercent, ...
        comparison.consistencyGainPercent]);
    key = [targetRmse, targetEospa, minimumCore, ...
        comparison.attemptedByteSavingPercent, -candidateIdx];
    if lexicographicallyGreater(key, bestKey)
        bestIdx = candidateIdx;
        bestComparison = comparison;
        bestKey = key;
    end
end
end

function aligned = isTailAligned(comparison, targetFormationIdx, tolerance)
aligned = isstruct(comparison) && isscalar(comparison) && ...
    comparison.jointPositive && ...
    comparison.formationEospaGainPercent(targetFormationIdx) >= ...
        -tolerance && ...
    comparison.formationRmseGainPercent(targetFormationIdx) > tolerance;
end

function greater = lexicographicallyGreater(left, right)
greater = false;
for valueIdx = 1:numel(left)
    if left(valueIdx) > right(valueIdx) + 1e-12
        greater = true;
        return;
    end
    if left(valueIdx) < right(valueIdx) - 1e-12
        return;
    end
end
end

function aggregate = aggregateArms(arms)
aggregate = struct();
aggregate.positionEospa = mean(cellfun( ...
    @(value) value.positionEospa, arms));
aggregate.positionRmse = mean(cellfun( ...
    @(value) value.positionRmse, arms));
aggregate.interFormationPositionOspa = mean(cellfun( ...
    @(value) value.interFormationPositionOspa, arms));
aggregate.attemptedPayloadBytes = sum(cellfun( ...
    @(value) value.attemptedPayloadBytes, arms));
formationCount = numel(arms{1}.perFormationPositionEospa);
formationEospa = zeros(numel(arms), formationCount);
formationRmse = zeros(numel(arms), formationCount);
for armIdx = 1:numel(arms)
    formationEospa(armIdx, :) = ...
        arms{armIdx}.perFormationPositionEospa;
    formationRmse(armIdx, :) = ...
        arms{armIdx}.perFormationPositionRmse;
end
aggregate.perFormationPositionEospa = mean(formationEospa, 1);
aggregate.perFormationPositionRmse = mean(formationRmse, 1);
end

function comparison = compareAggregate(candidate, reference, protocol)
comparison = struct();
comparison.eospaGainPercent = lowerGain( ...
    reference.positionEospa, candidate.positionEospa);
comparison.rmseGainPercent = lowerGain( ...
    reference.positionRmse, candidate.positionRmse);
comparison.consistencyGainPercent = lowerGain( ...
    reference.interFormationPositionOspa, ...
    candidate.interFormationPositionOspa);
comparison.attemptedByteSavingPercent = lowerGain( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.jointScorePercent = min([ ...
    comparison.eospaGainPercent, comparison.rmseGainPercent, ...
    comparison.consistencyGainPercent]);
comparison.jointPositive = ...
    comparison.jointScorePercent > ...
        protocol.minimumAggregateCoreGainPercent && ...
    comparison.attemptedByteSavingPercent >= ...
        protocol.minimumAggregateByteSavingPercent && ...
    comparison.minimumFormationEospaGainPercent >= ...
        -protocol.maximumFormationRegressionPercent && ...
    comparison.minimumFormationRmseGainPercent >= ...
        -protocol.maximumFormationRegressionPercent;
end

function writeReportFile(path, analysis, protocol)
parent = fileparts(path);
if exist(parent, 'dir') ~= 7
    mkdir(parent);
end
fid = fopen(path, 'w');
if fid < 0
    error('CausalGatewayEmbeddingV250:TailAwareReportOpen', ...
        'Could not write the V250 tail-aware report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V250 tail-aware H=3 oracle interpretation\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    analysis.presetName, analysis.seed);
fprintf(fid, '- Oracle source commit: `%s`\n', ...
    analysis.oracleGenerationGitCommit);
fprintf(fid, '- Analysis source commit: `%s`\n', ...
    analysis.analysisGitCommit);
fprintf(fid, '- Old / tail-aware aligned anchors: `%d / %d` of `%d`\n', ...
    analysis.oldAlignedAnchorCount, ...
    analysis.tailAlignedAnchorCount, numel(analysis.windows));
fprintf(fid, '- Tail-aware teacher / ridge / GNN authorized: `%d / %d / %d`\n\n', ...
    analysis.teacherAuthorized, ...
    analysis.ridgeTrainingAuthorized, ...
    analysis.gnnTrainingAuthorized);

fprintf(fid, '## Decision\n\n');
fprintf(fid, ['The original network-minimum selector is not aligned with ', ...
    'the diagnosed V248 failure: it improves the reference-worst ', ...
    'formation at only %d of %d anchors. The revised teacher first ', ...
    'requires positive network E-OSPA, RMSE and consistency gains, ', ...
    'nonincreasing attempted bytes and the existing %.1f%% formation ', ...
    'regression cap. Among those arms it requires nondegrading E-OSPA ', ...
    'and positive RMSE gain for the reference-worst formation, then ', ...
    'maximizes that formation RMSE gain. This selects a tail-relevant ', ...
    'action at every anchor and authorizes ridge labels, not an ', ...
    'end-to-end or generalization claim.\n\n'], ...
    analysis.oldAlignedAnchorCount, numel(analysis.windows), ...
    protocol.maximumFormationRegressionPercent);

fprintf(fid, ['| Anchor | Reference-worst formation / RMSE | Old selected | ', ...
    'Tail-aware selected | Type | Network E / R / C | Byte saving | ', ...
    'Target formation E / R | Weakest any formation E / R |\n']);
fprintf(fid, '|--:|:--|--:|--:|:--|:--|--:|:--|:--|\n');
for windowIdx = 1:numel(analysis.windows)
    record = analysis.windows{windowIdx};
    gain = record.selectedComparison;
    fprintf(fid, ['| %d | F%d / %.3f | %d | %d | %s | ', ...
        '%+.3f%% / %+.3f%% / %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% / %+.3f%% | %+.3f%% / %+.3f%% |\n'], ...
        record.anchorTime, record.targetFormationIndex, ...
        record.targetFormationReferenceRmse, ...
        record.oldSelectedCandidateIndex, ...
        record.selectedCandidateIndex, ...
        record.selectedCandidateType, ...
        gain.eospaGainPercent, gain.rmseGainPercent, ...
        gain.consistencyGainPercent, ...
        gain.attemptedByteSavingPercent, ...
        record.selectedTargetFormationEospaGainPercent, ...
        record.selectedTargetFormationRmseGainPercent, ...
        gain.minimumFormationEospaGainPercent, ...
        gain.minimumFormationRmseGainPercent);
end

fprintf(fid, '\n## Aggregate comparison\n\n');
fprintf(fid, '| Metric | Original selector | Tail-aware selector |\n');
fprintf(fid, '|:--|--:|--:|\n');
writeAggregateRow(fid, 'E-OSPA gain', ...
    analysis.oldAggregate.eospaGainPercent, ...
    analysis.tailAwareAggregate.eospaGainPercent);
writeAggregateRow(fid, 'RMSE gain', ...
    analysis.oldAggregate.rmseGainPercent, ...
    analysis.tailAwareAggregate.rmseGainPercent);
writeAggregateRow(fid, 'Consistency gain', ...
    analysis.oldAggregate.consistencyGainPercent, ...
    analysis.tailAwareAggregate.consistencyGainPercent);
writeAggregateRow(fid, 'Attempted-byte saving', ...
    analysis.oldAggregate.attemptedByteSavingPercent, ...
    analysis.tailAwareAggregate.attemptedByteSavingPercent);
writeAggregateRow(fid, 'Weakest formation E-OSPA', ...
    analysis.oldAggregate.minimumFormationEospaGainPercent, ...
    analysis.tailAwareAggregate.minimumFormationEospaGainPercent);
writeAggregateRow(fid, 'Weakest formation RMSE', ...
    analysis.oldAggregate.minimumFormationRmseGainPercent, ...
    analysis.tailAwareAggregate.minimumFormationRmseGainPercent);

fprintf(fid, '\n| Formation | Tail-aware E-OSPA gain | Tail-aware RMSE gain |\n');
fprintf(fid, '|--:|--:|--:|\n');
for formationIdx = 1:numel( ...
        analysis.tailAwareAggregate.formationEospaGainPercent)
    fprintf(fid, '| F%d | %+.6f%% | %+.6f%% |\n', ...
        formationIdx, ...
        analysis.tailAwareAggregate.formationEospaGainPercent( ...
            formationIdx), ...
        analysis.tailAwareAggregate.formationRmseGainPercent( ...
            formationIdx));
end

fprintf(fid, '\n## Evidence boundary\n\n');
fprintf(fid, ['This is a post-hoc selection over already completed paired ', ...
    'H=3 arms from one M24 development seed. Truth and future outcomes ', ...
    'are used only to create offline teacher labels. The result shows ', ...
    'that the fixed-budget gateway action space contains localization-', ...
    'tail-relevant actions; it is not a deployable policy, a full-', ...
    'episode best method, an X36 result or a paper-level conclusion. ', ...
    'The persistent current-best table therefore remains unchanged.\n']);
end

function writeAggregateRow(fid, name, oldValue, tailAwareValue)
fprintf(fid, '| %s | `%+.3f%%` | `%+.3f%%` |\n', ...
    name, oldValue, tailAwareValue);
end

function value = lowerGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = lowerGainVector(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function validateResult(result, protocol)
valid = isstruct(result) && isscalar(result) && ...
    isfield(result, 'contractVersion') && ...
    strcmp(result.contractVersion, ...
        'causal-gateway-embedding-v250-h3-oracle-result-v1') && ...
    isfield(result, 'protocolId') && ...
    strcmp(result.protocolId, protocol.id) && ...
    isfield(result, 'completedAt') && ~isempty(result.completedAt) && ...
    isfield(result, 'windows') && ...
    numel(result.windows) == numel(protocol.anchorTimes);
if valid
    for windowIdx = 1:numel(result.windows)
        window = result.windows{windowIdx};
        valid = valid && isstruct(window) && isscalar(window) && ...
            window.anchorTime == protocol.anchorTimes(windowIdx) && ...
            numel(window.arms) == window.candidateCount && ...
            numel(window.comparisons) == window.candidateCount;
    end
end
if ~valid
    error('CausalGatewayEmbeddingV250:InvalidTailAwareCheckpoint', ...
        'The V250 H=3 checkpoint is incomplete or violates the protocol.');
end
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    (~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once'))));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
