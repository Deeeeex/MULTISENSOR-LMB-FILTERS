function [reportPath, dataset] = ...
        mergeFormationLabelKlaImmediateDatasetV208(options)
% MERGEFORMATIONLABELKLAIMMEDIATEDATASETV208 Join deterministic page shards.

if nargin < 1 || isempty(options)
    options = struct();
end
evidenceRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v208');
pageOnePath = getField(options, 'pageOnePath', fullfile( ...
    evidenceRoot, 'formation_label_kla_immediate_smoke', ...
    'x36_seed211_t72', ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat'));
shardRoot = getField(options, 'shardRoot', fullfile( ...
    evidenceRoot, 'formation_label_kla_immediate_shards', ...
    'x36_seed211_t72_h8'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    evidenceRoot, 'formation_label_kla_immediate_merged', ...
    'x36_seed211_t72_h8'));
pageCount = 8;
paths = cell(1, pageCount);
paths{1} = pageOnePath;
for pageIdx = 2:pageCount
    paths{pageIdx} = fullfile(shardRoot, ...
        sprintf('page_%02d', pageIdx), ...
        'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat');
end

blocks = repmat(struct(), 1, 0);
rows = repmat(struct(), 1, 0);
sourceRecords = repmat(struct( ...
    'page', 0, 'currentTime', 0, 'path', '', ...
    'rowCount', 0), 1, pageCount);
actionFeatureNames = cell(1, 0);
targetNames = cell(1, 0);
presetName = '';
seed = NaN;
returnTimes = zeros(1, pageCount);

for pageIdx = 1:pageCount
    path = paths{pageIdx};
    if exist(path, 'file') ~= 2
        error('FormationLabelMergeV208:MissingShard', ...
            'Missing deterministic page shard: %s', path);
    end
    loaded = load(path, 'dataset');
    shard = loaded.dataset;
    validateShard(shard, pageIdx);
    if pageIdx == 1
        actionFeatureNames = reshape( ...
            shard.actionFeatureNames, 1, []);
        targetNames = reshape(shard.targetNames, 1, []);
        presetName = shard.presetName;
        seed = shard.seed;
    elseif ~isequal(actionFeatureNames, ...
            reshape(shard.actionFeatureNames, 1, [])) || ...
            ~isequal(targetNames, ...
                reshape(shard.targetNames, 1, [])) || ...
            ~strcmp(presetName, shard.presetName) || ...
            seed ~= shard.seed
        error('FormationLabelMergeV208:ContractDrift', ...
            'Feature, target, preset, or seed drifted across shards.');
    end

    block = shard.blocks(1);
    if ~isfield(block, 'evaluatedCandidateCount')
        block.evaluatedCandidateCount = ...
            block.shortlistedCandidateCount;
    end
    block.blockId = pageIdx;
    block.page = pageIdx;
    if isempty(blocks)
        blocks = block;
    else
        blocks(end + 1) = block; %#ok<AGROW>
    end

    shardRows = reshape(shard.rows, 1, []);
    for localIdx = 1:numel(shardRows)
        shardRows(localIdx).rowId = numel(rows) + localIdx;
        shardRows(localIdx).blockId = pageIdx;
        shardRows(localIdx).page = pageIdx;
    end
    if isempty(rows)
        rows = shardRows;
    else
        rows = [rows, shardRows]; %#ok<AGROW>
    end
    returnTimes(pageIdx) = block.currentTime;
    sourceRecords(pageIdx).page = pageIdx;
    sourceRecords(pageIdx).currentTime = block.currentTime;
    sourceRecords(pageIdx).path = path;
    sourceRecords(pageIdx).rowCount = numel(shardRows);
end

targets = vertcat(rows.targets);
strictTailMask = strictTailPositive(targets);
dataset = struct();
dataset.contractVersion = ...
    'formation-label-kla-immediate-dataset-v208-merged-v1';
dataset.generatedAt = datestr(now, 31);
dataset.presetName = presetName;
dataset.seed = seed;
dataset.pageIndices = 1:pageCount;
dataset.returnTimes = returnTimes;
dataset.actionFeatureNames = actionFeatureNames;
dataset.targetNames = targetNames;
dataset.blocks = blocks;
dataset.rows = rows;
dataset.sourceRecords = sourceRecords;
dataset.blockCount = numel(blocks);
dataset.rowCount = numel(rows);
dataset.netByteFeasibleRowCount = ...
    nnz([rows.netByteFeasible]);
dataset.jointTrackingPositiveRowCount = ...
    nnz([rows.jointTrackingPositive]);
dataset.jointAggregatePositiveRowCount = ...
    nnz([rows.jointAggregatePositive]);
dataset.strictZeroToleranceTailPositiveRowCount = ...
    nnz(strictTailMask);
dataset.teacherKeyRowCount = nnz([rows.teacherKey]);
dataset.featuresUseTruth = false;
dataset.featuresUseFutureInformation = false;
dataset.targetsUseCurrentTruth = true;
dataset.targetsUseFutureInformation = false;
dataset.numericLabelIdentifiersUsedAsFeatures = false;
dataset.numericSourceIdentifiersUsedAsFeatures = false;
dataset.recursiveTargetsIncluded = false;
dataset.validationClaimAllowed = false;
dataset.evidenceBoundary = [ ...
    'This deterministic merge joins eight dense immediate-action pages ', ...
    'from the already opened X36 seed-211 V99 trajectory. Candidate and ', ...
    'graph features remain truth-free; current truth supplies offline ', ...
    'one-step targets only. Page-level cross-validation measures ', ...
    'development learnability, not recursive, held-out, cross-seed, ', ...
    'cross-scene, or policy performance.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208_MERGED.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208_MERGED.md');
dataset.matPath = matPath;
dataset.reportPath = reportPath;
save('-mat7-binary', matPath, 'dataset');
writeReport(reportPath, dataset, strictTailMask);
fprintf('V208 merged immediate dataset: %s\n', reportPath);
end

function validateShard(dataset, expectedPage)
required = {'contractVersion', 'presetName', 'seed', ...
    'pageIndices', 'returnTimes', 'actionFeatureNames', ...
    'targetNames', 'blocks', 'rows', 'blockCount', ...
    'featuresUseTruth', 'featuresUseFutureInformation', ...
    'targetsUseCurrentTruth', 'targetsUseFutureInformation', ...
    'numericLabelIdentifiersUsedAsFeatures', ...
    'numericSourceIdentifiersUsedAsFeatures', ...
    'recursiveTargetsIncluded', 'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-label-kla-immediate-dataset-v208-v1') || ...
        dataset.blockCount ~= 1 || numel(dataset.blocks) ~= 1 || ...
        ~isequal(dataset.pageIndices, expectedPage) || ...
        numel(dataset.returnTimes) ~= 1 || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        ~dataset.targetsUseCurrentTruth || ...
        dataset.targetsUseFutureInformation || ...
        dataset.numericLabelIdentifiersUsedAsFeatures || ...
        dataset.numericSourceIdentifiersUsedAsFeatures || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed
    error('FormationLabelMergeV208:InvalidShard', ...
        'Page %d does not satisfy the V208 shard envelope.', ...
        expectedPage);
end
if isempty(dataset.rows) || ...
        any([dataset.rows.page] ~= expectedPage) || ...
        any([dataset.rows.truthUsedForFeatures]) || ...
        ~all([dataset.rows.truthUsedForTargets])
    error('FormationLabelMergeV208:InvalidRows', ...
        'Page %d has incomplete or contaminated rows.', expectedPage);
end
end

function mask = strictTailPositive(targets)
mask = targets(:, 1) > 0 & targets(:, 2) > 0 & ...
    targets(:, 3) >= 0 & targets(:, 5) > 0 & ...
    targets(:, 6) > 0 & targets(:, 7) >= 0 & ...
    targets(:, 8) >= 0 & targets(:, 9) >= 0 & ...
    targets(:, 10) >= 0 & targets(:, 11) >= 0;
end

function writeReport(path, dataset, strictTailMask)
fid = fopen(path, 'w');
if fid < 0
    error('FormationLabelMergeV208:ReportOpenFailed', ...
        'Could not write the merged V208 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V208 merged immediate action-value dataset\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    dataset.presetName, dataset.seed);
fprintf(fid, '- Blocks / actions: `%d / %d`\n', ...
    dataset.blockCount, dataset.rowCount);
fprintf(fid, '- Joint mean E-OSPA + RMSE positive: `%d`\n', ...
    dataset.jointTrackingPositiveRowCount);
fprintf(fid, ['- Joint tracking + consensus + byte positive: ', ...
    '`%d`\n'], dataset.jointAggregatePositiveRowCount);
fprintf(fid, '- Zero-tolerance tail-safe positive: `%d`\n', ...
    dataset.strictZeroToleranceTailPositiveRowCount);
fprintf(fid, '- V206 teacher keys recovered: `%d / 5`\n\n', ...
    dataset.teacherKeyRowCount);
fprintf(fid, ['| Time | Full | Shortlist | Actions | E+R | ', ...
    'Aggregate | Tail-safe | Best min(E,R,C) |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for block = reshape(dataset.blocks, 1, [])
    rowMask = [dataset.rows.blockId] == block.blockId;
    blockRows = dataset.rows(rowMask);
    blockTargets = vertcat(blockRows.targets);
    aggregate = [blockRows.jointAggregatePositive];
    bestJoint = NaN;
    if any(aggregate)
        bestJoint = max(min( ...
            blockTargets(aggregate, 1:3), [], 2));
    end
    fprintf(fid, ['| %d | %d | %d | %d | %d | %d | %d | ', ...
        '%+.3f%% |\n'], block.currentTime, ...
        block.fullCandidateCount, ...
        block.shortlistedCandidateCount, numel(blockRows), ...
        nnz([blockRows.jointTrackingPositive]), ...
        nnz(aggregate), nnz(strictTailMask(rowMask)), bestJoint);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
