function summary = runSparseReferenceLabelRollbackV156Suite(options)
% RUNSPARSEREFERENCELABELROLLBACKV156SUITE Frozen K={1,2,4,8} screen.

if nargin < 1 || isempty(options)
    options = struct();
end
capacities = [1, 2, 4, 8];
results = cell(1, numel(capacities));
for idx = 1:numel(capacities)
    [~, results{idx}] = ...
        runSparseReferenceLabelRollbackV156X36T72( ...
            capacities(idx), options);
end
summary = struct( ...
    'contractVersion', 'sparse-reference-label-v156-suite-v1', ...
    'capacities', capacities, ...
    'results', {results}, ...
    'gatePassed', cellfun(@(result) result.gatePassed, results), ...
    'meanGainPercent', cellfun( ...
        @(result) result.meanGainPercent, results), ...
    'minimumFormationGainPercent', cellfun( ...
        @(result) result.minimumFormationGainPercent, results), ...
    'minimumFormationTimeGainPercent', cellfun( ...
        @(result) result.minimumFormationTimeGainPercent, results), ...
    'adjustedAttemptedByteSavingPercent', cellfun( ...
        @(result) result.adjustedAttemptedByteSavingPercent, results));
end
