function summary = runSparseReferenceLabelRollbackV156Suite(options)
% RUNSPARSEREFERENCELABELROLLBACKV156SUITE Frozen K={1,2,4,8} screen.

if nargin < 1 || isempty(options)
    options = struct();
end
capacities = [1, 2, 4, 8];
results = cell(1, numel(capacities));
for idx = 1:numel(capacities)
    [~, results{idx}] = ...
        runSparseReferenceLabelRollbackV156X36T72( ...
            capacities(idx), options);
end
summary = struct( ...
    'contractVersion', 'sparse-reference-label-v156-suite-v1', ...
    'capacities', capacities, ...
    'results', {results}, ...
    'gatePassed', cellfun(@(result) result.gatePassed, results), ...
    'meanGainPercent', cellfun( ...
        @(result) result.meanGainPercent, results), ...
    'minimumFormationGainPercent', cellfun( ...
        @(result) result.minimumFormationGainPercent, results), ...
    'minimumFormationTimeGainPercent', cellfun( ...
        @(result) result.minimumFormationTimeGainPercent, results), ...
    'adjustedAttemptedByteSavingPercent', cellfun( ...
        @(result) result.adjustedAttemptedByteSavingPercent, results));
outputRoot = getField(options, 'suiteOutputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v156', 'sparse_reference_label_rollback', 'suite'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
summary.reportPath = fullfile(outputRoot, ...
    'SPARSE_REFERENCE_LABEL_ROLLBACK_V156_SUITE_SUMMARY.md');
writeSummary(summary.reportPath, summary);
end

function writeSummary(path, summary)
fileId = fopen(path, 'w');
if fileId < 0
    error('SparseReferenceLabelV156:SummaryWriteFailed', ...
        'Could not create the V156 suite summary.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '# V156 sparse reference-label capacity summary\n\n');
fprintf(fileId, ['All arms reuse the paired static X36 seed-211 t=72 H=8 ', ...
    'baseline. They are privileged representation oracles, not deployable ', ...
    'policies.\n\n']);
fprintf(fileId, ['| Maximum labels K | Mean gain | Minimum formation-time ', ...
    'gain | Adjusted byte saving | Gate |\n']);
fprintf(fileId, '|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(summary.capacities)
    fprintf(fileId, '| %d | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n', ...
        summary.capacities(idx), summary.meanGainPercent(idx), ...
        summary.minimumFormationTimeGainPercent(idx), ...
        summary.adjustedAttemptedByteSavingPercent(idx), ...
        summary.gatePassed(idx));
end
fprintf(fileId, ['\nNo uniform top-K arm passes. K=1 gives the strongest ', ...
    'mean gain, while larger K progressively repairs the worst local tail ', ...
    'but can over-correct other node-time cells. The fixed-capacity, ', ...
    'reference-discrepancy ranking is therefore closed. The next bounded ', ...
    'question is whether a label-value oracle that accepts only positive ', ...
    'marginal edits can satisfy both objectives with variable capacity.\n']);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
