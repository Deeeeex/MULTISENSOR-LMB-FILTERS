function audit = auditM24CounterfactualConsensusTeacher()
% AUDITM24COUNTERFACTUALCONSENSUSTEACHER Formal seed-7 teacher audit.
%
% This development-only audit compares all six joint-baseline posterior
% disagreement teachers with the identical code-24 rolling-safe reference.
% It is a surrogate-alignment diagnosis, not deployable policy evidence.

addpath(genpath(pwd));

seed = 7;
batchCount = 2;
reportPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'M24_COUNTERFACTUAL_CONSENSUS_TEACHER_AUDIT_SEED7_20260729.md');
gitState = resolveResearchGitState();
sourceFiles = cell(1, batchCount);
candidateRecords = repmat(struct(), 1, 0);
baselineRecords = repmat(struct(), 1, 0);
for batchIdx = 1:batchCount
    directory = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'rollout_dataset', sprintf( ...
            'seed%d_postfusion_b%02dof%02d', ...
            seed, batchIdx, batchCount));
    sourceFiles{batchIdx} = latestMatFile(directory);
    loaded = load(sourceFiles{batchIdx});
    for record = loaded.summary.records
        code = parseFirstActionCode(record.armMode);
        if code == 24
            baselineRecords(end + 1) = record; %#ok<AGROW>
        else
            candidateRecords(end + 1) = record; %#ok<AGROW>
        end
    end
end
if numel(candidateRecords) ~= 6 || ...
        numel(baselineRecords) ~= batchCount
    error('Expected six candidates and two code-24 references.');
end
[candidateRecords, codes] = sortRecordsByActionCode(candidateRecords);
if ~isequal(codes, 40:45)
    error('Counterfactual teacher evidence must cover codes 40:45.');
end
baseline = baselineRecords(1);
for baselineIdx = 2:numel(baselineRecords)
    assertSameBaseline(baseline, baselineRecords(baselineIdx));
end

rows = repmat(struct(), 1, numel(candidateRecords));
for candidateIdx = 1:numel(candidateRecords)
    code = codes(candidateIdx);
    record = candidateRecords(candidateIdx);
    if code <= 42
        objectiveMode = 'mean';
        exactCrossCount = code - 39;
    else
        objectiveMode = 'top-fraction';
        exactCrossCount = code - 42;
    end
    rows(candidateIdx) = struct( ...
        'code', code, ...
        'objectiveMode', objectiveMode, ...
        'k', exactCrossCount, ...
        'meanEospa', record.focusEospa, ...
        'meanGainPercent', percentGain( ...
            baseline.focusEospa, record.focusEospa), ...
        'worstEospa', record.focusWorstSensorEospa, ...
        'tailGainPercent', percentGain( ...
            baseline.focusWorstSensorEospa, ...
            record.focusWorstSensorEospa), ...
        'posteriorDisagreement', ...
            record.focusPosteriorConsensus, ...
        'posteriorGainPercent', percentGain( ...
            baseline.focusPosteriorConsensus, ...
            record.focusPosteriorConsensus), ...
        'byteChangePercent', percentChange( ...
            baseline.focusAttemptedBytes, ...
            record.focusAttemptedBytes), ...
        'policySeconds', record.topologyPolicySeconds, ...
        'repairRate', record.policyRepairRate, ...
        'truthUseFraction', record.policyTruthUseFraction, ...
        'payloadEmergencyRate', ...
            record.policyPayloadEmergencyRate, ...
        'topologyInfeasibleRate', ...
            record.focusTopologyInfeasibleRate, ...
        'selectedSensorB3', ...
            record.focusSelectedRollingB3SensorStrongFraction, ...
        'selectedFormationB3', ...
            record.focusSelectedRollingB3FormationStrongFraction, ...
        'offlineTeacher', ...
            isOfflineCounterfactualSequenceMode(record.armMode), ...
        'jointPass', false);
end
for rowIdx = 1:numel(rows)
    row = rows(rowIdx);
    rows(rowIdx).jointPass = ...
        row.meanGainPercent >= 5 - 1e-9 && ...
        row.tailGainPercent >= -1e-9 && ...
        abs(row.byteChangePercent) <= 2 + 1e-9 && ...
        row.repairRate == 0 && ...
        row.truthUseFraction == 0 && ...
        row.payloadEmergencyRate == 0 && ...
        row.topologyInfeasibleRate == 0 && ...
        row.selectedSensorB3 == 1 && ...
        row.selectedFormationB3 == 1 && ...
        row.offlineTeacher;
end

audit = struct( ...
    'protocolId', ...
        'm24-joint-baseline-counterfactual-teacher-seed7-v1', ...
    'seed', seed, ...
    'experimentCommit', '35496bc', ...
    'candidateCount', numel(rows), ...
    'surrogateImprovementCount', ...
        nnz([rows.posteriorGainPercent] > 0), ...
    'jointPassCount', nnz([rows.jointPass]), ...
    'baseline', baseline, ...
    'rows', rows, ...
    'sourceFiles', {sourceFiles}, ...
    'gitState', gitState);
writeReport(reportPath, audit);
fprintf('Report: %s\n', reportPath);
fprintf(['Candidates %d, posterior-disagreement improvements %d, ', ...
    'tracking/tail passes %d.\n'], audit.candidateCount, ...
    audit.surrogateImprovementCount, audit.jointPassCount);
end

function writeReport(reportPath, audit)
fileId = fopen(reportPath, 'w');
if fileId < 0
    error('Could not open counterfactual-teacher audit report.');
end
cleanup = onCleanup(@() fclose(fileId));
baseline = audit.baseline;
fprintf(fileId, ...
    '# M24 joint-baseline counterfactual-teacher audit: seed 7\n\n');
fprintf(fileId, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fileId, '- Experiment commit: `%s`\n', ...
    audit.experimentCommit);
fprintf(fileId, '- Evidence split: `development`\n');
fprintf(fileId, '- Design-seen seed: `%d`\n', audit.seed);
fprintf(fileId, '- Audit git commit: `%s`\n', ...
    audit.gitState.commit);
fprintf(fileId, '- Audit tracked worktree dirty: `%d`\n', ...
    audit.gitState.trackedWorktreeDirty);
fprintf(fileId, '- Audit untracked source dirty: `%d`\n', ...
    audit.gitState.untrackedSourceDirty);
fprintf(fileId, ['- Scope: truth-free centralized offline teacher; ', ...
    'requires all current full posteriors and is excluded from ', ...
    'primary and held-out evidence.\n\n']);
fprintf(fileId, '## Registered reference and gates\n\n');
fprintf(fileId, '- Code-24 E-OSPA: `%.4f`\n', ...
    baseline.focusEospa);
fprintf(fileId, '- Code-24 worst-node E-OSPA: `%.4f`\n', ...
    baseline.focusWorstSensorEospa);
fprintf(fileId, '- Code-24 posterior disagreement: `%.4f`\n', ...
    baseline.focusPosteriorConsensus);
fprintf(fileId, '- Code-24 attempted bytes: `%.0f`\n', ...
    baseline.focusAttemptedBytes);
fprintf(fileId, ['- Joint gate: at least 5%% mean tracking gain, ', ...
    'no worst-node regression, at most 2%% attempted-byte ', ...
    'mismatch, complete selected rolling-B3 safety, no repair, ', ...
    'emergency, truth use or infeasibility.\n\n']);
fprintf(fileId, '## Complete candidate table\n\n');
fprintf(fileId, ['| Code | Objective | k | E-OSPA | Mean gain | ', ...
    'Worst node | Tail gain | Posterior disagr. | Posterior gain | ', ...
    'Byte change | Policy s | Pass |\n']);
fprintf(fileId, ['|--:|:--|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|:--:|\n']);
for row = audit.rows
    fprintf(fileId, ...
        ['| %02d | `%s` | %d | %.4f | %+.2f%% | %.4f | ', ...
         '%+.2f%% | %.4f | %+.2f%% | %+.2f%% | %.2f | %d |\n'], ...
        row.code, row.objectiveMode, row.k, row.meanEospa, ...
        row.meanGainPercent, row.worstEospa, ...
        row.tailGainPercent, row.posteriorDisagreement, ...
        row.posteriorGainPercent, row.byteChangePercent, ...
        row.policySeconds, row.jointPass);
end
fprintf(fileId, '\n## Decision\n\n');
fprintf(fileId, ...
    '- Posterior-disagreement improvements: `%d / %d`\n', ...
    audit.surrogateImprovementCount, audit.candidateCount);
fprintf(fileId, '- Joint tracking/tail passes: `%d / %d`\n\n', ...
    audit.jointPassCount, audit.candidateCount);
fprintf(fileId, ['All six actions fail the tracking/tail gate despite ', ...
    'communication matching. The least harmful mean-k1 action lowers ', ...
    'posterior disagreement but worsens E-OSPA, directly falsifying ', ...
    'one-step posterior consensus as a sufficient tracking surrogate ', ...
    'for this M24 checkpoint. Larger k and the global top-fraction ', ...
    'objective worsen tracking further. Retain this implementation only ', ...
    'as a negative offline diagnostic; do not train a deployable scorer ', ...
    'from these labels.\n\n']);
fprintf(fileId, '## Source summaries\n\n');
for sourceFile = audit.sourceFiles
    fprintf(fileId, '- `%s`\n', sourceFile{1});
end
clear cleanup;
end

function sourceFile = latestMatFile(directory)
listing = dir(fullfile(directory, '*.mat'));
if isempty(listing)
    error('No MAT summary found in %s.', directory);
end
[~, latestIdx] = max([listing.datenum]);
sourceFile = fullfile(directory, listing(latestIdx).name);
end

function [records, codes] = sortRecordsByActionCode(records)
codes = arrayfun(@(record) ...
    parseFirstActionCode(record.armMode), records);
[codes, order] = sort(codes);
records = records(order);
end

function actionCode = parseFirstActionCode(armMode)
tokens = regexp(armMode, ...
    'rolling-safe-sequence-t[0-9]+-s([0-9]+)-w', ...
    'tokens', 'once');
if isempty(tokens) || numel(tokens{1}) < 2
    error('Could not parse action code from %s.', armMode);
end
actionCode = str2double(tokens{1}(1:2));
end

function assertSameBaseline(reference, candidate)
fields = {'focusEospa', 'focusWorstSensorEospa', ...
    'focusPosteriorConsensus', 'focusAttemptedBytes', ...
    'policySelectedRouteSignature'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    if isnumeric(reference.(fieldName))
        if abs(reference.(fieldName) - candidate.(fieldName)) > 1e-9
            error('Code-24 references differ in %s.', fieldName);
        end
    elseif ~isequal(reference.(fieldName), candidate.(fieldName))
        error('Code-24 references differ in %s.', fieldName);
    end
end
end

function value = percentGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = percentChange(reference, candidate)
value = 100 * (candidate - reference) / max(abs(reference), eps);
end
