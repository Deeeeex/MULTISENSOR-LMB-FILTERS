function [reportPath, summary] = ...
    summarizeLabelSetDiverseTemporalUpperBoundM24(options)
% SUMMARIZELABELSETDIVERSETEMPORALUPPERBOUNDM24 Gate C/G timing value.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
states = struct( ...
    'seed', {11, 19, 23, 27}, ...
    'time', {78, 78, 78, 78}, ...
    'behavior', protocol.diverseTemporalUpperBoundBehaviors, ...
    'behaviorAction', { ...
        'label-set-message-passing-safe-fixed-e05-a70', ...
        'fixed-counter-clockwise', ...
        'fixed-counter-clockwise', ...
        'label-set-message-passing-safe-fixed-e05-a70'});
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'diverse_temporal_upper_bound_v1'));
rows = repmat(emptyRow(), 1, numel(states));
for stateIdx = 1:numel(states)
    state = states(stateIdx);
    path = fullfile(inputDirectory, ...
        sprintf('seed%d', state.seed), sprintf([ ...
            'label_set_causal_graph_option_h3_m24_', ...
            'seed%d_t%d_%s_source.mat'], ...
            state.seed, state.time, state.behavior));
    loaded = load(path, 'preflight');
    if ~isfield(loaded, 'preflight')
        error('Temporal upper-bound artifact lacks preflight.');
    end
    preflight = loaded.preflight;
    validatePreflight(preflight, state, protocol);
    risk = [preflight.outcomes.meanEospa];
    oldOracle = min(risk(1:2));
    persistentOracle = min(risk(1:3));
    [temporalOracle, bestIdx] = min(risk);
    row = emptyRow();
    row.seed = state.seed;
    row.currentTime = state.time;
    row.behavior = state.behavior;
    row.rankToken = ...
        protocol.diverseTemporalUpperBoundRankTokens(stateIdx);
    row.artifactPath = path;
    row.cccMeanEospa = risk(1);
    row.g1MeanEospa = risk(2);
    row.persistentRankMeanEospa = risk(3);
    row.oldOracleMeanEospa = oldOracle;
    row.persistentOracleMeanEospa = persistentOracle;
    row.temporalOracleMeanEospa = temporalOracle;
    row.bestOption = preflight.actionSequenceNames{bestIdx};
    row.gainVsOldOraclePercent = ...
        relativeGain(oldOracle, temporalOracle);
    row.incrementalGainVsPersistentOraclePercent = ...
        relativeGain(persistentOracle, temporalOracle);
    row.refreshesPersistentOracle = ...
        temporalOracle < persistentOracle - 1e-12;
    row.maximumByteDeviationPercent = ...
        max(abs(preflight.attemptedByteDeviationPercent));
    row.restartEquivalencePassed = ...
        preflight.restartEquivalencePassed;
    row.safetyPassed = ...
        ~preflight.runtimePolicyUsesTruth && ...
        all([preflight.outcomes.repairCount] == 0) && ...
        all([preflight.outcomes.payloadEmergencyCount] == 0) && ...
        all([preflight.outcomes.infeasibleCount] == 0) && ...
        all(arrayfun(@(outcome) ...
            all(outcome.messageCounts == ...
                protocol. ...
                    diverseGraphOptionExpectedSelectedMessageCount) && ...
            all(outcome.selectedSensorB3Pass) && ...
            all(outcome.selectedFormationB3Pass), ...
            preflight.outcomes));
    rows(stateIdx) = row;
end

meanOldOracle = mean([rows.oldOracleMeanEospa]);
meanPersistentOracle = mean( ...
    [rows.persistentOracleMeanEospa]);
meanTemporalOracle = mean([rows.temporalOracleMeanEospa]);
gainVsOldOraclePercent = ...
    relativeGain(meanOldOracle, meanTemporalOracle);
incrementalGainVsPersistentPercent = ...
    relativeGain(meanPersistentOracle, meanTemporalOracle);
hardAuditPassed = ...
    all([rows.restartEquivalencePassed]) && ...
    all([rows.safetyPassed]) && ...
    max([rows.maximumByteDeviationPercent]) <= ...
        protocol.macroActionMaximumByteDeviationPercent;
headroomPassed = ...
    incrementalGainVsPersistentPercent >= ...
        protocol. ...
            diverseTemporalUpperBoundMinimumIncrementalGainPercent;

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-label-set-diverse-temporal-upper-bound-summary-v1';
summary.auditContractVersion = ...
    protocol.diverseTemporalUpperBoundAuditContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.rows = rows;
summary.meanOldTwoOptionOracleEospa = meanOldOracle;
summary.meanPersistentRankOracleEospa = ...
    meanPersistentOracle;
summary.meanTemporalOracleEospa = meanTemporalOracle;
summary.gainVsOldTwoOptionOraclePercent = ...
    gainVsOldOraclePercent;
summary.incrementalGainVsPersistentRankOraclePercent = ...
    incrementalGainVsPersistentPercent;
summary.refreshedPersistentStateCount = ...
    nnz([rows.refreshesPersistentOracle]);
summary.maximumByteDeviationPercent = ...
    max([rows.maximumByteDeviationPercent]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.temporalHeadroomGatePassed = headroomPassed;
summary.temporalUpperBoundRejected = ~headroomPassed;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.nextMethodDirection = [ ...
    'quota-adaptive-backbone-preserving-residual-routing'];
summary.evidenceBoundary = [ ...
    'This opened-training upper bound chooses each state rank after ', ...
    'observing future return and tests only eight C/G timing patterns. ', ...
    'It cannot establish a deployable selector, development, held-out ', ...
    'M24 or X36 result.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = 'label_set_diverse_temporal_upper_bound_m24_v1';
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Temporal upper-bound summary already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary, protocol);
fprintf('Temporal upper-bound summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function validatePreflight(preflight, state, protocol)
stateIdx = find( ...
    protocol.diverseTemporalUpperBoundSeedTimes(:, 1) == ...
        state.seed & ...
    protocol.diverseTemporalUpperBoundSeedTimes(:, 2) == ...
        state.time);
rankToken = ...
    protocol.diverseTemporalUpperBoundRankTokens(stateIdx);
expectedSequences = ...
    protocol.diverseTemporalUpperBoundPatterns;
expectedSequences(expectedSequences == 0) = rankToken;
if numel(stateIdx) ~= 1 || ...
        ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.auditMode, ...
            'diverse-temporal-upper-bound') || ...
        ~strcmp(preflight.auditContractVersion, ...
            protocol. ...
                diverseTemporalUpperBoundAuditContractVersion) || ...
        preflight.seed ~= state.seed || ...
        preflight.currentTime ~= state.time || ...
        ~strcmp(preflight.sourceBehaviorAction, ...
            state.behaviorAction) || ...
        ~isequal(preflight.actionSequences, expectedSequences) || ...
        preflight.exploratoryActionSubsetUsed || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || ...
        preflight.x36Opened
    error('Temporal upper-bound preflight violates the frozen contract.');
end
end

function writeReport(path, summary, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write temporal upper-bound report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 diverse temporal H=3 upper bound\n\n');
fprintf(fid, [ ...
    '- Mean old / persistent / temporal oracle E-OSPA: ', ...
    '`%.6f / %.6f / %.6f`\n'], ...
    summary.meanOldTwoOptionOracleEospa, ...
    summary.meanPersistentRankOracleEospa, ...
    summary.meanTemporalOracleEospa);
fprintf(fid, ...
    '- Gain vs old two-option oracle: `%.3f%%`\n', ...
    summary.gainVsOldTwoOptionOraclePercent);
fprintf(fid, [ ...
    '- Incremental gain vs persistent-rank oracle: ', ...
    '`%.3f%%` (gate `%.3f%%`)\n'], ...
    summary.incrementalGainVsPersistentRankOraclePercent, ...
    protocol. ...
        diverseTemporalUpperBoundMinimumIncrementalGainPercent);
fprintf(fid, '- Refreshed persistent states: `%d / %d`\n', ...
    summary.refreshedPersistentStateCount, ...
    numel(summary.rows));
fprintf(fid, '- Hard audit / temporal headroom gates: `%d / %d`\n\n', ...
    summary.hardAuditGatesPassed, ...
    summary.temporalHeadroomGatePassed);
fprintf(fid, [ ...
    '| Seed | Source | Rank | Old oracle | Persistent oracle | ', ...
    'Temporal oracle | Best | Gain vs old | Incremental | Safe |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|--:|--:|:--|--:|--:|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, [ ...
        '| %d | %s | %d | %.6f | %.6f | %.6f | `%s` | ', ...
        '%+.3f%% | %+.3f%% | %d |\n'], ...
        row.seed, row.behavior, row.rankToken - 2, ...
        row.oldOracleMeanEospa, ...
        row.persistentOracleMeanEospa, ...
        row.temporalOracleMeanEospa, row.bestOption, ...
        row.gainVsOldOraclePercent, ...
        row.incrementalGainVsPersistentOraclePercent, ...
        row.safetyPassed);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, ...
    ['The temporal upper bound is `%s`. The next opened ', ...
     'training-only method direction is `%s`.\n\n'], ...
    decisionText(summary.temporalUpperBoundRejected), ...
    summary.nextMethodDirection);
fprintf(fid, '## Boundary\n\n%s\n', summary.evidenceBoundary);
end

function text = decisionText(rejected)
if rejected
    text = 'rejected';
else
    text = 'accepted for broader action-space auditing';
end
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behavior', '', ...
    'rankToken', NaN, ...
    'artifactPath', '', ...
    'cccMeanEospa', NaN, ...
    'g1MeanEospa', NaN, ...
    'persistentRankMeanEospa', NaN, ...
    'oldOracleMeanEospa', NaN, ...
    'persistentOracleMeanEospa', NaN, ...
    'temporalOracleMeanEospa', NaN, ...
    'bestOption', '', ...
    'gainVsOldOraclePercent', NaN, ...
    'incrementalGainVsPersistentOraclePercent', NaN, ...
    'refreshesPersistentOracle', false, ...
    'maximumByteDeviationPercent', NaN, ...
    'restartEquivalencePassed', false, ...
    'safetyPassed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
