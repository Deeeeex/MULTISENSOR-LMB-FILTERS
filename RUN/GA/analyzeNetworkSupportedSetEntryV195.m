function [reportPath, result] = ...
        analyzeNetworkSupportedSetEntryV195(scaleName, options)
% ANALYZENETWORKSUPPORTEDSETENTRYV195 Re-evaluate V194 visited states.

if nargin < 2 || isempty(options)
    options = struct();
end
scaleName = upper(char(scaleName));
baseProtocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
entryIdx = find(strcmp({baseProtocol.cases.scaleName}, scaleName), 1);
if isempty(entryIdx)
    error('NetworkSetEntryV195:UnknownScale', ...
        'The requested V99 scale is not registered.');
end
entry = baseProtocol.cases(entryIdx);
if strcmp(scaleName, 'M24')
    currentTime = 104;
else
    currentTime = 72;
end
screenPath = char(getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v194', 'observation_supported_set_safe', ...
    sprintf('%s_seed%d_t%d_h3', ...
        lower(scaleName), entry.seed, currentTime), 'screen', ...
    sprintf( ...
        'TRACKING_ALIGNED_X36_SCHEDULE_H3_%s_SEED%d_T%d_D3.mat', ...
        upper(strrep(entry.presetName, '-', '_')), ...
        entry.seed, currentTime))));
if exist(screenPath, 'file') ~= 2
    error('NetworkSetEntryV195:MissingScreen', ...
        'The paired V194 screen is required.');
end
loaded = load(screenPath, 'screen');
screen = loaded.screen;
names = {screen.records.actionName};
candidateIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), names), 1);
if isempty(candidateIdx) || ...
        ~screen.capturePosteriorSnapshotsEnabled
    error('NetworkSetEntryV195:MissingCandidate', ...
        'The V194 candidate state capture is unavailable.');
end
outcome = screen.outcomes(candidateIdx);
cache = load(screen.cachePath, 'behaviorBundle');
history = cache.behaviorBundle. ...
    preDecisionTopologyHistoryByTime{currentTime};
priorAdjacency = convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
    history.selectedDirectedEdgeHistory);
inputs = generateDynamicTopologyScenarioInputs( ...
    entry.presetName, entry.seed);
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
pageCount = numel(screen.returnTimes);
records = repmat(emptyRecord(), 1, pageCount);
for pageIdx = 1:pageCount
    time = screen.returnTimes(pageIdx);
    fprintf('V195 %s network support page %d/%d: t=%d ...\n', ...
        scaleName, pageIdx, pageCount, time);
    preceding = cat(3, priorAdjacency, ...
        outcome.selectedAdjacency(:, :, 1:max(pageIdx - 1, 0)));
    precedingTimes = [reshape(history.times, 1, []), ...
        screen.returnTimes(1:max(pageIdx - 1, 0))];
    firstHistoryIdx = max(1, size(preceding, 3) - 1);
    preceding = preceding(:, :, firstHistoryIdx:end);
    precedingTimes = precedingTimes(firstHistoryIdx:end);
    context = buildContext(inputs, ...
        outcome.localPosteriorSnapshotsByTime{pageIdx}, time, ...
        preceding, precedingTimes, screen.missingLabelFusionMode);
    [~, control] = computeFormationRoutingLeverageSignature( ...
        context, groupIds);
    metrics = computeNetworkAdditiveFormationRiskV65( ...
        control, context, groupIds, ...
        baseProtocol.positiveSupportThreshold);
    proposal = selectPositiveNetAddressableRiskSetV97( ...
        metrics, baseProtocol);
    receiverOnly = projectObservationSupportedSetSafeV194( ...
        control, context, groupIds, proposal.selectedFormationIds, ...
        baseProtocol.positiveSupportThreshold, struct( ...
            'supportMode', 'receiver-only'));
    networkSupported = projectObservationSupportedSetSafeV194( ...
        control, context, groupIds, proposal.selectedFormationIds, ...
        baseProtocol.positiveSupportThreshold, struct( ...
            'supportMode', 'receiver-or-cross-sender'));
    records(pageIdx) = makeRecord( ...
        time, outcome, pageIdx, proposal, ...
        receiverOnly, networkSupported);
end

result = struct();
result.contractVersion = ...
    'network-supported-set-entry-v195-analysis-v1';
result.generatedAt = datestr(now, 31);
result.scaleName = scaleName;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.screenPath = screenPath;
result.records = records;
result.firstPageDesiredReleasePreserved = ...
    isequal(records(1).networkReleaseFormationIds, ...
        records(1).runtimeReleaseFormationIds);
result.laterFalseReleaseCountReceiverOnly = sum(arrayfun( ...
    @(record) numel(record.receiverReleaseFormationIds), ...
    records(2:end)));
result.laterFalseReleaseCountNetworkSupported = sum(arrayfun( ...
    @(record) numel(record.networkReleaseFormationIds), ...
    records(2:end)));
result.truthUsed = false;
result.futureInformationUsed = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V195 replays the current-observable V194 states already visited in ', ...
    'the paired recursive screen. It changes only the support definition: ', ...
    'an entering label is supported when the receiver or an active ', ...
    'cross-formation reference sender has current measurement association. ', ...
    'No tracking outcome, truth or future information enters the replay.'];
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v195', 'network_supported_set_entry', ...
    lower(scaleName))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, sprintf( ...
    'NETWORK_SUPPORTED_SET_ENTRY_V195_%s.mat', scaleName));
reportPath = fullfile(outputRoot, sprintf( ...
    'NETWORK_SUPPORTED_SET_ENTRY_V195_%s.md', scaleName));
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V195 %s report: %s\n', scaleName, reportPath);
end

function context = buildContext( ...
        inputs, localPosterior, currentTime, ...
        preceding, precedingTimes, receiverMode)
nodeCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = localPosterior;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.triggerConfig.missingLabelFusionMode = receiverMode;
context.currentTime = currentTime;
context.previousAdjacencyHistory = preceding;
context.previousAdjacencyHistoryCount = size(preceding, 3);
context.previousAdjacencyHistoryTimes = precedingTimes;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacencyHistorySource = ...
    'v194-candidate-runtime-posterior-capture';
context.previousAdjacency = preceding(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = inputs.graphData.positions(:, :, currentTime);
context.edgeScores = [];
context.localInnovationHistory = [];
context.localAssociationConfidenceHistory = [];
context.localNisNormHistory = [];
context.localNisDeviationHistory = [];
context.localUpdateHistoryTimes = zeros(1, 0);
context = buildObservableTopologyPolicyContext(context);
end

function record = makeRecord( ...
        time, outcome, pageIdx, proposal, receiverOnly, networkSupported)
record = emptyRecord();
record.currentTime = time;
record.proposedFormationIds = proposal.selectedFormationIds;
record.runtimeRequestedFormationIds = ...
    outcome.retentionDebtRequestedFormationIdsByTime{pageIdx};
record.runtimeSelectedFormationIds = ...
    outcome.retentionDebtSelectedFormationIdsByTime{pageIdx};
record.runtimeReleaseFormationIds = setdiff( ...
    record.runtimeRequestedFormationIds, ...
    record.runtimeSelectedFormationIds, 'stable');
record.receiverReleaseFormationIds = ...
    receiverOnly.releaseFormationIds;
record.networkReleaseFormationIds = ...
    networkSupported.releaseFormationIds;
record.receiverUnsupportedEntryCountByFormation = ...
    receiverOnly.unsupportedEntryCountByFormation;
record.networkUnsupportedEntryCountByFormation = ...
    networkSupported.unsupportedEntryCountByFormation;
record.receiverMaximumRiskByFormation = ...
    receiverOnly.maximumReceiverRiskByFormation;
record.networkMaximumRiskByFormation = ...
    networkSupported.maximumReceiverRiskByFormation;
end

function record = emptyRecord()
record = struct( ...
    'currentTime', NaN, ...
    'proposedFormationIds', zeros(1, 0), ...
    'runtimeRequestedFormationIds', zeros(1, 0), ...
    'runtimeSelectedFormationIds', zeros(1, 0), ...
    'runtimeReleaseFormationIds', zeros(1, 0), ...
    'receiverReleaseFormationIds', zeros(1, 0), ...
    'networkReleaseFormationIds', zeros(1, 0), ...
    'receiverUnsupportedEntryCountByFormation', zeros(1, 0), ...
    'networkUnsupportedEntryCountByFormation', zeros(1, 0), ...
    'receiverMaximumRiskByFormation', zeros(1, 0), ...
    'networkMaximumRiskByFormation', zeros(1, 0));
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkSetEntryV195:WriteFailed', ...
        'Could not create the V195 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V195 %s network-supported set-entry replay\n\n', ...
    result.scaleName);
fprintf(fid, ['| t | V99 proposal | V194 runtime release | ', ...
    'Receiver-only replay | Receiver-or-peer replay |\n']);
fprintf(fid, '|--:|:--|:--|:--|:--|\n');
for record = result.records
    fprintf(fid, '| %d | `%s` | `%s` | `%s` | `%s` |\n', ...
        record.currentTime, ...
        mat2str(record.proposedFormationIds), ...
        mat2str(record.runtimeReleaseFormationIds), ...
        mat2str(record.receiverReleaseFormationIds), ...
        mat2str(record.networkReleaseFormationIds));
end
fprintf(fid, '\n- First-page desired release preserved: `%d`\n', ...
    result.firstPageDesiredReleasePreserved);
fprintf(fid, '- Later receiver-only releases: `%d`\n', ...
    result.laterFalseReleaseCountReceiverOnly);
fprintf(fid, '- Later receiver-or-peer releases: `%d`\n\n', ...
    result.laterFalseReleaseCountNetworkSupported);
fprintf(fid, '## Per-formation risk\n\n');
for record = result.records
    fprintf(fid, '- t=%d receiver count `%s`, network count `%s`\n', ...
        record.currentTime, ...
        mat2str(record. ...
            receiverUnsupportedEntryCountByFormation), ...
        mat2str(record. ...
            networkUnsupportedEntryCountByFormation));
    fprintf(fid, '  receiver risk `%s`, network risk `%s`\n', ...
        mat2str(record.receiverMaximumRiskByFormation, 5), ...
        mat2str(record.networkMaximumRiskByFormation, 5));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

