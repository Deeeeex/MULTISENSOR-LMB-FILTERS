function [reportPath, result] = analyzeLmbCardinalityStabilityV192(options)
% ANALYZELMBCARDINALITYSTABILITYV192 Probe a set-level V99 release gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v192', 'cardinality_stability'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
caseSpecs = { ...
    'M24', 'm24-formation-fov', 211, 104, fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v188', 'base_capture', ...
        'm24_seed211_t104_h3', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H3_', ...
         'M24_FORMATION_FOV_SEED211_T104_D3.mat']); ...
    'X36', 'x36-formation-fov', 211, 72, fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v188', 'base_capture', ...
        'x36_seed211_t72_h3', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H3_', ...
         'X36_FORMATION_FOV_SEED211_T72_D3.mat'])};
records = struct([]);
for caseIdx = 1:size(caseSpecs, 1)
    scaleName = caseSpecs{caseIdx, 1};
    presetName = caseSpecs{caseIdx, 2};
    seed = caseSpecs{caseIdx, 3};
    currentTime = caseSpecs{caseIdx, 4};
    baseScreenPath = caseSpecs{caseIdx, 5};
    entryIdx = find(strcmp({protocol.cases.scaleName}, scaleName), 1);
    if isempty(entryIdx)
        error('CardinalityStabilityV192:MissingCase', ...
            'The V99 case is not registered.');
    end
    fprintf('V192 cardinality stability: %s t=%d ...\n', ...
        scaleName, currentTime);
    if exist(baseScreenPath, 'file') ~= 2
        error('CardinalityStabilityV192:MissingPairedInput', ...
            'The paired V99 base screen is required.');
    end
    loadedScreen = load(baseScreenPath, 'screen');
    cacheRoot = fileparts(loadedScreen.screen.cachePath);
    state = loadFormationH3ObservableState( ...
        presetName, seed, currentTime, struct( ...
            'cacheRoot', cacheRoot, ...
            'expectedMissingLabelFusionMode', protocol.receiverMode));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds);
    metrics = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    selection = selectPositiveNetAddressableRiskSetV97( ...
        metrics, protocol);
    groups = reshape(control.groups, 1, []);
    for formationIdx = 1:numel(groups)
        if ~control.singleActionAvailableMask(formationIdx)
            continue;
        end
        score = control.singleActionScores{formationIdx};
        [risk, stability] = computeLmbCardinalityDecisionStability( ...
            control.referenceScore.networkDetails. ...
                receiverDistributions, ...
            score.networkDetails.receiverDistributions, ...
            state.groupIds);
        record = emptyRecord();
        record.scaleName = scaleName;
        record.presetName = presetName;
        record.seed = seed;
        record.currentTime = currentTime;
        record.formationId = groups(formationIdx);
        record.v99Selected = ismember( ...
            groups(formationIdx), selection.selectedFormationIds);
        record.positiveNet = ...
            metrics.networkRescueFractionByFormation(formationIdx) > ...
                metrics.networkUsefulLossFractionByFormation(formationIdx) + ...
                    protocol.netBenefitTolerance;
        record.networkRescueFraction = ...
            metrics.networkRescueFractionByFormation(formationIdx);
        record.networkUsefulLossFraction = ...
            metrics.networkUsefulLossFractionByFormation(formationIdx);
        record.cardinalityRisk = risk;
        record.mapChangeCount = ...
            stability.formationMapChangeCount(formationIdx);
        record.uncertifiedCount = ...
            stability.formationUncertifiedCount(formationIdx);
        record.minimumStabilitySlack = ...
            stability.formationMinimumStabilitySlack(formationIdx);
        record.maximumPmfInfinityShift = ...
            stability.formationMaximumPmfInfinityShift(formationIdx);
        record.meanCardinalityChange = ...
            stability.formationMeanCardinalityChange(formationIdx);
        members = find(state.groupIds == groups(formationIdx));
        [record.worstReceiverSlack, localIdx] = min( ...
            stability.stabilitySlack(members));
        record.worstReceiver = members(localIdx);
        record.worstReferenceMap = ...
            stability.referenceMapCardinality(record.worstReceiver);
        record.worstCandidateMap = ...
            stability.candidateMapCardinality(record.worstReceiver);
        record.worstReferenceMargin = ...
            stability.referenceMapMargin(record.worstReceiver);
        record.worstPmfShift = ...
            stability.pmfInfinityShift(record.worstReceiver);
        records(end + 1) = record; %#ok<AGROW>
    end
end

result = struct();
result.contractVersion = ...
    'lmb-cardinality-stability-v192-analysis-v1';
result.generatedAt = datestr(now, 31);
result.records = records;
result.truthUsedForFeatures = false;
result.futureInformationUsedForFeatures = false;
result.teacherOutcomeUsedForSelection = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V192 computes an exact outcome-marginal LMB cardinality PMF from ', ...
    'the current observable routing surrogate.  The MAP certificate is ', ...
    'sufficient but not necessary and does not claim that the full-payload ', ...
    'reference is correct.  Opened M24/X36 anchors are development-only.'];
matPath = fullfile(outputRoot, ...
    'LMB_CARDINALITY_STABILITY_V192.mat');
reportPath = fullfile(outputRoot, ...
    'LMB_CARDINALITY_STABILITY_V192.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V192 report: %s\n', reportPath);
end

function record = emptyRecord()
record = struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'formationId', NaN, ...
    'v99Selected', false, 'positiveNet', false, ...
    'networkRescueFraction', NaN, ...
    'networkUsefulLossFraction', NaN, ...
    'cardinalityRisk', NaN, 'mapChangeCount', NaN, ...
    'uncertifiedCount', NaN, 'minimumStabilitySlack', NaN, ...
    'maximumPmfInfinityShift', NaN, ...
    'meanCardinalityChange', NaN, 'worstReceiver', NaN, ...
    'worstReceiverSlack', NaN, 'worstReferenceMap', NaN, ...
    'worstCandidateMap', NaN, 'worstReferenceMargin', NaN, ...
    'worstPmfShift', NaN);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CardinalityStabilityV192:WriteFailed', ...
        'Could not create the V192 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V192 observable LMB cardinality-stability probe\n\n');
fprintf(fid, ['A positive stability slack certifies that the candidate ', ...
    'keeps the reference MAP cardinality.  A non-positive value only ', ...
    'means that the sufficient certificate failed.\n\n']);
fprintf(fid, ['| Scale | F | V99 | Positive net | Rescue | Useful loss | ', ...
    'MAP changes | Uncertified | Min slack | Worst receiver | ', ...
    'Ref -> cand MAP | Ref margin | PMF shift | Mean card. delta |\n']);
fprintf(fid, ['|:--|--:|:--:|:--:|--:|--:|--:|--:|--:|--:|:--|--:|', ...
    '--:|--:|\n']);
for record = result.records
    fprintf(fid, ['| %s | %d | %d | %d | %.3f%% | %.3f%% | %d | %d | ', ...
        '%+.6f | %d | %d -> %d | %.6f | %.6f | %+.4f |\n'], ...
        record.scaleName, record.formationId, record.v99Selected, ...
        record.positiveNet, 100 * record.networkRescueFraction, ...
        100 * record.networkUsefulLossFraction, ...
        record.mapChangeCount, record.uncertifiedCount, ...
        record.minimumStabilitySlack, record.worstReceiver, ...
        record.worstReferenceMap, record.worstCandidateMap, ...
        record.worstReferenceMargin, record.worstPmfShift, ...
        record.meanCardinalityChange);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
