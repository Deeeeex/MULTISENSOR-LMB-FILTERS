function [reportPath, result] = ...
        runFormationGraphActionBankPreflightV208(options)
% RUNFORMATIONGRAPHACTIONBANKPREFLIGHTV208 Check causal action coverage.
%
% Rebuild the supported-label candidate bank on the captured V99 trajectory
% and apply the V208 diverse truth-free shortlist.  The five later V206
% teacher keys are used only as an offline coverage readout; they do not
% affect candidate construction or ranking.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v197', 'base_capture', ...
    'x36_seed211_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v208', 'formation_action_bank_preflight', ...
    'x36_seed211_t72_h8'));
maximumPerCriterion = getField( ...
    options, 'maximumPerCriterion', 2);
receiverPresenceThreshold = getField( ...
    options, 'receiverPresenceThreshold', 1e-2);
minimumRiskReductionThreshold = getField( ...
    options, 'minimumRiskReductionThreshold', -1);
if exist(screenPath, 'file') ~= 2
    error('FormationActionBankV208:MissingScreen', ...
        'The captured V99 H=8 screen is required.');
end

loaded = load(screenPath, 'screen');
screen = loaded.screen;
candidateOutcomeIdx = find(strncmp( ...
    {screen.records.actionName}, ...
    'v99-online-positive-net-', 24));
if numel(candidateOutcomeIdx) ~= 1
    error('FormationActionBankV208:CandidateOutcome', ...
        'The captured V99 outcome is missing or ambiguous.');
end
outcome = screen.outcomes(candidateOutcomeIdx);
pageCount = numel(screen.returnTimes);
if numel(outcome.fusedPosteriorSnapshotsByTime) ~= pageCount || ...
        numel(outcome.localPosteriorSnapshotsByTime) ~= pageCount || ...
        numel(outcome.retentionDebtSelectedFormationIdsByTime) ~= ...
            pageCount
    error('FormationActionBankV208:MissingSnapshots', ...
        'Every V99 page requires fused/local snapshots and route state.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
runtimeModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
groupIds = reshape(screen.sensorGroupIds, 1, []);
teacher = teacherKeys();
records = repmat(emptyRecord(), 1, pageCount);
allFeatureNames = cell(1, 0);
for pageIdx = 1:pageCount
    currentTime = screen.returnTimes(pageIdx);
    fprintf('V208 action bank page %d/%d: t=%d ...\n', ...
        pageIdx, pageCount, currentTime);
    fused = outcome.fusedPosteriorSnapshotsByTime{pageIdx};
    local = outcome.localPosteriorSnapshotsByTime{pageIdx};
    physical = logical(inputs.graphData. ...
        physicalAdjacency(:, :, currentTime));
    physical = physical | physical';
    physical(1:numel(groupIds)+1:end) = false;
    cache = buildFormationRepairLightSynopsisCacheV188( ...
        fused, local, runtimeModel, currentTime, struct());
    [candidates, fullDetails] = ...
        enumerateFormationCommonLabelRepairCandidatesV190( ...
            cache, physical, groupIds, struct( ...
                'receiverPresenceThreshold', ...
                    receiverPresenceThreshold, ...
                'minimumRiskReductionThreshold', ...
                    minimumRiskReductionThreshold));
    [shortlisted, shortlistDetails] = ...
        shortlistFormationLabelActionCandidatesV208( ...
            candidates, struct( ...
                'maximumPerCriterion', maximumPerCriterion));
    if isempty(allFeatureNames)
        allFeatureNames = shortlistDetails.featureNames;
    elseif ~isempty(shortlistDetails.featureNames) && ...
            ~isequal(allFeatureNames, shortlistDetails.featureNames)
        error('FormationActionBankV208:FeatureDrift', ...
            'The shortlist feature contract changed between pages.');
    end
    teacherIdx = find([teacher.time] == currentTime, 1);
    fullTeacherPresent = NaN;
    shortlistTeacherPresent = NaN;
    teacherFormation = NaN;
    teacherSource = NaN;
    teacherLabel = [NaN; NaN];
    if ~isempty(teacherIdx)
        key = teacher(teacherIdx);
        teacherFormation = key.formationId;
        teacherSource = key.sourceId;
        teacherLabel = key.label;
        fullTeacherPresent = any(matchesKey(candidates, key));
        shortlistTeacherPresent = any(matchesKey(shortlisted, key));
    end
    record = emptyRecord();
    record.page = pageIdx;
    record.currentTime = currentTime;
    record.fullCandidateCount = numel(candidates);
    record.shortlistedCandidateCount = numel(shortlisted);
    record.releaseCandidateFormationIds = reshape( ...
        outcome.retentionDebtSelectedFormationIdsByTime{pageIdx}, ...
        1, []);
    record.releaseCandidateCount = ...
        numel(record.releaseCandidateFormationIds);
    record.teacherFormationId = teacherFormation;
    record.teacherSourceId = teacherSource;
    record.teacherLabel = teacherLabel;
    record.fullTeacherPresent = fullTeacherPresent;
    record.shortlistTeacherPresent = shortlistTeacherPresent;
    record.fullCountByFormation = ...
        fullDetails.candidateCountByFormation;
    record.shortlistedCountByFormation = ...
        shortlistDetails.shortlistedCountByFormation;
    records(pageIdx) = record;
end

teacherMask = isfinite([records.fullTeacherPresent]);
fullCoverage = mean([records(teacherMask).fullTeacherPresent]);
shortlistCoverage = mean( ...
    [records(teacherMask).shortlistTeacherPresent]);
result = struct();
result.contractVersion = ...
    'formation-graph-action-bank-preflight-v208-v1';
result.generatedAt = datestr(now, 31);
result.screenPath = screenPath;
result.presetName = screen.presetName;
result.seed = screen.seed;
result.returnTimes = screen.returnTimes;
result.maximumPerCriterion = maximumPerCriterion;
result.receiverPresenceThreshold = receiverPresenceThreshold;
result.minimumRiskReductionThreshold = ...
    minimumRiskReductionThreshold;
result.featureNames = allFeatureNames;
result.records = records;
result.teacherKeyCount = nnz(teacherMask);
result.fullTeacherCoverageFraction = fullCoverage;
result.shortlistTeacherCoverageFraction = shortlistCoverage;
result.meanFullCandidateCount = mean([records.fullCandidateCount]);
result.meanShortlistedCandidateCount = ...
    mean([records.shortlistedCandidateCount]);
result.compressionFraction = ...
    result.meanShortlistedCandidateCount / ...
        result.meanFullCandidateCount;
result.truthUsedForCandidateConstruction = false;
result.futureInformationUsedForCandidateConstruction = false;
result.numericLabelIdentifiersUsedAsFeatures = false;
result.numericSourceIdentifiersUsedAsFeatures = false;
result.teacherKeysUsedForCoverageReadoutOnly = true;
result.preflightPassed = ...
    shortlistCoverage >= 1 - 1e-12;
result.evidenceBoundary = [ ...
    'V208 reconstructs truth-free supported-label candidates on the ', ...
    'already opened X36 seed-211 V99 trajectory. The five later V206 ', ...
    'teacher routing keys are read only after shortlisting to measure ', ...
    'action-space coverage. This is a development search-space preflight, ', ...
    'not a value-model, recursive policy, held-out, or performance result.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_GRAPH_ACTION_BANK_V208_PREFLIGHT.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_GRAPH_ACTION_BANK_V208_PREFLIGHT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V208 action-bank preflight: %s\n', reportPath);
end

function mask = matchesKey(candidates, key)
if isempty(candidates)
    mask = false(1, 0);
    return;
end
mask = [candidates.formationId] == key.formationId & ...
    [candidates.sourceId] == key.sourceId & ...
    arrayfun(@(candidate) ...
        isequal(candidate.label, key.label), candidates);
end

function teacher = teacherKeys()
teacher = repmat(struct( ...
    'time', 0, 'formationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1)), 1, 5);
times = [72, 73, 76, 77, 78];
formations = [2, 6, 3, 1, 3];
sources = [19, 19, 23, 13, 23];
labels = [13, 7, 19, 7, 19; ...
          12, 5, 13, 7, 13];
for idx = 1:numel(teacher)
    teacher(idx).time = times(idx);
    teacher(idx).formationId = formations(idx);
    teacher(idx).sourceId = sources(idx);
    teacher(idx).label = labels(:, idx);
end
end

function record = emptyRecord()
record = struct( ...
    'page', 0, 'currentTime', 0, ...
    'fullCandidateCount', 0, ...
    'shortlistedCandidateCount', 0, ...
    'releaseCandidateFormationIds', zeros(1, 0), ...
    'releaseCandidateCount', 0, ...
    'teacherFormationId', NaN, ...
    'teacherSourceId', NaN, ...
    'teacherLabel', [NaN; NaN], ...
    'fullTeacherPresent', NaN, ...
    'shortlistTeacherPresent', NaN, ...
    'fullCountByFormation', zeros(1, 0), ...
    'shortlistedCountByFormation', zeros(1, 0));
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FormationActionBankV208:ReportOpenFailed', ...
        'Could not open the V208 preflight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V208 formation-graph action-bank preflight\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Full / shortlist mean candidate count: `%.1f / %.1f`\n', ...
    result.meanFullCandidateCount, ...
    result.meanShortlistedCandidateCount);
fprintf(fid, '- Retained candidate fraction: `%.3f%%`\n', ...
    100 * result.compressionFraction);
fprintf(fid, ['- V206 teacher-key coverage, full / shortlist: ', ...
    '`%.1f%% / %.1f%%`\n'], ...
    100 * result.fullTeacherCoverageFraction, ...
    100 * result.shortlistTeacherCoverageFraction);
fprintf(fid, '- Preflight passed: `%d`\n\n', result.preflightPassed);
fprintf(fid, ['| Time | Full label actions | Shortlisted | ', ...
    'Release candidates | Teacher key | Full | Shortlist |\n']);
fprintf(fid, '|--:|--:|--:|:--|:--|:--:|:--:|\n');
for record = reshape(result.records, 1, [])
    releaseText = vectorText(record.releaseCandidateFormationIds);
    if isfinite(record.teacherFormationId)
        teacherText = sprintf('F%d / S%d / [%d,%d]', ...
            record.teacherFormationId, record.teacherSourceId, ...
            record.teacherLabel(1), record.teacherLabel(2));
        fullText = sprintf('%d', logical(record.fullTeacherPresent));
        shortlistText = sprintf('%d', ...
            logical(record.shortlistTeacherPresent));
    else
        teacherText = '--';
        fullText = '--';
        shortlistText = '--';
    end
    fprintf(fid, '| %d | %d | %d | `%s` | `%s` | %s | %s |\n', ...
        record.currentTime, record.fullCandidateCount, ...
        record.shortlistedCandidateCount, releaseText, ...
        teacherText, fullText, shortlistText);
end
fprintf(fid, '\n## Decision\n\n');
if result.preflightPassed
    fprintf(fid, ['The bounded diverse union preserves every later V206 ', ...
        'teacher key on the base V99 trajectory.  The action block may ', ...
        'advance to counterfactual value generation.\n']);
else
    fprintf(fid, ['The bounded diverse union misses at least one later ', ...
        'V206 teacher key.  Value-model training is not authorized until ', ...
        'candidate coverage is repaired.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = vectorText(values)
values = reshape(values, 1, []);
if isempty(values)
    value = 'none';
else
    value = strtrim(sprintf('%d ', values));
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
