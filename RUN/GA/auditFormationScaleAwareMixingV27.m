function [reportPath, audit] = ...
    auditFormationScaleAwareMixingV27(options)
% AUDITFORMATIONSCALEAWAREMIXINGV27 Deterministic v27 mechanism audit.
%
% This audit reads only the frozen opened-state v27 screen.  It verifies
% provenance, separates topology support from fusion-weight changes, and
% checks whether lower posterior disagreement coincides with worse
% cardinality and tracking.  It does not open another tracking state.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v27', 'scale_aware_residual_mixing', ...
    't72', 'screen', ...
    ['FORMATION_SCALE_AWARE_MIXING_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_SCALE_AWARE_RESIDUAL_MIXING_V27_', ...
     'AUDIT_20260802.md']));
expectedCommit = getField(options, 'expectedGenerationCommit', ...
    '9d9fc7e003a868f688718061aac5c01eebb0b78d');
expectedCacheSha256 = getField(options, 'expectedCacheSha256', ...
    ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
     '85b79042bfaf762']);

if exist(screenPath, 'file') ~= 2
    error('V27Audit:MissingScreen', ...
        'Frozen v27 screen is unavailable: %s', screenPath);
end
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V27Audit:InvalidScreen', ...
        'Frozen v27 MAT does not contain screen.');
end
screen = loaded.screen;
assertScreenContract( ...
    screen, expectedCommit, expectedCacheSha256);

records = screen.records;
outcomes = screen.outcomes;
bank = screen.bank;
actionCount = numel(records);
referenceRecordIndex = screen.referenceSubsetIndex;
referenceActionIndex = records(referenceRecordIndex).actionIndex;
if actionCount ~= bank.actionCount || ...
        numel(outcomes) ~= actionCount || ...
        referenceActionIndex ~= bank.referenceActionIndex || ...
        any([records.actionIndex] ~= 1:actionCount)
    error('V27Audit:InvalidScreen', ...
        'Frozen v27 action ordering is inconsistent.');
end

adjacencyEqualToReference = false(1, actionCount);
maximumWeightDifferenceFromReference = zeros(1, actionCount);
referenceAdjacency = bank.actionAdjacency(:, :, referenceActionIndex);
referenceWeights = bank.actionFusionWeights(:, :, referenceActionIndex);
for actionIdx = 1:actionCount
    adjacencyEqualToReference(actionIdx) = isequal( ...
        bank.actionAdjacency(:, :, actionIdx), referenceAdjacency);
    currentWeights = bank.actionFusionWeights(:, :, actionIdx);
    maximumWeightDifferenceFromReference(actionIdx) = max(abs( ...
        currentWeights(:) - ...
        referenceWeights(:)));
end

mixingGap = reshape( ...
    bank.actionFormationMixingSpectralGapProxy, 1, []);
meanGainPercent = [records.meanGainPercent];
worstGainPercent = [records.worstGainPercent];
minimumFormationGainPercent = ...
    [records.minimumFormationGainPercent];
windowConsensusGainPercent = [records.consensusGainPercent];
terminalConsensusGainPercent = ...
    [records.terminalConsensusGainPercent];
attemptedByteSavingPercent = ...
    [records.attemptedByteSavingPercent];
meanCardinalityError = [outcomes.meanCardinalityError];
posteriorDisagreement = [outcomes.posteriorConsensus];
positionDisagreement = [outcomes.consensusPosition];
cardinalityDispersion = [outcomes.consensusCardinality];
deliveredBytes = [outcomes.deliveredBytes];

nonreferenceMask = true(1, actionCount);
nonreferenceMask(referenceRecordIndex) = false;
trackingLossPercent = -meanGainPercent;
windowConsensusLossPercent = -windowConsensusGainPercent;
mixingTrackingLossCorrelation = pearsonCorrelation( ...
    mixingGap(nonreferenceMask), ...
    trackingLossPercent(nonreferenceMask));
mixingConsensusLossCorrelation = pearsonCorrelation( ...
    mixingGap(nonreferenceMask), ...
    windowConsensusLossPercent(nonreferenceMask));

posteriorAgreementImprovedMask = posteriorDisagreement < ...
    posteriorDisagreement(referenceRecordIndex) - 1e-12;
cardinalityErrorWorsenedMask = meanCardinalityError > ...
    meanCardinalityError(referenceRecordIndex) + 1e-12;
agreementCardinalitySplitMask = nonreferenceMask & ...
    posteriorAgreementImprovedMask & cardinalityErrorWorsenedMask;

referenceEospaByTime = mean( ...
    outcomes(referenceRecordIndex).eospaBySensorTime, 1);
meanEospaByTime = zeros(actionCount, numel(referenceEospaByTime));
meanGainByTimePercent = zeros(size(meanEospaByTime));
for actionIdx = 1:actionCount
    meanEospaByTime(actionIdx, :) = mean( ...
        outcomes(actionIdx).eospaBySensorTime, 1);
    meanGainByTimePercent(actionIdx, :) = 100 * ...
        (referenceEospaByTime - meanEospaByTime(actionIdx, :)) ./ ...
        max(referenceEospaByTime, eps);
end

sameGraphWeightOnlyIndices = find(adjacencyEqualToReference & ...
    maximumWeightDifferenceFromReference > 1e-12);
sameGraphWeightOnlyFailurePassed = ...
    isequal(sameGraphWeightOnlyIndices, [2, 3]) && ...
    all(meanGainPercent(sameGraphWeightOnlyIndices) < 0) && ...
    all(windowConsensusGainPercent( ...
        sameGraphWeightOnlyIndices) < 0) && ...
    all(meanGainByTimePercent( ...
        sameGraphWeightOnlyIndices, 1) < 0);
if ~sameGraphWeightOnlyFailurePassed || ...
        mixingTrackingLossCorrelation < 0.80 || ...
        mixingConsensusLossCorrelation < 0.80 || ...
        nnz(agreementCardinalitySplitMask) ~= actionCount - 1 || ...
        screen.strictStrongCandidateCount ~= 0
    error('V27Audit:MechanismCheckFailed', ...
        'Frozen v27 screen no longer satisfies the registered audit.');
end

audit = struct();
audit.contractVersion = ...
    'formation-scale-aware-mixing-v27-mechanism-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceScreenContractVersion = screen.contractVersion;
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.returnTimes = screen.returnTimes;
audit.actionNames = bank.actionNames;
audit.adjacencyEqualToReference = adjacencyEqualToReference;
audit.maximumWeightDifferenceFromReference = ...
    maximumWeightDifferenceFromReference;
audit.mixingGap = mixingGap;
audit.meanGainPercent = meanGainPercent;
audit.worstGainPercent = worstGainPercent;
audit.minimumFormationGainPercent = ...
    minimumFormationGainPercent;
audit.windowConsensusGainPercent = windowConsensusGainPercent;
audit.terminalConsensusGainPercent = ...
    terminalConsensusGainPercent;
audit.attemptedByteSavingPercent = ...
    attemptedByteSavingPercent;
audit.meanCardinalityError = meanCardinalityError;
audit.posteriorDisagreement = posteriorDisagreement;
audit.positionDisagreement = positionDisagreement;
audit.cardinalityDispersion = cardinalityDispersion;
audit.deliveredBytes = deliveredBytes;
audit.meanGainByTimePercent = meanGainByTimePercent;
audit.sameGraphWeightOnlyIndices = sameGraphWeightOnlyIndices;
audit.sameGraphWeightOnlyFailurePassed = ...
    sameGraphWeightOnlyFailurePassed;
audit.mixingTrackingLossCorrelation = ...
    mixingTrackingLossCorrelation;
audit.mixingConsensusLossCorrelation = ...
    mixingConsensusLossCorrelation;
audit.agreementCardinalitySplitMask = ...
    agreementCardinalitySplitMask;
audit.agreementCardinalitySplitCount = ...
    nnz(agreementCardinalitySplitMask);
audit.strictStrongCandidateCount = ...
    screen.strictStrongCandidateCount;
audit.truthUsedForActionConstruction = false;
audit.truthUsedForOutcomeScoring = true;
audit.futureOutcomeUsedForActionConstruction = false;
audit.newTrackingStateOpened = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.gnnTrainingAuthorized = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This deterministic audit reuses one already-opened M24 state. ', ...
    'Outcome correlations diagnose a mechanism but do not establish ', ...
    'generalization. The identical-adjacency weight intervention is ', ...
    'stronger within-state evidence, yet fresh multi-state gates are ', ...
    'still required before training or validation.'];

writeReport(reportPath, audit, screen);
fprintf('V27 formation-mixing mechanism audit: %s\n', reportPath);
end

function assertScreenContract(screen, expectedCommit, expectedCacheSha256)
required = {'contractVersion', 'generationGitCommit', ...
    'cacheSha256', 'presetName', 'seed', 'currentTime', ...
    'returnTimes', 'bank', 'records', 'outcomes', ...
    'referenceSubsetIndex', 'strictStrongCandidateCount'};
if ~isstruct(screen) || any(~isfield(screen, required)) || ...
        ~strcmp(screen.contractVersion, ...
            'formation-scale-aware-residual-mixing-v27-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, expectedCommit) || ...
        ~strcmp(screen.cacheSha256, expectedCacheSha256) || ...
        ~strcmp(screen.presetName, 'm24-formation-fov') || ...
        screen.seed ~= 211 || screen.currentTime ~= 72 || ...
        ~isequal(screen.returnTimes, [72, 73, 74]) || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized
    error('V27Audit:ProvenanceMismatch', ...
        'Frozen v27 screen provenance or evidence boundary changed.');
end
end

function correlation = pearsonCorrelation(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
if numel(left) ~= numel(right) || numel(left) < 2 || ...
        any(~isfinite(left)) || any(~isfinite(right))
    error('V27Audit:InvalidCorrelationInput', ...
        'Pearson-correlation inputs are invalid.');
end
left = left - mean(left);
right = right - mean(right);
denominator = sqrt(sum(left.^2) * sum(right.^2));
if denominator <= eps
    error('V27Audit:DegenerateCorrelationInput', ...
        'Pearson-correlation input has zero variance.');
end
correlation = sum(left .* right) / denominator;
end

function writeReport(path, audit, screen)
fid = fopen(path, 'w');
if fid < 0
    error('V27Audit:WriteFailed', ...
        'Could not open v27 audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, '# V27 scale-aware residual mixing audit\n\n');
fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    '**Reject global formation-mixing acceleration as the next method ', ...
    'direction.** The frozen primary screen found `0/10` strong ', ...
    'nonreference actions. No additional v27 M24 state, X36/X48 ', ...
    'outcome, or GNN training is authorized.\n\n']);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source screen: `%s`\n', audit.sourceScreenPath);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Cache SHA-256: `%s`\n', audit.sourceCacheSha256);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime);
fprintf(fid, '- Return times: `%s`\n', mat2str(audit.returnTimes));
fprintf(fid, '- New tracking state opened by this audit: `0`\n\n');

fprintf(fid, '## What the intervention shows\n\n');
fprintf(fid, [ ...
    'Actions 1, 2, and 3 have exactly the same directed adjacency and ', ...
    'the same 40-message budget. Only the cross-formation residual ', ...
    'weight changes from 0.05 to 0.10 and 0.15. Therefore the losses ', ...
    'of actions 2 and 3 cannot be attributed to adding edges, changing ', ...
    'message count, or selecting a different gateway graph.\n\n']);
fprintf(fid, [ ...
    '| Action | Same adjacency | Max weight change | Mix gap | ', ...
    'Mean gain | Window consensus gain | First-step gain |\n']);
fprintf(fid, '|:--|:--:|--:|--:|--:|--:|--:|\n');
for actionIdx = 1:3
    fprintf(fid, [ ...
        '| `%s` | %d | %.3f | %.6f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% |\n'], ...
        audit.actionNames{actionIdx}, ...
        audit.adjacencyEqualToReference(actionIdx), ...
        audit.maximumWeightDifferenceFromReference(actionIdx), ...
        audit.mixingGap(actionIdx), ...
        audit.meanGainPercent(actionIdx), ...
        audit.windowConsensusGainPercent(actionIdx), ...
        audit.meanGainByTimePercent(actionIdx, 1));
end

fprintf(fid, '\n## Agreement is not correctness\n\n');
fprintf(fid, [ ...
    'Every nonreference action lowers the moment-summary posterior ', ...
    'disagreement, yet every one increases mean cardinality error. ', ...
    'The sensors become more similar to each other while becoming ', ...
    'jointly worse at deciding how many labels exist.\n\n']);
fprintf(fid, [ ...
    '| Action | Posterior disagreement | Position disagreement | ', ...
    'Mean cardinality error | Cardinality dispersion | Delivered bytes |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|\n');
for actionIdx = 1:numel(audit.actionNames)
    fprintf(fid, '| `%s` | %.6f | %.6f | %.6f | %.6f | %.0f |\n', ...
        audit.actionNames{actionIdx}, ...
        audit.posteriorDisagreement(actionIdx), ...
        audit.positionDisagreement(actionIdx), ...
        audit.meanCardinalityError(actionIdx), ...
        audit.cardinalityDispersion(actionIdx), ...
        audit.deliveredBytes(actionIdx));
end
fprintf(fid, '\n- Posterior-agreement/cardinality split: `%d/%d` ', ...
    audit.agreementCardinalitySplitCount, ...
    numel(audit.actionNames) - 1);
fprintf(fid, 'nonreference actions.\n');
fprintf(fid, [ ...
    '- Mixing gap versus mean tracking loss, Pearson `r = %.6f`.\n', ...
    '- Mixing gap versus window-consensus loss, Pearson `r = %.6f`.\n'], ...
    audit.mixingTrackingLossCorrelation, ...
    audit.mixingConsensusLossCorrelation);
fprintf(fid, [ ...
    'These correlations are diagnostic associations within one opened ', ...
    'state, not generalization claims.\n\n']);

fprintf(fid, '## Why the existing posterior-risk score is insufficient\n\n');
fprintf(fid, [ ...
    'For a Bernoulli label, the current proxy is\n\n', ...
    '`min(r, (1-r) + r v)`, where `v = min(trace(P)/c^2, 1)`.\n\n', ...
    'When KLA conflict suppresses `r`, the empty-set term `r` also ', ...
    'shrinks. The score can therefore reward deleting a reference-', ...
    'supported label. It measures internal decision confidence, not an ', ...
    'explicit guarantee that plausible reference labels are retained. ', ...
    'The v27 structural bank did not use this proxy. A later post-hoc ', ...
    're-score does assign a small negative Bayes-risk advantage to every ', ...
    'v27 candidate, so it would be inaccurate to say that the proxy ', ...
    'missed the direction in this particular state. Its mathematical ', ...
    'blind spot and the earlier cross-state v10 instability nevertheless ', ...
    'mean it cannot serve as the required retention certificate. V27 ', ...
    'also shows that a disagreement guard cannot replace that certificate: ', ...
    'agreement can improve while all nodes move toward the same wrong ', ...
    'cardinality.\n\n']);

fprintf(fid, '## KLA mechanism and v28 requirement\n\n');
fprintf(fid, [ ...
    'For label `ell`, Bernoulli KLA gives\n\n', ...
    '`logit(r_bar_ell) = sum_i omega_i logit(r_i,ell) + log(eta_ell)`,\n\n', ...
    'with `eta_ell = integral prod_i p_i,ell(x)^omega_i dx <= 1`. ', ...
    'Spatial conflict makes `log(eta_ell)` negative and can suppress ', ...
    'existence below pruning or MAP thresholds. Stronger mixing is ', ...
    'therefore beneficial only when its contraction gain exceeds this ', ...
    'endogenous conflict disturbance.\n\n']);
fprintf(fid, [ ...
    'V28 must keep a hard connectivity floor but change the action from ', ...
    'global acceleration to **conflict-aware selective mixing**. Each ', ...
    'candidate must be compared with the reference using current ', ...
    'posteriors and must pass label-existence-retention/cardinality-risk ', ...
    'constraints before any disagreement or spectral-gap objective can ', ...
    'rank it. Extra cross trust may be assigned only to compatible or ', ...
    'complementary formation pairs; incompatible pairs must retain or ', ...
    'reduce reference trust.\n\n']);

fprintf(fid, '## Full frozen outcome table\n\n');
fprintf(fid, [ ...
    '| Action | Mix gap | Mean gain | Worst gain | Min formation | ', ...
    'Window consensus | Final consensus | Byte saving | Strong |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for actionIdx = 1:numel(audit.actionNames)
    fprintf(fid, [ ...
        '| `%s` | %.6f | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        audit.actionNames{actionIdx}, audit.mixingGap(actionIdx), ...
        audit.meanGainPercent(actionIdx), ...
        audit.worstGainPercent(actionIdx), ...
        audit.minimumFormationGainPercent(actionIdx), ...
        audit.windowConsensusGainPercent(actionIdx), ...
        audit.terminalConsensusGainPercent(actionIdx), ...
        audit.attemptedByteSavingPercent(actionIdx), ...
        screen.strictStrongMask(actionIdx));
end

fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
