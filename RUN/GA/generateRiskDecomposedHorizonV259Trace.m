function [reportPath, result] = ...
        generateRiskDecomposedHorizonV259Trace(options)
% GENERATERISKDECOMPOSEDHORIZONV259TRACE Passive full V242 risk trace.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRiskDecomposedHorizonV259Protocol();
presetName = char(getField(options, 'presetName', ...
    protocol.allowedPresets{1}));
seed = getField(options, 'seed', protocol.allowedSeeds(1));
referenceResultPath = char(getField(options, ...
    'referenceResultPath', ''));
resume = logical(getField(options, 'resume', true));
if ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds) || ...
        isempty(referenceResultPath) || ...
        ~islogical(resume) || ~isscalar(resume)
    error('RiskDecomposedV259:InvalidTraceRequest', ...
        'V259 requires its registered M24 case and V248 result.');
end
if exist(referenceResultPath, 'file') ~= 2
    error('RiskDecomposedV259:MissingReference', ...
        'The completed V248 reference result does not exist.');
end

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('RiskDecomposedV259:DirtyTraceSource', ...
        'Official V259 trace generation requires clean source.');
end
referenceEnvelope = load(referenceResultPath, 'result');
reference = referenceEnvelope.result;
validateReference(reference, presetName, seed);

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v259', 'risk_decomposed_horizon', ...
    sprintf('m24_seed%d_passive_trace', seed))));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7, mkdir(outputRoot); end
matPath = fullfile(outputRoot, ...
    'RISK_DECOMPOSED_HORIZON_V259_PASSIVE_TRACE.mat');
reportPath = fullfile(outputRoot, ...
    'RISK_DECOMPOSED_HORIZON_V259_PASSIVE_TRACE.md');
if resume && exist(matPath, 'file') == 2
    loaded = load(matPath, 'result');
    if isfield(loaded, 'result') && isComplete(loaded.result) && ...
            strcmp(loaded.result.generationGitCommit, gitState.commit) && ...
            strcmp(loaded.result.referenceResultPath, referenceResultPath)
        result = loaded.result;
        writeReport(reportPath, result);
        fprintf('Reused completed V259 trace: %s\n', reportPath);
        return;
    end
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
timeCount = inputs.config.simulationLength;
filterModel = removeRealizedTargetTruthFromDynamicTopologyModel( ...
    inputs.model);
config = buildCausalMinimumFormationBackboneV242Config(inputs.config);
config.topologyPosteriorCaptureTimes = 1:timeCount;
context = buildCausalMinimumFormationBackboneV242ExecutionContext( ...
    presetName, seed, timeCount);
rng(seed + protocol.filterSeedOffset, 'twister');
fprintf('\nV259 passive V242 risk trace: %s seed %d\n', ...
    presetName, seed);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    filterModel, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
elapsedSeconds = toc(timerId);

representatives = selectFormationRepresentativesLocal( ...
    inputs.config.sensorGroupIds);
metricWindow = struct( ...
    'activationStartTime', inputs.config.focusWindow(1), ...
    'activationEndTime', inputs.config.focusWindow(end));
arm = summarizeRepeatedMultiGatewayFullEpisodeArm( ...
    protocol.referenceArmId, estimates, diagnostics, ...
    inputs.groundTruthRfs, inputs.config, representatives, ...
    metricWindow, elapsedSeconds);
arm = attachRouteSummary(arm, diagnostics, inputs.config);
assertPassiveRuntime(arm, diagnostics, inputs.config);
passiveComparison = comparePassiveArm( ...
    arm, reference.minimumBackbone);
if ~passiveComparison.exactOutcomeReproductionPassed
    error('RiskDecomposedV259:PassiveCaptureChangedOutcome', ...
        'Posterior capture changed the deterministic V242 outcome.');
end

[riskTrace, riskSummaries] = buildRiskTrace( ...
    diagnostics.topologyLocalPosteriorSnapshot, ...
    inputs.config.sensorGroupIds, filterModel, protocol, timeCount);
contract = behaviorContinuationCacheContract();
behaviorConfig = config;
if isfield(behaviorConfig, 'topologyPolicyFcn')
    behaviorConfig = rmfield(behaviorConfig, 'topologyPolicyFcn');
end
behaviorBundle = struct( ...
    'cacheContractVersion', contract.version, ...
    'posteriorSnapshotConvention', ...
        contract.posteriorSnapshotConvention, ...
    'topologyHistoryDepth', contract.topologyHistoryDepth, ...
    'topologyHistoryConvention', ...
        contract.topologyHistoryConvention, ...
    'protocolId', protocol.id, ...
    'sourcePolicyProtocolId', protocol.sourceProtocolId, ...
    'presetName', presetName, 'seed', seed, ...
    'snapshotTimes', 1:timeCount, ...
    'maximumTime', timeCount, ...
    'configSnapshot', inputs.config, ...
    'behaviorConfigSnapshot', behaviorConfig, ...
    'behaviorSeconds', elapsedSeconds, ...
    'posteriorSnapshots', ...
        {diagnostics.topologyLocalPosteriorSnapshot}, ...
    'preDecisionTopologyHistoryByTime', ...
        {buildBehaviorContinuationHistoryRecords( ...
            diagnostics, 1:timeCount, contract.topologyHistoryDepth)}, ...
    'generationGitCommit', gitState.commit, ...
    'referenceArmName', protocol.referenceArmId, ...
    'policyTruthUsed', false, ...
    'policyFutureOutcomeUsed', false, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'evidenceBoundary', protocol.evidenceBoundary);

result = struct();
result.contractVersion = ...
    'risk-decomposed-horizon-v259-passive-trace-result-v1';
result.protocolId = protocol.id;
result.protocol = protocol;
result.generationGitCommit = gitState.commit;
result.generatedAt = datestr(now, 31);
result.presetName = presetName;
result.seed = seed;
result.referenceResultPath = referenceResultPath;
result.referenceGenerationGitCommit = ...
    reference.generationGitCommit;
result.passiveArm = arm;
result.passiveComparison = passiveComparison;
result.riskTrace = riskTrace;
result.riskSummaries = riskSummaries;
result.behaviorBundleStoredAlongsideResult = true;
result.completed = true;
result.developmentEvidenceOnly = true;
result.validationClaimAllowed = false;
result.matPath = matPath;
result.reportPath = reportPath;
result.evidenceBoundary = protocol.evidenceBoundary;
save('-mat7-binary', matPath, 'result', 'behaviorBundle');
writeReport(reportPath, result);
fprintf('V259 passive trace complete in %.1f s: %s\n', ...
    elapsedSeconds, reportPath);
end

function validateReference(reference, presetName, seed)
required = {'contractVersion', 'generationGitCommit', ...
    'presetName', 'seed', 'minimumBackbone'};
valid = isstruct(reference) && isscalar(reference) && ...
    all(isfield(reference, required)) && ...
    strcmp(reference.contractVersion, ...
        'temporal-task-coupled-formation-braid-v248-result-v1') && ...
    strcmp(reference.presetName, presetName) && ...
    reference.seed == seed && ...
    isstruct(reference.minimumBackbone) && ...
    isfield(reference.minimumBackbone, ...
        'fullHorizonPositionEospa');
if ~valid
    error('RiskDecomposedV259:InvalidReference', ...
        'The V248 reference is incomplete or belongs to another case.');
end
end

function arm = attachRouteSummary(arm, diagnostics, config)
arm.routeMessageCountByTime = reshape( ...
    diagnostics.topologyDirectedMessageCount, 1, []);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed);
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed);
formationCount = numel(unique(config.sensorGroupIds));
arm.expectedMinimumMessageCount = ...
    config.numberOfSensors + 2 * (formationCount - 1);
end

function assertPassiveRuntime(arm, diagnostics, config)
timeCount = config.simulationLength;
captured = diagnostics.topologyLocalPosteriorSnapshot;
passed = arm.physicalFeasibilityPassed && ...
    arm.selectedRollingB3SensorPassed && ...
    arm.selectedRollingB3FormationPassed && ...
    ~arm.policyTruthUsed && ~arm.policyFutureOutcomeUsed && ...
    numel(arm.routeMessageCountByTime) == timeCount && ...
    all(arm.routeMessageCountByTime == ...
        arm.expectedMinimumMessageCount) && ...
    numel(captured) >= timeCount && ...
    all(cellfun(@(value) iscell(value) && ...
        numel(value) == config.numberOfSensors, captured(1:timeCount)));
if ~passed
    error('RiskDecomposedV259:PassiveRuntimeContract', ...
        'The V259 passive V242 trace violated its runtime contract.');
end
end

function comparison = comparePassiveArm(candidate, reference)
comparison = struct();
comparison.fullEospaAbsoluteDifference = abs( ...
    candidate.fullHorizonPositionEospa - ...
    reference.fullHorizonPositionEospa);
comparison.fullRmseAbsoluteDifference = abs( ...
    candidate.fullHorizonPositionRmse - ...
    reference.fullHorizonPositionRmse);
comparison.focusConsistencyAbsoluteDifference = abs( ...
    candidate.focusInterFormationPositionOspa - ...
    reference.focusInterFormationPositionOspa);
comparison.attemptedByteDifference = ...
    candidate.attemptedPayloadBytes - reference.attemptedPayloadBytes;
comparison.maximumEospaArrayDifference = maxFiniteDifference( ...
    candidate.positionEospaBySensorTime, ...
    reference.positionEospaBySensorTime);
comparison.maximumRmseArrayDifference = maxFiniteDifference( ...
    candidate.positionRmseBySensorTime, ...
    reference.positionRmseBySensorTime);
comparison.exactOutcomeReproductionPassed = ...
    comparison.fullEospaAbsoluteDifference <= 1e-10 && ...
    comparison.fullRmseAbsoluteDifference <= 1e-10 && ...
    comparison.focusConsistencyAbsoluteDifference <= 1e-10 && ...
    comparison.attemptedByteDifference == 0 && ...
    comparison.maximumEospaArrayDifference <= 1e-10 && ...
    comparison.maximumRmseArrayDifference <= 1e-10;
end

function [trace, summaries] = buildRiskTrace( ...
        posteriorSnapshots, groupIds, model, protocol, timeCount)
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
fields = {'localizationMeanRiskByFormation', ...
    'localizationTailRiskByFormation', ...
    'supportMeanRiskByFormation', ...
    'supportTailRiskByFormation', ...
    'supportProminenceRiskByFormation', ...
    'networkSupportCoverageByFormation', ...
    'relativeNetworkSupportCoverageDeficitByFormation', ...
    'relativeActiveLabelCountDeficitByFormation', ...
    'formationMedianActiveLabelCount'};
trace = struct();
for fieldIdx = 1:numel(fields)
    trace.(fields{fieldIdx}) = zeros(formationCount, timeCount);
end
trace.highestLocalizationRiskLabelByFormationTime = ...
    nan(2, formationCount, timeCount);
trace.highestSupportRiskLabelByFormationTime = ...
    nan(2, formationCount, timeCount);
summaries = cell(1, timeCount);
for currentTime = 1:timeCount
    summary = summarizeFormationLmbRiskModesV259( ...
        posteriorSnapshots{currentTime}, groupIds, model, protocol);
    summaries{currentTime} = summary;
    for fieldIdx = 1:numel(fields)
        trace.(fields{fieldIdx})(:, currentTime) = reshape( ...
            summary.(fields{fieldIdx}), [], 1);
    end
    for formationIdx = 1:formationCount
        idx = summary. ...
            highestLocalizationRiskLabelIndexByFormation(formationIdx);
        if idx > 0
            trace.highestLocalizationRiskLabelByFormationTime( ...
                :, formationIdx, currentTime) = summary.labels(:, idx);
        end
        idx = summary.highestSupportRiskLabelIndexByFormation( ...
            formationIdx);
        if idx > 0
            trace.highestSupportRiskLabelByFormationTime( ...
                :, formationIdx, currentTime) = summary.labels(:, idx);
        end
    end
end
trace.contractVersion = 'risk-decomposed-v259-time-series-v1';
trace.formationIds = groups;
trace.times = 1:timeCount;
trace.truthUsed = false;
trace.futureMeasurementUsed = false;
trace.currentNetworkPosteriorSynopsisUsed = true;
trace.distributedControlSynopsisCostIncluded = false;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('RiskDecomposedV259:ReportOpenFailed', ...
        'Unable to write %s.', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
arm = result.passiveArm;
comparison = result.passiveComparison;
trace = result.riskTrace;
fprintf(fid, '# V259 passive risk-decomposition trace\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Passive V242 reproduction passed: `%d`\n', ...
    comparison.exactOutcomeReproductionPassed);
fprintf(fid, '- Development evidence only: `1`\n\n');
fprintf(fid, '| Passive arm | E-OSPA | RMSE | Focus consistency | Bytes | Messages / step |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|\n');
fprintf(fid, '| V242 with passive capture | %.3f | %.3f | %.3f | %.0f | %d--%d |\n\n', ...
    arm.fullHorizonPositionEospa, ...
    arm.fullHorizonPositionRmse, ...
    arm.focusInterFormationPositionOspa, ...
    arm.attemptedPayloadBytes, ...
    arm.routeMessageCountMinimum, arm.routeMessageCountMaximum);
fprintf(fid, 'Maximum reproduced E-OSPA/RMSE array difference: `%.3g / %.3g`; byte difference: `%+.0f`.\n\n', ...
    comparison.maximumEospaArrayDifference, ...
    comparison.maximumRmseArrayDifference, ...
    comparison.attemptedByteDifference);
fprintf(fid, '## Opened diagnostic anchors\n\n');
fprintf(fid, '| Time | Highest localization-tail formation / score | Highest support-prominence formation / score | Its coverage deficit | Its active-count deficit |\n');
fprintf(fid, '|--:|:--|:--|--:|--:|\n');
for currentTime = result.protocol.diagnosticAnchorTimes
    [localizationScore, localizationFormation] = max( ...
        trace.localizationTailRiskByFormation(:, currentTime));
    [supportScore, supportFormation] = max( ...
        trace.supportProminenceRiskByFormation(:, currentTime));
    fprintf(fid, '| %d | F%d / %.3f | F%d / %.3f | %.3f | %.3f |\n', ...
        currentTime, localizationFormation, localizationScore, ...
        supportFormation, supportScore, ...
        trace.relativeNetworkSupportCoverageDeficitByFormation( ...
            supportFormation, currentTime), ...
        trace.relativeActiveLabelCountDeficitByFormation( ...
            supportFormation, currentTime));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function difference = maxFiniteDifference(left, right)
if ~isequal(size(left), size(right)) || ...
        any(xor(isnan(left(:)), isnan(right(:))))
    difference = Inf;
    return;
end
mask = isfinite(left) & isfinite(right);
if any(mask(:))
    difference = max(abs(left(mask) - right(mask)));
else
    difference = 0;
end
end

function value = anyFiniteNonzero(values)
values = values(isfinite(values));
value = any(logical(values));
end

function complete = isComplete(result)
complete = isstruct(result) && isscalar(result) && ...
    isfield(result, 'completed') && logical(result.completed) && ...
    isfield(result, 'riskTrace') && ...
    isfield(result, 'passiveComparison');
end

function sensors = selectFormationRepresentativesLocal(groupIds)
groups = unique(groupIds, 'stable');
sensors = zeros(1, numel(groups));
for groupIdx = 1:numel(groups)
    sensors(groupIdx) = find(groupIds == groups(groupIdx), 1);
end
end

function absolute = isAbsolutePath(path)
if ispc
    absolute = numel(path) >= 3 && isletter(path(1)) && ...
        path(2) == ':' && any(path(3) == ['\\', '/']);
else
    absolute = ~isempty(path) && path(1) == '/';
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
