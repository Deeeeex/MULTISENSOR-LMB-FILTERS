function [reportPath, probe] = ...
    runFormationH3TerminalDebtRepairProbe(options)
% RUNFORMATIONH3TERMINALDEBTREPAIRPROBE Final H=3 mode-family gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3TerminalDebtRepairProbeProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official terminal debt-repair probe requires clean source.');
end
outputRoot = getField(options, 'outputDirectory', protocol.outputRoot);
probePath = fullfile(outputRoot, ...
    'formation_h3_terminal_debt_repair_grid_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_H3_TERMINAL_DEBT_REPAIR_GRID_V1.md');
probeExists = exist(probePath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(probeExists, reportExists)
    error('Terminal debt-repair probe artifacts are partial.');
elseif probeExists
    loaded = load(probePath, 'probe');
    if ~isfield(loaded, 'probe') || ...
            ~strcmp(loaded.probe.protocolId, protocol.id) || ...
            ~strcmp(loaded.probe.generationGitCommit, gitState.commit)
        error('Terminal debt-repair probe provenance mismatch.');
    end
    probe = loaded.probe;
    fprintf('Reused terminal debt-repair probe: %s\n', probePath);
    return;
end

prefixFirstModes = protocol.prefixFirstModeVectors;
prefixSecondModes = protocol.prefixSecondModeVectors;
prefixFirstActions = formationModeVectorToActionIndex( ...
    prefixFirstModes, protocol.modeCount);
prefixSecondActions = formationModeVectorToActionIndex( ...
    prefixSecondModes, protocol.modeCount);
[repairModes, repairActions] = ...
    enumerateFormationModeCartesianProduct( ...
        protocol.repairModeChoices, protocol.modeCount);
savedControlActions = formationModeVectorToActionIndex( ...
    protocol.savedControlModeVectors, protocol.modeCount)';
if size(prefixFirstModes, 1) ~= protocol.expectedPrefixCount || ...
        size(prefixSecondModes, 1) ~= protocol.expectedPrefixCount || ...
        size(repairModes, 1) ~= protocol.expectedRepairCount || ...
        ~isequal(repairModes(1, :), ...
            protocol.referenceModeVector) || ...
        repairActions(1) ~= protocol.referenceActionIndex
    error('Terminal debt-repair candidate contract changed.');
end

reference = protocol.referenceActionIndex;
prefixCount = size(prefixFirstModes, 1);
repairCount = size(repairModes, 1);
candidateCount = prefixCount * repairCount;
candidateSequences = zeros(candidateCount, protocol.horizonSteps);
prefixIndexByCandidate = zeros(candidateCount, 1);
repairIndexByCandidate = zeros(candidateCount, 1);
for prefixIdx = 1:prefixCount
    rows = (prefixIdx - 1) * repairCount + (1:repairCount);
    candidateSequences(rows, 1) = prefixFirstActions(prefixIdx);
    candidateSequences(rows, 2) = prefixSecondActions(prefixIdx);
    candidateSequences(rows, 3) = repairActions;
    prefixIndexByCandidate(rows) = prefixIdx;
    repairIndexByCandidate(rows) = (1:repairCount)';
end
sequences = [ ...
    reference, reference, reference; ...
    savedControlActions; ...
    candidateSequences];
candidateRows = (3:size(sequences, 1))';
if candidateCount ~= protocol.expectedCandidateCount || ...
        size(sequences, 1) ~= protocol.expectedSequenceCount || ...
        size(unique(sequences, 'rows'), 1) ~= size(sequences, 1)
    error('Terminal debt-repair sequence enumeration changed.');
end

screenDirectory = fullfile(outputRoot, 'screen');
screenOptions = struct( ...
    'cacheRoot', protocol.cacheRoot, ...
    'outputDirectory', screenDirectory, ...
    'interventionBankType', protocol.interventionBankType, ...
    'actionSequenceIndices', sequences, ...
    'writeReport', true);
[screenReportPath, screen] = ...
    runFormationModeH3OpenedReturnScreen( ...
        protocol.presetName, protocol.seed, ...
        protocol.currentTime, screenOptions);
if screen.bank.actionCount ~= protocol.expectedActionCount || ...
        ~isequal(screen.bank.actionModes(prefixFirstActions, :), ...
            prefixFirstModes) || ...
        ~isequal(screen.bank.actionModes(prefixSecondActions, :), ...
            prefixSecondModes) || ...
        ~isequal(screen.bank.actionModes(repairActions, :), ...
            repairModes)
    error('Terminal debt-repair action bank changed.');
end

targets = targetMatrix(screen);
prefixReferenceCandidateRows = find(repairIndexByCandidate == 1);
prefixReferenceRows = candidateRows(prefixReferenceCandidateRows);
prefixReproductionError = abs(targets(prefixReferenceRows, :) - ...
    protocol.expectedPrefixTargets);
savedControlError = abs(targets(2, :) - ...
    protocol.expectedSavedControlTargets);
if max(prefixReproductionError(:)) > ...
        protocol.reproductionTolerancePercent || ...
        max(savedControlError(:)) > ...
            protocol.reproductionTolerancePercent || ...
        any(abs(targets(1, :)) > 1e-12)
    error('Terminal debt-repair reproduction gate failed.');
end

candidateTargets = targets(candidateRows, :);
candidateStrict = all(candidateTargets >= -1e-12, 2);
candidateStrong = candidateStrict & ...
    candidateTargets(:, 1) >= protocol.strongGainPercent - 1e-12;
strongThresholds = [protocol.strongGainPercent, zeros(1, 5)];
normalizedStrongDeficits = max( ...
    strongThresholds - candidateTargets, 0) ./ ...
        protocol.constraintScalesPercent;
maximumStrongDeficit = max(normalizedStrongDeficits, [], 2);
totalStrongDeficit = sum(normalizedStrongDeficits, 2);
ranking = [ ...
    maximumStrongDeficit, totalStrongDeficit, ...
    -candidateTargets(:, 1), ...
    prefixIndexByCandidate, repairIndexByCandidate];
[~, rankOrder] = sortrows(ranking, [1, 2, 3, 4, 5]);
closestCandidateIndex = rankOrder(1);
[bestMeanGain, bestMeanCandidateIndex] = ...
    max(candidateTargets(:, 1));
strictCandidateIndices = find(candidateStrict);
strongCandidateIndices = find(candidateStrong);

prefixSummary = buildPrefixSummary( ...
    prefixFirstModes, prefixSecondModes, prefixIndexByCandidate, ...
    repairIndexByCandidate, repairModes, candidateTargets, ...
    candidateStrict, candidateStrong, maximumStrongDeficit, ...
    totalStrongDeficit);

probe = struct();
probe.contractVersion = ...
    'formation-h3-terminal-debt-repair-probe-result-v1';
probe.protocolId = protocol.id;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
probe.cacheProtocolId = protocol.cacheProtocolId;
probe.cacheGenerationGitCommit = ...
    protocol.cacheGenerationGitCommit;
probe.presetName = protocol.presetName;
probe.seed = protocol.seed;
probe.currentTime = protocol.currentTime;
probe.sequences = sequences;
probe.targets = targets;
probe.savedControlModeVectors = protocol.savedControlModeVectors;
probe.savedControlTargets = targets(2, :);
probe.prefixFirstModeVectors = prefixFirstModes;
probe.prefixSecondModeVectors = prefixSecondModes;
probe.prefixRoles = protocol.prefixRoles;
probe.repairModeVectors = repairModes;
probe.candidateSequences = candidateSequences;
probe.candidateTargets = candidateTargets;
probe.prefixIndexByCandidate = prefixIndexByCandidate;
probe.repairIndexByCandidate = repairIndexByCandidate;
probe.candidateStrictFeasible = candidateStrict;
probe.candidateStrongSafe = candidateStrong;
probe.candidateStrictFeasibleCount = nnz(candidateStrict);
probe.candidateStrongSafeCount = nnz(candidateStrong);
probe.strongSafeSequenceFound = any(candidateStrong);
probe.normalizedStrongConstraintDeficits = ...
    normalizedStrongDeficits;
probe.maximumStrongConstraintDeficit = maximumStrongDeficit;
probe.totalStrongConstraintDeficit = totalStrongDeficit;
probe.candidateRankOrder = rankOrder;
probe.closestCandidateIndex = closestCandidateIndex;
probe.closestFirstModeVector = prefixFirstModes( ...
    prefixIndexByCandidate(closestCandidateIndex), :);
probe.closestSecondModeVector = prefixSecondModes( ...
    prefixIndexByCandidate(closestCandidateIndex), :);
probe.closestRepairModeVector = repairModes( ...
    repairIndexByCandidate(closestCandidateIndex), :);
probe.closestTargets = candidateTargets(closestCandidateIndex, :);
probe.bestMeanCandidateIndex = bestMeanCandidateIndex;
probe.bestMeanFirstModeVector = prefixFirstModes( ...
    prefixIndexByCandidate(bestMeanCandidateIndex), :);
probe.bestMeanSecondModeVector = prefixSecondModes( ...
    prefixIndexByCandidate(bestMeanCandidateIndex), :);
probe.bestMeanRepairModeVector = repairModes( ...
    repairIndexByCandidate(bestMeanCandidateIndex), :);
probe.bestMeanTargets = candidateTargets( ...
    bestMeanCandidateIndex, :);
probe.bestMeanGainPercent = bestMeanGain;
if isempty(strictCandidateIndices)
    probe.strictOracleCandidateIndex = 0;
    probe.strictOracleTargets = [];
else
    [~, strictLocal] = max( ...
        candidateTargets(strictCandidateIndices, 1));
    probe.strictOracleCandidateIndex = ...
        strictCandidateIndices(strictLocal);
    probe.strictOracleTargets = candidateTargets( ...
        probe.strictOracleCandidateIndex, :);
end
if isempty(strongCandidateIndices)
    probe.strongOracleCandidateIndex = 0;
    probe.strongOracleTargets = [];
else
    [~, strongLocal] = max( ...
        candidateTargets(strongCandidateIndices, 1));
    probe.strongOracleCandidateIndex = ...
        strongCandidateIndices(strongLocal);
    probe.strongOracleTargets = candidateTargets( ...
        probe.strongOracleCandidateIndex, :);
end
probe.prefixSummary = prefixSummary;
probe.screen = screen;
probe.screenReportPath = screenReportPath;
probe.actionSelectionUsesTruth = protocol.actionSelectionUsesTruth;
probe.actionSelectionUsesFutureMeasurements = ...
    protocol.actionSelectionUsesFutureMeasurements;
probe.runtimePolicyUsesTruth = protocol.runtimePolicyUsesTruth;
probe.openedTrainingMechanismProbeOnly = true;
probe.teacherModelTrainingAuthorized = ...
    probe.strongSafeSequenceFound;
probe.currentActionFamilyExpansionAuthorized = ...
    probe.strongSafeSequenceFound;
probe.finalModelTrainingAuthorized = false;
probe.validationClaimAllowed = false;
probe.evidenceBoundary = protocol.evidenceBoundary;
probe.probePath = probePath;
probe.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', probePath, 'probe');
writeReport(reportPath, probe);
fprintf('Terminal debt-repair probe: %s\n', probePath);
fprintf(['Candidate strict=%d/%d; strong=%d; ', ...
    'teacher-training-authorized=%d; family-expansion=%d\n'], ...
    probe.candidateStrictFeasibleCount, candidateCount, ...
    probe.candidateStrongSafeCount, ...
    probe.teacherModelTrainingAuthorized, ...
    probe.currentActionFamilyExpansionAuthorized);
end

function summary = buildPrefixSummary( ...
        firstModes, secondModes, prefixIndexByCandidate, ...
        repairIndexByCandidate, repairModes, targets, strictFeasible, ...
        strongSafe, maximumStrongDeficit, totalStrongDeficit)
prefixCount = size(firstModes, 1);
summary = repmat(struct( ...
    'firstModeVector', [], ...
    'secondModeVector', [], ...
    'strictCount', 0, ...
    'strongCount', 0, ...
    'bestStrictMeanGainPercent', NaN, ...
    'closestRepairModeVector', [], ...
    'closestTargets', []), prefixCount, 1);
for prefixIdx = 1:prefixCount
    rows = find(prefixIndexByCandidate == prefixIdx);
    strictRows = rows(strictFeasible(rows));
    if ~isempty(strictRows)
        summary(prefixIdx).bestStrictMeanGainPercent = ...
            max(targets(strictRows, 1));
    end
    localRanking = [ ...
        maximumStrongDeficit(rows), totalStrongDeficit(rows), ...
        -targets(rows, 1), repairIndexByCandidate(rows)];
    [~, order] = sortrows(localRanking, [1, 2, 3, 4]);
    closestRow = rows(order(1));
    summary(prefixIdx).firstModeVector = firstModes(prefixIdx, :);
    summary(prefixIdx).secondModeVector = secondModes(prefixIdx, :);
    summary(prefixIdx).strictCount = nnz(strictFeasible(rows));
    summary(prefixIdx).strongCount = nnz(strongSafe(rows));
    summary(prefixIdx).closestRepairModeVector = repairModes( ...
        repairIndexByCandidate(closestRow), :);
    summary(prefixIdx).closestTargets = targets(closestRow, :);
end
end

function targets = targetMatrix(screen)
records = screen.records;
outcomes = screen.outcomes;
reference = outcomes(screen.referenceSubsetIndex);
delivered = zeros(numel(outcomes), 1);
for idx = 1:numel(outcomes)
    delivered(idx) = 100 * ...
        (reference.deliveredBytes - outcomes(idx).deliveredBytes) / ...
        max(reference.deliveredBytes, eps);
end
targets = [ ...
    reshape([records.meanGainPercent], [], 1), ...
    reshape([records.minimumFormationGainPercent], [], 1), ...
    reshape([records.worstGainPercent], [], 1), ...
    reshape([records.consensusGainPercent], [], 1), ...
    reshape([records.attemptedByteSavingPercent], [], 1), ...
    delivered];
end

function writeReport(path, probe)
fid = fopen(path, 'w');
if fid < 0
    error('Cannot write terminal debt-repair report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 terminal debt-repair grid\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    probe.contractVersion, probe.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', probe.generationGitCommit);
fprintf(fid, '- Cache protocol / commit: `%s / %s`\n', ...
    probe.cacheProtocolId, probe.cacheGenerationGitCommit);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    probe.presetName, probe.seed, probe.currentTime);
fprintf(fid, '- Candidate strict feasible: `%d/%d`\n', ...
    probe.candidateStrictFeasibleCount, ...
    size(probe.candidateSequences, 1));
fprintf(fid, '- Candidate strong safe: `%d/%d`\n', ...
    probe.candidateStrongSafeCount, ...
    size(probe.candidateSequences, 1));
fprintf(fid, '- Saved v21 control targets: `%s`\n', ...
    mat2str(probe.savedControlTargets, 7));
fprintf(fid, '- Closest sequence / targets: `%s -> %s -> %s / %s`\n', ...
    mat2str(probe.closestFirstModeVector), ...
    mat2str(probe.closestSecondModeVector), ...
    mat2str(probe.closestRepairModeVector), ...
    mat2str(probe.closestTargets, 7));
fprintf(fid, '- Best-mean sequence / targets: `%s -> %s -> %s / %s`\n', ...
    mat2str(probe.bestMeanFirstModeVector), ...
    mat2str(probe.bestMeanSecondModeVector), ...
    mat2str(probe.bestMeanRepairModeVector), ...
    mat2str(probe.bestMeanTargets, 7));
fprintf(fid, '- Teacher-model training authorized: `%d`\n', ...
    probe.teacherModelTrainingAuthorized);
fprintf(fid, '- Current action-family expansion authorized: `%d`\n\n', ...
    probe.currentActionFamilyExpansionAuthorized);

fprintf(fid, '## Prefix summary\n\n');
fprintf(fid, ['| First | Second | Strict | Strong | Best strict mean | ', ...
    'Closest repair | Closest targets |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|:--|:--|\n');
for idx = 1:numel(probe.prefixSummary)
    item = probe.prefixSummary(idx);
    fprintf(fid, '| `%s` | `%s` | %d | %d | %s | `%s` | `%s` |\n', ...
        formatModeVector(item.firstModeVector), ...
        formatModeVector(item.secondModeVector), ...
        item.strictCount, item.strongCount, ...
        formatPercent(item.bestStrictMeanGainPercent), ...
        formatModeVector(item.closestRepairModeVector), ...
        mat2str(item.closestTargets, 5));
end

fprintf(fid, '\n## Strong-constraint ranking\n\n');
fprintf(fid, ['| Rank | First | Second | Repair | Mean | Min. formation | ', ...
    'Worst sensor | Consensus | Attempted | Delivered | Strict | Strong |\n']);
fprintf(fid, '|--:|:--|:--|:--|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
topCount = min(20, numel(probe.candidateRankOrder));
for rankIdx = 1:topCount
    idx = probe.candidateRankOrder(rankIdx);
    prefixIdx = probe.prefixIndexByCandidate(idx);
    repairIdx = probe.repairIndexByCandidate(idx);
    targets = probe.candidateTargets(idx, :);
    fprintf(fid, ['| %d | `%s` | `%s` | `%s` | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d | %d |\n'], ...
        rankIdx, formatModeVector( ...
            probe.prefixFirstModeVectors(prefixIdx, :)), ...
        formatModeVector(probe.prefixSecondModeVectors(prefixIdx, :)), ...
        formatModeVector(probe.repairModeVectors(repairIdx, :)), ...
        targets(1), targets(2), targets(3), targets(4), ...
        targets(5), targets(6), ...
        probe.candidateStrictFeasible(idx), ...
        probe.candidateStrongSafe(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    probe.evidenceBoundary);
end

function value = formatModeVector(modes)
value = strtrim(sprintf('%d ', reshape(modes, 1, [])));
end

function value = formatPercent(number)
if isnan(number)
    value = 'none';
else
    value = sprintf('%+.3f%%', number);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
