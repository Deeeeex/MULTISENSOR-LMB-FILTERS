function [modelPath, result] = ...
    trainPrivilegedRollingSafeValueProposalHeads(options)
% TRAINPRIVILEGEDROLLINGSAFEVALUEPROPOSALHEADS Multi-solution diagnostic.
%
% Fits four truth-free linear edge-score heads and passes every prediction
% through the exact rolling-B=3 projector. Hyperparameters are selected by
% leave-one-seed-out capture on the design-seen privileged state dataset.
% This is an architecture diagnostic, not held-out or online validation.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
maximumBannedSelectedEdges = round(getField( ...
    options, 'maximumBannedSelectedEdges', 0));
if ~isscalar(maximumBannedSelectedEdges) || ...
        ~ismember(maximumBannedSelectedEdges, [0, 1])
    error(['maximumBannedSelectedEdges must be 0 (single-shot) ', ...
        'or 1 (one-edge exclusion bank).']);
end
datasetPath = getField(options, 'datasetPath', ...
    protocol.privilegedValueTargetDatasetRelativePath);
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
validateFrozenFile(datasetPath, ...
    protocol.privilegedValueTargetDatasetSha256, ...
    'value-target dataset');
validateFrozenFile(sourcePath, ...
    protocol.proposalSourceStateSha256, ...
    'source state dataset');
loaded = load(datasetPath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
if ~isfield(loaded, 'dataset') || ...
        ~isfield(sourceLoaded, 'dataset')
    error('Proposal-head input MAT lacks dataset.');
end
dataset = loaded.dataset;
source = sourceLoaded.dataset;
validateDatasets(dataset, source, protocol);

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official proposal-head diagnostic requires clean source.');
end

headCodes = protocol.valueProposalHeadActionCodes;
lambdaGrid = protocol.valueProposalHeadRidgeLambdaGrid;
supervisionModes = ...
    protocol.valueProposalHeadSupervisionModes;
candidateCount = numel(lambdaGrid) * ...
    numel(supervisionModes);
candidates = repmat(emptyCandidate(), 1, candidateCount);
cursor = 0;
for modeIdx = 1:numel(supervisionModes)
    for lambda = lambdaGrid
        cursor = cursor + 1;
        candidates(cursor) = evaluateLosoCandidate( ...
            dataset, source, headCodes, ...
            supervisionModes{modeIdx}, lambda, protocol, ...
            maximumBannedSelectedEdges);
        candidates(cursor).modeOrder = modeIdx;
        fprintf(['proposal heads %s lambda %.4g: ', ...
            'capture %d/%d (%.1f%%), target recall %.1f%%, ', ...
            'mean best F1 %.3f\n'], ...
            supervisionModes{modeIdx}, lambda, ...
            candidates(cursor).capturedTargetStateCount, ...
            candidates(cursor).targetStateCount, ...
            100 * candidates(cursor).targetStateCaptureFraction, ...
            100 * candidates(cursor).targetGraphRecallFraction, ...
            candidates(cursor).meanBestTargetEdgeF1);
    end
end

selectionKeys = zeros(candidateCount, 6);
for idx = 1:candidateCount
    candidate = candidates(idx);
    selectionKeys(idx, :) = [ ...
        -candidate.targetStateCaptureFraction, ...
        -candidate.targetGraphRecallFraction, ...
        -candidate.meanBestTargetEdgeF1, ...
        candidate.projectionFailureCount, ...
        candidate.modeOrder, log10(candidate.lambda)];
end
[~, order] = sortrows(selectionKeys);
candidates = candidates(order);
selected = candidates(1);

heads = fitHeads(dataset.blocks, dataset.seeds, ...
    headCodes, selected.supervisionMode, ...
    selected.lambda);
model = struct();
if maximumBannedSelectedEdges == 0
    model.kind = ...
        'ridge-multihead-rolling-safe-value-proposal-v1';
else
    model.kind = ...
        'ridge-multihead-kbest-rolling-safe-value-proposal-v2';
end
model.protocolId = protocol.id;
model.contractVersion = ...
    'rolling-safe-value-proposal-head-model-m24-v1';
model.generatedAt = datestr(now, 31);
model.headActionCodes = headCodes;
model.topK = numel(headCodes) * ...
    (1 + maximumBannedSelectedEdges * ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount);
model.maximumBannedSelectedEdges = ...
    maximumBannedSelectedEdges;
model.exactCurrentCrossEdgeCount = ...
    protocol.valueProposalHeadExactCurrentCrossEdgeCount;
model.sourceWeight = dataset.sourceWeight;
model.payloadToleranceFraction = inf;
model.edgeFeatureNames = dataset.edgeFeatureNames;
model.supervisionMode = selected.supervisionMode;
model.ridgeLambda = selected.lambda;
model.heads = heads;
model.datasetPath = datasetPath;
model.datasetSha256 = ...
    protocol.privilegedValueTargetDatasetSha256;
model.sourceStatePath = sourcePath;
model.sourceStateSha256 = ...
    protocol.proposalSourceStateSha256;
model.trainingSeeds = dataset.seeds;
model.trainingGitCommit = gitState.commit;
model.trainingTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
model.trainingUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
model.trainingResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
model.featuresUseTruth = false;
model.labelsUseTruth = true;
model.labelsUseFutureOutcome = true;
model.stateCollectionBehaviorUsesTruth = true;
model.developmentOnly = ...
    protocol.valueProposalHeadDevelopmentOnly;
model.validationClaimAllowed = ...
    protocol.valueProposalHeadValidationClaimAllowed;
model.losoMetrics = selected;
model.developmentCaptureGatePassed = ...
    selected.targetStateCaptureFraction + 1e-12 >= ...
        protocol.minimumTopKAdmissibleCaptureFraction;
model.onlineTruthFreeCaptureEvaluated = false;
model.criticTrainingAuthorized = false;
model.x36Authorized = false;
model.evidenceBoundary = [ ...
    'The four score heads read only frozen observable edge ', ...
    'features and every single-shot or exclusion proposal uses ', ...
    'the exact rolling-B=3 projector. Their ', ...
    'teacher graphs, value weights and all state histories are ', ...
    'design-seen privileged data. LOSO capture is an architecture ', ...
    'diagnostic only. Fresh online truth-free rollouts must pass ', ...
    'the same capture gate before critic or X36 experiments.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'models'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
if maximumBannedSelectedEdges == 0
    defaultModelName = ...
        'rolling_safe_value_proposal_heads_m24_hard_t75_v1.mat';
    defaultReportName = ...
        'VALUE_PROPOSAL_HEAD_LOSO_DIAGNOSTIC_M24.md';
else
    defaultModelName = ...
        'rolling_safe_value_proposal_heads_m24_hard_t75_v2.mat';
    defaultReportName = ...
        'VALUE_PROPOSAL_HEAD_KBEST_LOSO_DIAGNOSTIC_M24.md';
end
modelPath = getField(options, 'modelPath', ...
    fullfile(outputDirectory, defaultModelName));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', defaultReportName));
model.modelPath = modelPath;
model.reportPath = reportPath;
save('-mat7-binary', modelPath, 'model');

result = struct();
result.modelPath = modelPath;
result.reportPath = reportPath;
result.candidates = candidates;
result.selected = selected;
result.developmentCaptureGatePassed = ...
    model.developmentCaptureGatePassed;
result.onlineTruthFreeCaptureEvaluated = false;
result.criticTrainingAuthorized = false;
result.x36Authorized = false;
writeReport(reportPath, model, candidates, protocol);
fprintf(['Selected %s lambda %.4g: target-state capture ', ...
    '%d/%d (%.1f%%), target-graph recall %.1f%%, ', ...
    'gate=%d\nModel: %s\nReport: %s\n'], ...
    selected.supervisionMode, selected.lambda, ...
    selected.capturedTargetStateCount, ...
    selected.targetStateCount, ...
    100 * selected.targetStateCaptureFraction, ...
    100 * selected.targetGraphRecallFraction, ...
    model.developmentCaptureGatePassed, ...
    modelPath, reportPath);
end

function candidate = evaluateLosoCandidate( ...
        dataset, source, headCodes, ...
        supervisionMode, lambda, protocol, ...
        maximumBannedSelectedEdges)
rows = repmat(emptyBlockMetric(), 1, 0);
for heldoutSeed = dataset.seeds
    fitSeeds = setdiff( ...
        dataset.seeds, heldoutSeed, 'stable');
    heads = fitHeads(dataset.blocks, fitSeeds, ...
        headCodes, supervisionMode, lambda);
    heldoutIndices = find( ...
        [dataset.blocks.seed] == heldoutSeed & ...
        [dataset.blocks.valueTargetCount] > 0);
    for blockIdx = heldoutIndices
        block = dataset.blocks(blockIdx);
        sourceBlock = source.blocks(block.sourceBlockIndex);
        row = evaluateBlock( ...
            block, sourceBlock, heads, protocol, ...
            maximumBannedSelectedEdges);
        rows(end + 1) = row; %#ok<AGROW>
    end
end
if isempty(rows)
    error('Proposal-head LOSO has no target-bearing states.');
end
capturedStateCount = nnz([rows.targetStateCaptured]);
targetStateCount = numel(rows);
capturedGraphCount = sum( ...
    [rows.capturedTargetGraphCount]);
targetGraphCount = sum([rows.valueTargetCount]);
candidate = emptyCandidate();
candidate.supervisionMode = supervisionMode;
candidate.lambda = lambda;
candidate.blockRows = rows;
candidate.targetStateCount = targetStateCount;
candidate.capturedTargetStateCount = capturedStateCount;
candidate.targetStateCaptureFraction = ...
    capturedStateCount / targetStateCount;
candidate.targetGraphCount = targetGraphCount;
candidate.capturedTargetGraphCount = capturedGraphCount;
candidate.targetGraphRecallFraction = ...
    capturedGraphCount / targetGraphCount;
candidate.meanBestTargetEdgeF1 = ...
    mean([rows.bestTargetEdgeF1]);
candidate.meanDistinctProposalCount = ...
    mean([rows.distinctProposalCount]);
candidate.projectionFailureCount = ...
    sum([rows.projectionFailureCount]);
candidate.targetBearingSeedCount = ...
    numel(unique([rows.seed]));
candidate.minimumTargetBearingSeedCaptureFraction = ...
    minimumSeedCapture(rows);
end

function heads = fitHeads( ...
        blocks, fitSeeds, headCodes, supervisionMode, lambda)
heads = repmat(emptyHead(), 1, numel(headCodes));
for headIdx = 1:numel(headCodes)
    actionCode = headCodes(headIdx);
    [X, y, rowWeights, trainingBlockCount, ...
        positiveTargetBlockCount] = collectHeadExamples( ...
            blocks, fitSeeds, actionCode, supervisionMode);
    if isempty(X) || trainingBlockCount < 2
        error(['Insufficient proposal-head examples for code ', ...
            '%02d in mode %s.'], actionCode, supervisionMode);
    end
    featureMean = mean(X, 1);
    featureScale = std(X, 0, 1);
    featureScale(featureScale < 1e-12) = 1;
    normalized = bsxfun(@rdivide, ...
        bsxfun(@minus, X, featureMean), featureScale);
    design = [ones(size(normalized, 1), 1), normalized];
    weightedDesign = bsxfun(@times, ...
        design, rowWeights);
    regularizer = diag([0, ones(1, size(normalized, 2))]);
    coefficients = (design' * weightedDesign + ...
        lambda * regularizer) \ ...
        (design' * (rowWeights .* y));
    head = emptyHead();
    head.actionCode = actionCode;
    head.featureMean = featureMean;
    head.featureScale = featureScale;
    head.coefficients = coefficients;
    head.lambda = lambda;
    head.supervisionMode = supervisionMode;
    head.trainingSeeds = fitSeeds;
    head.trainingBlockCount = trainingBlockCount;
    head.positiveTargetBlockCount = ...
        positiveTargetBlockCount;
    heads(headIdx) = head;
end
end

function [X, y, rowWeights, blockCount, targetBlockCount] = ...
        collectHeadExamples( ...
            blocks, fitSeeds, actionCode, supervisionMode)
X = zeros(0, size(blocks(1).edgeFeatures, 2));
y = zeros(0, 1);
rowWeights = zeros(0, 1);
blockCount = 0;
targetBlockCount = 0;
for block = blocks
    if ~ismember(block.seed, fitSeeds)
        continue
    end
    candidateIdx = find( ...
        block.candidateActionCodes == actionCode, 1);
    if isempty(candidateIdx)
        continue
    end
    isValueTarget = ...
        block.candidateV2ValueTarget(candidateIdx);
    switch supervisionMode
        case 'all-privileged'
            blockWeight = 1;
        case 'value-weighted'
            blockWeight = 0.10 + ...
                0.90 * double(isValueTarget);
        case 'value-only'
            if ~isValueTarget
                continue
            end
            blockWeight = 1;
        otherwise
            error('Unknown proposal-head supervision mode.');
    end
    target = double( ...
        block.candidateCrossMasks(:, candidateIdx));
    positiveCount = nnz(target);
    negativeCount = numel(target) - positiveCount;
    if positiveCount <= 0 || negativeCount <= 0
        error('Proposal-head target lacks both edge classes.');
    end
    balancedWeights = zeros(size(target));
    balancedWeights(target > 0.5) = ...
        0.5 / positiveCount;
    balancedWeights(target <= 0.5) = ...
        0.5 / negativeCount;
    X = [X; block.edgeFeatures]; %#ok<AGROW>
    y = [y; target]; %#ok<AGROW>
    rowWeights = [rowWeights; ...
        blockWeight * balancedWeights]; %#ok<AGROW>
    blockCount = blockCount + 1;
    targetBlockCount = targetBlockCount + ...
        double(isValueTarget);
end
end

function row = evaluateBlock( ...
        block, sourceBlock, heads, protocol, ...
        maximumBannedSelectedEdges)
targetIndices = find(block.candidateV2ValueTarget);
predictedMasks = false( ...
    size(block.candidateCrossMasks, 1), 0);
predictedHashes = cell(1, 0);
matchedCandidateIndices = nan(1, 0);
projectionFailures = 0;
for headIdx = 1:numel(heads)
    head = heads(headIdx);
    normalized = bsxfun(@rdivide, ...
        bsxfun(@minus, block.edgeFeatures, ...
            head.featureMean), head.featureScale);
    scores = [ones(size(normalized, 1), 1), normalized] * ...
        head.coefficients;
    allowedMask = true(size(scores));
    [adjacency, actionMask, graphHash, valid] = ...
        projectScores(sourceBlock, block, scores, ...
            allowedMask, protocol);
    if ~valid
        projectionFailures = projectionFailures + 1;
        continue
    end
    [predictedMasks, predictedHashes, ...
        matchedCandidateIndices] = appendProposal( ...
            predictedMasks, predictedHashes, ...
            matchedCandidateIndices, adjacency, actionMask, ...
            graphHash, block);

    if maximumBannedSelectedEdges >= 1
        selectedExamples = find(actionMask);
        for selectedIdx = reshape(selectedExamples, 1, [])
            alternativeAllowed = true(size(scores));
            alternativeAllowed(selectedIdx) = false;
            [alternativeAdjacency, alternativeMask, ...
                alternativeHash, alternativeValid] = ...
                    projectScores( ...
                        sourceBlock, block, scores, ...
                        alternativeAllowed, protocol);
            if ~alternativeValid
                projectionFailures = projectionFailures + 1;
                continue
            end
            [predictedMasks, predictedHashes, ...
                matchedCandidateIndices] = appendProposal( ...
                    predictedMasks, predictedHashes, ...
                    matchedCandidateIndices, ...
                    alternativeAdjacency, alternativeMask, ...
                    alternativeHash, block);
        end
    end
end

capturedTargetIndices = unique( ...
    matchedCandidateIndices( ...
        ismember(matchedCandidateIndices, targetIndices)));
bestF1 = 0;
for headIdx = 1:size(predictedMasks, 2)
    predicted = predictedMasks(:, headIdx);
    for targetIdx = targetIndices
        target = block.candidateCrossMasks(:, targetIdx);
        intersection = nnz(predicted & target);
        denominator = nnz(predicted) + nnz(target);
        if denominator == 0
            f1 = 1;
        else
            f1 = 2 * intersection / denominator;
        end
        bestF1 = max(bestF1, f1);
    end
end
row = emptyBlockMetric();
row.seed = block.seed;
row.currentTime = block.currentTime;
row.valueTargetCount = numel(targetIndices);
row.targetStateCaptured = ...
    ~isempty(capturedTargetIndices);
row.capturedTargetGraphCount = ...
    numel(capturedTargetIndices);
row.capturedTargetCandidateIndices = ...
    capturedTargetIndices;
row.bestTargetEdgeF1 = bestF1;
row.distinctProposalCount = ...
    numel(predictedHashes);
row.projectionFailureCount = projectionFailures;
row.predictedGraphSha256 = predictedHashes;
row.matchedCandidateIndices = ...
    matchedCandidateIndices;
row.matchedValueTargetMask = ismember( ...
    matchedCandidateIndices, targetIndices);
end

function [adjacency, actionMask, graphHash, valid] = ...
        projectScores( ...
            sourceBlock, block, scores, allowedMask, protocol)
replayOptions = struct( ...
    'minimumCurrentCrossEdges', ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'maximumCurrentCrossEdges', ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'currentAllowedExampleMask', allowedMask);
try
    [adjacency, details] = ...
        replayRollingSafeRolloutProjection( ...
            sourceBlock, scores, ...
            protocol.sourceWeight, inf, replayOptions);
    valid = details.nominalProjectionFeasible && ...
        ~details.repairProjectionAttempted && ...
        ~details.repairTriggered && ...
        ~details.payloadEmergencyUsed && ...
        details.realizedCrossCount == ...
            protocol.valueProposalHeadExactCurrentCrossEdgeCount && ...
        ~details.truthUsed;
catch
    adjacency = false(size(block.candidateAdjacency, 1));
    details = struct();
    valid = false;
end
if ~valid
    actionMask = false(size(block.candidateCrossMasks, 1), 1);
    graphHash = '';
    return
end
edgeKeys = sub2ind(size(adjacency), ...
    block.receiverIndices, block.senderIndices);
actionMask = reshape(logical(adjacency(edgeKeys)), [], 1);
graphHash = computeTextSha256(sprintf( ...
    '%d,', details.selectedSourcesByReceiver));
end

function [masks, hashes, matchedIndices] = appendProposal( ...
        masks, hashes, matchedIndices, adjacency, actionMask, ...
        graphHash, block)
if any(strcmp(hashes, graphHash))
    return
end
masks(:, end + 1) = actionMask;
hashes{end + 1} = graphHash;
matchedIndex = NaN;
for candidateIdx = 1:block.candidateCount
    if isequal(adjacency, ...
            block.candidateAdjacency(:, :, candidateIdx))
        matchedIndex = candidateIdx;
        break
    end
end
matchedIndices(end + 1) = matchedIndex;
end

function value = minimumSeedCapture(rows)
seeds = unique([rows.seed]);
fractions = zeros(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    mask = [rows.seed] == seeds(seedIdx);
    fractions(seedIdx) = mean( ...
        [rows(mask).targetStateCaptured]);
end
value = min(fractions);
end

function validateDatasets(dataset, source, protocol)
if ~strcmp(dataset.contractVersion, ...
        protocol.privilegedValueTargetDatasetContractVersion) || ...
        ~strcmp(dataset.sourceStateSha256, ...
            protocol.proposalSourceStateSha256) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(dataset.snapshotTimes, protocol.snapshotTimes) || ...
        dataset.totalValueTargetCount ~= ...
            protocol.privilegedReturnV2ExpectedValueTargetCount || ...
        dataset.targetStateCount ~= ...
            protocol.privilegedReturnV2ExpectedTargetStateCount || ...
        ~dataset.truthUsed || ~dataset.futureOutcomeUsed || ...
        dataset.deployable || ~dataset.designSeen || ...
        ~strcmp(source.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~isequal(source.seeds, dataset.seeds) || ...
        ~isequal(source.snapshotTimes, dataset.snapshotTimes)
    error('Proposal-head datasets violate frozen contracts.');
end
for block = dataset.blocks
    if block.valueTargetCount ~= ...
            nnz(block.candidateV2ValueTarget) || ...
            any(sum(block.candidateCrossMasks, 1) ~= ...
                protocol. ...
                    valueProposalHeadExactCurrentCrossEdgeCount) || ...
            block.edgeFeatureMetadata.truthUsed || ...
            block.edgeFeatureMetadata.groundTruthUsed || ...
            block.edgeFeatureMetadata.futureOutcomeUsed
        error('Proposal-head block violates feature/target contracts.');
    end
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function writeReport(path, model, candidates, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open proposal-head report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
selected = model.losoMetrics;
fprintf(fid, ...
    '# M24 multi-head value-proposal LOSO diagnostic\n\n');
fprintf(fid, '- Generated: %s\n', model.generatedAt);
fprintf(fid, '- Model: `%s`\n', model.kind);
fprintf(fid, '- Training commit: `%s`\n', ...
    model.trainingGitCommit);
fprintf(fid, '- Dataset SHA-256: `%s`\n', ...
    model.datasetSha256);
fprintf(fid, '- Heads / top-K: `%s / %d`\n', ...
    mat2str(model.headActionCodes), model.topK);
fprintf(fid, '- Exact current cross edges per head: `%d`\n', ...
    model.exactCurrentCrossEdgeCount);
fprintf(fid, '- Selected supervision: `%s`\n', ...
    model.supervisionMode);
fprintf(fid, '- Selected ridge lambda: `%.6g`\n', ...
    model.ridgeLambda);
fprintf(fid, '- Target-state capture: `%d / %d (%.3f%%)`\n', ...
    selected.capturedTargetStateCount, ...
    selected.targetStateCount, ...
    100 * selected.targetStateCaptureFraction);
fprintf(fid, '- Target-graph recall: `%d / %d (%.3f%%)`\n', ...
    selected.capturedTargetGraphCount, ...
    selected.targetGraphCount, ...
    100 * selected.targetGraphRecallFraction);
fprintf(fid, '- Mean best target edge F1: `%.6f`\n', ...
    selected.meanBestTargetEdgeF1);
fprintf(fid, '- Mean distinct proposals per state: `%.3f`\n', ...
    selected.meanDistinctProposalCount);
fprintf(fid, '- Projection failures: `%d`\n', ...
    selected.projectionFailureCount);
fprintf(fid, '- Development capture gate (>= %.1f%%): `%d`\n', ...
    100 * protocol.minimumTopKAdmissibleCaptureFraction, ...
    model.developmentCaptureGatePassed);
fprintf(fid, '- Online truth-free capture evaluated: `%d`\n', ...
    model.onlineTruthFreeCaptureEvaluated);
fprintf(fid, '- Critic/X36 authorized: `%d / %d`\n', ...
    model.criticTrainingAuthorized, model.x36Authorized);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    model.evidenceBoundary);

fprintf(fid, '## Hyperparameter screen\n\n');
fprintf(fid, ...
    ['| Supervision | Lambda | State capture | Target recall | ', ...
     'Mean best F1 | Distinct | Failures |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for candidate = candidates
    fprintf(fid, ...
        '| %s | %.4g | %.1f%% | %.1f%% | %.3f | %.2f | %d |\n', ...
        candidate.supervisionMode, candidate.lambda, ...
        100 * candidate.targetStateCaptureFraction, ...
        100 * candidate.targetGraphRecallFraction, ...
        candidate.meanBestTargetEdgeF1, ...
        candidate.meanDistinctProposalCount, ...
        candidate.projectionFailureCount);
end

fprintf(fid, '\n## Selected LOSO states\n\n');
fprintf(fid, ...
    ['| Seed | Time | Targets | Captured | Captured graphs | ', ...
     'Best edge F1 | Distinct proposals | Failures | Matches |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--|\n');
for row = selected.blockRows
    fprintf(fid, ...
        '| %d | %d | %d | %d | %d | %.3f | %d | %d | `%s` |\n', ...
        row.seed, row.currentTime, row.valueTargetCount, ...
        row.targetStateCaptured, row.capturedTargetGraphCount, ...
        row.bestTargetEdgeF1, row.distinctProposalCount, ...
        row.projectionFailureCount, ...
        formatMatches(row.matchedCandidateIndices));
end
fprintf(fid, '\n## Decision\n\n');
if model.developmentCaptureGatePassed
    fprintf(fid, ['PASS as an architecture diagnostic only: the ', ...
        'four truth-free score heads reach the 80%% capture gate ', ...
        'on design-seen privileged histories. Fresh truth-free ', ...
        'online rollouts must repeat the gate before critic work.\n']);
else
    fprintf(fid, ['FAIL: the four linear truth-free score heads do ', ...
        'not reach the 80%% development capture gate. Do not train ', ...
        'a critic or run X36; redesign the proposal model first.\n']);
end
end

function token = formatMatches(indices)
parts = cell(1, numel(indices));
for idx = 1:numel(indices)
    if isfinite(indices(idx))
        parts{idx} = sprintf('%d', indices(idx));
    else
        parts{idx} = '-';
    end
end
token = strjoin(parts, ',');
end

function head = emptyHead()
