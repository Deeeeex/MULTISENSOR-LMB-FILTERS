    'featureMean', [], ...
    'featureScale', [], ...
    'coefficients', [], ...
    'lambda', NaN, ...
    'supervisionMode', '', ...
    'trainingSeeds', [], ...
    'trainingBlockCount', 0, ...
    'positiveTargetBlockCount', 0);
end

function candidate = emptyCandidate()
candidate = struct( ...
    'supervisionMode', '', ...
    'modeOrder', NaN, ...
    'lambda', NaN, ...
    'blockRows', repmat(emptyBlockMetric(), 1, 0), ...
    'targetStateCount', 0, ...
    'capturedTargetStateCount', 0, ...
    'targetStateCaptureFraction', 0, ...
