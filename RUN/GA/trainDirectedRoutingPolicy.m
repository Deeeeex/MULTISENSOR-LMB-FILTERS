function [modelPath, reportPath, result] = ...
    trainDirectedRoutingPolicy(options)
% TRAINDIRECTEDROUTINGPOLICY Fit the experimental v2 joint-action kNN model.
%
% The privileged teacher is used only to create edge-value labels. Model
% inputs contain no truth: they are derived from local LMB posteriors,
% sensor geometry, formation membership, and link reliability.
% This function writes a v2 artifact and intentionally does not overwrite
% the legacy single-snapshot artifact used by the historical
% 'learned-directed-routing' screen arm.

if nargin < 1 || isempty(options)
    options = struct();
end
presetName = getField(options, 'presetName', 'm24-hard');
seed = round(getField(options, 'seed', 7));
snapshotTime = round(getField(options, 'snapshotTime', 75));
artifactDirectory = getField(options, 'artifactDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
cacheDirectory = getField(options, 'cacheDirectory', ...
    fullfile(artifactDirectory, 'cache'));
modelDirectory = getField(options, 'modelDirectory', ...
    fullfile(artifactDirectory, 'models'));
datasetPath = getField(options, 'datasetPath', fullfile( ...
    cacheDirectory, sprintf( ...
        'directed_teacher_v2_%s_seed%d_t%d.mat', ...
        strrep(presetName, '-', '_'), seed, snapshotTime)));
modelPath = getField(options, 'modelPath', fullfile( ...
    modelDirectory, sprintf( ...
        'directed_routing_knn_v2_%s_t%d.mat', ...
        strrep(presetName, '-hard', ''), snapshotTime)));
reportPath = getField(options, 'reportPath', fullfile( ...
    artifactDirectory, 'DIRECTED_ROUTING_MODEL_V2_M24_T75.md'));
regenerateDataset = getField(options, ...
    'regenerateDataset', ~exist(datasetPath, 'file'));
fitModel = getField(options, 'fitModel', true);
teacherLabelVersion = ...
    'joint-action-bernoulli-risk-v3-directed-physical';
expectedScenarioConfig = ...
    buildDynamicTopologyScenarioConfig(presetName);
expectedFusionConfig = ...
    buildMixtureAwareKlaReferenceConfig();

if regenerateDataset
    behaviorCachePath = fullfile(cacheDirectory, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', ...
        strrep(presetName, '-', '_'), seed, snapshotTime));
    if ~exist(behaviorCachePath, 'file')
        error(['Missing behavior cache: %s. Generate the common static ', ...
            'prefix with runDynamicTopologyTeacherSignalScreen first.'], ...
            behaviorCachePath);
    end
    loaded = load(behaviorCachePath, 'behaviorBundle');
    if ~isfield(loaded, 'behaviorBundle')
        error('Behavior cache does not contain behaviorBundle.');
    end
    bundle = loaded.behaviorBundle;
    inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
    validateBehaviorBundle( ...
        bundle, inputs.config, presetName, seed, snapshotTime);
    context = buildTeacherContext( ...
        inputs, bundle.posteriorSnapshots{snapshotTime}, snapshotTime);
    teacherOptions = getField(options, 'teacherOptions', struct( ...
        'maxMessagesPerReceiver', 1, ...
        'sourceWeightGrid', [0.15, 0.30, 0.50, 0.70], ...
        'minimumRelativeNodeGain', 0, ...
        'deliveryExpectationMode', 'bernoulli-risk'));
    [~, teacherDetails] = ...
        selectDirectedTaskRoutingTeacher(context, teacherOptions);
    [features, featureNames, nodeSummary] = ...
        computeDirectedRoutingFeatures(context);
    actionFeatureOptions = struct( ...
        'rawFeatures', features, ...
        'rawFeatureNames', {featureNames});
    [actionFeatures, actionFeatureNames, ...
        actionFeatureMetadata] = ...
        computeScaleInvariantDirectedActionFeatures( ...
            context, teacherDetails.sourceWeightGrid, ...
            actionFeatureOptions);
    datasetMetadata = struct( ...
        'presetName', presetName, ...
        'seed', seed, ...
        'snapshotTime', snapshotTime, ...
        'behaviorCachePath', behaviorCachePath, ...
        'teacherOptions', teacherOptions, ...
        'teacherLabelVersion', ...
            teacherLabelVersion, ...
        'deliveryExpectationMode', ...
            teacherDetails.deliveryExpectationMode, ...
        'physicalAdjacencyConvention', ...
            'receiver-row-sender-column-directed', ...
        'scenarioConfigSnapshot', inputs.config, ...
        'fusionConfigSnapshot', context.triggerConfig, ...
        'truthUsedForLabelsOnly', true, ...
        'featuresUseTruth', false);
    ensureDirectory(fileparts(datasetPath));
    save('-mat7-binary', datasetPath, ...
        'features', 'featureNames', 'nodeSummary', ...
        'actionFeatures', 'actionFeatureNames', ...
        'actionFeatureMetadata', ...
        'teacherDetails', 'datasetMetadata');
end
validateDatasetMetadata( ...
    datasetPath, presetName, seed, snapshotTime, ...
    teacherLabelVersion, expectedScenarioConfig, ...
    expectedFusionConfig);

if ~fitModel
    modelPath = '';
    reportPath = '';
    result = struct( ...
        'datasetPath', datasetPath, ...
        'modelPath', '', ...
        'trainingSummary', struct(), ...
        'model', struct());
    return;
end

fitOptions = getField(options, 'fitOptions', struct());
[model, trainingSummary] = ...
    fitDirectedRoutingKnnModel(datasetPath, fitOptions);
model.trainingMetadata = struct( ...
    'presetName', presetName, ...
    'seed', seed, ...
    'snapshotTime', snapshotTime, ...
    'truthUsedForLabelsOnly', true, ...
    'featuresUseTruth', false);
ensureDirectory(fileparts(modelPath));
save('-mat7-binary', modelPath, 'model', 'trainingSummary');

result = struct();
result.datasetPath = datasetPath;
result.modelPath = modelPath;
result.trainingSummary = trainingSummary;
result.model = model;
writeTrainingReport(reportPath, result);
end

function validateDatasetMetadata( ...
    datasetPath, presetName, seed, snapshotTime, ...
    teacherLabelVersion, expectedScenarioConfig, ...
    expectedFusionConfig)
loaded = load(datasetPath, ...
    'datasetMetadata', 'teacherDetails', ...
    'actionFeatures', 'actionFeatureNames', ...
    'actionFeatureMetadata');
if ~isfield(loaded, 'datasetMetadata') || ...
        ~isstruct(loaded.datasetMetadata)
    error(['Directed-routing dataset predates metadata validation. ', ...
        'Regenerate it with regenerateDataset=true: %s'], datasetPath);
end
metadata = loaded.datasetMetadata;
validIdentity = ...
    isfield(metadata, 'presetName') && ...
    strcmp(metadata.presetName, presetName) && ...
    isfield(metadata, 'seed') && metadata.seed == seed && ...
    isfield(metadata, 'snapshotTime') && ...
    metadata.snapshotTime == snapshotTime;
validLabelVersion = ...
    isfield(metadata, 'teacherLabelVersion') && ...
    strcmp(metadata.teacherLabelVersion, teacherLabelVersion);
validConfiguration = ...
    isfield(metadata, 'physicalAdjacencyConvention') && ...
    strcmp(metadata.physicalAdjacencyConvention, ...
        'receiver-row-sender-column-directed') && ...
    isfield(metadata, 'scenarioConfigSnapshot') && ...
    isequaln(metadata.scenarioConfigSnapshot, ...
        expectedScenarioConfig) && ...
    isfield(metadata, 'fusionConfigSnapshot') && ...
    isequaln(metadata.fusionConfigSnapshot, expectedFusionConfig);
validTeacher = isfield(loaded, 'teacherDetails') && ...
    isfield(loaded.teacherDetails, ...
        'firstStepExpectedRiskByWeight') && ...
    isfield(loaded.teacherDetails, ...
        'firstStepConditionalRiskByWeight') && ...
    isfield(loaded.teacherDetails, 'deliveryExpectationMode') && ...
    strcmp(loaded.teacherDetails.deliveryExpectationMode, ...
        'bernoulli-risk');
validFeatures = isfield(loaded, 'actionFeatures') && ...
    isfield(loaded, 'actionFeatureNames') && ...
    isfield(loaded, 'actionFeatureMetadata') && ...
    isfield(loaded.actionFeatureMetadata, ...
        'scaleInvariantCardinality') && ...
    loaded.actionFeatureMetadata.scaleInvariantCardinality;
if ~validIdentity || ~validLabelVersion || ~validConfiguration || ...
        ~validTeacher || ~validFeatures
    error(['Directed-routing dataset identity or teacher-label ', ...
        'semantics mismatch. Regenerate: %s'], datasetPath);
end
end

function context = buildTeacherContext(inputs, posteriors, snapshotTime)
sensorCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = posteriors;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = snapshotTime;
context.previousAdjacency = inputs.graphData.staticAdjacency;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, snapshotTime);
context.edgeScores = double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * inputs.config.edgeBudget;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, snapshotTime);
end
end

function validateBehaviorBundle( ...
    bundle, config, presetName, seed, snapshotTime)
valid = ...
    strcmp(bundle.presetName, presetName) && ...
    bundle.seed == seed && ...
    isfield(bundle, 'configSnapshot') && ...
    isequaln(bundle.configSnapshot, config) && ...
    numel(bundle.posteriorSnapshots) >= snapshotTime && ...
    ~isempty(bundle.posteriorSnapshots{snapshotTime});
if ~valid
    error('Behavior cache metadata or posterior snapshot mismatches.');
end
end

function writeTrainingReport(path, result)
ensureDirectory(fileparts(path));
fid = fopen(path, 'w');
if fid < 0
    error('Could not open training report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
summary = result.trainingSummary;
cv = summary.crossValidation;
metadata = result.model.trainingMetadata;
fprintf(fid, '# Directed routing model: %s t=%d checkpoint\n\n', ...
    upper(metadata.presetName), metadata.snapshotTime);
fprintf(fid, '- Dataset: `%s`\n', result.datasetPath);
fprintf(fid, '- Model: `%s`\n', result.modelPath);
fprintf(fid, '- Examples: %d directed physical links\n', ...
    summary.exampleCount);
fprintf(fid, '- Receivers: %d\n', summary.receiverCount);
fprintf(fid, '- Features: %d deployment-observable values\n', ...
    numel(summary.featureNames));
fprintf(fid, '- k nearest neighbours: %d\n', ...
    summary.selectedNeighborCount);
fprintf(fid, '- Predicted-gain threshold: %.4f\n', ...
    summary.selectedGainThreshold);
fprintf(fid, '- Minimum positive-neighbour confidence: %.2f\n', ...
    cv.minimumPositiveNeighborFraction);
fprintf(fid, '\n## Receiver-held-out cross-validation\n\n');
fprintf(fid, '- Mean selected receiver gain: %.2f%%\n', ...
    100 * cv.meanSelectedGainFraction);
fprintf(fid, '- Minimum selected receiver gain: %.2f%%\n', ...
    100 * cv.minimumSelectedGainFraction);
fprintf(fid, '- Harmful selected receivers: %.2f%%\n', ...
    100 * cv.negativeSelectionFraction);
fprintf(fid, '- Receivers selecting a source: %.2f%%\n', ...
    100 * cv.receiverSelectionFraction);
fprintf(fid, '- Oracle positive-gain capture: %.2f%%\n', ...
    100 * cv.oracleCaptureFraction);
fprintf(fid, '\n## Boundary\n\n');
fprintf(fid, ['Ground truth is used only by the privileged teacher to ', ...
    'produce training labels. Inference features and routing decisions ', ...
    'do not access target truth. Receiver-held-out folds prevent edges ', ...
    'entering one receiver from appearing in both training and ', ...
    'validation, but this checkpoint is not seed- or time-held-out.\n']);
end

function ensureDirectory(path)
if ~isempty(path) && ~exist(path, 'dir')
    mkdir(path);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
