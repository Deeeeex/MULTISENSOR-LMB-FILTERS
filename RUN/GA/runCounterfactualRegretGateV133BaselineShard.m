function [shardPath, shard] = ...
    runCounterfactualRegretGateV133BaselineShard( ...
        presetName, seed, carrierMode, options)
% RUNCOUNTERFACTUALREGRETGATEV133BASELINESHARD One resumable full arm.

if nargin < 4 || isempty(options)
    options = struct();
end
protocol = getCounterfactualRegretGateV133Protocol();
gitState = resolveResearchGitState();
assertCleanSource(gitState);
[caseInfo, carrierMode] = validateRequest( ...
    protocol, presetName, seed, carrierMode);
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(protocol.outputRoot, 'baseline_selection'));
shardDirectory = fullfile(outputDirectory, 'shards', ...
    strrep(presetName, '-', '_'));
shardPath = fullfile(shardDirectory, sprintf( ...
    'V133_%s_SEED%d_%s.mat', ...
    upper(strrep(presetName, '-', '_')), seed, ...
    upper(strrep(carrierMode, '-', '_'))));
overwrite = logical(getField(options, 'overwrite', false));
if exist(shardPath, 'file') == 2 && ~overwrite
    loaded = load(shardPath, 'shard');
    validateShard(loaded, protocol, caseInfo, seed, carrierMode, gitState);
    shard = loaded.shard;
    fprintf('Reused V133 baseline shard: %s\n', shardPath);
    return;
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
truth = inputs.groundTruthRfs;
inputs = isolateRuntimeInputs(inputs);
context = buildCounterfactualRegretGateV133ExecutionContext( ...
    presetName, seed, 'development', 'baseline-selection', ...
    inputs.config.simulationLength, carrierMode, 0);
config = buildConfig(inputs.config, carrierMode, protocol);
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
elapsedSeconds = toc(timerId);
auditRuntime(diagnostics, inputs.config.simulationLength);
record = scoreRecord(estimates, diagnostics, inputs.model, truth, ...
    inputs.config, seed, carrierMode, elapsedSeconds);

shard = struct( ...
    'contractVersion', ...
        'counterfactual-regret-gate-v133-baseline-shard-v1', ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'carrierMode', carrierMode, ...
    'record', record, ...
    'generationGitCommit', gitState.commit, ...
    'generationTrackedWorktreeDirty', ...
        gitState.trackedWorktreeDirty, ...
    'generationUntrackedSourceFiles', ...
        {gitState.untrackedSourceFiles}, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', ...
        'repository-method-record-until-final-tracking-gate-passes');
if exist(shardDirectory, 'dir') ~= 7
    mkdir(shardDirectory);
end
temporaryPath = [shardPath, '.partial'];
save('-mat7-binary', temporaryPath, 'shard');
[moved, message] = movefile(temporaryPath, shardPath, 'f');
if ~moved
    error('CounterfactualRegretV133:BaselineShardWriteFailed', ...
        'Could not finalize baseline shard: %s', message);
end
fprintf([ ...
    'V133 baseline %s seed %d %s: full %.4f, focus %.4f, ', ...
    '%.1f MB, %.2f s\n'], ...
    caseInfo.scaleName, seed, carrierMode, record.meanEospa, ...
    record.focusMeanEospa, record.attemptedBytes / 1e6, ...
    elapsedSeconds);
fprintf('V133 baseline shard: %s\n', shardPath);
end

function [caseInfo, carrierMode] = validateRequest( ...
        protocol, presetName, seed, carrierMode)
if ~ischar(presetName) || isempty(presetName) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~ismember(seed, protocol.developmentSeeds) || ...
        ~ischar(carrierMode)
    error('CounterfactualRegretV133:InvalidBaselineShardRequest', ...
        'The V133 baseline shard request is malformed.');
end
carrierMode = lower(strrep(char(carrierMode), '_', '-'));
if ~ismember(carrierMode, protocol.referenceCarrierModes)
    error('CounterfactualRegretV133:InvalidBaselineShardRequest', ...
        'The requested carrier is outside the frozen V133 action set.');
end
caseInfo = struct([]);
for candidate = protocol.scaleCases
    if strcmp(candidate.presetName, presetName)
        caseInfo = candidate;
        break;
    end
end
if isempty(caseInfo)
    error('CounterfactualRegretV133:InvalidBaselineShardRequest', ...
        'The requested preset is outside the V133 scale contract.');
end
end

function validateShard( ...
        loaded, protocol, caseInfo, seed, carrierMode, gitState)
required = { ...
    'contractVersion', 'protocolId', 'scaleName', 'presetName', ...
    'seed', 'carrierMode', 'record', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles'};
if ~isstruct(loaded) || ~isfield(loaded, 'shard') || ...
        ~isstruct(loaded.shard) || ~isscalar(loaded.shard) || ...
        ~all(isfield(loaded.shard, required)) || ...
        ~strcmp(loaded.shard.contractVersion, ...
            'counterfactual-regret-gate-v133-baseline-shard-v1') || ...
        ~strcmp(loaded.shard.protocolId, protocol.id) || ...
        ~strcmp(loaded.shard.scaleName, caseInfo.scaleName) || ...
        ~strcmp(loaded.shard.presetName, caseInfo.presetName) || ...
        loaded.shard.seed ~= seed || ...
        ~strcmp(loaded.shard.carrierMode, carrierMode) || ...
        ~strcmp(loaded.shard.generationGitCommit, gitState.commit) || ...
        loaded.shard.generationTrackedWorktreeDirty || ...
        ~isempty(loaded.shard.generationUntrackedSourceFiles)
    error('CounterfactualRegretV133:BaselineShardProvenanceDrift', ...
        'An existing V133 baseline shard does not match this clean source.');
end
end

function assertCleanSource(gitState)
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('CounterfactualRegretV133:DirtySource', ...
        'Generate official V133 baseline shards only from clean source.');
end
end

function config = buildConfig(scenarioConfig, carrierMode, protocol)
config = buildMixtureAwareKlaReferenceConfig(struct( ...
    'missingLabelFusionMode', 'fov-aware-censored', ...
    'missingNeighborWeightMode', ...
        protocol.actionContract.primaryMissingNeighborWeightMode));
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * scenarioConfig.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicySensorObservationEnabled = true;
config.topologyPolicyName = protocol.outcomePolicyName;
config.v133ReferenceCarrierMode = carrierMode;
config.topologyPolicyFcn = @(context) ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, carrierMode, protocol.routeWeights);
config.receiverSafeLabelFusionEnabled = false;
end

function record = scoreRecord( ...
        estimates, diagnostics, model, truth, scenarioConfig, ...
        seed, carrierMode, elapsedSeconds)
nodeCount = numel(estimates);
timeCount = numel(truth.x);
eospa = zeros(nodeCount, timeCount);
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, ~] = computeSimulationOspa( ...
        model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa;
end
focusWindow = scenarioConfig.focusWindow(1): ...
    scenarioConfig.focusWindow(2);
focusEospa = eospa(:, focusWindow);
record = struct( ...
    'seed', seed, ...
    'carrierMode', carrierMode, ...
    'meanEospa', mean(eospa(:)), ...
    'focusMeanEospa', mean(focusEospa(:)), ...
    'worstSensorEospa', max(mean(eospa, 2)), ...
    'attemptedBytes', sum(diagnostics.attemptedPayloadBytes(:)), ...
    'deliveredBytes', sum(diagnostics.payloadBytes(:)), ...
    'elapsedSeconds', elapsedSeconds, ...
    'policyTruthUsed', any(finiteLogical( ...
        diagnostics.topologyPolicyTruthUsed)), ...
    'policyFutureOutcomeUsed', false);
end

function auditRuntime(diagnostics, timeCount)
times = 1:timeCount;
if any(finiteLogical(diagnostics.topologyPolicyTruthUsed(times))) || ...
        any(finiteLogical( ...
            diagnostics.topologyPolicyRepairTriggered(times))) || ...
        any(finiteLogical( ...
            diagnostics.topologyPolicyPayloadEmergencyUsed(times))) || ...
        any(~diagnostics.topologyFeasible(times)) || ...
        any(finiteLogical(diagnostics. ...
            topologyPolicyTopologyInfeasible(times)))
    error('CounterfactualRegretV133:BaselineRuntimeGateFailure', ...
        'A V133 fixed carrier violated a hard runtime gate.');
end
end

function inputs = isolateRuntimeInputs(inputs)
inputs = rmfield(inputs, { ...
    'groundTruth', 'groundTruthRfs', 'targetTrajectories'});
model = inputs.model;
if isfield(model, 'explicitTargetTrajectories')
    model = rmfield(model, 'explicitTargetTrajectories');
end
present = intersect({'targetTrajectories', 'target'}, ...
    fieldnames(model.dynamicTopologyScenario), 'stable');
if ~isempty(present)
    model.dynamicTopologyScenario = rmfield( ...
        model.dynamicTopologyScenario, present);
end
inputs.model = model;
end

function value = finiteLogical(value)
value = isfinite(value) & value ~= 0;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
