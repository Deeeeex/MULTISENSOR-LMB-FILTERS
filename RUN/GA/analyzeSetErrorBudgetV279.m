function [reportPath, result] = analyzeSetErrorBudgetV279(paths)
% ANALYZESETERRORBUDGETV279 Post-hoc set-error budget; no filter is rerun.
% Reconstruct count possibilities from stored E-OSPA, absolute count error
% and matched RMSE. Retain intervals whenever the count sign is ambiguous.
if nargin < 1
    base='/Users/dex/.config/superpowers/worktrees/MULTISENSOR-LMB-FILTERS';
    paths={ ...
        fullfile(base,'v248-temporal-coupled-routing','RUN','GA', ...
        'dynamic_topology','evidence','tracking_aligned_v248', ...
        'm24_temporal_task_coupled_formation_braid_seed1301', ...
        'minimum_causal_backbone', ...
        'CAUSAL_MINIMUM_FORMATION_BACKBONE_V242_FULL_EPISODE.mat'), ...
        fullfile(base,'v274-x36-minimum-backbone','RUN','GA', ...
        'dynamic_topology','evidence','tracking_aligned_v274', ...
        'x36_minimum_backbone_seed1301','minimum_causal_backbone', ...
        'CAUSAL_MINIMUM_FORMATION_BACKBONE_V242_FULL_EPISODE.mat')};
end
result=struct('analysis','set-error-budget-v279-v1', ...
    'sourcePaths',{paths},'filterRerun',false,'postHoc',true, ...
    'independentValidation',false);
keys={'referenceFixedTree','referenceFullCausal','candidate'};
names={'Fixed tree','Full causal repair','Sparse causal repair'};
result.scenes=cell(size(paths));
for sceneIdx=1:numel(paths)
    loaded=load(paths{sceneIdx},'result'); source=loaded.result;
    % Recreate only scene inputs, to obtain exact truth cardinality by time.
    % No posterior, local update, fusion, route or estimator is evaluated.
    inputs=generateDynamicTopologyScenarioInputs(source.presetName,source.seed);
    truthCounts=cellfun(@numel,inputs.groundTruthRfs.x);
    c=inputs.config.ospaPositionCutoff;
    scene=struct('preset',source.presetName,'seed',source.seed, ...
        'sourceCommit',source.generationGitCommit,'truthCounts',truthCounts, ...
        'cutoff',c,'armNames',{names});
    for armIdx=1:numel(keys)
        a=source.(keys{armIdx}); b=source.referenceFixedTree;
        e=a.positionEospaBySensorTime;
        r=a.positionRmseBySensorTime;
        d=a.absoluteCardinalityErrorBySensorTime;
        assert(isequal(size(e),size(r),size(d)));
        assert(size(e,2)==numel(truthCounts));
        ntruth=repmat(reshape(truthCounts,1,[]),size(e,1),1);
        [lo,hi,count,ambiguous]=countErrorPowerBounds(e,r,d,ntruth,c);
        mask=isfinite(r)&isfinite(b.positionRmseBySensorTime);
        stats=struct('name',names{armIdx},'meanEospa',mean(e(:)), ...
            'meanRmse',finiteMean(r(:)), ...
            'finiteRmseFraction',mean(isfinite(r(:))), ...
            'commonFiniteFraction',mean(mask(:)), ...
            'commonCellRmse',mean(r(mask)), ...
            'fixedCommonCellRmse',mean(b.positionRmseBySensorTime(mask)), ...
            'meanCardinalityError',mean(d(:)), ...
            'cardinalitySquaredErrorShareLower',sum(lo(:))/sum(e(:).^2), ...
            'cardinalitySquaredErrorShareUpper',sum(hi(:))/sum(e(:).^2), ...
            'perfectLocalizationFloorLower',mean(sqrt(lo(:))), ...
            'perfectLocalizationFloorUpper',mean(sqrt(hi(:))), ...
            'identifiedCountFraction',mean(~ambiguous(:)), ...
            'identifiedUnderCount',nnz(count<ntruth), ...
            'identifiedEqualCount',nnz(count==ntruth), ...
            'identifiedOverCount',nnz(count>ntruth), ...
            'ambiguousCount',nnz(ambiguous), ...
            'sensorTimeCount',numel(e), ...
            'cardinalityPowerLower',lo,'cardinalityPowerUpper',hi, ...
            'inferredEstimateCount',count);
        stats.commonCellRmseGain=100*( ...
            stats.fixedCommonCellRmse-stats.commonCellRmse)/ ...
            stats.fixedCommonCellRmse;
        stats.maxEospaGainFromLocalizationOnly= ...
            stats.meanEospa-stats.perfectLocalizationFloorLower;
        scene.arms{armIdx}=stats;
        fprintf('%s | %s | finite %.3f%% | common RMSE gain %.3f%% | count share %.3f--%.3f%% | localization-only room %.3f m | ambiguous %d\n', ...
            source.presetName,names{armIdx},100*stats.finiteRmseFraction, ...
            stats.commonCellRmseGain,100*stats.cardinalitySquaredErrorShareLower, ...
            100*stats.cardinalitySquaredErrorShareUpper, ...
            stats.maxEospaGainFromLocalizationOnly,stats.ambiguousCount);
    end
    result.scenes{sceneIdx}=scene;
end
root=fullfile('RUN','GA','dynamic_topology','evidence', ...
    'tracking_aligned_v279','set_error_budget_seed1301');
if exist(root,'dir')~=7,mkdir(root);end
reportPath=fullfile(root,'SET_ERROR_BUDGET_V279.md');
save('-mat7-binary',fullfile(root,'SET_ERROR_BUDGET_V279.mat'),'result');
writeReport(reportPath,result);
end

function [lo,hi,count,ambiguous]=countErrorPowerBounds(e,r,d,ntruth,c)
% For either possible estimate count n = truth +/- abs-count-error,
% c^2*d/max(n,truth) <= OSPA^2 <= that + min(n,truth)/max(n,truth)*RMSE^2.
% The upper bound uses the RMSE assignment as a feasible OSPA assignment;
% the two Hungarian objectives need not return the same assignment.
lo=zeros(size(e));hi=lo;count=nan(size(e));ambiguous=false(size(e));
tol=1e-8*c^2;
for idx=1:numel(e)
    candidates=unique([ntruth(idx)-d(idx),ntruth(idx)+d(idx)]);
    candidates=candidates(candidates>=0);
    feasible=[];powers=[];
    for n=candidates
        maxCount=max(ntruth(idx),n); minCount=min(ntruth(idx),n);
        if maxCount==0
            power=0; upper=0;
        else
            power=c^2*d(idx)/maxCount;
            if minCount==0
                upper=power;
                % A nonempty-vs-empty comparison has NaN RMSE in this code.
                if isfinite(r(idx)),continue;end
            elseif isfinite(r(idx))
                upper=power+minCount/maxCount*min(c^2,r(idx)^2);
            else
                continue;
            end
        end
        if e(idx)^2>=power-tol && e(idx)^2<=upper+tol
            feasible(end+1)=n; powers(end+1)=power; %#ok<AGROW>
        end
    end
    assert(~isempty(feasible),'Stored metrics do not satisfy the count bounds.');
    lo(idx)=min(powers);hi(idx)=max(powers);
    ambiguous(idx)=numel(feasible)>1;
    if ~ambiguous(idx),count(idx)=feasible(1);end
end
end

function writeReport(path,result)
fid=fopen(path,'w');assert(fid>=0);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'# V279: where the current set error comes from\n\n');
fprintf(fid,['Post-hoc analysis of the saved paired 160-step, seed-1301 results. ', ...
    'No filter was rerun and no policy or selection gate was changed. ', ...
    'Scene inputs were regenerated only to read the true cardinality at each time.\n\n']);
fprintf(fid,'| Scale | Arm | E-OSPA | Finite RMSE cells | Same-cell RMSE / fixed | Same-cell RMSE gain | Count share of squared OSPA | Perfect-localization E-OSPA floor |\n');
fprintf(fid,'|:--|:--|--:|--:|:--|--:|:--|:--|\n');
for i=1:numel(result.scenes)
    scene=result.scenes{i};
    for j=1:numel(scene.arms)
        a=scene.arms{j};
        fprintf(fid,'| N=%d | %s | %.3f | %.3f%% | %.3f / %.3f | %+.3f%% | %.3f--%.3f%% | %.3f--%.3f m |\n', ...
            size(a.inferredEstimateCount,1),a.name,a.meanEospa, ...
            100*a.finiteRmseFraction,a.commonCellRmse,a.fixedCommonCellRmse, ...
            a.commonCellRmseGain,100*a.cardinalitySquaredErrorShareLower, ...
            100*a.cardinalitySquaredErrorShareUpper, ...
            a.perfectLocalizationFloorLower,a.perfectLocalizationFloorUpper);
    end
end
fprintf(fid,'\n## Count reconstruction and boundaries\n\n');
fprintf(fid,['For true count T, absolute count error d and candidate estimate ', ...
    'count n in {T-d,T+d}, squared OSPA is c^2*d/max(T,n) plus a nonnegative ', ...
    'localization term. A feasible upper bound for that term is ', ...
    'min(T,n)/max(T,n) * min(RMSE^2,c^2), using the stored RMSE matching. ', ...
    'This bound does not require the two Hungarian assignments to coincide. ', ...
    'We eliminate count possibilities inconsistent with these bounds, and ', ...
    'retain an interval whenever both are possible. NaN RMSE and nonzero ', ...
    'true count identify an empty estimate under the recorded metric definition.\n\n']);
fprintf(fid,'| Scale | Arm | Identified below / equal / above true count | Ambiguous | Total sensor-time cells | Maximum mean E-OSPA reduction from localization alone |\n');
fprintf(fid,'|:--|:--|:--|--:|--:|--:|\n');
for i=1:numel(result.scenes)
    scene=result.scenes{i};
    for j=1:numel(scene.arms)
        a=scene.arms{j};
        fprintf(fid,'| N=%d | %s | %d / %d / %d | %d | %d | %.3f m |\n', ...
            size(a.inferredEstimateCount,1),a.name,a.identifiedUnderCount, ...
            a.identifiedEqualCount,a.identifiedOverCount,a.ambiguousCount, ...
            a.sensorTimeCount,a.maxEospaGainFromLocalizationOnly);
    end
end
fprintf(fid,['\nThe count share is a ratio of summed squared errors, not a ', ...
    'percentage decomposition of mean E-OSPA. The perfect-localization floor ', ...
    'is a hypothetical bound with each cell\x27s cardinality unchanged, not ', ...
    'an achievable routing result. Same-cell RMSE restricts both arms to cells ', ...
    'with finite RMSE; it does not guarantee the same target identities or ', ...
    'remove all matching-selection effects. This is one-seed development ', ...
    'evidence and an algebraic readout, not causal attribution to a specific edge.\n\n']);
fprintf(fid,'## Sources\n\n');
for i=1:numel(result.scenes)
    fprintf(fid,'- `%s`; source commit `%s`.\n', ...
        result.sourcePaths{i},result.scenes{i}.sourceCommit);
end
fprintf(fid,['\nMetric definitions: `common/computePositionEuclideanOspa.m`, ', ...
    '`common/computeSetRmseOverTime.m`, and ', ...
    '`common/summarizeRepeatedMultiGatewayFullEpisodeArm.m`.\n']);
end

function value=finiteMean(values)
values=values(isfinite(values));value=mean(values);
end
