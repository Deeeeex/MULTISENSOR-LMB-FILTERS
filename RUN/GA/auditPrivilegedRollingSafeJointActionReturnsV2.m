function [reportPath, audit] = ...
    auditPrivilegedRollingSafeJointActionReturnsV2(options)
% AUDITPRIVILEGEDROLLINGSAFEJOINTACTIONRETURNSV2 V2 development gate.
%
% Reinterprets only projection activations after the exact, repair-free
% first action as legal receding-horizon safety adaptation. All mean,
% tail, byte, emergency, infeasibility and selected rolling-B3 gates remain
% unchanged. The source is the frozen v1 audit, so this is explicitly a
% design-seen development reanalysis and never a validation result.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
sourceAuditPath = getField(options, 'sourceAuditPath', ...
    protocol.privilegedReturnV1AuditRelativePath);
if exist(sourceAuditPath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(sourceAuditPath), ...
            protocol.privilegedReturnV1AuditSha256)
    error('The frozen privileged v1 audit is missing or mismatched.');
end
loaded = load(sourceAuditPath, 'audit');
if ~isfield(loaded, 'audit')
    error('The privileged v1 audit MAT lacks audit.');
end
source = loaded.audit;
validateSourceAudit(source, protocol);

stateRows = source.stateRows;
candidateRows = source.candidateRows;
referenceMean = mean([stateRows.referenceMeanEospa]);
oracleMean = mean( ...
    [stateRows.repairMonitoredOracleMeanEospa]);
referenceAttemptedBytes = sum( ...
    [stateRows.referenceAttemptedBytes]);
oracleAttemptedBytes = sum( ...
    [stateRows.repairMonitoredOracleAttemptedBytes]);
aggregateGainFraction = safeRelativeReduction( ...
    referenceMean, oracleMean);
aggregateByteDeviationFraction = safeRelativeDeviation( ...
    referenceAttemptedBytes, oracleAttemptedBytes);
allTailNondegrading = all( ...
    [stateRows.repairMonitoredOracleTailNondegrading]);
allFeasible = all( ...
    [stateRows.repairMonitoredOracleFeasible]);
statesWithFivePercentTarget = nnz( ...
    [stateRows.repairMonitoredHasAdmissibleFivePercentAction]);
valueFilteredTargetMask = ...
    [candidateRows.repairMonitoredAdmissibleFivePercentGain];
valueFilteredTargetCount = nnz(valueFilteredTargetMask);
returnGatePassed = ...
    aggregateGainFraction >= ...
        protocol.minimumCandidateOracleAggregateGain && ...
    aggregateByteDeviationFraction <= ...
        protocol.maximumAttemptedByteDeviationFraction && ...
    allTailNondegrading && allFeasible;
if ~returnGatePassed
    error(['The v2 development reanalysis does not support ', ...
        'value-filtered proposal distillation.']);
end

audit = struct();
audit.protocolId = protocol.id;
audit.contractVersion = ...
    protocol.privilegedReturnV2AuditContractVersion;
audit.generatedAt = datestr(now, 31);
audit.sourceAuditPath = sourceAuditPath;
audit.sourceAuditSha256 = ...
    protocol.privilegedReturnV1AuditSha256;
audit.sourceShardSetSha256 = ...
    source.sourceShardSetSha256;
audit.sourceGenerationCommits = ...
    source.sourceGenerationCommits;
audit.seeds = source.seeds;
audit.times = source.times;
audit.completeOfficialGrid = ...
    source.completeOfficialGrid;
audit.stateRows = stateRows;
audit.candidateRows = candidateRows;
audit.referenceMeanEospa = referenceMean;
audit.candidateOracleMeanEospa = oracleMean;
audit.candidateOracleAggregateGainFraction = ...
    aggregateGainFraction;
audit.referenceAttemptedBytes = ...
    referenceAttemptedBytes;
audit.candidateOracleAttemptedBytes = ...
    oracleAttemptedBytes;
audit. ...
    candidateOracleAttemptedByteDeviationFraction = ...
        aggregateByteDeviationFraction;
audit.allOracleTailNondegrading = ...
    allTailNondegrading;
audit.allOracleSafetyPassed = allFeasible;
audit.statesWithAdmissibleFivePercentAction = ...
    statesWithFivePercentTarget;
audit.valueFilteredTargetCount = ...
    valueFilteredTargetCount;
audit.candidateOracleReturnGatePassed = ...
    returnGatePassed;
audit.firstActionExactRequired = ...
    protocol.privilegedReturnV2FirstActionExactRequired;
audit.firstActionRepairAllowed = ...
    protocol.privilegedReturnV2FirstActionRepairAllowed;
audit.laterProjectionRepairAllowed = ...
    protocol.privilegedReturnV2LaterProjectionRepairAllowed;
audit.developmentReanalysis = ...
    protocol.privilegedReturnV2DevelopmentReanalysis;
audit.validationClaimAllowed = ...
    protocol.privilegedReturnV2ValidationClaimAllowed;
audit.valueFilteredProposalDistillationAuthorized = ...
    returnGatePassed;
audit.proposalModelTrainingCompleted = false;
audit.topKCaptureEvaluated = false;
audit.criticTrainingAuthorized = false;
audit.x36Authorized = false;
audit.evidenceBoundary = [ ...
    'This v2 result reuses design-seen v1 M24 returns after the ', ...
    'continuation-repair sensitivity was inspected. It freezes a ', ...
    'method rule for future work: the proposed first graph must be ', ...
    'exact and repair-free, while later exact safety-projection ', ...
    'activation is legal and remains subject to tail, byte, B3, ', ...
    'emergency and infeasibility gates. Passing authorizes only ', ...
    'value-filtered proposal distillation on development data; it ', ...
    'does not validate a proposal model, critic, unseen M24 or X36.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'PRIVILEGED_JOINT_ACTION_PAIRED_RETURN_AUDIT_M24_H3_V2.md'));
auditPath = getField(options, 'auditPath', fullfile( ...
    outputDirectory, ...
    'privileged_joint_action_paired_return_audit_m24_h3_v2.mat'));
audit.reportPath = reportPath;
audit.auditPath = auditPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit, protocol);
fprintf(['Privileged v2 return audit: gain %.3f%%, ', ...
    'byte deviation %.3f%%, states >=5%% %d/%d, ', ...
    'targets %d, gate=%d\nReport: %s\nAudit: %s\n'], ...
    100 * aggregateGainFraction, ...
    100 * aggregateByteDeviationFraction, ...
    statesWithFivePercentTarget, numel(stateRows), ...
    valueFilteredTargetCount, returnGatePassed, ...
    reportPath, auditPath);
end

function validateSourceAudit(source, protocol)
if ~strcmp(source.contractVersion, ...
        protocol.privilegedReturnAuditContractVersion) || ...
        ~strcmp(source.proposalRole, 'privileged') || ...
        ~source.completeOfficialGrid || ...
        ~isequal(source.seeds, protocol.datasetSeeds) || ...
        ~isequal(source.times, protocol.snapshotTimes) || ...
        ~strcmp(source.sourceShardSetSha256, ...
            protocol.privilegedReturnShardSetSha256) || ...
        ~isequal(source.sourceGenerationCommits, ...
            {protocol.privilegedReturnGenerationCommit}) || ...
        ~strcmp(source.proposalDatasetSha256, ...
            protocol.privilegedProposalDatasetSha256) || ...
        source.candidateOracleReturnGatePassed || ...
        numel(source.stateRows) ~= 18 || ...
        numel(source.candidateRows) ~= ...
            protocol.privilegedProposalExpectedTargetCount
    error('The privileged v1 audit violates the frozen v2 source.');
end
requiredStateFields = { ...
    'repairMonitoredOracleMeanEospa', ...
    'repairMonitoredOracleAttemptedBytes', ...
    'repairMonitoredOracleTailNondegrading', ...
    'repairMonitoredOracleFeasible', ...
    'repairMonitoredHasAdmissibleFivePercentAction'};
for fieldIdx = 1:numel(requiredStateFields)
    if ~isfield(source.stateRows, ...
            requiredStateFields{fieldIdx})
        error('The v1 audit lacks state field %s.', ...
            requiredStateFields{fieldIdx});
    end
end
if ~isfield(source.candidateRows, ...
        'repairMonitoredAdmissibleFivePercentGain')
    error('The v1 audit lacks value-filtered candidate labels.');
end
end

function writeReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open privileged v2 report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# M24 privileged paired H=3 return audit: v2 semantics\n\n');
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source v1 audit SHA-256: `%s`\n', ...
    audit.sourceAuditSha256);
fprintf(fid, '- Raw shard-set SHA-256: `%s`\n', ...
    audit.sourceShardSetSha256);
fprintf(fid, '- Development reanalysis: `%d`\n', ...
    audit.developmentReanalysis);
fprintf(fid, '- Validation claim allowed: `%d`\n', ...
    audit.validationClaimAllowed);
fprintf(fid, '- First graph exact required: `%d`\n', ...
    audit.firstActionExactRequired);
fprintf(fid, '- First-step repair allowed: `%d`\n', ...
    audit.firstActionRepairAllowed);
fprintf(fid, '- Later exact projection activation allowed: `%d`\n', ...
    audit.laterProjectionRepairAllowed);
fprintf(fid, '- Reference mean E-OSPA: `%.6f`\n', ...
    audit.referenceMeanEospa);
fprintf(fid, '- Candidate-oracle mean E-OSPA: `%.6f`\n', ...
    audit.candidateOracleMeanEospa);
fprintf(fid, '- Candidate-oracle aggregate gain: `%.3f%%`\n', ...
    100 * audit.candidateOracleAggregateGainFraction);
fprintf(fid, '- Attempted-byte deviation: `%.3f%%`\n', ...
    100 * audit. ...
        candidateOracleAttemptedByteDeviationFraction);
fprintf(fid, '- All oracle tail nondegrading: `%d`\n', ...
    audit.allOracleTailNondegrading);
fprintf(fid, '- All oracle safety gates passed: `%d`\n', ...
    audit.allOracleSafetyPassed);
fprintf(fid, '- States with an admissible >=5%% target: `%d / %d`\n', ...
    audit.statesWithAdmissibleFivePercentAction, ...
    numel(audit.stateRows));
fprintf(fid, '- Value-filtered candidate targets: `%d`\n', ...
    audit.valueFilteredTargetCount);
fprintf(fid, '- Candidate-oracle return gate passed: `%d`\n', ...
    audit.candidateOracleReturnGatePassed);
fprintf(fid, ...
    '- Value-filtered proposal distillation authorized: `%d`\n', ...
    audit.valueFilteredProposalDistillationAuthorized);
fprintf(fid, '- Proposal model training completed: `%d`\n', ...
    audit.proposalModelTrainingCompleted);
fprintf(fid, '- Top-K capture evaluated: `%d`\n', ...
    audit.topKCaptureEvaluated);
fprintf(fid, '- Critic training authorized: `%d`\n', ...
    audit.criticTrainingAuthorized);
fprintf(fid, '- X36 authorized: `%d`\n', ...
    audit.x36Authorized);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    audit.evidenceBoundary);
fprintf(fid, '## State-matched v2 oracle\n\n');
fprintf(fid, ...
    ['| Seed | Time | Candidates | V2 feasible | >=5%% | ', ...
     'Reference | Oracle | Gain | Oracle index/code | ', ...
     'Byte deviation | Tail pass |\n']);
fprintf(fid, ...
    '|--:|--:|--:|--:|--:|--:|--:|--:|:--|--:|--:|\n');
for row = audit.stateRows
    fprintf(fid, ...
        ['| %d | %d | %d | %d | %d | %.6f | %.6f | ', ...
         '%.3f%% | `%d / %02d` | %.3f%% | %d |\n'], ...
        row.seed, row.currentTime, row.candidateCount, ...
        row.repairMonitoredFeasibleCandidateCount, ...
        row. ...
            repairMonitoredAdmissibleFivePercentCandidateCount, ...
        row.referenceMeanEospa, ...
        row.repairMonitoredOracleMeanEospa, ...
        100 * row.repairMonitoredOracleGainFraction, ...
        row.repairMonitoredOracleCandidateIndex, ...
        row.repairMonitoredOracleActionCode, ...
        100 * row. ...
            repairMonitoredOracleAttemptedByteDeviationFraction, ...
        row.repairMonitoredOracleTailNondegrading);
end
fprintf(fid, '\n## Frozen gates\n\n');
fprintf(fid, '- Minimum aggregate gain: `%.1f%%`\n', ...
    100 * protocol.minimumCandidateOracleAggregateGain);
fprintf(fid, '- Maximum attempted-byte deviation: `%.1f%%`\n', ...
    100 * protocol.maximumAttemptedByteDeviationFraction);
fprintf(fid, '- Tail nondegradation required: `%d`\n', ...
    protocol.requireTailNondegradation);
end

function value = safeRelativeReduction(reference, candidate)
if reference <= 0
    value = 0;
else
    value = (reference - candidate) / reference;
end
end

function value = safeRelativeDeviation(reference, candidate)
if reference <= 0
    value = double(candidate ~= reference) * inf;
else
    value = abs(candidate - reference) / reference;
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
