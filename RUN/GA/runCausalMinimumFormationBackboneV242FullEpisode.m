function [reportPath, result] = ...
        runCausalMinimumFormationBackboneV242FullEpisode(options)
% RUNCAUSALMINIMUMFORMATIONBACKBONEV242FULLEPISODE Run only sparse arm.
%
% A completed V241 pair is reused as the fixed-tree and 2N causal
% references.  By default the V242 arm cannot start unless V241 causal
% repair improves E-OSPA, RMSE and focus consistency over its fixed tree.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCausalMinimumFormationBackboneV242Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('CausalMinimumFormationBackboneV242:DirtySource', ...
        'The V242 full episode requires clean tracked source.');
end
presetName = char(getField(options, 'presetName', ...
    'm24-formation-fov-formation-braid'));
seed = getField(options, 'seed', protocol.allowedSeeds(1));
referenceResultPath = char(getField( ...
    options, 'referenceResultPath', ''));
requirePositiveReference = logical(getField( ...
    options, 'requirePositiveReference', true));
resume = logical(getField(options, 'resume', true));
if ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds) || ...
        isempty(referenceResultPath) || ...
        ~islogical(requirePositiveReference) || ...
        ~isscalar(requirePositiveReference) || ...
        ~islogical(resume) || ~isscalar(resume)
    error('CausalMinimumFormationBackboneV242:InvalidOptions', ...
        'V242 requires a registered case and completed V241 result path.');
end
if exist(referenceResultPath, 'file') ~= 2
    error('CausalMinimumFormationBackboneV242:MissingReference', ...
        'The completed V241 reference result does not exist.');
end
referenceEnvelope = load(referenceResultPath, 'result');
reference = referenceEnvelope.result;
validateReference(reference, presetName, seed);
referenceMechanismGatePassed = ...
    reference.causalOverStaticDropout.meanDirectionPassed && ...
    reference.causal.instantaneousStrongAllTimes && ...
    reference.staticDropout.instantaneousStrongFraction < 1;
if requirePositiveReference && ~referenceMechanismGatePassed
    error('CausalMinimumFormationBackboneV242:ReferenceGateFailed', ...
        ['V241 did not establish positive tracking and consistency value; ', ...
         'the sparse V242 full episode is not justified.']);
end

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, sprintf('%s_seed%d', ...
        strrep(presetName, '-', '_'), seed))));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'CAUSAL_MINIMUM_FORMATION_BACKBONE_V242_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'CAUSAL_MINIMUM_FORMATION_BACKBONE_V242_FULL_EPISODE.md');
result = initializeResult(protocol, gitState.commit, presetName, seed, ...
    referenceResultPath, reference, referenceMechanismGatePassed, ...
    matPath, reportPath);
if resume && exist(matPath, 'file') == 2
    loaded = load(matPath, 'result');
    validateExisting(loaded.result, result);
    result = loaded.result;
end
if armComplete(result.candidate)
    fprintf('Reused completed V242 result: %s\n', reportPath);
    return;
end

fprintf('\nV242 causal minimum formation backbone: %s seed %d\n', ...
    presetName, seed);
[~, preflight] = ...
    runCausalMinimumFormationBackboneV242StructuralPreflight( ...
        struct('presetNames', {{presetName}}, 'seed', seed, ...
            'writeReport', false));
result.preflight = preflight;
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
filterModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
representatives = selectFormationRepresentativesLocal( ...
    inputs.config.sensorGroupIds);
metricWindow = struct( ...
    'activationStartTime', inputs.config.focusWindow(1), ...
    'activationEndTime', inputs.config.focusWindow(end));
config = buildCausalMinimumFormationBackboneV242Config(inputs.config);
context = buildCausalMinimumFormationBackboneV242ExecutionContext( ...
    presetName, seed, inputs.config.simulationLength);
rng(seed + protocol.filterSeedOffset, 'twister');
timerId = tic;
fprintf('  running sparse causal full episode ...\n');
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        filterModel, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config, context);
candidate = summarizeRepeatedMultiGatewayFullEpisodeArm( ...
    protocol.armId, estimates, diagnostics, inputs.groundTruthRfs, ...
    inputs.config, representatives, metricWindow, toc(timerId));
candidate = attachTopologySummary( ...
    candidate, diagnostics, inputs.config);
assertRuntimeArm(candidate, inputs.config);
result.candidate = candidate;
result.candidateOverFixedTree = ...
    compareArm(candidate, reference.staticDropout);
result.candidateOverFullCausal = ...
    compareArm(candidate, reference.causal);
result.goalDirectionPassed = ...
    result.candidateOverFixedTree.meanDirectionPassed && ...
    result.candidateOverFixedTree.attemptedByteSavingPercent > 0;
result.paperThresholdPassed = ...
    result.candidateOverFixedTree.fullHorizonEospaGainPercent >= 5 && ...
    result.candidateOverFixedTree.fullHorizonRmseGainPercent >= 5 && ...
    result.candidateOverFixedTree.focusConsensusGainPercent >= 2 && ...
    result.candidateOverFixedTree.attemptedByteSavingPercent >= 1 && ...
    result.candidateOverFixedTree.nonnegativeFormationTailPassed;
result.completedAt = datestr(now, 31);
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf(['  V242 E-OSPA %.3f; RMSE %.3f; focus consensus %.3f; ', ...
    'bytes %.0f; messages %d; %.1f s\n'], ...
    candidate.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionRmse, ...
    candidate.focusInterFormationPositionOspa, ...
    candidate.attemptedPayloadBytes, ...
    candidate.routeMessageCountMinimum, candidate.elapsedSeconds);
fprintf('V242 result: %s\n', reportPath);
end

function validateReference(reference, presetName, seed)
required = {'contractVersion', 'generationGitCommit', ...
    'presetName', 'seed', 'causalStaticPairAvailable', ...
    'staticDropout', 'causal', 'causalOverStaticDropout'};
valid = isstruct(reference) && isscalar(reference) && ...
    all(isfield(reference, required)) && ...
    strcmp(reference.contractVersion, ...
        'formation-braid-routing-comparison-v241-full-episode-result-v1') && ...
    strcmp(reference.presetName, presetName) && ...
    reference.seed == seed && ...
    logical(reference.causalStaticPairAvailable) && ...
    armComplete(reference.staticDropout) && ...
    armComplete(reference.causal) && ...
    isstruct(reference.causalOverStaticDropout) && ...
    isfield(reference.causalOverStaticDropout, 'meanDirectionPassed');
if ~valid
    error('CausalMinimumFormationBackboneV242:InvalidReference', ...
        'The supplied V241 result is incomplete or belongs to another case.');
end
end

function result = initializeResult(protocol, commit, presetName, seed, ...
        referencePath, reference, mechanismPassed, matPath, reportPath)
result = struct();
result.contractVersion = ...
    'causal-minimum-formation-backbone-v242-full-episode-result-v1';
result.protocolId = protocol.id;
result.protocol = protocol;
result.startedAt = datestr(now, 31);
result.completedAt = '';
result.generationGitCommit = commit;
result.presetName = presetName;
result.seed = seed;
result.v241ReferenceResultPath = referencePath;
result.v241ReferenceGenerationGitCommit = ...
    reference.generationGitCommit;
result.referenceMechanismGatePassed = mechanismPassed;
result.referenceFixedTree = reference.staticDropout;
result.referenceFullCausal = reference.causal;
result.preflight = struct();
result.candidate = struct();
result.candidateOverFixedTree = struct();
result.candidateOverFullCausal = struct();
result.goalDirectionPassed = false;
result.paperThresholdPassed = false;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.matPath = matPath;
result.reportPath = reportPath;
result.evidenceBoundary = protocol.evidenceBoundary;
end

function validateExisting(actual, expected)
required = {'contractVersion', 'protocolId', 'generationGitCommit', ...
    'presetName', 'seed', 'v241ReferenceResultPath', ...
    'v241ReferenceGenerationGitCommit', 'candidate'};
if ~isstruct(actual) || ~isscalar(actual) || ...
        ~all(isfield(actual, required)) || ...
        ~strcmp(actual.contractVersion, expected.contractVersion) || ...
        ~strcmp(actual.protocolId, expected.protocolId) || ...
        ~strcmp(actual.generationGitCommit, ...
            expected.generationGitCommit) || ...
        ~strcmp(actual.presetName, expected.presetName) || ...
        actual.seed ~= expected.seed || ...
        ~strcmp(actual.v241ReferenceResultPath, ...
            expected.v241ReferenceResultPath) || ...
        ~strcmp(actual.v241ReferenceGenerationGitCommit, ...
            expected.v241ReferenceGenerationGitCommit)
    error('CausalMinimumFormationBackboneV242:InvalidResumeState', ...
        'The V242 checkpoint belongs to another source or reference.');
end
end

function arm = attachTopologySummary(arm, diagnostics, config)
pages = logical(diagnostics.topologyActiveEdge);
arm.uniqueTopologyCount = uniquePageCount(pages);
arm.topologyChangeCount = pageChangeCount(pages);
arm.routeMessageCountByTime = reshape( ...
    diagnostics.topologyDirectedMessageCount, 1, []);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed);
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed);
policyPages = permute(pages, [2, 1, 3]);
strong = false(1, size(policyPages, 3));
arm.treeReselectionTimes = zeros(1, 0);
for currentTime = 1:numel(strong)
    strong(currentTime) = ...
        isStronglyConnected(policyPages(:, :, currentTime));
    certificate = ...
        diagnostics.topologyPolicyScheduleCertificate{currentTime};
    if isstruct(certificate) && ...
            logical(getField(certificate, ...
                'treeReselectionUsed', false))
        arm.treeReselectionTimes(end + 1) = currentTime; %#ok<AGROW>
    end
end
arm.instantaneousStrongFraction = mean(strong);
arm.instantaneousStrongAllTimes = all(strong);
arm.treeReselectionCount = numel(arm.treeReselectionTimes);
formationCount = numel(unique(config.sensorGroupIds));
arm.expectedMinimumMessageCount = ...
    config.numberOfSensors + 2 * (formationCount - 1);
arm.referenceFullMessageCount = 2 * config.numberOfSensors;
arm.routeMessageSavingFraction = ...
    1 - arm.expectedMinimumMessageCount / arm.referenceFullMessageCount;
end

function assertRuntimeArm(arm, config)
formationCount = numel(unique(config.sensorGroupIds));
expectedMessages = config.numberOfSensors + 2 * (formationCount - 1);
passed = arm.physicalFeasibilityPassed && ...
    ~arm.policyTruthUsed && ~arm.policyFutureOutcomeUsed && ...
    arm.routeMessageCountMinimum == expectedMessages && ...
    arm.routeMessageCountMaximum == expectedMessages && ...
    arm.instantaneousStrongAllTimes && ...
    arm.treeReselectionCount > 0;
if ~passed
    error('CausalMinimumFormationBackboneV242:RuntimeContractFailed', ...
        'The executed sparse arm violated its route or causal boundary.');
end
end

function comparison = compareArm(candidate, reference)
comparison = struct();
comparison.fullHorizonEospaGainPercent = lowerGain( ...
    reference.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionEospa);
comparison.focusWindowEospaGainPercent = lowerGain( ...
    reference.focusWindowPositionEospa, ...
    candidate.focusWindowPositionEospa);
comparison.fullHorizonRmseGainPercent = lowerGain( ...
    reference.fullHorizonPositionRmse, ...
    candidate.fullHorizonPositionRmse);
comparison.focusWindowRmseGainPercent = lowerGain( ...
    reference.focusWindowPositionRmse, ...
    candidate.focusWindowPositionRmse);
comparison.focusConsensusGainPercent = lowerGain( ...
    reference.focusInterFormationPositionOspa, ...
    candidate.focusInterFormationPositionOspa);
comparison.terminalConsensusGainPercent = lowerGain( ...
    reference.terminalInterFormationPositionOspa, ...
    candidate.terminalInterFormationPositionOspa);
comparison.attemptedByteSavingPercent = lowerGain( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
comparison.deliveredByteSavingPercent = lowerGain( ...
    reference.deliveredPayloadBytes, candidate.deliveredPayloadBytes);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.meanDirectionPassed = ...
    comparison.fullHorizonEospaGainPercent > 0 && ...
    comparison.fullHorizonRmseGainPercent > 0 && ...
    comparison.focusConsensusGainPercent > 0;
comparison.nonnegativeFormationTailPassed = ...
    comparison.minimumFormationEospaGainPercent >= 0 && ...
    comparison.minimumFormationRmseGainPercent >= 0;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CausalMinimumFormationBackboneV242:ReportWriteFailed', ...
        'Could not create the V242 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V242 causal minimum formation backbone full episode\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Source commit: `%s`\n', result.generationGitCommit);
fprintf(fid, '- V241 reference commit: `%s`\n', ...
    result.v241ReferenceGenerationGitCommit);
fprintf(fid, '- V241 mechanism gate passed: `%d`\n', ...
    result.referenceMechanismGatePassed);
fprintf(fid, '- Goal direction passed: `%d`\n', ...
    result.goalDirectionPassed);
fprintf(fid, '- Paper threshold passed: `%d`\n\n', ...
    result.paperThresholdPassed);
fprintf(fid, ['| Arm | Full E-OSPA | Full RMSE | Focus consistency | ', ...
    'Attempted bytes | Messages | Strong fraction |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|:--:|--:|\n');
writeArmRow(fid, 'V241 fixed formation tree', result.referenceFixedTree);
writeArmRow(fid, 'V241 causal 2N', result.referenceFullCausal);
writeArmRow(fid, 'V242 causal minimum backbone', result.candidate);
if armComplete(result.candidate)
    writeComparison(fid, 'V242 over fixed formation tree', ...
        result.candidateOverFixedTree);
    writeComparison(fid, 'V242 over V241 causal 2N', ...
        result.candidateOverFullCausal);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeArmRow(fid, label, arm)
if ~armComplete(arm)
    fprintf(fid, '| %s | — | — | — | — | — | — |\n', label);
    return;
end
fprintf(fid, '| %s | %.3f | %.3f | %.3f | %.0f | %d--%d | %.3f |\n', ...
    label, arm.fullHorizonPositionEospa, ...
    arm.fullHorizonPositionRmse, ...
    arm.focusInterFormationPositionOspa, arm.attemptedPayloadBytes, ...
    arm.routeMessageCountMinimum, arm.routeMessageCountMaximum, ...
    arm.instantaneousStrongFraction);
end

function writeComparison(fid, title, gain)
fprintf(fid, '\n## %s\n\n', title);
fprintf(fid, '| Metric | Gain |\n|:--|--:|\n');
fprintf(fid, '| Full E-OSPA | `%+.3f%%` |\n', ...
    gain.fullHorizonEospaGainPercent);
fprintf(fid, '| Full RMSE | `%+.3f%%` |\n', ...
    gain.fullHorizonRmseGainPercent);
fprintf(fid, '| Focus consistency | `%+.3f%%` |\n', ...
    gain.focusConsensusGainPercent);
fprintf(fid, '| Attempted-byte saving | `%+.3f%%` |\n', ...
    gain.attemptedByteSavingPercent);
fprintf(fid, '| Weakest formation E-OSPA | `%+.3f%%` |\n', ...
    gain.minimumFormationEospaGainPercent);
fprintf(fid, '| Weakest formation RMSE | `%+.3f%%` |\n', ...
    gain.minimumFormationRmseGainPercent);
end

function complete = armComplete(arm)
complete = isstruct(arm) && isscalar(arm) && ...
    ~isempty(fieldnames(arm)) && ...
    isfield(arm, 'fullHorizonPositionEospa');
end

function count = uniquePageCount(pages)
keys = cell(1, size(pages, 3));
for pageIdx = 1:size(pages, 3)
    keys{pageIdx} = sprintf('%d', pages(:, :, pageIdx));
end
count = numel(unique(keys));
end

function count = pageChangeCount(pages)
count = 0;
for pageIdx = 2:size(pages, 3)
    count = count + ~isequal( ...
        pages(:, :, pageIdx), pages(:, :, pageIdx - 1));
end
end

function connected = isStronglyConnected(adjacency)
connected = reachesAll(adjacency) && reachesAll(adjacency');
end

function passed = reachesAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node), continue; end
    visited(node) = true;
    frontier = [frontier, find(adjacency(node, :) & ~visited)]; %#ok<AGROW>
end
passed = all(visited);
end

function value = lowerGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = lowerGainVector(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = anyFiniteNonzero(values)
values = values(isfinite(values));
value = any(values ~= 0);
end

function sensors = selectFormationRepresentativesLocal(groupIds)
groups = unique(groupIds, 'stable');
sensors = zeros(1, numel(groups));
for groupIdx = 1:numel(groups)
    sensors(groupIdx) = find(groupIds == groups(groupIdx), 1);
end
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    (~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once'))));
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
