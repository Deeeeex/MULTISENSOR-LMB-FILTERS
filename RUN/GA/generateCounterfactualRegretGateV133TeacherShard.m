function [shardPath, shard] = ...
    generateCounterfactualRegretGateV133TeacherShard( ...
        presetName, seed, evidenceSplit, options)
% GENERATECOUNTERFACTUALREGRETGATEV133TEACHERSHARD Paired trajectory shard.
%
% One call produces every registered anchor x receiver-formation example
% for one complete scene-seed trajectory.  The split unit is therefore
% indivisible and no random window split can leak trajectory state.

if nargin < 3 || isempty(evidenceSplit)
    evidenceSplit = 'development';
end
if nargin < 4 || isempty(options)
    options = struct();
end
protocol = getCounterfactualRegretGateV133Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('CounterfactualRegretV133:DirtySource', ...
        'Generate official V133 teacher shards only from clean source.');
end
evidenceSplit = lower(strrep(char(evidenceSplit), '_', '-'));
caseInfo = validateRequest( ...
    protocol, presetName, seed, evidenceSplit);
carrierMode = lower(strrep(char(getField( ...
    options, 'referenceCarrierMode', '')), '_', '-'));
if isempty(carrierMode)
    carrierMode = loadFrozenCarrierMode(protocol, presetName);
end
if ~ismember(carrierMode, protocol.referenceCarrierModes)
    error('CounterfactualRegretV133:UnfrozenReferenceCarrier', ...
        'The V133 teacher requires one frozen CW or CCW carrier.');
end
overwrite = logical(getField(options, 'overwrite', false));
outputRoot = getField(options, 'outputRoot', protocol.datasetRoot);

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
anchors = resolveAnchors(inputs.config, protocol);
maximumTime = anchors(end) + caseInfo.horizonSteps - 1;
inputs = cropInputs(inputs, maximumTime);
truth = cropTrackingTruthRfs(inputs.groundTruthRfs, maximumTime);
inputs = isolateRuntimeInputs(inputs);
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
formationIds = unique(groupIds, 'stable');

shardDirectory = fullfile(outputRoot, evidenceSplit, ...
    strrep(presetName, '-', '_'));
shardPath = fullfile(shardDirectory, sprintf( ...
    'V133_%s_SEED%d.mat', ...
    upper(strrep(presetName, '-', '_')), seed));
if exist(shardPath, 'file') == 2 && ~overwrite
    loaded = load(shardPath, 'shard');
    if ~isfield(loaded, 'shard') || ...
            ~strcmp(loaded.shard.protocolId, protocol.id) || ...
            ~strcmp(loaded.shard.presetName, presetName) || ...
            loaded.shard.seed ~= seed || ...
            ~strcmp(loaded.shard.evidenceSplit, evidenceSplit) || ...
            ~strcmp(loaded.shard.referenceCarrierMode, carrierMode)
        error('CounterfactualRegretV133:ShardProvenanceDrift', ...
            'The existing V133 shard does not match the request.');
    end
    shard = loaded.shard;
    fprintf('Reused V133 teacher shard: %s\n', shardPath);
    return;
end

prefixContext = buildCounterfactualRegretGateV133ExecutionContext( ...
    presetName, seed, evidenceSplit, 'reference-prefix', ...
    anchors(end), carrierMode, 0);
prefixConfig = buildRuntimeConfig( ...
    inputs.config, carrierMode, anchors, false, 0, protocol);
prefixConfig.topologyPosteriorCaptureTimes = anchors;
prefixInputs = cropInputs(inputs, anchors(end));
rng(seed + protocol.filterSeedOffset);
prefixTimer = tic;
[~, prefixDiagnostics] = runEventTriggeredDistributedLmbFilter( ...
    prefixInputs.model, prefixInputs.measurements, ...
    prefixInputs.sensorTrajectories, prefixInputs.neighborMap, ...
    prefixInputs.commConfig, prefixConfig, prefixContext);
prefixSeconds = toc(prefixTimer);
auditRuntime(prefixDiagnostics, 1:anchors(end));

examples = repmat(emptyExample(), ...
    1, numel(anchors) * numel(formationIds));
exampleCursor = 0;
featureContractSha256 = '';
for anchorTime = anchors
    initialPosteriors = prefixDiagnostics. ...
        topologyLocalPosteriorSnapshot{anchorTime};
    history = buildBehaviorContinuationHistoryRecords( ...
        prefixDiagnostics, anchorTime, 2);
    history = history{anchorTime};
    previousPolicyHistory = ...
        convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
            history.selectedDirectedEdgeHistory);
    updateHistory = extractUpdateHistory( ...
        prefixDiagnostics, anchorTime);
    observableContext = buildObservableContext( ...
        inputs, initialPosteriors, history, previousPolicyHistory, ...
        updateHistory, anchorTime, protocol);
    [referenceAdjacency, referenceDetails] = ...
        selectBackboneResidualSplicedCyclePolicy( ...
            observableContext, carrierMode, protocol.routeWeights);
    referenceWeights = referenceDetails.fusionWeightMatrix;
    referenceScore = computeReferenceScore( ...
        observableContext, referenceAdjacency, referenceWeights, ...
        groupIds, protocol);

    referenceContext = ...
        buildCounterfactualRegretGateV133ExecutionContext( ...
            presetName, seed, evidenceSplit, ...
            'reference-continuation', anchorTime, carrierMode, 0);
    referenceConfig = buildRuntimeConfig( ...
        inputs.config, carrierMode, anchorTime, false, 0, protocol);
    referenceOutcome = runContinuation( ...
        inputs, truth, initialPosteriors, history, ...
        previousPolicyHistory, updateHistory, anchorTime, ...
        caseInfo.horizonSteps, referenceConfig, referenceContext, ...
        seed, protocol);

    for protectedFormationId = formationIds
        exampleCursor = exampleCursor + 1;
        features = extractCounterfactualRegretFeaturesV133( ...
            observableContext, referenceAdjacency, referenceWeights, ...
            groupIds, protectedFormationId, protocol, struct(), ...
            referenceScore);
        if isempty(featureContractSha256)
            featureContractSha256 = features.featureContractSha256;
        elseif ~strcmp(featureContractSha256, ...
                features.featureContractSha256)
            error('CounterfactualRegretV133:FeatureContractDrift', ...
                'V133 feature columns changed inside one shard.');
        end
        candidateContext = ...
            buildCounterfactualRegretGateV133ExecutionContext( ...
                presetName, seed, evidenceSplit, ...
                'candidate-continuation', anchorTime, carrierMode, ...
                protectedFormationId);
        candidateConfig = buildRuntimeConfig( ...
            inputs.config, carrierMode, anchorTime, true, ...
            protectedFormationId, protocol);
        candidateOutcome = runContinuation( ...
            inputs, truth, initialPosteriors, history, ...
            previousPolicyHistory, updateHistory, anchorTime, ...
            caseInfo.horizonSteps, candidateConfig, ...
            candidateContext, seed, protocol);
        assertPairedContinuation(referenceOutcome, candidateOutcome);
        label = buildCounterfactualRegretTeacherLabelV133( ...
            referenceOutcome, candidateOutcome, groupIds, ...
            protectedFormationId, referenceAdjacency, protocol);
        examples(exampleCursor) = struct( ...
            'contractVersion', ...
                'counterfactual-regret-gate-v133-example-v1', ...
            'presetName', presetName, ...
            'scaleName', caseInfo.scaleName, ...
            'seed', seed, ...
            'evidenceSplit', evidenceSplit, ...
            'anchorTime', anchorTime, ...
            'protectedFormationIdTeacherMetadataOnly', ...
                protectedFormationId, ...
            'referenceCarrierMode', carrierMode, ...
            'referenceAdjacency', logical(referenceAdjacency), ...
            'referenceFusionWeights', referenceWeights, ...
            'featureNames', {features.names}, ...
            'featureValues', features.values, ...
            'featureContractSha256', ...
                features.featureContractSha256, ...
            'featureAudit', rmfield(features, ...
                {'names', 'values'}), ...
            'teacherLabel', label, ...
            'referenceOutcome', referenceOutcome, ...
            'candidateOutcome', candidateOutcome, ...
            'policyTruthUsed', false, ...
            'policyFutureOutcomeUsed', false, ...
            'teacherTruthUsedOfflineOnly', true, ...
            'teacherFutureOutcomeUsedOfflineOnly', true);
        fprintf([ ...
            '  V133 %s seed %d t=%d F%d harm=%d ', ...
            'regret=%+.4f gain=%+.3f%% bytes=%+.2f%%\n'], ...
            caseInfo.scaleName, seed, anchorTime, ...
            protectedFormationId, label.harmful, ...
            label.maximumRegret, label.actionGainPercent, ...
            label.attemptedByteSavingPercent);
    end
end

shard = struct();
shard.contractVersion = ...
    'counterfactual-regret-gate-v133-teacher-shard-v1';
shard.protocolId = protocol.id;
shard.presetName = presetName;
shard.scaleName = caseInfo.scaleName;
shard.seed = seed;
shard.evidenceSplit = evidenceSplit;
shard.trajectoryGroupingKey = sprintf('%s-seed-%d', presetName, seed);
shard.anchors = anchors;
shard.horizonSteps = caseInfo.horizonSteps;
shard.referenceCarrierMode = carrierMode;
shard.featureContractSha256 = featureContractSha256;
shard.examples = examples;
shard.safeActionFraction = mean(arrayfun( ...
    @(example) example.teacherLabel.safeAction, examples));
shard.meanOracleActionGainPercent = mean(arrayfun( ...
    @(example) example.teacherLabel.actionGainPercent, examples));
shard.prefixSeconds = prefixSeconds;
shard.generationGitCommit = gitState.commit;
shard.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
shard.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
shard.policyTruthUsed = false;
shard.policyFutureOutcomeUsed = false;
shard.teacherTruthUsedOfflineOnly = true;
shard.teacherFutureOutcomeUsedOfflineOnly = true;
shard.validationClaimAllowed = false;
shard.reportingPolicy = protocol.reportingPolicy;
shard.evidenceBoundary = protocol.evidenceBoundary;
if exist(shardDirectory, 'dir') ~= 7
    mkdir(shardDirectory);
end
save('-mat7-binary', shardPath, 'shard');
fprintf('V133 teacher shard: %s\n', shardPath);
end

function caseInfo = validateRequest( ...
        protocol, presetName, seed, evidenceSplit)
if ~ischar(presetName) || isempty(presetName) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~ismember(evidenceSplit, {'development', 'calibration'})
    error('CounterfactualRegretV133:InvalidTeacherRequest', ...
        'The V133 teacher request is malformed.');
end
caseInfo = struct([]);
for candidate = protocol.scaleCases
    if strcmp(candidate.presetName, presetName)
        caseInfo = candidate;
        break;
    end
end
if isempty(caseInfo)
    error('CounterfactualRegretV133:InvalidTeacherRequest', ...
        'The preset is outside the V133 scale contract.');
end
if strcmp(evidenceSplit, 'development')
    allowedSeeds = protocol.developmentSeeds;
else
    allowedSeeds = protocol.calibrationSeeds;
end
if ~ismember(seed, allowedSeeds)
    error('CounterfactualRegretV133:InvalidTeacherRequest', ...
        'The seed is outside the requested complete-trajectory split.');
end
end

function anchors = resolveAnchors(config, protocol)
window = reshape(config.focusWindow, 1, []);
anchors = round(window(1) + ...
    protocol.anchorQuantilesWithinFocusWindow * ...
        (window(2) - window(1)));
if numel(unique(anchors)) ~= numel(anchors) || ...
        any(anchors < 3)
    error('CounterfactualRegretV133:InvalidAnchors', ...
        'The quantile rule did not create valid distinct anchors.');
end
end

function mode = loadFrozenCarrierMode(protocol, presetName)
path = fullfile(protocol.outputRoot, 'baseline_selection', ...
    'FROZEN_REFERENCE_CARRIER_V133.mat');
if exist(path, 'file') ~= 2
    error('CounterfactualRegretV133:UnfrozenReferenceCarrier', ...
        ['Freeze the development-trajectory carrier selection before ', ...
         'generating teacher labels.']);
end
loaded = load(path, 'selection');
if ~isfield(loaded, 'selection') || ...
        ~strcmp(loaded.selection.protocolId, protocol.id)
    error('CounterfactualRegretV133:UnfrozenReferenceCarrier', ...
        'The frozen carrier-selection artifact is invalid.');
end
caseIdx = find(strcmp( ...
    {loaded.selection.cases.presetName}, presetName), 1);
if isempty(caseIdx)
    error('CounterfactualRegretV133:UnfrozenReferenceCarrier', ...
        'The preset lacks a frozen carrier selection.');
end
mode = loaded.selection.cases(caseIdx).selectedCarrierMode;
end

function config = buildRuntimeConfig( ...
        scenarioConfig, carrierMode, activeTimes, scheduleEnabled, ...
        protectedFormationId, protocol)
config = buildMixtureAwareKlaReferenceConfig(struct( ...
    'missingLabelFusionMode', 'fov-aware-censored', ...
    'missingNeighborWeightMode', ...
        protocol.actionContract.primaryMissingNeighborWeightMode));
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * scenarioConfig.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicySensorObservationEnabled = true;
config.topologyPolicyDeliveryHistoryEnabled = false;
config.topologyPolicyName = protocol.outcomePolicyName;
config.v133ReferenceCarrierMode = carrierMode;
config.topologyPolicyFcn = @(context) ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, carrierMode, protocol.routeWeights);
config.receiverSafeLabelFusionEnabled = logical(scheduleEnabled);
config.receiverSafeFormationConditionedOnlinePolicyEnabled = false;
if scheduleEnabled
    activeTimes = reshape(activeTimes, 1, []);
    if numel(activeTimes) ~= 1 || protectedFormationId < 1
        error('CounterfactualRegretV133:InvalidActionSchedule', ...
            'A V133 action must affect exactly one current page.');
    end
    config.receiverSafeLabelFusionMode = ...
        'formation-supported-label-plan';
    config.receiverSafeExternalActiveTimes = activeTimes;
    config.receiverSafeFormationConditionedTimes = activeTimes;
    config.receiverSafeFormationConditionedSchedule = ...
        {protectedFormationId};
    config.receiverSafeFormationConditionedPayloadMode = ...
        protocol.actionContract.payloadMode;
    config.receiverSafeExternalPositiveSupportThreshold = ...
        protocol.retentionOptions.referenceSupportThreshold;
    config.receiverSafeFormationConditionedHighExistenceThreshold = ...
        protocol.retentionOptions.decisionExistenceThreshold;
end
end

function outcome = runContinuation( ...
        inputs, truth, initialPosteriors, history, ...
        previousPolicyHistory, updateHistory, anchorTime, ...
        horizonSteps, config, executionContext, seed, protocol)
returnTimes = anchorTime + (0:(horizonSteps - 1));
runInputs = cropInputs(inputs, returnTimes(end));
config.topologyPosteriorCaptureTimes = returnTimes;
config.filterInitialLocalPosteriorBySensor = initialPosteriors;
config.filterInitialLocalPosteriorTime = anchorTime;
config.filterInitialPreviousAdjacencyHistory = previousPolicyHistory;
config.filterInitialPreviousAdjacencyTimes = history.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'v133-paired-reference-prefix';
config.filterInitialLocalUpdateHistoryTimes = updateHistory.times;
config.filterInitialLocalInnovationHistory = updateHistory.innovation;
config.filterInitialLocalAssociationConfidenceHistory = ...
    updateHistory.associationConfidence;
config.filterInitialLocalNisNormHistory = updateHistory.nisNorm;
config.filterInitialLocalNisDeviationHistory = ...
    updateHistory.nisDeviation;
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    runInputs.model, runInputs.measurements, ...
    runInputs.sensorTrajectories, runInputs.neighborMap, ...
    runInputs.commConfig, config, executionContext);
elapsedSeconds = toc(timerId);
auditRuntime(diagnostics, returnTimes);
outcome = scoreOutcome( ...
    runInputs.model, truth, estimates, diagnostics, ...
    returnTimes, runInputs.config.sensorGroupIds, elapsedSeconds);
end

function outcome = scoreOutcome( ...
        model, truth, estimates, diagnostics, returnTimes, ...
        groupIds, elapsedSeconds)
nodeCount = numel(estimates);
eospa = zeros(nodeCount, numel(returnTimes));
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, ~] = computeSimulationOspa( ...
        model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(returnTimes);
end
formationIds = unique(groupIds, 'stable');
formationMean = zeros(1, numel(formationIds));
sensorMean = mean(eospa, 2);
for formationIdx = 1:numel(formationIds)
    formationMean(formationIdx) = mean( ...
        sensorMean(groupIds == formationIds(formationIdx)));
end
outcome = struct();
outcome.meanEospa = mean(eospa(:));
matureEospa = eospa(:, 2:end);
outcome.matureMeanEospa = mean(matureEospa(:));
outcome.sensorMeanEospa = reshape(sensorMean, 1, []);
outcome.formationIds = formationIds;
outcome.formationMeanEospa = formationMean;
outcome.eospaBySensorTime = eospa;
outcome.posteriorConsensusByTime = reshape( ...
    diagnostics.posteriorConsensusCombined(returnTimes), 1, []);
outcome.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes(:, :, returnTimes), 1), 2), ...
    1, []);
outcome.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes(:, :, returnTimes), 1), 2), 1, []);
outcome.controlSynopsisBytesByTime = reshape( ...
    diagnostics.receiverSafeAttemptedControlSynopsisBytes( ...
        returnTimes), 1, []);
outcome.elapsedSeconds = elapsedSeconds;
outcome.selectedAdjacencyByTime = false( ...
    numel(estimates), numel(estimates), numel(returnTimes));
outcome.fusionWeightsByTime = zeros( ...
    numel(estimates), numel(estimates), numel(returnTimes));
for timeIdx = 1:numel(returnTimes)
    currentTime = returnTimes(timeIdx);
    outcome.selectedAdjacencyByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge(:, :, currentTime));
    outcome.fusionWeightsByTime(:, :, timeIdx) = ...
        diagnostics.topologyPolicyFusionWeightMatrix{currentTime};
end
outcome.attemptedEdgeByTime = logical( ...
    diagnostics.attempted(:, :, returnTimes));
outcome.deliveredEdgeByTime = logical( ...
    diagnostics.delivered(:, :, returnTimes));
end

function assertPairedContinuation(reference, candidate)
required = { ...
    'selectedAdjacencyByTime', 'fusionWeightsByTime', ...
    'attemptedEdgeByTime', 'deliveredEdgeByTime'};
if ~all(isfield(reference, required)) || ...
        ~all(isfield(candidate, required)) || ...
        ~isequal(reference.selectedAdjacencyByTime, ...
            candidate.selectedAdjacencyByTime) || ...
        ~isequal(size(reference.fusionWeightsByTime), ...
            size(candidate.fusionWeightsByTime)) || ...
        max(abs(reference.fusionWeightsByTime(:) - ...
            candidate.fusionWeightsByTime(:))) > 1e-12 || ...
        ~isequal(reference.attemptedEdgeByTime, ...
            candidate.attemptedEdgeByTime) || ...
        ~isequal(reference.deliveredEdgeByTime, ...
            candidate.deliveredEdgeByTime)
    error('CounterfactualRegretV133:UnpairedContinuation', ...
        ['Reference and candidate must execute identical routes, ', ...
         'weights, attempts and realized link deliveries.']);
end
end

function context = buildObservableContext( ...
        inputs, initialPosteriors, history, previousPolicyHistory, ...
        updateHistory, anchorTime, protocol)
nodeCount = inputs.config.numberOfSensors;
model = attachCurrentObservableSensorGeometry( ...
    inputs.model, inputs.graphData.positions(:, :, anchorTime), ...
    anchorTime, nodeCount);
triggerConfig = buildRuntimeConfig( ...
    inputs.config, protocol.referenceCarrierModes{1}, ...
    anchorTime, false, 0, protocol);
triggerConfig.v133ReferenceCarrierMode = '';
context = struct( ...
    'localPosteriorBySensor', {initialPosteriors}, ...
    'model', model, ...
    'commConfig', inputs.commConfig, ...
    'triggerConfig', triggerConfig, ...
    'currentTime', anchorTime, ...
    'previousAdjacency', previousPolicyHistory(:, :, end), ...
    'previousAdjacencyHistory', previousPolicyHistory, ...
    'previousAdjacencyHistoryCount', ...
        size(previousPolicyHistory, 3), ...
    'previousAdjacencyHistoryTimes', history.times, ...
    'previousAdjacencyHistoryConvention', ...
        ['receiver-row-sender-column-directed-', ...
         'oldest-to-newest'], ...
    'previousAdjacencyHistorySource', ...
        'v133-paired-reference-prefix', ...
    'baseAdjacency', inputs.graphData.staticAdjacency, ...
    'physicalAdjacency', logical(inputs.graphData. ...
        physicalAdjacency(:, :, anchorTime)), ...
    'edgeScores', [], ...
    'edgeBudget', inputs.config.edgeBudget, ...
    'directedMessageBudget', 2 * nodeCount, ...
    'positions', inputs.graphData.positions(:, :, anchorTime), ...
    'localInnovationHistory', updateHistory.innovation, ...
    'localAssociationConfidenceHistory', ...
        updateHistory.associationConfidence, ...
    'localNisNormHistory', updateHistory.nisNorm, ...
    'localNisDeviationHistory', updateHistory.nisDeviation, ...
    'localUpdateHistoryTimes', updateHistory.times, ...
    'previousDeliveryHistory', ...
        convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
            history.deliveredDirectedEdgeHistory), ...
    'previousDeliveryHistoryCount', ...
        size(history.deliveredDirectedEdgeHistory, 3), ...
    'previousDeliveryHistoryTimes', history.times, ...
    'previousDeliveryHistoryConvention', ...
        ['receiver-row-sender-column-directed-', ...
         'oldest-to-newest-successful-deliveries'], ...
    'previousDeliveryHistorySource', ...
        'v133-paired-reference-prefix');
context = buildObservableTopologyPolicyContext(context);
end

function score = computeReferenceScore( ...
        context, adjacency, weights, groupIds, protocol)
options = struct('maximumIncomingCount', ...
    protocol.maximumIncomingCountForOutcomeEnumeration);
[networkDisagreement, networkDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, adjacency, weights, options);
[taskRisk, taskRiskDetails] = ...
    computeExpectedLmbPosteriorTaskRiskV92( ...
        networkDetails, groupIds, context.model, protocol.riskOptions);
score = struct( ...
    'networkDisagreement', networkDisagreement, ...
    'networkDetails', networkDetails, ...
    'taskRisk', taskRisk, ...
    'taskRiskDetails', taskRiskDetails);
end

function history = extractUpdateHistory(diagnostics, anchorTime)
times = max(1, anchorTime - 2):anchorTime;
history = struct( ...
    'times', times, ...
    'innovation', diagnostics.localInnovation(:, times), ...
    'associationConfidence', ...
        diagnostics.localAssociationConfidence(:, times), ...
    'nisNorm', diagnostics.localNisNorm(:, times), ...
    'nisDeviation', diagnostics.localNisDeviation(:, times));
end

function auditRuntime(diagnostics, times)
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(times));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(times));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(times));
infeasible = logical(~diagnostics.topologyFeasible(times) | ...
    finiteLogical(diagnostics. ...
        topologyPolicyTopologyInfeasible(times)));
if any(truthUse) || any(repair) || any(emergency) || any(infeasible)
    error('CounterfactualRegretV133:RuntimeGateFailure', ...
        'A V133 reference or paired continuation violated a hard gate.');
end
end

function inputs = isolateRuntimeInputs(inputs)
truthFields = intersect( ...
    {'groundTruth', 'groundTruthRfs', 'targetTrajectories'}, ...
    fieldnames(inputs), 'stable');
if ~isempty(truthFields)
    inputs = rmfield(inputs, truthFields);
end
inputs.model = removeExplicitTargetTruth(inputs.model);
end

function model = removeExplicitTargetTruth(model)
if isfield(model, 'explicitTargetTrajectories')
    model = rmfield(model, 'explicitTargetTrajectories');
end
if isfield(model, 'dynamicTopologyScenario') && ...
        isstruct(model.dynamicTopologyScenario)
    present = intersect({'targetTrajectories', 'target'}, ...
        fieldnames(model.dynamicTopologyScenario), 'stable');
    if ~isempty(present)
        model.dynamicTopologyScenario = rmfield( ...
            model.dynamicTopologyScenario, present);
    end
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function truth = cropTrackingTruthRfs(truth, maximumTime)
truth.x = truth.x(1:maximumTime);
truth.mu = truth.mu(1:maximumTime);
truth.Sigma = truth.Sigma(1:maximumTime);
truth.cardinality = truth.cardinality(1:maximumTime);
end

function value = finiteLogical(value)
value = isfinite(value) & value ~= 0;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

