function rebuilt = ...
    rebuildFormationIndexEquivariantResidualDutyCycleV44Evidence( ...
        protocol, parentResult)
% REBUILD...V44EVIDENCE Recompute every registered V44 numeric record.
%
% This function deliberately does not accept a stored V44 result.  It
% rebuilds the 32 registered cases, all 11 candidate schedules, every
% cyclic start phase, and the development summaries from the frozen
% protocol and the independently pinned V43 parent result.

if nargin < 1 || isempty(protocol)
    protocol = ...
        getFormationIndexEquivariantResidualDutyCycleV44Protocol();
end
if nargin < 2 || ~isstruct(parentResult) || ~isscalar(parentResult)
    error('FormationResidualDutyCycleV44Rebuild:InvalidParent', ...
        'One scalar V43 parent result is required.');
end

registered = protocol.registeredCases;
cases = repmat(emptyCase(), 1, numel(registered));
for caseIdx = 1:numel(registered)
    item = registered(caseIdx);
    cases(caseIdx) = rebuildCase(item, protocol, parentResult);
end
gate = aggregateDevelopmentGate(cases, protocol);

rebuilt = struct();
rebuilt.contractVersion = ...
    'formation-index-equivariant-residual-duty-cycle-v44-rebuild-v1';
rebuilt.protocolCanonicalSha256 = protocol.canonicalSha256;
rebuilt.caseCount = numel(cases);
rebuilt.candidateCount = protocol.candidateCount;
rebuilt.cases = cases;
rebuilt.gate = gate;
rebuilt.recommendedCandidateId = gate.recommendedCandidateId;
rebuilt.posteriorUsed = false;
rebuilt.truthUsed = false;
rebuilt.measurementUsed = false;
rebuilt.futureOutcomeUsed = false;
rebuilt.realizedDeliveryUniformsUsed = false;
rebuilt.trackingOutcomeScored = false;
rebuilt.trackingOutcomeAuthorized = false;
rebuilt.validationClaimAllowed = false;
rebuilt.developmentEvidenceOnly = true;
rebuilt.canonicalSha256 = computeCanonicalValueSha256(rebuilt);
end

function value = rebuildCase(registered, protocol, parentResult)
[context, metadata] = ...
    buildFormationIndexEquivariantGeometryDevelopmentContext( ...
        registered.presetName, registered.seed);
metadataMatched = strcmp(metadata.presetName, ...
        registered.presetName) && ...
    metadata.seed == registered.seed && ...
    metadata.currentTime == registered.currentTime && ...
    metadata.nodeCount == registered.nodeCount && ...
    metadata.formationCount == registered.formationCount && ...
    strcmp(metadata.inputCanonicalSha256, ...
        registered.inputCanonicalSha256) && ...
    strcmp(metadata.physicalUidAssignmentCanonicalSha256, ...
        registered.physicalUidRegistryCanonicalSha256);
if ~metadataMatched
    error('FormationResidualDutyCycleV44Rebuild:InputDrift', ...
        'Registered input %s did not reproduce.', registered.caseId);
end

runtime = validateReliableKlaMixingRuntimeSemantics( ...
    context.triggerConfig);
if ~strcmp(runtime.missingNeighborWeightMode, ...
        protocol.missingNeighborWeightMode)
    error('FormationResidualDutyCycleV44Rebuild:RuntimeDrift', ...
        'The registered mixing runtime semantics changed.');
end

[referenceAdjacency, referenceDetails] = ...
    selectIndexEquivariantFormationBackbonePolicy(context, struct( ...
        'dominantWeight', protocol.dominantWeight, ...
        'residualWeight', protocol.referenceResidualWeight));
referenceWeights = referenceDetails.fusionWeightMatrix;
nodeCount = size(referenceAdjacency, 1);
fixedHorizon = nodeCount - 1;
maximumHorizon = protocol.maximumHorizonMultiplier * fixedHorizon;
reliability = 1 - context.commConfig.pDropByEdge';
referenceProfile = computeStaticReliableKlaMeanSquareHorizonProfile( ...
    referenceAdjacency, referenceWeights, reliability, ...
    maximumHorizon, struct( ...
        'missingNeighborWeightMode', ...
            protocol.missingNeighborWeightMode, ...
        'maximumIncomingCount', protocol.maximumIncomingCount, ...
        'targetSquaredFactors', ...
            protocol.targetSquaredContractionFactor));
referenceTargetHorizon = referenceProfile.firstTargetHorizon(1);
referenceFixedFactor = referenceProfile. ...
    worstCaseExpectedSquaredFactorByHorizon(fixedHorizon + 1);
referenceRouteSha256 = routeSha256( ...
    referenceAdjacency, referenceWeights);

parentMatches = strcmp({parentResult.cases.caseId}, ...
    registered.caseId);
if nnz(parentMatches) ~= 1
    error('FormationResidualDutyCycleV44Rebuild:ParentCaseMissing', ...
        'The V43 parent lacks case %s.', registered.caseId);
end
parentCase = parentResult.cases(parentMatches);
parentReferenceMatched = strcmp(referenceRouteSha256, ...
        parentCase.v43RouteCanonicalSha256) && ...
    referenceTargetHorizon == parentCase.v43TargetHorizon && ...
    abs(referenceFixedFactor - ...
        parentCase.v43FixedHorizonFactor) < 1e-12;
if ~parentReferenceMatched
    error('FormationResidualDutyCycleV44Rebuild:ParentMismatch', ...
        'The V43 reference did not reproduce for %s.', ...
        registered.caseId);
end

candidates = repmat(emptyCandidate(), 1, protocol.candidateCount);
for candidateIdx = 1:protocol.candidateCount
    candidates(candidateIdx) = rebuildCandidate( ...
        context, reliability, referenceAdjacency, ...
        referenceTargetHorizon, fixedHorizon, maximumHorizon, ...
        protocol.candidates(candidateIdx), protocol);
end

boundary = context.auditBoundary;
executionBoundaryPassed = ...
    boundary.fullPlannedSensorGeometryMaterialized && ...
    boundary.fullPlannedLinkProbabilityScheduleMaterialized && ...
    ~boundary.formalRuntimeObservableBoundaryPassed && ...
    ~boundary.runtimePhysicalUidRegistryIntegrated && ...
    ~boundary.posteriorContentsRead && ~boundary.truthUsed && ...
    ~boundary.measurementUsed && ~boundary.futureOutcomeUsed && ...
    ~boundary.realizedDeliveryUniformsUsed && ...
    ~boundary.trackingOutcomeScored && ...
    ~boundary.trackingOutcomeAuthorized && ...
    ~boundary.validationClaimAllowed && ...
    boundary.developmentEvidenceOnly;
if ~executionBoundaryPassed || ~all([candidates.boundaryPassed])
    error('FormationResidualDutyCycleV44Rebuild:BoundaryViolation', ...
        'A rebuilt case crossed the development-only boundary.');
end

value = emptyCase();
value.caseId = registered.caseId;
value.presetName = registered.presetName;
value.sceneRole = registered.sceneRole;
value.seed = registered.seed;
value.currentTime = metadata.currentTime;
value.nodeCount = nodeCount;
value.formationCount = metadata.formationCount;
value.inputCanonicalSha256 = metadata.inputCanonicalSha256;
value.physicalUidRegistryCanonicalSha256 = ...
    metadata.physicalUidAssignmentCanonicalSha256;
value.registeredInputIdentityMatched = metadataMatched;
value.parentReferenceMatched = parentReferenceMatched;
value.referenceRouteCanonicalSha256 = referenceRouteSha256;
value.referenceTargetHorizon = referenceTargetHorizon;
value.referenceFixedHorizonFactor = referenceFixedFactor;
value.referenceDirectedMessagesPerStep = nnz(referenceAdjacency);
value.referenceAttemptedMessagesToTarget = ...
    nnz(referenceAdjacency) * referenceTargetHorizon;
value.maximumHorizon = maximumHorizon;
value.fixedHorizon = fixedHorizon;
value.candidates = candidates;
value.executionBoundaryPassed = executionBoundaryPassed;
value.fullPlannedSensorGeometryMaterialized = ...
    boundary.fullPlannedSensorGeometryMaterialized;
value.fullPlannedLinkProbabilityScheduleMaterialized = ...
    boundary.fullPlannedLinkProbabilityScheduleMaterialized;
value.formalRuntimeObservableBoundaryPassed = false;
value.runtimePhysicalUidRegistryIntegrated = false;
value.posteriorUsed = false;
value.truthUsed = false;
value.measurementUsed = false;
value.futureOutcomeUsed = false;
value.realizedDeliveryUniformsUsed = false;
value.trackingOutcomeScored = false;
value.trackingOutcomeAuthorized = false;
value.validationClaimAllowed = false;
value.developmentEvidenceOnly = true;
value.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(value, 'canonicalSha256'));
end

function record = rebuildCandidate(context, reliability, ...
        referenceAdjacency, referenceTargetHorizon, fixedHorizon, ...
        maximumHorizon, definition, protocol)
options = struct('period', definition.period, ...
    'dutyLayer', definition.dutyLayer, ...
    'phasePattern', definition.phasePattern, ...
    'activeResidualWeight', definition.activeResidualWeight, ...
    'dominantWeight', protocol.dominantWeight, ...
    'referenceResidualWeight', protocol.referenceResidualWeight);
[adjacency, weights, details] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(context, options);
profile = computePeriodicReliableKlaMeanSquareHorizonProfile( ...
    adjacency, weights, reliability, maximumHorizon, struct( ...
        'missingNeighborWeightMode', ...
            protocol.missingNeighborWeightMode, ...
        'maximumIncomingCount', protocol.maximumIncomingCount, ...
        'targetSquaredFactors', ...
            protocol.targetSquaredContractionFactor));

targetHorizonByPhase = reshape( ...
    profile.firstTargetHorizonByStartPhase(:, 1), 1, []);
targetMessagesByPhase = nan(size(targetHorizonByPhase));
for phaseIdx = 1:numel(targetHorizonByPhase)
    horizon = targetHorizonByPhase(phaseIdx);
    if isfinite(horizon)
        targetMessagesByPhase(phaseIdx) = profile. ...
            cumulativeMessagesByStartPhaseAndHorizon( ...
                phaseIdx, horizon + 1);
    end
end
referenceMessages = nnz(referenceAdjacency) * ...
    referenceTargetHorizon;
targetMessageRatios = targetMessagesByPhase / referenceMessages;
fixedFactors = profile.factorByStartPhaseAndHorizon( ...
    :, fixedHorizon + 1)';
referenceTargetFactors = profile.factorByStartPhaseAndHorizon( ...
    :, referenceTargetHorizon + 1)';
scheduleEquivariancePassed = auditPermutationEquivariance( ...
    context, options, adjacency, weights, details);
rollingUnionPassed = auditRollingPeriodUnion( ...
    adjacency, referenceAdjacency);
minimumSelfWeight = minimumDiagonalWeight(weights);
dominantPages = repmat(details.dominantAdjacency, ...
    1, 1, definition.period);
dominantRetained = all(reshape(~dominantPages | adjacency, [], 1));

physicalPages = repmat(logical(context.physicalAdjacency), ...
    1, 1, definition.period);
directStructuralChecks = ...
    ~any(reshape(adjacency & ~physicalPages, [], 1)) && ...
    ~any(diagonalCommunicationEdges(adjacency)) && ...
    all(abs(reshape(sum(weights, 2), [], 1) - 1) < 1e-12) && ...
    all(weights(:) >= -1e-12) && all(weights(:) <= 1 + 1e-12) && ...
    all(reshape(sum(adjacency, 2), [], 1) <= ...
        protocol.maximumIncomingCount);
structuralContractsPassed = directStructuralChecks && ...
    details.periodUnionEqualsReference && ...
    details.periodUnionSensorStrongConnected && ...
    details.periodUnionFormationStrongConnected && ...
    rollingUnionPassed && dominantRetained && ...
    details.maximumMessagesPerReceiver <= ...
        protocol.maximumIncomingCount && ...
    minimumSelfWeight >= protocol.minimumActiveSelfWeight - 1e-12 && ...
    details.messageSavingFractionPerPeriod > 0;
boundaryPassed = details.currentGeometryUsed && ...
    details.currentLinkReliabilityUsed && ...
    details.currentPhysicalActionSetUsed && ...
    ~details.posteriorUsed && ~details.truthUsed && ...
    ~details.measurementUsed && ~details.futureOutcomeUsed && ...
    ~details.realizedDeliveryUniformsUsed && ...
    ~details.trackingOutcomeScored && ...
    ~details.validationClaimAllowed && details.developmentEvidenceOnly;

record = emptyCandidate();
record.candidateId = definition.id;
record.ordinal = definition.ordinal;
record.period = definition.period;
record.dutyLayer = definition.dutyLayer;
record.phasePattern = definition.phasePattern;
record.activeResidualWeight = definition.activeResidualWeight;
record.weightMode = definition.weightMode;
record.minimumSelfWeight = minimumSelfWeight;
record.routeSequenceCanonicalSha256 = computeCanonicalValueSha256( ...
    struct('adjacencySequence', logical(adjacency), ...
        'fusionWeightSequence', weights));
record.messageCountsByPhase = details.messageCountsByPhase;
record.peakAttemptedMessagesPerStep = ...
    max(details.messageCountsByPhase);
record.messagesPerPeriod = details.messagesPerPeriod;
record.referenceMessagesPerPeriod = details.referenceMessagesPerPeriod;
record.messageSavingFractionPerPeriod = ...
    details.messageSavingFractionPerPeriod;
record.targetHorizonByStartPhase = targetHorizonByPhase;
record.everyPhaseFiniteTargetHorizon = ...
    all(isfinite(targetHorizonByPhase));
record.worstPhaseTargetHorizon = max(targetHorizonByPhase);
record.targetMessagesByStartPhase = targetMessagesByPhase;
record.targetMessageRatioByStartPhase = targetMessageRatios;
record.worstPhaseTargetMessageRatio = max(targetMessageRatios);
record.medianPhaseTargetMessageRatio = median(targetMessageRatios);
record.fixedHorizonFactorByStartPhase = fixedFactors;
record.worstPhaseFixedHorizonFactor = max(fixedFactors);
record.factorAtReferenceTargetHorizonByStartPhase = ...
    referenceTargetFactors;
record.worstFactorAtReferenceTargetHorizon = ...
    max(referenceTargetFactors);
record.currentAbsolutePhase = details.currentAbsolutePhase;
record.currentPhaseTargetHorizon = ...
    targetHorizonByPhase(details.currentAbsolutePhase);
record.currentPhaseTargetMessageRatio = ...
    targetMessageRatios(details.currentAbsolutePhase);
record.rollingPeriodUnionEqualsReference = rollingUnionPassed;
record.dominantRetainedEveryPhase = dominantRetained;
record.scheduleEquivariancePassed = scheduleEquivariancePassed;
record.structuralContractsPassed = structuralContractsPassed;
record.boundaryPassed = boundaryPassed;
record.posteriorUsed = false;
record.truthUsed = false;
record.futureOutcomeUsed = false;
record.trackingOutcomeScored = false;
record.validationClaimAllowed = false;
record.developmentEvidenceOnly = true;
record.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(record, 'canonicalSha256'));
end

function gate = aggregateDevelopmentGate(cases, protocol)
candidateIds = {protocol.candidates.id};
caseIds = {cases.caseId};
registeredCaseIds = {protocol.registeredCases.caseId};
registeredBatchComplete = isequal(caseIds, registeredCaseIds);

candidateRegistryPassed = true;
registeredCaseIdentityPassed = ...
    numel(cases) == numel(protocol.registeredCases);
for caseIdx = 1:numel(cases)
    item = cases(caseIdx);
    registered = protocol.registeredCases(caseIdx);
    candidateRegistryPassed = candidateRegistryPassed && ...
        isequal({item.candidates.candidateId}, candidateIds);
    registeredCaseIdentityPassed = registeredCaseIdentityPassed && ...
        strcmp(item.caseId, registered.caseId) && ...
        strcmp(item.presetName, registered.presetName) && ...
        strcmp(item.sceneRole, registered.sceneRole) && ...
        item.seed == registered.seed && ...
        item.currentTime == registered.currentTime && ...
        item.nodeCount == registered.nodeCount && ...
        item.formationCount == registered.formationCount && ...
        strcmp(item.inputCanonicalSha256, ...
            registered.inputCanonicalSha256) && ...
        strcmp(item.physicalUidRegistryCanonicalSha256, ...
            registered.physicalUidRegistryCanonicalSha256) && ...
        item.registeredInputIdentityMatched && ...
        item.parentReferenceMatched && item.executionBoundaryPassed;
end

template = struct('candidateId', '', 'caseCount', 0, ...
    'allCasesFiniteTarget', false, ...
    'allCasesFixedHorizonStrictContraction', false, ...
    'allCasesTargetMessageNoninferior', false, ...
    'allCasesStructuralContractsPassed', false, ...
    'minimumPeriodMessageSavingFraction', NaN, ...
    'maximumWorstPhaseTargetMessageRatio', NaN, ...
    'meanWorstPhaseTargetMessageRatio', NaN, ...
    'medianWorstPhaseTargetMessageRatio', NaN, ...
    'm24MedianWorstPhaseTargetMessageRatio', NaN, ...
    'x36MedianWorstPhaseTargetMessageRatio', NaN, ...
    'sceneMedianWorstPhaseTargetMessageRatios', nan(1, 4), ...
    'developmentCriteriaPassed', false);
summaries = repmat(template, 1, numel(candidateIds));
for candidateIdx = 1:numel(candidateIds)
    records = arrayfun(@(item) item.candidates(candidateIdx), cases);
    ratios = [records.worstPhaseTargetMessageRatio];
    fixedFactors = [records.worstPhaseFixedHorizonFactor];
    finiteTarget = [records.everyPhaseFiniteTargetHorizon];
    contracts = [records.structuralContractsPassed] & ...
        [records.scheduleEquivariancePassed] & ...
        [records.boundaryPassed];
    savings = [records.messageSavingFractionPerPeriod];
    m24 = startsWithText({cases.presetName}, 'm24-');
    x36 = startsWithText({cases.presetName}, 'x36-');
    sceneNames = {'formation-fov', 'convoy', 'relay', 'crossing'};
    sceneMedians = nan(1, numel(sceneNames));
    for sceneIdx = 1:numel(sceneNames)
        if sceneIdx == 1
            sceneMask = endsWithText({cases.presetName}, ...
                '-formation-fov');
        else
            sceneMask = containsText({cases.presetName}, ...
                sceneNames{sceneIdx});
        end
        sceneMedians(sceneIdx) = median(ratios(sceneMask));
    end
    summaries(candidateIdx).candidateId = candidateIds{candidateIdx};
    summaries(candidateIdx).caseCount = numel(records);
    summaries(candidateIdx).allCasesFiniteTarget = ...
        all(finiteTarget & isfinite(ratios));
    summaries(candidateIdx).allCasesFixedHorizonStrictContraction = ...
        all(isfinite(fixedFactors) & fixedFactors < 1 - 1e-12);
    summaries(candidateIdx).allCasesTargetMessageNoninferior = ...
        all(ratios <= ...
            protocol.maximumWorstPhaseTargetMessageRatio + 1e-12);
    summaries(candidateIdx).allCasesStructuralContractsPassed = ...
        all(contracts);
    summaries(candidateIdx).minimumPeriodMessageSavingFraction = ...
        min(savings);
    summaries(candidateIdx).maximumWorstPhaseTargetMessageRatio = ...
        max(ratios);
    summaries(candidateIdx).meanWorstPhaseTargetMessageRatio = ...
        mean(ratios);
    summaries(candidateIdx).medianWorstPhaseTargetMessageRatio = ...
        median(ratios);
    summaries(candidateIdx).m24MedianWorstPhaseTargetMessageRatio = ...
        median(ratios(m24));
    summaries(candidateIdx).x36MedianWorstPhaseTargetMessageRatio = ...
        median(ratios(x36));
    summaries(candidateIdx).sceneMedianWorstPhaseTargetMessageRatios = ...
        sceneMedians;
    summaries(candidateIdx).developmentCriteriaPassed = ...
        summaries(candidateIdx).allCasesFiniteTarget && ...
        summaries(candidateIdx). ...
            allCasesFixedHorizonStrictContraction && ...
        summaries(candidateIdx).allCasesTargetMessageNoninferior && ...
        summaries(candidateIdx).allCasesStructuralContractsPassed && ...
        summaries(candidateIdx).minimumPeriodMessageSavingFraction >= ...
            protocol.minimumPeriodMessageSavingFraction - 1e-12 && ...
        summaries(candidateIdx).m24MedianWorstPhaseTargetMessageRatio <= ...
            protocol.maximumScaleMedianTargetMessageRatio + 1e-12 && ...
        summaries(candidateIdx).x36MedianWorstPhaseTargetMessageRatio <= ...
            protocol.maximumScaleMedianTargetMessageRatio + 1e-12 && ...
        all(sceneMedians <= 1 + 1e-12);
end

eligible = find([summaries.developmentCriteriaPassed]);
recommendedCandidateId = '';
if ~isempty(eligible)
    maximumRatios = [summaries(eligible).maximumWorstPhaseTargetMessageRatio];
    bestMaximum = min(maximumRatios);
    eligible = eligible(abs(maximumRatios - bestMaximum) <= 1e-12);
    meanRatios = [summaries(eligible).meanWorstPhaseTargetMessageRatio];
    bestMean = min(meanRatios);
    eligible = eligible(abs(meanRatios - bestMean) <= 1e-12);
    tiedIds = {summaries(eligible).candidateId};
    [~, order] = sort(tiedIds);
    recommendedCandidateId = tiedIds{order(1)};
end

gate = struct();
gate.contractVersion = ...
    'formation-index-equivariant-residual-duty-cycle-v44-gate-v1';
gate.registeredBatchComplete = registeredBatchComplete;
gate.candidateRegistryPassed = candidateRegistryPassed;
gate.registeredCaseIdentityPassed = registeredCaseIdentityPassed;
gate.candidateSummaries = summaries;
gate.anyDevelopmentCandidatePassed = ...
    any([summaries.developmentCriteriaPassed]);
gate.recommendedCandidateId = recommendedCandidateId;
gate.officialCleanSourcePassed = true;
gate.postHocExecutableFreezeAuditPassed = false;
gate.routeDevelopmentAdvancePassed = false;
gate.runnerSelfAuthorizationAllowed = false;
gate.trackingAdvancePassed = false;
gate.validationClaimAllowed = false;
gate.developmentEvidenceOnly = true;
end

function passed = auditPermutationEquivariance( ...
        context, options, expectedAdjacency, expectedWeights, ...
        expectedDetails)
[~, order] = sort(context.sensorPhysicalUids, 'descend');
[permuted, ~] = permuteFormationIndexEquivariantContext(context, order);
[actualAdjacency, actualWeights, actualDetails] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(permuted, options);
nodeCount = numel(order);
passed = true;
for phaseIdx = 1:size(expectedAdjacency, 3)
    restoredAdjacency = false(nodeCount);
    restoredAdjacency(order, order) = ...
        actualAdjacency(:, :, phaseIdx);
    restoredWeights = zeros(nodeCount);
    restoredWeights(order, order) = actualWeights(:, :, phaseIdx);
    passed = passed && isequal(restoredAdjacency, ...
        expectedAdjacency(:, :, phaseIdx)) && ...
        isequal(restoredWeights, expectedWeights(:, :, phaseIdx));
end
restoredPhases = nan(1, nodeCount);
restoredPhases(order) = actualDetails.dutyPhaseByReceiver;
passed = passed && isequaln(restoredPhases, ...
    expectedDetails.dutyPhaseByReceiver);
end

function passed = auditRollingPeriodUnion(adjacency, reference)
period = size(adjacency, 3);
passed = true;
for startPhase = 1:period
    phases = mod(startPhase - 1 + (0:period-1), period) + 1;
    passed = passed && isequal(any(adjacency(:, :, phases), 3), ...
        reference);
end
end

function flags = diagonalCommunicationEdges(adjacency)
nodeCount = size(adjacency, 1);
period = size(adjacency, 3);
flags = false(nodeCount, period);
for phaseIdx = 1:period
    flags(:, phaseIdx) = diag(adjacency(:, :, phaseIdx));
end
flags = flags(:);
end

function value = minimumDiagonalWeight(weights)
nodeCount = size(weights, 1);
period = size(weights, 3);
diagonal = zeros(nodeCount, period);
for phaseIdx = 1:period
    diagonal(:, phaseIdx) = diag(weights(:, :, phaseIdx));
end
value = min(diagonal(:));
end

