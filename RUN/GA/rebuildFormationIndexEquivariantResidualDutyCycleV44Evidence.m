function mask = startsWithText(values, prefix)
mask = cellfun(@(value) strncmp(value, prefix, numel(prefix)), values);
end

function mask = endsWithText(values, suffix)
mask = cellfun(@(value) numel(value) >= numel(suffix) && ...
    strcmp(value(end-numel(suffix)+1:end), suffix), values);
end

function mask = containsText(values, token)
mask = cellfun(@(value) ...
    ~isempty(strfind(value, token)), values); %#ok<STREMP>
end
