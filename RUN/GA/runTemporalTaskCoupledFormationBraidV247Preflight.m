function [reportPath, result] = ...
        runTemporalTaskCoupledFormationBraidV247Preflight(options)
% RUNTEMPORALTASKCOUPLEDFORMATIONBRAIDV247PREFLIGHT Validate real coupling.
%
% This preflight replaces nominal route-pair coverage with realised target
% ownership timing.  It checks that every initial-tree cut which truly fails
% also carries a source-side to destination-side target handover while that
% cut is unavailable.  It remains a geometry/visibility check and never
% scores a tracker.

if nargin < 1 || isempty(options)
    options = struct();
end
seed = getField(options, 'seed', 1301);
writeReport = logical(getField(options, 'writeReport', true));
failOnGate = logical(getField(options, 'failOnGate', true));
presets = getField(options, 'presets', registeredPresets());
if ischar(presets)
    presets = {presets};
end
if ~iscell(presets) || isempty(presets)
    error('TemporalBraidV247:InvalidPresets', ...
        'presets must be a non-empty cell array of names.');
end

records = repmat(emptyRecord(), 1, numel(presets));
for presetIdx = 1:numel(presets)
    records(presetIdx) = inspectPreset(presets{presetIdx}, seed);
    record = records(presetIdx);
    fprintf([ ...
        'V247 %-58s valid=%d failedCuts=%d aligned=%d ', ...
        'speed=%.3f minST=%.3f failures=%s\n'], ...
        record.presetName, record.sceneValid, ...
        record.failedCutCount, record.temporallyCoupledFailedCutCount, ...
        record.maxTargetSpeed, record.minimumSensorTargetSeparation, ...
        joinTokens(record.sceneHardFailures));
end

result = struct();
result.contractVersion = ...
    'temporal-task-coupled-formation-braid-v247-preflight-result-v1';
result.generatedAt = datestr(now, 31);
result.seed = seed;
result.records = records;
result.crossScaleGatePassed = all([records.sceneValid]) && ...
    all([records.allFailedCutsTemporallyCoupled]);
result.trackingOutcomeAuthorized = false;
result.evidenceBoundary = [ ...
    'V247 checks scene validity and realised target-owner transfers ', ...
    'during initial-tree cut failures. It does not establish a tracking, ', ...
    'consistency, communication-byte, learned-policy, or generalization ', ...
    'benefit.'];

reportPath = '';
if writeReport
    outputDirectory = fullfile('RUN', 'GA', 'dynamic_topology', ...
        'evidence', 'tracking_aligned_v247', ...
        'temporal_task_coupled_formation_braid');
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'TEMPORAL_TASK_COUPLED_FORMATION_BRAID_V247_PREFLIGHT.md');
    result.reportPath = reportPath;
    result.matPath = strrep(reportPath, '.md', '.mat');
    writeReportFile(reportPath, result);
    save('-mat7-binary', result.matPath, 'result');
end

if failOnGate && ~result.crossScaleGatePassed
    error('TemporalBraidV247:PreflightFailed', ...
        'The temporal task-coupling gate did not pass.');
end
end

function record = inspectPreset(presetName, seed)
rng(seed, 'twister');
config = buildDynamicTopologyScenarioConfig(presetName);
[sensors, ~] = generateMultiFormationTrajectories(config);
[targets, ~] = generateCorridorTargetTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensors);
validation = validateDynamicTopologyScenario( ...
    config, sensors, targets, graph, struct('throwOnInvalid', false));
coupling = measureFormationBraidTemporalTaskCoupling( ...
    config, graph, validation.difficulty);

record = emptyRecord();
record.presetName = config.presetName;
record.sceneStyle = config.sceneStyle;
record.sensorCount = config.numberOfSensors;
record.formationCount = config.formationCount;
record.targetCount = config.numberOfTargets;
record.sceneValid = validation.isValid;
record.sceneHardFailures = validation.hardFailures;
record.blackoutFraction = validation.difficulty.blackoutFraction;
record.singleFormationFraction = ...
    validation.difficulty.singleFormationFraction;
record.multiFormationFraction = ...
    validation.difficulty.multiFormationFraction;
record.totalHandovers = validation.difficulty.totalHandovers;
record.focusHandovers = validation.difficulty.focusHandovers;
record.minimumTargetSeparation = validation.minimumTargetSeparation;
record.minimumSensorTargetSeparation = ...
    validation.minimumSensorTargetSeparation;
record.maxTargetSpeed = validation.maxTargetSpeed;
record.maxTargetAcceleration = validation.maxTargetAcceleration;
record.targetRouteLaneSigns = config.targetRouteLaneSigns;
record.failedCutCount = coupling.failedCutCount;
record.temporallyCoupledFailedCutCount = ...
    coupling.temporallyCoupledFailedCutCount;
record.allFailedCutsTemporallyCoupled = ...
    coupling.allFailedCutsTemporallyCoupled;
record.minimumAlignedCohortsPerFailedCut = ...
    coupling.minimumAlignedCohortsPerFailedCut;
record.cutRecords = coupling.cutRecords;
record.taskTopologyCouplingContract = ...
    config.taskTopologyCouplingContract;
end

function presets = registeredPresets()
presets = { ...
    'm24-formation-fov-temporal-coupled-formation-braid', ...
    'x36-formation-fov-temporal-coupled-formation-braid', ...
    'x48-formation-fov-temporal-coupled-formation-braid'};
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', 'sceneStyle', '', ...
    'sensorCount', NaN, 'formationCount', NaN, 'targetCount', NaN, ...
    'sceneValid', false, 'sceneHardFailures', {{}}, ...
    'blackoutFraction', NaN, ...
    'singleFormationFraction', NaN, ...
    'multiFormationFraction', NaN, ...
    'totalHandovers', NaN, 'focusHandovers', NaN, ...
    'minimumTargetSeparation', NaN, ...
    'minimumSensorTargetSeparation', NaN, ...
    'maxTargetSpeed', NaN, 'maxTargetAcceleration', NaN, ...
    'targetRouteLaneSigns', zeros(1, 0), ...
    'failedCutCount', 0, ...
    'temporallyCoupledFailedCutCount', 0, ...
    'allFailedCutsTemporallyCoupled', false, ...
    'minimumAlignedCohortsPerFailedCut', 0, ...
    'cutRecords', struct([]), ...
    'taskTopologyCouplingContract', '');
end

function writeReportFile(path, result)
fileId = fopen(path, 'w');
if fileId < 0
    error('TemporalBraidV247:ReportOpenFailed', ...
        'Unable to open %s.', path);
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, ...
    '# V247 temporally task-coupled formation-braid preflight\n\n');
fprintf(fileId, '- Seed: `%d`\n', result.seed);
fprintf(fileId, '- Cross-scale geometry gate passed: `%d`\n', ...
    result.crossScaleGatePassed);
fprintf(fileId, '- Tracking outcome authorized: `0`\n');
fprintf(fileId, '- Evidence boundary: %s\n\n', result.evidenceBoundary);
fprintf(fileId, [ ...
    '| Scale | Valid | Blackout | Single / multi formation | ', ...
    'Target speed / acceleration | Min target / sensor-target separation ', ...
    '| Failed / temporally coupled cuts | Lane signs |\n']);
fprintf(fileId, '|:--|--:|--:|--:|--:|--:|--:|:--|\n');
for idx = 1:numel(result.records)
    record = result.records(idx);
    fprintf(fileId, [ ...
        '| %s | %d | %.3f | %.3f / %.3f | %.3f / %.3f | ', ...
        '%.3f / %.3f | %d / %d | `%s` |\n'], ...
        record.presetName, record.sceneValid, record.blackoutFraction, ...
        record.singleFormationFraction, record.multiFormationFraction, ...
        record.maxTargetSpeed, record.maxTargetAcceleration, ...
        record.minimumTargetSeparation, ...
        record.minimumSensorTargetSeparation, ...
        record.failedCutCount, ...
        record.temporallyCoupledFailedCutCount, ...
        mat2str(record.targetRouteLaneSigns));
end

fprintf(fileId, '\n## Realised cut/handover alignment\n\n');
for recordIdx = 1:numel(result.records)
    record = result.records(recordIdx);
    fprintf(fileId, '### %s\n\n', record.presetName);
    fprintf(fileId, ...
        '- Coupling contract: `%s`\n', ...
        record.taskTopologyCouplingContract);
    fprintf(fileId, '- Scene hard failures: `%s`\n\n', ...
        joinTokens(record.sceneHardFailures));
    fprintf(fileId, [ ...
        '| Initial-tree cut | Failure interval | Cohort | ', ...
        'Pre-failure source support | During-failure destination support ', ...
        '| Aligned targets | First aligned transition | Cross-cut ', ...
        'visibility overlap | Pass |\n']);
    fprintf(fileId, '|:--|:--|:--|--:|--:|--:|--:|--:|--:|\n');
    for cutIdx = 1:numel(record.cutRecords)
        cut = record.cutRecords(cutIdx);
        if ~cut.failed
            continue;
        end
        for cohortIdx = 1:numel(cut.cohortRecords)
            cohort = cut.cohortRecords(cohortIdx);
            fprintf(fileId, [ ...
                '| %d--%d | %s--%s | G%d: %d->%d | %.3f | %.3f ', ...
                '| %.3f | %s | %.3f | %d |\n'], ...
                cut.edgePair(1), cut.edgePair(2), ...
                scalarText(cut.firstFailureTime), ...
                scalarText(cut.lastFailureTime), ...
                cohort.groupId, cohort.sourceFormation, ...
                cohort.destinationFormation, ...
                cohort.preFailureSourceSupportFraction, ...
                cohort.duringFailureDestinationSupportFraction, ...
                cohort.alignedTargetFraction, ...
                scalarText(cohort.earliestAlignedTransitionTime), ...
                cohort.crossCutVisibilityOverlapFraction, ...
                cohort.temporallyAligned);
        end
    end
    fprintf(fileId, '\n');
end

fprintf(fileId, '## Interpretation\n\n');
fprintf(fileId, [ ...
    'The old V244 gate counted a target route when its registered source ', ...
    'and destination lay on opposite sides of a cut. That was insufficient ', ...
    'for moving formations. V247 instead requires realised source-side ', ...
    'ownership before the cut failure and a realised destination-side ', ...
    'transition while the cut is unavailable. Passing this report licenses ', ...
    'the scene for tracker experiments only; it is not itself evidence that ', ...
    'dynamic routing improves tracking.\n']);
end

function text = scalarText(value)
if isfinite(value)
    text = sprintf('%g', value);
else
    text = '--';
end
end

function text = joinTokens(tokens)
if isempty(tokens)
    text = '--';
else
    text = strjoin(tokens, '+');
end
end

function value = getField(structure, name, defaultValue)
if isstruct(structure) && isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
