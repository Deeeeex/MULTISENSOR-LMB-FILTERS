function [datasetPath, dataset] = ...
    generateRollingSafeJointActionStateDataset(options)
% GENERATEROLLINGSAFEJOINTACTIONSTATEDATASET Regenerate the frozen v3 state.

if nargin < 1 || isempty(options)
    options = struct();
end
if isfield(options, 'datasetVariant') && ...
        ~strcmp(lower(strrep(char( ...
            options.datasetVariant), '_', '-')), ...
            'joint-action-state-v3')
    error('Joint-action state wrapper cannot change dataset variant.');
end
options.datasetVariant = 'joint-action-state-v3';
[datasetPath, dataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        [], [], [], options);
end
