function [reportPath, result] = ...
        runStratifiedDirectGraphThreeArmH3V218(options)
% RUNSTRATIFIEDDIRECTGRAPHTHREEARMH3V218 Label selected causal states.
%
% Every V218 formation-time pair receives a common full-payload no-op arm,
% one one-page formation-withholding arm, and a bounded set of
% withholding-plus-one-complete-label-KLA arms.  Feasibility is decided by
% the deterministic V216/V217 projection; truth scores only the H=3 return.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getDirectGraphStratifiedSamplingV218Protocol();
v216 = getDirectGraphCreditRepairControllerV216Protocol();
v213 = getHierarchicalDelayedValueControllerV213Protocol();
presetName = char(getField(options, ...
    'presetName', 'm24-formation-fov'));
seed = getField(options, 'seed', 1301);
splitName = char(getField(options, 'splitName', 'training'));
trajectoryPath = char(getField(options, 'trajectoryPath', fullfile( ...
    protocol.outputRoot, 'trajectory_collection', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed), ...
    'STRATIFIED_DIRECT_GRAPH_TRAJECTORY_V218.mat')));
stratumIndices = reshape(getField( ...
    options, 'stratumIndices', zeros(1, 0)), 1, []);
topPerMode = getField(options, 'topPerMode', ...
    protocol.labeling.topPerRepairProposalMode);
reuseExistingScreens = logical(getField( ...
    options, 'reuseExistingScreens', true));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'three_arm_h3', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
if exist(trajectoryPath, 'file') ~= 2 || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~isscalar(topPerMode) || ~isfinite(topPerMode) || ...
        topPerMode < 1 || topPerMode ~= round(topPerMode)
    error('DirectGraphThreeArmH3V218:InvalidRequest', ...
        'A completed V218 trajectory and positive shortlist cap are required.');
end
if topPerMode ~= protocol.labeling.topPerRepairProposalMode
    error('DirectGraphThreeArmH3V218:ShortlistContract', ...
        'Official V218 labels use the frozen Top-3 per proposal mode.');
end

loaded = load(trajectoryPath, 'result');
trajectory = loaded.result;
validateTrajectory( ...
    trajectory, protocol, presetName, seed, splitName);
stratumCount = numel(trajectory.selection.stratumNames);
if isempty(stratumIndices)
    stratumIndices = 1:stratumCount;
elseif any(~isfinite(stratumIndices)) || ...
        any(stratumIndices ~= round(stratumIndices)) || ...
        any(stratumIndices < 1) || ...
        any(stratumIndices > stratumCount) || ...
        numel(unique(stratumIndices)) ~= numel(stratumIndices)
    error('DirectGraphThreeArmH3V218:StratumSubset', ...
        'Requested stratum indices must be unique valid integers.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('DirectGraphThreeArmH3V218:DirtySource', ...
        'Official V218 H=3 labeling requires clean source.');
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

states = repmat(emptyState(), 1, numel(stratumIndices));
sharedReferenceTimes = zeros(1, 0);
sharedReferenceScreenPaths = cell(1, 0);
for position = 1:numel(stratumIndices)
    stratumIdx = stratumIndices(position);
    currentTime = trajectory.selection. ...
        selectedTimesByStratum(stratumIdx);
    formationId = trajectory.selection. ...
        selectedFormationIdsByStratum(stratumIdx);
    cachePath = trajectory.cachePathsByStratum{stratumIdx};
    leaf = sprintf('%02d_%s_t%d_f%d', stratumIdx, ...
        strrep(trajectory.selection.stratumNames{stratumIdx}, '-', '_'), ...
        currentTime, formationId);
    stateRoot = fullfile(outputRoot, leaf);

    sharedIdx = find(sharedReferenceTimes == currentTime, 1);
    sharedReferencePath = '';
    if ~isempty(sharedIdx)
        sharedReferencePath = ...
            sharedReferenceScreenPaths{sharedIdx};
    end
    [~, withholdingScreen] = runWithholdingScreen( ...
        trajectory, stratumIdx, cachePath, formationId, ...
        sharedReferencePath, fullfile(stateRoot, 'withholding_screen'), ...
        reuseExistingScreens, gitState.commit, protocol);
    withholdingScreenPath = withholdingScreen.matPath;
    if isempty(sharedIdx)
        sharedReferenceTimes(end + 1) = currentTime; %#ok<AGROW>
        sharedReferenceScreenPaths{end + 1} = ...
            withholdingScreenPath; %#ok<AGROW>
    end

    [~, probeScreen] = runCandidateProbeScreen( ...
        trajectory, stratumIdx, cachePath, formationId, ...
        withholdingScreen, fullfile(stateRoot, 'candidate_probe_screen'), ...
        reuseExistingScreens, gitState.commit, protocol, v216);
    [~, bankResult] = buildPositionSafeDirectGraphCandidateBankV217( ...
        struct('sourceScreenPath', probeScreen.matPath, ...
            'pageIndex', 1, 'topPerMode', topPerMode, ...
            'outputRoot', fullfile(stateRoot, 'candidate_bank')));
    [transportCandidateIndices, transportProjection] = ...
        transportFeasibleCandidateIndices( ...
            bankResult, presetName, seed);
    [~, candidateResult] = ...
        runPositionSafeDirectGraphCandidateH3V217(struct( ...
            'candidateBankPath', bankResult.matPath, ...
            'candidateIndices', transportCandidateIndices, ...
            'reuseExistingScreens', reuseExistingScreens, ...
            'outputRoot', fullfile(stateRoot, 'candidate_h3')));
    states(position) = assembleState( ...
        trajectory, stratumIdx, withholdingScreen, ...
        bankResult, transportProjection, candidateResult, v213);
end

result = struct();
result.contractVersion = ...
    'stratified-direct-graph-three-arm-h3-v218-v1';
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.generationGitCommit = gitState.commit;
result.trajectoryPath = trajectoryPath;
result.trajectoryGenerationGitCommit = ...
    trajectory.generationGitCommit;
result.presetName = presetName;
result.seed = seed;
result.splitName = splitName;
result.stratumIndices = stratumIndices;
result.targetNames = v213.risk.targetNames;
result.riskTolerancePercent = v213.risk.tolerancePercent;
result.minimumStaticAttemptedByteSavingPercent = ...
    v213.risk.minimumStaticAttemptedByteSavingPercent;
result.states = states;
result.stateCount = numel(states);
result.fullPayloadNoOpIncluded = true;
result.withholdingOnlyIncluded = true;
result.completeLabelKlaAlternativeIncluded = ...
    any([states.repairCandidateCount] > 0);
result.completeLabelMixturesPreserved = true;
result.deterministicFeasibilityOwnsCandidateSet = true;
result.repairTeacherConditionedOnCurrentBidirectionalDelivery = true;
result.idealDeliveryUsedOnlyAfterTransportConditioning = true;
result.causalTwoStageDecisionRequired = true;
result.withholdingMustBeSafeWithoutRepair = true;
result.repairMayAuthorizeUnsafeWithholding = false;
result.continuousVectorTargetsRetainedBelowPromotionGate = true;
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.truthUsedForH3Targets = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V218 evaluates three complete alternative classes from each ', ...
    'truth-free stratified state: full-payload no-op, one-page ', ...
    'formation withholding, and withholding plus one position-safe, ', ...
    'credit-feasible complete-label KLA. A repair label is queried only ', ...
    'when the current realized request and all response directions are ', ...
    'available; ideal delivery then isolates conditional fusion value ', ...
    'instead of replacing transport risk. Every bounded repair candidate ', ...
    'keeps both its no-op-relative and withholding-relative continuous ', ...
    'twelve-coordinate H=3 targets even when it ', ...
    'fails the promotion or risk gate. Truth scores targets only; these ', ...
    'opened training states are not validation or policy evidence.'];
matPath = fullfile(outputRoot, ...
    'STRATIFIED_DIRECT_GRAPH_THREE_ARM_H3_V218.mat');
reportPath = fullfile(outputRoot, ...
    'STRATIFIED_DIRECT_GRAPH_THREE_ARM_H3_V218.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V218 stratified three-arm H=3: %s\n', reportPath);
end

function [reportPath, screen] = runWithholdingScreen( ...
        trajectory, stratumIdx, cachePath, formationId, ...
        referenceScreenPath, outputDirectory, reuseExisting, ...
        currentCommit, protocol)
options = commonScreenOptions( ...
    trajectory, cachePath, outputDirectory, protocol);
options.directGraphPayloadRepairBankOptions = struct( ...
    'actionMode', 'withholding-only', ...
    'formationIds', formationId);
options.referenceOutcomeScreenPath = referenceScreenPath;
expected = struct('actionMode', 'withholding-only', ...
    'formationId', formationId, 'captureLocal', false, ...
    'captureFused', false, 'referenceScreenPath', referenceScreenPath, ...
    'stratumIdx', stratumIdx);
[reportPath, screen] = runOrReuseScreen( ...
    trajectory, cachePath, options, expected, ...
    reuseExisting, currentCommit);
end

function [reportPath, screen] = runCandidateProbeScreen( ...
        trajectory, stratumIdx, cachePath, formationId, ...
        withholdingScreen, outputDirectory, reuseExisting, ...
        currentCommit, protocol, v216)
reference = withholdingScreen.outcomes( ...
    withholdingScreen.referenceSubsetIndex);
options = commonScreenOptions( ...
    trajectory, cachePath, outputDirectory, protocol);
options.capturePosteriorSnapshotsEnabled = true;
options.captureFusedPosteriorSnapshotsEnabled = true;
options.directGraphPayloadRepairBankOptions = struct( ...
    'actionMode', v216.actionMode, ...
    'referenceAttemptedBytes', reference.attemptedBytesByTime(1), ...
    'repairSourceWeight', v216.repairSourceWeight, ...
    'formationIds', formationId);
options.referenceOutcomeScreenPath = withholdingScreen.matPath;
expected = struct('actionMode', v216.actionMode, ...
    'formationId', formationId, 'captureLocal', true, ...
    'captureFused', true, ...
    'referenceScreenPath', withholdingScreen.matPath, ...
    'stratumIdx', stratumIdx);
[reportPath, screen] = runOrReuseScreen( ...
    trajectory, cachePath, options, expected, ...
    reuseExisting, currentCommit);
end

function options = commonScreenOptions( ...
        trajectory, cachePath, outputDirectory, protocol)
options = struct();
options.horizonSteps = protocol.horizonSteps;
options.interventionDurationSteps = 1;
options.filterSeedOffset = protocol.filterSeedOffset;
options.cacheRoot = fileparts(cachePath);
options.interventionBankType = ...
    'direct-graph-payload-repair-v214';
options.trackingAlignedExecutionProfile = ...
    'v214-direct-graph-payload-repair';
options.receiverMode = protocol.receiverMode;
options.directGraphSplitName = trajectory.splitName;
options.outputDirectory = outputDirectory;
options.writeReport = true;
options.capturePosteriorSnapshotsEnabled = false;
options.captureFusedPosteriorSnapshotsEnabled = false;
end

function [reportPath, screen] = runOrReuseScreen( ...
        trajectory, cachePath, options, expected, ...
        reuseExisting, currentCommit)
currentTime = trajectory.selection. ...
    selectedTimesByStratum(expected.stratumIdx);
stem = sprintf('FORMATION_MODE_H3_%s_SEED%d_T%d', ...
    upper(strrep(trajectory.presetName, '-', '_')), ...
    trajectory.seed, currentTime);
matPath = fullfile(options.outputDirectory, [stem, '.mat']);
if reuseExisting && exist(matPath, 'file') == 2
    loaded = load(matPath, 'screen');
    screen = loaded.screen;
    if reusableScreen(screen, trajectory, cachePath, expected, ...
            currentCommit)
        reportPath = screen.reportPath;
        return;
    end
end
[reportPath, screen] = runFormationModeOpenedReturnScreen( ...
    trajectory.presetName, trajectory.seed, currentTime, options);
if ~reusableScreen(screen, trajectory, cachePath, expected, ...
        currentCommit)
    error('DirectGraphThreeArmH3V218:ScreenReadback', ...
        'A generated V218 H=3 screen failed its provenance check.');
end
end

function reusable = reusableScreen( ...
        screen, trajectory, cachePath, expected, currentCommit)
reusable = false;
required = {'presetName', 'seed', 'currentTime', 'horizonSteps', ...
    'cachePath', 'generationGitCommit', 'bank', 'records', ...
    'outcomes', 'referenceSubsetIndex', ...
    'referenceOutcomeScreenPath', ...
    'capturePosteriorSnapshotsEnabled', ...
    'captureFusedPosteriorSnapshotsEnabled', ...
    'runtimePolicyUsesTruth', 'featuresUseTruth', ...
    'featuresUseFutureOutcome', 'validationClaimAllowed'};
if ~isstruct(screen) || ~isscalar(screen) || ...
        ~all(isfield(screen, required)) || ...
        ~strcmp(screen.presetName, trajectory.presetName) || ...
        screen.seed ~= trajectory.seed || ...
        screen.currentTime ~= trajectory.selection. ...
            selectedTimesByStratum(expected.stratumIdx) || ...
        screen.horizonSteps ~= 3 || ...
        ~strcmp(screen.cachePath, cachePath) || ...
        ~strcmp(screen.generationGitCommit, currentCommit) || ...
        ~strcmp(screen.referenceOutcomeScreenPath, ...
            expected.referenceScreenPath) || ...
        screen.capturePosteriorSnapshotsEnabled ~= ...
            expected.captureLocal || ...
        screen.captureFusedPosteriorSnapshotsEnabled ~= ...
            expected.captureFused || ...
        screen.runtimePolicyUsesTruth || screen.featuresUseTruth || ...
        screen.featuresUseFutureOutcome || ...
        screen.validationClaimAllowed || ...
        ~isfield(screen.bank, 'actionMode') || ...
        ~strcmp(screen.bank.actionMode, expected.actionMode)
    return;
end
nonreference = find([screen.records.actionIndex] ~= ...
    screen.bank.referenceActionIndex);
if numel(nonreference) ~= 1 || ...
        ~iscell(screen.bank.actionFormationIds) || ...
        ~isequal(screen.bank.actionFormationIds{ ...
            screen.records(nonreference).actionIndex}, ...
            expected.formationId)
    return;
end
reusable = true;
end

function state = assembleState( ...
        trajectory, stratumIdx, withholdingScreen, ...
        bankResult, transportProjection, candidateResult, v213)
referenceIdx = withholdingScreen.referenceSubsetIndex;
nonreferenceIdx = find([withholdingScreen.records.actionIndex] ~= ...
    withholdingScreen.bank.referenceActionIndex);
if numel(nonreferenceIdx) ~= 1
    error('DirectGraphThreeArmH3V218:WithholdingArm', ...
        'Each selected V218 state must have one withholding arm.');
end
referenceOutcome = withholdingScreen.outcomes(referenceIdx);
withholdingOutcome = withholdingScreen.outcomes(nonreferenceIdx);
withholdingRecord = withholdingScreen.records(nonreferenceIdx);
formationId = trajectory.selection. ...
    selectedFormationIdsByStratum(stratumIdx);
formationGraph = buildDirectGraphFormationLearningSnapshotV218( ...
    withholdingScreen.sensorGroupIds, ...
    withholdingScreen.bank.referenceAdjacency, ...
    withholdingScreen.bank.referenceFusionWeights, ...
    withholdingScreen.bank.referencePolicyDetails);
targetFormationRow = find( ...
    formationGraph.formationIds == formationId);
if numel(targetFormationRow) ~= 1
    error('DirectGraphThreeArmH3V218:TargetFormationRow', ...
        'The selected target formation is absent from the learning graph.');
end

actions = repmat(emptyAction(), ...
    1, 2 + numel(candidateResult.records));
actions(1) = buildAction('full-payload-no-op', ...
    withholdingScreen.records(referenceIdx).actionName, ...
    zeros(1, 12), 0, 0, zeros(2, 1), 0, ...
    zeros(1, 0), true, true, true, ...
    withholdingScreen.matPath, v213);
withholdingGain = computeDirectGraphH3GainVectorV218( ...
    referenceOutcome, withholdingOutcome, ...
    withholdingScreen.sensorGroupIds, formationId);
actions(2) = buildAction('formation-withholding', ...
    withholdingRecord.actionName, withholdingGain, ...
    withholdingRecord.attemptedByteSavingPercent, ...
    0, zeros(2, 1), 0, ...
    trajectory.selection.selectedRawFeaturesByStratum( ...
        stratumIdx, :), false, false, false, ...
    withholdingScreen.matPath, v213);
for idx = 1:numel(candidateResult.records)
    record = candidateResult.records(idx);
    loaded = load(record.screenPath, 'screen');
    candidateScreen = loaded.screen;
    candidateIdx = find([candidateScreen.records.actionIndex] ~= ...
        candidateScreen.bank.referenceActionIndex);
    if numel(candidateIdx) ~= 1
        error('DirectGraphThreeArmH3V218:RepairArm', ...
            'Each repair screen must contain one forced candidate arm.');
    end
    incrementalGain = computeDirectGraphH3GainVectorV218( ...
        withholdingOutcome, candidateScreen.outcomes(candidateIdx), ...
        candidateScreen.sensorGroupIds, formationId);
    expectedIncremental = [ ...
        record.repairVsWithholdingEospaGainPercent, ...
        record.repairVsWithholdingRmseGainPercent, ...
        record.repairVsWithholdingConsensusGainPercent];
    if max(abs(incrementalGain(1:3) - expectedIncremental)) > 1e-10
        error('DirectGraphThreeArmH3V218:IncrementalTargetDrift', ...
            'The repair-versus-withholding target changed provenance.');
    end
    actions(idx + 2) = buildAction( ...
        'withholding-plus-complete-label-kla', ...
        sprintf('F%d-withhold-plus-S%d-label-%d-%d', ...
            formationId, record.sourceId, ...
            record.label(1), record.label(2)), ...
        record.gainVectorPercent, ...
        record.attemptedByteSavingPercent, ...
        record.sourceId, record.label, ...
        record.candidateIndex, record.actionFeatureVector, ...
        false, false, false, record.screenPath, v213);
    actions(idx + 2).repairVsWithholdingGainPercent = [ ...
        record.repairVsWithholdingEospaGainPercent, ...
        record.repairVsWithholdingRmseGainPercent, ...
        record.repairVsWithholdingConsensusGainPercent];
    actions(idx + 2).incrementalFromWithholdingGainVectorPercent = ...
        incrementalGain;
    actions(idx + 2).incrementalRiskPassed = ...
        all(incrementalGain >= -1e-10);
    actions(idx + 2).payloadAttemptedBytes = ...
        record.payloadAttemptedBytes;
    actions(idx + 2).creditFeasible = true;
    actions(idx + 2).sourceFormationId = ...
        withholdingScreen.sensorGroupIds(record.sourceId);
    actions(idx + 2).sourceFormationRow = find( ...
        formationGraph.formationIds == ...
            actions(idx + 2).sourceFormationId);
end
actions(1).causallyAdmissible = true;
actions(2).causallyAdmissible = ...
    actions(2).admissibleAlternative;
for idx = 3:numel(actions)
    actions(idx).causallyAdmissible = ...
        actions(2).causallyAdmissible && ...
        actions(idx).admissibleAlternative && ...
        actions(idx).incrementalRiskPassed;
end

state = emptyState();
state.stratumIndex = stratumIdx;
state.stratumName = ...
    trajectory.selection.stratumNames{stratumIdx};
state.currentTime = trajectory.selection. ...
    selectedTimesByStratum(stratumIdx);
state.formationId = formationId;
state.stratumScore = trajectory.selection. ...
    selectedScoresByStratum(stratumIdx);
state.stateFeatureNames = trajectory.featureNames;
state.stateFeatureVector = trajectory.selection. ...
    selectedRawFeaturesByStratum(stratumIdx, :);
state.stratumComponentRanks = trajectory.selection. ...
    selectedComponentRanksByStratum{stratumIdx};
state.formationGraph = formationGraph;
state.targetFormationRow = targetFormationRow;
state.withholdingScreenPath = withholdingScreen.matPath;
state.candidateBankPath = bankResult.matPath;
state.candidateH3Path = candidateResult.matPath;
state.fullCandidateCount = bankResult.fullCandidateCount;
state.positionSafeCandidateCount = ...
    bankResult.positionSafeCandidateCount;
state.shortlistedCandidateCount = ...
    bankResult.shortlistedCandidateCount;
state.creditFeasibleCandidateCount = ...
    bankResult.creditFeasibleCandidateCount;
state.transportFeasibleCandidateCount = ...
    transportProjection.feasibleCandidateCount;
state.transportProjection = transportProjection;
state.repairCandidateCount = numel(candidateResult.records);
state.repairActionFeatureNames = ...
    bankResult.shortlistDetails.featureNames;
state.actions = actions;
state.precommunicationActionIndices = [1, 2];
state.postfusionActionIndices = 2:numel(actions);
state.withholdingMustPassWithoutRepair = true;
state.repairMayAuthorizeUnsafeWithholding = false;
state.bestAdmissibleActionIndex = selectBestAction(actions, v213);
state.bestAdmissibleActionName = ...
    actions(state.bestAdmissibleActionIndex).actionName;
state.truthUsedForTargets = true;
state.truthUsedForFeatures = false;
state.futureInformationUsedForFeatures = false;
end

function [candidateIndices, details] = ...
        transportFeasibleCandidateIndices(bankResult, presetName, seed)
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
time = bankResult.currentTime;
physical = logical(inputs.graphData.physicalAdjacency(:, :, time));
if inputs.commConfig.forceDelivery
    delivered = physical;
else
    delivered = physical & ...
        (inputs.commConfig.linkUniforms(:, :, time) >= ...
         inputs.commConfig.pDropByEdge(:, :, time));
end
shortlistCount = numel(bankResult.shortlist);
requestDelivered = false(1, shortlistCount);
responseDelivered = false(1, shortlistCount);
for idx = 1:shortlistCount
    proposal = bankResult.proposals(idx);
    coordinatorId = proposal.receiverIds(1);
    requestDelivered(idx) = ...
        delivered(coordinatorId, proposal.sourceId);
    responseDelivered(idx) = all( ...
        delivered(proposal.sourceId, proposal.receiverIds));
end
feasibleMask = bankResult.creditFeasibleMask & ...
    requestDelivered & responseDelivered;
candidateIndices = reshape( ...
    [bankResult.shortlist(feasibleMask).candidateIndex], 1, []);
details = struct();
details.contractVersion = ...
    'current-bidirectional-repair-transport-projector-v218-v1';
details.requestDeliveredMask = requestDelivered;
details.responseDeliveredMask = responseDelivered;
details.creditFeasibleMask = bankResult.creditFeasibleMask;
details.feasibleMask = feasibleMask;
details.feasibleCandidateIndices = candidateIndices;
details.feasibleCandidateCount = nnz(feasibleMask);
details.currentRealizedDeliveryUsed = true;
details.futureDeliveryUsed = false;
details.truthUsed = false;
end

function action = buildAction(kind, name, gainVector, byteSaving, ...
        sourceId, label, candidateIndex, featureVector, ...
        noOpFallback, riskPassed, byteReservePassed, screenPath, v213)
action = emptyAction();
action.kind = kind;
action.actionName = name;
action.gainVectorPercent = reshape(gainVector, 1, []);
action.meanEospaGainPercent = action.gainVectorPercent(1);
action.meanRmseGainPercent = action.gainVectorPercent(2);
action.consensusGainPercent = action.gainVectorPercent(3);
action.terminalConsensusGainPercent = action.gainVectorPercent(4);
action.attemptedByteSavingPercent = byteSaving;
action.sourceId = sourceId;
action.label = reshape(label, 2, 1);
action.candidateIndex = candidateIndex;
action.actionFeatureVector = reshape(featureVector, 1, []);
action.noOpFallback = noOpFallback;
if ~noOpFallback
    riskPassed = all(action.gainVectorPercent >= ...
        v213.risk.tolerancePercent - 1e-10);
    byteReservePassed = byteSaving >= ...
        v213.risk.minimumStaticAttemptedByteSavingPercent - 1e-10;
end
action.riskPassed = riskPassed;
action.byteReservePassed = byteReservePassed;
action.admissibleAlternative = noOpFallback || ...
    (riskPassed && byteReservePassed);
action.screenPath = screenPath;
end

function index = selectBestAction(actions, v213)
eligible = find([actions.causallyAdmissible]);
margin = zeros(numel(eligible), 1);
bytes = zeros(numel(eligible), 1);
for idx = 1:numel(eligible)
    action = actions(eligible(idx));
    margin(idx) = min(action.gainVectorPercent - ...
        v213.risk.tolerancePercent);
    bytes(idx) = action.attemptedByteSavingPercent;
end
table = [-margin, -bytes, reshape(eligible, [], 1)];
[~, order] = sortrows(table, [1, 2, 3]);
index = eligible(order(1));
end

function validateTrajectory( ...
        trajectory, protocol, presetName, seed, splitName)
required = {'contractVersion', 'protocolId', 'presetName', 'seed', ...
    'splitName', 'generationGitCommit', 'featureNames', ...
    'selection', 'cachePathsByStratum', ...
    'posteriorCounterfactualEnumerationUsed', ...
    'windowSelectionUsesTruth', ...
    'windowSelectionUsesFutureInformation', ...
    'validationClaimAllowed'};
selectionRequired = {'stratumNames', 'selectedTimesByStratum', ...
    'selectedFormationIdsByStratum', 'selectedScoresByStratum', ...
    'selectedRawFeaturesByStratum', ...
    'selectedComponentRanksByStratum'};
if ~isstruct(trajectory) || ~isscalar(trajectory) || ...
        any(~isfield(trajectory, required)) || ...
        ~strcmp(trajectory.contractVersion, ...
            'stratified-direct-graph-trajectory-v218-v1') || ...
        ~strcmp(trajectory.protocolId, protocol.id) || ...
        ~strcmp(trajectory.presetName, presetName) || ...
        trajectory.seed ~= seed || ...
        ~strcmp(trajectory.splitName, splitName) || ...
        trajectory.posteriorCounterfactualEnumerationUsed || ...
        trajectory.windowSelectionUsesTruth || ...
        trajectory.windowSelectionUsesFutureInformation || ...
        trajectory.validationClaimAllowed || ...
        ~isstruct(trajectory.selection) || ...
        any(~isfield(trajectory.selection, selectionRequired)) || ...
        numel(trajectory.selection.stratumNames) ~= ...
            protocol.collection.maximumPairsPerTrajectory || ...
        numel(trajectory.cachePathsByStratum) ~= ...
            protocol.collection.maximumPairsPerTrajectory || ...
        any(cellfun(@(path) exist(path, 'file') ~= 2, ...
            trajectory.cachePathsByStratum))
    error('DirectGraphThreeArmH3V218:TrajectoryProvenance', ...
        'The V218 trajectory does not match the H=3 labeling request.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('DirectGraphThreeArmH3V218:WriteReport', ...
        'Could not write the V218 three-arm report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V218 stratified direct-graph three-arm H=3 labels\n\n');
fprintf(fid, '- Split / scene / seed: `%s / %s / %d`\n', ...
    result.splitName, result.presetName, result.seed);
fprintf(fid, '- Labeled states: `%d`\n', result.stateCount);
fprintf(fid, '- Continuous vector targets retained below gates: `1`\n');
fprintf(fid, '- Complete Gaussian-mixture label payloads retained: `1`\n\n');
for state = result.states
    fprintf(fid, '## %s: t=%d, F%d\n\n', ...
        state.stratumName, state.currentTime, state.formationId);
    fprintf(fid, ['- Candidate bank full / position-safe / shortlisted / ', ...
        'credit-feasible / bidirectional-transport-feasible: ', ...
        '`%d / %d / %d / %d / %d`\n'], ...
        state.fullCandidateCount, state.positionSafeCandidateCount, ...
        state.shortlistedCandidateCount, ...
        state.creditFeasibleCandidateCount, ...
        state.transportFeasibleCandidateCount);
    fprintf(fid, '- Descriptive best admissible alternative: `%s`\n\n', ...
        state.bestAdmissibleActionName);
    fprintf(fid, ['- Causal use: stage 1 trains on no-op vs withholding; ', ...
        'stage 2 trains on repair vs the paired withholding outcome.\n\n']);
    fprintf(fid, ['| Alternative | Source / label | E-OSPA | RMSE | ', ...
        'Consistency | Terminal consistency | Byte saving | ', ...
        'Worst no-op-relative | Worst withholding-relative | ', ...
        'Risk / reserve / causal |\n']);
    fprintf(fid, '|:--|:--|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
    for action = state.actions
        source = '-';
        if action.sourceId > 0
            source = sprintf('S%d / [%d,%d]', action.sourceId, ...
                action.label(1), action.label(2));
        end
        incrementalMinimum = NaN;
        if strcmp(action.kind, ...
                'withholding-plus-complete-label-kla')
            incrementalMinimum = min( ...
                action.incrementalFromWithholdingGainVectorPercent);
        end
        fprintf(fid, ['| %s | %s | %+.3f%% | %+.3f%% | ', ...
            '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
            '%+.3f%% | %d / %d / %d |\n'], ...
            action.kind, source, action.meanEospaGainPercent, ...
            action.meanRmseGainPercent, action.consensusGainPercent, ...
            action.terminalConsensusGainPercent, ...
            action.attemptedByteSavingPercent, ...
            min(action.gainVectorPercent), incrementalMinimum, ...
            action.riskPassed, ...
            action.byteReservePassed, action.causallyAdmissible);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

