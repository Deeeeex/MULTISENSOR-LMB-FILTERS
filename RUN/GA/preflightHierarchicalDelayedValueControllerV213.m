function [reportPath, result] = ...
        preflightHierarchicalDelayedValueControllerV213(options)
% PREFLIGHTHIERARCHICALDELAYEDVALUECONTROLLERV213 Freeze the V213 contract.
%
% This is a source-only/development preflight.  It reuses the three opened
% policy-state action banks, the four H=3 semantic anchors, and the V212
% exact replay.  It does not run a new tracking outcome, fit a model, open a
% registered split, or support a held-out performance claim.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getHierarchicalDelayedValueControllerV213Protocol();
evidenceRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v209');
policySources = getField(options, 'policySources', ...
    defaultPolicySources(evidenceRoot));
recursivePath = char(getField(options, 'recursivePath', fullfile( ...
    evidenceRoot, 'formation_h3_residual_anchors', ...
    'x36_seed211_t72_h8', ...
    'FORMATION_H3_RESIDUAL_DATASET_V210.mat')));
exactReplayPath = char(getField(options, 'exactReplayPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v212', 'policy_state_h3_replay', ...
    'x36_seed211_t73_f6', ...
    'POLICY_STATE_H3_COUNTERFACTUAL_V212.mat')));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'controller_preflight', ...
    'x36_seed211_contract')));
if ~isstruct(policySources) || ...
        ~all(isfield(policySources, {'actionTime', 'path'})) || ...
        exist(recursivePath, 'file') ~= 2 || ...
        exist(exactReplayPath, 'file') ~= 2
    error('HierarchicalControllerPreflightV213:MissingInput', ...
        'The opened V208/V210/V212 contract evidence is required.');
end

validateRegisteredScenes(protocol);
recursiveLoaded = load(recursivePath, 'dataset');
recursive = recursiveLoaded.dataset;
validateRecursiveDataset(recursive, protocol);

states = repmat(emptyState(), 1, numel(policySources));
expectedTimes = [73, 76, 77];
expectedMembership = [true, false, true];
expectedFormationIds = {[6, 1], 1, 1};
expectedLabelCounts = [16, 8, 8];
expectedReleaseIds = {1, 1, 1};
for stateIdx = 1:numel(policySources)
    source = policySources(stateIdx);
    if source.actionTime ~= expectedTimes(stateIdx) || ...
            exist(char(source.path), 'file') ~= 2
        error('HierarchicalControllerPreflightV213:PolicySource', ...
            'The registered policy-state source manifest drifted.');
    end
    loaded = load(char(source.path), 'dataset');
    dataset = loaded.dataset;
    validatePolicyDataset(dataset, source.actionTime);
    rows = dataset.rows;
    featureMatrix = vertcat(rows.features);
    proposalOptions = struct( ...
        'modeFeatureMatrix', featureMatrix, ...
        'modeFeatureNames', {dataset.actionFeatureNames}, ...
        'releasableFormationIds', ...
            dataset.blocks(1).releaseCandidateFormationIds);
    [proposed, releaseIds, proposalDetails] = ...
        proposeHierarchicalFormationActionsV213( ...
            dataset.blocks(1).graph, rows, proposalOptions);
    teacherIdx = find([rows.teacherKey]);
    if numel(teacherIdx) ~= 1
        error('HierarchicalControllerPreflightV213:TeacherKey', ...
            'Every opened policy state must expose one teacher key.');
    end
    proposedCandidateIndices = [proposed.candidateIndex];
    teacherSelected = ismember( ...
        rows(teacherIdx).candidateIndex, proposedCandidateIndices);

    state = emptyState();
    state.actionTime = source.actionTime;
    state.sourcePath = char(source.path);
    state.fullCandidateCount = numel(rows);
    state.formationNeed = proposalDetails.formationNeed;
    state.selectedFormationIds = ...
        proposalDetails.selectedFormationIds;
    state.proposedLabelCandidateCount = numel(proposed);
    state.releaseFormationIds = releaseIds;
    state.proposalCount = proposalDetails.proposalCount;
    state.propagationFeatureAttemptedBytes = ...
        proposalDetails.propagationFeatureAttemptedBytes;
    state.teacherFormationId = ...
        rows(teacherIdx).receiverFormationId;
    state.teacherSourceId = rows(teacherIdx).sourceId;
    state.teacherLabel = rows(teacherIdx).label;
    state.teacherSelected = teacherSelected;
    state.expectedTeacherSelected = expectedMembership(stateIdx);
    state.membershipCorrect = teacherSelected == ...
        state.expectedTeacherSelected;
    state.expectedFormationIds = expectedFormationIds{stateIdx};
    state.formationSelectionCorrect = isequal( ...
        state.selectedFormationIds, state.expectedFormationIds);
    state.expectedLabelCandidateCount = ...
        expectedLabelCounts(stateIdx);
    state.labelCountCorrect = ...
        state.proposedLabelCandidateCount == ...
            state.expectedLabelCandidateCount;
    state.expectedReleaseFormationIds = ...
        expectedReleaseIds{stateIdx};
    state.releaseSelectionCorrect = isequal( ...
        state.releaseFormationIds, ...
        state.expectedReleaseFormationIds);
    state.proposalWithinCap = proposalDetails.proposalWithinCap;
    state.everyLabelPropagationCostExact = ...
        all(proposalDetails. ...
            propagationFeatureBytesByLabelProposal == 208);
    states(stateIdx) = state;
end

riskRows = evaluateRiskAnchors(recursive, protocol.risk);
exactLoaded = load(exactReplayPath, 'result');
exactReplay = exactLoaded.result;
exactReplayMatched = validateExactReplay(exactReplay);

positiveMask = [states.expectedTeacherSelected];
negativeMask = ~positiveMask;
result = struct();
result.contractVersion = ...
    'hierarchical-delayed-value-controller-v213-preflight-v1';
result.generatedAt = datestr(now, 31);
result.protocol = protocol;
result.policySources = policySources;
result.recursivePath = recursivePath;
result.exactReplayPath = exactReplayPath;
result.states = states;
result.positiveTeacherCoverage = nnz( ...
    positiveMask & [states.teacherSelected]);
result.positiveTeacherCount = nnz(positiveMask);
result.negativeTeacherExclusion = nnz( ...
    negativeMask & ~[states.teacherSelected]);
result.negativeTeacherCount = nnz(negativeMask);
result.membershipContractPassed = ...
    all([states.membershipCorrect]);
result.formationSelectionContractPassed = ...
    all([states.formationSelectionCorrect]);
result.proposalSizeContractPassed = ...
    all([states.labelCountCorrect]) && ...
    all([states.proposalWithinCap]);
result.releaseSelectionContractPassed = ...
    all([states.releaseSelectionCorrect]);
result.propagationCostContractPassed = ...
    all([states.everyLabelPropagationCostExact]);
result.riskRows = riskRows;
result.riskAdmissionContractPassed = ...
    all([riskRows.admissionCorrect]);
result.exactReplayMatched = exactReplayMatched;
result.registeredSceneCount = numel(unique([ ...
    protocol.split.mainPresets, protocol.split.stressPresets, ...
    protocol.split.scaleExtrapolationPresets]));
result.developmentAnchorSeed = protocol.developmentAnchorSeeds;
result.newTrackingOutcomesRun = false;
result.modelFitted = false;
result.calibrationPerformed = false;
result.completeTrajectoryHeldOut = false;
result.validationClaimAllowed = false;
result.preflightPassed = result.membershipContractPassed && ...
    result.formationSelectionContractPassed && ...
    result.proposalSizeContractPassed && ...
    result.releaseSelectionContractPassed && ...
    result.propagationCostContractPassed && ...
    result.riskAdmissionContractPassed && ...
    result.exactReplayMatched;
result.evidenceBoundary = [ ...
    'V213 freezes a scale-aware, truth-free proposal cap, explicit ', ...
    'release feasibility, one-page semantic cooldown, H=3 vector risk ', ...
    'budget, propagation-feature communication charge and disjoint ', ...
    'trajectory split before opening seeds 1301 and above.  The ', ...
    'seed-211 anchors test only proposal membership, risk semantics and ', ...
    'exact replay.  They cannot train, calibrate, validate or support a ', ...
    'new tracking-performance claim.'];
if ~result.preflightPassed
    error('HierarchicalControllerPreflightV213:ContractFailure', ...
        'At least one frozen V213 development contract failed.');
end

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'HIERARCHICAL_DELAYED_VALUE_CONTROLLER_V213_PREFLIGHT.mat');
reportPath = fullfile(outputRoot, ...
    'HIERARCHICAL_DELAYED_VALUE_CONTROLLER_V213_PREFLIGHT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V213 hierarchical controller preflight: %s\n', reportPath);
end

function sources = defaultPolicySources(evidenceRoot)
template = struct('actionTime', 0, 'path', '');
times = [73, 76, 77];
leaves = {'t73_after_v206_prefix', ...
    't76_after_v206_prefix', 't77_after_v204_prefix'};
sources = repmat(template, 1, numel(times));
for idx = 1:numel(times)
    sources(idx).actionTime = times(idx);
    sources(idx).path = fullfile(evidenceRoot, ...
        'policy_induced_immediate', leaves{idx}, ...
        'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat');
end
end

function validatePolicyDataset(dataset, actionTime)
required = {'contractVersion', 'seed', 'returnTimes', ...
    'actionFeatureNames', 'blocks', 'rows', 'blockCount', ...
    'featuresUseTruth', 'featuresUseFutureInformation', ...
    'recursiveTargetsIncluded', 'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-label-kla-immediate-dataset-v208-v1') || ...
        dataset.seed ~= 211 || dataset.blockCount ~= 1 || ...
        numel(dataset.returnTimes) ~= 1 || ...
        dataset.returnTimes ~= actionTime || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed || ...
        isempty(dataset.rows)
    error('HierarchicalControllerPreflightV213:PolicyDataset', ...
        'A policy-state V208 development dataset is malformed.');
end
end

function validateRecursiveDataset(dataset, protocol)
required = {'contractVersion', 'seed', 'returnHorizonSteps', ...
    'recursiveTargetNames', 'rows', 'rowCount', ...
    'trainingAllowed', 'calibrationAllowed', ...
    'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-h3-residual-dataset-v210-v1') || ...
        dataset.seed ~= protocol.developmentAnchorSeeds || ...
        dataset.returnHorizonSteps ~= protocol.horizonSteps || ...
        dataset.rowCount ~= 4 || dataset.trainingAllowed || ...
        dataset.calibrationAllowed || dataset.validationClaimAllowed || ...
        ~isequal(reshape(dataset.recursiveTargetNames, 1, []), ...
            protocol.risk.targetNames)
    error('HierarchicalControllerPreflightV213:RecursiveDataset', ...
        'The V210 recursive target contract drifted.');
end
end

function rows = evaluateRiskAnchors(dataset, risk)
template = struct('name', '', 'actionTime', 0, ...
    'gainPercent', zeros(1, 0), 'minimumRiskMarginPercent', NaN, ...
    'staticByteSavingPercent', NaN, 'targetRiskPassed', false, ...
    'byteReservePassed', false, 'admitted', false, ...
    'expectedAdmitted', false, 'admissionCorrect', false);
rows = repmat(template, 1, dataset.rowCount);
expectedTimes = [72, 73, 76, 77];
expectedAdmission = [false, true, false, true];
for rowIdx = 1:dataset.rowCount
    source = dataset.rows(rowIdx);
    if source.actionTime ~= expectedTimes(rowIdx)
        error('HierarchicalControllerPreflightV213:RiskOrder', ...
            'The V210 development anchor order drifted.');
    end
    row = template;
    row.name = source.name;
    row.actionTime = source.actionTime;
    row.gainPercent = source.recursiveGainPercent;
    margin = row.gainPercent - risk.tolerancePercent;
    row.minimumRiskMarginPercent = min(margin);
    row.staticByteSavingPercent = ...
        source.candidateStaticByteSavingPercent;
    row.targetRiskPassed = all(margin >= -1e-10);
    row.byteReservePassed = row.staticByteSavingPercent >= ...
        risk.minimumStaticAttemptedByteSavingPercent - 1e-10;
    row.admitted = row.targetRiskPassed && row.byteReservePassed;
    row.expectedAdmitted = expectedAdmission(rowIdx);
    row.admissionCorrect = ...
        row.admitted == row.expectedAdmitted;
    rows(rowIdx) = row;
end
end

function matched = validateExactReplay(result)
required = {'branchTime', 'noOpReproduction', ...
    'candidateReproduction', 'truthUsedAtRuntime', ...
    'futureMeasurementsUsedForFeatures', ...
    'validationClaimAllowed'};
if ~isstruct(result) || ~isscalar(result) || ...
        ~all(isfield(result, required)) || result.branchTime ~= 73 || ...
        result.truthUsedAtRuntime || ...
        result.futureMeasurementsUsedForFeatures || ...
        result.validationClaimAllowed
    error('HierarchicalControllerPreflightV213:ExactReplay', ...
        'The V212 exact replay contract is malformed.');
end
matched = reproductionExact(result.noOpReproduction) && ...
    reproductionExact(result.candidateReproduction);
if ~matched
    error('HierarchicalControllerPreflightV213:ExactReplay', ...
        'V212 no longer exactly reproduces both H=3 branches.');
end
end

function exact = reproductionExact(value)
required = {'matched', 'eospaMaximumDifference', ...
    'rmseMaximumDifference', 'consensusMaximumDifference', ...
    'attemptedBytesExact'};
exact = isstruct(value) && isscalar(value) && ...
    all(isfield(value, required)) && value.matched && ...
    value.eospaMaximumDifference == 0 && ...
    value.rmseMaximumDifference == 0 && ...
    value.consensusMaximumDifference == 0 && ...
    value.attemptedBytesExact;
end

function validateRegisteredScenes(protocol)
presets = unique([protocol.split.mainPresets, ...
    protocol.split.stressPresets, ...
    protocol.split.scaleExtrapolationPresets], 'stable');
for presetIdx = 1:numel(presets)
    config = buildDynamicTopologyScenarioConfig(presets{presetIdx});
    if config.numberOfSensors < 24 || ...
            config.fovTotalAngleDeg ~= 120 || ...
            config.fovRange ~= 300
        error('HierarchicalControllerPreflightV213:SceneContract', ...
            'A registered scale/geometry preset drifted: %s.', ...
            presets{presetIdx});
    end
end
end

function state = emptyState()
state = struct('actionTime', 0, 'sourcePath', '', ...
    'fullCandidateCount', 0, 'formationNeed', zeros(1, 0), ...
    'selectedFormationIds', zeros(1, 0), ...
    'proposedLabelCandidateCount', 0, ...
    'releaseFormationIds', zeros(1, 0), 'proposalCount', 0, ...
    'propagationFeatureAttemptedBytes', 0, ...
    'teacherFormationId', 0, 'teacherSourceId', 0, ...
    'teacherLabel', zeros(2, 1), 'teacherSelected', false, ...
    'expectedTeacherSelected', false, ...
    'membershipCorrect', false, ...
    'expectedFormationIds', zeros(1, 0), ...
    'formationSelectionCorrect', false, ...
    'expectedLabelCandidateCount', 0, ...
    'labelCountCorrect', false, ...
    'expectedReleaseFormationIds', zeros(1, 0), ...
    'releaseSelectionCorrect', false, ...
    'proposalWithinCap', false, ...
    'everyLabelPropagationCostExact', false);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('HierarchicalControllerPreflightV213:ReportOpen', ...
        'Could not write the V213 preflight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
protocol = result.protocol;
fprintf(fid, '# V213 hierarchical delayed-value controller preflight\n\n');
fprintf(fid, '- Preflight passed: `%d`\n', result.preflightPassed);
fprintf(fid, '- Base policy / H: `%s / %d`\n', ...
    protocol.basePolicyName, protocol.horizonSteps);
fprintf(fid, '- Formation rule: `need >= %.2f max`, at most `%d`\n', ...
    protocol.proposal.relativeNeedFloor, ...
    protocol.proposal.maximumFormationCount);
fprintf(fid, '- Mode cap / total cap: `%d per mode / %d`\n', ...
    protocol.proposal.topPerMode, ...
    protocol.proposal.maximumProposalCount);
fprintf(fid, '- Static attempted-byte reserve: `%.1f%%`\n', ...
    protocol.risk.minimumStaticAttemptedByteSavingPercent);
fprintf(fid, '- Registered scene presets: `%d`\n', ...
    result.registeredSceneCount);
fprintf(fid, '- New outcomes / fit / calibration: `0 / 0 / 0`\n\n');

fprintf(fid, ['| Time | Need-selected formations | Label / release / ', ...
    'total | Teacher selected | Feature bytes | Contract |\n']);
fprintf(fid, '|--:|:--|:--|:--:|--:|:--:|\n');
for state = result.states
    fprintf(fid, '| %d | `%s` | %d / %d / %d | %d | %d B | %d |\n', ...
        state.actionTime, integerList(state.selectedFormationIds), ...
        state.proposedLabelCandidateCount, ...
        numel(state.releaseFormationIds), state.proposalCount, ...
        state.teacherSelected, ...
        state.propagationFeatureAttemptedBytes, ...
        state.membershipCorrect && ...
            state.formationSelectionCorrect && ...
            state.labelCountCorrect && ...
            state.releaseSelectionCorrect && ...
            state.proposalWithinCap && ...
            state.everyLabelPropagationCostExact);
end

fprintf(fid, '\n## Frozen risk budget on semantic anchors\n\n');
fprintf(fid, ['| Action | Minimum target margin | Static saving | ', ...
    'Admit | Expected |\n']);
fprintf(fid, '|:--|--:|--:|:--:|:--:|\n');
for row = result.riskRows
    fprintf(fid, '| `%s` | %+.3f%% | %+.3f%% | %d | %d |\n', ...
        row.name, row.minimumRiskMarginPercent, ...
        row.staticByteSavingPercent, row.admitted, ...
        row.expectedAdmitted);
end

fprintf(fid, '\n## Exact short-horizon replay\n\n');
fprintf(fid, ['V212 still reproduces the no-op and known t=73 F6 ', ...
    'candidate branches with zero E-OSPA, RMSE and consistency ', ...
    'difference and exact attempted bytes: `%d`.\n\n'], ...
    result.exactReplayMatched);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = integerList(values)
if isempty(values)
    text = '--';
else
    text = strtrim(sprintf('%d ', values));
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
