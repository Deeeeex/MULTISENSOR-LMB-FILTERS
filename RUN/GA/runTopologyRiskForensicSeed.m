function [reportPath, summaryPath, summary, attribution] = ...
    runTopologyRiskForensicSeed(seed, simulationLength, runExperiment)
% RUNTOPOLOGYRISKFORENSICSEED Diagnose recovery-topology position risk.
%
% The default seed is 96, the N20 topology-recovery outlier where recovery
% improved delivery/effective graph but worsened truth and position metrics.

if nargin < 1 || isempty(seed)
    seed = 96;
end
if nargin < 2 || isempty(simulationLength)
    simulationLength = 100;
end
if nargin < 3 || isempty(runExperiment)
    runExperiment = true;
end

scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir)
    scriptDir = pwd;
end
projectRoot = resolveProjectRoot(scriptDir);
addpath(projectRoot);
addpath(scriptDir);
setPath;

baseSeed = seed - 1;
experimentOverrides = buildForensicOverrides(simulationLength);
armSelection = { ...
    'Recovery stress: Periodic light static topology', ...
    'Recovery stress: Reliability-guarded dynamic topology'};

fprintf('\nTopology risk forensic run\n');
fprintf('Seed: %d, baseSeed: %d, simulationLength: %d\n', ...
    seed, baseSeed, simulationLength);

reportPath = '';
summaryPath = fullfile(scriptDir, sprintf( ...
    'topology_risk_forensic_seed%d_len%d_%s.mat', ...
    seed, simulationLength, datestr(now, 'yyyymmdd_HHMMSS')));
summary = [];
attribution = struct();

if ~runExperiment
    fprintf('Dry run only. No experiment was launched.\n');
    attribution.config = experimentOverrides;
    return;
end

[reportPath, summary] = ...
    runMultisensorFilters_formation_4plus4_DualThresholdEventTriggerCompare( ...
        1, baseSeed, true, true, 'default', armSelection, ...
        experimentOverrides);
attribution = computeForensicAttribution(summary);
save(summaryPath, 'summary', 'reportPath', 'attribution', ...
    'experimentOverrides');
appendForensicReport(reportPath, attribution);
printForensicAttribution(attribution, reportPath, summaryPath);
end

function overrides = buildForensicOverrides(simulationLength)
overrides = struct( ...
    'simulationLength', simulationLength, ...
    'calibration', buildAlwaysLightCalibrationStub(), ...
    'pDropByEdge', buildBridgeFailureDropMatrix(8, 0.97, 0.08), ...
    'includeTopologyRecoveryStressVariants', true, ...
    'recoveryTopologyReliabilityWeight', 0.55, ...
    'recoveryTopologyOverlapWeight', 0.35, ...
    'recoveryTopologyComplementarityWeight', 0.10, ...
    'recoveryTopologyStaticEdgeBonus', 0.35, ...
    'recoveryModeAwareFusionWeights', false, ...
    'recoveryLightFusionWeightFactor', 1.0, ...
    'recoveryMaxSelfFusionWeight', 1.0, ...
    'recoveryTopologyFallbackToBase', true, ...
    'storeDebugArtifacts', true);
end

function attribution = computeForensicAttribution(summary)
staticIdx = find(strcmp(summary.armNames, ...
    'Recovery stress: Periodic light static topology'), 1);
recoveryIdx = find(strcmp(summary.armNames, ...
    'Recovery stress: Reliability-guarded dynamic topology'), 1);
if isempty(staticIdx) || isempty(recoveryIdx)
    error('Forensic arms were not found in the summary.');
end

staticDebug = summary.debugArtifacts{1, staticIdx};
recoveryDebug = summary.debugArtifacts{1, recoveryIdx};
staticPosition = staticDebug.consensusPositionSeries;
recoveryPosition = recoveryDebug.consensusPositionSeries;
positionDelta = recoveryPosition - staticPosition;
[worstDelta, worstTime] = max(positionDelta);

attribution = struct();
attribution.seed = summary.trialSeeds(1);
attribution.staticArm = summary.armNames{staticIdx};
attribution.recoveryArm = summary.armNames{recoveryIdx};
attribution.metricDeltas = struct( ...
    'payloadBytes', percentChange( ...
        summary.trials.payloadBytes(1, staticIdx), ...
        summary.trials.payloadBytes(1, recoveryIdx)), ...
    'deliveryCount', percentChange( ...
        summary.trials.deliveryCount(1, staticIdx), ...
        summary.trials.deliveryCount(1, recoveryIdx)), ...
    'localEOspa', percentChange( ...
        mean(summary.trials.localEOspa(1, :, staticIdx)), ...
        mean(summary.trials.localEOspa(1, :, recoveryIdx))), ...
    'consensusOspa', percentChange( ...
        summary.trials.consensusOspa(1, staticIdx), ...
        summary.trials.consensusOspa(1, recoveryIdx)), ...
    'positionDisagreement', percentChange( ...
        summary.trials.consensusPosition(1, staticIdx), ...
        summary.trials.consensusPosition(1, recoveryIdx)), ...
    'cardinalityDispersion', percentChange( ...
        summary.trials.consensusCardinality(1, staticIdx), ...
        summary.trials.consensusCardinality(1, recoveryIdx)));
attribution.riskMeans = struct( ...
    'staticEdgeRisk', summary.trials.topologyStaticEdgeRisk(1, recoveryIdx), ...
    'nonStaticEdgeRisk', ...
        summary.trials.topologyNonStaticEdgeRisk(1, recoveryIdx), ...
    'newEdgeRisk', summary.trials.topologyNewEdgeRisk(1, recoveryIdx), ...
    'staticLabelMismatch', ...
        summary.trials.topologyStaticLabelMismatch(1, recoveryIdx), ...
    'nonStaticLabelMismatch', ...
        summary.trials.topologyNonStaticLabelMismatch(1, recoveryIdx), ...
    'newEdgeLabelMismatch', ...
        summary.trials.topologyNewEdgeLabelMismatch(1, recoveryIdx), ...
    'fusionNonStaticWeightMass', ...
        summary.trials.fusionNonStaticWeightMass(1, recoveryIdx), ...
    'fusionNewEdgeWeightMass', ...
        summary.trials.fusionNewEdgeWeightMass(1, recoveryIdx), ...
    'fusionRiskWeightedEdgeRisk', ...
        summary.trials.fusionRiskWeightedEdgeRisk(1, recoveryIdx), ...
    'fusionRiskWeightedLabelMismatch', ...
        summary.trials.fusionRiskWeightedLabelMismatch(1, recoveryIdx), ...
    'topologyChurnRate', ...
        summary.trials.topologyChurnRate(1, recoveryIdx));
attribution.positionSeries = struct( ...
    'static', staticPosition, ...
    'recovery', recoveryPosition, ...
    'delta', positionDelta);
attribution.worstPositionDelta = worstDelta;
attribution.worstPositionTime = worstTime;
attribution.worstTimeDiagnostics = extractTimeDiagnostics( ...
    recoveryDebug.communicationDiagnostics, worstTime);
attribution.topPositionDeltaTimes = summarizeTopDeltaTimes( ...
    recoveryDebug.communicationDiagnostics, positionDelta, 5);
attribution.hypothesisScores = scoreFailureHypotheses(attribution);
end

function details = extractTimeDiagnostics(diagnostics, currentTime)
activeMask = diagnostics.topologyActiveEdge(:, :, currentTime);
baseMask = diagnostics.edgeMask;
nonStaticMask = activeMask & ~baseMask;
newMask = diagnostics.newEdgeActivated(:, :, currentTime);
fusionWeights = diagnostics.fusionWeight(:, :, currentTime);
sensorCount = size(activeMask, 1);
details = struct( ...
    'time', currentTime, ...
    'effectiveWeightLambda2', ...
        diagnostics.effectiveWeightAlgebraicConnectivity(currentTime), ...
    'topologyEdgeRisk', diagnostics.topologyEdgeRisk(currentTime), ...
    'topologyNonStaticEdgeRisk', ...
        diagnostics.topologyNonStaticEdgeRisk(currentTime), ...
    'topologyNewEdgeRisk', diagnostics.topologyNewEdgeRisk(currentTime), ...
    'topologyLabelMismatch', ...
        diagnostics.topologyLabelMismatch(currentTime), ...
    'topologyNonStaticLabelMismatch', ...
        diagnostics.topologyNonStaticLabelMismatch(currentTime), ...
    'topologyNewEdgeLabelMismatch', ...
        diagnostics.topologyNewEdgeLabelMismatch(currentTime), ...
    'fusionNonStaticWeightMass', ...
        diagnostics.fusionNonStaticWeightMass(currentTime), ...
    'fusionNewEdgeWeightMass', ...
        diagnostics.fusionNewEdgeWeightMass(currentTime), ...
    'fusionRiskWeightedEdgeRisk', ...
        diagnostics.fusionRiskWeightedEdgeRisk(currentTime), ...
    'fusionRiskWeightedLabelMismatch', ...
        diagnostics.fusionRiskWeightedLabelMismatch(currentTime), ...
    'nonStaticDirectedEdgeCount', nnz(nonStaticMask), ...
    'newDirectedEdgeCount', nnz(newMask), ...
    'nonStaticFusionWeightTotal', sum(fusionWeights(nonStaticMask)), ...
    'newEdgeFusionWeightTotal', sum(fusionWeights(newMask)), ...
    'nonStaticFusionWeightPerNode', ...
        sum(fusionWeights(nonStaticMask)) / max(sensorCount, 1));
end

function rows = summarizeTopDeltaTimes(diagnostics, positionDelta, maxRows)
valid = isfinite(positionDelta);
indices = find(valid);
[~, order] = sort(positionDelta(valid), 'descend');
rows = repmat(emptyTimeRow(), 1, min(maxRows, numel(order)));
for rowIdx = 1:numel(rows)
    timeIdx = indices(order(rowIdx));
    timeDetails = extractTimeDiagnostics(diagnostics, timeIdx);
    rows(rowIdx) = struct( ...
        'time', timeIdx, ...
        'positionDelta', positionDelta(timeIdx), ...
        'nonStaticRisk', timeDetails.topologyNonStaticEdgeRisk, ...
        'nonStaticMismatch', timeDetails.topologyNonStaticLabelMismatch, ...
        'nonStaticWeight', timeDetails.fusionNonStaticWeightMass, ...
        'newEdgeWeight', timeDetails.fusionNewEdgeWeightMass, ...
        'effectiveWeightLambda2', timeDetails.effectiveWeightLambda2);
end
end

function row = emptyTimeRow()
row = struct( ...
    'time', NaN, ...
    'positionDelta', NaN, ...
    'nonStaticRisk', NaN, ...
    'nonStaticMismatch', NaN, ...
    'nonStaticWeight', NaN, ...
    'newEdgeWeight', NaN, ...
    'effectiveWeightLambda2', NaN);
end

function scores = scoreFailureHypotheses(attribution)
r = attribution.riskMeans;
scores = struct();
scores.wrongNewEdges = mean([ ...
    normalizeScore(r.newEdgeRisk, 0.20, 0.70), ...
    normalizeScore(r.newEdgeLabelMismatch, 0.20, 0.80), ...
    normalizeScore(r.fusionNewEdgeWeightMass, 0.02, 0.15)]);
scores.overStrongDynamicWeights = mean([ ...
    normalizeScore(r.fusionNonStaticWeightMass, 0.10, 0.45), ...
    normalizeScore(r.fusionRiskWeightedEdgeRisk, 0.20, 0.70)]);
scores.topologyChurn = normalizeScore(r.topologyChurnRate, 0.05, 0.35);
scores.labelMismatch = mean([ ...
    normalizeScore(r.nonStaticLabelMismatch, 0.20, 0.80), ...
    normalizeScore(r.fusionRiskWeightedLabelMismatch, 0.20, 0.80)]);
end

function value = normalizeScore(x, low, high)
if ~isfinite(x)
    value = 0;
else
    value = min(max((x - low) / max(high - low, eps), 0), 1);
end
end

function appendForensicReport(reportPath, attribution)
if isempty(reportPath) || ~exist(reportPath, 'file')
    return;
end
fid = fopen(reportPath, 'a');
if fid < 0
    return;
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '\n## Topology Risk Forensic Attribution\n\n');
fprintf(fid, '- Seed: `%d`\n', attribution.seed);
fprintf(fid, '- Worst position-delta time: `%d` (delta %.3f)\n\n', ...
    attribution.worstPositionTime, attribution.worstPositionDelta);
fprintf(fid, '| Hypothesis | Score |\n');
fprintf(fid, '|:--|--:|\n');
fprintf(fid, '| Wrong new edges | %.3f |\n', ...
    attribution.hypothesisScores.wrongNewEdges);
fprintf(fid, '| Over-strong dynamic weights | %.3f |\n', ...
    attribution.hypothesisScores.overStrongDynamicWeights);
fprintf(fid, '| Topology churn | %.3f |\n', ...
    attribution.hypothesisScores.topologyChurn);
fprintf(fid, '| Label mismatch | %.3f |\n\n', ...
    attribution.hypothesisScores.labelMismatch);
fprintf(fid, '| Top delta time | Position delta | Non-static risk | Non-static mismatch | Non-static weight | New-edge weight | Eff. lambda2 |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for idx = 1:numel(attribution.topPositionDeltaTimes)
    row = attribution.topPositionDeltaTimes(idx);
    fprintf(fid, '| %d | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f |\n', ...
        row.time, row.positionDelta, row.nonStaticRisk, ...
        row.nonStaticMismatch, row.nonStaticWeight, ...
        row.newEdgeWeight, row.effectiveWeightLambda2);
end
end

function printForensicAttribution(attribution, reportPath, summaryPath)
fprintf('\nTopology risk forensic attribution\n');
fprintf('Report: %s\n', reportPath);
fprintf('Summary: %s\n', summaryPath);
fprintf('Seed: %d\n', attribution.seed);
fprintf('Position disagreement change: %.2f%%\n', ...
    attribution.metricDeltas.positionDisagreement);
fprintf('Worst position-delta time: %d (delta %.3f)\n', ...
    attribution.worstPositionTime, attribution.worstPositionDelta);
fprintf('Hypothesis scores: wrong-new=%.3f, overweight=%.3f, churn=%.3f, mismatch=%.3f\n', ...
    attribution.hypothesisScores.wrongNewEdges, ...
    attribution.hypothesisScores.overStrongDynamicWeights, ...
    attribution.hypothesisScores.topologyChurn, ...
    attribution.hypothesisScores.labelMismatch);
end

function pDropByEdge = buildBridgeFailureDropMatrix( ...
    numberOfSensors, bridgeDrop, defaultDrop)
pDropByEdge = defaultDrop * ones(numberOfSensors);
pDropByEdge(1:numberOfSensors+1:end) = 0;
staticBridgeEdges = [1 5; 2 6; 3 7; 4 8];
for edgeIdx = 1:size(staticBridgeEdges, 1)
    left = staticBridgeEdges(edgeIdx, 1);
    right = staticBridgeEdges(edgeIdx, 2);
    pDropByEdge(left, right) = bridgeDrop;
    pDropByEdge(right, left) = bridgeDrop;
end
end

function calibration = buildAlwaysLightCalibrationStub()
calibration = struct();
calibration.multi.loose = [0.20, 0.40];
calibration.multi.default = [0.25, 0.60];
calibration.multi.strict = [0.35, 0.80];
calibration.information.loose = [0.20, 0.40];
calibration.information.default = [0.25, 0.60];
calibration.information.strict = [0.35, 0.80];
calibration.sampleCount.utility = 0;
calibration.sampleCount.informationGain = 0;
end

function value = percentChange(baseline, candidate)
if ~isfinite(baseline) || abs(baseline) <= eps || ~isfinite(candidate)
    value = NaN;
else
    value = 100 * (candidate - baseline) / baseline;
end
end

function projectRoot = resolveProjectRoot(scriptDir)
projectRoot = scriptDir;
while ~exist(fullfile(projectRoot, 'setPath.m'), 'file')
    parentDir = fileparts(projectRoot);
    if strcmp(parentDir, projectRoot)
        error('Could not locate project root from %s.', scriptDir);
    end
    projectRoot = parentDir;
end
end
