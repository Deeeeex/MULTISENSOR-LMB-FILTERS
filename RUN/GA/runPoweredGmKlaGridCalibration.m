function [summary, reportPath] = ...
    runPoweredGmKlaGridCalibration(writeReport)
% RUNPOWEREDGMKLAGRIDCALIBRATION Calibrate installed GM-KLA approximation.

if nargin < 1 || isempty(writeReport)
    writeReport = false;
end
[sourceOne, sourceTwo] = buildControlledSources();
sources = {sourceOne, sourceTwo};
fusionWeights = [0.55, 0.45];
model = struct('xDimension', 2, 'object', sourceOne([]));
fusionDetails = struct('eventType', [0, 2]);

frozenConfig = buildMixtureAwareKlaReferenceConfig();
frozenApproximation = fuseLmbPosteriorsByLabel( ...
    sources, fusionWeights, model, fusionWeights, ...
    fusionDetails, frozenConfig);

untruncatedConfig = buildMixtureAwareKlaReferenceConfig(struct( ...
    'mixtureAwareTopComponents', 3, ...
    'mixtureAwareMaxFusedComponents', 9, ...
    'mixtureAwareMaxComponentTuples', 9));
untruncatedApproximation = fuseLmbPosteriorsByLabel( ...
    sources, fusionWeights, model, fusionWeights, ...
    fusionDetails, untruncatedConfig);

projectedConfig = frozenConfig;
projectedConfig.mixtureAwareHeavyFusionEnabled = false;
projectedApproximation = fuseLmbPosteriorsByLabel( ...
    sources, fusionWeights, model, fusionWeights, ...
    fusionDetails, projectedConfig);

fineOptions = struct( ...
    'gridPointCount', 161, ...
    'sigmaExtent', 7, ...
    'candidateObjects', {{ ...
        frozenApproximation, untruncatedApproximation, ...
        projectedApproximation}}, ...
    'candidateNames', {{ ...
        'frozen-powered-gm-top3-max8', ...
        'untruncated-powered-gm-3x3', ...
        'projected-single-gaussian'}});
fine = evaluateLmbKlaGridOracle( ...
    sources, fusionWeights, fineOptions);
coarse = evaluateLmbKlaGridOracle( ...
    sources, fusionWeights, struct( ...
        'gridPointCount', 81, 'sigmaExtent', 7));

summary = struct();
summary.contractVersion = 'powered-gm-kla-grid-calibration-v1';
summary.fusionWeights = fusionWeights;
summary.fineOracle = fine;
summary.coarseOracle = coarse;
summary.logEtaGridChange = abs(fine.logEta - coarse.logEta);
summary.existenceGridChange = abs( ...
    fine.existenceProbability - coarse.existenceProbability);
summary.meanGridChange = norm(fine.mean - coarse.mean);
summary.covarianceGridChange = norm( ...
    fine.covariance - coarse.covariance, 'fro');

fprintf('Powered-GM KLA grid calibration\n');
fprintf(['  grid convergence: logEta %.3e, existence %.3e, ', ...
    'mean %.3e, covariance %.3e\n'], ...
    summary.logEtaGridChange, summary.existenceGridChange, ...
    summary.meanGridChange, summary.covarianceGridChange);
for candidateIdx = 1:numel(fine.comparisons)
    item = fine.comparisons(candidateIdx);
    fprintf(['  %s: TV %.4f, KL %.4f, mean %.4f, ', ...
        'covariance %.4f, |dr| %.4f\n'], ...
        item.name, item.totalVariation, item.klOracleToCandidate, ...
        item.meanError, item.covarianceError, ...
        item.existenceAbsoluteError);
end

reportPath = '';
if writeReport
    reportPath = fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
        sprintf('POWERED_GM_KLA_GRID_CALIBRATION_%s.md', ...
            datestr(now, 'yyyymmdd_HHMMSS')));
    writeCalibrationReport(reportPath, summary);
end
end

function [sourceOne, sourceTwo] = buildControlledSources()
sourceOne = buildObject(0.92, [0.45, 0.35, 0.20], ...
    {[-3.0; 0.0], [0.8; 2.1], [4.0; -1.0]}, ...
    {diag([0.8, 0.6]).^2, diag([0.7, 0.9]).^2, ...
        diag([1.0, 0.7]).^2});
sourceTwo = buildObject(0.88, [0.40, 0.25, 0.35], ...
    {[-2.5; 0.5], [0.3; 2.4], [4.5; -0.4]}, ...
    {diag([0.9, 0.7]).^2, diag([0.8, 0.8]).^2, ...
        diag([0.9, 0.8]).^2});
end

function object = buildObject(r, weights, means, covariances)
object = struct();
object.r = r;
object.numberOfGmComponents = numel(weights);
object.w = reshape(weights, 1, []);
object.mu = means;
object.Sigma = covariances;
object.birthTime = 1;
object.birthLocation = 1;
end

function writeCalibrationReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('PoweredGmKlaCalibration:ReportWriteFailed', ...
        'Could not open %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Powered-GM KLA grid calibration\n\n');
fprintf(fid, ['This controlled two-dimensional case directly integrates ', ...
    'the normalized density power on a tensor grid. It calibrates the ', ...
    'receiver approximation and is not a full-tracker result.\n\n']);
fprintf(fid, '| Candidate | TV | KL oracle-to-candidate | Mean error | Cov. error | Existence error | log eta error |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for candidateIdx = 1:numel(summary.fineOracle.comparisons)
    item = summary.fineOracle.comparisons(candidateIdx);
    fprintf(fid, '| %s | %.6f | %.6f | %.6f | %.6f | %.6f | %+.6f |\n', ...
        item.name, item.totalVariation, item.klOracleToCandidate, ...
        item.meanError, item.covarianceError, ...
        item.existenceAbsoluteError, item.logEtaError);
end
fprintf(fid, '\nGrid convergence (81 to 161 points per dimension):\n\n');
fprintf(fid, '- log eta: `%.3e`\n', summary.logEtaGridChange);
fprintf(fid, '- existence: `%.3e`\n', summary.existenceGridChange);
fprintf(fid, '- mean: `%.3e`\n', summary.meanGridChange);
fprintf(fid, '- covariance: `%.3e`\n', summary.covarianceGridChange);
fprintf(fid, '- fine-grid boundary mass: `%.3e`\n', ...
    summary.fineOracle.boundaryMassFraction);
clear cleanup;
end
