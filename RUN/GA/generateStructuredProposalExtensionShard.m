function [datasetPath, dataset] = ...
    generateStructuredProposalExtensionShard(seed, options)
% GENERATESTRUCTUREDPROPOSALEXTENSIONSHARD Add one v2 design seed.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getRollingSafeStructuredProposalProtocol();
seed = round(seed);
if ~isscalar(seed) || ...
        ~ismember(seed, protocol.extensionSeeds)
    error('Structured proposal shard seed is not registered.');
end
seedIdx = find(protocol.datasetSeeds == seed, 1);
if isempty(protocol.behaviorCacheSha256{seedIdx})
    error('Structured proposal shard cache SHA-256 is not frozen.');
end
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'datasets', ...
    'structured_proposal_shards'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, sprintf( ...
        ['rolling_safe_structured_proposal_', ...
         'm24_hard_t75_t83_seed%d_v2.mat'], seed)));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, sprintf( ...
        ['ROLLING_SAFE_STRUCTURED_PROPOSAL_', ...
         'M24_HARD_T75_T83_SEED%d_V2.md'], seed)));
generatorOptions = struct( ...
    'protocol', protocol, ...
    'seedList', seed, ...
    'outputDirectory', outputDirectory, ...
    'outputPath', datasetPath, ...
    'reportPath', reportPath);
[datasetPath, dataset] = ...
    generateTruthFreeBehaviorProposalDistillationDataset( ...
        generatorOptions);
if numel(dataset.blocks) ~= ...
        numel(protocol.snapshotTimes) || ...
        ~isequal([dataset.blocks.currentTime], ...
            protocol.snapshotTimes) || ...
        dataset.featuresUseTruth || ...
        dataset.behaviorTruthUsed || ...
        ~dataset.teacherTargetsUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome
    error('Structured proposal extension shard failed validation.');
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
