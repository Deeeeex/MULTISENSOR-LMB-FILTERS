function [auditPath, audit] = ...
    auditFormationH3MultiscaleSentinelValueModel(options)
% AUDITFORMATIONH3MULTISCALESENTINELVALUEMODEL Shared ridge sentinel.
%
% Architecture and regularization are selected only by leave-one-training-
% seed-out replay over seeds 211/223.  The chosen model is then fitted on all
% training blocks and evaluated exactly once on seed 227 across D12/M24/X36.
% The result may select a model direction, but no fitted head is deployable.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3MultiscaleTeacherProtocol();
datasetPath = getField(options, 'datasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v13', 'multiscale_teacher_sentinel', 'dataset', ...
    'formation_h3_multiscale_sentinel_dataset_v1.mat'));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v13', 'multiscale_teacher_sentinel', ...
    'representation_audit'));
lambdaGrid = getField(options, 'lambdaGrid', ...
    [1e-4, 1e-3, 1e-2, 0.1, 1, 10, 100, 1000]);
if exist(datasetPath, 'file') ~= 2 || ...
        isempty(lambdaGrid) || any(~isfinite(lambdaGrid)) || ...
        any(lambdaGrid <= 0)
    error('Formation H=3 multiscale model-audit options are invalid.');
end
loaded = load(datasetPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Formation H=3 multiscale sentinel dataset is missing.');
end
dataset = loaded.dataset;
validateDataset(dataset, protocol);
if ~dataset.sharedRidgeAuditAuthorized || ...
        ~dataset.oracleHeadroomGatePassed
    error([ ...
        'Formation H=3 shared ridge audit is not authorized because ', ...
        'the frozen multi-scale oracle-headroom gate failed.']);
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 multiscale model audit requires clean source.');
end

trainingMask = strcmp( ...
    {dataset.blocks.evidenceSplit}, 'sentinel-training');
developmentMask = strcmp( ...
    {dataset.blocks.evidenceSplit}, 'sentinel-development');
trainingBlocks = dataset.blocks(trainingMask);
developmentBlocks = dataset.blocks(developmentMask);
if numel(trainingBlocks) ~= 12 || numel(developmentBlocks) ~= 6 || ...
        ~isequal(unique([trainingBlocks.seed]), ...
            protocol.trainingSeeds) || ...
        ~isequal(unique([developmentBlocks.seed]), ...
            protocol.developmentSeeds)
    error('Formation H=3 sentinel split is invalid.');
end

architectures = {'direct', 'additive-pair-residual'};
candidates = repmat(emptyCandidate(), 1, ...
    numel(architectures) * numel(lambdaGrid));
cursor = 0;
for architectureIdx = 1:numel(architectures)
    for lambda = lambdaGrid
        cursor = cursor + 1;
        candidates(cursor) = evaluateTrainingCv( ...
            trainingBlocks, architectures{architectureIdx}, lambda);
        candidates(cursor).architectureOrder = architectureIdx;
        fprintf([ ...
            'formation H=3 training-CV %s lambda %.4g: ', ...
            'NRMSE %.3f, mean-r %.3f, top3 %.1f%%, ', ...
            'safe %.1f%%, selected gain %+.3f%%\n'], ...
            architectures{architectureIdx}, lambda, ...
            candidates(cursor).meanNormalizedRmse, ...
            candidates(cursor).targetPearson(1), ...
            100 * candidates(cursor).top3OracleCaptureFraction, ...
            100 * candidates(cursor).safeSelectionFraction, ...
            candidates(cursor).meanSelectedRealizedGainPercent);
    end
end
keys = zeros(numel(candidates), 6);
for idx = 1:numel(candidates)
    item = candidates(idx);
    keys(idx, :) = [ ...
        item.meanNormalizedRmse, ...
        -item.top3OracleCaptureFraction, ...
        -item.safeSelectionFraction, ...
        -item.targetPearson(1), ...
        item.architectureOrder, log10(item.lambda)];
end
[~, candidateOrder] = sortrows(keys);
candidates = candidates(candidateOrder);
selectedCv = candidates(1);

model = fitArchitecture( ...
    trainingBlocks, selectedCv.architecture, selectedCv.lambda);
developmentPredictions = cell(1, numel(developmentBlocks));
for blockIdx = 1:numel(developmentBlocks)
    developmentPredictions{blockIdx} = ...
        predictBlock(model, developmentBlocks(blockIdx));
end
development = evaluatePredictions( ...
    developmentBlocks, developmentPredictions, ...
    selectedCv.architecture, selectedCv.lambda);
scaleDiagnostics = repmat(emptyScaleDiagnostic(), ...
    1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    mask = strcmp({developmentBlocks.presetName}, ...
        protocol.presets{presetIdx});
    scaleEvaluation = evaluatePredictions( ...
        developmentBlocks(mask), developmentPredictions(mask), ...
        selectedCv.architecture, selectedCv.lambda);
    diagnostic = emptyScaleDiagnostic();
    diagnostic.presetName = protocol.presets{presetIdx};
    diagnostic.stateCount = nnz(mask);
    diagnostic.meanGainPearson = ...
        scaleEvaluation.targetPearson(1);
    diagnostic.top3OracleCaptureFraction = ...
        scaleEvaluation.top3OracleCaptureFraction;
    diagnostic.safeSelectionFraction = ...
        scaleEvaluation.safeSelectionFraction;
    diagnostic.dynamicSelectionFraction = ...
        scaleEvaluation.dynamicSelectionFraction;
    diagnostic.meanSelectedRealizedGainPercent = ...
        scaleEvaluation.meanSelectedRealizedGainPercent;
    scaleDiagnostics(presetIdx) = diagnostic;
end

developmentSignalGatePassed = ...
    development.targetPearson(1) >= ...
        protocol.minimumDevelopmentMeanGainPearson - 1e-12 && ...
    development.top3OracleCaptureFraction >= ...
        protocol.minimumDevelopmentTop3CaptureFraction - 1e-12 && ...
    development.safeSelectionFraction >= ...
        protocol.minimumDevelopmentSafeSelectionFraction - 1e-12 && ...
    development.meanSelectedRealizedGainPercent >= -1e-12;
nontrivialDynamicSelectionObserved = ...
    development.dynamicSelectionFraction > 0;

audit = struct();
audit.contractVersion = ...
    'formation-h3-multiscale-sentinel-value-audit-v1';
audit.protocolId = protocol.id;
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.datasetPath = datasetPath;
audit.datasetSha256 = computeFileSha256(datasetPath);
audit.datasetGenerationCommit = dataset.generationGitCommit;
audit.teacherGenerationCommit = dataset.teacherGenerationCommit;
audit.featureContractVersion = dataset.featureContractVersion;
audit.targetNames = dataset.targetNames;
audit.lambdaGrid = lambdaGrid;
audit.trainingCvCandidates = candidates;
audit.selectedTrainingCv = selectedCv;
audit.development = development;
audit.developmentScaleDiagnostics = scaleDiagnostics;
audit.minimumDevelopmentMeanGainPearson = ...
    protocol.minimumDevelopmentMeanGainPearson;
audit.minimumDevelopmentTop3CaptureFraction = ...
    protocol.minimumDevelopmentTop3CaptureFraction;
audit.minimumDevelopmentSafeSelectionFraction = ...
    protocol.minimumDevelopmentSafeSelectionFraction;
audit.oracleHeadroomGatePassed = ...
    dataset.oracleHeadroomGatePassed;
audit.developmentSignalGatePassed = developmentSignalGatePassed;
audit.nontrivialDynamicSelectionObserved = ...
    nontrivialDynamicSelectionObserved;
audit.predictorFreezeReviewAuthorized = ...
    developmentSignalGatePassed && ...
    nontrivialDynamicSelectionObserved;
audit.finalModelTrainingAuthorized = false;
audit.messagePassingModelAuthorized = false;
audit.validationClaimAllowed = false;
audit.openedSentinelDevelopmentOnly = true;
audit.reservedValidationSeeds = ...
    protocol.finalValidationSeedsReserved;
audit.evidenceBoundary = [ ...
    'Architecture and lambda use only leave-one-training-seed-out ', ...
    'replay over seeds 211 and 223. Seed 227 is evaluated once after ', ...
    'selection and may choose a representation direction only. The ', ...
    'fitted ridge model is not deployable. Reserved seeds remain ', ...
    'unopened until a later predictor, calibration rule, and exact ', ...
    'projector are frozen.'];

if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
auditPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    'formation_h3_multiscale_sentinel_value_audit_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'FORMATION_H3_MULTISCALE_SENTINEL_VALUE_AUDIT_V1.md'));
audit.auditPath = auditPath;
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Formation H=3 multiscale sentinel value audit: %s\n', ...
    auditPath);
end

function candidate = evaluateTrainingCv(blocks, architecture, lambda)
seeds = unique([blocks.seed]);
predictions = cell(1, numel(blocks));
for heldoutSeed = seeds
    fitMask = [blocks.seed] ~= heldoutSeed;
    heldoutMask = [blocks.seed] == heldoutSeed;
    model = fitArchitecture(blocks(fitMask), architecture, lambda);
    heldoutIndices = find(heldoutMask);
    for cursor = 1:numel(heldoutIndices)
        blockIdx = heldoutIndices(cursor);
        predictions{blockIdx} = predictBlock(model, blocks(blockIdx));
    end
end
if any(cellfun(@isempty, predictions))
    error('Formation H=3 training-CV predictions are incomplete.');
end
candidate = evaluatePredictions( ...
    blocks, predictions, architecture, lambda);
end

function candidate = evaluatePredictions( ...
        blocks, predictions, architecture, lambda)
[targetRmse, targetNormalizedRmse, targetPearson, rows] = ...
    summarizePredictions(blocks, predictions);
candidate = emptyCandidate();
candidate.architecture = architecture;
candidate.lambda = lambda;
candidate.targetRmse = targetRmse;
candidate.targetNormalizedRmse = targetNormalizedRmse;
candidate.targetPearson = targetPearson;
candidate.meanNormalizedRmse = mean(targetNormalizedRmse);
candidate.rows = rows;
candidate.top1OracleCaptureFraction = ...
    mean([rows.oracleMeanRank] <= 1);
candidate.top3OracleCaptureFraction = ...
    mean([rows.oracleMeanRank] <= 3);
candidate.safeSelectionFraction = ...
    mean([rows.selectedRealizedSafe]);
candidate.dynamicSelectionFraction = ...
    mean([rows.selectedActionIndex] ~= 1);
candidate.meanSelectedRealizedGainPercent = ...
    mean([rows.selectedRealizedGainPercent]);
candidate.positiveSelectedStateFraction = ...
    mean([rows.selectedRealizedGainPercent] > 1e-12);
end

function model = fitArchitecture(blocks, architecture, lambda)
model = struct( ...
    'architecture', architecture, 'lambda', lambda, ...
    'stateBalancedRowWeights', true);
switch architecture
    case 'direct'
        [X, Y, weights] = collectRows(blocks, 'all');
        model.direct = fitWeightedRidge(X, Y, weights, lambda);
    case 'additive-pair-residual'
        [localX, localY, localWeights] = ...
            collectRows(blocks, 'local');
        [pairX, pairResidual, pairWeights] = ...
            collectRows(blocks, 'pair-residual');
        model.local = fitWeightedRidge( ...
            localX, localY, localWeights, lambda);
        model.residual = fitWeightedRidge( ...
            pairX, pairResidual, pairWeights, lambda);
    otherwise
        error('Unknown formation H=3 multiscale architecture.');
end
end

function prediction = predictBlock(model, block)
switch model.architecture
    case 'direct'
        prediction = predictRidge(model.direct, block.features);
    case 'additive-pair-residual'
        prediction = zeros(size(block.targets));
        localMask = block.interventionOrder <= 1;
        prediction(localMask, :) = predictRidge( ...
            model.local, block.features(localMask, :));
        pairIndices = find(block.interventionOrder == 2);
        residual = predictRidge( ...
            model.residual, block.features(pairIndices, :));
        for cursor = 1:numel(pairIndices)
            actionIdx = pairIndices(cursor);
            formations = ...
                block.formationIndicesAuditOnly(actionIdx, :);
            singletonIndices = matchingSingletons( ...
                block, formations, block.trustWeights(actionIdx));
            prediction(actionIdx, :) = ...
                sum(prediction(singletonIndices, :), 1) + ...
                residual(cursor, :);
        end
end
referenceIdx = find(block.interventionOrder == 0);
if numel(referenceIdx) ~= 1
    error('Formation H=3 block lacks a unique reference action.');
end
prediction(referenceIdx, :) = 0;
if any(~isfinite(prediction(:)))
    error('Formation H=3 multiscale prediction is non-finite.');
end
end

function indices = matchingSingletons(block, formations, trust)
indices = zeros(1, 2);
for cursor = 1:2
    match = find(block.interventionOrder == 1 & ...
        block.formationIndicesAuditOnly(:, 1)' == formations(cursor) & ...
        abs(block.trustWeights - trust) <= 1e-12);
    if numel(match) ~= 1
        error('Formation H=3 pair lacks a unique singleton action.');
    end
    indices(cursor) = match;
end
end

function [X, Y, weights] = collectRows(blocks, mode)
X = zeros(0, size(blocks(1).features, 2));
Y = zeros(0, size(blocks(1).targets, 2));
weights = zeros(0, 1);
for block = blocks
    switch mode
        case 'all'
            mask = true(size(block.features, 1), 1);
            target = block.targets;
        case 'local'
            mask = block.interventionOrder <= 1;
            target = block.targets;
        case 'pair-residual'
            mask = block.interventionOrder == 2;
            target = block.interactionResidualTargets;
        otherwise
            error('Unknown formation H=3 row collection mode.');
    end
    rowCount = nnz(mask);
    if rowCount < 1
        error('Formation H=3 state has no rows for a model head.');
    end
    X = [X; block.features(mask, :)]; %#ok<AGROW>
    Y = [Y; target(mask, :)]; %#ok<AGROW>
    weights = [weights; ...
        ones(rowCount, 1) / rowCount]; %#ok<AGROW>
end
end

function model = fitWeightedRidge(X, Y, weights, lambda)
if isempty(X) || size(X, 1) ~= size(Y, 1) || ...
        numel(weights) ~= size(X, 1) || ...
        any(~isfinite(X(:))) || any(~isfinite(Y(:))) || ...
        any(~isfinite(weights)) || any(weights <= 0)
    error('Formation H=3 weighted ridge rows are invalid.');
end
weights = weights(:) / sum(weights);
xMean = weights' * X;
yMean = weights' * Y;
xCentered = bsxfun(@minus, X, xMean);
yCentered = bsxfun(@minus, Y, yMean);
xScale = sqrt(weights' * (xCentered .^ 2));
yScale = sqrt(weights' * (yCentered .^ 2));
xScale(~isfinite(xScale) | xScale < 1e-12) = 1;
yScale(~isfinite(yScale) | yScale < 1e-12) = 1;
Xn = bsxfun(@rdivide, xCentered, xScale);
Yn = bsxfun(@rdivide, yCentered, yScale);
design = [ones(size(Xn, 1), 1), Xn];
sqrtWeights = sqrt(weights);
weightedDesign = bsxfun(@times, design, sqrtWeights);
weightedTarget = bsxfun(@times, Yn, sqrtWeights);
regularizer = diag([0, ones(1, size(Xn, 2))]);
coefficients = (weightedDesign' * weightedDesign + ...
    lambda * regularizer) \ ...
    (weightedDesign' * weightedTarget);
model = struct( ...
    'xMean', xMean, 'xScale', xScale, ...
    'yMean', yMean, 'yScale', yScale, ...
    'coefficients', coefficients, ...
    'stateBalancedRowWeights', true);
end

function prediction = predictRidge(model, X)
Xn = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.xMean), model.xScale);
normalized = [ones(size(Xn, 1), 1), Xn] * ...
    model.coefficients;
prediction = bsxfun(@plus, ...
    bsxfun(@times, normalized, model.yScale), model.yMean);
end

function [rmse, normalizedRmse, correlation, rows] = ...
        summarizePredictions(blocks, predictions)
allTarget = zeros(0, size(blocks(1).targets, 2));
allPrediction = allTarget;
allWeights = zeros(0, 1);
rows = repmat(emptyRow(), 1, numel(blocks));
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    prediction = predictions{blockIdx};
    if ~isequal(size(prediction), size(block.targets))
        error('Formation H=3 prediction shape is invalid.');
    end
    nonreference = block.interventionOrder > 0;
    allTarget = [allTarget; ...
        block.targets(nonreference, :)]; %#ok<AGROW>
    allPrediction = [allPrediction; ...
        prediction(nonreference, :)]; %#ok<AGROW>
    nonreferenceCount = nnz(nonreference);
    allWeights = [allWeights; ...
        ones(nonreferenceCount, 1) / nonreferenceCount]; %#ok<AGROW>
    [~, predictedOrder] = sort(prediction(:, 1), 'descend');
    oracleRank = find(predictedOrder == ...
        block.oracleDeploymentActionIndex, 1);
    predictedFeasible = all(prediction >= 0, 2);
    referenceIdx = find(block.interventionOrder == 0, 1);
    predictedFeasible(referenceIdx) = true;
    feasibleIndices = find(predictedFeasible);
    [~, localBest] = max(prediction(feasibleIndices, 1));
    selectedIdx = feasibleIndices(localBest);
    realized = block.targets(selectedIdx, :);
    row = emptyRow();
    row.presetName = block.presetName;
    row.seed = block.seed;
    row.currentTime = block.currentTime;
    row.oracleActionIndex = block.oracleDeploymentActionIndex;
    row.oracleActionName = block.oracleDeploymentActionName;
    row.oracleMeanRank = oracleRank;
    row.selectedActionIndex = selectedIdx;
    row.selectedActionName = block.actionNames{selectedIdx};
    row.selectedPredictedGainPercent = prediction(selectedIdx, 1);
    row.selectedRealizedGainPercent = realized(1);
    row.selectedRealizedSafe = all(realized >= -1e-12);
    rows(blockIdx) = row;
end
allWeights = allWeights / sum(allWeights);
errorValues = allPrediction - allTarget;
rmse = sqrt(allWeights' * (errorValues .^ 2));
targetMean = allWeights' * allTarget;
targetCentered = bsxfun(@minus, allTarget, targetMean);
targetScale = sqrt(allWeights' * (targetCentered .^ 2));
targetScale(~isfinite(targetScale) | targetScale < 1e-12) = 1;
normalizedRmse = rmse ./ targetScale;
correlation = zeros(1, size(allTarget, 2));
for targetIdx = 1:size(allTarget, 2)
    correlation(targetIdx) = weightedPearson( ...
        allPrediction(:, targetIdx), ...
        allTarget(:, targetIdx), allWeights);
end
end

function value = weightedPearson(left, right, weights)
left = left(:);
right = right(:);
weights = weights(:) / sum(weights);
left = left - weights' * left;
right = right - weights' * right;
denominator = sqrt(weights' * (left .^ 2)) * ...
    sqrt(weights' * (right .^ 2));
if denominator <= eps
    value = 0;
else
    value = (weights' * (left .* right)) / denominator;
end
end

function validateDataset(dataset, protocol)
required = { ...
    'contractVersion', 'protocolId', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'teacherGenerationCommit', ...
    'featureContractVersion', 'featureNames', 'targetNames', ...
    'blocks', 'blockCount', 'trainingBlockCount', ...
    'developmentBlockCount', 'scaleSummaries', ...
    'oracleHeadroomGatePassed', 'featuresUseTruth', ...
    'featuresUseFutureMeasurements', 'featuresUseFutureOutcome', ...
    'targetsUseTruth', 'targetsUseFutureMeasurements', ...
    'openedSentinelDevelopmentOnly', ...
    'sharedRidgeAuditAuthorized', ...
    'finalModelTrainingAuthorized', ...
    'messagePassingModelAuthorized', 'validationClaimAllowed', ...
    'reservedValidationSeeds'};
if ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-h3-multiscale-sentinel-dataset-v1') || ...
        ~strcmp(dataset.protocolId, protocol.id) || ...
        dataset.generationTrackedWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        dataset.blockCount ~= 18 || ...
        dataset.trainingBlockCount ~= 12 || ...
        dataset.developmentBlockCount ~= 6 || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureMeasurements || ...
        dataset.featuresUseFutureOutcome || ...
        ~dataset.targetsUseTruth || ...
        ~dataset.targetsUseFutureMeasurements || ...
        ~dataset.openedSentinelDevelopmentOnly || ...
        dataset.finalModelTrainingAuthorized || ...
        dataset.messagePassingModelAuthorized || ...
        dataset.validationClaimAllowed || ...
        ~isequal(dataset.reservedValidationSeeds, ...
            protocol.finalValidationSeedsReserved) || ...
        ~isempty(intersect([dataset.blocks.seed], ...
            dataset.reservedValidationSeeds))
    error('Formation H=3 multiscale dataset contract failed.');
end
for block = dataset.blocks
    if size(block.features, 2) ~= numel(dataset.featureNames) || ...
            size(block.targets, 2) ~= numel(dataset.targetNames) || ...
            size(block.features, 1) ~= size(block.targets, 1) || ...
            any(~isfinite(block.features(:))) || ...
            any(~isfinite(block.targets(:))) || ...
            block.featuresUseTruth || ...
            block.featuresUseFutureMeasurements || ...
            block.featuresUseFutureOutcome || ...
            ~block.targetsUseTruth || ...
            ~block.targetsUseFutureMeasurements || ...
            ~block.openedSentinelDevelopmentOnly || ...
            block.validationClaimAllowed
        error('Formation H=3 multiscale dataset block is invalid.');
    end
end
end

