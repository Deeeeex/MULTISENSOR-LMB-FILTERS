end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 multiscale model report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
selected = audit.selectedTrainingCv;
development = audit.development;
fprintf(fid, '# Formation H=3 multiscale sentinel value audit\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    audit.contractVersion, audit.protocolId);
fprintf(fid, '- Audit / dataset / teacher commit: `%s / %s / %s`\n', ...
    audit.generationGitCommit, audit.datasetGenerationCommit, ...
    audit.teacherGenerationCommit);
fprintf(fid, '- Training-CV selected architecture / lambda: `%s / %.4g`\n', ...
    selected.architecture, selected.lambda);
fprintf(fid, '- Development mean-gain Pearson: `%+.4f` (gate `%+.2f`)\n', ...
    development.targetPearson(1), ...
    audit.minimumDevelopmentMeanGainPearson);
fprintf(fid, '- Development top-1 / top-3 capture: `%.1f%% / %.1f%%`\n', ...
    100 * development.top1OracleCaptureFraction, ...
    100 * development.top3OracleCaptureFraction);
fprintf(fid, '- Development safe / dynamic selection: `%.1f%% / %.1f%%`\n', ...
    100 * development.safeSelectionFraction, ...
    100 * development.dynamicSelectionFraction);
fprintf(fid, '- Development selected realized gain: `%+.3f%%`\n', ...
    development.meanSelectedRealizedGainPercent);
fprintf(fid, '- Oracle / development signal gates: `%d / %d`\n', ...
    audit.oracleHeadroomGatePassed, ...
    audit.developmentSignalGatePassed);
fprintf(fid, '- Nontrivial dynamic selection / freeze review: `%d / %d`\n', ...
    audit.nontrivialDynamicSelectionObserved, ...
    audit.predictorFreezeReviewAuthorized);
fprintf(fid, '- Final model / GNN / validation authorized: `%d / %d / %d`\n\n', ...
    audit.finalModelTrainingAuthorized, ...
    audit.messagePassingModelAuthorized, ...
    audit.validationClaimAllowed);

fprintf(fid, '| Training-CV architecture | Lambda | NRMSE | Mean r | Top-3 | Safe | Gain |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for candidate = audit.trainingCvCandidates
    fprintf(fid, '| `%s` | %.4g | %.3f | %+.3f | %.1f%% | %.1f%% | %+.3f%% |\n', ...
        candidate.architecture, candidate.lambda, ...
        candidate.meanNormalizedRmse, candidate.targetPearson(1), ...
        100 * candidate.top3OracleCaptureFraction, ...
        100 * candidate.safeSelectionFraction, ...
        candidate.meanSelectedRealizedGainPercent);
end

fprintf(fid, '\n## Development scale diagnostics\n\n');
fprintf(fid, '| Scale | States | Mean r | Top-3 | Safe | Dynamic | Gain |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for diagnostic = audit.developmentScaleDiagnostics
