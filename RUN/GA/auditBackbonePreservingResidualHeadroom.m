function [auditPath, audit] = ...
    auditBackbonePreservingResidualHeadroom(sourcePath, options)
% AUDITBACKBONEPRESERVINGRESIDUALHEADROOM Fail-closed action-space gate.
%
% Privileged arms diagnose whether preserving a dominant fixed-index input
% and changing only a low-weight residual input has enough tracking
% headroom. A pass authorizes return-data generation only.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getBackbonePreservingResidualProtocol( ...
    getField(options, 'protocolVariant', 'v1-e05'));
if nargin < 1 || isempty(sourcePath)
    presetName = getField(options, ...
        'presetName', protocol.scenarioPresets{1});
    seed = getField(options, ...
        'seed', protocol.screeningSeeds);
    sourcePath = findLatestSource( ...
        presetName, seed, options, protocol);
end
if exist(sourcePath, 'file') ~= 2
    error('Missing residual-headroom source: %s', sourcePath);
end
loaded = load(sourcePath, 'summary');
if ~isfield(loaded, 'summary')
    error('Residual-headroom source does not contain summary.');
end
summary = loaded.summary;
validateSource(summary, protocol);

aggregates = summary.aggregate;
modes = {aggregates.mode};
local = requireArm(aggregates, modes, protocol.localArm);
baselines = repmat(aggregates(1), ...
    1, numel(protocol.baselineArms));
for baselineIdx = 1:numel(protocol.baselineArms)
    baselines(baselineIdx) = requireArm( ...
        aggregates, modes, protocol.baselineArms{baselineIdx});
end
matchedStatic = requireArm( ...
    aggregates, modes, protocol.matchedResidualStaticArm);
candidateModes = { ...
    protocol.currentOracleArm, ...
    protocol.minimaxOracleArm};
rows = repmat(emptyRow(), 1, numel(candidateModes));
for candidateIdx = 1:numel(candidateModes)
    candidate = requireArm( ...
        aggregates, modes, candidateModes{candidateIdx});
    rows(candidateIdx) = evaluateCandidate( ...
        candidate, baselines, matchedStatic, ...
        local, protocol);
end

passing = find([rows.passed]);
if isempty(passing)
    [~, selectedIdx] = max( ...
        [rows.minimumBaselineMeanGainFraction]);
else
    [~, localIdx] = min([rows(passing).focusEospa]);
    selectedIdx = passing(localIdx);
end
selected = rows(selectedIdx);
gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'backbone-preserving-residual-headroom-audit-v1';
audit.protocolId = protocol.id;
audit.generatedAt = datestr(now, 31);
audit.presetName = summary.presetName;
audit.seed = summary.seeds;
audit.sourcePath = sourcePath;
audit.sourceSha256 = computeFileSha256(sourcePath);
audit.sourceArmModes = modes;
audit.baselineModes = protocol.baselineArms;
audit.matchedResidualStaticMode = ...
    protocol.matchedResidualStaticArm;
audit.candidateModes = candidateModes;
audit.rows = rows;
audit.selectedCandidateMode = selected.mode;
audit.selectedMinimumBaselineMeanGainFraction = ...
    selected.minimumBaselineMeanGainFraction;
audit.selectedMinimumBaselineWorstNodeGainFraction = ...
    selected.minimumBaselineWorstNodeGainFraction;
audit.selectedAttemptedByteDeviationFraction = ...
    selected.attemptedByteDeviationFraction;
audit.headroomGatePassed = any([rows.passed]);
audit.returnDataGenerationAuthorized = ...
    audit.headroomGatePassed;
audit.criticTrainingAuthorized = false;
audit.x36PolicyRunAuthorized = false;
audit.heldoutClaimAllowed = false;
audit.privilegedDiagnosticOnly = true;
audit.auditGitCommit = gitState.commit;
audit.auditTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.auditUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.evidenceBoundary = [ ...
    'This development audit tests the additive residual action ', ...
    'space against local-only, fixed-index w=0.50, fixed-index ', ...
    'w=0.70, and an equal-payload static residual control. The ', ...
    'candidate policies read truth and are nondeployable. A pass ', ...
    'authorizes paired return-data generation only.'];

outputDirectory = getField(options, ...
    'outputDirectory', fileparts(sourcePath));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
stem = sprintf( ...
    'BACKBONE_RESIDUAL_HEADROOM_AUDIT_%s_SEED%d', ...
    upper(strrep(summary.presetName, '-', '_')), ...
    summary.seeds);
auditPath = fullfile(outputDirectory, ...
    [lower(stem), '.mat']);
reportPath = fullfile(outputDirectory, [stem, '.md']);
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit, protocol);
fprintf('Audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function row = evaluateCandidate( ...
        candidate, baselines, matchedStatic, local, protocol)
baselineMeanGain = arrayfun(@(baseline) ...
    fractionalGain(baseline.focusEospa, ...
        candidate.focusEospa), baselines);
baselineTailGain = arrayfun(@(baseline) ...
    fractionalGain(baseline.focusWorstSensorEospa, ...
        candidate.focusWorstSensorEospa), baselines);
byteDeviation = abs(candidate.focusAttemptedBytes - ...
    matchedStatic.focusAttemptedBytes) / ...
    max(matchedStatic.focusAttemptedBytes, 1);
row = emptyRow();
row.mode = candidate.mode;
row.name = candidate.name;
row.focusEospa = candidate.focusEospa;
row.focusWorstSensorEospa = ...
    candidate.focusWorstSensorEospa;
row.minimumBaselineMeanGainFraction = ...
    min(baselineMeanGain);
row.minimumBaselineWorstNodeGainFraction = ...
    min(baselineTailGain);
row.localMeanGainFraction = fractionalGain( ...
    local.focusEospa, candidate.focusEospa);
row.localWorstNodeGainFraction = fractionalGain( ...
    local.focusWorstSensorEospa, ...
    candidate.focusWorstSensorEospa);
row.attemptedByteDeviationFraction = byteDeviation;
row.backbonePreservingFraction = getMetric( ...
    candidate, 'policyBackbonePreservingResidualFraction');
row.sensorWindowStrongFraction = getMetric( ...
    candidate, 'policySensorWindowStrongFraction');
row.formationWindowStrongFraction = getMetric( ...
    candidate, 'policyFormationWindowStrongFraction');
row.sensorWindowMatureCount = getMetric( ...
    candidate, 'policySensorWindowMatureCount');
row.formationWindowMatureCount = getMetric( ...
    candidate, 'policyFormationWindowMatureCount');
row.oneStepReservePassFraction = getMetric( ...
    candidate, 'policyOneStepTopologyReservePassFraction');
row.policyRepairRate = getMetric( ...
    candidate, 'policyRepairRate');
row.payloadEmergencyRate = getMetric( ...
    candidate, 'policyPayloadEmergencyRate');
row.topologyInfeasibleRate = getMetric( ...
    candidate, 'focusTopologyInfeasibleRate');
row.truthUseFraction = getMetric( ...
    candidate, 'policyTruthUseFraction');
row.sourceWeightMean = getMetric( ...
    candidate, 'policySourceWeightMean');
row.sourceWeightSpread = getMetric( ...
    candidate, 'policySourceWeightSpread');
row.meanGatePassed = ...
    row.minimumBaselineMeanGainFraction + 1e-12 >= ...
        protocol.minimumMeanTrackingGainFraction && ...
    row.localMeanGainFraction >= -1e-12;
row.tailGatePassed = ...
    row.minimumBaselineWorstNodeGainFraction >= ...
        -protocol.maximumWorstNodeRegressionFraction - 1e-12 && ...
    row.localWorstNodeGainFraction >= -1e-12;
row.byteGatePassed = ...
    row.attemptedByteDeviationFraction <= ...
        protocol.maximumAttemptedByteDeviationFraction + 1e-12;
row.backboneGatePassed = ...
    abs(row.backbonePreservingFraction - 1) <= 1e-12;
row.safetyGatePassed = ...
    row.sensorWindowMatureCount >= 1 && ...
    row.formationWindowMatureCount >= 1 && ...
    abs(row.sensorWindowStrongFraction - 1) <= 1e-12 && ...
    abs(row.formationWindowStrongFraction - 1) <= 1e-12 && ...
    abs(row.oneStepReservePassFraction - 1) <= 1e-12 && ...
    abs(row.policyRepairRate) <= 1e-12 && ...
    abs(row.payloadEmergencyRate) <= 1e-12 && ...
    abs(row.topologyInfeasibleRate) <= 1e-12;
row.provenanceGatePassed = ...
    abs(row.truthUseFraction - 1) <= 1e-12 && ...
    abs(row.sourceWeightMean - ...
        protocol.residualSourceWeight) <= 1e-12 && ...
    abs(row.sourceWeightSpread) <= 1e-12;
row.passed = row.meanGatePassed && ...
    row.tailGatePassed && row.byteGatePassed && ...
    row.backboneGatePassed && row.safetyGatePassed && ...
    row.provenanceGatePassed;
end

function validateSource(summary, protocol)
required = {'presetName', 'seeds', 'options', 'aggregate'};
if ~isstruct(summary) || ~all(isfield(summary, required)) || ...
        ~ismember(summary.presetName, protocol.scenarioPresets) || ...
        ~isscalar(summary.seeds) || ...
        summary.options.continuationStartTime ~= ...
            protocol.continuationStartTime || ...
        summary.options.maxTimeSteps ~= ...
            protocol.continuationEndTime || ...
        ~strcmp(summary.options.rollingSafeBackboneMode, ...
            protocol.residualBackboneMode)
    error('Residual-headroom source does not match the protocol.');
end
modes = {summary.aggregate.mode};
if ~all(ismember(protocol.armNames, modes)) || ...
        numel(modes) ~= numel(protocol.armNames)
    error('Residual-headroom source has incomplete or extra arms.');
end
end

function arm = requireArm(aggregates, modes, mode)
index = find(strcmp(modes, mode));
if numel(index) ~= 1
    error('Expected exactly one residual-headroom arm: %s.', mode);
end
arm = aggregates(index);
end

function value = getMetric(arm, fieldName)
if ~isfield(arm, fieldName) || ...
        ~isscalar(arm.(fieldName)) || ...
        ~isfinite(arm.(fieldName))
    value = NaN;
else
    value = arm.(fieldName);
end
end

function gain = fractionalGain(reference, candidate)
gain = (reference - candidate) / max(abs(reference), eps);
end

function sourcePath = findLatestSource( ...
        presetName, seed, options, protocol)
outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'backbone_residual_headroom', sprintf( ...
            '%s_%s_seed%d', ...
            strrep(protocol.variant, '-', '_'), ...
            strrep(presetName, '-', '_'), seed)));
pattern = sprintf( ...
    'DYNAMIC_TOPOLOGY_CONTINUATION_%s_T75_N1_*.mat', ...
    upper(strrep(presetName, '-', '_')));
files = dir(fullfile(outputDirectory, pattern));
if isempty(files)
    error('No complete residual-headroom source found in %s.', ...
        outputDirectory);
end
[~, latestIdx] = max([files.datenum]);
sourcePath = fullfile( ...
    files(latestIdx).folder, files(latestIdx).name);
end

function writeReport(path, audit, protocol)
fileId = fopen(path, 'w');
if fileId < 0
    error('Could not open residual-headroom report: %s', path);
end
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, ...
    '# Backbone-preserving residual headroom audit\n\n');
fprintf(fileId, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fileId, '- Preset: `%s`\n', audit.presetName);
fprintf(fileId, '- Seed: `%d`\n', audit.seed);
fprintf(fileId, '- Source SHA-256: `%s`\n', ...
    audit.sourceSha256);
fprintf(fileId, ...
    '- Dominant/residual weights: `%.2f / %.2f`\n', ...
    protocol.dominantSourceWeight, ...
    protocol.residualSourceWeight);
fprintf(fileId, '- Baselines: `%s`\n', ...
    strjoin(audit.baselineModes, ', '));
fprintf(fileId, '- Headroom gate passed: `%d`\n', ...
    audit.headroomGatePassed);
fprintf(fileId, ...
    '- Return-data generation authorized: `%d`\n', ...
    audit.returnDataGenerationAuthorized);
fprintf(fileId, '- Evidence boundary: %s\n\n', ...
    audit.evidenceBoundary);
fprintf(fileId, ['| Candidate | E-OSPA | Worst node | ', ...
    'Min mean gain | Min tail gain | Local mean | Local tail | ', ...
    'Byte dev. | B3 | Repair | Emergency | Pass |\n']);
fprintf(fileId, ...
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for rowIdx = 1:numel(audit.rows)
    row = audit.rows(rowIdx);
    fprintf(fileId, ...
        '| `%s` | %.4f | %.4f | %.2f%% | %.2f%% | %.2f%% | %.2f%% | %.2f%% | %.3f | %.3f | %.3f | %d |\n', ...
        row.mode, row.focusEospa, ...
        row.focusWorstSensorEospa, ...
        100 * row.minimumBaselineMeanGainFraction, ...
        100 * row.minimumBaselineWorstNodeGainFraction, ...
        100 * row.localMeanGainFraction, ...
        100 * row.localWorstNodeGainFraction, ...
        100 * row.attemptedByteDeviationFraction, ...
        min(row.sensorWindowStrongFraction, ...
            row.formationWindowStrongFraction), ...
        row.policyRepairRate, ...
        row.payloadEmergencyRate, row.passed);
end
end

function row = emptyRow()
row = struct( ...
    'mode', '', 'name', '', ...
    'focusEospa', NaN, ...
    'focusWorstSensorEospa', NaN, ...
    'minimumBaselineMeanGainFraction', NaN, ...
    'minimumBaselineWorstNodeGainFraction', NaN, ...
    'localMeanGainFraction', NaN, ...
    'localWorstNodeGainFraction', NaN, ...
    'attemptedByteDeviationFraction', NaN, ...
    'backbonePreservingFraction', NaN, ...
    'sensorWindowStrongFraction', NaN, ...
    'formationWindowStrongFraction', NaN, ...
    'sensorWindowMatureCount', NaN, ...
    'formationWindowMatureCount', NaN, ...
    'oneStepReservePassFraction', NaN, ...
    'policyRepairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'truthUseFraction', NaN, ...
    'sourceWeightMean', NaN, ...
    'sourceWeightSpread', NaN, ...
    'meanGatePassed', false, ...
    'tailGatePassed', false, ...
    'byteGatePassed', false, ...
    'backboneGatePassed', false, ...
    'safetyGatePassed', false, ...
    'provenanceGatePassed', false, ...
    'passed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
