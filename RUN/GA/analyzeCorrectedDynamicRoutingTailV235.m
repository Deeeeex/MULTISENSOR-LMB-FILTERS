function [reportPath, result] = ...
        analyzeCorrectedDynamicRoutingTailV235(options)
% ANALYZECORRECTEDDYNAMICROUTINGTAILV235 Localize V227 tail regression.
%
% Route pages are reconstructed from the same causal geometry/reliability
% policy.  Tracking errors come only from the completed paired V227 result
% and are used offline to identify which route segments need a safe fallback.

if nargin < 1 || isempty(options)
    options = struct();
end
resultPath = char(getField(options, 'resultPath', ''));
if isempty(resultPath) || exist(resultPath, 'file') ~= 2
    error('CorrectedDynamicRoutingTailV235:InvalidRequest', ...
        'A completed paired V227 MAT result is required.');
end
loaded = load(resultPath, 'result');
paired = loaded.result;
required = {'contractVersion', 'presetName', 'seed', 'static', ...
    'dynamic', 'comparison', 'staticRegistration', ...
    'pairedOutcomeAvailable', 'generationGitCommit'};
if ~isstruct(paired) || ~isscalar(paired) || ...
        any(~isfield(paired, required)) || ...
        ~strcmp(paired.contractVersion, ...
            'corrected-static-routing-v227-full-episode-result-v1') || ...
        ~paired.pairedOutcomeAvailable
    error('CorrectedDynamicRoutingTailV235:ResultContract', ...
        'The V227 pair is missing or incomplete.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    paired.presetName, paired.seed);
protocol = getCorrectedStaticRoutingBaselineV227Protocol();
nodeCount = inputs.config.numberOfSensors;
timeCount = inputs.config.simulationLength;
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
formationIds = unique(groupIds, 'stable');
if ~isequal(size(paired.static.positionEospaBySensorTime), ...
        [nodeCount, timeCount]) || ...
        ~isequal(size(paired.dynamic.positionEospaBySensorTime), ...
            [nodeCount, timeCount]) || ...
        ~isequal(size(paired.static.positionRmseBySensorTime), ...
            [nodeCount, timeCount]) || ...
        ~isequal(size(paired.dynamic.positionRmseBySensorTime), ...
            [nodeCount, timeCount])
    error('CorrectedDynamicRoutingTailV235:MetricShape', ...
        'The paired sensor-time metric arrays changed shape.');
end

[dynamicPages, dynamicWeights, routeDetails] = ...
    reconstructDynamicPages(inputs, protocol);
staticAdjacency = logical(paired.staticRegistration.adjacency);
staticWeights = paired.staticRegistration.fusionWeightMatrix;
staticPages = repmat(staticAdjacency, 1, 1, timeCount);
if paired.static.uniqueTopologyCount ~= 1 || ...
        paired.dynamic.uniqueTopologyCount ~= uniquePageCount(dynamicPages) || ...
        paired.dynamic.topologyChangeCount ~= pageChangeCount(dynamicPages) || ...
        any(pageCounts(dynamicPages) ~= ...
            protocol.directedInputsPerReceiver * nodeCount)
    error('CorrectedDynamicRoutingTailV235:RouteReconstruction', ...
        'The reconstructed route sequence differs from V227.');
end

changeTimes = find(pageChanged(dynamicPages)) + 1;
segmentStarts = [1, changeTimes];
segmentEnds = [changeTimes - 1, timeCount];
segmentCount = numel(segmentStarts);
formationAudits = repmat(emptyFormationAudit(), ...
    1, numel(formationIds));
for formationPosition = 1:numel(formationIds)
    formationId = formationIds(formationPosition);
    members = find(groupIds == formationId);
    staticEospa = mean( ...
        paired.static.positionEospaBySensorTime(members, :), 1);
    dynamicEospa = mean( ...
        paired.dynamic.positionEospaBySensorTime(members, :), 1);
    staticRmse = mean( ...
        paired.static.positionRmseBySensorTime(members, :), 1);
    dynamicRmse = mean( ...
        paired.dynamic.positionRmseBySensorTime(members, :), 1);
    segmentAudits = repmat(emptySegmentAudit(), 1, segmentCount);
    for segmentIndex = 1:segmentCount
        firstTime = segmentStarts(segmentIndex);
        lastTime = segmentEnds(segmentIndex);
        times = firstTime:lastTime;
        dynamicAdjacency = dynamicPages(:, :, firstTime);
        segmentAudits(segmentIndex) = struct( ...
            'segmentIndex', segmentIndex, ...
            'firstTime', firstTime, 'lastTime', lastTime, ...
            'routeChangedAtStart', segmentIndex > 1 && ...
                formationRowsChanged(dynamicPages, members, firstTime), ...
            'differsFromStatic', any(any( ...
                dynamicAdjacency(members, :) ~= ...
                staticAdjacency(members, :))), ...
            'dynamicIncomingCrossPairs', crossPairs( ...
                dynamicAdjacency, groupIds, formationId), ...
            'staticIncomingCrossPairs', crossPairs( ...
                staticAdjacency, groupIds, formationId), ...
            'dynamicIncomingSourcesByReceiver', { ...
                incomingSources(dynamicAdjacency, members)}, ...
            'staticIncomingSourcesByReceiver', { ...
                incomingSources(staticAdjacency, members)}, ...
            'eospaGainPercent', lowerGain( ...
                finiteMean(staticEospa(times)), ...
                finiteMean(dynamicEospa(times))), ...
            'rmseGainPercent', lowerGain( ...
                finiteMean(staticRmse(times)), ...
                finiteMean(dynamicRmse(times))), ...
            'bothWorsePageFraction', mean( ...
                dynamicEospa(times) > staticEospa(times) & ...
                dynamicRmse(times) > staticRmse(times)), ...
            'meanDynamicStaticEospaDelta', mean( ...
                dynamicEospa(times) - staticEospa(times)), ...
            'meanDynamicStaticRmseDelta', mean( ...
                dynamicRmse(times) - staticRmse(times)));
    end
    bothWorse = dynamicEospa > staticEospa & ...
        dynamicRmse > staticRmse;
    formationAudits(formationPosition) = struct( ...
        'formationId', formationId, 'memberSensorIds', members, ...
        'fullEospaGainPercent', paired.comparison. ...
            formationEospaGainPercent(formationPosition), ...
        'fullRmseGainPercent', paired.comparison. ...
            formationRmseGainPercent(formationPosition), ...
        'negativeEospaPageCount', nnz(dynamicEospa > staticEospa), ...
        'negativeRmsePageCount', nnz(dynamicRmse > staticRmse), ...
        'bothWorsePageCount', nnz(bothWorse), ...
        'bothWorseRuns', contiguousRuns(bothWorse), ...
        'segmentAudits', segmentAudits);
end

[~, worstPosition] = min([formationAudits.fullRmseGainPercent]);
worst = formationAudits(worstPosition);
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v235', 'corrected_dynamic_routing_tail', ...
    sprintf('%s_seed%d', ...
        strrep(paired.presetName, '-', '_'), paired.seed))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
result = struct();
result.contractVersion = ...
    'corrected-dynamic-routing-tail-v235-v1';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.v227GenerationGitCommit = paired.generationGitCommit;
result.v227ResultPath = resultPath;
result.presetName = paired.presetName;
result.seed = paired.seed;
result.sensorGroupIds = groupIds;
result.formationIds = formationIds;
result.routeChangeTimes = changeTimes;
result.segmentStarts = segmentStarts;
result.segmentEnds = segmentEnds;
result.dynamicPages = dynamicPages;
result.dynamicFusionWeightsByTime = dynamicWeights;
result.staticAdjacency = staticAdjacency;
result.staticFusionWeightMatrix = staticWeights;
result.routeDetailsAtChangeTimes = routeDetails([1, changeTimes]);
result.formationAudits = formationAudits;
result.worstFormationId = worst.formationId;
result.worstFormationFullEospaGainPercent = ...
    worst.fullEospaGainPercent;
result.worstFormationFullRmseGainPercent = ...
    worst.fullRmseGainPercent;
result.worstFormationBothWorseRuns = worst.bothWorseRuns;
result.routeFeaturesUsePosterior = false;
result.routeFeaturesUseTruth = false;
result.routeFeaturesUseFutureOutcome = false;
result.offlineTailTargetsUseTruth = true;
result.onlineGuardImplemented = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V235 is an offline localization of the completed V227 M24 pair. ', ...
    'The reconstructed routes use only current geometry and link ', ...
    'probability, but the tail labels use paired tracking outcomes. ', ...
    'It may guide a causal formation-level fallback design; it is not ', ...
    'an online policy, held-out result or tracking guarantee.'];
matPath = fullfile(outputRoot, ...
    'CORRECTED_DYNAMIC_ROUTING_TAIL_V235.mat');
reportPath = fullfile(outputRoot, ...
    'CORRECTED_DYNAMIC_ROUTING_TAIL_V235.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V235 corrected dynamic-routing tail: %s\n', reportPath);
end

function [pages, weights, detailsByTime] = ...
        reconstructDynamicPages(inputs, protocol)
nodeCount = inputs.config.numberOfSensors;
timeCount = inputs.config.simulationLength;
identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
context = struct();
context.localPosteriorBySensor = repmat({struct([])}, 1, nodeCount);
context.model = inputs.model;
context.baseAdjacency = logical(inputs.graphData.staticAdjacency);
context.directedMessageBudget = ...
    protocol.directedInputsPerReceiver * nodeCount;
context.sensorPhysicalUids = identity.sensorPhysicalUids;
context.formationPhysicalUidsBySensor = ...
    identity.formationPhysicalUidsBySensor;
routeOptions = struct('dominantWeight', protocol.dominantWeight, ...
    'residualWeight', protocol.residualWeight);
pages = false(nodeCount, nodeCount, timeCount);
weights = cell(1, timeCount);
detailsByTime = cell(1, timeCount);
for currentTime = 1:timeCount
    context.currentTime = currentTime;
    context.positions = inputs.graphData.positions(:, :, currentTime);
    context.physicalAdjacency = logical( ...
        inputs.graphData.physicalAdjacency(:, :, currentTime));
    context.commConfig = struct('pDropByEdge', ...
        inputs.commConfig.pDropByEdge(:, :, currentTime));
    [pages(:, :, currentTime), details] = ...
        selectIndexEquivariantFormationBackbonePolicy( ...
            context, routeOptions);
    weights{currentTime} = details.fusionWeightMatrix;
    detailsByTime{currentTime} = compactRouteDetails(details);
end
end

function compact = compactRouteDetails(details)
compact = struct( ...
    'objective', details.objective, ...
    'crossReceivers', details.crossReceivers, ...
    'crossSenders', details.crossSenders, ...
    'incomingCrossReceiversByFormation', ...
        {details.incomingCrossReceiversByFormation}, ...
    'incomingCrossSendersByFormation', ...
        {details.incomingCrossSendersByFormation});
end

function pairs = crossPairs(adjacency, groupIds, targetFormation)
receivers = find(groupIds == targetFormation);
pairs = zeros(0, 2);
for receiver = receivers
    sources = find(adjacency(receiver, :));
    sources = sources(groupIds(sources) ~= targetFormation);
    for source = sources
        pairs(end + 1, :) = [source, receiver]; %#ok<AGROW>
    end
end
end

function values = incomingSources(adjacency, receiverIds)
values = cell(1, numel(receiverIds));
for position = 1:numel(receiverIds)
    values{position} = find(adjacency(receiverIds(position), :));
end
end

function changed = formationRowsChanged(pages, members, currentTime)
changed = currentTime > 1 && ~isequal( ...
    pages(members, :, currentTime), ...
    pages(members, :, currentTime - 1));
end

function changed = pageChanged(pages)
changed = false(1, size(pages, 3) - 1);
for timeIndex = 2:size(pages, 3)
    changed(timeIndex - 1) = ~isequal( ...
        pages(:, :, timeIndex), pages(:, :, timeIndex - 1));
end
end

function runs = contiguousRuns(mask)
mask = logical(reshape(mask, 1, []));
starts = find(mask & [true, ~mask(1:end - 1)]);
ends = find(mask & [~mask(2:end), true]);
runs = [starts(:), ends(:), ends(:) - starts(:) + 1];
end

function count = uniquePageCount(pages)
flat = reshape(logical(pages), [], size(pages, 3))';
count = size(unique(flat, 'rows'), 1);
end

function count = pageChangeCount(pages)
count = nnz(pageChanged(pages));
end

function counts = pageCounts(pages)
counts = zeros(1, size(pages, 3));
for timeIndex = 1:size(pages, 3)
    counts(timeIndex) = nnz(pages(:, :, timeIndex));
end
end

function gain = lowerGain(reference, candidate)
if ~isfinite(reference) || ~isfinite(candidate)
    gain = NaN;
    return;
end
if abs(reference) <= eps
    gain = 0;
    if candidate > reference + eps
        gain = -inf;
    end
else
    gain = 100 * (reference - candidate) / abs(reference);
end
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CorrectedDynamicRoutingTailV235:WriteReport', ...
        'Could not write the V235 tail report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V235 corrected dynamic-routing tail localization\n\n');
fprintf(fid, '- Pair: `%s / seed %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Dynamic route changes: `%d` at `%s`\n', ...
    numel(result.routeChangeTimes), integerText(result.routeChangeTimes));
fprintf(fid, '- Worst formation: `F%d`\n', result.worstFormationId);
fprintf(fid, '- Worst formation full E-OSPA gain: `%+.3f%%`\n', ...
    result.worstFormationFullEospaGainPercent);
fprintf(fid, '- Worst formation full RMSE gain: `%+.3f%%`\n\n', ...
    result.worstFormationFullRmseGainPercent);
fprintf(fid, ['| Formation | Full E-OSPA gain | Full RMSE gain | ', ...
    'Negative E pages | Negative R pages | Both-worse pages |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|\n');
for audit = result.formationAudits
    fprintf(fid, '| F%d | `%+.3f%%` | `%+.3f%%` | %d | %d | %d |\n', ...
        audit.formationId, audit.fullEospaGainPercent, ...
        audit.fullRmseGainPercent, audit.negativeEospaPageCount, ...
        audit.negativeRmsePageCount, audit.bothWorsePageCount);
end
worst = result.formationAudits( ...
    [result.formationAudits.formationId] == result.worstFormationId);
fprintf(fid, '\n## Worst-formation route segments\n\n');
fprintf(fid, ['| Segment | Times | Changed for F%d | Differs from static | ', ...
    'Dynamic cross source->receiver | Static cross source->receiver | ', ...
    'E gain | R gain | ', ...
    'Both-worse fraction |\n'], result.worstFormationId);
fprintf(fid, '|--:|:--|:--:|:--:|:--|:--|--:|--:|--:|\n');
for segment = worst.segmentAudits
    fprintf(fid, ['| %d | %d-%d | `%d` | `%d` | `%s` | `%s` | ', ...
        '`%+.3f%%` | `%+.3f%%` | %.1f%% |\n'], ...
        segment.segmentIndex, segment.firstTime, segment.lastTime, ...
        segment.routeChangedAtStart, segment.differsFromStatic, ...
        pairText(segment.dynamicIncomingCrossPairs), ...
        pairText(segment.staticIncomingCrossPairs), ...
        segment.eospaGainPercent, segment.rmseGainPercent, ...
        100 * segment.bothWorsePageFraction);
end
fprintf(fid, '\nBoth-worse runs for F%d: `%s`.\n', ...
    result.worstFormationId, runText(worst.bothWorseRuns));
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = integerText(values)
parts = arrayfun(@(value) sprintf('%d', value), ...
    reshape(values, 1, []), 'UniformOutput', false);
text = strjoin(parts, ',');
end

function text = pairText(pairs)
if isempty(pairs)
    text = '-';
    return;
end
parts = cell(1, size(pairs, 1));
for index = 1:size(pairs, 1)
    parts{index} = sprintf('S%d->S%d', pairs(index, 1), pairs(index, 2));
end
text = strjoin(parts, ', ');
end

function text = runText(runs)
if isempty(runs)
    text = '-';
    return;
end
parts = cell(1, size(runs, 1));
for index = 1:size(runs, 1)
    parts{index} = sprintf('%d-%d (%d)', ...
        runs(index, 1), runs(index, 2), runs(index, 3));
end
text = strjoin(parts, ', ');
end

function audit = emptyFormationAudit()
audit = struct('formationId', 0, 'memberSensorIds', zeros(1, 0), ...
    'fullEospaGainPercent', NaN, 'fullRmseGainPercent', NaN, ...
    'negativeEospaPageCount', 0, 'negativeRmsePageCount', 0, ...
    'bothWorsePageCount', 0, 'bothWorseRuns', zeros(0, 3), ...
    'segmentAudits', repmat(emptySegmentAudit(), 1, 0));
end

function audit = emptySegmentAudit()
audit = struct('segmentIndex', 0, 'firstTime', 0, 'lastTime', 0, ...
    'routeChangedAtStart', false, 'differsFromStatic', false, ...
    'dynamicIncomingCrossPairs', zeros(0, 2), ...
    'staticIncomingCrossPairs', zeros(0, 2), ...
    'dynamicIncomingSourcesByReceiver', {cell(1, 0)}, ...
    'staticIncomingSourcesByReceiver', {cell(1, 0)}, ...
    'eospaGainPercent', NaN, 'rmseGainPercent', NaN, ...
    'bothWorsePageFraction', NaN, ...
    'meanDynamicStaticEospaDelta', NaN, ...
    'meanDynamicStaticRmseDelta', NaN);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
