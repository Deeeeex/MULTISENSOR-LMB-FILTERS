function [reportPath, audit] = ...
    auditFormationStaggeredRecoveryM24V36(options)
% AUDITFORMATIONSTAGGEREDRECOVERYM24V36 Freeze multi-state finding.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = ...
    getFormationStaggeredRecoveryM24ReplicationProtocol();
screenPath = getField(options, 'screenPath', fullfile( ...
    protocol.outputRoot, 'screen', protocol.replicationScreenFile));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_STAGGERED_RECOVERY_M24_V36_', ...
     'AUDIT_20260802.md']));
if exist(screenPath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(screenPath), ...
            protocol.replicationScreenSha256)
    error('V36Audit:MissingScreen', ...
        'The frozen v36 aggregate screen is unavailable.');
end
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V36Audit:MissingScreen', ...
        'The frozen v36 screen structure is unavailable.');
end
screen = loaded.screen;
assertScreenProvenance(screen, protocol);

recomputedGate = ...
    evaluateFormationStaggeredRecoveryM24V36Gate( ...
        screen.stateSummaries, protocol);
assertGateMatches(screen.replicationGate, recomputedGate);
stateCount = numel(screen.stateSummaries);
numericalGateMatrix = false(stateCount, 6);
for stateIdx = 1:stateCount
    summary = screen.stateSummaries(stateIdx);
    numericalGateMatrix(stateIdx, :) = [ ...
        summary.meanGainPercent >= ...
            protocol.meanTrackingGainThresholdPercent - 1e-12, ...
        summary.minimumFormationGainPercent >= ...
            protocol.minimumFormationGainThresholdPercent - 1e-12, ...
        summary.worstSensorGainPercent >= ...
            protocol.worstSensorGainThresholdPercent - 1e-12, ...
        summary.windowConsensusGainPercent >= ...
            protocol.windowConsensusGainThresholdPercent - 1e-12, ...
        summary.terminalConsensusGainPercent >= ...
            protocol.terminalConsensusGainThresholdPercent - 1e-12, ...
        summary.attemptedByteSavingPercent >= ...
            protocol.minimumAttemptedByteSavingPercent - 1e-12];
end
t60OnlyMeanGateMissed = ...
    ~numericalGateMatrix(1, 1) && ...
    all(numericalGateMatrix(1, 2:end)) && ...
    ~screen.stateSummaries(1).strictStrong;

audit = struct();
audit.contractVersion = ...
    'formation-staggered-recovery-m24-v36-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceScreenSha256 = computeFileSha256(screenPath);
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourcePreflightGenerationCommit = ...
    screen.sourcePreflightGenerationCommit;
audit.sourcePreflightSha256 = screen.sourcePreflightSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.anchorTimes = screen.anchorTimes;
audit.stateSummaries = screen.stateSummaries;
audit.numericalGateMatrix = numericalGateMatrix;
audit.strictStrongMask = recomputedGate.strictStrongMask;
audit.strongStateCount = recomputedGate.strongStateCount;
audit.medianMeanGainPercent = ...
    recomputedGate.medianMeanGainPercent;
audit.minimumStateMeanGainPercent = ...
    recomputedGate.minimumStateMeanGainPercent;
audit.positiveTerminalConsensusStateCount = ...
    recomputedGate.positiveTerminalConsensusStateCount;
audit.allStateMeanTrackingPositive = all( ...
    [screen.stateSummaries.meanGainPercent] > 0);
audit.allStateWorstSensorNonnegative = all( ...
    [screen.stateSummaries.worstSensorGainPercent] >= 0);
audit.allStateFormationNonnegative = all( ...
    [screen.stateSummaries.minimumFormationGainPercent] >= 0);
audit.allStateWindowConsensusPositive = all( ...
    [screen.stateSummaries.windowConsensusGainPercent] > 0);
audit.allStateTerminalConsensusPositive = all( ...
    [screen.stateSummaries.terminalConsensusGainPercent] > 0);
audit.allStateAttemptedByteSavingPositive = all( ...
    [screen.stateSummaries.attemptedByteSavingPercent] > 0);
audit.t60OnlyMeanGateMissed = t60OnlyMeanGateMissed;
audit.formalReplicationGatePassed = ...
    screen.formalReplicationGatePassed && recomputedGate.passed;
audit.x36SourceOnlyProtocolAuthorized = ...
    audit.formalReplicationGatePassed;
audit.gnnTrainingAuthorized = false;
audit.x36OutcomeOpeningAuthorized = false;
audit.x48OutcomeOpeningAuthorized = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This audit freezes three paired H=3 outcomes from already-opened ', ...
    'M24 seed-211 states. The three actions and runtime traces were ', ...
    'source-frozen before the outcome screen. The result establishes ', ...
    'temporal development stability for the analytic controller and ', ...
    'authorizes only an X36 source-only protocol. It does not establish ', ...
    'cross-scale generalization and does not authorize X36 outcomes, ', ...
    'GNN training, X48, reserved seeds, or validation claims.'];

assertAuditFinding(audit, protocol);
writeReport(reportPath, audit, protocol);
fprintf('V36 M24 replication audit: %s\n', reportPath);
end

function assertScreenProvenance(screen, protocol)
if ~strcmp(screen.contractVersion, ...
        'formation-staggered-recovery-m24-v36-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            protocol.replicationScreenGenerationCommit) || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.sourcePreflightGenerationCommit, ...
            protocol.replicationPreflightGenerationCommit) || ...
        ~strcmp(screen.sourcePreflightSha256, ...
            protocol.replicationPreflightSha256) || ...
        ~strcmp(screen.presetName, protocol.presetName) || ...
        screen.seed ~= protocol.seed || ...
        ~isequal(screen.anchorTimes, protocol.anchorTimes) || ...
        numel(screen.stateScreens) ~= ...
            numel(protocol.anchorTimes) || ...
        numel(screen.stateSummaries) ~= ...
            numel(protocol.anchorTimes) || ...
        ~screen.formalReplicationGatePassed || ...
        ~screen.x36SourceOnlyProtocolAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V36Audit:ProvenanceMismatch', ...
        'The frozen v36 screen provenance or decision changed.');
end
for stateIdx = 1:numel(protocol.anchorTimes)
    stateScreen = screen.stateScreens{stateIdx};
    summary = screen.stateSummaries(stateIdx);
    candidateIdx = summary.candidateIndex;
    candidate = stateScreen.outcomes(candidateIdx);
    if stateScreen.currentTime ~= protocol.anchorTimes(stateIdx) || ...
            ~strcmp(stateScreen.generationGitCommit, ...
                protocol.replicationScreenGenerationCommit) || ...
            ~strcmp(stateScreen.cacheSha256, ...
                protocol.expectedCacheSha256{stateIdx}) || ...
            ~summary.traceAttested || ...
            candidate.truthUseCount ~= 0 || ...
            candidate.repairCount ~= 0 || ...
            candidate.payloadEmergencyCount ~= 0 || ...
            candidate.infeasibleCount ~= 0 || ...
            ~all(candidate.selectedSensorB3Pass) || ...
            ~all(candidate.selectedFormationB3Pass)
        error('V36Audit:ProvenanceMismatch', ...
            'A frozen v36 state screen changed.');
    end
end
end

function assertGateMatches(stored, recomputed)
fields = { ...
    'strictStrongMask', 'strongStateCount', ...
    'meanGainPercentByState', 'medianMeanGainPercent', ...
    'minimumStateMeanGainPercent', ...
    'terminalConsensusGainPercentByState', ...
    'positiveTerminalConsensusMask', ...
    'positiveTerminalConsensusStateCount', ...
    'strongCountPassed', 'medianMeanGainPassed', ...
    'minimumStateMeanGainPassed', ...
    'positiveTerminalCountPassed', 'passed'};
for fieldIdx = 1:numel(fields)
    name = fields{fieldIdx};
    if ~isfield(stored, name) || ...
            ~isequaln(stored.(name), recomputed.(name))
        error('V36Audit:GateDrift', ...
            'The stored v36 aggregate gate changed.');
    end
end
end

function assertAuditFinding(audit, protocol)
if ~audit.formalReplicationGatePassed || ...
        audit.strongStateCount ~= ...
            protocol.minimumStrongReplicationStateCount || ...
        ~isequal(audit.strictStrongMask, logical([0, 1, 1])) || ...
        audit.medianMeanGainPercent < 7 || ...
        audit.minimumStateMeanGainPercent < 1 || ...
        audit.positiveTerminalConsensusStateCount ~= 3 || ...
        ~audit.allStateMeanTrackingPositive || ...
        ~audit.allStateWorstSensorNonnegative || ...
        ~audit.allStateFormationNonnegative || ...
        ~audit.allStateWindowConsensusPositive || ...
        ~audit.allStateTerminalConsensusPositive || ...
        ~audit.allStateAttemptedByteSavingPositive || ...
        ~audit.t60OnlyMeanGateMissed || ...
        ~audit.x36SourceOnlyProtocolAuthorized || ...
        audit.gnnTrainingAuthorized || ...
        audit.x36OutcomeOpeningAuthorized || ...
        audit.x48OutcomeOpeningAuthorized || ...
        audit.validationClaimAllowed
    error('V36Audit:UnexpectedFinding', ...
        'The frozen v36 multi-state finding changed.');
end
end

function writeReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('V36Audit:WriteFailed', ...
        'Could not open the v36 audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V36 multi-state M24 replication audit\n\n');
fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    '**The preregistered replication gate passes.** Two of three ', ...
    'new states are strict-strong, all three improve mean tracking, ', ...
    'worst-sensor tracking, window consensus, terminal consensus, ', ...
    'and attempted bytes without a formation regression. The weak ', ...
    't=60 state misses only the 2%% mean-gain threshold.\n\n']);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Source screen SHA-256: `%s`\n', ...
    audit.sourceScreenSha256);
fprintf(fid, '- Source preflight commit / SHA-256: `%s / %s`\n', ...
    audit.sourcePreflightGenerationCommit, ...
    audit.sourcePreflightSha256);
fprintf(fid, '- Preset / seed / anchors: `%s / %d / %s`\n\n', ...
    audit.presetName, audit.seed, mat2str(audit.anchorTimes));

fprintf(fid, '## Per-state result\n\n');
fprintf(fid, [ ...
    '| Anchor | Runtime suspension | Mean tracking | Worst sensor ', ...
    '| Formation gains | Window consensus | Terminal consensus ', ...
    '| Byte saving | Mean card. error | Strong |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|:--|--:|--:|--:|:--|:--:|\n');
for summary = audit.stateSummaries
    fprintf(fid, [ ...
        '| %d | `%s` | %+.4f%% | %+.4f%% | `%s` | %+.4f%% ', ...
        '| %+.4f%% | %+.4f%% | %.6f -> %.6f | %d |\n'], ...
        summary.anchorTime, ...
        formatTrace(summary.runtimeSelectedFormationIdsByTime), ...
        summary.meanGainPercent, summary.worstSensorGainPercent, ...
        mat2str(summary.formationGainPercent, 5), ...
        summary.windowConsensusGainPercent, ...
        summary.terminalConsensusGainPercent, ...
        summary.attemptedByteSavingPercent, ...
        summary.referenceMeanCardinalityError, ...
        summary.candidateMeanCardinalityError, ...
        summary.strictStrong);
end

fprintf(fid, '\n## Aggregate result\n\n');
fprintf(fid, '- Strict-strong states: `%d / 3`\n', ...
    audit.strongStateCount);
fprintf(fid, '- Median mean tracking gain: `%+.4f%%`\n', ...
    audit.medianMeanGainPercent);
fprintf(fid, '- Minimum state mean tracking gain: `%+.4f%%`\n', ...
    audit.minimumStateMeanGainPercent);
fprintf(fid, '- Positive terminal-consensus states: `%d / 3`\n', ...
    audit.positiveTerminalConsensusStateCount);
fprintf(fid, '- t=60 misses only the 2%% mean gate: `%d`\n\n', ...
    audit.t60OnlyMeanGateMissed);

fprintf(fid, '## Interpretation\n\n');
fprintf(fid, [ ...
    'Together with the separate t=72 primary result, the analytic ', ...
    'controller now has positive local development evidence at four ', ...
    'temporally separated M24 windows. V36 itself evaluates only the ', ...
    'three newly opened windows and passes its frozen 2-of-3 gate. ', ...
    'This supports testing whether the same source-side mechanism ', ...
    'exists at X36; it is not yet cross-scale evidence.\n\n']);
fprintf(fid, [ ...
    'The terminal step increases bytes at each new state, but earlier ', ...
    'suspension yields a positive H=3 total saving. This confirms that ', ...
    'the useful object is the full temporal route, not a claim that ', ...
    'every individual step saves communication.\n\n']);

fprintf(fid, '## Authorization boundary\n\n');
fprintf(fid, [ ...
    '- X36 source-only protocol: **authorized**.\n', ...
    '- X36 outcome, GNN training, X48, reserved seeds, and ', ...
    'validation: **not authorized**.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = formatTrace(trace)
parts = cell(1, numel(trace));
for idx = 1:numel(trace)
    parts{idx} = mat2str(trace{idx});
end
value = strjoin(parts, ' -> ');
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
