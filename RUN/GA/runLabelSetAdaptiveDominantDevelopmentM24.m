function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantDevelopmentM24(seed, options)
% RUNLABELSETADAPTIVEDOMINANTDEVELOPMENTM24 Paired frozen D-B evaluation.
%
% Both the frozen CCW reference and the frozen D-B method are rerun for
% each development seed.  No saved outcome is used to choose an arm.

if nargin < 1 || isempty(seed)
    seed = 31;
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantDevelopmentEvaluationAuthorized || ...
        ~ismember(seed, protocol.adaptiveDominantDevelopmentSeeds)
    error('Seed is outside the opened adaptive-dominant development split.');
end

rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_balanced_development_v1'));
screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantDevelopmentTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantDevelopmentTimes(1), ...
    'armNames', {{ ...
        protocol.adaptiveDominantDevelopmentReferenceArmName, ...
        protocol.adaptiveDominantDevelopmentArmName}}, ...
    'writeReport', true, ...
    'outputDirectory', fullfile( ...
        rootDirectory, sprintf('seed%d', seed)), ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'cache')), ...
    'generateMissingBehaviorCache', false, ...
    'evidenceSplit', 'development');
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    'm24-hard', seed, screenOptions);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
