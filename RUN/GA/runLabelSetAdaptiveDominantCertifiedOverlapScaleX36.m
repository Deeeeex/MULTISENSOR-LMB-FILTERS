function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantCertifiedOverlapScaleX36(seed, options)
% RUNLABELSETADAPTIVEDOMINANTCERTIFIEDOVERLAPSCALEX36
% Run the frozen M24-selected v4 pair on one registered X36 scale seed.
%
% The candidate, payload margin, reference and aggregate gates are fixed.
% Each X36 scenario-seed pair may produce at most one completed artifact.

if nargin < 1 || isempty(seed)
    error('An explicitly registered X36 scale seed is required.');
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantCertifiedOverlapX36Authorized || ...
        ~protocol.adaptiveDominantCertifiedOverlapX36ZeroShot || ...
        ~protocol.adaptiveDominantCertifiedOverlapX36OneShot || ...
        protocol.adaptiveDominantCertifiedOverlapX36ValidationClaimAllowed || ...
        ~protocol.adaptiveDominantCertifiedOverlapHeldoutM24GatePassed || ...
        ~ismember(seed, protocol. ...
            adaptiveDominantCertifiedOverlapX36Seeds) || ...
        ismember(seed, protocol. ...
            adaptiveDominantCertifiedOverlapPreviouslyOpenedX36Seeds)
    error('Certified-overlap X36 scale seed is not authorized.');
end

rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantCertifiedOverlapSelectedMarginToken), ...
    protocol.adaptiveDominantCertifiedOverlapX36PresetName));
seedDirectory = fullfile(rootDirectory, sprintf('seed%d', seed));
if completedEvidenceExists(seedDirectory)
    error(['One-shot X36 scale evidence already exists for seed %d; ', ...
        'refusing to rerun it.'], seed);
end

screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantCertifiedOverlapX36Times(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantCertifiedOverlapX36Times(1), ...
    'armNames', {{ ...
        protocol.adaptiveDominantFullWindowReferenceArmName, ...
        protocol.adaptiveDominantCertifiedOverlapSelectedArmName}}, ...
    'writeReport', true, ...
    'outputDirectory', seedDirectory, ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile(rootDirectory, 'cache')), ...
    'generateMissingBehaviorCache', true, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'evidenceSplit', 'scale-validation');
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    protocol.adaptiveDominantCertifiedOverlapX36PresetName, ...
    seed, screenOptions);
end

function exists = completedEvidenceExists(seedDirectory)
exists = false;
if exist(seedDirectory, 'dir') ~= 7
    return;
end
exists = ~isempty(dir(fullfile(seedDirectory, '*.mat'))) || ...
    ~isempty(dir(fullfile(seedDirectory, '*.md')));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
