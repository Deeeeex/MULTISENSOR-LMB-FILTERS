function [datasetPath, dataset] = ...
    generateLabelSetPolicyDatasetShard(options)
% GENERATELABELSETPOLICYDATASETSHARD Replay observable per-label states.
%
% The registered truth-free M24 behavior trajectory is replayed to recover
% local LMB posteriors. For the exact 288 residual-splice candidates, this
% generator stores a padded lossless per-label tensor plus the already
% registered aggregate graph features and training-only diagnostic targets.

if nargin < 1 || isempty(options)
    options = struct();
end
frozenProtocol = getLabelSetSimulatorPolicyProtocol();
protocol = getField(options, 'protocol', frozenProtocol);
if ~isequaln(protocol, frozenProtocol)
    error(['Official label-set shard generation requires the ', ...
        'canonical frozen protocol without overrides.']);
end
if ~protocol.labelSetShardGenerationAuthorized
    error('Label-set shard generation is not authorized.');
end
seed = getField(options, 'seed', protocol.preflightSeeds(1));
if ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~ismember(seed, protocol.trainingSeeds)
    error('Label-set shard seed must be one opened M24 training seed.');
end
labelTimes = reshape(getField( ...
    options, 'labelTimes', protocol.snapshotTimes), 1, []);
if isempty(labelTimes) || ~issorted(labelTimes) || ...
        numel(unique(labelTimes)) ~= numel(labelTimes) || ...
        any(~ismember(labelTimes, protocol.snapshotTimes))
    error('Label-set shard times are not a registered subset.');
end

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error(['Official label-set shard generation requires clean ', ...
        'tracked source and no untracked MATLAB source.']);
end

graphProtocol = getCvarResidualGraphPolicyDatasetProtocol();
bundle = loadCvarResidualGraphPolicyShards('training');
sourceBlocks = bundle.graphBlocks( ...
    [bundle.graphBlocks.seed] == seed & ...
    ismember([bundle.graphBlocks.currentTime], labelTimes));
if numel(sourceBlocks) ~= numel(labelTimes)
    error('Registered graph source does not cover the shard states.');
end
[~, sourceOrder] = sort([sourceBlocks.currentTime]);
sourceBlocks = sourceBlocks(sourceOrder);
sourceRecord = bundle.shardRecords(bundle.seeds == seed);
if numel(sourceRecord) ~= 1
    error('Registered graph source record is ambiguous.');
end

datasetBlocks = repmat(emptyBlock(), 1, numel(labelTimes));
blockCursor = 0;
expectedFeatureNames = {};
expectedFeatureContractSha256 = '';
seedIndex = find(protocol.datasetSeeds == seed, 1);
actionCodeSequence = ...
    protocol.actionCodeSequences(seedIndex, :);
rolloutOptions = struct( ...
    'datasetVariant', protocol.datasetVariant, ...
    'continuationStartTime', ...
        protocol.continuationStartTime, ...
    'sourceWeight', protocol.sourceWeight, ...
    'payloadToleranceFraction', ...
        protocol.payloadToleranceFraction, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'featureContextMode', protocol.featureContextMode, ...
    'proposalDistillationProtocol', graphProtocol, ...
    'blockObserverFcn', @captureLabelSetState, ...
    'skipArtifactWrite', true);
[~, behaviorDataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        protocol.presetName, seed, ...
        actionCodeSequence, rolloutOptions);
if blockCursor ~= numel(datasetBlocks)
    error('Label-set shard state collection is incomplete.');
end

outputDirectory = getField(options, ...
    'outputDirectory', protocol.defaultOutputDirectory);
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
timeToken = formatTimeToken(labelTimes);
defaultName = sprintf( ...
    'label_set_policy_m24_seed%d_t%s_v1.mat', ...
    seed, timeToken);
defaultReportName = sprintf( ...
    'LABEL_SET_POLICY_M24_SEED%d_T%s_V1.md', ...
    seed, upper(timeToken));
datasetPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, defaultName));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, defaultReportName));

dataset = struct();
dataset.protocolId = protocol.id;
dataset.contractVersion = protocol.datasetContractVersion;
dataset.generatedAt = datestr(now, 31);
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.presetName = protocol.presetName;
dataset.seed = seed;
dataset.labelTimes = labelTimes;
dataset.featureNames = expectedFeatureNames;
dataset.featureContractSha256 = ...
    expectedFeatureContractSha256;
dataset.maxLabelCount = protocol.maxLabelCount;
dataset.blocks = datasetBlocks;
dataset.sourceGraphProtocolId = bundle.protocolId;
dataset.sourceGraphDatasetSetSha256 = ...
    bundle.datasetSetSha256;
dataset.sourceGraphFeatureContractSha256 = ...
    bundle.featureContractSha256;
dataset.sourceGraphShardRecord = sourceRecord;
dataset.behaviorCacheRecords = ...
    behaviorDataset.behaviorCacheRecords;
dataset.featuresUseTruth = false;
dataset.featuresUseFutureOutcome = false;
dataset.behaviorUsesTruth = false;
dataset.behaviorUsesFutureOutcome = false;
dataset.diagnosticTargetsUseTruth = true;
dataset.diagnosticTargetsUseFutureOutcome = false;
dataset.numericLabelIdentifiersUsedAsFeatures = false;
dataset.labelKeysStoredForAuditOnly = true;
dataset.labelCapacityOverflowed = false;
dataset.losslessWithinCapacity = true;
dataset.trainingOnlyDiagnostic = true;
dataset.policyModelTrained = false;
dataset.closedLoopReturnEvaluated = false;
dataset.developmentLabelsOpened = false;
dataset.heldoutM24Opened = false;
dataset.x36Opened = false;
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
dataset.evidenceBoundary = protocol.evidenceBoundary;
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Label-set policy shard: %s\nReport: %s\n', ...
    datasetPath, reportPath);

    function captureLabelSetState(context, behaviorBlock)
        if ~ismember(behaviorBlock.currentTime, labelTimes)
            return;
        end
        matches = [sourceBlocks.seed] == behaviorBlock.seed & ...
            [sourceBlocks.currentTime] == ...
                behaviorBlock.currentTime;
        if nnz(matches) ~= 1
            error('Registered graph block alignment failed.');
        end
        graphBlock = sourceBlocks(find(matches, 1));
        observableContext = removeTargetTruthFromContext(context);
        featureOptions = struct( ...
            'maxLabelCount', protocol.maxLabelCount, ...
            'velocityScale', protocol.velocityScale, ...
            'highExistenceThreshold', ...
                protocol.highExistenceThreshold);
        [labelFeatures, labelMask, featureNames, metadata] = ...
            computeLabelSetDirectedActionFeatures( ...
                observableContext, ...
                graphBlock.receiverIndices, ...
                graphBlock.senderIndices, ...
                featureOptions);
        if metadata.truthUsed || metadata.groundTruthUsed || ...
                metadata.futureOutcomeUsed || ...
                metadata.numericLabelIdentifiersUsedAsFeatures || ...
                ~metadata.losslessWithinCapacity || ...
                size(labelFeatures, 1) ~= ...
                    protocol.expectedCandidateCount || ...
                size(labelFeatures, 2) ~= ...
                    protocol.maxLabelCount || ...
                size(labelFeatures, 3) ~= ...
                    protocol.expectedLabelFeatureCount || ...
                ~isequal(size(labelMask), ...
                    [protocol.expectedCandidateCount, ...
                     protocol.maxLabelCount]) || ...
                ~isequal(metadata.receiverIndices, ...
                    graphBlock.receiverIndices) || ...
                ~isequal(metadata.senderIndices, ...
                    graphBlock.senderIndices)
            error('Label-set feature contract failed.');
        end
        if isempty(expectedFeatureNames)
            expectedFeatureNames = featureNames;
            expectedFeatureContractSha256 = ...
                metadata.featureContractSha256;
        elseif ~isequal(expectedFeatureNames, featureNames) || ...
                ~strcmp(expectedFeatureContractSha256, ...
                    metadata.featureContractSha256)
            error('Label-set feature contracts differ across states.');
        end

        blockCursor = blockCursor + 1;
        block = emptyBlock();
        block.seed = behaviorBlock.seed;
        block.currentTime = behaviorBlock.currentTime;
        block.receiverIndices = ...
            graphBlock.receiverIndices;
        block.senderIndices = ...
            graphBlock.senderIndices;
        block.groupIds = behaviorBlock.groupIds;
        block.physicalAdjacency = ...
            behaviorBlock.physicalAdjacency;
        block.edgeFeatures = graphBlock.edgeFeatures;
        block.edgeFeatureNames = ...
            graphBlock.edgeFeatureNames;
        block.nodeFeatures = graphBlock.nodeFeatures;
        block.nodeFeatureNames = ...
            graphBlock.nodeFeatureNames;
        block.labelFeatures = labelFeatures;
        block.labelMask = labelMask;
        block.labelCounts = metadata.labelCounts;
        block.labelKeysAuditOnly = ...
            metadata.edgeLabelKeys;
        block.labelFeatureContractSha256 = ...
            metadata.featureContractSha256;
        block.residualWeightGrid = ...
            graphBlock.residualWeightGrid;
        block.residualBaselineSourcesByReceiver = ...
            graphBlock. ...
                residualBaselineSourcesByReceiver;
        block.dominantSourcesByReceiver = ...
            graphBlock.dominantSourcesByReceiver;
        block.nodeRiskDiagnosticTarget = ...
            graphBlock.nodeRiskTarget;
        block.nodeCvarMaskDiagnosticTarget = ...
            graphBlock.nodeCvarMaskTarget;
        block.edgeTaskAdvantageDiagnosticTarget = ...
            graphBlock.edgeTaskAdvantageTarget;
        block.edgeProtectionAdvantageDiagnosticTarget = ...
            graphBlock.edgeProtectionAdvantageTarget;
        block.edgeReferenceSafeDiagnosticTarget = ...
            graphBlock.edgeReferenceSafeTarget;
        block.selectedEdgeWeightStructuralTarget = ...
            graphBlock.selectedEdgeWeightTarget;
        block.teacherAdjacencyDiagnosticOnly = ...
            graphBlock.teacherAdjacency;
        block.featuresUseTruth = false;
        block.featuresUseFutureOutcome = false;
        block.diagnosticTargetsUseTruth = true;
        block.diagnosticTargetsUseFutureOutcome = false;
        block.numericLabelIdentifiersUsedAsFeatures = false;
        block.labelKeysStoredForAuditOnly = true;
        block.deployable = false;
        datasetBlocks(blockCursor) = block;
        fprintf(['  label-set seed %d t=%d: %d candidates, ', ...
            'max %d labels, %d features\n'], ...
            block.seed, block.currentTime, ...
            size(labelFeatures, 1), ...
            max(block.labelCounts), ...
            size(labelFeatures, 3));
    end
end

function observableContext = removeTargetTruthFromContext(context)
observableContext = context;
if isfield(observableContext.model, ...
        'explicitTargetTrajectories')
    observableContext.model = rmfield( ...
        observableContext.model, ...
        'explicitTargetTrajectories');
end
if isfield(observableContext.model, ...
        'dynamicTopologyScenario') && ...
        isfield(observableContext.model. ...
            dynamicTopologyScenario, ...
            'targetTrajectories')
    observableContext.model.dynamicTopologyScenario = ...
        rmfield(observableContext.model. ...
            dynamicTopologyScenario, ...
            'targetTrajectories');
end
end

function token = formatTimeToken(times)
if numel(times) == 1
    token = sprintf('%d', times);
elseif isequal(times, times(1):times(end))
    token = sprintf('%d_t%d', times(1), times(end));
else
    token = sprintf('%d_', times);
    token(end) = [];
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open label-set shard report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
maxCounts = arrayfun(@(block) ...
    max(block.labelCounts), dataset.blocks);
meanCounts = arrayfun(@(block) ...
    mean(block.labelCounts), dataset.blocks);
fprintf(fid, '# M24 label-set policy state shard\n\n');
fprintf(fid, '- Protocol: `%s`\n', dataset.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Seed: `%d`\n', dataset.seed);
fprintf(fid, '- Times: `%s`\n', ...
    mat2str(dataset.labelTimes));
fprintf(fid, '- States: `%d`\n', numel(dataset.blocks));
fprintf(fid, '- Candidate edges per state: `%d`\n', ...
    size(dataset.blocks(1).labelFeatures, 1));
fprintf(fid, '- Label feature columns: `%d`\n', ...
    numel(dataset.featureNames));
fprintf(fid, '- Frozen label capacity: `%d` (no truncation)\n', ...
    dataset.maxLabelCount);
fprintf(fid, '- Maximum observed union size: `%d`\n', ...
    max(maxCounts));
fprintf(fid, '- Mean edge-label union size: `%.3f`\n', ...
    mean(meanCounts));
fprintf(fid, '- Feature contract SHA-256: `%s`\n\n', ...
    dataset.featureContractSha256);
fprintf(fid, '## Boundary\n\n%s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, ['Numeric label identifiers are retained only in the ', ...
    'audit field and are excluded from model inputs. The shard ', ...
    'contains no policy or closed-loop performance result.\n']);
end

function block = emptyBlock()
block = struct( ...
    'seed', 0, ...
    'currentTime', 0, ...
    'receiverIndices', zeros(0, 1), ...
    'senderIndices', zeros(0, 1), ...
    'groupIds', zeros(1, 0), ...
    'physicalAdjacency', false(0), ...
    'edgeFeatures', zeros(0, 0, 0), ...
    'edgeFeatureNames', {{}}, ...
    'nodeFeatures', zeros(0, 0), ...
    'nodeFeatureNames', {{}}, ...
    'labelFeatures', zeros(0, 0, 0), ...
    'labelMask', false(0, 0), ...
    'labelCounts', zeros(0, 1), ...
    'labelKeysAuditOnly', {{}}, ...
    'labelFeatureContractSha256', '', ...
    'residualWeightGrid', zeros(1, 0), ...
    'residualBaselineSourcesByReceiver', zeros(1, 0), ...
    'dominantSourcesByReceiver', zeros(1, 0), ...
    'nodeRiskDiagnosticTarget', zeros(1, 0), ...
    'nodeCvarMaskDiagnosticTarget', false(1, 0), ...
    'edgeTaskAdvantageDiagnosticTarget', zeros(0, 0), ...
    'edgeProtectionAdvantageDiagnosticTarget', zeros(0, 0), ...
    'edgeReferenceSafeDiagnosticTarget', false(0, 0), ...
    'selectedEdgeWeightStructuralTarget', false(0, 0), ...
    'teacherAdjacencyDiagnosticOnly', false(0), ...
    'featuresUseTruth', false, ...
    'featuresUseFutureOutcome', false, ...
    'diagnosticTargetsUseTruth', true, ...
    'diagnosticTargetsUseFutureOutcome', false, ...
    'numericLabelIdentifiersUsedAsFeatures', false, ...
    'labelKeysStoredForAuditOnly', true, ...
    'deployable', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
