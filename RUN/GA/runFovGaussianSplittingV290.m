function [reportPath,result] = runFovGaussianSplittingV290(options)
% Isolated local-update control. Reuse the actual V242 reference and metrics.
s=load(options.baselineTracePath,'trace'); baseline=s.trace;
s=load(options.baselineSummaryPath,'result'); referenceCache=s.result;
T=options.maximumTime; out=options.outputRoot;
assert(ismember(T,[2,40]) && T<=baseline.maximumTime);
assert(referenceCache.maximumTime==T && referenceCache.seed==baseline.seed && ...
    strcmp(referenceCache.presetName,baseline.presetName));
assert(strcmp(baseline.presetName,'x36-formation-fov-temporal-coupled-formation-braid') && baseline.seed==1301);
if exist(out,'dir')~=7, mkdir(out); end
rawPath=fullfile(out,'FOV_GAUSSIAN_SPLITTING_V290_RAW.mat');
splitOptions=struct('enabled',true,'minimumWeight',.01,'gridRadius',3,'gridPointCount',15);
if exist(rawPath,'file')==2
    s=load(rawPath,'run'); run=s.run;
    assert(strcmp(run.contractVersion,'fov-gaussian-splitting-v290-v1') && ...
        run.maximumTime==T && isequal(run.splitOptions,splitOptions) && ...
        strcmp(run.baselineTracePath,options.baselineTracePath));
else
    inputs=generateDynamicTopologyScenarioInputs(baseline.presetName,baseline.seed);
    assert(inputs.config.simulationLength==baseline.originalTimeCount);
    inputs=cropInputs(inputs,T);
    model=removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
    % Measurement generation has finished: this affects the filter only.
    model.fovGaussianSplitting=splitOptions;
    model.gmCanonicalizationGroupingMethod='sorted';
    config=buildCausalMinimumFormationBackboneV242Config(inputs.config);
    config.diagnosticsProgressInterval=5;
    assert(strcmp(config.fusionWeightMode,'metropolis') && ...
        ~config.receiverSafeLabelFusionEnabled && config.mixtureAwareMaxFusedComponents==8);
    context=buildCausalMinimumFormationBackboneV242ExecutionContext(baseline.presetName,baseline.seed,T);
    protocol=getCausalMinimumFormationBackboneV242Protocol();
    [~,commit]=system('git rev-parse HEAD');
    rng(baseline.seed+protocol.filterSeedOffset,'twister');
    fprintf('V290 FoV splitting: %s, seed %d, prefix 1:%d of %d; local posterior cap %d.\n', ...
        baseline.presetName,baseline.seed,T,baseline.originalTimeCount,model.maximumNumberOfGmComponents);
    started=tic;
    [estimates,d]=runEventTriggeredDistributedLmbFilter(model,inputs.measurements, ...
        inputs.sensorTrajectories,inputs.neighborMap,inputs.commConfig,config,context);
    run=struct('contractVersion','fov-gaussian-splitting-v290-v1', ...
        'generationGitCommit',strtrim(commit),'baselineTracePath',options.baselineTracePath, ...
        'baselineSummaryPath',options.baselineSummaryPath, ...
        'baselineGenerationGitCommit',baseline.generationGitCommit, ...
        'presetName',baseline.presetName,'seed',baseline.seed,'maximumTime',T, ...
        'originalTimeCount',baseline.originalTimeCount,'splitOptions',splitOptions, ...
        'exactGroupingMethod',model.gmCanonicalizationGroupingMethod, ...
        'localPosteriorComponentCap',model.maximumNumberOfGmComponents, ...
        'elapsedSeconds',toc(started),'completedAt',datestr(now,31), ...
        'config',inputs.config,'groundTruthRfs',inputs.groundTruthRfs, ...
        'estimates',{estimates},'attempted',d.attempted,'delivered',d.delivered, ...
        'attemptedPayloadBytes',d.attemptedPayloadBytes, ...
        'splitInputComponents',d.localFovSplitInputComponents, ...
        'splitOutputComponents',d.localFovSplitOutputComponents, ...
        'splitOperations',d.localFovSplitOperations,'splitLabels',d.localFovSplitLabels, ...
        'splitMaximumComponents',d.localFovSplitMaximumComponents, ...
        'splitMaximumDepth',d.localFovSplitMaximumDepth, ...
        'splitTerminalBoundaryMass',d.localFovSplitTerminalBoundaryMass, ...
        'splitSeconds',d.localFovSplitSeconds,'developmentEvidenceOnly',true);
    save('-mat7-binary',[rawPath,'.partial'],'run'); movefile([rawPath,'.partial'],rawPath);
    fprintf('V290 raw output saved after %.1f seconds: %s\n',run.elapsedSeconds,rawPath);
end
reference=referenceCache.reference; candidate=summarizeCandidate(run);
common=isfinite(reference.rmseBySensorTime) & isfinite(candidate.rmseBySensorTime);
commonReference=finiteMean(reference.rmseBySensorTime(common));
commonCandidate=finiteMean(candidate.rmseBySensorTime(common));
formationChange=100*(candidate.perFormationEospa./reference.perFormationEospa-1);
result=struct('contractVersion','fov-gaussian-splitting-v290-analysis-v1', ...
    'rawPath',rawPath,'generationGitCommit',run.generationGitCommit, ...
    'maximumTime',T,'presetName',run.presetName,'seed',run.seed, ...
    'reference',reference,'candidate',candidate,'elapsedSeconds',run.elapsedSeconds, ...
    'commonFiniteCellCount',nnz(common),'commonReferenceRmse',commonReference, ...
    'commonCandidateRmse',commonCandidate, ...
    'eospaImprovementPercent',100*(1-candidate.eospa/reference.eospa), ...
    'commonRmseChangePercent',100*(commonCandidate/commonReference-1), ...
    'attemptedByteRatio',candidate.attemptedBytes/reference.attemptedBytes, ...
    'attemptedRouteDifferences',nnz(xor(run.attempted,baseline.attempted(:,:,1:T))), ...
    'deliveredRouteDifferences',nnz(xor(run.delivered,baseline.delivered(:,:,1:T))), ...
    'formationEospaChangePercent',formationChange,'screenEvaluated',T==40, ...
    'splitInputComponents',sum(run.splitInputComponents(:)), ...
    'splitOutputComponents',sum(run.splitOutputComponents(:)), ...
    'splitOperations',sum(run.splitOperations(:)),'splitLabels',sum(run.splitLabels(:)), ...
    'maximumSplitComponents',max(run.splitMaximumComponents(:)), ...
    'maximumSplitDepth',max(run.splitMaximumDepth(:)), ...
    'terminalBoundaryMassSum',sum(run.splitTerminalBoundaryMass(:)), ...
    'splitSeconds',sum(run.splitSeconds(:)), ...
    'localPosteriorComponentCap',run.localPosteriorComponentCap,'developmentEvidenceOnly',true);
result.screenPassed=result.screenEvaluated && result.eospaImprovementPercent>=1 && ...
    candidate.countError<reference.countError && ...
    candidate.representativeDisagreement<=reference.representativeDisagreement && ...
    isfinite(result.commonRmseChangePercent) && result.commonRmseChangePercent<=1 && ...
    max(formationChange)<=1 && result.attemptedByteRatio<=1.05 && ...
    result.attemptedRouteDifferences==0 && result.deliveredRouteDifferences==0;
save('-mat7-binary',fullfile(out,'FOV_GAUSSIAN_SPLITTING_V290.mat'),'result');
reportPath=fullfile(out,'FOV_GAUSSIAN_SPLITTING_V290_REPORT.md');
writeOutputs(out,reportPath,result,run.config);
fprintf('V290 prefix %d: E-OSPA %.6f -> %.6f (%+.3f%% gain), RMSE %.6f -> %.6f, bytes ratio %.4f, screen evaluated %d / passed %d.\n', ...
    T,reference.eospa,candidate.eospa,result.eospaImprovementPercent, ...
    reference.conditionalRmse,candidate.conditionalRmse,result.attemptedByteRatio, ...
    result.screenEvaluated,result.screenPassed);
end

function s=summarizeCandidate(run)
N=numel(run.estimates); T=run.maximumTime; truth=run.groundTruthRfs; cfg=run.config;
E=zeros(N,T); C=E; R=nan(N,T); groups=unique(cfg.sensorGroupIds,'stable'); reps=zeros(size(groups));
for f=1:numel(groups), reps(f)=find(cfg.sensorGroupIds==groups(f),1); end
for i=1:N
    R(i,:)=computeSetRmseOverTime(run.estimates{i},truth);
    for t=1:T
        metric=computePositionEuclideanOspa(truth.x{t},run.estimates{i}.mu{t},cfg.ospaPositionCutoff,2,[1,2]);
        E(i,t)=metric(1); C(i,t)=abs(numel(run.estimates{i}.mu{t})-numel(truth.x{t}));
    end
end
disagreement=zeros(1,T);
for t=1:T
    values=[];
    for a=1:numel(reps)-1
        for b=a+1:numel(reps)
            metric=computePositionEuclideanOspa(run.estimates{reps(a)}.mu{t}, ...
                run.estimates{reps(b)}.mu{t},cfg.ospaPositionCutoff,2,[1,2]);
            values(end+1)=metric(1);
        end
    end
    disagreement(t)=mean(values);
end
nodeR=zeros(N,1); for i=1:N,nodeR(i)=finiteMean(R(i,:));end
formationE=zeros(size(groups));
for f=1:numel(groups), values=E(cfg.sensorGroupIds==groups(f),:);formationE(f)=mean(values(:));end
bytes=run.attemptedPayloadBytes;
s=struct('eospa',mean(E(:)),'conditionalRmse',finiteMean(R(:)),'countError',mean(C(:)), ...
    'representativeDisagreement',mean(disagreement),'finiteRmseFraction',nnz(isfinite(R))/numel(R), ...
    'attemptedBytes',sum(bytes(:)),'deliveredBytes',sum(bytes(logical(run.delivered))), ...
    'attemptedMessages',nnz(run.attempted),'deliveredMessages',nnz(run.delivered), ...
    'eospaBySensorTime',E,'rmseBySensorTime',R,'countErrorBySensorTime',C, ...
    'disagreementByTime',disagreement,'perSensorEospa',mean(E,2),'perSensorRmse',nodeR, ...
    'perFormationEospa',formationE,'worstSensorEospa',max(mean(E,2)),'representatives',reps);
end

function writeOutputs(out,path,r,config)
fields={'eospa','conditionalRmse','countError','representativeDisagreement', ...
    'worstSensorEospa','attemptedBytes','deliveredBytes','attemptedMessages','deliveredMessages','finiteRmseFraction'};
fid=fopen(path,'w'); assert(fid>=0); cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'# V290: FoV-aware local update, paired prefix\n\n');
fprintf(fid,'X36, seed 1301, steps 1--%d of the original 160-step scene; source `%s`. Self-check only, development evidence.\n\n',r.maximumTime,r.generationGitCommit);
fprintf(fid,'Only local pre-update density resolution changes; KLA, common labels and V242 routing stay fixed. Reference metrics reuse the saved V242 arm, not the MIL candidate.\n\n');
fprintf(fid,'| Metric | V242 reference | FoV splitting |\n| --- | ---: | ---: |\n');
for k=1:numel(fields),fprintf(fid,'| %s | %.9f | %.9f |\n',fields{k},r.reference.(fields{k}),r.candidate.(fields{k}));end
fprintf(fid,'\nCommon-finite RMSE: %.6f -> %.6f, %d cells. Matched target identities can differ.\n',r.commonReferenceRmse,r.commonCandidateRmse,r.commonFiniteCellCount);
fprintf(fid,'Route-mask differences attempted/delivered: %d/%d. Filter runtime %.1f s; splitter %.1f s.\n',r.attemptedRouteDifferences,r.deliveredRouteDifferences,r.elapsedSeconds,r.splitSeconds);
fprintf(fid,'\nSplitting: %d input -> %d output components across %d affected label stages; %d split operations, maximum %d components/label, depth %d. Original local posterior cap %d is unchanged.\n', ...
    r.splitInputComponents,r.splitOutputComponents,r.splitLabels,r.splitOperations,r.maximumSplitComponents,r.maximumSplitDepth,r.localPosteriorComponentCap);
fprintf(fid,'Terminal low-weight boundary-leaf conditional mass sum %.6f across all label stages; this is not an error bound or discarded mass.\n',r.terminalBoundaryMassSum);
fprintf(fid,'\n| Formation | Reference E-OSPA | Candidate E-OSPA | Reference RMSE | Candidate RMSE |\n| --- | ---: | ---: | ---: | ---: |\n');
groups=unique(config.sensorGroupIds,'stable');
for g=1:numel(groups)
    selected=config.sensorGroupIds==groups(g);
    fprintf(fid,'| %d | %.6f | %.6f | %.6f | %.6f |\n',groups(g),r.reference.perFormationEospa(g), ...
        r.candidate.perFormationEospa(g),finiteMean(r.reference.rmseBySensorTime(selected,:)),finiteMean(r.candidate.rmseBySensorTime(selected,:)));
end
fprintf(fid,'\nScreen evaluated %d; passed %d. Two steps are integration only. No full-episode, held-out or same-fusion static-versus-dynamic conclusion.\n',r.screenEvaluated,r.screenPassed);
clear cleanup;
fid=fopen(fullfile(out,'V290_JOINT_METRICS.csv'),'w');cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'metric,reference,candidate\n');
for k=1:numel(fields),fprintf(fid,'%s,%.12g,%.12g\n',fields{k},r.reference.(fields{k}),r.candidate.(fields{k}));end
clear cleanup;
fid=fopen(fullfile(out,'V290_SENSOR_METRICS.csv'),'w');cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'sensor,formation,reference_eospa,candidate_eospa,reference_rmse,candidate_rmse\n');
for n=1:numel(config.sensorGroupIds)
    fprintf(fid,'%d,%d,%.12g,%.12g,%.12g,%.12g\n',n,config.sensorGroupIds(n), ...
        r.reference.perSensorEospa(n),r.candidate.perSensorEospa(n),r.reference.perSensorRmse(n),r.candidate.perSensorRmse(n));
end
clear cleanup;
fid=fopen(fullfile(out,'V290_TIME_SERIES.csv'),'w');cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'time,reference_eospa,candidate_eospa,reference_rmse,candidate_rmse,reference_count_error,candidate_count_error,reference_disagreement,candidate_disagreement\n');
for t=1:r.maximumTime
    fprintf(fid,'%d,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g\n',t, ...
        mean(r.reference.eospaBySensorTime(:,t)),mean(r.candidate.eospaBySensorTime(:,t)), ...
        finiteMean(r.reference.rmseBySensorTime(:,t)),finiteMean(r.candidate.rmseBySensorTime(:,t)), ...
        mean(r.reference.countErrorBySensorTime(:,t)),mean(r.candidate.countErrorBySensorTime(:,t)), ...
        r.reference.disagreementByTime(t),r.candidate.disagreementByTime(t));
end
end

function inputs=cropInputs(inputs,T)
inputs.measurements=inputs.measurements(:,1:T); inputs.config.simulationLength=T;
inputs.model.simulationLength=T; inputs.model.dynamicTopologyScenario.config.simulationLength=T;
for n=1:numel(inputs.sensorTrajectories),inputs.sensorTrajectories{n}=inputs.sensorTrajectories{n}(:,1:T);end
for name={'x','mu','Sigma'},inputs.groundTruthRfs.(name{1})=inputs.groundTruthRfs.(name{1})(1:T);end
inputs.groundTruthRfs.cardinality=inputs.groundTruthRfs.cardinality(1:T);
if ndims(inputs.commConfig.pDropByEdge)>=3,inputs.commConfig.pDropByEdge=inputs.commConfig.pDropByEdge(:,:,1:T);end
if isfield(inputs.commConfig,'linkUniforms') && ndims(inputs.commConfig.linkUniforms)>=3
    inputs.commConfig.linkUniforms=inputs.commConfig.linkUniforms(:,:,1:T);
end
inputs.graphData.physicalAdjacency=inputs.graphData.physicalAdjacency(:,:,1:T);
inputs.graphData.positions=inputs.graphData.positions(:,:,1:T);
end

function v=finiteMean(x)
x=x(isfinite(x)); if isempty(x),v=NaN;else,v=mean(x(:));end
end
