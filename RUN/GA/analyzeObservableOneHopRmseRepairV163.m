function [reportPath, summary] = ...
        analyzeObservableOneHopRmseRepairV163(options)
% ANALYZEOBSERVABLEONEHOPRMSEREPAIRV163 F3/F5 label-repair mechanism gate.
%
% The schedule is selected after opening the V162 formation-RMSE failure.
% It is therefore a privileged mechanism screen, not an online trigger.

if nargin < 1 || isempty(options)
    options = struct();
end
v157 = getPositiveValueReferenceLabelV157Protocol();
v162 = getObservableOneHopRiskLabelV162Protocol();
snapshotScreenPath = getField(options, 'snapshotScreenPath', fullfile( ...
    v157.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
recursiveScreenPath = getField(options, 'recursiveScreenPath', fullfile( ...
    v162.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    v162.headroomOutputRoot, 'rmse_repair_preflight'));
if exist(snapshotScreenPath, 'file') ~= 2 || ...
        exist(recursiveScreenPath, 'file') ~= 2
    error('ObservableRmseRepairV163:MissingInput', ...
        'The V157 snapshot and V162 recursive screens are required.');
end

snapshotLoaded = load(snapshotScreenPath, 'screen');
recursiveLoaded = load(recursiveScreenPath, 'screen');
snapshotScreen = snapshotLoaded.screen;
recursiveScreen = recursiveLoaded.screen;
snapshotOutcome = outcomeByAction(snapshotScreen, ...
    v157.candidateActionName);
recursiveReference = outcomeByAction(recursiveScreen, ...
    'reference-full-payload');
recursiveCandidate = outcomeByAction(recursiveScreen, ...
    v162.candidateActionName);
if ~snapshotScreen.captureFusedPosteriorSnapshotsEnabled || ...
        isempty(snapshotOutcome.fusedPosteriorSnapshotsByTime) || ...
        isempty(snapshotOutcome.localPosteriorSnapshotsByTime)
    error('ObservableRmseRepairV163:MissingSnapshots', ...
        'The V157 screen lacks pre-action fused or local snapshots.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    snapshotScreen.presetName, snapshotScreen.seed);
model = inputs.model;
model.dynamicTopologyScenario.targetTrajectories = ...
    inputs.targetTrajectories;
groupIds = reshape(snapshotScreen.sensorGroupIds, 1, []);
nodeCount = numel(groupIds);
repairPages = [5, 7, 8];
repairFormationsByPage = {[3], [3, 5], [3, 5]};
rows = repmat(emptyRow(), 1, 0);
jointOracleRows = repmat(emptyOracleRow(), 1, 0);

for scheduleIdx = 1:numel(repairPages)
    pageIdx = repairPages(scheduleIdx);
    currentTime = snapshotScreen.returnTimes(pageIdx);
    receiverIds = find(ismember( ...
        groupIds, repairFormationsByPage{scheduleIdx}));
    physical = logical(inputs.graphData. ...
        physicalAdjacency(:, :, currentTime));
    physical = physical | physical';
    physical(1:nodeCount+1:end) = false;
    for receiverIdx = reshape(receiverIds, 1, [])
        config = selectorConfig(v162, currentTime, receiverIdx);
        baseline = snapshotOutcome. ...
            fusedPosteriorSnapshotsByTime{pageIdx}{receiverIdx};
        locals = snapshotOutcome. ...
            localPosteriorSnapshotsByTime{pageIdx};
        [trial, details] = selectObservableOneHopRiskLabels( ...
            baseline, locals, physical, physical, config, ...
            receiverIdx, currentTime, model);
        row = emptyRow();
        row.page = pageIdx;
        row.time = currentTime;
        row.formation = groupIds(receiverIdx);
        row.receiver = receiverIdx;
        row.selectedLabelCount = details.selectedLabelCount;
        row.appliedLabelCount = details.appliedLabelCount;
        row.attemptedBytes = details.attemptedTotalBytes;
        row.baselineEospa = evaluateLmbTopologyCurrentEospa( ...
            baseline, model, currentTime, struct());
        row.trialEospa = evaluateLmbTopologyCurrentEospa( ...
            trial, model, currentTime, struct());
        row.eospaGain = row.baselineEospa - row.trialEospa;
        row.snapshotBaselineRmse = currentPosteriorRmse( ...
            baseline, model, currentTime);
        row.trialRmse = currentPosteriorRmse( ...
            trial, model, currentTime);
        row.rmseGain = row.snapshotBaselineRmse - row.trialRmse;
        row.recursiveBaseRmse = ...
            recursiveCandidate.rmseBySensorTime(receiverIdx, pageIdx);
        row.snapshotMismatch = ...
            row.snapshotBaselineRmse - row.recursiveBaseRmse;
        rows(end + 1) = row; %#ok<AGROW>
        if row.formation == 5
            oracle = runJointTruthOracle( ...
                baseline, locals, physical, receiverIdx, ...
                currentTime, model, v162, details.attemptedSynopsisBytes);
            jointOracleRows(end + 1) = oracle; %#ok<AGROW>
            fprintf(['V163 F5 truth-oracle t=%d sensor=%d: ', ...
                'actions=%d, E-OSPA gain=%+.6f, RMSE gain=%+.6f\n'], ...
                currentTime, receiverIdx, oracle.actionCount, ...
                oracle.eospaGain, oracle.rmseGain);
        end
    end
end

projectedFormationRmse = recursiveCandidate.formationMeanRmse;
groups = unique(groupIds, 'stable');
for groupIdx = 1:numel(groups)
    groupGain = sum([rows([rows.formation] == groups(groupIdx)).rmseGain]);
    memberCount = nnz(groupIds == groups(groupIdx));
    projectedFormationRmse(groupIdx) = ...
        projectedFormationRmse(groupIdx) - ...
        groupGain / (memberCount * numel(snapshotScreen.returnTimes));
end
projectedFormationGainPercent = 100 * ( ...
    recursiveReference.formationMeanRmse - projectedFormationRmse) ./ ...
    max(abs(recursiveReference.formationMeanRmse), eps);
additionalAttemptedBytes = sum([rows.attemptedBytes]);
projectedByteSavingPercent = 100 * ( ...
    recursiveReference.attemptedBytes - ...
    (recursiveCandidate.attemptedBytes + additionalAttemptedBytes)) / ...
    max(abs(recursiveReference.attemptedBytes), eps);
targetGroupMask = ismember(groups, [3, 5]);
jointProjectedFormationRmse = recursiveCandidate.formationMeanRmse;
f3Gain = sum([rows([rows.formation] == 3).rmseGain]);
f5OracleGain = sum([jointOracleRows.rmseGain]);
jointProjectedFormationRmse(groups == 3) = ...
    jointProjectedFormationRmse(groups == 3) - ...
    f3Gain / (nnz(groupIds == 3) * numel(snapshotScreen.returnTimes));
jointProjectedFormationRmse(groups == 5) = ...
    jointProjectedFormationRmse(groups == 5) - ...
    f5OracleGain / (nnz(groupIds == 5) * numel(snapshotScreen.returnTimes));
jointProjectedFormationGainPercent = 100 * ( ...
    recursiveReference.formationMeanRmse - ...
    jointProjectedFormationRmse) ./ ...
    max(abs(recursiveReference.formationMeanRmse), eps);
jointAdditionalAttemptedBytes = ...
    sum([rows([rows.formation] == 3).attemptedBytes]) + ...
    sum([jointOracleRows.attemptedBytes]);
jointProjectedByteSavingPercent = 100 * ( ...
    recursiveReference.attemptedBytes - ...
    (recursiveCandidate.attemptedBytes + ...
     jointAdditionalAttemptedBytes)) / ...
    max(abs(recursiveReference.attemptedBytes), eps);

summary = struct();
summary.contractVersion = ...
    'observable-one-hop-rmse-repair-v163-preflight-v1';
summary.presetName = snapshotScreen.presetName;
summary.seed = snapshotScreen.seed;
summary.repairPages = repairPages;
summary.repairTimes = snapshotScreen.returnTimes(repairPages);
summary.repairFormationsByPage = repairFormationsByPage;
summary.cellCount = numel(rows);
summary.rows = rows;
summary.totalEospaGain = sum([rows.eospaGain]);
summary.totalRmseGain = sum([rows.rmseGain]);
summary.harmfulEospaCellCount = nnz([rows.eospaGain] < -1e-9);
summary.harmfulRmseCellCount = nnz([rows.rmseGain] < -1e-9);
summary.minimumEospaGain = min([rows.eospaGain]);
summary.minimumRmseGain = min([rows.rmseGain]);
summary.meanAbsoluteSnapshotMismatch = mean(abs([rows.snapshotMismatch]));
summary.maximumAbsoluteSnapshotMismatch = max(abs([rows.snapshotMismatch]));
summary.additionalAttemptedBytes = additionalAttemptedBytes;
summary.projectedByteSavingPercent = projectedByteSavingPercent;
summary.referenceFormationMeanRmse = ...
    recursiveReference.formationMeanRmse;
summary.baseFormationMeanRmse = ...
    recursiveCandidate.formationMeanRmse;
summary.projectedFormationMeanRmse = projectedFormationRmse;
summary.projectedFormationRmseGainPercent = ...
    projectedFormationGainPercent;
summary.mechanismGatePassed = ...
    summary.totalEospaGain > 0 && ...
    summary.totalRmseGain > 0 && ...
    summary.harmfulEospaCellCount == 0 && ...
    summary.harmfulRmseCellCount == 0 && ...
    all(projectedFormationGainPercent(targetGroupMask) >= -1e-12) && ...
    projectedByteSavingPercent >= -1e-12;
summary.jointTruthOracleRows = jointOracleRows;
summary.jointTruthOracleEospaGain = sum([jointOracleRows.eospaGain]);
summary.jointTruthOracleRmseGain = sum([jointOracleRows.rmseGain]);
summary.jointTruthOracleActionCount = ...
    sum([jointOracleRows.actionCount]);
summary.jointTruthOracleAdditionalAttemptedBytes = ...
    jointAdditionalAttemptedBytes;
summary.jointTruthOracleProjectedByteSavingPercent = ...
    jointProjectedByteSavingPercent;
summary.jointTruthOracleProjectedFormationMeanRmse = ...
    jointProjectedFormationRmse;
summary.jointTruthOracleProjectedFormationRmseGainPercent = ...
    jointProjectedFormationGainPercent;
summary.jointTruthOracleMechanismGatePassed = ...
    all([jointOracleRows.eospaGain] >= -1e-9) && ...
    all([jointOracleRows.rmseGain] >= -1e-9) && ...
    all(jointProjectedFormationGainPercent(targetGroupMask) >= -1e-12) && ...
    jointProjectedByteSavingPercent >= -1e-12;
summary.truthUsedForEvaluation = true;
summary.truthUsedBySelector = false;
summary.futureInformationUsedBySelector = false;
summary.recursiveResultClaimAllowed = false;
summary.evidenceBoundary = [ ...
    'V163 is an opened, nonrecursive repair-mechanism screen. The F3/F5 ', ...
    'receiver-time schedule is selected after observing the V162 ', ...
    'formation-RMSE failure and is privileged. The minimum-risk source ', ...
    'and positive-risk Top-4 label rules remain truth-free. Edits use ', ...
    'pre-action V157 fused snapshots and all-delivered physical links; ', ...
    'truth scores immediate E-OSPA and matched-position RMSE only. The ', ...
    'projected recursive formation means add these snapshot deltas to ', ...
    'the V162 outcome, so snapshot mismatch is reported explicitly. ', ...
    'A separate F5 joint-positive truth oracle asks whether any one-hop ', ...
    'source-label replacement can improve both metrics; it is a mechanism ', ...
    'upper bound and does not define the deployable selector. ', ...
    'A positive preflight only authorizes a recursive mechanism probe; ', ...
    'it is not an online trigger, tracking result or validation claim.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'OBSERVABLE_ONE_HOP_RMSE_REPAIR_V163_PREFLIGHT.mat');
reportPath = fullfile(outputRoot, ...
    'OBSERVABLE_ONE_HOP_RMSE_REPAIR_V163_PREFLIGHT.md');
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary);
fprintf('V163 RMSE-repair preflight: %s\n', reportPath);
end

function oracle = runJointTruthOracle( ...
        baseline, localPosteriors, physical, receiverIdx, currentTime, ...
        model, protocol, synopsisBytes)
neighborIds = reshape(find(physical(receiverIdx, :)), 1, []);
candidates = collectSourceLabelCandidates( ...
    localPosteriors, neighborIds, protocol.activeExistenceThreshold, model);
working = baseline;
selectedLabels = zeros(2, 0);
selected = repmat(emptySourceLabelCandidate(), 1, 0);
totalEospaGain = 0;
totalRmseGain = 0;
for rankIdx = 1:protocol.maximumLabelEdits
    currentEospa = evaluateLmbTopologyCurrentEospa( ...
        working, model, currentTime, struct());
    currentRmse = currentPosteriorRmse(working, model, currentTime);
    bestIdx = 0;
    bestRmseGain = -inf;
    bestEospaGain = -inf;
    rmseGains = -inf(1, numel(candidates));
    for candidateIdx = 1:numel(candidates)
        candidate = candidates(candidateIdx);
        if ~isempty(selectedLabels) && ...
                any(all(bsxfun(@eq, selectedLabels, candidate.label), 1))
            continue;
        end
        trial = replaceLabelObject(working, candidate.object);
        rmseGain = currentRmse - currentPosteriorRmse( ...
            trial, model, currentTime);
        rmseGains(candidateIdx) = rmseGain;
    end
    [~, candidateOrder] = sort(rmseGains, 'descend');
    for orderIdx = 1:numel(candidateOrder)
        candidateIdx = candidateOrder(orderIdx);
        rmseGain = rmseGains(candidateIdx);
        if ~(rmseGain > 1e-9) || ...
                (bestIdx ~= 0 && rmseGain < bestRmseGain - 1e-12)
            break;
        end
        candidate = candidates(candidateIdx);
        trial = replaceLabelObject(working, candidate.object);
        eospaGain = currentEospa - evaluateLmbTopologyCurrentEospa( ...
            trial, model, currentTime, struct());
        if eospaGain >= -1e-9 && ...
                (rmseGain > bestRmseGain + 1e-12 || ...
                 (abs(rmseGain - bestRmseGain) <= 1e-12 && ...
                  eospaGain > bestEospaGain + 1e-12))
            bestIdx = candidateIdx;
            bestRmseGain = rmseGain;
            bestEospaGain = eospaGain;
        end
    end
    if bestIdx == 0
        break;
    end
    best = candidates(bestIdx);
    working = replaceLabelObject(working, best.object);
    selected(end + 1) = best; %#ok<AGROW>
    selectedLabels(:, end + 1) = best.label; %#ok<AGROW>
    totalEospaGain = totalEospaGain + bestEospaGain;
    totalRmseGain = totalRmseGain + bestRmseGain;
end
oracle = emptyOracleRow();
oracle.time = currentTime;
oracle.receiver = receiverIdx;
oracle.actionCount = numel(selected);
oracle.eospaGain = totalEospaGain;
oracle.rmseGain = totalRmseGain;
oracle.attemptedBytes = synopsisBytes + ...
    selectedTransportBytes(selected, protocol, model);
end

function candidates = collectSourceLabelCandidates( ...
        localPosteriors, neighborIds, threshold, model)
candidates = repmat(emptySourceLabelCandidate(), 1, 0);
for sourceIdx = neighborIds
    objects = reshape(localPosteriors{sourceIdx}, 1, []);
    for objectIdx = 1:numel(objects)
        object = objects(objectIdx);
        if object.r <= threshold || object.numberOfGmComponents <= 0
            continue;
        end
        candidate = emptySourceLabelCandidate();
        candidate.source = sourceIdx;
        candidate.label = [object.birthTime; object.birthLocation];
        candidate.object = object;
        stats = estimateLmbPayloadSize(object, model, 2, struct());
        candidate.responseBytes = stats.estimatedBytes;
        candidates(end + 1) = candidate; %#ok<AGROW>
    end
end
end

function bytes = selectedTransportBytes(selected, protocol, model)
bytes = 0;
if isempty(selected)
    return;
end
sources = unique([selected.source], 'stable');
for sourceIdx = sources
    sourceItems = selected([selected.source] == sourceIdx);
    bytes = bytes + protocol.requestHeaderBytes + ...
        protocol.requestBytesPerLabel * numel(sourceItems);
    objects = reshape([sourceItems.object], 1, []);
    stats = estimateLmbPayloadSize(objects, model, 2, struct());
    bytes = bytes + stats.estimatedBytes;
end
end

function posterior = replaceLabelObject(posterior, object)
posterior = reshape(posterior, 1, []);
idx = 0;
for objectIdx = 1:numel(posterior)
    if posterior(objectIdx).birthTime == object.birthTime && ...
            posterior(objectIdx).birthLocation == object.birthLocation
        idx = objectIdx;
        break;
    end
end
if idx == 0
    posterior(end + 1) = object;
else
    posterior(idx) = object;
end
end

function config = selectorConfig(protocol, currentTime, receiverIdx)
config = struct( ...
    'observableOneHopRiskLabelEnabled', true, ...
    'observableOneHopRiskLabelTimes', currentTime, ...
    'observableOneHopRiskLabelSensorIdsByTime', {{receiverIdx}}, ...
    'observableOneHopRiskLabelMaximumEdits', protocol.maximumLabelEdits, ...
    'observableOneHopRiskLabelExistenceThreshold', ...
        protocol.activeExistenceThreshold, ...
    'observableOneHopRiskLabelMinimumRiskReduction', ...
        protocol.minimumRiskReduction, ...
    'observableOneHopRiskLabelSynopsisHeaderBytes', ...
        protocol.synopsisHeaderBytes, ...
    'observableOneHopRiskLabelSynopsisBytesPerLabel', ...
        protocol.synopsisBytesPerLabel, ...
    'observableOneHopRiskLabelRequestHeaderBytes', ...
        protocol.requestHeaderBytes, ...
    'observableOneHopRiskLabelRequestBytesPerLabel', ...
        protocol.requestBytesPerLabel);
end

function value = currentPosteriorRmse(posterior, model, currentTime)
objects = reshape(posterior, 1, []);
if ~isempty(objects)
    objects = objects([objects.r] > model.existenceThreshold);
end
estimate = zeros(2, 0);
if ~isempty(objects)
    [mapCardinality, mapIndices] = ...
        lmbMapCardinalityEstimate([objects.r]);
    estimate = zeros(2, mapCardinality);
    for mapIdx = 1:mapCardinality
        object = objects(mapIndices(mapIdx));
        weights = reshape(object.w, 1, []);
        weights(~isfinite(weights)) = -inf;
        [~, componentIdx] = max(weights);
        if isempty(componentIdx) || ~isfinite(weights(componentIdx))
            componentIdx = 1;
        end
        estimate(:, mapIdx) = object.mu{componentIdx}(1:2);
    end
end
truth = zeros(2, 0);
trajectories = model.dynamicTopologyScenario.targetTrajectories;
for targetIdx = 1:numel(trajectories)
    if currentTime <= size(trajectories{targetIdx}, 2)
        state = trajectories{targetIdx}(:, currentTime);
        if all(isfinite(state))
            truth(:, end + 1) = state(1:2); %#ok<AGROW>
        end
    end
end
if isempty(truth) || isempty(estimate)
    value = NaN;
    return;
end
distances = zeros(size(truth, 2), size(estimate, 2));
for truthIdx = 1:size(truth, 2)
    delta = bsxfun(@minus, estimate, truth(:, truthIdx));
    distances(truthIdx, :) = sqrt(sum(delta .^ 2, 1));
end
[matching, ~] = Hungarian(distances);
matched = distances(matching == 1);
if isempty(matched)
    value = NaN;
else
    value = sqrt(mean(matched .^ 2));
end
end

function outcome = outcomeByAction(screen, actionName)
idx = find(strcmp({screen.records.actionName}, actionName), 1);
if isempty(idx)
    error('ObservableRmseRepairV163:MissingAction', ...
        'The requested action is missing: %s', actionName);
end
outcome = screen.outcomes(idx);
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('ObservableRmseRepairV163:ReportOpenFailed', ...
        'Could not open the V163 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V163 observable F3/F5 RMSE-repair preflight\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    summary.presetName, summary.seed);
fprintf(fid, '- Privileged repair pages / times: `%s / %s`\n', ...
    mat2str(summary.repairPages), mat2str(summary.repairTimes));
fprintf(fid, '- Repair formations: `%s`\n', ...
    formatCellSchedule(summary.repairFormationsByPage));
fprintf(fid, '- Receiver-time cells: `%d`\n\n', summary.cellCount);
fprintf(fid, '| t | F | Sensor | Labels | E-OSPA gain | RMSE gain | Bytes | Snapshot mismatch |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for row = summary.rows
    fprintf(fid, '| %d | %d | %d | %d | %+.6f | %+.6f | %d | %+.6f |\n', ...
        row.time, row.formation, row.receiver, row.appliedLabelCount, ...
        row.eospaGain, row.rmseGain, row.attemptedBytes, ...
        row.snapshotMismatch);
end
fprintf(fid, '\n- Total immediate E-OSPA / RMSE gain: `%.6f / %.6f`\n', ...
    summary.totalEospaGain, summary.totalRmseGain);
fprintf(fid, '- Harmful E-OSPA / RMSE cells: `%d / %d`\n', ...
    summary.harmfulEospaCellCount, summary.harmfulRmseCellCount);
fprintf(fid, '- Minimum cell E-OSPA / RMSE gain: `%+.6f / %+.6f`\n', ...
    summary.minimumEospaGain, summary.minimumRmseGain);
fprintf(fid, '- Mean / max absolute snapshot mismatch: `%.6f / %.6f`\n', ...
    summary.meanAbsoluteSnapshotMismatch, ...
    summary.maximumAbsoluteSnapshotMismatch);
fprintf(fid, '- Additional attempted bytes: `%d`\n', ...
    summary.additionalAttemptedBytes);
fprintf(fid, '- Projected byte saving: `%+.3f%%`\n', ...
    summary.projectedByteSavingPercent);
fprintf(fid, '- Base formation RMSE: `%s`\n', ...
    mat2str(summary.baseFormationMeanRmse, 6));
fprintf(fid, '- Projected formation RMSE: `%s`\n', ...
    mat2str(summary.projectedFormationMeanRmse, 6));
fprintf(fid, '- Projected formation RMSE gain: `%s%%`\n', ...
    mat2str(summary.projectedFormationRmseGainPercent, 5));
fprintf(fid, '- Mechanism gate passed: `%d`\n\n', ...
    summary.mechanismGatePassed);
fprintf(fid, '## F5 joint-positive truth mechanism oracle\n\n');
fprintf(fid, '| t | Sensor | Actions | E-OSPA gain | RMSE gain | Bytes |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|--:|\n');
for row = summary.jointTruthOracleRows
    fprintf(fid, '| %d | %d | %d | %+.6f | %+.6f | %d |\n', ...
        row.time, row.receiver, row.actionCount, ...
        row.eospaGain, row.rmseGain, row.attemptedBytes);
end
fprintf(fid, '\n- Joint-oracle actions: `%d`\n', ...
    summary.jointTruthOracleActionCount);
fprintf(fid, '- Joint-oracle F5 E-OSPA / RMSE gain: `%.6f / %.6f`\n', ...
    summary.jointTruthOracleEospaGain, ...
    summary.jointTruthOracleRmseGain);
fprintf(fid, '- F3 analytic + F5 oracle additional bytes: `%d`\n', ...
    summary.jointTruthOracleAdditionalAttemptedBytes);
fprintf(fid, '- Projected byte saving: `%+.3f%%`\n', ...
    summary.jointTruthOracleProjectedByteSavingPercent);
fprintf(fid, '- Projected formation RMSE gain: `%s%%`\n', ...
    mat2str(summary. ...
        jointTruthOracleProjectedFormationRmseGainPercent, 5));
fprintf(fid, '- Joint-oracle mechanism gate passed: `%d`\n\n', ...
    summary.jointTruthOracleMechanismGatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', summary.evidenceBoundary);
end

function row = emptyOracleRow()
row = struct( ...
    'time', 0, ...
    'receiver', 0, ...
    'actionCount', 0, ...
    'eospaGain', 0, ...
    'rmseGain', 0, ...
    'attemptedBytes', 0);
end

function candidate = emptySourceLabelCandidate()
candidate = struct( ...
    'source', 0, ...
    'label', zeros(2, 1), ...
    'object', [], ...
    'responseBytes', 0);
end

function value = formatCellSchedule(schedule)
tokens = cellfun(@(ids) mat2str(reshape(ids, 1, [])), schedule, ...
    'UniformOutput', false);
value = strjoin(tokens, ' | ');
end

function row = emptyRow()
row = struct( ...
    'page', 0, ...
    'time', 0, ...
    'formation', 0, ...
    'receiver', 0, ...
    'selectedLabelCount', 0, ...
    'appliedLabelCount', 0, ...
    'attemptedBytes', 0, ...
    'baselineEospa', NaN, ...
    'trialEospa', NaN, ...
    'eospaGain', NaN, ...
    'snapshotBaselineRmse', NaN, ...
    'recursiveBaseRmse', NaN, ...
    'trialRmse', NaN, ...
    'rmseGain', NaN, ...
    'snapshotMismatch', NaN);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
