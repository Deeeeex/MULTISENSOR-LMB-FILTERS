function [reportPath, result] = ...
    runSignedMergeSplitOpportunityV69Discovery(options)
% RUNSIGNEDMERGESPLITOPPORTUNITYV69DISCOVERY Current-only cross-scale scan.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getSignedMergeSplitOpportunityV69Protocol();
v65 = getNetworkAdditiveFormationRiskV65Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('SignedMergeSplitV69:DirtySource', ...
        'The V69 source-only discovery requires clean source.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

selectorOptions = v65;
selectorOptions.minimumNormalizedRobustMarginExposure = ...
    protocol.minimumNormalizedRobustMarginExposure;
sceneResults = repmat(struct(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    records = repmat(emptyRecord(), 1, numel(protocol.snapshotTimes));
    for timeIdx = 1:numel(protocol.snapshotTimes)
        currentTime = protocol.snapshotTimes(timeIdx);
        state = loadFormationH3ObservableState( ...
            protocol.presets{presetIdx}, protocol.allSeeds, currentTime, ...
            struct('cacheRoot', protocol.cacheRoot));
        [~, control] = computeFormationRoutingLeverageSignature( ...
            state.context, state.groupIds, struct( ...
                'referenceMode', 'current-physical-tree'));
        base = computeNetworkAdditiveFormationRiskV65( ...
            control, state.context, state.groupIds, ...
            protocol.positiveSupportThreshold);
        influence = computeInfluenceAwareDecisionBreadthV66( ...
            control, state.context, state.groupIds, struct( ...
                'positiveSupportThreshold', ...
                    protocol.positiveSupportThreshold, ...
                'horizonSteps', protocol.horizonSteps));
        quarantineSelection = ...
            selectInfluenceAwareDecisionBreadthV66( ...
                base, influence, selectorOptions);
        signed = computeSignedCrossFormationOpportunityV67( ...
            base, protocol.minimumMaterialPressureFraction);
        transport = computeAlternativeTransportHeadroomV68( ...
            state.context, control, state.groupIds, protocol);
        records(timeIdx) = makeRecord( ...
            currentTime, quarantineSelection, signed, transport, protocol);
        fprintf([ ...
            'V69 %s t=%d q=%.3f%% qAction=%d retain=%.3f%% ', ...
            'altNet=%.3f%% altAction=%d\n'], ...
            protocol.presets{presetIdx}, currentTime, ...
            100 * signed.totalQuarantinePressure, ...
            quarantineSelection.actionEnabled, ...
            100 * signed.totalTransportRetentionPressure, ...
            100 * transport.optimisticNetHeadroomFraction, ...
            records(timeIdx).alternativeTransportActionEnabled);
    end
    sceneResults(presetIdx) = summarizeScene( ...
        protocol.presets{presetIdx}, protocol.allSeeds, records);
end

result = struct();
result.contractVersion = ...
    'signed-merge-split-opportunity-v69-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.sceneResults = sceneResults;
result.trackingOutcomeRead = false;
result.routeExecutionAuthorized = false;
result.trackingOutcomeScoringAuthorized = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'SIGNED_MERGE_SPLIT_OPPORTUNITY_V69_DISCOVERY.mat');
reportPath = fullfile(outputRoot, ...
    'SIGNED_MERGE_SPLIT_OPPORTUNITY_V69_DISCOVERY.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V69 signed merge-split discovery: %s\n', reportPath);
end

function record = makeRecord( ...
        currentTime, quarantine, signed, transport, protocol)
record = emptyRecord();
record.currentTime = currentTime;
record.quarantinePressure = signed.totalQuarantinePressure;
record.transportRetentionPressure = ...
    signed.totalTransportRetentionPressure;
record.signedTransportBalance = signed.totalSignedTransportBalance;
record.transportShare = signed.transportShare;
record.signedReferenceRegime = signed.regime;
record.quarantineActionEnabled = quarantine.actionEnabled;
record.quarantineFormationIds = quarantine.selectedFormationIds;
record.normalizedRobustMarginExposure = ...
    quarantine.selectedNormalizedRobustMarginExposure;
record.alternativeTransportHeadroom = ...
    transport.optimisticNetHeadroomFraction;
record.alternativeTransportGain = ...
    transport.optimisticTransportGainFraction;
record.alternativeTransportHarm = ...
    transport.optimisticSupportedHarmFraction;
record.alternativeSafePositiveSlotCount = ...
    transport.safePositiveSlotCount;
record.alternativeTransportActionEnabled = ...
    record.alternativeTransportHeadroom >= ...
        protocol.minimumMaterialAlternativeHeadroomFraction - 1e-12;
if record.quarantineActionEnabled && ...
        record.alternativeTransportActionEnabled
    record.actionableRegime = 'mixed';
elseif record.alternativeTransportActionEnabled
    record.actionableRegime = 'transport';
elseif record.quarantineActionEnabled
    record.actionableRegime = 'quarantine';
else
    record.actionableRegime = 'fallback';
end
end

function summary = summarizeScene(presetName, seed, records)
summary = struct();
summary.presetName = presetName;
summary.seed = seed;
summary.records = records;
summary.quarantineActionTimes = ...
    [records([records.quarantineActionEnabled]).currentTime];
summary.alternativeTransportActionTimes = ...
    [records([records.alternativeTransportActionEnabled]).currentTime];
summary.actionableTimes = [records(~strcmp( ...
    {records.actionableRegime}, 'fallback')).currentTime];
[~, qIdx] = max([records.quarantinePressure]);
[~, retentionIdx] = max([records.transportRetentionPressure]);
[~, alternativeIdx] = max([records.alternativeTransportHeadroom]);
summary.maximumQuarantineRecord = records(qIdx);
summary.maximumRetentionRecord = records(retentionIdx);
summary.maximumAlternativeRecord = records(alternativeIdx);
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'quarantinePressure', NaN, ...
    'transportRetentionPressure', NaN, ...
    'signedTransportBalance', NaN, ...
    'transportShare', NaN, ...
    'signedReferenceRegime', 'not-evaluated', ...
    'quarantineActionEnabled', false, ...
    'quarantineFormationIds', zeros(1, 0), ...
    'normalizedRobustMarginExposure', NaN, ...
    'alternativeTransportHeadroom', NaN, ...
    'alternativeTransportGain', NaN, ...
    'alternativeTransportHarm', NaN, ...
    'alternativeSafePositiveSlotCount', NaN, ...
    'alternativeTransportActionEnabled', false, ...
    'actionableRegime', 'fallback');
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('SignedMergeSplitV69:WriteFailed', ...
        'Could not create the V69 discovery report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V69 signed merge-split opportunity discovery\n\n');
for scene = result.sceneResults
    fprintf(fid, '## %s / seed %d\n\n', ...
        scene.presetName, scene.seed);
    fprintf(fid, ['| Time | Quarantine | Q action | Robust exposure | ', ...
        'Retention | Alternative net | Alt action | Regime |\n']);
    fprintf(fid, '|--:|--:|:--:|--:|--:|--:|:--:|:--|\n');
    for record = scene.records
        fprintf(fid, ...
            ['| %d | %.3f%% | %d | %.4f | %.3f%% | %.3f%% | ', ...
             '%d | `%s` |\n'], ...
            record.currentTime, 100 * record.quarantinePressure, ...
            record.quarantineActionEnabled, ...
            record.normalizedRobustMarginExposure, ...
            100 * record.transportRetentionPressure, ...
            100 * record.alternativeTransportHeadroom, ...
            record.alternativeTransportActionEnabled, ...
            record.actionableRegime);
    end
    fprintf(fid, '\n- Quarantine action times: `%s`\n', ...
        mat2str(scene.quarantineActionTimes));
    fprintf(fid, '- Alternative transport action times: `%s`\n', ...
        mat2str(scene.alternativeTransportActionTimes));
    fprintf(fid, '- Maximum quarantine: `t=%d / %.3f%%`\n', ...
        scene.maximumQuarantineRecord.currentTime, ...
        100 * scene.maximumQuarantineRecord.quarantinePressure);
    fprintf(fid, '- Maximum reference retention: `t=%d / %.3f%%`\n', ...
        scene.maximumRetentionRecord.currentTime, ...
        100 * scene.maximumRetentionRecord.transportRetentionPressure);
    fprintf(fid, '- Maximum alternative net: `t=%d / %.3f%%`\n\n', ...
        scene.maximumAlternativeRecord.currentTime, ...
        100 * scene.maximumAlternativeRecord.alternativeTransportHeadroom);
end
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
