function [datasetPath, dataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        presetName, seedList, actionCodeSequences, options)
% GENERATEROLLINGSAFEROLLOUTIMITATIONDATASET Collect rollout graph labels.
%
% Each seed follows one already-screened finite-horizon action sequence
% from a common continuation cache. At every predecision state, the
% generator stores truth-free posterior/link/history features and the
% executed safe cross-formation graph. The action sequences and their
% selection use privileged outcome information; the features do not.

protocol = getRollingSafeRolloutProtocol();
if nargin < 1 || isempty(presetName)
    presetName = protocol.presetName;
end
if nargin < 2 || isempty(seedList)
    seedList = protocol.datasetSeeds;
end
if nargin < 3 || isempty(actionCodeSequences)
    actionCodeSequences = protocol.actionCodeSequences;
end
if nargin < 4 || isempty(options)
    options = struct();
end
datasetVariant = lower(strrep(char(getField( ...
    options, 'datasetVariant', ...
    'rollout-imitation-v2')), '_', '-'));
jointActionMode = strcmp( ...
    datasetVariant, 'joint-action-state-v3');
if ~jointActionMode && ...
        ~strcmp(datasetVariant, 'rollout-imitation-v2')
    error('Unknown rolling-safe dataset variant.');
end
jointActionProtocol = ...
    getRollingSafeJointActionCriticProtocol();
seedList = round(reshape(seedList, 1, []));
actionCodeSequences = round(actionCodeSequences);
if size(actionCodeSequences, 1) ~= numel(seedList) || ...
        isempty(actionCodeSequences) || ...
        any(~isfinite(actionCodeSequences(:))) || ...
        any(actionCodeSequences(:) < 0)
    error(['actionCodeSequences must contain one finite nonnegative ', ...
        'row per seed.']);
end
if numel(unique(seedList)) ~= numel(seedList) || ...
        any(seedList < 1)
    error('seedList must contain unique positive integers.');
end
if ~strcmp(presetName, protocol.presetName) || ...
        ~isequal(seedList, protocol.datasetSeeds) || ...
        ~isequal(actionCodeSequences, ...
            protocol.actionCodeSequences)
    error(['Official rollout dataset generation must match the ', ...
        'frozen protocol.']);
end

continuationStartTime = max(1, round(getField( ...
    options, 'continuationStartTime', ...
    protocol.continuationStartTime)));
horizonLength = size(actionCodeSequences, 2);
snapshotTimes = continuationStartTime + (0:(horizonLength - 1));
sourceWeight = getField( ...
    options, 'sourceWeight', protocol.sourceWeight);
payloadToleranceFraction = getField(options, ...
    'payloadToleranceFraction', ...
    protocol.payloadToleranceFraction);
if continuationStartTime ~= protocol.continuationStartTime || ...
        abs(sourceWeight - protocol.sourceWeight) > 1e-12 || ...
        ~sameScalar(payloadToleranceFraction, ...
            protocol.payloadToleranceFraction)
    error(['Official rollout generation parameters differ from the ', ...
        'frozen protocol.']);
end
filterSeedOffset = getField(options, ...
    'filterSeedOffset', protocol.filterSeedOffset);
if ~isscalar(filterSeedOffset) || ...
        filterSeedOffset ~= protocol.filterSeedOffset
    error(['Official rollout filter RNG offset differs from the ', ...
        'frozen protocol.']);
end
featureContextMode = lower(strrep(char(getField( ...
    options, 'featureContextMode', 'raw')), '_', '-'));
if jointActionMode && ...
        ~strcmp(featureContextMode, ...
            jointActionProtocol.featureContextMode)
    error(['Joint-action state generation requires the frozen ', ...
        'raw feature context.']);
end
behaviorCacheDirectory = getField(options, ...
    'behaviorCacheDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'cache'));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'datasets'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
if jointActionMode
    defaultDatasetName = sprintf( ...
        'rolling_safe_joint_action_state_%s_t%d_v3.mat', ...
        strrep(presetName, '-', '_'), ...
        continuationStartTime);
    defaultReportName = sprintf( ...
        'ROLLING_SAFE_JOINT_ACTION_STATE_%s_T%d_V3.md', ...
        upper(strrep(presetName, '-', '_')), ...
        continuationStartTime);
else
    defaultDatasetName = sprintf( ...
        'rolling_safe_rollout_imitation_%s_t%d.mat', ...
        strrep(presetName, '-', '_'), ...
        continuationStartTime);
    defaultReportName = sprintf( ...
        'ROLLING_SAFE_ROLLOUT_IMITATION_%s_T%d.md', ...
        upper(strrep(presetName, '-', '_')), ...
        continuationStartTime);
end
datasetPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, defaultDatasetName));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, defaultReportName));

blocks = repmat(emptyBlock(), ...
    1, numel(seedList) * horizonLength);
outcomes = repmat(emptyOutcome(), 1, numel(seedList));
blockCursor = 0;
expectedFeatureNames = {};
generationGitState = resolveResearchGitState();
behaviorCacheRecords = repmat(struct( ...
    'seed', NaN, 'path', '', 'sha256', ''), ...
    1, numel(seedList));
for seedCursor = 1:numel(seedList)
    seed = seedList(seedCursor);
    actionCodes = actionCodeSequences(seedCursor, :);
    inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
    if snapshotTimes(end) > inputs.config.simulationLength
        error('Rollout snapshots exceed the scenario horizon.');
    end
    inputs = cropInputs(inputs, snapshotTimes(end));
    [initialPosteriors, continuationHistory, cachePath, cacheSha256] = ...
        loadContinuationPosterior( ...
            behaviorCacheDirectory, presetName, seed, ...
            continuationStartTime, inputs.config, ...
            protocol.behaviorCacheSha256{seedCursor});
    behaviorCacheRecords(seedCursor) = struct( ...
        'seed', seed, 'path', cachePath, ...
        'sha256', cacheSha256);
    triggerConfig = buildRolloutConfig( ...
        inputs, initialPosteriors, continuationHistory, ...
        snapshotTimes, continuationStartTime, ...
        actionCodes, sourceWeight, ...
        payloadToleranceFraction);

    rng(seed + filterSeedOffset);
    timerId = tic;
    [estimates, diagnostics] = ...
        runEventTriggeredDistributedLmbFilter( ...
            inputs.model, inputs.measurements, ...
            inputs.sensorTrajectories, inputs.neighborMap, ...
            inputs.commConfig, triggerConfig);
    elapsedSeconds = toc(timerId);
    outcomes(seedCursor) = summarizeOutcome( ...
        seed, actionCodes, estimates, diagnostics, ...
        inputs, snapshotTimes, elapsedSeconds);
    fprintf(['rollout imitation seed %d codes=%s: ', ...
        'E-OSPA %.4f, worst %.4f, %.2f s\n'], ...
        seed, formatActionCodes(actionCodes), ...
        outcomes(seedCursor).meanEospa, ...
        outcomes(seedCursor).worstSensorEospa, ...
        elapsedSeconds);

    for timeCursor = 1:numel(snapshotTimes)
        currentTime = snapshotTimes(timeCursor);
        posteriors = ...
            diagnostics.topologyLocalPosteriorSnapshot{currentTime};
        if isempty(posteriors)
            error('Missing rollout posterior snapshot at t=%d.', ...
                currentTime);
        end
        [context, deliveredHistory, ...
            deliveredHistoryTimes] = buildFeatureContext( ...
            inputs, diagnostics, posteriors, currentTime, ...
            continuationStartTime, continuationHistory);
        featureOptions = struct( ...
            'featureContextMode', featureContextMode);
        [X, featureNames, receiverIndices, ...
            senderIndices, featureMetadata] = ...
                computeRollingSafeDirectedActionExamples( ...
                    context, sourceWeight, featureOptions);
        if isempty(expectedFeatureNames)
            expectedFeatureNames = featureNames;
        elseif ~isequal(expectedFeatureNames, featureNames)
            error('Rollout feature contracts differ across blocks.');
        end
        selectedAdjacency = ...
            convertDiagnosticEdgeMaskToPolicyAdjacency( ...
                diagnostics.topologyActiveEdge( ...
                    :, :, currentTime));
        [selectedMask, selectedSources] = ...
            extractExecutedLabels( ...
                selectedAdjacency, receiverIndices, ...
                senderIndices, context.physicalAdjacency);
        groupIds = reshape( ...
            inputs.config.sensorGroupIds, 1, []);
        validateCandidateBijection( ...
            context.physicalAdjacency, groupIds, ...
            receiverIndices, senderIndices, ...
            selectedAdjacency, selectedMask);

        blockCursor = blockCursor + 1;
        block = emptyBlock();
        block.seed = seed;
        block.currentTime = currentTime;
        block.relativeTime = timeCursor;
        block.actionCode = actionCodes(timeCursor);
        block.actionTruthUsed = logical( ...
            diagnostics.topologyPolicyTruthUsed(currentTime));
        block.features = X;
        block.featureNames = featureNames;
        block.featureMetadata = featureMetadata;
        block.receiverIndices = receiverIndices;
        block.senderIndices = senderIndices;
        block.selectedCrossMask = selectedMask;
        block.selectedCrossEdgeCount = nnz(selectedMask);
        block.selectedSourcesByReceiver = selectedSources;
        block.selectedAdjacency = selectedAdjacency;
        block.physicalAdjacency = context.physicalAdjacency;
        block.groupIds = groupIds;
        block.senderPayloadBytes = computeSenderPayloadBytes( ...
            posteriors, inputs.model);
        block.previousAdjacencyHistory = ...
            context.previousAdjacencyHistory;
        block.previousAdjacencyHistoryTimes = ...
            context.previousAdjacencyHistoryTimes;
        block.previousDeliveredAdjacencyHistory = ...
            deliveredHistory;
        block.previousDeliveredAdjacencyHistoryTimes = ...
            deliveredHistoryTimes;
        block.labelTruthUsed = true;
        block.labelSource = ...
            'outcome-selected-safe-rollout-executed-graph';
        blocks(blockCursor) = block;
    end
end

if ~jointActionMode
    blocks = rmfield(blocks, { ...
        'previousDeliveredAdjacencyHistory', ...
        'previousDeliveredAdjacencyHistoryTimes'});
end

dataset = struct();
if jointActionMode
    dataset.protocolId = jointActionProtocol.id;
    dataset.contractVersion = ...
        jointActionProtocol.datasetContractVersion;
else
    dataset.protocolId = protocol.id;
    dataset.contractVersion = ...
        protocol.datasetContractVersion;
end
dataset.sourceRolloutProtocolId = protocol.id;
dataset.datasetVariant = datasetVariant;
dataset.generatedAt = datestr(now, 31);
dataset.presetName = presetName;
dataset.seeds = seedList;
dataset.actionCodeSequences = actionCodeSequences;
dataset.continuationStartTime = continuationStartTime;
dataset.snapshotTimes = snapshotTimes;
dataset.sourceWeight = sourceWeight;
dataset.payloadToleranceFraction = ...
    payloadToleranceFraction;
dataset.filterSeedOffset = filterSeedOffset;
dataset.designSeeds = protocol.designSeeds;
dataset.behaviorCacheRecords = behaviorCacheRecords;
dataset.behaviorCacheSha256 = ...
    protocol.behaviorCacheSha256;
dataset.generationGitCommit = generationGitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    generationGitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    generationGitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    generationGitState.researchWorktreeDirty;
dataset.featureContextMode = featureContextMode;
dataset.featureNames = expectedFeatureNames;
dataset.blocks = blocks;
dataset.outcomes = outcomes;
dataset.featuresUseTruth = false;
dataset.labelsUseTruth = true;
dataset.labelSelectionUsesFutureOutcome = true;
dataset.behaviorCacheDirectory = behaviorCacheDirectory;
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
dataset.evidenceBoundary = [ ...
    'Features are deployment-observable. Executed graph labels come ', ...
    'from seed-specific action sequences selected after closed-loop ', ...
    'outcome inspection and are privileged training supervision only.'];
if jointActionMode
    dataset.selectedHistoryConvention = ...
        ['receiver-row-sender-column-directed-', ...
         'oldest-to-newest'];
    dataset.deliveredHistoryConvention = ...
        dataset.selectedHistoryConvention;
    dataset.evidenceBoundary = [ ...
        dataset.evidenceBoundary, ...
        ' The v3 state contract separately stores the two ', ...
        'predecision selected and delivered history pages; delivered ', ...
        'edges are attested subsets of selected edges.'];
end
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Dataset: %s\nReport: %s\n', datasetPath, reportPath);
end

function config = buildRolloutConfig( ...
        inputs, initialPosteriors, continuationHistory, ...
        snapshotTimes, continuationStartTime, ...
        actionCodes, sourceWeight, payloadToleranceFraction)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    inputs.config.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'rollout-imitation-label-trajectory';
sequenceOptions = struct( ...
    'sourceWeight', sourceWeight, ...
    'payloadToleranceFraction', payloadToleranceFraction, ...
    'scoreOptions', struct( ...
        'sourceWeight', sourceWeight, ...
        'horizonSteps', 0, ...
        'discountFactor', 0.9));
config.topologyPolicyFcn = ...
    @(context) selectRollingSafeActionSequencePolicy( ...
        context, actionCodes, continuationStartTime, ...
        sequenceOptions);
config.topologyPosteriorCaptureTimes = snapshotTimes;
config.filterInitialLocalPosteriorBySensor = initialPosteriors;
config.filterInitialLocalPosteriorTime = continuationStartTime;
if size(continuationHistory. ...
        selectedDirectedEdgeHistory, 3) > 0
    config.filterInitialPreviousAdjacencyHistory = ...
        convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
            continuationHistory.selectedDirectedEdgeHistory);
    config.filterInitialPreviousAdjacencyTimes = ...
        continuationHistory.times;
    config.filterInitialPreviousAdjacencyHistorySource = ...
        'behavior-filter-diagnostics-cache-v2';
end
end

function [context, deliveredHistory, deliveredHistoryTimes] = ...
        buildFeatureContext( ...
        inputs, diagnostics, posteriors, ...
        currentTime, continuationStartTime, continuationHistory)
sensorCount = inputs.config.numberOfSensors;
[history, historyTimes] = reconstructHistory( ...
    diagnostics, currentTime, continuationStartTime, 2);
[deliveredHistory, deliveredHistoryTimes] = ...
    reconstructDeliveredHistory( ...
        diagnostics, currentTime, ...
        continuationStartTime, ...
        continuationHistory, 2);
context = struct();
context.localPosteriorBySensor = posteriors;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = history;
context.previousAdjacencyHistoryCount = size(history, 3);
context.previousAdjacencyHistoryTimes = historyTimes;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
if isempty(history)
    context.previousAdjacency = false(sensorCount);
else
    context.previousAdjacency = history(:, :, end);
end
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, currentTime);
context.edgeScores = double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = sensorCount;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, currentTime);
end
end

function [history, times] = reconstructDeliveredHistory( ...
        diagnostics, currentTime, continuationStartTime, ...
        continuationHistory, depth)
history = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        continuationHistory.deliveredDirectedEdgeHistory);
times = reshape(continuationHistory.times, 1, []);
for executedTime = continuationStartTime:(currentTime - 1)
    page = convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.delivered(:, :, executedTime));
    history(:, :, end + 1) = page; %#ok<AGROW>
    times(end + 1) = executedTime; %#ok<AGROW>
    if size(history, 3) > depth
        history = history(:, :, ...
            (end - depth + 1):end);
        times = times((end - depth + 1):end);
    end
end
if size(history, 3) ~= numel(times)
    error('Reconstructed delivered history times are misaligned.');
end
end

function [history, times] = reconstructHistory( ...
        diagnostics, currentTime, continuationStartTime, depth)
history = diagnostics.initialPreviousPolicyAdjacencyHistory;
times = reshape( ...
    diagnostics.initialPreviousAdjacencyHistoryTimes, 1, []);
for executedTime = continuationStartTime:(currentTime - 1)
    page = convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge(:, :, executedTime));
    history(:, :, end + 1) = page; %#ok<AGROW>
    times(end + 1) = executedTime; %#ok<AGROW>
    if size(history, 3) > depth
        history = history(:, :, (end - depth + 1):end);
        times = times((end - depth + 1):end);
    end
end
if size(history, 3) ~= numel(times)
    error('Reconstructed rollout history times are misaligned.');
end
end

function [selectedMask, selectedSources] = ...
        extractExecutedLabels( ...
            selectedAdjacency, receiverIndices, ...
            senderIndices, physicalAdjacency)
sensorCount = size(selectedAdjacency, 1);
if ~isequal(size(selectedAdjacency), [sensorCount, sensorCount]) || ...
        any(selectedAdjacency(:) & ~physicalAdjacency(:))
    error('Executed rollout adjacency violates the physical graph.');
end
selectedSources = nan(1, sensorCount);
for receiverIdx = 1:sensorCount
    senders = find(selectedAdjacency(receiverIdx, :));
    if numel(senders) ~= 1
        error(['Rollout imitation requires exactly one sender for ', ...
            'every receiver.']);
    end
    selectedSources(receiverIdx) = senders;
end
linearIndices = sub2ind( ...
    [sensorCount, sensorCount], receiverIndices, senderIndices);
selectedMask = logical(selectedAdjacency(linearIndices));
selectedMask = reshape(selectedMask, [], 1);
end

function validateCandidateBijection( ...
        physicalAdjacency, groupIds, receiverIndices, ...
        senderIndices, selectedAdjacency, selectedMask)
nodeCount = size(physicalAdjacency, 1);
[expectedReceivers, expectedSenders] = ...
    find(logical(physicalAdjacency));
crossMask = groupIds(expectedReceivers) ~= ...
    groupIds(expectedSenders);
expectedReceivers = expectedReceivers(crossMask);
expectedSenders = expectedSenders(crossMask);
featureKeys = receiverIndices + ...
    nodeCount * (senderIndices - 1);
expectedKeys = expectedReceivers + ...
    nodeCount * (expectedSenders - 1);
if numel(featureKeys) ~= numel(expectedKeys) || ...
        numel(unique(featureKeys)) ~= numel(featureKeys) || ...
        ~all(ismember(expectedKeys, featureKeys))
    error(['Rollout feature candidates are not a bijection of the ', ...
        'physical cross-formation action set.']);
end
selectedCross = logical(selectedAdjacency);
sameFormation = groupIds(:) == groupIds(:)';
selectedCross(sameFormation) = false;
if nnz(selectedMask) ~= nnz(selectedCross)
    error(['Executed cross-formation labels are incomplete relative ', ...
        'to the selected adjacency.']);
end
end

function bytes = computeSenderPayloadBytes(posteriors, model)
bytes = zeros(1, numel(posteriors));
for sensorIdx = 1:numel(posteriors)
    stats = estimateLmbPayloadSize( ...
        posteriors{sensorIdx}, model, 2, struct());
    bytes(sensorIdx) = stats.estimatedBytes;
end
if any(~isfinite(bytes)) || any(bytes < 0)
    error('Rollout sender payload estimates are invalid.');
end
end

function outcome = summarizeOutcome( ...
        seed, actionCodes, estimates, diagnostics, ...
        inputs, snapshotTimes, elapsedSeconds)
sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(inputs.groundTruthRfs.x));
for sensorIdx = 1:sensorCount
    eospa(sensorIdx, :) = computeSimulationOspa( ...
        inputs.model, inputs.groundTruthRfs, ...
        estimates{sensorIdx});
end
sensorMeans = mean(eospa(:, snapshotTimes), 2);
focusEospa = eospa(:, snapshotTimes);
attemptedBytes = sum(reshape( ...
    diagnostics.attemptedPayloadBytes( ...
        :, :, snapshotTimes), 1, []));
deliveredBytes = sum(reshape( ...
    diagnostics.payloadBytes(:, :, snapshotTimes), 1, []));
outcome = emptyOutcome();
outcome.seed = seed;
outcome.actionCodes = actionCodes;
outcome.meanEospa = mean(focusEospa(:));
outcome.worstSensorEospa = max(sensorMeans);
[~, outcome.worstSensorIndex] = max(sensorMeans);
outcome.attemptedBytes = attemptedBytes;
outcome.deliveredBytes = deliveredBytes;
outcome.policyTruthUseFraction = mean( ...
    diagnostics.topologyPolicyTruthUsed(snapshotTimes));
outcome.policyRepairRate = mean( ...
    diagnostics.topologyPolicyRepairTriggered(snapshotTimes));
outcome.topologyInfeasibleRate = mean( ...
    ~diagnostics.topologyFeasible(snapshotTimes));
mature = diagnostics.topologyPolicySensorWindowMature(snapshotTimes) == 1;
outcome.selectedRollingB3PassFraction = mean( ...
    diagnostics.topologyPolicySensorWindowStrong( ...
        snapshotTimes(mature)));
outcome.elapsedSeconds = elapsedSeconds;
end

function [posteriors, history, cachePath, cacheSha256] = ...
        loadContinuationPosterior( ...
            directory, presetName, seed, startTime, config, ...
            expectedCacheSha256)
cachePath = fullfile(directory, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', ...
    strrep(presetName, '-', '_'), seed, startTime));
if exist(cachePath, 'file') ~= 2
    error('Missing continuation cache: %s', cachePath);
end
cacheSha256 = computeFileSha256(cachePath);
if ~strcmp(cacheSha256, expectedCacheSha256)
    error(['Continuation cache does not match the frozen SHA-256 ', ...
        'registry: %s'], cachePath);
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Continuation cache has no behaviorBundle: %s', cachePath);
end
bundle = loaded.behaviorBundle;
expectedConfig = buildMixtureAwareKlaReferenceConfig();
expectedConfig.dynamicTopologyEnabled = false;
expectedConfig.topologyPosteriorCaptureTimes = startTime;
valid = strcmp(bundle.presetName, presetName) && ...
    bundle.seed == seed && ...
    isequaln(bundle.configSnapshot, config) && ...
    isequaln(bundle.behaviorConfigSnapshot, expectedConfig) && ...
    isequal(bundle.snapshotTimes, startTime);
if ~valid
    error('Continuation cache metadata mismatch: %s', cachePath);
end
try
    [posteriors, history] = ...
        extractBehaviorContinuationSnapshot( ...
            bundle, startTime, config.numberOfSensors);
catch errorInfo
    error(['Continuation cache history contract mismatch (%s): ', ...
        '%s'], errorInfo.identifier, cachePath);
end
end

function inputs = cropInputs(inputs, maxTime)
maxTime = min(max(1, round(maxTime)), size(inputs.measurements, 2));
inputs.measurements = inputs.measurements(:, 1:maxTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maxTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maxTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maxTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maxTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maxTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maxTime);
inputs.model.simulationLength = maxTime;
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open rollout imitation report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
if strcmp(dataset.datasetVariant, 'joint-action-state-v3')
    fprintf(fid, '# Rolling-safe joint-action state dataset v3\n\n');
else
    fprintf(fid, '# Rolling-safe rollout imitation dataset\n\n');
end
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Preset: `%s`\n', dataset.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%s`\n', mat2str(dataset.snapshotTimes));
fprintf(fid, '- Source weight: %.2f\n', dataset.sourceWeight);
fprintf(fid, '- Payload tolerance fraction: `%s`\n', ...
    formatScalar(dataset.payloadToleranceFraction));
fprintf(fid, '- Filter RNG offset: `%d`\n', ...
    dataset.filterSeedOffset);
fprintf(fid, '- Protocol: `%s`\n', dataset.protocolId);
fprintf(fid, '- Source rollout protocol: `%s`\n', ...
    dataset.sourceRolloutProtocolId);
fprintf(fid, '- Generation git commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Generation research worktree dirty: `%d`\n', ...
    dataset.generationResearchWorktreeDirty);
fprintf(fid, '- Feature context: `%s`\n', ...
    dataset.featureContextMode);
fprintf(fid, '- Feature count: %d\n', ...
    numel(dataset.featureNames));
fprintf(fid, '- Features use truth: `%d`\n', ...
    dataset.featuresUseTruth);
fprintf(fid, '- Labels use truth: `%d`\n', ...
    dataset.labelsUseTruth);
fprintf(fid, '- Future outcomes selected labels: `%d`\n', ...
    dataset.labelSelectionUsesFutureOutcome);
fprintf(fid, ['- Joint-projector replay context: physical action set, ', ...
    'group IDs, sender payload estimates and executed B=3 history\n']);
if strcmp(dataset.datasetVariant, 'joint-action-state-v3')
    fprintf(fid, ['- Selected/delivered history contract: separate ', ...
        'two-page predecision histories; delivered is a subset of ', ...
        'selected\n']);
end
