function token = formatActionCodes(actionCodes)
parts = arrayfun(@(code) sprintf('%02d', code), ...
    reshape(actionCodes, 1, []), 'UniformOutput', false);
token = strjoin(parts, '-');
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function equal = sameScalar(left, right)
equal = isscalar(left) && isscalar(right) && ...
    ((isinf(left) && isinf(right) && sign(left) == sign(right)) || ...
     (isfinite(left) && isfinite(right) && abs(left - right) <= 1e-12));
end

function token = formatScalar(value)
if isinf(value)
    token = 'inf';
else
    token = sprintf('%.17g', value);
end
end
