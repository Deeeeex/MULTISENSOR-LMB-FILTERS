function [reportPath, dataset] = ...
        runSparseRecursiveCounterfactualsV209(options)
% RUNSPARSERECURSIVECOUNTERFACTUALSV209 Same-state delayed-action probes.
%
% Reuse the completed V206 teacher trajectory as the action branch and run
% only the paired continuations that delete one action.  The common prefix,
% release plan, random inputs and (where applicable) forced continuation are
% identical.  Each target is evaluated on a fixed three-page post-decision
% window, relative to the same-state no-op branch.

if nargin < 1 || isempty(options)
    options = struct();
end
runMissingScreens = logical(getField( ...
    options, 'runMissingScreens', true));
reuseExistingScreens = logical(getField( ...
    options, 'reuseExistingScreens', true));
returnHorizonSteps = getField(options, 'returnHorizonSteps', 3);
if ~isscalar(returnHorizonSteps) || ...
        ~isfinite(returnHorizonSteps) || ...
        returnHorizonSteps < 1 || ...
        returnHorizonSteps ~= round(returnHorizonSteps)
    error('SparseRecursiveV209:InvalidReturnHorizon', ...
        'The recursive return horizon must be a positive integer.');
end

candidateScreenPath = char(getField(options, ...
    'candidateScreenPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v206', 'support_aware_complete_teacher', ...
        'x36_seed211_t72_h8', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat'])));
v204WithF1ScreenPath = char(getField(options, ...
    'v204WithF1ScreenPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v204', 'mode_complete_teacher', ...
        'x36_seed211_t72_h8', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat'])));
v204WithoutF1ScreenPath = char(getField(options, ...
    'v204WithoutF1ScreenPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v204', 'without_f1_teacher', ...
        'x36_seed211_t72_h8', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat'])));
immediateDatasetPath = char(getField(options, ...
    'immediateDatasetPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v208', ...
        'formation_label_kla_immediate_merged', ...
        'x36_seed211_t72_h8', ...
        'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208_MERGED.mat')));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v209', 'sparse_recursive_counterfactuals', ...
    'x36_seed211_t72_h8')));
if exist(candidateScreenPath, 'file') ~= 2 || ...
        exist(v204WithF1ScreenPath, 'file') ~= 2 || ...
        exist(v204WithoutF1ScreenPath, 'file') ~= 2 || ...
        exist(immediateDatasetPath, 'file') ~= 2
    error('SparseRecursiveV209:MissingInput', ...
        ['The completed V204/V206 screens and V208 immediate dataset ', ...
         'are required.']);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

releasePlan = struct( ...
    'contractVersion', ...
        'online-positive-net-formation-release-v191-plan-v1', ...
    'times', 72, ...
    'formationIdsByTime', {{5}}, ...
    'teacherMode', true);
cases = counterfactualCases( ...
    outputRoot, candidateScreenPath, ...
    v204WithF1ScreenPath, v204WithoutF1ScreenPath);
for caseIdx = 1:numel(cases)
    currentCase = cases(caseIdx);
    if ~currentCase.generateNoOpScreen
        continue;
    end
    expectedScreenPath = fullfile(currentCase.outputRoot, 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat']);
    if exist(expectedScreenPath, 'file') ~= 2
        if ~runMissingScreens
            error('SparseRecursiveV209:MissingCounterfactual', ...
                'A requested no-op counterfactual screen is missing.');
        end
        runOptions = struct( ...
            'horizonSteps', 8, ...
            'currentTime', 72, ...
            'repairPageOffsets', currentCase.noOpRepairPageOffsets, ...
            'forcedFormationId', currentCase.noOpFormationIds, ...
            'forcedSourceId', currentCase.noOpSourceIds, ...
            'forcedLabel', currentCase.noOpLabels, ...
            'maximumActions', 1, ...
            'updateMode', 'label-kla', ...
            'sourceWeight', 0.5, ...
            'idealDeliveryTeacherMode', true, ...
            'onlinePositiveNetFormationReleasePlan', releasePlan, ...
            'outputRoot', currentCase.outputRoot, ...
            'reuseExistingScreen', reuseExistingScreens);
        runBudgetRecycledFormationRepairV188RecursivePilot( ...
            'X36', runOptions);
    end
    cases(caseIdx).noOpScreenPath = expectedScreenPath;
end

immediateLoaded = load(immediateDatasetPath, 'dataset');
immediateDataset = immediateLoaded.dataset;
rows = repmat(emptyRow(), 1, numel(cases));
for caseIdx = 1:numel(cases)
    candidateLoaded = load( ...
        cases(caseIdx).candidateScreenPath, 'screen');
    noOpLoaded = load(cases(caseIdx).noOpScreenPath, 'screen');
    rows(caseIdx) = evaluateCase( ...
        cases(caseIdx), candidateLoaded.screen, noOpLoaded.screen, ...
        immediateDataset, returnHorizonSteps);
end

referenceLoaded = load(candidateScreenPath, 'screen');
referenceScreen = referenceLoaded.screen;

dataset = struct();
dataset.contractVersion = ...
    'sparse-recursive-counterfactual-action-value-v209-v1';
dataset.generatedAt = datestr(now, 31);
dataset.presetName = referenceScreen.presetName;
dataset.seed = referenceScreen.seed;
dataset.immediateDatasetPath = immediateDatasetPath;
dataset.returnHorizonSteps = returnHorizonSteps;
dataset.rows = rows;
dataset.truthUsedForTargets = true;
dataset.truthUsedAtRuntime = false;
dataset.completeTrajectoryHeldOut = false;
dataset.policyInducedStateTargets = true;
dataset.validationClaimAllowed = false;
dataset.evidenceBoundary = [ ...
    'V209 reuses opened X36 seed-211 V204/V206 teacher trajectories and ', ...
    'runs only the two missing delete-one-action continuations.  Every ', ...
    'pair has the same causal prefix, random inputs and fixed continuation ', ...
    'schedule over its scored window; truth scores the three-page return ', ...
    'after the branch.  The four rows span formation release and three ', ...
    'supported-label modes.  They test whether delayed recursive value ', ...
    'exists on policy-induced development states.  This is not a learned ', ...
    'selector, calibration set, held-out seed or performance claim.'];
dataset.matPath = fullfile(outputRoot, ...
    'SPARSE_RECURSIVE_COUNTERFACTUALS_V209.mat');
reportPath = fullfile(outputRoot, ...
    'SPARSE_RECURSIVE_COUNTERFACTUALS_V209.md');
dataset.reportPath = reportPath;
save('-mat7-binary', dataset.matPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('V209 sparse recursive counterfactuals: %s\n', reportPath);
end

