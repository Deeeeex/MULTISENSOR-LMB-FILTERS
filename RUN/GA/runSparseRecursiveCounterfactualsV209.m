    dataset.evidenceBoundary);
end

function value = vectorText(values)
value = strtrim(sprintf('%d ', reshape(values, 1, [])));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
