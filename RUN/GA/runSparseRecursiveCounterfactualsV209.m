function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('SparseRecursiveV209:ReportOpen', ...
        'Could not open the V209 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V209 sparse recursive counterfactuals\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    dataset.presetName, dataset.seed);
fprintf(fid, '- Fixed post-decision return horizon: `%d pages`\n', ...
    dataset.returnHorizonSteps);
fprintf(fid, '- Paired action branches: `%d`\n\n', ...
    numel(dataset.rows));
fprintf(fid, ['| Branch | Type | Window | E-OSPA | RMSE | Consensus | ', ...
    'Receiver E / R | Added bytes | Static saving | Aggregate / strict |\n']);
fprintf(fid, ['|:--|:--|:--|--:|--:|--:|:--|--:|--:|:--:|\n']);
for row = reshape(dataset.rows, 1, [])
    fprintf(fid, ['| `%s` | `%s` | `%s` | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% / %+.3f%% | %+.0f B | %+.3f%% | %d / %d |\n'], ...
        row.name, row.actionType, vectorText(row.windowTimes), ...
        row.meanEospaGainPercent, row.meanRmseGainPercent, ...
        row.consensusGainPercent, ...
        row.receiverFormationEospaGainPercent, ...
        row.receiverFormationRmseGainPercent, ...
        row.incrementalAttemptedBytes, ...
        row.candidateStaticByteSavingPercent, ...
        row.aggregateReturnPositive, row.strictReturnPositive);
end
fprintf(fid, '\n## Tail readout\n\n');
fprintf(fid, ['| Branch | Min receiver-sensor E / R | ', ...
    'Worst-network E / R | Min formation E / R | Terminal consensus |\n']);
fprintf(fid, '|:--|:--|:--|:--|--:|\n');
for row = reshape(dataset.rows, 1, [])
    fprintf(fid, ['| `%s` | %+.3f%% / %+.3f%% | ', ...
        '%+.3f%% / %+.3f%% | %+.3f%% / %+.3f%% | %+.3f%% |\n'], ...
        row.name, ...
        row.minimumAffectedSensorEospaGainPercent, ...
        row.minimumAffectedSensorRmseGainPercent, ...
        row.worstSensorEospaGainPercent, ...
        row.worstSensorRmseGainPercent, ...
        row.minimumFormationEospaGainPercent, ...
        row.minimumFormationRmseGainPercent, ...
        row.terminalConsensusGainPercent);
end
fprintf(fid, '\n## Base-route immediate reference\n\n');
fprintf(fid, ['These immediate values come from the unmodified V99 route. ', ...
    'They are proposal diagnostics, not same-state substitutes for the ', ...
    'recursive branch targets above.\n\n']);
fprintf(fid, '| Branch | Immediate E / R / C | Joint aggregate positive |\n');
fprintf(fid, '|:--|:--|:--:|\n');
for row = reshape(dataset.rows, 1, [])
    immediate = row.baseRouteImmediate;
    if immediate.found
        fprintf(fid, '| `%s` | %+.3f%% / %+.3f%% / %+.3f%% | %d |\n', ...
            row.name, immediate.meanEospaGainPercent, ...
            immediate.meanRmseGainPercent, ...
            immediate.consensusGainPercent, ...
            immediate.jointAggregatePositive);
    else
        fprintf(fid, '| `%s` | -- | -- |\n', row.name);
    end
end
fprintf(fid, '\n## Pairing checks\n\n');
for row = reshape(dataset.rows, 1, [])
    fprintf(fid, '- `%s`: common prefix matched = `%d`; %s.\n', ...
        row.name, row.prefixMatched, row.continuationDescription);
end
