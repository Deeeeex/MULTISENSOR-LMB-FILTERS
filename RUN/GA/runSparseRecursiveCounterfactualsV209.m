function row = evaluateCase( ...
        currentCase, candidateScreen, noOpScreen, ...
        immediateDataset, returnHorizonSteps)
validatePairedScreens(candidateScreen, noOpScreen);
candidateIdx = candidateOutcomeIndex(candidateScreen);
noOpIdx = candidateOutcomeIndex(noOpScreen);
candidateOutcome = candidateScreen.outcomes(candidateIdx);
noOpOutcome = noOpScreen.outcomes(noOpIdx);
branchPage = find(candidateScreen.returnTimes == ...
    currentCase.actionTime, 1);
if isempty(branchPage)
    error('SparseRecursiveV209:MissingBranchPage', ...
        'The branch time is absent from the paired screen.');
end
prefixPages = 1:(branchPage - 1);
prefixMatched = comparePrefix( ...
    candidateOutcome, noOpOutcome, prefixPages);
if ~prefixMatched
    error('SparseRecursiveV209:PrefixDrift', ...
        'The candidate and no-op screens do not share the same prefix.');
end
windowPages = branchPage:min( ...
    branchPage + returnHorizonSteps - 1, ...
    numel(candidateScreen.returnTimes));
candidateMetrics = windowMetrics( ...
    candidateOutcome, candidateScreen.sensorGroupIds, ...
    windowPages, currentCase.receiverFormationId);
noOpMetrics = windowMetrics( ...
    noOpOutcome, noOpScreen.sensorGroupIds, ...
    windowPages, currentCase.receiverFormationId);
referenceOutcome = candidateScreen.outcomes( ...
    candidateScreen.referenceSubsetIndex);
referenceMetrics = windowMetrics( ...
    referenceOutcome, candidateScreen.sensorGroupIds, ...
    windowPages, currentCase.receiverFormationId);

row = emptyRow();
row.name = currentCase.name;
row.actionType = currentCase.actionType;
row.actionTime = currentCase.actionTime;
row.receiverFormationId = currentCase.receiverFormationId;
row.sourceId = currentCase.sourceId;
row.label = currentCase.label;
row.windowTimes = candidateScreen.returnTimes(windowPages);
row.continuationDescription = currentCase.continuationDescription;
row.candidateScreenPath = currentCase.candidateScreenPath;
row.noOpScreenPath = currentCase.noOpScreenPath;
row.prefixMatched = prefixMatched;
row.noOpMetrics = noOpMetrics;
row.candidateMetrics = candidateMetrics;
row.meanEospaGainPercent = relativeGain( ...
    noOpMetrics.meanEospa, candidateMetrics.meanEospa);
row.meanRmseGainPercent = relativeGain( ...
    noOpMetrics.meanRmse, candidateMetrics.meanRmse);
row.consensusGainPercent = relativeGain( ...
    noOpMetrics.consensusOspa, candidateMetrics.consensusOspa);
row.terminalConsensusGainPercent = relativeGain( ...
    noOpMetrics.terminalConsensusOspa, ...
    candidateMetrics.terminalConsensusOspa);
row.receiverFormationEospaGainPercent = relativeGain( ...
    noOpMetrics.receiverFormationEospa, ...
    candidateMetrics.receiverFormationEospa);
row.receiverFormationRmseGainPercent = relativeGain( ...
    noOpMetrics.receiverFormationRmse, ...
    candidateMetrics.receiverFormationRmse);
row.minimumAffectedSensorEospaGainPercent = min( ...
    relativeGainVector(noOpMetrics.receiverSensorEospa, ...
        candidateMetrics.receiverSensorEospa));
row.minimumAffectedSensorRmseGainPercent = min( ...
    relativeGainVector(noOpMetrics.receiverSensorRmse, ...
        candidateMetrics.receiverSensorRmse));
row.worstSensorEospaGainPercent = relativeGain( ...
    noOpMetrics.worstSensorEospa, ...
    candidateMetrics.worstSensorEospa);
row.worstSensorRmseGainPercent = relativeGain( ...
    noOpMetrics.worstSensorRmse, ...
    candidateMetrics.worstSensorRmse);
row.minimumFormationEospaGainPercent = min( ...
    relativeGainVector(noOpMetrics.formationEospa, ...
        candidateMetrics.formationEospa));
row.minimumFormationRmseGainPercent = min( ...
    relativeGainVector(noOpMetrics.formationRmse, ...
        candidateMetrics.formationRmse));
row.incrementalAttemptedBytes = ...
    candidateMetrics.attemptedBytes - noOpMetrics.attemptedBytes;
row.candidateStaticByteSaving = ...
    referenceMetrics.attemptedBytes - candidateMetrics.attemptedBytes;
row.candidateStaticByteSavingPercent = 100 * ...
    row.candidateStaticByteSaving / ...
        max(referenceMetrics.attemptedBytes, eps);
row.aggregateReturnPositive = ...
    row.meanEospaGainPercent > 0 && ...
    row.meanRmseGainPercent > 0 && ...
    row.consensusGainPercent >= 0 && ...
    row.candidateStaticByteSaving >= 0;
row.strictReturnPositive = row.aggregateReturnPositive && ...
    row.receiverFormationEospaGainPercent >= 0 && ...
    row.receiverFormationRmseGainPercent >= 0 && ...
    row.minimumAffectedSensorEospaGainPercent >= -1e-10 && ...
    row.minimumAffectedSensorRmseGainPercent >= -1e-10 && ...
    row.worstSensorEospaGainPercent >= -1e-10 && ...
    row.worstSensorRmseGainPercent >= -1e-10 && ...
    row.minimumFormationEospaGainPercent >= -1e-10 && ...
    row.minimumFormationRmseGainPercent >= -1e-10;
row.baseRouteImmediate = findImmediateReference( ...
    immediateDataset, currentCase);
end

function validatePairedScreens(candidateScreen, noOpScreen)
if ~strcmp(candidateScreen.presetName, noOpScreen.presetName) || ...
        candidateScreen.seed ~= noOpScreen.seed || ...
        ~isequal(candidateScreen.returnTimes, noOpScreen.returnTimes) || ...
        ~isequal(candidateScreen.sensorGroupIds, noOpScreen.sensorGroupIds)
    error('SparseRecursiveV209:ScreenDrift', ...
        'The candidate and no-op screens are not paired.');
end
end

function index = candidateOutcomeIndex(screen)
index = find(strncmp( ...
    {screen.records.actionName}, ...
    'v99-online-positive-net-', 24));
if numel(index) ~= 1
    error('SparseRecursiveV209:CandidateArm', ...
        'Each screen must contain one V99 candidate arm.');
end
end

function matched = comparePrefix(candidate, noOp, prefixPages)
if isempty(prefixPages)
    matched = true;
    return;
end
tolerance = 1e-10;
matched = maximumAbsoluteDifference( ...
        candidate.eospaBySensorTime(:, prefixPages), ...
        noOp.eospaBySensorTime(:, prefixPages)) <= tolerance && ...
    maximumAbsoluteDifference( ...
        candidate.rmseBySensorTime(:, prefixPages), ...
        noOp.rmseBySensorTime(:, prefixPages)) <= tolerance && ...
    maximumAbsoluteDifference( ...
        candidate.consensusOspaByTime(prefixPages), ...
        noOp.consensusOspaByTime(prefixPages)) <= tolerance && ...
    isequal(candidate.attemptedBytesByTime(prefixPages), ...
        noOp.attemptedBytesByTime(prefixPages));
end

function value = maximumAbsoluteDifference(first, second)
mask = isfinite(first) & isfinite(second);
if any(xor(isfinite(first(:)), isfinite(second(:))))
    value = inf;
elseif ~any(mask(:))
    value = 0;
else
    value = max(abs(first(mask) - second(mask)));
end
end

function metrics = windowMetrics( ...
        outcome, groupIds, pages, receiverFormationId)
eospa = outcome.eospaBySensorTime(:, pages);
rmse = outcome.rmseBySensorTime(:, pages);
sensorEospa = finiteMeanRows(eospa);
sensorRmse = finiteMeanRows(rmse);
formationIds = unique(reshape(groupIds, 1, []), 'stable');
formationEospa = NaN(1, numel(formationIds));
formationRmse = NaN(1, numel(formationIds));
for formationIdx = 1:numel(formationIds)
    sensorMask = groupIds == formationIds(formationIdx);
    formationEospa(formationIdx) = ...
        finiteMean(eospa(sensorMask, :));
    formationRmse(formationIdx) = ...
        finiteMean(rmse(sensorMask, :));
end
receiverMask = groupIds == receiverFormationId;
if ~any(receiverMask)
    error('SparseRecursiveV209:ReceiverFormation', ...
        'The receiver formation is absent from the screen.');
end
metrics = struct();
metrics.meanEospa = finiteMean(eospa);
metrics.meanRmse = finiteMean(rmse);
metrics.consensusOspa = finiteMean( ...
    outcome.consensusOspaByTime(pages));
metrics.terminalConsensusOspa = ...
    outcome.consensusOspaByTime(pages(end));
metrics.sensorEospa = sensorEospa;
metrics.sensorRmse = sensorRmse;
metrics.worstSensorEospa = max(sensorEospa);
metrics.worstSensorRmse = max(sensorRmse);
metrics.formationEospa = formationEospa;
metrics.formationRmse = formationRmse;
metrics.receiverFormationEospa = finiteMean( ...
    eospa(receiverMask, :));
metrics.receiverFormationRmse = finiteMean( ...
    rmse(receiverMask, :));
metrics.receiverSensorEospa = sensorEospa(receiverMask);
metrics.receiverSensorRmse = sensorRmse(receiverMask);
metrics.attemptedBytes = sum(outcome.attemptedBytesByTime(pages));
end

function means = finiteMeanRows(values)
means = NaN(size(values, 1), 1);
for rowIdx = 1:size(values, 1)
    means(rowIdx) = finiteMean(values(rowIdx, :));
end
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(abs(reference), eps);
end

function gains = relativeGainVector(reference, candidate)
gains = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function immediate = findImmediateReference(dataset, currentCase)
immediate = struct( ...
    'found', false, ...
    'meanEospaGainPercent', NaN, ...
    'meanRmseGainPercent', NaN, ...
    'consensusGainPercent', NaN, ...
    'jointAggregatePositive', false, ...
    'sameStateAsRecursiveBranch', false);
if ~strcmp(currentCase.actionType, 'supported-label-kla') || ...
        ~isfield(dataset, 'rows') || isempty(dataset.rows)
    return;
end
mask = [dataset.rows.currentTime] == currentCase.actionTime & ...
    [dataset.rows.receiverFormationId] == ...
        currentCase.receiverFormationId & ...
    [dataset.rows.sourceId] == currentCase.sourceId & ...
    arrayfun(@(row) isequal(row.label, currentCase.label), ...
        dataset.rows);
index = find(mask, 1);
if isempty(index)
    return;
end
source = dataset.rows(index);
immediate.found = true;
immediate.meanEospaGainPercent = ...
    source.meanEospaGainPercent;
immediate.meanRmseGainPercent = ...
    source.meanRmseGainPercent;
immediate.consensusGainPercent = ...
    source.consensusGainPercent;
immediate.jointAggregatePositive = ...
    source.jointAggregatePositive;
end

