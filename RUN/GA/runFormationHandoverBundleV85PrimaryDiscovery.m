function [reportPath, result] = ...
    runFormationHandoverBundleV85PrimaryDiscovery(options)
% RUNFORMATIONHANDOVERBUNDLEV85PRIMARYDISCOVERY Two-scale source gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationHandoverBundleV85Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('FormationHandoverBundleV85:DirtySource', ...
        'The V85 source discovery requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds, struct( ...
            'referenceMode', 'current-physical-tree'));
    base = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    influence = computeInfluenceAwareDecisionBreadthV66( ...
        control, state.context, state.groupIds, struct( ...
            'positiveSupportThreshold', ...
                protocol.positiveSupportThreshold, ...
            'horizonSteps', protocol.horizonSteps));
    transport = computeAlternativeTransportHeadroomV68( ...
        state.context, control, state.groupIds, protocol);
    bundle = computeFormationHandoverBundleOpportunityV85( ...
        state.context, control, transport, state.groupIds, protocol);
    projection = buildProjection( ...
        state, control, base, influence, transport, bundle, protocol);
    records(caseIdx) = makeRecord( ...
        caseInfo, bundle, projection);
    fprintf([ ...
        'V85 %s t=%d formation=%s receivers=%d net=%.3f%% ', ...
        'novelty=%.3f%% messages=%d/%d b3=%d gate=%d\n'], ...
        caseInfo.presetName, caseInfo.currentTime, ...
        mat2str(records(caseIdx).selectedFormationId), ...
        records(caseIdx).changedReceiverCount, ...
        100 * records(caseIdx).localNetFraction, ...
        100 * records(caseIdx).senderNoveltyFraction, ...
        records(caseIdx).selectedMessageCount, ...
        records(caseIdx).referenceMessageCount, ...
        records(caseIdx).rollingB3Passed, ...
        records(caseIdx).sourceGatePassed);
end

result = struct();
result.contractVersion = ...
    'formation-handover-bundle-v85-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.bothScalesSourceGatePassed = ...
    all([records.sourceGatePassed]);
result.routeExecutionAuthorized = false;
result.trackingOutcomeRead = false;
result.trackingOutcomeScoringAuthorized = ...
    result.bothScalesSourceGatePassed;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'FORMATION_HANDOVER_BUNDLE_V85_PRIMARY_DISCOVERY.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_HANDOVER_BUNDLE_V85_PRIMARY_DISCOVERY.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V85 formation handover bundle: %s\n', reportPath);
end

function projection = buildProjection( ...
        state, control, base, influence, transport, bundle, protocol)
localOptions = struct( ...
    'minimumLocalQuarantineNetFraction', ...
        protocol.minimumBundleLocalNetFraction, ...
    'minimumLocalAlternativeNetFraction', ...
        protocol.minimumBundleLocalNetFraction, ...
    'minimumLocalRobustMarginExposure', 0.10, ...
    'maximumUsefulLossToRescueRatio', ...
        protocol.maximumProtectedHarmRatio, ...
    'requireZeroSupportedDownwardCrossings', ...
        protocol.requireZeroSupportedDownwardCrossings);
local = computeReceiverDomainNormalizedOpportunityV70( ...
    base, influence, control, transport, state.groupIds, localOptions);
selectedMask = false(size(bundle.actionMask));
if ~isempty(bundle.bestFormationIndex)
    selectedMask(bundle.bestFormationIndex) = true;
end
local.alternativeTransportActionMask = selectedMask;
local.alternativeTransportActionFormationIds = ...
    local.groups(selectedMask);
local.actionableFormationMask = selectedMask;
local.actionableFormationIds = local.groups(selectedMask);
local.preferredActionByFormation = ...
    repmat({'fallback'}, 1, numel(local.groups));
local.preferredActionByFormation(selectedMask) = {'transport'};
projectionOptions = getReceiverDomainTransportProjectionV71Protocol();
projectionOptions.id = 'formation-handover-bundle-projection-v85-v1';
projection = buildReceiverDomainTransportProjectionV71( ...
    state.context, control, transport, local, state.groupIds, ...
    projectionOptions);
end

function record = makeRecord(caseInfo, bundle, projection)
record = emptyRecord();
record.presetName = caseInfo.presetName;
record.seed = caseInfo.seed;
record.currentTime = caseInfo.currentTime;
record.selectedFormationId = bundle.bestFormationId;
record.changedReceiverIndices = bundle.bestReceiverIndices;
record.changedReceiverCount = bundle.bestChangedReceiverCount;
record.changedReceiverCoverage = bundle.bestChangedReceiverCoverage;
record.localNetFraction = bundle.bestLocalNetFraction;
record.senderNoveltyFraction = ...
    bundle.bestLocalSenderNoveltyFraction;
record.actionScore = bundle.maximumActionScore;
record.referenceMessageCount = projection.referenceMessageCount;
record.selectedMessageCount = projection.selectedMessageCount;
record.messageParityPassed = ...
    projection.messageCountParityWithReference && ...
    projection.perReceiverMessageCountParityWithReference && ...
    projection.perReceiverWeightMultisetParityWithReference;
record.rollingB3Passed = ...
    all(projection.selectedRollingB3SensorPass) && ...
    all(projection.selectedRollingB3FormationPass);
record.routeConstructed = projection.routeConstructed;
record.sourceGatePassed = ...
    isfinite(record.selectedFormationId) && ...
    record.changedReceiverCount >= 2 && ...
    record.messageParityPassed && record.rollingB3Passed && ...
    record.routeConstructed;
record.projection = projection;
record.bundle = bundle;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FormationHandoverBundleV85:WriteFailed', ...
        'Could not create the V85 source report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V85 formation-level handover bundle source gate\n\n');
fprintf(fid, ['| Scale | Time | Formation | Receivers | Coverage | ', ...
    'Local net | Sender novelty | Messages | B3 | Gate |\n']);
fprintf(fid, '|:--|--:|--:|:--|--:|--:|--:|:--|:--:|:--:|\n');
for record = result.records
    fprintf(fid, ['| %s | %d | %s | `%s` | %.1f%% | %.3f%% | ', ...
        '%.3f%% | `%d/%d` | %d | %d |\n'], ...
        record.presetName, record.currentTime, ...
        mat2str(record.selectedFormationId), ...
        mat2str(record.changedReceiverIndices), ...
        100 * record.changedReceiverCoverage, ...
        100 * record.localNetFraction, ...
        100 * record.senderNoveltyFraction, ...
        record.selectedMessageCount, record.referenceMessageCount, ...
        record.rollingB3Passed, record.sourceGatePassed);
end
fprintf(fid, '\n- Both scales pass the source gate: `%d`\n', ...
    result.bothScalesSourceGatePassed);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route execution authorized: `0`\n');
fprintf(fid, '- Model training authorized: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'selectedFormationId', NaN, ...
    'changedReceiverIndices', zeros(1, 0), ...
    'changedReceiverCount', 0, ...
    'changedReceiverCoverage', 0, ...
    'localNetFraction', NaN, ...
    'senderNoveltyFraction', NaN, ...
    'actionScore', 0, ...
    'referenceMessageCount', NaN, ...
    'selectedMessageCount', NaN, ...
    'messageParityPassed', false, ...
    'rollingB3Passed', false, ...
    'routeConstructed', false, ...
    'sourceGatePassed', false, ...
    'projection', struct(), ...
    'bundle', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
