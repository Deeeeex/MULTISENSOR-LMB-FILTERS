function [reportPath, result] = ...
    runCenteredPerturbationRecoveryV77Anchors(options)
% RUNCENTEREDPERTURBATIONRECOVERYV77ANCHORS Modal KLA recovery check.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCenteredPerturbationRecoveryV77Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('CenteredRecoveryV77:DirtySource', ...
        'The V77 modal replay requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, historicalApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            alignedTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    historical = runModalReplay( ...
        state, referenceAdjacency, referenceWeights, ...
        historicalAdjacency, historicalWeights, ...
        historicalApplied, protocol);
    aligned = runModalReplay( ...
        state, referenceAdjacency, referenceWeights, ...
        alignedAdjacency, alignedWeights, alignedApplied, protocol);
    records(caseIdx) = makeCaseRecord( ...
        state, caseInfo, historical, aligned);
    fprintf('V77 %s t=%d historical=%s aligned=%s\n', ...
        caseInfo.presetName, caseInfo.currentTime, ...
        formatReplay(historical), formatReplay(aligned));
end

result = struct();
result.contractVersion = ...
    'centered-perturbation-recovery-v77-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allHistoricalCenteredRecoverySafe = all(arrayfun( ...
    @(record) record.historical.centeredRecoverySafe, records));
result.allAlignedCenteredRecoverySafe = all(arrayfun( ...
    @(record) record.aligned.centeredRecoverySafe, records));
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.futureLinkPageUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'CENTERED_PERTURBATION_RECOVERY_V77_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'CENTERED_PERTURBATION_RECOVERY_V77_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V77 centered perturbation recovery: %s\n', reportPath);
end

function replay = runModalReplay( ...
        state, referenceAdjacency, referenceWeights, ...
        candidateAdjacency, candidateWeights, appliedTriples, protocol)
referencePosteriors = state.context.localPosteriorBySensor;
candidatePosteriors = state.context.localPosteriorBySensor;
rounds = repmat(emptyRoundRecord(), 1, protocol.totalFusionRounds);
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
modeOptions = struct( ...
    'covarianceRegularization', protocol.covarianceRegularization);
for roundIdx = 1:protocol.totalFusionRounds
    [referencePosteriors, ~] = ...
        fuseLmbNetworkWithDirectedWeights( ...
            referencePosteriors, referenceAdjacency, ...
            referenceWeights, state.context.model, ...
            state.context.commConfig, state.currentTime, ...
            protocol.fusionConfig, fusionOptions);
    if roundIdx <= protocol.candidateRounds
        adjacency = candidateAdjacency;
        weights = candidateWeights;
    else
        adjacency = referenceAdjacency;
        weights = referenceWeights;
    end
    [candidatePosteriors, ~] = ...
        fuseLmbNetworkWithDirectedWeights( ...
            candidatePosteriors, adjacency, weights, ...
            state.context.model, state.context.commConfig, ...
            state.currentTime, protocol.fusionConfig, fusionOptions);
    modes = computeLmbArmPerturbationModesV77( ...
        referencePosteriors, candidatePosteriors, ...
        state.context.model, modeOptions);
    rounds(roundIdx) = makeRoundRecord(roundIdx, modes.aggregate);
end
centered = [rounds.centeredEnergy];
existenceCentered = [rounds.existenceCenteredEnergy];
spatialCentered = [rounds.spatialCenteredEnergy];
replay = struct();
replay.appliedSlotTriples = appliedTriples;
replay.rounds = rounds;
replay.commonEnergyByRound = [rounds.commonEnergy];
replay.centeredEnergyByRound = centered;
replay.existenceCenteredEnergyByRound = existenceCentered;
replay.spatialCenteredEnergyByRound = spatialCentered;
replay.centeredEnergyMonotoneNonincreasing = ...
    all(diff(centered) <= 1e-12);
replay.existenceCenteredMonotoneNonincreasing = ...
    all(diff(existenceCentered) <= 1e-12);
replay.spatialCenteredMonotoneNonincreasing = ...
    all(diff(spatialCentered) <= 1e-12);
replay.terminalCenteredContractionFraction = ...
    contraction(centered(1), centered(end));
replay.centeredRecoverySafe = ...
    ~protocol.requireMonotoneCenteredEnergyContraction || ...
        replay.centeredEnergyMonotoneNonincreasing;
replay.commonModeConstrained = false;
replay.truthUsed = false;
replay.futureMeasurementUsed = false;
end

function round = makeRoundRecord(roundIdx, aggregate)
round = emptyRoundRecord();
round.roundIndex = roundIdx;
fields = fieldnames(aggregate);
for idx = 1:numel(fields)
    fieldName = fields{idx};
    if isfield(round, fieldName)
        round.(fieldName) = aggregate.(fieldName);
    end
end
end

function value = contraction(initial, terminal)
if initial <= eps
    value = double(terminal <= eps);
else
    value = (initial - terminal) / initial;
end
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('CenteredRecoveryV77:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('CenteredRecoveryV77:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        nnz(adjacency) ~= nnz(referenceAdjacency)
    error('CenteredRecoveryV77:BudgetDrift', ...
        'Candidate replacement changed row sums or message count.');
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function record = makeCaseRecord( ...
        state, caseInfo, historical, aligned)
record = emptyCaseRecord();
record.presetName = state.presetName;
record.seed = state.seed;
record.currentTime = state.currentTime;
record.directSafeFormationIds = ...
    reshape(caseInfo.directSafeFormationIds, 1, []);
record.historical = historical;
record.aligned = aligned;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CenteredRecoveryV77:WriteFailed', ...
        'Could not create the V77 result report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V77 centered perturbation-recovery replay\n\n');
fprintf(fid, '- Common mode constrained: `0`\n');
fprintf(fid, '- Centered total energy must be monotone non-increasing: `1`\n');
fprintf(fid, '- Prediction / measurement / future link / truth: `0 / 0 / 0 / 0`\n\n');
for caseRecord = result.records
    fprintf(fid, '## %s / t=%d\n\n', ...
        caseRecord.presetName, caseRecord.currentTime);
    fprintf(fid, '- Direct-safe formations replayed: `%s`\n\n', ...
        mat2str(caseRecord.directSafeFormationIds));
    writeReplayTable(fid, 'Historical exact V71/V72 route', ...
        caseRecord.historical);
    writeReplayTable(fid, 'Prospective exact V73 route', ...
        caseRecord.aligned);
end
fprintf(fid, '## Summary\n\n');
fprintf(fid, '- All historical centered-recovery certificates pass: `%d`\n', ...
    result.allHistoricalCenteredRecoverySafe);
fprintf(fid, '- All aligned centered-recovery certificates pass: `%d`\n', ...
    result.allAlignedCenteredRecoverySafe);
fprintf(fid, '- Route executed / tracking outcome read: `0 / 0`\n');
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeReplayTable(fid, title, replay)
fprintf(fid, '### %s\n\n', title);
fprintf(fid, '- Applied slot triples: `%s`\n\n', ...
    mat2str(replay.appliedSlotTriples));
fprintf(fid, ['| Round | Common energy | Centered energy | Common fraction | ', ...
    'Existence centered | Spatial centered |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|\n');
for round = replay.rounds
    fprintf(fid, '| %d | %.9g | %.9g | %.3f%% | %.9g | %.9g |\n', ...
        round.roundIndex, round.commonEnergy, round.centeredEnergy, ...
        100 * round.commonEnergyFraction, ...
        round.existenceCenteredEnergy, round.spatialCenteredEnergy);
end
fprintf(fid, ['\n- Total / existence / spatial centered monotone: ', ...
    '`%d / %d / %d`\n', ...
    '- Terminal centered contraction: `%+.3f%%`\n', ...
    '- Centered-recovery certificate: `%d`\n\n'], ...
    replay.centeredEnergyMonotoneNonincreasing, ...
    replay.existenceCenteredMonotoneNonincreasing, ...
    replay.spatialCenteredMonotoneNonincreasing, ...
    100 * replay.terminalCenteredContractionFraction, ...
    replay.centeredRecoverySafe);
end

function text = formatReplay(replay)
text = sprintf('centered=%s common=%s safe=%d', ...
    mat2str(replay.centeredEnergyByRound, 4), ...
    mat2str(replay.commonEnergyByRound, 4), ...
    replay.centeredRecoverySafe);
end

function round = emptyRoundRecord()
round = struct( ...
    'roundIndex', NaN, ...
    'labelCount', 0, ...
    'existenceCommonEnergy', 0, ...
    'existenceCenteredEnergy', 0, ...
    'spatialCommonEnergy', 0, ...
    'spatialCenteredEnergy', 0, ...
    'commonEnergy', 0, ...
    'centeredEnergy', 0, ...
    'totalEnergy', 0, ...
    'commonEnergyFraction', 0, ...
    'centeredEnergyFraction', 0);
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'directSafeFormationIds', zeros(1, 0), ...
    'historical', struct(), ...
    'aligned', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
