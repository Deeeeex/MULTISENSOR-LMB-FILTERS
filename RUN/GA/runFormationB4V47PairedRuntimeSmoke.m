function result = runFormationB4V47PairedRuntimeSmoke()
% RUNFORMATIONB4V47PAIREDRUNTIMESMOKE Real-filter non-scoring V47 gate.

protocol = getFormationGatewayDebtV47Protocol();
if protocol.trackingOutcomeScored || ...
        protocol.trackingOutcomeAuthorized || ...
        protocol.validationClaimAllowed
    error('FormationB4V47Smoke:ProtocolDrift', ...
        'The V47 smoke boundary unexpectedly authorized outcome scoring.');
end

[model, measurements, sensorTrajectories, neighborMap, ...
    commConfig, identity] = buildFormationB4RuntimeSmokeCase();
nodeCount = model.numberOfSensors;
timeCount = model.simulationLength;
deliverySeed = 47008;
[linkUniforms, uniformMetadata] = ...
    materializePhysicalUidDirectedDeliveryUniforms( ...
        deliverySeed, identity.sensorPhysicalUids, timeCount);
commConfig.linkUniforms = linkUniforms;

arms = protocol.primaryArms;
records = repmat(emptyArm(), 1, numel(arms));
for armIdx = 1:numel(arms)
    triggerConfig = buildFormationB4V47FixedTriggerConfig( ...
        arms{armIdx}, nodeCount);
    [~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
        model, measurements, sensorTrajectories, neighborMap, ...
        commConfig, triggerConfig);
    records(armIdx) = auditArm( ...
        arms{armIdx}, diagnostics, commConfig, linkUniforms, ...
        identity, nodeCount, timeCount, protocol);
end

reference = records(1);
candidate = records(2);
commonAttempted = reference.attemptedMask & ...
    candidate.attemptedMask;
candidateSubsetOfReference = all( ...
    ~candidate.attemptedMask(:) | reference.attemptedMask(:));
pairedCommonDeliveryPassed = isequal( ...
    reference.deliveredMask(commonAttempted), ...
    candidate.deliveredMask(commonAttempted));
referenceTotal = reference.totalAttemptedMessageCount;
candidateTotal = candidate.totalAttemptedMessageCount;
exactSavingPassed = 8 * (referenceTotal - candidateTotal) == ...
    3 * referenceTotal;
if ~candidateSubsetOfReference || ~pairedCommonDeliveryPassed || ...
        ~exactSavingPassed || referenceTotal ~= 16 * nodeCount || ...
        candidateTotal ~= 10 * nodeCount
    error('FormationB4V47Smoke:PairedArmMismatch', ...
        'The V47 pair violated subset, delivery, or exact B4 counts.');
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v47-paired-runtime-smoke-v1';
payload.protocolId = protocol.id;
payload.protocolCanonicalSha256 = protocol.canonicalSha256;
payload.deliverySeed = deliverySeed;
payload.deliveryUniformContractVersion = ...
    uniformMetadata.contractVersion;
payload.deliveryUniformCanonicalTensorSha256 = ...
    uniformMetadata.canonicalTensorSha256;
payload.deliveryUniformMetadataCanonicalSha256 = ...
    uniformMetadata.canonicalSha256;
payload.physicalIdentityRegistryCanonicalSha256 = ...
    identity.canonicalSha256;
payload.sensorPhysicalUids = identity.sensorPhysicalUids;
payload.nodeCount = nodeCount;
payload.timeCount = timeCount;
payload.expectedRepairTriggeredByTime = ...
    logical([0, 0, 0, 0, 1, 1, 1, 1]);
payload.arms = records;
payload.candidateAttemptedSubsetOfReference = ...
    candidateSubsetOfReference;
payload.commonAttemptedPhysicalUidPairedDeliveryPassed = ...
    pairedCommonDeliveryPassed;
payload.commonAttemptedMessageCount = nnz(commonAttempted);
payload.referenceAttemptedMessageCount = referenceTotal;
payload.candidateAttemptedMessageCount = candidateTotal;
payload.attemptedMessageSavingFraction = ...
    (referenceTotal - candidateTotal) / referenceTotal;
payload.exactEightStepSavingFractionPassed = exactSavingPassed;
payload.candidateDeliveryHistoryContractPassed = ...
    candidate.deliveryHistoryContractPassed;
payload.candidatePosteriorDebtSignalUsed = ...
    candidate.posteriorUsedByPolicy;
payload.measurementCellsAllEmpty = ...
    all(cellfun(@isempty, measurements(:)));
payload.posteriorOutputRead = false;
payload.truthGeneratedOrRead = false;
payload.trackingOutcomeScored = false;
payload.trackingOutcomeAuthorized = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
result = payload;
result.canonicalSha256 = computeCanonicalValueSha256(payload);
fprintf(['FormationB4V47 paired runtime smoke passed: ', ...
    'reference=%d candidate=%d saving=%.1f%% sha256=%s\n'], ...
    referenceTotal, candidateTotal, ...
    100 * payload.attemptedMessageSavingFraction, ...
    result.canonicalSha256);
end

function record = auditArm(armId, diagnostics, commConfig, ...
        linkUniforms, identity, nodeCount, timeCount, protocol)
isCandidate = strcmp(armId, protocol.primaryArms{2});
if isCandidate
    quotaByPhase = diff(floor((0:protocol.period) * ...
        nodeCount / protocol.period));
    expectedCounts = repmat(nodeCount + quotaByPhase, ...
        1, timeCount / protocol.period);
    expectedContract = protocol.observableContractVersion;
    expectedProtocolId = protocol.id;
    expectedProtocolHash = protocol.canonicalSha256;
else
    expectedCounts = 2 * nodeCount * ones(1, timeCount);
    parent = getFormationCausalMinimalEditV46Protocol();
    expectedContract = ...
        'topology-policy-observable-input-v3-physical-uid';
    expectedProtocolId = parent.id;
    expectedProtocolHash = parent.canonicalSha256;
end
expectedRepair = logical([0, 0, 0, 0, 1, 1, 1, 1]);
attempted = logical(diagnostics.attempted);
delivered = logical(diagnostics.delivered);
expectedDelivered = attempted & ...
    (linkUniforms >= commConfig.pDropByEdge);
messageCounts = reshape(sum(sum(attempted, 1), 2), 1, []);
repair = logical(reshape( ...
    diagnostics.topologyPolicyRepairTriggered, 1, []));
if ~isequal(messageCounts, expectedCounts) || ...
        ~isequal(repair, expectedRepair) || ...
        ~isequal(delivered, expectedDelivered) || ...
        ~isequal(reshape( ...
            diagnostics.topologyDirectedMessageCount, 1, []), ...
            expectedCounts) || ...
        any(~diagnostics.topologyPolicyRouteAndWeightHashVerified)
    error('FormationB4V47Smoke:RuntimeMismatch', ...
        '%s violated its attempted/delivered runtime contract.', armId);
end

routeHashes = cell(1, timeCount);
weightHashes = cell(1, timeCount);
observableContractHashes = cell(1, timeCount);
deliveryContractPassed = true;
for currentTime = 1:timeCount
    policyAdjacency = logical( ...
        diagnostics.topologyActiveEdge(:, :, currentTime)');
    weights = diagnostics. ...
        topologyPolicyFusionWeightMatrix{currentTime};
    positive = weights > 1e-12;
    positive(1:nodeCount+1:end) = false;
    observable = diagnostics. ...
        topologyPolicyObservableInputContract{currentTime};
    boundaryPassed = isequal(positive, policyAdjacency) && ...
        all(abs(sum(weights, 2) - 1) <= 1e-12) && ...
        observable.enforced && observable.passed && ...
        observable.targetTruthAbsent && ...
        observable.linkUniformsAbsent && ...
        observable.futurePDropPagesAbsent && ...
        observable.physicalIdentityPresent && ...
        strcmp(observable.contractVersion, expectedContract) && ...
        strcmp(observable. ...
            physicalIdentityRegistryCanonicalSha256, ...
            identity.canonicalSha256) && ...
        ~diagnostics.topologyPolicyTruthUsed(currentTime) && ...
        ~diagnostics.topologyPolicyFutureOutcomeUsed(currentTime) && ...
        diagnostics. ...
            topologyPolicyCurrentLinkReliabilityUsed(currentTime) && ...
        strcmp(diagnostics.topologyPolicyArmId{currentTime}, armId) && ...
        strcmp(diagnostics.topologyPolicyProtocolId{currentTime}, ...
            expectedProtocolId) && ...
        strcmp(diagnostics. ...
            topologyPolicyProtocolCanonicalSha256{currentTime}, ...
            expectedProtocolHash);
    if isCandidate
        deliveryContractPassed = deliveryContractPassed && ...
            observable.deliveryHistoryPresent && ...
            observable.pastDeliveryHistoryOnly && ...
            observable.deliveryHistoryAlignedToTopologyHistory && ...
            observable.deliveryHistoryAttemptSubset && ...
            diagnostics.topologyPolicyPosteriorContentUsed(currentTime);
    else
        boundaryPassed = boundaryPassed && ...
            ~diagnostics.topologyPolicyPosteriorContentUsed(currentTime);
    end
    if ~boundaryPassed
        error('FormationB4V47Smoke:ObservableBoundary', ...
            '%s crossed its causal observable boundary.', armId);
    end
    routeHashes{currentTime} = computeCanonicalValueSha256( ...
        policyAdjacency);
    weightHashes{currentTime} = ...
        computeCanonicalValueSha256(weights);
    observableContractHashes{currentTime} = ...
        computeCanonicalValueSha256(observable);
end
if isCandidate && ~deliveryContractPassed
    error('FormationB4V47Smoke:DeliveryHistoryBoundary', ...
        'The V47 candidate did not expose its causal ACK contract.');
end

for windowEnd = protocol.period:timeCount
    rollingUnion = any(attempted(:, :, ...
        windowEnd-protocol.period+1:windowEnd), 3);
    if ~isStronglyConnected(rollingUnion)
        error('FormationB4V47Smoke:RollingWindowDisconnected', ...
            '%s has a disconnected actual rolling-B4 union.', armId);
    end
end

record = emptyArm();
record.armId = armId;
record.messageCountByTime = messageCounts;
record.repairTriggeredByTime = repair;
record.totalAttemptedMessageCount = nnz(attempted);
record.totalDeliveredMessageCount = nnz(delivered);
record.totalAttemptedPayloadBytes = sum( ...
    diagnostics.attemptedPayloadBytes(:));
record.attemptedMask = attempted;
record.deliveredMask = delivered;
record.routeCanonicalSha256ByTime = routeHashes;
record.fusionWeightCanonicalSha256ByTime = weightHashes;
record.observableContractCanonicalSha256ByTime = ...
    observableContractHashes;
record.deliveryRecomputedExactly = true;
record.deliveryHistoryContractPassed = deliveryContractPassed;
record.everyRollingB4SensorUnionStrong = true;
record.posteriorUsedByPolicy = isCandidate;
record.truthUsedByPolicy = false;
record.futureOutcomeUsedByPolicy = false;
record.realizedDeliveryUniformsUsedByPolicy = false;
record.trackingOutcomeScored = false;
record.canonicalSha256 = '';
record.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(record, 'canonicalSha256'));
end

function connected = isStronglyConnected(adjacency)
connected = reachableAll(adjacency) && reachableAll(adjacency');
end

function passed = reachableAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
passed = all(visited);
end

function value = emptyArm()
value = struct( ...
    'armId', '', ...
    'messageCountByTime', zeros(1, 0), ...
    'repairTriggeredByTime', false(1, 0), ...
    'totalAttemptedMessageCount', 0, ...
    'totalDeliveredMessageCount', 0, ...
    'totalAttemptedPayloadBytes', 0, ...
    'attemptedMask', false(0, 0, 0), ...
    'deliveredMask', false(0, 0, 0), ...
    'routeCanonicalSha256ByTime', {{}}, ...
    'fusionWeightCanonicalSha256ByTime', {{}}, ...
    'observableContractCanonicalSha256ByTime', {{}}, ...
    'deliveryRecomputedExactly', false, ...
    'deliveryHistoryContractPassed', false, ...
    'everyRollingB4SensorUnionStrong', false, ...
    'posteriorUsedByPolicy', false, ...
    'truthUsedByPolicy', false, ...
    'futureOutcomeUsedByPolicy', false, ...
    'realizedDeliveryUniformsUsedByPolicy', false, ...
    'trackingOutcomeScored', false, ...
    'canonicalSha256', '');
end
