function [reportPath, validation] = ...
    summarizeLabelSetAdaptiveDominantPayloadAwareScreenM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTPAYLOADAWARESCREENM24 Select margin.
%
% The grid and gates were registered before the runs.  A margin passes
% only when tracking, tail, communication, topology, observability and
% payload-projection checks all pass on the opened three-seed screen.
% The smallest passing registered margin is selected.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantPayloadAwareRedesignAuthorized || ...
        protocol.adaptiveDominantPayloadAwareHeldoutM24Authorized || ...
        protocol.adaptiveDominantPayloadAwareX36Authorized
    error('Payload-aware M24 screen summary is not authorized.');
end
seeds = protocol.adaptiveDominantPayloadAwareScreenSeeds;
tokens = protocol.adaptiveDominantPayloadAwareMarginTokens;
rootDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_payload_aware_screen_v2'));
rows = repmat(emptyRow(), numel(tokens), numel(seeds));
runCommit = '';
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    baseline = loadBaseline(seed, protocol);
    for tokenIdx = 1:numel(tokens)
        token = tokens(tokenIdx);
        path = findSingleEvidence( ...
            rootDirectory, token, seed);
        loaded = load(path, 'summary');
        summary = loaded.summary;
        armName = sprintf([ ...
            'adaptive-dominant-composite-balanced-', ...
            'payload-margin%03d-e05-a70'], token);
        validateSummary(summary, seed, armName, protocol);
        if isempty(runCommit)
            runCommit = summary.generationGitCommit;
        elseif ~strcmp(runCommit, summary.generationGitCommit)
            error('Payload-aware screen runs use different commits.');
        end
        candidate = findArm(summary.aggregate, armName);
        row = emptyRow();
        row.seed = seed;
        row.marginToken = token;
        row.marginFraction = token / 1000;
        row.evidencePath = path;
        row.baselineEospa = baseline.focusEospa;
        row.candidateEospa = candidate.focusEospa;
        row.gainPercent = relativeGain( ...
            row.baselineEospa, row.candidateEospa);
        row.baselineWorstEospa = ...
            baseline.focusWorstSensorEospa;
        row.candidateWorstEospa = ...
            candidate.focusWorstSensorEospa;
        row.baselineConsensusOspa = ...
            baseline.focusMapSetDisagreement;
        row.candidateConsensusOspa = ...
            candidate.focusMapSetDisagreement;
        row.baselineAttemptedBytes = ...
            baseline.focusAttemptedBytes;
        row.candidateAttemptedBytes = ...
            candidate.focusAttemptedBytes;
        row.byteDeltaPercent = 100 * ...
            (row.candidateAttemptedBytes - ...
             row.baselineAttemptedBytes) / ...
                max(row.baselineAttemptedBytes, eps);
        row.meanMessageCount = ...
            candidate.meanDirectedMessageCount;
        row.selectedSensorB3 = candidate. ...
            focusSelectedRollingB3SensorStrongFraction;
        row.selectedFormationB3 = candidate. ...
            focusSelectedRollingB3FormationStrongFraction;
        row.truthUseFraction = ...
            candidate.policyTruthUseFraction;
        row.posteriorUseFraction = ...
            candidate.policyPosteriorContentUseFraction;
        row.payloadMetadataUseFraction = candidate. ...
            policyPosteriorPayloadMetadataUseFraction;
        row.currentLinkReliabilityUseFraction = candidate. ...
            policyCurrentLinkReliabilityUseFraction;
        row.payloadConstraintFraction = candidate. ...
            policyPayloadConstraintEnforcedFraction;
        row.payloadLimitPassFraction = candidate. ...
            policyPayloadLimitPassFraction;
        row.repairRate = candidate.policyRepairRate;
        row.payloadEmergencyRate = ...
            candidate.policyPayloadEmergencyRate;
        row.topologyInfeasibleRate = ...
            candidate.focusTopologyInfeasibleRate;
        row.distinctRouteMaps = ...
            candidate.focusDistinctDirectedRouteMapCount;
        row.hardSafetyPassed = ...
            hardSafetyPassed(row, protocol);
        rows(tokenIdx, seedIdx) = row;
    end
end

marginResults = repmat(emptyMarginResult(), 1, numel(tokens));
for tokenIdx = 1:numel(tokens)
    marginRows = rows(tokenIdx, :);
    result = emptyMarginResult();
    result.marginToken = tokens(tokenIdx);
    result.marginFraction = tokens(tokenIdx) / 1000;
    result.baselineMeanEospa = ...
        mean([marginRows.baselineEospa]);
    result.candidateMeanEospa = ...
        mean([marginRows.candidateEospa]);
    result.meanGainPercent = relativeGain( ...
        result.baselineMeanEospa, ...
        result.candidateMeanEospa);
    result.positiveSeedFraction = ...
        mean([marginRows.gainPercent] > 0);
    result.aggregateWorstGainPercent = relativeGain( ...
        mean([marginRows.baselineWorstEospa]), ...
        mean([marginRows.candidateWorstEospa]));
    result.aggregateConsensusGainPercent = relativeGain( ...
        mean([marginRows.baselineConsensusOspa]), ...
        mean([marginRows.candidateConsensusOspa]));
    byteDeltas = [marginRows.byteDeltaPercent];
    result.maximumPositiveByteDeltaPercent = ...
        max([0, byteDeltas]);
    result.maximumAbsoluteByteDeltaPercent = ...
        max(abs(byteDeltas));
    result.hardSafetyPassed = ...
        all([marginRows.hardSafetyPassed]);
    result.trackingGatePassed = ...
        result.meanGainPercent >= protocol. ...
            adaptiveDominantPayloadAwareMinimumMeanGainPercent && ...
        result.positiveSeedFraction >= protocol. ...
            adaptiveDominantFullWindowMinimumPositiveSeedFraction;
    result.tailGatePassed = ...
        result.aggregateWorstGainPercent >= -1e-12 && ...
        result.aggregateConsensusGainPercent >= -1e-12;
    result.communicationGatePassed = ...
        result.maximumPositiveByteDeltaPercent <= protocol. ...
            adaptiveDominantPayloadAwareMaximumPositiveByteDeltaPercent + ...
                1e-12 && ...
        result.maximumAbsoluteByteDeltaPercent <= protocol. ...
            adaptiveDominantPayloadAwareMaximumAbsoluteByteDeltaPercent + ...
                1e-12;
    result.screenGatePassed = ...
        result.hardSafetyPassed && ...
        result.trackingGatePassed && ...
        result.tailGatePassed && ...
        result.communicationGatePassed;
    marginResults(tokenIdx) = result;
end
passingIndices = find([marginResults.screenGatePassed]);
if isempty(passingIndices)
    selectedToken = NaN;
    selectedMargin = NaN;
    screenPassed = false;
else
    [~, localIdx] = min([marginResults( ...
        passingIndices).marginFraction]);
    selectedIdx = passingIndices(localIdx);
    selectedToken = marginResults(selectedIdx).marginToken;
    selectedMargin = marginResults(selectedIdx).marginFraction;
    screenPassed = true;
end

gitState = resolveResearchGitState();
validation = struct();
validation.protocolId = protocol.id;
validation.contractVersion = ...
    protocol.adaptiveDominantPayloadAwareRoutingContractVersion;
validation.generatedAt = datestr(now, 31);
validation.generationGitCommit = gitState.commit;
validation.runGenerationGitCommit = runCommit;
validation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
validation.seeds = seeds;
validation.times = ...
    protocol.adaptiveDominantPayloadAwareScreenTimes;
validation.marginTokens = tokens;
validation.marginGrid = ...
    protocol.adaptiveDominantPayloadAwareMarginGrid;
validation.rows = rows;
validation.marginResults = marginResults;
validation.selectedMarginToken = selectedToken;
validation.selectedMarginFraction = selectedMargin;
validation.screenGatePassed = screenPassed;
validation.heldoutM24Opened = false;
validation.x36Opened = false;
validation.nextDirection = chooseNextDirection(screenPassed);
validation.evidenceBoundary = ...
    protocol.adaptiveDominantPayloadAwareEvidenceBoundary;

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(rootDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_PAYLOAD_AWARE_SCREEN_M24_V2.md');
writeReport(reportPath, validation, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
validation.reportPath = reportPath;
validation.matPath = matPath;
fprintf('Payload-aware screen summary: %s\n', reportPath);
end

function baseline = loadBaseline(seed, protocol)
seedIdx = find(protocol.trainingSeeds == seed, 1);
if isempty(seedIdx)
    error('Payload-aware screen seed is outside frozen training.');
end
path = protocol. ...
    adaptiveDominantFullWindowBaselineMatPaths{seedIdx};
expectedHash = protocol. ...
    adaptiveDominantFullWindowBaselineMatSha256{seedIdx};
if ~strcmp(computeFileSha256(path), expectedHash)
    error('Frozen payload-aware screen baseline hash mismatch.');
end
loaded = load(path, 'summary');
baseline = findArm(loaded.summary.aggregate, ...
    protocol.adaptiveDominantFullWindowReferenceArmName);
end

function path = findSingleEvidence(rootDirectory, token, seed)
matches = dir(fullfile(rootDirectory, ...
    sprintf('margin%03d', token), 'training', ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error(['Expected exactly one payload-aware MAT for ', ...
        'margin %03d seed %d.'], token, seed);
end
path = fullfile(matches.folder, matches.name);
end

function validateSummary(summary, seed, armName, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'training') || ...
        summary.options.continuationStartTime ~= ...
            protocol.adaptiveDominantPayloadAwareScreenTimes(1) || ...
        summary.options.maxTimeSteps ~= ...
            protocol.adaptiveDominantPayloadAwareScreenTimes(end) || ...
        ~any(strcmp({summary.aggregate.mode}, armName)) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Payload-aware screen provenance contract failed.');
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Payload-aware evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    abs(row.meanMessageCount - protocol. ...
        adaptiveDominantPayloadAwareExpectedMessageCount) < 1e-12 && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.payloadMetadataUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.payloadConstraintFraction == 1 && ...
    row.payloadLimitPassFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(reference, eps);
end

function direction = chooseNextDirection(passed)
if passed
    direction = ...
        'freeze-selected-margin-and-run-complete-six-seed-training-gate';
else
    direction = ...
        'stop-without-opening-development-heldout-or-X36';
end
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'marginToken', NaN, ...
    'marginFraction', NaN, ...
    'evidencePath', '', ...
    'baselineEospa', NaN, ...
    'candidateEospa', NaN, ...
    'gainPercent', NaN, ...
    'baselineWorstEospa', NaN, ...
    'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, ...
    'candidateConsensusOspa', NaN, ...
    'baselineAttemptedBytes', NaN, ...
    'candidateAttemptedBytes', NaN, ...
    'byteDeltaPercent', NaN, ...
    'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, ...
    'selectedFormationB3', NaN, ...
    'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'payloadMetadataUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'payloadConstraintFraction', NaN, ...
    'payloadLimitPassFraction', NaN, ...
    'repairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'distinctRouteMaps', NaN, ...
    'hardSafetyPassed', false);
end

function result = emptyMarginResult()
result = struct( ...
    'marginToken', NaN, ...
    'marginFraction', NaN, ...
    'baselineMeanEospa', NaN, ...
    'candidateMeanEospa', NaN, ...
    'meanGainPercent', NaN, ...
    'positiveSeedFraction', NaN, ...
    'aggregateWorstGainPercent', NaN, ...
    'aggregateConsensusGainPercent', NaN, ...
    'maximumPositiveByteDeltaPercent', NaN, ...
    'maximumAbsoluteByteDeltaPercent', NaN, ...
    'hardSafetyPassed', false, ...
    'trackingGatePassed', false, ...
    'tailGatePassed', false, ...
    'communicationGatePassed', false, ...
    'screenGatePassed', false);
end

function writeReport(path, validation, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write payload-aware M24 screen report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 payload-aware adaptive-dominant screen\n\n');
fprintf(fid, '- Contract: `%s`\n', validation.contractVersion);
fprintf(fid, '- Generated: %s\n', validation.generatedAt);
fprintf(fid, '- Run commit: `%s`\n', ...
    validation.runGenerationGitCommit);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seeds));
fprintf(fid, '- Window: `%s`\n\n', mat2str(validation.times));
fprintf(fid, ['| Margin | Seed | CCW E-OSPA | Candidate E-OSPA | ', ...
    'Gain | CCW worst | Candidate worst | CCW consensus | ', ...
    'Candidate consensus | Byte delta | Maps | Safe |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|:--:|\n']);
for tokenIdx = 1:size(validation.rows, 1)
    for seedIdx = 1:size(validation.rows, 2)
        row = validation.rows(tokenIdx, seedIdx);
        fprintf(fid, ['| %.1f%% | %d | %.6f | %.6f | %+.3f%% | ', ...
            '%.6f | %.6f | %.6f | %.6f | %+.3f%% | %.0f | %d |\n'], ...
            100 * row.marginFraction, row.seed, ...
            row.baselineEospa, row.candidateEospa, ...
            row.gainPercent, row.baselineWorstEospa, ...
            row.candidateWorstEospa, ...
            row.baselineConsensusOspa, ...
            row.candidateConsensusOspa, ...
            row.byteDeltaPercent, row.distinctRouteMaps, ...
            row.hardSafetyPassed);
    end
end
fprintf(fid, '\n## Registered grid gate\n\n');
fprintf(fid, ['| Margin | Mean gain | Positive seeds | Worst gain | ', ...
    'Consensus gain | Max +byte | Max abs. byte | Hard | Track | ', ...
    'Tail | Comm | Pass |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|', ...
    ':--:|:--:|:--:|\n']);
for result = validation.marginResults
    fprintf(fid, ['| %.1f%% | %+.3f%% | %.3f | %+.3f%% | ', ...
        '%+.3f%% | %.3f%% | %.3f%% | %d | %d | %d | %d | %d |\n'], ...
        100 * result.marginFraction, result.meanGainPercent, ...
        result.positiveSeedFraction, ...
        result.aggregateWorstGainPercent, ...
        result.aggregateConsensusGainPercent, ...
        result.maximumPositiveByteDeltaPercent, ...
        result.maximumAbsoluteByteDeltaPercent, ...
        result.hardSafetyPassed, result.trackingGatePassed, ...
        result.tailGatePassed, ...
        result.communicationGatePassed, ...
        result.screenGatePassed);
end
fprintf(fid, '\n- Mean-gain gate: `>= %.3f%%`\n', ...
    protocol.adaptiveDominantPayloadAwareMinimumMeanGainPercent);
fprintf(fid, '- Maximum positive byte delta: `<= %.3f%%`\n', ...
    protocol. ...
        adaptiveDominantPayloadAwareMaximumPositiveByteDeltaPercent);
fprintf(fid, '- Maximum absolute byte delta: `<= %.3f%%`\n', ...
    protocol. ...
        adaptiveDominantPayloadAwareMaximumAbsoluteByteDeltaPercent);
fprintf(fid, '- Screen passed: `%d`\n', ...
    validation.screenGatePassed);
fprintf(fid, '- Selected margin: `%.1f%%` (token `%03d`)\n', ...
    100 * validation.selectedMarginFraction, ...
    validation.selectedMarginToken);
fprintf(fid, '- Next: `%s`\n\n', validation.nextDirection);
fprintf(fid, '%s\n', validation.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
