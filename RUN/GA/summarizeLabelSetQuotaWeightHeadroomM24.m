function [reportPath, summary] = ...
    summarizeLabelSetQuotaWeightHeadroomM24(options)
% SUMMARIZELABELSETQUOTAWEIGHTHEADROOMM24 Gate larger residual weights.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.quotaWeightRoutingImplementationAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 quota-weight headroom summary is not authorized.');
end
states = struct( ...
    'seed', {11, 19, 23, 27}, ...
    'time', {78, 78, 78, 78}, ...
    'behavior', {'learned', 'ccw', 'ccw', 'learned'}, ...
    'behaviorAction', { ...
        'label-set-message-passing-safe-fixed-e05-a70', ...
        'fixed-counter-clockwise', ...
        'fixed-counter-clockwise', ...
        'label-set-message-passing-safe-fixed-e05-a70'});
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'quota_weight_headroom_v1'));
prior = loadPriorSummaries(options, protocol);
rows = repmat(emptyRow(), 1, numel(states));
riskMatrix = inf(numel(states), size( ...
    protocol.quotaWeightRoutingActionSequences, 1));
runCommit = '';
for stateIdx = 1:numel(states)
    state = states(stateIdx);
    path = fullfile(inputDirectory, ...
        sprintf('seed%d', state.seed), sprintf([ ...
            'label_set_causal_graph_option_h3_m24_', ...
            'seed%d_t%d_%s_source.mat'], ...
            state.seed, state.time, state.behavior));
    loaded = load(path, 'preflight');
    if ~isfield(loaded, 'preflight')
        error('Quota-weight artifact lacks preflight.');
    end
    preflight = loaded.preflight;
    validatePreflight(preflight, state, protocol);
    if isempty(runCommit)
        runCommit = preflight.generationGitCommit;
    elseif ~strcmp(runCommit, preflight.generationGitCommit)
        error('Quota-weight preflights use different source commits.');
    end
    risk = [preflight.outcomes.meanEospa];
    oldOracle = min(risk(1:2));
    [weightedOracle, bestIdx] = min(risk);
    quotaOracle = ...
        prior.quotaOracleByState(stateIdx);
    temporalOracle = ...
        prior.temporalOracleByState(stateIdx);
    combinedOracle = min(temporalOracle, weightedOracle);
    row = emptyRow();
    row.seed = state.seed;
    row.currentTime = state.time;
    row.behavior = state.behavior;
    row.artifactPath = path;
    row.oldOracleMeanEospa = oldOracle;
    row.quotaOracleMeanEospa = quotaOracle;
    row.temporalOracleMeanEospa = temporalOracle;
    row.weightedOracleMeanEospa = weightedOracle;
    row.combinedOracleMeanEospa = combinedOracle;
    row.bestWeightedAuditOption = ...
        preflight.actionSequenceNames{bestIdx};
    newActionRisk = risk(3:end);
    [row.bestNewWeightMeanEospa, newBestIdx] = ...
        min(newActionRisk);
    row.bestNewWeightOption = ...
        preflight.actionSequenceNames{newBestIdx + 2};
    row.newWeightGainVsOldOraclePercent = ...
        relativeGain(oldOracle, ...
            row.bestNewWeightMeanEospa);
    row.refreshesOldOracle = ...
        row.bestNewWeightMeanEospa < ...
            oldOracle - 1e-12;
    row.refreshesTemporalOracle = ...
        row.bestNewWeightMeanEospa < ...
            temporalOracle - 1e-12;
    row.maximumByteDeviationPercent = finiteMax(abs( ...
        preflight.attemptedByteDeviationPercent));
    row.restartEquivalencePassed = ...
        preflight.restartEquivalencePassed;
    row.safetyPassed = ...
        completedActionsSafe(preflight, protocol);
    rows(stateIdx) = row;
    riskMatrix(stateIdx, :) = risk;
end

meanOldOracle = mean([rows.oldOracleMeanEospa]);
meanWeightedOracle = mean([rows.weightedOracleMeanEospa]);
meanCombinedOracle = mean([rows.combinedOracleMeanEospa]);
meanTemporalOracle = mean([rows.temporalOracleMeanEospa]);
incrementalVsTemporalPercent = ...
    relativeGain(meanTemporalOracle, meanCombinedOracle);
hardAuditPassed = ...
    all([rows.restartEquivalencePassed]) && ...
    all([rows.safetyPassed]) && ...
    max([rows.maximumByteDeviationPercent]) <= ...
        protocol.macroActionMaximumByteDeviationPercent;
headroomPassed = ...
    incrementalVsTemporalPercent >= ...
        protocol. ...
            quotaWeightRoutingMinimumIncrementalOracleGainPercent;

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-label-set-quota-weight-headroom-summary-v1';
summary.auditContractVersion = ...
    protocol.quotaWeightRoutingAuditContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.runGenerationGitCommit = runCommit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.rows = rows;
summary.actionSequences = ...
    protocol.quotaWeightRoutingActionSequences;
summary.riskMatrix = riskMatrix;
summary.meanOldTwoOptionOracleEospa = meanOldOracle;
summary.meanWeightedAuditOracleEospa = ...
    meanWeightedOracle;
summary.meanQuotaE05OracleEospa = ...
    mean(prior.quotaOracleByState);
summary.meanTemporalOracleEospa = ...
    meanTemporalOracle;
summary.meanCombinedOracleEospa = ...
    meanCombinedOracle;
summary.incrementalGainVsTemporalOraclePercent = ...
    incrementalVsTemporalPercent;
summary.newWeightRefreshOldOracleStateCount = ...
    nnz([rows.refreshesOldOracle]);
summary.newWeightRefreshTemporalOracleStateCount = ...
    nnz([rows.refreshesTemporalOracle]);
summary.registeredHardFailureCount = ...
    nnz(~isfinite(riskMatrix));
summary.maximumByteDeviationPercent = ...
    max([rows.maximumByteDeviationPercent]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.quotaWeightHeadroomGatePassed = headroomPassed;
summary.largerResidualWeightFamilyRejected = ...
    ~hardAuditPassed || ~headroomPassed;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.nextMethodDirection = [ ...
    'sub-e05-or-nodewise-risk-calibrated-residual-weighting-', ...
    'before-any-selector-fit'];
summary.evidenceBoundary = [ ...
    'This opened-training audit evaluates persistent H=3 residual ', ...
    'weights 0.10, 0.20 and 0.25 at safe Q3/Q6 on four adversarial ', ...
    'M24 behavior states. It does not establish a deployable selector, ', ...
    'development, held-out M24 or X36 result.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = 'label_set_quota_weight_headroom_m24_v1';
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Quota-weight summary already exists. Set overwrite=true ', ...
        'only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary, protocol);
fprintf('Quota-weight summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function validatePreflight(preflight, state, protocol)
if ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.auditMode, ...
            'quota-weight-headroom') || ...
        ~strcmp(preflight.auditContractVersion, ...
            protocol.quotaWeightRoutingAuditContractVersion) || ...
        preflight.seed ~= state.seed || ...
        preflight.currentTime ~= state.time || ...
        ~strcmp(preflight.sourceBehaviorAction, ...
            state.behaviorAction) || ...
        ~isequal(preflight.actionSequences, ...
            protocol.quotaWeightRoutingActionSequences) || ...
        preflight.exploratoryActionSubsetUsed || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        preflight.registeredProjectionFailureCount ~= 0 || ...
        ~preflight.allRegisteredActionsFeasible || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || ...
        preflight.x36Opened
    error('Quota-weight preflight violates the frozen contract.');
end
end

function passed = completedActionsSafe(preflight, protocol)
outcomes = preflight.outcomes;
passed = ~preflight.runtimePolicyUsesTruth && ...
    all([outcomes.executionCompleted]) && ...
    ~any([outcomes.hardFailure]) && ...
    all([outcomes.repairCount] == 0) && ...
    all([outcomes.payloadEmergencyCount] == 0) && ...
    all([outcomes.infeasibleCount] == 0) && ...
    all(arrayfun(@(outcome) ...
        outcome.firstActionExact && ...
        all(outcome.messageCounts == ...
            protocol.quotaWeightRoutingExpectedMessageCount) && ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass), outcomes));
end

function prior = loadPriorSummaries(options, protocol)
defaultRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1');
quotaPath = getField(options, ...
    'quotaSummaryPath', fullfile(defaultRoot, ...
        'quota_adaptive_headroom_v1', 'summary', ...
        'label_set_quota_adaptive_headroom_m24_v1.mat'));
temporalPath = getField(options, ...
    'temporalSummaryPath', fullfile(defaultRoot, ...
        'diverse_temporal_upper_bound_v1', 'summary', ...
        'label_set_diverse_temporal_upper_bound_m24_v1.mat'));
quotaLoaded = load(quotaPath, 'summary');
temporalLoaded = load(temporalPath, 'summary');
if ~isfield(quotaLoaded, 'summary') || ...
        ~isfield(temporalLoaded, 'summary') || ...
        ~strcmp(quotaLoaded.summary.protocolId, protocol.id) || ...
        ~strcmp(temporalLoaded.summary.protocolId, protocol.id) || ...
        quotaLoaded.summary.developmentOpened || ...
        quotaLoaded.summary.heldoutM24Opened || ...
        quotaLoaded.summary.x36Opened || ...
        temporalLoaded.summary.developmentOpened || ...
        temporalLoaded.summary.heldoutM24Opened || ...
        temporalLoaded.summary.x36Opened
    error('Prior action-space summaries violate the boundary.');
end
prior = struct( ...
    'quotaOracleByState', ...
        [quotaLoaded.summary.rows.quotaOracleMeanEospa], ...
    'temporalOracleByState', ...
        [temporalLoaded.summary.rows.temporalOracleMeanEospa]);
end

function writeReport(path, summary, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write quota-weight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 quota-weight H=3 headroom audit\n\n');
fprintf(fid, [ ...
    '- Mean old / larger-weight / Q-e05 / temporal / combined ', ...
    'oracle E-OSPA: `%.6f / %.6f / %.6f / %.6f / %.6f`\n'], ...
    summary.meanOldTwoOptionOracleEospa, ...
    summary.meanWeightedAuditOracleEospa, ...
    summary.meanQuotaE05OracleEospa, ...
    summary.meanTemporalOracleEospa, ...
    summary.meanCombinedOracleEospa);
fprintf(fid, [ ...
    '- Incremental vs temporal oracle: `%+.3f%%` ', ...
    '(gate `%.3f%%`)\n'], ...
    summary.incrementalGainVsTemporalOraclePercent, ...
    protocol. ...
        quotaWeightRoutingMinimumIncrementalOracleGainPercent);
fprintf(fid, '- New-weight refresh old / temporal states: `%d / %d`\n', ...
    summary.newWeightRefreshOldOracleStateCount, ...
    summary.newWeightRefreshTemporalOracleStateCount);
fprintf(fid, '- Registered hard failures: `%d`\n', ...
    summary.registeredHardFailureCount);
fprintf(fid, '- Hard audit / headroom gates: `%d / %d`\n\n', ...
    summary.hardAuditGatesPassed, ...
    summary.quotaWeightHeadroomGatePassed);
fprintf(fid, [ ...
    '| Seed | Source | Old | Q-e05 | Temporal | Best new weight | ', ...
    'New-weight E-OSPA | Gain vs old | Safe |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|--:|:--|--:|--:|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, [ ...
        '| %d | %s | %.6f | %.6f | %.6f | `%s` | %.6f | ', ...
        '%+.3f%% | %d |\n'], ...
        row.seed, row.behavior, ...
        row.oldOracleMeanEospa, ...
        row.quotaOracleMeanEospa, ...
        row.temporalOracleMeanEospa, ...
        row.bestNewWeightOption, ...
        row.bestNewWeightMeanEospa, ...
        row.newWeightGainVsOldOraclePercent, ...
        row.safetyPassed);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, [ ...
    'The larger residual-weight family is `%s`. The next opened ', ...
    'training-only method direction is `%s`.\n\n'], ...
    decisionText(summary.largerResidualWeightFamilyRejected), ...
    summary.nextMethodDirection);
fprintf(fid, '## Boundary\n\n%s\n', summary.evidenceBoundary);
end

function text = decisionText(rejected)
if rejected
    text = 'rejected';
else
    text = 'accepted for selector fitting';
end
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = finiteMax(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behavior', '', ...
    'artifactPath', '', ...
    'oldOracleMeanEospa', NaN, ...
    'quotaOracleMeanEospa', NaN, ...
    'temporalOracleMeanEospa', NaN, ...
    'weightedOracleMeanEospa', NaN, ...
    'combinedOracleMeanEospa', NaN, ...
    'bestWeightedAuditOption', '', ...
    'bestNewWeightMeanEospa', NaN, ...
    'bestNewWeightOption', '', ...
    'newWeightGainVsOldOraclePercent', NaN, ...
    'refreshesOldOracle', false, ...
    'refreshesTemporalOracle', false, ...
    'maximumByteDeviationPercent', NaN, ...
    'restartEquivalencePassed', false, ...
    'safetyPassed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
