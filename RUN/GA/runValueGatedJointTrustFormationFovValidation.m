function [reportPath, summary] = ...
    runValueGatedJointTrustFormationFovValidation( ...
        presetName, seed, options)
% RUNVALUEGATEDJOINTTRUSTFORMATIONFOVVALIDATION Open one frozen pair.

if nargin < 1 || isempty(presetName) || nargin < 2 || isempty(seed)
    error('An explicitly registered formation-FoV preset and seed are required.');
end
if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
verifyValueGatedJointTrustDevelopmentGate(protocol);
scenarioConfig = buildDynamicTopologyScenarioConfig(presetName);
caseDetails = resolveValueGatedFormationFovValidationCase( ...
    protocol, presetName, seed, scenarioConfig);

gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error(['Formation-FoV tracking validation requires a clean ', ...
        'tracked worktree with no untracked MATLAB source files.']);
end

rootDirectory = getField(options, 'outputDirectory', ...
    protocol.valueGatedFormationFovValidationRoot);
sceneDirectory = fullfile(rootDirectory, presetName);
seedDirectory = fullfile(sceneDirectory, sprintf('seed%d', seed));
if completedEvidenceExists(seedDirectory)
    error(['Formation-FoV tracking evidence already exists for ', ...
        '%s seed %d; refusing to overwrite it.'], presetName, seed);
end
cacheDirectory = getField(options, 'behaviorCacheDirectory', ...
    fullfile(rootDirectory, 'cache'));
window = caseDetails.window;
screenOptions = struct( ...
    'maxTimeSteps', window(2), ...
    'continuationStartTime', window(1), ...
    'armNames', {{ ...
        protocol.valueGatedFormationFovValidationReferenceArmName, ...
        protocol.valueGatedFormationFovValidationCandidateArmName}}, ...
    'writeReport', true, ...
    'outputDirectory', seedDirectory, ...
    'behaviorCacheDirectory', cacheDirectory, ...
    'generateMissingBehaviorCache', true, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'minimumPracticalTrackingGainPercent', protocol. ...
        valueGatedFormationFovValidationMinimumMeanGainPercent, ...
    'evidenceSplit', protocol. ...
        valueGatedFormationFovValidationEvidenceSplit);
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    presetName, seed, screenOptions);
end

function exists = completedEvidenceExists(seedDirectory)
exists = false;
if exist(seedDirectory, 'dir') ~= 7
    return;
end
exists = ~isempty(dir(fullfile(seedDirectory, '*.mat'))) || ...
    ~isempty(dir(fullfile(seedDirectory, '*.md')));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
