function result = runFormationB4V48LaggedWindowStructuralProbe(options)
% RUNFORMATIONB4V48LAGGEDWINDOWSTRUCTURALPROBE
% Plan from t-1, then score the actual current-page-repaired t:t+3 route.

if nargin < 1 || isempty(options)
    options = struct();
end
allowed = {'presets', 'seeds', 'maximumCoordinateSweeps'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowed))
    error('FormationB4V48LaggedProbe:InvalidOptions', ...
        'The lagged-window options are malformed.');
end
presets = getField(options, 'presets', { ...
    'm24-formation-fov', 'x36-formation-fov'});
seeds = reshape(getField(options, 'seeds', 41), 1, []);
maximumSweeps = getField(options, 'maximumCoordinateSweeps', 2);
if ~iscell(presets) || isempty(presets) || ...
        ~isnumeric(seeds) || isempty(seeds) || ...
        any(~isfinite(seeds)) || any(seeds ~= round(seeds)) || ...
        ~isscalar(maximumSweeps) || ~isfinite(maximumSweeps) || ...
        maximumSweeps < 0 || maximumSweeps ~= round(maximumSweeps)
    error('FormationB4V48LaggedProbe:InvalidOptions', ...
        'A lagged-window option is invalid.');
end

caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        fprintf('V48 lagged window %d/%d: %s seed=%d\n', ...
            cursor, caseCount, presets{presetIdx}, seeds(seedIdx));
        cases(cursor) = buildCase(presets{presetIdx}, ...
            seeds(seedIdx), maximumSweeps);
    end
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v48-lagged-window-structural-probe-v1';
payload.presets = presets;
payload.seeds = seeds;
payload.maximumCoordinateSweeps = maximumSweeps;
payload.cases = cases;
payload.caseCount = caseCount;
payload.allCandidateSamePosteriorMessageBudget = ...
    all([cases.candidateSamePosteriorMessageBudget]);
payload.allCandidateSensorUnionStrong = ...
    all([cases.candidateSensorUnionStrong]);
payload.allCandidateFormationUnionStrong = ...
    all([cases.candidateFormationUnionStrong]);
payload.realizedImprovementCaseCount = nnz( ...
    [cases.realizedRelativeSquaredFactorImprovementVsCausalSync] > 1e-6);
payload.posthocBestSyncImprovementCaseCount = nnz( ...
    [cases.realizedRelativeSquaredFactorImprovementVsPosthocBestSync] ...
        > 1e-6);
payload.allRealizedNoWorseThanCausalSync = all( ...
    [cases.candidateRealizedSquaredFactor] <= ...
        [cases.causalSyncRealizedSquaredFactor] + 1e-12);
payload.allRealizedNoWorseThanPosthocBestSync = all( ...
    [cases.candidateRealizedSquaredFactor] <= ...
        [cases.posthocBestSyncRealizedSquaredFactor] + 1e-12);
payload.planningSnapshotLag = 1;
payload.currentPageRepairExecuted = true;
payload.posteriorUsed = false;
payload.truthUsed = false;
payload.measurementUsed = false;
payload.futurePageUsedByPolicy = false;
payload.realizedDeliveryUniformsUsed = false;
payload.trackingOutcomeScored = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
result = payload;
fprintf(['V48 lagged probe complete: improved=%d/%d ', ...
    'noWorseCausal=%d noWorsePosthoc=%d sha256=%s\n'], ...
    result.realizedImprovementCaseCount, caseCount, ...
    result.allRealizedNoWorseThanCausalSync, ...
    result.allRealizedNoWorseThanPosthocBestSync, ...
    result.canonicalSha256);
end

function value = buildCase(presetName, seed, maximumSweeps)
rng(seed, 'twister');
config = buildDynamicTopologyScenarioConfig(presetName);
[sensorTrajectories, trajectoryMetadata] = ...
    generateMultiFormationTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensorTrajectories);
[pDropByEdge, ~] = buildDynamicTopologyLinkSchedule(config, graph);
identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
if ~isequal(identity.sensorPhysicalUids, ...
        trajectoryMetadata.sensorPhysicalUids) || ...
        ~strcmp(identity.canonicalSha256, ...
            trajectoryMetadata.physicalIdentityRegistryCanonicalSha256)
    error('FormationB4V48LaggedProbe:IdentityDrift', ...
        'The materialized physical identity drifted.');
end
registeredBase = FormationB4V45BuildCausalRegisteredBaseGraph( ...
    config.formationBackboneMode, config.sensorGroupIds, ...
    identity.sensorPhysicalUids, ...
    identity.formationPhysicalUidsBySensor, ...
    graph.positions(:, :, 1), graph.physicalAdjacency(:, :, 1));

windowStart = resolveWindowStart(config.focusWindow);
planTime = windowStart - 1;
if planTime < 1 || windowStart + 3 > config.simulationLength
    error('FormationB4V48LaggedProbe:WindowOutsideEpisode', ...
        'The registered focus start cannot support a lagged B4 probe.');
end
planSnapshot = buildFormationB4V48CurrentReferenceSnapshot( ...
    config, identity, registeredBase.baseAdjacency, ...
    graph.positions(:, :, planTime), ...
    graph.physicalAdjacency(:, :, planTime), ...
    pDropByEdge(:, :, planTime), planTime);
[~, ~, plan] = buildFormationB4V48ContractionOptimizedSchedule( ...
    planSnapshot.graphOnlyContext, planSnapshot.reference, ...
    struct('maximumCoordinateSweeps', maximumSweeps, ...
        'minimumRelativeImprovementVsBestSynchronized', 0));

nodeCount = config.numberOfSensors;
candidateAdjacency = false(nodeCount, nodeCount, 4);
candidateWeights = zeros(nodeCount, nodeCount, 4);
syncAdjacency = false(nodeCount, nodeCount, 4, 4);
syncWeights = zeros(nodeCount, nodeCount, 4, 4);
reliability = zeros(nodeCount, nodeCount, 4);
referenceHashes = cell(1, 4);
residualSenderChangeCount = 0;
previousResidual = [];
phaseByArray = restorePhysicalValues( ...
    plan.sensorPhysicalUids, plan.selectedPhaseByPhysicalUid, ...
    identity.sensorPhysicalUids);
for phase = 1:4
    currentTime = windowStart + phase - 1;
    snapshot = buildFormationB4V48CurrentReferenceSnapshot( ...
        config, identity, registeredBase.baseAdjacency, ...
        graph.positions(:, :, currentTime), ...
        graph.physicalAdjacency(:, :, currentTime), ...
        pDropByEdge(:, :, currentTime), currentTime);
    referenceHashes{phase} = ...
        snapshot.referencePhysicalUidCanonicalSha256;
    dominant = snapshot.reference.dominantAdjacency;
    residual = snapshot.reference.residualAdjacency;
    if ~isempty(previousResidual)
        residualSenderChangeCount = residualSenderChangeCount + ...
            nnz(any(residual ~= previousResidual, 2));
    end
    previousResidual = residual;
    activeCandidateRows = reshape(phaseByArray == phase, [], 1);
    activeCandidateResidual = residual & ...
        repmat(activeCandidateRows, 1, nodeCount);
    candidateAdjacency(:, :, phase) = ...
        dominant | activeCandidateResidual;
    candidateWeights(:, :, phase) = buildWeights( ...
        dominant, activeCandidateResidual);

    for syncPulsePhase = 1:4
        activeSyncResidual = false(nodeCount);
        if phase == syncPulsePhase
            activeSyncResidual = residual;
        end
        syncAdjacency(:, :, phase, syncPulsePhase) = ...
            dominant | activeSyncResidual;
        syncWeights(:, :, phase, syncPulsePhase) = ...
            buildWeights(dominant, activeSyncResidual);
    end
    reliability(:, :, phase) = ...
        1 - pDropByEdge(:, :, currentTime)';
end

certificateOptions = struct( ...
    'missingNeighborWeightMode', 'renormalize', ...
    'maximumIncomingCount', 2);
candidateCertificate = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        candidateAdjacency, candidateWeights, reliability, ...
        certificateOptions);
candidateFactor = candidateCertificate. ...
    worstCaseExpectedSquaredContractionFactor;
syncFactors = nan(1, 4);
for syncPulsePhase = 1:4
    syncCertificate = ...
        computeReliableKlaWindowMeanSquareContractionCertificate( ...
            syncAdjacency(:, :, :, syncPulsePhase), ...
            syncWeights(:, :, :, syncPulsePhase), ...
            reliability, certificateOptions);
    syncFactors(syncPulsePhase) = syncCertificate. ...
        worstCaseExpectedSquaredContractionFactor;
end
causalSyncPhase = plan.bestSynchronizedPulsePhase;
causalSyncFactor = syncFactors(causalSyncPhase);
[posthocBestSyncFactor, posthocBestSyncPhase] = min(syncFactors);
candidateFormation = collapseToFormations( ...
    candidateAdjacency, identity.formationPhysicalUidsBySensor);
controlCost = estimateFormationB4V48ScheduleControlPlaneCost( ...
    nodeCount, config.formationCount, 1);

value = emptyCase();
value.caseId = sprintf('%s__seed%d__t%d__lagged-b4', ...
    presetName, seed, windowStart);
value.presetName = presetName;
value.seed = seed;
value.nodeCount = nodeCount;
value.formationCount = config.formationCount;
value.planTime = planTime;
value.executionTimes = windowStart:(windowStart + 3);
value.planCanonicalSha256 = plan.canonicalSha256;
value.referencePhysicalUidCanonicalSha256ByPhase = referenceHashes;
value.referenceChangedWithinWindow = ...
    numel(unique(referenceHashes)) > 1;
value.residualSenderChangeCount = residualSenderChangeCount;
value.plannedBestSyncSquaredFactor = ...
    plan.bestSynchronizedB4SquaredFactor;
value.plannedCandidateSquaredFactor = plan.selectedSquaredFactor;
value.plannedRelativeSquaredFactorImprovement = ...
    plan.relativeSquaredFactorImprovementVsBestSynchronized;
value.causalSyncPulsePhase = causalSyncPhase;
value.causalSyncRealizedSquaredFactor = causalSyncFactor;
value.posthocBestSyncPulsePhase = posthocBestSyncPhase;
value.posthocSyncRealizedSquaredFactorByPulsePhase = syncFactors;
value.posthocBestSyncRealizedSquaredFactor = posthocBestSyncFactor;
value.candidateRealizedSquaredFactor = candidateFactor;
value.realizedRelativeSquaredFactorImprovementVsCausalSync = ...
    safeRelativeImprovement(causalSyncFactor, candidateFactor);
value.realizedRelativeSquaredFactorImprovementVsPosthocBestSync = ...
    safeRelativeImprovement(posthocBestSyncFactor, candidateFactor);
value.syncMessageCountByPhase = reshape(sum(sum( ...
    syncAdjacency(:, :, :, causalSyncPhase), 1), 2), 1, []);
value.candidateMessageCountByPhase = reshape(sum(sum( ...
    candidateAdjacency, 1), 2), 1, []);
value.candidateSamePosteriorMessageBudget = ...
    sum(value.syncMessageCountByPhase) == 5 * nodeCount && ...
    sum(value.candidateMessageCountByPhase) == 5 * nodeCount;
value.candidateSensorUnionStrong = ...
    isStronglyConnected(any(candidateAdjacency, 3));
value.candidateFormationUnionStrong = ...
    isStronglyConnected(any(candidateFormation, 3));
value.idealizedControlLowerBoundBytes = ...
    controlCost.attemptedControlBytes;
value.controlExecutionImplemented = false;
value.sameTotalByteClaimAllowed = false;
value.posteriorUsed = false;
value.truthUsed = false;
value.measurementUsed = false;
value.futurePageUsedByPolicy = false;
value.trackingOutcomeScored = false;
value.developmentEvidenceOnly = true;
value.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(value, 'canonicalSha256'));
fprintf(['  planGain=%+.3f%% causalGain=%+.3f%% ', ...
    'posthocGain=%+.3f%% syncPhase=%d/%d ', ...
    'routeChanged=%d senderChanges=%d messages=%s/%s\n'], ...
    100 * value.plannedRelativeSquaredFactorImprovement, ...
    100 * value.realizedRelativeSquaredFactorImprovementVsCausalSync, ...
    100 * value.realizedRelativeSquaredFactorImprovementVsPosthocBestSync, ...
    value.causalSyncPulsePhase, value.posthocBestSyncPulsePhase, ...
    value.referenceChangedWithinWindow, ...
    value.residualSenderChangeCount, ...
    mat2str(value.candidateMessageCountByPhase), ...
    mat2str(value.syncMessageCountByPhase));
end

function weights = buildWeights(dominant, activeResidual)
nodeCount = size(dominant, 1);
weights = zeros(nodeCount);
weights(dominant) = 0.70;
weights(activeResidual) = 0.20;
weights(1:nodeCount+1:end) = 1 - sum(weights, 2)';
end

function values = restorePhysicalValues(sortedUids, sortedValues, uids)
values = nan(1, numel(uids));
for idx = 1:numel(uids)
    match = find(sortedUids == uids(idx));
    if numel(match) ~= 1
        error('FormationB4V48LaggedProbe:PhysicalIdentityDrift', ...
            'A sensor physical UID is absent or duplicated.');
    end
    values(idx) = sortedValues(match);
end
end

function startTime = resolveWindowStart(focusWindow)
focus = reshape(focusWindow, 1, []);
if isempty(focus) || any(~isfinite(focus))
    error('FormationB4V48LaggedProbe:InvalidFocusWindow', ...
        'The scene focus window is invalid.');
end
startTime = round(focus(1));
end

function pages = collapseToFormations(sensorPages, formationUids)
uids = sort(unique(formationUids));
pages = false(numel(uids), numel(uids), size(sensorPages, 3));
for timeIdx = 1:size(sensorPages, 3)
    for receiverIdx = 1:numel(uids)
        receivers = formationUids == uids(receiverIdx);
        for senderIdx = 1:numel(uids)
            senders = formationUids == uids(senderIdx);
            pages(receiverIdx, senderIdx, timeIdx) = any(any( ...
                sensorPages(receivers, senders, timeIdx)));
        end
    end
end
end

function passed = isStronglyConnected(adjacency)
senderAdjacency = logical(adjacency');
passed = reachableAll(senderAdjacency) && ...
    reachableAll(senderAdjacency');
end

function passed = reachableAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
passed = all(visited);
end

function value = safeRelativeImprovement(reference, candidate)
if reference > 0
    value = (reference - candidate) / reference;
elseif candidate == 0
    value = 0;
else
    value = -inf;
end
end

