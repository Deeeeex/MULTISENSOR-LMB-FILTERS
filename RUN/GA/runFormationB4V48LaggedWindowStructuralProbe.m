    'posthocBestSyncRealizedSquaredFactor', NaN, ...
    'candidateRealizedSquaredFactor', NaN, ...
    'realizedRelativeSquaredFactorImprovementVsCausalSync', NaN, ...
    'realizedRelativeSquaredFactorImprovementVsPosthocBestSync', NaN, ...
    'syncMessageCountByPhase', zeros(1, 0), ...
    'candidateMessageCountByPhase', zeros(1, 0), ...
    'candidateSamePosteriorMessageBudget', false, ...
    'candidateSensorUnionStrong', false, ...
