function [reportPath, result] = ...
    runTrackingAlignedRoutingLeverageHeadroomV59Batch(options)
% RUNTRACKINGALIGNEDROUTINGLEVERAGEHEADROOMV59BATCH Three fresh H=3 states.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getTrackingAlignedRoutingLeverageHeadroomV59Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('TrackingAlignedV59:DirtySource', ...
        'V59 event headroom requires a clean source checkout.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

stateResults = repmat(emptyStateResult(), 1, numel(protocol.eventTimes));
for timeIdx = 1:numel(protocol.eventTimes)
    currentTime = protocol.eventTimes(timeIdx);
    screenDirectory = fullfile( ...
        outputRoot, sprintf('t%d', currentTime));
    screenOptions = struct( ...
        'horizonSteps', protocol.horizonSteps, ...
        'interventionDurationSteps', ...
            protocol.interventionDurationSteps, ...
        'filterSeedOffset', protocol.filterSeedOffset, ...
        'cacheRoot', protocol.cacheRoot, ...
        'interventionBankType', protocol.interventionBankType, ...
        'trackingAlignedExecutionProfile', ...
            'v59-routing-leverage-headroom', ...
        'outputDirectory', screenDirectory, ...
        'writeReport', true);
    [screenReportPath, screen] = ...
        runFormationModeOpenedReturnScreen( ...
            protocol.presetName, protocol.seed, currentTime, ...
            screenOptions);
    stateResults(timeIdx) = summarizeState( ...
        screen, screenReportPath, protocol);
    fprintf([ ...
        'V59 state t=%d safe=%d strict=%d best=%+.6f%% ', ...
        'action=%s\n'], ...
        currentTime, stateResults(timeIdx).safeActionCount, ...
        stateResults(timeIdx).strictCandidateCount, ...
        stateResults(timeIdx).bestStrictMeanGainPercent, ...
        stateResults(timeIdx).bestStrictActionName);
end

bestGain = [stateResults.bestStrictMeanGainPercent];
strongMask = [stateResults.strongState];
result = struct();
result.contractVersion = ...
    'tracking-aligned-routing-leverage-headroom-v59-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.stateResults = stateResults;
result.bestStrictMeanGainPercentByState = bestGain;
result.meanBestStrictGainPercent = mean(bestGain);
result.minimumBestStrictGainPercent = min(bestGain);
result.strongStateMask = strongMask;
result.strongStateCount = nnz(strongMask);
result.meanGainGatePassed = ...
    result.meanBestStrictGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12;
result.majorityStrongGatePassed = ...
    result.strongStateCount >= 2;
result.formationLevelHeadroomGatePassed = ...
    result.meanGainGatePassed && result.majorityStrongGatePassed;
result.receiverLabelActionRequired = ...
    ~result.formationLevelHeadroomGatePassed;
result.trackingOutcomeScored = true;
result.x36OutcomeOpened = false;
result.modelTrainingAuthorized = false;
result.openedDevelopmentEvidenceOnly = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'TRACKING_ALIGNED_ROUTING_LEVERAGE_HEADROOM_V59_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'TRACKING_ALIGNED_ROUTING_LEVERAGE_HEADROOM_V59_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V59 event-headroom result: %s\n', reportPath);
end

function state = summarizeState(screen, reportPath, protocol)
records = screen.records;
referenceIdx = screen.referenceSubsetIndex;
candidateMask = true(1, numel(records));
candidateMask(referenceIdx) = false;
strictMask = candidateMask & ...
    [records.posteriorProxyAllowed] & ...
    [records.selectedB3Passed] & ...
    [records.minimumFormationGainPercent] >= ...
        protocol.minimumFormationGainPercent - 1e-12 & ...
    [records.worstGainPercent] >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 & ...
    [records.consensusGainPercent] >= ...
        protocol.minimumConsensusGainPercent - 1e-12 & ...
    [records.terminalConsensusGainPercent] >= ...
        protocol.minimumConsensusGainPercent - 1e-12 & ...
    [records.attemptedByteSavingPercent] >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12;
candidateIndices = find(strictMask);
if isempty(candidateIndices)
    bestIdx = referenceIdx;
    bestGain = 0;
else
    [bestGain, localIdx] = max( ...
        [records(candidateIndices).meanGainPercent]);
    bestIdx = candidateIndices(localIdx);
end

state = emptyStateResult();
state.currentTime = screen.currentTime;
state.returnTimes = screen.returnTimes;
state.safeActionCount = numel(records);
state.strictCandidateCount = nnz(strictMask);
state.bestStrictRecordIndex = bestIdx;
state.bestStrictActionName = records(bestIdx).actionName;
state.bestStrictMeanGainPercent = bestGain;
state.bestStrictWorstGainPercent = records(bestIdx).worstGainPercent;
state.bestStrictMinimumFormationGainPercent = ...
    records(bestIdx).minimumFormationGainPercent;
state.bestStrictConsensusGainPercent = ...
    records(bestIdx).consensusGainPercent;
state.bestStrictTerminalConsensusGainPercent = ...
    records(bestIdx).terminalConsensusGainPercent;
state.bestStrictAttemptedByteSavingPercent = ...
    records(bestIdx).attemptedByteSavingPercent;
state.strongState = bestGain >= ...
    protocol.minimumMeanGainPercent - 1e-12;
state.screenReportPath = reportPath;
state.screenMatPath = screen.matPath;
end

function state = emptyStateResult()
state = struct( ...
    'currentTime', NaN, ...
    'returnTimes', zeros(1, 0), ...
    'safeActionCount', 0, ...
    'strictCandidateCount', 0, ...
    'bestStrictRecordIndex', NaN, ...
    'bestStrictActionName', '', ...
    'bestStrictMeanGainPercent', 0, ...
    'bestStrictWorstGainPercent', 0, ...
    'bestStrictMinimumFormationGainPercent', 0, ...
    'bestStrictConsensusGainPercent', 0, ...
    'bestStrictTerminalConsensusGainPercent', 0, ...
    'bestStrictAttemptedByteSavingPercent', 0, ...
    'strongState', false, ...
    'screenReportPath', '', ...
    'screenMatPath', '');
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('TrackingAlignedV59:WriteFailed', ...
        'Could not create the V59 event-headroom report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V59 event-conditioned formation headroom\n\n');
fprintf(fid, '| Time | Safe actions | Strict candidates | Best action | Mean tracking gain | Worst sensor | Minimum formation | Window consensus | Terminal consensus | Attempted-byte saving | Strong |\n');
fprintf(fid, '|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|:--:|\n');
for state = result.stateResults
    fprintf(fid, '| %d | %d | %d | `%s` | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n', ...
        state.currentTime, state.safeActionCount, ...
        state.strictCandidateCount, state.bestStrictActionName, ...
        state.bestStrictMeanGainPercent, ...
        state.bestStrictWorstGainPercent, ...
        state.bestStrictMinimumFormationGainPercent, ...
        state.bestStrictConsensusGainPercent, ...
        state.bestStrictTerminalConsensusGainPercent, ...
        state.bestStrictAttemptedByteSavingPercent, ...
        state.strongState);
end
fprintf(fid, '\n- Mean best strict gain: `%+.3f%%`\n', ...
    result.meanBestStrictGainPercent);
fprintf(fid, '- Minimum state gain: `%+.3f%%`\n', ...
    result.minimumBestStrictGainPercent);
fprintf(fid, '- Strong states: `%d / %d`\n', ...
    result.strongStateCount, numel(result.stateResults));
fprintf(fid, '- Formation-level headroom gate: `%d`\n', ...
    result.formationLevelHeadroomGatePassed);
fprintf(fid, '- Receiver-label action required: `%d`\n\n', ...
    result.receiverLabelActionRequired);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
