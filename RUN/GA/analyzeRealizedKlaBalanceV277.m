function [reportPath, result] = analyzeRealizedKlaBalanceV277()
% ANALYZEREALIZEDKLABALANCEV277 Replay packet-level weights, without filtering.
% Matrix rows are receivers; linkUniforms and pDrop rows are senders.
% Delivered empty payloads and label-dependent censoring are not simulated.

presets = {'m24-formation-fov-temporal-coupled-formation-braid', ...
    'x36-formation-fov-temporal-coupled-formation-braid'};
records = struct([]);
for sceneIdx = 1:numel(presets)
    inputs = generateDynamicTopologyScenarioInputs(presets{sceneIdx}, 1301);
    config = inputs.config;
    identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
    policies = {@selectCausalMinimalEditFormationTreeV240Policy, ...
        @selectCausalMinimumFormationBackboneV242Policy};
    for armIdx = 1:2
        n = config.numberOfSensors;
        f = numel(unique(config.sensorGroupIds));
        budget = 2*n;
        if armIdx == 2, budget = n + 2*(f-1); end
        history = false(n,n,0);
        times = [];
        plannedDev = zeros(1,config.simulationLength);
        realizedDev = plannedDev;
        selfDev = plannedDev;
        strong = plannedDev;
        extraWeight = plannedDev;
        omittedMass = plannedDev;
        for t = 1:config.simulationLength
            context = struct('localPosteriorBySensor', {repmat({struct([])},1,n)}, ...
                'model', struct('dynamicTopologyScenario', struct( ...
                    'config',config,'staticAdjacency',inputs.graphData.staticAdjacency)), ...
                'baseAdjacency',inputs.graphData.staticAdjacency, ...
                'physicalAdjacency',inputs.graphData.physicalAdjacency(:,:,t), ...
                'positions',inputs.graphData.positions(:,:,t), ...
                'currentTime',t,'commConfig',struct( ...
                    'pDropByEdge',inputs.commConfig.pDropByEdge(:,:,t)), ...
                'directedMessageBudget',budget, ...
                'sensorPhysicalUids',identity.sensorPhysicalUids, ...
                'formationPhysicalUidsBySensor',identity.formationPhysicalUidsBySensor, ...
                'previousAdjacencyHistory',history, ...
                'previousAdjacencyHistoryCount',size(history,3), ...
                'previousAdjacencyHistoryTimes',times);
            [adj, details] = policies{armIdx}(context);
            w = details.fusionWeightMatrix;
            delivered = logical(adj);
            if ~inputs.commConfig.forceDelivery
                delivered = delivered & (inputs.commConfig.linkUniforms(:,:,t)' >= ...
                    inputs.commConfig.pDropByEdge(:,:,t)');
            end
            kept = w .* (double(delivered) + eye(n));
            mass = sum(w-kept,2);
            % Current V240/V242 inherit the runtime's 'renormalize' default.
            actual = kept ./ sum(kept,2);
            % Counterfactual: retain each surviving neighbor's planned weight.
            compensated = kept + diag(mass);
            plannedDev(t) = max(abs(sum(w,1)-1));
            realizedDev(t) = max(abs(sum(actual,1)-1));
            selfDev(t) = max(abs(sum(compensated,1)-1));
            extraWeight(t) = max(max((actual-w).*double(delivered)));
            omittedMass(t) = mean(mass);
            strong(t) = reachesAll(delivered) && reachesAll(delivered');
            assert(max(abs(sum(actual,2)-1)) < 1e-12);
            assert(max(abs(sum(compensated,2)-1)) < 1e-12);
            history = cat(3,history,logical(adj));
            times(end+1) = t;
            if size(history,3)>2
                history=history(:,:,end-1:end); times=times(end-1:end);
            end
        end
        rec = struct('presetName',presets{sceneIdx},'armIndex',armIdx, ...
            'messages',budget,'timeCount',config.simulationLength, ...
            'plannedNonDoublePages',nnz(plannedDev>1e-12), ...
            'packetNonDoublePages',nnz(realizedDev>1e-12), ...
            'selfNonDoublePages',nnz(selfDev>1e-12), ...
            'packetStrongPages',nnz(strong), ...
            'maximumPlannedColumnDeviation',max(plannedDev), ...
            'maximumPacketColumnDeviation',max(realizedDev), ...
            'maximumSelfColumnDeviation',max(selfDev), ...
            'maximumSurvivingNeighborWeightIncrease',max(extraWeight), ...
            'meanMissingWeightMass',mean(omittedMass));
        records(end+1) = rec;
        fprintf('V277 %s arm%d: planned/packet/self non-DS=%d/%d/%d; strong=%d/%d; max amplification=%.6f\n', ...
            presets{sceneIdx},armIdx,rec.plannedNonDoublePages, ...
            rec.packetNonDoublePages,rec.selfNonDoublePages, ...
            rec.packetStrongPages,rec.timeCount,rec.maximumSurvivingNeighborWeightIncrease);
    end
end
gitState = resolveResearchGitState();
result = struct('generatedAt',datestr(now,31), ...
    'generationGitCommit',gitState.commit,'seed',1301,'records',records, ...
    'trackingRun',false,'packetLevelOnly',true);
outputRoot = fullfile('RUN','GA','dynamic_topology','evidence', ...
    'tracking_aligned_v277','packet_weight_realization_seed1301');
if exist(outputRoot,'dir')~=7, mkdir(outputRoot); end
reportPath = fullfile(outputRoot,'REALIZED_KLA_BALANCE_V277.md');
save('-mat7-binary',fullfile(outputRoot,'REALIZED_KLA_BALANCE_V277.mat'),'result');
fid=fopen(reportPath,'w');
assert(fid>=0); cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'# Packet-level KLA weight realization\n\n');
fprintf(fid,'Source: `%s`; paired input seed: `1301`.\n\n',gitState.commit);
fprintf(fid,['| Scene | Arm | Messages | Non-double pages: planned / renormalize / self | ', ...
    'Packet-strong pages | Maximum surviving-neighbor weight increase |\n']);
fprintf(fid,'|:--|:--|--:|:--|:--|--:|\n');
for rec=records
    arm='Full causal'; if rec.armIndex==2, arm='Minimum backbone'; end
    fprintf(fid,'| %s | %s | %d | %d / %d / %d | %d / %d | %.6f |\n', ...
        rec.presetName,arm,rec.messages,rec.plannedNonDoublePages, ...
        rec.packetNonDoublePages,rec.selfNonDoublePages, ...
        rec.packetStrongPages,rec.timeCount,rec.maximumSurvivingNeighborWeightIncrease);
end
fprintf(fid,['\nThese are packet-level matrices, assuming a delivered packet supplies an input. ', ...
    'They are not realized label-wise fusion matrices: empty payloads, support censoring ', ...
    'and label-specific renormalization can further change the active inputs. ', ...
    'The exact scenario generator is called to reproduce the registered directed ', ...
    'delivery uniforms, but its posterior, tracking output and scoring functions are ', ...
    'not run. Generated truth and measurements are not used by this analysis.\n\n']);
fprintf(fid,['V240/V242 inherit missingNeighborWeightMode=renormalize. Planned removal ', ...
    'of a local residual edge returns mass to self inside the routing policy, ', ...
    'whereas an unexpected missing packet is omitted and remaining weights are ', ...
    'renormalized. The self column is a counterfactual on the same packet realization, ', ...
    'not a tracking result. Neither handling rule guarantees per-round double stochasticity.\n']);
end

function yes=reachesAll(adj)
seen=false(1,size(adj,1)); todo=1;
while ~isempty(todo)
    node=todo(end); todo(end)=[];
    if seen(node), continue; end
    seen(node)=true;
    todo=[todo,find(adj(node,:) & ~seen)]; %#ok<AGROW>
end
yes=all(seen);
end
