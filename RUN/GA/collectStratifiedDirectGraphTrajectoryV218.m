function [reportPath, result] = ...
        collectStratifiedDirectGraphTrajectoryV218( ...
            presetName, seed, options)
% COLLECTSTRATIFIEDDIRECTGRAPHTRAJECTORYV218 One-pass state sampling.
%
% The V214 current-physical reference route is executed once.  Every focus
% page exposes the already-computed V215 formation features, and four
% truth-free causal strata select formation-time pairs after the complete
% trajectory.  Only selected predecision posteriors are persisted.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getDirectGraphStratifiedSamplingV218Protocol();
splitName = char(getField(options, 'splitName', 'training'));
[allowedPresets, allowedSeeds] = splitMembership(protocol, splitName);
if ~ischar(presetName) || ~ismember(presetName, allowedPresets) || ...
        ~isscalar(seed) || ~ismember(seed, allowedSeeds)
    error('DirectGraphStratifiedSamplingV218:CollectionSplit', ...
        'The requested trajectory is outside the frozen V218 split.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('DirectGraphStratifiedSamplingV218:DirtySource', ...
        'Official V218 trajectory collection requires clean source.');
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
scenario = inputs.config;
scanTimes = scenario.focusWindow(1): ...
    (scenario.focusWindow(end) - protocol.horizonSteps + 1);
maximumTime = scanTimes(end);
inputs = cropInputs(inputs, maximumTime);
inputs.model = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'trajectory_collection', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
cacheRoot = char(getField(options, 'cacheRoot', ...
    fullfile(outputRoot, 'cache')));
overwrite = logical(getField(options, 'overwrite', false));
matPath = fullfile(outputRoot, ...
    'STRATIFIED_DIRECT_GRAPH_TRAJECTORY_V218.mat');
reportPath = fullfile(outputRoot, ...
    'STRATIFIED_DIRECT_GRAPH_TRAJECTORY_V218.md');
if ~overwrite && exist(matPath, 'file') == 2 && ...
        exist(reportPath, 'file') == 2
    loaded = load(matPath, 'result');
    result = loaded.result;
    validateExisting(result, protocol, presetName, seed, ...
        splitName, gitState.commit);
    fprintf('Reused V218 stratified trajectory: %s\n', reportPath);
    return;
end

config = buildCollectionConfig(scenario, scanTimes);
context = buildDirectGraphPayloadRepairV214ExecutionContext( ...
    presetName, seed, [splitName, '-v218-stratified-capture'], ...
    1, maximumTime, 'v218-stratified-state-trajectory', ...
    false, struct());
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
elapsedSeconds = toc(timerId);
trajectory = auditAndExtractTrajectory(diagnostics, scanTimes);
selection = selectDirectGraphStratifiedStatesV218( ...
    scanTimes, trajectory.formationIds, trajectory.featureNames, ...
    trajectory.featuresByTime, struct('protocol', protocol));

if exist(cacheRoot, 'dir') ~= 7
    mkdir(cacheRoot);
end
[uniqueTimes, uniqueCachePaths] = writeSelectedCaches( ...
    cacheRoot, presetName, seed, selection, scenario, config, ...
    diagnostics, protocol, gitState, elapsedSeconds);
[present, cacheIndicesByStratum] = ismember( ...
    selection.selectedTimesByStratum, uniqueTimes);
if ~all(present)
    error('DirectGraphStratifiedSamplingV218:CacheMapping', ...
        'A selected stratum did not map to a persisted cache.');
end
cachePathsByStratum = uniqueCachePaths(cacheIndicesByStratum);

result = struct();
result.contractVersion = ...
    'stratified-direct-graph-trajectory-v218-v1';
result.protocolId = protocol.id;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = presetName;
result.seed = seed;
result.splitName = splitName;
result.scanTimes = scanTimes;
result.featureContractVersion = trajectory.featureContractVersion;
result.featureNames = trajectory.featureNames;
result.payloadFeatureNames = trajectory.payloadFeatureNames;
result.maximumFormationNeedByTime = trajectory.maximumFormationNeed;
result.referencePayloadBytesProxyByTime = ...
    trajectory.referencePayloadBytesProxy;
result.selection = selection;
result.uniqueSelectedTimes = uniqueTimes;
result.uniqueCachePaths = uniqueCachePaths;
result.cachePathsByStratum = cachePathsByStratum;
result.elapsedSeconds = elapsedSeconds;
result.posteriorCounterfactualEnumerationUsed = false;
result.captureEveryFocusPageInMemory = true;
result.windowSelectionUsesTruth = false;
result.windowSelectionUsesFutureInformation = false;
result.numericFormationIdentifiersUsedAsScores = false;
result.recursiveTargetsCollected = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
result.matPath = matPath;
result.reportPath = reportPath;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V218 stratified direct-graph trajectory: %s\n', reportPath);
end

function config = buildCollectionConfig(scenario, captureTimes)
source = getDirectGraphPayloadRepairControllerV214Protocol();
config = buildMixtureAwareKlaReferenceConfig();
config.missingLabelFusionMode = source.receiverMode;
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenario.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = 2 * scenario.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicyName = source.base.policyName;
config.topologyPolicyFcn = @(context) ...
    selectDirectGraphPayloadRepairV214ReferencePolicy(context);
config.topologyPosteriorCaptureTimes = reshape(captureTimes, 1, []);
config.receiverSafeLabelFusionEnabled = false;
config.receiverSafeFormationConditionedOnlinePolicyEnabled = false;
end

function trajectory = auditAndExtractTrajectory(diagnostics, times)
formationPages = diagnostics. ...
    topologyPolicyHierarchicalFormationIds(times);
needPages = diagnostics. ...
    topologyPolicyHierarchicalFormationNeedByFormation(times);
maximumNeed = diagnostics. ...
    topologyPolicyHierarchicalMaximumFormationNeed(times);
graphVersions = diagnostics. ...
    topologyPolicyHierarchicalGraphContractVersion(times);
featureVersions = diagnostics. ...
    topologyPolicyHierarchicalWithholdingFeatureContractVersion(times);
featureNamePages = diagnostics. ...
    topologyPolicyHierarchicalWithholdingFeatureNames(times);
featurePages = diagnostics. ...
    topologyPolicyHierarchicalWithholdingFeaturesByFormation(times);
payloadNamePages = diagnostics. ...
    topologyPolicyHierarchicalWithholdingPayloadFeatureNames(times);
payloadPages = diagnostics. ...
    topologyPolicyHierarchicalWithholdingPayloadFeaturesByFormation(times);
referencePayload = diagnostics. ...
    topologyPolicyHierarchicalWithholdingReferencePayloadBytesProxy(times);
truthUse = diagnostics. ...
    topologyPolicyHierarchicalWithholdingTruthUsed(times);
futureUse = diagnostics. ...
    topologyPolicyHierarchicalWithholdingFutureInformationUsed(times);
repair = diagnostics.topologyPolicyRepairTriggered(times);
if any(~isfinite(maximumNeed)) || ...
        any(~isfinite(referencePayload)) || ...
        any(cellfun(@isempty, formationPages)) || ...
        any(cellfun(@isempty, needPages)) || ...
        any(cellfun(@isempty, graphVersions)) || ...
        any(cellfun(@isempty, featureVersions)) || ...
        any(cellfun(@isempty, featureNamePages)) || ...
        any(cellfun(@isempty, featurePages)) || ...
        any(cellfun(@isempty, payloadNamePages)) || ...
        any(cellfun(@isempty, payloadPages)) || ...
        any(isfinite(truthUse) & truthUse ~= 0) || ...
        any(isfinite(futureUse) & futureUse ~= 0) || ...
        any(isfinite(repair) & repair ~= 0) || ...
        any(~diagnostics.topologyFeasible(times))
    error('DirectGraphStratifiedSamplingV218:TrajectoryGate', ...
        'The V218 observable feature trajectory failed its runtime gate.');
end

formationIds = reshape(formationPages{1}, 1, []);
featureNames = reshape(featureNamePages{1}, 1, []);
payloadFeatureNames = reshape(payloadNamePages{1}, 1, []);
featureContractVersion = featureVersions{1};
for idx = 1:numel(times)
    if ~isequal(reshape(formationPages{idx}, 1, []), formationIds) || ...
            ~isequal(reshape(featureNamePages{idx}, 1, []), ...
                featureNames) || ...
            ~isequal(reshape(payloadNamePages{idx}, 1, []), ...
                payloadFeatureNames) || ...
            ~strcmp(featureVersions{idx}, featureContractVersion) || ...
            ~isequal(size(featurePages{idx}), ...
                [numel(formationIds), numel(featureNames)]) || ...
            ~isequal(size(payloadPages{idx}), ...
                [numel(formationIds), numel(payloadFeatureNames)]) || ...
            any(~isfinite(featurePages{idx}(:))) || ...
            any(~isfinite(payloadPages{idx}(:)))
        error('DirectGraphStratifiedSamplingV218:FeatureDrift', ...
            'The V218 feature contract changed within one trajectory.');
    end
end
trajectory = struct();
trajectory.formationIds = formationIds;
trajectory.featureContractVersion = featureContractVersion;
trajectory.featureNames = featureNames;
trajectory.featuresByTime = featurePages;
trajectory.payloadFeatureNames = payloadFeatureNames;
trajectory.payloadFeaturesByTime = payloadPages;
trajectory.maximumFormationNeed = maximumNeed;
trajectory.referencePayloadBytesProxy = referencePayload;
end

function [uniqueTimes, cachePaths] = writeSelectedCaches( ...
        cacheRoot, presetName, seed, selection, scenario, config, ...
        diagnostics, protocol, gitState, elapsedSeconds)
contract = behaviorContinuationCacheContract();
configSnapshot = config;
if isfield(configSnapshot, 'topologyPolicyFcn')
    configSnapshot = rmfield(configSnapshot, 'topologyPolicyFcn');
end
uniqueTimes = unique(selection.selectedTimesByStratum, 'sorted');
cachePaths = cell(1, numel(uniqueTimes));
for idx = 1:numel(uniqueTimes)
    time = uniqueTimes(idx);
    posterior = diagnostics.topologyLocalPosteriorSnapshot{time};
    if isempty(posterior)
        error('DirectGraphStratifiedSamplingV218:MissingPosterior', ...
            'A selected V218 state was not captured.');
    end
    selectedMask = selection.selectedTimesByStratum == time;
    historyByTime = buildBehaviorContinuationHistoryRecords( ...
        diagnostics, time, contract.topologyHistoryDepth);
    posteriorSnapshots = cell(1, time);
    posteriorSnapshots{time} = posterior;
    behaviorBundle = struct( ...
        'cacheContractVersion', contract.version, ...
        'posteriorSnapshotConvention', ...
            contract.posteriorSnapshotConvention, ...
        'topologyHistoryDepth', contract.topologyHistoryDepth, ...
        'topologyHistoryConvention', ...
            contract.topologyHistoryConvention, ...
        'protocolId', protocol.id, ...
        'presetName', presetName, 'seed', seed, ...
        'snapshotTimes', time, ...
        'selectedStrataAtSnapshot', ...
            {selection.stratumNames(selectedMask)}, ...
        'selectedFormationIdsAtSnapshot', ...
            selection.selectedFormationIdsByStratum(selectedMask), ...
        'configSnapshot', scenario, ...
        'behaviorConfigSnapshot', configSnapshot, ...
        'behaviorSeconds', elapsedSeconds, ...
        'behaviorEospaByTime', [], ...
        'behaviorCardinalityErrorByTime', [], ...
        'posteriorSnapshots', {posteriorSnapshots}, ...
        'preDecisionTopologyHistoryByTime', {historyByTime}, ...
        'generationGitCommit', gitState.commit, ...
        'generationTrackedWorktreeDirty', ...
            gitState.trackedWorktreeDirty, ...
        'generationUntrackedSourceFiles', ...
            {gitState.untrackedSourceFiles}, ...
        'referenceArmName', protocol.base.policyName, ...
        'referenceReplayOnly', true, ...
        'missingLabelFusionMode', protocol.receiverMode, ...
        'policyTruthUsed', false, ...
        'policyFutureOutcomeUsed', false, ...
        'openedDevelopmentEvidenceOnly', true, ...
        'validationClaimAllowed', false, ...
        'evidenceBoundary', protocol.evidenceBoundary);
    cachePaths{idx} = fullfile(cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
        seed, time));
    save(cachePaths{idx}, 'behaviorBundle', '-v7');
    [posteriors, history] = extractBehaviorContinuationSnapshot( ...
        behaviorBundle, time, scenario.numberOfSensors);
    if numel(posteriors) ~= scenario.numberOfSensors || ...
            history.snapshotTime ~= time
        error('DirectGraphStratifiedSamplingV218:CacheReadback', ...
            'A selected V218 cache failed readback.');
    end
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
if isfield(inputs.commConfig, 'linkUniforms') && ...
        ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = ...
        inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function [presets, seeds] = splitMembership(protocol, splitName)
switch splitName
    case 'training'
        presets = protocol.split.mainPresets;
        seeds = protocol.split.trainingSeeds;
    case 'calibration'
        presets = protocol.split.mainPresets;
        seeds = protocol.split.calibrationSeeds;
    case 'evaluation'
        presets = protocol.split.mainPresets;
        seeds = protocol.split.evaluationSeeds;
    case 'stress'
        presets = protocol.split.stressPresets;
        seeds = protocol.split.stressSeeds;
    case 'scale-extrapolation'
        presets = protocol.split.scaleExtrapolationPresets;
        seeds = protocol.split.scaleExtrapolationSeeds;
    otherwise
        error('DirectGraphStratifiedSamplingV218:UnknownSplit', ...
            'The V218 trajectory split is not registered.');
end
end

function validateExisting(result, protocol, presetName, seed, ...
        splitName, commit)
required = {'contractVersion', 'protocolId', 'presetName', 'seed', ...
    'splitName', 'generationGitCommit', 'selection', ...
    'uniqueCachePaths', 'posteriorCounterfactualEnumerationUsed'};
if ~isstruct(result) || ~all(isfield(result, required)) || ...
        ~strcmp(result.protocolId, protocol.id) || ...
        ~strcmp(result.presetName, presetName) || ...
        result.seed ~= seed || ~strcmp(result.splitName, splitName) || ...
        ~strcmp(result.generationGitCommit, commit) || ...
        numel(result.selection.stratumNames) ~= ...
            protocol.collection.maximumPairsPerTrajectory || ...
        result.posteriorCounterfactualEnumerationUsed || ...
        any(cellfun(@(path) exist(path, 'file') ~= 2, ...
            result.uniqueCachePaths))
    error('DirectGraphStratifiedSamplingV218:ExistingArtifactDrift', ...
        'The existing V218 trajectory artifact does not match source.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('DirectGraphStratifiedSamplingV218:WriteReport', ...
        'Could not write the V218 trajectory report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
selection = result.selection;
fprintf(fid, '# V218 stratified direct-graph trajectory\n\n');
fprintf(fid, '- Split / scene / seed: `%s / %s / %d`\n', ...
    result.splitName, result.presetName, result.seed);
fprintf(fid, '- Scan window: `%d:%d`\n', ...
    result.scanTimes(1), result.scanTimes(end));
fprintf(fid, '- Runtime: `%.1f s`\n', result.elapsedSeconds);
fprintf(fid, '- Rank normalization: `%s`\n', ...
    selection.rankNormalization);
fprintf(fid, '- Distinct-time separation: `%d` pages\n', ...
    selection.minimumDistinctTimeSeparation);
fprintf(fid, '- Online posterior counterfactuals: `0`\n\n');
fprintf(fid, '| Causal stratum | Time | Formation | Score | Component ranks |\n');
fprintf(fid, '|:--|--:|--:|--:|:--|\n');
for idx = 1:numel(selection.stratumNames)
    fprintf(fid, '| %s | %d | %d | %.4f | `%s` |\n', ...
        selection.stratumNames{idx}, ...
        selection.selectedTimesByStratum(idx), ...
        selection.selectedFormationIdsByStratum(idx), ...
        selection.selectedScoresByStratum(idx), ...
        mat2str(selection.selectedComponentRanksByStratum{idx}, 4));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
