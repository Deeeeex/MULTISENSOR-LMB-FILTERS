function audit = auditLabelSetStaticDynamicGateSignalsM24()
% AUDITLABELSETSTATICDYNAMICGATESIGNALSM24 Predecision gate signal audit.
%
% This is an exploratory training-only diagnostic. It reconstructs the
% registered t=75 continuation state for every opened M24 training seed and
% compares deployment-observable compatibility, GNN-score and posterior
% complexity signals against the already registered closed-loop gain of the
% topology-only arm versus the frozen CCW control.

protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.predecisionStaticDynamicGateDesignAuthorized || ...
        ~protocol.alwaysOnTopologyOnlyCandidateRejected || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Static/dynamic gate signal audit is not authorized.');
end
loadedModel = load( ...
    protocol.messagePassingInitializationPath, 'model');
if ~isfield(loadedModel, 'model') || ...
        ~strcmp(computeFileSha256( ...
            protocol.messagePassingInitializationPath), ...
            protocol.messagePassingInitializationSha256)
    error('Registered label-set model is unavailable.');
end
model = loadedModel.model;
seeds = reshape(protocol.trainingSeeds, 1, []);
targetGainPercent = nan(numel(seeds), 1);
featureRows = [];
featureNames = {};

for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    context = reconstructPredecisionContext( ...
        protocol, seed);
    block = computeLabelSetMessagePassingPolicyBlock( ...
        context, struct('protocol', protocol));
    scoreOutput = scoreLabelSetMessagePassingPolicyModel( ...
        model, block);
    weightIdx = find(abs(block.residualWeightGrid - ...
        protocol.localResidualWeight) <= 1e-12);
    if numel(weightIdx) ~= 1
        error('Registered fixed residual weight is unavailable.');
    end
    fixedTaskScores = ...
        scoreOutput.edgeTaskScore(:, weightIdx);
    [~, learnedDetails] = ...
        selectLabelSetMessagePassingRoutingPolicy( ...
            context, model, struct( ...
                'protocol', protocol, ...
                'fixedResidualWeight', ...
                    protocol.localResidualWeight));
    [~, cwDetails] = ...
        selectBackboneResidualSplicedCyclePolicy( ...
            context, 'fixed-clockwise', struct( ...
                'dominantWeight', ...
                    protocol.dominantWeight, ...
                'residualWeight', ...
                    protocol.localResidualWeight));
    [~, ccwDetails] = ...
        selectBackboneResidualSplicedCyclePolicy( ...
            context, 'fixed-counter-clockwise', struct( ...
                'dominantWeight', ...
                    protocol.dominantWeight, ...
                'residualWeight', ...
                    protocol.localResidualWeight));
    [~, compatibility] = ...
        computeLmbKlaCompatibilityMatrix( ...
            context, struct('sourceWeight', ...
                protocol.localResidualWeight));

    learnedEdges = selectedCrossEdges(learnedDetails);
    cwEdges = selectedCrossEdges(cwDetails);
    ccwEdges = selectedCrossEdges(ccwDetails);
    learnedRows = findCandidateRows(block, learnedEdges);
    cwRows = findCandidateRows(block, cwEdges);
    ccwRows = findCandidateRows(block, ccwEdges);

    [complexityValues, complexityNames] = ...
        summarizePosteriorComplexity( ...
            context.localPosteriorBySensor);
    currentValues = [ ...
        summarizeSelectedMatrix( ...
            compatibility.bernoulliCompatibilityMatrix, ...
            learnedEdges, 'learned_bernoulli'), ...
        summarizeSelectedMatrix( ...
            compatibility.bernoulliCompatibilityMatrix, ...
            ccwEdges, 'ccw_bernoulli'), ...
        summarizeDeltaMatrix( ...
            compatibility.bernoulliCompatibilityMatrix, ...
            learnedEdges, ccwEdges, ...
            'learned_minus_ccw_bernoulli'), ...
        summarizeSelectedMatrix( ...
            compatibility.spatialOverlapMatrix, ...
            learnedEdges, 'learned_spatial'), ...
        summarizeSelectedMatrix( ...
            compatibility.spatialOverlapMatrix, ...
            ccwEdges, 'ccw_spatial'), ...
        summarizeDeltaMatrix( ...
            compatibility.spatialOverlapMatrix, ...
            learnedEdges, ccwEdges, ...
            'learned_minus_ccw_spatial'), ...
        summarizeSelectedMatrix( ...
            compatibility.scoreMatrix, ...
            learnedEdges, 'learned_compatibility_score'), ...
        summarizeDeltaMatrix( ...
            compatibility.scoreMatrix, ...
            learnedEdges, ccwEdges, ...
            'learned_minus_ccw_compatibility_score'), ...
        summarizeVector(fixedTaskScores(learnedRows), ...
            'learned_gnn_score'), ...
        summarizeVector( ...
            fixedTaskScores(learnedRows) - ...
                fixedTaskScores(ccwRows), ...
            'learned_minus_ccw_gnn_score'), ...
        summarizeVector( ...
            fixedTaskScores(learnedRows) - ...
                fixedTaskScores(cwRows), ...
            'learned_minus_cw_gnn_score'), ...
        complexityValues];
    currentNames = [ ...
        selectedSummaryNames('learned_bernoulli'), ...
        selectedSummaryNames('ccw_bernoulli'), ...
        selectedSummaryNames( ...
            'learned_minus_ccw_bernoulli'), ...
        selectedSummaryNames('learned_spatial'), ...
        selectedSummaryNames('ccw_spatial'), ...
        selectedSummaryNames( ...
            'learned_minus_ccw_spatial'), ...
        selectedSummaryNames( ...
            'learned_compatibility_score'), ...
        selectedSummaryNames( ...
            'learned_minus_ccw_compatibility_score'), ...
        selectedSummaryNames('learned_gnn_score'), ...
        selectedSummaryNames( ...
            'learned_minus_ccw_gnn_score'), ...
        selectedSummaryNames( ...
            'learned_minus_cw_gnn_score'), ...
        complexityNames];
    if isempty(featureNames)
        featureNames = currentNames;
    elseif ~isequal(featureNames, currentNames)
        error('Gate signal feature names changed across seeds.');
    end
    featureRows(seedIdx, :) = currentValues; %#ok<AGROW>
    targetGainPercent(seedIdx) = ...
        loadRegisteredGainVsFrozenCcw(seed);
    fprintf('  seed %d: frozen-CCW gain %.3f%%\n', ...
        seed, targetGainPercent(seedIdx));
end

if any(~isfinite(featureRows(:))) || ...
        any(~isfinite(targetGainPercent))
    error('Gate signal audit produced nonfinite values.');
end
spearman = nan(1, size(featureRows, 2));
for featureIdx = 1:size(featureRows, 2)
    spearman(featureIdx) = rankCorrelation( ...
        featureRows(:, featureIdx), targetGainPercent);
end
[~, order] = sort(abs(spearman), 'descend');

audit = struct();
audit.contractVersion = ...
    'label-set-static-dynamic-gate-signal-audit-m24-v1';
audit.protocolId = protocol.id;
audit.seeds = seeds;
audit.currentTime = protocol.continuationStartTime;
audit.featureNames = featureNames;
audit.features = featureRows;
audit.targetGainPercent = targetGainPercent;
audit.targetUsesClosedLoopTruth = true;
audit.featuresUseTruth = false;
audit.featuresUseFutureOutcome = false;
audit.seedIdentifierUsedAsFeature = false;
audit.spearman = spearman;
audit.rankOrder = order;
audit.binaryGainPositive = ...
    targetGainPercent > 0;
audit.nestedScalarGate = ...
    evaluateNestedOneDimensionalGateLoso( ...
        featureRows, audit.binaryGainPositive, ...
        featureNames);
audit.trainingOnlyExploratory = true;
audit.developmentOpened = false;
audit.heldoutM24Opened = false;
audit.x36Opened = false;

fprintf('Top predecision gate signals by absolute Spearman:\n');
for rankIdx = 1:min(12, numel(order))
    featureIdx = order(rankIdx);
    fprintf('  %2d. %-48s rho=% .4f values=%s\n', ...
        rankIdx, featureNames{featureIdx}, ...
        spearman(featureIdx), ...
        mat2str(featureRows(:, featureIdx)', 5));
end
fprintf(['Nested scalar-gate LOSO accuracy: %.3f ', ...
    '(%d/%d)\n'], ...
    audit.nestedScalarGate.accuracy, ...
    sum(audit.nestedScalarGate.correct), ...
    numel(audit.nestedScalarGate.correct));
end

function context = reconstructPredecisionContext(protocol, seed)
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCount
    error('Registered M24 scenario is invalid.');
end
currentTime = protocol.continuationStartTime;
cachePath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'cache', ...
    sprintf('m24_hard_seed%d_n1_sig%d.mat', ...
        seed, currentTime));
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Registered continuation cache is unavailable.');
end
[localPosteriors, history] = ...
    extractBehaviorContinuationSnapshot( ...
        loaded.behaviorBundle, currentTime, ...
        protocol.expectedNodeCount);
policyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
positions = inputs.graphData.positions(:, :, currentTime);
physical = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
nodeCount = protocol.expectedNodeCount;

context = struct();
context.localPosteriorBySensor = localPosteriors;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = ...
    buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = policyHistory;
context.previousAdjacencyHistoryCount = ...
    size(policyHistory, 3);
context.previousAdjacencyHistoryTimes = ...
    reshape(history.times, 1, []);
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacencyHistorySource = ...
    'behavior-filter-diagnostics-cache-v2';
if isempty(policyHistory)
    context.previousAdjacency = false(nodeCount);
else
    context.previousAdjacency = policyHistory(:, :, end);
end
context.baseAdjacency = ...
    neighborMapToAdjacency(inputs.neighborMap, nodeCount);
context.physicalAdjacency = physical;
context.edgeScores = double(physical);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = positions;
context.localInnovationHistory = zeros(nodeCount, 3);
context.localAssociationConfidenceHistory = ...
    ones(nodeCount, 3);
context.localNisNormHistory = nan(nodeCount, 3);
context.localNisDeviationHistory = nan(nodeCount, 3);
context.localUpdateHistoryTimes = ...
    (currentTime - 2):currentTime;
end

function edges = selectedCrossEdges(details)
edges = [ ...
    reshape(details.spliceSelection.crossReceivers, [], 1), ...
    reshape(details.spliceSelection.crossSenders, [], 1)];
if isempty(edges)
    error('Spliced-cycle policy selected no cross edges.');
end
end

function rows = findCandidateRows(block, edges)
nodeCount = block.nodeCount;
candidateKeys = block.receiverIndices + ...
    nodeCount * (block.senderIndices - 1);
edgeKeys = edges(:, 1) + ...
    nodeCount * (edges(:, 2) - 1);
[present, rows] = ismember(edgeKeys, candidateKeys);
if any(~present) || numel(unique(rows)) ~= size(edges, 1)
    error('Selected edge is outside the registered candidate set.');
end
rows = reshape(rows, [], 1);
end

function values = summarizeSelectedMatrix(matrix, edges, prefix)
indices = sub2ind(size(matrix), ...
    edges(:, 1), edges(:, 2));
values = summarizeVector(matrix(indices), prefix);
end

function values = summarizeDeltaMatrix( ...
        matrix, leftEdges, rightEdges, prefix)
leftIndices = sub2ind(size(matrix), ...
    leftEdges(:, 1), leftEdges(:, 2));
rightIndices = sub2ind(size(matrix), ...
    rightEdges(:, 1), rightEdges(:, 2));
values = summarizeVector( ...
    matrix(leftIndices) - matrix(rightIndices), prefix);
end

function values = summarizeVector(values, ~)
values = reshape(values, [], 1);
values = [mean(values), min(values), max(values), std(values, 1)];
end

function names = selectedSummaryNames(prefix)
names = { ...
    [prefix, '_mean'], [prefix, '_min'], ...
    [prefix, '_max'], [prefix, '_std']};
end

function [values, names] = summarizePosteriorComplexity(posteriors)
sensorCount = numel(posteriors);
labelCount = zeros(sensorCount, 1);
componentCount = zeros(sensorCount, 1);
existenceMean = zeros(sensorCount, 1);
existenceEntropyMean = zeros(sensorCount, 1);
for sensorIdx = 1:sensorCount
    objects = posteriors{sensorIdx};
    labelCount(sensorIdx) = numel(objects);
    if isempty(objects)
        continue;
    end
    componentCount(sensorIdx) = ...
        sum([objects.numberOfGmComponents]);
    existence = min(max([objects.r], eps), 1 - eps);
    existenceMean(sensorIdx) = mean(existence);
    existenceEntropyMean(sensorIdx) = mean( ...
        -existence .* log(existence) - ...
        (1 - existence) .* log(1 - existence));
end
values = [ ...
    summarizeVector(labelCount, 'label_count'), ...
    summarizeVector(componentCount, 'component_count'), ...
    summarizeVector(existenceMean, 'existence_mean'), ...
    summarizeVector(existenceEntropyMean, ...
        'existence_entropy_mean')];
names = [ ...
    selectedSummaryNames('label_count'), ...
    selectedSummaryNames('component_count'), ...
    selectedSummaryNames('existence_mean'), ...
    selectedSummaryNames('existence_entropy_mean')];
end

function gainPercent = loadRegisteredGainVsFrozenCcw(seed)
if seed == 11
    baseline = load( ...
        fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'closed_loop_init_seed11_t75_t83', ...
        ['DYNAMIC_TOPOLOGY_CONTINUATION_M24_HARD_', ...
         'T75_N1_20260730_064638.mat']));
    learned = load( ...
        fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'closed_loop_fixed_e05_seed11_t75_t83', ...
        ['DYNAMIC_TOPOLOGY_CONTINUATION_M24_HARD_', ...
         'T75_N1_20260730_071528.mat']));
    ccw = baseline.summary.aggregate(2);
    candidate = learned.summary.aggregate(1);
else
    reportPattern = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        sprintf('training_sweep_seed%d_t75_t83', seed), ...
        '*.mat');
    matches = dir(reportPattern);
    if numel(matches) ~= 1
        error('Registered training sweep evidence is ambiguous.');
    end
    loaded = load(fullfile(matches.folder, matches.name));
    ccw = loaded.summary.aggregate(2);
    candidate = loaded.summary.aggregate(3);
end
gainPercent = 100 * ...
    (ccw.meanEospa - candidate.meanEospa) / ...
    ccw.meanEospa;
end

function rho = rankCorrelation(left, right)
leftRanks = rankValues(left);
rightRanks = rankValues(right);
leftCentered = leftRanks - mean(leftRanks);
rightCentered = rightRanks - mean(rightRanks);
denominator = norm(leftCentered) * norm(rightCentered);
if denominator <= eps
    rho = 0;
else
    rho = (leftCentered' * rightCentered) / denominator;
end
end

function ranks = rankValues(values)
values = reshape(values, [], 1);
[sorted, order] = sort(values);
ranks = zeros(size(values));
cursor = 1;
while cursor <= numel(values)
    finish = cursor;
    while finish < numel(values) && ...
            sorted(finish + 1) == sorted(cursor)
        finish = finish + 1;
    end
    ranks(order(cursor:finish)) = ...
        mean(cursor:finish);
    cursor = finish + 1;
end
end

function adjacency = neighborMapToAdjacency(neighborMap, nodeCount)
adjacency = false(nodeCount);
for receiverIdx = 1:nodeCount
    senders = reshape(neighborMap{receiverIdx}, 1, []);
    senders = senders(senders ~= receiverIdx);
    adjacency(receiverIdx, senders) = true;
end
end
