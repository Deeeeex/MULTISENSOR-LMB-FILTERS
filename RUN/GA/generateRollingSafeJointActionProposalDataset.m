function [datasetPath, dataset] = ...
    generateRollingSafeJointActionProposalDataset(options)
% GENERATEROLLINGSAFEJOINTACTIONPROPOSALDATASET M24 safe action bank.
%
% Replays the frozen six-seed behavior trajectories, attests every
% predecision state against the versioned v3 source artifact, and applies
% the truth-free proposal bank. This stage records safe candidate graphs
% and state-action features only; no tracking return is evaluated here.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
if exist(sourcePath, 'file') ~= 2
    error('Missing frozen proposal source state: %s', sourcePath);
end
sourceSha256 = computeFileSha256(sourcePath);
if ~strcmp(sourceSha256, protocol.proposalSourceStateSha256)
    error(['Proposal source state does not match the frozen SHA-256 ', ...
        'contract.']);
end
loaded = load(sourcePath, 'dataset');
if ~isfield(loaded, 'dataset') || ...
        ~strcmp(loaded.dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~isequal(loaded.dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(loaded.dataset.snapshotTimes, ...
            protocol.snapshotTimes)
    error('Proposal source state metadata violates the frozen contract.');
end
sourceDataset = loaded.dataset;

outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'datasets'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    'rolling_safe_joint_action_proposals_m24_hard_t75_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'ROLLING_SAFE_JOINT_ACTION_PROPOSALS_M24_HARD_T75_V1.md'));

proposalBlocks = repmat(emptyProposalBlock(), ...
    1, numel(protocol.datasetSeeds) * ...
        numel(protocol.snapshotTimes));
proposalCursor = 0;
expectedJointFeatureNames = {};
collectorOptions = struct( ...
    'datasetVariant', 'joint-action-state-v3', ...
    'featureContextMode', protocol.featureContextMode, ...
    'blockObserverFcn', @observeBlock, ...
    'skipArtifactWrite', true);
if isfield(options, 'behaviorCacheDirectory')
    collectorOptions.behaviorCacheDirectory = ...
        options.behaviorCacheDirectory;
end
[~, replayDataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        [], [], [], collectorOptions);
if proposalCursor ~= numel(proposalBlocks)
    error('Proposal observer did not receive every frozen state block.');
end

dataset = struct();
dataset.protocolId = protocol.id;
dataset.contractVersion = ...
    protocol.proposalDatasetContractVersion;
dataset.proposalBankContractVersion = ...
    protocol.proposalBankContractVersion;
dataset.generatedAt = datestr(now, 31);
dataset.presetName = protocol.presetName;
dataset.seeds = protocol.datasetSeeds;
dataset.snapshotTimes = protocol.snapshotTimes;
dataset.sourceWeight = protocol.sourceWeight;
dataset.payloadToleranceFraction = ...
    protocol.proposalProjectionPayloadToleranceFraction;
dataset.pairedReturnMaximumAttemptedByteDeviationFraction = ...
    protocol.maximumAttemptedByteDeviationFraction;
dataset.maximumCandidateCount = ...
    protocol.maximumCandidateCount;
dataset.proposalActionCodes = ...
    protocol.proposalActionCodes;
dataset.proposalActionCodeSetSha256 = ...
    protocol.proposalActionCodeSetSha256;
dataset.sourceStatePath = sourcePath;
dataset.sourceStateSha256 = sourceSha256;
dataset.sourceStateContractVersion = ...
    sourceDataset.contractVersion;
dataset.sourceStateGenerationCommit = ...
    sourceDataset.generationGitCommit;
dataset.generationGitCommit = ...
    replayDataset.generationGitCommit;
dataset.generationTrackedWorktreeDirty = ...
    replayDataset.generationTrackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    replayDataset.generationUntrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    replayDataset.generationResearchWorktreeDirty;
dataset.behaviorCacheRecords = ...
    replayDataset.behaviorCacheRecords;
dataset.jointFeatureNames = ...
    expectedJointFeatureNames;
dataset.blocks = proposalBlocks;
dataset.truthUsed = false;
dataset.futureOutcomeUsed = false;
dataset.returnEvaluated = false;
dataset.candidateRankingPerformed = false;
dataset.continuationPosteriorsStored = true;
dataset.controlMetadataTrafficAccounted = ...
    protocol.controlMetadataTrafficAccounted;
dataset.evidenceBoundary = [ ...
    'This artifact verifies truth-free distinct safe candidate ', ...
    'construction and joint state-action featurization on the frozen ', ...
    'M24 development states. Truth-free predecision posteriors are ', ...
    'stored only to restart paired counterfactual continuations. It ', ...
    'contains no candidate tracking ', ...
    'returns and does not establish top-K coverage, oracle gain, ', ...
    'critic accuracy, X36 support or end-to-end communication savings.'];
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
save('-mat7-binary', datasetPath, 'dataset');
writeProposalReport(reportPath, dataset);
fprintf('Proposal dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);

    function observeBlock(context, replayBlock)
        sourceIdx = findSourceBlock( ...
            sourceDataset.blocks, replayBlock.seed, ...
            replayBlock.currentTime);
        sourceBlock = sourceDataset.blocks(sourceIdx);
        assertReplayMatchesFrozenSource( ...
            replayBlock, sourceBlock);
        [candidateAdjacency, candidateRecords, ...
            proposalMetadata] = ...
                buildRollingSafeJointActionProposalBank(context);
        referenceCandidateIndex = ...
            proposalMetadata.referenceCandidateIndex;
        nodeCount = numel(replayBlock.groupIds);
        candidateKeys = sub2ind([nodeCount, nodeCount], ...
            replayBlock.receiverIndices, ...
            replayBlock.senderIndices);
        referenceAdjacency = candidateAdjacency( ...
            :, :, referenceCandidateIndex);
        referenceMask = logical( ...
            referenceAdjacency(candidateKeys));
        referenceMask = reshape(referenceMask, [], 1);
        candidateCount = size(candidateAdjacency, 3);
        candidateCrossMasks = false( ...
            numel(candidateKeys), candidateCount);
        jointFeatures = zeros(candidateCount, 0);
        jointMetadata = cell(1, candidateCount);
        for candidateIdx = 1:candidateCount
            adjacency = candidateAdjacency(:, :, candidateIdx);
            actionMask = reshape(logical( ...
                adjacency(candidateKeys)), [], 1);
            featureOptions = struct( ...
                'referenceCrossMask', referenceMask, ...
                'actionProposalTruthUsed', false, ...
                'actionProposalOutcomeSelected', false, ...
                'actionProposalSource', ...
                    protocol.proposalBankContractVersion);
            [features, featureNames, featureMetadata] = ...
                computeRollingSafeJointActionFeatures( ...
                    replayBlock, actionMask, featureOptions);
            if isempty(expectedJointFeatureNames)
                expectedJointFeatureNames = featureNames;
            elseif ~isequal( ...
                    expectedJointFeatureNames, featureNames)
                error(['Proposal joint-action feature names drifted ', ...
                    'across candidates.']);
            end
            if candidateIdx == 1
                jointFeatures = zeros( ...
                    candidateCount, numel(features));
            end
            candidateCrossMasks(:, candidateIdx) = ...
                actionMask;
            jointFeatures(candidateIdx, :) = features;
            jointMetadata{candidateIdx} = featureMetadata;
        end
        proposalCursor = proposalCursor + 1;
        proposalBlock = emptyProposalBlock();
        proposalBlock.seed = replayBlock.seed;
        proposalBlock.currentTime = ...
            replayBlock.currentTime;
        proposalBlock.sourceBlockIndex = sourceIdx;
        proposalBlock.candidateCount = candidateCount;
        proposalBlock.referenceCandidateIndex = ...
            referenceCandidateIndex;
        proposalBlock.candidateActionCodes = ...
            [candidateRecords.actionCode];
        proposalBlock.candidateGraphSha256 = ...
            {candidateRecords.graphSha256};
        proposalBlock.candidateAdjacency = ...
            candidateAdjacency;
        proposalBlock.candidateCrossMasks = ...
            candidateCrossMasks;
        proposalBlock.jointFeatures = jointFeatures;
        proposalBlock.jointFeatureMetadata = ...
            jointMetadata;
        proposalBlock.candidateRecords = ...
            candidateRecords;
        proposalBlock.proposalMetadata = ...
            proposalMetadata;
        proposalBlock.initialLocalPosteriorBySensor = ...
            context.localPosteriorBySensor;
        proposalBlocks(proposalCursor) = proposalBlock;
    end
end

function index = findSourceBlock(blocks, seed, currentTime)
index = find([blocks.seed] == seed & ...
    [blocks.currentTime] == currentTime);
if numel(index) ~= 1
    error('Frozen source state lacks a unique seed-time block.');
end
end

function assertReplayMatchesFrozenSource(replay, frozen)
fields = { ...
    'seed', 'currentTime', 'features', 'featureNames', ...
    'featureMetadata', 'receiverIndices', 'senderIndices', ...
    'physicalAdjacency', 'groupIds', 'senderPayloadBytes', ...
    'previousAdjacencyHistory', ...
    'previousAdjacencyHistoryTimes', ...
    'previousDeliveredAdjacencyHistory', ...
    'previousDeliveredAdjacencyHistoryTimes'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    if ~isequaln(replay.(fieldName), frozen.(fieldName))
        error(['Replayed proposal state differs from the frozen v3 ', ...
            'source in field %s.'], fieldName);
    end
end
end

function writeProposalReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open proposal report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
counts = [dataset.blocks.candidateCount];
duplicates = arrayfun(@(block) ...
    block.proposalMetadata.duplicateCount, dataset.blocks);
unavailable = arrayfun(@(block) ...
    block.proposalMetadata.unavailableCount, dataset.blocks);
fprintf(fid, '# Rolling-safe joint-action proposal dataset: M24\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Proposal bank: `%s`\n', ...
    dataset.proposalBankContractVersion);
fprintf(fid, '- Source state SHA-256: `%s`\n', ...
    dataset.sourceStateSha256);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Generation tracked worktree dirty: `%d`\n', ...
    dataset.generationTrackedWorktreeDirty);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%s`\n', ...
    mat2str(dataset.snapshotTimes));
fprintf(fid, '- Frozen proposal attempts per state: `%d`\n', ...
    numel(dataset.proposalActionCodes));
fprintf(fid, '- Distinct candidates min/mean/max: `%d / %.2f / %d`\n', ...
    min(counts), mean(counts), max(counts));
fprintf(fid, '- Joint feature dimension: `%d`\n', ...
    numel(dataset.jointFeatureNames));
fprintf(fid, '- Truth used: `%d`\n', dataset.truthUsed);
fprintf(fid, '- Future outcome used: `%d`\n', ...
    dataset.futureOutcomeUsed);
fprintf(fid, '- Return evaluated: `%d`\n', ...
    dataset.returnEvaluated);
fprintf(fid, '- Continuation posteriors stored: `%d`\n', ...
    dataset.continuationPosteriorsStored);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, '## State blocks\n\n');
fprintf(fid, ['| Seed | Time | Distinct | Duplicates | ', ...
    'Unavailable | Reference index | Action codes |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|:--|\n');
for block = dataset.blocks
    fprintf(fid, '| %d | %d | %d | %d | %d | %d | `%s` |\n', ...
        block.seed, block.currentTime, ...
        block.candidateCount, ...
        block.proposalMetadata.duplicateCount, ...
        block.proposalMetadata.unavailableCount, ...
        block.referenceCandidateIndex, ...
        formatActionCodes(block.candidateActionCodes));
end
fprintf(fid, '\n## Aggregate construction readout\n\n');
fprintf(fid, '- Total distinct state-actions: `%d`\n', ...
    sum(counts));
fprintf(fid, '- Total duplicate proposals removed: `%d`\n', ...
    sum(duplicates));
fprintf(fid, '- Total unavailable proposals: `%d`\n', ...
    sum(unavailable));
fprintf(fid, '- Candidate cap respected on every state: `%d`\n', ...
    all(counts <= dataset.maximumCandidateCount));
fprintf(fid, '- Candidate tracking-return gate evaluated: `0`\n');
end

function block = emptyProposalBlock()
block = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'sourceBlockIndex', NaN, ...
    'candidateCount', 0, ...
    'referenceCandidateIndex', NaN, ...
    'candidateActionCodes', [], ...
    'candidateGraphSha256', {cell(1, 0)}, ...
    'candidateAdjacency', false(0, 0, 0), ...
    'candidateCrossMasks', false(0, 0), ...
    'jointFeatures', zeros(0, 0), ...
    'jointFeatureMetadata', {cell(1, 0)}, ...
    'candidateRecords', repmat(struct(), 1, 0), ...
    'proposalMetadata', struct(), ...
    'initialLocalPosteriorBySensor', {cell(1, 0)});
end

function token = formatActionCodes(actionCodes)
parts = arrayfun(@(code) sprintf('%02d', code), ...
    reshape(actionCodes, 1, []), 'UniformOutput', false);
token = strjoin(parts, '-');
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
