function [reportPath, dataset] = ...
        generateRecursiveRolloutLabelActionDatasetV176(options)
% GENERATERECURSIVEROLLOUTLABELACTIONDATASETV176 Aggregate V169 states.
%
% The V169 recursive screen exposes the actual pre-side-channel fused
% posterior and local source posteriors at its F5 repair cells. V176 scores
% the same truth-free source-label shortlist on those rollout states so a
% later policy can be trained on the state distribution it actually visits.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLearnedOneHopSafeLabelV169Protocol();
screenPath = getField(options, 'snapshotScreenPath', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v176', 'recursive_rollout_action_value'));
generatorOptions = struct( ...
    'snapshotScreenPath', screenPath, ...
    'snapshotActionName', protocol.candidateActionName, ...
    'outputRoot', outputRoot, ...
    'repairPages', [7, 8], ...
    'repairFormationsByPage', {{5, 5}}, ...
    'splitBySchedule', [1, 3], ...
    'shortlistPerCriterion', 1, ...
    'datasetContractVersion', ...
        'recursive-rollout-label-action-value-dataset-v176-v1', ...
    'resultFileStem', ...
        'RECURSIVE_ROLLOUT_LABEL_ACTION_VALUE_DATASET_V176', ...
    'reportTitle', ...
        'V176 recursive-rollout label-action value dataset', ...
    'evidenceBoundary', [ ...
        'V176 is an opened X36 seed-211 rollout-state development ', ...
        'dataset. It reads the pre-side-channel fused posterior and ', ...
        'current local source posteriors actually visited by recursive ', ...
        'V169 at the twelve F5 t=78/79 cells. Candidate features and the ', ...
        'seven-criterion shortlist use present posterior, topology and ', ...
        'FoV summaries only; truth, future measurements and numeric label ', ...
        'identifiers are excluded. Current truth scores immediate E-OSPA ', ...
        'and matched-position RMSE action values. The source rollout was ', ...
        'itself developed on seed 211, so this dataset diagnoses recursive ', ...
        'distribution shift and supports policy iteration only; it is not ', ...
        'validation or generalization evidence.']);
[reportPath, dataset] = ...
    generateOneHopLabelActionValueDatasetV166(generatorOptions);
dataset.sourceProtocolId = protocol.id;
dataset.sourceResultContractVersion = protocol.resultContractVersion;
save('-mat7-binary', dataset.matPath, 'dataset');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
