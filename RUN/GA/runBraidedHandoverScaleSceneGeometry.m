function [reportPath, result] = ...
    runBraidedHandoverScaleSceneGeometry(options)
% RUNBRAIDEDHANDOVERSCALESCENEGEOMETRY Exact M24/X36 geometry gate.

if nargin < 1 || isempty(options)
    options = struct();
end
presets = { ...
    'm24-formation-fov-braided-handover', ...
    'x36-formation-fov-braided-handover'};
seeds = getField(options, 'seeds', [41, 43, 47]);
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v70', 'braided_handover_geometry'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(presets) * numel(seeds));
cursor = 0;
for seed = reshape(seeds, 1, [])
    for presetIdx = 1:numel(presets)
        cursor = cursor + 1;
        rng(seed);
        config = buildDynamicTopologyScenarioConfig(presets{presetIdx});
        [sensors, ~] = generateMultiFormationTrajectories(config);
        [targets, ~] = generateCorridorTargetTrajectories(config);
        graph = buildDynamicTopologyGraphs(config, sensors);
        validation = validateDynamicTopologyScenario( ...
            config, sensors, targets, graph, ...
            struct('throwOnInvalid', false));
        formationAdjacency = buildFormationAdjacency( ...
            graph.intersectionAdjacency, config.sensorGroupIds, ...
            config.formationCount);
        records(cursor) = makeRecord( ...
            presets{presetIdx}, seed, config, validation, ...
            formationAdjacency);
        fprintf([ ...
            'Braided geometry %s seed=%d valid=%d visible=%.4f ', ...
            'blackout=%.3f%% single=%.3f%% multi=%.3f%% ', ...
            'load=%.4f edges=%d minST=%.2f\n'], ...
            presets{presetIdx}, seed, records(cursor).isValid, ...
            records(cursor).meanVisibleFormationCount, ...
            100 * records(cursor).blackoutFraction, ...
            100 * records(cursor).singleFormationFraction, ...
            100 * records(cursor).multiFormationFraction, ...
            records(cursor).focusMeanVisibleTargetsPerSensorTime, ...
            records(cursor).physicalFormationEdgeCount, ...
            records(cursor).minimumSensorTargetSeparation);
    end
end

scaleRows = repmat(emptyScaleRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    m24 = records(strcmp({records.presetName}, presets{1}) & ...
        [records.seed] == seed);
    x36 = records(strcmp({records.presetName}, presets{2}) & ...
        [records.seed] == seed);
    scaleRows(seedIdx).seed = seed;
    scaleRows(seedIdx).visibleFormationRatio = ...
        x36.meanVisibleFormationCount / ...
            max(m24.meanVisibleFormationCount, eps);
    scaleRows(seedIdx).localSensorLoadRatio = ...
        x36.focusMeanVisibleTargetsPerSensorTime / ...
            max(m24.focusMeanVisibleTargetsPerSensorTime, eps);
end

recordGate = all([records.isValid]) && ...
    all([records.blackoutFraction] <= 0.01 + 1e-12) && ...
    all([records.minimumSensorTargetSeparation] >= 30 - 1e-9) && ...
    all([records.minimumTargetGroupHandovers] >= 1) && ...
    all([records.physicalFormationEdgeCount] == ...
        [records.formationCount] - 1) && ...
    all([records.maximumPhysicalFormationDegree] <= 2) && ...
    all([records.physicalFormationGraphConnected]);
scaleGate = all([scaleRows.visibleFormationRatio] >= 0.90) && ...
    all([scaleRows.visibleFormationRatio] <= 1.10) && ...
    all([scaleRows.localSensorLoadRatio] >= 0.90) && ...
    all([scaleRows.localSensorLoadRatio] <= 1.10);

result = struct();
result.contractVersion = 'braided-handover-scale-geometry-v1';
result.generatedAt = datestr(now, 31);
result.presets = presets;
result.seeds = seeds;
result.records = records;
result.scaleRows = scaleRows;
result.recordGatePassed = recordGate;
result.scaleGatePassed = scaleGate;
result.passed = recordGate && scaleGate;
result.trackingOutcomeRead = false;
result.trackingOutcomeAuthorized = false;
result.sceneCalibrationStatus = 'development-only';
matPath = fullfile(outputRoot, ...
    'BRAIDED_HANDOVER_SCALE_GEOMETRY_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'BRAIDED_HANDOVER_SCALE_GEOMETRY_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('Braided geometry gate passed=%d: %s\n', ...
    result.passed, reportPath);
end

function record = makeRecord( ...
        presetName, seed, config, validation, formationAdjacency)
record = emptyRecord();
record.presetName = presetName;
record.seed = seed;
record.nodeCount = config.numberOfSensors;
record.formationCount = config.formationCount;
record.isValid = validation.isValid;
record.hardFailures = validation.hardFailures;
record.blackoutFraction = validation.difficulty.blackoutFraction;
record.singleFormationFraction = ...
    validation.difficulty.singleFormationFraction;
record.multiFormationFraction = ...
    validation.difficulty.multiFormationFraction;
record.meanVisibleFormationCount = ...
    validation.difficulty.meanVisibleFormationCount;
record.focusMeanVisibleTargetsPerSensorTime = ...
    validation.difficulty.focusMeanVisibleTargetsPerSensorTime;
record.minimumSensorTargetSeparation = ...
    validation.minimumSensorTargetSeparation;
record.minimumTargetGroupHandovers = ...
    min(validation.targetGroupHandoverCounts);
record.physicalFormationEdgeCount = ...
    nnz(triu(formationAdjacency, 1));
record.maximumPhysicalFormationDegree = ...
    max(sum(formationAdjacency, 2));
record.physicalFormationGraphConnected = isConnected(formationAdjacency);
end

function adjacency = buildFormationAdjacency( ...
        sensorAdjacency, groupIds, formationCount)
adjacency = false(formationCount);
for left = 1:formationCount-1
    leftNodes = find(groupIds == left);
    for right = left+1:formationCount
        rightNodes = find(groupIds == right);
        block = sensorAdjacency(leftNodes, rightNodes);
        if any(block(:))
            adjacency(left, right) = true;
            adjacency(right, left) = true;
        end
    end
end
end

function value = isConnected(adjacency)
nodeCount = size(adjacency, 1);
visited = false(1, nodeCount);
frontier = 1;
visited(1) = true;
while ~isempty(frontier)
    node = frontier(1);
    frontier(1) = [];
    neighbors = find(adjacency(node, :) & ~visited);
    visited(neighbors) = true;
    frontier = [frontier, neighbors]; %#ok<AGROW>
end
value = all(visited);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BraidedHandoverGeometry:WriteFailed', ...
        'Could not create the braided-handover geometry report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Braided-handover M24/X36 geometry gate\n\n');
fprintf(fid, ['| Preset | Seed | Valid | Blackout | Single | Multi | ', ...
    'Mean visible formations | Local sensor load | Formation edges | ', ...
    'Max degree | Min sensor-target | Min handovers |\n']);
fprintf(fid, ['|:--|--:|:--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n']);
for row = result.records
    fprintf(fid, ['| `%s` | %d | %d | %.3f%% | %.3f%% | %.3f%% | ', ...
        '%.4f | %.4f | %d | %d | %.2f m | %d |\n'], ...
        row.presetName, row.seed, row.isValid, ...
        100 * row.blackoutFraction, ...
        100 * row.singleFormationFraction, ...
        100 * row.multiFormationFraction, ...
        row.meanVisibleFormationCount, ...
        row.focusMeanVisibleTargetsPerSensorTime, ...
        row.physicalFormationEdgeCount, ...
        row.maximumPhysicalFormationDegree, ...
        row.minimumSensorTargetSeparation, ...
        row.minimumTargetGroupHandovers);
end
fprintf(fid, ['\n| Seed | X36/M24 visible-formation ratio | ', ...
    'X36/M24 local-load ratio |\n']);
fprintf(fid, '|--:|--:|--:|\n');
for row = result.scaleRows
    fprintf(fid, '| %d | %.4f | %.4f |\n', ...
        row.seed, row.visibleFormationRatio, row.localSensorLoadRatio);
end
fprintf(fid, '\n- Record gate passed: `%d`\n', ...
    result.recordGatePassed);
fprintf(fid, '- Scale gate passed: `%d`\n', result.scaleGatePassed);
fprintf(fid, '- Overall passed: `%d`\n', result.passed);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Scene status: `%s`\n', result.sceneCalibrationStatus);
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', 'seed', NaN, 'nodeCount', NaN, ...
    'formationCount', NaN, 'isValid', false, ...
    'hardFailures', {cell(1, 0)}, 'blackoutFraction', NaN, ...
    'singleFormationFraction', NaN, 'multiFormationFraction', NaN, ...
    'meanVisibleFormationCount', NaN, ...
    'focusMeanVisibleTargetsPerSensorTime', NaN, ...
    'minimumSensorTargetSeparation', NaN, ...
    'minimumTargetGroupHandovers', NaN, ...
    'physicalFormationEdgeCount', NaN, ...
    'maximumPhysicalFormationDegree', NaN, ...
    'physicalFormationGraphConnected', false);
end

function value = emptyScaleRow()
value = struct( ...
    'seed', NaN, 'visibleFormationRatio', NaN, ...
    'localSensorLoadRatio', NaN);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
