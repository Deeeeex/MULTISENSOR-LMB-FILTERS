function value = validateInteger(value, name, minimum)
if ~(isscalar(value) && isfinite(value) && ...
        mod(value, 1) == 0 && value >= minimum)
    error('%s must be an integer >= %d.', name, minimum);
end
value = round(value);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function token = formatActionCodes(actionCodes)
parts = arrayfun(@(code) sprintf('%02d', code), ...
    reshape(actionCodes, 1, []), 'UniformOutput', false);
token = strjoin(parts, '-');
end

function token = logicalVectorToken(values)
token = sprintf('%d', logical(values));
end

function token = reuseToken(reused)
if reused
    token = ' [reference reuse]';
else
    token = '';
end
end
