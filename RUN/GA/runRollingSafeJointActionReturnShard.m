function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2
    error('Missing frozen %s: %s', description, path);
end
if ~strcmp(computeFileSha256(path), expectedSha256)
    error('Frozen %s SHA-256 contract mismatch.', description);
end
end

function writeShardReport(path, shard)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open paired return report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 paired H=3 joint-action return shard\n\n');
fprintf(fid, '- Generated: %s\n', shard.generatedAt);
fprintf(fid, '- Contract: `%s`\n', shard.contractVersion);
fprintf(fid, '- Seed/time: `%d / %d`\n', ...
    shard.seed, shard.currentTime);
fprintf(fid, '- Horizon: `%s`\n', ...
    mat2str(shard.horizonTimes));
fprintf(fid, '- Batch: `%d / %d`\n', ...
    shard.batchIndex, shard.batchCount);
fprintf(fid, '- Complete shard: `%d`\n', shard.completeShard);
fprintf(fid, '- Proposal SHA-256: `%s`\n', ...
    shard.proposalDatasetSha256);
fprintf(fid, '- Source state SHA-256: `%s`\n', ...
    shard.sourceStateSha256);
fprintf(fid, '- Generation commit: `%s`\n', ...
    shard.generationGitCommit);
fprintf(fid, '- Common random numbers: `%d`\n', ...
    shard.commonRandomNumbers);
fprintf(fid, '- Repair gate: %s\n', ...
    shard.repairGateSemantics);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    shard.evidenceBoundary);
if shard.referenceIncluded
    ref = shard.referenceOutcome;
    fprintf(fid, '## Reference\n\n');
    fprintf(fid, ...
        ['| Mean E-OSPA | Worst node | Attempted bytes | ', ...
         'Delivered bytes | Repairs | Emergency | Infeasible |\n']);
    fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
    fprintf(fid, '| %.6f | %.6f | %.0f | %.0f | %d | %d | %d |\n\n', ...
        ref.meanEospa, ref.worstSensorEospa, ...
        ref.attemptedBytes, ref.deliveredBytes, ...
        ref.repairCount, ref.payloadEmergencyCount, ...
        ref.infeasibleCount);
end
fprintf(fid, '## Candidate outcomes\n\n');
fprintf(fid, ...
    ['| Index | Code | Reference graph | Mean E-OSPA | ', ...
     'Worst node | Attempted bytes | Repairs | ', ...
     'Delivered B3 sensor/formation |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--|\n');
for result = shard.candidateResults
    outcome = result.outcome;
    fprintf(fid, ...
        '| %d | %02d | %d | %.6f | %.6f | %.0f | %d | `%s / %s` |\n', ...
        result.candidateIndex, result.actionCode, ...
        result.isReferenceGraph, outcome.meanEospa, ...
        outcome.worstSensorEospa, outcome.attemptedBytes, ...
        outcome.repairCount, ...
        logicalVectorToken(outcome.deliveredSensorB3Pass), ...
        logicalVectorToken(outcome.deliveredFormationB3Pass));
end
end

