function [shardPath, shard] = ...
    runRollingSafeJointActionReturnShard( ...
        seed, currentTime, batchIndex, batchCount, options)
% RUNROLLINGSAFEJOINTACTIONRETURNSHARD Paired M24 H=3 action returns.
%
% Each selectable truth-free graph, or each offline truth-labelled
% privileged target, is replayed from the frozen predecision posterior and
% selected-topology history. The candidate controls only the first step;
% the remaining two steps use code 24. Every arm resets the filter RNG and
% reuses the same measurements, trajectories, and link uniforms. Privileged
% graphs are injected from the frozen artifact and never read truth online.

if nargin < 5 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
proposalRole = char(getField( ...
    options, 'proposalRole', 'truth-free'));
role = resolveProposalRole(proposalRole, protocol);
seed = validateInteger(seed, 'seed', 1);
currentTime = validateInteger(currentTime, 'currentTime', 1);
batchIndex = validateInteger(batchIndex, 'batchIndex', 1);
batchCount = validateInteger(batchCount, 'batchCount', 1);
if batchIndex > batchCount
    error('batchIndex must not exceed batchCount.');
end
if ~any(protocol.datasetSeeds == seed) || ...
        ~any(protocol.snapshotTimes == currentTime)
    error('The requested seed-time state is outside the frozen M24 grid.');
end

proposalPath = getField(options, 'proposalDatasetPath', ...
    role.proposalDatasetPath);
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
referenceProposalPath = getField( ...
    options, 'referenceProposalDatasetPath', ...
    protocol.proposalDatasetRelativePath);
validateFrozenFile(proposalPath, role.proposalDatasetSha256, ...
    'proposal dataset');
validateFrozenFile(sourcePath, protocol.proposalSourceStateSha256, ...
    'source state dataset');
validateFrozenFile(referenceProposalPath, ...
    protocol.proposalDatasetSha256, ...
    'reference proposal dataset');
proposalLoaded = load(proposalPath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
referenceProposalLoaded = load( ...
    referenceProposalPath, 'dataset');
proposalDataset = proposalLoaded.dataset;
sourceDataset = sourceLoaded.dataset;
referenceProposalDataset = ...
    referenceProposalLoaded.dataset;
validateDatasetContracts(proposalDataset, sourceDataset, ...
    referenceProposalDataset, role, protocol);

proposalBlockIndex = find( ...
    [proposalDataset.blocks.seed] == seed & ...
    [proposalDataset.blocks.currentTime] == currentTime);
if numel(proposalBlockIndex) ~= 1
    error('The proposal dataset lacks a unique requested state block.');
end
proposalBlock = proposalDataset.blocks(proposalBlockIndex);
sourceBlock = sourceDataset.blocks( ...
    proposalBlock.sourceBlockIndex);
if sourceBlock.seed ~= seed || ...
        sourceBlock.currentTime ~= currentTime
    error('Proposal and source state blocks are misaligned.');
end
referenceProposalBlockIndex = find( ...
    [referenceProposalDataset.blocks.seed] == seed & ...
    [referenceProposalDataset.blocks.currentTime] == currentTime);
if numel(referenceProposalBlockIndex) ~= 1
    error(['The reference proposal dataset lacks a unique requested ', ...
        'state block.']);
end
referenceProposalBlock = ...
    referenceProposalDataset.blocks(referenceProposalBlockIndex);
validateStateBlock(proposalBlock, sourceBlock, role, protocol);

selectable = findCandidateIndices(proposalBlock, role);
if isempty(selectable)
    error('The requested state has no selectable joint actions.');
end
selectedOrdinals = batchIndex:batchCount:numel(selectable);
selectedCandidateIndices = selectable(selectedOrdinals);
maximumCandidates = getField( ...
    options, 'maximumCandidatesToRun', inf);
if ~(isscalar(maximumCandidates) && ...
        (isinf(maximumCandidates) || ...
         (isfinite(maximumCandidates) && ...
          maximumCandidates >= 1 && ...
          mod(maximumCandidates, 1) == 0)))
    error('maximumCandidatesToRun must be a positive integer or inf.');
end
if isfinite(maximumCandidates)
    selectedCandidateIndices = selectedCandidateIndices( ...
        1:min(maximumCandidates, ...
            numel(selectedCandidateIndices)));
end
if isempty(selectedCandidateIndices)
    error('The requested shard contains no selectable candidates.');
end

gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles) || ...
         gitState.researchWorktreeDirty)
    error(['Official return generation requires clean tracked and ', ...
        'MATLAB/Octave source state.']);
end

horizonTimes = currentTime + ...
    (0:(protocol.returnHorizonSteps - 1));
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            numel(sourceBlock.groupIds) || ...
        ~isequal(reshape(inputs.config.sensorGroupIds, 1, []), ...
            reshape(sourceBlock.groupIds, 1, []))
    error('Regenerated M24 scenario violates the frozen state contract.');
end
if horizonTimes(end) > size(inputs.measurements, 2)
    error('The paired return horizon exceeds the scenario length.');
end
inputs = cropInputs(inputs, horizonTimes(end));

referenceCandidateIndex = ...
    referenceProposalBlock.referenceCandidateIndex;
referenceCodes = repmat( ...
    protocol.returnContinuationActionCode, ...
    1, protocol.returnHorizonSteps);
referenceExpectedAdjacency = referenceProposalBlock. ...
    candidateAdjacency(:, :, referenceCandidateIndex);
referenceIncluded = batchIndex == 1;
referenceOutcome = emptyOutcome();
if referenceIncluded
    fprintf(['M24 paired return seed %d t=%d batch %d/%d: ', ...
        'reference codes=%s\n'], ...
        seed, currentTime, batchIndex, batchCount, ...
        formatActionCodes(referenceCodes));
    referenceOutcome = runOneArm( ...
        inputs, referenceProposalBlock, sourceBlock, ...
        referenceCodes, referenceExpectedAdjacency, ...
        protocol, true, emptyFrozenFirstAction());
end

candidateResults = repmat(emptyCandidateResult(), ...
    1, numel(selectedCandidateIndices));
for resultIdx = 1:numel(selectedCandidateIndices)
    candidateIdx = selectedCandidateIndices(resultIdx);
    candidateRecord = ...
        proposalBlock.candidateRecords(candidateIdx);
    actionCodes = [candidateRecord.actionCode, ...
        repmat(protocol.returnContinuationActionCode, ...
            1, protocol.returnHorizonSteps - 1)];
    expectedAdjacency = ...
        proposalBlock.candidateAdjacency(:, :, candidateIdx);
    isReferenceGraph = isequal(expectedAdjacency, ...
        referenceExpectedAdjacency);
    canReuseReference = referenceIncluded && ...
        isReferenceGraph && ...
        isequal(actionCodes, referenceCodes);
    fprintf(['  candidate %d/%d index=%d code=%02d ', ...
        'graph=%s%s\n'], ...
        resultIdx, numel(selectedCandidateIndices), ...
        candidateIdx, candidateRecord.actionCode, ...
        candidateRecord.graphSha256(1:12), ...
        reuseToken(canReuseReference));
    if canReuseReference
        outcome = referenceOutcome;
        outcome.elapsedSeconds = 0;
        outcome.reusedReferenceOutcome = true;
    else
        frozenFirstAction = ...
            buildFrozenFirstAction( ...
                proposalBlock, candidateIdx, role);
        outcome = runOneArm( ...
            inputs, referenceProposalBlock, sourceBlock, ...
            actionCodes, expectedAdjacency, ...
            protocol, false, frozenFirstAction);
    end
    result = emptyCandidateResult();
    result.candidateIndex = candidateIdx;
    result.actionCode = candidateRecord.actionCode;
    result.proposalActionCodes = ...
        candidateRecord.proposalActionCodes;
    result.graphSha256 = candidateRecord.graphSha256;
    result.isReferenceGraph = isReferenceGraph;
    result.jointFeatures = ...
        proposalBlock.jointFeatures(candidateIdx, :);
    result.outcome = outcome;
    candidateResults(resultIdx) = result;
    fprintf(['    E-OSPA %.5f, worst %.5f, attempted %.0f B, ', ...
        'repairs %d, %.2f s\n'], ...
        outcome.meanEospa, outcome.worstSensorEospa, ...
        outcome.attemptedBytes, outcome.repairCount, ...
        outcome.elapsedSeconds);
end

shard = struct();
shard.protocolId = protocol.id;
shard.contractVersion = role.returnContractVersion;
shard.proposalRole = role.id;
shard.generatedAt = datestr(now, 31);
shard.presetName = protocol.presetName;
shard.seed = seed;
shard.currentTime = currentTime;
shard.horizonTimes = horizonTimes;
shard.horizonSteps = protocol.returnHorizonSteps;
shard.batchIndex = batchIndex;
shard.batchCount = batchCount;
shard.selectableCandidateCount = numel(selectable);
shard.selectedCandidateIndices = selectedCandidateIndices;
shard.completeShard = isinf(maximumCandidates);
shard.referenceCandidateIndex = referenceCandidateIndex;
shard.referenceIncluded = referenceIncluded;
shard.referenceActionCodes = referenceCodes;
shard.referenceOutcome = referenceOutcome;
shard.candidateResults = candidateResults;
shard.proposalDatasetPath = proposalPath;
shard.proposalDatasetSha256 = ...
    role.proposalDatasetSha256;
shard.referenceProposalDatasetPath = ...
    referenceProposalPath;
shard.referenceProposalDatasetSha256 = ...
    protocol.proposalDatasetSha256;
shard.sourceStatePath = sourcePath;
shard.sourceStateSha256 = ...
    protocol.proposalSourceStateSha256;
shard.sourceBlockIndex = proposalBlock.sourceBlockIndex;
shard.generationGitCommit = gitState.commit;
shard.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
shard.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
shard.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
shard.filterSeed = seed + protocol.returnFilterSeedOffset;
shard.commonRandomNumbers = true;
shard.candidateFirstActionOnly = true;
shard.firstActionReplayMode = ...
    role.firstActionReplayMode;
shard.continuationActionCode = ...
    protocol.returnContinuationActionCode;
shard.repairGateSemantics = ...
    protocol.returnRepairGateSemantics;
shard.truthUsedByPolicy = false;
shard.proposalTruthUsedOffline = ...
    role.proposalTruthUsedOffline;
shard.evidenceBoundary = role.evidenceBoundary;

outputDirectory = getField(options, 'outputDirectory', ...
    role.outputDirectory);
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
stem = sprintf(role.shardStemFormat, ...
    seed, currentTime, batchIndex, batchCount);
shardPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [stem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(stem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(shardPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Return shard output already exists. Set overwrite=true ', ...
        'only when intentionally regenerating it.']);
end
shard.shardPath = shardPath;
shard.reportPath = reportPath;
save('-mat7-binary', shardPath, 'shard');
writeShardReport(reportPath, shard);
fprintf('Return shard: %s\nReport: %s\n', ...
    shardPath, reportPath);
end

function outcome = runOneArm( ...
        inputs, proposalBlock, sourceBlock, actionCodes, ...
        expectedFirstAdjacency, protocol, isReference, ...
        frozenFirstAction)
triggerConfig = buildTriggerConfig( ...
    inputs, proposalBlock, sourceBlock, ...
    actionCodes, protocol, frozenFirstAction);
rng(sourceBlock.seed + protocol.returnFilterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, triggerConfig);
elapsedSeconds = toc(timerId);
firstExecutedAdjacency = ...
    convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge( ...
            :, :, sourceBlock.currentTime));
if ~isequal(firstExecutedAdjacency, ...
        logical(expectedFirstAdjacency))
    error(['The return arm did not execute the frozen proposed ', ...
        'first graph exactly.']);
end
times = sourceBlock.currentTime + ...
    (0:(protocol.returnHorizonSteps - 1));
repairVector = logical( ...
    diagnostics.topologyPolicyRepairTriggered(times));
emergencyVector = logical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(times));
infeasibleVector = logical( ...
    ~diagnostics.topologyFeasible(times) | ...
    diagnostics.topologyPolicyTopologyInfeasible(times));
truthUseVector = logical( ...
    diagnostics.topologyPolicyTruthUsed(times));
selectedSensorMature = ...
    diagnostics.topologyPolicySensorWindowMature(times) == 1;
selectedFormationMature = ...
    diagnostics.topologyPolicyFormationWindowMature(times) == 1;
selectedSensorStrong = ...
    diagnostics.topologyPolicySensorWindowStrong(times) == 1;
selectedFormationStrong = ...
    diagnostics.topologyPolicyFormationWindowStrong(times) == 1;
if ~isReference && protocol.requireNoCandidateInitialRepair && ...
        repairVector(1)
    error('A selectable candidate required first-action repair.');
end
if protocol.requireNoEmergencyFallback && any(emergencyVector)
    error('A paired return arm used payload-emergency fallback.');
end
if protocol.requireNoInfeasibility && any(infeasibleVector)
    error('A paired return arm became infeasible.');
end
if any(truthUseVector)
    error('A paired return policy unexpectedly read ground truth.');
end
if protocol.requireRollingB3Pass && ...
        (~all(selectedSensorMature) || ...
         ~all(selectedFormationMature) || ...
         ~all(selectedSensorStrong) || ...
         ~all(selectedFormationStrong))
    error('A paired return arm violated selected rolling-B3 safety.');
end

selectedAdjacency = false( ...
    size(firstExecutedAdjacency, 1), ...
    size(firstExecutedAdjacency, 2), numel(times));
deliveredAdjacency = selectedAdjacency;
for timeIdx = 1:numel(times)
    selectedAdjacency(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, times(timeIdx)));
    deliveredAdjacency(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered(:, :, times(timeIdx)));
end
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousAdjacencyHistory, ...
        selectedAdjacency, sourceBlock.groupIds);
[deliveredSensorB3, deliveredFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousDeliveredAdjacencyHistory, ...
        deliveredAdjacency, sourceBlock.groupIds);
if ~isequal(selectedSensorB3, selectedSensorStrong) || ...
        ~isequal(selectedFormationB3, selectedFormationStrong)
    error('Independent selected rolling-B3 audit disagrees with policy.');
end

sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(times));
for sensorIdx = 1:sensorCount
    sensorEospa = computeSimulationOspa( ...
        inputs.model, inputs.groundTruthRfs, ...
        estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(times);
end
sensorMeans = mean(eospa, 2);
attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes(:, :, times), 1), 2), ...
    1, []);
deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes(:, :, times), 1), 2), 1, []);
outcome = emptyOutcome();
outcome.actionCodes = actionCodes;
outcome.meanEospa = mean(eospa(:));
outcome.sensorMeanEospa = reshape(sensorMeans, 1, []);
outcome.eospaBySensorTime = eospa;
outcome.worstSensorEospa = max(sensorMeans);
[~, outcome.worstSensorIndex] = max(sensorMeans);
outcome.attemptedBytesByTime = attemptedBytesByTime;
outcome.deliveredBytesByTime = deliveredBytesByTime;
outcome.attemptedBytes = sum(attemptedBytesByTime);
outcome.deliveredBytes = sum(deliveredBytesByTime);
outcome.attemptCount = sum(reshape( ...
    diagnostics.attempted(:, :, times), 1, []));
outcome.deliveryCount = sum(reshape( ...
    diagnostics.delivered(:, :, times), 1, []));
outcome.repairVector = repairVector;
outcome.repairCount = nnz(repairVector);
outcome.firstActionRepair = repairVector(1);
outcome.payloadEmergencyVector = emergencyVector;
outcome.payloadEmergencyCount = nnz(emergencyVector);
outcome.infeasibleVector = infeasibleVector;
outcome.infeasibleCount = nnz(infeasibleVector);
outcome.truthUseVector = truthUseVector;
outcome.selectedSensorB3Pass = selectedSensorB3;
outcome.selectedFormationB3Pass = selectedFormationB3;
outcome.deliveredSensorB3Pass = deliveredSensorB3;
outcome.deliveredFormationB3Pass = deliveredFormationB3;
outcome.selectedAdjacency = selectedAdjacency;
outcome.deliveredAdjacency = deliveredAdjacency;
outcome.firstActionExact = true;
outcome.reusedReferenceOutcome = false;
outcome.elapsedSeconds = elapsedSeconds;
end

function config = buildTriggerConfig( ...
        inputs, proposalBlock, sourceBlock, ...
        actionCodes, protocol, frozenFirstAction)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    inputs.config.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'paired-joint-action-return-h3';
sequenceOptions = struct( ...
    'sourceWeight', protocol.sourceWeight, ...
    'payloadToleranceFraction', ...
        protocol.proposalProjectionPayloadToleranceFraction, ...
    'fallbackActionCode', ...
        protocol.returnContinuationActionCode, ...
    'scoreOptions', struct( ...
        'sourceWeight', protocol.sourceWeight, ...
        'horizonSteps', 0, ...
        'discountFactor', 0.9));
if frozenFirstAction.enabled
    config.topologyPolicyFcn = ...
        @(context) selectFrozenFirstGraphThenReference( ...
            context, frozenFirstAction, ...
            sourceBlock.currentTime, sequenceOptions);
else
    config.topologyPolicyFcn = ...
        @(context) selectRollingSafeActionSequencePolicy( ...
            context, actionCodes, sourceBlock.currentTime, ...
            sequenceOptions);
end
config.filterInitialLocalPosteriorBySensor = ...
    proposalBlock.initialLocalPosteriorBySensor;
config.filterInitialLocalPosteriorTime = ...
    sourceBlock.currentTime;
if size(sourceBlock.previousAdjacencyHistory, 3) > 0
    config.filterInitialPreviousAdjacencyHistory = ...
        sourceBlock.previousAdjacencyHistory;
    config.filterInitialPreviousAdjacencyTimes = ...
        sourceBlock.previousAdjacencyHistoryTimes;
    config.filterInitialPreviousAdjacencyHistorySource = ...
        'frozen-joint-action-state-v3';
end
end

function [adjacency, details] = ...
        selectFrozenFirstGraphThenReference( ...
            context, frozenFirstAction, anchorTime, ...
            sequenceOptions)
if context.currentTime == anchorTime
    adjacency = frozenFirstAction.adjacency;
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            ~islogical(adjacency) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:)))
        error(['Frozen first-action graph is incompatible with the ', ...
            'live physical action set.']);
    end
    details = frozenFirstAction.policyDetails;
    details.truthUsed = false;
    details.posteriorUsed = false;
    details.actionSequenceTruthUsed = false;
    details.runtimeFrozenGraphReplay = true;
    details.offlineProposalTruthUsed = ...
        frozenFirstAction.offlineProposalTruthUsed;
    details.actionSequenceCodes = ...
        frozenFirstAction.actionCode;
    details.actionSequenceCode = ...
        frozenFirstAction.actionCode;
    details.actionSequenceBranch = ...
        'frozen-offline-proposal-graph-replay';
    details.actionSequenceAnchorTime = anchorTime;
    details.actionSequenceRelativeTime = 1;
else
    [adjacency, details] = ...
        selectRollingSafeActionSequencePolicy( ...
            context, 24, anchorTime, sequenceOptions);
    details.runtimeFrozenGraphReplay = false;
    details.offlineProposalTruthUsed = false;
end
end

function frozen = buildFrozenFirstAction( ...
        proposalBlock, candidateIdx, role)
frozen = emptyFrozenFirstAction();
if ~role.replayFrozenFirstGraph
    return;
end
record = proposalBlock.candidateRecords(candidateIdx);
frozen.enabled = true;
frozen.adjacency = proposalBlock. ...
    candidateAdjacency(:, :, candidateIdx);
frozen.policyDetails = record.policyDetails;
frozen.actionCode = record.actionCode;
frozen.offlineProposalTruthUsed = ...
    role.proposalTruthUsedOffline;
end

function frozen = emptyFrozenFirstAction()
frozen = struct( ...
    'enabled', false, ...
    'adjacency', false(0), ...
    'policyDetails', struct(), ...
    'actionCode', NaN, ...
    'offlineProposalTruthUsed', false);
end

function [sensorPass, formationPass] = ...
    computeRollingB3Pass(previousHistory, executed, groupIds)
depth = 2;
history = logical(previousHistory);
if size(history, 3) > depth
    history = history(:, :, (end - depth + 1):end);
end
stepCount = size(executed, 3);
sensorPass = false(1, stepCount);
formationPass = false(1, stepCount);
for stepIdx = 1:stepCount
    pages = cat(3, history, executed(:, :, stepIdx));
    window = any(pages(:, :, ...
        max(1, end - depth):end), 3);
    sensorPass(stepIdx) = isStronglyConnected(window);
    formationPass(stepIdx) = isStronglyConnected( ...
        collapseToFormations(window, groupIds));
    history(:, :, end + 1) = executed(:, :, stepIdx); %#ok<AGROW>
    if size(history, 3) > depth
        history = history(:, :, (end - depth + 1):end);
    end
end
end

function formationAdjacency = ...
    collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
formationAdjacency = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formationAdjacency(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formationAdjacency(1:numel(groups)+1:end) = false;
end

function valid = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
if ~isequal(size(adjacency), [nodeCount, nodeCount])
    error('Strong-connectivity input must be square.');
end
valid = true;
for startNode = 1:nodeCount
    visited = false(1, nodeCount);
    visited(startNode) = true;
    while true
        next = visited | any(adjacency(visited, :), 1);
        if isequal(next, visited)
            break;
        end
        visited = next;
    end
    if ~all(visited)
        valid = false;
        return;
    end
end
end

function inputs = cropInputs(inputs, maxTime)
maxTime = min(max(1, round(maxTime)), ...
    size(inputs.measurements, 2));
inputs.measurements = inputs.measurements(:, 1:maxTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maxTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maxTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maxTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maxTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maxTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maxTime);
inputs.model.simulationLength = maxTime;
end

function validateDatasetContracts( ...
        proposalDataset, sourceDataset, ...
        referenceProposalDataset, role, protocol)
if ~strcmp(proposalDataset.contractVersion, ...
        role.proposalDatasetContractVersion) || ...
        ~strcmp(sourceDataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~strcmp(referenceProposalDataset.contractVersion, ...
            protocol.proposalDatasetContractVersion) || ...
        ~isequal(proposalDataset.seeds, ...
            protocol.datasetSeeds) || ...
        ~isequal(proposalDataset.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~isequal(sourceDataset.seeds, ...
            protocol.datasetSeeds) || ...
        ~isequal(sourceDataset.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~isequal(referenceProposalDataset.seeds, ...
            protocol.datasetSeeds) || ...
        ~isequal(referenceProposalDataset.snapshotTimes, ...
            protocol.snapshotTimes)
    error('Frozen proposal/source datasets violate the return contract.');
end
end

function validateStateBlock( ...
        proposalBlock, sourceBlock, role, protocol)
candidateCount = proposalBlock.candidateCount;
if candidateCount < 1 || ...
        candidateCount > protocol.maximumCandidateCount || ...
        candidateCount ~= ...
            numel(proposalBlock.candidateRecords) || ...
        size(proposalBlock.candidateAdjacency, 3) ~= candidateCount || ...
        size(proposalBlock.jointFeatures, 1) ~= candidateCount
    error('Proposal state block has inconsistent candidate dimensions.');
end
if ~isequal(proposalBlock.candidateGraphSha256, ...
        {proposalBlock.candidateRecords.graphSha256}) || ...
        numel(unique(proposalBlock.candidateGraphSha256)) ~= ...
            candidateCount
    error('Proposal state block graph identities are inconsistent.');
end
selectable = findCandidateIndices(proposalBlock, role);
if isempty(selectable)
    error('Proposal state block selectable count is inconsistent.');
end
if strcmp(role.id, 'truth-free') && ...
        proposalBlock.selectableCandidateCount ~= numel(selectable)
    error('Proposal state block selectable count is inconsistent.');
elseif strcmp(role.id, 'privileged') && ...
        proposalBlock.distillationTargetCount ~= numel(selectable)
    error('Privileged proposal target count is inconsistent.');
end
if ~isequal(size(sourceBlock.previousAdjacencyHistory, 3), ...
        numel(sourceBlock.previousAdjacencyHistoryTimes)) || ...
        ~isequal(size( ...
            sourceBlock.previousDeliveredAdjacencyHistory, 3), ...
            numel(sourceBlock. ...
                previousDeliveredAdjacencyHistoryTimes)) || ...
        ~isequal(sourceBlock.previousAdjacencyHistoryTimes, ...
            sourceBlock.previousDeliveredAdjacencyHistoryTimes)
    error('Frozen selected/delivered histories are misaligned.');
end
if size(sourceBlock.previousAdjacencyHistory, 3) ~= 2 || ...
        ~isequal(sourceBlock.previousAdjacencyHistoryTimes, ...
            (sourceBlock.currentTime - 2): ...
            (sourceBlock.currentTime - 1))
    error('Paired H=3 returns require two exact preceding history pages.');
end
end

function indices = findCandidateIndices(proposalBlock, role)
records = proposalBlock.candidateRecords;
if strcmp(role.eligibilityField, ...
        'eligibleForCriticSelection')
    mask = [records.eligibleForCriticSelection];
else
    mask = [records.eligibleForProposalDistillation];
end
indices = find(mask);
end

