function [reportPath, shard] = ...
    runFormationH3MultiscaleTeacherShard(presetName, seed, options)
% RUNFORMATIONH3MULTISCALETEACHERSHARD One preset-seed sentinel shard.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getFormationH3MultiscaleTeacherProtocol();
if ~ischar(presetName) || ...
        ~ismember(presetName, protocol.presets) || ...
        ~isscalar(seed) || ~ismember(seed, protocol.allSeeds)
    error('Formation H=3 teacher shard request violates protocol.');
end
snapshotTimes = reshape(getField( ...
    options, 'snapshotTimes', protocol.snapshotTimes), 1, []);
if ~isequal(snapshotTimes, protocol.snapshotTimes)
    error('Official formation H=3 shard requires both frozen times.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 shard requires clean source.');
end
rootDirectory = getField(options, 'outputDirectory', ...
    protocol.shardRoot);
seedDirectory = fullfile(rootDirectory, presetName, ...
    sprintf('seed%d', seed));
shardPath = fullfile(seedDirectory, sprintf( ...
    'formation_h3_teacher_%s_seed%d_v1.mat', ...
    strrep(presetName, '-', '_'), seed));
reportPath = fullfile(seedDirectory, sprintf( ...
    'FORMATION_H3_TEACHER_%s_SEED%d_V1.md', ...
    upper(strrep(presetName, '-', '_')), seed));
shardExists = exist(shardPath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(shardExists, reportExists)
    error('Formation H=3 final shard artifact set is partial.');
elseif shardExists
    loaded = load(shardPath, 'shard');
    if ~isfield(loaded, 'shard') || ...
            ~strcmp(loaded.shard.protocolId, protocol.id) || ...
            ~strcmp(loaded.shard.generationGitCommit, gitState.commit) || ...
            ~strcmp(loaded.shard.presetName, presetName) || ...
            loaded.shard.seed ~= seed
        error('Formation H=3 existing shard provenance mismatch.');
    end
    shard = loaded.shard;
    fprintf('Reused formation H=3 multiscale teacher shard: %s\n', ...
        shardPath);
    return;
end
[cachePaths, cacheSummary] = ...
    generateFormationH3ReferenceStateCaches( ...
        presetName, seed, snapshotTimes, struct( ...
            'cacheRoot', protocol.cacheRoot));
if ~strcmp(cacheSummary.generationGitCommit, gitState.commit)
    error('Formation H=3 cache and shard source commits differ.');
end

localReports = cell(1, numel(snapshotTimes));
pairReports = localReports;
localScreens = cell(size(localReports));
pairScreens = cell(size(localReports));
for timeIdx = 1:numel(snapshotTimes)
    currentTime = snapshotTimes(timeIdx);
    localDirectory = fullfile(seedDirectory, ...
        sprintf('t%d', currentTime), 'local');
    pairDirectory = fullfile(seedDirectory, ...
        sprintf('t%d', currentTime), 'pair');
    commonOptions = struct( ...
        'cacheRoot', protocol.cacheRoot, ...
        'outputDirectory', localDirectory);
    [localReports{timeIdx}, localScreens{timeIdx}] = ...
        loadOrRunScreen( ...
            'local', presetName, seed, currentTime, ...
            commonOptions, gitState.commit);
    pairOptions = commonOptions;
    pairOptions.outputDirectory = pairDirectory;
    [pairReports{timeIdx}, pairScreens{timeIdx}] = ...
        loadOrRunScreen( ...
            'pair', presetName, seed, currentTime, ...
            pairOptions, gitState.commit);
    assertShardState(localScreens{timeIdx}, ...
        pairScreens{timeIdx}, cachePaths{timeIdx}, ...
        presetName, seed, currentTime, protocol);
end

presetIdx = find(strcmp(protocol.presets, presetName), 1);
shard = struct();
shard.contractVersion = ...
    'formation-h3-multiscale-teacher-shard-v1';
shard.protocolId = protocol.id;
shard.generatedAt = datestr(now, 31);
shard.generationGitCommit = gitState.commit;
shard.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
shard.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
shard.presetName = presetName;
shard.seed = seed;
shard.evidenceSplit = splitForSeed(seed, protocol);
shard.snapshotTimes = snapshotTimes;
shard.cachePaths = cachePaths;
shard.cacheSha256 = cacheSummary.cacheSha256;
shard.localReports = localReports;
shard.pairReports = pairReports;
shard.localScreens = localScreens;
shard.pairScreens = pairScreens;
shard.expectedFormationCount = ...
    protocol.expectedFormationCounts(presetIdx);
shard.expectedLocalActionCount = ...
    protocol.expectedLocalActionCounts(presetIdx);
shard.expectedPairActionCount = ...
    protocol.expectedPairActionCounts(presetIdx);
shard.expectedAugmentedActionCount = ...
    protocol.expectedAugmentedActionCounts(presetIdx);
shard.featuresUseTruth = false;
shard.featuresUseFutureMeasurements = false;
shard.targetsUseTruth = true;
shard.targetsUseFutureMeasurements = true;
shard.openedSentinelDevelopmentOnly = true;
shard.finalModelTrainingAuthorized = false;
shard.validationClaimAllowed = false;
shard.evidenceBoundary = protocol.evidenceBoundary;

if exist(seedDirectory, 'dir') ~= 7
    mkdir(seedDirectory);
end
shard.shardPath = shardPath;
shard.reportPath = reportPath;
save('-mat7-binary', shardPath, 'shard');
writeReport(reportPath, shard);
fprintf('Formation H=3 multiscale teacher shard: %s\n', shardPath);
end

function [reportPath, screen] = loadOrRunScreen( ...
        kind, presetName, seed, currentTime, options, expectedCommit)
switch kind
    case 'local'
        prefix = 'FORMATION_MODE_H3';
    case 'pair'
        prefix = 'FORMATION_PAIR_H3';
    otherwise
        error('Unknown formation H=3 screen kind.');
end
stem = sprintf('%s_%s_SEED%d_T%d', prefix, ...
    upper(strrep(presetName, '-', '_')), seed, currentTime);
reportPath = fullfile(options.outputDirectory, [stem, '.md']);
matPath = fullfile(options.outputDirectory, [stem, '.mat']);
matExists = exist(matPath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(matExists, reportExists)
    error('Formation H=3 screen artifact set is partial: %s', stem);
elseif matExists
    loaded = load(matPath, 'screen');
    if ~isfield(loaded, 'screen') || ...
            ~strcmp(loaded.screen.generationGitCommit, expectedCommit) || ...
            ~strcmp(loaded.screen.presetName, presetName) || ...
            loaded.screen.seed ~= seed || ...
            loaded.screen.currentTime ~= currentTime
        error('Formation H=3 existing screen provenance mismatch.');
    end
    screen = loaded.screen;
    fprintf('Reused formation H=3 %s screen: %s\n', ...
        kind, matPath);
    return;
end
switch kind
    case 'local'
        [reportPath, screen] = ...
            runFormationModeH3OpenedReturnScreen( ...
                presetName, seed, currentTime, options);
    case 'pair'
        [reportPath, screen] = ...
            runFormationPairH3OpenedReturnScreen( ...
                presetName, seed, currentTime, options);
end
end

function assertShardState( ...
        localScreen, pairScreen, cachePath, ...
        presetName, seed, currentTime, protocol)
presetIdx = find(strcmp(protocol.presets, presetName), 1);
if localScreen.seed ~= seed || pairScreen.seed ~= seed || ...
        localScreen.currentTime ~= currentTime || ...
        pairScreen.currentTime ~= currentTime || ...
        ~strcmp(localScreen.generationGitCommit, ...
            pairScreen.generationGitCommit) || ...
        ~strcmp(localScreen.cacheSha256, ...
            computeFileSha256(cachePath)) || ...
        ~strcmp(pairScreen.cacheSha256, ...
            computeFileSha256(cachePath)) || ...
        localScreen.bank.formationCount ~= ...
            protocol.expectedFormationCounts(presetIdx) || ...
        localScreen.bank.actionCount ~= ...
            protocol.expectedLocalActionCounts(presetIdx) || ...
        pairScreen.bank.actionCount ~= ...
            protocol.expectedPairActionCounts(presetIdx) || ...
        numel(localScreen.records) + ...
            numel(pairScreen.records) - 1 ~= ...
                protocol.expectedAugmentedActionCounts(presetIdx) || ...
        localScreen.featuresUseTruth || pairScreen.featuresUseTruth || ...
        localScreen.runtimePolicyUsesTruth || ...
        pairScreen.runtimePolicyUsesTruth
    error('Formation H=3 multiscale teacher state audit failed.');
end
end

function split = splitForSeed(seed, protocol)
if ismember(seed, protocol.trainingSeeds)
    split = 'sentinel-training';
elseif ismember(seed, protocol.developmentSeeds)
    split = 'sentinel-development';
else
    error('Formation H=3 sentinel seed has no split.');
end
end

function writeReport(path, shard)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 shard report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 multiscale teacher shard\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    shard.contractVersion, shard.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    shard.generationGitCommit);
fprintf(fid, '- Preset / seed / split: `%s / %d / %s`\n', ...
    shard.presetName, shard.seed, shard.evidenceSplit);
fprintf(fid, '- Times: `%s`\n', mat2str(shard.snapshotTimes));
fprintf(fid, '- Formations: `%d`\n', shard.expectedFormationCount);
fprintf(fid, '- Local / pair / augmented actions per state: `%d / %d / %d`\n', ...
    shard.expectedLocalActionCount, shard.expectedPairActionCount, ...
    shard.expectedAugmentedActionCount);
fprintf(fid, '- Feature truth/future use: `%d / %d`\n', ...
    shard.featuresUseTruth, shard.featuresUseFutureMeasurements);
fprintf(fid, '- Final model / validation authorized: `%d / %d`\n\n', ...
    shard.finalModelTrainingAuthorized, shard.validationClaimAllowed);
fprintf(fid, '| Time | Local best / tail | Pair best / tail |\n');
fprintf(fid, '|--:|--:|--:|\n');
for idx = 1:numel(shard.snapshotTimes)
    local = shard.localScreens{idx};
    pair = shard.pairScreens{idx};
    fprintf(fid, '| %d | %+.3f%% / %+.3f%% | %+.3f%% / %+.3f%% |\n', ...
        shard.snapshotTimes(idx), local.bestMeanGainPercent, ...
        local.bestTailSafeMeanGainPercent, pair.bestMeanGainPercent, ...
        pair.bestTailSafeMeanGainPercent);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    shard.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
