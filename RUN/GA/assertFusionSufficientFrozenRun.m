function assertFusionSufficientFrozenRun(summary, config, expectedSeeds)
% ASSERTFUSIONSUFFICIENTFROZENRUN Enforce the v2 per-batch hard gates.

if nargin < 3 || isempty(expectedSeeds)
    expectedSeeds = config.firstSeed:config.lastSeed;
end
expectedSeeds = reshape(expectedSeeds, 1, []);
require(isequal(summary.armNames, config.armSelection), ...
    'Arm names differ from the frozen pair.');
require(summary.numberOfTrials == numel(expectedSeeds), ...
    'Trial count differs from the expected seed set.');
require(isequal(summary.trialSeeds, expectedSeeds), ...
    'Trial seeds differ from the expected ordered seed set.');
require(summary.scenarioConfig.simulationLength == ...
    config.simulationLength, ...
    'Simulation length differs from the frozen configuration.');
require(summary.scenarioConfig.numberOfSensors == 8, ...
    'The frozen scenario requires eight sensors.');
require(summary.equivalence.captured, ...
    'Posterior equivalence snapshots were not captured.');

for armIdx = 1:2
    trigger = summary.arms(armIdx).triggerConfig;
    require(trigger.capturePosteriorSnapshots, ...
        'Posterior snapshot capture is disabled.');
    require(~trigger.linkGateEnabled && ...
        ~trigger.forceInitialHeavy && ...
        ~trigger.forceLabelChangeHeavy && ...
        ~trigger.forceStaleHeavy && ...
        ~trigger.useStaleNeighborCache && ...
        ~trigger.labelHeartbeatEnabled && ...
        ~trigger.mixedPayloadEnabled && ...
        ~trigger.mixedPayloadLightForAllActiveLabels && ...
        ~trigger.dynamicTopologyEnabled && ...
        ~trigger.modeAwareFusionWeights && ...
        ~trigger.lightCovarianceInflationEnabled, ...
        'An arm violates the frozen isolation settings.');
    require(trigger.lightFusionWeightFactor == ...
        trigger.heavyFusionWeightFactor, ...
        'Light and heavy fusion weights differ.');
end
require(strcmp(summary.arms(1).triggerConfig.eventPolicy, ...
    'alwaysHeavy'), 'The full arm is not alwaysHeavy.');
require(strcmp(summary.arms(2).triggerConfig.eventPolicy, ...
    'alwaysLight'), 'The moment arm is not alwaysLight.');
fullTrigger = rmfield(summary.arms(1).triggerConfig, 'eventPolicy');
momentTrigger = rmfield(summary.arms(2).triggerConfig, 'eventPolicy');
require(isequaln(orderfields(fullTrigger), orderfields(momentTrigger)), ...
    'The two trigger configs contain a non-payload confound.');

for trialIdx = 1:numel(expectedSeeds)
    require(isequal( ...
        summary.trials.attemptedMask{trialIdx, 1}, ...
        summary.trials.attemptedMask{trialIdx, 2}), ...
        sprintf('Attempted masks differ for seed %d.', ...
        expectedSeeds(trialIdx)));
    require(isequal( ...
        summary.trials.deliveredMask{trialIdx, 1}, ...
        summary.trials.deliveredMask{trialIdx, 2}), ...
        sprintf('Delivered masks differ for seed %d.', ...
        expectedSeeds(trialIdx)));
end
require(all(summary.trials.deliveredPayloadBytes(:) <= ...
    summary.trials.attemptedPayloadBytes(:)), ...
    'Delivered bytes exceed attempted bytes.');
require(all(summary.trials.attemptedPayloadBytes(:) > 0), ...
    'Every arm and seed must attempt positive bytes.');
trackingFields = {'localEOspa', 'consensusOspa', ...
    'consensusPosition', 'consensusCardinality'};
for fieldIdx = 1:numel(trackingFields)
    values = summary.trials.(trackingFields{fieldIdx});
    require(isnumeric(values) && isreal(values) && ...
        all(isfinite(values(:))), ...
        sprintf('Tracking field %s contains nonfinite values.', ...
        trackingFields{fieldIdx}));
end

expectedSnapshotCount = summary.scenarioConfig.numberOfSensors * ...
    summary.scenarioConfig.simulationLength;
require(all(summary.trials.posteriorSnapshotCount(:) == ...
    expectedSnapshotCount), ...
    'A trial did not compare exactly S*T snapshots.');
require(all(summary.trials.posteriorMissingSnapshotCount(:) == 0), ...
    'A posterior snapshot is missing.');
require(all(summary.trials.posteriorLabelSetMismatchCount(:) == 0), ...
    'A posterior label set differs.');
require(all(summary.trials.posteriorMissingLabelCount(:) == 0), ...
    'A posterior label is missing.');
require(all(summary.trials.posteriorMaxAbsR(:) == ...
    config.requiredMaxExistenceResidual), ...
    'Existence residual gate failed.');
require(all(summary.trials.posteriorMaxAbsMu(:) == ...
    config.requiredMaxMeanResidual), ...
    'Mean residual gate failed.');
require(all(summary.trials.posteriorMaxAbsSigma(:) == ...
    config.requiredMaxCovarianceResidual), ...
    'Covariance residual gate failed.');
require(all(summary.trials.posteriorExactMatch(:)), ...
    'Exact posterior equivalence gate failed.');
end

function require(condition, message)
if ~condition
    error('FusionSufficientFrozenRun:GateFailed', '%s', message);
end
end
