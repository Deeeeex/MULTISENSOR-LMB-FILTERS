function [auditPath, audit] = ...
    auditCvarResidualGraphPolicyDataset(datasetPaths, options)
% AUDITCVARRESIDUALGRAPHPOLICYDATASET Fail-closed shard integrity audit.

if nargin < 1 || isempty(datasetPaths)
    protocol = getCvarResidualGraphPolicyDatasetProtocol();
    datasetPaths = {protocol.preflightDatasetPath};
else
    protocol = getCvarResidualGraphPolicyDatasetProtocol();
end
if nargin < 2 || isempty(options)
    options = struct();
end
if ischar(datasetPaths)
    datasetPaths = {datasetPaths};
end
datasetPaths = reshape(datasetPaths, 1, []);
if isempty(datasetPaths) || ...
        ~all(cellfun(@ischar, datasetPaths))
    error('CVaR residual graph audit needs dataset paths.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official CVaR residual graph audit requires clean source.');
end

records = repmat(emptyRecord(), 1, numel(datasetPaths));
allBlocks = repmat(emptyBlockSummary(), 1, 0);
allFeatureContracts = cell(1, 0);
allSeeds = zeros(1, 0);
allStateKeys = cell(1, 0);
for datasetIdx = 1:numel(datasetPaths)
    path = datasetPaths{datasetIdx};
    if exist(path, 'file') ~= 2
        error('Missing CVaR residual graph shard: %s', path);
    end
    sourceSha256 = computeFileSha256(path);
    loaded = load(path, 'dataset');
    if ~isfield(loaded, 'dataset')
        error('CVaR residual graph shard has no dataset: %s', path);
    end
    dataset = loaded.dataset;
    validateDatasetEnvelope(dataset, protocol);
    validateCacheRecords(dataset, protocol);
    teacherTargetProvenancePassed = ...
        validateTeacherTargetProvenance( ...
            dataset, sourceSha256, protocol);
    for blockIdx = 1:numel(dataset.graphBlocks)
        block = dataset.graphBlocks(blockIdx);
        behaviorBlock = dataset. ...
            behaviorDataset.blocks(blockIdx);
        summary = validateBlock( ...
            block, behaviorBlock, protocol);
        stateKey = sprintf('%d:%d', ...
            block.seed, block.currentTime);
        if any(strcmp(allStateKeys, stateKey))
            error('Duplicate CVaR residual graph state: %s', stateKey);
        end
        allStateKeys{end + 1} = stateKey; %#ok<AGROW>
        allBlocks(end + 1) = summary; %#ok<AGROW>
        allFeatureContracts{end + 1} = ...
            block.featureContractSha256; %#ok<AGROW>
    end
    records(datasetIdx) = struct( ...
        'path', path, ...
        'sha256', sourceSha256, ...
        'generationCommit', ...
            dataset.generationGitCommit, ...
        'teacherTargetProvenancePassed', ...
            teacherTargetProvenancePassed, ...
        'seeds', dataset.seeds, ...
        'times', dataset.labelTimes, ...
        'stateCount', numel(dataset.graphBlocks));
    allSeeds = [allSeeds, dataset.seeds]; %#ok<AGROW>
end

uniqueFeatureContracts = unique(allFeatureContracts);
if numel(uniqueFeatureContracts) ~= 1
    error('CVaR residual graph shards use different feature contracts.');
end
if numel(unique(allSeeds)) ~= numel(allSeeds)
    error('CVaR residual graph shards overlap in seed.');
end
preflightOnly = isequal(sort(allSeeds), ...
    sort(protocol.preflightSeeds)) && ...
    numel(allBlocks) == 1 && ...
    allBlocks(1).currentTime == ...
        protocol.preflightLabelTime;
if preflightOnly
    if numel(records) ~= 1 || ...
            ~strcmp(records(1).sha256, ...
                protocol.preflightDatasetSha256) || ...
            ~strcmp(records(1).generationCommit, ...
                protocol. ...
                    preflightDatasetGenerationCommit) || ...
            ~strcmp(uniqueFeatureContracts{1}, ...
                protocol. ...
                    preflightFeatureContractSha256) || ...
            allBlocks(1).candidateCount ~= ...
                protocol.preflightExpectedCandidateCount || ...
            allBlocks(1).edgeFeatureCount ~= ...
                protocol.preflightExpectedEdgeFeatureCount || ...
            allBlocks(1).nodeFeatureCount ~= ...
                protocol.preflightExpectedNodeFeatureCount
        error('CVaR residual graph preflight registry mismatch.');
    end
end

defaultAuditPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    sprintf('cvar_residual_graph_dataset_audit_m24_%s.mat', ...
        protocol.artifactVersionToken));
defaultReportPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    sprintf('CVAR_RESIDUAL_GRAPH_DATASET_AUDIT_M24_%s.md', ...
        upper(protocol.artifactVersionToken)));
auditPath = getField(options, ...
    'auditPath', defaultAuditPath);
reportPath = getField(options, ...
    'reportPath', defaultReportPath);
audit = struct();
audit.contractVersion = ...
    ['cvar-residual-graph-dataset-audit-m24-', ...
     protocol.artifactVersionToken];
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
audit.protocolId = protocol.id;
audit.datasetRecords = records;
audit.datasetSetSha256 = computeTextSha256( ...
    strjoin({records.sha256}, char(31)));
audit.featureContractSha256 = ...
    uniqueFeatureContracts{1};
audit.seeds = allSeeds;
audit.stateCount = numel(allBlocks);
audit.blockSummaries = allBlocks;
audit.preflightOnly = preflightOnly;
audit.featuresTruthFree = ...
    all(~[allBlocks.featuresUseTruth]) && ...
    all(~[allBlocks.featuresUseFutureOutcome]);
audit.teacherBoundaryPassed = ...
    all([allBlocks.targetsUseTruth]) && ...
    all(~[allBlocks.targetsUseFutureOutcome]);
audit.teacherTargetProvenancePassed = ...
    all([records.teacherTargetProvenancePassed]);
audit.shapeGatePassed = ...
    all([allBlocks.shapeGatePassed]);
audit.updateDiagnosticContractPassed = ...
    all([allBlocks.updateDiagnosticContractPassed]);
audit.updateDiagnosticSignalStateFraction = ...
    mean([allBlocks.updateDiagnosticSignalPresent]);
audit.updateDiagnosticSignalPassed = ...
    audit.updateDiagnosticSignalStateFraction >= ...
        protocol.minimumUpdateDiagnosticSignalStateFraction;
audit.actionAlignmentPassed = ...
    all([allBlocks.actionAlignmentPassed]);
audit.cvarMembershipPassed = ...
    all([allBlocks.cvarMembershipPassed]);
audit.selectedTailSafetyPassed = ...
    all([allBlocks.selectedTailSafetyPassed]);
audit.zeroFallbackPassed = ...
    all(~[allBlocks.fallbackUsed]);
audit.zeroInfeasibilityPassed = ...
    all(~[allBlocks.topologyInfeasible]);
audit.zeroRepairPassed = ...
    all(~[allBlocks.repairTriggered]);
audit.zeroEmergencyPassed = ...
    all(~[allBlocks.payloadEmergencyUsed]);
audit.cleanGenerationPassed = all(arrayfun(@(record) ...
    ~isempty(record.generationCommit), records));
audit.allGatesPassed = ...
    audit.featuresTruthFree && ...
    audit.teacherBoundaryPassed && ...
    audit.teacherTargetProvenancePassed && ...
    audit.shapeGatePassed && ...
    audit.updateDiagnosticContractPassed && ...
    audit.updateDiagnosticSignalPassed && ...
    audit.actionAlignmentPassed && ...
    audit.cvarMembershipPassed && ...
    audit.selectedTailSafetyPassed && ...
    audit.zeroFallbackPassed && ...
    audit.zeroInfeasibilityPassed && ...
    audit.zeroRepairPassed && ...
    audit.zeroEmergencyPassed && ...
    audit.cleanGenerationPassed;
audit.modelTrainingAuthorized = false;
audit.heldoutM24Authorized = false;
audit.x36Authorized = false;
audit.auditPath = auditPath;
audit.reportPath = reportPath;
audit.evidenceBoundary = [ ...
    'This audit establishes state/feature/label integrity only. ', ...
    'Current truth is privileged teacher supervision. It does not ', ...
    'establish learned-policy accuracy, return improvement, M24 ', ...
    'generalization, or X36 benefit.'];
if ~audit.allGatesPassed
    error('CVaR residual graph dataset audit failed.');
end
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('CVaR residual graph audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function validateDatasetEnvelope(dataset, protocol)
required = { ...
    'protocolId', 'contractVersion', ...
    'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty', ...
    'seeds', 'labelTimes', ...
    'behaviorCacheRecords', 'behaviorDataset', ...
    'graphBlocks', 'featureContractSha256', ...
    'featuresUseTruth', ...
    'featuresUseFutureOutcome', ...
    'behaviorUsesTruth', ...
    'behaviorUsesFutureOutcome', ...
    'teacherTargetsUseTruth', ...
    'teacherTargetsUseFutureOutcome'};
if ~isstruct(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        dataset.generationTrackedWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        dataset.generationResearchWorktreeDirty || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureOutcome || ...
        dataset.behaviorUsesTruth || ...
        dataset.behaviorUsesFutureOutcome || ...
        ~dataset.teacherTargetsUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome || ...
        numel(dataset.graphBlocks) ~= ...
            numel(dataset.behaviorDataset.blocks) || ...
        any(~ismember(dataset.seeds, ...
            protocol.datasetSeeds)) || ...
        any(ismember(dataset.seeds, ...
            protocol.lockedHeldoutM24Seeds)) || ...
        any(~ismember(dataset.labelTimes, ...
            protocol.learningLabelTimes))
    error('CVaR residual graph dataset envelope is invalid.');
end
end

function validateCacheRecords(dataset, protocol)
if numel(dataset.behaviorCacheRecords) ~= ...
        numel(dataset.seeds)
    error('CVaR residual graph cache records are incomplete.');
end
for record = dataset.behaviorCacheRecords
    protocolIdx = find( ...
        protocol.datasetSeeds == record.seed, 1);
    if isempty(protocolIdx) || ...
            ~strcmp(record.sha256, ...
                protocol. ...
                    behaviorCacheSha256{protocolIdx})
        error('CVaR residual graph cache registry mismatch.');
    end
end
end

function passed = validateTeacherTargetProvenance( ...
        dataset, datasetSha256, protocol)
hasMode = isfield(dataset, ...
    'teacherTargetProvenanceMode');
if ~hasMode
    passed = isequal(dataset.seeds, ...
        protocol.preflightSeeds) && ...
        isequal(dataset.labelTimes, ...
            protocol.preflightLabelTime) && ...
        strcmp(datasetSha256, ...
            protocol.preflightDatasetSha256);
    if ~passed
        error('CVaR graph teacher provenance is missing.');
    end
    return;
end
mode = dataset.teacherTargetProvenanceMode;
if strcmp(mode, 'fresh-current-truth-evaluation')
    passed = isequal(dataset.seeds, ...
        protocol.preflightSeeds) && ...
        dataset.teacherTargetsRecomputed && ...
        ~dataset. ...
            teacherTargetsReusedFromAuditedPredecessor && ...
        isempty(dataset.teacherTargetSourceRecords);
    if ~passed
        error('Fresh teacher evaluation is restricted to preflight.');
    end
    return;
end
if ~strcmp(mode, ...
        'audited-v1-exact-target-reuse') || ...
        dataset.teacherTargetsRecomputed || ...
        ~dataset. ...
            teacherTargetsReusedFromAuditedPredecessor || ...
        ~dataset.predecessorFeatureAlignmentPassed || ...
        numel(dataset.teacherTargetSourceRecords) ~= ...
            numel(dataset.seeds)
    error('CVaR graph reused-teacher provenance envelope failed.');
end
if exist(protocol.predecessorShardAuditPath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256( ...
            protocol.predecessorShardAuditPath), ...
            protocol.predecessorShardAuditSha256)
    error('CVaR graph predecessor audit hash mismatch.');
end
loadedAudit = load( ...
    protocol.predecessorShardAuditPath, 'audit');
if ~isfield(loadedAudit, 'audit') || ...
        ~loadedAudit.audit.allGatesPassed || ...
        ~strcmp(loadedAudit.audit.datasetSetSha256, ...
            protocol.predecessorDatasetSetSha256) || ...
        ~strcmp(loadedAudit.audit.featureContractSha256, ...
            protocol.predecessorFeatureContractSha256)
    error('CVaR graph predecessor audit registry failed.');
end
for recordIdx = 1:numel( ...
        dataset.teacherTargetSourceRecords)
    record = dataset. ...
        teacherTargetSourceRecords(recordIdx);
    registryIdx = find( ...
        protocol.predecessorRegisteredShardSeeds == ...
            record.seed, 1);
    if isempty(registryIdx) || ...
            dataset.seeds(recordIdx) ~= record.seed || ...
            ~strcmp(record.path, protocol. ...
                predecessorRegisteredShardPaths{registryIdx}) || ...
            ~strcmp(record.sha256, protocol. ...
                predecessorRegisteredShardSha256{registryIdx}) || ...
            ~strcmp(record.generationCommit, ...
                protocol.predecessorShardGenerationCommit) || ...
            ~strcmp(record.contractVersion, ...
                protocol. ...
                    predecessorDatasetContractVersion) || ...
            ~strcmp(record.featureContractSha256, ...
                protocol.predecessorFeatureContractSha256) || ...
            exist(record.path, 'file') ~= 2 || ...
            ~strcmp(computeFileSha256(record.path), ...
                record.sha256)
        error('CVaR graph predecessor source record failed.');
    end
    loaded = load(record.path, 'dataset');
    if ~isfield(loaded, 'dataset')
        error('CVaR graph predecessor source dataset is missing.');
    end
    compareReusedTeacherBlocks( ...
        dataset.graphBlocks( ...
            [dataset.graphBlocks.seed] == record.seed), ...
        loaded.dataset.graphBlocks, protocol);
end
passed = true;
end

function compareReusedTeacherBlocks( ...
        currentBlocks, predecessorBlocks, protocol)
predecessorBlocks = predecessorBlocks(ismember( ...
    [predecessorBlocks.currentTime], ...
    protocol.learningLabelTimes));
if numel(currentBlocks) ~= ...
        numel(protocol.learningLabelTimes) || ...
        numel(predecessorBlocks) ~= ...
        numel(protocol.learningLabelTimes)
    error('CVaR graph predecessor state coverage failed.');
end
targetFields = { ...
    'nodeRiskTarget', 'nodeCvarMaskTarget', ...
    'edgeTaskAdvantageTarget', ...
    'edgeProtectionAdvantageTarget', ...
    'edgeProtectionObservedMask', ...
    'edgeReferenceSafeTarget', ...
    'selectedEdgeWeightTarget', ...
    'teacherAdjacency', ...
    'teacherResidualAdjacency', ...
    'teacherCrossReceivers', ...
    'teacherCrossSenders', ...
    'teacherCrossResidualWeights', ...
    'teacherDetails'};
for blockIdx = 1:numel(currentBlocks)
    current = currentBlocks(blockIdx);
    predecessor = predecessorBlocks(blockIdx);
    oldNodeFeatureCount = ...
        size(predecessor.nodeFeatures, 2);
    if current.seed ~= predecessor.seed || ...
            current.currentTime ~= predecessor.currentTime || ...
            ~isequal(current.edgeFeatureNames, ...
                predecessor.edgeFeatureNames) || ...
            ~isequal(current.nodeFeatureNames( ...
                1:oldNodeFeatureCount), ...
                predecessor.nodeFeatureNames) || ...
            ~isequal(current.edgeFeatures, ...
                predecessor.edgeFeatures) || ...
            ~isequal(current.nodeFeatures( ...
                :, 1:oldNodeFeatureCount), ...
                predecessor.nodeFeatures)
        error('CVaR graph predecessor feature alignment failed.');
    end
    for fieldIdx = 1:numel(targetFields)
        fieldName = targetFields{fieldIdx};
        if ~isfield(current, fieldName) || ...
                ~isfield(predecessor, fieldName) || ...
                ~isequaln(current.(fieldName), ...
                    predecessor.(fieldName))
            error(['CVaR graph reused teacher target differs: ', ...
                fieldName, '.']);
        end
    end
end
end

function summary = validateBlock( ...
        block, behaviorBlock, protocol)
candidateCount = numel(block.receiverIndices);
weightCount = numel(block.residualWeightGrid);
nodeCount = size(block.nodeFeatures, 1);
edgeFeatureCount = size(block.edgeFeatures, 3);
nodeFeatureCount = size(block.nodeFeatures, 2);
shapeGatePassed = ...
    isequal(size(block.edgeFeatures), ...
        [candidateCount, weightCount, edgeFeatureCount]) && ...
    isequal(size(block.edgeTaskAdvantageTarget), ...
        [candidateCount, weightCount]) && ...
    isequal(size(block.edgeProtectionAdvantageTarget), ...
        [candidateCount, weightCount]) && ...
    isequal(size(block.edgeProtectionObservedMask), ...
        [candidateCount, weightCount]) && ...
    isequal(size(block.edgeReferenceSafeTarget), ...
        [candidateCount, weightCount]) && ...
    isequal(size(block.selectedEdgeWeightTarget), ...
        [candidateCount, weightCount]) && ...
    numel(block.nodeRiskTarget) == nodeCount && ...
    numel(block.nodeCvarMaskTarget) == nodeCount && ...
    numel(block.edgeFeatureNames) == edgeFeatureCount && ...
    numel(block.nodeFeatureNames) == nodeFeatureCount && ...
    all(isfinite(block.edgeFeatures(:))) && ...
    all(isfinite(block.nodeFeatures(:))) && ...
    all(isfinite(block.nodeRiskTarget(:)));
if ~shapeGatePassed
    error('CVaR residual graph block shape gate failed.');
end
expectedUpdateNames = { ...
    'update_innovation_current', ...
    'update_innovation_mean', ...
    'update_innovation_max', ...
    'update_innovation_trend', ...
    'update_association_current', ...
    'update_association_mean', ...
    'update_association_min', ...
    'update_association_trend', ...
    'update_log_nis_norm_current', ...
    'update_log_nis_norm_mean', ...
    'update_log_nis_norm_max', ...
    'update_log_nis_norm_trend', ...
    'update_log_nis_deviation_current', ...
    'update_log_nis_deviation_mean', ...
    'update_log_nis_deviation_max', ...
    'update_nis_available_fraction'};
updateDiagnosticContractPassed = ...
    nodeFeatureCount >= numel(expectedUpdateNames) && ...
    isequal(block.nodeFeatureNames( ...
        (end - numel(expectedUpdateNames) + 1):end), ...
        expectedUpdateNames);
if ~updateDiagnosticContractPassed
    error('CVaR residual graph update-diagnostic contract failed.');
end
updateFeatures = block.nodeFeatures(:, ...
    (end - numel(expectedUpdateNames) + 1):end);
innovationCurrent = updateFeatures(:, 1);
associationCurrent = updateFeatures(:, 5);
nisAvailableFraction = updateFeatures(:, 16);
updateDiagnosticSignalPresent = ...
    any(abs(innovationCurrent) > 1e-12) || ...
    any(abs(associationCurrent - 1) > 1e-12) || ...
    any(nisAvailableFraction > 0);
edgeKeys = block.receiverIndices + ...
    nodeCount * (block.senderIndices - 1);
actionAlignmentPassed = ...
    numel(unique(edgeKeys)) == candidateCount && ...
    numel(block.residualBaselineSourcesByReceiver) == nodeCount && ...
    numel(block.dominantSourcesByReceiver) == nodeCount && ...
    all(block.residualBaselineSourcesByReceiver >= 1 & ...
        block.residualBaselineSourcesByReceiver <= nodeCount) && ...
    all(block.dominantSourcesByReceiver >= 1 & ...
        block.dominantSourcesByReceiver <= nodeCount) && ...
    behaviorBlock.seed == block.seed && ...
    behaviorBlock.currentTime == block.currentTime && ...
    ~behaviorBlock.actionTruthUsed && ...
    ~behaviorBlock.labelTruthUsed && ...
    isequal(block.residualWeightGrid, ...
        protocol.residualWeightGrid) && ...
    nnz(block.selectedEdgeWeightTarget) == ...
        protocol.expectedCrossCycleEdgeCount;
if ~actionAlignmentPassed
    error('CVaR residual graph action alignment failed.');
end
[~, riskOrder] = sort( ...
    block.nodeRiskTarget, 'descend');
expectedTail = false(1, nodeCount);
expectedTail(riskOrder(1: ...
    protocol.expectedProtectedReceiverCount)) = true;
cvarMembershipPassed = isequal( ...
    logical(block.nodeCvarMaskTarget), expectedTail);
if ~cvarMembershipPassed
    error('CVaR residual graph tail membership is invalid.');
end
selectedRows = find(any( ...
    block.selectedEdgeWeightTarget, 2));
selectedTailRows = selectedRows( ...
    expectedTail(block.receiverIndices(selectedRows)));
selectedTailSafetyPassed = true;
for rowIdx = reshape(selectedTailRows, 1, [])
    weightIdx = find( ...
        block.selectedEdgeWeightTarget(rowIdx, :), 1);
    selectedTailSafetyPassed = ...
        selectedTailSafetyPassed && ...
        block.edgeProtectionObservedMask( ...
            rowIdx, weightIdx) && ...
        block.edgeReferenceSafeTarget( ...
            rowIdx, weightIdx);
end
if ~selectedTailSafetyPassed
    error('CVaR residual graph selected tail action is unsafe.');
end
details = block.teacherDetails;
summary = emptyBlockSummary();
summary.seed = block.seed;
summary.currentTime = block.currentTime;
summary.candidateCount = candidateCount;
summary.weightCount = weightCount;
summary.edgeFeatureCount = edgeFeatureCount;
summary.nodeFeatureCount = nodeFeatureCount;
summary.tailNodeCount = nnz(expectedTail);
summary.selectedEdgeWeightCount = ...
    nnz(block.selectedEdgeWeightTarget);
summary.featuresUseTruth = block.featuresUseTruth;
summary.featuresUseFutureOutcome = ...
    block.featuresUseFutureOutcome;
summary.targetsUseTruth = block.targetsUseTruth;
summary.targetsUseFutureOutcome = ...
    block.targetsUseFutureOutcome;
summary.shapeGatePassed = shapeGatePassed;
summary.updateDiagnosticContractPassed = ...
    updateDiagnosticContractPassed;
summary.updateDiagnosticSignalPresent = ...
    updateDiagnosticSignalPresent;
summary.actionAlignmentPassed = ...
    actionAlignmentPassed;
summary.cvarMembershipPassed = ...
    cvarMembershipPassed;
summary.selectedTailSafetyPassed = ...
    selectedTailSafetyPassed;
summary.fallbackUsed = ...
    details.tailSafeFallbackUsed;
summary.topologyInfeasible = ...
    details.topologyInfeasible;
summary.repairTriggered = details.repairTriggered;
summary.payloadEmergencyUsed = ...
    details.payloadEmergencyUsed;
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open CVaR residual graph audit report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 CVaR residual graph dataset audit\n\n');
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Audit contract: `%s`\n', ...
    audit.contractVersion);
fprintf(fid, '- Audit commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Dataset-set SHA-256: `%s`\n', ...
    audit.datasetSetSha256);
fprintf(fid, '- Feature contract SHA-256: `%s`\n', ...
    audit.featureContractSha256);
fprintf(fid, '- Seeds: `%s`\n', mat2str(audit.seeds));
fprintf(fid, '- States: `%d`\n', audit.stateCount);
fprintf(fid, '- Preflight-only: `%d`\n', ...
    audit.preflightOnly);
fprintf(fid, '- All gates passed: `%d`\n', ...
    audit.allGatesPassed);
fprintf(fid, '- Teacher target provenance passed: `%d`\n', ...
    audit.teacherTargetProvenancePassed);
fprintf(fid, ...
    '- Update-diagnostic signal state fraction: `%.6f`\n', ...
    audit.updateDiagnosticSignalStateFraction);
fprintf(fid, '- Model training authorized: `%d`\n', ...
    audit.modelTrainingAuthorized);
fprintf(fid, '- Held-out M24 authorized: `%d`\n', ...
    audit.heldoutM24Authorized);
fprintf(fid, '- X36 authorized: `%d`\n', ...
    audit.x36Authorized);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    audit.evidenceBoundary);
fprintf(fid, ...
    ['| Seed | Time | Candidates | Weights | Edge F | Node F | ', ...
     'Tail | Selected | Safe |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for block = audit.blockSummaries
    fprintf(fid, ...
        '| %d | %d | %d | %d | %d | %d | %d | %d | %d |\n', ...
        block.seed, block.currentTime, ...
        block.candidateCount, block.weightCount, ...
        block.edgeFeatureCount, block.nodeFeatureCount, ...
        block.tailNodeCount, ...
        block.selectedEdgeWeightCount, ...
        block.selectedTailSafetyPassed);
end
end

function record = emptyRecord()
record = struct( ...
    'path', '', ...
    'sha256', '', ...
    'generationCommit', '', ...
    'teacherTargetProvenancePassed', false, ...
    'seeds', [], ...
    'times', [], ...
    'stateCount', 0);
end

