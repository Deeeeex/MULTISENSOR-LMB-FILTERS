    'selectedEdgeWeightCount', 0, ...
    'featuresUseTruth', true, ...
    'featuresUseFutureOutcome', true, ...
    'targetsUseTruth', false, ...
    'targetsUseFutureOutcome', true, ...
    'shapeGatePassed', false, ...
    'updateDiagnosticContractPassed', false, ...
    'updateDiagnosticSignalPresent', false, ...
    'actionAlignmentPassed', false, ...
    'cvarMembershipPassed', false, ...
    'selectedTailSafetyPassed', false, ...
    'fallbackUsed', true, ...
    'topologyInfeasible', true, ...
    'repairTriggered', true, ...
    'payloadEmergencyUsed', true);
