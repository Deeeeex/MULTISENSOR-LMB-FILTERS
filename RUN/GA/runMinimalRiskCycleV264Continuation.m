inputs.model.dynamicTopologyScenario.config.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
for name = {'x', 'mu', 'Sigma'}
    inputs.groundTruthRfs.(name{1}) = ...
        inputs.groundTruthRfs.(name{1})(1:maximumTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maximumTime);
inputs.commConfig.pDropByEdge = ...
    inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function assertCandidate(candidate, comparison, config, protocol)
formationCount = numel(unique(config.sensorGroupIds));
treeMessages = config.numberOfSensors + 2 * (formationCount - 1);
expectedMessages = treeMessages + ...
    protocol.additionalDirectedMessages * ...
        double(candidate.cycleActiveByTime);
passed = candidate.completed && candidate.physicalFeasibilityPassed && ...
    candidate.instantaneousStrongPassed && ~candidate.policyTruthUsed && ...
    ~candidate.policyFutureOutcomeUsed && ...
    all(candidate.messageCountByTime == expectedMessages) && ...
    ~isempty(candidate.cycleInitiationTimes) && ...
    any(candidate.cycleActiveByTime) && ...
    all(candidate.pairwiseDistanceDominancePassedByTime( ...
        candidate.cycleActiveByTime)) && ...
    all(candidate.strictDilationRepairPassedByTime( ...
        candidate.cycleActiveByTime)) && ...
    islogical(comparison.shortHorizonGatePassed);
if ~passed
    error('MinimalRiskCycleV264:RuntimeContract', ...
        'The V264 continuation violated its route or evidence contract.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('MinimalRiskCycleV264:ReportOpen', ...
        'Unable to write the V264 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
base = result.v242;
candidate = result.candidate;
comparison = result.comparison;
fprintf(fid, '# V264 minimal risk cycle\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Continuation: `t=%d--%d` from the V259 V242 state\n', ...
    result.protocol.continuationStartTime, ...
    result.protocol.continuationEndTime);
fprintf(fid, '- Cycle initiated / active pages: `%s / %s`\n', ...
    mat2str(candidate.cycleInitiationTimes), ...
    mat2str(candidate.cycleActiveTimes));
fprintf(fid, '- Active pages dominate both tree distance vectors: `%d`\n', ...
    all(candidate.pairwiseDistanceDominancePassedByTime( ...
        candidate.cycleActiveByTime)));
fprintf(fid, '- Active protective formation pairs: `%s`\n', ...
    formatPairHistory(candidate.protectiveFormationPairIdsByTime, ...
        candidate.cycleActiveByTime));
fprintf(fid, '- Mechanism / full-M24 authorization: `%d / %d`\n\n', ...
    result.actionMechanismPassed, result.fullM24RunAuthorized);
fprintf(fid, ['| Arm | E-OSPA | RMSE | Consistency | F4 event E / RMSE | ', ...
    'Window bytes | Spliced static saving |\n']);
fprintf(fid, '|:--|--:|--:|--:|:--|--:|--:|\n');
writeArm(fid, base);
writeArm(fid, candidate);
fprintf(fid, '\n## Gains over V242\n\n');
fprintf(fid, '| Scope | E-OSPA | RMSE |\n');
fprintf(fid, '|:--|--:|--:|\n');
fprintf(fid, '| Network | `%+.3f%%` | `%+.3f%%` |\n', ...
    comparison.eospaGainPercent, comparison.rmseGainPercent);
fprintf(fid, '| F4 event | `%+.3f%%` | `%+.3f%%` |\n', ...
    comparison.eventFormationEospaGainPercent, ...
    comparison.eventFormationRmseGainPercent);
fprintf(fid, '| Weakest formation | `%+.3f%%` | `%+.3f%%` |\n\n', ...
    comparison.minimumFormationEospaGainPercent, ...
    comparison.minimumFormationRmseGainPercent);
fprintf(fid, '- Consistency gain: `%+.3f%%`\n', ...
    comparison.consistencyGainPercent);
fprintf(fid, '- Window byte change vs V242: `%+.3f%%`\n', ...
    candidate.windowByteChangeOverV242Percent);
fprintf(fid, '- Short-horizon gate: `%d`\n', ...
    comparison.shortHorizonGatePassed);
fprintf(fid, '- Next method decision: `%s`\n\n', ...
    result.nextMethodDecision);
fprintf(fid, '## Decision\n\n');
if result.actionMechanismPassed
    fprintf(fid, ['The minimally redundant risk cycle repairs the ', ...
        'diagnosed F4 event while preserving all registered guards and ', ...
        'remaining below static communication. Run one complete M24 ', ...
        'candidate without changing its edge or weight rule.\n\n']);
else
    fprintf(fid, ['One protective cycle edge does not repair the ', ...
        'diagnosed event under the registered guards. Close topology-', ...
        'only routing and test label-selective edge trust before any ', ...
        'learned ranker.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function writeArm(fid, arm)
fprintf(fid, ['| %s | %.3f | %.3f | %.3f | %.3f / %.3f | ', ...
    '%.0f | %.3f%% |\n'], arm.name, arm.positionEospa, ...
    arm.positionRmse, arm.interFormationPositionOspa, ...
    arm.eventFormationEospa, arm.eventFormationRmse, ...
    arm.windowAttemptedPayloadBytes, ...
    arm.splicedStaticByteSavingPercent);
end

function text = formatPairHistory(pairsByTime, activeMask)
activePairs = pairsByTime(activeMask);
if isempty(activePairs)
    text = '--';
    return;
end
parts = cell(1, numel(activePairs));
for pairIdx = 1:numel(activePairs)
    parts{pairIdx} = mat2str(activePairs{pairIdx});
end
text = strjoin(parts, ',');
end

function complete = isCompleteResult(result)
complete = isstruct(result) && isscalar(result) && ...
    isfield(result, 'contractVersion') && ...
    strcmp(result.contractVersion, ...
        'minimal-risk-cycle-v264-result-v1') && ...
    isfield(result, 'candidate') && result.candidate.completed;
end

function value = lowerGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = lowerGainVector(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = mean(values); end
end

function value = anyFiniteNonzero(values)
values = values(isfinite(values));
value = any(values ~= 0);
end

function connected = isStronglyConnected(adjacency)
connected = reachesAll(adjacency) && reachesAll(adjacency');
end

function passed = reachesAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node), continue; end
    visited(node) = true;
    frontier = [frontier, find(adjacency(node, :) & ~visited)]; ...
        %#ok<AGROW>
end
passed = all(visited);
end

function value = conditionalValue(condition, left, right)
if condition, value = left; else, value = right; end
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    (~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once'))));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
