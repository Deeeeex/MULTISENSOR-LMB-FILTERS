function [reportPath, audit] = ...
    auditRollingSafeJointActionProposalDataset(options)
% AUDITROLLINGSAFEJOINTACTIONPROPOSALDATASET Formal M24 proposal audit.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
datasetPath = getField(options, 'datasetPath', ...
    protocol.proposalDatasetRelativePath);
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'JOINT_ACTION_PROPOSAL_PREFLIGHT_M24.md'));
if exist(datasetPath, 'file') ~= 2 || ...
        exist(sourcePath, 'file') ~= 2
    error('Proposal audit requires both frozen MAT artifacts.');
end
datasetSha256 = computeFileSha256(datasetPath);
sourceSha256 = computeFileSha256(sourcePath);
if ~strcmp(datasetSha256, protocol.proposalDatasetSha256) || ...
        ~strcmp(sourceSha256, protocol.proposalSourceStateSha256)
    error('Proposal audit artifact SHA-256 mismatch.');
end
loaded = load(datasetPath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
if ~isfield(loaded, 'dataset') || ...
        ~isfield(sourceLoaded, 'dataset')
    error('Proposal audit MAT file lacks dataset.');
end
dataset = loaded.dataset;
source = sourceLoaded.dataset;
validateDatasetEnvelope(dataset, source, protocol);

expectedPairs = zeros( ...
    numel(protocol.datasetSeeds) * ...
        numel(protocol.snapshotTimes), 2);
cursor = 0;
for seed = protocol.datasetSeeds
    for currentTime = protocol.snapshotTimes
        cursor = cursor + 1;
        expectedPairs(cursor, :) = [seed, currentTime];
    end
end
observedPairs = [[dataset.blocks.seed]', ...
    [dataset.blocks.currentTime]'];
if ~isequal(observedPairs, expectedPairs)
    error('Proposal blocks do not follow the frozen seed-time grid.');
end

minimumFeatureDistance = inf;
featureCollisionCount = 0;
maximumFeatureReplayDifference = 0;
totalSelectable = 0;
totalReferenceOnly = 0;
totalDistinct = 0;
totalDuplicates = 0;
totalUnavailable = 0;
blockRows = repmat(struct( ...
    'seed', NaN, 'currentTime', NaN, ...
    'distinctCount', NaN, 'selectableCount', NaN, ...
    'duplicateCount', NaN, 'unavailableCount', NaN, ...
    'referenceRequiredRepair', false, ...
    'minimumFeatureDistance', NaN), ...
    1, numel(dataset.blocks));
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    sourceBlock = source.blocks(block.sourceBlockIndex);
    validateSourceBlockIdentity(block, sourceBlock);
    candidateCount = block.candidateCount;
    if candidateCount < 1 || ...
            candidateCount > protocol.maximumCandidateCount || ...
            size(block.candidateAdjacency, 3) ~= candidateCount || ...
            size(block.candidateCrossMasks, 2) ~= candidateCount || ...
            size(block.jointFeatures, 1) ~= candidateCount || ...
            numel(block.candidateRecords) ~= candidateCount || ...
            numel(unique(block.candidateGraphSha256)) ~= ...
                candidateCount
        error('Proposal block candidate arrays are invalid.');
    end
    if block.referenceCandidateIndex < 1 || ...
            block.referenceCandidateIndex > candidateCount || ...
            ~any(block.candidateRecords( ...
                block.referenceCandidateIndex). ...
                    proposalActionCodes == ...
                        protocol.referenceActionCode)
        error('Proposal block lacks the frozen action-24 reference.');
    end
    if ~block.proposalMetadata.defaultFrozenBankUsed || ...
            block.proposalMetadata.truthUsed || ...
            block.proposalMetadata.futureOutcomeUsed || ...
            block.proposalMetadata.candidateRankingPerformed || ...
            ~strcmp(block.proposalMetadata. ...
                actionCodeSetSha256, ...
                protocol.proposalActionCodeSetSha256)
        error('Proposal block metadata violates the frozen bank.');
    end
    nodeCount = numel(sourceBlock.groupIds);
    edgeKeys = sub2ind([nodeCount, nodeCount], ...
        sourceBlock.receiverIndices, ...
        sourceBlock.senderIndices);
    referenceAdjacency = block.candidateAdjacency( ...
        :, :, block.referenceCandidateIndex);
    referenceMask = reshape(logical( ...
        referenceAdjacency(edgeKeys)), [], 1);
    blockMinimumDistance = inf;
    selectableCount = 0;
    referenceOnlyCount = 0;
    for candidateIdx = 1:candidateCount
        adjacency = block.candidateAdjacency( ...
            :, :, candidateIdx);
        record = block.candidateRecords(candidateIdx);
        details = record.policyDetails;
        validateCandidateAttestation( ...
            adjacency, record, details, sourceBlock, ...
            candidateIdx, block.referenceCandidateIndex);
        actionMask = reshape(logical( ...
            adjacency(edgeKeys)), [], 1);
        if ~isequal(actionMask, ...
                block.candidateCrossMasks(:, candidateIdx))
            error('Proposal cross mask does not match its graph.');
        end
        expectedGraphSha256 = computeTextSha256( ...
            sprintf('%d,', ...
            details.selectedSourcesByReceiver));
        if ~strcmp(expectedGraphSha256, ...
                block.candidateGraphSha256{candidateIdx}) || ...
                ~strcmp(expectedGraphSha256, ...
                    record.graphSha256)
            error('Proposal graph SHA-256 attestation failed.');
        end
        featureOptions = struct( ...
            'referenceCrossMask', referenceMask, ...
            'actionProposalTruthUsed', false, ...
            'actionProposalOutcomeSelected', false, ...
            'actionProposalSource', ...
                protocol.proposalBankContractVersion);
        replayed = computeRollingSafeJointActionFeatures( ...
            sourceBlock, actionMask, featureOptions);
        replayDifference = max(abs( ...
            replayed - block.jointFeatures(candidateIdx, :)));
        maximumFeatureReplayDifference = max( ...
            maximumFeatureReplayDifference, replayDifference);
        if record.eligibleForCriticSelection
            selectableCount = selectableCount + 1;
        else
            referenceOnlyCount = referenceOnlyCount + 1;
        end
        if candidateIdx < candidateCount
            distances = sqrt(sum(( ...
                block.jointFeatures( ...
                    candidateIdx + 1:end, :) - ...
                block.jointFeatures(candidateIdx, :)) .^ 2, 2));
            blockMinimumDistance = min( ...
                blockMinimumDistance, min(distances));
            featureCollisionCount = featureCollisionCount + ...
                nnz(distances <= ...
                    protocol.minimumRegisteredActionDistance);
        end
    end
    if selectableCount ~= block.selectableCandidateCount || ...
            selectableCount ~= ...
                block.proposalMetadata.selectableCandidateCount || ...
            referenceOnlyCount > 1 || selectableCount < 1
        error('Proposal selectable/reference-only counts are invalid.');
    end
    minimumFeatureDistance = min( ...
        minimumFeatureDistance, blockMinimumDistance);
    totalSelectable = totalSelectable + selectableCount;
    totalReferenceOnly = ...
        totalReferenceOnly + referenceOnlyCount;
    totalDistinct = totalDistinct + candidateCount;
    totalDuplicates = totalDuplicates + ...
        block.proposalMetadata.duplicateCount;
    totalUnavailable = totalUnavailable + ...
        block.proposalMetadata.unavailableCount;
    blockRows(blockIdx) = struct( ...
        'seed', block.seed, ...
        'currentTime', block.currentTime, ...
        'distinctCount', candidateCount, ...
        'selectableCount', selectableCount, ...
        'duplicateCount', ...
            block.proposalMetadata.duplicateCount, ...
        'unavailableCount', ...
            block.proposalMetadata.unavailableCount, ...
        'referenceRequiredRepair', ...
            block.proposalMetadata.referenceRequiredRepair, ...
        'minimumFeatureDistance', blockMinimumDistance);
end

accepted = ...
    featureCollisionCount == 0 && ...
    maximumFeatureReplayDifference <= 1e-12 && ...
    all([blockRows.distinctCount] <= ...
        protocol.maximumCandidateCount) && ...
    all([blockRows.selectableCount] >= 1);
if ~accepted
    error('Proposal preflight failed its frozen structural gates.');
end
audit = struct();
audit.contractVersion = ...
    protocol.proposalAuditContractVersion;
audit.protocolId = protocol.id;
audit.datasetPath = datasetPath;
audit.datasetSha256 = datasetSha256;
audit.sourceStateSha256 = sourceSha256;
audit.generationCommit = dataset.generationGitCommit;
audit.blockCount = numel(dataset.blocks);
audit.totalDistinctCandidateCount = totalDistinct;
audit.totalSelectableCandidateCount = totalSelectable;
audit.totalReferenceOnlyCandidateCount = totalReferenceOnly;
audit.totalDuplicateProposalCount = totalDuplicates;
audit.totalUnavailableProposalCount = totalUnavailable;
audit.minimumDistinctCandidateCount = ...
    min([blockRows.distinctCount]);
audit.maximumDistinctCandidateCount = ...
    max([blockRows.distinctCount]);
audit.minimumSelectableCandidateCount = ...
    min([blockRows.selectableCount]);
audit.maximumSelectableCandidateCount = ...
    max([blockRows.selectableCount]);
audit.repairedReferenceBlockCount = nnz( ...
    [blockRows.referenceRequiredRepair]);
audit.minimumDistinctGraphFeatureDistance = ...
    minimumFeatureDistance;
audit.featureCollisionCount = featureCollisionCount;
audit.maximumFeatureReplayDifference = ...
    maximumFeatureReplayDifference;
audit.blockRows = blockRows;
audit.acceptedForPairedH3ReturnGeneration = accepted;
audit.acceptedForCriticTraining = false;
audit.acceptedForX36ZeroShot = false;
writeAuditReport(reportPath, audit, protocol);
fprintf(['Proposal preflight: %d distinct, %d selectable, ', ...
    'min distance %.8g, collisions %d.\nReport: %s\n'], ...
    totalDistinct, totalSelectable, minimumFeatureDistance, ...
    featureCollisionCount, reportPath);
end

function validateDatasetEnvelope(dataset, source, protocol)
if ~strcmp(dataset.contractVersion, ...
        protocol.proposalDatasetContractVersion) || ...
        ~strcmp(dataset.proposalBankContractVersion, ...
            protocol.proposalBankContractVersion) || ...
        ~strcmp(dataset.sourceStateSha256, ...
            protocol.proposalSourceStateSha256) || ...
        ~strcmp(dataset.generationGitCommit, ...
            protocol.proposalDatasetGenerationCommit) || ...
        dataset.generationTrackedWorktreeDirty || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(dataset.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        dataset.maximumCandidateCount ~= ...
            protocol.maximumCandidateCount || ...
        ~isequal(dataset.proposalActionCodes, ...
            protocol.proposalActionCodes) || ...
        ~strcmp(dataset.proposalActionCodeSetSha256, ...
            protocol.proposalActionCodeSetSha256) || ...
        dataset.truthUsed || dataset.futureOutcomeUsed || ...
        dataset.returnEvaluated || ...
        dataset.candidateRankingPerformed || ...
        ~dataset.continuationPosteriorsStored || ...
        ~strcmp(source.contractVersion, ...
            protocol.datasetContractVersion)
    error('Proposal dataset envelope violates the frozen protocol.');
end
end

function validateSourceBlockIdentity(block, sourceBlock)
if block.seed ~= sourceBlock.seed || ...
        block.currentTime ~= sourceBlock.currentTime || ...
        isempty(block.initialLocalPosteriorBySensor)
    error('Proposal continuation state is missing or misaligned.');
end
end

function validateCandidateAttestation( ...
        adjacency, record, details, sourceBlock, ...
        candidateIdx, referenceIdx)
if ~islogical(adjacency) || ...
        any(sum(adjacency, 2) ~= 1) || ...
        any(adjacency(:) & ...
            ~sourceBlock.physicalAdjacency(:)) || ...
        details.truthUsed || ...
        details.actionSequenceTruthUsed || ...
        ~details.oneStepJointProjectionUsed || ...
        ~details.sensorWindowStrongConnected || ...
        ~details.formationWindowStrongConnected || ...
        details.payloadEmergencyUsed || ...
        ~details.payloadLimitPassed
    error('Proposal candidate safety/truth attestation failed.');
end
if details.oneStepTopologyReserveChecked && ...
        ~details.oneStepTopologyReservePassed
    error('Proposal candidate reserve witness failed.');
end
if record.eligibleForCriticSelection
    if details.repairTriggered
        error('A selectable candidate uses a realized repair.');
    end
elseif candidateIdx ~= referenceIdx || ...
        ~details.repairTriggered
    error('Only a repaired reference may be non-selectable.');
end
end

function writeAuditReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open proposal audit report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Joint-action proposal preflight: M24\n\n');
fprintf(fid, '- Generated: %s\n', datestr(now, 31));
fprintf(fid, '- Audit contract: `%s`\n', ...
    audit.contractVersion);
fprintf(fid, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fid, '- Dataset SHA-256: `%s`\n', ...
    audit.datasetSha256);
fprintf(fid, '- Source state SHA-256: `%s`\n', ...
    audit.sourceStateSha256);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationCommit);
fprintf(fid, '- Blocks: `%d`\n', audit.blockCount);
fprintf(fid, '- Distinct candidates: `%d`\n', ...
    audit.totalDistinctCandidateCount);
fprintf(fid, '- Selectable candidates: `%d`\n', ...
    audit.totalSelectableCandidateCount);
fprintf(fid, '- Reference-only candidates: `%d`\n', ...
    audit.totalReferenceOnlyCandidateCount);
fprintf(fid, '- Distinct candidates min/max: `%d / %d`\n', ...
    audit.minimumDistinctCandidateCount, ...
    audit.maximumDistinctCandidateCount);
fprintf(fid, '- Selectable candidates min/max: `%d / %d`\n', ...
    audit.minimumSelectableCandidateCount, ...
    audit.maximumSelectableCandidateCount);
fprintf(fid, '- Repaired reference blocks: `%d`\n', ...
    audit.repairedReferenceBlockCount);
fprintf(fid, '- Minimum distinct-graph feature distance: `%.12g`\n', ...
    audit.minimumDistinctGraphFeatureDistance);
fprintf(fid, '- Feature collisions at <= %.3g: `%d`\n', ...
    protocol.minimumRegisteredActionDistance, ...
    audit.featureCollisionCount);
fprintf(fid, '- Maximum feature replay difference: `%.12g`\n', ...
    audit.maximumFeatureReplayDifference);
fprintf(fid, '- Accepted for paired H=3 returns: `%d`\n', ...
    audit.acceptedForPairedH3ReturnGeneration);
fprintf(fid, '- Accepted for critic training: `%d`\n', ...
    audit.acceptedForCriticTraining);
fprintf(fid, '- Accepted for X36 zero-shot: `%d`\n\n', ...
    audit.acceptedForX36ZeroShot);
fprintf(fid, '## State blocks\n\n');
fprintf(fid, ['| Seed | Time | Distinct | Selectable | ', ...
    'Duplicates | Unavailable | Reference repaired | ', ...
    'Minimum feature distance |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for row = audit.blockRows
    fprintf(fid, ...
        '| %d | %d | %d | %d | %d | %d | %d | %.8g |\n', ...
        row.seed, row.currentTime, row.distinctCount, ...
        row.selectableCount, row.duplicateCount, ...
        row.unavailableCount, row.referenceRequiredRepair, ...
        row.minimumFeatureDistance);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, ['PASS: all 18 frozen M24 states retain at least one ', ...
    'repair-free selectable action, every complete graph is unique ', ...
    'within its state, all 341 feature vectors replay exactly, and ', ...
    'no distinct graph pair collides at the frozen threshold. Paired ', ...
    'H=3 return generation may proceed.\n\n']);
fprintf(fid, '## Evidence boundary\n\n');
fprintf(fid, ['This preflight verifies construction, safety ', ...
    'attestation, exact feature replay and within-state representation ', ...
    'separation. It does not evaluate tracking return, top-K coverage, ', ...
    'candidate-oracle gain, critic accuracy, X36 support or control-', ...
    'metadata traffic. Three repaired action-24 graphs are retained ', ...
    'only as matched references and are not critic-selectable.\n']);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
