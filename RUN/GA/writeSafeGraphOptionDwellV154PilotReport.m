function writeSafeGraphOptionDwellV154PilotReport(path, summary)
% WRITESAFEGRAPHOPTIONDWELLV154PILOTREPORT Render option pilot summary.

fid = fopen(path, 'w');
if fid < 0
    error('Could not write V154 pilot report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V154 propagation-coherent safe graph-option pilot\n\n');
fprintf(fid, '- Preset / seed / window: `%s / %d / %d:%d`\n', ...
    summary.presetName, summary.seed, summary.analysisWindow);
fprintf(fid, '- Formation-scale dwell: `%d pages`\n', ...
    summary.optionDwellPages);
fprintf(fid, '- Better static reference: `%s`\n', ...
    summary.referenceArmMode);
fprintf(fid, '- Selected option: `%s`\n', summary.selectedArmMode);
fprintf(fid, '- Retained options: `%d / %d`\n', ...
    summary.retainedOptionCount, summary.optionCount);
fprintf(fid, '- Attempted-byte increase ceiling: `%.1f%%`\n\n', ...
    summary.maximumAttemptedByteIncreasePercent);
fprintf(fid, ['| Mean gain | Worst-sensor gain | Minimum-formation gain | ', ...
    'Consensus gain | Attempted-byte saving | 5%% pilot gate |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--:|\n');
fprintf(fid, '| %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n\n', ...
    summary.oracleGainPercent, summary.worstSensorGainPercent, ...
    summary.minimumFormationGainPercent, ...
    summary.consensusGainPercent, ...
    summary.attemptedByteSavingPercent, ...
    summary.pilotMeanGatePassed);

fprintf(fid, '## Complete graph options\n\n');
fprintf(fid, ['| Rank | Mean gain | Worst-sensor gain | ', ...
    'Minimum-formation gain | Consensus gain | Byte saving | ', ...
    'Route changes | Schedule pass | Structure pass | Retained |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|:--:|\n');
for idx = 1:summary.optionCount
    fprintf(fid, ['| %d | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d | %d | %d | %d |\n'], ...
        idx, summary.optionMeanGainPercent(idx), ...
        summary.optionWorstSensorGainPercent(idx), ...
        summary.optionMinimumFormationGainPercent(idx), ...
        summary.optionConsensusGainPercent(idx), ...
        summary.optionAttemptedByteSavingPercent(idx), ...
        summary.optionRouteChangeCount(idx), ...
        summary.optionSchedulePass(idx), ...
        summary.optionStructurePass(idx), ...
        summary.optionRetained(idx));
end
fprintf(fid, '\n## Boundary\n\n%s\n', summary.claimBoundary);
end
