function completedPaths = ...
    runCounterfactualRegretGateV133BaselineWorker( ...
        workerIndex, workerCount, options)
% RUNCOUNTERFACTUALREGRETGATEV133BASELINEWORKER Parallel seed worker.
%
% Development trajectories are assigned by seed, so both carriers and
% both scales for a seed stay on one worker while different seeds execute
% independently.  Each completed arm is checkpointed by the shard runner.

if nargin < 2 || isempty(workerCount)
    workerCount = 4;
end
if nargin < 3 || isempty(options)
    options = struct();
end
if ~isscalar(workerIndex) || ~isscalar(workerCount) || ...
        any(~isfinite([workerIndex, workerCount])) || ...
        workerIndex ~= round(workerIndex) || ...
        workerCount ~= round(workerCount) || ...
        workerIndex < 1 || workerIndex > workerCount
    error('CounterfactualRegretV133:InvalidBaselineWorker', ...
        'workerIndex must be an integer in 1:workerCount.');
end
protocol = getCounterfactualRegretGateV133Protocol();
assignedSeedIndices = workerIndex:workerCount: ...
    numel(protocol.developmentSeeds);
completedPaths = cell(1, ...
    numel(assignedSeedIndices) * numel(protocol.scaleCases) * ...
        numel(protocol.referenceCarrierModes));
cursor = 0;
for seedIdx = assignedSeedIndices
    seed = protocol.developmentSeeds(seedIdx);
    for caseInfo = protocol.scaleCases
        for carrierIdx = 1:numel(protocol.referenceCarrierModes)
            cursor = cursor + 1;
            completedPaths{cursor} = ...
                runCounterfactualRegretGateV133BaselineShard( ...
                    caseInfo.presetName, seed, ...
                    protocol.referenceCarrierModes{carrierIdx}, ...
                    options);
        end
    end
end
completedPaths = completedPaths(1:cursor);
fprintf('V133 baseline worker %d/%d completed %d shards.\n', ...
    workerIndex, workerCount, numel(completedPaths));
end
