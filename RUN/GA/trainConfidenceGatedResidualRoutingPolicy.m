function [modelPath, reportPath, result] = ...
    trainConfidenceGatedResidualRoutingPolicy(options)
% TRAINCONFIDENCEGATEDRESIDUALROUTINGPOLICY Fit and save residual policy.

if nargin < 1 || isempty(options)
    options = struct();
end
artifactDirectory = getField(options, 'artifactDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
trainingDatasetPaths = getField(options, ...
    'trainingDatasetPaths', { ...
        fullfile(artifactDirectory, 'cache', ...
            'directed_teacher_v2_m24_hard_seed7_t75.mat'), ...
        fullfile(artifactDirectory, 'cache', ...
            'directed_teacher_v2_m24_hard_seed17_t75.mat')});
calibrationDatasetPaths = getField(options, ...
    'calibrationDatasetPaths', {fullfile( ...
        artifactDirectory, 'cache', ...
        'directed_teacher_v2_m24_hard_seed11_t75.mat')});
modelPath = getField(options, 'modelPath', fullfile( ...
    artifactDirectory, 'models', ...
    'confidence_gated_residual_m24_t75.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    artifactDirectory, ...
    'CONFIDENCE_GATED_RESIDUAL_MODEL_M24_T75.md'));
fitOptions = getField(options, 'fitOptions', struct());

[model, trainingSummary] = ...
    fitConfidenceGatedResidualRoutingModel( ...
        trainingDatasetPaths, calibrationDatasetPaths, fitOptions);
model.trainingMetadata = struct( ...
    'trainingDatasetPaths', {trainingDatasetPaths}, ...
    'calibrationDatasetPaths', {calibrationDatasetPaths}, ...
    'truthUsedForLabelsOnly', true, ...
    'featuresUseTruth', false, ...
    'teacherLabelVersion', ...
        'joint-action-bernoulli-risk-v3-directed-physical');
ensureDirectory(fileparts(modelPath));
save('-mat7-binary', modelPath, 'model', 'trainingSummary');

result = struct( ...
    'modelPath', modelPath, ...
    'reportPath', reportPath, ...
    'model', model, ...
    'trainingSummary', trainingSummary);
writeReport(reportPath, result);
end

function writeReport(path, result)
ensureDirectory(fileparts(path));
fid = fopen(path, 'w');
if fid < 0
    error('Could not open residual-model report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
summary = result.trainingSummary;
calibration = summary.calibration;
fprintf(fid, '# Support-gated residual directed KLA model\n\n');
fprintf(fid, '- Model: `%s`\n', result.modelPath);
fprintf(fid, '- Training datasets: `%s`\n', strjoin( ...
    result.model.trainingDatasetPaths, '`, `'));
fprintf(fid, '- Calibration datasets: `%s`\n', strjoin( ...
    result.model.calibrationDatasetPaths, '`, `'));
fprintf(fid, '- Training examples: %d\n', ...
    summary.trainingExampleCount);
fprintf(fid, '- Calibration examples: %d\n', ...
    summary.calibrationExampleCount);
fprintf(fid, '- Training receiver groups: %d\n', ...
    summary.trainingReceiverGroups);
fprintf(fid, '- Calibration receiver groups: %d\n', ...
    summary.calibrationReceiverGroups);
fprintf(fid, '- Training scenario/seed/time blocks: %d\n', ...
    summary.trainingBlockCount);
fprintf(fid, '- Calibration scenario/seed/time blocks: %d\n', ...
    summary.calibrationBlockCount);
fprintf(fid, '- Scale-invariant action features: %d\n', ...
    summary.featureCount);
fprintf(fid, '- Ridge lambda: %.6g\n', summary.ridgeLambda);
fprintf(fid, ['- Nominal quantile parameter (not a coverage ', ...
    'guarantee): %.3f\n'], ...
    result.model.confidenceLevel);
fprintf(fid, '- Calibration mode: `%s`\n', ...
    result.model.calibrationMode);
fprintf(fid, '- Calibration unit: `%s`\n', ...
    result.model.calibrationUnit);
fprintf(fid, '- Registered overestimate correction: %.6f\n', ...
    summary.overestimateQuantile);
fprintf(fid, '- Simultaneous-action diagnostic correction: %.6f\n', ...
    summary.simultaneousOverestimateQuantile);
fprintf(fid, '- Maximum calibration harmful-override fraction: %.2f%%\n', ...
    100 * summary.maximumCalibrationHarmfulOverrideFraction);
fprintf(fid, '- Empirical harmful-override correction escalated: `%d`\n', ...
    summary.calibrationSafetyEscalated);
fprintf(fid, '- Calibration in-support actions: %.2f%%\n', ...
    100 * summary.calibrationInSupportFraction);
fprintf(fid, '\n## Calibration selection\n\n');
fprintf(fid, '- Receiver override fraction: %.2f%%\n', ...
    100 * calibration.receiverOverrideFraction);
fprintf(fid, '- Harmful override fraction: %.2f%%\n', ...
    100 * calibration.harmfulOverrideFraction);
fprintf(fid, '- Mean selected residual: %.2f%%\n', ...
    100 * calibration.meanSelectedResidual);
fprintf(fid, '- Minimum selected residual: %.2f%%\n', ...
    100 * calibration.minimumSelectedResidual);
fprintf(fid, '- Oracle residual capture: %.2f%%\n', ...
    100 * calibration.oracleCaptureFraction);
fprintf(fid, '\n## Evidence boundary\n\n');
fprintf(fid, ['Ground truth is used only by the offline teacher labels. ', ...
    'The empirical calibration result uses one complete M24 ', ...
    'scenario/seed/time block. It is a block-level worst-error check, ', ...
    'not a 95%% population-coverage or unconditional closed-loop OSPA ', ...
    'guarantee. ', ...
    'X36 and new seeds must remain excluded from fitting and threshold ', ...
    'selection.\n']);
end

function ensureDirectory(path)
if ~isempty(path) && ~exist(path, 'dir')
    mkdir(path);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
