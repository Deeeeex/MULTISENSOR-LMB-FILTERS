function [reportPath, result] = ...
        analyzeHierarchicalFormationProposalV211(options)
% ANALYZEHIERARCHICALFORMATIONPROPOSALV211 Structural top-K diagnostic.
%
% Select high-need formations first, then retain a small source-label union
% across interpretable action modes.  Selection is truth-free.  The known
% V210 recursive labels are attached only after the proposal is frozen.

if nargin < 1 || isempty(options)
    options = struct();
end
evidenceRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v209');
policySources = getField(options, 'policySources', ...
    defaultPolicySources(evidenceRoot));
recursivePath = char(getField(options, 'recursivePath', fullfile( ...
    evidenceRoot, 'formation_h3_residual_anchors', ...
    'x36_seed211_t72_h8', ...
    'FORMATION_H3_RESIDUAL_DATASET_V210.mat')));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v211', 'hierarchical_formation_proposal', ...
    'x36_seed211_t72_h8')));
formationFeatureName = char(getField( ...
    options, 'formationFeatureName', 'need_max'));
topFormationCount = getField(options, 'topFormationCount', 1);
topPerMode = getField(options, 'topPerMode', 3);
modeFeatureNames = reshape(getField(options, 'modeFeatureNames', { ...
    'precision_refresh_evidence', ...
    'receiver_existence_deficit', ...
    'observation_handover_evidence'}), 1, []);
if ~isstruct(policySources) || ...
        ~all(isfield(policySources, {'actionTime', 'path'})) || ...
        exist(recursivePath, 'file') ~= 2 || ...
        ~isscalar(topFormationCount) || topFormationCount < 1 || ...
        topFormationCount ~= round(topFormationCount) || ...
        ~isscalar(topPerMode) || topPerMode < 1 || ...
        topPerMode ~= round(topPerMode) || isempty(modeFeatureNames)
    error('HierarchicalFormationProposalV211:InvalidRequest', ...
        'Policy states, recursive labels and positive proposal caps are required.');
end
recursiveLoaded = load(recursivePath, 'dataset');
recursive = recursiveLoaded.dataset;
validateRecursive(recursive);

states = repmat(emptyState(), 1, numel(policySources));
for stateIdx = 1:numel(policySources)
    source = policySources(stateIdx);
    loaded = load(char(source.path), 'dataset');
    dataset = loaded.dataset;
    validatePolicyState(dataset, source.actionTime);
    graph = dataset.blocks(1).graph;
    formationFeatureIdx = resolveUnique( ...
        graph.nodeFeatureNames, formationFeatureName);
    modeFeatureIndices = arrayfun(@(idx) resolveUnique( ...
        dataset.actionFeatureNames, modeFeatureNames{idx}), ...
        1:numel(modeFeatureNames));
    formationScore = graph.nodeFeatures(:, formationFeatureIdx);
    formationTable = [-formationScore(:), graph.formationIds(:)];
    [~, formationOrder] = sortrows(formationTable, [1, 2]);
    keepFormationCount = min(topFormationCount, ...
        numel(formationOrder));
    selectedFormationIndices = ...
        formationOrder(1:keepFormationCount);
    selectedFormationIds = ...
        graph.formationIds(selectedFormationIndices);

    rows = dataset.rows;
    featureMatrix = vertcat(rows.features);
    selectedMask = false(1, numel(rows));
    selectedByMode = false(numel(rows), numel(modeFeatureNames));
    for formationId = reshape(selectedFormationIds, 1, [])
        formationRows = find( ...
            [rows.receiverFormationId] == formationId);
        for modeIdx = 1:numel(modeFeatureNames)
            score = featureMatrix( ...
                formationRows, modeFeatureIndices(modeIdx));
            orderTable = [-score(:), ...
                [rows(formationRows).candidateIndex]'];
            [~, order] = sortrows(orderTable, [1, 2]);
            keepCount = min(topPerMode, numel(order));
            keepRows = formationRows(order(1:keepCount));
            selectedMask(keepRows) = true;
            selectedByMode(keepRows, modeIdx) = true;
        end
    end
    teacherIdx = find([rows.teacherKey]);
    if numel(teacherIdx) ~= 1
        error('HierarchicalFormationProposalV211:TeacherKey', ...
            'Each policy state must contain one teacher action.');
    end
    recursiveRow = matchRecursive(recursive, rows(teacherIdx));
    teacherFormationIndex = find( ...
        graph.formationIds == rows(teacherIdx).receiverFormationId, 1);
    teacherFormationRank = find( ...
        formationOrder == teacherFormationIndex, 1);
    state = emptyState();
    state.actionTime = source.actionTime;
    state.actionCount = numel(rows);
    state.selectedFormationIds = ...
        reshape(selectedFormationIds, 1, []);
    state.selectedActionIndices = find(selectedMask);
    state.selectedActionCount = nnz(selectedMask);
    state.teacherFormationId = ...
        rows(teacherIdx).receiverFormationId;
    state.teacherFormationRank = teacherFormationRank;
    state.teacherSourceId = rows(teacherIdx).sourceId;
    state.teacherLabel = rows(teacherIdx).label;
    state.teacherSelected = selectedMask(teacherIdx);
    state.teacherSelectedByMode = ...
        selectedByMode(teacherIdx, :);
    state.recursiveAggregatePositive = ...
        recursiveRow.aggregateReturnPositive;
    state.recursiveStrictPositive = ...
        recursiveRow.strictReturnPositive;
    state.expectedProposalMembership = ...
        recursiveRow.aggregateReturnPositive;
    state.membershipCorrect = state.teacherSelected == ...
        state.expectedProposalMembership;
    states(stateIdx) = state;
end

result = struct();
result.contractVersion = ...
    'hierarchical-formation-proposal-v211-v1';
result.generatedAt = datestr(now, 31);
result.policySources = policySources;
result.recursivePath = recursivePath;
result.formationFeatureName = formationFeatureName;
result.topFormationCount = topFormationCount;
result.modeFeatureNames = modeFeatureNames;
result.topPerMode = topPerMode;
result.maximumProposalSize = topFormationCount * ...
    topPerMode * numel(modeFeatureNames);
result.states = states;
result.stateCount = numel(states);
result.positiveTeacherCoverage = nnz( ...
    [states.recursiveAggregatePositive] & ...
    [states.teacherSelected]);
result.positiveTeacherCount = nnz( ...
    [states.recursiveAggregatePositive]);
result.negativeTeacherExcluded = nnz( ...
    ~[states.recursiveAggregatePositive] & ...
    ~[states.teacherSelected]);
result.negativeTeacherCount = nnz( ...
    ~[states.recursiveAggregatePositive]);
result.membershipCorrectCount = nnz([states.membershipCorrect]);
result.featuresUseTruth = false;
result.recursiveTruthUsedOnlyForEvaluation = true;
result.ruleSelectedOnOpenedDevelopmentStates = true;
result.completeTrajectoryHeldOut = false;
result.proposalRuleFrozen = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V211 applies a deterministic truth-free high-need-formation and ', ...
    'mode-diverse action proposal to three already opened X36 seed-211 ', ...
    'policy states.  H=3 recursive truth labels membership only after ', ...
    'selection.  The rule and its caps were designed after inspecting ', ...
    'these development states, so this result is a proposal-mechanism ', ...
    'diagnostic, not a frozen selector, held-out result, calibration ', ...
    'claim or performance improvement.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'HIERARCHICAL_FORMATION_PROPOSAL_V211.mat');
reportPath = fullfile(outputRoot, ...
    'HIERARCHICAL_FORMATION_PROPOSAL_V211.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V211 hierarchical formation proposal: %s\n', reportPath);
end

function sources = defaultPolicySources(evidenceRoot)
template = struct('actionTime', 0, 'path', '');
times = [73, 76, 77];
leaves = {'t73_after_v206_prefix', ...
    't76_after_v206_prefix', 't77_after_v204_prefix'};
sources = repmat(template, 1, numel(times));
for idx = 1:numel(times)
    sources(idx).actionTime = times(idx);
    sources(idx).path = fullfile(evidenceRoot, ...
        'policy_induced_immediate', leaves{idx}, ...
        'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat');
end
end

function validateRecursive(dataset)
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~isfield(dataset, 'contractVersion') || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-h3-residual-dataset-v210-v1') || ...
        ~isfield(dataset, 'rows') || numel(dataset.rows) ~= 4 || ...
        dataset.validationClaimAllowed
    error('HierarchicalFormationProposalV211:RecursiveContract', ...
        'The V210 recursive anchors are invalid.');
end
end

function validatePolicyState(dataset, actionTime)
required = {'contractVersion', 'returnTimes', 'blocks', 'rows', ...
    'blockCount', 'actionFeatureNames', 'featuresUseTruth', ...
    'featuresUseFutureInformation', 'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-label-kla-immediate-dataset-v208-v1') || ...
        dataset.blockCount ~= 1 || ...
        numel(dataset.returnTimes) ~= 1 || ...
        dataset.returnTimes ~= actionTime || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.validationClaimAllowed
    error('HierarchicalFormationProposalV211:PolicyContract', ...
        'A policy-induced V208 page is invalid.');
end
end

function row = matchRecursive(dataset, action)
mask = [dataset.rows.actionTime] == action.currentTime & ...
    [dataset.rows.receiverFormationId] == ...
        action.receiverFormationId & ...
    [dataset.rows.sourceId] == action.sourceId & ...
    arrayfun(@(candidate) isequal(candidate.label, action.label), ...
        dataset.rows);
indices = find(mask);
if numel(indices) ~= 1
    error('HierarchicalFormationProposalV211:RecursiveKey', ...
        'The teacher action must match one H=3 recursive anchor.');
end
row = dataset.rows(indices);
end

function index = resolveUnique(names, requested)
indices = find(strcmp(names, requested));
if numel(indices) ~= 1
    error('HierarchicalFormationProposalV211:FeatureName', ...
        'Required feature is missing or duplicated: %s', requested);
end
index = indices(1);
end

function state = emptyState()
state = struct( ...
    'actionTime', 0, 'actionCount', 0, ...
    'selectedFormationIds', zeros(1, 0), ...
    'selectedActionIndices', zeros(1, 0), ...
    'selectedActionCount', 0, ...
    'teacherFormationId', 0, 'teacherFormationRank', NaN, ...
    'teacherSourceId', 0, 'teacherLabel', zeros(2, 1), ...
    'teacherSelected', false, ...
    'teacherSelectedByMode', false(1, 0), ...
    'recursiveAggregatePositive', false, ...
    'recursiveStrictPositive', false, ...
    'expectedProposalMembership', false, ...
    'membershipCorrect', false);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('HierarchicalFormationProposalV211:ReportOpen', ...
        'Could not write the hierarchical proposal report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V211 hierarchical formation proposal\n\n');
fprintf(fid, '- Formation score / top count: `%s / %d`\n', ...
    result.formationFeatureName, result.topFormationCount);
fprintf(fid, '- Per-mode cap / maximum proposal size: `%d / %d`\n', ...
    result.topPerMode, result.maximumProposalSize);
fprintf(fid, '- Modes: `%s`\n\n', ...
    strjoin(result.modeFeatureNames, ', '));
fprintf(fid, ['| Time | Teacher | Formation rank | Proposal size | ', ...
    'H=3 positive | Proposed | Correct |\n']);
fprintf(fid, '|--:|:--|--:|--:|:--:|:--:|:--:|\n');
for state = reshape(result.states, 1, [])
    fprintf(fid, ['| %d | F%d<-S%d [%d,%d] | %d | %d | ', ...
        '%d | %d | %d |\n'], ...
        state.actionTime, state.teacherFormationId, ...
        state.teacherSourceId, state.teacherLabel(1), ...
        state.teacherLabel(2), state.teacherFormationRank, ...
        state.selectedActionCount, ...
        state.recursiveAggregatePositive, ...
        state.teacherSelected, state.membershipCorrect);
end
fprintf(fid, ['\n- Positive teacher coverage: `%d / %d`\n', ...
    '- Negative teacher exclusion: `%d / %d`\n', ...
    '- Membership decisions correct: `%d / %d`\n'], ...
    result.positiveTeacherCoverage, result.positiveTeacherCount, ...
    result.negativeTeacherExcluded, result.negativeTeacherCount, ...
    result.membershipCorrectCount, result.stateCount);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
