function [reportPath, dataset] = ...
        generateRecursiveRolloutLabelActionDatasetV180(options)
% GENERATERECURSIVEROLLOUTLABELACTIONDATASETV180 Score V179 rollout states.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRolloutAwareOneHopSafeLabelV179Protocol();
screenPath = getField(options, 'snapshotScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v180', 'recursive_rollout_capture', ...
    'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v180', 'recursive_rollout_action_value'));
generatorOptions = struct( ...
    'snapshotScreenPath', screenPath, ...
    'snapshotActionName', protocol.candidateActionName, ...
    'outputRoot', outputRoot, ...
    'repairPages', [7, 8], ...
    'repairFormationsByPage', {{5, 5}}, ...
    'splitBySchedule', [1, 3], ...
    'shortlistPerCriterion', 1, ...
    'datasetContractVersion', ...
        'recursive-rollout-label-action-value-dataset-v180-v1', ...
    'resultFileStem', ...
        'RECURSIVE_V179_ROLLOUT_ACTION_VALUE_DATASET_V180', ...
    'reportTitle', ...
        'V180 recursive V179-rollout label-action value dataset', ...
    'evidenceBoundary', [ ...
        'V180 is the second opened X36 seed-211 policy-iteration ', ...
        'dataset. It reads the pre-side-channel fused posterior and ', ...
        'current local source posteriors actually visited by recursive ', ...
        'V179 at the twelve F5 t=78/79 cells. Candidate features and ', ...
        'shortlisting are present-time and truth-free; current truth ', ...
        'scores immediate E-OSPA and RMSE action values. The source ', ...
        'rollout and prior learner were developed on seed 211, so this ', ...
        'supports method development only, not validation.']);
[reportPath, dataset] = ...
    generateOneHopLabelActionValueDatasetV166(generatorOptions);
dataset.sourceProtocolId = protocol.id;
dataset.sourceResultContractVersion = protocol.resultContractVersion;
save('-mat7-binary', dataset.matPath, 'dataset');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
