function [reportPath, result] = ...
    runOnlinePositiveNetPropagationV100X36T72(options)
% RUNONLINEPOSITIVENETPROPAGATIONV100X36T72 Matched H=6 probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getOnlinePositiveNetPropagationV100Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('OnlinePositiveNetV100:DirtySource', ...
        'The V100 propagation probe requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
outputRoot = getField(options, ...
    'outputRoot', fullfile(protocol.headroomOutputRoot, 'x36_t72_h6'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v100-online-positive-net-propagation', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', 'online-positive-net-propagation-v100', ...
        'horizonSteps', protocol.horizonSteps), ...
    'receiverMode', protocol.receiverMode, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);

names = {screen.records.actionName};
referenceIdx = screen.referenceSubsetIndex;
fixedIdx = find(cellfun(@(name) ~isempty(strfind(name, ...
    'v97-positive-net-persistent-h6-')), names), 1); %#ok<STREMP>
onlineIdx = find(cellfun(@(name) ~isempty(strfind(name, ...
    'v100-online-positive-net-h6-')), names), 1); %#ok<STREMP>
if isempty(fixedIdx) || isempty(onlineIdx)
    error('OnlinePositiveNetV100:MissingPairedArm', ...
        'The V100 bank did not produce all paired arms.');
end

reference = screen.records(referenceIdx);
fixed = screen.records(fixedIdx);
online = screen.records(onlineIdx);
referenceOutcome = screen.outcomes(referenceIdx);
fixedOutcome = screen.outcomes(fixedIdx);
onlineOutcome = screen.outcomes(onlineIdx);
referenceByTime = mean(referenceOutcome.eospaBySensorTime, 1);
fixedByTime = mean(fixedOutcome.eospaBySensorTime, 1);
onlineByTime = mean(onlineOutcome.eospaBySensorTime, 1);
onlineGainByTime = 100 * (referenceByTime - onlineByTime) ./ ...
    max(abs(referenceByTime), eps);
fixedGainByTime = 100 * (referenceByTime - fixedByTime) ./ ...
    max(abs(referenceByTime), eps);

result = struct();
result.contractVersion = ...
    'online-positive-net-propagation-v100-x36-t72-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.baselineName = protocol.baselineName;
result.receiverMode = protocol.receiverMode;
result.formationPropagationDiameter = ...
    protocol.formationPropagationDiameter;
result.initialFormationIds = ...
    screen.bank.positiveNetAddressableSelection.selectedFormationIds;
result.onlineFormationIdsByTime = ...
    onlineOutcome.retentionDebtSelectedFormationIdsByTime;
result.referenceMeanEospa = reference.meanEospa;
result.fixedV97MeanEospa = fixed.meanEospa;
result.onlineV100MeanEospa = online.meanEospa;
result.fixedV97GainPercent = fixed.meanGainPercent;
result.onlineV100GainPercent = online.meanGainPercent;
result.onlineGainOverFixedPercent = relativeGainPercent( ...
    fixed.meanEospa, online.meanEospa);
result.referenceMeanEospaByTime = referenceByTime;
result.fixedV97MeanEospaByTime = fixedByTime;
result.onlineV100MeanEospaByTime = onlineByTime;
result.fixedV97GainPercentByTime = fixedGainByTime;
result.onlineV100GainPercentByTime = onlineGainByTime;
result.minimumPostPropagationGainPercent = min( ...
    onlineGainByTime(protocol.formationPropagationDiameter:end));
result.worstSensorGainPercent = online.worstGainPercent;
result.minimumFormationGainPercent = ...
    online.minimumFormationGainPercent;
result.windowConsensusGainPercent = online.consensusGainPercent;
result.terminalConsensusGainPercent = ...
    online.terminalConsensusGainPercent;
result.attemptedByteSavingPercent = ...
    online.attemptedByteSavingPercent;
result.selectedB3Passed = online.selectedB3Passed;
result.referenceElapsedSeconds = referenceOutcome.elapsedSeconds;
result.fixedV97ElapsedSeconds = fixedOutcome.elapsedSeconds;
result.onlineV100ElapsedSeconds = onlineOutcome.elapsedSeconds;
result.gatePassed = ...
    online.meanGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    result.minimumPostPropagationGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    online.worstGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    online.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    online.consensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    online.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    online.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    online.selectedB3Passed;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.screenReportPath = screenReportPath;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'ONLINE_POSITIVE_NET_PROPAGATION_V100_X36_T72_H6_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'ONLINE_POSITIVE_NET_PROPAGATION_V100_X36_T72_H6_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V100 X36-t72 H=6 result: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('OnlinePositiveNetV100:WriteFailed', ...
        'Could not create the V100 propagation report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V100 online positive-net propagation: X36 t72 H=6\n\n');
fprintf(fid, '- Matched baseline: `%s`\n', result.baselineName);
fprintf(fid, '- Formation-graph directed diameter: `%d`\n', ...
    result.formationPropagationDiameter);
fprintf(fid, '- Horizon: `one action step + diameter = %d`\n\n', ...
    numel(result.returnTimes));
fprintf(fid, '| Arm | Mean E-OSPA | Gain vs static | Gain vs fixed |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
fprintf(fid, '| Static full payload | %.6f | -- | -- |\n', ...
    result.referenceMeanEospa);
fprintf(fid, '| Fixed initial set | %.6f | %+.3f%% | -- |\n', ...
    result.fixedV97MeanEospa, result.fixedV97GainPercent);
fprintf(fid, '| Online V100 | %.6f | %+.3f%% | %+.3f%% |\n\n', ...
    result.onlineV100MeanEospa, result.onlineV100GainPercent, ...
    result.onlineGainOverFixedPercent);
fprintf(fid, '| t | Static | Fixed | Online | Online/static |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|\n');
for idx = 1:numel(result.returnTimes)
    fprintf(fid, '| %d | %.6f | %.6f | %.6f | %+.3f%% |\n', ...
        result.returnTimes(idx), ...
        result.referenceMeanEospaByTime(idx), ...
        result.fixedV97MeanEospaByTime(idx), ...
        result.onlineV100MeanEospaByTime(idx), ...
        result.onlineV100GainPercentByTime(idx));
end
fprintf(fid, '\n- Online sets: `%s`\n', ...
    formatCellVectors(result.onlineFormationIdsByTime));
fprintf(fid, '- Minimum post-propagation gain: `%+.3f%%`\n', ...
    result.minimumPostPropagationGainPercent);
fprintf(fid, '- Worst sensor / minimum formation: `%+.3f%% / %+.3f%%`\n', ...
    result.worstSensorGainPercent, result.minimumFormationGainPercent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    result.windowConsensusGainPercent, ...
    result.terminalConsensusGainPercent);
fprintf(fid, '- Attempted-byte saving: `%+.3f%%`\n', ...
    result.attemptedByteSavingPercent);
fprintf(fid, '- Static / fixed / online runtime: `%.2f / %.2f / %.2f s`\n', ...
    result.referenceElapsedSeconds, result.fixedV97ElapsedSeconds, ...
    result.onlineV100ElapsedSeconds);
fprintf(fid, '- H=6 propagation gate passed: `%d`\n\n', ...
    result.gatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = formatCellVectors(vectors)
tokens = cellfun(@mat2str, vectors, 'UniformOutput', false);
value = strjoin(tokens, ' -> ');
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
