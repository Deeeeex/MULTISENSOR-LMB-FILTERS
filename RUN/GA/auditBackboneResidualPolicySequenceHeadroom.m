function [auditPath, audit] = ...
    auditBackboneResidualPolicySequenceHeadroom( ...
        sourcePaths, options)
% AUDITBACKBONERESIDUALPOLICYSEQUENCEHEADROOM Fail-closed S/C audit.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getBackboneResidualPolicySequenceProtocol();
if nargin < 1 || isempty(sourcePaths)
    rootDirectory = getField(options, ...
        'inputDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'evidence', ...
            'backbone_residual_policy_sequence'));
    files = dir(fullfile(rootDirectory, ...
        'batch_*_of_*', ...
        'DYNAMIC_TOPOLOGY_CONTINUATION_M24_HARD_T75_N1_*.mat'));
    sourcePaths = arrayfun(@(file) ...
        fullfile(file.folder, file.name), files, ...
        'UniformOutput', false);
end
if ischar(sourcePaths)
    sourcePaths = {sourcePaths};
end
if isempty(sourcePaths)
    error('No residual policy-sequence sources were supplied.');
end

aggregates = repmat(struct(), 1, 0);
sourceHashes = cell(1, numel(sourcePaths));
for sourceIdx = 1:numel(sourcePaths)
    loaded = load(sourcePaths{sourceIdx}, 'summary');
    if ~isfield(loaded, 'summary')
        error('Policy-sequence source lacks summary.');
    end
    validateSummary(loaded.summary, protocol);
    aggregates = [aggregates, ...
        loaded.summary.aggregate]; %#ok<AGROW>
    sourceHashes{sourceIdx} = ...
        computeFileSha256(sourcePaths{sourceIdx});
end
modes = {aggregates.mode};
if numel(unique(modes)) ~= numel(modes)
    error('Policy-sequence sources contain duplicate arms.');
end

local = requireArm(aggregates, 'local');
fixed = requireArm(aggregates, ...
    'directed-fixed-index-w70');
staticResidual = requireArm(aggregates, ...
    'backbone-residual-static-a70-e05');
analyticResidual = requireArm(aggregates, ...
    'backbone-residual-analytic-a70-e05');
baselines = [fixed, staticResidual, analyticResidual];

[~, ~, sourceState] = ...
    loadBackboneResidualReturnHeadroomState();
rows = repmat(emptyRow(), ...
    1, size(protocol.sequenceMasks, 1));
for maskIdx = 1:size(protocol.sequenceMasks, 1)
    mask = protocol.sequenceMasks(maskIdx, :);
    mode = sprintf([ ...
        'oracle-backbone-residual-sequence-', ...
        't75-m%s-a70-e05'], mask);
    arm = requireArm(aggregates, mode);
    rows(maskIdx) = evaluateSequence( ...
        arm, mask, sourceState, ...
        baselines, local, staticResidual, protocol);
end

safeIndices = find([rows.constraintEligible]);
if isempty(safeIndices)
    error('No S/C sequence satisfies the frozen constraints.');
end
[~, safeOrder] = sortrows([ ...
    [rows(safeIndices).focusEospa]', ...
    [rows(safeIndices).focusWorstSensorEospa]'], [1, 2]);
rankedIndices = safeIndices(safeOrder);
best = rows(rankedIndices(1));

gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'backbone-residual-policy-sequence-headroom-audit-v1';
audit.protocolId = protocol.id;
audit.generatedAt = datestr(now, 31);
audit.sourcePaths = sourcePaths;
audit.sourceSha256 = sourceHashes;
audit.baselineModes = {baselines.mode};
audit.rows = rows;
audit.constraintEligibleSequenceCount = ...
    numel(safeIndices);
audit.rankedConstraintEligibleIndices = ...
    rankedIndices;
audit.bestSequence = best;
audit.headroomGatePassed = best.passed;
audit.returnDataGenerationAuthorized = ...
    audit.headroomGatePassed;
audit.criticTrainingAuthorized = false;
audit.x36PolicyRunAuthorized = false;
audit.heldoutClaimAllowed = false;
audit.maskSelectionUsesFutureOutcome = true;
audit.privilegedDiagnosticOnly = true;
audit.auditGitCommit = gitState.commit;
audit.auditTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.auditUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.evidenceBoundary = [ ...
    'The best S/C mask is selected after observing all paired ', ...
    'three-step outcomes and C steps read current truth. This is a ', ...
    'nondeployable development diagnosis. A pass authorizes broader ', ...
    'return-data generation only.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'backbone_residual_policy_sequence'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
auditPath = fullfile(outputDirectory, ...
    'backbone_residual_policy_sequence_audit_m24_h3_v1.mat');
reportPath = fullfile(outputDirectory, ...
    'BACKBONE_RESIDUAL_POLICY_SEQUENCE_AUDIT_M24_H3_V1.md');
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit, ...
    local, baselines);
fprintf('Audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function row = evaluateSequence( ...
        arm, mask, sourceState, baselines, ...
        local, staticResidual, protocol)
selectedDiagnostic = ...
    arm.focusSelectedDirectedEdgeHistoryBySeed{1};
selectedPolicy = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        selectedDiagnostic);
[sensorPass, formationPass] = computeRollingPass( ...
    sourceState.previousAdjacencyHistory, ...
    selectedPolicy, sourceState.groupIds);
meanGains = arrayfun(@(baseline) ...
    fractionalGain(baseline.focusEospa, ...
        arm.focusEospa), baselines);
tailGains = arrayfun(@(baseline) ...
    fractionalGain( ...
        baseline.focusWorstSensorEospa, ...
        arm.focusWorstSensorEospa), baselines);
byteDeviation = fractionalDeviation( ...
    staticResidual.focusAttemptedBytes, ...
    arm.focusAttemptedBytes);
repairRate = finiteOrZero(arm.policyRepairRate);
emergencyRate = finiteOrZero( ...
    arm.policyPayloadEmergencyRate);
infeasibleRate = finiteOrZero( ...
    arm.focusTopologyInfeasibleRate);
truthUseFraction = finiteOrZero( ...
    arm.policyTruthUseFraction);
expectedTruthUseFraction = ...
    nnz(mask == '1') / numel(mask);

row = emptyRow();
row.mode = arm.mode;
row.mask = mask;
row.focusEospa = arm.focusEospa;
row.focusWorstSensorEospa = ...
    arm.focusWorstSensorEospa;
row.focusAttemptedBytes = ...
    arm.focusAttemptedBytes;
row.minimumBaselineMeanGainFraction = ...
    min(meanGains);
row.minimumBaselineWorstNodeGainFraction = ...
    min(tailGains);
row.localMeanGainFraction = fractionalGain( ...
    local.focusEospa, arm.focusEospa);
row.localWorstNodeGainFraction = fractionalGain( ...
    local.focusWorstSensorEospa, ...
    arm.focusWorstSensorEospa);
row.attemptedByteDeviationFraction = ...
    byteDeviation;
row.sensorB3Pass = sensorPass;
row.formationB3Pass = formationPass;
row.repairRate = repairRate;
row.payloadEmergencyRate = emergencyRate;
row.topologyInfeasibleRate = infeasibleRate;
row.truthUseFraction = truthUseFraction;
row.expectedTruthUseFraction = ...
    expectedTruthUseFraction;
row.meanGatePassed = ...
    row.minimumBaselineMeanGainFraction + 1e-12 >= ...
        protocol.minimumMeanTrackingGainFraction && ...
    row.localMeanGainFraction >= -1e-12;
row.tailGatePassed = ...
    row.minimumBaselineWorstNodeGainFraction >= ...
        -protocol.maximumWorstNodeRegressionFraction - 1e-12 && ...
    row.localWorstNodeGainFraction >= -1e-12;
row.byteGatePassed = ...
    byteDeviation <= ...
        protocol.maximumAttemptedByteDeviationFraction + 1e-12;
row.safetyGatePassed = all(sensorPass) && ...
    all(formationPass) && repairRate == 0 && ...
    emergencyRate == 0 && infeasibleRate == 0;
row.provenanceGatePassed = ...
    abs(truthUseFraction - ...
        expectedTruthUseFraction) <= 1e-12;
row.constraintEligible = row.byteGatePassed && ...
    row.safetyGatePassed && row.provenanceGatePassed;
row.passed = row.constraintEligible && ...
    row.meanGatePassed && row.tailGatePassed;
end

function validateSummary(summary, protocol)
required = {'presetName', 'seeds', 'options', 'aggregate'};
if ~isstruct(summary) || ~all(isfield(summary, required)) || ...
        ~strcmp(summary.presetName, protocol.presetName) || ...
        ~isequal(summary.seeds, protocol.seed) || ...
        summary.options.continuationStartTime ~= ...
            protocol.anchorTime || ...
        summary.options.maxTimeSteps ~= ...
            protocol.horizonTimes(end)
    error('Policy-sequence source violates the protocol.');
end
end

function arm = requireArm(aggregates, mode)
index = find(strcmp({aggregates.mode}, mode));
if numel(index) ~= 1
    error('Expected exactly one policy-sequence arm: %s.', mode);
end
arm = aggregates(index);
end

function [sensorPass, formationPass] = ...
    computeRollingPass(previousHistory, executed, groupIds)
depth = 2;
history = logical(previousHistory);
if size(history, 3) > depth
    history = history(:, :, end-depth+1:end);
end
stepCount = size(executed, 3);
sensorPass = false(1, stepCount);
formationPass = false(1, stepCount);
for stepIdx = 1:stepCount
    pages = cat(3, history, executed(:, :, stepIdx));
    window = any(pages(:, :, ...
        max(1, end-depth):end), 3);
    sensorPass(stepIdx) = ...
        isStronglyConnected(window);
    formationPass(stepIdx) = ...
        isStronglyConnected( ...
            collapseToFormations(window, groupIds));
    history(:, :, end + 1) = executed(:, :, stepIdx);
    if size(history, 3) > depth
        history = history(:, :, end-depth+1:end);
    end
end
end

function formationAdjacency = ...
    collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
formationAdjacency = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formationAdjacency(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formationAdjacency(1:numel(groups)+1:end) = false;
end

function valid = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
valid = true;
for startNode = 1:nodeCount
    visited = false(1, nodeCount);
    visited(startNode) = true;
    while true
        next = visited | any(adjacency(visited, :), 1);
        if isequal(next, visited)
            break;
        end
        visited = next;
    end
    if ~all(visited)
        valid = false;
        return;
    end
end
end

function gain = fractionalGain(reference, candidate)
gain = (reference - candidate) / max(abs(reference), eps);
end

function deviation = fractionalDeviation(reference, candidate)
deviation = abs(reference - candidate) / max(abs(reference), 1);
end

function value = finiteOrZero(value)
if ~isscalar(value) || ~isfinite(value)
    value = 0;
end
end

function writeReport(path, audit, local, baselines)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open policy-sequence audit report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# Backbone residual S/C policy-sequence audit\n\n');
fprintf(fid, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fid, '- Gate passed: `%d`\n', ...
    audit.headroomGatePassed);
fprintf(fid, '- Eligible sequences: `%d/8`\n', ...
    audit.constraintEligibleSequenceCount);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    audit.evidenceBoundary);
fprintf(fid, '## Baselines\n\n');
fprintf(fid, '| Baseline | E-OSPA | Worst | Bytes |\n');
fprintf(fid, '|---|---:|---:|---:|\n');
fprintf(fid, '| `local` | %.4f | %.4f | %.0f |\n', ...
    local.focusEospa, local.focusWorstSensorEospa, ...
    local.focusAttemptedBytes);
for idx = 1:numel(baselines)
    row = baselines(idx);
    fprintf(fid, '| `%s` | %.4f | %.4f | %.0f |\n', ...
        row.mode, row.focusEospa, ...
        row.focusWorstSensorEospa, ...
        row.focusAttemptedBytes);
end
fprintf(fid, '\n## Sequences\n\n');
fprintf(fid, ['| Mask | E-OSPA | Worst | Min mean gain | ', ...
    'Min tail gain | Byte dev. | B3 | Truth | Eligible | Pass |\n']);
fprintf(fid, ...
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for idx = 1:numel(audit.rows)
    row = audit.rows(idx);
    fprintf(fid, ...
        '| `%s` | %.4f | %.4f | %.2f%% | %.2f%% | %.2f%% | %d | %.2f | %d | %d |\n', ...
        row.mask, row.focusEospa, ...
        row.focusWorstSensorEospa, ...
        100 * row.minimumBaselineMeanGainFraction, ...
        100 * row.minimumBaselineWorstNodeGainFraction, ...
        100 * row.attemptedByteDeviationFraction, ...
        all(row.sensorB3Pass) && ...
            all(row.formationB3Pass), ...
        row.truthUseFraction, ...
        row.constraintEligible, row.passed);
end
best = audit.bestSequence;
fprintf(fid, '\n## Selected development upper bound\n\n');
fprintf(fid, '- Mask: `%s`\n', best.mask);
fprintf(fid, '- E-OSPA / worst: `%.4f / %.4f`\n', ...
    best.focusEospa, best.focusWorstSensorEospa);
fprintf(fid, '- Minimum baseline mean gain: `%.2f%%`\n', ...
    100 * best.minimumBaselineMeanGainFraction);
fprintf(fid, '- Gate passed: `%d`\n', best.passed);
end

function row = emptyRow()
row = struct( ...
    'mode', '', 'mask', '', ...
    'focusEospa', NaN, ...
    'focusWorstSensorEospa', NaN, ...
    'focusAttemptedBytes', NaN, ...
    'minimumBaselineMeanGainFraction', NaN, ...
    'minimumBaselineWorstNodeGainFraction', NaN, ...
    'localMeanGainFraction', NaN, ...
    'localWorstNodeGainFraction', NaN, ...
    'attemptedByteDeviationFraction', NaN, ...
    'sensorB3Pass', false(1, 0), ...
    'formationB3Pass', false(1, 0), ...
    'repairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'truthUseFraction', NaN, ...
    'expectedTruthUseFraction', NaN, ...
    'meanGatePassed', false, ...
    'tailGatePassed', false, ...
    'byteGatePassed', false, ...
    'safetyGatePassed', false, ...
    'provenanceGatePassed', false, ...
    'constraintEligible', false, ...
    'passed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
