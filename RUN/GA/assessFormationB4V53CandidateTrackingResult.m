function assessment = assessFormationB4V53CandidateTrackingResult( ...
        resultOrPath, reportPath)
% ASSESSFORMATIONB4V53CANDIDATETRACKINGRESULT Apply the frozen V53 gate.

if ischar(resultOrPath)
    loaded = load(resultOrPath, 'result');
    if ~isfield(loaded, 'result')
        error('FormationB4V53Gate:MissingResult', ...
            'The MAT file does not contain result.');
    end
    result = loaded.result;
    sourcePath = resultOrPath;
else
    result = resultOrPath;
    sourcePath = '';
end
if ~isstruct(result) || ~isfield(result, 'contractVersion') || ...
        ~strcmp(result.contractVersion, ...
            'formation-b4-v53-candidate-tracking-development-result-v1')
    error('FormationB4V53Gate:InvalidResult', ...
        'A completed V53 candidate tracking result is required.');
end
if isempty(result.cases)
    error('FormationB4V53Gate:NoCases', ...
        'The V53 result contains no paired case.');
end

thresholds = struct( ...
    'minimumFullHorizonImprovementPct', 1.0, ...
    'minimumCardinalityImprovementPct', 1.0, ...
    'minimumFocusImprovementPct', -0.5);
rows = repmat(emptyRow(), 1, numel(result.cases));
for caseIdx = 1:numel(result.cases)
    record = result.cases(caseIdx);
    improvement = record.improvement;
    row = emptyRow();
    row.presetName = record.presetName;
    row.seed = record.seed;
    row.fullHorizonImprovementPct = ...
        improvement.fullHorizonPositionEospaPct;
    row.cardinalityImprovementPct = ...
        improvement.meanAbsoluteCardinalityErrorPct;
    row.focusImprovementPct = ...
        improvement.focusWindowPositionEospaPct;
    row.referenceAttemptedMessageCount = ...
        record.reference.attemptedMessageCount;
    row.candidateAttemptedMessageCount = ...
        record.candidate.attemptedMessageCount;
    row.fullHorizonPassed = row.fullHorizonImprovementPct >= ...
        thresholds.minimumFullHorizonImprovementPct;
    row.cardinalityPassed = row.cardinalityImprovementPct >= ...
        thresholds.minimumCardinalityImprovementPct;
    row.focusPassed = row.focusImprovementPct >= ...
        thresholds.minimumFocusImprovementPct;
    row.messageBudgetPassed = row.candidateAttemptedMessageCount <= ...
        row.referenceAttemptedMessageCount;
    row.passed = all([row.fullHorizonPassed, row.cardinalityPassed, ...
        row.focusPassed, row.messageBudgetPassed]);
    rows(caseIdx) = row;
end

assessment = struct();
assessment.contractVersion = ...
    'formation-b4-v53-development-gate-assessment-v1';
assessment.thresholds = thresholds;
assessment.rows = rows;
assessment.passed = all([rows.passed]);
if assessment.passed
    assessment.decision = 'advance-to-frozen-cross-scene-validation';
else
    assessment.decision = ...
        'reject-topology-scheduling-and-build-mixture-aware-reference';
end

if nargin < 2 || isempty(reportPath)
    reportPath = defaultReportPath(sourcePath);
end
assessment.reportPath = reportPath;
if ~isempty(reportPath)
    writeReport(reportPath, assessment);
end
end

function row = emptyRow()
row = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'fullHorizonImprovementPct', NaN, ...
    'cardinalityImprovementPct', NaN, ...
    'focusImprovementPct', NaN, ...
    'referenceAttemptedMessageCount', NaN, ...
    'candidateAttemptedMessageCount', NaN, ...
    'fullHorizonPassed', false, ...
    'cardinalityPassed', false, ...
    'focusPassed', false, ...
    'messageBudgetPassed', false, ...
    'passed', false);
end

function path = defaultReportPath(sourcePath)
path = '';
if isempty(sourcePath)
    return;
end
[folder, name] = fileparts(sourcePath);
path = fullfile(folder, [name, '_GATE.md']);
end

function writeReport(path, assessment)
fid = fopen(path, 'w');
if fid < 0
    error('FormationB4V53Gate:ReportWriteFailed', ...
        'Could not open %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
thresholds = assessment.thresholds;
fprintf(fid, '# V53 frozen development gate\n\n');
fprintf(fid, ['The decision uses only the four thresholds registered ', ...
    'before the result was opened.\n\n']);
fprintf(fid, '- Full-horizon E-OSPA improvement: `>= %+.1f%%`\n', ...
    thresholds.minimumFullHorizonImprovementPct);
fprintf(fid, '- Cardinality-error improvement: `>= %+.1f%%`\n', ...
    thresholds.minimumCardinalityImprovementPct);
fprintf(fid, '- Focus-window E-OSPA improvement: `>= %+.1f%%`\n', ...
    thresholds.minimumFocusImprovementPct);
fprintf(fid, '- Attempted posterior messages: candidate `<=` V46\n\n');
fprintf(fid, ['| Scene | Seed | Full | Card. | Focus | Messages ', ...
    '(V46/V53) | Pass |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|:--:|\n');
for rowIdx = 1:numel(assessment.rows)
    row = assessment.rows(rowIdx);
    fprintf(fid, '| %s | %d | %+.2f%% | %+.2f%% | %+.2f%% | ', ...
        row.presetName, row.seed, row.fullHorizonImprovementPct, ...
        row.cardinalityImprovementPct, row.focusImprovementPct);
    fprintf(fid, '%d / %d | %d |\n', ...
        row.referenceAttemptedMessageCount, ...
        row.candidateAttemptedMessageCount, row.passed);
end
fprintf(fid, '\n**Decision:** `%s`\n', assessment.decision);
clear cleanup;
end
