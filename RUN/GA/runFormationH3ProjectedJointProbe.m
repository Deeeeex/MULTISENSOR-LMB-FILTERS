function [reportPath, probe] = ...
    runFormationH3ProjectedJointProbe(options)
% RUNFORMATIONH3PROJECTEDJOINTPROBE Opened seed-211 action-space probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3ProjectedJointProbeProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official projected-joint probe requires clean source.');
end
outputRoot = getField(options, 'outputDirectory', ...
    protocol.outputRoot);
probePath = fullfile(outputRoot, ...
    'formation_h3_projected_joint_probe_seed211_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_H3_PROJECTED_JOINT_PROBE_SEED211_V1.md');
probeExists = exist(probePath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(probeExists, reportExists)
    error('Formation H=3 projected-joint probe artifacts are partial.');
elseif probeExists
    loaded = load(probePath, 'probe');
    if ~isfield(loaded, 'probe') || ...
            ~strcmp(loaded.probe.protocolId, protocol.id) || ...
            ~strcmp(loaded.probe.generationGitCommit, gitState.commit)
        error('Formation H=3 projected-joint probe provenance mismatch.');
    end
    probe = loaded.probe;
    fprintf('Reused formation H=3 projected-joint probe: %s\n', ...
        probePath);
    return;
end

screens = cell(1, numel(protocol.snapshotTimes));
screenReports = screens;
audits = screens;
for timeIdx = 1:numel(protocol.snapshotTimes)
    currentTime = protocol.snapshotTimes(timeIdx);
    cachePath = fullfile(protocol.cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', ...
        strrep(protocol.presetName, '-', '_'), ...
        protocol.seed, currentTime));
    validateCache(cachePath, protocol, currentTime);
    screenDirectory = fullfile( ...
        outputRoot, sprintf('t%d', currentTime));
    [screenReports{timeIdx}, screens{timeIdx}] = ...
        runFormationProjectedJointH3OpenedReturnScreen( ...
            protocol.presetName, protocol.seed, currentTime, struct( ...
                'cacheRoot', protocol.cacheRoot, ...
                'outputDirectory', screenDirectory));
    audits{timeIdx} = strictAudit(screens{timeIdx});
end

strictGains = cellfun(@(item) item.oracleGainPercent, audits);
probe = struct();
probe.contractVersion = ...
    'formation-h3-projected-joint-probe-result-v1';
probe.protocolId = protocol.id;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
probe.cacheProtocolId = protocol.cacheProtocolId;
probe.cacheGenerationGitCommit = ...
    protocol.cacheGenerationGitCommit;
probe.presetName = protocol.presetName;
probe.seed = protocol.seed;
probe.snapshotTimes = protocol.snapshotTimes;
probe.screenReports = screenReports;
probe.screens = screens;
probe.audits = audits;
probe.strictOracleGainsPercent = strictGains;
probe.positiveStateCount = nnz(strictGains > 1e-12);
probe.strongStateCount = nnz(strictGains >= 3 - 1e-12);
probe.meanStrictOracleGainPercent = mean(strictGains);
probe.actionSelectionUsesTruth = false;
probe.actionSelectionUsesFutureMeasurements = false;
probe.targetsUseTruth = true;
probe.targetsUseFutureMeasurements = true;
probe.openedTrainingMechanismProbeOnly = true;
probe.finalModelTrainingAuthorized = false;
probe.validationClaimAllowed = false;
probe.evidenceBoundary = protocol.evidenceBoundary;
probe.probePath = probePath;
probe.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', probePath, 'probe');
writeReport(reportPath, probe);
fprintf('Formation H=3 projected-joint probe: %s\n', probePath);
end

function validateCache(cachePath, protocol, currentTime)
if exist(cachePath, 'file') ~= 2
    error('Projected-joint probe cache is missing: %s', cachePath);
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Projected-joint probe cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
required = { ...
    'protocolId', 'generationGitCommit', 'presetName', ...
    'seed', 'snapshotTimes', 'policyTruthUsed', ...
    'policyFutureOutcomeUsed', 'validationClaimAllowed'};
if ~all(isfield(bundle, required)) || ...
        ~strcmp(bundle.protocolId, protocol.cacheProtocolId) || ...
        ~strcmp(bundle.generationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~strcmp(bundle.presetName, protocol.presetName) || ...
        bundle.seed ~= protocol.seed || ...
        ~isequal(bundle.snapshotTimes, currentTime) || ...
        bundle.policyTruthUsed || ...
        bundle.policyFutureOutcomeUsed || ...
        bundle.validationClaimAllowed
    error('Projected-joint probe cache provenance mismatch.');
end
end

function audit = strictAudit(screen)
if numel(screen.records) ~= 2 || ...
        numel(screen.outcomes) ~= 2 || ...
        screen.referenceSubsetIndex ~= 1 || ...
        ~strcmp(screen.records(1).actionName, 'reference')
    error('Projected-joint probe screen is invalid.');
end
reference = screen.outcomes(1);
candidate = screen.outcomes(2);
record = screen.records(2);
targets = [ ...
    record.meanGainPercent, ...
    record.minimumFormationGainPercent, ...
    record.worstGainPercent, ...
    record.consensusGainPercent, ...
    record.attemptedByteSavingPercent, ...
    100 * (reference.deliveredBytes - candidate.deliveredBytes) / ...
        max(reference.deliveredBytes, eps)];
candidateFeasible = all(targets >= -1e-12);
if candidateFeasible && targets(1) > 1e-12
    oracleActionName = record.actionName;
    oracleGain = targets(1);
    oracleTargets = targets;
else
    oracleActionName = 'reference';
    oracleGain = 0;
    oracleTargets = zeros(1, 6);
end
audit = struct( ...
    'contractVersion', ...
        'formation-h3-projected-joint-strict-audit-v1', ...
    'currentTime', screen.currentTime, ...
    'selectedModes', screen.bank.selectedModes, ...
    'selectedTrustWeights', screen.bank.selectedTrustWeights, ...
    'candidateActionName', record.actionName, ...
    'candidateTargets', targets, ...
    'candidateDeploymentFeasible', candidateFeasible, ...
    'oracleActionName', oracleActionName, ...
    'oracleGainPercent', oracleGain, ...
    'oracleTargets', oracleTargets);
end

function writeReport(path, probe)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open projected-joint probe report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 projected-joint action probe\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    probe.contractVersion, probe.protocolId);
fprintf(fid, '- Probe generation commit: `%s`\n', ...
    probe.generationGitCommit);
fprintf(fid, '- Cache protocol / generation commit: `%s / %s`\n', ...
    probe.cacheProtocolId, probe.cacheGenerationGitCommit);
fprintf(fid, '- Preset / seed / times: `%s / %d / %s`\n', ...
    probe.presetName, probe.seed, mat2str(probe.snapshotTimes));
fprintf(fid, '- Strict gains: `%s`\n', ...
    mat2str(probe.strictOracleGainsPercent, 6));
fprintf(fid, '- Positive / strong / mean: `%d/%d / %d/%d / %+.3f%%`\n\n', ...
    probe.positiveStateCount, numel(probe.snapshotTimes), ...
    probe.strongStateCount, numel(probe.snapshotTimes), ...
    probe.meanStrictOracleGainPercent);
fprintf(fid, '| Time | Projected modes | Trust | Candidate feasible | Candidate six targets | Strict oracle |\n');
fprintf(fid, '|--:|:--|:--|:--:|:--|:--|\n');
for idx = 1:numel(probe.audits)
    audit = probe.audits{idx};
    fprintf(fid, '| %d | `%s` | `%s` | %s | `%s` | %s (%+.3f%%) |\n', ...
        audit.currentTime, mat2str(audit.selectedModes), ...
        mat2str(audit.selectedTrustWeights, 3), ...
        yesNo(audit.candidateDeploymentFeasible), ...
        mat2str(audit.candidateTargets, 6), ...
        audit.oracleActionName, audit.oracleGainPercent);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    probe.evidenceBoundary);
end

function value = yesNo(flag)
if flag
    value = 'yes';
else
    value = 'no';
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
