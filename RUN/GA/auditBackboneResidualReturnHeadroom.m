function [auditPath, audit] = ...
    auditBackboneResidualReturnHeadroom( ...
        shardPaths, options)
% AUDITBACKBONERESIDUALRETURNHEADROOM Fail-closed H=3 replay audit.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getBackboneResidualReturnHeadroomProtocol();
if nargin < 1 || isempty(shardPaths)
    inputDirectory = getField(options, ...
        'inputDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'returns', ...
            'backbone_residual_headroom_m24_h3_v1'));
    files = dir(fullfile(inputDirectory, ...
        'backbone_residual_return_m24_h3_b*.mat'));
    shardPaths = arrayfun(@(file) ...
        fullfile(file.folder, file.name), ...
        files, 'UniformOutput', false);
end
if ischar(shardPaths)
    shardPaths = {shardPaths};
end
if isempty(shardPaths)
    error('No backbone-residual return shards were supplied.');
end

shards = cell(1, numel(shardPaths));
for shardIdx = 1:numel(shardPaths)
    loaded = load(shardPaths{shardIdx}, 'shard');
    if ~isfield(loaded, 'shard')
        error('Return shard lacks shard variable: %s', ...
            shardPaths{shardIdx});
    end
    shards{shardIdx} = loaded.shard;
end
validateShardSet(shards, protocol);

controlShard = find(cellfun(@(shard) ...
    shard.controlsIncluded, shards));
controls = shards{controlShard}.controls;
candidateCells = cellfun(@(shard) ...
    shard.candidateResults, shards, ...
    'UniformOutput', false);
candidates = [candidateCells{:}];
[~, order] = sort([candidates.candidateIndex]);
candidates = candidates(order);
candidateIndices = [candidates.candidateIndex];
if ~isequal(candidateIndices, 1:shards{1}.candidateCount)
    error('Return shard candidate coverage is incomplete or duplicated.');
end

[~, rankOrder] = sortrows([ ...
    [candidates.meanEospa]', ...
    [candidates.worstSensorEospa]'], [1, 2]);
ranked = candidates(rankOrder);
best = ranked(1);
baselineModes = { ...
    'fixed-index-w70', 'static-residual', ...
    'scheduled-residual', 'analytic-residual'};
baselines = repmat(controls(1), 1, numel(baselineModes));
for baselineIdx = 1:numel(baselineModes)
    baselines(baselineIdx) = requireControl( ...
        controls, baselineModes{baselineIdx});
end
local = requireControl(controls, 'local');
staticResidual = requireControl( ...
    controls, 'static-residual');
scheduledResidual = requireControl( ...
    controls, 'scheduled-residual');

meanGains = arrayfun(@(baseline) ...
    fractionalGain(baseline.meanEospa, ...
        best.meanEospa), baselines);
tailGains = arrayfun(@(baseline) ...
    fractionalGain(baseline.worstSensorEospa, ...
        best.worstSensorEospa), baselines);
byteDeviations = [ ...
    fractionalDeviation(staticResidual.attemptedBytes, ...
        best.attemptedBytes), ...
    fractionalDeviation(scheduledResidual.attemptedBytes, ...
        best.attemptedBytes)];
meanGatePassed = min(meanGains) + 1e-12 >= ...
    protocol.minimumMeanTrackingGainFraction && ...
    fractionalGain(local.meanEospa, ...
        best.meanEospa) >= -1e-12;
tailGatePassed = min(tailGains) >= ...
    -protocol.maximumWorstNodeRegressionFraction - 1e-12 && ...
    fractionalGain(local.worstSensorEospa, ...
        best.worstSensorEospa) >= -1e-12;
byteGatePassed = max(byteDeviations) <= ...
    protocol.maximumAttemptedByteDeviationFraction + 1e-12;
safetyGatePassed = ...
    all(best.selectedSensorB3Pass) && ...
    all(best.selectedFormationB3Pass) && ...
    best.repairCount == 0 && ...
    best.payloadEmergencyCount == 0 && ...
    best.infeasibleCount == 0 && ...
    best.firstActionExact;
runtimeGatePassed = ...
    best.runtimeTruthUseCount == 0;

gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'backbone-residual-return-headroom-audit-v1';
audit.protocolId = protocol.id;
audit.generatedAt = datestr(now, 31);
audit.shardPaths = shardPaths;
audit.shardSha256 = cellfun( ...
    @computeFileSha256, shardPaths, ...
    'UniformOutput', false);
audit.proposalDatasetSha256 = ...
    shards{1}.proposalDatasetSha256;
audit.sourceCacheSha256 = ...
    shards{1}.sourceCacheSha256;
audit.candidateCount = numel(candidates);
audit.baselineModes = baselineModes;
audit.controls = controls;
audit.bestCandidate = best;
audit.bestCandidateRank = 1;
audit.bestCandidateMinimumBaselineMeanGainFraction = ...
    min(meanGains);
audit.bestCandidateMinimumBaselineWorstNodeGainFraction = ...
    min(tailGains);
audit.bestCandidateLocalMeanGainFraction = ...
    fractionalGain(local.meanEospa, best.meanEospa);
audit.bestCandidateLocalWorstNodeGainFraction = ...
    fractionalGain(local.worstSensorEospa, ...
        best.worstSensorEospa);
audit.bestCandidateByteDeviationFractions = ...
    byteDeviations;
audit.meanGatePassed = meanGatePassed;
audit.tailGatePassed = tailGatePassed;
audit.byteGatePassed = byteGatePassed;
audit.safetyGatePassed = safetyGatePassed;
audit.runtimeGatePassed = runtimeGatePassed;
audit.headroomGatePassed = ...
    meanGatePassed && tailGatePassed && ...
    byteGatePassed && safetyGatePassed && ...
    runtimeGatePassed;
audit.returnDataGenerationAuthorized = ...
    audit.headroomGatePassed;
audit.criticTrainingAuthorized = false;
audit.x36PolicyRunAuthorized = false;
audit.heldoutClaimAllowed = false;
audit.bestCandidateSelectionUsesFutureOutcome = true;
audit.privilegedDiagnosticOnly = true;
audit.topCandidates = ranked( ...
    1:min(10, numel(ranked)));
audit.auditGitCommit = gitState.commit;
audit.auditTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.auditUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.evidenceBoundary = [ ...
    'The best first action was selected after observing paired ', ...
    'three-step outcomes, so this is a nondeployable development ', ...
    'upper bound. A pass authorizes broader return-data generation ', ...
    'only; it does not validate a learned policy or X36 transfer.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'returns', ...
        'backbone_residual_headroom_m24_h3_v1'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
auditPath = fullfile(outputDirectory, ...
    'backbone_residual_return_headroom_audit_m24_h3_v1.mat');
reportPath = fullfile(outputDirectory, ...
    'BACKBONE_RESIDUAL_RETURN_HEADROOM_AUDIT_M24_H3_V1.md');
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Audit: %s\nReport: %s\n', auditPath, reportPath);
end

function validateShardSet(shards, protocol)
batchCounts = cellfun(@(shard) ...
    shard.batchCount, shards);
batchIndices = cellfun(@(shard) ...
    shard.batchIndex, shards);
candidateCounts = cellfun(@(shard) ...
    shard.candidateCount, shards);
proposalHashes = cellfun(@(shard) ...
    shard.proposalDatasetSha256, shards, ...
    'UniformOutput', false);
cacheHashes = cellfun(@(shard) ...
    shard.sourceCacheSha256, shards, ...
    'UniformOutput', false);
protocolIds = cellfun(@(shard) ...
    shard.protocolId, shards, ...
    'UniformOutput', false);
if numel(shards) ~= batchCounts(1) || ...
        any(batchCounts ~= numel(shards)) || ...
        ~isequal(sort(batchIndices), 1:numel(shards)) || ...
        any(candidateCounts ~= candidateCounts(1)) || ...
        numel(unique(proposalHashes)) ~= 1 || ...
        numel(unique(cacheHashes)) ~= 1 || ...
        any(~strcmp(protocolIds, protocol.id)) || ...
        nnz(cellfun(@(shard) ...
            shard.controlsIncluded, shards)) ~= 1 || ...
        any(~cellfun(@(shard) ...
            shard.commonRandomNumbers, shards))
    error('Return-headroom shard set violates the frozen contract.');
end
end

function control = requireControl(controls, mode)
index = find(strcmp({controls.mode}, mode));
if numel(index) ~= 1
    error('Expected one return-headroom control: %s.', mode);
end
control = controls(index);
end

function gain = fractionalGain(reference, candidate)
gain = (reference - candidate) / max(abs(reference), eps);
end

function deviation = fractionalDeviation(reference, candidate)
deviation = abs(reference - candidate) / max(abs(reference), 1);
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open return-headroom audit report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Backbone residual H=3 return-headroom audit\n\n');
fprintf(fid, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fid, '- Proposal SHA-256: `%s`\n', ...
    audit.proposalDatasetSha256);
fprintf(fid, '- Candidates: `%d`\n', audit.candidateCount);
fprintf(fid, '- Gate passed: `%d`\n', ...
    audit.headroomGatePassed);
fprintf(fid, '- Return-data generation authorized: `%d`\n', ...
    audit.returnDataGenerationAuthorized);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    audit.evidenceBoundary);
fprintf(fid, '## Controls\n\n');
fprintf(fid, '| Control | E-OSPA | Worst | Bytes |\n');
fprintf(fid, '|---|---:|---:|---:|\n');
for idx = 1:numel(audit.controls)
    row = audit.controls(idx);
    fprintf(fid, '| `%s` | %.4f | %.4f | %.0f |\n', ...
        row.mode, row.meanEospa, ...
        row.worstSensorEospa, row.attemptedBytes);
end
fprintf(fid, '\n## Best candidate and gates\n\n');
best = audit.bestCandidate;
fprintf(fid, '- Candidate: `%d`, `%s`\n', ...
    best.candidateIndex, best.proposalId);
fprintf(fid, '- Family: `%s`\n', best.family);
fprintf(fid, '- Graph SHA-256: `%s`\n', best.graphSha256);
fprintf(fid, '- E-OSPA / worst: `%.4f / %.4f`\n', ...
    best.meanEospa, best.worstSensorEospa);
fprintf(fid, '- Minimum baseline mean gain: `%.2f%%`\n', ...
    100 * audit. ...
        bestCandidateMinimumBaselineMeanGainFraction);
fprintf(fid, '- Minimum baseline tail gain: `%.2f%%`\n', ...
    100 * audit. ...
        bestCandidateMinimumBaselineWorstNodeGainFraction);
fprintf(fid, '- Maximum byte deviation: `%.2f%%`\n', ...
    100 * max(audit. ...
        bestCandidateByteDeviationFractions));
fprintf(fid, ...
    '- Mean / tail / byte / safety / runtime gates: `%d / %d / %d / %d / %d`\n\n', ...
    audit.meanGatePassed, audit.tailGatePassed, ...
    audit.byteGatePassed, audit.safetyGatePassed, ...
    audit.runtimeGatePassed);
fprintf(fid, '## Top candidates\n\n');
fprintf(fid, ...
    '| Rank | Index | Proposal | Family | E-OSPA | Worst | Bytes | Offline truth |\n');
fprintf(fid, ...
    '|---:|---:|---|---|---:|---:|---:|---:|\n');
for idx = 1:numel(audit.topCandidates)
    row = audit.topCandidates(idx);
    fprintf(fid, ...
        '| %d | %d | `%s` | `%s` | %.4f | %.4f | %.0f | %d |\n', ...
        idx, row.candidateIndex, row.proposalId, ...
        row.family, row.meanEospa, ...
        row.worstSensorEospa, row.attemptedBytes, ...
        row.offlineProposalTruthUsed);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
