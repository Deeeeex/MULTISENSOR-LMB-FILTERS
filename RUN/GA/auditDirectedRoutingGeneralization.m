function [reportPath, summary] = ...
    auditDirectedRoutingGeneralization(options)
% AUDITDIRECTEDROUTINGGENERALIZATION Reproduce kNN support-shift checks.
%
% The audit compares stored M24 training examples with deployment-observable
% edge features extracted from common static-prefix checkpoints. It never
% reads target truth. Distance is Euclidean in the training-standardized
% feature space used by the deployed kNN policy.

if nargin < 1 || isempty(options)
    options = struct();
end
snapshotTime = round(getField(options, 'snapshotTime', 75));
artifactDirectory = getField(options, 'artifactDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
cacheDirectory = getField(options, 'cacheDirectory', ...
    fullfile(artifactDirectory, 'cache'));
modelPath = getField(options, 'modelPath', fullfile( ...
    artifactDirectory, 'models', ...
    'directed_routing_knn_m24_t75.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    artifactDirectory, ...
    'DIRECTED_ROUTING_GENERALIZATION_AUDIT_M24_X36_T75.md'));
cases = getField(options, 'cases', { ...
    'm24-hard', 17; ...
    'x36-clean-scale', 7; ...
    'x36-clean-scale', 17});

loadedModel = load(modelPath, 'model');
if ~isfield(loadedModel, 'model')
    error('Directed-routing model file does not contain model.');
end
model = loadedModel.model;
training = model.trainingFeatures;
internal = internalDistanceSummary( ...
    training, model.neighborCount);
records = repmat(emptyRecord(), size(cases, 1), 1);
for caseIdx = 1:size(cases, 1)
    presetName = cases{caseIdx, 1};
    seed = cases{caseIdx, 2};
    context = loadCheckpointContext( ...
        presetName, seed, snapshotTime, cacheDirectory);
    [featureTensor, availableNames] = ...
        computeDirectedRoutingFeatures(context);
    featureIndices = resolveFeatureIndices( ...
        availableNames, model.featureNames);
    physical = logical(context.physicalAdjacency);
    [receiverIndices, senderIndices] = find(physical);
    query = zeros(numel(receiverIndices), numel(featureIndices));
    for queryIdx = 1:numel(receiverIndices)
        query(queryIdx, :) = reshape(featureTensor( ...
            receiverIndices(queryIdx), senderIndices(queryIdx), ...
            featureIndices), 1, []);
    end
    standardized = bsxfun(@rdivide, bsxfun(@minus, ...
        query, model.featureMean), model.featureScale);
    distance = crossDistanceSummary( ...
        standardized, training, model.neighborCount);
    trainingLower = min(training, [], 1);
    trainingUpper = max(training, [], 1);
    outOfRange = any(bsxfun(@lt, standardized, trainingLower) | ...
        bsxfun(@gt, standardized, trainingUpper), 2);
    [adjacency, ~] = ...
        selectFeatureDirectedRoutingPolicy(context, model);
    sourceCardinalityIdx = find(strcmp( ...
        model.featureNames, 'source_expected_cardinality'), 1);
    receiverCardinalityIdx = find(strcmp( ...
        model.featureNames, 'receiver_expected_cardinality'), 1);

    records(caseIdx) = struct( ...
        'presetName', presetName, ...
        'seed', seed, ...
        'candidateCount', size(query, 1), ...
        'nearestDistanceMedian', distance.nearestMedian, ...
        'neighborDistanceMedian', distance.kthMedian, ...
        'outOfRangeFraction', mean(outOfRange), ...
        'selectedReceiverCount', nnz(adjacency), ...
        'sensorCount', numel(context.localPosteriorBySensor), ...
        'sourceCardinalityShift', featureMeanOrNaN( ...
            standardized, sourceCardinalityIdx), ...
        'receiverCardinalityShift', featureMeanOrNaN( ...
            standardized, receiverCardinalityIdx));
end

summary = struct();
summary.modelPath = modelPath;
summary.snapshotTime = snapshotTime;
summary.neighborCount = model.neighborCount;
summary.trainingExampleCount = size(training, 1);
summary.trainingInternal = internal;
summary.records = records;
summary.truthUsed = false;
writeReport(reportPath, summary);
end

function context = loadCheckpointContext( ...
    presetName, seed, snapshotTime, cacheDirectory)
cachePath = fullfile(cacheDirectory, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', ...
    lower(strrep(presetName, '-', '_')), seed, snapshotTime));
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Behavior cache does not contain behaviorBundle: %s', cachePath);
end
bundle = loaded.behaviorBundle;
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
valid = strcmp(bundle.presetName, presetName) && ...
    bundle.seed == seed && ...
    isfield(bundle, 'configSnapshot') && ...
    isequaln(bundle.configSnapshot, inputs.config) && ...
    numel(bundle.posteriorSnapshots) >= snapshotTime && ...
    ~isempty(bundle.posteriorSnapshots{snapshotTime});
if ~valid
    error('Behavior cache identity/configuration mismatch: %s', cachePath);
end

sensorCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{snapshotTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = snapshotTime;
context.previousAdjacency = inputs.graphData.staticAdjacency;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, snapshotTime);
context.edgeScores = double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * inputs.config.edgeBudget;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, snapshotTime);
end
end

function result = internalDistanceSummary(features, neighborCount)
distanceSquared = squaredDistances(features, features);
distanceSquared(1:size(distanceSquared, 1)+1:end) = inf;
sorted = sort(distanceSquared, 2, 'ascend');
neighborIdx = min(neighborCount, size(sorted, 2) - 1);
result = struct( ...
    'nearestMedian', median(sqrt(sorted(:, 1))), ...
    'kthMedian', median(sqrt(sorted(:, neighborIdx))));
end

function result = crossDistanceSummary(query, training, neighborCount)
distanceSquared = squaredDistances(query, training);
sorted = sort(distanceSquared, 2, 'ascend');
neighborIdx = min(neighborCount, size(sorted, 2));
result = struct( ...
    'nearestMedian', median(sqrt(sorted(:, 1))), ...
    'kthMedian', median(sqrt(sorted(:, neighborIdx))));
end

function distanceSquared = squaredDistances(left, right)
leftNorm = sum(left.^2, 2);
rightNorm = sum(right.^2, 2)';
distanceSquared = bsxfun(@plus, leftNorm, rightNorm) - ...
    2 * (left * right');
distanceSquared = max(distanceSquared, 0);
end

function indices = resolveFeatureIndices(availableNames, requiredNames)
indices = zeros(1, numel(requiredNames));
for requiredIdx = 1:numel(requiredNames)
    match = find(strcmp( ...
        availableNames, requiredNames{requiredIdx}), 1);
    if isempty(match)
        error('Missing directed-routing feature: %s', ...
            requiredNames{requiredIdx});
    end
    indices(requiredIdx) = match;
end
end

function value = featureMeanOrNaN(features, featureIdx)
if isempty(featureIdx)
    value = NaN;
else
    value = mean(features(:, featureIdx));
end
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'candidateCount', NaN, ...
    'nearestDistanceMedian', NaN, ...
    'neighborDistanceMedian', NaN, ...
    'outOfRangeFraction', NaN, ...
    'selectedReceiverCount', NaN, ...
    'sensorCount', NaN, ...
    'sourceCardinalityShift', NaN, ...
    'receiverCardinalityShift', NaN);
end

function writeReport(path, summary)
ensureDirectory(fileparts(path));
fid = fopen(path, 'w');
if fid < 0
    error('Could not open routing generalization report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Directed-routing generalization audit\n\n');
fprintf(fid, '- Model: `%s`\n', summary.modelPath);
fprintf(fid, '- Snapshot: `t=%d`\n', summary.snapshotTime);
fprintf(fid, '- Training examples: %d\n', ...
    summary.trainingExampleCount);
fprintf(fid, '- kNN neighbour count: %d\n', ...
    summary.neighborCount);
fprintf(fid, '- Truth read by audit or policy: `0`\n\n');
fprintf(fid, '| Query | Nearest median | k=%d median | ', ...
    summary.neighborCount);
fprintf(fid, 'Any feature out of range | Selected receivers | ');
fprintf(fid, 'Source card. shift | Receiver card. shift |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
fprintf(fid, '| M24 training, leave-self-out | %.3f | %.3f | ', ...
    summary.trainingInternal.nearestMedian, ...
    summary.trainingInternal.kthMedian);
fprintf(fid, '— | — | — | — |\n');
for recordIdx = 1:numel(summary.records)
    record = summary.records(recordIdx);
    fprintf(fid, '| %s seed %d | %.3f | %.3f | %.1f%% | ', ...
        record.presetName, record.seed, ...
        record.nearestDistanceMedian, ...
        record.neighborDistanceMedian, ...
        100 * record.outOfRangeFraction);
    fprintf(fid, '%d/%d | %.2f sigma | %.2f sigma |\n', ...
        record.selectedReceiverCount, record.sensorCount, ...
        record.sourceCardinalityShift, ...
        record.receiverCardinalityShift);
end
fprintf(fid, '\n## Interpretation boundary\n\n');
fprintf(fid, ['Distances are Euclidean in the exact standardized feature ', ...
    'space consumed by the stored kNN model. A range violation means at ', ...
    'least one query feature lies outside the elementwise minimum/maximum ', ...
    'of the training examples; it is a support-shift diagnostic, not a ', ...
    'formal density estimate. The audit uses posterior, geometry and link ', ...
    'state only and does not establish closed-loop tracking quality.\n']);
end

function ensureDirectory(path)
if ~isempty(path) && ~exist(path, 'dir')
    mkdir(path);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
