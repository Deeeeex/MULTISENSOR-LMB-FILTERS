function passed = verifyManifestSources(repoRoot, manifest, commit)
required = {'records', 'canonicalSha256', ...
    'allEntriesTrackedByHead', 'allWorkingFilesMatchHead', ...
    'pathResolutionPassed'};
if ~all(isfield(manifest, required)) || ...
        ~isExactLogical(manifest.allEntriesTrackedByHead, true) || ...
        ~isExactLogical(manifest.allWorkingFilesMatchHead, true) || ...
        ~isExactLogical(manifest.pathResolutionPassed, true)
    passed = false;
    return;
end
passed = true;
for recordIdx = 1:numel(manifest.records)
    record = manifest.records(recordIdx);
    expectedPath = fullfile(repoRoot, record.relativePath);
    resolvedPath = which(record.functionName);
    [generationStatus, generationBlob] = gitCommand(repoRoot, sprintf( ...
        'rev-parse "%s:%s"', commit, record.relativePath));
    [headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
        'rev-parse "HEAD:%s"', record.relativePath));
    [workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
        'hash-object -- "%s"', record.relativePath));
    passed = passed && generationStatus == 0 && headStatus == 0 && ...
        workingStatus == 0 && strcmp(resolvedPath, expectedPath) && ...
        strcmp(record.resolvedPath, expectedPath) && ...
        strcmp(strtrim(generationBlob), record.headBlobId) && ...
        strcmp(strtrim(headBlob), record.headBlobId) && ...
        strcmp(strtrim(workingBlob), record.headBlobId) && ...
        strcmp(record.workingBlobId, record.headBlobId) && ...
        strcmp(computeFileSha256(expectedPath), record.fileSha256) && ...
        isExactLogical(record.trackedByHead, true) && ...
        isExactLogical(record.workingFileMatchesHead, true);
end
end

function passed = verifyNestedCanonicalHashes(cases)
passed = true;
for caseIdx = 1:numel(cases)
    item = cases(caseIdx);
    expectedCaseSha256 = item.canonicalSha256;
    passed = passed && strcmp(computeCanonicalValueSha256( ...
        rmfield(item, 'canonicalSha256')), expectedCaseSha256);
    for candidateIdx = 1:numel(item.candidates)
        candidate = item.candidates(candidateIdx);
        expectedCandidateSha256 = candidate.canonicalSha256;
        passed = passed && strcmp(computeCanonicalValueSha256( ...
            rmfield(candidate, 'canonicalSha256')), ...
            expectedCandidateSha256);
    end
end
end

function passed = pathBlobMatchesCommitAndHead( ...
        repoRoot, relativePath, commit)
[freezeStatus, freezeBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "%s:%s"', commit, relativePath));
[headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "HEAD:%s"', relativePath));
[workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
    'hash-object -- "%s"', relativePath));
passed = freezeStatus == 0 && headStatus == 0 && ...
    workingStatus == 0 && strcmp(strtrim(freezeBlob), ...
        strtrim(headBlob)) && strcmp(strtrim(headBlob), ...
        strtrim(workingBlob));
end

function passed = trackedAndHeadMatched(repoRoot, relativePath)
[trackedStatus, ~] = gitCommand(repoRoot, sprintf( ...
    'ls-files --error-unmatch -- "%s"', relativePath));
[workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
    'hash-object -- "%s"', relativePath));
[headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "HEAD:%s"', relativePath));
passed = trackedStatus == 0 && workingStatus == 0 && ...
    headStatus == 0 && strcmp(strtrim(workingBlob), strtrim(headBlob));
end

function exists = pathExistsAtCommit(repoRoot, commit, relativePath)
[status, ~] = gitCommand(repoRoot, sprintf( ...
    'cat-file -e "%s:%s"', commit, relativePath));
exists = status == 0;
end

function clean = isCleanWorktree(repoRoot)
[status, porcelain] = gitCommand(repoRoot, ...
    'status --porcelain --untracked-files=all');
clean = status == 0 && isempty(strtrim(porcelain));
end

function yes = isAncestor(repoRoot, ancestor, descendant)
[status, ~] = gitCommand(repoRoot, sprintf( ...
    'merge-base --is-ancestor %s %s', ancestor, descendant));
yes = status == 0;
end

function [status, output] = gitCommand(repoRoot, arguments)
environmentName = 'FORMATION_V44_POSTHOC_GIT_ROOT';
previousValue = getenv(environmentName);
cleanup = onCleanup(@() ...
    setenv(environmentName, previousValue)); %#ok<NASGU>
setenv(environmentName, repoRoot);
[status, output] = system(sprintf( ...
    'git -C "$%s" %s 2>/dev/null', environmentName, arguments));
end

function passed = isExactLogical(value, expected)
passed = islogical(value) && isscalar(value) && value == expected;
end

function yes = hasText(text, pattern)
yes = ~isempty(strfind(text, pattern)); %#ok<STREMP>
end
