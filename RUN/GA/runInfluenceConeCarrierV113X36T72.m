function [reportPath, result] = ...
        runInfluenceConeCarrierV113X36T72(options)
% RUNINFLUENCECONECARRIERV113X36T72 Carrier-direction interaction.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getInfluenceConeCarrierV113Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('InfluenceConeCarrierV113:DirtySource', ...
        'The V113 screen requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', protocol.executionProfile, ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', protocol.bankVariant, ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', 1:3, ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', ...
        protocol.referenceOutcomeScreenPath, ...
    'capturePosteriorSnapshotsEnabled', false, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);
if ~screen.referenceOutcomeReused
    error('InfluenceConeCarrierV113:ReferenceNotReused', ...
        'The frozen counter-clockwise reference was unexpectedly rerun.');
end

ccwIdx = find(strcmp({screen.records.actionName}, ...
    'reference-full-payload'), 1);
cwFullIdx = find(strcmp({screen.records.actionName}, ...
    protocol.clockwiseFullActionName), 1);
candidateIdx = find(strcmp({screen.records.actionName}, ...
    protocol.clockwiseAbstentionActionName), 1);
if isempty(ccwIdx) || isempty(cwFullIdx) || isempty(candidateIdx)
    error('InfluenceConeCarrierV113:MissingArm', ...
        'The V113 bank did not produce all three registered arms.');
end
fullIndices = [ccwIdx, cwFullIdx];
[~, localBest] = min([screen.records(fullIndices).meanEospa]);
bestFullIdx = fullIndices(localBest);
bestFull = screen.records(bestFullIdx);
bestFullOutcome = screen.outcomes(bestFullIdx);
candidate = screen.records(candidateIdx);
candidateOutcome = screen.outcomes(candidateIdx);

bestByTime = mean(bestFullOutcome.eospaBySensorTime, 1);
candidateByTime = mean(candidateOutcome.eospaBySensorTime, 1);
gainByTime = relativeGainPercent(bestByTime, candidateByTime);
[formationGain, formationGainByTime] = formationGains( ...
    bestFullOutcome.eospaBySensorTime, ...
    candidateOutcome.eospaBySensorTime, screen.sensorGroupIds);
targetMembers = find(screen.sensorGroupIds == protocol.targetFormationId);
residualSources = reshape(screen.bank.clockwiseCarrierPolicyDetails. ...
    residualSourcesByReceiver, 1, []);
gatewayCandidates = targetMembers( ...
    screen.sensorGroupIds(residualSources(targetMembers)) ~= ...
        protocol.targetFormationId);
if numel(gatewayCandidates) ~= 1
    error('InfluenceConeCarrierV113:GatewayDrift', ...
        'The clockwise F6 carrier no longer has one cross-input gateway.');
end
targetPeers = setdiff(targetMembers, gatewayCandidates(1), 'stable');
targetPeerTerminalGain = relativeGainPercent( ...
    mean(bestFullOutcome.eospaBySensorTime(targetPeers, end)), ...
    mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));

metrics = struct();
metrics.meanGainPercent = relativeGainPercent( ...
    bestFull.meanEospa, candidate.meanEospa);
metrics.worstSensorGainPercent = relativeGainPercent( ...
    bestFull.worstSensorEospa, candidate.worstSensorEospa);
metrics.minimumFormationGainPercent = min(formationGain);
metrics.minimumAfterMaturityGainPercent = min( ...
    gainByTime(protocol.firstHandoffTimeIndex:end));
metrics.targetPeerTerminalGainPercent = targetPeerTerminalGain;
metrics.windowConsensusGainPercent = relativeGainPercent( ...
    bestFull.consensusOspa, candidate.consensusOspa);
metrics.terminalConsensusGainPercent = relativeGainPercent( ...
    bestFull.terminalConsensusOspa, candidate.terminalConsensusOspa);
metrics.attemptedByteSavingPercent = relativeGainPercent( ...
    bestFull.attemptedBytes, candidate.attemptedBytes);
metrics.selectedB3Passed = candidate.selectedB3Passed;
metrics.gatePassed = ...
    metrics.meanGainPercent >= protocol.minimumMeanGainPercent - 1e-12 && ...
    metrics.minimumAfterMaturityGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    metrics.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    metrics.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    metrics.targetPeerTerminalGainPercent >= ...
        protocol.minimumTargetPeerTerminalGainPercent - 1e-12 && ...
    metrics.windowConsensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    metrics.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    metrics.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    metrics.selectedB3Passed;

result = struct();
result.contractVersion = protocol.resultContractVersion;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.referenceOutcomeReused = screen.referenceOutcomeReused;
result.ccwFullRecord = screen.records(ccwIdx);
result.clockwiseFullRecord = screen.records(cwFullIdx);
result.candidateRecord = candidate;
result.bestFullActionName = bestFull.actionName;
result.bestFullRecordIndex = bestFullIdx;
result.metrics = metrics;
result.gainPercentByTime = gainByTime;
result.formationGainPercent = formationGain;
result.formationGainPercentByTime = formationGainByTime;
result.targetPeerIndices = targetPeers;
result.screenReportPath = screenReportPath;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, [protocol.resultFileStem, '.mat']);
reportPath = fullfile(outputRoot, [protocol.resultFileStem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('%s result: %s\n', protocol.runLabel, reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('InfluenceConeCarrierV113:WriteFailed', ...
        'Could not create the V113 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
ccw = result.ccwFullRecord;
cw = result.clockwiseFullRecord;
candidate = result.candidateRecord;
metrics = result.metrics;
fprintf(fid, '# %s\n\n', result.protocol.reportTitle);
fprintf(fid, '- Frozen CCW reference reused: `%d`\n', ...
    result.referenceOutcomeReused);
fprintf(fid, '- Better full-payload direction: `%s`\n', ...
    result.bestFullActionName);
fprintf(fid, '- Interaction gate passed: `%d`\n\n', ...
    metrics.gatePassed);
fprintf(fid, ['| Arm | Mean E-OSPA | Gain vs CCW | ', ...
    'Gain vs best full | Byte saving vs CCW | B3 |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|:--:|\n');
fprintf(fid, '| CCW full payload | %.6f | -- | -- | -- | %d |\n', ...
    ccw.meanEospa, ccw.selectedB3Passed);
fprintf(fid, '| CW full payload | %.6f | %+.3f%% | -- | %+.3f%% | %d |\n', ...
    cw.meanEospa, cw.meanGainPercent, ...
    cw.attemptedByteSavingPercent, cw.selectedB3Passed);
fprintf(fid, ['| CW safe-formation abstention | %.6f | %+.3f%% | ', ...
    '%+.3f%% | %+.3f%% | %d |\n\n'], ...
    candidate.meanEospa, candidate.meanGainPercent, ...
    metrics.meanGainPercent, candidate.attemptedByteSavingPercent, ...
    candidate.selectedB3Passed);
fprintf(fid, '- Mature-page minimum: `%+.3f%%`\n', ...
    metrics.minimumAfterMaturityGainPercent);
fprintf(fid, '- Formation gains vs best full: `%s%%`\n', ...
    mat2str(result.formationGainPercent, 4));
fprintf(fid, '- F6 non-gateway terminal gain: `%+.3f%%`\n', ...
    metrics.targetPeerTerminalGainPercent);
fprintf(fid, '- Worst-sensor gain: `%+.3f%%`\n', ...
    metrics.worstSensorGainPercent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    metrics.windowConsensusGainPercent, ...
    metrics.terminalConsensusGainPercent);
fprintf(fid, '- Byte saving vs best full: `%+.3f%%`\n', ...
    metrics.attemptedByteSavingPercent);
fprintf(fid, '- Per-page gains vs best full: `%s%%`\n\n', ...
    mat2str(result.gainPercentByTime, 4));
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function [gain, gainByTime] = formationGains( ...
        referenceBySensorTime, candidateBySensorTime, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
gain = zeros(1, numel(groups));
gainByTime = zeros(numel(groups), size(referenceBySensorTime, 2));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    referenceValues = referenceBySensorTime(mask, :);
    candidateValues = candidateBySensorTime(mask, :);
    gain(idx) = relativeGainPercent( ...
        mean(referenceValues(:)), mean(candidateValues(:)));
    gainByTime(idx, :) = relativeGainPercent( ...
        mean(referenceValues, 1), mean(candidateValues, 1));
end
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
