function [reportPath, screen] = ...
    runFormationModeH3OpenedReturnScreen( ...
        presetName, seed, currentTime, options)
% RUNFORMATIONMODEH3OPENEDRETURNSCREEN Formation-local H=3 teacher screen.
%
% A current posterior and topology history are loaded from an already-opened
% continuation cache.  The truth-free v10 machinery constructs the current
% reference/candidate trust-mode bank.  Each return arm changes exactly one
% formation for the first step and then returns to the registered fixed
% reference for the remaining H=3 window.  Truth and future measurements are
% used only after action construction to score offline teacher targets.

if nargin < 4 || isempty(options)
    options = struct();
end
if ~ischar(presetName) || ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || seed < 1 || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || currentTime < 1
    error('Formation-mode H=3 screen request is invalid.');
end
protocol = getLabelSetSimulatorPolicyProtocol();
horizonSteps = round(getField(options, 'horizonSteps', 3));
if horizonSteps ~= 3
    error('Formation-mode opened screen is registered for H=3 only.');
end
interventionDurationSteps = getField( ...
    options, 'interventionDurationSteps', 1);
if ~isscalar(interventionDurationSteps) || ...
        ~isfinite(interventionDurationSteps) || ...
        interventionDurationSteps ~= round(interventionDurationSteps) || ...
        interventionDurationSteps < 1 || ...
        interventionDurationSteps > horizonSteps
    error('Formation-mode intervention duration is invalid.');
end
interventionDurationSteps = round(interventionDurationSteps);
filterSeedOffset = round(getField(options, ...
    'filterSeedOffset', 100000));
if filterSeedOffset ~= 100000
    error('Formation-mode opened screen requires the formal RNG offset.');
end
cacheRoot = getField(options, 'cacheRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'posterior_risk_v10', 'opened_state_audit', 'cache'));
interventionBankType = lower(strrep(char(getField( ...
    options, 'interventionBankType', ...
    'formation-local-single')), '_', '-'));
switch interventionBankType
    case 'formation-local-single'
        defaultOutputRoot = 'formation_mode_h3_v11';
        screenContractVersion = ...
            'formation-local-h3-opened-return-screen-v1';
    case 'formation-conservative-pair'
        defaultOutputRoot = 'formation_pair_h3_v12';
        screenContractVersion = ...
            'formation-conservative-pair-h3-opened-return-screen-v1';
    case 'formation-projected-joint'
        defaultOutputRoot = 'formation_joint_h3_v15';
        screenContractVersion = ...
            'formation-projected-joint-h3-opened-return-screen-v1';
    otherwise
        error('Unknown formation-mode intervention bank type.');
end
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    defaultOutputRoot, 'opened_return_screen', presetName));
writeReportEnabled = logical(getField(options, 'writeReport', true));
allowDirtySource = logical(getField(options, 'allowDirtySource', false));

gitState = resolveResearchGitState();
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official formation-mode return generation requires a ', ...
        'clean tracked and MATLAB/Octave source state.']);
end
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
returnTimes = currentTime + (0:(horizonSteps - 1));
if returnTimes(end) > size(inputs.measurements, 2)
    error('Formation-mode H=3 return exceeds the scenario length.');
end
cachePath = fullfile(cacheRoot, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
    seed, currentTime));
bundle = loadOpenedBundle( ...
    cachePath, presetName, seed, currentTime, inputs.config);
context = buildOpenedContext(inputs, bundle, currentTime);

policyOptions = buildPosteriorRiskPolicyOptions(protocol);
timerId = tic;
[selectedPolicyAdjacency, v10Details] = ...
    selectLabelSetAdaptiveDominantRoutingPolicy( ...
        context, ...
        ['composite-balanced-certified-overlap-consensus-', ...
         'joint-trust-posterior-risk-tail-safe-payload-aware'], ...
        policyOptions);
bankConstructionSeconds = toc(timerId);
projection = v10Details.consensusProjection;
assertV10BankContract(v10Details, projection);
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
switch interventionBankType
    case 'formation-local-single'
        bank = buildFormationModeInterventionBank( ...
            projection, groupIds);
    case 'formation-conservative-pair'
        bank = buildConservativePairFormationModeInterventionBank( ...
            projection, groupIds, struct('pairTrustWeight', 0.30));
    case 'formation-projected-joint'
        bank = buildProjectedJointFormationModeInterventionBank( ...
            projection, groupIds);
        assertProjectedJointMatchesPolicy( ...
            bank, selectedPolicyAdjacency, ...
            v10Details.fusionWeightMatrix);
end
assertReferenceMatchesRegisteredPolicy( ...
    context, bank, protocol);

defaultActionIndices = find(bank.actionWithinReferencePayload);
actionIndices = reshape(getField( ...
    options, 'actionIndices', defaultActionIndices), 1, []);
if isempty(actionIndices) || ...
        any(~isfinite(actionIndices)) || ...
        any(actionIndices ~= round(actionIndices)) || ...
        any(actionIndices < 1) || ...
        any(actionIndices > bank.actionCount) || ...
        numel(unique(actionIndices)) ~= numel(actionIndices) || ...
        ~any(actionIndices == bank.referenceActionIndex)
    error('Formation-mode H=3 action subset is invalid.');
end
if any(~bank.actionWithinReferencePayload(actionIndices))
    error('Formation-mode H=3 action exceeds reference payload.');
end

croppedInputs = cropInputs(inputs, returnTimes(end));
history = bundle.preDecisionTopologyHistoryByTime{currentTime};
previousPolicyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
outcomes = repmat(emptyOutcome(), 1, numel(actionIndices));
for subsetIdx = 1:numel(actionIndices)
    actionIdx = actionIndices(subsetIdx);
    actionDurationSteps = interventionDurationSteps;
    if actionIdx == bank.referenceActionIndex
        actionDurationSteps = 1;
    end
    fprintf([ ...
        '%s seed %d t=%d H=3 action %d/%d: %s...\n'], ...
        presetName, seed, currentTime, subsetIdx, ...
        numel(actionIndices), bank.actionNames{actionIdx});
    outcomes(subsetIdx) = runAction( ...
        croppedInputs, bundle.posteriorSnapshots{currentTime}, ...
        history, previousPolicyHistory, returnTimes, ...
        bank.actionAdjacency(:, :, actionIdx), ...
        bank.actionFusionWeights(:, :, actionIdx), ...
        actionDurationSteps, protocol, seed, filterSeedOffset);
    fprintf([ ...
        '  E-OSPA %.6f; worst %.6f; consensus %.6f; ', ...
        'attempted %.0f B; %.2fs\n'], ...
        outcomes(subsetIdx).meanEospa, ...
        outcomes(subsetIdx).worstSensorEospa, ...
        outcomes(subsetIdx).consensusOspa, ...
        outcomes(subsetIdx).attemptedBytes, ...
        outcomes(subsetIdx).elapsedSeconds);
end

referenceSubsetIdx = find( ...
    actionIndices == bank.referenceActionIndex, 1);
referenceOutcome = outcomes(referenceSubsetIdx);
records = repmat(emptyRecord(), 1, numel(actionIndices));
for subsetIdx = 1:numel(actionIndices)
    actionIdx = actionIndices(subsetIdx);
    outcome = outcomes(subsetIdx);
    record = emptyRecord();
    record.actionIndex = actionIdx;
    record.actionName = bank.actionNames{actionIdx};
    record.formationIndex = ...
        bank.actionFormationIndex(actionIdx);
    if isfield(bank, 'actionFormationIndices')
        record.formationIndices = ...
            bank.actionFormationIndices(actionIdx, :);
    elseif record.formationIndex > 0
        record.formationIndices = record.formationIndex;
    else
        record.formationIndices = zeros(1, 0);
    end
    if isfield(bank, 'actionModeIndices')
        record.formationModeIndices = ...
            bank.actionModeIndices(actionIdx, :);
        record.trustWeightByFormation = ...
            bank.modeTrustWeights(record.formationModeIndices);
        record.modeIndex = NaN;
        record.trustWeight = mean(record.trustWeightByFormation);
    else
        record.modeIndex = bank.actionModeIndex(actionIdx);
        record.trustWeight = bank.modeTrustWeights(record.modeIndex);
    end
    record.posteriorProxyAllowed = ...
        bank.actionPosteriorProxyAllowed(actionIdx);
    record.posteriorProxyObjective = ...
        bank.actionPosteriorObjective(actionIdx);
    record.predictedPayloadBytes = ...
        bank.actionPayloadBytes(actionIdx);
    record.meanEospa = outcome.meanEospa;
    record.worstSensorEospa = outcome.worstSensorEospa;
    record.consensusOspa = outcome.consensusOspa;
    record.attemptedBytes = outcome.attemptedBytes;
    record.meanGainPercent = relativeGainPercent( ...
        referenceOutcome.meanEospa, outcome.meanEospa);
    record.worstGainPercent = relativeGainPercent( ...
        referenceOutcome.worstSensorEospa, ...
        outcome.worstSensorEospa);
    record.consensusGainPercent = relativeGainPercent( ...
        referenceOutcome.consensusOspa, ...
        outcome.consensusOspa);
    record.attemptedByteSavingPercent = ...
        relativeGainPercent( ...
            referenceOutcome.attemptedBytes, ...
            outcome.attemptedBytes);
    record.formationMeanEospa = outcome.formationMeanEospa;
    record.formationGainPercent = 100 * ...
        (referenceOutcome.formationMeanEospa - ...
            outcome.formationMeanEospa) ./ ...
        max(referenceOutcome.formationMeanEospa, eps);
    record.minimumFormationGainPercent = ...
        min(record.formationGainPercent);
    record.selectedB3Passed = ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass);
    records(subsetIdx) = record;
end

nonreference = [records.actionIndex] ~= ...
    bank.referenceActionIndex;
proxyPositive = [records.posteriorProxyAllowed] & nonreference;
realizedMeanPositive = [records.meanGainPercent] > 0 & nonreference;
proxyAllowedByRecord = [records.posteriorProxyAllowed];
meanGainByRecord = [records.meanGainPercent];
tailSafeMask = ...
    [records.minimumFormationGainPercent] >= -1e-12;
screen = struct();
screen.contractVersion = screenContractVersion;
screen.interventionBankType = interventionBankType;
screen.generatedAt = datestr(now, 31);
screen.generationGitCommit = gitState.commit;
screen.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
screen.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
screen.presetName = presetName;
screen.seed = seed;
screen.currentTime = currentTime;
screen.returnTimes = returnTimes;
screen.horizonSteps = horizonSteps;
screen.interventionDurationSteps = interventionDurationSteps;
screen.cachePath = cachePath;
screen.cacheSha256 = computeFileSha256(cachePath);
screen.bankConstructionSeconds = bankConstructionSeconds;
screen.bank = bank;
screen.actionIndices = actionIndices;
screen.outcomes = outcomes;
screen.records = records;
screen.referenceSubsetIndex = referenceSubsetIdx;
screen.posteriorProxyPositiveCount = nnz(proxyPositive);
screen.realizedMeanPositiveCount = nnz(realizedMeanPositive);
screen.proxyTruePositiveCount = ...
    nnz(proxyPositive & realizedMeanPositive);
screen.proxyFalsePositiveCount = ...
    nnz(proxyPositive & ~realizedMeanPositive & nonreference);
screen.proxyFalseNegativeCount = ...
    nnz(~proxyAllowedByRecord & ...
        realizedMeanPositive & nonreference);
screen.proxyActionAgreementFraction = mean( ...
    proxyAllowedByRecord(nonreference) == ...
        realizedMeanPositive(nonreference));
screen.bestMeanGainPercent = max(meanGainByRecord);
screen.bestTailSafeMeanGainPercent = ...
    maximumOrNaN(meanGainByRecord(tailSafeMask));
screen.featuresUseTruth = false;
screen.featuresUseFutureMeasurements = false;
screen.featuresUseFutureOutcome = false;
screen.targetsUseTruth = true;
screen.targetsUseFutureMeasurements = true;
screen.runtimePolicyUsesTruth = false;
screen.openedDevelopmentEvidenceOnly = true;
screen.validationClaimAllowed = false;
screen.evidenceBoundary = [ ...
    'The action bank uses only the opened current posterior, ', ...
    'current link probabilities, payload estimates, and topology ', ...
    'history. A selected route may be held for the registered duration ', ...
    'without recomputing it from future data. Truth and future ', ...
    'measurements score H=3 offline teacher ', ...
    'targets only. The source state and action design are already ', ...
    'opened, so this screen may select a learning target but cannot ', ...
    'support M24 or X36 validation claims.'];

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    if strcmp(interventionBankType, 'formation-conservative-pair')
        stemPrefix = 'FORMATION_PAIR_H3';
    else
        stemPrefix = 'FORMATION_MODE_H3';
    end
    if interventionDurationSteps == 1
        stem = sprintf( ...
            '%s_%s_SEED%d_T%d', stemPrefix, ...
            upper(strrep(presetName, '-', '_')), seed, currentTime);
    else
        stem = sprintf( ...
            '%s_%s_SEED%d_T%d_D%d', stemPrefix, ...
            upper(strrep(presetName, '-', '_')), seed, ...
            currentTime, interventionDurationSteps);
    end
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    screen.reportPath = reportPath;
    screen.matPath = matPath;
    save('-mat7-binary', matPath, 'screen');
    writeReport(reportPath, screen);
    fprintf('Formation-mode H=3 opened screen: %s\n', reportPath);
end
end

function outcome = runAction( ...
        inputs, initialPosteriors, history, previousPolicyHistory, ...
        returnTimes, firstAdjacency, firstWeights, ...
        interventionDurationSteps, protocol, seed, filterSeedOffset)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * inputs.config.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    sprintf('formation-h3-frozen-duration-%d-then-reference-v1', ...
        interventionDurationSteps);
config.topologyPosteriorCaptureTimes = returnTimes;
config.topologyPolicyFcn = @(context) frozenDurationThenReference( ...
    context, returnTimes(1), firstAdjacency, ...
    firstWeights, interventionDurationSteps, protocol);
config.filterInitialLocalPosteriorBySensor = initialPosteriors;
config.filterInitialLocalPosteriorTime = returnTimes(1);
config.filterInitialPreviousAdjacencyHistory = previousPolicyHistory;
config.filterInitialPreviousAdjacencyTimes = history.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'opened-reference-continuation-cache-v1';

rng(seed + filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);
for durationIdx = 1:interventionDurationSteps
    executed = convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge( ...
            :, :, returnTimes(durationIdx)));
    if ~isequal(executed, logical(firstAdjacency))
        error('Formation-mode H=3 arm did not hold its registered action.');
    end
end
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(returnTimes));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(returnTimes));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(returnTimes));
infeasible = logical( ...
    ~diagnostics.topologyFeasible(returnTimes) | ...
    finiteLogical(diagnostics. ...
        topologyPolicyTopologyInfeasible(returnTimes)));
if any(truthUse) || any(repair) || ...
        any(emergency) || any(infeasible)
    error('Formation-mode H=3 arm violated a hard runtime gate.');
end

nodeCount = inputs.config.numberOfSensors;
selected = false(nodeCount, nodeCount, numel(returnTimes));
delivered = selected;
for timeIdx = 1:numel(returnTimes)
    selected(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(timeIdx)));
    delivered(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered(:, :, returnTimes(timeIdx)));
end
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        previousPolicyHistory, selected, ...
        inputs.config.sensorGroupIds);
[deliveredSensorB3, deliveredFormationB3] = ...
    computeRollingB3Pass( ...
        convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
            history.deliveredDirectedEdgeHistory), ...
        delivered, inputs.config.sensorGroupIds);
if ~all(selectedSensorB3) || ~all(selectedFormationB3)
    error('Formation-mode H=3 arm violated selected rolling-B3 safety.');
end

eospa = zeros(nodeCount, numel(returnTimes));
cardinalityError = zeros(nodeCount, numel(returnTimes));
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, sensorCardinality] = ...
        computeSimulationOspa( ...
            inputs.model, inputs.groundTruthRfs, ...
            estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(returnTimes);
    cardinalityError(sensorIdx, :) = abs( ...
        sensorCardinality(returnTimes) - ...
        inputs.groundTruthRfs.cardinality(returnTimes));
end
sensorMeans = mean(eospa, 2);
groups = unique(inputs.config.sensorGroupIds, 'stable');
formationMeans = zeros(1, numel(groups));
for formationIdx = 1:numel(groups)
    members = inputs.config.sensorGroupIds == groups(formationIdx);
    formationMeans(formationIdx) = mean(sensorMeans(members));
end
[positionDisagreement, cardinalityDispersion, ...
    ospaDisagreement] = computeDistributedConsensusMetrics( ...
        estimates, inputs.model);

outcome = emptyOutcome();
outcome.meanEospa = mean(eospa(:));
outcome.worstSensorEospa = max(sensorMeans);
outcome.sensorMeanEospa = reshape(sensorMeans, 1, []);
outcome.formationMeanEospa = formationMeans;
outcome.eospaBySensorTime = eospa;
outcome.meanCardinalityError = mean(cardinalityError(:));
outcome.consensusOspa = finiteMean( ...
    ospaDisagreement(returnTimes));
outcome.consensusPosition = finiteMean( ...
    positionDisagreement(returnTimes));
outcome.consensusCardinality = finiteMean( ...
    cardinalityDispersion(returnTimes));
outcome.posteriorConsensus = finiteMean( ...
    diagnostics.posteriorConsensusCombined(returnTimes));
outcome.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes( ...
        :, :, returnTimes), 1), 2), 1, []);
outcome.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes( ...
        :, :, returnTimes), 1), 2), 1, []);
outcome.attemptedBytes = sum(outcome.attemptedBytesByTime);
outcome.deliveredBytes = sum(outcome.deliveredBytesByTime);
outcome.selectedAdjacency = selected;
outcome.deliveredAdjacency = delivered;
outcome.selectedSensorB3Pass = selectedSensorB3;
outcome.selectedFormationB3Pass = selectedFormationB3;
outcome.deliveredSensorB3Pass = deliveredSensorB3;
outcome.deliveredFormationB3Pass = deliveredFormationB3;
outcome.truthUseCount = nnz(truthUse);
outcome.repairCount = nnz(repair);
outcome.payloadEmergencyCount = nnz(emergency);
outcome.infeasibleCount = nnz(infeasible);
outcome.firstActionExact = true;
outcome.interventionActionsExact = true;
outcome.interventionDurationSteps = interventionDurationSteps;
outcome.elapsedSeconds = elapsedSeconds;
end

function [adjacency, details] = frozenDurationThenReference( ...
        context, anchorTime, firstAdjacency, firstWeights, ...
        interventionDurationSteps, protocol)
if context.currentTime >= anchorTime && ...
        context.currentTime < anchorTime + interventionDurationSteps
    adjacency = logical(firstAdjacency);
    weightSupport = adjacency | eye(size(adjacency, 1)) > 0;
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:))) || ...
            ~isequal(size(firstWeights), size(adjacency)) || ...
            any(firstWeights(:) < 0) || ...
            any(firstWeights(~weightSupport) > 1e-12)
        error('Frozen formation-mode first action is invalid.');
    end
    details = struct( ...
        'mode', 'frozen-formation-mode-first-step', ...
        'fusionWeightMatrix', firstWeights, ...
        'truthUsed', false, ...
        'groundTruthUsed', false, ...
        'futureOutcomeUsed', false, ...
        'runtimeFrozenGraphReplay', true, ...
        'interventionDurationSteps', interventionDurationSteps);
else
    [adjacency, details] = ...
        selectBackboneResidualSplicedCyclePolicy( ...
            context, 'fixed-counter-clockwise', ...
            referencePolicyOptions(protocol));
    details.runtimeFrozenGraphReplay = false;
    details.interventionDurationSteps = interventionDurationSteps;
end
end

function bundle = loadOpenedBundle( ...
        path, presetName, seed, currentTime, config)
if exist(path, 'file') ~= 2
    error('Missing opened formation-mode cache: %s', path);
end
loaded = load(path, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Opened formation-mode cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
required = { ...
    'presetName', 'seed', 'snapshotTimes', 'configSnapshot', ...
    'posteriorSnapshots', 'preDecisionTopologyHistoryByTime', ...
    'openedDevelopmentEvidenceOnly', 'validationClaimAllowed'};
if ~all(isfield(bundle, required)) || ...
        ~strcmp(bundle.presetName, presetName) || ...
        bundle.seed ~= seed || ...
        ~isequal(bundle.snapshotTimes, currentTime) || ...
        ~isequaln(bundle.configSnapshot, config) || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        bundle.validationClaimAllowed || ...
        numel(bundle.posteriorSnapshots) < currentTime || ...
        isempty(bundle.posteriorSnapshots{currentTime}) || ...
        numel(bundle.preDecisionTopologyHistoryByTime) < currentTime || ...
        isempty(bundle.preDecisionTopologyHistoryByTime{currentTime})
    error('Opened formation-mode cache provenance mismatch.');
end
history = bundle.preDecisionTopologyHistoryByTime{currentTime};
if ~isfield(history, 'selectedDirectedEdgeHistory') || ...
        ~isfield(history, 'deliveredDirectedEdgeHistory') || ...
        ~isfield(history, 'times') || ...
        size(history.selectedDirectedEdgeHistory, 3) ~= 2 || ...
        size(history.deliveredDirectedEdgeHistory, 3) ~= 2 || ...
        numel(history.times) ~= 2
    error('Opened formation-mode cache lacks two-step history.');
end
end

function context = buildOpenedContext(inputs, bundle, currentTime)
nodeCount = inputs.config.numberOfSensors;
history = bundle.preDecisionTopologyHistoryByTime{currentTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{currentTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = previousHistory;
context.previousAdjacencyHistoryCount = size(previousHistory, 3);
context.previousAdjacencyHistoryTimes = history.times;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacencyHistorySource = ...
    'opened-reference-continuation-cache-v1';
context.previousAdjacency = previousHistory(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = inputs.graphData.positions(:, :, currentTime);
end

function options = buildPosteriorRiskPolicyOptions(protocol)
options = struct( ...
    'protocol', protocol, ...
    'dominantWeight', protocol. ...
        adaptiveDominantJointTrustStabilityReferenceWeight, ...
    'residualWeight', protocol. ...
        adaptiveDominantJointTrustStabilityResidualWeight, ...
    'residualOrientation', protocol. ...
        adaptiveDominantResidualOrientation, ...
    'payloadMarginFraction', protocol. ...
        adaptiveDominantJointTrustStabilityPayloadMarginFraction, ...
    'candidateDominantWeightGrid', protocol. ...
        adaptiveDominantJointTrustStabilityCandidateWeightGrid, ...
    'minimumDynamicObjectiveAdvantage', protocol. ...
        adaptiveDominantJointTrustStabilityMinimumDynamicObjectiveAdvantage, ...
    'consensusAggregationMode', protocol. ...
        adaptiveDominantJointTrustStabilityAggregationMode, ...
    'consensusTailFraction', protocol. ...
        adaptiveDominantJointTrustStabilityTailFraction, ...
    'maximumConsensusProjectionFormationCount', protocol. ...
        adaptiveDominantJointTrustStabilityMaximumFormationCount, ...
    'consensusPayloadFallbackMode', protocol. ...
        adaptiveDominantJointTrustStabilityPayloadFallbackMode, ...
    'posteriorRiskPrototypeAuthorized', true, ...
    'posteriorRiskReceiverTailFraction', 0.34, ...
    'posteriorRiskReceiverTailWeight', 0.5, ...
    'formationRiskTailFraction', 0.34, ...
    'formationRiskTailWeight', 0.5, ...
    'formationRiskToleranceFraction', 0);
end

function assertV10BankContract(details, projection)
if ~strcmp(details.contractVersion, ...
        ['adaptive-dominant-posterior-risk-formation-', ...
         'tail-v10-prototype']) || ...
        ~strcmp(projection.objectiveMode, ...
            'posterior-bayes-risk') || ...
        ~projection.formationRiskGuardEnabled || ...
        ~projection.singleRoundExact || ...
        details.truthUsed || ...
        projection.posteriorRiskObjectiveDetails.truthUsed
    error('Formation-mode H=3 v10 bank contract failed.');
end
end

function assertReferenceMatchesRegisteredPolicy( ...
        context, bank, protocol)
[adjacency, details] = ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, 'fixed-counter-clockwise', ...
        referencePolicyOptions(protocol));
