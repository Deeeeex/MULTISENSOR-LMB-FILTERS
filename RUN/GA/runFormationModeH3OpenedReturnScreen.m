        ~isequal(size(referenceWeights), size(bankWeights)) || ...
        max(abs(referenceWeights(:) - bankWeights(:))) > 1e-12
    error(['Formation-mode bank reference does not match the ', ...
        'registered fixed reference arm.']);
end
end

function assertProjectedJointMatchesPolicy( ...
        bank, selectedAdjacency, selectedWeights)
