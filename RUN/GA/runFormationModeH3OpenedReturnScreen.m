fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    screen.evidenceBoundary);
end

function value = formatFormationIndices(indices)
indices = reshape(indices, 1, []);
indices = indices(indices > 0);
if isempty(indices)
    value = '0';
elseif numel(indices) == 1
    value = sprintf('%d', indices);
else
    value = sprintf('%d+%d', indices(1), indices(2));
end
end

