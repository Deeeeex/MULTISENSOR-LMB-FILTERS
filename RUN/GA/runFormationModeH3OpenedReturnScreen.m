if fid < 0
    error('Could not open formation-mode H=3 report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
if strcmp(screen.interventionBankType, ...
        'formation-conservative-pair')
    reportTitle = 'Formation-pair H=3 opened return screen';
elseif strcmp(screen.interventionBankType, ...
        'formation-projected-joint')
    reportTitle = 'Formation-projected-joint H=3 opened return screen';
else
    reportTitle = 'Formation-local H=3 opened return screen';
end
fprintf(fid, '# %s\n\n', reportTitle);
fprintf(fid, '- Contract: `%s`\n', screen.contractVersion);
