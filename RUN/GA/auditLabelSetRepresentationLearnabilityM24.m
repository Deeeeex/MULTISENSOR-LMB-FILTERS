function [auditPath, audit] = ...
    auditLabelSetRepresentationLearnabilityM24(options)
% AUDITLABELSETREPRESENTATIONLEARNABILITYM24 Whole-seed set preflight.
%
% A fixed DeepSets relational model predicts pairwise current-task
% differences on one completely held-out M24 training seed. Current truth
% is used only as a representation diagnostic target. A task-trained
% aggregate relational ridge model is evaluated on the identical folds so
% that added label detail must show measurable value before a GNN policy is
% implemented or any closed-loop training is authorized.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.representationAuditAuthorized
    error('Label-set representation audit is not authorized.');
end
gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error('Official label-set representation audit requires clean source.');
end

[blocks, shardRecords, sourceSummary] = ...
    loadRegisteredShards(protocol);
if exist(protocol.actionEvidencePath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256( ...
            protocol.actionEvidencePath), ...
            protocol.actionEvidenceSha256)
    error('Registered pairwise action evidence is unavailable.');
end
loaded = load(protocol.actionEvidencePath, 'analysis');
if ~isfield(loaded, 'analysis')
    error('Registered action evidence has no analysis payload.');
end
[actions, pairs] = assembleActions( ...
    loaded.analysis, blocks, protocol);

folds = repmat(emptyFold(), 1, numel(protocol.trainingSeeds));
aggregatePrediction = nan(1, numel(pairs));
labelSetPrediction = nan(1, numel(pairs));
for foldIdx = 1:numel(protocol.trainingSeeds)
    heldoutSeed = protocol.trainingSeeds(foldIdx);
    fitSeeds = setdiff( ...
        protocol.trainingSeeds, heldoutSeed, 'stable');
    aggregateModel = fitAggregatePairModel( ...
        actions, pairs, fitSeeds, protocol);
    labelSetModel = fitLabelSetPairModel( ...
        actions, pairs, fitSeeds, protocol, ...
        protocol.representationInitializationSeed + heldoutSeed);
    heldoutMask = [pairs.seed] == heldoutSeed;
    aggregateFoldPrediction = predictAggregatePairs( ...
        aggregateModel, actions, pairs(heldoutMask));
    labelSetFoldPrediction = predictLabelSetPairs( ...
        labelSetModel, actions, pairs(heldoutMask));
    aggregatePrediction(heldoutMask) = ...
        aggregateFoldPrediction;
    labelSetPrediction(heldoutMask) = ...
        labelSetFoldPrediction;

    fold = emptyFold();
    fold.heldoutSeed = heldoutSeed;
    fold.fitSeeds = fitSeeds;
    fold.aggregateMetrics = computeMetrics( ...
        pairs(heldoutMask), aggregateFoldPrediction);
    fold.labelSetMetrics = computeMetrics( ...
        pairs(heldoutMask), labelSetFoldPrediction);
    fold.labelSetFinalLoss = ...
        labelSetModel.lossHistory(end, 1);
    fold.labelSetFinalRegularization = ...
        labelSetModel.lossHistory(end, 2);
    folds(foldIdx) = fold;
    fprintf(['label-set LOSO seed %d: aggregate acc %.3f rho %.3f, ', ...
        'set acc %.3f rho %.3f\n'], ...
        heldoutSeed, ...
        fold.aggregateMetrics.preferenceAccuracy, ...
        fold.aggregateMetrics.differenceSpearman, ...
        fold.labelSetMetrics.preferenceAccuracy, ...
        fold.labelSetMetrics.differenceSpearman);
end
if any(~isfinite(aggregatePrediction)) || ...
        any(~isfinite(labelSetPrediction))
    error('Label-set LOSO predictions are incomplete.');
end

aggregateMetrics = computeMetrics(pairs, aggregatePrediction);
labelSetMetrics = computeMetrics(pairs, labelSetPrediction);
perSeedLabelSetSpearman = arrayfun(@(fold) ...
    fold.labelSetMetrics.differenceSpearman, folds);
positivePerSeedSpearmanFraction = mean( ...
    perSeedLabelSetSpearman > 0);
accuracyImprovement = ...
    labelSetMetrics.preferenceAccuracy - ...
    aggregateMetrics.preferenceAccuracy;
spearmanImprovement = ...
    labelSetMetrics.differenceSpearman - ...
    aggregateMetrics.differenceSpearman;

gates = struct();
gates.source = ...
    sourceSummary.stateCount == ...
        protocol.registeredStateCount && ...
    sourceSummary.validLabelRowCount == ...
        protocol.registeredValidLabelRowCount && ...
    sourceSummary.maximumObservedLabelCount == ...
        protocol.registeredMaximumObservedLabelCount && ...
    numel(pairs) == protocol.expectedPairCount;
gates.preference = ...
    labelSetMetrics.preferenceAccuracy >= ...
        protocol. ...
            minimumRepresentationPairwisePreferenceAccuracy;
gates.rank = isfinite( ...
    labelSetMetrics.differenceSpearman) && ...
    labelSetMetrics.differenceSpearman >= ...
        protocol.minimumRepresentationDifferenceSpearman;
gates.perSeedRank = ...
    positivePerSeedSpearmanFraction >= ...
        protocol.minimumPositivePerSeedSpearmanFraction;
gates.taskAggregateImprovement = ...
    ~protocol.requireTaskAggregateImprovement || ...
    accuracyImprovement >= ...
        protocol. ...
            minimumPairwiseImprovementOverTaskAggregate || ...
    spearmanImprovement >= ...
        protocol. ...
            minimumSpearmanImprovementOverTaskAggregate;
allGatesPassed = all(structfun( ...
    @(value) logical(value), gates));

audit = struct();
audit.contractVersion = ...
    'label-set-representation-learnability-m24-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
audit.protocolId = protocol.id;
audit.shardRecords = shardRecords;
audit.sourceSummary = sourceSummary;
audit.actionEvidenceSha256 = ...
    protocol.actionEvidenceSha256;
audit.trainingSeeds = protocol.trainingSeeds;
audit.snapshotTimes = protocol.snapshotTimes;
audit.actionCount = numel(actions);
audit.pairCount = numel(pairs);
audit.aggregatePrediction = aggregatePrediction;
audit.labelSetPrediction = labelSetPrediction;
audit.aggregateMetrics = aggregateMetrics;
audit.labelSetMetrics = labelSetMetrics;
audit.perSeedLabelSetSpearman = ...
    perSeedLabelSetSpearman;
audit.positivePerSeedLabelSetSpearmanFraction = ...
    positivePerSeedSpearmanFraction;
audit.pairwiseAccuracyImprovementOverTaskAggregate = ...
    accuracyImprovement;
audit.differenceSpearmanImprovementOverTaskAggregate = ...
    spearmanImprovement;
audit.folds = folds;
audit.featuresUseTruth = false;
audit.featuresUseFutureOutcome = false;
audit.modelTrainingUsesCurrentTaskTruth = true;
audit.modelTrainingUsesFutureOutcome = false;
audit.numericLabelIdentifiersUsedAsFeatures = false;
audit.wholeSeedOuterEvaluation = true;
audit.hyperparametersFrozenBeforeAudit = true;
audit.gates = gates;
audit.allGatesPassed = allGatesPassed;
audit.labelSetRepresentationAccepted = allGatesPassed;
audit.messagePassingImplementationAuthorized = allGatesPassed;
audit.closedLoopPolicyTrainingAuthorized = false;
audit.developmentEvaluationAuthorized = false;
audit.heldoutM24Authorized = false;
audit.x36PolicyRunAuthorized = false;
audit.evidenceBoundary = [ ...
    'All model inputs are truth-free observable posterior, link and ', ...
    'history features. Current tracking truth trains this preflight ', ...
    'only to test whether per-label structure transfers across whole ', ...
    'M24 training seeds. It is not a deployable policy, an imitation ', ...
    'claim or a closed-loop result. Even a pass authorizes only the ', ...
    'message-passing implementation; policy selection must use paired ', ...
    'closed-loop simulator return. Development M24, held-out M24 and ', ...
    'X36 remain sealed.'];

auditPath = getField(options, 'auditPath', ...
    protocol.defaultRepresentationAuditPath);
reportPath = getField(options, 'reportPath', ...
    protocol.defaultRepresentationReportPath);
audit.auditPath = auditPath;
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Label-set representation audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function [blocks, records, summary] = ...
        loadRegisteredShards(protocol)
blocks = repmat(emptyBlock(), 1, 0);
records = repmat(struct( ...
    'seed', 0, 'path', '', 'sha256', '', ...
    'generationCommit', '', 'stateCount', 0), ...
    1, numel(protocol.registeredShardSeeds));
validLabelRowCount = 0;
maximumObservedLabelCount = 0;
for seedIdx = 1:numel(protocol.registeredShardSeeds)
    seed = protocol.registeredShardSeeds(seedIdx);
    path = protocol.registeredShardPaths{seedIdx};
    expectedSha256 = ...
        protocol.registeredShardSha256{seedIdx};
    if exist(path, 'file') ~= 2 || ...
            ~strcmp(computeFileSha256(path), expectedSha256)
        error('Registered label-set shard hash mismatch: %s', path);
    end
    loaded = load(path, 'dataset');
    if ~isfield(loaded, 'dataset')
        error('Registered label-set shard has no dataset.');
    end
    dataset = loaded.dataset;
    if ~strcmp(dataset.protocolId, protocol.id) || ...
            ~strcmp(dataset.contractVersion, ...
                protocol.datasetContractVersion) || ...
            ~strcmp(dataset.generationGitCommit, ...
                protocol.shardGenerationCommit) || ...
            dataset.generationResearchWorktreeDirty || ...
            dataset.seed ~= seed || ...
            ~isequal(dataset.labelTimes, ...
                protocol.snapshotTimes) || ...
            ~strcmp(dataset.featureContractSha256, ...
                protocol. ...
                    registeredFeatureContractSha256) || ...
            dataset.featuresUseTruth || ...
            dataset.featuresUseFutureOutcome || ...
            dataset.behaviorUsesTruth || ...
            dataset.behaviorUsesFutureOutcome || ...
            ~dataset.diagnosticTargetsUseTruth || ...
            dataset.diagnosticTargetsUseFutureOutcome || ...
            dataset.numericLabelIdentifiersUsedAsFeatures || ...
            dataset.labelCapacityOverflowed || ...
            ~dataset.losslessWithinCapacity || ...
            dataset.policyModelTrained || ...
            dataset.closedLoopReturnEvaluated || ...
            dataset.developmentLabelsOpened || ...
            dataset.heldoutM24Opened || dataset.x36Opened || ...
            numel(dataset.blocks) ~= ...
                numel(protocol.snapshotTimes)
        error('Registered label-set shard envelope is invalid.');
    end
    for blockIdx = 1:numel(dataset.blocks)
        source = dataset.blocks(blockIdx);
        if source.seed ~= seed || ...
                source.currentTime ~= ...
                    protocol.snapshotTimes(blockIdx) || ...
                source.featuresUseTruth || ...
                source.featuresUseFutureOutcome || ...
                ~source.diagnosticTargetsUseTruth || ...
                source.diagnosticTargetsUseFutureOutcome || ...
                source.numericLabelIdentifiersUsedAsFeatures || ...
                size(source.labelFeatures, 1) ~= ...
                    protocol.expectedCandidateCount || ...
                size(source.labelFeatures, 2) ~= ...
                    protocol.maxLabelCount || ...
                size(source.labelFeatures, 3) ~= ...
                    protocol.expectedLabelFeatureCount || ...
                any(~isfinite(source.labelFeatures(:))) || ...
                any(sum(source.labelMask, 2) ~= ...
                    source.labelCounts)
            error('Registered label-set block is invalid.');
        end
        padding = bsxfun(@times, source.labelFeatures, ...
            ~source.labelMask);
        if any(padding(:) ~= 0)
            error('Registered label-set padding is nonzero.');
        end
        validLabelRowCount = validLabelRowCount + ...
            nnz(source.labelMask);
        maximumObservedLabelCount = max( ...
            maximumObservedLabelCount, ...
            max(source.labelCounts));
        block = emptyBlock();
        fields = fieldnames(block);
        for fieldIdx = 1:numel(fields)
            block.(fields{fieldIdx}) = ...
                source.(fields{fieldIdx});
        end
        blocks(end + 1) = block; %#ok<AGROW>
    end
    records(seedIdx) = struct( ...
        'seed', seed, 'path', path, ...
        'sha256', expectedSha256, ...
        'generationCommit', ...
            dataset.generationGitCommit, ...
        'stateCount', numel(dataset.blocks));
end
keys = [[blocks.seed]', [blocks.currentTime]'];
[~, order] = sortrows(keys, [1, 2]);
blocks = blocks(order);
summary = struct();
summary.stateCount = numel(blocks);
summary.validLabelRowCount = validLabelRowCount;
summary.maximumObservedLabelCount = ...
    maximumObservedLabelCount;
summary.featureContractSha256 = ...
    protocol.registeredFeatureContractSha256;
summary.featuresUseTruth = false;
summary.numericLabelIdentifiersUsedAsFeatures = false;
end

function [actions, pairs] = ...
        assembleActions(source, blocks, protocol)
ordinal = getOrdinalFullInformationLearnabilityProtocol();
required = { ...
    'protocolId', 'generationResearchWorktreeDirty', ...
    'trainingSeeds', 'snapshotTimes', ...
    'scoreTruthUsed', 'targetTruthUsed', 'rows'};
if ~all(isfield(source, required)) || ...
        ~strcmp(source.protocolId, ...
            ordinal.predecessorProtocolId) || ...
        source.generationResearchWorktreeDirty || ...
        ~isequal(source.trainingSeeds, ...
            protocol.trainingSeeds) || ...
        ~isequal(source.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        source.scoreTruthUsed || ~source.targetTruthUsed || ...
        numel(source.rows) ~= 2 * ...
            protocol.expectedPairCount
    error('Pairwise action evidence contract is invalid.');
end
actions = repmat(emptyAction(), 1, numel(source.rows));
for actionIdx = 1:numel(source.rows)
    row = source.rows(actionIdx);
    blockMask = [blocks.seed] == row.seed & ...
        [blocks.currentTime] == row.currentTime;
    if nnz(blockMask) ~= 1
        error('Label-set action state is missing.');
    end
    block = blocks(find(blockMask, 1));
    edgeIdx = find(block.receiverIndices == ...
        row.receiverIdx & block.senderIndices == ...
        row.senderIdx);
    weightIdx = find(abs(block.residualWeightGrid - ...
        row.residualWeight) <= 1e-12);
    if numel(edgeIdx) ~= 1 || numel(weightIdx) ~= 1 || ...
            abs(block. ...
                edgeTaskAdvantageDiagnosticTarget( ...
                    edgeIdx, weightIdx) - ...
                row.trueTaskAdvantage) > 1e-12
        error('Label-set action/target join failed.');
    end
    labelCount = block.labelCounts(edgeIdx);
    action = emptyAction();
    action.pairId = row.pairId;
    action.seed = row.seed;
    action.currentTime = row.currentTime;
    action.receiverIdx = row.receiverIdx;
    action.senderIdx = row.senderIdx;
    action.weightIdx = weightIdx;
    action.edge = reshape(block.edgeFeatures( ...
        edgeIdx, weightIdx, :), 1, []);
    action.receiverNode = ...
        block.nodeFeatures(row.receiverIdx, :);
    action.senderNode = ...
        block.nodeFeatures(row.senderIdx, :);
    action.labelSet = reshape(block.labelFeatures( ...
        edgeIdx, 1:labelCount, :), ...
        labelCount, size(block.labelFeatures, 3));
    action.trueTaskAdvantage = row.trueTaskAdvantage;
    action.canonicalKey = row.receiverIdx + ...
        protocol.expectedNodeCount * ...
            (row.senderIdx - 1) + ...
        protocol.expectedNodeCount^2 * ...
            (weightIdx - 1);
    if labelCount < 1 || ...
            any(~isfinite([ ...
                action.edge, action.receiverNode, ...
                action.senderNode, ...
                action.labelSet(:)', ...
                action.trueTaskAdvantage]))
        error('Label-set action contains invalid features.');
    end
    actions(actionIdx) = action;
end

pairIds = unique([actions.pairId], 'stable');
pairs = repmat(emptyPair(), 1, numel(pairIds));
for pairIdx = 1:numel(pairIds)
    actionIndices = find( ...
        [actions.pairId] == pairIds(pairIdx));
    if numel(actionIndices) ~= 2
        error('Label-set pair is malformed.');
    end
    [~, order] = sort([ ...
        actions(actionIndices).canonicalKey]);
    actionIndices = actionIndices(order);
    pair = emptyPair();
    pair.pairId = pairIds(pairIdx);
    pair.seed = actions(actionIndices(1)).seed;
    pair.currentTime = ...
        actions(actionIndices(1)).currentTime;
    pair.actionA = actionIndices(1);
    pair.actionB = actionIndices(2);
    pair.trueTaskDifference = ...
        actions(pair.actionA).trueTaskAdvantage - ...
        actions(pair.actionB).trueTaskAdvantage;
    if actions(pair.actionA).seed ~= ...
            actions(pair.actionB).seed || ...
            actions(pair.actionA).currentTime ~= ...
            actions(pair.actionB).currentTime || ...
            abs(pair.trueTaskDifference) <= 1e-12
        error('Label-set pair target is invalid.');
    end
    pairs(pairIdx) = pair;
end
if numel(pairs) ~= protocol.expectedPairCount
    error('Label-set pair coverage is incomplete.');
end
end

function model = fitAggregatePairModel( ...
        actions, pairs, fitSeeds, protocol)
fitActionIndices = find(ismember( ...
    [actions.seed], fitSeeds));
X = aggregateFeatures(actions(fitActionIndices));
featureScale = std(X, 0, 1);
featureScale(~isfinite(featureScale) | ...
    featureScale <= eps) = 1;
fitPairs = pairs(ismember([pairs.seed], fitSeeds));
D = zeros(numel(fitPairs), size(X, 2));
y = zeros(numel(fitPairs), 1);
for pairIdx = 1:numel(fitPairs)
    pair = fitPairs(pairIdx);
    left = aggregateFeatures(actions(pair.actionA));
    right = aggregateFeatures(actions(pair.actionB));
    D(pairIdx, :) = (left - right) ./ featureScale;
    y(pairIdx) = pair.trueTaskDifference;
end
targetScale = std(y);
if ~isfinite(targetScale) || targetScale <= eps
    targetScale = 1;
end
target = y / targetScale;
lambda = protocol.aggregateRidgeLambda;
if size(D, 2) <= size(D, 1)
    coefficient = (D' * D + ...
        lambda * eye(size(D, 2))) \ (D' * target);
else
    coefficient = D' * ((D * D' + ...
        lambda * eye(size(D, 1))) \ target);
end
if any(~isfinite(coefficient))
    error('Aggregate task ridge produced non-finite coefficients.');
end
model = struct( ...
    'featureScale', featureScale, ...
    'targetScale', targetScale, ...
    'coefficient', coefficient, ...
    'fitSeeds', fitSeeds);
end

function prediction = predictAggregatePairs(model, actions, pairs)
prediction = zeros(1, numel(pairs));
for pairIdx = 1:numel(pairs)
    left = aggregateFeatures( ...
        actions(pairs(pairIdx).actionA));
    right = aggregateFeatures( ...
        actions(pairs(pairIdx).actionB));
    prediction(pairIdx) = model.targetScale * ...
        (((left - right) ./ model.featureScale) * ...
            model.coefficient);
end
end

function X = aggregateFeatures(actions)
edge = vertcat(actions.edge);
receiver = vertcat(actions.receiverNode);
sender = vertcat(actions.senderNode);
X = [edge, receiver, sender, receiver - sender];
end

function model = fitLabelSetPairModel( ...
        actions, pairs, fitSeeds, protocol, initializationSeed)
fitActionIndices = find(ismember( ...
    [actions.seed], fitSeeds));
fitActions = actions(fitActionIndices);
actionMap = zeros(1, numel(actions));
actionMap(fitActionIndices) = 1:numel(fitActionIndices);
fitPairs = pairs(ismember([pairs.seed], fitSeeds));
pairA = actionMap([fitPairs.actionA]);
pairB = actionMap([fitPairs.actionB]);
if any(pairA == 0) || any(pairB == 0)
    error('DeepSets fit pair/action map is invalid.');
end

edgeX = vertcat(fitActions.edge);
receiverX = vertcat(fitActions.receiverNode);
senderX = vertcat(fitActions.senderNode);
allLabelX = vertcat(fitActions.labelSet);
[edgeMean, edgeScale] = fitScaler(edgeX);
[nodeMean, nodeScale] = fitScaler([receiverX; senderX]);
[labelMean, labelScale] = fitScaler(allLabelX);
edgeZ = applyScaler(edgeX, edgeMean, edgeScale);
receiverZ = applyScaler(receiverX, nodeMean, nodeScale);
senderZ = applyScaler(senderX, nodeMean, nodeScale);
labelZ = cell(1, numel(fitActions));
for actionIdx = 1:numel(fitActions)
    labelZ{actionIdx} = applyScaler( ...
        fitActions(actionIdx).labelSet, ...
        labelMean, labelScale);
end
target = reshape([fitPairs.trueTaskDifference], [], 1);
targetScale = std(target);
if ~isfinite(targetScale) || targetScale <= eps
    targetScale = 1;
end
target = target / targetScale;

labelWidth = protocol.labelHiddenWidth;
nodeWidth = protocol.nodeHiddenWidth;
edgeWidth = protocol.edgeHiddenWidth;
relationalWidth = size(edgeZ, 2) + ...
    2 * labelWidth + 1 + 4 * nodeWidth;
rng(initializationSeed);
parameters = { ...
    randn(size(allLabelX, 2), labelWidth) / ...
        sqrt(size(allLabelX, 2)), ...
    zeros(1, labelWidth), ...
    randn(size(receiverX, 2), nodeWidth) / ...
        sqrt(size(receiverX, 2)), ...
    zeros(1, nodeWidth), ...
    randn(relationalWidth, edgeWidth) / ...
        sqrt(relationalWidth), ...
    zeros(1, edgeWidth), ...
    randn(edgeWidth, 1) / sqrt(edgeWidth), ...
    0};
[firstMoment, secondMoment] = initializeAdam(parameters);
lossHistory = nan(protocol.representationEpochCount, 2);
for epoch = 1:protocol.representationEpochCount
    [utility, cache] = forwardLabelSet( ...
        parameters, edgeZ, receiverZ, senderZ, labelZ);
    difference = utility(pairA) - utility(pairB);
    [dataLoss, dDifference] = huberLossGradient( ...
        difference - target, ...
        protocol.representationHuberDelta);
    dDifference = dDifference / numel(target);
    dUtility = zeros(size(utility));
    for pairIdx = 1:numel(pairA)
        dUtility(pairA(pairIdx)) = ...
            dUtility(pairA(pairIdx)) + ...
                dDifference(pairIdx);
        dUtility(pairB(pairIdx)) = ...
            dUtility(pairB(pairIdx)) - ...
                dDifference(pairIdx);
    end
    [gradients, regularization] = backwardLabelSet( ...
        parameters, cache, edgeZ, receiverZ, ...
        senderZ, labelZ, dUtility, ...
        protocol.representationWeightDecay);
    [parameters, firstMoment, secondMoment] = adamStep( ...
        parameters, gradients, firstMoment, secondMoment, ...
        epoch, protocol.representationLearningRate);
    lossHistory(epoch, :) = ...
        [dataLoss + regularization, regularization];
end
if any(~isfinite(lossHistory(:))) || ...
        any(cellfun(@(value) ...
            any(~isfinite(value(:))), parameters))
    error('DeepSets pair model training became non-finite.');
end
model = struct();
model.kind = protocol.representationPreflightModel;
model.parameters = parameters;
model.edgeMean = edgeMean;
model.edgeScale = edgeScale;
model.nodeMean = nodeMean;
model.nodeScale = nodeScale;
model.labelMean = labelMean;
model.labelScale = labelScale;
model.targetScale = targetScale;
model.fitSeeds = fitSeeds;
model.lossHistory = lossHistory;
model.featuresUseTruth = false;
model.targetUsesTruth = true;
model.numericLabelIdentifiersUsedAsFeatures = false;
end

function prediction = predictLabelSetPairs(model, actions, pairs)
actionIndices = unique([ ...
    [pairs.actionA], [pairs.actionB]], 'stable');
actionMap = zeros(1, numel(actions));
actionMap(actionIndices) = 1:numel(actionIndices);
selected = actions(actionIndices);
edgeZ = applyScaler(vertcat(selected.edge), ...
    model.edgeMean, model.edgeScale);
receiverZ = applyScaler(vertcat(selected.receiverNode), ...
    model.nodeMean, model.nodeScale);
senderZ = applyScaler(vertcat(selected.senderNode), ...
    model.nodeMean, model.nodeScale);
labelZ = cell(1, numel(selected));
for actionIdx = 1:numel(selected)
    labelZ{actionIdx} = applyScaler( ...
        selected(actionIdx).labelSet, ...
        model.labelMean, model.labelScale);
end
utility = forwardLabelSet( ...
    model.parameters, edgeZ, receiverZ, senderZ, labelZ);
prediction = zeros(1, numel(pairs));
for pairIdx = 1:numel(pairs)
    prediction(pairIdx) = model.targetScale * ( ...
        utility(actionMap(pairs(pairIdx).actionA)) - ...
        utility(actionMap(pairs(pairIdx).actionB)));
end
end

function [utility, cache] = forwardLabelSet( ...
        parameters, edgeZ, receiverZ, senderZ, labelZ)
actionCount = size(edgeZ, 1);
labelWidth = size(parameters{1}, 2);
meanPool = zeros(actionCount, labelWidth);
scaledSumPool = zeros(actionCount, labelWidth);
logCount = zeros(actionCount, 1);
labelHidden = cell(1, actionCount);
for actionIdx = 1:actionCount
    hidden = tanh(bsxfun(@plus, ...
        labelZ{actionIdx} * parameters{1}, ...
        parameters{2}));
    labelHidden{actionIdx} = hidden;
    count = size(hidden, 1);
    meanPool(actionIdx, :) = mean(hidden, 1);
    scaledSumPool(actionIdx, :) = ...
        sum(hidden, 1) / sqrt(count);
    logCount(actionIdx) = log1p(count);
end
receiverHidden = tanh(bsxfun(@plus, ...
    receiverZ * parameters{3}, parameters{4}));
senderHidden = tanh(bsxfun(@plus, ...
    senderZ * parameters{3}, parameters{4}));
relational = [ ...
    edgeZ, meanPool, scaledSumPool, logCount, ...
    receiverHidden, senderHidden, ...
    receiverHidden - senderHidden, ...
    receiverHidden .* senderHidden];
edgeHidden = tanh(bsxfun(@plus, ...
    relational * parameters{5}, parameters{6}));
utility = edgeHidden * parameters{7} + parameters{8};
if nargout > 1
    cache = struct( ...
        'labelHidden', {labelHidden}, ...
        'receiverHidden', receiverHidden, ...
        'senderHidden', senderHidden, ...
        'relational', relational, ...
        'edgeHidden', edgeHidden);
end
end

function [gradients, regularization] = backwardLabelSet( ...
        parameters, cache, edgeZ, receiverZ, senderZ, ...
        labelZ, dUtility, weightDecay)
gradients = cellfun(@(value) zeros(size(value)), ...
    parameters, 'UniformOutput', false);
gradients{7} = cache.edgeHidden' * dUtility;
gradients{8} = sum(dUtility);
dEdgeHidden = dUtility * parameters{7}';
dEdgeActivation = dEdgeHidden .* ...
    (1 - cache.edgeHidden.^2);
gradients{5} = cache.relational' * dEdgeActivation;
gradients{6} = sum(dEdgeActivation, 1);
dRelational = dEdgeActivation * parameters{5}';

edgeWidth = size(edgeZ, 2);
labelWidth = size(parameters{1}, 2);
nodeWidth = size(parameters{3}, 2);
cursor = edgeWidth;
dMeanPool = dRelational(:, cursor + (1:labelWidth));
cursor = cursor + labelWidth;
dScaledSumPool = ...
    dRelational(:, cursor + (1:labelWidth));
cursor = cursor + labelWidth + 1;
dReceiverDirect = ...
    dRelational(:, cursor + (1:nodeWidth));
cursor = cursor + nodeWidth;
dSenderDirect = ...
    dRelational(:, cursor + (1:nodeWidth));
cursor = cursor + nodeWidth;
dDifference = ...
    dRelational(:, cursor + (1:nodeWidth));
cursor = cursor + nodeWidth;
dProduct = ...
    dRelational(:, cursor + (1:nodeWidth));

dReceiverHidden = dReceiverDirect + ...
    dDifference + ...
    dProduct .* cache.senderHidden;
dSenderHidden = dSenderDirect - ...
    dDifference + ...
    dProduct .* cache.receiverHidden;
dReceiverActivation = dReceiverHidden .* ...
    (1 - cache.receiverHidden.^2);
dSenderActivation = dSenderHidden .* ...
    (1 - cache.senderHidden.^2);
gradients{3} = ...
    receiverZ' * dReceiverActivation + ...
    senderZ' * dSenderActivation;
gradients{4} = sum( ...
    dReceiverActivation + dSenderActivation, 1);

for actionIdx = 1:numel(labelZ)
    count = size(labelZ{actionIdx}, 1);
    dHidden = repmat( ...
        dMeanPool(actionIdx, :) / count + ...
        dScaledSumPool(actionIdx, :) / sqrt(count), ...
        count, 1);
    dActivation = dHidden .* ...
        (1 - cache.labelHidden{actionIdx}.^2);
    gradients{1} = gradients{1} + ...
        labelZ{actionIdx}' * dActivation;
    gradients{2} = gradients{2} + ...
        sum(dActivation, 1);
end
regularizedParameters = [1, 3, 5, 7];
regularization = 0;
for parameterIdx = regularizedParameters
    regularization = regularization + ...
        0.5 * weightDecay * ...
            sum(parameters{parameterIdx}(:).^2);
    gradients{parameterIdx} = ...
        gradients{parameterIdx} + ...
            weightDecay * parameters{parameterIdx};
end
end

function metrics = computeMetrics(pairs, prediction)
target = reshape([pairs.trueTaskDifference], 1, []);
prediction = reshape(prediction, 1, []);
metrics = struct();
metrics.pairCount = numel(pairs);
metrics.preferenceAccuracy = mean( ...
    sign(prediction) == sign(target));
metrics.differenceSpearman = ...
    computeSpearman(prediction, target);
metrics.meanAbsoluteDifferenceError = ...
    mean(abs(prediction - target));
end

function [loss, gradient] = huberLossGradient(residual, delta)
absolute = abs(residual);
quadratic = absolute <= delta;
values = delta * absolute - 0.5 * delta^2;
values(quadratic) = 0.5 * residual(quadratic).^2;
gradient = delta * sign(residual);
gradient(quadratic) = residual(quadratic);
loss = mean(values);
end

