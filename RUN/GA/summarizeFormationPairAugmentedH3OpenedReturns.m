function [reportPath, summary] = ...
    summarizeFormationPairAugmentedH3OpenedReturns(options)
% SUMMARIZEFORMATIONPAIRAUGMENTEDH3OPENEDRETURNS v11 plus v12 headroom.
%
% This opened-development summary retains the frozen v11 thresholds.  It
% merges the completed singleton bank with all payload-compliant conservative
% pair actions only after exact reference and runtime provenance checks.

if nargin < 1 || isempty(options)
    options = struct();
end
presetName = getField(options, ...
    'presetName', 'm24-formation-fov');
seedTimes = getField(options, 'seedTimes', [ ...
    83, 71; 97, 71; 89, 72; 101, 72; 103, 73]);
localRoot = getField(options, 'localRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_mode_h3_v11', 'opened_return_screen', presetName));
pairRoot = getField(options, 'pairRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_pair_h3_v12', 'opened_return_screen', presetName));
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(pairRoot, 'summary'));
minimumPositiveStateCount = round(getField( ...
    options, 'minimumPositiveStateCount', 3));
minimumStrongStateCount = round(getField( ...
    options, 'minimumStrongStateCount', 2));
strongGainThresholdPercent = getField( ...
    options, 'strongGainThresholdPercent', 5);
minimumMeanTailSafeGainPercent = getField( ...
    options, 'minimumMeanTailSafeGainPercent', 2);
formationGainTolerancePercent = getField( ...
    options, 'formationGainTolerancePercent', 0);
writeReportEnabled = logical(getField( ...
    options, 'writeReport', true));
if ~ischar(presetName) || size(seedTimes, 2) ~= 2 || ...
        isempty(seedTimes) || any(~isfinite(seedTimes(:))) || ...
        any(seedTimes(:) ~= round(seedTimes(:))) || ...
        minimumPositiveStateCount < 1 || ...
        minimumStrongStateCount < 1 || ...
        strongGainThresholdPercent <= 0 || ...
        minimumMeanTailSafeGainPercent <= 0 || ...
        formationGainTolerancePercent < 0
    error('Formation-pair augmented summary options are invalid.');
end

rows = repmat(emptyRow(), 1, size(seedTimes, 1));
localCommits = cell(1, size(seedTimes, 1));
pairCommits = localCommits;
interactionResiduals = zeros(0, 1);
for caseIdx = 1:size(seedTimes, 1)
    seed = seedTimes(caseIdx, 1);
    currentTime = seedTimes(caseIdx, 2);
    localPath = screenPath( ...
        localRoot, 'FORMATION_MODE_H3', ...
        presetName, seed, currentTime);
    pairPath = screenPath( ...
        pairRoot, 'FORMATION_PAIR_H3', ...
        presetName, seed, currentTime);
    localScreen = loadScreen(localPath);
    pairScreen = loadScreen(pairPath);
    validateScreen(localScreen, ...
        'formation-local-h3-opened-return-screen-v1', ...
        presetName, seed, currentTime);
    validateScreen(pairScreen, ...
        ['formation-conservative-pair-h3-opened-', ...
         'return-screen-v1'], presetName, seed, currentTime);
    if ~strcmp(pairScreen.bank.contractVersion, ...
            'formation-conservative-pair-intervention-bank-v1') || ...
            abs(pairScreen.bank.pairTrustWeight - 0.30) > 1e-12
        error('Formation-pair supplemental bank contract failed.');
    end
    assertReferenceOutcomesEqual(localScreen, pairScreen);
    localCommits{caseIdx} = localScreen.generationGitCommit;
    pairCommits{caseIdx} = pairScreen.generationGitCommit;

    localRecords = normalizeFormationIndices( ...
        localScreen.records);
    pairNonreference = [pairScreen.records.actionIndex] ~= ...
        pairScreen.bank.referenceActionIndex;
    pairRecords = normalizeFormationIndices( ...
        pairScreen.records(pairNonreference));
    pairRecords = orderfields( ...
        pairRecords, fieldnames(localRecords));
    records = [localRecords, pairRecords];
    meanGain = [records.meanGainPercent];
    minimumFormationGain = ...
        [records.minimumFormationGainPercent];
    tailSafe = minimumFormationGain >= ...
        -formationGainTolerancePercent - 1e-12;
    [bestMeanGain, bestMeanIdx] = max(meanGain);
    tailSafeIndices = find(tailSafe);
    [bestTailSafeGain, localBestIdx] = ...
        max(meanGain(tailSafeIndices));
    bestTailSafeIdx = tailSafeIndices(localBestIdx);

    caseResiduals = computeInteractionResiduals( ...
        localRecords, pairRecords, ...
        pairScreen.bank.pairTrustWeight);
    interactionResiduals = ...
        [interactionResiduals; caseResiduals(:)]; %#ok<AGROW>
    row = emptyRow();
    row.seed = seed;
    row.currentTime = currentTime;
    row.localPath = localPath;
    row.pairPath = pairPath;
    row.localActionCount = numel(localRecords);
    row.pairActionCount = numel(pairRecords);
    row.bestMeanAction = records(bestMeanIdx).actionName;
    row.bestMeanGainPercent = bestMeanGain;
    row.bestMeanMinimumFormationGainPercent = ...
        records(bestMeanIdx).minimumFormationGainPercent;
    row.bestTailSafeAction = ...
        records(bestTailSafeIdx).actionName;
    row.bestTailSafeGainPercent = bestTailSafeGain;
    row.bestTailSafeWorstGainPercent = ...
        records(bestTailSafeIdx).worstGainPercent;
    row.bestTailSafeConsensusGainPercent = ...
        records(bestTailSafeIdx).consensusGainPercent;
    row.bestTailSafeByteSavingPercent = ...
        records(bestTailSafeIdx).attemptedByteSavingPercent;
    row.meanAbsInteractionResidualPercent = ...
        mean(abs(caseResiduals));
    row.maximumAbsInteractionResidualPercent = ...
        max(abs(caseResiduals));
    row.allRuntimeGatesPassed = all(arrayfun( ...
        @recordRuntimePassed, records));
    rows(caseIdx) = row;
end
if numel(unique(localCommits)) ~= 1 || ...
        numel(unique(pairCommits)) ~= 1
    error('Formation H=3 source commits vary within a bank.');
end

bestTailSafeGains = [rows.bestTailSafeGainPercent];
positiveStateCount = nnz(bestTailSafeGains > 1e-12);
strongStateCount = nnz(bestTailSafeGains >= ...
    strongGainThresholdPercent - 1e-12);
meanTailSafeGainPercent = mean(bestTailSafeGains);
allRuntimeGatesPassed = all([rows.allRuntimeGatesPassed]);
headroomGatePassed = allRuntimeGatesPassed && ...
    positiveStateCount >= minimumPositiveStateCount && ...
    strongStateCount >= minimumStrongStateCount && ...
    meanTailSafeGainPercent >= ...
        minimumMeanTailSafeGainPercent - 1e-12;

summary = struct();
summary.contractVersion = ...
    'formation-pair-augmented-h3-opened-headroom-summary-v1';
summary.generatedAt = datestr(now, 31);
summary.presetName = presetName;
summary.seedTimes = seedTimes;
summary.localGenerationCommit = localCommits{1};
summary.pairGenerationCommit = pairCommits{1};
summary.rows = rows;
summary.formationGainTolerancePercent = ...
    formationGainTolerancePercent;
summary.minimumPositiveStateCount = minimumPositiveStateCount;
summary.minimumStrongStateCount = minimumStrongStateCount;
summary.strongGainThresholdPercent = strongGainThresholdPercent;
summary.minimumMeanTailSafeGainPercent = ...
    minimumMeanTailSafeGainPercent;
summary.positiveStateCount = positiveStateCount;
summary.strongStateCount = strongStateCount;
summary.meanTailSafeGainPercent = meanTailSafeGainPercent;
summary.allRuntimeGatesPassed = allRuntimeGatesPassed;
summary.interactionResidualsPercent = interactionResiduals;
summary.meanAbsInteractionResidualPercent = ...
    mean(abs(interactionResiduals));
summary.maximumAbsInteractionResidualPercent = ...
    max(abs(interactionResiduals));
summary.headroomGatePassed = headroomGatePassed;
summary.modelTrainingAuthorized = headroomGatePassed;
summary.openedDevelopmentEvidenceOnly = true;
summary.validationClaimAllowed = false;
summary.evidenceBoundary = [ ...
    'This opened M24 summary decides only whether a fixed singleton ', ...
    'plus conservative-pair teacher bank has enough oracle H=3 ', ...
    'headroom for value-model development. It does not evaluate a ', ...
    'learned selector or support M24 or X36 validation claims.'];

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'FORMATION_PAIR_AUGMENTED_H3_OPENED_HEADROOM_SUMMARY_V1.md');
    matPath = strrep(reportPath, '.md', '.mat');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    save('-mat7-binary', matPath, 'summary');
    writeReport(reportPath, summary);
    fprintf('Formation-pair augmented H=3 summary: %s\n', ...
        reportPath);
end
end

function path = screenPath(root, prefix, presetName, seed, currentTime)
stem = sprintf('%s_%s_SEED%d_T%d.mat', prefix, ...
    upper(strrep(presetName, '-', '_')), seed, currentTime);
nestedPath = fullfile(root, sprintf('seed%d', seed), stem);
directPath = fullfile(root, stem);
if exist(nestedPath, 'file') == 2
    path = nestedPath;
elseif exist(directPath, 'file') == 2
    path = directPath;
else
    path = nestedPath;
end
end

function screen = loadScreen(path)
loaded = load(path, 'screen');
if ~isfield(loaded, 'screen')
    error('Formation H=3 screen is missing: %s', path);
end
screen = loaded.screen;
end

function validateScreen(screen, contract, presetName, seed, currentTime)
required = { ...
    'contractVersion', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'presetName', 'seed', ...
    'currentTime', 'horizonSteps', 'bank', 'actionIndices', ...
    'outcomes', 'records', 'featuresUseTruth', ...
    'featuresUseFutureMeasurements', 'featuresUseFutureOutcome', ...
    'targetsUseTruth', 'targetsUseFutureMeasurements', ...
    'runtimePolicyUsesTruth', 'openedDevelopmentEvidenceOnly', ...
    'validationClaimAllowed'};
if ~isstruct(screen) || ~all(isfield(screen, required)) || ...
        ~strcmp(screen.contractVersion, contract) || ...
        ~strcmp(screen.presetName, presetName) || ...
        screen.seed ~= seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= 3 || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        screen.featuresUseTruth || ...
        screen.featuresUseFutureMeasurements || ...
        screen.featuresUseFutureOutcome || ...
        ~screen.targetsUseTruth || ...
        ~screen.targetsUseFutureMeasurements || ...
        screen.runtimePolicyUsesTruth || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed || ...
        ~isequal(screen.actionIndices, reshape(find( ...
            screen.bank.actionWithinReferencePayload), 1, [])) || ...
        numel(screen.records) ~= numel(screen.actionIndices) || ...
        numel(screen.outcomes) ~= numel(screen.actionIndices)
    error('Formation H=3 screen contract failed.');
end
for recordIdx = 1:numel(screen.records)
    record = screen.records(recordIdx);
    outcome = screen.outcomes(recordIdx);
    if record.actionIndex ~= screen.actionIndices(recordIdx) || ...
            ~strcmp(record.actionName, ...
                screen.bank.actionNames{record.actionIndex}) || ...
            ~record.selectedB3Passed || ...
            ~outcome.firstActionExact || ...
            outcome.truthUseCount ~= 0 || ...
            outcome.repairCount ~= 0 || ...
            outcome.payloadEmergencyCount ~= 0 || ...
            outcome.infeasibleCount ~= 0 || ...
            ~all(outcome.selectedSensorB3Pass) || ...
            ~all(outcome.selectedFormationB3Pass)
        error('Formation H=3 action runtime audit failed.');
    end
end
end

function assertReferenceOutcomesEqual(localScreen, pairScreen)
localIdx = find([localScreen.records.actionIndex] == ...
    localScreen.bank.referenceActionIndex, 1);
pairIdx = find([pairScreen.records.actionIndex] == ...
    pairScreen.bank.referenceActionIndex, 1);
if isempty(localIdx) || isempty(pairIdx)
    error('Singleton and pair H=3 reference outcomes differ.');
end
localOutcome = localScreen.outcomes(localIdx);
pairOutcome = pairScreen.outcomes(pairIdx);
deterministicFields = { ...
    'meanEospa', 'worstSensorEospa', 'sensorMeanEospa', ...
    'formationMeanEospa', 'eospaBySensorTime', ...
    'meanCardinalityError', 'consensusOspa', ...
    'consensusPosition', 'consensusCardinality', ...
    'posteriorConsensus', 'attemptedBytesByTime', ...
    'deliveredBytesByTime', 'attemptedBytes', 'deliveredBytes', ...
    'selectedAdjacency', 'deliveredAdjacency', ...
    'selectedSensorB3Pass', 'selectedFormationB3Pass', ...
    'deliveredSensorB3Pass', 'deliveredFormationB3Pass', ...
    'truthUseCount', 'repairCount', 'payloadEmergencyCount', ...
    'infeasibleCount', 'firstActionExact'};
for fieldIdx = 1:numel(deterministicFields)
    name = deterministicFields{fieldIdx};
    if ~isfield(localOutcome, name) || ...
            ~isfield(pairOutcome, name) || ...
            ~isequaln(localOutcome.(name), pairOutcome.(name))
        error('Singleton and pair H=3 reference outcomes differ.');
    end
end
end

function records = normalizeFormationIndices(records)
for recordIdx = 1:numel(records)
    if ~isfield(records, 'formationIndices') || ...
            isempty(records(recordIdx).formationIndices)
        if records(recordIdx).formationIndex > 0
            records(recordIdx).formationIndices = ...
                records(recordIdx).formationIndex;
        else
            records(recordIdx).formationIndices = zeros(1, 0);
        end
    end
end
end

function residuals = computeInteractionResiduals( ...
        localRecords, pairRecords, trustWeight)
residuals = zeros(1, numel(pairRecords));
for pairIdx = 1:numel(pairRecords)
    pairRecord = pairRecords(pairIdx);
    formations = reshape(pairRecord.formationIndices, 1, []);
    formations = formations(formations > 0);
    if numel(formations) ~= 2 || ...
            abs(pairRecord.trustWeight - trustWeight) > 1e-12
        error('Pair interaction record is invalid.');
    end
    singletonGains = zeros(1, 2);
    for formationIdx = 1:2
        match = find([localRecords.formationIndex] == ...
            formations(formationIdx) & ...
            abs([localRecords.trustWeight] - trustWeight) <= 1e-12);
        if numel(match) ~= 1
            error('Matching singleton interaction arm is missing.');
        end
        singletonGains(formationIdx) = ...
            localRecords(match).meanGainPercent;
    end
    residuals(pairIdx) = pairRecord.meanGainPercent - ...
        sum(singletonGains);
end
end

function passed = recordRuntimePassed(record)
passed = record.selectedB3Passed;
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, 'currentTime', NaN, ...
    'localPath', '', 'pairPath', '', ...
    'localActionCount', NaN, 'pairActionCount', NaN, ...
    'bestMeanAction', '', 'bestMeanGainPercent', NaN, ...
    'bestMeanMinimumFormationGainPercent', NaN, ...
    'bestTailSafeAction', '', ...
    'bestTailSafeGainPercent', NaN, ...
    'bestTailSafeWorstGainPercent', NaN, ...
    'bestTailSafeConsensusGainPercent', NaN, ...
    'bestTailSafeByteSavingPercent', NaN, ...
    'meanAbsInteractionResidualPercent', NaN, ...
    'maximumAbsInteractionResidualPercent', NaN, ...
    'allRuntimeGatesPassed', false);
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation-pair summary report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation-pair augmented H=3 opened headroom summary\n\n');
fprintf(fid, '- Contract: `%s`\n', summary.contractVersion);
fprintf(fid, '- Preset: `%s`\n', summary.presetName);
fprintf(fid, '- Singleton generation commit: `%s`\n', ...
    summary.localGenerationCommit);
fprintf(fid, '- Pair generation commit: `%s`\n', ...
    summary.pairGenerationCommit);
fprintf(fid, '- Tail tolerance: `%.3f%%`\n', ...
    summary.formationGainTolerancePercent);
fprintf(fid, '- Positive states: `%d / %d` (gate `%d`)\n', ...
    summary.positiveStateCount, numel(summary.rows), ...
    summary.minimumPositiveStateCount);
fprintf(fid, ...
    '- Strong states (gain >= %.1f%%): `%d / %d` (gate `%d`)\n', ...
    summary.strongGainThresholdPercent, summary.strongStateCount, ...
    numel(summary.rows), summary.minimumStrongStateCount);
fprintf(fid, '- Mean best tail-safe gain: `%+.3f%%` (gate `>= %.3f%%`)\n', ...
    summary.meanTailSafeGainPercent, ...
    summary.minimumMeanTailSafeGainPercent);
fprintf(fid, [ ...
    '- Mean / maximum absolute pair interaction residual: ', ...
    '`%.3f%% / %.3f%%`\n'], ...
    summary.meanAbsInteractionResidualPercent, ...
    summary.maximumAbsInteractionResidualPercent);
fprintf(fid, '- Runtime gates / headroom gate: `%d / %d`\n\n', ...
    summary.allRuntimeGatesPassed, summary.headroomGatePassed);
fprintf(fid, [ ...
    '| Seed-time | Best mean action | Mean gain | Min form. | ', ...
    'Best tail-safe action | Tail-safe gain | Worst gain | ', ...
    'Consensus gain | Byte saving | Pair interaction mean/max | Runtime |\n']);
fprintf(fid, [ ...
    '|:--|:--|--:|--:|:--|--:|--:|--:|--:|--:|:--:|\n']);
for row = summary.rows
    fprintf(fid, [ ...
        '| `%d-%d` | `%s` | %+.3f%% | %+.3f%% | `%s` | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%.3f%% / %.3f%% | %d |\n'], ...
        row.seed, row.currentTime, row.bestMeanAction, ...
        row.bestMeanGainPercent, ...
        row.bestMeanMinimumFormationGainPercent, ...
        row.bestTailSafeAction, row.bestTailSafeGainPercent, ...
        row.bestTailSafeWorstGainPercent, ...
        row.bestTailSafeConsensusGainPercent, ...
        row.bestTailSafeByteSavingPercent, ...
        row.meanAbsInteractionResidualPercent, ...
        row.maximumAbsInteractionResidualPercent, ...
        row.allRuntimeGatesPassed);
end
fprintf(fid, '\n## Decision\n\n');
if summary.headroomGatePassed
    fprintf(fid, [ ...
        'The augmented opened teacher bank passes the frozen headroom ', ...
        'gate and may proceed to value-model development.\n']);
else
    fprintf(fid, [ ...
        'The augmented opened teacher bank fails the frozen headroom ', ...
        'gate. Replace the candidate topology family before fitting a ', ...
        'value model.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
