            error('RollingSafeReferenceSwitch:InvalidTrace', ...
                'Candidate hashes disagree with its raw attestation.');
        end
    elseif ~isempty(trace.candidateAdjacencySha256{stepIdx}) || ...
            ~isempty(trace.candidateFusionWeightSha256{stepIdx}) || ...
            ~isnan(trace.candidateSelectionSeconds(stepIdx))
        error('RollingSafeReferenceSwitch:InvalidTrace', ...
            'Unavailable candidate has execution evidence.');
    end
    if referenceAvailable
        requireAlternativeHashes( ...
            trace.referenceAdjacencySha256{stepIdx}, ...
            trace.referenceFusionWeightSha256{stepIdx}, ...
            trace.referenceSelectionSeconds(stepIdx), 'reference');
        if ~strcmp(trace.referenceAdjacencySha256{stepIdx}, ...
                computeTextSha256(serializeReferenceSwitchNumeric( ...
                    referenceRawAudit{stepIdx}.adjacency))) || ...
                ~strcmp(trace.referenceFusionWeightSha256{stepIdx}, ...
                    computeTextSha256(serializeReferenceSwitchNumeric( ...
                        referenceRawAudit{stepIdx}.fusionWeightMatrix))) || ...
                ~strcmp(trace.physicalAdjacencySha256{stepIdx}, ...
                    computeTextSha256(serializeReferenceSwitchNumeric( ...
                        referenceRawAudit{stepIdx}.physicalAdjacency)))
            error('RollingSafeReferenceSwitch:InvalidTrace', ...
                'Reference hashes disagree with its raw attestation.');
        end
    elseif ~isempty(trace.referenceAdjacencySha256{stepIdx}) || ...
            ~isempty(trace.referenceFusionWeightSha256{stepIdx}) || ...
            ~isnan(trace.referenceSelectionSeconds(stepIdx))
        error('RollingSafeReferenceSwitch:InvalidTrace', ...
            'Unavailable reference has execution evidence.');
    end
    if ~isValidSha256(trace.selectedAdjacencySha256{stepIdx}) || ...
            ~isValidSha256( ...
                trace.selectedFusionWeightSha256{stepIdx}) || ...
            ~isValidSha256(trace.contextSha256{stepIdx}) || ...
            ~isValidSha256(trace.historySha256{stepIdx}) || ...
            ~isValidSha256( ...
                trace.physicalAdjacencySha256{stepIdx})
        error('RollingSafeReferenceSwitch:InvalidTrace', ...
            'Reference-switch provenance hashes are invalid.');
    end
    if trace.selectedCandidate(stepIdx)
        expectedAdjacencySha256 = ...
            trace.candidateAdjacencySha256{stepIdx};
        expectedFusionWeightSha256 = ...
            trace.candidateFusionWeightSha256{stepIdx};
    else
        expectedAdjacencySha256 = ...
            trace.referenceAdjacencySha256{stepIdx};
        expectedFusionWeightSha256 = ...
            trace.referenceFusionWeightSha256{stepIdx};
    end
    executedAdjacency = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(stepIdx)));
    executedWeights = diagnostics. ...
        topologyPolicyFusionWeightMatrix{returnTimes(stepIdx)};
    executedAdjacencySha256 = computeTextSha256( ...
        serializeReferenceSwitchNumeric(executedAdjacency));
    executedFusionWeightSha256 = computeTextSha256( ...
        serializeReferenceSwitchNumeric(executedWeights));
    if ~strcmp(trace.selectedAdjacencySha256{stepIdx}, ...
            expectedAdjacencySha256) || ...
            ~strcmp(trace.selectedFusionWeightSha256{stepIdx}, ...
                expectedFusionWeightSha256) || ...
            ~strcmp(executedAdjacencySha256, ...
                expectedAdjacencySha256) || ...
            ~strcmp(executedFusionWeightSha256, ...
                expectedFusionWeightSha256)
        error('RollingSafeReferenceSwitch:ExecutionMismatch', ...
            'Executed graph or fusion weights differ from the chosen arm.');
    end
    if candidateAvailable && referenceAvailable
        graphEqual = requireFiniteBinaryDiagnostic( ...
            trace.alternativeGraphEqual(stepIdx), 1, ...
            'referenceSwitchAlternativeGraphEqual');
        hammingDistance = ...
            trace.alternativeGraphHammingDistance(stepIdx);
        hashesEqual = strcmp( ...
            trace.candidateAdjacencySha256{stepIdx}, ...
            trace.referenceAdjacencySha256{stepIdx});
        if ~isscalar(hammingDistance) || ...
                ~isfinite(hammingDistance) || ...
                hammingDistance < 0 || ...
                hammingDistance ~= round(hammingDistance) || ...
                logical(graphEqual) ~= hashesEqual || ...
                (hashesEqual && hammingDistance ~= 0) || ...
                (~hashesEqual && hammingDistance == 0)
            error('RollingSafeReferenceSwitch:InvalidTrace', ...
                'Alternative graph-distance diagnostics are inconsistent.');
        end
    else
        graphEqual = requireFiniteBinaryDiagnostic( ...
            trace.alternativeGraphEqual(stepIdx), 1, ...
            'referenceSwitchAlternativeGraphEqual');
        if logical(graphEqual) || ...
                ~isnan(trace.alternativeGraphHammingDistance(stepIdx))
            error('RollingSafeReferenceSwitch:InvalidTrace', ...
                'Unavailable alternatives have a graph distance.');
        end
    end
end
trace.auditPassed = true;
end

function [available, nominalFree, requestedActionRealized, rawAudit] = ...
        auditStoredReferenceSwitchAlternative( ...
            attestation, failureIdentifier, actionCode, ...
            expectedEvaluated, protocol)
if ~expectedEvaluated
    if ~isstruct(attestation) || ~isempty(attestation) || ...
            ~isempty(failureIdentifier)
        error('RollingSafeReferenceSwitch:InvalidTrace', ...
            'An unevaluated arm has raw evidence or a failure identifier.');
    end
    available = NaN;
    nominalFree = NaN;
    requestedActionRealized = NaN;
    rawAudit = struct([]);
    return;
end
if ~ischar(failureIdentifier) || ~isstruct(attestation)
    error('RollingSafeReferenceSwitch:InvalidTrace', ...
        'An evaluated arm has an invalid evidence container.');
end
if isempty(attestation)
    if isempty(failureIdentifier) || ...
            ~isExpectedRollingSafeReferenceSwitchAlternativeUnavailable( ...
                failureIdentifier, actionCode, protocol)
        error('RollingSafeReferenceSwitch:InvalidTrace', ...
            'An unavailable arm lacks a registered failure identifier.');
    end
    available = false;
    nominalFree = false;
    requestedActionRealized = false;
    rawAudit = struct([]);
    return;
end
if ~isempty(failureIdentifier)
    error('RollingSafeReferenceSwitch:InvalidTrace', ...
        'An attested arm also reports an unavailable failure.');
end
rawAudit = auditRollingSafeReferenceSwitchAttestation( ...
    attestation, actionCode);
if ~rawAudit.available
    error('RollingSafeReferenceSwitch:InvalidTrace', ...
        'An attested arm failed the independently derived availability gate.');
end
available = rawAudit.available;
nominalFree = rawAudit.strictNominalFree;
requestedActionRealized = rawAudit.requestedActionRealized;
end

function requireAlternativeHashes( ...
        adjacencySha256, fusionWeightSha256, selectionSeconds, name)
