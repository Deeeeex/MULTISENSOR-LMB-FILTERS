        ~isValidSha256(fusionWeightSha256) || ...
        ~isscalar(selectionSeconds) || ~isfinite(selectionSeconds) || ...
        selectionSeconds < 0
    error('RollingSafeReferenceSwitch:InvalidTrace', ...
        '%s alternative evidence is invalid.', name);
end
end

function text = serializeReferenceSwitchNumeric(value)
if ~(isnumeric(value) || islogical(value)) || ~isreal(value)
    error('RollingSafeReferenceSwitch:InvalidTrace', ...
        'Reference-switch hash values must be real numeric arrays.');
end
sizeText = sprintf('%d,', size(value));
if islogical(value)
    valueText = sprintf('%d,', value(:));
else
    valueText = sprintf('%.17g,', value(:));
end
text = sprintf('%s:%s:%s', class(value), sizeText, valueText);
end

