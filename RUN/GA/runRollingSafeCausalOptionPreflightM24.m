function assertStrictNominalFreeFirstDetails( ...
        adjacency, details, actionCode, context, protocol)
requiredFields = { ...
    'actionSequenceCode', 'nominalProjectionFeasible', ...
    'repairProjectionAttempted', 'repairTriggered', ...
    'payloadEmergencyUsed', 'payloadLimitPassed', ...
    'topologyInfeasible', 'oneStepTopologyReserveChecked', ...
    'oneStepTopologyReservePassed', ...
    'sensorWindowStrongConnected', ...
    'formationWindowStrongConnected', ...
    'successorSensorStrongConnected', ...
    'successorFormationStrongConnected', ...
    'messageCount', 'fusionWeightMatrix', 'sourceWeight', ...
    'selectedSourcesByReceiver'};
if ~all(isfield(details, requiredFields))
    error('RollingSafeReferenceSwitch:InvalidAlternativeDiagnostics', ...
        'The frozen first action lacks strict safety diagnostics.');
end
binaryFields = { ...
    'nominalProjectionFeasible', 'repairProjectionAttempted', ...
    'repairTriggered', 'payloadEmergencyUsed', ...
    'payloadLimitPassed', 'topologyInfeasible', ...
    'oneStepTopologyReserveChecked', 'oneStepTopologyReservePassed', ...
    'sensorWindowStrongConnected', ...
    'formationWindowStrongConnected', ...
    'successorSensorStrongConnected', ...
    'successorFormationStrongConnected'};
for fieldIdx = 1:numel(binaryFields)
    fieldName = binaryFields{fieldIdx};
    requireFiniteBinaryDiagnostic(details.(fieldName), 1, fieldName);
end
nodeCount = numel(context.localPosteriorBySensor);
if ~(isnumeric(adjacency) || islogical(adjacency)) || ...
        ~isreal(adjacency) || ...
        ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        any(~isfinite(adjacency(:))) || ...
        any(adjacency(:) ~= 0 & adjacency(:) ~= 1)
    error('RollingSafeReferenceSwitch:InvalidAlternative', ...
        'The frozen first action has a non-binary adjacency.');
end
adjacency = logical(adjacency);
selectedSources = reshape(details.selectedSourcesByReceiver, [], 1);
sourceWeight = details.sourceWeight;
registeredSourceWeight = ...
    protocol.rollingSafeCausalOptionSourceWeight;
if numel(selectedSources) ~= nodeCount || ...
        any(~isfinite(selectedSources)) || ...
        any(selectedSources ~= round(selectedSources)) || ...
        any(selectedSources < 1) || any(selectedSources > nodeCount) || ...
        ~isscalar(sourceWeight) || ~isfinite(sourceWeight) || ...
        sourceWeight ~= registeredSourceWeight
    error('RollingSafeReferenceSwitch:InvalidFusionWeights', ...
        'The frozen first action changed the routing-weight contract.');
end
expectedAdjacency = false(nodeCount);
expectedAdjacency(sub2ind([nodeCount, nodeCount], ...
    (1:nodeCount)', selectedSources)) = true;
expectedWeights = eye(nodeCount);
expectedWeights(1:(nodeCount + 1):end) = 1 - registeredSourceWeight;
expectedWeights(sub2ind([nodeCount, nodeCount], ...
    (1:nodeCount)', selectedSources)) = registeredSourceWeight;
weights = details.fusionWeightMatrix;
exactRouteAndWeights = isequal(adjacency, expectedAdjacency) && ...
    isnumeric(weights) && isreal(weights) && ...
    isequal(size(weights), [nodeCount, nodeCount]) && ...
    all(isfinite(weights(:))) && ...
    isequal(weights, expectedWeights);
assertRollingSafeReferenceSwitchActionRealized(details, actionCode);
strictFree = details.actionSequenceCode == actionCode && ...
    logical(details.nominalProjectionFeasible) && ...
    ~logical(details.repairProjectionAttempted) && ...
    ~logical(details.repairTriggered) && ...
    ~logical(details.payloadEmergencyUsed) && ...
    logical(details.payloadLimitPassed) && ...
    ~logical(details.topologyInfeasible) && ...
    logical(details.oneStepTopologyReserveChecked) && ...
    logical(details.oneStepTopologyReservePassed) && ...
    logical(details.sensorWindowStrongConnected) && ...
    logical(details.formationWindowStrongConnected) && ...
    logical(details.successorSensorStrongConnected) && ...
    logical(details.successorFormationStrongConnected) && ...
    details.messageCount == nodeCount && ...
    nodeCount == protocol.rollingSafeCausalOptionMessageBudget && ...
    exactRouteAndWeights;
if ~strictFree
    error('RollingSafeReferenceSwitch:NoNominalFreeAction', ...
        'The frozen paired first action is not strict nominal-free.');
end
end

