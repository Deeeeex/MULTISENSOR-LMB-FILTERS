            rollingSafeReferencePreferredSwitchContractVersion;
        details.referenceSwitchApplied = false;
        details.referenceSwitchSelectedCandidate = true;
        details.referenceSwitchCandidateActionCode = sequence(1);
        details.referenceSwitchReferenceActionCode = protocol. ...
            rollingSafeReferencePreferredSwitchReferenceActionCode;
        details.referenceSwitchSelectedActionCode = sequence(1);
        details.referenceSwitchCandidateAvailable = true;
        details.referenceSwitchReferenceAvailable = NaN;
        details.referenceSwitchCandidateNominalFree = true;
        details.referenceSwitchReferenceNominalFree = NaN;
        details.referenceSwitchCandidateRequestedActionRealized = true;
        details.referenceSwitchReferenceRequestedActionRealized = NaN;
        details.referenceSwitchCandidateAttestation = ...
            buildRollingSafeReferenceSwitchAttestation( ...
                adjacency, details, sequence(1), ...
                logical(context.physicalAdjacency));
        details.referenceSwitchReferenceAttestation = struct([]);
        details.referenceSwitchCandidateFailureIdentifier = '';
        details.referenceSwitchReferenceFailureIdentifier = '';
