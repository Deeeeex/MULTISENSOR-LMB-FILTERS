        ~isfield(trace, 'contractVersion') || ...
        ~strcmp(trace.contractVersion, ...
            'dynamic-topology-restart-trace-sha256-v1') || ...
        ~isfield(trace, 'times') || ...
        ~isequal(reshape(trace.times, 1, []), ...
            currentTime + (0:(protocol.returnValueGateHorizon - 1))) || ...
        ~isfield(trace, 'overallSha256') || ...
        ~isValidSha256(trace.overallSha256)
