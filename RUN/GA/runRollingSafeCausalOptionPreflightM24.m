function names = resolveOptionNames( ...
        sequences, registeredSequences, registeredNames)
names = cell(1, size(sequences, 1));
for rowIdx = 1:size(sequences, 1)
    registryIdx = find(all( ...
        registeredSequences == sequences(rowIdx, :), 2));
    if numel(registryIdx) == 1
        names{rowIdx} = registeredNames{registryIdx};
    else
        names{rowIdx} = sprintf('exploratory-%s', ...
            strrep(mat2str(sequences(rowIdx, :)), ' ', '-'));
    end
end
end

function validateOptionSequences(sequences, protocol)
if ~isnumeric(sequences) || ...
        size(sequences, 2) ~= ...
            protocol.returnValueGateHorizon || ...
        isempty(sequences) || ...
        any(~isfinite(sequences(:))) || ...
        any(sequences(:) ~= round(sequences(:))) || ...
        any(~ismember(sequences(:), ...
            protocol.rollingSafeSparseTruthFreeActionCodes)) || ...
        size(unique(sequences, 'rows'), 1) ~= ...
            size(sequences, 1) || ...
        nnz(all(sequences == ...
            protocol.rollingSafeCausalOptionReferenceSequence, 2)) ~= 1
    error(['optionSequences must contain distinct truth-free H=3 ', ...
        'rows and include the reference exactly once.']);
end
end

