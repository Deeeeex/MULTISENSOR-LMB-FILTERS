            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:)))
        error('Frozen causal option first action is physically invalid.');
    end
    assertTruthFreeRollingSafePolicyDetails(firstDetails);
    details = firstDetails;
    details.mode = ...
        'frozen-rolling-safe-causal-option-first-step';
    details.runtimeFrozenGraphReplay = true;
    if strcmp(auditMode, 'reference-preferred-switch')
        assertStrictNominalFreeFirstDetails( ...
