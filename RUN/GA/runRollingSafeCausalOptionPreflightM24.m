function [reportPath, preflight] = ...
    runRollingSafeCausalOptionPreflightM24( ...
        seed, currentTime, options)
% RUNROLLINGSAFECAUSALOPTIONPREFLIGHTM24 Causal H=3 sparse option bank.
%
% Every option is a three-step sequence of registered truth-free rolling
% safe action codes. The first graph and fusion weights are frozen from the
% saved predecision context. Steps two and three recompute their registered
% controllers from the actual live posterior and selected-topology history.
% All completed options use exactly one directed message per receiver.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.rollingSafeCausalOptionAuthorized || ...
        protocol.returnValueGateHorizon ~= 3 || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Rolling-safe causal option preflight is not authorized.');
end
seed = validateTrainingSeed(seed, protocol);
currentTime = validateSourceTime(currentTime, protocol);
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles) || ...
         gitState.researchWorktreeDirty)
    error(['Official causal option preflight requires clean tracked ', ...
        'and MATLAB/Octave source state.']);
end

auditMode = getField(options, 'auditMode', 'causal-persistent');
if isstring(auditMode) && isscalar(auditMode)
    auditMode = char(auditMode);
end
switch auditMode
    case 'causal-persistent'
        registeredSequences = ...
            protocol.rollingSafeCausalOptionSequences;
        registeredNames = ...
            protocol.rollingSafeCausalOptionNames;
        auditStem = 'persistent';
    case 'one-step-control'
        registeredSequences = ...
            protocol.rollingSafeCausalOneStepControlSequences;
        registeredNames = ...
            protocol.rollingSafeCausalOneStepControlNames;
        auditStem = 'one_step';
    otherwise
        error('Unknown rolling-safe causal option auditMode.');
end
optionSequences = getField(options, 'optionSequences', ...
    registeredSequences);
validateOptionSequences(optionSequences, protocol);
exploratoryOptionSubsetUsed = ~isequal( ...
    optionSequences, registeredSequences);
if ~allowDirtySource && exploratoryOptionSubsetUsed
    error(['Official causal option preflight requires the exact ', ...
        'registered option bank.']);
end
optionNames = resolveOptionNames( ...
    optionSequences, registeredSequences, registeredNames);

sourcePath = getField(options, 'sourcePath', ...
    resolveSentinelSourcePath( ...
        seed, currentTime, protocol));
sourceSha256 = computeFileSha256(sourcePath);
loaded = load(sourcePath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Causal option source shard lacks dataset.');
end
source = loaded.dataset;
[expectedBehavior, expectedBehaviorAction] = ...
    resolveSentinelBehavior(seed, currentTime, protocol);
validateSource(source, seed, currentTime, ...
    expectedBehaviorAction, protocol, allowDirtySource);
blockIdx = find([source.blocks.currentTime] == currentTime);
if numel(blockIdx) ~= 1
    error('Causal option source state is not unique.');
end
sourceBlock = source.blocks(blockIdx);
validateSourceBlock(sourceBlock, seed, currentTime, ...
    expectedBehaviorAction, protocol);
sourceHistoryLabel = behaviorHistorySourceLabel( ...
    expectedBehaviorAction);

returnTimes = currentTime + ...
    (0:(protocol.returnValueGateHorizon - 1));
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCount
    error('Causal option M24 scenario is invalid.');
end
inputs = cropInputs(inputs, returnTimes(end));
initialContext = buildPredecisionContext( ...
    sourceBlock, inputs, protocol, sourceHistoryLabel);
sequenceOptions = buildSequenceOptions(protocol);
[restartObservedTrace, restartReplaySeconds] = ...
    replayBehaviorRestart( ...
        inputs, sourceBlock, returnTimes, source, ...
        protocol, sourceHistoryLabel);
assertDynamicTopologyRestartTraceEqual( ...
    sourceBlock.restartReferenceTrace, restartObservedTrace);

optionCount = size(optionSequences, 1);
outcomes = repmat(emptyOutcome(), 1, optionCount);
optionStatus = repmat({'pending'}, 1, optionCount);
optionFailureIdentifier = repmat({''}, 1, optionCount);
optionFailureMessage = repmat({''}, 1, optionCount);
optionExpectedUnavailable = false(1, optionCount);
firstActionGraphSha256 = repmat({''}, 1, optionCount);
firstActionFusionWeightSha256 = repmat({''}, 1, optionCount);
for optionIdx = 1:optionCount
    sequence = optionSequences(optionIdx, :);
    fprintf('Sparse causal H=3 seed %d t=%d option %s...\n', ...
        seed, currentTime, optionNames{optionIdx});
    try
        [firstAdjacency, firstDetails] = ...
            selectRollingSafeActionSequencePolicy( ...
                initialContext, sequence, currentTime, ...
                sequenceOptions);
        assertTruthFreeRollingSafePolicyDetails(firstDetails);
        if ~isfield(firstDetails, 'fusionWeightMatrix') || ...
                ~isnumeric(firstDetails.fusionWeightMatrix) || ...
                ~isequal(size(firstDetails.fusionWeightMatrix), ...
                    [protocol.expectedNodeCount, ...
                     protocol.expectedNodeCount]) || ...
                any(~isfinite( ...
                    firstDetails.fusionWeightMatrix(:)))
            error('Causal option first action lacks fusion weights.');
        end
        firstActionGraphSha256{optionIdx} = ...
            computeTextSha256(sprintf('%d,', ...
                firstAdjacency(:)));
        firstActionFusionWeightSha256{optionIdx} = ...
            computeTextSha256(sprintf('%.17g,', ...
                firstDetails.fusionWeightMatrix(:)));
        outcomes(optionIdx) = runOneSequence( ...
            inputs, sourceBlock, returnTimes, sequence, ...
            firstAdjacency, firstDetails, protocol, ...
            sequenceOptions, sourceHistoryLabel);
        optionStatus{optionIdx} = 'completed';
        fprintf(['  E-OSPA %.6f, worst %.6f, consensus %.6f, ', ...
            'attempted %.0f B, delivered %.0f B, %.2f s\n'], ...
            outcomes(optionIdx).meanEospa, ...
            outcomes(optionIdx).worstSensorEospa, ...
            outcomes(optionIdx).consensusOspa, ...
            outcomes(optionIdx).attemptedBytes, ...
            outcomes(optionIdx).deliveredBytes, ...
            outcomes(optionIdx).elapsedSeconds);
    catch errorInfo
        if isequal(sequence, ...
                protocol.rollingSafeCausalOptionReferenceSequence)
            rethrow(errorInfo);
        end
        if ~isExpectedRollingSafeOptionUnavailableError( ...
                errorInfo, protocol. ...
                    rollingSafeCausalOptionExpectedUnavailableErrorIdentifiers)
            rethrow(errorInfo);
        end
        optionStatus{optionIdx} = 'unavailable';
        optionExpectedUnavailable(optionIdx) = true;
        optionFailureIdentifier{optionIdx} = ...
            errorInfo.identifier;
        optionFailureMessage{optionIdx} = ...
            errorInfo.message;
        fprintf('  unavailable [%s]: %s\n', ...
            errorInfo.identifier, errorInfo.message);
    end
end

referenceIdx = find(all(optionSequences == ...
    protocol.rollingSafeCausalOptionReferenceSequence, 2));
if numel(referenceIdx) ~= 1
    error('Causal option reference is not unique.');
end
completed = strcmp(optionStatus, 'completed');
if ~completed(referenceIdx)
    error('Causal option reference did not complete.');
end
referenceOutcome = outcomes(referenceIdx);
referenceLaterPolicyReportedRepairCount = ...
    referenceOutcome.laterPolicyReportedRepairCount;
risk = [outcomes.meanEospa];
meanGainVsReferencePercent = nan(1, optionCount);
worstGainVsReferencePercent = nan(1, optionCount);
consensusGainVsReferencePercent = nan(1, optionCount);
attemptedByteDeviationPercent = nan(1, optionCount);
hardRuntimeGatePassed = false(1, optionCount);
completedIndices = find(completed);
for optionIdx = completedIndices
    outcome = outcomes(optionIdx);
    meanGainVsReferencePercent(optionIdx) = relativeGain( ...
        referenceOutcome.meanEospa, outcome.meanEospa);
    worstGainVsReferencePercent(optionIdx) = relativeGain( ...
        referenceOutcome.worstSensorEospa, ...
        outcome.worstSensorEospa);
    consensusGainVsReferencePercent(optionIdx) = relativeGain( ...
        referenceOutcome.consensusOspa, ...
        outcome.consensusOspa);
    attemptedByteDeviationPercent(optionIdx) = 100 * abs( ...
        outcome.attemptedBytes - referenceOutcome.attemptedBytes) / ...
        max(referenceOutcome.attemptedBytes, eps);
    hardRuntimeGatePassed(optionIdx) = ...
        outcome.truthUseCount == 0 && ...
        outcome.payloadEmergencyCount == 0 && ...
        outcome.infeasibleCount == 0 && ...
        outcome.initialPolicyReportedRepairCount == 0 && ...
        outcome.laterPolicyReportedRepairCount <= ...
            referenceLaterPolicyReportedRepairCount + ...
            protocol. ...
                rollingSafeCausalOptionMaximumLaterPolicyReportedRepairExcess && ...
        all(outcome.oneStepReserveChecked) && ...
        all(outcome.oneStepReservePassed) && ...
        all(outcome.messageCounts == ...
            protocol.rollingSafeCausalOptionMessageBudget) && ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass) && ...
        outcome.firstActionExact && ...
        outcome.firstFusionWeightsExact;
end
admissibleForSelection = completed & hardRuntimeGatePassed & ...
    attemptedByteDeviationPercent <= ...
        protocol.rollingSafeCausalOptionMaximumByteDeviationPercent;
if protocol.rollingSafeCausalOptionRequireWorstAndConsensusNonregression
    admissibleForSelection = admissibleForSelection & ...
        worstGainVsReferencePercent >= -1e-9 & ...
        consensusGainVsReferencePercent >= -1e-9;
end
admissibleIndices = find(admissibleForSelection);
if isempty(admissibleIndices)
    error('Causal option bank has no admissible reference.');
end
[bestAdmissibleMeanEospa, localBestIdx] = ...
    min(risk(admissibleIndices));
bestAdmissibleIdx = ...
    admissibleIndices(localBestIdx);
completedTrajectoryHashes = ...
    {outcomes(completed).trajectoryGraphSha256};

preflight = struct();
preflight.protocolId = protocol.id;
preflight.contractVersion = ...
    protocol.rollingSafeCausalOptionContractVersion;
preflight.auditMode = auditMode;
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
preflight.seed = seed;
preflight.currentTime = currentTime;
preflight.returnTimes = returnTimes;
preflight.optionSequences = optionSequences;
preflight.optionNames = optionNames;
preflight.optionSequenceSetSha256 = ...
    computeTextSha256(sprintf('%02d,', optionSequences(:)));
preflight.optionStatus = optionStatus;
preflight.optionFailureIdentifier = ...
    optionFailureIdentifier;
preflight.optionFailureMessage = optionFailureMessage;
preflight.optionExpectedUnavailable = ...
    optionExpectedUnavailable;
preflight.firstActionGraphSha256 = ...
    firstActionGraphSha256;
preflight.firstActionFusionWeightSha256 = ...
    firstActionFusionWeightSha256;
preflight.referenceOptionIndex = referenceIdx;
preflight.referenceMeanEospa = ...
    referenceOutcome.meanEospa;
preflight.referenceWorstSensorEospa = ...
    referenceOutcome.worstSensorEospa;
preflight.referenceConsensusOspa = ...
    referenceOutcome.consensusOspa;
preflight.referenceLaterPolicyReportedRepairCount = ...
    referenceLaterPolicyReportedRepairCount;
preflight.outcomes = outcomes;
preflight.meanGainVsReferencePercent = ...
    meanGainVsReferencePercent;
preflight.worstGainVsReferencePercent = ...
    worstGainVsReferencePercent;
preflight.consensusGainVsReferencePercent = ...
    consensusGainVsReferencePercent;
preflight.attemptedByteDeviationPercent = ...
    attemptedByteDeviationPercent;
preflight.hardRuntimeGatePassed = ...
    hardRuntimeGatePassed;
preflight.admissibleForSelection = ...
    admissibleForSelection;
preflight.bestAdmissibleOptionIndex = ...
    bestAdmissibleIdx;
preflight.bestAdmissibleOptionName = ...
    optionNames{bestAdmissibleIdx};
preflight.bestAdmissibleSequence = ...
    optionSequences(bestAdmissibleIdx, :);
preflight.bestAdmissibleMeanEospa = ...
    bestAdmissibleMeanEospa;
preflight.bestAdmissibleGainVsReferencePercent = ...
    meanGainVsReferencePercent(bestAdmissibleIdx);
preflight.bestAdmissibleWorstGainVsReferencePercent = ...
    worstGainVsReferencePercent(bestAdmissibleIdx);
preflight.bestAdmissibleConsensusGainVsReferencePercent = ...
    consensusGainVsReferencePercent(bestAdmissibleIdx);
preflight.bestAdmissibleAttemptedByteDeviationPercent = ...
    attemptedByteDeviationPercent(bestAdmissibleIdx);
preflight.completedOptionCount = nnz(completed);
preflight.unavailableOptionCount = nnz(~completed);
preflight.uniqueCompletedTrajectoryCount = ...
    numel(unique(completedTrajectoryHashes));
preflight.sourcePath = sourcePath;
preflight.sourceSha256 = sourceSha256;
preflight.sourceContractVersion = source.contractVersion;
preflight.sourceBehavior = expectedBehavior;
preflight.sourceBehaviorAction = source.behaviorAction;
preflight.sourceGenerationGitCommit = ...
    source.generationGitCommit;
preflight.sourceCacheSha256 = source.sourceCacheSha256;
preflight.sourceBehaviorModelSha256 = ...
    source.behaviorModelSha256;
preflight.sourceHistoryLabel = sourceHistoryLabel;
preflight.restartReferenceOverallSha256 = ...
    sourceBlock.restartReferenceTrace.overallSha256;
preflight.restartObservedOverallSha256 = ...
    restartObservedTrace.overallSha256;
preflight.restartEquivalencePassed = true;
preflight.restartReplaySeconds = restartReplaySeconds;
preflight.commonRandomNumbers = true;
preflight.firstActionGraphAndWeightsFrozen = true;
preflight.subsequentActionsCausal = true;
preflight.livePosteriorAndHistoryRecomputed = true;
preflight.centralizedCoordinatorAssumed = ...
    protocol.rollingSafeCausalOptionCentralizedCoordinatorAssumed;
preflight.controlMetadataBytesAccounted = ...
    protocol.rollingSafeCausalOptionControlMetadataBytesAccounted;
preflight.exploratoryOptionSubsetUsed = ...
    exploratoryOptionSubsetUsed;
preflight.runtimePolicyUsesTruth = ...
    any([outcomes(completed).truthUseCount] > 0);
preflight.trainingOnlyDiagnostic = true;
preflight.developmentOpened = false;
preflight.heldoutM24Opened = false;
preflight.x36Opened = false;
preflight.evidenceBoundary = [ ...
    'This opened-training preflight tests a registered H=3 option ', ...
    'family inside ', ...
    'a truth-free 24-message rolling-safe family. Its frozen ', ...
    'predecision state was generated by a registered 40-message CCW ', ...
    'or learned behavior trajectory. It is not a sparse-versus-dense ', ...
    'same-budget comparison, a learned selector, or evidence on the ', ...
    'new formation-FoV M24, X36, or X48 scenes. Later-step safety ', ...
    'projection is part of the registered safety policy and is not ', ...
    'claimed ', ...
    'as recursive feasibility because future geometry is unknown. ', ...
    'The repair diagnostic is only the repair flag reported by the ', ...
    'policy; it is not a universal proposal-to-selected rewrite flag. ', ...
    'Central coordinator metadata bytes are not yet charged.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        protocol.rollingSafeCausalOptionEvidenceNamespace));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = sprintf( ...
    'rolling_safe_causal_h3_%s_m24_seed%d_t%d', ...
    auditStem, seed, currentTime);
artifactSuffix = getField(options, 'artifactSuffix', ...
    protocol.rollingSafeCausalOptionArtifactSuffix);
if ~ischar(artifactSuffix) || ...
        isempty(regexp(artifactSuffix, ...
            '^[A-Za-z0-9_-]+$', 'once'))
    error('artifactSuffix is invalid.');
end
stem = sprintf('%s_%s', stem, artifactSuffix);
matPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [stem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(stem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Causal option output already exists. Set overwrite=true ', ...
        'only for intentional regeneration.']);
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save(matPath, 'preflight', '-v7');
writeReport(reportPath, preflight);
fprintf('Causal option preflight: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function outcome = runOneSequence( ...
        inputs, sourceBlock, returnTimes, sequence, ...
        firstAdjacency, firstDetails, protocol, ...
        sequenceOptions, sourceHistoryLabel)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = ...
    inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    protocol.rollingSafeCausalOptionMessageBudget;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'rolling-safe-causal-h3-option';
config.topologyPolicyFcn = ...
    @(context) selectCausalOptionAction( ...
        context, returnTimes(1), sequence, ...
        firstAdjacency, firstDetails, ...
        sequenceOptions);
config.filterInitialLocalPosteriorBySensor = ...
    sourceBlock.initialLocalPosteriorBySensor;
config.filterInitialLocalPosteriorTime = ...
    sourceBlock.currentTime;
config.filterInitialLocalUpdateHistoryTimes = ...
    sourceBlock.localUpdateHistoryTimes;
config.filterInitialLocalInnovationHistory = ...
    sourceBlock.localInnovationHistory;
config.filterInitialLocalAssociationConfidenceHistory = ...
    sourceBlock.localAssociationConfidenceHistory;
config.filterInitialLocalNisNormHistory = ...
    sourceBlock.localNisNormHistory;
config.filterInitialLocalNisDeviationHistory = ...
    sourceBlock.localNisDeviationHistory;
config.filterInitialPreviousAdjacencyHistory = ...
    sourceBlock.previousAdjacencyHistory;
config.filterInitialPreviousAdjacencyTimes = ...
    sourceBlock.previousAdjacencyHistoryTimes;
config.filterInitialPreviousAdjacencyHistorySource = ...
    sourceHistoryLabel;

rng(sourceBlock.seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);
if ~diagnostics.usedInitialLocalUpdateHistory || ...
        ~isequal( ...
            diagnostics.initialLocalUpdateHistoryTimes, ...
            sourceBlock.localUpdateHistoryTimes) || ...
        ~isequal( ...
            diagnostics.initialLocalInnovationHistory, ...
            sourceBlock.localInnovationHistory) || ...
        ~isequal( ...
            diagnostics. ...
                initialLocalAssociationConfidenceHistory, ...
            sourceBlock. ...
                localAssociationConfidenceHistory) || ...
        ~isequaln( ...
            diagnostics.initialLocalNisNormHistory, ...
            sourceBlock.localNisNormHistory) || ...
        ~isequaln( ...
            diagnostics.initialLocalNisDeviationHistory, ...
            sourceBlock.localNisDeviationHistory)
    error('Causal option did not restore all local update histories.');
end

firstExecuted = ...
    convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge( ...
            :, :, returnTimes(1)));
if ~isequal(firstExecuted, logical(firstAdjacency))
    error('Causal option did not execute its first graph exactly.');
end
firstExecutedWeights = ...
    diagnostics.topologyPolicyFusionWeightMatrix{ ...
        returnTimes(1)};
firstFusionWeightsExact = ...
    isequal(size(firstExecutedWeights), ...
        size(firstDetails.fusionWeightMatrix)) && ...
    max(abs(firstExecutedWeights(:) - ...
        firstDetails.fusionWeightMatrix(:))) <= 1e-12;
if ~firstFusionWeightsExact
    error('Causal option did not execute its first weights exactly.');
end
for stepIdx = 1:numel(returnTimes)
    weights = diagnostics.topologyPolicyFusionWeightMatrix{ ...
        returnTimes(stepIdx)};
    if ~isnumeric(weights) || ...
            ~isequal(size(weights), ...
                [inputs.config.numberOfSensors, ...
                 inputs.config.numberOfSensors]) || ...
            any(~isfinite(weights(:)))
        error('RollingSafeCausalOption:InvalidFusionWeights', ...
            'Causal option has invalid fusion weights at step %d.', ...
            stepIdx);
    end
end
messageCounts = ...
    diagnostics.topologyDirectedMessageCount(returnTimes);
messageCounts = requireFiniteNumericVector( ...
    messageCounts, numel(returnTimes), ...
    'topologyDirectedMessageCount');
if any(messageCounts ~= ...
        protocol.rollingSafeCausalOptionMessageBudget)
    error('RollingSafeCausalOption:MessageBudget', ...
        'Causal option changed the exact message budget.');
end
truthUse = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyPolicyTruthUsed(returnTimes), ...
    numel(returnTimes), 'topologyPolicyTruthUsed');
repair = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyPolicyRepairTriggered(returnTimes), ...
    numel(returnTimes), 'topologyPolicyRepairTriggered');
oneStepReserveChecked = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyPolicyOneStepTopologyReserveChecked( ...
        returnTimes), numel(returnTimes), ...
    'topologyPolicyOneStepTopologyReserveChecked');
oneStepReservePassed = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyPolicyOneStepTopologyReservePassed( ...
        returnTimes), numel(returnTimes), ...
    'topologyPolicyOneStepTopologyReservePassed');
emergency = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(returnTimes), ...
    numel(returnTimes), 'topologyPolicyPayloadEmergencyUsed');
feasible = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyFeasible(returnTimes), ...
    numel(returnTimes), 'topologyFeasible');
reportedInfeasible = requireFiniteBinaryDiagnostic( ...
    diagnostics.topologyPolicyTopologyInfeasible(returnTimes), ...
    numel(returnTimes), 'topologyPolicyTopologyInfeasible');
infeasible = ~feasible | reportedInfeasible;
if any(truthUse)
    error('RollingSafeCausalOption:TruthUse', ...
        'Causal option used privileged truth at runtime.');
end
if protocol.rollingSafeCausalOptionRequireNoInitialPolicyReportedRepair && ...
        repair(1)
    error('RollingSafeCausalOption:InitialPolicyReportedRepair', ...
        ['Causal option reported a repair on its identity step. This ', ...
         'diagnostic is policy-specific.']);
end
if any(emergency)
    error('RollingSafeCausalOption:PayloadEmergency', ...
        'Causal option used a payload emergency path.');
end
if any(infeasible)
    error('RollingSafeCausalOption:Infeasible', ...
        'Causal option reported an infeasible selected topology.');
end
if protocol.rollingSafeCausalOptionRequireOneStepReserveAudit && ...
        (~all(oneStepReserveChecked) || ...
         ~all(oneStepReservePassed))
    error('RollingSafeCausalOption:ReserveAudit', ...
        'Causal option failed the one-step reserve audit.');
end

nodeCount = inputs.config.numberOfSensors;
selected = false(nodeCount, nodeCount, numel(returnTimes));
delivered = selected;
trajectoryText = '';
for stepIdx = 1:numel(returnTimes)
    selected(:, :, stepIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(stepIdx)));
    delivered(:, :, stepIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered( ...
                :, :, returnTimes(stepIdx)));
    trajectoryText = [trajectoryText, ...
        sprintf('%d,', selected(:, :, stepIdx))]; %#ok<AGROW>
end
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousAdjacencyHistory, ...
        selected, inputs.config.sensorGroupIds);
[deliveredSensorB3, deliveredFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousDeliveredAdjacencyHistory, ...
        delivered, inputs.config.sensorGroupIds);
if ~all(selectedSensorB3) || ...
        ~all(selectedFormationB3)
    error('RollingSafeCausalOption:SelectedB3', ...
        'Causal option failed its independent selected B3 audit.');
end

sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(returnTimes));
for sensorIdx = 1:sensorCount
    sensorEospa = computeSimulationOspa( ...
        inputs.model, inputs.groundTruthRfs, ...
        estimates{sensorIdx});
    eospa(sensorIdx, :) = ...
        sensorEospa(returnTimes);
end
requireFiniteNonnegative(eospa, 'E-OSPA');
sensorMeans = mean(eospa, 2);
[~, ~, ospaDisagreement] = ...
    computeDistributedConsensusMetrics( ...
        estimates, inputs.model);
outcome = emptyOutcome();
outcome.meanEospa = mean(eospa(:));
outcome.worstSensorEospa = max(sensorMeans);
consensusByStep = requireFiniteNumericVector( ...
    ospaDisagreement(returnTimes), numel(returnTimes), ...
    'consensus OSPA');
requireFiniteNonnegative(consensusByStep, 'consensus OSPA');
outcome.consensusOspa = mean(consensusByStep);
attemptedPayload = diagnostics.attemptedPayloadBytes( ...
    :, :, returnTimes);
deliveredPayload = diagnostics.payloadBytes(:, :, returnTimes);
requireFiniteNonnegative(attemptedPayload, 'attempted payload bytes');
requireFiniteNonnegative(deliveredPayload, 'delivered payload bytes');
outcome.attemptedBytesByStep = reshape(sum(sum( ...
    attemptedPayload, 1), 2), 1, []);
outcome.deliveredBytesByStep = reshape(sum(sum( ...
    deliveredPayload, 1), 2), 1, []);
outcome.attemptedBytes = sum(outcome.attemptedBytesByStep);
outcome.deliveredBytes = sum(outcome.deliveredBytesByStep);
outcome.messageCounts = messageCounts;
outcome.truthUseCount = nnz(truthUse);
outcome.policyReportedRepairCount = nnz(repair);
outcome.policyReportedRepairByStep = repair;
outcome.initialPolicyReportedRepairCount = nnz(repair(1));
outcome.laterPolicyReportedRepairCount = nnz(repair(2:end));
outcome.oneStepReserveChecked = oneStepReserveChecked;
outcome.oneStepReservePassed = oneStepReservePassed;
outcome.payloadEmergencyCount = nnz(emergency);
outcome.infeasibleCount = nnz(infeasible);
