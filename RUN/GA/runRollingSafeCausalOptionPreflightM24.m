function validateSource( ...
        source, seed, currentTime, expectedBehaviorAction, ...
        protocol, allowDirty)
requiredFields = { ...
    'protocolId', 'contractVersion', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty', 'presetName', 'seed', ...
    'sourceTimes', 'horizonSteps', 'behaviorAction', ...
    'behaviorFilterSeed', 'behaviorModelPath', ...
    'behaviorModelSha256', 'sourceCachePath', ...
    'sourceCacheSha256', 'blocks', 'behaviorTruthUseCount', ...
    'behaviorRepairCount', 'behaviorPayloadEmergencyCount', ...
    'behaviorInfeasibleCount', 'behaviorSelectedSensorB3Pass', ...
    'behaviorSelectedFormationB3Pass', ...
    'restartReferenceHashesStored', 'featuresUseTruth', ...
    'featuresUseFutureOutcome', 'targetsStored', ...
    'postdecisionTopologyStored', 'developmentOpened', ...
    'heldoutM24Opened', 'x36Opened'};
if ~all(isfield(source, requiredFields))
    error('Causal option source lacks required provenance fields.');
end
behaviorSensorB3 = requireFiniteBinaryDiagnostic( ...
    source.behaviorSelectedSensorB3Pass, ...
    numel(source.behaviorSelectedSensorB3Pass), ...
    'source behaviorSelectedSensorB3Pass');
behaviorFormationB3 = requireFiniteBinaryDiagnostic( ...
    source.behaviorSelectedFormationB3Pass, ...
    numel(source.behaviorSelectedFormationB3Pass), ...
    'source behaviorSelectedFormationB3Pass');
if ~strcmp(source.protocolId, protocol.id) || ...
        ~strcmp(source.contractVersion, ...
            protocol.macroActionBehaviorSourceContractVersion) || ...
        ~strcmp(source.presetName, protocol.presetName) || ...
        ~strcmp(source.behaviorAction, expectedBehaviorAction) || ...
        source.seed ~= seed || ...
        ~isequal(reshape(source.sourceTimes, 1, []), ...
            reshape(protocol.macroActionBehaviorSourceTimes, 1, [])) || ...
        ~any(source.sourceTimes == currentTime) || ...
        source.horizonSteps ~= protocol.returnValueGateHorizon || ...
        source.behaviorFilterSeed ~= ...
            seed + protocol.filterSeedOffset || ...
        source.behaviorTruthUseCount ~= 0 || ...
        source.behaviorRepairCount ~= 0 || ...
        source.behaviorPayloadEmergencyCount ~= 0 || ...
        source.behaviorInfeasibleCount ~= 0 || ...
        isempty(behaviorSensorB3) || ~all(behaviorSensorB3) || ...
        isempty(behaviorFormationB3) || ~all(behaviorFormationB3) || ...
        source.featuresUseTruth || ...
        source.featuresUseFutureOutcome || ...
        source.targetsStored || ...
        source.postdecisionTopologyStored || ...
        source.developmentOpened || ...
        source.heldoutM24Opened || source.x36Opened
    error('Causal option source violates the contract.');
end
if ~ischar(source.generationGitCommit) || ...
        isempty(regexp(source.generationGitCommit, ...
            '^[0-9a-f]{40}$', 'once')) || ...
        ~isValidSha256(source.sourceCacheSha256) || ...
        ~ischar(source.sourceCachePath) || ...
        isempty(source.sourceCachePath)
    error('Causal option source provenance hashes are invalid.');
end
[commitStatus, ~] = system(sprintf( ...
    'git cat-file -e %s^{commit}', source.generationGitCommit));
if commitStatus ~= 0
    error('Causal option source generation commit is unavailable.');
end
if strcmp(expectedBehaviorAction, ...
        'label-set-message-passing-safe-fixed-e05-a70')
    if ~strcmp(source.behaviorModelPath, ...
            protocol.messagePassingInitializationPath) || ...
            ~strcmp(source.behaviorModelSha256, ...
                protocol.messagePassingInitializationSha256)
        error('Learned behavior source model provenance is invalid.');
    end
elseif ~isempty(source.behaviorModelPath) || ...
        ~isempty(source.behaviorModelSha256)
    error('Fixed behavior source unexpectedly records a model.');
end
if ~isfield(source, 'restartReferenceHashesStored') || ...
        ~source.restartReferenceHashesStored
    error('Causal option source lacks restart-reference hashes.');
end
if ~allowDirty && ...
        (source.generationTrackedWorktreeDirty || ...
         ~isempty(source.generationUntrackedSourceFiles) || ...
         source.generationResearchWorktreeDirty)
    error('Causal option preflight requires a clean source shard.');
end
end

function validateSourceBlock( ...
        block, seed, currentTime, expectedBehaviorAction, protocol)
requiredFields = { ...
    'seed', 'currentTime', 'behaviorAction', ...
    'initialLocalPosteriorBySensor', ...
    'previousAdjacencyHistory', ...
    'previousDeliveredAdjacencyHistory', ...
    'previousAdjacencyHistoryTimes', ...
    'localUpdateHistoryTimes', 'localInnovationHistory', ...
    'localAssociationConfidenceHistory', ...
    'localNisNormHistory', 'localNisDeviationHistory', ...
    'restartReferenceTrace'};
if ~all(isfield(block, requiredFields)) || ...
        block.seed ~= seed || block.currentTime ~= currentTime || ...
        ~strcmp(block.behaviorAction, expectedBehaviorAction) || ...
        numel(block.initialLocalPosteriorBySensor) ~= ...
            protocol.expectedNodeCount || ...
        ~isequal(size(block.previousAdjacencyHistory), ...
            [protocol.expectedNodeCount, ...
             protocol.expectedNodeCount, 2]) || ...
        ~isequal(size(block.previousDeliveredAdjacencyHistory), ...
            [protocol.expectedNodeCount, ...
             protocol.expectedNodeCount, 2]) || ...
        ~isequal(reshape(block.previousAdjacencyHistoryTimes, 1, []), ...
            (currentTime - 2):(currentTime - 1)) || ...
        ~isequal(reshape(block.localUpdateHistoryTimes, 1, []), ...
            (currentTime - 2):currentTime)
    error('Causal option source block violates restart metadata.');
end
historyFields = { ...
    'localInnovationHistory', ...
    'localAssociationConfidenceHistory', ...
    'localNisNormHistory', 'localNisDeviationHistory'};
for fieldIdx = 1:numel(historyFields)
    values = block.(historyFields{fieldIdx});
    if ~isequal(size(values), ...
            [protocol.expectedNodeCount, 3])
        error('Causal option source block has invalid local histories.');
    end
end
trace = block.restartReferenceTrace;
if ~isstruct(trace) || ...
        ~isfield(trace, 'contractVersion') || ...
        ~strcmp(trace.contractVersion, ...
            'dynamic-topology-restart-trace-sha256-v1') || ...
        ~isfield(trace, 'times') || ...
        ~isequal(reshape(trace.times, 1, []), ...
            currentTime + (0:(protocol.returnValueGateHorizon - 1))) || ...
        ~isfield(trace, 'overallSha256') || ...
        ~isValidSha256(trace.overallSha256)
    error('Causal option source block lacks a valid restart trace.');
end
end

