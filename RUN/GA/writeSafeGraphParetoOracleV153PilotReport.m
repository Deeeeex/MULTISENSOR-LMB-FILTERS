function writeSafeGraphParetoOracleV153PilotReport(path, summary)
% WRITESAFEGRAPHPARETOORACLEV153PILOTREPORT Render two-cost pilot summary.

fid = fopen(path, 'w');
if fid < 0
    error('Could not write V153 pilot report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V153 safe graph Pareto oracle pilot\n\n');
fprintf(fid, '- Preset / seed / window: `%s / %d / %d:%d`\n', ...
    summary.presetName, summary.seed, summary.analysisWindow);
fprintf(fid, '- Better static reference: `%s`\n', ...
    summary.referenceArmMode);
fprintf(fid, '- Selected Pareto action: `%s`\n', ...
    summary.selectedArmMode);
fprintf(fid, '- Retained dynamic graphs: `%d / %d`\n', ...
    summary.admissibleDynamicCount, summary.dynamicArmCount);
fprintf(fid, '- Attempted-byte increase ceiling: `%.1f%%`\n\n', ...
    summary.maximumAttemptedByteIncreasePercent);
fprintf(fid, ['| Mean gain | Worst-sensor gain | Minimum-formation gain | ', ...
    'Consensus gain | Attempted-byte saving | 5%% pilot gate |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--:|\n');
fprintf(fid, '| %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n\n', ...
    summary.oracleGainPercent, summary.worstSensorGainPercent, ...
    summary.minimumFormationGainPercent, ...
    summary.consensusGainPercent, ...
    summary.attemptedByteSavingPercent, ...
    summary.pilotMeanGatePassed);

fprintf(fid, '## Dynamic codebook\n\n');
fprintf(fid, ['| Rank | Mean gain | Worst-sensor gain | ', ...
    'Minimum-formation gain | Consensus gain | Byte saving | ', ...
    'Structure pass | V152 strict | V153 retained |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|:--:|:--:|:--:|\n');
for idx = 1:summary.dynamicArmCount
    fprintf(fid, ['| %d | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d | %d | %d |\n'], ...
        idx, summary.dynamicMeanGainPercent(idx), ...
        summary.dynamicWorstSensorGainPercent(idx), ...
        summary.dynamicMinimumFormationGainPercent(idx), ...
        summary.dynamicConsensusGainPercent(idx), ...
        summary.dynamicAttemptedByteSavingPercent(idx), ...
        summary.dynamicStructurePass(idx), ...
        summary.strictV152DynamicAdmissible(idx), ...
        summary.dynamicAdmissible(idx));
end
fprintf(fid, '\n## Boundary\n\n%s\n', summary.claimBoundary);
end
