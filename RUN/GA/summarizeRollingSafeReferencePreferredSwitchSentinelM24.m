function [reportPath, summary] = ...
    summarizeRollingSafeReferencePreferredSwitchSentinelM24(options)
% SUMMARIZEROLLINGSAFEREFERENCEPREFERREDSWITCHSENTINELM24 Paired falsifier.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.rollingSafeReferencePreferredSwitchAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Reference-preferred switching sentinel is not authorized.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error(['Official reference-switch summary requires clean tracked ', ...
        'and MATLAB/Octave source state.']);
end

inputDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', protocol. ...
        rollingSafeReferencePreferredSwitchEvidenceNamespace));
artifactSuffix = getField(options, 'artifactSuffix', protocol. ...
    rollingSafeReferencePreferredSwitchArtifactSuffix);
if ~ischar(artifactSuffix) || isempty(regexp( ...
        artifactSuffix, '^[A-Za-z0-9_-]+$', 'once'))
    error('artifactSuffix is invalid.');
end
controlSummary = recomputeControlSummaryFromRaw( ...
    inputDirectory, artifactSuffix);

states = protocol.rollingSafeCausalOptionSentinelSeedTimes;
rows = repmat(emptyRow(), 1, size(states, 1));
generationCommits = {controlSummary.preflightGenerationGitCommit};
for stateIdx = 1:size(states, 1)
    seed = states(stateIdx, 1);
    currentTime = states(stateIdx, 2);
    behavior = protocol. ...
        rollingSafeCausalOptionSentinelBehaviors{stateIdx};
    behaviorAction = protocol. ...
        rollingSafeCausalOptionSentinelBehaviorActions{stateIdx};
    adaptivePath = artifactPath(inputDirectory, ...
        'reference_switch', seed, currentTime, artifactSuffix);
    persistentPath = artifactPath(inputDirectory, ...
        'persistent', seed, currentTime, artifactSuffix);
    oneStepPath = artifactPath(inputDirectory, ...
        'one_step', seed, currentTime, artifactSuffix);
    adaptive = loadPreflight(adaptivePath);
    persistentPreflight = loadPreflight(persistentPath);
    oneStep = loadPreflight(oneStepPath);
    validateAdaptivePreflight( ...
        adaptive, seed, currentTime, behaviorAction, protocol);
    assertRollingSafeCausalOptionPairedFirstActions( ...
        persistentPreflight, adaptive);
    assertRollingSafeCausalOptionPairedFirstActions( ...
        oneStep, adaptive);
    assertCommonSourceAndReference( ...
        persistentPreflight, oneStep, adaptive, protocol);
    derived = recomputeAdaptiveDerived(adaptive, protocol);
    assertStoredAdaptiveDerivedEqual(adaptive, derived, protocol);

    controlRow = controlSummary.rows(stateIdx);
    if controlRow.seed ~= seed || ...
            controlRow.currentTime ~= currentTime || ...
            ~strcmp(controlRow.behavior, behavior) || ...
            ~strcmp(controlRow.behaviorAction, behaviorAction) || ...
            ~strcmp(controlRow.sourceSha256, adaptive.sourceSha256)
        error('Control-summary state ordering or provenance changed.');
    end
    bestIdx = derived.bestAdmissibleOptionIndex;
    bestOutcome = adaptive.outcomes(bestIdx);
    fixedEnvelopeEospa = min( ...
        controlRow.oneStepBestMeanEospa, ...
        controlRow.persistentBestMeanEospa);
    row = emptyRow();
    row.seed = seed;
    row.currentTime = currentTime;
    row.behavior = behavior;
    row.behaviorAction = behaviorAction;
    row.adaptiveArtifactPath = adaptivePath;
    row.persistentArtifactPath = persistentPath;
    row.oneStepArtifactPath = oneStepPath;
    row.sourceSha256 = adaptive.sourceSha256;
    row.referenceMeanEospa = derived.referenceMeanEospa;
    row.oneStepBestMeanEospa = controlRow.oneStepBestMeanEospa;
    row.persistentBestMeanEospa = ...
        controlRow.persistentBestMeanEospa;
    row.fixedDurationEnvelopeMeanEospa = fixedEnvelopeEospa;
    row.adaptiveBestMeanEospa = derived.bestAdmissibleMeanEospa;
    row.adaptiveBestOptionName = adaptive.optionNames{bestIdx};
    row.adaptiveBestCandidateCode = adaptive.optionSequences(bestIdx, 1);
    row.adaptiveBestSelectedActionCodes = ...
        bestOutcome.referenceSwitchSelectedActionCodeByStep;
    row.adaptiveGainVsReferencePercent = ...
        derived.meanGainVsReferencePercent(bestIdx);
    row.fixedEnvelopeGainVsReferencePercent = relativeGain( ...
        row.referenceMeanEospa, fixedEnvelopeEospa);
    row.adaptiveIncrementalVsFixedEnvelopePercent = ...
        row.adaptiveGainVsReferencePercent - ...
        row.fixedEnvelopeGainVsReferencePercent;
    row.adaptiveWorstGainVsReferencePercent = ...
        derived.worstGainVsReferencePercent(bestIdx);
    row.adaptiveConsensusGainVsReferencePercent = ...
        derived.consensusGainVsReferencePercent(bestIdx);
    row.adaptiveByteDeviationPercent = ...
        derived.attemptedByteDeviationPercent(bestIdx);
    row.adaptiveUnavailableOptionCount = ...
        derived.unavailableOptionCount;
    row.adaptiveAdmissibleOptionCount = ...
        nnz(derived.admissibleForSelection);
    row.selectedCandidateLater = any( ...
        bestOutcome.referenceSwitchSelectedCandidateByStep(2:end));
    row.selectedReferenceLater = any( ...
        ~bestOutcome.referenceSwitchSelectedCandidateByStep(2:end));
    row.improvesReference = ...
        row.adaptiveGainVsReferencePercent > 1e-9;
    row.improvesFixedEnvelope = ...
        row.adaptiveIncrementalVsFixedEnvelopePercent > 1e-9;
    row.isExcludedOutlier = isequal([seed, currentTime], protocol. ...
        rollingSafeReferencePreferredSwitchExcludedOutlierSeedTime);
    row.isStrongNonOutlier = ~row.isExcludedOutlier && ...
        row.adaptiveGainVsReferencePercent >= protocol. ...
            rollingSafeReferencePreferredSwitchMinimumNonOutlierGainPercent;
    row.safetyPassed = derived.bankSafetyPassed && ...
        row.adaptiveWorstGainVsReferencePercent >= -1e-9 && ...
        row.adaptiveConsensusGainVsReferencePercent >= -1e-9;
    rows(stateIdx) = row;
    generationCommits = [generationCommits, ...
        {adaptive.generationGitCommit, ...
         persistentPreflight.generationGitCommit, ...
         oneStep.generationGitCommit}]; %#ok<AGROW>
end

generationCommits = unique(generationCommits);
if numel(generationCommits) ~= 1 || ...
        ~strcmp(gitState.commit, generationCommits{1})
    error(['All adaptive and fixed-duration artifacts must come from ', ...
        'the current frozen commit.']);
end
meanReferenceEospa = mean([rows.referenceMeanEospa]);
meanFixedEnvelopeEospa = ...
    mean([rows.fixedDurationEnvelopeMeanEospa]);
meanAdaptiveBestEospa = mean([rows.adaptiveBestMeanEospa]);
fixedEnvelopeAggregateGainPercent = relativeGain( ...
    meanReferenceEospa, meanFixedEnvelopeEospa);
adaptiveAggregateGainPercent = relativeGain( ...
    meanReferenceEospa, meanAdaptiveBestEospa);
if fixedEnvelopeAggregateGainPercent > 1e-12
    envelopeRecoveryFraction = adaptiveAggregateGainPercent / ...
        fixedEnvelopeAggregateGainPercent;
elseif adaptiveAggregateGainPercent >= -1e-12
    envelopeRecoveryFraction = 1;
else
    envelopeRecoveryFraction = 0;
end
improvedStateCount = nnz([rows.improvesReference]);
improvedVsFixedEnvelopeStateCount = ...
    nnz([rows.improvesFixedEnvelope]);
strongNonOutlierStateCount = nnz([rows.isStrongNonOutlier]);
selectedCandidateStateCount = nnz([rows.selectedCandidateLater]);
selectedReferenceStateCount = nnz([rows.selectedReferenceLater]);
hardAuditPassed = all([rows.safetyPassed]);
headroomGatePassed = ...
    adaptiveAggregateGainPercent >= protocol. ...
        rollingSafeReferencePreferredSwitchMinimumAggregateGainPercent && ...
    envelopeRecoveryFraction >= protocol. ...
        rollingSafeReferencePreferredSwitchMinimumEnvelopeRecoveryFraction && ...
    improvedStateCount >= protocol. ...
        rollingSafeReferencePreferredSwitchMinimumImprovedStateCount && ...
    strongNonOutlierStateCount >= 1 && ...
    selectedCandidateStateCount >= protocol. ...
        rollingSafeReferencePreferredSwitchMinimumSelectedCandidateStateCount && ...
    selectedReferenceStateCount >= protocol. ...
        rollingSafeReferencePreferredSwitchMinimumSelectedReferenceStateCount;
selectorDevelopmentAuthorized = hardAuditPassed && headroomGatePassed;

summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-rolling-safe-reference-preferred-switch-paired-summary-v2';
summary.switchContractVersion = protocol. ...
    rollingSafeReferencePreferredSwitchContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.preflightGenerationGitCommit = generationCommits{1};
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.controlSummaryPath = '';
summary.controlSummaryRawRecomputed = true;
summary.rows = rows;
summary.meanReferenceEospa = meanReferenceEospa;
summary.meanFixedDurationEnvelopeEospa = meanFixedEnvelopeEospa;
summary.meanAdaptiveBestEospa = meanAdaptiveBestEospa;
summary.fixedEnvelopeAggregateGainPercent = ...
    fixedEnvelopeAggregateGainPercent;
summary.adaptiveAggregateGainPercent = adaptiveAggregateGainPercent;
summary.envelopeRecoveryFraction = envelopeRecoveryFraction;
summary.incrementalGainVsFixedEnvelopePercent = ...
    adaptiveAggregateGainPercent - fixedEnvelopeAggregateGainPercent;
summary.improvedStateCount = improvedStateCount;
summary.improvedVsFixedEnvelopeStateCount = ...
    improvedVsFixedEnvelopeStateCount;
summary.strongNonOutlierStateCount = strongNonOutlierStateCount;
summary.selectedCandidateStateCount = selectedCandidateStateCount;
summary.selectedReferenceStateCount = selectedReferenceStateCount;
summary.hardAuditGatesPassed = hardAuditPassed;
summary.sentinelHeadroomGatePassed = headroomGatePassed;
summary.selectorDevelopmentAuthorized = ...
    selectorDevelopmentAuthorized;
summary.formationFovM24Authorized = false;
summary.x36Authorized = false;
summary.x48Authorized = false;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.evidenceBoundary = [ ...
    'This paired opened-training mechanism falsifier compares a ', ...
    'non-absorbing, reference-preferred strict nominal-free switching ', ...
    'bank with same-commit one-step and persistent controls. The four ', ...
    'sentinel states were already used to design the rule, so success ', ...
    'only authorizes opened-training selector development. Best-of-eight ', ...
    'first-action selection remains an offline oracle. Fail-closed arms ', ...
    'are retained as unavailable rather than silently projected. No ', ...
    'formation-FoV M24, X36, X48, recursive-feasibility or deployable ', ...
    'fallback claim is made. Coordinator metadata bytes are uncharged.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = protocol.rollingSafeReferencePreferredSwitchSummaryStem;
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && (exist(matPath, 'file') == 2 || ...
        exist(reportPath, 'file') == 2)
    error(['Reference-switch summary already exists. Set overwrite=true ', ...
        'only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save(matPath, 'summary', '-v7');
writeReport(reportPath, summary, protocol);
fprintf('Reference-preferred switch sentinel: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function controlSummary = recomputeControlSummaryFromRaw( ...
        inputDirectory, artifactSuffix)
temporaryDirectory = tempname();
mkdir(temporaryDirectory);
cleanup = onCleanup(@() removeDirectoryIfPresent( ...
    temporaryDirectory)); %#ok<NASGU>
[~, controlSummary] = ...
    summarizeRollingSafeCausalOptionSentinelM24(struct( ...
        'inputDirectory', inputDirectory, ...
        'artifactSuffix', artifactSuffix, ...
        'outputDirectory', temporaryDirectory, ...
        'overwrite', true));
end

function removeDirectoryIfPresent(path)
if exist(path, 'dir') == 7
    rmdir(path, 's');
end
end

function path = artifactPath(directory, auditStem, seed, currentTime, suffix)
path = fullfile(directory, sprintf([ ...
    'rolling_safe_causal_h3_%s_m24_seed%d_t%d_%s.mat'], ...
    auditStem, seed, currentTime, suffix));
end

function preflight = loadPreflight(path)
loaded = load(path, 'preflight');
if ~isfield(loaded, 'preflight')
    error('Preflight is missing: %s', path);
end
preflight = loaded.preflight;
end

function validateAdaptivePreflight( ...
        preflight, seed, currentTime, behaviorAction, protocol)
required = {'protocolId', 'contractVersion', 'auditMode', ...
    'referencePreferredSwitchEnabled', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty', 'seed', 'currentTime', ...
    'returnTimes', 'optionSequences', 'optionNames', ...
    'optionStatus', 'optionFailureIdentifier', ...
    'optionExpectedUnavailable', 'firstActionGraphSha256', ...
    'firstActionFusionWeightSha256', 'referenceOptionIndex', ...
    'outcomes', 'meanGainVsReferencePercent', ...
    'worstGainVsReferencePercent', ...
    'consensusGainVsReferencePercent', ...
    'attemptedByteDeviationPercent', 'hardRuntimeGatePassed', ...
    'admissibleForSelection', 'bestAdmissibleOptionIndex', ...
    'bestAdmissibleMeanEospa', 'completedOptionCount', ...
    'unavailableOptionCount', 'sourceSha256', ...
    'sourceBehaviorAction', 'restartReferenceOverallSha256', ...
    'restartObservedOverallSha256', 'restartEquivalencePassed', ...
    'firstActionGraphAndWeightsFrozen', 'subsequentActionsCausal', ...
    'livePosteriorAndHistoryRecomputed', 'runtimePolicyUsesTruth', ...
    'exploratoryOptionSubsetUsed', 'trainingOnlyDiagnostic', ...
    'developmentOpened', 'heldoutM24Opened', 'x36Opened'};
if ~isstruct(preflight) || ~all(isfield(preflight, required))
    error('Adaptive preflight lacks required raw evidence.');
end
binaryFields = { ...
    'referencePreferredSwitchEnabled', ...
    'generationTrackedWorktreeDirty', ...
    'generationResearchWorktreeDirty', ...
    'restartEquivalencePassed', ...
    'firstActionGraphAndWeightsFrozen', ...
    'subsequentActionsCausal', ...
    'livePosteriorAndHistoryRecomputed', ...
    'runtimePolicyUsesTruth', ...
    'exploratoryOptionSubsetUsed', ...
    'trainingOnlyDiagnostic', 'developmentOpened', ...
    'heldoutM24Opened', 'x36Opened'};
for fieldIdx = 1:numel(binaryFields)
    fieldName = binaryFields{fieldIdx};
    requireFiniteBinaryDiagnostic( ...
        preflight.(fieldName), 1, fieldName);
end
optionCount = size(protocol. ...
    rollingSafeReferencePreferredSwitchCandidateSequences, 1);
registeredReferenceIndices = find(all(protocol. ...
    rollingSafeReferencePreferredSwitchCandidateSequences == ...
        protocol.rollingSafeCausalOptionReferenceSequence, 2));
if numel(registeredReferenceIndices) ~= 1
    error('Reference-switch protocol lacks one unique reference row.');
end
registeredReferenceIndex = registeredReferenceIndices(1);
requireFiniteBinaryDiagnostic(preflight.optionExpectedUnavailable, ...
    optionCount, 'optionExpectedUnavailable');
requireFiniteBinaryDiagnostic(preflight.hardRuntimeGatePassed, ...
    optionCount, 'hardRuntimeGatePassed');
requireFiniteBinaryDiagnostic(preflight.admissibleForSelection, ...
    optionCount, 'admissibleForSelection');
if ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.contractVersion, protocol. ...
            rollingSafeReferencePreferredSwitchContractVersion) || ...
        ~strcmp(preflight.auditMode, 'reference-preferred-switch') || ...
        ~preflight.referencePreferredSwitchEnabled || ...
        preflight.seed ~= seed || preflight.currentTime ~= currentTime || ...
        ~isequal(preflight.returnTimes, currentTime + (0:2)) || ...
        ~isequal(preflight.optionSequences, protocol. ...
            rollingSafeReferencePreferredSwitchCandidateSequences) || ...
        ~isequal(preflight.optionNames, protocol. ...
            rollingSafeReferencePreferredSwitchCandidateNames) || ...
        ~strcmp(preflight.sourceBehaviorAction, behaviorAction) || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        ~strcmp(preflight.restartReferenceOverallSha256, ...
            preflight.restartObservedOverallSha256) || ...
        ~preflight.firstActionGraphAndWeightsFrozen || ...
        ~preflight.subsequentActionsCausal || ...
        ~preflight.livePosteriorAndHistoryRecomputed || ...
        preflight.runtimePolicyUsesTruth || ...
        preflight.exploratoryOptionSubsetUsed || ...
        ~preflight.trainingOnlyDiagnostic || ...
        preflight.developmentOpened || preflight.heldoutM24Opened || ...
        preflight.x36Opened || ...
        ~iscell(preflight.optionStatus) || ...
        numel(preflight.optionStatus) ~= optionCount || ...
        ~iscell(preflight.optionFailureIdentifier) || ...
        numel(preflight.optionFailureIdentifier) ~= optionCount || ...
        ~iscell(preflight.firstActionGraphSha256) || ...
        numel(preflight.firstActionGraphSha256) ~= optionCount || ...
        ~iscell(preflight.firstActionFusionWeightSha256) || ...
        numel(preflight.firstActionFusionWeightSha256) ~= optionCount || ...
        ~isscalar(preflight.referenceOptionIndex) || ...
        ~isfinite(preflight.referenceOptionIndex) || ...
        preflight.referenceOptionIndex ~= ...
            round(preflight.referenceOptionIndex) || ...
        preflight.referenceOptionIndex < 1 || ...
        preflight.referenceOptionIndex > optionCount || ...
        preflight.referenceOptionIndex ~= registeredReferenceIndex || ...
        ~isscalar(preflight.completedOptionCount) || ...
        ~isfinite(preflight.completedOptionCount) || ...
        preflight.completedOptionCount ~= ...
            round(preflight.completedOptionCount) || ...
        ~isscalar(preflight.unavailableOptionCount) || ...
        ~isfinite(preflight.unavailableOptionCount) || ...
        preflight.unavailableOptionCount ~= ...
            round(preflight.unavailableOptionCount)
    error('Adaptive preflight violates its frozen contract.');
end
end

function assertCommonSourceAndReference( ...
        persistentPreflight, oneStep, adaptive, protocol)
preflights = {persistentPreflight, oneStep, adaptive};
sourceSha = adaptive.sourceSha256;
for idx = 1:numel(preflights)
    preflight = preflights{idx};
    if ~strcmp(preflight.sourceSha256, sourceSha) || ...
            ~strcmp(preflight.restartReferenceOverallSha256, ...
                adaptive.restartReferenceOverallSha256) || ...
            ~strcmp(preflight.restartObservedOverallSha256, ...
                adaptive.restartObservedOverallSha256)
        error('Paired source or restart provenance differs.');
    end
end
adaptiveReference = adaptive.outcomes(adaptive.referenceOptionIndex);
for idx = 1:2
    control = preflights{idx};
    controlReference = control.outcomes(control.referenceOptionIndex);
    metrics = [adaptiveReference.meanEospa, ...
        controlReference.meanEospa, ...
        adaptiveReference.worstSensorEospa, ...
        controlReference.worstSensorEospa, ...
        adaptiveReference.consensusOspa, ...
        controlReference.consensusOspa];
    if any(~isfinite(metrics)) || ...
            max(abs(metrics(1:2:end) - metrics(2:2:end))) > ...
                protocol.rollingSafeCausalOptionReferenceTolerance || ...
            adaptiveReference.attemptedBytes ~= ...
                controlReference.attemptedBytes || ...
            adaptiveReference.deliveredBytes ~= ...
                controlReference.deliveredBytes || ...
            ~strcmp(adaptiveReference.trajectoryGraphSha256, ...
                controlReference.trajectoryGraphSha256) || ...
            ~strcmp(adaptiveReference.executionTrace.overallSha256, ...
                controlReference.executionTrace.overallSha256)
        error('Adaptive and fixed-duration references differ.');
    end
end
end

function derived = recomputeAdaptiveDerived(preflight, protocol)
count = size(preflight.optionSequences, 1);
completed = strcmp(preflight.optionStatus, 'completed');
unavailable = strcmp(preflight.optionStatus, 'unavailable');
if any(~completed & ~unavailable) || ...
        any(unavailable & ~preflight.optionExpectedUnavailable) || ...
        any(preflight.optionExpectedUnavailable & ~unavailable)
    error('Adaptive preflight has an unregistered failure state.');
end
for idx = find(unavailable)
    if ~any(strcmp(preflight.optionFailureIdentifier{idx}, protocol. ...
            rollingSafeReferencePreferredSwitchExpectedUnavailableErrorIdentifiers))
        error('Adaptive unavailable identifier is not registered.');
    end
end
referenceIdx = preflight.referenceOptionIndex;
if ~completed(referenceIdx)
    error('Adaptive reference did not complete.');
end
reference = preflight.outcomes(referenceIdx);
validateAdaptiveOutcome(reference, ...
    preflight.optionSequences(referenceIdx, 1), ...
    preflight.firstActionGraphSha256{referenceIdx}, ...
    preflight.firstActionFusionWeightSha256{referenceIdx}, protocol);
meanGain = nan(1, count);
worstGain = nan(1, count);
consensusGain = nan(1, count);
byteDeviation = nan(1, count);
hardGate = false(1, count);
for idx = find(completed)
    outcome = preflight.outcomes(idx);
    validateAdaptiveOutcome( ...
        outcome, preflight.optionSequences(idx, 1), ...
        preflight.firstActionGraphSha256{idx}, ...
        preflight.firstActionFusionWeightSha256{idx}, protocol);
    meanGain(idx) = relativeGain(reference.meanEospa, outcome.meanEospa);
    worstGain(idx) = relativeGain( ...
        reference.worstSensorEospa, outcome.worstSensorEospa);
    consensusGain(idx) = relativeGain( ...
        reference.consensusOspa, outcome.consensusOspa);
    byteDeviation(idx) = 100 * abs( ...
        outcome.attemptedBytes - reference.attemptedBytes) / ...
        max(reference.attemptedBytes, eps);
    hardGate(idx) = outcome.truthUseCount == 0 && ...
        outcome.policyReportedRepairCount == 0 && ...
        outcome.payloadEmergencyCount == 0 && ...
        outcome.infeasibleCount == 0 && ...
        all(outcome.oneStepReserveChecked) && ...
        all(outcome.oneStepReservePassed) && ...
        all(outcome.messageCounts == protocol. ...
            rollingSafeCausalOptionMessageBudget) && ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass) && ...
        outcome.firstActionExact && outcome.firstFusionWeightsExact && ...
        outcome.referenceSwitchAuditPassed;
end
admissible = completed & hardGate & ...
    byteDeviation <= protocol. ...
        rollingSafeCausalOptionMaximumByteDeviationPercent & ...
    worstGain >= -1e-9 & consensusGain >= -1e-9;
indices = find(admissible);
if isempty(indices)
    error('Adaptive bank has no admissible reference.');
end
[bestMean, localIdx] = min([preflight.outcomes(indices).meanEospa]);
bestIdx = indices(localIdx);
derived = struct( ...
    'completed', completed, ...
    'unavailable', unavailable, ...
    'meanGainVsReferencePercent', meanGain, ...
    'worstGainVsReferencePercent', worstGain, ...
    'consensusGainVsReferencePercent', consensusGain, ...
    'attemptedByteDeviationPercent', byteDeviation, ...
    'hardRuntimeGatePassed', hardGate, ...
    'admissibleForSelection', admissible, ...
    'referenceMeanEospa', reference.meanEospa, ...
    'bestAdmissibleOptionIndex', bestIdx, ...
    'bestAdmissibleMeanEospa', bestMean, ...
    'completedOptionCount', nnz(completed), ...
    'unavailableOptionCount', nnz(unavailable), ...
    'bankSafetyPassed', hardGate(referenceIdx) && ...
        all(hardGate(completed)) && any(admissible));
end

function validateAdaptiveOutcome( ...
        outcome, candidateCode, firstGraphSha256, ...
        firstFusionWeightSha256, protocol)
horizon = protocol.returnValueGateHorizon;
required = {'meanEospa', 'worstSensorEospa', 'consensusOspa', ...
    'attemptedBytes', 'deliveredBytes', 'attemptedBytesByStep', ...
    'deliveredBytesByStep', 'messageCounts', ...
    'truthUseCount', 'policyReportedRepairCount', ...
    'policyReportedRepairByStep', 'payloadEmergencyCount', ...
    'infeasibleCount', 'oneStepReserveChecked', ...
    'oneStepReservePassed', 'selectedSensorB3Pass', ...
    'selectedFormationB3Pass', 'firstActionExact', ...
    'firstFusionWeightsExact', 'trajectoryGraphSha256', ...
    'executionTrace', 'referenceSwitchAuditPassed', ...
    'referenceSwitchAppliedByStep', ...
    'referenceSwitchSelectedCandidateByStep', ...
    'referenceSwitchCandidateActionCodeByStep', ...
    'referenceSwitchReferenceActionCodeByStep', ...
    'referenceSwitchSelectedActionCodeByStep', ...
    'referenceSwitchCandidateAvailableByStep', ...
    'referenceSwitchReferenceAvailableByStep', ...
    'referenceSwitchCandidateNominalFreeByStep', ...
    'referenceSwitchReferenceNominalFreeByStep', ...
    'referenceSwitchCandidateRequestedActionRealizedByStep', ...
    'referenceSwitchReferenceRequestedActionRealizedByStep', ...
    'referenceSwitchCandidateAttestationByStep', ...
    'referenceSwitchReferenceAttestationByStep', ...
    'referenceSwitchAlternativeTruthUsedByStep', ...
    'referenceSwitchFutureOutcomeUsedByStep', ...
    'referenceSwitchAbsorbingExitByStep', ...
    'referenceSwitchDecisionReasonByStep', ...
    'referenceSwitchCandidateFailureIdentifierByStep', ...
    'referenceSwitchReferenceFailureIdentifierByStep', ...
    'referenceSwitchCandidateAdjacencySha256ByStep', ...
    'referenceSwitchReferenceAdjacencySha256ByStep', ...
    'referenceSwitchSelectedAdjacencySha256ByStep', ...
    'referenceSwitchCandidateFusionWeightSha256ByStep', ...
    'referenceSwitchReferenceFusionWeightSha256ByStep', ...
    'referenceSwitchSelectedFusionWeightSha256ByStep', ...
    'referenceSwitchCandidateSelectionSecondsByStep', ...
    'referenceSwitchReferenceSelectionSecondsByStep', ...
    'referenceSwitchAlternativeGraphEqualByStep', ...
    'referenceSwitchAlternativeGraphHammingDistanceByStep', ...
    'referenceSwitchContextSha256ByStep', ...
    'referenceSwitchHistorySha256ByStep', ...
    'referenceSwitchPhysicalAdjacencySha256ByStep', ...
    'referenceSwitchEvaluationOrderByStep', ...
    'referenceSwitchContractVersionByStep'};
if ~isstruct(outcome) || ~all(isfield(outcome, required))
    error('Adaptive outcome lacks raw switch evidence.');
end
referenceSwitchAuditPassed = requireFiniteBinaryDiagnostic( ...
    outcome.referenceSwitchAuditPassed, 1, ...
