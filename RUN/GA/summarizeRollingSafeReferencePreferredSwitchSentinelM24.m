function [available, nominalFree, requestedActionRealized, rawAudit] = ...
        auditStoredSummaryAlternative( ...
            attestation, failureIdentifier, actionCode, protocol)
if ~ischar(failureIdentifier) || ~isstruct(attestation)
    error('Adaptive alternative has an invalid attestation container.');
end
if isempty(attestation)
    if isempty(failureIdentifier) || ...
            ~isExpectedRollingSafeReferenceSwitchAlternativeUnavailable( ...
                failureIdentifier, actionCode, protocol)
        error('Adaptive unavailable arm lacks an action-valid failure.');
    end
    available = false;
    nominalFree = false;
    requestedActionRealized = false;
    rawAudit = struct([]);
    return;
end
if ~isempty(failureIdentifier)
    error('Adaptive attested arm also reports an unavailable failure.');
end
rawAudit = auditRollingSafeReferenceSwitchAttestation( ...
    attestation, actionCode);
if ~rawAudit.available
    error('Adaptive raw attestation fails the availability contract.');
end
available = rawAudit.available;
nominalFree = rawAudit.strictNominalFree;
requestedActionRealized = rawAudit.requestedActionRealized;
end

function text = serializeSummaryNumeric(value)
if ~(isnumeric(value) || islogical(value)) || ~isreal(value)
    error('Adaptive attestation hash input must be real numeric.');
end
sizeText = sprintf('%d,', size(value));
if islogical(value)
    valueText = sprintf('%d,', value(:));
else
    valueText = sprintf('%.17g,', value(:));
end
text = sprintf('%s:%s:%s', class(value), sizeText, valueText);
end

