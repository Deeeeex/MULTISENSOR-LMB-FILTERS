if ~equal
    return;
end
bothNaN = isnan(left) & isnan(right);
finite = isfinite(left) & isfinite(right);
equal = all(bothNaN(:) | ...
    (finite(:) & abs(left(:) - right(:)) <= tolerance));
end

function valid = isValidSha256(value)
valid = ischar(value) && ...
    ~isempty(regexp(value, '^[0-9a-f]{64}$', 'once'));
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
