function receiptPath = publishFusionSufficientPublishedReceipt( ...
    plan, config, claim, testAuthorization)
% PUBLISHFUSIONSUFFICIENTPUBLISHEDRECEIPT Seal final evidence publication.

if nargin < 4
    testAuthorization = struct();
end
testMode = isFusionSufficientInternalTestAuthorization(testAuthorization);
if testMode
    if ~config.testOnly || ...
            ~strcmp(config.evidenceSchema, ...
            'fusion-sufficient-moment-exchange-test-v2') || ...
            ~strcmp(config.workerSchema, ...
            'fusion-sufficient-seed-worker-test-v2') || ...
            ~strncmp(config.artifactStem, 'TEST_', 5) || ...
            ~strncmp(config.batchIdentity, 'test-', 5)
        error('FusionSufficientPublished:TestMode', ...
            'Test authorization requires testOnly config.');
    end
else
    if config.testOnly
        error('FusionSufficientPublished:ProductionMode', ...
            'Production PUBLISHED receipt rejects testOnly config.');
    end
    assertFusionSufficientConfigProvenance(config);
end
assertFusionSufficientPublishClaim(plan, config, claim);
if exist(plan.publishedReceiptPath, 'file') == 2
    error('FusionSufficientPublished:ReceiptExists', ...
        'Refusing to overwrite PUBLISHED receipt.');
end
for pathIdx = 1:numel(plan.finalPaths)
    if exist(plan.finalPaths{pathIdx}, 'file') ~= 2
        error('FusionSufficientPublished:MissingArtifact', ...
            'Final evidence artifact is missing: %s', ...
            plan.finalPaths{pathIdx});
    end
end
validateFusionSufficientEvidence( ...
    plan.finalPaths{1}, plan.finalPaths{2}, plan.finalPaths{3}, ...
    testAuthorization);
temporaryPath = [tempname(plan.attemptDirectory), '.published'];
cleanup = onCleanup(@() deleteIfPresent(temporaryPath)); %#ok<NASGU>
text = sprintf([ ...
    'published_schema=fusion-sufficient-evidence-published-v2\n', ...
    'test_only=%d\n', ...
    'batch_identity=%s\n', ...
    'config_sha256=%s\n', ...
    'publish_claim_sha256=%s\n', ...
    'summary_sha256=%s\n', ...
    'csv_sha256=%s\n', ...
    'report_sha256=%s\n'], ...
    double(config.testOnly), config.batchIdentity, config.configSha256, ...
    claim.tokenSha256, ...
    fusionSufficientSha256File(plan.finalPaths{1}), ...
    fusionSufficientSha256File(plan.finalPaths{2}), ...
    fusionSufficientSha256File(plan.finalPaths{3}));
writeText(temporaryPath, text);
linkFusionSufficientFileNoClobber( ...
    temporaryPath, plan.publishedReceiptPath);
receiptPath = plan.publishedReceiptPath;
end

function writeText(path, value)
fid = fopen(path, 'wb');
if fid < 0
    error('FusionSufficientPublished:Write', ...
        'Unable to write PUBLISHED receipt.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = uint8(value);
count = fwrite(fid, bytes, 'uint8');
if count ~= numel(bytes)
    error('FusionSufficientPublished:Write', ...
        'Unable to write complete PUBLISHED receipt.');
end
end

function deleteIfPresent(path)
if exist(path, 'file') == 2
    delete(path);
end
end
