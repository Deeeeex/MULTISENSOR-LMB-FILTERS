function [reportPath, summary] = ...
        analyzeBudgetedLocalGatewayActionStructureV255(options)
% ANALYZEBUDGETEDLOCALGATEWAYACTIONSTRUCTUREV255 Scope the next action set.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBudgetedLocalGatewayRepairV255Protocol();
source = getIndependentM24GatewayTeacherV252Protocol();
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
checkpointPaths = getField(options, 'checkpointPaths', ...
    defaultCheckpointPaths(repoRoot, source, protocol.trainingSeeds));
if ischar(checkpointPaths)
    checkpointPaths = {checkpointPaths};
end
if ~iscell(checkpointPaths) || ...
        numel(checkpointPaths) ~= numel(protocol.trainingSeeds)
    error('BudgetedLocalGatewayRepairV255:CheckpointList', ...
        'V255 action analysis requires the three development checkpoints.');
end
outputRoot = char(getField(options, 'outputRoot', ...
    fullfile(repoRoot, protocol.outputRoot, 'action_structure')));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
writeReport = logical(getField(options, 'writeReport', true));
writeMat = logical(getField(options, 'writeMat', true));

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('BudgetedLocalGatewayRepairV255:DirtySource', ...
        'Official V255 action analysis requires clean source.');
end

rows = repmat(emptyRow(), 1, 0);
sourceCommits = cell(1, numel(checkpointPaths));
exactNetPositiveCandidateCount = 0;
creditPositiveCandidateCount = 0;
unrestrictedCreditPositiveCandidateCount = 0;
exactNetCoveredWindowCount = 0;
creditCoveredWindowCount = 0;
unrestrictedCreditCoveredWindowCount = 0;
allBestJointScores = zeros(1, 0);
localBestJointScores = zeros(1, 0);

for pathIdx = 1:numel(checkpointPaths)
    loaded = load(char(checkpointPaths{pathIdx}), 'result');
    if ~isfield(loaded, 'result')
        error('BudgetedLocalGatewayRepairV255:MissingResult', ...
            'A V252 checkpoint has no result envelope.');
    end
    oracle = loaded.result;
    validateOracle(oracle, source, protocol.trainingSeeds);
    sourceCommits{pathIdx} = oracle.generationGitCommit;
    cache = load(oracle.cachePath, 'behaviorBundle');
    sensorsPerFormation = ...
        cache.behaviorBundle.configSnapshot.sensorsPerFormation;
    localControlBytes = localControlCost( ...
        protocol, sensorsPerFormation);
    for windowIdx = 1:numel(oracle.windows)
        window = oracle.windows{windowIdx};
        reference = window.arms{window.referenceCandidateIndex};
        exactCount = 0;
        creditCount = 0;
        unrestrictedCount = 0;
        bestAllScore = -Inf;
        bestLocalScore = -Inf;
        bestAllIndex = window.referenceCandidateIndex;
        bestLocalIndex = window.referenceCandidateIndex;
        for candidateIdx = 1:window.candidateCount
            if candidateIdx == window.referenceCandidateIndex
                continue;
            end
            comparison = window.comparisons{candidateIdx};
            candidate = window.arms{candidateIdx};
            changedCount = countChangedArcs( ...
                window.candidateAssignments{candidateIdx}, ...
                window.candidateAssignments{ ...
                    window.referenceCandidateIndex});
            totalByteSaving = lowerGain( ...
                reference.attemptedPayloadBytes, ...
                candidate.attemptedPayloadBytes + localControlBytes);
            corePositive = comparison.eospaGainPercent > ...
                    protocol.minimumCoreGainPercent && ...
                comparison.rmseGainPercent > ...
                    protocol.minimumCoreGainPercent && ...
                comparison.consistencyGainPercent > ...
                    protocol.minimumCoreGainPercent;
            tailsSafe = ...
                comparison.minimumFormationEospaGainPercent >= ...
                    -protocol.maximumFormationRegressionPercent && ...
                comparison.minimumFormationRmseGainPercent >= ...
                    -protocol.maximumFormationRegressionPercent;
            local = changedCount <= ...
                protocol.maximumChangedDirectedGatewayArcs;
            exactPositive = corePositive && tailsSafe && local && ...
                totalByteSaving >= 0;
            creditPositive = corePositive && tailsSafe && local && ...
                totalByteSaving >= ...
                    -protocol.developmentIncrementalByteCapPercentRelativeV242;
            unrestrictedPositive = corePositive && tailsSafe && ...
                totalByteSaving >= ...
                    -protocol.developmentIncrementalByteCapPercentRelativeV242;
            exactCount = exactCount + exactPositive;
            creditCount = creditCount + creditPositive;
            unrestrictedCount = unrestrictedCount + unrestrictedPositive;
            jointScore = min([comparison.eospaGainPercent, ...
                comparison.rmseGainPercent, ...
                comparison.consistencyGainPercent]);
            if unrestrictedPositive && jointScore > bestAllScore
                bestAllScore = jointScore;
                bestAllIndex = candidateIdx;
            end
            if creditPositive && jointScore > bestLocalScore
                bestLocalScore = jointScore;
                bestLocalIndex = candidateIdx;
            end
        end
        row = emptyRow();
        row.seed = oracle.seed;
        row.anchorTime = window.anchorTime;
        row.localControlBytes = localControlBytes;
        row.exactNetPositiveCandidateCount = exactCount;
        row.creditPositiveCandidateCount = creditCount;
        row.unrestrictedCreditPositiveCandidateCount = unrestrictedCount;
        row.exactNetPositiveAvailable = exactCount > 0;
        row.creditPositiveAvailable = creditCount > 0;
        row.unrestrictedCreditPositiveAvailable = unrestrictedCount > 0;
        row.bestUnrestrictedCandidateIndex = bestAllIndex;
        row.bestLocalCandidateIndex = bestLocalIndex;
        row.bestUnrestrictedJointScorePercent = finiteOrZero(bestAllScore);
        row.bestLocalJointScorePercent = finiteOrZero(bestLocalScore);
        if isfinite(bestAllScore) && bestAllScore > 0
            row.localJointScoreRetentionFraction = ...
                max(0, bestLocalScore) / bestAllScore;
            allBestJointScores(end + 1) = bestAllScore; %#ok<AGROW>
            localBestJointScores(end + 1) = ...
                max(0, bestLocalScore); %#ok<AGROW>
        end
        rows(end + 1) = row; %#ok<AGROW>
        exactNetPositiveCandidateCount = ...
            exactNetPositiveCandidateCount + exactCount;
        creditPositiveCandidateCount = ...
            creditPositiveCandidateCount + creditCount;
        unrestrictedCreditPositiveCandidateCount = ...
            unrestrictedCreditPositiveCandidateCount + unrestrictedCount;
        exactNetCoveredWindowCount = exactNetCoveredWindowCount + ...
            row.exactNetPositiveAvailable;
        creditCoveredWindowCount = creditCoveredWindowCount + ...
            row.creditPositiveAvailable;
        unrestrictedCreditCoveredWindowCount = ...
            unrestrictedCreditCoveredWindowCount + ...
            row.unrestrictedCreditPositiveAvailable;
    end
end

summary = struct();
summary.contractVersion = ...
    'budgeted-local-gateway-action-structure-v255-summary-v1';
summary.protocol = protocol;
summary.analysisGitCommit = gitState.commit;
summary.sourceGenerationGitCommits = sourceCommits;
summary.checkpointPaths = checkpointPaths;
summary.rows = rows;
summary.windowCount = numel(rows);
summary.exactNetPositiveCandidateCount = ...
    exactNetPositiveCandidateCount;
summary.creditPositiveCandidateCount = creditPositiveCandidateCount;
summary.unrestrictedCreditPositiveCandidateCount = ...
    unrestrictedCreditPositiveCandidateCount;
summary.exactNetCoveredWindowCount = exactNetCoveredWindowCount;
summary.creditCoveredWindowCount = creditCoveredWindowCount;
summary.unrestrictedCreditCoveredWindowCount = ...
    unrestrictedCreditCoveredWindowCount;
summary.creditCoveragePreserved = creditCoveredWindowCount == ...
    unrestrictedCreditCoveredWindowCount;
summary.positiveJointScoreSumRetentionFraction = ...
    sum(localBestJointScores) / max(sum(allBestJointScores), eps);
summary.singleArcActionSpaceSupported = ...
    summary.creditCoveragePreserved && ...
    summary.creditCoveredWindowCount >= 0.5 * summary.windowCount && ...
    summary.exactNetCoveredWindowCount >= 0.5 * summary.windowCount;
summary.multiOutputModelAuthorized = ...
    summary.singleArcActionSpaceSupported;
summary.gnnAuthorized = false;
summary.validationClaimAllowed = false;
summary.developmentEvidenceOnly = true;
if summary.singleArcActionSpaceSupported
    summary.nextDecision = ...
        'freeze-v255-single-arc-multi-output-model-before-seed1306';
else
    summary.nextDecision = ...
        'stop-local-action-space-before-model-training';
end
summary.evidenceBoundary = protocol.evidenceBoundary;
summary.completedAt = datestr(now, 31);

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
reportPath = fullfile(outputRoot, ...
    'V255_BUDGETED_LOCAL_GATEWAY_ACTION_STRUCTURE.md');
matPath = fullfile(outputRoot, ...
    'V255_BUDGETED_LOCAL_GATEWAY_ACTION_STRUCTURE.mat');
summary.reportPath = reportPath;
summary.matPath = matPath;
if writeMat
    save('-mat7-binary', matPath, 'summary');
end
if writeReport
    writeReportFile(reportPath, summary);
end
fprintf(['V255 action structure complete: exact-net windows %d/%d; ', ...
    'credit windows %d/%d; unrestricted credit windows %d/%d; ', ...
    'single-arc supported=%d\n'], ...
    summary.exactNetCoveredWindowCount, summary.windowCount, ...
    summary.creditCoveredWindowCount, summary.windowCount, ...
    summary.unrestrictedCreditCoveredWindowCount, summary.windowCount, ...
    summary.singleArcActionSpaceSupported);
fprintf('V255 report: %s\n', reportPath);
end

function paths = defaultCheckpointPaths(repoRoot, source, seeds)
paths = cell(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    paths{seedIdx} = fullfile(repoRoot, source.outputRoot, ...
        sprintf('seed%d', seeds(seedIdx)), source.oracleMatName);
end
end

function validateOracle(oracle, source, seeds)
valid = isstruct(oracle) && isscalar(oracle) && ...
    isfield(oracle, 'contractVersion') && ...
    strcmp(oracle.contractVersion, source.resultContractVersion) && ...
    isfield(oracle, 'protocolId') && ...
    strcmp(oracle.protocolId, source.id) && ...
    isfield(oracle, 'seed') && ismember(oracle.seed, seeds) && ...
    isfield(oracle, 'windows') && ...
    numel(oracle.windows) == numel(source.anchorTimes) && ...
    isfield(oracle, 'generationGitCommit') && ...
    ischar(oracle.generationGitCommit);
if ~valid
    error('BudgetedLocalGatewayRepairV255:InvalidOracle', ...
        'A development checkpoint is incomplete or incompatible.');
end
end

function bytes = localControlCost(protocol, sensorsPerFormation)
bytes = 2 * sensorsPerFormation * ...
    protocol.compactNodeBytesPerSensor + ...
    protocol.routeCommandHeaderBytes + ...
    protocol.routeCommandBytesPerChangedArc * ...
        protocol.maximumChangedDirectedGatewayArcs;
end

function count = countChangedArcs(candidate, reference)
candidate = sortrows(candidate, [2, 1, 4, 3]);
reference = sortrows(reference, [2, 1, 4, 3]);
if ~isequal(candidate(:, 1:2), reference(:, 1:2))
    error('BudgetedLocalGatewayRepairV255:FormationTreeDrift', ...
        'A V252 candidate changed the formation tree.');
end
count = nnz(any(candidate(:, 3:4) ~= reference(:, 3:4), 2));
end

function writeReportFile(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('BudgetedLocalGatewayRepairV255:ReportOpen', ...
        'Could not write the V255 action report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V255 budgeted local gateway action structure\n\n');
fprintf(fid, '- Analysis source commit: `%s`\n', ...
    summary.analysisGitCommit);
fprintf(fid, '- V252 source commits: `%s`\n', ...
    strjoin(unique(summary.sourceGenerationGitCommits), ', '));
fprintf(fid, '- Development windows: `%d`\n', summary.windowCount);
fprintf(fid, '- Maximum changed directed gateway arcs: `1`\n');
fprintf(fid, ['- Incremental development byte cap relative to V242: ', ...
    '`%.1f%%`\n'], ...
    summary.protocol.developmentIncrementalByteCapPercentRelativeV242);
fprintf(fid, '- Exact-net positive window coverage: `%d/%d`\n', ...
    summary.exactNetCoveredWindowCount, summary.windowCount);
fprintf(fid, '- Credit-positive window coverage: `%d/%d`\n', ...
    summary.creditCoveredWindowCount, summary.windowCount);
fprintf(fid, '- Unrestricted credit-positive coverage: `%d/%d`\n', ...
    summary.unrestrictedCreditCoveredWindowCount, summary.windowCount);
fprintf(fid, '- Coverage preserved by one-arc restriction: `%d`\n', ...
    summary.creditCoveragePreserved);
fprintf(fid, '- Positive joint-score sum retained: `%.3f`\n', ...
    summary.positiveJointScoreSumRetentionFraction);
fprintf(fid, '- Next decision: `%s`\n\n', summary.nextDecision);

fprintf(fid, ['| Seed | Anchor | Local control B | Exact-net positive ', ...
    '| Credit positive local / all | Best joint local / all | ', ...
    'Retention |\n']);
fprintf(fid, '|--:|--:|--:|--:|:--|:--|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, ['| %d | %d | %d | %d | %d / %d | ', ...
        '%+.4f%% / %+.4f%% | %.3f |\n'], ...
        row.seed, row.anchorTime, row.localControlBytes, ...
        row.exactNetPositiveCandidateCount, ...
        row.creditPositiveCandidateCount, ...
        row.unrestrictedCreditPositiveCandidateCount, ...
        row.bestLocalJointScorePercent, ...
        row.bestUnrestrictedJointScorePercent, ...
        row.localJointScoreRetentionFraction);
end

fprintf(fid, '\n## Interpretation\n\n');
fprintf(fid, ['A one-directed-arc action preserves every development ', ...
    'window that has a positive action under the registered local ', ...
    'communication-credit screen. It also leaves positive exact-net ', ...
    'actions in at least half of the windows. Global additive composition ', ...
    'therefore adds unsupported extrapolation without increasing positive ', ...
    'window coverage in these data. This authorizes only the V255 ', ...
    'multi-output ridge screen and the new seed-1306 teacher; it is not a ', ...
    'deployable tracking result.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = emptyRow()
value = struct('seed', 0, 'anchorTime', 0, ...
    'localControlBytes', 0, ...
    'exactNetPositiveCandidateCount', 0, ...
    'creditPositiveCandidateCount', 0, ...
    'unrestrictedCreditPositiveCandidateCount', 0, ...
    'exactNetPositiveAvailable', false, ...
    'creditPositiveAvailable', false, ...
    'unrestrictedCreditPositiveAvailable', false, ...
    'bestUnrestrictedCandidateIndex', 0, ...
    'bestLocalCandidateIndex', 0, ...
    'bestUnrestrictedJointScorePercent', 0, ...
    'bestLocalJointScorePercent', 0, ...
    'localJointScoreRetentionFraction', 0);
end

function value = finiteOrZero(value)
if ~isfinite(value)
    value = 0;
end
end

function value = lowerGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    (~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once'))));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
