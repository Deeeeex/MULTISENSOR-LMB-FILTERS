function [reportPath, result] = ...
    runRepeatedMultiGatewayHandoverV89FullEpisode(options)
% RUNREPEATEDMULTIGATEWAYHANDOVERV89FULLEPISODE Paired M24/X36 outcome.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRepeatedMultiGatewayHandoverV89Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('RepeatedMultiGatewayV89:DirtySource', ...
        'The V89 full-episode outcome requires clean frozen source.');
end
presetNames = getField(options, 'presetNames', protocol.presets);
if ischar(presetNames)
    presetNames = {presetNames};
end
if ~iscell(presetNames) || isempty(presetNames) || ...
        any(~cellfun(@(value) any(strcmp(value, protocol.presets)), ...
            presetNames))
    error('RepeatedMultiGatewayV89:InvalidPresetSelection', ...
        'Only the frozen M24/X36 braided-handover scenes are allowed.');
end
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = getField(options, 'outputRoot', protocol.fullEpisodeOutputRoot);
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(presetNames));
startedAt = datestr(now, 31);
totalTimer = tic;
for presetIdx = 1:numel(presetNames)
    presetName = presetNames{presetIdx};
    registryIdx = find(strcmp(presetName, protocol.presets), 1);
    seed = protocol.allSeeds;
    fprintf('\nV89 full episode: %s seed %d (%d/%d)\n', ...
        presetName, seed, presetIdx, numel(presetNames));
    inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
    if inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCounts(registryIdx) || ...
            inputs.config.formationCount ~= ...
                protocol.expectedFormationCounts(registryIdx)
        error('RepeatedMultiGatewayV89:ScenarioScaleDrift', ...
            'The generated V89 scene changed its registered scale.');
    end
    identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
    deliverySeed = protocol.deliverySeedOffset + ...
        100 * seed + registryIdx;
    [inputs.commConfig.linkUniforms, ~] = ...
        materializePhysicalUidDirectedDeliveryUniforms( ...
            deliverySeed, identity.sensorPhysicalUids, ...
            inputs.config.simulationLength);
    filterSeed = protocol.filterSeedOffset + 100 * seed + registryIdx;
    filterModel = removeRealizedTargetTruth(inputs.model);
    representatives = selectFormationRepresentatives( ...
        inputs.config.sensorGroupIds);
    armIds = {protocol.referenceArmId, protocol.candidateArmId};
    arms = cell(1, 2);
    for armIdx = 1:2
        armId = armIds{armIdx};
        config = buildRepeatedMultiGatewayHandoverV89TriggerConfig( ...
            armId, inputs.config.numberOfSensors);
        context = ...
            buildRepeatedMultiGatewayHandoverV89ExecutionContext( ...
                presetName, seed, armId, ...
                inputs.config.simulationLength);
        rng(filterSeed, 'twister');
        armTimer = tic;
        fprintf('  running %s ...\n', armId);
        [estimates, diagnostics] = ...
            runEventTriggeredDistributedLmbFilter( ...
                filterModel, inputs.measurements, ...
                inputs.sensorTrajectories, inputs.neighborMap, ...
                inputs.commConfig, config, context);
        arms{armIdx} = summarizeArm( ...
            armId, estimates, diagnostics, inputs.groundTruthRfs, ...
            inputs.config, representatives, protocol, toc(armTimer));
        fprintf(['    E-OSPA full %.3f focus %.3f; gateways %d; ', ...
            'fallbacks %d; %.1f s\n'], ...
            arms{armIdx}.fullHorizonPositionEospa, ...
            arms{armIdx}.focusWindowPositionEospa, ...
            arms{armIdx}.selectedGatewayCount, ...
            arms{armIdx}.referenceFallbackCount, ...
            arms{armIdx}.elapsedSeconds);
        clear estimates diagnostics;
    end
    record = emptyRecord();
    record.presetName = presetName;
    record.seed = seed;
    record.numberOfSensors = inputs.config.numberOfSensors;
    record.formationCount = inputs.config.formationCount;
    record.simulationLength = inputs.config.simulationLength;
    record.focusWindow = [protocol.activationStartTime, ...
        protocol.activationEndTime];
    record.deliverySeed = deliverySeed;
    record.filterSeed = filterSeed;
    record.reference = arms{1};
    record.candidate = arms{2};
    record.improvement = summarizeImprovement( ...
        record.reference, record.candidate, protocol);
    records(presetIdx) = record;
    fprintf(['  V89 improvement: full %+.3f%% focus %+.3f%% ', ...
        'worst %+.3f%% formation %+.3f%% consensus %+.3f%% ', ...
        'strong=%d\n'], ...
        record.improvement.fullHorizonMeanGainPercent, ...
        record.improvement.focusWindowMeanGainPercent, ...
        record.improvement.worstSensorGainPercent, ...
        record.improvement.minimumFormationGainPercent, ...
        record.improvement.focusConsensusGainPercent, ...
        record.improvement.strongGatePassed);
    clear inputs filterModel arms;
end

result = struct();
result.contractVersion = ...
    'repeated-multi-gateway-handover-v89-full-episode-result-v1';
result.protocol = protocol;
result.startedAt = startedAt;
result.completedAt = datestr(now, 31);
result.elapsedSeconds = toc(totalTimer);
result.generationGitCommit = gitState.commit;
result.presetNames = presetNames;
result.records = records;
improvements = [records.improvement];
result.allRequestedScalesStrongGatePassed = ...
    all([improvements.strongGatePassed]);
result.bothScalesStrongGatePassed = ...
    numel(presetNames) == numel(protocol.presets) && ...
    all(ismember(protocol.presets, presetNames)) && ...
    result.allRequestedScalesStrongGatePassed;
result.trackingOutcomeRead = true;
result.multistyleScoringAuthorized = ...
    result.bothScalesStrongGatePassed;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_FULL_EPISODE.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('\nV89 full-episode result: %s\n', reportPath);
end

function summary = summarizeArm( ...
        armId, estimates, diagnostics, truth, config, ...
        representatives, protocol, elapsedSeconds)
sensorCount = numel(estimates);
timeCount = numel(truth.x);
eospa = zeros(sensorCount, timeCount);
cardinality = zeros(sensorCount, timeCount);
for sensorIdx = 1:sensorCount
    for currentTime = 1:timeCount
        components = computePositionEuclideanOspa( ...
            truth.x{currentTime}, estimates{sensorIdx}.mu{currentTime}, ...
            config.ospaPositionCutoff, 2, [1, 2]);
        eospa(sensorIdx, currentTime) = components(1);
        cardinality(sensorIdx, currentTime) = abs( ...
            numel(estimates{sensorIdx}.mu{currentTime}) - ...
            numel(truth.x{currentTime}));
    end
end

interFormation = zeros(1, timeCount);
for currentTime = 1:timeCount
    values = zeros(1, nchoosek(numel(representatives), 2));
    cursor = 0;
    for left = 1:numel(representatives)-1
        for right = left+1:numel(representatives)
            cursor = cursor + 1;
            components = computePositionEuclideanOspa( ...
                estimates{representatives(left)}.mu{currentTime}, ...
                estimates{representatives(right)}.mu{currentTime}, ...
                config.ospaPositionCutoff, 2, [1, 2]);
            values(cursor) = components(1);
        end
    end
    interFormation(currentTime) = mean(values);
end

focusTimes = protocol.activationStartTime:min( ...
    protocol.activationEndTime, timeCount);
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
perSensor = mean(eospa, 2);
perFormation = zeros(1, numel(groups));
for formationIdx = 1:numel(groups)
    perFormation(formationIdx) = mean( ...
        perSensor(groupIds == groups(formationIdx)));
end

phaseCounts = struct('acquire', 0, 'broadcast', 0, 'reference', 0);
selectedGatewayCount = 0;
referenceFallbackCount = 0;
phaseByTime = repmat({''}, 1, timeCount);
selectedGatewayCountByTime = zeros(1, timeCount);
referenceFallbackByTime = false(1, timeCount);
for currentTime = 1:timeCount
    schedule = diagnostics.topologyPolicyScheduleCertificate{currentTime};
    if ~isstruct(schedule) || ~isfield(schedule, 'phase')
        continue;
    end
    if isfield(phaseCounts, schedule.phase)
        phaseCounts.(schedule.phase) = ...
            phaseCounts.(schedule.phase) + 1;
    end
    phaseByTime{currentTime} = schedule.phase;
    selectedGatewayCountByTime(currentTime) = ...
        getField(schedule, 'selectedGatewayCount', 0);
    referenceFallbackByTime(currentTime) = logical( ...
        getField(schedule, 'referenceFallbackUsed', false));
end
selectedGatewayCount = sum(selectedGatewayCountByTime);
referenceFallbackCount = nnz(referenceFallbackByTime);

[sensorB3, formationB3] = selectedRollingB3( ...
    diagnostics.topologyActiveEdge, groupIds);
summary = struct();
summary.armId = armId;
summary.elapsedSeconds = elapsedSeconds;
summary.fullHorizonPositionEospa = mean(eospa(:));
summary.focusWindowPositionEospa = mean( ...
    reshape(eospa(:, focusTimes), 1, []));
summary.worstSensorPositionEospa = max(perSensor);
summary.perSensorPositionEospa = reshape(perSensor, 1, []);
summary.perFormationPositionEospa = perFormation;
summary.positionEospaBySensorTime = eospa;
summary.networkMeanPositionEospaByTime = mean(eospa, 1);
summary.meanAbsoluteCardinalityError = mean(cardinality(:));
summary.focusAbsoluteCardinalityError = mean( ...
    reshape(cardinality(:, focusTimes), 1, []));
summary.absoluteCardinalityErrorBySensorTime = cardinality;
summary.networkMeanAbsoluteCardinalityErrorByTime = ...
    mean(cardinality, 1);
summary.meanInterFormationPositionOspa = mean(interFormation);
summary.focusInterFormationPositionOspa = mean( ...
    interFormation(focusTimes));
summary.terminalInterFormationPositionOspa = interFormation(end);
summary.interFormationPositionOspaByTime = interFormation;
summary.attemptedMessageCount = nnz(diagnostics.attempted);
summary.deliveredMessageCount = nnz(diagnostics.delivered);
summary.attemptedPayloadBytes = sum( ...
    diagnostics.attemptedPayloadBytes(:));
summary.deliveredPayloadBytes = sum( ...
    diagnostics.attemptedPayloadBytes( ...
        logical(diagnostics.delivered)));
summary.phaseCounts = phaseCounts;
summary.phaseByTime = phaseByTime;
summary.selectedGatewayCount = selectedGatewayCount;
summary.selectedGatewayCountByTime = selectedGatewayCountByTime;
summary.referenceFallbackCount = referenceFallbackCount;
summary.referenceFallbackByTime = referenceFallbackByTime;
summary.exactMessageParityPassed = all( ...
    diagnostics.topologyDirectedMessageCount == 2 * sensorCount);
summary.physicalFeasibilityPassed = all(diagnostics.topologyFeasible);
summary.selectedRollingB3SensorPassed = sensorB3;
summary.selectedRollingB3FormationPassed = formationB3;
end

function improvement = summarizeImprovement(reference, candidate, protocol)
improvement = struct();
improvement.fullHorizonMeanGainPercent = percentImprovement( ...
    reference.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionEospa);
improvement.focusWindowMeanGainPercent = percentImprovement( ...
    reference.focusWindowPositionEospa, ...
    candidate.focusWindowPositionEospa);
improvement.worstSensorGainPercent = percentImprovement( ...
    reference.worstSensorPositionEospa, ...
    candidate.worstSensorPositionEospa);
improvement.formationGainPercent = 100 * ( ...
    reference.perFormationPositionEospa - ...
    candidate.perFormationPositionEospa) ./ ...
    max(reference.perFormationPositionEospa, eps);
improvement.minimumFormationGainPercent = ...
    min(improvement.formationGainPercent);
improvement.fullConsensusGainPercent = percentImprovement( ...
    reference.meanInterFormationPositionOspa, ...
    candidate.meanInterFormationPositionOspa);
improvement.focusConsensusGainPercent = percentImprovement( ...
    reference.focusInterFormationPositionOspa, ...
    candidate.focusInterFormationPositionOspa);
improvement.cardinalityGainPercent = percentImprovement( ...
    reference.meanAbsoluteCardinalityError, ...
    candidate.meanAbsoluteCardinalityError);
improvement.attemptedByteSavingPercent = percentImprovement( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
improvement.networkMeanPositionEospaGainPercentByTime = ...
    elementwisePercentImprovement( ...
        reference.networkMeanPositionEospaByTime, ...
        candidate.networkMeanPositionEospaByTime);
improvement.networkMeanCardinalityGainPercentByTime = ...
    elementwisePercentImprovement( ...
        reference.networkMeanAbsoluteCardinalityErrorByTime, ...
        candidate.networkMeanAbsoluteCardinalityErrorByTime);
improvement.interFormationConsensusGainPercentByTime = ...
    elementwisePercentImprovement( ...
        reference.interFormationPositionOspaByTime, ...
        candidate.interFormationPositionOspaByTime);
improvement.phaseMeanGainPercent = summarizePhaseGain( ...
    reference, candidate, protocol);
improvement.strongGatePassed = ...
    improvement.fullHorizonMeanGainPercent >= ...
        protocol.minimumFullEpisodeMeanGainPercent - 1e-12 && ...
    improvement.focusWindowMeanGainPercent >= ...
        protocol.minimumFocusWindowMeanGainPercent - 1e-12 && ...
    improvement.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    improvement.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    improvement.focusConsensusGainPercent >= ...
        protocol.minimumConsensusGainPercent - 1e-12 && ...
    improvement.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    candidate.exactMessageParityPassed && ...
    candidate.physicalFeasibilityPassed && ...
    candidate.selectedRollingB3SensorPassed && ...
    candidate.selectedRollingB3FormationPassed;
end

function phaseGain = summarizePhaseGain(reference, candidate, protocol)
phaseNames = {'acquire', 'broadcast', 'reference'};
phaseGain = struct();
timeCount = numel(candidate.phaseByTime);
focusMask = false(1, timeCount);
focusMask(protocol.activationStartTime:min( ...
    protocol.activationEndTime, timeCount)) = true;
for phaseIdx = 1:numel(phaseNames)
    phaseName = phaseNames{phaseIdx};
    mask = focusMask & strcmp(candidate.phaseByTime, phaseName);
    phaseGain.(phaseName) = NaN;
    if any(mask)
        phaseGain.(phaseName) = percentImprovement( ...
            mean(reference.networkMeanPositionEospaByTime(mask)), ...
            mean(candidate.networkMeanPositionEospaByTime(mask)));
    end
end
end

function [sensorPassed, formationPassed] = ...
        selectedRollingB3(runtimeEdges, groupIds)
sensorPassed = true;
formationPassed = true;
policyPages = permute(logical(runtimeEdges), [2, 1, 3]);
for currentTime = 3:size(policyPages, 3)
    window = any(policyPages(:, :, currentTime-2:currentTime), 3);
    sensorPassed = sensorPassed && isStronglyConnectedLocal(window);
    formationPassed = formationPassed && isStronglyConnectedLocal( ...
        collapseToFormations(window, groupIds));
end
end

function formation = collapseToFormations(adjacency, groupIds)
groups = unique(groupIds, 'stable');
formation = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formation(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formation(1:numel(groups)+1:end) = false;
end

function connected = isStronglyConnectedLocal(adjacency)
connected = reachesAll(adjacency) && reachesAll(adjacency');
end

function passed = reachesAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
passed = all(visited);
end

function value = percentImprovement(reference, candidate)
if reference == 0
    value = 0;
    if candidate > 0
        value = -Inf;
    end
else
    value = 100 * (reference - candidate) / reference;
end
end

function values = elementwisePercentImprovement(reference, candidate)
values = zeros(size(reference));
zero = reference == 0;
values(~zero) = 100 * (reference(~zero) - candidate(~zero)) ./ ...
    reference(~zero);
values(zero & candidate > 0) = -Inf;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('RepeatedMultiGatewayV89:ReportWriteFailed', ...
        'Could not create the V89 full-episode report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V89 repeated multi-gateway full-episode result\n\n');
fprintf(fid, ['Reference and candidate share the scene, measurements, ', ...
    'delivery uniforms and filter seed. Positive values mean the ', ...
    'candidate is better.\n\n']);
fprintf(fid, ['| Scale | Reference E-OSPA | Candidate E-OSPA | Full | ', ...
    'Focus | Worst sensor | Minimum formation | Focus consensus | ', ...
    'Attempted bytes | Gateways | Fallbacks | Strong |\n']);
fprintf(fid, ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for record = result.records
    gain = record.improvement;
    fprintf(fid, ['| %s | %.3f | %.3f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d | %d | %d |\n'], ...
        record.presetName, ...
        record.reference.fullHorizonPositionEospa, ...
        record.candidate.fullHorizonPositionEospa, ...
        gain.fullHorizonMeanGainPercent, ...
        gain.focusWindowMeanGainPercent, ...
        gain.worstSensorGainPercent, ...
        gain.minimumFormationGainPercent, ...
        gain.focusConsensusGainPercent, ...
        gain.attemptedByteSavingPercent, ...
        record.candidate.selectedGatewayCount, ...
        record.candidate.referenceFallbackCount, ...
        gain.strongGatePassed);
end
fprintf(fid, '\n## Phase-resolved focus-window tracking\n\n');
fprintf(fid, '| Scale | Acquire | Broadcast | Reference recovery |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
for record = result.records
    phase = record.improvement.phaseMeanGainPercent;
    fprintf(fid, '| %s | %+.3f%% | %+.3f%% | %+.3f%% |\n', ...
        record.presetName, phase.acquire, phase.broadcast, ...
        phase.reference);
end
fprintf(fid, '\n- Both scales pass the strong gate: `%d`\n', ...
    result.bothScalesStrongGatePassed);
fprintf(fid, '- Multistyle scoring authorized: `%d`\n', ...
    result.multistyleScoringAuthorized);
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'numberOfSensors', NaN, ...
    'formationCount', NaN, ...
    'simulationLength', NaN, ...
    'focusWindow', zeros(1, 0), ...
    'deliverySeed', NaN, ...
    'filterSeed', NaN, ...
    'reference', struct(), ...
    'candidate', struct(), ...
    'improvement', struct());
end

function model = removeRealizedTargetTruth(model)
if isfield(model, 'explicitTargetTrajectories')
    model = rmfield(model, 'explicitTargetTrajectories');
end
fields = {'targetTrajectories', 'target'};
for fieldIdx = 1:numel(fields)
    if isfield(model.dynamicTopologyScenario, fields{fieldIdx})
        model.dynamicTopologyScenario = rmfield( ...
            model.dynamicTopologyScenario, fields{fieldIdx});
    end
end
end

function sensors = selectFormationRepresentatives(groupIds)
groups = unique(groupIds, 'stable');
sensors = zeros(1, numel(groups));
for formationIdx = 1:numel(groups)
    sensors(formationIdx) = find( ...
        groupIds == groups(formationIdx), 1);
end
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && path(1) == filesep;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
