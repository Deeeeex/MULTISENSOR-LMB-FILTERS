function [reportPath, audit] = ...
    auditPosteriorRiskTailSafeOpenedStates(options)
% AUDITPOSTERIORRISKTAILSAFEOPENEDSTATES
% Compare frozen v9 and posterior-risk v10 on opened one-step states.
%
% This audit is deliberately development-only. It uses no truth or future
% outcome in either policy, but the continuation states have already been
% opened and therefore cannot support a validation claim.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
presetName = getField(options, 'presetName', 'm24-formation-fov');
seeds = reshape(getField(options, 'seeds', 83), 1, []);
currentTime = round(getField(options, 'currentTime', ...
    defaultDecisionTime(presetName)));
cacheRoot = getField(options, 'cacheRoot', fullfile( ...
    protocol.valueGatedFormationFovValidationRoot, 'cache'));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'posterior_risk_v10', 'opened_state_audit', presetName));
writeReportEnabled = logical(getField(options, 'writeReport', true));

rows = repmat(emptyRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
    cachePath = fullfile(cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
        seed, currentTime));
    bundle = loadBehaviorBundle( ...
        cachePath, presetName, seed, currentTime, inputs.config);
    context = buildPolicyContext( ...
        inputs, bundle, currentTime);
    commonOptions = buildPolicyOptions(protocol);

    timerId = tic;
    [v9Adjacency, v9Details] = ...
        selectLabelSetAdaptiveDominantRoutingPolicy( ...
            context, ...
            ['composite-balanced-certified-overlap-consensus-', ...
             'joint-trust-value-gated-payload-aware'], ...
            commonOptions);
    v9Seconds = toc(timerId);

    v10Options = commonOptions;
    v10Options.posteriorRiskPrototypeAuthorized = true;
    v10Options.posteriorRiskReceiverTailFraction = 0.34;
    v10Options.posteriorRiskReceiverTailWeight = 0.5;
    v10Options.formationRiskTailFraction = 0.34;
    v10Options.formationRiskTailWeight = 0.5;
    v10Options.formationRiskToleranceFraction = 0;
    timerId = tic;
    [v10Adjacency, v10Details] = ...
        selectLabelSetAdaptiveDominantRoutingPolicy( ...
            context, ...
            ['composite-balanced-certified-overlap-consensus-', ...
             'joint-trust-posterior-risk-tail-safe-', ...
             'payload-aware'], v10Options);
    v10Seconds = toc(timerId);

    v9Projection = v9Details.consensusProjection;
    v10Projection = v10Details.consensusProjection;
    assertAuditContracts(v9Details, v10Details, v10Projection);
    row = emptyRow();
    row.seed = seed;
    row.cachePath = cachePath;
    row.currentTime = currentTime;
    row.v9SelectedModes = v9Projection.selectedModeByFormation;
    row.v10SelectedModes = v10Projection.selectedModeByFormation;
    row.v9SelectedTrustWeights = ...
        v9Projection.selectedTrustWeightByFormation;
    row.v10SelectedTrustWeights = ...
        v10Projection.selectedTrustWeightByFormation;
    row.v10ObjectiveByFormationMode = ...
        v10Projection.objectiveByFormationMode;
    row.v10DynamicModeAllowedMask = ...
        v10Projection.dynamicModeAllowedMask;
    row.v10FormationRiskByMode = v10Projection. ...
        posteriorRiskObjectiveDetails.formationRiskByMode;
    row.v10ReferenceFormationRisk = ...
        v10Projection.referenceFormationRisk;
    row.v10SelectedFormationRisk = ...
        v10Projection.selectedFormationRisk;
    row.v10FormationRiskLimit = ...
        v10Projection.formationRiskLimit;
    row.v10UnguardedSelectedModes = ...
        v10Projection.projector.unguardedSelectedModeByFormation;
    row.v10UnguardedSelectedFormationRisk = ...
        v10Projection.projector.unguardedSelectedFormationRisk;
    row.v10UnguardedFormationRiskExcessPercent = 100 * ...
        v10Projection.projector. ...
            unguardedFormationRiskExcessFraction;
    row.v10MaximumUnguardedFormationRiskExcessPercent = 100 * ...
        v10Projection.projector. ...
            maximumUnguardedFormationRiskExcessFraction;
    row.v10FormationRiskGuardBinding = ...
        v10Projection.projector.formationRiskGuardBinding;
    row.v9GlobalRiskGapPercent = relativeDeltaPercent( ...
        v9Projection.selectedRisk, v9Projection.referenceRisk);
    row.v10GlobalRiskGapPercent = relativeDeltaPercent( ...
        v10Projection.selectedRisk, v10Projection.referenceRisk);
    row.v9PayloadSavingPercent = relativeSavingPercent( ...
        v9Projection.referencePayloadBytes, ...
        v9Projection.selectedPayloadBytes);
    row.v10PayloadSavingPercent = relativeSavingPercent( ...
        v10Projection.referencePayloadBytes, ...
        v10Projection.selectedPayloadBytes);
    row.changedFormationMask = ...
        row.v9SelectedModes ~= row.v10SelectedModes;
    row.v10ReferenceFormationMask = ...
        v10Projection.selectedReferenceFormationMask;
    row.edgeDifferenceCount = nnz(v9Adjacency ~= v10Adjacency);
    row.v9Seconds = v9Seconds;
    row.v10Seconds = v10Seconds;
    rows(seedIdx) = row;
    fprintf([ ...
        '%s seed %d: v9 modes %s; v10 modes %s; ', ...
        'unguarded %s; max guard excess %+.3f%%; ', ...
        'v10 saving %.3f%%; %.2fs + %.2fs\n'], ...
        presetName, seed, mat2str(row.v9SelectedModes), ...
        mat2str(row.v10SelectedModes), ...
        mat2str(row.v10UnguardedSelectedModes), ...
        row.v10MaximumUnguardedFormationRiskExcessPercent, ...
        row.v10PayloadSavingPercent, v9Seconds, v10Seconds);
end

gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'opened-state-posterior-risk-tail-safe-audit-v2';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.presetName = presetName;
audit.seeds = seeds;
audit.currentTime = currentTime;
audit.rows = rows;
audit.anyFormationDecisionChanged = ...
    any([rows.changedFormationMask]);
audit.allFormationRiskConstraintsPassed = all(arrayfun( ...
    @(row) all(row.v10SelectedFormationRisk <= ...
        row.v10FormationRiskLimit + 1e-12), rows));
audit.truthUsed = false;
audit.futureOutcomeUsed = false;
audit.openedDevelopmentEvidenceOnly = true;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'Both policies use current posteriors and current delivery ', ...
    'probabilities only. These states belong to already-opened ', ...
    'formation-FoV pairs, so the audit may guide redesign but cannot ', ...
    'support a fresh M24 or X36 tracking claim.'];

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'POSTERIOR_RISK_TAIL_SAFE_OPENED_STATE_AUDIT.md');
    writeReport(reportPath, audit);
    matPath = strrep(reportPath, '.md', '.mat');
    save('-mat7-binary', matPath, 'audit');
    audit.reportPath = reportPath;
    audit.matPath = matPath;
    fprintf('Posterior-risk opened-state audit: %s\n', reportPath);
end
end

function value = defaultDecisionTime(presetName)
switch presetName
    case 'm24-formation-fov'
        value = 70;
    case 'x36-formation-fov'
        value = 60;
    otherwise
        error('Posterior-risk audit preset is not registered.');
end
end

function bundle = loadBehaviorBundle( ...
        path, presetName, seed, currentTime, config)
if exist(path, 'file') ~= 2
    error('Missing opened behavior cache: %s', path);
end
loaded = load(path, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Opened behavior cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.presetName, presetName) || ...
        bundle.seed ~= seed || ...
        ~isequal(bundle.snapshotTimes, currentTime) || ...
        ~isequaln(bundle.configSnapshot, config) || ...
        numel(bundle.posteriorSnapshots) < currentTime || ...
        isempty(bundle.posteriorSnapshots{currentTime}) || ...
        numel(bundle.preDecisionTopologyHistoryByTime) < currentTime || ...
        isempty(bundle.preDecisionTopologyHistoryByTime{currentTime})
    error('Opened behavior cache provenance mismatch.');
end
end

function context = buildPolicyContext(inputs, bundle, currentTime)
sensorCount = inputs.config.numberOfSensors;
history = bundle.preDecisionTopologyHistoryByTime{currentTime};
previousAdjacency = inputs.graphData.staticAdjacency;
if isfield(history, 'selectedDirectedEdgeHistory') && ...
        ~isempty(history.selectedDirectedEdgeHistory)
    previousAdjacency = ...
        history.selectedDirectedEdgeHistory(:, :, end);
end
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{currentTime};
context.model = inputs.model;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacency = previousAdjacency;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, currentTime);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * sensorCount;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, currentTime);
end
end

function options = buildPolicyOptions(protocol)
options = struct( ...
    'protocol', protocol, ...
    'dominantWeight', ...
        protocol.adaptiveDominantJointTrustStabilityReferenceWeight, ...
    'residualWeight', ...
        protocol.adaptiveDominantJointTrustStabilityResidualWeight, ...
    'residualOrientation', ...
        protocol.adaptiveDominantResidualOrientation, ...
    'payloadMarginFraction', ...
        protocol.adaptiveDominantJointTrustStabilityPayloadMarginFraction, ...
    'candidateDominantWeightGrid', ...
        protocol.adaptiveDominantJointTrustStabilityCandidateWeightGrid, ...
    'minimumDynamicObjectiveAdvantage', ...
        protocol. ...
            adaptiveDominantJointTrustStabilityMinimumDynamicObjectiveAdvantage, ...
    'consensusAggregationMode', ...
        protocol.adaptiveDominantJointTrustStabilityAggregationMode, ...
    'consensusTailFraction', ...
        protocol.adaptiveDominantJointTrustStabilityTailFraction, ...
    'maximumConsensusProjectionFormationCount', ...
        protocol.adaptiveDominantJointTrustStabilityMaximumFormationCount, ...
    'consensusPayloadFallbackMode', ...
        protocol.adaptiveDominantJointTrustStabilityPayloadFallbackMode);
end

function assertAuditContracts(v9Details, v10Details, v10Projection)
protocol = getLabelSetSimulatorPolicyProtocol();
if ~strcmp(v9Details.contractVersion, protocol. ...
        adaptiveDominantJointTrustStabilityRoutingContractVersion) || ...
        ~strcmp(v10Details.contractVersion, ...
            ['adaptive-dominant-posterior-risk-formation-', ...
             'tail-v10-prototype']) || ...
        ~strcmp(v10Projection.objectiveMode, ...
            'posterior-bayes-risk') || ...
        ~v10Projection.formationRiskGuardEnabled || ...
        ~v10Projection.projector.formationRiskConstraintPassed || ...
        ~v10Projection.singleRoundExact || ...
        v9Details.truthUsed || v10Details.truthUsed || ...
        v10Projection.posteriorRiskObjectiveDetails.truthUsed
    error('Posterior-risk opened-state audit contract failed.');
end
end

function value = relativeDeltaPercent(candidate, reference)
value = 100 * (candidate - reference) / max(reference, eps);
end

function value = relativeSavingPercent(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'cachePath', '', ...
    'currentTime', NaN, ...
    'v9SelectedModes', [], ...
    'v10SelectedModes', [], ...
    'v9SelectedTrustWeights', [], ...
    'v10SelectedTrustWeights', [], ...
    'v10ObjectiveByFormationMode', [], ...
    'v10DynamicModeAllowedMask', false(0, 0), ...
    'v10FormationRiskByMode', [], ...
    'v10ReferenceFormationRisk', [], ...
    'v10SelectedFormationRisk', [], ...
    'v10FormationRiskLimit', [], ...
    'v10UnguardedSelectedModes', [], ...
    'v10UnguardedSelectedFormationRisk', [], ...
    'v10UnguardedFormationRiskExcessPercent', [], ...
    'v10MaximumUnguardedFormationRiskExcessPercent', NaN, ...
    'v10FormationRiskGuardBinding', false, ...
    'v9GlobalRiskGapPercent', NaN, ...
    'v10GlobalRiskGapPercent', NaN, ...
    'v9PayloadSavingPercent', NaN, ...
    'v10PayloadSavingPercent', NaN, ...
    'changedFormationMask', false(1, 0), ...
    'v10ReferenceFormationMask', false(1, 0), ...
    'edgeDifferenceCount', 0, ...
    'v9Seconds', NaN, ...
    'v10Seconds', NaN);
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open posterior-risk audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Posterior-risk tail-safe opened-state audit\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Preset: `%s`\n', audit.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(audit.seeds));
fprintf(fid, '- Decision time: `%d`\n', audit.currentTime);
fprintf(fid, '- Truth used by policies: `%d`\n', audit.truthUsed);
fprintf(fid, '- Development evidence only: `%d`\n\n', ...
    audit.openedDevelopmentEvidenceOnly);
fprintf(fid, [ ...
    '| Seed | v9 modes | v10 modes | Unguarded v10 | ', ...
    'Max guard excess | ', ...
    'v9 global risk gap | v10 global risk gap | ', ...
    'v9 byte saving | v10 byte saving | Runtime v9/v10 |\n']);
fprintf(fid, '|--:|:--|:--|:--|--:|--:|--:|--:|--:|--:|\n');
for row = audit.rows
    fprintf(fid, [ ...
        '| %d | `%s` | `%s` | `%s` | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | ', ...
        '%.3f%% | %.3f%% | %.2fs / %.2fs |\n'], ...
        row.seed, mat2str(row.v9SelectedModes), ...
        mat2str(row.v10SelectedModes), ...
        mat2str(row.v10UnguardedSelectedModes), ...
        row.v10MaximumUnguardedFormationRiskExcessPercent, ...
        row.v9GlobalRiskGapPercent, row.v10GlobalRiskGapPercent, ...
        row.v9PayloadSavingPercent, row.v10PayloadSavingPercent, ...
        row.v9Seconds, row.v10Seconds);
end
for row = audit.rows
    fprintf(fid, '\n## Seed %d formation detail\n\n', row.seed);
    fprintf(fid, [ ...
        'Columns are reference, dynamic trust 0.30, 0.50, and 0.70. ', ...
        'Positive objective means lower posterior risk than reference.\n\n']);
    writeMatrix(fid, 'Posterior-risk objective', ...
        row.v10ObjectiveByFormationMode, '%.6f');
    writeMatrix(fid, 'Posterior risk', ...
        row.v10FormationRiskByMode, '%.6f');
    writeMatrix(fid, 'Allowed mode mask', ...
        double(row.v10DynamicModeAllowedMask), '%.0f');
    fprintf(fid, [ ...
        '- Reference formation risk: `%s`\n', ...
        '- Selected formation risk: `%s`\n', ...
        '- Formation risk limit: `%s`\n', ...
        '- Unguarded v10 modes: `%s`\n', ...
        '- Unguarded formation risk: `%s`\n', ...
        '- Unguarded formation excess: `%s%%`\n', ...
        '- Formation guard binding: `%d`\n', ...
        '- v10 reference formations: `%s`\n', ...
        '- Directed-edge differences from v9: `%d`\n'], ...
        mat2str(row.v10ReferenceFormationRisk, 6), ...
        mat2str(row.v10SelectedFormationRisk, 6), ...
        mat2str(row.v10FormationRiskLimit, 6), ...
        mat2str(row.v10UnguardedSelectedModes), ...
        mat2str(row.v10UnguardedSelectedFormationRisk, 6), ...
        mat2str(row.v10UnguardedFormationRiskExcessPercent, 6), ...
        row.v10FormationRiskGuardBinding, ...
        mat2str(find(row.v10ReferenceFormationMask)), ...
        row.edgeDifferenceCount);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function writeMatrix(fid, title, values, format)
fprintf(fid, '**%s**\n\n', title);
fprintf(fid, '| Formation | Ref | 0.30 | 0.50 | 0.70 |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|\n');
for rowIdx = 1:size(values, 1)
    fprintf(fid, '| %d ', rowIdx);
    for columnIdx = 1:size(values, 2)
        fprintf(fid, ['| ', format, ' '], values(rowIdx, columnIdx));
    end
    fprintf(fid, '|\n');
end
fprintf(fid, '\n');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
