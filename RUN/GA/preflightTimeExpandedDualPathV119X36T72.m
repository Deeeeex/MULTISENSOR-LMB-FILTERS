function report = preflightTimeExpandedDualPathV119X36T72()
% PREFLIGHTTIMEEXPANDEDDUALPATHV119X36T72 Real X36 route gate.

protocol = getTimeExpandedDualPathV119Protocol();
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
inputs = generateDynamicTopologyScenarioInputs(entry.presetName, entry.seed);
loaded = load(protocol.v113ScreenPath, 'screen');
referenceScreen = loaded.screen;
cache = load(referenceScreen.cachePath, 'behaviorBundle');
bundle = cache.behaviorBundle;
currentTime = 72;
history = bundle.preDecisionTopologyHistoryByTime{currentTime};
previous = convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
    history.selectedDirectedEdgeHistory);
context = struct( ...
    'localPosteriorBySensor', {bundle.posteriorSnapshots{currentTime}}, ...
    'model', inputs.model, ...
    'sensorTrajectories', {inputs.sensorTrajectories}, ...
    'commConfig', inputs.commConfig, ...
    'triggerConfig', buildMixtureAwareKlaReferenceConfig(), ...
    'currentTime', currentTime, ...
    'previousAdjacencyHistory', previous, ...
    'previousAdjacencyHistoryCount', size(previous, 3), ...
    'previousAdjacencyHistoryTimes', history.times, ...
    'previousAdjacencyHistoryConvention', ...
        'receiver-row-sender-column-directed-oldest-to-newest', ...
    'previousAdjacencyHistorySource', ...
        'opened-reference-continuation-cache-v1', ...
    'previousAdjacency', previous(:, :, end), ...
    'baseAdjacency', inputs.graphData.staticAdjacency, ...
    'physicalAdjacency', logical( ...
        inputs.graphData.physicalAdjacency(:, :, currentTime)), ...
    'edgeBudget', inputs.config.edgeBudget, ...
    'directedMessageBudget', 2 * inputs.config.numberOfSensors, ...
    'positions', inputs.graphData.positions(:, :, currentTime), ...
    'edgeScores', [], ...
    'localInnovationHistory', [], ...
    'localAssociationConfidenceHistory', [], ...
    'localNisNormHistory', [], ...
    'localNisDeviationHistory', [], ...
    'localUpdateHistoryTimes', []);
context.triggerConfig.missingLabelFusionMode = protocol.receiverMode;
context = buildObservableTopologyPolicyContext(context);
bank = buildTrackingAlignedX36ScheduleActionBank( ...
    context, inputs.config.sensorGroupIds, struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', protocol.bankVariant, ...
        'horizonSteps', protocol.horizonSteps));
if bank.actionCount ~= 11 || ...
        ~strcmp(bank.bankVariant, protocol.bankVariant)
    error('TimeExpandedDualPathV119:BankDrift', ...
        'The real V119 action bank is malformed.');
end

sequences = ones(bank.actionCount, protocol.horizonSteps);
sequences(2, :) = 2;
sequences(3, :) = 3;
for actionIdx = 4:bank.actionCount
    sequences(actionIdx, :) = 3;
    sequences(actionIdx, protocol.pulsePageIndex) = actionIdx;
end
sensorPass = false(bank.actionCount, protocol.horizonSteps);
formationPass = sensorPass;
for armIdx = 1:bank.actionCount
    executed = false(inputs.config.numberOfSensors, ...
        inputs.config.numberOfSensors, protocol.horizonSteps);
    for pageIdx = 1:protocol.horizonSteps
        executed(:, :, pageIdx) = ...
            bank.actionAdjacency(:, :, sequences(armIdx, pageIdx));
    end
    [sensorPass(armIdx, :), formationPass(armIdx, :)] = ...
        rollingB3(previous, executed, inputs.config.sensorGroupIds);
end
if ~all(sensorPass(:)) || ~all(formationPass(:))
    error('TimeExpandedDualPathV119:RollingB3Failed', ...
        'A real V119 sequence failed rolling B3.');
end
report = struct( ...
    'contractVersion', 'time-expanded-dual-path-v119-preflight-v1', ...
    'actionNames', {bank.actionNames}, ...
    'messageCounts', squeeze(sum(sum(bank.actionAdjacency, 1), 2))', ...
    'sensorB3Passed', all(sensorPass, 2)', ...
    'formationB3Passed', all(formationPass, 2)', ...
    'allPhysical', all(arrayfun(@(idx) ~any(reshape( ...
        bank.actionAdjacency(:, :, idx) & ...
        ~context.physicalAdjacency, 1, [])), 1:bank.actionCount)), ...
    'passed', true);
fprintf('V119 real X36 preflight passed: %d actions, %d sequences.\n', ...
    bank.actionCount, size(sequences, 1));
end

function [sensorPass, formationPass] = rollingB3(history, executed, groupIds)
sensorPass = false(1, size(executed, 3));
formationPass = sensorPass;
for pageIdx = 1:size(executed, 3)
    pages = cat(3, history, executed(:, :, pageIdx));
    window = any(pages(:, :, max(1, end - 2):end), 3);
    sensorPass(pageIdx) = isStronglyConnected(window);
    formationPass(pageIdx) = isStronglyConnected( ...
        collapseToFormations(window, groupIds));
    history(:, :, end + 1) = executed(:, :, pageIdx); %#ok<AGROW>
    if size(history, 3) > 2
        history = history(:, :, end-1:end);
    end
end
end

function collapsed = collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
collapsed = false(numel(groups));
for receiverIdx = 1:numel(groups)
    receivers = reshape(find(groupIds == groups(receiverIdx)), 1, []);
    for sourceIdx = 1:numel(groups)
        senders = reshape(find(groupIds == groups(sourceIdx)), 1, []);
        collapsed(receiverIdx, sourceIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
end

function passed = isStronglyConnected(adjacency)
reachability = logical(adjacency) | eye(size(adjacency, 1)) > 0;
for idx = 1:size(adjacency, 1)
    reachability = reachability | bsxfun(@and, ...
        reachability(:, idx), reachability(idx, :));
end
passed = all(reachability(:));
end
