function [reportPath, result] = runZipperMergeSceneV276Preflight(options)
% RUNZIPPERMERGESCENEV276PREFLIGHT Freeze non-radial scene geometry.

if nargin < 1 || isempty(options)
    options = struct();
end
presetNames = { ...
    'm24-formation-fov-zipper-merge', ...
    'x36-formation-fov-zipper-merge'};
seed = getField(options, 'seed', 1301);
writeReport = getField(options, 'writeReport', true);
if ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~islogical(writeReport) || ~isscalar(writeReport)
    error('ZipperMergeSceneV276:InvalidOptions', ...
        'V276 requires one integer seed and one logical report flag.');
end

records = repmat(emptyRecord(), 1, numel(presetNames));
for presetIdx = 1:numel(presetNames)
    records(presetIdx) = inspectPreset(presetNames{presetIdx}, seed);
end

startTimes = [records.failureStartTime];
stopTimes = [records.failureStopTime];
feasibleFractions = [records.initialTreeFeasibleFraction];
crossScaleMatched = max(startTimes) - min(startTimes) <= 2 && ...
    max(stopTimes) - min(stopTimes) <= 2 && ...
    max(feasibleFractions) - min(feasibleFractions) <= 0.02;
result = struct();
result.contractVersion = 'zipper-merge-scene-v276-preflight-result-v1';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.seed = seed;
result.records = records;
result.crossScaleTimingMatched = crossScaleMatched;
result.geometryGatePassed = all([records.gatePassed]) && crossScaleMatched;
result.trackingOutcomeAuthorized = false;
result.nextDecision = ternary(result.geometryGatePassed, ...
    'freeze-scene-before-any-tracking-and-use-after-method-selection', ...
    'revise-geometry-before-any-tracking');
result.evidenceBoundary = [ ...
    'V276 uses generated sensor/target geometry and physical ', ...
    'reachability only. It does not run the LMB filter and reads no ', ...
    'posterior, realized delivery, tracking outcome or method score. ', ...
    'Passing this gate qualifies a non-radial scene for a later paired ', ...
    'experiment; it does not establish method benefit or generalization.'];

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v276', ...
    sprintf('zipper_merge_scene_seed%d', seed)));
if ~isAbsolutePathLocal(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
reportPath = fullfile(outputRoot, ...
    'ZIPPER_MERGE_SCENE_V276_PREFLIGHT.md');
matPath = strrep(reportPath, '.md', '.mat');
result.reportPath = reportPath;
result.matPath = matPath;
if writeReport
    save('-mat7-binary', matPath, 'result');
    writeReportFile(reportPath, result);
end

for record = records
    fprintf([ ...
        'V276 %s: valid=%d connected=%d tree=%.3f failure=%d..%d ', ...
        'planned=%s actual-in-failure=%.3f gate=%d\n'], ...
        record.presetName, record.sceneValid, ...
        record.formationConnectedAllTimes, ...
        record.initialTreeFeasibleFraction, ...
        record.failureStartTime, record.failureStopTime, ...
        mat2str(record.plannedHandoverTimes), ...
        record.actualOwnerChangesDuringFailureFraction, ...
        record.gatePassed);
end
fprintf('ZIPPER_MERGE_SCENE_V276_GEOMETRY_GATE_PASSED=%d\n', ...
    result.geometryGatePassed);
end

function record = inspectPreset(presetName, seed)
rng(seed, 'twister');
config = buildDynamicTopologyScenarioConfig(presetName);
[sensors, ~] = generateMultiFormationTrajectories(config);
[targets, ~] = generateCorridorTargetTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensors);
validation = validateDynamicTopologyScenario( ...
    config, sensors, targets, graph, struct('throwOnInvalid', false));

groupIds = reshape(config.sensorGroupIds, 1, []);
initialTree = formationAdjacency(graph.staticAdjacency, groupIds);
timeCount = config.simulationLength;
formationConnected = false(1, timeCount);
treeFeasible = false(1, timeCount);
exactRoutePhysical = false(1, timeCount);
alternativeEdgeCount = zeros(1, timeCount);
for currentTime = 1:timeCount
    physical = logical(graph.physicalAdjacency(:, :, currentTime));
    currentFormation = formationAdjacency(physical, groupIds);
    formationConnected(currentTime) = isConnected(currentFormation);
    treeFeasible(currentTime) = ...
        ~any(initialTree(:) & ~currentFormation(:));
    exactRoutePhysical(currentTime) = ...
        ~any(logical(graph.staticAdjacency(:)) & ~physical(:));
    alternativeEdgeCount(currentTime) = nnz(triu( ...
        currentFormation & ~initialTree, 1));
end
failed = ~treeFeasible;
[starts, stops] = failureEpisodes(failed);
plannedHandoverTimes = round(1 + (timeCount - 1) * ...
    config.targetRouteHandoverFractions);
plannedHandoverInsideFailure = ...
    all(failed(plannedHandoverTimes));

owner = validation.difficulty.ownerByTarget;
ownerChanges = owner(:, 2:end) ~= owner(:, 1:end-1);
[~, changeColumns] = find(ownerChanges);
ownerChangeTimes = changeColumns + 1;
if isempty(ownerChangeTimes)
    ownerChangesDuringFailureFraction = 0;
else
    ownerChangesDuringFailureFraction = ...
        mean(failed(ownerChangeTimes));
end
minimumAlternativeEdges = min(alternativeEdgeCount(failed));

record = emptyRecord();
record.presetName = presetName;
record.sceneStyle = config.sceneStyle;
record.seed = seed;
record.nodeCount = config.numberOfSensors;
record.formationCount = config.formationCount;
record.targetCount = config.numberOfTargets;
record.sceneValid = validation.isValid;
record.sceneHardFailures = validation.hardFailures;
record.formationConnectedAllTimes = all(formationConnected);
record.initialTreeFeasibleFraction = mean(treeFeasible);
record.exactStaticRoutePhysicalFraction = mean(exactRoutePhysical);
record.failureEpisodeCount = numel(starts);
record.failureStartTime = starts(1);
record.failureStopTime = stops(1);
record.minimumAlternativeFormationEdgesDuringFailure = ...
    minimumAlternativeEdges;
record.plannedHandoverTimes = unique(plannedHandoverTimes);
record.plannedHandoverInsideFailure = ...
    plannedHandoverInsideFailure;
record.actualOwnerChangeCount = numel(ownerChangeTimes);
record.actualOwnerChangesDuringFailureFraction = ...
    ownerChangesDuringFailureFraction;
record.focusHandoverCount = validation.difficulty.focusHandovers;
record.blackoutFraction = validation.difficulty.blackoutFraction;
record.focusBlackoutFraction = ...
    validation.difficulty.focusBlackoutFraction;
record.minimumSensorTargetSeparation = ...
    validation.minimumSensorTargetSeparation;
record.maximumSensorSpeed = validation.maxSensorSpeed;
record.maximumSensorAcceleration = validation.maxSensorAcceleration;
record.maximumTargetSpeed = validation.maxTargetSpeed;
record.maximumTargetAcceleration = validation.maxTargetAcceleration;
record.gatePassed = validation.isValid && ...
    all(formationConnected) && numel(starts) == 1 && ...
    starts(1) >= 45 && starts(1) <= 65 && ...
    stops(1) >= 95 && stops(1) <= 120 && ...
    mean(treeFeasible) >= 0.55 && mean(treeFeasible) <= 0.75 && ...
    minimumAlternativeEdges >= 1 && ...
    plannedHandoverInsideFailure && ...
    ownerChangesDuringFailureFraction >= 0.50;
end

function adjacency = formationAdjacency(sensorAdjacency, groupIds)
groups = unique(groupIds, 'stable');
adjacency = false(numel(groups));
for left = 1:numel(groups)-1
    for right = left+1:numel(groups)
        block = logical(sensorAdjacency( ...
            groupIds == groups(left), groupIds == groups(right)));
        adjacency(left, right) = any(block(:));
        adjacency(right, left) = adjacency(left, right);
    end
end
end

function connected = isConnected(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node), continue; end
    visited(node) = true;
    frontier = [frontier, find(adjacency(node, :) & ~visited)]; %#ok<AGROW>
end
connected = all(visited);
end

function [starts, stops] = failureEpisodes(failed)
starts = find(failed & [true, ~failed(1:end-1)]);
stops = find(failed & [~failed(2:end), true]);
end

function writeReportFile(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write V276 report: %s.', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V276 zipper-merge scene preflight\n\n');
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Geometry seed: `%d`\n', result.seed);
fprintf(fid, '- Geometry gate passed: `%d`\n', ...
    result.geometryGatePassed);
fprintf(fid, '- Cross-scale timing matched: `%d`\n', ...
    result.crossScaleTimingMatched);
fprintf(fid, '- Tracking outcome authorized: `0`\n');
fprintf(fid, '- Next decision: `%s`\n\n', result.nextDecision);
fprintf(fid, ['| Scene | Valid | Physical connected | Fixed-tree feasible | ', ...
    'Failure episode | Alternative edges | Planned handoffs | ', ...
    'Actual owner changes in failure |\n']);
fprintf(fid, '|:--|:--:|:--:|--:|:--:|--:|:--:|--:|\n');
for record = result.records
    fprintf(fid, '| %s | %d | %d | %.3f | %d--%d | %d | %s | %.3f |\n', ...
        record.presetName, record.sceneValid, ...
        record.formationConnectedAllTimes, ...
        record.initialTreeFeasibleFraction, ...
        record.failureStartTime, record.failureStopTime, ...
        record.minimumAlternativeFormationEdgesDuringFailure, ...
        mat2str(record.plannedHandoverTimes), ...
        record.actualOwnerChangesDuringFailureFraction);
end
fprintf(fid, '\n## Geometry and observation envelope\n\n');
fprintf(fid, ['| Scene | Nodes / targets | Min sensor-target distance | ', ...
    'Sensor speed / accel | Target speed / accel | ', ...
    'Blackout / focus blackout | Focus handovers |\n']);
fprintf(fid, '|:--|:--:|--:|:--|:--|:--|--:|\n');
for record = result.records
    fprintf(fid, ...
        '| %s | %d / %d | %.3f | %.3f / %.3f | %.3f / %.3f | %.3f / %.3f | %d |\n', ...
        record.presetName, record.nodeCount, record.targetCount, ...
        record.minimumSensorTargetSeparation, ...
        record.maximumSensorSpeed, record.maximumSensorAcceleration, ...
        record.maximumTargetSpeed, record.maximumTargetAcceleration, ...
        record.blackoutFraction, record.focusBlackoutFraction, ...
        record.focusHandoverCount);
end
fprintf(fid, '\n## Role in the scenario suite\n\n');
fprintf(fid, ['Zipper merge is the non-radial positive stress case: two ', ...
    'parallel platoons enter one shared bottleneck, change longitudinal ', ...
    'neighbours, and split again. The physical formation graph stays ', ...
    'connected while the initial tree fails during the same interval as ', ...
    'the registered target handoffs. Parallel convoy and linear relay ', ...
    'remain useful negative controls because their fixed routes stay ', ...
    'available throughout; formation braid remains the development case.\n']);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function record = emptyRecord()
record = struct('presetName', '', 'sceneStyle', '', 'seed', NaN, ...
    'nodeCount', NaN, 'formationCount', NaN, 'targetCount', NaN, ...
    'sceneValid', false, 'sceneHardFailures', {{}}, ...
    'formationConnectedAllTimes', false, ...
    'initialTreeFeasibleFraction', NaN, ...
    'exactStaticRoutePhysicalFraction', NaN, ...
    'failureEpisodeCount', NaN, 'failureStartTime', NaN, ...
    'failureStopTime', NaN, ...
    'minimumAlternativeFormationEdgesDuringFailure', NaN, ...
    'plannedHandoverTimes', zeros(1, 0), ...
    'plannedHandoverInsideFailure', false, ...
    'actualOwnerChangeCount', NaN, ...
    'actualOwnerChangesDuringFailureFraction', NaN, ...
    'focusHandoverCount', NaN, 'blackoutFraction', NaN, ...
    'focusBlackoutFraction', NaN, ...
    'minimumSensorTargetSeparation', NaN, ...
    'maximumSensorSpeed', NaN, 'maximumSensorAcceleration', NaN, ...
    'maximumTargetSpeed', NaN, 'maximumTargetAcceleration', NaN, ...
    'gatePassed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function passed = isAbsolutePathLocal(pathValue)
pathValue = char(pathValue);
passed = ~isempty(pathValue) && pathValue(1) == filesep;
end

function value = ternary(condition, trueValue, falseValue)
if condition
    value = trueValue;
else
    value = falseValue;
end
end
