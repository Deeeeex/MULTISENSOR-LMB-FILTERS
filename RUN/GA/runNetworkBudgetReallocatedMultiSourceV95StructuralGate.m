function [reportPath, result] = ...
    runNetworkBudgetReallocatedMultiSourceV95StructuralGate(options)
% RUNNETWORKBUDGETREALLOCATEDMULTISOURCEV95STRUCTURALGATE No truth scoring.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNetworkBudgetReallocatedMultiSourceV95Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NetworkBudgetV95:DirtySource', ...
        'V95 structural gating requires clean frozen source.');
end
outputRoot = getField(options, ...
    'outputRoot', protocol.structuralOutputRoot);
records = repmat(emptyRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        entry.presetName, entry.seed, entry.currentTime, struct( ...
            'cacheRoot', entry.cacheRoot, ...
            'expectedMissingLabelFusionMode', ...
                protocol.receiverMode));
    bank = buildNetworkBudgetReallocatedMultiSourceV95ActionBank( ...
        state.context, struct( ...
            'requiredTokenCount', entry.requiredTokenCount, ...
            'requiredTargetFormationCount', ...
                entry.requiredTargetFormationCount, ...
            'requiredSourceFormationCount', ...
                entry.requiredSourceFormationCount, ...
            'horizonSteps', entry.horizonSteps));
    record = emptyRecord();
    record.scaleName = entry.scaleName;
    record.presetName = entry.presetName;
    record.seed = entry.seed;
    record.currentTime = entry.currentTime;
    record.nodeCount = bank.nodeCount;
    record.formationCount = bank.formationCount;
    record.formationGraphDiameter = bank.formationGraphDiameter;
    record.horizonSteps = bank.horizonSteps;
    record.candidateTokenCount = bank.projection.candidateCount;
    record.connectivityCutCount = ...
        bank.projection.connectivityCutCount;
    record.requiredTokenCount = entry.requiredTokenCount;
    record.selectedTokenCount = bank.selectedTokenCount;
    record.targetFormationCoverage = ...
        bank.targetFormationCoverageCount;
    record.sourceFormationCoverage = ...
        bank.sourceFormationCoverageCount;
    record.selectedTargetFormationIds = ...
        bank.selectedTargetFormationIds;
    record.selectedSourceFormationIds = ...
        bank.selectedSourceFormationIds;
    record.aggregateTargetNoveltyFraction = ...
        bank.projection.aggregateTargetNoveltyFraction;
    record.aggregateDonorUniqueFraction = ...
        bank.projection.aggregateDonorUniqueFraction;
    record.aggregateNetUtilityFraction = ...
        bank.projection.aggregateNetUtilityFraction;
    record.referenceMessageCount = bank.actionMessageCounts(1);
    record.donorOnlyMessageCount = bank.actionMessageCounts(2);
    record.candidateMessageCount = bank.actionMessageCounts(3);
    record.senderMessageParityPassed = ...
        bank.senderMessageParityPassed;
    record.networkMessageParityPassed = ...
        bank.networkMessageParityPassed;
    record.candidateInstantSensorStrong = ...
        bank.candidateInstantSensorStrong;
    record.candidateInstantFormationStrong = ...
        bank.candidateInstantFormationStrong;
    record.donorOnlyRollingB3Passed = all( ...
        bank.actionRollingB3SensorPass(2, :)) && all( ...
        bank.actionRollingB3FormationPass(2, :));
    record.candidateRollingB3Passed = all( ...
        bank.actionRollingB3SensorPass(3, :)) && all( ...
        bank.actionRollingB3FormationPass(3, :));
    record.fixedRouteRollingB3Passed = all( ...
        bank.fixedCandidateRollingB3SensorPass) && all( ...
        bank.fixedCandidateRollingB3FormationPass);
    record.structuralGatePassed = bank.structuralGatePassed && ...
        bank.formationGraphDiameter == ...
            entry.expectedFormationDiameter && ...
        bank.horizonSteps == entry.horizonSteps;
    record.failureReason = bank.projection.failureReason;
    records(caseIdx) = record;
    fprintf([ ...
        'V95 structural %s: selected %d/%d, target/source ', ...
        '%d/%d, sender parity %d, B3 %d, gate %d\n'], ...
        record.scaleName, record.selectedTokenCount, ...
        record.requiredTokenCount, record.targetFormationCoverage, ...
        record.sourceFormationCoverage, ...
        record.senderMessageParityPassed, ...
        record.candidateRollingB3Passed, ...
        record.structuralGatePassed);
end

result = struct();
result.contractVersion = ...
    'network-budget-reallocated-multi-source-v95-structural-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.records = records;
result.crossScaleStructuralGatePassed = ...
    all([records.structuralGatePassed]);
result.matchedStaticHeadroomAuthorized = ...
    result.crossScaleStructuralGatePassed;
result.trackingOutcomeRead = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_STRUCTURAL_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_STRUCTURAL_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V95 structural result: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkBudgetV95:WriteFailed', ...
        'Could not create the V95 structural report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V95 sender-budget reallocation structural gate\n\n');
fprintf(fid, ['The deployable arm moves each 0.05 residual token to a ', ...
    'new receiver without changing its sender. Therefore its per-sender ', ...
    'message count and network message count must match the static ', ...
    'physical-tree baseline exactly. No tracking truth is read here.\n\n']);
fprintf(fid, ['| Scale | Candidates | Selected / required | Target forms | ', ...
    'Source forms | Cuts | Messages B/O/C | Sender parity | Instant strong | ', ...
    'Candidate B3 | Fixed B3 | Gate |\n']);
fprintf(fid, ['|:--|--:|:--|--:|--:|--:|:--|:--:|:--:|:--:|', ...
    ':--:|:--:|\n']);
for record = result.records
    fprintf(fid, ['| %s | %d | %d / %d | %d | %d | %d | ', ...
        '%d / %d / %d | ', ...
        '%d | %d | %d | %d | %d |\n'], ...
        record.scaleName, record.candidateTokenCount, ...
        record.selectedTokenCount, record.requiredTokenCount, ...
        record.targetFormationCoverage, ...
        record.sourceFormationCoverage, ...
        record.connectivityCutCount, ...
        record.referenceMessageCount, ...
        record.donorOnlyMessageCount, ...
        record.candidateMessageCount, ...
        record.senderMessageParityPassed, ...
        record.candidateInstantSensorStrong && ...
            record.candidateInstantFormationStrong, ...
        record.candidateRollingB3Passed, ...
        record.fixedRouteRollingB3Passed, ...
        record.structuralGatePassed);
end
fprintf(fid, '\n- Cross-scale structural gate: `%d`\n', ...
    result.crossScaleStructuralGatePassed);
fprintf(fid, '- Matched-static headroom authorized: `%d`\n', ...
    result.matchedStaticHeadroomAuthorized);
fprintf(fid, '- Tracking outcome read: `0`\n\n');
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function record = emptyRecord()
record = struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'nodeCount', NaN, ...
    'formationCount', NaN, 'formationGraphDiameter', NaN, ...
    'horizonSteps', NaN, 'candidateTokenCount', 0, ...
    'connectivityCutCount', 0, ...
    'requiredTokenCount', 0, 'selectedTokenCount', 0, ...
    'targetFormationCoverage', 0, 'sourceFormationCoverage', 0, ...
    'selectedTargetFormationIds', zeros(1, 0), ...
    'selectedSourceFormationIds', zeros(1, 0), ...
    'aggregateTargetNoveltyFraction', 0, ...
    'aggregateDonorUniqueFraction', 0, ...
    'aggregateNetUtilityFraction', 0, ...
    'referenceMessageCount', 0, 'donorOnlyMessageCount', 0, ...
    'candidateMessageCount', 0, ...
    'senderMessageParityPassed', false, ...
    'networkMessageParityPassed', false, ...
    'candidateInstantSensorStrong', false, ...
    'candidateInstantFormationStrong', false, ...
    'donorOnlyRollingB3Passed', false, ...
    'candidateRollingB3Passed', false, ...
    'fixedRouteRollingB3Passed', false, ...
    'structuralGatePassed', false, 'failureReason', '');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
