function [reportPath, result] = ...
        analyzeBeneficiaryCoordinatorOfferRanksV234(options)
% ANALYZEBENEFICIARYCOORDINATOROFFERRANKSV234 Screen causal separability.
%
% This uses the first registered receiver as the already-frozen V228
% coordinator and only its current fused posterior plus V233 donor records.
% Teacher labels are used after ranking solely to measure proposal rank.

if nargin < 1 || isempty(options)
    options = struct();
end
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices)
    error('BeneficiaryCoordinatorOfferV234:InvalidRequest', ...
        'A V220 bank and unique teacher rows are required.');
end

loaded = load(candidateBankPath, 'result');
bank = loaded.result;
if ~isstruct(bank) || ~isscalar(bank) || ...
        ~isfield(bank, 'sourceScreenPath') || ...
        ~isfield(bank, 'records') || ...
        ~isfield(bank, 'beneficiaryDetails') || ...
        ~isfield(bank, 'donorFormationId') || ...
        ~isfield(bank, 'admissionNetSavingBytes')
    error('BeneficiaryCoordinatorOfferV234:BankContract', ...
        'The causal V220 bank is malformed.');
end
if isempty(recordIndices)
    selectedRows = 1:numel(bank.records);
else
    [present, selectedRows] = ismember( ...
        recordIndices, [bank.records.recordIndex]);
    if ~all(present)
        error('BeneficiaryCoordinatorOfferV234:UnknownRecord', ...
            'A requested teacher row is absent from the bank.');
    end
end
teachers = bank.records(selectedRows);

screenLoaded = load(bank.sourceScreenPath, 'screen');
screen = screenLoaded.screen;
timeIndex = find(screen.returnTimes == bank.currentTime, 1);
donorName = sprintf( ...
    'v214-withhold-full-posterior-f%d-one-page', ...
    bank.donorFormationId);
donorIndex = find(strcmp({screen.records.actionName}, donorName));
if isempty(timeIndex) || numel(donorIndex) ~= 1 || ...
        ~screen.capturePosteriorSnapshotsEnabled || ...
        ~screen.captureFusedPosteriorSnapshotsEnabled
    error('BeneficiaryCoordinatorOfferV234:SnapshotContract', ...
        'The same-state donor local/fused snapshots are unavailable.');
end
donor = screen.outcomes(donorIndex);
localPosteriors = donor.localPosteriorSnapshotsByTime{timeIndex};
fusedPosteriors = donor.fusedPosteriorSnapshotsByTime{timeIndex};
groupIds = reshape(screen.sensorGroupIds, 1, []);
model = struct('xDimension', inferStateDimension(localPosteriors));
positionCutoff = loadPositionCutoff(screen.cachePath);

audits = repmat(emptyAudit(), 1, numel(teachers));
for auditIndex = 1:numel(teachers)
    teacher = teachers(auditIndex);
    receiverIds = reshape(teacher.candidate.receiverIds, 1, []);
    coordinatorId = receiverIds(1);
    sourceIds = donorSourceIds( ...
        bank, teacher.beneficiaryFormationId, ...
        receiverIds, groupIds);
    offers = repmat(emptyOffer(), 1, 0);
    for sourceId = sourceIds
        sourceOffers = buildCacheFreeDonorOfferRecordsV234( ...
            localPosteriors{sourceId}, model, sourceId, struct());
        offers = [offers, sourceOffers]; %#ok<AGROW>
    end
    featureResult = ...
        buildBeneficiaryCoordinatorOfferFeaturesV234( ...
            offers, fusedPosteriors{coordinatorId}, model, struct( ...
                'positionCutoff', positionCutoff, ...
                'receiverCount', numel(receiverIds), ...
                'admissionCreditBytes', ...
                    bank.admissionNetSavingBytes));
    teacherLabel = reshape(teacher.label, 2, 1);
    ranks = zeros(1, size(featureResult.modeScores, 2) + 1);
    for modeIndex = 1:size(featureResult.modeScores, 2)
        ranks(modeIndex) = teacherRank(offers, ...
            featureResult.modeScores(:, modeIndex), ...
            teacher.sourceId, teacherLabel);
    end
    compositeScores = max(featureResult.modeScores, [], 2);
    ranks(end) = teacherRank(offers, compositeScores, ...
        teacher.sourceId, teacherLabel);
    audits(auditIndex) = struct( ...
        'recordIndex', teacher.recordIndex, ...
        'beneficiaryFormationId', teacher.beneficiaryFormationId, ...
        'coordinatorSensorId', coordinatorId, ...
        'sourceId', teacher.sourceId, ...
        'label', teacherLabel, ...
        'sourceSensorIds', sourceIds, ...
        'offerCount', numel(offers), ...
        'modeNames', {featureResult.modeNames}, ...
        'teacherRanksByMode', ranks(1:end - 1), ...
        'teacherCompositeRank', ranks(end), ...
        'topThreeModeRecall', any(ranks(1:end - 1) <= 3), ...
        'topSixModeRecall', any(ranks(1:end - 1) <= 6), ...
        'featureResult', featureResult);
end

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v234', ...
    'beneficiary_coordinator_offer_ranks', ...
    sprintf('%s_seed%d_t%d_donor_f%d', ...
        strrep(bank.presetName, '-', '_'), bank.seed, ...
        bank.currentTime, bank.donorFormationId))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
result = struct();
result.contractVersion = ...
    'beneficiary-coordinator-offer-ranks-v234-v1';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.candidateBankPath = candidateBankPath;
result.presetName = bank.presetName;
result.seed = bank.seed;
result.currentTime = bank.currentTime;
result.donorFormationId = bank.donorFormationId;
result.teacherAudits = audits;
result.teacherLabelCount = numel(audits);
result.topThreeModeRecallCount = nnz([audits.topThreeModeRecall]);
result.topSixModeRecallCount = nnz([audits.topSixModeRecall]);
result.topThreeModeRecall = result.topThreeModeRecallCount / ...
    max(result.teacherLabelCount, 1);
result.topSixModeRecall = result.topSixModeRecallCount / ...
    max(result.teacherLabelCount, 1);
result.screenPassed = result.topSixModeRecallCount == ...
    result.teacherLabelCount;
result.coordinatorRule = 'first-registered-beneficiary-receiver';
result.teacherLabelsUsedOnlyForRankAudit = true;
result.fullSourceMixtureUsedForRanking = false;
result.etaUsedForRanking = false;
result.truthUsedForRanking = false;
result.futureInformationUsedForRanking = false;
result.numericLabelIdentifiersUsedAsFeatures = false;
result.onlineCoordinatorImplemented = false;
result.valueModelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V234 checks whether one frozen coordinator can distinguish the ', ...
    'opened teacher source-label pairs from compact V233 records. It ', ...
    'does not select a payload online, use exact eta, run tracking, ', ...
    'validate a learned model, or establish generalization.'];
matPath = fullfile(outputRoot, ...
    'BENEFICIARY_COORDINATOR_OFFER_RANKS_V234.mat');
reportPath = fullfile(outputRoot, ...
    'BENEFICIARY_COORDINATOR_OFFER_RANKS_V234.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V234 beneficiary coordinator ranks: %s\n', reportPath);
end

function ids = donorSourceIds(bank, formationId, receiverIds, groupIds)
match = find([bank.beneficiaryDetails.formationId] == formationId, 1);
if isempty(match)
    error('BeneficiaryCoordinatorOfferV234:SourceSet', ...
        'The beneficiary participant set is unavailable.');
end
participants = reshape( ...
    bank.beneficiaryDetails(match).synopsisSensorIds, 1, []);
remote = setdiff(participants, receiverIds, 'stable');
ids = intersect(remote, find(groupIds == bank.donorFormationId), 'stable');
if isempty(ids)
    error('BeneficiaryCoordinatorOfferV234:SourceSet', ...
        'No common donor source is available.');
end
end

function rank = teacherRank(offers, scores, sourceId, label)
payload = reshape([offers.payloadBytesPerReceiver], [], 1);
labels = reshape([offers.label], 2, [])';
keys = [-reshape(scores, [], 1), payload, labels];
[~, order] = sortrows(keys, 1:size(keys, 2));
orderedSourceIds = [offers(order).sourceSensorId];
orderedLabels = reshape([offers(order).label], 2, []);
rank = find(orderedSourceIds == sourceId & ...
    all(orderedLabels == label, 1), 1);
if isempty(rank)
    rank = inf;
end
end

function value = loadPositionCutoff(cachePath)
loaded = load(cachePath, 'behaviorBundle');
bundle = loaded.behaviorBundle;
if ~isfield(bundle, 'configSnapshot') || ...
        ~isfield(bundle.configSnapshot, 'ospaPositionCutoff')
    error('BeneficiaryCoordinatorOfferV234:PositionCutoff', ...
        'The scenario position cutoff is unavailable.');
end
value = bundle.configSnapshot.ospaPositionCutoff;
end

function dimension = inferStateDimension(posteriors)
dimension = 0;
for sensorIndex = 1:numel(posteriors)
    objects = posteriors{sensorIndex};
    for objectIndex = 1:numel(objects)
        if objects(objectIndex).numberOfGmComponents > 0 && ...
                ~isempty(objects(objectIndex).mu)
            dimension = numel(objects(objectIndex).mu{1});
            break;
        end
    end
    if dimension > 0
        break;
    end
end
if dimension < 2
    error('BeneficiaryCoordinatorOfferV234:StateDimension', ...
        'A position-bearing posterior is required.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BeneficiaryCoordinatorOfferV234:WriteReport', ...
        'Could not write the V234 rank report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V234 beneficiary-coordinator offer ranks\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Coordinator rule: `%s`\n', result.coordinatorRule);
fprintf(fid, '- Top-3 mode recall: `%d / %d = %.1f%%`\n', ...
    result.topThreeModeRecallCount, result.teacherLabelCount, ...
    100 * result.topThreeModeRecall);
fprintf(fid, '- Top-6 mode recall: `%d / %d = %.1f%%`\n\n', ...
    result.topSixModeRecallCount, result.teacherLabelCount, ...
    100 * result.topSixModeRecall);
fprintf(fid, ['| Row | Beneficiary / coordinator | Source / label | ', ...
    'Sources | Offers | Mode ranks E/P/D/R | Composite rank | ', ...
    'Top-3 / top-6 |\n']);
fprintf(fid, '|--:|:--|:--|:--|--:|:--|--:|:--|\n');
for audit = result.teacherAudits
    fprintf(fid, ['| %d | F%d / S%d | S%d / `[%d,%d]` | `%s` | ', ...
        '%d | `%s` | %d | `%d / %d` |\n'], ...
        audit.recordIndex, audit.beneficiaryFormationId, ...
        audit.coordinatorSensorId, audit.sourceId, ...
        audit.label(1), audit.label(2), ...
        integerText(audit.sourceSensorIds), audit.offerCount, ...
        integerText(audit.teacherRanksByMode), ...
        audit.teacherCompositeRank, audit.topThreeModeRecall, ...
        audit.topSixModeRecall);
end
fprintf(fid, '\n## Decision\n\n');
if result.screenPassed
    fprintf(fid, ['Every opened teacher label is visible within the ', ...
        'top six of at least one causal compact-data mode. Retain these ', ...
        'features for H=3 outcome collection; do not train or claim an ', ...
        'online policy until material teacher headroom passes.\n']);
else
    fprintf(fid, ['At least one opened teacher label is not separable ', ...
        'within the compact top-six mode bank. Redesign the coordinator ', ...
        'state before collecting tracking outcomes.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = integerText(values)
parts = arrayfun(@(value) rankText(value), ...
    reshape(values, 1, []), 'UniformOutput', false);
text = strjoin(parts, '/');
end

function text = rankText(value)
if isfinite(value)
    text = sprintf('%d', value);
else
    text = '-';
end
end

function offer = emptyOffer()
offer = struct('sourceSensorId', 0, 'label', zeros(2, 1), ...
    'existence', 0, 'evidenceQuality', 0, ...
    'positionMean', zeros(2, 1), 'positionTrace', 0, ...
    'payloadBytesPerReceiver', 0);
end

function audit = emptyAudit()
audit = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'coordinatorSensorId', 0, 'sourceId', 0, ...
    'label', zeros(2, 1), 'sourceSensorIds', zeros(1, 0), ...
    'offerCount', 0, 'modeNames', {cell(1, 0)}, ...
    'teacherRanksByMode', zeros(1, 0), ...
    'teacherCompositeRank', inf, 'topThreeModeRecall', false, ...
    'topSixModeRecall', false, 'featureResult', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
