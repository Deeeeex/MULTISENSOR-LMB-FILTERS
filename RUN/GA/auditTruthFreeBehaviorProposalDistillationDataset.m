function [auditPath, audit] = ...
    auditTruthFreeBehaviorProposalDistillationDataset(options)
% AUDITTRUTHFREEBEHAVIORPROPOSALDISTILLATIONDATASET Fail-closed M24 audit.
%
% The audit checks the frozen merged artifact, the truth boundary of every
% behavior state, exact alignment of every offline teacher graph, and the
% rolling-safety attestations used when the targets were constructed.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeProposalDistillationProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official proposal-distillation audit requires clean source.');
end
datasetPath = getField(options, ...
    'datasetPath', protocol.datasetPath);
actualDatasetSha256 = computeFileSha256(datasetPath);
if ~strcmp(actualDatasetSha256, protocol.datasetSha256)
    error('Proposal-distillation dataset SHA-256 mismatch.');
end
loaded = load(datasetPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Proposal-distillation artifact lacks dataset.');
end
dataset = loaded.dataset;
validateDatasetHeader(dataset, protocol);

targetCountsByActionCode = ...
    zeros(size(protocol.targetActionCodes));
targetGraphSha256 = cell(1, 0);
behaviorGraphSha256 = cell(1, numel(dataset.blocks));
stateFeatureSha256 = cell(1, numel(dataset.blocks));
featureMinimum = inf(1, protocol.expectedFeatureColumnCount);
featureMaximum = -inf(1, protocol.expectedFeatureColumnCount);
targetPositiveEdgeCount = 0;
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    teacher = dataset.teacherBlocks(blockIdx);
    validateBehaviorBlock(block, protocol);
    validateTeacherBlock(teacher, block, protocol);
    featureMinimum = min(featureMinimum, ...
        min(block.features, [], 1));
    featureMaximum = max(featureMaximum, ...
        max(block.features, [], 1));
    behaviorGraphSha256{blockIdx} = ...
        computeTextSha256(sprintf('%d,', ...
            block.selectedSourcesByReceiver));
    stateFeatureSha256{blockIdx} = ...
        computeTextSha256(sprintf('%.17g,', ...
            block.features(:)));
    targetPositiveEdgeCount = targetPositiveEdgeCount + ...
        nnz(teacher.targetCrossMasks);
    targetGraphSha256 = [ ...
        targetGraphSha256, ...
        teacher.targetGraphSha256]; %#ok<AGROW>
    for codeIdx = 1:numel(protocol.targetActionCodes)
        targetCountsByActionCode(codeIdx) = ...
            targetCountsByActionCode(codeIdx) + ...
            nnz(teacher.targetActionCodes == ...
                protocol.targetActionCodes(codeIdx));
    end
end

uniqueTargetGraphCount = numel(unique(targetGraphSha256));
uniqueBehaviorGraphCount = ...
    numel(unique(behaviorGraphSha256));
uniqueStateFeatureCount = ...
    numel(unique(stateFeatureSha256));
varyingFeatureColumnCount = ...
    nnz(featureMaximum > featureMinimum);
if ~isequal(targetCountsByActionCode, ...
        protocol.expectedTargetCountByActionCode) || ...
        uniqueTargetGraphCount ~= ...
            protocol.expectedUniqueTargetGraphCount || ...
        uniqueBehaviorGraphCount ~= ...
            protocol.expectedUniqueBehaviorGraphCount || ...
        uniqueStateFeatureCount ~= ...
            protocol.expectedUniqueStateFeatureCount || ...
        targetPositiveEdgeCount ~= ...
            3 * protocol.expectedTotalTargetCount
    error('Proposal-distillation aggregate coverage changed.');
end

requireSourceShards = logical(getField( ...
    options, 'requireSourceShards', false));
sourceShardVerificationCount = verifySourceShards( ...
    dataset, requireSourceShards);
if requireSourceShards && ...
        sourceShardVerificationCount ~= ...
            numel(protocol.datasetSeeds)
    error('Proposal-distillation source shard verification failed.');
end

audit = struct();
audit.contractVersion = ...
    'rolling-safe-proposal-distillation-audit-m24-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
audit.datasetPath = datasetPath;
audit.datasetSha256 = actualDatasetSha256;
audit.datasetGenerationCommit = ...
    dataset.generationGitCommit;
audit.sourceShardSetSha256 = ...
    dataset.sourceShardSetSha256;
audit.sourceShardVerificationCount = ...
    sourceShardVerificationCount;
audit.stateBlockCount = numel(dataset.blocks);
audit.targetCount = dataset.totalTeacherTargetCount;
audit.targetCountsByActionCode = ...
    targetCountsByActionCode;
audit.uniqueTargetGraphCount = uniqueTargetGraphCount;
audit.uniqueBehaviorGraphCount = uniqueBehaviorGraphCount;
audit.uniqueStateFeatureCount = uniqueStateFeatureCount;
audit.varyingFeatureColumnCount = ...
    varyingFeatureColumnCount;
audit.featureColumnCount = size(dataset.blocks(1).features, 2);
audit.candidateEdgeCount = size(dataset.blocks(1).features, 1);
audit.targetPositiveEdgeCount = targetPositiveEdgeCount;
audit.targetEdgePrevalence = targetPositiveEdgeCount / ...
    (protocol.expectedCandidateEdgeCount * ...
     protocol.expectedTotalTargetCount);
audit.behaviorTruthUsed = dataset.behaviorTruthUsed;
audit.behaviorFutureOutcomeUsed = ...
    dataset.behaviorFutureOutcomeUsed;
audit.featureTruthUsed = dataset.featuresUseTruth;
audit.featureFutureOutcomeUsed = ...
    dataset.featureFutureOutcomeUsed;
audit.teacherTruthUsed = dataset.teacherTargetsUseTruth;
audit.teacherFutureOutcomeUsed = ...
    dataset.teacherTargetsUseFutureOutcome;
audit.allBehaviorActionsRepairFree = ...
    all([dataset.outcomes.policyRepairRate] == 0);
audit.allBehaviorActionsFeasible = ...
    all([dataset.outcomes.topologyInfeasibleRate] == 0);
audit.allBehaviorWindowsPassB3 = ...
    all([dataset.outcomes.selectedRollingB3PassFraction] == 1);
audit.proposalModelTrained = false;
audit.criticTrainingAuthorized = false;
audit.x36Authorized = false;
audit.pass = true;
audit.evidenceBoundary = [ ...
    'This preflight certifies a 54-state M24 development dataset ', ...
    'collected under truth-free behavior and exact offline ', ...
    'alignment of 210 current-truth safe teacher graphs. It does ', ...
    'not establish proposal capture, value return, M24 benefit, ', ...
    'generalization, critic accuracy or X36 benefit.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
auditPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    'proposal_distillation_dataset_preflight_m24.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'PROPOSAL_DISTILLATION_DATASET_PREFLIGHT_M24.md'));
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit, protocol);
fprintf('Proposal-distillation preflight: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function validateDatasetHeader(dataset, protocol)
required = { ...
    'sourceShardSetSha256', 'featureFutureOutcomeUsed', ...
    'teacherTargetsUseTruth', 'teacherTargetsUseFutureOutcome'};
for fieldIdx = 1:numel(required)
    if ~isfield(dataset, required{fieldIdx})
        error('Proposal-distillation dataset lacks %s.', ...
            required{fieldIdx});
    end
end
expectedPairs = zeros(protocol.expectedBlockCount, 2);
cursor = 0;
for seed = protocol.datasetSeeds
    for currentTime = protocol.snapshotTimes
        cursor = cursor + 1;
        expectedPairs(cursor, :) = [seed, currentTime];
    end
end
blockPairs = [[dataset.blocks.seed]', ...
    [dataset.blocks.currentTime]'];
teacherPairs = [[dataset.teacherBlocks.seed]', ...
    [dataset.teacherBlocks.currentTime]'];
if ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~strcmp(dataset.datasetVariant, ...
            protocol.datasetVariant) || ...
        ~strcmp(dataset.generationGitCommit, ...
            protocol.datasetGenerationCommit) || ...
        ~strcmp(dataset.sourceShardSetSha256, ...
            protocol.sourceShardSetSha256) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(dataset.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~isequal(blockPairs, expectedPairs) || ...
        ~isequal(teacherPairs, expectedPairs) || ...
        numel(dataset.blocks) ~= protocol.expectedBlockCount || ...
        numel(dataset.teacherBlocks) ~= ...
            protocol.expectedBlockCount || ...
        dataset.totalTeacherTargetCount ~= ...
            protocol.expectedTotalTargetCount || ...
        dataset.minimumTeacherTargetsPerBlock < ...
            protocol.minimumTargetsPerBlock || ...
        dataset.maximumTeacherTargetsPerBlock > ...
            protocol.maximumTargetsPerBlock || ...
        dataset.generationTrackedWorktreeDirty || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        dataset.behaviorTruthUsed || ...
        dataset.behaviorFutureOutcomeUsed || ...
        dataset.featuresUseTruth || ...
        dataset.featureFutureOutcomeUsed || ...
        ~dataset.teacherTargetsUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome || ...
        dataset.deployable || ~dataset.developmentOnly || ...
        dataset.validationClaimAllowed || ...
        dataset.proposalModelTrained || ...
        dataset.valueReturnEvaluated || ...
        dataset.criticTrainingAuthorized || ...
        dataset.x36Authorized
    error('Proposal-distillation dataset header violates contract.');
end
end

function validateBehaviorBlock(block, protocol)
expectedSize = [ ...
    protocol.expectedCandidateEdgeCount, ...
    protocol.expectedFeatureColumnCount];
metadata = block.featureMetadata;
if block.actionCode ~= protocol.behaviorActionCode || ...
        block.actionTruthUsed || block.labelTruthUsed || ...
        ~strcmp(block.labelSource, ...
            'truth-free-posterior-analytic-behavior-graph') || ...
        ~isequal(size(block.features), expectedSize) || ...
        any(~isfinite(block.features(:))) || ...
        ~strcmp(metadata.featureContractSha256, ...
            protocol.expectedFeatureContractSha256) || ...
        metadata.truthUsed || metadata.groundTruthUsed || ...
        metadata.futureOutcomeUsed || ...
        any(block.previousAdjacencyHistoryTimes >= ...
            block.currentTime) || ...
        size(block.previousAdjacencyHistory, 3) ~= ...
            numel(block.previousAdjacencyHistoryTimes) || ...
        ~isequal(size(block.selectedAdjacency), ...
            [24, 24]) || ...
        any(sum(block.selectedAdjacency, 2) ~= 1) || ...
        any(block.selectedAdjacency(:) & ...
            ~block.physicalAdjacency(:))
    error('Proposal-distillation behavior block violates contract.');
end
edgeKeys = sub2ind([24, 24], ...
    block.receiverIndices, block.senderIndices);
if ~isequal(reshape(logical( ...
        block.selectedAdjacency(edgeKeys)), [], 1), ...
        reshape(logical(block.selectedCrossMask), [], 1))
    error('Behavior selected graph and cross mask disagree.');
end
end

function validateTeacherBlock(teacher, block, protocol)
count = teacher.targetCount;
if teacher.seed ~= block.seed || ...
        teacher.currentTime ~= block.currentTime || ...
        teacher.behaviorBlockIndex < 1 || ...
        count < protocol.minimumTargetsPerBlock || ...
        count > protocol.maximumTargetsPerBlock || ...
        numel(teacher.targetActionCodes) ~= count || ...
        numel(teacher.targetGraphSha256) ~= count || ...
        size(teacher.targetAdjacency, 3) ~= count || ...
        size(teacher.targetCrossMasks, 2) ~= count || ...
        numel(teacher.targetRecords) ~= count || ...
        ~all(ismember(teacher.targetActionCodes, ...
            protocol.targetActionCodes)) || ...
        ~teacher.truthUsed || teacher.futureOutcomeUsed || ...
        teacher.deployable || ...
        ~teacher.targetMetadata.truthUsed || ...
        teacher.targetMetadata.futureOutcomeUsed || ...
        teacher.targetMetadata.deployable
    error('Proposal-distillation teacher block violates contract.');
end
edgeKeys = sub2ind([24, 24], ...
    block.receiverIndices, block.senderIndices);
localHashes = cell(1, count);
for targetIdx = 1:count
    adjacency = logical( ...
        teacher.targetAdjacency(:, :, targetIdx));
    record = teacher.targetRecords(targetIdx);
    details = record.policyDetails;
    expectedSources = zeros(1, 24);
    for receiver = 1:24
        expectedSources(receiver) = find( ...
            adjacency(receiver, :), 1);
    end
    expectedHash = computeTextSha256(sprintf( ...
        '%d,', expectedSources));
    expectedMask = reshape(logical( ...
        adjacency(edgeKeys)), [], 1);
    localHashes{targetIdx} = expectedHash;
    if ~isequal(size(adjacency), [24, 24]) || ...
            any(sum(adjacency, 2) ~= 1) || ...
            any(adjacency(:) & ...
                ~block.physicalAdjacency(:)) || ...
            ~isequal(expectedMask, ...
                teacher.targetCrossMasks(:, targetIdx)) || ...
            nnz(expectedMask) ~= 3 || ...
            ~strcmp(expectedHash, ...
                teacher.targetGraphSha256{targetIdx}) || ...
            ~strcmp(expectedHash, record.graphSha256) || ...
            ~isequal(expectedSources, ...
                record.selectedSourcesByReceiver) || ...
            record.actionCode ~= ...
                teacher.targetActionCodes(targetIdx) || ...
            ~record.eligibleForProposalDistillation || ...
            record.crossFormationMessageCount ~= 3 || ...
            details.repairTriggered || ...
            details.payloadEmergencyUsed || ...
            ~details.oneStepJointProjectionUsed || ...
            ~details.sensorWindowStrongConnected || ...
            ~details.formationWindowStrongConnected || ...
            ~details.oneStepTopologyReservePassed || ...
            ~details.oneStepReservePayloadLimitPassed || ...
            ~(details.truthUsed || ...
                details.actionSequenceTruthUsed)
        error('Proposal-distillation target graph violates contract.');
    end
end
if numel(unique(localHashes)) ~= count
    error('Proposal-distillation block contains duplicate targets.');
end
end

function verifiedCount = verifySourceShards( ...
        dataset, requireSourceShards)
verifiedCount = 0;
if numel(dataset.sourceShardPaths) ~= ...
        numel(dataset.sourceShardSha256)
    error('Proposal-distillation source shard manifest is malformed.');
end
for shardIdx = 1:numel(dataset.sourceShardPaths)
    path = dataset.sourceShardPaths{shardIdx};
    if exist(path, 'file') ~= 2
        if requireSourceShards
            error('Missing proposal-distillation source shard: %s', path);
        end
        continue;
    end
    if ~strcmp(computeFileSha256(path), ...
            dataset.sourceShardSha256{shardIdx})
        error('Proposal-distillation source shard SHA mismatch.');
    end
    verifiedCount = verifiedCount + 1;
end
if ~strcmp(computeTextSha256(strjoin( ...
        dataset.sourceShardSha256, char(31))), ...
        dataset.sourceShardSetSha256)
    error('Proposal-distillation shard-set SHA mismatch.');
end
end

function writeReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open proposal-distillation audit report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# Proposal-distillation dataset preflight: M24\n\n');
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Audit contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Audit generation commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Dataset SHA-256: `%s`\n', audit.datasetSha256);
fprintf(fid, '- Dataset generation commit: `%s`\n', ...
    audit.datasetGenerationCommit);
fprintf(fid, '- Source shard-set SHA-256: `%s`\n', ...
    audit.sourceShardSetSha256);
fprintf(fid, '- Source shards verified: `%d / %d`\n', ...
    audit.sourceShardVerificationCount, ...
    numel(protocol.datasetSeeds));
fprintf(fid, '- State blocks / teacher targets: `%d / %d`\n', ...
    audit.stateBlockCount, audit.targetCount);
fprintf(fid, '- Target counts for `[00 90 91 92]`: `%s`\n', ...
    mat2str(audit.targetCountsByActionCode));
fprintf(fid, ...
    '- Unique target / behavior / feature states: `%d / %d / %d`\n', ...
    audit.uniqueTargetGraphCount, ...
    audit.uniqueBehaviorGraphCount, ...
    audit.uniqueStateFeatureCount);
fprintf(fid, '- Feature shape: `%d x %d` per state\n', ...
    audit.candidateEdgeCount, audit.featureColumnCount);
fprintf(fid, '- Varying feature columns: `%d / %d`\n', ...
    audit.varyingFeatureColumnCount, audit.featureColumnCount);
fprintf(fid, '- Positive teacher edges / prevalence: `%d / %.6f`\n', ...
    audit.targetPositiveEdgeCount, audit.targetEdgePrevalence);
fprintf(fid, '- Behavior/feature truth used: `%d / %d`\n', ...
    audit.behaviorTruthUsed, audit.featureTruthUsed);
fprintf(fid, '- Teacher truth/future used: `%d / %d`\n', ...
    audit.teacherTruthUsed, audit.teacherFutureOutcomeUsed);
fprintf(fid, '- Behavior repair-free / feasible / B3: `%d / %d / %d`\n', ...
    audit.allBehaviorActionsRepairFree, ...
    audit.allBehaviorActionsFeasible, ...
    audit.allBehaviorWindowsPassB3);
fprintf(fid, '- Pass: `%d`\n', audit.pass);
fprintf(fid, '- Evidence boundary: %s\n', audit.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
