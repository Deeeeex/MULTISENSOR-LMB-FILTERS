function [modelPath, reportPath, result] = ...
    trainStructuredFormationTreeRoutingPolicy(datasetPaths, options)
% TRAINSTRUCTUREDFORMATIONTREEROUTINGPOLICY Fit and freeze a v4 ranker.

if nargin < 1 || isempty(datasetPaths)
    error('Structured formation-tree training needs explicit datasets.');
end
if nargin < 2 || isempty(options)
    options = struct();
end
artifactDirectory = getField(options, 'artifactDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
modelPath = getField(options, 'modelPath', fullfile( ...
    artifactDirectory, 'models', ...
    'structured_formation_tree_m24_proxy_candidate.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    artifactDirectory, ...
    'STRUCTURED_FORMATION_TREE_MODEL_M24.md'));
auditOptions = getField(options, 'auditOptions', struct());
auditOptions.modelFamily = 'structured-ranking';
auditOptions.sourceWeight = getField( ...
    auditOptions, 'sourceWeight', 0.70);
auditOptions.baselineMode = getField( ...
    auditOptions, 'baselineMode', 'fixed-index-star');
auditOptions.requirePreviousUnionStrongConnectivity = ...
    logical(getField(auditOptions, ...
        'requirePreviousUnionStrongConnectivity', true));
if ~strcmp(auditOptions.baselineMode, 'fixed-index-star')
    error([ ...
        'Structured formation-tree artifacts require the ', ...
        'fixed-index-star baseline contract.']);
end
if ~auditOptions.requirePreviousUnionStrongConnectivity
    error([ ...
        'Structured formation-tree artifacts require the previous/current ', ...
        'formation-union strong-connectivity contract.']);
end
auditOptions.writeReport = false;

[~, auditResult] = auditLearnedFormationTreeProxy( ...
    datasetPaths, auditOptions);
if isfield(options, 'requireValidationGate') && ...
        ~logical(options.requireValidationGate)
    error('Structured artifact proxy validation cannot be disabled.');
end
if ~auditResult.trainingGatePassed || ...
        ~auditResult.validationGatePassed
    error([ ...
        'Structured formation-tree proxy training/validation gate ', ...
        'failed; ', ...
        'no frozen closed-loop candidate artifact was written.']);
end

model = struct();
model.kind = 'structured-formation-tree-routing-v1';
model.generatedAt = datestr(now, 31);
model.sourceWeight = auditResult.sourceWeight;
model.baselineMode = auditResult.baselineMode;
model.featureContextMode = auditResult.featureContextMode;
model.allFeatureNames = auditResult.allFeatureNames;
model.featureMask = auditResult.model.featureMask;
model.retainedFeatureNames = auditResult.retainedFeatureNames;
model.ranker = auditResult.model;
model.requirePreviousUnionStrongConnectivity = ...
    auditResult.requirePreviousUnionStrongConnectivity;
model.teacherSeriesContractVersion = ...
    auditResult.teacherSeriesContractVersion;
model.previousAdjacencyConvention = ...
    auditResult.previousAdjacencyConvention;
model.trainingDatasetPaths = auditResult.datasetPaths( ...
    auditResult.trainDatasetIndices);
model.validationDatasetPaths = auditResult.datasetPaths( ...
    auditResult.validationDatasetIndices);
model.trainingBehaviorTruthUsed = any( ...
    auditResult.behaviorTruthUsedByBlock( ...
        auditResult.trainDatasetIndices));
model.validationBehaviorTruthUsed = any( ...
    auditResult.behaviorTruthUsedByBlock( ...
        auditResult.validationDatasetIndices));
model.actionFeaturesUseTruth = false;
model.closedLoopValidated = false;
model.proxyValidatedOnly = true;
model.proxyTrainingGatePassed = ...
    auditResult.trainingGatePassed;
model.proxyValidationGatePassed = ...
    auditResult.validationGatePassed;
model.artifactContractVersion = ...
    'structured-formation-tree-proxy-candidate-v2-ctxv2';

trainingSummary = auditResult;
ensureDirectory(fileparts(modelPath));
save('-mat7-binary', modelPath, 'model', 'trainingSummary');
result = struct( ...
    'modelPath', modelPath, ...
    'reportPath', reportPath, ...
    'model', model, ...
    'trainingSummary', trainingSummary);
writeReport(reportPath, result);
fprintf('Model: %s\n', modelPath);
fprintf('Report: %s\n', reportPath);
end

function writeReport(path, result)
ensureDirectory(fileparts(path));
fid = fopen(path, 'w');
if fid < 0
    error('Could not open structured-tree model report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
summary = result.trainingSummary;
fprintf(fid, '# Structured formation-tree routing model\n\n');
fprintf(fid, '- Generated: %s\n', result.model.generatedAt);
fprintf(fid, '- Model: `%s`\n', result.modelPath);
fprintf(fid, '- Model kind: `%s`\n', result.model.kind);
fprintf(fid, '- Artifact contract: `%s`\n', ...
    result.model.artifactContractVersion);
fprintf(fid, '- Teacher-series contract: `%s`\n', ...
    result.model.teacherSeriesContractVersion);
fprintf(fid, '- Previous-adjacency convention: `%s`\n', ...
    result.model.previousAdjacencyConvention);
fprintf(fid, '- Source weight: %.2f\n', result.model.sourceWeight);
fprintf(fid, '- Feature context: `%s`\n', ...
    result.model.featureContextMode);
fprintf(fid, '- Retained features: %d / %d\n', ...
    nnz(result.model.featureMask), ...
    numel(result.model.featureMask));
fprintf(fid, '- Structured lambda: %.6g\n', ...
    result.model.ranker.lambda);
fprintf(fid, '- Structured epochs: %d\n', ...
    result.model.ranker.epochCount);
fprintf(fid, '- Training blocks: `%s`\n', ...
    mat2str(summary.trainDatasetIndices));
fprintf(fid, '- Validation blocks: `%s`\n', ...
    mat2str(summary.validationDatasetIndices));
fprintf(fid, '- Training proxy gate passed: `%d`\n', ...
    summary.trainingGatePassed);
fprintf(fid, '- Validation proxy gate passed: `%d`\n', ...
    summary.validationGatePassed);
fprintf(fid, '- Closed-loop validated: `%d`\n', ...
    result.model.closedLoopValidated);
fprintf(fid, '- Truth-assisted training behavior: `%d`\n', ...
    result.model.trainingBehaviorTruthUsed);
fprintf(fid, '\n## Evidence boundary\n\n');
fprintf(fid, ['Projection-time action features do not read truth. ', ...
    'Training labels are privileged, and the current oracle-v4 training ', ...
    'state distribution is also truth-assisted. Passing this proxy audit ', ...
    'does not establish closed-loop tracking gain or held-out transfer.\n']);
end

function ensureDirectory(path)
if ~isempty(path) && ~exist(path, 'dir')
    mkdir(path);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
