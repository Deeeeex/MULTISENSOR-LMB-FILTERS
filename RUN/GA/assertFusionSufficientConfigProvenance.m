function provenance = assertFusionSufficientConfigProvenance(config)
% ASSERTFUSIONSUFFICIENTCONFIGPROVENANCE Bind production config to Git.

if ~isfield(config, 'testOnly') || ~isequal(config.testOnly, false)
    error('FusionSufficientConfigProvenance:TestConfig', ...
        'Production provenance rejects testOnly configs.');
end
provenance = assertFusionSufficientGitProvenance(config.projectRoot);
if ~strcmp(provenance.head, config.gitCommit) || ...
        ~strcmp(provenance.requiredSourcesSha256, ...
        config.requiredSourcesSha256) || ...
        ~strcmp(provenance.requiredSourcesAtHeadSha256, ...
        config.requiredSourcesSha256)
    error('FusionSufficientConfigProvenance:Mismatch', ...
        'Frozen config does not match clean published Git provenance.');
end
end
