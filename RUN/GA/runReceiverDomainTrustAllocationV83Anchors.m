function [reportPath, result] = ...
    runReceiverDomainTrustAllocationV83Anchors(options)
% RUNRECEIVERDOMAINTRUSTALLOCATIONV83ANCHORS Two-scale H=3 headroom.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReceiverDomainTrustAllocationV83Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReceiverDomainTrustV83:DirtySource', ...
        'The V83 headroom screen requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
screenPaths = cell(1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    screenOptions = struct( ...
        'horizonSteps', protocol.horizonSteps, ...
        'interventionDurationSteps', ...
            protocol.interventionDurationSteps, ...
        'filterSeedOffset', protocol.filterSeedOffset, ...
        'cacheRoot', cacheRoot, ...
        'interventionBankType', ...
            'receiver-domain-transport-v71', ...
        'trackingAlignedExecutionProfile', ...
            'v72-receiver-domain-transport-h3', ...
        'receiverDomainTransportBankOptions', struct( ...
            'expectedSelectedFormationIds', ...
                caseInfo.expectedSelectedFormationIds, ...
            'expectedSelectedSlotCount', ...
                caseInfo.expectedSelectedSlotCount, ...
            'directSafeFormationIds', ...
                caseInfo.directSafeFormationIds, ...
            'candidateTrustWeights', ...
                protocol.candidateTrustWeights, ...
            'selfFundedTrust', true, ...
            'rollingB3DurationSteps', ...
                protocol.interventionDurationSteps, ...
            'rollingB3ActionUse', ...
                protocol.candidateUseByRound), ...
        'actionSequenceIndices', buildActionSequences( ...
            numel(protocol.candidateTrustWeights)), ...
        'outputDirectory', fullfile(outputRoot, 'screen', ...
            caseInfo.presetName, sprintf('t%d', caseInfo.currentTime)), ...
        'writeReport', true);
    [screenPaths{caseIdx}, screen] = ...
        runFormationModeOpenedReturnScreen( ...
            caseInfo.presetName, caseInfo.seed, ...
            caseInfo.currentTime, screenOptions);
    records(caseIdx) = summarizeCase(screen, protocol);
    fprintf([ ...
        'V83 %s t=%d best=%s mean=%+.3f%% worst=%+.3f%% ', ...
        'formation=%+.3f%% consensus=%+.3f%% gate=%d\n'], ...
        caseInfo.presetName, caseInfo.currentTime, ...
        records(caseIdx).bestActionName, ...
        records(caseIdx).bestMeanGainPercent, ...
        records(caseIdx).bestWorstSensorGainPercent, ...
        records(caseIdx).bestMinimumFormationGainPercent, ...
        records(caseIdx).bestWindowConsensusGainPercent, ...
        records(caseIdx).headroomGatePassed);
end

result = struct();
result.contractVersion = ...
    'receiver-domain-route-trust-h3-v83-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.screenPaths = screenPaths;
result.records = records;
result.bothScalesHeadroomGatePassed = ...
    all([records.headroomGatePassed]);
result.trackingOutcomeRead = true;
result.onlineSelectorAvailable = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RECEIVER_DOMAIN_ROUTE_TRUST_V83_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'RECEIVER_DOMAIN_ROUTE_TRUST_V83_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V83 route-trust headroom: %s\n', reportPath);
end

function sequences = buildActionSequences(candidateCount)
sequences = ones(candidateCount + 1, 3);
for candidateIdx = 1:candidateCount
    actionIdx = candidateIdx + 1;
    sequences(actionIdx, :) = [actionIdx, 1, actionIdx];
end
end

function record = summarizeCase(screen, protocol)
candidateIndices = setdiff( ...
    1:numel(screen.records), screen.referenceSubsetIndex);
if isempty(candidateIndices)
    error('ReceiverDomainTrustV83:MissingCandidates', ...
        'V83 requires at least one non-reference trust action.');
end
candidateRecords = screen.records(candidateIndices);
gateMask = arrayfun(@(value) actionPasses(value, protocol), ...
    candidateRecords);
if any(gateMask)
    eligible = find(gateMask);
else
    eligible = 1:numel(candidateRecords);
end
score = [[candidateRecords(eligible).meanGainPercent]', ...
    -[candidateRecords(eligible).trustWeight]'];
[~, localBest] = sortrows(score, [-1, -2]);
best = candidateRecords(eligible(localBest(1)));
record = emptyCaseRecord();
record.presetName = screen.presetName;
record.seed = screen.seed;
record.currentTime = screen.currentTime;
record.bestActionName = best.actionName;
record.bestTrustWeight = best.trustWeight;
record.bestMeanGainPercent = best.meanGainPercent;
record.bestWorstSensorGainPercent = best.worstGainPercent;
record.bestMinimumFormationGainPercent = ...
    best.minimumFormationGainPercent;
record.bestWindowConsensusGainPercent = ...
    best.consensusGainPercent;
record.bestTerminalConsensusGainPercent = ...
    best.terminalConsensusGainPercent;
record.bestAttemptedByteSavingPercent = ...
    best.attemptedByteSavingPercent;
record.bestSelectedB3Passed = best.selectedB3Passed;
record.headroomGatePassed = any(gateMask);
record.actionRecords = candidateRecords;
record.referenceMeanEospa = ...
    screen.outcomes(screen.referenceSubsetIndex).meanEospa;
end

function value = actionPasses(record, protocol)
value = ...
    record.meanGainPercent >= ...
        protocol.minimumMeanTrackingGainPercent - 1e-12 && ...
    record.worstGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    record.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    record.consensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    record.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    record.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    record.selectedB3Passed;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReceiverDomainTrustV83:WriteFailed', ...
        'Could not create the V83 result report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V83 receiver-domain route-and-trust H=3 headroom\n\n');
fprintf(fid, '- Both scales pass the headroom gate: `%d`\n', ...
    result.bothScalesHeadroomGatePassed);
fprintf(fid, '- Online selector available: `0`\n');
fprintf(fid, '- Tracking outcome read: `1`\n\n');
for caseIdx = 1:numel(result.records)
    record = result.records(caseIdx);
    fprintf(fid, '## %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    fprintf(fid, '| Trust | Mean tracking | Worst sensor | Minimum formation | Window consensus | Terminal consensus | Attempted bytes | B3 | Gate |\n');
    fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
    for action = record.actionRecords
        fprintf(fid, ['| %.2f | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
            '%+.3f%% | %+.3f%% | %+.3f%% | %d | %d |\n'], ...
            action.trustWeight, action.meanGainPercent, ...
            action.worstGainPercent, ...
            action.minimumFormationGainPercent, ...
            action.consensusGainPercent, ...
            action.terminalConsensusGainPercent, ...
            action.attemptedByteSavingPercent, ...
            action.selectedB3Passed, ...
            actionPasses(action, result.protocol));
    end
    fprintf(fid, ['\n- Best action / trust: `%s / %.2f`\n', ...
        '- Best mean gain: `%+.3f%%`\n', ...
        '- Headroom gate passed: `%d`\n\n'], ...
        record.bestActionName, record.bestTrustWeight, ...
        record.bestMeanGainPercent, record.headroomGatePassed);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyCaseRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'bestActionName', '', ...
    'bestTrustWeight', NaN, ...
    'bestMeanGainPercent', NaN, ...
    'bestWorstSensorGainPercent', NaN, ...
    'bestMinimumFormationGainPercent', NaN, ...
    'bestWindowConsensusGainPercent', NaN, ...
    'bestTerminalConsensusGainPercent', NaN, ...
    'bestAttemptedByteSavingPercent', NaN, ...
    'bestSelectedB3Passed', false, ...
    'headroomGatePassed', false, ...
    'actionRecords', repmat(struct(), 1, 0), ...
    'referenceMeanEospa', NaN);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
