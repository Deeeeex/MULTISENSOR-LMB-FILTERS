    config.lineageRelayPredictiveEvidenceFallbackEnabled = false;
    config.lineageRelayPostFusionLabelReadoutEnabled = true;
    config.receiverSafeEvidenceOptions = ...
        protocol.labelReadout.evidenceOptions;
elseif strcmp(protocol.id, 'combined-output-safety-v139-v1')
    config.lineageRelayPredictiveEvidenceFallbackEnabled = false;
    config.lineageRelayPredictiveEvidenceReadoutOnlyEnabled = true;
    config.lineageRelayPredictiveEvidenceMinimumLogScoreMargin = ...
        protocol.predictiveEvidence.minimumMargin;
    config.lineageRelayPostFusionLabelReadoutEnabled = true;
    config.receiverSafeEvidenceOptions = ...
        protocol.labelReadout.evidenceOptions;
elseif strcmp(protocol.id, 'reference-cardinality-readout-v140-v1')
    config.lineageRelayPredictiveEvidenceFallbackEnabled = false;
    config.lineageRelayPredictiveEvidenceReadoutOnlyEnabled = true;
    config.lineageRelayPredictiveEvidenceMinimumLogScoreMargin = ...
        protocol.predictiveEvidence.minimumMargin;
    config.lineageRelayPostFusionLabelReadoutEnabled = true;
    config.lineageRelayReferenceCardinalityReadoutEnabled = true;
    config.receiverSafeEvidenceOptions = ...
        protocol.labelReadout.evidenceOptions;
end
end

function outcome = runContinuation( ...
        inputs, truth, state, anchorTime, config, context, seed, protocol)
returnTimes = anchorTime + (0:(context.horizonSteps - 1));
config.filterInitialLocalPosteriorBySensor = state.initialPosteriors;
config.filterInitialLocalPosteriorTime = anchorTime;
config.filterInitialPreviousAdjacencyHistory = state.previousPolicyHistory;
config.filterInitialPreviousAdjacencyTimes = state.history.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'v134-paired-reference-prefix';
config.filterInitialLocalUpdateHistoryTimes = state.updateHistory.times;
config.filterInitialLocalInnovationHistory = state.updateHistory.innovation;
config.filterInitialLocalAssociationConfidenceHistory = ...
    state.updateHistory.associationConfidence;
config.filterInitialLocalNisNormHistory = state.updateHistory.nisNorm;
config.filterInitialLocalNisDeviationHistory = ...
    state.updateHistory.nisDeviation;
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
elapsedSeconds = toc(timerId);
nodeCount = numel(estimates);
eospa = zeros(nodeCount, numel(returnTimes));
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, ~] = computeSimulationOspa( ...
        inputs.model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(returnTimes);
end
outcome = struct();
outcome.eospaBySensorTime = eospa;
outcome.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes(:, :, returnTimes), 1), 2), 1, []);
outcome.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes(:, :, returnTimes), 1), 2), 1, []);
outcome.auxiliaryAttemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.lineageRelayAttemptedWorkingPayloadBytes( ...
        :, :, returnTimes), 1), 2), 1, []);
outcome.elapsedSeconds = elapsedSeconds;
outcome.selectedAdjacencyByTime = false( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.nominalFusionWeightsByTime = zeros( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.attemptedEdgeByTime = logical( ...
    diagnostics.attempted(:, :, returnTimes));
outcome.deliveredEdgeByTime = logical( ...
    diagnostics.delivered(:, :, returnTimes));
outcome.abstentionByTime = false( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.workingRelayDisagreementBySensorTime = ...
    diagnostics.lineageRelayWorkingCombinedDisagreement(:, returnTimes);
outcome.predictiveEvidenceFallbackBySensorTime = ...
    diagnostics.lineageRelayPredictiveEvidenceFallback(:, returnTimes);
outcome.predictiveEvidenceMarginBySensorTime = ...
    diagnostics.lineageRelayPredictiveEvidenceMargin(:, returnTimes);
outcome.postFusionLabelEvaluatedCountBySensorTime = ...
    diagnostics.lineageRelayPostFusionLabelEvaluatedCount(:, returnTimes);
outcome.postFusionLabelRelaySelectedCountBySensorTime = ...
    diagnostics.lineageRelayPostFusionLabelRelaySelectedCount( ...
        :, returnTimes);
outcome.localMapCardinalityBySensorTime = ...
    diagnostics.lineageRelayLocalMapCardinality(:, returnTimes);
outcome.workingMapCardinalityBySensorTime = ...
    diagnostics.lineageRelayWorkingMapCardinality(:, returnTimes);
outcome.relayMapCardinalityBySensorTime = ...
    diagnostics.lineageRelayRelayMapCardinality(:, returnTimes);
outcome.labelReadoutMapCardinalityBySensorTime = ...
    diagnostics.lineageRelayLabelReadoutMapCardinality(:, returnTimes);
outcome.finalOutputMapCardinalityBySensorTime = ...
    diagnostics.lineageRelayFinalOutputMapCardinality(:, returnTimes);
outcome.referenceCardinalityProjectionBySensorTime = ...
    diagnostics.lineageRelayReferenceCardinalityProjection(:, returnTimes);
outcome.referenceCardinalityRelayFallbackBySensorTime = ...
    diagnostics.lineageRelayReferenceCardinalityRelayFallback( ...
        :, returnTimes);
for timeIdx = 1:numel(returnTimes)
    currentTime = returnTimes(timeIdx);
    outcome.selectedAdjacencyByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge(:, :, currentTime));
    outcome.nominalFusionWeightsByTime(:, :, timeIdx) = ...
        diagnostics.topologyPolicyFusionWeightMatrix{currentTime};
    outcome.abstentionByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.receiverSafeAbstainFromFusionEdge( ...
                :, :, currentTime));
end
end

function metrics = scoreOutcome( ...
        reference, candidate, groupIds, actionSpec, caseInfo, protocol)
referenceEosp = reference.eospaBySensorTime;
candidateEosp = candidate.eospaBySensorTime;
horizonSteps = size(referenceEosp, 2);
intervention = find(cellfun(@(factors) any(factors == 0), ...
    actionSpec.trustFactorsByTime));
mature = (horizonSteps - caseInfo.recoveryTailSteps + 1):horizonSteps;
sensorGain = safeGain(mean(referenceEosp, 2), mean(candidateEosp, 2));
formationIds = unique(groupIds, 'stable');
formationGain = zeros(1, numel(formationIds));
for formationIdx = 1:numel(formationIds)
    members = groupIds == formationIds(formationIdx);
    formationGain(formationIdx) = safeGain( ...
        mean(referenceEosp(members, :), 'all'), ...
        mean(candidateEosp(members, :), 'all'));
end
activeAbstentionByReceiverTime = squeeze(any( ...
    candidate.abstentionByTime, 2));
if isvector(activeAbstentionByReceiverTime)
    activeAbstentionByReceiverTime = reshape( ...
        activeAbstentionByReceiverTime, [], horizonSteps);
end
groups = reshape(groupIds, 1, []);
formationProtected = false(size(activeAbstentionByReceiverTime));
for formationId = unique(groups, 'stable')
    members = groups == formationId;
    active = any(activeAbstentionByReceiverTime(members, :), 1);
    formationProtected(members, :) = repmat(active, sum(members), 1);
end
rejoined = ~formationProtected;
relayDisagreement = candidate.workingRelayDisagreementBySensorTime;
metrics = struct();
metrics.interventionGainFraction = safeGain( ...
    mean(referenceEosp(:, intervention), 'all'), ...
    mean(candidateEosp(:, intervention), 'all'));
metrics.meanGainFraction = safeGain( ...
    mean(referenceEosp(:)), mean(candidateEosp(:)));
metrics.matureGainFraction = safeGain( ...
    mean(referenceEosp(:, mature), 'all'), ...
    mean(candidateEosp(:, mature), 'all'));
metrics.sensorGainFraction = reshape(sensorGain, 1, []);
metrics.minimumSensorGainFraction = min(sensorGain);
metrics.formationGainFraction = formationGain;
metrics.minimumFormationGainFraction = min(formationGain);
metrics.maximumRejoinedRelayDisagreement = ...
    max(relayDisagreement(rejoined));
metrics.rejoinedRelayMatchFraction = mean( ...
    relayDisagreement(rejoined) <= 1e-12);
referenceBytes = sum(reference.attemptedBytesByTime);
candidateBytes = sum(candidate.attemptedBytesByTime);
metrics.referenceAttemptedBytes = referenceBytes;
metrics.candidateAttemptedBytes = candidateBytes;
metrics.auxiliaryAttemptedBytes = ...
    sum(candidate.auxiliaryAttemptedBytesByTime);
metrics.attemptedByteDeltaFraction = ...
    (candidateBytes - referenceBytes) / max(referenceBytes, eps);
gate = protocol.screen;
metrics.passesMechanismGate = ...
    metrics.interventionGainFraction >= ...
        gate.minimumInterventionGainFraction - 1e-12 && ...
    metrics.meanGainFraction >= ...
        gate.minimumFullWindowGainFraction - 1e-12 && ...
    metrics.matureGainFraction >= ...
        gate.minimumMatureGainFraction - 1e-12 && ...
    metrics.minimumSensorGainFraction >= ...
        gate.minimumSensorGainFraction - 1e-12 && ...
    metrics.minimumFormationGainFraction >= ...
        gate.minimumFormationGainFraction - 1e-12 && ...
    metrics.rejoinedRelayMatchFraction >= ...
        gate.minimumRejoinedRelayMatchFraction - 1e-12 && ...
    (~gate.requirePositiveAuxiliaryPayload || ...
        metrics.auxiliaryAttemptedBytes > 0);
end

function assertPairedExecution(reference, candidate)
if ~isequal(reference.selectedAdjacencyByTime, ...
        candidate.selectedAdjacencyByTime) || ...
        max(abs(reference.nominalFusionWeightsByTime(:) - ...
            candidate.nominalFusionWeightsByTime(:))) > 1e-12 || ...
        ~isequal(reference.attemptedEdgeByTime, ...
            candidate.attemptedEdgeByTime) || ...
        ~isequal(reference.deliveredEdgeByTime, ...
            candidate.deliveredEdgeByTime)
    error('FormationDualPayloadV136:UnpairedContinuation', ...
        'V136 must share route, weights, opportunities and deliveries.');
end
end

function state = validateV134State( ...
        loaded, presetName, seed, anchorTime, caseInfo)
if ~isfield(loaded, 'pilotState') || ...
        ~isstruct(loaded.pilotState) || ...
        ~strcmp(loaded.pilotState.contractVersion, ...
            'v134-binary-admission-pilot-state-v4') || ...
        ~strcmp(loaded.pilotState.presetName, presetName) || ...
        loaded.pilotState.seed ~= seed || ...
        loaded.pilotState.anchorTime ~= anchorTime || ...
        loaded.pilotState.horizonSteps ~= caseInfo.horizonSteps
    error('FormationDualPayloadV136:InvalidV134State', ...
        'The frozen V134 paired state is malformed or mismatched.');
end
state = loaded.pilotState;
end

function actionIndex = resolveActionIndex(protocol, caseInfo)
if strcmp(caseInfo.scaleName, 'M24')
    actionIndex = protocol.screen.m24ActionIndex;
else
    actionIndex = protocol.screen.x36ActionIndex;
end
end

function path = defaultV134PilotStatePath(presetName, seed, anchorTime)
root = getenv('V134_PILOT_SOURCE_ROOT');
if isempty(root)
    error('FormationDualPayloadV136:MissingV134SourceRoot', ...
        ['Set V134_PILOT_SOURCE_ROOT or pass v134PilotStatePath to ', ...
         'reuse the frozen paired state.']);
end
path = fullfile(root, strrep(presetName, '-', '_'), ...
    sprintf('seed%d_t%d', seed, anchorTime), 'PILOT_STATE_V134.mat');
end

function inputs = isolateRuntimeInputs(inputs)
present = intersect( ...
    {'groundTruth', 'groundTruthRfs', 'targetTrajectories'}, ...
    fieldnames(inputs), 'stable');
if ~isempty(present)
    inputs = rmfield(inputs, present);
end
if isfield(inputs.model, 'explicitTargetTrajectories')
    inputs.model = rmfield(inputs.model, 'explicitTargetTrajectories');
end
if isfield(inputs.model, 'dynamicTopologyScenario')
    present = intersect({'targetTrajectories', 'target'}, ...
        fieldnames(inputs.model.dynamicTopologyScenario), 'stable');
    if ~isempty(present)
        inputs.model.dynamicTopologyScenario = rmfield( ...
            inputs.model.dynamicTopologyScenario, present);
    end
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function truth = cropTrackingTruthRfs(truth, maximumTime)
truth.x = truth.x(1:maximumTime);
truth.mu = truth.mu(1:maximumTime);
truth.Sigma = truth.Sigma(1:maximumTime);
truth.cardinality = truth.cardinality(1:maximumTime);
end

function caseInfo = resolveCase(protocol, presetName)
caseIdx = find(strcmp({protocol.scaleCases.presetName}, presetName), 1);
if isempty(caseIdx)
    error('FormationDualPayloadV136:InvalidPreset', ...
        'The preset is outside the V136 screen.');
end
caseInfo = protocol.scaleCases(caseIdx);
end

function gitState = requireCleanSource()
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('FormationDualPayloadV136:DirtySource', ...
        'Run the V136 screen only from clean source.');
end
end

function atomicSave(path, variableName, value)
directory = fileparts(path);
if exist(directory, 'dir') ~= 7
    mkdir(directory);
end
temporaryPath = [path, '.partial'];
payload = struct();
payload.(variableName) = value;
save('-mat7-binary', temporaryPath, '-struct', 'payload');
[moved, message] = movefile(temporaryPath, path, 'f');
if ~moved
    error('FormationDualPayloadV136:WriteFailed', ...
        'Could not finalize %s: %s', path, message);
end
end

function writeReport(path, screen, protocolVersion)
fileId = fopen(path, 'w');
if fileId < 0
    error('FormationDualPayloadV136:ReportWriteFailed', ...
        'Could not open the repository-only report.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
m = screen.metrics;
fprintf(fileId, ...
    '# V%d formation-isolated dual-payload screen: %s\n\n', ...
    protocolVersion, screen.scaleName);
fprintf(fileId, ...
    ['Repository-only mechanism upper bound. The charged auxiliary ', ...
     'payload forbids a communication-method claim.\n\n']);
fprintf(fileId, '- Action: `%02d` / `%s`\n', ...
    screen.actionIndex, screen.actionSpec.name);
fprintf(fileId, '- Intervention E-OSPA gain: `%+.3f%%`\n', ...
    100 * m.interventionGainFraction);
fprintf(fileId, '- Full-window E-OSPA gain: `%+.3f%%`\n', ...
    100 * m.meanGainFraction);
fprintf(fileId, '- Mature-window E-OSPA gain: `%+.3f%%`\n', ...
    100 * m.matureGainFraction);
fprintf(fileId, '- Minimum sensor / formation gain: `%+.3f%% / %+.3f%%`\n', ...
    100 * m.minimumSensorGainFraction, ...
    100 * m.minimumFormationGainFraction);
fprintf(fileId, '- Rejoined relay match: `%.3f%%`\n', ...
    100 * m.rejoinedRelayMatchFraction);
fprintf(fileId, '- Charged attempted-byte delta: `%+.3f%%`\n', ...
    100 * m.attemptedByteDeltaFraction);
if protocolVersion == 137
    fprintf(fileId, '- Predictive-evidence fallback count: `%d`\n', ...
        nnz(screen.candidateOutcome. ...
            predictiveEvidenceFallbackBySensorTime));
elseif protocolVersion == 138
    fprintf(fileId, ...
        '- Post-fusion labels evaluated / relay-selected: `%d / %d`\n', ...
        sum(screen.candidateOutcome. ...
            postFusionLabelEvaluatedCountBySensorTime(:)), ...
        sum(screen.candidateOutcome. ...
            postFusionLabelRelaySelectedCountBySensorTime(:)));
elseif protocolVersion == 139
    fprintf(fileId, ...
        '- Post-fusion labels evaluated / relay-selected: `%d / %d`\n', ...
        sum(screen.candidateOutcome. ...
            postFusionLabelEvaluatedCountBySensorTime(:)), ...
        sum(screen.candidateOutcome. ...
            postFusionLabelRelaySelectedCountBySensorTime(:)));
    fprintf(fileId, ...
        '- Output-only predictive node fallbacks: `%d`\n', ...
        nnz(screen.candidateOutcome. ...
            predictiveEvidenceFallbackBySensorTime));
    fprintf(fileId, ...
        '- Registered minimum-sensor tolerance: `%+.3f%%`\n', ...
        100 * screen.registeredMinimumSensorGainFraction);
elseif protocolVersion == 140
    fprintf(fileId, ...
        '- Post-fusion labels evaluated / relay-selected: `%d / %d`\n', ...
        sum(screen.candidateOutcome. ...
            postFusionLabelEvaluatedCountBySensorTime(:)), ...
        sum(screen.candidateOutcome. ...
            postFusionLabelRelaySelectedCountBySensorTime(:)));
    fprintf(fileId, ...
        '- Reference-cardinality projections / relay fallbacks: `%d / %d`\n', ...
        nnz(screen.candidateOutcome. ...
            referenceCardinalityProjectionBySensorTime), ...
        nnz(screen.candidateOutcome. ...
            referenceCardinalityRelayFallbackBySensorTime));
    fprintf(fileId, ...
        '- Output-only predictive node fallbacks: `%d`\n', ...
        nnz(screen.candidateOutcome. ...
            predictiveEvidenceFallbackBySensorTime));
    fprintf(fileId, ...
        '- Registered minimum-sensor tolerance: `%+.3f%%`\n', ...
        100 * screen.registeredMinimumSensorGainFraction);
end
fprintf(fileId, '- Pass: `%d`\n', m.passesMechanismGate);
end

function value = screenContractVersion(protocolVersion)
switch protocolVersion
    case 136
        value = 'v136-formation-isolated-dual-payload-screen-v1';
    case 137
        value = 'v137-predictive-evidence-fallback-screen-v1';
    case 138
        value = 'v138-post-fusion-label-readout-screen-v1';
    case 139
        value = 'v139-combined-output-safety-screen-v1';
    case 140
        value = 'v140-reference-cardinality-readout-screen-v1';
    otherwise
        error('FormationDualPayloadScreen:UnsupportedProtocol', ...
            'The shared screen received an unsupported version.');
end
end

function version = resolveProtocolVersion(protocol)
switch protocol.id
    case 'formation-isolated-dual-payload-v136-v1'
        version = 136;
    case 'predictive-evidence-fallback-v137-v1'
        version = 137;
    case 'post-fusion-label-readout-v138-v1'
        version = 138;
    case 'combined-output-safety-v139-v1'
        version = 139;
    case 'reference-cardinality-readout-v140-v1'
        version = 140;
    otherwise
        error('FormationDualPayloadScreen:UnsupportedProtocol', ...
            ['The shared screen supports only the registered ', ...
             'V136/V137/V138/V139/V140 protocols.']);
end
end

function gain = safeGain(reference, candidate)
gain = (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
