    actionSpec.trustFactorsByTime;
config.receiverSafeFormationConditionedPayloadMode = ...
    protocol.runtimePayloadMode;
config.receiverSafeFormationConditionedOnlinePolicyEnabled = false;
config.lineageIsolatedRelayEnabled = true;
config.lineageRelayIntraFormationWorkingPayloadEnabled = true;
if strcmp(protocol.id, 'predictive-evidence-fallback-v137-v1')
    config.lineageRelayPredictiveEvidenceFallbackEnabled = true;
    config.lineageRelayPredictiveEvidenceMinimumLogScoreMargin = ...
        protocol.predictiveEvidence.minimumMargin;
