function [artifactPath, screen] = ...
    runFormationIsolatedDualPayloadV136Screen(presetName, options, protocol)
% RUNFORMATIONISOLATEDDUALPAYLOADV136SCREEN Charged dual-payload upper bound.

if nargin < 2 || isempty(options)
    options = struct();
end
if nargin < 3 || isempty(protocol)
    protocol = getFormationIsolatedDualPayloadV136Protocol();
end
protocolVersion = resolveProtocolVersion(protocol);
isV137 = protocolVersion == 137;
isV138 = protocolVersion == 138;
isV139 = protocolVersion == 139;
isV140 = protocolVersion == 140;
gitState = requireCleanSource();
caseInfo = resolveCase(protocol, presetName);
seed = getField(options, 'seed', protocol.pilotSeed);
if seed ~= protocol.pilotSeed
    error('FormationDualPayloadScreen:UnsupportedSeed', ...
        'The first upper-bound screen is frozen to the V134 pilot seed.');
end
anchorTime = ...
    resolveSetTrustSequenceV134PilotAnchor(caseInfo, protocol);
statePath = getField(options, 'v134PilotStatePath', ...
    defaultV134PilotStatePath(presetName, seed, anchorTime));
loaded = load(statePath, 'pilotState');
state = validateV134State( ...
    loaded, presetName, seed, anchorTime, caseInfo);
actionIndex = resolveActionIndex(protocol, caseInfo);
actionSpec = state.actionBank.actions(actionIndex);

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
truth = cropTrackingTruthRfs( ...
    inputs.groundTruthRfs, anchorTime + caseInfo.horizonSteps - 1);
inputs = isolateRuntimeInputs(inputs);
inputs = cropInputs(inputs, anchorTime + caseInfo.horizonSteps - 1);
config = buildRuntimeConfig( ...
    inputs.config, state.referenceCarrierMode, anchorTime, ...
    actionSpec, protocol);
if isV137
    context = buildPredictiveEvidenceFallbackV137ExecutionContext( ...
        presetName, seed, 'candidate', anchorTime, ...
        state.referenceCarrierMode, actionSpec);
elseif isV138
    context = buildPostFusionLabelReadoutV138ExecutionContext( ...
        presetName, seed, 'candidate', anchorTime, ...
        state.referenceCarrierMode, actionSpec);
elseif isV139
    context = buildCombinedOutputSafetyV139ExecutionContext( ...
        presetName, seed, 'candidate', anchorTime, ...
        state.referenceCarrierMode, actionSpec);
elseif isV140
    context = buildReferenceCardinalityReadoutV140ExecutionContext( ...
        presetName, seed, 'candidate', anchorTime, ...
        state.referenceCarrierMode, actionSpec);
else
    context = buildFormationIsolatedDualPayloadV136ExecutionContext( ...
        presetName, seed, 'candidate', anchorTime, ...
        state.referenceCarrierMode, actionSpec);
end
candidate = runContinuation( ...
    inputs, truth, state, anchorTime, config, context, seed, protocol);
reference = state.referenceOutcome;
assertPairedExecution(reference, candidate);

metrics = scoreOutcome( ...
    reference, candidate, state.groupIds, actionSpec, caseInfo, protocol);
screen = struct( ...
    'contractVersion', screenContractVersion(protocolVersion), ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'anchorTime', anchorTime, ...
    'referenceCarrierMode', state.referenceCarrierMode, ...
    'actionIndex', actionIndex, ...
    'actionSpec', actionSpec, ...
    'metrics', metrics, ...
    'registeredMinimumSensorGainFraction', ...
        protocol.screen.minimumSensorGainFraction, ...
    'candidateOutcome', candidate, ...
    'generationGitCommit', gitState.commit, ...
    'mechanismUpperBoundOnly', true, ...
    'communicationMethodClaimAllowed', false, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', ...
        'repository-only-until-joint-cross-scale-gate-passes');
outputDirectory = fullfile(protocol.outputRoot, 'pilot', ...
    strrep(presetName, '-', '_'), ...
    sprintf('seed%d_t%d', seed, anchorTime));
artifactPath = fullfile(outputDirectory, ...
    sprintf('SCREEN_RESULT_V%d.mat', protocolVersion));
atomicSave(artifactPath, 'screen', screen);
writeReport(fullfile(outputDirectory, ...
    sprintf('SCREEN_RESULT_V%d.md', protocolVersion)), ...
    screen, protocolVersion);
fprintf([ ...
    'V%d %s action %02d intervention=%+.3f%% full=%+.3f%% ', ...
    'mature=%+.3f%% min-sensor=%+.3f%% min-formation=%+.3f%% ', ...
    'relay-match=%.3f%% extra-bytes=%+.3f%% pass=%d\n'], ...
    protocolVersion, caseInfo.scaleName, actionIndex, ...
    100 * metrics.interventionGainFraction, ...
    100 * metrics.meanGainFraction, ...
    100 * metrics.matureGainFraction, ...
    100 * metrics.minimumSensorGainFraction, ...
    100 * metrics.minimumFormationGainFraction, ...
    100 * metrics.rejoinedRelayMatchFraction, ...
    100 * metrics.attemptedByteDeltaFraction, ...
    metrics.passesMechanismGate);
end

