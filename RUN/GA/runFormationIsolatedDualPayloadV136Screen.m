config.topologyPolicyFcn = @(context) ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, carrierMode, protocol.routeWeights);
returnTimes = anchorTime + (0:(numel( ...
    actionSpec.formationIdsByTime) - 1));
config.receiverSafeLabelFusionEnabled = true;
config.receiverSafeLabelFusionMode = ...
    'formation-supported-label-plan';
config.receiverSafeExternalActiveTimes = returnTimes;
config.receiverSafeFormationConditionedTimes = returnTimes;
