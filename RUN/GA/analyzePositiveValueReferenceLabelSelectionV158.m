function [reportPath, summary] = ...
        analyzePositiveValueReferenceLabelSelectionV158(options)
% ANALYZEPOSITIVEVALUEREFERENCELABELSELECTIONV158 Replay V157 edit types.
%
% This diagnostic replays the truth-valued V157 selector on the fused
% posterior snapshots captured immediately before each registered rollback.
% It separates explicit tombstones from complete reference-label restores.
% The replay remains privileged and is not a deployable policy.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getPositiveValueReferenceLabelV157Protocol();
candidateScreenPath = getField(options, 'candidateScreenPath', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
referenceScreenPath = getField(options, 'referenceScreenPath', ...
    protocol.shadowCaptureScreenPath);
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.headroomOutputRoot, 'selection_replay'));
reportPath = fullfile(outputRoot, ...
    'POSITIVE_VALUE_REFERENCE_LABEL_SELECTION_V158.md');
matPath = fullfile(outputRoot, ...
    'POSITIVE_VALUE_REFERENCE_LABEL_SELECTION_V158.mat');

if exist(candidateScreenPath, 'file') ~= 2 || ...
        exist(referenceScreenPath, 'file') ~= 2
    error('PositiveValueSelectionV158:MissingScreen', ...
        'Both V157 and static-reference screens are required.');
end
candidateLoaded = load(candidateScreenPath, 'screen');
referenceLoaded = load(referenceScreenPath, 'screen');
candidateScreen = candidateLoaded.screen;
referenceScreen = referenceLoaded.screen;
candidateOutcome = outcomeByAction(candidateScreen, ...
    protocol.candidateActionName);
referenceOutcome = outcomeByAction(referenceScreen, ...
    'reference-full-payload');
candidatePages = candidateOutcome.fusedPosteriorSnapshotsByTime;
referencePages = referenceOutcome.fusedPosteriorSnapshotsByTime;
if numel(candidatePages) ~= protocol.horizonSteps || ...
        numel(referencePages) ~= protocol.horizonSteps
    error('PositiveValueSelectionV158:SnapshotHorizonMismatch', ...
        'The captured posterior horizons do not match V157.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    candidateScreen.presetName, candidateScreen.seed);
oracleModel = inputs.model;
if ~isfield(oracleModel, 'dynamicTopologyScenario') || ...
        ~isstruct(oracleModel.dynamicTopologyScenario)
    oracleModel.dynamicTopologyScenario = struct();
end
oracleModel.dynamicTopologyScenario.targetTrajectories = ...
    inputs.targetTrajectories;
groupIds = reshape(candidateScreen.sensorGroupIds, 1, []);
if ~isequal(groupIds, reshape(referenceScreen.sensorGroupIds, 1, []))
    error('PositiveValueSelectionV158:GroupMismatch', ...
        'Candidate and reference sensor groups differ.');
end

rows = repmat(emptyRow(), 1, 0);
for pageIdx = 1:protocol.horizonSteps
    formationIds = protocol.rollbackFormationIdsByTime{pageIdx};
    sensorIds = find(ismember(groupIds, formationIds));
    for sensorIdx = sensorIds
        [~, details] = selectPositiveValueReferenceLmbLabels( ...
            candidatePages{pageIdx}{sensorIdx}, ...
            referencePages{pageIdx}{sensorIdx}, ...
            protocol.maximumLabelEdits, 1e-2, oracleModel, ...
            protocol.rollbackTimes(pageIdx));
        row = emptyRow();
        row.page = pageIdx;
        row.time = protocol.rollbackTimes(pageIdx);
        row.formation = groupIds(sensorIdx);
        row.sensor = sensorIdx;
        row.candidateLabelCount = details.candidateLabelCount;
        row.selectedLabelCount = details.selectedLabelCount;
        row.tombstoneCount = nnz(details.selectedTombstone);
        row.referenceLabelCount = details.selectedLabelCount - ...
            row.tombstoneCount;
        row.initialEospa = details.initialEospa;
        row.finalEospa = details.finalEospa;
        row.currentStepReduction = ...
            details.initialEospa - details.finalEospa;
        row.estimatedPayloadBytes = details.estimatedPayloadBytes;
        row.selectedLabels = details.selectedLabels;
        row.selectedTombstone = details.selectedTombstone;
        row.marginalEospaReduction = ...
            details.marginalEospaReduction;
        row.selectedLabelText = formatSelectedLabels(details);
        rows(end + 1) = row; %#ok<AGROW>
    end
end
if numel(rows) ~= 36
    error('PositiveValueSelectionV158:CellCountDrift', ...
        'The V157 replay must cover exactly 36 receiver-time cells.');
end

selectedCounts = [rows.selectedLabelCount];
tombstoneCounts = [rows.tombstoneCount];
referenceCounts = [rows.referenceLabelCount];
summary = struct();
summary.contractVersion = ...
    'positive-value-reference-label-selection-v158-v1';
summary.candidateScreenPath = candidateScreenPath;
summary.referenceScreenPath = referenceScreenPath;
summary.candidateOutcomeCommit = candidateScreen.generationGitCommit;
summary.referenceOutcomeCommit = referenceScreen.generationGitCommit;
summary.presetName = candidateScreen.presetName;
summary.seed = candidateScreen.seed;
summary.rollbackCellCount = numel(rows);
summary.rows = rows;
summary.selectedLabelCount = sum(selectedCounts);
summary.tombstoneCount = sum(tombstoneCounts);
summary.referenceLabelCount = sum(referenceCounts);
summary.zeroEditCellCount = nnz(selectedCounts == 0);
summary.capacityHistogram = arrayfun( ...
    @(count) nnz(selectedCounts == count), ...
    0:protocol.maximumLabelEdits);
summary.actualEstimatedPayloadBytes = ...
    sum([rows.estimatedPayloadBytes]);
summary.frozenWorstCasePayloadBytes = ...
    protocol.additionalPosteriorPayloadBytes;
summary.payloadBoundUtilizationPercent = 100 * ...
    summary.actualEstimatedPayloadBytes / ...
    max(summary.frozenWorstCasePayloadBytes, eps);
summary.totalCurrentStepEospaReduction = ...
    sum([rows.currentStepReduction]);
marginalByRank = zeros(1, protocol.maximumLabelEdits);
allMarginalReductions = zeros(1, 0);
for row = rows
    count = numel(row.marginalEospaReduction);
    marginalByRank(1:count) = marginalByRank(1:count) + ...
        row.marginalEospaReduction;
    allMarginalReductions = [allMarginalReductions, ...
        row.marginalEospaReduction]; %#ok<AGROW>
end
summary.marginalEospaReductionByRank = marginalByRank;
summary.marginalGainFractionByRankPercent = 100 * marginalByRank / ...
    max(sum(marginalByRank), eps);
summary.marginalThresholds = [1, 0.1, 0.01, 0.001];
summary.marginalCountAboveThreshold = arrayfun( ...
    @(threshold) nnz(allMarginalReductions > threshold), ...
    summary.marginalThresholds);
summary.marginalGainFractionAboveThresholdPercent = arrayfun( ...
    @(threshold) 100 * sum(allMarginalReductions( ...
        allMarginalReductions > threshold)) / ...
        max(sum(allMarginalReductions), eps), ...
    summary.marginalThresholds);
summary.truthUsed = true;
summary.deployable = false;
summary.evidenceBoundary = [ ...
    'V158 deterministically replays the privileged V157 selector on ', ...
    'captured pre-rollback candidate and static-reference posteriors. ', ...
    'It identifies edit type and capacity demand only. It does not show ', ...
    'that a runtime node can source the selected reference label or ', ...
    'predict its value without truth.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary);
fprintf('V158 selection replay: %s\n', reportPath);
end

function outcome = outcomeByAction(screen, actionName)
idx = find(strcmp({screen.records.actionName}, actionName), 1);
if isempty(idx)
    error('PositiveValueSelectionV158:MissingAction', ...
        'The requested action is missing: %s', actionName);
end
outcome = screen.outcomes(idx);
if isempty(outcome.fusedPosteriorSnapshotsByTime)
    error('PositiveValueSelectionV158:MissingSnapshots', ...
        'The requested action has no fused posterior snapshots.');
end
end

function text = formatSelectedLabels(details)
tokens = cell(1, details.selectedLabelCount);
for idx = 1:details.selectedLabelCount
    if details.selectedTombstone(idx)
        mode = 'delete';
    else
        mode = 'restore';
    end
    tokens{idx} = sprintf('(%d,%d):%s:%0.3f', ...
        details.selectedLabels(1, idx), ...
        details.selectedLabels(2, idx), mode, ...
        details.marginalEospaReduction(idx));
end
text = strjoin(tokens, ', ');
if isempty(text)
    text = '--';
end
end

function writeReport(path, summary)
fileId = fopen(path, 'w');
if fileId < 0
    error('PositiveValueSelectionV158:ReportOpenFailed', ...
        'Could not open the V158 report.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '# V158 positive-value label selection replay\n\n');
fprintf(fileId, '- Preset / seed: `%s / %d`\n', ...
    summary.presetName, summary.seed);
fprintf(fileId, '- Registered receiver-time cells: `%d`\n', ...
    summary.rollbackCellCount);
fprintf(fileId, '- Selected complete-label edits: `%d`\n', ...
    summary.selectedLabelCount);
fprintf(fileId, '- Deletes / restores: `%d / %d`\n', ...
    summary.tombstoneCount, summary.referenceLabelCount);
fprintf(fileId, '- Cells selecting 0..4 edits: `%s`\n', ...
    mat2str(summary.capacityHistogram));
fprintf(fileId, '- Zero-edit cells: `%d`\n', ...
    summary.zeroEditCellCount);
fprintf(fileId, ['- Replayed actual / frozen worst-case payload: ', ...
    '`%d / %d B` (`%.2f%%` utilization)\n'], ...
    summary.actualEstimatedPayloadBytes, ...
    summary.frozenWorstCasePayloadBytes, ...
    summary.payloadBoundUtilizationPercent);
fprintf(fileId, '- Sum of accepted current-step E-OSPA reductions: `%.6f`\n\n', ...
    summary.totalCurrentStepEospaReduction);
fprintf(fileId, '- Marginal reduction by selection rank: `%s`\n', ...
    mat2str(summary.marginalEospaReductionByRank, 6));
fprintf(fileId, '- Gain share by selection rank: `%s%%`\n', ...
    mat2str(summary.marginalGainFractionByRankPercent, 5));
fprintf(fileId, '- Marginal thresholds: `%s`\n', ...
    mat2str(summary.marginalThresholds));
fprintf(fileId, '- Edits above thresholds: `%s`\n', ...
    mat2str(summary.marginalCountAboveThreshold));
fprintf(fileId, '- Gain retained above thresholds: `%s%%`\n\n', ...
    mat2str(summary.marginalGainFractionAboveThresholdPercent, 5));
fprintf(fileId, ['| t | Formation | Sensor | Candidates | Selected | ', ...
    'Delete | Restore | E-OSPA before | E-OSPA after | Bytes | Edits |\n']);
fprintf(fileId, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|\n']);
for row = summary.rows
    fprintf(fileId, ['| %d | %d | %d | %d | %d | %d | %d | ', ...
        '%.4f | %.4f | %d | %s |\n'], ...
        row.time, row.formation, row.sensor, ...
        row.candidateLabelCount, row.selectedLabelCount, ...
        row.tombstoneCount, row.referenceLabelCount, ...
        row.initialEospa, row.finalEospa, ...
        row.estimatedPayloadBytes, row.selectedLabelText);
end
fprintf(fileId, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function row = emptyRow()
row = struct( ...
    'page', 0, ...
    'time', 0, ...
    'formation', 0, ...
    'sensor', 0, ...
    'candidateLabelCount', 0, ...
    'selectedLabelCount', 0, ...
    'tombstoneCount', 0, ...
    'referenceLabelCount', 0, ...
    'initialEospa', 0, ...
    'finalEospa', 0, ...
    'currentStepReduction', 0, ...
    'estimatedPayloadBytes', 0, ...
    'selectedLabels', zeros(2, 0), ...
    'selectedTombstone', false(1, 0), ...
    'marginalEospaReduction', zeros(1, 0), ...
    'selectedLabelText', '');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
