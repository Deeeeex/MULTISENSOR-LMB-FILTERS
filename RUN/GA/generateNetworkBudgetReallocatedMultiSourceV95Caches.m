function [reportPath, result] = ...
    generateNetworkBudgetReallocatedMultiSourceV95Caches(options)
% GENERATENETWORKBUDGETREALLOCATEDMULTISOURCEV95CACHES Corrected states.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNetworkBudgetReallocatedMultiSourceV95Protocol();
overwrite = logical(getField(options, 'overwrite', false));
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NetworkBudgetV95:DirtySource', ...
        'V95 cache generation requires clean frozen source.');
end
sourceProtocol = getBraidedHandoverOpportunityV84Protocol();
records = repmat(struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'cacheRoot', '', 'cachePath', '', ...
    'receiverMode', '', 'reusedExisting', false), ...
    1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    cacheTimes = unique([ ...
        entry.currentTime, max(sourceProtocol.snapshotTimes)], 'stable');
    [cachePaths, summary] = ...
        generateFormationH3ReferenceStateCaches( ...
            entry.presetName, entry.seed, cacheTimes, struct( ...
                'protocol', sourceProtocol, ...
                'cacheRoot', entry.cacheRoot, ...
                'overwrite', overwrite, ...
                'receiverMode', protocol.receiverMode));
    records(caseIdx) = struct( ...
        'scaleName', entry.scaleName, ...
        'presetName', entry.presetName, ...
        'seed', entry.seed, ...
        'currentTime', entry.currentTime, ...
        'cacheRoot', entry.cacheRoot, ...
        'cachePath', cachePaths{find( ...
            cacheTimes == entry.currentTime, 1)}, ...
        'receiverMode', summary.missingLabelFusionMode, ...
        'reusedExisting', summary.reusedExisting);
end

result = struct();
result.contractVersion = ...
    'network-budget-reallocated-multi-source-v95-cache-result-v1';
result.protocolId = protocol.id;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.receiverMode = protocol.receiverMode;
result.records = records;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
if exist(protocol.outputRoot, 'dir') ~= 7
    mkdir(protocol.outputRoot);
end
matPath = fullfile(protocol.outputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_CACHE_RESULT.mat');
reportPath = fullfile(protocol.outputRoot, ...
    'NETWORK_BUDGET_REALLOCATED_MULTI_SOURCE_V95_CACHE_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V95 corrected cache result: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkBudgetV95:WriteFailed', ...
        'Could not create the V95 cache report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V95 corrected braided-handover caches\n\n');
fprintf(fid, '- Receiver semantics: `%s`\n\n', result.receiverMode);
fprintf(fid, '| Scale | Scenario / seed / time | Reused |\n');
fprintf(fid, '|:--|:--|:--:|\n');
for record = result.records
    fprintf(fid, '| %s | `%s / %d / %d` | %d |\n', ...
        record.scaleName, record.presetName, record.seed, ...
        record.currentTime, record.reusedExisting);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
