function [reportPath, result] = ...
        analyzeCacheFreeDonorOfferCoverageV233(options)
% ANALYZECACHEFREEDONOROFFERCOVERAGEV233 Audit bounded donor enumeration.
%
% This is a same-state structural screen.  It checks whether a donor-only,
% cache-free offer schedule covers the opened V220 teacher labels and all
% active labels at each retained donor source under the exact byte credit.
% It does not run an online coordinator or establish a tracking gain.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCacheFreeDonorOfferCoverageV233Protocol();
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices)
    error('CacheFreeDonorOfferV233:InvalidRequest', ...
        'A causal V220 candidate bank and unique teacher rows are required.');
end

loaded = load(candidateBankPath, 'result');
bank = loaded.result;
required = {'contractVersion', 'presetName', 'seed', 'currentTime', ...
    'donorFormationId', 'sourceScreenPath', 'referencePageBytes', ...
    'admissionNetSavingBytes', 'beneficiaryDetails', 'records'};
if ~isstruct(bank) || ~isscalar(bank) || ...
        any(~isfield(bank, required)) || ...
        ~strcmp(bank.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        getField(bank, 'truthUsedForCandidateFeatures', true) || ...
        getField(bank, 'futureInformationUsedForCandidateFeatures', true)
    error('CacheFreeDonorOfferV233:BankContract', ...
        'The causal V220 candidate-bank contract is required.');
end
if isempty(recordIndices)
    selectedRows = 1:numel(bank.records);
else
    [present, selectedRows] = ismember( ...
        recordIndices, [bank.records.recordIndex]);
    if ~all(present)
        error('CacheFreeDonorOfferV233:UnknownRecord', ...
            'A requested teacher row is absent from the bank.');
    end
end
teacherRows = bank.records(selectedRows);

screenLoaded = load(bank.sourceScreenPath, 'screen');
screen = screenLoaded.screen;
timeIndex = find(screen.returnTimes == bank.currentTime, 1);
if isempty(timeIndex) || ~screen.capturePosteriorSnapshotsEnabled || ...
        screen.referenceSubsetIndex < 1 || ...
        screen.referenceSubsetIndex > numel(screen.outcomes) || ...
        ~isfield(screen, 'sensorGroupIds')
    error('CacheFreeDonorOfferV233:SnapshotContract', ...
        'The same-state reference posterior snapshot is unavailable.');
end
reference = screen.outcomes(screen.referenceSubsetIndex);
posteriors = reference.localPosteriorSnapshotsByTime{timeIndex};
groupIds = reshape(screen.sensorGroupIds, 1, []);
if ~iscell(posteriors) || numel(posteriors) ~= numel(groupIds)
    error('CacheFreeDonorOfferV233:SnapshotContract', ...
        'One local posterior per registered sensor is required.');
end
model = struct('xDimension', inferStateDimension(posteriors));

audits = repmat(emptyAudit(), 1, numel(teacherRows));
for auditIndex = 1:numel(teacherRows)
    teacher = teacherRows(auditIndex);
    receiverIds = reshape(teacher.candidate.receiverIds, 1, []);
    commonRemoteSources = sourceIdsForFormation( ...
        bank, teacher.beneficiaryFormationId, receiverIds);
    donorMembers = find(groupIds == bank.donorFormationId);
    sourceIds = intersect( ...
        commonRemoteSources, donorMembers, 'stable');
    if isempty(sourceIds) || ~ismember(teacher.sourceId, sourceIds)
        error('CacheFreeDonorOfferV233:DonorScope', ...
            'The teacher source is absent from the donor-only source set.');
    end
    activeCounts = arrayfun(@(sourceId) countActiveLabels( ...
        posteriors{sourceId}, protocol.coverage.minimumActiveExistence), ...
        sourceIds);
    bytePlan = planCacheFreeDonorOfferCoverageV233( ...
        sourceIds, activeCounts, teacher.payloadAttemptedBytes, ...
        bank.admissionNetSavingBytes, bank.referencePageBytes, struct());

    partitions = cell(1, numel(sourceIds));
    for sourcePosition = 1:numel(sourceIds)
        partitions{sourcePosition} = ...
            partitionCacheFreeDonorOffersV233( ...
                posteriors{sourceIds(sourcePosition)}, model, ...
                bytePlan, sourceIds(sourcePosition));
    end
    teacherPosition = find(sourceIds == teacher.sourceId, 1);
    teacherPartition = partitions{teacherPosition};
    teacherLabel = reshape(teacher.label, 2, 1);
    teacherPhase = labelPhase( ...
        teacherPartition.phaseLabels, teacherLabel);
    teacherActive = labelSelected( ...
        activeLabels(posteriors{teacher.sourceId}, ...
            protocol.coverage.minimumActiveExistence), ...
        teacherLabel);
    allActiveCovered = all(cellfun( ...
        @(item) item.coverageComplete, partitions));
    payloadFeasible = all(bytePlan.candidateFeasibleMask);
    audits(auditIndex) = struct( ...
        'recordIndex', teacher.recordIndex, ...
        'beneficiaryFormationId', teacher.beneficiaryFormationId, ...
        'sourceId', teacher.sourceId, ...
        'label', teacherLabel, ...
        'receiverIds', receiverIds, ...
        'donorSourceIds', sourceIds, ...
        'activeLabelCounts', activeCounts, ...
        'teacherLabelActive', teacherActive, ...
        'teacherLabelCovered', teacherPhase > 0, ...
        'teacherOfferPhase', teacherPhase, ...
        'allActiveDonorLabelsCovered', allActiveCovered, ...
        'payloadFeasible', payloadFeasible, ...
        'partitions', {partitions}, ...
        'bytePlan', bytePlan);
end

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v233', 'cache_free_donor_offer_coverage', ...
    sprintf('%s_seed%d_t%d_donor_f%d', ...
        strrep(bank.presetName, '-', '_'), bank.seed, ...
        bank.currentTime, bank.donorFormationId))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
result = struct();
result.contractVersion = ...
    'cache-free-donor-offer-coverage-v233-v1';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.sourceScreenPath = bank.sourceScreenPath;
result.presetName = bank.presetName;
result.seed = bank.seed;
result.currentTime = bank.currentTime;
result.donorFormationId = bank.donorFormationId;
result.teacherAudits = audits;
result.teacherLabelCount = numel(audits);
result.coveredTeacherLabelCount = nnz([audits.teacherLabelCovered]);
result.teacherRecall = result.coveredTeacherLabelCount / ...
    max(result.teacherLabelCount, 1);
result.allTeacherLabelsCovered = ...
    result.coveredTeacherLabelCount == result.teacherLabelCount;
result.allActiveDonorLabelsCovered = ...
    all([audits.allActiveDonorLabelsCovered]);
result.allPayloadsByteFeasible = all([audits.payloadFeasible]);
result.sameStateCoverageScreenPassed = ...
    result.allTeacherLabelsCovered && ...
    result.allActiveDonorLabelsCovered && ...
    result.allPayloadsByteFeasible;
result.actualRuntimeBeneficiaryCacheRequired = false;
result.teacherLabelsUsedOnlyForCoverageAudit = true;
result.truthUsedForOfferSchedule = false;
result.futureInformationUsedForOfferSchedule = false;
result.numericLabelIdentifiersUsedAsValueFeatures = false;
result.onlineCoordinatorImplemented = false;
result.trackingExperimentAuthorized = ...
    result.sameStateCoverageScreenPassed;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'CACHE_FREE_DONOR_OFFER_COVERAGE_V233.mat');
reportPath = fullfile(outputRoot, ...
    'CACHE_FREE_DONOR_OFFER_COVERAGE_V233.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V233 cache-free donor-offer coverage: %s\n', reportPath);
end

function ids = sourceIdsForFormation(bank, formationId, receiverIds)
match = find([bank.beneficiaryDetails.formationId] == formationId, 1);
if isempty(match) || ...
        ~isfield(bank.beneficiaryDetails(match), 'synopsisSensorIds')
    error('CacheFreeDonorOfferV233:SourceSet', ...
        'The beneficiary common-source set is unavailable.');
end
participants = reshape( ...
    bank.beneficiaryDetails(match).synopsisSensorIds, 1, []);
ids = setdiff(participants, reshape(receiverIds, 1, []), 'stable');
end

function count = countActiveLabels(posterior, threshold)
if isempty(posterior)
    count = 0;
    return;
end
count = nnz([posterior.numberOfGmComponents] > 0 & ...
    [posterior.r] >= threshold);
end

function labels = activeLabels(posterior, threshold)
if isempty(posterior)
    labels = zeros(2, 0);
    return;
end
active = [posterior.numberOfGmComponents] > 0 & ...
    [posterior.r] >= threshold;
objects = posterior(active);
labels = zeros(2, numel(objects));
for objectIndex = 1:numel(objects)
    labels(:, objectIndex) = [objects(objectIndex).birthTime; ...
        objects(objectIndex).birthLocation];
end
end

function phase = labelPhase(phaseLabels, label)
phase = 0;
for phaseIndex = 1:numel(phaseLabels)
    if labelSelected(phaseLabels{phaseIndex}, label)
        phase = phaseIndex;
        return;
    end
end
end

function present = labelSelected(labels, label)
present = ~isempty(labels) && any(all(labels == label, 1));
end

function dimension = inferStateDimension(posteriors)
dimension = 0;
for sensorIndex = 1:numel(posteriors)
    objects = posteriors{sensorIndex};
    for objectIndex = 1:numel(objects)
        if objects(objectIndex).numberOfGmComponents > 0 && ...
                ~isempty(objects(objectIndex).mu)
            dimension = numel(objects(objectIndex).mu{1});
            break;
        end
    end
    if dimension > 0
        break;
    end
end
if dimension < 2
    error('CacheFreeDonorOfferV233:StateDimension', ...
        'A position-bearing Gaussian-mixture state is required.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CacheFreeDonorOfferV233:WriteReport', ...
        'Could not write the V233 coverage report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V233 cache-free donor-offer coverage screen\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Donor formation: `F%d`\n', result.donorFormationId);
fprintf(fid, '- Teacher coverage: `%d / %d = %.1f%%`\n', ...
    result.coveredTeacherLabelCount, result.teacherLabelCount, ...
    100 * result.teacherRecall);
fprintf(fid, '- All retained donor-source active labels covered: `%d`\n', ...
    result.allActiveDonorLabelsCovered);
fprintf(fid, '- Runtime beneficiary cache required: `%d`\n\n', ...
    result.actualRuntimeBeneficiaryCacheRequired);
fprintf(fid, ['| Row | Beneficiary | Source / label | Donor sources | ', ...
    'Active labels/source | Phases / offers | Teacher phase | ', ...
    'Control | Payload | Certified net saving | Pass |\n']);
fprintf(fid, ['|--:|--:|:--|:--|:--|:--|--:|--:|--:|--:|:--|\n']);
for audit = result.teacherAudits
    p = audit.bytePlan;
    fprintf(fid, ['| %d | F%d | S%d / `[%d,%d]` | `%s` | `%s` | ', ...
        '`%d x %d` | %d | %d B | %.0f B | %.0f B | `%d` |\n'], ...
        audit.recordIndex, audit.beneficiaryFormationId, ...
        audit.sourceId, audit.label(1), audit.label(2), ...
        integerText(audit.donorSourceIds), ...
        integerText(audit.activeLabelCounts), ...
        p.phaseCount, p.offersPerSourcePerPhase, ...
        audit.teacherOfferPhase, p.controlAttemptedBytes, ...
        p.candidatePayloadBytes(1), ...
        p.certifiedNetSavingBytes(1), ...
        audit.teacherLabelCovered && ...
            audit.allActiveDonorLabelsCovered && ...
            audit.payloadFeasible);
end
fprintf(fid, '\n## Decision\n\n');
if result.sameStateCoverageScreenPassed
    fprintf(fid, ['The two-phase donor-only schedule covers every active ', ...
        'label and every opened teacher label while preserving positive ', ...
        'certified saving. The proposal layer may advance to an online ', ...
        'beneficiary coordinator; no tracking gain is claimed here.\n']);
else
    fprintf(fid, ['The bounded schedule misses an active/teacher label or ', ...
        'exceeds the byte credit. Redesign before online integration.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = integerText(values)
parts = arrayfun(@(value) sprintf('%d', value), ...
    reshape(values, 1, []), 'UniformOutput', false);
text = strjoin(parts, ',');
end

function value = emptyAudit()
value = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'receiverIds', zeros(1, 0), ...
    'donorSourceIds', zeros(1, 0), ...
    'activeLabelCounts', zeros(1, 0), ...
    'teacherLabelActive', false, ...
    'teacherLabelCovered', false, 'teacherOfferPhase', 0, ...
    'allActiveDonorLabelsCovered', false, ...
    'payloadFeasible', false, 'partitions', {{}}, ...
    'bytePlan', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
