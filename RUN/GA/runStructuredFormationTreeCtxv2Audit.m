function result = runStructuredFormationTreeCtxv2Audit(options)
% RUNSTRUCTUREDFORMATIONTREECTXV2AUDIT Execute the preregistered M24 audit.
%
% This entry point does not generate data or tune on validation seeds. It
% first checks the exact-projector attainability and learned proxy gates.
% A timestamped proxy-only model is frozen only when both training and
% validation pass. Closed-loop tracking remains a separate evidence gate.

if nargin < 1 || isempty(options)
    options = struct();
end
cacheDirectory = getField(options, 'cacheDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'cache'));
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
protocol = getStructuredFormationTreeCtxv2Protocol(cacheDirectory);

missingMask = cellfun(@(path) exist(path, 'file') ~= 2, ...
    protocol.datasetPaths);
if any(missingMask)
    missingPaths = protocol.datasetPaths(missingMask);
    error('Missing preregistered ctxv2 dataset: %s', missingPaths{1});
end

auditOptions = struct( ...
    'trainDatasetIndices', protocol.trainDatasetIndices, ...
    'validationDatasetIndices', ...
        protocol.validationDatasetIndices, ...
    'sourceWeight', protocol.sourceWeight, ...
    'baselineMode', protocol.baselineMode, ...
    'baselinePhase', protocol.baselinePhase, ...
    'anchorTime', protocol.anchorTime, ...
    'featureContextMode', protocol.featureContextMode, ...
    'modelFamily', protocol.modelFamily, ...
    'structuredLambdaGrid', protocol.structuredLambdaGrid, ...
    'structuredEpochCount', protocol.structuredEpochCount, ...
    'structuredLearningRate', protocol.structuredLearningRate, ...
    'structuredLossScale', protocol.structuredLossScale, ...
    'structuredMaximumCoefficientNorm', ...
        protocol.structuredMaximumCoefficientNorm, ...
    'minimumAggregateRiskImprovement', ...
        protocol.minimumAggregateRiskImprovement, ...
    'maximumHarmfulEdgeFraction', ...
        protocol.maximumHarmfulEdgeFraction, ...
    'maximumHarmfulEdgeCount', ...
        protocol.maximumHarmfulEdgeCount, ...
    'minimumOracleCaptureFraction', ...
        protocol.minimumOracleCaptureFraction, ...
    'maximumAttemptedByteDeviation', ...
        protocol.maximumAttemptedByteDeviation, ...
    'enforcePerEdgeSafety', protocol.enforcePerEdgeSafety, ...
    'requirePreviousUnionStrongConnectivity', ...
        protocol.requirePreviousUnionStrongConnectivity, ...
    'excludedFeatureNames', {protocol.excludedFeatureNames}, ...
    'outputDirectory', outputDirectory, ...
    'writeReport', true);

[auditReportPath, auditResult] = ...
    auditLearnedFormationTreeProxy( ...
        protocol.datasetPaths, auditOptions);
result = struct( ...
    'generatedAt', datestr(now, 31), ...
    'protocol', protocol, ...
    'auditReportPath', auditReportPath, ...
    'auditResult', auditResult, ...
    'artifactWritten', false, ...
    'modelPath', '', ...
    'modelReportPath', '');

fprintf('Training oracle gate attainable: %d\n', ...
    auditResult.trainingOracleGateAttainable);
fprintf('Validation oracle gate attainable: %d\n', ...
    auditResult.validationOracleGateAttainable);
fprintf('Training learned proxy gate passed: %d\n', ...
    auditResult.trainingGatePassed);
fprintf('Validation learned proxy gate passed: %d\n', ...
    auditResult.validationGatePassed);

if ~auditResult.trainingOracleGateAttainable || ...
        ~auditResult.validationOracleGateAttainable
    fprintf([ ...
        'No artifact written: the exact projector cannot meet the ', ...
        'minimum-gain gate on every declared block.\n']);
    return;
end
if ~auditResult.trainingGatePassed || ...
        ~auditResult.validationGatePassed
    fprintf([ ...
        'No artifact written: the learned proxy candidate failed the ', ...
        'preregistered training or validation gate.\n']);
    return;
end

timestamp = datestr(now, 'yyyymmdd_HHMMSS');
modelPath = fullfile(outputDirectory, 'models', sprintf( ...
    'structured_formation_tree_m24_ctxv2_%s.mat', timestamp));
modelReportPath = fullfile(outputDirectory, sprintf( ...
    'STRUCTURED_FORMATION_TREE_M24_CTXV2_%s.md', timestamp));
[modelPath, modelReportPath] = ...
    trainStructuredFormationTreeRoutingPolicy( ...
        protocol.datasetPaths, struct( ...
            'modelPath', modelPath, ...
            'reportPath', modelReportPath, ...
            'requireValidationGate', true, ...
            'auditOptions', auditOptions));
result.artifactWritten = true;
result.modelPath = modelPath;
result.modelReportPath = modelReportPath;
fprintf([ ...
    'Proxy-only artifact frozen. Closed-loop validation is still ', ...
    'required before deployment claims.\n']);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
