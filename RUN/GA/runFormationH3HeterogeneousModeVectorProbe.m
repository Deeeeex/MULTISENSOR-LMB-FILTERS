function [reportPath, probe] = ...
    runFormationH3HeterogeneousModeVectorProbe(options)
% RUNFORMATIONH3HETEROGENEOUSMODEVECTORPROBE Radius-two terminal oracle.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3HeterogeneousModeVectorProbeProtocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official heterogeneous mode-vector probe requires clean source.');
end
outputRoot = getField(options, 'outputDirectory', protocol.outputRoot);
probePath = fullfile(outputRoot, ...
    'formation_h3_heterogeneous_mode_vector_radius2_v1.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_H3_HETEROGENEOUS_MODE_VECTOR_RADIUS2_V1.md');
probeExists = exist(probePath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(probeExists, reportExists)
    error('Heterogeneous mode-vector probe artifacts are partial.');
elseif probeExists
    loaded = load(probePath, 'probe');
    if ~isfield(loaded, 'probe') || ...
            ~strcmp(loaded.probe.protocolId, protocol.id) || ...
            ~strcmp(loaded.probe.generationGitCommit, gitState.commit)
        error('Heterogeneous mode-vector probe provenance mismatch.');
    end
    probe = loaded.probe;
    fprintf('Reused heterogeneous mode-vector probe: %s\n', probePath);
    return;
end

[candidateModes, candidateActions, candidateDistances] = ...
    enumerateFormationModeVectorHammingBall( ...
        protocol.centerModeVector, protocol.modeCount, ...
        protocol.maximumHammingDistance);
if size(candidateModes, 1) ~= protocol.expectedCandidateCount || ...
        ~isequal(formationModeVectorToActionIndex( ...
            candidateModes, protocol.modeCount), candidateActions') || ...
        ~isequal(formationModeVectorToActionIndex( ...
            protocol.prefixModeVectors, protocol.modeCount)', ...
                protocol.prefixActionIndices) || ...
        formationModeVectorToActionIndex( ...
            protocol.centerModeVector, protocol.modeCount) ~= ...
                protocol.centerActionIndex
    error('Heterogeneous mode-vector candidate contract changed.');
end

reference = protocol.referenceActionIndex;
prefix = protocol.prefixActionIndices;
sequences = [ ...
    reference, reference, reference; ...
    prefix, reference; ...
    repmat(prefix, numel(candidateActions), 1), candidateActions(:)];
screenDirectory = fullfile(outputRoot, 'screen');
screenOptions = struct( ...
    'cacheRoot', protocol.cacheRoot, ...
    'outputDirectory', screenDirectory, ...
    'interventionBankType', protocol.interventionBankType, ...
    'actionSequenceIndices', sequences, ...
    'writeReport', true);
[screenReportPath, screen] = ...
    runFormationModeH3OpenedReturnScreen( ...
        protocol.presetName, protocol.seed, ...
        protocol.currentTime, screenOptions);
if screen.bank.actionCount ~= protocol.expectedActionCount || ...
        ~isequal(screen.bank.actionModes(candidateActions, :), ...
            candidateModes)
    error('Heterogeneous mode-vector action bank changed.');
end
targets = targetMatrix(screen);
prefixRow = find(all(screen.actionSequenceIndices == ...
    [prefix, reference], 2));
centerRow = find(all(screen.actionSequenceIndices == ...
    [prefix, protocol.centerActionIndex], 2));
if numel(prefixRow) ~= 1 || numel(centerRow) ~= 1 || ...
        max(abs(targets(prefixRow, :) - ...
            protocol.expectedPrefixTargets)) > ...
                protocol.reproductionTolerancePercent || ...
        max(abs(targets(centerRow, :) - ...
            protocol.expectedCenterTargets)) > ...
                protocol.reproductionTolerancePercent
    error('Heterogeneous mode-vector probe failed reproduction gates.');
end

candidateRows = 3:size(sequences, 1);
strictFeasible = all(targets >= -1e-12, 2);
strictIndices = find(strictFeasible);
[strictGain, localBest] = max(targets(strictIndices, 1));
strictOracleIndex = strictIndices(localBest);
candidateStrict = strictFeasible(candidateRows);
candidateTargets = targets(candidateRows, :);
normalizedDeficits = max(-candidateTargets, 0) ./ ...
    protocol.constraintScalesPercent;
maximumDeficit = max(normalizedDeficits, [], 2);
totalDeficit = sum(normalizedDeficits, 2);
ranking = [ ...
    maximumDeficit, totalDeficit, ...
    -candidateTargets(:, 1), candidateActions(:)];
[~, rankOrder] = sortrows(ranking, [1, 2, 3, 4]);
closestCandidateIndex = rankOrder(1);
[bestConsensus, bestConsensusIndex] = max(candidateTargets(:, 4));

probe = struct();
probe.contractVersion = ...
    'formation-h3-heterogeneous-mode-vector-probe-result-v1';
probe.protocolId = protocol.id;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
probe.cacheProtocolId = protocol.cacheProtocolId;
probe.cacheGenerationGitCommit = ...
    protocol.cacheGenerationGitCommit;
probe.presetName = protocol.presetName;
probe.seed = protocol.seed;
probe.currentTime = protocol.currentTime;
probe.sequences = sequences;
probe.targets = targets;
probe.candidateModeVectors = candidateModes;
probe.candidateActionIndices = candidateActions;
probe.candidateHammingDistances = candidateDistances;
probe.candidateTargets = candidateTargets;
probe.candidateStrictFeasible = candidateStrict;
probe.candidateStrictFeasibleCount = nnz(candidateStrict);
probe.normalizedConstraintDeficits = normalizedDeficits;
probe.maximumNormalizedDeficit = maximumDeficit;
probe.totalNormalizedDeficit = totalDeficit;
probe.candidateRankOrder = rankOrder;
probe.closestCandidateIndex = closestCandidateIndex;
probe.closestModeVector = candidateModes(closestCandidateIndex, :);
probe.closestTargets = candidateTargets(closestCandidateIndex, :);
probe.bestConsensusCandidateIndex = bestConsensusIndex;
probe.bestConsensusModeVector = candidateModes(bestConsensusIndex, :);
probe.bestConsensusTargets = candidateTargets(bestConsensusIndex, :);
probe.bestConsensusGainPercent = bestConsensus;
probe.strictFeasible = strictFeasible;
probe.strictFeasibleSequenceCount = nnz(strictFeasible);
probe.strictOracleIndex = strictOracleIndex;
probe.strictOracleSequence = sequences(strictOracleIndex, :);
probe.strictOracleTargets = targets(strictOracleIndex, :);
probe.strictOracleGainPercent = strictGain;
probe.strongSafeSequenceFound = ...
    strictGain >= protocol.strongGainPercent - 1e-12;
probe.screen = screen;
probe.screenReportPath = screenReportPath;
probe.actionSelectionUsesTruth = protocol.actionSelectionUsesTruth;
probe.actionSelectionUsesFutureMeasurements = ...
    protocol.actionSelectionUsesFutureMeasurements;
probe.runtimePolicyUsesTruth = protocol.runtimePolicyUsesTruth;
probe.openedTrainingMechanismProbeOnly = true;
probe.finalModelTrainingAuthorized = false;
probe.validationClaimAllowed = false;
probe.evidenceBoundary = protocol.evidenceBoundary;
probe.probePath = probePath;
probe.reportPath = reportPath;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', probePath, 'probe');
writeReport(reportPath, probe);
fprintf('Heterogeneous mode-vector probe: %s\n', probePath);
fprintf(['Candidate strict: %d/%d; strict oracle gain=%+.6f%%; ', ...
    'strong=%d\n'], probe.candidateStrictFeasibleCount, ...
    size(candidateModes, 1), probe.strictOracleGainPercent, ...
    probe.strongSafeSequenceFound);
end

function targets = targetMatrix(screen)
records = screen.records;
outcomes = screen.outcomes;
reference = outcomes(screen.referenceSubsetIndex);
delivered = zeros(numel(outcomes), 1);
for idx = 1:numel(outcomes)
    delivered(idx) = 100 * ...
        (reference.deliveredBytes - outcomes(idx).deliveredBytes) / ...
        max(reference.deliveredBytes, eps);
end
targets = [ ...
    reshape([records.meanGainPercent], [], 1), ...
    reshape([records.minimumFormationGainPercent], [], 1), ...
    reshape([records.worstGainPercent], [], 1), ...
    reshape([records.consensusGainPercent], [], 1), ...
    reshape([records.attemptedByteSavingPercent], [], 1), ...
    delivered];
end

function writeReport(path, probe)
fid = fopen(path, 'w');
if fid < 0
    error('Cannot write heterogeneous mode-vector report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 heterogeneous mode-vector radius-2 probe\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    probe.contractVersion, probe.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    probe.generationGitCommit);
fprintf(fid, '- Cache protocol / commit: `%s / %s`\n', ...
    probe.cacheProtocolId, probe.cacheGenerationGitCommit);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    probe.presetName, probe.seed, probe.currentTime);
fprintf(fid, '- Candidate strict feasible: `%d/%d`\n', ...
    probe.candidateStrictFeasibleCount, ...
    size(probe.candidateModeVectors, 1));
fprintf(fid, '- Strict oracle / gain: `%s / %+.6f%%`\n', ...
    mat2str(probe.strictOracleSequence), ...
    probe.strictOracleGainPercent);
fprintf(fid, '- Strong safe sequence found: `%d`\n', ...
    probe.strongSafeSequenceFound);
fprintf(fid, '- Closest vector / targets: `%s / %s`\n', ...
    mat2str(probe.closestModeVector), ...
    mat2str(probe.closestTargets, 7));
fprintf(fid, '- Best-consensus vector / targets: `%s / %s`\n\n', ...
    mat2str(probe.bestConsensusModeVector), ...
    mat2str(probe.bestConsensusTargets, 7));

topCount = min(15, numel(probe.candidateRankOrder));
fprintf(fid, ['| Rank | Mode vector | Hamming | Mean | Min. formation | ', ...
    'Worst sensor | Consensus | Attempted | Delivered | Strict |\n']);
fprintf(fid, '|--:|:--|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for rankIdx = 1:topCount
    idx = probe.candidateRankOrder(rankIdx);
    targets = probe.candidateTargets(idx, :);
    fprintf(fid, ['| %d | `%s` | %d | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        rankIdx, strtrim(sprintf('%d ', ...
            probe.candidateModeVectors(idx, :))), ...
        probe.candidateHammingDistances(idx), ...
        targets(1), targets(2), targets(3), targets(4), ...
        targets(5), targets(6), probe.candidateStrictFeasible(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    probe.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
