function [policyPath, reportPath, policy] = ...
        freezeFormationCoordinatedPosteriorRepairV185(options)
% FREEZEFORMATIONCOORDINATEDPOSTERIORREPAIRV185 Freeze the V184 rule.

if nargin < 1 || isempty(options)
    options = struct();
end
modelPath = getField(options, 'modelPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v181', 'second_rollout_aware_model', ...
    'compact_scalar', 'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_MODEL.mat'));
modelResultPath = getField(options, 'modelResultPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v181', 'second_rollout_aware_model', ...
    'compact_scalar', 'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_RESULT.mat'));
analysisPath = getField(options, 'analysisPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v184', 'formation_coordinated_posterior_repair', ...
    'FORMATION_COORDINATED_POSTERIOR_REPAIR_V184_RESULT.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v185', 'formation_coordinated_policy'));
if exist(modelPath, 'file') ~= 2 || ...
        exist(modelResultPath, 'file') ~= 2 || ...
        exist(analysisPath, 'file') ~= 2
    error('FormationPosteriorRepairV185:MissingInput', ...
        'The V181 model/result and V184 diagnostic are required.');
end
model = load(modelPath, 'model').model;
modelResult = load(modelResultPath, 'result').result;
analysis = load(analysisPath, 'analysis').analysis;
if ~strcmp(model.datasetContractVersion, ...
        'second-rollout-aggregated-label-action-value-dataset-v181-v1') || ...
        model.featuresUseTruth || ...
        model.numericLabelIdentifiersUsedAsFeatures || ...
        ~model.heldoutSafetyGatePassed || ...
        ~modelResult.heldoutSafetyGatePassed || ...
        modelResult.heldout.harmfulActionCount ~= 0 || ...
        ~strcmp(analysis.contractVersion, ...
            'formation-coordinated-posterior-repair-analysis-v184-v1') || ...
        analysis.selectionUsesTruth || ...
        analysis.featuresUseTruth || ...
        analysis.eligibleContextCount ~= 6 || ...
        analysis.safeContextCount ~= analysis.eligibleContextCount
    error('FormationPosteriorRepairV185:SafetyGate', ...
        'The V181/V184 preflight evidence did not pass.');
end

policy = struct();
policy.contractVersion = ...
    'formation-coordinated-posterior-repair-policy-v185-v1';
policy.modelPath = modelPath;
policy.minimumSupportCount = analysis.minimumSupportCount;
policy.minimumSafetyProbability = analysis.minimumSafetyProbability;
policy.minimumRiskReduction = analysis.minimumRiskReduction;
policy.minimumReceiverPresence = analysis.minimumReceiverPresence;
policy.shortlistPerCriterion = 1;
policy.maximumEditsPerReceiver = 1;
policy.synopsisBytesPerLabel = 24;
policy.featuresUseTruth = false;
policy.numericLabelIdentifiersUsedAsFeatures = false;
policy.preflightGatePassed = true;
policy.openedContextCount = analysis.eligibleContextCount;
policy.openedHarmfulContextCount = ...
    analysis.eligibleContextCount - analysis.safeContextCount;
policy.recursiveEvaluationRun = false;
policy.deployable = false;
policy.evidenceBoundary = [ ...
    'V185 freezes the truth-free V184 formation-level common-action ', ...
    'rule after six opened V166/V176/V180 X36 contexts are safe. The ', ...
    'policy may replace at most one already-present complete Bernoulli ', ...
    'GM posterior per receiver and uses no numeric label identifier. ', ...
    'This preflight authorization supports one seed-211 recursive ', ...
    'development probe only.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
policyPath = fullfile(outputRoot, ...
    'FORMATION_COORDINATED_POSTERIOR_REPAIR_POLICY_V185.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_COORDINATED_POSTERIOR_REPAIR_POLICY_V185.md');
policy.policyPath = policyPath;
policy.reportPath = reportPath;
save('-mat7-binary', policyPath, 'policy');
writeReport(reportPath, policy);
fprintf('V185 formation-coordinated policy: %s\n', reportPath);
end

function writeReport(path, policy)
fid = fopen(path, 'w');
if fid < 0
    error('FormationPosteriorRepairV185:ReportOpenFailed', ...
        'Could not write the V185 policy report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V185 formation-coordinated posterior-repair policy\n\n');
fprintf(fid, '- Maximum edits per receiver: `%d`\n', ...
    policy.maximumEditsPerReceiver);
fprintf(fid, '- Minimum formation support: `%d`\n', ...
    policy.minimumSupportCount);
fprintf(fid, '- Minimum safety probability: `%.3f`\n', ...
    policy.minimumSafetyProbability);
fprintf(fid, '- Minimum observable risk reduction: `%.3f`\n', ...
    policy.minimumRiskReduction);
fprintf(fid, '- Minimum receiver label presence: `%.3f`\n', ...
    policy.minimumReceiverPresence);
fprintf(fid, '- Opened safe / harmful contexts: `%d / %d`\n\n', ...
    policy.openedContextCount, policy.openedHarmfulContextCount);
fprintf(fid, '## Evidence boundary\n\n%s\n', policy.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
