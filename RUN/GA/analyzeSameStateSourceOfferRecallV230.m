function [reportPath, result] = ...
        analyzeSameStateSourceOfferRecallV230(options)
% ANALYZESAMESTATESOURCEOFFERRECALLV230 Screen source-relative ranking.
%
% This intentionally optimistic screen gives each teacher source a fresh
% full posterior from every beneficiary sensor.  It asks whether the frozen
% two-offer ranker can express the teacher source-label pair at all.  The
% same test is repeated with each beneficiary sensor as the only cache entry
% to expose dependence on an unrealistically complete formation cache.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCausalSourceOfferRankerV230Protocol();
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices)
    error('SameStateSourceOfferRecallV230:InvalidRequest', ...
        'A causal V220 candidate bank and unique row indices are required.');
end

loaded = load(candidateBankPath, 'result');
bank = loaded.result;
required = {'contractVersion', 'presetName', 'seed', 'currentTime', ...
    'sourceScreenPath', 'records'};
if ~isstruct(bank) || ~isscalar(bank) || ...
        any(~isfield(bank, required)) || ...
        ~strcmp(bank.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        getField(bank, 'truthUsedForCandidateFeatures', true) || ...
        getField(bank, 'futureInformationUsedForCandidateFeatures', true)
    error('SameStateSourceOfferRecallV230:CandidateBankContract', ...
        'The causal V220 candidate-bank contract is required.');
end
if isempty(recordIndices)
    selectedRows = 1:numel(bank.records);
else
    [present, selectedRows] = ismember( ...
        recordIndices, [bank.records.recordIndex]);
    if ~all(present)
        error('SameStateSourceOfferRecallV230:UnknownRecord', ...
            'A requested teacher record is absent from the bank.');
    end
end

screenLoaded = load(bank.sourceScreenPath, 'screen');
screen = screenLoaded.screen;
timeIndex = find(screen.returnTimes == bank.currentTime, 1);
if isempty(timeIndex) || ~screen.capturePosteriorSnapshotsEnabled || ...
        screen.referenceSubsetIndex < 1 || ...
        screen.referenceSubsetIndex > numel(screen.outcomes)
    error('SameStateSourceOfferRecallV230:SnapshotContract', ...
        'The same-state reference local posteriors are unavailable.');
end
reference = screen.outcomes(screen.referenceSubsetIndex);
posteriors = reference.localPosteriorSnapshotsByTime{timeIndex};
if ~iscell(posteriors) || isempty(posteriors)
    error('SameStateSourceOfferRecallV230:SnapshotContract', ...
        'One local posterior per sensor is required.');
end
model = struct('xDimension', inferStateDimension(posteriors));

teacherRows = bank.records(selectedRows);
audits = repmat(emptyAudit(), 1, numel(teacherRows));
for auditIndex = 1:numel(teacherRows)
    teacher = teacherRows(auditIndex);
    sourceId = teacher.sourceId;
    receiverIds = reshape(teacher.candidate.receiverIds, 1, []);
    if sourceId < 1 || sourceId > numel(posteriors) || ...
            isempty(receiverIds) || any(receiverIds < 1) || ...
            any(receiverIds > numel(posteriors))
        error('SameStateSourceOfferRecallV230:TeacherContract', ...
            'A teacher source or beneficiary receiver set is invalid.');
    end
    cache = posteriors(receiverIds);
    fullResult = rankCausalSourceOffersV230( ...
        posteriors{sourceId}, cache, receiverIds, ...
        zeros(size(receiverIds)), 2 * ones(size(receiverIds)), ...
        model, struct());
    teacherLabel = reshape(teacher.label, 2, 1);
    fullSelected = labelSelected(fullResult.selectedLabels, teacherLabel);
    [existenceRank, spatialRank] = teacherRanks( ...
        fullResult, teacherLabel);

    singleSensorSelected = false(1, numel(receiverIds));
    singleSensorLabels = cell(1, numel(receiverIds));
    for receiverPosition = 1:numel(receiverIds)
        receiverId = receiverIds(receiverPosition);
        singleResult = rankCausalSourceOffersV230( ...
            posteriors{sourceId}, {posteriors{receiverId}}, ...
            receiverId, 0, 2, model, struct());
        singleSensorSelected(receiverPosition) = labelSelected( ...
            singleResult.selectedLabels, teacherLabel);
        singleSensorLabels{receiverPosition} = ...
            singleResult.selectedLabels;
    end
    candidate = findCandidate(fullResult.candidates, teacherLabel);
    audits(auditIndex) = struct( ...
        'recordIndex', teacher.recordIndex, ...
        'beneficiaryFormationId', ...
            teacher.beneficiaryFormationId, ...
        'sourceId', sourceId, 'label', teacherLabel, ...
        'receiverIds', receiverIds, ...
        'fullCacheSelectedLabels', fullResult.selectedLabels, ...
        'fullCacheSelectedModes', {fullResult.selectedModes}, ...
        'fullCacheTeacherSelected', fullSelected, ...
        'fullCacheExistenceRank', existenceRank, ...
        'fullCacheSpatialRank', spatialRank, ...
        'teacherSourceExistence', ...
            getCandidateField(candidate, 'sourceExistence', NaN), ...
        'teacherReferenceExistence', ...
            getCandidateField(candidate, 'referenceExistence', NaN), ...
        'teacherExistenceScore', ...
            getCandidateField(candidate, 'existenceScore', NaN), ...
        'teacherSpatialScore', ...
            getCandidateField(candidate, 'spatialScore', NaN), ...
        'singleSensorTeacherSelected', singleSensorSelected, ...
        'singleSensorSelectedLabels', {singleSensorLabels}, ...
        'singleSensorRecallCount', nnz(singleSensorSelected), ...
        'singleSensorRecallRate', ...
            mean(double(singleSensorSelected)));
end

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v230', 'same_state_source_offer_recall', ...
    sprintf('%s_seed%d_t%d', strrep(bank.presetName, '-', '_'), ...
        bank.seed, bank.currentTime))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
result = struct();
result.contractVersion = 'same-state-source-offer-recall-v230-v1';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.sourceScreenPath = bank.sourceScreenPath;
result.presetName = bank.presetName;
result.seed = bank.seed;
result.currentTime = bank.currentTime;
result.teacherAudits = audits;
result.teacherLabelCount = numel(audits);
result.fullCacheRecoveredTeacherLabelCount = ...
    nnz([audits.fullCacheTeacherSelected]);
result.fullCacheTeacherRecall = ...
    result.fullCacheRecoveredTeacherLabelCount / ...
    max(result.teacherLabelCount, 1);
result.allTeacherLabelsRecoveredWithFullCache = ...
    result.fullCacheRecoveredTeacherLabelCount == ...
    result.teacherLabelCount;
result.minimumSingleSensorRecallRate = ...
    min([audits.singleSensorRecallRate]);
result.sameStateScreenPassed = ...
    result.allTeacherLabelsRecoveredWithFullCache;
result.runtimeCacheIntegrationAuthorized = ...
    result.sameStateScreenPassed;
result.sameStateBeneficiaryPosteriorsUsedAsFreshCacheProxy = true;
result.actualRuntimeReceivedCacheUsed = false;
result.teacherLabelsUsedOnlyForRecallAudit = true;
result.truthUsedForRanking = false;
result.futureInformationUsedForRanking = false;
result.onlinePolicyImplemented = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'SAME_STATE_SOURCE_OFFER_RECALL_V230.mat');
reportPath = fullfile(outputRoot, ...
    'SAME_STATE_SOURCE_OFFER_RECALL_V230.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V230 same-state source-offer recall: %s\n', reportPath);
end

function [existenceRank, spatialRank] = teacherRanks(result, label)
existenceRank = labelRank(result.existenceRanking, label);
spatialRank = labelRank(result.spatialRanking, label);
end

function rank = labelRank(labels, label)
match = find(all(labels == label, 1), 1);
if isempty(match)
    rank = inf;
else
    rank = match;
end
end

function present = labelSelected(labels, label)
present = ~isempty(labels) && any(all(labels == label, 1));
end

function candidate = findCandidate(candidates, label)
candidate = [];
for candidateIndex = 1:numel(candidates)
    if all(candidates(candidateIndex).label == label)
        candidate = candidates(candidateIndex);
        return;
    end
end
end

function value = getCandidateField(candidate, name, fallback)
if isstruct(candidate) && ~isempty(candidate) && isfield(candidate, name)
    value = candidate.(name);
else
    value = fallback;
end
end

function dimension = inferStateDimension(posteriors)
dimension = 0;
for sensorIndex = 1:numel(posteriors)
    objects = posteriors{sensorIndex};
    for objectIndex = 1:numel(objects)
        if objects(objectIndex).numberOfGmComponents > 0 && ...
                ~isempty(objects(objectIndex).mu)
            dimension = numel(objects(objectIndex).mu{1});
            break;
        end
    end
    if dimension > 0
        break;
    end
end
if dimension < 2
    error('SameStateSourceOfferRecallV230:StateDimension', ...
        'A position-bearing Gaussian-mixture state is required.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('SameStateSourceOfferRecallV230:WriteReport', ...
        'Could not write the V230 source-offer report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V230 same-state source-offer ranking screen\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Offer cap: `2 labels per source`\n');
fprintf(fid, '- Full-cache teacher recall: `%d / %d = %.1f%%`\n', ...
    result.fullCacheRecoveredTeacherLabelCount, ...
    result.teacherLabelCount, 100 * result.fullCacheTeacherRecall);
fprintf(fid, ['- Actual runtime received cache used: `%d` ', ...
    '(same-state full-cache proxy only)\n\n'], ...
    result.actualRuntimeReceivedCacheUsed);
fprintf(fid, ['| Row | Beneficiary | Source / teacher label | ', ...
    'Selected offers | Teacher rank E / spatial | ', ...
    'Source r / reference r | Single-cache recall |\n']);
fprintf(fid, '|--:|--:|:--|:--|:--|:--|:--|\n');
for audit = result.teacherAudits
    fprintf(fid, ['| %d | F%d | S%d / `[%d,%d]` | `%s` | ', ...
        '`%s / %s` | `%.3f / %.3f` | `%d/%d = %.1f%%` |\n'], ...
        audit.recordIndex, audit.beneficiaryFormationId, ...
        audit.sourceId, audit.label(1), audit.label(2), ...
        labelsText(audit.fullCacheSelectedLabels), ...
        rankText(audit.fullCacheExistenceRank), ...
        rankText(audit.fullCacheSpatialRank), ...
        audit.teacherSourceExistence, ...
        audit.teacherReferenceExistence, ...
        audit.singleSensorRecallCount, numel(audit.receiverIds), ...
        100 * audit.singleSensorRecallRate);
end
fprintf(fid, '\n## Decision\n\n');
if result.sameStateScreenPassed
    fprintf(fid, ['The two-mode source-relative ranker recovers every ', ...
        'opened teacher row when given a perfectly fresh full cache. ', ...
        'This authorizes capture and evaluation of the actual runtime ', ...
        '`receivedCache`; it does not authorize an online controller or ', ...
        'a tracking claim.\n']);
else
    fprintf(fid, ['The ranker misses at least one teacher row even with ', ...
        'a perfectly fresh full cache. Do not integrate this score into ', ...
        'the recursive filter; redesign the source-side statistic first.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = labelsText(labels)
if isempty(labels)
    text = 'none';
    return;
end
parts = cell(1, size(labels, 2));
for labelIndex = 1:size(labels, 2)
    parts{labelIndex} = sprintf('[%d,%d]', ...
        labels(1, labelIndex), labels(2, labelIndex));
end
text = strjoin(parts, ', ');
end

function text = rankText(rank)
if isfinite(rank)
    text = sprintf('%d', rank);
else
    text = '-';
end
end

function value = emptyAudit()
value = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'receiverIds', zeros(1, 0), ...
    'fullCacheSelectedLabels', zeros(2, 0), ...
    'fullCacheSelectedModes', {{}}, ...
    'fullCacheTeacherSelected', false, ...
    'fullCacheExistenceRank', inf, 'fullCacheSpatialRank', inf, ...
    'teacherSourceExistence', NaN, ...
    'teacherReferenceExistence', NaN, ...
    'teacherExistenceScore', NaN, 'teacherSpatialScore', NaN, ...
    'singleSensorTeacherSelected', false(1, 0), ...
    'singleSensorSelectedLabels', {{}}, ...
    'singleSensorRecallCount', 0, 'singleSensorRecallRate', 0);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
