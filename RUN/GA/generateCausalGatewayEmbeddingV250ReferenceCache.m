function [cachePath, summary] = ...
        generateCausalGatewayEmbeddingV250ReferenceCache(options)
% GENERATECAUSALGATEWAYEMBEDDINGV250REFERENCECACHE V242 prefix state.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getField(options, 'protocol', ...
    getCausalGatewayEmbeddingV250Protocol());
presetName = char(getField(options, 'presetName', ...
    protocol.allowedPresets{1}));
seed = getField(options, 'seed', protocol.allowedSeeds(1));
overwrite = logical(getField(options, 'overwrite', false));
if ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds) || ...
        ~islogical(overwrite) || ~isscalar(overwrite)
    error('CausalGatewayEmbeddingV250:InvalidCacheRequest', ...
        'The V250 cache request is outside its M24 protocol.');
end

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('CausalGatewayEmbeddingV250:DirtyCacheSource', ...
        'Official V250 cache generation requires clean source.');
end
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
cacheRoot = char(getField(options, 'cacheRoot', protocol.cacheRoot));
if ~isAbsolutePath(cacheRoot)
    cacheRoot = fullfile(repoRoot, cacheRoot);
end
cachePath = fullfile(cacheRoot, sprintf( ...
    '%s_%s_SEED%d.mat', ...
    getField(protocol, 'cacheFilePrefix', 'V250_V242_REFERENCE'), ...
    upper(strrep(presetName, '-', '_')), seed));
if exist(cachePath, 'file') == 2 && ~overwrite
    loaded = load(cachePath, 'behaviorBundle');
    validateBundle(loaded, protocol, presetName, seed, ...
        gitState.commit);
    summary = buildSummary(loaded.behaviorBundle, cachePath, true);
    fprintf('Reused V250 reference cache: %s\n', cachePath);
    return;
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
maximumTime = max(protocol.anchorTimes);
inputs = cropInputs(inputs, maximumTime);
filterModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
config = buildCausalMinimumFormationBackboneV242Config(inputs.config);
config.topologyPosteriorCaptureTimes = protocol.anchorTimes;
if isIndependentM24TeacherProtocol(protocol)
    context = buildIndependentM24GatewayTeacherV252ExecutionContext( ...
        presetName, seed, maximumTime, ...
        'reference-prefix', 0, 1);
else
    context = buildCausalMinimumFormationBackboneV242ExecutionContext( ...
        presetName, seed, maximumTime);
end
rng(seed + protocol.filterSeedOffset, 'twister');
timerId = tic;
fprintf('Generating V250 V242 reference cache to t=%d ...\n', ...
    maximumTime);
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    filterModel, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
elapsedSeconds = toc(timerId);
auditRuntime(diagnostics, inputs.config, protocol.anchorTimes);

contract = behaviorContinuationCacheContract();
sourceProtocol = getCausalMinimumFormationBackboneV242Protocol();
posteriorSnapshots = cell(1, maximumTime);
for anchorTime = protocol.anchorTimes
    posteriorSnapshots{anchorTime} = ...
        diagnostics.topologyLocalPosteriorSnapshot{anchorTime};
end
historyByTime = buildBehaviorContinuationHistoryRecords( ...
    diagnostics, protocol.anchorTimes, contract.topologyHistoryDepth);
configSnapshot = config;
if isfield(configSnapshot, 'topologyPolicyFcn')
    configSnapshot = rmfield(configSnapshot, 'topologyPolicyFcn');
end
behaviorBundle = struct( ...
    'cacheContractVersion', contract.version, ...
    'posteriorSnapshotConvention', ...
        contract.posteriorSnapshotConvention, ...
    'topologyHistoryDepth', contract.topologyHistoryDepth, ...
    'topologyHistoryConvention', ...
        contract.topologyHistoryConvention, ...
    'protocolId', protocol.id, ...
    'sourcePolicyProtocolId', ...
        sourceProtocol.id, ...
    'presetName', presetName, 'seed', seed, ...
    'snapshotTimes', protocol.anchorTimes, ...
    'maximumTime', maximumTime, ...
    'configSnapshot', inputs.config, ...
    'behaviorConfigSnapshot', configSnapshot, ...
    'behaviorSeconds', elapsedSeconds, ...
    'posteriorSnapshots', {posteriorSnapshots}, ...
    'preDecisionTopologyHistoryByTime', {historyByTime}, ...
    'generationGitCommit', gitState.commit, ...
    'referenceArmName', ...
        'v242-causal-minimum-formation-backbone', ...
    'policyTruthUsed', false, ...
    'policyFutureOutcomeUsed', false, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'evidenceBoundary', protocol.evidenceBoundary);
if exist(cacheRoot, 'dir') ~= 7, mkdir(cacheRoot); end
save(cachePath, 'behaviorBundle', '-v7');
validateBundle(struct('behaviorBundle', behaviorBundle), protocol, ...
    presetName, seed, gitState.commit);
summary = buildSummary(behaviorBundle, cachePath, false);
fprintf('V250 reference cache complete in %.1f s: %s\n', ...
    elapsedSeconds, cachePath);
end

function validateBundle(envelope, protocol, presetName, seed, commit)
sourceProtocol = getCausalMinimumFormationBackboneV242Protocol();
required = {'protocolId', 'sourcePolicyProtocolId', 'presetName', ...
    'seed', 'snapshotTimes', 'maximumTime', 'generationGitCommit', ...
    'policyTruthUsed', 'policyFutureOutcomeUsed'};
if ~isstruct(envelope) || ~isfield(envelope, 'behaviorBundle')
    error('CausalGatewayEmbeddingV250:MissingCacheBundle', ...
        'The V250 cache lacks its behavior bundle.');
end
bundle = envelope.behaviorBundle;
if ~isstruct(bundle) || ~all(isfield(bundle, required)) || ...
        ~strcmp(bundle.protocolId, protocol.id) || ...
        ~strcmp(bundle.sourcePolicyProtocolId, ...
            sourceProtocol.id) || ...
        ~strcmp(bundle.presetName, presetName) || ...
        bundle.seed ~= seed || ...
        ~isequal(bundle.snapshotTimes, protocol.anchorTimes) || ...
        bundle.maximumTime ~= max(protocol.anchorTimes) || ...
        ~strcmp(bundle.generationGitCommit, commit) || ...
        bundle.policyTruthUsed || bundle.policyFutureOutcomeUsed
    error('CausalGatewayEmbeddingV250:CacheProvenance', ...
        'The V250 cache belongs to another source or protocol.');
end
for anchorTime = protocol.anchorTimes
    extractBehaviorContinuationSnapshot( ...
        bundle, anchorTime, ...
        bundle.configSnapshot.numberOfSensors);
end
end

function summary = buildSummary(bundle, cachePath, reused)
summary = struct();
summary.contractVersion = ...
    'causal-gateway-embedding-v250-cache-summary-v1';
summary.cachePath = cachePath;
summary.presetName = bundle.presetName;
summary.seed = bundle.seed;
summary.snapshotTimes = bundle.snapshotTimes;
summary.maximumTime = bundle.maximumTime;
summary.generationGitCommit = bundle.generationGitCommit;
summary.elapsedSeconds = bundle.behaviorSeconds;
summary.reusedExisting = reused;
summary.policyTruthUsed = false;
summary.policyFutureOutcomeUsed = false;
end

function auditRuntime(diagnostics, config, anchorTimes)
formationCount = numel(unique(config.sensorGroupIds));
expectedMessages = config.numberOfSensors + 2 * (formationCount - 1);
times = 1:max(anchorTimes);
passed = all(diagnostics.topologyFeasible(times)) && ...
    all(diagnostics.topologyDirectedMessageCount(times) == ...
        expectedMessages) && ...
    ~anyFiniteNonzero(diagnostics.topologyPolicyTruthUsed(times)) && ...
    ~anyFiniteNonzero( ...
        diagnostics.topologyPolicyFutureOutcomeUsed(times));
if ~passed
    error('CausalGatewayEmbeddingV250:ReferenceRuntime', ...
        'The V242 cache prefix violated its causal sparse contract.');
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.config.simulationLength = maximumTime;
inputs.model.simulationLength = maximumTime;
if isfield(inputs.model, 'dynamicTopologyScenario') && ...
        isfield(inputs.model.dynamicTopologyScenario, 'config')
    inputs.model.dynamicTopologyScenario.config.simulationLength = ...
        maximumTime;
end
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
if isfield(inputs.commConfig, 'linkUniforms') && ...
        ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = ...
        inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
end
if isfield(inputs, 'graphData')
    inputs.graphData.physicalAdjacency = ...
        inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
    inputs.graphData.positions = ...
        inputs.graphData.positions(:, :, 1:maximumTime);
end
end

function value = anyFiniteNonzero(values)
values = values(isfinite(values));
value = any(values ~= 0);
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    (~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once'))));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

function detected = isIndependentM24TeacherProtocol(protocol)
detected = isstruct(protocol) && isscalar(protocol) && ...
    isfield(protocol, 'id') && ...
    strcmp(protocol.id, ...
        'independent-m24-gateway-teacher-v252-v1');
end
