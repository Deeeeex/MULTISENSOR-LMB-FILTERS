function [reportPath, result] = ...
    runTrackingAlignedFormationH3HeadroomBatch(options)
% RUNTRACKINGALIGNEDFORMATIONH3HEADROOMBATCH V56 M24/X36 first gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getTrackingAlignedFormationH3HeadroomProtocol();
if ~isempty(fieldnames(options))
    error(['The frozen V56 first-headroom batch does not accept ', ...
        'option overrides.']);
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official V56 headroom generation requires clean source.');
end

blockCount = numel(protocol.presets) * ...
    numel(protocol.allSeeds) * numel(protocol.snapshotTimes);
blocks = cell(1, blockCount);
screenPaths = cell(1, blockCount);
cachePaths = cell(1, 0);
blockIdx = 0;
for presetIdx = 1:numel(protocol.presets)
    presetName = protocol.presets{presetIdx};
    inputs = generateDynamicTopologyScenarioInputs( ...
        presetName, protocol.allSeeds(1));
    if inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCounts(presetIdx) || ...
            inputs.config.formationCount ~= ...
                protocol.expectedFormationCounts(presetIdx)
        error('V56 headroom scene scale changed: %s.', presetName);
    end
    for seed = protocol.allSeeds
        [currentCachePaths, cacheSummary] = ...
            generateFormationH3ReferenceStateCaches( ...
                presetName, seed, protocol.snapshotTimes, struct( ...
                    'protocol', protocol, ...
                    'cacheRoot', protocol.cacheRoot));
        if ~strcmp(cacheSummary.generationGitCommit, gitState.commit)
            error('V56 cache and headroom source commits differ.');
        end
        cachePaths = [cachePaths, currentCachePaths]; %#ok<AGROW>
        for currentTime = protocol.snapshotTimes
            blockIdx = blockIdx + 1;
            outputDirectory = fullfile(protocol.screenRoot, ...
                presetName, sprintf('seed%d', seed), ...
                sprintf('t%d', currentTime));
            screenOptions = struct( ...
                'cacheRoot', protocol.cacheRoot, ...
                'outputDirectory', outputDirectory, ...
                'interventionBankType', ...
                    'tracking-aligned-formation-local', ...
                'horizonSteps', protocol.horizonSteps, ...
                'interventionDurationSteps', 1);
            [screenPaths{blockIdx}, screen] = ...
                runFormationModeOpenedReturnScreen( ...
                    presetName, seed, currentTime, screenOptions);
            state = loadFormationH3ObservableState( ...
                presetName, seed, currentTime, struct( ...
                    'cacheRoot', protocol.cacheRoot));
            if ~strcmp(state.cacheSha256, screen.cacheSha256)
                error('V56 state and teacher cache differ.');
            end
            blocks{blockIdx} = ...
                buildTrackingAlignedFormationValueBlock( ...
                    state.context, state.groupIds, screen);
            fprintf(['V56 block %d/%d: %s seed %d t=%d, ', ...
                '%d target modes\n'], ...
                blockIdx, blockCount, presetName, seed, currentTime, ...
                nnz(blocks{blockIdx}.targetAvailableMask));
        end
    end
end
if blockIdx ~= blockCount
    error('V56 headroom block enumeration is incomplete.');
end

oracle = computeTrackingAlignedFormationOracleHeadroom( ...
    blocks, struct( ...
        'minimumMeanGainPercent', ...
            protocol.minimumMeanGainPercent, ...
        'minimumPositiveStateFraction', ...
            protocol.minimumPositiveStateFraction, ...
        'requiredScaleNodeCounts', ...
            protocol.requiredScaleNodeCounts));
result = struct();
result.contractVersion = ...
    'tracking-aligned-formation-h3-headroom-result-v1';
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
result.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
result.protocol = protocol;
result.cachePaths = cachePaths;
result.screenPaths = screenPaths;
result.blocks = blocks;
result.oracle = oracle;
result.modelTrainingAuthorized = oracle.gatePassed;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;

if exist(protocol.outputRoot, 'dir') ~= 7
    mkdir(protocol.outputRoot);
end
timestamp = datestr(now, 'yyyymmdd_HHMMSS');
reportPath = fullfile(protocol.outputRoot, [ ...
    'TRACKING_ALIGNED_FORMATION_H3_HEADROOM_', ...
    timestamp, '.md']);
matPath = strrep(reportPath, '.md', '.mat');
result.reportPath = reportPath;
result.matPath = matPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V56 tracking-aligned headroom report: %s\n', reportPath);
fprintf('V56_HEADROOM_GATE_PASSED=%d\n', oracle.gatePassed);
end

function writeReport(path, result)
fileId = fopen(path, 'w');
if fileId < 0
    error('Could not write V56 headroom report.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
oracle = result.oracle;
fprintf(fileId, '# V56 tracking-aligned M24/X36 oracle headroom\n\n');
fprintf(fileId, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fileId, '- Development seed: `%s`\n', ...
    mat2str(result.protocol.allSeeds));
fprintf(fileId, '- Anchor times: `%s`\n', ...
    mat2str(result.protocol.snapshotTimes));
fprintf(fileId, '- Mean gain gate: `%.2f%%`\n', ...
    oracle.minimumMeanGainPercent);
fprintf(fileId, '- Positive-state gate: `%.3f`\n', ...
    oracle.minimumPositiveStateFraction);
fprintf(fileId, '- Model training authorized: `%d`\n\n', ...
    result.modelTrainingAuthorized);

fprintf(fileId, ['| Preset | Seed | Time | Actions | Safe actions | ', ...
    'Tracking oracle | Constrained oracle | Selected mode |\n']);
fprintf(fileId, ['|:--|--:|--:|--:|--:|--:|--:|:--|\n']);
for state = oracle.states
    fprintf(fileId, ['| %s | %d | %d | %d | %d | ', ...
        '%+.3f%% | %+.3f%% | %s |\n'], ...
        state.presetName, state.seed, state.currentTime, ...
        state.availableActionCount, state.constrainedActionCount, ...
        state.trackingOracleGainPercent, ...
        state.constrainedOracleGainPercent, ...
        state.constrainedOracleModeName);
end

fprintf(fileId, '\n| Sensors | States | Mean tracking oracle | ');
fprintf(fileId, ['Mean constrained oracle | Minimum constrained | ', ...
    'Positive states | Gate |\n']);
fprintf(fileId, '|--:|--:|--:|--:|--:|--:|:--:|\n');
for scale = oracle.scales
    fprintf(fileId, ['| %d | %d | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%d/%d | %d |\n'], ...
        scale.nodeCount, scale.stateCount, ...
        scale.meanTrackingOracleGainPercent, ...
        scale.meanConstrainedOracleGainPercent, ...
        scale.minimumConstrainedOracleGainPercent, ...
        scale.positiveConstrainedStateCount, scale.stateCount, ...
        scale.gatePassed);
end

fprintf(fileId, '\n## Decision\n\n');
if oracle.gatePassed
    fprintf(fileId, [ ...
        'The finite local bank clears the first M24/X36 headroom gate. ', ...
        'Graph-model training may begin, but multi-scene and held-out ', ...
        'tracking claims remain closed.\n']);
else
    fprintf(fileId, [ ...
        'The finite local bank does not clear the first M24/X36 ', ...
        'headroom gate. Redesign the action space before training a ', ...
        'larger predictor.\n']);
end
fprintf(fileId, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end
