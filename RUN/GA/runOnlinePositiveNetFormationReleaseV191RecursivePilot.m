function [reportPath, result] = ...
        runOnlinePositiveNetFormationReleaseV191RecursivePilot( ...
            scaleName, options)
% RUNONLINEPOSITIVENETFORMATIONRELEASEV191RECURSIVEPILOT Release one page.

if nargin < 2 || isempty(options)
    options = struct();
end
scaleName = upper(char(scaleName));
baseProtocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
releaseProtocol = getOnlinePositiveNetFormationReleaseV191Protocol();
entryIdx = find(strcmp({baseProtocol.cases.scaleName}, scaleName), 1);
if isempty(entryIdx)
    error('OnlinePositiveNetReleaseV191:UnknownScale', ...
        'The requested V99 scale is not registered.');
end
entry = baseProtocol.cases(entryIdx);
if strcmp(scaleName, 'M24')
    defaultTime = 104;
else
    defaultTime = 72;
end
currentTime = getField(options, 'currentTime', defaultTime);
releasePageOffsets = reshape(getField( ...
    options, 'releasePageOffsets', 0), 1, []);
releaseFormationIdsByTime = getField( ...
    options, 'releaseFormationIdsByTime', {1});
releaseTimes = currentTime + releasePageOffsets;
releasePlan = struct( ...
    'contractVersion', ...
        'online-positive-net-formation-release-v191-plan-v1', ...
    'times', releaseTimes, ...
    'formationIdsByTime', {releaseFormationIdsByTime}, ...
    'teacherMode', true);
if ~isValidOnlinePositiveNetFormationReleaseV191Plan( ...
        releasePlan, entry.expectedFormationCount) || ...
        numel(releasePageOffsets) ~= numel(releaseFormationIdsByTime) || ...
        any(releasePageOffsets < 0) || ...
        any(releasePageOffsets >= baseProtocol.horizonSteps)
    error('OnlinePositiveNetReleaseV191:InvalidReleasePlan', ...
        'The H=3 release plan is malformed.');
end

defaultBaseScreenPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v188', 'base_capture', ...
    sprintf('%s_seed%d_t%d_h3', ...
        lower(scaleName), entry.seed, currentTime), ...
    'screen', sprintf( ...
        'TRACKING_ALIGNED_X36_SCHEDULE_H3_%s_SEED%d_T%d_D3.mat', ...
        upper(strrep(entry.presetName, '-', '_')), ...
        entry.seed, currentTime));
baseScreenPath = char(getField( ...
    options, 'baseScreenPath', defaultBaseScreenPath));
if exist(baseScreenPath, 'file') ~= 2
    error('OnlinePositiveNetReleaseV191:MissingPairedInput', ...
        'The paired base screen is required.');
end
loaded = load(baseScreenPath, 'screen');
baseScreen = loaded.screen;
if ~strcmp(baseScreen.presetName, entry.presetName) || ...
        baseScreen.seed ~= entry.seed || ...
        baseScreen.returnTimes(1) ~= currentTime || ...
        numel(baseScreen.returnTimes) ~= baseProtocol.horizonSteps || ...
        any(~ismember(releaseTimes, baseScreen.returnTimes))
    error('OnlinePositiveNetReleaseV191:BaseScreenDrift', ...
        'The base screen does not match the frozen H=3 pilot.');
end
defaultCacheRoot = entry.cacheRoot;
if isfield(baseScreen, 'cachePath') && ...
        exist(baseScreen.cachePath, 'file') == 2
    defaultCacheRoot = fileparts(baseScreen.cachePath);
end
cacheRoot = char(getField(options, 'cacheRoot', defaultCacheRoot));
if exist(cacheRoot, 'dir') ~= 7
    error('OnlinePositiveNetReleaseV191:MissingPairedInput', ...
        'The opened-state cache used by the paired base is required.');
end

baseNames = {baseScreen.records.actionName};
baseIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), baseNames), 1);
referenceIdx = baseScreen.referenceSubsetIndex;
if isempty(baseIdx)
    error('OnlinePositiveNetReleaseV191:MissingBaseArm', ...
        'The paired screen does not contain the causal V99 arm.');
end

releaseTag = cellfun(@(ids) sprintf('%d-', ids), ...
    releaseFormationIdsByTime, 'UniformOutput', false);
releaseTag = strjoin(releaseTag, 'p');
releaseTag(end) = [];
defaultOutputLeaf = sprintf('%s_seed%d_t%d_h3_release_%s', ...
    lower(scaleName), entry.seed, currentTime, releaseTag);
if numel(releasePageOffsets) ~= 1 || releasePageOffsets(1) ~= 0
    offsetTag = sprintf('%d-', releasePageOffsets);
    offsetTag(end) = [];
    defaultOutputLeaf = sprintf('%s_pages_%s', ...
        defaultOutputLeaf, offsetTag);
end
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v191', 'formation_release_teacher', ...
    defaultOutputLeaf)));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenDirectory = fullfile(outputRoot, 'screen');
screenOptions = struct( ...
    'horizonSteps', baseProtocol.horizonSteps, ...
    'interventionDurationSteps', baseProtocol.horizonSteps, ...
    'filterSeedOffset', baseProtocol.filterSeedOffset, ...
    'cacheRoot', cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v191-online-positive-net-formation-release', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', ...
            baseProtocol.positiveSupportThreshold, ...
        'bankVariant', 'online-positive-net-addressable-v99'), ...
    'receiverMode', baseProtocol.receiverMode, ...
    'actionIndices', [1, 3], ...
    'referenceOutcomeScreenPath', baseScreenPath, ...
    'onlinePositiveNetFormationReleasePlan', releasePlan, ...
    'outputDirectory', screenDirectory, ...
    'writeReport', true, ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'captureFusedPosteriorSnapshotsEnabled', true);
screenStem = sprintf( ...
    'TRACKING_ALIGNED_X36_SCHEDULE_H3_%s_SEED%d_T%d_D3', ...
    upper(strrep(entry.presetName, '-', '_')), entry.seed, currentTime);
screenMatPath = fullfile(screenDirectory, [screenStem, '.mat']);
screenReportPath = fullfile(screenDirectory, [screenStem, '.md']);
reuseExistingScreen = logical(getField( ...
    options, 'reuseExistingScreen', false));
if reuseExistingScreen && exist(screenMatPath, 'file') == 2
    loadedScreen = load(screenMatPath, 'screen');
    screen = loadedScreen.screen;
else
    [screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
        entry.presetName, entry.seed, currentTime, screenOptions);
end

releaseNames = {screen.records.actionName};
releaseIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), releaseNames), 1);
if isempty(releaseIdx)
    error('OnlinePositiveNetReleaseV191:MissingReleaseArm', ...
        'The recursive screen did not return the V191 candidate arm.');
end
reference = baseScreen.records(referenceIdx);
base = baseScreen.records(baseIdx);
release = screen.records(releaseIdx);
baseOutcome = baseScreen.outcomes(baseIdx);
releaseOutcome = screen.outcomes(releaseIdx);

[requestedByTime, appliedByTime, effectiveByTime] = ...
    summarizeReleasePlan( ...
        releasePlan, releaseOutcome. ...
            retentionDebtSelectedFormationIdsByTime, ...
        screen.returnTimes);
result = struct();
result.contractVersion = ...
    'online-positive-net-formation-release-v191-recursive-pilot-v1';
result.generatedAt = datestr(now, 31);
result.scaleName = scaleName;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.baseScreenPath = baseScreenPath;
result.screenReportPath = screenReportPath;
result.releasePageOffsets = releasePageOffsets;
result.requestedReleaseFormationIdsByTime = requestedByTime;
result.appliedReleaseFormationIdsByTime = appliedByTime;
result.effectiveWithheldFormationIdsByTime = effectiveByTime;
result.releaseActuallyApplied = any(cellfun(@(ids) ~isempty(ids), ...
    appliedByTime));
result.referenceMeanEospa = reference.meanEospa;
result.baseMeanEospa = base.meanEospa;
result.releaseMeanEospa = release.meanEospa;
result.baseEospaGainPercent = base.meanGainPercent;
result.releaseEospaGainPercent = release.meanGainPercent;
result.incrementalEospaGainPercent = relativeGain( ...
    base.meanEospa, release.meanEospa);
result.referenceMeanRmse = reference.meanRmse;
result.baseMeanRmse = base.meanRmse;
result.releaseMeanRmse = release.meanRmse;
result.baseRmseGainPercent = base.rmseGainPercent;
result.releaseRmseGainPercent = release.rmseGainPercent;
result.incrementalRmseGainPercent = relativeGain( ...
    base.meanRmse, release.meanRmse);
result.baseConsensusGainPercent = base.consensusGainPercent;
result.releaseConsensusGainPercent = release.consensusGainPercent;
result.incrementalConsensusGainPercent = relativeGain( ...
    baseOutcome.consensusOspa, releaseOutcome.consensusOspa);
result.baseAttemptedByteSavingPercent = base.attemptedByteSavingPercent;
result.releaseAttemptedByteSavingPercent = ...
    release.attemptedByteSavingPercent;
result.incrementalAttemptedBytes = ...
    releaseOutcome.attemptedBytes - baseOutcome.attemptedBytes;
result.minimumFormationEospaGainPercent = ...
    release.minimumFormationGainPercent;
result.minimumFormationRmseGainPercent = ...
    release.minimumFormationRmseGainPercent;
result.formationEospaGainPercent = release.formationGainPercent;
result.formationRmseGainPercent = release.formationRmseGainPercent;
result.worstSensorEospaGainPercent = release.worstGainPercent;
result.worstSensorRmseGainPercent = release.worstRmseGainPercent;
result.developmentGatePassed = ...
    release.meanGainPercent >= 5 && ...
    release.rmseGainPercent >= 2 && ...
    release.worstGainPercent >= 0 && ...
    release.worstRmseGainPercent >= 0 && ...
    release.minimumFormationGainPercent >= 0 && ...
    release.minimumFormationRmseGainPercent >= 0 && ...
    release.consensusGainPercent >= 0 && ...
    release.attemptedByteSavingPercent >= 0;
result.validationClaimAllowed = false;
result.evidenceBoundary = releaseProtocol.evidenceBoundary;

matPath = fullfile(outputRoot, sprintf( ...
    'FORMATION_RELEASE_V191_%s_RECURSIVE_PILOT.mat', scaleName));
reportPath = fullfile(outputRoot, sprintf( ...
    'FORMATION_RELEASE_V191_%s_RECURSIVE_PILOT.md', scaleName));
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V191 %s recursive pilot: %s\n', scaleName, reportPath);
end

function [requestedByTime, appliedByTime, effectiveByTime] = ...
        summarizeReleasePlan(plan, selectedByTime, returnTimes)
pageCount = numel(returnTimes);
requestedByTime = repmat({zeros(1, 0)}, 1, pageCount);
appliedByTime = repmat({zeros(1, 0)}, 1, pageCount);
effectiveByTime = repmat({zeros(1, 0)}, 1, pageCount);
for pageIdx = 1:pageCount
    selected = reshape(selectedByTime{pageIdx}, 1, []);
    planIdx = find(reshape(plan.times, 1, []) == returnTimes(pageIdx), 1);
    if ~isempty(planIdx)
        requestedByTime{pageIdx} = reshape( ...
            plan.formationIdsByTime{planIdx}, 1, []);
    end
    appliedByTime{pageIdx} = intersect( ...
        selected, requestedByTime{pageIdx}, 'stable');
    effectiveByTime{pageIdx} = setdiff( ...
        selected, appliedByTime{pageIdx}, 'stable');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('OnlinePositiveNetReleaseV191:WriteFailed', ...
        'Could not create the recursive V191 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V191 %s H=3 recursive formation-release pilot\n\n', ...
    result.scaleName);
fprintf(fid, '- Release page offsets: `%s`\n', ...
    mat2str(result.releasePageOffsets));
fprintf(fid, '- Requested releases by page: `%s`\n', ...
    cellVectorText(result.requestedReleaseFormationIdsByTime));
fprintf(fid, '- Applied releases by page: `%s`\n', ...
    cellVectorText(result.appliedReleaseFormationIdsByTime));
fprintf(fid, '- Effective withheld formations by page: `%s`\n', ...
    cellVectorText(result.effectiveWithheldFormationIdsByTime));
fprintf(fid, '- Release actually applied: `%d`\n\n', ...
    result.releaseActuallyApplied);
fprintf(fid, '| Metric | Reference | V99 base | V191 release |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
fprintf(fid, '| Mean E-OSPA | %.6f | %.6f | %.6f |\n', ...
    result.referenceMeanEospa, result.baseMeanEospa, ...
    result.releaseMeanEospa);
fprintf(fid, '| E-OSPA gain | 0 | %+.3f%% | %+.3f%% |\n', ...
    result.baseEospaGainPercent, result.releaseEospaGainPercent);
fprintf(fid, '| Mean RMSE | %.6f | %.6f | %.6f |\n', ...
    result.referenceMeanRmse, result.baseMeanRmse, ...
    result.releaseMeanRmse);
fprintf(fid, '| RMSE gain | 0 | %+.3f%% | %+.3f%% |\n', ...
    result.baseRmseGainPercent, result.releaseRmseGainPercent);
fprintf(fid, '| Consensus gain | 0 | %+.3f%% | %+.3f%% |\n', ...
    result.baseConsensusGainPercent, ...
    result.releaseConsensusGainPercent);
fprintf(fid, '| Byte saving | 0 | %+.3f%% | %+.3f%% |\n\n', ...
    result.baseAttemptedByteSavingPercent, ...
    result.releaseAttemptedByteSavingPercent);
fprintf(fid, '- Formation E-OSPA gains: `%s`\n', ...
    mat2str(result.formationEospaGainPercent, 6));
fprintf(fid, '- Formation RMSE gains: `%s`\n\n', ...
    mat2str(result.formationRmseGainPercent, 6));
fprintf(fid, '## Incremental effect over V99\n\n');
fprintf(fid, '- Mean E-OSPA: `%+.3f%%`\n', ...
    result.incrementalEospaGainPercent);
fprintf(fid, '- Mean RMSE: `%+.3f%%`\n', ...
    result.incrementalRmseGainPercent);
fprintf(fid, '- Consensus: `%+.3f%%`\n', ...
    result.incrementalConsensusGainPercent);
fprintf(fid, '- Attempted bytes: `%+d B`\n\n', ...
    round(result.incrementalAttemptedBytes));
fprintf(fid, '- Development gate passed: `%d`\n\n', ...
    result.developmentGatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = cellVectorText(values)
parts = cell(1, numel(values));
for idx = 1:numel(values)
    parts{idx} = mat2str(values{idx});
end
value = ['{', strjoin(parts, ', '), '}'];
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
