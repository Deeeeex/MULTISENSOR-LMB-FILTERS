function [reportPath, preflight] = ...
    auditFormationIsolateReconnectV30Preflight(options)
% AUDITFORMATIONISOLATERECONNECTV30PREFLIGHT No-outcome gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationIsolateReconnectProbeProtocol();
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v30 preflight requires a clean tracked and ', ...
        'MATLAB/Octave source state.']);
end
sourceScreenPath = getField(options, 'sourceScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v29', 'temporal_cross_edge_suspension', ...
    't72', 'screen', ...
    ['FORMATION_TEMPORAL_SUSPENSION_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_CAUSAL_ISOLATE_RECONNECT_V30_', ...
     'PREFLIGHT_20260802.md']));
matPath = getField(options, 'matPath', fullfile( ...
    protocol.outputRoot, 'preflight', ...
    'FORMATION_CAUSAL_ISOLATE_RECONNECT_V30_PREFLIGHT.mat'));
loaded = load(sourceScreenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V30Preflight:MissingSource', ...
        'Frozen v29 primary screen is unavailable.');
end
source = loaded.screen;
assertSourceProvenance(source, protocol);
context = reconstructContext(source);

initialTimer = tic;
initialBank = buildTemporalCrossEdgeSuspensionActionBank(context);
initialBankConstructionSeconds = toc(initialTimer);
assertInitialBankReproduced(initialBank, source.bank);
controlTimer = tic;
control = buildFormationRetentionDebtControl(context);
controlConstructionSeconds = toc(controlTimer);
assertRetentionDebtControlContract(control, protocol);
selectedInitialActionIndex = findInitialActionIndex( ...
    initialBank, control.selectedFormationIds);

preflight = struct();
preflight.contractVersion = ...
    'formation-causal-isolate-reconnect-v30-preflight-v1';
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.protocol = protocol;
preflight.sourceScreenPath = sourceScreenPath;
preflight.sourceGenerationCommit = source.generationGitCommit;
preflight.sourceCachePath = source.cachePath;
preflight.sourceCacheSha256 = source.cacheSha256;
preflight.presetName = source.presetName;
preflight.seed = source.seed;
preflight.currentTime = source.currentTime;
preflight.initialBankConstructionSeconds = ...
    initialBankConstructionSeconds;
preflight.controlConstructionSeconds = ...
    controlConstructionSeconds;
preflight.initialBank = initialBank;
preflight.retentionDebtControlAtAnchor = control;
preflight.safeInitialNonreferenceActionCount = ...
    initialBank.safeNonreferenceActionCount;
preflight.selectedInitialActionIndex = ...
    selectedInitialActionIndex;
preflight.selectedInitialActionName = ...
    initialBank.actionNames{selectedInitialActionIndex};
preflight.selectedFormationIdsAtAnchor = ...
    control.selectedFormationIds;
preflight.requestedFormationIdsAtAnchor = ...
    control.requestedFormationIds;
preflight.formationRetentionDebtFractionAtAnchor = ...
    control.formationRetentionDebtFraction;
preflight.referenceFormationExpectedCardinalityAtAnchor = ...
    control.referenceFormationExpectedCardinality;
preflight.singleActionSafetyMaskAtAnchor = ...
    control.singleActionSafetyMask;
preflight.controllerReferenceFallbackAtAnchor = ...
    control.referenceFallbackUsed;
preflight.trackingContinuationExecuted = false;
preflight.newStateOpened = false;
preflight.truthUsed = false;
preflight.futureOutcomeUsed = false;
preflight.gnnTrainingAuthorized = false;
preflight.x36Opened = false;
preflight.x48Opened = false;
preflight.validationClaimAllowed = false;
preflight.primaryTrackingScreenAuthorized = ...
    ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles) && ...
    initialBank.safeNonreferenceActionCount > 0 && ...
    selectedInitialActionIndex ~= ...
        initialBank.referenceActionIndex && ...
    initialBank.actionPosteriorSafetyMask( ...
        selectedInitialActionIndex) && ...
    ~control.referenceFallbackUsed && ...
    control.selectedScore.safe && ...
    all(control.selectedRollingB3SensorPass) && ...
    all(control.selectedRollingB3FormationPass);
preflight.evidenceBoundary = protocol.evidenceBoundary;

if exist(fileparts(matPath), 'dir') ~= 7
    mkdir(fileparts(matPath));
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('V30 isolate-reconnect preflight: %s\n', reportPath);
end

function context = reconstructContext(source)
inputs = generateDynamicTopologyScenarioInputs( ...
    source.presetName, source.seed);
loaded = load(source.cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V30Preflight:MissingCache', ...
        'Opened behavior cache is unavailable.');
end
bundle = loaded.behaviorBundle;
currentTime = source.currentTime;
history = bundle.preDecisionTopologyHistoryByTime{currentTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{currentTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = previousHistory;
context.previousAdjacencyHistoryCount = size(previousHistory, 3);
context.previousAdjacencyHistoryTimes = history.times;
context.previousAdjacency = previousHistory(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * ...
    inputs.config.numberOfSensors;
context.positions = inputs.graphData.positions(:, :, currentTime);
end

function assertSourceProvenance(source, protocol)
if ~strcmp(source.contractVersion, ...
        'formation-temporal-cross-edge-suspension-v29-screen-v1') || ...
        ~strcmp(source.generationGitCommit, ...
            protocol.sourceV29ScreenCommit) || ...
        source.generationTrackedWorktreeDirty || ...
        ~isempty(source.generationUntrackedSourceFiles) || ...
        ~strcmp(source.cacheSha256, protocol.sourceCacheSha256) || ...
        ~strcmp(source.presetName, protocol.presetName) || ...
        source.seed ~= protocol.seed || ...
        source.currentTime ~= protocol.primarySnapshotTime || ...
        source.strictStrongCandidateCount ~= 0 || ...
        source.strongCandidateFound || ...
        source.additionalOpenedStateScreenAuthorized || ...
        source.gnnTrainingAuthorized || ...
        source.x36OutcomeOpeningAuthorized || ...
        source.x48OutcomeOpeningAuthorized || ...
        source.validationClaimAllowed
    error('V30Preflight:SourceProvenance', ...
        'Frozen v29 failure evidence changed.');
end
end

function assertInitialBankReproduced(current, source)
fields = { ...
    'actionAdjacency', 'actionFusionWeights', ...
    'actionPosteriorSafetyMask', 'retentionRisk', ...
    'networkDisagreementRisk'};
if ~strcmp(current.contractVersion, source.contractVersion) || ...
        current.actionCount ~= source.actionCount
    error('V30Preflight:InitialBankDrift', ...
        'Frozen v29 initial bank contract changed.');
end
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    if ~isequaln(current.(fieldName), source.(fieldName))
        error('V30Preflight:InitialBankDrift', ...
            'Frozen v29 initial bank field %s changed.', fieldName);
    end
end
end

function assertRetentionDebtControlContract(control, protocol)
if ~strcmp(control.contractVersion, ...
        'formation-retention-debt-control-v1') || ...
        ~strcmp(control.protocolId, protocol.id) || ...
        control.nodeCount ~= protocol.expectedNodeCount || ...
        control.formationCount ~= protocol.expectedFormationCount || ...
        control.evaluatedRouteCount < 1 || ...
        control.evaluatedRouteCount > ...
            protocol.maximumControlRouteEvaluations || ...
        ~control.referenceScore.safe || ...
        ~control.selectionUsesCurrentPosterior || ...
        ~control.selectionUsesCurrentLinkReliability || ...
        ~control.selectionUsesSelectedTopologyHistory || ...
        ~control.hysteresisEnabled || ...
        ~isequal(control.selectedFormationIds, ...
            protocol.expectedPrimarySelectedFormationIds) || ...
        control.referenceFallbackUsed || ...
        control.selectedMessageCount > ...
            control.referenceMessageCount || ...
        ~control.selectedScore.safe || ...
        ~all(control.selectedRollingB3SensorPass) || ...
        ~all(control.selectedRollingB3FormationPass) || ...
        control.truthUsed || control.futureOutcomeUsed || ...
        control.validationClaimAllowed
    error('V30Preflight:RetentionDebtControlContract', ...
        'The v30 retention-debt controller violated a frozen invariant.');
end
end

function actionIdx = findInitialActionIndex(bank, formationIds)
matches = false(1, bank.actionCount);
formationIds = reshape(formationIds, 1, []);
for candidateIdx = 1:bank.actionCount
    matches(candidateIdx) = isequal(reshape( ...
        bank.actionSuspendedFormationIds{candidateIdx}, 1, []), ...
        formationIds);
end
actionIdx = find(matches);
if numel(actionIdx) ~= 1
    error('V30Preflight:InitialActionMapping', ...
        'The controller selection does not map to one v29 action.');
end
end

function writeReport(path, preflight)
control = preflight.retentionDebtControlAtAnchor;
fid = fopen(path, 'w');
if fid < 0
    error('V30Preflight:WriteFailed', ...
        'Could not open v30 preflight report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V30 causal retention-debt preflight\n\n');
fprintf(fid, '- Contract: `%s`\n', preflight.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    preflight.generationGitCommit);
fprintf(fid, '- Tracked worktree dirty: `%d`\n', ...
    preflight.generationTrackedWorktreeDirty);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    preflight.presetName, preflight.seed, preflight.currentTime);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    preflight.sourceCacheSha256);
fprintf(fid, '- Safe initial nonreference actions: `%d`\n', ...
    preflight.safeInitialNonreferenceActionCount);
fprintf(fid, '- Controller evaluations at anchor: `%d`\n', ...
    control.evaluatedRouteCount);
fprintf(fid, '- Anchor requested / selected formations: `%s / %s`\n', ...
    mat2str(control.requestedFormationIds), ...
    mat2str(control.selectedFormationIds));
fprintf(fid, '- Selected initial action: `%d / %s`\n', ...
    preflight.selectedInitialActionIndex, ...
    preflight.selectedInitialActionName);
fprintf(fid, '- Tracking continuation executed: `0`\n');
fprintf(fid, '- New state / X36 / X48 opened: `0 / 0 / 0`\n');
fprintf(fid, '- Initial bank / controller construction: `%.2f / %.2f s`\n\n', ...
    preflight.initialBankConstructionSeconds, ...
    preflight.controlConstructionSeconds);

fprintf(fid, '## Anchor-state source-only diagnostic\n\n');
fprintf(fid, [ ...
    '| Formation | Previously suspended | Reference E-card | ', ...
    'Suspend d-card | Retention debt | Active threshold | ', ...
    'Single safe | Requested |\n']);
fprintf(fid, [ ...
    '|--:|:--:|--:|--:|--:|--:|:--:|:--:|\n']);
for formationIdx = 1:control.formationCount
    score = control.singleActionScores{formationIdx};
    cardinalityChange = NaN;
    if ~isempty(score)
        cardinalityChange = score.retentionDetails. ...
            formationMeanCardinalityChange(formationIdx);
    end
    fprintf(fid, [ ...
        '| %d | %d | %.6f | %+.6f | %+.3f%% | %.3f%% | %d | %d |\n'], ...
        control.groups(formationIdx), ...
        control.previouslySuspendedMask(formationIdx), ...
        control.referenceFormationExpectedCardinality(formationIdx), ...
        cardinalityChange, ...
        100 * control.formationRetentionDebtFraction(formationIdx), ...
        100 * control.debtThresholdByFormation(formationIdx), ...
        control.singleActionSafetyMask(formationIdx), ...
        ismember(control.groups(formationIdx), ...
            control.requestedFormationIds));
end

fprintf(fid, '\n## Decision\n\n');
fprintf(fid, [ ...
    'The v29 initial bank is reproduced exactly and at least one ', ...
    'nonreference suspension action remains safe. The frozen 2%%/1%% ', ...
    'hysteretic retention-debt rule selects formations `%s` without ', ...
    'truth or future outcomes and maps uniquely to `%s`. The controller ', ...
    'will be recomputed from the live posterior at all three selected ', ...
    'steps, with exact joint label-retention and rolling-B3 projection. ', ...
    'The primary M24/t72 tracking screen may run.\n\n'], ...
    mat2str(control.selectedFormationIds), ...
    preflight.selectedInitialActionName);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
