function writeReport(path, result, datasets)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open report path: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation-gateway proxy audit\n\n');
fprintf(fid, '- Generated: %s\n', result.generatedAt);
fprintf(fid, '- Candidate policies: `%d`\n', result.candidateCount);
fprintf(fid, '- Training blocks used for selection: `%s`\n', ...
    mat2str(result.trainDatasetIndices));
fprintf(fid, '- Read-only validation blocks: `%s`\n', ...
    mat2str(result.validationDatasetIndices));
fprintf(fid, '- Training gate passed: `%d`\n', ...
    result.trainingGatePassed);
fprintf(fid, '- Validation gate passed: `%d`\n', ...
    result.validationGatePassed);
fprintf(fid, '- All observed blocks pass: `%d`\n', ...
    result.allObservedBlocksPassGate);
fprintf(fid, '- Evidence boundary: %s\n\n', result.evidenceBoundary);
fprintf(fid, '## Selected training-only policy\n\n');
writeParameters(fid, result.selected.parameters);
fprintf(fid, '\n| Block | Split | Risk improvement vs RR | ');
fprintf(fid, ['Worst override | Harmful overrides | Overrides | ', ...
    'Formation coverage | Bytes ratio | Oracle capture |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|--:|--:|--:|--:|\n');
for datasetIdx = 1:numel(datasets)
    split = 'unused';
    if any(result.trainDatasetIndices == datasetIdx)
        split = 'train';
    elseif any(result.validationDatasetIndices == datasetIdx)
        split = 'validation';
    end
    metric = result.selected.metrics(datasetIdx);
    fprintf(fid, ['| %s seed %d t=%d | %s | %.4f | %.4f | ', ...
        '%.4f | %d | %.4f | %.4f | %.4f |\n'], ...
        datasets(datasetIdx).presetName, datasets(datasetIdx).seed, ...
        datasets(datasetIdx).snapshotTime, split, ...
        metric.aggregateRiskImprovement, ...
        metric.minimumOverrideNormalizedResidual, ...
        metric.harmfulOverrideFraction, metric.overrideCount, ...
        metric.formationCoverageFraction, ...
        metric.attemptedByteRatio, ...
        metric.oracleGatewayCaptureFraction);
end
fprintf(fid, '\n## Top policies by training-only safety key\n\n');
fprintf(fid, ['| Rank | w | phase | +exist | +precision | -exist | ', ...
    '-precision | discrepancy | need | margin | min novelty | ', ...
    'Worst train gain | Train harmful | Validation gain | ', ...
    'Validation harmful |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|--:|--:|--:|\n']);
for rankIdx = 1:numel(result.topCandidates)
    candidate = result.topCandidates(rankIdx);
    p = candidate.parameters;
    fprintf(fid, ['| %d | %.2f | %d | %.2f | %.2f | %.2f | ', ...
        '%.2f | %.2f | %.2f | %.3f | %.3f | %.4f | %.4f | ', ...
        '%.4f | %.4f |\n'], ...
        rankIdx, p.sourceWeight, p.baselinePhase, ...
        p.positiveExistenceWeight, p.positivePrecisionWeight, ...
        p.negativeExistencePenalty, ...
        p.negativePrecisionPenalty, p.discrepancyPenalty, ...
        p.receiverNeedMultiplier, p.marginThreshold, ...
        p.minimumPositiveExistence, ...
        candidate.minimumTrainAggregateRiskImprovement, ...
        candidate.maximumTrainHarmfulOverrideFraction, ...
        candidate.minimumValidationAggregateRiskImprovement, ...
        candidate.maximumValidationHarmfulOverrideFraction);
end
fprintf(fid, ['\nThe round-robin backbone sends one same-formation ', ...
    'posterior to every receiver. The candidate keeps the same message ', ...
    'count and replaces at most one route per formation. Validation ', ...
    'columns are descriptive only and never affect candidate ranking.\n']);
end

function writeParameters(fid, parameters)
fields = fieldnames(parameters);
for fieldIdx = 1:numel(fields)
    fprintf(fid, '- %s: `%.6g`\n', fields{fieldIdx}, ...
        parameters.(fields{fieldIdx}));
end
end

function paths = normalizePaths(paths)
if ischar(paths)
    paths = {paths};
end
paths = reshape(paths, 1, []);
for pathIdx = 1:numel(paths)
    if ~ischar(paths{pathIdx}) || ~exist(paths{pathIdx}, 'file')
        error('Missing dataset path: %s', char(paths{pathIdx}));
    end
end
end

function assertValidSplit(train, validation, datasetCount)
if isempty(train) || isempty(validation) || ...
        any(train < 1 | train > datasetCount) || ...
        any(validation < 1 | validation > datasetCount) || ...
        any(mod(train, 1) ~= 0) || any(mod(validation, 1) ~= 0) || ...
        any(ismember(train, validation))
    error('Training and validation dataset indices must be valid/disjoint.');
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
