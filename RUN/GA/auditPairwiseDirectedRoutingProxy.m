function [reportPath, result] = ...
    auditPairwiseDirectedRoutingProxy(datasetPaths, options)
% AUDITPAIRWISEDIRECTEDROUTINGPROXY Audit safe cross-formation handovers.
%
% The default action is a balanced, intra-formation round-robin route for
% every receiver. A candidate may replace at most one receiver route per
% formation with a physical cross-formation route. Replacements are chosen
% from a truth-free pairwise utility margin and are evaluated afterward
% with privileged one-step teacher labels.
%
% Candidate selection uses only trainDatasetIndices. Validation labels are
% never included in the selection key. This is a snapshot proxy audit, not
% closed-loop or held-out tracking evidence.

if nargin < 1 || isempty(datasetPaths)
    datasetPaths = arrayfun(@(seed) fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'cache', ...
        sprintf( ...
            'directed_teacher_v2_m24_hard_seed%d_t75.mat', seed)), ...
        [7, 11, 17], 'UniformOutput', false);
end
if nargin < 2 || isempty(options)
    options = struct();
end
datasetPaths = normalizePaths(datasetPaths);
trainDatasetIndices = reshape(getField( ...
    options, 'trainDatasetIndices', 1:max(numel(datasetPaths) - 1, 1)), ...
    1, []);
validationDatasetIndices = reshape(getField( ...
    options, 'validationDatasetIndices', ...
    setdiff(1:numel(datasetPaths), trainDatasetIndices)), 1, []);
if isempty(validationDatasetIndices)
    validationDatasetIndices = trainDatasetIndices;
end
assertValidSplit( ...
    trainDatasetIndices, validationDatasetIndices, numel(datasetPaths));

datasets = loadDatasets(datasetPaths);
grid = resolveGrid(options, datasets);
constraints = resolveConstraints(options);
candidateCount = gridSize(grid);
topCount = max(1, round(getField(options, 'topCandidateCount', 20)));
top = repmat(emptyCandidate(numel(datasets)), 1, 0);

candidateIdx = 0;
for sourceWeight = grid.sourceWeight
    for baselinePhase = grid.baselinePhase
        for positiveExistenceWeight = ...
                grid.positiveExistenceWeight
            for positivePrecisionWeight = ...
                    grid.positivePrecisionWeight
                for negativeExistencePenalty = ...
                        grid.negativeExistencePenalty
                    for negativePrecisionPenalty = ...
                            grid.negativePrecisionPenalty
                        for discrepancyPenalty = ...
                                grid.discrepancyPenalty
                            for receiverNeedMultiplier = ...
                                    grid.receiverNeedMultiplier
                                for marginThreshold = ...
                                        grid.marginThreshold
                                    for minimumPositiveExistence = ...
                                            grid.minimumPositiveExistence
                                        candidateIdx = candidateIdx + 1;
                                        parameters = struct( ...
                                            'sourceWeight', sourceWeight, ...
                                            'baselinePhase', baselinePhase, ...
                                            'positiveExistenceWeight', ...
                                                positiveExistenceWeight, ...
                                            'positivePrecisionWeight', ...
                                                positivePrecisionWeight, ...
                                            'negativeExistencePenalty', ...
                                                negativeExistencePenalty, ...
                                            'negativePrecisionPenalty', ...
                                                negativePrecisionPenalty, ...
                                            'discrepancyPenalty', ...
                                                discrepancyPenalty, ...
                                            'receiverNeedMultiplier', ...
                                                receiverNeedMultiplier, ...
                                            'marginThreshold', ...
                                                marginThreshold, ...
                                            'minimumPositiveExistence', ...
                                                minimumPositiveExistence);
                                        candidate = evaluateCandidate( ...
                                            datasets, parameters, ...
                                            constraints, ...
                                            trainDatasetIndices, ...
                                            validationDatasetIndices);
                                        top = insertTop( ...
                                            top, candidate, topCount);
                                    end
                                end
                            end
                        end
                    end
                end
            end
        end
    end
end

selected = top(1);
result = struct();
result.generatedAt = datestr(now, 31);
result.datasetPaths = datasetPaths;
result.trainDatasetIndices = trainDatasetIndices;
result.validationDatasetIndices = validationDatasetIndices;
result.grid = grid;
result.constraints = constraints;
result.candidateCount = candidateCount;
result.selected = selected;
result.topCandidates = top;
result.trainingGatePassed = splitPassesGate( ...
    selected.metrics(trainDatasetIndices), constraints);
result.validationGatePassed = splitPassesGate( ...
    selected.metrics(validationDatasetIndices), constraints);
result.allObservedBlocksPassGate = splitPassesGate( ...
    selected.metrics, constraints);
result.evidenceBoundary = [ ...
    'Truth-free scores are selected on declared training snapshots; ', ...
    'privileged labels only audit selected actions. Validation labels ', ...
    'do not affect ranking. No closed-loop or held-out claim.'];

reportPath = '';
if getField(options, 'writeReport', true)
    outputDirectory = getField(options, 'outputDirectory', ...
        fullfile('RUN', 'GA', 'dynamic_topology'));
    if ~exist(outputDirectory, 'dir')
        mkdir(outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    reportPath = fullfile(outputDirectory, [ ...
        'FORMATION_GATEWAY_PROXY_AUDIT_', timestamp, '.md']);
    writeReport(reportPath, result, datasets);
    result.reportPath = reportPath;
    fprintf('Report: %s\n', reportPath);
end
end

function grid = resolveGrid(options, datasets)
maximumPhase = 1;
for datasetIdx = 1:numel(datasets)
    groups = unique(datasets(datasetIdx).groupIds, 'stable');
    for groupIdx = 1:numel(groups)
        maximumPhase = max(maximumPhase, ...
            nnz(datasets(datasetIdx).groupIds == groups(groupIdx)) - 1);
    end
end
grid = struct();
grid.sourceWeight = reshape(getField( ...
    options, 'sourceWeightGrid', [0.30, 0.50, 0.70]), 1, []);
grid.baselinePhase = reshape(getField( ...
    options, 'baselinePhaseGrid', 1:maximumPhase), 1, []);
grid.positiveExistenceWeight = reshape(getField( ...
    options, 'positiveExistenceWeightGrid', [0.50, 1, 2, 4]), ...
    1, []);
grid.positivePrecisionWeight = reshape(getField( ...
    options, 'positivePrecisionWeightGrid', [0, 1]), 1, []);
grid.negativeExistencePenalty = reshape(getField( ...
    options, 'negativeExistencePenaltyGrid', [0, 0.25, 1, 2]), ...
    1, []);
grid.negativePrecisionPenalty = reshape(getField( ...
    options, 'negativePrecisionPenaltyGrid', [50, 100, 200]), ...
    1, []);
grid.discrepancyPenalty = reshape(getField( ...
    options, 'discrepancyPenaltyGrid', [2, 4, 8]), 1, []);
grid.receiverNeedMultiplier = reshape(getField( ...
    options, 'receiverNeedMultiplierGrid', [0, 1, 2]), 1, []);
grid.marginThreshold = reshape(getField( ...
    options, 'marginThresholdGrid', [0, 0.01, 0.02, 0.05, 0.10]), ...
    1, []);
grid.minimumPositiveExistence = reshape(getField( ...
    options, 'minimumPositiveExistenceGrid', [0, 0.01, 0.02, 0.04]), ...
    1, []);
fields = fieldnames(grid);
for fieldIdx = 1:numel(fields)
    values = grid.(fields{fieldIdx});
    if isempty(values) || any(~isfinite(values))
        error('Proxy grid field %s must be finite and nonempty.', ...
            fields{fieldIdx});
    end
end
if any(grid.sourceWeight <= 0 | grid.sourceWeight >= 1)
    error('Source weights must be strictly between zero and one.');
end
if any(grid.baselinePhase < 1 | mod(grid.baselinePhase, 1) ~= 0)
    error('Baseline phases must be positive integers.');
end
nonnegativeFields = setdiff(fields, ...
    {'sourceWeight', 'baselinePhase'});
for fieldIdx = 1:numel(nonnegativeFields)
    if any(grid.(nonnegativeFields{fieldIdx}) < 0)
        error('Proxy grid field %s must be nonnegative.', ...
            nonnegativeFields{fieldIdx});
    end
end
end

function constraints = resolveConstraints(options)
constraints = struct();
constraints.maxCrossPerFormation = max(0, floor(getField( ...
    options, 'maxCrossPerFormation', 1)));
constraints.maxCrossSourceLoad = max(1, floor(getField( ...
    options, 'maxCrossSourceLoad', 1)));
constraints.anchorTime = round(getField(options, 'anchorTime', 1));
constraints.minimumAggregateRiskImprovement = getField( ...
    options, 'minimumAggregateRiskImprovement', 0.05);
constraints.maximumHarmfulOverrideFraction = getField( ...
    options, 'maximumHarmfulOverrideFraction', 0);
constraints.maximumAttemptedByteDeviation = getField( ...
    options, 'maximumAttemptedByteDeviation', 0.02);
constraints.minimumOverridesPerBlock = max(0, floor(getField( ...
    options, 'minimumOverridesPerBlock', 1)));
if constraints.maxCrossPerFormation < 1
    error('maxCrossPerFormation must be at least one for this audit.');
end
end

function count = gridSize(grid)
fields = fieldnames(grid);
count = 1;
for fieldIdx = 1:numel(fields)
    count = count * numel(grid.(fields{fieldIdx}));
end
end

function datasets = loadDatasets(paths)
datasets = repmat(struct(), 1, numel(paths));
expectedFeatureNames = {};
expectedWeightGrid = [];
for datasetIdx = 1:numel(paths)
    loaded = load(paths{datasetIdx}, ...
        'actionFeatures', 'actionFeatureNames', ...
        'actionFeatureMetadata', 'teacherDetails', ...
        'datasetMetadata');
    required = {'actionFeatures', 'actionFeatureNames', ...
        'actionFeatureMetadata', 'teacherDetails', 'datasetMetadata'};
    if ~all(isfield(loaded, required))
        error('Incomplete teacher dataset: %s', paths{datasetIdx});
    end
    featureNames = reshape(loaded.actionFeatureNames, 1, []);
    weightGrid = reshape( ...
        loaded.actionFeatureMetadata.sourceWeightGrid, 1, []);
    if isempty(expectedFeatureNames)
        expectedFeatureNames = featureNames;
        expectedWeightGrid = weightGrid;
    elseif ~isequal(featureNames, expectedFeatureNames) || ...
            ~isequal(weightGrid, expectedWeightGrid)
        error('Teacher dataset feature contracts differ.');
    end
    metadata = loaded.datasetMetadata;
    if ~isfield(metadata, 'featuresUseTruth') || ...
            metadata.featuresUseTruth || ...
            ~isfield(metadata, 'truthUsedForLabelsOnly') || ...
            ~metadata.truthUsedForLabelsOnly
        error('Teacher dataset truth boundary is invalid: %s', ...
            paths{datasetIdx});
    end
    if ~isfield(loaded.teacherDetails, 'nodePayloadBytes')
        error('Teacher dataset lacks nodePayloadBytes: %s', ...
            paths{datasetIdx});
    end
    datasets(datasetIdx).path = paths{datasetIdx};
    datasets(datasetIdx).presetName = metadata.presetName;
    datasets(datasetIdx).seed = metadata.seed;
    datasets(datasetIdx).snapshotTime = metadata.snapshotTime;
    datasets(datasetIdx).featureNames = featureNames;
    datasets(datasetIdx).weightGrid = weightGrid;
    datasets(datasetIdx).features = loaded.actionFeatures;
    datasets(datasetIdx).expectedGain = ...
        loaded.teacherDetails.firstStepExpectedGainByWeight;
    datasets(datasetIdx).nodeRisk = reshape( ...
        loaded.teacherDetails.nodeRiskBefore, 1, []);
    datasets(datasetIdx).nodePayloadBytes = reshape( ...
        loaded.teacherDetails.nodePayloadBytes, 1, []);
    datasets(datasetIdx).groupIds = reshape( ...
        metadata.scenarioConfigSnapshot.sensorGroupIds, 1, []);
end
end

function candidate = evaluateCandidate( ...
    datasets, parameters, constraints, trainIndices, validationIndices)
metrics = repmat(emptyMetrics(), 1, numel(datasets));
for datasetIdx = 1:numel(datasets)
    metrics(datasetIdx) = evaluateOne( ...
        datasets(datasetIdx), parameters, constraints);
end
trainMetrics = metrics(trainIndices);
validationMetrics = metrics(validationIndices);
candidate = emptyCandidate(numel(datasets));
candidate.parameters = parameters;
candidate.metrics = metrics;
candidate.minimumTrainAggregateRiskImprovement = min( ...
    [trainMetrics.aggregateRiskImprovement]);
candidate.meanTrainAggregateRiskImprovement = mean( ...
    [trainMetrics.aggregateRiskImprovement]);
candidate.maximumTrainHarmfulOverrideFraction = max( ...
    [trainMetrics.harmfulOverrideFraction]);
candidate.minimumTrainOverrideResidual = min( ...
    [trainMetrics.minimumOverrideNormalizedResidual]);
candidate.maximumTrainAttemptedByteDeviation = max(abs( ...
    [trainMetrics.attemptedByteRatio] - 1));
candidate.minimumTrainOverrideCount = min( ...
    [trainMetrics.overrideCount]);
candidate.minimumValidationAggregateRiskImprovement = min( ...
    [validationMetrics.aggregateRiskImprovement]);
candidate.maximumValidationHarmfulOverrideFraction = max( ...
    [validationMetrics.harmfulOverrideFraction]);
candidate.minimumValidationOverrideResidual = min( ...
    [validationMetrics.minimumOverrideNormalizedResidual]);
candidate.maximumValidationAttemptedByteDeviation = max(abs( ...
    [validationMetrics.attemptedByteRatio] - 1));

% Safety dominates utility. Validation metrics are deliberately absent.
candidate.selectionKey = [ ...
    candidate.maximumTrainHarmfulOverrideFraction > ...
        constraints.maximumHarmfulOverrideFraction, ...
    candidate.maximumTrainHarmfulOverrideFraction, ...
    -candidate.minimumTrainAggregateRiskImprovement, ...
    -candidate.meanTrainAggregateRiskImprovement, ...
    candidate.maximumTrainAttemptedByteDeviation, ...
    -candidate.minimumTrainOverrideCount];
end

function metrics = evaluateOne(dataset, parameters, constraints)
featureNames = dataset.featureNames;
features = dataset.features;
weightIdx = findClosestWeight( ...
    dataset.weightGrid, parameters.sourceWeight);
reliability = feature( ...
    features, featureNames, 'link_reliability', weightIdx);
positiveExistence = feature( ...
    features, featureNames, 'positive_existence_gain', weightIdx);
positivePrecision = feature( ...
    features, featureNames, 'positive_precision_gain', weightIdx);
negativeExistence = feature( ...
    features, featureNames, 'negative_existence_gap', weightIdx);
negativePrecision = feature( ...
    features, featureNames, 'negative_precision_gap', weightIdx);
discrepancy = feature( ...
    features, featureNames, 'normalized_state_discrepancy', weightIdx);
overlap = feature( ...
    features, featureNames, 'active_label_overlap', weightIdx);
receiverNeed = feature( ...
    features, featureNames, 'receiver_need', weightIdx);
alpha = parameters.sourceWeight;
positiveInformation = ...
    parameters.positiveExistenceWeight * positiveExistence + ...
    parameters.positivePrecisionWeight * positivePrecision;
utility = reliability .* alpha .* ...
    (1 + parameters.receiverNeedMultiplier * receiverNeed) .* ...
    positiveInformation ...
    - alpha * ( ...
        parameters.negativeExistencePenalty * negativeExistence + ...
        parameters.negativePrecisionPenalty * negativePrecision) ...
    - parameters.discrepancyPenalty * alpha^2 .* ...
        overlap .* discrepancy;

nodeCount = size(utility, 1);
baselineSender = roundRobinSenderByReceiver( ...
    dataset.groupIds, dataset.snapshotTime, ...
    constraints.anchorTime, parameters.baselinePhase);
baselineGain = nan(1, nodeCount);
baselineUtility = nan(1, nodeCount);
for receiverIdx = 1:nodeCount
    senderIdx = baselineSender(receiverIdx);
    if ~isfinite(senderIdx) || ...
            ~isfinite(utility(receiverIdx, senderIdx))
        error([ ...
            'The registered intra-formation baseline is not physical ', ...
            'for %s seed %d, receiver %d, phase %d.'], ...
            dataset.presetName, dataset.seed, receiverIdx, ...
            parameters.baselinePhase);
    end
    baselineGain(receiverIdx) = dataset.expectedGain( ...
        receiverIdx, senderIdx, weightIdx);
    baselineUtility(receiverIdx) = utility(receiverIdx, senderIdx);
end

proposals = repmat(struct( ...
    'receiver', NaN, 'sender', NaN, 'formation', NaN, ...
    'margin', -inf), 1, 0);
bestCrossSenderByReceiver = nan(1, nodeCount);
bestCrossMarginByReceiver = -inf(1, nodeCount);
for receiverIdx = 1:nodeCount
    cross = isfinite(utility(receiverIdx, :)) & ...
        dataset.groupIds ~= dataset.groupIds(receiverIdx) & ...
        positiveExistence(receiverIdx, :) >= ...
            parameters.minimumPositiveExistence;
    senders = find(cross);
    if isempty(senders)
        continue;
    end
    [bestUtility, bestCursor] = max( ...
        utility(receiverIdx, senders));
    margin = bestUtility - baselineUtility(receiverIdx);
    bestCrossSenderByReceiver(receiverIdx) = senders(bestCursor);
    bestCrossMarginByReceiver(receiverIdx) = margin;
    if margin <= parameters.marginThreshold
        continue;
    end
    proposals(end + 1) = struct( ... %#ok<AGROW>
        'receiver', receiverIdx, ...
        'sender', senders(bestCursor), ...
        'formation', dataset.groupIds(receiverIdx), ...
        'margin', margin);
end

selectedSender = baselineSender;
overrideMask = false(1, nodeCount);
if ~isempty(proposals)
    [~, order] = sort([proposals.margin], 'descend');
    formationLoad = zeros(1, max(dataset.groupIds));
    sourceLoad = zeros(1, nodeCount);
    for cursor = reshape(order, 1, [])
        proposal = proposals(cursor);
        if formationLoad(proposal.formation) >= ...
                constraints.maxCrossPerFormation || ...
                sourceLoad(proposal.sender) >= ...
                constraints.maxCrossSourceLoad
            continue;
        end
        selectedSender(proposal.receiver) = proposal.sender;
        overrideMask(proposal.receiver) = true;
        formationLoad(proposal.formation) = ...
            formationLoad(proposal.formation) + 1;
        sourceLoad(proposal.sender) = sourceLoad(proposal.sender) + 1;
    end
end

selectedGain = baselineGain;
for receiverIdx = find(overrideMask)
    selectedGain(receiverIdx) = dataset.expectedGain( ...
        receiverIdx, selectedSender(receiverIdx), weightIdx);
end
residual = selectedGain - baselineGain;
baselineRisk = dataset.nodeRisk - baselineGain;
selectedRisk = dataset.nodeRisk - selectedGain;
normalizedResidual = residual ./ max(dataset.nodeRisk, eps);
overrideResidual = normalizedResidual(overrideMask);
if isempty(overrideResidual)
    minimumOverrideResidual = 0;
    harmfulOverrideFraction = 0;
    positiveOverrideFraction = 0;
else
    minimumOverrideResidual = min(overrideResidual);
    harmfulOverrideFraction = mean(overrideResidual < -1e-12);
    positiveOverrideFraction = mean(overrideResidual > 1e-12);
end
baselineBytes = sum(dataset.nodePayloadBytes(baselineSender));
selectedBytes = sum(dataset.nodePayloadBytes(selectedSender));
groups = unique(dataset.groupIds, 'stable');

oracleResidual = gatewayOracleResidual( ...
    dataset, baselineGain, weightIdx, ...
    constraints.maxCrossPerFormation);
positiveSelectedResidual = sum(max(residual, 0));
metrics = emptyMetrics();
metrics.aggregateRiskImprovement = ...
    (mean(baselineRisk) - mean(selectedRisk)) / ...
    max(mean(baselineRisk), eps);
metrics.meanNodeNormalizedResidual = mean(normalizedResidual);
metrics.minimumOverrideNormalizedResidual = minimumOverrideResidual;
metrics.harmfulOverrideFraction = harmfulOverrideFraction;
metrics.positiveOverrideFraction = positiveOverrideFraction;
metrics.overrideCount = nnz(overrideMask);
metrics.overrideReceiverFraction = mean(overrideMask);
metrics.formationCoverageFraction = ...
    numel(unique(dataset.groupIds(overrideMask))) / numel(groups);
metrics.attemptedByteRatio = selectedBytes / max(baselineBytes, eps);
metrics.maximumCrossSourceLoad = maximumSourceLoad( ...
    selectedSender(overrideMask), nodeCount);
metrics.oracleGatewayCaptureFraction = ...
    positiveSelectedResidual / max(oracleResidual, eps);
metrics.baselineMeanRisk = mean(baselineRisk);
metrics.selectedMeanRisk = mean(selectedRisk);
metrics.baselineSenderByReceiver = baselineSender;
metrics.selectedSenderByReceiver = selectedSender;
metrics.overrideMask = overrideMask;
metrics.bestCrossSenderByReceiver = bestCrossSenderByReceiver;
metrics.bestCrossMarginByReceiver = bestCrossMarginByReceiver;
end

function senders = roundRobinSenderByReceiver( ...
    groupIds, currentTime, anchorTime, phase)
nodeCount = numel(groupIds);
senders = nan(1, nodeCount);
groups = unique(groupIds, 'stable');
for groupIdx = 1:numel(groups)
    members = reshape(find(groupIds == groups(groupIdx)), 1, []);
    groupSize = numel(members);
    if groupSize < 2
        continue;
    end
    shift = 1 + mod( ...
        currentTime - anchorTime + phase - 1, groupSize - 1);
    senders(members) = circshift(members, [0, -shift]);
end
end

function total = gatewayOracleResidual( ...
    dataset, baselineGain, weightIdx, maxPerFormation)
total = 0;
groups = unique(dataset.groupIds, 'stable');
for groupIdx = 1:numel(groups)
    receivers = find(dataset.groupIds == groups(groupIdx));
    residuals = [];
    for receiverIdx = reshape(receivers, 1, [])
        cross = dataset.groupIds ~= groups(groupIdx);
        gain = reshape(dataset.expectedGain( ...
            receiverIdx, :, weightIdx), 1, []);
        values = gain(cross) - baselineGain(receiverIdx);
        residuals = [residuals, values(isfinite(values))]; %#ok<AGROW>
    end
    residuals = sort(residuals(residuals > 0), 'descend');
    total = total + sum(residuals( ...
        1:min(maxPerFormation, numel(residuals))));
end
end

function value = maximumSourceLoad(senders, nodeCount)
if isempty(senders)
    value = 0;
    return;
end
counts = accumarray(reshape(senders, [], 1), 1, [nodeCount, 1]);
value = max(counts);
end

function matrix = feature(features, names, name, weightIdx)
featureIdx = find(strcmp(names, name), 1);
if isempty(featureIdx)
    error('Missing action feature: %s', name);
end
matrix = reshape( ...
    features(:, :, weightIdx, featureIdx), ...
    size(features, 1), size(features, 2));
end

function index = findClosestWeight(grid, value)
[difference, index] = min(abs(grid - value));
if difference > 1e-12
    error('Requested source weight %.4f is absent from the dataset.', ...
        value);
end
end

function top = insertTop(top, candidate, count)
top(end + 1) = candidate;
keys = vertcat(top.selectionKey);
[~, order] = sortrows(keys, 1:size(keys, 2));
top = top(order(1:min(count, numel(order))));
end

function passed = splitPassesGate(metrics, constraints)
passed = all( ...
    [metrics.aggregateRiskImprovement] >= ...
        constraints.minimumAggregateRiskImprovement & ...
    [metrics.harmfulOverrideFraction] <= ...
        constraints.maximumHarmfulOverrideFraction & ...
    [metrics.minimumOverrideNormalizedResidual] >= -1e-12 & ...
    abs([metrics.attemptedByteRatio] - 1) <= ...
        constraints.maximumAttemptedByteDeviation & ...
    [metrics.overrideCount] >= constraints.minimumOverridesPerBlock);
end

