function replay = replayLearnedSequentialLabelCellV169( ...
        currentTime, receiverIdx)
% REPLAYLEARNEDSEQUENTIALLABELCELLV169 Check the frozen V175 runtime path.

% This all-delivered snapshot replay is a narrow implementation contract
% check. It must reproduce the first and second source-label choices used
% by the V175 preflight before the policy is admitted to recursive V169.

if nargin < 1 || isempty(currentTime)
    currentTime = 79;
end
if nargin < 2 || isempty(receiverIdx)
    receiverIdx = 25;
end
protocol = getLearnedOneHopSafeLabelV169Protocol();
v157 = getPositiveValueReferenceLabelV157Protocol();
screenPath = fullfile( ...
    v157.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']);
v173Path = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v173', 'conditional_second_action', ...
    'CONDITIONAL_SECOND_LABEL_ACTION_DATASET_V173.mat');
v175Path = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v175', 'cardinality_pressure_relief', ...
    'CARDINALITY_PRESSURE_RELIEF_V175_RESULT.mat');
if exist(screenPath, 'file') ~= 2 || exist(v173Path, 'file') ~= 2 || ...
        exist(v175Path, 'file') ~= 2
    error('LearnedOneHopSafeLabelV169:MissingReplayInput', ...
        'The V157 snapshot and V173/V175 preflight artifacts are required.');
end

screen = load(screenPath, 'screen').screen;
dataset = load(v173Path, 'dataset').dataset;
summary = load(v175Path, 'summary').summary;
pageIdx = find(screen.returnTimes == currentTime, 1);
actionIdx = find(strcmp( ...
    {screen.records.actionName}, v157.candidateActionName), 1);
cellRecord = dataset.cells( ...
    [dataset.cells.time] == currentTime & ...
    [dataset.cells.receiver] == receiverIdx);
policyRow = summary.policyRows( ...
    [summary.policyRows.time] == currentTime & ...
    [summary.policyRows.receiver] == receiverIdx);
if isempty(pageIdx) || isempty(actionIdx) || numel(cellRecord) ~= 1 || ...
        numel(policyRow) ~= 1 || ~policyRow.selected
    error('LearnedOneHopSafeLabelV169:ReplayCellDrift', ...
        'The requested frozen replay cell is unavailable.');
end

outcome = screen.outcomes(actionIdx);
inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
model = inputs.model;
model.dynamicTopologyScenario.targetTrajectories = ...
    inputs.targetTrajectories;
nodeCount = numel(screen.sensorGroupIds);
physical = logical(inputs.graphData. ...
    physicalAdjacency(:, :, currentTime));
physical = physical | physical';
physical(1:nodeCount+1:end) = false;
config = selectorConfig(protocol, currentTime, receiverIdx);
baseline = outcome.fusedPosteriorSnapshotsByTime{pageIdx}{receiverIdx};
locals = outcome.localPosteriorSnapshotsByTime{pageIdx};
[trial, details] = selectObservableOneHopRiskLabels( ...
    baseline, locals, physical, physical, config, ...
    receiverIdx, currentTime, model);
expectedLabels = [cellRecord.firstLabel, policyRow.secondLabel];
expectedSources = [cellRecord.firstSource, policyRow.secondSource];
if details.selectedLabelCount ~= 2 || details.appliedLabelCount ~= 2 || ...
        ~details.cardinalityPressureGatePassed || ...
        ~isequal(details.selectedLabels, expectedLabels) || ...
        ~isequal(details.selectedSources, expectedSources)
    error('LearnedOneHopSafeLabelV169:SequentialReplayMismatch', ...
        'The runtime source-label sequence differs from V175 preflight.');
end
replay = struct();
replay.contractVersion = ...
    'learned-one-hop-safe-label-v169-cell-replay-v1';
replay.time = currentTime;
replay.receiver = receiverIdx;
replay.selectedLabels = details.selectedLabels;
replay.selectedSources = details.selectedSources;
replay.safetyScores = details.selectedSafetyScore;
replay.expectedCardinalityFraction = ...
    details.cardinalityPressureExpectedFraction;
replay.mapProbability = details.cardinalityPressureMapProbability;
replay.attemptedBytes = details.attemptedTotalBytes;
replay.eospaGain = evaluateLmbTopologyCurrentEospa( ...
    baseline, model, currentTime, struct()) - ...
    evaluateLmbTopologyCurrentEospa(trial, model, currentTime, struct());
replay.rmseGain = currentPosteriorRmse( ...
    baseline, model, currentTime) - ...
    currentPosteriorRmse(trial, model, currentTime);
replay.truthUsedByPolicy = false;
replay.truthUsedForEvaluation = true;
fprintf(['V169 sequential replay t=%d receiver=%d: labels=%s ', ...
    'sources=%s pressure=%.6f/%.6f E=%+.6f R=%+.6f bytes=%d\n'], ...
    currentTime, receiverIdx, mat2str(replay.selectedLabels), ...
    mat2str(replay.selectedSources), ...
    replay.expectedCardinalityFraction, replay.mapProbability, ...
    replay.eospaGain, replay.rmseGain, replay.attemptedBytes);
end

function config = selectorConfig(protocol, currentTime, receiverIdx)
config = struct( ...
    'observableOneHopRiskLabelEnabled', true, ...
    'observableOneHopRiskLabelTimes', currentTime, ...
    'observableOneHopRiskLabelSensorIdsByTime', {{[]}}, ...
    'observableOneHopRiskLabelMaximumEdits', protocol.maximumLabelEdits, ...
    'observableOneHopRiskLabelExistenceThreshold', ...
        protocol.activeExistenceThreshold, ...
    'observableOneHopRiskLabelMinimumRiskReduction', ...
        protocol.minimumRiskReduction, ...
    'observableOneHopRiskLabelSynopsisHeaderBytes', ...
        protocol.synopsisHeaderBytes, ...
    'observableOneHopRiskLabelSynopsisBytesPerLabel', ...
        protocol.synopsisBytesPerLabel, ...
    'observableOneHopRiskLabelRequestHeaderBytes', ...
        protocol.requestHeaderBytes, ...
    'observableOneHopRiskLabelRequestBytesPerLabel', ...
        protocol.requestBytesPerLabel, ...
    'learnedOneHopSafeLabelEnabled', true, ...
    'learnedOneHopSafeLabelTimes', currentTime, ...
    'learnedOneHopSafeLabelSensorIdsByTime', {{receiverIdx}}, ...
    'learnedOneHopSafeLabelModelPath', protocol.learnedModelPath, ...
    'learnedOneHopSafeLabelPolicyPath', protocol.learnedPolicyPath, ...
    'learnedOneHopSafeLabelMaximumEdits', ...
        protocol.learnedMaximumLabelEdits, ...
    'learnedOneHopSafeLabelSynopsisHeaderBytes', ...
        protocol.learnedSynopsisHeaderBytes, ...
    'learnedOneHopSafeLabelSynopsisBytesPerLabel', ...
        protocol.learnedSynopsisBytesPerLabel, ...
    'learnedOneHopSafeLabelRequestHeaderBytes', ...
        protocol.learnedRequestHeaderBytes, ...
    'learnedOneHopSafeLabelRequestBytesPerLabel', ...
        protocol.learnedRequestBytesPerLabel);
end

function value = currentPosteriorRmse(posterior, model, currentTime)
objects = reshape(posterior, 1, []);
if ~isempty(objects)
    objects = objects([objects.r] > model.existenceThreshold);
end
estimate = zeros(2, 0);
if ~isempty(objects)
    [mapCardinality, mapIndices] = ...
        lmbMapCardinalityEstimate([objects.r]);
    estimate = zeros(2, mapCardinality);
    for idx = 1:mapCardinality
        object = objects(mapIndices(idx));
        weights = reshape(object.w, 1, []);
        weights(~isfinite(weights)) = -inf;
        [~, componentIdx] = max(weights);
        if isempty(componentIdx) || ~isfinite(weights(componentIdx))
            componentIdx = 1;
        end
        estimate(:, idx) = object.mu{componentIdx}(1:2);
    end
end
truth = zeros(2, 0);
trajectories = model.dynamicTopologyScenario.targetTrajectories;
for targetIdx = 1:numel(trajectories)
    if currentTime <= size(trajectories{targetIdx}, 2)
        state = trajectories{targetIdx}(:, currentTime);
        if all(isfinite(state))
            truth(:, end + 1) = state(1:2); %#ok<AGROW>
        end
    end
end
if isempty(estimate) || isempty(truth)
    value = NaN;
    return;
end
distance = zeros(size(estimate, 2), size(truth, 2));
for estimateIdx = 1:size(estimate, 2)
    for truthIdx = 1:size(truth, 2)
        distance(estimateIdx, truthIdx) = norm( ...
            estimate(:, estimateIdx) - truth(:, truthIdx));
    end
end
[matching, ~] = Hungarian(distance);
matched = distance(matching == 1);
if isempty(matched)
    value = NaN;
else
    value = sqrt(mean(matched .^ 2));
end
end
