function matched = numericTraceMatches(actual, expected, tolerance)
matched = isequal(size(actual), size(expected)) && ...
    isequal(isnan(actual), isnan(expected));
if ~matched
    return;
end
finiteMask = ~isnan(expected);
if any(finiteMask(:))
    matched = all(isfinite(actual(finiteMask))) && ...
        max(abs(actual(finiteMask) - expected(finiteMask))) <= ...
            tolerance;
end
end

function lines = splitNonemptyLines(value)
value = strtrim(value);
if isempty(value)
    lines = cell(1, 0);
else
    lines = regexp(value, '\r?\n', 'split');
    lines = reshape(lines, 1, []);
end
end

function value = formatTrace(trace)
parts = cell(1, numel(trace));
for idx = 1:numel(trace)
    parts{idx} = mat2str(trace{idx});
end
value = strjoin(parts, ' -> ');
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) ./ max(reference, eps);
end
