function [reportPath, screen] = ...
    runFormationStaggeredRecoveryX36V37Screen()
% RUNFORMATIONSTAGGEREDRECOVERYX36V37SCREEN Exact permitted X36 two-arm run.

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
originalDirectory = pwd;
cd(repoRoot);
directoryCleanup = onCleanup( ...
    @() cd(originalDirectory)); %#ok<NASGU>

[permit, preflight, releaseDescriptor] = ...
    loadFormationStaggeredRecoveryX36OutcomePermit();
protocol = getFormationStaggeredRecoveryX36SourceProtocol();
assertOutcomeAuthorization(permit, preflight, protocol);

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('V37Screen:DirtySource', ...
        ['Official v37 outcome generation requires a clean tracked ', ...
         'and MATLAB/Octave source state.']);
end

outputDirectory = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v37', 'x36_outcome_v3', 'screen');
stem = 'FORMATION_STAGGERED_RECOVERY_X36_V37_V3_SCREEN';
reportPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    [stem, '_20260803.md']);
matPath = fullfile(outputDirectory, [stem, '.mat']);
completionMarkerPath = [matPath, '.complete'];
assertOfficialOutputAbsent( ...
    reportPath, matPath, completionMarkerPath);
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
assertAllCacheArtifacts(preflight, protocol);
assertExecutionSourceStable(gitState);
[outcomeClaim, outcomeClaimMetadataPath] = ...
    consumeFormationStaggeredRecoveryX36OutcomePermit( ...
        permit, releaseDescriptor, gitState.commit, ...
        reportPath, matPath, completionMarkerPath);
outcomeClaimMetadataSha256 = ...
    computeFileSha256(outcomeClaimMetadataPath);

stateCount = numel(protocol.anchorTimes);
stateScreens = cell(1, stateCount);
stateSummaries = repmat(emptyStateSummary(), 1, stateCount);
for stateIdx = 1:stateCount
    assertExecutionSourceStable(gitState);
    assertOutcomeClaimStable( ...
        outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
        outcomeClaim);
    proposal = preflight.pairProposals(stateIdx);
    sourceState = preflight.states(stateIdx);
    candidateActionIndex = proposal.candidateInitialActionIndex;
    pairedActionIndices = [1, candidateActionIndex];
    safetyOptions = struct( ...
        'posteriorSafetyActionIndices', pairedActionIndices);
    expectedFingerprints = ...
        proposal.runtimeFingerprintSha256ByArm;
    executorOptions = struct( ...
        'horizonSteps', protocol.horizonSteps, ...
        'interventionDurationSteps', 1, ...
        'cacheRoot', protocol.cacheRoot, ...
        'interventionBankType', ...
            'formation-staggered-recovery', ...
        'actionIndices', pairedActionIndices, ...
        'temporalSuspensionBankOptions', safetyOptions, ...
        'expectedRuntimePolicyFingerprintSha256ByArm', ...
            {expectedFingerprints}, ...
        'writeReport', false);
    fprintf('V37 X36 state %d/%d: t=%d\n', ...
        stateIdx, stateCount, proposal.anchorTime);
    [~, stateScreen] = runFormationModeOpenedReturnScreen( ...
        proposal.presetName, proposal.seed, ...
        proposal.anchorTime, executorOptions);
    assertStateScreenContract( ...
        stateScreen, sourceState, proposal, ...
        stateIdx, protocol, gitState);
    assertExecutionSourceStable(gitState);
    assertOutcomeClaimStable( ...
        outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
        outcomeClaim);
    stateScreens{stateIdx} = stateScreen;
    stateSummaries(stateIdx) = buildStateSummary( ...
        stateScreen, stateIdx, protocol);
end

gate = evaluateFormationStaggeredRecoveryX36V37Gate( ...
    stateSummaries, protocol);
cleanSource = ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles);

screen = struct();
screen.contractVersion = ...
    'formation-staggered-recovery-x36-v37-screen-v3';
screen.runnerContractVersion = ...
    permit.authorizedRunnerContractVersion;
screen.generatedAt = datestr(now, 31);
screen.generationGitCommit = gitState.commit;
screen.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
screen.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
screen.protocol = protocol;
screen.outcomePermit = permit;
screen.outcomePermitCanonicalSha256 = ...
    permit.permitCanonicalSha256;
screen.releaseDescriptor = releaseDescriptor;
screen.releaseDescriptorCanonicalSha256 = ...
    releaseDescriptor.descriptorCanonicalSha256;
screen.outcomeClaim = outcomeClaim;
screen.outcomeClaimMetadataPath = outcomeClaimMetadataPath;
screen.outcomeClaimMetadataSha256 = ...
    outcomeClaimMetadataSha256;
screen.outcomeClaimConsumedBeforeTrackingOutcome = true;
screen.failedOrInterruptedRunConsumesAuthorization = true;
screen.sourcePreflightPath = permit.preflightPath;
screen.sourcePreflightSha256 = permit.preflightSha256;
screen.sourcePreflightReportPath = ...
    permit.preflightReportPath;
screen.sourcePreflightReportSha256 = ...
    permit.preflightReportSha256;
screen.sourcePreflightCompletionMarkerPath = ...
    permit.preflightCompletionMarkerPath;
screen.sourcePreflightCompletionMarkerSha256 = ...
    permit.preflightCompletionMarkerSha256;
screen.sourcePreflightSourceManifestSha256 = ...
    permit.preflightSourceManifestSha256;
screen.sourcePreflightGenerationCommit = ...
    preflight.generationGitCommit;
screen.presetName = protocol.presetName;
screen.seed = protocol.seed;
screen.anchorTimes = protocol.anchorTimes;
screen.stateScreens = stateScreens;
screen.stateSummaries = stateSummaries;
screen.outcomeGate = gate;
screen.formalOutcomeGatePassed = cleanSource && gate.passed;
screen.trackingOutcomeScored = true;
screen.outcomeSelectionOrRankingPerformed = false;
screen.openedDevelopmentEvidenceOnly = true;
screen.gnnTrainingAuthorized = false;
screen.x48OutcomeOpeningAuthorized = false;
screen.validationClaimAllowed = false;
screen.reportPath = reportPath;
screen.matPath = matPath;
screen.publicationCompletionContractVersion = ...
    'formation-staggered-recovery-outcome-publication-v2';
screen.publicationCompletionMarkerRequired = true;
screen.publicationCompletionMarkerPath = completionMarkerPath;
screen.sourceEvidenceBoundary = protocol.evidenceBoundary;
screen.evidenceBoundary = permit.evidenceBoundary;

temporaryMatPath = [tempname(outputDirectory), '.mat'];
temporaryReportPath = [tempname(outputDirectory), '.md'];
temporaryMarkerPath = [tempname(outputDirectory), '.complete'];
temporaryCleanup = onCleanup(@() cleanupTemporaryArtifacts( ...
    temporaryMatPath, temporaryReportPath, ...
    temporaryMarkerPath)); %#ok<NASGU>
assertExecutionSourceStable(gitState);
assertOutcomeClaimStable( ...
    outcomeClaimMetadataPath, outcomeClaimMetadataSha256, outcomeClaim);
save('-mat7-binary', temporaryMatPath, 'screen');
writeReport(temporaryReportPath, screen);
publicationMetadata = struct( ...
    'contractVersion', ...
        screen.publicationCompletionContractVersion, ...
    'generationGitCommit', screen.generationGitCommit, ...
    'outcomePermitCanonicalSha256', ...
        screen.outcomePermitCanonicalSha256, ...
    'releaseDescriptorCanonicalSha256', ...
        screen.releaseDescriptorCanonicalSha256, ...
    'outcomeClaimMetadataPath', ...
        screen.outcomeClaimMetadataPath, ...
    'outcomeClaimMetadataSha256', ...
        screen.outcomeClaimMetadataSha256, ...
    'outcomeClaimRemoteRef', ...
        screen.outcomeClaim.remoteClaimRef, ...
    'outcomeClaimRemoteTagObjectId', ...
        screen.outcomeClaim.remoteClaimTagObjectId, ...
    'sourcePreflightSha256', ...
        screen.sourcePreflightSha256, ...
    'sourcePreflightCompletionMarkerSha256', ...
        screen.sourcePreflightCompletionMarkerSha256);
publishOfficialArtifactSet( ...
    temporaryMatPath, temporaryReportPath, temporaryMarkerPath, ...
    matPath, reportPath, completionMarkerPath, ...
    publicationMetadata, gitState, ...
    outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
    outcomeClaim);
fprintf('V37 X36 exact paired screen: %s\n', reportPath);
end

function assertOutcomeClaimStable( ...
        metadataPath, expectedSha256, outcomeClaim)
if exist(metadataPath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(metadataPath), expectedSha256)
    error('V37Screen:OutcomeClaimChanged', ...
        'The irreversible permit-consumption record changed during execution.');
end
assertNoRemoteUrlRewrite();
[remoteStatus, remoteListing] = system(sprintf([ ...
    remoteGitEnvironment(), ...
    'git ls-remote --tags ''%s'' ', ...
    '''%s'' ''%s^{}'''], ...
    outcomeClaim.releaseRemoteUrl, outcomeClaim.remoteClaimRef, ...
    outcomeClaim.remoteClaimRef));
actualLines = sort(splitNonemptyLines(remoteListing));
expectedLines = sort({ ...
    sprintf('%s\t%s', outcomeClaim.remoteClaimTagObjectId, ...
        outcomeClaim.remoteClaimRef), ...
    sprintf('%s\t%s^{}', outcomeClaim.remoteClaimTargetCommit, ...
        outcomeClaim.remoteClaimRef)});
if remoteStatus ~= 0 || ~isequal(actualLines, expectedLines)
    error('V37Screen:OutcomeClaimChanged', ...
        'The global remote permit-consumption ref changed during execution.');
end
end

function assertNoRemoteUrlRewrite()
[status, listing] = system([ ...
    'git config --show-origin --get-regexp ', ...
    '''^url\..*\.(insteadOf|pushInsteadOf)$''']);
if ~(status == 0 || status == 1) || ~isempty(strtrim(listing))
    error('V37Screen:OutcomeClaimChanged', ...
        'A Git URL rewrite could redirect the pinned remote claim check.');
end
end

function value = remoteGitEnvironment()
value = [ ...
    'GIT_TERMINAL_PROMPT=0 ', ...
    ['GIT_SSH_COMMAND=''ssh -oBatchMode=yes -oHostname=github.com ', ...
     '-oHostKeyAlias=github.com'' ']];
end

function assertOfficialOutputAbsent( ...
        reportPath, matPath, completionMarkerPath)
if exist(reportPath, 'file') ~= 0 || ...
        exist(matPath, 'file') ~= 0 || ...
        exist(completionMarkerPath, 'file') ~= 0
    error('V37Screen:OutputExists', ...
        ['The fixed v37 v3 outcome artifact set already exists; ', ...
         'refusing overwrite.']);
end
end

function assertAllCacheArtifacts(preflight, protocol)
for stateIdx = 1:numel(protocol.anchorTimes)
    proposal = preflight.pairProposals(stateIdx);
    if exist(proposal.cachePath, 'file') ~= 2
        error('V37Screen:CacheRequired', ...
            'The permitted cache is unavailable at t=%d.', ...
            proposal.anchorTime);
    end
    actualSha256 = computeFileSha256(proposal.cachePath);
    if ~strcmp(actualSha256, proposal.cacheSha256) || ...
            ~strcmp(actualSha256, ...
                protocol.expectedCacheSha256{stateIdx})
        error('V37Screen:CacheDrift', ...
            ['The permitted cache changed before any outcome ', ...
             'was scored at t=%d.'], proposal.anchorTime);
    end
end
end

function publishOfficialArtifactSet( ...
        temporaryMatPath, temporaryReportPath, temporaryMarkerPath, ...
        matPath, reportPath, completionMarkerPath, ...
        publicationMetadata, initialGitState, ...
        outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
        outcomeClaim)
matPublished = false;
reportPublished = false;
markerPublished = false;
try
    assertOfficialOutputAbsent( ...
        reportPath, matPath, completionMarkerPath);
    [moved, message] = movefile(temporaryMatPath, matPath);
    if ~moved
        error('V37Screen:PublishFailed', ...
            'Could not publish the official MAT artifact: %s', message);
    end
    matPublished = true;
    if exist(reportPath, 'file') ~= 0
        error('V37Screen:OutputExists', ...
            ['The fixed v37 report appeared during publication; ', ...
             'refusing overwrite.']);
    end
    [moved, message] = movefile(temporaryReportPath, reportPath);
    if ~moved
        error('V37Screen:PublishFailed', ...
            'Could not publish the official report artifact: %s', message);
    end
    reportPublished = true;
    if exist(matPath, 'file') ~= 2 || ...
            exist(reportPath, 'file') ~= 2
        error('V37Screen:PublishFailed', ...
            'The official MAT/report pair was not published completely.');
    end
    publication = publicationMetadata;
    publication.publishedAt = datestr(now, 31);
    publication.matPath = matPath;
    publication.reportPath = reportPath;
    publication.matSha256 = computeFileSha256(matPath);
    publication.reportSha256 = computeFileSha256(reportPath);
    publication.completionMarkerPath = completionMarkerPath;
    publication.completionMarkerWrittenLast = true;
    assertOutcomeClaimStable( ...
        outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
        outcomeClaim);
    save('-mat7-binary', temporaryMarkerPath, 'publication');
    assertExecutionSourceStable(initialGitState);
    assertOutcomeClaimStable( ...
        outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
        outcomeClaim);
    if ~strcmp(publication.matSha256, ...
            computeFileSha256(matPath)) || ...
            ~strcmp(publication.reportSha256, ...
                computeFileSha256(reportPath))
        error('V37Screen:PublishFailed', ...
            'The outcome artifact pair changed before completion marking.');
    end
    if exist(completionMarkerPath, 'file') ~= 0
        error('V37Screen:OutputExists', ...
            'The completion marker appeared during publication.');
    end
    [moved, message] = movefile( ...
        temporaryMarkerPath, completionMarkerPath);
    if ~moved
        error('V37Screen:PublishFailed', ...
            'Could not publish the outcome completion marker: %s', ...
            message);
    end
    markerPublished = true;
    if exist(completionMarkerPath, 'file') ~= 2
        error('V37Screen:PublishFailed', ...
            'The outcome completion marker was not published.');
    end
    assertOutcomeClaimStable( ...
        outcomeClaimMetadataPath, outcomeClaimMetadataSha256, ...
        outcomeClaim);
catch publicationError
    cleanupTemporaryArtifacts( ...
        temporaryMatPath, temporaryReportPath, temporaryMarkerPath);
    if markerPublished && exist(completionMarkerPath, 'file') == 2
        delete(completionMarkerPath);
    end
    if matPublished && exist(matPath, 'file') == 2
        delete(matPath);
    end
    if reportPublished && exist(reportPath, 'file') == 2
        delete(reportPath);
    end
    rethrow(publicationError);
end
end

function cleanupTemporaryArtifacts( ...
        temporaryMatPath, temporaryReportPath, temporaryMarkerPath)
if exist(temporaryMatPath, 'file') == 2
    delete(temporaryMatPath);
end
if exist(temporaryReportPath, 'file') == 2
    delete(temporaryReportPath);
end
if exist(temporaryMarkerPath, 'file') == 2
    delete(temporaryMarkerPath);
end
end

function assertExecutionSourceStable(initialGitState)
currentGitState = resolveResearchGitState();
if ~strcmp(currentGitState.commit, initialGitState.commit) || ...
        currentGitState.trackedWorktreeDirty || ...
        ~isempty(currentGitState.untrackedSourceFiles)
    error('V37Screen:SourceChangedDuringRun', ...
        'Executable source changed during the exact X36 outcome run.');
end
[currentPermit, ~, currentReleaseDescriptor] = ...
    loadFormationStaggeredRecoveryX36OutcomePermit();
expectedPermit = ...
    getFormationStaggeredRecoveryX36OutcomePermit();
if ~strcmp(currentPermit.permitCanonicalSha256, ...
        expectedPermit.permitCanonicalSha256) || ...
        ~strcmp(currentReleaseDescriptor.permitCanonicalSha256, ...
            expectedPermit.permitCanonicalSha256) || ...
        ~isfield(currentReleaseDescriptor, ...
            'descriptorCanonicalSha256')
    error('V37Screen:SourceChangedDuringRun', ...
        ['The immutable outcome permit or independent release ', ...
         'descriptor changed during execution.']);
end
end

function assertOutcomeAuthorization(permit, preflight, protocol)
validateFormationStaggeredRecoveryX36OutcomePreflight( ...
    preflight, permit);
if ~strcmp(permit.contractVersion, ...
            'formation-staggered-recovery-x36-outcome-permit-v3') || ...
        ~strcmp(permit.authorizedRunnerContractVersion, [ ...
            'formation-staggered-recovery-x36-v37-', ...
            'exact-two-arm-runner-v3']) || ...
        ~strcmp(permit.sourceProtocolContractVersion, ...
            protocol.contractVersion) || ...
        permit.authorizedPairCount ~= 3 || ...
        permit.exactArmCountPerPair ~= 2 || ...
        permit.maximumPairedRunCountPerPair ~= 1 || ...
        permit.maximumOfficialAggregateRunCount ~= 1 || ...
        ~permit.outcomeClaimRemoteMustBeCreatedAtomically || ...
        ~permit.outcomeClaimMustCoverAllWorktreesAndClones || ...
        ~permit.outcomeClaimMustPrecedeTrackingOutcome || ...
        ~permit.failedClaimConsumesAuthorization || ...
        permit.referenceArmOrdinal ~= 1 || ...
        permit.candidateArmOrdinal ~= 2 || ...
        ~permit.trackingOutcomeRerunAuthorized || ...
        ~permit.x36PairedOutcomeRerunAuthorized || ...
        permit.unrestrictedX36OutcomeOpeningAuthorized || ...
        permit.overwriteExistingOfficialOutputAuthorized || ...
        permit.outcomeSelectionOrRankingAuthorized || ...
        permit.gnnTrainingAuthorized || ...
        permit.x48OutcomeOpeningAuthorized || ...
        permit.reservedSeedOpeningAuthorized || ...
        permit.validationClaimAllowed || ...
        ~permit.developmentEvidenceOnly || ...
        ~isequal(preflight.pairedOutcomeEligibilityMask, ...
            true(1, 3)) || ...
        ~preflight.x36PairedOutcomePermitMayBeMinted || ...
        preflight.x36PairedOutcomeRerunAuthorized || ...
        preflight.maximumAuthorizedPairCount ~= 0 || ...
        preflight.trackingOutcomeScored || ...
        ~isequal(preflight. ...
            runtimeFingerprintSha256ByStateArm, ...
            permit.authorizedRuntimeFingerprintSha256ByStateArm)
    error('V37Screen:PermitRequired', ...
        'The immutable v37 v3 permit does not authorize the exact run.');
end
for stateIdx = 1:permit.authorizedPairCount
    proposal = preflight.pairProposals(stateIdx);
    state = preflight.states(stateIdx);
    if ~strcmp(computeCanonicalValueSha256(proposal), ...
            permit.authorizedPairProposalCanonicalSha256{stateIdx}) || ...
            ~isequal(proposal.runtimeFingerprintSha256ByArm, ...
                permit. ...
                    authorizedRuntimeFingerprintSha256ByStateArm( ...
                        stateIdx, :)) || ...
            ~isequal(state.runtimeFingerprintSha256ByArm, ...
                proposal.runtimeFingerprintSha256ByArm) || ...
            ~isequal(state.runtimeReplayPassedByArm, true(1, 2)) || ...
            state.trackingOutcomeScored || ...
            state.truthUsed || state.futureOutcomeUsed
        error('V37Screen:PreflightRequired', ...
            'A permitted v37 v3 pair drifted at state %d.', stateIdx);
    end
end
end

function assertStateScreenContract( ...
        stateScreen, sourceState, proposal, ...
        stateIdx, protocol, gitState)
anchorTime = protocol.anchorTimes(stateIdx);
candidateAction = proposal.candidateInitialActionIndex;
pairedActions = [1, candidateAction];
expectedSequences = [ ...
    proposal.referenceNominalActionSequenceIndices; ...
    proposal.candidateNominalActionSequenceIndices];
expectedFingerprintContract = ...
    proposal.runtimeFingerprintSha256ByArm;
expectedScoredMask = false(1, stateScreen.bank.actionCount);
expectedScoredMask(pairedActions) = true;
referenceIdx = stateScreen.referenceSubsetIndex;
candidateIdx = setdiff( ...
    1:numel(stateScreen.records), referenceIdx);
if referenceIdx ~= 1 || numel(stateScreen.records) ~= 2 || ...
        numel(stateScreen.outcomes) ~= 2 || ...
        ~isequal(candidateIdx, 2)
    error('V37Screen:StateContract', ...
        'Each v37 state must contain exactly the ordered two-arm pair.');
end
reference = stateScreen.outcomes(referenceIdx);
candidate = stateScreen.outcomes(candidateIdx);
referenceRecord = stateScreen.records(referenceIdx);
candidateRecord = stateScreen.records(candidateIdx);
bank = stateScreen.bank;
if ~strcmp(stateScreen.contractVersion, ...
        'formation-staggered-recovery-h3-opened-return-screen-v1') || ...
        ~strcmp(stateScreen.interventionBankType, ...
            'formation-staggered-recovery') || ...
        ~strcmp(stateScreen.generationGitCommit, gitState.commit) || ...
        stateScreen.generationTrackedWorktreeDirty || ...
        ~isempty(stateScreen.generationUntrackedSourceFiles) || ...
        ~strcmp(stateScreen.presetName, proposal.presetName) || ...
        stateScreen.seed ~= proposal.seed || ...
        stateScreen.currentTime ~= anchorTime || ...
        ~isequal(stateScreen.returnTimes, proposal.returnTimes) || ...
        stateScreen.horizonSteps ~= protocol.horizonSteps || ...
        stateScreen.interventionDurationSteps ~= 1 || ...
        stateScreen.explicitActionSequenceEnabled || ...
        ~isequal(stateScreen.actionIndices, pairedActions) || ...
        ~isequal(stateScreen.actionSequenceIndices, expectedSequences) || ...
        ~isequal(stateScreen. ...
            expectedRuntimePolicyFingerprintSha256ByArm, ...
            expectedFingerprintContract) || ...
        bank.referenceActionIndex ~= 1 || ...
        bank.nodeCount ~= protocol.expectedNodeCount || ...
        bank.formationCount ~= protocol.expectedFormationCount || ...
        ~bank.posteriorSafetyScored || ...
        ~strcmp(bank.posteriorSafetyScoringMode, ...
            'explicit-index-subset-v1') || ...
        ~isequal(bank.posteriorSafetyRequestedActionIndices, ...
            pairedActions) || ...
        ~isequal(bank.posteriorSafetyScoredMask, expectedScoredMask) || ...
        ~isequal(bank.actionPosteriorSafetyMask, expectedScoredMask) || ...
        ~isequal(bank.safeActionIndices, pairedActions) || ...
        any(~bank.actionPosteriorSafetyMask(pairedActions)) || ...
        ~isequal(bank.actionSuspendedFormationIds{candidateAction}, ...
            protocol.expectedInitialFormationIdsByState{stateIdx}) || ...
        ~strcmp(stateScreen.cachePath, proposal.cachePath) || ...
        ~strcmp(stateScreen.cachePath, sourceState.cachePath) || ...
        ~strcmp(stateScreen.cacheSha256, proposal.cacheSha256) || ...
        ~strcmp(stateScreen.cacheSha256, ...
            protocol.expectedCacheSha256{stateIdx}) || ...
        ~stateScreen.runtimeRecoveryPolicyEnabled || ...
        ~strcmp(stateScreen.runtimePolicyContractVersion, ...
            'formation-staggered-recovery-runtime-policy-v1') || ...
        stateScreen.runtimePolicyUsesTruth || ...
        stateScreen.featuresUseTruth || ...
        stateScreen.featuresUseFutureMeasurements || ...
        stateScreen.featuresUseFutureOutcome || ...
        ~stateScreen.targetsUseTruth || ...
        ~stateScreen.targetsUseFutureMeasurements || ...
        ~stateScreen.trackingTruthSeparatedFromPolicyInputs || ...
        ~strcmp(stateScreen.policyContextSanitizerContractVersion, ...
            'topology-policy-observable-input-v2') || ...
        ~stateScreen.policyContextUsesCurrentObservableInputsOnly || ...
        ~isequal(stateScreen. ...
            scenarioTruthFieldsRemovedBeforePolicyConstruction, ...
            {'groundTruth', 'groundTruthRfs', 'targetTrajectories', ...
             'model.explicitTargetTrajectories', ...
             ['model.dynamicTopologyScenario.', ...
              'targetTrajectories']}) || ...
        ~stateScreen.openedDevelopmentEvidenceOnly || ...
        stateScreen.validationClaimAllowed || ...
        referenceRecord.actionIndex ~= 1 || ...
        ~isequal(referenceRecord.actionSequenceIndices, ...
            proposal.referenceNominalActionSequenceIndices) || ...
        ~referenceRecord.posteriorProxyAllowed || ...
        candidateRecord.actionIndex ~= candidateAction || ...
        ~isequal(candidateRecord.actionSequenceIndices, ...
            proposal.candidateNominalActionSequenceIndices) || ...
        ~candidateRecord.posteriorProxyAllowed
    error('V37Screen:StateContract', ...
        'The paired action, cache, or safety contract drifted at t=%d.', ...
        anchorTime);
end

if any([reference.truthUseCount, candidate.truthUseCount] ~= 0) || ...
        any([reference.repairCount, candidate.repairCount] ~= 0) || ...
        any([reference.payloadEmergencyCount, ...
             candidate.payloadEmergencyCount] ~= 0) || ...
        any([reference.infeasibleCount, candidate.infeasibleCount] ~= 0) || ...
        ~reference.firstActionExact || ...
        ~reference.firstFusionWeightsExact || ...
        ~candidate.firstActionExact || ...
        ~candidate.firstFusionWeightsExact || ...
        ~reference.laterActionsDynamicallyRecomputed || ...
        ~candidate.laterActionsDynamicallyRecomputed || ...
        ~all(reference.selectedSensorB3Pass) || ...
        ~all(reference.selectedFormationB3Pass) || ...
        ~all(candidate.selectedSensorB3Pass) || ...
        ~all(candidate.selectedFormationB3Pass) || ...
        any(reference.posteriorContentUsedByTime) || ...
        any(reference.currentLinkReliabilityUsedByTime) || ...
        ~all(candidate.posteriorContentUsedByTime) || ...
        ~all(candidate.currentLinkReliabilityUsedByTime) || ...
        ~reference.runtimePolicyFingerprintMatched || ...
        ~strcmp(reference.expectedRuntimePolicyFingerprintSha256, ...
            proposal.referenceRuntimeFingerprintSha256) || ...
        ~strcmp(reference.runtimePolicyFingerprintSha256, ...
            proposal.referenceRuntimeFingerprintSha256) || ...
        ~strcmp(reference.runtimePolicyFingerprintSha256, ...
            sourceState.runtimeFingerprintSha256ByArm{1}) || ...
        ~isequaln(reference.runtimePolicyFingerprint, ...
            sourceState.runtimeReplays{1}.runtimeFingerprint) || ...
        ~isequal(reference.selectedAdjacency, ...
            sourceState.runtimeReplays{1}.selectedAdjacency) || ...
        ~isequal(reference.attemptedBytesByTime, ...
            sourceState.runtimeReplays{1}.attemptedBytesByTime) || ...
        ~candidate.runtimePolicyFingerprintMatched || ...
        ~strcmp(candidate.expectedRuntimePolicyFingerprintSha256, ...
            proposal.candidateRuntimeFingerprintSha256) || ...
        ~strcmp(candidate.runtimePolicyFingerprintSha256, ...
            proposal.candidateRuntimeFingerprintSha256) || ...
        ~strcmp(candidate.runtimePolicyFingerprintSha256, ...
            sourceState.runtimeFingerprintSha256ByArm{2}) || ...
        ~isequaln(candidate.runtimePolicyFingerprint, ...
            sourceState.runtimeReplays{2}.runtimeFingerprint) || ...
        ~isequal(candidate.selectedAdjacency, ...
            sourceState.runtimeReplays{2}.selectedAdjacency) || ...
        ~isequal(candidate.attemptedBytesByTime, ...
            sourceState.runtimeReplays{2}.attemptedBytesByTime) || ...
        ~hasExpectedTrace(candidate, stateIdx, protocol)
    error('V37Screen:RuntimeContract', ...
        'The hard gate or complete runtime trace drifted at t=%d.', ...
        anchorTime);
end
end

function value = hasExpectedTrace(candidate, stateIdx, protocol)
expectedSelected = protocol. ...
    expectedRuntimeSelectedFormationIdsByState{stateIdx};
expectedRequested = protocol. ...
    expectedRuntimeRequestedFormationIdsByState{stateIdx};
expectedReleased = protocol. ...
    expectedRuntimeReleasedFormationIdsByState{stateIdx};
expectedStaggered = protocol. ...
    expectedRuntimeStaggeredReleaseMaskByState{stateIdx};
expectedFallback = protocol. ...
    expectedRuntimeReferenceFallbackCountByState{stateIdx};
expectedBytes = protocol. ...
    expectedRuntimeAttemptedBytesByState{stateIdx};
expectedReferenceRisk = protocol. ...
    expectedRuntimeReferenceRiskByState{stateIdx};
expectedSelectedRisk = protocol. ...
    expectedRuntimeSelectedRiskByState{stateIdx};
value = ...
    isequal(candidate. ...
        retentionDebtSelectedFormationIdsByTime, expectedSelected) && ...
    isequal(candidate. ...
        retentionDebtRequestedFormationIdsByTime, expectedRequested) && ...
    isequal(candidate. ...
        retentionDebtProjectionRemovalOrderByTime, expectedReleased) && ...
    isequal(candidate.recoveryFallbackCountByTime, expectedFallback) && ...
    isequal(candidate.attemptedBytesByTime, expectedBytes) && ...
    numericTraceMatches(candidate.recoveryReferenceRiskByTime, ...
        expectedReferenceRisk, protocol.sourceMetricTolerance) && ...
    numericTraceMatches(candidate.recoverySelectedRiskByTime, ...
        expectedSelectedRisk, protocol.sourceMetricTolerance) && ...
    numel(candidate.staggeredRecoveryScheduleByTime) == ...
        protocol.horizonSteps;
if ~value
    return;
end
expectedDebt = protocol. ...
    expectedRuntimeDebtFractionByState{stateIdx};
for timeIdx = 1:protocol.horizonSteps
    schedule = candidate.staggeredRecoveryScheduleByTime{timeIdx};
    value = value && ...
        numericTraceMatches( ...
            candidate.retentionDebtFractionByTime{timeIdx}, ...
            expectedDebt{timeIdx}, protocol.sourceMetricTolerance) && ...
        isstruct(schedule) && ...
        isfield(schedule, 'contractVersion') && ...
        strcmp(schedule.contractVersion, ...
            'formation-staggered-recovery-runtime-schedule-v1') && ...
        schedule.currentTime == ...
            protocol.anchorTimes(stateIdx) + timeIdx - 1 && ...
        schedule.staggeredReleaseUsed == expectedStaggered(timeIdx) && ...
        isequal(schedule.selectedFormationIds, ...
            expectedSelected{timeIdx}) && ...
        isequal(schedule.releasedFormationIds, ...
            expectedReleased{timeIdx}) && ...
        ~schedule.truthUsed && ~schedule.futureOutcomeUsed;
end
end

function summary = buildStateSummary(stateScreen, stateIdx, protocol)
referenceIdx = stateScreen.referenceSubsetIndex;
candidateIdx = setdiff( ...
    1:numel(stateScreen.records), referenceIdx);
reference = stateScreen.outcomes(referenceIdx);
candidate = stateScreen.outcomes(candidateIdx);
record = stateScreen.records(candidateIdx);
traceAttested = hasExpectedTrace(candidate, stateIdx, protocol);
strictStrong = ...
    record.posteriorProxyAllowed && ...
    candidate.firstActionExact && ...
    candidate.firstFusionWeightsExact && ...
    candidate.laterActionsDynamicallyRecomputed && ...
    candidate.runtimePolicyFingerprintMatched && ...
    all(candidate.posteriorContentUsedByTime) && ...
    all(candidate.currentLinkReliabilityUsedByTime) && ...
    traceAttested && ...
    record.meanGainPercent >= ...
        protocol.meanTrackingGainThresholdPercent - 1e-12 && ...
    record.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainThresholdPercent - 1e-12 && ...
    record.worstGainPercent >= ...
        protocol.worstSensorGainThresholdPercent - 1e-12 && ...
    record.consensusGainPercent >= ...
        protocol.windowConsensusGainThresholdPercent - 1e-12 && ...
    record.terminalConsensusGainPercent >= ...
        protocol.terminalConsensusGainThresholdPercent - 1e-12 && ...
    record.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    record.selectedB3Passed;

summary = emptyStateSummary();
summary.anchorTime = protocol.anchorTimes(stateIdx);
summary.returnTimes = stateScreen.returnTimes;
summary.cacheSha256 = stateScreen.cacheSha256;
summary.referenceIndex = referenceIdx;
summary.candidateIndex = candidateIdx;
summary.runtimeFingerprintSha256ByArm = { ...
    reference.runtimePolicyFingerprintSha256, ...
    candidate.runtimePolicyFingerprintSha256};
summary.candidateRuntimeFingerprintSha256 = ...
    candidate.runtimePolicyFingerprintSha256;
summary.traceAttested = traceAttested;
summary.strictStrong = strictStrong;
summary.meanGainPercent = record.meanGainPercent;
summary.worstSensorGainPercent = record.worstGainPercent;
summary.formationGainPercent = record.formationGainPercent;
summary.minimumFormationGainPercent = ...
    record.minimumFormationGainPercent;
summary.windowConsensusGainPercent = record.consensusGainPercent;
summary.terminalConsensusGainPercent = ...
    record.terminalConsensusGainPercent;
summary.attemptedByteSavingPercent = ...
    record.attemptedByteSavingPercent;
summary.referenceMeanCardinalityError = ...
    reference.meanCardinalityError;
summary.candidateMeanCardinalityError = ...
    candidate.meanCardinalityError;
summary.referenceTrackingByTime = mean( ...
    reference.eospaBySensorTime, 1);
summary.candidateTrackingByTime = mean( ...
    candidate.eospaBySensorTime, 1);
summary.trackingGainByTimePercent = relativeGain( ...
    summary.referenceTrackingByTime, ...
    summary.candidateTrackingByTime);
summary.referenceConsensusByTime = ...
    reference.consensusOspaByTime;
summary.candidateConsensusByTime = ...
    candidate.consensusOspaByTime;
summary.consensusGainByTimePercent = relativeGain( ...
    summary.referenceConsensusByTime, ...
    summary.candidateConsensusByTime);
summary.referenceAttemptedBytesByTime = ...
    reference.attemptedBytesByTime;
summary.candidateAttemptedBytesByTime = ...
    candidate.attemptedBytesByTime;
summary.attemptedByteSavingByTimePercent = relativeGain( ...
    summary.referenceAttemptedBytesByTime, ...
    summary.candidateAttemptedBytesByTime);
summary.runtimeSelectedFormationIdsByTime = ...
    candidate.retentionDebtSelectedFormationIdsByTime;
summary.runtimeReleasedFormationIdsByTime = ...
    candidate.retentionDebtProjectionRemovalOrderByTime;
end

