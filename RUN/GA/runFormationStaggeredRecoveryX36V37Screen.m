function writeReport(path, screen)
fid = fopen(path, 'w');
if fid < 0
    error('V37Screen:WriteFailed', ...
        'Could not open the fixed v37 outcome report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
gate = screen.outcomeGate;
fprintf(fid, '# V37 X36 exact permitted paired screen\n\n');
fprintf(fid, '- Contract / generation commit: `%s / %s`\n', ...
    screen.contractVersion, screen.generationGitCommit);
fprintf(fid, '- Authorized runner contract: `%s`\n', ...
    screen.runnerContractVersion);
fprintf(fid, '- Source preflight commit: `%s`\n', ...
    screen.sourcePreflightGenerationCommit);
fprintf(fid, '- Permit / preflight SHA-256: `%s / %s`\n', ...
    screen.outcomePermitCanonicalSha256, ...
    screen.sourcePreflightSha256);
fprintf(fid, '- Preset / seed / anchors: `%s / %d / %s`\n', ...
    screen.presetName, screen.seed, mat2str(screen.anchorTimes));
fprintf(fid, '- Authorized pairs / arms per pair: `%d / %d`\n', ...
    screen.outcomePermit.authorizedPairCount, ...
    screen.outcomePermit.exactArmCountPerPair);
fprintf(fid, '- Formal X36 outcome gate: `%d`\n\n', ...
    screen.formalOutcomeGatePassed);

