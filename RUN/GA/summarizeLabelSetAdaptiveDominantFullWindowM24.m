function [reportPath, validation] = ...
    summarizeLabelSetAdaptiveDominantFullWindowM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTFULLWINDOWM24 Gate persistent M24 D-B.
%
% This opened-training gate was fixed before the six candidate runs:
% >=5% aggregate E-OSPA gain versus frozen CCW, positive gain on >=5/6
% seeds, no aggregate worst-node or consensus regression, <=2% per-seed
% attempted-byte mismatch, exact 40-message operation, selected B3, and
% no truth, repair, payload emergency, or topology infeasibility.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol. ...
        adaptiveDominantFullWindowTrainingValidationAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Adaptive-dominant full-window training summary is not authorized.');
end
seeds = protocol.adaptiveDominantFullWindowTrainingSeeds;
inputDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_balanced_full_window_v1'));
rows = repmat(emptyRow(), 1, numel(seeds));
runCommit = '';
restartSentinelPassed = false;

for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    candidatePath = findSingleCandidate(inputDirectory, seed);
    candidateLoaded = load(candidatePath, 'summary');
    candidateSummary = candidateLoaded.summary;
    validateCandidateSummary( ...
        candidateSummary, seed, protocol);
    candidate = findArm(candidateSummary.aggregate, ...
        protocol.adaptiveDominantFullWindowArmName);
    if isempty(runCommit)
        runCommit = candidateSummary.generationGitCommit;
    elseif ~strcmp(runCommit, ...
            candidateSummary.generationGitCommit)
        error('Adaptive-dominant runs use different commits.');
    end

    baselinePath = ...
        protocol.adaptiveDominantFullWindowBaselineMatPaths{seedIdx};
    requireHash(baselinePath, ...
        protocol. ...
            adaptiveDominantFullWindowBaselineMatSha256{seedIdx});
    baselineLoaded = load(baselinePath, 'summary');
    baseline = findArm(baselineLoaded.summary.aggregate, ...
        protocol.adaptiveDominantFullWindowReferenceArmName);

    legacyPath = ...
        protocol.adaptiveDominantFullWindowLegacyMatPaths{seedIdx};
    requireHash(legacyPath, ...
        protocol. ...
            adaptiveDominantFullWindowLegacyMatSha256{seedIdx});
    legacyLoaded = load(legacyPath, 'summary');
    legacy = findArm(legacyLoaded.summary.aggregate, ...
        protocol.topologyOnlyCandidateMode);

    if seed == protocol. ...
            adaptiveDominantFullWindowRestartSentinelSeed
        currentReference = findArm(candidateSummary.aggregate, ...
            protocol.adaptiveDominantFullWindowReferenceArmName);
        restartSentinelPassed = ...
            exactReferenceMatch(currentReference, baseline);
    end

    row = emptyRow();
    row.seed = seed;
    row.candidatePath = candidatePath;
    row.baselinePath = baselinePath;
    row.legacyPath = legacyPath;
    row.baselineEospa = baseline.focusEospa;
    row.candidateEospa = candidate.focusEospa;
    row.legacyEospa = legacy.focusEospa;
    row.gainVsBaselinePercent = relativeGain( ...
        row.baselineEospa, row.candidateEospa);
    row.gainVsLegacyPercent = relativeGain( ...
        row.legacyEospa, row.candidateEospa);
    row.baselineWorstEospa = ...
        baseline.focusWorstSensorEospa;
    row.candidateWorstEospa = ...
        candidate.focusWorstSensorEospa;
    row.baselineConsensusOspa = ...
        baseline.focusMapSetDisagreement;
    row.candidateConsensusOspa = ...
        candidate.focusMapSetDisagreement;
    row.baselineAttemptedBytes = ...
        baseline.focusAttemptedBytes;
    row.candidateAttemptedBytes = ...
        candidate.focusAttemptedBytes;
    row.byteDeltaPercent = 100 * ...
        (row.candidateAttemptedBytes - ...
         row.baselineAttemptedBytes) / ...
        max(row.baselineAttemptedBytes, eps);
    row.meanMessageCount = ...
        candidate.meanDirectedMessageCount;
    row.selectedSensorB3 = ...
        candidate.focusSelectedRollingB3SensorStrongFraction;
    row.selectedFormationB3 = ...
        candidate.focusSelectedRollingB3FormationStrongFraction;
    row.deliveredSensorB3 = ...
        candidate.focusDeliveredRollingB3SensorStrongFraction;
    row.truthUseFraction = ...
        candidate.policyTruthUseFraction;
    row.posteriorUseFraction = ...
        candidate.policyPosteriorContentUseFraction;
    row.currentLinkReliabilityUseFraction = ...
        candidate.policyCurrentLinkReliabilityUseFraction;
    row.repairRate = candidate.policyRepairRate;
    row.payloadEmergencyRate = ...
        candidate.policyPayloadEmergencyRate;
    row.topologyInfeasibleRate = ...
        candidate.focusTopologyInfeasibleRate;
    row.routeChangeFraction = ...
        candidate.focusWithinWindowRouteChangeFraction;
    row.distinctRouteMaps = ...
        candidate.focusDistinctDirectedRouteMapCount;
    row.hardSafetyPassed = hardSafetyPassed(row, protocol);
    rows(seedIdx) = row;
end

baselineMean = mean([rows.baselineEospa]);
candidateMean = mean([rows.candidateEospa]);
legacyMean = mean([rows.legacyEospa]);
meanGain = relativeGain(baselineMean, candidateMean);
meanGainVsLegacy = relativeGain(legacyMean, candidateMean);
positiveSeedFraction = mean( ...
    [rows.gainVsBaselinePercent] > 0);
baselineWorstMean = mean([rows.baselineWorstEospa]);
candidateWorstMean = mean([rows.candidateWorstEospa]);
worstGain = relativeGain( ...
    baselineWorstMean, candidateWorstMean);
baselineConsensusMean = ...
    mean([rows.baselineConsensusOspa]);
candidateConsensusMean = ...
    mean([rows.candidateConsensusOspa]);
consensusGain = relativeGain( ...
    baselineConsensusMean, candidateConsensusMean);
maximumAbsoluteByteDelta = ...
    max(abs([rows.byteDeltaPercent]));
hardSafetyPassedAll = all([rows.hardSafetyPassed]);
trackingGatePassed = meanGain >= ...
    protocol.adaptiveDominantFullWindowMinimumMeanGainPercent && ...
    positiveSeedFraction >= ...
        protocol. ...
            adaptiveDominantFullWindowMinimumPositiveSeedFraction;
tailGatePassed = ...
    (~protocol. ...
        adaptiveDominantFullWindowRequireNoAggregateWorstRegression || ...
        worstGain >= -1e-12) && ...
    (~protocol. ...
        adaptiveDominantFullWindowRequireNoAggregateConsensusRegression || ...
        consensusGain >= -1e-12);
communicationGatePassed = maximumAbsoluteByteDelta <= ...
    protocol. ...
        adaptiveDominantFullWindowMaximumByteDeltaPercent + 1e-12;
trainingGatePassed = restartSentinelPassed && ...
    hardSafetyPassedAll && trackingGatePassed && ...
    tailGatePassed && communicationGatePassed;

gitState = resolveResearchGitState();
validation = struct();
validation.protocolId = protocol.id;
validation.contractVersion = ...
    protocol.adaptiveDominantFullWindowContractVersion;
validation.generatedAt = datestr(now, 31);
validation.generationGitCommit = gitState.commit;
validation.runGenerationGitCommit = runCommit;
validation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
validation.seeds = seeds;
validation.times = ...
    protocol.adaptiveDominantFullWindowTimes;
validation.rows = rows;
validation.baselineMeanEospa = baselineMean;
validation.candidateMeanEospa = candidateMean;
validation.legacyMeanEospa = legacyMean;
validation.meanGainVsBaselinePercent = meanGain;
validation.meanGainVsLegacyPercent = meanGainVsLegacy;
validation.positiveSeedFraction = positiveSeedFraction;
validation.baselineWorstMeanEospa = baselineWorstMean;
validation.candidateWorstMeanEospa = candidateWorstMean;
validation.aggregateWorstGainPercent = worstGain;
validation.baselineConsensusMeanOspa = ...
    baselineConsensusMean;
validation.candidateConsensusMeanOspa = ...
    candidateConsensusMean;
validation.aggregateConsensusGainPercent = consensusGain;
validation.maximumAbsoluteByteDeltaPercent = ...
    maximumAbsoluteByteDelta;
validation.restartSentinelPassed = restartSentinelPassed;
validation.hardSafetyPassed = hardSafetyPassedAll;
validation.trackingGatePassed = trackingGatePassed;
validation.tailGatePassed = tailGatePassed;
validation.communicationGatePassed = ...
    communicationGatePassed;
validation.trainingGatePassed = trainingGatePassed;
validation.trainingOnly = true;
validation.developmentOpened = false;
validation.heldoutM24Opened = false;
validation.x36Opened = false;
if trainingGatePassed
    validation.nextDirection = ...
        'freeze-balanced-default-and-open-registered-M24-development';
else
    validation.nextDirection = ...
        'fit4-cal1-test1-lcb-upgrade-on-opened-training-only';
end
validation.evidenceBoundary = [ ...
    'This report evaluates a frozen truth-free controller only on the ', ...
    'six opened M24 training seeds. It does not establish development, ', ...
    'held-out M24, X36, or cross-scale generalization.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_FULL_WINDOW_M24_V1.md');
writeReport(reportPath, validation, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
validation.reportPath = reportPath;
validation.matPath = matPath;
fprintf('Adaptive-dominant full-window summary: %s\n', reportPath);
end

function path = findSingleCandidate(rootDirectory, seed)
matches = dir(fullfile( ...
    rootDirectory, sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected exactly one adaptive-dominant MAT for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function validateCandidateSummary(summary, seed, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'training') || ...
        summary.options.continuationStartTime ~= ...
            protocol.adaptiveDominantFullWindowTimes(1) || ...
        summary.options.maxTimeSteps ~= ...
            protocol.adaptiveDominantFullWindowTimes(end) || ...
        ~any(strcmp({summary.aggregate.mode}, ...
            protocol.adaptiveDominantFullWindowArmName)) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty
    error('Adaptive-dominant candidate provenance contract failed.');
end
end

function requireHash(path, expected)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expected)
    error('Registered evidence hash mismatch: %s', path);
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = exactReferenceMatch(current, registered)
passed = ...
    isequaln(current.focusEospa, registered.focusEospa) && ...
    isequaln(current.focusWorstSensorEospa, ...
        registered.focusWorstSensorEospa) && ...
    isequaln(current.focusMapSetDisagreement, ...
        registered.focusMapSetDisagreement) && ...
    isequaln(current.focusAttemptedBytes, ...
        registered.focusAttemptedBytes) && ...
    isequaln(current.focusDeliveredBytes, ...
        registered.focusDeliveredBytes) && ...
    isequaln(current.focusSelectedDirectedEdgeHistoryBySeed, ...
        registered.focusSelectedDirectedEdgeHistoryBySeed) && ...
    isequaln(current.focusDeliveredDirectedEdgeHistoryBySeed, ...
        registered.focusDeliveredDirectedEdgeHistoryBySeed) && ...
    isequaln(current.focusEospaBySensorTimeBySeed, ...
        registered.focusEospaBySensorTimeBySeed);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    abs(row.meanMessageCount - ...
        protocol.adaptiveDominantFullWindowExpectedMessageCount) < 1e-12 && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'candidatePath', '', ...
    'baselinePath', '', ...
    'legacyPath', '', ...
    'baselineEospa', NaN, ...
    'candidateEospa', NaN, ...
    'legacyEospa', NaN, ...
    'gainVsBaselinePercent', NaN, ...
    'gainVsLegacyPercent', NaN, ...
    'baselineWorstEospa', NaN, ...
    'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, ...
    'candidateConsensusOspa', NaN, ...
    'baselineAttemptedBytes', NaN, ...
    'candidateAttemptedBytes', NaN, ...
    'byteDeltaPercent', NaN, ...
    'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, ...
    'selectedFormationB3', NaN, ...
    'deliveredSensorB3', NaN, ...
    'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'repairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'routeChangeFraction', NaN, ...
    'distinctRouteMaps', NaN, ...
    'hardSafetyPassed', false);
end

function writeReport(path, validation, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write adaptive-dominant full-window report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 adaptive-dominant balanced full-window gate\n\n');
fprintf(fid, '- Contract: `%s`\n', validation.contractVersion);
fprintf(fid, '- Generated: %s\n', validation.generatedAt);
fprintf(fid, '- Run commit: `%s`\n', ...
    validation.runGenerationGitCommit);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seeds));
fprintf(fid, '- Window: `%s`\n', mat2str(validation.times));
fprintf(fid, '- Frozen arm: `%s`\n', ...
    protocol.adaptiveDominantFullWindowArmName);
fprintf(fid, '- Reference: `%s`\n\n', ...
    protocol.adaptiveDominantFullWindowReferenceArmName);
fprintf(fid, ['| Seed | CCW E-OSPA | D-B E-OSPA | Gain vs CCW | ', ...
    'Legacy E-OSPA | Gain vs legacy | CCW worst | D-B worst | ', ...
    'CCW consensus | D-B consensus | Byte delta | Msgs | ', ...
    'Selected B3 | Delivered B3 | Safe |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|--:|--:|:--:|\n']);
for row = validation.rows
    fprintf(fid, ['| %d | %.6f | %.6f | %+.3f%% | %.6f | ', ...
        '%+.3f%% | %.6f | %.6f | %.6f | %.6f | %+.3f%% | ', ...
        '%.2f | %.3f | %.3f | %d |\n'], ...
        row.seed, row.baselineEospa, row.candidateEospa, ...
        row.gainVsBaselinePercent, row.legacyEospa, ...
        row.gainVsLegacyPercent, row.baselineWorstEospa, ...
        row.candidateWorstEospa, ...
        row.baselineConsensusOspa, ...
        row.candidateConsensusOspa, row.byteDeltaPercent, ...
        row.meanMessageCount, row.selectedSensorB3, ...
        row.deliveredSensorB3, row.hardSafetyPassed);
end
fprintf(fid, '\n## Registered gate\n\n');
fprintf(fid, '- Mean CCW E-OSPA: `%.6f`\n', ...
    validation.baselineMeanEospa);
fprintf(fid, '- Mean D-B E-OSPA: `%.6f`\n', ...
    validation.candidateMeanEospa);
fprintf(fid, '- Mean legacy E-OSPA: `%.6f`\n', ...
    validation.legacyMeanEospa);
fprintf(fid, '- Mean gain vs CCW: `%+.3f%%` (gate `>= %.3f%%`)\n', ...
    validation.meanGainVsBaselinePercent, ...
    protocol.adaptiveDominantFullWindowMinimumMeanGainPercent);
fprintf(fid, '- Mean gain vs legacy: `%+.3f%%`\n', ...
    validation.meanGainVsLegacyPercent);
fprintf(fid, ['- Positive seeds: `%d/%d` (gate `>= %.0f/%d`)\n'], ...
    nnz([validation.rows.gainVsBaselinePercent] > 0), ...
    numel(validation.rows), ...
    protocol.adaptiveDominantFullWindowMinimumPositiveSeedFraction * ...
        numel(validation.rows), numel(validation.rows));
fprintf(fid, '- Aggregate worst-node gain: `%+.3f%%`\n', ...
    validation.aggregateWorstGainPercent);
fprintf(fid, '- Aggregate consensus gain: `%+.3f%%`\n', ...
    validation.aggregateConsensusGainPercent);
fprintf(fid, ['- Maximum absolute attempted-byte delta: `%.3f%%` ', ...
    '(gate `<= %.3f%%`)\n'], ...
    validation.maximumAbsoluteByteDeltaPercent, ...
    protocol.adaptiveDominantFullWindowMaximumByteDeltaPercent);
fprintf(fid, '- Restart sentinel passed: `%d`\n', ...
    validation.restartSentinelPassed);
fprintf(fid, '- Hard safety passed: `%d`\n', ...
    validation.hardSafetyPassed);
fprintf(fid, '- Tracking gate passed: `%d`\n', ...
    validation.trackingGatePassed);
fprintf(fid, '- Tail gate passed: `%d`\n', ...
    validation.tailGatePassed);
fprintf(fid, '- Communication gate passed: `%d`\n', ...
    validation.communicationGatePassed);
fprintf(fid, '- Full training gate passed: `%d`\n', ...
    validation.trainingGatePassed);
fprintf(fid, '- Next: `%s`\n\n', validation.nextDirection);
fprintf(fid, '%s\n', validation.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
