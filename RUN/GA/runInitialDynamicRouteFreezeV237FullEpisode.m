function [reportPath, result] = ...
        runInitialDynamicRouteFreezeV237FullEpisode(options)
% RUNINITIALDYNAMICROUTEFREEZEV237FULLEPISODE Strong causal baseline.
%
% Reuse the deterministic V227 registered-static and dynamic arms. Only
% execute the route selected from the t=1 physical page and then frozen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getInitialDynamicRouteFreezeV237Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('InitialDynamicRouteFreezeV237:DirtySource', ...
        'The official V237 outcome requires clean frozen source.');
end
presetName = char(getField( ...
    options, 'presetName', 'm24-formation-fov'));
seed = getField(options, 'seed', 1301);
if ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds)
    error('InitialDynamicRouteFreezeV237:SplitMembership', ...
        'The requested V237 case is outside the frozen development split.');
end
v227ResultPath = char(getField(options, 'v227ResultPath', ''));
if isempty(v227ResultPath) || exist(v227ResultPath, 'file') ~= 2
    error('InitialDynamicRouteFreezeV237:MissingV227Pair', ...
        'A completed paired V227 MAT result is required.');
end
loaded = load(v227ResultPath, 'result');
paired = loaded.result;
validateV227Pair(paired, presetName, seed, protocol);

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, sprintf('%s_seed%d', ...
        strrep(presetName, '-', '_'), seed))));
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'INITIAL_DYNAMIC_ROUTE_FREEZE_V237_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'INITIAL_DYNAMIC_ROUTE_FREEZE_V237_FULL_EPISODE.md');

fprintf('\nV237 initial dynamic-route freeze: %s seed %d\n', ...
    presetName, seed);
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
registration = ...
    buildInitialDynamicRouteFreezeV237Registration(inputs);
fprintf(['  t=1 route frozen: messages/round=%d, ', ...
    'all-time physical=%d\n'], registration.messageCount, ...
    registration.allTimePhysicalEligibilityPassed);
config = buildInitialDynamicRouteFreezeV237Config( ...
    inputs.config, registration);
context = buildInitialDynamicRouteFreezeV237ExecutionContext( ...
    presetName, seed, inputs.config.simulationLength);
filterModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
representatives = selectFormationRepresentativesLocal( ...
    inputs.config.sensorGroupIds);
metricWindow = struct( ...
    'activationStartTime', inputs.config.focusWindow(1), ...
    'activationEndTime', inputs.config.focusWindow(end));
rng(seed + protocol.filterSeedOffset, 'twister');
timerId = tic;
fprintf('  running frozen-route full episode ...\n');
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    filterModel, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
freeze = summarizeRepeatedMultiGatewayFullEpisodeArm( ...
    protocol.armId, estimates, diagnostics, inputs.groundTruthRfs, ...
    inputs.config, representatives, metricWindow, toc(timerId));
freeze = attachTopologySummary(freeze, diagnostics);
assertRuntimeFreeze(freeze, registration, diagnostics);

result = struct();
result.contractVersion = ...
    'initial-dynamic-route-freeze-v237-result-v1';
result.protocolId = protocol.id;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.v227GenerationGitCommit = paired.generationGitCommit;
result.v227ResultPath = v227ResultPath;
result.presetName = presetName;
result.seed = seed;
result.splitName = protocol.splitName;
result.static = paired.static;
result.freeze = freeze;
result.dynamic = paired.dynamic;
result.freezeGainOverRegisteredStatic = ...
    compareArm(freeze, paired.static);
result.dynamicGainOverFreeze = compareArm(paired.dynamic, freeze);
result.freezeGainOverDynamic = compareArm(freeze, paired.dynamic);
result.initialSelectionGainRetention = gainRetention( ...
    result.freezeGainOverRegisteredStatic, paired.comparison);
result.registeredStaticMeanGatePassed = meanGate( ...
    result.freezeGainOverRegisteredStatic);
result.formationTailPassed = ...
    result.freezeGainOverRegisteredStatic. ...
        minimumFormationEospaGainPercent >= 0 && ...
    result.freezeGainOverRegisteredStatic. ...
        minimumFormationRmseGainPercent >= 0;
result.temporalReselectionJointlyHelpful = meanGate( ...
    result.dynamicGainOverFreeze);
result.freezeJointlyDominatesDynamic = nonnegativeMeanGate( ...
    result.freezeGainOverDynamic);
result.initialRouteRegistration = compactRegistration(registration);
result.runtimeTruthUsed = freeze.policyTruthUsed;
result.runtimeFutureOutcomeUsed = freeze.policyFutureOutcomeUsed;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf(['  freeze E-OSPA %.3f; RMSE %.3f; focus consensus %.3f; ', ...
    'bytes %.0f; %.1f s\n'], freeze.fullHorizonPositionEospa, ...
    freeze.fullHorizonPositionRmse, ...
    freeze.focusInterFormationPositionOspa, ...
    freeze.attemptedPayloadBytes, freeze.elapsedSeconds);
fprintf('V237 result: %s\n', reportPath);
end

function validateV227Pair(paired, presetName, seed, protocol)
required = {'contractVersion', 'presetName', 'seed', 'splitName', ...
    'static', 'dynamic', 'comparison', 'pairedOutcomeAvailable', ...
    'generationGitCommit'};
if ~isstruct(paired) || ~isscalar(paired) || ...
        ~all(isfield(paired, required)) || ...
        ~strcmp(paired.contractVersion, ...
            'corrected-static-routing-v227-full-episode-result-v1') || ...
        ~paired.pairedOutcomeAvailable || ...
        ~strcmp(paired.presetName, presetName) || ...
        paired.seed ~= seed || ...
        ~strcmp(paired.splitName, protocol.splitName)
    error('InitialDynamicRouteFreezeV237:V227PairMismatch', ...
        'The V227 pair does not match the frozen V237 case.');
end
end

function arm = attachTopologySummary(arm, diagnostics)
pages = logical(diagnostics.topologyActiveEdge);
arm.uniqueTopologyCount = uniquePageCount(pages);
arm.topologyChangeCount = pageChangeCount(pages);
arm.routeMessageCountByTime = pageCounts(pages);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed);
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed);
end

function assertRuntimeFreeze(arm, registration, diagnostics)
certificates = diagnostics.topologyPolicyScheduleCertificate;
schedulePassed = all(cellfun(@(certificate) ...
    isstruct(certificate) && ...
    isfield(certificate, 'routeReselectionUsed') && ...
    ~logical(certificate.routeReselectionUsed) && ...
    isfield(certificate, 'truthReadAtRuntime') && ...
    ~logical(certificate.truthReadAtRuntime) && ...
    isfield(certificate, 'futureOutcomeReadAtRuntime') && ...
    ~logical(certificate.futureOutcomeReadAtRuntime), certificates));
if ~arm.exactMessageParityPassed || ...
        ~arm.physicalFeasibilityPassed || ...
        arm.routeMessageCountMinimum ~= registration.messageCount || ...
        arm.routeMessageCountMaximum ~= registration.messageCount || ...
        arm.uniqueTopologyCount ~= 1 || arm.topologyChangeCount ~= 0 || ...
        arm.policyTruthUsed || arm.policyFutureOutcomeUsed || ...
        ~schedulePassed
    error('InitialDynamicRouteFreezeV237:RuntimeContractFailed', ...
        'The executed V237 arm violated its frozen-route contract.');
end
end

function comparison = compareArm(candidate, reference)
comparison = struct();
comparison.fullHorizonEospaGainPercent = lowerGain( ...
    reference.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionEospa);
comparison.focusWindowEospaGainPercent = lowerGain( ...
    reference.focusWindowPositionEospa, ...
    candidate.focusWindowPositionEospa);
comparison.worstSensorEospaGainPercent = lowerGain( ...
    reference.worstSensorPositionEospa, ...
    candidate.worstSensorPositionEospa);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.fullHorizonRmseGainPercent = lowerGain( ...
    reference.fullHorizonPositionRmse, ...
    candidate.fullHorizonPositionRmse);
comparison.focusWindowRmseGainPercent = lowerGain( ...
    reference.focusWindowPositionRmse, ...
    candidate.focusWindowPositionRmse);
comparison.worstSensorRmseGainPercent = lowerGain( ...
    reference.worstSensorPositionRmse, ...
    candidate.worstSensorPositionRmse);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.fullConsensusGainPercent = lowerGain( ...
    reference.meanInterFormationPositionOspa, ...
    candidate.meanInterFormationPositionOspa);
comparison.focusConsensusGainPercent = lowerGain( ...
    reference.focusInterFormationPositionOspa, ...
    candidate.focusInterFormationPositionOspa);
comparison.terminalConsensusGainPercent = lowerGain( ...
    reference.terminalInterFormationPositionOspa, ...
    candidate.terminalInterFormationPositionOspa);
comparison.attemptedByteSavingPercent = lowerGain( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
comparison.deliveredByteSavingPercent = lowerGain( ...
    reference.deliveredPayloadBytes, candidate.deliveredPayloadBytes);
comparison.cardinalityGainPercent = lowerGain( ...
    reference.meanAbsoluteCardinalityError, ...
    candidate.meanAbsoluteCardinalityError);
end

function retention = gainRetention(freezeGain, dynamicGain)
names = {'fullHorizonEospaGainPercent', ...
    'fullHorizonRmseGainPercent', 'focusConsensusGainPercent', ...
    'attemptedByteSavingPercent'};
values = nan(1, numel(names));
for index = 1:numel(names)
    name = names{index};
    values(index) = freezeGain.(name) / max(dynamicGain.(name), eps);
end
retention.metricNames = names;
retention.byMetric = values;
retention.minimum = min(values);
retention.mean = mean(values);
end

function passed = meanGate(gain)
passed = gain.fullHorizonEospaGainPercent > 0 && ...
    gain.fullHorizonRmseGainPercent > 0 && ...
    gain.focusConsensusGainPercent > 0 && ...
    gain.attemptedByteSavingPercent > 0;
end

function passed = nonnegativeMeanGate(gain)
passed = gain.fullHorizonEospaGainPercent >= 0 && ...
    gain.fullHorizonRmseGainPercent >= 0 && ...
    gain.focusConsensusGainPercent >= 0 && ...
    gain.attemptedByteSavingPercent >= 0;
end

function compact = compactRegistration(registration)
compact = rmfield(registration, ...
    {'adjacency', 'fusionWeightMatrix', 'selectionDetails'});
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('InitialDynamicRouteFreezeV237:ReportWriteFailed', ...
        'Could not create the V237 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V237 initial dynamic-route freeze baseline\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Current source commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Reused V227 pair commit: `%s`\n', ...
    result.v227GenerationGitCommit);
fprintf(fid, '- Runtime truth / future outcome read: `%d / %d`\n\n', ...
    result.runtimeTruthUsed, result.runtimeFutureOutcomeUsed);
fprintf(fid, ['| Arm | Full E-OSPA | Focus E-OSPA | Full RMSE | ', ...
    'Focus RMSE | Focus consensus | Attempted bytes | Routes |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|\n');
writeArmRow(fid, 'Registered static', result.static);
writeArmRow(fid, 'Initial route frozen', result.freeze);
writeArmRow(fid, 'Dynamic reselection', result.dynamic);
writeGainSection(fid, 'Initial route frozen over registered static', ...
    result.freezeGainOverRegisteredStatic);
writeGainSection(fid, 'Dynamic reselection over initial route frozen', ...
    result.dynamicGainOverFreeze);
fprintf(fid, '\n## Attribution checks\n\n');
fprintf(fid, '- Frozen route improves all four mean axes over registered static: `%d`\n', ...
    result.registeredStaticMeanGatePassed);
fprintf(fid, '- Frozen route has nonnegative formation tail: `%d`\n', ...
    result.formationTailPassed);
fprintf(fid, '- Dynamic reselection improves all four mean axes over freeze: `%d`\n', ...
    result.temporalReselectionJointlyHelpful);
fprintf(fid, '- Freeze jointly dominates dynamic on four mean axes: `%d`\n', ...
    result.freezeJointlyDominatesDynamic);
fprintf(fid, '- Minimum initial-selection gain retention: `%.3f`\n', ...
    result.initialSelectionGainRetention.minimum);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function writeArmRow(fid, label, arm)
fprintf(fid, '| %s | %.3f | %.3f | %.3f | %.3f | %.3f | %.0f | %d |\n', ...
    label, arm.fullHorizonPositionEospa, ...
    arm.focusWindowPositionEospa, arm.fullHorizonPositionRmse, ...
    arm.focusWindowPositionRmse, ...
    arm.focusInterFormationPositionOspa, ...
    arm.attemptedPayloadBytes, arm.uniqueTopologyCount);
end

function writeGainSection(fid, titleText, gain)
fprintf(fid, '\n## %s\n\n', titleText);
fprintf(fid, '| Metric | Gain |\n|:--|--:|\n');
fprintf(fid, '| Full E-OSPA | `%+.3f%%` |\n', ...
    gain.fullHorizonEospaGainPercent);
fprintf(fid, '| Full RMSE | `%+.3f%%` |\n', ...
    gain.fullHorizonRmseGainPercent);
fprintf(fid, '| Focus consistency | `%+.3f%%` |\n', ...
    gain.focusConsensusGainPercent);
fprintf(fid, '| Attempted-byte saving | `%+.3f%%` |\n', ...
    gain.attemptedByteSavingPercent);
fprintf(fid, '| Weakest formation E-OSPA | `%+.3f%%` |\n', ...
    gain.minimumFormationEospaGainPercent);
fprintf(fid, '| Weakest formation RMSE | `%+.3f%%` |\n', ...
    gain.minimumFormationRmseGainPercent);
end

function sensors = selectFormationRepresentativesLocal(groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
sensors = zeros(1, numel(groups));
for groupIndex = 1:numel(groups)
    sensors(groupIndex) = find(groupIds == groups(groupIndex), 1);
end
end

function gain = lowerGain(reference, candidate)
if ~isfinite(reference) || ~isfinite(candidate)
    gain = NaN;
elseif abs(reference) <= eps
    gain = 0;
    if candidate > 0
        gain = -Inf;
    end
else
    gain = 100 * (reference - candidate) / abs(reference);
end
end

function gains = lowerGainVector(reference, candidate)
gains = nan(size(reference));
for index = 1:numel(reference)
    gains(index) = lowerGain(reference(index), candidate(index));
end
end

function count = uniquePageCount(pages)
flat = reshape(logical(pages), [], size(pages, 3))';
count = size(unique(flat, 'rows'), 1);
end

function count = pageChangeCount(pages)
count = 0;
for timeIndex = 2:size(pages, 3)
    count = count + ~isequal( ...
        pages(:, :, timeIndex), pages(:, :, timeIndex - 1));
end
end

function counts = pageCounts(pages)
counts = zeros(1, size(pages, 3));
for timeIndex = 1:size(pages, 3)
    counts(timeIndex) = nnz(pages(:, :, timeIndex));
end
end

function value = anyFiniteNonzero(values)
values = values(isfinite(values));
value = any(values ~= 0);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

function result = isAbsolutePath(pathValue)
if ispc
    result = ~isempty(regexp(pathValue, '^[A-Za-z]:[\\/]', 'once'));
else
    result = ~isempty(pathValue) && pathValue(1) == filesep;
end
end
