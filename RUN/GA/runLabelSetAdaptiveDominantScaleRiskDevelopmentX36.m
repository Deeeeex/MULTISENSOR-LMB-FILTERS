function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantScaleRiskDevelopmentX36(seed, options)
% RUNLABELSETADAPTIVEDOMINANTSCALERISKDEVELOPMENTX36
% Evaluate the preregistered v5 regret grid on one opened X36 pair.
%
% This development runner reuses the frozen v4 continuation cache and runs
% only the two new candidate arms.  The reference result is reused later by
% the summarizer, so deterministic baseline computation is not repeated.

if nargin < 1 || isempty(seed)
    error('An explicitly registered opened X36 seed is required.');
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantScaleRiskGatedRedesignAuthorized || ...
        ~ismember(seed, protocol. ...
            adaptiveDominantScaleRiskGatedDevelopmentSeeds)
    error('Scale-risk X36 development seed is not authorized.');
end
gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error(['Scale-risk X36 development runs require a clean tracked ', ...
        'worktree with no untracked MATLAB source files.']);
end

rootDirectory = getField(options, 'outputDirectory', ...
    protocol.adaptiveDominantScaleRiskGatedDevelopmentRoot);
seedDirectory = fullfile(rootDirectory, sprintf('seed%d', seed));
if completedEvidenceExists(seedDirectory)
    error(['Scale-risk X36 development evidence already exists for ', ...
        'seed %d; refusing to overwrite it.'], seed);
end
behaviorCacheDirectory = getField(options, ...
    'behaviorCacheDirectory', fullfile( ...
        protocol.adaptiveDominantScaleRiskGatedBaselineRoot, 'cache'));

screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantScaleRiskGatedDevelopmentTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantScaleRiskGatedDevelopmentTimes(1), ...
    'armNames', ...
        {protocol.adaptiveDominantScaleRiskGatedArmNames}, ...
    'writeReport', true, ...
    'outputDirectory', seedDirectory, ...
    'behaviorCacheDirectory', behaviorCacheDirectory, ...
    'generateMissingBehaviorCache', false, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'evidenceSplit', 'development');
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    protocol.adaptiveDominantScaleRiskGatedDevelopmentPresetName, ...
    seed, screenOptions);
end

function exists = completedEvidenceExists(seedDirectory)
exists = false;
if exist(seedDirectory, 'dir') ~= 7
    return;
end
exists = ~isempty(dir(fullfile(seedDirectory, '*.mat'))) || ...
    ~isempty(dir(fullfile(seedDirectory, '*.md')));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
