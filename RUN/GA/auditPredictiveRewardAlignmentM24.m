function [auditPath, audit] = ...
    auditPredictiveRewardAlignmentM24(sourceRoot, options)
% AUDITPREDICTIVEREWARDALIGNMENTM24 Test observable reward alignment.
%
% This audit is deliberately training-only. It asks whether the
% truth-assisted action-space headroom produces a better next-step
% truth-free predictive measurement score than matched references. It does
% not treat the privileged arm as deployable.

if nargin < 1 || isempty(sourceRoot)
    sourceRoot = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'predictive_reward_alignment_m24_seed7_h3_v1');
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getPredictiveRewardAlignmentProtocol();
bootstrapReplicates = getField(options, ...
    'bootstrapReplicates', 2000);
bootstrapReplicates = max(200, round(bootstrapReplicates));

files = dir(fullfile(sourceRoot, '*', ...
    'DYNAMIC_TOPOLOGY_CONTINUATION_M24_HARD_T75_N1_*.mat'));
if numel(files) ~= numel(protocol.armModes)
    error('Expected exactly %d score-gate source MAT files, found %d.', ...
        numel(protocol.armModes), numel(files));
end

sources = repmat(struct( ...
    'path', '', 'sha256', '', 'summary', struct(), ...
    'record', struct(), 'generation', struct()), ...
    1, numel(files));
observedModes = cell(1, numel(files));
for sourceIdx = 1:numel(files)
    sourcePath = fullfile(files(sourceIdx).folder, ...
        files(sourceIdx).name);
    loaded = load(sourcePath, 'summary');
    if ~isfield(loaded, 'summary')
        error('Score-gate source lacks summary: %s.', sourcePath);
    end
    validateSummary(loaded.summary, protocol);
    sources(sourceIdx).path = sourcePath;
    sources(sourceIdx).sha256 = ...
        computeFileSha256(sourcePath);
    sources(sourceIdx).summary = loaded.summary;
    sources(sourceIdx).record = loaded.summary.records;
    sources(sourceIdx).generation = ...
        loaded.summary.predictiveRewardEvidenceGeneration;
    observedModes{sourceIdx} = ...
        loaded.summary.records.armMode;
end
if numel(unique(observedModes)) ~= numel(protocol.armModes) || ...
        ~all(ismember(protocol.armModes, observedModes))
    error('Score-gate source arm modes are incomplete or duplicated.');
end
sources = reorderSources(sources, protocol.armModes);
records = [sources.record];
generationCommits = arrayfun(@(source) ...
    source.generation.commit, sources, ...
    'UniformOutput', false);
if numel(unique(generationCommits)) ~= 1 || ...
        any(arrayfun(@(source) ...
            source.generation.researchWorktreeDirty, sources))
    error('Score-gate sources lack a common clean generation commit.');
end
sourceGenerationCommit = generationCommits{1};

actionTimes = protocol.actionTimes;
rewardTimes = protocol.rewardTimes;
for armIdx = 1:numel(records)
    requireScoreFields(records(armIdx));
    if max(rewardTimes) > ...
            size(records(armIdx). ...
                predictiveMeasurementLogScoreBySensorTime, 2)
        error('Score-gate source is shorter than the reward horizon.');
    end
end

observedCounts = arrayfun(@(record) ...
    record.predictiveMeasurementObservedCountBySensorTime( ...
        :, rewardTimes), records, 'UniformOutput', false);
pairingPassed = all(cellfun(@(value) ...
    all(isfinite(value(:))) && ...
    isequaln(value, observedCounts{1}), observedCounts));

armScores = arrayfun(@(record) finiteMean( ...
    record.predictiveMeasurementLogScoreBySensorTime( ...
        :, rewardTimes)), records);
armEospa = [records.focusEospa];
armWorstEospa = [records.focusWorstSensorEospa];
armAttemptedBytes = [records.focusAttemptedBytes];
armRankSpearman = computeSpearman( ...
    armScores, -armEospa);

teacherIdx = find(strcmp(protocol.armModes, ...
    protocol.privilegedHeadroomArmMode));
referenceIndices = find(ismember( ...
    protocol.armModes, protocol.referenceArmModes));
teacherScoreAdvantage = armScores(teacherIdx) - ...
    max(armScores(referenceIndices));

referenceComparisons = repmat(struct( ...
    'mode', '', ...
    'meanScoreAdvantage', NaN, ...
    'meanScoreAdvantageCi95', [NaN, NaN], ...
    'pairedSensorTimeSpearman', NaN, ...
    'pairedSensorTimeSpearmanCi95', [NaN, NaN], ...
    'directionAgreementFraction', NaN, ...
    'positiveTrackingGainFraction', NaN), ...
    1, numel(referenceIndices));
rng(270729, 'twister');
for comparisonIdx = 1:numel(referenceIndices)
    referenceIdx = referenceIndices(comparisonIdx);
    teacherScore = records(teacherIdx). ...
        predictiveMeasurementLogScoreBySensorTime(:, rewardTimes);
    referenceScore = records(referenceIdx). ...
        predictiveMeasurementLogScoreBySensorTime(:, rewardTimes);
    scoreAdvantage = teacherScore - referenceScore;
    trackingGain = ...
        records(referenceIdx).eospaBySensorTime(:, actionTimes) - ...
        records(teacherIdx).eospaBySensorTime(:, actionTimes);
    valid = isfinite(scoreAdvantage) & isfinite(trackingGain);
    scoreAdvantage = scoreAdvantage(valid);
    trackingGain = trackingGain(valid);

    comparison = referenceComparisons(comparisonIdx);
    comparison.mode = protocol.armModes{referenceIdx};
    comparison.meanScoreAdvantage = ...
        finiteMean(scoreAdvantage);
    comparison.pairedSensorTimeSpearman = ...
        computeSpearman(scoreAdvantage, trackingGain);
    nonzero = abs(scoreAdvantage) > 1e-12 | ...
        abs(trackingGain) > 1e-12;
    comparison.directionAgreementFraction = finiteMean(double( ...
        sign(scoreAdvantage(nonzero)) == ...
        sign(trackingGain(nonzero))));
    comparison.positiveTrackingGainFraction = finiteMean(double( ...
        trackingGain > 0));
    [comparison.meanScoreAdvantageCi95, ...
        comparison.pairedSensorTimeSpearmanCi95] = ...
        clusterBootstrapIntervals( ...
            teacherScore - referenceScore, ...
            records(referenceIdx). ...
                eospaBySensorTime(:, actionTimes) - ...
            records(teacherIdx). ...
                eospaBySensorTime(:, actionTimes), ...
            bootstrapReplicates);
    referenceComparisons(comparisonIdx) = comparison;
end

byteDeviation = max(abs( ...
    armAttemptedBytes(referenceIndices) - ...
    armAttemptedBytes(teacherIdx)) ./ ...
    max(abs(armAttemptedBytes(referenceIndices)), 1));
safetyPassed = all(arrayfun(@(record) ...
    isFiniteZero(record.policyRepairRate) && ...
    isFiniteZero(record.policyPayloadEmergencyRate) && ...
    isFiniteZero(record.focusTopologyInfeasibleRate) && ...
    abs(record.focusSelectedRollingB3SensorStrongFraction - 1) ...
        <= 1e-12, records));
minimumPairedSpearman = min( ...
    [referenceComparisons.pairedSensorTimeSpearman]);

gates = struct();
gates.provenance = verifyGenerationCommit( ...
    sourceGenerationCommit);
gates.pairedMeasurements = pairingPassed;
gates.teacherScoreAdvantage = teacherScoreAdvantage >= ...
    protocol.minimumTeacherScoreAdvantage;
gates.armRank = isfinite(armRankSpearman) && ...
    armRankSpearman >= protocol.minimumArmRankSpearman;
gates.pairedSensorTime = ...
    isfinite(minimumPairedSpearman) && ...
    minimumPairedSpearman >= ...
        protocol.minimumPairedSensorTimeSpearman;
gates.bytes = byteDeviation <= ...
    protocol.maximumAttemptedByteDeviationFraction + 1e-12;
gates.safety = safetyPassed;

gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'predictive-reward-alignment-audit-v1';
audit.protocolId = protocol.id;
audit.generatedAt = datestr(now, 31);
audit.sourceRoot = sourceRoot;
audit.sourcePaths = {sources.path};
audit.sourceSha256 = {sources.sha256};
audit.sourceGenerationCommit = sourceGenerationCommit;
audit.auditGitCommit = gitState.commit;
audit.auditTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.auditUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.armModes = protocol.armModes;
audit.actionTimes = actionTimes;
audit.rewardTimes = rewardTimes;
audit.scoreType = protocol.scoreType;
audit.scoreTruthUsed = protocol.scoreTruthUsed;
audit.scoreExactLmbMeasurementSetLikelihood = ...
    protocol.scoreExactLmbMeasurementSetLikelihood;
audit.armPredictiveScores = armScores;
audit.armEospa = armEospa;
audit.armWorstSensorEospa = armWorstEospa;
audit.armAttemptedBytes = armAttemptedBytes;
audit.armRankSpearman = armRankSpearman;
audit.teacherScoreAdvantage = teacherScoreAdvantage;
audit.referenceComparisons = referenceComparisons;
audit.minimumPairedSensorTimeSpearman = ...
    minimumPairedSpearman;
audit.maximumAttemptedByteDeviationFraction = byteDeviation;
audit.gates = gates;
audit.alignmentGatePassed = all(structfun( ...
    @(value) logical(value), gates));
audit.banditImplementationAuthorized = ...
    audit.alignmentGatePassed;
audit.developmentEvaluationAuthorized = false;
audit.heldoutM24Authorized = false;
audit.x36PolicyRunAuthorized = false;
audit.privilegedDiagnosticOnly = true;
audit.evidenceBoundary = [ ...
    'The predictive score reads measurements but no target truth. ', ...
    'The headroom arm itself reads current truth, so this training-only ', ...
    'audit tests reward alignment and cannot establish deployable ', ...
    'policy performance or authorize development/held-out evaluation.'];

outputDirectory = getField(options, ...
    'outputDirectory', sourceRoot);
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
auditPath = fullfile(outputDirectory, ...
    'predictive_reward_alignment_audit_m24_seed7_h3_v1.mat');
reportPath = fullfile(outputDirectory, ...
    'PREDICTIVE_REWARD_ALIGNMENT_AUDIT_M24_SEED7_H3_V1.md');
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function validateSummary(summary, protocol)
required = { ...
    'presetName', 'seeds', 'options', 'records', ...
    'predictiveRewardEvidenceGeneration'};
if ~isstruct(summary) || ~all(isfield(summary, required)) || ...
        ~strcmp(summary.presetName, protocol.presetName) || ...
        ~isequal(summary.seeds, protocol.seed) || ...
        summary.options.continuationStartTime ~= ...
            protocol.continuationStartTime || ...
        summary.options.maxTimeSteps ~= ...
            protocol.continuationEndTime || ...
        summary.options.filterSeedOffset ~= ...
            protocol.filterSeedOffset || ...
        ~strcmp(summary.options.evidenceSplit, 'development') || ...
        numel(summary.records) ~= 1 || ...
        ~isstruct(summary.predictiveRewardEvidenceGeneration) || ...
        ~all(isfield(summary.predictiveRewardEvidenceGeneration, ...
            {'commit', 'researchWorktreeDirty'}))
    error('Score-gate source violates the frozen protocol.');
end
end

function sources = reorderSources(sources, modes)
ordered = sources;
observed = arrayfun(@(source) ...
    source.record.armMode, sources, 'UniformOutput', false);
for modeIdx = 1:numel(modes)
    sourceIdx = find(strcmp(observed, modes{modeIdx}));
    if numel(sourceIdx) ~= 1
        error('Expected exactly one source for mode %s.', ...
            modes{modeIdx});
    end
    ordered(modeIdx) = sources(sourceIdx);
end
sources = ordered;
end

function requireScoreFields(record)
required = { ...
    'predictiveMeasurementLogScoreBySensorTime', ...
    'predictiveMeasurementExpectedCountBySensorTime', ...
    'predictiveMeasurementObservedCountBySensorTime', ...
    'eospaBySensorTime', ...
    'policyRepairRate', ...
    'policyPayloadEmergencyRate', ...
    'focusTopologyInfeasibleRate', ...
    'focusSelectedRollingB3SensorStrongFraction'};
if ~all(isfield(record, required))
    error('Score-gate record lacks predictive reward diagnostics.');
end
end

function [meanInterval, correlationInterval] = ...
    clusterBootstrapIntervals(scoreAdvantage, trackingGain, replicates)
sensorCount = size(scoreAdvantage, 1);
meanSamples = nan(1, replicates);
correlationSamples = nan(1, replicates);
for replicateIdx = 1:replicates
    sampledSensors = randi(sensorCount, 1, sensorCount);
    sampledScore = scoreAdvantage(sampledSensors, :);
    sampledGain = trackingGain(sampledSensors, :);
    meanSamples(replicateIdx) = finiteMean(sampledScore);
    correlationSamples(replicateIdx) = ...
        computeSpearman(sampledScore, sampledGain);
end
meanInterval = empiricalInterval(meanSamples, [0.025, 0.975]);
correlationInterval = empiricalInterval( ...
    correlationSamples, [0.025, 0.975]);
end

function interval = empiricalInterval(values, probabilities)
values = sort(values(isfinite(values)));
if isempty(values)
    interval = [NaN, NaN];
    return;
end
indices = 1 + (numel(values) - 1) * probabilities;
lowerIndices = floor(indices);
upperIndices = ceil(indices);
fractions = indices - lowerIndices;
interval = values(lowerIndices) .* (1 - fractions) + ...
    values(upperIndices) .* fractions;
end

function correlation = computeSpearman(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
valid = isfinite(left) & isfinite(right);
left = left(valid);
right = right(valid);
if numel(left) < 3 || numel(unique(left)) < 2 || ...
        numel(unique(right)) < 2
    correlation = NaN;
    return;
end
leftRanks = averageRanks(left);
rightRanks = averageRanks(right);
correlationMatrix = corrcoef(leftRanks, rightRanks);
correlation = correlationMatrix(1, 2);
end

function ranks = averageRanks(values)
[sortedValues, order] = sort(values);
ranks = zeros(size(values));
startIdx = 1;
while startIdx <= numel(values)
    endIdx = startIdx;
    while endIdx < numel(values) && ...
            sortedValues(endIdx + 1) == sortedValues(startIdx)
        endIdx = endIdx + 1;
    end
    ranks(order(startIdx:endIdx)) = ...
        0.5 * (startIdx + endIdx);
    startIdx = endIdx + 1;
end
end

function passed = verifyGenerationCommit(expectedCommit)
[status, output] = system(sprintf( ...
    'git merge-base --is-ancestor %s HEAD', expectedCommit));
passed = status == 0 && isempty(strtrim(output));
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write predictive reward alignment report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, '# M24 predictive reward alignment audit\n\n');
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fid, '- Evidence commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Action times: `%s`; delayed reward times: `%s`\n', ...
    mat2str(audit.actionTimes), mat2str(audit.rewardTimes));
fprintf(fid, '- Score: `%s`; truth used by score: `%d`\n', ...
    audit.scoreType, audit.scoreTruthUsed);
fprintf(fid, ['- Evidence boundary: %s\n\n'], ...
    audit.evidenceBoundary);

fprintf(fid, ['| Arm | Predictive score | Focus E-OSPA | ', ...
    'Worst node | Attempted bytes |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|\n');
for armIdx = 1:numel(audit.armModes)
    fprintf(fid, '| `%s` | %.6f | %.4f | %.4f | %.0f |\n', ...
        audit.armModes{armIdx}, ...
        audit.armPredictiveScores(armIdx), ...
        audit.armEospa(armIdx), ...
        audit.armWorstSensorEospa(armIdx), ...
        audit.armAttemptedBytes(armIdx));
end

fprintf(fid, ['\n| Reference | Mean score advantage [95%% CI] | ', ...
    'Paired Spearman [95%% CI] | Direction agreement | ', ...
    'Positive tracking gain |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|\n');
for comparisonIdx = 1:numel(audit.referenceComparisons)
    comparison = audit.referenceComparisons(comparisonIdx);
    fprintf(fid, ...
        '| `%s` | %.6f [%.6f, %.6f] | %.4f [%.4f, %.4f] | %.3f | %.3f |\n', ...
        comparison.mode, comparison.meanScoreAdvantage, ...
        comparison.meanScoreAdvantageCi95(1), ...
        comparison.meanScoreAdvantageCi95(2), ...
        comparison.pairedSensorTimeSpearman, ...
        comparison.pairedSensorTimeSpearmanCi95(1), ...
        comparison.pairedSensorTimeSpearmanCi95(2), ...
        comparison.directionAgreementFraction, ...
        comparison.positiveTrackingGainFraction);
end

fprintf(fid, '\n- Arm-rank Spearman: `%.4f`\n', ...
    audit.armRankSpearman);
fprintf(fid, '- Teacher score advantage over best reference: `%.6f`\n', ...
    audit.teacherScoreAdvantage);
fprintf(fid, '- Minimum paired sensor-time Spearman: `%.4f`\n', ...
    audit.minimumPairedSensorTimeSpearman);
fprintf(fid, '- Maximum attempted-byte deviation: `%.4f%%`\n', ...
    100 * audit.maximumAttemptedByteDeviationFraction);
fprintf(fid, ['- Gates (provenance / paired measurements / score ', ...
    'advantage / arm rank / paired sensor-time / bytes / safety): ', ...
    '`%d / %d / %d / %d / %d / %d / %d`\n'], ...
    audit.gates.provenance, ...
    audit.gates.pairedMeasurements, ...
    audit.gates.teacherScoreAdvantage, ...
    audit.gates.armRank, ...
    audit.gates.pairedSensorTime, ...
    audit.gates.bytes, audit.gates.safety);
fprintf(fid, '- Alignment gate passed: `%d`\n', ...
    audit.alignmentGatePassed);
fprintf(fid, '- Bandit implementation authorized: `%d`\n', ...
    audit.banditImplementationAuthorized);
fprintf(fid, ['- Development / held-out M24 / X36 authorized: ', ...
    '`%d / %d / %d`\n'], ...
    audit.developmentEvaluationAuthorized, ...
    audit.heldoutM24Authorized, ...
    audit.x36PolicyRunAuthorized);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function valid = isFiniteZero(value)
valid = isscalar(value) && isfinite(value) && value == 0;
end
