function result = ...
    runFormationB4V49TimeVaryingB4StructuralReplay(options)
% RUNFORMATIONB4V49TIMEVARYINGB4STRUCTURALREPLAY
% Select a cycle on the current burst page, then score the actual current-
% page V46 dominant routes and link probabilities over the next four pages.

if nargin < 1 || isempty(options)
    options = struct();
end
allowed = {'presets', 'seeds', 'windowMode', ...
    'cycleSelectionMode', 'maximumExactProposalEvaluations', ...
    'minimumRouteImprovementVsIncumbent'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowed))
    error('FormationB4V49Replay:InvalidOptions', ...
        'The time-varying replay options are malformed.');
end
presets = getField(options, 'presets', { ...
    'm24-formation-fov', 'm24-formation-fov-convoy', ...
    'm24-formation-fov-relay', 'm24-formation-fov-crossing', ...
    'x36-formation-fov', 'x36-formation-fov-convoy', ...
    'x36-formation-fov-relay', 'x36-formation-fov-crossing'});
seeds = reshape(getField(options, 'seeds', 41), 1, []);
windowMode = lower(char(getField(options, ...
    'windowMode', 'focus-start')));
protocol = getFormationB4V49FeasibleCycleCompletionProtocol();
selectionMode = lower(char(getField(options, ...
    'cycleSelectionMode', protocol.defaultCycleSelectionMode)));
maximumExactProposalEvaluations = getField(options, ...
    'maximumExactProposalEvaluations', ...
    protocol.maximumExactProposalEvaluations);
minimumRouteImprovement = getField(options, ...
    'minimumRouteImprovementVsIncumbent', ...
    protocol.minimumRelativeImprovementVsIncumbent);
if ~iscell(presets) || isempty(presets) || ...
        ~isnumeric(seeds) || isempty(seeds) || ...
        any(~isfinite(seeds)) || any(seeds ~= round(seeds)) || ...
        ~ismember(windowMode, {'focus-start', 'all-b4'}) || ...
        ~ismember(selectionMode, { ...
            'reliability-proposal-topk', ...
            'exact-contraction-enumeration'}) || ...
        ~isscalar(maximumExactProposalEvaluations) || ...
        ~isfinite(maximumExactProposalEvaluations) || ...
        maximumExactProposalEvaluations < 1 || ...
        maximumExactProposalEvaluations ~= ...
            round(maximumExactProposalEvaluations) || ...
        ~isscalar(minimumRouteImprovement) || ...
        ~isfinite(minimumRouteImprovement) || ...
        minimumRouteImprovement < 0 || ...
        minimumRouteImprovement > 1
    error('FormationB4V49Replay:InvalidOptions', ...
        'A replay option is invalid.');
end

caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        fprintf('V49 time-varying case %d/%d: %s seed=%d mode=%s\n', ...
            cursor, caseCount, presets{presetIdx}, ...
            seeds(seedIdx), windowMode);
        cases(cursor) = replayCase(presets{presetIdx}, ...
            seeds(seedIdx), windowMode, selectionMode, ...
            maximumExactProposalEvaluations, ...
            minimumRouteImprovement);
    end
end

allWindows = concatenateWindows(cases);
payload = struct();
payload.contractVersion = ...
    'formation-b4-v49-time-varying-b4-structural-replay-v1';
payload.presets = presets;
payload.seeds = seeds;
payload.windowMode = windowMode;
payload.cycleSelectionMode = selectionMode;
payload.maximumExactProposalEvaluations = ...
    maximumExactProposalEvaluations;
payload.minimumRouteImprovementVsIncumbent = ...
    minimumRouteImprovement;
payload.cases = cases;
payload.caseCount = caseCount;
payload.windowCount = numel(allWindows);
payload.cycleSelectedWindowCount = nnz( ...
    [allWindows.cycleSelected]);
payload.realizedPositiveWindowCount = nnz( ...
    [allWindows.realizedRelativeImprovement] > 1e-6);
payload.realizedNegativeWindowCount = nnz( ...
    [allWindows.realizedRelativeImprovement] < -1e-6);
payload.realizedNoWorseWindowFraction = mean( ...
    [allWindows.candidateRealizedSquaredFactor] <= ...
        [allWindows.incumbentRealizedSquaredFactor] + 1e-12);
payload.allSamePosteriorMessageBudget = all( ...
    [allWindows.samePosteriorMessageBudget]);
payload.allBurstSensorStrongConnected = all( ...
    [allWindows.burstSensorStrongConnected]);
payload.allBurstFormationStrongConnected = all( ...
    [allWindows.burstFormationStrongConnected]);
payload.currentBurstPageUsedByPolicy = true;
payload.futurePagesUsedByPolicy = false;
payload.futurePagesUsedByPosthocAudit = true;
payload.fullPlannedSensorAndLinkSchedulesMaterialized = true;
payload.posteriorUsed = false;
payload.truthUsed = false;
payload.measurementUsed = false;
payload.realizedDeliveryUniformsUsed = false;
payload.trackingOutcomeScored = false;
payload.routeDisseminationImplemented = false;
payload.atomicCommitImplemented = false;
payload.sameTotalByteClaimAllowed = false;
payload.timeVaryingNoWorseCertified = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
payload.wallClockTimingExcludedFromCanonicalSha256 = true;
payload.canonicalSha256 = computeCanonicalValueSha256( ...
    stripWallClockTiming(payload));
result = payload;
fprintf(['V49 time-varying replay complete: cycle=%d/%d ', ...
    'positive=%d negative=%d noWorse=%.3f sha256=%s\n'], ...
    result.cycleSelectedWindowCount, result.windowCount, ...
    result.realizedPositiveWindowCount, ...
    result.realizedNegativeWindowCount, ...
    result.realizedNoWorseWindowFraction, ...
    result.canonicalSha256);
end

function value = replayCase(presetName, seed, windowMode, ...
        selectionMode, maximumExactProposalEvaluations, ...
        minimumRouteImprovement)
rng(seed, 'twister');
config = buildDynamicTopologyScenarioConfig(presetName);
[sensorTrajectories, trajectoryMetadata] = ...
    generateMultiFormationTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensorTrajectories);
[pDropByEdge, ~] = buildDynamicTopologyLinkSchedule(config, graph);
identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
if ~isequal(identity.sensorPhysicalUids, ...
        trajectoryMetadata.sensorPhysicalUids) || ...
        ~isequal(identity.formationPhysicalUidsBySensor, ...
            trajectoryMetadata.formationPhysicalUidsBySensor)
    error('FormationB4V49Replay:IdentityDrift', ...
        'The scene and trajectory physical identities disagree.');
end
registeredBase = FormationB4V45BuildCausalRegisteredBaseGraph( ...
    config.formationBackboneMode, config.sensorGroupIds, ...
    identity.sensorPhysicalUids, ...
    identity.formationPhysicalUidsBySensor, ...
    graph.positions(:, :, 1), graph.physicalAdjacency(:, :, 1));
windowStarts = resolveWindowStarts(config, windowMode);
windows = repmat(emptyWindow(), 1, numel(windowStarts));
previousSelectedCrossEdges = zeros(0, 4);
previousSelectedCyclePairs = zeros(0, 2);
for windowIdx = 1:numel(windowStarts)
    startTime = windowStarts(windowIdx);
        windows(windowIdx) = replayWindow(config, identity, ...
            registeredBase.baseAdjacency, graph, pDropByEdge, ...
            startTime, selectionMode, maximumExactProposalEvaluations, ...
            minimumRouteImprovement, windowIdx > 1, ...
            previousSelectedCrossEdges, previousSelectedCyclePairs);
    previousSelectedCrossEdges = ...
        windows(windowIdx).selectedCrossResidualPhysicalUidTable;
    previousSelectedCyclePairs = ...
        windows(windowIdx).selectedCycleFormationPairPhysicalUidTable;
    fprintf(['  t=%d selected=%d planGain=%+.3f%% ', ...
        'realizedGain=%+.3f%% routeChanged=%d gatewayDelta=%d ', ...
        'eval=%d time=%.3fs\n'], ...
        startTime, windows(windowIdx).cycleSelected, ...
        100 * windows(windowIdx).planningRelativeImprovement, ...
        100 * windows(windowIdx).realizedRelativeImprovement, ...
        windows(windowIdx).formationCycleChangedFromPreviousWindow, ...
        windows(windowIdx).crossResidualGatewaySymmetricDifferenceCount, ...
        windows(windowIdx).totalCertificateEvaluationCount, ...
        windows(windowIdx).selectionSeconds);
end

value = emptyCase();
value.caseId = sprintf('%s__seed%d__%s', ...
    presetName, seed, windowMode);
value.presetName = presetName;
value.seed = seed;
value.nodeCount = config.numberOfSensors;
value.formationCount = config.formationCount;
value.windowStarts = windowStarts;
value.windows = windows;
value.windowCount = numel(windows);
value.cycleSelectedWindowCount = nnz([windows.cycleSelected]);
value.realizedPositiveWindowCount = nnz( ...
    [windows.realizedRelativeImprovement] > 1e-6);
value.realizedNegativeWindowCount = nnz( ...
    [windows.realizedRelativeImprovement] < -1e-6);
value.meanRealizedRelativeImprovement = mean( ...
    [windows.realizedRelativeImprovement]);
value.medianRealizedRelativeImprovement = median( ...
    [windows.realizedRelativeImprovement]);
value.minimumRealizedRelativeImprovement = min( ...
    [windows.realizedRelativeImprovement]);
value.maximumRealizedRelativeImprovement = max( ...
    [windows.realizedRelativeImprovement]);
value.formationCycleChangeCount = nnz( ...
    [windows.formationCycleChangedFromPreviousWindow]);
value.crossResidualGatewaySymmetricDifferenceTotal = sum( ...
    [windows.crossResidualGatewaySymmetricDifferenceCount]);
value.meanSelectionSeconds = mean([windows.selectionSeconds]);
value.maximumSelectionSeconds = max([windows.selectionSeconds]);
value.fullPlannedSensorAndLinkSchedulesMaterialized = true;
value.futurePagesUsedByPolicy = false;
value.futurePagesUsedByPosthocAudit = true;
value.posteriorUsed = false;
value.truthUsed = false;
value.measurementUsed = false;
value.realizedDeliveryUniformsUsed = false;
value.trackingOutcomeScored = false;
value.developmentEvidenceOnly = true;
value.wallClockTimingExcludedFromCanonicalSha256 = true;
value.canonicalSha256 = computeCanonicalValueSha256( ...
    stripWallClockTiming(rmfield(value, 'canonicalSha256')));
end

function value = replayWindow(config, identity, registeredBase, ...
        graph, pDropByEdge, startTime, selectionMode, ...
        maximumExactProposalEvaluations, minimumRouteImprovement, ...
        hasPreviousWindow, previousCrossEdges, previousCyclePairs)
if startTime < 1 || startTime + 3 > config.simulationLength
    error('FormationB4V49Replay:WindowOutsideEpisode', ...
        'A B4 replay window lies outside the episode.');
end
incumbentPages = cell(1, 4);
for phase = 1:4
    currentTime = startTime + phase - 1;
    incumbentPages{phase} = ...
        buildFormationB4V48CurrentReferenceSnapshot( ...
            config, identity, registeredBase, ...
            graph.positions(:, :, currentTime), ...
            graph.physicalAdjacency(:, :, currentTime), ...
            pDropByEdge(:, :, currentTime), currentTime);
end
incumbentAtBurst = incumbentPages{1}.reference;
routeInput = buildFullRouteInput(config, identity, graph, ...
    pDropByEdge, startTime);
routeContext = buildFormationB4V49GraphOnlyRouteContext(routeInput);
timerId = tic;
[selectedReference, selection] = ...
    selectFormationB4V49CyclePreservingReference( ...
        routeContext, incumbentAtBurst, struct( ...
            'minimumRelativeImprovementVsIncumbent', ...
                minimumRouteImprovement, ...
            'cycleSelectionMode', selectionMode, ...
            'maximumExactProposalEvaluations', ...
                maximumExactProposalEvaluations, ...
            'pulsePhaseMode', 'fixed-phase-one'));
selectionSeconds = toc(timerId);

nodeCount = config.numberOfSensors;
incumbentAdjacency = false(nodeCount, nodeCount, 4);
incumbentWeights = zeros(nodeCount, nodeCount, 4);
candidateAdjacency = false(nodeCount, nodeCount, 4);
candidateWeights = zeros(nodeCount, nodeCount, 4);
reliability = zeros(nodeCount, nodeCount, 4);
for phase = 1:4
    dominant = incumbentPages{phase}.reference.dominantAdjacency;
    incumbentResidual = false(nodeCount);
    candidateResidual = false(nodeCount);
    if phase == 1
        incumbentResidual = ...
            incumbentPages{phase}.reference.residualAdjacency;
        candidateResidual = selectedReference.residualAdjacency;
    end
    incumbentAdjacency(:, :, phase) = ...
        dominant | incumbentResidual;
    incumbentWeights(:, :, phase) = buildWeights( ...
        dominant, incumbentResidual);
    candidateAdjacency(:, :, phase) = dominant | candidateResidual;
    candidateWeights(:, :, phase) = buildWeights( ...
        dominant, candidateResidual);
    reliability(:, :, phase) = ...
        1 - pDropByEdge(:, :, startTime + phase - 1)';
end
certificateOptions = struct( ...
    'missingNeighborWeightMode', 'renormalize', ...
    'maximumIncomingCount', 2);
incumbentCertificate = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        incumbentAdjacency, incumbentWeights, reliability, ...
        certificateOptions);
candidateCertificate = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        candidateAdjacency, candidateWeights, reliability, ...
        certificateOptions);
incumbentFactor = incumbentCertificate. ...
    worstCaseExpectedSquaredContractionFactor;
candidateFactor = candidateCertificate. ...
    worstCaseExpectedSquaredContractionFactor;
formationBurst = collapseToFormations( ...
    candidateAdjacency(:, :, 1), ...
    identity.formationPhysicalUidsBySensor);
selectedCrossEdges = crossEdgeUidTable( ...
    selectedReference.residualAdjacency, ...
    identity.sensorPhysicalUids, ...
    identity.formationPhysicalUidsBySensor);
selectedCyclePairs = cyclePairTable(selection.selectedCycleOrder);
if isempty(selection.selectedCycleOrder)
    selectedCyclePairs = crossFormationPairTable( ...
        selectedReference.residualAdjacency, ...
        identity.formationPhysicalUidsBySensor);
end
sameMessages = sum(reshape(sum(sum( ...
    incumbentAdjacency, 1), 2), 1, [])) == 5 * nodeCount && ...
    sum(reshape(sum(sum(candidateAdjacency, 1), 2), 1, [])) == ...
        5 * nodeCount;
candidateBurst = candidateAdjacency(:, :, 1);
physicalBurst = graph.physicalAdjacency(:, :, startTime);
if ~sameMessages || ...
        any(candidateBurst(:) & ~physicalBurst(:)) || ...
        ~isStronglyConnected(candidateBurst) || ...
        ~isStronglyConnected(formationBurst)
    error('FormationB4V49Replay:InvalidExecution', ...
        'The current-page cycle execution violates a hard invariant.');
end

value = emptyWindow();
value.windowStart = startTime;
value.executionTimes = startTime:(startTime + 3);
value.cycleSelected = ...
    selection.selectedIsCyclePreservingReference;
value.selectedUsedIncumbentFallback = ...
    selection.selectedUsedIncumbentFallback;
value.selectionCanonicalSha256 = selection.canonicalSha256;
value.selectedPhysicalRouteCanonicalSha256 = ...
    selection.selectedPhysicalRouteCanonicalSha256;
value.selectedCycleOrder = selection.selectedCycleOrder;
value.selectedCycleFormationPairPhysicalUidTable = ...
    selectedCyclePairs;
value.selectedCrossResidualPhysicalUidTable = selectedCrossEdges;
value.formationCycleChangedFromPreviousWindow = ...
    hasPreviousWindow && ...
        ~isequal(selectedCyclePairs, previousCyclePairs);
if hasPreviousWindow
    value.formationCyclePairSymmetricDifferenceCount = ...
        size(setxor(selectedCyclePairs, previousCyclePairs, 'rows'), 1);
    value.crossResidualGatewaySymmetricDifferenceCount = ...
        size(setxor(selectedCrossEdges, previousCrossEdges, 'rows'), 1);
else
    value.formationCyclePairSymmetricDifferenceCount = 0;
    value.crossResidualGatewaySymmetricDifferenceCount = 0;
end
value.planningIncumbentSquaredFactor = ...
    selection.incumbentBestSynchronizedSquaredFactor;
value.planningSelectedSquaredFactor = selection.selectedSquaredFactor;
value.planningRelativeImprovement = ...
    selection.selectedRelativeImprovementVsIncumbent;
value.incumbentRealizedSquaredFactor = incumbentFactor;
value.candidateRealizedSquaredFactor = candidateFactor;
value.realizedRelativeImprovement = ...
    safeRelativeImprovement(incumbentFactor, candidateFactor);
value.snapshotToRealizedCandidateFactorDelta = ...
    candidateFactor - selection.selectedSquaredFactor;
value.samePosteriorMessageBudget = sameMessages;
value.incumbentMessageCountByPhase = reshape(sum(sum( ...
    incumbentAdjacency, 1), 2), 1, []);
value.candidateMessageCountByPhase = reshape(sum(sum( ...
    candidateAdjacency, 1), 2), 1, []);
value.burstSensorStrongConnected = ...
    isStronglyConnected(candidateAdjacency(:, :, 1));
value.burstFormationStrongConnected = ...
    isStronglyConnected(formationBurst);
value.candidateMaterializationAttemptCount = ...
    selection.candidateMaterializationAttemptCount;
value.totalCertificateEvaluationCount = ...
    selection.totalCertificateEvaluationCount;
value.selectionSeconds = selectionSeconds;
value.currentBurstPageUsedByPolicy = true;
value.futurePagesUsedByPolicy = false;
value.futurePagesUsedByPosthocAudit = true;
value.cycleUsedOnBurstPageOnly = true;
value.posteriorUsed = false;
value.truthUsed = false;
value.measurementUsed = false;
value.realizedDeliveryUniformsUsed = false;
value.trackingOutcomeScored = false;
value.sameTotalByteClaimAllowed = false;
value.timeVaryingNoWorseCertified = false;
value.developmentEvidenceOnly = true;
value.wallClockTimingExcludedFromCanonicalSha256 = true;
value.canonicalSha256 = computeCanonicalValueSha256( ...
    stripWallClockTiming(rmfield(value, 'canonicalSha256')));
end

function context = buildFullRouteInput( ...
        config, identity, graph, pDropByEdge, currentTime)
context = struct();
context.model = struct('dynamicTopologyScenario', struct( ...
    'config', struct('sensorGroupIds', config.sensorGroupIds)));
context.positions = graph.positions(:, :, currentTime);
context.sensorPhysicalUids = identity.sensorPhysicalUids;
context.formationPhysicalUidsBySensor = ...
    identity.formationPhysicalUidsBySensor;
context.physicalAdjacency = ...
    graph.physicalAdjacency(:, :, currentTime);
context.commConfig = struct('pDropByEdge', ...
    pDropByEdge(:, :, currentTime));
context.currentTime = currentTime;
end

function starts = resolveWindowStarts(config, mode)
if strcmp(mode, 'focus-start')
    starts = round(config.focusWindow(1));
else
    starts = 1:4:(config.simulationLength - 3);
end
end

function weights = buildWeights(dominant, residual)
nodeCount = size(dominant, 1);
weights = zeros(nodeCount);
weights(dominant) = 0.70;
weights(residual) = 0.20;
weights(1:nodeCount+1:end) = 1 - sum(weights, 2)';
end

function pages = collapseToFormations(sensorPages, formationUids)
uids = sort(unique(formationUids));
pages = false(numel(uids), numel(uids), size(sensorPages, 3));
for pageIdx = 1:size(sensorPages, 3)
    for receiverIdx = 1:numel(uids)
        receivers = formationUids == uids(receiverIdx);
        for senderIdx = 1:numel(uids)
            senders = formationUids == uids(senderIdx);
            pages(receiverIdx, senderIdx, pageIdx) = any(any( ...
                sensorPages(receivers, senders, pageIdx)));
        end
    end
end
end

function table = crossEdgeUidTable(residual, sensorUids, formationUids)
crossMask = formationUids(:) ~= formationUids(:)';
[receivers, senders] = find(residual & crossMask);
table = [reshape(formationUids(receivers), [], 1), ...
    reshape(formationUids(senders), [], 1), ...
    reshape(sensorUids(receivers), [], 1), ...
    reshape(sensorUids(senders), [], 1)];
if ~isempty(table)
    table = sortrows(table, 1:4);
end
end

function table = crossFormationPairTable(residual, formationUids)
crossMask = formationUids(:) ~= formationUids(:)';
[receivers, senders] = find(residual & crossMask);
directedPairs = [reshape(formationUids(receivers), [], 1), ...
    reshape(formationUids(senders), [], 1)];
undirectedPairs = sort(directedPairs, 2);
table = sortrows(unique(undirectedPairs, 'rows'), [1, 2]);
end

function table = cyclePairTable(order)
if isempty(order)
    table = zeros(0, 2);
    return;
end
table = zeros(numel(order), 2);
for idx = 1:numel(order)
    table(idx, :) = sort([order(idx), ...
        order(mod(idx, numel(order)) + 1)]);
end
table = sortrows(unique(table, 'rows'), [1, 2]);
end

function passed = isStronglyConnected(adjacency)
senderAdjacency = logical(adjacency');
passed = reachableAll(senderAdjacency) && ...
    reachableAll(senderAdjacency');
end

function passed = reachableAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
passed = all(visited);
end

function windows = concatenateWindows(cases)
windows = repmat(emptyWindow(), 1, 0);
for caseIdx = 1:numel(cases)
    windows = [windows, cases(caseIdx).windows]; %#ok<AGROW>
end
end

function value = safeRelativeImprovement(reference, candidate)
if reference > 0
    value = (reference - candidate) / reference;
elseif candidate == 0
    value = 0;
else
    value = -inf;
end
end

function value = stripWallClockTiming(value)
% Preserve measured timings in the result while excluding them from the
% semantic evidence hash.  Recurse without removing any contract fields.
if ~isstruct(value)
    return;
end
for valueIdx = 1:numel(value)
    fields = fieldnames(value(valueIdx));
    for fieldIdx = 1:numel(fields)
        name = fields{fieldIdx};
        if ismember(name, {'selectionSeconds', ...
                'meanSelectionSeconds', 'maximumSelectionSeconds'})
            value(valueIdx).(name) = [];
        elseif isstruct(value(valueIdx).(name))
            value(valueIdx).(name) = ...
                stripWallClockTiming(value(valueIdx).(name));
        end
    end
end
end

