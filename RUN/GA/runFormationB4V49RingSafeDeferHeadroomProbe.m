function result = runFormationB4V49RingSafeDeferHeadroomProbe(options)
% RUNFORMATIONB4V49RINGSAFEDEFERHEADROOMPROBE Graph-only action-bank gate.

if nargin < 1 || isempty(options)
    options = struct();
end
allowed = {'presets', 'seeds', 'cycleSelectionMode', ...
    'maximumExactProposalEvaluations', ...
    'minimumRouteImprovementVsIncumbent', ...
    'includeDeferAblation', 'pulsePhaseMode'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowed))
    error('FormationB4V49Headroom:InvalidOptions', ...
        'The V49 headroom options are malformed.');
end
presets = getField(options, 'presets', { ...
    'm24-formation-fov', 'm24-formation-fov-convoy', ...
    'm24-formation-fov-relay', 'm24-formation-fov-crossing', ...
    'x36-formation-fov', 'x36-formation-fov-convoy', ...
    'x36-formation-fov-relay', 'x36-formation-fov-crossing'});
seeds = reshape(getField(options, 'seeds', 41), 1, []);
protocol = getFormationB4V49FeasibleCycleCompletionProtocol();
selectionMode = lower(char(getField(options, ...
    'cycleSelectionMode', protocol.defaultCycleSelectionMode)));
maximumExactProposalEvaluations = getField(options, ...
    'maximumExactProposalEvaluations', ...
    protocol.maximumExactProposalEvaluations);
minimumRouteImprovement = getField(options, ...
    'minimumRouteImprovementVsIncumbent', ...
    protocol.minimumRelativeImprovementVsIncumbent);
includeDeferAblation = getField(options, ...
    'includeDeferAblation', false);
pulsePhaseMode = lower(char(getField(options, ...
    'pulsePhaseMode', protocol.runtimePulsePhaseMode)));
if ~iscell(presets) || isempty(presets) || ...
        ~isnumeric(seeds) || isempty(seeds) || ...
        any(~isfinite(seeds)) || any(seeds ~= round(seeds)) || ...
        ~ismember(selectionMode, { ...
            'reliability-proposal-topk', ...
            'exact-contraction-enumeration'}) || ...
        ~isscalar(maximumExactProposalEvaluations) || ...
        ~isfinite(maximumExactProposalEvaluations) || ...
        maximumExactProposalEvaluations < 1 || ...
        maximumExactProposalEvaluations ~= ...
            round(maximumExactProposalEvaluations) || ...
        ~isscalar(minimumRouteImprovement) || ...
        ~isfinite(minimumRouteImprovement) || ...
        minimumRouteImprovement < 0 || ...
        minimumRouteImprovement > 1 || ...
        ~islogical(includeDeferAblation) || ...
        ~isscalar(includeDeferAblation) || ...
        ~ismember(pulsePhaseMode, { ...
            'fixed-phase-one', 'best-of-four-development-oracle'})
    error('FormationB4V49Headroom:InvalidOptions', ...
        'The preset or seed list is invalid.');
end

records = repmat(emptyRecord(), 1, numel(presets) * numel(seeds));
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        presetName = presets{presetIdx};
        seed = seeds(seedIdx);
        fprintf('V49 ring-safe headroom %d/%d: %s seed=%d\n', ...
            cursor, numel(records), presetName, seed);
        [context, metadata] = ...
            buildFormationIndexEquivariantGeometryDevelopmentContext( ...
                presetName, seed);
        [referenceAdjacency, policy] = ...
            selectIndexEquivariantFormationBackbonePolicy( ...
                context, struct('dominantWeight', 0.70, ...
                    'residualWeight', 0.05));
        reference = struct( ...
            'dominantAdjacency', logical(policy.dominantAdjacency), ...
            'residualAdjacency', logical(policy.residualAdjacency), ...
            'referenceAdjacency', logical(referenceAdjacency), ...
            'referenceFusionWeights', policy.fusionWeightMatrix);
        [routeContext, routeContextContract] = ...
            buildFormationB4V49GraphOnlyRouteContext(context);
        [cycleReference, routeDetails] = ...
            selectFormationB4V49CyclePreservingReference( ...
                routeContext, reference, struct( ...
                    'minimumRelativeImprovementVsIncumbent', ...
                        minimumRouteImprovement, ...
                    'cycleSelectionMode', selectionMode, ...
                    'maximumExactProposalEvaluations', ...
                        maximumExactProposalEvaluations, ...
                    'pulsePhaseMode', pulsePhaseMode));
        [scheduleContext, scheduleContextContract] = ...
            buildFormationB4V48GraphOnlyContext(context);
        deferDetails = struct();
        if routeDetails.selectedIsCyclePreservingReference && ...
                includeDeferAblation
            [~, ~, deferDetails] = ...
                buildFormationB4V49RingSafeDeferSchedule( ...
                    scheduleContext, cycleReference, struct( ...
                        'minimumRelativeImprovementVsBestSynchronized', ...
                        0, 'pulsePhase', ...
                        routeDetails. ...
                            selectedBestSynchronizedPulsePhase));
            if abs(deferDetails.bestSynchronizedB4SquaredFactor - ...
                    routeDetails.selectedSquaredFactor) > 1e-12
                error('FormationB4V49Headroom:ComparatorDrift', ...
                    'The route and defer stages disagree on sync B4.');
            end
            finalFactor = deferDetails.selectedSquaredFactor;
            deferIncrementalImprovement = ...
                deferDetails. ...
                    selectedRelativeSquaredFactorImprovementVsBestSynchronized;
            deferredCrossEdgeCount = ...
                deferDetails.selectedDeferredCrossEdgeCount;
            mandatoryCycleOrdinal = ...
                deferDetails.selectedMandatoryCycleOrdinal;
            messageCountByPhase = deferDetails.messageCountByPhase;
            burstSensorStrong = ...
                deferDetails.burstSensorStrongConnected;
            burstFormationStrong = ...
                deferDetails.burstFormationStrongConnected;
            scheduleHash = deferDetails.canonicalSha256;
        else
            finalFactor = routeDetails.selectedSquaredFactor;
            deferIncrementalImprovement = 0;
            deferredCrossEdgeCount = 0;
            mandatoryCycleOrdinal = 0;
            messageCountByPhase = syncMessageCountByPhase( ...
                metadata.nodeCount, ...
                routeDetails.selectedBestSynchronizedPulsePhase);
            burstSensorStrong = true;
            burstFormationStrong = true;
            scheduleHash = '';
        end
        item = emptyRecord();
        item.presetName = presetName;
        item.seed = seed;
        item.currentTime = metadata.currentTime;
        item.nodeCount = metadata.nodeCount;
        item.formationCount = metadata.formationCount;
        item.incumbentBestSynchronizedSquaredFactor = ...
            routeDetails.incumbentBestSynchronizedSquaredFactor;
        item.rawBestCycleSquaredFactor = ...
            routeDetails.rawBestCycleSquaredFactor;
        item.rawBestCycleRelativeImprovementVsIncumbent = ...
            routeDetails.rawBestCycleRelativeImprovementVsIncumbent;
        item.selectedCyclePreservingReference = ...
            routeDetails.selectedIsCyclePreservingReference;
        item.routeMaterialityGateTriggered = ...
            routeDetails.materialityGateTriggered;
        item.cycleSelectionMode = routeDetails.cycleSelectionMode;
        item.selectedRouteSquaredFactor = ...
            routeDetails.selectedSquaredFactor;
        item.selectedRouteRelativeImprovementVsIncumbent = ...
            routeDetails.selectedRelativeImprovementVsIncumbent;
        item.selectedBestSynchronizedPulsePhase = ...
            routeDetails.selectedBestSynchronizedPulsePhase;
        item.deferIncrementalRelativeImprovement = ...
            deferIncrementalImprovement;
        item.deferAblationExecuted = ...
            routeDetails.selectedIsCyclePreservingReference && ...
                includeDeferAblation;
        item.finalSquaredFactor = finalFactor;
        item.finalRelativeImprovementVsIncumbent = ...
            safeRelativeImprovement( ...
                item.incumbentBestSynchronizedSquaredFactor, ...
                finalFactor);
        item.selectedDeferredCrossEdgeCount = deferredCrossEdgeCount;
        item.selectedMandatoryCycleOrdinal = mandatoryCycleOrdinal;
        item.physicalCycleCandidateCount = ...
            routeDetails.physicalCycleCandidateCount;
        item.feasibleCycleCandidateCount = ...
            routeDetails.feasibleCycleCandidateCount;
        item.messageCountByPhase = messageCountByPhase;
        item.burstSensorStrongConnected = burstSensorStrong;
        item.burstFormationStrongConnected = burstFormationStrong;
        item.sameDirectedReferenceMessageBudget = ...
            routeDetails.sameDirectedReferenceMessageBudget;
        item.routeCanonicalSha256 = routeDetails.canonicalSha256;
        item.scheduleCanonicalSha256 = scheduleHash;
        item.routeContextCanonicalSha256 = ...
            routeContextContract.canonicalSha256;
        item.scheduleContextCanonicalSha256 = ...
            scheduleContextContract.canonicalSha256;
        records(cursor) = item;
        fprintf(['  incumbent=%.9g cycle=%.9g routeGain=%+.3f%% ', ...
            'final=%.9g totalGain=%+.3f%% deferGain=%+.3f%% ', ...
            'deferred=%d/%d cycles=%d/%d messages=%s\n'], ...
            item.incumbentBestSynchronizedSquaredFactor, ...
            item.selectedRouteSquaredFactor, ...
            100 * item.selectedRouteRelativeImprovementVsIncumbent, ...
            item.finalSquaredFactor, ...
            100 * item.finalRelativeImprovementVsIncumbent, ...
            100 * item.deferIncrementalRelativeImprovement, ...
            item.selectedDeferredCrossEdgeCount, ...
            item.formationCount, ...
            item.feasibleCycleCandidateCount, ...
            item.physicalCycleCandidateCount, ...
            mat2str(item.messageCountByPhase));
    end
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v49-cycle-preserving-headroom-v2';
payload.presets = presets;
payload.seeds = seeds;
payload.cycleSelectionMode = selectionMode;
payload.maximumExactProposalEvaluations = ...
    maximumExactProposalEvaluations;
payload.minimumRouteImprovementVsIncumbent = ...
    minimumRouteImprovement;
payload.includeDeferAblation = includeDeferAblation;
payload.pulsePhaseMode = pulsePhaseMode;
payload.records = records;
payload.caseCount = numel(records);
payload.cycleSelectedCaseCount = nnz( ...
    [records.selectedCyclePreservingReference]);
payload.nontrivialCaseCount = nnz( ...
    [records.selectedDeferredCrossEdgeCount] > 0);
payload.positiveHeadroomCaseCount = nnz( ...
    [records.finalRelativeImprovementVsIncumbent] > 1e-6);
payload.allSameDirectedReferenceMessageBudget = ...
    all([records.sameDirectedReferenceMessageBudget]);
payload.allBurstSensorStrongConnected = ...
    all([records.burstSensorStrongConnected]);
payload.allBurstFormationStrongConnected = ...
    all([records.burstFormationStrongConnected]);
payload.posteriorUsed = false;
payload.truthUsed = false;
payload.measurementUsed = false;
payload.futureOutcomeUsed = false;
payload.realizedDeliveryUniformsUsed = false;
payload.trackingOutcomeScored = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
result = payload;
fprintf(['V49 ring-safe headroom complete: nontrivial=%d/%d ', ...
    'cycle=%d/%d positive=%d/%d sha256=%s\n'], ...
    result.nontrivialCaseCount, result.caseCount, ...
    result.cycleSelectedCaseCount, result.caseCount, ...
    result.positiveHeadroomCaseCount, result.caseCount, ...
    result.canonicalSha256);
end

function item = emptyRecord()
item = struct('presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'nodeCount', NaN, 'formationCount', NaN, ...
    'incumbentBestSynchronizedSquaredFactor', NaN, ...
    'rawBestCycleSquaredFactor', NaN, ...
    'rawBestCycleRelativeImprovementVsIncumbent', NaN, ...
    'selectedCyclePreservingReference', false, ...
    'routeMaterialityGateTriggered', false, ...
    'cycleSelectionMode', '', ...
    'selectedRouteSquaredFactor', NaN, ...
    'selectedRouteRelativeImprovementVsIncumbent', NaN, ...
    'selectedBestSynchronizedPulsePhase', NaN, ...
    'deferIncrementalRelativeImprovement', NaN, ...
    'deferAblationExecuted', false, ...
    'finalSquaredFactor', NaN, ...
    'finalRelativeImprovementVsIncumbent', NaN, ...
    'selectedDeferredCrossEdgeCount', NaN, ...
    'selectedMandatoryCycleOrdinal', NaN, ...
    'physicalCycleCandidateCount', NaN, ...
    'feasibleCycleCandidateCount', NaN, ...
    'messageCountByPhase', zeros(1, 0), ...
    'burstSensorStrongConnected', false, ...
    'burstFormationStrongConnected', false, ...
    'sameDirectedReferenceMessageBudget', false, ...
    'routeCanonicalSha256', '', ...
    'scheduleCanonicalSha256', '', ...
    'routeContextCanonicalSha256', '', ...
    'scheduleContextCanonicalSha256', '');
end

function counts = syncMessageCountByPhase(nodeCount, pulsePhase)
counts = nodeCount * ones(1, 4);
counts(pulsePhase) = 2 * nodeCount;
end

function value = safeRelativeImprovement(reference, candidate)
if reference > 0
    value = (reference - candidate) / reference;
elseif candidate == 0
    value = 0;
else
    value = -inf;
end
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
