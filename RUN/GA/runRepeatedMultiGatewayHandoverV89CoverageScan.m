function [reportPath, result] = ...
    runRepeatedMultiGatewayHandoverV89CoverageScan(options)
% RUNREPEATEDMULTIGATEWAYHANDOVERV89COVERAGESCAN Full cached time axis.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRepeatedMultiGatewayHandoverV89Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('RepeatedMultiGatewayV89:DirtySource', ...
        'The V89 coverage scan requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

scenes = repmat(emptyScene(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    presetName = protocol.presets{presetIdx};
    expectedNodes = protocol.expectedNodeCounts(presetIdx);
    expectedFormations = protocol.expectedFormationCounts(presetIdx);
    records = repmat(emptyRecord(), 1, numel(protocol.snapshotTimes));
    for timeIdx = 1:numel(protocol.snapshotTimes)
        currentTime = protocol.snapshotTimes(timeIdx);
        state = loadFormationH3ObservableState( ...
            presetName, protocol.allSeeds, currentTime, ...
            struct('cacheRoot', cacheRoot));
        if numel(state.groupIds) ~= expectedNodes || ...
                numel(unique(state.groupIds, 'stable')) ~= ...
                    expectedFormations
            error('RepeatedMultiGatewayV89:ScaleDrift', ...
                'A V89 source state no longer matches its frozen scale.');
        end
        metrics = computeRepeatedMultiGatewayHandoverNominationsV89( ...
            state.context, state.groupIds, protocol);
        records(timeIdx) = makeRecord(metrics);
        fprintf([ ...
            'V89 %s t=%d gateways=%d formations=%s novelty=%.3f%% ', ...
            'deficit=%.3f%%\n'], ...
            presetName, currentTime, records(timeIdx).gatewayCount, ...
            mat2str(records(timeIdx).formationIds), ...
            100 * records(timeIdx).aggregateNoveltyFraction, ...
            100 * records(timeIdx).aggregateProtectedDeficitFraction);
    end
    scenes(presetIdx) = summarizeScene( ...
        presetName, protocol.allSeeds, expectedFormations, records, ...
        protocol);
end

result = struct();
result.contractVersion = ...
    'repeated-multi-gateway-handover-coverage-v89-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.scenes = scenes;
result.bothScalesCoverageGatePassed = ...
    all([scenes.coverageGatePassed]);
result.fullEpisodeImplementationAuthorized = ...
    result.bothScalesCoverageGatePassed;
result.routeExecutionAuthorized = false;
result.trackingOutcomeRead = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_COVERAGE.mat');
reportPath = fullfile(outputRoot, ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_COVERAGE.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V89 repeated multi-gateway coverage: %s\n', reportPath);
end

function record = makeRecord(metrics)
record = emptyRecord();
record.currentTime = metrics.currentTime;
record.gatewayCount = metrics.selectedGatewayCount;
record.gatewayIndices = metrics.selectedGatewayIndices;
record.formationIds = metrics.selectedFormationIds;
record.formationCoverageFraction = ...
    metrics.selectedFormationCoverageFraction;
record.sourceIndices = [metrics.selectedGateways.candidateSenderIdx];
record.aggregateNoveltyFraction = ...
    metrics.aggregateSenderNoveltyFraction;
record.aggregateProtectedDeficitFraction = ...
    metrics.aggregateProtectedSupportDeficitFraction;
record.maximumGatewayNoveltyFraction = finiteMax( ...
    [metrics.selectedGateways.senderNoveltyFraction]);
record.metrics = metrics;
end

function scene = summarizeScene( ...
        presetName, seed, formationCount, records, protocol)
counts = [records.gatewayCount];
active = counts > 0;
covered = unique([records(active).formationIds], 'stable');
scene = emptyScene();
scene.presetName = presetName;
scene.seed = seed;
scene.formationCount = formationCount;
scene.records = records;
scene.actionableTimes = [records(active).currentTime];
scene.actionableTimeCount = nnz(active);
scene.actionableTimeFraction = mean(active);
scene.multiGatewayTimes = ...
    [records(counts >= 2).currentTime];
scene.multiGatewayTimeCount = nnz(counts >= 2);
scene.maximumSimultaneousGatewayCount = max(counts);
scene.distinctCoveredFormationIds = covered;
scene.distinctCoveredFormationFraction = ...
    numel(covered) / formationCount;
scene.meanActiveFormationCoverageFraction = meanOrZero( ...
    [records(active).formationCoverageFraction]);
scene.totalGatewayActions = sum(counts);
scene.coverageGatePassed = ...
    scene.actionableTimeFraction >= ...
        protocol.minimumActionableTimeFraction - 1e-12 && ...
    scene.multiGatewayTimeCount >= ...
        protocol.minimumMultiGatewayTimeCount && ...
    scene.distinctCoveredFormationFraction >= ...
        protocol.minimumDistinctCoveredFormationFraction - 1e-12;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('RepeatedMultiGatewayV89:WriteFailed', ...
        'Could not create the V89 coverage report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V89 repeated multi-gateway handover coverage\n\n');
fprintf(fid, ['| Scale | Active times | Active fraction | ', ...
    'Multi-gateway times | Max simultaneous | Distinct formations | ', ...
    'Mean active coverage | Total gateway actions | Gate |\n']);
fprintf(fid, ...
    '|:--|--:|--:|--:|--:|:--|--:|--:|:--:|\n');
for scene = result.scenes
    fprintf(fid, ...
        '| %s | %d/%d | %.1f%% | %d | %d | `%s` | %.1f%% | %d | %d |\n', ...
        scene.presetName, scene.actionableTimeCount, ...
        numel(scene.records), 100 * scene.actionableTimeFraction, ...
        scene.multiGatewayTimeCount, ...
        scene.maximumSimultaneousGatewayCount, ...
        mat2str(scene.distinctCoveredFormationIds), ...
        100 * scene.meanActiveFormationCoverageFraction, ...
        scene.totalGatewayActions, scene.coverageGatePassed);
end
fprintf(fid, '\n## Time-resolved nominations\n\n');
for scene = result.scenes
    fprintf(fid, '### %s\n\n', scene.presetName);
    fprintf(fid, ['| Time | Gateways | Receiver formations | Sources | ', ...
        'Novelty | Protected deficit |\n']);
    fprintf(fid, '|--:|:--|:--|:--|--:|--:|\n');
    for record = scene.records
        fprintf(fid, '| %d | `%s` | `%s` | `%s` | %.3f%% | %.3f%% |\n', ...
            record.currentTime, mat2str(record.gatewayIndices), ...
            mat2str(record.formationIds), ...
            mat2str(record.sourceIndices), ...
            100 * record.aggregateNoveltyFraction, ...
            100 * record.aggregateProtectedDeficitFraction);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '- Both scales pass the coverage gate: `%d`\n', ...
    result.bothScalesCoverageGatePassed);
fprintf(fid, '- Full-episode implementation authorized: `%d`\n', ...
    result.fullEpisodeImplementationAuthorized);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route execution authorized: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'gatewayCount', 0, ...
    'gatewayIndices', zeros(1, 0), ...
    'formationIds', zeros(1, 0), ...
    'sourceIndices', zeros(1, 0), ...
    'formationCoverageFraction', 0, ...
    'aggregateNoveltyFraction', 0, ...
    'aggregateProtectedDeficitFraction', 0, ...
    'maximumGatewayNoveltyFraction', 0, ...
    'metrics', struct());
end

function value = emptyScene()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'formationCount', NaN, ...
    'records', repmat(emptyRecord(), 1, 0), ...
    'actionableTimes', zeros(1, 0), ...
    'actionableTimeCount', 0, ...
    'actionableTimeFraction', 0, ...
    'multiGatewayTimes', zeros(1, 0), ...
    'multiGatewayTimeCount', 0, ...
    'maximumSimultaneousGatewayCount', 0, ...
    'distinctCoveredFormationIds', zeros(1, 0), ...
    'distinctCoveredFormationFraction', 0, ...
    'meanActiveFormationCoverageFraction', 0, ...
    'totalGatewayActions', 0, ...
    'coverageGatePassed', false);
end

function value = finiteMax(values)
values = reshape(values, 1, []);
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = max(values);
end
end

function value = meanOrZero(values)
values = reshape(values, 1, []);
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = mean(values);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
