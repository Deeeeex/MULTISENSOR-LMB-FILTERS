function audit = ...
    auditFormationIndexEquivariantRouteV43DevelopmentEvidence()
% AUDIT...EVIDENCE Post-hoc freeze audit for the committed 32-case batch.

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
relativeDirectory = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'formation_value_v43', ...
    'index_equivariant_route_development_v1');
matRelativePath = fullfile(relativeDirectory, ...
    'FORMATION_INDEX_EQUIVARIANT_ROUTE_V43_DEVELOPMENT_V1.mat');
reportRelativePath = fullfile(relativeDirectory, ...
    'FORMATION_INDEX_EQUIVARIANT_ROUTE_V43_DEVELOPMENT_V1.md');
matPath = fullfile(repoRoot, matRelativePath);
reportPath = fullfile(repoRoot, reportRelativePath);

expected = struct( ...
    'generationCommit', ...
        '1bf79e9120526782447e4058d2355542af2c7e75', ...
    'protocolSha256', ...
        '4eae77976aa8b5b6cd2722b09a3909dbf8b2bce45eb2e464a54ed45a1c84aa03', ...
    'resultCanonicalSha256', ...
        '545e94d4f1f7b6a682a3188a3b135ae8bc0e0031b85c843ee7cfba1c2a40a6f2', ...
    'executableManifestCanonicalSha256', ...
        'cce8f95ac4cb535d3f59ebe3a02be32dd091af7a5001b4905f45d47fb50a484b', ...
    'matFileSha256', ...
        'c46552b5f42363faa5491df3f720f748b9505ba976c84355cfe64fb3f9c00914', ...
    'reportFileSha256', ...
        '7e48805af496f8fd5dbb8c71f6b92d793bc959e1d1058fe279c180a94498c888');

if exist(matPath, 'file') ~= 2 || exist(reportPath, 'file') ~= 2
    error('FormationIndexEquivariantV43Audit:ArtifactMissing', ...
        'The frozen v43 evidence artifacts are missing.');
end
matFileSha256 = computeFileSha256(matPath);
reportFileSha256 = computeFileSha256(reportPath);
artifactFilesShaPinned = ...
    strcmp(matFileSha256, expected.matFileSha256) && ...
    strcmp(reportFileSha256, expected.reportFileSha256);

loaded = load(matPath);
if ~isfield(loaded, 'result') || ~isstruct(loaded.result) || ...
        ~isscalar(loaded.result)
    error('FormationIndexEquivariantV43Audit:ArtifactMalformed', ...
        'The v43 MAT artifact lacks one scalar result.');
end
result = loaded.result;
resultPayload = rmfield(result, 'canonicalSha256');
recomputedResultSha256 = ...
    computeCanonicalValueSha256(resultPayload);
resultCanonicalShaRecomputed = ...
    strcmp(recomputedResultSha256, result.canonicalSha256) && ...
    strcmp(result.canonicalSha256, expected.resultCanonicalSha256);

protocol = getFormationIndexEquivariantRouteV43DevelopmentProtocol();
protocolShaMatched = ...
    strcmp(protocol.canonicalSha256, expected.protocolSha256) && ...
    strcmp(result.protocolCanonicalSha256, expected.protocolSha256);
generationCommitPinned = ...
    strcmp(result.generationGitCommit, expected.generationCommit) && ...
    strcmp(result.endingGitCommit, expected.generationCommit) && ...
    ~result.generationGitDirty && ~result.endingGitDirty && ...
    isAncestor(repoRoot, expected.generationCommit, 'HEAD');

manifest = result.executableSourceManifest;
manifestPayload = rmfield(manifest, 'canonicalSha256');
manifestCanonicalRecomputed = strcmp( ...
    computeCanonicalValueSha256(manifestPayload), ...
    manifest.canonicalSha256);
manifestBoundToGenerationCommit = ...
    verifyManifestAgainstCommit(repoRoot, manifest, ...
        expected.generationCommit);
executableManifestShaPinned = ...
    manifestCanonicalRecomputed && manifestBoundToGenerationCommit && ...
    strcmp(manifest.canonicalSha256, ...
        expected.executableManifestCanonicalSha256);

reportText = fileread(reportPath);
reportIdentityMatched = ...
    hasText(reportText, expected.generationCommit) && ...
    hasText(reportText, expected.protocolSha256) && ...
    hasText(reportText, expected.resultCanonicalSha256) && ...
    hasText(reportText, expected.executableManifestCanonicalSha256);

caseCanonicalHashesPassed = true;
for caseIdx = 1:numel(result.cases)
    item = result.cases(caseIdx);
    expectedCaseSha256 = item.canonicalSha256;
    item.canonicalSha256 = '';
    caseCanonicalHashesPassed = caseCanonicalHashesPassed && ...
        strcmp(computeCanonicalValueSha256(item), ...
            expectedCaseSha256);
end
resultUidHashes = ...
    {result.cases.physicalUidRegistryCanonicalSha256};
registeredUidHashes = ...
    {protocol.registeredCases.physicalUidRegistryCanonicalSha256};
registeredCasesMatched = ...
    numel(result.cases) == numel(protocol.registeredCases) && ...
    isequal({result.cases.caseId}, ...
        {protocol.registeredCases.caseId}) && ...
    all(strcmp({result.cases.inputCanonicalSha256}, ...
        {protocol.registeredCases.inputCanonicalSha256})) && ...
    all(strcmp(resultUidHashes, registeredUidHashes));

auditRelativePath = fullfile('RUN', 'GA', ...
    'auditFormationIndexEquivariantRouteV43DevelopmentEvidence.m');
testRelativePath = fullfile('tests', ...
    'test_formation_index_equivariant_route_v43_evidence_audit.m');
independentAuditCommitted = ...
    trackedAndHeadMatched(repoRoot, auditRelativePath) && ...
    trackedAndHeadMatched(repoRoot, testRelativePath) && ...
    trackedAndHeadMatched(repoRoot, matRelativePath) && ...
    trackedAndHeadMatched(repoRoot, reportRelativePath);
auditSourceClean = isCleanWorktree(repoRoot);

postHocEvidence = struct( ...
    'contractVersion', ...
        ['formation-index-equivariant-route-v43-', ...
         'posthoc-freeze-evidence-v1'], ...
    'generationCommitPinned', generationCommitPinned, ...
    'protocolShaMatched', protocolShaMatched, ...
    'resultCanonicalShaRecomputed', ...
        resultCanonicalShaRecomputed, ...
    'executableManifestShaPinned', ...
        executableManifestShaPinned, ...
    'artifactFilesShaPinned', artifactFilesShaPinned, ...
    'independentAuditCommitted', independentAuditCommitted, ...
    'auditSourceClean', auditSourceClean);
execution = struct( ...
    'registeredBatchComplete', result.registeredBatchComplete, ...
    'cleanSourceEvidence', result.cleanSourceEvidence, ...
    'postHocExecutableFreezeEvidence', postHocEvidence);
auditedGate = ...
    evaluateFormationIndexEquivariantRouteV43DevelopmentGate( ...
        result.cases, execution, protocol);

audit = struct();
audit.contractVersion = ...
    'formation-index-equivariant-route-v43-posthoc-audit-v1';
audit.expected = expected;
audit.matRelativePath = matRelativePath;
audit.reportRelativePath = reportRelativePath;
audit.matFileSha256 = matFileSha256;
audit.reportFileSha256 = reportFileSha256;
audit.recomputedResultCanonicalSha256 = recomputedResultSha256;
audit.reportIdentityMatched = reportIdentityMatched;
audit.caseCanonicalHashesPassed = caseCanonicalHashesPassed;
audit.registeredCasesMatched = registeredCasesMatched;
audit.postHocExecutableFreezeEvidence = postHocEvidence;
audit.auditedGate = auditedGate;
audit.routeReferenceAdvancePassed = ...
    auditedGate.routeReferenceAdvancePassed;
audit.trackingAdvancePassed = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This post-hoc audit accepts the frozen v43 route reference as ', ...
    'development structural evidence only. It does not authorize ', ...
    'tracking, sparse communication gain, or validation claims.'];
audit.passed = artifactFilesShaPinned && ...
    resultCanonicalShaRecomputed && protocolShaMatched && ...
    generationCommitPinned && executableManifestShaPinned && ...
    reportIdentityMatched && caseCanonicalHashesPassed && ...
    registeredCasesMatched && independentAuditCommitted && ...
    auditSourceClean && audit.routeReferenceAdvancePassed && ...
    ~audit.trackingAdvancePassed && ~audit.validationClaimAllowed;
audit.canonicalSha256 = computeCanonicalValueSha256(audit);
if ~audit.passed
    error('FormationIndexEquivariantV43Audit:Failed', ...
        'The committed v43 post-hoc evidence audit failed closed.');
end
fprintf(['V43 post-hoc audit PASS: result=%s audit=%s ', ...
    'M24=%.6f X36=%.6f\n'], ...
    result.canonicalSha256, audit.canonicalSha256, ...
    result.m24NonCrossingMedianTargetHorizonRatio, ...
    result.x36NonCrossingMedianTargetHorizonRatio);
end

function passed = verifyManifestAgainstCommit(repoRoot, manifest, commit)
required = {'records', 'canonicalSha256', ...
    'allEntriesTrackedByHead', 'allWorkingFilesMatchHead', ...
    'pathResolutionPassed'};
if ~all(isfield(manifest, required)) || ...
        ~manifest.allEntriesTrackedByHead || ...
        ~manifest.allWorkingFilesMatchHead || ...
        ~manifest.pathResolutionPassed
    passed = false;
    return;
end
passed = true;
for recordIdx = 1:numel(manifest.records)
    record = manifest.records(recordIdx);
    [status, blobId] = gitCommand(repoRoot, sprintf( ...
        'rev-parse "%s:%s"', commit, record.relativePath));
    passed = passed && status == 0 && record.trackedByHead && ...
        record.workingFileMatchesHead && ...
        strcmp(strtrim(blobId), record.headBlobId) && ...
        strcmp(record.workingBlobId, record.headBlobId);
end
end

function passed = trackedAndHeadMatched(repoRoot, relativePath)
[trackedStatus, ~] = gitCommand(repoRoot, sprintf( ...
    'ls-files --error-unmatch -- "%s"', relativePath));
[workingStatus, workingBlob] = gitCommand(repoRoot, sprintf( ...
    'hash-object -- "%s"', relativePath));
[headStatus, headBlob] = gitCommand(repoRoot, sprintf( ...
    'rev-parse "HEAD:%s"', relativePath));
passed = trackedStatus == 0 && workingStatus == 0 && ...
    headStatus == 0 && strcmp(strtrim(workingBlob), strtrim(headBlob));
end

function clean = isCleanWorktree(repoRoot)
[status, porcelain] = gitCommand(repoRoot, ...
    'status --porcelain --untracked-files=all');
clean = status == 0 && isempty(strtrim(porcelain));
end

function yes = isAncestor(repoRoot, ancestor, descendant)
[status, ~] = gitCommand(repoRoot, sprintf( ...
    'merge-base --is-ancestor %s %s', ancestor, descendant));
yes = status == 0;
end

function [status, output] = gitCommand(repoRoot, arguments)
environmentName = 'FORMATION_V43_POSTHOC_GIT_ROOT';
previousValue = getenv(environmentName);
cleanup = onCleanup(@() setenv(environmentName, previousValue)); %#ok<NASGU>
setenv(environmentName, repoRoot);
[status, output] = system(sprintf( ...
    'git -C "$%s" %s 2>/dev/null', environmentName, arguments));
end

function yes = hasText(text, pattern)
yes = ~isempty(strfind(text, pattern)); %#ok<STREMP>
end
