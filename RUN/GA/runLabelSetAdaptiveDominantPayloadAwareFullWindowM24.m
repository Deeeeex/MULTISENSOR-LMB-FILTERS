function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantPayloadAwareFullWindowM24(seed, options)
% RUNLABELSETADAPTIVEDOMINANTPAYLOADAWAREFULLWINDOWM24 Frozen M24 v2 arm.

if nargin < 1 || isempty(seed)
    seed = 17;
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol. ...
        adaptiveDominantPayloadAwareFullWindowTrainingAuthorized || ...
        ~ismember(seed, protocol. ...
            adaptiveDominantPayloadAwareFullWindowTrainingSeeds)
    error('Seed is outside frozen payload-aware full-window training.');
end
runOptions = options;
runOptions.evidenceSplit = 'training';
[reportPath, summary] = ...
    runLabelSetAdaptiveDominantPayloadAwareM24( ...
        seed, protocol. ...
            adaptiveDominantPayloadAwareSelectedMarginToken, ...
        runOptions);
end
