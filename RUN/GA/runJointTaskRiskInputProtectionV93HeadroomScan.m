    'records', repmat(emptyRecord(), 1, 0), ...
    'snapshotCount', 0, ...
    'actionableTimeCount', 0, ...
    'actionableTimeFraction', 0, ...
    'medianPositiveTaskRiskGainPercent', 0, ...
    'peakSafeTaskRiskGainPercent', 0, ...
    'minimumSafeWorstReceiverGainPercent', 0, ...
    'minimumSafeWorstFormationGainPercent', 0, ...
    'medianBestSubsetSize', 0, ...
    'maximumBestSubsetSize', 0, ...
    'totalBestMessageSavingCount', 0, ...
    'maximumDirectAuditError', 0, ...
    'headroomGatePassed', false);
end

function value = isExpectedUnavailable(errorInfo)
value = any(strcmp(errorInfo.identifier, { ...
    'FormationBundleSuspension:Infeasible', ...
    'FormationBundleSuspension:InvalidCandidate', ...
    'FormationBackboneTour:NonphysicalTour'}));
end

function value = formatSubset(ids)
if isempty(ids)
    value = '--';
    return;
end
body = sprintf('%d,', ids);
value = ['{', body(1:end-1), '}'];
end

function value = medianOrZero(values)
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = median(values);
end
end

function value = maxOrZero(values)
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = max(values);
end
end

function value = minOrZero(values)
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = min(values);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
