function result = ...
    runFormationReliableKlaWindowContractionV41DevelopmentProbe( ...
        outputDirectory, options)
% RUNFORMATIONRELIABLEKLAWINDOWCONTRACTIONV41DEVELOPMENTPROBE
% Geometry-only M24/X36 scale diagnostic.  No target process is generated.

if nargin < 1 || isempty(outputDirectory)
    outputDirectory = fullfile('RUN', 'GA', 'dynamic_topology', ...
        'evidence', 'formation_value_v41', ...
        'window_contraction_development_v1');
end
if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = {'presets', 'seeds', 'requireCleanGit'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationKlaWindowProbeRunner:InvalidOptions', ...
        'The v41 development-run options are malformed.');
end
presets = getField(options, 'presets', { ...
    'm24-formation-fov', 'x36-formation-fov'});
seeds = reshape(getField(options, 'seeds', [41, 43, 47, 53]), 1, []);
requireCleanGit = logical(getField(options, 'requireCleanGit', true));
validateInputs(outputDirectory, presets, seeds, requireCleanGit);

matPath = fullfile(outputDirectory, ...
    'FORMATION_RELIABLE_KLA_WINDOW_CONTRACTION_V41_DEVELOPMENT_V1.mat');
reportPath = fullfile(outputDirectory, ...
    'FORMATION_RELIABLE_KLA_WINDOW_CONTRACTION_V41_DEVELOPMENT_V1.md');
if exist(matPath, 'file') || exist(reportPath, 'file')
    error('FormationKlaWindowProbeRunner:OutputExists', ...
        'The v41 development output is non-overwriting.');
end
if ~exist(outputDirectory, 'dir')
    [created, message] = mkdir(outputDirectory);
    if ~created
        error('FormationKlaWindowProbeRunner:OutputCreateFailed', ...
            'The output directory could not be created: %s', message);
    end
end

[gitCommit, gitDirty] = resolveGitState();
if requireCleanGit && gitDirty
    error('FormationKlaWindowProbeRunner:DirtyGitState', ...
        'A registered development probe requires a clean worktree.');
end
protocol = getReliableKlaWindowContractionProtocol();
caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
caseCursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        caseCursor = caseCursor + 1;
        presetName = presets{presetIdx};
        seed = seeds(seedIdx);
        fprintf('V41 structural case %d/%d: %s seed %d\n', ...
            caseCursor, caseCount, presetName, seed);
        cases(caseCursor) = buildCase(presetName, seed);
    end
end

result = struct();
result.contractVersion = ...
    'formation-reliable-kla-window-contraction-development-result-v1';
result.protocolId = protocol.id;
result.protocolCanonicalSha256 = protocol.canonicalSha256;
result.generationGitCommit = gitCommit;
result.generationGitDirty = gitDirty;
result.presets = presets;
result.seeds = seeds;
result.cases = cases;
result.caseCount = caseCount;
result.groundTruthGeneratorCalled = false;
result.targetTrajectoryGeneratorCalled = false;
result.measurementGeneratorCalled = false;
result.posteriorUsed = false;
result.trackingOutcomeScored = false;
result.futureOutcomeUsed = false;
result.realizedDeliveryUniformsUsed = false;
result.fullPlannedSensorGeometryMaterialized = true;
result.fullPlannedLinkProbabilityScheduleMaterialized = true;
result.formalRuntimeObservableBoundaryPassed = false;
result.developmentEvidenceOnly = true;
result.m24TrackingAuthorized = false;
result.x36TrackingAuthorized = false;
result.validationClaimAllowed = false;
result.canonicalSha256 = computeCanonicalValueSha256(result);

save(matPath, 'result', '-mat7-binary');
writeReport(reportPath, result, matPath);
fprintf('V41 structural development probe complete: %s\n', reportPath);
end

function value = buildCase(presetName, seed)
rng(seed, 'twister');
config = buildDynamicTopologyScenarioConfig(presetName);
[sensorTrajectories, ~] = ...
    generateMultiFormationTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensorTrajectories);
[pDropByEdge, ~] = buildDynamicTopologyLinkSchedule(config, graph);
currentTime = config.focusWindow(1);
nodeCount = config.numberOfSensors;

model = struct();
model.dynamicTopologyScenario = struct( ...
    'config', struct('sensorGroupIds', config.sensorGroupIds), ...
    'staticAdjacency', graph.staticAdjacency);
context = struct();
context.model = model;
context.baseAdjacency = graph.staticAdjacency;
context.physicalAdjacency = ...
    graph.physicalAdjacency(:, :, currentTime);
context.currentTime = currentTime;
context.commConfig = struct( ...
    'forceDelivery', config.forceDelivery, ...
    'pDropByEdge', pDropByEdge(:, :, currentTime), ...
    'outageSchedule', getField(config, 'outageSchedule', []), ...
    'deliveryIndependenceAttested', true, ...
    'deliverySampler', [ ...
        'runEventTriggeredDistributedLmbFilter-simulateDelivery-', ...
        'independent-uniform-per-sender-receiver-time']);
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.previousAdjacencyHistory = ...
    buildReferenceHistory(context, nodeCount);
probe = buildFormationReliableKlaWindowContractionRouteProbe(context);
adaptiveProbe = ...
    buildFormationReliableKlaAdaptiveWindowRouteProbe(context);

inputPayload = struct( ...
    'presetName', presetName, ...
    'seed', seed, ...
    'currentTime', currentTime, ...
    'sensorGroupIds', config.sensorGroupIds, ...
    'baseAdjacency', graph.staticAdjacency, ...
    'physicalAdjacency', context.physicalAdjacency, ...
    'pDropByEdge', context.commConfig.pDropByEdge);
value = emptyCase();
value.caseId = sprintf('%s__seed%d__t%d', ...
    presetName, seed, currentTime);
value.presetName = presetName;
value.seed = seed;
value.currentTime = currentTime;
value.nodeCount = nodeCount;
value.formationCount = config.formationCount;
value.inputCanonicalSha256 = ...
    computeCanonicalValueSha256(inputPayload);
value.probe = probe;
value.adaptiveProbe = adaptiveProbe;
value.groundTruthGeneratorCalled = false;
value.targetTrajectoryGeneratorCalled = false;
value.measurementGeneratorCalled = false;
value.fullPlannedSensorGeometryMaterialized = true;
value.fullPlannedLinkProbabilityScheduleMaterialized = true;
value.developmentEvidenceOnly = true;
end

function history = buildReferenceHistory(context, nodeCount)
routeContext = context;
routeContext.localPosteriorBySensor = cell(1, nodeCount);
routeContext.directedMessageBudget = 2 * nodeCount;
[referenceAdjacency, ~] = ...
    selectFormationBackboneResidualTourPolicy(routeContext);
history = repmat(referenceAdjacency, 1, 1, 2);
end

function writeReport(path, result, matPath)
fileId = fopen(path, 'w');
if fileId < 0
    error('FormationKlaWindowProbeRunner:ReportWriteFailed', ...
        'The v41 Markdown report could not be opened.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '# V41 reliable KLA window-contraction development probe\n\n');
fprintf(fileId, '- Contract: `%s`\n', result.contractVersion);
fprintf(fileId, '- Protocol SHA-256: `%s`\n', ...
    result.protocolCanonicalSha256);
fprintf(fileId, '- Generation commit: `%s` (dirty: `%d`)\n', ...
    result.generationGitCommit, result.generationGitDirty);
fprintf(fileId, '- MAT artifact: `%s`\n', matPath);
fprintf(fileId, '- Result SHA-256: `%s`\n\n', result.canonicalSha256);
fprintf(fileId, [ ...
    'This is a geometry-only development diagnostic. It materializes ', ...
    'the complete planned sensor geometry and link-probability schedule ', ...
    'before slicing the focus-start page, so it does not satisfy the ', ...
    'formal runtime observable-input boundary. It calls no target, ', ...
    'measurement or ground-truth generator and scores no tracking ', ...
    'outcome.\n\n']);
fprintf(fileId, '## Scale calibration\n\n');
fprintf(fileId, [ ...
    '| Preset | Seed | N | N-1 | Event q beta | Event E[delta] upper ', ...
    '| rho at N-1 | first rho<1 | Calibration pass | Target H ', ...
    '| Evaluation H | rho at evaluation H |\n']);
fprintf(fileId, [ ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|:--:|--:|--:|--:|\n']);
for caseIdx = 1:numel(result.cases)
    current = result.cases(caseIdx);
    nominal = current.probe;
    event = nominal.actions(1).certificates{1};
    nominalMeanSquare = nominal.actions(1).meanSquareCertificates{1};
    adaptive = current.adaptiveProbe;
    fprintf(fileId, [ ...
        '| %s | %d | %d | %d | %.4g | %.10f | %.10f | %g ', ...
        '| %d | %g | %d | %.10f |\n'], ...
        current.presetName, current.seed, current.nodeCount, ...
        nominal.horizon, event.expectedContractionGainLowerBound, ...
        event.expectedDobrushinUpperBound, ...
        nominalMeanSquare.worstCaseExpectedSquaredContractionFactor, ...
        adaptive.referenceHorizonProfile.firstStrictContractionHorizon, ...
        adaptive.calibrationPassed, adaptive.targetHorizon, ...
        adaptive.evaluationHorizon, ...
        adaptive.referenceSquaredFactorAtEvaluationHorizon);
end

fprintf(fileId, '\n## Adaptive-window route comparison\n\n');
fprintf(fileId, [ ...
    '| Preset | Seed | N | H | Action | Missing mode ', ...
    '| Operational? | Messages | Window messages ', ...
    '| Delta window messages ', ...
    '| Cross mass | MS rho ', ...
    '| rho/ref | delta rho | Strict rho<1 |\n']);
fprintf(fileId, [ ...
    '|:--|--:|--:|--:|:--|:--|:--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for caseIdx = 1:numel(result.cases)
    current = result.cases(caseIdx);
    adaptive = current.adaptiveProbe;
    probe = adaptive.routeProbe;
    for actionIdx = 1:numel(probe.actions)
        action = probe.actions(actionIdx);
        if ~action.available
            continue;
        end
        for modeIdx = 1:numel(probe.missingNeighborWeightModes)
            meanSquare = action.meanSquareCertificates{modeIdx};
            operational = 'no';
            if probe.operationalMissingNeighborWeightModeMask(modeIdx)
                operational = 'yes';
            end
            fprintf(fileId, [ ...
                '| %s | %d | %d | %d | %s | %s | %s | %d | %d | %+d ', ...
                '| %.4g | %.10f | %.6f | %+.6f | %d |\n'], ...
                current.presetName, current.seed, current.nodeCount, ...
                adaptive.evaluationHorizon, ...
                action.actionName, ...
                probe.missingNeighborWeightModes{modeIdx}, ...
                operational, ...
                action.directedMessageCount, ...
                action.windowDirectedMessageCount, ...
                action.incrementalWindowDirectedMessageCount, ...
                action.totalCrossFormationFusionWeight, ...
                meanSquare.worstCaseExpectedSquaredContractionFactor, ...
                action.referenceMeanSquareFactorRatioByMode(modeIdx), ...
                action.referenceMeanSquareFactorDeltaByMode(modeIdx), ...
                meanSquare.strictMeanSquareContractionCertified);
        end
    end
end
fprintf(fileId, '\n## Claim boundary\n\n');
fprintf(fileId, [ ...
    '- `formalRuntimeObservableBoundaryPassed=false`; this artifact is ', ...
    'not a policy permit.\n', ...
    '- H counts successive online fusion updates (one per tracking ', ...
    'step), not extra within-step rounds. The current reliability page ', ...
    'is repeated as a causal development approximation.\n', ...
    '- The bound concerns propagation of existing exact KLA set-density ', ...
    'log-ratio disagreement under common support.\n', ...
    '- Marginal existence log odds, local Bayes updates, label loss, ', ...
    'mixture approximation and pruning require disturbance control.\n', ...
    '- M24/X36 tracking and validation remain unauthorized.\n']);
end

function value = emptyCase()
value = struct( ...
    'caseId', '', 'presetName', '', 'seed', nan, ...
    'currentTime', nan, 'nodeCount', nan, 'formationCount', nan, ...
    'inputCanonicalSha256', '', 'probe', struct(), ...
    'adaptiveProbe', struct(), ...
    'groundTruthGeneratorCalled', false, ...
    'targetTrajectoryGeneratorCalled', false, ...
    'measurementGeneratorCalled', false, ...
    'fullPlannedSensorGeometryMaterialized', true, ...
    'fullPlannedLinkProbabilityScheduleMaterialized', true, ...
    'developmentEvidenceOnly', true);
end

function [commit, dirty] = resolveGitState()
[status, commit] = system('git rev-parse HEAD');
if status ~= 0
    error('FormationKlaWindowProbeRunner:GitStateUnavailable', ...
        'The generation commit could not be resolved.');
end
commit = strtrim(commit);
[status, porcelain] = system('git status --porcelain');
if status ~= 0
    error('FormationKlaWindowProbeRunner:GitStateUnavailable', ...
        'The generation worktree state could not be resolved.');
end
dirty = ~isempty(strtrim(porcelain));
end

function validateInputs(outputDirectory, presets, seeds, requireCleanGit)
if ~(ischar(outputDirectory) && ~isempty(outputDirectory)) || ...
        ~iscell(presets) || isempty(presets) || ...
        any(~cellfun(@ischar, presets)) || ...
        ~isnumeric(seeds) || ~isreal(seeds) || isempty(seeds) || ...
        any(~isfinite(seeds)) || any(seeds ~= round(seeds)) || ...
        numel(unique(seeds)) ~= numel(seeds) || ...
        ~isscalar(requireCleanGit)
    error('FormationKlaWindowProbeRunner:InvalidOptions', ...
        'The v41 development-run inputs are invalid.');
end
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
