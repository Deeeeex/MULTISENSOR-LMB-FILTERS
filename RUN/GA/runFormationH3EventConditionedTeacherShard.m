function [reportPath, shard] = ...
    runFormationH3EventConditionedTeacherShard( ...
        presetName, seed, options)
% RUNFORMATIONH3EVENTCONDITIONEDTEACHERSHARD One v14 M24 shard.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getFormationH3EventConditionedProtocol();
if ~ischar(presetName) || ...
        ~ismember(presetName, protocol.presets) || ...
        ~isscalar(seed) || ~ismember(seed, protocol.allSeeds)
    error('Formation H=3 event teacher request violates protocol.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 event teacher requires clean source.');
end

outputRoot = getField(options, 'outputDirectory', protocol.shardRoot);
seedDirectory = fullfile( ...
    outputRoot, presetName, sprintf('seed%d', seed));
shardPath = fullfile(seedDirectory, sprintf( ...
    'formation_h3_event_teacher_%s_seed%d_v1.mat', ...
    strrep(presetName, '-', '_'), seed));
reportPath = fullfile(seedDirectory, sprintf( ...
    'FORMATION_H3_EVENT_TEACHER_%s_SEED%d_V1.md', ...
    upper(strrep(presetName, '-', '_')), seed));
shardExists = exist(shardPath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(shardExists, reportExists)
    error('Formation H=3 event teacher artifact set is partial.');
elseif shardExists
    loaded = load(shardPath, 'shard');
    if ~isfield(loaded, 'shard') || ...
            ~strcmp(loaded.shard.protocolId, protocol.id) || ...
            ~strcmp(loaded.shard.generationGitCommit, gitState.commit) || ...
            ~strcmp(loaded.shard.presetName, presetName) || ...
            loaded.shard.seed ~= seed
        error('Formation H=3 existing event shard provenance mismatch.');
    end
    shard = loaded.shard;
    fprintf('Reused formation H=3 event teacher shard: %s\n', ...
        shardPath);
    return;
end

[manifestReport, manifest] = ...
    selectFormationH3EventConditionedStates( ...
        presetName, seed, struct( ...
            'manifestRoot', protocol.manifestRoot));
snapshotTimes = manifest.selectedTimes;
localReports = cell(1, numel(snapshotTimes));
pairReports = localReports;
localScreens = localReports;
pairScreens = localReports;
strictAudits = localReports;
for timeIdx = 1:numel(snapshotTimes)
    currentTime = snapshotTimes(timeIdx);
    localDirectory = fullfile(seedDirectory, ...
        sprintf('t%d', currentTime), 'local');
    pairDirectory = fullfile(seedDirectory, ...
        sprintf('t%d', currentTime), 'pair');
    commonOptions = struct( ...
        'cacheRoot', protocol.cacheRoot, ...
        'outputDirectory', localDirectory);
    [localReports{timeIdx}, localScreens{timeIdx}] = ...
        runFormationModeH3OpenedReturnScreen( ...
            presetName, seed, currentTime, commonOptions);
    pairOptions = commonOptions;
    pairOptions.outputDirectory = pairDirectory;
    [pairReports{timeIdx}, pairScreens{timeIdx}] = ...
        runFormationPairH3OpenedReturnScreen( ...
            presetName, seed, currentTime, pairOptions);
    assertState( ...
        localScreens{timeIdx}, pairScreens{timeIdx}, ...
        manifest.selectedCachePaths{timeIdx}, ...
        protocol, presetName, seed, currentTime);
    strictAudits{timeIdx} = ...
        computeFormationH3StrictOracleAudit( ...
            localScreens{timeIdx}, pairScreens{timeIdx});
end

strictOracleGains = cellfun( ...
    @(item) item.oracleGainPercent, strictAudits);
shard = struct();
shard.contractVersion = ...
    'formation-h3-event-conditioned-teacher-shard-v1';
shard.protocolId = protocol.id;
shard.generatedAt = datestr(now, 31);
shard.generationGitCommit = gitState.commit;
shard.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
shard.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
shard.presetName = presetName;
shard.seed = seed;
shard.evidenceSplit = manifest.evidenceSplit;
shard.manifestPath = manifest.manifestPath;
shard.manifestReport = manifestReport;
shard.manifestSelectedTimes = snapshotTimes;
shard.manifestSelectedScores = manifest.selectedScores;
shard.snapshotTimes = snapshotTimes;
shard.cachePaths = manifest.selectedCachePaths;
shard.cacheSha256 = manifest.selectedCacheSha256;
shard.localReports = localReports;
shard.pairReports = pairReports;
shard.localScreens = localScreens;
shard.pairScreens = pairScreens;
shard.strictAudits = strictAudits;
shard.strictOracleGainsPercent = strictOracleGains;
shard.positiveStrictStateCount = ...
    nnz(strictOracleGains > 1e-12);
shard.strongStrictStateCount = ...
    nnz(strictOracleGains >= ...
        protocol.strongGainThresholdPercent - 1e-12);
shard.meanStrictOracleGainPercent = mean(strictOracleGains);
shard.expectedFormationCount = ...
    protocol.expectedFormationCounts;
shard.expectedLocalActionCount = ...
    protocol.expectedLocalActionCounts;
shard.expectedPairActionCount = ...
    protocol.expectedPairActionCounts;
shard.expectedAugmentedActionCount = ...
    protocol.expectedAugmentedActionCounts;
shard.eventSelectionUsesTruth = false;
shard.eventSelectionUsesFutureMeasurements = false;
shard.eventSelectionUsesFutureLinkOutcomes = false;
shard.targetsUseTruth = true;
shard.targetsUseFutureMeasurements = true;
shard.openedSentinelDevelopmentOnly = true;
shard.finalModelTrainingAuthorized = false;
shard.validationClaimAllowed = false;
shard.evidenceBoundary = protocol.evidenceBoundary;
shard.shardPath = shardPath;
shard.reportPath = reportPath;

if exist(seedDirectory, 'dir') ~= 7
    mkdir(seedDirectory);
end
save('-mat7-binary', shardPath, 'shard');
writeReport(reportPath, shard);
fprintf('Formation H=3 event teacher shard: %s\n', shardPath);
end

function assertState( ...
        localScreen, pairScreen, cachePath, protocol, ...
        presetName, seed, currentTime)
if localScreen.seed ~= seed || pairScreen.seed ~= seed || ...
        localScreen.currentTime ~= currentTime || ...
        pairScreen.currentTime ~= currentTime || ...
        ~strcmp(localScreen.presetName, presetName) || ...
        ~strcmp(pairScreen.presetName, presetName) || ...
        ~strcmp(localScreen.generationGitCommit, ...
            pairScreen.generationGitCommit) || ...
        ~strcmp(localScreen.cacheSha256, ...
            computeFileSha256(cachePath)) || ...
        ~strcmp(pairScreen.cacheSha256, ...
            computeFileSha256(cachePath)) || ...
        localScreen.bank.formationCount ~= ...
            protocol.expectedFormationCounts || ...
        localScreen.bank.actionCount ~= ...
            protocol.expectedLocalActionCounts || ...
        pairScreen.bank.actionCount ~= ...
            protocol.expectedPairActionCounts || ...
        numel(localScreen.records) + ...
            numel(pairScreen.records) - 1 ~= ...
                protocol.expectedAugmentedActionCounts || ...
        localScreen.featuresUseTruth || pairScreen.featuresUseTruth || ...
        localScreen.runtimePolicyUsesTruth || ...
        pairScreen.runtimePolicyUsesTruth
    error('Formation H=3 event teacher state audit failed.');
end
end

function writeReport(path, shard)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 event teacher report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 event-conditioned teacher shard\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    shard.contractVersion, shard.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    shard.generationGitCommit);
fprintf(fid, '- Preset / seed / split: `%s / %d / %s`\n', ...
    shard.presetName, shard.seed, shard.evidenceSplit);
fprintf(fid, '- Selected times / event scores: `%s / %s`\n', ...
    mat2str(shard.snapshotTimes), ...
    mat2str(shard.manifestSelectedScores, 6));
fprintf(fid, ['- Event truth / future measurement / future link use: ', ...
    '`%d / %d / %d`\n'], ...
    shard.eventSelectionUsesTruth, ...
    shard.eventSelectionUsesFutureMeasurements, ...
    shard.eventSelectionUsesFutureLinkOutcomes);
fprintf(fid, '- Strict gains: `%s`\n', ...
    mat2str(shard.strictOracleGainsPercent, 6));
fprintf(fid, '- Positive / strong / mean: `%d/%d / %d/%d / %+.3f%%`\n\n', ...
    shard.positiveStrictStateCount, numel(shard.snapshotTimes), ...
    shard.strongStrictStateCount, numel(shard.snapshotTimes), ...
    shard.meanStrictOracleGainPercent);
fprintf(fid, '| Time | Event score | Feasible | Strict action | Six targets |\n');
fprintf(fid, '|--:|--:|--:|:--|:--|\n');
for idx = 1:numel(shard.snapshotTimes)
    audit = shard.strictAudits{idx};
    fprintf(fid, '| %d | %.6f | %d/%d | %s | `%s` |\n', ...
        shard.snapshotTimes(idx), ...
        shard.manifestSelectedScores(idx), ...
        audit.feasibleActionCount, audit.actionCount, ...
        audit.oracleActionName, ...
        mat2str(audit.oracleTargets, 6));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    shard.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
