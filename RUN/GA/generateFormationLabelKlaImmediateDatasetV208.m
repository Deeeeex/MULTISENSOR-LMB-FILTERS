end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('FormationLabelDatasetV208:ReportOpenFailed', ...
        'Could not create the V208 immediate dataset report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V208 immediate formation-label KLA dataset\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    dataset.presetName, dataset.seed);
fprintf(fid, '- Graph blocks / action rows: `%d / %d`\n', ...
    dataset.blockCount, dataset.rowCount);
fprintf(fid, '- Byte-feasible rows: `%d`\n', ...
    dataset.netByteFeasibleRowCount);
fprintf(fid, '- Joint E-OSPA + RMSE positive rows: `%d`\n', ...
    dataset.jointTrackingPositiveRowCount);
fprintf(fid, '- Joint tracking + consensus + byte positive rows: `%d`\n', ...
    dataset.jointAggregatePositiveRowCount);
fprintf(fid, '- V206 teacher-key rows recovered: `%d / 5`\n\n', ...
    dataset.teacherKeyRowCount);
fprintf(fid, ['| Time | Full | Shortlist | Evaluated | Executable | ', ...
    'Byte-safe | E+R positive | Joint aggregate | ', ...
    'Best E-OSPA | Best RMSE | Best min(E,R) |\n']);
fprintf(fid, ...
    '|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for block = reshape(dataset.blocks, 1, [])
    blockRows = dataset.rows([dataset.rows.blockId] == block.blockId & ...
        [dataset.rows.netByteFeasible]);
    [bestE, bestR, bestJoint] = bestValues(blockRows);
    fprintf(fid, ['| %d | %d | %d | %d | %d | %d | %d | %d | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% |\n'], ...
        block.currentTime, block.fullCandidateCount, ...
        block.shortlistedCandidateCount, ...
        block.evaluatedCandidateCount, block.executableRowCount, ...
        block.netByteFeasibleRowCount, ...
        block.jointTrackingPositiveRowCount, ...
        block.jointAggregatePositiveRowCount, ...
        bestE, bestR, bestJoint);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function [bestE, bestR, bestJoint] = bestValues(rows)
if isempty(rows)
    bestE = NaN;
    bestR = NaN;
    bestJoint = NaN;
    return;
end
bestE = max([rows.meanEospaGainPercent]);
bestR = max([rows.meanRmseGainPercent]);
bestJoint = max(arrayfun(@(row) min( ...
    row.meanEospaGainPercent, row.meanRmseGainPercent), rows));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
