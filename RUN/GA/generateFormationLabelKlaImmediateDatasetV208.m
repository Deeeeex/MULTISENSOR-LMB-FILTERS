    'sourceFormationId', 0, ...
    'sourceFormationIndex', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'candidateIndex', 0, 'features', zeros(1, 0), ...
    'targets', zeros(1, 0), ...
    'actionBytes', 0, 'lightSynopsisBytes', 0, ...
    'referencePageBytes', 0, 'basePageBytes', 0, ...
    'chargedNetByteSaving', 0, ...
    'chargedNetByteSavingPercent', 0, ...
    'meanEospaGainPercent', NaN, ...
    'meanRmseGainPercent', NaN, ...
    'consensusGainPercent', NaN, ...
    'netByteFeasible', false, ...
    'jointTrackingPositive', false, ...
    'jointAggregatePositive', false, ...
    'teacherKey', false, ...
