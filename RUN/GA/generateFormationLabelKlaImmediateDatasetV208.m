    'shortlistedCandidateCount', 0, ...
    'evaluatedCandidateCount', 0, ...
    'executableRowCount', 0, ...
    'netByteFeasibleRowCount', 0, ...
    'jointTrackingPositiveRowCount', 0, ...
    'jointAggregatePositiveRowCount', 0, ...
    'releaseCandidateFormationIds', zeros(1, 0), ...
