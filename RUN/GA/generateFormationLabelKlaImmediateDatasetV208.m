function [reportPath, dataset] = ...
        generateFormationLabelKlaImmediateDatasetV208(options)
% GENERATEFORMATIONLABELKLAIMMEDIATEDATASETV208 Dense current-state targets.
%
% Candidate construction, shortlisting, graph features, and payload
% resolution are truth-free.  Current truth is attached only after every
% executable label-KLA action is frozen, to provide dense one-step targets
% for representation learning.  Recursive return remains a separate sparse
% target stage.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v197', 'base_capture', ...
    'x36_seed211_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v208', 'formation_label_kla_immediate', ...
    'x36_seed211_t72_h8'));
maximumPerCriterion = getField( ...
    options, 'maximumPerCriterion', 2);
maximumCandidateEvaluationsPerBlock = getField( ...
    options, 'maximumCandidateEvaluationsPerBlock', inf);
sourceWeight = getField(options, 'sourceWeight', 0.5);
receiverPresenceThreshold = getField( ...
    options, 'receiverPresenceThreshold', 1e-2);
minimumRiskReductionThreshold = getField( ...
    options, 'minimumRiskReductionThreshold', -1);
if exist(screenPath, 'file') ~= 2 || ...
        ~isscalar(sourceWeight) || ~isfinite(sourceWeight) || ...
        sourceWeight <= 0 || sourceWeight >= 1 || ...
        ~isnumeric(maximumCandidateEvaluationsPerBlock) || ...
        ~isscalar(maximumCandidateEvaluationsPerBlock) || ...
        isnan(maximumCandidateEvaluationsPerBlock) || ...
        maximumCandidateEvaluationsPerBlock < 1 || ...
        (~isinf(maximumCandidateEvaluationsPerBlock) && ...
         maximumCandidateEvaluationsPerBlock ~= ...
            round(maximumCandidateEvaluationsPerBlock))
    error('FormationLabelDatasetV208:InvalidRequest', ...
        'A captured V99 screen and valid KLA weight are required.');
end

loaded = load(screenPath, 'screen');
screen = loaded.screen;
names = {screen.records.actionName};
baseIdx = find(strncmp(names, ...
    'v99-online-positive-net-', 24));
if numel(baseIdx) ~= 1 || ...
        screen.referenceSubsetIndex < 1 || ...
        screen.referenceSubsetIndex > numel(screen.outcomes)
    error('FormationLabelDatasetV208:ScreenContract', ...
        'The V99 and matched reference arms must be unique.');
end
baseOutcome = screen.outcomes(baseIdx);
referenceOutcome = screen.outcomes(screen.referenceSubsetIndex);
pageCount = numel(screen.returnTimes);
pageIndices = reshape(getField(options, ...
    'pageIndices', 1:pageCount), 1, []);
if isempty(pageIndices) || any(pageIndices < 1) || ...
        any(pageIndices > pageCount) || ...
        any(pageIndices ~= round(pageIndices)) || ...
        numel(unique(pageIndices)) ~= numel(pageIndices)
    error('FormationLabelDatasetV208:InvalidPages', ...
        'Page indices must be unique valid captured-screen pages.');
end
if numel(baseOutcome.fusedPosteriorSnapshotsByTime) ~= pageCount || ...
        numel(baseOutcome.localPosteriorSnapshotsByTime) ~= pageCount
    error('FormationLabelDatasetV208:MissingSnapshots', ...
        'Every V99 page requires fused and local posterior snapshots.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
truthModel = inputs.model;
truthModel.dynamicTopologyScenario.targetTrajectories = ...
    inputs.targetTrajectories;
runtimeModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(truthModel);
groupIds = reshape(screen.sensorGroupIds, 1, []);
initialPrevious = initialPreviousAdjacency(screen, numel(groupIds));
teacher = teacherKeys();
rows = repmat(emptyRow(), 1, 0);
blocks = repmat(emptyBlock(), 1, numel(pageIndices));
actionFeatureNames = cell(1, 0);
targetNames = targetFeatureNames();

for blockIdx = 1:numel(pageIndices)
    pageIdx = pageIndices(blockIdx);
    currentTime = screen.returnTimes(pageIdx);
    fprintf('V208 immediate dataset block %d/%d: page=%d t=%d ...\n', ...
        blockIdx, numel(pageIndices), pageIdx, currentTime);
    fused = baseOutcome.fusedPosteriorSnapshotsByTime{pageIdx};
    local = baseOutcome.localPosteriorSnapshotsByTime{pageIdx};
    physical = logical(inputs.graphData. ...
        physicalAdjacency(:, :, currentTime));
    physical = physical | physical';
    physical(1:numel(groupIds)+1:end) = false;
    selectedAdjacency = logical( ...
        baseOutcome.selectedAdjacency(:, :, pageIdx));
    if pageIdx == 1
        previousAdjacency = initialPrevious;
    else
        previousAdjacency = logical( ...
            baseOutcome.selectedAdjacency(:, :, pageIdx - 1));
    end
    referencePageBytes = ...
        referenceOutcome.attemptedBytesByTime(pageIdx);
    basePageBytes = baseOutcome.attemptedBytesByTime(pageIdx);
    graph = buildObservableFormationGraphSnapshotV208( ...
        local, groupIds, physical, selectedAdjacency, ...
        previousAdjacency, ...
        inputs.graphData.positions(:, :, currentTime), ...
        inputs.commConfig, runtimeModel, currentTime, ...
        referencePageBytes);

    cache = buildFormationRepairLightSynopsisCacheV188( ...
        fused, local, runtimeModel, currentTime, struct());
    [candidates, fullDetails] = ...
        enumerateFormationCommonLabelRepairCandidatesV190( ...
            cache, physical, groupIds, struct( ...
                'receiverPresenceThreshold', ...
                    receiverPresenceThreshold, ...
                'minimumRiskReductionThreshold', ...
                    minimumRiskReductionThreshold));
    [shortlisted, shortlistDetails] = ...
        shortlistFormationLabelActionCandidatesV208( ...
            candidates, struct( ...
                'maximumPerCriterion', maximumPerCriterion));
    evaluatedCandidates = reshape(shortlisted, 1, []);
    evaluatedCandidates = evaluatedCandidates(1:min( ...
        numel(evaluatedCandidates), ...
        maximumCandidateEvaluationsPerBlock));
    baseline = evaluatePrivilegedCurrentLmbNetworkMetricsV208( ...
        fused, truthModel, currentTime, groupIds);
    blockRowStart = numel(rows) + 1;
    for candidateIdx = 1:numel(evaluatedCandidates)
        candidate = evaluatedCandidates(candidateIdx);
        [proposal, payloadDetails] = ...
            resolveFormationRepairCandidatePayloadV190( ...
                candidate, local, physical, runtimeModel, struct( ...
                    'minimumUtilityLowerBound', -1e6, ...
                    'rollingConnectivityPassed', true));
        if ~payloadDetails.completePayloadResolved || ...
                ~proposal.safetyPassed
            continue;
        end
        [trialPosterior, applyDetails] = ...
            applyFormationCommonLabelKlaRepairV190( ...
                fused, proposal, 1, runtimeModel, struct( ...
                    'sourceWeight', sourceWeight));
        if applyDetails.appliedActionCount ~= 1
            error('FormationLabelDatasetV208:ActionNotApplied', ...
                'A frozen label-KLA action did not execute.');
        end
        trial = evaluatePrivilegedCurrentLmbNetworkMetricsV208( ...
            trialPosterior, truthModel, currentTime, groupIds, ...
            baseline, proposal.receiverIds);
        [modeFeatures, modeFeatureNames] = ...
            buildFormationLabelActionModeFeaturesV202(candidate);
        extraFeatures = actionCostFeatures( ...
            candidate, proposal, groupIds, ...
            referencePageBytes, basePageBytes, ...
            cache.totalAttemptedBytes);
        currentFeatureNames = [modeFeatureNames, ...
            actionCostFeatureNames()];
        if isempty(actionFeatureNames)
            actionFeatureNames = currentFeatureNames;
        elseif ~isequal(actionFeatureNames, currentFeatureNames)
            error('FormationLabelDatasetV208:FeatureDrift', ...
                'The action feature contract changed between rows.');
        end
        row = emptyRow();
        row.rowId = numel(rows) + 1;
        row.blockId = blockIdx;
        row.page = pageIdx;
        row.currentTime = currentTime;
        row.actionType = 'supported-label-kla';
        row.receiverFormationId = candidate.formationId;
        row.receiverFormationIndex = find( ...
            graph.formationIds == candidate.formationId, 1);
        sourceFormationId = groupIds(candidate.sourceId);
        row.sourceFormationId = sourceFormationId;
        row.sourceFormationIndex = find( ...
            graph.formationIds == sourceFormationId, 1);
        row.sourceId = candidate.sourceId;
        row.label = candidate.label;
        row.candidateIndex = candidate.candidateIndex;
        row.features = [modeFeatures, extraFeatures];
        row.actionBytes = proposal.attemptedBytes;
        row.lightSynopsisBytes = cache.totalAttemptedBytes;
        row.referencePageBytes = referencePageBytes;
        row.basePageBytes = basePageBytes;
        row.chargedNetByteSaving = ...
            referencePageBytes - basePageBytes - ...
            cache.totalAttemptedBytes - proposal.attemptedBytes;
        row.chargedNetByteSavingPercent = 100 * ...
            row.chargedNetByteSaving / max(referencePageBytes, eps);
        row.targets = actionTargets( ...
            baseline, trial, proposal.receiverIds, ...
            row.receiverFormationIndex, ...
            row.chargedNetByteSavingPercent);
        row.meanEospaGainPercent = row.targets(1);
        row.meanRmseGainPercent = row.targets(2);
        row.consensusGainPercent = row.targets(3);
        row.netByteFeasible = row.chargedNetByteSaving >= 0;
        row.jointTrackingPositive = ...
            row.meanEospaGainPercent > 0 && ...
            row.meanRmseGainPercent > 0;
        row.jointAggregatePositive = ...
            row.jointTrackingPositive && ...
            row.consensusGainPercent >= 0 && ...
            row.netByteFeasible;
        row.teacherKey = isTeacherKey(teacher, row);
        row.truthUsedForFeatures = false;
        row.truthUsedForTargets = true;
        rows(end + 1) = row; %#ok<AGROW>
        if mod(candidateIdx, 10) == 0 || ...
                candidateIdx == numel(evaluatedCandidates)
            fprintf('  scored %d/%d shortlisted candidates\n', ...
                candidateIdx, numel(evaluatedCandidates));
        end
    end

    blockRows = rows(blockRowStart:end);
    block = emptyBlock();
    block.blockId = blockIdx;
    block.page = pageIdx;
    block.currentTime = currentTime;
    block.graph = graph;
    block.fullCandidateCount = numel(candidates);
    block.shortlistedCandidateCount = numel(shortlisted);
    block.evaluatedCandidateCount = numel(evaluatedCandidates);
    block.executableRowCount = numel(blockRows);
    block.netByteFeasibleRowCount = ...
        nnz([blockRows.netByteFeasible]);
    block.jointTrackingPositiveRowCount = ...
        nnz([blockRows.jointTrackingPositive]);
    block.jointAggregatePositiveRowCount = ...
        nnz([blockRows.jointAggregatePositive]);
    block.releaseCandidateFormationIds = reshape( ...
        baseOutcome.retentionDebtSelectedFormationIdsByTime{pageIdx}, ...
        1, []);
    block.fullCandidateCountByFormation = ...
        fullDetails.candidateCountByFormation;
    block.shortlistedCountByFormation = ...
        shortlistDetails.shortlistedCountByFormation;
    block.baselineMetrics = stripInternalMetrics(baseline);
    blocks(blockIdx) = block;
end

dataset = struct();
dataset.contractVersion = ...
    'formation-label-kla-immediate-dataset-v208-v1';
dataset.generatedAt = datestr(now, 31);
dataset.screenPath = screenPath;
dataset.presetName = screen.presetName;
dataset.seed = screen.seed;
dataset.pageIndices = pageIndices;
dataset.returnTimes = screen.returnTimes(pageIndices);
dataset.sourceWeight = sourceWeight;
dataset.maximumPerCriterion = maximumPerCriterion;
dataset.maximumCandidateEvaluationsPerBlock = ...
    maximumCandidateEvaluationsPerBlock;
dataset.receiverPresenceThreshold = receiverPresenceThreshold;
dataset.minimumRiskReductionThreshold = ...
    minimumRiskReductionThreshold;
dataset.actionFeatureNames = actionFeatureNames;
dataset.targetNames = targetNames;
dataset.blocks = blocks;
dataset.rows = rows;
dataset.blockCount = numel(blocks);
dataset.rowCount = numel(rows);
dataset.netByteFeasibleRowCount = nnz([rows.netByteFeasible]);
dataset.jointTrackingPositiveRowCount = ...
    nnz([rows.jointTrackingPositive]);
dataset.jointAggregatePositiveRowCount = ...
    nnz([rows.jointAggregatePositive]);
dataset.teacherKeyRowCount = nnz([rows.teacherKey]);
dataset.featuresUseTruth = false;
dataset.featuresUseFutureInformation = false;
dataset.targetsUseCurrentTruth = true;
dataset.targetsUseFutureInformation = false;
dataset.numericLabelIdentifiersUsedAsFeatures = false;
dataset.numericSourceIdentifiersUsedAsFeatures = false;
dataset.recursiveTargetsIncluded = false;
dataset.validationClaimAllowed = false;
dataset.evidenceBoundary = [ ...
    'V208 builds the graph and diverse action bank from current V99 ', ...
    'posteriors, geometry, link metadata, causal route history, and byte ', ...
    'accounting only. Current truth scores each frozen one-step KLA action ', ...
    'after construction. Every block comes from opened X36 seed 211, so ', ...
    'the dataset supports representation and proposal development only. ', ...
    'It contains no recursive, held-out, cross-seed, or cross-scene target.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.md');
dataset.matPath = matPath;
dataset.reportPath = reportPath;
save('-mat7-binary', matPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('V208 immediate label-KLA dataset: %s\n', reportPath);
end

function previous = initialPreviousAdjacency(screen, nodeCount)
cache = load(screen.cachePath, 'behaviorBundle');
history = cache.behaviorBundle. ...
    preDecisionTopologyHistoryByTime{screen.returnTimes(1)};
converted = convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
    history.selectedDirectedEdgeHistory);
if isempty(converted)
    previous = false(nodeCount);
else
    previous = logical(converted(:, :, end));
end
end

function values = actionCostFeatures(candidate, proposal, groupIds, ...
        referenceBytes, baseBytes, synopsisBytes)
sourceFormationId = groupIds(candidate.sourceId);
values = [ ...
    0, 1, ...
    double(sourceFormationId == candidate.formationId), ...
    proposal.attemptedBytes / max(referenceBytes, 1), ...
    synopsisBytes / max(referenceBytes, 1), ...
    (referenceBytes - baseBytes) / max(referenceBytes, 1), ...
    (referenceBytes - baseBytes - synopsisBytes - ...
        proposal.attemptedBytes) / max(referenceBytes, 1)];
end

function names = actionCostFeatureNames()
names = { ...
    'is_full_formation_release', ...
    'is_supported_label_kla', ...
    'source_same_formation', ...
    'action_payload_fraction_of_reference', ...
    'light_synopsis_fraction_of_reference', ...
    'base_byte_credit_fraction', ...
    'post_action_byte_credit_fraction'};
end

function names = targetFeatureNames()
names = { ...
    'mean_eospa_gain_percent', ...
    'mean_rmse_gain_percent', ...
    'consensus_gain_percent', ...
    'cardinality_error_gain_percent', ...
    'receiver_formation_eospa_gain_percent', ...
    'receiver_formation_rmse_gain_percent', ...
    'minimum_affected_sensor_eospa_gain_percent', ...
    'minimum_affected_sensor_rmse_gain_percent', ...
    'worst_sensor_eospa_gain_percent', ...
    'worst_sensor_rmse_gain_percent', ...
    'charged_net_byte_saving_percent'};
end

function values = actionTargets( ...
        baseline, trial, receiverIds, formationIdx, byteSavingPercent)
affectedEospa = elementwiseGain( ...
    baseline.eospaBySensor(receiverIds), ...
    trial.eospaBySensor(receiverIds));
affectedRmse = elementwiseGain( ...
    baseline.rmseBySensor(receiverIds), ...
    trial.rmseBySensor(receiverIds));
values = [ ...
    relativeGain(baseline.meanEospa, trial.meanEospa), ...
    relativeGain(baseline.meanRmse, trial.meanRmse), ...
    relativeGain(baseline.consensusOspa, trial.consensusOspa), ...
    relativeGain(baseline.meanCardinalityError, ...
        trial.meanCardinalityError), ...
    relativeGain(baseline.formationMeanEospa(formationIdx), ...
        trial.formationMeanEospa(formationIdx)), ...
    relativeGain(baseline.formationMeanRmse(formationIdx), ...
        trial.formationMeanRmse(formationIdx)), ...
    minimumFinite(affectedEospa), ...
    minimumFinite(affectedRmse), ...
    relativeGain(baseline.worstSensorEospa, ...
        trial.worstSensorEospa), ...
    relativeGain(baseline.worstSensorRmse, ...
        trial.worstSensorRmse), ...
    byteSavingPercent];
end

function values = elementwiseGain(reference, candidate)
values = 100 * (reference - candidate) ./ ...
    max(abs(reference), eps);
values(~isfinite(reference) | ~isfinite(candidate)) = NaN;
end

function value = relativeGain(reference, candidate)
if ~isfinite(reference) || ~isfinite(candidate)
    value = NaN;
else
    value = 100 * (reference - candidate) / ...
        max(abs(reference), eps);
end
end

function value = minimumFinite(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = min(values);
end
end

function metrics = stripInternalMetrics(metrics)
fields = {'internalStateEstimateBySensor', ...
    'internalConsensusOspaMatrix'};
for fieldIdx = 1:numel(fields)
    if isfield(metrics, fields{fieldIdx})
        metrics = rmfield(metrics, fields{fieldIdx});
    end
end
end

function value = isTeacherKey(teacher, row)
value = false;
for key = reshape(teacher, 1, [])
    if key.time == row.currentTime && ...
            key.formationId == row.receiverFormationId && ...
            key.sourceId == row.sourceId && ...
            isequal(key.label, row.label)
        value = true;
        return;
    end
end
end

function teacher = teacherKeys()
teacher = repmat(struct( ...
    'time', 0, 'formationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1)), 1, 5);
times = [72, 73, 76, 77, 78];
formations = [2, 6, 3, 1, 3];
sources = [19, 19, 23, 13, 23];
labels = [13, 7, 19, 7, 19; ...
          12, 5, 13, 7, 13];
for idx = 1:numel(teacher)
    teacher(idx).time = times(idx);
    teacher(idx).formationId = formations(idx);
    teacher(idx).sourceId = sources(idx);
    teacher(idx).label = labels(:, idx);
end
end

