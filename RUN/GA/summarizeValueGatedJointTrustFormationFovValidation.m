function [reportPath, validation] = ...
    summarizeValueGatedJointTrustFormationFovValidation(options)
% SUMMARIZEVALUEGATEDJOINTTRUSTFORMATIONFOVVALIDATION Gate all fresh pairs.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
verifyValueGatedJointTrustDevelopmentGate(protocol);
gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error(['Formation-FoV validation summarization requires a clean ', ...
        'tracked worktree with no untracked MATLAB source files.']);
end
rootDirectory = getField(options, 'inputDirectory', ...
    protocol.valueGatedFormationFovValidationRoot);
presets = protocol.valueGatedFormationFovValidationPresets;
seeds = protocol.valueGatedFormationFovValidationSeeds;
rows = repmat(emptyRow(), numel(presets), numel(seeds));
runCommits = cell(1, numel(presets) * numel(seeds));
commitIdx = 0;
for sceneIdx = 1:numel(presets)
    presetName = presets{sceneIdx};
    scenarioConfig = buildDynamicTopologyScenarioConfig(presetName);
    for seedIdx = 1:numel(seeds)
        seed = seeds(seedIdx);
        caseDetails = resolveValueGatedFormationFovValidationCase( ...
            protocol, presetName, seed, scenarioConfig);
        evidencePath = findSingleEvidence( ...
            rootDirectory, presetName, seed);
        loaded = load(evidencePath, 'summary');
        validateRun(loaded.summary, caseDetails, protocol);
        baseline = findArm(loaded.summary.aggregate, protocol. ...
            valueGatedFormationFovValidationReferenceArmName);
        candidate = findArm(loaded.summary.aggregate, protocol. ...
            valueGatedFormationFovValidationCandidateArmName);
        rows(sceneIdx, seedIdx) = buildRow( ...
            caseDetails, baseline, candidate, evidencePath, protocol);
        commitIdx = commitIdx + 1;
        runCommits{commitIdx} = loaded.summary.generationGitCommit;
    end
end
if numel(unique(runCommits, 'stable')) ~= 1
    error('Formation-FoV validation pairs use multiple code commits.');
end
if ~strcmp(runCommits{1}, gitState.commit)
    error(['Formation-FoV validation must be summarized by the same ', ...
        'frozen source commit that generated every pair.']);
end

sceneResults = repmat(emptySceneResult(), 1, numel(presets));
for sceneIdx = 1:numel(presets)
    sceneResults(sceneIdx) = aggregateScene( ...
        presets{sceneIdx}, rows(sceneIdx, :), protocol);
end
validation = struct();
validation.contractVersion = protocol. ...
    valueGatedFormationFovValidationContractVersion;
validation.generatedAt = datestr(now, 31);
validation.generationGitCommit = gitState.commit;
validation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
validation.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
validation.runGenerationGitCommit = runCommits{1};
validation.presets = presets;
validation.seeds = seeds;
validation.windows = protocol. ...
    valueGatedFormationFovValidationWindows;
validation.referenceArmName = protocol. ...
    valueGatedFormationFovValidationReferenceArmName;
validation.candidateArmName = protocol. ...
    valueGatedFormationFovValidationCandidateArmName;
validation.rows = rows;
validation.scenes = sceneResults;
validation.allPairsOpened = true;
validation.validationGatePassed = all([sceneResults.gatePassed]);
validation.evaluationScope = protocol. ...
    valueGatedFormationFovValidationEvaluationScope;
validation.conditionalContinuationOnly = protocol. ...
    valueGatedFormationFovValidationConditionalContinuationOnly;
validation.conditionalWindowClaimAllowed = ...
    validation.allPairsOpened && validation.validationGatePassed;
validation.fullEpisodeClaimAllowed = protocol. ...
    valueGatedFormationFovValidationFullEpisodeClaimAllowed;
validation.x48ClaimAllowed = protocol. ...
    valueGatedFormationFovValidationX48ClaimAllowed;
validation.evidenceBoundary = protocol. ...
    valueGatedFormationFovValidationEvidenceBoundary;

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(rootDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'VALUE_GATED_JOINT_TRUST_FORMATION_FOV_VALIDATION_V1.md');
writeReport(reportPath, validation);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
validation.reportPath = reportPath;
validation.matPath = matPath;
fprintf('Formation-FoV tracking validation: %s\n', reportPath);
end

function row = buildRow( ...
        caseDetails, baseline, candidate, evidencePath, protocol)
row = emptyRow();
row.presetName = caseDetails.presetName;
row.seed = caseDetails.seed;
row.window = caseDetails.window;
row.evidencePath = evidencePath;
row.baselineEospa = baseline.focusEospa;
row.candidateEospa = candidate.focusEospa;
row.gainPercent = relativeGain(row.baselineEospa, row.candidateEospa);
row.baselineWorstEospa = baseline.focusWorstSensorEospa;
row.candidateWorstEospa = candidate.focusWorstSensorEospa;
row.baselineConsensusOspa = baseline.focusMapSetDisagreement;
row.candidateConsensusOspa = candidate.focusMapSetDisagreement;
row.baselineAttemptedBytes = baseline.focusAttemptedBytes;
row.candidateAttemptedBytes = candidate.focusAttemptedBytes;
row.byteDeltaPercent = 100 * ...
    (row.candidateAttemptedBytes - row.baselineAttemptedBytes) / ...
        max(row.baselineAttemptedBytes, eps);
row.selectedSensorB3 = candidate. ...
    focusSelectedRollingB3SensorStrongFraction;
row.selectedFormationB3 = candidate. ...
    focusSelectedRollingB3FormationStrongFraction;
row.truthUseFraction = candidate.policyTruthUseFraction;
row.payloadLimitPassFraction = ...
    candidate.policyPayloadLimitPassFraction;
row.payloadConstraintFraction = ...
    candidate.policyPayloadConstraintEnforcedFraction;
row.repairRate = candidate.policyRepairRate;
row.payloadEmergencyRate = candidate.policyPayloadEmergencyRate;
row.topologyInfeasibleRate = candidate.focusTopologyInfeasibleRate;
row.oneStepConstraintPassFraction = ...
    candidate.policyOneStepTopologyReservePassFraction;
row.oneStepConstraintCheckCount = ...
    candidate.policyOneStepTopologyReserveCheckCount;
row.expectedOneStepConstraintCheckCount = ...
    candidate.policyExpectedOneStepTopologyReserveCheckCount;
row.referenceOneStepRisk = ...
    candidate.policyConsensusProjectionReferenceRisk;
row.selectedOneStepRisk = ...
    candidate.policyConsensusProjectionSelectedRisk;
row.evaluatedActionCount = ...
    candidate.policyConsensusProjectionEvaluatedCountMinimum;
row.feasibleActionCount = ...
    candidate.policyConsensusProjectionFeasibleCountMinimum;
row.payloadRelaxationRate = ...
    candidate.policyConsensusProjectionPayloadRelaxationRate;
row.meanSelectedDominantWeight = ...
    candidate.policyMeanSelectedDominantWeight;
row.minimumSelectedDominantWeight = ...
    candidate.policyMinimumSelectedDominantWeight;
row.minimumSelectedObjectiveAdvantage = ...
    candidate.policyMinimumDominantObjectiveAdvantage;
row.referenceFormationMean = ...
    candidate.policyJointTrustReferenceFormationMean;
row.lowTrustFormationMean = ...
    candidate.policyJointTrustLowTrustFormationMean;
row.fullTrustCandidateFormationMean = ...
    candidate.policyJointTrustFullTrustCandidateFormationMean;
row.elapsedSeconds = candidate.elapsedSeconds;
windowLength = caseDetails.window(2) - caseDetails.window(1) + 1;
row.hardSafetyPassed = ...
    row.selectedSensorB3 >= 1 - 1e-12 && ...
    row.selectedFormationB3 >= 1 - 1e-12 && ...
    row.truthUseFraction == 0 && ...
    row.payloadLimitPassFraction >= 1 - 1e-12 && ...
    row.payloadConstraintFraction >= 1 - 1e-12 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0 && ...
    row.oneStepConstraintPassFraction >= 1 - 1e-12 && ...
    row.oneStepConstraintCheckCount == ...
        row.expectedOneStepConstraintCheckCount && ...
    row.oneStepConstraintCheckCount == windowLength && ...
    row.evaluatedActionCount == caseDetails.expectedCandidateCount && ...
    row.feasibleActionCount >= 1 && ...
    row.selectedOneStepRisk <= row.referenceOneStepRisk + 1e-12 && ...
    row.minimumSelectedDominantWeight >= min(protocol. ...
        adaptiveDominantJointTrustStabilityCandidateWeightGrid) - 1e-12 && ...
    row.meanSelectedDominantWeight <= protocol. ...
        adaptiveDominantJointTrustStabilityReferenceWeight + 1e-12 && ...
    row.minimumSelectedObjectiveAdvantage >= protocol. ...
        adaptiveDominantJointTrustStabilityMinimumDynamicObjectiveAdvantage ...
            - 1e-12;
end

function result = aggregateScene(presetName, rows, protocol)
result = emptySceneResult();
result.presetName = presetName;
result.seedGainPercent = [rows.gainPercent];
result.seedByteDeltaPercent = [rows.byteDeltaPercent];
result.meanGainPercent = relativeGain( ...
    mean([rows.baselineEospa]), mean([rows.candidateEospa]));
result.positiveSeedFraction = mean(result.seedGainPercent > 0);
result.minimumSeedGainPercent = min(result.seedGainPercent);
result.aggregateWorstGainPercent = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
result.aggregateConsensusGainPercent = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
result.aggregateByteSavingPercent = 100 * ...
    (sum([rows.baselineAttemptedBytes]) - ...
     sum([rows.candidateAttemptedBytes])) / ...
        max(sum([rows.baselineAttemptedBytes]), eps);
result.maximumPositiveByteDeltaPercent = ...
    max([0, result.seedByteDeltaPercent]);
result.hardSafetyPassed = all([rows.hardSafetyPassed]);
result.trackingGatePassed = ...
    result.meanGainPercent >= protocol. ...
        valueGatedFormationFovValidationMinimumMeanGainPercent && ...
    result.positiveSeedFraction >= protocol. ...
        valueGatedFormationFovValidationMinimumPositiveSeedFraction;
result.tailGatePassed = ...
    (~protocol.valueGatedFormationFovValidationRequireNoAggregateWorstRegression || ...
     result.aggregateWorstGainPercent >= -1e-12) && ...
    (~protocol.valueGatedFormationFovValidationRequireNoAggregateConsensusRegression || ...
     result.aggregateConsensusGainPercent >= -1e-12);
result.communicationGatePassed = ...
    result.aggregateByteSavingPercent >= protocol. ...
        valueGatedFormationFovValidationMinimumByteSavingPercent && ...
    result.maximumPositiveByteDeltaPercent <= protocol. ...
        valueGatedFormationFovValidationMaximumPositiveByteDeltaPercent ...
            + 1e-12;
result.gatePassed = ...
    result.hardSafetyPassed && result.trackingGatePassed && ...
    result.tailGatePassed && result.communicationGatePassed;
end

function validateRun(summary, caseDetails, protocol)
expectedWindow = caseDetails.window;
expectedArms = { ...
    protocol.valueGatedFormationFovValidationReferenceArmName, ...
    protocol.valueGatedFormationFovValidationCandidateArmName};
if ~strcmp(summary.presetName, caseDetails.presetName) || ...
        ~isequal(summary.seeds, caseDetails.seed) || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles) || ...
        ~strcmp(summary.options.evidenceSplit, protocol. ...
            valueGatedFormationFovValidationEvidenceSplit) || ...
        summary.options.continuationStartTime ~= expectedWindow(1) || ...
        summary.options.maxTimeSteps ~= expectedWindow(2) || ...
        ~isequal(summary.options.armNames, expectedArms) || ...
        numel(summary.aggregate) ~= 2
    error('Formation-FoV validation evidence provenance mismatch.');
end
end

function path = findSingleEvidence(rootDirectory, presetName, seed)
matches = dir(fullfile(rootDirectory, presetName, ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one %s tracking result for seed %d.', ...
        presetName, seed);
end
path = fullfile(matches.folder, matches.name);
end

function arm = findArm(aggregate, mode)
armIdx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(armIdx)
    error('Formation-FoV evidence lacks arm %s.', mode);
end
arm = aggregate(armIdx);
end

function writeReport(path, validation)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation-FoV validation report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Value-gated joint source-trust formation-FoV validation\n\n');
fprintf(fid, '- Generated: `%s`\n', validation.generatedAt);
fprintf(fid, '- Contract: `%s`\n', validation.contractVersion);
fprintf(fid, '- Run commit: `%s`\n', validation.runGenerationGitCommit);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seeds));
fprintf(fid, '- Evaluation scope: `%s`\n', validation.evaluationScope);
fprintf(fid, '- All pairs opened: `%d`\n', validation.allPairsOpened);
fprintf(fid, '- Validation gate passed: `%d`\n\n', ...
    validation.validationGatePassed);
fprintf(fid, '- Conditional-window claim allowed: `%d`\n', ...
    validation.conditionalWindowClaimAllowed);
fprintf(fid, '- Full-episode claim allowed: `%d`\n', ...
    validation.fullEpisodeClaimAllowed);
fprintf(fid, '- X48 claim allowed: `%d`\n\n', ...
    validation.x48ClaimAllowed);
fprintf(fid, ['| Scene | Window | Mean gain | Positive seeds | ', ...
    'Minimum seed | Worst-node gain | Consensus gain | Byte saving | ', ...
    'Hard safety | Gate |\n']);
fprintf(fid, '|:--|:--:|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
for sceneIdx = 1:numel(validation.scenes)
    scene = validation.scenes(sceneIdx);
    fprintf(fid, ['| %s | %s | %+.3f%% | %d/%d | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %d | %d |\n'], ...
        scene.presetName, mat2str(validation.windows(sceneIdx, :)), ...
        scene.meanGainPercent, nnz(scene.seedGainPercent > 0), ...
        numel(scene.seedGainPercent), scene.minimumSeedGainPercent, ...
        scene.aggregateWorstGainPercent, ...
        scene.aggregateConsensusGainPercent, ...
        scene.aggregateByteSavingPercent, ...
        scene.hardSafetyPassed, scene.gatePassed);
end
fprintf(fid, '\n## Paired results\n\n');
fprintf(fid, ['| Scene | Seed | Baseline E-OSPA | Candidate E-OSPA | ', ...
    'Gain | Consensus gain | Byte delta | Actions | Safe |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for rowIdx = 1:numel(validation.rows)
    row = validation.rows(rowIdx);
    fprintf(fid, ['| %s | %d | %.4f | %.4f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %.0f | %d |\n'], ...
        row.presetName, row.seed, row.baselineEospa, ...
        row.candidateEospa, row.gainPercent, ...
        relativeGain(row.baselineConsensusOspa, ...
            row.candidateConsensusOspa), ...
        row.byteDeltaPercent, row.evaluatedActionCount, ...
        row.hardSafetyPassed);
end
fprintf(fid, '\n## Interpretation boundary\n\n%s\n', ...
    validation.evidenceBoundary);
end

