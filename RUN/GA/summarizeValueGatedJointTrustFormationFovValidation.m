    'baselineWorstEospa', NaN, 'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, 'candidateConsensusOspa', NaN, ...
    'baselineAttemptedBytes', NaN, 'candidateAttemptedBytes', NaN, ...
    'byteDeltaPercent', NaN, ...
    'selectedSensorB3', NaN, 'selectedFormationB3', NaN, ...
    'truthUseFraction', NaN, ...
    'payloadLimitPassFraction', NaN, ...
    'payloadConstraintFraction', NaN, ...
    'repairRate', NaN, 'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'oneStepConstraintPassFraction', NaN, ...
    'oneStepConstraintCheckCount', NaN, ...
    'expectedOneStepConstraintCheckCount', NaN, ...
    'referenceOneStepRisk', NaN, 'selectedOneStepRisk', NaN, ...
    'evaluatedActionCount', NaN, 'feasibleActionCount', NaN, ...
    'payloadRelaxationRate', NaN, ...
    'meanSelectedDominantWeight', NaN, ...
    'minimumSelectedDominantWeight', NaN, ...
    'minimumSelectedObjectiveAdvantage', NaN, ...
    'referenceFormationMean', NaN, 'lowTrustFormationMean', NaN, ...
    'fullTrustCandidateFormationMean', NaN, ...
    'elapsedSeconds', NaN, 'hardSafetyPassed', false);
end

function result = emptySceneResult()
result = struct( ...
    'presetName', '', 'seedGainPercent', [], ...
    'seedByteDeltaPercent', [], 'meanGainPercent', NaN, ...
    'positiveSeedFraction', NaN, 'minimumSeedGainPercent', NaN, ...
    'aggregateWorstGainPercent', NaN, ...
    'aggregateConsensusGainPercent', NaN, ...
    'aggregateByteSavingPercent', NaN, ...
    'maximumPositiveByteDeltaPercent', NaN, ...
    'hardSafetyPassed', false, 'trackingGatePassed', false, ...
    'tailGatePassed', false, 'communicationGatePassed', false, ...
    'gatePassed', false);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
