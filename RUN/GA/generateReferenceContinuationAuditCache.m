function [cachePath, behaviorBundle] = ...
    generateReferenceContinuationAuditCache( ...
        presetName, seed, sourceTime, targetTime, options)
% GENERATEREFERENCECONTINUATIONAUDITCACHE
% Reconstruct a later predecision state using only the fixed reference arm.
%
% The caller supplies an already-opened continuation cache at sourceTime.
% The registered fixed CCW reference is replayed through targetTime with
% the formal filter RNG offset. The resulting targetTime local posterior
% and predecision topology history are stored in the standard behavior
% cache shape so one-step development audits can consume them.

if nargin < 5 || isempty(options)
    options = struct();
end
if ~ischar(presetName) || ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || seed < 1 || ...
        ~isscalar(sourceTime) || ~isfinite(sourceTime) || ...
        sourceTime ~= round(sourceTime) || sourceTime < 1 || ...
        ~isscalar(targetTime) || ~isfinite(targetTime) || ...
        targetTime ~= round(targetTime) || targetTime <= sourceTime
    error('Reference continuation audit-cache request is invalid.');
end
protocol = getLabelSetSimulatorPolicyProtocol();
sourceCacheDirectory = getField(options, ...
    'sourceCacheDirectory', fullfile( ...
        protocol.valueGatedFormationFovValidationRoot, 'cache'));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'posterior_risk_v10', 'opened_state_audit', 'cache'));
filterSeedOffset = round(getField(options, ...
    'filterSeedOffset', 100000));
if filterSeedOffset ~= 100000
    error('Reference continuation audit requires the formal RNG offset.');
end

inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
if targetTime > size(inputs.measurements, 2)
    error('Reference continuation target exceeds the scenario length.');
end
sourcePath = fullfile(sourceCacheDirectory, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
    seed, sourceTime));
[sourceBundle, sourcePosteriors, sourceHistory] = ...
    loadSourceBundle(sourcePath, presetName, seed, ...
        sourceTime, inputs.config);

croppedInputs = cropInputs(inputs, targetTime);
referenceConfig = buildReferenceConfig( ...
    protocol, croppedInputs.config, targetTime, ...
    sourceTime, sourcePosteriors, sourceHistory);
rng(seed + filterSeedOffset);
timerId = tic;
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    croppedInputs.model, croppedInputs.measurements, ...
    croppedInputs.sensorTrajectories, croppedInputs.neighborMap, ...
    croppedInputs.commConfig, referenceConfig);
elapsedSeconds = toc(timerId);
if numel(diagnostics.topologyLocalPosteriorSnapshot) < targetTime || ...
        isempty(diagnostics.topologyLocalPosteriorSnapshot{targetTime})
    error('Reference replay did not capture the target posterior.');
end

diagnostics = attachSourceHistory(diagnostics, sourceHistory);
cacheContract = behaviorContinuationCacheContract();
historyByTime = buildBehaviorContinuationHistoryRecords( ...
    diagnostics, targetTime, cacheContract.topologyHistoryDepth);
posteriorSnapshots = cell(1, targetTime);
posteriorSnapshots{targetTime} = ...
    diagnostics.topologyLocalPosteriorSnapshot{targetTime};
gitState = resolveResearchGitState();
referenceConfigSnapshot = referenceConfig;
if isfield(referenceConfigSnapshot, 'topologyPolicyFcn')
    referenceConfigSnapshot = rmfield( ...
        referenceConfigSnapshot, 'topologyPolicyFcn');
end
behaviorBundle = struct( ...
    'cacheContractVersion', cacheContract.version, ...
    'posteriorSnapshotConvention', ...
        cacheContract.posteriorSnapshotConvention, ...
    'topologyHistoryDepth', cacheContract.topologyHistoryDepth, ...
    'topologyHistoryConvention', ...
        cacheContract.topologyHistoryConvention, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'snapshotTimes', targetTime, ...
    'configSnapshot', inputs.config, ...
    'behaviorConfigSnapshot', referenceConfigSnapshot, ...
    'behaviorSeconds', elapsedSeconds, ...
    'behaviorEospaByTime', [], ...
    'behaviorCardinalityErrorByTime', [], ...
    'posteriorSnapshots', {posteriorSnapshots}, ...
    'preDecisionTopologyHistoryByTime', {historyByTime}, ...
    'generationGitCommit', gitState.commit, ...
    'generationTrackedWorktreeDirty', ...
        gitState.trackedWorktreeDirty, ...
    'generationUntrackedSourceFiles', ...
        {gitState.untrackedSourceFiles}, ...
    'sourceCachePath', sourcePath, ...
    'sourceCacheSha256', computeFileSha256(sourcePath), ...
    'sourceSnapshotTime', sourceTime, ...
    'targetSnapshotTime', targetTime, ...
    'referenceArmName', protocol. ...
        valueGatedFormationFovValidationReferenceArmName, ...
    'referenceReplayOnly', true, ...
    'policyTruthUsed', false, ...
    'policyFutureOutcomeUsed', false, ...
    'openedDevelopmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'evidenceBoundary', [ ...
        'The target state is reconstructed from an already-opened ', ...
        'formation-FoV source cache using only the registered fixed ', ...
        'reference arm. The caller chooses targetTime; this artifact ', ...
        'supports redesign diagnostics only and cannot serve as fresh ', ...
        'tracking validation evidence.']);

[checkPosteriors, checkHistory] = ...
    extractBehaviorContinuationSnapshot( ...
        behaviorBundle, targetTime, inputs.config.numberOfSensors);
if numel(checkPosteriors) ~= inputs.config.numberOfSensors || ...
        checkHistory.snapshotTime ~= targetTime
    error('Generated reference continuation cache failed validation.');
end
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
cachePath = fullfile(outputDirectory, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
    seed, targetTime));
save(cachePath, 'behaviorBundle', '-v7');
fprintf([ ...
    'Reference continuation cache: %s (t=%d -> %d, %.2fs)\n'], ...
    cachePath, sourceTime, targetTime, elapsedSeconds);
end

function [bundle, posteriors, history] = loadSourceBundle( ...
        path, presetName, seed, sourceTime, config)
if exist(path, 'file') ~= 2
    error('Missing opened source continuation cache: %s', path);
end
loaded = load(path, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Opened source cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
required = {'presetName', 'seed', 'snapshotTimes', 'configSnapshot'};
if ~all(isfield(bundle, required)) || ...
        ~strcmp(bundle.presetName, presetName) || ...
        bundle.seed ~= seed || ...
        ~isequal(bundle.snapshotTimes, sourceTime) || ...
        ~isequaln(bundle.configSnapshot, config)
    error('Opened source continuation cache provenance mismatch.');
end
[posteriors, history] = extractBehaviorContinuationSnapshot( ...
    bundle, sourceTime, config.numberOfSensors);
end

function config = buildReferenceConfig( ...
        protocol, scenarioConfig, targetTime, sourceTime, ...
        sourcePosteriors, sourceHistory)
config = buildMixtureAwareKlaReferenceConfig();
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.eventPolicy = 'alwaysHeavy';
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * scenarioConfig.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = protocol. ...
    valueGatedFormationFovValidationReferenceArmName;
config.topologyPosteriorCaptureTimes = targetTime;
policyOptions = struct( ...
    'dominantWeight', protocol. ...
        adaptiveDominantJointTrustStabilityReferenceWeight, ...
    'residualWeight', protocol. ...
        adaptiveDominantJointTrustStabilityResidualWeight);
config.topologyPolicyFcn = @(context) ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, 'fixed-counter-clockwise', policyOptions);
config.filterInitialLocalPosteriorBySensor = sourcePosteriors;
config.filterInitialLocalPosteriorTime = sourceTime;
policyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        sourceHistory.selectedDirectedEdgeHistory);
if ~isempty(policyHistory)
    config.filterInitialPreviousAdjacencyHistory = policyHistory;
    config.filterInitialPreviousAdjacencyTimes = sourceHistory.times;
    config.filterInitialPreviousAdjacencyHistorySource = ...
        'opened-behavior-cache-reference-replay-v1';
end
end

function diagnostics = attachSourceHistory(diagnostics, history)
for historyIdx = 1:numel(history.times)
    currentTime = history.times(historyIdx);
    diagnostics.topologyActiveEdge(:, :, currentTime) = ...
        history.selectedDirectedEdgeHistory(:, :, historyIdx);
    diagnostics.delivered(:, :, currentTime) = ...
        history.deliveredDirectedEdgeHistory(:, :, historyIdx);
end
end

function inputs = cropInputs(inputs, timeCount)
inputs.measurements = inputs.measurements(:, 1:timeCount);
inputs.model.simulationLength = timeCount;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:timeCount);
end
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:timeCount);
end
if isfield(inputs.commConfig, 'linkUniforms') && ...
        ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = ...
        inputs.commConfig.linkUniforms(:, :, 1:timeCount);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
