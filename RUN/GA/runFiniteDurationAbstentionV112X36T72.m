function [reportPath, result] = ...
        runFiniteDurationAbstentionV112X36T72(options)
% RUNFINITEDURATIONABSTENTIONV112X36T72 Paired duration label screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFiniteDurationAbstentionV112Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('FiniteDurationAbstentionV112:DirtySource', ...
        'The V112 label screen requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', protocol.executionProfile, ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', protocol.bankVariant, ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', 1:(1 + numel(protocol.candidateDurations)), ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', ...
        protocol.referenceOutcomeScreenPath, ...
    'capturePosteriorSnapshotsEnabled', false, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);
if ~screen.referenceOutcomeReused
    error('FiniteDurationAbstentionV112:ReferenceNotReused', ...
        'The frozen H=8 static outcome was unexpectedly rerun.');
end

referenceIdx = screen.referenceSubsetIndex;
reference = screen.records(referenceIdx);
referenceOutcome = screen.outcomes(referenceIdx);
referenceByTime = mean(referenceOutcome.eospaBySensorTime, 1);
targetMembers = find(screen.sensorGroupIds == protocol.targetFormationId);
residualSources = reshape( ...
    screen.bank.referencePolicyDetails.residualSourcesByReceiver, 1, []);
gatewayCandidates = targetMembers( ...
    screen.sensorGroupIds(residualSources(targetMembers)) ~= ...
        protocol.targetFormationId);
if numel(gatewayCandidates) ~= 1
    error('FiniteDurationAbstentionV112:GatewayDrift', ...
        'The target formation no longer has one cross-input gateway.');
end
targetPeers = setdiff( ...
    targetMembers, gatewayCandidates(1), 'stable');

labels = repmat(emptyLabel(), 1, numel(protocol.candidateDurations));
for durationIdx = 1:numel(protocol.candidateDurations)
    actionName = protocol.candidateActionNames{durationIdx};
    recordIdx = find(strcmp({screen.records.actionName}, actionName), 1);
    if isempty(recordIdx)
        error('FiniteDurationAbstentionV112:MissingArm', ...
            'The V112 bank did not produce action %s.', actionName);
    end
    candidate = screen.records(recordIdx);
    candidateOutcome = screen.outcomes(recordIdx);
    candidateByTime = mean(candidateOutcome.eospaBySensorTime, 1);
    gainByTime = relativeGainPercent(referenceByTime, candidateByTime);
    [formationGain, formationGainByTime] = formationGains( ...
        referenceOutcome.eospaBySensorTime, ...
        candidateOutcome.eospaBySensorTime, screen.sensorGroupIds);
    targetPeerTerminalGain = relativeGainPercent( ...
        mean(referenceOutcome.eospaBySensorTime(targetPeers, end)), ...
        mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));
    minimumAfterMaturityGain = min( ...
        gainByTime(protocol.firstHandoffTimeIndex:end));
    minimumFormationGain = min(formationGain);
    label = emptyLabel();
    label.durationSteps = protocol.candidateDurations(durationIdx);
    label.actionName = actionName;
    label.recordIndex = recordIdx;
    label.meanEospa = candidate.meanEospa;
    label.meanGainPercent = candidate.meanGainPercent;
    label.gainPercentByTime = gainByTime;
    label.formationGainPercent = formationGain;
    label.formationGainPercentByTime = formationGainByTime;
    label.minimumAfterMaturityGainPercent = ...
        minimumAfterMaturityGain;
    label.minimumFormationGainPercent = minimumFormationGain;
    label.worstDownstreamFormationRegretPercent = ...
        max(0, -minimumFormationGain);
    label.targetPeerTerminalGainPercent = targetPeerTerminalGain;
    label.worstSensorGainPercent = candidate.worstGainPercent;
    label.windowConsensusGainPercent = candidate.consensusGainPercent;
    label.terminalConsensusGainPercent = ...
        candidate.terminalConsensusGainPercent;
    label.attemptedByteSavingPercent = ...
        candidate.attemptedByteSavingPercent;
    label.selectedB3Passed = candidate.selectedB3Passed;
    label.elapsedSeconds = candidateOutcome.elapsedSeconds;
    label.gatePassed = ...
        label.meanGainPercent >= protocol.minimumMeanGainPercent - 1e-12 && ...
        label.minimumAfterMaturityGainPercent >= ...
            protocol.minimumMeanGainPercent - 1e-12 && ...
        label.worstSensorGainPercent >= ...
            protocol.minimumWorstSensorGainPercent - 1e-12 && ...
        label.minimumFormationGainPercent >= ...
            protocol.minimumFormationGainPercent - 1e-12 && ...
        label.targetPeerTerminalGainPercent >= ...
            protocol.minimumTargetPeerTerminalGainPercent - 1e-12 && ...
        label.windowConsensusGainPercent >= ...
            protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
        label.terminalConsensusGainPercent >= ...
            protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
        label.attemptedByteSavingPercent >= ...
            protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
        label.selectedB3Passed;
    labels(durationIdx) = label;
end

passing = find([labels.gatePassed]);
if isempty(passing)
    regret = [labels.worstDownstreamFormationRegretPercent];
    bestRegret = min(regret);
    tied = find(abs(regret - bestRegret) <= 1e-12);
    [~, bestWithinTie] = max([labels(tied).meanGainPercent]);
    oracleIndex = tied(bestWithinTie);
else
    [~, bestWithinPassing] = max([labels(passing).meanGainPercent]);
    oracleIndex = passing(bestWithinPassing);
end

result = struct();
result.contractVersion = protocol.resultContractVersion;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.referenceOutcomeReused = screen.referenceOutcomeReused;
result.referenceMeanEospa = reference.meanEospa;
result.referenceMeanEospaByTime = referenceByTime;
result.labels = labels;
result.oracleIndex = oracleIndex;
result.oracleDurationSteps = labels(oracleIndex).durationSteps;
result.oracleGatePassed = labels(oracleIndex).gatePassed;
result.anyGatePassed = any([labels.gatePassed]);
result.targetFormationId = protocol.targetFormationId;
result.targetPeerIndices = targetPeers;
result.screenReportPath = screenReportPath;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, [protocol.resultFileStem, '.mat']);
reportPath = fullfile(outputRoot, [protocol.resultFileStem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('%s result: %s\n', protocol.runLabel, reportPath);
end

function label = emptyLabel()
label = struct( ...
    'durationSteps', 0, ...
    'actionName', '', ...
    'recordIndex', 0, ...
    'meanEospa', nan, ...
    'meanGainPercent', nan, ...
    'gainPercentByTime', [], ...
    'formationGainPercent', [], ...
    'formationGainPercentByTime', [], ...
    'minimumAfterMaturityGainPercent', nan, ...
    'minimumFormationGainPercent', nan, ...
    'worstDownstreamFormationRegretPercent', nan, ...
    'targetPeerTerminalGainPercent', nan, ...
    'worstSensorGainPercent', nan, ...
    'windowConsensusGainPercent', nan, ...
    'terminalConsensusGainPercent', nan, ...
    'attemptedByteSavingPercent', nan, ...
    'selectedB3Passed', false, ...
    'elapsedSeconds', nan, ...
    'gatePassed', false);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FiniteDurationAbstentionV112:WriteFailed', ...
        'Could not create the V112 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# %s\n\n', result.protocol.reportTitle);
fprintf(fid, '- Matched baseline: `%s`\n', result.protocol.baselineName);
fprintf(fid, '- Frozen H=8 reference reused: `%d`\n', ...
    result.referenceOutcomeReused);
fprintf(fid, '- Oracle duration: `%d` step(s)\n', ...
    result.oracleDurationSteps);
fprintf(fid, '- Any candidate passed: `%d`\n\n', result.anyGatePassed);
fprintf(fid, ['| Duration | Mean E-OSPA | Gain | Min post-maturity | ', ...
    'Min formation | Downstream regret | F6 peers | Byte saving | ', ...
    'Window cons. | Terminal cons. | Gate |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for idx = 1:numel(result.labels)
    label = result.labels(idx);
    fprintf(fid, ['| %d | %.6f | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        label.durationSteps, label.meanEospa, label.meanGainPercent, ...
        label.minimumAfterMaturityGainPercent, ...
        label.minimumFormationGainPercent, ...
        label.worstDownstreamFormationRegretPercent, ...
        label.targetPeerTerminalGainPercent, ...
        label.attemptedByteSavingPercent, ...
        label.windowConsensusGainPercent, ...
        label.terminalConsensusGainPercent, label.gatePassed);
end
oracle = result.labels(result.oracleIndex);
fprintf(fid, '\n## Oracle label\n\n');
fprintf(fid, '- Action: `%s`\n', oracle.actionName);
fprintf(fid, '- Formation gains: `%s%%`\n', ...
    mat2str(oracle.formationGainPercent, 4));
fprintf(fid, '- Per-page gains: `%s%%`\n', ...
    mat2str(oracle.gainPercentByTime, 4));
fprintf(fid, '- Gate passed: `%d`\n\n', oracle.gatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function [gain, gainByTime] = formationGains( ...
        referenceBySensorTime, candidateBySensorTime, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
gain = zeros(1, numel(groups));
gainByTime = zeros(numel(groups), size(referenceBySensorTime, 2));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    referenceValues = referenceBySensorTime(mask, :);
    candidateValues = candidateBySensorTime(mask, :);
    gain(idx) = relativeGainPercent( ...
        mean(referenceValues(:)), mean(candidateValues(:)));
    gainByTime(idx, :) = relativeGainPercent( ...
        mean(referenceValues, 1), mean(candidateValues, 1));
end
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
