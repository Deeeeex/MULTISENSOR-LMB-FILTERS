function actionIndices = formationSubsetsToActionIndices(subsets)
actionIndices = zeros(1, numel(subsets));
for timeIdx = 1:numel(subsets)
    formationIds = reshape(subsets{timeIdx}, 1, []);
    if any(~isfinite(formationIds)) || ...
            any(formationIds ~= round(formationIds)) || ...
            any(formationIds < 1) || ...
            numel(unique(formationIds)) ~= numel(formationIds)
        error('FormationModeScreen:InvalidRuntimeFingerprintContract', ...
            'Runtime formation subset is invalid.');
    end
    actionIndices(timeIdx) = 1 + sum(2 .^ (formationIds - 1));
end
end

function assertObservableRuntimeContracts( ...
        enabledByTime, contractsByTime, returnTimes)
requiredFlags = { ...
    'enforced', 'targetTruthAbsent', 'fullDynamicScenarioAbsent', ...
    'modelStaticFusionInputsOnly', 'modelObjectTemplateEmpty', ...
    'triggerConfigStaticFusionInputsOnly', ...
    'triggerConfigPrimitiveValuesOnly', ...
    'linkUniformsAbsent', 'futurePDropPagesAbsent', ...
    'sensorTrajectoriesAbsent', 'currentPositionsOnly', ...
    'currentPosteriorPresent', ...
    'posteriorSchemaRestricted', ...
    'posteriorTrajectoryFieldsAbsent', ...
    'contextHasNoFunctionHandles', ...
    'contextUsesPrimitiveContainersOnly', ...
    'causalArraySchemaRestricted', ...
    'currentPosteriorHasNoFutureTimestamps', ...
    'pastTopologyHistoryOnly', ...
    'nonfutureUpdateHistoryOnly', 'modelScenarioGroupIdsOnly', ...
    'passed'};
if ~isequal(size(enabledByTime), size(returnTimes)) || ...
        ~all(enabledByTime) || ...
        ~iscell(contractsByTime) || ...
        ~isequal(size(contractsByTime), size(returnTimes))
    error('FormationModeScreen:ObservableContextDrift', ...
        'The runtime policy was not restricted to observable inputs.');
end
for timeIdx = 1:numel(returnTimes)
    contract = contractsByTime{timeIdx};
    if ~isstruct(contract) || ~isscalar(contract) || ...
            ~isfield(contract, 'contractVersion') || ...
            ~strcmp(contract.contractVersion, ...
                'topology-policy-observable-input-v2') || ...
            ~isfield(contract, 'currentTime') || ...
            contract.currentTime ~= returnTimes(timeIdx) || ...
            ~all(isfield(contract, requiredFlags)) || ...
            ~all(cellfun(@(name) islogical(contract.(name)) && ...
                isscalar(contract.(name)) && contract.(name), ...
                requiredFlags)) || ...
            ~isfield(contract, 'forbiddenFieldPaths') || ...
            ~iscell(contract.forbiddenFieldPaths) || ...
            ~isempty(contract.forbiddenFieldPaths)
        error('FormationModeScreen:ObservableContextDrift', ...
            'An observable-input contract failed at time %d.', ...
            returnTimes(timeIdx));
    end
end
end

function [adjacency, details] = frozenActionSequence( ...
        context, anchorTime, bank, actionSequenceIndices, protocol)
relativeTime = context.currentTime - anchorTime + 1;
if relativeTime >= 1 && relativeTime <= numel(actionSequenceIndices)
    actionIdx = actionSequenceIndices(relativeTime);
else
    actionIdx = bank.referenceActionIndex;
end
if actionIdx ~= bank.referenceActionIndex
    adjacency = logical(bank.actionAdjacency(:, :, actionIdx));
    weights = bank.actionFusionWeights(:, :, actionIdx);
    weightSupport = adjacency | eye(size(adjacency, 1)) > 0;
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:))) || ...
            ~isequal(size(weights), size(adjacency)) || ...
            any(weights(:) < 0) || ...
            any(weights(~weightSupport) > 1e-12)
        error('Frozen formation-mode sequence action is invalid.');
    end
    details = struct( ...
        'mode', 'frozen-formation-mode-action-sequence', ...
        'fusionWeightMatrix', weights, ...
        'truthUsed', false, ...
        'groundTruthUsed', false, ...
        'futureOutcomeUsed', false, ...
        'runtimeFrozenGraphReplay', true, ...
        'actionSequenceIndices', actionSequenceIndices, ...
        'actionSequenceRelativeTime', relativeTime);
else
    if isfield(bank, 'referenceMode') && ...
            strcmp(bank.referenceMode, 'current-physical-tree')
        [adjacency, details] = ...
            selectTemporalFormationBackboneInputBundleSuspensionPolicy( ...
                context, zeros(1, 0), struct( ...
                    'referenceMode', 'current-physical-tree'));
    else
        [adjacency, details] = ...
            selectBackboneResidualSplicedCyclePolicy( ...
                context, 'fixed-counter-clockwise', ...
                referencePolicyOptions(protocol));
    end
    details.runtimeFrozenGraphReplay = false;
    details.actionSequenceIndices = actionSequenceIndices;
    details.actionSequenceRelativeTime = relativeTime;
end
end

