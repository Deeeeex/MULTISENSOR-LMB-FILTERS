        fprintf(fid, '- Risk coverage target / achieved: `%.1f%% / %.1f%%`\n', ...
            100 * screen.bank.riskCoverageTargetFraction, ...
            100 * screen.bank.riskCoverageAchievedFraction);
        fprintf(fid, '- Risk-coverage formations: `%s`\n', ...
            mat2str(screen.bank.riskCoverageFormationIds));
    end
end
fprintf(fid, '- Proxy positive / realized positive: `%d / %d`\n', ...
    screen.posteriorProxyPositiveCount, ...
    screen.realizedMeanPositiveCount);
fprintf(fid, '- Proxy TP / FP / FN: `%d / %d / %d`\n', ...
    screen.proxyTruePositiveCount, ...
    screen.proxyFalsePositiveCount, ...
    screen.proxyFalseNegativeCount);
fprintf(fid, '- Proxy action agreement: `%.3f`\n', ...
    screen.proxyActionAgreementFraction);
fprintf(fid, '- Best mean gain: `%+.3f%%`\n', ...
    screen.bestMeanGainPercent);
fprintf(fid, '- Best tail-safe mean gain: `%+.3f%%`\n\n', ...
    screen.bestTailSafeMeanGainPercent);
if screen.horizonSteps > 3
    fprintf(fid, [ ...
        '| Action | Form. | Mode | Trust | Proxy obj. | Proxy allow | ', ...
        'Mean gain | Worst gain | Min form. gain | Window cons. | ', ...
        'Terminal cons. | Byte saving | B3 |\n']);
    fprintf(fid, [ ...
        '|:--|--:|--:|--:|--:|:--:|--:|--:|--:|--:|--:|--:|', ...
        ':--:|\n']);
else
    fprintf(fid, [ ...
        '| Action | Form. | Mode | Trust | Proxy obj. | Proxy allow | ', ...
        'Mean gain | Worst gain | Min form. gain | Cons. gain | ', ...
        'Byte saving | B3 |\n']);
    fprintf(fid, ...
        '|:--|--:|--:|--:|--:|:--:|--:|--:|--:|--:|--:|:--:|\n');
end
for record = screen.records
    formationText = formatFormationIndices( ...
        record.formationIndices);
    if screen.horizonSteps > 3
        fprintf(fid, [ ...
            '| `%s` | %s | %d | %.2f | %+.6f | %d | ', ...
            '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
            '%+.3f%% | %d |\n'], ...
            record.actionName, formationText, ...
            record.modeIndex, record.trustWeight, ...
            record.posteriorProxyObjective, ...
            record.posteriorProxyAllowed, ...
            record.meanGainPercent, record.worstGainPercent, ...
            record.minimumFormationGainPercent, ...
            record.consensusGainPercent, ...
            record.terminalConsensusGainPercent, ...
            record.attemptedByteSavingPercent, ...
            record.selectedB3Passed);
    else
        fprintf(fid, [ ...
            '| `%s` | %s | %d | %.2f | %+.6f | %d | ', ...
            '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
            '%+.3f%% | %d |\n'], ...
            record.actionName, formationText, ...
            record.modeIndex, record.trustWeight, ...
            record.posteriorProxyObjective, ...
            record.posteriorProxyAllowed, ...
            record.meanGainPercent, record.worstGainPercent, ...
            record.minimumFormationGainPercent, ...
            record.consensusGainPercent, ...
            record.attemptedByteSavingPercent, ...
            record.selectedB3Passed);
    end
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    screen.evidenceBoundary);
end

function values = validateExpectedRuntimeFingerprints(values, armCount)
if ~iscell(values) || numel(values) ~= armCount
    error('FormationModeScreen:InvalidRuntimeFingerprintContract', ...
        'Expected runtime fingerprints must contain one value per arm.');
end
values = reshape(values, 1, []);
for armIdx = 1:armCount
    value = values{armIdx};
    if ~ischar(value) || ...
            (~isempty(value) && isempty(regexp( ...
                value, '^[0-9a-f]{64}$', 'once')))
        error('FormationModeScreen:InvalidRuntimeFingerprintContract', ...
            'Expected runtime fingerprint is not a lowercase SHA-256.');
    end
end
end

function value = formatFormationIndices(indices)
indices = reshape(indices, 1, []);
indices = indices(indices > 0);
if isempty(indices)
    value = '0';
elseif numel(indices) == 1
    value = sprintf('%d', indices);
else
    value = strtrim(sprintf('%d+', indices));
    value = value(1:(end - 1));
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
