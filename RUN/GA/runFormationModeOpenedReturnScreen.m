function [reportPath, screen] = ...
    runFormationModeOpenedReturnScreen( ...
        presetName, seed, currentTime, options)
% RUNFORMATIONMODEOPENEDRETURNSCREEN Formation-local opened teacher screen.
%
% A current posterior and topology history are loaded from an already-opened
% continuation cache.  The truth-free v10 machinery constructs the current
% reference/candidate trust-mode bank.  By default, each arm changes one
% formation for the registered duration and then returns to the reference.
% The optional actionSequenceIndices matrix instead replays an explicit
% frozen sequence with horizonSteps columns; action index 1 recomputes the
% registered reference at that step.  Truth and future measurements score
% offline targets only.  H=3 retains the historical screen contracts.

if nargin < 4 || isempty(options)
    options = struct();
end
if ~ischar(presetName) || ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || seed < 1 || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || currentTime < 1
    error('Formation-mode opened screen request is invalid.');
end
protocol = getLabelSetSimulatorPolicyProtocol();
receiverMode = normalizeReceiverMode(getField( ...
    options, 'receiverMode', 'support-renormalized'));
horizonSteps = getField(options, 'horizonSteps', 3);
if ~isscalar(horizonSteps) || ~isfinite(horizonSteps) || ...
        horizonSteps ~= round(horizonSteps) || horizonSteps < 3
    error('Formation-mode opened-screen horizon must be an integer >= 3.');
end
horizonSteps = round(horizonSteps);
interventionDurationSteps = getField( ...
    options, 'interventionDurationSteps', 1);
if ~isscalar(interventionDurationSteps) || ...
        ~isfinite(interventionDurationSteps) || ...
        interventionDurationSteps ~= round(interventionDurationSteps) || ...
        interventionDurationSteps < 1 || ...
        interventionDurationSteps > horizonSteps
    error('Formation-mode intervention duration is invalid.');
end
interventionDurationSteps = round(interventionDurationSteps);
filterSeedOffset = round(getField(options, ...
    'filterSeedOffset', 100000));
if filterSeedOffset ~= 100000
    error('Formation-mode opened screen requires the formal RNG offset.');
end
cacheRoot = getField(options, 'cacheRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'posterior_risk_v10', 'opened_state_audit', 'cache'));
interventionBankType = lower(strrep(char(getField( ...
    options, 'interventionBankType', ...
    'formation-local-single')), '_', '-'));
switch interventionBankType
    case 'formation-local-single'
        if horizonSteps == 3
            defaultOutputRoot = 'formation_mode_h3_v11';
        else
            defaultOutputRoot = sprintf( ...
                'formation_mode_h%d', horizonSteps);
        end
        screenContractVersion = sprintf( ...
            'formation-local-h%d-opened-return-screen-v1', ...
            horizonSteps);
    case 'formation-conservative-pair'
        if horizonSteps == 3
            defaultOutputRoot = 'formation_pair_h3_v12';
        else
            defaultOutputRoot = sprintf( ...
                'formation_pair_h%d', horizonSteps);
        end
        screenContractVersion = sprintf( ...
            ['formation-conservative-pair-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'formation-projected-joint'
        if horizonSteps == 3
            defaultOutputRoot = 'formation_joint_h3_v15';
        else
            defaultOutputRoot = sprintf( ...
                'formation_joint_h%d', horizonSteps);
        end
        screenContractVersion = sprintf( ...
            ['formation-projected-joint-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'formation-single-plus-pair'
        if horizonSteps == 3
            defaultOutputRoot = 'formation_sequence_h3_v19';
        else
            defaultOutputRoot = sprintf( ...
                'formation_sequence_h%d', horizonSteps);
        end
        screenContractVersion = sprintf( ...
            ['formation-single-plus-pair-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'formation-local-pair-coordinated-subset'
        if horizonSteps == 3
            defaultOutputRoot = 'formation_sequence_h3_v20';
        else
            defaultOutputRoot = sprintf( ...
                'formation_coordinated_h%d', horizonSteps);
        end
        screenContractVersion = sprintf( ...
            ['formation-local-pair-coordinated-subset-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'formation-exhaustive-mode-vector'
        if horizonSteps == 3
            defaultOutputRoot = 'formation_mode_vector_h3_v21';
        else
            defaultOutputRoot = sprintf( ...
                'formation_mode_vector_h%d', horizonSteps);
        end
        screenContractVersion = sprintf( ...
            ['formation-exhaustive-mode-vector-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'scale-aware-formation-mixing'
        defaultOutputRoot = sprintf( ...
            'formation_scale_aware_mixing_h%d_v27', horizonSteps);
        screenContractVersion = sprintf( ...
            ['scale-aware-formation-mixing-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'conflict-aware-formation-mixing'
        defaultOutputRoot = sprintf( ...
            'formation_conflict_aware_mixing_h%d_v28', horizonSteps);
        screenContractVersion = sprintf( ...
            ['conflict-aware-formation-mixing-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'temporal-cross-edge-suspension'
        defaultOutputRoot = sprintf( ...
            'formation_temporal_suspension_h%d_v29', horizonSteps);
        screenContractVersion = sprintf( ...
            ['temporal-cross-edge-suspension-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'formation-isolate-reconnect'
        defaultOutputRoot = sprintf( ...
            'formation_isolate_reconnect_h%d_v30', horizonSteps);
        screenContractVersion = sprintf( ...
            ['formation-isolate-reconnect-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'formation-staggered-recovery'
        defaultOutputRoot = sprintf( ...
            'formation_staggered_recovery_h%d_v35', horizonSteps);
        screenContractVersion = sprintf( ...
            ['formation-staggered-recovery-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'tracking-aligned-formation-local'
        defaultOutputRoot = sprintf( ...
            'tracking_aligned_formation_h%d_v56', horizonSteps);
        screenContractVersion = sprintf( ...
            ['tracking-aligned-formation-local-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'tracking-aligned-formation-joint'
        defaultOutputRoot = sprintf( ...
            'tracking_aligned_formation_joint_h%d_v57', horizonSteps);
        screenContractVersion = sprintf( ...
            ['tracking-aligned-formation-joint-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'tracking-aligned-formation-protection-joint'
        defaultOutputRoot = sprintf( ...
            'tracking_aligned_protection_joint_h%d_v57', horizonSteps);
        screenContractVersion = sprintf( ...
            ['tracking-aligned-formation-protection-joint-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'tracking-aligned-receiver-label'
        defaultOutputRoot = sprintf( ...
            'tracking_aligned_receiver_label_h%d_v61', horizonSteps);
        screenContractVersion = sprintf( ...
            ['tracking-aligned-receiver-label-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'tracking-aligned-layered-label'
        defaultOutputRoot = sprintf( ...
            'tracking_aligned_layered_label_h%d_v62', horizonSteps);
        screenContractVersion = sprintf( ...
            ['tracking-aligned-layered-label-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'tracking-aligned-x36-schedule'
        defaultOutputRoot = sprintf( ...
            'tracking_aligned_x36_schedule_h%d_v63', horizonSteps);
        screenContractVersion = sprintf( ...
            ['tracking-aligned-x36-schedule-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'receiver-domain-transport-v71'
        defaultOutputRoot = sprintf( ...
            'receiver_domain_transport_h%d_v72', horizonSteps);
        screenContractVersion = sprintf( ...
            ['receiver-domain-transport-h%d-', ...
             'opened-return-screen-v1'], horizonSteps);
    case 'braided-handover-transport-v84'
        defaultOutputRoot = sprintf( ...
            'braided_handover_transport_h%d_v84', horizonSteps);
        screenContractVersion = sprintf( ...
            ['braided-handover-transport-h%d-', ...
             'opened-return-screen-v84-v1'], horizonSteps);
    case 'temporal-acquire-broadcast-v86'
        defaultOutputRoot = sprintf( ...
            'temporal_acquire_broadcast_h%d_v86', horizonSteps);
        screenContractVersion = sprintf( ...
            ['temporal-acquire-broadcast-h%d-', ...
             'opened-return-screen-v86-v1'], horizonSteps);
    case 'time-expanded-path-selective-v88'
        defaultOutputRoot = sprintf( ...
            'time_expanded_path_selective_h%d_v88', horizonSteps);
        screenContractVersion = sprintf( ...
            ['time-expanded-path-selective-h%d-', ...
             'opened-return-screen-v88-v1'], horizonSteps);
    case 'network-budget-reallocated-multi-source-v95'
        defaultOutputRoot = sprintf( ...
            'network_budget_reallocated_h%d_v95', horizonSteps);
        screenContractVersion = sprintf( ...
            ['network-budget-reallocated-multi-source-h%d-', ...
             'opened-return-screen-v95-v1'], horizonSteps);
    otherwise
        error('Unknown formation-mode intervention bank type.');
end
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    defaultOutputRoot, 'opened_return_screen', presetName));
writeReportEnabled = logical(getField(options, 'writeReport', true));
allowDirtySource = logical(getField(options, 'allowDirtySource', false));
capturePosteriorSnapshotsEnabled = logical(getField( ...
    options, 'capturePosteriorSnapshotsEnabled', false));
referenceOutcomeScreenPath = char(getField( ...
    options, 'referenceOutcomeScreenPath', ''));

gitState = resolveResearchGitState();
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official formation-mode return generation requires a ', ...
        'clean tracked and MATLAB/Octave source state.']);
end
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
truthFields = { ...
    'groundTruth', 'groundTruthRfs', 'targetTrajectories'};
if ~all(isfield(inputs, truthFields))
    error('FormationModeScreen:MissingTruthBoundary', ...
        'Scenario truth cannot be isolated from policy inputs.');
end
trackingTruthRfs = inputs.groundTruthRfs;
inputs = rmfield(inputs, truthFields);
inputs.model = removeExplicitTargetTruth(inputs.model);
truthFieldsRemoved = [truthFields, { ...
    'model.explicitTargetTrajectories', ...
    'model.dynamicTopologyScenario.targetTrajectories', ...
    'model.dynamicTopologyScenario.target'}];
returnTimes = currentTime + (0:(horizonSteps - 1));
if returnTimes(end) > size(inputs.measurements, 2)
    error('Formation-mode opened return exceeds the scenario length.');
end
trackingTruthRfs = cropTrackingTruthRfs( ...
    trackingTruthRfs, returnTimes(end));
cachePath = fullfile(cacheRoot, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', strrep(presetName, '-', '_'), ...
    seed, currentTime));
bundle = loadOpenedBundle( ...
    cachePath, presetName, seed, currentTime, inputs.config, ...
    receiverMode);
cacheSha256 = computeFileSha256(cachePath);
context = buildOpenedContext( ...
    inputs, bundle, currentTime, receiverMode);

groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
scaleAwareBank = strcmp(interventionBankType, ...
    'scale-aware-formation-mixing');
conflictAwareBank = strcmp(interventionBankType, ...
    'conflict-aware-formation-mixing');
temporalSuspensionBank = strcmp(interventionBankType, ...
    'temporal-cross-edge-suspension');
isolateReconnectBank = strcmp(interventionBankType, ...
    'formation-isolate-reconnect');
staggeredRecoveryBank = strcmp(interventionBankType, ...
    'formation-staggered-recovery');
trackingAlignedLocalBank = strcmp(interventionBankType, ...
    'tracking-aligned-formation-local');
trackingAlignedJointBank = strcmp(interventionBankType, ...
    'tracking-aligned-formation-joint');
trackingAlignedProtectionBank = strcmp(interventionBankType, ...
    'tracking-aligned-formation-protection-joint');
receiverLabelBank = strcmp(interventionBankType, ...
    'tracking-aligned-receiver-label');
layeredLabelBank = strcmp(interventionBankType, ...
    'tracking-aligned-layered-label');
x36ScheduleBank = strcmp(interventionBankType, ...
    'tracking-aligned-x36-schedule');
receiverDomainTransportBank = strcmp(interventionBankType, ...
    'receiver-domain-transport-v71');
braidedHandoverTransportBank = strcmp(interventionBankType, ...
    'braided-handover-transport-v84');
temporalAcquireBroadcastBank = strcmp(interventionBankType, ...
    'temporal-acquire-broadcast-v86');
timeExpandedPathSelectiveBank = strcmp(interventionBankType, ...
    'time-expanded-path-selective-v88');
networkBudgetReallocationBank = strcmp(interventionBankType, ...
    'network-budget-reallocated-multi-source-v95');
temporalGatewayBank = temporalAcquireBroadcastBank || ...
    timeExpandedPathSelectiveBank;
receiverTransportBank = ...
    receiverDomainTransportBank || braidedHandoverTransportBank || ...
    temporalGatewayBank || networkBudgetReallocationBank;
trackingAlignedBank = ...
    trackingAlignedLocalBank || trackingAlignedJointBank || ...
    trackingAlignedProtectionBank;
trackingAlignedExecutionProfile = lower(strrep(char(getField( ...
    options, 'trackingAlignedExecutionProfile', 'v56')), '_', '-'));
if ~ismember(trackingAlignedExecutionProfile, { ...
        'v56', 'v59-routing-leverage-headroom', ...
        'v61-receiver-label-headroom', ...
        'v62-layered-label-headroom', ...
        'v63-x36-schedule-headroom', ...
        'v64-risk-coverage-headroom', ...
        'v65-network-additive-headroom', ...
        'v96-addressable-risk-adaptive-payload', ...
        'v97-positive-net-addressable-payload', ...
        'v99-online-positive-net-addressable-payload', ...
        'v100-online-positive-net-propagation', ...
        'v101-propagation-aware-dwell', ...
        'v102-shield-broadcast', ...
        'v103-matured-handoff', ...
        'v104-receiver-selective-handoff', ...
        'v105-protection-only-h8', ...
        'v106-protection-release-oracle', ...
        'v107-protection-early-release-oracle', ...
        'v108-signed-complete-label-exception', ...
        'v72-receiver-domain-transport-h3', ...
        'v84-braided-handover-primary-h3', ...
        'v86-temporal-acquire-broadcast-primary-h3', ...
        'v88-time-expanded-path-selective-primary-h3', ...
        'v95-network-budget-reallocated-multi-source'}) || ...
        (~trackingAlignedBank && ...
         ~receiverLabelBank && ...
         ~layeredLabelBank && ...
         ~x36ScheduleBank && ~receiverTransportBank && ...
         ~strcmp(trackingAlignedExecutionProfile, 'v56')) || ...
        (receiverLabelBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v61-receiver-label-headroom')) || ...
    (layeredLabelBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v62-layered-label-headroom')) || ...
        (x36ScheduleBank && ...
         ~ismember(trackingAlignedExecutionProfile, { ...
            'v63-x36-schedule-headroom', ...
            'v64-risk-coverage-headroom', ...
            'v65-network-additive-headroom', ...
            'v96-addressable-risk-adaptive-payload', ...
            'v97-positive-net-addressable-payload', ...
            'v99-online-positive-net-addressable-payload', ...
            'v100-online-positive-net-propagation', ...
            'v101-propagation-aware-dwell', ...
            'v102-shield-broadcast', ...
            'v103-matured-handoff', ...
            'v104-receiver-selective-handoff', ...
            'v105-protection-only-h8', ...
            'v106-protection-release-oracle', ...
            'v107-protection-early-release-oracle', ...
            'v108-signed-complete-label-exception'})) || ...
        (receiverDomainTransportBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v72-receiver-domain-transport-h3')) || ...
        (braidedHandoverTransportBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v84-braided-handover-primary-h3')) || ...
        (temporalAcquireBroadcastBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v86-temporal-acquire-broadcast-primary-h3')) || ...
        (timeExpandedPathSelectiveBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v88-time-expanded-path-selective-primary-h3')) || ...
        (networkBudgetReallocationBank && ...
         ~strcmp(trackingAlignedExecutionProfile, ...
            'v95-network-budget-reallocated-multi-source'))
    error('FormationModeScreen:InvalidTrackingExecutionProfile', ...
        'The tracking-aligned execution profile is not registered.');
end
runtimeRecoveryBank = ...
    isolateReconnectBank || staggeredRecoveryBank;
temporalInitialBank = ...
    temporalSuspensionBank || runtimeRecoveryBank || ...
    trackingAlignedProtectionBank;
if timeExpandedPathSelectiveBank
    pathOptions = getField(options, ...
        'timeExpandedPathSelectiveBankOptions', struct());
    pathOptions.presetName = presetName;
    pathOptions.seed = seed;
    pathOptions.currentTime = currentTime;
    timerId = tic;
    bank = buildTimeExpandedPathSelectiveV88ActionBank( ...
        context, pathOptions);
    bankConstructionSeconds = toc(timerId);
elseif temporalAcquireBroadcastBank
    temporalOptions = getField(options, ...
        'temporalAcquireBroadcastBankOptions', struct());
    temporalOptions.presetName = presetName;
    temporalOptions.seed = seed;
    temporalOptions.currentTime = currentTime;
    timerId = tic;
    bank = buildTemporalAcquireBroadcastV86ActionBank( ...
        context, temporalOptions);
    bankConstructionSeconds = toc(timerId);
elseif braidedHandoverTransportBank
    braidedOptions = getField(options, ...
        'braidedHandoverTransportBankOptions', struct());
    braidedOptions.presetName = presetName;
    braidedOptions.seed = seed;
    braidedOptions.currentTime = currentTime;
    timerId = tic;
    bank = buildBraidedHandoverH3V84ActionBank( ...
        context, braidedOptions);
    bankConstructionSeconds = toc(timerId);
elseif networkBudgetReallocationBank
    reallocationOptions = getField(options, ...
        'networkBudgetReallocationBankOptions', struct());
    reallocationOptions.horizonSteps = horizonSteps;
    timerId = tic;
    bank = buildNetworkBudgetReallocatedMultiSourceV95ActionBank( ...
        context, reallocationOptions);
    bankConstructionSeconds = toc(timerId);
elseif receiverDomainTransportBank
    receiverDomainBankOptions = getField(options, ...
        'receiverDomainTransportBankOptions', struct());
    receiverDomainBankOptions.presetName = presetName;
    receiverDomainBankOptions.seed = seed;
    receiverDomainBankOptions.currentTime = currentTime;
    timerId = tic;
    bank = buildReceiverDomainTransportActionBankV71( ...
        context, receiverDomainBankOptions);
    bankConstructionSeconds = toc(timerId);
elseif x36ScheduleBank
    timerId = tic;
    bank = buildTrackingAlignedX36ScheduleActionBank( ...
        context, groupIds, getField(options, ...
            'trackingAlignedX36ScheduleBankOptions', struct()));
    bankConstructionSeconds = toc(timerId);
elseif layeredLabelBank
    timerId = tic;
    bank = buildTrackingAlignedLayeredLabelActionBank( ...
        context, getField(options, ...
            'trackingAlignedLayeredLabelBankOptions', struct()));
    bankConstructionSeconds = toc(timerId);
elseif receiverLabelBank
    timerId = tic;
    bank = buildTrackingAlignedReceiverLabelActionBank( ...
        context, getField(options, ...
            'trackingAlignedReceiverLabelBankOptions', struct()));
    bankConstructionSeconds = toc(timerId);
elseif scaleAwareBank
    timerId = tic;
    bank = buildScaleAwareFormationMixingActionBank( ...
        context, getField(options, 'scaleAwareBankOptions', struct()));
    bankConstructionSeconds = toc(timerId);
elseif conflictAwareBank
    timerId = tic;
    bank = buildConflictAwareFormationMixingActionBank( ...
        context, getField(options, ...
            'conflictAwareBankOptions', struct()));
    bankConstructionSeconds = toc(timerId);
elseif temporalInitialBank
    timerId = tic;
    bank = buildTemporalCrossEdgeSuspensionActionBank( ...
        context, getField(options, ...
            'temporalSuspensionBankOptions', struct()));
    bankConstructionSeconds = toc(timerId);
else
    policyOptions = buildPosteriorRiskPolicyOptions(protocol);
    timerId = tic;
    [selectedPolicyAdjacency, v10Details] = ...
        selectLabelSetAdaptiveDominantRoutingPolicy( ...
            context, ...
            ['composite-balanced-certified-overlap-consensus-', ...
             'joint-trust-posterior-risk-tail-safe-payload-aware'], ...
            policyOptions);
    bankConstructionSeconds = toc(timerId);
    projection = v10Details.consensusProjection;
    assertV10BankContract(v10Details, projection);
    switch interventionBankType
        case 'formation-local-single'
            bank = buildFormationModeInterventionBank( ...
                projection, groupIds);
        case 'formation-conservative-pair'
            bank = buildConservativePairFormationModeInterventionBank( ...
                projection, groupIds, struct('pairTrustWeight', 0.30));
        case 'formation-projected-joint'
            bank = buildProjectedJointFormationModeInterventionBank( ...
                projection, groupIds);
            assertProjectedJointMatchesPolicy( ...
                bank, selectedPolicyAdjacency, ...
                v10Details.fusionWeightMatrix);
        case 'formation-single-plus-pair'
            bank = buildCombinedFormationModeInterventionBank( ...
                projection, groupIds, struct('pairTrustWeight', 0.30));
        case 'formation-local-pair-coordinated-subset'
            bank = buildExpandedFormationModeInterventionBank( ...
                projection, groupIds, struct( ...
                    'pairTrustWeight', 0.30, ...
                    'subsetTrustWeight', 0.30, ...
                    'subsetOrders', [3, 4]));
        case 'formation-exhaustive-mode-vector'
            bank = buildExhaustiveFormationModeVectorInterventionBank( ...
                projection, groupIds, ...
                struct('maximumActionCount', 4096));
        case 'tracking-aligned-formation-local'
            sourceTrustBank = buildFormationModeInterventionBank( ...
                projection, groupIds);
            bank = buildTrackingAlignedFormationModeBank( ...
                context, sourceTrustBank, groupIds, ...
                getField(options, ...
                    'trackingAlignedBankOptions', struct()));
        case 'tracking-aligned-formation-joint'
            bank = buildExhaustiveFormationModeVectorInterventionBank( ...
                projection, groupIds, ...
                struct('maximumActionCount', 15625));
    end
end
assertReferenceMatchesRegisteredPolicy( ...
    context, bank, protocol);

explicitActionSequences = getField( ...
    options, 'actionSequenceIndices', []);
sequenceMode = ~isempty(explicitActionSequences);
if sequenceMode
    actionSequenceIndices = validateActionSequences( ...
        explicitActionSequences, bank, horizonSteps);
    if temporalGatewayBank
        if timeExpandedPathSelectiveBank
            temporalProtocol = ...
                getTimeExpandedPathSelectiveV88Protocol();
        else
            temporalProtocol = ...
                getTemporalAcquireBroadcastV86Protocol();
        end
        if ~isequal(actionSequenceIndices, ...
                temporalProtocol.actionSequenceIndices)
            error('FormationModeScreen:InvalidTemporalGatewaySequence', ...
                ['The temporal gateway arm opens only ', ...
                 'reference/reference/reference and ', ...
                 'acquire/broadcast/reference.']);
        end
    end
    if conflictAwareBank && any( ...
            ~bank.actionPosteriorSafetyMask( ...
                actionSequenceIndices(:)))
        error(['Conflict-aware explicit sequence contains an action ', ...
            'that failed the frozen posterior safety projection.']);
    end
    if temporalInitialBank && any( ...
            ~bank.actionPosteriorSafetyMask( ...
                actionSequenceIndices(:)))
        error(['Temporal-suspension explicit sequence contains an ', ...
            'action that failed the frozen safety projection.']);
    end
    actionIndices = reshape(actionSequenceIndices(:, 1), 1, []);
else
    if scaleAwareBank
        defaultActionIndices = 1:bank.actionCount;
    elseif conflictAwareBank
        defaultActionIndices = bank.safeActionIndices;
    elseif temporalInitialBank
        defaultActionIndices = bank.safeActionIndices;
    elseif trackingAlignedBank || receiverLabelBank || ...
            layeredLabelBank || x36ScheduleBank || ...
            receiverTransportBank
        defaultActionIndices = find( ...
            bank.actionWithinReferencePayload & ...
            bank.actionPosteriorProxyAllowed);
    else
        defaultActionIndices = find( ...
            bank.actionWithinReferencePayload);
    end
    actionIndices = reshape(getField( ...
        options, 'actionIndices', defaultActionIndices), 1, []);
    if isempty(actionIndices) || ...
            any(~isfinite(actionIndices)) || ...
            any(actionIndices ~= round(actionIndices)) || ...
            any(actionIndices < 1) || ...
            any(actionIndices > bank.actionCount) || ...
            numel(unique(actionIndices)) ~= numel(actionIndices) || ...
            ~any(actionIndices == bank.referenceActionIndex)
        error('Formation-mode opened-screen action subset is invalid.');
    end
    if ~scaleAwareBank && ~conflictAwareBank && ...
            ~temporalInitialBank && ...
            any(~bank.actionWithinReferencePayload(actionIndices))
        error('Formation-mode action exceeds reference payload.');
    end
    if conflictAwareBank && ...
            any(~bank.actionPosteriorSafetyMask(actionIndices))
        error(['Conflict-aware formation-mode action failed the ', ...
            'frozen current-posterior safety projection.']);
    end
    if temporalInitialBank && ...
            any(~bank.actionPosteriorSafetyMask(actionIndices))
        error(['Temporal-suspension action failed the frozen ', ...
            'existence-retention or rolling-B3 projection.']);
    end
    if (trackingAlignedBank || receiverLabelBank || ...
            layeredLabelBank || x36ScheduleBank || ...
