function [reportPath, result] = ...
        runBudgetRecycledFormationRepairV188RecursivePilot( ...
            scaleName, options)
% RUNBUDGETRECYCLEDFORMATIONREPAIRV188RECURSIVEPILOT First-page repair.

if nargin < 2 || isempty(options)
    options = struct();
end
scaleName = upper(char(scaleName));
protocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
entryIdx = find(strcmp({protocol.cases.scaleName}, scaleName), 1);
if isempty(entryIdx)
    error('BudgetRecycledRepairRecursiveV188:UnknownScale', ...
        'The requested V99 scale is not registered.');
end
entry = protocol.cases(entryIdx);
if strcmp(scaleName, 'M24')
    defaultTime = 104;
else
    defaultTime = 72;
end
currentTime = getField(options, 'currentTime', defaultTime);
defaultBaseScreenPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v188', 'base_capture', ...
    sprintf('%s_seed%d_t%d_h3', ...
        lower(scaleName), entry.seed, currentTime), ...
    'screen', sprintf( ...
        'TRACKING_ALIGNED_X36_SCHEDULE_H3_%s_SEED%d_T%d_D3.mat', ...
        upper(strrep(entry.presetName, '-', '_')), ...
        entry.seed, currentTime));
baseScreenPath = char(getField( ...
    options, 'baseScreenPath', defaultBaseScreenPath));
cacheRoot = char(getField(options, 'cacheRoot', entry.cacheRoot));
if exist(baseScreenPath, 'file') ~= 2 || exist(cacheRoot, 'dir') ~= 7
    error('BudgetRecycledRepairRecursiveV188:MissingPairedInput', ...
        'The paired base screen and opened-state cache are required.');
end
loaded = load(baseScreenPath, 'screen');
baseScreen = loaded.screen;
if ~strcmp(baseScreen.presetName, entry.presetName) || ...
        baseScreen.seed ~= entry.seed || ...
        baseScreen.returnTimes(1) ~= currentTime || ...
        numel(baseScreen.returnTimes) ~= protocol.horizonSteps
    error('BudgetRecycledRepairRecursiveV188:BaseScreenDrift', ...
        'The base screen does not match the frozen H=3 pilot.');
end
names = {baseScreen.records.actionName};
baseIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), names), 1);
referenceIdx = baseScreen.referenceSubsetIndex;
if isempty(baseIdx)
    error('BudgetRecycledRepairRecursiveV188:MissingBaseArm', ...
        'The base screen does not contain the causal V99 arm.');
end
repairPlan = struct( ...
    'times', currentTime, ...
    'referenceAttemptedBytes', ...
        baseScreen.outcomes(referenceIdx).attemptedBytesByTime(1), ...
    'idealDeliveryTeacherMode', logical(getField( ...
        options, 'idealDeliveryTeacherMode', true)), ...
    'maximumActions', 1);
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v188', 'recursive_pilot', ...
    sprintf('%s_seed%d_t%d_h3', ...
        lower(scaleName), entry.seed, currentTime))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v188-budget-recycled-formation-repair', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', ...
            protocol.positiveSupportThreshold, ...
        'bankVariant', 'online-positive-net-addressable-v99'), ...
    'receiverMode', protocol.receiverMode, ...
    'actionIndices', [1, 3], ...
    'referenceOutcomeScreenPath', baseScreenPath, ...
    'budgetRecycledFormationRepairPlan', repairPlan, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true, ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'captureFusedPosteriorSnapshotsEnabled', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);
repairNames = {screen.records.actionName};
repairIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), repairNames), 1);
if isempty(repairIdx)
    error('BudgetRecycledRepairRecursiveV188:MissingRepairArm', ...
        'The recursive screen did not return the V188 candidate arm.');
end
reference = baseScreen.records(referenceIdx);
base = baseScreen.records(baseIdx);
repair = screen.records(repairIdx);
repairOutcome = screen.outcomes(repairIdx);

result = struct();
result.contractVersion = ...
    'budget-recycled-formation-repair-v188-recursive-pilot-v1';
result.generatedAt = datestr(now, 31);
result.scaleName = scaleName;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.baseScreenPath = baseScreenPath;
result.screenReportPath = screenReportPath;
result.referenceMeanEospa = reference.meanEospa;
result.baseMeanEospa = base.meanEospa;
result.repairMeanEospa = repair.meanEospa;
result.baseEospaGainPercent = base.meanGainPercent;
result.repairEospaGainPercent = repair.meanGainPercent;
result.incrementalEospaGainPercent = relativeGain( ...
    base.meanEospa, repair.meanEospa);
result.referenceMeanRmse = reference.meanRmse;
result.baseMeanRmse = base.meanRmse;
result.repairMeanRmse = repair.meanRmse;
result.baseRmseGainPercent = base.meanRmseGainPercent;
result.repairRmseGainPercent = repair.meanRmseGainPercent;
result.incrementalRmseGainPercent = relativeGain( ...
    base.meanRmse, repair.meanRmse);
result.baseConsensusGainPercent = base.consensusGainPercent;
result.repairConsensusGainPercent = repair.consensusGainPercent;
result.incrementalConsensusGainPercent = relativeGain( ...
    baseScreen.outcomes(baseIdx).consensusOspa, ...
    repairOutcome.consensusOspa);
result.baseAttemptedByteSavingPercent = ...
    base.attemptedByteSavingPercent;
result.repairAttemptedByteSavingPercent = ...
    repair.attemptedByteSavingPercent;
result.incrementalAttemptedBytes = repairOutcome.attemptedBytes - ...
    baseScreen.outcomes(baseIdx).attemptedBytes;
result.repairAttemptedBytesByTime = ...
    repairOutcome. ...
        budgetRecycledFormationRepairAttemptedBytesByTime;
result.repairAppliedActionCountByTime = ...
    repairOutcome. ...
        budgetRecycledFormationRepairAppliedActionCountByTime;
result.repairProposalCountByTime = ...
    repairOutcome. ...
        budgetRecycledFormationRepairProposalCountByTime;
result.repairCertifiedNetSavingBytesByTime = ...
    repairOutcome. ...
        budgetRecycledFormationRepairCertifiedNetSavingBytesByTime;
result.minimumFormationEospaGainPercent = ...
    repair.minimumFormationGainPercent;
result.minimumFormationRmseGainPercent = ...
    repair.minimumFormationRmseGainPercent;
result.worstSensorEospaGainPercent = repair.worstGainPercent;
result.worstSensorRmseGainPercent = repair.worstRmseGainPercent;
result.idealDeliveryTeacherMode = ...
    repairPlan.idealDeliveryTeacherMode;
result.developmentGatePassed = ...
    repair.meanGainPercent >= 5 && ...
    repair.meanRmseGainPercent >= 2 && ...
    repair.worstGainPercent >= 0 && ...
    repair.worstRmseGainPercent >= 0 && ...
    repair.minimumFormationGainPercent >= 0 && ...
    repair.minimumFormationRmseGainPercent >= 0 && ...
    repair.consensusGainPercent >= 0 && ...
    repair.attemptedByteSavingPercent >= 0;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'This H=3 opened recursive pilot applies the truth-free first-page ', ...
    'V188 action before state extraction and lets the exact complete GM ', ...
    'label propagate through later V99 pages. Ideal repair delivery is ', ...
    'charged but not sampled, so the result is a recursive teacher ', ...
    'mechanism screen, not deployable or cross-scene evidence.'];
matPath = fullfile(outputRoot, sprintf( ...
    'BUDGET_RECYCLED_REPAIR_V188_%s_RECURSIVE_PILOT.mat', scaleName));
reportPath = fullfile(outputRoot, sprintf( ...
    'BUDGET_RECYCLED_REPAIR_V188_%s_RECURSIVE_PILOT.md', scaleName));
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V188 %s recursive pilot: %s\n', scaleName, reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BudgetRecycledRepairRecursiveV188:WriteFailed', ...
        'Could not create the recursive V188 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V188 %s H=3 recursive repair pilot\n\n', ...
    result.scaleName);
fprintf(fid, '- Repair applied by page: `%s`\n', ...
    mat2str(result.repairAppliedActionCountByTime));
fprintf(fid, '- Repair bytes by page: `%s`\n\n', ...
    mat2str(result.repairAttemptedBytesByTime));
fprintf(fid, '| Metric | Reference | V99 base | V188 repair |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
fprintf(fid, '| Mean E-OSPA | %.6f | %.6f | %.6f |\n', ...
    result.referenceMeanEospa, result.baseMeanEospa, ...
    result.repairMeanEospa);
fprintf(fid, '| E-OSPA gain | 0 | %+.3f%% | %+.3f%% |\n', ...
    result.baseEospaGainPercent, result.repairEospaGainPercent);
fprintf(fid, '| Mean RMSE | %.6f | %.6f | %.6f |\n', ...
    result.referenceMeanRmse, result.baseMeanRmse, ...
    result.repairMeanRmse);
fprintf(fid, '| RMSE gain | 0 | %+.3f%% | %+.3f%% |\n', ...
    result.baseRmseGainPercent, result.repairRmseGainPercent);
fprintf(fid, '| Consensus gain | 0 | %+.3f%% | %+.3f%% |\n', ...
    result.baseConsensusGainPercent, ...
    result.repairConsensusGainPercent);
fprintf(fid, '| Byte saving | 0 | %+.3f%% | %+.3f%% |\n\n', ...
    result.baseAttemptedByteSavingPercent, ...
    result.repairAttemptedByteSavingPercent);
fprintf(fid, '- Development gate passed: `%d`\n\n', ...
    result.developmentGatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
