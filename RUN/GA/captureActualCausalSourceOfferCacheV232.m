function [reportPath, result] = ...
        captureActualCausalSourceOfferCacheV232(options)
% CAPTUREACTUALCAUSALSOURCEOFFERCACHEV232 Run a causal prefix and rank offers.
%
% The filter executes from page one through the opened candidate page.  At
% that page it captures only the source-local ordinary receive cache that
% the runtime has actually populated.  Teacher labels are consulted after
% ranking to measure proposal recall.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBudgetAdaptiveSourceOfferProtocolV231();
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
overwrite = logical(getField(options, 'overwrite', false));
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices)
    error('ActualCausalSourceCacheV232:InvalidRequest', ...
        'A causal V220 bank and unique teacher rows are required.');
end

loaded = load(candidateBankPath, 'result');
bank = loaded.result;
required = {'contractVersion', 'presetName', 'seed', 'currentTime', ...
    'referencePageBytes', 'admissionNetSavingBytes', ...
    'beneficiaryDetails', 'records'};
if ~isstruct(bank) || ~isscalar(bank) || ...
        any(~isfield(bank, required)) || ...
        ~strcmp(bank.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        getField(bank, 'truthUsedForCandidateFeatures', true) || ...
        getField(bank, 'futureInformationUsedForCandidateFeatures', true)
    error('ActualCausalSourceCacheV232:BankContract', ...
        'The causal V220 candidate-bank contract is required.');
end
if isempty(recordIndices)
    selectedRows = 1:numel(bank.records);
else
    [present, selectedRows] = ismember( ...
        recordIndices, [bank.records.recordIndex]);
    if ~all(present)
        error('ActualCausalSourceCacheV232:UnknownRecord', ...
            'A requested teacher row is absent from the bank.');
    end
end
teacherRows = bank.records(selectedRows);

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v232', 'actual_causal_source_cache', ...
    sprintf('%s_seed%d_t%d', strrep(bank.presetName, '-', '_'), ...
        bank.seed, bank.currentTime))));
matPath = fullfile(outputRoot, 'ACTUAL_CAUSAL_SOURCE_CACHE_V232.mat');
reportPath = fullfile(outputRoot, 'ACTUAL_CAUSAL_SOURCE_CACHE_V232.md');
if ~overwrite && exist(matPath, 'file') == 2 && ...
        exist(reportPath, 'file') == 2
    existing = load(matPath, 'result');
    result = existing.result;
    fprintf('Reused V232 actual causal source cache: %s\n', reportPath);
    return;
end

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ActualCausalSourceCacheV232:DirtySource', ...
        'Official V232 causal-cache capture requires clean source.');
end

inputs = generateDynamicTopologyScenarioInputs(bank.presetName, bank.seed);
inputs = cropInputs(inputs, bank.currentTime);
inputs.model = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
config = buildCaptureConfig(inputs.config, bank.currentTime);
context = buildDirectGraphPayloadRepairV214ExecutionContext( ...
    bank.presetName, bank.seed, 'training-v232-causal-cache', ...
    1, bank.currentTime, 'v232-causal-source-cache', false, struct());
sampling = getDirectGraphStratifiedSamplingV218Protocol();
rng(bank.seed + sampling.filterSeedOffset);
timerId = tic;
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
elapsedSeconds = toc(timerId);

currentTime = bank.currentTime;
localPosteriors = diagnostics.topologyLocalPosteriorSnapshot{currentTime};
receivedCache = diagnostics.topologyReceivedCacheSnapshot{currentTime};
cacheEventType = diagnostics. ...
    topologyReceivedCacheEventTypeSnapshot{currentTime};
cacheTime = diagnostics.topologyReceivedCacheTimeSnapshot{currentTime};
sensorCount = inputs.config.numberOfSensors;
if ~iscell(localPosteriors) || numel(localPosteriors) ~= sensorCount || ...
        ~iscell(receivedCache) || ...
        ~isequal(size(receivedCache), [sensorCount, sensorCount]) || ...
        ~isequal(size(cacheEventType), [sensorCount, sensorCount]) || ...
        ~isequal(size(cacheTime), [sensorCount, sensorCount])
    error('ActualCausalSourceCacheV232:MissingRuntimeSnapshot', ...
        'The source-local runtime cache snapshot is incomplete.');
end

audits = repmat(emptyAudit(), 1, numel(teacherRows));
sourceViews = repmat(emptySourceView(), 1, numel(teacherRows));
for auditIndex = 1:numel(teacherRows)
    teacher = teacherRows(auditIndex);
    sourceId = teacher.sourceId;
    receiverIds = reshape(teacher.candidate.receiverIds, 1, []);
    sourceIds = sourceIdsForFormation( ...
        bank, teacher.beneficiaryFormationId, receiverIds);
    bytePlan = planBudgetAdaptiveSourceOfferBreadthV231( ...
        sourceIds, teacher.payloadAttemptedBytes, ...
        bank.admissionNetSavingBytes, bank.referencePageBytes, struct());
    cacheEntries = receivedCache(sourceId, receiverIds);
    eventTypes = cacheEventType(sourceId, receiverIds);
    receivedTimes = cacheTime(sourceId, receiverIds);
    ages = currentTime - receivedTimes;
    ages(receivedTimes <= 0) = inf;
    offerResult = rankBudgetAdaptiveSourceOffersV231( ...
        localPosteriors{sourceId}, cacheEntries, receiverIds, ...
        ages, eventTypes, inputs.model, bytePlan);
    teacherLabel = reshape(teacher.label, 2, 1);
    audits(auditIndex) = struct( ...
        'recordIndex', teacher.recordIndex, ...
        'beneficiaryFormationId', teacher.beneficiaryFormationId, ...
        'sourceId', sourceId, 'label', teacherLabel, ...
        'receiverIds', receiverIds, ...
        'validCacheSensorIds', offerResult.validCacheSensorIds, ...
        'cacheAgeBySensor', ages, ...
        'cacheEventTypeBySensor', eventTypes, ...
        'selectedLabels', offerResult.selectedLabels, ...
        'teacherSelected', labelSelected( ...
            offerResult.selectedLabels, teacherLabel), ...
        'existenceRank', labelRank( ...
            offerResult.existenceRanking, teacherLabel), ...
        'spatialRank', labelRank( ...
            offerResult.spatialRanking, teacherLabel), ...
        'bytePlan', bytePlan, ...
        'rankStatus', offerResult.status);
    sourceViews(auditIndex) = struct( ...
        'recordIndex', teacher.recordIndex, ...
        'beneficiaryFormationId', teacher.beneficiaryFormationId, ...
        'sourceId', sourceId, 'receiverIds', receiverIds, ...
        'sourceCurrentPosterior', localPosteriors{sourceId}, ...
        'receivedBeneficiaryCache', {cacheEntries}, ...
        'cacheAgeBySensor', ages, ...
        'cacheEventTypeBySensor', eventTypes);
end

cacheArtifact = struct();
cacheArtifact.contractVersion = ...
    'actual-causal-source-cache-artifact-v232-v1';
cacheArtifact.presetName = bank.presetName;
cacheArtifact.seed = bank.seed;
cacheArtifact.currentTime = bank.currentTime;
cacheArtifact.generationGitCommit = gitState.commit;
cacheArtifact.sourceViews = sourceViews;
cacheArtifact.snapshotConvention = [ ...
    'source current pre-topology local posterior plus ordinary ', ...
    'receivedCache after current-page realized deliveries'];
cacheArtifact.cacheUpdatedOnlyOnSuccessfulOrdinaryDelivery = true;
cacheArtifact.globalBeneficiaryPosteriorExposedToRanker = false;
cacheArtifact.truthUsed = false;
cacheArtifact.futureInformationUsed = false;

result = struct();
result.contractVersion = ...
    'actual-causal-source-cache-recall-v232-v1';
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.presetName = bank.presetName;
result.seed = bank.seed;
result.currentTime = bank.currentTime;
result.elapsedSeconds = elapsedSeconds;
result.teacherAudits = audits;
result.teacherLabelCount = numel(audits);
result.recoveredTeacherLabelCount = nnz([audits.teacherSelected]);
result.teacherRecall = result.recoveredTeacherLabelCount / ...
    max(result.teacherLabelCount, 1);
result.actualRuntimeReceivedCacheUsed = true;
result.sameStateProxyUsed = false;
result.truthUsedForRanking = false;
result.futureInformationUsedForRanking = false;
result.allTeacherLabelsRecovered = ...
    result.recoveredTeacherLabelCount == result.teacherLabelCount;
result.integratedOfferSelectionAuthorized = ...
    result.allTeacherLabelsRecovered && ...
    all(cellfun(@(plan) all(plan.candidateFeasibleMask), ...
        {audits.bytePlan}));
result.onlinePolicyImplemented = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V232 is a single opened X36 runtime-cache recall audit. It uses only ', ...
    'source current posteriors and ordinary beneficiary payloads actually ', ...
    'delivered into each source cache. A pass authorizes an integrated ', ...
    'offer-selection headroom run, not an online, full-episode, held-out ', ...
    'or paper-level tracking claim.'];
result.matPath = matPath;
result.reportPath = reportPath;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
save('-mat7-binary', matPath, 'result', 'cacheArtifact');
writeReport(reportPath, result);
fprintf('V232 actual causal source cache: %s\n', reportPath);
end

function config = buildCaptureConfig(scenario, currentTime)
source = getDirectGraphPayloadRepairControllerV214Protocol();
config = buildMixtureAwareKlaReferenceConfig();
config.missingLabelFusionMode = source.receiverMode;
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenario.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = 2 * scenario.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicyName = source.base.policyName;
config.topologyPolicyFcn = @(context) ...
    selectDirectGraphPayloadRepairV214ReferencePolicy(context);
config.topologyPosteriorCaptureTimes = currentTime;
config.topologyReceivedCacheCaptureTimes = currentTime;
config.receiverSafeLabelFusionEnabled = false;
config.receiverSafeFormationConditionedOnlinePolicyEnabled = false;
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
if isfield(inputs.commConfig, 'linkUniforms') && ...
        ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = ...
        inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function ids = sourceIdsForFormation(bank, formationId, receiverIds)
match = find([bank.beneficiaryDetails.formationId] == formationId, 1);
if isempty(match) || ...
        ~isfield(bank.beneficiaryDetails(match), 'synopsisSensorIds')
    error('ActualCausalSourceCacheV232:SourceSet', ...
        'The beneficiary common-source set is unavailable.');
end
participants = reshape( ...
    bank.beneficiaryDetails(match).synopsisSensorIds, 1, []);
ids = setdiff(participants, reshape(receiverIds, 1, []), 'stable');
end

function present = labelSelected(labels, label)
present = ~isempty(labels) && any(all(labels == label, 1));
end

function rank = labelRank(labels, label)
match = find(all(labels == label, 1), 1);
if isempty(match)
    rank = inf;
else
    rank = match;
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ActualCausalSourceCacheV232:WriteReport', ...
        'Could not write the V232 causal-cache report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V232 actual source-local cache recall\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Runtime seconds: `%.1f`\n', result.elapsedSeconds);
fprintf(fid, '- Actual runtime received cache used: `1`\n');
fprintf(fid, '- Teacher recall: `%d / %d = %.1f%%`\n\n', ...
    result.recoveredTeacherLabelCount, result.teacherLabelCount, ...
    100 * result.teacherRecall);
fprintf(fid, ['| Row | Beneficiary | Source / label | Valid cached ', ...
    'beneficiary sensors | Ages | Rank E / spatial | Selected |\n']);
fprintf(fid, '|--:|--:|:--|:--|:--|:--|:--|\n');
for audit = result.teacherAudits
    validMask = ismember(audit.receiverIds, audit.validCacheSensorIds);
    fprintf(fid, ['| %d | F%d | S%d / `[%d,%d]` | `%s` | `%s` | ', ...
        '`%s / %s` | `%d` |\n'], ...
        audit.recordIndex, audit.beneficiaryFormationId, ...
        audit.sourceId, audit.label(1), audit.label(2), ...
        numericText(audit.validCacheSensorIds), ...
        numericText(audit.cacheAgeBySensor(validMask)), ...
        rankText(audit.existenceRank), rankText(audit.spatialRank), ...
        audit.teacherSelected);
end
fprintf(fid, '\n## Decision\n\n');
if result.integratedOfferSelectionAuthorized
    fprintf(fid, ['Every teacher row is retained by the byte-bounded ', ...
        'proposal set using only cache entries actually owned by its ', ...
        'source. Integrate the beneficiary-side selection and unchanged ', ...
        'V226 projection for a paired H=3 headroom test next.\n']);
else
    fprintf(fid, ['At least one teacher row is unavailable or not retained ', ...
        'under the actual source-local cache. Do not integrate the action; ', ...
        'redesign cache freshness or the proposal rule first.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = numericText(values)
if isempty(values)
    text = 'none';
    return;
end
parts = arrayfun(@(x) sprintf('%.0f', x), ...
    reshape(values, 1, []), 'UniformOutput', false);
text = strjoin(parts, ', ');
end

function text = rankText(rank)
if isfinite(rank)
    text = sprintf('%d', rank);
else
    text = '-';
end
end

function value = emptyAudit()
value = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'receiverIds', zeros(1, 0), ...
    'validCacheSensorIds', zeros(1, 0), ...
    'cacheAgeBySensor', zeros(1, 0), ...
    'cacheEventTypeBySensor', zeros(1, 0), ...
    'selectedLabels', zeros(2, 0), 'teacherSelected', false, ...
    'existenceRank', inf, 'spatialRank', inf, ...
    'bytePlan', struct(), 'rankStatus', '');
end

function value = emptySourceView()
value = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'receiverIds', zeros(1, 0), ...
    'sourceCurrentPosterior', [], ...
    'receivedBeneficiaryCache', {{}}, ...
    'cacheAgeBySensor', zeros(1, 0), ...
    'cacheEventTypeBySensor', zeros(1, 0));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
