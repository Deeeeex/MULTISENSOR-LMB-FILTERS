function [modelPath, result] = ...
    trainRollingSafeRolloutEdgeModel(datasetPath, options)
% TRAINROLLINGSAFEROLLOUTEDGEMODEL Fit an observable rollout edge ranker.
%
% Hyperparameters are selected only by leave-one-training-seed-out graph
% imitation. Development/audit seeds never select the model. Closed-loop
% tracking remains a separate frozen-model gate.

if nargin < 1 || isempty(datasetPath)
    datasetPath = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'datasets', ...
        'rolling_safe_rollout_imitation_m24_hard_t75.mat');
end
if nargin < 2 || isempty(options)
    options = struct();
end
loaded = load(datasetPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Rollout imitation dataset file has no dataset variable.');
end
dataset = loaded.dataset;
protocol = getRollingSafeRolloutProtocol();
validateDataset(dataset, protocol);
requestedFeatureContext = lower(strrep(char(getField( ...
    options, 'featureContextMode', ...
    protocol.featureContextMode)), '_', '-'));
if ~strcmp(requestedFeatureContext, ...
        protocol.featureContextMode)
    error(['Rollout feature context differs from the frozen ', ...
        'protocol.']);
end
options.featureContextMode = protocol.featureContextMode;
[dataset.blocks, featureNames, featureContextMode] = ...
    prepareFeatureContext(dataset, options);

trainingSeeds = protocol.trainingSeeds;
auditSeeds = protocol.auditSeeds;
designSeeds = protocol.designSeeds;
if isempty(trainingSeeds) || ...
        ~all(ismember(trainingSeeds, dataset.seeds)) || ...
        ~isempty(intersect(trainingSeeds, auditSeeds)) || ...
        ~all(ismember([trainingSeeds, auditSeeds], designSeeds)) || ...
        ~all(ismember(dataset.seeds, designSeeds))
    error('Rolling-safe training/audit seed split is invalid.');
end
if numel(unique(trainingSeeds)) < 2
    error('At least two distinct training seeds are required.');
end

if isfield(options, 'excludedFeatureNames') && ...
        ~isequal(reshape(options.excludedFeatureNames, 1, []), ...
            reshape(protocol.excludedFeatureNames, 1, []))
    error(['Excluded rollout features differ from the frozen ', ...
        'protocol.']);
end
baseExcludedNames = reshape( ...
    protocol.excludedFeatureNames, 1, []);
missingExclusions = setdiff( ...
    baseExcludedNames, reshape(dataset.featureNames, 1, []));
if ~isempty(missingExclusions)
    error('Unknown excluded rollout feature: %s', ...
        missingExclusions{1});
end
[featureMask, excludedNames] = buildFeatureMask( ...
    featureNames, baseExcludedNames);
if ~any(featureMask)
    error('No rollout edge features remain after exclusion.');
end

hiddenWidthGrid = protocol.hiddenWidthGrid;
lambdaGrid = protocol.lambdaGrid;
epochCount = protocol.epochCount;
learningRate = protocol.learningRate;
initializationSeed = protocol.initializationSeed;
minimumSeedProjectedRecall = ...
    protocol.minimumSeedProjectedEdgeRecall;
minimumMeanProjectedRecall = ...
    protocol.minimumMeanProjectedEdgeRecall;
minimumSeedProjectedF1 = ...
    protocol.minimumSeedProjectedEdgeF1;
minimumMeanProjectedF1 = ...
    protocol.minimumMeanProjectedEdgeF1;
minimumBlockProjectedF1 = ...
    protocol.minimumBlockProjectedEdgeF1;
minimumSeedProjectedExact = ...
    protocol.minimumSeedProjectedExactGraphFraction;
minimumMeanProjectedExact = ...
    protocol.minimumMeanProjectedExactGraphFraction;
minimumZeroEdgeExact = ...
    protocol.minimumZeroEdgeExactFraction;
minimumSingleEdgeExact = ...
    protocol.minimumSingleEdgeExactFraction;
minimumZeroEdgeBlockCount = ...
    protocol.minimumZeroEdgeBlockCount;
minimumSingleEdgeBlockCount = ...
    protocol.minimumSingleEdgeBlockCount;
candidateCount = numel(hiddenWidthGrid) * numel(lambdaGrid);
candidates = repmat(emptyCandidate(), 1, candidateCount);
candidateCursor = 0;
for hiddenWidth = hiddenWidthGrid
    for lambda = lambdaGrid
        candidateCursor = candidateCursor + 1;
        foldMetrics = repmat(emptySplitMetrics(), ...
            1, numel(trainingSeeds));
        for foldIdx = 1:numel(trainingSeeds)
            heldoutSeed = trainingSeeds(foldIdx);
            fitSeeds = setdiff( ...
                trainingSeeds, heldoutSeed, 'stable');
            fitBlocks = selectBlocks(dataset.blocks, fitSeeds);
            heldoutBlocks = selectBlocks( ...
                dataset.blocks, heldoutSeed);
            fitOptions = struct( ...
                'hiddenWidth', hiddenWidth, ...
                'lambda', lambda, ...
                'epochCount', epochCount, ...
                'learningRate', learningRate, ...
                'initializationSeed', ...
                    initializationSeed + ...
                    1000 * candidateCursor + foldIdx);
            foldModel = fitMlp( ...
                fitBlocks, featureMask, fitOptions);
            foldMetrics(foldIdx) = evaluateBlocks( ...
                heldoutBlocks, foldModel, ...
                dataset.sourceWeight, ...
                dataset.payloadToleranceFraction);
        end
        candidates(candidateCursor) = summarizeCandidate( ...
            hiddenWidth, lambda, foldMetrics);
    end
end
[~, order] = sortrows(vertcat(candidates.selectionKey));
candidates = candidates(order);
selected = candidates(1);

fitOptions = struct( ...
    'hiddenWidth', selected.hiddenWidth, ...
    'lambda', selected.lambda, ...
    'epochCount', epochCount, ...
    'learningRate', learningRate, ...
    'initializationSeed', initializationSeed);
trainingBlocks = selectBlocks(dataset.blocks, trainingSeeds);
model = fitMlp(trainingBlocks, featureMask, fitOptions);
model.kind = 'mlp-rolling-safe-rollout-edge-v1';
model.protocolId = protocol.id;
model.sourceWeight = dataset.sourceWeight;
model.payloadToleranceFraction = ...
    dataset.payloadToleranceFraction;
model.filterSeedOffset = dataset.filterSeedOffset;
model.behaviorCacheSha256 = ...
    dataset.behaviorCacheSha256;
model.featureContextMode = featureContextMode;
model.datasetFeatureContextMode = dataset.featureContextMode;
model.allFeatureNames = featureNames;
model.excludedFeatureNames = excludedNames;
model.trainingSeeds = trainingSeeds;
model.auditSeeds = auditSeeds;
model.designSeeds = designSeeds;
model.datasetSeeds = dataset.seeds;
model.datasetGenerationGitCommit = ...
    dataset.generationGitCommit;
model.datasetGenerationResearchWorktreeDirty = ...
    dataset.generationResearchWorktreeDirty;
model.featuresUseTruth = dataset.featuresUseTruth;
model.labelsUseTruth = dataset.labelsUseTruth;
model.labelSelectionUsesFutureOutcome = ...
    dataset.labelSelectionUsesFutureOutcome;
model.datasetContractVersion = dataset.contractVersion;
model.datasetPath = datasetPath;
model.datasetSha256 = computeFileSha256(datasetPath);
model.featureContractSha256 = hash('sha256', sprintf( ...
    '%s|%.17g|%s', featureContextMode, ...
    dataset.sourceWeight, strjoin(featureNames, char(31))));
model.trainingConfigSha256 = hash('sha256', sprintf( ...
    ['hidden=%s|lambda=%s|epochs=%d|lr=%.17g|seed=%d|', ...
     'train=%s|audit=%s|design=%s|minseedf1=%.17g|', ...
     'minmeanf1=%.17g|minblockf1=%.17g|', ...
     'minseedrecall=%.17g|minmeanrecall=%.17g|', ...
     'minseedexact=%.17g|minmeanexact=%.17g|', ...
     'minzeroexact=%.17g|minsingleexact=%.17g|', ...
     'minzerocount=%d|minsinglecount=%d|', ...
     'payload=%s|filterseedoffset=%d|cache=%s|', ...
     'protocol=%s|excluded=%s'], ...
    mat2str(hiddenWidthGrid), mat2str(lambdaGrid), ...
    epochCount, learningRate, initializationSeed, ...
    mat2str(trainingSeeds), mat2str(auditSeeds), ...
    mat2str(designSeeds), ...
    minimumSeedProjectedF1, minimumMeanProjectedF1, ...
    minimumBlockProjectedF1, ...
    minimumSeedProjectedRecall, minimumMeanProjectedRecall, ...
    minimumSeedProjectedExact, minimumMeanProjectedExact, ...
    minimumZeroEdgeExact, minimumSingleEdgeExact, ...
    minimumZeroEdgeBlockCount, minimumSingleEdgeBlockCount, ...
    formatScalar(dataset.payloadToleranceFraction), ...
    dataset.filterSeedOffset, ...
    strjoin(dataset.behaviorCacheSha256, char(31)), ...
    protocol.id, ...
    strjoin(excludedNames, char(31))));
trainingGitState = resolveResearchGitState();
model.trainingGitCommit = trainingGitState.commit;
model.trainingTrackedWorktreeDirty = ...
    trainingGitState.trackedWorktreeDirty;
model.trainingUntrackedSourceFiles = ...
    trainingGitState.untrackedSourceFiles;
model.trainingWorktreeDirty = ...
    trainingGitState.researchWorktreeDirty;
model.selectedByTrainingSeedCrossValidation = true;
model.closedLoopValidationUsedForSelection = false;
model.frozen = true;
model.acceptedForClosedLoopScreen = ...
    selected.minimumHeldoutSeedProjectedEdgeF1 >= ...
        minimumSeedProjectedF1 - 1e-12 && ...
    selected.meanHeldoutProjectedEdgeF1 >= ...
        minimumMeanProjectedF1 - 1e-12 && ...
    selected.minimumHeldoutBlockProjectedEdgeF1 >= ...
        minimumBlockProjectedF1 - 1e-12 && ...
    selected.minimumHeldoutSeedProjectedEdgeRecall >= ...
        minimumSeedProjectedRecall - 1e-12 && ...
    selected.meanHeldoutProjectedEdgeRecall >= ...
        minimumMeanProjectedRecall - 1e-12 && ...
    selected.minimumHeldoutProjectedExactGraphFraction >= ...
        minimumSeedProjectedExact - 1e-12 && ...
    selected.meanHeldoutProjectedExactGraphFraction >= ...
        minimumMeanProjectedExact - 1e-12 && ...
    passesOptionalMetric( ...
        selected.minimumHeldoutZeroEdgeExactFraction, ...
        minimumZeroEdgeExact) && ...
    passesOptionalMetric( ...
        selected.minimumHeldoutSingleEdgeExactFraction, ...
        minimumSingleEdgeExact) && ...
    selected.heldoutZeroEdgeBlockCount >= ...
        minimumZeroEdgeBlockCount && ...
    selected.heldoutSingleEdgeBlockCount >= ...
        minimumSingleEdgeBlockCount && ...
    ~dataset.generationResearchWorktreeDirty && ...
    ~model.trainingWorktreeDirty;
model.acceptanceThresholds = struct( ...
    'minimumSeedProjectedEdgeF1', ...
        minimumSeedProjectedF1, ...
    'minimumMeanProjectedEdgeF1', ...
        minimumMeanProjectedF1, ...
    'minimumBlockProjectedEdgeF1', ...
        minimumBlockProjectedF1, ...
    'minimumSeedProjectedEdgeRecall', ...
        minimumSeedProjectedRecall, ...
    'minimumMeanProjectedEdgeRecall', ...
        minimumMeanProjectedRecall, ...
    'minimumSeedProjectedExactGraphFraction', ...
        minimumSeedProjectedExact, ...
    'minimumMeanProjectedExactGraphFraction', ...
        minimumMeanProjectedExact, ...
    'minimumZeroEdgeExactFraction', ...
        minimumZeroEdgeExact, ...
    'minimumSingleEdgeExactFraction', ...
        minimumSingleEdgeExact, ...
    'minimumZeroEdgeBlockCount', ...
        minimumZeroEdgeBlockCount, ...
    'minimumSingleEdgeBlockCount', ...
        minimumSingleEdgeBlockCount);
model.imitationGateMetrics = struct( ...
    'minimumHeldoutSeedProjectedEdgeF1', ...
        selected.minimumHeldoutSeedProjectedEdgeF1, ...
    'meanHeldoutProjectedEdgeF1', ...
        selected.meanHeldoutProjectedEdgeF1, ...
    'minimumHeldoutBlockProjectedEdgeF1', ...
        selected.minimumHeldoutBlockProjectedEdgeF1, ...
    'minimumHeldoutSeedProjectedEdgeRecall', ...
        selected.minimumHeldoutSeedProjectedEdgeRecall, ...
    'meanHeldoutProjectedEdgeRecall', ...
        selected.meanHeldoutProjectedEdgeRecall, ...
    'minimumHeldoutProjectedExactGraphFraction', ...
        selected.minimumHeldoutProjectedExactGraphFraction, ...
    'meanHeldoutProjectedExactGraphFraction', ...
        selected.meanHeldoutProjectedExactGraphFraction, ...
    'minimumHeldoutZeroEdgeExactFraction', ...
        selected.minimumHeldoutZeroEdgeExactFraction, ...
    'minimumHeldoutSingleEdgeExactFraction', ...
        selected.minimumHeldoutSingleEdgeExactFraction, ...
    'heldoutZeroEdgeBlockCount', ...
        selected.heldoutZeroEdgeBlockCount, ...
    'heldoutSingleEdgeBlockCount', ...
        selected.heldoutSingleEdgeBlockCount);
model.selectedHyperparameter = struct( ...
    'hiddenWidth', selected.hiddenWidth, ...
    'lambda', selected.lambda, ...
    'epochCount', epochCount, ...
    'learningRate', learningRate);
model.artifactIdVersion = ...
    'rolling-safe-rollout-artifact-v1';
model.artifactId = computeRollingSafeRolloutArtifactId(model);

trainingMetrics = evaluateBlocks( ...
    trainingBlocks, model, dataset.sourceWeight, ...
    dataset.payloadToleranceFraction);
auditMetrics = emptySplitMetrics();
if ~isempty(auditSeeds)
    auditMetrics = evaluateBlocks( ...
        selectBlocks(dataset.blocks, auditSeeds), model, ...
        dataset.sourceWeight, ...
        dataset.payloadToleranceFraction);
end

outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'models'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
modelPath = getField(options, 'modelPath', fullfile( ...
    outputDirectory, ...
    'rolling_safe_rollout_edge_mlp_m24_t75.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'ROLLING_SAFE_ROLLOUT_EDGE_MODEL_AUDIT.md'));

result = struct();
result.generatedAt = datestr(now, 31);
result.datasetPath = datasetPath;
result.modelPath = modelPath;
result.reportPath = reportPath;
result.trainingSeeds = trainingSeeds;
result.auditSeeds = auditSeeds;
result.designSeeds = designSeeds;
result.featureNames = featureNames;
result.excludedFeatureNames = excludedNames;
result.retainedFeatureNames = featureNames(featureMask);
result.hiddenWidthGrid = hiddenWidthGrid;
result.lambdaGrid = lambdaGrid;
result.hyperparameterGridBoundary = [ ...
    'The compact width/lambda grid was narrowed using the rejected ', ...
    'v1 development audit; no held-out validation seed selected it.'];
result.featureContextMode = featureContextMode;
result.datasetFeatureContextMode = dataset.featureContextMode;
result.candidates = candidates;
result.selectedCandidate = selected;
result.trainingMetrics = trainingMetrics;
result.auditMetrics = auditMetrics;
result.model = model;
result.acceptedForClosedLoopScreen = ...
    model.acceptedForClosedLoopScreen;
result.acceptanceThresholds = model.acceptanceThresholds;
result.artifactId = model.artifactId;
result.datasetSha256 = model.datasetSha256;
result.featureContractSha256 = ...
    model.featureContractSha256;
result.trainingConfigSha256 = model.trainingConfigSha256;
result.trainingGitCommit = model.trainingGitCommit;
result.trainingWorktreeDirty = model.trainingWorktreeDirty;
result.rejectionReasons = buildRejectionReasons( ...
    selected, model);
result.evidenceBoundary = [ ...
    'The model is selected only by leave-one-training-seed-out ', ...
    'imitation of privileged rollout graphs. Audit-seed labels do not ', ...
    'select hyperparameters. Joint-projector replay uses the recorded ', ...
    'teacher-forced state and history in each block; neither split is ', ...
    'on-policy closed-loop validation.'];
save('-mat7-binary', modelPath, 'model', 'result');
writeReport(reportPath, result);
fprintf('Model: %s\nReport: %s\n', modelPath, reportPath);
end

function reasons = buildRejectionReasons(selected, model)
reasons = {};
if selected.minimumHeldoutSeedProjectedEdgeF1 < ...
        model.acceptanceThresholds. ...
            minimumSeedProjectedEdgeF1 - 1e-12
    reasons{end + 1} = ...
        'minimum held-out-seed projected edge F1'; %#ok<AGROW>
end
if selected.meanHeldoutProjectedEdgeF1 < ...
        model.acceptanceThresholds. ...
            minimumMeanProjectedEdgeF1 - 1e-12
    reasons{end + 1} = ...
        'mean held-out projected edge F1'; %#ok<AGROW>
end
if selected.minimumHeldoutBlockProjectedEdgeF1 < ...
        model.acceptanceThresholds. ...
            minimumBlockProjectedEdgeF1 - 1e-12
    reasons{end + 1} = ...
        'minimum held-out block projected edge F1'; %#ok<AGROW>
end
if selected.minimumHeldoutSeedProjectedEdgeRecall < ...
        model.acceptanceThresholds. ...
            minimumSeedProjectedEdgeRecall - 1e-12 || ...
        selected.meanHeldoutProjectedEdgeRecall < ...
        model.acceptanceThresholds. ...
            minimumMeanProjectedEdgeRecall - 1e-12
    reasons{end + 1} = ...
        'held-out projected edge recall'; %#ok<AGROW>
end
if selected.minimumHeldoutProjectedExactGraphFraction < ...
        model.acceptanceThresholds. ...
            minimumSeedProjectedExactGraphFraction - 1e-12 || ...
        selected.meanHeldoutProjectedExactGraphFraction < ...
        model.acceptanceThresholds. ...
            minimumMeanProjectedExactGraphFraction - 1e-12
    reasons{end + 1} = ...
        'held-out projected exact-graph fraction'; %#ok<AGROW>
end
if ~passesOptionalMetric( ...
        selected.minimumHeldoutZeroEdgeExactFraction, ...
        model.acceptanceThresholds. ...
            minimumZeroEdgeExactFraction)
    reasons{end + 1} = ...
        'zero-edge exact imitation'; %#ok<AGROW>
end
if ~passesOptionalMetric( ...
        selected.minimumHeldoutSingleEdgeExactFraction, ...
        model.acceptanceThresholds. ...
            minimumSingleEdgeExactFraction)
    reasons{end + 1} = ...
        'single-edge exact imitation'; %#ok<AGROW>
end
if selected.heldoutZeroEdgeBlockCount < ...
        model.acceptanceThresholds.minimumZeroEdgeBlockCount || ...
        selected.heldoutSingleEdgeBlockCount < ...
        model.acceptanceThresholds.minimumSingleEdgeBlockCount
    reasons{end + 1} = ...
        'zero/single-edge held-out support'; %#ok<AGROW>
end
if model.datasetGenerationResearchWorktreeDirty
    reasons{end + 1} = ...
        'dataset generation worktree was dirty'; %#ok<AGROW>
end
if model.trainingWorktreeDirty
    reasons{end + 1} = 'training worktree was dirty'; %#ok<AGROW>
end
end

function [blocks, featureNames, mode] = ...
        prepareFeatureContext(dataset, options)
blocks = dataset.blocks;
datasetMode = lower(strrep( ...
    char(dataset.featureContextMode), '_', '-'));
mode = lower(strrep(char(getField( ...
    options, 'featureContextMode', 'graph-context')), '_', '-'));
if strcmp(mode, datasetMode)
    featureNames = reshape(dataset.featureNames, 1, []);
    return;
end
if ~strcmp(datasetMode, 'raw') || ...
        ~strcmp(mode, 'graph-context')
    error(['Unsupported rollout feature-context conversion: ', ...
        '%s -> %s.'], datasetMode, mode);
end
featureNames = {};
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    [converted, names] = buildFormationTreeContextFeatures( ...
        block.features, dataset.featureNames, ...
        block.receiverIndices, block.senderIndices, ...
        reshape(block.groupIds, 1, []), mode);
    if isempty(featureNames)
        featureNames = reshape(names, 1, []);
    elseif ~isequal(featureNames, reshape(names, 1, []))
        error('Converted rollout feature names differ across blocks.');
    end
    blocks(blockIdx).features = converted;
    blocks(blockIdx).featureNames = featureNames;
end
end

function [featureMask, excludedNames] = ...
        buildFeatureMask(featureNames, baseExcludedNames)
featureMask = true(1, numel(featureNames));
prefixes = {'', 'receiver_rel_', ...
    'formation_pair_rel_', 'block_rel_'};
for excludedIdx = 1:numel(baseExcludedNames)
    for prefixIdx = 1:numel(prefixes)
        featureMask = featureMask & ~strcmp( ...
            featureNames, [prefixes{prefixIdx}, ...
                baseExcludedNames{excludedIdx}]);
    end
end
excludedNames = featureNames(~featureMask);
end

function model = fitMlp(blocks, featureMask, options)
X = vertcat(blocks.features);
y = double(vertcat(blocks.selectedCrossMask));
X = X(:, featureMask);
if isempty(X) || numel(y) ~= size(X, 1) || ...
        ~any(y == 1) || ~any(y == 0)
    error('Rollout MLP training examples are invalid.');
end
featureMean = mean(X, 1);
featureScale = std(X, 0, 1);
featureScale(~isfinite(featureScale) | featureScale <= eps) = 1;
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, featureMean), featureScale);

hiddenWidth = options.hiddenWidth;
lambda = options.lambda;
epochCount = options.epochCount;
learningRate = options.learningRate;
rng(options.initializationSeed);
inputCount = size(Z, 2);
hiddenWeight = randn(inputCount, hiddenWidth) / sqrt(inputCount);
hiddenBias = zeros(1, hiddenWidth);
outputWeight = randn(hiddenWidth, 1) / sqrt(hiddenWidth);
outputBias = 0;

positiveCount = nnz(y == 1);
negativeCount = nnz(y == 0);
sampleWeight = ones(size(y));
sampleWeight(y == 1) = negativeCount / max(positiveCount, 1);
weightDenominator = sum(sampleWeight);

parameters = { ...
    hiddenWeight, hiddenBias, outputWeight, outputBias};
firstMoment = cellfun(@zerosLike, parameters, ...
    'UniformOutput', false);
secondMoment = cellfun(@zerosLike, parameters, ...
    'UniformOutput', false);
beta1 = 0.9;
beta2 = 0.999;
adamEpsilon = 1e-8;
lossHistory = nan(1, epochCount);
for epoch = 1:epochCount
    hidden = tanh(bsxfun(@plus, ...
        Z * parameters{1}, parameters{2}));
    logits = hidden * parameters{3} + parameters{4};
    probability = stableSigmoid(logits);
    clipped = min(max(probability, 1e-9), 1 - 1e-9);
    dataLoss = sum(sampleWeight .* ( ...
        -y .* log(clipped) - ...
        (1 - y) .* log(1 - clipped))) / ...
            weightDenominator;
    regularization = 0.5 * lambda * ( ...
        sum(parameters{1}(:).^2) + ...
        sum(parameters{3}(:).^2));
    lossHistory(epoch) = dataLoss + regularization;

    dLogit = sampleWeight .* (probability - y) / ...
        weightDenominator;
    gradients = cell(1, 4);
    gradients{3} = hidden' * dLogit + ...
        lambda * parameters{3};
    gradients{4} = sum(dLogit);
    dHidden = dLogit * parameters{3}';
    dActivation = dHidden .* (1 - hidden.^2);
    gradients{1} = Z' * dActivation + ...
        lambda * parameters{1};
    gradients{2} = sum(dActivation, 1);
    gradients = clipGradients(gradients, 10);
    for parameterIdx = 1:numel(parameters)
        firstMoment{parameterIdx} = ...
            beta1 * firstMoment{parameterIdx} + ...
            (1 - beta1) * gradients{parameterIdx};
        secondMoment{parameterIdx} = ...
            beta2 * secondMoment{parameterIdx} + ...
            (1 - beta2) * gradients{parameterIdx}.^2;
        correctedFirst = firstMoment{parameterIdx} / ...
            (1 - beta1^epoch);
        correctedSecond = secondMoment{parameterIdx} / ...
            (1 - beta2^epoch);
        parameters{parameterIdx} = ...
            parameters{parameterIdx} - learningRate * ...
                correctedFirst ./ ...
                (sqrt(correctedSecond) + adamEpsilon);
    end
end
if any(~isfinite(lossHistory)) || ...
        any(cellfun(@(value) any(~isfinite(value(:))), parameters))
    error('Rollout MLP training produced non-finite values.');
end

model = struct();
model.kind = 'mlp-rolling-safe-rollout-edge-v1';
model.featureMask = logical(reshape(featureMask, 1, []));
model.featureMean = featureMean;
model.featureScale = featureScale;
model.hiddenWeight = parameters{1};
model.hiddenBias = parameters{2};
model.outputWeight = parameters{3};
model.outputBias = parameters{4};
model.hiddenWidth = hiddenWidth;
model.lambda = lambda;
model.epochCount = epochCount;
model.learningRate = learningRate;
model.finalTrainingLoss = lossHistory(end);
model.trainingLossHistory = lossHistory;
end

function metrics = evaluateBlocks( ...
        blocks, model, sourceWeight, payloadToleranceFraction)
blockMetrics = repmat(emptyBlockMetrics(), 1, numel(blocks));
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    scores = scoreRollingSafeRolloutEdgeModel( ...
        model, block.features);
    truth = logical(block.selectedCrossMask);
    selected = receiverConstrainedTopK( ...
        scores, block.receiverIndices, nnz(truth));
    [projectedAdjacency, projectionDetails] = ...
        replayJointProjection( ...
            block, scores, sourceWeight, ...
            payloadToleranceFraction);
    projectedMask = extractProjectedCrossMask( ...
        projectedAdjacency, block.receiverIndices, ...
        block.senderIndices);
    [projectedPrecision, projectedRecall, projectedF1] = ...
        binaryEdgeMetrics(projectedMask, truth);
    positiveRanks = computePositiveReceiverRanks( ...
        scores, truth, block.receiverIndices);
    metric = emptyBlockMetrics();
    metric.seed = block.seed;
    metric.currentTime = block.currentTime;
    metric.actionCode = block.actionCode;
    metric.positiveCount = nnz(truth);
    [~, metric.edgeRecall] = binaryEdgeMetrics(selected, truth);
    metric.exactEdgeSet = isequal(selected, truth);
    metric.projectedEdgePrecision = projectedPrecision;
    metric.projectedEdgeRecall = projectedRecall;
    metric.projectedEdgeF1 = projectedF1;
    metric.projectedExactGraph = isequal( ...
        logical(projectedAdjacency), ...
        logical(block.selectedAdjacency));
    metric.projectedCrossEdgeCount = nnz(projectedMask);
    metric.projectionRepairTriggered = ...
        projectionDetails.repairTriggered;
    metric.projectionInfeasible = ...
        projectionDetails.topologyInfeasible;
    if isempty(positiveRanks)
        metric.receiverTopOneFraction = double(~any(selected));
        metric.meanPositiveReceiverRank = 0;
        metric.minimumPositiveMargin = -max(scores);
    else
        metric.receiverTopOneFraction = mean(positiveRanks == 1);
        metric.meanPositiveReceiverRank = mean(positiveRanks);
        metric.minimumPositiveMargin = min(scores(truth)) - ...
            max(scores(~truth));
    end
    metric.selectedReceiverCount = ...
        numel(unique(block.receiverIndices(selected)));
    blockMetrics(blockIdx) = metric;
end
seeds = unique([blockMetrics.seed], 'stable');
seedRecall = zeros(1, numel(seeds));
seedExact = zeros(1, numel(seeds));
seedTopOne = zeros(1, numel(seeds));
seedProjectedRecall = zeros(1, numel(seeds));
seedProjectedF1 = zeros(1, numel(seeds));
seedProjectedExact = zeros(1, numel(seeds));
