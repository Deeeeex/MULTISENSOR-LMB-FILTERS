function selected = receiverConstrainedTopK( ...
        scores, receiverIndices, count)
selected = false(size(scores));
if count <= 0
    return;
end
[~, order] = sort(scores, 'descend');
usedReceivers = [];
for exampleIdx = reshape(order, 1, [])
    receiver = receiverIndices(exampleIdx);
    if any(usedReceivers == receiver)
        continue;
    end
    selected(exampleIdx) = true;
    usedReceivers(end + 1) = receiver; %#ok<AGROW>
    if nnz(selected) >= count
        break;
    end
end
if nnz(selected) ~= count
    error('Receiver-constrained rollout ranking could not select K edges.');
end
end

function ranks = computePositiveReceiverRanks( ...
        scores, truth, receiverIndices)
positiveIndices = find(truth);
ranks = nan(numel(positiveIndices), 1);
for cursor = 1:numel(positiveIndices)
    exampleIdx = positiveIndices(cursor);
    receiver = receiverIndices(exampleIdx);
    sameReceiver = find(receiverIndices == receiver);
    [~, order] = sort(scores(sameReceiver), 'descend');
    ranks(cursor) = find( ...
        sameReceiver(order) == exampleIdx, 1);
end
end

