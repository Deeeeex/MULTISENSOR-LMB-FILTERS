function [precision, recall, f1] = binaryEdgeMetrics(predicted, truth)
predicted = logical(reshape(predicted, [], 1));
truth = logical(reshape(truth, [], 1));
if numel(predicted) ~= numel(truth)
    error('Projected and target edge masks are misaligned.');
end
truePositive = nnz(predicted & truth);
predictedPositive = nnz(predicted);
truthPositive = nnz(truth);
if predictedPositive == 0
    precision = double(truthPositive == 0);
else
    precision = truePositive / predictedPositive;
end
if truthPositive == 0
    recall = double(predictedPositive == 0);
else
    recall = truePositive / truthPositive;
end
if precision + recall <= eps
    f1 = 0;
else
    f1 = 2 * precision * recall / (precision + recall);
end
end

