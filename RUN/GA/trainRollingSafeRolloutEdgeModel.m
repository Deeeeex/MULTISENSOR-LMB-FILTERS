function gradients = clipGradients(gradients, maximumNorm)
totalSquared = 0;
for gradient = gradients
    totalSquared = totalSquared + sum(gradient{1}(:).^2);
end
normValue = sqrt(totalSquared);
if normValue <= maximumNorm
    return;
end
scale = maximumNorm / max(normValue, eps);
for gradientIdx = 1:numel(gradients)
    gradients{gradientIdx} = gradients{gradientIdx} * scale;
end
end

function value = stableSigmoid(value)
positive = value >= 0;
negative = ~positive;
output = zeros(size(value));
output(positive) = 1 ./ (1 + exp(-value(positive)));
expValue = exp(value(negative));
output(negative) = expValue ./ (1 + expValue);
value = output;
end

function value = zerosLike(value)
value = zeros(size(value));
end

function validateDataset(dataset, protocol)
required = { ...
    'protocolId', 'contractVersion', 'seeds', ...
    'designSeeds', 'sourceWeight', ...
    'payloadToleranceFraction', ...
    'filterSeedOffset', 'behaviorCacheRecords', ...
    'behaviorCacheSha256', ...
    'generationGitCommit', ...
    'generationResearchWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'featureContextMode', 'featureNames', 'blocks', ...
    'featuresUseTruth', 'labelsUseTruth', ...
    'labelSelectionUsesFutureOutcome'};
if ~isstruct(dataset) || ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~isequal(reshape(dataset.seeds, 1, []), ...
            protocol.datasetSeeds) || ...
        ~isequal(reshape(dataset.designSeeds, 1, []), ...
            protocol.designSeeds) || ...
        abs(dataset.sourceWeight - protocol.sourceWeight) > 1e-12 || ...
        ~sameScalar(dataset.payloadToleranceFraction, ...
            protocol.payloadToleranceFraction) || ...
        dataset.filterSeedOffset ~= ...
            protocol.filterSeedOffset || ...
        ~isequal(reshape(dataset.behaviorCacheSha256, 1, []), ...
            reshape(protocol.behaviorCacheSha256, 1, [])) || ...
        numel(dataset.behaviorCacheRecords) ~= ...
            numel(protocol.datasetSeeds) || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        isempty(regexp(dataset.generationGitCommit, ...
            '^[0-9a-f]{40}$', 'once')) || ...
        dataset.featuresUseTruth || ...
        ~dataset.labelsUseTruth || ...
        ~dataset.labelSelectionUsesFutureOutcome
    error('Invalid rolling-safe rollout imitation dataset contract.');
end
for cacheIdx = 1:numel(dataset.behaviorCacheRecords)
    record = dataset.behaviorCacheRecords(cacheIdx);
    if record.seed ~= protocol.datasetSeeds(cacheIdx) || ...
            ~strcmp(record.sha256, ...
                protocol.behaviorCacheSha256{cacheIdx})
        error('Rollout continuation-cache provenance is invalid.');
    end
end
positiveCounts = [dataset.blocks.selectedCrossEdgeCount];
if nnz(positiveCounts == 0) < ...
        protocol.minimumZeroEdgeBlockCount || ...
        nnz(positiveCounts == 1) < ...
            protocol.minimumSingleEdgeBlockCount
    error(['Rollout dataset lacks the frozen zero/single-edge ', ...
        'support contract.']);
end
for block = dataset.blocks
    if size(block.features, 2) ~= ...
            numel(dataset.featureNames) || ...
            size(block.features, 1) ~= ...
                numel(block.selectedCrossMask) || ...
            any(~isfinite(block.features(:))) || ...
            ~block.labelTruthUsed || ...
            ~all(isfield(block, { ...
                'groupIds', 'senderPayloadBytes', ...
                'selectedAdjacency', 'physicalAdjacency', ...
                'previousAdjacencyHistory'})) || ...
            numel(block.groupIds) ~= ...
                size(block.selectedAdjacency, 1) || ...
            numel(block.senderPayloadBytes) ~= ...
                numel(block.groupIds) || ...
            any(~isfinite(block.senderPayloadBytes)) || ...
            any(block.senderPayloadBytes < 0)
        error('Rollout imitation block contract is invalid.');
    end
    validateBlockCandidateContract(block);
end
end

function validateBlockCandidateContract(block)
nodeCount = numel(block.groupIds);
featureKeys = block.receiverIndices + ...
    nodeCount * (block.senderIndices - 1);
[expectedReceivers, expectedSenders] = ...
    find(logical(block.physicalAdjacency));
crossMask = block.groupIds(expectedReceivers) ~= ...
    block.groupIds(expectedSenders);
expectedKeys = expectedReceivers(crossMask) + ...
    nodeCount * (expectedSenders(crossMask) - 1);
if numel(featureKeys) ~= numel(expectedKeys) || ...
        numel(unique(featureKeys)) ~= numel(featureKeys) || ...
        ~all(ismember(expectedKeys, featureKeys))
    error('Rollout imitation candidate-edge bijection is invalid.');
end
indices = sub2ind( ...
    [nodeCount, nodeCount], block.receiverIndices, ...
    block.senderIndices);
expectedLabels = reshape( ...
    logical(block.selectedAdjacency(indices)), [], 1);
if ~isequal(expectedLabels, ...
        logical(reshape(block.selectedCrossMask, [], 1)))
    error('Rollout imitation labels do not match selected adjacency.');
end
sameFormation = ...
    block.groupIds(:) == block.groupIds(:)';
selectedCross = logical(block.selectedAdjacency);
selectedCross(sameFormation) = false;
if nnz(expectedLabels) ~= nnz(selectedCross)
    error('Rollout imitation labels omit selected cross edges.');
end
end

