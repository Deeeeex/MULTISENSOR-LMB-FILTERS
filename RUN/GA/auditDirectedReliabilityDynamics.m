function [reportPath, summary] = ...
    auditDirectedReliabilityDynamics(presetNames, seedList, options)
% AUDITDIRECTEDRELIABILITYDYNAMICS Test whether reliability routing changes.
%
% This audit is posterior-free. It compares the online reliability selector
% with the registered fixed-index control at every time step and reports
% route-map diversity without counting a continuation-prefix boundary.

if nargin < 1 || isempty(presetNames)
    presetNames = {'m24-hard', 'x36-clean-scale'};
elseif ischar(presetNames)
    presetNames = {presetNames};
end
if nargin < 2 || isempty(seedList)
    seedList = [7, 17, 27];
end
if nargin < 3 || isempty(options)
    options = struct();
end
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
writeReportEnabled = getField(options, 'writeReport', true);

records = repmat(emptyRecord(), numel(presetNames), numel(seedList));
for presetIdx = 1:numel(presetNames)
    presetName = char(presetNames{presetIdx});
    for seedIdx = 1:numel(seedList)
        seed = seedList(seedIdx);
        fprintf('Auditing %s seed %d...\n', presetName, seed);
        rng(seed);
        config = buildDynamicTopologyScenarioConfig(presetName);
        [sensorTrajectories, ~] = ...
            generateMultiFormationTrajectories(config);
        graphs = buildDynamicTopologyGraphs(config, sensorTrajectories);
        [pDropByEdge, ~] = ...
            buildDynamicTopologyLinkSchedule(config, graphs);
        model = struct( ...
            'dynamicTopologyScenario', struct('config', config));
        context = struct( ...
            'localPosteriorBySensor', ...
                {repmat({struct([])}, 1, config.numberOfSensors)}, ...
            'model', model, ...
            'physicalAdjacency', false(config.numberOfSensors), ...
            'commConfig', struct('pDropByEdge', pDropByEdge), ...
            'currentTime', 1, ...
            'directedMessageBudget', config.numberOfSensors);

        maps = false( ...
            config.numberOfSensors, config.numberOfSensors, ...
            config.simulationLength);
        exactFixedClone = true;
        for timeIdx = 1:config.simulationLength
            context.currentTime = timeIdx;
            context.physicalAdjacency = ...
                graphs.physicalAdjacency(:, :, timeIdx);
            [maps(:, :, timeIdx), reliabilityDetails] = ...
                selectAnalyticDirectedRoutingPolicy( ...
                    context, 'reliability', ...
                    struct('sourceWeight', 0.50));
            [fixedMap, fixedDetails] = ...
                selectRegisteredDirectedRoutingPolicy( ...
                    context, 'fixed-index-star', ...
                    struct('sourceWeight', 0.50));
            exactFixedClone = exactFixedClone && ...
                isequal(maps(:, :, timeIdx), fixedMap) && ...
                isequal( ...
                    reliabilityDetails.fusionWeightMatrix, ...
                    fixedDetails.fusionWeightMatrix);
        end

        record = emptyRecord();
        record.presetName = presetName;
        record.seed = seed;
        record.sensorCount = config.numberOfSensors;
        record.timeCount = config.simulationLength;
        record.distinctMapCount = size(unique( ...
            reshape(maps, [], config.simulationLength)', ...
            'rows'), 1);
        if config.simulationLength < 2
            record.withinWindowReceiverChangeFraction = 0;
        else
            changed = xor( ...
                maps(:, :, 1:(end - 1)), maps(:, :, 2:end));
            record.withinWindowReceiverChangeFraction = ...
                nnz(any(changed, 2)) / ...
                (config.numberOfSensors * ...
                 (config.simulationLength - 1));
        end
        record.exactFixedIndexClone = exactFixedClone;
        record.crossFormationMessageFraction = ...
            crossFormationFraction(maps, config.sensorGroupIds);
        record.receiverCoverageFraction = ...
            nnz(any(maps, 2)) / ...
            (config.numberOfSensors * config.simulationLength);
        senderLoad = sum(maps(:, :, 1), 1);
        record.maximumSenderLoad = max(senderLoad);
        record.firstFormationSenderMap = senderMapForGroup( ...
            maps(:, :, 1), ...
            find(config.sensorGroupIds == config.sensorGroupIds(1)));
        records(presetIdx, seedIdx) = record;
    end
end

summary = struct();
summary.generatedAt = datestr(now, 31);
summary.presetNames = presetNames;
summary.seedList = reshape(seedList, 1, []);
summary.records = records;
summary.allExactFixedIndexClones = ...
    all([records.exactFixedIndexClone]);
summary.allRoutesStatic = ...
    all([records.distinctMapCount] == 1) && ...
    all([records.withinWindowReceiverChangeFraction] == 0);

reportPath = '';
if writeReportEnabled
    if ~exist(outputDirectory, 'dir')
        mkdir(outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    stem = ['DIRECTED_RELIABILITY_DYNAMICITY_AUDIT_', timestamp];
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    writeReport(reportPath, summary);
    save(matPath, 'summary');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    fprintf('Report: %s\n', reportPath);
end
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', 0, ...
    'sensorCount', 0, ...
    'timeCount', 0, ...
    'distinctMapCount', 0, ...
    'withinWindowReceiverChangeFraction', NaN, ...
    'exactFixedIndexClone', false, ...
    'crossFormationMessageFraction', NaN, ...
    'receiverCoverageFraction', NaN, ...
    'maximumSenderLoad', NaN, ...
    'firstFormationSenderMap', []);
end

function fraction = crossFormationFraction(maps, groupIds)
groupIds = reshape(groupIds, 1, []);
crossFormation = groupIds(:) ~= groupIds;
crossCount = 0;
messageCount = 0;
for timeIdx = 1:size(maps, 3)
    active = maps(:, :, timeIdx);
    crossCount = crossCount + nnz(active & crossFormation);
    messageCount = messageCount + nnz(active);
end
fraction = crossCount / max(messageCount, 1);
end

function senderMap = senderMapForGroup(adjacency, members)
senderMap = nan(1, numel(members));
for localReceiverIdx = 1:numel(members)
    receiverIdx = members(localReceiverIdx);
    senderIdx = find(adjacency(receiverIdx, :), 1);
    if ~isempty(senderIdx)
        senderMap(localReceiverIdx) = find( ...
            members == senderIdx, 1);
    end
end
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open report path: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Directed reliability dynamicity audit\n\n');
fprintf(fid, '- Generated: %s\n', summary.generatedAt);
fprintf(fid, '- Seeds: `%s`\n', mat2str(summary.seedList));
fprintf(fid, '- All routes static: `%d`\n', summary.allRoutesStatic);
fprintf(fid, '- Exact fixed-index clones: `%d`\n\n', ...
    summary.allExactFixedIndexClones);
fprintf(fid, ['| Preset | Seed | Sensors | Steps | Distinct maps | ', ...
    'Within-window receiver changes | Exact fixed clone | ', ...
    'Cross-formation | Coverage | Max sender load | ', ...
    'First formation sender map |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|\n');
for recordIdx = 1:numel(summary.records)
    record = summary.records(recordIdx);
    fprintf(fid, ['| %s | %d | %d | %d | %d | %.4f | %d | ', ...
        '%.4f | %.4f | %.0f | `%s` |\n'], ...
        record.presetName, record.seed, record.sensorCount, ...
        record.timeCount, record.distinctMapCount, ...
        record.withinWindowReceiverChangeFraction, ...
        record.exactFixedIndexClone, ...
        record.crossFormationMessageFraction, ...
        record.receiverCoverageFraction, ...
        record.maximumSenderLoad, ...
        mat2str(record.firstFormationSenderMap));
end
fprintf(fid, ['\nInterpretation: the audited reliability arm is a fixed ', ...
    'receiver-specific one-incoming-message control. Any tracking gain ', ...
    'from that arm cannot be attributed to online topology adaptation.\n']);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
