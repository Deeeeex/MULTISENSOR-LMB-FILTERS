function [auditPath, audit] = ...
    auditStructuredSetProposalGeneralizationGap(options)
% AUDITSTRUCTUREDSETPROPOSALGENERALIZATIONGAP Training-vs-LOSO diagnosis.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeStructuredProposalProtocol();
criticProtocol = getRollingSafeJointActionCriticProtocol();
modelVariant = lower(strrep(char(getField( ...
    options, 'modelVariant', 'sampled-bank-v1')), '_', '-'));
exactOracleMode = strcmp(modelVariant, ...
    protocol.exactOracleMethodVariant);
if exactOracleMode
    modelPathDefault = protocol.exactOracleModelPath;
    modelSha256 = protocol.exactOracleModelSha256;
    modelGenerationCommit = ...
        protocol.exactOracleModelGenerationCommit;
    modelContractVersion = ...
        protocol.exactOracleModelContractVersion;
else
    modelPathDefault = protocol.structuredModelPath;
    modelSha256 = protocol.structuredModelSha256;
    modelGenerationCommit = ...
        protocol.structuredModelGenerationCommit;
    modelContractVersion = protocol.modelContractVersion;
end
required = {'datasetSha256'};
if ~all(isfield(protocol, required))
    error('Structured set-proposal model is not frozen.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official structured proposal diagnosis requires clean source.');
end
modelPath = getField(options, ...
    'modelPath', modelPathDefault);
datasetPath = getField(options, ...
    'datasetPath', protocol.datasetPath);
validateFrozenFile(modelPath, ...
    modelSha256, 'structured proposal model');
validateFrozenFile(datasetPath, ...
    protocol.datasetSha256, 'structured proposal dataset');
modelLoaded = load(modelPath, 'model');
datasetLoaded = load(datasetPath, 'dataset');
model = modelLoaded.model;
dataset = datasetLoaded.dataset;
if ~strcmp(model.contractVersion, ...
        modelContractVersion) || ...
        ~strcmp(model.trainingGitCommit, ...
            modelGenerationCommit) || ...
        ~strcmp(model.datasetSha256, protocol.datasetSha256) || ...
        model.featuresUseTruth || model.labelsUseFutureOutcome || ...
        model.stateCollectionBehaviorUsesTruth || ...
        model.proposalReturnGenerationAuthorized
    error('Frozen structured proposal model violates audit contract.');
end

rows = repmat(emptyRow(), 1, numel(dataset.blocks));
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    teacher = dataset.teacherBlocks(blockIdx);
    [features, names] = buildFormationTreeContextFeatures( ...
        block.features, dataset.featureNames, ...
        block.receiverIndices, block.senderIndices, ...
        reshape(block.groupIds, 1, []), ...
        model.featureContextMode);
    if ~isequal(reshape(names, 1, []), ...
            reshape(model.featureNames, 1, []))
        error('Structured proposal feature contract changed.');
    end
    scores = scoreModel(model, features);
    [masks, hashes, failures] = ...
        projectBank(block, scores, criticProtocol);
    captured = ismember(teacher.targetGraphSha256, hashes);
    bestF1 = 0;
    for proposalIdx = 1:size(masks, 2)
        for targetIdx = 1:teacher.targetCount
            intersection = nnz(masks(:, proposalIdx) & ...
                teacher.targetCrossMasks(:, targetIdx));
            denominator = nnz(masks(:, proposalIdx)) + ...
                nnz(teacher.targetCrossMasks(:, targetIdx));
            bestF1 = max(bestF1, ...
                2 * intersection / max(denominator, 1));
        end
    end
    row = emptyRow();
    row.seed = block.seed;
    row.currentTime = block.currentTime;
    row.targetCount = teacher.targetCount;
    row.capturedTargetCount = nnz(captured);
    row.stateCaptured = any(captured);
    row.bestTargetEdgeF1 = bestF1;
    row.distinctProposalCount = numel(hashes);
    row.projectionFailureCount = failures;
    rows(blockIdx) = row;
end
training = summarizeRows(rows);
loso = model.expandedTopKMetrics;
if training.stateCount ~= protocol.expectedBlockCount || ...
        loso.stateCount ~= protocol.expectedBlockCount
    error('Structured proposal diagnosis state grid changed.');
end

audit = struct();
audit.contractVersion = ...
    'rolling-safe-structured-set-generalization-audit-m24-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
audit.modelPath = modelPath;
audit.modelVariant = modelVariant;
audit.modelSha256 = computeFileSha256(modelPath);
audit.datasetPath = datasetPath;
audit.datasetSha256 = computeFileSha256(datasetPath);
audit.trainingMetrics = training;
audit.losoMetrics = loso;
audit.finalTrainingLoss = model.finalTrainingLoss;
audit.trainingToLosoStateCaptureGap = ...
    training.stateCaptureFraction - loso.stateCaptureFraction;
audit.trainingToLosoGraphRecallGap = ...
    training.targetGraphRecallFraction - ...
        loso.targetGraphRecallFraction;
audit.trainingCaptureGatePassed = ...
    training.stateCaptureFraction + 1e-12 >= ...
        protocol.minimumStateCaptureFraction;
audit.seedSpecificGeneralizationFailure = ...
    audit.trainingCaptureGatePassed && ...
    ~model.expandedCaptureGatePassed && ...
    audit.trainingToLosoStateCaptureGap >= 0.50;
audit.sampledObjectiveToExactProjectorMismatch = ...
    ~exactOracleMode && ...
    ~audit.trainingCaptureGatePassed && ...
    model.finalTrainingLoss < model.trainingLossHistory(1) && ...
    training.meanDistinctProposalCount >= 2;
audit.exactOracleHardNegativeMiningRequired = ...
    audit.sampledObjectiveToExactProjectorMismatch;
audit.incompleteExactConstraintConvergence = ...
    exactOracleMode && ~audit.trainingCaptureGatePassed && ...
    isfield(model, 'hardNegativeAddedByRound') && ...
    ~isempty(model.hardNegativeAddedByRound) && ...
    model.hardNegativeAddedByRound(end) > 0;
audit.repeatFixedRoundScheduleAuthorized = false;
audit.moreCapacityAuthorized = false;
audit.proposalReturnGenerationAuthorized = false;
audit.criticTrainingAuthorized = false;
audit.x36Authorized = false;
audit.pass = true;
audit.evidenceBoundary = [ ...
    'This development diagnosis replays the final all-seed model ', ...
    'on its training states through the same exact top-16 ', ...
    'projector used in LOSO evaluation. It distinguishes ', ...
    'training-set projector capture from cross-seed generalization; ', ...
    'it is not held-out validation or tracking-benefit evidence.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
if exactOracleMode
    defaultAuditName = ...
        'exact_oracle_set_proposal_generalization_audit_m24.mat';
    defaultReportName = ...
        'EXACT_ORACLE_SET_PROPOSAL_GENERALIZATION_AUDIT_M24.md';
else
    defaultAuditName = ...
        'structured_set_proposal_generalization_audit_m24.mat';
    defaultReportName = ...
        'STRUCTURED_SET_PROPOSAL_GENERALIZATION_AUDIT_M24.md';
end
auditPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, defaultAuditName));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, defaultReportName));
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Structured proposal diagnosis: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function scores = scoreModel(model, features)
normalized = bsxfun(@rdivide, ...
    bsxfun(@minus, features, model.featureMean), ...
    model.featureScale);
hidden = tanh(bsxfun(@plus, ...
    normalized * model.hiddenWeight, model.hiddenBias));
scores = bsxfun(@plus, ...
    hidden * model.outputWeight, model.outputBias);
end

function [masks, hashes, failures] = ...
        projectBank(block, scores, protocol)
masks = false(size(scores, 1), 0);
hashes = cell(1, 0);
failures = 0;
for headIdx = 1:size(scores, 2)
    headScores = scores(:, headIdx);
    [mask, graphHash, valid] = projectOne( ...
        block, headScores, true(size(headScores)), protocol);
    if ~valid
        failures = failures + 1;
        continue
    end
    [masks, hashes] = appendUnique( ...
        masks, hashes, mask, graphHash);
    for selectedIdx = reshape(find(mask), 1, [])
        allowed = true(size(headScores));
        allowed(selectedIdx) = false;
        [alternativeMask, alternativeHash, valid] = ...
            projectOne(block, headScores, allowed, protocol);
        if valid
            [masks, hashes] = appendUnique( ...
                masks, hashes, ...
                alternativeMask, alternativeHash);
        else
            failures = failures + 1;
        end
    end
end
end

function [mask, graphHash, valid] = ...
        projectOne(block, scores, allowed, protocol)
options = struct( ...
    'minimumCurrentCrossEdges', ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'maximumCurrentCrossEdges', ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'currentAllowedExampleMask', allowed);
try
    [adjacency, details] = replayRollingSafeRolloutProjection( ...
        block, scores, protocol.sourceWeight, inf, options);
    valid = details.nominalProjectionFeasible && ...
        ~details.repairProjectionAttempted && ...
        ~details.repairTriggered && ...
        ~details.payloadEmergencyUsed && ...
        details.realizedCrossCount == ...
            protocol.valueProposalHeadExactCurrentCrossEdgeCount && ...
        ~details.truthUsed;
catch
    adjacency = false(numel(block.groupIds));
    details = struct();
    valid = false;
end
if ~valid
    mask = false(size(scores));
    graphHash = '';
    return
end
keys = sub2ind(size(adjacency), ...
    block.receiverIndices, block.senderIndices);
mask = reshape(logical(adjacency(keys)), [], 1);
graphHash = computeTextSha256(sprintf( ...
    '%d,', details.selectedSourcesByReceiver));
end

function [masks, hashes] = appendUnique( ...
        masks, hashes, mask, graphHash)
if any(strcmp(hashes, graphHash))
    return
end
masks(:, end + 1) = mask;
hashes{end + 1} = graphHash;
end

function metrics = summarizeRows(rows)
seeds = unique([rows.seed], 'stable');
seedCapture = zeros(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    mask = [rows.seed] == seeds(seedIdx);
    seedCapture(seedIdx) = mean([rows(mask).stateCaptured]);
end
metrics = struct( ...
    'rows', rows, ...
    'stateCount', numel(rows), ...
    'capturedStateCount', nnz([rows.stateCaptured]), ...
    'stateCaptureFraction', mean([rows.stateCaptured]), ...
    'minimumSeedCaptureFraction', min(seedCapture), ...
    'targetGraphCount', sum([rows.targetCount]), ...
    'capturedTargetGraphCount', ...
        sum([rows.capturedTargetCount]), ...
    'targetGraphRecallFraction', ...
        sum([rows.capturedTargetCount]) / sum([rows.targetCount]), ...
    'meanBestTargetEdgeF1', mean([rows.bestTargetEdgeF1]), ...
    'meanDistinctProposalCount', ...
        mean([rows.distinctProposalCount]), ...
    'projectionFailureCount', ...
        sum([rows.projectionFailureCount]));
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open structured proposal diagnosis report.');
end
cleanup = onCleanup(@() fclose(fid));
training = audit.trainingMetrics;
loso = audit.losoMetrics;
fprintf(fid, '# Structured set-proposal generalization audit: M24\n\n');
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Model SHA-256: `%s`\n', audit.modelSha256);
fprintf(fid, '- Model variant: `%s`\n', audit.modelVariant);
fprintf(fid, '- Final sampled-bank training loss: `%.6f`\n', ...
    audit.finalTrainingLoss);
fprintf(fid, '- Training-state capture: `%d / %d (%.3f%%)`\n', ...
    training.capturedStateCount, training.stateCount, ...
    100 * training.stateCaptureFraction);
fprintf(fid, '- Training graph recall: `%d / %d (%.3f%%)`\n', ...
    training.capturedTargetGraphCount, ...
    training.targetGraphCount, ...
    100 * training.targetGraphRecallFraction);
fprintf(fid, '- Training mean best edge F1 / distinct: `%.6f / %.6f`\n', ...
    training.meanBestTargetEdgeF1, ...
    training.meanDistinctProposalCount);
fprintf(fid, '- LOSO state capture: `%d / %d (%.3f%%)`\n', ...
    loso.capturedStateCount, loso.stateCount, ...
    100 * loso.stateCaptureFraction);
fprintf(fid, '- State-capture gap: `%.3f pp`\n', ...
    100 * audit.trainingToLosoStateCaptureGap);
fprintf(fid, '- Seed-specific generalization failure: `%d`\n', ...
    audit.seedSpecificGeneralizationFailure);
fprintf(fid, '- Sampled-objective/exact-projector mismatch: `%d`\n', ...
    audit.sampledObjectiveToExactProjectorMismatch);
fprintf(fid, '- Exact-oracle hard-negative mining required: `%d`\n', ...
    audit.exactOracleHardNegativeMiningRequired);
fprintf(fid, '- Incomplete exact-constraint convergence: `%d`\n', ...
    audit.incompleteExactConstraintConvergence);
fprintf(fid, '- Repeat fixed-round schedule authorized: `%d`\n', ...
    audit.repeatFixedRoundScheduleAuthorized);
fprintf(fid, '- More capacity authorized: `%d`\n', ...
    audit.moreCapacityAuthorized);
fprintf(fid, '- Return/critic/X36 authorized: `%d / %d / %d`\n', ...
    audit.proposalReturnGenerationAuthorized, ...
    audit.criticTrainingAuthorized, audit.x36Authorized);
fprintf(fid, '- Pass: `%d`\n', audit.pass);
fprintf(fid, '- Evidence boundary: %s\n', audit.evidenceBoundary);
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, 'currentTime', NaN, ...
    'targetCount', 0, 'capturedTargetCount', 0, ...
    'stateCaptured', false, 'bestTargetEdgeF1', 0, ...
    'distinctProposalCount', 0, ...
    'projectionFailureCount', 0);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
