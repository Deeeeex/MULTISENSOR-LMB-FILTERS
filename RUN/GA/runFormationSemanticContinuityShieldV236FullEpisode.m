function [reportPath, result] = ...
        runFormationSemanticContinuityShieldV236FullEpisode(options)
% RUNFORMATIONSEMANTICCONTINUITYSHIELDV236FULLEPISODE Teacher mechanism.
%
% The completed deterministic V227 static/dynamic pair is reused.  Only
% the matched V236 teacher arm is executed on the current clean source.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationSemanticContinuityShieldV236Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('FormationSemanticContinuityV236:DirtySource', ...
        'The official V236 teacher outcome requires clean frozen source.');
end
v227ResultPath = char(getField(options, 'v227ResultPath', ''));
if isempty(v227ResultPath) || exist(v227ResultPath, 'file') ~= 2
    error('FormationSemanticContinuityV236:MissingV227Pair', ...
        'A completed paired V227 MAT result is required.');
end
loaded = load(v227ResultPath, 'result');
paired = loaded.result;
validateV227Pair(paired, protocol);

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, sprintf('%s_seed%d', ...
        strrep(protocol.presetName, '-', '_'), protocol.seed))));
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_SEMANTIC_CONTINUITY_SHIELD_V236_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_SEMANTIC_CONTINUITY_SHIELD_V236_FULL_EPISODE.md');

fprintf('\nV236 semantic-continuity teacher: %s seed %d\n', ...
    protocol.presetName, protocol.seed);
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, protocol.seed);
fprintf('  running structural preflight ...\n');
preflight = preflightFormationSemanticContinuityShieldV236(inputs);
if ~preflight.structuralPass
    error('FormationSemanticContinuityV236:StructuralPreflight', ...
        'The V236 formation-row shield failed structural preflight.');
end
fprintf(['  routes=%d, changes=%d, shield pages=%d, ', ...
    'messages/round=%d\n'], preflight.uniqueTopologyCount, ...
    preflight.topologyChangeCount, preflight.shieldAppliedPageCount, ...
    preflight.messageCountPerRound);

config = buildFormationSemanticContinuityShieldV236Config( ...
    inputs.config, preflight.staticRegistration);
context = buildFormationSemanticContinuityShieldV236ExecutionContext( ...
    inputs.config.simulationLength);
filterModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
representatives = selectFormationRepresentativesLocal( ...
    inputs.config.sensorGroupIds);
metricWindow = struct( ...
    'activationStartTime', inputs.config.focusWindow(1), ...
    'activationEndTime', inputs.config.focusWindow(end));
rng(protocol.seed + protocol.filterSeedOffset, 'twister');
timerId = tic;
fprintf('  running matched teacher full episode ...\n');
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    filterModel, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, context);
teacher = summarizeRepeatedMultiGatewayFullEpisodeArm( ...
    protocol.armId, estimates, diagnostics, inputs.groundTruthRfs, ...
    inputs.config, representatives, metricWindow, toc(timerId));
teacher = attachTopologySummary(teacher, diagnostics);
assertRuntimeTeacher(teacher, preflight, diagnostics);

result = struct();
result.contractVersion = ...
    'formation-semantic-continuity-shield-v236-result-v1';
result.protocolId = protocol.id;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.v227GenerationGitCommit = paired.generationGitCommit;
result.v227ResultPath = v227ResultPath;
result.presetName = protocol.presetName;
result.seed = protocol.seed;
result.splitName = protocol.splitName;
result.static = paired.static;
result.dynamic = paired.dynamic;
result.teacher = teacher;
result.preflight = compactPreflight(preflight);
result.comparisonToStatic = compareArm(teacher, paired.static);
result.comparisonToDynamic = compareArm(teacher, paired.dynamic);
result.retainedGainFraction = retainedGainFraction( ...
    result.comparisonToStatic, paired.comparison);
result.materialGate = evaluateMaterialGate( ...
    result, protocol.materialGate);
result.scheduleSelectedFromOfflineOutcome = true;
result.runtimeTruthUsed = teacher.policyTruthUsed;
result.runtimeFutureOutcomeUsed = teacher.policyFutureOutcomeUsed;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf(['  teacher E-OSPA %.3f; RMSE %.3f; focus consensus %.3f; ', ...
    'bytes %.0f; %.1f s\n'], teacher.fullHorizonPositionEospa, ...
    teacher.fullHorizonPositionRmse, ...
    teacher.focusInterFormationPositionOspa, ...
    teacher.attemptedPayloadBytes, teacher.elapsedSeconds);
fprintf('  material teacher gate: %d\n', result.materialGate.passed);
fprintf('V236 result: %s\n', reportPath);
end

function validateV227Pair(paired, protocol)
required = {'contractVersion', 'presetName', 'seed', 'splitName', ...
    'static', 'dynamic', 'comparison', 'staticRegistration', ...
    'pairedOutcomeAvailable', 'generationGitCommit'};
if ~isstruct(paired) || ~isscalar(paired) || ...
        ~all(isfield(paired, required)) || ...
        ~strcmp(paired.contractVersion, ...
            'corrected-static-routing-v227-full-episode-result-v1') || ...
        ~paired.pairedOutcomeAvailable || ...
        ~strcmp(paired.presetName, protocol.presetName) || ...
        paired.seed ~= protocol.seed || ...
        ~strcmp(paired.splitName, protocol.splitName)
    error('FormationSemanticContinuityV236:V227PairMismatch', ...
        'The V227 reference pair does not match the frozen teacher case.');
end
end

function arm = attachTopologySummary(arm, diagnostics)
pages = logical(diagnostics.topologyActiveEdge);
arm.uniqueTopologyCount = uniquePageCount(pages);
arm.topologyChangeCount = pageChangeCount(pages);
arm.routeMessageCountByTime = pageCounts(pages);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed);
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed);
arm.sensorStrongConnected = all( ...
    diagnostics.topologyPolicySensorWindowStrong ~= 0);
arm.formationStrongConnected = all( ...
    diagnostics.topologyPolicyFormationWindowStrong ~= 0);
end

function assertRuntimeTeacher(arm, preflight, diagnostics)
certificates = diagnostics.topologyPolicyScheduleCertificate;
teacherDisclosurePassed = all(cellfun(@(certificate) ...
    isstruct(certificate) && ...
    isfield(certificate, 'teacherScheduleOutcomeDerived') && ...
    logical(certificate.teacherScheduleOutcomeDerived) && ...
    isfield(certificate, 'truthReadAtRuntime') && ...
    ~logical(certificate.truthReadAtRuntime) && ...
    isfield(certificate, 'futureOutcomeReadAtRuntime') && ...
    ~logical(certificate.futureOutcomeReadAtRuntime), certificates));
if ~arm.exactMessageParityPassed || ...
        ~arm.physicalFeasibilityPassed || ...
        arm.routeMessageCountMinimum ~= preflight.messageCountPerRound || ...
        arm.routeMessageCountMaximum ~= preflight.messageCountPerRound || ...
        arm.policyTruthUsed || arm.policyFutureOutcomeUsed || ...
        ~arm.sensorStrongConnected || ~arm.formationStrongConnected || ...
        ~teacherDisclosurePassed
    error('FormationSemanticContinuityV236:RuntimeContractFailed', ...
        'The executed V236 teacher violated its matched contract.');
end
end

function comparison = compareArm(candidate, reference)
comparison = struct();
comparison.fullHorizonEospaGainPercent = lowerGain( ...
    reference.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionEospa);
comparison.focusWindowEospaGainPercent = lowerGain( ...
    reference.focusWindowPositionEospa, ...
    candidate.focusWindowPositionEospa);
comparison.worstSensorEospaGainPercent = lowerGain( ...
    reference.worstSensorPositionEospa, ...
    candidate.worstSensorPositionEospa);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.fullHorizonRmseGainPercent = lowerGain( ...
    reference.fullHorizonPositionRmse, ...
    candidate.fullHorizonPositionRmse);
comparison.focusWindowRmseGainPercent = lowerGain( ...
    reference.focusWindowPositionRmse, ...
    candidate.focusWindowPositionRmse);
comparison.worstSensorRmseGainPercent = lowerGain( ...
    reference.worstSensorPositionRmse, ...
    candidate.worstSensorPositionRmse);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.fullConsensusGainPercent = lowerGain( ...
    reference.meanInterFormationPositionOspa, ...
    candidate.meanInterFormationPositionOspa);
comparison.focusConsensusGainPercent = lowerGain( ...
    reference.focusInterFormationPositionOspa, ...
    candidate.focusInterFormationPositionOspa);
comparison.terminalConsensusGainPercent = lowerGain( ...
    reference.terminalInterFormationPositionOspa, ...
    candidate.terminalInterFormationPositionOspa);
comparison.attemptedByteSavingPercent = lowerGain( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
comparison.deliveredByteSavingPercent = lowerGain( ...
    reference.deliveredPayloadBytes, candidate.deliveredPayloadBytes);
comparison.cardinalityGainPercent = lowerGain( ...
    reference.meanAbsoluteCardinalityError, ...
    candidate.meanAbsoluteCardinalityError);
end

function retained = retainedGainFraction(candidateGain, dynamicGain)
names = {'fullHorizonEospaGainPercent', ...
    'fullHorizonRmseGainPercent', 'focusConsensusGainPercent', ...
    'attemptedByteSavingPercent'};
retained = struct();
ratios = nan(1, numel(names));
for index = 1:numel(names)
    name = names{index};
    ratios(index) = candidateGain.(name) / ...
        max(dynamicGain.(name), eps);
end
retained.metricNames = names;
retained.byMetric = ratios;
retained.minimum = min(ratios);
retained.mean = mean(ratios);
end

function gate = evaluateMaterialGate(result, thresholds)
gain = result.comparisonToStatic;
targetIndex = result.protocol.targetFormationId;
checks = [ ...
    gain.fullHorizonEospaGainPercent > ...
        thresholds.aggregateEospaGainOverStaticPercent, ...
    gain.fullHorizonRmseGainPercent > ...
        thresholds.aggregateRmseGainOverStaticPercent, ...
    gain.focusConsensusGainPercent > ...
        thresholds.focusConsensusGainOverStaticPercent, ...
    gain.attemptedByteSavingPercent > ...
        thresholds.attemptedByteSavingOverStaticPercent, ...
    gain.formationEospaGainPercent(targetIndex) >= ...
        thresholds.targetFormationEospaGainOverStaticPercent, ...
    gain.formationRmseGainPercent(targetIndex) >= ...
        thresholds.targetFormationRmseGainOverStaticPercent, ...
    result.retainedGainFraction.minimum >= ...
        thresholds.minimumRetainedAggregateGainFraction];
gate = struct();
gate.checkNames = {'aggregate-eospa-positive', ...
    'aggregate-rmse-positive', 'focus-consensus-positive', ...
    'attempted-byte-saving-positive', 'target-formation-eospa-nonnegative', ...
    'target-formation-rmse-nonnegative', ...
    'retain-at-least-half-of-each-dynamic-mean-gain'};
gate.checks = checks;
gate.passed = all(checks);
end

function preflight = compactPreflight(preflight)
preflight = rmfield(preflight, ...
    {'staticRegistration', 'pages', 'fusionWeightMatrixByTime'});
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FormationSemanticContinuityV236:ReportWriteFailed', ...
        'Could not create the V236 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V236 formation semantic-continuity teacher\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Current source commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Reused V227 pair commit: `%s`\n', ...
    result.v227GenerationGitCommit);
fprintf(fid, '- Outcome-derived schedule: `F%d`, from `t=%d`\n', ...
    result.protocol.targetFormationId, ...
    result.protocol.shieldStartTime);
fprintf(fid, '- Runtime truth / future outcome read: `%d / %d`\n\n', ...
    result.runtimeTruthUsed, result.runtimeFutureOutcomeUsed);
fprintf(fid, ['| Arm | Full E-OSPA | Focus E-OSPA | Full RMSE | ', ...
    'Focus RMSE | Focus consensus | Attempted bytes | Routes |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|\n');
writeArmRow(fid, 'Static', result.static);
writeArmRow(fid, 'Dynamic', result.dynamic);
writeArmRow(fid, 'V236 teacher', result.teacher);
writeGainSection(fid, 'V236 teacher over static', ...
    result.comparisonToStatic, result.protocol.targetFormationId);
writeGainSection(fid, 'V236 teacher over dynamic', ...
    result.comparisonToDynamic, result.protocol.targetFormationId);
fprintf(fid, '\n## Material mechanism gate\n\n');
for index = 1:numel(result.materialGate.checks)
    fprintf(fid, '- %s: `%d`\n', ...
        result.materialGate.checkNames{index}, ...
        result.materialGate.checks(index));
end
fprintf(fid, '- Overall pass: `%d`\n', result.materialGate.passed);
fprintf(fid, '- Minimum retained mean-gain fraction: `%.3f`\n', ...
    result.retainedGainFraction.minimum);
fprintf(fid, '\n## Structural preflight\n\n');
fprintf(fid, ['Routes `%d`; changes `%d`; shield pages `%d`; ', ...
    'messages/round `%d`; all physical/weight/sensor-strong/', ...
    'formation-strong `%d/%d/%d/%d`.\n'], ...
    result.preflight.uniqueTopologyCount, ...
    result.preflight.topologyChangeCount, ...
    result.preflight.shieldAppliedPageCount, ...
    result.preflight.messageCountPerRound, ...
    result.preflight.allPhysicalPassed, ...
    result.preflight.allWeightPassed, ...
    result.preflight.allSensorStrongConnected, ...
    result.preflight.allFormationStrongConnected);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeArmRow(fid, label, arm)
fprintf(fid, '| %s | %.3f | %.3f | %.3f | %.3f | %.3f | %.0f | %d |\n', ...
    label, arm.fullHorizonPositionEospa, ...
    arm.focusWindowPositionEospa, arm.fullHorizonPositionRmse, ...
    arm.focusWindowPositionRmse, ...
    arm.focusInterFormationPositionOspa, ...
    arm.attemptedPayloadBytes, arm.uniqueTopologyCount);
end

