function result = runFormationB4V55RuntimeSmoke( ...
        runtimeModes, timeCount, presetName, seed)
% RUNFORMATIONB4V55RUNTIMESMOKE Short paired V55 mechanism check.

if nargin < 1 || isempty(runtimeModes)
    runtimeModes = { ...
        'projection-only', ...
        'context-aware-selection-only', ...
        'context-aware-combined'};
elseif ischar(runtimeModes)
    runtimeModes = {runtimeModes};
end
if nargin < 2 || isempty(timeCount)
    timeCount = 8;
end
if nargin < 3 || isempty(presetName)
    presetName = 'm24-formation-fov-convoy';
end
if nargin < 4 || isempty(seed)
    seed = 41;
end

inputs = truncateInputs( ...
    generateDynamicTopologyScenarioInputs(presetName, seed), ...
    timeCount);
identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
[inputs.commConfig.linkUniforms, ~] = ...
    materializePhysicalUidDirectedDeliveryUniforms( ...
        55008, identity.sensorPhysicalUids, timeCount);
model = removeRealizedTargetTruth(inputs.model);
protocol = getFormationB4V49RuntimeProtocol();
context = buildFormationB4V49PairedTrackingDevelopmentContext( ...
    presetName, seed, protocol.referenceArmId);

arms = repmat(makeArm(), 1, numel(runtimeModes));
for modeIdx = 1:numel(runtimeModes)
    mode = runtimeModes{modeIdx};
    triggerConfig = buildFormationB4V46FixedTriggerConfig( ...
        protocol.referenceArmId, inputs.config.numberOfSensors);
    triggerConfig.receiverSafeLabelFusionEnabled = true;
    triggerConfig.receiverSafeLabelFusionMode = mode;
    triggerConfig.receiverSafeOracleByteBudgetFraction = 1;
    triggerConfig.receiverSafeSupportedExistenceThreshold = 0.50;
    triggerConfig.receiverSafeMaximumLogOddsDrop = log(4);

    rng(55009, 'twister');
    [~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
        model, inputs.measurements, inputs.sensorTrajectories, ...
        inputs.neighborMap, inputs.commConfig, triggerConfig, context);
    summary = diagnostics.summary;
    selectionEnabled = any(strcmpi(mode, { ...
        'context-aware-selection-only', ...
        'context-aware-combined'}));
    projectionEnabled = any(strcmpi(mode, { ...
        'projection-only', ...
        'context-aware-combined'}));
    selectiveBytes = ...
        summary.receiverSafeAttemptedControlSynopsisBytes + ...
        summary.receiverSafeAttemptedSelectedPayloadBytes;
    if selectionEnabled
        selectionPassed = ...
            summary.receiverSafeSelectiveEdgeTimeCount > 0 && ...
            summary.receiverSafeBaselineFullBytes > 0 && ...
            summary.receiverSafeAttemptedControlSynopsisBytes > 0 && ...
            selectiveBytes <= ...
                summary.receiverSafeBaselineFullBytes + 1e-9;
    else
        selectionPassed = ...
            summary.receiverSafeSelectiveEdgeTimeCount == 0 && ...
            summary.receiverSafeAttemptedControlSynopsisBytes == 0 && ...
            summary.receiverSafeAttemptedSelectedPayloadBytes == 0;
    end
    if projectionEnabled
        projectionPassed = ...
            summary.receiverSafeRetentionRemovalCount == 0 && ...
            summary.receiverSafeRetentionUnresolvedCount == 0;
    else
        projectionPassed = ...
            summary.receiverSafeRetentionViolationCount == 0 && ...
            summary.receiverSafeRetentionRemovalCount == 0 && ...
            summary.receiverSafeRetentionClampCount == 0 && ...
            summary.receiverSafeRetentionUnresolvedCount == 0;
    end

    arm = makeArm();
    arm.runtimeMode = mode;
    arm.selectionEnabled = selectionEnabled;
    arm.projectionEnabled = projectionEnabled;
    arm.selectiveEdgeTimeCount = ...
        summary.receiverSafeSelectiveEdgeTimeCount;
    arm.baselineFullBytes = summary.receiverSafeBaselineFullBytes;
    arm.controlSynopsisBytes = ...
        summary.receiverSafeAttemptedControlSynopsisBytes;
    arm.selectedPayloadBytes = ...
        summary.receiverSafeAttemptedSelectedPayloadBytes;
    arm.totalAttemptedPayloadBytes = summary.attemptedPayloadBytes;
    arm.retentionViolationCount = ...
        summary.receiverSafeRetentionViolationCount;
    arm.retentionRemovalCount = ...
        summary.receiverSafeRetentionRemovalCount;
    arm.retentionClampCount = ...
        summary.receiverSafeRetentionClampCount;
    arm.retentionUnresolvedCount = ...
        summary.receiverSafeRetentionUnresolvedCount;
    arm.passed = selectionPassed && projectionPassed;
    arms(modeIdx) = arm;
    fprintf([ ...
        'V55 smoke %s: selective edge-times=%d, synopsis=%d B, ', ...
        'selected=%d B, total=%d B, violation/removal/clamp/', ...
        'unresolved=%d/%d/%d/%d, passed=%d\n'], ...
        arm.runtimeMode, arm.selectiveEdgeTimeCount, ...
        arm.controlSynopsisBytes, arm.selectedPayloadBytes, ...
        arm.totalAttemptedPayloadBytes, arm.retentionViolationCount, ...
        arm.retentionRemovalCount, arm.retentionClampCount, ...
        arm.retentionUnresolvedCount, arm.passed);
end

result = struct();
result.contractVersion = 'formation-b4-v55-runtime-smoke-result-v1';
result.presetName = presetName;
result.seed = seed;
result.timeCount = timeCount;
result.filterSeed = 55009;
result.deliverySeed = 55008;
result.arms = arms;
result.passed = all([arms.passed]);
if ~result.passed
    error('FormationB4V55Smoke:RuntimeFailed', ...
        'At least one V55 attribution mechanism failed its focused check.');
end
end

function arm = makeArm()
arm = struct( ...
    'runtimeMode', '', ...
    'selectionEnabled', false, ...
    'projectionEnabled', false, ...
    'selectiveEdgeTimeCount', 0, ...
    'baselineFullBytes', 0, ...
    'controlSynopsisBytes', 0, ...
    'selectedPayloadBytes', 0, ...
    'totalAttemptedPayloadBytes', 0, ...
    'retentionViolationCount', 0, ...
    'retentionRemovalCount', 0, ...
    'retentionClampCount', 0, ...
    'retentionUnresolvedCount', 0, ...
    'passed', false);
end

function inputs = truncateInputs(inputs, timeCount)
inputs.model.simulationLength = timeCount;
if isfield(inputs.model, 'dynamicTopologyScenario') && ...
        isfield(inputs.model.dynamicTopologyScenario, 'config')
    inputs.model.dynamicTopologyScenario.config.simulationLength = ...
        timeCount;
end
inputs.config.simulationLength = timeCount;
inputs.measurements = inputs.measurements(:, 1:timeCount);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:timeCount);
end
fields = {'pDropByEdge', 'linkUniforms'};
for fieldIdx = 1:numel(fields)
    name = fields{fieldIdx};
    if isfield(inputs.commConfig, name) && ...
            ndims(inputs.commConfig.(name)) >= 3
        value = inputs.commConfig.(name);
        inputs.commConfig.(name) = value(:, :, 1:timeCount);
    end
end
if isfield(inputs.commConfig, 'nodeActiveSchedule') && ...
        size(inputs.commConfig.nodeActiveSchedule, 2) >= timeCount
    inputs.commConfig.nodeActiveSchedule = ...
        inputs.commConfig.nodeActiveSchedule(:, 1:timeCount);
end
end

function model = removeRealizedTargetTruth(model)
if isfield(model, 'explicitTargetTrajectories')
    model = rmfield(model, 'explicitTargetTrajectories');
end
fields = {'targetTrajectories', 'target'};
for fieldIdx = 1:numel(fields)
    if isfield(model.dynamicTopologyScenario, fields{fieldIdx})
        model.dynamicTopologyScenario = rmfield( ...
            model.dynamicTopologyScenario, fields{fieldIdx});
    end
end
end
