function [reportPath, preflight] = ...
    auditFormationStaggeredRecoveryM24V36Preflight(options)
% AUDITFORMATIONSTAGGEREDRECOVERYM24V36PREFLIGHT Multi-state source gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = ...
    getFormationStaggeredRecoveryM24ReplicationProtocol();
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v36 preflight requires a clean tracked and ', ...
        'MATLAB/Octave source state.']);
end
primaryScreenPath = getField(options, ...
    'primaryScreenPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'formation_value_v35', 'staggered_recovery', ...
        't72', 'screen', ...
        ['FORMATION_STAGGERED_RECOVERY_H3_', ...
         'M24_FORMATION_FOV_SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_STAGGERED_RECOVERY_M24_V36_', ...
     'PREFLIGHT_20260802.md']));
matPath = getField(options, 'matPath', fullfile( ...
    protocol.outputRoot, 'preflight', ...
    'FORMATION_STAGGERED_RECOVERY_M24_V36_PREFLIGHT.mat'));

primaryLoaded = load(primaryScreenPath, 'screen');
if ~isfield(primaryLoaded, 'screen')
    error('V36Preflight:MissingPrimary', ...
        'Frozen v35 primary evidence is unavailable.');
end
assertPrimaryAuthorization(primaryLoaded.screen, protocol);
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, protocol.seed);
stateCount = numel(protocol.anchorTimes);
states = repmat(emptyState(), 1, stateCount);
for stateIdx = 1:stateCount
    anchorTime = protocol.anchorTimes(stateIdx);
    cachePath = fullfile(protocol.cacheRoot, sprintf( ...
        '%s_seed%d_n1_sig%d.mat', ...
        strrep(protocol.presetName, '-', '_'), ...
        protocol.seed, anchorTime));
    cacheSha256 = computeFileSha256(cachePath);
    if ~strcmp(cacheSha256, ...
            protocol.expectedCacheSha256{stateIdx})
        error('V36Preflight:CacheDrift', ...
            'Opened M24 cache hash changed at t=%d.', anchorTime);
    end
    [context, bundle] = buildOpenedContext( ...
        inputs, cachePath, anchorTime, protocol);

    controlTimer = tic;
    initialControl = ...
        buildFormationStaggeredRecoveryControl(context);
    controlSeconds = toc(controlTimer);
    assertInitialControl( ...
        initialControl, stateIdx, protocol);

    bank = buildTemporalCrossEdgeSuspensionActionBank( ...
        context, struct('scorePosteriorSafety', false));
    initialActionIdx = findActionIndex( ...
        bank, initialControl.selectedFormationIds);
    if initialActionIdx ~= ...
            protocol.expectedInitialActionIndices(stateIdx)
        error('V36Preflight:InitialActionDrift', ...
            'Initial action index changed at t=%d.', anchorTime);
    end
    sourceScreen = struct('cachePath', cachePath);
    sourcePreflight = struct( ...
        'initialBank', bank, ...
        'selectedInitialActionIndex', initialActionIdx);
    runtimeProtocol = protocol;
    runtimeProtocol.anchorTime = anchorTime;
    runtimeProtocol.reconnectTime = ...
        anchorTime + protocol.horizonSteps - 1;
    replayTimer = tic;
    replay = ...
        replayFormationStaggeredRecoveryV35SourceTrajectory( ...
            sourceScreen, sourcePreflight, runtimeProtocol);
    replaySeconds = toc(replayTimer);
    assertRuntimeReplay( ...
        replay, initialControl, stateIdx, protocol);

    state = emptyState();
    state.anchorTime = anchorTime;
    state.cachePath = cachePath;
    state.cacheSha256 = cacheSha256;
    state.cacheGenerationGitCommit = ...
        bundle.generationGitCommit;
    state.initialControlConstructionSeconds = controlSeconds;
    state.runtimeReplaySeconds = replaySeconds;
    state.initialControl = initialControl;
    state.initialActionIndex = initialActionIdx;
    state.runtimeReplay = replay;
    state.runtimeReplayPassed = true;
    state.trackingOutcomeScored = false;
    state.truthUsed = false;
    state.futureOutcomeUsed = false;
    states(stateIdx) = state;
end

cleanSource = ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles);
authorizedMask = cleanSource & [states.runtimeReplayPassed] & ...
    arrayfun(@(state) ...
        ~state.initialControl.referenceFallbackUsed && ...
        state.initialControl.selectedScore.safe && ...
        all(state.initialControl.selectedRollingB3SensorPass) && ...
        all(state.initialControl.selectedRollingB3FormationPass), ...
        states);

preflight = struct();
preflight.contractVersion = ...
    'formation-staggered-recovery-m24-v36-preflight-v1';
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.protocol = protocol;
preflight.primaryScreenPath = primaryScreenPath;
preflight.primaryScreenGenerationCommit = ...
    primaryLoaded.screen.generationGitCommit;
preflight.states = states;
preflight.anchorTimes = protocol.anchorTimes;
preflight.trackingOutcomeAuthorizedMask = authorizedMask;
preflight.authorizedStateCount = nnz(authorizedMask);
preflight.trackingOutcomeScored = false;
preflight.newPosteriorStateOpened = false;
preflight.gnnTrainingAuthorized = false;
preflight.x36Opened = false;
preflight.x48Opened = false;
preflight.validationClaimAllowed = false;
preflight.evidenceBoundary = protocol.evidenceBoundary;

if exist(fileparts(matPath), 'dir') ~= 7
    mkdir(fileparts(matPath));
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('V36 M24 replication preflight: %s\n', reportPath);
end

function assertPrimaryAuthorization(screen, protocol)
if ~strcmp(screen.contractVersion, ...
        'formation-staggered-recovery-v35-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            protocol.sourcePrimaryScreenCommit) || ...
        ~screen.causalStaggeredRecoveryAttested || ...
        ~screen.strongCandidateFound || ...
        screen.strictStrongCandidateCount ~= 1 || ...
        ~screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V36Preflight:PrimaryAuthorization', ...
        'Frozen v35 primary result did not authorize replication.');
end
end

function [context, bundle] = buildOpenedContext( ...
        inputs, cachePath, anchorTime, protocol)
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V36Preflight:MissingCache', ...
        'Opened cache is unavailable at t=%d.', anchorTime);
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.protocolId, protocol.cacheProtocolId) || ...
        ~strcmp(bundle.generationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        bundle.validationClaimAllowed || ...
        numel(bundle.posteriorSnapshots) < anchorTime || ...
        isempty(bundle.posteriorSnapshots{anchorTime}) || ...
        numel(bundle.preDecisionTopologyHistoryByTime) < ...
            anchorTime || ...
        isempty(bundle. ...
            preDecisionTopologyHistoryByTime{anchorTime})
    error('V36Preflight:CacheProvenance', ...
        'Opened cache provenance changed at t=%d.', anchorTime);
end
history = bundle.preDecisionTopologyHistoryByTime{anchorTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
nodeCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{anchorTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = anchorTime;
context.previousAdjacencyHistory = previousHistory;
context.previousAdjacencyHistoryCount = ...
    size(previousHistory, 3);
context.previousAdjacencyHistoryTimes = history.times;
context.previousAdjacency = previousHistory(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, anchorTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = ...
    inputs.graphData.positions(:, :, anchorTime);
end

function assertInitialControl(control, stateIdx, protocol)
expectedDebt = ...
    protocol.expectedInitialDebtFractionByState{stateIdx};
if ~strcmp(control.contractVersion, ...
        'formation-staggered-recovery-control-v1') || ...
        control.nodeCount ~= protocol.expectedNodeCount || ...
        control.formationCount ~= protocol.expectedFormationCount || ...
        ~isequal(control.selectedFormationIds, ...
            protocol. ...
                expectedInitialFormationIdsByState{stateIdx}) || ...
        control.referenceFallbackUsed || ...
        max(abs(control.baseControl. ...
            formationRetentionDebtFraction - expectedDebt)) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.referenceScore.networkRisk - ...
            protocol.expectedInitialReferenceRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        abs(control.selectedScore.networkRisk - ...
            protocol.expectedInitialSelectedRisk(stateIdx)) > ...
                protocol.sourceMetricTolerance || ...
        ~control.selectedScore.safe || ...
        ~all(control.selectedRollingB3SensorPass) || ...
        ~all(control.selectedRollingB3FormationPass) || ...
        control.truthUsed || control.futureOutcomeUsed
    error('V36Preflight:InitialControlDrift', ...
        'Initial v35 control drifted for replication state %d.', ...
        stateIdx);
end
end

function actionIdx = findActionIndex(bank, formationIds)
matches = false(1, bank.actionCount);
for candidateIdx = 1:bank.actionCount
    matches(candidateIdx) = isequal(reshape( ...
        bank.actionSuspendedFormationIds{candidateIdx}, 1, []), ...
        reshape(formationIds, 1, []));
end
actionIdx = find(matches);
if numel(actionIdx) ~= 1
    error('V36Preflight:InitialActionDrift', ...
        'Initial formation subset does not map uniquely to the bank.');
end
end

function assertRuntimeReplay( ...
        replay, initialControl, stateIdx, protocol)
expectedSelected = protocol. ...
    expectedRuntimeSelectedFormationIdsByState{stateIdx};
expectedReleased = protocol. ...
    expectedRuntimeReleasedFormationIdsByState{stateIdx};
expectedStaggered = protocol. ...
    expectedRuntimeStaggeredReleaseMaskByState{stateIdx};
expectedFallback = protocol. ...
    expectedRuntimeReferenceFallbackCountByState{stateIdx};
if ~strcmp(replay.contractVersion, ...
        'formation-staggered-recovery-v35-source-replay-v1') || ...
        ~isequal(replay.returnTimes, ...
            protocol.anchorTimes(stateIdx) + ...
                (0:protocol.horizonSteps - 1)) || ...
        ~isequal(replay.retentionDebtSelectedFormationIdsByTime{1}, ...
            initialControl.selectedFormationIds) || ...
        ~isequal(replay.retentionDebtSelectedFormationIdsByTime, ...
            expectedSelected) || ...
        ~isequal(replay.retentionDebtProjectionRemovalOrderByTime, ...
            expectedReleased) || ...
        ~isequal(replay.referenceFallbackCountByTime, ...
            expectedFallback) || ...
        ~all(replay.posteriorContentUsedByTime) || ...
        ~all(replay.currentLinkReliabilityUsedByTime) || ...
        ~all(replay.oneStepReservePassedByTime) || ...
        ~replay.firstActionExact || ...
        ~replay.firstFusionWeightsExact || ...
        replay.truthUsed || replay.futureOutcomeUsed || ...
        replay.trackingOutcomeScored || replay.groundTruthAccessed
    error('V36Preflight:RuntimeReplayDrift', ...
        'Full runtime replay drifted for replication state %d.', ...
        stateIdx);
end
for timeIdx = 1:protocol.horizonSteps
    schedule = replay.staggeredRecoveryScheduleByTime{timeIdx};
    if ~isstruct(schedule) || ...
            ~isfield(schedule, 'contractVersion') || ...
            ~strcmp(schedule.contractVersion, ...
                ['formation-staggered-recovery-', ...
                 'runtime-schedule-v1']) || ...
            schedule.currentTime ~= replay.returnTimes(timeIdx) || ...
            schedule.staggeredReleaseUsed ~= ...
                expectedStaggered(timeIdx) || ...
            ~isequal(schedule.selectedFormationIds, ...
                expectedSelected{timeIdx}) || ...
            ~isequal(schedule.releasedFormationIds, ...
                expectedReleased{timeIdx}) || ...
            schedule.truthUsed || schedule.futureOutcomeUsed
        error('V36Preflight:RuntimeReplayDrift', ...
            ['Runtime schedule drifted for replication ', ...
             'state %d at step %d.'], stateIdx, timeIdx);
    end
end
end

function state = emptyState()
state = struct( ...
    'anchorTime', NaN, ...
    'cachePath', '', ...
    'cacheSha256', '', ...
    'cacheGenerationGitCommit', '', ...
    'initialControlConstructionSeconds', NaN, ...
    'runtimeReplaySeconds', NaN, ...
    'initialControl', struct(), ...
    'initialActionIndex', NaN, ...
    'runtimeReplay', struct(), ...
    'runtimeReplayPassed', false, ...
    'trackingOutcomeScored', false, ...
    'truthUsed', false, ...
    'futureOutcomeUsed', false);
end

function writeReport(path, preflight)
fid = fopen(path, 'w');
if fid < 0
    error('V36Preflight:WriteFailed', ...
        'Could not open v36 preflight report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V36 multi-state M24 source-only preflight\n\n');
fprintf(fid, '- Contract / generation commit: `%s / %s`\n', ...
    preflight.contractVersion, preflight.generationGitCommit);
fprintf(fid, '- Tracked dirty / untracked source: `%d / %d`\n', ...
    preflight.generationTrackedWorktreeDirty, ...
    numel(preflight.generationUntrackedSourceFiles));
fprintf(fid, '- Preset / seed / anchor times: `%s / %d / %s`\n', ...
    preflight.protocol.presetName, preflight.protocol.seed, ...
    mat2str(preflight.anchorTimes));
fprintf(fid, '- Tracking scored: `0`\n');
fprintf(fid, '- Authorized states: `%d / %d`\n\n', ...
    preflight.authorizedStateCount, numel(preflight.states));

for stateIdx = 1:numel(preflight.states)
    state = preflight.states(stateIdx);
    replay = state.runtimeReplay;
    fprintf(fid, '## t=%d\n\n', state.anchorTime);
    fprintf(fid, '- Cache SHA-256: `%s`\n', state.cacheSha256);
    fprintf(fid, '- Initial action / formations: `%d / %s`\n', ...
        state.initialActionIndex, ...
        mat2str(state.initialControl.selectedFormationIds));
    fprintf(fid, '- Initial control / runtime replay: `%.2f / %.2f s`\n', ...
        state.initialControlConstructionSeconds, ...
        state.runtimeReplaySeconds);
    fprintf(fid, '- Tracking authorized: `%d`\n\n', ...
        preflight.trackingOutcomeAuthorizedMask(stateIdx));
    fprintf(fid, '| Time | Debt fractions | Selected | Released | Reserve |\n');
    fprintf(fid, '|--:|:--|:--|:--|:--:|\n');
    for timeIdx = 1:numel(replay.returnTimes)
        fprintf(fid, '| %d | `%s` | `%s` | `%s` | %d |\n', ...
            replay.returnTimes(timeIdx), ...
            mat2str(replay. ...
                retentionDebtFractionByTime{timeIdx}, 5), ...
            mat2str(replay. ...
                retentionDebtSelectedFormationIdsByTime{timeIdx}), ...
            mat2str(replay. ...
                retentionDebtProjectionRemovalOrderByTime{timeIdx}), ...
            replay.oneStepReservePassedByTime(timeIdx));
    end
    fprintf(fid, '\n');
end

fprintf(fid, '## Decision\n\n');
if all(preflight.trackingOutcomeAuthorizedMask)
    fprintf(fid, [ ...
        'All three already-opened M24 states pass the full source-only ', ...
        'runtime gate. One paired H=3 outcome per state is authorized ', ...
        'under the unchanged v35 numerical gates.\n\n']);
else
    fprintf(fid, [ ...
        'Only states marked above may open paired outcomes; all others ', ...
        'remain source-only.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
