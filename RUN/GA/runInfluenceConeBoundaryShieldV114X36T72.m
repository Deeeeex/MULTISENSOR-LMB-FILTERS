function [reportPath, result] = ...
        runInfluenceConeBoundaryShieldV114X36T72(options)
% RUNINFLUENCECONEBOUNDARYSHIELDV114X36T72 F6 arrival shielding.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getInfluenceConeBoundaryShieldV114Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('InfluenceConeBoundaryShieldV114:DirtySource', ...
        'The V114 screen requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
v113 = loadV113Screen(protocol, entry, currentTime);
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', protocol.executionProfile, ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', protocol.bankVariant, ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', 1:3, ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', protocol.v113ScreenPath, ...
    'capturePosteriorSnapshotsEnabled', false, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
screenMatPath = fullfile( ...
    screenOptions.outputDirectory, ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']);
reuseCompletedCandidateScreen = logical(getField( ...
    options, 'reuseCompletedCandidateScreen', true));
if reuseCompletedCandidateScreen && exist(screenMatPath, 'file') == 2
    loadedScreen = load(screenMatPath, 'screen');
    if ~isfield(loadedScreen, 'screen')
        error('InfluenceConeBoundaryShieldV114:InvalidCandidateScreen', ...
            'The saved V114 candidate screen lacks the screen variable.');
    end
    screen = loadedScreen.screen;
    validateCandidateScreen(screen, protocol, entry, currentTime);
    screenReportPath = screen.reportPath;
    candidateScreenReused = true;
else
    [screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
        entry.presetName, entry.seed, currentTime, screenOptions);
    candidateScreenReused = false;
end
if ~screen.referenceOutcomeReused || ...
        ~strcmp(screen.cacheSha256, v113.cacheSha256) || ...
        ~isequal(screen.sensorGroupIds, v113.sensorGroupIds)
    error('InfluenceConeBoundaryShieldV114:PairingDrift', ...
        'The V114 screen did not preserve the V113 paired baseline.');
end

[cwFullRecord, cwFullOutcome] = findArm( ...
    v113, protocol.clockwiseFullActionName);
[baseRecord, baseOutcome] = findArm( ...
    v113, protocol.baseMechanismActionName);
[ccwRecord, ~] = findArm(v113, 'reference-full-payload');
candidateRecords = repmat(emptyLabel(), 1, ...
    numel(protocol.candidateActionNames));

residual = logical(screen.bank.clockwiseCarrierPolicyDetails. ...
    residualAdjacency);
[receiverIds, sourceIds] = find(residual);
groupIds = reshape(screen.sensorGroupIds, 1, []);
boundaryMask = groupIds(receiverIds) == ...
        protocol.boundaryFormationId & ...
    groupIds(sourceIds) == protocol.boundaryFormationId - 1;
if nnz(boundaryMask) ~= 1 || ...
        receiverIds(boundaryMask) ~= ...
            protocol.boundaryReceiverSensorId || ...
        sourceIds(boundaryMask) ~= protocol.boundarySourceSensorId
    error('InfluenceConeBoundaryShieldV114:BoundaryDrift', ...
        'The registered clockwise F5-to-F6 boundary edge changed.');
end
targetMembers = find(groupIds == protocol.boundaryFormationId);
targetPeers = setdiff( ...
    targetMembers, protocol.boundaryReceiverSensorId, 'stable');

cwByTime = mean(cwFullOutcome.eospaBySensorTime, 1);
for candidateIdx = 1:numel(protocol.candidateActionNames)
    actionName = protocol.candidateActionNames{candidateIdx};
    [candidate, candidateOutcome, recordIdx] = findArm(screen, actionName);
    candidateByTime = mean(candidateOutcome.eospaBySensorTime, 1);
    gainByTime = relativeGainPercent(cwByTime, candidateByTime);
    [formationGain, formationGainByTime] = formationGains( ...
        cwFullOutcome.eospaBySensorTime, ...
        candidateOutcome.eospaBySensorTime, groupIds);
    targetPeerTerminalGain = relativeGainPercent( ...
        mean(cwFullOutcome.eospaBySensorTime(targetPeers, end)), ...
        mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));
    marginalTargetPeerTerminalGain = relativeGainPercent( ...
        mean(baseOutcome.eospaBySensorTime(targetPeers, end)), ...
        mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));
    label = emptyLabel();
    label.actionName = actionName;
    label.recordIndex = recordIdx;
    if strcmp(actionName, protocol.arrivalShieldActionName)
        label.shieldStartPage = protocol.arrivalPageIndex;
    else
        label.shieldStartPage = protocol.earlyPageIndex;
    end
    label.meanEospa = candidate.meanEospa;
    label.meanGainPercent = relativeGainPercent( ...
        cwFullRecord.meanEospa, candidate.meanEospa);
    label.marginalMeanGainPercent = relativeGainPercent( ...
        baseRecord.meanEospa, candidate.meanEospa);
    label.gainPercentByTime = gainByTime;
    label.formationGainPercent = formationGain;
    label.formationGainPercentByTime = formationGainByTime;
    label.minimumAfterMaturityGainPercent = min( ...
        gainByTime(protocol.firstHandoffTimeIndex:end));
    label.minimumFormationGainPercent = min(formationGain);
    label.targetPeerTerminalGainPercent = targetPeerTerminalGain;
    label.marginalTargetPeerTerminalGainPercent = ...
        marginalTargetPeerTerminalGain;
    label.boundaryReceiverTerminalGainPercent = relativeGainPercent( ...
        cwFullOutcome.eospaBySensorTime( ...
            protocol.boundaryReceiverSensorId, end), ...
        candidateOutcome.eospaBySensorTime( ...
            protocol.boundaryReceiverSensorId, end));
    label.worstSensorGainPercent = relativeGainPercent( ...
        cwFullRecord.worstSensorEospa, candidate.worstSensorEospa);
    label.windowConsensusGainPercent = relativeGainPercent( ...
        cwFullRecord.consensusOspa, candidate.consensusOspa);
    label.terminalConsensusGainPercent = relativeGainPercent( ...
        cwFullRecord.terminalConsensusOspa, ...
        candidate.terminalConsensusOspa);
    label.attemptedByteSavingPercent = relativeGainPercent( ...
        cwFullRecord.attemptedBytes, candidate.attemptedBytes);
    label.selectedB3Passed = candidate.selectedB3Passed;
    label.elapsedSeconds = candidateOutcome.elapsedSeconds;
    label.gatePassed = passesGate(label, protocol);
    candidateRecords(candidateIdx) = label;
end

passing = find([candidateRecords.gatePassed]);
if isempty(passing)
    downstreamRegret = max(0, ...
        -[candidateRecords.minimumFormationGainPercent]) + ...
        max(0, -[candidateRecords.targetPeerTerminalGainPercent]);
    bestRegret = min(downstreamRegret);
    tied = find(abs(downstreamRegret - bestRegret) <= 1e-12);
    [~, bestWithinTie] = max( ...
        [candidateRecords(tied).meanGainPercent]);
    oracleIndex = tied(bestWithinTie);
else
    [~, bestWithinPassing] = max( ...
        [candidateRecords(passing).meanGainPercent]);
    oracleIndex = passing(bestWithinPassing);
end

baseMetrics = baselineMetrics( ...
    cwFullRecord, cwFullOutcome, baseRecord, baseOutcome, ...
    groupIds, targetPeers, protocol);
result = struct();
result.contractVersion = protocol.resultContractVersion;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.referenceOutcomeReused = screen.referenceOutcomeReused;
result.v113BaselinesReused = true;
result.v114CandidateScreenReused = candidateScreenReused;
result.candidateScreenGenerationGitCommit = ...
    screen.generationGitCommit;
result.ccwFullRecord = ccwRecord;
result.clockwiseFullRecord = cwFullRecord;
result.unshieldedMechanismRecord = baseRecord;
result.unshieldedMechanismMetrics = baseMetrics;
result.labels = candidateRecords;
result.oracleIndex = oracleIndex;
result.oracleActionName = candidateRecords(oracleIndex).actionName;
result.oracleGatePassed = candidateRecords(oracleIndex).gatePassed;
result.anyGatePassed = any([candidateRecords.gatePassed]);
result.boundaryEdge = [ ...
    protocol.boundarySourceSensorId, ...
    protocol.boundaryReceiverSensorId];
result.targetPeerIndices = targetPeers;
result.v113ScreenPath = protocol.v113ScreenPath;
result.screenReportPath = screenReportPath;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, [protocol.resultFileStem, '.mat']);
reportPath = fullfile(outputRoot, [protocol.resultFileStem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('%s result: %s\n', protocol.runLabel, reportPath);
end

function validateCandidateScreen(screen, protocol, entry, currentTime)
requiredActions = [{'reference-full-payload'}, ...
    protocol.candidateActionNames];
valid = isstruct(screen) && isscalar(screen) && ...
    strcmp(screen.presetName, entry.presetName) && ...
    screen.seed == entry.seed && ...
    screen.currentTime == currentTime && ...
    screen.horizonSteps == protocol.horizonSteps && ...
    strcmp(screen.missingLabelFusionMode, protocol.receiverMode) && ...
    strcmp(screen.bank.bankVariant, protocol.bankVariant) && ...
    isequal(screen.bank.actionNames, requiredActions) && ...
    numel(screen.outcomes) == numel(requiredActions) && ...
    ~screen.generationTrackedWorktreeDirty && ...
    isempty(screen.generationUntrackedSourceFiles) && ...
    screen.openedDevelopmentEvidenceOnly && ...
    ~screen.validationClaimAllowed;
if ~valid
    error('InfluenceConeBoundaryShieldV114:CandidateScreenDrift', ...
        'The saved V114 candidate screen does not match the protocol.');
end
end

function screen = loadV113Screen(protocol, entry, currentTime)
if exist(protocol.v113ScreenPath, 'file') ~= 2
    error('InfluenceConeBoundaryShieldV114:MissingV113Screen', ...
        'The frozen V113 screen is missing.');
end
loaded = load(protocol.v113ScreenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('InfluenceConeBoundaryShieldV114:InvalidV113Screen', ...
        'The V113 screen file lacks the screen variable.');
end
screen = loaded.screen;
if ~strcmp(screen.presetName, entry.presetName) || ...
        screen.seed ~= entry.seed || ...
        screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= protocol.horizonSteps || ...
        ~strcmp(screen.missingLabelFusionMode, protocol.receiverMode) || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed
    error('InfluenceConeBoundaryShieldV114:V113ProvenanceDrift', ...
        'The V113 baseline provenance does not match V114.');
end
end

function [record, outcome, recordIdx] = findArm(screen, actionName)
recordIdx = find(strcmp({screen.records.actionName}, actionName), 1);
if isempty(recordIdx)
    error('InfluenceConeBoundaryShieldV114:MissingArm', ...
        'Required arm %s is missing.', actionName);
end
record = screen.records(recordIdx);
outcome = screen.outcomes(recordIdx);
end

function metrics = baselineMetrics( ...
        cwRecord, cwOutcome, baseRecord, baseOutcome, ...
        groupIds, targetPeers, protocol)
cwByTime = mean(cwOutcome.eospaBySensorTime, 1);
baseByTime = mean(baseOutcome.eospaBySensorTime, 1);
gainByTime = relativeGainPercent(cwByTime, baseByTime);
[formationGain, ~] = formationGains( ...
    cwOutcome.eospaBySensorTime, ...
    baseOutcome.eospaBySensorTime, groupIds);
metrics = struct();
metrics.meanGainPercent = relativeGainPercent( ...
    cwRecord.meanEospa, baseRecord.meanEospa);
metrics.minimumAfterMaturityGainPercent = min( ...
    gainByTime(protocol.firstHandoffTimeIndex:end));
metrics.minimumFormationGainPercent = min(formationGain);
metrics.targetPeerTerminalGainPercent = relativeGainPercent( ...
    mean(cwOutcome.eospaBySensorTime(targetPeers, end)), ...
    mean(baseOutcome.eospaBySensorTime(targetPeers, end)));
metrics.attemptedByteSavingPercent = relativeGainPercent( ...
    cwRecord.attemptedBytes, baseRecord.attemptedBytes);
end

function passed = passesGate(label, protocol)
passed = ...
    label.meanGainPercent >= protocol.minimumMeanGainPercent - 1e-12 && ...
    label.minimumAfterMaturityGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    label.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    label.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    label.targetPeerTerminalGainPercent >= ...
        protocol.minimumTargetPeerTerminalGainPercent - 1e-12 && ...
    label.windowConsensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    label.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    label.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    label.selectedB3Passed;
end

function label = emptyLabel()
label = struct( ...
    'actionName', '', ...
    'recordIndex', 0, ...
    'shieldStartPage', 0, ...
    'meanEospa', nan, ...
    'meanGainPercent', nan, ...
    'marginalMeanGainPercent', nan, ...
    'gainPercentByTime', [], ...
    'formationGainPercent', [], ...
    'formationGainPercentByTime', [], ...
    'minimumAfterMaturityGainPercent', nan, ...
    'minimumFormationGainPercent', nan, ...
    'targetPeerTerminalGainPercent', nan, ...
    'marginalTargetPeerTerminalGainPercent', nan, ...
    'boundaryReceiverTerminalGainPercent', nan, ...
    'worstSensorGainPercent', nan, ...
    'windowConsensusGainPercent', nan, ...
    'terminalConsensusGainPercent', nan, ...
    'attemptedByteSavingPercent', nan, ...
    'selectedB3Passed', false, ...
    'elapsedSeconds', nan, ...
    'gatePassed', false);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('InfluenceConeBoundaryShieldV114:WriteFailed', ...
        'Could not create the V114 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# %s\n\n', result.protocol.reportTitle);
fprintf(fid, '- V113 baselines reused: `%d`\n', ...
    result.v113BaselinesReused);
fprintf(fid, '- V114 candidate screen reused: `%d`\n', ...
    result.v114CandidateScreenReused);
fprintf(fid, '- Boundary edge: `%d -> %d`\n', ...
    result.boundaryEdge(1), result.boundaryEdge(2));
fprintf(fid, '- Any candidate passed: `%d`\n', result.anyGatePassed);
fprintf(fid, '- Oracle action: `%s`\n\n', result.oracleActionName);
fprintf(fid, ['| Arm | Shield start | Mean E-OSPA | Gain vs CW full | ', ...
    'Marginal vs V113 | Mature min | Min formation | F6 peers | ', ...
    'F6 repair vs V113 | Bytes | Gate |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
fprintf(fid, '| CCW full | -- | %.6f | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.ccwFullRecord.meanEospa, ...
    result.ccwFullRecord.selectedB3Passed);
fprintf(fid, '| CW full | -- | %.6f | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.clockwiseFullRecord.meanEospa, ...
    result.clockwiseFullRecord.selectedB3Passed);
base = result.unshieldedMechanismRecord;
baseMetrics = result.unshieldedMechanismMetrics;
fprintf(fid, ['| V113 unshielded | -- | %.6f | %+.3f%% | -- | ', ...
    '%+.3f%% | %+.3f%% | %+.3f%% | -- | %+.3f%% | %d |\n'], ...
    base.meanEospa, baseMetrics.meanGainPercent, ...
    baseMetrics.minimumAfterMaturityGainPercent, ...
    baseMetrics.minimumFormationGainPercent, ...
    baseMetrics.targetPeerTerminalGainPercent, ...
    baseMetrics.attemptedByteSavingPercent, ...
    base.selectedB3Passed);
for idx = 1:numel(result.labels)
    label = result.labels(idx);
    fprintf(fid, ['| `%s` | %d | %.6f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        label.actionName, label.shieldStartPage, label.meanEospa, ...
        label.meanGainPercent, label.marginalMeanGainPercent, ...
        label.minimumAfterMaturityGainPercent, ...
        label.minimumFormationGainPercent, ...
        label.targetPeerTerminalGainPercent, ...
        label.marginalTargetPeerTerminalGainPercent, ...
        label.attemptedByteSavingPercent, label.gatePassed);
end
oracle = result.labels(result.oracleIndex);
fprintf(fid, '\n## Oracle diagnostics\n\n');
fprintf(fid, '- Formation gains vs CW full: `%s%%`\n', ...
    mat2str(oracle.formationGainPercent, 4));
fprintf(fid, '- Per-page gains vs CW full: `%s%%`\n', ...
    mat2str(oracle.gainPercentByTime, 4));
fprintf(fid, '- Boundary receiver terminal gain: `%+.3f%%`\n', ...
    oracle.boundaryReceiverTerminalGainPercent);
fprintf(fid, '- Worst-sensor gain: `%+.3f%%`\n', ...
    oracle.worstSensorGainPercent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    oracle.windowConsensusGainPercent, ...
    oracle.terminalConsensusGainPercent);
fprintf(fid, '- Gate passed: `%d`\n\n', oracle.gatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function [gain, gainByTime] = formationGains( ...
        referenceBySensorTime, candidateBySensorTime, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
gain = zeros(1, numel(groups));
gainByTime = zeros(numel(groups), size(referenceBySensorTime, 2));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    referenceValues = referenceBySensorTime(mask, :);
    candidateValues = candidateBySensorTime(mask, :);
    gain(idx) = relativeGainPercent( ...
        mean(referenceValues(:)), mean(candidateValues(:)));
    gainByTime(idx, :) = relativeGainPercent( ...
        mean(referenceValues, 1), mean(candidateValues, 1));
end
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
