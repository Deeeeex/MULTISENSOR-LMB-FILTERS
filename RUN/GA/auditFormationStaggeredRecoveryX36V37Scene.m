function [reportPath, audit] = ...
    auditFormationStaggeredRecoveryX36V37Scene(options)
% AUDITFORMATIONSTAGGEREDRECOVERYX36V37SCENE Geometry-only scale gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationStaggeredRecoveryX36SourceProtocol();
requireCleanSource = logical(getField( ...
    options, 'requireCleanSource', true));
writeReportEnabled = logical(getField( ...
    options, 'writeReport', true));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'FORMATION_STAGGERED_RECOVERY_X36_V37_SCENE_20260802.md'));
matPath = getField(options, 'matPath', fullfile( ...
    protocol.outputRoot, 'scene', ...
    'FORMATION_STAGGERED_RECOVERY_X36_V37_SCENE.mat'));

gitState = resolveResearchGitState();
if requireCleanSource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v37 scene audit requires clean tracked and ', ...
        'MATLAB/Octave source.']);
end

[~, raw] = runDynamicTopologyScenarioDifficultyAudit( ...
    {protocol.referencePresetName, protocol.presetName}, ...
    protocol.seed, struct('writeReport', false));
reference = findRecord(raw.records, ...
    protocol.referencePresetName);
candidate = findRecord(raw.records, protocol.presetName);
referenceConfig = buildDynamicTopologyScenarioConfig( ...
    protocol.referencePresetName);
candidateConfig = buildDynamicTopologyScenarioConfig( ...
    protocol.presetName);
hardwareFields = { ...
    'fovTotalAngleDeg', 'fovRange', ...
    'sensorFovHeadingMode', 'detectionProbability', ...
    'measurementNoiseStd', 'clutterRate', ...
    'birthProbability', 'sensorQuality', ...
    'sensorHardwareProfile', 'observationSpaceLimits', ...
    'clutterSpatialProfile'};
hardwareContractPassed = true;
for fieldIdx = 1:numel(hardwareFields)
    fieldName = hardwareFields{fieldIdx};
    hardwareContractPassed = hardwareContractPassed && ...
        isfield(referenceConfig, fieldName) && ...
        isfield(candidateConfig, fieldName) && ...
        isequaln(referenceConfig.(fieldName), ...
            candidateConfig.(fieldName));
end
focusLoadRelativeErrorPercent = 100 * ( ...
    candidate.focusMeanVisibleTargetsPerSensorTime / ...
        max(reference.focusMeanVisibleTargetsPerSensorTime, eps) - 1);

audit = struct();
audit.contractVersion = ...
    'formation-staggered-recovery-x36-v37-scene-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.protocol = protocol;
audit.reference = reference;
audit.candidate = candidate;
audit.hardwareContractPassed = hardwareContractPassed;
audit.focusLoadRelativeErrorPercent = ...
    focusLoadRelativeErrorPercent;
audit.sceneGatePassed = all([ ...
    raw.allValid, hardwareContractPassed, ...
    candidate.sensorCount == protocol.expectedNodeCount, ...
    candidate.targetCount == protocol.expectedTargetCount, ...
    candidateConfig.formationCount == ...
        protocol.expectedFormationCount, ...
    candidateConfig.fovTotalAngleDeg == ...
        protocol.expectedFovTotalAngleDeg, ...
    candidateConfig.fovRange == protocol.expectedFovRange, ...
    strcmp(candidateConfig.sensorHardwareProfile, ...
        protocol.expectedSensorHardwareProfile), ...
    strcmp(candidateConfig.sensorFovHeadingMode, ...
        protocol.expectedSensorFovHeadingMode), ...
    abs(focusLoadRelativeErrorPercent) <= ...
        protocol.maximumFocusLoadRelativeErrorPercent + 1e-12, ...
    candidate.focusBlackoutFraction <= ...
        protocol.maximumFocusBlackoutFraction + 1e-12, ...
    candidate.maximumPerTargetBlackoutFraction <= ...
        protocol.maximumPerTargetBlackoutFraction + 1e-12, ...
    candidate.maximumConsecutiveBlackoutSteps <= ...
        protocol.maximumConsecutiveBlackoutSteps, ...
    candidate.focusHandovers >= protocol.minimumFocusHandovers, ...
    candidate.ownershipEntropy >= ...
        protocol.minimumOwnershipEntropy - 1e-12, ...
    candidate.multiFormationFraction >= ...
        protocol.minimumMultiFormationFraction - 1e-12]);
audit.trackingOutcomeScored = false;
audit.posteriorGenerated = false;
audit.cacheGenerationAuthorized = ...
    audit.sceneGatePassed && protocol.cacheGenerationAuthorized;
audit.sourceOnlyControlAuditAuthorized = false;
audit.trackingOutcomeRerunAuthorized = false;
audit.gnnTrainingAuthorized = false;
audit.x36OutcomeOpeningAuthorized = false;
audit.x48OutcomeOpeningAuthorized = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This audit uses scenario geometry and visibility only. It compares ', ...
    'M24 and X36 under identical sensor hardware and checks that the ', ...
    'per-sensor focus load remains matched without hiding blackout or ', ...
    'handover failures. It generates no posterior and scores no ', ...
    'tracking outcome. Passing authorizes only the registered X36 ', ...
    'fixed-reference cache trajectory.'];

if ~audit.sceneGatePassed
    error('V37Scene:GateFailed', ...
        'The registered X36 scale scene failed its geometry gate.');
end
if writeReportEnabled
    if exist(fileparts(matPath), 'dir') ~= 7
        mkdir(fileparts(matPath));
    end
    audit.reportPath = reportPath;
    audit.matPath = matPath;
    save('-mat7-binary', matPath, 'audit');
    writeReport(reportPath, audit);
    fprintf('V37 X36 scene audit: %s\n', reportPath);
else
    reportPath = '';
end
end

function record = findRecord(records, presetName)
mask = strcmp({records.presetName}, presetName);
if nnz(mask) ~= 1
    error('V37Scene:RecordMissing', ...
        'The requested scene record is ambiguous.');
end
record = records(mask);
end

function writeReport(path, audit)
reference = audit.reference;
candidate = audit.candidate;
fid = fopen(path, 'w');
if fid < 0
    error('V37Scene:WriteFailed', ...
        'Could not open the v37 scene report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V37 X36 same-hardware scene audit\n\n');
fprintf(fid, '- Contract / generation commit: `%s / %s`\n', ...
    audit.contractVersion, audit.generationGitCommit);
fprintf(fid, '- Hardware contract passed: `%d`\n', ...
    audit.hardwareContractPassed);
fprintf(fid, '- Scene gate passed: `%d`\n', audit.sceneGatePassed);
fprintf(fid, '- Tracking scored / posterior generated: `0 / 0`\n\n');

fprintf(fid, '## Matched sensing load\n\n');
fprintf(fid, [ ...
    '| Scene | Sensors | Targets | Focus visible targets / sensor ', ...
    '| Focus blackout | Multi-formation visibility | Handovers ', ...
    '| Mean physical inter-formation edges |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|\n');
writeRow(fid, reference);
writeRow(fid, candidate);
fprintf(fid, '\n- X36/M24 focus-load error: `%+.4f%%`\n', ...
    audit.focusLoadRelativeErrorPercent);
fprintf(fid, '- X36 maximum per-target blackout: `%.4f%%`\n', ...
    100 * candidate.maximumPerTargetBlackoutFraction);
fprintf(fid, '- X36 maximum consecutive blackout: `%d` steps\n', ...
    candidate.maximumConsecutiveBlackoutSteps);
fprintf(fid, '- X36 ownership entropy: `%.6f`\n\n', ...
    candidate.ownershipEntropy);

fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    'X36 preserves the registered 120-degree, 300 m sensor hardware ', ...
    'and matches M24 local sensing load within 1%%. Its larger number ', ...
    'of formations, targets, handovers, and physical cross-formation ', ...
    'choices makes it a scale/route test rather than a hidden FoV ', ...
    'stress change. The three fixed-reference source caches may now ', ...
    'be generated; no X36 tracking outcome is authorized.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function writeRow(fid, record)
fprintf(fid, '| `%s` | %d | %d | %.6f | %.6f | %.6f | %d | %.3f |\n', ...
    record.presetName, record.sensorCount, record.targetCount, ...
    record.focusMeanVisibleTargetsPerSensorTime, ...
    record.focusBlackoutFraction, ...
    record.multiFormationFraction, record.focusHandovers, ...
    record.meanPhysicalInterFormationEdges);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
