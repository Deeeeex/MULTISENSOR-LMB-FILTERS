function [reportPath, screen] = ...
    runFormationStaggeredRecoveryOpenedScreen(options)
% RUNFORMATIONSTAGGEREDRECOVERYOPENEDSCREEN Frozen v35 paired H=3 run.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationStaggeredRecoveryProbeProtocol();
preflight = assertPreflightAuthorized(protocol);
writeReportEnabled = logical(getField( ...
    options, 'writeReport', true));
outputDirectory = getField(options, ...
    'outputDirectory', fullfile(protocol.outputRoot, ...
        sprintf('t%d', protocol.anchorTime), 'screen'));

executorOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', 1, ...
    'cacheRoot', protocol.cacheRoot, ...
    'interventionBankType', 'formation-staggered-recovery', ...
    'actionIndices', [ ...
        preflight.sourceTrajectoryReplay.actionSequenceIndices(2), ...
        preflight.sourceTrajectoryReplay.actionSequenceIndices(1)], ...
    'writeReport', false, ...
    'allowDirtySource', logical(getField( ...
        options, 'allowDirtySource', false)));
[~, screen] = runFormationModeOpenedReturnScreen( ...
    protocol.presetName, protocol.seed, protocol.anchorTime, ...
    executorOptions);
assertScreenContract(screen, preflight, protocol);

referenceIdx = screen.referenceSubsetIndex;
candidateIdx = setdiff(1:numel(screen.records), referenceIdx);
strictStrongMask = false(1, numel(screen.records));
for recordIdx = candidateIdx
    record = screen.records(recordIdx);
    outcome = screen.outcomes(recordIdx);
    strictStrongMask(recordIdx) = ...
        record.posteriorProxyAllowed && ...
        outcome.firstActionExact && ...
        outcome.firstFusionWeightsExact && ...
        outcome.laterActionsDynamicallyRecomputed && ...
        all(outcome.posteriorContentUsedByTime) && ...
        all(outcome.currentLinkReliabilityUsedByTime) && ...
        hasStaggeredRecoveryTrace(outcome, protocol) && ...
        record.meanGainPercent >= protocol. ...
            meanTrackingGainThresholdPercent - 1e-12 && ...
        record.minimumFormationGainPercent >= protocol. ...
            minimumFormationGainThresholdPercent - 1e-12 && ...
        record.worstGainPercent >= protocol. ...
            worstSensorGainThresholdPercent - 1e-12 && ...
        record.consensusGainPercent >= protocol. ...
            windowConsensusGainThresholdPercent - 1e-12 && ...
        record.terminalConsensusGainPercent >= protocol. ...
            terminalConsensusGainThresholdPercent - 1e-12 && ...
        record.attemptedByteSavingPercent >= protocol. ...
            minimumAttemptedByteSavingPercent - 1e-12 && ...
        record.selectedB3Passed;
end

screen.contractVersion = ...
    'formation-staggered-recovery-v35-screen-v1';
screen.protocol = protocol;
screen.sourcePreflightPath = preflight.matPath;
screen.sourcePreflightGenerationCommit = ...
    preflight.generationGitCommit;
screen.strictStrongMask = strictStrongMask;
screen.strictStrongCandidateCount = nnz(strictStrongMask);
screen.strongCandidateFound = any(strictStrongMask);
screen.causalStaggeredRecoveryAttested = ...
    hasStaggeredRecoveryTrace( ...
        screen.outcomes(candidateIdx), protocol);
screen.executedOnlyPosteriorSafeInitialActions = all( ...
    screen.bank.actionPosteriorSafetyMask(screen.actionIndices));
screen.terminalConsensusGateEnabled = true;
screen.outcomeRankingUsesTruth = true;
screen.additionalOpenedStateScreenAuthorized = ...
    screen.strongCandidateFound;
screen.teacherCollectionAllowed = false;
screen.gnnTrainingAuthorized = false;
screen.x36OutcomeOpeningAuthorized = false;
screen.x48OutcomeOpeningAuthorized = false;
screen.validationClaimAllowed = false;
screen.evidenceBoundary = protocol.evidenceBoundary;

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    stem = sprintf( ...
        'FORMATION_STAGGERED_RECOVERY_H3_%s_SEED%d_T%d', ...
        upper(strrep(protocol.presetName, '-', '_')), ...
        protocol.seed, protocol.anchorTime);
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    screen.reportPath = reportPath;
    screen.matPath = matPath;
    save('-mat7-binary', matPath, 'screen');
    writeReport(reportPath, screen);
    fprintf('V35 staggered-recovery screen: %s\n', reportPath);
end
end

function preflight = assertPreflightAuthorized(protocol)
path = fullfile(protocol.outputRoot, 'preflight', ...
    'FORMATION_STAGGERED_RECOVERY_V35_PREFLIGHT.mat');
if exist(path, 'file') ~= 2
    error('StaggeredRecovery:PreflightRequired', ...
        'The frozen v35 preflight artifact is unavailable.');
end
loaded = load(path, 'preflight');
if ~isfield(loaded, 'preflight')
    error('StaggeredRecovery:PreflightRequired', ...
        'The frozen v35 preflight structure is unavailable.');
end
preflight = loaded.preflight;
if ~strcmp(preflight.contractVersion, ...
        'formation-staggered-recovery-v35-preflight-v1') || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        ~preflight.trackingOutcomeRerunAuthorized || ...
        preflight.trackingOutcomeScored || ...
        preflight.newTrackingStateOpened || ...
        preflight.additionalM24StateAuthorized || ...
        preflight.gnnTrainingAuthorized || ...
        preflight.x36Opened || preflight.x48Opened || ...
        preflight.validationClaimAllowed || ...
        ~strcmp(preflight.sourceCacheSha256, ...
            protocol.sourceCacheSha256) || ...
        ~preflight.staggeredReleaseUsed || ...
        ~isequal(preflight.selectedFormationIds, ...
            protocol.expectedSelectedFormationIds)
    error('StaggeredRecovery:PreflightRequired', ...
        'The clean v35 preflight did not authorize tracking.');
end
end

function assertScreenContract(screen, preflight, protocol)
bank = screen.bank;
expectedActionIndices = [1, 15];
if ~strcmp(screen.contractVersion, ...
        'formation-staggered-recovery-h3-opened-return-screen-v1') || ...
        ~strcmp(screen.interventionBankType, ...
            'formation-staggered-recovery') || ...
        screen.horizonSteps ~= protocol.horizonSteps || ...
        screen.currentTime ~= protocol.anchorTime || ...
        ~isequal(screen.returnTimes, ...
            protocol.anchorTime:protocol.reconnectTime) || ...
        bank.nodeCount ~= protocol.expectedNodeCount || ...
        bank.formationCount ~= protocol.expectedFormationCount || ...
        ~isequal(screen.actionIndices, expectedActionIndices) || ...
        any(~bank.actionPosteriorSafetyMask(screen.actionIndices)) || ...
        ~screen.runtimeRecoveryPolicyEnabled || ...
        ~strcmp(screen.runtimePolicyContractVersion, ...
            'formation-staggered-recovery-runtime-policy-v1') || ...
        any([screen.outcomes.truthUseCount] ~= 0) || ...
        any([screen.outcomes.repairCount] ~= 0) || ...
        any([screen.outcomes.payloadEmergencyCount] ~= 0) || ...
        any([screen.outcomes.infeasibleCount] ~= 0) || ...
        ~all([screen.outcomes.firstActionExact]) || ...
        ~all([screen.outcomes.firstFusionWeightsExact]) || ...
        ~strcmp(screen.cacheSha256, preflight.sourceCacheSha256)
    error('StaggeredRecovery:ScreenContract', ...
        'The v35 screen violated a frozen runtime invariant.');
end
end

function value = hasStaggeredRecoveryTrace(outcome, protocol)
value = isstruct(outcome) && ...
    numel(outcome.staggeredRecoveryScheduleByTime) == ...
        protocol.horizonSteps && ...
    numel(outcome.retentionDebtSelectedFormationIdsByTime) == ...
        protocol.horizonSteps;
if ~value
    return;
end
schedule = outcome.staggeredRecoveryScheduleByTime{2};
value = isstruct(schedule) && ...
    isfield(schedule, 'contractVersion') && ...
    strcmp(schedule.contractVersion, ...
        'formation-staggered-recovery-runtime-schedule-v1') && ...
    schedule.currentTime == protocol.staggerTime && ...
    schedule.staggeredReleaseUsed && ...
    isequal(schedule.incumbentFormationIds, ...
        protocol.expectedBaseSelectedFormationIds) && ...
    isequal(schedule.releasedFormationIds, 3) && ...
    isequal(schedule.selectedFormationIds, ...
        protocol.expectedSelectedFormationIds) && ...
    abs(schedule.selectedDebtCoverageFraction - ...
        protocol.expectedRetainedDebtCoverageFraction) <= ...
            protocol.sourceMetricTolerance && ...
    abs(schedule.selectedDisagreementImprovementFraction - ...
        protocol.expectedDisagreementImprovementFraction) <= ...
            protocol.sourceMetricTolerance && ...
    isequal(outcome.retentionDebtSelectedFormationIdsByTime{1}, ...
        protocol.expectedBaseSelectedFormationIds) && ...
    isequal(outcome.retentionDebtSelectedFormationIdsByTime{2}, ...
        protocol.expectedSelectedFormationIds) && ...
    isempty(outcome.retentionDebtSelectedFormationIdsByTime{3});
end

function writeReport(path, screen)
referenceIdx = screen.referenceSubsetIndex;
candidateIdx = setdiff(1:numel(screen.records), referenceIdx);
reference = screen.outcomes(referenceIdx);
candidate = screen.outcomes(candidateIdx);
record = screen.records(candidateIdx);
trackingReferenceByTime = mean(reference.eospaBySensorTime, 1);
trackingCandidateByTime = mean(candidate.eospaBySensorTime, 1);
trackingGainByTime = relativeGain( ...
    trackingReferenceByTime, trackingCandidateByTime);
consensusGainByTime = relativeGain( ...
    reference.consensusOspaByTime, candidate.consensusOspaByTime);
byteSavingByTime = relativeGain( ...
    reference.attemptedBytesByTime, candidate.attemptedBytesByTime);

fid = fopen(path, 'w');
if fid < 0
    error('StaggeredRecovery:WriteFailed', ...
        'Could not open v35 screen report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V35 debt-coverage staggered-recovery H=3 screen\n\n');
fprintf(fid, '- Contract: `%s`\n', screen.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    screen.generationGitCommit);
fprintf(fid, '- Preset / seed / times: `%s / %d / %s`\n', ...
    screen.presetName, screen.seed, mat2str(screen.returnTimes));
fprintf(fid, '- Initial / staggered suspension: `%s / %s`\n', ...
    mat2str(screen.protocol.expectedBaseSelectedFormationIds), ...
    mat2str(screen.protocol.expectedSelectedFormationIds));
fprintf(fid, '- Causal staggered trace attested: `%d`\n', ...
    screen.causalStaggeredRecoveryAttested);
fprintf(fid, '- Strong candidates: `%d / 1`\n\n', ...
    screen.strictStrongCandidateCount);

fprintf(fid, '## Aggregate result\n\n');
fprintf(fid, [ ...
    '| Mean tracking | Worst sensor | Formation gains | Window consensus ', ...
    '| Terminal consensus | Byte saving | Mean card. error | Strong |\n']);
fprintf(fid, '|--:|--:|:--|--:|--:|--:|--:|:--:|\n');
fprintf(fid, [ ...
    '| %+.4f%% | %+.4f%% | `%s` | %+.4f%% | %+.4f%% | %+.4f%% ', ...
    '| %.6f -> %.6f | %d |\n\n'], ...
    record.meanGainPercent, record.worstGainPercent, ...
    mat2str(record.formationGainPercent, 5), ...
    record.consensusGainPercent, ...
    record.terminalConsensusGainPercent, ...
    record.attemptedByteSavingPercent, ...
    reference.meanCardinalityError, ...
    candidate.meanCardinalityError, ...
    screen.strictStrongMask(candidateIdx));

fprintf(fid, '## Temporal result\n\n');
fprintf(fid, [ ...
    '| Time | Reference tracking | Candidate tracking | Tracking gain ', ...
    '| Reference consensus | Candidate consensus | Consensus gain ', ...
    '| Byte saving | Selected suspension |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--|\n');
for timeIdx = 1:numel(screen.returnTimes)
    fprintf(fid, [ ...
        '| %d | %.6f | %.6f | %+.3f%% | %.6f | %.6f | %+.3f%% ', ...
        '| %+.3f%% | `%s` |\n'], ...
        screen.returnTimes(timeIdx), ...
        trackingReferenceByTime(timeIdx), ...
        trackingCandidateByTime(timeIdx), ...
        trackingGainByTime(timeIdx), ...
        reference.consensusOspaByTime(timeIdx), ...
        candidate.consensusOspaByTime(timeIdx), ...
        consensusGainByTime(timeIdx), ...
        byteSavingByTime(timeIdx), ...
        mat2str(candidate. ...
            retentionDebtSelectedFormationIdsByTime{timeIdx}));
end

fprintf(fid, '\n## Decision\n\n');
if screen.strongCandidateFound
    fprintf(fid, [ ...
        'The paired opened-state arm passes every frozen gate. A ', ...
        'separate protocol may now test another already-opened M24 ', ...
        'state; GNN and X36/X48 remain sealed.\n\n']);
else
    fprintf(fid, [ ...
        'The paired opened-state arm fails at least one frozen gate. ', ...
        'Stop this v35 controller before another M24 state, GNN, ', ...
        'X36, or X48.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    screen.evidenceBoundary);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) ./ max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
