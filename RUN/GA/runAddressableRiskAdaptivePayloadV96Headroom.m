function [reportPath, result] = ...
    runAddressableRiskAdaptivePayloadV96Headroom(options)
% RUNADDRESSABLERISKADAPTIVEPAYLOADV96HEADROOM Three-arm paired screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getAddressableRiskAdaptivePayloadV96Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('AddressableRiskV96:DirtySource', ...
        'V96 headroom requires clean frozen source.');
end
structural = loadStructuralGate(protocol);
if ~structural.crossScaleStructuralGatePassed || ...
        ~structural.trackingHeadroomAuthorized
    error('AddressableRiskV96:StructuralGateClosed', ...
        'The V96 matched-static screen is not structurally authorized.');
end
outputRoot = getField(options, ...
    'outputRoot', protocol.headroomOutputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

anchorCount = sum(arrayfun(@(entry) ...
    numel(entry.anchorTimes), protocol.cases));
anchors = repmat(emptyAnchor(), 1, anchorCount);
anchorIdx = 0;
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    for currentTime = entry.anchorTimes
        anchorIdx = anchorIdx + 1;
        screenRoot = fullfile(outputRoot, 'screens', ...
            lower(entry.scaleName), sprintf('t%d', currentTime));
        screenOptions = struct( ...
            'horizonSteps', protocol.horizonSteps, ...
            'interventionDurationSteps', protocol.horizonSteps, ...
            'filterSeedOffset', protocol.filterSeedOffset, ...
            'cacheRoot', entry.cacheRoot, ...
            'interventionBankType', ...
                'tracking-aligned-x36-schedule', ...
            'trackingAlignedExecutionProfile', ...
                'v96-addressable-risk-adaptive-payload', ...
            'trackingAlignedX36ScheduleBankOptions', struct( ...
                'positiveSupportThreshold', ...
                    protocol.positiveSupportThreshold, ...
                'bankVariant', 'addressable-risk-v96'), ...
            'receiverMode', protocol.receiverMode, ...
            'outputDirectory', screenRoot, ...
            'writeReport', true);
        [screenReportPath, screen] = ...
            runFormationModeOpenedReturnScreen( ...
                entry.presetName, entry.seed, currentTime, ...
                screenOptions);
        anchors(anchorIdx) = summarizeAnchor( ...
            screen, screenReportPath, entry, currentTime, protocol);
    end
end

result = struct();
result.contractVersion = ...
    'addressable-risk-adaptive-payload-v96-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.baselineName = protocol.baselineName;
result.receiverMode = protocol.receiverMode;
result.structuralResultPath = structural.reportPath;
result.anchors = anchors;
result.anchorPassCount = nnz([anchors.matchedStaticGatePassed]);
result.requiredAnchorPassCount = numel(anchors);
result.crossScaleGatePassed = ...
    result.anchorPassCount == result.requiredAnchorPassCount;
result.fullEpisodeTrackingAuthorized = ...
    protocol.fullEpisodeTrackingAuthorized && ...
    result.crossScaleGatePassed;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'ADDRESSABLE_RISK_ADAPTIVE_PAYLOAD_V96_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'ADDRESSABLE_RISK_ADAPTIVE_PAYLOAD_V96_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V96 matched-static result: %s\n', reportPath);
end

function structural = loadStructuralGate(protocol)
path = fullfile(protocol.structuralOutputRoot, ...
    'ADDRESSABLE_RISK_ADAPTIVE_PAYLOAD_V96_STRUCTURAL_RESULT.mat');
if exist(path, 'file') ~= 2
    error('AddressableRiskV96:MissingStructuralGate', ...
        'Run the V96 structural gate before opening tracking outcomes.');
end
loaded = load(path, 'result');
if ~isfield(loaded, 'result') || ~isstruct(loaded.result) || ...
        ~isfield(loaded.result, 'protocol') || ...
        ~strcmp(loaded.result.protocol.id, protocol.id)
    error('AddressableRiskV96:StructuralGateDrift', ...
        'The saved V96 structural result does not match the protocol.');
end
structural = loaded.result;
end

function value = summarizeAnchor( ...
        screen, screenReportPath, entry, currentTime, protocol)
names = {screen.records.actionName};
referenceIdx = screen.referenceSubsetIndex;
oneStepIdx = find(cellfun(@(name) ...
    strncmp(name, 'addressable-risk-one-step-', 26), names), 1);
persistentIdx = find(cellfun(@(name) ...
    strncmp(name, 'addressable-risk-persistent-', 28), names), 1);

value = emptyAnchor();
value.scaleName = entry.scaleName;
value.presetName = entry.presetName;
value.seed = entry.seed;
value.currentTime = currentTime;
value.referenceMeanEospa = ...
    screen.records(referenceIdx).meanEospa;
value.actionEnabled = ~isempty(oneStepIdx) && ~isempty(persistentIdx);
value.selectedFormationIds = ...
    screen.bank.addressableRiskSelection.selectedFormationIds;
value.addressableRiskFraction = ...
    screen.bank.addressableRiskSelection. ...
        addressableNetworkRiskFraction;
value.totalRiskFraction = ...
    screen.bank.addressableRiskSelection.totalNetworkRiskFraction;
value.screenReportPath = screenReportPath;
if ~value.actionEnabled
    value.failureReason = ...
        screen.bank.addressableRiskSelection.fallbackReason;
    return;
end

oneStep = screen.records(oneStepIdx);
persistentArm = screen.records(persistentIdx);
value.oneStepMeanEospa = oneStep.meanEospa;
value.persistentMeanEospa = persistentArm.meanEospa;
value.persistentGainPercent = persistentArm.meanGainPercent;
value.gainOverOneStepPercent = relativeGainPercent( ...
    oneStep.meanEospa, persistentArm.meanEospa);
value.worstSensorGainPercent = persistentArm.worstGainPercent;
value.minimumFormationGainPercent = ...
    persistentArm.minimumFormationGainPercent;
value.windowConsensusGainPercent = persistentArm.consensusGainPercent;
value.terminalConsensusGainPercent = ...
    persistentArm.terminalConsensusGainPercent;
value.attemptedByteSavingPercent = ...
    persistentArm.attemptedByteSavingPercent;
value.matchedStaticGatePassed = ...
    persistentArm.meanGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    value.gainOverOneStepPercent >= -1e-12 && ...
    persistentArm.worstGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    persistentArm.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    persistentArm.consensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    persistentArm.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    persistentArm.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    persistentArm.selectedB3Passed && oneStep.selectedB3Passed;
if ~value.matchedStaticGatePassed
    value.failureReason = 'frozen-tracking-gate-failed';
end
end

function gain = relativeGainPercent(reference, candidate)
gain = 100 * (reference - candidate) / max(abs(reference), eps);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('AddressableRiskV96:WriteFailed', ...
        'Could not create the V96 headroom report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V96 addressable-risk adaptive payload\n\n');
fprintf(fid, '- Matched baseline: `%s`\n', result.baselineName);
fprintf(fid, '- Receiver semantics: `%s`\n', result.receiverMode);
fprintf(fid, ['- Pairing: same cached posterior, measurements, link ', ...
    'uniforms, filter RNG, horizon and communication constraints.\n\n']);
fprintf(fid, ['| Scale | t | Selected | Static | One step | Persistent | ', ...
    'Gain/static | Gain/one step | Worst sensor | Min formation | ', ...
    'Consensus | Bytes | Pass |\n']);
fprintf(fid, ['|:--|--:|:--|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|:--:|\n']);
for entry = result.anchors
    fprintf(fid, ['| %s | %d | %s | %.6f | %.6f | %.6f | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %d |\n'], ...
        entry.scaleName, entry.currentTime, ...
        mat2str(entry.selectedFormationIds), ...
        entry.referenceMeanEospa, entry.oneStepMeanEospa, ...
        entry.persistentMeanEospa, entry.persistentGainPercent, ...
        entry.gainOverOneStepPercent, ...
        entry.worstSensorGainPercent, ...
        entry.minimumFormationGainPercent, ...
        entry.windowConsensusGainPercent, ...
        entry.attemptedByteSavingPercent, ...
        entry.matchedStaticGatePassed);
end
fprintf(fid, '\n- Cross-scale pass: `%d / %d`; gate `%d`.\n', ...
    result.anchorPassCount, result.requiredAnchorPassCount, ...
    result.crossScaleGatePassed);
fprintf(fid, '- Full-episode tracking authorized: `%d`\n\n', ...
    result.fullEpisodeTrackingAuthorized);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = emptyAnchor()
value = struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'actionEnabled', false, ...
    'selectedFormationIds', zeros(1, 0), ...
    'addressableRiskFraction', NaN, 'totalRiskFraction', NaN, ...
    'referenceMeanEospa', NaN, 'oneStepMeanEospa', NaN, ...
    'persistentMeanEospa', NaN, 'persistentGainPercent', NaN, ...
    'gainOverOneStepPercent', NaN, ...
    'worstSensorGainPercent', NaN, ...
    'minimumFormationGainPercent', NaN, ...
    'windowConsensusGainPercent', NaN, ...
    'terminalConsensusGainPercent', NaN, ...
    'attemptedByteSavingPercent', NaN, ...
    'matchedStaticGatePassed', false, ...
    'failureReason', '', 'screenReportPath', '');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
