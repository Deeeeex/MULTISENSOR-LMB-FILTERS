function audit = auditM24ObservableScoreBasisCoverage()
% AUDITM24OBSERVABLESCOREBASISCOVERAGE Formal seed-7 action support audit.
%
% The audit consumes four clean score-basis continuation shards, compares
% their realized t=75 sensor routes with the earlier truth-free codebook,
% and writes a single evidence table plus registered headroom gates.

addpath(genpath(pwd));

seed = 7;
batchCount = 4;
reportPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'M24_OBSERVABLE_SCORE_BASIS_COVERAGE_SEED7_20260729.md');
[registry, registryMetadata] = ...
    getRollingSafeObservableScoreBasisRegistry();
gitState = resolveResearchGitState();

sourceFiles = cell(1, batchCount);
candidateRecords = repmat(struct(), 1, 0);
baselineRecords = repmat(struct(), 1, 0);
for batchIdx = 1:batchCount
    directory = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'rollout_dataset', sprintf( ...
            'seed%d_scorebasis_b%02dof%02d', ...
            seed, batchIdx, batchCount));
    sourceFiles{batchIdx} = latestMatFile(directory);
    loaded = load(sourceFiles{batchIdx});
    records = loaded.summary.records;
    for recordIdx = 1:numel(records)
        actionCode = parseFirstActionCode( ...
            records(recordIdx).armMode);
        if actionCode == 24
            baselineRecords(end + 1) = records(recordIdx); %#ok<AGROW>
        else
            candidateRecords(end + 1) = records(recordIdx); %#ok<AGROW>
        end
    end
end
if numel(candidateRecords) ~= numel(registry)
    error('Expected %d score-basis candidates, found %d.', ...
        numel(registry), numel(candidateRecords));
end
if numel(baselineRecords) ~= batchCount
    error('Expected one code-24 reference in every score-basis shard.');
end

[candidateRecords, codes] = sortRecordsByActionCode(candidateRecords);
if ~isequal(codes, [registry.actionCode])
    error('Score-basis evidence does not match the frozen registry.');
end
baseline = baselineRecords(1);
for baselineIdx = 2:numel(baselineRecords)
    assertSameBaseline(baseline, baselineRecords(baselineIdx));
end

oldSignatures = loadOldCodebookSignatures(seed, batchCount);
groupIds = repelem(1:4, 6);
candidateCount = numel(candidateRecords);
rows = repmat(struct(), 1, candidateCount);
for candidateIdx = 1:candidateCount
    record = candidateRecords(candidateIdx);
    entry = registry(candidateIdx);
    selectedHistory = logical( ...
        record.focusSelectedDirectedEdgeHistory);
    if size(selectedHistory, 3) < 1 || ...
            size(selectedHistory, 1) ~= numel(groupIds)
        error('Score-basis selected route history is incomplete.');
    end
    firstAdjacency = selectedHistory(:, :, 1);
    sensorSignature = adjacencySignature(firstAdjacency);
    formationAdjacency = sensorToFormationAdjacency( ...
        firstAdjacency, groupIds);
    rows(candidateIdx) = struct( ...
        'code', entry.actionCode, ...
        'basisId', entry.basisId, ...
        'k', entry.exactCurrentCrossEdgeCount, ...
        'meanEospa', record.focusEospa, ...
        'meanGainPercent', percentGain( ...
            baseline.focusEospa, record.focusEospa), ...
        'worstEospa', record.focusWorstSensorEospa, ...
        'tailGainPercent', percentGain( ...
            baseline.focusWorstSensorEospa, ...
            record.focusWorstSensorEospa), ...
        'byteChangePercent', percentChange( ...
            baseline.focusAttemptedBytes, ...
            record.focusAttemptedBytes), ...
        'repairRate', record.policyRepairRate, ...
        'truthUseFraction', record.policyTruthUseFraction, ...
        'payloadEmergencyRate', ...
            record.policyPayloadEmergencyRate, ...
        'topologyInfeasibleRate', ...
            record.focusTopologyInfeasibleRate, ...
        'selectedSensorB3', ...
            record.focusSelectedRollingB3SensorStrongFraction, ...
        'selectedFormationB3', ...
            record.focusSelectedRollingB3FormationStrongFraction, ...
        'sensorSignature', sensorSignature, ...
        'formationSignature', ...
            adjacencySignature(formationAdjacency), ...
        'newVersusOldCodebook', ...
            ~any(strcmp(oldSignatures, sensorSignature)), ...
        'jointPass', false);
end

for candidateIdx = 1:candidateCount
    row = rows(candidateIdx);
    rows(candidateIdx).jointPass = ...
        row.newVersusOldCodebook && ...
        row.meanGainPercent >= 5 - 1e-9 && ...
        row.tailGainPercent >= -1e-9 && ...
        abs(row.byteChangePercent) <= 2 + 1e-9 && ...
        row.repairRate == 0 && ...
        row.truthUseFraction == 0 && ...
        row.payloadEmergencyRate == 0 && ...
        row.topologyInfeasibleRate == 0 && ...
        row.selectedSensorB3 == 1 && ...
        row.selectedFormationB3 == 1;
end

allSensorSignatures = {rows.sensorSignature};
uniqueSensorSignatures = unique(allSensorSignatures);
noRepairMask = [rows.repairRate] == 0 & ...
    [rows.payloadEmergencyRate] == 0;
newNoRepairMask = noRepairMask & [rows.newVersusOldCodebook];
uniqueNewNoRepairSensorSignatures = unique( ...
    {rows(newNoRepairMask).sensorSignature});
uniqueNewNoRepairFormationSignatures = unique( ...
    {rows(newNoRepairMask).formationSignature});
coveredNonzeroCardinalities = unique([rows( ...
    newNoRepairMask & [rows.k] > 0).k]);
duplicateRate = 1 - numel(uniqueSensorSignatures) / candidateCount;
diversityPass = ...
    numel(uniqueNewNoRepairSensorSignatures) >= 6 && ...
    numel(uniqueNewNoRepairFormationSignatures) >= 3 && ...
    numel(coveredNonzeroCardinalities) >= 2 && ...
    duplicateRate <= 0.5 + 1e-9;
jointPassCount = nnz([rows.jointPass]);

audit = struct( ...
    'protocolId', ...
        'm24-observable-score-basis-coverage-seed7-v1', ...
    'seed', seed, ...
    'registrySha256', registryMetadata.registrySha256, ...
    'candidateCount', candidateCount, ...
    'uniqueSensorSignatureCount', ...
        numel(uniqueSensorSignatures), ...
    'uniqueNewNoRepairSensorSignatureCount', ...
        numel(uniqueNewNoRepairSensorSignatures), ...
    'uniqueNewNoRepairFormationSignatureCount', ...
        numel(uniqueNewNoRepairFormationSignatures), ...
    'coveredNonzeroCardinalities', ...
        coveredNonzeroCardinalities, ...
    'duplicateRate', duplicateRate, ...
    'diversityPass', diversityPass, ...
    'jointPassCount', jointPassCount, ...
    'headroomPass', jointPassCount > 0, ...
    'baseline', baseline, ...
    'rows', rows, ...
    'sourceFiles', {sourceFiles}, ...
    'gitState', gitState);
writeReport(reportPath, audit);
fprintf('Report: %s\n', reportPath);
fprintf(['Candidates %d, unique sensor routes %d, new no-repair ', ...
    'sensor routes %d, joint passes %d.\n'], ...
    candidateCount, numel(uniqueSensorSignatures), ...
    numel(uniqueNewNoRepairSensorSignatures), jointPassCount);
end

function writeReport(reportPath, audit)
fileId = fopen(reportPath, 'w');
if fileId < 0
    error('Could not open score-basis audit report.');
end
cleanup = onCleanup(@() fclose(fileId));
baseline = audit.baseline;
fprintf(fileId, '# M24 observable score-basis coverage audit: seed 7\n\n');
fprintf(fileId, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fileId, '- Registry SHA-256: `%s`\n', audit.registrySha256);
fprintf(fileId, '- Evidence split: `development`\n');
fprintf(fileId, '- Design-seen seed: `%d`\n', audit.seed);
fprintf(fileId, '- Candidate count: `%d`\n', audit.candidateCount);
fprintf(fileId, '- Audit git commit: `%s`\n', ...
    audit.gitState.commit);
fprintf(fileId, '- Audit tracked worktree dirty: `%d`\n', ...
    audit.gitState.trackedWorktreeDirty);
fprintf(fileId, '- Audit untracked source dirty: `%d`\n', ...
    audit.gitState.untrackedSourceDirty);
fprintf(fileId, ['- Evidence boundary: action-space coverage only; ', ...
    'seed 7 is not held-out validation and cannot support a ', ...
    'generalization claim.\n\n']);
fprintf(fileId, '## Registered reference and gates\n\n');
fprintf(fileId, ...
    '- Code-24 E-OSPA: `%.4f`\n', baseline.focusEospa);
fprintf(fileId, ...
    '- Code-24 worst-node E-OSPA: `%.4f`\n', ...
    baseline.focusWorstSensorEospa);
fprintf(fileId, ...
    '- Code-24 attempted bytes: `%.0f`\n', ...
    baseline.focusAttemptedBytes);
fprintf(fileId, ['- Headroom gate: a new realized route must provide ', ...
    'at least 5%% mean gain, no worst-node regression, at most ', ...
    '2%% attempted-byte mismatch, no repair or payload emergency, ', ...
    'and complete selected rolling-B3 safety.\n\n']);
fprintf(fileId, '## Complete candidate table\n\n');
fprintf(fileId, ['| Code | Basis | k | E-OSPA | Mean gain | ', ...
    'Worst node | Tail gain | Byte change | Repair | New route | Pass |\n']);
fprintf(fileId, ...
    '|--:|:--|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
for row = audit.rows
    fprintf(fileId, ...
        ['| %02d | `%s` | %d | %.4f | %+.2f%% | %.4f | ', ...
         '%+.2f%% | %+.2f%% | %.4f | %d | %d |\n'], ...
        row.code, row.basisId, row.k, row.meanEospa, ...
        row.meanGainPercent, row.worstEospa, ...
        row.tailGainPercent, row.byteChangePercent, ...
        row.repairRate, row.newVersusOldCodebook, ...
        row.jointPass);
end
fprintf(fileId, '\n## Diversity and headroom decision\n\n');
fprintf(fileId, '- Unique realized sensor routes: `%d / %d`\n', ...
    audit.uniqueSensorSignatureCount, audit.candidateCount);
fprintf(fileId, ...
    '- New no-repair sensor routes versus old codebook: `%d`\n', ...
    audit.uniqueNewNoRepairSensorSignatureCount);
fprintf(fileId, ...
    '- New no-repair formation routes versus old codebook: `%d`\n', ...
    audit.uniqueNewNoRepairFormationSignatureCount);
fprintf(fileId, '- Covered nonzero exact cardinalities: `%s`\n', ...
    mat2str(audit.coveredNonzeroCardinalities));
fprintf(fileId, '- Projector duplicate rate: `%.2f%%`\n', ...
    100 * audit.duplicateRate);
fprintf(fileId, '- Diversity gate passed: `%d`\n', ...
    audit.diversityPass);
fprintf(fileId, '- Joint headroom pass count: `%d`\n', ...
    audit.jointPassCount);
fprintf(fileId, '- Action-space headroom passed: `%d`\n\n', ...
    audit.headroomPass);
fprintf(fileId, ['The registry creates genuine new sensor-level actions, ', ...
    'but none improves even the mean E-OSPA over code 24; every ', ...
    'candidate also regresses worst-node E-OSPA. The failure is ', ...
    'therefore not caused by duplicate projector outputs alone. ', ...
    'This local observable linear-score family should be rejected ', ...
    'before any selector or value model is trained.\n\n']);
fprintf(fileId, '## Source summaries\n\n');
for sourceFile = audit.sourceFiles
    fprintf(fileId, '- `%s`\n', sourceFile{1});
end
clear cleanup;
end

function signatures = loadOldCodebookSignatures(seed, batchCount)
signatures = {};
for batchIdx = 1:batchCount
    directory = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'rollout_dataset', sprintf( ...
            'seed%d_counterfactual_b%02dof%02d', ...
            seed, batchIdx, batchCount));
    sourceFile = latestMatFile(directory);
    loaded = load(sourceFile);
    for record = loaded.summary.records
        history = logical(record.focusSelectedDirectedEdgeHistory);
        signatures{end + 1} = ... %#ok<AGROW>
            adjacencySignature(history(:, :, 1));
    end
end
signatures = unique(signatures);
end

function sourceFile = latestMatFile(directory)
listing = dir(fullfile(directory, '*.mat'));
if isempty(listing)
    error('No MAT summary found in %s.', directory);
end
[~, latestIdx] = max([listing.datenum]);
sourceFile = fullfile(directory, listing(latestIdx).name);
end

function [records, codes] = sortRecordsByActionCode(records)
codes = arrayfun(@(record) ...
    parseFirstActionCode(record.armMode), records);
[codes, order] = sort(codes);
records = records(order);
end

function actionCode = parseFirstActionCode(armMode)
tokens = regexp(armMode, ...
    'rolling-safe-sequence-t[0-9]+-s([0-9]+)-w', ...
    'tokens', 'once');
if isempty(tokens) || numel(tokens{1}) < 2
    error('Could not parse action code from %s.', armMode);
end
actionCode = str2double(tokens{1}(1:2));
end

function assertSameBaseline(reference, candidate)
fields = {'focusEospa', 'focusWorstSensorEospa', ...
    'focusAttemptedBytes', 'policySelectedRouteSignature'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    if isnumeric(reference.(fieldName))
        if abs(reference.(fieldName) - candidate.(fieldName)) > 1e-9
            error('Code-24 references differ in %s.', fieldName);
        end
    elseif ~isequal(reference.(fieldName), candidate.(fieldName))
        error('Code-24 references differ in %s.', fieldName);
    end
end
end

function signature = adjacencySignature(adjacency)
bits = char('0' + reshape(logical(adjacency), 1, []));
signature = hash('sha256', bits);
end

function formationAdjacency = ...
        sensorToFormationAdjacency(sensorAdjacency, groupIds)
groups = unique(groupIds, 'stable');
formationAdjacency = false(numel(groups));
for receiverIdx = 1:numel(groupIds)
    for senderIdx = reshape(find( ...
            sensorAdjacency(receiverIdx, :)), 1, [])
        receiverGroup = find( ...
            groups == groupIds(receiverIdx), 1);
        senderGroup = find(groups == groupIds(senderIdx), 1);
        if receiverGroup ~= senderGroup
            formationAdjacency(receiverGroup, senderGroup) = true;
        end
    end
end
end

function value = percentGain(reference, candidate)
value = 100 * (reference - candidate) / reference;
end

function value = percentChange(reference, candidate)
value = 100 * (candidate - reference) / reference;
end
