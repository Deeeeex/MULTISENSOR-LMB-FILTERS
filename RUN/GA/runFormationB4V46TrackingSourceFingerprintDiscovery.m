function [discovery, runMetadata, outputPath] = ...
    runFormationB4V46TrackingSourceFingerprintDiscovery(outputPath)
% RUNFORMATIONB4V46TRACKINGSOURCEFINGERPRINTDISCOVERY Full 40-case audit.
%
% This runner publishes only hashes and provenance for the complete V46
% source registry.  It never executes a filter, returns a state estimate,
% scores tracking, freezes a permit, or opens confirmation outcomes.

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
initialGit = resolveExactGitState(repoRoot);
if ~initialGit.clean
    error('FormationB4V46TrackingDiscovery:DirtyGitState', ...
        'The full-registry discovery requires a clean worktree.');
end
if nargin < 1 || isempty(outputPath)
    outputDirectory = fullfile(repoRoot, 'RUN', 'GA', ...
        'dynamic_topology', 'evidence', ...
        'formation_b4_v46_tracking_source_fingerprints', ...
        initialGit.headCommit);
    outputPath = fullfile(outputDirectory, ...
        'formation_b4_v46_tracking_source_discovery_v2.mat');
else
    validateOutputPath(outputPath);
    outputDirectory = fileparts(outputPath);
    if isempty(outputDirectory)
        outputDirectory = pwd;
        outputPath = fullfile(outputDirectory, outputPath);
    end
end
validateOutputPath(outputPath);
if exist(outputPath, 'file') ~= 0 || exist(outputPath, 'dir') ~= 0
    error('FormationB4V46TrackingDiscovery:OutputExists', ...
        'The discovery runner refuses to overwrite an existing path.');
end
if exist(outputDirectory, 'dir') == 0
    [created, message] = mkdir(outputDirectory);
    if ~created
        error('FormationB4V46TrackingDiscovery:OutputCreateFailed', ...
            'Could not create output directory: %s', message);
    end
end

registry = getFormationB4V46TrackingSourceRegistry();
startedAt = datestr(now, 31);
timerId = tic;
discovery = discoverFormationB4V46TrackingSourceFingerprints();
elapsedSeconds = toc(timerId);
auditFullRegistryDiscovery(discovery, registry);

endingGit = resolveExactGitState(repoRoot);
if ~endingGit.clean || ...
        ~strcmp(endingGit.headCommit, initialGit.headCommit) || ...
        ~strcmp(endingGit.repositoryRoot, initialGit.repositoryRoot)
    error('FormationB4V46TrackingDiscovery:GitStateChanged', ...
        'The repository state changed during source discovery.');
end

metadataPayload = struct();
metadataPayload.contractVersion = ...
    'formation-b4-v46-tracking-source-discovery-run-metadata-v1';
metadataPayload.generationGitCommit = initialGit.headCommit;
metadataPayload.generationGitClean = true;
metadataPayload.endingGitCommit = endingGit.headCommit;
metadataPayload.endingGitClean = true;
metadataPayload.registryId = registry.id;
metadataPayload.registryCanonicalSha256 = registry.canonicalSha256;
metadataPayload.discoveryContractVersion = discovery.contractVersion;
metadataPayload.discoveryCanonicalSha256 = discovery.canonicalSha256;
metadataPayload.caseCount = discovery.caseCount;
metadataPayload.fullRegistryRequested = discovery.fullRegistryRequested;
metadataPayload.sourceInputFingerprintsFrozen = false;
metadataPayload.sourceArtifactPublicationAuthorized = false;
metadataPayload.filterExecuted = false;
metadataPayload.stateEstimateGenerated = false;
metadataPayload.trackingOutcomeScored = false;
metadataPayload.developmentAdvanceDecisionMade = false;
metadataPayload.confirmationOpened = false;
metadataPayload.validationClaimAllowed = false;
metadataPayload.startedAt = startedAt;
metadataPayload.completedAt = datestr(now, 31);
metadataPayload.elapsedSeconds = elapsedSeconds;
metadataPayload.evidenceBoundary = [ ...
    'This hash-only artifact covers all forty registered V46 source ', ...
    'cases. It is not a source-input freeze, filter-execution permit, ', ...
    'tracking result, arm decision, confirmation opening, secrecy ', ...
    'guarantee, or validation claim.'];
runMetadata = metadataPayload;
runMetadata.canonicalSha256 = ...
    computeCanonicalValueSha256(metadataPayload);

temporaryPath = [tempname(outputDirectory), '.mat'];
temporaryCleanup = onCleanup(@() deleteIfPresent(temporaryPath));
save('-mat7-binary', temporaryPath, 'discovery', 'runMetadata');
publicationGit = resolveExactGitState(repoRoot);
if ~publicationGit.clean || ...
        ~strcmp(publicationGit.headCommit, initialGit.headCommit)
    error('FormationB4V46TrackingDiscovery:GitStateChanged', ...
        'The repository state changed during artifact publication.');
end
if exist(outputPath, 'file') ~= 0
    error('FormationB4V46TrackingDiscovery:OutputExists', ...
        'The discovery output appeared during execution.');
end
[moved, message] = movefile(temporaryPath, outputPath, 'f');
if ~moved
    error('FormationB4V46TrackingDiscovery:PublicationFailed', ...
        'Could not atomically publish discovery MAT: %s', message);
end
clear temporaryCleanup;
fprintf('V46 full-registry source discovery: %s\n', outputPath);
fprintf('V46 discovery canonical SHA-256: %s\n', ...
    discovery.canonicalSha256);
end

function auditFullRegistryDiscovery(discovery, registry)
expectedDiscoveryFields = { ...
    'contractVersion', 'registryId', 'registryCanonicalSha256', ...
    'presets', 'seeds', 'records', 'caseCount', 'runtimeEngine', ...
    'runtimeVersion', 'fullRegistryRequested', ...
    'sourceInputFingerprintsFrozen', ...
    'sourceArtifactPublicationAuthorized', ...
    'rawSourceObjectsReturned', 'rawTruthReturned', ...
    'rawMeasurementsReturned', 'runtimeFilterModelReturned', ...
    'runtimeTargetTrajectoryRealizationAbsent', ...
    'registeredBirthPriorRetained', 'filterExecuted', ...
    'stateEstimateGenerated', ...
    'sourceGeometryTruthValidationExecuted', ...
    'truthHashedForSealing', ...
    'estimateVsTruthTrackingMetricComputed', ...
    'armComparedOrSelected', 'trackingOutcomeScored', ...
    'developmentAdvanceDecisionMade', 'confirmationOpened', ...
    'validationClaimAllowed', 'developmentEvidenceOnly', ...
    'canonicalSha256'};
expectedRecordFields = { ...
    'caseId', 'caseOrdinal', 'presetName', 'seed', 'seedRole', ...
    'primaryMatrix', 'stressMatrix', 'deliverySeed', ...
    'inputFingerprint', 'runtimeFilterInputFingerprint', ...
    'runtimeTargetTrajectoryRealizationAbsent', ...
    'registeredBirthPriorRetained', ...
    'sourceGeometryTruthValidationExecuted', ...
    'truthHashedForSealing', 'filterExecuted', ...
    'estimateVsTruthTrackingMetricComputed', ...
    'trackingOutcomeScored', 'sourceEnvelopeCanonicalSha256', ...
    'canonicalSha256'};
if ~isstruct(discovery) || ~isscalar(discovery) || ...
        ~isequal(sort(fieldnames(discovery)), ...
            sort(expectedDiscoveryFields(:))) || ...
        ~strcmp(discovery.contractVersion, ...
            ['formation-b4-v46-tracking-source-', ...
             'fingerprint-discovery-v2']) || ...
        ~strcmp(discovery.registryId, registry.id) || ...
        ~strcmp(discovery.registryCanonicalSha256, ...
            registry.canonicalSha256) || ...
        ~isequal(discovery.presets, {registry.scenes.presetName}) || ...
        ~isequal(discovery.seeds, registry.orderedSeeds) || ...
        discovery.caseCount ~= registry.caseCount || ...
        discovery.caseCount ~= 40 || ...
        ~discovery.fullRegistryRequested || ...
        discovery.sourceInputFingerprintsFrozen || ...
        discovery.sourceArtifactPublicationAuthorized || ...
        discovery.rawSourceObjectsReturned || ...
        discovery.rawTruthReturned || ...
        discovery.rawMeasurementsReturned || ...
        discovery.runtimeFilterModelReturned || ...
        ~discovery.runtimeTargetTrajectoryRealizationAbsent || ...
        ~discovery.registeredBirthPriorRetained || ...
        discovery.filterExecuted || discovery.stateEstimateGenerated || ...
        ~discovery.sourceGeometryTruthValidationExecuted || ...
        ~discovery.truthHashedForSealing || ...
        discovery.estimateVsTruthTrackingMetricComputed || ...
        discovery.armComparedOrSelected || ...
        discovery.trackingOutcomeScored || ...
        discovery.developmentAdvanceDecisionMade || ...
        discovery.confirmationOpened || ...
        discovery.validationClaimAllowed || ...
        ~discovery.developmentEvidenceOnly || ...
        ~strcmp(computeCanonicalValueSha256( ...
            rmfield(discovery, 'canonicalSha256')), ...
            discovery.canonicalSha256)
    error('FormationB4V46TrackingDiscovery:DiscoveryAuditFailed', ...
        'The full-registry discovery payload failed its outer audit.');
end
if ~isstruct(discovery.records) || ...
        numel(discovery.records) ~= registry.caseCount
    error('FormationB4V46TrackingDiscovery:DiscoveryAuditFailed', ...
        'The discovery record count differs from the registry.');
end
for caseIdx = 1:registry.caseCount
    record = discovery.records(caseIdx);
    contract = registry.cases(caseIdx);
    if ~isequal(sort(fieldnames(record)), ...
            sort(expectedRecordFields(:))) || ...
            ~strcmp(record.caseId, contract.id) || ...
            record.caseOrdinal ~= contract.ordinal || ...
            ~strcmp(record.presetName, contract.presetName) || ...
            record.seed ~= contract.seed || ...
            ~strcmp(record.seedRole, contract.seedRole) || ...
            record.primaryMatrix ~= contract.primaryMatrix || ...
            record.stressMatrix ~= contract.stressMatrix || ...
            record.deliverySeed ~= contract.deliverySeed || ...
            ~record.runtimeTargetTrajectoryRealizationAbsent || ...
            ~record.registeredBirthPriorRetained || ...
            ~record.sourceGeometryTruthValidationExecuted || ...
            ~record.truthHashedForSealing || ...
            record.filterExecuted || ...
            record.estimateVsTruthTrackingMetricComputed || ...
            record.trackingOutcomeScored || ...
            ~strcmp(computeCanonicalValueSha256( ...
                rmfield(record.inputFingerprint, ...
                    'canonicalSha256')), ...
                record.inputFingerprint.canonicalSha256) || ...
            ~isequaln( ...
                projectFormationB4V46RuntimeFilterInputFingerprint( ...
                    record.inputFingerprint), ...
                record.runtimeFilterInputFingerprint) || ...
            ~strcmp(computeCanonicalValueSha256( ...
                rmfield(record, 'canonicalSha256')), ...
                record.canonicalSha256)
        error('FormationB4V46TrackingDiscovery:DiscoveryAuditFailed', ...
            'Discovery record %d failed its exact audit.', caseIdx);
    end
end
end

function state = resolveExactGitState(repoRoot)
originalDirectory = pwd;
cleanup = onCleanup(@() cd(originalDirectory));
cd(repoRoot);
[headStatus, head] = system('git rev-parse HEAD');
[rootStatus, root] = system('git rev-parse --show-toplevel');
[statusCode, porcelain] = system('git status --porcelain');
if headStatus ~= 0 || rootStatus ~= 0 || statusCode ~= 0
    error('FormationB4V46TrackingDiscovery:GitStateUnavailable', ...
        'Could not resolve the exact repository state.');
end
state = struct();
state.headCommit = strtrim(head);
state.repositoryRoot = strtrim(root);
state.clean = isempty(strtrim(porcelain));
clear cleanup;
end

function validateOutputPath(outputPath)
if ~ischar(outputPath) || isempty(outputPath) || ...
        numel(outputPath) < 5 || ...
        ~strcmpi(outputPath(end - 3:end), '.mat')
    error('FormationB4V46TrackingDiscovery:InvalidOutputPath', ...
        'outputPath must be a nonempty MAT-file path.');
end
end

function deleteIfPresent(path)
if exist(path, 'file') ~= 0
    delete(path);
end
end
