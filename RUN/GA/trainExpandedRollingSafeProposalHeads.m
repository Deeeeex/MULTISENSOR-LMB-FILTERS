function value = stableSigmoidLocal(values)
value = zeros(size(values));
positive = values >= 0;
value(positive) = 1 ./ (1 + exp(-values(positive)));
negative = ~positive;
expValue = exp(values(negative));
value(negative) = expValue ./ (1 + expValue);
end

function values = clipGradientsLocal(values, maximumNorm)
total = 0;
for idx = 1:numel(values)
    total = total + sum(values{idx}(:).^2);
end
normValue = sqrt(total);
if normValue > maximumNorm
    scale = maximumNorm / normValue;
    for idx = 1:numel(values)
        values{idx} = scale * values{idx};
    end
end
end

