function [modelPath, result] = ...
    trainExpandedRollingSafeProposalHeads(options)
% TRAINEXPANDEDROLLINGSAFEPROPOSALHEADS Relational multi-head diagnostic.
%
% Hyperparameters are selected only by leave-one-seed-out imitation on the
% 54 truth-free-behavior states. The selected model is then evaluated with
% a top-16 exact safety-projected bank on both those held-out teacher states
% and the older value-filtered development states. The latter never selects
% a hyperparameter and remains a design-only external diagnostic.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeProposalDistillationProtocol();
criticProtocol = getRollingSafeJointActionCriticProtocol();
datasetPath = getField(options, ...
    'datasetPath', protocol.datasetPath);
valuePath = getField(options, 'valueDatasetPath', ...
    criticProtocol.privilegedValueTargetDatasetRelativePath);
sourcePath = getField(options, 'sourceStatePath', ...
    criticProtocol.proposalSourceStateRelativePath);
validateFrozenFile(datasetPath, protocol.datasetSha256, ...
    'expanded proposal dataset');
validateFrozenFile(valuePath, ...
    criticProtocol.privilegedValueTargetDatasetSha256, ...
    'legacy value-target dataset');
validateFrozenFile(sourcePath, ...
    criticProtocol.proposalSourceStateSha256, ...
    'legacy source-state dataset');
expandedLoaded = load(datasetPath, 'dataset');
valueLoaded = load(valuePath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
expanded = expandedLoaded.dataset;
valueDataset = valueLoaded.dataset;
sourceDataset = sourceLoaded.dataset;
validateDatasets(expanded, valueDataset, sourceDataset, ...
    protocol, criticProtocol);

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official expanded proposal training requires clean source.');
end

configs = buildCandidateConfigs(protocol);
candidates = repmat(emptyCandidate(), 1, numel(configs));
for configIdx = 1:numel(configs)
    config = configs(configIdx);
    [featureCells, featureNames] = prepareExpandedFeatures( ...
        expanded, config.featureMode);
    rows = repmat(emptyCoverageRow(), 1, 0);
    for heldoutSeed = protocol.datasetSeeds
        fitSeeds = setdiff(protocol.datasetSeeds, ...
            heldoutSeed, 'stable');
        fitOptions = config;
        fitOptions.initializationSeed = ...
            protocol.modelInitializationSeed + ...
            1000 * configIdx + heldoutSeed;
        foldModel = fitSharedHeads( ...
            expanded, featureCells, fitSeeds, ...
            protocol.modelHeadActionCodes, fitOptions);
        heldoutIndices = find( ...
            [expanded.blocks.seed] == heldoutSeed);
        for blockIdx = heldoutIndices
            scores = scoreSharedHeads( ...
                foldModel, featureCells{blockIdx});
            row = evaluateExpandedBlock( ...
                expanded, blockIdx, scores, ...
                sourceDataset, criticProtocol, ...
                protocol.modelSelectionMaximumBannedEdges);
            rows(end + 1) = row; %#ok<AGROW>
        end
    end
    candidates(configIdx) = summarizeCandidate( ...
        config, rows, featureNames);
    candidates(configIdx).configurationIndex = configIdx;
    fprintf(['expanded proposal %s/%s h=%d lambda=%.4g: ', ...
        'state %.1f%%, min-seed %.1f%%, graph %.1f%%, F1 %.3f\n'], ...
        config.family, config.featureMode, ...
        config.hiddenWidth, config.lambda, ...
        100 * candidates(configIdx).stateCaptureFraction, ...
        100 * candidates(configIdx).minimumSeedCaptureFraction, ...
        100 * candidates(configIdx).targetGraphRecallFraction, ...
        candidates(configIdx).meanBestTargetEdgeF1);
end
selectionKeys = zeros(numel(candidates), 8);
for idx = 1:numel(candidates)
    candidate = candidates(idx);
    selectionKeys(idx, :) = [ ...
        -candidate.minimumSeedCaptureFraction, ...
        -candidate.stateCaptureFraction, ...
        -candidate.targetGraphRecallFraction, ...
        -candidate.meanBestTargetEdgeF1, ...
        candidate.projectionFailureCount, ...
        candidate.familyOrder, candidate.featureModeOrder, ...
        candidate.complexityOrder];
end
[~, order] = sortrows(selectionKeys);
candidates = candidates(order);
selected = candidates(1);

[selectedFeatures, selectedFeatureNames] = ...
    prepareExpandedFeatures(expanded, selected.featureMode);
[valueFeatures, valueFeatureNames] = prepareValueFeatures( ...
    valueDataset, selected.featureMode);
if ~isequal(selectedFeatureNames, valueFeatureNames)
    error('Expanded and legacy value feature contracts differ.');
end
expandedRows = repmat(emptyCoverageRow(), 1, 0);
valueRows = repmat(emptyCoverageRow(), 1, 0);
for heldoutSeed = protocol.datasetSeeds
    fitSeeds = setdiff(protocol.datasetSeeds, ...
        heldoutSeed, 'stable');
    fitOptions = candidateFitOptions(selected, ...
        protocol.modelInitializationSeed + ...
        1000 * selected.configurationIndex + heldoutSeed);
    foldModel = fitSharedHeads( ...
        expanded, selectedFeatures, fitSeeds, ...
        protocol.modelHeadActionCodes, fitOptions);
    heldoutExpanded = find( ...
        [expanded.blocks.seed] == heldoutSeed);
    for blockIdx = heldoutExpanded
        scores = scoreSharedHeads( ...
            foldModel, selectedFeatures{blockIdx});
        expandedRows(end + 1) = evaluateExpandedBlock( ...
            expanded, blockIdx, scores, sourceDataset, ...
            criticProtocol, ...
            protocol.modelEvaluationMaximumBannedEdges); %#ok<AGROW>
    end
    heldoutValue = find( ...
        [valueDataset.blocks.seed] == heldoutSeed & ...
        [valueDataset.blocks.valueTargetCount] > 0);
    for blockIdx = heldoutValue
        scores = scoreSharedHeads( ...
            foldModel, valueFeatures{blockIdx});
        valueRows(end + 1) = evaluateValueBlock( ...
            valueDataset, sourceDataset, blockIdx, ...
            scores, criticProtocol, ...
            protocol.modelEvaluationMaximumBannedEdges); %#ok<AGROW>
    end
end
expandedMetrics = summarizeRows(expandedRows);
valueMetrics = summarizeRows(valueRows);

fitOptions = candidateFitOptions(selected, ...
    protocol.modelInitializationSeed);
finalHeadModel = fitSharedHeads( ...
    expanded, selectedFeatures, protocol.datasetSeeds, ...
    protocol.modelHeadActionCodes, fitOptions);
model = finalHeadModel;
model.kind = ...
    'shared-relational-multihead-rolling-safe-proposal-v1';
model.protocolId = protocol.id;
model.contractVersion = protocol.modelContractVersion;
model.generatedAt = datestr(now, 31);
model.family = selected.family;
model.featureContextMode = selected.featureMode;
model.featureNames = selectedFeatureNames;
model.headActionCodes = protocol.modelHeadActionCodes;
model.topK = protocol.modelEvaluationTopK;
model.maximumBannedSelectedEdges = ...
    protocol.modelEvaluationMaximumBannedEdges;
model.sourceWeight = expanded.sourceWeight;
model.datasetPath = datasetPath;
model.datasetSha256 = protocol.datasetSha256;
model.datasetGenerationCommit = ...
    expanded.generationGitCommit;
model.valueDiagnosticPath = valuePath;
model.valueDiagnosticSha256 = ...
    criticProtocol.privilegedValueTargetDatasetSha256;
model.sourceStatePath = sourcePath;
model.sourceStateSha256 = ...
    criticProtocol.proposalSourceStateSha256;
model.trainingSeeds = protocol.datasetSeeds;
model.trainingGitCommit = gitState.commit;
model.trainingTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
model.trainingUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
model.trainingResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
model.featuresUseTruth = false;
model.labelsUseTruth = true;
model.labelsUseFutureOutcome = false;
model.stateCollectionBehaviorUsesTruth = false;
model.selectionMetrics = selected;
model.expandedTopKMetrics = expandedMetrics;
model.legacyValueTopKMetrics = valueMetrics;
model.expandedCaptureGatePassed = ...
    expandedMetrics.stateCaptureFraction + 1e-12 >= ...
        protocol.minimumExpandedTargetStateCaptureFraction && ...
    expandedMetrics.minimumSeedCaptureFraction + 1e-12 >= ...
        protocol.minimumExpandedSeedTargetStateCaptureFraction;
model.legacyValueCaptureGatePassed = ...
    valueMetrics.stateCaptureFraction + 1e-12 >= ...
        protocol.minimumLegacyValueStateCaptureFraction;
model.proposalReturnGenerationAuthorized = ...
    model.expandedCaptureGatePassed && ...
    model.legacyValueCaptureGatePassed;
model.valueReturnEvaluatedOnExpandedStates = false;
model.criticTrainingAuthorized = false;
model.x36Authorized = false;
model.developmentOnly = true;
model.validationClaimAllowed = false;
model.evidenceBoundary = [ ...
    'Hyperparameters use only LOSO current-truth graph imitation ', ...
    'on states collected by a frozen truth-free behavior policy. ', ...
    'The older value-filtered states are an external architecture ', ...
    'diagnostic and do not select the model. Passing authorizes ', ...
    'only H=3 proposal-return generation on the expanded M24 ', ...
    'development states, never critic training or X36.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'models'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
modelPath = getField(options, 'modelPath', fullfile( ...
    outputDirectory, ...
    'rolling_safe_expanded_proposal_heads_m24_t75_t83_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'EXPANDED_PROPOSAL_HEAD_LOSO_DIAGNOSTIC_M24.md'));
model.modelPath = modelPath;
model.reportPath = reportPath;
save('-mat7-binary', modelPath, 'model');

result = struct();
result.modelPath = modelPath;
result.reportPath = reportPath;
result.candidates = candidates;
result.selected = selected;
result.expandedTopKMetrics = expandedMetrics;
result.legacyValueTopKMetrics = valueMetrics;
result.proposalReturnGenerationAuthorized = ...
    model.proposalReturnGenerationAuthorized;
result.criticTrainingAuthorized = false;
result.x36Authorized = false;
writeReport(reportPath, model, candidates, protocol);
fprintf(['Selected %s/%s h=%d lambda=%.4g; top-16 ', ...
    'expanded capture %.1f%% (min seed %.1f%%), ', ...
    'legacy value capture %.1f%%; return generation=%d\n', ...
    'Model: %s\nReport: %s\n'], ...
    selected.family, selected.featureMode, ...
    selected.hiddenWidth, selected.lambda, ...
    100 * expandedMetrics.stateCaptureFraction, ...
    100 * expandedMetrics.minimumSeedCaptureFraction, ...
    100 * valueMetrics.stateCaptureFraction, ...
    model.proposalReturnGenerationAuthorized, ...
    modelPath, reportPath);
end

function configs = buildCandidateConfigs(protocol)
template = struct( ...
    'family', '', 'featureMode', '', ...
    'hiddenWidth', 0, 'lambda', NaN, ...
    'epochCount', protocol.modelMlpEpochCount, ...
    'learningRate', protocol.modelMlpLearningRate, ...
    'initializationSeed', protocol.modelInitializationSeed, ...
    'familyOrder', NaN, 'featureModeOrder', NaN, ...
    'complexityOrder', NaN);
configs = repmat(template, 1, 0);
for modeIdx = 1:numel(protocol.modelRidgeFeatureModes)
    mode = protocol.modelRidgeFeatureModes{modeIdx};
    for lambdaIdx = 1:numel(protocol.modelRidgeLambdaGrid)
        config = template;
        config.family = 'ridge';
        config.featureMode = mode;
        config.lambda = protocol.modelRidgeLambdaGrid(lambdaIdx);
        config.familyOrder = 1;
        config.featureModeOrder = modeIdx;
        config.complexityOrder = lambdaIdx;
        configs(end + 1) = config; %#ok<AGROW>
    end
end
for modeIdx = 1:numel(protocol.modelMlpFeatureModes)
    mode = protocol.modelMlpFeatureModes{modeIdx};
    for widthIdx = 1:numel(protocol.modelMlpHiddenWidthGrid)
        for lambdaIdx = 1:numel(protocol.modelMlpLambdaGrid)
            config = template;
            config.family = 'mlp';
            config.featureMode = mode;
            config.hiddenWidth = ...
                protocol.modelMlpHiddenWidthGrid(widthIdx);
            config.lambda = ...
                protocol.modelMlpLambdaGrid(lambdaIdx);
            config.familyOrder = 2;
            config.featureModeOrder = modeIdx;
            config.complexityOrder = ...
                10 * widthIdx + lambdaIdx;
            configs(end + 1) = config; %#ok<AGROW>
        end
    end
end
end

function [featureCells, names] = ...
        prepareExpandedFeatures(dataset, mode)
featureCells = cell(1, numel(dataset.blocks));
names = {};
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    [featureCells{blockIdx}, blockNames] = ...
        buildFormationTreeContextFeatures( ...
            block.features, dataset.featureNames, ...
            block.receiverIndices, block.senderIndices, ...
            reshape(block.groupIds, 1, []), mode);
    if isempty(names)
        names = reshape(blockNames, 1, []);
    elseif ~isequal(names, reshape(blockNames, 1, []))
        error('Expanded proposal feature names differ by block.');
    end
end
end

function [featureCells, names] = ...
        prepareValueFeatures(dataset, mode)
featureCells = cell(1, numel(dataset.blocks));
names = {};
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    [featureCells{blockIdx}, blockNames] = ...
        buildFormationTreeContextFeatures( ...
            block.edgeFeatures, block.edgeFeatureNames, ...
            block.receiverIndices, block.senderIndices, ...
            reshape(block.groupIds, 1, []), mode);
    if isempty(names)
        names = reshape(blockNames, 1, []);
    elseif ~isequal(names, reshape(blockNames, 1, []))
        error('Legacy value feature names differ by block.');
    end
end
end

function model = fitSharedHeads( ...
        dataset, featureCells, fitSeeds, headCodes, options)
[X, Y, W, blockCountByHead] = collectTrainingExamples( ...
    dataset, featureCells, fitSeeds, headCodes);
featureMean = mean(X, 1);
featureScale = std(X, 0, 1);
featureScale(~isfinite(featureScale) | ...
    featureScale <= eps) = 1;
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, featureMean), featureScale);
switch options.family
    case 'ridge'
        design = [ones(size(Z, 1), 1), Z];
        regularizer = diag([0, ones(1, size(Z, 2))]);
        coefficients = zeros( ...
            size(design, 2), numel(headCodes));
        for headIdx = 1:numel(headCodes)
            weights = W(:, headIdx);
            weightedDesign = bsxfun(@times, ...
                design, weights);
            coefficients(:, headIdx) = ...
                (design' * weightedDesign + ...
                 options.lambda * regularizer) \ ...
                (design' * (weights .* Y(:, headIdx)));
        end
        model = struct( ...
            'family', 'ridge', ...
            'coefficients', coefficients);
    case 'mlp'
        model = fitSharedMlp(Z, Y, W, options);
    otherwise
        error('Unknown expanded proposal model family.');
end
model.featureMean = featureMean;
model.featureScale = featureScale;
model.headActionCodes = headCodes;
model.trainingSeeds = fitSeeds;
model.trainingBlockCountByHead = blockCountByHead;
model.lambda = options.lambda;
model.hiddenWidth = options.hiddenWidth;
model.epochCount = options.epochCount;
model.learningRate = options.learningRate;
model.initializationSeed = options.initializationSeed;
end

function [X, Y, W, blockCountByHead] = ...
        collectTrainingExamples( ...
            dataset, featureCells, fitSeeds, headCodes)
X = zeros(0, size(featureCells{1}, 2));
Y = zeros(0, numel(headCodes));
W = zeros(0, numel(headCodes));
blockCountByHead = zeros(1, numel(headCodes));
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    if ~ismember(block.seed, fitSeeds)
        continue
    end
    teacher = dataset.teacherBlocks(blockIdx);
    blockX = featureCells{blockIdx};
    blockY = zeros(size(blockX, 1), numel(headCodes));
    blockW = zeros(size(blockY));
    for headIdx = 1:numel(headCodes)
        targetIdx = find(teacher.targetActionCodes == ...
            headCodes(headIdx), 1);
        if isempty(targetIdx)
            continue
        end
        target = double( ...
            teacher.targetCrossMasks(:, targetIdx));
        positiveCount = nnz(target);
        negativeCount = numel(target) - positiveCount;
        if positiveCount ~= 3 || negativeCount <= 0
            error('Expanded proposal target class balance changed.');
        end
        weights = zeros(size(target));
        weights(target > 0.5) = 0.5 / positiveCount;
        weights(target <= 0.5) = 0.5 / negativeCount;
        blockY(:, headIdx) = target;
        blockW(:, headIdx) = weights;
        blockCountByHead(headIdx) = ...
            blockCountByHead(headIdx) + 1;
    end
    X = [X; blockX]; %#ok<AGROW>
    Y = [Y; blockY]; %#ok<AGROW>
    W = [W; blockW]; %#ok<AGROW>
end
if isempty(X) || any(blockCountByHead < 2) || ...
        any(sum(W, 1) <= 0)
    error('Expanded proposal training support is incomplete.');
end
end

function model = fitSharedMlp(Z, Y, W, options)
rng(options.initializationSeed);
inputCount = size(Z, 2);
headCount = size(Y, 2);
hiddenWidth = options.hiddenWidth;
parameters = { ...
    randn(inputCount, hiddenWidth) / sqrt(inputCount), ...
    zeros(1, hiddenWidth), ...
    randn(hiddenWidth, headCount) / sqrt(hiddenWidth), ...
    zeros(1, headCount)};
firstMoment = cellfun(@zerosLike, parameters, ...
    'UniformOutput', false);
secondMoment = cellfun(@zerosLike, parameters, ...
    'UniformOutput', false);
weightDenominator = sum(W(:));
lossHistory = nan(1, options.epochCount);
for epoch = 1:options.epochCount
    hidden = tanh(bsxfun(@plus, ...
        Z * parameters{1}, parameters{2}));
    logits = bsxfun(@plus, ...
        hidden * parameters{3}, parameters{4});
    probability = stableSigmoidLocal(logits);
    clipped = min(max(probability, 1e-9), 1 - 1e-9);
    weightedLoss = W .* ( ...
        -Y .* log(clipped) - ...
        (1 - Y) .* log(1 - clipped));
    dataLoss = sum(weightedLoss(:)) / ...
        weightDenominator;
    regularization = 0.5 * options.lambda * ( ...
        sum(parameters{1}(:).^2) + ...
        sum(parameters{3}(:).^2));
    lossHistory(epoch) = dataLoss + regularization;
    dLogit = W .* (probability - Y) / ...
        weightDenominator;
    gradients = cell(1, 4);
    gradients{3} = hidden' * dLogit + ...
        options.lambda * parameters{3};
    gradients{4} = sum(dLogit, 1);
    dHidden = dLogit * parameters{3}';
    dActivation = dHidden .* (1 - hidden.^2);
    gradients{1} = Z' * dActivation + ...
        options.lambda * parameters{1};
    gradients{2} = sum(dActivation, 1);
    gradients = clipGradientsLocal(gradients, 10);
    for parameterIdx = 1:numel(parameters)
        firstMoment{parameterIdx} = ...
            0.9 * firstMoment{parameterIdx} + ...
            0.1 * gradients{parameterIdx};
        secondMoment{parameterIdx} = ...
            0.999 * secondMoment{parameterIdx} + ...
            0.001 * gradients{parameterIdx}.^2;
        correctedFirst = firstMoment{parameterIdx} / ...
            (1 - 0.9^epoch);
        correctedSecond = secondMoment{parameterIdx} / ...
            (1 - 0.999^epoch);
        parameters{parameterIdx} = ...
            parameters{parameterIdx} - ...
            options.learningRate * correctedFirst ./ ...
            (sqrt(correctedSecond) + 1e-8);
    end
end
if any(~isfinite(lossHistory)) || ...
        any(cellfun(@(value) ...
            any(~isfinite(value(:))), parameters))
    error('Expanded proposal MLP produced non-finite values.');
end
model = struct();
model.family = 'mlp';
model.hiddenWeight = parameters{1};
model.hiddenBias = parameters{2};
model.outputWeight = parameters{3};
model.outputBias = parameters{4};
model.trainingLossHistory = lossHistory;
model.finalTrainingLoss = lossHistory(end);
end

function scores = scoreSharedHeads(model, X)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.featureMean), ...
    model.featureScale);
switch model.family
    case 'ridge'
        scores = [ones(size(Z, 1), 1), Z] * ...
            model.coefficients;
    case 'mlp'
        hidden = tanh(bsxfun(@plus, ...
            Z * model.hiddenWeight, model.hiddenBias));
        scores = bsxfun(@plus, ...
            hidden * model.outputWeight, model.outputBias);
    otherwise
        error('Unknown shared-head model family.');
end
end

function row = evaluateExpandedBlock( ...
        dataset, blockIdx, scores, sourceDataset, ...
        criticProtocol, maximumBannedEdges)
block = dataset.blocks(blockIdx);
teacher = dataset.teacherBlocks(blockIdx);
targetMasks = teacher.targetCrossMasks;
targetHashes = teacher.targetGraphSha256;
[proposalMasks, proposalHashes, failures] = ...
    projectProposalBank(block, block.receiverIndices, ...
        block.senderIndices, scores, criticProtocol, ...
        maximumBannedEdges);
row = makeCoverageRow(block.seed, block.currentTime, ...
    targetMasks, targetHashes, proposalMasks, ...
    proposalHashes, failures);
end

function row = evaluateValueBlock( ...
        dataset, sourceDataset, blockIdx, scores, ...
        criticProtocol, maximumBannedEdges)
block = dataset.blocks(blockIdx);
sourceBlock = sourceDataset.blocks(block.sourceBlockIndex);
targetIndices = find(block.candidateV2ValueTarget);
targetMasks = block.candidateCrossMasks(:, targetIndices);
targetHashes = block.candidateGraphSha256(targetIndices);
[proposalMasks, proposalHashes, failures] = ...
    projectProposalBank(sourceBlock, ...
        block.receiverIndices, block.senderIndices, ...
        scores, criticProtocol, maximumBannedEdges);
row = makeCoverageRow(block.seed, block.currentTime, ...
    targetMasks, targetHashes, proposalMasks, ...
    proposalHashes, failures);
end

function [masks, hashes, failures] = ...
        projectProposalBank( ...
            projectionBlock, receiverIndices, senderIndices, ...
            scores, protocol, maximumBannedEdges)
masks = false(size(scores, 1), 0);
hashes = cell(1, 0);
failures = 0;
for headIdx = 1:size(scores, 2)
    headScores = scores(:, headIdx);
    allowed = true(size(headScores));
    [mask, hash, valid] = projectOne( ...
        projectionBlock, receiverIndices, senderIndices, ...
        headScores, allowed, protocol);
    if ~valid
        failures = failures + 1;
        continue
    end
    [masks, hashes] = appendUnique( ...
        masks, hashes, mask, hash);
    if maximumBannedEdges >= 1
        for selectedIdx = reshape(find(mask), 1, [])
            alternativeAllowed = true(size(headScores));
            alternativeAllowed(selectedIdx) = false;
            [alternativeMask, alternativeHash, ...
                alternativeValid] = projectOne( ...
                    projectionBlock, receiverIndices, ...
                    senderIndices, headScores, ...
                    alternativeAllowed, protocol);
            if ~alternativeValid
                failures = failures + 1;
                continue
            end
            [masks, hashes] = appendUnique( ...
                masks, hashes, alternativeMask, ...
                alternativeHash);
        end
    end
end
end

function [mask, graphHash, valid] = projectOne( ...
        block, receiverIndices, senderIndices, ...
        scores, allowedMask, protocol)
options = struct( ...
    'minimumCurrentCrossEdges', ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'maximumCurrentCrossEdges', ...
        protocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'currentAllowedExampleMask', allowedMask);
try
    [adjacency, details] = ...
        replayRollingSafeRolloutProjection( ...
            block, scores, protocol.sourceWeight, inf, options);
    valid = details.nominalProjectionFeasible && ...
        ~details.repairProjectionAttempted && ...
        ~details.repairTriggered && ...
        ~details.payloadEmergencyUsed && ...
        details.realizedCrossCount == ...
            protocol.valueProposalHeadExactCurrentCrossEdgeCount && ...
        ~details.truthUsed;
catch
    adjacency = false(numel(block.groupIds));
    details = struct();
    valid = false;
end
if ~valid
    mask = false(size(scores));
    graphHash = '';
    return
end
keys = sub2ind(size(adjacency), ...
    receiverIndices, senderIndices);
mask = reshape(logical(adjacency(keys)), [], 1);
graphHash = computeTextSha256(sprintf( ...
    '%d,', details.selectedSourcesByReceiver));
end

function [masks, hashes] = appendUnique( ...
        masks, hashes, mask, graphHash)
if any(strcmp(hashes, graphHash))
    return
end
masks(:, end + 1) = mask;
hashes{end + 1} = graphHash;
end

function row = makeCoverageRow( ...
        seed, currentTime, targetMasks, targetHashes, ...
        proposalMasks, proposalHashes, failures)
captured = ismember(targetHashes, proposalHashes);
bestF1 = 0;
for proposalIdx = 1:size(proposalMasks, 2)
    for targetIdx = 1:size(targetMasks, 2)
        intersection = nnz( ...
            proposalMasks(:, proposalIdx) & ...
            targetMasks(:, targetIdx));
        denominator = nnz(proposalMasks(:, proposalIdx)) + ...
            nnz(targetMasks(:, targetIdx));
        bestF1 = max(bestF1, ...
            2 * intersection / max(denominator, 1));
    end
end
row = emptyCoverageRow();
row.seed = seed;
row.currentTime = currentTime;
row.targetCount = numel(targetHashes);
row.capturedTargetCount = nnz(captured);
row.stateCaptured = any(captured);
row.bestTargetEdgeF1 = bestF1;
row.distinctProposalCount = numel(proposalHashes);
row.projectionFailureCount = failures;
row.proposalGraphSha256 = proposalHashes;
row.capturedTargetMask = captured;
end

function candidate = summarizeCandidate( ...
        config, rows, featureNames)
metrics = summarizeRows(rows);
candidate = emptyCandidate();
