function validateDatasets( ...
        expanded, valueDataset, sourceDataset, ...
        protocol, criticProtocol)
if ~strcmp(expanded.contractVersion, ...
        protocol.datasetContractVersion) || ...
        ~isequal(expanded.seeds, protocol.datasetSeeds) || ...
        ~isequal(expanded.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        expanded.totalTeacherTargetCount ~= ...
            protocol.expectedTotalTargetCount || ...
        expanded.behaviorTruthUsed || ...
        expanded.featuresUseTruth || ...
        expanded.teacherTargetsUseFutureOutcome || ...
        ~expanded.teacherTargetsUseTruth || ...
        ~strcmp(valueDataset.contractVersion, ...
            criticProtocol. ...
                privilegedValueTargetDatasetContractVersion) || ...
        ~strcmp(sourceDataset.contractVersion, ...
            criticProtocol.datasetContractVersion)
    error('Expanded proposal inputs violate frozen contracts.');
end
for blockIdx = 1:numel(expanded.blocks)
    block = expanded.blocks(blockIdx);
    teacher = expanded.teacherBlocks(blockIdx);
    if block.actionTruthUsed || block.labelTruthUsed || ...
            block.featureMetadata.truthUsed || ...
            block.featureMetadata.groundTruthUsed || ...
            block.featureMetadata.futureOutcomeUsed || ...
            ~teacher.truthUsed || teacher.futureOutcomeUsed || ...
            any(sum(teacher.targetCrossMasks, 1) ~= 3)
        error('Expanded proposal block violates truth/safety contract.');
    end
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

