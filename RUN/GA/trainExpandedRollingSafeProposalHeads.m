    candidate.(fields{fieldIdx}) = metrics.(fields{fieldIdx});
end
end

function metrics = summarizeRows(rows)
if isempty(rows)
    error('Proposal coverage summary has no rows.');
end
seeds = unique([rows.seed], 'stable');
seedCapture = zeros(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    mask = [rows.seed] == seeds(seedIdx);
    seedCapture(seedIdx) = mean([rows(mask).stateCaptured]);
end
metrics = struct();
metrics.rows = rows;
metrics.stateCount = numel(rows);
metrics.capturedStateCount = nnz([rows.stateCaptured]);
metrics.stateCaptureFraction = ...
    metrics.capturedStateCount / metrics.stateCount;
metrics.minimumSeedCaptureFraction = min(seedCapture);
metrics.meanSeedCaptureFraction = mean(seedCapture);
metrics.targetGraphCount = sum([rows.targetCount]);
metrics.capturedTargetGraphCount = ...
    sum([rows.capturedTargetCount]);
metrics.targetGraphRecallFraction = ...
    metrics.capturedTargetGraphCount / ...
    metrics.targetGraphCount;
metrics.meanBestTargetEdgeF1 = ...
    mean([rows.bestTargetEdgeF1]);
metrics.meanDistinctProposalCount = ...
    mean([rows.distinctProposalCount]);
metrics.projectionFailureCount = ...
    sum([rows.projectionFailureCount]);
end

