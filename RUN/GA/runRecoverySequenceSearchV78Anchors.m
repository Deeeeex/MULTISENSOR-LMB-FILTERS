    'useCandidateByRound', false(1, 0), ...
    'rounds', repmat(emptyRoundRecord(), 1, 0), ...
    'centeredEnergyByRound', zeros(1, 0), ...
    'commonEnergyByRound', zeros(1, 0), ...
    'rieSafeByRound', false(1, 0), ...
    'maximumRieByRound', zeros(1, 0), ...
    'rieEligible', false, ...
    'centeredMonotoneNonincreasing', false, ...
    'peakCenteredExpansionFactor', NaN, ...
    'terminalCenteredFactor', NaN, ...
    'candidateRecoveryRoundCount', NaN);
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'directSafeFormationIds', zeros(1, 0), ...
    'historical', struct(), ...
    'aligned', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
