function [reportPath, result] = runRecoverySequenceSearchV78Anchors(options)
% RUNRECOVERYSEQUENCESEARCHV78ANCHORS Four-schedule recovery headroom.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRecoverySequenceSearchV78Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('RecoverySequenceV78:DirtySource', ...
        'The V78 sequence search requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    referenceTrajectory = buildReferenceTrajectory( ...
        state, referenceAdjacency, referenceWeights, protocol);
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, historicalApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            alignedTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    historical = searchSchedules( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, historicalAdjacency, historicalWeights, ...
        historicalApplied, protocol);
    aligned = searchSchedules( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, alignedAdjacency, alignedWeights, ...
        alignedApplied, protocol);
    records(caseIdx) = makeCaseRecord( ...
        state, caseInfo, historical, aligned);
    fprintf('V78 %s t=%d historical=%s aligned=%s\n', ...
        caseInfo.presetName, caseInfo.currentTime, ...
        formatSearch(historical), formatSearch(aligned));
end

result = struct();
result.contractVersion = ...
    'recovery-sequence-search-v78-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.anyHistoricalMonotoneSchedule = ...
    any(arrayfun(@(record) ...
        record.historical.anyMonotoneEligibleSchedule, records));
result.anyAlignedMonotoneSchedule = ...
    any(arrayfun(@(record) ...
        record.aligned.anyMonotoneEligibleSchedule, records));
result.allHistoricalHaveMonotoneSchedule = ...
    all(arrayfun(@(record) ...
        record.historical.anyMonotoneEligibleSchedule, records));
result.allAlignedHaveMonotoneSchedule = ...
    all(arrayfun(@(record) ...
        record.aligned.anyMonotoneEligibleSchedule, records));
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RECOVERY_SEQUENCE_SEARCH_V78_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'RECOVERY_SEQUENCE_SEARCH_V78_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V78 recovery sequence search: %s\n', reportPath);
end

function trajectory = buildReferenceTrajectory( ...
        state, adjacency, weights, protocol)
posteriors = state.context.localPosteriorBySensor;
trajectory = cell(1, protocol.totalFusionRounds);
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
for roundIdx = 1:protocol.totalFusionRounds
    [posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
        posteriors, adjacency, weights, state.context.model, ...
        state.context.commConfig, state.currentTime, ...
        protocol.fusionConfig, fusionOptions);
    trajectory{roundIdx} = posteriors;
end
end

function search = searchSchedules( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, candidateAdjacency, candidateWeights, ...
        appliedTriples, protocol)
scheduleCount = numel(protocol.scheduleNames);
records = repmat(emptyScheduleRecord(), 1, scheduleCount);
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
modeOptions = struct( ...
    'covarianceRegularization', protocol.covarianceRegularization);
rieOptions = struct( ...
    'conditionalEnergyLimit', protocol.recoveryCandidateRieLimit, ...
    'covarianceRegularization', protocol.covarianceRegularization);

initialPosteriors = state.context.localPosteriorBySensor;
[round1RieSafe, round1MaximumRie] = scoreRie( ...
    initialPosteriors, state, appliedTriples, rieOptions);
round1Posteriors = fuseRound(initialPosteriors, ...
    candidateAdjacency, candidateWeights, state, ...
    protocol, fusionOptions);
round1 = scoreModes(referenceTrajectory{1}, ...
    round1Posteriors, state.context.model, modeOptions, 1);

round2Posteriors = cell(1, 2);
round2Records = repmat(emptyRoundRecord(), 1, 2);
round2RieSafe = true(1, 2);
round2MaximumRie = zeros(1, 2);
round2Posteriors{1} = fuseRound(round1Posteriors, ...
    referenceAdjacency, referenceWeights, state, ...
    protocol, fusionOptions);
round2Records(1) = scoreModes(referenceTrajectory{2}, ...
    round2Posteriors{1}, state.context.model, modeOptions, 2);
[round2RieSafe(2), round2MaximumRie(2)] = scoreRie( ...
    round1Posteriors, state, appliedTriples, rieOptions);
round2Posteriors{2} = fuseRound(round1Posteriors, ...
    candidateAdjacency, candidateWeights, state, ...
    protocol, fusionOptions);
round2Records(2) = scoreModes(referenceTrajectory{2}, ...
    round2Posteriors{2}, state.context.model, modeOptions, 2);

for scheduleIdx = 1:scheduleCount
    useCandidate = protocol.candidateUseBySchedule(scheduleIdx, :);
    round2Branch = 1 + double(useCandidate(2));
    rieSafeByRound = [round1RieSafe, ...
        round2RieSafe(round2Branch), true];
    maximumRieByRound = [round1MaximumRie, ...
        round2MaximumRie(round2Branch), 0];
    if useCandidate(3)
        [rieSafeByRound(3), maximumRieByRound(3)] = scoreRie( ...
            round2Posteriors{round2Branch}, state, ...
            appliedTriples, rieOptions);
        adjacency = candidateAdjacency;
        weights = candidateWeights;
    else
        adjacency = referenceAdjacency;
        weights = referenceWeights;
    end
    round3Posteriors = fuseRound( ...
        round2Posteriors{round2Branch}, adjacency, weights, ...
        state, protocol, fusionOptions);
    round3 = scoreModes(referenceTrajectory{3}, ...
        round3Posteriors, state.context.model, modeOptions, 3);
    rounds = [round1, round2Records(round2Branch), round3];
    centered = [rounds.centeredEnergy];
    record = emptyScheduleRecord();
    record.name = protocol.scheduleNames{scheduleIdx};
    record.useCandidateByRound = useCandidate;
    record.rounds = rounds;
    record.centeredEnergyByRound = centered;
    record.commonEnergyByRound = [rounds.commonEnergy];
    record.rieSafeByRound = rieSafeByRound;
    record.maximumRieByRound = maximumRieByRound;
    record.rieEligible = all(rieSafeByRound(useCandidate));
    record.centeredMonotoneNonincreasing = ...
        all(diff(centered) <= 1e-12);
    record.peakCenteredExpansionFactor = ...
        max(centered(2:end)) / max(centered(1), eps);
    record.terminalCenteredFactor = ...
        centered(end) / max(centered(1), eps);
    record.candidateRecoveryRoundCount = nnz(useCandidate(2:end));
    records(scheduleIdx) = record;
end

eligible = find([records.rieEligible]);
if isempty(eligible)
    error('RecoverySequenceV78:NoEligibleSchedule', ...
        'No schedule preserves the frozen replacement risk.');
end
score = [[records(eligible).peakCenteredExpansionFactor]', ...
    [records(eligible).terminalCenteredFactor]', ...
    [records(eligible).candidateRecoveryRoundCount]', ...
    eligible'];
[~, order] = sortrows(score, [1, 2, 3, 4]);
selectedIdx = eligible(order(1));
search = struct();
search.appliedSlotTriples = appliedTriples;
search.schedules = records;
search.selectedScheduleIndex = selectedIdx;
search.selectedScheduleName = records(selectedIdx).name;
search.selectedPeakCenteredExpansionFactor = ...
    records(selectedIdx).peakCenteredExpansionFactor;
search.selectedTerminalCenteredFactor = ...
    records(selectedIdx).terminalCenteredFactor;
search.selectedCenteredMonotoneNonincreasing = ...
    records(selectedIdx).centeredMonotoneNonincreasing;
search.anyMonotoneEligibleSchedule = any( ...
    [records(eligible).centeredMonotoneNonincreasing]);
search.eligibleScheduleCount = numel(eligible);
search.truthUsed = false;
search.futureMeasurementUsed = false;
end

function [safe, maximumEnergy] = scoreRie( ...
        posteriors, state, appliedTriples, options)
rie = computeReplacementInnovationEnergyV75( ...
    posteriors, appliedTriples, state.groupIds, ...
    state.context.model, state.context.commConfig, ...
    state.currentTime, options);
safe = rie.allFormationsSafe;
maximumEnergy = max( ...
    [rie.formationRecords.maximumConditionalEnergy]);
end

function posteriors = fuseRound( ...
        posteriors, adjacency, weights, state, protocol, options)
[posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
    posteriors, adjacency, weights, state.context.model, ...
    state.context.commConfig, state.currentTime, ...
    protocol.fusionConfig, options);
end

function round = scoreModes( ...
        referencePosteriors, candidatePosteriors, ...
        model, options, roundIdx)
modes = computeLmbArmPerturbationModesV77( ...
    referencePosteriors, candidatePosteriors, model, options);
round = makeRoundRecord(roundIdx, modes.aggregate);
end

function round = makeRoundRecord(roundIdx, aggregate)
round = emptyRoundRecord();
round.roundIndex = roundIdx;
fields = fieldnames(aggregate);
for idx = 1:numel(fields)
    fieldName = fields{idx};
    if isfield(round, fieldName)
        round.(fieldName) = aggregate.(fieldName);
    end
end
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('RecoverySequenceV78:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('RecoverySequenceV78:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        nnz(adjacency) ~= nnz(referenceAdjacency)
    error('RecoverySequenceV78:BudgetDrift', ...
        'Candidate replacement changed row sums or message count.');
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function record = makeCaseRecord(state, caseInfo, historical, aligned)
record = emptyCaseRecord();
record.presetName = state.presetName;
record.seed = state.seed;
record.currentTime = state.currentTime;
record.directSafeFormationIds = ...
    reshape(caseInfo.directSafeFormationIds, 1, []);
record.historical = historical;
record.aligned = aligned;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('RecoverySequenceV78:WriteFailed', ...
        'Could not create the V78 result report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V78 recovery-sequence search\n\n');
fprintf(fid, '- Schedules: `CRR / CRC / CCR / CCC`\n');
fprintf(fid, '- Candidate RIE rechecked before every C round: `1`\n');
fprintf(fid, '- Tracking outcome label available: `0`\n\n');
for caseRecord = result.records
    fprintf(fid, '## %s / t=%d\n\n', ...
        caseRecord.presetName, caseRecord.currentTime);
    fprintf(fid, '- Direct-safe formations: `%s`\n\n', ...
        mat2str(caseRecord.directSafeFormationIds));
    writeSearchTable(fid, 'Historical exact V71/V72 route', ...
        caseRecord.historical);
    writeSearchTable(fid, 'Prospective exact V73 route', ...
        caseRecord.aligned);
end
fprintf(fid, '## Summary\n\n');
fprintf(fid, '- Any / all historical cases have a monotone schedule: `%d / %d`\n', ...
    result.anyHistoricalMonotoneSchedule, ...
    result.allHistoricalHaveMonotoneSchedule);
fprintf(fid, '- Any / all aligned cases have a monotone schedule: `%d / %d`\n', ...
    result.anyAlignedMonotoneSchedule, ...
    result.allAlignedHaveMonotoneSchedule);
fprintf(fid, '- Route executed / tracking outcome read: `0 / 0`\n');
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function writeSearchTable(fid, title, search)
fprintf(fid, '### %s\n\n', title);
fprintf(fid, '- Applied slot triples: `%s`\n\n', ...
    mat2str(search.appliedSlotTriples));
fprintf(fid, ['| Schedule | Centered energy by round | Common energy by round | ', ...
    'Peak factor | Terminal factor | RIE eligible | Monotone |\n']);
fprintf(fid, '|:--|:--|:--|--:|--:|:--:|:--:|\n');
for schedule = search.schedules
    fprintf(fid, '| %s | `%s` | `%s` | %.6f | %.6f | %d | %d |\n', ...
        schedule.name, mat2str(schedule.centeredEnergyByRound, 6), ...
        mat2str(schedule.commonEnergyByRound, 6), ...
        schedule.peakCenteredExpansionFactor, ...
        schedule.terminalCenteredFactor, schedule.rieEligible, ...
        schedule.centeredMonotoneNonincreasing);
end
fprintf(fid, ['\n- Selected schedule: `%s`\n', ...
    '- Selected peak / terminal factor: `%.6f / %.6f`\n', ...
    '- Selected monotone / any monotone eligible: `%d / %d`\n\n'], ...
    search.selectedScheduleName, ...
    search.selectedPeakCenteredExpansionFactor, ...
    search.selectedTerminalCenteredFactor, ...
    search.selectedCenteredMonotoneNonincreasing, ...
    search.anyMonotoneEligibleSchedule);
end

function text = formatSearch(search)
text = sprintf('%s peak=%.3f terminal=%.3f monotone=%d', ...
    search.selectedScheduleName, ...
    search.selectedPeakCenteredExpansionFactor, ...
    search.selectedTerminalCenteredFactor, ...
    search.anyMonotoneEligibleSchedule);
end

