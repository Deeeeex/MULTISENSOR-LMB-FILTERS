function [reportPath, result] = ...
    auditLearnedFormationTreeProxy(datasetPaths, options)
% AUDITLEARNEDFORMATIONTREEPROXY Screen a learned safe graph projection.
%
% A ridge edge-value model is fitted only on declared training blocks. At
% inference it reads truth-free directed-action features and projects the
% scores onto a receiver-complete routing map whose cross-formation edges
% form a rooted spanning tree. Privileged labels are read only afterward to
% audit the selected tree. This is a snapshot development audit, not
% closed-loop or held-out tracking evidence.

if nargin < 1 || isempty(datasetPaths)
    datasetPaths = arrayfun(@(seed) fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'cache', ...
        sprintf( ...
            'directed_teacher_v2_m24_hard_seed%d_t75.mat', seed)), ...
        [7, 11, 17], 'UniformOutput', false);
end
if nargin < 2 || isempty(options)
    options = struct();
end
datasetPaths = normalizePaths(datasetPaths);
trainIndices = reshape(getField( ...
    options, 'trainDatasetIndices', 1:max(numel(datasetPaths) - 1, 1)), ...
    1, []);
validationIndices = reshape(getField( ...
    options, 'validationDatasetIndices', ...
    setdiff(1:numel(datasetPaths), trainIndices)), 1, []);
if isempty(validationIndices)
    validationIndices = trainIndices;
end
assertValidSplit(trainIndices, validationIndices, numel(datasetPaths));

sourceWeight = getField(options, 'sourceWeight', 0.50);
baselineMode = lower(strrep(char(getField( ...
    options, 'baselineMode', 'round-robin-balanced')), '_', '-'));
baselinePhase = max(1, round(getField(options, 'baselinePhase', 1)));
anchorTime = round(getField(options, 'anchorTime', 1));
featureContextMode = lower(strrep(char(getField( ...
    options, 'featureContextMode', 'raw')), '_', '-'));
modelFamily = lower(strrep(char(getField( ...
    options, 'modelFamily', 'ridge')), '_', '-'));
switch modelFamily
    case 'ridge'
        hyperparameterGrid = reshape(getField( ...
            options, 'ridgeLambdaGrid', ...
            [0.01, 0.1, 1, 10, 100]), 1, []);
    case 'knn'
        hyperparameterGrid = reshape(getField( ...
            options, 'neighborCountGrid', ...
            [5, 10, 20, 40, 80]), 1, []);
        hyperparameterGrid = unique( ...
            max(1, round(hyperparameterGrid)), 'stable');
    otherwise
        error('Unknown learned formation-tree model family: %s', ...
            modelFamily);
end
minimumGain = getField( ...
    options, 'minimumAggregateRiskImprovement', 0.05);
maximumHarmfulFraction = getField( ...
    options, 'maximumHarmfulEdgeFraction', 0);
maximumByteDeviation = getField( ...
    options, 'maximumAttemptedByteDeviation', 0.02);

blocks = loadBlocks( ...
    datasetPaths, sourceWeight, baselineMode, ...
    baselinePhase, anchorTime, featureContextMode);
featureNames = blocks(1).featureNames;
excludedNames = reshape(getField(options, 'excludedFeatureNames', { ...
    'same_formation', 'source_weight', ...
    'source_weight_squared', 'backbone_action'}), 1, []);
includedNames = reshape(getField( ...
    options, 'includedFeatureNames', {}), 1, []);
if isempty(includedNames)
    featureMask = ~ismember(featureNames, excludedNames);
else
    missingNames = setdiff(includedNames, featureNames);
    if ~isempty(missingNames)
        error('Unknown included formation-tree feature: %s', ...
            missingNames{1});
    end
    featureMask = ismember(featureNames, includedNames);
end
if ~any(featureMask)
    error('The learned formation-tree model has no retained features.');
end

candidates = repmat(emptyCandidate(numel(trainIndices)), ...
    1, numel(hyperparameterGrid));
crossValidationSeeds = unique( ...
    [blocks(trainIndices).seed], 'stable');
for hyperparameterIdx = 1:numel(hyperparameterGrid)
    hyperparameter = hyperparameterGrid(hyperparameterIdx);
    foldMetrics = repmat(emptyMetrics(), 1, numel(trainIndices));
    metricCursor = 0;
    for foldIdx = 1:numel(crossValidationSeeds)
        heldoutIndices = trainIndices( ...
            [blocks(trainIndices).seed] == ...
                crossValidationSeeds(foldIdx));
        fitIndices = setdiff( ...
            trainIndices, heldoutIndices, 'stable');
        if isempty(fitIndices)
            fitIndices = trainIndices;
        end
        foldModel = fitModel( ...
            blocks, fitIndices, featureMask, ...
            modelFamily, hyperparameter);
        for heldoutIdx = heldoutIndices
            metricCursor = metricCursor + 1;
            foldMetrics(metricCursor) = evaluateBlock( ...
                blocks(heldoutIdx), foldModel);
        end
    end
    candidates(hyperparameterIdx) = summarizeCandidate( ...
        modelFamily, hyperparameter, foldMetrics);
end
[~, order] = sortrows(vertcat(candidates.selectionKey));
candidates = candidates(order);
selectedHyperparameter = candidates(1).hyperparameter;
model = fitModel( ...
    blocks, trainIndices, featureMask, ...
    modelFamily, selectedHyperparameter);

metrics = repmat(emptyMetrics(), 1, numel(blocks));
for blockIdx = 1:numel(blocks)
    metrics(blockIdx) = evaluateBlock(blocks(blockIdx), model);
end
trainingGatePassed = splitPassesGate( ...
    metrics(trainIndices), minimumGain, ...
    maximumHarmfulFraction, maximumByteDeviation);
validationGatePassed = splitPassesGate( ...
    metrics(validationIndices), minimumGain, ...
    maximumHarmfulFraction, maximumByteDeviation);
allObservedBlocksPassGate = splitPassesGate( ...
    metrics, minimumGain, ...
    maximumHarmfulFraction, maximumByteDeviation);

result = struct();
result.generatedAt = datestr(now, 31);
result.datasetPaths = datasetPaths;
result.trainDatasetIndices = trainIndices;
result.validationDatasetIndices = validationIndices;
result.crossValidationSeeds = crossValidationSeeds;
result.sourceWeight = sourceWeight;
result.baselineMode = baselineMode;
result.baselinePhase = baselinePhase;
result.anchorTime = anchorTime;
result.featureContextMode = featureContextMode;
result.modelFamily = modelFamily;
result.hyperparameterGrid = hyperparameterGrid;
result.excludedFeatureNames = excludedNames;
result.includedFeatureNames = includedNames;
result.retainedFeatureNames = featureNames(featureMask);
result.crossValidationCandidates = candidates;
result.model = model;
result.metrics = metrics;
result.trainingGatePassed = trainingGatePassed;
result.validationGatePassed = validationGatePassed;
result.allObservedBlocksPassGate = allObservedBlocksPassGate;
result.minimumAggregateRiskImprovement = minimumGain;
result.maximumHarmfulEdgeFraction = maximumHarmfulFraction;
result.maximumAttemptedByteDeviation = maximumByteDeviation;
result.evidenceBoundary = [ ...
    'The edge model uses privileged labels only on declared training ', ...
    'blocks. Projection-time features are truth-free. Validation labels ', ...
    'do not select the model. This is not closed-loop evidence.'];

reportPath = '';
if getField(options, 'writeReport', true)
    outputDirectory = getField(options, 'outputDirectory', ...
        fullfile('RUN', 'GA', 'dynamic_topology'));
    if ~exist(outputDirectory, 'dir')
        mkdir(outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    reportPath = fullfile(outputDirectory, [ ...
        'LEARNED_FORMATION_TREE_PROXY_AUDIT_', timestamp, '.md']);
    writeReport(reportPath, result, blocks);
    result.reportPath = reportPath;
    fprintf('Report: %s\n', reportPath);
end
end

function blocks = loadBlocks( ...
        paths, sourceWeight, baselineMode, baselinePhase, ...
        anchorTime, featureContextMode)
blocks = repmat(struct(), 1, numel(paths));
expectedNames = {};
for blockIdx = 1:numel(paths)
    loaded = load(paths{blockIdx}, ...
        'actionFeatures', 'actionFeatureNames', ...
        'actionFeatureMetadata', 'teacherDetails', ...
        'datasetMetadata');
    validateDataset(loaded, paths{blockIdx});
    featureNames = reshape(loaded.actionFeatureNames, 1, []);
    if isempty(expectedNames)
        expectedNames = featureNames;
    elseif ~isequal(featureNames, expectedNames)
        error('Formation-tree feature contracts differ.');
    end
    weightGrid = reshape( ...
        loaded.actionFeatureMetadata.sourceWeightGrid, 1, []);
    [weightDifference, weightIdx] = min(abs(weightGrid - sourceWeight));
    if weightDifference > 1e-12
        error('Requested source weight is absent from %s.', ...
            paths{blockIdx});
    end
    metadata = loaded.datasetMetadata;
    groupIds = reshape( ...
        metadata.scenarioConfigSnapshot.sensorGroupIds, 1, []);
    nodeCount = numel(groupIds);
    baselineSender = registeredSenderByReceiver( ...
        groupIds, metadata.snapshotTime, anchorTime, ...
        baselinePhase, baselineMode);
    expectedGain = ...
        loaded.teacherDetails.firstStepExpectedGainByWeight;
    baselineGain = nan(1, nodeCount);
    for receiverIdx = 1:nodeCount
        baselineGain(receiverIdx) = expectedGain( ...
            receiverIdx, baselineSender(receiverIdx), weightIdx);
    end
    nodeRisk = reshape( ...
        loaded.teacherDetails.nodeRiskBefore, 1, []);
    [rawX, y, rawResidual, receiverIndices, senderIndices] = ...
        unpackCrossFormationExamples( ...
            loaded.actionFeatures, expectedGain, weightIdx, ...
            groupIds, baselineGain, nodeRisk);
    [X, contextualFeatureNames] = addGraphContextFeatures( ...
        rawX, featureNames, receiverIndices, senderIndices, ...
        groupIds, featureContextMode);
    blocks(blockIdx).path = paths{blockIdx};
    blocks(blockIdx).presetName = metadata.presetName;
    blocks(blockIdx).seed = metadata.seed;
    blocks(blockIdx).snapshotTime = metadata.snapshotTime;
    blocks(blockIdx).featureNames = contextualFeatureNames;
    blocks(blockIdx).X = X;
    blocks(blockIdx).y = y;
    blocks(blockIdx).rawResidual = rawResidual;
    blocks(blockIdx).receiverIndices = receiverIndices;
    blocks(blockIdx).senderIndices = senderIndices;
    blocks(blockIdx).groupIds = groupIds;
    blocks(blockIdx).baselineSender = baselineSender;
    blocks(blockIdx).baselineGain = baselineGain;
    blocks(blockIdx).baselineRisk = nodeRisk - baselineGain;
    blocks(blockIdx).nodePayloadBytes = reshape( ...
        loaded.teacherDetails.nodePayloadBytes, 1, []);
end
end

function [X, names] = addGraphContextFeatures( ...
        rawX, rawNames, receiverIndices, senderIndices, ...
        groupIds, mode)
rawNames = reshape(rawNames, 1, []);
switch mode
    case 'raw'
        X = rawX;
        names = rawNames;
    case 'graph-context'
        receiverRelative = normalizeWithinGroups( ...
            rawX, receiverIndices);
        receiverGroups = groupIds(receiverIndices);
        senderGroups = groupIds(senderIndices);
        groupCount = numel(unique(groupIds, 'stable'));
        formationPair = receiverGroups + ...
            groupCount * (senderGroups - 1);
        formationPairRelative = normalizeWithinGroups( ...
            rawX, formationPair);
        blockRelative = normalizeWithinGroups( ...
            rawX, ones(size(receiverIndices)));
        X = [ ...
            rawX, receiverRelative, ...
            formationPairRelative, blockRelative];
        names = [ ...
            rawNames, prefixNames(rawNames, 'receiver_rel_'), ...
            prefixNames(rawNames, 'formation_pair_rel_'), ...
            prefixNames(rawNames, 'block_rel_')];
    otherwise
        error('Unknown graph-context feature mode: %s', mode);
end
end

function normalized = normalizeWithinGroups(X, groupKeys)
normalized = zeros(size(X));
keys = unique(reshape(groupKeys, 1, []), 'stable');
for key = keys
    mask = reshape(groupKeys == key, [], 1);
    groupX = X(mask, :);
    location = mean(groupX, 1);
    scale = std(groupX, 0, 1);
    scale(~isfinite(scale) | scale <= eps) = 1;
    normalized(mask, :) = bsxfun(@rdivide, ...
        bsxfun(@minus, groupX, location), scale);
end
end

function names = prefixNames(rawNames, prefix)
names = cell(size(rawNames));
for nameIdx = 1:numel(rawNames)
    names{nameIdx} = [prefix, rawNames{nameIdx}];
end
end

function validateDataset(loaded, path)
required = {'actionFeatures', 'actionFeatureNames', ...
    'actionFeatureMetadata', 'teacherDetails', 'datasetMetadata'};
if ~all(isfield(loaded, required))
    error('Incomplete learned formation-tree dataset: %s', path);
end
metadata = loaded.datasetMetadata;
if ~isfield(metadata, 'featuresUseTruth') || ...
        metadata.featuresUseTruth || ...
        ~isfield(metadata, 'truthUsedForLabelsOnly') || ...
        ~metadata.truthUsedForLabelsOnly || ...
        ~isfield(metadata, 'teacherLabelVersion') || ...
        ~strcmp(metadata.teacherLabelVersion, ...
            'joint-action-bernoulli-risk-v3-directed-physical') || ...
        ~isfield(metadata, 'physicalAdjacencyConvention') || ...
        ~strcmp(metadata.physicalAdjacencyConvention, ...
            'receiver-row-sender-column-directed') || ...
        ~isfield(loaded.actionFeatureMetadata, 'truthUsed') || ...
        loaded.actionFeatureMetadata.truthUsed
    error('Learned formation-tree dataset contract is invalid: %s', path);
end
end

function [X, y, rawResidual, receiverIndices, senderIndices] = ...
        unpackCrossFormationExamples( ...
            features, expectedGain, weightIdx, groupIds, ...
            baselineGain, nodeRisk)
featureCount = size(features, 4);
X = zeros(0, featureCount);
y = zeros(0, 1);
rawResidual = zeros(0, 1);
receiverIndices = zeros(0, 1);
senderIndices = zeros(0, 1);
nodeCount = numel(groupIds);
for receiverIdx = 1:nodeCount
    for senderIdx = 1:nodeCount
        if groupIds(receiverIdx) == groupIds(senderIdx)
            continue;
        end
        row = reshape( ...
            features(receiverIdx, senderIdx, weightIdx, :), 1, []);
        candidateGain = expectedGain(receiverIdx, senderIdx, weightIdx);
        if any(~isfinite(row)) || ~isfinite(candidateGain)
            continue;
        end
        residual = candidateGain - baselineGain(receiverIdx);
        X(end + 1, :) = row; %#ok<AGROW>
        y(end + 1, 1) = residual / ...
            max(nodeRisk(receiverIdx), eps); %#ok<AGROW>
        rawResidual(end + 1, 1) = residual; %#ok<AGROW>
        receiverIndices(end + 1, 1) = receiverIdx; %#ok<AGROW>
        senderIndices(end + 1, 1) = senderIdx; %#ok<AGROW>
    end
end
end

function model = fitModel( ...
        blocks, indices, featureMask, modelFamily, hyperparameter)
X = vertcat(blocks(indices).X);
y = vertcat(blocks(indices).y);
X = X(:, featureMask);
featureMean = mean(X, 1);
featureScale = std(X, 0, 1);
featureScale(~isfinite(featureScale) | featureScale <= eps) = 1;
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, featureMean), featureScale);
model = struct( ...
    'kind', '', ...
    'family', modelFamily, ...
    'featureMask', featureMask, ...
    'featureMean', featureMean, ...
    'featureScale', featureScale, ...
    'hyperparameter', hyperparameter, ...
    'trainingBlockIndices', indices);
switch modelFamily
    case 'ridge'
        intercept = mean(y);
        coefficient = (Z' * Z + ...
            hyperparameter * eye(size(Z, 2))) \ ...
            (Z' * (y - intercept));
        model.kind = 'ridge-formation-tree-edge-value-v1';
        model.intercept = intercept;
        model.coefficient = coefficient;
        model.ridgeLambda = hyperparameter;
    case 'knn'
        model.kind = 'knn-formation-tree-edge-value-v1';
        model.neighborCount = min( ...
            max(1, round(hyperparameter)), size(Z, 1));
        model.trainingZ = Z;
        model.trainingTarget = y;
    otherwise
        error('Unknown formation-tree fit family: %s', modelFamily);
end
end

function metrics = evaluateBlock(block, model)
X = block.X(:, model.featureMask);
prediction = predictModel(model, X);
selection = selectRootedFormationTreeEdges( ...
    block.groupIds, block.receiverIndices, ...
    block.senderIndices, prediction);
oracleSelection = selectRootedFormationTreeEdges( ...
    block.groupIds, block.receiverIndices, ...
    block.senderIndices, block.rawResidual);
selectedActual = block.y(selection.exampleIndices);
selectedRawResidual = ...
    block.rawResidual(selection.exampleIndices);
oracleActual = block.y(oracleSelection.exampleIndices);
oracleRawResidual = ...
    block.rawResidual(oracleSelection.exampleIndices);
selectedSender = block.baselineSender;
selectedSender(selection.receiverIndices) = selection.senderIndices;
baselineBytes = sum( ...
    block.nodePayloadBytes(block.baselineSender));
selectedBytes = sum(block.nodePayloadBytes(selectedSender));

metrics = emptyMetrics();
metrics.aggregateRiskImprovement = ...
    sum(selectedRawResidual) / max(sum(block.baselineRisk), eps);
metrics.oracleAggregateRiskImprovement = ...
    sum(oracleRawResidual) / max(sum(block.baselineRisk), eps);
metrics.minimumSelectedNormalizedResidual = min(selectedActual);
metrics.oracleMinimumSelectedNormalizedResidual = min(oracleActual);
metrics.harmfulEdgeFraction = mean(selectedActual < -1e-12);
metrics.positiveEdgeFraction = mean(selectedActual > 1e-12);
metrics.attemptedByteRatio = selectedBytes / max(baselineBytes, eps);
metrics.rootFormation = selection.rootFormation;
metrics.oracleRootFormation = oracleSelection.rootFormation;
metrics.formationParents = selection.formationParents;
metrics.receiverIndices = selection.receiverIndices;
metrics.senderIndices = selection.senderIndices;
metrics.selectedPredictedResidual = ...
    prediction(selection.exampleIndices);
metrics.selectedActualNormalizedResidual = selectedActual;
metrics.formationWeakConnected = true;
metrics.formationRooted = true;
metrics.crossEdgeCount = numel(selection.exampleIndices);
metrics.maximumSourceLoad = maximumSourceLoad( ...
    selection.senderIndices, numel(block.groupIds));
end

function prediction = predictModel(model, X)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.featureMean), model.featureScale);
switch model.family
    case 'ridge'
        prediction = model.intercept + Z * model.coefficient;
    case 'knn'
        prediction = zeros(size(Z, 1), 1);
        neighborCount = min( ...
            model.neighborCount, size(model.trainingZ, 1));
        for rowIdx = 1:size(Z, 1)
            difference = bsxfun(@minus, ...
                model.trainingZ, Z(rowIdx, :));
            distanceSquared = sum(difference.^2, 2);
            [~, order] = sort(distanceSquared, 'ascend');
            prediction(rowIdx) = mean( ...
                model.trainingTarget(order(1:neighborCount)));
        end
    otherwise
        error('Unknown formation-tree prediction family: %s', ...
            model.family);
end
end

function candidate = summarizeCandidate( ...
        modelFamily, hyperparameter, metrics)
gains = [metrics.aggregateRiskImprovement];
harmful = [metrics.harmfulEdgeFraction];
minimumResidual = [metrics.minimumSelectedNormalizedResidual];
candidate = emptyCandidate(numel(metrics));
candidate.modelFamily = modelFamily;
candidate.hyperparameter = hyperparameter;
candidate.foldMetrics = metrics;
candidate.minimumCrossValidatedGain = min(gains);
candidate.meanCrossValidatedGain = mean(gains);
candidate.maximumCrossValidatedHarmfulFraction = max(harmful);
candidate.minimumCrossValidatedSelectedResidual = min(minimumResidual);
candidate.selectionKey = [ ...
    candidate.maximumCrossValidatedHarmfulFraction > 0, ...
    candidate.maximumCrossValidatedHarmfulFraction, ...
    candidate.minimumCrossValidatedGain <= 0, ...
    -candidate.minimumCrossValidatedGain, ...
    -candidate.meanCrossValidatedGain, ...
    -candidate.minimumCrossValidatedSelectedResidual, ...
    hyperparameter];
end

function passed = splitPassesGate( ...
        metrics, minimumGain, maximumHarmful, maximumByteDeviation)
passed = all( ...
    [metrics.aggregateRiskImprovement] >= minimumGain & ...
    [metrics.harmfulEdgeFraction] <= maximumHarmful & ...
    [metrics.minimumSelectedNormalizedResidual] >= -1e-12 & ...
    abs([metrics.attemptedByteRatio] - 1) <= ...
        maximumByteDeviation & ...
    [metrics.formationWeakConnected] >= 1 & ...
    [metrics.formationRooted] >= 1);
end

function candidate = emptyCandidate(metricCount)
candidate = struct( ...
    'modelFamily', '', ...
    'hyperparameter', NaN, ...
    'foldMetrics', repmat(emptyMetrics(), 1, metricCount), ...
    'minimumCrossValidatedGain', NaN, ...
    'meanCrossValidatedGain', NaN, ...
    'maximumCrossValidatedHarmfulFraction', NaN, ...
    'minimumCrossValidatedSelectedResidual', NaN, ...
    'selectionKey', nan(1, 7));
end

function metrics = emptyMetrics()
metrics = struct( ...
    'aggregateRiskImprovement', NaN, ...
    'oracleAggregateRiskImprovement', NaN, ...
    'minimumSelectedNormalizedResidual', NaN, ...
    'oracleMinimumSelectedNormalizedResidual', NaN, ...
    'harmfulEdgeFraction', NaN, ...
    'positiveEdgeFraction', NaN, ...
    'attemptedByteRatio', NaN, ...
    'rootFormation', NaN, ...
    'oracleRootFormation', NaN, ...
    'formationParents', [], ...
    'receiverIndices', [], ...
    'senderIndices', [], ...
    'selectedPredictedResidual', [], ...
    'selectedActualNormalizedResidual', [], ...
    'formationWeakConnected', false, ...
    'formationRooted', false, ...
    'crossEdgeCount', 0, ...
    'maximumSourceLoad', NaN);
end

function senders = registeredSenderByReceiver( ...
        groupIds, currentTime, anchorTime, phase, mode)
senders = nan(1, numel(groupIds));
groups = unique(groupIds, 'stable');
for groupIdx = 1:numel(groups)
    members = reshape(find(groupIds == groups(groupIdx)), 1, []);
    groupSize = numel(members);
    if groupSize < 2
        error('Every formation needs at least two sensors.');
    end
    switch mode
        case 'round-robin-balanced'
            shift = 1 + mod( ...
                currentTime - anchorTime + phase - 1, ...
                groupSize - 1);
            senders(members) = ...
                circshift(members, [0, -shift]);
        case 'fixed-index-star'
            senders(members(1)) = members(2);
            senders(members(2:end)) = members(1);
        otherwise
            error('Unknown learned-proxy baseline mode: %s', mode);
    end
end
end

function value = maximumSourceLoad(senders, nodeCount)
counts = accumarray( ...
    reshape(senders, [], 1), 1, [nodeCount, 1]);
value = max(counts);
end

function writeReport(path, result, blocks)
fid = fopen(path, 'w');
if fid < 0
    error('Unable to write learned formation-tree report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Learned formation-tree proxy audit\n\n');
fprintf(fid, '- Generated: %s\n', result.generatedAt);
fprintf(fid, '- Source weight: %.2f\n', result.sourceWeight);
fprintf(fid, '- Baseline mode: `%s`\n', result.baselineMode);
fprintf(fid, '- Feature context: `%s`\n', ...
    result.featureContextMode);
fprintf(fid, '- Baseline phase: %d\n', result.baselinePhase);
fprintf(fid, '- Model family: `%s`\n', result.modelFamily);
fprintf(fid, '- Selected hyperparameter: %.6g\n', ...
    result.model.hyperparameter);
fprintf(fid, '- Training blocks: `%s`\n', ...
    mat2str(result.trainDatasetIndices));
fprintf(fid, '- Leave-one-seed-out CV seeds: `%s`\n', ...
    mat2str(result.crossValidationSeeds));
fprintf(fid, '- Validation blocks: `%s`\n', ...
    mat2str(result.validationDatasetIndices));
fprintf(fid, '- Training gate passed: `%d`\n', ...
    result.trainingGatePassed);
fprintf(fid, '- Validation gate passed: `%d`\n', ...
    result.validationGatePassed);
fprintf(fid, '- All observed blocks pass: `%d`\n', ...
    result.allObservedBlocksPassGate);
fprintf(fid, '- Evidence boundary: %s\n', result.evidenceBoundary);

fprintf(fid, '\n## Cross-validated model selection\n\n');
fprintf(fid, ['| Hyperparameter | Worst fold gain | Mean fold gain | ', ...
    'Worst harmful | Worst selected residual |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|\n');
for candidateIdx = 1:numel(result.crossValidationCandidates)
    candidate = result.crossValidationCandidates(candidateIdx);
    fprintf(fid, '| %.6g | %.4f | %.4f | %.4f | %.4f |\n', ...
        candidate.hyperparameter, ...
        candidate.minimumCrossValidatedGain, ...
        candidate.meanCrossValidatedGain, ...
        candidate.maximumCrossValidatedHarmfulFraction, ...
        candidate.minimumCrossValidatedSelectedResidual);
end

fprintf(fid, '\n## Frozen-model projection audit\n\n');
fprintf(fid, ['| Block | Split | Risk improvement vs baseline | ', ...
    'Privileged projected-tree gain | Worst selected edge | Harmful edges | ', ...
    'Bytes ratio | Root | ', ...
    'Formation parents |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|--:|--:|--:|:--|\n');
for blockIdx = 1:numel(blocks)
    split = 'unused';
    if any(result.trainDatasetIndices == blockIdx)
        split = 'train';
    elseif any(result.validationDatasetIndices == blockIdx)
        split = 'validation';
    end
    metrics = result.metrics(blockIdx);
    fprintf(fid, ['| %s seed %d t=%d | %s | %.4f | %.4f | ', ...
        '%.4f | %.4f | %.4f | %d | `%s` |\n'], ...
        blocks(blockIdx).presetName, blocks(blockIdx).seed, ...
        blocks(blockIdx).snapshotTime, split, ...
        metrics.aggregateRiskImprovement, ...
        metrics.oracleAggregateRiskImprovement, ...
        metrics.minimumSelectedNormalizedResidual, ...
        metrics.harmfulEdgeFraction, ...
        metrics.attemptedByteRatio, ...
        metrics.rootFormation, ...
        mat2str(metrics.formationParents));
end

fprintf(fid, '\n## Selected sensor edges\n\n');
for blockIdx = 1:numel(blocks)
    metrics = result.metrics(blockIdx);
    fprintf(fid, '- %s seed %d: receivers `%s`, senders `%s`, ', ...
        blocks(blockIdx).presetName, blocks(blockIdx).seed, ...
        mat2str(metrics.receiverIndices), ...
        mat2str(metrics.senderIndices));
    fprintf(fid, 'predicted `%s`, actual `%s`\n', ...
        mat2str(metrics.selectedPredictedResidual, 5), ...
        mat2str(metrics.selectedActualNormalizedResidual, 5));
end
end

function paths = normalizePaths(paths)
if ischar(paths)
    paths = {paths};
end
paths = reshape(paths, 1, []);
for pathIdx = 1:numel(paths)
    paths{pathIdx} = char(paths{pathIdx});
    if exist(paths{pathIdx}, 'file') ~= 2
        error('Missing learned formation-tree dataset: %s', ...
            paths{pathIdx});
    end
end
end

function assertValidSplit(trainIndices, validationIndices, count)
if isempty(trainIndices) || ...
        any(trainIndices < 1 | trainIndices > count) || ...
        any(validationIndices < 1 | validationIndices > count) || ...
        numel(unique(trainIndices)) ~= numel(trainIndices) || ...
        numel(unique(validationIndices)) ~= numel(validationIndices) || ...
        ~isempty(intersect(trainIndices, validationIndices))
    error('Training and validation block indices must be valid and disjoint.');
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
