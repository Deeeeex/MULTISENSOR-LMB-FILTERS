    metrics = result.metrics(blockIdx);
    fprintf(fid, '- %s seed %d: receivers `%s`, senders `%s`, ', ...
        blocks(blockIdx).presetName, blocks(blockIdx).seed, ...
        mat2str(metrics.receiverIndices), ...
        mat2str(metrics.senderIndices));
    fprintf(fid, 'predicted `%s`, actual `%s`\n', ...
        mat2str(metrics.selectedPredictedResidual, 5), ...
        mat2str(metrics.selectedActualNormalizedResidual, 5));
end
end

function paths = normalizePaths(paths)
if ischar(paths)
    paths = {paths};
end
paths = reshape(paths, 1, []);
for pathIdx = 1:numel(paths)
    paths{pathIdx} = char(paths{pathIdx});
    if exist(paths{pathIdx}, 'file') ~= 2
        error('Missing learned formation-tree dataset: %s', ...
            paths{pathIdx});
    end
end
end

function [trainIndices, validationIndices] = resolveDatasetSplit( ...
        blocks, requestedTrainIndices, requestedValidationIndices)
count = numel(blocks);
allIndices = 1:count;
if isempty(requestedTrainIndices) && ...
        isempty(requestedValidationIndices)
    seeds = unique([blocks.seed], 'stable');
    if numel(seeds) < 3
        error([ ...
            'The default learned formation-tree split requires at ', ...
            'least three distinct seeds: two for model-selection CV ', ...
            'and one for validation.']);
    end
    validationSeed = seeds(end);
    validationIndices = find([blocks.seed] == validationSeed);
    trainIndices = setdiff( ...
        allIndices, validationIndices, 'stable');
elseif isempty(requestedTrainIndices)
    validationIndices = requestedValidationIndices;
    trainIndices = setdiff( ...
        allIndices, validationIndices, 'stable');
elseif isempty(requestedValidationIndices)
    trainIndices = requestedTrainIndices;
    validationIndices = setdiff( ...
        allIndices, trainIndices, 'stable');
else
    trainIndices = requestedTrainIndices;
    validationIndices = requestedValidationIndices;
end
trainIndices = reshape(trainIndices, 1, []);
validationIndices = reshape(validationIndices, 1, []);
end

function assertValidSplit( ...
        trainIndices, validationIndices, count, seeds)
if isempty(trainIndices) || ...
        isempty(validationIndices) || ...
        any(trainIndices < 1 | trainIndices > count) || ...
        any(validationIndices < 1 | validationIndices > count) || ...
        numel(unique(trainIndices)) ~= numel(trainIndices) || ...
        numel(unique(validationIndices)) ~= numel(validationIndices) || ...
        ~isempty(intersect(trainIndices, validationIndices))
    error('Training and validation block indices must be valid and disjoint.');
end
trainSeeds = unique(seeds(trainIndices));
validationSeeds = unique(seeds(validationIndices));
if ~isempty(intersect(trainSeeds, validationSeeds))
    error([ ...
        'Training and validation must be disjoint by complete seed, ', ...
        'not only by block index.']);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
