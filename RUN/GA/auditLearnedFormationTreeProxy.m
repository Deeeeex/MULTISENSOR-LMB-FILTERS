    result.trainingGatePassed);
fprintf(fid, '- Validation gate passed: `%d`\n', ...
    result.validationGatePassed);
fprintf(fid, '- All observed blocks pass: `%d`\n', ...
    result.allObservedBlocksPassGate);
fprintf(fid, ['- Training minimum-gain threshold attainable by exact ', ...
    'projector: `%d`\n'], ...
    result.trainingOracleGateAttainable);
fprintf(fid, ['- Validation minimum-gain threshold attainable by exact ', ...
    'projector: ', ...
    '`%d`\n'], result.validationOracleGateAttainable);
fprintf(fid, ['- Minimum-gain threshold attainable on every observed block: ', ...
    '`%d`\n'], result.allObservedOracleGateAttainable);
