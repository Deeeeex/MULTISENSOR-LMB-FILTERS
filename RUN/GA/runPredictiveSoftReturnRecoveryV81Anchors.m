function [reportPath, result] = ...
    runPredictiveSoftReturnRecoveryV81Anchors(options)
% RUNPREDICTIVESOFTRETURNRECOVERYV81ANCHORS Two-round action-bank MPC.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getPredictiveSoftReturnRecoveryV81Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('PredictiveSoftReturnV81:DirtySource', ...
        'The V81 predictive replay requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    homotopyProtocol = getReliabilityBalancedHomotopyV80Protocol();
    homotopy = buildReliabilityBalancedWeightHomotopyV80( ...
        state.context, referenceAdjacency, referenceWeights, ...
        homotopyProtocol.alphaGrid, struct( ...
            'sinkhornTolerance', protocol.sinkhornTolerance, ...
            'sinkhornMaximumIterations', ...
                protocol.sinkhornMaximumIterations, ...
            'effectiveWeightTolerance', ...
                protocol.effectiveWeightTolerance));
    referenceTrajectory = buildReferenceTrajectory( ...
        state, referenceAdjacency, referenceWeights, protocol);
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, historicalApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            alignedTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    historical = runPredictiveRecovery( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, historicalAdjacency, historicalWeights, ...
        historicalApplied, homotopy, protocol);
    aligned = runPredictiveRecovery( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, alignedAdjacency, alignedWeights, ...
        alignedApplied, homotopy, protocol);
    record = emptyCaseRecord();
    record.presetName = state.presetName;
    record.seed = state.seed;
    record.currentTime = state.currentTime;
    record.nodeCount = numel(state.groupIds);
    record.formationCount = numel(unique( ...
        state.groupIds, 'stable'));
    record.referenceCenteredSpectralNorm = ...
        homotopy.referenceCenteredSpectralNorm;
    record.balancedCenteredSpectralNorm = ...
        homotopy.balancedCenteredSpectralNorm;
    record.historical = historical;
    record.aligned = aligned;
    records(caseIdx) = record;
    fprintf('V81 %s t=%d historical=%s aligned=%s\n', ...
        state.presetName, state.currentTime, ...
        formatRecovery(historical), formatRecovery(aligned));
end

allHistoricalMonotone = true;
allAlignedMonotone = true;
for caseIdx = 1:numel(records)
    allHistoricalMonotone = allHistoricalMonotone && ...
        records(caseIdx).historical.centeredMonotoneNonincreasing;
    allAlignedMonotone = allAlignedMonotone && ...
        records(caseIdx).aligned.centeredMonotoneNonincreasing;
end
result = struct();
result.contractVersion = ...
    'predictive-soft-return-recovery-v81-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allHistoricalCenteredMonotone = allHistoricalMonotone;
result.allAlignedCenteredMonotone = allAlignedMonotone;
result.sourceMechanismGatePassed = ...
    allHistoricalMonotone && allAlignedMonotone;
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'PREDICTIVE_SOFT_RETURN_RECOVERY_V81_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'PREDICTIVE_SOFT_RETURN_RECOVERY_V81_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V81 predictive soft-return recovery: %s\n', reportPath);
end

function trajectory = buildReferenceTrajectory( ...
        state, adjacency, weights, protocol)
options = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
posteriors = state.context.localPosteriorBySensor;
trajectory = cell(1, protocol.totalFusionRounds);
for roundIdx = 1:protocol.totalFusionRounds
    posteriors = fuseRound(posteriors, adjacency, weights, ...
        state, protocol, options);
    trajectory{roundIdx} = posteriors;
end
end

function recovery = runPredictiveRecovery( ...
        state, referenceTrajectory, referenceAdjacency, ...
        referenceWeights, candidateAdjacency, candidateWeights, ...
        appliedTriples, homotopy, protocol)
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
modeOptions = struct( ...
    'covarianceRegularization', protocol.covarianceRegularization);
rieOptions = struct( ...
    'conditionalEnergyLimit', protocol.recoveryCandidateRieLimit, ...
    'covarianceRegularization', protocol.covarianceRegularization);
initial = state.context.localPosteriorBySensor;
rie = computeReplacementInnovationEnergyV75( ...
    initial, appliedTriples, state.groupIds, ...
    state.context.model, state.context.commConfig, ...
    state.currentTime, rieOptions);
current = fuseRound(initial, candidateAdjacency, candidateWeights, ...
    state, protocol, fusionOptions);
round1Modes = scoreModes(referenceTrajectory{1}, current, ...
    state.context.model, modeOptions);
actionBank = buildActionBank( ...
    referenceAdjacency, referenceWeights, ...
    appliedTriples, homotopy, protocol);
rounds = repmat(emptyRecoveryRound(), 1, ...
    protocol.predictiveRecoveryRounds);
for recoveryIdx = 1:protocol.predictiveRecoveryRounds
    referenceRoundIdx = recoveryIdx + 1;
    [rounds(recoveryIdx), current] = selectAction( ...
        current, referenceTrajectory{referenceRoundIdx}, ...
        actionBank, state, protocol, fusionOptions, modeOptions);
end
centered = [round1Modes.centeredEnergy, ...
    [rounds.selectedCenteredEnergy]];
recovery = struct();
recovery.appliedSlotTriples = appliedTriples;
recovery.maximumRound1Rie = max( ...
    [rie.formationRecords.maximumConditionalEnergy]);
recovery.round1RieSafe = rie.allFormationsSafe;
recovery.round1Modes = round1Modes;
recovery.actionBank = stripWeights(actionBank);
recovery.recoveryRounds = rounds;
recovery.centeredEnergyByRound = centered;
recovery.existenceCenteredEnergyByRound = [ ...
    round1Modes.existenceCenteredEnergy, ...
    [rounds.selectedExistenceCenteredEnergy]];
recovery.spatialCenteredEnergyByRound = [ ...
    round1Modes.spatialCenteredEnergy, ...
    [rounds.selectedSpatialCenteredEnergy]];
recovery.commonEnergyByRound = [ ...
    round1Modes.commonEnergy, ...
    [rounds.selectedCommonEnergy]];
recovery.selectedActionNames = ...
    {rounds.selectedActionName};
recovery.centeredMonotoneNonincreasing = ...
    all(diff(centered) <= 1e-12);
recovery.peakCenteredExpansionFactor = ...
    max(centered(2:end)) / max(centered(1), eps);
recovery.terminalCenteredFactor = ...
    centered(end) / max(centered(1), eps);
recovery.truthUsed = false;
recovery.futureMeasurementUsed = false;
end

function bank = buildActionBank( ...
        referenceAdjacency, referenceWeights, ...
        appliedTriples, homotopy, protocol)
actionCount = 1 + numel(protocol.globalBalancingAlphas) + ...
    numel(protocol.localSoftReturnBetas);
bank = repmat(emptyAction(), 1, actionCount);
cursor = 1;
bank(cursor) = makeAction( ...
    protocol.referenceActionName, 'reference', 0, ...
    referenceAdjacency, referenceWeights, referenceWeights);
for alpha = protocol.globalBalancingAlphas
    pointIdx = find(abs([homotopy.points.alpha] - alpha) <= 1e-12, 1);
    if isempty(pointIdx)
        error('PredictiveSoftReturnV81:MissingGlobalAction', ...
            'A frozen global alpha is absent from the V80 homotopy.');
    end
    cursor = cursor + 1;
    name = sprintf('G%02d', round(100 * alpha));
    bank(cursor) = makeAction( ...
        name, 'global-balance', alpha, ...
        referenceAdjacency, ...
        homotopy.points(pointIdx).fusionWeights, ...
        referenceWeights);
end
for beta = protocol.localSoftReturnBetas
    soft = buildInterventionLocalSoftReturnWeightsV81( ...
        referenceAdjacency, referenceWeights, appliedTriples, beta);
    cursor = cursor + 1;
    name = sprintf('L%02d', round(100 * beta));
    bank(cursor) = makeAction( ...
        name, 'local-soft-return', beta, ...
        soft.adjacency, soft.fusionWeights, referenceWeights);
end
if cursor ~= actionCount || ...
        any([bank.messageCount] ~= nnz(referenceAdjacency))
    error('PredictiveSoftReturnV81:InvalidActionBank', ...
        'The frozen recovery action bank violates message parity.');
end
end

function action = makeAction( ...
        name, type, parameter, adjacency, weights, referenceWeights)
action = emptyAction();
action.name = name;
action.type = type;
action.parameter = parameter;
action.adjacency = logical(adjacency);
action.fusionWeights = weights;
action.interventionMagnitude = ...
    norm(weights - referenceWeights, 'fro');
action.messageCount = nnz(adjacency);
end

function [round, selectedPosteriors] = selectAction( ...
        currentPosteriors, referencePosteriors, actionBank, ...
        state, protocol, fusionOptions, modeOptions)
responses = repmat(emptyActionResponse(), 1, numel(actionBank));
outputs = cell(1, numel(actionBank));
for actionIdx = 1:numel(actionBank)
    action = actionBank(actionIdx);
    outputs{actionIdx} = fuseRound( ...
        currentPosteriors, action.adjacency, ...
        action.fusionWeights, state, protocol, fusionOptions);
    modes = scoreModes(referencePosteriors, outputs{actionIdx}, ...
        state.context.model, modeOptions);
    response = emptyActionResponse();
    response.actionIndex = actionIdx;
    response.actionName = action.name;
    response.actionType = action.type;
    response.parameter = action.parameter;
    response.interventionMagnitude = ...
        action.interventionMagnitude;
    response.centeredEnergy = modes.centeredEnergy;
    response.existenceCenteredEnergy = ...
        modes.existenceCenteredEnergy;
    response.spatialCenteredEnergy = ...
        modes.spatialCenteredEnergy;
    response.commonEnergy = modes.commonEnergy;
    responses(actionIdx) = response;
end
score = [[responses.centeredEnergy]', ...
    [responses.interventionMagnitude]', ...
    [responses.actionIndex]'];
[~, order] = sortrows(score, [1, 2, 3]);
selectedIdx = order(1);
selected = responses(selectedIdx);
selectedPosteriors = outputs{selectedIdx};
round = emptyRecoveryRound();
round.responses = responses;
round.selectedActionIndex = selectedIdx;
round.selectedActionName = selected.actionName;
round.selectedActionType = selected.actionType;
round.selectedParameter = selected.parameter;
round.selectedCenteredEnergy = selected.centeredEnergy;
round.selectedExistenceCenteredEnergy = ...
    selected.existenceCenteredEnergy;
round.selectedSpatialCenteredEnergy = ...
    selected.spatialCenteredEnergy;
round.selectedCommonEnergy = selected.commonEnergy;
end

function aggregate = scoreModes( ...
        referencePosteriors, candidatePosteriors, model, options)
modes = computeLmbArmPerturbationModesV77( ...
    referencePosteriors, candidatePosteriors, model, options);
aggregate = modes.aggregate;
end

function posteriors = fuseRound( ...
        posteriors, adjacency, weights, state, protocol, options)
[posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
    posteriors, adjacency, weights, state.context.model, ...
    state.context.commConfig, state.currentTime, ...
    protocol.fusionConfig, options);
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('PredictiveSoftReturnV81:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('PredictiveSoftReturnV81:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        nnz(adjacency) ~= nnz(referenceAdjacency)
    error('PredictiveSoftReturnV81:BudgetDrift', ...
        'Candidate replacement changed row sums or message count.');
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function stripped = stripWeights(bank)
stripped = repmat(struct( ...
    'name', '', 'type', '', 'parameter', NaN, ...
    'interventionMagnitude', NaN, 'messageCount', 0), ...
    1, numel(bank));
for idx = 1:numel(bank)
    stripped(idx).name = bank(idx).name;
    stripped(idx).type = bank(idx).type;
    stripped(idx).parameter = bank(idx).parameter;
    stripped(idx).interventionMagnitude = ...
        bank(idx).interventionMagnitude;
    stripped(idx).messageCount = bank(idx).messageCount;
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('PredictiveSoftReturnV81:WriteFailed', ...
        'Cannot open V81 report for writing.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V81 predictive soft-return recovery\n\n');
fprintf(fid, '- Source mechanism gate passed: `%d`\n', ...
    result.sourceMechanismGatePassed);
fprintf(fid, '- Tracking outcome available: `0`\n\n');
for caseIdx = 1:numel(result.records)
    record = result.records(caseIdx);
    fprintf(fid, '## %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    fprintf(fid, '- Nodes / formations: `%d / %d`\n', ...
        record.nodeCount, record.formationCount);
    fprintf(fid, ['- Reference / balanced centered norm: ', ...
        '`%.6f / %.6f`\n\n'], ...
        record.referenceCenteredSpectralNorm, ...
        record.balancedCenteredSpectralNorm);
    writeRecovery(fid, 'Historical exact V71/V72 route', ...
        record.historical);
    writeRecovery(fid, 'Prospective exact V73 route', ...
        record.aligned);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeRecovery(fid, titleText, recovery)
fprintf(fid, '### %s\n\n', titleText);
fprintf(fid, '- Applied slot triples: `%s`\n', ...
    mat2str(recovery.appliedSlotTriples));
fprintf(fid, '- Round-1 RIE safe / maximum: `%d / %.6f`\n', ...
    recovery.round1RieSafe, recovery.maximumRound1Rie);
fprintf(fid, '- Selected recovery actions: `%s`\n', ...
    strjoin(recovery.selectedActionNames, ' -> '));
fprintf(fid, '- Centered energy by round: `%s`\n', ...
    formatVector(recovery.centeredEnergyByRound));
fprintf(fid, '- Existence-centered by round: `%s`\n', ...
    formatVector(recovery.existenceCenteredEnergyByRound));
fprintf(fid, '- Spatial-centered by round: `%s`\n', ...
    formatVector(recovery.spatialCenteredEnergyByRound));
fprintf(fid, ['- Peak / terminal factor / monotone: ', ...
    '`%.6f / %.6f / %d`\n\n'], ...
    recovery.peakCenteredExpansionFactor, ...
    recovery.terminalCenteredFactor, ...
    recovery.centeredMonotoneNonincreasing);
for roundIdx = 1:numel(recovery.recoveryRounds)
    round = recovery.recoveryRounds(roundIdx);
    fprintf(fid, '#### Recovery round %d\n\n', roundIdx);
    fprintf(fid, ['| Action | Type | Parameter | Centered | ', ...
        'Existence | Spatial | Common |\n']);
    fprintf(fid, '|:--|:--|--:|--:|--:|--:|--:|\n');
    for responseIdx = 1:numel(round.responses)
        response = round.responses(responseIdx);
        fprintf(fid, '| %s | %s | %.3f | %.8g | %.8g | %.8g | %.8g |\n', ...
            response.actionName, response.actionType, ...
            response.parameter, response.centeredEnergy, ...
            response.existenceCenteredEnergy, ...
            response.spatialCenteredEnergy, ...
            response.commonEnergy);
    end
    fprintf(fid, '\n- Selected: `%s`\n\n', ...
        round.selectedActionName);
end
end

function text = formatRecovery(recovery)
text = sprintf('%s energy=%s monotone=%d', ...
    strjoin(recovery.selectedActionNames, '-'), ...
    formatVector(recovery.centeredEnergyByRound), ...
    recovery.centeredMonotoneNonincreasing);
end

function text = formatVector(values)
text = ['[', strtrim(sprintf('%.8g ', values)), ']'];
end

