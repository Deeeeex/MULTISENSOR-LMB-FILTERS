function [reportPath, result] = ...
    runTrackingAlignedX36RiskCoverageHeadroomV64(options)
% RUNTRACKINGALIGNEDX36RISKCOVERAGEHEADROOMV64 Minimal 80%-coverage gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getTrackingAlignedX36RiskCoverageHeadroomV64Protocol();
currentTime = getField(options, ...
    'currentTime', protocol.primaryAnchorTime);
if ~isscalar(currentTime) || ~ismember(currentTime, protocol.anchorTimes)
    error('TrackingAlignedV64:InvalidAnchor', ...
        'V64 currentTime must be a registered X36 anchor.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('TrackingAlignedV64:DirtySource', ...
        'V64 risk-coverage headroom requires a clean source checkout.');
end

outputRoot = getField(options, 'outputRoot', ...
    fullfile(protocol.outputRoot, sprintf('t%d', currentTime)));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', protocol.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v64-risk-coverage-headroom', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', ...
            protocol.positiveSupportThreshold, ...
        'bankVariant', 'risk-coverage-v64', ...
        'riskCoverageTargetFraction', ...
            protocol.riskCoverageTargetFraction), ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    protocol.presetName, protocol.seed, currentTime, screenOptions);

records = screen.records;
referenceIdx = screen.referenceSubsetIndex;
candidateMask = true(1, numel(records));
candidateMask(referenceIdx) = false;
strictMask = candidateMask & ...
    [records.posteriorProxyAllowed] & ...
    [records.selectedB3Passed] & ...
    [records.minimumFormationGainPercent] >= ...
        protocol.minimumFormationGainPercent - 1e-12 & ...
    [records.worstGainPercent] >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 & ...
    [records.consensusGainPercent] >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 & ...
    [records.terminalConsensusGainPercent] >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 & ...
    [records.attemptedByteSavingPercent] >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12;
candidateIndices = find(strictMask);
if isempty(candidateIndices)
    bestIdx = referenceIdx;
    bestGain = 0;
else
    [bestGain, localIdx] = max( ...
        [records(candidateIndices).meanGainPercent]);
    bestIdx = candidateIndices(localIdx);
end

result = struct();
result.contractVersion = ...
    'tracking-aligned-x36-risk-coverage-v64-result-v1';
result.protocol = protocol;
result.currentTime = currentTime;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.screenReportPath = screenReportPath;
result.screenMatPath = screen.matPath;
result.actionCount = numel(records);
result.strictCandidateCount = nnz(strictMask);
result.bestStrictActionName = records(bestIdx).actionName;
result.bestStrictMeanGainPercent = bestGain;
result.bestStrictWorstGainPercent = records(bestIdx).worstGainPercent;
result.bestStrictMinimumFormationGainPercent = ...
    records(bestIdx).minimumFormationGainPercent;
result.bestStrictWindowConsensusGainPercent = ...
    records(bestIdx).consensusGainPercent;
result.bestStrictTerminalConsensusGainPercent = ...
    records(bestIdx).terminalConsensusGainPercent;
result.bestStrictAttemptedByteSavingPercent = ...
    records(bestIdx).attemptedByteSavingPercent;
result.strongHeadroomGatePassed = bestGain >= ...
    protocol.minimumMeanGainPercent - 1e-12;
result.observableFormationRanking = ...
    screen.bank.rankedFormationIds;
result.observableFormationScores = ...
    screen.bank.rankedFormationScores;
result.riskCoverageTargetFraction = ...
    screen.bank.riskCoverageTargetFraction;
result.riskCoverageAchievedFraction = ...
    screen.bank.riskCoverageAchievedFraction;
result.riskCoverageFormationIds = ...
    screen.bank.riskCoverageFormationIds;
result.modelTrainingAuthorized = false;
result.openedDevelopmentEvidenceOnly = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, sprintf( ...
    'TRACKING_ALIGNED_X36_RISK_COVERAGE_V64_T%d_RESULT.mat', ...
    currentTime));
reportPath = fullfile(outputRoot, sprintf( ...
    'TRACKING_ALIGNED_X36_RISK_COVERAGE_V64_T%d_RESULT.md', ...
    currentTime));
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeResultReport(reportPath, result, records, strictMask);
fprintf('V64 X36 risk-coverage result: %s\n', reportPath);
end

function writeResultReport(path, result, records, strictMask)
fid = fopen(path, 'w');
if fid < 0
    error('TrackingAlignedV64:WriteFailed', ...
        'Could not create the V64 risk-coverage report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V64 X36 risk-coverage headroom at t=%d\n\n', ...
    result.currentTime);
fprintf(fid, '- Observable ranking: `%s`\n', ...
    mat2str(result.observableFormationRanking));
fprintf(fid, '- Observable scores: `%s`\n', ...
    mat2str(result.observableFormationScores, 6));
fprintf(fid, '- Risk target / achieved: `%.1f%% / %.1f%%`\n', ...
    100 * result.riskCoverageTargetFraction, ...
    100 * result.riskCoverageAchievedFraction);
fprintf(fid, '- Selected formations: `%s`\n\n', ...
    mat2str(result.riskCoverageFormationIds));
fprintf(fid, ['| Action | Mean tracking | Worst sensor | ', ...
    'Minimum formation | Window consensus | Terminal consensus | ', ...
    'Attempted bytes | Strict |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(records)
    record = records(idx);
    fprintf(fid, ['| `%s` | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        record.actionName, record.meanGainPercent, ...
        record.worstGainPercent, record.minimumFormationGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent, strictMask(idx));
end
fprintf(fid, '\n- Best strict action: `%s`\n', ...
    result.bestStrictActionName);
fprintf(fid, '- Best strict mean tracking gain: `%+.3f%%`\n', ...
    result.bestStrictMeanGainPercent);
fprintf(fid, '- Strong headroom gate (>= %.1f%%): `%d`\n\n', ...
    result.protocol.minimumMeanGainPercent, ...
    result.strongHeadroomGatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
