function validateInputs( ...
        dataset, valueDataset, sourceDataset, ...
        protocol, criticProtocol)
if ~strcmp(dataset.contractVersion, ...
        protocol.datasetContractVersion) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(dataset.snapshotTimes, protocol.snapshotTimes) || ...
        numel(dataset.blocks) ~= protocol.expectedBlockCount || ...
        dataset.behaviorTruthUsed || dataset.featuresUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome || ...
        ~dataset.teacherTargetsUseTruth || ...
        ~strcmp(valueDataset.contractVersion, ...
            criticProtocol. ...
                privilegedValueTargetDatasetContractVersion) || ...
        ~strcmp(sourceDataset.contractVersion, ...
            criticProtocol.datasetContractVersion)
    error('Structured proposal inputs violate frozen contracts.');
end
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    teacher = dataset.teacherBlocks(blockIdx);
    if block.actionTruthUsed || block.labelTruthUsed || ...
            block.featureMetadata.truthUsed || ...
            block.featureMetadata.groundTruthUsed || ...
            block.featureMetadata.futureOutcomeUsed || ...
            ~teacher.truthUsed || teacher.futureOutcomeUsed || ...
            any(sum(teacher.targetCrossMasks, 1) ~= ...
                criticProtocol. ...
                    valueProposalHeadExactCurrentCrossEdgeCount)
        error('Structured proposal block violates truth/safety contract.');
    end
end
end

