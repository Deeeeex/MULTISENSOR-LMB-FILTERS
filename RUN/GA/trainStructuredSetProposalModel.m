function [modelPath, result] = trainStructuredSetProposalModel(options)
% TRAINSTRUCTUREDSETPROPOSALMODEL Set-level exchangeable-head M24 proposal.
%
% Model selection uses only leave-one-seed-out current-truth graph
% distillation on truth-free behavior states. The older value-filtered
% states are evaluated only after the structured configuration is selected.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeStructuredProposalProtocol();
criticProtocol = getRollingSafeJointActionCriticProtocol();
if ~isfield(protocol, 'datasetSha256') || ...
        numel(protocol.datasetSha256) ~= 64
    error('Structured proposal dataset SHA-256 is not frozen.');
end
datasetPath = getField(options, 'datasetPath', protocol.datasetPath);
valuePath = getField(options, 'valueDatasetPath', ...
    criticProtocol.privilegedValueTargetDatasetRelativePath);
sourcePath = getField(options, 'sourceStatePath', ...
    criticProtocol.proposalSourceStateRelativePath);
validateFrozenFile(datasetPath, protocol.datasetSha256, ...
    'structured proposal dataset');
validateFrozenFile(valuePath, ...
    criticProtocol.privilegedValueTargetDatasetSha256, ...
    'legacy value-target dataset');
validateFrozenFile(sourcePath, ...
    criticProtocol.proposalSourceStateSha256, ...
    'legacy source-state dataset');
loaded = load(datasetPath, 'dataset');
valueLoaded = load(valuePath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
dataset = loaded.dataset;
valueDataset = valueLoaded.dataset;
sourceDataset = sourceLoaded.dataset;
validateInputs(dataset, valueDataset, sourceDataset, ...
    protocol, criticProtocol);

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official structured proposal training requires clean source.');
end

[featureCells, featureNames] = prepareExpandedFeatures( ...
    dataset, protocol.modelFeatureMode);
[valueFeatureCells, valueFeatureNames] = prepareValueFeatures( ...
    valueDataset, protocol.modelFeatureMode);
if ~isequal(featureNames, valueFeatureNames)
    error('Structured and legacy value feature contracts differ.');
end
scoreDirections = frozenScoreDirections( ...
    numel(featureNames), protocol);
banks = buildTrainingBanks( ...
    dataset, featureCells, scoreDirections, criticProtocol);
configs = buildConfigs(protocol);
candidates = repmat(emptyCandidate(), 1, numel(configs));

for configIdx = 1:numel(configs)
    rows = repmat(emptyCoverageRow(), 1, 0);
    for heldoutSeed = protocol.datasetSeeds
        fitSeeds = setdiff(protocol.datasetSeeds, ...
            heldoutSeed, 'stable');
        fitOptions = configs(configIdx);
        fitOptions.initializationSeed = ...
            protocol.initializationSeed + ...
            1000 * configIdx + heldoutSeed;
        foldModel = fitStructuredHeads( ...
            dataset, featureCells, banks, fitSeeds, fitOptions);
        heldoutIndices = find( ...
            [dataset.blocks.seed] == heldoutSeed);
        for blockIdx = heldoutIndices
            scores = scoreStructuredHeads( ...
                foldModel, featureCells{blockIdx});
            rows(end + 1) = evaluateExpandedBlock( ...
                dataset, blockIdx, scores, criticProtocol, ...
                protocol.maximumBannedSelectedEdges); %#ok<AGROW>
        end
    end
    candidates(configIdx) = summarizeCandidate( ...
        configs(configIdx), rows, numel(featureNames));
    candidates(configIdx).configurationIndex = configIdx;
    fprintf(['structured set h=%d lambda=%.4g: state %.1f%%, ', ...
        'min-seed %.1f%%, graph %.1f%%, F1 %.3f\n'], ...
        candidates(configIdx).hiddenWidth, ...
        candidates(configIdx).lambda, ...
        100 * candidates(configIdx).stateCaptureFraction, ...
        100 * candidates(configIdx).minimumSeedCaptureFraction, ...
        100 * candidates(configIdx).targetGraphRecallFraction, ...
        candidates(configIdx).meanBestTargetEdgeF1);
end

selectionKeys = zeros(numel(candidates), 6);
for candidateIdx = 1:numel(candidates)
    candidate = candidates(candidateIdx);
    selectionKeys(candidateIdx, :) = [ ...
        -candidate.minimumSeedCaptureFraction, ...
        -candidate.stateCaptureFraction, ...
        -candidate.targetGraphRecallFraction, ...
        -candidate.meanBestTargetEdgeF1, ...
        candidate.projectionFailureCount, ...
        candidate.complexityOrder];
end
[~, order] = sortrows(selectionKeys);
candidates = candidates(order);
selected = candidates(1);

expandedRows = repmat(emptyCoverageRow(), 1, 0);
valueRows = repmat(emptyCoverageRow(), 1, 0);
foldModels = cell(1, numel(protocol.datasetSeeds));
for seedIdx = 1:numel(protocol.datasetSeeds)
    heldoutSeed = protocol.datasetSeeds(seedIdx);
    fitOptions = candidateFitOptions(selected, ...
        protocol.initializationSeed + ...
        1000 * selected.configurationIndex + heldoutSeed);
    foldModels{seedIdx} = fitStructuredHeads( ...
        dataset, featureCells, banks, ...
        setdiff(protocol.datasetSeeds, heldoutSeed, 'stable'), ...
        fitOptions);
    expandedIndices = find( ...
        [dataset.blocks.seed] == heldoutSeed);
    for blockIdx = expandedIndices
        scores = scoreStructuredHeads( ...
            foldModels{seedIdx}, featureCells{blockIdx});
        expandedRows(end + 1) = evaluateExpandedBlock( ...
            dataset, blockIdx, scores, criticProtocol, ...
            protocol.maximumBannedSelectedEdges); %#ok<AGROW>
    end
    valueIndices = find( ...
        [valueDataset.blocks.seed] == heldoutSeed & ...
        [valueDataset.blocks.valueTargetCount] > 0);
    for blockIdx = valueIndices
        scores = scoreStructuredHeads( ...
            foldModels{seedIdx}, valueFeatureCells{blockIdx});
        valueRows(end + 1) = evaluateValueBlock( ...
            valueDataset, sourceDataset, blockIdx, scores, ...
            criticProtocol, ...
            protocol.maximumBannedSelectedEdges); %#ok<AGROW>
    end
end
expandedMetrics = summarizeRows(expandedRows);
valueMetrics = summarizeRows(valueRows);

finalOptions = candidateFitOptions( ...
    selected, protocol.initializationSeed);
model = fitStructuredHeads( ...
    dataset, featureCells, banks, ...
    protocol.datasetSeeds, finalOptions);
model.kind = 'exchangeable-set-softmax-rolling-safe-proposal-v1';
model.protocolId = protocol.id;
model.contractVersion = protocol.modelContractVersion;
model.generatedAt = datestr(now, 31);
model.featureContextMode = protocol.modelFeatureMode;
model.featureNames = featureNames;
model.headCount = protocol.modelHeadCount;
model.permutationInvariantTargetAssignment = ...
    protocol.permutationInvariantTargetAssignment;
model.loss = protocol.modelLoss;
model.topK = protocol.topK;
model.maximumBannedSelectedEdges = ...
    protocol.maximumBannedSelectedEdges;
model.sourceWeight = dataset.sourceWeight;
model.datasetPath = datasetPath;
model.datasetSha256 = protocol.datasetSha256;
model.datasetGenerationCommit = dataset.generationGitCommit;
model.valueDiagnosticPath = valuePath;
model.valueDiagnosticSha256 = ...
    criticProtocol.privilegedValueTargetDatasetSha256;
model.sourceStatePath = sourcePath;
model.sourceStateSha256 = ...
    criticProtocol.proposalSourceStateSha256;
model.trainingGitCommit = gitState.commit;
model.trainingTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
model.trainingUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
model.trainingResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
model.featuresUseTruth = false;
model.labelsUseTruth = true;
model.labelsUseFutureOutcome = false;
model.stateCollectionBehaviorUsesTruth = false;
model.selectionMetrics = selected;
model.expandedTopKMetrics = expandedMetrics;
model.legacyValueTopKMetrics = valueMetrics;
model.expandedCaptureGatePassed = ...
    expandedMetrics.stateCaptureFraction + 1e-12 >= ...
        protocol.minimumStateCaptureFraction && ...
    expandedMetrics.minimumSeedCaptureFraction + 1e-12 >= ...
        protocol.minimumSeedCaptureFraction;
model.legacyValueCaptureGatePassed = ...
    valueMetrics.stateCaptureFraction + 1e-12 >= ...
        protocol.minimumLegacyValueStateCaptureFraction;
model.proposalReturnGenerationAuthorized = ...
    model.expandedCaptureGatePassed && ...
    model.legacyValueCaptureGatePassed;
model.valueReturnEvaluatedOnExpandedStates = false;
model.criticTrainingAuthorized = false;
model.x36Authorized = false;
model.developmentOnly = true;
model.validationClaimAllowed = false;
model.evidenceBoundary = [ ...
    'LOSO selection uses unordered current-truth safe graph sets on ', ...
    'states collected by a frozen truth-free behavior policy. ', ...
    'Relative observable features use neither truth nor future ', ...
    'returns. The older value-bearing states are an external ', ...
    'architecture diagnostic only. A pass authorizes H=3 return ', ...
    'generation for the frozen M24 proposal bank, not critic ', ...
    'training, an M24 effect claim, or X36.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'models'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
modelPath = getField(options, 'modelPath', fullfile( ...
    outputDirectory, ...
    'rolling_safe_structured_set_proposal_m24_t75_t83_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'STRUCTURED_SET_PROPOSAL_LOSO_DIAGNOSTIC_M24.md'));
model.modelPath = modelPath;
model.reportPath = reportPath;
save('-mat7-binary', modelPath, 'model');

result = struct( ...
    'modelPath', modelPath, ...
    'reportPath', reportPath, ...
    'candidates', candidates, ...
    'selected', selected, ...
    'expandedTopKMetrics', expandedMetrics, ...
    'legacyValueTopKMetrics', valueMetrics, ...
    'proposalReturnGenerationAuthorized', ...
        model.proposalReturnGenerationAuthorized, ...
    'criticTrainingAuthorized', false, ...
    'x36Authorized', false);
writeReport(reportPath, model, candidates);
fprintf(['Selected structured set h=%d lambda=%.4g; top-%d ', ...
    'capture %.1f%% (min seed %.1f%%), legacy %.1f%%; ', ...
    'return generation=%d\nModel: %s\nReport: %s\n'], ...
    selected.hiddenWidth, selected.lambda, model.topK, ...
    100 * expandedMetrics.stateCaptureFraction, ...
    100 * expandedMetrics.minimumSeedCaptureFraction, ...
    100 * valueMetrics.stateCaptureFraction, ...
    model.proposalReturnGenerationAuthorized, ...
    modelPath, reportPath);
end

function configs = buildConfigs(protocol)
template = struct( ...
    'hiddenWidth', 0, 'lambda', NaN, ...
    'headCount', protocol.modelHeadCount, ...
    'epochCount', protocol.epochCount, ...
    'learningRate', protocol.learningRate, ...
    'initializationSeed', protocol.initializationSeed, ...
    'complexityOrder', NaN);
configs = repmat(template, 1, 0);
for widthIdx = 1:numel(protocol.hiddenWidthGrid)
    for lambdaIdx = 1:numel(protocol.lambdaGrid)
        config = template;
        config.hiddenWidth = protocol.hiddenWidthGrid(widthIdx);
        config.lambda = protocol.lambdaGrid(lambdaIdx);
        config.complexityOrder = 10 * widthIdx + lambdaIdx;
        configs(end + 1) = config; %#ok<AGROW>
    end
end
end

function [featureCells, names] = ...
        prepareExpandedFeatures(dataset, mode)
featureCells = cell(1, numel(dataset.blocks));
names = {};
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    [featureCells{blockIdx}, blockNames] = ...
        buildFormationTreeContextFeatures( ...
            block.features, dataset.featureNames, ...
            block.receiverIndices, block.senderIndices, ...
            reshape(block.groupIds, 1, []), mode);
    if isempty(names)
        names = reshape(blockNames, 1, []);
    elseif ~isequal(names, reshape(blockNames, 1, []))
        error('Structured proposal feature names differ by block.');
    end
end
end

function [featureCells, names] = ...
        prepareValueFeatures(dataset, mode)
featureCells = cell(1, numel(dataset.blocks));
names = {};
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    [featureCells{blockIdx}, blockNames] = ...
        buildFormationTreeContextFeatures( ...
            block.edgeFeatures, block.edgeFeatureNames, ...
            block.receiverIndices, block.senderIndices, ...
            reshape(block.groupIds, 1, []), mode);
    if isempty(names)
        names = reshape(blockNames, 1, []);
    elseif ~isequal(names, reshape(blockNames, 1, []))
        error('Legacy value feature names differ by block.');
    end
end
end

function directions = frozenScoreDirections(featureCount, protocol)
rng(protocol.negativeScoreDirectionSeed);
directions = randn( ...
    featureCount, protocol.negativeScoreDirectionCount);
norms = sqrt(sum(directions.^2, 1));
directions = bsxfun(@rdivide, directions, max(norms, eps));
end

function banks = buildTrainingBanks( ...
        dataset, featureCells, directions, criticProtocol)
banks = repmat(emptyBank(), 1, numel(dataset.blocks));
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    teacher = dataset.teacherBlocks(blockIdx);
    masks = false(size(block.features, 1), 0);
    hashes = cell(1, 0);
    targetIndices = zeros(1, teacher.targetCount);
    for targetIdx = 1:teacher.targetCount
        [masks, hashes, candidateIdx] = appendCandidate( ...
            masks, hashes, ...
            teacher.targetCrossMasks(:, targetIdx), ...
            teacher.targetGraphSha256{targetIdx});
        targetIndices(targetIdx) = candidateIdx;
    end
    behaviorHash = computeTextSha256(sprintf( ...
        '%d,', block.selectedSourcesByReceiver));
    [masks, hashes] = appendCandidate( ...
        masks, hashes, block.selectedCrossMask, behaviorHash);
    randomScores = featureCells{blockIdx} * directions;
    for directionIdx = 1:size(randomScores, 2)
        [mask, graphHash, valid] = projectOne( ...
            block, block.receiverIndices, block.senderIndices, ...
            randomScores(:, directionIdx), ...
            true(size(randomScores, 1), 1), criticProtocol);
        if valid
            [masks, hashes] = appendCandidate( ...
                masks, hashes, mask, graphHash);
        end
    end
    if numel(unique(targetIndices)) ~= teacher.targetCount || ...
            any(sum(masks, 1) ~= ...
                criticProtocol. ...
                    valueProposalHeadExactCurrentCrossEdgeCount)
        error('Structured proposal training bank is invalid.');
    end
    activeEdges = find(any(masks, 2));
    bank = emptyBank();
    bank.candidateMasks = masks;
    bank.candidateHashes = hashes;
    bank.targetCandidateIndices = targetIndices;
    bank.activeEdgeIndices = activeEdges;
    bank.activeIncidence = double(masks(activeEdges, :));
    banks(blockIdx) = bank;
end
end

function model = fitStructuredHeads( ...
        dataset, featureCells, banks, fitSeeds, options)
fitIndices = find(ismember([dataset.blocks.seed], fitSeeds));
allX = vertcat(featureCells{fitIndices});
featureMean = mean(allX, 1);
featureScale = std(allX, 0, 1);
featureScale(~isfinite(featureScale) | ...
    featureScale <= eps) = 1;
activeZ = cell(1, numel(fitIndices));
for localIdx = 1:numel(fitIndices)
    blockIdx = fitIndices(localIdx);
    indices = banks(blockIdx).activeEdgeIndices;
    activeZ{localIdx} = bsxfun(@rdivide, ...
        bsxfun(@minus, featureCells{blockIdx}(indices, :), ...
            featureMean), featureScale);
end

rng(options.initializationSeed);
inputCount = size(allX, 2);
headCount = options.headCount;
parameters = { ...
    randn(inputCount, options.hiddenWidth) / sqrt(inputCount), ...
    zeros(1, options.hiddenWidth), ...
    randn(options.hiddenWidth, headCount) / ...
        sqrt(options.hiddenWidth), ...
    zeros(1, headCount)};
firstMoment = cellfun(@zerosLike, parameters, ...
    'UniformOutput', false);
secondMoment = cellfun(@zerosLike, parameters, ...
    'UniformOutput', false);
lossHistory = nan(1, options.epochCount);
for epoch = 1:options.epochCount
    gradients = cellfun(@zerosLike, parameters, ...
        'UniformOutput', false);
    dataLoss = 0;
    supervisedCount = 0;
    for localIdx = 1:numel(fitIndices)
        blockIdx = fitIndices(localIdx);
        Z = activeZ{localIdx};
        incidence = banks(blockIdx).activeIncidence;
        hidden = tanh(bsxfun(@plus, ...
            Z * parameters{1}, parameters{2}));
        edgeScores = bsxfun(@plus, ...
            hidden * parameters{3}, parameters{4});
        [blockLoss, dEdge, ~, blockSupervisedCount] = ...
            computeExchangeableSetSoftmaxLoss( ...
                edgeScores, incidence, ...
                banks(blockIdx).targetCandidateIndices);
        dataLoss = dataLoss + blockLoss;
        supervisedCount = ...
            supervisedCount + blockSupervisedCount;
        gradients{3} = gradients{3} + hidden' * dEdge;
        gradients{4} = gradients{4} + sum(dEdge, 1);
        dHidden = dEdge * parameters{3}';
        dActivation = dHidden .* (1 - hidden.^2);
        gradients{1} = gradients{1} + Z' * dActivation;
        gradients{2} = gradients{2} + sum(dActivation, 1);
    end
    if supervisedCount < 1
        error('Structured proposal training has no supervised targets.');
    end
    for parameterIdx = 1:numel(gradients)
        gradients{parameterIdx} = ...
            gradients{parameterIdx} / supervisedCount;
    end
    gradients{1} = gradients{1} + ...
        options.lambda * parameters{1};
    gradients{3} = gradients{3} + ...
        options.lambda * parameters{3};
    regularization = 0.5 * options.lambda * ( ...
        sum(parameters{1}(:).^2) + ...
        sum(parameters{3}(:).^2));
    lossHistory(epoch) = ...
        dataLoss / supervisedCount + regularization;
    gradients = clipGradients(gradients, 10);
    for parameterIdx = 1:numel(parameters)
        firstMoment{parameterIdx} = ...
            0.9 * firstMoment{parameterIdx} + ...
            0.1 * gradients{parameterIdx};
        secondMoment{parameterIdx} = ...
            0.999 * secondMoment{parameterIdx} + ...
            0.001 * gradients{parameterIdx}.^2;
        correctedFirst = firstMoment{parameterIdx} / ...
            (1 - 0.9^epoch);
        correctedSecond = secondMoment{parameterIdx} / ...
            (1 - 0.999^epoch);
        parameters{parameterIdx} = ...
            parameters{parameterIdx} - ...
            options.learningRate * correctedFirst ./ ...
            (sqrt(correctedSecond) + 1e-8);
    end
end
if any(~isfinite(lossHistory)) || ...
        any(cellfun(@(value) any(~isfinite(value(:))), parameters))
    error('Structured proposal model produced non-finite values.');
end
model = struct( ...
    'family', 'mlp', ...
    'hiddenWeight', parameters{1}, ...
    'hiddenBias', parameters{2}, ...
    'outputWeight', parameters{3}, ...
    'outputBias', parameters{4}, ...
    'featureMean', featureMean, ...
    'featureScale', featureScale, ...
    'trainingSeeds', fitSeeds, ...
    'hiddenWidth', options.hiddenWidth, ...
    'lambda', options.lambda, ...
    'epochCount', options.epochCount, ...
    'learningRate', options.learningRate, ...
    'initializationSeed', options.initializationSeed, ...
    'trainingLossHistory', lossHistory, ...
    'finalTrainingLoss', lossHistory(end));
end

function scores = scoreStructuredHeads(model, X)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.featureMean), model.featureScale);
hidden = tanh(bsxfun(@plus, ...
    Z * model.hiddenWeight, model.hiddenBias));
scores = bsxfun(@plus, ...
    hidden * model.outputWeight, model.outputBias);
end

function row = evaluateExpandedBlock( ...
        dataset, blockIdx, scores, criticProtocol, maximumBannedEdges)
block = dataset.blocks(blockIdx);
teacher = dataset.teacherBlocks(blockIdx);
[proposalMasks, proposalHashes, failures] = projectProposalBank( ...
    block, block.receiverIndices, block.senderIndices, scores, ...
    criticProtocol, maximumBannedEdges);
row = makeCoverageRow(block.seed, block.currentTime, ...
    teacher.targetCrossMasks, teacher.targetGraphSha256, ...
    proposalMasks, proposalHashes, failures);
end

function row = evaluateValueBlock( ...
        dataset, sourceDataset, blockIdx, scores, ...
        criticProtocol, maximumBannedEdges)
block = dataset.blocks(blockIdx);
sourceBlock = sourceDataset.blocks(block.sourceBlockIndex);
targetIndices = find(block.candidateV2ValueTarget);
[proposalMasks, proposalHashes, failures] = projectProposalBank( ...
    sourceBlock, block.receiverIndices, block.senderIndices, scores, ...
    criticProtocol, maximumBannedEdges);
row = makeCoverageRow(block.seed, block.currentTime, ...
    block.candidateCrossMasks(:, targetIndices), ...
    block.candidateGraphSha256(targetIndices), ...
    proposalMasks, proposalHashes, failures);
end

function [masks, hashes, failures] = projectProposalBank( ...
        block, receiverIndices, senderIndices, scores, ...
        criticProtocol, maximumBannedEdges)
masks = false(size(scores, 1), 0);
hashes = cell(1, 0);
failures = 0;
for headIdx = 1:size(scores, 2)
    allowed = true(size(scores, 1), 1);
    [mask, graphHash, valid] = projectOne( ...
        block, receiverIndices, senderIndices, ...
        scores(:, headIdx), allowed, criticProtocol);
    if ~valid
        failures = failures + 1;
        continue
    end
    [masks, hashes] = appendCandidate( ...
        masks, hashes, mask, graphHash);
    if maximumBannedEdges >= 1
        for selectedIdx = reshape(find(mask), 1, [])
            alternativeAllowed = true(size(allowed));
            alternativeAllowed(selectedIdx) = false;
            [alternativeMask, alternativeHash, alternativeValid] = ...
                projectOne(block, receiverIndices, senderIndices, ...
                    scores(:, headIdx), alternativeAllowed, ...
                    criticProtocol);
            if alternativeValid
                [masks, hashes] = appendCandidate( ...
                    masks, hashes, alternativeMask, ...
                    alternativeHash);
            else
                failures = failures + 1;
            end
        end
    end
end
end

function [mask, graphHash, valid] = projectOne( ...
        block, receiverIndices, senderIndices, ...
        scores, allowedMask, criticProtocol)
options = struct( ...
    'minimumCurrentCrossEdges', ...
        criticProtocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'maximumCurrentCrossEdges', ...
        criticProtocol.valueProposalHeadExactCurrentCrossEdgeCount, ...
    'currentAllowedExampleMask', allowedMask);
try
    [adjacency, details] = replayRollingSafeRolloutProjection( ...
        block, scores, criticProtocol.sourceWeight, inf, options);
    valid = details.nominalProjectionFeasible && ...
        ~details.repairProjectionAttempted && ...
        ~details.repairTriggered && ...
        ~details.payloadEmergencyUsed && ...
        details.realizedCrossCount == ...
            criticProtocol. ...
                valueProposalHeadExactCurrentCrossEdgeCount && ...
        ~details.truthUsed;
catch
    adjacency = false(numel(block.groupIds));
    details = struct();
    valid = false;
end
if ~valid
    mask = false(size(scores));
    graphHash = '';
    return
end
keys = sub2ind(size(adjacency), receiverIndices, senderIndices);
mask = reshape(logical(adjacency(keys)), [], 1);
graphHash = computeTextSha256(sprintf( ...
    '%d,', details.selectedSourcesByReceiver));
end

function [masks, hashes, candidateIdx] = ...
        appendCandidate(masks, hashes, mask, graphHash)
candidateIdx = find(strcmp(hashes, graphHash), 1);
if ~isempty(candidateIdx)
    return
end
masks(:, end + 1) = logical(mask);
hashes{end + 1} = graphHash;
candidateIdx = numel(hashes);
end

function row = makeCoverageRow( ...
        seed, currentTime, targetMasks, targetHashes, ...
        proposalMasks, proposalHashes, failures)
captured = ismember(targetHashes, proposalHashes);
bestF1 = 0;
for proposalIdx = 1:size(proposalMasks, 2)
    for targetIdx = 1:size(targetMasks, 2)
        intersection = nnz( ...
            proposalMasks(:, proposalIdx) & ...
            targetMasks(:, targetIdx));
        denominator = nnz(proposalMasks(:, proposalIdx)) + ...
            nnz(targetMasks(:, targetIdx));
        bestF1 = max(bestF1, ...
            2 * intersection / max(denominator, 1));
    end
end
row = emptyCoverageRow();
row.seed = seed;
row.currentTime = currentTime;
row.targetCount = numel(targetHashes);
row.capturedTargetCount = nnz(captured);
row.stateCaptured = any(captured);
row.bestTargetEdgeF1 = bestF1;
row.distinctProposalCount = numel(proposalHashes);
row.projectionFailureCount = failures;
row.proposalGraphSha256 = proposalHashes;
row.capturedTargetMask = captured;
end

function candidate = summarizeCandidate( ...
        config, rows, featureCount)
metrics = summarizeRows(rows);
candidate = emptyCandidate();
candidate.hiddenWidth = config.hiddenWidth;
candidate.lambda = config.lambda;
candidate.headCount = config.headCount;
candidate.epochCount = config.epochCount;
candidate.learningRate = config.learningRate;
candidate.complexityOrder = config.complexityOrder;
candidate.featureCount = featureCount;
candidate.rows = rows;
fields = fieldnames(metrics);
for fieldIdx = 1:numel(fields)
    candidate.(fields{fieldIdx}) = metrics.(fields{fieldIdx});
end
end

function metrics = summarizeRows(rows)
if isempty(rows)
    error('Structured proposal coverage summary has no rows.');
end
seeds = unique([rows.seed], 'stable');
seedCapture = zeros(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    mask = [rows.seed] == seeds(seedIdx);
    seedCapture(seedIdx) = mean([rows(mask).stateCaptured]);
end
metrics = struct( ...
    'rows', rows, ...
    'stateCount', numel(rows), ...
    'capturedStateCount', nnz([rows.stateCaptured]), ...
    'stateCaptureFraction', mean([rows.stateCaptured]), ...
    'minimumSeedCaptureFraction', min(seedCapture), ...
