function [reportPath, result] = ...
    runNetworkAdditiveFormationRiskV65ObservableFreeze(options)
% RUNNETWORKADDITIVEFORMATIONRISKV65OBSERVABLEFREEZE Freeze X36 decisions.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNetworkAdditiveFormationRiskV65Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NetworkAdditiveFreezeV65:DirtySource', ...
        'V65 observable freezing requires a clean source checkout.');
end
times = reshape(getField( ...
    options, 'anchorTimes', protocol.x36AnchorTimes), 1, []);
if isempty(times) || any(~ismember(times, protocol.x36AnchorTimes)) || ...
        numel(unique(times)) ~= numel(times)
    error('NetworkAdditiveFreezeV65:InvalidTimes', ...
        'V65 anchor times must be a unique registered X36 subset.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(times));
for idx = 1:numel(times)
    currentTime = times(idx);
    fprintf('V65 observable freeze %d/%d: X36 t=%d ...\n', ...
        idx, numel(times), currentTime);
    state = loadFormationH3ObservableState( ...
        protocol.x36PresetName, protocol.x36Seed, currentTime, ...
        struct('cacheRoot', protocol.x36CacheRoot));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds);
    metrics = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    selection = selectNetworkAdditiveFormationRiskSetV65( ...
        metrics, protocol);
    records(idx) = makeRecord(currentTime, metrics, selection);
    fprintf(['  risk=%.3f%% loss=%.3f%% enabled=%d set=%s ', ...
        'coverage=%.3f%% fallback=%s\n'], ...
        100 * metrics.totalNetworkRescueFraction, ...
        100 * metrics.totalNetworkUsefulLossFraction, ...
        selection.actionEnabled, ...
        mat2str(selection.selectedFormationIds), ...
        100 * selection.achievedCoverageFraction, ...
        selection.fallbackReason);
end

result = struct();
result.contractVersion = ...
    'network-additive-formation-risk-v65-observable-freeze-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.records = records;
result.anchorTimes = times;
result.x36T128OutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementsUsed = false;
result.futureOutcomesUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'NETWORK_ADDITIVE_FORMATION_RISK_V65_OBSERVABLE_FREEZE.mat');
reportPath = fullfile(outputRoot, ...
    'NETWORK_ADDITIVE_FORMATION_RISK_V65_OBSERVABLE_FREEZE.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V65 observable freeze report: %s\n', reportPath);
end

function record = makeRecord(currentTime, metrics, selection)
record = emptyRecord();
record.currentTime = currentTime;
record.networkReferenceExistenceMass = ...
    metrics.networkReferenceExistenceMass;
record.totalNetworkRescueFraction = ...
    metrics.totalNetworkRescueFraction;
record.totalNetworkUsefulLossFraction = ...
    metrics.totalNetworkUsefulLossFraction;
record.rescueFractionByFormation = ...
    metrics.networkRescueFractionByFormation;
record.usefulLossFractionByFormation = ...
    metrics.networkUsefulLossFractionByFormation;
record.upwardCrossingsByFormation = ...
    metrics.receiverSupportedUpwardCrossingsByFormation;
record.downwardCrossingsByFormation = ...
    metrics.crossSupportedDownwardCrossingsByFormation;
record.selection = selection;
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'networkReferenceExistenceMass', NaN, ...
    'totalNetworkRescueFraction', NaN, ...
    'totalNetworkUsefulLossFraction', NaN, ...
    'rescueFractionByFormation', zeros(1, 0), ...
    'usefulLossFractionByFormation', zeros(1, 0), ...
    'upwardCrossingsByFormation', zeros(1, 0), ...
    'downwardCrossingsByFormation', zeros(1, 0), ...
    'selection', struct());
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkAdditiveFreezeV65:WriteFailed', ...
        'Could not create the V65 observable freeze report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V65 X36 network-additive observable freeze\n\n');
fprintf(fid, ['The selector below was evaluated from current posterior ', ...
    'states before the X36 t=128 tracking outcome was opened.\n\n']);
fprintf(fid, ['| Time | Network risk | Useful loss | Action | Formations | ', ...
    'Coverage | Loss / rescue | Fallback |\n']);
fprintf(fid, '|--:|--:|--:|:--:|:--|--:|--:|:--|\n');
for record = result.records
    selection = record.selection;
    fprintf(fid, '| %d | %.3f%% | %.3f%% | %d | `%s` | %.3f%% | %.3f%% | `%s` |\n', ...
        record.currentTime, ...
        100 * record.totalNetworkRescueFraction, ...
        100 * record.totalNetworkUsefulLossFraction, ...
        selection.actionEnabled, ...
        mat2str(selection.selectedFormationIds), ...
        100 * selection.achievedCoverageFraction, ...
        100 * selection.usefulLossToRescueRatio, ...
        selection.fallbackReason);
end
fprintf(fid, '\n## Formation details\n\n');
for record = result.records
    fprintf(fid, '- t=%d rescue: `%s`\n', record.currentTime, ...
        mat2str(record.rescueFractionByFormation, 6));
    fprintf(fid, '- t=%d useful loss: `%s`\n', record.currentTime, ...
        mat2str(record.usefulLossFractionByFormation, 6));
    fprintf(fid, '- t=%d upward / downward crossings: `%s / %s`\n', ...
        record.currentTime, ...
        mat2str(record.upwardCrossingsByFormation), ...
        mat2str(record.downwardCrossingsByFormation));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
