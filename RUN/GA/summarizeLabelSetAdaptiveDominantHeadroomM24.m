function [reportPath, summary] = ...
    summarizeLabelSetAdaptiveDominantHeadroomM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTHEADROOMM24 Gate high-weight routing.
%
% The primary oracle is not allowed to trade mean tracking against an
% arbitrary tail failure.  A new action is admissible only when it passes
% the exact runtime/message/B3/byte gates, stays within 1% of the prior
% temporal oracle's worst-node E-OSPA, and does not regress its consensus
% OSPA.  The separate persistent-balanced readout is deployable and uses
% no future outcome; the safe oracle is only an action-space upper bound.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantRoutingImplementationAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 adaptive-dominant headroom summary is not authorized.');
end
states = struct( ...
    'seed', {11, 19, 23, 27}, ...
    'time', {78, 78, 78, 78}, ...
    'behavior', {'learned', 'ccw', 'ccw', 'learned'}, ...
    'behaviorAction', { ...
        'label-set-message-passing-safe-fixed-e05-a70', ...
        'fixed-counter-clockwise', ...
        'fixed-counter-clockwise', ...
        'label-set-message-passing-safe-fixed-e05-a70'});
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'adaptive_dominant_headroom_v1'));
prior = loadTemporalReference(options, protocol, states);
rows = repmat(emptyRow(), 1, numel(states));
actionCount = size( ...
    protocol.adaptiveDominantRoutingActionSequences, 1);
riskMatrix = inf(numel(states), actionCount);
admissibleMatrix = false(numel(states), actionCount);
runCommit = '';
balancedIdx = actionIndexForToken( ...
    protocol.adaptiveDominantBalancedActionToken, protocol);
unbalancedIdx = actionIndexForToken( ...
    protocol.adaptiveDominantUnbalancedActionToken, protocol);

for stateIdx = 1:numel(states)
    state = states(stateIdx);
    path = fullfile(inputDirectory, ...
        sprintf('seed%d', state.seed), sprintf([ ...
            'label_set_causal_graph_option_h3_m24_', ...
            'seed%d_t%d_%s_source.mat'], ...
            state.seed, state.time, state.behavior));
    loaded = load(path, 'preflight');
    if ~isfield(loaded, 'preflight')
        error('Adaptive-dominant artifact lacks preflight.');
    end
    preflight = loaded.preflight;
    validatePreflight(preflight, state, protocol);
    if isempty(runCommit)
        runCommit = preflight.generationGitCommit;
    elseif ~strcmp(runCommit, preflight.generationGitCommit)
        error('Adaptive-dominant preflights use different commits.');
    end
    outcomes = preflight.outcomes;
    risk = [outcomes.meanEospa];
    riskMatrix(stateIdx, :) = risk;
    basicSafe = basicActionSafety(preflight, protocol);
    byteSafe = abs(preflight.attemptedByteDeviationPercent) <= ...
        protocol.macroActionMaximumByteDeviationPercent + 1e-12;
    worstSafe = [outcomes.worstSensorEospa] <= ...
        prior.worstByState(stateIdx) * (1 + ...
            protocol. ...
                adaptiveDominantRoutingMaximumWorstRegressionPercent / ...
            100) + 1e-12;
    consensusSafe = [outcomes.consensusOspa] <= ...
        prior.consensusByState(stateIdx) * (1 + ...
            protocol. ...
                adaptiveDominantRoutingMaximumConsensusRegressionPercent / ...
            100) + 1e-12;
    admissible = basicSafe & byteSafe & ...
        worstSafe & consensusSafe;
    newActionMask = false(1, actionCount);
    newActionMask(3:end) = true;
    admissibleNew = admissible & newActionMask;
    admissibleMatrix(stateIdx, :) = admissible;
    [safeOracle, bestIdx] = ...
        maskedMinimum(risk, admissibleNew);

    row = emptyRow();
    row.seed = state.seed;
    row.currentTime = state.time;
    row.behavior = state.behavior;
    row.artifactPath = path;
    row.cccMeanEospa = risk(1);
    row.learnedMeanEospa = risk(2);
    row.temporalOracleMeanEospa = ...
        prior.meanByState(stateIdx);
    row.temporalOracleWorstEospa = ...
        prior.worstByState(stateIdx);
    row.temporalOracleConsensusOspa = ...
        prior.consensusByState(stateIdx);
    row.safeAdaptiveOracleMeanEospa = safeOracle;
    row.safeAdaptiveOracleOption = ...
        preflight.actionSequenceNames{bestIdx};
    row.safeAdaptiveOracleWorstEospa = ...
        outcomes(bestIdx).worstSensorEospa;
    row.safeAdaptiveOracleConsensusOspa = ...
        outcomes(bestIdx).consensusOspa;
    row.safeAdaptiveOracleByteDeviationPercent = ...
        preflight.attemptedByteDeviationPercent(bestIdx);
    row.safeAdaptiveIncrementalGainPercent = ...
        relativeGain(row.temporalOracleMeanEospa, ...
            row.safeAdaptiveOracleMeanEospa);
    row.admissibleNewActionCount = nnz(admissibleNew);
    row.balancedMeanEospa = risk(balancedIdx);
    row.balancedWorstEospa = ...
        outcomes(balancedIdx).worstSensorEospa;
    row.balancedConsensusOspa = ...
        outcomes(balancedIdx).consensusOspa;
    row.balancedByteDeviationPercent = ...
        preflight.attemptedByteDeviationPercent(balancedIdx);
    row.balancedGainVsCccPercent = ...
        relativeGain(row.cccMeanEospa, row.balancedMeanEospa);
    row.balancedGainVsTemporalPercent = ...
        relativeGain(row.temporalOracleMeanEospa, ...
            row.balancedMeanEospa);
    row.balancedBasicSafetyPassed = ...
        basicSafe(balancedIdx) && byteSafe(balancedIdx);
    row.unbalancedMeanEospa = risk(unbalancedIdx);
    row.unbalancedWorstEospa = ...
        outcomes(unbalancedIdx).worstSensorEospa;
    row.unbalancedConsensusOspa = ...
        outcomes(unbalancedIdx).consensusOspa;
    row.unbalancedByteDeviationPercent = ...
        preflight.attemptedByteDeviationPercent(unbalancedIdx);
    row.unbalancedGainVsTemporalPercent = ...
        relativeGain(row.temporalOracleMeanEospa, ...
            row.unbalancedMeanEospa);
    row.unbalancedTailAdmissible = ...
        admissible(unbalancedIdx);
    row.restartEquivalencePassed = ...
        preflight.restartEquivalencePassed;
    rows(stateIdx) = row;
end

meanTemporal = mean([rows.temporalOracleMeanEospa]);
meanSafeOracle = mean([rows.safeAdaptiveOracleMeanEospa]);
safeOracleIncremental = ...
    relativeGain(meanTemporal, meanSafeOracle);
meanBalanced = mean([rows.balancedMeanEospa]);
balancedGainVsTemporal = ...
    relativeGain(meanTemporal, meanBalanced);
meanUnbalanced = mean([rows.unbalancedMeanEospa]);
unbalancedGainVsTemporal = ...
    relativeGain(meanTemporal, meanUnbalanced);
balancedPositiveVsCcc = ...
    nnz([rows.balancedGainVsCccPercent] > 0);
balancedWorstReferenceMean = ...
    mean([rows.temporalOracleWorstEospa]);
balancedWorstMean = mean([rows.balancedWorstEospa]);
balancedConsensusReferenceMean = ...
    mean([rows.temporalOracleConsensusOspa]);
balancedConsensusMean = mean([rows.balancedConsensusOspa]);
balancedAggregateWorstGain = relativeGain( ...
    balancedWorstReferenceMean, balancedWorstMean);
balancedAggregateConsensusRegression = 100 * ...
    (balancedConsensusMean - ...
     balancedConsensusReferenceMean) / ...
    max(balancedConsensusReferenceMean, eps);
admissibleStateCount = nnz( ...
    [rows.admissibleNewActionCount] > 0);
hardAuditPassed = ...
    all([rows.restartEquivalencePassed]) && ...
    all(all(isfinite(riskMatrix))) && ...
    all([rows.balancedBasicSafetyPassed]);
headroomPassed = ...
    hardAuditPassed && ...
    admissibleStateCount >= ...
        protocol. ...
            adaptiveDominantRoutingRequiredAdmissibleStateCount && ...
    safeOracleIncremental >= ...
        protocol. ...
            adaptiveDominantRoutingMinimumIncrementalOracleGainPercent;
balancedGatePassed = ...
    hardAuditPassed && ...
    balancedGainVsTemporal >= ...
        protocol. ...
            adaptiveDominantBalancedMinimumGainVsTemporalPercent && ...
    balancedPositiveVsCcc >= ...
        protocol. ...
            adaptiveDominantBalancedMinimumPositiveVsCccStateCount && ...
    balancedAggregateWorstGain >= 0 && ...
    balancedAggregateConsensusRegression <= ...
        protocol. ...
            adaptiveDominantBalancedMaximumAggregateConsensusRegressionPercent;

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-label-set-adaptive-dominant-headroom-summary-v1';
summary.auditContractVersion = ...
    protocol.adaptiveDominantRoutingAuditContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.runGenerationGitCommit = runCommit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.rows = rows;
summary.actionSequences = ...
    protocol.adaptiveDominantRoutingActionSequences;
summary.riskMatrix = riskMatrix;
summary.admissibleMatrix = admissibleMatrix;
summary.meanTemporalOracleEospa = meanTemporal;
summary.meanSafeAdaptiveOracleEospa = meanSafeOracle;
summary.safeAdaptiveIncrementalGainPercent = ...
    safeOracleIncremental;
summary.admissibleStateCount = admissibleStateCount;
summary.meanBalancedEospa = meanBalanced;
summary.balancedGainVsTemporalPercent = ...
    balancedGainVsTemporal;
summary.balancedPositiveVsCccStateCount = ...
    balancedPositiveVsCcc;
summary.balancedAggregateWorstGainPercent = ...
    balancedAggregateWorstGain;
summary.balancedAggregateConsensusRegressionPercent = ...
    balancedAggregateConsensusRegression;
summary.meanUnbalancedEospa = meanUnbalanced;
summary.unbalancedGainVsTemporalPercent = ...
    unbalancedGainVsTemporal;
summary.unbalancedTailAdmissibleStateCount = ...
    nnz([rows.unbalancedTailAdmissible]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.safeActionHeadroomGatePassed = headroomPassed;
summary.persistentBalancedGatePassed = balancedGatePassed;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.nextMethodDirection = [ ...
    'full-six-seed-training-validation-of-persistent-balanced-', ...
    'default-plus-lcb-gated-concentrated-upgrade'];
summary.evidenceBoundary = [ ...
    'This opened-training audit establishes action-space headroom and ', ...
    'a promising truth-free persistent balanced controller on four ', ...
    'registered behavior states. The safe oracle uses future return ', ...
    'only to select among already truth-free actions. It does not ', ...
    'establish a learned gate, six-seed training stability, ', ...
    'development, held-out M24 or X36 performance.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = 'label_set_adaptive_dominant_headroom_m24_v1';
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Adaptive-dominant summary already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary, protocol);
fprintf('Adaptive-dominant summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function prior = loadTemporalReference(options, protocol, states)
defaultPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'diverse_temporal_upper_bound_v1', 'summary', ...
    'label_set_diverse_temporal_upper_bound_m24_v1.mat');
path = getField(options, 'temporalSummaryPath', defaultPath);
loaded = load(path, 'summary');
if ~isfield(loaded, 'summary') || ...
        ~strcmp(loaded.summary.protocolId, protocol.id) || ...
        loaded.summary.developmentOpened || ...
        loaded.summary.heldoutM24Opened || ...
        loaded.summary.x36Opened || ...
        numel(loaded.summary.rows) ~= numel(states)
    error('Temporal reference summary violates the boundary.');
end
prior = struct( ...
    'meanByState', nan(1, numel(states)), ...
    'worstByState', nan(1, numel(states)), ...
    'consensusByState', nan(1, numel(states)));
for stateIdx = 1:numel(states)
    row = loaded.summary.rows(stateIdx);
    state = states(stateIdx);
    if row.seed ~= state.seed || ...
            row.currentTime ~= state.time
        error('Temporal reference state ordering changed.');
    end
    artifact = load(row.artifactPath, 'preflight');
    if ~isfield(artifact, 'preflight')
        error('Temporal reference artifact is missing.');
    end
    outcomes = artifact.preflight.outcomes;
    [bestMean, bestIdx] = min([outcomes.meanEospa]);
    if abs(bestMean - row.temporalOracleMeanEospa) > 1e-9
        error('Temporal reference oracle value drifted.');
    end
    prior.meanByState(stateIdx) = bestMean;
    prior.worstByState(stateIdx) = ...
        outcomes(bestIdx).worstSensorEospa;
    prior.consensusByState(stateIdx) = ...
        outcomes(bestIdx).consensusOspa;
end
end

function validatePreflight(preflight, state, protocol)
if ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.auditMode, ...
            'adaptive-dominant-headroom') || ...
        ~strcmp(preflight.auditContractVersion, ...
            protocol.adaptiveDominantRoutingAuditContractVersion) || ...
        preflight.seed ~= state.seed || ...
        preflight.currentTime ~= state.time || ...
        ~strcmp(preflight.sourceBehaviorAction, ...
            state.behaviorAction) || ...
        ~isequal(preflight.actionSequences, ...
            protocol.adaptiveDominantRoutingActionSequences) || ...
        preflight.exploratoryActionSubsetUsed || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        preflight.registeredProjectionFailureCount ~= 0 || ...
        ~preflight.allRegisteredActionsFeasible || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || ...
        preflight.x36Opened
    error('Adaptive-dominant preflight violates the frozen contract.');
end
end

function safe = basicActionSafety(preflight, protocol)
outcomes = preflight.outcomes;
safe = arrayfun(@(outcome) ...
    outcome.executionCompleted && ...
    ~outcome.hardFailure && ...
    outcome.firstActionExact && ...
    outcome.truthUseCount == 0 && ...
    outcome.repairCount == 0 && ...
    outcome.payloadEmergencyCount == 0 && ...
    outcome.infeasibleCount == 0 && ...
    all(outcome.messageCounts == ...
        protocol.adaptiveDominantRoutingExpectedMessageCount) && ...
    all(outcome.selectedSensorB3Pass) && ...
    all(outcome.selectedFormationB3Pass), outcomes);
end

function [value, index] = maskedMinimum(values, mask)
masked = values;
masked(~mask) = inf;
[value, index] = min(masked);
if ~isfinite(value)
    error('No admissible adaptive dominant action exists.');
end
end

function index = actionIndexForToken(token, protocol)
index = find(all( ...
    protocol.adaptiveDominantRoutingActionSequences == ...
        token, 2));
if numel(index) ~= 1
    error('Adaptive dominant action token is not unique.');
end
end

function writeReport(path, summary, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write adaptive-dominant report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 adaptive-dominant H=3 headroom audit\n\n');
fprintf(fid, ...
    '- Mean temporal / tail-safe adaptive oracle E-OSPA: `%.6f / %.6f`\n', ...
    summary.meanTemporalOracleEospa, ...
    summary.meanSafeAdaptiveOracleEospa);
fprintf(fid, ...
    '- Tail-safe incremental gain: `%.3f%%` (gate `%.3f%%`)\n', ...
    summary.safeAdaptiveIncrementalGainPercent, ...
    protocol. ...
        adaptiveDominantRoutingMinimumIncrementalOracleGainPercent);
fprintf(fid, ...
    '- States with an admissible new action: `%d / %d`\n', ...
    summary.admissibleStateCount, numel(summary.rows));
fprintf(fid, ...
    '- Persistent balanced gain vs temporal oracle: `%.3f%%`\n', ...
    summary.balancedGainVsTemporalPercent);
fprintf(fid, ...
    '- Persistent balanced positive states vs CCC: `%d / %d`\n', ...
    summary.balancedPositiveVsCccStateCount, ...
    numel(summary.rows));
fprintf(fid, ...
    '- Persistent balanced aggregate worst gain: `%+.3f%%`\n', ...
    summary.balancedAggregateWorstGainPercent);
fprintf(fid, [ ...
    '- Persistent balanced aggregate consensus regression: ', ...
    '`%+.3f%%`\n'], ...
    summary.balancedAggregateConsensusRegressionPercent);
fprintf(fid, ...
    '- Persistent unbalanced gain / tail-admissible states: `%.3f%% / %d`\n', ...
    summary.unbalancedGainVsTemporalPercent, ...
    summary.unbalancedTailAdmissibleStateCount);
fprintf(fid, ...
    '- Hard / action-headroom / persistent-balanced gates: `%d / %d / %d`\n\n', ...
    summary.hardAuditGatesPassed, ...
    summary.safeActionHeadroomGatePassed, ...
    summary.persistentBalancedGatePassed);
fprintf(fid, [ ...
    '| Seed | Source | Temporal | Safe new oracle | Best safe | ', ...
    'Incremental | New admissible | Balanced | Bal. vs CCC | ', ...
    'Unbalanced | U tail-safe |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|:--|--:|--:|--:|--:|--:|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, [ ...
        '| %d | %s | %.6f | %.6f | `%s` | %+.3f%% | %d | ', ...
        '%.6f | %+.3f%% | %.6f | %d |\n'], ...
        row.seed, row.behavior, ...
        row.temporalOracleMeanEospa, ...
        row.safeAdaptiveOracleMeanEospa, ...
        row.safeAdaptiveOracleOption, ...
        row.safeAdaptiveIncrementalGainPercent, ...
        row.admissibleNewActionCount, ...
        row.balancedMeanEospa, ...
        row.balancedGainVsCccPercent, ...
        row.unbalancedMeanEospa, ...
        row.unbalancedTailAdmissible);
end
fprintf(fid, '\n## Decision\n\n');
if summary.safeActionHeadroomGatePassed
    fprintf(fid, [ ...
        'The adaptive-dominant action space passes the registered ', ...
        'tail-safe incremental-headroom gate. ']);
else
    fprintf(fid, [ ...
        'The adaptive-dominant action space fails the registered ', ...
        'tail-safe incremental-headroom gate. ']);
end
if summary.persistentBalancedGatePassed
    fprintf(fid, [ ...
        'The persistent balanced controller also passes its ', ...
        'four-state progression gate. ']);
else
    fprintf(fid, [ ...
        'The persistent balanced controller does not pass its ', ...
        'four-state progression gate. ']);
end
fprintf(fid, 'Next: `%s`.\n\n', summary.nextMethodDirection);
fprintf(fid, '## Boundary\n\n%s\n', summary.evidenceBoundary);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behavior', '', ...
    'artifactPath', '', ...
    'cccMeanEospa', NaN, ...
    'learnedMeanEospa', NaN, ...
    'temporalOracleMeanEospa', NaN, ...
    'temporalOracleWorstEospa', NaN, ...
    'temporalOracleConsensusOspa', NaN, ...
    'safeAdaptiveOracleMeanEospa', NaN, ...
    'safeAdaptiveOracleOption', '', ...
    'safeAdaptiveOracleWorstEospa', NaN, ...
    'safeAdaptiveOracleConsensusOspa', NaN, ...
    'safeAdaptiveOracleByteDeviationPercent', NaN, ...
    'safeAdaptiveIncrementalGainPercent', NaN, ...
    'admissibleNewActionCount', 0, ...
    'balancedMeanEospa', NaN, ...
    'balancedWorstEospa', NaN, ...
    'balancedConsensusOspa', NaN, ...
    'balancedByteDeviationPercent', NaN, ...
    'balancedGainVsCccPercent', NaN, ...
    'balancedGainVsTemporalPercent', NaN, ...
    'balancedBasicSafetyPassed', false, ...
    'unbalancedMeanEospa', NaN, ...
    'unbalancedWorstEospa', NaN, ...
    'unbalancedConsensusOspa', NaN, ...
    'unbalancedByteDeviationPercent', NaN, ...
    'unbalancedGainVsTemporalPercent', NaN, ...
    'unbalancedTailAdmissible', false, ...
    'restartEquivalencePassed', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
