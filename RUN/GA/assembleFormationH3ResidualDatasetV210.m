function [reportPath, dataset] = ...
        assembleFormationH3ResidualDatasetV210(options)
% ASSEMBLEFORMATIONH3RESIDUALDATASETV210 Align dense and recursive targets.
%
% The four V209 same-prefix branches define the first target-semantic
% anchors.  Supported-label actions are joined to dense immediate features
% generated on their exact policy-induced pre-action states.  Formation
% release remains recursive-only until a matching dense action encoder is
% implemented.  Four development rows are not a training or calibration
% set; this assembler makes that boundary executable.

if nargin < 1 || isempty(options)
    options = struct();
end
evidenceRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v209');
recursivePath = char(getField(options, 'recursivePath', fullfile( ...
    evidenceRoot, 'sparse_recursive_counterfactuals', ...
    'x36_seed211_t72_h8', ...
    'SPARSE_RECURSIVE_COUNTERFACTUALS_V209.mat')));
immediateSources = getField(options, 'immediateSources', ...
    defaultImmediateSources(evidenceRoot));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    evidenceRoot, 'formation_h3_residual_anchors', ...
    'x36_seed211_t72_h8')));

if exist(recursivePath, 'file') ~= 2 || ...
        ~isstruct(immediateSources) || ...
        ~all(isfield(immediateSources, {'actionTime', 'path'}))
    error('FormationH3ResidualV210:InvalidRequest', ...
        'The recursive dataset and immediate-source manifest are required.');
end

loaded = load(recursivePath, 'dataset');
recursive = loaded.dataset;
validateRecursiveDataset(recursive);
recursiveTargetNames = { ...
    'mean_eospa_gain_percent', ...
    'mean_rmse_gain_percent', ...
    'consensus_gain_percent', ...
    'terminal_consensus_gain_percent', ...
    'receiver_formation_eospa_gain_percent', ...
    'receiver_formation_rmse_gain_percent', ...
    'minimum_affected_sensor_eospa_gain_percent', ...
    'minimum_affected_sensor_rmse_gain_percent', ...
    'worst_sensor_eospa_gain_percent', ...
    'worst_sensor_rmse_gain_percent', ...
    'minimum_formation_eospa_gain_percent', ...
    'minimum_formation_rmse_gain_percent'};
sharedTargetIndices = [1, 2, 3, 5, 6, 7, 8, 9, 10];
rows = repmat(emptyRow(), 1, numel(recursive.rows));
actionFeatureNames = cell(1, 0);
immediateTargetNames = cell(1, 0);

for rowIdx = 1:numel(recursive.rows)
    source = recursive.rows(rowIdx);
    row = emptyRow();
    row.rowId = rowIdx;
    row.name = source.name;
    row.actionType = source.actionType;
    row.actionTime = source.actionTime;
    row.receiverFormationId = source.receiverFormationId;
    row.sourceId = source.sourceId;
    row.label = source.label;
    row.windowTimes = source.windowTimes;
    row.prefixMatched = source.prefixMatched;
    row.recursiveGainPercent = recursiveTargetVector(source);
    row.recursiveTarget = gainPercentToBoundedLogRatio( ...
        row.recursiveGainPercent);
    row.incrementalAttemptedBytes = source.incrementalAttemptedBytes;
    row.candidateStaticByteSaving = source.candidateStaticByteSaving;
    row.candidateStaticByteSavingPercent = ...
        source.candidateStaticByteSavingPercent;
    row.aggregateReturnPositive = source.aggregateReturnPositive;
    row.strictReturnPositive = source.strictReturnPositive;
    if source.strictReturnPositive
        row.admissionClass = 2;
        row.admissionLabel = 'strict-execute';
    elseif source.aggregateReturnPositive
        row.admissionClass = 1;
        row.admissionLabel = 'risk-budget-execute';
    else
        row.admissionClass = 0;
        row.admissionLabel = 'no-op';
    end

    if strcmp(source.actionType, 'supported-label-kla')
        [immediate, immediatePath] = loadImmediateSource( ...
            immediateSources, source.actionTime, recursive);
        [matchedRow, matchedIndex] = matchImmediateRow( ...
            immediate, source);
        row.stateAlignedImmediateFound = true;
        row.immediateDatasetPath = immediatePath;
        row.immediateRowIndex = matchedIndex;
        row.graph = immediate.blocks(1).graph;
        row.actionFeatures = matchedRow.features;
        row.immediateGainPercent = ...
            matchedRow.targets(sharedTargetIndices);
        row.immediateTarget = gainPercentToBoundedLogRatio( ...
            row.immediateGainPercent);
        row.recursiveSharedTarget = ...
            row.recursiveTarget(sharedTargetIndices);
        row.h3ResidualTarget = ...
            row.recursiveSharedTarget - row.immediateTarget;
        row.actionBytes = matchedRow.actionBytes;
        row.lightSynopsisBytes = matchedRow.lightSynopsisBytes;
        row.immediateChargedNetByteSaving = ...
            matchedRow.chargedNetByteSaving;
        row.immediateChargedNetByteSavingPercent = ...
            matchedRow.chargedNetByteSavingPercent;
        row.immediateTeacherKey = matchedRow.teacherKey;
        if isempty(actionFeatureNames)
            actionFeatureNames = reshape( ...
                immediate.actionFeatureNames, 1, []);
            immediateTargetNames = reshape( ...
                immediate.targetNames(sharedTargetIndices), 1, []);
        elseif ~isequal(actionFeatureNames, reshape( ...
                immediate.actionFeatureNames, 1, [])) || ...
                ~isequal(immediateTargetNames, reshape( ...
                    immediate.targetNames(sharedTargetIndices), 1, []))
            error('FormationH3ResidualV210:ImmediateContractDrift', ...
                'Action or target features drifted between policy states.');
        end
    end
    rows(rowIdx) = row;
end

dataset = struct();
dataset.contractVersion = ...
    'formation-h3-residual-dataset-v210-v1';
dataset.generatedAt = datestr(now, 31);
dataset.presetName = recursive.presetName;
dataset.seed = recursive.seed;
dataset.returnHorizonSteps = recursive.returnHorizonSteps;
dataset.recursivePath = recursivePath;
dataset.immediateSources = immediateSources;
dataset.actionFeatureNames = actionFeatureNames;
dataset.immediateTargetNames = immediateTargetNames;
dataset.recursiveTargetNames = recursiveTargetNames;
dataset.sharedRecursiveTargetIndices = sharedTargetIndices;
dataset.targetTransform = ...
    'tanh_negative_log_candidate_over_reference';
dataset.rows = rows;
dataset.rowCount = numel(rows);
dataset.stateAlignedFeatureRowCount = ...
    nnz([rows.stateAlignedImmediateFound]);
dataset.strictExecuteRowCount = ...
    nnz([rows.admissionClass] == 2);
dataset.riskBudgetExecuteRowCount = ...
    nnz([rows.admissionClass] == 1);
dataset.noOpRowCount = nnz([rows.admissionClass] == 0);
dataset.featuresUseTruth = false;
dataset.immediateTargetsUseCurrentTruth = true;
dataset.recursiveTargetsUseFutureTruth = true;
dataset.completeTrajectoryHeldOut = false;
dataset.trainingAllowed = false;
dataset.calibrationAllowed = false;
dataset.validationClaimAllowed = false;
dataset.evidenceBoundary = [ ...
    'V210 aligns three policy-induced supported-label states with the ', ...
    'four same-prefix X36 seed-211 H=3 counterfactual branches.  Graph ', ...
    'and action features are truth-free; current and future truth score ', ...
    'offline targets only.  Formation release remains recursive-only.  ', ...
    'The four development rows define target semantics and exercise the ', ...
    'residual data path; they are insufficient for model fitting, ', ...
    'conformal calibration, validation, or performance claims.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_H3_RESIDUAL_DATASET_V210.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_H3_RESIDUAL_DATASET_V210.md');
dataset.matPath = matPath;
dataset.reportPath = reportPath;
save('-mat7-binary', matPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('V210 H=3 residual anchors: %s\n', reportPath);
end

function sources = defaultImmediateSources(evidenceRoot)
template = struct('actionTime', 0, 'path', '');
times = [73, 76, 77];
leaves = {'t73_after_v206_prefix', ...
    't76_after_v206_prefix', 't77_after_v204_prefix'};
sources = repmat(template, 1, numel(times));
for idx = 1:numel(times)
    sources(idx).actionTime = times(idx);
    sources(idx).path = fullfile(evidenceRoot, ...
        'policy_induced_immediate', leaves{idx}, ...
        'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat');
end
end

function validateRecursiveDataset(dataset)
required = {'contractVersion', 'presetName', 'seed', ...
    'returnHorizonSteps', 'rows', 'truthUsedForTargets', ...
    'truthUsedAtRuntime', 'policyInducedStateTargets', ...
    'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'sparse-recursive-counterfactual-action-value-v209-v1') || ...
        dataset.returnHorizonSteps ~= 3 || ...
        numel(dataset.rows) ~= 4 || ...
        ~dataset.truthUsedForTargets || dataset.truthUsedAtRuntime || ...
        ~dataset.policyInducedStateTargets || ...
        dataset.validationClaimAllowed || ...
        ~all([dataset.rows.prefixMatched])
    error('FormationH3ResidualV210:RecursiveContract', ...
        'The V209 same-prefix recursive dataset is invalid.');
end
end

function [dataset, path] = loadImmediateSource( ...
        sources, actionTime, recursive)
indices = find([sources.actionTime] == actionTime);
if numel(indices) ~= 1
    error('FormationH3ResidualV210:ImmediateManifest', ...
        'Each label action requires one immediate-state source.');
end
path = char(sources(indices).path);
if exist(path, 'file') ~= 2
    error('FormationH3ResidualV210:MissingImmediateSource', ...
        'Missing policy-induced immediate source: %s', path);
end
loaded = load(path, 'dataset');
dataset = loaded.dataset;
required = {'contractVersion', 'presetName', 'seed', ...
    'returnTimes', 'actionFeatureNames', 'targetNames', ...
    'blocks', 'rows', 'blockCount', 'featuresUseTruth', ...
    'featuresUseFutureInformation', 'recursiveTargetsIncluded', ...
    'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-label-kla-immediate-dataset-v208-v1') || ...
        dataset.blockCount ~= 1 || ...
        numel(dataset.returnTimes) ~= 1 || ...
        dataset.returnTimes ~= actionTime || ...
        ~strcmp(dataset.presetName, recursive.presetName) || ...
        dataset.seed ~= recursive.seed || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed
    error('FormationH3ResidualV210:ImmediateContract', ...
        'The policy-induced immediate source is invalid.');
end
end

function [row, index] = matchImmediateRow(dataset, recursiveRow)
mask = [dataset.rows.currentTime] == recursiveRow.actionTime & ...
    [dataset.rows.receiverFormationId] == ...
        recursiveRow.receiverFormationId & ...
    [dataset.rows.sourceId] == recursiveRow.sourceId & ...
    arrayfun(@(candidate) isequal( ...
        candidate.label, recursiveRow.label), dataset.rows);
indices = find(mask);
if numel(indices) ~= 1
    error('FormationH3ResidualV210:ImmediateKey', ...
        'The recursive action must match exactly one immediate row.');
end
index = indices(1);
row = dataset.rows(index);
if ~row.teacherKey
    error('FormationH3ResidualV210:TeacherKey', ...
        'The matched development action is not a registered teacher key.');
end
end

function values = recursiveTargetVector(row)
values = [ ...
    row.meanEospaGainPercent, ...
    row.meanRmseGainPercent, ...
    row.consensusGainPercent, ...
    row.terminalConsensusGainPercent, ...
    row.receiverFormationEospaGainPercent, ...
    row.receiverFormationRmseGainPercent, ...
    row.minimumAffectedSensorEospaGainPercent, ...
    row.minimumAffectedSensorRmseGainPercent, ...
    row.worstSensorEospaGainPercent, ...
    row.worstSensorRmseGainPercent, ...
    row.minimumFormationEospaGainPercent, ...
    row.minimumFormationRmseGainPercent];
end

function transformed = gainPercentToBoundedLogRatio(gainPercent)
ratio = 1 - gainPercent / 100;
if any(~isfinite(ratio(:))) || any(ratio(:) < -1e-9)
    error('FormationH3ResidualV210:InvalidGain', ...
        'Every target must imply a finite nonnegative error ratio.');
end
ratio = max(ratio, eps);
transformed = tanh(-log(ratio));
end

function row = emptyRow()
row = struct( ...
    'rowId', 0, 'name', '', 'actionType', '', ...
    'actionTime', 0, 'receiverFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'windowTimes', zeros(1, 0), 'prefixMatched', false, ...
    'stateAlignedImmediateFound', false, ...
    'immediateDatasetPath', '', 'immediateRowIndex', 0, ...
    'graph', struct(), 'actionFeatures', zeros(1, 0), ...
    'immediateGainPercent', zeros(1, 0), ...
    'immediateTarget', zeros(1, 0), ...
    'recursiveGainPercent', zeros(1, 0), ...
    'recursiveTarget', zeros(1, 0), ...
    'recursiveSharedTarget', zeros(1, 0), ...
    'h3ResidualTarget', zeros(1, 0), ...
    'actionBytes', NaN, 'lightSynopsisBytes', NaN, ...
    'immediateChargedNetByteSaving', NaN, ...
    'immediateChargedNetByteSavingPercent', NaN, ...
    'incrementalAttemptedBytes', NaN, ...
    'candidateStaticByteSaving', NaN, ...
    'candidateStaticByteSavingPercent', NaN, ...
    'aggregateReturnPositive', false, ...
    'strictReturnPositive', false, ...
    'admissionClass', 0, 'admissionLabel', '', ...
    'immediateTeacherKey', false);
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('FormationH3ResidualV210:ReportOpen', ...
        'Could not write the V210 residual report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V210 policy-state H=3 residual anchors\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    dataset.presetName, dataset.seed);
fprintf(fid, '- H=3 branches / state-aligned features: `%d / %d`\n', ...
    dataset.rowCount, dataset.stateAlignedFeatureRowCount);
fprintf(fid, '- Strict / risk-budget / no-op: `%d / %d / %d`\n', ...
    dataset.strictExecuteRowCount, ...
    dataset.riskBudgetExecuteRowCount, dataset.noOpRowCount);
fprintf(fid, '- Training / calibration allowed: `0 / 0`\n\n');
fprintf(fid, ['| Action | State features | Immediate E / R / C | ', ...
    'H=3 E / R / C | Added bytes | Static saving | Label |\n']);
fprintf(fid, '|:--|:--:|:--|:--|--:|--:|:--|\n');
for row = reshape(dataset.rows, 1, [])
    immediateText = '--';
    if row.stateAlignedImmediateFound
        immediateText = sprintf('%+.3f / %+.3f / %+.3f', ...
            row.immediateGainPercent(1), ...
            row.immediateGainPercent(2), ...
            row.immediateGainPercent(3));
    end
    fprintf(fid, ['| `%s` | %d | %s | %+.3f / %+.3f / %+.3f | ', ...
        '%+.0f B | %+.3f%% | `%s` |\n'], ...
        row.name, row.stateAlignedImmediateFound, immediateText, ...
        row.recursiveGainPercent(1), ...
        row.recursiveGainPercent(2), ...
        row.recursiveGainPercent(3), ...
        row.incrementalAttemptedBytes, ...
        row.candidateStaticByteSavingPercent, row.admissionLabel);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
