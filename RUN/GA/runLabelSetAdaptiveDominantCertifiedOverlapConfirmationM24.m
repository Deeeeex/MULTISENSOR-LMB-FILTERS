function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantCertifiedOverlapConfirmationM24( ...
        seed, options)
% RUNLABELSETADAPTIVEDOMINANTCERTIFIEDOVERLAPCONFIRMATIONM24
% Confirm the frozen v4 Pareto arm on opened M24 redesign seeds.
%
% The six training seeds and seed 37 were all opened before this
% confirmation contract.  They can confirm robustness before a later
% one-shot held-out M24 run, but they are not fresh validation evidence.

if nargin < 1 || isempty(seed)
    seed = 11;
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantCertifiedOverlapConfirmationAuthorized || ...
        protocol.adaptiveDominantCertifiedOverlapHeldoutM24Authorized || ...
        protocol.adaptiveDominantCertifiedOverlapX36Authorized || ...
        ~ismember(seed, protocol. ...
            adaptiveDominantCertifiedOverlapParetoConfirmationSeeds)
    error('Certified-overlap M24 confirmation seed is not authorized.');
end
if ismember(seed, protocol.adaptiveDominantFullWindowTrainingSeeds)
    evidenceSplit = 'training';
else
    evidenceSplit = 'development';
end
rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantCertifiedOverlapSelectedMarginToken), ...
    'confirmation'));
candidateArm = protocol. ...
    adaptiveDominantCertifiedOverlapSelectedArmName;
screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(1), ...
    'armNames', {{candidateArm}}, ...
    'writeReport', true, ...
    'outputDirectory', fullfile( ...
        rootDirectory, evidenceSplit, sprintf('seed%d', seed)), ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'cache')), ...
    'generateMissingBehaviorCache', false, ...
    'evidenceSplit', evidenceSplit);
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    'm24-hard', seed, screenOptions);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
