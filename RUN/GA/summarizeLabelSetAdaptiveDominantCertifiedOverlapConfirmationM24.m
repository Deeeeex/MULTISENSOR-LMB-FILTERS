function [reportPath, confirmation] = ...
    summarizeLabelSetAdaptiveDominantCertifiedOverlapConfirmationM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTCERTIFIEDOVERLAPCONFIRMATIONM24
% Confirm the frozen 2% v4 Pareto arm on seven opened M24 seeds.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantCertifiedOverlapConfirmationAuthorized || ...
        protocol.adaptiveDominantCertifiedOverlapHeldoutM24Authorized || ...
        protocol.adaptiveDominantCertifiedOverlapX36Authorized
    error('Certified-overlap M24 confirmation is not authorized.');
end

seeds = protocol. ...
    adaptiveDominantCertifiedOverlapParetoConfirmationSeeds;
rootDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantCertifiedOverlapSelectedMarginToken), ...
    'confirmation'));
rows = repmat(emptyRow(), 1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    [baseline, evidenceSplit] = loadBaseline(seed, protocol);
    path = findSingleEvidence( ...
        rootDirectory, evidenceSplit, seed);
    loaded = load(path, 'summary');
    summary = loaded.summary;
    validateSummary( ...
        summary, seed, evidenceSplit, protocol);
    candidate = findArm(summary.aggregate, protocol. ...
        adaptiveDominantCertifiedOverlapSelectedArmName);
    row = emptyRow();
    row.seed = seed;
    row.evidenceSplit = evidenceSplit;
    row.runCommit = summary.generationGitCommit;
    row.evidencePath = path;
    row.baselineEospa = baseline.focusEospa;
    row.candidateEospa = candidate.focusEospa;
    row.gainPercent = relativeGain( ...
        row.baselineEospa, row.candidateEospa);
    row.baselineWorstEospa = baseline.focusWorstSensorEospa;
    row.candidateWorstEospa = candidate.focusWorstSensorEospa;
    row.baselineConsensusOspa = baseline.focusMapSetDisagreement;
    row.candidateConsensusOspa = candidate.focusMapSetDisagreement;
    row.baselineAttemptedBytes = baseline.focusAttemptedBytes;
    row.candidateAttemptedBytes = candidate.focusAttemptedBytes;
    row.byteDeltaPercent = 100 * ...
        (row.candidateAttemptedBytes - row.baselineAttemptedBytes) / ...
            max(row.baselineAttemptedBytes, eps);
    row.meanMessageCount = candidate.meanDirectedMessageCount;
    row.selectedSensorB3 = candidate. ...
        focusSelectedRollingB3SensorStrongFraction;
    row.selectedFormationB3 = candidate. ...
        focusSelectedRollingB3FormationStrongFraction;
    row.deliveredSensorB3 = candidate. ...
        focusDeliveredRollingB3SensorStrongFraction;
    row.truthUseFraction = candidate.policyTruthUseFraction;
    row.posteriorUseFraction = ...
        candidate.policyPosteriorContentUseFraction;
    row.payloadMetadataUseFraction = candidate. ...
        policyPosteriorPayloadMetadataUseFraction;
    row.currentLinkReliabilityUseFraction = candidate. ...
        policyCurrentLinkReliabilityUseFraction;
    row.payloadConstraintFraction = candidate. ...
        policyPayloadConstraintEnforcedFraction;
    row.payloadLimitPassFraction = candidate. ...
        policyPayloadLimitPassFraction;
    row.repairRate = candidate.policyRepairRate;
    row.payloadEmergencyRate = candidate.policyPayloadEmergencyRate;
    row.topologyInfeasibleRate = candidate.focusTopologyInfeasibleRate;
    row.distinctRouteMaps = ...
        candidate.focusDistinctDirectedRouteMapCount;
    row.hardSafetyPassed = hardSafetyPassed(row, protocol);
    rows(seedIdx) = row;
end

baselineMean = mean([rows.baselineEospa]);
candidateMean = mean([rows.candidateEospa]);
meanGain = relativeGain(baselineMean, candidateMean);
positiveFraction = mean([rows.gainPercent] > 0);
worstGain = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
consensusGain = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
baselineBytes = sum([rows.baselineAttemptedBytes]);
candidateBytes = sum([rows.candidateAttemptedBytes]);
aggregateByteSaving = 100 * ...
    (baselineBytes - candidateBytes) / max(baselineBytes, eps);
maximumPositiveByteDelta = max([0, [rows.byteDeltaPercent]]);
hardSafetyPassedAll = all([rows.hardSafetyPassed]);
trackingGatePassed = ...
    meanGain >= protocol. ...
        adaptiveDominantCertifiedOverlapParetoMinimumMeanGainPercent && ...
    positiveFraction >= protocol. ...
        adaptiveDominantCertifiedOverlapParetoMinimumPositiveSeedFraction;
tailGatePassed = ...
    (~protocol. ...
        adaptiveDominantCertifiedOverlapParetoRequireNoAggregateWorstRegression || ...
        worstGain >= -1e-12) && ...
    (~protocol. ...
        adaptiveDominantCertifiedOverlapParetoRequireNoAggregateConsensusRegression || ...
        consensusGain >= -1e-12);
communicationGatePassed = ...
    aggregateByteSaving >= protocol. ...
        adaptiveDominantCertifiedOverlapParetoMinimumMeanByteSavingPercent && ...
    maximumPositiveByteDelta <= protocol. ...
        adaptiveDominantCertifiedOverlapParetoMaximumPositiveByteDeltaPercent + ...
            1e-12;
confirmationGatePassed = hardSafetyPassedAll && ...
    trackingGatePassed && tailGatePassed && communicationGatePassed;

gitState = resolveResearchGitState();
confirmation = struct();
confirmation.protocolId = protocol.id;
confirmation.contractVersion = protocol. ...
    adaptiveDominantCertifiedOverlapParetoConfirmationContractVersion;
confirmation.generatedAt = datestr(now, 31);
confirmation.generationGitCommit = gitState.commit;
confirmation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
confirmation.runGenerationGitCommits = ...
    unique({rows.runCommit}, 'stable');
confirmation.seeds = seeds;
confirmation.times = ...
    protocol.adaptiveDominantPayloadAwareDevelopmentTimes;
confirmation.selectedMarginToken = protocol. ...
    adaptiveDominantCertifiedOverlapSelectedMarginToken;
confirmation.selectedMarginFraction = protocol. ...
    adaptiveDominantCertifiedOverlapSelectedMarginFraction;
confirmation.rows = rows;
confirmation.baselineMeanEospa = baselineMean;
confirmation.candidateMeanEospa = candidateMean;
confirmation.meanGainPercent = meanGain;
confirmation.positiveSeedFraction = positiveFraction;
confirmation.aggregateWorstGainPercent = worstGain;
confirmation.aggregateConsensusGainPercent = consensusGain;
confirmation.aggregateByteSavingPercent = aggregateByteSaving;
confirmation.maximumPositiveByteDeltaPercent = ...
    maximumPositiveByteDelta;
confirmation.hardSafetyPassed = hardSafetyPassedAll;
confirmation.trackingGatePassed = trackingGatePassed;
confirmation.tailGatePassed = tailGatePassed;
confirmation.communicationGatePassed = communicationGatePassed;
confirmation.confirmationGatePassed = confirmationGatePassed;
confirmation.allSeedsPreviouslyOpened = true;
confirmation.validationClaimAllowed = false;
confirmation.heldoutM24Opened = false;
confirmation.x36Opened = false;
if confirmationGatePassed
    confirmation.nextDirection = ...
        'authorize-one-shot-heldout-M24-before-any-X36-run';
else
    confirmation.nextDirection = ...
        'stop-without-opening-heldout-M24-or-X36';
end
confirmation.evidenceBoundary = [ ...
    'All seven seeds were opened before this contract. This report ', ...
    'confirms the frozen Pareto design for method selection but is ', ...
    'not fresh held-out M24 or X36 validation evidence.'];

outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    rootDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_CERTIFIED_OVERLAP_CONFIRMATION_M24_V4.md');
writeReport(reportPath, confirmation, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'confirmation');
confirmation.reportPath = reportPath;
confirmation.matPath = matPath;
fprintf('Certified-overlap confirmation summary: %s\n', reportPath);
end

function [baseline, evidenceSplit] = loadBaseline(seed, protocol)
trainingIdx = find( ...
    protocol.adaptiveDominantFullWindowTrainingSeeds == seed, 1);
if ~isempty(trainingIdx)
    evidenceSplit = 'training';
    path = protocol. ...
        adaptiveDominantFullWindowBaselineMatPaths{trainingIdx};
    expectedHash = protocol. ...
        adaptiveDominantFullWindowBaselineMatSha256{trainingIdx};
else
    developmentIdx = find( ...
        protocol.adaptiveDominantDevelopmentSeeds == seed, 1);
    if isempty(developmentIdx)
        error('Confirmation seed has no frozen CCW baseline.');
    end
    evidenceSplit = 'development';
    path = protocol. ...
        adaptiveDominantDevelopmentMatPaths{developmentIdx};
    expectedHash = protocol. ...
        adaptiveDominantDevelopmentMatSha256{developmentIdx};
end
if ~strcmp(computeFileSha256(path), expectedHash)
    error('Frozen confirmation baseline hash mismatch.');
end
loaded = load(path, 'summary');
baseline = findArm(loaded.summary.aggregate, ...
    protocol.adaptiveDominantFullWindowReferenceArmName);
end

function path = findSingleEvidence(rootDirectory, split, seed)
matches = dir(fullfile(rootDirectory, split, ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one confirmation MAT for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function validateSummary(summary, seed, split, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, split) || ...
        summary.options.continuationStartTime ~= protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTimes(1) || ...
        summary.options.maxTimeSteps ~= protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTimes(end) || ...
        ~any(strcmp({summary.aggregate.mode}, protocol. ...
            adaptiveDominantCertifiedOverlapSelectedArmName)) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Certified-overlap confirmation provenance contract failed.');
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Confirmation evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    row.meanMessageCount >= protocol. ...
        adaptiveDominantCertifiedOverlapMinimumMessageCount && ...
    row.meanMessageCount <= protocol. ...
        adaptiveDominantCertifiedOverlapMaximumMessageCount && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.payloadMetadataUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.payloadConstraintFraction == 1 && ...
    row.payloadLimitPassFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, 'evidenceSplit', '', 'runCommit', '', ...
    'evidencePath', '', ...
    'baselineEospa', NaN, 'candidateEospa', NaN, ...
    'gainPercent', NaN, ...
    'baselineWorstEospa', NaN, 'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, 'candidateConsensusOspa', NaN, ...
    'baselineAttemptedBytes', NaN, 'candidateAttemptedBytes', NaN, ...
    'byteDeltaPercent', NaN, 'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, 'selectedFormationB3', NaN, ...
    'deliveredSensorB3', NaN, 'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'payloadMetadataUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'payloadConstraintFraction', NaN, ...
    'payloadLimitPassFraction', NaN, ...
    'repairRate', NaN, 'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, 'distinctRouteMaps', NaN, ...
    'hardSafetyPassed', false);
end

function writeReport(path, confirmation, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Unable to write certified-overlap confirmation report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 certified-overlap Pareto confirmation\n\n');
fprintf(fid, '- Contract: `%s`\n', confirmation.contractVersion);
fprintf(fid, '- Generated: %s\n', confirmation.generatedAt);
fprintf(fid, '- Margin: `%.1f%%`\n', ...
    100 * confirmation.selectedMarginFraction);
fprintf(fid, '- Seeds: `%s`\n', mat2str(confirmation.seeds));
fprintf(fid, '- Window: `%s`\n\n', mat2str(confirmation.times));
fprintf(fid, ['| Seed | Split | CCW E-OSPA | Candidate E-OSPA | ', ...
    'Gain | Byte delta | Msgs | Maps | Safe |\n']);
fprintf(fid, '|--:|:--|--:|--:|--:|--:|--:|--:|:--:|\n');
for row = confirmation.rows
    fprintf(fid, ...
        '| %d | %s | %.6f | %.6f | %+.3f%% | %+.3f%% | %.2f | %.0f | %d |\n', ...
        row.seed, row.evidenceSplit, row.baselineEospa, ...
        row.candidateEospa, row.gainPercent, ...
        row.byteDeltaPercent, row.meanMessageCount, ...
        row.distinctRouteMaps, row.hardSafetyPassed);
end
fprintf(fid, '\n## Registered Pareto confirmation gate\n\n');
fprintf(fid, '- Mean E-OSPA gain: `%+.3f%%`\n', ...
    confirmation.meanGainPercent);
fprintf(fid, '- Positive-seed fraction: `%.3f`\n', ...
    confirmation.positiveSeedFraction);
fprintf(fid, '- Aggregate worst-node gain: `%+.3f%%`\n', ...
    confirmation.aggregateWorstGainPercent);
fprintf(fid, '- Aggregate consensus gain: `%+.3f%%`\n', ...
    confirmation.aggregateConsensusGainPercent);
fprintf(fid, '- Aggregate attempted-byte saving: `%+.3f%%`\n', ...
    confirmation.aggregateByteSavingPercent);
fprintf(fid, '- Maximum positive byte delta: `%+.3f%%`\n', ...
    confirmation.maximumPositiveByteDeltaPercent);
fprintf(fid, '- Required minimum byte saving: `%.3f%%`\n', ...
    protocol. ...
        adaptiveDominantCertifiedOverlapParetoMinimumMeanByteSavingPercent);
fprintf(fid, '- Hard safety passed: `%d`\n', ...
    confirmation.hardSafetyPassed);
fprintf(fid, '- Tracking gate passed: `%d`\n', ...
    confirmation.trackingGatePassed);
fprintf(fid, '- Tail gate passed: `%d`\n', ...
    confirmation.tailGatePassed);
fprintf(fid, '- Communication gate passed: `%d`\n', ...
    confirmation.communicationGatePassed);
fprintf(fid, '- Confirmation gate passed: `%d`\n', ...
    confirmation.confirmationGatePassed);
fprintf(fid, '- Fresh validation claim allowed: `%d`\n', ...
    confirmation.validationClaimAllowed);
fprintf(fid, '- Next: `%s`\n\n', confirmation.nextDirection);
fprintf(fid, '%s\n', confirmation.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
