function [reportPath, result] = runUntouchedPriorExclusionV284(options)
% Paired startup intervention. Reuse V282; never rerun its reference filter.
baselinePath = options.baselineTracePath;
loaded = load(baselinePath, 'trace'); baseline = loaded.trace;
maximumTime = getField(options, 'maximumTime', 40);
assert(isscalar(maximumTime) && maximumTime == round(maximumTime) && ...
    maximumTime >= 1 && maximumTime <= baseline.maximumTime);
assert(strcmp(baseline.presetName, ...
    'x36-formation-fov-temporal-coupled-formation-braid') && baseline.seed == 1301);
out = options.outputRoot;
if exist(out, 'dir') ~= 7, mkdir(out); end
rawPath = fullfile(out, 'UNTOUCHED_PRIOR_EXCLUSION_V284_RAW.mat');
if exist(rawPath, 'file') == 2
    loaded = load(rawPath, 'run'); run = loaded.run;
    assert(run.maximumTime == maximumTime && strcmp(run.baselineTracePath, baselinePath));
else
    % Full generation precedes truncation so the original random inputs stay paired.
    inputs = generateDynamicTopologyScenarioInputs(baseline.presetName, baseline.seed);
    assert(inputs.config.simulationLength == baseline.originalTimeCount);
    inputs = cropInputs(inputs, maximumTime);
    model = removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
    config = buildCausalMinimumFormationBackboneV242Config(inputs.config);
    config.untouchedPriorExclusionEnabled = true;
    config.diagnosticsProgressInterval = 5;
    context = buildCausalMinimumFormationBackboneV242ExecutionContext( ...
        baseline.presetName, baseline.seed, maximumTime);
    protocol = getCausalMinimumFormationBackboneV242Protocol();
    [~, commit] = system('git rev-parse HEAD');
    rng(baseline.seed + protocol.filterSeedOffset, 'twister');
    fprintf('V284 intervention: %s, seed %d, prefix 1:%d of %d.\n', ...
        baseline.presetName, baseline.seed, maximumTime, baseline.originalTimeCount);
    started = tic;
    [estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
        model, inputs.measurements, inputs.sensorTrajectories, ...
        inputs.neighborMap, inputs.commConfig, config, context);
    run = struct('contractVersion', 'untouched-prior-exclusion-v284-v1', ...
        'generationGitCommit', strtrim(commit), 'baselineTracePath', baselinePath, ...
        'baselineGenerationGitCommit', baseline.generationGitCommit, ...
        'presetName', baseline.presetName, 'seed', baseline.seed, ...
        'maximumTime', maximumTime, 'originalTimeCount', baseline.originalTimeCount, ...
        'elapsedSeconds', toc(started), 'completedAt', datestr(now, 31), ...
        'config', inputs.config, 'groundTruthRfs', inputs.groundTruthRfs, ...
        'estimates', {estimates}, 'attempted', diagnostics.attempted, ...
        'delivered', diagnostics.delivered, ...
        'attemptedPayloadBytes', diagnostics.attemptedPayloadBytes, ...
        'attemptedLineageMetadataBytes', diagnostics.attemptedLineageMetadataBytes, ...
        'lineageExcludedSourceCount', diagnostics.lineageExcludedSourceCount, ...
        'lineageInformedFusedLabelCount', diagnostics.lineageInformedFusedLabelCount, ...
        'developmentEvidenceOnly', true);
    % No live model or trigger config: their function handles cannot be saved as MAT7.
    save('-mat7-binary', [rawPath, '.partial'], 'run');
    movefile([rawPath, '.partial'], rawPath);
    fprintf('V284 raw output saved after %.1f seconds: %s\n', run.elapsedSeconds, rawPath);
end
truth = run.groundTruthRfs;
reference = summarizePrefix(baseline, truth, run.config, maximumTime);
candidate = summarizePrefix(run, truth, run.config, maximumTime);
common = isfinite(reference.rmseBySensorTime) & isfinite(candidate.rmseBySensorTime);
commonReferenceRmse = finiteMean(reference.rmseBySensorTime(common));
commonCandidateRmse = finiteMean(candidate.rmseBySensorTime(common));
formationChange = 100 * (candidate.perFormationEospa ./ reference.perFormationEospa - 1);
result = struct('contractVersion', 'untouched-prior-exclusion-v284-analysis-v1', ...
    'rawPath', rawPath, 'generationGitCommit', run.generationGitCommit, ...
    'maximumTime', maximumTime, 'seed', run.seed, 'presetName', run.presetName, ...
    'reference', reference, 'candidate', candidate, ...
    'commonFiniteCellCount', nnz(common), ...
    'commonReferenceRmse', commonReferenceRmse, ...
    'commonCandidateRmse', commonCandidateRmse, ...
    'attemptedRouteDifferences', nnz(xor( ...
        run.attempted, baseline.attempted(:, :, 1:maximumTime))), ...
    'deliveredRouteDifferences', nnz(xor( ...
        run.delivered, baseline.delivered(:, :, 1:maximumTime))), ...
    'eospaImprovementPercent', 100 * (1 - candidate.eospa / reference.eospa), ...
    'commonRmseChangePercent', 100 * (commonCandidateRmse / commonReferenceRmse - 1), ...
    'attemptedByteRatio', candidate.attemptedBytes / reference.attemptedBytes, ...
    'formationEospaChangePercent', formationChange, ...
    'lineageMetadataBytes', sum(run.attemptedLineageMetadataBytes(:)), ...
    'lineageExclusionCount', sum(run.lineageExcludedSourceCount(:)), ...
    'lineageExclusionsByTime', sum(run.lineageExcludedSourceCount, 1), ...
    'screenEvaluated', maximumTime == 40, 'developmentEvidenceOnly', true);
result.screenPassed = result.screenEvaluated && ...
    result.eospaImprovementPercent >= 1 && ...
    candidate.countError < reference.countError && ...
    candidate.representativeDisagreement <= reference.representativeDisagreement && ...
    isfinite(result.commonRmseChangePercent) && result.commonRmseChangePercent <= 1 && ...
    result.attemptedByteRatio <= 1.05 && max(formationChange) <= 1 && ...
    result.attemptedRouteDifferences == 0 && result.deliveredRouteDifferences == 0;
save('-mat7-binary', fullfile(out, 'UNTOUCHED_PRIOR_EXCLUSION_V284.mat'), 'result');
reportPath = fullfile(out, 'UNTOUCHED_PRIOR_EXCLUSION_V284_REPORT.md');
writeReport(reportPath, result);
writeSensorCsv(fullfile(out, 'V284_SENSOR_METRICS.csv'), result, run.config);
fprintf('V284 prefix %d: E-OSPA %.6f -> %.6f (%+.3f%% gain), bytes ratio %.4f, screen evaluated %d / passed %d.\n', ...
    maximumTime, reference.eospa, candidate.eospa, result.eospaImprovementPercent, ...
    result.attemptedByteRatio, result.screenEvaluated, result.screenPassed);
end

function summary = summarizePrefix(data, truth, config, timeCount)
sensorCount = numel(data.estimates);
eospa = zeros(sensorCount, timeCount); countError = eospa; rmse = nan(size(eospa));
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable'); representatives = zeros(1, numel(groups));
for g = 1:numel(groups), representatives(g) = find(groupIds == groups(g), 1); end
for n = 1:sensorCount
    rmse(n, :) = computeSetRmseOverTime(data.estimates{n}, truth);
    for t = 1:timeCount
        c = computePositionEuclideanOspa(truth.x{t}, ...
            data.estimates{n}.mu{t}, config.ospaPositionCutoff, 2, [1, 2]);
        eospa(n, t) = c(1);
        countError(n, t) = abs(numel(data.estimates{n}.mu{t}) - numel(truth.x{t}));
    end
end
disagreement = zeros(1, timeCount);
for t = 1:timeCount
    values = zeros(1, nchoosek(numel(representatives), 2)); k = 0;
    for a = 1:numel(representatives)-1
        for b = a+1:numel(representatives)
            k = k + 1;
            c = computePositionEuclideanOspa(data.estimates{representatives(a)}.mu{t}, ...
                data.estimates{representatives(b)}.mu{t}, config.ospaPositionCutoff, 2, [1, 2]);
            values(k) = c(1);
        end
    end
    disagreement(t) = mean(values);
end
perSensorEospa = mean(eospa, 2); perSensorRmse = nan(sensorCount, 1);
for n = 1:sensorCount, perSensorRmse(n) = finiteMean(rmse(n, :)); end
perFormationEospa = zeros(1, numel(groups));
for g = 1:numel(groups)
    perFormationEospa(g) = mean(perSensorEospa(groupIds == groups(g)));
end
bytes = data.attemptedPayloadBytes(:, :, 1:timeCount);
attempted = data.attempted(:, :, 1:timeCount); delivered = data.delivered(:, :, 1:timeCount);
summary = struct('eospa', mean(eospa(:)), 'conditionalRmse', finiteMean(rmse(:)), ...
    'countError', mean(countError(:)), 'representativeDisagreement', mean(disagreement), ...
    'finiteRmseFraction', nnz(isfinite(rmse)) / numel(rmse), ...
    'attemptedBytes', sum(bytes(:)), 'deliveredBytes', sum(bytes(logical(delivered))), ...
    'attemptedMessages', nnz(attempted), 'deliveredMessages', nnz(delivered), ...
    'eospaBySensorTime', eospa, 'rmseBySensorTime', rmse, ...
    'countErrorBySensorTime', countError, 'disagreementByTime', disagreement, ...
    'perSensorEospa', perSensorEospa, 'perSensorRmse', perSensorRmse, ...
    'perFormationEospa', perFormationEospa, 'worstSensorEospa', max(perSensorEospa), ...
    'representatives', representatives);
end

function writeReport(path, r)
fid = fopen(path, 'w'); assert(fid >= 0); cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# V284 untouched-prior exclusion: paired prefix\n\n');
fprintf(fid, 'X36, seed 1301, steps 1--%d of the original 160-step scene. Source `%s`.\n\n', ...
    r.maximumTime, r.generationGitCommit);
fprintf(fid, 'Development evidence, self-check only. The reference is reused from V282; no baseline filter rerun.\n\n');
fprintf(fid, '| Metric (lower is better) | V242 reference | V284 intervention |\n| --- | ---: | ---: |\n');
names = {'E-OSPA', 'Count absolute error', 'Conditional matched RMSE', ...
    'Representative disagreement, entire prefix', 'Worst-node E-OSPA', ...
    'Attempted payload bytes', 'Delivered payload bytes', 'Attempted messages', 'Delivered messages'};
fields = {'eospa', 'countError', 'conditionalRmse', 'representativeDisagreement', ...
    'worstSensorEospa', 'attemptedBytes', 'deliveredBytes', 'attemptedMessages', 'deliveredMessages'};
for k = 1:numel(fields)
    fprintf(fid, '| %s | %.6f | %.6f |\n', names{k}, r.reference.(fields{k}), r.candidate.(fields{k}));
end
fprintf(fid, '\nCommon-finite-cell RMSE: %.6f -> %.6f over %d cells; change %+.3f%%.\n', ...
    r.commonReferenceRmse, r.commonCandidateRmse, r.commonFiniteCellCount, r.commonRmseChangePercent);
fprintf(fid, 'Finite RMSE fractions (not an accuracy metric): %.6f -> %.6f.\n', ...
    r.reference.finiteRmseFraction, r.candidate.finiteRmseFraction);
fprintf(fid, 'Attempted / delivered route differences: %d / %d. Metadata bytes: %d (included above); excluded source-label pools: %d.\n\n', ...
    r.attemptedRouteDifferences, r.deliveredRouteDifferences, r.lineageMetadataBytes, r.lineageExclusionCount);
fprintf(fid, '| Formation | V242 E-OSPA | V284 E-OSPA | Change (%%) |\n| --- | ---: | ---: | ---: |\n');
for g = 1:numel(r.formationEospaChangePercent)
    fprintf(fid, '| %d | %.6f | %.6f | %+.3f |\n', g, r.reference.perFormationEospa(g), ...
        r.candidate.perFormationEospa(g), r.formationEospaChangePercent(g));
end
fprintf(fid, '\nScreen evaluated: %d. Screen passed: %d. A two-step run is integration only.\n\n', ...
    r.screenEvaluated, r.screenPassed);
fprintf(fid, 'This is not a full-episode or held-out result. Prefix disagreement is not the paper focus-window metric. Lower conditional RMSE alone cannot establish set recovery.\n');
fprintf(fid, 'A passing prefix requires a full-episode fixed-routing arm with the same semantic rule before attributing gains to routing; a failed screen closes startup-only follow-ups under the design.\n');
end

function writeSensorCsv(path, r, config)
fid = fopen(path, 'w'); assert(fid >= 0); cleanup = onCleanup(@() fclose(fid));
fprintf(fid, 'sensor,formation,reference_eospa,candidate_eospa,reference_conditional_rmse,candidate_conditional_rmse\n');
for n = 1:numel(r.reference.perSensorEospa)
    fprintf(fid, '%d,%d,%.12g,%.12g,%.12g,%.12g\n', n, config.sensorGroupIds(n), ...
        r.reference.perSensorEospa(n), r.candidate.perSensorEospa(n), ...
        r.reference.perSensorRmse(n), r.candidate.perSensorRmse(n));
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.config.simulationLength = maximumTime;
inputs.model.simulationLength = maximumTime;
inputs.model.dynamicTopologyScenario.config.simulationLength = maximumTime;
for n = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{n} = inputs.sensorTrajectories{n}(:, 1:maximumTime);
end
for name = {'x', 'mu', 'Sigma'}
    inputs.groundTruthRfs.(name{1}) = inputs.groundTruthRfs.(name{1})(1:maximumTime);
end
inputs.groundTruthRfs.cardinality = inputs.groundTruthRfs.cardinality(1:maximumTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
if isfield(inputs.commConfig, 'linkUniforms') && ndims(inputs.commConfig.linkUniforms) >= 3
    inputs.commConfig.linkUniforms = inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = inputs.graphData.positions(:, :, 1:maximumTime);
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = mean(values); end
end

function value = getField(s, name, fallback)
if isfield(s, name), value = s.(name); else, value = fallback; end
end
