function [datasetPaths, summary] = ...
    generateDirectedRoutingTeacherSeries( ...
        presetName, seedList, snapshotTimes, options)
% GENERATEDIRECTEDROUTINGTEACHERSERIES Build behavior-continuation labels.
%
% The generator resumes from a common static-prefix posterior, follows the
% selected registered directed behavior, and captures pre-fusion local
% posteriors at requested times. A privileged one-step teacher then creates
% labels, while all stored action features remain truth-free. Oracle-tree
% behavior nevertheless makes the sampled posterior-state distribution
% truth-assisted.

if nargin < 1 || isempty(presetName)
    presetName = 'm24-hard';
end
if nargin < 2 || isempty(seedList)
    seedList = [7, 11, 17];
end
if nargin < 3 || isempty(snapshotTimes)
    snapshotTimes = 76:77;
end
if nargin < 4 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
snapshotTimes = unique(round(reshape(snapshotTimes, 1, [])));
continuationStartTime = round(getField( ...
    options, 'continuationStartTime', min(snapshotTimes)));
if continuationStartTime > min(snapshotTimes)
    error('continuationStartTime must not exceed the first snapshot.');
end
sourceWeight = getField(options, 'sourceWeight', 0.50);
behaviorPolicy = lower(strrep(char(getField( ...
    options, 'behaviorPolicy', 'round-robin-balanced')), '_', '-'));
switch behaviorPolicy
    case 'round-robin-balanced'
        behaviorTag = 'rr';
    case 'fixed-index-star'
        behaviorTag = 'fixed';
    case 'oracle-tree-v4'
        behaviorTag = 'oracle_v4';
    otherwise
        error('Unsupported teacher-series behavior policy: %s', ...
            behaviorPolicy);
end
teacherSeriesContractVersion = ...
    'directed-teacher-series-v2-receiver-row-previous-adjacency';
datasetTag = [behaviorTag, '_ctxv2'];
baselinePhase = max(1, round(getField( ...
    options, 'baselinePhase', 1)));
behaviorCacheDirectory = getField(options, ...
    'behaviorCacheDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'cache'));
outputDirectory = getField(options, 'outputDirectory', ...
    behaviorCacheDirectory);
overwrite = logical(getField(options, 'overwrite', false));
teacherLabelVersion = ...
    'joint-action-bernoulli-risk-v3-directed-physical';
teacherOptions = getField(options, 'teacherOptions', struct( ...
    'maxMessagesPerReceiver', 1, ...
    'sourceWeightGrid', sourceWeight, ...
    'minimumRelativeNodeGain', 0, ...
    'deliveryExpectationMode', 'bernoulli-risk'));
if ~any(abs(reshape( ...
        teacherOptions.sourceWeightGrid, 1, []) - sourceWeight) < 1e-12)
    error('teacherOptions must include the registered source weight.');
end
cacheContract = behaviorContinuationCacheContract();

if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
datasetPaths = cell(1, numel(seedList) * numel(snapshotTimes));
records = repmat(struct( ...
    'seed', NaN, 'snapshotTime', NaN, ...
    'datasetPath', '', 'generationSeconds', NaN, ...
    'reused', false), 1, numel(datasetPaths));
outputCursor = 0;

for seed = seedList
    inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
    if any(snapshotTimes < 1 | ...
            snapshotTimes > inputs.config.simulationLength)
        error('Requested snapshot lies outside the scenario.');
    end
    inputs = cropInputs(inputs, max(snapshotTimes));
    [initialPosteriors, continuationHistory, cachePath] = ...
        loadContinuationPosterior( ...
        behaviorCacheDirectory, presetName, seed, ...
        continuationStartTime, inputs.config);
    triggerConfig = buildMixtureAwareKlaReferenceConfig();
    triggerConfig.eventPolicy = 'alwaysHeavy';
    triggerConfig.dynamicTopologyEnabled = true;
    triggerConfig.dynamicTopologyEdgeBudget = inputs.config.edgeBudget;
    triggerConfig.topologyMaxEdgeChangeFraction = inf;
    triggerConfig.topologyDirectedEnabled = true;
    triggerConfig.topologyDirectedMessageBudget = ...
        inputs.config.numberOfSensors;
    triggerConfig.topologyPolicyName = ...
        ['teacher-series-', behaviorPolicy];
    if strcmp(behaviorPolicy, 'oracle-tree-v4')
        policyOptions = struct( ...
            'sourceWeight', sourceWeight, ...
            'baselineMode', 'fixed-index-star', ...
            'requirePreviousUnionStrongConnectivity', true);
        triggerConfig.topologyPolicyFcn = ...
            @(context) selectFormationTreeRoutingTeacher( ...
                context, policyOptions);
    else
        policyOptions = struct( ...
            'sourceWeight', sourceWeight, ...
            'phase', baselinePhase);
        triggerConfig.topologyPolicyFcn = ...
            @(context) selectRegisteredDirectedRoutingPolicy( ...
                context, behaviorPolicy, policyOptions);
    end
    triggerConfig.topologyPosteriorCaptureTimes = snapshotTimes;
    triggerConfig.filterInitialLocalPosteriorBySensor = ...
        initialPosteriors;
    triggerConfig.filterInitialLocalPosteriorTime = ...
        continuationStartTime;
    if size(continuationHistory. ...
            selectedDirectedEdgeHistory, 3) > 0
        triggerConfig.filterInitialPreviousAdjacencyHistory = ...
            convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
                continuationHistory.selectedDirectedEdgeHistory);
        triggerConfig.filterInitialPreviousAdjacencyTimes = ...
            continuationHistory.times;
        triggerConfig.filterInitialPreviousAdjacencyHistorySource = ...
            'behavior-filter-diagnostics-cache-v2';
    end

    rng(seed + getField(options, 'filterSeedOffset', 100000));
    behaviorTimer = tic;
    [~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, triggerConfig);
    behaviorSeconds = toc(behaviorTimer);
    fprintf(['%s teacher series: %s seed %d, t=%d:%d, ', ...
        'behavior %.2f s\n'], behaviorPolicy, presetName, seed, ...
        continuationStartTime, max(snapshotTimes), behaviorSeconds);

    for snapshotTime = snapshotTimes
        outputCursor = outputCursor + 1;
        datasetPath = fullfile(outputDirectory, sprintf( ...
            'directed_teacher_%s_%s_seed%d_t%d.mat', ...
            datasetTag, strrep(presetName, '-', '_'), ...
            seed, snapshotTime));
        datasetPaths{outputCursor} = datasetPath;
        records(outputCursor).seed = seed;
        records(outputCursor).snapshotTime = snapshotTime;
        records(outputCursor).datasetPath = datasetPath;
        if exist(datasetPath, 'file') == 2 && ~overwrite
            validateExistingDataset( ...
                datasetPath, presetName, seed, snapshotTime, ...
                teacherLabelVersion, teacherSeriesContractVersion, ...
                sourceWeight, behaviorPolicy);
            records(outputCursor).reused = true;
            records(outputCursor).generationSeconds = 0;
            fprintf('  reused dataset: %s\n', datasetPath);
            continue;
        end
        localPosteriors = ...
            diagnostics.topologyLocalPosteriorSnapshot{snapshotTime};
        if isempty(localPosteriors)
            error('Missing behavior posterior snapshot at t=%d.', ...
                snapshotTime);
        end
        context = buildTeacherContext( ...
            inputs, diagnostics, localPosteriors, ...
            snapshotTime, continuationStartTime);
        teacherTimer = tic;
        [~, teacherDetails] = ...
            selectDirectedTaskRoutingTeacher(context, teacherOptions);
        [features, featureNames, nodeSummary] = ...
            computeDirectedRoutingFeatures(context);
        actionFeatureOptions = struct( ...
            'rawFeatures', features, ...
            'rawFeatureNames', {featureNames});
        [actionFeatures, actionFeatureNames, ...
            actionFeatureMetadata] = ...
            computeScaleInvariantDirectedActionFeatures( ...
                context, teacherDetails.sourceWeightGrid, ...
                actionFeatureOptions);
        generationSeconds = toc(teacherTimer);
        behaviorTruthUsed = ...
            strcmp(behaviorPolicy, 'oracle-tree-v4');
        previousFormationAdjacency = ...
            formationAdjacencyFromSensorAdjacency( ...
                context.previousAdjacency, ...
                inputs.config.sensorGroupIds);
        datasetMetadata = struct( ...
            'presetName', presetName, ...
            'seed', seed, ...
            'snapshotTime', snapshotTime, ...
            'behaviorCachePath', cachePath, ...
            'behaviorCacheContractVersion', ...
                cacheContract.version, ...
            'behaviorPolicy', behaviorPolicy, ...
            'behaviorTruthUsed', behaviorTruthUsed, ...
            'behaviorContinuationStartTime', ...
                continuationStartTime, ...
            'behaviorSourceWeight', sourceWeight, ...
            'behaviorBaselinePhase', baselinePhase, ...
            'teacherOptions', teacherOptions, ...
            'teacherLabelVersion', teacherLabelVersion, ...
            'teacherSeriesContractVersion', ...
                teacherSeriesContractVersion, ...
            'deliveryExpectationMode', ...
                teacherDetails.deliveryExpectationMode, ...
            'physicalAdjacencyConvention', ...
                'receiver-row-sender-column-directed', ...
            'previousAdjacencyConvention', ...
                'receiver-row-sender-column-directed', ...
            'scenarioConfigSnapshot', inputs.config, ...
            'fusionConfigSnapshot', context.triggerConfig, ...
            'previousFormationAdjacency', ...
                previousFormationAdjacency, ...
            'teacherLabelsUseTruth', true, ...
            'truthUsedForLabelsOnly', ~behaviorTruthUsed, ...
            'featuresUseTruth', false);
        save('-mat7-binary', datasetPath, ...
            'features', 'featureNames', 'nodeSummary', ...
            'actionFeatures', 'actionFeatureNames', ...
            'actionFeatureMetadata', ...
            'teacherDetails', 'datasetMetadata');
        records(outputCursor).generationSeconds = generationSeconds;
        fprintf('  wrote t=%d in %.2f s: %s\n', ...
            snapshotTime, generationSeconds, datasetPath);
    end
end

summary = struct( ...
    'generatedAt', datestr(now, 31), ...
    'presetName', presetName, ...
    'seeds', seedList, ...
    'snapshotTimes', snapshotTimes, ...
    'continuationStartTime', continuationStartTime, ...
    'sourceWeight', sourceWeight, ...
    'behaviorPolicy', behaviorPolicy, ...
    'teacherSeriesContractVersion', ...
        teacherSeriesContractVersion, ...
    'baselinePhase', baselinePhase, ...
    'records', records, ...
    'datasetPaths', {datasetPaths});
end

function context = buildTeacherContext( ...
        inputs, diagnostics, posteriors, ...
        snapshotTime, continuationStartTime)
sensorCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = posteriors;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = snapshotTime;
if snapshotTime <= continuationStartTime
    context.previousAdjacency = inputs.graphData.staticAdjacency;
else
    context.previousAdjacency = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, snapshotTime - 1));
end
context.previousAdjacency(1:sensorCount+1:end) = false;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, snapshotTime);
context.edgeScores = double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * inputs.config.edgeBudget;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, snapshotTime);
end
end

function [posteriors, history, cachePath] = ...
    loadContinuationPosterior( ...
        directory, presetName, seed, startTime, config)
cachePath = fullfile(directory, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', ...
    strrep(presetName, '-', '_'), seed, startTime));
if exist(cachePath, 'file') ~= 2
    error('Missing continuation cache: %s', cachePath);
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Continuation cache has no behaviorBundle: %s', cachePath);
end
bundle = loaded.behaviorBundle;
expectedConfig = buildMixtureAwareKlaReferenceConfig();
expectedConfig.dynamicTopologyEnabled = false;
expectedConfig.topologyPosteriorCaptureTimes = startTime;
valid = strcmp(bundle.presetName, presetName) && ...
    bundle.seed == seed && ...
    isequaln(bundle.configSnapshot, config) && ...
    isequaln(bundle.behaviorConfigSnapshot, expectedConfig) && ...
    isequal(bundle.snapshotTimes, startTime);
if ~valid
    error('Continuation cache metadata mismatch: %s', cachePath);
end
try
    [posteriors, history] = ...
        extractBehaviorContinuationSnapshot( ...
            bundle, startTime, config.numberOfSensors);
catch errorInfo
    error(['Continuation cache history contract mismatch (%s): ', ...
        '%s'], errorInfo.identifier, cachePath);
end
end

function validateExistingDataset( ...
        path, presetName, seed, snapshotTime, ...
        labelVersion, seriesContractVersion, ...
        sourceWeight, behaviorPolicy)
loaded = load(path, 'datasetMetadata', ...
    'actionFeatureMetadata', 'teacherDetails');
required = {'datasetMetadata', ...
    'actionFeatureMetadata', 'teacherDetails'};
if ~all(isfield(loaded, required))
    error('Existing teacher-series dataset is incomplete: %s', path);
end
metadata = loaded.datasetMetadata;
cacheContract = behaviorContinuationCacheContract();
weightGrid = reshape( ...
    loaded.actionFeatureMetadata.sourceWeightGrid, 1, []);
valid = strcmp(metadata.presetName, presetName) && ...
    metadata.seed == seed && ...
    metadata.snapshotTime == snapshotTime && ...
    strcmp(metadata.teacherLabelVersion, labelVersion) && ...
    isfield(metadata, 'teacherSeriesContractVersion') && ...
    strcmp(metadata.teacherSeriesContractVersion, ...
        seriesContractVersion) && ...
    isfield(metadata, 'behaviorCacheContractVersion') && ...
    strcmp(metadata.behaviorCacheContractVersion, ...
        cacheContract.version) && ...
    ~metadata.featuresUseTruth && ...
    isfield(metadata, 'teacherLabelsUseTruth') && ...
    metadata.teacherLabelsUseTruth && ...
    isfield(metadata, 'behaviorPolicy') && ...
    strcmp(metadata.behaviorPolicy, behaviorPolicy) && ...
    isfield(metadata, 'behaviorTruthUsed') && ...
    metadata.behaviorTruthUsed == ...
        strcmp(behaviorPolicy, 'oracle-tree-v4') && ...
    isfield(metadata, 'truthUsedForLabelsOnly') && ...
    metadata.truthUsedForLabelsOnly == ...
        ~metadata.behaviorTruthUsed && ...
    isfield(metadata, 'previousFormationAdjacency') && ...
    isfield(metadata, 'previousAdjacencyConvention') && ...
    strcmp(metadata.previousAdjacencyConvention, ...
        'receiver-row-sender-column-directed') && ...
    any(abs(weightGrid - sourceWeight) < 1e-12) && ...
    strcmp(loaded.teacherDetails.deliveryExpectationMode, ...
        'bernoulli-risk');
if ~valid
    error('Existing teacher-series dataset contract mismatch: %s', path);
end
end

function adjacency = formationAdjacencyFromSensorAdjacency( ...
        sensorAdjacency, groupIds)
groups = unique(groupIds, 'stable');
groupCount = numel(groups);
adjacency = false(groupCount);
sensorAdjacency = logical(sensorAdjacency);
for receiverIdx = 1:numel(groupIds)
    receiverGroup = find(groups == groupIds(receiverIdx), 1);
    for senderIdx = reshape(find(sensorAdjacency(receiverIdx, :)), 1, [])
        senderGroup = find(groups == groupIds(senderIdx), 1);
        if receiverGroup ~= senderGroup
            adjacency(senderGroup, receiverGroup) = true;
        end
    end
end
end

function inputs = cropInputs(inputs, maxTime)
maxTime = min(max(1, round(maxTime)), size(inputs.measurements, 2));
inputs.measurements = inputs.measurements(:, 1:maxTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maxTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maxTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maxTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maxTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maxTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maxTime);
inputs.model.simulationLength = maxTime;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
