    audit.expandedRewardDatasetAuthorized);
fprintf(fid, ['- Bandit / development / held-out M24 / X36 ', ...
    'authorized: `%d / %d / %d / %d`\n'], ...
    audit.banditImplementationAuthorized, ...
    audit.developmentEvaluationAuthorized, ...
    audit.heldoutM24Authorized, ...
    audit.x36PolicyRunAuthorized);
end

function correlation = computeSpearman(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
valid = isfinite(left) & isfinite(right);
left = left(valid);
right = right(valid);
if numel(left) < 3 || numel(unique(left)) < 2 || ...
        numel(unique(right)) < 2
    correlation = NaN;
    return;
end
leftRanks = averageRanks(left);
rightRanks = averageRanks(right);
matrix = corrcoef(leftRanks, rightRanks);
correlation = matrix(1, 2);
end

function ranks = averageRanks(values)
[sortedValues, order] = sort(values);
ranks = zeros(size(values));
startIdx = 1;
while startIdx <= numel(values)
    endIdx = startIdx;
    while endIdx < numel(values) && ...
            sortedValues(endIdx + 1) == ...
                sortedValues(startIdx)
        endIdx = endIdx + 1;
    end
    ranks(order(startIdx:endIdx)) = ...
        0.5 * (startIdx + endIdx);
    startIdx = endIdx + 1;
end
end

function names = prependNames(source, prefix)
names = cellfun(@(name) [prefix, name], source, ...
    'UniformOutput', false);
end

function action = emptyAction()
action = struct( ...
    'sourceRowIndex', NaN, 'pairId', NaN, ...
    'seed', NaN, 'currentTime', NaN, ...
    'receiverIdx', NaN, 'senderIdx', NaN, ...
    'weightIdx', NaN, 'role', '', ...
    'edgeOnly', zeros(1, 0), ...
    'relational', zeros(1, 0), ...
    'scoreAdvantage', NaN, ...
    'trueTaskAdvantage', NaN, ...
    'canonicalKey', NaN);
end

function pair = emptyPair()
pair = struct( ...
    'pairId', NaN, 'seed', NaN, ...
    'currentTime', NaN, ...
    'actionA', NaN, 'actionB', NaN, ...
    'observedScoreDifference', NaN, ...
    'trueTaskDifference', NaN);
end

function fold = emptyFold()
fold = struct( ...
    'heldoutSeed', NaN, 'fitSeeds', zeros(1, 0), ...
    'selectedFeatureVariant', '', ...
    'selectedLambda', NaN, ...
    'innerSurrogatePairwiseAccuracy', NaN, ...
    'innerSurrogateDifferenceSpearman', NaN, ...
    'heldoutPairIndices', zeros(1, 0), ...
    'metrics', struct());
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
