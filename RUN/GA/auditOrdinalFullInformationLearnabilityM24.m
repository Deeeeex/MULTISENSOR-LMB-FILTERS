for fold = audit.outerFolds
    fprintf(fid, '| %d | %s | %.6g | %.4f | %.4f | %.4f | %.4f |\n', ...
        fold.heldoutSeed, fold.selectedFeatureVariant, ...
        fold.selectedLambda, ...
