    'selected task advantage): `%d / %d / %d / %d / %d / %d`\n'], ...
    audit.gates.source, audit.gates.surrogatePairwise, ...
    audit.gates.surrogateRank, audit.gates.perSeedRank, ...
    audit.gates.taskPreference, ...
    audit.gates.selectedTaskAdvantage);
fprintf(fid, '- All gates passed: `%d`\n', ...
    audit.allGatesPassed);
