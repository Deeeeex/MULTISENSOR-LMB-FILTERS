function [auditPath, audit] = ...
    auditOrdinalFullInformationLearnabilityM24(options)
% AUDITORDINALFULLINFORMATIONLEARNABILITYM24 Nested seed-level preflight.
%
% The delayed IID-cluster score is deployment-observable. This audit asks
% whether its pairwise action ordering can be predicted from predecision
% graph features on an unseen training seed. Current tracking truth is
% excluded from fitting and hyperparameter selection, then used only for
% a secondary alignment readout.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getOrdinalFullInformationLearnabilityProtocol();
graphProtocol = getCvarResidualGraphPolicyDatasetProtocol();
gitState = resolveResearchGitState();
if gitState.researchWorktreeDirty
    error('Official ordinal learnability audit requires clean source.');
end
if exist(protocol.sourceAnalysisPath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(protocol.sourceAnalysisPath), ...
            protocol.sourceAnalysisSha256)
    error('Registered IID-cluster action evidence is unavailable.');
end
loaded = load(protocol.sourceAnalysisPath, 'analysis');
if ~isfield(loaded, 'analysis')
    error('IID-cluster action evidence has no analysis payload.');
end
source = loaded.analysis;
bundle = loadCvarResidualGraphPolicyShards('training');
validateSources(source, bundle, protocol, graphProtocol);
[actions, pairs, featureNames] = ...
    assembleExamples(source.rows, bundle.graphBlocks, protocol);

outerFolds = repmat(emptyFold(), ...
    1, numel(protocol.trainingSeeds));
outerPredictedDifference = nan(1, numel(pairs));
for foldIdx = 1:numel(protocol.trainingSeeds)
    heldoutSeed = protocol.trainingSeeds(foldIdx);
    fitSeeds = setdiff(protocol.trainingSeeds, ...
        heldoutSeed, 'stable');
    selection = selectInnerModel( ...
        actions, pairs, fitSeeds, protocol);
    model = fitPairUtilityModel( ...
        actions, pairs, fitSeeds, ...
        selection.featureVariant, ...
        selection.lambda);
    heldoutPairMask = [pairs.seed] == heldoutSeed;
    heldoutPairIndices = find(heldoutPairMask);
    predicted = predictPairDifferences( ...
        model, actions, pairs(heldoutPairMask));
    outerPredictedDifference(heldoutPairMask) = predicted;
    metrics = computeFoldMetrics( ...
        pairs(heldoutPairMask), predicted, actions);
    fold = emptyFold();
    fold.heldoutSeed = heldoutSeed;
    fold.fitSeeds = fitSeeds;
    fold.selectedFeatureVariant = ...
        selection.featureVariant;
    fold.selectedLambda = selection.lambda;
    fold.innerSurrogatePairwiseAccuracy = ...
        selection.pairwiseAccuracy;
    fold.innerSurrogateDifferenceSpearman = ...
        selection.differenceSpearman;
    fold.heldoutPairIndices = heldoutPairIndices;
    fold.metrics = metrics;
    outerFolds(foldIdx) = fold;
end
if any(~isfinite(outerPredictedDifference))
    error('Outer ordinal predictions are incomplete.');
end

outerMetrics = computeFoldMetrics( ...
    pairs, outerPredictedDifference, actions);
perSeedSurrogateSpearman = arrayfun(@(fold) ...
    fold.metrics.surrogateDifferenceSpearman, outerFolds);
positivePerSeedSurrogateSpearmanFraction = mean( ...
    perSeedSurrogateSpearman > 0);
gates = struct();
gates.source = numel(pairs) == ...
    protocol.expectedPairCount && ...
    ~source.scoreTruthUsed && source.targetTruthUsed && ...
    ~bundle.featuresUseTruth && bundle.targetsUseTruth;
gates.surrogatePairwise = ...
    outerMetrics.surrogatePairwiseAccuracy >= ...
        protocol.minimumOuterSurrogatePairwiseAccuracy;
gates.surrogateRank = ...
    isfinite(outerMetrics. ...
        surrogateDifferenceSpearman) && ...
    outerMetrics.surrogateDifferenceSpearman >= ...
        protocol.minimumOuterSurrogateDifferenceSpearman;
gates.perSeedRank = ...
    positivePerSeedSurrogateSpearmanFraction >= ...
        protocol. ...
            minimumPositivePerSeedSurrogateSpearmanFraction;
gates.taskPreference = ...
    outerMetrics.taskPreferenceAccuracy >= ...
        protocol.minimumOuterTaskPreferenceAccuracy;
gates.selectedTaskAdvantage = ...
    outerMetrics.meanSelectedTaskAdvantage >= ...
        protocol.minimumOuterMeanSelectedTaskAdvantage;

audit = struct();
audit.contractVersion = ...
    'ordinal-full-information-learnability-m24-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
audit.protocolId = protocol.id;
audit.sourceAnalysisSha256 = ...
    protocol.sourceAnalysisSha256;
audit.graphDatasetSetSha256 = ...
    bundle.datasetSetSha256;
audit.trainingSeeds = protocol.trainingSeeds;
audit.snapshotTimes = protocol.snapshotTimes;
audit.featureNamesByVariant = featureNames;
audit.actionCount = numel(actions);
audit.pairCount = numel(pairs);
audit.actions = actions;
audit.pairs = pairs;
audit.outerPredictedDifference = ...
    outerPredictedDifference;
audit.outerFolds = outerFolds;
audit.outerMetrics = outerMetrics;
audit.perSeedSurrogateSpearman = ...
    perSeedSurrogateSpearman;
audit.positivePerSeedSurrogateSpearmanFraction = ...
    positivePerSeedSurrogateSpearmanFraction;
audit.modelTrainingUsesTaskTruth = false;
audit.modelSelectionUsesTaskTruth = false;
audit.secondaryTaskAuditUsesTruth = true;
audit.gates = gates;
audit.allGatesPassed = all(structfun( ...
    @(value) logical(value), gates));
audit.expandedRewardDatasetAuthorized = ...
    audit.allGatesPassed;
audit.banditImplementationAuthorized = false;
audit.developmentEvaluationAuthorized = false;
audit.heldoutM24Authorized = false;
audit.x36PolicyRunAuthorized = false;
audit.evidenceBoundary = [ ...
    'Outer and inner splits hold out complete scenario seeds. ', ...
    'Model fitting and hyperparameter selection use only observable ', ...
    'IID-cluster score differences and truth-free graph features. ', ...
    'Current tracking truth is used only for the secondary outer task ', ...
    'alignment readout. A pass authorizes only an expanded observable ', ...
    'reward dataset, not policy deployment or any sealed split.'];

auditPath = getField(options, ...
    'auditPath', protocol.defaultOutputPath);
reportPath = getField(options, ...
    'reportPath', protocol.defaultReportPath);
audit.auditPath = auditPath;
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Ordinal full-information audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function validateSources(source, bundle, protocol, graphProtocol)
required = { ...
    'protocolId', 'generationGitCommit', ...
    'generationResearchWorktreeDirty', ...
    'trainingSeeds', 'snapshotTimes', 'scoreType', ...
    'scoreTruthUsed', 'targetTruthUsed', 'rows'};
if ~isstruct(source) || ~all(isfield(source, required)) || ...
        ~strcmp(source.protocolId, ...
            protocol.predecessorProtocolId) || ...
        ~strcmp(source.generationGitCommit, ...
            protocol.sourceAnalysisGenerationCommit) || ...
        source.generationResearchWorktreeDirty || ...
        ~isequal(source.trainingSeeds, ...
            protocol.trainingSeeds) || ...
        ~isequal(source.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~strcmp(source.scoreType, protocol.scoreType) || ...
        source.scoreTruthUsed || ~source.targetTruthUsed || ...
        numel(source.rows) ~= 2 * ...
            protocol.expectedPairCount || ...
        ~isequal(bundle.seeds, protocol.trainingSeeds) || ...
        ~isequal(bundle.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        bundle.developmentLabelsOpened || ...
        bundle.featuresUseTruth || ~bundle.targetsUseTruth || ...
        ~graphProtocol.developmentOnly || ...
        ~isempty(intersect(protocol.trainingSeeds, ...
            graphProtocol.developmentValidationSeeds)) || ...
        ~isempty(intersect(protocol.trainingSeeds, ...
            graphProtocol.lockedHeldoutM24Seeds))
    error('Ordinal learnability source contract is invalid.');
end
end

function [actions, pairs, namesByVariant] = ...
        assembleExamples(rows, blocks, protocol)
actions = repmat(emptyAction(), 1, numel(rows));
for actionIdx = 1:numel(rows)
    row = rows(actionIdx);
    blockMatches = [blocks.seed] == row.seed & ...
        [blocks.currentTime] == row.currentTime;
    if nnz(blockMatches) ~= 1
        error('Ordinal action graph block is missing.');
    end
    block = blocks(find(blockMatches, 1));
    edgeMatches = block.receiverIndices == ...
        row.receiverIdx & ...
        block.senderIndices == row.senderIdx;
    weightMatches = abs(block.residualWeightGrid - ...
        row.residualWeight) <= 1e-12;
    rowIdx = find(edgeMatches);
    weightIdx = find(weightMatches);
    if numel(rowIdx) ~= 1 || numel(weightIdx) ~= 1
        error('Ordinal action cannot be joined to graph features.');
    end
    edge = reshape(block.edgeFeatures( ...
        rowIdx, weightIdx, :), 1, []);
    receiver = block.nodeFeatures(row.receiverIdx, :);
    sender = block.nodeFeatures(row.senderIdx, :);
    action = emptyAction();
    action.sourceRowIndex = actionIdx;
    action.pairId = row.pairId;
    action.seed = row.seed;
    action.currentTime = row.currentTime;
    action.receiverIdx = row.receiverIdx;
    action.senderIdx = row.senderIdx;
    action.weightIdx = weightIdx;
    action.role = row.role;
    action.edgeOnly = edge;
    action.relational = [ ...
        edge, receiver, sender, receiver - sender];
    action.scoreAdvantage = row.scoreAdvantage;
    action.trueTaskAdvantage = ...
        row.trueTaskAdvantage;
    action.canonicalKey = row.receiverIdx + ...
        size(block.nodeFeatures, 1) * ...
            (row.senderIdx - 1) + ...
        size(block.nodeFeatures, 1)^2 * ...
            (weightIdx - 1);
    if any(~isfinite([ ...
            action.edgeOnly, action.relational, ...
            action.scoreAdvantage, ...
            action.trueTaskAdvantage]))
        error('Ordinal action example is non-finite.');
    end
    actions(actionIdx) = action;
end

pairIds = unique([actions.pairId], 'stable');
pairs = repmat(emptyPair(), 1, numel(pairIds));
for pairIdx = 1:numel(pairIds)
    actionIndices = find( ...
        [actions.pairId] == pairIds(pairIdx));
    if numel(actionIndices) ~= 2 || ...
            actions(actionIndices(1)).seed ~= ...
                actions(actionIndices(2)).seed || ...
            actions(actionIndices(1)).currentTime ~= ...
                actions(actionIndices(2)).currentTime
        error('Ordinal pair is malformed.');
    end
    [~, order] = sort([ ...
        actions(actionIndices).canonicalKey]);
    actionIndices = actionIndices(order);
    pair = emptyPair();
    pair.pairId = pairIds(pairIdx);
    pair.seed = actions(actionIndices(1)).seed;
    pair.currentTime = ...
        actions(actionIndices(1)).currentTime;
    pair.actionA = actionIndices(1);
    pair.actionB = actionIndices(2);
    pair.observedScoreDifference = ...
        actions(pair.actionA).scoreAdvantage - ...
        actions(pair.actionB).scoreAdvantage;
    pair.trueTaskDifference = ...
        actions(pair.actionA).trueTaskAdvantage - ...
        actions(pair.actionB).trueTaskAdvantage;
    if abs(pair.observedScoreDifference) <= 1e-12 || ...
            abs(pair.trueTaskDifference) <= 1e-12
        error('Ordinal pair contains an unresolved tie.');
    end
    pairs(pairIdx) = pair;
end
if numel(pairs) ~= protocol.expectedPairCount || ...
        numel(unique([pairs.pairId])) ~= numel(pairs)
    error('Ordinal pair coverage is incomplete.');
end
firstBlock = blocks(1);
namesByVariant = struct();
namesByVariant.edgeOnly = ...
    firstBlock.edgeFeatureNames;
namesByVariant.relational = [ ...
    firstBlock.edgeFeatureNames, ...
    prependNames(firstBlock.nodeFeatureNames, 'receiver_'), ...
    prependNames(firstBlock.nodeFeatureNames, 'sender_'), ...
    prependNames(firstBlock.nodeFeatureNames, ...
        'receiver_minus_sender_')];
end

function selection = selectInnerModel( ...
        actions, pairs, fitSeeds, protocol)
candidates = repmat(struct( ...
    'featureVariant', '', 'lambda', NaN, ...
    'pairwiseAccuracy', NaN, ...
    'differenceSpearman', NaN), ...
    1, numel(protocol.featureVariants) * ...
        numel(protocol.ridgeLambdaGrid));
cursor = 0;
for variantIdx = 1:numel(protocol.featureVariants)
    featureVariant = ...
        protocol.featureVariants{variantIdx};
    for lambdaIdx = 1:numel(protocol.ridgeLambdaGrid)
        lambda = protocol.ridgeLambdaGrid(lambdaIdx);
        predicted = nan(1, nnz(ismember( ...
            [pairs.seed], fitSeeds)));
        observed = nan(size(predicted));
        writeCursor = 0;
        for innerHeldoutSeed = fitSeeds
            innerFitSeeds = setdiff( ...
                fitSeeds, innerHeldoutSeed, 'stable');
            model = fitPairUtilityModel( ...
                actions, pairs, innerFitSeeds, ...
                featureVariant, lambda);
            mask = [pairs.seed] == innerHeldoutSeed;
            count = nnz(mask);
            indices = writeCursor + (1:count);
            predicted(indices) = ...
                predictPairDifferences( ...
                    model, actions, pairs(mask));
            observed(indices) = ...
                [pairs(mask).observedScoreDifference];
            writeCursor = writeCursor + count;
        end
        cursor = cursor + 1;
        candidates(cursor).featureVariant = ...
            featureVariant;
        candidates(cursor).lambda = lambda;
        candidates(cursor).pairwiseAccuracy = mean( ...
            sign(predicted) == sign(observed));
        candidates(cursor).differenceSpearman = ...
            computeSpearman(predicted, observed);
    end
end
selection = candidates(1);
for candidateIdx = 2:numel(candidates)
    candidate = candidates(candidateIdx);
    if candidate.pairwiseAccuracy > ...
            selection.pairwiseAccuracy + 1e-12 || ...
            (abs(candidate.pairwiseAccuracy - ...
                selection.pairwiseAccuracy) <= 1e-12 && ...
             candidate.differenceSpearman > ...
                selection.differenceSpearman + 1e-12)
        selection = candidate;
    end
end
end

function model = fitPairUtilityModel( ...
        actions, pairs, fitSeeds, featureVariant, lambda)
actionMask = ismember([actions.seed], fitSeeds);
pairMask = ismember([pairs.seed], fitSeeds);
X = selectFeatures(actions(actionMask), featureVariant);
featureMean = mean(X, 1);
featureScale = std(X, 0, 1);
featureScale(~isfinite(featureScale) | ...
    featureScale <= eps) = 1;
pairSubset = pairs(pairMask);
D = zeros(numel(pairSubset), size(X, 2));
y = zeros(numel(pairSubset), 1);
for pairIdx = 1:numel(pairSubset)
    pair = pairSubset(pairIdx);
    left = selectFeatures( ...
        actions(pair.actionA), featureVariant);
    right = selectFeatures( ...
        actions(pair.actionB), featureVariant);
    D(pairIdx, :) = (left - right) ./ featureScale;
    y(pairIdx) = pair.observedScoreDifference;
end
targetScale = std(y);
if ~isfinite(targetScale) || targetScale <= eps
    targetScale = 1;
end
target = y / targetScale;
if size(D, 2) <= size(D, 1)
    coefficient = (D' * D + ...
        lambda * eye(size(D, 2))) \ ...
        (D' * target);
else
    coefficient = D' * ((D * D' + ...
        lambda * eye(size(D, 1))) \ target);
end
if any(~isfinite(coefficient))
    error('Ordinal ridge fit produced non-finite coefficients.');
end
model = struct( ...
    'featureVariant', featureVariant, ...
    'lambda', lambda, ...
    'featureMean', featureMean, ...
    'featureScale', featureScale, ...
    'targetScale', targetScale, ...
    'coefficient', coefficient, ...
    'fitSeeds', fitSeeds, ...
    'taskTruthUsed', false);
end

function predicted = predictPairDifferences(model, actions, pairs)
predicted = zeros(1, numel(pairs));
for pairIdx = 1:numel(pairs)
    left = selectFeatures( ...
        actions(pairs(pairIdx).actionA), ...
        model.featureVariant);
    right = selectFeatures( ...
        actions(pairs(pairIdx).actionB), ...
        model.featureVariant);
    difference = (left - right) ./ ...
        model.featureScale;
    predicted(pairIdx) = ...
        model.targetScale * ...
            (difference * model.coefficient);
end
end

function metrics = computeFoldMetrics(pairs, predicted, actions)
observed = [pairs.observedScoreDifference];
task = [pairs.trueTaskDifference];
selectedTask = zeros(1, numel(pairs));
for pairIdx = 1:numel(pairs)
    if predicted(pairIdx) >= 0
        selectedAction = pairs(pairIdx).actionA;
    else
        selectedAction = pairs(pairIdx).actionB;
    end
    selectedTask(pairIdx) = ...
        actions(selectedAction).trueTaskAdvantage;
end
metrics = struct();
metrics.pairCount = numel(pairs);
metrics.surrogatePairwiseAccuracy = mean( ...
    sign(predicted) == sign(observed));
metrics.surrogateDifferenceSpearman = ...
    computeSpearman(predicted, observed);
metrics.taskPreferenceAccuracy = mean( ...
    sign(predicted) == sign(task));
metrics.taskDifferenceSpearman = ...
    computeSpearman(predicted, task);
metrics.meanSelectedTaskAdvantage = ...
    mean(selectedTask);
metrics.minimumSelectedTaskAdvantage = ...
    min(selectedTask);
end

function X = selectFeatures(actions, variant)
switch variant
    case 'edge-only'
        X = vertcat(actions.edgeOnly);
    case 'edge-receiver-sender-difference'
        X = vertcat(actions.relational);
    otherwise
        error('Unknown ordinal feature variant: %s.', variant);
end
end

