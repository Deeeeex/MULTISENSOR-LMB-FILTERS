function [reportPath, result] = ...
        analyzeObservationSupportedSetEntryRiskV193(options)
% ANALYZEOBSERVATIONSUPPORTEDSETENTRYRISKV193 Support-aware V99 probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v193', 'observation_supported_set_entry'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
caseSpecs = buildCaseSpecs();
records = struct([]);
for caseIdx = 1:size(caseSpecs, 1)
    scaleName = caseSpecs{caseIdx, 1};
    presetName = caseSpecs{caseIdx, 2};
    seed = caseSpecs{caseIdx, 3};
    currentTime = caseSpecs{caseIdx, 4};
    baseScreenPath = caseSpecs{caseIdx, 5};
    fprintf('V193 set-entry risk: %s t=%d ...\n', ...
        scaleName, currentTime);
    loadedScreen = load(baseScreenPath, 'screen');
    state = loadFormationH3ObservableState( ...
        presetName, seed, currentTime, struct( ...
            'cacheRoot', fileparts(loadedScreen.screen.cachePath), ...
            'expectedMissingLabelFusionMode', protocol.receiverMode));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds);
    network = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    support = computeObservationSupportedRoutingLeverage( ...
        control, state.context, state.groupIds, ...
        protocol.positiveSupportThreshold);
    selection = selectPositiveNetAddressableRiskSetV97( ...
        network, protocol);
    groups = reshape(control.groups, 1, []);
    for formationIdx = 1:numel(groups)
        if ~control.singleActionAvailableMask(formationIdx)
            continue;
        end
        score = control.singleActionScores{formationIdx};
        [risk, entry] = computeObservationSupportedLmbSetEntryRisk( ...
            control.referenceScore.networkDetails. ...
                receiverDistributions, ...
            score.networkDetails.receiverDistributions, ...
            state.context.localPosteriorBySensor, state.groupIds, ...
            struct('positiveSupportThreshold', ...
                protocol.positiveSupportThreshold));
        formationId = groups(formationIdx);
        members = find(state.groupIds == formationId);
        [~, worstLocalIdx] = max(entry.receiverRisk(members));
        worstReceiver = members(worstLocalIdx);
        record = emptyRecord();
        record.scaleName = scaleName;
        record.formationId = formationId;
        record.v99Selected = ismember( ...
            formationId, selection.selectedFormationIds);
        record.networkRescueFraction = ...
            network.networkRescueFractionByFormation(formationIdx);
        record.networkUsefulLossFraction = ...
            network.networkUsefulLossFractionByFormation(formationIdx);
        record.supportedShareOfRescue = ...
            support.singlePositiveSupportedShareOfRescue(formationIdx);
        record.supportWeightedRescueFraction = ...
            support.singleSupportWeightedRescuedFractionOfReference( ...
                formationIdx);
        record.mapChangeCount = ...
            entry.cardinality.formationMapChangeCount(formationIdx);
        record.entryCount = entry.formationEntryCount(formationIdx);
        record.unsupportedEntryCount = ...
            entry.formationUnsupportedEntryCount(formationIdx);
        record.unsupportedEntryMass = ...
            entry.formationUnsupportedEntryExistenceMass(formationIdx);
        record.maximumReceiverRisk = ...
            entry.formationMaximumReceiverRisk(formationIdx);
        record.meanReceiverRisk = ...
            entry.formationMeanReceiverRisk(formationIdx);
        record.minimumEntrySupport = ...
            entry.formationMinimumEntrySupport(formationIdx);
        record.worstReceiver = worstReceiver;
        record.worstReferenceMap = ...
            entry.cardinality.referenceMapCardinality(worstReceiver);
        record.worstCandidateMap = ...
            entry.cardinality.candidateMapCardinality(worstReceiver);
        record.worstEnteredLabels = ...
            entry.enteredLabelsByReceiver{worstReceiver};
        record.worstEnteredSupport = ...
            entry.enteredSupportByReceiver{worstReceiver};
        record.risk = risk;
        records(end + 1) = record; %#ok<AGROW>
    end
end

result = struct();
result.contractVersion = ...
    'observation-supported-set-entry-risk-v193-analysis-v1';
result.generatedAt = datestr(now, 31);
result.records = records;
result.truthUsedForFeatures = false;
result.futureInformationUsedForFeatures = false;
result.teacherOutcomeUsedForSelection = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V193 combines the observable V192 cardinality change with current ', ...
    'receiver measurement-association support for labels entering the ', ...
    'marginal LMB extraction.  Numeric label values only align Bernoulli ', ...
    'components.  Opened paired outcomes are not used by the feature and ', ...
    'remain development-only interpretation evidence.'];
matPath = fullfile(outputRoot, ...
    'OBSERVATION_SUPPORTED_SET_ENTRY_RISK_V193.mat');
reportPath = fullfile(outputRoot, ...
    'OBSERVATION_SUPPORTED_SET_ENTRY_RISK_V193.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V193 report: %s\n', reportPath);
end

function specs = buildCaseSpecs()
root = fullfile('RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v188', 'base_capture');
specs = { ...
    'M24', 'm24-formation-fov', 211, 104, fullfile(root, ...
        'm24_seed211_t104_h3', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H3_', ...
         'M24_FORMATION_FOV_SEED211_T104_D3.mat']); ...
    'X36', 'x36-formation-fov', 211, 72, fullfile(root, ...
        'x36_seed211_t72_h3', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H3_', ...
         'X36_FORMATION_FOV_SEED211_T72_D3.mat'])};
end

function record = emptyRecord()
record = struct( ...
    'scaleName', '', 'formationId', NaN, 'v99Selected', false, ...
    'networkRescueFraction', NaN, ...
    'networkUsefulLossFraction', NaN, ...
    'supportedShareOfRescue', NaN, ...
    'supportWeightedRescueFraction', NaN, ...
    'mapChangeCount', NaN, 'entryCount', NaN, ...
    'unsupportedEntryCount', NaN, 'unsupportedEntryMass', NaN, ...
    'maximumReceiverRisk', NaN, 'meanReceiverRisk', NaN, ...
    'minimumEntrySupport', NaN, 'worstReceiver', NaN, ...
    'worstReferenceMap', NaN, 'worstCandidateMap', NaN, ...
    'worstEnteredLabels', zeros(2, 0), ...
    'worstEnteredSupport', zeros(1, 0), 'risk', NaN);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('SetEntryRiskV193:WriteFailed', ...
        'Could not create the V193 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V193 observation-supported LMB set-entry probe\n\n');
fprintf(fid, ['| Scale | F | V99 | Rescue | Useful loss | Supported ', ...
    'rescue share | Weighted rescue | MAP changes | Entries | ', ...
    'Unsupported | Unsupported mass | Max risk | Min support | ', ...
    'Worst receiver | Ref -> cand MAP |\n']);
fprintf(fid, ['|:--|--:|:--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|--:|:--|\n']);
for record = result.records
    fprintf(fid, ['| %s | %d | %d | %.3f%% | %.3f%% | %.3f%% | ', ...
        '%.3f%% | %d | %d | %d | %.4f | %.4f | %.4f | %d | ', ...
        '%d -> %d |\n'], ...
        record.scaleName, record.formationId, record.v99Selected, ...
        100 * record.networkRescueFraction, ...
        100 * record.networkUsefulLossFraction, ...
        100 * record.supportedShareOfRescue, ...
        100 * record.supportWeightedRescueFraction, ...
        record.mapChangeCount, record.entryCount, ...
        record.unsupportedEntryCount, record.unsupportedEntryMass, ...
        record.maximumReceiverRisk, record.minimumEntrySupport, ...
        record.worstReceiver, record.worstReferenceMap, ...
        record.worstCandidateMap);
end
fprintf(fid, '\n## Worst-receiver entry diagnostics\n\n');
for record = result.records
    if ~record.v99Selected
        continue;
    end
    fprintf(fid, '- `%s F%d / sensor %d`: labels `%s`, support `%s`\n', ...
        record.scaleName, record.formationId, record.worstReceiver, ...
        mat2str(record.worstEnteredLabels'), ...
        mat2str(record.worstEnteredSupport, 4));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

