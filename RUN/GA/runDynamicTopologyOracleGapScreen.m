function [reportPath, summary] = ...
    runDynamicTopologyOracleGapScreen(presetName, seedList, options)
% RUNDYNAMICTOPOLOGYORACLEGAPSCREEN Paired topology-only evidence gate.
%
% Example:
%   opts = struct('maxTimeSteps', 20);
%   runDynamicTopologyOracleGapScreen('d12-handover', 7, opts);
%
% The same measurements, trajectories and link uniforms are reused across
% arms. Payload compression and event triggering are disabled; only the
% selected topology changes. A cached post-update posterior can optionally
% initialize every arm at the same focus-window state.

if nargin < 1 || isempty(presetName)
    presetName = 'd12-handover';
end
if nargin < 2 || isempty(seedList)
    seedList = 1:3;
end
if nargin < 3 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
options = resolveOptions(options);
armDefinitions = buildArms(options.armNames);

fprintf(['Dynamic topology screen: %s, %d seed(s), ', ...
    '%d arm(s), maxTimeSteps=%s, continuation=%s\n'], ...
    presetName, numel(seedList), numel(armDefinitions), ...
    numericOrAll(options.maxTimeSteps), ...
    numericOrNone(options.continuationStartTime));

records = repmat(emptyRecord(), ...
    numel(seedList), numel(armDefinitions));
validationBySeed = cell(1, numel(seedList));
scenarioConfigSnapshot = struct();
for seedIdx = 1:numel(seedList)
    seed = seedList(seedIdx);
    fprintf('Generating paired input for seed %d...\n', seed);
    inputs = generateDynamicTopologyScenarioInputs( ...
        presetName, seed, options.scenarioOverrides);
    if seedIdx == 1
        scenarioConfigSnapshot = inputs.config;
    elseif inputs.config.numberOfSensors ~= ...
            scenarioConfigSnapshot.numberOfSensors || ...
            ~isequal(inputs.config.sensorGroupIds, ...
                scenarioConfigSnapshot.sensorGroupIds)
        error('Scenario topology contract differs across paired seeds.');
    end
    inputs = cropInputs(inputs, options.maxTimeSteps);
    validationBySeed{seedIdx} = inputs.validation;
    [analysisStartTime, initialLocalPosteriors] = ...
        loadContinuationSnapshot( ...
            options, presetName, seed, inputs);
    for armIdx = 1:numel(armDefinitions)
        arm = armDefinitions(armIdx);
        fprintf('  seed %d arm %s...\n', seed, arm.name);
        triggerConfig = buildArmTriggerConfig( ...
            arm, inputs.config, options.fusionOverrides, ...
            options.directedRoutingModelPath, ...
            options.residualRoutingModelPath, ...
            options.structuredTreeModelPath);
        if ~isempty(initialLocalPosteriors)
            triggerConfig.filterInitialLocalPosteriorBySensor = ...
                initialLocalPosteriors;
            triggerConfig.filterInitialLocalPosteriorTime = ...
                analysisStartTime;
            historyCount = min(2, analysisStartTime - 1);
            if historyCount > 0
                triggerConfig.filterInitialPreviousAdjacencyHistory = ...
                    repmat(inputs.graphData.staticAdjacency, ...
                        1, 1, historyCount);
                triggerConfig.filterInitialPreviousAdjacencyTimes = ...
                    (analysisStartTime - historyCount): ...
                    (analysisStartTime - 1);
            end
        end
        rng(seed + options.filterSeedOffset);
        timerId = tic;
        [stateEstimates, diagnostics] = ...
            runEventTriggeredDistributedLmbFilter( ...
                inputs.model, inputs.measurements, ...
                inputs.sensorTrajectories, inputs.neighborMap, ...
                inputs.commConfig, triggerConfig);
        elapsedSeconds = toc(timerId);
        record = scoreRun( ...
            seed, arm, stateEstimates, diagnostics, ...
            inputs.model, inputs.groundTruthRfs, ...
            inputs.config, elapsedSeconds, analysisStartTime);
        records(seedIdx, armIdx) = record;
        fprintf(['    E-OSPA %.4f, consensus OSPA %.4f, ', ...
            'attempted %.0f B, %.2f s\n'], ...
            record.meanEospa, record.consensusOspa, ...
            record.attemptedBytes, record.elapsedSeconds);
    end
end

summary = aggregateRecords( ...
    presetName, seedList, armDefinitions, records, ...
    validationBySeed, options, scenarioConfigSnapshot);
reportPath = '';
if options.writeReport
    outputDirectory = options.outputDirectory;
    if ~exist(outputDirectory, 'dir')
        mkdir(outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    if isempty(options.continuationStartTime)
        stem = sprintf('DYNAMIC_TOPOLOGY_ORACLE_GAP_%s_N%d_%s', ...
            upper(strrep(char(presetName), '-', '_')), ...
            numel(seedList), timestamp);
    else
        stem = sprintf( ...
            'DYNAMIC_TOPOLOGY_CONTINUATION_%s_T%d_N%d_%s', ...
            upper(strrep(char(presetName), '-', '_')), ...
            options.continuationStartTime, ...
            numel(seedList), timestamp);
    end
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    writeReport(reportPath, summary);
    save(matPath, 'summary');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    fprintf('Report: %s\n', reportPath);
end
end

function options = resolveOptions(options)
options.armNames = getField(options, 'armNames', { ...
    'local', 'robust-static', 'reliability', 'discrepancy', ...
    'oracle-consensus', 'oracle-truth'});
options.maxTimeSteps = getField(options, 'maxTimeSteps', inf);
options.writeReport = getField(options, 'writeReport', true);
options.scenarioOverrides = getField( ...
    options, 'scenarioOverrides', struct());
options.fusionOverrides = getField( ...
    options, 'fusionOverrides', struct());
options.outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
options.filterSeedOffset = getField(options, 'filterSeedOffset', 100000);
options.directedRoutingModelPath = getField( ...
    options, 'directedRoutingModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'directed_routing_knn_m24_t75.mat'));
options.residualRoutingModelPath = getField( ...
    options, 'residualRoutingModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'confidence_gated_residual_m24_t75.mat'));
options.structuredTreeModelPath = getField( ...
    options, 'structuredTreeModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'structured_formation_tree_m24_proxy_candidate.mat'));
continuationStart = getField(options, 'continuationStartTime', []);
if isempty(continuationStart)
    options.continuationStartTime = [];
else
    options.continuationStartTime = max(1, round(continuationStart));
end
options.behaviorCacheDirectory = getField( ...
    options, 'behaviorCacheDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'cache'));
options.generateMissingBehaviorCache = getField( ...
    options, 'generateMissingBehaviorCache', false);
options.minimumPracticalTrackingGainPercent = max(0, getField( ...
    options, 'minimumPracticalTrackingGainPercent', 5));
options.minimumDynamicRouteDifferenceFraction = min(max(getField( ...
    options, 'minimumDynamicRouteDifferenceFraction', 0.10), 0), 1);
options.minimumGatewayControlPhaseCount = max(1, round(getField( ...
    options, 'minimumGatewayControlPhaseCount', 6)));
end

function arms = buildArms(names)
if ischar(names)
    names = {names};
end
arms = repmat(struct('name', '', 'mode', ''), 1, numel(names));
for armIdx = 1:numel(names)
    mode = lower(strrep(char(names{armIdx}), '_', '-'));
    fixedToken = regexp(mode, ...
        '^fixed-candidate-([0-9]+)$', 'tokens', 'once');
    if ~isempty(fixedToken)
        displayName = sprintf( ...
            'Registered fixed candidate %d', ...
            str2double(fixedToken{1}));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    directedReliabilityToken = regexp(mode, ...
        '^directed-reliability-w([0-9]+)$', 'tokens', 'once');
    if ~isempty(directedReliabilityToken)
        sourceWeight = str2double(directedReliabilityToken{1}) / 100;
        displayName = sprintf( ...
            'Directed reliability control (w=%.2f)', sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    formationTreeOracleToken = regexp(mode, ...
        '^oracle-formation-tree-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(formationTreeOracleToken)
        sourceWeight = ...
            str2double(formationTreeOracleToken{1}) / 100;
        displayName = sprintf([ ...
            'Privileged rooted formation-tree diagnostic ', ...
            '(w=%.2f)'], sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    jointTreeOracleToken = regexp(mode, ...
        '^oracle-tree-v4-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(jointTreeOracleToken)
        sourceWeight = ...
            str2double(jointTreeOracleToken{1}) / 100;
        displayName = sprintf([ ...
            'Privileged jointly-strong tree diagnostic ', ...
            '(w=%.2f)'], sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    connectedTreeToken = regexp(mode, ...
        '^directed-tree-v2-b([0-9]+)-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(connectedTreeToken)
        bridgeWeight = str2double( ...
            connectedTreeToken{1}) / 100;
        sourceWeight = str2double( ...
            connectedTreeToken{2}) / 100;
        displayName = sprintf([ ...
            'Connected formation tree v2 ', ...
            '(bridge=%.2f, w=%.2f)'], ...
            bridgeWeight, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    strongCycleToken = regexp(mode, ...
        '^directed-cycle-v3-b([0-9]+)-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(strongCycleToken)
        bridgeWeight = str2double( ...
            strongCycleToken{1}) / 100;
        sourceWeight = str2double( ...
            strongCycleToken{2}) / 100;
        displayName = sprintf([ ...
            'Strong formation cycle v3 ', ...
            '(bridge=%.2f, w=%.2f)'], ...
            bridgeWeight, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    jointTreeToken = regexp(mode, ...
        '^directed-tree-v4-b([0-9]+)-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(jointTreeToken)
        bridgeWeight = str2double(jointTreeToken{1}) / 100;
        sourceWeight = str2double(jointTreeToken{2}) / 100;
        displayName = sprintf([ ...
            'Jointly strong formation tree v4 ', ...
            '(bridge=%.2f, w=%.2f)'], ...
            bridgeWeight, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    structuredTreeToken = regexp(mode, ...
        '^structured-tree-routing-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(structuredTreeToken)
        sourceWeight = ...
            str2double(structuredTreeToken{1}) / 100;
        if sourceWeight <= 0 || sourceWeight >= 1
            error('Structured tree-routing weight must be in (0,1).');
        end
        displayName = sprintf([ ...
            'Structured jointly-strong formation tree ', ...
            '(w=%.2f)'], sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    registeredTreePhaseToken = regexp(mode, ...
        ['^directed-scheduled-tree-r([0-9]+)-', ...
         'e([0-9]+)-w([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(registeredTreePhaseToken)
        rootPhase = str2double(registeredTreePhaseToken{1});
        endpointPhase = str2double(registeredTreePhaseToken{2});
        sourceWeight = ...
            str2double(registeredTreePhaseToken{3}) / 100;
        if rootPhase < 1 || endpointPhase < 1 || ...
                sourceWeight <= 0 || sourceWeight >= 1
            error('Scheduled-tree control phases/weight are invalid.');
        end
        displayName = sprintf([ ...
            'Directed scheduled-tree control ', ...
            '(root=%d, endpoint=%d, w=%.2f)'], ...
            rootPhase, endpointPhase, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    registeredLinkTreeToken = regexp(mode, ...
        '^directed-link-tree-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(registeredLinkTreeToken)
        sourceWeight = ...
            str2double(registeredLinkTreeToken{1}) / 100;
        if sourceWeight <= 0 || sourceWeight >= 1
            error('Link-tree control weight must be in (0,1).');
        end
        displayName = sprintf( ...
            'Directed link-aware tree control (w=%.2f)', ...
            sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    gatewayCandidateToken = regexp(mode, ...
        '^directed-gateway-v1-w([0-9]+)$', 'tokens', 'once');
    if ~isempty(gatewayCandidateToken)
        sourceWeight = str2double(gatewayCandidateToken{1}) / 100;
        displayName = sprintf([ ...
            'Novelty-gated formation gateway (v1, w=%.2f)'], ...
            sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    registeredGatewayPhaseToken = regexp(mode, ...
        ['^directed-(fixed|rotating)-gateway-', ...
         'p([0-9]+)-w([0-9]+)$'], 'tokens', 'once');
    if ~isempty(registeredGatewayPhaseToken)
        policyMode = registeredGatewayPhaseToken{1};
        phase = str2double(registeredGatewayPhaseToken{2});
        sourceWeight = ...
            str2double(registeredGatewayPhaseToken{3}) / 100;
        displayName = sprintf( ...
            'Directed %s gateway control (phase=%d, w=%.2f)', ...
            policyMode, phase, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    registeredLinkGatewayToken = regexp(mode, ...
        '^directed-link-gateway-w([0-9]+)$', 'tokens', 'once');
    if ~isempty(registeredLinkGatewayToken)
        sourceWeight = ...
            str2double(registeredLinkGatewayToken{1}) / 100;
        displayName = sprintf( ...
            'Directed link-aware gateway control (w=%.2f)', ...
            sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    registeredPhaseToken = regexp(mode, ...
        ['^directed-(fixed-cycle|round-robin|', ...
         'physical-round-robin)-p([0-9]+)-', ...
         'w([0-9]+)$'], 'tokens', 'once');
    if ~isempty(registeredPhaseToken)
        policyMode = registeredPhaseToken{1};
        phase = str2double(registeredPhaseToken{2});
        sourceWeight = str2double(registeredPhaseToken{3}) / 100;
        if phase < 1
            error('Registered directed-control phase must be positive.');
        end
        displayName = sprintf( ...
            'Directed %s control (phase=%d, w=%.2f)', ...
            strrep(policyMode, '-', ' '), phase, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    registeredToken = regexp(mode, ...
        ['^directed-(fixed-index|fixed-cycle|round-robin|', ...
         'physical-round-robin)-', ...
         'w([0-9]+)$'], 'tokens', 'once');
    if ~isempty(registeredToken)
        policyMode = registeredToken{1};
        sourceWeight = str2double(registeredToken{2}) / 100;
        displayName = sprintf( ...
            'Directed %s control (w=%.2f)', ...
            strrep(policyMode, '-', ' '), sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    reliabilityQualityToken = regexp(mode, ...
        ['^directed-reliability-quality-c([0-9]+)-', ...
         'w([0-9]+)$'], 'tokens', 'once');
    if ~isempty(reliabilityQualityToken)
        coefficient = ...
            str2double(reliabilityQualityToken{1}) / 100;
        sourceWeight = ...
            str2double(reliabilityQualityToken{2}) / 100;
        displayName = sprintf([ ...
            'Directed reliability + source quality ', ...
            '(c=%.2f, w=%.2f)'], coefficient, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    budgetedReliabilityToken = regexp(mode, ...
        '^directed-reliability-b([0-9]+)-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(budgetedReliabilityToken)
        messageBudget = str2double(budgetedReliabilityToken{1});
        sourceWeight = str2double(budgetedReliabilityToken{2}) / 100;
        displayName = sprintf([ ...
            'Directed reliability control (B=%d, w=%.2f)'], ...
            messageBudget, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    compatibilityToken = regexp(mode, ...
        ['^directed-(moment-compatibility|kla-compatibility)-', ...
         'w([0-9]+)$'], 'tokens', 'once');
    if ~isempty(compatibilityToken)
        policyMode = compatibilityToken{1};
        sourceWeight = str2double(compatibilityToken{2}) / 100;
        displayName = sprintf( ...
            'Directed %s control (w=%.2f)', ...
            strrep(policyMode, '-', ' '), sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    budgetedCompatibilityToken = regexp(mode, ...
        ['^directed-(moment-compatibility|kla-compatibility)-', ...
         'b([0-9]+)-w([0-9]+)$'], 'tokens', 'once');
    if ~isempty(budgetedCompatibilityToken)
        policyMode = budgetedCompatibilityToken{1};
        messageBudget = str2double( ...
            budgetedCompatibilityToken{2});
        sourceWeight = str2double( ...
            budgetedCompatibilityToken{3}) / 100;
        displayName = sprintf( ...
            'Directed %s control (B=%d, w=%.2f)', ...
            strrep(policyMode, '-', ' '), ...
            messageBudget, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    switch mode
        case 'local'
            displayName = 'Local only';
        case 'robust-static'
            displayName = 'All-time geometry static';
        case 'reliability'
            displayName = 'Reliability dynamic';
        case 'discrepancy'
            displayName = 'Posterior discrepancy dynamic';
        case 'oracle-consensus'
            displayName = 'Exact one-step consensus oracle';
        case 'oracle-truth'
            displayName = 'Exact one-step truth diagnostic oracle';
        case 'teacher-current'
            displayName = 'Pure current task-risk teacher';
        case 'teacher-current-balanced'
            displayName = 'Balanced current task-risk teacher';
        case 'teacher-current-cvar'
            displayName = 'Tail-risk current task-risk teacher';
        case 'teacher-directed-routing'
            displayName = 'Directed risk-gated routing teacher';
        case 'learned-directed-routing'
            displayName = ...
                'Legacy M24 single-snapshot kNN directed routing';
        case 'confidence-residual-directed-routing'
            displayName = 'Support-gated residual directed KLA';
        case 'directed-reliability'
            displayName = 'Directed reliability control';
        case 'teacher-predictive'
            displayName = 'Open-loop predictive task-risk teacher';
        otherwise
            error('Unknown topology screen arm: %s', names{armIdx});
    end
    arms(armIdx) = struct('name', displayName, 'mode', mode);
end
end

function config = buildArmTriggerConfig( ...
    arm, scenarioConfig, overrides, ...
    directedRoutingModelPath, residualRoutingModelPath, ...
    structuredTreeModelPath)
config = buildMixtureAwareKlaReferenceConfig(overrides);
config.dynamicTopologyEnabled = false;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
fixedToken = regexp(arm.mode, ...
    '^fixed-candidate-([0-9]+)$', 'tokens', 'once');
if ~isempty(fixedToken)
    fixedCandidateIndex = str2double(fixedToken{1});
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyPolicyName = arm.mode;
    config.topologyPolicyFcn = ...
        @(context) selectRegisteredFixedTopology( ...
            context, fixedCandidateIndex);
    return;
end
directedReliabilityToken = regexp(arm.mode, ...
    '^directed-reliability-w([0-9]+)$', 'tokens', 'once');
if ~isempty(directedReliabilityToken)
    sourceWeight = ...
        str2double(directedReliabilityToken{1}) / 100;
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        2 * scenarioConfig.edgeBudget;
    config.topologyPolicyName = arm.mode;
    policyOptions = struct('sourceWeight', sourceWeight);
    config.topologyPolicyFcn = ...
        @(context) selectAnalyticDirectedRoutingPolicy( ...
            context, 'reliability', policyOptions);
    return;
end
formationTreeOracleToken = regexp(arm.mode, ...
    '^oracle-formation-tree-w([0-9]+)$', ...
    'tokens', 'once');
if ~isempty(formationTreeOracleToken)
    sourceWeight = ...
        str2double(formationTreeOracleToken{1}) / 100;
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        scenarioConfig.numberOfSensors;
    config.topologyPolicyName = arm.mode;
    policyOptions = struct('sourceWeight', sourceWeight);
    config.topologyPolicyFcn = ...
        @(context) selectFormationTreeRoutingTeacher( ...
            context, policyOptions);
    return;
end
jointTreeOracleToken = regexp(arm.mode, ...
    '^oracle-tree-v4-w([0-9]+)$', ...
    'tokens', 'once');
if ~isempty(jointTreeOracleToken)
    sourceWeight = str2double(jointTreeOracleToken{1}) / 100;
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        scenarioConfig.numberOfSensors;
    config.topologyPolicyName = arm.mode;
    policyOptions = struct( ...
        'sourceWeight', sourceWeight, ...
        'baselineMode', 'fixed-index-star', ...
        'requirePreviousUnionStrongConnectivity', true);
    config.topologyPolicyFcn = ...
        @(context) selectFormationTreeRoutingTeacher( ...
            context, policyOptions);
    return;
end
connectedTreeToken = regexp(arm.mode, ...
    '^directed-tree-v2-b([0-9]+)-w([0-9]+)$', ...
    'tokens', 'once');
if ~isempty(connectedTreeToken)
    bridgeWeight = str2double(connectedTreeToken{1}) / 100;
    sourceWeight = str2double(connectedTreeToken{2}) / 100;
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        scenarioConfig.numberOfSensors;
    config.topologyPolicyName = arm.mode;
    policyOptions = buildFormationGatewayRoutingOptions( ...
        'connected-tree-v2', struct( ...
            'sourceWeight', sourceWeight, ...
            'bridgeSourceWeight', bridgeWeight));
    config.topologyPolicyFcn = ...
        @(context) selectConnectedFormationTreeRoutingPolicy( ...
            context, policyOptions);
    return;
end
strongCycleToken = regexp(arm.mode, ...
    '^directed-cycle-v3-b([0-9]+)-w([0-9]+)$', ...
    'tokens', 'once');
if ~isempty(strongCycleToken)
    bridgeWeight = str2double(strongCycleToken{1}) / 100;
    sourceWeight = str2double(strongCycleToken{2}) / 100;
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        scenarioConfig.numberOfSensors;
    config.topologyPolicyName = arm.mode;
    policyOptions = buildFormationGatewayRoutingOptions( ...
        'strong-cycle-v3', struct( ...
            'sourceWeight', sourceWeight, ...
            'bridgeSourceWeight', bridgeWeight));
    config.topologyPolicyFcn = ...
        @(context) selectConnectedFormationTreeRoutingPolicy( ...
            context, policyOptions);
    return;
end
jointTreeToken = regexp(arm.mode, ...
    '^directed-tree-v4-b([0-9]+)-w([0-9]+)$', ...
    'tokens', 'once');
if ~isempty(jointTreeToken)
    bridgeWeight = str2double(jointTreeToken{1}) / 100;
    sourceWeight = str2double(jointTreeToken{2}) / 100;
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        scenarioConfig.numberOfSensors;
    config.topologyPolicyName = arm.mode;
    policyOptions = buildFormationGatewayRoutingOptions( ...
        'joint-tree-v4', struct( ...
            'sourceWeight', sourceWeight, ...
            'bridgeSourceWeight', bridgeWeight));
    config.topologyPolicyFcn = ...
        @(context) selectConnectedFormationTreeRoutingPolicy( ...
            context, policyOptions);
    return;
end
structuredTreeToken = regexp(arm.mode, ...
    '^structured-tree-routing-w([0-9]+)$', ...
    'tokens', 'once');
if ~isempty(structuredTreeToken)
    sourceWeight = ...
        str2double(structuredTreeToken{1}) / 100;
    modelPath = structuredTreeModelPath;
    if ~exist(modelPath, 'file')
        error('Missing structured tree-routing model: %s', ...
            modelPath);
    end
