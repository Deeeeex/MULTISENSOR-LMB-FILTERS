            protocol.messagePassingInitializationPath) && ...
            ~strcmp(computeFileSha256( ...
                labelSetMessagePassingModelPath), ...
                protocol.messagePassingInitializationSha256)
        error('Registered label-set initialization hash mismatch.');
    end
