function history = resolveWindowPreviousActiveEdgeHistory( ...
        diagnostics, windowStart, historyDepth)
sensorCount = size(diagnostics.topologyActiveEdge, 1);
history = false(sensorCount, sensorCount, 0);
if historyDepth <= 0
    return;
end
if isfield(diagnostics, ...
        'initialPreviousDirectedEdgeHistory') && ...
        ~isempty(diagnostics.initialPreviousDirectedEdgeHistory)
    history = logical( ...
        diagnostics.initialPreviousDirectedEdgeHistory);
elseif isfield(diagnostics, ...
        'usedInitialPreviousAdjacency') && ...
        diagnostics.usedInitialPreviousAdjacency
    history = reshape(logical( ...
        diagnostics.initialPreviousDirectedEdgeMask), ...
        sensorCount, sensorCount, 1);
end
firstExecutedTime = diagnostics.continuationStartTime;
for timeIdx = firstExecutedTime:(windowStart - 1)
    if timeIdx < 1 || ...
            timeIdx > size(diagnostics.topologyActiveEdge, 3)
        continue;
    end
    if isempty(history)
        history = reshape( ...
            diagnostics.topologyActiveEdge(:, :, timeIdx), ...
            sensorCount, sensorCount, 1);
    else
        history(:, :, end + 1) = ...
            diagnostics.topologyActiveEdge(:, :, timeIdx);
    end
end
if size(history, 3) > historyDepth
    history = history(:, :, end-historyDepth+1:end);
end
end

