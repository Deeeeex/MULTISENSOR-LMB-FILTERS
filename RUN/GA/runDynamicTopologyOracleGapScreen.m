function decision = applyRoutingDecisions(decision, seedCount)
decision = applyDirectedRoutingDecision(decision, seedCount);
readout = decision.residualRouting;
if readout.available
    if ~readout.passesIncrementalGain
        readout.status = 'residual-routing-no-incremental-gain';
        readout.recommendation = [ ...
        'The residual learner does not pass the registered practical ', ...
        'gain, per-seed, tail, feasibility and communication gates ', ...
        'against reliability-w0.50; do not attribute the backbone ', ...
        'gain to learning.'];
    elseif seedCount < 10
        readout.status = 'residual-routing-development-gain';
        readout.recommendation = [ ...
        'The residual learner improves its registered analytic ', ...
        'backbone under the development gate, but at least 10 ', ...
        'screening seeds and a held-out split are still required.'];
    elseif seedCount < 30
        readout.status = 'residual-routing-screening-gain';
        readout.recommendation = [ ...
        'The residual learner improves its registered analytic ', ...
        'backbone in a screening-size run; a registered held-out ', ...
        'validation remains required.'];
    else
        readout.status = 'residual-routing-validation-size-gain';
        readout.recommendation = [ ...
        'The residual learner improves its registered analytic ', ...
        'backbone in a validation-size run. Held-out status must ', ...
        'still be established by the registered data split.'];
    end
    decision.residualRouting = readout;
end
dynamicReadout = decision.dynamicAttribution;
if dynamicReadout.available
    if ~dynamicReadout.completeBaselineSet
        dynamicReadout.status = ...
            'dynamic-attribution-incomplete-controls';
        dynamicReadout.recommendation = [ ...
            'Run the candidate-specific registered controls at the ', ...
            'same source weight and action support before attributing ', ...
            'online gain. Gateway candidates require round-robin, ', ...
            'fixed, rotating and link-aware gateway controls.'];
    elseif ~dynamicReadout.passesAttributionGate
        dynamicReadout.status = 'dynamic-attribution-gate-failed';
        dynamicReadout.recommendation = [ ...
            'The candidate does not jointly pass the gain, per-seed, ', ...
            'tail, byte, feasibility and within-window route-change ', ...
            'gates, including gateway-only dynamics and formation-union ', ...
            'connectivity, against the strongest registered controls.'];
    elseif seedCount < 10
        dynamicReadout.status = 'dynamic-attribution-development-gain';
        dynamicReadout.recommendation = [ ...
            'The candidate passes the bounded attribution gate; retain ', ...
            'it for a frozen 10-seed screening run.'];
    elseif seedCount < 30
        dynamicReadout.status = 'dynamic-attribution-screening-gain';
        dynamicReadout.recommendation = [ ...
            'The candidate passes a screening-size attribution gate; ', ...
            'a separately registered held-out validation is required.'];
