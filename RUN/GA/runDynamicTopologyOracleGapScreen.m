function readout = computeResidualRoutingReadout( ...
    aggregates, residualIdx, backboneIdx, minimumGainPercent)
readout = emptyResidualRoutingReadout();
if isempty(residualIdx) || isempty(backboneIdx)
    return;
end
eligible = false(1, numel(residualIdx));
for cursor = 1:numel(residualIdx)
    arm = aggregates(residualIdx(cursor));
    eligible(cursor) = ...
        all(isfinite(arm.focusEospaBySeed)) && ...
        all(arm.topologyInfeasibleRateBySeed <= 1e-12);
end
eligibleIdx = residualIdx(eligible);
readout.available = ~isempty(eligibleIdx);
readout.eligibleArmCount = numel(eligibleIdx);
if isempty(eligibleIdx)
    return;
end
[~, bestCursor] = min([aggregates(eligibleIdx).focusEospa]);
best = aggregates(eligibleIdx(bestCursor));
backbone = aggregates(backboneIdx(1));
readout.arm = best.name;
readout.backboneArm = backbone.name;
readout.focusEospa = best.focusEospa;
readout.backboneFocusEospa = backbone.focusEospa;
readout.gainVsBackbonePercent = percentImprovement( ...
    backbone.focusEospa, best.focusEospa);
readout.worstNodeGainVsBackbonePercent = percentImprovement( ...
    backbone.worstSensorEospa, best.worstSensorEospa);
readout.attemptedByteRatioPercent = ...
    100 * best.attemptedBytes / max(backbone.attemptedBytes, 1);
readout.policySecondsOverhead = ...
    best.topologyPolicySeconds - backbone.topologyPolicySeconds;
readout.meanOverrideFraction = best.meanPolicyOverrideFraction;
readout.meanSupportedCandidateFraction = ...
    best.meanPolicySupportedCandidateFraction;
readout.zeroInfeasibility = ...
    all(best.topologyInfeasibleRateBySeed <= 1e-12);
perSeedGain = 100 * ( ...
    backbone.focusEospaBySeed - best.focusEospaBySeed) ./ ...
    max(abs(backbone.focusEospaBySeed), eps);
readout.positiveGainEverySeed = all(perSeedGain > 0);
readout.tailSafeVsBackbone = ...
    all(best.worstSensorEospaBySeed <= ...
        backbone.worstSensorEospaBySeed + 1e-12);
readout.withinBackboneAttemptedBytes = ...
    all(best.attemptedBytesBySeed <= ...
        1.02 * backbone.attemptedBytesBySeed);
readout.minimumPracticalGainPercent = minimumGainPercent;
readout.passesIncrementalGain = ...
    readout.gainVsBackbonePercent >= minimumGainPercent && ...
    readout.positiveGainEverySeed && ...
    readout.tailSafeVsBackbone && ...
    readout.withinBackboneAttemptedBytes && ...
    readout.zeroInfeasibility;
readout.exactBackboneMatch = ...
    all(abs(best.focusEospaBySeed - ...
        backbone.focusEospaBySeed) <= 1e-12) && ...
    all(abs(best.worstSensorEospaBySeed - ...
        backbone.worstSensorEospaBySeed) <= 1e-12) && ...
    all(abs(best.attemptedBytesBySeed - ...
        backbone.attemptedBytesBySeed) <= 1e-12) && ...
    all(abs(best.meanDirectedMessageCountBySeed - ...
        backbone.meanDirectedMessageCountBySeed) <= 1e-12);
end

