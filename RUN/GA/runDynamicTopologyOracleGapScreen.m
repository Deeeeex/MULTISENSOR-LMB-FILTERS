function churnRate = computeWindowChurnRate(activeEdges, previousEdges)
if nargin >= 2 && ~isempty(previousEdges)
    activeEdges = cat(3, logical(previousEdges), activeEdges);
end
timeCount = size(activeEdges, 3);
if timeCount < 2
    churnRate = 0;
    return;
end
previousEdges = activeEdges(:, :, 1:(timeCount - 1));
nextEdges = activeEdges(:, :, 2:timeCount);
changedEdges = xor(previousEdges, nextEdges);
edgeUnion = previousEdges | nextEdges;
churnRate = sum(changedEdges(:)) / max(sum(edgeUnion(:)), 1);
end

function fraction = computeWithinWindowRouteChangeFraction(activeEdges)
timeCount = size(activeEdges, 3);
receiverCount = size(activeEdges, 2);
if timeCount < 2 || receiverCount == 0
    fraction = 0;
    return;
end
changed = xor( ...
    activeEdges(:, :, 1:(timeCount - 1)), ...
    activeEdges(:, :, 2:timeCount));
changedByReceiver = any(changed, 1);
fraction = nnz(changedByReceiver) / ...
    (receiverCount * (timeCount - 1));
end

function count = computeDistinctTopologyCount(activeEdges)
timeCount = size(activeEdges, 3);
if timeCount == 0
    count = 0;
    return;
end
maps = reshape(activeEdges, [], timeCount)';
count = size(unique(maps, 'rows'), 1);
end

function fraction = computePrefixBoundaryRouteChangeFraction( ...
    activeEdges, previousEdges)
receiverCount = size(activeEdges, 2);
if isempty(previousEdges) || isempty(activeEdges) || receiverCount == 0
    fraction = 0;
    return;
end
changedByReceiver = any(xor( ...
    logical(previousEdges), activeEdges(:, :, 1)), 1);
fraction = nnz(changedByReceiver) / receiverCount;
end

function fraction = computeReceiverCoverageFraction(activeEdges)
receiverTimeCoverage = any(activeEdges, 1);
if isempty(receiverTimeCoverage)
    fraction = 0;
else
    fraction = nnz(receiverTimeCoverage) / ...
        numel(receiverTimeCoverage);
end
end

function value = computeMeanUniqueSendersPerReceiver(activeEdges)
receiverCount = size(activeEdges, 2);
if receiverCount == 0
    value = 0;
    return;
end
uniqueSenderCount = zeros(1, receiverCount);
for receiverIdx = 1:receiverCount
    uniqueSenderCount(receiverIdx) = nnz(any( ...
        activeEdges(:, receiverIdx, :), 3));
end
value = mean(uniqueSenderCount);
end

function fraction = computeCrossFormationMessageFraction( ...
    activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = size(activeEdges, 1);
if numel(groupIds) ~= nodeCount
    fraction = NaN;
    return;
end
crossFormation = groupIds(:) ~= groupIds;
crossCount = 0;
messageCount = 0;
for timeIdx = 1:size(activeEdges, 3)
    active = activeEdges(:, :, timeIdx);
    crossCount = crossCount + nnz(active & crossFormation);
    messageCount = messageCount + nnz(active);
end
fraction = crossCount / max(messageCount, 1);
end

function crossEdges = keepCrossFormationEdges(activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = size(activeEdges, 1);
if numel(groupIds) ~= nodeCount
    error('sensorGroupIds must match the active-edge tensor.');
end
crossMask = groupIds(:) ~= groupIds;
crossEdges = activeEdges & repmat( ...
    crossMask, 1, 1, size(activeEdges, 3));
end

function [weakFraction, strongFraction, unionWeak, unionStrong, ...
        meanCoverage] = computeFormationGraphMetrics( ...
            activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
groupCount = numel(groups);
timeCount = size(activeEdges, 3);
if groupCount <= 1
    weakFraction = 1;
    strongFraction = 1;
    unionWeak = 1;
    unionStrong = 1;
    meanCoverage = 1;
    return;
end
weakByTime = false(1, timeCount);
strongByTime = false(1, timeCount);
coverageByTime = zeros(1, timeCount);
unionAdjacency = false(groupCount);
for timeIdx = 1:timeCount
    formationAdjacency = buildFormationAdjacencyFromDiagnosticMask( ...
        activeEdges(:, :, timeIdx), groupIds, groups);
    unionAdjacency = unionAdjacency | formationAdjacency;
    weakByTime(timeIdx) = isWeaklyConnected(formationAdjacency);
    strongByTime(timeIdx) = isStronglyConnected(formationAdjacency);
    incident = any( ...
        formationAdjacency | formationAdjacency', 2);
    coverageByTime(timeIdx) = mean(incident);
end
weakFraction = mean(weakByTime);
strongFraction = mean(strongByTime);
unionWeak = double(isWeaklyConnected(unionAdjacency));
unionStrong = double(isStronglyConnected(unionAdjacency));
meanCoverage = mean(coverageByTime);
end

function fraction = computePairwiseFormationUnionStrongFraction( ...
        activeEdges, groupIds, previousActiveEdges)
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
timeCount = size(activeEdges, 3);
if numel(groups) <= 1
    fraction = 1;
    return;
end
if isempty(previousActiveEdges)
    previousFormationAdjacency = false(numel(groups));
    previousAvailable = false;
else
    previousFormationAdjacency = ...
        buildFormationAdjacencyFromDiagnosticMask( ...
            previousActiveEdges, groupIds, groups);
    previousAvailable = true;
end
strongByStep = false(1, timeCount);
for timeIdx = 1:timeCount
    currentFormationAdjacency = ...
        buildFormationAdjacencyFromDiagnosticMask( ...
            activeEdges(:, :, timeIdx), groupIds, groups);
    if previousAvailable
        strongByStep(timeIdx) = isStronglyConnected( ...
            previousFormationAdjacency | ...
            currentFormationAdjacency);
    end
    previousFormationAdjacency = currentFormationAdjacency;
    previousAvailable = true;
end
fraction = mean(strongByStep);
end

function fraction = computeFormationRootedTreeFraction( ...
        activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
timeCount = size(activeEdges, 3);
if numel(groups) <= 1
    fraction = 1;
    return;
end
rootedByStep = false(1, timeCount);
for timeIdx = 1:timeCount
    adjacency = buildFormationAdjacencyFromDiagnosticMask( ...
        activeEdges(:, :, timeIdx), groupIds, groups);
    indegree = sum(adjacency, 1);
    root = find(indegree == 0);
    rootedByStep(timeIdx) = ...
        nnz(adjacency) == numel(groups) - 1 && ...
        numel(root) == 1 && ...
        all(indegree(setdiff(1:numel(groups), root)) == 1) && ...
        all(reachableFromNode(adjacency, root));
end
fraction = mean(rootedByStep);
end

function fraction = computeCrossFormationEdgeCountExactFraction( ...
        activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
groupCount = numel(unique(groupIds, 'stable'));
if groupCount <= 1
    fraction = 1;
    return;
end
crossMask = groupIds(:) ~= groupIds;
timeCount = size(activeEdges, 3);
exactByStep = false(1, timeCount);
for timeIdx = 1:timeCount
    exactByStep(timeIdx) = nnz( ...
        activeEdges(:, :, timeIdx) & crossMask) == ...
        groupCount - 1;
end
fraction = mean(exactByStep);
end

function adjacency = buildFormationAdjacencyFromDiagnosticMask( ...
        diagnosticMask, groupIds, groups)
groupCount = numel(groups);
adjacency = false(groupCount);
[senderIndices, receiverIndices] = find(diagnosticMask);
for edgeIdx = 1:numel(senderIndices)
    senderGroup = find( ...
        groups == groupIds(senderIndices(edgeIdx)), 1);
    receiverGroup = find( ...
        groups == groupIds(receiverIndices(edgeIdx)), 1);
    if senderGroup ~= receiverGroup
        adjacency(senderGroup, receiverGroup) = true;
    end
end
end

function previousActiveEdges = resolveWindowPreviousActiveEdges( ...
        diagnostics, windowStart)
previousActiveEdges = [];
if windowStart > diagnostics.continuationStartTime
    previousActiveEdges = ...
        diagnostics.topologyActiveEdge(:, :, windowStart - 1);
    return;
end
if windowStart == diagnostics.continuationStartTime && ...
        isfield(diagnostics, 'usedInitialPreviousAdjacency') && ...
        diagnostics.usedInitialPreviousAdjacency
    previousActiveEdges = diagnostics.initialPreviousDirectedEdgeMask;
end
end

function connected = isWeaklyConnected(adjacency)
nodeCount = size(adjacency, 1);
if nodeCount <= 1
    connected = true;
    return;
end
connected = all(reachableFromFirst(adjacency | adjacency'));
end

function connected = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
if nodeCount <= 1
    connected = true;
    return;
end
connected = all(reachableFromFirst(adjacency)) && ...
    all(reachableFromFirst(adjacency'));
end

function reachable = reachableFromFirst(adjacency)
nodeCount = size(adjacency, 1);
reachable = false(1, nodeCount);
reachable(1) = true;
while true
    expanded = reachable | any(adjacency(reachable, :), 1);
    if isequal(expanded, reachable)
        break;
    end
    reachable = expanded;
end
end

function reachable = reachableFromNode(adjacency, root)
nodeCount = size(adjacency, 1);
reachable = false(1, nodeCount);
reachable(root) = true;
while true
    expanded = reachable | any(adjacency(reachable, :), 1);
    if isequal(expanded, reachable)
        break;
    end
    reachable = expanded;
end
end

function fraction = computeDifferenceFromFixedIndexMap( ...
    activeEdges, groupIds)
reference = buildFixedIndexDirectedMask(groupIds);
receiverCount = size(activeEdges, 2);
timeCount = size(activeEdges, 3);
if receiverCount == 0 || timeCount == 0
    fraction = 0;
    return;
end
changedCount = 0;
for timeIdx = 1:timeCount
    changedCount = changedCount + nnz(any(xor( ...
        activeEdges(:, :, timeIdx), reference), 1));
end
fraction = changedCount / (receiverCount * timeCount);
end

function mask = buildFixedIndexDirectedMask(groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = numel(groupIds);
mask = false(nodeCount);
groups = unique(groupIds);
for groupCursor = 1:numel(groups)
    members = reshape(find(groupIds == groups(groupCursor)), 1, []);
    if numel(members) < 2
        continue;
    end
    mask(members(2), members(1)) = true;
    mask(members(1), members(2:end)) = true;
end
end

function indices = resolveFocusWindow(config, timeCount, analysisStartTime)
window = getField(config, 'focusWindow', [1, timeCount]);
startTime = max([1, round(window(1)), analysisStartTime]);
stopTime = min(timeCount, round(window(end)));
if stopTime < startTime
    indices = analysisStartTime:timeCount;
else
    indices = startTime:stopTime;
end
end

function value = percentImprovement(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = numericOrAll(number)
if isfinite(number)
    value = num2str(number);
else
    value = 'all';
end
end

function value = numericOrNone(number)
if isempty(number)
    value = 'none';
else
    value = num2str(number);
end
end

function tf = endsWithText(text, suffix)
text = char(text);
suffix = char(suffix);
tf = numel(text) >= numel(suffix) && ...
    strcmp(text((end - numel(suffix) + 1):end), suffix);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
