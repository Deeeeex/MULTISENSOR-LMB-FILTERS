function decision = applyRoutingDecisions(decision, seedCount)
decision = applyDirectedRoutingDecision(decision, seedCount);
readout = decision.residualRouting;
if readout.available
    if ~readout.passesIncrementalGain
        readout.status = 'residual-routing-no-incremental-gain';
        readout.recommendation = [ ...
        'The residual learner does not pass the registered practical ', ...
        'gain, per-seed, tail, feasibility and communication gates ', ...
        'against reliability-w0.50; do not attribute the backbone ', ...
        'gain to learning.'];
    elseif seedCount < 10
        readout.status = 'residual-routing-development-gain';
        readout.recommendation = [ ...
        'The residual learner improves its registered analytic ', ...
        'backbone under the development gate, but at least 10 ', ...
        'screening seeds and a held-out split are still required.'];
    elseif seedCount < 30
        readout.status = 'residual-routing-screening-gain';
        readout.recommendation = [ ...
        'The residual learner improves its registered analytic ', ...
        'backbone in a screening-size run; a registered held-out ', ...
        'validation remains required.'];
    else
        readout.status = 'residual-routing-validation-size-gain';
        readout.recommendation = [ ...
        'The residual learner improves its registered analytic ', ...
        'backbone in a validation-size run. Held-out status must ', ...
        'still be established by the registered data split.'];
    end
    decision.residualRouting = readout;
end
dynamicReadout = decision.dynamicAttribution;
if dynamicReadout.available
    if ~dynamicReadout.completeBaselineSet
        dynamicReadout.status = ...
            'dynamic-attribution-incomplete-controls';
        dynamicReadout.recommendation = [ ...
            'Run the candidate-specific registered controls at the ', ...
            'same source weight and action support before attributing ', ...
            'online gain. Gateway candidates require round-robin, ', ...
            'fixed, rotating and link-aware gateway controls.'];
    elseif ~dynamicReadout.passesAttributionGate
        dynamicReadout.status = 'dynamic-attribution-gate-failed';
        dynamicReadout.recommendation = [ ...
            'The candidate does not jointly pass the gain, per-seed, ', ...
            'tail, byte, feasibility and within-window route-change ', ...
            'gates, including gateway-only dynamics and formation-union ', ...
            'connectivity, against the strongest registered controls.'];
    elseif seedCount < 10
        dynamicReadout.status = 'dynamic-attribution-development-gain';
        dynamicReadout.recommendation = [ ...
            'The candidate passes the bounded attribution gate; retain ', ...
            'it for a frozen 10-seed screening run.'];
    elseif seedCount < 30
        dynamicReadout.status = 'dynamic-attribution-screening-gain';
        dynamicReadout.recommendation = [ ...
            'The candidate passes a screening-size attribution gate; ', ...
            'a separately registered held-out validation is required.'];
    else
        dynamicReadout.status = ...
            'dynamic-attribution-validation-size-gain';
        dynamicReadout.recommendation = [ ...
            'The candidate passes the validation-size attribution gate; ', ...
            'held-out provenance must still be verified.'];
    end
    decision.dynamicAttribution = dynamicReadout;
end
structuredReadout = decision.structuredTreeAttribution;
if structuredReadout.available
    if ~structuredReadout.completeBaselineSet
        structuredReadout.status = ...
            'structured-tree-attribution-incomplete-controls';
        structuredReadout.recommendation = [ ...
            'Run the complete same-weight fixed-index, link-tree and ', ...
            'registered cyclic-path root/receiver-phase sweep ', ...
            'before attributing any gain to the learned ranker.'];
    elseif ~structuredReadout.passesAttributionGate
        structuredReadout.status = ...
            'structured-tree-attribution-gate-failed';
        structuredReadout.recommendation = [ ...
            'The structured candidate does not jointly pass matched ', ...
            'gain, every-seed, tail, communication, route-change and ', ...
            'every-step pairwise-union strong-connectivity gates.'];
    elseif seedCount < 10
        structuredReadout.status = ...
            'structured-tree-attribution-development-gain';
        structuredReadout.recommendation = [ ...
            'The frozen candidate passes the bounded matched-control ', ...
            'gate; retain it for a separately registered 10-seed ', ...
            'screening run.'];
    elseif seedCount < 30
        structuredReadout.status = ...
            'structured-tree-attribution-screening-gain';
        structuredReadout.recommendation = [ ...
            'The frozen candidate passes the screening-size matched ', ...
            'gate; a separately registered held-out validation remains ', ...
            'required.'];
    else
        structuredReadout.status = ...
            'structured-tree-attribution-validation-size-gain';
        structuredReadout.recommendation = [ ...
            'The frozen candidate passes the validation-size matched ', ...
            'gate; held-out provenance must still be verified.'];
    end
    decision.structuredTreeAttribution = structuredReadout;
end
if decision.structuredTreeAttribution.available
    decision.status = ...
        decision.structuredTreeAttribution.status;
    decision.recommendation = ...
        decision.structuredTreeAttribution.recommendation;
elseif strcmp(decision.status, 'insufficient-arms')
    if decision.residualRouting.available
        decision.status = decision.residualRouting.status;
        decision.recommendation = ...
            decision.residualRouting.recommendation;
    elseif decision.dynamicAttribution.available
        decision.status = decision.dynamicAttribution.status;
        decision.recommendation = ...
            decision.dynamicAttribution.recommendation;
    elseif decision.directedRouting.available
        decision.status = decision.directedRouting.status;
        decision.recommendation = ...
            decision.directedRouting.recommendation;
    end
end
end

function decision = applyDirectedRoutingDecision(decision, seedCount)
readout = decision.directedRouting;
if ~readout.available
    return;
end
if ~readout.passesMeanTrackingGate
    readout.status = 'directed-routing-below-mean-gate';
    readout.recommendation = [ ...
        'The deployment-observable directed-routing arm remains below ', ...
        'the registered mean-tracking gain against static and local.'];
elseif ~readout.tailSafeVsStatic
    readout.status = 'directed-routing-development-gain-tail-caveat';
    readout.recommendation = [ ...
        'The deployment-observable directed-routing arm passes the ', ...
        'mean-tracking and communication screen, but its strict ', ...
        'worst-node comparison against static still needs validation.'];
elseif seedCount < 10
    readout.status = 'directed-routing-development-gain';
    readout.recommendation = [ ...
        'The deployment-observable directed-routing arm passes the ', ...
        'bounded development gates; at least 10 screening seeds and ', ...
        'a held-out split are still required.'];
elseif seedCount < 30
    readout.status = 'directed-routing-screening-gain';
    readout.recommendation = [ ...
        'The deployment-observable directed-routing arm passes a ', ...
        'screening-size run; registered held-out validation remains ', ...
        'required.'];
else
    readout.status = 'directed-routing-validation-size-gain';
    readout.recommendation = [ ...
        'The deployment-observable directed-routing arm passes the ', ...
        'validation-size gate. Held-out status must still be established ', ...
        'by the registered data split.'];
end
decision.directedRouting = readout;
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open report path: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, '# Dynamic-topology oracle-gap screen\n\n');
fprintf(fid, '- Preset: `%s`\n', summary.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(summary.seeds));
fprintf(fid, '- Generated: %s\n', summary.generatedAt);
fprintf(fid, '- Decision status: `%s`\n\n', summary.decision.status);
fprintf(fid, '- Focus window: `%s`, steps `%s`\n\n', ...
    summary.records(1, 1).focusWindowName, ...
