function decision = computeScreenDecision( ...
        aggregates, seedCount, options, scenarioConfig)
staticIdx = findMode(aggregates, 'robust-static');
localIdx = findMode(aggregates, 'local');
learnedDirectedIdx = findMode( ...
    aggregates, 'learned-directed-routing');
residualDirectedIdx = findMode( ...
    aggregates, 'confidence-residual-directed-routing');
residualBackboneIdx = findMode( ...
    aggregates, 'directed-reliability-w50');
analyticIdx = [findMode(aggregates, 'reliability'), ...
    findMode(aggregates, 'discrepancy')];
oracleIdx = findMode(aggregates, 'oracle-consensus');
truthOracleIdx = findMode(aggregates, 'oracle-truth');
decision = struct( ...
    'status', 'insufficient-arms', ...
    'primaryAttributionFamily', ...
        options.primaryAttributionFamily, ...
    'availableAttributionFamilies', {cell(1, 0)}, ...
    'constraintEligibleArmCount', 0, ...
    'bestObservedArm', '', ...
    'bestObservedFocusEospa', NaN, ...
    'bestObservedGainVsStaticPercent', NaN, ...
    'bestObservedByteMismatchPercent', NaN, ...
    'minimumPracticalTrackingGainPercent', ...
        options.minimumPracticalTrackingGainPercent, ...
    'oracleConsensusGainPercent', NaN, ...
    'oracleTrackingGainPercent', NaN, ...
    'analyticOracleGainCapture', NaN, ...
    'diagnosticReferenceDominated', false, ...
    'attemptedByteMismatchPercent', NaN, ...
    'communicationMatchedWithinTwoPercent', false, ...
    'directedRouting', emptyDirectedRoutingReadout(), ...
    'residualRouting', emptyResidualRoutingReadout(), ...
    'dynamicAttribution', emptyDynamicAttributionReadout(), ...
    'structuredTreeAttribution', ...
        emptyStructuredTreeAttributionReadout(), ...
    'rollingSafeAttribution', ...
        emptyRollingSafeAttributionReadout(), ...
    'diagnosticOracle', emptyDiagnosticOracleReadout(), ...
    'recommendation', 'Run the complete registered arm set.');
decision.diagnosticOracle = ...
    computeDiagnosticOracleReadout(aggregates);
decision.directedRouting = computeDirectedRoutingReadout( ...
    aggregates, staticIdx, localIdx, learnedDirectedIdx, ...
    options.minimumPracticalTrackingGainPercent);
decision.residualRouting = computeResidualRoutingReadout( ...
    aggregates, residualDirectedIdx, residualBackboneIdx, ...
    options.minimumPracticalTrackingGainPercent);
decision.dynamicAttribution = computeDynamicAttributionReadout( ...
    aggregates, options.minimumPracticalTrackingGainPercent, ...
    options.minimumDynamicRouteDifferenceFraction, ...
    options.minimumGatewayControlPhaseCount);
decision.structuredTreeAttribution = ...
    computeStructuredTreeAttributionReadout( ...
        aggregates, scenarioConfig, ...
        options.minimumPracticalTrackingGainPercent, ...
        options.minimumDynamicRouteDifferenceFraction);
decision.rollingSafeAttribution = ...
    computeRollingSafeAttributionReadout( ...
        aggregates, scenarioConfig, ...
        options.minimumPracticalTrackingGainPercent);
if ~isempty(staticIdx)
    eligible = false(1, numel(aggregates));
    staticBytesBySeed = ...
        aggregates(staticIdx).attemptedBytesBySeed;
    staticEdgesBySeed = ...
        aggregates(staticIdx).meanEdgeCountBySeed;
    byteMismatchByArm = inf(1, numel(aggregates));
    for armIdx = 1:numel(aggregates)
        byteMismatchBySeed = 100 * abs( ...
            aggregates(armIdx).attemptedBytesBySeed - ...
            staticBytesBySeed) ./ max(staticBytesBySeed, 1);
        byteMismatchByArm(armIdx) = max(byteMismatchBySeed);
        eligible(armIdx) = ...
            ~isPrivilegedAggregate(aggregates(armIdx)) && ...
            all(isfinite(aggregates(armIdx).focusEospaBySeed)) && ...
            all(aggregates(armIdx).topologyInfeasibleRateBySeed <= ...
                1e-12) && ...
            all(abs(aggregates(armIdx).meanEdgeCountBySeed - ...
                staticEdgesBySeed) <= 1e-9) && ...
            all(byteMismatchBySeed <= 2 + 1e-12);
    end
    eligibleIdx = find(eligible);
    decision.constraintEligibleArmCount = numel(eligibleIdx);
    if isempty(eligibleIdx)
        decision = applyRoutingDecisions(decision, seedCount);
        return;
    end
    [decision.bestObservedFocusEospa, bestCursor] = min( ...
        [aggregates(eligibleIdx).focusEospa]);
    bestIdx = eligibleIdx(bestCursor);
    decision.bestObservedArm = aggregates(bestIdx).name;
    decision.bestObservedGainVsStaticPercent = percentImprovement( ...
        aggregates(staticIdx).focusEospa, ...
        aggregates(bestIdx).focusEospa);
    decision.bestObservedByteMismatchPercent = ...
        byteMismatchByArm(bestIdx);
end

if isempty(staticIdx) || isempty(analyticIdx) || isempty(oracleIdx)
    if isempty(staticIdx)
        decision = applyRoutingDecisions(decision, seedCount);
        return;
    end
    decision.communicationMatchedWithinTwoPercent = ...
        decision.bestObservedByteMismatchPercent <= 2;
    if decision.bestObservedGainVsStaticPercent <= 0
        decision.status = 'stop-no-observed-dynamic-gain';
        decision.recommendation = [ ...
            'No evaluated dynamic policy improves focus tracking over ', ...
            'the registered static graph in this conditional screen.'];
    elseif decision.bestObservedGainVsStaticPercent < ...
            decision.minimumPracticalTrackingGainPercent
        decision.status = 'stop-negligible-observed-gain';
        decision.recommendation = sprintf([ ...
            'The best observed communication-matched gain is below ', ...
            'the registered %.2f%% practical-effect threshold.'], ...
            decision.minimumPracticalTrackingGainPercent);
    elseif ~decision.communicationMatchedWithinTwoPercent
        decision.status = 'communication-mismatch';
        decision.recommendation = [ ...
            'The best observed tracking arm is not attempted-byte ', ...
            'matched to the registered static graph.'];
    elseif seedCount < 10
        decision.status = 'best-observed-development';
        decision.recommendation = [ ...
            'A communication-matched best observed strategy exists, ', ...
            'but fewer than 10 seeds make this a bounded development ', ...
            'result.'];
    elseif seedCount < 30
        decision.status = 'best-observed-screening';
        decision.recommendation = [ ...
            'The reported arm is the best observed registered strategy ', ...
            'in a screening-size run; retain the finite-pool boundary.'];
    else
        decision.status = 'best-observed-validation-size';
        decision.recommendation = [ ...
            'The reported arm is the best observed registered strategy ', ...
            'in a validation-size run. Held-out status must still be ', ...
            'established by the registered data split.'];
    end
    decision = applyRoutingDecisions(decision, seedCount);
    return;
end

candidateIdx = [staticIdx, analyticIdx];
[bestConsensus, bestConsensusCursor] = min( ...
    [aggregates(candidateIdx).focusPosteriorConsensus]);
bestConsensusIdx = candidateIdx(bestConsensusCursor);
[bestTracking, ~] = min([aggregates(candidateIdx).focusEospa]);
oracleConsensus = aggregates(oracleIdx).focusPosteriorConsensus;
if isempty(truthOracleIdx)
    oracleTracking = aggregates(oracleIdx).focusEospa;
else
    oracleTracking = aggregates(truthOracleIdx).focusEospa;
end
decision.oracleConsensusGainPercent = percentImprovement( ...
    bestConsensus, oracleConsensus);
decision.oracleTrackingGainPercent = percentImprovement( ...
    bestTracking, oracleTracking);
decision.attemptedByteMismatchPercent = 100 * abs( ...
    aggregates(bestConsensusIdx).attemptedBytes - ...
    aggregates(oracleIdx).attemptedBytes) / max( ...
    aggregates(bestConsensusIdx).attemptedBytes, 1);
decision.communicationMatchedWithinTwoPercent = ...
    decision.attemptedByteMismatchPercent <= 2;
decision.diagnosticReferenceDominated = ...
    oracleConsensus >= bestConsensus && ...
    oracleTracking >= bestTracking;

bestAnalytic = min([aggregates(analyticIdx).focusPosteriorConsensus]);
staticValue = aggregates(staticIdx).focusPosteriorConsensus;
oracleDenominator = staticValue - oracleConsensus;
if oracleDenominator > 0 && bestAnalytic >= oracleConsensus
    decision.analyticOracleGainCapture = ...
        (staticValue - bestAnalytic) / oracleDenominator;
end

if seedCount < 10
    decision.status = 'screening-only';
    decision.recommendation = [ ...
        'Treat this as a runtime and signal check; at least 10 paired ', ...
        'screening seeds are required before a research stop decision.'];
elseif ~decision.communicationMatchedWithinTwoPercent
    decision.status = 'communication-mismatch';
    decision.recommendation = [ ...
        'Compare performance on an attempted-byte-matched curve before ', ...
        'interpreting the oracle gap.'];
elseif decision.diagnosticReferenceDominated
    decision.status = 'diagnostic-reference-dominated';
    decision.recommendation = [ ...
        'The one-step diagnostic reference is beaten by a deployable ', ...
        'control and cannot identify a residual learning gap. Redesign ', ...
        'the teacher/look-ahead objective and audit the strongest fixed ', ...
        'graph before training a GNN.'];
elseif decision.oracleConsensusGainPercent < 10 && ...
        decision.oracleTrackingGainPercent < 5
    decision.status = 'stop-no-oracle-gap';
    decision.recommendation = [ ...
        'The registered practical gap is absent; do not train a GNN on ', ...
        'this scene without redesigning the information handover.'];
elseif isfinite(decision.analyticOracleGainCapture) && ...
        decision.analyticOracleGainCapture >= 0.90
    decision.status = 'stop-analytic-sufficient';
    decision.recommendation = [ ...
        'The analytic posterior heuristic captures at least 90% of the ', ...
        'oracle consensus gain; prefer the simpler method.'];
else
    decision.status = 'continue-learned-policy';
    decision.recommendation = [ ...
        'A residual oracle gap remains after strong analytic controls; ', ...
        'proceed to learned edge-value prediction with constraint ', ...
        'projection.'];
end
decision = applyRoutingDecisions(decision, seedCount);
end

