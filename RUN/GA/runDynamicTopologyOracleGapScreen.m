        labelSetPolicyOptions.fixedResidualWeight = ...
            protocol.localResidualWeight;
    end
    config.topologyPolicyFcn = ...
        @(context) ...
            selectLabelSetMessagePassingRoutingPolicy( ...
                context, labelSetModel, ...
                labelSetPolicyOptions);
    return;
end
