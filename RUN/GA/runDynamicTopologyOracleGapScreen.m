    candidate.focusFormationUnionWeakConnectedBySeed >= 1);
readout.formationUnionStrongConnectedEverySeed = all( ...
    candidate.focusFormationUnionStrongConnectedBySeed >= 1);
readout.minimumInstantaneousFormationWeakFraction = min( ...
    candidate.focusFormationWeakConnectivityFractionBySeed);
readout.minimumGatewayFormationCoverage = min( ...
    candidate.focusGatewayFormationCoverageFractionBySeed);
readout.minimumDifferenceFromFixedIndex = min( ...
    candidate.focusFractionReceiverTimeDifferentFromFixedIndexMapBySeed);
readout.differsFromFixedIndexEnough = ...
    readout.minimumDifferenceFromFixedIndex + 1e-12 >= ...
    minimumRouteDifference;
readout.receiverCoverageComplete = all( ...
    candidate.focusReceiverCoverageFractionBySeed >= 1 - 1e-12);
readout.crossFormationRoutesObserved = any( ...
    candidate.focusCrossFormationMessageFractionBySeed > 0);
readout.zeroInfeasibility = all( ...
    candidate.focusTopologyInfeasibleRateBySeed <= 1e-12);
readout.minimumPracticalGainPercent = minimumGainPercent;
readout.minimumRouteDifferenceFraction = minimumRouteDifference;
readout.passesAttributionGate = ...
    readout.completeBaselineSet && ...
    readout.gainVsStrongControlPercent >= minimumGainPercent && ...
    readout.positiveGainEverySeed && ...
    readout.tailSafeVsStrongControl && ...
    readout.communicationFair && ...
    readout.distinctMapsEverySeed && ...
    readout.withinWindowChangesEverySeed && ...
    readout.crossFormationRoutesObserved && ...
    readout.distinctGatewayMapsEverySeed && ...
    readout.gatewayChangesEverySeed && ...
    readout.formationUnionWeakConnectedEverySeed && ...
    readout.differsFromFixedIndexEnough && ...
    readout.receiverCoverageComplete && ...
    readout.zeroInfeasibility;
end

