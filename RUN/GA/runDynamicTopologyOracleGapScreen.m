            ~ismember(currentSeed, ...
                protocol.lockedHeldoutM24Seeds)
        error(['Label-set held-out evaluation is sealed or the ', ...
            'seed is outside the registered split.']);
    end
    if ~protocol.safeProjectionSmokeAuthorized || ...
            scenarioConfig.numberOfSensors ~= ...
                protocol.expectedNodeCount || ...
            exist(labelSetMessagePassingModelPath, 'file') ~= 2
        error('Label-set message-passing arm is unavailable.');
    end
    loaded = load(labelSetMessagePassingModelPath, 'model');
