function readout = computeDynamicAttributionReadout( ...
    aggregates, minimumGainPercent, minimumRouteDifference, ...
    minimumGatewayControlPhaseCount)
readout = emptyDynamicAttributionReadout();
modes = {aggregates.mode};
candidateIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, ['^directed-(reliability-quality-|', ...
           'gateway-v1-|tree-v2-|cycle-v3-|tree-v4-)'], ...
        'once')), modes));
if isempty(candidateIdx)
    return;
end
fixedIndexIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-fixed-index-', 'once')), modes));
fixedCycleIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-fixed-cycle-', 'once')), modes));
roundRobinIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-round-robin-', 'once')), modes));
physicalRoundRobinIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-physical-round-robin-', 'once')), modes));
fixedGatewayIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-fixed-gateway-', 'once')), modes));
rotatingGatewayIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-rotating-gateway-', 'once')), modes));
linkGatewayIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    mode, '^directed-link-gateway-', 'once')), modes));
allBaselineIdx = [ ...
    fixedIndexIdx, fixedCycleIdx, roundRobinIdx, ...
    physicalRoundRobinIdx, fixedGatewayIdx, ...
    rotatingGatewayIdx, linkGatewayIdx];
if isempty(allBaselineIdx)
    return;
end
validBaselineMask = false(1, numel(allBaselineIdx));
for cursor = 1:numel(allBaselineIdx)
    arm = aggregates(allBaselineIdx(cursor));
    validBaselineMask(cursor) = ...
        all(isfinite(arm.focusEospaBySeed)) && ...
        all(isfinite(arm.focusWorstSensorEospaBySeed)) && ...
        all(isfinite(arm.focusAttemptedBytesBySeed)) && ...
        all(arm.focusReceiverCoverageFractionBySeed >= 1 - 1e-12) && ...
        all(arm.focusTopologyInfeasibleRateBySeed <= 1e-12);
end
baselineIdx = allBaselineIdx(validBaselineMask);
if isempty(baselineIdx)
    return;
end
validFixedIndexIdx = intersect(fixedIndexIdx, baselineIdx, 'stable');
validFixedCycleIdx = intersect(fixedCycleIdx, baselineIdx, 'stable');
validRoundRobinIdx = intersect(roundRobinIdx, baselineIdx, 'stable');
validPhysicalRoundRobinIdx = intersect( ...
    physicalRoundRobinIdx, baselineIdx, 'stable');
validFixedGatewayIdx = intersect( ...
    fixedGatewayIdx, baselineIdx, 'stable');
validRotatingGatewayIdx = intersect( ...
    rotatingGatewayIdx, baselineIdx, 'stable');
validLinkGatewayIdx = intersect( ...
    linkGatewayIdx, baselineIdx, 'stable');
completeControlsByCandidate = false(1, numel(candidateIdx));
structuralEligibilityByCandidate = false(1, numel(candidateIdx));
candidateGainByCandidate = -inf(1, numel(candidateIdx));
for cursor = 1:numel(candidateIdx)
    token = regexp( ...
        modes{candidateIdx(cursor)}, '-w([0-9]+)$', ...
        'tokens', 'once');
    if isempty(token)
        continue;
    end
    suffix = ['-w', token{1}];
    arm = aggregates(candidateIdx(cursor));
    matchedFixedIndex = validFixedIndexIdx(cellfun(@(mode) ...
        endsWithText(mode, suffix), modes(validFixedIndexIdx)));
    matchedFixedCycle = validFixedCycleIdx(cellfun(@(mode) ...
        endsWithText(mode, suffix), modes(validFixedCycleIdx)));
    matchedRoundRobin = validRoundRobinIdx(cellfun(@(mode) ...
        endsWithText(mode, suffix), modes(validRoundRobinIdx)));
    matchedPhysicalRoundRobin = validPhysicalRoundRobinIdx( ...
        cellfun(@(mode) endsWithText(mode, suffix), ...
            modes(validPhysicalRoundRobinIdx)));
    matchedFixedGateway = validFixedGatewayIdx(cellfun(@(mode) ...
        endsWithText(mode, suffix), modes(validFixedGatewayIdx)));
    matchedRotatingGateway = validRotatingGatewayIdx(cellfun(@(mode) ...
        endsWithText(mode, suffix), modes(validRotatingGatewayIdx)));
    matchedLinkGateway = validLinkGatewayIdx(cellfun(@(mode) ...
        endsWithText(mode, suffix), modes(validLinkGatewayIdx)));
    usesCrossFormation = any( ...
        arm.focusCrossFormationMessageFractionBySeed > 0);
    crossFormationControlSet = false;
    for physicalCursor = 1:numel(matchedPhysicalRoundRobin)
        physicalControl = ...
            aggregates(matchedPhysicalRoundRobin(physicalCursor));
        crossFormationControlSet = ...
            crossFormationControlSet || all( ...
                physicalControl. ...
                    focusCrossFormationMessageFractionBySeed > 0);
    end
    isGatewayCandidate = ~isempty(regexp( ...
        modes{candidateIdx(cursor)}, ...
        ['^directed-(gateway-v1-|tree-v2-|', ...
         'cycle-v3-|tree-v4-)'], 'once'));
    if isGatewayCandidate
        fixedGatewayPhaseCount = countCanonicalGatewayControlPhases( ...
            modes, matchedFixedGateway, ...
            minimumGatewayControlPhaseCount);
        rotatingGatewayPhaseCount = countCanonicalGatewayControlPhases( ...
            modes, matchedRotatingGateway, ...
            minimumGatewayControlPhaseCount);
        weightMatchedControlSet = ...
            ~isempty(matchedRoundRobin) && ...
            fixedGatewayPhaseCount >= ...
                minimumGatewayControlPhaseCount && ...
            rotatingGatewayPhaseCount >= ...
                minimumGatewayControlPhaseCount && ...
            ~isempty(matchedLinkGateway);
        gatewayControls = [ ...
            matchedFixedGateway, matchedRotatingGateway, ...
            matchedLinkGateway];
        crossFormationControlSet = false;
        for gatewayCursor = 1:numel(gatewayControls)
            gatewayControl = aggregates(gatewayControls(gatewayCursor));
            crossFormationControlSet = ...
                crossFormationControlSet || all( ...
                    gatewayControl. ...
                        focusCrossFormationMessageFractionBySeed > 0);
        end
        actionSupportMatched = ...
            ~usesCrossFormation || crossFormationControlSet;
        matchedCandidateControls = [ ...
            matchedRoundRobin, gatewayControls];
    else
        weightMatchedControlSet = ...
            ~isempty(matchedFixedIndex) && ...
            ~isempty(matchedFixedCycle) && ...
            ~isempty(matchedRoundRobin);
        actionSupportMatched = ...
            ~usesCrossFormation || crossFormationControlSet;
        matchedCandidateControls = [ ...
            matchedFixedIndex, matchedFixedCycle, ...
            matchedRoundRobin];
        if usesCrossFormation
            matchedCandidateControls = [ ...
                matchedCandidateControls, ...
                matchedPhysicalRoundRobin]; %#ok<AGROW>
        end
    end
    completeControlsByCandidate(cursor) = ...
        weightMatchedControlSet && actionSupportMatched;
    structuralEligibilityByCandidate(cursor) = ...
        completeControlsByCandidate(cursor) && ...
        all(isfinite(arm.focusEospaBySeed)) && ...
        all(arm.focusTopologyInfeasibleRateBySeed <= 1e-12) && ...
        all(arm.focusReceiverCoverageFractionBySeed >= 1 - 1e-12) && ...
        all(arm.focusDistinctDirectedRouteMapCountBySeed > 1) && ...
        all(arm.focusWithinWindowRouteChangeFractionBySeed > 0) && ...
        all(arm.focusDistinctGatewayRouteMapCountBySeed > 1) && ...
        all(arm. ...
            focusWithinWindowGatewayRouteChangeFractionBySeed > 0) && ...
        all(arm.focusFormationUnionWeakConnectedBySeed >= 1) && ...
        all(arm. ...
            focusFractionReceiverTimeDifferentFromFixedIndexMapBySeed + ...
            1e-12 >= minimumRouteDifference);
    if completeControlsByCandidate(cursor)
        registeredFocus = vertcat( ...
            aggregates(matchedCandidateControls).focusEospaBySeed);
        referenceBySeed = min(registeredFocus, [], 1);
        candidateGainByCandidate(cursor) = percentImprovement( ...
            mean(referenceBySeed), arm.focusEospa);
    end
end
completeCandidateIdx = candidateIdx(completeControlsByCandidate);
structuralCandidateIdx = ...
    candidateIdx(structuralEligibilityByCandidate);
if ~isempty(structuralCandidateIdx)
    selectionPool = structuralCandidateIdx;
elseif ~isempty(completeCandidateIdx)
    selectionPool = completeCandidateIdx;
else
    selectionPool = candidateIdx;
end
selectionCandidateCursor = zeros(1, numel(selectionPool));
for poolCursor = 1:numel(selectionPool)
    selectionCandidateCursor(poolCursor) = ...
        find(candidateIdx == selectionPool(poolCursor), 1);
end
selectionValues = ...
    candidateGainByCandidate(selectionCandidateCursor);
if any(isfinite(selectionValues))
    [~, candidateCursor] = max(selectionValues);
else
    selectionValues = [aggregates(selectionPool).focusEospa];
    selectionValues(~isfinite(selectionValues)) = inf;
    [~, candidateCursor] = min(selectionValues);
    if isempty(candidateCursor) || all(isinf(selectionValues))
        candidateCursor = 1;
    end
end
candidate = aggregates(selectionPool(candidateCursor));
weightToken = regexp( ...
    candidate.mode, '-w([0-9]+)$', 'tokens', 'once');
if isempty(weightToken)
    return;
end
weightSuffix = ['-w', weightToken{1}];
readout.available = true;
readout.arm = candidate.name;
readout.availableCandidateCount = numel(candidateIdx);
readout.completeControlCandidateCount = ...
    numel(completeCandidateIdx);
readout.structurallyEligibleCandidateCount = ...
    numel(structuralCandidateIdx);
matchedFixedIndexIdx = validFixedIndexIdx(cellfun(@(mode) ...
    endsWithText(mode, weightSuffix), modes(validFixedIndexIdx)));
matchedFixedCycleIdx = validFixedCycleIdx(cellfun(@(mode) ...
    endsWithText(mode, weightSuffix), modes(validFixedCycleIdx)));
matchedRoundRobinIdx = validRoundRobinIdx(cellfun(@(mode) ...
    endsWithText(mode, weightSuffix), modes(validRoundRobinIdx)));
matchedPhysicalRoundRobinIdx = validPhysicalRoundRobinIdx( ...
    cellfun(@(mode) endsWithText(mode, weightSuffix), ...
        modes(validPhysicalRoundRobinIdx)));
matchedFixedGatewayIdx = validFixedGatewayIdx(cellfun(@(mode) ...
    endsWithText(mode, weightSuffix), modes(validFixedGatewayIdx)));
matchedRotatingGatewayIdx = validRotatingGatewayIdx(cellfun(@(mode) ...
    endsWithText(mode, weightSuffix), modes(validRotatingGatewayIdx)));
matchedLinkGatewayIdx = validLinkGatewayIdx(cellfun(@(mode) ...
    endsWithText(mode, weightSuffix), modes(validLinkGatewayIdx)));
isGatewayCandidate = ~isempty(regexp( ...
    candidate.mode, ...
    ['^directed-(gateway-v1-|tree-v2-|', ...
     'cycle-v3-|tree-v4-)'], 'once'));
if isGatewayCandidate
    readout.matchedFixedGatewayPhaseCount = ...
        countCanonicalGatewayControlPhases( ...
            modes, matchedFixedGatewayIdx, ...
            minimumGatewayControlPhaseCount);
    readout.matchedRotatingGatewayPhaseCount = ...
        countCanonicalGatewayControlPhases( ...
            modes, matchedRotatingGatewayIdx, ...
            minimumGatewayControlPhaseCount);
    readout.minimumGatewayControlPhaseCount = ...
        minimumGatewayControlPhaseCount;
    readout.weightMatchedControlSet = ...
        ~isempty(matchedRoundRobinIdx) && ...
        readout.matchedFixedGatewayPhaseCount >= ...
            minimumGatewayControlPhaseCount && ...
        readout.matchedRotatingGatewayPhaseCount >= ...
            minimumGatewayControlPhaseCount && ...
        ~isempty(matchedLinkGatewayIdx);
else
    readout.weightMatchedControlSet = ...
        ~isempty(matchedFixedIndexIdx) && ...
        ~isempty(matchedFixedCycleIdx) && ...
        ~isempty(matchedRoundRobinIdx);
end
readout.candidateUsesCrossFormation = any( ...
    candidate.focusCrossFormationMessageFractionBySeed > 0);
readout.crossFormationControlSet = false;
if isGatewayCandidate
    crossControlIdx = [ ...
        matchedFixedGatewayIdx, matchedRotatingGatewayIdx, ...
        matchedLinkGatewayIdx];
else
    crossControlIdx = matchedPhysicalRoundRobinIdx;
end
for controlCursor = 1:numel(crossControlIdx)
    crossControl = aggregates(crossControlIdx(controlCursor));
    readout.crossFormationControlSet = ...
        readout.crossFormationControlSet || all( ...
            crossControl.focusCrossFormationMessageFractionBySeed > 0);
end
readout.actionSupportMatched = ...
    ~readout.candidateUsesCrossFormation || ...
    readout.crossFormationControlSet;
readout.completeBaselineSet = ...
    readout.weightMatchedControlSet && ...
    readout.actionSupportMatched;
readout.candidateSourceWeight = ...
    str2double(weightToken{1}) / 100;
if isGatewayCandidate
    matchedBaselineIdx = [ ...
        matchedRoundRobinIdx, matchedFixedGatewayIdx, ...
        matchedRotatingGatewayIdx, matchedLinkGatewayIdx];
else
    matchedBaselineIdx = [ ...
        matchedFixedIndexIdx, matchedFixedCycleIdx, ...
        matchedRoundRobinIdx];
    if readout.candidateUsesCrossFormation
        matchedBaselineIdx = [ ...
            matchedBaselineIdx, matchedPhysicalRoundRobinIdx];
    end
end
if isempty(matchedBaselineIdx)
    return;
end
matchedBaselineFocus = vertcat( ...
    aggregates(matchedBaselineIdx).focusEospaBySeed);
[matchedReferenceBySeed, ~] = min(matchedBaselineFocus, [], 1);
baselineFocus = vertcat(aggregates(baselineIdx).focusEospaBySeed);
[referenceBySeed, referenceCursorBySeed] = min(baselineFocus, [], 1);
seedCount = numel(referenceBySeed);
referenceWorstBySeed = zeros(1, seedCount);
referenceBytesBySeed = zeros(1, seedCount);
for seedIdx = 1:seedCount
    reference = aggregates( ...
        baselineIdx(referenceCursorBySeed(seedIdx)));
    referenceWorstBySeed(seedIdx) = ...
        reference.focusWorstSensorEospaBySeed(seedIdx);
    referenceBytesBySeed(seedIdx) = ...
        reference.focusAttemptedBytesBySeed(seedIdx);
end
gainBySeed = 100 * ( ...
    referenceBySeed - candidate.focusEospaBySeed) ./ ...
    max(abs(referenceBySeed), eps);
byteMismatchBySeed = 100 * abs( ...
    candidate.focusAttemptedBytesBySeed - referenceBytesBySeed) ./ ...
    max(referenceBytesBySeed, 1);
readout.referenceArm = ...
    'best per-seed registered fixed/scheduled control across weights';
if isGatewayCandidate
    readout.matchedReferenceArm = ...
        ['best per-seed weight-matched round-robin/fixed/', ...
         'rotating/link-aware gateway control'];
else
    readout.matchedReferenceArm = ...
        ['best per-seed weight-matched registered control ', ...
         '(including physical round robin when required)'];
end
matchedGainBySeed = 100 * ( ...
    matchedReferenceBySeed - candidate.focusEospaBySeed) ./ ...
    max(abs(matchedReferenceBySeed), eps);
readout.gainVsMatchedControlPercent = percentImprovement( ...
    mean(matchedReferenceBySeed), candidate.focusEospa);
readout.gainVsMatchedControlBySeedPercent = matchedGainBySeed;
readout.positiveGainVsMatchedEverySeed = ...
    all(matchedGainBySeed > 0);
readout.gainVsStrongControlPercent = percentImprovement( ...
    mean(referenceBySeed), candidate.focusEospa);
readout.gainVsStrongControlBySeedPercent = gainBySeed;
readout.positiveGainEverySeed = all(gainBySeed > 0);
readout.tailSafeVsStrongControl = all( ...
    candidate.focusWorstSensorEospaBySeed <= ...
    referenceWorstBySeed + 1e-12);
readout.maximumAttemptedByteMismatchPercent = ...
    max(byteMismatchBySeed);
readout.communicationMatchedWithinTwoPercent = ...
    all(byteMismatchBySeed <= 2 + 1e-12);
readout.noMoreAttemptedBytesEverySeed = all( ...
    candidate.focusAttemptedBytesBySeed <= ...
    referenceBytesBySeed + 1e-12);
readout.strictParetoEverySeed = ...
    readout.positiveGainEverySeed && ...
    readout.noMoreAttemptedBytesEverySeed;
readout.communicationFair = ...
    readout.communicationMatchedWithinTwoPercent || ...
    readout.strictParetoEverySeed;
