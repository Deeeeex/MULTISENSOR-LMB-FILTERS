            'structured-tree-attribution-development-gain';
        structuredReadout.recommendation = [ ...
            'The frozen candidate passes the bounded matched-control ', ...
            'gate; retain it for a separately registered 10-seed ', ...
            'screening run.'];
    elseif seedCount < 30
        structuredReadout.status = ...
            'structured-tree-attribution-screening-gain';
        structuredReadout.recommendation = [ ...
            'The frozen candidate passes the screening-size matched ', ...
            'gate; a separately registered held-out validation remains ', ...
            'required.'];
    else
        structuredReadout.status = ...
            'structured-tree-attribution-validation-size-gain';
        structuredReadout.recommendation = [ ...
            'The frozen candidate passes the validation-size matched ', ...
            'gate; held-out provenance must still be verified.'];
    end
    decision.structuredTreeAttribution = structuredReadout;
end
rollingReadout = decision.rollingSafeAttribution;
if rollingReadout.available
    if ~rollingReadout.completeControlSet
        rollingReadout.status = ...
            'rolling-safe-attribution-incomplete-controls';
        rollingReadout.recommendation = [ ...
            'Run every same-weight cyclic-chunk and burst phase plus ', ...
            'the rolling-constrained link-aware control exactly once, ', ...
            'verify its registered proposal/phase signature, and repair ', ...
            'any duplicate or collapsed behavior before attribution.'];
    elseif ~rollingReadout.passesAttributionGate
        rollingReadout.status = ...
            'rolling-safe-attribution-gate-failed';
        rollingReadout.recommendation = [ ...
            'The rolling-safe candidate does not jointly pass the ', ...
