function readout = computeDirectedRoutingReadout( ...
    aggregates, staticIdx, localIdx, learnedIdx, minimumGainPercent)
readout = emptyDirectedRoutingReadout();
if isempty(staticIdx) || isempty(learnedIdx)
    return;
end
eligible = false(1, numel(learnedIdx));
for cursor = 1:numel(learnedIdx)
    arm = aggregates(learnedIdx(cursor));
    eligible(cursor) = ...
        all(isfinite(arm.focusEospaBySeed)) && ...
        all(arm.topologyInfeasibleRateBySeed <= 1e-12) && ...
        all(arm.attemptedBytesBySeed > 0) && ...
        all(arm.attemptedBytesBySeed <= ...
            1.02 * aggregates(staticIdx).attemptedBytesBySeed);
end
eligibleIdx = learnedIdx(eligible);
readout.available = ~isempty(eligibleIdx);
readout.eligibleArmCount = numel(eligibleIdx);
if isempty(eligibleIdx)
    return;
end
[~, bestCursor] = min([aggregates(eligibleIdx).focusEospa]);
bestIdx = eligibleIdx(bestCursor);
best = aggregates(bestIdx);
static = aggregates(staticIdx);
readout.arm = best.name;
readout.focusEospa = best.focusEospa;
readout.gainVsStaticPercent = percentImprovement( ...
    static.focusEospa, best.focusEospa);
readout.worstNodeGainVsStaticPercent = percentImprovement( ...
    static.worstSensorEospa, best.worstSensorEospa);
readout.attemptedByteRatioPercent = ...
    100 * best.attemptedBytes / max(static.attemptedBytes, 1);
readout.meanDirectedMessageCount = ...
    best.meanDirectedMessageCount;
readout.zeroInfeasibility = ...
    all(best.topologyInfeasibleRateBySeed <= 1e-12);
readout.withinStaticAttemptedBytes = ...
    all(best.attemptedBytesBySeed <= ...
        1.02 * static.attemptedBytesBySeed);
readout.tailSafeVsStatic = ...
    all(best.worstSensorEospaBySeed <= ...
        static.worstSensorEospaBySeed + 1e-12);
if ~isempty(localIdx)
    local = aggregates(localIdx);
    readout.gainVsLocalPercent = percentImprovement( ...
        local.focusEospa, best.focusEospa);
    readout.worstNodeGainVsLocalPercent = percentImprovement( ...
        local.worstSensorEospa, best.worstSensorEospa);
    readout.tailSafeVsLocal = ...
        all(best.worstSensorEospaBySeed <= ...
            local.worstSensorEospaBySeed + 1e-12);
end
readout.passesMeanTrackingGate = ...
    ~isempty(localIdx) && ...
    readout.gainVsStaticPercent >= minimumGainPercent && ...
    readout.gainVsLocalPercent >= minimumGainPercent;
end

