            ~allowUnselectedLabelSetArtifact
        error(['Unselected label-set model requires an explicit ', ...
            'training-only override.']);
    end
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyDirectedEnabled = true;
    config.topologyDirectedMessageBudget = ...
        2 * scenarioConfig.numberOfSensors;
    config.topologyPolicyHistoryDepth = 3;
    config.topologyPolicyName = arm.mode;
    labelSetModel = loaded.model;
    labelSetPolicyOptions = struct( ...
        'protocol', protocol);
