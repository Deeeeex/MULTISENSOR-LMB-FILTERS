            'B3, maturity-denominator, delivered-B3 and observable-policy ', ...
            'contract against the strongest matched controls.'];
    elseif seedCount < 10
        rollingReadout.status = ...
            'rolling-safe-attribution-development-gain';
        rollingReadout.recommendation = [ ...
            'The candidate passes the bounded rolling-safe attribution ', ...
            'gate; freeze it before a separately registered 10-seed ', ...
            'screening run.'];
    elseif seedCount < 30
        rollingReadout.status = ...
            'rolling-safe-attribution-screening-gain';
        rollingReadout.recommendation = [ ...
            'The frozen candidate passes the screening-size matched ', ...
            'rolling-safe gate; a separately registered held-out ', ...
            'validation remains required.'];
    else
        rollingReadout.status = ...
            'rolling-safe-attribution-validation-size-gain';
        rollingReadout.recommendation = [ ...
            'The frozen candidate passes the validation-size matched ', ...
            'rolling-safe gate; held-out provenance must still be ', ...
            'verified.'];
    end
    decision.rollingSafeAttribution = rollingReadout;
end
decision = applyPrimaryAttributionFamily(decision);
end

function decision = applyPrimaryAttributionFamily(decision)
families = { ...
    'rolling-safe', 'structured-tree', 'dynamic', ...
    'residual-routing', 'directed-routing'};
readouts = { ...
    decision.rollingSafeAttribution, ...
    decision.structuredTreeAttribution, ...
    decision.dynamicAttribution, ...
    decision.residualRouting, ...
    decision.directedRouting};
available = cellfun(@(readout) readout.available, readouts);
decision.availableAttributionFamilies = families(available);
primary = decision.primaryAttributionFamily;
if strcmp(primary, 'auto')
    if nnz(available) == 1
        selected = find(available, 1);
        decision.status = readouts{selected}.status;
        decision.recommendation = ...
            readouts{selected}.recommendation;
    elseif nnz(available) > 1
        decision.status = 'multiple-attribution-families';
        decision.recommendation = sprintf([ ...
            'Multiple attribution families are present (%s). ', ...
            'Set primaryAttributionFamily explicitly before using a ', ...
            'single top-level research decision.'], ...
            strjoin(families(available), ', '));
    end
    return;
end
selected = find(strcmp(families, primary), 1);
if isempty(selected) || ~available(selected)
    decision.status = 'primary-attribution-family-unavailable';
    decision.recommendation = sprintf([ ...
        'The requested primary attribution family `%s` has no ', ...
        'candidate in this run.'], primary);
    return;
end
decision.status = readouts{selected}.status;
decision.recommendation = readouts{selected}.recommendation;
end

