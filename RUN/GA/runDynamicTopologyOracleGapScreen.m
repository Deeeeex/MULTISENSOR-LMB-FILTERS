function fraction = computeCrossFormationMessageFraction( ...
    activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = size(activeEdges, 1);
if numel(groupIds) ~= nodeCount
    fraction = NaN;
    return;
end
crossFormation = groupIds(:) ~= groupIds;
crossCount = 0;
messageCount = 0;
for timeIdx = 1:size(activeEdges, 3)
    active = activeEdges(:, :, timeIdx);
    crossCount = crossCount + nnz(active & crossFormation);
    messageCount = messageCount + nnz(active);
end
fraction = crossCount / max(messageCount, 1);
end

function crossEdges = keepCrossFormationEdges(activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = size(activeEdges, 1);
if numel(groupIds) ~= nodeCount
    error('sensorGroupIds must match the active-edge tensor.');
end
crossMask = groupIds(:) ~= groupIds;
crossEdges = activeEdges & repmat( ...
    crossMask, 1, 1, size(activeEdges, 3));
end

function [weakFraction, strongFraction, unionWeak, unionStrong, ...
        meanCoverage] = computeFormationGraphMetrics( ...
            activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
groupCount = numel(groups);
timeCount = size(activeEdges, 3);
if groupCount <= 1
    weakFraction = 1;
    strongFraction = 1;
    unionWeak = 1;
    unionStrong = 1;
    meanCoverage = 1;
    return;
end
weakByTime = false(1, timeCount);
strongByTime = false(1, timeCount);
coverageByTime = zeros(1, timeCount);
unionAdjacency = false(groupCount);
for timeIdx = 1:timeCount
    formationAdjacency = buildFormationAdjacencyFromDiagnosticMask( ...
        activeEdges(:, :, timeIdx), groupIds, groups);
    unionAdjacency = unionAdjacency | formationAdjacency;
    weakByTime(timeIdx) = isWeaklyConnected(formationAdjacency);
    strongByTime(timeIdx) = isStronglyConnected(formationAdjacency);
    incident = any( ...
        formationAdjacency | formationAdjacency', 2);
    coverageByTime(timeIdx) = mean(incident);
end
weakFraction = mean(weakByTime);
strongFraction = mean(strongByTime);
unionWeak = double(isWeaklyConnected(unionAdjacency));
unionStrong = double(isStronglyConnected(unionAdjacency));
meanCoverage = mean(coverageByTime);
end

function fraction = computePairwiseFormationUnionStrongFraction( ...
        activeEdges, groupIds, previousActiveEdges)
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
timeCount = size(activeEdges, 3);
if numel(groups) <= 1
    fraction = 1;
    return;
end
if isempty(previousActiveEdges)
    previousFormationAdjacency = false(numel(groups));
    previousAvailable = false;
else
    previousFormationAdjacency = ...
        buildFormationAdjacencyFromDiagnosticMask( ...
            previousActiveEdges, groupIds, groups);
    previousAvailable = true;
end
strongByStep = false(1, timeCount);
for timeIdx = 1:timeCount
    currentFormationAdjacency = ...
        buildFormationAdjacencyFromDiagnosticMask( ...
            activeEdges(:, :, timeIdx), groupIds, groups);
    if previousAvailable
        strongByStep(timeIdx) = isStronglyConnected( ...
            previousFormationAdjacency | ...
            currentFormationAdjacency);
    end
    previousFormationAdjacency = currentFormationAdjacency;
    previousAvailable = true;
end
fraction = mean(strongByStep);
end

function fraction = computeFormationRootedTreeFraction( ...
        activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
timeCount = size(activeEdges, 3);
if numel(groups) <= 1
    fraction = 1;
    return;
end
rootedByStep = false(1, timeCount);
for timeIdx = 1:timeCount
    adjacency = buildFormationAdjacencyFromDiagnosticMask( ...
        activeEdges(:, :, timeIdx), groupIds, groups);
    indegree = sum(adjacency, 1);
    root = find(indegree == 0);
    rootedByStep(timeIdx) = ...
        nnz(adjacency) == numel(groups) - 1 && ...
        numel(root) == 1 && ...
        all(indegree(setdiff(1:numel(groups), root)) == 1) && ...
        all(reachableFromNode(adjacency, root));
end
fraction = mean(rootedByStep);
end

function fraction = computeCrossFormationEdgeCountExactFraction( ...
        activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
groupCount = numel(unique(groupIds, 'stable'));
if groupCount <= 1
    fraction = 1;
    return;
end
crossMask = groupIds(:) ~= groupIds;
timeCount = size(activeEdges, 3);
exactByStep = false(1, timeCount);
for timeIdx = 1:timeCount
    exactByStep(timeIdx) = nnz( ...
        activeEdges(:, :, timeIdx) & crossMask) == ...
        groupCount - 1;
end
fraction = mean(exactByStep);
end

function adjacency = buildFormationAdjacencyFromDiagnosticMask( ...
        diagnosticMask, groupIds, groups)
groupCount = numel(groups);
adjacency = false(groupCount);
[senderIndices, receiverIndices] = find(diagnosticMask);
for edgeIdx = 1:numel(senderIndices)
    senderGroup = find( ...
        groups == groupIds(senderIndices(edgeIdx)), 1);
    receiverGroup = find( ...
        groups == groupIds(receiverIndices(edgeIdx)), 1);
    if senderGroup ~= receiverGroup
        adjacency(senderGroup, receiverGroup) = true;
    end
end
end

