function churnRate = computeWindowChurnRate(activeEdges, previousEdges)
if nargin >= 2 && ~isempty(previousEdges)
    activeEdges = cat(3, logical(previousEdges), activeEdges);
end
timeCount = size(activeEdges, 3);
if timeCount < 2
    churnRate = 0;
    return;
end
previousEdges = activeEdges(:, :, 1:(timeCount - 1));
nextEdges = activeEdges(:, :, 2:timeCount);
changedEdges = xor(previousEdges, nextEdges);
edgeUnion = previousEdges | nextEdges;
churnRate = sum(changedEdges(:)) / max(sum(edgeUnion(:)), 1);
end

function fraction = computeWithinWindowRouteChangeFraction(activeEdges)
timeCount = size(activeEdges, 3);
receiverCount = size(activeEdges, 2);
if timeCount < 2 || receiverCount == 0
    fraction = 0;
    return;
end
changed = xor( ...
    activeEdges(:, :, 1:(timeCount - 1)), ...
    activeEdges(:, :, 2:timeCount));
changedByReceiver = any(changed, 1);
fraction = nnz(changedByReceiver) / ...
    (receiverCount * (timeCount - 1));
end

function count = computeDistinctTopologyCount(activeEdges)
timeCount = size(activeEdges, 3);
if timeCount == 0
    count = 0;
    return;
end
maps = reshape(activeEdges, [], timeCount)';
count = size(unique(maps, 'rows'), 1);
end

function fraction = computePrefixBoundaryRouteChangeFraction( ...
    activeEdges, previousEdges)
receiverCount = size(activeEdges, 2);
if isempty(previousEdges) || isempty(activeEdges) || receiverCount == 0
    fraction = 0;
    return;
end
changedByReceiver = any(xor( ...
    logical(previousEdges), activeEdges(:, :, 1)), 1);
fraction = nnz(changedByReceiver) / receiverCount;
end

function fraction = computeReceiverCoverageFraction(activeEdges)
receiverTimeCoverage = any(activeEdges, 1);
if isempty(receiverTimeCoverage)
    fraction = 0;
else
    fraction = nnz(receiverTimeCoverage) / ...
        numel(receiverTimeCoverage);
end
end

function value = computeMeanUniqueSendersPerReceiver(activeEdges)
receiverCount = size(activeEdges, 2);
if receiverCount == 0
    value = 0;
    return;
end
uniqueSenderCount = zeros(1, receiverCount);
for receiverIdx = 1:receiverCount
    uniqueSenderCount(receiverIdx) = nnz(any( ...
        activeEdges(:, receiverIdx, :), 3));
end
value = mean(uniqueSenderCount);
end

function fraction = computeCrossFormationMessageFraction( ...
    activeEdges, groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = size(activeEdges, 1);
if numel(groupIds) ~= nodeCount
    fraction = NaN;
    return;
end
crossFormation = groupIds(:) ~= groupIds;
crossCount = 0;
messageCount = 0;
for timeIdx = 1:size(activeEdges, 3)
    active = activeEdges(:, :, timeIdx);
    crossCount = crossCount + nnz(active & crossFormation);
    messageCount = messageCount + nnz(active);
end
fraction = crossCount / max(messageCount, 1);
end

function fraction = computeDifferenceFromFixedIndexMap( ...
    activeEdges, groupIds)
reference = buildFixedIndexDirectedMask(groupIds);
receiverCount = size(activeEdges, 2);
timeCount = size(activeEdges, 3);
if receiverCount == 0 || timeCount == 0
    fraction = 0;
    return;
end
changedCount = 0;
for timeIdx = 1:timeCount
    changedCount = changedCount + nnz(any(xor( ...
        activeEdges(:, :, timeIdx), reference), 1));
end
fraction = changedCount / (receiverCount * timeCount);
end

function mask = buildFixedIndexDirectedMask(groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = numel(groupIds);
mask = false(nodeCount);
groups = unique(groupIds);
for groupCursor = 1:numel(groups)
    members = reshape(find(groupIds == groups(groupCursor)), 1, []);
    if numel(members) < 2
        continue;
    end
    mask(members(2), members(1)) = true;
    mask(members(1), members(2:end)) = true;
end
end

function indices = resolveFocusWindow(config, timeCount, analysisStartTime)
window = getField(config, 'focusWindow', [1, timeCount]);
startTime = max([1, round(window(1)), analysisStartTime]);
stopTime = min(timeCount, round(window(end)));
if stopTime < startTime
    indices = analysisStartTime:timeCount;
else
    indices = startTime:stopTime;
end
end

