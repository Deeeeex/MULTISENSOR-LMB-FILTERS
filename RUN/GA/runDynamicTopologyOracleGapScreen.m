function [fraction, matureWindowCount] = ...
    computeRollingB3StrongFraction( ...
        activeEdges, previousHistory, groupIds)
sensorCount = size(activeEdges, 1);
if isempty(previousHistory)
    history = false(sensorCount, sensorCount, 0);
else
    history = logical(previousHistory);
    if ndims(history) < 3
        history = reshape(history, sensorCount, sensorCount, 1);
    end
    if size(history, 3) > 2
        history = history(:, :, end-1:end);
    end
end
strongByWindow = false(1, size(activeEdges, 3));
matureByWindow = false(1, size(activeEdges, 3));
groups = [];
if ~isempty(groupIds)
    groupIds = reshape(groupIds, 1, []);
    groups = unique(groupIds, 'stable');
end
for timeIdx = 1:size(activeEdges, 3)
    current = activeEdges(:, :, timeIdx);
    if size(history, 3) >= 2
        matureByWindow(timeIdx) = true;
        unionMask = any(cat(3, history, current), 3);
        if isempty(groupIds)
            strongByWindow(timeIdx) = ...
                isStronglyConnected(unionMask);
        else
            formationAdjacency = ...
                buildFormationAdjacencyFromDiagnosticMask( ...
                    unionMask, groupIds, groups);
            strongByWindow(timeIdx) = ...
                isStronglyConnected(formationAdjacency);
        end
    end
    if isempty(history)
        history = reshape(current, ...
            sensorCount, sensorCount, 1);
    else
        history(:, :, end + 1) = current;
        if size(history, 3) > 2
            history = history(:, :, end-1:end);
        end
    end
end
matureWindowCount = nnz(matureByWindow);
if matureWindowCount == 0
    fraction = NaN;
else
    fraction = mean(strongByWindow(matureByWindow));
end
end

function connected = isWeaklyConnected(adjacency)
nodeCount = size(adjacency, 1);
if nodeCount <= 1
    connected = true;
    return;
end
connected = all(reachableFromFirst(adjacency | adjacency'));
end

function connected = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
if nodeCount <= 1
    connected = true;
    return;
end
connected = all(reachableFromFirst(adjacency)) && ...
    all(reachableFromFirst(adjacency'));
end

function reachable = reachableFromFirst(adjacency)
nodeCount = size(adjacency, 1);
reachable = false(1, nodeCount);
reachable(1) = true;
while true
    expanded = reachable | any(adjacency(reachable, :), 1);
    if isequal(expanded, reachable)
        break;
    end
    reachable = expanded;
end
end

function reachable = reachableFromNode(adjacency, root)
nodeCount = size(adjacency, 1);
reachable = false(1, nodeCount);
reachable(root) = true;
while true
    expanded = reachable | any(adjacency(reachable, :), 1);
    if isequal(expanded, reachable)
        break;
    end
    reachable = expanded;
end
end

function fraction = computeDifferenceFromFixedIndexMap( ...
    activeEdges, groupIds)
reference = buildFixedIndexDirectedMask(groupIds);
receiverCount = size(activeEdges, 2);
timeCount = size(activeEdges, 3);
if receiverCount == 0 || timeCount == 0
    fraction = 0;
    return;
end
changedCount = 0;
for timeIdx = 1:timeCount
    changedCount = changedCount + nnz(any(xor( ...
        activeEdges(:, :, timeIdx), reference), 1));
end
fraction = changedCount / (receiverCount * timeCount);
end

function mask = buildFixedIndexDirectedMask(groupIds)
groupIds = reshape(groupIds, 1, []);
nodeCount = numel(groupIds);
mask = false(nodeCount);
groups = unique(groupIds);
for groupCursor = 1:numel(groups)
    members = reshape(find(groupIds == groups(groupCursor)), 1, []);
    if numel(members) < 2
        continue;
    end
    mask(members(2), members(1)) = true;
    mask(members(1), members(2:end)) = true;
end
end

function indices = resolveFocusWindow(config, timeCount, analysisStartTime)
window = getField(config, 'focusWindow', [1, timeCount]);
startTime = max([1, round(window(1)), analysisStartTime]);
stopTime = min(timeCount, round(window(end)));
if stopTime < startTime
    indices = analysisStartTime:timeCount;
else
    indices = startTime:stopTime;
end
end

