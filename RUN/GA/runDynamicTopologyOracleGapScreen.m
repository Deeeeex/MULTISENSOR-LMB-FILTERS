            ~strcmp(loaded.model.kind, ...
                'label-set-message-passing-policy') || ...
            ~strcmp(loaded.model.contractVersion, ...
                protocol.messagePassingModelContractVersion) || ...
            loaded.model.featuresUseTruth || ...
            loaded.model.numericLabelIdentifiersUsedAsFeatures || ...
            ~loaded.model.safeProjectorRequired
