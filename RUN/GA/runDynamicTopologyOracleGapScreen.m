function [reportPath, summary] = ...
    runDynamicTopologyOracleGapScreen(presetName, seedList, options)
% RUNDYNAMICTOPOLOGYORACLEGAPSCREEN Paired topology-only evidence gate.
%
% Example:
%   opts = struct('maxTimeSteps', 20);
%   runDynamicTopologyOracleGapScreen('d12-handover', 7, opts);
%
% The same measurements, trajectories and link uniforms are reused across
% arms. Payload compression and event triggering are disabled; only the
% selected topology changes. A cached post-update posterior can optionally
% initialize every arm at the same focus-window state.

if nargin < 1 || isempty(presetName)
    presetName = 'd12-handover';
end
if nargin < 2 || isempty(seedList)
    seedList = 1:3;
end
if nargin < 3 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
options = resolveOptions(options);
armDefinitions = buildArms(options.armNames);

fprintf(['Dynamic topology screen: %s, %d seed(s), ', ...
    '%d arm(s), maxTimeSteps=%s, continuation=%s\n'], ...
    presetName, numel(seedList), numel(armDefinitions), ...
    numericOrAll(options.maxTimeSteps), ...
    numericOrNone(options.continuationStartTime));

records = repmat(emptyRecord(), ...
    numel(seedList), numel(armDefinitions));
validationBySeed = cell(1, numel(seedList));
for seedIdx = 1:numel(seedList)
    seed = seedList(seedIdx);
    fprintf('Generating paired input for seed %d...\n', seed);
    inputs = generateDynamicTopologyScenarioInputs( ...
        presetName, seed, options.scenarioOverrides);
    inputs = cropInputs(inputs, options.maxTimeSteps);
    validationBySeed{seedIdx} = inputs.validation;
    [analysisStartTime, initialLocalPosteriors] = ...
        loadContinuationSnapshot( ...
            options, presetName, seed, inputs);
    for armIdx = 1:numel(armDefinitions)
        arm = armDefinitions(armIdx);
        fprintf('  seed %d arm %s...\n', seed, arm.name);
        triggerConfig = buildArmTriggerConfig( ...
            arm, inputs.config, options.fusionOverrides);
        if ~isempty(initialLocalPosteriors)
            triggerConfig.filterInitialLocalPosteriorBySensor = ...
                initialLocalPosteriors;
            triggerConfig.filterInitialLocalPosteriorTime = ...
                analysisStartTime;
            triggerConfig.filterInitialPreviousAdjacency = ...
                inputs.graphData.staticAdjacency;
        end
        rng(seed + options.filterSeedOffset);
        timerId = tic;
        [stateEstimates, diagnostics] = ...
            runEventTriggeredDistributedLmbFilter( ...
                inputs.model, inputs.measurements, ...
                inputs.sensorTrajectories, inputs.neighborMap, ...
                inputs.commConfig, triggerConfig);
        elapsedSeconds = toc(timerId);
        record = scoreRun( ...
            seed, arm, stateEstimates, diagnostics, ...
            inputs.model, inputs.groundTruthRfs, ...
            inputs.config, elapsedSeconds, analysisStartTime);
        records(seedIdx, armIdx) = record;
        fprintf(['    E-OSPA %.4f, consensus OSPA %.4f, ', ...
            'attempted %.0f B, %.2f s\n'], ...
            record.meanEospa, record.consensusOspa, ...
            record.attemptedBytes, record.elapsedSeconds);
    end
end

summary = aggregateRecords( ...
    presetName, seedList, armDefinitions, records, ...
    validationBySeed, options);
reportPath = '';
if options.writeReport
    outputDirectory = options.outputDirectory;
    if ~exist(outputDirectory, 'dir')
        mkdir(outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    if isempty(options.continuationStartTime)
        stem = sprintf('DYNAMIC_TOPOLOGY_ORACLE_GAP_%s_N%d_%s', ...
            upper(strrep(char(presetName), '-', '_')), ...
            numel(seedList), timestamp);
    else
        stem = sprintf( ...
            'DYNAMIC_TOPOLOGY_CONTINUATION_%s_T%d_N%d_%s', ...
            upper(strrep(char(presetName), '-', '_')), ...
            options.continuationStartTime, ...
            numel(seedList), timestamp);
    end
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    writeReport(reportPath, summary);
    save(matPath, 'summary');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    fprintf('Report: %s\n', reportPath);
end
end

function options = resolveOptions(options)
options.armNames = getField(options, 'armNames', { ...
    'local', 'robust-static', 'reliability', 'discrepancy', ...
    'oracle-consensus', 'oracle-truth'});
options.maxTimeSteps = getField(options, 'maxTimeSteps', inf);
options.writeReport = getField(options, 'writeReport', true);
options.scenarioOverrides = getField( ...
    options, 'scenarioOverrides', struct());
options.fusionOverrides = getField( ...
    options, 'fusionOverrides', struct());
options.outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
options.filterSeedOffset = getField(options, 'filterSeedOffset', 100000);
continuationStart = getField(options, 'continuationStartTime', []);
if isempty(continuationStart)
    options.continuationStartTime = [];
else
    options.continuationStartTime = max(1, round(continuationStart));
end
options.behaviorCacheDirectory = getField( ...
    options, 'behaviorCacheDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'cache'));
options.generateMissingBehaviorCache = getField( ...
    options, 'generateMissingBehaviorCache', false);
end

function arms = buildArms(names)
if ischar(names)
    names = {names};
end
arms = repmat(struct('name', '', 'mode', ''), 1, numel(names));
for armIdx = 1:numel(names)
    mode = lower(strrep(char(names{armIdx}), '_', '-'));
    fixedToken = regexp(mode, ...
        '^fixed-candidate-([0-9]+)$', 'tokens', 'once');
    if ~isempty(fixedToken)
        displayName = sprintf( ...
            'Registered fixed candidate %d', ...
            str2double(fixedToken{1}));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    switch mode
        case 'local'
            displayName = 'Local only';
        case 'robust-static'
            displayName = 'All-time geometry static';
        case 'reliability'
            displayName = 'Reliability dynamic';
        case 'discrepancy'
            displayName = 'Posterior discrepancy dynamic';
        case 'oracle-consensus'
            displayName = 'Exact one-step consensus oracle';
        case 'oracle-truth'
            displayName = 'Exact one-step truth diagnostic oracle';
        case 'teacher-current'
            displayName = 'Pure current task-risk teacher';
        case 'teacher-current-balanced'
            displayName = 'Balanced current task-risk teacher';
        case 'teacher-current-cvar'
            displayName = 'Tail-risk current task-risk teacher';
        case 'teacher-predictive'
            displayName = 'Open-loop predictive task-risk teacher';
        otherwise
            error('Unknown topology screen arm: %s', names{armIdx});
    end
    arms(armIdx) = struct('name', displayName, 'mode', mode);
end
end

function config = buildArmTriggerConfig(arm, scenarioConfig, overrides)
config = buildMixtureAwareKlaReferenceConfig(overrides);
config.dynamicTopologyEnabled = false;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
fixedToken = regexp(arm.mode, ...
    '^fixed-candidate-([0-9]+)$', 'tokens', 'once');
if ~isempty(fixedToken)
    fixedCandidateIndex = str2double(fixedToken{1});
    config.eventPolicy = 'alwaysHeavy';
    config.dynamicTopologyEnabled = true;
    config.topologyPolicyName = arm.mode;
    config.topologyPolicyFcn = ...
        @(context) selectRegisteredFixedTopology( ...
            context, fixedCandidateIndex);
    return;
end
switch arm.mode
    case 'local'
        config.eventPolicy = 'none';
    case 'robust-static'
        config.eventPolicy = 'alwaysHeavy';
    case {'reliability', 'discrepancy'}
        config.eventPolicy = 'alwaysHeavy';
        config.dynamicTopologyEnabled = true;
        config.topologyPolicyName = arm.mode;
        mode = arm.mode;
        if strcmpi(scenarioConfig.topologyFamily, 'd12-enumerated')
            config.topologyPolicyFcn = ...
                @(context) selectD12TopologyPolicy(context, mode);
        else
            config.topologyPolicyFcn = ...
                @(context) selectProjectedTopologyPolicy(context, mode);
        end
    case {'oracle-consensus', 'oracle-truth'}
        config.eventPolicy = 'alwaysHeavy';
        config.dynamicTopologyEnabled = true;
        config.topologyPolicyName = arm.mode;
        mode = arm.mode;
        config.topologyPolicyFcn = ...
            @(context) selectD12TopologyPolicy(context, mode);
    case {'teacher-current', 'teacher-current-balanced', ...
            'teacher-current-cvar', 'teacher-predictive'}
        config.eventPolicy = 'alwaysHeavy';
        config.dynamicTopologyEnabled = true;
        config.topologyPolicyName = arm.mode;
        if strcmp(arm.mode, 'teacher-predictive')
            teacherMode = 'predictive';
        else
            teacherMode = 'current';
        end
        riskOptions = getField( ...
            config, 'topologyTeacherRiskOptions', struct());
        if strcmp(arm.mode, 'teacher-current-balanced')
            riskOptions.sensorAggregationMode = 'mean-cvar';
            riskOptions.sensorCvarFraction = 0.25;
            riskOptions.sensorCvarWeight = 0.5;
        elseif strcmp(arm.mode, 'teacher-current-cvar')
            riskOptions.sensorAggregationMode = 'cvar';
            riskOptions.sensorCvarFraction = 0.25;
        end
        config.topologyTeacherRiskOptions = riskOptions;
        config.topologyPolicyFcn = ...
            @(context) selectCounterfactualTopologyTeacher( ...
                context, teacherMode);
end
end

function [startTime, localPosteriors] = loadContinuationSnapshot( ...
    options, presetName, seed, inputs)
startTime = 1;
localPosteriors = {};
if isempty(options.continuationStartTime)
    return;
end
startTime = options.continuationStartTime;
if startTime > size(inputs.measurements, 2)
    error('continuationStartTime exceeds the cropped experiment length.');
end
cacheStem = sprintf('%s_seed%d_n1_sig%d.mat', ...
    lower(strrep(char(presetName), '-', '_')), seed, startTime);
cachePath = fullfile(options.behaviorCacheDirectory, cacheStem);
if ~exist(cachePath, 'file') && options.generateMissingBehaviorCache
    teacherOptions = struct( ...
        'snapshotTimes', startTime, ...
        'teacherHorizonSteps', 0, ...
        'closedLoopHorizonSteps', 0, ...
        'scenarioOverrides', options.scenarioOverrides, ...
        'fusionOverrides', options.fusionOverrides, ...
        'behaviorCacheDirectory', options.behaviorCacheDirectory, ...
        'writeReport', false);
    runDynamicTopologyTeacherSignalScreen( ...
        presetName, seed, teacherOptions);
end
if ~exist(cachePath, 'file')
    error(['Missing continuation behavior cache: %s. Generate it ', ...
        'with runDynamicTopologyTeacherSignalScreen or enable ', ...
        'generateMissingBehaviorCache.'], cachePath);
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Continuation cache does not contain behaviorBundle.');
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.presetName, presetName) || ...
        bundle.seed ~= seed || ...
        ~any(bundle.snapshotTimes == startTime) || ...
        numel(bundle.posteriorSnapshots) < startTime || ...
        isempty(bundle.posteriorSnapshots{startTime})
    error('Continuation cache metadata or posterior snapshot mismatches.');
end
localPosteriors = bundle.posteriorSnapshots{startTime};
fprintf('  continuation cache: %s\n', cachePath);
end

function inputs = cropInputs(inputs, maxTimeSteps)
availableTime = size(inputs.measurements, 2);
if ~isfinite(maxTimeSteps) || maxTimeSteps >= availableTime
    return;
end
timeCount = max(1, round(maxTimeSteps));
inputs.measurements = inputs.measurements(:, 1:timeCount);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:timeCount);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:timeCount);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:timeCount);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:timeCount);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:timeCount);
inputs.model.simulationLength = timeCount;
end

function record = scoreRun( ...
    seed, arm, estimates, diagnostics, model, truth, ...
    scenarioConfig, elapsedSeconds, analysisStartTime)
sensorCount = numel(estimates);
timeCount = numel(truth.x);
analysisStartTime = min(max(1, round(analysisStartTime)), timeCount);
analysisTimes = analysisStartTime:timeCount;
eospa = zeros(sensorCount, timeCount);
cardinalityError = zeros(sensorCount, timeCount);
for sensorIdx = 1:sensorCount
    [sensorEospa, ~, cardinality] = ...
        computeSimulationOspa(model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa;
    cardinalityError(sensorIdx, :) = abs( ...
        cardinality - truth.cardinality);
end
[positionDisagreement, cardinalityDispersion, ospaDisagreement] = ...
    computeDistributedConsensusMetrics(estimates, model);
sensorMeanEospa = mean(eospa(:, analysisTimes), 2);
focusWindow = resolveFocusWindow( ...
    scenarioConfig, timeCount, analysisStartTime);

record = emptyRecord();
record.seed = seed;
record.armName = arm.name;
record.armMode = arm.mode;
record.analysisWindow = [analysisTimes(1), analysisTimes(end)];
record.meanEospa = meanAll(eospa(:, analysisTimes));
record.worstSensorEospa = max(sensorMeanEospa);
record.meanCardinalityError = meanAll( ...
    cardinalityError(:, analysisTimes));
record.consensusOspa = finiteMean(ospaDisagreement(analysisTimes));
record.consensusPosition = finiteMean( ...
    positionDisagreement(analysisTimes));
record.cardinalityDispersion = finiteMean( ...
    cardinalityDispersion(analysisTimes));
record.focusWindowName = scenarioConfig.focusWindowName;
record.focusWindow = [focusWindow(1), focusWindow(end)];
record.focusEospa = meanAll(eospa(:, focusWindow));
record.focusCardinalityError = meanAll( ...
    cardinalityError(:, focusWindow));
record.focusPosteriorConsensus = finiteMean( ...
    diagnostics.posteriorConsensusCombined(focusWindow));
record.focusMapSetDisagreement = finiteMean( ...
    ospaDisagreement(focusWindow));
record.posteriorConsensus = finiteMean( ...
    diagnostics.posteriorConsensusCombined(analysisTimes));
record.posteriorExistenceConsensus = finiteMean( ...
    diagnostics.posteriorConsensusExistence(analysisTimes));
record.posteriorSpatialConsensus = finiteMean( ...
    diagnostics.posteriorConsensusSpatial(analysisTimes));
record.attemptedBytes = sumAll( ...
    diagnostics.attemptedPayloadBytes(:, :, analysisTimes));
record.deliveredBytes = sumAll( ...
    diagnostics.payloadBytes(:, :, analysisTimes));
record.attemptCount = sumAll( ...
    diagnostics.attempted(:, :, analysisTimes));
record.deliveryCount = sumAll( ...
    diagnostics.delivered(:, :, analysisTimes));
record.meanEdgeCount = mean( ...
    diagnostics.topologyUndirectedEdgeCount(analysisTimes));
previousActiveEdges = [];
if diagnostics.usedInitialLocalPosterior && ...
        analysisStartTime == diagnostics.continuationStartTime
    previousActiveEdges = ...
        diagnostics.continuationPreviousDirectedEdgeMask;
end
record.topologyChurnRate = computeWindowChurnRate( ...
    diagnostics.topologyActiveEdge(:, :, analysisTimes), ...
    previousActiveEdges);
record.topologyInfeasibleRate = mean( ...
    ~diagnostics.topologyFeasible(analysisTimes));
record.topologyPolicySeconds = finiteSum( ...
    diagnostics.topologyPolicySeconds(analysisTimes));
record.meanPolicyTaskAdvantage = finiteMean( ...
    diagnostics.topologyPolicyTaskAdvantage(analysisTimes));
record.meanPolicyTaskRiskSpread = finiteMean( ...
    diagnostics.topologyPolicyTaskRiskSpread(analysisTimes));
record.meanPolicyValidCandidateCount = finiteMean( ...
    diagnostics.topologyPolicyValidCandidateCount(analysisTimes));
record.elapsedSeconds = elapsedSeconds;
candidateIndices = ...
    diagnostics.topologyPolicyCandidateIndex(analysisTimes);
candidateIndices = candidateIndices(isfinite(candidateIndices));
record.distinctCandidateCount = numel(unique(candidateIndices));
record.meanEospaByTime = mean(eospa, 1);
record.meanCardinalityErrorByTime = mean(cardinalityError, 1);
record.posteriorConsensusByTime = ...
    diagnostics.posteriorConsensusCombined;
record.mapSetDisagreementByTime = ospaDisagreement;
end

