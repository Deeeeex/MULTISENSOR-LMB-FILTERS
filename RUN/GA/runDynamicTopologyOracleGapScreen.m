function [reportPath, summary] = ...
    runDynamicTopologyOracleGapScreen(presetName, seedList, options)
% RUNDYNAMICTOPOLOGYORACLEGAPSCREEN Paired topology-only evidence gate.
%
% Example:
%   opts = struct('maxTimeSteps', 20);
%   runDynamicTopologyOracleGapScreen('d12-handover', 7, opts);
%
% The same measurements, trajectories and link uniforms are reused across
% arms. Payload compression and event triggering are disabled; only the
% selected topology changes. A cached post-update posterior can optionally
% initialize every arm at the same focus-window state.

if nargin < 1 || isempty(presetName)
    presetName = 'd12-handover';
end
if nargin < 2 || isempty(seedList)
    seedList = 1:3;
end
if nargin < 3 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
options = resolveOptions(options);
if options.includeRollingMatchedControls
    armScenarioConfig = buildDynamicTopologyScenarioConfig( ...
        presetName, options.scenarioOverrides);
    options.armNames = expandRollingSafeMatchedArmNames( ...
        options.armNames, armScenarioConfig);
end
armDefinitions = buildArms(options.armNames);

fprintf(['Dynamic topology screen: %s, %d seed(s), ', ...
    '%d arm(s), maxTimeSteps=%s, continuation=%s\n'], ...
    presetName, numel(seedList), numel(armDefinitions), ...
    numericOrAll(options.maxTimeSteps), ...
    numericOrNone(options.continuationStartTime));

records = repmat(emptyRecord(), ...
    numel(seedList), numel(armDefinitions));
validationBySeed = cell(1, numel(seedList));
scenarioConfigSnapshot = struct();
for seedIdx = 1:numel(seedList)
    seed = seedList(seedIdx);
    fprintf('Generating paired input for seed %d...\n', seed);
    inputs = generateDynamicTopologyScenarioInputs( ...
        presetName, seed, options.scenarioOverrides);
    if seedIdx == 1
        scenarioConfigSnapshot = inputs.config;
    elseif inputs.config.numberOfSensors ~= ...
            scenarioConfigSnapshot.numberOfSensors || ...
            ~isequal(inputs.config.sensorGroupIds, ...
                scenarioConfigSnapshot.sensorGroupIds)
        error('Scenario topology contract differs across paired seeds.');
    end
    inputs = cropInputs(inputs, options.maxTimeSteps);
    validationBySeed{seedIdx} = inputs.validation;
    [analysisStartTime, initialLocalPosteriors, ...
        continuationHistory] = ...
        loadContinuationSnapshot( ...
            options, presetName, seed, inputs);
    for armIdx = 1:numel(armDefinitions)
        arm = armDefinitions(armIdx);
        fprintf('  seed %d arm %s...\n', seed, arm.name);
        triggerConfig = buildArmTriggerConfig( ...
            arm, inputs.config, options.fusionOverrides, ...
            options.directedRoutingModelPath, ...
            options.residualRoutingModelPath, ...
            options.structuredTreeModelPath, ...
            options.rollingSafeRolloutModelPath, ...
            options.labelSetMessagePassingModelPath, ...
            options.rollingPayloadProjectionToleranceFraction, ...
            options.rollingSafeBackboneMode, ...
            seed, options.evidenceSplit, ...
            options.allowRejectedLearnedArtifact, ...
            options.allowUnselectedLabelSetArtifact);
        if ~isempty(initialLocalPosteriors)
            triggerConfig.filterInitialLocalPosteriorBySensor = ...
                initialLocalPosteriors;
            triggerConfig.filterInitialLocalPosteriorTime = ...
                analysisStartTime;
            if size(continuationHistory. ...
                    selectedDirectedEdgeHistory, 3) > 0
                triggerConfig.filterInitialPreviousAdjacencyHistory = ...
                    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
                        continuationHistory. ...
                            selectedDirectedEdgeHistory);
                triggerConfig.filterInitialPreviousAdjacencyTimes = ...
                    continuationHistory.times;
                triggerConfig. ...
                    filterInitialPreviousAdjacencyHistorySource = ...
                    'behavior-filter-diagnostics-cache-v2';
            end
        end
        rng(seed + options.filterSeedOffset);
        timerId = tic;
        [stateEstimates, diagnostics] = ...
            runEventTriggeredDistributedLmbFilter( ...
                inputs.model, inputs.measurements, ...
                inputs.sensorTrajectories, inputs.neighborMap, ...
                inputs.commConfig, triggerConfig);
        diagnostics.initialPreviousDeliveredEdgeHistory = ...
            continuationHistory.deliveredDirectedEdgeHistory;
        diagnostics.initialPreviousDeliveredEdgeHistoryTimes = ...
            continuationHistory.times;
        diagnostics.usedInitialPreviousDeliveredHistory = ...
            size(continuationHistory. ...
                deliveredDirectedEdgeHistory, 3) > 0;
        elapsedSeconds = toc(timerId);
        record = scoreRun( ...
            seed, arm, stateEstimates, diagnostics, ...
            inputs.model, inputs.groundTruthRfs, ...
            inputs.config, elapsedSeconds, analysisStartTime);
        records(seedIdx, armIdx) = record;
        fprintf(['    E-OSPA %.4f, worst node %.4f, ', ...
            'consensus OSPA %.4f, attempted %.0f B, %.2f s\n'], ...
            record.meanEospa, record.worstSensorEospa, ...
            record.consensusOspa, ...
            record.attemptedBytes, record.elapsedSeconds);
    end
end

summary = aggregateRecords( ...
    presetName, seedList, armDefinitions, records, ...
    validationBySeed, options, scenarioConfigSnapshot);
reportPath = '';
if options.writeReport
    outputDirectory = options.outputDirectory;
    if ~exist(outputDirectory, 'dir')
        mkdir(outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    if isempty(options.continuationStartTime)
        stem = sprintf('DYNAMIC_TOPOLOGY_ORACLE_GAP_%s_N%d_%s', ...
            upper(strrep(char(presetName), '-', '_')), ...
            numel(seedList), timestamp);
    else
        stem = sprintf( ...
            'DYNAMIC_TOPOLOGY_CONTINUATION_%s_T%d_N%d_%s', ...
            upper(strrep(char(presetName), '-', '_')), ...
            options.continuationStartTime, ...
            numel(seedList), timestamp);
    end
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    writeReport(reportPath, summary);
    save(matPath, 'summary');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    fprintf('Report: %s\n', reportPath);
end
end

function options = resolveOptions(options)
options.armNames = getField(options, 'armNames', { ...
    'local', 'robust-static', 'reliability', 'discrepancy', ...
    'oracle-consensus', 'oracle-truth'});
options.maxTimeSteps = getField(options, 'maxTimeSteps', inf);
options.writeReport = getField(options, 'writeReport', true);
options.scenarioOverrides = getField( ...
    options, 'scenarioOverrides', struct());
options.fusionOverrides = getField( ...
    options, 'fusionOverrides', struct());
options.outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
options.filterSeedOffset = getField(options, 'filterSeedOffset', 100000);
options.directedRoutingModelPath = getField( ...
    options, 'directedRoutingModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'directed_routing_knn_m24_t75.mat'));
options.residualRoutingModelPath = getField( ...
    options, 'residualRoutingModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'confidence_gated_residual_m24_t75.mat'));
options.structuredTreeModelPath = getField( ...
    options, 'structuredTreeModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'structured_formation_tree_m24_proxy_candidate.mat'));
options.rollingSafeRolloutModelPath = getField( ...
    options, 'rollingSafeRolloutModelPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'models', ...
        'rolling_safe_rollout_edge_mlp_m24_t75.mat'));
labelSetProtocol = getLabelSetSimulatorPolicyProtocol();
options.labelSetMessagePassingModelPath = getField( ...
    options, 'labelSetMessagePassingModelPath', ...
    labelSetProtocol.messagePassingInitializationPath);
options.evidenceSplit = lower(strrep(char(getField( ...
    options, 'evidenceSplit', 'development')), '_', '-'));
if ~ismember(options.evidenceSplit, ...
        {'training', 'development', 'heldout-validation'})
    error(['evidenceSplit must be training, development or ', ...
        'heldout-validation.']);
end
options.allowRejectedLearnedArtifact = logical(getField( ...
    options, 'allowRejectedLearnedArtifact', false));
options.allowUnselectedLabelSetArtifact = logical(getField( ...
    options, 'allowUnselectedLabelSetArtifact', false));
if strcmp(options.evidenceSplit, 'heldout-validation')
    protocol = getRollingSafeRolloutProtocol();
    if options.filterSeedOffset ~= protocol.filterSeedOffset
        error(['Held-out validation filter RNG offset differs from ', ...
            'the frozen protocol.']);
    end
end
if options.allowRejectedLearnedArtifact && ...
        strcmp(options.evidenceSplit, 'heldout-validation')
    error(['Rejected learned artifacts cannot be enabled in ', ...
        'heldout-validation mode.']);
end
if options.allowUnselectedLabelSetArtifact && ...
        ~strcmp(options.evidenceSplit, 'training')
    error(['Unselected label-set artifacts cannot be enabled in ', ...
        'development or heldout-validation mode.']);
end
continuationStart = getField(options, 'continuationStartTime', []);
if isempty(continuationStart)
    options.continuationStartTime = [];
else
    options.continuationStartTime = max(1, round(continuationStart));
end
options.behaviorCacheDirectory = getField( ...
    options, 'behaviorCacheDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'cache'));
options.generateMissingBehaviorCache = getField( ...
    options, 'generateMissingBehaviorCache', false);
options.rollingSafeBackboneMode = lower(strrep(char(getField( ...
    options, 'rollingSafeBackboneMode', ...
    'fixed-balanced-cycle')), '_', '-'));
if ~ismember(options.rollingSafeBackboneMode, { ...
        'fixed-balanced-cycle', 'fixed-index-star'})
    error(['rollingSafeBackboneMode must be fixed-balanced-cycle ', ...
        'or fixed-index-star.']);
end
options.minimumPracticalTrackingGainPercent = max(0, getField( ...
    options, 'minimumPracticalTrackingGainPercent', 5));
options.minimumDynamicRouteDifferenceFraction = min(max(getField( ...
    options, 'minimumDynamicRouteDifferenceFraction', 0.10), 0), 1);
options.minimumGatewayControlPhaseCount = max(1, round(getField( ...
    options, 'minimumGatewayControlPhaseCount', 6)));
options.includeRollingMatchedControls = logical(getField( ...
    options, 'includeRollingMatchedControls', false));
options.primaryAttributionFamily = lower(strrep(char(getField( ...
    options, 'primaryAttributionFamily', 'auto')), '_', '-'));
if options.includeRollingMatchedControls && ...
        strcmp(options.primaryAttributionFamily, 'auto')
    options.primaryAttributionFamily = 'rolling-safe';
end
validPrimaryFamilies = { ...
    'auto', 'rolling-safe', 'structured-tree', ...
    'dynamic', 'residual-routing', 'directed-routing'};
if ~any(strcmp(options.primaryAttributionFamily, validPrimaryFamilies))
    error('Unknown primaryAttributionFamily: %s', ...
        options.primaryAttributionFamily);
end
options.rollingPayloadProjectionToleranceFraction = getField( ...
    options, 'rollingPayloadProjectionToleranceFraction', inf);
if ~isscalar(options.rollingPayloadProjectionToleranceFraction) || ...
        isnan(options.rollingPayloadProjectionToleranceFraction) || ...
        options.rollingPayloadProjectionToleranceFraction < 0
    error([ ...
        'rollingPayloadProjectionToleranceFraction must be a ', ...
        'nonnegative scalar or inf.']);
end
end

function arms = buildArms(names)
if ischar(names)
    names = {names};
end
arms = repmat(struct('name', '', 'mode', ''), 1, numel(names));
for armIdx = 1:numel(names)
    mode = lower(strrep(char(names{armIdx}), '_', '-'));
    if strcmp(mode, ...
            'label-set-message-passing-safe-a70')
        protocol = getLabelSetSimulatorPolicyProtocol();
        displayName = sprintf([ ...
            'Label-set two-round message-passing safe residual ', ...
            'cycle (alpha=%.2f, weights=%s)'], ...
            protocol.dominantWeight, ...
            mat2str(protocol.residualWeightGrid));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    if strcmp(mode, ...
            'label-set-message-passing-safe-fixed-e05-a70')
        protocol = getLabelSetSimulatorPolicyProtocol();
        displayName = sprintf([ ...
            'Label-set two-round message-passing safe residual ', ...
            'cycle (alpha=%.2f, fixed epsilon=%.2f)'], ...
            protocol.dominantWeight, ...
            protocol.localResidualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    certifiedOverlapToken = regexp(mode, ...
        ['^adaptive-dominant-composite-balanced-', ...
         'certified-overlap-payload-margin([0-9]{3})-', ...
         'e([0-9]+)-a([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(certifiedOverlapToken)
        payloadMarginFraction = ...
            str2double(certifiedOverlapToken{1}) / 1000;
        residualWeight = ...
            str2double(certifiedOverlapToken{2}) / 100;
        dominantWeight = ...
            str2double(certifiedOverlapToken{3}) / 100;
        displayName = sprintf([ ...
            'Adaptive dominant certified-overlap payload-budget ', ...
            'routing (margin=%.1f%%, alpha=%.2f, epsilon=%.2f)'], ...
            100 * payloadMarginFraction, ...
            dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    payloadAwareDominantToken = regexp(mode, ...
        ['^adaptive-dominant-composite-balanced-', ...
         'payload-margin([0-9]{3})-', ...
         'e([0-9]+)-a([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(payloadAwareDominantToken)
        payloadMarginFraction = ...
            str2double(payloadAwareDominantToken{1}) / 1000;
        residualWeight = ...
            str2double(payloadAwareDominantToken{2}) / 100;
        dominantWeight = ...
            str2double(payloadAwareDominantToken{3}) / 100;
        displayName = sprintf([ ...
            'Adaptive dominant composite balanced payload-budget ', ...
            'routing (margin=%.1f%%, alpha=%.2f, epsilon=%.2f)'], ...
            100 * payloadMarginFraction, ...
            dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    adaptiveDominantToken = regexp(mode, ...
        ['^adaptive-dominant-(source-quality|transfer|', ...
         'compatibility|composite-balanced|', ...
         'composite-concentrated)-e([0-9]+)-a([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(adaptiveDominantToken)
        policyMode = adaptiveDominantToken{1};
        residualWeight = ...
            str2double(adaptiveDominantToken{2}) / 100;
        dominantWeight = ...
            str2double(adaptiveDominantToken{3}) / 100;
        displayName = sprintf([ ...
            'Adaptive dominant %s routing ', ...
            '(alpha=%.2f, epsilon=%.2f)'], ...
            strrep(policyMode, '-', ' '), ...
            dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    if strcmp(mode, [ ...
            'oracle-backbone-residual-spliced-cycle-', ...
            'cvar-tail-guard-adaptive-current-a70'])
        protocol = ...
            getBackboneResidualCvarTailGuardAdaptiveTrustProtocol();
        displayName = sprintf([ ...
            'Privileged CVaR-tail-guarded adaptive-trust ', ...
            'spliced residual cycle ', ...
            '(alpha=%.2f, weights=%s, tail=%.0f%%)'], ...
            protocol.dominantWeight, ...
            mat2str(protocol.crossResidualWeightGrid), ...
            100 * protocol.protectedReceiverFraction);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    if strcmp(mode, [ ...
            'oracle-backbone-residual-spliced-cycle-', ...
            'eospa-tail-guard-adaptive-current-a70'])
        protocol = ...
            getBackboneResidualEospaTailGuardAdaptiveTrustProtocol();
        displayName = sprintf([ ...
            'Privileged E-OSPA-tail-guarded adaptive-trust ', ...
            'spliced residual cycle ', ...
            '(alpha=%.2f, weights=%s)'], ...
            protocol.dominantWeight, ...
            mat2str(protocol.crossResidualWeightGrid));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    if strcmp(mode, [ ...
            'oracle-backbone-residual-spliced-cycle-', ...
            'tail-guard-adaptive-current-a70'])
        protocol = ...
            getBackboneResidualTailGuardAdaptiveTrustProtocol();
        displayName = sprintf([ ...
            'Privileged max-risk-guarded adaptive-trust ', ...
            'spliced residual cycle ', ...
            '(alpha=%.2f, weights=%s)'], ...
            protocol.dominantWeight, ...
            mat2str(protocol.crossResidualWeightGrid));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    if strcmp(mode, [ ...
            'oracle-backbone-residual-spliced-cycle-', ...
            'tail-safe-adaptive-current-a70'])
        protocol = ...
            getBackboneResidualTailSafeAdaptiveTrustProtocol();
        displayName = sprintf([ ...
            'Privileged tail-safe adaptive-trust spliced ', ...
            'residual cycle (alpha=%.2f, weights=%s)'], ...
            protocol.dominantWeight, ...
            mat2str(protocol.crossResidualWeightGrid));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    if strcmp(mode, [ ...
            'oracle-backbone-residual-spliced-cycle-', ...
            'adaptive-current-a70'])
        protocol = ...
            getBackboneResidualAdaptiveTrustProtocol();
        displayName = sprintf([ ...
            'Privileged adaptive-trust spliced residual cycle ', ...
            '(alpha=%.2f, weights=%s)'], ...
            protocol.dominantWeight, ...
            mat2str(protocol.crossResidualWeightGrid));
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    splicedStaticToken = regexp(mode, ...
        ['^backbone-residual-spliced-cycle-', ...
         '(cw|ccw)-a([0-9]+)-e([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(splicedStaticToken)
        direction = splicedStaticToken{1};
        dominantWeight = ...
            str2double(splicedStaticToken{2}) / 100;
        residualWeight = ...
            str2double(splicedStaticToken{3}) / 100;
        displayName = sprintf([ ...
            'Backbone residual fixed spliced cycle ', ...
            '(%s, alpha=%.2f, epsilon=%.2f)'], ...
            direction, dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    splicedCurrentToken = regexp(mode, ...
        ['^oracle-backbone-residual-spliced-cycle-current-', ...
         'a([0-9]+)-e([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(splicedCurrentToken)
        dominantWeight = ...
            str2double(splicedCurrentToken{1}) / 100;
        residualWeight = ...
            str2double(splicedCurrentToken{2}) / 100;
        displayName = sprintf([ ...
            'Privileged current-risk spliced residual cycle ', ...
            '(alpha=%.2f, epsilon=%.2f)'], ...
            dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    residualSequenceToken = regexp(mode, ...
        ['^oracle-backbone-residual-sequence-', ...
         't([0-9]+)-m([01]+)-a([0-9]+)-e([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(residualSequenceToken)
        anchorTime = str2double(residualSequenceToken{1});
        activationToken = residualSequenceToken{2};
        dominantWeight = ...
            str2double(residualSequenceToken{3}) / 100;
        residualWeight = ...
            str2double(residualSequenceToken{4}) / 100;
        displayName = sprintf([ ...
            'Backbone residual static/current sequence ', ...
            '(t=%d, mask=%s, alpha=%.2f, epsilon=%.2f)'], ...
            anchorTime, activationToken, ...
            dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    residualToken = regexp(mode, ...
        ['^(backbone-residual-static|', ...
         'backbone-residual-analytic|', ...
         'oracle-backbone-residual-current|', ...
         'oracle-backbone-residual-minimax)-', ...
         'a([0-9]+)-e([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(residualToken)
        policyMode = residualToken{1};
        dominantWeight = str2double(residualToken{2}) / 100;
        residualWeight = str2double(residualToken{3}) / 100;
        switch policyMode
            case 'backbone-residual-static'
                policyLabel = 'static matched control';
            case 'backbone-residual-analytic'
                policyLabel = 'posterior-analytic routing';
            case 'oracle-backbone-residual-current'
                policyLabel = 'privileged current-risk routing';
            case 'oracle-backbone-residual-minimax'
                policyLabel = 'privileged minimax routing';
        end
        displayName = sprintf([ ...
            'Backbone-preserving residual %s ', ...
            '(alpha=%.2f, epsilon=%.2f)'], ...
            policyLabel, dominantWeight, residualWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    rollingChunkToken = regexp(mode, ...
        ['^directed-rolling-chunk-q([0-9]+)-', ...
         'd(cw|ccw)-c([0-9]+)-w([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(rollingChunkToken)
        quota = str2double(rollingChunkToken{1});
        direction = rollingChunkToken{2};
        formationPhase = str2double(rollingChunkToken{3});
        sourceWeight = str2double(rollingChunkToken{4}) / 100;
        displayName = sprintf([ ...
            'Directed rolling-B3 cyclic chunk ', ...
            '(q=%d, %s, phase=%d, w=%.2f)'], ...
            quota, direction, formationPhase, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    rollingBurstToken = regexp(mode, ...
        ['^directed-rolling-burst-r([0-9]+)-', ...
         'd(cw|ccw)-p([0-2])-w([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(rollingBurstToken)
        rootFormation = str2double(rollingBurstToken{1});
        direction = rollingBurstToken{2};
        temporalPhase = str2double(rollingBurstToken{3});
        sourceWeight = str2double(rollingBurstToken{4}) / 100;
        displayName = sprintf([ ...
            'Directed rolling-B3 burst control ', ...
            '(root=%d, %s, phase=%d, w=%.2f)'], ...
            rootFormation, direction, temporalPhase, sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    rollingLinkToken = regexp(mode, ...
        '^directed-link-aware-rolling-b3-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(rollingLinkToken)
        sourceWeight = str2double(rollingLinkToken{1}) / 100;
        displayName = sprintf([ ...
            'Directed link-aware rolling-B3 control ', ...
            '(w=%.2f)'], sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    rollingAnalyticToken = regexp(mode, ...
        '^rolling-safe-analytic-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(rollingAnalyticToken)
        sourceWeight = ...
            str2double(rollingAnalyticToken{1}) / 100;
        displayName = sprintf([ ...
            'Rolling-safe posterior-analytic routing ', ...
            '(w=%.2f)'], sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    rollingLearnedToken = regexp(mode, ...
        '^learned-rolling-safe-rollout-w([0-9]+)$', ...
        'tokens', 'once');
    if ~isempty(rollingLearnedToken)
        sourceWeight = ...
            str2double(rollingLearnedToken{1}) / 100;
        displayName = sprintf([ ...
            'Learned rolling-safe rollout edge routing ', ...
            '(w=%.2f)'], sourceWeight);
        arms(armIdx) = struct( ...
            'name', displayName, 'mode', mode);
        continue;
    end
    rollingSequenceToken = regexp(mode, ...
        ['^rolling-safe-sequence-t([0-9]+)-', ...
         's([0-9]+)-w([0-9]+)$'], ...
        'tokens', 'once');
    if ~isempty(rollingSequenceToken)
        anchorTime = str2double(rollingSequenceToken{1});
        actionToken = rollingSequenceToken{2};
        if mod(numel(actionToken), 2) ~= 0
            error(['Rolling-safe action sequence must use two digits ', ...
                'per action code: %s'], actionToken);
        end
        actionCodes = sscanf(actionToken, '%2d')';
        if any(actionCodes == 0 | actionCodes >= 90)
            error(['Truth-free rolling-safe sequences cannot contain ', ...
                'privileged action codes 00 or 90:99.']);
        end
        sourceWeight = ...
            str2double(rollingSequenceToken{3}) / 100;
        if any(actionCodes >= 40 & actionCodes <= 45)
            displayName = sprintf([ ...
                'Offline centralized counterfactual-teacher ', ...
                'sequence (t=%d, codes=%s, w=%.2f)'], ...
                anchorTime, formatActionCodes(actionCodes), ...
                sourceWeight);
        else
            displayName = sprintf([ ...
                'Truth-free rolling-safe action sequence ', ...
                '(t=%d, codes=%s, w=%.2f)'], ...
