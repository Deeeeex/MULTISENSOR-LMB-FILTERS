function [startTime, localPosteriors, history] = ...
    loadContinuationSnapshot(options, presetName, seed, inputs)
startTime = 1;
localPosteriors = {};
sensorCount = inputs.config.numberOfSensors;
history = emptyContinuationHistory(sensorCount);
if isempty(options.continuationStartTime)
    return;
end
startTime = options.continuationStartTime;
if startTime > size(inputs.measurements, 2)
    error('continuationStartTime exceeds the cropped experiment length.');
end
cacheStem = sprintf('%s_seed%d_n1_sig%d.mat', ...
    lower(strrep(char(presetName), '-', '_')), seed, startTime);
cachePath = fullfile(options.behaviorCacheDirectory, cacheStem);
[valid, localPosteriors, history, failureReason] = ...
    tryLoadContinuationCache( ...
        cachePath, presetName, seed, startTime, inputs, options);
if ~valid && options.generateMissingBehaviorCache
    teacherOptions = struct( ...
        'snapshotTimes', startTime, ...
        'teacherHorizonSteps', 0, ...
        'closedLoopHorizonSteps', 0, ...
        'scenarioOverrides', options.scenarioOverrides, ...
        'fusionOverrides', options.fusionOverrides, ...
        'behaviorCacheDirectory', options.behaviorCacheDirectory, ...
        'writeReport', false);
    runDynamicTopologyTeacherSignalScreen( ...
        presetName, seed, teacherOptions);
    [valid, localPosteriors, history, failureReason] = ...
        tryLoadContinuationCache( ...
            cachePath, presetName, seed, startTime, inputs, options);
end
if ~valid
    if ~exist(cachePath, 'file')
        error(['Missing continuation behavior cache: %s. Generate it ', ...
            'with runDynamicTopologyTeacherSignalScreen or enable ', ...
            'generateMissingBehaviorCache.'], cachePath);
    end
    error(['Continuation cache metadata or posterior snapshot ', ...
        'mismatches: %s'], failureReason);
end
fprintf('  continuation cache: %s\n', cachePath);
end

function [valid, localPosteriors, history, failureReason] = ...
    tryLoadContinuationCache( ...
        cachePath, presetName, seed, startTime, inputs, options)
valid = false;
localPosteriors = {};
history = emptyContinuationHistory(inputs.config.numberOfSensors);
failureReason = 'cache file is missing';
if ~exist(cachePath, 'file')
    return;
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    failureReason = 'behaviorBundle is missing';
    return;
end
bundle = loaded.behaviorBundle;
expectedBehaviorConfig = buildMixtureAwareKlaReferenceConfig( ...
    options.fusionOverrides);
expectedBehaviorConfig.dynamicTopologyEnabled = false;
expectedBehaviorConfig.topologyPosteriorCaptureTimes = startTime;
requiredMetadata = { ...
    'presetName', 'seed', 'configSnapshot', ...
    'behaviorConfigSnapshot', 'snapshotTimes'};
if ~all(isfield(bundle, requiredMetadata)) || ...
        ~strcmp(bundle.presetName, presetName) || ...
        bundle.seed ~= seed || ...
        ~isequaln(bundle.configSnapshot, inputs.config) || ...
        ~isequaln( ...
            bundle.behaviorConfigSnapshot, expectedBehaviorConfig) || ...
        ~isequal(bundle.snapshotTimes, startTime)
    failureReason = 'scenario, seed, fusion, or snapshot metadata differs';
    return;
end
try
    [localPosteriors, history] = ...
        extractBehaviorContinuationSnapshot( ...
            bundle, startTime, inputs.config.numberOfSensors);
catch errorInfo
    failureReason = sprintf('%s: %s', ...
        errorInfo.identifier, errorInfo.message);
    return;
end
valid = true;
failureReason = '';
end

