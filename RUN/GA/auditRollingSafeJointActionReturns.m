function value = safeRelativeReduction(reference, candidate)
if reference <= 0
    value = 0;
else
    value = (reference - candidate) / reference;
end
end

function value = safeRelativeDeviation(reference, candidate)
if reference <= 0
    value = double(candidate ~= reference) * inf;
else
    value = abs(candidate - reference) / reference;
end
end

function lines = splitLines(value)
value = strtrim(value);
if isempty(value)
    lines = {};
else
    lines = regexp(value, '\r?\n', 'split');
    lines = reshape(lines, 1, []);
end
end

