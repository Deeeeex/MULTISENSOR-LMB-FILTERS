function [reportPath, audit] = ...
    auditRollingSafeJointActionReturns(options)
% AUDITROLLINGSAFEJOINTACTIONRETURNS Stitch and gate paired M24 H=3 shards.
%
% The candidate oracle may select any frozen truth-free proposal, or any
% frozen offline privileged target when proposalRole='privileged', that
% satisfies the state-matched tail, byte, repair, emergency,
% infeasibility, and rolling-B3 gates. The action-24 reference is always
% available as a virtual no-change action. This audit never trains a
% deployable proposal model or critic.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
proposalRole = char(getField( ...
    options, 'proposalRole', 'truth-free'));
role = resolveReturnAuditRole(proposalRole, protocol);
seedList = round(reshape(getField( ...
    options, 'seeds', protocol.datasetSeeds), 1, []));
timeList = round(reshape(getField( ...
    options, 'times', protocol.snapshotTimes), 1, []));
batchCount = validateInteger(getField( ...
    options, 'batchCount', 4), 'batchCount', 1);
requireOfficialGrid = logical(getField( ...
    options, 'requireCompleteOfficialGrid', true));
if isempty(seedList) || isempty(timeList) || ...
        any(~ismember(seedList, protocol.datasetSeeds)) || ...
        any(~ismember(timeList, protocol.snapshotTimes)) || ...
        numel(unique(seedList)) ~= numel(seedList) || ...
        numel(unique(timeList)) ~= numel(timeList)
    error('Audit seeds/times must be unique subsets of the frozen grid.');
end
if requireOfficialGrid && ...
        (~isequal(seedList, protocol.datasetSeeds) || ...
         ~isequal(timeList, protocol.snapshotTimes))
    error('The official audit requires the complete frozen M24 grid.');
end

inputDirectory = getField(options, 'inputDirectory', ...
    role.inputDirectory);
proposalPath = getField(options, 'proposalDatasetPath', ...
    role.proposalDatasetPath);
if exist(proposalPath, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(proposalPath), ...
            role.proposalDatasetSha256)
    error('Frozen proposal dataset is missing or has the wrong SHA-256.');
end
loadedProposal = load(proposalPath, 'dataset');
proposalDataset = loadedProposal.dataset;
if ~strcmp(proposalDataset.contractVersion, ...
        role.proposalDatasetContractVersion)
    error('Frozen proposal dataset contract mismatch.');
end

stateCount = numel(seedList) * numel(timeList);
stateRows = repmat(emptyStateRow(), 1, stateCount);
candidateRows = repmat(emptyCandidateRow(), 1, 0);
sourceFiles = cell(1, stateCount * batchCount);
sourceFileSha256 = cell(1, stateCount * batchCount);
sourceFileCursor = 0;
generationCommits = cell(1, 0);
stateCursor = 0;
for seed = seedList
    for currentTime = timeList
        stateCursor = stateCursor + 1;
        proposalBlockIndex = find( ...
            [proposalDataset.blocks.seed] == seed & ...
            [proposalDataset.blocks.currentTime] == currentTime);
        if numel(proposalBlockIndex) ~= 1
            error('Proposal dataset lacks a unique state block.');
        end
        proposalBlock = ...
            proposalDataset.blocks(proposalBlockIndex);
        referenceOutcomes = repmat(emptyOutcome(), 1, 0);
        stateCandidateResults = repmat( ...
            emptyCandidateResult(), 1, 0);
        for batchIndex = 1:batchCount
            shardPath = fullfile(inputDirectory, sprintf( ...
                role.shardFileFormat, ...
                seed, currentTime, batchIndex, batchCount));
            if exist(shardPath, 'file') ~= 2
                error('Missing paired return shard: %s', shardPath);
            end
            shardLoaded = load(shardPath, 'shard');
            if ~isfield(shardLoaded, 'shard')
                error('Return shard lacks the expected variable.');
            end
            shard = shardLoaded.shard;
            validateShard(shard, seed, currentTime, ...
                batchIndex, batchCount, role, protocol);
            sourceFileCursor = sourceFileCursor + 1;
            sourceFiles{sourceFileCursor} = shardPath;
            sourceFileSha256{sourceFileCursor} = ...
                computeFileSha256(shardPath);
            generationCommits{end + 1} = ...
                shard.generationGitCommit; %#ok<AGROW>
            if shard.referenceIncluded
                referenceOutcomes(end + 1) = ...
                    shard.referenceOutcome; %#ok<AGROW>
            end
            stateCandidateResults = [ ...
                stateCandidateResults, ...
                shard.candidateResults]; %#ok<AGROW>
        end
        if numel(referenceOutcomes) ~= 1
            error('Each state must contain exactly one paired reference.');
        end
        reference = referenceOutcomes(1);
        selectableIndices = ...
            findCandidateIndices(proposalBlock, role);
        returnedIndices = ...
            [stateCandidateResults.candidateIndex];
        if numel(returnedIndices) ~= numel(selectableIndices) || ...
                ~isequal(sort(returnedIndices), ...
                    sort(selectableIndices)) || ...
                numel(unique(returnedIndices)) ~= ...
                    numel(returnedIndices)
            error('Return shards do not partition the selectable bank.');
        end
        validateReference(reference, protocol);

        rows = repmat(emptyCandidateRow(), ...
            1, numel(stateCandidateResults));
        for resultIdx = 1:numel(stateCandidateResults)
            result = stateCandidateResults(resultIdx);
            candidateIdx = result.candidateIndex;
            proposalRecord = ...
                proposalBlock.candidateRecords(candidateIdx);
            if ~strcmp(result.graphSha256, ...
                    proposalRecord.graphSha256) || ...
                    result.actionCode ~= ...
                        proposalRecord.actionCode || ...
                    ~isequal(result.jointFeatures, ...
                        proposalBlock.jointFeatures( ...
                            candidateIdx, :))
                error('Return candidate identity/features drifted.');
            end
            rows(resultIdx) = scoreCandidate( ...
                seed, currentTime, result, reference, protocol);
        end
        candidateRows = [candidateRows, rows]; %#ok<AGROW>
        stateRows(stateCursor) = scoreState( ...
            seed, currentTime, rows, reference);
    end
end

generationCommits = unique(generationCommits);
for commitIdx = 1:numel(generationCommits)
    validateGenerationCommit(generationCommits{commitIdx});
end

referenceMean = mean([stateRows.referenceMeanEospa]);
oracleMean = mean([stateRows.oracleMeanEospa]);
referenceAttemptedBytes = sum( ...
    [stateRows.referenceAttemptedBytes]);
oracleAttemptedBytes = sum( ...
    [stateRows.oracleAttemptedBytes]);
aggregateGainFraction = ...
    safeRelativeReduction(referenceMean, oracleMean);
aggregateAttemptedByteDeviationFraction = ...
    safeRelativeDeviation( ...
        referenceAttemptedBytes, oracleAttemptedBytes);
allOracleTailNondegrading = all( ...
    [stateRows.oracleTailNondegrading]);
allOracleSafetyPassed = all( ...
    [stateRows.oracleHardFeasible]);
candidateOracleReturnGatePassed = ...
    aggregateGainFraction >= ...
        protocol.minimumCandidateOracleAggregateGain && ...
    aggregateAttemptedByteDeviationFraction <= ...
        protocol.maximumAttemptedByteDeviationFraction && ...
    allOracleTailNondegrading && allOracleSafetyPassed;
repairMonitoredOracleMean = mean( ...
    [stateRows.repairMonitoredOracleMeanEospa]);
repairMonitoredOracleAttemptedBytes = sum( ...
    [stateRows.repairMonitoredOracleAttemptedBytes]);
repairMonitoredAggregateGainFraction = ...
    safeRelativeReduction( ...
        referenceMean, repairMonitoredOracleMean);
repairMonitoredAttemptedByteDeviationFraction = ...
    safeRelativeDeviation( ...
        referenceAttemptedBytes, ...
        repairMonitoredOracleAttemptedBytes);

audit = struct();
audit.protocolId = protocol.id;
audit.contractVersion = role.auditContractVersion;
audit.proposalRole = role.id;
audit.generatedAt = datestr(now, 31);
audit.seeds = seedList;
audit.times = timeList;
audit.batchCount = batchCount;
audit.completeOfficialGrid = ...
    isequal(seedList, protocol.datasetSeeds) && ...
    isequal(timeList, protocol.snapshotTimes);
audit.sourceFiles = sourceFiles;
audit.sourceFileSha256 = sourceFileSha256;
shardManifestLines = cell(1, numel(sourceFiles));
for sourceIdx = 1:numel(sourceFiles)
    shardManifestLines{sourceIdx} = sprintf( ...
        '%s=%s', sourceFiles{sourceIdx}, ...
        sourceFileSha256{sourceIdx});
end
audit.sourceShardSetSha256 = computeTextSha256( ...
    sprintf('%s\n', shardManifestLines{:}));
audit.sourceGenerationCommits = generationCommits;
audit.proposalDatasetSha256 = ...
    role.proposalDatasetSha256;
audit.stateRows = stateRows;
audit.candidateRows = candidateRows;
audit.referenceMeanEospa = referenceMean;
audit.candidateOracleMeanEospa = oracleMean;
audit.candidateOracleAggregateGainFraction = ...
    aggregateGainFraction;
audit.referenceAttemptedBytes = ...
    referenceAttemptedBytes;
audit.candidateOracleAttemptedBytes = ...
    oracleAttemptedBytes;
audit.candidateOracleAttemptedByteDeviationFraction = ...
    aggregateAttemptedByteDeviationFraction;
audit.allOracleTailNondegrading = ...
    allOracleTailNondegrading;
audit.allOracleSafetyPassed = ...
    allOracleSafetyPassed;
audit.statesWithAdmissibleFivePercentAction = nnz( ...
    [stateRows.hasAdmissibleFivePercentAction]);
audit.candidateOracleReturnGatePassed = ...
    candidateOracleReturnGatePassed;
audit.repairMonitoredSensitivityEvaluated = true;
audit.repairMonitoredCandidateOracleMeanEospa = ...
    repairMonitoredOracleMean;
audit.repairMonitoredCandidateOracleAggregateGainFraction = ...
    repairMonitoredAggregateGainFraction;
audit.repairMonitoredCandidateOracleAttemptedBytes = ...
    repairMonitoredOracleAttemptedBytes;
audit. ...
    repairMonitoredCandidateOracleAttemptedByteDeviationFraction = ...
        repairMonitoredAttemptedByteDeviationFraction;
audit.repairMonitoredStatesWithAdmissibleFivePercentAction = ...
    nnz([stateRows.repairMonitoredHasAdmissibleFivePercentAction]);
audit.repairMonitoredCandidateOracleReturnGatePassed = ...
    repairMonitoredAggregateGainFraction >= ...
        protocol.minimumCandidateOracleAggregateGain && ...
    repairMonitoredAttemptedByteDeviationFraction <= ...
        protocol.maximumAttemptedByteDeviationFraction;
audit.topKPrivilegedCaptureEvaluated = false;
audit.topKPrivilegedCapturePassed = false;
audit.candidateProposalGatePassed = false;
audit.privilegedTargetReturnGatePassed = ...
    strcmp(role.id, 'privileged') && ...
    audit.completeOfficialGrid && ...
    candidateOracleReturnGatePassed;
audit.valueFilteredProposalDistillationAuthorized = ...
    audit.privilegedTargetReturnGatePassed;
audit.candidateReturnSupportsCriticTraining = ...
    strcmp(role.id, 'truth-free') && ...
    audit.completeOfficialGrid && ...
    candidateOracleReturnGatePassed;
audit.criticTrainingAuthorized = ...
    audit.candidateReturnSupportsCriticTraining && ...
    audit.candidateProposalGatePassed;
audit.evidenceBoundary = role.evidenceBoundary;

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
if audit.completeOfficialGrid
    stem = role.officialAuditStem;
else
    stem = sprintf(role.partialAuditStemFormat, stateCount);
end
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [stem, '.md']));
auditPath = getField(options, 'auditPath', ...
    fullfile(outputDirectory, [lower(stem), '.mat']));
audit.reportPath = reportPath;
audit.auditPath = auditPath;
save('-mat7-binary', auditPath, 'audit');
writeAuditReport(reportPath, audit, protocol);
fprintf(['Paired return audit: gain %.3f%%, byte deviation %.3f%%, ', ...
    'states >=5%% %d/%d, return gate=%d\n'], ...
    100 * aggregateGainFraction, ...
    100 * aggregateAttemptedByteDeviationFraction, ...
    audit.statesWithAdmissibleFivePercentAction, ...
    stateCount, candidateOracleReturnGatePassed);
fprintf('Report: %s\nAudit: %s\n', reportPath, auditPath);
end

function row = scoreCandidate( ...
        seed, currentTime, result, reference, protocol)
outcome = result.outcome;
validateOutcome(outcome, protocol);
gainFraction = safeRelativeReduction( ...
    reference.meanEospa, outcome.meanEospa);
attemptedByteDeviationFraction = ...
    safeRelativeDeviation( ...
        reference.attemptedBytes, ...
        outcome.attemptedBytes);
tailNondegrading = ...
    outcome.worstSensorEospa <= ...
        reference.worstSensorEospa + 1e-12;
additionalRepairCount = ...
    outcome.repairCount - reference.repairCount;
hardFeasible = ...
    outcome.firstActionExact && ...
    (~protocol.requireNoCandidateInitialRepair || ...
        ~outcome.firstActionRepair) && ...
    additionalRepairCount <= ...
        protocol. ...
            maximumAdditionalRepairCountRelativeToReference && ...
    (~protocol.requireNoEmergencyFallback || ...
        outcome.payloadEmergencyCount == 0) && ...
    (~protocol.requireNoInfeasibility || ...
        outcome.infeasibleCount == 0) && ...
    (~protocol.requireRollingB3Pass || ...
        (all(outcome.selectedSensorB3Pass) && ...
         all(outcome.selectedFormationB3Pass))) && ...
    (~protocol.requireTailNondegradation || tailNondegrading) && ...
    attemptedByteDeviationFraction <= ...
        protocol.maximumAttemptedByteDeviationFraction;
row = emptyCandidateRow();
row.seed = seed;
row.currentTime = currentTime;
row.candidateIndex = result.candidateIndex;
row.actionCode = result.actionCode;
row.graphSha256 = result.graphSha256;
row.isReferenceGraph = result.isReferenceGraph;
row.meanEospa = outcome.meanEospa;
row.worstSensorEospa = outcome.worstSensorEospa;
row.attemptedBytes = outcome.attemptedBytes;
row.deliveredBytes = outcome.deliveredBytes;
row.gainFraction = gainFraction;
row.attemptedByteDeviationFraction = ...
    attemptedByteDeviationFraction;
row.tailNondegrading = tailNondegrading;
row.additionalRepairCount = additionalRepairCount;
row.firstActionRepair = outcome.firstActionRepair;
row.payloadEmergencyCount = ...
    outcome.payloadEmergencyCount;
row.infeasibleCount = outcome.infeasibleCount;
row.selectedRollingB3Passed = ...
    all(outcome.selectedSensorB3Pass) && ...
    all(outcome.selectedFormationB3Pass);
row.deliveredRollingB3Passed = ...
    all(outcome.deliveredSensorB3Pass) && ...
    all(outcome.deliveredFormationB3Pass);
row.hardFeasible = hardFeasible;
row.admissibleFivePercentGain = ...
    hardFeasible && ...
    gainFraction >= ...
        protocol.minimumPrivilegedAdmissibleGain;
row.repairMonitoredFeasible = ...
    outcome.firstActionExact && ...
    (~protocol.requireNoCandidateInitialRepair || ...
        ~outcome.firstActionRepair) && ...
    (~protocol.requireNoEmergencyFallback || ...
        outcome.payloadEmergencyCount == 0) && ...
    (~protocol.requireNoInfeasibility || ...
        outcome.infeasibleCount == 0) && ...
    (~protocol.requireRollingB3Pass || ...
        (all(outcome.selectedSensorB3Pass) && ...
         all(outcome.selectedFormationB3Pass))) && ...
    (~protocol.requireTailNondegradation || tailNondegrading) && ...
    attemptedByteDeviationFraction <= ...
        protocol.maximumAttemptedByteDeviationFraction;
row.repairMonitoredAdmissibleFivePercentGain = ...
    row.repairMonitoredFeasible && ...
    gainFraction >= ...
        protocol.minimumPrivilegedAdmissibleGain;
end

function row = scoreState( ...
        seed, currentTime, candidateRows, reference)
[oracleCandidateIndex, oracleActionCode, oracleMean, ...
    oracleWorst, oracleAttemptedBytes, oracleDeliveredBytes, ...
    oracleTailNondegrading, oracleHardFeasible] = ...
        selectStateOracle( ...
            candidateRows, reference, 'hardFeasible');
[repairMonitoredCandidateIndex, ...
    repairMonitoredActionCode, repairMonitoredMean, ...
    repairMonitoredWorst, repairMonitoredAttemptedBytes, ...
    repairMonitoredDeliveredBytes, ...
    repairMonitoredTailNondegrading, ...
    repairMonitoredFeasible] = selectStateOracle( ...
        candidateRows, reference, 'repairMonitoredFeasible');
row = emptyStateRow();
row.seed = seed;
row.currentTime = currentTime;
row.candidateCount = numel(candidateRows);
row.hardFeasibleCandidateCount = nnz( ...
    [candidateRows.hardFeasible]);
row.admissibleFivePercentCandidateCount = nnz( ...
    [candidateRows.admissibleFivePercentGain]);
row.hasAdmissibleFivePercentAction = ...
    row.admissibleFivePercentCandidateCount > 0;
row.referenceMeanEospa = reference.meanEospa;
row.referenceWorstSensorEospa = ...
    reference.worstSensorEospa;
row.referenceAttemptedBytes = ...
    reference.attemptedBytes;
row.referenceDeliveredBytes = ...
    reference.deliveredBytes;
row.referenceRepairCount = reference.repairCount;
row.oracleCandidateIndex = oracleCandidateIndex;
row.oracleActionCode = oracleActionCode;
row.oracleMeanEospa = oracleMean;
row.oracleWorstSensorEospa = oracleWorst;
row.oracleAttemptedBytes = oracleAttemptedBytes;
row.oracleDeliveredBytes = oracleDeliveredBytes;
row.oracleGainFraction = safeRelativeReduction( ...
    reference.meanEospa, oracleMean);
row.oracleAttemptedByteDeviationFraction = ...
    safeRelativeDeviation( ...
        reference.attemptedBytes, oracleAttemptedBytes);
row.oracleTailNondegrading = ...
    oracleTailNondegrading;
row.oracleHardFeasible = oracleHardFeasible;
row.repairMonitoredFeasibleCandidateCount = nnz( ...
    [candidateRows.repairMonitoredFeasible]);
row. ...
    repairMonitoredAdmissibleFivePercentCandidateCount = ...
        nnz([candidateRows.repairMonitoredAdmissibleFivePercentGain]);
row.repairMonitoredHasAdmissibleFivePercentAction = ...
    row. ...
        repairMonitoredAdmissibleFivePercentCandidateCount > 0;
row.repairMonitoredOracleCandidateIndex = ...
    repairMonitoredCandidateIndex;
row.repairMonitoredOracleActionCode = ...
    repairMonitoredActionCode;
row.repairMonitoredOracleMeanEospa = ...
    repairMonitoredMean;
row.repairMonitoredOracleWorstSensorEospa = ...
    repairMonitoredWorst;
row.repairMonitoredOracleAttemptedBytes = ...
    repairMonitoredAttemptedBytes;
row.repairMonitoredOracleDeliveredBytes = ...
    repairMonitoredDeliveredBytes;
row.repairMonitoredOracleGainFraction = ...
    safeRelativeReduction( ...
        reference.meanEospa, repairMonitoredMean);
row. ...
    repairMonitoredOracleAttemptedByteDeviationFraction = ...
        safeRelativeDeviation( ...
            reference.attemptedBytes, ...
            repairMonitoredAttemptedBytes);
row.repairMonitoredOracleTailNondegrading = ...
    repairMonitoredTailNondegrading;
row.repairMonitoredOracleFeasible = ...
    repairMonitoredFeasible;
end

function [candidateIndex, actionCode, meanEospa, ...
        worstEospa, attemptedBytes, deliveredBytes, ...
        tailNondegrading, feasible] = ...
    selectStateOracle(candidateRows, reference, feasibleField)
feasibleIndices = find([candidateRows.(feasibleField)]);
candidateIndex = 0;
actionCode = 24;
meanEospa = reference.meanEospa;
worstEospa = reference.worstSensorEospa;
attemptedBytes = reference.attemptedBytes;
deliveredBytes = reference.deliveredBytes;
tailNondegrading = true;
feasible = true;
if isempty(feasibleIndices)
    return;
end
[bestMean, relativeIdx] = min( ...
    [candidateRows(feasibleIndices).meanEospa]);
bestIdx = feasibleIndices(relativeIdx);
if bestMean >= meanEospa
    return;
end
best = candidateRows(bestIdx);
candidateIndex = best.candidateIndex;
actionCode = best.actionCode;
meanEospa = best.meanEospa;
worstEospa = best.worstSensorEospa;
attemptedBytes = best.attemptedBytes;
deliveredBytes = best.deliveredBytes;
tailNondegrading = best.tailNondegrading;
feasible = best.(feasibleField);
end

function validateShard( ...
        shard, seed, currentTime, batchIndex, batchCount, ...
        role, protocol)
shardProposalRole = char(getField( ...
    shard, 'proposalRole', 'truth-free'));
referenceProposalSha256 = char(getField( ...
    shard, 'referenceProposalDatasetSha256', ...
    protocol.proposalDatasetSha256));
firstActionReplayMode = char(getField( ...
    shard, 'firstActionReplayMode', ...
    'registered-action-recompute'));
proposalTruthUsedOffline = logical(getField( ...
    shard, 'proposalTruthUsedOffline', false));
truthUsedByPolicy = logical(getField( ...
    shard, 'truthUsedByPolicy', false));
if ~strcmp(shard.contractVersion, ...
        role.returnContractVersion) || ...
        ~strcmp(shard.protocolId, protocol.id) || ...
        ~strcmp(shardProposalRole, role.id) || ...
        shard.seed ~= seed || ...
        shard.currentTime ~= currentTime || ...
        shard.batchIndex ~= batchIndex || ...
        shard.batchCount ~= batchCount || ...
        ~shard.completeShard || ...
        ~shard.commonRandomNumbers || ...
        ~shard.candidateFirstActionOnly || ...
        shard.continuationActionCode ~= ...
            protocol.returnContinuationActionCode || ...
        ~strcmp(shard.proposalDatasetSha256, ...
            role.proposalDatasetSha256) || ...
        ~strcmp(referenceProposalSha256, ...
            protocol.proposalDatasetSha256) || ...
        ~strcmp(firstActionReplayMode, ...
            role.firstActionReplayMode) || ...
        proposalTruthUsedOffline ~= ...
            role.proposalTruthUsedOffline || ...
        truthUsedByPolicy || ...
        ~strcmp(shard.sourceStateSha256, ...
            protocol.proposalSourceStateSha256)
    error('A paired return shard violates the frozen contract.');
end
if shard.generationTrackedWorktreeDirty || ...
        ~isempty(shard.generationUntrackedSourceFiles) || ...
        shard.generationResearchWorktreeDirty
    error('A paired return shard was generated from dirty source.');
end
if batchIndex == 1 && ~shard.referenceIncluded
    error('Batch one must contain the paired reference.');
elseif batchIndex ~= 1 && shard.referenceIncluded
    error('Only batch one may contain the paired reference.');
end
end

function validateReference(reference, protocol)
validateOutcome(reference, protocol);
if ~reference.firstActionExact || ...
        reference.payloadEmergencyCount ~= 0 || ...
        reference.infeasibleCount ~= 0 || ...
        ~all(reference.selectedSensorB3Pass) || ...
        ~all(reference.selectedFormationB3Pass)
    error('The state-matched reference failed its hard safety contract.');
end
end

function validateOutcome(outcome, protocol)
if numel(outcome.actionCodes) ~= ...
        protocol.returnHorizonSteps || ...
        ~isscalar(outcome.meanEospa) || ...
        ~isfinite(outcome.meanEospa) || ...
        outcome.meanEospa < 0 || ...
        ~isscalar(outcome.worstSensorEospa) || ...
        ~isfinite(outcome.worstSensorEospa) || ...
        outcome.worstSensorEospa < 0 || ...
        ~isscalar(outcome.attemptedBytes) || ...
        ~isfinite(outcome.attemptedBytes) || ...
        outcome.attemptedBytes <= 0 || ...
        numel(outcome.repairVector) ~= ...
            protocol.returnHorizonSteps || ...
        numel(outcome.selectedSensorB3Pass) ~= ...
            protocol.returnHorizonSteps || ...
        numel(outcome.selectedFormationB3Pass) ~= ...
            protocol.returnHorizonSteps
    error('A paired return outcome is malformed.');
end
end

function validateGenerationCommit(commit)
commit = char(commit);
if isempty(regexp(commit, '^[0-9a-f]{40}$', 'once'))
    error('Return shard generation commit is invalid.');
end
[headStatus, head] = system('git rev-parse HEAD');
head = strtrim(head);
if headStatus ~= 0 || ...
        isempty(regexp(head, '^[0-9a-f]{40}$', 'once'))
    error('Could not resolve the current audit commit.');
end
[ancestorStatus, ~] = system(sprintf( ...
    'git merge-base --is-ancestor %s %s', commit, head));
if ancestorStatus ~= 0
    error('Return generation commit is not an audit ancestor.');
end
[diffStatus, changedSource] = system(sprintf( ...
    ['git diff --name-only %s..%s -- ', ...
     ''':(glob)**/*.m'''], commit, head));
if diffStatus ~= 0
    error('Could not audit post-generation source changes.');
end
changedPaths = splitLines(changedSource);
allowedPaths = { ...
    'RUN/GA/auditRollingSafeJointActionReturns.m'};
unexpected = setdiff(changedPaths, allowedPaths);
if ~isempty(unexpected)
    error(['MATLAB/Octave source other than the return audit changed ', ...
        'after shard generation: %s'], strjoin(unexpected, ', '));
end
[localStatus, localSource] = system( ...
    ['git status --porcelain --untracked-files=all -- ', ...
     ''':(glob)**/*.m''']);
if localStatus ~= 0 || ~isempty(strtrim(localSource))
    error('Return audit requires a clean local MATLAB/Octave source tree.');
end
end

function writeAuditReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open paired return audit report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 paired H=3 %s joint-action return audit\n\n', ...
    audit.proposalRole);
fprintf(fid, '- Generated: %s\n', audit.generatedAt);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Proposal role: `%s`\n', audit.proposalRole);
fprintf(fid, '- Return source commits: `%s`\n', ...
    strjoin(audit.sourceGenerationCommits, ', '));
fprintf(fid, '- Raw return shard-set SHA-256: `%s`\n', ...
    audit.sourceShardSetSha256);
fprintf(fid, '- Complete official grid: `%d`\n', ...
