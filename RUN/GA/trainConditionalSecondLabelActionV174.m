function [reportPath, modelPath, result] = ...
        trainConditionalSecondLabelActionV174(options)
% TRAINCONDITIONALSECONDLABELACTIONV174 Compact conditional safety head.

if nargin < 1 || isempty(options)
    options = struct();
end
datasetPath = getField(options, 'datasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v173', 'conditional_second_action', ...
    'CONDITIONAL_SECOND_LABEL_ACTION_DATASET_V173.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v174', 'conditional_second_action'));
if exist(datasetPath, 'file') ~= 2
    error('ConditionalSecondActionV174:MissingDataset', ...
        'Generate the V173 conditional dataset before training V174.');
end
loaded = load(datasetPath, 'dataset');
dataset = loaded.dataset;
excludedSpatialNames = { ...
    'log_mahalanobis_disagreement', ...
    'receiver_source_compatibility', ...
    'confidence_disagreement_score', ...
    'handover_rescue_score', ...
    'peer_consensus_mean', ...
    'peer_consensus_median', ...
    'peer_consensus_maximum', ...
    'peer_support_chi2_95', ...
    'peer_support_chi2_99', ...
    'spatial_credibility'};
featureNames = setdiff( ...
    dataset.featureNames, excludedSpatialNames, 'stable');
fitOptions = struct( ...
    'datasetPath', datasetPath, ...
    'outputRoot', outputRoot, ...
    'featureProfileName', ...
        'conditional-compact-packed-summary', ...
    'featureNamesToUse', {featureNames}, ...
    'rankingMode', 'safety-probability');
[modelPath, result] = ...
    trainNonlinearSafeOneHopActionClassifierV168(fitOptions);
reportPath = fullfile(outputRoot, ...
    'CONDITIONAL_SECOND_LABEL_ACTION_V174.md');
writeReport(reportPath, modelPath, result, numel(featureNames));
fprintf('V174 conditional second-action gate: %s\n', reportPath);
end

function writeReport(path, modelPath, result, featureCount)
fid = fopen(path, 'w');
if fid < 0
    error('ConditionalSecondActionV174:ReportOpenFailed', ...
        'Could not open the V174 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V174 conditional second-label safety gate\n\n');
fprintf(fid, '- Model artifact: `%s`\n', modelPath);
fprintf(fid, '- Compact conditional feature count: `%d`\n', featureCount);
fprintf(fid, '- Heldout safety / efficiency gate: `%d / %d`\n\n', ...
    result.heldoutSafetyGatePassed, result.heldoutGatePassed);
fprintf(fid, ['| Split | Selected cells/actions | Harmful cells/actions | ', ...
    'E-OSPA / RMSE gain | Joint-utility capture |\n']);
fprintf(fid, '|:--|:--|:--|:--|--:|\n');
writeReadout(fid, 'Training F3', result.trainingF3);
writeReadout(fid, 'Training F5', result.trainingF5);
writeReadout(fid, 'Calibration F3 t=79', result.calibration);
writeReadout(fid, 'Heldout F5 t=79', result.heldout);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeReadout(fid, name, readout)
fprintf(fid, '| %s | %d/%d | %d/%d | %+.4f / %+.4f | %.3f |\n', ...
    name, readout.selectedCellCount, readout.selectedActionCount, ...
    readout.harmfulCellCount, readout.harmfulActionCount, ...
    readout.totalGain(1), readout.totalGain(2), ...
    readout.jointUtilityCaptureFraction);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
