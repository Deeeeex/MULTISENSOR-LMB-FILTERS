function [reportPath, screen] = ...
        captureBudgetedObservationSupportedRepairV197Base( ...
            scaleName, options)
% CAPTUREBUDGETEDOBSERVATIONSUPPORTEDREPAIRV197BASE Paired V99 base.

if nargin < 2 || isempty(options)
    options = struct();
end
scaleName = upper(char(scaleName));
horizonSteps = getField(options, 'horizonSteps', 3);
protocol = getOnlinePositiveNetAddressablePayloadV99Protocol( ...
    horizonSteps);
entryIdx = find(strcmp({protocol.cases.scaleName}, scaleName), 1);
if isempty(entryIdx)
    error('BudgetedSetRepairV197:UnknownScale', ...
        'The requested V99 scale is not registered.');
end
entry = protocol.cases(entryIdx);
if strcmp(scaleName, 'M24')
    defaultTime = 104;
else
    defaultTime = 72;
end
currentTime = getField(options, 'currentTime', defaultTime);
cacheRoot = char(getField(options, 'cacheRoot', entry.cacheRoot));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v197', 'base_capture', ...
    sprintf('%s_seed%d_t%d_h%d', lower(scaleName), entry.seed, ...
        currentTime, horizonSteps))));
if exist(cacheRoot, 'dir') ~= 7
    error('BudgetedSetRepairV197:MissingCache', ...
        'The registered opened-state cache root does not exist.');
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

defaultReferencePath = '';
if strcmp(scaleName, 'X36') && horizonSteps == 8 && ...
        entry.seed == 211 && currentTime == 72
    h8Protocol = getProtectionOnlyH8V105Protocol();
    if exist(h8Protocol.referenceOutcomeScreenPath, 'file') == 2
        defaultReferencePath = h8Protocol.referenceOutcomeScreenPath;
    end
end
referenceOutcomeScreenPath = char(getField( ...
    options, 'referenceOutcomeScreenPath', defaultReferencePath));

screenOptions = struct( ...
    'horizonSteps', horizonSteps, ...
    'interventionDurationSteps', horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v99-online-positive-net-addressable-payload', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', ...
            protocol.positiveSupportThreshold, ...
        'bankVariant', 'online-positive-net-addressable-v99', ...
        'horizonSteps', horizonSteps), ...
    'receiverMode', protocol.receiverMode, ...
    'actionIndices', [1, 3], ...
    'referenceOutcomeScreenPath', referenceOutcomeScreenPath, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true, ...
    'allowDirtySource', logical(getField( ...
        options, 'allowDirtySource', false)), ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'captureFusedPosteriorSnapshotsEnabled', true);
[reportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);

names = {screen.records.actionName};
onlineIdx = find(cellfun(@(name) strncmp(name, ...
    'v99-online-positive-net-', 24), names), 1);
if isempty(onlineIdx) || ...
        isempty(screen.outcomes(onlineIdx).localPosteriorSnapshotsByTime) || ...
        isempty(screen.outcomes(onlineIdx).fusedPosteriorSnapshotsByTime)
    error('BudgetedSetRepairV197:MissingSnapshots', ...
        'The paired V99 arm did not return the required posterior pages.');
end
fprintf('V197 %s H=%d base capture: %s\n', ...
    scaleName, horizonSteps, reportPath);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
