function [reportPath, result] = ...
    runReceiverDomainNormalizedOpportunityV70Discovery(options)
% RUNRECEIVERDOMAINNORMALIZEDOPPORTUNITYV70DISCOVERY Source-only scan.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReceiverDomainNormalizedOpportunityV70Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReceiverDomainV70:DirtySource', ...
        'The V70 source discovery requires clean source.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

sceneResults = repmat(struct(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    records = repmat(emptyRecord(), 1, numel(protocol.snapshotTimes));
    for timeIdx = 1:numel(protocol.snapshotTimes)
        currentTime = protocol.snapshotTimes(timeIdx);
        state = loadFormationH3ObservableState( ...
            protocol.presets{presetIdx}, protocol.allSeeds, currentTime, ...
            struct('cacheRoot', cacheRoot));
        [~, control] = computeFormationRoutingLeverageSignature( ...
            state.context, state.groupIds, struct( ...
                'referenceMode', 'current-physical-tree'));
        base = computeNetworkAdditiveFormationRiskV65( ...
            control, state.context, state.groupIds, ...
            protocol.positiveSupportThreshold);
        influence = computeInfluenceAwareDecisionBreadthV66( ...
            control, state.context, state.groupIds, struct( ...
                'positiveSupportThreshold', ...
                    protocol.positiveSupportThreshold, ...
                'horizonSteps', protocol.horizonSteps));
        transport = computeAlternativeTransportHeadroomV68( ...
            state.context, control, state.groupIds, ...
            getSignedMergeSplitOpportunityV69Protocol());
        local = computeReceiverDomainNormalizedOpportunityV70( ...
            base, influence, control, transport, state.groupIds, protocol);
        records(timeIdx) = makeRecord( ...
            currentTime, base, transport, local);
        fprintf([ ...
            'V70 %s t=%d qGlobalNet=%.3f%% qLocalNet=%.3f%% ', ...
            'altGlobal=%.3f%% altLocal=%.3f%% actions=%s\n'], ...
            protocol.presets{presetIdx}, currentTime, ...
            100 * (base.totalNetworkRescueFraction - ...
                base.totalNetworkUsefulLossFraction), ...
            100 * local.maximumLocalQuarantineNetFraction, ...
            100 * transport.optimisticNetHeadroomFraction, ...
            100 * local.maximumLocalAlternativeTransportNetFraction, ...
            mat2str(local.actionableFormationIds));
    end
    sceneResults(presetIdx) = summarizeScene( ...
        protocol.presets{presetIdx}, protocol.allSeeds, records);
end

result = struct();
result.contractVersion = ...
    'receiver-domain-normalized-opportunity-v70-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.sceneResults = sceneResults;
result.trackingOutcomeRead = false;
result.routeExecutionAuthorized = false;
result.trackingOutcomeScoringAuthorized = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RECEIVER_DOMAIN_NORMALIZED_OPPORTUNITY_V70_DISCOVERY.mat');
reportPath = fullfile(outputRoot, ...
    'RECEIVER_DOMAIN_NORMALIZED_OPPORTUNITY_V70_DISCOVERY.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V70 receiver-domain discovery: %s\n', reportPath);
end

function record = makeRecord(time, base, transport, local)
record = emptyRecord();
record.currentTime = time;
record.globalQuarantineRescueFraction = base.totalNetworkRescueFraction;
record.globalQuarantineNetFraction = ...
    base.totalNetworkRescueFraction - ...
        base.totalNetworkUsefulLossFraction;
record.maximumLocalQuarantineRescueFraction = ...
    local.maximumLocalQuarantineRescueFraction;
record.maximumLocalQuarantineNetFraction = ...
    local.maximumLocalQuarantineNetFraction;
record.globalAlternativeNetFraction = ...
    transport.optimisticNetHeadroomFraction;
record.maximumLocalAlternativeNetFraction = ...
    local.maximumLocalAlternativeTransportNetFraction;
record.quarantineFormationIds = ...
    local.quarantineActionFormationIds;
record.transportFormationIds = ...
    local.alternativeTransportActionFormationIds;
record.actionableFormationIds = local.actionableFormationIds;
record.preferredActionByFormation = local.preferredActionByFormation;
record.localQuarantineRescueByFormation = ...
    local.localQuarantineRescueFractionByFormation;
record.localQuarantineNetByFormation = ...
    local.localQuarantineNetFractionByFormation;
record.localRobustExposureByFormation = ...
    local.localRobustMarginExposureByFormation;
record.localAlternativeNetByFormation = ...
    local.localAlternativeTransportNetFractionByFormation;
end

function scene = summarizeScene(presetName, seed, records)
scene = struct();
scene.presetName = presetName;
scene.seed = seed;
scene.records = records;
scene.actionableTimes = [records(arrayfun( ...
    @(r) ~isempty(r.actionableFormationIds), records)).currentTime];
[~, qIdx] = max([records.maximumLocalQuarantineNetFraction]);
[~, altIdx] = max([records.maximumLocalAlternativeNetFraction]);
scene.maximumLocalQuarantineRecord = records(qIdx);
scene.maximumLocalAlternativeRecord = records(altIdx);
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'globalQuarantineRescueFraction', NaN, ...
    'globalQuarantineNetFraction', NaN, ...
    'maximumLocalQuarantineRescueFraction', NaN, ...
    'maximumLocalQuarantineNetFraction', NaN, ...
    'globalAlternativeNetFraction', NaN, ...
    'maximumLocalAlternativeNetFraction', NaN, ...
    'quarantineFormationIds', zeros(1, 0), ...
    'transportFormationIds', zeros(1, 0), ...
    'actionableFormationIds', zeros(1, 0), ...
    'preferredActionByFormation', {cell(1, 0)}, ...
    'localQuarantineRescueByFormation', zeros(1, 0), ...
    'localQuarantineNetByFormation', zeros(1, 0), ...
    'localRobustExposureByFormation', zeros(1, 0), ...
    'localAlternativeNetByFormation', zeros(1, 0));
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReceiverDomainV70:WriteFailed', ...
        'Could not create the V70 discovery report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V70 receiver-domain normalized opportunity discovery\n\n');
for scene = result.sceneResults
    fprintf(fid, '## %s / seed %d\n\n', ...
        scene.presetName, scene.seed);
    fprintf(fid, ['| Time | Q global net | Q local net max | ', ...
        'Alt global | Alt local max | Q formations | ', ...
        'Alt formations |\n']);
    fprintf(fid, '|--:|--:|--:|--:|--:|:--|:--|\n');
    for record = scene.records
        fprintf(fid, ...
            '| %d | %.3f%% | %.3f%% | %.3f%% | %.3f%% | `%s` | `%s` |\n', ...
            record.currentTime, ...
            100 * record.globalQuarantineNetFraction, ...
            100 * record.maximumLocalQuarantineNetFraction, ...
            100 * record.globalAlternativeNetFraction, ...
            100 * record.maximumLocalAlternativeNetFraction, ...
            mat2str(record.quarantineFormationIds), ...
            mat2str(record.transportFormationIds));
    end
    fprintf(fid, '\n- Actionable times: `%s`\n', ...
        mat2str(scene.actionableTimes));
    maximumLocalQuarantine = getField( ...
        scene.maximumLocalQuarantineRecord, ...
        'maximumLocalQuarantineNetFraction', NaN);
    maximumLocalAlternative = getField( ...
        scene.maximumLocalAlternativeRecord, ...
        'maximumLocalAlternativeNetFraction', NaN);
    fprintf(fid, '- Maximum local quarantine: `t=%d / %.3f%%`\n', ...
        scene.maximumLocalQuarantineRecord.currentTime, ...
        100 * maximumLocalQuarantine);
    fprintf(fid, '- Maximum local alternative: `t=%d / %.3f%%`\n\n', ...
        scene.maximumLocalAlternativeRecord.currentTime, ...
        100 * maximumLocalAlternative);
end
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route execution authorized: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
