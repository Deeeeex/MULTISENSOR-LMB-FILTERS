function [reportPath, result] = ...
    runReceiverDomainTransportProjectionV71Anchors(options)
% RUNRECEIVERDOMAINTRANSPORTPROJECTIONV71ANCHORS Source-only route anchors.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReceiverDomainTransportProjectionV71Protocol();
v70Protocol = getReceiverDomainNormalizedOpportunityV70Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReceiverDomainProjectionV71:DirtySource', ...
        'The V71 anchor projection requires clean source.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    presetName = protocol.presets{presetIdx};
    currentTime = protocol.anchorTimes(presetIdx);
    state = loadFormationH3ObservableState( ...
        presetName, protocol.allSeeds, currentTime, ...
        struct('cacheRoot', cacheRoot));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds, struct( ...
            'referenceMode', 'current-physical-tree'));
    base = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        v70Protocol.positiveSupportThreshold);
    influence = computeInfluenceAwareDecisionBreadthV66( ...
        control, state.context, state.groupIds, struct( ...
            'positiveSupportThreshold', ...
                v70Protocol.positiveSupportThreshold, ...
            'horizonSteps', ...
                v70Protocol.horizonSteps));
    transport = computeAlternativeTransportHeadroomV68( ...
        state.context, control, state.groupIds, ...
        getSignedMergeSplitOpportunityV69Protocol());
    local = computeReceiverDomainNormalizedOpportunityV70( ...
        base, influence, control, transport, state.groupIds, ...
        v70Protocol);
    expectedFormationIds = ...
        reshape(protocol.anchorFormationIds{presetIdx}, 1, []);
    if ~isequal(local.alternativeTransportActionFormationIds, ...
            expectedFormationIds)
        error('ReceiverDomainProjectionV71:AnchorDrift', ...
            'The frozen V70 anchor nomination changed before projection.');
    end
    projection = buildReceiverDomainTransportProjectionV71( ...
        state.context, control, transport, local, state.groupIds, protocol);
    records(presetIdx) = makeRecord( ...
        presetName, protocol.allSeeds, currentTime, ...
        local, transport, projection);
    fprintf([ ...
        'V71 %s t=%d nominated=%s selected=%s slots=%d ', ...
        'feasible=%d/%d utility=%.3f%% fallback=%d\n'], ...
        presetName, currentTime, ...
        mat2str(projection.nominatedFormationIds), ...
        mat2str(projection.selectedFormationIds), ...
        numel(projection.selectedSlotIndices), ...
        projection.feasibleCandidateCount, projection.candidateCount, ...
        100 * projection.selectedNetworkAverageNetFraction, ...
        projection.referenceFallbackUsed);
end

result = struct();
result.contractVersion = ...
    'receiver-domain-transport-projection-v71-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allAnchorsConstructed = all([records.routeConstructed]);
result.allMessageParityPass = all([records.messageParityPass]);
result.allRollingB3Pass = all([records.rollingB3Pass]);
result.trackingOutcomeRead = false;
result.routeExecutionAuthorized = false;
result.trackingOutcomeScoringAuthorized = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RECEIVER_DOMAIN_TRANSPORT_PROJECTION_V71_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'RECEIVER_DOMAIN_TRANSPORT_PROJECTION_V71_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V71 anchor projection: %s\n', reportPath);
end

function record = makeRecord( ...
        presetName, seed, currentTime, local, transport, projection)
record = emptyRecord();
record.presetName = presetName;
record.seed = seed;
record.currentTime = currentTime;
record.nominatedFormationIds = projection.nominatedFormationIds;
record.selectedFormationIds = projection.selectedFormationIds;
record.selectedSlotIndices = projection.selectedSlotIndices;
record.selectedSlotCount = numel(projection.selectedSlotIndices);
record.candidateCount = projection.candidateCount;
record.feasibleCandidateCount = projection.feasibleCandidateCount;
record.selectedUtilityMass = projection.selectedUtilityMass;
record.selectedNetworkAverageNetFraction = ...
    projection.selectedNetworkAverageNetFraction;
record.localNetFractionByFormation = ...
    local.localAlternativeTransportNetFractionByFormation;
record.referenceMessageCount = projection.referenceMessageCount;
record.selectedMessageCount = projection.selectedMessageCount;
record.messageParityPass = ...
    projection.messageCountParityWithReference && ...
    projection.perReceiverMessageCountParityWithReference && ...
    projection.perReceiverWeightMultisetParityWithReference;
record.rollingB3SensorPass = ...
    projection.selectedRollingB3SensorPass;
record.rollingB3FormationPass = ...
    projection.selectedRollingB3FormationPass;
record.rollingB3Pass = ...
    all(record.rollingB3SensorPass) && ...
    all(record.rollingB3FormationPass);
record.formationGraphParityWithReference = ...
    projection.formationGraphParityWithReference;
record.referenceFallbackUsed = projection.referenceFallbackUsed;
record.routeConstructed = projection.routeConstructed;
record.selectedSlots = summarizeSlots( ...
    transport.slotRecords, projection.selectedSlotIndices);
end

function summaries = summarizeSlots(slots, selectedIndices)
summaries = repmat(emptySlotSummary(), 1, numel(selectedIndices));
for selectedIdx = 1:numel(selectedIndices)
    slot = slots(selectedIndices(selectedIdx));
    summaries(selectedIdx) = struct( ...
        'receiverIdx', slot.receiverIdx, ...
        'incumbentSenderIdx', slot.incumbentSenderIdx, ...
        'candidateSenderIdx', slot.bestCandidateSenderIdx, ...
        'sourceWeight', slot.sourceWeight, ...
        'transportGainFraction', slot.bestTransportGainFraction, ...
        'supportedHarmFraction', slot.bestSupportedHarmFraction, ...
        'netHeadroomFraction', slot.bestNetHeadroomFraction, ...
        'upwardCrossingCount', slot.bestUpwardCrossingCount, ...
        'downwardCrossingCount', slot.bestDownwardCrossingCount);
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReceiverDomainProjectionV71:WriteFailed', ...
        'Could not create the V71 anchor report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V71 receiver-domain transport projection anchors\n\n');
fprintf(fid, ['| Scale | Time | Nominated formations | Selected formations | ', ...
    'Slots | Feasible subsets | Net mass / network | Messages | ', ...
    'Rolling B3 | Route |\n']);
fprintf(fid, '|:--|--:|:--|:--|--:|--:|--:|:--|:--|:--|\n');
for record = result.records
    fprintf(fid, ...
        '| %s | %d | `%s` | `%s` | %d | %d / %d | %.3f%% | ', ...
        record.presetName, record.currentTime, ...
        mat2str(record.nominatedFormationIds), ...
        mat2str(record.selectedFormationIds), ...
        record.selectedSlotCount, record.feasibleCandidateCount, ...
        record.candidateCount, ...
        100 * record.selectedNetworkAverageNetFraction);
    fprintf(fid, '`%d / %d` | `%d` | `%s` |\n', ...
        record.selectedMessageCount, record.referenceMessageCount, ...
        record.rollingB3Pass, routeName(record));
end
fprintf(fid, '\n## Selected receiver slots\n\n');
for record = result.records
    fprintf(fid, '### %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    if isempty(record.selectedSlots)
        fprintf(fid, 'Reference fallback; no receiver slot selected.\n\n');
        continue;
    end
    fprintf(fid, ['| Receiver | Incumbent sender | Candidate sender | ', ...
        'Weight | Gain | Harm | Net | Up / down crossings |\n']);
    fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--|\n');
    for slot = record.selectedSlots
        fprintf(fid, ...
            '| %d | %d | %d | %.2f | %.3f%% | %.3f%% | %.3f%% | `%d / %d` |\n', ...
            slot.receiverIdx, slot.incumbentSenderIdx, ...
            slot.candidateSenderIdx, slot.sourceWeight, ...
            100 * slot.transportGainFraction, ...
            100 * slot.supportedHarmFraction, ...
            100 * slot.netHeadroomFraction, ...
            slot.upwardCrossingCount, slot.downwardCrossingCount);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '## Gate summary\n\n');
fprintf(fid, '- Both anchors constructed a non-reference route: `%d`\n', ...
    result.allAnchorsConstructed);
fprintf(fid, '- Exact message and row-weight parity at both anchors: `%d`\n', ...
    result.allMessageParityPass);
fprintf(fid, '- Rolling-B3 sensor and formation connectivity at both anchors: `%d`\n', ...
    result.allRollingB3Pass);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route executed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function name = routeName(record)
if record.routeConstructed
    name = 'constructed';
else
    name = 'reference fallback';
end
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'nominatedFormationIds', zeros(1, 0), ...
    'selectedFormationIds', zeros(1, 0), ...
    'selectedSlotIndices', zeros(1, 0), ...
    'selectedSlotCount', 0, ...
    'candidateCount', 0, ...
    'feasibleCandidateCount', 0, ...
    'selectedUtilityMass', NaN, ...
    'selectedNetworkAverageNetFraction', NaN, ...
    'localNetFractionByFormation', zeros(1, 0), ...
    'referenceMessageCount', NaN, ...
    'selectedMessageCount', NaN, ...
    'messageParityPass', false, ...
    'rollingB3SensorPass', false(1, 0), ...
    'rollingB3FormationPass', false(1, 0), ...
    'rollingB3Pass', false, ...
    'formationGraphParityWithReference', false, ...
    'referenceFallbackUsed', true, ...
    'routeConstructed', false, ...
    'selectedSlots', repmat(emptySlotSummary(), 1, 0));
end

function value = emptySlotSummary()
value = struct( ...
    'receiverIdx', NaN, ...
    'incumbentSenderIdx', NaN, ...
    'candidateSenderIdx', NaN, ...
    'sourceWeight', NaN, ...
    'transportGainFraction', NaN, ...
    'supportedHarmFraction', NaN, ...
    'netHeadroomFraction', NaN, ...
    'upwardCrossingCount', NaN, ...
    'downwardCrossingCount', NaN);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
