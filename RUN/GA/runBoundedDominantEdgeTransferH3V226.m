function [reportPath, result] = ...
        runBoundedDominantEdgeTransferH3V226(options)
% RUNBOUNDEDDOMINANTEDGETRANSFERH3V226 Frozen bounded label-edge screens.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBoundedDominantEdgeTransferV226Protocol();
options.etaProjectionEnabled = true;
options.inputRouteWeightMode = protocol.inputRouteWeightMode;
[reportPath, result] = ...
    runSinglePassSemanticInputRoutingH3V221(options);
if ~strcmp(result.contractVersion, ...
        'bounded-dominant-edge-transfer-h3-v226-v1') || ...
        ~result.etaProjectionEnabled || ...
        ~result.boundedDominantEdgeTransferEnabled || ...
        result.dominantEdgeReplacementEnabled || ...
        ~strcmp(result.inputRouteWeightMode, ...
            protocol.inputRouteWeightMode)
    error('BoundedDominantEdgeTransferV226:WrapperDrift', ...
        'The V226 wrapper did not produce a bounded eta-safe transfer.');
end
end
