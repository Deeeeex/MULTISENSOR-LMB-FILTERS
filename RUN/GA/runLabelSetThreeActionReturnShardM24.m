function [shardPath, shard] = ...
    runLabelSetThreeActionReturnShardM24( ...
        seed, currentTime, options)
% RUNLABELSETTHREEACTIONRETURNSHARDM24 Exact paired H=3 action returns.
%
% CW, CCW and a label-set message-passing graph each control only the
% current topology. The next two steps use the frozen CCW fallback. Every
% arm starts from the same captured predecision posterior/history, resets
% the same filter RNG and reuses the same measurements and link uniforms.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.returnValueGateDesignAuthorized || ...
        ~protocol.returnValueGateReturnGenerationAuthorized || ...
        protocol.returnValueGateHorizon ~= 3 || ...
        protocol.returnValueGateActionPersistenceSteps ~= 1 || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Three-action H=3 return generation is not authorized.');
end
seed = validateTrainingSeed(seed, protocol);
currentTime = validateSourceTime(currentTime, protocol);
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles) || ...
         gitState.researchWorktreeDirty)
    error(['Official three-action return generation requires clean ', ...
        'tracked and MATLAB/Octave source state.']);
end

sourcePath = getField(options, 'sourcePath', ...
    fullfile(protocol.returnValueGateSourceDirectory, ...
        sprintf([ ...
            'label_set_ccw_return_source_m24_seed%d_v1.mat'], ...
            seed)));
sourceSha256 = computeFileSha256(sourcePath);
loadedSource = load(sourcePath, 'dataset');
if ~isfield(loadedSource, 'dataset')
    error('Frozen-CCW source shard lacks dataset.');
end
source = loadedSource.dataset;
validateSourceDataset(source, seed, currentTime, ...
    protocol, allowDirtySource);
blockIdx = find([source.blocks.currentTime] == currentTime);
if numel(blockIdx) ~= 1
    error('Frozen-CCW source lacks a unique requested state.');
end
sourceBlock = source.blocks(blockIdx);

modelPath = getField(options, 'modelPath', ...
    protocol.messagePassingInitializationPath);
modelSha256 = computeFileSha256(modelPath);
loadedModel = load(modelPath, 'model');
if ~isfield(loadedModel, 'model')
    error('Low-level label-set model artifact is missing.');
end
model = loadedModel.model;
validateLowLevelModel( ...
    model, modelPath, modelSha256, protocol);

inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCount
    error('Registered M24 return scenario is invalid.');
end
returnTimes = currentTime + ...
    (0:(protocol.returnValueGateHorizon - 1));
inputs = cropInputs(inputs, returnTimes(end));
context = buildPredecisionContext( ...
    sourceBlock, inputs, protocol);

actionNames = protocol.returnValueGateActions;
[cwAdjacency, cwDetails] = ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, 'fixed-clockwise', ...
        staticPolicyOptions(protocol));
[ccwAdjacency, ccwDetails] = ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, 'fixed-counter-clockwise', ...
        staticPolicyOptions(protocol));
[learnedAdjacency, learnedDetails] = ...
    selectLabelSetMessagePassingRoutingPolicy( ...
        context, model, struct( ...
            'protocol', protocol, ...
            'fixedResidualWeight', ...
                protocol.localResidualWeight));
actionAdjacency = cat(3, ...
    logical(cwAdjacency), logical(ccwAdjacency), ...
    logical(learnedAdjacency));
actionDetails = {cwDetails, ccwDetails, learnedDetails};
featureBundle = ...
    computeLabelSetThreeActionValueFeatures( ...
        context, model, actionAdjacency, ...
        actionDetails, actionNames, struct( ...
            'referenceActionIndex', 2));

outcomes = repmat(emptyOutcome(), 1, 3);
for actionIdx = 1:3
    fprintf('M24 H=3 seed %d t=%d action %s...\n', ...
        seed, currentTime, actionNames{actionIdx});
    outcomes(actionIdx) = runOneAction( ...
        inputs, sourceBlock, returnTimes, ...
        actionAdjacency(:, :, actionIdx), ...
        actionDetails{actionIdx}, protocol);
    fprintf(['  E-OSPA %.6f, worst %.6f, consensus %.6f, ', ...
        'attempted %.0f B, max GM %.0f, %.2f s\n'], ...
        outcomes(actionIdx).meanEospa, ...
        outcomes(actionIdx).worstSensorEospa, ...
        outcomes(actionIdx).consensusOspa, ...
        outcomes(actionIdx).attemptedBytes, ...
        outcomes(actionIdx).maximumComponentCount, ...
        outcomes(actionIdx).elapsedSeconds);
end

meanRisk = [outcomes.meanEospa];
[oracleMeanEospa, oracleActionIndex] = min(meanRisk);
ccwMeanEospa = outcomes(2).meanEospa;
oracleGainPercent = 100 * ...
    (ccwMeanEospa - oracleMeanEospa) / ...
    max(ccwMeanEospa, eps);
learnedGainPercent = 100 * ...
    (ccwMeanEospa - outcomes(3).meanEospa) / ...
    max(ccwMeanEospa, eps);

shard = struct();
shard.protocolId = protocol.id;
shard.contractVersion = ...
    protocol.returnValueGateReturnContractVersion;
shard.generatedAt = datestr(now, 31);
shard.generationGitCommit = gitState.commit;
shard.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
shard.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
shard.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
shard.presetName = protocol.presetName;
shard.seed = seed;
shard.currentTime = currentTime;
shard.returnTimes = returnTimes;
shard.horizonSteps = ...
    protocol.returnValueGateHorizon;
shard.actionPersistenceSteps = ...
    protocol.returnValueGateActionPersistenceSteps;
shard.continuationAction = ...
    protocol.returnValueGateDefaultAction;
shard.actionNames = actionNames;
shard.actionAdjacency = actionAdjacency;
shard.features = featureBundle;
shard.featureContractSha256 = ...
    featureBundle.featureContractSha256;
shard.actionOrderSha256 = ...
    featureBundle.actionOrderSha256;
shard.outcomes = outcomes;
shard.oracleActionIndex = oracleActionIndex;
shard.oracleActionName = actionNames{oracleActionIndex};
shard.oracleMeanEospa = oracleMeanEospa;
shard.oracleGainVsCcwPercent = oracleGainPercent;
shard.learnedGainVsCcwPercent = learnedGainPercent;
shard.sourcePath = sourcePath;
shard.sourceSha256 = sourceSha256;
shard.lowLevelModelPath = modelPath;
shard.lowLevelModelSha256 = modelSha256;
shard.lowLevelModelTrainingSeeds = ...
    getField(model, 'trainingSeeds', ...
        protocol.trainingSeeds);
shard.lowLevelModelOuterFoldRestricted = ...
    isfield(model, 'trainingSeedSubset') && ...
        model.trainingSeedSubset;
shard.filterSeed = seed + protocol.filterSeedOffset;
shard.commonRandomNumbers = true;
shard.targetsUseTruth = true;
shard.targetsUseFutureMeasurements = true;
shard.featuresUseTruth = false;
shard.featuresUseFutureMeasurements = false;
shard.featuresUseFutureOutcome = false;
shard.runtimePolicyUsesTruth = ...
    any([outcomes.truthUseCount] > 0);
shard.trainingOnlyDiagnostic = true;
shard.developmentOpened = false;
shard.heldoutM24Opened = false;
shard.x36Opened = false;
shard.evidenceBoundary = [ ...
    'This training-only shard uses truth and future measurements only ', ...
    'after action selection to score paired H=3 outcomes. Features ', ...
    'and runtime action construction are truth-free. A shard using ', ...
    'the all-seed low-level initialization is mechanism evidence only; ', ...
    'strict outer-seed claims require a fit-seed-restricted model.'];

outputDirectory = getField(options, ...
    'outputDirectory', ...
    protocol.returnValueGateReturnDirectory);
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = sprintf( ...
    'label_set_three_action_h3_m24_seed%d_t%d_%s', ...
    seed, currentTime, modelSha256(1:12));
shardPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [stem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(stem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(shardPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Three-action return output already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
shard.shardPath = shardPath;
shard.reportPath = reportPath;
save('-mat7-binary', shardPath, 'shard');
writeReport(reportPath, shard);
fprintf('Three-action return shard: %s\nReport: %s\n', ...
    shardPath, reportPath);
end

function outcome = runOneAction( ...
        inputs, sourceBlock, returnTimes, ...
        firstAdjacency, firstDetails, protocol)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = ...
    inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * inputs.config.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'label-set-three-action-h3-first-then-ccw';
config.topologyPosteriorCaptureTimes = returnTimes;
config.topologyPolicyFcn = ...
    @(context) frozenFirstThenCcw( ...
        context, returnTimes(1), ...
        firstAdjacency, firstDetails, protocol);
config.filterInitialLocalPosteriorBySensor = ...
    sourceBlock.initialLocalPosteriorBySensor;
config.filterInitialLocalPosteriorTime = ...
    sourceBlock.currentTime;
config.filterInitialPreviousAdjacencyHistory = ...
    sourceBlock.previousAdjacencyHistory;
config.filterInitialPreviousAdjacencyTimes = ...
    sourceBlock.previousAdjacencyHistoryTimes;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'frozen-ccw-return-source-v1';

rng(sourceBlock.seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);

firstExecuted = ...
    convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge( ...
            :, :, returnTimes(1)));
if ~isequal(firstExecuted, logical(firstAdjacency))
    error('Three-action return did not execute its first graph exactly.');
end
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(returnTimes));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(returnTimes));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(returnTimes));
infeasible = logical( ...
    ~diagnostics.topologyFeasible(returnTimes) | ...
    finiteLogical(diagnostics. ...
        topologyPolicyTopologyInfeasible(returnTimes)));
if any(truthUse) || any(repair) || ...
        any(emergency) || any(infeasible)
    error('Three-action return violated a hard runtime gate.');
end

selected = false( ...
    inputs.config.numberOfSensors, ...
    inputs.config.numberOfSensors, numel(returnTimes));
delivered = selected;
for timeIdx = 1:numel(returnTimes)
    selected(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(timeIdx)));
    delivered(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered( ...
                :, :, returnTimes(timeIdx)));
end
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousAdjacencyHistory, ...
        selected, inputs.config.sensorGroupIds);
[deliveredSensorB3, deliveredFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousDeliveredAdjacencyHistory, ...
        delivered, inputs.config.sensorGroupIds);
if ~all(selectedSensorB3) || ...
        ~all(selectedFormationB3)
    error('Three-action return violated selected rolling-B3 safety.');
end

sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(returnTimes));
cardinalityError = zeros(sensorCount, numel(returnTimes));
for sensorIdx = 1:sensorCount
    [sensorEospa, ~, sensorCardinality] = ...
        computeSimulationOspa( ...
        inputs.model, inputs.groundTruthRfs, ...
        estimates{sensorIdx});
    eospa(sensorIdx, :) = ...
        sensorEospa(returnTimes);
    cardinalityError(sensorIdx, :) = abs( ...
        sensorCardinality(returnTimes) - ...
        inputs.groundTruthRfs.cardinality(returnTimes));
end
sensorMeans = mean(eospa, 2);
[positionDisagreement, cardinalityDispersion, ...
    ospaDisagreement] = ...
    computeDistributedConsensusMetrics( ...
        estimates, inputs.model);
consensusValues = ospaDisagreement(returnTimes);
consensusOspa = finiteMean(consensusValues);
consensusPosition = finiteMean( ...
    positionDisagreement(returnTimes));
consensusCardinality = finiteMean( ...
    cardinalityDispersion(returnTimes));
posteriorConsensus = finiteMean( ...
    diagnostics.posteriorConsensusCombined(returnTimes));
[meanComponents, maximumComponents] = ...
    summarizeCapturedComplexity( ...
        diagnostics, returnTimes);

outcome = emptyOutcome();
outcome.meanEospa = mean(eospa(:));
outcome.worstSensorEospa = max(sensorMeans);
outcome.sensorMeanEospa = reshape(sensorMeans, 1, []);
outcome.eospaBySensorTime = eospa;
outcome.meanCardinalityError = ...
    mean(cardinalityError(:));
outcome.consensusOspa = consensusOspa;
outcome.consensusPosition = consensusPosition;
outcome.consensusCardinality = ...
    consensusCardinality;
outcome.posteriorConsensus = posteriorConsensus;
outcome.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes( ...
        :, :, returnTimes), 1), 2), 1, []);
outcome.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes( ...
        :, :, returnTimes), 1), 2), 1, []);
outcome.attemptedBytes = ...
    sum(outcome.attemptedBytesByTime);
outcome.deliveredBytes = ...
    sum(outcome.deliveredBytesByTime);
outcome.attemptCount = sum(reshape( ...
    diagnostics.attempted(:, :, returnTimes), 1, []));
outcome.deliveryCount = sum(reshape( ...
    diagnostics.delivered(:, :, returnTimes), 1, []));
outcome.meanComponentCount = meanComponents;
outcome.maximumComponentCount = maximumComponents;
outcome.selectedAdjacency = selected;
outcome.deliveredAdjacency = delivered;
outcome.selectedSensorB3Pass = selectedSensorB3;
outcome.selectedFormationB3Pass = ...
    selectedFormationB3;
outcome.deliveredSensorB3Pass = deliveredSensorB3;
outcome.deliveredFormationB3Pass = ...
    deliveredFormationB3;
outcome.truthUseCount = nnz(truthUse);
outcome.repairCount = nnz(repair);
outcome.payloadEmergencyCount = nnz(emergency);
outcome.infeasibleCount = nnz(infeasible);
outcome.firstActionExact = true;
outcome.elapsedSeconds = elapsedSeconds;
end

function [adjacency, details] = ...
        frozenFirstThenCcw( ...
            context, anchorTime, firstAdjacency, ...
            firstDetails, protocol)
if context.currentTime == anchorTime
    adjacency = logical(firstAdjacency);
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:)))
        error('Frozen first action is physically invalid.');
    end
    details = firstDetails;
    details.mode = 'frozen-three-action-first-step';
    details.truthUsed = false;
    details.groundTruthUsed = false;
    details.futureOutcomeUsed = false;
    details.runtimeFrozenGraphReplay = true;
else
    [adjacency, details] = ...
        selectBackboneResidualSplicedCyclePolicy( ...
            context, protocol.returnValueGateDefaultAction, ...
            staticPolicyOptions(protocol));
    details.runtimeFrozenGraphReplay = false;
end
end

function context = buildPredecisionContext( ...
        block, inputs, protocol)
currentTime = block.currentTime;
nodeCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = ...
    block.initialLocalPosteriorBySensor;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = ...
    buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = ...
    block.previousAdjacencyHistory;
context.previousAdjacencyHistoryCount = ...
    size(block.previousAdjacencyHistory, 3);
context.previousAdjacencyHistoryTimes = ...
    block.previousAdjacencyHistoryTimes;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacencyHistorySource = ...
    'frozen-ccw-return-source-v1';
context.previousAdjacency = ...
    block.previousAdjacencyHistory(:, :, end);
context.baseAdjacency = ...
    neighborMapToAdjacency( ...
        inputs.neighborMap, nodeCount);
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency( ...
        :, :, currentTime));
context.edgeScores = ...
    double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = ...
    inputs.graphData.positions(:, :, currentTime);
context.localInnovationHistory = ...
    block.localInnovationHistory;
context.localAssociationConfidenceHistory = ...
    block.localAssociationConfidenceHistory;
context.localNisNormHistory = ...
    block.localNisNormHistory;
context.localNisDeviationHistory = ...
    block.localNisDeviationHistory;
context.localUpdateHistoryTimes = ...
    block.localUpdateHistoryTimes;
if context.previousAdjacencyHistoryCount ~= 2
    error('H=3 return context requires two history pages.');
end
end

function validateSourceDataset( ...
        source, seed, currentTime, protocol, allowDirty)
required = { ...
    'protocolId', 'contractVersion', 'presetName', ...
    'seed', 'sourceTimes', 'horizonSteps', ...
    'behaviorAction', 'blocks', ...
    'featuresUseTruth', 'featuresUseFutureOutcome', ...
    'targetsStored', 'developmentOpened', ...
    'heldoutM24Opened', 'x36Opened'};
if ~isstruct(source) || ...
        ~all(isfield(source, required)) || ...
        ~strcmp(source.protocolId, protocol.id) || ...
        ~strcmp(source.contractVersion, ...
            protocol.returnValueGateSourceContractVersion) || ...
        ~strcmp(source.presetName, protocol.presetName) || ...
        source.seed ~= seed || ...
        ~isequal(source.sourceTimes, ...
            protocol.returnValueGateSourceTimes) || ...
        source.horizonSteps ~= ...
            protocol.returnValueGateHorizon || ...
        ~strcmp(source.behaviorAction, ...
            protocol.returnValueGateBehaviorAction) || ...
        ~any(source.sourceTimes == currentTime) || ...
        source.featuresUseTruth || ...
        source.featuresUseFutureOutcome || ...
        source.targetsStored || ...
        source.developmentOpened || ...
        source.heldoutM24Opened || source.x36Opened
    error('Frozen-CCW source dataset violates the return contract.');
end
if ~allowDirty && ...
        (source.generationTrackedWorktreeDirty || ...
         ~isempty(source.generationUntrackedSourceFiles) || ...
         source.generationResearchWorktreeDirty)
    error('Official return generation requires a clean source shard.');
end
end

function validateLowLevelModel( ...
        model, modelPath, modelSha256, protocol)
if ~isstruct(model) || ...
        ~isfield(model, 'kind') || ...
        ~strcmp(model.kind, ...
            'label-set-message-passing-policy') || ...
        ~strcmp(model.contractVersion, ...
            protocol.messagePassingModelContractVersion) || ...
        model.featuresUseTruth || ...
        model.numericLabelIdentifiersUsedAsFeatures || ...
        ~model.safeProjectorRequired
    error('Low-level label-set model violates the return contract.');
end
if strcmp(modelPath, ...
        protocol.messagePassingInitializationPath) && ...
        ~strcmp(modelSha256, ...
            protocol.messagePassingInitializationSha256)
    error('Registered low-level model hash mismatch.');
end
if isfield(model, 'trainingSeeds') && ...
        (~all(ismember(model.trainingSeeds, ...
            protocol.trainingSeeds)) || ...
         isempty(model.trainingSeeds))
    error('Low-level model training split is invalid.');
end
end

function [meanComponents, maximumComponents] = ...
        summarizeCapturedComplexity(diagnostics, times)
counts = zeros(0, 1);
for timeIdx = 1:numel(times)
    posteriors = diagnostics. ...
        topologyLocalPosteriorSnapshot{times(timeIdx)};
    for sensorIdx = 1:numel(posteriors)
        objects = posteriors{sensorIdx};
        if isempty(objects)
            counts(end + 1, 1) = 0; %#ok<AGROW>
        else
            counts(end + 1, 1) = ...
                sum([objects.numberOfGmComponents]); %#ok<AGROW>
        end
    end
end
meanComponents = mean(counts);
maximumComponents = max(counts);
end

function [sensorPass, formationPass] = ...
        computeRollingB3Pass(previousHistory, executed, groupIds)
history = logical(previousHistory);
sensorPass = false(1, size(executed, 3));
formationPass = sensorPass;
for stepIdx = 1:size(executed, 3)
    pages = cat(3, history, executed(:, :, stepIdx));
    window = any(pages(:, :, ...
        max(1, end - 2):end), 3);
    sensorPass(stepIdx) = isStronglyConnected(window);
    formationPass(stepIdx) = isStronglyConnected( ...
        collapseToFormations(window, groupIds));
    history(:, :, end + 1) = ...
        executed(:, :, stepIdx); %#ok<AGROW>
    if size(history, 3) > 2
        history = history(:, :, end-1:end);
    end
end
end

function formation = ...
        collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
formation = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formation(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formation(1:numel(groups)+1:end) = false;
end

function connected = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
connected = true;
for startNode = 1:nodeCount
    visited = false(1, nodeCount);
    visited(startNode) = true;
    while true
        next = visited | any(adjacency(visited, :), 1);
        if isequal(next, visited)
            break;
        end
        visited = next;
    end
    if ~all(visited)
        connected = false;
        return;
    end
end
end

function adjacency = ...
        neighborMapToAdjacency(neighborMap, nodeCount)
adjacency = false(nodeCount);
for receiverIdx = 1:nodeCount
    senders = reshape(neighborMap{receiverIdx}, 1, []);
    senders = senders(senders ~= receiverIdx);
    adjacency(receiverIdx, senders) = true;
end
end

function options = staticPolicyOptions(protocol)
options = struct( ...
    'dominantWeight', protocol.dominantWeight, ...
    'residualWeight', protocol.localResidualWeight);
end

function inputs = cropInputs(inputs, maximumTime)
maximumTime = min(maximumTime, size(inputs.measurements, 2));
inputs.measurements = inputs.measurements(:, 1:maximumTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maximumTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maximumTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
end

function outcome = emptyOutcome()
outcome = struct( ...
    'meanEospa', NaN, ...
    'worstSensorEospa', NaN, ...
    'sensorMeanEospa', [], ...
    'eospaBySensorTime', [], ...
    'meanCardinalityError', NaN, ...
    'consensusOspa', NaN, ...
    'consensusPosition', NaN, ...
    'consensusCardinality', NaN, ...
    'posteriorConsensus', NaN, ...
    'attemptedBytesByTime', [], ...
    'deliveredBytesByTime', [], ...
    'attemptedBytes', NaN, ...
    'deliveredBytes', NaN, ...
    'attemptCount', NaN, ...
    'deliveryCount', NaN, ...
    'meanComponentCount', NaN, ...
    'maximumComponentCount', NaN, ...
    'selectedAdjacency', false(0), ...
    'deliveredAdjacency', false(0), ...
    'selectedSensorB3Pass', false(1, 0), ...
    'selectedFormationB3Pass', false(1, 0), ...
    'deliveredSensorB3Pass', false(1, 0), ...
    'deliveredFormationB3Pass', false(1, 0), ...
    'truthUseCount', NaN, ...
    'repairCount', NaN, ...
    'payloadEmergencyCount', NaN, ...
    'infeasibleCount', NaN, ...
    'firstActionExact', false, ...
