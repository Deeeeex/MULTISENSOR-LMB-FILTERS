function writeReport(path, shard)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write three-action return report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 label-set three-action H=3 return\n\n');
fprintf(fid, '- Protocol: `%s`\n', shard.protocolId);
fprintf(fid, '- Contract: `%s`\n', shard.contractVersion);
fprintf(fid, '- Seed / time: `%d / %d`\n', ...
    shard.seed, shard.currentTime);
fprintf(fid, '- Return times: `%s`\n', ...
    mat2str(shard.returnTimes));
fprintf(fid, '- Source SHA-256: `%s`\n', ...
    shard.sourceSha256);
fprintf(fid, '- Low-level model SHA-256: `%s`\n', ...
    shard.lowLevelModelSha256);
fprintf(fid, '- Value-feature contract SHA-256: `%s`\n', ...
    shard.featureContractSha256);
fprintf(fid, '- Action-order SHA-256: `%s`\n', ...
    shard.actionOrderSha256);
fprintf(fid, '- Low-level outer-fold restricted: `%d`\n', ...
    shard.lowLevelModelOuterFoldRestricted);
fprintf(fid, '- Oracle action: `%s`\n', ...
    shard.oracleActionName);
fprintf(fid, '- Oracle gain versus CCW: `%.3f%%`\n', ...
    shard.oracleGainVsCcwPercent);
fprintf(fid, '- Learned gain versus CCW: `%.3f%%`\n\n', ...
    shard.learnedGainVsCcwPercent);
fprintf(fid, ['| Action | Mean E-OSPA | Worst | Card err | ', ...
    'Consensus | Posterior cons. | Attempted B | ', ...
    'Delivered B | Mean GM | Max GM | B3 |\n']);
fprintf(fid, ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for actionIdx = 1:numel(shard.actionNames)
    row = shard.outcomes(actionIdx);
    fprintf(fid, ...
        ['| `%s` | %.6f | %.6f | %.6f | %.6f | %.6f | ', ...
         '%.0f | %.0f | %.2f | %.0f | %d |\n'], ...
        shard.actionNames{actionIdx}, ...
        row.meanEospa, row.worstSensorEospa, ...
        row.meanCardinalityError, row.consensusOspa, ...
        row.posteriorConsensus, row.attemptedBytes, ...
        row.deliveredBytes, row.meanComponentCount, ...
        row.maximumComponentCount, ...
        all(row.selectedSensorB3Pass) && ...
            all(row.selectedFormationB3Pass));
end
fprintf(fid, '\n## Boundary\n\n%s\n', ...
    shard.evidenceBoundary);
end

function seed = validateTrainingSeed(seed, protocol)
if ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || ...
        ~ismember(seed, protocol.trainingSeeds)
    error('seed must be a registered M24 training seed.');
end
end

function currentTime = validateSourceTime( ...
        currentTime, protocol)
if ~isscalar(currentTime) || ...
        ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || ...
        ~ismember(currentTime, ...
            protocol.returnValueGateSourceTimes)
    error('currentTime must be a registered return-source time.');
end
end

function values = finiteLogical(values)
values = isfinite(values) & values ~= 0;
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
