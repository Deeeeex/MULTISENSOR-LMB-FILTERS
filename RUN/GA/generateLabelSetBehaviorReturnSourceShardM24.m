function [sourcePath, dataset] = ...
    generateLabelSetBehaviorReturnSourceShardM24( ...
        seed, behaviorAction, options)
% GENERATELABELSETBEHAVIORRETURNSOURCESHARDM24 Behavior predecision states.
%
% The shard follows one registered deployable behavior trajectory from the
% t=75 continuation state. It captures truth-free predecision LMB
% posteriors, selected/delivered topology history and local-update
% diagnostics for causal H=3 graph-option evaluation.

if nargin < 2 || isempty(behaviorAction)
    protocol = getLabelSetSimulatorPolicyProtocol();
    behaviorAction = protocol.returnValueGateBehaviorAction;
end
if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.returnValueGateDesignAuthorized || ...
        ~protocol.macroActionBehaviorSourceGenerationAuthorized || ...
        ~protocol.singleFrameScalarGateRejected || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Graph-option behavior-source generation is not authorized.');
end
seed = validateTrainingSeed(seed, protocol);
behaviorAction = validateBehaviorAction( ...
    behaviorAction, protocol);
legacyCcwContract = logical(getField( ...
    options, 'legacyCcwContract', false));
if legacyCcwContract && ...
        ~strcmp(behaviorAction, ...
            protocol.returnValueGateBehaviorAction)
    error('The legacy source contract is restricted to fixed CCW.');
end
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles) || ...
         gitState.researchWorktreeDirty)
    error(['Official frozen-CCW source generation requires clean ', ...
        'tracked and MATLAB/Octave source state.']);
end

inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCount
    error('Registered M24 source scenario is invalid.');
end
if legacyCcwContract
    sourceTimes = reshape( ...
        protocol.returnValueGateSourceTimes, 1, []);
else
    sourceTimes = reshape( ...
        protocol.macroActionBehaviorSourceTimes, 1, []);
end
requestedSourceTimes = reshape(getField( ...
    options, 'sourceTimes', sourceTimes), 1, []);
if ~allowDirtySource && ...
        ~isequal(requestedSourceTimes, sourceTimes)
    error(['Official behavior-source generation requires the exact ', ...
        'registered source times.']);
end
if isempty(requestedSourceTimes) || ...
        any(~ismember(requestedSourceTimes, sourceTimes)) || ...
        any(diff(requestedSourceTimes) <= 0)
    error('Exploratory sourceTimes must be an ordered protocol subset.');
end
sourceTimes = requestedSourceTimes;
maximumTime = sourceTimes(end) + ...
    protocol.returnValueGateHorizon - 1;
inputs = cropInputs(inputs, maximumTime);
[initialPosteriors, initialHistory, sourceCachePath, ...
    sourceCacheSha256] = loadRegisteredContinuation( ...
        inputs, seed, protocol);

config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = ...
    inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * inputs.config.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = [ ...
    'label-set-graph-option-source-', ...
    behaviorAction];
[behaviorModel, behaviorModelPath, ...
    behaviorModelSha256] = loadBehaviorModel( ...
        behaviorAction, protocol);
config.topologyPolicyFcn = ...
    @(context) selectBehaviorPolicy( ...
        context, behaviorAction, ...
        behaviorModel, protocol);
config.topologyPosteriorCaptureTimes = sourceTimes;
config.filterInitialLocalPosteriorBySensor = ...
    initialPosteriors;
config.filterInitialLocalPosteriorTime = ...
    protocol.continuationStartTime;
config.filterInitialPreviousAdjacencyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        initialHistory.selectedDirectedEdgeHistory);
config.filterInitialPreviousAdjacencyTimes = ...
    initialHistory.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'registered-static-behavior-cache-v2';

rng(seed + protocol.filterSeedOffset);
timerId = tic;
[behaviorEstimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);

blocks = repmat(emptyBlock(), 1, numel(sourceTimes));
for timeIdx = 1:numel(sourceTimes)
    currentTime = sourceTimes(timeIdx);
    localPosteriors = diagnostics. ...
        topologyLocalPosteriorSnapshot{currentTime};
    if isempty(localPosteriors) || ...
            numel(localPosteriors) ~= ...
                protocol.expectedNodeCount
        error('Frozen-CCW source posterior capture is missing.');
    end
    [selectedHistory, deliveredHistory, historyTimes] = ...
        resolvePredecisionHistory( ...
            currentTime, protocol.continuationStartTime, ...
            initialHistory, diagnostics);
    updateTimes = max(1, currentTime - 2):currentTime;
    block = emptyBlock();
    block.seed = seed;
    block.currentTime = currentTime;
    block.behaviorAction = behaviorAction;
    block.initialLocalPosteriorBySensor = localPosteriors;
    block.previousAdjacencyHistory = selectedHistory;
    block.previousDeliveredAdjacencyHistory = ...
        deliveredHistory;
    block.previousAdjacencyHistoryTimes = historyTimes;
    block.localUpdateHistoryTimes = updateTimes;
    block.localInnovationHistory = ...
        diagnostics.localInnovation(:, updateTimes);
    block.localAssociationConfidenceHistory = ...
        diagnostics.localAssociationConfidence(:, updateTimes);
    block.localNisNormHistory = ...
        diagnostics.localNisNorm(:, updateTimes);
    block.localNisDeviationHistory = ...
        diagnostics.localNisDeviation(:, updateTimes);
    block.restartReferenceTrace = ...
        computeDynamicTopologyRestartTraceSha256( ...
            behaviorEstimates, diagnostics, ...
            currentTime + ...
                (0:(protocol.returnValueGateHorizon - 1)));
    block.posteriorSummary = ...
        summarizePosteriorComplexity(localPosteriors);
    blocks(timeIdx) = block;
end

auditTimes = protocol.continuationStartTime:maximumTime;
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(auditTimes));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(auditTimes));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(auditTimes));
infeasible = logical( ...
    ~diagnostics.topologyFeasible(auditTimes) | ...
    finiteLogical( ...
        diagnostics. ...
            topologyPolicyTopologyInfeasible(auditTimes)));
if any(truthUse) || any(repair) || any(emergency) || ...
        any(infeasible)
    error('Graph-option source behavior violated a hard safety gate.');
end
messageCounts = diagnostics. ...
    topologyDirectedMessageCount(auditTimes);
if any(messageCounts ~= ...
        protocol.macroActionExpectedSelectedMessageCount)
    error('Graph-option behavior changed the exact message count.');
end
selected = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        diagnostics.topologyActiveEdge(:, :, auditTimes));
initialSelected = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        initialHistory.selectedDirectedEdgeHistory);
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        initialSelected, selected, ...
        inputs.config.sensorGroupIds);
if ~all(selectedSensorB3) || ...
        ~all(selectedFormationB3)
    error('Graph-option behavior failed independent selected B3.');
end
for auditIdx = 1:numel(auditTimes)
    weights = diagnostics. ...
        topologyPolicyFusionWeightMatrix{auditTimes(auditIdx)};
    if isempty(weights) || ...
            ~isequal(size(weights), ...
                [protocol.expectedNodeCount, ...
                 protocol.expectedNodeCount])
        error('Graph-option behavior lacks a fusion-weight matrix.');
    end
end

dataset = struct();
dataset.protocolId = protocol.id;
if legacyCcwContract
    dataset.contractVersion = ...
        protocol.returnValueGateSourceContractVersion;
else
    dataset.contractVersion = ...
        protocol.macroActionBehaviorSourceContractVersion;
end
dataset.generatedAt = datestr(now, 31);
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.presetName = protocol.presetName;
dataset.seed = seed;
dataset.sourceTimes = sourceTimes;
dataset.horizonSteps = ...
    protocol.returnValueGateHorizon;
dataset.behaviorAction = behaviorAction;
dataset.behaviorFilterSeed = ...
    seed + protocol.filterSeedOffset;
dataset.behaviorModelPath = behaviorModelPath;
dataset.behaviorModelSha256 = behaviorModelSha256;
dataset.sourceCachePath = sourceCachePath;
dataset.sourceCacheSha256 = sourceCacheSha256;
dataset.blocks = blocks;
dataset.behaviorSeconds = elapsedSeconds;
dataset.behaviorTruthUseCount = nnz(truthUse);
dataset.behaviorRepairCount = nnz(repair);
dataset.behaviorPayloadEmergencyCount = nnz(emergency);
dataset.behaviorInfeasibleCount = nnz(infeasible);
dataset.behaviorSelectedSensorB3Pass = ...
    selectedSensorB3;
dataset.behaviorSelectedFormationB3Pass = ...
    selectedFormationB3;
dataset.featuresUseTruth = false;
dataset.featuresUseFutureOutcome = false;
dataset.postdecisionTopologyStored = false;
dataset.restartReferenceHashesStored = true;
dataset.targetsStored = false;
dataset.developmentOpened = false;
dataset.heldoutM24Opened = false;
dataset.x36Opened = false;
dataset.evidenceBoundary = [ ...
    'This shard contains deployment-observable predecision states ', ...
    'from the opened M24 training split under one registered ', ...
    'deployable behavior ', ...
    'policy. It stores no truth-derived target and opens no ', ...
    'development, held-out M24 or X36 outcome.'];

if legacyCcwContract
    defaultOutputDirectory = ...
        protocol.returnValueGateSourceDirectory;
    defaultStem = sprintf( ...
        'label_set_ccw_return_source_m24_seed%d_v1', seed);
else
    defaultOutputDirectory = ...
        protocol.macroActionBehaviorSourceDirectory;
    defaultStem = sprintf( ...
        'label_set_%s_return_source_m24_seed%d_v1', ...
        behaviorActionToken(behaviorAction), seed);
end
outputDirectory = getField(options, ...
    'outputDirectory', defaultOutputDirectory);
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
sourcePath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [defaultStem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(defaultStem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(sourcePath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Graph-option behavior-source output already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
dataset.sourcePath = sourcePath;
dataset.reportPath = reportPath;
save('-mat7-binary', sourcePath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Graph-option behavior source: %s\nReport: %s\n', ...
    sourcePath, reportPath);
end

function [posteriors, history, cachePath, cacheSha256] = ...
        loadRegisteredContinuation(inputs, seed, protocol)
cachePath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'cache', ...
    sprintf('m24_hard_seed%d_n1_sig%d.mat', ...
        seed, protocol.continuationStartTime));
if exist(cachePath, 'file') ~= 2
    error('Registered continuation cache is missing.');
end
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('Continuation cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
expectedConfig = buildMixtureAwareKlaReferenceConfig();
expectedConfig.dynamicTopologyEnabled = false;
expectedConfig.topologyPosteriorCaptureTimes = ...
    protocol.continuationStartTime;
if ~isfield(bundle, 'presetName') || ...
        ~isfield(bundle, 'seed') || ...
        ~isfield(bundle, 'configSnapshot') || ...
        ~isfield(bundle, 'behaviorConfigSnapshot') || ...
        ~strcmp(bundle.presetName, protocol.presetName) || ...
        bundle.seed ~= seed || ...
        ~isequaln(bundle.configSnapshot, inputs.config) || ...
        ~isequaln(bundle.behaviorConfigSnapshot, ...
            expectedConfig)
    error('Continuation cache metadata differs from the protocol.');
end
[posteriors, history] = ...
    extractBehaviorContinuationSnapshot( ...
        bundle, protocol.continuationStartTime, ...
        protocol.expectedNodeCount);
cacheSha256 = computeFileSha256(cachePath);
end

function [selected, delivered, times] = ...
        resolvePredecisionHistory( ...
            currentTime, startTime, initialHistory, diagnostics)
depth = 2;
times = (currentTime - depth):(currentTime - 1);
sensorCount = size(diagnostics.topologyActiveEdge, 1);
selectedDiagnostic = false(sensorCount, sensorCount, depth);
deliveredDiagnostic = selectedDiagnostic;
for pageIdx = 1:depth
    historyTime = times(pageIdx);
    if historyTime < startTime
        sourceIdx = find( ...
            initialHistory.times == historyTime);
        if numel(sourceIdx) ~= 1
            error('Initial predecision history is incomplete.');
        end
        selectedDiagnostic(:, :, pageIdx) = ...
            initialHistory.selectedDirectedEdgeHistory( ...
                :, :, sourceIdx);
        deliveredDiagnostic(:, :, pageIdx) = ...
            initialHistory.deliveredDirectedEdgeHistory( ...
                :, :, sourceIdx);
    else
        selectedDiagnostic(:, :, pageIdx) = ...
            diagnostics.topologyActiveEdge( ...
                :, :, historyTime);
        deliveredDiagnostic(:, :, pageIdx) = ...
            diagnostics.delivered(:, :, historyTime);
    end
end
selected = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        selectedDiagnostic);
delivered = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        deliveredDiagnostic);
end

function summary = summarizePosteriorComplexity(posteriors)
sensorCount = numel(posteriors);
labelCount = zeros(1, sensorCount);
componentCount = zeros(1, sensorCount);
for sensorIdx = 1:sensorCount
    objects = posteriors{sensorIdx};
    labelCount(sensorIdx) = numel(objects);
    if ~isempty(objects)
        componentCount(sensorIdx) = ...
            sum([objects.numberOfGmComponents]);
    end
end
summary = struct( ...
    'meanLabelCount', mean(labelCount), ...
    'maximumLabelCount', max(labelCount), ...
    'meanComponentCount', mean(componentCount), ...
    'maximumComponentCount', max(componentCount));
end

function block = emptyBlock()
block = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behaviorAction', '', ...
    'initialLocalPosteriorBySensor', {{}}, ...
    'previousAdjacencyHistory', false(0), ...
    'previousDeliveredAdjacencyHistory', false(0), ...
    'previousAdjacencyHistoryTimes', [], ...
    'localUpdateHistoryTimes', [], ...
    'localInnovationHistory', [], ...
    'localAssociationConfidenceHistory', [], ...
    'localNisNormHistory', [], ...
    'localNisDeviationHistory', [], ...
    'restartReferenceTrace', struct(), ...
    'posteriorSummary', struct());
end

function inputs = cropInputs(inputs, maximumTime)
maximumTime = min(maximumTime, size(inputs.measurements, 2));
inputs.measurements = inputs.measurements(:, 1:maximumTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maximumTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maximumTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write graph-option behavior-source report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 graph-option behavior H=3 return source\n\n');
fprintf(fid, '- Protocol: `%s`\n', dataset.protocolId);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Seed: `%d`\n', dataset.seed);
fprintf(fid, '- Times: `%s`\n', mat2str(dataset.sourceTimes));
fprintf(fid, '- H=3 target-time union: `%s`\n', ...
    mat2str(dataset.sourceTimes(1): ...
        (dataset.sourceTimes(end) + ...
         dataset.horizonSteps - 1)));
fprintf(fid, '- Behavior action: `%s`\n', ...
    dataset.behaviorAction);
if ~isempty(dataset.behaviorModelSha256)
    fprintf(fid, '- Behavior model SHA-256: `%s`\n', ...
        dataset.behaviorModelSha256);
end
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    dataset.sourceCacheSha256);
fprintf(fid, '- Behavior seconds: `%.3f`\n', ...
    dataset.behaviorSeconds);
fprintf(fid, ['- Truth / repair / emergency / infeasible: ', ...
    '`%d / %d / %d / %d`\n\n'], ...
    dataset.behaviorTruthUseCount, ...
    dataset.behaviorRepairCount, ...
    dataset.behaviorPayloadEmergencyCount, ...
    dataset.behaviorInfeasibleCount);
fprintf(fid, '- Selected sensor / formation B3: `%d / %d`\n', ...
    all(dataset.behaviorSelectedSensorB3Pass), ...
    all(dataset.behaviorSelectedFormationB3Pass));
fprintf(fid, '- Restart reference hashes stored: `%d`\n\n', ...
    dataset.restartReferenceHashesStored);
fprintf(fid, '| Time | Mean labels | Max labels | Mean GM | Max GM |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|\n');
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    row = block.posteriorSummary;
    fprintf(fid, '| %d | %.2f | %.0f | %.2f | %.0f |\n', ...
        block.currentTime, row.meanLabelCount, ...
        row.maximumLabelCount, row.meanComponentCount, ...
        row.maximumComponentCount);
end
fprintf(fid, '\n## Boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function [adjacency, details] = selectBehaviorPolicy( ...
        context, behaviorAction, model, protocol)
switch behaviorAction
    case 'fixed-counter-clockwise'
        [adjacency, details] = ...
            selectBackboneResidualSplicedCyclePolicy( ...
                context, behaviorAction, struct( ...
                    'dominantWeight', ...
                        protocol.dominantWeight, ...
                    'residualWeight', ...
                        protocol.localResidualWeight));
    case 'label-set-message-passing-safe-fixed-e05-a70'
        [adjacency, details] = ...
            selectLabelSetMessagePassingRoutingPolicy( ...
                context, model, struct( ...
                    'protocol', protocol, ...
                    'fixedResidualWeight', ...
                        protocol.localResidualWeight));
    otherwise
        error('Unknown graph-option behavior action.');
end
end

function [sensorPass, formationPass] = ...
        computeRollingB3Pass(previousHistory, executed, groupIds)
history = logical(previousHistory);
sensorPass = false(1, size(executed, 3));
formationPass = sensorPass;
for stepIdx = 1:size(executed, 3)
    pages = cat(3, history, executed(:, :, stepIdx));
    window = any(pages(:, :, ...
        max(1, end - 2):end), 3);
    sensorPass(stepIdx) = isStronglyConnected(window);
    formationPass(stepIdx) = isStronglyConnected( ...
        collapseToFormations(window, groupIds));
    history(:, :, end + 1) = ...
        executed(:, :, stepIdx); %#ok<AGROW>
    if size(history, 3) > 2
        history = history(:, :, end-1:end);
    end
end
end

function formation = ...
        collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
formation = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formation(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formation(1:numel(groups)+1:end) = false;
end

function connected = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
connected = true;
for startNode = 1:nodeCount
    visited = false(1, nodeCount);
    visited(startNode) = true;
    while true
        next = visited | any(adjacency(visited, :), 1);
        if isequal(next, visited)
            break;
        end
        visited = next;
    end
    if ~all(visited)
        connected = false;
        return;
    end
end
end

function [model, path, sha256] = ...
        loadBehaviorModel(behaviorAction, protocol)
model = [];
path = '';
sha256 = '';
if strcmp(behaviorAction, ...
        'fixed-counter-clockwise')
    return;
end
path = protocol.messagePassingInitializationPath;
sha256 = computeFileSha256(path);
if ~strcmp(sha256, ...
        protocol.messagePassingInitializationSha256)
    error('Pinned behavior model hash mismatch.');
end
loaded = load(path, 'model');
if ~isfield(loaded, 'model')
    error('Pinned behavior model is missing.');
end
model = loaded.model;
if ~isstruct(model) || ...
        ~strcmp(model.kind, ...
            'label-set-message-passing-policy') || ...
        ~strcmp(model.contractVersion, ...
            protocol.messagePassingModelContractVersion) || ...
        model.featuresUseTruth || ...
        model.numericLabelIdentifiersUsedAsFeatures || ...
        ~model.safeProjectorRequired
    error('Pinned behavior model violates the contract.');
end
end

function action = validateBehaviorAction(action, protocol)
if isstring(action) && isscalar(action)
    action = char(action);
end
if ~ischar(action) || ...
        ~any(strcmp(action, ...
            protocol.macroActionBehaviorActions))
    error('behaviorAction must be a registered deployable behavior.');
end
end

function token = behaviorActionToken(action)
switch action
    case 'fixed-counter-clockwise'
        token = 'ccw';
    case 'label-set-message-passing-safe-fixed-e05-a70'
        token = 'learned';
    otherwise
        error('Unknown behavior action token.');
end
end

function seed = validateTrainingSeed(seed, protocol)
if ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || ...
        ~ismember(seed, protocol.trainingSeeds)
    error('seed must be a registered M24 training seed.');
end
end

function values = finiteLogical(values)
values = isfinite(values) & values ~= 0;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
