function [modelPath, result] = ...
    trainCounterfactualRegretGateV133(options)
% TRAINCOUNTERFACTUALREGRETGATEV133 Fit after both registered splits exist.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCounterfactualRegretGateV133Protocol();
spec = getCounterfactualRegretGateV133ModelSpec();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('CounterfactualRegretV133:DirtySource', ...
        'Train the official V133 model only from clean source.');
end
developmentPaths = getField(options, 'developmentShardPaths', ...
    discoverShards(protocol, 'development'));
calibrationPaths = getField(options, 'calibrationShardPaths', ...
    discoverShards(protocol, 'calibration'));
assertCompleteSplit(developmentPaths, protocol, 'development');
assertCompleteSplit(calibrationPaths, protocol, 'calibration');
development = loadCounterfactualRegretGateV133Examples( ...
    developmentPaths, 'development', protocol, spec);
calibration = loadCounterfactualRegretGateV133Examples( ...
    calibrationPaths, 'calibration', protocol, spec);
[model, summary] = fitCounterfactualRegretGateV133( ...
    development, calibration, protocol, spec);

if exist(protocol.modelRoot, 'dir') ~= 7
    mkdir(protocol.modelRoot);
end
modelPath = fullfile(protocol.modelRoot, ...
    'COUNTERFACTUAL_REGRET_GATE_V133_MODEL.mat');
reportPath = fullfile(protocol.modelRoot, ...
    'COUNTERFACTUAL_REGRET_GATE_V133_MODEL.md');
result = struct( ...
    'contractVersion', ...
        'counterfactual-regret-gate-v133-training-result-v1', ...
    'protocolId', protocol.id, ...
    'modelSpec', spec, ...
    'model', model, ...
    'summary', summary, ...
    'developmentShardPaths', {developmentPaths}, ...
    'calibrationShardPaths', {calibrationPaths}, ...
    'generationGitCommit', gitState.commit, ...
    'generationTrackedWorktreeDirty', ...
        gitState.trackedWorktreeDirty, ...
    'generationUntrackedSourceFiles', ...
        {gitState.untrackedSourceFiles}, ...
    'teacherGatePassed', summary.teacherGatePassed, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', conditional( ...
        summary.teacherGatePassed, ...
        'method-progress-only-until-unseen-tracking-gate-passes', ...
        'repository-failure-record-only'));
save('-mat7-binary', modelPath, 'result');
writeReport(reportPath, result);
result.modelPath = modelPath;
result.reportPath = reportPath;
fprintf('V133 model: %s (teacher gate %d)\n', ...
    modelPath, summary.teacherGatePassed);
end

function paths = discoverShards(protocol, split)
directory = fullfile(protocol.datasetRoot, split);
listing = dir(fullfile(directory, '**', 'V133_*.mat'));
paths = arrayfun(@(entry) fullfile(entry.folder, entry.name), ...
    listing, 'UniformOutput', false);
paths = sort(reshape(paths, 1, []));
end

function assertCompleteSplit(paths, protocol, split)
if strcmp(split, 'development')
    expectedSeeds = protocol.developmentSeeds;
else
    expectedSeeds = protocol.calibrationSeeds;
end
expectedCount = numel(protocol.scaleCases) * numel(expectedSeeds);
if numel(paths) ~= expectedCount
    error('CounterfactualRegretV133:IncompleteTrainingSplit', ...
        ['V133 %s requires exactly %d complete scale-seed shards; ', ...
         'found %d.'], split, expectedCount, numel(paths));
end
seen = cell(1, 0);
for pathIdx = 1:numel(paths)
    loaded = load(paths{pathIdx}, 'shard');
    if ~isfield(loaded, 'shard') || ...
            ~strcmp(loaded.shard.evidenceSplit, split)
        error('CounterfactualRegretV133:IncompleteTrainingSplit', ...
            'A discovered V133 shard is outside the requested split.');
    end
    seen{end + 1} = sprintf('%s-%d', ...
        loaded.shard.presetName, loaded.shard.seed); %#ok<AGROW>
end
expected = cell(1, expectedCount);
cursor = 0;
for caseInfo = protocol.scaleCases
    for seed = expectedSeeds
        cursor = cursor + 1;
        expected{cursor} = sprintf('%s-%d', ...
            caseInfo.presetName, seed);
    end
end
if ~isequal(sort(seen), sort(expected))
    error('CounterfactualRegretV133:IncompleteTrainingSplit', ...
        'V133 scale-seed shard identities are incomplete or duplicated.');
end
end

function writeReport(path, result)
fileId = fopen(path, 'w');
if fileId < 0
    error('CounterfactualRegretV133:ModelReportWriteFailed', ...
        'Could not open the V133 model report.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
summary = result.summary;
fprintf(fileId, '# V133 conservative harm gate\n\n');
fprintf(fileId, '- Teacher gate passed: `%d`\n', ...
    summary.teacherGatePassed);
fprintf(fileId, '- Shared threshold: `%.6f`\n', ...
    summary.harmProbabilityThreshold);
fprintf(fileId, '- Development examples/trajectories: `%d / %d`\n', ...
    summary.developmentExampleCount, ...
    summary.developmentTrajectoryCount);
fprintf(fileId, '- Calibration examples/trajectories: `%d / %d`\n', ...
    summary.calibrationExampleCount, ...
    summary.calibrationTrajectoryCount);
fprintf(fileId, '- Calibration harmful recall: `%.3f`\n', ...
    summary.calibration.harmfulRecall);
fprintf(fileId, '- Calibration false-safe rate: `%.3f`\n', ...
    summary.calibration.falseSafeRate);
fprintf(fileId, '- Calibration action coverage: `%.3f`\n', ...
    summary.calibration.actionCoverage);
fprintf(fileId, '- Retained oracle gain fraction: `%.3f`\n', ...
    summary.calibration.retainedOracleGainFraction);
fprintf(fileId, '\n');
if summary.teacherGatePassed
    fprintf(fileId, ['This is method progress only. It does not enter ', ...
        'the main document until unseen-seed tracking gates pass.\n']);
else
    fprintf(fileId, ['Below-gate result: repository experiment record ', ...
        'only; do not add it to the main document.\n']);
end
end

function value = conditional(condition, ifTrue, ifFalse)
if condition
    value = ifTrue;
else
    value = ifFalse;
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
