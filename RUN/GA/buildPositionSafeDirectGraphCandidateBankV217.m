function [reportPath, result] = ...
        buildPositionSafeDirectGraphCandidateBankV217(options)
% BUILDPOSITIONSAFEDIRECTGRAPHCANDIDATEBANKV217 Rebuild one causal bank.

if nargin < 1 || isempty(options)
    options = struct();
end
sourceScreenPath = char(getField(options, 'sourceScreenPath', ''));
sourceOutcomeIndex = getField(options, 'sourceOutcomeIndex', 0);
pageIndex = getField(options, 'pageIndex', 1);
topPerMode = getField(options, 'topPerMode', 3);
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v217', 'candidate_bank')));
if isempty(sourceScreenPath) || exist(sourceScreenPath, 'file') ~= 2 || ...
        ~isscalar(sourceOutcomeIndex) || ~isfinite(sourceOutcomeIndex) || ...
        sourceOutcomeIndex < 0 || sourceOutcomeIndex ~= round(sourceOutcomeIndex) || ...
        ~isscalar(pageIndex) || ~isfinite(pageIndex) || pageIndex < 1 || ...
        pageIndex ~= round(pageIndex)
    error('DirectGraphCandidateBankV217:InvalidRequest', ...
        'A captured direct-graph screen and valid page are required.');
end
loaded = load(sourceScreenPath, 'screen');
screen = loaded.screen;
protocol = getDirectGraphCreditRepairControllerV216Protocol();
if sourceOutcomeIndex == 0
    prefix = 'v216-withhold-';
    sourceOutcomeIndex = find(strncmp( ...
        {screen.records.actionName}, prefix, numel(prefix)));
end
if numel(sourceOutcomeIndex) ~= 1 || ...
        sourceOutcomeIndex < 1 || sourceOutcomeIndex > numel(screen.outcomes)
    error('DirectGraphCandidateBankV217:OutcomeIndex', ...
        'The source screen must identify one V216 withholding arm.');
end
outcome = screen.outcomes(sourceOutcomeIndex);
requiredOutcome = {'localPosteriorSnapshotsByTime', ...
    'fusedPosteriorSnapshotsByTime', ...
    'budgetRecycledFormationRepairDetailsByTime'};
if any(~isfield(outcome, requiredOutcome)) || ...
        numel(outcome.localPosteriorSnapshotsByTime) < pageIndex || ...
        numel(outcome.fusedPosteriorSnapshotsByTime) < pageIndex || ...
        isempty(outcome.localPosteriorSnapshotsByTime{pageIndex}) || ...
        isempty(outcome.fusedPosteriorSnapshotsByTime{pageIndex})
    error('DirectGraphCandidateBankV217:MissingCapture', ...
        'The source arm lacks local or ordinary-fused posterior capture.');
end
repair = outcome.budgetRecycledFormationRepairDetailsByTime{pageIndex};
if isempty(repair) || ~repair.targetFormationScoped || ...
        repair.targetFormationId < 1 || ...
        ~strcmp(repair.synopsisRecordMode, 'v216-risk-only')
    error('DirectGraphCandidateBankV217:RepairState', ...
        'The source page is not a scoped V216 causal repair state.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
currentTime = screen.returnTimes(pageIndex);
if currentTime ~= repair.currentTime || ...
        ~isequal(reshape(inputs.config.sensorGroupIds, 1, []), ...
            reshape(screen.sensorGroupIds, 1, []))
    error('DirectGraphCandidateBankV217:ScenarioDrift', ...
        'The regenerated scenario does not match the captured page.');
end
physical = logical(inputs.graphData.physicalAdjacency(:, :, currentTime));
if inputs.commConfig.forceDelivery
    delivered = physical;
else
    delivered = physical & ...
        (inputs.commConfig.linkUniforms(:, :, currentTime) >= ...
         inputs.commConfig.pDropByEdge(:, :, currentTime));
end
availableSourceAdjacency = physical & delivered';
groupIds = reshape(screen.sensorGroupIds, 1, []);
receivers = find(groupIds == repair.targetFormationId);
commonSources = find(all( ...
    availableSourceAdjacency(receivers, :), 1));
localPosteriorBySensor = reshape( ...
    outcome.localPosteriorSnapshotsByTime{pageIndex}, 1, []);
fusedPosteriorBySensor = reshape( ...
    outcome.fusedPosteriorSnapshotsByTime{pageIndex}, 1, []);
synopsisSensorIds = unique([receivers, commonSources], 'stable');
cache = buildFormationRepairLightSynopsisCacheV188( ...
    fusedPosteriorBySensor, localPosteriorBySensor, ...
    inputs.model, currentTime, struct( ...
        'localParticipatingSensorIds', synopsisSensorIds, ...
        'fusedParticipatingSensorIds', receivers, ...
        'recordMode', 'v216-risk-only'));
[fullCandidates, enumeration] = ...
    enumerateFormationCommonLabelRepairCandidatesV190( ...
        cache, availableSourceAdjacency, groupIds, struct( ...
            'receiverPresenceThreshold', ...
                protocol.candidateReceiverPresenceThreshold));
fullCandidates = fullCandidates( ...
    [fullCandidates.formationId] == repair.targetFormationId);
[positionSafeCandidates, positionProjection] = ...
    projectFormationLabelCandidatesByPositionSupportV217( ...
        fullCandidates, struct());
[shortlist, shortlistDetails] = ...
    selectModeDiversePositionSafeRepairCandidatesV217( ...
        positionSafeCandidates, struct('topPerMode', topPerMode));

proposals = repmat(emptyProposal(), 1, numel(shortlist));
payloadDetails = repmat(struct(), 1, numel(shortlist));
for candidateIdx = 1:numel(shortlist)
    [proposals(candidateIdx), payloadDetails(candidateIdx)] = ...
        resolveFormationRepairCandidatePayloadV190( ...
            shortlist(candidateIdx), localPosteriorBySensor, ...
            availableSourceAdjacency, inputs.model, struct());
end
availableCreditBytes = repair.projection.availableSpendableCreditBytes;
payloadBytes = reshape([proposals.attemptedBytes], 1, []);
creditFeasibleMask = reshape([proposals.safetyPassed], 1, []) & ...
    payloadBytes <= availableCreditBytes + 1e-12;

expectedCount = repair.proposalDetails.opportunity. ...
    commonCandidateCount(repair.targetFormationId);
if cache.totalAttemptedBytes ~= repair.lightSynopsisBytes || ...
        numel(fullCandidates) ~= expectedCount || ...
        ~isequal(synopsisSensorIds, repair.synopsisSensorIds)
    error('DirectGraphCandidateBankV217:ReconstructionDrift', ...
        'The reconstructed candidate bank differs from the live V216 page.');
end

result = struct();
result.contractVersion = ...
    'position-safe-direct-graph-candidate-bank-v217-v1';
result.generatedAt = datestr(now, 31);
result.sourceScreenPath = sourceScreenPath;
result.sourceOutcomeIndex = sourceOutcomeIndex;
result.sourceActionName = screen.records(sourceOutcomeIndex).actionName;
result.presetName = screen.presetName;
result.seed = screen.seed;
result.currentTime = currentTime;
result.targetFormationId = repair.targetFormationId;
result.receiverIds = receivers;
result.commonSourceIds = commonSources;
result.synopsisSensorIds = synopsisSensorIds;
result.lightSynopsisBytes = cache.totalAttemptedBytes;
result.candidateReceiverPresenceThreshold = ...
    protocol.candidateReceiverPresenceThreshold;
result.availableCreditBytes = availableCreditBytes;
result.fullCandidates = fullCandidates;
result.enumerationDetails = enumeration;
result.positionSafeCandidates = positionSafeCandidates;
result.positionProjection = positionProjection;
result.shortlist = shortlist;
result.shortlistDetails = shortlistDetails;
result.proposals = proposals;
result.payloadDetails = payloadDetails;
result.payloadAttemptedBytes = payloadBytes;
result.creditFeasibleMask = creditFeasibleMask;
result.creditFeasibleCandidateIndices = reshape( ...
    [shortlist(creditFeasibleMask).candidateIndex], 1, []);
result.fullCandidateCount = numel(fullCandidates);
result.positionSafeCandidateCount = numel(positionSafeCandidates);
result.shortlistedCandidateCount = numel(shortlist);
result.creditFeasibleCandidateCount = nnz(creditFeasibleMask);
result.exactLiveBankReconstructed = true;
result.modeScoresAreActionValues = false;
result.truthUsed = false;
result.futureInformationUsed = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V217 reconstructs the exact causal V216 postfusion candidate bank, ', ...
    'applies the frozen position-support guard, retains a bounded ', ...
    'mode-diverse proposal union and checks exact payload affordability. ', ...
    'It does not score tracking value or authorize online execution.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'POSITION_SAFE_DIRECT_GRAPH_CANDIDATE_BANK_V217.mat');
reportPath = fullfile(outputRoot, ...
    'POSITION_SAFE_DIRECT_GRAPH_CANDIDATE_BANK_V217.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V217 position-safe candidate bank: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('DirectGraphCandidateBankV217:WriteReport', ...
        'Could not write the V217 candidate-bank report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V217 position-safe direct-graph candidate bank\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d / F%d`\n', ...
    result.presetName, result.seed, result.currentTime, ...
    result.targetFormationId);
fprintf(fid, '- Exact live bank reconstructed: `%d`\n', ...
    result.exactLiveBankReconstructed);
fprintf(fid, '- Risk-only synopsis: `%d B`; spendable credit: `%.1f B`\n', ...
    result.lightSynopsisBytes, result.availableCreditBytes);
fprintf(fid, '- Full / position-safe / shortlisted / credit-feasible: `%d / %d / %d / %d`\n\n', ...
    result.fullCandidateCount, result.positionSafeCandidateCount, ...
    result.shortlistedCandidateCount, ...
    result.creditFeasibleCandidateCount);
fprintf(fid, '| Candidate | Source | Label | Modes | Min position compatibility | Min risk reduction | Min receiver existence | Opportunity | Payload bytes | Credit feasible |\n');
fprintf(fid, '|--:|--:|:--|:--|--:|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(result.shortlist)
    candidate = result.shortlist(idx);
    modes = result.shortlistDetails.modeNames( ...
        result.shortlistDetails.selectedByMode(idx, :));
    fprintf(fid, '| %d | %d | `[%d,%d]` | %s | %.6f | %.6g | %.6f | %.6g | %.0f | %d |\n', ...
        candidate.candidateIndex, candidate.sourceId, ...
        candidate.label(1), candidate.label(2), ...
        strjoin(modes, ', '), ...
        candidate.receiverCompatibilityMinimum, ...
        candidate.minimumRiskReduction, ...
        candidate.minimumReceiverExistence, ...
        candidate.opportunityMedian, ...
        result.payloadAttemptedBytes(idx), ...
        result.creditFeasibleMask(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function proposal = emptyProposal()
proposal = struct( ...
    'formationId', 0, 'receiverIds', zeros(1, 0), ...
    'sourceId', 0, 'label', zeros(2, 1), 'sourceObject', [], ...
    'richSynopsisBytes', 0, 'requestBytes', 0, ...
    'completeResponseBytesPerReceiver', 0, 'responseBytes', 0, ...
    'attemptedBytes', 0, 'estimatedUtilityLowerBound', 0, ...
    'rankingOpportunity', 0, 'minimumRiskReduction', 0, ...
    'minimumReceiverExistence', 0, 'peerConsensus', 0, ...
    'receiverCompatibility', 1, 'commonSourcePassed', false, ...
    'safetyPassed', false, 'rollingConnectivityPassed', false);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
