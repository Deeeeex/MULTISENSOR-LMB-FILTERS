function [reportPath, screen] = ...
    runFormationPairH3OpenedReturnScreen( ...
        presetName, seed, currentTime, options)
% RUNFORMATIONPAIRH3OPENEDRETURNSCREEN Conservative pair H=3 screen.

if nargin < 4 || isempty(options)
    options = struct();
end
if isfield(options, 'interventionBankType') && ...
        ~strcmpi(strrep(options.interventionBankType, '_', '-'), ...
            'formation-conservative-pair')
    error('Formation-pair wrapper bank type cannot be overridden.');
end
options.interventionBankType = 'formation-conservative-pair';
[reportPath, screen] = ...
    runFormationModeH3OpenedReturnScreen( ...
        presetName, seed, currentTime, options);
end
