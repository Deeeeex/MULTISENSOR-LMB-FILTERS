function [reportPath, summary] = ...
    runFormationFovMultistyleGeometryValidation(options)
% RUNFORMATIONFOVMULTISTYLEGEOMETRYVALIDATION Execute frozen v5 manifest.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationFovMultistyleGeometryValidationProtocol();
writeReport = getField(options, 'writeReport', true);
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_fov_multistyle_v5', 'held_out_geometry_validation'));
requestedCleanWorktree = getField(options, 'requireCleanWorktree', ...
    protocol.requireCleanWorktree);
if ~isequal(writeReport, true) || ...
        ~isequal(requestedCleanWorktree, true)
    error('FormationFovGeometryProtocol:UnsafeOption', [ ...
        'Formal validation requires report writing and a clean ', ...
        'worktree; these safeguards cannot be disabled.']);
end

sourceRoot = resolveFormalSourceRoot();
gitState = resolveResearchGitState(sourceRoot);
verifyFormalSourceResolution(gitState.repositoryRoot);
if gitState.researchWorktreeDirty
    error('FormationFovGeometryProtocol:DirtyWorktree', [ ...
        'Held-out geometry validation requires a clean tracked ', ...
        'worktree with no untracked MATLAB source files.']);
end
verifyRegisteredScenes(protocol);

presetNames = {protocol.presets.presetName};
try
    [~, rawAudit] = runDynamicTopologyScenarioDifficultyAudit( ...
        presetNames, protocol.validationSeeds, struct( ...
            'writeReport', false, 'collectInvalidRecords', true));
    evaluation = evaluateFormationFovMultistyleGeometryValidation( ...
        rawAudit, protocol);
    verifyRegisteredScenes(protocol);
    postGitState = resolveResearchGitState(sourceRoot);
    verifyFormalSourceResolution(postGitState.repositoryRoot);
    if postGitState.researchWorktreeDirty || ...
            ~strcmp(postGitState.commit, gitState.commit) || ...
            ~strcmp(postGitState.repositoryRoot, gitState.repositoryRoot)
        error('FormationFovGeometryProtocol:SourceDrift', [ ...
            'The source commit or worktree changed during held-out ', ...
            'geometry validation.']);
    end
catch errorInfo
    failureReportPath = writeExecutionFailureReport( ...
        outputDirectory, protocol, gitState, errorInfo);
    fprintf('Execution failure report: %s\n', failureReportPath);
    rethrow(errorInfo);
end

summary = struct();
summary.contractVersion = ...
    'formation-fov-multistyle-held-out-geometry-result-v1';
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.generationGitRepositoryRoot = gitState.repositoryRoot;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.postRunGitCommit = postGitState.commit;
summary.postRunTrackedWorktreeDirty = ...
    postGitState.trackedWorktreeDirty;
summary.postRunUntrackedSourceFiles = ...
    postGitState.untrackedSourceFiles;
summary.protocol = protocol;
summary.rawAudit = rawAudit;
summary.evaluation = evaluation;
summary.geometryValidationPassed = evaluation.gatePassed;
summary.trackingOutcomeAuthorized = false;
summary.evidenceBoundary = protocol.evidenceBoundary;

reportPath = '';
if writeReport
    try
        if exist(outputDirectory, 'dir') ~= 7
            mkdir(outputDirectory);
        end
        timestamp = datestr(now, 'yyyymmdd_HHMMSS');
        reportPath = fullfile(outputDirectory, [ ...
            'FORMATION_FOV_MULTISTYLE_GEOMETRY_VALIDATION_', ...
            timestamp, '.md']);
        matPath = strrep(reportPath, '.md', '.mat');
        summary.reportPath = reportPath;
        summary.matPath = matPath;
        writeValidationReport(reportPath, summary);
        save(matPath, 'summary');
        fprintf('Report: %s\n', reportPath);
    catch errorInfo
        failureReportPath = writeExecutionFailureReport( ...
            outputDirectory, protocol, gitState, errorInfo);
        fprintf('Execution failure report: %s\n', failureReportPath);
        rethrow(errorInfo);
    end
end

if ~evaluation.gatePassed
    error('FormationFovGeometryProtocol:GateFailed', [ ...
        'The frozen v5 held-out geometry gate failed. ', ...
        'Tracking remains unauthorized.']);
end
fprintf('FORMATION_FOV_MULTISTYLE_GEOMETRY_VALIDATION_PASSED=1\n');
end

function verifyRegisteredScenes(protocol)
for presetIdx = 1:numel(protocol.presets)
    expected = protocol.presets(presetIdx);
    config = buildDynamicTopologyScenarioConfig(expected.presetName);
    if ~strcmp(config.sceneGeometryVersion, ...
            protocol.sceneGeometryVersion) || ...
            config.numberOfSensors ~= expected.sensorCount || ...
            config.formationCount ~= expected.formationCount || ...
            config.sensorsPerFormation ~= expected.sensorsPerFormation || ...
            config.numberOfTargets ~= expected.targetCount || ...
            ~strcmp(config.sceneStyle, expected.styleName) || ...
            ~strcmp(config.sceneContractSha256, ...
                expected.sceneContractSha256) || ...
            ~isequal(config.formalValidationAuthorized, true) || ...
            ~isequal(config.trackingOutcomeAuthorized, false) || ...
            ~isequal(config.enforceDifficultyRequirements, true)
        error('FormationFovGeometryProtocol:SceneMismatch', ...
            'Registered held-out scene changed: %s.', ...
            expected.presetName);
    end
end
end

function writeValidationReport(path, summary)
fileId = fopen(path, 'w');
if fileId < 0
    error('Unable to write held-out geometry report: %s.', path);
end

cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
protocol = summary.protocol;
evaluation = summary.evaluation;
fprintf(fileId, '# Formation-FoV multistyle held-out geometry validation\n\n');
fprintf(fileId, '- Git commit: `%s`\n', summary.generationGitCommit);
fprintf(fileId, '- Git repository root: `%s`\n', ...
    summary.generationGitRepositoryRoot);
fprintf(fileId, '- Protocol SHA-256: `%s`\n', ...
    protocol.canonicalSha256);
fprintf(fileId, '- Scene version: `%s`\n', ...
    protocol.sceneGeometryVersion);
fprintf(fileId, '- Seeds: `%s`\n', mat2str(protocol.validationSeeds));
fprintf(fileId, '- Absolute gates all passed: `%d`\n', ...
    evaluation.allAbsolutePass);
fprintf(fileId, '- Cross-scale gates all passed: `%d`\n', ...
    evaluation.allCrossScalePass);
fprintf(fileId, '- Geometry validation passed: `%d`\n', ...
    evaluation.gatePassed);
fprintf(fileId, '- Tracking outcome authorized: `0`\n\n');

fprintf(fileId, '## Absolute realization gates\n\n');
fprintf(fileId, ['| Preset | Seed | Blackout | Focus | Worst target | ', ...
    'Longest | Single | Multi | Load | Norm. handovers | Ownership | ', ...
    'Blockage | Close | Target sep. | Sensor-target sep. | ', ...
    'Structural failures | Pass | Gate failures |\n']);
fprintf(fileId, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|--:|--:|:--|:--:|:--|\n']);
for row = evaluation.absoluteRows
    record = row.record;
    fprintf(fileId, ['| %s | %d | %.4f | %.4f | %.4f | %d | ', ...
        '%.4f | %.4f | %.4f | %.4f | %.4f | %.4f | %.4f | ', ...
        '%.2f | %.2f | %s | %d | %s |\n'], ...
        row.presetName, row.seed, record.blackoutFraction, ...
        record.focusBlackoutFraction, ...
        record.maximumPerTargetBlackoutFraction, ...
        record.maximumConsecutiveBlackoutSteps, ...
        record.singleFormationFraction, record.multiFormationFraction, ...
        record.focusMeanVisibleTargetsPerSensorTime, ...
        row.normalizedHandovers, record.ownershipEntropy, ...
        record.blockageFocusOverlapFraction, ...
        record.focusCloseEncounterFraction, ...
        record.minimumTargetSeparation, ...
        record.minimumSensorTargetSeparation, ...
        joinTokens(record.hardFailures), row.gatePassed, ...
        joinTokens(row.failureTokens));
end

fprintf(fileId, '\n## Paired M24/X36 gates\n\n');
fprintf(fileId, ['| Style | Seed | Blackout diff. | Focus diff. | ', ...
    'Worst-target diff. | Longest diff. | Single diff. | Multi diff. | ', ...
    'Load ratio | Handover diff. | Entropy diff. | Blockage diff. | ', ...
    'Pass | Failures |\n']);
fprintf(fileId, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|:--:|:--|\n']);
for row = evaluation.pairedRows
    fprintf(fileId, ['| %s | %d | %.4f | %.4f | %.4f | %d | ', ...
        '%.4f | %.4f | %.4f | %.4f | %.4f | %.4f | %d | %s |\n'], ...
        row.styleName, row.seed, row.blackoutDifference, ...
        row.focusBlackoutDifference, ...
        row.worstTargetBlackoutDifference, ...
        row.longestBlackoutStepDifference, ...
        row.singleFormationDifference, row.multiFormationDifference, ...
        row.focusLoadRatio, ...
        row.normalizedHandoverDifference, ...
        row.ownershipEntropyDifference, row.blockageOverlapDifference, ...
        row.gatePassed, ...
        joinTokens(row.failureTokens));
end

fprintf(fileId, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function path = writeExecutionFailureReport( ...
        outputDirectory, protocol, gitState, errorInfo)
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
timestamp = datestr(now, 'yyyymmdd_HHMMSS');
path = fullfile(outputDirectory, [ ...
    'FORMATION_FOV_MULTISTYLE_GEOMETRY_EXECUTION_FAILURE_', ...
    timestamp, '.md']);
fileId = fopen(path, 'w');
if fileId < 0
    error('Unable to write held-out execution failure report: %s.', path);
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '# Formation-FoV geometry validation execution failure\n\n');
fprintf(fileId, '- Git commit: `%s`\n', gitState.commit);
fprintf(fileId, '- Git repository root: `%s`\n', gitState.repositoryRoot);
fprintf(fileId, '- Protocol SHA-256: `%s`\n', protocol.canonicalSha256);
fprintf(fileId, '- Error identifier: `%s`\n', errorInfo.identifier);
fprintf(fileId, '- Geometry validation passed: `0`\n');
fprintf(fileId, '- Tracking outcome authorized: `0`\n\n');
fprintf(fileId, '## Error\n\n```text\n%s\n```\n\n', errorInfo.message);
fprintf(fileId, '## Decision boundary\n\n');
fprintf(fileId, ['The formal manifest did not complete. No geometry or ', ...
    'tracking claim is authorized. Because execution may have opened a ', ...
    'prefix of the held-out manifest, any source or gate repair requires ', ...
    'a new protocol version and a new unopened seed manifest.\n']);
end

function value = joinTokens(tokens)
if isempty(tokens)
    value = '--';
else
    value = strjoin(tokens, ', ');
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function sourceRoot = resolveFormalSourceRoot()
runnerDirectory = fileparts(mfilename('fullpath'));
sourceRoot = fileparts(fileparts(runnerDirectory));
if exist(fullfile(sourceRoot, '.git'), 'file') ~= 2 && ...
        exist(fullfile(sourceRoot, '.git'), 'dir') ~= 7
    error('FormationFovGeometryProtocol:SourceRootMismatch', ...
        'The formal validator is not loaded from a Git worktree.');
end
end

function verifyFormalSourceResolution(sourceRoot)
if ~ischar(sourceRoot) || exist(sourceRoot, 'dir') ~= 7
    error('FormationFovGeometryProtocol:SourceRootMismatch', ...
        'The formal source repository root is unavailable.');
end
originalDirectory = pwd;
cleanup = onCleanup(@() cd(originalDirectory)); %#ok<NASGU>
cd(sourceRoot);
[status, trackedOutput] = system('git ls-files');
if status ~= 0
    error('FormationFovGeometryProtocol:SourceRootMismatch', ...
        'Unable to enumerate tracked formal source files.');
end
trackedOutput = strtrim(trackedOutput);
if isempty(trackedOutput)
    trackedFiles = {};
else
    trackedFiles = regexp(trackedOutput, '\r?\n', 'split');
end
criticalFunctions = { ...
    'runFormationFovMultistyleGeometryValidation', ...
    'resolveResearchGitState', ...
    'computeCanonicalValueSha256', ...
    'getFormationFovMultistyleGeometryValidationProtocol', ...
    'evaluateFormationFovMultistyleGeometryValidation', ...
    'runDynamicTopologyScenarioDifficultyAudit', ...
    'validateDynamicTopologyScenario', ...
    'buildDynamicTopologyScenarioConfig', ...
    'applyFormationFovSceneStyle', ...
    'getFormationFovMultistyleAbsoluteGeometryGate', ...
    'getFormationFovMultistyleAbsoluteDifficultyRequirements', ...
    'computeFormationFovMultistyleSceneContractSha256', ...
    'getExpectedFormationFovMultistyleSceneContractSha256', ...
    'generateMultiFormationTrajectories', ...
    'generateCorridorTargetTrajectories', ...
    'buildDynamicTopologyGraphs', ...
    'measureDynamicTopologyScenarioDifficulty', ...
    'buildSensorFovHeadingSchedule', ...
    'evaluateSensorQuality', ...
    'resolveDynamicTopologyBlockageWindows'};
rootPrefix = [sourceRoot, filesep];
for functionIdx = 1:numel(criticalFunctions)
    resolvedPath = which(criticalFunctions{functionIdx});
    if isempty(resolvedPath) || ...
            length(resolvedPath) <= length(rootPrefix) || ...
            ~strcmp(resolvedPath(1:length(rootPrefix)), rootPrefix)
        error('FormationFovGeometryProtocol:SourceResolutionMismatch', ...
            'Formal function resolved outside the source worktree: %s.', ...
            criticalFunctions{functionIdx});
    end
    relativePath = strrep(resolvedPath(length(rootPrefix)+1:end), ...
        filesep, '/');
    if ~any(strcmp(trackedFiles, relativePath))
        error('FormationFovGeometryProtocol:UntrackedSource', ...
            'Formal function is not tracked by Git: %s.', relativePath);
    end
end
end
