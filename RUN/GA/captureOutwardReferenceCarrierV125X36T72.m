function [screenPath, screen] = ...
        captureOutwardReferenceCarrierV125X36T72(options)
% CAPTUREOUTWARDREFERENCECARRIERV125X36T72 Capture paired CW sender states.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getOutwardReferenceCarrierV125Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('OutwardReferenceCarrierV125:DirtySource', ...
        'The V125 reference capture requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', 'v113-influence-cone-carrier', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', 'influence-cone-carrier-v113', ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', [1, 2], ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', protocol.referenceOutcomeScreenPath, ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'outputDirectory', getField(options, 'outputDirectory', ...
        protocol.referenceCarrierCaptureDirectory), ...
    'writeReport', true);
[~, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, 72, screenOptions);
screenPath = screen.matPath;
idx = find(strcmp({screen.records.actionName}, ...
    protocol.referenceCarrierSourceActionName), 1);
if isempty(idx) || ...
        numel(screen.outcomes(idx).localPosteriorSnapshotsByTime) ~= ...
            protocol.horizonSteps
    error('OutwardReferenceCarrierV125:CaptureFailed', ...
        'The paired clockwise arm did not capture all sender states.');
end
fprintf('V125 paired clockwise carrier capture: %s\n', screenPath);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
