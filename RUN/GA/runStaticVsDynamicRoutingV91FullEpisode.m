function [reportPath, result] = ...
    runStaticVsDynamicRoutingV91FullEpisode(options)
% RUNSTATICVSDYNAMICROUTINGV91FULLEPISODE Matched baseline outcome.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getStaticVsDynamicRoutingV91Protocol();
sourceProtocol = getRepeatedMultiGatewayHandoverV89Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('StaticVsDynamicV91:DirtySource', ...
        'The V91 paired outcome requires clean frozen source.');
end
presetNames = normalizeSelection(getField( ...
    options, 'presetNames', protocol.presets), protocol.presets);
resume = logical(getField(options, 'resume', true));

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'STATIC_VS_DYNAMIC_ROUTING_V91_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'STATIC_VS_DYNAMIC_ROUTING_V91_FULL_EPISODE.md');
result = initializeResult(protocol, gitState.commit, matPath, reportPath);
if resume && exist(matPath, 'file') == 2
    loaded = load(matPath, 'result');
    if ~isfield(loaded, 'result') || ...
            ~strcmp(loaded.result.contractVersion, ...
                result.contractVersion) || ...
            ~strcmp(loaded.result.generationGitCommit, gitState.commit)
        error('StaticVsDynamicV91:InvalidResumeState', ...
            'The V91 checkpoint belongs to another source contract.');
    end
    result = loaded.result;
end

for presetIdx = 1:numel(presetNames)
    presetName = presetNames{presetIdx};
    recordIdx = findRecord(result.records, presetName);
    if isempty(recordIdx)
        record = emptyRecord();
        record.presetName = presetName;
        record.seed = protocol.allSeeds;
        result.records(end + 1) = record; %#ok<AGROW>
        recordIdx = numel(result.records);
    end
    if result.records(recordIdx).complete
        fprintf('V91 resume: %s already complete.\n', presetName);
        continue;
    end

    registryIdx = find(strcmp(presetName, protocol.presets), 1);
    seed = protocol.allSeeds;
    fprintf('\nV91 static-vs-dynamic: %s seed %d\n', ...
        presetName, seed);
    inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
    if inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCounts(registryIdx) || ...
            inputs.config.formationCount ~= ...
                protocol.expectedFormationCounts(registryIdx)
        error('StaticVsDynamicV91:ScenarioScaleDrift', ...
            'The generated V91 scene changed its registered scale.');
    end
    preflight = preflightStaticVsDynamicRoutingV91(inputs);
    fprintf(['  route preflight: static unique=%d, dynamic unique=%d, ', ...
        'messages/round=%d, identical=%d\n'], ...
        preflight.staticUniqueTopologyCount, ...
        preflight.dynamicUniqueTopologyCount, ...
        preflight.messageCountPerRound, ...
        preflight.dynamicEquivalentToFrozenStatic);

    identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
    deliverySeed = protocol.deliverySeedOffset + ...
        100 * seed + registryIdx;
    [inputs.commConfig.linkUniforms, ~] = ...
        materializePhysicalUidDirectedDeliveryUniforms( ...
            deliverySeed, identity.sensorPhysicalUids, ...
            inputs.config.simulationLength);
    filterSeed = protocol.filterSeedOffset + 100 * seed + registryIdx;
    filterModel = removeRealizedTargetTruth(inputs.model);
    representatives = selectFormationRepresentatives( ...
        inputs.config.sensorGroupIds);
    result.records(recordIdx).numberOfSensors = ...
        inputs.config.numberOfSensors;
    result.records(recordIdx).formationCount = ...
        inputs.config.formationCount;
    result.records(recordIdx).simulationLength = ...
        inputs.config.simulationLength;
    result.records(recordIdx).deliverySeed = deliverySeed;
    result.records(recordIdx).filterSeed = filterSeed;
    result.records(recordIdx).preflight = preflight;

    armIds = {protocol.dynamicArmId, protocol.staticArmId};
    armFields = {'dynamic', 'static'};
    for armIdx = 1:2
        armField = armFields{armIdx};
        if ~isempty(fieldnames(result.records(recordIdx).(armField)))
            fprintf('  V91 resume: %s arm already complete.\n', armField);
            continue;
        end
        armId = armIds{armIdx};
        config = buildStaticVsDynamicRoutingV91TriggerConfig( ...
            armId, inputs.config.numberOfSensors);
        context = buildStaticVsDynamicRoutingV91ExecutionContext( ...
            presetName, seed, armId, inputs.config.simulationLength);
        rng(filterSeed, 'twister');
        armTimer = tic;
        fprintf('  running %s ...\n', armId);
        [estimates, diagnostics] = ...
            runEventTriggeredDistributedLmbFilter( ...
                filterModel, inputs.measurements, ...
                inputs.sensorTrajectories, inputs.neighborMap, ...
                inputs.commConfig, config, context);
        arm = summarizeRepeatedMultiGatewayFullEpisodeArm( ...
            armId, estimates, diagnostics, inputs.groundTruthRfs, ...
            inputs.config, representatives, sourceProtocol, toc(armTimer));
        arm = attachTopologySummary(arm, diagnostics);
        result.records(recordIdx).(armField) = arm;
        result.completedAt = datestr(now, 31);
        save('-mat7-binary', matPath, 'result');
        writeReport(reportPath, result);
        fprintf(['    E-OSPA full %.3f focus %.3f; unique routes %d; ', ...
            '%.1f s\n'], ...
            arm.fullHorizonPositionEospa, ...
            arm.focusWindowPositionEospa, ...
            arm.uniqueTopologyCount, arm.elapsedSeconds);
        clear estimates diagnostics arm;
    end

    dynamic = result.records(recordIdx).dynamic;
    static = result.records(recordIdx).static;
    assertMatchedExecution(dynamic, static, preflight);
    result.records(recordIdx).comparison = ...
        compareDynamicOverStatic(dynamic, static, protocol);
    result.records(recordIdx).complete = true;
    comparison = result.records(recordIdx).comparison;
    fprintf(['  dynamic over static: full %+.3f%% focus %+.3f%% ', ...
        'worst %+.3f%% formation %+.3f%% consensus %+.3f%% ', ...
        'notable=%d\n'], ...
        comparison.fullHorizonGainPercent, ...
        comparison.focusWindowGainPercent, ...
        comparison.worstSensorGainPercent, ...
        comparison.minimumFormationGainPercent, ...
        comparison.focusConsensusGainPercent, ...
        comparison.notableGainPassed);
    result.completedAt = datestr(now, 31);
    result.allRequestedRecordsComplete = all([result.records.complete]);
    save('-mat7-binary', matPath, 'result');
    writeReport(reportPath, result);
    clear inputs filterModel;
end
result.completedAt = datestr(now, 31);
result.allRequestedRecordsComplete = all([result.records.complete]);
result.bothScalesNotableGainPassed = ...
    bothScalesPass(result.records, protocol);
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('\nV91 result: %s\n', reportPath);
end

function arm = attachTopologySummary(arm, diagnostics)
pages = logical(diagnostics.topologyActiveEdge);
arm.uniqueTopologyCount = uniquePageCount(pages);
arm.topologyChangeCount = pageChangeCount(pages);
arm.routeMessageCountByTime = pageCounts(pages);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
end

function assertMatchedExecution(dynamic, static, preflight)
if ~preflight.messageParityPassed || ...
        dynamic.routeMessageCountMinimum ~= ...
            preflight.messageCountPerRound || ...
        dynamic.routeMessageCountMaximum ~= ...
            preflight.messageCountPerRound || ...
        static.routeMessageCountMinimum ~= ...
            preflight.messageCountPerRound || ...
        static.routeMessageCountMaximum ~= ...
            preflight.messageCountPerRound || ...
        static.uniqueTopologyCount ~= 1 || ...
        static.topologyChangeCount ~= 0
    error('StaticVsDynamicV91:RuntimeParityFailed', ...
        'The executed V91 arms violated the matched routing contract.');
end
end

function comparison = compareDynamicOverStatic(dynamic, static, protocol)
comparison = struct();
comparison.fullHorizonGainPercent = lowerGain( ...
    static.fullHorizonPositionEospa, dynamic.fullHorizonPositionEospa);
comparison.focusWindowGainPercent = lowerGain( ...
    static.focusWindowPositionEospa, dynamic.focusWindowPositionEospa);
comparison.worstSensorGainPercent = lowerGain( ...
    static.worstSensorPositionEospa, dynamic.worstSensorPositionEospa);
comparison.minimumFormationGainPercent = min(100 * ( ...
    static.perFormationPositionEospa - ...
        dynamic.perFormationPositionEospa) ./ ...
            max(static.perFormationPositionEospa, eps));
comparison.focusConsensusGainPercent = lowerGain( ...
    static.focusInterFormationPositionOspa, ...
    dynamic.focusInterFormationPositionOspa);
comparison.cardinalityGainPercent = lowerGain( ...
    static.meanAbsoluteCardinalityError, ...
    dynamic.meanAbsoluteCardinalityError);
comparison.attemptedByteSavingPercent = lowerGain( ...
    static.attemptedPayloadBytes, dynamic.attemptedPayloadBytes);
comparison.deliveredByteSavingPercent = lowerGain( ...
    static.deliveredPayloadBytes, dynamic.deliveredPayloadBytes);
comparison.notableGainPassed = ...
    comparison.fullHorizonGainPercent >= ...
        protocol.minimumNotableFullGainPercent && ...
    comparison.focusWindowGainPercent >= ...
        protocol.minimumNotableFocusGainPercent && ...
    comparison.worstSensorGainPercent >= 0 && ...
    comparison.minimumFormationGainPercent >= 0;
end

function value = lowerGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function count = uniquePageCount(pages)
flat = reshape(logical(pages), [], size(pages, 3))';
count = size(unique(flat, 'rows'), 1);
end

function count = pageChangeCount(pages)
count = 0;
for timeIdx = 2:size(pages, 3)
    count = count + ~isequal( ...
        pages(:, :, timeIdx), pages(:, :, timeIdx - 1));
end
end

function counts = pageCounts(pages)
counts = zeros(1, size(pages, 3));
for timeIdx = 1:size(pages, 3)
    counts(timeIdx) = nnz(pages(:, :, timeIdx));
end
end

function result = initializeResult(protocol, commit, matPath, reportPath)
result = struct();
result.contractVersion = ...
    'static-vs-dynamic-routing-v91-full-episode-result-v1';
result.protocol = protocol;
result.startedAt = datestr(now, 31);
result.completedAt = '';
result.generationGitCommit = commit;
result.records = repmat(emptyRecord(), 1, 0);
result.allRequestedRecordsComplete = false;
result.bothScalesNotableGainPassed = false;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.matPath = matPath;
result.reportPath = reportPath;
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'numberOfSensors', NaN, ...
    'formationCount', NaN, ...
    'simulationLength', NaN, ...
    'deliverySeed', NaN, ...
    'filterSeed', NaN, ...
    'preflight', struct(), ...
    'dynamic', struct(), ...
    'static', struct(), ...
    'comparison', struct(), ...
    'complete', false);
end

function idx = findRecord(records, presetName)
idx = [];
if ~isempty(records)
    idx = find(strcmp({records.presetName}, presetName), 1);
end
end

function passed = bothScalesPass(records, protocol)
passed = true;
for presetIdx = 1:numel(protocol.presets)
    idx = findRecord(records, protocol.presets{presetIdx});
    passed = passed && ~isempty(idx) && records(idx).complete && ...
        records(idx).comparison.notableGainPassed;
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('StaticVsDynamicV91:ReportWriteFailed', ...
        'Could not create the V91 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V91 static versus dynamic routing result\n\n');
fprintf(fid, ['Positive percentages mean that the current-physical ', ...
    'dynamic route is better than the fixed all-time-physical route.\n\n']);
fprintf(fid, ['| Scale | Static E-OSPA | Dynamic E-OSPA | Full gain | ', ...
    'Focus gain | Worst gain | Min formation | Consensus | ', ...
    'Static routes | Dynamic routes | Notable |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for record = result.records
    if ~record.complete
        continue;
    end
    gain = record.comparison;
    fprintf(fid, ['| %s | %.3f | %.3f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %d | %d | %d |\n'], ...
        record.presetName, ...
        record.static.fullHorizonPositionEospa, ...
        record.dynamic.fullHorizonPositionEospa, ...
        gain.fullHorizonGainPercent, gain.focusWindowGainPercent, ...
        gain.worstSensorGainPercent, ...
        gain.minimumFormationGainPercent, ...
        gain.focusConsensusGainPercent, ...
        record.static.uniqueTopologyCount, ...
        record.dynamic.uniqueTopologyCount, ...
        gain.notableGainPassed);
end
fprintf(fid, '\n- All requested records complete: `%d`\n', ...
    result.allRequestedRecordsComplete);
fprintf(fid, '- Both scales pass the notable-gain gate: `%d`\n', ...
    result.bothScalesNotableGainPassed);
fprintf(fid, '- Validation claim allowed: `0`\n');
fprintf(fid, '\n## Matched comparison boundary\n\n%s\n', ...
    result.protocol.evidenceBoundary);
end

function values = normalizeSelection(values, allowed)
if ischar(values)
    values = {values};
end
if ~iscell(values) || isempty(values) || ...
        any(~cellfun(@(value) any(strcmp(value, allowed)), values))
    error('StaticVsDynamicV91:InvalidPresetSelection', ...
        'Only the frozen M24/X36 braided-handover scenes are allowed.');
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function result = isAbsolutePath(pathValue)
if ispc
    result = ~isempty(regexp(pathValue, '^[A-Za-z]:[\\/]', 'once'));
else
    result = ~isempty(pathValue) && pathValue(1) == filesep;
end
end
