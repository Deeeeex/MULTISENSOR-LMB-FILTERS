function [summary, reportPath] = ...
    summarizeFormationB4V46FiniteEpisodeWeakMixing(matPath, reportPath)
% SUMMARIZEFORMATIONB4V46FINITEEPISODEWEAKMIXING Audit and report a run.

if nargin < 1 || isempty(matPath)
    repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    matPath = fullfile(repoRoot, 'RUN', 'GA', 'dynamic_topology', ...
        'evidence', 'formation_value_v46', ...
        'finite_episode_weak_mixing_f0643b1', ...
        'FORMATION_B4_V46_FINITE_EPISODE_WEAK_MIXING_FULL32.mat');
end
if nargin < 2 || isempty(reportPath)
    [directory, name] = fileparts(matPath);
    reportPath = fullfile(directory, [name, '.md']);
end
if exist(matPath, 'file') ~= 2 || exist(reportPath, 'file') ~= 0
    error('FormationB4V46MixingSummary:PathContract', ...
        'The input must exist and the report path must be new.');
end
loaded = load(matPath);
if ~isfield(loaded, 'result') || ~isfield(loaded, 'runMetadata')
    error('FormationB4V46MixingSummary:MalformedArtifact', ...
        'The finite-episode artifact envelope is malformed.');
end
result = loaded.result;
runMetadata = loaded.runMetadata;
validateArtifact(result, runMetadata);

horizonRows = buildHorizonRows(result);
caseRows = buildCaseRows(result);
universalIdx = find([horizonRows.everyCaseFullPositiveSupport], 1);
universalHorizon = NaN;
if ~isempty(universalIdx)
    universalHorizon = horizonRows(universalIdx).horizon;
end
m24Horizon = scaleUniversalHorizon(result, 24);
x36Horizon = scaleUniversalHorizon(result, 36);

payload = struct();
payload.contractVersion = ...
    'formation-b4-v46-finite-episode-weak-mixing-summary-v1';
payload.sourceMatPath = matPath;
payload.sourceMatRawSha256 = computeFileSha256(matPath);
payload.resultCanonicalSha256 = result.canonicalSha256;
payload.runMetadata = runMetadata;
payload.caseCount = result.caseCount;
payload.horizons = result.horizons;
payload.horizonRows = horizonRows;
payload.caseRows = caseRows;
payload.universalAuditedFullPositiveSupportHorizon = ...
    universalHorizon;
payload.m24UniversalAuditedFullPositiveSupportHorizon = m24Horizon;
payload.x36UniversalAuditedFullPositiveSupportHorizon = x36Horizon;
payload.biasAudit = buildBiasAudit( ...
    horizonRows, caseRows, universalIdx);
payload.finiteEpisodeWeakMixingCertificatePassed = ...
    result.finiteEpisodeWeakMixingCertificatePassed;
payload.infiniteHorizonConvergenceCertified = ...
    result.infiniteHorizonConvergenceCertified;
payload.uniformAverageConsensusCertified = ...
    result.uniformAverageConsensusCertified;
payload.trackingOutcomeScored = result.trackingOutcomeScored;
payload.validationClaimAllowed = result.validationClaimAllowed;
summary = payload;
summary.canonicalSha256 = computeCanonicalValueSha256(payload);
writeReport(reportPath, summary);
fprintf('V46 finite-episode summary: %s\n', reportPath);
end

function audit = buildBiasAudit(horizonRows, caseRows, universalIdx)
if isempty(universalIdx)
    error('FormationB4V46MixingSummary:UniversalHorizonMissing', ...
        'The full registry has no universal full-positive horizon.');
end
universal = horizonRows(universalIdx);
m24 = caseRows([caseRows.nodeCount] == 24);
x36 = caseRows([caseRows.nodeCount] == 36);
audit = struct();
audit.uniformAverageTarget = 'J=ones(N)/N';
audit.universalHorizon = universal.horizon;
audit.universalWorstDistanceToUniformAveraging = ...
    universal.worstDistanceToUniformAveraging;
audit.universalWorstMaximumColumnSumError = ...
    universal.worstMaximumColumnSumError;
audit.universalWorstInfluenceWeightL1Imbalance = ...
    universal.worstInfluenceWeightL1Imbalance;
audit.m24TheoremWorstDistanceToUniformAveraging = max( ...
    [m24.theoremWorstDistanceToUniformAveraging]);
audit.m24TheoremWorstMaximumColumnSumError = max( ...
    [m24.theoremWorstMaximumColumnSumError]);
audit.m24TheoremWorstInfluenceWeightL1Imbalance = max( ...
    [m24.theoremWorstInfluenceWeightL1Imbalance]);
audit.x36TheoremWorstDistanceToUniformAveraging = max( ...
    [x36.theoremWorstDistanceToUniformAveraging]);
audit.x36TheoremWorstMaximumColumnSumError = max( ...
    [x36.theoremWorstMaximumColumnSumError]);
audit.x36TheoremWorstInfluenceWeightL1Imbalance = max( ...
    [x36.theoremWorstInfluenceWeightL1Imbalance]);
audit.uniformAverageConsensusCertified = false;
audit.trackingNoninferiorityMustBeTestedSeparately = true;
audit.canonicalSha256 = computeCanonicalValueSha256(audit);
end

function validateArtifact(result, metadata)
requiredResult = {'contractVersion', 'canonicalSha256', 'cases', ...
    'caseCount', 'horizons', 'fullRegistryRequested', ...
    'allCasesFullHorizonCovered', 'allParentPageHashesMatched', ...
    'everyRollingB4UnionStrong', ...
    'finiteEpisodeWeakMixingCertificatePassed', ...
    'infiniteHorizonConvergenceCertified', ...
    'uniformAverageConsensusCertified', 'trackingOutcomeScored', ...
    'validationClaimAllowed'};
requiredMetadata = {'contractVersion', 'generationGitCommit', ...
    'generationGitClean', 'caseCount', 'resultCanonicalSha256'};
if ~isstruct(result) || ~isscalar(result) || ...
        ~all(isfield(result, requiredResult)) || ...
        ~isstruct(metadata) || ~isscalar(metadata) || ...
        ~all(isfield(metadata, requiredMetadata)) || ...
        ~strcmp(result.contractVersion, ...
            ['formation-b4-v46-finite-episode-weak-mixing-', ...
             'audit-development-v2']) || ...
        ~strcmp(computeCanonicalValueSha256( ...
            rmfield(result, 'canonicalSha256')), ...
            result.canonicalSha256) || ...
        ~strcmp(metadata.resultCanonicalSha256, result.canonicalSha256) || ...
        metadata.caseCount ~= result.caseCount || ...
        ~metadata.generationGitClean || ...
        result.caseCount ~= numel(result.cases) || ...
        ~result.fullRegistryRequested || ...
        ~result.allCasesFullHorizonCovered || ...
        ~result.allParentPageHashesMatched || ...
        ~result.everyRollingB4UnionStrong || ...
        result.trackingOutcomeScored || result.validationClaimAllowed || ...
        result.infiniteHorizonConvergenceCertified || ...
        result.uniformAverageConsensusCertified
    error('FormationB4V46MixingSummary:ArtifactDrift', ...
        'The finite-episode artifact failed its self-audit.');
end
end

function rows = buildHorizonRows(result)
rows = repmat(emptyHorizonRow(), 1, numel(result.horizons));
for horizonIdx = 1:numel(result.horizons)
    row = emptyHorizonRow();
    row.horizon = result.horizons(horizonIdx);
    row.caseCount = result.caseCount;
    for caseIdx = 1:result.caseCount
        item = result.cases(caseIdx).horizonSummaries(horizonIdx);
        row.windowCount = row.windowCount + item.windowCount;
        row.supportScramblingWindowCount = ...
            row.supportScramblingWindowCount + ...
            item.supportScramblingWindowCount;
        row.positiveColumnWindowCount = ...
            row.positiveColumnWindowCount + ...
            item.positiveColumnWindowCount;
        row.fullPositiveSupportWindowCount = ...
            row.fullPositiveSupportWindowCount + ...
            item.fullPositiveSupportWindowCount;
        row.saturatedNumericalDobrushinWindowCount = ...
            row.saturatedNumericalDobrushinWindowCount + ...
            item.saturatedNumericalDobrushinWindowCount;
        row.caseEverySupportScramblingCount = ...
            row.caseEverySupportScramblingCount + ...
            item.everyProductSupportScrambling;
        row.caseEveryPositiveColumnCount = ...
            row.caseEveryPositiveColumnCount + ...
            item.everyProductHasPositiveColumn;
        row.caseEveryFullPositiveSupportCount = ...
            row.caseEveryFullPositiveSupportCount + ...
            item.everyProductSupportPositive;
        row.caseNumericalDobrushinBelowOneCount = ...
            row.caseNumericalDobrushinBelowOneCount + ...
            item.everyProductNumericallyDobrushinBelowOne;
        row.worstDobrushin = max(row.worstDobrushin, ...
            item.worstDobrushin);
        row.worstCenteredSpectralNorm = max( ...
            row.worstCenteredSpectralNorm, ...
            item.worstCenteredSpectralNorm);
        row.worstMaximumCenteredRowL2 = max( ...
            row.worstMaximumCenteredRowL2, ...
            item.worstMaximumCenteredRowL2);
        row.worstMaximumColumnSumError = max( ...
            row.worstMaximumColumnSumError, ...
            item.worstMaximumColumnSumError);
        row.worstDistanceToUniformAveraging = max( ...
            row.worstDistanceToUniformAveraging, ...
            item.worstDistanceToUniformAveraging);
        row.worstInfluenceWeightL1Imbalance = max( ...
            row.worstInfluenceWeightL1Imbalance, ...
            item.worstInfluenceWeightL1Imbalance);
        row.everyFloatingSupportMatchesBoolean = ...
            row.everyFloatingSupportMatchesBoolean && ...
            item.everyFloatingSupportMatchesBoolean;
    end
    row.everyCaseSupportScrambling = ...
        row.caseEverySupportScramblingCount == row.caseCount;
    row.everyCasePositiveColumn = ...
        row.caseEveryPositiveColumnCount == row.caseCount;
    row.everyCaseFullPositiveSupport = ...
        row.caseEveryFullPositiveSupportCount == row.caseCount;
    row.canonicalSha256 = computeCanonicalValueSha256( ...
        rmfield(row, 'canonicalSha256'));
    rows(horizonIdx) = row;
end
end

function rows = buildCaseRows(result)
rows = repmat(emptyCaseRow(), 1, result.caseCount);
for caseIdx = 1:result.caseCount
    item = result.cases(caseIdx);
    summaries = item.horizonSummaries;
    firstIdx = find([summaries.everyProductSupportPositive], 1);
    earliestHorizon = NaN;
    if ~isempty(firstIdx)
        earliestHorizon = summaries(firstIdx).horizon;
    end
    theoremIdx = find([summaries.horizon] == item.theoremHorizon, 1);
    if isempty(theoremIdx)
        error('FormationB4V46MixingSummary:TheoremHorizonMissing', ...
            'A case lacks its registered theorem horizon.');
    end
    theorem = summaries(theoremIdx);
    row = emptyCaseRow();
    row.presetName = item.presetName;
    row.seed = item.seed;
    row.nodeCount = item.nodeCount;
    row.formationCount = item.formationCount;
    row.repairPageCount = item.repairPageCount;
    row.theoremHorizon = item.theoremHorizon;
    row.earliestAuditedFullPositiveSupportHorizon = earliestHorizon;
    row.theoremFullPositiveSupport = ...
        theorem.everyProductSupportPositive;
    row.theoremWorstDobrushin = theorem.worstDobrushin;
    row.theoremWorstMaximumColumnSumError = ...
        theorem.worstMaximumColumnSumError;
    row.theoremWorstDistanceToUniformAveraging = ...
        theorem.worstDistanceToUniformAveraging;
    row.theoremWorstInfluenceWeightL1Imbalance = ...
        theorem.worstInfluenceWeightL1Imbalance;
    row.finiteEpisodeWeakMixingCertificatePassed = ...
        item.finiteEpisodeWeakMixingCertificatePassed;
    row.canonicalSha256 = computeCanonicalValueSha256( ...
        rmfield(row, 'canonicalSha256'));
    rows(caseIdx) = row;
end
end

function horizon = scaleUniversalHorizon(result, nodeCount)
matching = find([result.cases.nodeCount] == nodeCount);
horizon = NaN;
for horizonIdx = 1:numel(result.horizons)
    passed = true;
    for caseIdx = matching
        passed = passed && result.cases(caseIdx). ...
            horizonSummaries(horizonIdx).everyProductSupportPositive;
    end
    if passed
        horizon = result.horizons(horizonIdx);
        return;
    end
end
end

function writeReport(path, summary)
temporaryPath = [tempname(fileparts(path)), '.md'];
cleanup = onCleanup(@() deleteIfPresent(temporaryPath));
fileId = fopen(temporaryPath, 'w');
if fileId < 0
    error('FormationB4V46MixingSummary:ReportWrite', ...
        'The report could not be opened.');
end
fileCleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '# V46 finite-episode weak-mixing audit\n\n');
fprintf(fileId, '- Result SHA-256: `%s`\n', ...
    summary.resultCanonicalSha256);
fprintf(fileId, '- MAT SHA-256: `%s`\n', ...
    summary.sourceMatRawSha256);
fprintf(fileId, '- Generation commit: `%s` (clean: `%d`)\n', ...
    summary.runMetadata.generationGitCommit, ...
    summary.runMetadata.generationGitClean);
fprintf(fileId, '- Cases: `%d`; summary SHA-256: `%s`\n\n', ...
    summary.caseCount, summary.canonicalSha256);

fprintf(fileId, '## Scope\n\n');
fprintf(fileId, ['The certificate is limited to the frozen 160-step ', ...
    'episodes. It proves Boolean temporal influence propagation and ', ...
    'finite-episode weak mixing at the registered theorem horizons. ', ...
    'It does not prove infinite-horizon convergence, uniform-average ', ...
    'consensus, tracking non-inferiority, or a validation claim.\n\n']);
fprintf(fileId, ['The earliest audited horizon that gives full-positive ', ...
    'support in every window of every case is `%g` steps ', ...
    '(M24: `%g`, X36: `%g`).\n\n'], ...
    summary.universalAuditedFullPositiveSupportHorizon, ...
    summary.m24UniversalAuditedFullPositiveSupportHorizon, ...
    summary.x36UniversalAuditedFullPositiveSupportHorizon);

fprintf(fileId, '## Bias audit\n\n');
fprintf(fileId, ['Full-positive influence support does not imply uniform ', ...
    'averaging. At H=`%g`, the worst audited `||P-J||_2` is `%.6g`, ', ...
    'the worst column-sum error is `%.6g`, and the worst influence ', ...
    'L1 imbalance is `%.6g`.\n\n'], ...
    summary.biasAudit.universalHorizon, ...
    summary.biasAudit.universalWorstDistanceToUniformAveraging, ...
    summary.biasAudit.universalWorstMaximumColumnSumError, ...
    summary.biasAudit.universalWorstInfluenceWeightL1Imbalance);
fprintf(fileId, ['At the registered theorem horizons, the worst ', ...
    '`||P-J||_2` remains `%.6g` for M24 and `%.6g` for X36. ', ...
    'The structural certificate therefore cannot replace the paired ', ...
    'tracking non-inferiority test.\n\n'], ...
    summary.biasAudit.m24TheoremWorstDistanceToUniformAveraging, ...
    summary.biasAudit.x36TheoremWorstDistanceToUniformAveraging);

fprintf(fileId, '## Horizon aggregate\n\n');
fprintf(fileId, ['| H | all-support cases | all-positive-column cases | ', ...
    'full-positive cases | scrambling windows | full-positive windows | ', ...
    'numeric delta<1 cases | saturated delta windows | ', ...
    'worst ||P-J||2 | worst column error |\n']);
fprintf(fileId, ['|---:|---:|---:|---:|---:|---:|---:|---:|', ...
    '---:|---:|\n']);
for row = summary.horizonRows
    fprintf(fileId, ['| %d | %d/%d | %d/%d | %d/%d | %d/%d | ', ...
        '%d/%d | %d/%d | %d | %.6g | %.6g |\n'], ...
        row.horizon, row.caseEverySupportScramblingCount, row.caseCount, ...
        row.caseEveryPositiveColumnCount, row.caseCount, ...
        row.caseEveryFullPositiveSupportCount, row.caseCount, ...
        row.supportScramblingWindowCount, row.windowCount, ...
        row.fullPositiveSupportWindowCount, row.windowCount, ...
        row.caseNumericalDobrushinBelowOneCount, row.caseCount, ...
        row.saturatedNumericalDobrushinWindowCount, ...
        row.worstDistanceToUniformAveraging, ...
        row.worstMaximumColumnSumError);
end

fprintf(fileId, '\n## Case audit\n\n');
fprintf(fileId, ['| preset | seed | N | repair pages | theorem H | ', ...
    'earliest audited full-positive H | theorem pass | ', ...
    'theorem worst delta | theorem worst ||P-J||2 |\n']);
fprintf(fileId, '|---|---:|---:|---:|---:|---:|:---:|---:|---:|\n');
for row = summary.caseRows
    fprintf(fileId, '| %s | %d | %d | %d | %d | %g | %d | %.6g | %.6g |\n', ...
        row.presetName, row.seed, row.nodeCount, row.repairPageCount, ...
        row.theoremHorizon, ...
        row.earliestAuditedFullPositiveSupportHorizon, ...
        row.finiteEpisodeWeakMixingCertificatePassed, ...
        row.theoremWorstDobrushin, ...
        row.theoremWorstDistanceToUniformAveraging);
end
clear fileCleanup;
movefile(temporaryPath, path, 'f');
clear cleanup;
end

