function writeReport(path, result, matPath, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('FormationResidualDutyCycleV44Runner:ReportWriteFailed', ...
        'Cannot open the v44 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V44 residual duty-cycle structural screen\n\n');
fprintf(fid, '- Protocol: `%s`\n', result.protocolId);
fprintf(fid, '- Protocol SHA-256: `%s`\n', ...
    result.protocolCanonicalSha256);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Result SHA-256: `%s`\n', result.canonicalSha256);
fprintf(fid, '- MAT: `%s`\n', matPath);
fprintf(fid, '- Cases: `%d / %d registered`\n', result.caseCount, ...
