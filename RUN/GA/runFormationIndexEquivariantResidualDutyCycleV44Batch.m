function result = ...
    runFormationIndexEquivariantResidualDutyCycleV44Batch( ...
        outputDirectory, options)
% Registered V44 structural communication--contraction screen.

repoRoot = resolveRepoRoot();
protocol = getFormationIndexEquivariantResidualDutyCycleV44Protocol();
if nargin < 1 || isempty(outputDirectory)
    outputDirectory = fullfile(repoRoot, 'RUN', 'GA', ...
        'dynamic_topology', 'evidence', 'formation_value_v44', ...
        'residual_duty_cycle_development_v1');
elseif ischar(outputDirectory) && outputDirectory(1) ~= filesep
    outputDirectory = fullfile(repoRoot, outputDirectory);
end
if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = {'presets', 'seeds', 'requireCleanGit'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationResidualDutyCycleV44Runner:InvalidOptions', ...
        'The v44 runner options are malformed.');
end
presets = getField(options, 'presets', protocol.registeredPresets);
seeds = reshape(getField(options, 'seeds', ...
    protocol.registeredSeeds), 1, []);
requireCleanGit = logicalScalar(getField( ...
    options, 'requireCleanGit', true), 'requireCleanGit');
validateRequestedCases(presets, seeds, protocol);

matPath = fullfile(outputDirectory, ...
    'FORMATION_RESIDUAL_DUTY_CYCLE_V44_DEVELOPMENT_V1.mat');
reportPath = fullfile(outputDirectory, ...
    'FORMATION_RESIDUAL_DUTY_CYCLE_V44_DEVELOPMENT_V1.md');
if exist(outputDirectory, 'dir') || exist(outputDirectory, 'file') || ...
        exist(matPath, 'file') || exist(reportPath, 'file')
    error('FormationResidualDutyCycleV44Runner:OutputExists', ...
        'The v44 output is non-overwriting.');
end

[gitCommit, gitDirty] = resolveGitState(repoRoot);
if requireCleanGit && gitDirty
    error('FormationResidualDutyCycleV44Runner:DirtyGitState', ...
        'A registered v44 run requires a fully clean worktree.');
end
if ~isAncestor(repoRoot, protocol.methodCommit, gitCommit)
    error('FormationResidualDutyCycleV44Runner:MethodCommitMissing', ...
        'The frozen v44 method commit is not an ancestor of HEAD.');
end
manifest = ...
    buildFormationIndexEquivariantResidualDutyCycleV44ExecutableManifest( ...
        repoRoot);
if requireCleanGit && (~manifest.allEntriesTrackedByHead || ...
        ~manifest.allWorkingFilesMatchHead)
    error('FormationResidualDutyCycleV44Runner:ExecutableSourceNotHead', ...
        'Every executable v44 source must be tracked and match HEAD.');
end
parent = loadParentEvidence(repoRoot, protocol, requireCleanGit);

if ~exist(outputDirectory, 'dir')
    [created, message] = mkdir(outputDirectory);
    if ~created
        error('FormationResidualDutyCycleV44Runner:OutputCreateFailed', ...
            'Cannot create the output directory: %s', message);
    end
end

caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        presetName = presets{presetIdx};
        seed = seeds(seedIdx);
        fprintf('V44 duty-cycle case %d/%d: %s seed %d\n', ...
            cursor, caseCount, presetName, seed);
        registered = findRegisteredCase(protocol, presetName, seed);
        parentCase = findParentCase(parent, registered.caseId);
        cases(cursor) = buildCase( ...
            presetName, seed, registered, parentCase, protocol);
    end
end

[endingCommit, endingDirty] = resolveGitState(repoRoot);
endingManifest = ...
    buildFormationIndexEquivariantResidualDutyCycleV44ExecutableManifest( ...
        repoRoot);
sourceStable = strcmp(gitCommit, endingCommit) && ...
    endingDirty == gitDirty && ...
    strcmp(manifest.canonicalSha256, endingManifest.canonicalSha256);
if requireCleanGit && ~sourceStable
    error('FormationResidualDutyCycleV44Runner:SourceChangedDuringRun', ...
        'The v44 executable source changed during the run.');
end
officialCleanSourcePassed = requireCleanGit && ~gitDirty && ...
    manifest.pathResolutionPassed && manifest.allEntriesTrackedByHead && ...
    manifest.allWorkingFilesMatchHead && sourceStable;
execution = struct( ...
    'officialCleanSourcePassed', officialCleanSourcePassed);
gate = evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
    cases, execution, protocol);

result = struct();
result.contractVersion = ...
    'formation-index-equivariant-residual-duty-cycle-v44-result-v1';
result.protocolId = protocol.id;
result.protocolCanonicalSha256 = protocol.canonicalSha256;
result.methodCommit = protocol.methodCommit;
result.generationGitCommit = gitCommit;
result.generationGitDirty = gitDirty;
result.endingGitCommit = endingCommit;
result.endingGitDirty = endingDirty;
result.executionSourceStable = sourceStable;
result.requireCleanGit = requireCleanGit;
result.executableSourceManifest = manifest;
result.parentEvidenceRawSha256 = parent.rawSha256;
result.parentEvidenceResultCanonicalSha256 = ...
    parent.result.canonicalSha256;
result.parentEvidenceRouteReferenceAuditPassed = ...
    parent.routeReferenceAuditPassed;
result.presets = presets;
result.seeds = seeds;
result.requestedCaseIds = {cases.caseId};
result.registeredCaseIds = {protocol.registeredCases.caseId};
result.registeredBatchComplete = gate.registeredBatchComplete;
result.exploratorySubsetOnly = ~gate.registeredBatchComplete;
result.caseCount = numel(cases);
result.candidateCount = protocol.candidateCount;
result.cases = cases;
result.gate = gate;
result.officialCleanSourcePassed = officialCleanSourcePassed;
result.postHocExecutableFreezeAuditPassed = false;
result.routeDevelopmentAdvancePassed = false;
result.recommendedCandidateId = gate.recommendedCandidateId;
result.formalRuntimeObservableBoundaryPassed = false;
result.runtimePhysicalUidRegistryIntegrated = false;
result.posteriorUsed = any([cases.posteriorUsed]);
result.truthUsed = any([cases.truthUsed]);
result.measurementUsed = any([cases.measurementUsed]);
result.futureOutcomeUsed = any([cases.futureOutcomeUsed]);
result.realizedDeliveryUniformsUsed = ...
    any([cases.realizedDeliveryUniformsUsed]);
result.trackingOutcomeScored = false;
result.trackingOutcomeAuthorized = false;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.canonicalSha256 = '';
result.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(result, 'canonicalSha256'));

save(matPath, 'result', '-v7');
writeReport(reportPath, result, matPath, protocol);
fprintf('V44 duty-cycle batch complete: %s\n', reportPath);
end

function value = buildCase(presetName, seed, registered, parentCase, protocol)
[context, metadata] = ...
    buildFormationIndexEquivariantGeometryDevelopmentContext( ...
        presetName, seed);
assertRegisteredIdentity(metadata, registered);
runtime = validateReliableKlaMixingRuntimeSemantics( ...
    context.triggerConfig);
if ~strcmp(runtime.missingNeighborWeightMode, ...
        protocol.missingNeighborWeightMode)
    error('FormationResidualDutyCycleV44Runner:RuntimeMismatch', ...
        'The runtime missing-neighbor semantics drifted.');
end
[referenceAdjacency, referenceDetails] = ...
    selectIndexEquivariantFormationBackbonePolicy(context, struct( ...
        'dominantWeight', protocol.dominantWeight, ...
        'residualWeight', protocol.referenceResidualWeight));
referenceWeights = referenceDetails.fusionWeightMatrix;
nodeCount = size(referenceAdjacency, 1);
maximumHorizon = protocol.maximumHorizonMultiplier * (nodeCount - 1);
fixedHorizon = nodeCount - 1;
reliability = 1 - context.commConfig.pDropByEdge';
referenceProfile = computeStaticReliableKlaMeanSquareHorizonProfile( ...
    referenceAdjacency, referenceWeights, reliability, ...
    maximumHorizon, struct( ...
        'missingNeighborWeightMode', ...
            protocol.missingNeighborWeightMode, ...
        'maximumIncomingCount', protocol.maximumIncomingCount, ...
        'targetSquaredFactors', ...
            protocol.targetSquaredContractionFactor));
referenceTargetHorizon = referenceProfile.firstTargetHorizon(1);
referenceFixedFactor = referenceProfile. ...
    worstCaseExpectedSquaredFactorByHorizon(fixedHorizon + 1);
referenceRouteSha256 = routeSha256( ...
    referenceAdjacency, referenceWeights);
parentMatched = strcmp(referenceRouteSha256, ...
        parentCase.v43RouteCanonicalSha256) && ...
    referenceTargetHorizon == parentCase.v43TargetHorizon && ...
    abs(referenceFixedFactor - parentCase.v43FixedHorizonFactor) < 1e-12;
if ~parentMatched
    error('FormationResidualDutyCycleV44Runner:ParentMismatch', ...
        'The frozen V43 reference did not reproduce exactly.');
end

candidates = repmat(emptyCandidate(), 1, protocol.candidateCount);
for candidateIdx = 1:protocol.candidateCount
    definition = protocol.candidates(candidateIdx);
    fprintf('  candidate %d/%d: %s\n', candidateIdx, ...
        protocol.candidateCount, definition.id);
    candidates(candidateIdx) = evaluateCandidate( ...
        context, reliability, referenceAdjacency, ...
        referenceTargetHorizon, fixedHorizon, maximumHorizon, ...
        definition, protocol);
end

boundary = context.auditBoundary;
boundaryPassed = boundary.fullPlannedSensorGeometryMaterialized && ...
    boundary.fullPlannedLinkProbabilityScheduleMaterialized && ...
    ~boundary.formalRuntimeObservableBoundaryPassed && ...
    ~boundary.runtimePhysicalUidRegistryIntegrated && ...
    ~boundary.posteriorContentsRead && ~boundary.truthUsed && ...
    ~boundary.measurementUsed && ~boundary.futureOutcomeUsed && ...
    ~boundary.realizedDeliveryUniformsUsed && ...
    ~boundary.trackingOutcomeScored && ...
    ~boundary.trackingOutcomeAuthorized && ...
    ~boundary.validationClaimAllowed && boundary.developmentEvidenceOnly;
if ~boundaryPassed || ~all([candidates.boundaryPassed])
    error('FormationResidualDutyCycleV44Runner:BoundaryViolation', ...
        'The v44 case crossed its development-only boundary.');
end

value = emptyCase();
value.caseId = registered.caseId;
value.presetName = presetName;
value.sceneRole = registered.sceneRole;
value.seed = seed;
value.currentTime = metadata.currentTime;
value.nodeCount = nodeCount;
value.formationCount = metadata.formationCount;
value.inputCanonicalSha256 = metadata.inputCanonicalSha256;
value.physicalUidRegistryCanonicalSha256 = ...
    metadata.physicalUidAssignmentCanonicalSha256;
value.registeredInputIdentityMatched = true;
value.parentReferenceMatched = parentMatched;
value.referenceRouteCanonicalSha256 = referenceRouteSha256;
value.referenceTargetHorizon = referenceTargetHorizon;
value.referenceFixedHorizonFactor = referenceFixedFactor;
value.referenceDirectedMessagesPerStep = nnz(referenceAdjacency);
value.referenceAttemptedMessagesToTarget = ...
    nnz(referenceAdjacency) * referenceTargetHorizon;
value.maximumHorizon = maximumHorizon;
value.fixedHorizon = fixedHorizon;
value.candidates = candidates;
value.executionBoundaryPassed = boundaryPassed;
value.fullPlannedSensorGeometryMaterialized = ...
    boundary.fullPlannedSensorGeometryMaterialized;
value.fullPlannedLinkProbabilityScheduleMaterialized = ...
    boundary.fullPlannedLinkProbabilityScheduleMaterialized;
value.formalRuntimeObservableBoundaryPassed = false;
value.runtimePhysicalUidRegistryIntegrated = false;
value.posteriorUsed = false;
value.truthUsed = false;
value.measurementUsed = false;
value.futureOutcomeUsed = false;
value.realizedDeliveryUniformsUsed = false;
value.trackingOutcomeScored = false;
value.trackingOutcomeAuthorized = false;
value.validationClaimAllowed = false;
value.developmentEvidenceOnly = true;
value.canonicalSha256 = '';
value.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(value, 'canonicalSha256'));
end

function record = evaluateCandidate(context, reliability, ...
        referenceAdjacency, referenceTargetHorizon, fixedHorizon, ...
        maximumHorizon, definition, protocol)
options = struct('period', definition.period, ...
    'dutyLayer', definition.dutyLayer, ...
    'phasePattern', definition.phasePattern, ...
    'activeResidualWeight', definition.activeResidualWeight, ...
    'dominantWeight', protocol.dominantWeight, ...
    'referenceResidualWeight', protocol.referenceResidualWeight);
[adjacency, weights, details] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(context, options);
profile = computePeriodicReliableKlaMeanSquareHorizonProfile( ...
    adjacency, weights, reliability, maximumHorizon, struct( ...
        'missingNeighborWeightMode', ...
            protocol.missingNeighborWeightMode, ...
        'maximumIncomingCount', protocol.maximumIncomingCount, ...
        'targetSquaredFactors', ...
            protocol.targetSquaredContractionFactor));
targetHorizonByPhase = reshape( ...
    profile.firstTargetHorizonByStartPhase(:, 1), 1, []);
targetMessagesByPhase = nan(size(targetHorizonByPhase));
for phaseIdx = 1:numel(targetHorizonByPhase)
    horizon = targetHorizonByPhase(phaseIdx);
    if isfinite(horizon)
        targetMessagesByPhase(phaseIdx) = profile. ...
            cumulativeMessagesByStartPhaseAndHorizon( ...
                phaseIdx, horizon + 1);
    end
end
referenceMessagesToTarget = ...
    nnz(referenceAdjacency) * referenceTargetHorizon;
targetMessageRatios = targetMessagesByPhase / ...
    referenceMessagesToTarget;
fixedFactors = profile.factorByStartPhaseAndHorizon( ...
    :, fixedHorizon + 1)';
referenceTargetFactors = profile.factorByStartPhaseAndHorizon( ...
    :, referenceTargetHorizon + 1)';
equivariancePassed = auditPermutationEquivariance( ...
    context, options, adjacency, weights, details);
rollingUnionPassed = auditRollingPeriodUnion( ...
    adjacency, referenceAdjacency);
minimumSelfWeight = minimumDiagonalWeight(weights);
dominantPages = repmat( ...
    details.dominantAdjacency, 1, 1, definition.period);
dominantRetained = all(reshape(~dominantPages | adjacency, [], 1));
structuralContractsPassed = ...
    details.periodUnionEqualsReference && ...
    details.periodUnionSensorStrongConnected && ...
    details.periodUnionFormationStrongConnected && ...
    rollingUnionPassed && dominantRetained && ...
    details.maximumMessagesPerReceiver <= ...
        protocol.maximumIncomingCount && ...
    minimumSelfWeight >= protocol.minimumActiveSelfWeight - 1e-12 && ...
    all(abs(reshape(sum(weights, 2), [], 1) - 1) < 1e-12) && ...
    details.messageSavingFractionPerPeriod > 0;
boundaryPassed = details.currentGeometryUsed && ...
    details.currentLinkReliabilityUsed && ...
    details.currentPhysicalActionSetUsed && ...
    ~details.posteriorUsed && ~details.truthUsed && ...
    ~details.measurementUsed && ~details.futureOutcomeUsed && ...
    ~details.realizedDeliveryUniformsUsed && ...
    ~details.trackingOutcomeScored && ...
    ~details.validationClaimAllowed && details.developmentEvidenceOnly;

record = emptyCandidate();
record.candidateId = definition.id;
record.ordinal = definition.ordinal;
record.period = definition.period;
record.dutyLayer = definition.dutyLayer;
record.phasePattern = definition.phasePattern;
record.activeResidualWeight = definition.activeResidualWeight;
record.weightMode = definition.weightMode;
record.minimumSelfWeight = minimumSelfWeight;
record.routeSequenceCanonicalSha256 = computeCanonicalValueSha256( ...
    struct('adjacencySequence', logical(adjacency), ...
        'fusionWeightSequence', weights));
record.messageCountsByPhase = details.messageCountsByPhase;
record.peakAttemptedMessagesPerStep = ...
    max(details.messageCountsByPhase);
record.messagesPerPeriod = details.messagesPerPeriod;
record.referenceMessagesPerPeriod = ...
    details.referenceMessagesPerPeriod;
record.messageSavingFractionPerPeriod = ...
    details.messageSavingFractionPerPeriod;
record.targetHorizonByStartPhase = targetHorizonByPhase;
record.everyPhaseFiniteTargetHorizon = ...
    all(isfinite(targetHorizonByPhase));
record.worstPhaseTargetHorizon = max(targetHorizonByPhase);
record.targetMessagesByStartPhase = targetMessagesByPhase;
record.targetMessageRatioByStartPhase = targetMessageRatios;
record.worstPhaseTargetMessageRatio = max(targetMessageRatios);
record.medianPhaseTargetMessageRatio = median(targetMessageRatios);
record.fixedHorizonFactorByStartPhase = fixedFactors;
record.worstPhaseFixedHorizonFactor = max(fixedFactors);
record.factorAtReferenceTargetHorizonByStartPhase = ...
    referenceTargetFactors;
record.worstFactorAtReferenceTargetHorizon = ...
    max(referenceTargetFactors);
record.currentAbsolutePhase = details.currentAbsolutePhase;
record.currentPhaseTargetHorizon = ...
    targetHorizonByPhase(details.currentAbsolutePhase);
record.currentPhaseTargetMessageRatio = ...
    targetMessageRatios(details.currentAbsolutePhase);
record.rollingPeriodUnionEqualsReference = rollingUnionPassed;
record.dominantRetainedEveryPhase = dominantRetained;
record.scheduleEquivariancePassed = equivariancePassed;
record.structuralContractsPassed = structuralContractsPassed;
record.boundaryPassed = boundaryPassed;
record.posteriorUsed = false;
record.truthUsed = false;
record.futureOutcomeUsed = false;
record.trackingOutcomeScored = false;
record.validationClaimAllowed = false;
record.developmentEvidenceOnly = true;
record.canonicalSha256 = '';
record.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(record, 'canonicalSha256'));
end

function passed = auditPermutationEquivariance( ...
        context, options, expectedAdjacency, expectedWeights, expectedDetails)
[~, order] = sort(context.sensorPhysicalUids, 'descend');
[permuted, ~] = permuteFormationIndexEquivariantContext(context, order);
[actualAdjacency, actualWeights, actualDetails] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(permuted, options);
nodeCount = numel(order);
passed = true;
for phaseIdx = 1:size(expectedAdjacency, 3)
    restoredAdjacency = false(nodeCount);
    restoredAdjacency(order, order) = ...
        actualAdjacency(:, :, phaseIdx);
    restoredWeights = zeros(nodeCount);
    restoredWeights(order, order) = actualWeights(:, :, phaseIdx);
    passed = passed && isequal(restoredAdjacency, ...
        expectedAdjacency(:, :, phaseIdx)) && ...
        isequal(restoredWeights, expectedWeights(:, :, phaseIdx));
end
restoredPhases = nan(1, nodeCount);
restoredPhases(order) = actualDetails.dutyPhaseByReceiver;
passed = passed && isequaln(restoredPhases, ...
    expectedDetails.dutyPhaseByReceiver);
end

function passed = auditRollingPeriodUnion(adjacency, reference)
period = size(adjacency, 3);
passed = true;
for startPhase = 1:period
    phases = mod(startPhase - 1 + (0:period-1), period) + 1;
    passed = passed && isequal(any(adjacency(:, :, phases), 3), reference);
end
end

function value = minimumDiagonalWeight(weights)
nodeCount = size(weights, 1);
period = size(weights, 3);
diagonal = zeros(nodeCount, period);
for phaseIdx = 1:period
    page = weights(:, :, phaseIdx);
    diagonal(:, phaseIdx) = diag(page);
end
value = min(diagonal(:));
end

function parent = loadParentEvidence(repoRoot, protocol, requireAudit)
path = fullfile(repoRoot, protocol.parentEvidenceRelativePath);
if exist(path, 'file') ~= 2
    error('FormationResidualDutyCycleV44Runner:ParentMissing', ...
        'The frozen V43 evidence artifact is missing.');
end
rawSha256 = computeFileSha256(path);
if ~strcmp(rawSha256, protocol.parentEvidenceRawSha256)
    error('FormationResidualDutyCycleV44Runner:ParentHashMismatch', ...
        'The frozen V43 evidence artifact changed.');
end
loaded = load(path, 'result');
if ~isfield(loaded, 'result')
    error('FormationResidualDutyCycleV44Runner:ParentInvalid', ...
        'The V43 parent evidence payload is missing.');
end
payload = rmfield(loaded.result, 'canonicalSha256');
if ~strcmp(computeCanonicalValueSha256(payload), ...
        loaded.result.canonicalSha256)
    error('FormationResidualDutyCycleV44Runner:ParentCanonicalMismatch', ...
        'The V43 parent result canonical hash failed.');
end
routeReferenceAuditPassed = false;
if requireAudit
    audit = auditFormationIndexEquivariantRouteV43DevelopmentEvidence();
    routeReferenceAuditPassed = audit.passed && ...
        audit.routeReferenceAdvancePassed;
    if ~routeReferenceAuditPassed
        error('FormationResidualDutyCycleV44Runner:ParentAuditFailed', ...
            'The committed V43 parent audit failed closed.');
    end
end
parent = struct('result', loaded.result, 'rawSha256', rawSha256, ...
    'routeReferenceAuditPassed', routeReferenceAuditPassed);
end

function item = findParentCase(parent, caseId)
matches = strcmp({parent.result.cases.caseId}, caseId);
if nnz(matches) ~= 1
    error('FormationResidualDutyCycleV44Runner:ParentCaseMissing', ...
        'The requested case is absent from the V43 evidence.');
end
item = parent.result.cases(matches);
end

function item = findRegisteredCase(protocol, presetName, seed)
matches = strcmp({protocol.registeredCases.presetName}, presetName) & ...
    [protocol.registeredCases.seed] == seed;
if nnz(matches) ~= 1
    error('FormationResidualDutyCycleV44Runner:CaseRegistry', ...
        'The requested case is not registered.');
end
item = protocol.registeredCases(matches);
end

function assertRegisteredIdentity(metadata, registered)
passed = strcmp(metadata.presetName, registered.presetName) && ...
    metadata.seed == registered.seed && ...
    metadata.currentTime == registered.currentTime && ...
    metadata.nodeCount == registered.nodeCount && ...
    metadata.formationCount == registered.formationCount && ...
    strcmp(metadata.inputCanonicalSha256, ...
        registered.inputCanonicalSha256) && ...
    strcmp(metadata.physicalUidAssignmentCanonicalSha256, ...
        registered.physicalUidRegistryCanonicalSha256);
if ~passed
    error('FormationResidualDutyCycleV44Runner:RegisteredInputDrift', ...
        'A registered v44 input identity changed.');
end
end

function validateRequestedCases(presets, seeds, protocol)
if ~iscell(presets) || isempty(presets) || ...
        numel(unique(presets)) ~= numel(presets) || ...
        any(~ismember(presets, protocol.registeredPresets)) || ...
        ~isnumeric(seeds) || isempty(seeds) || ...
        numel(unique(seeds)) ~= numel(seeds) || ...
        any(~ismember(seeds, protocol.registeredSeeds))
    error('FormationResidualDutyCycleV44Runner:UnregisteredCases', ...
        'The requested v44 case subset is invalid.');
end
expectedPresetOrder = protocol.registeredPresets( ...
    ismember(protocol.registeredPresets, presets));
expectedSeedOrder = protocol.registeredSeeds( ...
    ismember(protocol.registeredSeeds, seeds));
if ~isequal(presets, expectedPresetOrder) || ...
        ~isequal(seeds, expectedSeedOrder)
    error('FormationResidualDutyCycleV44Runner:CaseOrder', ...
        'Requested cases must retain the registered order.');
end
end

