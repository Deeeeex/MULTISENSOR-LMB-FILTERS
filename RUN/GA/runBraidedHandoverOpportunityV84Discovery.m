function [reportPath, result] = ...
    runBraidedHandoverOpportunityV84Discovery(options)
% RUNBRAIDEDHANDOVEROPPORTUNITYV84DISCOVERY Current-only source scan.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getBraidedHandoverOpportunityV84Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('BraidedHandoverV84:DirtySource', ...
        'The V84 source discovery requires clean source.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

sceneResults = repmat(struct(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    records = repmat(emptyRecord(), 1, numel(protocol.snapshotTimes));
    for timeIdx = 1:numel(protocol.snapshotTimes)
        currentTime = protocol.snapshotTimes(timeIdx);
        state = loadFormationH3ObservableState( ...
            protocol.presets{presetIdx}, protocol.allSeeds, currentTime, ...
            struct('cacheRoot', cacheRoot));
        [~, control] = computeFormationRoutingLeverageSignature( ...
            state.context, state.groupIds, struct( ...
                'referenceMode', 'current-physical-tree'));
        base = computeNetworkAdditiveFormationRiskV65( ...
            control, state.context, state.groupIds, ...
            protocol.positiveSupportThreshold);
        influence = computeInfluenceAwareDecisionBreadthV66( ...
            control, state.context, state.groupIds, struct( ...
                'positiveSupportThreshold', ...
                    protocol.positiveSupportThreshold, ...
                'horizonSteps', protocol.horizonSteps));
        transport = computeAlternativeTransportHeadroomV68( ...
            state.context, control, state.groupIds, protocol);
        localOptions = struct( ...
            'minimumLocalQuarantineNetFraction', ...
                protocol.minimumLocalNetFraction, ...
            'minimumLocalAlternativeNetFraction', ...
                protocol.minimumLocalNetFraction, ...
            'minimumLocalRobustMarginExposure', ...
                protocol.minimumLocalRobustMarginExposure, ...
            'maximumUsefulLossToRescueRatio', ...
                protocol.maximumProtectedHarmRatio, ...
            'requireZeroSupportedDownwardCrossings', ...
                protocol.requireZeroSupportedDownwardCrossings);
        local = computeReceiverDomainNormalizedOpportunityV70( ...
            base, influence, control, transport, ...
            state.groupIds, localOptions);
        flow = computeBraidedHandoverInformationFlowV84( ...
            state.context, control, transport, state.groupIds, protocol);
        records(timeIdx) = makeRecord( ...
            currentTime, local, flow, protocol);
        fprintf([ ...
            'V84 %s t=%d protect=%.3f%% f=%s ', ...
            'transfer=%.3f%% novelty=%.3f%% edge=%s score=%.3f\n'], ...
            protocol.presets{presetIdx}, currentTime, ...
            100 * records(timeIdx).maximumProtectionNetFraction, ...
            mat2str(records(timeIdx).protectionFormationIds), ...
            100 * records(timeIdx).maximumTransferNetFraction, ...
            100 * records(timeIdx).maximumSenderNoveltyFraction, ...
            edgeString(records(timeIdx)), records(timeIdx).actionScore);
    end
    sceneResults(presetIdx) = summarizeScene( ...
        protocol.presets{presetIdx}, protocol.allSeeds, records, protocol);
end

result = struct();
result.contractVersion = ...
    'braided-handover-opportunity-v84-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.sceneResults = sceneResults;
result.sourceGatePassed = all(arrayfun( ...
    @(scene) ~isempty(scene.selectedAnchors), sceneResults));
result.trackingOutcomeRead = false;
result.routeExecutionAuthorized = false;
result.trackingOutcomeScoringAuthorized = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'BRAIDED_HANDOVER_OPPORTUNITY_V84_DISCOVERY.mat');
reportPath = fullfile(outputRoot, ...
    'BRAIDED_HANDOVER_OPPORTUNITY_V84_DISCOVERY.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V84 braided-handover discovery: %s\n', reportPath);
end

function record = makeRecord(time, local, flow, protocol)
record = emptyRecord();
record.currentTime = time;
record.maximumProtectionNetFraction = ...
    local.maximumLocalQuarantineNetFraction;
record.maximumProtectionRobustExposure = finiteMax( ...
    local.localRobustMarginExposureByFormation( ...
        local.quarantineActionMask));
record.protectionFormationIds = ...
    local.quarantineActionFormationIds;
record.protectionActionEnabled = ...
    ~isempty(record.protectionFormationIds);
record.transferActionEnabled = flow.actionableEdgeCount > 0;
record.maximumTransferNetFraction = flow.maximumLocalNetFraction;
record.maximumSenderNoveltyFraction = ...
    flow.maximumLocalSenderNoveltyFraction;
record.transferRankingScore = flow.maximumRankingScore;
if record.transferActionEnabled
    best = flow.bestAction;
    record.receiverIdx = best.receiverIdx;
    record.receiverFormationId = best.receiverFormationId;
    record.incumbentSenderIdx = best.incumbentSenderIdx;
    record.incumbentFormationId = best.incumbentFormationId;
    record.candidateSenderIdx = best.candidateSenderIdx;
    record.candidateFormationId = best.candidateFormationId;
end
protectionScore = 0;
if record.protectionActionEnabled
    protectionScore = min( ...
        record.maximumProtectionNetFraction / ...
            protocol.minimumLocalNetFraction, ...
        record.maximumProtectionRobustExposure / ...
            protocol.minimumLocalRobustMarginExposure);
end
record.protectionRankingScore = protectionScore;
record.actionScore = max(protectionScore, record.transferRankingScore);
if record.transferRankingScore > protectionScore + 1e-12
    record.preferredAction = 'transfer';
elseif record.protectionActionEnabled
    record.preferredAction = 'protect';
else
    record.preferredAction = 'fallback';
end
end

function scene = summarizeScene(presetName, seed, records, protocol)
scene = struct();
scene.presetName = presetName;
scene.seed = seed;
scene.records = records;
scene.actionableTimes = [records([records.actionScore] > 0).currentTime];
scene.selectedAnchors = selectAnchors(records, protocol);
end

function anchors = selectAnchors(records, protocol)
eligible = find([records.actionScore] > 0);
anchors = repmat(emptyRecord(), 1, 0);
if isempty(eligible)
    return;
end
scores = [records(eligible).actionScore];
times = [records(eligible).currentTime];
ranking = [-scores(:), times(:), eligible(:)];
[~, order] = sortrows(ranking, [1, 2, 3]);
for idx = reshape(eligible(order), 1, [])
    if ~isempty(anchors) && any(abs( ...
            [anchors.currentTime] - records(idx).currentTime) < ...
            protocol.minimumAnchorSeparation)
        continue;
    end
    anchors(end + 1) = records(idx); %#ok<AGROW>
    if numel(anchors) >= protocol.maximumAnchorsPerScale
        break;
    end
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BraidedHandoverV84:WriteFailed', ...
        'Could not create the V84 discovery report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V84 braided-handover current-only opportunity\n\n');
for scene = result.sceneResults
    fprintf(fid, '## %s / seed %d\n\n', ...
        scene.presetName, scene.seed);
    fprintf(fid, ['| Time | Protect net | Protect formations | ', ...
        'Transfer net | Sender novelty | Transfer edge | ', ...
        'Preferred | Score |\n']);
    fprintf(fid, '|--:|--:|:--|--:|--:|:--|:--|--:|\n');
    for record = scene.records
        fprintf(fid, ...
            '| %d | %.3f%% | `%s` | %.3f%% | %.3f%% | `%s` | `%s` | %.3f |\n', ...
            record.currentTime, ...
            100 * record.maximumProtectionNetFraction, ...
            mat2str(record.protectionFormationIds), ...
            100 * record.maximumTransferNetFraction, ...
            100 * record.maximumSenderNoveltyFraction, ...
            edgeString(record), record.preferredAction, ...
            record.actionScore);
    end
    fprintf(fid, '\n### Automatically selected source anchors\n\n');
    if isempty(scene.selectedAnchors)
        fprintf(fid, '- None.\n\n');
    else
        for anchor = scene.selectedAnchors
            fprintf(fid, ...
                '- `t=%d`: `%s`, score `%.3f`, edge `%s`, formations `%s`.\n', ...
                anchor.currentTime, anchor.preferredAction, ...
                anchor.actionScore, edgeString(anchor), ...
                mat2str(anchor.protectionFormationIds));
        end
        fprintf(fid, '\n');
    end
end
fprintf(fid, '- Cross-scale source gate passed: `%d`\n', ...
    result.sourceGatePassed);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route execution authorized: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'maximumProtectionNetFraction', NaN, ...
    'maximumProtectionRobustExposure', NaN, ...
    'protectionFormationIds', zeros(1, 0), ...
    'protectionActionEnabled', false, ...
    'maximumTransferNetFraction', NaN, ...
    'maximumSenderNoveltyFraction', NaN, ...
    'transferActionEnabled', false, ...
    'receiverIdx', NaN, ...
    'receiverFormationId', NaN, ...
    'incumbentSenderIdx', NaN, ...
    'incumbentFormationId', NaN, ...
    'candidateSenderIdx', NaN, ...
    'candidateFormationId', NaN, ...
    'protectionRankingScore', 0, ...
    'transferRankingScore', 0, ...
    'actionScore', 0, ...
    'preferredAction', 'fallback');
end

function value = finiteMax(values)
values = reshape(values, 1, []);
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = edgeString(record)
if ~record.transferActionEnabled
    value = '-';
else
    value = sprintf('%d(f%d)->%d(f%d), replacing %d(f%d)', ...
        record.candidateSenderIdx, record.candidateFormationId, ...
        record.receiverIdx, record.receiverFormationId, ...
        record.incumbentSenderIdx, record.incumbentFormationId);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
