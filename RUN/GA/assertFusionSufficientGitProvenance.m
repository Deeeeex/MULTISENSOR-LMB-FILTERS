function provenance = assertFusionSufficientGitProvenance(projectRoot)
% ASSERTFUSIONSUFFICIENTGITPROVENANCE Require a published clean runtime.

projectRoot = char(projectRoot);
if exist(projectRoot, 'dir') ~= 7
    error('FusionSufficientProvenance:InvalidRoot', ...
        'Project root does not exist: %s', projectRoot);
end
runtimeStatusCommand = sprintf([ ...
    'git -C %s status --porcelain=v1 --untracked-files=all -- %s'], ...
    shellQuote(projectRoot), shellQuote(':(glob)**/*.m'));
protocolStatusCommand = sprintf([ ...
    'git -C %s status --porcelain=v1 --untracked-files=all -- %s'], ...
    shellQuote(projectRoot), shellQuote( ...
    'docs/icassp2027_paper/EXPERIMENT_PROTOCOL_CN.md'));
[runtimeStatus, runtimeOutput] = system(runtimeStatusCommand);
[protocolStatus, protocolOutput] = system(protocolStatusCommand);
if runtimeStatus ~= 0 || protocolStatus ~= 0
    error('FusionSufficientProvenance:StatusFailed', ...
        'Unable to inspect the experiment runtime worktree.');
end
dirtyOutput = strtrim(sprintf('%s\n%s', runtimeOutput, protocolOutput));
if ~isempty(dirtyOutput)
    error('FusionSufficientProvenance:DirtyRuntime', ...
        ['Experiment runtime/protocol files must be tracked and clean ', ...
        'before a smoke or confirmatory run:\n%s'], dirtyOutput);
end

requiredPaths = { ...
    'RUN/GA/runFusionSufficientMomentExchangeConfirmatory.m', ...
    'RUN/GA/assertFusionSufficientGitProvenance.m', ...
    'RUN/GA/renderFusionSufficientEvidenceReport.m', ...
    'RUN/GA/publishFusionSufficientEvidenceBundle.m', ...
    'RUN/GA/writeFusionSufficientEvidence.m', ...
    'RUN/GA/validateFusionSufficientEvidence.m', ...
    ['RUN/GA/runMultisensorFilters_formation_4plus4_', ...
        'DualThresholdEventTriggerCompare.m'], ...
    'multisensorLmb/runEventTriggeredDistributedLmbFilter.m', ...
    'multisensorLmb/snapshotLmbPosterior.m', ...
    'multisensorLmb/compareLmbPosteriorSnapshots.m', ...
    'multisensorLmb/projectLmbObjectMoments.m', ...
    'multisensorLmb/compressLmbPosterior.m', ...
    'multisensorLmb/fuseLmbPosteriorsByLabel.m', ...
    'multisensorLmb/getLmbWireSchema.m', ...
    'multisensorLmb/encodeLmbWireMessage.m', ...
    'multisensorLmb/decodeLmbWireMessage.m', ...
    'docs/icassp2027_paper/EXPERIMENT_PROTOCOL_CN.md'};
for pathIdx = 1:numel(requiredPaths)
    command = sprintf('git -C %s cat-file -e %s', ...
        shellQuote(projectRoot), ...
        shellQuote(['HEAD:', requiredPaths{pathIdx}]));
    [status, ~] = system(command);
    if status ~= 0
        error('FusionSufficientProvenance:NotInHead', ...
            'Required runtime file is not contained in HEAD: %s', ...
            requiredPaths{pathIdx});
    end
end

head = readGitRevision(projectRoot, 'HEAD');
upstream = readGitRevision(projectRoot, '@{upstream}');
if ~strcmp(head, upstream)
    error('FusionSufficientProvenance:UnpublishedHead', ...
        ['Experiment HEAD %s does not equal its configured upstream %s. ', ...
        'Commit and push before running.'], head, upstream);
end
provenance = struct('head', head, 'upstream', upstream, ...
    'runtimeClean', true);
end

function revision = readGitRevision(projectRoot, expression)
command = sprintf('git -C %s rev-parse --verify %s', ...
    shellQuote(projectRoot), shellQuote(expression));
[status, output] = system(command);
if status ~= 0
    error('FusionSufficientProvenance:MissingUpstream', ...
        'Unable to resolve Git revision %s.', expression);
end
revision = strtrim(output);
if isempty(regexp(revision, '^[0-9a-f]{40}$', 'once'))
    error('FusionSufficientProvenance:InvalidRevision', ...
        'Git revision %s is not a 40-hex commit.', expression);
end
end

function quoted = shellQuote(value)
value = char(value);
quoted = ['''', strrep(value, '''', '''"''"'''), ''''];
end
