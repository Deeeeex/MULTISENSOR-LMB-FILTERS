function [reportPath, result] = runRecursiveRolloutCaptureV176(options)
% RUNRECURSIVEROLLOUTCAPTUREV176 Reuse static and capture V169 states.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLearnedOneHopSafeLabelV169Protocol();
sourceScreenPath = getField(options, ...
    'referenceOutcomeScreenPath', fullfile( ...
        protocol.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
if exist(sourceScreenPath, 'file') ~= 2
    error('RecursiveRolloutCaptureV176:MissingReference', ...
        'The completed paired V169 screen is required for reference reuse.');
end
protocol.reuseFrozenReferenceOutcome = true;
protocol.referenceOutcomeScreenPath = sourceScreenPath;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v176', 'recursive_rollout_capture');
protocol.headroomOutputRoot = protocol.outputRoot;
protocol.reportTitle = ...
    'V176 recursive-rollout capture: X36 t72 H=8';
protocol.resultFileStem = ...
    'RECURSIVE_ROLLOUT_CAPTURE_V176_X36_T72_RESULT';
protocol.resultContractVersion = ...
    'recursive-rollout-capture-v176-x36-t72-result-v1';
runOptions = struct( ...
    'protocolOverride', protocol, ...
    'outputRoot', getField(options, 'outputRoot', ...
        fullfile(protocol.headroomOutputRoot, 'x36_t72_h8')), ...
    'captureFusedPosteriorSnapshotsEnabled', true, ...
    'reuseCompletedCandidateScreen', getField(options, ...
        'reuseCompletedCandidateScreen', true));
[reportPath, result] = runProtectionOnlyH8V105X36T72(runOptions);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
