function [summary, execution] = ...
    assembleFusionSufficientMomentExchangeWorkers( ...
        workerDirectory, config, expectedProvenance, testAuthorization)
% ASSEMBLEFUSIONSUFFICIENTMOMENTEXCHANGEWORKERS Strict seed-order merge.

if nargin < 3
    expectedProvenance = struct();
end
if nargin < 4
    testAuthorization = struct();
end
testMode = isFusionSufficientInternalTestAuthorization(testAuthorization);
validateExecutionMode(config, testMode);
if ~testMode
    currentProvenance = assertFusionSufficientConfigProvenance(config);
    if isempty(fieldnames(expectedProvenance))
        expectedProvenance = currentProvenance;
    end
end
workerDirectory = char(workerDirectory);
plan = buildFusionSufficientParallelPlan(config);
if ~strcmp(workerDirectory, plan.workerDirectory)
    error('FusionSufficientAssembler:WorkerDirectory', ...
        'Worker directory differs from the deterministic plan.');
end
if exist(workerDirectory, 'dir') ~= 7
    error('FusionSufficientAssembler:MissingDirectory', ...
        'Worker directory does not exist: %s', workerDirectory);
end
receipt = validateBatchSeal(plan, config);
assertExactArtifactSet(workerDirectory, plan);

numberOfTrials = numel(plan.workerSeeds);
workerSummaries = cell(1, numberOfTrials);
workerMatSha256 = cell(1, numberOfTrials);
observedSeeds = NaN(1, numberOfTrials);
for seedIdx = 1:numberOfTrials
    loaded = load(plan.workerMatPaths{seedIdx});
    if ~isfield(loaded, 'workerResult')
        error('FusionSufficientAssembler:InvalidWorker', ...
            'Worker MAT lacks workerResult: %s', ...
            plan.workerMatPaths{seedIdx});
    end
    result = loaded.workerResult;
    validateWorkerResult(result, config, ...
        plan.workerSeeds(seedIdx), expectedProvenance);
    observedSeeds(seedIdx) = result.seed;
    workerSummaries{seedIdx} = result.summary;
    workerMatSha256{seedIdx} = ...
        fusionSufficientSha256File(plan.workerMatPaths{seedIdx});
    if ~strcmp(workerMatSha256{seedIdx}, ...
            receipt.workerMatSha256{seedIdx})
        error('FusionSufficientAssembler:PostLoadArtifactHash', ...
            'Worker MAT changed during validation for seed %d.', ...
            plan.workerSeeds(seedIdx));
    end
end
if numel(unique(observedSeeds)) ~= numberOfTrials
    error('FusionSufficientAssembler:DuplicateSeed', ...
        'Worker results contain duplicate internal seeds.');
end

summary = combineMinimalSummary(workerSummaries, config);
execution = struct( ...
    'protocol', config.executionProtocol, ...
    'batchIdentity', config.batchIdentity, ...
    'workerSchema', config.workerSchema, ...
    'maxWorkers', config.maxWorkers, ...
    'octaveVersion', config.octaveVersion, ...
    'configSha256', config.configSha256, ...
    'requiredSourcesSha256', config.requiredSourcesSha256, ...
    'planSha256', receipt.planSha256, ...
    'exitLedgerSha256', receipt.exitLedgerSha256, ...
    'launcherCapabilitySha256', ...
        receipt.launcherCapabilitySha256, ...
    'completionTokenSha256', receipt.completionTokenSha256, ...
    'batchSuccessReceiptSha256', receipt.receiptSha256, ...
    'receiptValidated', true, ...
    'workerSeeds', plan.workerSeeds, ...
    'workerMatSha256', {workerMatSha256}, ...
    'workerLogSha256', {receipt.workerLogSha256});
summary.execution = execution;
assertFusionSufficientFrozenRun(summary, config);
if ~strcmp(inspectFusionSufficientBatchState(plan).name, ...
        'COMPLETE_WORKERS') || ...
        ~strcmp(fusionSufficientSha256File( ...
        plan.workerSuccessReceiptPath), receipt.receiptSha256)
    error('FusionSufficientAssembler:TerminalStateChanged', ...
        'Batch terminal state or receipt changed during assembly.');
end
for seedIdx = 1:numel(plan.workerSeeds)
    if ~strcmp(fusionSufficientSha256File( ...
            plan.workerMatPaths{seedIdx}), ...
            receipt.workerMatSha256{seedIdx}) || ...
            ~strcmp(fusionSufficientSha256File( ...
            plan.workerLogPaths{seedIdx}), ...
            receipt.workerLogSha256{seedIdx})
        error('FusionSufficientAssembler:ArtifactChanged', ...
            'Worker artifact changed during assembly for seed %d.', ...
            plan.workerSeeds(seedIdx));
    end
end
end

function validateExecutionMode(config, testMode)
if testMode
    valid = isfield(config, 'testOnly') && ...
        isequal(config.testOnly, true) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-test-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-test-v2') && ...
        strncmp(config.artifactStem, 'TEST_', 5) && ...
        strncmp(config.batchIdentity, 'test-', 5);
else
    valid = isfield(config, 'testOnly') && ...
        isequal(config.testOnly, false) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-v2');
end
if ~valid
    error('FusionSufficientAssembler:ExecutionMode', ...
        'Assembler rejects unauthorized production/test schema.');
end
end

function receipt = validateBatchSeal(plan, config)
state = inspectFusionSufficientBatchState(plan);
if ~strcmp(state.name, 'COMPLETE_WORKERS')
    error('FusionSufficientAssembler:BatchState', ...
        'Assembler requires COMPLETE_WORKERS, observed %s.', state.name);
end
published = load(plan.batchPlanPath);
if ~isfield(published, 'config') || ...
        ~isfield(published, 'parallelPlan') || ...
        ~isequaln(orderfields(published.config), orderfields(config)) || ...
        ~isequaln(orderfields(published.parallelPlan), orderfields(plan))
    error('FusionSufficientAssembler:PublishedPlan', ...
        'Published batch plan differs from current frozen plan/config.');
end
reservation = parseReceipt(plan.reservationReceiptPath);
requireReceiptValue(reservation, 'reservation_schema', ...
    'fusion-sufficient-batch-reservation-v2');
requireReceiptValue(reservation, 'batch_identity', config.batchIdentity);
requireReceiptValue(reservation, 'config_sha256', config.configSha256);
requireReceiptValue(reservation, 'git_commit', config.gitCommit);
capabilitySha256 = requireReceiptHash( ...
    reservation, 'launcher_capability_sha256');
requireReceiptValue(reservation, 'ordered_seeds', ...
    joinIntegers(plan.workerSeeds));
requireReceiptValue(reservation, 'max_workers', ...
    sprintf('%d', plan.maxWorkers));
claim = parseReceipt(plan.lifecycleClaimPath);
requireReceiptValue(claim, 'claim_schema', ...
    'fusion-sufficient-launch-claim-v2');
requireReceiptValue(claim, 'batch_identity', config.batchIdentity);
requireReceiptValue(claim, 'launcher_capability_sha256', ...
    capabilitySha256);

workerText = fileread(plan.workerSuccessReceiptPath);
attemptText = fileread(plan.attemptSuccessReceiptPath);
if ~isequal(uint8(workerText), uint8(attemptText))
    error('FusionSufficientAssembler:ReceiptCopies', ...
        'Worker and stable-ledger success receipts differ.');
end
values = parseReceipt(plan.workerSuccessReceiptPath);
requireReceiptValue(values, 'receipt_schema', ...
    'fusion-sufficient-batch-success-v2');
requireReceiptValue(values, 'batch_identity', config.batchIdentity);
requireReceiptValue(values, 'config_sha256', config.configSha256);
requireReceiptValue(values, 'required_sources_sha256', ...
    config.requiredSourcesSha256);
requireReceiptValue(values, 'launcher_capability_sha256', ...
    capabilitySha256);
completion = parseReceipt(plan.completionAuthorizationPath);
requireReceiptValue(completion, 'completion_schema', ...
    'fusion-sufficient-completion-v2');
requireReceiptValue(completion, 'batch_identity', config.batchIdentity);
requireReceiptValue(completion, 'launcher_capability_sha256', ...
    capabilitySha256);
completionTokenSha256 = requireReceiptHash( ...
    completion, 'completion_token_sha256');
requireReceiptValue(values, 'completion_token_sha256', ...
    completionTokenSha256);
planHash = fusionSufficientSha256File(plan.batchPlanPath);
requireReceiptValue(values, 'plan_sha256', planHash);
exitLedgerHash = fusionSufficientSha256File(plan.exitLedgerPath);
requireReceiptValue(values, 'exit_ledger_sha256', exitLedgerHash);
exitValues = parseReceipt(plan.exitLedgerPath);
requireReceiptValue(exitValues, 'exit_schema', ...
    'fusion-sufficient-worker-exits-v2');
requireReceiptValue(exitValues, 'batch_identity', config.batchIdentity);
requireReceiptValue(exitValues, 'launcher_capability_sha256', ...
    capabilitySha256);
requireReceiptValue(exitValues, 'ordered_seeds', ...
    joinIntegers(plan.workerSeeds));
if numel(fieldnames(exitValues)) ~= 4 + numel(plan.workerSeeds)
    error('FusionSufficientAssembler:ExitLedgerFields', ...
        'Worker exit ledger contains missing or extra fields.');
end
requireReceiptValue(values, 'ordered_seeds', ...
    joinIntegers(plan.workerSeeds));
requireReceiptValue(values, 'max_workers', ...
    sprintf('%d', plan.maxWorkers));
requireReceiptValue(values, 'worker_count', ...
    sprintf('%d', numel(plan.workerSeeds)));
expectedFieldCount = 11 + 3 * numel(plan.workerSeeds);
if numel(fieldnames(values)) ~= expectedFieldCount
    error('FusionSufficientAssembler:ReceiptFields', ...
        'Success receipt contains missing or extra fields.');
end
matHashes = cell(1, numel(plan.workerSeeds));
logHashes = cell(1, numel(plan.workerSeeds));
for seedIdx = 1:numel(plan.workerSeeds)
    seed = plan.workerSeeds(seedIdx);
    exitKey = sprintf('worker_%06d_exit', seed);
    matKey = sprintf('worker_%06d_mat_sha256', seed);
    logKey = sprintf('worker_%06d_log_sha256', seed);
    matHashes{seedIdx} = ...
        fusionSufficientSha256File(plan.workerMatPaths{seedIdx});
    logHashes{seedIdx} = ...
        fusionSufficientSha256File(plan.workerLogPaths{seedIdx});
    requireReceiptValue(exitValues, exitKey, '0');
    requireReceiptValue(values, exitKey, '0');
    requireReceiptValue(values, matKey, matHashes{seedIdx});
    requireReceiptValue(values, logKey, logHashes{seedIdx});
end
receipt = struct( ...
    'planSha256', planHash, ...
    'exitLedgerSha256', exitLedgerHash, ...
    'launcherCapabilitySha256', capabilitySha256, ...
    'completionTokenSha256', completionTokenSha256, ...
    'receiptSha256', fusionSufficientSha256File( ...
        plan.workerSuccessReceiptPath), ...
    'workerMatSha256', {matHashes}, ...
    'workerLogSha256', {logHashes});
end

function value = requireReceiptHash(values, name)
if ~isfield(values, name) || isempty(regexp(values.(name), ...
        '^[0-9a-f]{64}$', 'once'))
    error('FusionSufficientAssembler:ReceiptHash', ...
        'Receipt hash field %s is missing or invalid.', name);
end
value = values.(name);
end

function values = parseReceipt(path)
text = fileread(path);
lines = strsplit(strtrim(text), '\n');
values = struct();
for lineIdx = 1:numel(lines)
    token = regexp(lines{lineIdx}, '^([a-z0-9_]+)=(.*)$', ...
        'tokens', 'once');
    if isempty(token) || isfield(values, token{1})
        error('FusionSufficientAssembler:ReceiptSyntax', ...
            'Receipt has invalid or duplicate line %d.', lineIdx);
    end
    values.(token{1}) = token{2};
end
end

function requireReceiptValue(values, name, expected)
if ~isfield(values, name) || ~strcmp(values.(name), expected)
    error('FusionSufficientAssembler:ReceiptValue', ...
        'Receipt field %s differs from expected value.', name);
end
end

function text = joinIntegers(values)
parts = arrayfun(@(value) sprintf('%d', value), values, ...
    'UniformOutput', false);
text = strjoin(parts, ',');
end

function assertExactArtifactSet(workerDirectory, plan)
expectedMatNames = cellfun(@basename, plan.workerMatPaths, ...
    'UniformOutput', false);
expectedLogNames = cellfun(@basename, plan.workerLogPaths, ...
    'UniformOutput', false);
actualMat = dir(fullfile(workerDirectory, 'worker_seed_*.mat'));
actualLog = dir(fullfile(workerDirectory, 'worker_seed_*.log'));
actualMatNames = sort({actualMat.name});
actualLogNames = sort({actualLog.name});
if ~isequal(actualMatNames, sort(expectedMatNames))
    error('FusionSufficientAssembler:WorkerMatSet', ...
        'Worker MAT set contains missing or extra seed artifacts.');
end
if ~isequal(actualLogNames, sort(expectedLogNames))
    error('FusionSufficientAssembler:WorkerLogSet', ...
        'Worker log set contains missing or extra seed artifacts.');
end
for pathIdx = 1:numel(plan.workerMatPaths)
    if exist(plan.workerMatPaths{pathIdx}, 'file') ~= 2 || ...
            exist(plan.workerLogPaths{pathIdx}, 'file') ~= 2
        error('FusionSufficientAssembler:MissingWorker', ...
            'Worker seed %d is incomplete.', plan.workerSeeds(pathIdx));
    end
end
end

function validateWorkerResult(result, config, expectedSeed, provenance)
required = {'workerSchema', 'evidenceSchema', 'gitCommit', ...
    'requiredSourcesSha256', 'configSha256', 'summarySha256', ...
    'octaveVersion', 'seed', 'exactGatePassed', 'config', 'summary'};
for fieldIdx = 1:numel(required)
    if ~isfield(result, required{fieldIdx})
        error('FusionSufficientAssembler:InvalidWorker', ...
            'Worker seed %d is missing %s.', ...
            expectedSeed, required{fieldIdx});
    end
end
if result.seed ~= expectedSeed
    error('FusionSufficientAssembler:UnexpectedSeed', ...
        'Expected worker seed %d, observed %d.', ...
        expectedSeed, result.seed);
end
if ~strcmp(result.workerSchema, config.workerSchema) || ...
        ~strcmp(result.evidenceSchema, config.evidenceSchema) || ...
        ~strcmp(result.gitCommit, config.gitCommit) || ...
        ~strcmp(result.requiredSourcesSha256, ...
        config.requiredSourcesSha256) || ...
        ~strcmp(result.configSha256, config.configSha256) || ...
        ~strcmp(result.octaveVersion, config.octaveVersion) || ...
        ~isequal(result.exactGatePassed, true)
    error('FusionSufficientAssembler:WorkerProvenance', ...
        'Worker seed %d has mismatched schema/provenance.', expectedSeed);
end
if ~isequaln(orderfields(result.config), orderfields(config)) || ...
        ~strcmp(hashFusionSufficientConfig(result.config), ...
        config.configSha256)
    error('FusionSufficientAssembler:WorkerConfig', ...
        'Worker seed %d has a different frozen config.', expectedSeed);
end
if ~strcmp(hashFusionSufficientValue(result.summary), ...
        result.summarySha256)
    error('FusionSufficientAssembler:WorkerSummaryHash', ...
        'Worker seed %d summary hash is invalid.', expectedSeed);
end
if ~isempty(fieldnames(provenance))
    if ~isfield(provenance, 'head') || ...
            ~isfield(provenance, 'requiredSourcesSha256') || ...
            ~strcmp(provenance.head, result.gitCommit) || ...
            ~strcmp(provenance.requiredSourcesSha256, ...
            result.requiredSourcesSha256)
        error('FusionSufficientAssembler:CurrentProvenance', ...
            'Current source provenance differs from worker seed %d.', ...
            expectedSeed);
    end
end
assertFusionSufficientFrozenRun(result.summary, config, expectedSeed);
end

function summary = combineMinimalSummary(workerSummaries, config)
first = workerSummaries{1};
for workerIdx = 2:numel(workerSummaries)
    candidate = workerSummaries{workerIdx};
    if ~isequaln(candidate.armNames, first.armNames) || ...
            ~isequaln(candidate.arms, first.arms) || ...
            ~isequaln(candidate.scenarioConfig, first.scenarioConfig)
        error('FusionSufficientAssembler:ScenarioMismatch', ...
            'Worker seed %d has different arms or scenario.', ...
            candidate.trialSeeds);
    end
end

trialFields = {'localEOspa', 'consensusOspa', ...
    'consensusPosition', 'consensusCardinality', ...
    'attemptedPayloadBytes', 'deliveredPayloadBytes', ...
    'attemptedMask', 'deliveredMask', ...
    'posteriorMissingSnapshotCount', ...
    'posteriorLabelSetMismatchCount', ...
    'posteriorMissingLabelCount', 'posteriorComparisonCount', ...
    'posteriorSnapshotCount', 'posteriorMaxAbsR', ...
    'posteriorMaxAbsMu', 'posteriorMaxAbsSigma', ...
    'posteriorExactMatch'};
trials = struct();
for fieldIdx = 1:numel(trialFields)
    name = trialFields{fieldIdx};
    pieces = cellfun(@(value) value.trials.(name), ...
        workerSummaries, 'UniformOutput', false);
    trials.(name) = cat(1, pieces{:});
end

summary = struct();
summary.armNames = first.armNames;
summary.arms = first.arms;
summary.numberOfTrials = numel(workerSummaries);
summary.trialSeeds = config.firstSeed:config.lastSeed;
summary.scenarioConfig = first.scenarioConfig;
summary.trials = trials;
summary.equivalence = recomputeEquivalence( ...
    trials, config.armSelection{1});
end

function equivalence = recomputeEquivalence(trials, baselineArm)
equivalence = struct();
equivalence.captured = true;
equivalence.baselineArm = baselineArm;
equivalence.missingSnapshotCount = ...
    sum(trials.posteriorMissingSnapshotCount, 1);
equivalence.labelSetMismatchCount = ...
    sum(trials.posteriorLabelSetMismatchCount, 1);
equivalence.missingLabelCount = ...
    sum(trials.posteriorMissingLabelCount, 1);
equivalence.comparisonCount = ...
    sum(trials.posteriorComparisonCount, 1);
equivalence.snapshotCount = sum(trials.posteriorSnapshotCount, 1);
equivalence.maxAbsR = max(trials.posteriorMaxAbsR, [], 1);
equivalence.maxAbsMu = max(trials.posteriorMaxAbsMu, [], 1);
equivalence.maxAbsSigma = max(trials.posteriorMaxAbsSigma, [], 1);
equivalence.exactMatch = all(trials.posteriorExactMatch, 1);
end

function value = basename(path)
[~, name, extension] = fileparts(path);
value = [name, extension];
end

function hashValue = sha256File(path)
command = sprintf('shasum -a 256 %s', shellQuote(path));
[status, output] = system(command);
if status ~= 0
    error('FusionSufficientAssembler:HashFailed', ...
        'Unable to hash worker MAT: %s', path);
end
hashValue = regexp(lower(strtrim(output)), ...
    '^[0-9a-f]{64}', 'match', 'once');
if isempty(hashValue)
    error('FusionSufficientAssembler:InvalidHash', ...
        'Invalid worker MAT SHA-256: %s', path);
end
end

function quoted = shellQuote(value)
value = char(value);
quoted = ['''', strrep(value, '''', '''"''"'''), ''''];
end
