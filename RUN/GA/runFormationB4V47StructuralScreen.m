function result = runFormationB4V47StructuralScreen(options)
% RUNFORMATIONB4V47STRUCTURALSCREEN Compare V46 sync and V47 information debt.
%
% This runner materializes planned geometry/link pages for development
% diagnostics, but passes only one current page to either policy.  It calls
% no target, measurement, or truth generator and scores no tracking output.

if nargin < 1 || isempty(options)
    options = struct();
end
allowed = {'presets', 'seeds', 'timeIndices', ...
    'horizons', 'deliverySeedOffset', 'progressEvery'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowed))
    error('FormationB4V47Structural:InvalidOptions', ...
        'The V47 structural-screen options are malformed.');
end
presets = getField(options, 'presets', { ...
    'm24-formation-fov', 'x36-formation-fov'});
seeds = reshape(getField(options, 'seeds', 41), 1, []);
requestedTimes = reshape(getField(options, ...
    'timeIndices', []), 1, []);
horizons = reshape(getField(options, 'horizons', ...
    [4, 8, 16, 32, 64, 92, 140]), 1, []);
deliverySeedOffset = getField(options, ...
    'deliverySeedOffset', 47047000);
progressEvery = getField(options, 'progressEvery', 40);
validateOptions(presets, seeds, requestedTimes, horizons, ...
    deliverySeedOffset, progressEvery);

protocol = getFormationGatewayDebtV47Protocol();
caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        fprintf('V47 structural case %d/%d: %s seed=%d\n', ...
            cursor, caseCount, presets{presetIdx}, seeds(seedIdx));
        cases(cursor) = buildCase(presets{presetIdx}, ...
            seeds(seedIdx), requestedTimes, horizons, ...
            deliverySeedOffset, progressEvery, protocol);
    end
end

result = struct();
result.contractVersion = ...
    'formation-b4-v47-structural-screen-development-v1';
result.protocolId = protocol.id;
result.protocolCanonicalSha256 = protocol.canonicalSha256;
result.presets = presets;
result.seeds = seeds;
result.horizons = horizons;
result.deliverySeedOffset = deliverySeedOffset;
result.caseCount = caseCount;
result.cases = cases;
result.allCandidateAttemptedRollingB4Strong = ...
    all([cases.candidateEveryAttemptedRollingB4Strong]);
result.allCandidateExactNoFallbackSavingPassed = ...
    all([cases.candidateExactNoFallbackSavingPassed]);
result.allCandidateFullEpisodePostHocMeanSquareImproved = ...
    all([cases.candidateFullEpisodePostHocMeanSquareImproved]);
result.allCandidateFocusPostHocMeanSquareImproved = ...
    all([cases.candidateFocusPostHocMeanSquareImproved]);
result.fullPlannedSensorGeometryMaterialized = true;
result.fullPlannedLinkProbabilityScheduleMaterialized = true;
result.policyReceivedCurrentPageOnly = true;
result.posteriorSignalHeldNeutral = true;
result.adaptiveRouteDependsOnPastDeliveries = true;
result.postHocFixedRouteMeanSquareDiagnosticOnly = true;
result.closedLoopMeanSquareContractionCertified = false;
result.groundTruthGeneratedOrUsed = false;
result.measurementGeneratedOrUsed = false;
result.targetTrajectoryGeneratedOrUsed = false;
result.trackingOutcomeScored = false;
result.trackingOutcomeAuthorized = false;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.canonicalSha256 = '';
result.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(result, 'canonicalSha256'));
fprintf(['V47 structural screen complete: cases=%d ', ...
    'rollingB4=%d fullMSgain=%d focusMSgain=%d sha256=%s\n'], ...
    caseCount, result.allCandidateAttemptedRollingB4Strong, ...
    result.allCandidateFullEpisodePostHocMeanSquareImproved, ...
    result.allCandidateFocusPostHocMeanSquareImproved, ...
    result.canonicalSha256);
end

function value = buildCase(presetName, seed, requestedTimes, ...
        requestedHorizons, deliverySeedOffset, progressEvery, protocol)
rng(seed, 'twister');
config = buildDynamicTopologyScenarioConfig(presetName);
[sensorTrajectories, trajectoryMetadata] = ...
    generateMultiFormationTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensorTrajectories);
[pDropByEdge, ~] = buildDynamicTopologyLinkSchedule(config, graph);
identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
if ~isequal(identity.sensorPhysicalUids, ...
        trajectoryMetadata.sensorPhysicalUids) || ...
        ~isequal(identity.formationPhysicalUidsBySensor, ...
            trajectoryMetadata.formationPhysicalUidsBySensor) || ...
        ~strcmp(identity.canonicalSha256, ...
            trajectoryMetadata.physicalIdentityRegistryCanonicalSha256)
    error('FormationB4V47Structural:IdentityDrift', ...
        'The materialized scene identity registry drifted.');
end
registeredBase = FormationB4V45BuildCausalRegisteredBaseGraph( ...
    config.formationBackboneMode, config.sensorGroupIds, ...
    identity.sensorPhysicalUids, ...
    identity.formationPhysicalUidsBySensor, ...
    graph.positions(:, :, 1), graph.physicalAdjacency(:, :, 1));

if isempty(requestedTimes)
    auditedTimes = 1:config.simulationLength;
else
    auditedTimes = requestedTimes;
end
if any(auditedTimes > config.simulationLength) || ...
        ~isequal(auditedTimes, auditedTimes(1):auditedTimes(end))
    error('FormationB4V47Structural:InvalidOptions', ...
        'Audited times must be one in-range consecutive interval.');
end
nodeCount = config.numberOfSensors;
timeCount = numel(auditedTimes);
horizons = requestedHorizons(requestedHorizons <= timeCount);
if isempty(horizons)
    horizons = timeCount;
end
deliverySeed = deliverySeedOffset + seed;
[uniforms, uniformMetadata] = ...
    materializePhysicalUidDirectedDeliveryUniforms( ...
        deliverySeed, identity.sensorPhysicalUids, ...
        config.simulationLength);

syncAdjacency = false(nodeCount, nodeCount, timeCount);
candidateAdjacency = false(nodeCount, nodeCount, timeCount);
syncWeights = zeros(nodeCount, nodeCount, timeCount);
candidateWeights = zeros(nodeCount, nodeCount, timeCount);
reliability = zeros(nodeCount, nodeCount, timeCount);
syncDelivered = false(nodeCount, nodeCount, timeCount);
candidateDelivered = false(nodeCount, nodeCount, timeCount);
candidateFallback = false(1, timeCount);
candidateCrossCount = zeros(1, timeCount);
candidateSelectedCrossCount = zeros(1, timeCount);
candidateMaximumAttemptAge = zeros(1, timeCount);
candidateMaximumFiniteDeliveryAge = zeros(1, timeCount);
candidateNeverDeliveredCount = zeros(1, timeCount);
repairCount = zeros(1, timeCount);
historyAdjacency = false(nodeCount, nodeCount, 0);
historyDelivery = false(nodeCount, nodeCount, 0);
historyTimes = zeros(1, 0);
for localIdx = 1:timeCount
    currentTime = auditedTimes(localIdx);
    context = buildCurrentContext( ...
        config, identity, registeredBase.baseAdjacency, ...
        graph.positions(:, :, currentTime), ...
        graph.physicalAdjacency(:, :, currentTime), ...
        pDropByEdge(:, :, currentTime), currentTime, ...
        historyAdjacency, historyDelivery, historyTimes, protocol);
    [candidatePage, details] = ...
        selectFormationB4V47GatewayDebtRuntimePolicy(context);
    [syncPage, syncWeightPage] = ...
        buildSynchronizedPage(details, currentTime, protocol);
    candidateWeightPage = details.fusionWeightMatrix;
    currentReliability = 1 - pDropByEdge(:, :, currentTime)';
    currentUniforms = uniforms(:, :, currentTime)';
    currentSuccess = currentUniforms >= ...
        pDropByEdge(:, :, currentTime)';
    syncDeliveryPage = logical(syncPage) & currentSuccess;
    candidateDeliveryPage = logical(candidatePage) & currentSuccess;

    syncAdjacency(:, :, localIdx) = syncPage;
    candidateAdjacency(:, :, localIdx) = candidatePage;
    syncWeights(:, :, localIdx) = syncWeightPage;
    candidateWeights(:, :, localIdx) = candidateWeightPage;
    reliability(:, :, localIdx) = currentReliability;
    syncDelivered(:, :, localIdx) = syncDeliveryPage;
    candidateDelivered(:, :, localIdx) = candidateDeliveryPage;
    candidateFallback(localIdx) = details.referenceFallbackUsed;
    candidateCrossCount(localIdx) = details.crossResidualCount;
    candidateSelectedCrossCount(localIdx) = ...
        numel(details.selectedCrossReceivers);
    candidateMaximumAttemptAge(localIdx) = cappedMaximum( ...
        details.attemptAgeByReceiver, timeCount + 1);
    candidateMaximumFiniteDeliveryAge(localIdx) = finiteMaximum( ...
        details.deliveryAgeByReceiver);
    candidateNeverDeliveredCount(localIdx) = nnz( ...
        isinf(details.deliveryAgeByReceiver));
    repairCount(localIdx) = details. ...
        projectionCertificate.registeredRemovalCount;

    historyAdjacency(:, :, end + 1) = candidatePage; %#ok<AGROW>
    historyDelivery(:, :, end + 1) = candidateDeliveryPage; %#ok<AGROW>
    historyTimes(end + 1) = currentTime; %#ok<AGROW>
    historyDepth = context.triggerConfig.topologyPolicyHistoryDepth;
    if numel(historyTimes) > historyDepth
        firstKept = numel(historyTimes) - historyDepth + 1;
        historyAdjacency = historyAdjacency(:, :, firstKept:end);
        historyDelivery = historyDelivery(:, :, firstKept:end);
        historyTimes = historyTimes(firstKept:end);
    end
    if localIdx == 1 || localIdx == timeCount || ...
            mod(localIdx, progressEvery) == 0
        fprintf('  %s seed=%d t=%d/%d scheduled\n', ...
            presetName, seed, currentTime, config.simulationLength);
    end
end

syncMessageCount = nnz(syncAdjacency);
candidateMessageCount = nnz(candidateAdjacency);
fullReferenceMessageCount = 2 * nodeCount * timeCount;
noFallback = ~any(candidateFallback);
exactSaving = noFallback && ...
    syncMessageCount == candidateMessageCount && ...
    8 * (fullReferenceMessageCount - candidateMessageCount) == ...
        3 * fullReferenceMessageCount;
syncNominal = auditFiniteEpisodeWeakMixingSequence( ...
    syncWeights, horizons);
candidateNominal = auditFiniteEpisodeWeakMixingSequence( ...
    candidateWeights, horizons);
meanSquareOptions = struct( ...
    'missingNeighborWeightMode', 'renormalize', ...
    'maximumIncomingCount', 2);
syncFullMs = computeReliableKlaWindowMeanSquareContractionCertificate( ...
    syncAdjacency, syncWeights, reliability, meanSquareOptions);
candidateFullMs = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        candidateAdjacency, candidateWeights, reliability, ...
        meanSquareOptions);
focusLocal = resolveFocusLocalIndices(config.focusWindow, auditedTimes);
if numel(focusLocal) >= protocol.period
    syncFocusMs = ...
        computeReliableKlaWindowMeanSquareContractionCertificate( ...
            syncAdjacency(:, :, focusLocal), ...
            syncWeights(:, :, focusLocal), ...
            reliability(:, :, focusLocal), meanSquareOptions);
    candidateFocusMs = ...
        computeReliableKlaWindowMeanSquareContractionCertificate( ...
            candidateAdjacency(:, :, focusLocal), ...
            candidateWeights(:, :, focusLocal), ...
            reliability(:, :, focusLocal), meanSquareOptions);
else
    syncFocusMs = syncFullMs;
    candidateFocusMs = candidateFullMs;
    focusLocal = 1:timeCount;
end

rollingWindow = protocol.period;
syncAttemptedStrong = everyRollingStrong( ...
    syncAdjacency, rollingWindow);
candidateAttemptedStrong = everyRollingStrong( ...
    candidateAdjacency, rollingWindow);
syncDeliveredStrong = everyRollingStrong( ...
    syncDelivered, rollingWindow);
candidateDeliveredStrong = everyRollingStrong( ...
    candidateDelivered, rollingWindow);

value = emptyCase();
value.caseId = sprintf('%s__seed%d__v47-structural', ...
    presetName, seed);
value.presetName = presetName;
value.seed = seed;
value.deliverySeed = deliverySeed;
value.deliveryUniformMetadataCanonicalSha256 = ...
    uniformMetadata.canonicalSha256;
value.nodeCount = nodeCount;
value.formationCount = config.formationCount;
value.simulationLength = config.simulationLength;
value.auditedTimes = auditedTimes;
value.focusAuditedTimes = auditedTimes(focusLocal);
value.repairCountByTime = repairCount;
value.repairPageCount = nnz(repairCount > 0);
value.syncRouteSequenceCanonicalSha256 = ...
    computeCanonicalValueSha256(struct( ...
        'adjacency', syncAdjacency, 'weights', syncWeights));
value.candidateRouteSequenceCanonicalSha256 = ...
    computeCanonicalValueSha256(struct( ...
        'adjacency', candidateAdjacency, ...
        'weights', candidateWeights));
value.receiverSenderReliabilitySequenceCanonicalSha256 = ...
    computeCanonicalValueSha256(reliability);
value.syncDeliveredSequenceCanonicalSha256 = ...
    computeCanonicalValueSha256(syncDelivered);
value.candidateDeliveredSequenceCanonicalSha256 = ...
    computeCanonicalValueSha256(candidateDelivered);
value.syncAttemptedMessageCount = syncMessageCount;
value.candidateAttemptedMessageCount = candidateMessageCount;
value.fullReferenceAttemptedMessageCount = fullReferenceMessageCount;
value.candidateSameBudgetAsSynchronizedB4 = ...
    candidateMessageCount == syncMessageCount;
value.candidateAttemptedMessageSavingFraction = ...
    (fullReferenceMessageCount - candidateMessageCount) / ...
        fullReferenceMessageCount;
value.candidateFallbackByTime = candidateFallback;
value.candidateFallbackCount = nnz(candidateFallback);
value.candidateExactNoFallbackSavingPassed = exactSaving;
value.candidateCrossResidualCountByTime = candidateCrossCount;
value.candidateSelectedCrossCountByTime = ...
    candidateSelectedCrossCount;
value.candidateMaximumAttemptAgeByTime = ...
    candidateMaximumAttemptAge;
value.candidateMaximumFiniteDeliveryAgeByTime = ...
    candidateMaximumFiniteDeliveryAge;
value.candidateNeverDeliveredCountByTime = ...
    candidateNeverDeliveredCount;
value.syncEveryAttemptedRollingB4Strong = syncAttemptedStrong;
value.candidateEveryAttemptedRollingB4Strong = ...
    candidateAttemptedStrong;
value.syncEveryDeliveredRollingB4Strong = syncDeliveredStrong;
value.candidateEveryDeliveredRollingB4Strong = ...
    candidateDeliveredStrong;
value.horizons = horizons;
value.syncNominalMixing = compactMixing(syncNominal);
value.candidateNominalMixing = compactMixing(candidateNominal);
value.syncFullEpisodePostHocFixedRouteMeanSquare = ...
    compactMeanSquare(syncFullMs);
value.candidateFullEpisodePostHocFixedRouteMeanSquare = ...
    compactMeanSquare(candidateFullMs);
value.syncFocusPostHocFixedRouteMeanSquare = ...
    compactMeanSquare(syncFocusMs);
value.candidateFocusPostHocFixedRouteMeanSquare = ...
    compactMeanSquare(candidateFocusMs);
value.candidateFullEpisodePostHocMeanSquareImproved = ...
    candidateFullMs.worstCaseExpectedSquaredContractionFactor < ...
        syncFullMs.worstCaseExpectedSquaredContractionFactor - 1e-12;
value.candidateFocusPostHocMeanSquareImproved = ...
    candidateFocusMs.worstCaseExpectedSquaredContractionFactor < ...
        syncFocusMs.worstCaseExpectedSquaredContractionFactor - 1e-12;
value.policyReceivedCurrentPageOnly = true;
value.posteriorSignalHeldNeutral = true;
value.adaptiveRouteDependsOnPastDeliveries = true;
value.postHocFixedRouteMeanSquareDiagnosticOnly = true;
value.closedLoopMeanSquareContractionCertified = false;
value.groundTruthGeneratedOrUsed = false;
value.measurementGeneratedOrUsed = false;
value.trackingOutcomeScored = false;
value.developmentEvidenceOnly = true;
value.canonicalSha256 = '';
value.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(value, 'canonicalSha256'));
fprintf(['  %s seed=%d messages=%d/%d fallback=%d ', ...
    'full=%d rhoFull=%.6g/%.6g rhoFocus=%.6g/%.6g\n'], ...
    presetName, seed, candidateMessageCount, syncMessageCount, ...
    value.candidateFallbackCount, ...
    fullReferenceMessageCount, ...
    candidateFullMs.worstCaseExpectedSquaredContractionFactor, ...
    syncFullMs.worstCaseExpectedSquaredContractionFactor, ...
    candidateFocusMs.worstCaseExpectedSquaredContractionFactor, ...
    syncFocusMs.worstCaseExpectedSquaredContractionFactor);
end

function context = buildCurrentContext(config, identity, registeredBase, ...
        positions, physical, pDrop, currentTime, adjacencyHistory, ...
        deliveryHistory, historyTimes, protocol)
nodeCount = config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = cell(1, nodeCount);
context.model = struct('dynamicTopologyScenario', struct( ...
    'config', struct('sensorGroupIds', config.sensorGroupIds), ...
    'staticAdjacency', logical(registeredBase)));
context.baseAdjacency = logical(registeredBase);
context.physicalAdjacency = logical(physical);
context.positions = positions;
context.sensorPhysicalUids = identity.sensorPhysicalUids;
context.formationPhysicalUidsBySensor = ...
    identity.formationPhysicalUidsBySensor;
context.physicalIdentityRegistryCanonicalSha256 = ...
    identity.canonicalSha256;
context.currentTime = currentTime;
context.commConfig = struct('pDropByEdge', pDrop);
context.triggerConfig = buildFormationB4V47FixedTriggerConfig( ...
    protocol.primaryArms{2}, nodeCount);
context.previousAdjacencyHistory = adjacencyHistory;
context.previousAdjacencyHistoryTimes = historyTimes;
context.previousDeliveryHistory = deliveryHistory;
context.previousDeliveryHistoryTimes = historyTimes;
context.observableInputContract = struct( ...
    'contractVersion', protocol.observableContractVersion, ...
    'passed', true, 'deliveryHistoryPresent', true, ...
    'pastDeliveryHistoryOnly', true, ...
    'deliveryHistoryAlignedToTopologyHistory', true, ...
    'deliveryHistoryAttemptSubset', true);
end

function [adjacency, weights] = ...
        buildSynchronizedPage(details, currentTime, protocol)
nodeCount = size(details.dominantAdjacency, 1);
phase = mod(currentTime - 1, protocol.period) + 1;
dominant = logical(details.dominantAdjacency);
residual = logical(details.residualAdjacency);
weights = zeros(nodeCount);
weights(dominant) = protocol.dominantWeight;
if phase == 1
    adjacency = dominant | residual;
    weights(residual) = protocol.maximumActiveResidualWeight;
else
    adjacency = dominant;
end
weights(1:nodeCount+1:end) = 1 - sum(weights, 2)';
end

function localIndices = resolveFocusLocalIndices(focusWindow, times)
focus = reshape(focusWindow, 1, []);
if numel(focus) == 2 && focus(2) >= focus(1)
    focus = focus(1):focus(2);
end
localIndices = find(ismember(times, focus));
end

function passed = everyRollingStrong(history, window)
passed = true;
for windowEnd = window:size(history, 3)
    passed = passed && isStronglyConnected( ...
        any(history(:, :, windowEnd-window+1:windowEnd), 3));
end
end

function passed = isStronglyConnected(adjacency)
passed = reachableAll(adjacency) && reachableAll(adjacency');
end

function passed = reachableAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
passed = all(visited);
end

function value = cappedMaximum(values, cap)
values = min(values, cap);
value = max(values);
end

function value = finiteMaximum(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function compact = compactMixing(full)
compact = repmat(struct(), 1, numel(full));
for idx = 1:numel(full)
    compact(idx).horizon = full(idx).horizon;
    compact(idx).minimumDobrushin = full(idx).minimumDobrushin;
    compact(idx).medianDobrushin = full(idx).medianDobrushin;
    compact(idx).worstDobrushin = full(idx).worstDobrushin;
    compact(idx).worstCenteredSpectralNorm = ...
        full(idx).worstCenteredSpectralNorm;
    compact(idx).supportScramblingWindowCount = ...
        full(idx).supportScramblingWindowCount;
    compact(idx).windowCount = full(idx).windowCount;
    compact(idx).everyProductSupportScrambling = ...
        full(idx).everyProductSupportScrambling;
end
end

function compact = compactMeanSquare(full)
compact = struct( ...
    'horizon', full.horizon, ...
    'worstCaseExpectedSquaredContractionFactor', ...
        full.worstCaseExpectedSquaredContractionFactor, ...
    'worstCaseExpectedRmsContractionFactor', ...
        full.worstCaseExpectedRmsContractionFactor, ...
    'allDeliveredSquaredContractionFactor', ...
        full.allDeliveredSquaredContractionFactor, ...
    'meanProductSquaredContractionFactor', ...
        full.meanProductSquaredContractionFactor, ...
    'strictMeanSquareContractionCertified', ...
        full.strictMeanSquareContractionCertified, ...
    'nonexpansiveMeanSquarePropagationCertified', ...
        full.nonexpansiveMeanSquarePropagationCertified);
end

function validateOptions(presets, seeds, times, horizons, ...
        deliverySeedOffset, progressEvery)
valid = iscell(presets) && ~isempty(presets) && ...
    all(cellfun(@(value) ischar(value) && isrow(value) && ...
        ~isempty(value), presets)) && ...
    isnumeric(seeds) && isreal(seeds) && ~isempty(seeds) && ...
    all(isfinite(seeds)) && all(seeds == round(seeds)) && ...
    (isempty(times) || (isnumeric(times) && isreal(times) && ...
        all(isfinite(times)) && all(times >= 1) && ...
        all(times == round(times)))) && ...
    isnumeric(horizons) && isreal(horizons) && ~isempty(horizons) && ...
    all(isfinite(horizons)) && all(horizons >= 1) && ...
    all(horizons == round(horizons)) && ...
    isequal(horizons, sort(unique(horizons))) && ...
    isscalar(deliverySeedOffset) && isfinite(deliverySeedOffset) && ...
    deliverySeedOffset == round(deliverySeedOffset) && ...
    isscalar(progressEvery) && isfinite(progressEvery) && ...
    progressEvery >= 1 && progressEvery == round(progressEvery);
if ~valid
    error('FormationB4V47Structural:InvalidOptions', ...
        'A V47 structural-screen option is invalid.');
end
end

