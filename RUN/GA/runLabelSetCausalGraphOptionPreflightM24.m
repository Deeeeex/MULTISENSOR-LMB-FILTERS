function [reportPath, preflight] = ...
    runLabelSetCausalGraphOptionPreflightM24( ...
        seed, currentTime, options)
% RUNLABELSETCAUSALGRAPHOPTIONPREFLIGHTM24 Causal H=3 option falsifier.
%
% Each row of actionSequences is a three-step option over CCW, CW and the
% label-set GNN. The first action graph and its fusion weights are computed
% from the complete saved predecision context and replayed exactly. The
% second and third controllers are recomputed from their actual live
% posterior, topology and restored local-update histories. Thus LLL is a
% causal closed-loop graph option, not an open-loop frozen graph sequence.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.macroActionPreflightAuthorized || ...
        protocol.returnValueGateHorizon ~= 3 || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Causal graph-option preflight is not authorized.');
end
seed = validateTrainingSeed(seed, protocol);
currentTime = validateSourceTime(currentTime, protocol);
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles) || ...
         gitState.researchWorktreeDirty)
    error(['Official graph-option preflight requires clean tracked ', ...
        'and MATLAB/Octave source state.']);
end

actionSequences = getField(options, 'actionSequences', ...
    protocol.macroActionSequences);
validateActionSequences(actionSequences, protocol);
exploratoryActionSubsetUsed = ...
    ~isequal(actionSequences, ...
        protocol.macroActionSequences);
if ~allowDirtySource && exploratoryActionSubsetUsed
    error(['Official graph-option preflight requires the exact ', ...
        'frozen action-sequence registry.']);
end
sourcePath = getField(options, 'sourcePath', ...
    fullfile(protocol.returnValueGateSourceDirectory, ...
        sprintf([ ...
            'label_set_ccw_return_source_m24_seed%d_v1.mat'], ...
            seed)));
sourceSha256 = computeFileSha256(sourcePath);
loadedSource = load(sourcePath, 'dataset');
if ~isfield(loadedSource, 'dataset')
    error('Graph-option source shard lacks dataset.');
end
source = loadedSource.dataset;
validateSource(source, seed, currentTime, ...
    protocol, allowDirtySource);
blockIdx = find([source.blocks.currentTime] == currentTime);
if numel(blockIdx) ~= 1
    error('Graph-option source state is not unique.');
end
sourceBlock = source.blocks(blockIdx);
if numel(sourceBlock.localUpdateHistoryTimes) ~= 3
    error(['Graph-option sentinel requires three complete GNN-used ', ...
        'local update-history pages.']);
end

modelPath = getField(options, 'modelPath', ...
    protocol.messagePassingInitializationPath);
modelSha256 = computeFileSha256(modelPath);
loadedModel = load(modelPath, 'model');
if ~isfield(loadedModel, 'model')
    error('Graph-option low-level model is missing.');
end
model = loadedModel.model;
validateLowLevelModel(model, modelPath, ...
    modelSha256, protocol);
if ~allowDirtySource && ...
        ~strcmp(modelPath, ...
            protocol.messagePassingInitializationPath)
    error('Official graph-option preflight requires the pinned model.');
end

inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCount
    error('Graph-option M24 scenario is invalid.');
end
returnTimes = currentTime + ...
    (0:(protocol.returnValueGateHorizon - 1));
inputs = cropInputs(inputs, returnTimes(end));
initialContext = buildPredecisionContext( ...
    sourceBlock, inputs, protocol);

sequenceCount = size(actionSequences, 1);
outcomes = repmat(emptyOutcome(), 1, sequenceCount);
sequenceNames = cell(1, sequenceCount);
firstActionGraphSha256 = cell(1, sequenceCount);
firstActionFusionWeightSha256 = cell(1, sequenceCount);
for sequenceIdx = 1:sequenceCount
    sequence = actionSequences(sequenceIdx, :);
    sequenceNames{sequenceIdx} = ...
        formatSequenceName(sequence);
    [firstAdjacency, firstDetails] = resolveAction( ...
        initialContext, sequence(1), ...
        model, protocol);
    firstActionGraphSha256{sequenceIdx} = ...
        computeTextSha256(sprintf( ...
            '%d,', firstAdjacency(:)));
    if ~isfield(firstDetails, 'fusionWeightMatrix')
        error('Graph-option first action lacks fusion weights.');
    end
    firstActionFusionWeightSha256{sequenceIdx} = ...
        computeTextSha256(sprintf('%.17g,', ...
            firstDetails.fusionWeightMatrix(:)));
    fprintf('M24 causal H=3 seed %d t=%d option %s...\n', ...
        seed, currentTime, sequenceNames{sequenceIdx});
    outcomes(sequenceIdx) = runOneSequence( ...
        inputs, sourceBlock, returnTimes, ...
        sequence, firstAdjacency, firstDetails, ...
        model, protocol);
    fprintf(['  E-OSPA %.6f, worst %.6f, consensus %.6f, ', ...
        'attempted %.0f B, %.2f s\n'], ...
        outcomes(sequenceIdx).meanEospa, ...
        outcomes(sequenceIdx).worstSensorEospa, ...
        outcomes(sequenceIdx).consensusOspa, ...
        outcomes(sequenceIdx).attemptedBytes, ...
        outcomes(sequenceIdx).elapsedSeconds);
end

referenceSequence = repmat( ...
    protocol.macroActionReferenceToken, ...
    1, protocol.returnValueGateHorizon);
referenceIdx = find(all( ...
    actionSequences == referenceSequence, 2));
if numel(referenceIdx) ~= 1
    error('Graph-option reference sequence is not unique.');
end
risk = [outcomes.meanEospa];
[bestMeanEospa, bestIdx] = min(risk);
referenceMeanEospa = risk(referenceIdx);
gainPercent = 100 * ...
    (referenceMeanEospa - bestMeanEospa) / ...
    max(referenceMeanEospa, eps);
byteDeviationPercent = 100 * ...
    ([outcomes.attemptedBytes] - ...
     outcomes(referenceIdx).attemptedBytes) / ...
    max(outcomes(referenceIdx).attemptedBytes, eps);

preflight = struct();
preflight.protocolId = protocol.id;
preflight.contractVersion = ...
    protocol.macroActionContractVersion;
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
preflight.seed = seed;
preflight.currentTime = currentTime;
preflight.returnTimes = returnTimes;
preflight.actionNames = ...
    protocol.macroActionNames;
preflight.actionSequences = actionSequences;
preflight.actionSequenceNames = sequenceNames;
preflight.actionSequenceSetSha256 = ...
    computeTextSha256(sprintf('%d,', ...
        actionSequences(:)));
preflight.firstActionGraphSha256 = ...
    firstActionGraphSha256;
preflight.firstActionFusionWeightSha256 = ...
    firstActionFusionWeightSha256;
preflight.referenceSequenceIndex = referenceIdx;
preflight.referenceMeanEospa = referenceMeanEospa;
preflight.outcomes = outcomes;
preflight.bestSequenceIndex = bestIdx;
preflight.bestSequence = ...
    actionSequences(bestIdx, :);
preflight.bestSequenceName = ...
    sequenceNames{bestIdx};
preflight.bestMeanEospa = bestMeanEospa;
preflight.bestGainVsReferencePercent = gainPercent;
preflight.attemptedByteDeviationPercent = ...
    byteDeviationPercent;
preflight.sourcePath = sourcePath;
preflight.sourceSha256 = sourceSha256;
preflight.lowLevelModelPath = modelPath;
preflight.lowLevelModelSha256 = modelSha256;
preflight.commonRandomNumbers = true;
preflight.firstActionGraphAndWeightsFrozen = true;
preflight.subsequentActionsCausal = true;
preflight.initialGnnUsedUpdateHistoryRestored = true;
preflight.exploratoryActionSubsetUsed = ...
    exploratoryActionSubsetUsed;
preflight.targetsUseTruth = true;
preflight.targetsUseFutureMeasurements = true;
preflight.runtimePolicyUsesTruth = ...
    any([outcomes.truthUseCount] > 0);
preflight.messageBudget = ...
    protocol.macroActionMessageBudget;
preflight.exactSelectedMessageCount = ...
    protocol.macroActionExpectedSelectedMessageCount;
preflight.trainingOnlyDiagnostic = true;
preflight.developmentOpened = false;
preflight.heldoutM24Opened = false;
preflight.x36Opened = false;
preflight.evidenceBoundary = [ ...
    'This opened-training preflight tests whether causal three-step ', ...
    'safe graph options expose delayed topology value that the ', ...
    'one-step-then-CCW target suppresses. It performs oracle ', ...
    'selection using future truth and does not establish a learned ', ...
    'policy, development, held-out M24 or X36 claim.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'causal_graph_option_preflight'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = sprintf( ...
    'label_set_causal_graph_option_h3_m24_seed%d_t%d', ...
    seed, currentTime);
artifactSuffix = getField(options, 'artifactSuffix', '');
if ~isempty(artifactSuffix)
    if ~ischar(artifactSuffix) || ...
            isempty(regexp(artifactSuffix, ...
                '^[A-Za-z0-9_-]+$', 'once'))
        error(['artifactSuffix must contain only letters, digits, ', ...
            'underscores or hyphens.']);
    end
    stem = sprintf('%s_%s', stem, artifactSuffix);
end
matPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [stem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(stem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Graph-option preflight output already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('Graph-option preflight: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function outcome = runOneSequence( ...
        inputs, sourceBlock, returnTimes, ...
        sequence, firstAdjacency, firstDetails, ...
        model, protocol)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = ...
    inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    protocol.macroActionMessageBudget;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'label-set-causal-h3-graph-option';
config.topologyPosteriorCaptureTimes = returnTimes;
config.topologyPolicyFcn = ...
    @(context) selectSequenceAction( ...
        context, returnTimes(1), sequence, ...
        firstAdjacency, firstDetails, ...
        model, protocol);
config.filterInitialLocalPosteriorBySensor = ...
    sourceBlock.initialLocalPosteriorBySensor;
config.filterInitialLocalPosteriorTime = ...
    sourceBlock.currentTime;
config.filterInitialLocalUpdateHistoryTimes = ...
    sourceBlock.localUpdateHistoryTimes;
config.filterInitialLocalInnovationHistory = ...
    sourceBlock.localInnovationHistory;
config.filterInitialLocalAssociationConfidenceHistory = ...
    sourceBlock.localAssociationConfidenceHistory;
config.filterInitialLocalNisNormHistory = ...
    sourceBlock.localNisNormHistory;
config.filterInitialLocalNisDeviationHistory = ...
    sourceBlock.localNisDeviationHistory;
config.filterInitialLocalUpdateHistoryCompleteWindowRequired = true;
config.filterInitialPreviousAdjacencyHistory = ...
    sourceBlock.previousAdjacencyHistory;
config.filterInitialPreviousAdjacencyTimes = ...
    sourceBlock.previousAdjacencyHistoryTimes;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'frozen-ccw-return-source-v1';

rng(sourceBlock.seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);
if ~diagnostics.usedInitialLocalUpdateHistory || ...
        ~isequal( ...
            diagnostics.initialLocalUpdateHistoryTimes, ...
            sourceBlock.localUpdateHistoryTimes) || ...
        ~isequal( ...
            diagnostics.initialLocalInnovationHistory, ...
            sourceBlock.localInnovationHistory) || ...
        ~isequal( ...
            diagnostics. ...
                initialLocalAssociationConfidenceHistory, ...
            sourceBlock. ...
                localAssociationConfidenceHistory) || ...
        ~isequaln( ...
            diagnostics.initialLocalNisNormHistory, ...
            sourceBlock.localNisNormHistory) || ...
        ~isequaln( ...
            diagnostics.initialLocalNisDeviationHistory, ...
            sourceBlock.localNisDeviationHistory)
    error(['Graph option did not restore all four GNN-used local ', ...
        'update histories exactly.']);
end

firstExecuted = ...
    convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge( ...
            :, :, returnTimes(1)));
if ~isequal(firstExecuted, logical(firstAdjacency))
    error('Graph option did not execute its first graph exactly.');
end
firstExecutedWeights = ...
    diagnostics.topologyPolicyFusionWeightMatrix{ ...
        returnTimes(1)};
if ~isequal(size(firstExecutedWeights), ...
        size(firstDetails.fusionWeightMatrix)) || ...
        max(abs(firstExecutedWeights(:) - ...
            firstDetails.fusionWeightMatrix(:))) > 1e-12
    error('Graph option did not execute its first weights exactly.');
end
messageCounts = ...
    diagnostics.topologyDirectedMessageCount(returnTimes);
if any(messageCounts ~= ...
        protocol.macroActionExpectedSelectedMessageCount)
    error('Graph option changed the exact message budget.');
end
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(returnTimes));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(returnTimes));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(returnTimes));
infeasible = logical( ...
    ~diagnostics.topologyFeasible(returnTimes) | ...
    finiteLogical(diagnostics. ...
        topologyPolicyTopologyInfeasible(returnTimes)));
if any(truthUse) || any(repair) || ...
        any(emergency) || any(infeasible)
    error('Graph option violated a hard runtime gate.');
end

nodeCount = inputs.config.numberOfSensors;
selected = false(nodeCount, nodeCount, numel(returnTimes));
delivered = selected;
for timeIdx = 1:numel(returnTimes)
    selected(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(timeIdx)));
    delivered(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered( ...
                :, :, returnTimes(timeIdx)));
end
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousAdjacencyHistory, ...
        selected, inputs.config.sensorGroupIds);
[deliveredSensorB3, deliveredFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousDeliveredAdjacencyHistory, ...
        delivered, inputs.config.sensorGroupIds);
if ~all(selectedSensorB3) || ...
        ~all(selectedFormationB3)
    error('Graph option violated selected rolling-B3 safety.');
end

sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(returnTimes));
cardinalityError = zeros(sensorCount, numel(returnTimes));
for sensorIdx = 1:sensorCount
    [sensorEospa, ~, sensorCardinality] = ...
        computeSimulationOspa( ...
            inputs.model, inputs.groundTruthRfs, ...
            estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(returnTimes);
    cardinalityError(sensorIdx, :) = abs( ...
        sensorCardinality(returnTimes) - ...
        inputs.groundTruthRfs.cardinality(returnTimes));
end
sensorMeans = mean(eospa, 2);
[~, ~, ospaDisagreement] = ...
    computeDistributedConsensusMetrics( ...
        estimates, inputs.model);
outcome = emptyOutcome();
outcome.meanEospa = mean(eospa(:));
outcome.worstSensorEospa = max(sensorMeans);
outcome.meanCardinalityError = ...
    mean(cardinalityError(:));
outcome.consensusOspa = finiteMean( ...
    ospaDisagreement(returnTimes));
outcome.attemptedBytes = sum(reshape( ...
    diagnostics.attemptedPayloadBytes( ...
        :, :, returnTimes), 1, []));
outcome.deliveredBytes = sum(reshape( ...
    diagnostics.payloadBytes( ...
        :, :, returnTimes), 1, []));
outcome.messageCounts = messageCounts;
outcome.selectedSensorB3Pass = selectedSensorB3;
outcome.selectedFormationB3Pass = ...
    selectedFormationB3;
outcome.deliveredSensorB3Pass = ...
    deliveredSensorB3;
outcome.deliveredFormationB3Pass = ...
    deliveredFormationB3;
outcome.truthUseCount = nnz(truthUse);
outcome.repairCount = nnz(repair);
outcome.payloadEmergencyCount = nnz(emergency);
outcome.infeasibleCount = nnz(infeasible);
outcome.firstActionExact = true;
outcome.elapsedSeconds = elapsedSeconds;
end

function [adjacency, details] = selectSequenceAction( ...
        context, anchorTime, sequence, ...
        firstAdjacency, firstDetails, ...
        model, protocol)
relativeTime = context.currentTime - anchorTime + 1;
if relativeTime < 1 || relativeTime > numel(sequence)
    actionToken = protocol.macroActionReferenceToken;
elseif relativeTime == 1
    adjacency = logical(firstAdjacency);
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:)))
        error('Frozen graph-option first action is physically invalid.');
    end
    details = firstDetails;
    details.mode = 'frozen-causal-graph-option-first-step';
    details.truthUsed = false;
    details.groundTruthUsed = false;
    details.futureOutcomeUsed = false;
    details.runtimeFrozenGraphReplay = true;
    return;
else
    actionToken = sequence(relativeTime);
end
[adjacency, details] = resolveAction( ...
    context, actionToken, model, protocol);
details.runtimeFrozenGraphReplay = false;
end

function [adjacency, details] = resolveAction( ...
        context, actionToken, model, protocol)
switch actionToken
    case 1
        [adjacency, details] = ...
            selectBackboneResidualSplicedCyclePolicy( ...
                context, 'fixed-counter-clockwise', ...
                staticPolicyOptions(protocol));
    case 2
        [adjacency, details] = ...
            selectBackboneResidualSplicedCyclePolicy( ...
                context, 'fixed-clockwise', ...
                staticPolicyOptions(protocol));
    case 3
        [adjacency, details] = ...
            selectLabelSetMessagePassingRoutingPolicy( ...
                context, model, struct( ...
                    'protocol', protocol, ...
                    'fixedResidualWeight', ...
                        protocol.localResidualWeight));
    otherwise
        error('Unknown graph-option action token.');
end
end

