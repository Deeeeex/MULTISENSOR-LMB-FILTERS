function writeReport(path, preflight)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write graph-option preflight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 causal H=3 safe graph-option preflight\n\n');
fprintf(fid, '- Seed / anchor: `%d / %d`\n', ...
    preflight.seed, preflight.currentTime);
fprintf(fid, '- Audit mode: `%s`\n', ...
    preflight.auditMode);
fprintf(fid, '- Return times: `%s`\n', ...
    mat2str(preflight.returnTimes));
fprintf(fid, '- Source SHA-256: `%s`\n', ...
    preflight.sourceSha256);
fprintf(fid, '- Source behavior: `%s`\n', ...
    preflight.sourceBehaviorAction);
fprintf(fid, '- Low-level model SHA-256: `%s`\n', ...
    preflight.lowLevelModelSha256);
fprintf(fid, '- Exact message budget per step: `%d`\n', ...
    preflight.exactSelectedMessageCount);
fprintf(fid, '- Restart equivalence passed: `%d`\n', ...
    preflight.restartEquivalencePassed);
fprintf(fid, '- Best option: `%s`\n', ...
    preflight.bestSequenceName);
fprintf(fid, '- Best gain versus CCC: `%.3f%%`\n\n', ...
    preflight.bestGainVsReferencePercent);
fprintf(fid, '- Registered projection failures: `%d`\n\n', ...
    preflight.registeredProjectionFailureCount);
fprintf(fid, ...
    ['| Option | Status | Mean E-OSPA | Worst | Card err | ', ...
     'Consensus | Attempted B | Byte dev. | B3 |\n']);
fprintf(fid, ...
    '|:--|:--|--:|--:|--:|--:|--:|--:|--:|\n');
for sequenceIdx = 1:numel(preflight.actionSequenceNames)
    row = preflight.outcomes(sequenceIdx);
    status = 'completed';
    if row.hardFailure
        status = 'infeasible';
    end
    fprintf(fid, ...
        ['| `%s` | %s | %.6f | %.6f | %.6f | %.6f | %.0f | ', ...
         '%+.3f%% | %d |\n'], ...
        preflight.actionSequenceNames{sequenceIdx}, ...
        status, ...
        row.meanEospa, row.worstSensorEospa, ...
        row.meanCardinalityError, row.consensusOspa, ...
        row.attemptedBytes, ...
        preflight.attemptedByteDeviationPercent(sequenceIdx), ...
        row.executionCompleted && ...
            all(row.selectedSensorB3Pass) && ...
            all(row.selectedFormationB3Pass));
end
failedIndices = find(preflight.actionHardFailure);
if ~isempty(failedIndices)
    fprintf(fid, '\n## Hard failures\n\n');
    for failedIdx = reshape(failedIndices, 1, [])
        row = preflight.outcomes(failedIdx);
        fprintf(fid, '- `%s`: `%s` — %s\n', ...
            preflight.actionSequenceNames{failedIdx}, ...
            row.failureIdentifier, row.failureMessage);
    end
end
fprintf(fid, '\n## Boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

