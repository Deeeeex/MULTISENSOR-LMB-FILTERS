function [sensorPass, formationPass] = ...
        computeRollingB3Pass(previousHistory, executed, groupIds)
history = logical(previousHistory);
sensorPass = false(1, size(executed, 3));
formationPass = sensorPass;
for stepIdx = 1:size(executed, 3)
    pages = cat(3, history, executed(:, :, stepIdx));
    window = any(pages(:, :, ...
        max(1, end - 2):end), 3);
    sensorPass(stepIdx) = isStronglyConnected(window);
    formationPass(stepIdx) = isStronglyConnected( ...
        collapseToFormations(window, groupIds));
    history(:, :, end + 1) = ...
        executed(:, :, stepIdx); %#ok<AGROW>
    if size(history, 3) > 2
        history = history(:, :, end-1:end);
    end
end
end

function formation = ...
        collapseToFormations(adjacency, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
formation = false(numel(groups));
for receiverGroupIdx = 1:numel(groups)
    receivers = groupIds == groups(receiverGroupIdx);
    for senderGroupIdx = 1:numel(groups)
        senders = groupIds == groups(senderGroupIdx);
        formation(receiverGroupIdx, senderGroupIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formation(1:numel(groups)+1:end) = false;
end

function connected = isStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
connected = true;
for startNode = 1:nodeCount
    visited = false(1, nodeCount);
    visited(startNode) = true;
    while true
        next = visited | any(adjacency(visited, :), 1);
        if isequal(next, visited)
            break;
        end
        visited = next;
    end
    if ~all(visited)
        connected = false;
        return;
    end
end
end

function adjacency = ...
        neighborMapToAdjacency(neighborMap, nodeCount)
adjacency = false(nodeCount);
for receiverIdx = 1:nodeCount
    senders = reshape(neighborMap{receiverIdx}, 1, []);
    senders = senders(senders ~= receiverIdx);
    adjacency(receiverIdx, senders) = true;
end
end

