function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantCertifiedOverlapHeldoutM24(seed, options)
% RUNLABELSETADAPTIVEDOMINANTCERTIFIEDOVERLAPHELDOUTM24
% Run one frozen v4 candidate/reference pair on a registered unseen seed.
%
% Each seed directory may contain at most one completed evidence artifact.
% The runner executes the frozen CCW reference and certified-overlap
% candidate together from the same generated continuation cache.

if nargin < 1 || isempty(seed)
    error('An explicitly registered held-out M24 seed is required.');
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantCertifiedOverlapHeldoutM24Authorized || ...
        ~protocol.adaptiveDominantCertifiedOverlapHeldoutM24OneShot || ...
        protocol.adaptiveDominantCertifiedOverlapHeldoutM24ValidationClaimAllowed || ...
        protocol.adaptiveDominantCertifiedOverlapX36Authorized || ...
        ~ismember(seed, protocol. ...
            adaptiveDominantCertifiedOverlapHeldoutM24Seeds)
    error('Certified-overlap held-out M24 seed is not authorized.');
end

rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_certified_overlap_v4', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantCertifiedOverlapSelectedMarginToken), ...
    'heldout'));
seedDirectory = fullfile(rootDirectory, sprintf('seed%d', seed));
if completedEvidenceExists(seedDirectory)
    error(['One-shot held-out evidence already exists for seed %d; ', ...
        'refusing to rerun it.'], seed);
end

screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(1), ...
    'armNames', {{ ...
        protocol.adaptiveDominantFullWindowReferenceArmName, ...
        protocol.adaptiveDominantCertifiedOverlapSelectedArmName}}, ...
    'writeReport', true, ...
    'outputDirectory', seedDirectory, ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile(rootDirectory, 'cache')), ...
    'generateMissingBehaviorCache', true, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'evidenceSplit', 'heldout-validation');
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    'm24-hard', seed, screenOptions);
end

function exists = completedEvidenceExists(seedDirectory)
exists = false;
if exist(seedDirectory, 'dir') ~= 7
    return;
end
exists = ~isempty(dir(fullfile(seedDirectory, '*.mat'))) || ...
    ~isempty(dir(fullfile(seedDirectory, '*.md')));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
