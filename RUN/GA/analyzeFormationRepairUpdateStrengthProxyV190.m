function [reportPath, result] = ...
        analyzeFormationRepairUpdateStrengthProxyV190( ...
            targetFormationId, options)
% ANALYZEFORMATIONREPAIRUPDATESTRENGTHPROXYV190 Truth-labelled triage only.
%
% This proxy ranks a causal shortlist by present/future predicted LMB task
% risk under hard replacement and residual label KLA.  Truth is used only
% offline to choose the next expensive recursive teacher; no future
% measurements or runtime policy decisions are read.

if nargin < 2 || isempty(options)
    options = struct();
end
if ~isscalar(targetFormationId) || ~isnumeric(targetFormationId) || ...
        ~isfinite(targetFormationId) || targetFormationId < 1 || ...
        targetFormationId ~= round(targetFormationId)
    error('FormationRepairUpdateStrengthProxyV190:InvalidFormation', ...
        'The target formation identifier must be a positive integer.');
end
analysisPath = char(getField(options, 'analysisPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v188', 'immediate_headroom', ...
    'x36_formation_fov_seed211_t72', ...
    'BUDGET_RECYCLED_REPAIR_V188_X36_FORMATION_FOV_SEED211_T72.mat')));
sourceWeight = getField(options, 'sourceWeight', 0.5);
horizonSteps = reshape(getField(options, 'horizonSteps', 0:2), 1, []);
shortlistOptions = getField(options, 'shortlistOptions', struct( ...
    'perCriterion', 2, 'maximumPerFormation', 12));
if ~isscalar(sourceWeight) || ~isnumeric(sourceWeight) || ...
        ~isfinite(sourceWeight) || sourceWeight <= 0 || sourceWeight >= 1
    error('FormationRepairUpdateStrengthProxyV190:InvalidWeight', ...
        'The residual source weight must lie strictly between zero and one.');
end

loaded = load(analysisPath, 'analysis');
analysis = loaded.analysis;
loadedScreen = load(analysis.screenPath, 'screen');
screen = loadedScreen.screen;
names = {screen.records.actionName};
baseIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), names), 1);
if isempty(baseIdx)
    error('FormationRepairUpdateStrengthProxyV190:MissingBaseArm', ...
        'The paired V99 base arm is absent.');
end
baseOutcome = screen.outcomes(baseIdx);
pageIdx = analysis.pageIndex;
localPosterior = baseOutcome.localPosteriorSnapshotsByTime{pageIdx};
fusedPosterior = baseOutcome.fusedPosteriorSnapshotsByTime{pageIdx};
inputs = generateDynamicTopologyScenarioInputs( ...
    analysis.presetName, analysis.seed);
model = inputs.model;
groupIds = reshape(screen.sensorGroupIds, 1, []);
if targetFormationId > max(groupIds)
    error('FormationRepairUpdateStrengthProxyV190:UnknownFormation', ...
        'The target formation is absent from the paired scene.');
end
physical = logical(inputs.graphData.physicalAdjacency( ...
    :, :, analysis.currentTime));
physical = physical | physical';
physical(1:numel(groupIds)+1:end) = false;

cache = buildFormationRepairLightSynopsisCacheV188( ...
    fusedPosterior, localPosterior, model, ...
    analysis.currentTime, struct());
[candidateBank, ~] = enumerateFormationCommonLabelRepairCandidatesV190( ...
    cache, physical, groupIds, struct());
[shortlist, shortlistDetails] = ...
    selectDiverseFormationRepairShortlistV190( ...
        candidateBank, shortlistOptions);
shortlist = shortlist([shortlist.formationId] == targetFormationId);
if isempty(shortlist)
    error('FormationRepairUpdateStrengthProxyV190:EmptyShortlist', ...
        'No causal shortlist candidate exists for the target formation.');
end

receiverIds = find(groupIds == targetFormationId);
riskOptions = struct( ...
    'horizonSteps', horizonSteps, ...
    'sensorAggregationMode', 'mean-cvar', ...
    'sensorCvarFraction', 0.25, ...
    'sensorCvarWeight', 0.5);
[baseRisk, baseDetails] = evaluateLmbTopologyTaskRisk( ...
    fusedPosterior(receiverIds), model, analysis.currentTime, riskOptions);
rows = repmat(emptyRow(), 1, numel(shortlist));
for candidateIdx = 1:numel(shortlist)
    candidate = shortlist(candidateIdx);
    [proposal, payloadDetails] = ...
        resolveFormationRepairCandidatePayloadV190( ...
            candidate, localPosterior, physical, model, struct());
    row = emptyRow();
    row.formationId = targetFormationId;
    row.sourceId = candidate.sourceId;
    row.label = candidate.label;
    row.minimumRiskReduction = candidate.minimumRiskReduction;
    row.precisionGain = candidate.precisionGainNormalized;
    row.opportunity = candidate.opportunityMedian;
    row.payloadBytes = proposal.attemptedBytes;
    row.safetyPassed = proposal.safetyPassed && ...
        payloadDetails.completePayloadResolved;
    if row.safetyPassed
        hardPosterior = applyFormationCommonLabelRepairV188( ...
            fusedPosterior, proposal, 1);
        klaPosterior = applyFormationCommonLabelKlaRepairV190( ...
            fusedPosterior, proposal, 1, model, ...
            struct('sourceWeight', sourceWeight));
        [row.hardRisk, hardDetails] = evaluateLmbTopologyTaskRisk( ...
            hardPosterior(receiverIds), model, ...
            analysis.currentTime, riskOptions);
        [row.klaRisk, klaDetails] = evaluateLmbTopologyTaskRisk( ...
            klaPosterior(receiverIds), model, ...
            analysis.currentTime, riskOptions);
        row.hardRiskGainPercent = relativeGain( ...
            baseRisk, row.hardRisk);
        row.klaRiskGainPercent = relativeGain( ...
            baseRisk, row.klaRisk);
        row.hardPositionGainPercent = relativeGain( ...
            baseDetails.positionRisk, hardDetails.positionRisk);
        row.klaPositionGainPercent = relativeGain( ...
            baseDetails.positionRisk, klaDetails.positionRisk);
    end
    rows(candidateIdx) = row;
end
ranking = arrayfun(@(row) max( ...
    row.hardRiskGainPercent, row.klaRiskGainPercent), rows);
ranking(~isfinite(ranking)) = -inf;
[~, order] = sort(ranking, 'descend');
rows = rows(order);

result = struct();
result.contractVersion = ...
    'formation-repair-update-strength-proxy-v190-v1';
result.generatedAt = datestr(now, 31);
result.presetName = analysis.presetName;
result.seed = analysis.seed;
result.currentTime = analysis.currentTime;
result.targetFormationId = targetFormationId;
result.receiverIds = receiverIds;
result.sourceWeight = sourceWeight;
result.horizonSteps = horizonSteps;
result.baseRisk = baseRisk;
result.baseRiskDetails = baseDetails;
result.rows = rows;
result.shortlistDetails = shortlistDetails;
result.truthUsedForOfflineScoring = true;
result.futureMeasurementsUsed = false;
result.runtimePolicyAuthorized = false;
result.recursiveTrackingBenefitClaimed = false;
result.evidenceBoundary = [ ...
    'Truth scores a no-future-measurement posterior-risk proxy only. ', ...
    'The causal shortlist and payload resolver remain truth-free, but ', ...
    'this ranking is teacher triage rather than deployable policy or ', ...
    'recursive tracking evidence.'];

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v190', 'update_strength_proxy')));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
stem = sprintf('V190_%s_F%d_UPDATE_STRENGTH_PROXY', ...
    upper(strrep(analysis.presetName, '-', '_')), targetFormationId);
matPath = fullfile(outputRoot, [stem, '.mat']);
reportPath = fullfile(outputRoot, [stem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V190 update-strength proxy: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FormationRepairUpdateStrengthProxyV190:WriteFailed', ...
        'Could not create the proxy report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V190 formation-%d update-strength proxy\n\n', ...
    result.targetFormationId);
fprintf(fid, '- Scene / seed / time: `%s` / `%d` / `%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Prediction horizons: `%s`\n', ...
    mat2str(result.horizonSteps));
fprintf(fid, '- Residual KLA source weight: `%.3f`\n', ...
    result.sourceWeight);
fprintf(fid, '- Base task risk: `%.6f`\n\n', result.baseRisk);
fprintf(fid, ['| Source | Label | Min causal risk | Precision gain | ', ...
    'Hard task gain | KLA task gain | Hard position gain | ', ...
    'KLA position gain | Bytes |\n']);
fprintf(fid, '|--:|:--|--:|--:|--:|--:|--:|--:|--:|\n');
for rowIdx = 1:numel(result.rows)
    row = result.rows(rowIdx);
    fprintf(fid, ['| %d | `[%d,%d]` | %.5f | %.5f | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        row.sourceId, row.label(1), row.label(2), ...
        row.minimumRiskReduction, row.precisionGain, ...
        row.hardRiskGainPercent, row.klaRiskGainPercent, ...
        row.hardPositionGainPercent, row.klaPositionGainPercent, ...
        round(row.payloadBytes));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = emptyRow()
value = struct( ...
    'formationId', 0, ...
    'sourceId', 0, ...
    'label', zeros(2, 1), ...
    'minimumRiskReduction', 0, ...
    'precisionGain', 0, ...
    'opportunity', 0, ...
    'payloadBytes', 0, ...
    'safetyPassed', false, ...
    'hardRisk', nan, ...
    'klaRisk', nan, ...
    'hardRiskGainPercent', nan, ...
    'klaRiskGainPercent', nan, ...
    'hardPositionGainPercent', nan, ...
    'klaPositionGainPercent', nan);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
