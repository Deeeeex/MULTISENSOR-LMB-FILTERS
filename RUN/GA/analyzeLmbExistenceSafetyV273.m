function validateOracle(oracle, protocol)
required = {'generationGitCommit', 'presetName', 'seed', ...
    'cachePath', 'windows'};
valid = isstruct(oracle) && isscalar(oracle) && ...
    all(isfield(oracle, required)) && ...
    strcmp(oracle.presetName, protocol.allowedPreset) && ...
    oracle.seed == protocol.allowedSeed && ...
    numel(oracle.windows) == numel(protocol.anchorTimes);
if valid
    for windowIdx = 1:numel(oracle.windows)
        window = oracle.windows{windowIdx};
        valid = valid && isstruct(window) && isscalar(window) && ...
            window.anchorTime == protocol.anchorTimes(windowIdx) && ...
            numel(window.candidateAssignments) == window.candidateCount && ...
            numel(window.candidateTypes) == window.candidateCount && ...
            numel(window.arms) == window.candidateCount && ...
            numel(window.comparisons) == window.candidateCount;
    end
end
if ~valid
    error('LmbExistenceSafetyV273:OracleContractDrift', ...
        'The supplied V250 oracle violates the frozen V273 contract.');
end
end

function writeReportFile(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('LmbExistenceSafetyV273:ReportOpen', ...
        'Could not write the V273 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V273 operator-aligned LMB existence-safety diagnostic\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    summary.presetName, summary.seed);
fprintf(fid, '- Analysis commit: `%s`\n', summary.analysisGitCommit);
fprintf(fid, '- V250 oracle commit: `%s`\n', ...
    summary.oracleGenerationGitCommit);
fprintf(fid, '- Anchors: `%s`\n', mat2str(summary.anchorTimes));
fprintf(fid, '- Stable safety signal found: `%d`\n', ...
    summary.stableSafetySignalFound);
fprintf(fid, '- New tracking / GNN authorized: `%d / %d`\n', ...
    summary.newTrackingOutcomeAuthorized, summary.gnnAuthorized);
fprintf(fid, '- Next decision: `%s`\n', summary.nextDecision);
fprintf(fid, '- Runtime: `%.1f s`\n\n', summary.elapsedSeconds);

fprintf(fid, '## Signal gate\n\n');
fprintf(fid, ['| Risk signal | Card. rho by anchor | E-harm rho by anchor | ', ...
    'LOAO balanced / recall / specificity | Useful retained | Pass |\n']);
fprintf(fid, '|:--|:--|:--|:--|:--|:--:|\n');
for signalIdx = 1:numel(summary.signalResults)
    signal = summary.signalResults(signalIdx);
    fprintf(fid, '| `%s` | `%s` | `%s` | %.3f / %.3f / %.3f | `%s` | %d |\n', ...
        signal.name, mat2str( ...
            signal.anchorCardinalityRankCorrelation, 3), ...
        mat2str(signal.anchorEospaHarmRankCorrelation, 3), ...
        signal.loaoBalancedAccuracy, signal.loaoHarmRecall, ...
        signal.loaoHarmlessSpecificity, ...
        mat2str(signal.usefulRetainedByAnchor), ...
        signal.gatePassed);
end

fprintf(fid, '\n## Candidate evidence\n\n');
fprintf(fid, ['| t | Candidate | Type | Retention risk | Min retention | ', ...
    'MAP drops | One-round disagreement change | H=3 E gain | ', ...
    'Min-formation E gain | Card-error delta | Harm | Useful |\n']);
fprintf(fid, '|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
for windowIdx = 1:numel(summary.windowRecords)
    records = summary.windowRecords{windowIdx}.records;
    for recordIdx = 1:numel(records)
        record = records(recordIdx);
        disagreementChange = (record.candidateDisagreement - ...
            record.referenceDisagreement) / ...
            max(record.referenceDisagreement, eps);
        fprintf(fid, ['| %d | %d | `%s` | %.6f | %.6f | %d | ', ...
            '%+.3f%% | %+.4f%% | %+.4f%% | %+.5f | %d | %d |\n'], ...
            record.anchorTime, record.candidateIndex, ...
            record.candidateType, record.retentionRisk, ...
            record.minimumSupportedLabelRetentionRatio, ...
            record.decisionThresholdCrossingCount, ...
            100 * disagreementChange, record.eospaGainPercent, ...
            record.minimumFormationEospaGainPercent, ...
            record.cardinalityErrorDelta, record.materialHarm, ...
            record.usefulAction);
    end
end

fprintf(fid, '\n## Interpretation\n\n');
if summary.stableSafetySignalFound
    best = summary.signalResults(summary.bestSignalIndex);
    fprintf(fid, ['`%s` passes the frozen cross-anchor diagnostic gate. ', ...
        'This authorizes design of a charged, distributed safety projector; ', ...
        'it does not authorize another tracking run. Structural mixing may ', ...
        'be optimized only inside the projected safe set.\n\n'], best.name);
else
    fprintf(fid, ['No operator-aligned scalar existence-safety quantity ', ...
        'passes the frozen cross-anchor gate. Contraction-first gateway ', ...
        'substitution is therefore closed as a deployable method family ', ...
        'on the current evidence; fitting a GNN to these three anchors is ', ...
        'not authorized.\n\n']);
end
fprintf(fid, ['Conditional set RMSE is secondary: a lower RMSE is not ', ...
    'called localization improvement when cardinality error or E-OSPA ', ...
    'worsens. One-round disagreement is diagnostic only and is not a ', ...
    'recursive consensus certificate.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', summary.evidenceBoundary);
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    ~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once')));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
