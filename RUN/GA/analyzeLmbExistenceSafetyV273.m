function [reportPath, summary] = analyzeLmbExistenceSafetyV273(options)
% ANALYZELMBEXISTENCESAFETYV273 Test operator-aligned harm prediction.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLmbExistenceSafetyDiagnosticV273Protocol();
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
checkpointPath = char(getField(options, 'checkpointPath', fullfile( ...
    repoRoot, getCausalGatewayEmbeddingV250Protocol().oracleOutputRoot, ...
    'CAUSAL_GATEWAY_EMBEDDING_V250_H3_ORACLE.mat')));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    repoRoot, protocol.outputRoot)));
writeReport = logical(getField(options, 'writeReport', true));
writeMat = logical(getField(options, 'writeMat', true));
if ~isAbsolutePath(checkpointPath)
    checkpointPath = fullfile(repoRoot, checkpointPath);
end
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if ~isscalar(writeReport) || ~isscalar(writeMat) || ...
        exist(checkpointPath, 'file') ~= 2
    error('LmbExistenceSafetyV273:InvalidRequest', ...
        'V273 requires one completed V250 H=3 checkpoint.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('LmbExistenceSafetyV273:DirtySource', ...
        'Official V273 analysis requires clean source.');
end

loaded = load(checkpointPath, 'result');
if ~isfield(loaded, 'result')
    error('LmbExistenceSafetyV273:MissingOracle', ...
        'The V250 checkpoint does not contain its result structure.');
end
oracle = loaded.result;
validateOracle(oracle, protocol);
if exist(oracle.cachePath, 'file') ~= 2
    error('LmbExistenceSafetyV273:MissingBehaviorCache', ...
        'The V250 current-posterior behavior cache is unavailable.');
end
cached = load(oracle.cachePath, 'behaviorBundle');
if ~isfield(cached, 'behaviorBundle')
    error('LmbExistenceSafetyV273:MissingBehaviorCache', ...
        'The V250 cache does not contain behaviorBundle.');
end
bundle = cached.behaviorBundle;
inputs = generateDynamicTopologyScenarioInputs( ...
    oracle.presetName, oracle.seed);
runtimeModel = removeRealizedTargetTruthFromDynamicTopologyModel( ...
    inputs.model);
identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);

windowRecords = cell(1, numel(oracle.windows));
allRecords = repmat(emptyRecord(numel(protocol.riskFeatureNames)), 1, 0);
analysisTimer = tic;
for windowIdx = 1:numel(oracle.windows)
    window = oracle.windows{windowIdx};
    [posteriors, history] = extractBehaviorContinuationSnapshot( ...
        bundle, window.anchorTime, inputs.config.numberOfSensors);
    context = buildContext(inputs, runtimeModel, identity, posteriors, ...
        history, window.anchorTime);
    referenceIdx = window.referenceCandidateIndex;
    [referenceAdjacency, referenceDetails] = ...
        selectCausalGatewayEmbeddingV250Policy( ...
            context, window.candidateAssignments{referenceIdx});
    referenceWeights = referenceDetails.fusionWeightMatrix;
    enumerationOptions = struct('maximumIncomingCount', ...
        protocol.maximumIncomingCount);
    [referenceDisagreement, referenceNetwork] = ...
        computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
            context, referenceAdjacency, referenceWeights, ...
            enumerationOptions);
    currentRecords = repmat( ...
        emptyRecord(numel(protocol.riskFeatureNames)), ...
        1, window.candidateCount);
    for candidateIdx = 1:window.candidateCount
        fprintf('V273 anchor %d candidate %02d/%02d ...\n', ...
            window.anchorTime, candidateIdx, window.candidateCount);
        [adjacency, routeDetails] = ...
            selectCausalGatewayEmbeddingV250Policy( ...
                context, window.candidateAssignments{candidateIdx});
        weights = routeDetails.fusionWeightMatrix;
        if candidateIdx == referenceIdx
            candidateDisagreement = referenceDisagreement;
            candidateNetwork = referenceNetwork;
        else
            candidateOptions = enumerationOptions;
            candidateOptions.referenceNetworkDetails = referenceNetwork;
            candidateOptions.referenceAdjacency = referenceAdjacency;
            candidateOptions.referenceFusionWeights = referenceWeights;
            [candidateDisagreement, candidateNetwork] = ...
                computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
                    context, adjacency, weights, candidateOptions);
        end
        retentionOptions = struct( ...
            'referenceSupportThreshold', ...
                protocol.referenceSupportThreshold, ...
            'decisionExistenceThreshold', ...
                protocol.decisionExistenceThreshold, ...
            'receiverTailFraction', ...
                protocol.retentionReceiverTailFraction, ...
            'receiverTailWeight', ...
                protocol.retentionReceiverTailWeight);
        [retentionRisk, retention] = ...
            computeLmbReferenceExistenceRetentionRisk( ...
                referenceNetwork.receiverDistributions, ...
                candidateNetwork.receiverDistributions, ...
                groupIds, retentionOptions);
        riskFeatures = buildRiskFeatures( ...
            retentionRisk, retention, referenceDisagreement, ...
            candidateDisagreement);
        if numel(riskFeatures) ~= numel(protocol.riskFeatureNames) || ...
                any(~isfinite(riskFeatures))
            error('LmbExistenceSafetyV273:FeatureContractDrift', ...
                'The V273 risk feature contract changed.');
        end
        record = buildRecord(window, windowIdx, candidateIdx, ...
            riskFeatures, protocol);
        record.referenceDisagreement = referenceDisagreement;
        record.candidateDisagreement = candidateDisagreement;
        record.changedReceiverCount = nnz(any( ...
            adjacency ~= referenceAdjacency, 2) | any( ...
            weights ~= referenceWeights, 2));
        record.retentionRisk = retentionRisk;
        record.minimumSupportedLabelRetentionRatio = min( ...
            retention.minimumSupportedLabelRetentionRatio);
        record.decisionThresholdCrossingCount = sum( ...
            retention.decisionThresholdCrossingCount);
        currentRecords(candidateIdx) = record;
        allRecords(end + 1) = record; %#ok<AGROW>
    end
    windowRecord = struct();
    windowRecord.anchorTime = window.anchorTime;
    windowRecord.referenceCandidateIndex = referenceIdx;
    windowRecord.records = currentRecords;
    windowRecords{windowIdx} = windowRecord;
end

nonreference = allRecords(~[allRecords.isReference]);
featureMatrix = vertcat(nonreference.riskFeatures);
cardinalityDelta = [nonreference.cardinalityErrorDelta]';
eospaHarm = -[nonreference.eospaGainPercent]';
anchorIndices = [nonreference.anchorIndex]';
signalResults = repmat(emptySignalResult(), ...
    1, numel(protocol.riskFeatureNames));
for featureIdx = 1:numel(protocol.riskFeatureNames)
    signalResults(featureIdx) = evaluateSignal( ...
        nonreference, featureMatrix(:, featureIdx), ...
        cardinalityDelta, eospaHarm, anchorIndices, protocol);
    signalResults(featureIdx).name = ...
        protocol.riskFeatureNames{featureIdx};
end
passes = [signalResults.gatePassed];
if any(passes)
    passedIndices = find(passes);
    scores = [signalResults(passedIndices).loaoBalancedAccuracy];
    [~, bestLocal] = max(scores);
    bestSignalIndex = passedIndices(bestLocal);
    nextDecision = ...
        'design-charged-distributed-safety-projector-before-tracking';
else
    bestSignalIndex = NaN;
    nextDecision = ...
        'close-contraction-first-gateway-substitution-family';
end

summary = struct();
summary.contractVersion = ...
    'lmb-existence-safety-diagnostic-v273-result-v1';
summary.protocol = protocol;
summary.analysisGitCommit = gitState.commit;
summary.oracleGenerationGitCommit = oracle.generationGitCommit;
summary.checkpointPath = checkpointPath;
summary.behaviorCachePath = oracle.cachePath;
summary.presetName = oracle.presetName;
summary.seed = oracle.seed;
summary.anchorTimes = protocol.anchorTimes;
summary.riskFeatureNames = protocol.riskFeatureNames;
summary.windowRecords = windowRecords;
summary.signalResults = signalResults;
summary.bestSignalIndex = bestSignalIndex;
summary.nextDecision = nextDecision;
summary.stableSafetySignalFound = any(passes);
summary.onlineSafetyProjectorDesignAuthorized = any(passes);
summary.newTrackingOutcomeAuthorized = false;
summary.gnnAuthorized = false;
summary.centralizedCurrentPosteriorRequired = true;
summary.controlMetadataCharged = false;
summary.truthUsedByPredictors = false;
summary.futureInformationUsedByPredictors = false;
summary.truthUsedByReusedOutcomeLabels = true;
summary.developmentEvidenceOnly = true;
summary.validationClaimAllowed = false;
summary.elapsedSeconds = toc(analysisTimer);
summary.completedAt = datestr(now, 31);
summary.evidenceBoundary = protocol.evidenceBoundary;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
reportPath = fullfile(outputRoot, protocol.reportFileName);
matPath = fullfile(outputRoot, protocol.matFileName);
summary.reportPath = reportPath;
summary.matPath = matPath;
if writeMat
    save('-mat7-binary', matPath, 'summary');
end
if writeReport
    writeReportFile(reportPath, summary);
end
fprintf('V273 stable safety signal: %d; next=%s\n', ...
    summary.stableSafetySignalFound, summary.nextDecision);
fprintf('V273 report: %s\n', reportPath);
end

function context = buildContext( ...
        inputs, runtimeModel, identity, posteriors, history, currentTime)
nodeCount = inputs.config.numberOfSensors;
formationCount = numel(unique(inputs.config.sensorGroupIds));
context = struct();
context.localPosteriorBySensor = posteriors;
context.model = runtimeModel;
context.baseAdjacency = logical(inputs.graphData.staticAdjacency);
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
context.positions = inputs.graphData.positions(:, :, currentTime);
context.currentTime = currentTime;
context.commConfig = inputs.commConfig;
context.commConfig.pDropByEdge = ...
    inputs.commConfig.pDropByEdge(:, :, currentTime);
context.triggerConfig = ...
    buildCausalMinimumFormationBackboneV242Config(inputs.config);
context.directedMessageBudget = nodeCount + 2 * (formationCount - 1);
context.sensorPhysicalUids = identity.sensorPhysicalUids;
context.formationPhysicalUidsBySensor = ...
    identity.formationPhysicalUidsBySensor;
context.previousAdjacencyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
context.previousAdjacencyHistoryCount = ...
    size(context.previousAdjacencyHistory, 3);
context.previousAdjacencyHistoryTimes = history.times;
end

function features = buildRiskFeatures( ...
        risk, details, referenceDisagreement, candidateDisagreement)
features = [ ...
    risk, ...
    max(details.receiverRisk), ...
    max(details.formationRisk), ...
    max(-min(details.expectedCardinalityChange), 0), ...
    max(-min(details.formationMeanCardinalityChange), 0), ...
    max(1 - min(details.minimumSupportedLabelRetentionRatio), 0), ...
    sum(details.decisionThresholdCrossingCount), ...
    sum(details.decisionThresholdCrossingMass), ...
    max(details.referenceWeightedExistenceShortfall), ...
    mean(details.referenceWeightedExistenceShortfall), ...
    max(details.normalizedExistenceDrift), ...
    mean(details.normalizedExistenceDrift), ...
    (candidateDisagreement - referenceDisagreement) / ...
        max(referenceDisagreement, eps)];
end

function record = buildRecord( ...
        window, windowIdx, candidateIdx, riskFeatures, protocol)
comparison = window.comparisons{candidateIdx};
arm = window.arms{candidateIdx};
referenceArm = window.arms{window.referenceCandidateIndex};
cardinalityDelta = arm.meanAbsoluteCardinalityError - ...
    referenceArm.meanAbsoluteCardinalityError;
eospaGain = comparison.eospaGainPercent;
minimumFormationEospaGain = ...
    comparison.minimumFormationEospaGainPercent;
materialHarm = cardinalityDelta > protocol.numericTolerance || ...
    eospaGain < -protocol.materialNetworkEospaRegressionPercent || ...
    minimumFormationEospaGain < ...
        -protocol.materialFormationEospaRegressionPercent;
useful = eospaGain > ...
        protocol.usefulMinimumNetworkEospaGainPercent && ...
    cardinalityDelta <= protocol.numericTolerance && ...
    minimumFormationEospaGain >= ...
        -protocol.usefulMaximumFormationEospaRegressionPercent && ...
    comparison.rmseGainPercent > 0 && ...
    comparison.consistencyGainPercent >= 0 && ...
    comparison.attemptedByteSavingPercent >= 0;
record = emptyRecord(numel(riskFeatures));
record.anchorIndex = windowIdx;
record.anchorTime = window.anchorTime;
record.candidateIndex = candidateIdx;
record.candidateType = window.candidateTypes{candidateIdx};
record.isReference = candidateIdx == window.referenceCandidateIndex;
record.riskFeatures = riskFeatures;
record.eospaGainPercent = eospaGain;
record.minimumFormationEospaGainPercent = minimumFormationEospaGain;
record.rmseGainPercent = comparison.rmseGainPercent;
record.consistencyGainPercent = comparison.consistencyGainPercent;
record.attemptedByteSavingPercent = ...
    comparison.attemptedByteSavingPercent;
record.cardinalityErrorDelta = cardinalityDelta;
record.materialHarm = materialHarm;
record.usefulAction = useful;
end

function result = evaluateSignal( ...
        records, values, cardinalityDelta, eospaHarm, ...
        anchorIndices, protocol)
anchorCount = numel(protocol.anchorTimes);
cardinalityCorrelation = zeros(1, anchorCount);
eospaHarmCorrelation = zeros(1, anchorCount);
thresholds = nan(1, anchorCount);
predictedHarm = false(size(values));
usefulRetainedByAnchor = zeros(1, anchorCount);
for anchorIdx = 1:anchorCount
    anchorMask = anchorIndices == anchorIdx;
    cardinalityCorrelation(anchorIdx) = rankCorrelation( ...
        values(anchorMask), cardinalityDelta(anchorMask));
    eospaHarmCorrelation(anchorIdx) = rankCorrelation( ...
        values(anchorMask), eospaHarm(anchorMask));
    trainMask = ~anchorMask;
    thresholds(anchorIdx) = selectTrainingThreshold( ...
        values(trainMask), [records(trainMask).materialHarm]', ...
        [records(trainMask).usefulAction]', ...
        anchorIndices(trainMask));
    predictedHarm(anchorMask) = ...
        values(anchorMask) > thresholds(anchorIdx) + ...
            protocol.numericTolerance;
    usefulRetainedByAnchor(anchorIdx) = nnz( ...
        [records(anchorMask).usefulAction]' & ...
        ~predictedHarm(anchorMask));
end
observedHarm = [records.materialHarm]';
[balancedAccuracy, recall, specificity, confusion] = ...
    classificationMetrics(observedHarm, predictedHarm);
medianCardinality = median(cardinalityCorrelation);
medianEospa = median(eospaHarmCorrelation);
nonnegativeCardinalityCount = nnz(cardinalityCorrelation >= ...
    -protocol.numericTolerance);
nonnegativeEospaCount = nnz(eospaHarmCorrelation >= ...
    -protocol.numericTolerance);
usefulRetentionPassed = ...
    ~protocol.requireUsefulActionRetainedAtEveryAnchor || ...
    all(usefulRetainedByAnchor >= 1);
gatePassed = ...
    balancedAccuracy >= protocol.minimumLoaoBalancedAccuracy && ...
    recall >= protocol.minimumLoaoHarmRecall && ...
    specificity >= protocol.minimumLoaoHarmlessSpecificity && ...
    medianCardinality >= ...
        protocol.minimumMedianCardinalityRankCorrelation && ...
    medianEospa >= ...
        protocol.minimumMedianEospaHarmRankCorrelation && ...
    nonnegativeCardinalityCount >= ...
        protocol.minimumNonnegativeAnchorCorrelationCount && ...
    nonnegativeEospaCount >= ...
        protocol.minimumNonnegativeAnchorCorrelationCount && ...
    usefulRetentionPassed;
result = emptySignalResult();
result.anchorCardinalityRankCorrelation = cardinalityCorrelation;
result.anchorEospaHarmRankCorrelation = eospaHarmCorrelation;
result.medianCardinalityRankCorrelation = medianCardinality;
result.medianEospaHarmRankCorrelation = medianEospa;
result.loaoThresholdByHeldoutAnchor = thresholds;
result.loaoBalancedAccuracy = balancedAccuracy;
result.loaoHarmRecall = recall;
result.loaoHarmlessSpecificity = specificity;
result.loaoConfusion = confusion;
result.usefulRetainedByAnchor = usefulRetainedByAnchor;
result.gatePassed = gatePassed;
end

function threshold = selectTrainingThreshold( ...
        values, harm, useful, anchorIndices)
candidates = unique(values(:));
candidates = [-inf; candidates; inf];
bestScore = -inf;
bestRecall = -inf;
bestUsefulRetention = -inf;
threshold = inf;
trainingAnchors = unique(anchorIndices(:))';
for candidateIdx = 1:numel(candidates)
    current = candidates(candidateIdx);
    predicted = values > current;
    [balanced, recall, ~, ~] = ...
        classificationMetrics(harm, predicted);
    acceptedUseful = useful & ~predicted;
    retainsEachTrainingAnchor = true;
    for anchorIdx = trainingAnchors
        if any(useful(anchorIndices == anchorIdx)) && ...
                ~any(acceptedUseful(anchorIndices == anchorIdx))
            retainsEachTrainingAnchor = false;
            break;
        end
    end
    if ~retainsEachTrainingAnchor
        continue;
    end
    usefulRetention = sum(acceptedUseful) / max(sum(useful), 1);
    score = balanced;
    better = score > bestScore + 1e-12 || ...
        (abs(score - bestScore) <= 1e-12 && ...
         recall > bestRecall + 1e-12) || ...
        (abs(score - bestScore) <= 1e-12 && ...
         abs(recall - bestRecall) <= 1e-12 && ...
         usefulRetention > bestUsefulRetention + 1e-12) || ...
        (abs(score - bestScore) <= 1e-12 && ...
         abs(recall - bestRecall) <= 1e-12 && ...
         abs(usefulRetention - bestUsefulRetention) <= 1e-12 && ...
         current < threshold);
    if better
        bestScore = score;
        bestRecall = recall;
        bestUsefulRetention = usefulRetention;
        threshold = current;
    end
end
end

function [balanced, recall, specificity, confusion] = ...
        classificationMetrics(observedHarm, predictedHarm)
observedHarm = logical(observedHarm(:));
predictedHarm = logical(predictedHarm(:));
tp = nnz(observedHarm & predictedHarm);
fn = nnz(observedHarm & ~predictedHarm);
tn = nnz(~observedHarm & ~predictedHarm);
fp = nnz(~observedHarm & predictedHarm);
recall = tp / max(tp + fn, 1);
specificity = tn / max(tn + fp, 1);
balanced = 0.5 * (recall + specificity);
confusion = [tp, fn, tn, fp];
end

function rho = rankCorrelation(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
if numel(left) ~= numel(right) || isempty(left) || ...
        any(~isfinite(left)) || any(~isfinite(right))
    error('LmbExistenceSafetyV273:InvalidCorrelationInput', ...
        'Rank-correlation inputs are invalid.');
end
leftRank = tiedRanks(left);
rightRank = tiedRanks(right);
leftRank = leftRank - mean(leftRank);
rightRank = rightRank - mean(rightRank);
denominator = norm(leftRank) * norm(rightRank);
if denominator <= eps
    rho = 0;
else
    rho = (leftRank' * rightRank) / denominator;
end
end

function ranks = tiedRanks(values)
[sorted, order] = sort(values);
ranks = zeros(size(values));
cursor = 1;
while cursor <= numel(values)
    last = cursor;
    while last < numel(values) && sorted(last + 1) == sorted(cursor)
        last = last + 1;
    end
    ranks(order(cursor:last)) = mean(cursor:last);
    cursor = last + 1;
end
end

