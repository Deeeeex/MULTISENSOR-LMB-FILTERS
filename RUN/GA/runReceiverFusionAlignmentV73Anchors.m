function [reportPath, result] = ...
    runReceiverFusionAlignmentV73Anchors(options)
% RUNRECEIVERFUSIONALIGNMENTV73ANCHORS Source-only receiver parity check.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReceiverFusionAlignmentV73Protocol();
v70 = getReceiverDomainNormalizedOpportunityV70Protocol();
v71 = getReceiverDomainTransportProjectionV71Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReceiverFusionAlignmentV73:DirtySource', ...
        'The V73 receiver alignment requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    if numel(state.groupIds) ~= caseInfo.expectedNodeCount || ...
            numel(unique(state.groupIds, 'stable')) ~= ...
                caseInfo.expectedFormationCount
        error('ReceiverFusionAlignmentV73:CaseDrift', ...
            'A frozen V73 source case changed scale.');
    end
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds, struct( ...
            'referenceMode', 'current-physical-tree'));
    base = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        v70.positiveSupportThreshold);
    influence = computeInfluenceAwareDecisionBreadthV66( ...
        control, state.context, state.groupIds, struct( ...
            'positiveSupportThreshold', ...
                v70.positiveSupportThreshold, ...
            'horizonSteps', v70.horizonSteps));
    transportOptions = getSignedMergeSplitOpportunityV69Protocol();
    transportOptions.fusionConfig = protocol.fusionConfig;
    transport = computeAlternativeTransportHeadroomV68( ...
        state.context, control, state.groupIds, transportOptions);
    local = computeReceiverDomainNormalizedOpportunityV70( ...
        base, influence, control, transport, state.groupIds, v70);
    projection = buildReceiverDomainTransportProjectionV71( ...
        state.context, control, transport, local, state.groupIds, v71);
    records(caseIdx) = makeRecord( ...
        caseInfo, local, transport, projection);
    fprintf([ ...
        'V73 %s t=%d old=%s aligned-nominated=%s selected=%s ', ...
        'slots=%d route-changed=%d fallback=%d\n'], ...
        caseInfo.presetName, caseInfo.currentTime, ...
        mat2str(caseInfo.v71SelectedFormationIds), ...
        mat2str(projection.nominatedFormationIds), ...
        mat2str(projection.selectedFormationIds), ...
        numel(projection.selectedSlotIndices), ...
        records(caseIdx).routeChangedFromV71, ...
        projection.referenceFallbackUsed);
end

result = struct();
result.contractVersion = ...
    'receiver-fusion-alignment-v73-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.anyRouteChangedFromV71 = any([records.routeChangedFromV71]);
result.allAlignedRoutesConstructed = ...
    all([records.alignedRouteConstructed]);
result.receiverSemanticMismatchIsolated = true;
result.temporalPropagationModelUsed = false;
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RECEIVER_FUSION_ALIGNMENT_V73_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'RECEIVER_FUSION_ALIGNMENT_V73_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V73 receiver-fusion alignment: %s\n', reportPath);
end

function record = makeRecord(caseInfo, local, transport, projection)
record = emptyRecord();
record.presetName = caseInfo.presetName;
record.seed = caseInfo.seed;
record.currentTime = caseInfo.currentTime;
record.v71SelectedFormationIds = ...
    caseInfo.v71SelectedFormationIds;
record.v71SelectedSlotCount = caseInfo.v71SelectedSlotCount;
record.alignedNominatedFormationIds = ...
    projection.nominatedFormationIds;
record.alignedSelectedFormationIds = ...
    projection.selectedFormationIds;
record.alignedSelectedSlotIndices = projection.selectedSlotIndices;
record.alignedSelectedSlotCount = ...
    numel(projection.selectedSlotIndices);
record.localNetFractionByFormation = ...
    local.localAlternativeTransportNetFractionByFormation;
record.alignedSelectedNetworkNetFraction = ...
    projection.selectedNetworkAverageNetFraction;
record.alignedRouteConstructed = projection.routeConstructed;
record.referenceFallbackUsed = projection.referenceFallbackUsed;
record.messageParityPass = ...
    projection.messageCountParityWithReference && ...
    projection.perReceiverMessageCountParityWithReference && ...
    projection.perReceiverWeightMultisetParityWithReference;
record.rollingB3Pass = ...
    all(projection.selectedRollingB3SensorPass) && ...
    all(projection.selectedRollingB3FormationPass);
record.routeChangedFromV71 = ...
    ~isequal(record.alignedSelectedFormationIds, ...
        record.v71SelectedFormationIds) || ...
    record.alignedSelectedSlotCount ~= record.v71SelectedSlotCount;
record.receiverFusionMode = transport.receiverFusionMode;
record.receiverFirstInputEnforced = ...
    transport.receiverFirstInputEnforced;
record.neighborMessageEventType = ...
    transport.neighborMessageEventType;
record.selectedSlots = summarizeSlots( ...
    transport.slotRecords, projection.selectedSlotIndices);
end

function summaries = summarizeSlots(slots, selectedIndices)
summaries = repmat(emptySlotSummary(), 1, numel(selectedIndices));
for selectedIdx = 1:numel(selectedIndices)
    slot = slots(selectedIndices(selectedIdx));
    summaries(selectedIdx) = struct( ...
        'receiverIdx', slot.receiverIdx, ...
        'incumbentSenderIdx', slot.incumbentSenderIdx, ...
        'candidateSenderIdx', slot.bestCandidateSenderIdx, ...
        'gainFraction', slot.bestTransportGainFraction, ...
        'harmFraction', slot.bestSupportedHarmFraction, ...
        'netFraction', slot.bestNetHeadroomFraction, ...
        'upwardCrossingCount', slot.bestUpwardCrossingCount, ...
        'downwardCrossingCount', slot.bestDownwardCrossingCount);
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReceiverFusionAlignmentV73:WriteFailed', ...
        'Could not create the V73 alignment report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V73 receiver-fusion alignment anchors\n\n');
fprintf(fid, ['| Scale | Time | V71 selection | Aligned nomination | ', ...
    'Aligned selection | Slots old / aligned | Local net by formation | ', ...
    'Route changed | Route |\n']);
fprintf(fid, '|:--|--:|:--|:--|:--|:--|:--|:--:|:--:|\n');
for record = result.records
    fprintf(fid, ['| %s | %d | `%s` | `%s` | `%s` | `%d / %d` | ', ...
        '`%s` | %d | %s |\n'], ...
        record.presetName, record.currentTime, ...
        mat2str(record.v71SelectedFormationIds), ...
        mat2str(record.alignedNominatedFormationIds), ...
        mat2str(record.alignedSelectedFormationIds), ...
        record.v71SelectedSlotCount, ...
        record.alignedSelectedSlotCount, ...
        mat2str(100 * record.localNetFractionByFormation, 5), ...
        record.routeChangedFromV71, routeName(record));
end
fprintf(fid, '\n## Aligned selected receiver slots\n\n');
for record = result.records
    fprintf(fid, '### %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    if isempty(record.selectedSlots)
        fprintf(fid, 'Reference fallback; no slot selected.\n\n');
        continue;
    end
    fprintf(fid, ['| Receiver | Incumbent | Candidate | Gain | Harm | ', ...
        'Net | Up / down crossings |\n']);
    fprintf(fid, '|--:|--:|--:|--:|--:|--:|:--|\n');
    for slot = record.selectedSlots
        fprintf(fid, ...
            '| %d | %d | %d | %.3f%% | %.3f%% | %.3f%% | `%d / %d` |\n', ...
            slot.receiverIdx, slot.incumbentSenderIdx, ...
            slot.candidateSenderIdx, 100 * slot.gainFraction, ...
            100 * slot.harmFraction, 100 * slot.netFraction, ...
            slot.upwardCrossingCount, slot.downwardCrossingCount);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '## Gate summary\n\n');
fprintf(fid, '- Receiver mode: `mixture-aware-heavy`\n');
fprintf(fid, '- Receiver-first ordering at both anchors: `%d`\n', ...
    all([result.records.receiverFirstInputEnforced]));
fprintf(fid, '- Heavy neighbor event type at both anchors: `%d`\n', ...
    all([result.records.neighborMessageEventType] == 2));
fprintf(fid, '- Any route changed from V71: `%d`\n', ...
    result.anyRouteChangedFromV71);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route executed: `0`\n');
fprintf(fid, '- Temporal propagation model used: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function name = routeName(record)
if record.alignedRouteConstructed
    name = 'constructed';
else
    name = 'reference fallback';
end
end

function value = emptyRecord()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'v71SelectedFormationIds', zeros(1, 0), ...
    'v71SelectedSlotCount', 0, ...
    'alignedNominatedFormationIds', zeros(1, 0), ...
    'alignedSelectedFormationIds', zeros(1, 0), ...
    'alignedSelectedSlotIndices', zeros(1, 0), ...
    'alignedSelectedSlotCount', 0, ...
    'localNetFractionByFormation', zeros(1, 0), ...
    'alignedSelectedNetworkNetFraction', NaN, ...
    'alignedRouteConstructed', false, ...
    'referenceFallbackUsed', true, ...
    'messageParityPass', false, ...
    'rollingB3Pass', false, ...
    'routeChangedFromV71', false, ...
    'receiverFusionMode', '', ...
    'receiverFirstInputEnforced', false, ...
    'neighborMessageEventType', NaN, ...
    'selectedSlots', repmat(emptySlotSummary(), 1, 0));
end

function value = emptySlotSummary()
value = struct( ...
    'receiverIdx', NaN, ...
    'incumbentSenderIdx', NaN, ...
    'candidateSenderIdx', NaN, ...
    'gainFraction', NaN, ...
    'harmFraction', NaN, ...
    'netFraction', NaN, ...
    'upwardCrossingCount', NaN, ...
    'downwardCrossingCount', NaN);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
