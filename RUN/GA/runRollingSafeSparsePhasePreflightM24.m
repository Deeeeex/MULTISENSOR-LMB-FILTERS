function [reportPath, preflight] = ...
    runRollingSafeSparsePhasePreflightM24( ...
        seed, currentTime, options)
% RUNROLLINGSAFESPARSEPHASEPREFLIGHTM24 Truth-free sparse H=3 action bank.
%
% The registered bank spans a deterministic schedule control plus
% link-, posterior-, compatibility-, history-, and analytic-score graph
% proposals. Every completed action has the same 24-message budget and
% passes through the common rolling-B3 safety projector. The first graph
% and its fusion weights are frozen from the complete saved predecision
% context; t+1 and t+2 both recompute reference code 24. This is an
% opened-training falsifier for actionable graph-option headroom, not a
% selector or a scale-generalization experiment.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.rollingSafeSparsePreflightAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('Rolling-safe sparse preflight is not authorized.');
end
seed = validateTrainingSeed(seed, protocol);
currentTime = validateSourceTime(currentTime, protocol);
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles) || ...
         gitState.researchWorktreeDirty)
    error(['Official sparse preflight requires clean tracked and ', ...
        'MATLAB/Octave source state.']);
end

sourcePath = getField(options, 'sourcePath', ...
    fullfile(protocol.returnValueGateSourceDirectory, ...
        sprintf([ ...
            'label_set_ccw_return_source_m24_seed%d_v1.mat'], ...
            seed)));
sourceSha256 = computeFileSha256(sourcePath);
loaded = load(sourcePath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Sparse preflight source shard lacks dataset.');
end
source = loaded.dataset;
validateSource(source, seed, currentTime, ...
    protocol, allowDirtySource);
blockIdx = find([source.blocks.currentTime] == currentTime);
if numel(blockIdx) ~= 1
    error('Sparse preflight source state is not unique.');
end
sourceBlock = source.blocks(blockIdx);

returnTimes = currentTime + ...
    (0:(protocol.returnValueGateHorizon - 1));
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, seed);
if ~inputs.validation.isValid || ...
        inputs.config.numberOfSensors ~= ...
            protocol.expectedNodeCount
    error('Sparse preflight M24 scenario is invalid.');
end
inputs = cropInputs(inputs, returnTimes(end));
context = buildPredecisionContext( ...
    sourceBlock, inputs, protocol);
sequenceOptions = buildSequenceOptions(protocol);
actionCodes = reshape(getField( ...
    options, 'actionCodes', ...
    protocol.rollingSafeSparseActionBankCodes), 1, []);
validateActionCodes(actionCodes, protocol);
outcomes = repmat(emptyOutcome(), 1, numel(actionCodes));
actionAdjacency = false( ...
    protocol.expectedNodeCount, ...
    protocol.expectedNodeCount, numel(actionCodes));
actionGraphSha256 = cell(1, numel(actionCodes));
actionStatus = repmat({'pending'}, 1, numel(actionCodes));
actionFailureIdentifier = repmat({''}, 1, numel(actionCodes));
actionFailureMessage = repmat({''}, 1, numel(actionCodes));
for actionIdx = 1:numel(actionCodes)
    actionCode = actionCodes(actionIdx);
    try
        [adjacency, details] = ...
            selectRollingSafeActionSequencePolicy( ...
                context, actionCode, currentTime, ...
                sequenceOptions);
        actionAdjacency(:, :, actionIdx) = ...
            logical(adjacency);
        actionGraphSha256{actionIdx} = ...
            computeTextSha256(sprintf('%d,', adjacency(:)));
        fprintf('Sparse M24 H=3 seed %d t=%d code %d...\n', ...
            seed, currentTime, actionCode);
        outcomes(actionIdx) = runOneAction( ...
            inputs, sourceBlock, returnTimes, ...
            adjacency, details, protocol, ...
            sequenceOptions);
        actionStatus{actionIdx} = 'completed';
        fprintf(['  E-OSPA %.6f, worst %.6f, consensus %.6f, ', ...
            'attempted %.0f B, delivered %.0f B, %.2f s\n'], ...
            outcomes(actionIdx).meanEospa, ...
            outcomes(actionIdx).worstSensorEospa, ...
            outcomes(actionIdx).consensusOspa, ...
            outcomes(actionIdx).attemptedBytes, ...
            outcomes(actionIdx).deliveredBytes, ...
            outcomes(actionIdx).elapsedSeconds);
    catch errorInfo
        if actionCode == ...
                protocol.rollingSafeSparseReferenceActionCode
            rethrow(errorInfo);
        end
        actionStatus{actionIdx} = 'unavailable';
        actionFailureIdentifier{actionIdx} = ...
            errorInfo.identifier;
        actionFailureMessage{actionIdx} = ...
            errorInfo.message;
        fprintf('  unavailable: %s\n', errorInfo.message);
    end
end

referenceIdx = find(actionCodes == ...
    protocol.rollingSafeSparseReferenceActionCode);
if numel(referenceIdx) ~= 1
    error('Sparse reference action is not unique.');
end
completed = strcmp(actionStatus, 'completed');
if ~completed(referenceIdx) || ~any(completed)
    error('Sparse preflight did not complete its reference.');
end
risk = [outcomes.meanEospa];
completedIndices = find(completed);
[bestMeanEospa, localBestIdx] = ...
    min(risk(completedIndices));
bestIdx = completedIndices(localBestIdx);
gainPercent = 100 * ...
    (risk(referenceIdx) - bestMeanEospa) / ...
    max(risk(referenceIdx), eps);
referenceOutcome = outcomes(referenceIdx);
meanGainVsReferencePercent = nan(1, numel(actionCodes));
worstGainVsReferencePercent = nan(1, numel(actionCodes));
consensusGainVsReferencePercent = nan(1, numel(actionCodes));
attemptedByteDeviationPercent = nan(1, numel(actionCodes));
hardRuntimeGatePassed = false(1, numel(actionCodes));
for actionIdx = completedIndices
    outcome = outcomes(actionIdx);
    meanGainVsReferencePercent(actionIdx) = relativeGain( ...
        referenceOutcome.meanEospa, outcome.meanEospa);
    worstGainVsReferencePercent(actionIdx) = relativeGain( ...
        referenceOutcome.worstSensorEospa, ...
        outcome.worstSensorEospa);
    consensusGainVsReferencePercent(actionIdx) = relativeGain( ...
        referenceOutcome.consensusOspa, ...
        outcome.consensusOspa);
    attemptedByteDeviationPercent(actionIdx) = 100 * abs( ...
        outcome.attemptedBytes - referenceOutcome.attemptedBytes) / ...
        max(referenceOutcome.attemptedBytes, eps);
    hardRuntimeGatePassed(actionIdx) = ...
        outcome.truthUseCount == 0 && ...
        outcome.repairCount == 0 && ...
        outcome.payloadEmergencyCount == 0 && ...
        outcome.infeasibleCount == 0 && ...
        all(outcome.messageCounts == ...
            protocol.rollingSafeSparseMessageBudget) && ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass) && ...
        outcome.firstActionExact;
end
admissibleForSelection = completed & hardRuntimeGatePassed & ...
    attemptedByteDeviationPercent <= ...
        protocol.rollingSafeSparseMaximumByteDeviationPercent;
if protocol.rollingSafeSparseRequireWorstAndConsensusNonregression
    admissibleForSelection = admissibleForSelection & ...
        worstGainVsReferencePercent >= -1e-9 & ...
        consensusGainVsReferencePercent >= -1e-9;
end
admissibleIndices = find(admissibleForSelection);
if isempty(admissibleIndices)
    error('Sparse action bank has no admissible reference action.');
end
[bestAdmissibleMeanEospa, localAdmissibleIdx] = ...
    min(risk(admissibleIndices));
bestAdmissibleIdx = ...
    admissibleIndices(localAdmissibleIdx);
completedGraphHashes = actionGraphSha256(completed);
uniqueCompletedGraphCount = ...
    numel(unique(completedGraphHashes));

preflight = struct();
preflight.protocolId = protocol.id;
preflight.contractVersion = ...
    'm24-rolling-safe-truth-free-action-bank-h3-preflight-v2';
preflight.actionBankContractVersion = ...
    protocol.rollingSafeSparseActionBankContractVersion;
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
preflight.seed = seed;
preflight.currentTime = currentTime;
preflight.returnTimes = returnTimes;
preflight.actionCodes = actionCodes;
preflight.actionCodeSetSha256 = ...
    computeTextSha256(sprintf('%02d,', actionCodes));
preflight.referenceActionCode = ...
    protocol.rollingSafeSparseReferenceActionCode;
preflight.actionAdjacency = actionAdjacency;
preflight.actionGraphSha256 = actionGraphSha256;
preflight.actionStatus = actionStatus;
preflight.actionFailureIdentifier = ...
    actionFailureIdentifier;
preflight.actionFailureMessage = ...
    actionFailureMessage;
preflight.completedActionCount = nnz(completed);
preflight.unavailableActionCount = nnz(~completed);
preflight.outcomes = outcomes;
preflight.bestActionCode = actionCodes(bestIdx);
preflight.bestMeanEospa = bestMeanEospa;
preflight.bestGainVsReferencePercent = gainPercent;
preflight.referenceMeanEospa = ...
    referenceOutcome.meanEospa;
preflight.meanGainVsReferencePercent = ...
    meanGainVsReferencePercent;
preflight.worstGainVsReferencePercent = ...
    worstGainVsReferencePercent;
preflight.consensusGainVsReferencePercent = ...
    consensusGainVsReferencePercent;
preflight.attemptedByteDeviationPercent = ...
    attemptedByteDeviationPercent;
preflight.hardRuntimeGatePassed = ...
    hardRuntimeGatePassed;
preflight.admissibleForSelection = ...
    admissibleForSelection;
preflight.bestAdmissibleActionCode = ...
    actionCodes(bestAdmissibleIdx);
preflight.bestAdmissibleMeanEospa = ...
    bestAdmissibleMeanEospa;
preflight.bestAdmissibleGainVsReferencePercent = ...
    meanGainVsReferencePercent(bestAdmissibleIdx);
preflight.bestAdmissibleWorstGainVsReferencePercent = ...
    worstGainVsReferencePercent(bestAdmissibleIdx);
preflight.bestAdmissibleConsensusGainVsReferencePercent = ...
    consensusGainVsReferencePercent(bestAdmissibleIdx);
preflight.bestAdmissibleAttemptedByteDeviationPercent = ...
    attemptedByteDeviationPercent(bestAdmissibleIdx);
preflight.uniqueCompletedGraphCount = ...
    uniqueCompletedGraphCount;
preflight.sourcePath = sourcePath;
preflight.sourceSha256 = sourceSha256;
preflight.commonRandomNumbers = true;
preflight.firstActionGraphAndWeightsFrozen = true;
preflight.continuationActionCode = ...
    protocol.rollingSafeSparseReferenceActionCode;
preflight.targetsUseTruth = true;
preflight.targetsUseFutureMeasurements = true;
preflight.runtimePolicyUsesTruth = ...
    any([outcomes.truthUseCount] > 0);
preflight.trainingOnlyDiagnostic = true;
preflight.developmentOpened = false;
preflight.heldoutM24Opened = false;
preflight.x36Opened = false;
preflight.evidenceBoundary = [ ...
    'This opened-training preflight tests paired H=3 headroom inside ', ...
    'a truth-free 24-message sparse action family. Its predecision ', ...
    'state was produced by the earlier 40-message dense CCW behavior ', ...
    'trajectory, so it is not a same-budget sparse-versus-dense ', ...
    'comparison. It is not a learned selector, does not use the new ', ...
    'formation-FoV scenes, and supports no development, held-out M24, ', ...
    'X36, or scale-generalization claim.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'rolling_safe_sparse_phase_preflight'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = sprintf( ...
    'rolling_safe_sparse_h3_m24_seed%d_t%d', ...
    seed, currentTime);
artifactSuffix = getField(options, 'artifactSuffix', '');
if ~isempty(artifactSuffix)
    if ~ischar(artifactSuffix) || ...
            isempty(regexp(artifactSuffix, ...
                '^[A-Za-z0-9_-]+$', 'once'))
        error(['artifactSuffix must contain only letters, digits, ', ...
            'underscores or hyphens.']);
    end
    stem = sprintf('%s_%s', stem, artifactSuffix);
end
matPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, [stem, '.mat']));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, [upper(stem), '.md']));
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Sparse preflight output already exists. Set overwrite=true ', ...
        'only for intentional regeneration.']);
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('Sparse preflight: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function outcome = runOneAction( ...
        inputs, sourceBlock, returnTimes, ...
        firstAdjacency, firstDetails, protocol, ...
        sequenceOptions)
config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = ...
    inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    protocol.rollingSafeSparseMessageBudget;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'rolling-safe-sparse-phase-h3-first-then-code24';
config.topologyPolicyFcn = ...
    @(context) frozenFirstThenReference( ...
        context, returnTimes(1), ...
        firstAdjacency, firstDetails, ...
        protocol, sequenceOptions);
config.filterInitialLocalPosteriorBySensor = ...
    sourceBlock.initialLocalPosteriorBySensor;
config.filterInitialLocalPosteriorTime = ...
    sourceBlock.currentTime;
config.filterInitialLocalUpdateHistoryTimes = ...
    sourceBlock.localUpdateHistoryTimes;
config.filterInitialLocalInnovationHistory = ...
    sourceBlock.localInnovationHistory;
config.filterInitialLocalAssociationConfidenceHistory = ...
    sourceBlock.localAssociationConfidenceHistory;
config.filterInitialLocalNisNormHistory = ...
    sourceBlock.localNisNormHistory;
config.filterInitialLocalNisDeviationHistory = ...
    sourceBlock.localNisDeviationHistory;
config.filterInitialPreviousAdjacencyHistory = ...
    sourceBlock.previousAdjacencyHistory;
config.filterInitialPreviousAdjacencyTimes = ...
    sourceBlock.previousAdjacencyHistoryTimes;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'frozen-ccw-return-source-v1';

rng(sourceBlock.seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        inputs.model, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config);
elapsedSeconds = toc(timerId);
if ~diagnostics.usedInitialLocalUpdateHistory || ...
        ~isequal( ...
            diagnostics.initialLocalUpdateHistoryTimes, ...
            sourceBlock.localUpdateHistoryTimes)
    error('Sparse preflight did not restore update history.');
end
firstExecuted = ...
    convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        diagnostics.topologyActiveEdge( ...
            :, :, returnTimes(1)));
if ~isequal(firstExecuted, logical(firstAdjacency))
    error('Sparse preflight did not execute its first graph exactly.');
end
messageCounts = ...
    diagnostics.topologyDirectedMessageCount(returnTimes);
if any(messageCounts ~= ...
        protocol.rollingSafeSparseMessageBudget)
    error('Sparse preflight message count changed.');
end
truthUse = finiteLogical( ...
    diagnostics.topologyPolicyTruthUsed(returnTimes));
repair = finiteLogical( ...
    diagnostics.topologyPolicyRepairTriggered(returnTimes));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(returnTimes));
infeasible = logical( ...
    ~diagnostics.topologyFeasible(returnTimes) | ...
    finiteLogical(diagnostics. ...
        topologyPolicyTopologyInfeasible(returnTimes)));
if any(truthUse) || any(repair) || ...
        any(emergency) || any(infeasible)
    error('Sparse preflight violated a hard runtime gate.');
end

nodeCount = inputs.config.numberOfSensors;
selected = false(nodeCount, nodeCount, numel(returnTimes));
delivered = selected;
for timeIdx = 1:numel(returnTimes)
    selected(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(timeIdx)));
    delivered(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.delivered( ...
                :, :, returnTimes(timeIdx)));
end
[selectedSensorB3, selectedFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousAdjacencyHistory, ...
        selected, inputs.config.sensorGroupIds);
[deliveredSensorB3, deliveredFormationB3] = ...
    computeRollingB3Pass( ...
        sourceBlock.previousDeliveredAdjacencyHistory, ...
        delivered, inputs.config.sensorGroupIds);
if ~all(selectedSensorB3) || ...
        ~all(selectedFormationB3)
    error('Sparse preflight failed its independent selected B3 audit.');
end

sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(returnTimes));
for sensorIdx = 1:sensorCount
    sensorEospa = computeSimulationOspa( ...
        inputs.model, inputs.groundTruthRfs, ...
        estimates{sensorIdx});
    eospa(sensorIdx, :) = ...
        sensorEospa(returnTimes);
end
sensorMeans = mean(eospa, 2);
[~, ~, ospaDisagreement] = ...
    computeDistributedConsensusMetrics( ...
        estimates, inputs.model);
outcome = emptyOutcome();
outcome.meanEospa = mean(eospa(:));
outcome.worstSensorEospa = max(sensorMeans);
outcome.consensusOspa = finiteMean( ...
    ospaDisagreement(returnTimes));
outcome.attemptedBytes = sum(reshape( ...
    diagnostics.attemptedPayloadBytes( ...
        :, :, returnTimes), 1, []));
outcome.deliveredBytes = sum(reshape( ...
    diagnostics.payloadBytes( ...
        :, :, returnTimes), 1, []));
outcome.messageCounts = messageCounts;
outcome.truthUseCount = nnz(truthUse);
outcome.repairCount = nnz(repair);
outcome.payloadEmergencyCount = nnz(emergency);
outcome.infeasibleCount = nnz(infeasible);
outcome.selectedSensorB3Pass = selectedSensorB3;
outcome.selectedFormationB3Pass = ...
    selectedFormationB3;
outcome.deliveredSensorB3Pass = ...
    deliveredSensorB3;
outcome.deliveredFormationB3Pass = ...
    deliveredFormationB3;
outcome.firstActionExact = true;
outcome.elapsedSeconds = elapsedSeconds;
end

function [adjacency, details] = ...
        frozenFirstThenReference( ...
            context, anchorTime, firstAdjacency, ...
            firstDetails, protocol, sequenceOptions)
if context.currentTime == anchorTime
    adjacency = logical(firstAdjacency);
    if ~isequal(size(adjacency), ...
            size(context.physicalAdjacency)) || ...
            any(adjacency(:) & ...
                ~logical(context.physicalAdjacency(:)))
        error('Sparse frozen first action is physically invalid.');
    end
    details = firstDetails;
    details.mode = 'frozen-sparse-phase-first-step';
    details.truthUsed = false;
    details.groundTruthUsed = false;
    details.futureOutcomeUsed = false;
    details.runtimeFrozenGraphReplay = true;
else
    [adjacency, details] = ...
        selectRollingSafeActionSequencePolicy( ...
            context, ...
            protocol.rollingSafeSparseReferenceActionCode, ...
            anchorTime, sequenceOptions);
    details.runtimeFrozenGraphReplay = false;
end
end

function context = buildPredecisionContext( ...
        block, inputs, protocol)
currentTime = block.currentTime;
nodeCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = ...
    block.initialLocalPosteriorBySensor;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = ...
    buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = ...
    block.previousAdjacencyHistory;
context.previousAdjacencyHistoryCount = ...
    size(block.previousAdjacencyHistory, 3);
context.previousAdjacencyHistoryTimes = ...
    block.previousAdjacencyHistoryTimes;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacencyHistorySource = ...
    'frozen-ccw-return-source-v1';
context.previousAdjacency = ...
    block.previousAdjacencyHistory(:, :, end);
context.baseAdjacency = ...
    neighborMapToAdjacency( ...
        inputs.neighborMap, nodeCount);
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency( ...
        :, :, currentTime));
context.edgeScores = ...
    double(context.physicalAdjacency);
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = ...
    protocol.rollingSafeSparseMessageBudget;
context.positions = ...
    inputs.graphData.positions(:, :, currentTime);
context.localInnovationHistory = ...
    block.localInnovationHistory;
context.localAssociationConfidenceHistory = ...
    block.localAssociationConfidenceHistory;
context.localNisNormHistory = ...
    block.localNisNormHistory;
context.localNisDeviationHistory = ...
    block.localNisDeviationHistory;
context.localUpdateHistoryTimes = ...
    block.localUpdateHistoryTimes;
end

function options = buildSequenceOptions(protocol)
options = struct( ...
    'sourceWeight', ...
        protocol.rollingSafeSparseSourceWeight, ...
    'payloadToleranceFraction', inf, ...
    'fallbackActionCode', ...
        protocol.rollingSafeSparseReferenceActionCode, ...
    'scoreOptions', struct( ...
        'sourceWeight', ...
            protocol.rollingSafeSparseSourceWeight, ...
        'horizonSteps', 0, ...
        'discountFactor', 0.9));
end

function validateSource( ...
        source, seed, currentTime, protocol, allowDirty)
if ~strcmp(source.protocolId, protocol.id) || ...
        ~strcmp(source.contractVersion, ...
            protocol.returnValueGateSourceContractVersion) || ...
        source.seed ~= seed || ...
        ~any(source.sourceTimes == currentTime) || ...
        source.featuresUseTruth || ...
        source.featuresUseFutureOutcome || ...
        source.targetsStored || ...
        source.postdecisionTopologyStored || ...
        source.developmentOpened || ...
        source.heldoutM24Opened || source.x36Opened
    error('Sparse preflight source violates the contract.');
end
if ~allowDirty && ...
        (source.generationTrackedWorktreeDirty || ...
         ~isempty(source.generationUntrackedSourceFiles) || ...
         source.generationResearchWorktreeDirty)
    error('Sparse preflight requires a clean source shard.');
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:maximumTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maximumTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
end

function adjacency = ...
        neighborMapToAdjacency(neighborMap, nodeCount)
adjacency = false(nodeCount);
for receiverIdx = 1:nodeCount
    senders = reshape(neighborMap{receiverIdx}, 1, []);
    senders = senders(senders ~= receiverIdx);
    adjacency(receiverIdx, senders) = true;
end
end

function outcome = emptyOutcome()
outcome = struct( ...
    'meanEospa', NaN, ...
    'worstSensorEospa', NaN, ...
    'consensusOspa', NaN, ...
    'attemptedBytes', NaN, ...
    'deliveredBytes', NaN, ...
    'messageCounts', [], ...
    'truthUseCount', NaN, ...
    'repairCount', NaN, ...
    'payloadEmergencyCount', NaN, ...
    'infeasibleCount', NaN, ...
    'selectedSensorB3Pass', false(1, 0), ...
    'selectedFormationB3Pass', false(1, 0), ...
    'deliveredSensorB3Pass', false(1, 0), ...
    'deliveredFormationB3Pass', false(1, 0), ...
    'firstActionExact', false, ...
    'elapsedSeconds', NaN);
end

function writeReport(path, preflight)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write sparse preflight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 truth-free sparse action-bank H=3 preflight\n\n');
fprintf(fid, '- Seed / anchor: `%d / %d`\n', ...
    preflight.seed, preflight.currentTime);
fprintf(fid, '- Return times: `%s`\n', ...
    mat2str(preflight.returnTimes));
fprintf(fid, '- Source SHA-256: `%s`\n', ...
    preflight.sourceSha256);
fprintf(fid, '- Reference action: `%d`\n', ...
    preflight.referenceActionCode);
fprintf(fid, '- Best action: `%d`\n', ...
    preflight.bestActionCode);
fprintf(fid, '- Best gain versus reference: `%.3f%%`\n\n', ...
    preflight.bestGainVsReferencePercent);
fprintf(fid, '- Best admissible action: `%d`\n', ...
    preflight.bestAdmissibleActionCode);
fprintf(fid, '- Best admissible gain versus reference: `%.3f%%`\n', ...
    preflight.bestAdmissibleGainVsReferencePercent);
fprintf(fid, '- Completed / unique graphs: `%d / %d`\n\n', ...
    preflight.completedActionCount, ...
    preflight.uniqueCompletedGraphCount);
fprintf(fid, ...
    ['| Code | Mean E-OSPA | Mean gain | Worst gain | Consensus gain | ', ...
     'Attempted B | Byte dev. | Admissible |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for actionIdx = 1:numel(preflight.actionCodes)
    row = preflight.outcomes(actionIdx);
    if strcmp(preflight.actionStatus{actionIdx}, 'completed')
        fprintf(fid, ...
            ['| %d | %.6f | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
             '%.0f | %.3f%% | %d |\n'], ...
            preflight.actionCodes(actionIdx), ...
            row.meanEospa, ...
            preflight.meanGainVsReferencePercent(actionIdx), ...
            preflight.worstGainVsReferencePercent(actionIdx), ...
            preflight.consensusGainVsReferencePercent(actionIdx), ...
            row.attemptedBytes, ...
            preflight.attemptedByteDeviationPercent(actionIdx), ...
            preflight.admissibleForSelection(actionIdx));
    else
        fprintf(fid, ['| %d | unavailable | unavailable | unavailable | ', ...
            'unavailable | unavailable | unavailable | 0 |\n'], ...
            preflight.actionCodes(actionIdx));
    end
end
fprintf(fid, '\n## Boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function seed = validateTrainingSeed(seed, protocol)
if ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || ...
        ~ismember(seed, protocol.trainingSeeds)
    error('seed must be a registered M24 training seed.');
end
end

function currentTime = validateSourceTime( ...
        currentTime, protocol)
if ~isscalar(currentTime) || ...
        ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || ...
        ~ismember(currentTime, ...
            protocol.returnValueGateSourceTimes)
    error('currentTime must be a registered return-source time.');
end
end

function validateActionCodes(actionCodes, protocol)
if isempty(actionCodes) || ...
        any(~isfinite(actionCodes)) || ...
        any(actionCodes ~= round(actionCodes)) || ...
        numel(unique(actionCodes)) ~= numel(actionCodes) || ...
        any(~ismember(actionCodes, ...
            protocol.rollingSafeSparseTruthFreeActionCodes)) || ...
        nnz(actionCodes == ...
            protocol.rollingSafeSparseReferenceActionCode) ~= 1
    error(['Sparse action codes must be distinct registered truth-free ', ...
        'codes and include the reference exactly once.']);
end
end

