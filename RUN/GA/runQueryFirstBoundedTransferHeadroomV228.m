function [reportPath, result] = ...
        runQueryFirstBoundedTransferHeadroomV228(options)
% RUNQUERYFIRSTBOUNDEDTRANSFERHEADROOMV228 Test affordable safe actions.
%
% This runner keeps the V226 teacher-selected donor/source/label candidates
% but replaces the all-active-label synopsis charge with the frozen V228
% query-first upper bound.  Each candidate is then executed through the
% ordinary complete-mixture V226 runtime and exact receiver-wise eta/KLA
% projection.  It is an action-space headroom test, not an online policy.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFusionAwareLabelEdgeControllerV228Protocol();
candidateBankPath = char(getField(options, 'candidateBankPath', ''));
recordIndices = reshape(getField(options, ...
    'recordIndices', zeros(1, 0)), 1, []);
maximumQueriedLabels = getField(options, ...
    'maximumQueriedLabels', ...
    protocol.controlPlane.maximumQueriedLabels);
if isempty(candidateBankPath) || exist(candidateBankPath, 'file') ~= 2 || ...
        any(~isfinite(recordIndices)) || ...
        any(recordIndices ~= round(recordIndices)) || ...
        numel(unique(recordIndices)) ~= numel(recordIndices)
    error('FusionAwareQueryFirstV228:InvalidRunRequest', ...
        'A V220 candidate bank and unique record indices are required.');
end

loaded = load(candidateBankPath, 'result');
bank = loaded.result;
required = {'contractVersion', 'presetName', 'seed', 'currentTime', ...
    'donorFormationId', 'referencePageBytes', 'donorPageBytes', ...
    'admissionNetSavingBytes', 'beneficiaryDetails', 'records'};
if ~isstruct(bank) || ~isscalar(bank) || ...
        any(~isfield(bank, required)) || ...
        ~strcmp(bank.contractVersion, ...
            'decoupled-semantic-shortcut-candidate-bank-v220-v1') || ...
        getField(bank, 'truthUsedForCandidateFeatures', true) || ...
        getField(bank, 'futureInformationUsedForCandidateFeatures', true)
    error('FusionAwareQueryFirstV228:CandidateBankContract', ...
        'V228 requires a causal V220 candidate bank.');
end
if isempty(recordIndices)
    selectedRows = 1:numel(bank.records);
else
    [present, selectedRows] = ismember( ...
        recordIndices, [bank.records.recordIndex]);
    if ~all(present)
        error('FusionAwareQueryFirstV228:UnknownRecord', ...
            'A requested candidate record is not present in the bank.');
    end
end

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'query_first_headroom', ...
    char(getField(bank, 'splitName', 'training')), ...
    sprintf('%s_seed%d_t%d_donor_f%d', ...
        strrep(bank.presetName, '-', '_'), bank.seed, ...
        bank.currentTime, bank.donorFormationId))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyRecord(), 1, numel(selectedRows));
bestSafe = emptyBest();
bestSafeScore = -inf;
bestMaterial = emptyBest();
bestMaterialScore = -inf;
identityTolerance = 1e-10;
for position = 1:numel(selectedRows)
    row = selectedRows(position);
    bankRecord = bank.records(row);
    beneficiary = findBeneficiary( ...
        bank.beneficiaryDetails, ...
        bankRecord.beneficiaryFormationId);
    queryPlan = planFusionAwareQueryFirstExchangeV228( ...
        beneficiary.synopsisSensorIds, ...
        bankRecord.payloadAttemptedBytes, ...
        bank.admissionNetSavingBytes, bank.referencePageBytes, ...
        struct('maximumQueriedLabels', maximumQueriedLabels));

    item = emptyRecord();
    item.recordIndex = bankRecord.recordIndex;
    item.donorFormationId = bankRecord.donorFormationId;
    item.beneficiaryFormationId = ...
        bankRecord.beneficiaryFormationId;
    item.sourceId = bankRecord.sourceId;
    item.label = reshape(bankRecord.label, 2, 1);
    item.participantSensorIds = queryPlan.participantSensorIds;
    item.participantCount = queryPlan.participantCount;
    item.queryAttemptedBytes = queryPlan.queryAttemptedBytes;
    item.payloadAttemptedBytes = bankRecord.payloadAttemptedBytes;
    item.certifiedNetSavingBytes = ...
        queryPlan.certifiedNetSavingBytes;
    item.queryFirstCreditFeasible = ...
        queryPlan.candidateFeasibleMask;
    item.queryPlan = queryPlan;
    if ~item.queryFirstCreditFeasible
        item.executionStatus = 'credit-infeasible';
        records(position) = item;
        continue;
    end

    leaf = sprintf('r%03d_b%d_s%d_l%d-%d', ...
        item.recordIndex, item.beneficiaryFormationId, ...
        item.sourceId, item.label(1), item.label(2));
    [~, candidateResult] = ...
        runBoundedDominantEdgeTransferH3V226(struct( ...
            'candidateBankPath', candidateBankPath, ...
            'recordIndices', item.recordIndex, ...
            'inputRouteSynopsisBytesOverride', ...
                item.queryAttemptedBytes, ...
            'outputRoot', fullfile(outputRoot, leaf)));
    if numel(candidateResult.records) ~= 1
        error('FusionAwareQueryFirstV228:CandidateExecution', ...
            'Every V228 headroom row must produce one V226 outcome.');
    end
    outcome = candidateResult.records(1);
    joint = reshape(outcome.jointGainVectorPercent, 1, []);
    incremental = reshape( ...
        outcome.incrementalGainVectorPercent, 1, []);
    donor = recoverDonorGainVector(joint, incremental);
    item.executionStatus = 'executed';
    item.screenPath = outcome.screenPath;
    item.jointGainVectorPercent = joint;
    item.incrementalGainVectorPercent = incremental;
    item.donorGainVectorPercent = donor;
    item.attemptedByteSavingPercent = ...
        outcome.attemptedByteSavingPercent;
    item.etaProjectionAppliedActionCount = ...
        outcome.etaProjectionAppliedActionCount;
    item.etaProjectionAllowedReceiverIds = ...
        outcome.etaProjectionAllowedReceiverIds;
    item.etaProjectionRejectedReceiverIds = ...
        outcome.etaProjectionRejectedReceiverIds;
    item.donorCoreNonnegative = ...
        all(donor(1:4) >= -identityTolerance);
    item.incrementalCorePositive = all(incremental(1:4) > 0);
    item.jointCorePositive = all(joint(1:4) > 0);
    item.bytePositive = item.attemptedByteSavingPercent > 0;
    item.compositionallySafe = item.donorCoreNonnegative && ...
        item.incrementalCorePositive && item.jointCorePositive && ...
        item.bytePositive;
    item.materialHeadroomPassed = item.compositionallySafe && ...
        max(incremental(1:2)) >= ...
            protocol.headroom.minimumIncrementalTrackingGainPercent && ...
        max(joint(1:2)) >= ...
            protocol.headroom.minimumJointTrackingGainPercent && ...
        max(joint(3:4)) >= ...
            protocol.headroom.minimumJointConsensusGainPercent && ...
        item.attemptedByteSavingPercent >= ...
            protocol.headroom.minimumAttemptedByteSavingPercent;
    item.strictRiskPassed = all( ...
        joint >= protocol.risk.tolerancePercent - 1e-12);
    records(position) = item;

    if item.compositionallySafe
        score = min([joint(1:4), incremental(1:4), ...
            item.attemptedByteSavingPercent]);
        if score > bestSafeScore + 1e-12
            bestSafeScore = score;
            bestSafe = buildBest(item, score);
        end
        if item.materialHeadroomPassed && ...
                score > bestMaterialScore + 1e-12
            bestMaterialScore = score;
            bestMaterial = buildBest(item, score);
        end
    end
end

result = struct();
result.contractVersion = ...
    'fusion-aware-query-first-headroom-v228-v2';
result.generatedAt = datestr(now, 31);
gitState = resolveResearchGitState();
result.generationGitCommit = gitState.commit;
result.protocolId = protocol.id;
result.candidateBankPath = candidateBankPath;
result.presetName = bank.presetName;
result.seed = bank.seed;
result.splitName = char(getField(bank, 'splitName', 'training'));
result.currentTime = bank.currentTime;
result.donorFormationId = bank.donorFormationId;
result.maximumQueriedLabels = maximumQueriedLabels;
result.recordIndices = [records.recordIndex];
result.records = records;
result.candidateCount = numel(records);
result.creditFeasibleCount = ...
    nnz([records.queryFirstCreditFeasible]);
result.executedCount = nnz(strcmp( ...
    {records.executionStatus}, 'executed'));
result.compositionallySafeCount = ...
    nnz([records.compositionallySafe]);
result.materialHeadroomCount = nnz([records.materialHeadroomPassed]);
result.bestSafe = bestSafe;
result.best = bestMaterial;
result.queryKeySelectorImplemented = ...
    protocol.controlPlane.queryKeySelectorImplemented;
result.queryKeyDiscoverabilityValidated = ...
    protocol.controlPlane.queryKeyDiscoverabilityValidated;
result.actionSpaceAuthorizedForDiscoveryDesign = bestMaterial.present;
result.actionSpaceAuthorizedForLearning = bestMaterial.present && ...
    result.queryKeySelectorImplemented && ...
    result.queryKeyDiscoverabilityValidated;
result.teacherDonorSourceLabelSelection = true;
result.onlinePolicyImplemented = false;
result.paperPromotionAllowed = false;
result.validationClaimAllowed = false;
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.evidenceBoundary = [ ...
    'V228 query-first headroom uses causal current-state candidate ', ...
    'features but teacher-selected donor/source/label rows. It charges a ', ...
    'worst-case bounded query exchange and the complete GM payload, then ', ...
    'runs the exact V226 receiver projection. The queried label keys are ', ...
    'still teacher-selected: a material-gate pass authorizes design of a ', ...
    'causal query-key discovery rule, but cannot by itself authorize ', ...
    'dataset expansion or value-policy training. It is not a full-episode, ', ...
    'held-out or paper-level claim.'];
matPath = fullfile(outputRoot, ...
    'QUERY_FIRST_BOUNDED_TRANSFER_HEADROOM_V228.mat');
reportPath = fullfile(outputRoot, ...
    'QUERY_FIRST_BOUNDED_TRANSFER_HEADROOM_V228.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V228 query-first bounded-transfer headroom: %s\n', reportPath);
end

function beneficiary = findBeneficiary(details, formationId)
matches = find([details.formationId] == formationId);
if numel(matches) ~= 1 || ...
        ~isfield(details(matches), 'synopsisSensorIds') || ...
        isempty(details(matches).synopsisSensorIds)
    error('FusionAwareQueryFirstV228:BeneficiaryParticipants', ...
        'The beneficiary participant set is unavailable or ambiguous.');
end
beneficiary = details(matches);
end

function donor = recoverDonorGainVector(joint, incremental)
candidateOverReference = 1 - joint / 100;
candidateOverDonor = 1 - incremental / 100;
if any(candidateOverReference < 0) || ...
        any(candidateOverDonor <= 0)
    donor = nan(size(joint));
else
    donor = 100 * (1 - ...
        candidateOverReference ./ candidateOverDonor);
end
end

function best = buildBest(record, score)
best = emptyBest();
best.present = true;
best.recordIndex = record.recordIndex;
best.donorFormationId = record.donorFormationId;
best.beneficiaryFormationId = record.beneficiaryFormationId;
best.sourceId = record.sourceId;
best.label = record.label;
best.queryAttemptedBytes = record.queryAttemptedBytes;
best.payloadAttemptedBytes = record.payloadAttemptedBytes;
best.jointGainVectorPercent = record.jointGainVectorPercent;
best.incrementalGainVectorPercent = ...
    record.incrementalGainVectorPercent;
best.donorGainVectorPercent = record.donorGainVectorPercent;
best.attemptedByteSavingPercent = ...
    record.attemptedByteSavingPercent;
best.strictRiskPassed = record.strictRiskPassed;
best.score = score;
best.screenPath = record.screenPath;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('FusionAwareQueryFirstV228:WriteReport', ...
        'Could not write the V228 headroom report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V228 query-first bounded-transfer headroom\n\n');
fprintf(fid, '- State: `%s / seed %d / t=%d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Donor formation: `F%d`\n', result.donorFormationId);
fprintf(fid, '- Query cap: `%d labels`\n', ...
    result.maximumQueriedLabels);
fprintf(fid, '- Causal query-key selector implemented / validated: `%d / %d`\n', ...
    result.queryKeySelectorImplemented, ...
    result.queryKeyDiscoverabilityValidated);
fprintf(fid, ...
    '- Candidates / feasible / executed / safe / material: `%d / %d / %d / %d / %d`\n\n', ...
    result.candidateCount, result.creditFeasibleCount, ...
    result.executedCount, result.compositionallySafeCount, ...
    result.materialHeadroomCount);
fprintf(fid, ['| Row | Donor -> beneficiary | Source / label | ', ...
    'Participants | Query + payload | Donor E/R/C/T | ', ...
    'Increment E/R/C/T | Joint E/R/C/T | Byte saving | Safe / material |\n']);
fprintf(fid, '|--:|:--|:--|--:|--:|:--|:--|:--|--:|:--|\n');
for record = result.records
    if strcmp(record.executionStatus, 'executed')
        fprintf(fid, ...
            ['| %d | F%d -> F%d | S%d / `[%d,%d]` | %d | ', ...
             '%d + %d B | `%+.3f/%+.3f/%+.3f/%+.3f` | ', ...
             '`%+.3f/%+.3f/%+.3f/%+.3f` | ', ...
             '`%+.3f/%+.3f/%+.3f/%+.3f` | %+.3f%% | `%d / %d` |\n'], ...
            record.recordIndex, record.donorFormationId, ...
            record.beneficiaryFormationId, record.sourceId, ...
            record.label(1), record.label(2), ...
            record.participantCount, record.queryAttemptedBytes, ...
            record.payloadAttemptedBytes, ...
            record.donorGainVectorPercent(1), ...
            record.donorGainVectorPercent(2), ...
            record.donorGainVectorPercent(3), ...
            record.donorGainVectorPercent(4), ...
            record.incrementalGainVectorPercent(1), ...
            record.incrementalGainVectorPercent(2), ...
            record.incrementalGainVectorPercent(3), ...
            record.incrementalGainVectorPercent(4), ...
            record.jointGainVectorPercent(1), ...
            record.jointGainVectorPercent(2), ...
            record.jointGainVectorPercent(3), ...
            record.jointGainVectorPercent(4), ...
            record.attemptedByteSavingPercent, ...
            record.compositionallySafe, ...
            record.materialHeadroomPassed);
    else
        fprintf(fid, ...
            ['| %d | F%d -> F%d | S%d / `[%d,%d]` | %d | ', ...
             '%d + %d B | - | - | - | - | `0 / 0` |\n'], ...
            record.recordIndex, record.donorFormationId, ...
            record.beneficiaryFormationId, record.sourceId, ...
            record.label(1), record.label(2), ...
            record.participantCount, record.queryAttemptedBytes, ...
            record.payloadAttemptedBytes);
    end
end
fprintf(fid, '\n## Decision\n\n');
if result.actionSpaceAuthorizedForLearning
    fprintf(fid, ['At least one query-first action passes the frozen ', ...
        'material headroom gate. This authorizes online value-policy ', ...
        'training after V227 freezes the physical carrier.\n']);
elseif result.actionSpaceAuthorizedForDiscoveryDesign
    fprintf(fid, ['At least one teacher-keyed action passes the frozen ', ...
        'material headroom gate. This authorizes implementation and ', ...
        'validation of a causal query-key discovery rule, but not dataset ', ...
        'expansion or value-policy training: the current headroom run ', ...
        'does not show that the teacher label would enter the beneficiary ', ...
        'top-%d query without remote-label information.\n'], ...
        result.maximumQueriedLabels);
else
    fprintf(fid, ['No evaluated query-first action passes the frozen ', ...
        'material headroom gate. Safe but smaller actions remain ', ...
        'mechanism records; do not expand the dataset or train a value ', ...
        'model from this action family.\n']);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'recordIndex', 0, 'donorFormationId', 0, ...
    'beneficiaryFormationId', 0, 'sourceId', 0, ...
    'label', zeros(2, 1), 'participantSensorIds', zeros(1, 0), ...
    'participantCount', 0, 'queryAttemptedBytes', 0, ...
    'payloadAttemptedBytes', 0, 'certifiedNetSavingBytes', 0, ...
    'queryFirstCreditFeasible', false, 'queryPlan', struct(), ...
    'executionStatus', '', 'screenPath', '', ...
    'jointGainVectorPercent', nan(1, 12), ...
    'incrementalGainVectorPercent', nan(1, 12), ...
    'donorGainVectorPercent', nan(1, 12), ...
    'attemptedByteSavingPercent', NaN, ...
    'etaProjectionAppliedActionCount', 0, ...
    'etaProjectionAllowedReceiverIds', zeros(1, 0), ...
    'etaProjectionRejectedReceiverIds', zeros(1, 0), ...
    'donorCoreNonnegative', false, ...
    'incrementalCorePositive', false, ...
    'jointCorePositive', false, 'bytePositive', false, ...
    'compositionallySafe', false, ...
    'materialHeadroomPassed', false, 'strictRiskPassed', false);
end

function value = emptyBest()
value = struct('present', false, 'recordIndex', 0, ...
    'donorFormationId', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'queryAttemptedBytes', 0, 'payloadAttemptedBytes', 0, ...
    'jointGainVectorPercent', nan(1, 12), ...
    'incrementalGainVectorPercent', nan(1, 12), ...
    'donorGainVectorPercent', nan(1, 12), ...
    'attemptedByteSavingPercent', NaN, ...
    'strictRiskPassed', false, 'score', -inf, 'screenPath', '');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
