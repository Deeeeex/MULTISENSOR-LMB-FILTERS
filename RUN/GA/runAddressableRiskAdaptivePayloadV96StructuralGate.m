function [reportPath, result] = ...
    runAddressableRiskAdaptivePayloadV96StructuralGate(options)
% RUNADDRESSABLERISKADAPTIVEPAYLOADV96STRUCTURALGATE No tracking truth.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getAddressableRiskAdaptivePayloadV96Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('AddressableRiskV96:DirtySource', ...
        'V96 structural gating requires clean frozen source.');
end
outputRoot = getField(options, ...
    'outputRoot', protocol.structuralOutputRoot);
recordCount = sum(arrayfun(@(entry) ...
    numel(entry.anchorTimes), protocol.cases));
records = repmat(emptyRecord(), 1, recordCount);
recordIdx = 0;
for caseIdx = 1:numel(protocol.cases)
    entry = protocol.cases(caseIdx);
    for currentTime = entry.anchorTimes
        recordIdx = recordIdx + 1;
        state = loadFormationH3ObservableState( ...
            entry.presetName, entry.seed, currentTime, struct( ...
                'cacheRoot', entry.cacheRoot, ...
                'expectedMissingLabelFusionMode', ...
                    protocol.receiverMode));
        groupIds = state.context.model.dynamicTopologyScenario. ...
            config.sensorGroupIds;
        bank = buildTrackingAlignedX36ScheduleActionBank( ...
            state.context, groupIds, struct( ...
                'positiveSupportThreshold', ...
                    protocol.positiveSupportThreshold, ...
                'bankVariant', 'addressable-risk-v96'));
        selection = bank.addressableRiskSelection;
        selectedMask = ismember( ...
            bank.networkRiskMetrics.groups, ...
            selection.selectedFormationIds);
        downward = bank.networkRiskMetrics. ...
            crossSupportedDownwardCrossingsByFormation;
        graphParity = all(arrayfun(@(idx) ...
            isequal(bank.actionAdjacency(:, :, idx), ...
                bank.referenceAdjacency), ...
            1:bank.actionCount));
        weightParity = all(arrayfun(@(idx) ...
            max(abs(reshape(bank.actionFusionWeights(:, :, idx) - ...
                bank.referenceFusionWeights, 1, []))) <= 1e-12, ...
            1:bank.actionCount));
        schedulePassed = bank.actionCount == 3 && ...
            isempty(bank.actionFormationConditionedSchedule{2}{2}) && ...
            isempty(bank.actionFormationConditionedSchedule{2}{3}) && ...
            all(cellfun(@(ids) ...
                isequal(ids, selection.selectedFormationIds), ...
                bank.actionFormationConditionedSchedule{3}));

        record = emptyRecord();
        record.scaleName = entry.scaleName;
        record.presetName = entry.presetName;
        record.seed = entry.seed;
        record.currentTime = currentTime;
        record.selectedFormationIds = ...
            selection.selectedFormationIds;
        record.totalRiskFraction = ...
            selection.totalNetworkRiskFraction;
        record.addressableRiskFraction = ...
            selection.addressableNetworkRiskFraction;
        record.addressableCoverageFraction = ...
            selection.achievedAddressableCoverageFraction;
        record.usefulLossToRescueRatio = ...
            selection.usefulLossToRescueRatio;
        record.noSelectedDownwardCrossings = ...
            selection.actionEnabled && all(downward(selectedMask) == 0);
        record.graphParityPassed = graphParity;
        record.weightParityPassed = weightParity;
        record.schedulePassed = schedulePassed;
        record.structuralGatePassed = ...
            selection.actionEnabled && ...
            ~isempty(selection.selectedFormationIds) && ...
            selection.achievedAddressableCoverageFraction >= ...
                protocol.coverageTargetFraction - 1e-12 && ...
            selection.usefulLossToRescueRatio <= ...
                protocol.maximumUsefulLossToRescueRatio + 1e-12 && ...
            record.noSelectedDownwardCrossings && ...
            graphParity && weightParity && schedulePassed;
        record.failureReason = selection.fallbackReason;
        records(recordIdx) = record;
        fprintf([ ...
            'V96 structural %s t%d: selected %s, coverage %.3f, ', ...
            'graph/weight/schedule %d/%d/%d, gate %d\n'], ...
            record.scaleName, currentTime, ...
            mat2str(record.selectedFormationIds), ...
            record.addressableCoverageFraction, ...
            graphParity, weightParity, schedulePassed, ...
            record.structuralGatePassed);
    end
end

result = struct();
result.contractVersion = ...
    'addressable-risk-adaptive-payload-v96-structural-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.records = records;
result.crossScaleStructuralGatePassed = ...
    all([records.structuralGatePassed]);
result.trackingHeadroomAuthorized = ...
    result.crossScaleStructuralGatePassed;
result.trackingOutcomeRead = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'ADDRESSABLE_RISK_ADAPTIVE_PAYLOAD_V96_STRUCTURAL_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'ADDRESSABLE_RISK_ADAPTIVE_PAYLOAD_V96_STRUCTURAL_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V96 structural result: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('AddressableRiskV96:WriteFailed', ...
        'Could not create the V96 structural report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V96 addressable-risk structural gate\n\n');
fprintf(fid, ['No tracking truth is read. Every arm retains the same ', ...
    'static carrier graph and fusion weights.\n\n']);
fprintf(fid, ['| Scale | t | Selected | Total risk | Addressable risk | ', ...
    'Coverage | Loss / rescue | Graph | Weights | Schedule | Gate |\n']);
fprintf(fid, ['|:--|--:|:--|--:|--:|--:|--:|:--:|:--:|:--:|:--:|\n']);
for entry = result.records
    fprintf(fid, ['| %s | %d | %s | %.3f%% | %.3f%% | %.3f%% | ', ...
        '%.3f%% | %d | %d | %d | %d |\n'], ...
        entry.scaleName, entry.currentTime, ...
        mat2str(entry.selectedFormationIds), ...
        100 * entry.totalRiskFraction, ...
        100 * entry.addressableRiskFraction, ...
        100 * entry.addressableCoverageFraction, ...
        100 * entry.usefulLossToRescueRatio, ...
        entry.graphParityPassed, entry.weightParityPassed, ...
        entry.schedulePassed, entry.structuralGatePassed);
end
fprintf(fid, '\n- Cross-scale structural gate: `%d`\n', ...
    result.crossScaleStructuralGatePassed);
fprintf(fid, '- Tracking headroom authorized: `%d`\n', ...
    result.trackingHeadroomAuthorized);
fprintf(fid, '- Tracking outcome read: `0`\n\n');
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = emptyRecord()
value = struct( ...
    'scaleName', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, ...
    'selectedFormationIds', zeros(1, 0), ...
    'totalRiskFraction', NaN, 'addressableRiskFraction', NaN, ...
    'addressableCoverageFraction', NaN, ...
    'usefulLossToRescueRatio', NaN, ...
    'noSelectedDownwardCrossings', false, ...
    'graphParityPassed', false, 'weightParityPassed', false, ...
    'schedulePassed', false, 'structuralGatePassed', false, ...
    'failureReason', '');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
