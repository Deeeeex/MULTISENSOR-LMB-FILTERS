function [reportPath, validation] = ...
    summarizeLabelSetAdaptiveDominantPayloadAwareDevelopmentM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTPAYLOADAWAREDEVELOPMENTM24 Tuning gate.
%
% These two seeds were already opened by D-B v1.  They are therefore
% redesign/tuning evidence, not a renewed validation split.  Passing may
% freeze the method before a later one-shot held-out M24 evaluation.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol. ...
        adaptiveDominantPayloadAwareDevelopmentEvaluationAuthorized || ...
        protocol.adaptiveDominantPayloadAwareHeldoutM24Authorized || ...
        protocol.adaptiveDominantPayloadAwareX36Authorized
    error('Payload-aware development tuning summary is not authorized.');
end
seeds = protocol.adaptiveDominantPayloadAwareDevelopmentSeeds;
rootDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_payload_aware_screen_v2', ...
    sprintf('margin%03d', protocol. ...
        adaptiveDominantPayloadAwareSelectedMarginToken), ...
    'development'));
rows = repmat(emptyRow(), 1, numel(seeds));
runCommit = '';
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    baseline = loadBaseline(seed, protocol);
    path = findSingleEvidence(rootDirectory, seed);
    loaded = load(path, 'summary');
    summary = loaded.summary;
    validateSummary(summary, seed, protocol);
    if isempty(runCommit)
        runCommit = summary.generationGitCommit;
    elseif ~strcmp(runCommit, summary.generationGitCommit)
        error('Payload-aware development runs use different commits.');
    end
    candidate = findArm(summary.aggregate, ...
        protocol. ...
            adaptiveDominantPayloadAwareDevelopmentCandidateArmName);
    row = emptyRow();
    row.seed = seed;
    row.evidencePath = path;
    row.baselineEospa = baseline.focusEospa;
    row.candidateEospa = candidate.focusEospa;
    row.gainPercent = relativeGain( ...
        row.baselineEospa, row.candidateEospa);
    row.baselineWorstEospa = ...
        baseline.focusWorstSensorEospa;
    row.candidateWorstEospa = ...
        candidate.focusWorstSensorEospa;
    row.baselineConsensusOspa = ...
        baseline.focusMapSetDisagreement;
    row.candidateConsensusOspa = ...
        candidate.focusMapSetDisagreement;
    row.byteDeltaPercent = 100 * ...
        (candidate.focusAttemptedBytes - ...
         baseline.focusAttemptedBytes) / ...
            max(baseline.focusAttemptedBytes, eps);
    row.meanMessageCount = ...
        candidate.meanDirectedMessageCount;
    row.selectedSensorB3 = candidate. ...
        focusSelectedRollingB3SensorStrongFraction;
    row.selectedFormationB3 = candidate. ...
        focusSelectedRollingB3FormationStrongFraction;
    row.deliveredSensorB3 = candidate. ...
        focusDeliveredRollingB3SensorStrongFraction;
    row.truthUseFraction = candidate.policyTruthUseFraction;
    row.posteriorUseFraction = ...
        candidate.policyPosteriorContentUseFraction;
    row.payloadMetadataUseFraction = candidate. ...
        policyPosteriorPayloadMetadataUseFraction;
    row.currentLinkReliabilityUseFraction = candidate. ...
        policyCurrentLinkReliabilityUseFraction;
    row.payloadConstraintFraction = candidate. ...
        policyPayloadConstraintEnforcedFraction;
    row.payloadLimitPassFraction = candidate. ...
        policyPayloadLimitPassFraction;
    row.repairRate = candidate.policyRepairRate;
    row.payloadEmergencyRate = ...
        candidate.policyPayloadEmergencyRate;
    row.topologyInfeasibleRate = ...
        candidate.focusTopologyInfeasibleRate;
    row.distinctRouteMaps = ...
        candidate.focusDistinctDirectedRouteMapCount;
    row.hardSafetyPassed = hardSafetyPassed(row, protocol);
    rows(seedIdx) = row;
end

baselineMean = mean([rows.baselineEospa]);
candidateMean = mean([rows.candidateEospa]);
meanGain = relativeGain(baselineMean, candidateMean);
positiveFraction = mean([rows.gainPercent] > 0);
worstGain = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
consensusGain = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
byteDeltas = [rows.byteDeltaPercent];
maximumPositiveByteDelta = max([0, byteDeltas]);
maximumAbsoluteByteDelta = max(abs(byteDeltas));
hardSafetyPassedAll = all([rows.hardSafetyPassed]);
trackingGatePassed = ...
    meanGain >= protocol. ...
        adaptiveDominantPayloadAwareMinimumMeanGainPercent && ...
    positiveFraction == 1;
tailGatePassed = worstGain >= -1e-12 && ...
    consensusGain >= -1e-12;
communicationGatePassed = ...
    maximumPositiveByteDelta <= protocol. ...
        adaptiveDominantPayloadAwareMaximumPositiveByteDeltaPercent + ...
            1e-12 && ...
    maximumAbsoluteByteDelta <= protocol. ...
        adaptiveDominantPayloadAwareMaximumAbsoluteByteDeltaPercent + ...
            1e-12;
developmentTuningGatePassed = hardSafetyPassedAll && ...
    trackingGatePassed && tailGatePassed && ...
    communicationGatePassed;

gitState = resolveResearchGitState();
validation = struct();
validation.protocolId = protocol.id;
validation.contractVersion = ...
    protocol.adaptiveDominantPayloadAwareRoutingContractVersion;
validation.generatedAt = datestr(now, 31);
validation.generationGitCommit = gitState.commit;
validation.runGenerationGitCommit = runCommit;
validation.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
validation.seeds = seeds;
validation.times = ...
    protocol.adaptiveDominantPayloadAwareDevelopmentTimes;
validation.selectedMarginFraction = ...
    protocol.adaptiveDominantPayloadAwareSelectedMarginFraction;
validation.rows = rows;
validation.baselineMeanEospa = baselineMean;
validation.candidateMeanEospa = candidateMean;
validation.meanGainPercent = meanGain;
validation.positiveSeedFraction = positiveFraction;
validation.aggregateWorstGainPercent = worstGain;
validation.aggregateConsensusGainPercent = consensusGain;
validation.maximumPositiveByteDeltaPercent = ...
    maximumPositiveByteDelta;
validation.maximumAbsoluteByteDeltaPercent = ...
    maximumAbsoluteByteDelta;
validation.hardSafetyPassed = hardSafetyPassedAll;
validation.trackingGatePassed = trackingGatePassed;
validation.tailGatePassed = tailGatePassed;
validation.communicationGatePassed = communicationGatePassed;
validation.developmentTuningGatePassed = ...
    developmentTuningGatePassed;
validation.splitWasAlreadyOpened = true;
validation.validationClaimAllowed = false;
validation.heldoutM24Opened = false;
validation.x36Opened = false;
validation.nextDirection = chooseNextDirection( ...
    developmentTuningGatePassed);
validation.evidenceBoundary = [ ...
    'Seeds 31 and 37 were already opened by D-B v1. These results ', ...
    'may tune and freeze v2 but are not fresh validation evidence. ', ...
    'Held-out M24 and X36 remain sealed in this report.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(rootDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_PAYLOAD_AWARE_DEVELOPMENT_M24_V2.md');
writeReport(reportPath, validation, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
validation.reportPath = reportPath;
validation.matPath = matPath;
fprintf('Payload-aware development summary: %s\n', reportPath);
end

function baseline = loadBaseline(seed, protocol)
seedIdx = find( ...
    protocol.adaptiveDominantDevelopmentSeeds == seed, 1);
path = protocol.adaptiveDominantDevelopmentMatPaths{seedIdx};
expectedHash = protocol. ...
    adaptiveDominantDevelopmentMatSha256{seedIdx};
if ~strcmp(computeFileSha256(path), expectedHash)
    error('Frozen development baseline hash mismatch.');
end
loaded = load(path, 'summary');
baseline = findArm(loaded.summary.aggregate, protocol. ...
    adaptiveDominantPayloadAwareDevelopmentReferenceArmName);
end

function path = findSingleEvidence(rootDirectory, seed)
matches = dir(fullfile(rootDirectory, ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one payload-aware development MAT for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function validateSummary(summary, seed, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'development') || ...
        summary.options.continuationStartTime ~= protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTimes(1) || ...
        summary.options.maxTimeSteps ~= protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTimes(end) || ...
        ~any(strcmp({summary.aggregate.mode}, protocol. ...
            adaptiveDominantPayloadAwareDevelopmentCandidateArmName)) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Payload-aware development provenance contract failed.');
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Development evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    abs(row.meanMessageCount - protocol. ...
        adaptiveDominantPayloadAwareExpectedMessageCount) < 1e-12 && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.payloadMetadataUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.payloadConstraintFraction == 1 && ...
    row.payloadLimitPassFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(reference, eps);
end

function direction = chooseNextDirection(passed)
if passed
    direction = ...
        'freeze-v2-and-pre-register-one-shot-heldout-M24';
else
    direction = ...
        'stop-without-opening-heldout-M24-or-X36';
end
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'evidencePath', '', ...
    'baselineEospa', NaN, ...
    'candidateEospa', NaN, ...
    'gainPercent', NaN, ...
    'baselineWorstEospa', NaN, ...
    'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, ...
    'candidateConsensusOspa', NaN, ...
    'byteDeltaPercent', NaN, ...
    'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, ...
    'selectedFormationB3', NaN, ...
    'deliveredSensorB3', NaN, ...
    'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'payloadMetadataUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'payloadConstraintFraction', NaN, ...
    'payloadLimitPassFraction', NaN, ...
    'repairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'distinctRouteMaps', NaN, ...
    'hardSafetyPassed', false);
end

function writeReport(path, validation, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write payload-aware development report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 payload-aware adaptive-dominant development tuning\n\n');
fprintf(fid, '- Contract: `%s`\n', validation.contractVersion);
fprintf(fid, '- Generated: %s\n', validation.generatedAt);
fprintf(fid, '- Run commit: `%s`\n', ...
    validation.runGenerationGitCommit);
fprintf(fid, '- Selected margin: `%.1f%%`\n', ...
    100 * validation.selectedMarginFraction);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seeds));
fprintf(fid, '- Window: `%s`\n\n', mat2str(validation.times));
fprintf(fid, ['| Seed | CCW E-OSPA | Candidate E-OSPA | Gain | ', ...
    'CCW worst | Candidate worst | CCW consensus | ', ...
    'Candidate consensus | Byte delta | Msgs | Selected B3 | ', ...
    'Delivered B3 | Maps | Safe |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|--:|:--:|\n']);
for row = validation.rows
    fprintf(fid, ['| %d | %.6f | %.6f | %+.3f%% | %.6f | ', ...
        '%.6f | %.6f | %.6f | %+.3f%% | %.2f | %.3f | ', ...
        '%.3f | %.0f | %d |\n'], ...
        row.seed, row.baselineEospa, row.candidateEospa, ...
        row.gainPercent, row.baselineWorstEospa, ...
        row.candidateWorstEospa, row.baselineConsensusOspa, ...
        row.candidateConsensusOspa, row.byteDeltaPercent, ...
        row.meanMessageCount, row.selectedSensorB3, ...
        row.deliveredSensorB3, row.distinctRouteMaps, ...
        row.hardSafetyPassed);
end
fprintf(fid, '\n## Redesign tuning gate\n\n');
fprintf(fid, '- Mean CCW E-OSPA: `%.6f`\n', ...
    validation.baselineMeanEospa);
fprintf(fid, '- Mean candidate E-OSPA: `%.6f`\n', ...
    validation.candidateMeanEospa);
fprintf(fid, '- Mean gain: `%+.3f%%`\n', ...
    validation.meanGainPercent);
fprintf(fid, '- Positive seeds: `%d/%d`\n', ...
    nnz([validation.rows.gainPercent] > 0), ...
    numel(validation.rows));
fprintf(fid, '- Aggregate worst-node gain: `%+.3f%%`\n', ...
    validation.aggregateWorstGainPercent);
fprintf(fid, '- Aggregate consensus gain: `%+.3f%%`\n', ...
    validation.aggregateConsensusGainPercent);
fprintf(fid, '- Maximum positive byte delta: `%.3f%%`\n', ...
    validation.maximumPositiveByteDeltaPercent);
fprintf(fid, '- Maximum absolute byte delta: `%.3f%%`\n', ...
    validation.maximumAbsoluteByteDeltaPercent);
fprintf(fid, '- Hard safety passed: `%d`\n', ...
    validation.hardSafetyPassed);
fprintf(fid, '- Tracking gate passed: `%d`\n', ...
    validation.trackingGatePassed);
fprintf(fid, '- Tail gate passed: `%d`\n', ...
    validation.tailGatePassed);
fprintf(fid, '- Communication gate passed: `%d`\n', ...
    validation.communicationGatePassed);
fprintf(fid, '- Development tuning gate passed: `%d`\n', ...
    validation.developmentTuningGatePassed);
fprintf(fid, '- Fresh validation claim allowed: `%d`\n', ...
    validation.validationClaimAllowed);
fprintf(fid, '- Next: `%s`\n\n', validation.nextDirection);
fprintf(fid, '%s\n', validation.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
