function [reportPath, result] = ...
    runTrackingAlignedM24NetworkAdditiveV65(options)
% RUNTRACKINGALIGNEDM24NETWORKADDITIVEV65 Paired M24 V65 headroom.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getNetworkAdditiveFormationRiskV65Protocol();
currentTime = getField(options, 'currentTime', 104);
registeredTimes = [104, 124];
if ~isscalar(currentTime) || ~ismember(currentTime, registeredTimes)
    error('NetworkAdditiveM24V65:InvalidAnchor', ...
        'V65 M24 currentTime must be 104 or 124.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('NetworkAdditiveM24V65:DirtySource', ...
        'V65 M24 headroom requires a clean source checkout.');
end

target = resolveTarget( ...
    protocol.m24OpenedTrackingTargets, currentTime);
entry = resolveCase(protocol.m24Cases, ...
    target.presetName, target.seed);
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v65', 'm24_network_additive_headroom', ...
    sprintf('t%d', currentTime)));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', 100000, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v65-network-additive-headroom', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', ...
            protocol.positiveSupportThreshold, ...
        'bankVariant', 'network-additive-v65'), ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    target.presetName, target.seed, currentTime, screenOptions);

selection = screen.bank.networkRiskSelection;
if ~selection.actionEnabled || screen.bank.actionCount ~= 2
    error('NetworkAdditiveM24V65:UnexpectedFallback', ...
        'The registered strong M24 state did not produce one V65 action.');
end
records = screen.records;
referenceIdx = screen.referenceSubsetIndex;
candidateMask = true(1, numel(records));
candidateMask(referenceIdx) = false;
strictMask = candidateMask & ...
    [records.posteriorProxyAllowed] & ...
    [records.selectedB3Passed] & ...
    [records.minimumFormationGainPercent] >= ...
        protocol.minimumFormationGainPercent - 1e-12 & ...
    [records.worstGainPercent] >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 & ...
    [records.consensusGainPercent] >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 & ...
    [records.terminalConsensusGainPercent] >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 & ...
    [records.attemptedByteSavingPercent] >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12;
candidateIndices = find(strictMask);
if isempty(candidateIndices)
    bestIdx = referenceIdx;
    bestGain = 0;
else
    [bestGain, localIdx] = max( ...
        [records(candidateIndices).meanGainPercent]);
    bestIdx = candidateIndices(localIdx);
end

result = struct();
result.contractVersion = ...
    'tracking-aligned-m24-network-additive-v65-result-v1';
result.protocol = protocol;
result.currentTime = currentTime;
result.presetName = target.presetName;
result.seed = target.seed;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.screenReportPath = screenReportPath;
result.screenMatPath = screen.matPath;
result.networkRiskSelection = selection;
result.strictCandidateCount = nnz(strictMask);
result.bestStrictActionName = records(bestIdx).actionName;
result.bestStrictMeanGainPercent = bestGain;
result.bestStrictWorstGainPercent = records(bestIdx).worstGainPercent;
result.bestStrictMinimumFormationGainPercent = ...
    records(bestIdx).minimumFormationGainPercent;
result.bestStrictWindowConsensusGainPercent = ...
    records(bestIdx).consensusGainPercent;
result.bestStrictTerminalConsensusGainPercent = ...
    records(bestIdx).terminalConsensusGainPercent;
result.bestStrictAttemptedByteSavingPercent = ...
    records(bestIdx).attemptedByteSavingPercent;
result.strongHeadroomGatePassed = bestGain >= ...
    protocol.minimumMeanGainPercent - 1e-12;
result.priorKnownGainPercent = target.meanGainPercent;
result.priorKnownGainSource = target.source;
result.openedDevelopmentEvidenceOnly = true;
result.validationClaimAllowed = false;

matPath = fullfile(outputRoot, sprintf( ...
    'TRACKING_ALIGNED_M24_NETWORK_ADDITIVE_V65_T%d_RESULT.mat', ...
    currentTime));
reportPath = fullfile(outputRoot, sprintf( ...
    'TRACKING_ALIGNED_M24_NETWORK_ADDITIVE_V65_T%d_RESULT.md', ...
    currentTime));
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result, records, strictMask);
fprintf('V65 M24 network-additive result: %s\n', reportPath);
end

function writeReport(path, result, records, strictMask)
fid = fopen(path, 'w');
if fid < 0
    error('NetworkAdditiveM24V65:WriteFailed', ...
        'Could not create the V65 M24 result report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
selection = result.networkRiskSelection;
fprintf(fid, '# V65 M24 network-additive headroom at t=%d\n\n', ...
    result.currentTime);
fprintf(fid, '- Network risk / budget: `%.3f%% / %.3f%%`\n', ...
    100 * selection.totalNetworkRiskFraction, ...
    100 * selection.minimumNetworkRiskFraction);
fprintf(fid, '- Selected formations / coverage: `%s / %.3f%%`\n', ...
    mat2str(selection.selectedFormationIds), ...
    100 * selection.achievedCoverageFraction);
fprintf(fid, '- Useful-loss / rescue ratio: `%.3f%%`\n\n', ...
    100 * selection.usefulLossToRescueRatio);
fprintf(fid, ['| Action | Mean tracking | Worst sensor | ', ...
    'Minimum formation | Window consensus | Terminal consensus | ', ...
    'Attempted bytes | Strict |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(records)
    record = records(idx);
    fprintf(fid, ['| `%s` | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %d |\n'], ...
        record.actionName, record.meanGainPercent, ...
        record.worstGainPercent, record.minimumFormationGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent, strictMask(idx));
end
fprintf(fid, '\n- Strong headroom gate (at least %.1f%%): `%d`\n', ...
    result.protocol.minimumMeanGainPercent, ...
    result.strongHeadroomGatePassed);
fprintf(fid, ['- Evidence boundary: opened M24 development state; ', ...
    'no held-out or validation claim.\n']);
end

function target = resolveTarget(targets, currentTime)
mask = strcmp({targets.presetName}, 'm24-formation-fov') & ...
    [targets.seed] == 211 & [targets.currentTime] == currentTime;
if nnz(mask) ~= 1
    error('NetworkAdditiveM24V65:MissingTarget', ...
        'The M24 V65 anchor does not have one registered target.');
end
target = targets(find(mask, 1));
end

function entry = resolveCase(cases, presetName, seed)
mask = strcmp({cases.presetName}, presetName) & [cases.seed] == seed;
if nnz(mask) ~= 1
    error('NetworkAdditiveM24V65:MissingCase', ...
        'The M24 V65 anchor does not have one registered cache case.');
end
entry = cases(find(mask, 1));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
