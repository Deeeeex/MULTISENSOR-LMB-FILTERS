function [artifactPath, screen] = ...
        runSpatialLabelSupportDebtRoutingV147Screen(presetName, options)
% RUNSPATIALLABELSUPPORTDEBTROUTINGV147SCREEN Evaluate one frozen row action.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getSpatialLabelSupportDebtRoutingV147Protocol();
gitState = requireCleanSource();
caseInfo = resolveCase(protocol, presetName);
seed = getField(options, 'seed', protocol.pilotSeed);
if seed ~= protocol.pilotSeed
    error('SpatialDebtV147:UnsupportedSeed', ...
        'The first V147 screen is frozen to the registered pilot seed.');
end
anchorTime = resolveSetTrustSequenceV134PilotAnchor(caseInfo, protocol);
bankStatePath = getField(options, 'bankStatePath', ...
    defaultBankStatePath(protocol, presetName, seed, anchorTime));
loadedBank = load(bankStatePath, 'bankState');
bankState = validateBankState( ...
    loadedBank, protocol, caseInfo, presetName, seed, anchorTime);
actionIndex = getField(options, 'actionIndex', 0);
if ~isscalar(actionIndex) || ~isfinite(actionIndex) || ...
        actionIndex ~= round(actionIndex) || actionIndex < 2 || ...
        actionIndex > bankState.bank.actionCount
    error('SpatialDebtV147:InvalidActionIndex', ...
        'Select one nonreference action from the frozen V147 bank.');
end
actionSpec = bankState.bank.actions(actionIndex);
if ~logical(actionSpec.gateEligible)
    error('SpatialDebtV147:IneligibleAction', ...
        'The selected V147 action failed the pre-outcome graph bank gate.');
end

loadedState = load(bankState.v134PilotStatePath, 'pilotState');
state = validateV134State( ...
    loadedState, presetName, seed, anchorTime, caseInfo);
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
maximumTime = anchorTime + caseInfo.horizonSteps - 1;
truth = cropTrackingTruthRfs(inputs.groundTruthRfs, maximumTime);
inputs = isolateRuntimeInputs(inputs);
inputs = cropInputs(inputs, maximumTime);
config = buildRuntimeConfig( ...
    inputs.config, state.referenceCarrierMode, anchorTime, ...
    actionSpec, protocol);
executionContext = ...
    buildSpatialLabelSupportDebtRoutingV147ExecutionContext( ...
        presetName, seed, anchorTime, ...
        state.referenceCarrierMode, actionSpec);
candidate = runContinuation( ...
    inputs, truth, state, anchorTime, config, executionContext, ...
    seed, protocol);
reference = state.referenceOutcome;
metrics = scoreSpatialLabelSupportDebtRoutingV147Outcome( ...
    reference, candidate, state.groupIds, ...
    caseInfo.recoveryTailSteps, actionSpec, protocol);

screen = struct( ...
    'contractVersion', ...
        'v147-spatial-label-support-debt-routing-screen-v1', ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'anchorTime', anchorTime, ...
    'referenceCarrierMode', state.referenceCarrierMode, ...
    'actionIndex', actionIndex, ...
    'actionSpec', actionSpec, ...
    'metrics', metrics, ...
    'candidateOutcome', candidate, ...
    'bankGenerationGitCommit', bankState.generationGitCommit, ...
    'generationGitCommit', gitState.commit, ...
    'communicationMethodClaimAllowed', false, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', ...
        'repository-only-until-joint-cross-scale-gate-passes');
outputDirectory = fullfile(protocol.outputRoot, 'pilot', ...
    strrep(presetName, '-', '_'), ...
    sprintf('seed%d_t%d', seed, anchorTime), ...
    sprintf('action%02d_%s', actionIndex, ...
        regexprep(lower(actionSpec.name), '[^a-z0-9]+', '_')));
artifactPath = fullfile(outputDirectory, 'SCREEN_RESULT_V147.mat');
atomicSave(artifactPath, 'screen', screen);
writeReport(fullfile(outputDirectory, 'SCREEN_RESULT_V147.md'), screen);
fprintf([ ...
    'V147 %s action %02d intervention=%+.3f%% full=%+.3f%% ', ...
    'mature=%+.3f%% min-sensor=%+.3f%% min-formation=%+.3f%% ', ...
    'consensus=%+.3f%% bytes=%+.3f%% pass=%d\n'], ...
    caseInfo.scaleName, actionIndex, ...
    100 * metrics.interventionGainFraction, ...
    100 * metrics.meanGainFraction, ...
    100 * metrics.matureGainFraction, ...
    100 * metrics.minimumSensorGainFraction, ...
    100 * metrics.minimumFormationGainFraction, ...
    100 * metrics.consensusGainFraction, ...
    100 * metrics.attemptedByteDeltaFraction, ...
    metrics.passesHeadroomGate);
end

function config = buildRuntimeConfig( ...
        scenarioConfig, carrierMode, anchorTime, actionSpec, protocol)
config = buildMixtureAwareKlaReferenceConfig(struct( ...
    'missingLabelFusionMode', 'fov-aware-censored', ...
    'missingNeighborWeightMode', ...
        protocol.primaryMissingNeighborWeightMode, ...
    'fusionWeightMode', protocol.nominalKlaWeightMode, ...
    'useStaleNeighborCache', false));
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * scenarioConfig.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicySensorObservationEnabled = true;
config.topologyPolicyDeliveryHistoryEnabled = false;
config.topologyPolicyName = protocol.outcomePolicyName;
config.v147ReferenceCarrierMode = carrierMode;
config.topologyPolicyFcn = @(context) ...
    selectSpatialLabelSupportDebtRoutingV147Policy( ...
        context, anchorTime, carrierMode, actionSpec);
config.receiverSafeLabelFusionEnabled = false;
config.receiverSafeFormationConditionedOnlinePolicyEnabled = false;
end

function outcome = runContinuation( ...
        inputs, truth, state, anchorTime, config, executionContext, ...
        seed, protocol)
returnTimes = anchorTime + (0:(executionContext.horizonSteps - 1));
config.filterInitialLocalPosteriorBySensor = state.initialPosteriors;
config.filterInitialLocalPosteriorTime = anchorTime;
config.filterInitialPreviousAdjacencyHistory = state.previousPolicyHistory;
config.filterInitialPreviousAdjacencyTimes = state.history.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'v134-paired-reference-prefix';
config.filterInitialLocalUpdateHistoryTimes = state.updateHistory.times;
config.filterInitialLocalInnovationHistory = state.updateHistory.innovation;
config.filterInitialLocalAssociationConfidenceHistory = ...
    state.updateHistory.associationConfidence;
config.filterInitialLocalNisNormHistory = state.updateHistory.nisNorm;
config.filterInitialLocalNisDeviationHistory = ...
    state.updateHistory.nisDeviation;
rng(seed + protocol.filterSeedOffset);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, executionContext);
elapsedSeconds = toc(timerId);
auditRuntime(diagnostics, returnTimes);
outcome = scoreOutcome( ...
    inputs.model, truth, estimates, diagnostics, inputs.commConfig, ...
    returnTimes, elapsedSeconds);
end

function outcome = scoreOutcome( ...
        model, truth, estimates, diagnostics, commConfig, ...
        returnTimes, elapsedSeconds)
nodeCount = numel(estimates);
eospa = zeros(nodeCount, numel(returnTimes));
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, ~] = computeSimulationOspa( ...
        model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa(returnTimes);
end
outcome = struct();
outcome.eospaBySensorTime = eospa;
outcome.posteriorConsensusByTime = reshape( ...
    diagnostics.posteriorConsensusCombined(returnTimes), 1, []);
outcome.attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes(:, :, returnTimes), 1), 2), ...
    1, []);
outcome.deliveredBytesByTime = reshape(sum(sum( ...
    diagnostics.payloadBytes(:, :, returnTimes), 1), 2), 1, []);
outcome.elapsedSeconds = elapsedSeconds;
outcome.selectedAdjacencyByTime = false( ...
    nodeCount, nodeCount, numel(returnTimes));
outcome.nominalFusionWeightsByTime = zeros( ...
    nodeCount, nodeCount, numel(returnTimes));
for timeIdx = 1:numel(returnTimes)
    currentTime = returnTimes(timeIdx);
    outcome.selectedAdjacencyByTime(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge(:, :, currentTime));
    outcome.nominalFusionWeightsByTime(:, :, timeIdx) = ...
        diagnostics.topologyPolicyFusionWeightMatrix{currentTime};
end
outcome.pDropByEdgeByTime = commConfig.pDropByEdge(:, :, returnTimes);
outcome.attemptedEdgeByTime = logical( ...
    diagnostics.attempted(:, :, returnTimes));
outcome.deliveredEdgeByTime = logical( ...
    diagnostics.delivered(:, :, returnTimes));
end

function state = validateBankState( ...
        loaded, protocol, caseInfo, presetName, seed, anchorTime)
if ~isfield(loaded, 'bankState') || ...
        ~isstruct(loaded.bankState) || ...
        ~strcmp(loaded.bankState.contractVersion, ...
            'v147-spatial-label-support-debt-routing-bank-state-v1') || ...
        ~strcmp(loaded.bankState.protocolId, protocol.id) || ...
        ~strcmp(loaded.bankState.presetName, presetName) || ...
        loaded.bankState.seed ~= seed || ...
        loaded.bankState.anchorTime ~= anchorTime || ...
        loaded.bankState.horizonSteps ~= caseInfo.horizonSteps || ...
        ~isstruct(loaded.bankState.bank) || ...
        ~strcmp(loaded.bankState.bank.protocolId, protocol.id) || ...
        loaded.bankState.bank.actionCount ~= ...
            numel(protocol.actionPatterns)
    error('SpatialDebtV147:InvalidBankState', ...
        'The frozen V147 action bank is malformed or mismatched.');
end
state = loaded.bankState;
end

function state = validateV134State( ...
        loaded, presetName, seed, anchorTime, caseInfo)
if ~isfield(loaded, 'pilotState') || ...
        ~isstruct(loaded.pilotState) || ...
        ~strcmp(loaded.pilotState.contractVersion, ...
            'v134-binary-admission-pilot-state-v4') || ...
        ~strcmp(loaded.pilotState.presetName, presetName) || ...
        loaded.pilotState.seed ~= seed || ...
        loaded.pilotState.anchorTime ~= anchorTime || ...
        loaded.pilotState.horizonSteps ~= caseInfo.horizonSteps
    error('SpatialDebtV147:InvalidV134State', ...
        'The frozen V134 state is malformed or mismatched.');
end
state = loaded.pilotState;
end

function auditRuntime(diagnostics, times)
truthUse = finiteLogical(diagnostics.topologyPolicyTruthUsed(times));
repair = finiteLogical(diagnostics.topologyPolicyRepairTriggered(times));
emergency = finiteLogical( ...
    diagnostics.topologyPolicyPayloadEmergencyUsed(times));
infeasible = logical(~diagnostics.topologyFeasible(times) | ...
    finiteLogical(diagnostics.topologyPolicyTopologyInfeasible(times)));
if any(truthUse) || any(repair) || any(emergency) || any(infeasible)
    error('SpatialDebtV147:RuntimeGateFailure', ...
        'The V147 candidate violated a hard runtime gate.');
end
end

function output = finiteLogical(value)
output = false(size(value));
finite = isfinite(value);
output(finite) = logical(value(finite));
end

function inputs = isolateRuntimeInputs(inputs)
present = intersect( ...
    {'groundTruth', 'groundTruthRfs', 'targetTrajectories'}, ...
    fieldnames(inputs), 'stable');
if ~isempty(present)
    inputs = rmfield(inputs, present);
end
if isfield(inputs.model, 'explicitTargetTrajectories')
    inputs.model = rmfield(inputs.model, 'explicitTargetTrajectories');
end
if isfield(inputs.model, 'dynamicTopologyScenario')
    present = intersect({'targetTrajectories', 'target'}, ...
        fieldnames(inputs.model.dynamicTopologyScenario), 'stable');
    if ~isempty(present)
        inputs.model.dynamicTopologyScenario = rmfield( ...
            inputs.model.dynamicTopologyScenario, present);
    end
end
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function truth = cropTrackingTruthRfs(truth, maximumTime)
truth.x = truth.x(1:maximumTime);
truth.mu = truth.mu(1:maximumTime);
truth.Sigma = truth.Sigma(1:maximumTime);
truth.cardinality = truth.cardinality(1:maximumTime);
end

function writeReport(path, screen)
parent = fileparts(path);
if exist(parent, 'dir') ~= 7
    mkdir(parent);
end
fid = fopen(path, 'w');
if fid < 0
    error('SpatialDebtV147:ReportWriteFailed', ...
        'Could not create the V147 screen report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
m = screen.metrics;
fprintf(fid, '# V147 spatial label-support debt routing: %s\n\n', ...
    screen.scaleName);
fprintf(fid, ['Repository-only development evidence. This single arm ', ...
    'does not establish a communication method or validation claim.\n\n']);
fprintf(fid, '- Seed / anchor / action: `%d / %d / %02d %s`\n', ...
    screen.seed, screen.anchorTime, screen.actionIndex, ...
    screen.actionSpec.name);
fprintf(fid, '- Selected formations: `%s`\n', ...
    mat2str(screen.actionSpec.selectedFormationIds));
fprintf(fid, '- Intervention E-OSPA gain: `%+.3f%%`\n', ...
    100 * m.interventionGainFraction);
fprintf(fid, '- Full / mature E-OSPA gain: `%+.3f%% / %+.3f%%`\n', ...
    100 * m.meanGainFraction, 100 * m.matureGainFraction);
fprintf(fid, '- Minimum sensor / formation gain: `%+.3f%% / %+.3f%%`\n', ...
    100 * m.minimumSensorGainFraction, ...
    100 * m.minimumFormationGainFraction);
fprintf(fid, '- Consensus gain: `%+.3f%%`\n', ...
    100 * m.consensusGainFraction);
fprintf(fid, '- Attempted-byte delta: `%+.3f%%`\n', ...
    100 * m.attemptedByteDeltaFraction);
fprintf(fid, '- Active execution / exact rejoin: `%.3f / %.3f`\n', ...
    m.activeExecutedFraction, m.rejoinedReferenceFraction);
fprintf(fid, '- Joint gate for this scale: `%d`\n', ...
    m.passesHeadroomGate);
end

function path = defaultBankStatePath( ...
        protocol, presetName, seed, anchorTime)
path = fullfile(protocol.outputRoot, 'pilot', ...
    strrep(presetName, '-', '_'), ...
    sprintf('seed%d_t%d', seed, anchorTime), 'BANK_STATE_V147.mat');
end

function caseInfo = resolveCase(protocol, presetName)
caseIdx = find(strcmp({protocol.scaleCases.presetName}, presetName), 1);
if isempty(caseIdx)
    error('SpatialDebtV147:InvalidPreset', ...
        'The preset is outside the V147 scale contract.');
end
caseInfo = protocol.scaleCases(caseIdx);
end

function gitState = requireCleanSource()
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('SpatialDebtV147:DirtySource', ...
        'Official V147 tracking outcomes require clean source.');
end
end

function atomicSave(path, variableName, value)
parent = fileparts(path);
if exist(parent, 'dir') ~= 7
    mkdir(parent);
end
temporary = [path, '.partial'];
payload = struct();
payload.(variableName) = value;
save('-mat7-binary', temporary, '-struct', 'payload');
[ok, message] = movefile(temporary, path, 'f');
if ~ok
    error('SpatialDebtV147:AtomicSaveFailed', '%s', message);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
