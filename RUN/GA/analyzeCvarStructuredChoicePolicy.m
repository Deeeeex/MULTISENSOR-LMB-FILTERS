function [analysisPath, analysis] = ...
    analyzeCvarStructuredChoicePolicy(options)
% ANALYZECVARSTRUCTUREDCHOICEPOLICY Training-only bridge-choice LOSO.
%
% One selected bridge-weight action is ranked against the two admissible
% cyclic sender formations for each receiving formation. This removes the
% global 4-positive-versus-thousands imbalance of the rejected dense edge
% regressors and aligns supervision with the exact cycle projector.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCvarResidualGraphPolicyDatasetProtocol();
if ~protocol.rejectedV2 || ...
        ~protocol.structuredChoicePivotAuthorized || ...
        protocol.developmentEvaluationAuthorized
    error('Structured-choice analysis is not authorized.');
end
bundle = loadCvarResidualGraphPolicyShards('training');
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official structured-choice analysis requires clean source.');
end

featureVariants = {'edge-only', 'edge-update-relational'};
ridgeLambdas = [1e-2, 1e-1, 1, 10, 100];
candidates = repmat(emptyCandidate(), 1, ...
    numel(featureVariants) * numel(ridgeLambdas));
candidateCursor = 0;
for variantIdx = 1:numel(featureVariants)
    variant = featureVariants{variantIdx};
    rowsByLambda = cell(1, numel(ridgeLambdas));
    for foldIdx = 1:numel(protocol.outerLosoHeldoutSeeds)
        heldoutSeed = ...
            protocol.outerLosoHeldoutSeeds(foldIdx);
        calibrationSeed = ...
            protocol.outerLosoCalibrationSeeds(foldIdx);
        fitSeeds = setdiff(protocol.trainingSeeds, ...
            [heldoutSeed, calibrationSeed], 'stable');
        fitMask = ismember( ...
            [bundle.graphBlocks.seed], fitSeeds);
        testMask = [bundle.graphBlocks.seed] == ...
            heldoutSeed;
        training = buildChoiceTraining( ...
            bundle.graphBlocks(fitMask), ...
            bundle.behaviorBlocks(fitMask), variant);
        models = fitChoiceRidgeFamily( ...
            training, ridgeLambdas);
        for lambdaIdx = 1:numel(ridgeLambdas)
            foldRows = evaluateChoiceModel( ...
                models(lambdaIdx), ...
                bundle.graphBlocks(testMask), ...
                bundle.behaviorBlocks(testMask), protocol);
            rowsByLambda{lambdaIdx} = [ ...
                rowsByLambda{lambdaIdx}, ...
                foldRows]; %#ok<AGROW>
        end
    end
    for lambdaIdx = 1:numel(ridgeLambdas)
        candidateCursor = candidateCursor + 1;
        candidate = emptyCandidate();
        candidate.featureVariant = variant;
        candidate.lambda = ridgeLambdas(lambdaIdx);
        candidate.rows = rowsByLambda{lambdaIdx};
        candidate.metrics = summarizeRows( ...
            candidate.rows);
        candidates(candidateCursor) = candidate;
    end
end

analysis = struct();
analysis.contractVersion = ...
    'm24-cvar-structured-formation-bridge-choice-analysis-v1';
analysis.generatedAt = datestr(now, 31);
analysis.generationGitCommit = gitState.commit;
analysis.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
analysis.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
analysis.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
analysis.protocolId = protocol.id;
analysis.datasetSetSha256 = ...
    protocol.fullShardDatasetSetSha256;
analysis.featureContractSha256 = ...
    protocol.fullShardFeatureContractSha256;
analysis.trainingSeeds = protocol.trainingSeeds;
analysis.developmentSeedsOpened = false;
analysis.featureVariants = featureVariants;
analysis.ridgeLambdas = ridgeLambdas;
analysis.candidates = candidates;
analysis.bestCandidate = selectBestCandidate(candidates);
analysis.developmentEvaluationAuthorized = false;
analysis.heldoutM24Authorized = false;
analysis.x36Authorized = false;
analysis.evidenceBoundary = [ ...
    'This is a training-only architecture analysis on already-opened ', ...
    'seeds. Hyperparameters are compared on the same outer LOSO ', ...
    'results, so the best row is diagnostic rather than a frozen ', ...
    'generalization estimate. No development labels are opened.'];

analysisPath = getField(options, 'analysisPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'cvar_structured_choice_policy_analysis_m24.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'CVAR_STRUCTURED_CHOICE_POLICY_ANALYSIS_M24.md'));
analysis.analysisPath = analysisPath;
analysis.reportPath = reportPath;
save('-mat7-binary', analysisPath, 'analysis');
writeReport(reportPath, analysis);
fprintf('CVaR structured-choice analysis: %s\nReport: %s\n', ...
    analysisPath, reportPath);
end

function training = buildChoiceTraining( ...
        graphBlocks, behaviorBlocks, variant)
actionX = zeros(0, 0);
actionBlock = zeros(0, 1);
actionReceiverGroup = zeros(0, 1);
actionSenderGroup = zeros(0, 1);
selected = false(0, 1);
blockCursor = 0;
for blockIdx = 1:numel(graphBlocks)
    [X, receiverGroup, senderGroup] = ...
        buildActionFeatures(graphBlocks(blockIdx), ...
            behaviorBlocks(blockIdx), variant);
    selectedMask = ...
        graphBlocks(blockIdx).selectedEdgeWeightTarget(:);
    if numel(selectedMask) ~= size(X, 1)
        error('Structured-choice selected mask is misaligned.');
    end
    blockCursor = blockCursor + 1;
    actionX = appendRows(actionX, X);
    actionBlock = [actionBlock; ...
        blockCursor * ones(size(X, 1), 1)]; %#ok<AGROW>
    actionReceiverGroup = [actionReceiverGroup; ...
        receiverGroup]; %#ok<AGROW>
    actionSenderGroup = [actionSenderGroup; ...
        senderGroup]; %#ok<AGROW>
    selected = [selected; selectedMask]; %#ok<AGROW>
end
[featureMean, featureScale] = fitScaler(actionX);
Z = applyScaler(actionX, featureMean, featureScale);
differenceX = zeros(0, size(Z, 2));
for blockIdx = 1:blockCursor
    blockMask = actionBlock == blockIdx;
    groups = unique(actionReceiverGroup(blockMask), 'stable');
    groupCount = numel(groups);
    for group = reshape(groups, 1, [])
        positive = find(blockMask & selected & ...
            actionReceiverGroup == group);
        if numel(positive) ~= 1
            error(['Structured teacher must choose exactly one ', ...
                'bridge-weight action per receiving formation.']);
        end
        previousGroup = mod(group - 2, groupCount) + 1;
        nextGroup = mod(group, groupCount) + 1;
        eligible = find(blockMask & ...
            actionReceiverGroup == group & ...
            (actionSenderGroup == previousGroup | ...
             actionSenderGroup == nextGroup));
        negatives = setdiff(eligible, positive, 'stable');
        if isempty(negatives)
            error('Structured-choice set has no negative actions.');
        end
        differenceX = [differenceX; ... %#ok<AGROW>
            bsxfun(@minus, Z(positive, :), ...
                Z(negatives, :))];
    end
end
training = struct('differenceX', differenceX, ...
    'featureMean', featureMean, ...
    'featureScale', featureScale, ...
    'featureVariant', variant);
end

function models = fitChoiceRidgeFamily(training, lambdas)
D = training.differenceX;
target = ones(size(D, 1), 1);
gram = D' * D;
right = D' * target;
models = repmat(struct( ...
    'featureMean', [], 'featureScale', [], ...
    'featureVariant', '', 'lambda', NaN, ...
    'coefficients', []), 1, numel(lambdas));
for lambdaIdx = 1:numel(lambdas)
    lambda = lambdas(lambdaIdx);
    coefficients = (gram + ...
        lambda * eye(size(gram))) \ right;
    if any(~isfinite(coefficients))
        error('Structured-choice ridge fit is non-finite.');
    end
    models(lambdaIdx) = struct( ...
        'featureMean', training.featureMean, ...
        'featureScale', training.featureScale, ...
        'featureVariant', training.featureVariant, ...
        'lambda', lambda, ...
        'coefficients', coefficients);
end
end

function rows = evaluateChoiceModel( ...
        model, graphBlocks, behaviorBlocks, protocol)
rows = repmat(emptyRow(), 1, numel(graphBlocks));
for blockIdx = 1:numel(graphBlocks)
    block = graphBlocks(blockIdx);
    behaviorBlock = behaviorBlocks(blockIdx);
    [X, receiverGroup, senderGroup] = ...
        buildActionFeatures( ...
            block, behaviorBlock, ...
            model.featureVariant);
    scoresFlat = applyScaler(X, ...
        model.featureMean, ...
        model.featureScale) * ...
            model.coefficients;
    scoreMatrix = reshape(scoresFlat, ...
        size(block.edgeFeatures, 1), ...
        size(block.edgeFeatures, 2));
    scores = struct( ...
        'nodeRisk', zeros(1, ...
            size(block.nodeFeatures, 1)), ...
        'edgeTaskAdvantage', scoreMatrix, ...
        'edgeProtectionAdvantage', ...
            ones(size(scoreMatrix)), ...
        'featuresUseTruth', false, ...
        'futureOutcomeUsed', false);
    projection = projectCvarResidualGraphPolicyScores( ...
        scores, block, behaviorBlock, 0, protocol);
    oracleScores = struct( ...
        'nodeRisk', reshape( ...
            block.nodeRiskTarget, 1, []), ...
        'edgeTaskAdvantage', ...
            block.edgeTaskAdvantageTarget, ...
        'edgeProtectionAdvantage', ...
            2 * double(block.edgeReferenceSafeTarget) - 1, ...
        'featuresUseTruth', true, ...
        'futureOutcomeUsed', false);
    oracleProjection = ...
        projectCvarResidualGraphPolicyScores( ...
            oracleScores, block, behaviorBlock, ...
            0, protocol);
    selectedMask = projection.selectedEdgeWeightMask;
    teacherMask = block.selectedEdgeWeightTarget;
    selectedTrueTaskAdvantage = sum( ...
        block.edgeTaskAdvantageTarget(selectedMask));
    oracleTrueTaskAdvantage = sum( ...
        block.edgeTaskAdvantageTarget( ...
            oracleProjection.selectedEdgeWeightMask));
    selectedTailSafe = evaluateTailSafety( ...
        selectedMask, block);
    row = emptyRow();
    row.seed = block.seed;
    row.currentTime = block.currentTime;
    row.featureVariant = model.featureVariant;
    row.lambda = model.lambda;
    row.choiceTop1Accuracy = ...
        evaluateChoiceTop1(scoresFlat, ...
            block, receiverGroup, senderGroup);
    row.selectedActionRecall = ...
        nnz(selectedMask & teacherMask) / ...
            max(nnz(teacherMask), 1);
    row.orientationExact = ...
        compareFormationPairs(selectedMask, ...
            teacherMask, receiverGroup, senderGroup);
    row.selectedTrueTaskAdvantage = ...
        selectedTrueTaskAdvantage;
    row.oracleTrueTaskAdvantage = ...
        oracleTrueTaskAdvantage;
    row.oracleActionGap = ...
        oracleTrueTaskAdvantage - ...
            selectedTrueTaskAdvantage;
    row.nonnegativeTask = ...
        selectedTrueTaskAdvantage >= -1e-12;
    row.selectedTailSafe = selectedTailSafe;
    row.fallbackUsed = projection.fallbackUsed;
    rows(blockIdx) = row;
end
end

function [X, receiverGroup, senderGroup] = ...
        buildActionFeatures(block, behaviorBlock, variant)
candidateCount = size(block.edgeFeatures, 1);
weightCount = size(block.edgeFeatures, 2);
edgeFeatureCount = size(block.edgeFeatures, 3);
edgeX = reshape(block.edgeFeatures, ...
    candidateCount * weightCount, edgeFeatureCount);
receiverRows = repmat(reshape( ...
    block.receiverIndices, [], 1), weightCount, 1);
senderRows = repmat(reshape( ...
    block.senderIndices, [], 1), weightCount, 1);
groupIds = reshape(behaviorBlock.groupIds, 1, []);
receiverGroup = reshape(groupIds(receiverRows), [], 1);
senderGroup = reshape(groupIds(senderRows), [], 1);
switch variant
    case 'edge-only'
        X = edgeX;
    case 'edge-update-relational'
        updateX = block.nodeFeatures(:, ...
            (end - 15):end);
        receiverUpdate = updateX(receiverRows, :);
        senderUpdate = updateX(senderRows, :);
        X = [edgeX, receiverUpdate, senderUpdate, ...
            receiverUpdate - senderUpdate, ...
            receiverUpdate .* senderUpdate];
    otherwise
        error('Unknown structured-choice feature variant.');
end
end

function accuracy = evaluateChoiceTop1( ...
        scores, block, receiverGroup, senderGroup)
selected = block.selectedEdgeWeightTarget(:);
groups = unique(receiverGroup, 'stable');
correct = false(1, numel(groups));
groupCount = numel(groups);
for groupIdx = 1:numel(groups)
    group = groups(groupIdx);
    positive = find(selected & ...
        receiverGroup == group);
    previousGroup = mod(group - 2, groupCount) + 1;
    nextGroup = mod(group, groupCount) + 1;
    eligible = find(receiverGroup == group & ...
        (senderGroup == previousGroup | ...
         senderGroup == nextGroup));
    [~, localIdx] = max(scores(eligible));
    correct(groupIdx) = numel(positive) == 1 && ...
        eligible(localIdx) == positive;
end
accuracy = mean(correct);
end

function exact = compareFormationPairs( ...
        selectedMask, teacherMask, ...
        receiverGroup, senderGroup)
selectedFlat = selectedMask(:);
teacherFlat = teacherMask(:);
selectedPairs = unique([ ...
    receiverGroup(selectedFlat), ...
    senderGroup(selectedFlat)], 'rows');
teacherPairs = unique([ ...
    receiverGroup(teacherFlat), ...
    senderGroup(teacherFlat)], 'rows');
exact = isequal(sortrows(selectedPairs), ...
    sortrows(teacherPairs));
end

function safe = evaluateTailSafety(selectedMask, block)
trueTail = logical(reshape( ...
    block.nodeCvarMaskTarget, 1, []));
selectedRows = find(any(selectedMask, 2));
selectedTailRows = selectedRows( ...
    trueTail(block.receiverIndices(selectedRows)));
safe = true;
for rowIdx = reshape(selectedTailRows, 1, [])
    weightIdx = find(selectedMask(rowIdx, :), 1);
    safe = safe && ...
        block.edgeReferenceSafeTarget(rowIdx, weightIdx);
end
end

function metrics = summarizeRows(rows)
seeds = unique([rows.seed], 'stable');
seedMetrics = repmat(struct( ...
    'seed', 0, 'meanTaskAdvantage', NaN, ...
    'nonnegativeTaskFraction', NaN, ...
    'selectedTailSafeFraction', NaN), ...
    1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seedRows = rows([rows.seed] == seeds(seedIdx));
    seedMetrics(seedIdx) = struct( ...
        'seed', seeds(seedIdx), ...
        'meanTaskAdvantage', mean( ...
            [seedRows.selectedTrueTaskAdvantage]), ...
        'nonnegativeTaskFraction', mean( ...
            [seedRows.nonnegativeTask]), ...
        'selectedTailSafeFraction', mean( ...
            [seedRows.selectedTailSafe]));
end
metrics = struct();
metrics.stateCount = numel(rows);
metrics.choiceTop1Accuracy = mean( ...
    [rows.choiceTop1Accuracy]);
metrics.selectedActionRecall = mean( ...
    [rows.selectedActionRecall]);
metrics.orientationAccuracy = mean( ...
    [rows.orientationExact]);
metrics.meanTaskAdvantage = mean( ...
    [rows.selectedTrueTaskAdvantage]);
metrics.minimumSeedMeanTaskAdvantage = min( ...
    [seedMetrics.meanTaskAdvantage]);
metrics.medianOracleActionGap = median( ...
    [rows.oracleActionGap]);
metrics.p90OracleActionGap = empiricalQuantile( ...
    [rows.oracleActionGap], 0.90);
metrics.nonnegativeTaskFraction = mean( ...
    [rows.nonnegativeTask]);
metrics.selectedTailSafeFraction = mean( ...
    [rows.selectedTailSafe]);
metrics.fallbackCount = nnz( ...
    [rows.fallbackUsed]);
metrics.seedMetrics = seedMetrics;
end

function selected = selectBestCandidate(candidates)
minimumAdvantage = arrayfun(@(candidate) ...
    candidate.metrics.minimumSeedMeanTaskAdvantage, ...
    candidates);
meanAdvantage = arrayfun(@(candidate) ...
    candidate.metrics.meanTaskAdvantage, candidates);
safety = arrayfun(@(candidate) ...
    candidate.metrics.selectedTailSafeFraction, ...
    candidates);
gap = arrayfun(@(candidate) ...
    candidate.metrics.medianOracleActionGap, ...
    candidates);
[~, order] = sortrows([ ...
    -minimumAdvantage(:), -meanAdvantage(:), ...
    -safety(:), gap(:)], [1, 2, 3, 4]);
best = candidates(order(1));
selected = struct( ...
    'candidateIndex', order(1), ...
    'featureVariant', best.featureVariant, ...
    'lambda', best.lambda, ...
    'metrics', best.metrics, ...
    'selectionUse', ...
        'training-only-architecture-diagnosis');
end

function [meanValue, scaleValue] = fitScaler(X)
meanValue = mean(X, 1);
scaleValue = std(X, 0, 1);
scaleValue(~isfinite(scaleValue) | ...
    scaleValue <= eps) = 1;
end

function Z = applyScaler(X, meanValue, scaleValue)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, meanValue), scaleValue);
end

function output = appendRows(output, values)
if isempty(output)
    output = zeros(0, size(values, 2));
end
output = [output; values];
end

function value = empiricalQuantile(values, probability)
values = sort(reshape(values, 1, []));
position = 1 + (numel(values) - 1) * probability;
lowerIdx = floor(position);
upperIdx = ceil(position);
if lowerIdx == upperIdx
    value = values(lowerIdx);
else
    fraction = position - lowerIdx;
    value = (1 - fraction) * values(lowerIdx) + ...
        fraction * values(upperIdx);
end
end

function writeReport(path, analysis)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open structured-choice report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 structured formation-bridge choice analysis\n\n');
fprintf(fid, '- Generated: %s\n', analysis.generatedAt);
fprintf(fid, '- Commit: `%s`\n', analysis.generationGitCommit);
fprintf(fid, '- Dataset-set SHA-256: `%s`\n', ...
    analysis.datasetSetSha256);
fprintf(fid, '- Training seeds: `%s`\n', ...
    mat2str(analysis.trainingSeeds));
fprintf(fid, '- Development seeds opened: `%d`\n', ...
    analysis.developmentSeedsOpened);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    analysis.evidenceBoundary);
fprintf(fid, ['| Features | Lambda | Choice top-1 | ', ...
    'Action recall | Orientation | Mean adv. | Min seed adv. | ', ...
    'Median gap | P90 gap | Nonnegative | Tail safe | Fallback |\n']);
fprintf(fid, ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for candidate = analysis.candidates
    metric = candidate.metrics;
    fprintf(fid, ...
        ['| %s | %.3g | %.3f | %.3f | %.3f | %.4f | ', ...
         '%.4f | %.4f | %.4f | %.3f | %.3f | %d |\n'], ...
        candidate.featureVariant, candidate.lambda, ...
        metric.choiceTop1Accuracy, ...
        metric.selectedActionRecall, ...
        metric.orientationAccuracy, ...
        metric.meanTaskAdvantage, ...
        metric.minimumSeedMeanTaskAdvantage, ...
        metric.medianOracleActionGap, ...
        metric.p90OracleActionGap, ...
        metric.nonnegativeTaskFraction, ...
        metric.selectedTailSafeFraction, ...
        metric.fallbackCount);
end
best = analysis.bestCandidate;
fprintf(fid, ...
    ['\nBest training-only diagnostic: `%s`, lambda `%.3g`, ', ...
     'mean advantage `%.4f`, minimum seed advantage `%.4f`, ', ...
     'tail-safe fraction `%.3f`.\n'], ...
    best.featureVariant, best.lambda, ...
    best.metrics.meanTaskAdvantage, ...
    best.metrics.minimumSeedMeanTaskAdvantage, ...
    best.metrics.selectedTailSafeFraction);
end

function row = emptyRow()
row = struct('seed', 0, 'currentTime', 0, ...
    'featureVariant', '', 'lambda', NaN, ...
    'choiceTop1Accuracy', NaN, ...
    'selectedActionRecall', NaN, ...
    'orientationExact', false, ...
    'selectedTrueTaskAdvantage', NaN, ...
    'oracleTrueTaskAdvantage', NaN, ...
    'oracleActionGap', NaN, ...
    'nonnegativeTask', false, ...
    'selectedTailSafe', false, ...
    'fallbackUsed', false);
end

function candidate = emptyCandidate()
candidate = struct('featureVariant', '', ...
    'lambda', NaN, ...
    'rows', repmat(emptyRow(), 1, 0), ...
    'metrics', struct());
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
