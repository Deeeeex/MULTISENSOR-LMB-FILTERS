function [reportPath, result] = ...
    runReceiverDirectTaskRiskV74Anchors(options)
% RUNRECEIVERDIRECTTASKRISKV74ANCHORS Source-only direct-risk diagnosis.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReceiverDirectTaskRiskV74Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ReceiverDirectTaskRiskV74:DirtySource', ...
        'The V74 direct-risk diagnosis requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    records(caseIdx) = evaluateCase( ...
        state, analysis, protocol);
    fprintf([ ...
        'V74 %s t=%d modes=%d direct-pass=%d sets=%s\n'], ...
        caseInfo.presetName, caseInfo.currentTime, ...
        numel(records(caseIdx).modes), ...
        records(caseIdx).directGateCandidateCount, ...
        formatFormationSetCollection( ...
            records(caseIdx).directGateFormationSets));
end

result = struct();
result.contractVersion = ...
    'receiver-direct-task-risk-v74-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.anyDirectGateCandidate = ...
    any([records.directGateCandidateCount] > 0);
result.temporalPropagationModelUsed = false;
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RECEIVER_DIRECT_TASK_RISK_V74_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'RECEIVER_DIRECT_TASK_RISK_V74_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V74 receiver direct task risk: %s\n', reportPath);
end

function record = evaluateCase(state, analysis, protocol)
projection = analysis.projection;
modes = materializeModes(projection, analysis.transport);
context = state.context;
context.triggerConfig = protocol.fusionConfig;
disagreementOptions = struct( ...
    'aggregationMode', protocol.disagreementAggregationMode, ...
    'tailFraction', protocol.disagreementTailFraction, ...
    'maximumIncomingCount', protocol.maximumIncomingCount);
[referenceRisk, referenceDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, modes(1).adjacency, modes(1).fusionWeights, ...
        disagreementOptions);
receiverDistributionsByMode = cell(1, numel(modes));
receiverDistributionsByMode{1} = referenceDetails.receiverDistributions;
meanRisk = zeros(1, numel(modes));
tailRisk = zeros(1, numel(modes));
meanRisk(1) = referenceRisk;
tailRisk(1) = aggregatePairTail( ...
    referenceDetails.expectedPairRisk, ...
    protocol.disagreementTailFraction);
for modeIdx = 2:numel(modes)
    candidateOptions = disagreementOptions;
    candidateOptions.referenceNetworkDetails = referenceDetails;
    candidateOptions.referenceAdjacency = modes(1).adjacency;
    candidateOptions.referenceFusionWeights = modes(1).fusionWeights;
    [meanRisk(modeIdx), candidateDetails] = ...
        computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
            context, modes(modeIdx).adjacency, ...
            modes(modeIdx).fusionWeights, candidateOptions);
    tailRisk(modeIdx) = aggregatePairTail( ...
        candidateDetails.expectedPairRisk, ...
        protocol.disagreementTailFraction);
    receiverDistributionsByMode{modeIdx} = ...
        candidateDetails.receiverDistributions;
end

positionCutoff = state.context.model.ospaParameters.eC;
bayesOptions = struct( ...
    'referenceModeIndex', 1, ...
    'positionCutoff', positionCutoff, ...
    'labelAggregationMode', ...
        protocol.posteriorBayesLabelAggregationMode, ...
    'receiverTailFraction', protocol.receiverTailFraction, ...
    'receiverTailWeight', protocol.receiverTailWeight);
[bayesObjectives, bayesDetails] = ...
    computeFormationModePosteriorBayesRiskObjectives( ...
        receiverDistributionsByMode, state.groupIds, bayesOptions);
groups = unique(state.groupIds, 'stable');
modeRecords = repmat(emptyModeRecord(), 1, numel(modes));
for modeIdx = 1:numel(modes)
    mode = modes(modeIdx);
    affectedIndices = find(ismember(groups, mode.formationIds));
    affectedObjectives = bayesObjectives(affectedIndices, modeIdx);
    if isempty(affectedObjectives)
        minimumAffectedObjective = 0;
    else
        minimumAffectedObjective = min(affectedObjectives);
    end
    meanGain = relativeGain(meanRisk(1), meanRisk(modeIdx));
    tailGain = relativeGain(tailRisk(1), tailRisk(modeIdx));
    directGate = modeIdx == 1 || ( ...
        (~protocol. ...
            requireNonnegativeAffectedFormationBayesObjective || ...
         minimumAffectedObjective >= -1e-12) && ...
        (~protocol.requireNonincreasingMeanNetworkDisagreement || ...
         meanGain >= -1e-12) && ...
        (~protocol.requireNonincreasingTailNetworkDisagreement || ...
         tailGain >= -1e-12));
    modeRecords(modeIdx) = makeModeRecord( ...
        mode, bayesObjectives(:, modeIdx), affectedObjectives, ...
        minimumAffectedObjective, meanRisk(modeIdx), ...
        tailRisk(modeIdx), meanGain, tailGain, directGate);
end

candidateMask = 2:numel(modeRecords);
directMask = false(1, numel(modeRecords));
directMask(candidateMask) = [modeRecords(candidateMask).directGatePassed];
record = emptyCaseRecord();
record.presetName = state.presetName;
record.seed = state.seed;
record.currentTime = state.currentTime;
record.groups = groups;
record.positionCutoff = positionCutoff;
record.referenceMeanDisagreement = meanRisk(1);
record.referenceTailDisagreement = tailRisk(1);
record.referenceFormationBayesRisk = ...
    bayesDetails.formationRiskByMode(:, 1)';
record.modes = modeRecords;
record.directGateCandidateCount = nnz(directMask);
record.directGateFormationSets = ...
    {modeRecords(directMask).formationIds};
record.allCandidateFormationSets = ...
    {modeRecords(candidateMask).formationIds};
record.receiverFusionMode = analysis.receiverFusionMode;
record.sourceProjectionFormationIds = ...
    projection.selectedFormationIds;
record.sourceProjectionSlotIndices = ...
    projection.selectedSlotIndices;
record.truthUsed = false;
record.futureMeasurementsUsed = false;
record.futureOutcomesUsed = false;
end

function modes = materializeModes(projection, transport)
feasible = find([projection.candidates.feasible]);
modes = repmat(emptyMode(), 1, 1 + numel(feasible));
modes(1) = struct( ...
    'name', 'reference', ...
    'formationIds', zeros(1, 0), ...
    'slotIndices', zeros(1, 0), ...
    'existenceUtilityMass', 0, ...
    'networkExistenceNetFraction', 0, ...
    'adjacency', projection.referenceAdjacency, ...
    'fusionWeights', projection.referenceFusionWeights);
for outputIdx = 1:numel(feasible)
    candidate = projection.candidates(feasible(outputIdx));
    [adjacency, weights] = applySlots( ...
        projection.referenceAdjacency, ...
        projection.referenceFusionWeights, ...
        transport.slotRecords, candidate.slotIndices);
    modes(outputIdx + 1) = struct( ...
        'name', actionName(candidate.formationIds), ...
        'formationIds', candidate.formationIds, ...
        'slotIndices', candidate.slotIndices, ...
        'existenceUtilityMass', candidate.utilityMass, ...
        'networkExistenceNetFraction', ...
            candidate.networkAverageNetFraction, ...
        'adjacency', adjacency, ...
        'fusionWeights', weights);
end
selectedMode = find(cellfun(@(ids) isequal(ids, ...
    projection.selectedFormationIds), {modes.formationIds}), 1);
if projection.routeConstructed && ...
        (isempty(selectedMode) || ...
         ~isequal(modes(selectedMode).adjacency, ...
            projection.selectedAdjacency) || ...
         max(abs(modes(selectedMode).fusionWeights(:) - ...
            projection.selectedFusionWeights(:))) > 1e-12)
    error('ReceiverDirectTaskRiskV74:MaterializationDrift', ...
        'A materialized candidate differs from the V73 projection.');
end
end

function [adjacency, weights] = applySlots( ...
        referenceAdjacency, referenceWeights, slots, slotIndices)
adjacency = referenceAdjacency;
weights = referenceWeights;
for slotIdx = reshape(slotIndices, 1, [])
    slot = slots(slotIdx);
    receiver = slot.receiverIdx;
    incumbent = slot.incumbentSenderIdx;
    candidate = slot.bestCandidateSenderIdx;
    adjacency(receiver, incumbent) = false;
    adjacency(receiver, candidate) = true;
    weights(receiver, incumbent) = 0;
    weights(receiver, candidate) = slot.sourceWeight;
end
end

function record = makeModeRecord( ...
        mode, formationObjectives, affectedObjectives, ...
        minimumAffectedObjective, meanRisk, tailRisk, ...
        meanGain, tailGain, directGate)
record = emptyModeRecord();
record.name = mode.name;
record.formationIds = mode.formationIds;
record.slotIndices = mode.slotIndices;
record.existenceUtilityMass = mode.existenceUtilityMass;
record.networkExistenceNetFraction = ...
    mode.networkExistenceNetFraction;
record.formationBayesObjective = formationObjectives';
record.affectedFormationBayesObjective = ...
    reshape(affectedObjectives, 1, []);
record.minimumAffectedFormationBayesObjective = ...
    minimumAffectedObjective;
record.meanNetworkDisagreement = meanRisk;
record.tailNetworkDisagreement = tailRisk;
record.meanNetworkDisagreementGainFraction = meanGain;
record.tailNetworkDisagreementGainFraction = tailGain;
record.directGatePassed = directGate;
end

function risk = aggregatePairTail(pairRisk, tailFraction)
values = pairRisk(triu(true(size(pairRisk)), 1));
if isempty(values)
    risk = 0;
    return;
end
values = sort(values, 'descend');
tailCount = max(1, ceil(tailFraction * numel(values)));
risk = mean(values(1:tailCount));
end

function gain = relativeGain(reference, candidate)
gain = (reference - candidate) / max(abs(reference), eps);
end

function name = actionName(formationIds)
suffix = sprintf('f%d-', formationIds);
name = ['receiver-domain-transport-', suffix(1:end-1)];
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ReceiverDirectTaskRiskV74:WriteFailed', ...
        'Could not create the V74 direct-risk report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V74 receiver direct task-risk anchors\n\n');
for record = result.records
    fprintf(fid, '## %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    fprintf(fid, ['| Route formations | Existence net / network | ', ...
        'Affected Bayes objective | Minimum Bayes objective | ', ...
        'Mean disagreement gain | Tail disagreement gain | Direct gate |\n']);
    fprintf(fid, '|:--|--:|:--|--:|--:|--:|:--:|\n');
    for mode = record.modes
        fprintf(fid, ['| `%s` | %+.3f%% | `%s` | %+.6f | ', ...
            '%+.3f%% | %+.3f%% | %d |\n'], ...
            mat2str(mode.formationIds), ...
            100 * mode.networkExistenceNetFraction, ...
            mat2str(mode.affectedFormationBayesObjective, 6), ...
            mode.minimumAffectedFormationBayesObjective, ...
            100 * mode.meanNetworkDisagreementGainFraction, ...
            100 * mode.tailNetworkDisagreementGainFraction, ...
            mode.directGatePassed);
    end
    fprintf(fid, '\n- Direct-gate candidate sets: `%s`\n', ...
        formatFormationSetCollection(record.directGateFormationSets));
    fprintf(fid, '- Position cutoff: `%.3f`\n\n', ...
        record.positionCutoff);
end
fprintf(fid, '## Gate summary\n\n');
fprintf(fid, '- Any non-reference direct-gate candidate: `%d`\n', ...
    result.anyDirectGateCandidate);
fprintf(fid, '- Receiver mode: `mixture-aware-heavy`\n');
fprintf(fid, '- Temporal propagation model used: `0`\n');
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route executed: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function text = formatFormationSetCollection(sets)
if isempty(sets)
    text = 'none';
    return;
end
parts = cell(1, numel(sets));
for setIdx = 1:numel(sets)
    parts{setIdx} = mat2str(sets{setIdx});
end
text = strjoin(parts, '; ');
end

