function writeAuditReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open same-hardware scale audit report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Same-hardware formation-FoV scale calibration\n\n');
fprintf(fid, '- Generated: `%s`\n', summary.generatedAt);
fprintf(fid, '- Commit: `%s`\n', summary.generationGitCommit);
fprintf(fid, '- Reference: `%s`\n', summary.referencePreset);
fprintf(fid, '- Hardware profile: `%s`\n', summary.hardwareProfile.id);
fprintf(fid, '- Total FoV / range: `%.0f deg / %.0f m`\n', ...
    summary.hardwareProfile.fovTotalAngleDeg, ...
    summary.hardwareProfile.fovRange);
fprintf(fid, '- Clutter space: `%s`\n', ...
    summary.hardwareProfile.clutterSpatialProfile);
fprintf(fid, '- Hardware contract passed: `%d`\n', ...
    summary.hardwareContractPassed);
fprintf(fid, '- Seeds: `%s`\n', mat2str(summary.seeds));
fprintf(fid, '- Mean / paired error caps: `%.1f%% / %.1f%%`\n', ...
    summary.maximumMeanRelativeErrorPercent, ...
    summary.maximumPairedRelativeErrorPercent);
fprintf(fid, '- Calibration gate passed: `%d`\n\n', ...
    summary.calibrationGatePassed);
fprintf(fid, ['| Preset | Sensors | Targets | Seed | Visible support | ', ...
    'Expected detections (diagnostic) | Sensor load | Blackout | ', ...
    'Focus blackout | Max target blackout | Longest blackout (steps) | ', ...
    'Single | Multi |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|\n']);
for row = reshape(summary.rows, 1, [])
    fprintf(fid, ['| %s | %d | %d | %d | %.3f%% | %.3f%% | ', ...
        '%.3f%% | %.3f | %.3f | %.3f | %d | %.3f | %.3f |\n'], ...
        row.presetName, row.sensorCount, row.targetCount, row.seed, ...
        row.focusMeanVisibleSensorCountRelativeErrorPercent, ...
        row.focusMeanExpectedTargetDetectionCountRelativeErrorPercent, ...
        row.focusMeanVisibleTargetsPerSensorTimeRelativeErrorPercent, ...
        row.blackoutFraction, row.focusBlackoutFraction, ...
        row.maximumPerTargetBlackoutFraction, ...
        row.maximumConsecutiveBlackoutSteps, ...
        row.singleFormationFraction, ...
        row.multiFormationFraction);
end
fprintf(fid, ['\nOnly sensor load enters the geometry-matching gate. ', ...
    'Visible support is a derived check; expected detection differences ', ...
    'are diagnostic and excluded from the gate.\n']);
fprintf(fid, '\n## Aggregate geometry gate\n\n');
fprintf(fid, '| Preset | Max mean error | Max paired error | Gate |\n');
fprintf(fid, '|:--|--:|--:|:--:|\n');
for aggregate = summary.aggregates
    fprintf(fid, '| %s | %.3f%% | %.3f%% | %d |\n', ...
        aggregate.presetName, ...
        aggregate.maximumAbsoluteMeanRelativeErrorPercent, ...
        aggregate.maximumAbsolutePairedRelativeErrorPercent, ...
        aggregate.gatePassed);
end
fprintf(fid, '\n## Interpretation boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
