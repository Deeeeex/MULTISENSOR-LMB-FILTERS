function [reportPath, summary] = ...
    auditFormationFovScaleScenarios(seedList, options)
% AUDITFORMATIONFOVSCALESCENARIOS Freeze same-hardware scale controls.
%
% All sensor hardware is held exactly fixed. The audit pairs each larger
% scene with M24 under the same seed and gates only geometry-controlled
% per-sensor target load. Visible support is algebraically coupled to this
% load when the target-to-sensor ratio is fixed, so it is reported only as
% a derived check. Expected detection count is diagnostic scale pressure.

if nargin < 1 || isempty(seedList)
    seedList = [41, 43, 47, 53, 59];
end
if nargin < 2 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
referencePreset = 'm24-formation-fov';
matchedPresets = {'x36-formation-fov', 'x48-formation-fov'};
allPresets = [{referencePreset}, matchedPresets];
maximumMeanRelativeErrorPercent = getField( ...
    options, 'maximumMeanRelativeErrorPercent', 1);
maximumPairedRelativeErrorPercent = getField( ...
    options, 'maximumPairedRelativeErrorPercent', 3);
requireCleanWorktree = getField(options, 'requireCleanWorktree', true);

gitState = resolveResearchGitState();
if requireCleanWorktree && (gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles))
    error(['Same-hardware scale audit requires a clean tracked ', ...
        'worktree with no untracked MATLAB source files.']);
end

[hardwareContractPassed, hardwareProfile] = ...
    verifyFrozenHardwareContract(allPresets);

[~, rawAudit] = runDynamicTopologyScenarioDifficultyAudit( ...
    allPresets, seedList, struct('writeReport', false));
reportedFields = { ...
    'focusMeanVisibleSensorCount', ...
    'focusMeanExpectedTargetDetectionCount', ...
    'focusMeanVisibleTargetsPerSensorTime'};
matchedFields = { ...
    'focusMeanVisibleTargetsPerSensorTime'};
derivedFields = {'focusMeanVisibleSensorCount'};
rows = repmat(emptyRow(), numel(matchedPresets), numel(seedList));
aggregates = repmat(emptyAggregate(), 1, numel(matchedPresets));
for presetIdx = 1:numel(matchedPresets)
    preset = matchedPresets{presetIdx};
    for seedIdx = 1:numel(seedList)
        seed = seedList(seedIdx);
        reference = findRecord(rawAudit.records, referencePreset, seed);
        candidate = findRecord(rawAudit.records, preset, seed);
        rows(presetIdx, seedIdx) = buildRow( ...
            reference, candidate, reportedFields);
    end
    aggregates(presetIdx) = buildAggregate( ...
        preset, rows(presetIdx, :), reportedFields, matchedFields, ...
        maximumMeanRelativeErrorPercent, ...
        maximumPairedRelativeErrorPercent);
end

summary = struct();
summary.contractVersion = ...
    'same-hardware-formation-fov-scale-scenes-v3';
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.referencePreset = referencePreset;
summary.matchedPresets = matchedPresets;
summary.seeds = seedList;
summary.hardwareProfile = hardwareProfile;
summary.hardwareContractPassed = hardwareContractPassed;
summary.matchedFields = matchedFields;
summary.derivedFields = derivedFields;
summary.reportedFields = reportedFields;
summary.maximumMeanRelativeErrorPercent = ...
    maximumMeanRelativeErrorPercent;
summary.maximumPairedRelativeErrorPercent = ...
    maximumPairedRelativeErrorPercent;
summary.rawAudit = rawAudit;
summary.rows = rows;
summary.aggregates = aggregates;
summary.calibrationGatePassed = ...
    hardwareContractPassed && rawAudit.allValid && ...
    all([aggregates.gatePassed]);
summary.evidenceBoundary = sprintf([ ...
    'The opened seeds calibrate scene geometry only. Passing proves ', ...
    'that the sole cross-scale matching statistic, local per-sensor ', ...
    'sensing load, is matched while every sensor-hardware and ', ...
    'clutter-space ', ...
    'parameter remains identical under a fixed %.0f-degree total FoV, ', ...
    'a %.0f m hard sensing range, and the `%s` boresight ', ...
    'contract. Visible support is a ', ...
    'derived sanity check because the target-to-sensor ratio is fixed. ', ...
    'Focus, per-target, and consecutive-blackout gates prevent the ', ...
    'aggregate load match from hiding prolonged unobservable targets. ', ...
    'Expected detection count is diagnostic scale pressure, not an ', ...
    'equivalence gate. This audit ', ...
    'does not establish tracking gain, policy generalization, or an ', ...
    'X36/X48 validation claim.'], ...
    hardwareProfile.fovTotalAngleDeg, hardwareProfile.fovRange, ...
    hardwareProfile.sensorFovHeadingMode);

outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_fov_scale_scenarios', 'calibration'));
writeReport = getField(options, 'writeReport', true);
reportPath = '';
if writeReport
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    reportPath = fullfile(outputDirectory, ...
        'SAME_HARDWARE_SCALE_SCENARIO_CALIBRATION.md');
    writeAuditReport(reportPath, summary);
    matPath = strrep(reportPath, '.md', '.mat');
    save('-mat7-binary', matPath, 'summary');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    fprintf('Same-hardware scale audit: %s\n', reportPath);
end
end

function row = buildRow(reference, candidate, fields)
row = emptyRow();
row.presetName = candidate.presetName;
row.seed = candidate.seed;
row.sensorCount = candidate.sensorCount;
row.targetCount = candidate.targetCount;
row.isValid = candidate.isValid;
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    referenceValue = reference.(fieldName);
    candidateValue = candidate.(fieldName);
    row.([fieldName, 'Reference']) = referenceValue;
    row.([fieldName, 'Candidate']) = candidateValue;
    row.([fieldName, 'RelativeErrorPercent']) = ...
        100 * (candidateValue / max(referenceValue, eps) - 1);
end
row.blackoutFraction = candidate.blackoutFraction;
row.focusBlackoutFraction = candidate.focusBlackoutFraction;
row.maximumPerTargetBlackoutFraction = ...
    candidate.maximumPerTargetBlackoutFraction;
row.maximumConsecutiveBlackoutSteps = ...
    candidate.maximumConsecutiveBlackoutSteps;
row.singleFormationFraction = candidate.singleFormationFraction;
row.multiFormationFraction = candidate.multiFormationFraction;
row.focusHandovers = candidate.focusHandovers;
row.ownershipEntropy = candidate.ownershipEntropy;
end

function aggregate = buildAggregate( ...
        preset, rows, reportedFields, matchedFields, ...
        maximumMeanError, maximumPairedError)
aggregate = emptyAggregate();
aggregate.presetName = preset;
aggregate.seedCount = numel(rows);
aggregate.allValid = all([rows.isValid]);
for fieldIdx = 1:numel(reportedFields)
    fieldName = reportedFields{fieldIdx};
    referenceValues = [rows.([fieldName, 'Reference'])];
    candidateValues = [rows.([fieldName, 'Candidate'])];
    pairedErrors = [rows.([fieldName, 'RelativeErrorPercent'])];
    aggregate.([fieldName, 'ReferenceMean']) = mean(referenceValues);
    aggregate.([fieldName, 'CandidateMean']) = mean(candidateValues);
    meanError = 100 * ( ...
        mean(candidateValues) / max(mean(referenceValues), eps) - 1);
    maximumPairedError = max(abs(pairedErrors));
    aggregate.([fieldName, 'MeanRelativeErrorPercent']) = ...
        meanError;
    aggregate.([fieldName, 'MaximumPairedRelativeErrorPercent']) = ...
        maximumPairedError;
end
meanErrors = zeros(1, numel(matchedFields));
maximumPairedErrors = zeros(1, numel(matchedFields));
for fieldIdx = 1:numel(matchedFields)
    fieldName = matchedFields{fieldIdx};
    meanErrors(fieldIdx) = aggregate.( ...
        [fieldName, 'MeanRelativeErrorPercent']);
    maximumPairedErrors(fieldIdx) = aggregate.( ...
        [fieldName, 'MaximumPairedRelativeErrorPercent']);
end
aggregate.maximumAbsoluteMeanRelativeErrorPercent = ...
    max(abs(meanErrors));
aggregate.maximumAbsolutePairedRelativeErrorPercent = ...
    max(maximumPairedErrors);
aggregate.maximumBlackoutFraction = max([rows.blackoutFraction]);
aggregate.maximumFocusBlackoutFraction = ...
    max([rows.focusBlackoutFraction]);
aggregate.maximumPerTargetBlackoutFraction = ...
    max([rows.maximumPerTargetBlackoutFraction]);
aggregate.maximumConsecutiveBlackoutSteps = ...
    max([rows.maximumConsecutiveBlackoutSteps]);
aggregate.minimumSingleFormationFraction = ...
    min([rows.singleFormationFraction]);
aggregate.minimumMultiFormationFraction = ...
    min([rows.multiFormationFraction]);
aggregate.gatePassed = aggregate.allValid && ...
    aggregate.maximumAbsoluteMeanRelativeErrorPercent <= ...
        maximumMeanError + 1e-12 && ...
    aggregate.maximumAbsolutePairedRelativeErrorPercent <= ...
        maximumPairedError + 1e-12;
end

function [passed, profile] = verifyFrozenHardwareContract(presets)
reference = buildDynamicTopologyScenarioConfig(presets{1});
fields = { ...
    'fovHalfAngleDeg', ...
    'fovTotalAngleDeg', ...
    'fovRange', ...
    'sensorFovHeadingMode', ...
    'sensorFovPointingCenter', ...
    'detectionProbability', ...
    'measurementNoiseStd', ...
    'sensorQuality', ...
    'sensorHardwareProfile', ...
    'observationSpaceLimits', ...
    'clutterRate', ...
    'clutterSpatialProfile'};
passed = true;
for presetIdx = 2:numel(presets)
    candidate = buildDynamicTopologyScenarioConfig(presets{presetIdx});
    for fieldIdx = 1:numel(fields)
        fieldName = fields{fieldIdx};
        passed = passed && isfield(reference, fieldName) && ...
            isfield(candidate, fieldName) && ...
            isequaln(reference.(fieldName), candidate.(fieldName));
    end
end
passed = passed && reference.fovHalfAngleDeg == 60 && ...
    reference.fovTotalAngleDeg == 120 && ...
    reference.fovRange == 300 && ...
    strcmp(reference.sensorFovHeadingMode, ...
        'formation-shared-scene-center') && ...
    strcmp(reference.sensorHardwareProfile, ...
        'formation-shared-120deg-r300-q300-v1');
profile = struct( ...
    'id', reference.sensorHardwareProfile, ...
    'fovHalfAngleDeg', reference.fovHalfAngleDeg, ...
    'fovTotalAngleDeg', reference.fovTotalAngleDeg, ...
    'fovRange', reference.fovRange, ...
    'sensorFovHeadingMode', reference.sensorFovHeadingMode, ...
    'detectionProbability', reference.detectionProbability, ...
    'measurementNoiseStd', reference.measurementNoiseStd, ...
    'sensorQuality', reference.sensorQuality, ...
    'observationSpaceLimits', reference.observationSpaceLimits, ...
    'clutterRate', reference.clutterRate, ...
    'clutterSpatialProfile', reference.clutterSpatialProfile);
end

function record = findRecord(records, preset, seed)
mask = strcmp({records.presetName}, preset) & [records.seed] == seed;
selected = records(mask);
if numel(selected) ~= 1
    error('Expected one difficulty record for %s seed %d.', preset, seed);
end
record = selected;
end

