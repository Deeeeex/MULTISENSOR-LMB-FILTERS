function [reportPath, result] = runDirectGraphCreditRepairH3V216(options)
% RUNDIRECTGRAPHCREDITREPAIRH3V216 Paired causal two-stage action screen.
%
% Each nonreference arm withholds one receiver formation for the first page.
% After ordinary fusion on that page, the V188 ledger may spend only the
% resulting exact byte credit on one current-state supported complete-label
% KLA update.  Source/label selection and delivery are causal; truth scores
% the H=3 return only.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getDirectGraphCreditRepairControllerV216Protocol();
base = getDirectGraphPayloadRepairControllerV214Protocol();
presetName = char(getField(options, ...
    'presetName', 'm24-formation-fov'));
seed = getField(options, 'seed', 1301);
splitName = char(getField(options, 'splitName', 'training'));
windowIndex = getField(options, 'windowIndex', 1);
trajectoryRoot = char(getField(options, 'trajectoryRoot', fullfile( ...
    base.outputRoot, 'trajectory_collection', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
trajectoryPath = fullfile(trajectoryRoot, ...
    'DIRECT_GRAPH_TRAJECTORY_V214.mat');
if exist(trajectoryPath, 'file') ~= 2 || ...
        ~isscalar(windowIndex) || ~isfinite(windowIndex) || ...
        windowIndex ~= round(windowIndex) || windowIndex < 1
    error('DirectGraphCreditRepairV216:InvalidScreen', ...
        'A completed V214 trajectory and valid window are required.');
end
loaded = load(trajectoryPath, 'result');
trajectory = loaded.result;
if ~isfield(trajectory, 'selectedTimes') || ...
        windowIndex > numel(trajectory.selectedTimes) || ...
        ~strcmp(trajectory.presetName, presetName) || ...
        trajectory.seed ~= seed || ...
        ~strcmp(trajectory.splitName, splitName) || ...
        trajectory.posteriorCounterfactualEnumerationUsed
    error('DirectGraphCreditRepairV216:TrajectoryProvenance', ...
        'The V214 trajectory does not match the V216 H=3 screen.');
end
currentTime = trajectory.selectedTimes(windowIndex);
cachePath = trajectory.cachePaths{windowIndex};
cacheRoot = fileparts(cachePath);

referenceScreenPath = char(getField(options, ...
    'referenceScreenPath', resolveReferenceScreenPath( ...
        base, presetName, seed, splitName, currentTime)));
referenceScreen = loadReferenceScreen( ...
    referenceScreenPath, presetName, seed, currentTime, ...
    protocol.horizonSteps);
referenceOutcome = referenceScreen.outcomes( ...
    referenceScreen.referenceSubsetIndex);
referencePageBytes = referenceOutcome.attemptedBytesByTime(1);

outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'credit_repair_h3', splitName, ...
    sprintf('%s_seed%d_t%d', ...
        strrep(presetName, '-', '_'), seed, currentTime))));
screenRoot = fullfile(outputRoot, 'screen');
screenOptions = struct();
screenOptions.horizonSteps = protocol.horizonSteps;
screenOptions.interventionDurationSteps = 1;
screenOptions.filterSeedOffset = protocol.filterSeedOffset;
screenOptions.cacheRoot = cacheRoot;
screenOptions.interventionBankType = ...
    'direct-graph-payload-repair-v214';
screenOptions.trackingAlignedExecutionProfile = ...
    'v214-direct-graph-payload-repair';
screenOptions.receiverMode = protocol.receiverMode;
screenOptions.directGraphSplitName = splitName;
screenOptions.directGraphPayloadRepairBankOptions = struct( ...
    'actionMode', protocol.actionMode, ...
    'referenceAttemptedBytes', referencePageBytes, ...
    'repairSourceWeight', protocol.repairSourceWeight);
screenOptions.referenceOutcomeScreenPath = referenceScreenPath;
screenOptions.outputDirectory = screenRoot;
screenOptions.writeReport = true;
screenOptions.capturePosteriorSnapshotsEnabled = false;
screenOptions.captureFusedPosteriorSnapshotsEnabled = false;
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    presetName, seed, currentTime, screenOptions);

nonreferenceIndices = find([screen.records.actionIndex] ~= ...
    screen.bank.referenceActionIndex);
candidateRecords = screen.records(nonreferenceIndices);
candidateOutcomes = screen.outcomes(nonreferenceIndices);
repairAppliedCount = arrayfun(@(outcome) sum(outcome. ...
    budgetRecycledFormationRepairAppliedActionCountByTime), ...
    candidateOutcomes);
repairProposalCount = arrayfun(@(outcome) sum(outcome. ...
    budgetRecycledFormationRepairProposalCountByTime), ...
    candidateOutcomes);
repairAttemptedBytes = arrayfun(@(outcome) sum(outcome. ...
    budgetRecycledFormationRepairAttemptedBytesByTime), ...
    candidateOutcomes);
positiveMask = arrayfun(@multiObjectivePositive, candidateRecords);
tailMask = arrayfun(@(record) tailTolerant(record, base.risk), ...
    candidateRecords);
eligibleMask = repairAppliedCount > 0 & positiveMask & tailMask;
bestLocalIndex = selectBest(candidateRecords, eligibleMask);

result = struct();
result.contractVersion = ...
    'direct-graph-credit-repair-h3-v216-v1';
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.presetName = presetName;
result.seed = seed;
result.splitName = splitName;
result.windowIndex = windowIndex;
result.currentTime = currentTime;
result.windowTimes = currentTime + (0:(protocol.horizonSteps - 1));
result.trajectoryPath = trajectoryPath;
result.trajectoryGenerationGitCommit = ...
    trajectory.generationGitCommit;
result.cachePath = cachePath;
result.referenceScreenPath = referenceScreenPath;
result.referencePageBytes = referencePageBytes;
result.screenPath = screenReportPath;
result.records = screen.records;
result.repairAppliedCount = repairAppliedCount;
result.repairProposalCount = repairProposalCount;
result.repairAttemptedBytes = repairAttemptedBytes;
result.multiObjectivePositiveMask = positiveMask;
result.tailTolerantMask = tailMask;
result.eligibleMask = eligibleMask;
result.bestCandidateLocalIndex = bestLocalIndex;
result.anyRepairExecuted = any(repairAppliedCount > 0);
result.anyEligibleCandidate = any(eligibleMask);
result.actualDeliverySampled = protocol.actualDeliverySampled;
result.posteriorCounterfactualEnumerationUsedAtRuntime = false;
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.momentMatchedLightPosteriorUsed = false;
result.retainedLabelsPreserveCompleteMixture = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'DIRECT_GRAPH_CREDIT_REPAIR_H3_V216.mat');
reportPath = fullfile(outputRoot, ...
    'DIRECT_GRAPH_CREDIT_REPAIR_H3_V216.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result, candidateRecords);
fprintf('V216 direct-graph credit repair H=3: %s\n', reportPath);
end

function path = resolveReferenceScreenPath( ...
        base, presetName, seed, splitName, currentTime)
resultPath = fullfile( ...
    base.outputRoot, 'formation_withholding_h3', splitName, ...
    sprintf('%s_seed%d_t%d', ...
        strrep(presetName, '-', '_'), seed, currentTime), ...
    'DIRECT_GRAPH_FORMATION_WITHHOLDING_H3_V214.mat');
if exist(resultPath, 'file') ~= 2
    error('DirectGraphCreditRepairV216:MissingReferenceScreen', ...
        'The paired V214 withholding screen is required.');
end
loaded = load(resultPath, 'result');
[folder, stem] = fileparts(loaded.result.screenPath);
path = fullfile(folder, [stem, '.mat']);
end

function screen = loadReferenceScreen( ...
        path, presetName, seed, currentTime, horizonSteps)
if exist(path, 'file') ~= 2
    error('DirectGraphCreditRepairV216:MissingReferenceScreen', ...
        'The paired V214 screen MAT file is required.');
end
loaded = load(path, 'screen');
screen = loaded.screen;
if ~strcmp(screen.presetName, presetName) || ...
        screen.seed ~= seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= horizonSteps || ...
        screen.referenceSubsetIndex < 1 || ...
        screen.referenceSubsetIndex > numel(screen.outcomes)
    error('DirectGraphCreditRepairV216:ReferenceScreenDrift', ...
        'The paired V214 reference screen changed scope.');
end
end

function passed = multiObjectivePositive(record)
passed = record.meanGainPercent > 0 && ...
    record.rmseGainPercent > 0 && ...
    record.consensusGainPercent >= 0 && ...
    record.terminalConsensusGainPercent >= 0 && ...
    record.attemptedByteSavingPercent > 0 && ...
    record.selectedB3Passed;
end

function passed = tailTolerant(record, risk)
names = risk.targetNames;
tolerance = risk.tolerancePercent;
passed = record.worstGainPercent >= tolerance(strcmp( ...
        names, 'worst_sensor_eospa_gain_percent')) && ...
    record.worstRmseGainPercent >= tolerance(strcmp( ...
        names, 'worst_sensor_rmse_gain_percent')) && ...
    record.minimumFormationGainPercent >= tolerance(strcmp( ...
        names, 'minimum_formation_eospa_gain_percent')) && ...
    record.minimumFormationRmseGainPercent >= tolerance(strcmp( ...
        names, 'minimum_formation_rmse_gain_percent'));
end

function index = selectBest(records, eligibleMask)
index = NaN;
eligible = find(eligibleMask);
if isempty(eligible)
    return;
end
score = -inf(1, numel(records));
for recordIdx = eligible
    score(recordIdx) = min([ ...
        records(recordIdx).meanGainPercent, ...
        records(recordIdx).rmseGainPercent, ...
        records(recordIdx).consensusGainPercent, ...
        records(recordIdx).attemptedByteSavingPercent]);
end
[~, index] = max(score);
end

function writeReport(path, result, records)
fid = fopen(path, 'w');
if fid < 0
    error('DirectGraphCreditRepairV216:WriteReport', ...
        'Could not write the V216 H=3 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V216 direct-graph causal credit repair H=3\n\n');
fprintf(fid, '- Split / scene / seed / time: `%s / %s / %d / %d`\n', ...
    result.splitName, result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Reference attempted bytes on action page: `%d`\n', ...
    result.referencePageBytes);
fprintf(fid, '- Actual repair delivery sampled: `%d`\n', ...
    result.actualDeliverySampled);
fprintf(fid, '- Any supported-label repair executed: `%d`\n', ...
    result.anyRepairExecuted);
fprintf(fid, '- Any multi-objective eligible candidate: `%d`\n', ...
    result.anyEligibleCandidate);
fprintf(fid, '- Online posterior counterfactuals: `0`\n');
fprintf(fid, '- Moment-matched light posterior: `0`\n\n');
fprintf(fid, ['| Combined action | Repair proposals / applied | Repair bytes | ', ...
    'E-OSPA gain | RMSE gain | Consensus | Terminal consensus | ', ...
    'Byte saving | Worst sensor E / R | Minimum formation E / R | Eligible |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for idx = 1:numel(records)
    fprintf(fid, ['| %s | %d / %d | %d | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f / %+.3f%% | ', ...
        '%+.3f / %+.3f%% | %d |\n'], ...
        records(idx).actionName, result.repairProposalCount(idx), ...
        result.repairAppliedCount(idx), result.repairAttemptedBytes(idx), ...
        records(idx).meanGainPercent, records(idx).rmseGainPercent, ...
        records(idx).consensusGainPercent, ...
        records(idx).terminalConsensusGainPercent, ...
        records(idx).attemptedByteSavingPercent, ...
        records(idx).worstGainPercent, records(idx).worstRmseGainPercent, ...
        records(idx).minimumFormationGainPercent, ...
        records(idx).minimumFormationRmseGainPercent, ...
        result.eligibleMask(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
