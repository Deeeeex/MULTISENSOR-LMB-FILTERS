function writeOutputAlignedSafeGraphNeighborhoodV155Report(path, summary)
% WRITEOUTPUTALIGNEDSAFEGRAPHNEIGHBORHOODV155REPORT Render Stage A.

fid = fopen(path, 'w');
if fid < 0
    error('Could not write V155 Stage-A report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V155 output-aligned safe graph-neighborhood pilot\n\n');
fprintf(fid, '- Preset / seed / window: `%s / %d / %d:%d`\n', ...
    summary.presetName, summary.seed, summary.analysisWindow);
fprintf(fid, '- Better static reference: `%s`\n', ...
    summary.referenceArmMode);
fprintf(fid, '- Selected action: `%s`\n', summary.selectedArmMode);
fprintf(fid, '- Retained radius-one graphs: `%d / %d`\n', ...
    summary.retainedCandidateCount, summary.candidateCount);
fprintf(fid, '- Radius-two follow-up authorized: `%d`\n', ...
    summary.radiusTwoAuthorized);
fprintf(fid, '- Attempted-byte increase ceiling: `%.1f%%`\n\n', ...
    summary.maximumAttemptedByteIncreasePercent);
fprintf(fid, ['| Mean gain | Worst-sensor gain | Minimum-formation gain | ', ...
    'Consensus gain | Attempted-byte saving | 5%% Stage-A gate |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|:--:|\n');
fprintf(fid, '| %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n\n', ...
    summary.oracleGainPercent, summary.worstSensorGainPercent, ...
    summary.minimumFormationGainPercent, ...
    summary.consensusGainPercent, ...
    summary.attemptedByteSavingPercent, ...
    summary.stageAMeanGatePassed);

fprintf(fid, '## Complete radius-one neighborhood\n\n');
fprintf(fid, ['| Candidate | Mean gain | Worst-sensor gain | ', ...
    'Minimum-formation gain | Consensus gain | Byte saving | ', ...
    'Route changes | Held | Structure | Retained |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|:--:|\n');
for idx = 1:summary.candidateCount
    fprintf(fid, ['| %d | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d | %d | %d | %d |\n'], ...
        idx, summary.candidateMeanGainPercent(idx), ...
        summary.candidateWorstSensorGainPercent(idx), ...
        summary.candidateMinimumFormationGainPercent(idx), ...
        summary.candidateConsensusGainPercent(idx), ...
        summary.candidateAttemptedByteSavingPercent(idx), ...
        summary.candidateRouteChangeCount(idx), ...
        summary.candidateHeldAllPages(idx), ...
        summary.candidateStructurePass(idx), ...
        summary.candidateRetained(idx));
end
fprintf(fid, '\n## Boundary\n\n%s\n', summary.claimBoundary);
end
