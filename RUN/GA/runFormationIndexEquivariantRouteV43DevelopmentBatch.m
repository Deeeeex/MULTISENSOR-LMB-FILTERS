function result = ...
    runFormationIndexEquivariantRouteV43DevelopmentBatch( ...
        outputDirectory, options)
% RUNFORMATIONINDEXEQUIVARIANTROUTEV43DEVELOPMENTBATCH
% Registered structural comparison across M24/X36 and four scene styles.

repoRoot = resolveRunnerRepoRoot();
if nargin < 1 || isempty(outputDirectory)
    outputDirectory = fullfile(repoRoot, 'RUN', 'GA', ...
        'dynamic_topology', 'evidence', 'formation_value_v43', ...
        'index_equivariant_route_development_v1');
elseif ischar(outputDirectory) && outputDirectory(1) ~= filesep
    outputDirectory = fullfile(repoRoot, outputDirectory);
end
if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = {'presets', 'seeds', 'requireCleanGit'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationIndexEquivariantV43Runner:InvalidOptions', ...
        'The v43 runner options are malformed.');
end
protocol = getFormationIndexEquivariantRouteV43DevelopmentProtocol();
presets = getField(options, 'presets', protocol.registeredPresets);
seeds = reshape(getField(options, 'seeds', ...
    protocol.registeredSeeds), 1, []);
requireCleanGitInput = getField(options, 'requireCleanGit', true);
if ~isscalar(requireCleanGitInput) || ...
        ~(islogical(requireCleanGitInput) || ...
          (isnumeric(requireCleanGitInput) && ...
           isreal(requireCleanGitInput) && ...
           isfinite(requireCleanGitInput) && ...
           any(requireCleanGitInput == [0, 1])))
    error('FormationIndexEquivariantV43Runner:InvalidOptions', ...
        'requireCleanGit must be scalar logical or exact numeric 0/1.');
end
requireCleanGit = logical(requireCleanGitInput);
validateRequestedCases(presets, seeds, protocol);

matPath = fullfile(outputDirectory, ...
    'FORMATION_INDEX_EQUIVARIANT_ROUTE_V43_DEVELOPMENT_V1.mat');
reportPath = fullfile(outputDirectory, ...
    'FORMATION_INDEX_EQUIVARIANT_ROUTE_V43_DEVELOPMENT_V1.md');
if exist(outputDirectory, 'dir') || exist(outputDirectory, 'file') || ...
        exist(matPath, 'file') || exist(reportPath, 'file')
    error('FormationIndexEquivariantV43Runner:OutputExists', ...
        'The v43 development output is non-overwriting.');
end
[gitCommit, gitDirty] = resolveGitState(repoRoot);
if requireCleanGit && gitDirty
    error('FormationIndexEquivariantV43Runner:DirtyGitState', ...
        ['A registered v43 batch requires a clean worktree, including ', ...
         'no untracked files.']);
end
if ~isAncestor(repoRoot, protocol.methodCommit, gitCommit)
    error('FormationIndexEquivariantV43Runner:MethodCommitMissing', ...
        'The frozen v43 method commit is not an ancestor of the runner.');
end
executableSourceManifest = ...
    buildFormationIndexEquivariantRouteV43ExecutableSourceManifest( ...
        repoRoot);
if requireCleanGit && ...
        (~executableSourceManifest.allEntriesTrackedByHead || ...
         ~executableSourceManifest.allWorkingFilesMatchHead)
    error('FormationIndexEquivariantV43Runner:ExecutableSourceNotHead', ...
        ['A registered batch requires every executable source file to ', ...
         'be tracked by and byte-identical to HEAD.']);
end
officialCleanSourcePassed = requireCleanGit && ~gitDirty && ...
    executableSourceManifest.pathResolutionPassed && ...
    executableSourceManifest.allEntriesTrackedByHead && ...
    executableSourceManifest.allWorkingFilesMatchHead;
if ~exist(outputDirectory, 'dir')
    [created, message] = mkdir(outputDirectory);
    if ~created
        error('FormationIndexEquivariantV43Runner:OutputCreateFailed', ...
            'Cannot create the v43 output directory: %s', message);
    end
end

caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
caseCursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        caseCursor = caseCursor + 1;
        fprintf('V43 route case %d/%d: %s seed %d\n', ...
            caseCursor, caseCount, presets{presetIdx}, seeds(seedIdx));
        registeredCase = findRegisteredCase( ...
            protocol, presets{presetIdx}, seeds(seedIdx));
        cases(caseCursor) = buildCase( ...
            presets{presetIdx}, seeds(seedIdx), protocol, ...
            registeredCase);
    end
end

[endingGitCommit, endingGitDirty] = resolveGitState(repoRoot);
endingExecutableSourceManifest = ...
    buildFormationIndexEquivariantRouteV43ExecutableSourceManifest( ...
        repoRoot);
executionSourceStable = strcmp(endingGitCommit, gitCommit) && ...
    endingGitDirty == gitDirty && ...
    strcmp(endingExecutableSourceManifest.canonicalSha256, ...
        executableSourceManifest.canonicalSha256);
if requireCleanGit && ~executionSourceStable
    error('FormationIndexEquivariantV43Runner:SourceChangedDuringRun', ...
        'The clean v43 executable source changed during the batch.');
end
officialCleanSourcePassed = ...
    officialCleanSourcePassed && executionSourceStable;
requestedCaseIds = {cases.caseId};
registeredCaseIds = {protocol.registeredCases.caseId};
registeredBatchComplete = isequal(requestedCaseIds, registeredCaseIds);
cleanSourceEvidence = struct( ...
    'contractVersion', ...
        'formation-index-equivariant-route-v43-clean-source-evidence-v1', ...
    'requireCleanGit', requireCleanGit, ...
    'initialGitDirty', gitDirty, ...
    'endingGitDirty', endingGitDirty, ...
    'generationCommitStable', strcmp(endingGitCommit, gitCommit), ...
    'executableManifestStable', strcmp( ...
        endingExecutableSourceManifest.canonicalSha256, ...
        executableSourceManifest.canonicalSha256), ...
    'pathResolutionPassed', ...
        executableSourceManifest.pathResolutionPassed, ...
    'allEntriesTrackedByHead', ...
        executableSourceManifest.allEntriesTrackedByHead, ...
    'allWorkingFilesMatchHead', ...
        executableSourceManifest.allWorkingFilesMatchHead);
postHocExecutableFreezeEvidence = struct( ...
    'contractVersion', ...
        ['formation-index-equivariant-route-v43-', ...
         'posthoc-freeze-evidence-v1'], ...
    'generationCommitPinned', false, ...
    'protocolShaMatched', false, ...
    'resultCanonicalShaRecomputed', false, ...
    'executableManifestShaPinned', false, ...
    'artifactFilesShaPinned', false, ...
    'independentAuditCommitted', false, ...
    'auditSourceClean', false);
execution = struct( ...
    'registeredBatchComplete', registeredBatchComplete, ...
    'cleanSourceEvidence', cleanSourceEvidence, ...
    'postHocExecutableFreezeEvidence', ...
        postHocExecutableFreezeEvidence);
gate = evaluateFormationIndexEquivariantRouteV43DevelopmentGate( ...
    cases, execution, protocol);
if gate.officialCleanSourcePassed ~= officialCleanSourcePassed
    error('FormationIndexEquivariantV43Runner:CleanEvidenceMismatch', ...
        'The aggregate gate disagrees with the runner clean-source audit.');
end

result = struct();
result.contractVersion = ...
    'formation-index-equivariant-route-v43-development-result-v1';
result.protocolId = protocol.id;
result.protocolCanonicalSha256 = protocol.canonicalSha256;
result.methodCommit = protocol.methodCommit;
result.generationGitCommit = gitCommit;
result.generationGitDirty = gitDirty;
result.endingGitCommit = endingGitCommit;
result.endingGitDirty = endingGitDirty;
result.executionSourceStable = executionSourceStable;
result.requireCleanGit = requireCleanGit;
result.executableSourceManifest = executableSourceManifest;
result.cleanSourceEvidence = cleanSourceEvidence;
result.postHocExecutableFreezeEvidence = ...
    postHocExecutableFreezeEvidence;
result.officialCleanSourcePassed = officialCleanSourcePassed;
result.presets = presets;
result.seeds = seeds;
result.requestedCaseIds = requestedCaseIds;
result.registeredCaseIds = registeredCaseIds;
result.registeredBatchComplete = registeredBatchComplete;
result.exploratorySubsetOnly = ~registeredBatchComplete;
result.caseCount = caseCount;
result.cases = cases;
result.gate = gate;
result.sameMessageBudget = gate.sameMessageAndWeightBudget;
result.sameMessageAndWeightBudget = gate.sameMessageAndWeightBudget;
result.registeredInputIdentityPassed = ...
    gate.registeredInputIdentityPassed;
result.executionBoundaryPassed = gate.executionBoundaryPassed;
result.everyCaseFiniteTargetHorizon = ...
    gate.everyCaseFiniteTargetHorizon;
result.everyCaseV43TargetHorizonNotWorse = ...
    gate.everyCaseV43TargetHorizonNotWorse;
result.everyCaseFixedNMinusOneFactorLower = ...
    gate.everyCaseFixedNMinusOneFactorLower;
result.m24NonCrossingMedianTargetHorizonRatio = ...
    gate.m24NonCrossingMedianTargetHorizonRatio;
result.x36NonCrossingMedianTargetHorizonRatio = ...
    gate.x36NonCrossingMedianTargetHorizonRatio;
result.scaleMedianTargetHorizonRatioGatePassed = ...
    gate.scaleMedianTargetHorizonRatioGatePassed;
result.sparseFallbackContractPassed = ...
    gate.sparseFallbackContractPassed;
result.routeReferenceAdvanceCriteriaPassed = ...
    gate.routeReferenceAdvanceCriteriaPassed;
result.postHocExecutableFreezeAuditPassed = ...
    gate.postHocExecutableFreezeAuditPassed;
result.routeReferenceAdvancePassed = ...
    gate.routeReferenceAdvancePassed;
result.anySparseActionStructurallyAuthorized = ...
    any([cases.sparseActionAuthorized]);
result.allSingleFormationSuspensionsFallbackReference = ...
    all([cases.referenceFallbackUsed]);
result.fullPlannedSensorGeometryMaterialized = ...
    all([cases.fullPlannedSensorGeometryMaterialized]);
result.fullPlannedLinkProbabilityScheduleMaterialized = ...
    all([cases.fullPlannedLinkProbabilityScheduleMaterialized]);
result.formalRuntimeObservableBoundaryPassed = ...
    any([cases.formalRuntimeObservableBoundaryPassed]);
result.runtimePhysicalUidRegistryIntegrated = ...
    any([cases.runtimePhysicalUidRegistryIntegrated]);
result.posteriorUsed = any([cases.posteriorUsed]);
result.truthUsed = any([cases.truthUsed]);
result.measurementUsed = any([cases.measurementUsed]);
result.futureOutcomeUsed = any([cases.futureOutcomeUsed]);
result.realizedDeliveryUniformsUsed = ...
    any([cases.realizedDeliveryUniformsUsed]);
result.trackingOutcomeScored = any([cases.trackingOutcomeScored]);
result.trackingOutcomeAuthorized = ...
    any([cases.trackingOutcomeAuthorized]);
result.validationClaimAllowed = ...
    any([cases.validationClaimAllowed]);
result.developmentEvidenceOnly = ...
    all([cases.developmentEvidenceOnly]);
result.canonicalSha256 = computeCanonicalValueSha256(result);

save(matPath, 'result', '-v7');
writeReport(reportPath, result, matPath, protocol);
fprintf('V43 route development batch complete: %s\n', reportPath);
end

function value = buildCase(presetName, seed, protocol, registeredCase)
[context, metadata] = ...
    buildFormationIndexEquivariantGeometryDevelopmentContext( ...
        presetName, seed);
options = struct( ...
    'targetSquaredContractionFactor', ...
        protocol.targetSquaredContractionFactor, ...
    'maximumHorizonMultiplier', ...
        protocol.maximumHorizonMultiplier, ...
    'maximumIncomingCount', protocol.maximumIncomingCount, ...
    'dominantWeight', protocol.dominantWeight, ...
    'residualWeight', protocol.residualWeight);
comparison = compareLegacyAndIndexEquivariantFormationRoutes( ...
    context, options);
probe = buildFormationIndexEquivariantAdaptiveWindowRouteProbe( ...
    context, options);
if comparison.v43TargetHorizon ~= probe.evaluationHorizon || ...
        abs(comparison.v43Profile. ...
            worstCaseExpectedSquaredFactorByHorizon( ...
                probe.evaluationHorizon + 1) - ...
            probe.referenceSquaredContractionFactor) > 1e-12 || ...
        ~comparison.fusionWeightsMatched || ...
        comparison.dominantWeight ~= protocol.dominantWeight || ...
        comparison.residualWeight ~= protocol.residualWeight || ...
        probe.dominantWeight ~= protocol.dominantWeight || ...
        probe.residualWeight ~= protocol.residualWeight
    error('FormationIndexEquivariantV43Runner:InternalContract', ...
        'The comparison and adaptive probe disagree.');
end
assertRegisteredCaseIdentity(metadata, registeredCase);
boundary = auditExecutionBoundary( ...
    context, metadata, comparison, probe);

candidateActions = probe.actions(2:end);
candidateUids = [candidateActions.formationPhysicalUid];
candidateAvailable = [candidateActions.available];
candidateDeltas = [candidateActions.factorDelta];
candidateMessageSavings = [candidateActions.messageSavingCount];
if probe.sparseActionAuthorized
    fallbackContract = ~probe.referenceFallbackUsed && ...
        probe.leastHarmfulCandidateFactorDelta < ...
            -protocol.sparseActionImprovementTolerance && ...
        probe.selectedActionPhysicalFormationUid == ...
            probe.leastHarmfulCandidatePhysicalFormationUid && ...
        ~strcmp(probe.selectedActionName, 'reference');
else
    fallbackContract = probe.referenceFallbackUsed && ...
        strcmp(probe.selectedActionName, 'reference') && ...
        isnan(probe.selectedActionPhysicalFormationUid) && ...
        all(~candidateAvailable | candidateDeltas >= ...
            -protocol.sparseActionImprovementTolerance);
end

value = emptyCase();
value.caseId = sprintf('%s__seed%d__t%d', ...
    presetName, seed, metadata.currentTime);
value.presetName = presetName;
value.sceneRole = registeredCase.sceneRole;
value.seed = seed;
value.currentTime = metadata.currentTime;
value.nodeCount = metadata.nodeCount;
value.formationCount = metadata.formationCount;
value.inputCanonicalSha256 = metadata.inputCanonicalSha256;
value.physicalUidRegistryCanonicalSha256 = ...
    metadata.physicalUidAssignmentCanonicalSha256;
value.registeredInputIdentityMatched = true;
value.legacyRouteCanonicalSha256 = ...
    comparison.legacyRouteCanonicalSha256;
value.v43RouteCanonicalSha256 = comparison.v43RouteCanonicalSha256;
value.legacyTargetHorizon = comparison.legacyTargetHorizon;
value.v43TargetHorizon = comparison.v43TargetHorizon;
value.targetHorizonReduction = comparison.targetHorizonReduction;
value.targetHorizonRatio = comparison.targetHorizonRatio;
value.fixedComparisonHorizon = comparison.fixedComparisonHorizon;
value.legacyFixedHorizonFactor = ...
    comparison.legacyFixedHorizonFactor;
value.v43FixedHorizonFactor = comparison.v43FixedHorizonFactor;
value.fixedHorizonFactorDelta = comparison.fixedHorizonFactorDelta;
value.fixedHorizonRelativeReduction = ...
    comparison.fixedHorizonRelativeReduction;
value.legacyDirectedMessageCount = ...
    comparison.legacyDirectedMessageCount;
value.v43DirectedMessageCount = comparison.v43DirectedMessageCount;
value.sameDirectedMessageBudget = ...
    comparison.sameDirectedMessageBudget;
value.legacyCrossFormationMessageCount = ...
    comparison.legacyCrossFormationMessageCount;
value.v43CrossFormationMessageCount = ...
    comparison.v43CrossFormationMessageCount;
value.sameCrossFormationMessageBudget = ...
    comparison.sameCrossFormationMessageBudget;
value.fusionWeightsMatched = comparison.fusionWeightsMatched;
value.protocolWeightsMatched = ...
    comparison.dominantWeight == protocol.dominantWeight && ...
    comparison.residualWeight == protocol.residualWeight && ...
    probe.dominantWeight == protocol.dominantWeight && ...
    probe.residualWeight == protocol.residualWeight;
value.candidateFormationPhysicalUids = candidateUids;
value.candidateAvailableMask = candidateAvailable;
value.candidateFactorDeltas = candidateDeltas;
value.candidateMessageSavingCounts = candidateMessageSavings;
value.leastHarmfulCandidatePhysicalFormationUid = ...
    probe.leastHarmfulCandidatePhysicalFormationUid;
value.leastHarmfulCandidateFactorDelta = ...
    probe.leastHarmfulCandidateFactorDelta;
value.improvingCandidateCount = probe.improvingCandidateCount;
value.sparseActionAuthorized = probe.sparseActionAuthorized;
value.selectedActionName = probe.selectedActionName;
value.referenceFallbackUsed = probe.referenceFallbackUsed;
value.sparseFallbackContractPassed = fallbackContract;
value.executionBoundaryVerified = boundary.passed;
value.executionBoundaryCanonicalSha256 = boundary.canonicalSha256;
value.fullPlannedSensorGeometryMaterialized = ...
    boundary.fullPlannedSensorGeometryMaterialized;
value.fullPlannedLinkProbabilityScheduleMaterialized = ...
    boundary.fullPlannedLinkProbabilityScheduleMaterialized;
value.formalRuntimeObservableBoundaryPassed = ...
    boundary.formalRuntimeObservableBoundaryPassed;
value.runtimePhysicalUidRegistryIntegrated = ...
    boundary.runtimePhysicalUidRegistryIntegrated;
value.posteriorUsed = boundary.posteriorUsed;
value.truthUsed = boundary.truthUsed;
value.measurementUsed = boundary.measurementUsed;
value.futureOutcomeUsed = boundary.futureOutcomeUsed;
value.realizedDeliveryUniformsUsed = ...
    boundary.realizedDeliveryUniformsUsed;
value.trackingOutcomeScored = boundary.trackingOutcomeScored;
value.trackingOutcomeAuthorized = boundary.trackingOutcomeAuthorized;
value.validationClaimAllowed = boundary.validationClaimAllowed;
value.developmentEvidenceOnly = boundary.developmentEvidenceOnly;
value.canonicalSha256 = computeCanonicalValueSha256(value);
end

