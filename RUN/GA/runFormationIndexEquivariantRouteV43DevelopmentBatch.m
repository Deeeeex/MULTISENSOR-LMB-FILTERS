    result.postHocExecutableFreezeAuditPassed);
fprintf(fid, '- Route-reference advance passed: `%d`\n', ...
    result.routeReferenceAdvancePassed);
fprintf(fid, '- M24 non-crossing median H ratio: `%.6f`\n', ...
    result.m24NonCrossingMedianTargetHorizonRatio);
