    result.sameMessageAndWeightBudget);
fprintf(fid, '- Execution boundary passed: `%d`\n', ...
    result.executionBoundaryPassed);
fprintf(fid, '- Route-reference criteria passed: `%d`\n', ...
    result.routeReferenceAdvanceCriteriaPassed);
