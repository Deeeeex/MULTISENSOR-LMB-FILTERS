        item.leastHarmfulCandidateFactorDelta, ...
        item.selectedActionName);
end
fprintf(fid, '\n## Claim boundary\n\n');
fprintf(fid, ['This batch compares propagation structure under equal ', ...
    'message and fusion-weight budgets. Per-case execution-boundary ', ...
    'records attest that it materializes complete planned sensor/link ', ...
    'schedules in a development loader, does not read posterior contents ', ...
    'or values, truth, measurements, future outcomes, or realized ', ...
    'delivery uniforms, and does not score tracking. Runtime UID ', ...
    'integration, tracking ', ...
    'authorization, and validation claims remain false.\n']);
fprintf(fid, ['\nThe generation runner never self-authorizes advancement. ', ...
    'Even if all frozen structural criteria pass, a separately committed ', ...
    'post-hoc executable-freeze audit is required.\n']);
fprintf(fid, '\nFrozen ratio gate: `%.3f` per non-crossing scale family.\n', ...
    protocol.scaleMedianTargetHorizonRatioMaximum);
end

function registeredCase = findRegisteredCase(protocol, presetName, seed)
matches = strcmp({protocol.registeredCases.presetName}, presetName) & ...
    [protocol.registeredCases.seed] == seed;
if nnz(matches) ~= 1
    error('FormationIndexEquivariantV43Runner:CaseRegistry', ...
        'The requested v43 case lacks one frozen identity record.');
end
registeredCase = protocol.registeredCases(matches);
end

function assertRegisteredCaseIdentity(metadata, registeredCase)
matched = strcmp(metadata.presetName, registeredCase.presetName) && ...
    metadata.seed == registeredCase.seed && ...
    metadata.currentTime == registeredCase.currentTime && ...
    metadata.nodeCount == registeredCase.nodeCount && ...
    metadata.formationCount == registeredCase.formationCount && ...
    strcmp(metadata.inputCanonicalSha256, ...
        registeredCase.inputCanonicalSha256) && ...
    strcmp(metadata.physicalUidAssignmentCanonicalSha256, ...
        registeredCase.physicalUidRegistryCanonicalSha256);
if ~matched
    error('FormationIndexEquivariantV43Runner:RegisteredInputDrift', ...
        'The generated case differs from its frozen v43 input identity.');
end
end

function boundary = auditExecutionBoundary( ...
        context, metadata, comparison, probe)
contextRequired = {'fullPlannedSensorGeometryMaterialized', ...
    'fullPlannedLinkProbabilityScheduleMaterialized', ...
    'formalRuntimeObservableBoundaryPassed', ...
    'runtimePhysicalUidRegistryIntegrated', 'posteriorContentsRead', ...
    'truthUsed', 'measurementUsed', 'futureOutcomeUsed', ...
    'realizedDeliveryUniformsUsed', 'trackingOutcomeScored', ...
    'trackingOutcomeAuthorized', 'validationClaimAllowed', ...
    'developmentEvidenceOnly'};
metadataRequired = {'fullPlannedSensorGeometryMaterialized', ...
    'fullPlannedLinkProbabilityScheduleMaterialized', ...
    'formalRuntimeObservableBoundaryPassed', 'posteriorUsed', ...
    'truthUsed', 'measurementUsed', 'targetTrajectoryGenerated', ...
    'realizedDeliveryUniformsUsed', 'developmentEvidenceOnly'};
comparisonRequired = {'routeBoundaryVerified', ...
    'auditBoundaryCanonicalSha256', 'posteriorUsed', 'truthUsed', ...
    'measurementUsed', 'futureOutcomeUsed', ...
    'realizedDeliveryUniformsUsed', 'trackingOutcomeScored', ...
    'developmentEvidenceOnly', 'auditBoundary'};
probeRequired = {'routeBoundaryVerified', ...
    'auditBoundaryCanonicalSha256', 'posteriorContentsRead', ...
    'truthUsed', 'measurementUsed', 'futureOutcomeUsed', ...
    'realizedDeliveryUniformsUsed', 'trackingOutcomeScored', ...
    'trackingOutcomeAuthorized', 'validationClaimAllowed', ...
    'developmentEvidenceOnly', 'auditBoundary'};
if ~isfield(context, 'auditBoundary') || ...
        ~all(isfield(context.auditBoundary, contextRequired)) || ...
        ~all(isfield(metadata, metadataRequired)) || ...
        ~all(isfield(comparison, comparisonRequired)) || ...
        ~all(isfield(probe, probeRequired))
    error('FormationIndexEquivariantV43Runner:BoundaryMissing', ...
        'A v43 execution layer omitted required boundary evidence.');
end
source = context.auditBoundary;
sourceSha256 = computeCanonicalValueSha256(source);
boundary = struct();
boundary.contractVersion = ...
    'formation-index-equivariant-route-v43-case-boundary-v2';
boundary.sourceBoundaryCanonicalSha256 = sourceSha256;
boundary.fullPlannedSensorGeometryMaterialized = ...
    source.fullPlannedSensorGeometryMaterialized && ...
    metadata.fullPlannedSensorGeometryMaterialized && ...
    probe.fullPlannedSensorGeometryMaterialized;
boundary.fullPlannedLinkProbabilityScheduleMaterialized = ...
    source.fullPlannedLinkProbabilityScheduleMaterialized && ...
    metadata.fullPlannedLinkProbabilityScheduleMaterialized && ...
    probe.fullPlannedLinkProbabilityScheduleMaterialized;
boundary.formalRuntimeObservableBoundaryPassed = ...
    source.formalRuntimeObservableBoundaryPassed || ...
    metadata.formalRuntimeObservableBoundaryPassed || ...
    probe.formalRuntimeObservableBoundaryPassed;
boundary.runtimePhysicalUidRegistryIntegrated = ...
    source.runtimePhysicalUidRegistryIntegrated || ...
    probe.runtimePhysicalUidRegistryIntegrated;
boundary.posteriorUsed = source.posteriorContentsRead || ...
    metadata.posteriorUsed || comparison.posteriorUsed || ...
    probe.posteriorContentsRead;
boundary.truthUsed = source.truthUsed || metadata.truthUsed || ...
    comparison.truthUsed || probe.truthUsed;
boundary.measurementUsed = source.measurementUsed || ...
    metadata.measurementUsed || comparison.measurementUsed || ...
    probe.measurementUsed;
boundary.futureOutcomeUsed = source.futureOutcomeUsed || ...
    comparison.futureOutcomeUsed || probe.futureOutcomeUsed;
boundary.realizedDeliveryUniformsUsed = ...
    source.realizedDeliveryUniformsUsed || ...
    metadata.realizedDeliveryUniformsUsed || ...
    comparison.realizedDeliveryUniformsUsed || ...
    probe.realizedDeliveryUniformsUsed;
boundary.trackingOutcomeScored = source.trackingOutcomeScored || ...
    comparison.trackingOutcomeScored || probe.trackingOutcomeScored;
boundary.trackingOutcomeAuthorized = ...
    source.trackingOutcomeAuthorized || probe.trackingOutcomeAuthorized;
boundary.validationClaimAllowed = ...
    source.validationClaimAllowed || probe.validationClaimAllowed;
boundary.targetTrajectoryGenerated = metadata.targetTrajectoryGenerated;
boundary.routeBoundariesVerified = comparison.routeBoundaryVerified && ...
    probe.routeBoundaryVerified;
boundary.layerBoundaryHashesMatched = ...
    strcmp(comparison.auditBoundaryCanonicalSha256, sourceSha256) && ...
    strcmp(probe.auditBoundaryCanonicalSha256, sourceSha256) && ...
    isequal(comparison.auditBoundary, source) && ...
    isequal(probe.auditBoundary, source);
boundary.developmentEvidenceOnly = ...
    source.developmentEvidenceOnly && metadata.developmentEvidenceOnly && ...
    comparison.developmentEvidenceOnly && probe.developmentEvidenceOnly;
boundary.passed = ...
    boundary.fullPlannedSensorGeometryMaterialized && ...
    boundary.fullPlannedLinkProbabilityScheduleMaterialized && ...
    ~boundary.formalRuntimeObservableBoundaryPassed && ...
    ~boundary.runtimePhysicalUidRegistryIntegrated && ...
    ~boundary.posteriorUsed && ~boundary.truthUsed && ...
    ~boundary.measurementUsed && ~boundary.futureOutcomeUsed && ...
    ~boundary.realizedDeliveryUniformsUsed && ...
    ~boundary.trackingOutcomeScored && ...
    ~boundary.trackingOutcomeAuthorized && ...
    ~boundary.validationClaimAllowed && ...
    ~boundary.targetTrajectoryGenerated && ...
    boundary.routeBoundariesVerified && ...
    boundary.layerBoundaryHashesMatched && ...
    boundary.developmentEvidenceOnly;
boundary.canonicalSha256 = computeCanonicalValueSha256(boundary);
if ~boundary.passed
    error('FormationIndexEquivariantV43Runner:BoundaryViolation', ...
        'The v43 execution chain crossed its development-only boundary.');
end
end

function validateRequestedCases(presets, seeds, protocol)
if ~iscell(presets) || isempty(presets) || ...
        any(~cellfun(@ischar, presets)) || ...
        numel(unique(presets)) ~= numel(presets) || ...
        ~isnumeric(seeds) || ~isreal(seeds) || isempty(seeds) || ...
        any(~isfinite(seeds)) || any(seeds ~= round(seeds)) || ...
        numel(unique(seeds)) ~= numel(seeds) || ...
        any(~ismember(presets, protocol.registeredPresets)) || ...
        any(~ismember(seeds, protocol.registeredSeeds))
    error('FormationIndexEquivariantV43Runner:InvalidCases', ...
        'Requested cases are not a unique registered subset.');
end
end

function [commit, dirty] = resolveGitState(repoRoot)
[status, commit] = system(sprintf( ...
    'git -C "%s" rev-parse HEAD', repoRoot));
if status ~= 0
    error('FormationIndexEquivariantV43Runner:GitState', ...
        'Cannot resolve the v43 generation commit.');
end
commit = strtrim(commit);
[status, porcelain] = system(sprintf( ...
    'git -C "%s" status --porcelain --untracked-files=all', repoRoot));
if status ~= 0
    error('FormationIndexEquivariantV43Runner:GitState', ...
        'Cannot resolve the complete v43 worktree state.');
end
dirty = ~isempty(strtrim(porcelain));
end

function yes = isAncestor(repoRoot, ancestor, descendant)
status = system(sprintf( ...
    'git -C "%s" merge-base --is-ancestor %s %s', ...
    repoRoot, ancestor, descendant));
yes = status == 0;
end

function root = resolveRunnerRepoRoot()
scriptPath = mfilename('fullpath');
root = fileparts(fileparts(fileparts(scriptPath)));
[status, topLevel] = system(sprintf( ...
    'git -C "%s" rev-parse --show-toplevel', root));
if status ~= 0 || ~strcmp(strtrim(topLevel), root)
    error('FormationIndexEquivariantV43Runner:RepoRoot', ...
        'The runner repository root cannot be verified.');
end
end

