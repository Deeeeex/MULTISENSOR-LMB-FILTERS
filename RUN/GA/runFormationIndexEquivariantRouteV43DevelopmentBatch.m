    result.protocolCanonicalSha256);
fprintf(fid, '- Generation commit: `%s`\n', result.generationGitCommit);
fprintf(fid, '- Result SHA-256: `%s`\n', result.canonicalSha256);
fprintf(fid, '- MAT artifact: `%s`\n', matPath);
fprintf(fid, '- Registered batch complete: `%d`\n', ...
    result.registeredBatchComplete);
