function [reportPath, audit] = ...
    auditFormationTemporalSuspensionV29(options)
% AUDITFORMATIONTEMPORALSUSPENSIONV29 Frozen primary-screen audit.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v29', 'temporal_cross_edge_suspension', ...
    't72', 'screen', ...
    ['FORMATION_TEMPORAL_SUSPENSION_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_TEMPORAL_CROSS_EDGE_SUSPENSION_V29_', ...
     'AUDIT_20260802.md']));
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V29Audit:MissingScreen', ...
        'Frozen v29 primary screen is unavailable.');
end
screen = loaded.screen;
assertScreenProvenance(screen);

records = screen.records;
outcomes = screen.outcomes;
referenceIdx = screen.referenceSubsetIndex;
nonreferenceIndices = setdiff(1:numel(records), referenceIdx);
[bestMeanGainPercent, bestLocalIdx] = max( ...
    [records(nonreferenceIndices).meanGainPercent]);
bestIdx = nonreferenceIndices(bestLocalIdx);
referenceOutcome = outcomes(referenceIdx);
bestOutcome = outcomes(bestIdx);
referenceTrackingByTime = mean( ...
    referenceOutcome.eospaBySensorTime, 1);
bestTrackingByTime = mean(bestOutcome.eospaBySensorTime, 1);
trackingGainByTimePercent = 100 * ( ...
    referenceTrackingByTime - bestTrackingByTime) ./ max( ...
        referenceTrackingByTime, eps);
referenceConsensusByTime = ...
    referenceOutcome.consensusOspaByTime;
bestConsensusByTime = bestOutcome.consensusOspaByTime;
consensusGainByTimePercent = 100 * ( ...
    referenceConsensusByTime - bestConsensusByTime) ./ max( ...
        referenceConsensusByTime, eps);
bestRecord = records(bestIdx);
meanThreshold = ...
    screen.protocol.meanTrackingGainThresholdPercent;
bestPassesEveryNonmeanGate = ...
    bestRecord.posteriorProxyAllowed && ...
    bestRecord.minimumFormationGainPercent >= ...
        screen.protocol.minimumFormationGainThresholdPercent - 1e-12 && ...
    bestRecord.worstGainPercent >= ...
        screen.protocol.worstSensorGainThresholdPercent - 1e-12 && ...
    bestRecord.consensusGainPercent >= ...
        screen.protocol.windowConsensusGainThresholdPercent - 1e-12 && ...
    bestRecord.attemptedByteSavingPercent >= ...
        screen.protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    bestRecord.selectedB3Passed;

audit = struct();
audit.contractVersion = ...
    'formation-temporal-cross-edge-suspension-v29-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.returnTimes = screen.returnTimes;
audit.referenceIndex = referenceIdx;
audit.bestIndex = bestIdx;
audit.bestActionName = bestRecord.actionName;
audit.bestSuspendedFormations = bestRecord.formationIndices;
audit.bestMeanGainPercent = bestMeanGainPercent;
audit.meanThresholdPercent = meanThreshold;
audit.meanThresholdGapPercent = ...
    meanThreshold - bestMeanGainPercent;
audit.bestWorstGainPercent = bestRecord.worstGainPercent;
audit.bestFormationGainPercent = ...
    bestRecord.formationGainPercent;
audit.bestMinimumFormationGainPercent = ...
    bestRecord.minimumFormationGainPercent;
audit.bestWindowConsensusGainPercent = ...
    bestRecord.consensusGainPercent;
audit.bestTerminalConsensusGainPercent = ...
    bestRecord.terminalConsensusGainPercent;
audit.bestAttemptedByteSavingPercent = ...
    bestRecord.attemptedByteSavingPercent;
audit.referenceMeanCardinalityError = ...
    referenceOutcome.meanCardinalityError;
audit.bestMeanCardinalityError = bestOutcome.meanCardinalityError;
audit.referenceTrackingByTime = referenceTrackingByTime;
audit.bestTrackingByTime = bestTrackingByTime;
audit.trackingGainByTimePercent = trackingGainByTimePercent;
audit.referenceConsensusByTime = referenceConsensusByTime;
audit.bestConsensusByTime = bestConsensusByTime;
audit.consensusGainByTimePercent = consensusGainByTimePercent;
audit.bestPassesEveryNonmeanGate = ...
    bestPassesEveryNonmeanGate;
audit.bestFailsOnlyMeanThreshold = ...
    bestPassesEveryNonmeanGate && ...
    bestMeanGainPercent < meanThreshold && ...
    bestMeanGainPercent > 0;
audit.strongCandidateCount = ...
    screen.strictStrongCandidateCount;
audit.truthUsedForActionConstruction = screen.bank.truthUsed;
audit.futureOutcomeUsedForActionConstruction = ...
    screen.bank.futureOutcomeUsed;
audit.truthUsedForOutcomeScoring = screen.outcomeRankingUsesTruth;
audit.newTrackingStateOpened = false;
audit.additionalM24Authorized = false;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'This audit reuses only the frozen v29 primary M24 screen. The ', ...
    'outcomes may motivate a preregistered two-phase controller on the ', ...
    'same opened state, but cannot relax the failed v29 gate, select a ', ...
    'deployed action with truth, open another state, train a GNN, or ', ...
    'support validation or generalization claims.'];

if ~audit.bestFailsOnlyMeanThreshold || ...
        ~strcmp(audit.bestActionName, 'suspend-f2-f3-f4') || ...
        audit.bestTerminalConsensusGainPercent >= 0
    error('V29Audit:UnexpectedMechanism', ...
        'Frozen v29 mechanism or failure mode changed.');
end

writeReport(reportPath, audit, screen);
fprintf('V29 temporal-suspension audit: %s\n', reportPath);
end

function assertScreenProvenance(screen)
if ~strcmp(screen.contractVersion, ...
        'formation-temporal-cross-edge-suspension-v29-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            '7e6e61bcc6efc8d85de5dc4c6e3f152dac06d481') || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(screen.presetName, 'm24-formation-fov') || ...
        screen.seed ~= 211 || screen.currentTime ~= 72 || ...
        ~isequal(screen.returnTimes, [72, 73, 74]) || ...
        screen.interventionDurationSteps ~= 1 || ...
        numel(screen.records) ~= 16 || ...
        ~screen.executedOnlyPosteriorSafeActions || ...
        screen.strictStrongCandidateCount ~= 0 || ...
        screen.strongCandidateFound || ...
        screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed
    error('V29Audit:ProvenanceMismatch', ...
        'Frozen v29 screen provenance or gate decision changed.');
end
end

function writeReport(path, audit, screen)
fid = fopen(path, 'w');
if fid < 0
    error('V29Audit:WriteFailed', ...
        'Could not open v29 audit report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V29 temporal cross-edge suspension audit\n\n');
fprintf(fid, '## Decision\n\n');
fprintf(fid, [ ...
    '**The frozen v29 primary gate fails with `0/15` strong ', ...
    'candidates.** The best action reaches `%.4f%%` mean tracking ', ...
    'gain, `%.4f` percentage points below the preregistered `%.1f%%` ', ...
    'threshold. Do not open another M24 state, train a GNN, or run ', ...
    'X36/X48 under v29.\n\n'], audit.bestMeanGainPercent, ...
    audit.meanThresholdGapPercent, audit.meanThresholdPercent);
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime);
fprintf(fid, '- Return times: `%s`\n', mat2str(audit.returnTimes));
fprintf(fid, '- Best action: `%s`\n', audit.bestActionName);
fprintf(fid, '- New tracking state opened by audit: `0`\n\n');

fprintf(fid, '## What the best action establishes\n\n');
fprintf(fid, [ ...
    '| Suspended formations | Mean gain | Worst-sensor gain | ', ...
    'Formation gains | Window consensus | Final consensus | ', ...
    'Attempted-byte saving | Mean card. error |\n']);
fprintf(fid, '|:--|--:|--:|:--|--:|--:|--:|--:|\n');
fprintf(fid, [ ...
    '| `%s` | %+.4f%% | %+.4f%% | `%s` | %+.4f%% | %+.4f%% | ', ...
    '%+.4f%% | %.6f -> %.6f |\n\n'], ...
    mat2str(audit.bestSuspendedFormations), ...
    audit.bestMeanGainPercent, audit.bestWorstGainPercent, ...
    mat2str(audit.bestFormationGainPercent, 5), ...
    audit.bestWindowConsensusGainPercent, ...
    audit.bestTerminalConsensusGainPercent, ...
    audit.bestAttemptedByteSavingPercent, ...
    audit.referenceMeanCardinalityError, ...
    audit.bestMeanCardinalityError);
fprintf(fid, [ ...
    'The best subset passes posterior safety, rolling-B3, worst-sensor, ', ...
    'minimum-formation, window-consensus, and byte-saving gates. It ', ...
    'fails only the frozen mean-gain threshold. This is stronger ', ...
    'mechanism evidence than v28, but it is still a failed gate rather ', ...
    'than a near-pass that can be rounded upward.\n\n']);

fprintf(fid, '## Temporal diagnosis\n\n');
fprintf(fid, [ ...
    '| Time | Reference tracking | Best tracking | Tracking gain | ', ...
    'Reference consensus | Best consensus | Consensus gain |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
for timeIdx = 1:numel(audit.returnTimes)
    fprintf(fid, [ ...
        '| %d | %.6f | %.6f | %+.3f%% | %.6f | %.6f | ', ...
        '%+.3f%% |\n'], audit.returnTimes(timeIdx), ...
        audit.referenceTrackingByTime(timeIdx), ...
        audit.bestTrackingByTime(timeIdx), ...
        audit.trackingGainByTimePercent(timeIdx), ...
        audit.referenceConsensusByTime(timeIdx), ...
        audit.bestConsensusByTime(timeIdx), ...
        audit.consensusGainByTimePercent(timeIdx));
end
fprintf(fid, [ ...
    '\nSuspension produces a large first-step improvement, but two ', ...
    'plain reference-recovery steps do not preserve it: tracking ', ...
    'advantage decays and terminal consensus becomes worse than ', ...
    'reference. Therefore simply extending suspension or treating ', ...
    'reference recovery as automatically safe is not justified.\n\n']);

fprintf(fid, '## Frozen v30 direction\n\n');
fprintf(fid, [ ...
    'The next upper-bound probe should test a **two-phase isolate-and-', ...
    'reconnect controller** on this same opened t=72 state. Phase A ', ...
    'uses the v29 existence-safe suspension bank. Phase B must ', ...
    'recompute a causal recovery route from the then-current posterior ', ...
    'and restore cross-formation information through a compatible ', ...
    'gateway or bounded recovery pulse, rather than blindly returning ', ...
    'to the fixed reference graph. The recovery bank and all safety ', ...
    'gates must be frozen before outcomes are run. A GNN remains ', ...
    'unauthorized until a source-only controller clears the same-state ', ...
    'strong gate and then survives additional opened states.\n\n']);

fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
