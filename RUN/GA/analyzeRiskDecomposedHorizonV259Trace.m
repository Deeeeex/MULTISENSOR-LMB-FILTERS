function [reportPath, analysis] = ...
        analyzeRiskDecomposedHorizonV259Trace(options)
% ANALYZERISKDECOMPOSEDHORIZONV259TRACE Dense offline alignment screen.

if nargin < 1 || isempty(options)
    options = struct();
end
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
defaultRoot = fullfile(repoRoot, 'RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v259', ...
    'risk_decomposed_horizon', 'm24_seed1301_passive_trace');
tracePath = char(getField(options, 'tracePath', fullfile( ...
    defaultRoot, 'RISK_DECOMPOSED_HORIZON_V259_PASSIVE_TRACE.mat')));
reportPath = char(getField(options, 'reportPath', fullfile( ...
    defaultRoot, 'RISK_DECOMPOSED_HORIZON_V259_ALIGNMENT.md')));
if ~isAbsolutePath(tracePath)
    tracePath = fullfile(repoRoot, tracePath);
end
if ~isAbsolutePath(reportPath)
    reportPath = fullfile(repoRoot, reportPath);
end
if exist(tracePath, 'file') ~= 2
    error('RiskDecomposedV259:MissingTrace', ...
        'The completed V259 passive trace is required.');
end
loaded = load(tracePath, 'result', 'behaviorBundle');
if ~isfield(loaded, 'result') || ~isfield(loaded, 'behaviorBundle')
    error('RiskDecomposedV259:MalformedTrace', ...
        'The V259 trace lacks its result or behavior bundle.');
end
result = loaded.result;
bundle = loaded.behaviorBundle;
validateTrace(result, bundle);
screen = buildScreen();

trace = result.riskTrace;
localization = trace.localizationTailRiskByFormation;
support = trace.supportProminenceRiskByFormation;
supportDeficit = max( ...
    trace.relativeNetworkSupportCoverageDeficitByFormation, ...
    trace.relativeActiveLabelCountDeficitByFormation);
formationCount = size(localization, 1);
timeCount = size(localization, 2);
localizationMedian = median(localization, 1);
localizationRatio = localization ./ max(localizationMedian, eps);
localizationGate = localization >= ...
    screen.localizationAbsoluteThreshold & ...
    localizationRatio >= screen.localizationRelativeThreshold;
supportGate = support >= screen.supportProminenceThreshold & ...
    supportDeficit >= screen.supportDeficitThreshold;
localizationChoice = selectOneFormation( ...
    localization, localizationGate);
supportChoice = selectOneFormation(support, supportGate);
localizationPulse = buildPulseSchedule( ...
    localizationChoice, screen.localizationPulsePeriod);

[formationRmse, formationCardinality] = ...
    formationOutcomeSeries(result, bundle.configSnapshot);
[futureRmseTop, futureCardinalityTop] = ...
    futureTailFormation(formationRmse, formationCardinality, ...
        screen.offlineAlignmentHorizon);
localizationChoiceTimes = find(localizationChoice( ...
    1:numel(futureRmseTop)) > 0);
supportChoiceTimes = find(supportChoice( ...
    1:numel(futureCardinalityTop)) > 0);

eventTimes = screen.localizationEventWindow(1): ...
    screen.localizationEventWindow(2);
supportTimes = screen.supportTailWindow(1): ...
    screen.supportTailWindow(2);
eventFormation = screen.localizationEventFormation;
supportFormation = screen.supportTailFormation;
firstEventChoice = find(localizationChoice == eventFormation, 1);
eventChoiceFraction = mean( ...
    localizationChoice(eventTimes) == eventFormation);
eventTopFraction = mean(argmaxByColumn( ...
    localization(:, eventTimes)) == eventFormation);
supportTailChoiceFraction = mean( ...
    supportChoice(supportTimes) == supportFormation);
supportTailTopFraction = mean(argmaxByColumn( ...
    support(:, supportTimes)) == supportFormation);
localizationDutyCycle = nnz(localizationChoice) / timeCount;
supportDutyCycle = nnz(supportChoice) / timeCount;
localizationHorizonTopPrecision = selectedPrecision( ...
    localizationChoice, futureRmseTop, localizationChoiceTimes);
supportHorizonTopPrecision = selectedPrecision( ...
    supportChoice, futureCardinalityTop, supportChoiceTimes);

byteHeadroom = estimatePulseByteHeadroom( ...
    result, bundle, localizationChoice, localizationPulse);
localizationEvidencePassed = isfinite(firstEventChoice) && ...
    firstEventChoice <= screen.localizationEventWindow(1) && ...
    eventChoiceFraction >= screen.minimumEventChoiceFraction && ...
    eventTopFraction >= screen.minimumEventChoiceFraction && ...
    localizationDutyCycle <= screen.maximumLocalizationDutyCycle;
supportEvidencePassed = ...
    supportTailChoiceFraction >= screen.minimumSupportTailFraction && ...
    supportTailTopFraction >= screen.minimumSupportTailFraction && ...
    supportHorizonTopPrecision >= ...
        screen.minimumSupportHorizonTopPrecision;
byteHeadroomPassed = ...
    byteHeadroom.headroomUseFraction <= ...
        screen.maximumPassiveHeadroomUseFraction && ...
    byteHeadroom.projectedStaticSavingPercent > 0;

gitState = resolveResearchGitState();
analysis = struct();
analysis.contractVersion = ...
    'risk-decomposed-horizon-v259-alignment-v1';
analysis.analysisGitCommit = gitState.commit;
analysis.traceGenerationGitCommit = result.generationGitCommit;
analysis.tracePath = tracePath;
analysis.reportPath = reportPath;
analysis.presetName = result.presetName;
analysis.seed = result.seed;
analysis.screen = screen;
analysis.localizationChoiceByTime = localizationChoice;
analysis.supportChoiceByTime = supportChoice;
analysis.localizationPulseByTime = localizationPulse;
analysis.firstLocalizationEventChoice = firstEventChoice;
analysis.localizationEventChoiceFraction = eventChoiceFraction;
analysis.localizationEventTopFraction = eventTopFraction;
analysis.localizationDutyCycle = localizationDutyCycle;
analysis.localizationHorizonTopPrecision = ...
    localizationHorizonTopPrecision;
analysis.supportTailChoiceFraction = supportTailChoiceFraction;
analysis.supportTailTopFraction = supportTailTopFraction;
analysis.supportDutyCycle = supportDutyCycle;
analysis.supportHorizonTopPrecision = supportHorizonTopPrecision;
analysis.byteHeadroom = byteHeadroom;
analysis.localizationEvidencePassed = localizationEvidencePassed;
analysis.supportEvidencePassed = supportEvidencePassed;
analysis.byteHeadroomPassed = byteHeadroomPassed;
analysis.passiveReproductionPassed = ...
    result.passiveComparison.exactOutcomeReproductionPassed;
analysis.actionScreenAuthorized = ...
    analysis.passiveReproductionPassed && ...
    localizationEvidencePassed && supportEvidencePassed && ...
    byteHeadroomPassed;
analysis.nextMethodDecision = ...
    'test-risk-triggered-formation-local-residual-pulses';
analysis.trackingGainEstablished = false;
analysis.validationClaimAllowed = false;
analysis.evidenceBoundary = [ ...
    'This is an outcome-opened development alignment screen. The online ', ...
    'risk traces use current posteriors only, while event alignment and ', ...
    'future H=3 precision use recorded truth offline. Passive pulse bytes ', ...
    'are evaluated on the unchanged V242 posterior trajectory and do not ', ...
    'include recursive payload-size changes. The result authorizes a ', ...
    'bounded causal action screen, not a tracking or generalization claim.'];
writeReport(reportPath, analysis);
fprintf(['V259 alignment: localization/support/bytes %d/%d/%d; ', ...
    'action screen authorized=%d\n'], ...
    analysis.localizationEvidencePassed, ...
    analysis.supportEvidencePassed, analysis.byteHeadroomPassed, ...
    analysis.actionScreenAuthorized);
fprintf('V259 alignment report: %s\n', reportPath);
end

function validateTrace(result, bundle)
requiredResult = {'contractVersion', 'generationGitCommit', ...
    'presetName', 'seed', 'passiveArm', 'passiveComparison', ...
    'riskTrace', 'referenceResultPath'};
requiredBundle = {'cacheContractVersion', 'presetName', 'seed', ...
    'configSnapshot', 'posteriorSnapshots', ...
    'preDecisionTopologyHistoryByTime'};
valid = isstruct(result) && isscalar(result) && ...
    all(isfield(result, requiredResult)) && ...
    strcmp(result.contractVersion, ...
        'risk-decomposed-horizon-v259-passive-trace-result-v1') && ...
    isstruct(bundle) && isscalar(bundle) && ...
    all(isfield(bundle, requiredBundle)) && ...
    strcmp(bundle.presetName, result.presetName) && ...
    bundle.seed == result.seed && ...
    result.passiveComparison.exactOutcomeReproductionPassed && ...
    exist(result.referenceResultPath, 'file') == 2;
if ~valid
    error('RiskDecomposedV259:TraceContract', ...
        'The completed V259 trace contract is invalid.');
end
end

function screen = buildScreen()
screen = struct();
screen.localizationAbsoluteThreshold = 0.25;
screen.localizationRelativeThreshold = 2.50;
screen.supportProminenceThreshold = 0.20;
screen.supportDeficitThreshold = 0.25;
screen.localizationPulsePeriod = 2;
screen.offlineAlignmentHorizon = 3;
screen.localizationEventWindow = [58, 73];
screen.localizationEventFormation = 4;
screen.supportTailWindow = [131, 160];
screen.supportTailFormation = 1;
screen.minimumEventChoiceFraction = 1;
screen.maximumLocalizationDutyCycle = 0.30;
screen.minimumSupportTailFraction = 1;
screen.minimumSupportHorizonTopPrecision = 0.90;
screen.maximumPassiveHeadroomUseFraction = 0.20;
screen.thresholdStatus = ...
    'interpretable-opened-seed-development-thresholds';
end

function choice = selectOneFormation(score, gate)
choice = zeros(1, size(score, 2));
for currentTime = 1:size(score, 2)
    candidates = find(gate(:, currentTime));
    if isempty(candidates)
        continue;
    end
    [~, localIdx] = max(score(candidates, currentTime));
    choice(currentTime) = candidates(localIdx);
end
end

function pulse = buildPulseSchedule(choice, period)
pulse = false(size(choice));
previous = 0;
runLength = 0;
for currentTime = 1:numel(choice)
    if choice(currentTime) == 0
        previous = 0;
        runLength = 0;
        continue;
    end
    if choice(currentTime) ~= previous
        previous = choice(currentTime);
        runLength = 1;
    else
        runLength = runLength + 1;
    end
    pulse(currentTime) = mod(runLength - 1, period) == 0;
end
end

function [rmse, cardinality] = formationOutcomeSeries(result, config)
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
timeCount = size(result.passiveArm.positionRmseBySensorTime, 2);
rmse = nan(numel(groups), timeCount);
cardinality = zeros(numel(groups), timeCount);
for formationIdx = 1:numel(groups)
    members = find(groupIds == groups(formationIdx));
    cardinality(formationIdx, :) = mean( ...
        result.passiveArm.absoluteCardinalityErrorBySensorTime( ...
            members, :), 1);
    for currentTime = 1:timeCount
        rmse(formationIdx, currentTime) = finiteMean( ...
            result.passiveArm.positionRmseBySensorTime( ...
                members, currentTime));
    end
end
end

function [rmseTop, cardinalityTop] = futureTailFormation( ...
        rmse, cardinality, horizon)
outputCount = size(rmse, 2) - horizon + 1;
rmseTop = zeros(1, outputCount);
cardinalityTop = zeros(1, outputCount);
for currentTime = 1:outputCount
    times = currentTime:(currentTime + horizon - 1);
    futureRmse = zeros(1, size(rmse, 1));
    futureCardinality = zeros(1, size(cardinality, 1));
    for formationIdx = 1:size(rmse, 1)
        futureRmse(formationIdx) = finiteMean( ...
            rmse(formationIdx, times));
        futureCardinality(formationIdx) = mean( ...
            cardinality(formationIdx, times));
    end
    [~, rmseTop(currentTime)] = max(futureRmse);
    [~, cardinalityTop(currentTime)] = max(futureCardinality);
end
end

function value = selectedPrecision(choice, target, selectedTimes)
if isempty(selectedTimes)
    value = 0;
else
    value = mean(choice(selectedTimes) == target(selectedTimes));
end
end

function indices = argmaxByColumn(values)
[~, indices] = max(values, [], 1);
end

function headroom = estimatePulseByteHeadroom( ...
        result, bundle, localizationChoice, pulse)
config = bundle.configSnapshot;
[sensorTrajectories, ~] = generateMultiFormationTrajectories(config);
graph = buildDynamicTopologyGraphs(config, sensorTrajectories);
[pDropByEdge, ~] = buildDynamicTopologyLinkSchedule(config, graph);
identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
nodeCount = config.numberOfSensors;
model = struct('xDimension', 4, 'existenceThreshold', 1e-2, ...
    'dynamicTopologyScenario', struct('config', config, ...
        'staticAdjacency', logical(graph.staticAdjacency)));
extraBytesByTime = zeros(1, config.simulationLength);
edgeCountByTime = zeros(1, config.simulationLength);
for currentTime = find(pulse)
    history = bundle.preDecisionTopologyHistoryByTime{currentTime};
    context = struct();
    context.localPosteriorBySensor = ...
        bundle.posteriorSnapshots{currentTime};
    context.model = model;
    context.baseAdjacency = logical(graph.staticAdjacency);
    context.physicalAdjacency = logical( ...
        graph.physicalAdjacency(:, :, currentTime));
    context.positions = graph.positions(:, :, currentTime);
    context.currentTime = currentTime;
    context.commConfig = struct('pDropByEdge', ...
        pDropByEdge(:, :, currentTime));
    context.directedMessageBudget = 2 * nodeCount;
    context.sensorPhysicalUids = identity.sensorPhysicalUids;
    context.formationPhysicalUidsBySensor = ...
        identity.formationPhysicalUidsBySensor;
    context.previousAdjacencyHistory = ...
        convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
            history.selectedDirectedEdgeHistory);
    context.previousAdjacencyHistoryCount = ...
        size(context.previousAdjacencyHistory, 3);
    context.previousAdjacencyHistoryTimes = history.times;
    [~, details] = ...
        selectCausalMinimumFormationBackboneV242Policy(context);
    formationId = localizationChoice(currentTime);
    members = find(config.sensorGroupIds == formationId);
    selected = false(nodeCount);
    selected(members, members) = ...
        details.localResidualAdjacency(members, members);
    senderBytes = zeros(1, nodeCount);
    for sender = 1:nodeCount
        stats = estimateLmbPayloadSize( ...
            bundle.posteriorSnapshots{currentTime}{sender}, ...
            model, 2);
        senderBytes(sender) = stats.estimatedBytes;
    end
    extraBytesByTime(currentTime) = ...
        sum(sum(selected, 1) .* senderBytes);
    edgeCountByTime(currentTime) = nnz(selected);
end
referenceEnvelope = load(result.referenceResultPath, 'result');
reference = referenceEnvelope.result;
fixedBytes = reference.fixedTree.attemptedPayloadBytes;
minimumBytes = result.passiveArm.attemptedPayloadBytes;
availableHeadroom = fixedBytes - minimumBytes;
totalExtraBytes = sum(extraBytesByTime);
eventTimes = 58:73;
headroom = struct();
headroom.pulseTimes = find(pulse);
headroom.pulseFormationByTime = localizationChoice(pulse);
headroom.residualEdgeCountByPulse = edgeCountByTime(pulse);
headroom.extraBytesByTime = extraBytesByTime;
headroom.totalPassiveExtraBytes = totalExtraBytes;
headroom.localizationEventPassiveExtraBytes = ...
    sum(extraBytesByTime(eventTimes));
headroom.fixedAttemptedPayloadBytes = fixedBytes;
headroom.minimumBackboneAttemptedPayloadBytes = minimumBytes;
headroom.availableStaticHeadroomBytes = availableHeadroom;
headroom.headroomUseFraction = ...
    totalExtraBytes / max(availableHeadroom, eps);
headroom.passiveProjectedAttemptedPayloadBytes = ...
    minimumBytes + totalExtraBytes;
headroom.projectedStaticSavingPercent = 100 * ...
    (fixedBytes - headroom.passiveProjectedAttemptedPayloadBytes) / ...
        max(fixedBytes, eps);
headroom.recursivePayloadChangesIncluded = false;
end

function writeReport(path, analysis)
parent = fileparts(path);
if exist(parent, 'dir') ~= 7
    mkdir(parent);
end
fid = fopen(path, 'w');
if fid < 0
    error('RiskDecomposedV259:ReportOpen', ...
        'Unable to write the V259 alignment report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
s = analysis.screen;
b = analysis.byteHeadroom;
fprintf(fid, '# V259 dense risk-alignment result\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    analysis.presetName, analysis.seed);
fprintf(fid, '- Trace commit: `%s`\n', ...
    analysis.traceGenerationGitCommit);
fprintf(fid, '- Passive V242 reproduction: `%d`\n', ...
    analysis.passiveReproductionPassed);
fprintf(fid, '- Localization / support / byte screen: `%d / %d / %d`\n', ...
    analysis.localizationEvidencePassed, ...
    analysis.supportEvidencePassed, analysis.byteHeadroomPassed);
fprintf(fid, '- Bounded causal action screen authorized: `%d`\n\n', ...
    analysis.actionScreenAuthorized);

fprintf(fid, '## Dense alignment\n\n');
fprintf(fid, '| Observable decision | Result |\n');
fprintf(fid, '|:--|:--|\n');
fprintf(fid, ['| Localization entry (`tail >= %.2f`, ', ...
    '`tail / formation-median >= %.1f`) | first selects F%d at ', ...
    '`t=%d`; F%d is selected on `%.0f%%` of `t=%d--%d`; ', ...
    'all-page duty `%.1f%%` |\n'], ...
    s.localizationAbsoluteThreshold, ...
    s.localizationRelativeThreshold, ...
    s.localizationEventFormation, ...
    analysis.firstLocalizationEventChoice, ...
    s.localizationEventFormation, ...
    100 * analysis.localizationEventChoiceFraction, ...
    s.localizationEventWindow(1), s.localizationEventWindow(2), ...
    100 * analysis.localizationDutyCycle);
fprintf(fid, ['| Support entry (`prominence >= %.2f`, ', ...
    '`coverage/count deficit >= %.2f`) | selects F%d on `%.0f%%` ', ...
    'of `t=%d--%d`; agreement with the largest future-H=%d ', ...
    'cardinality-error formation is `%.1f%%` |\n'], ...
    s.supportProminenceThreshold, s.supportDeficitThreshold, ...
    s.supportTailFormation, 100 * analysis.supportTailChoiceFraction, ...
    s.supportTailWindow(1), s.supportTailWindow(2), ...
    s.offlineAlignmentHorizon, ...
    100 * analysis.supportHorizonTopPrecision);
fprintf(fid, ['| Localization diagnostic precision | selected formation ', ...
    'matches the largest future-H=%d RMSE formation on `%.1f%%` of ', ...
    'trigger pages; this is a candidate-generation signal, not an ', ...
    'action-value guarantee |\n\n'], ...
    s.offlineAlignmentHorizon, ...
    100 * analysis.localizationHorizonTopPrecision);

fprintf(fid, '## Passive communication headroom\n\n');
fprintf(fid, '| Quantity | Value |\n');
fprintf(fid, '|:--|--:|\n');
fprintf(fid, '| Strong localization trigger pages | %d / %d |\n', ...
    nnz(analysis.localizationChoiceByTime), ...
    numel(analysis.localizationChoiceByTime));
fprintf(fid, '| Period-%d residual-bundle pulse pages | %d |\n', ...
    s.localizationPulsePeriod, numel(b.pulseTimes));
fprintf(fid, '| Residual edges per pulse | %d--%d |\n', ...
    min(b.residualEdgeCountByPulse), ...
    max(b.residualEdgeCountByPulse));
fprintf(fid, '| F4 event passive incremental bytes | %.0f |\n', ...
    b.localizationEventPassiveExtraBytes);
fprintf(fid, '| Full-trace passive incremental bytes | %.0f |\n', ...
    b.totalPassiveExtraBytes);
fprintf(fid, '| Fraction of V242-to-static byte headroom used | %.3f%% |\n', ...
    100 * b.headroomUseFraction);
fprintf(fid, '| Passive projected saving versus static | %.3f%% |\n\n', ...
    b.projectedStaticSavingPercent);

fprintf(fid, '## Method decision\n\n');
fprintf(fid, ['The risk representation passes the opened-seed action-space ', ...
    'screen. It detects the F4 localization event one page before the ', ...
    'registered interval and keeps F4 first throughout the interval. ', ...
    'The earlier one-edge action is therefore replaced by a formation-', ...
    'level residual bundle pulsed every two pages. This restores four or ', ...
    'five omitted local inputs together, matching the systemic spatial ', ...
    'failure while consuming only a bounded part of the static-route byte ', ...
    'headroom on the passive trajectory.\n\n']);
fprintf(fid, ['Support risk remains a separate zero-message gateway-', ...
    're-embedding action family. It must not be mixed with localization ', ...
    'risk or automatically fired from this report: finite-horizon ', ...
    'mixture-aware value and fallback still decide whether any action is ', ...
    'executed. The next experiment compares a period-2 mass-matched pulse ', ...
    'with a bounded strong pulse from the first causal trigger, reusing ', ...
    'the V242 continuation state.\n\n']);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    analysis.evidenceBoundary);
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    (~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once'))));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
