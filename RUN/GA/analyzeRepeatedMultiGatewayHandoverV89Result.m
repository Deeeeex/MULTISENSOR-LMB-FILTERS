function [reportPath, analysis] = ...
    analyzeRepeatedMultiGatewayHandoverV89Result(resultPath)
% ANALYZEREPEATEDMULTIGATEWAYHANDOVERV89RESULT Mechanism decomposition.

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
if nargin < 1 || isempty(resultPath)
    resultPath = fullfile(repoRoot, 'RUN', 'GA', ...
        'dynamic_topology', 'evidence', 'tracking_aligned_v89', ...
        'multi_gateway_handover_full_episode', ...
        'REPEATED_MULTI_GATEWAY_HANDOVER_V89_FULL_EPISODE.mat');
elseif ~isAbsolutePath(resultPath)
    resultPath = fullfile(repoRoot, resultPath);
end
loaded = load(resultPath, 'result');
if ~isfield(loaded, 'result') || ...
        ~strcmp(loaded.result.contractVersion, ...
            ['repeated-multi-gateway-handover-v89-', ...
             'full-episode-result-v1'])
    error('RepeatedMultiGatewayV89:InvalidAnalysisInput', ...
        'A completed V89 full-episode result is required.');
end
source = loaded.result;
records = repmat(emptyRecord(), 1, numel(source.records));
for recordIdx = 1:numel(source.records)
    records(recordIdx) = analyzeRecord( ...
        source.records(recordIdx), source.protocol);
end

analysis = struct();
analysis.contractVersion = ...
    'repeated-multi-gateway-handover-v89-mechanism-analysis-v1';
analysis.generatedAt = datestr(now, 31);
analysis.sourceResultPath = resultPath;
analysis.sourceGenerationGitCommit = source.generationGitCommit;
analysis.records = records;
analysis.bothScalesStrongGatePassed = ...
    source.bothScalesStrongGatePassed;
analysis.developmentEvidenceOnly = true;
analysis.validationClaimAllowed = false;
outputRoot = fileparts(resultPath);
matPath = fullfile(outputRoot, ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_MECHANISM_ANALYSIS.mat');
reportPath = fullfile(outputRoot, ...
    'REPEATED_MULTI_GATEWAY_HANDOVER_V89_MECHANISM_ANALYSIS.md');
analysis.matPath = matPath;
analysis.reportPath = reportPath;
save('-mat7-binary', matPath, 'analysis');
writeReport(reportPath, analysis);
fprintf('V89 mechanism analysis: %s\n', reportPath);
end

function output = analyzeRecord(record, protocol)
reference = record.reference;
candidate = record.candidate;
timeCount = numel(candidate.phaseByTime);
focusMask = false(1, timeCount);
focusMask(protocol.activationStartTime:min( ...
    protocol.activationEndTime, timeCount)) = true;
gatewayCounts = candidate.selectedGatewayCountByTime;
executedAcquire = focusMask & ...
    strcmp(candidate.phaseByTime, 'acquire') & gatewayCounts > 0;
executedBroadcast = focusMask & ...
    strcmp(candidate.phaseByTime, 'broadcast') & gatewayCounts > 0;
previousBroadcastExecuted = [false, ...
    strcmp(candidate.phaseByTime(1:end-1), 'broadcast') & ...
        gatewayCounts(1:end-1) > 0];
postBroadcastRecovery = focusMask & ...
    strcmp(candidate.phaseByTime, 'reference') & ...
    previousBroadcastExecuted;
phaseNames = {'acquire', 'broadcast', 'reference'};
phaseMasks = {executedAcquire, executedBroadcast, ...
    postBroadcastRecovery};
phase = struct();
for phaseIdx = 1:numel(phaseNames)
    name = phaseNames{phaseIdx};
    phase.(name) = summarizeMask( ...
        phaseMasks{phaseIdx}, reference, candidate);
end

levels = unique(gatewayCounts(focusMask));
intensity = repmat(emptyIntensity(), 1, numel(levels));
for levelIdx = 1:numel(levels)
    level = levels(levelIdx);
    intensity(levelIdx) = summarizeMask( ...
        focusMask & gatewayCounts == level, reference, candidate);
    intensity(levelIdx).gatewayCount = level;
end

eospaDelta = reference.networkMeanPositionEospaByTime - ...
    candidate.networkMeanPositionEospaByTime;
focusTimes = find(focusMask);
[~, helpfulOrder] = sort(eospaDelta(focusTimes), 'descend');
[~, harmfulOrder] = sort(eospaDelta(focusTimes), 'ascend');
count = min(5, numel(focusTimes));
helpfulTimes = focusTimes(helpfulOrder(1:count));
harmfulTimes = focusTimes(harmfulOrder(1:count));

sensorGain = elementwisePercentImprovement( ...
    reference.perSensorPositionEospa, ...
    candidate.perSensorPositionEospa);
[~, worstSensorOrder] = sort(sensorGain, 'ascend');
worstSensorCount = min(5, numel(sensorGain));

executedSequenceMask = executedAcquire | executedBroadcast | ...
    postBroadcastRecovery;
inactiveMask = focusMask & ~executedSequenceMask;
output = emptyRecord();
output.presetName = record.presetName;
output.seed = record.seed;
output.fullGainPercent = ...
    record.improvement.fullHorizonMeanGainPercent;
output.focusGainPercent = ...
    record.improvement.focusWindowMeanGainPercent;
output.worstSensorGainPercent = ...
    record.improvement.worstSensorGainPercent;
output.minimumFormationGainPercent = ...
    record.improvement.minimumFormationGainPercent;
output.focusConsensusGainPercent = ...
    record.improvement.focusConsensusGainPercent;
output.strongGatePassed = record.improvement.strongGatePassed;
output.phase = phase;
output.intensity = intensity;
output.activeAction = summarizeMask( ...
    executedSequenceMask, reference, candidate);
output.noAction = summarizeMask( ...
    inactiveMask, reference, candidate);
output.helpfulTimes = makeTimeRecords( ...
    helpfulTimes, reference, candidate);
output.harmfulTimes = makeTimeRecords( ...
    harmfulTimes, reference, candidate);
output.perSensorGainPercent = sensorGain;
output.worstSensorIndices = ...
    reshape(worstSensorOrder(1:worstSensorCount), 1, []);
output.worstSensorGainsPercent = ...
    sensorGain(output.worstSensorIndices);
output.formationGainPercent = ...
    record.improvement.formationGainPercent;
output.mechanismFinding = inferMechanismFinding(output);
end

function summary = summarizeMask(mask, reference, candidate)
summary = emptyIntensity();
summary.timeCount = nnz(mask);
if ~any(mask)
    return;
end
summary.positionGainPercent = percentImprovement( ...
    mean(reference.networkMeanPositionEospaByTime(mask)), ...
    mean(candidate.networkMeanPositionEospaByTime(mask)));
summary.cardinalityGainPercent = percentImprovement( ...
    mean(reference.networkMeanAbsoluteCardinalityErrorByTime(mask)), ...
    mean(candidate.networkMeanAbsoluteCardinalityErrorByTime(mask)));
summary.consensusGainPercent = percentImprovement( ...
    mean(reference.interFormationPositionOspaByTime(mask)), ...
    mean(candidate.interFormationPositionOspaByTime(mask)));
summary.meanReferenceEospa = mean( ...
    reference.networkMeanPositionEospaByTime(mask));
summary.meanCandidateEospa = mean( ...
    candidate.networkMeanPositionEospaByTime(mask));
end

function records = makeTimeRecords(times, reference, candidate)
records = repmat(emptyTimeRecord(), 1, numel(times));
for timeIdx = 1:numel(times)
    currentTime = times(timeIdx);
    records(timeIdx) = struct( ...
        'currentTime', currentTime, ...
        'phase', candidate.phaseByTime{currentTime}, ...
        'gatewayCount', ...
            candidate.selectedGatewayCountByTime(currentTime), ...
        'referenceEospa', ...
            reference.networkMeanPositionEospaByTime(currentTime), ...
        'candidateEospa', ...
            candidate.networkMeanPositionEospaByTime(currentTime), ...
        'eospaDelta', ...
            reference.networkMeanPositionEospaByTime(currentTime) - ...
            candidate.networkMeanPositionEospaByTime(currentTime), ...
        'cardinalityDelta', ...
            reference.networkMeanAbsoluteCardinalityErrorByTime( ...
                currentTime) - ...
            candidate.networkMeanAbsoluteCardinalityErrorByTime( ...
                currentTime), ...
        'consensusDelta', ...
            reference.interFormationPositionOspaByTime(currentTime) - ...
            candidate.interFormationPositionOspaByTime(currentTime));
end
end

function finding = inferMechanismFinding(record)
acquire = record.phase.acquire.positionGainPercent;
broadcast = record.phase.broadcast.positionGainPercent;
recovery = record.phase.reference.positionGainPercent;
if record.strongGatePassed
    finding = ['The repeated transport mechanism passes the frozen ', ...
        'tracking and safety gate on this scale.'];
elseif all(abs([acquire, broadcast, recovery]) < 1)
    finding = ['All three phases are near neutral; current novelty ', ...
        'identifies transferable information but not enough task headroom ', ...
        'over the physical-tree reference.'];
elseif acquire >= 0 && broadcast < 0
    finding = ['Acquisition is non-harmful but full-formation broadcast ', ...
        'is harmful; the next method decision is broadcast trust/content, ', ...
        'not source discovery.'];
elseif acquire >= 0 && broadcast >= 0 && recovery < 0
    finding = ['Acquire and broadcast are non-harmful but the reference ', ...
        'round loses the benefit; the next method decision is temporal ', ...
        'retention rather than a new source proxy.'];
elseif acquire < 0
    finding = ['Harm begins at acquisition; current unique detection ', ...
        'support is not a sufficient task-value criterion.'];
else
    finding = ['The aggregate gate fails with mixed phase signs; inspect ', ...
        'the listed harmful times and sensor/formation tails before ', ...
        'changing the policy.'];
end
end

function writeReport(path, analysis)
fid = fopen(path, 'w');
if fid < 0
    error('RepeatedMultiGatewayV89:AnalysisWriteFailed', ...
        'Could not create the V89 mechanism report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V89 repeated multi-gateway mechanism analysis\n\n');
fprintf(fid, ['Positive percentages mean the candidate is better. ', ...
    'All phase summaries use the frozen t=40--140 focus window.\n\n']);
fprintf(fid, ['| Scale | Full | Focus | Worst sensor | Minimum formation | ', ...
    'Focus consensus | Strong |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|:--:|\n');
for record = analysis.records
    fprintf(fid, '| %s | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n', ...
        record.presetName, record.fullGainPercent, ...
        record.focusGainPercent, record.worstSensorGainPercent, ...
        record.minimumFormationGainPercent, ...
        record.focusConsensusGainPercent, record.strongGatePassed);
end

fprintf(fid, '\n## Phase decomposition\n\n');
fprintf(fid, ['| Scale | Metric | Acquire | Broadcast | ', ...
    'Reference recovery |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|\n');
for record = analysis.records
    writePhaseCountRow(fid, record);
    writePhaseRow(fid, record, 'Position E-OSPA', ...
        'positionGainPercent');
    writePhaseRow(fid, record, 'Cardinality', ...
        'cardinalityGainPercent');
    writePhaseRow(fid, record, 'Consensus', ...
        'consensusGainPercent');
end

for record = analysis.records
    fprintf(fid, '\n## %s\n\n', record.presetName);
    fprintf(fid, '%s\n\n', record.mechanismFinding);
    fprintf(fid, ['Executed acquire--broadcast--recovery sequence gain: ', ...
        '`%+.3f%%`; other focus times: `%+.3f%%`.\n\n'], ...
        record.activeAction.positionGainPercent, ...
        record.noAction.positionGainPercent);
    fprintf(fid, '| Gateways | Times | Position | Cardinality | Consensus |\n');
    fprintf(fid, '|--:|--:|--:|--:|--:|\n');
    for row = record.intensity
        fprintf(fid, '| %d | %d | %+.3f%% | %+.3f%% | %+.3f%% |\n', ...
            row.gatewayCount, row.timeCount, ...
            row.positionGainPercent, row.cardinalityGainPercent, ...
            row.consensusGainPercent);
    end
    fprintf(fid, '\nWorst sensors: `%s`, gains `%s%%`.\n\n', ...
        mat2str(record.worstSensorIndices), ...
        mat2str(record.worstSensorGainsPercent, 4));
    fprintf(fid, 'Formation gains: `%s%%`.\n\n', ...
        mat2str(record.formationGainPercent, 4));
    writeTimeTable(fid, 'Most helpful times', record.helpfulTimes);
    writeTimeTable(fid, 'Most harmful times', record.harmfulTimes);
end
fprintf(fid, ['\nDevelopment evidence only. Phase association describes ', ...
    'where paired errors appear; it is not a validation or causal ', ...
    'identification claim beyond the frozen paired execution.\n']);
end

function writePhaseCountRow(fid, record)
fprintf(fid, '| %s | Executed times | %d | %d | %d |\n', ...
    record.presetName, record.phase.acquire.timeCount, ...
    record.phase.broadcast.timeCount, ...
    record.phase.reference.timeCount);
end

function writePhaseRow(fid, record, metricName, fieldName)
fprintf(fid, '| %s | %s | %+.3f%% | %+.3f%% | %+.3f%% |\n', ...
    record.presetName, metricName, ...
    record.phase.acquire.(fieldName), ...
    record.phase.broadcast.(fieldName), ...
    record.phase.reference.(fieldName));
end

function writeTimeTable(fid, title, records)
fprintf(fid, '### %s\n\n', title);
fprintf(fid, ['| Time | Phase | Gateways | Reference | Candidate | ', ...
    'E-OSPA delta | Card. delta | Consensus delta |\n']);
fprintf(fid, '|--:|:--|--:|--:|--:|--:|--:|--:|\n');
for record = records
    fprintf(fid, '| %d | %s | %d | %.3f | %.3f | %+.3f | %+.3f | %+.3f |\n', ...
        record.currentTime, record.phase, record.gatewayCount, ...
        record.referenceEospa, record.candidateEospa, ...
        record.eospaDelta, record.cardinalityDelta, ...
        record.consensusDelta);
end
fprintf(fid, '\n');
end

function value = percentImprovement(reference, candidate)
if reference == 0
    value = 0;
    if candidate > 0
        value = -Inf;
    end
else
    value = 100 * (reference - candidate) / reference;
end
end

function values = elementwisePercentImprovement(reference, candidate)
values = zeros(size(reference));
zero = reference == 0;
values(~zero) = 100 * (reference(~zero) - candidate(~zero)) ./ ...
    reference(~zero);
values(zero & candidate > 0) = -Inf;
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'fullGainPercent', NaN, ...
    'focusGainPercent', NaN, ...
    'worstSensorGainPercent', NaN, ...
    'minimumFormationGainPercent', NaN, ...
    'focusConsensusGainPercent', NaN, ...
    'strongGatePassed', false, ...
    'phase', struct(), ...
    'intensity', repmat(emptyIntensity(), 1, 0), ...
    'activeAction', emptyIntensity(), ...
    'noAction', emptyIntensity(), ...
    'helpfulTimes', repmat(emptyTimeRecord(), 1, 0), ...
    'harmfulTimes', repmat(emptyTimeRecord(), 1, 0), ...
    'perSensorGainPercent', zeros(1, 0), ...
    'worstSensorIndices', zeros(1, 0), ...
    'worstSensorGainsPercent', zeros(1, 0), ...
    'formationGainPercent', zeros(1, 0), ...
    'mechanismFinding', '');
end

function record = emptyIntensity()
record = struct( ...
    'gatewayCount', NaN, ...
    'timeCount', 0, ...
    'positionGainPercent', NaN, ...
    'cardinalityGainPercent', NaN, ...
    'consensusGainPercent', NaN, ...
    'meanReferenceEospa', NaN, ...
    'meanCandidateEospa', NaN);
end

function record = emptyTimeRecord()
record = struct( ...
    'currentTime', NaN, ...
    'phase', '', ...
    'gatewayCount', 0, ...
    'referenceEospa', NaN, ...
    'candidateEospa', NaN, ...
    'eospaDelta', NaN, ...
    'cardinalityDelta', NaN, ...
    'consensusDelta', NaN);
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && path(1) == filesep;
end
