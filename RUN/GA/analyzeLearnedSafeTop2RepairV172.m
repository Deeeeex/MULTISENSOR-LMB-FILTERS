function [reportPath, summary] = ...
        analyzeLearnedSafeTop2RepairV172(options)
% ANALYZELEARNEDSAFETOP2REPAIRV172 Replay compact learned F5 Top-2.
%
% V172 keeps the already-opened V163 analytic F3 repair, but replaces its
% harmful F5 analytic Top-4 with the compact V170 safety classifier. The
% two highest-confidence unique labels are applied jointly before truth
% scoring, so the screen directly tests the interaction ignored by V166's
% single-action targets. This is nonrecursive development evidence.

if nargin < 1 || isempty(options)
    options = struct();
end
v157 = getPositiveValueReferenceLabelV157Protocol();
v162 = getObservableOneHopRiskLabelV162Protocol();
snapshotScreenPath = getField(options, 'snapshotScreenPath', fullfile( ...
    v157.headroomOutputRoot, 'x36_t72_h8', 'screen', ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']));
v162ResultPath = getField(options, 'v162ResultPath', fullfile( ...
    v162.headroomOutputRoot, 'x36_t72_h8', ...
    [v162.resultFileStem, '.mat']));
v163SummaryPath = getField(options, 'v163SummaryPath', fullfile( ...
    v162.headroomOutputRoot, 'rmse_repair_preflight', ...
    'OBSERVABLE_ONE_HOP_RMSE_REPAIR_V163_PREFLIGHT.mat'));
modelPath = getField(options, 'modelPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v170', 'cost_aware_feature_profile', ...
    'compact_scalar', ...
    'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_MODEL.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v172', 'learned_safe_top2_repair'));
synopsisBytesPerLabel = getField(options, ...
    'synopsisBytesPerLabel', 24);
maximumEdits = getField(options, 'maximumEdits', 2);
if exist(snapshotScreenPath, 'file') ~= 2 || ...
        exist(v162ResultPath, 'file') ~= 2 || ...
        exist(v163SummaryPath, 'file') ~= 2 || ...
        exist(modelPath, 'file') ~= 2 || ...
        synopsisBytesPerLabel < 0 || ...
        mod(synopsisBytesPerLabel, 8) ~= 0 || maximumEdits ~= 2
    error('LearnedSafeTop2V172:InvalidInputs', ...
        'The V172 registered inputs are missing or invalid.');
end

snapshotLoaded = load(snapshotScreenPath, 'screen');
v162Loaded = load(v162ResultPath, 'result');
v163Loaded = load(v163SummaryPath, 'summary');
snapshotScreen = snapshotLoaded.screen;
v162Result = v162Loaded.result;
v163Summary = v163Loaded.summary;
snapshotOutcome = outcomeByAction(snapshotScreen, ...
    v157.candidateActionName);
inputs = generateDynamicTopologyScenarioInputs( ...
    snapshotScreen.presetName, snapshotScreen.seed);
model = inputs.model;
model.dynamicTopologyScenario.targetTrajectories = ...
    inputs.targetTrajectories;
groupIds = reshape(snapshotScreen.sensorGroupIds, 1, []);
nodeCount = numel(groupIds);
repairTimes = [78, 79];
rows = repmat(emptyRow(), 1, 0);
for currentTime = repairTimes
    pageIdx = find(snapshotScreen.returnTimes == currentTime, 1);
    physical = logical(inputs.graphData. ...
        physicalAdjacency(:, :, currentTime));
    physical = physical | physical';
    physical(1:nodeCount+1:end) = false;
    receiverIds = find(groupIds == 5);
    for receiverIdx = reshape(receiverIds, 1, [])
        config = selectorConfig( ...
            v162, modelPath, currentTime, receiverIdx, ...
            maximumEdits, synopsisBytesPerLabel);
        baseline = snapshotOutcome. ...
            fusedPosteriorSnapshotsByTime{pageIdx}{receiverIdx};
        locals = snapshotOutcome. ...
            localPosteriorSnapshotsByTime{pageIdx};
        [trial, details] = selectObservableOneHopRiskLabels( ...
            baseline, locals, physical, physical, config, ...
            receiverIdx, currentTime, model);
        row = emptyRow();
        row.page = pageIdx;
        row.time = currentTime;
        row.formation = 5;
        row.receiver = receiverIdx;
        row.selectedLabelCount = details.selectedLabelCount;
        row.appliedLabelCount = details.appliedLabelCount;
        row.selectedLabels = details.selectedLabels;
        row.selectedSources = details.selectedSources;
        row.minimumSafetyScore = min(details.selectedSafetyScore);
        row.attemptedBytes = details.attemptedTotalBytes;
        row.eospaGain = evaluateLmbTopologyCurrentEospa( ...
            baseline, model, currentTime, struct()) - ...
            evaluateLmbTopologyCurrentEospa( ...
                trial, model, currentTime, struct());
        row.rmseGain = currentPosteriorRmse( ...
            baseline, model, currentTime) - ...
            currentPosteriorRmse(trial, model, currentTime);
        rows(end + 1) = row; %#ok<AGROW>
        fprintf(['V172 F5 compact Top-2 t=%d sensor=%d: ', ...
            'E=%+.6f R=%+.6f bytes=%d\n'], ...
            currentTime, receiverIdx, row.eospaGain, ...
            row.rmseGain, row.attemptedBytes);
    end
end

f3Rows = v163Summary.rows([v163Summary.rows.formation] == 3);
f3EospaGain = sum([f3Rows.eospaGain]);
f3RmseGain = sum([f3Rows.rmseGain]);
f3AttemptedBytes = sum([f3Rows.attemptedBytes]);
f5EospaGain = sum([rows.eospaGain]);
f5RmseGain = sum([rows.rmseGain]);
f5AttemptedBytes = sum([rows.attemptedBytes]);
projectedFormationMeanRmse = v162Result.candidateFormationMeanRmse;
groups = unique(groupIds, 'stable');
f3Idx = find(groups == 3, 1);
f5Idx = find(groups == 5, 1);
windowCount = numel(snapshotScreen.returnTimes);
projectedFormationMeanRmse(f3Idx) = ...
    projectedFormationMeanRmse(f3Idx) - ...
    f3RmseGain / (nnz(groupIds == 3) * windowCount);
projectedFormationMeanRmse(f5Idx) = ...
    projectedFormationMeanRmse(f5Idx) - ...
    f5RmseGain / (nnz(groupIds == 5) * windowCount);
projectedFormationRmseGainPercent = 100 * ( ...
    v162Result.referenceFormationMeanRmse - ...
    projectedFormationMeanRmse) ./ ...
    max(abs(v162Result.referenceFormationMeanRmse), eps);
totalAdditionalAttemptedBytes = ...
    f3AttemptedBytes + f5AttemptedBytes;
projectedByteSavingPercent = 100 * ( ...
    v162Result.referenceAttemptedBytes - ...
    (v162Result.candidateMainPathAttemptedBytes + ...
        totalAdditionalAttemptedBytes)) / ...
    max(abs(v162Result.referenceAttemptedBytes), eps);
gatePassed = all([rows.eospaGain] > 0) && ...
    all([rows.rmseGain] > 0) && ...
    all([rows.selectedLabelCount] == maximumEdits) && ...
    all(projectedFormationRmseGainPercent >= -1e-12) && ...
    projectedByteSavingPercent >= -1e-12;

summary = struct();
summary.contractVersion = ...
    'learned-safe-top2-repair-v172-preflight-v1';
summary.presetName = snapshotScreen.presetName;
summary.seed = snapshotScreen.seed;
summary.modelPath = modelPath;
summary.featureProfile = ...
    'compact-scalar-20-byte-model-with-24-byte-packed-synopsis';
summary.maximumEdits = maximumEdits;
summary.repairTimes = repairTimes;
summary.rows = rows;
summary.f3AnalyticEospaGain = f3EospaGain;
summary.f3AnalyticRmseGain = f3RmseGain;
summary.f3AnalyticAttemptedBytes = f3AttemptedBytes;
summary.f5LearnedEospaGain = f5EospaGain;
summary.f5LearnedRmseGain = f5RmseGain;
summary.f5LearnedAttemptedBytes = f5AttemptedBytes;
summary.totalAdditionalAttemptedBytes = totalAdditionalAttemptedBytes;
summary.projectedFormationMeanRmse = projectedFormationMeanRmse;
summary.projectedFormationRmseGainPercent = ...
    projectedFormationRmseGainPercent;
summary.projectedByteSavingPercent = projectedByteSavingPercent;
summary.gatePassed = gatePassed;
summary.truthUsedBySelector = false;
summary.truthUsedForEvaluation = true;
summary.recursiveEvaluationRun = false;
summary.evidenceBoundary = [ ...
    'V172 is an opened, nonrecursive interaction and communication ', ...
    'screen. It reuses the V163 analytic F3 snapshot gains and applies ', ...
    'the frozen compact V170 classifier to two complete labels jointly ', ...
    'at the twelve opened F5 receiver-time cells. Current truth scores ', ...
    'the combined action but is not an inference feature. The 24-byte ', ...
    'per-label synopsis is a packed, quantized implementation budget; ', ...
    'its numerical quantization error is not yet validated. Projected ', ...
    'metrics add snapshot deltas to V162 and only authorize an actual ', ...
    'recursive V169 run.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'LEARNED_SAFE_TOP2_REPAIR_V172_PREFLIGHT.mat');
reportPath = fullfile(outputRoot, ...
    'LEARNED_SAFE_TOP2_REPAIR_V172_PREFLIGHT.md');
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary);
fprintf('V172 learned safe Top-2 preflight: %s\n', reportPath);
end

function config = selectorConfig( ...
        protocol, modelPath, currentTime, receiverIdx, ...
        maximumEdits, synopsisBytesPerLabel)
config = struct( ...
    'observableOneHopRiskLabelEnabled', true, ...
    'observableOneHopRiskLabelTimes', currentTime, ...
    'observableOneHopRiskLabelSensorIdsByTime', {{[]}}, ...
    'observableOneHopRiskLabelMaximumEdits', protocol.maximumLabelEdits, ...
    'observableOneHopRiskLabelExistenceThreshold', ...
        protocol.activeExistenceThreshold, ...
    'observableOneHopRiskLabelMinimumRiskReduction', ...
        protocol.minimumRiskReduction, ...
    'observableOneHopRiskLabelSynopsisHeaderBytes', ...
        protocol.synopsisHeaderBytes, ...
    'observableOneHopRiskLabelSynopsisBytesPerLabel', ...
        protocol.synopsisBytesPerLabel, ...
    'observableOneHopRiskLabelRequestHeaderBytes', ...
        protocol.requestHeaderBytes, ...
    'observableOneHopRiskLabelRequestBytesPerLabel', ...
        protocol.requestBytesPerLabel, ...
    'learnedOneHopSafeLabelEnabled', true, ...
    'learnedOneHopSafeLabelTimes', currentTime, ...
    'learnedOneHopSafeLabelSensorIdsByTime', {{receiverIdx}}, ...
    'learnedOneHopSafeLabelModelPath', modelPath, ...
    'learnedOneHopSafeLabelMaximumEdits', maximumEdits, ...
    'learnedOneHopSafeLabelSynopsisHeaderBytes', 16, ...
    'learnedOneHopSafeLabelSynopsisBytesPerLabel', ...
        synopsisBytesPerLabel, ...
    'learnedOneHopSafeLabelRequestHeaderBytes', 16, ...
    'learnedOneHopSafeLabelRequestBytesPerLabel', 16);
end

function value = currentPosteriorRmse(posterior, model, currentTime)
objects = reshape(posterior, 1, []);
if ~isempty(objects)
    objects = objects([objects.r] > model.existenceThreshold);
end
estimate = zeros(2, 0);
if ~isempty(objects)
    [mapCardinality, mapIndices] = ...
        lmbMapCardinalityEstimate([objects.r]);
    estimate = zeros(2, mapCardinality);
    for mapIdx = 1:mapCardinality
        object = objects(mapIndices(mapIdx));
        weights = reshape(object.w, 1, []);
        weights(~isfinite(weights)) = -inf;
        [~, componentIdx] = max(weights);
        if isempty(componentIdx) || ~isfinite(weights(componentIdx))
            componentIdx = 1;
        end
        estimate(:, mapIdx) = object.mu{componentIdx}(1:2);
    end
end
truth = zeros(2, 0);
trajectories = model.dynamicTopologyScenario.targetTrajectories;
for targetIdx = 1:numel(trajectories)
    if currentTime <= size(trajectories{targetIdx}, 2)
        state = trajectories{targetIdx}(:, currentTime);
        if all(isfinite(state))
            truth(:, end + 1) = state(1:2); %#ok<AGROW>
        end
    end
end
if isempty(truth) || isempty(estimate)
    value = NaN;
    return;
end
distances = zeros(size(truth, 2), size(estimate, 2));
for truthIdx = 1:size(truth, 2)
    delta = bsxfun(@minus, estimate, truth(:, truthIdx));
    distances(truthIdx, :) = sqrt(sum(delta .^ 2, 1));
end
[matching, ~] = Hungarian(distances);
matched = distances(matching == 1);
if isempty(matched)
    value = NaN;
else
    value = sqrt(mean(matched .^ 2));
end
end

function outcome = outcomeByAction(screen, actionName)
idx = find(strcmp({screen.records.actionName}, actionName), 1);
if isempty(idx)
    error('LearnedSafeTop2V172:MissingAction', ...
        'The requested action is missing: %s', actionName);
end
outcome = screen.outcomes(idx);
end

function row = emptyRow()
row = struct( ...
    'page', 0, 'time', 0, 'formation', 0, 'receiver', 0, ...
    'selectedLabelCount', 0, 'appliedLabelCount', 0, ...
    'selectedLabels', zeros(2, 0), ...
    'selectedSources', zeros(1, 0), ...
    'minimumSafetyScore', NaN, 'attemptedBytes', 0, ...
    'eospaGain', NaN, 'rmseGain', NaN);
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('LearnedSafeTop2V172:ReportOpenFailed', ...
        'Could not open the V172 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V172 compact learned F5 Top-2 interaction screen\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    summary.presetName, summary.seed);
fprintf(fid, '- Feature / edit budget: `%s / %d`\n', ...
    summary.featureProfile, summary.maximumEdits);
fprintf(fid, '- Repair times: `%s`\n\n', ...
    mat2str(summary.repairTimes));
fprintf(fid, ['| t | Receiver | Labels | Min safety | ', ...
    'E-OSPA gain | RMSE gain | Bytes |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
for row = summary.rows
    fprintf(fid, '| %d | %d | %d | %.4f | %+.6f | %+.6f | %d |\n', ...
        row.time, row.receiver, row.selectedLabelCount, ...
        row.minimumSafetyScore, row.eospaGain, row.rmseGain, ...
        row.attemptedBytes);
end
fprintf(fid, '\n- F3 analytic E-OSPA / RMSE gain: `%.6f / %.6f`\n', ...
    summary.f3AnalyticEospaGain, summary.f3AnalyticRmseGain);
fprintf(fid, '- F5 learned E-OSPA / RMSE gain: `%.6f / %.6f`\n', ...
    summary.f5LearnedEospaGain, summary.f5LearnedRmseGain);
fprintf(fid, '- Additional attempted bytes: `%d`\n', ...
    summary.totalAdditionalAttemptedBytes);
fprintf(fid, '- Projected byte saving: `%+.3f%%`\n', ...
    summary.projectedByteSavingPercent);
fprintf(fid, '- Projected formation RMSE gain: `%s%%`\n', ...
    mat2str(summary.projectedFormationRmseGainPercent, 5));
fprintf(fid, '- Preflight gate passed: `%d`\n', summary.gatePassed);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
