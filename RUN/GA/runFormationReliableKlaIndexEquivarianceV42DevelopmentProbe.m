function [commit, dirty] = resolveGitState(repoRoot)
environmentName = 'FORMATION_V42_INTERNAL_GIT_ROOT';
previousValue = getenv(environmentName);
cleanup = onCleanup(@() setenv(environmentName, previousValue)); %#ok<NASGU>
setenv(environmentName, repoRoot);
[status, topLevel] = system([ ...
    'git -C "$FORMATION_V42_INTERNAL_GIT_ROOT" ', ...
    'rev-parse --show-toplevel']);
if status ~= 0 || ~strcmp(strtrim(topLevel), repoRoot)
    error('FormationKlaIndexEquivarianceRunner:GitStateUnavailable', ...
        'Git did not resolve to the v42 runner worktree.');
end
[status, commit] = system([ ...
    'git -C "$FORMATION_V42_INTERNAL_GIT_ROOT" rev-parse HEAD']);
if status ~= 0
    error('FormationKlaIndexEquivarianceRunner:GitStateUnavailable', ...
        'The generation commit could not be resolved.');
end
commit = strtrim(commit);
[status, porcelain] = system([ ...
    'git -C "$FORMATION_V42_INTERNAL_GIT_ROOT" status --porcelain']);
if status ~= 0
    error('FormationKlaIndexEquivarianceRunner:GitStateUnavailable', ...
        'The generation worktree state could not be resolved.');
end
dirty = ~isempty(strtrim(porcelain));
end

function caseIds = buildCartesianCaseIds(presets, seeds)
caseIds = cell(1, numel(presets) * numel(seeds));
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        caseIds{cursor} = sprintf('%s__seed%d', ...
            presets{presetIdx}, seeds(seedIdx));
    end
end
end

function validateInputs(outputDirectory, presets, seeds, ...
        requireCleanGit, protocol)
if ~(ischar(outputDirectory) && ~isempty(outputDirectory)) || ...
        ~iscell(presets) || isempty(presets) || ...
        any(~cellfun(@ischar, presets)) || ...
        numel(unique(presets)) ~= numel(presets) || ...
        any(~ismember(presets, protocol.registeredPresets)) || ...
        ~isnumeric(seeds) || ~isreal(seeds) || isempty(seeds) || ...
        any(~isfinite(seeds)) || any(seeds ~= round(seeds)) || ...
        numel(unique(seeds)) ~= numel(seeds) || ...
        any(~ismember(seeds, protocol.registeredSeeds)) || ...
        ~isscalar(requireCleanGit)
    error('FormationKlaIndexEquivarianceRunner:InvalidOptions', ...
        'The v42 development-run inputs are invalid.');
end
end

