        current.referenceRouteUniqueCount, ...
        current.referenceWeightMaxAbsoluteDifference, ...
        current.referenceFactorMaxAbsoluteDifference, ...
        numericVectorText( ...
            current.bestCandidatePhysicalFormationIdsByShift), ...
        numericVectorText( ...
            current.bestCandidateOrderPositionsByShift), ...
        min(current.bestCandidateDeltasByShift), ...
        max(current.bestCandidateDeltasByShift), ...
        current.bestCandidatePattern, current.primaryFailureLayer);
