function result = ...
    runFormationReliableKlaIndexEquivarianceV42DevelopmentProbe( ...
        outputDirectory, options)
% RUNFORMATIONRELIABLEKLAINDEXEQUIVARIANCEV42DEVELOPMENTPROBE
% Audit complete formation-block/node-coordinate ordering effects.

repoRoot = resolveRunnerRepoRoot();
if nargin < 1 || isempty(outputDirectory)
    outputDirectory = fullfile(repoRoot, 'RUN', 'GA', 'dynamic_topology', ...
        'evidence', 'formation_value_v42', ...
        'index_equivariance_development_v1');
elseif ischar(outputDirectory) && ~isempty(outputDirectory) && ...
        outputDirectory(1) ~= filesep
    outputDirectory = fullfile(repoRoot, outputDirectory);
end
if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = {'presets', 'seeds', 'requireCleanGit'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationKlaIndexEquivarianceRunner:InvalidOptions', ...
        'The v42 development-run options are malformed.');
end
protocol = getFormationReliableKlaIndexEquivarianceV42Protocol();
executableSourceManifest = buildExecutableSourceManifest(repoRoot);
presets = getField(options, 'presets', protocol.registeredPresets);
seeds = reshape(getField(options, ...
    'seeds', protocol.registeredSeeds), 1, []);
requireCleanGit = logical(getField(options, 'requireCleanGit', true));
validateInputs(outputDirectory, presets, seeds, requireCleanGit, protocol);

matPath = fullfile(outputDirectory, ...
    'FORMATION_RELIABLE_KLA_INDEX_EQUIVARIANCE_V42_DEVELOPMENT_V1.mat');
reportPath = fullfile(outputDirectory, ...
    'FORMATION_RELIABLE_KLA_INDEX_EQUIVARIANCE_V42_DEVELOPMENT_V1.md');
if exist(matPath, 'file') || exist(reportPath, 'file')
    error('FormationKlaIndexEquivarianceRunner:OutputExists', ...
        'The v42 development output is non-overwriting.');
end
if ~exist(outputDirectory, 'dir')
    [created, message] = mkdir(outputDirectory);
    if ~created
        error('FormationKlaIndexEquivarianceRunner:OutputCreateFailed', ...
            'The output directory could not be created: %s', message);
    end
end

[gitCommit, gitDirty] = resolveGitState(repoRoot);
if requireCleanGit && gitDirty
    error('FormationKlaIndexEquivarianceRunner:DirtyGitState', ...
        'A registered v42 diagnostic requires a clean worktree.');
end

caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
caseCursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        caseCursor = caseCursor + 1;
        presetName = presets{presetIdx};
        seed = seeds(seedIdx);
        fprintf('V42 index-equivariance case %d/%d: %s seed %d\n', ...
            caseCursor, caseCount, presetName, seed);
        cases(caseCursor) = buildCase(presetName, seed, protocol);
    end
end
requestedCaseIds = buildCartesianCaseIds(presets, seeds);
registeredCaseIds = buildCartesianCaseIds( ...
    protocol.registeredPresets, protocol.registeredSeeds);
registeredBatchComplete = ...
    numel(requestedCaseIds) == numel(registeredCaseIds) && ...
    all(ismember(requestedCaseIds, registeredCaseIds)) && ...
    all(ismember(registeredCaseIds, requestedCaseIds));

result = struct();
result.contractVersion = ...
    'formation-reliable-kla-index-equivariance-development-result-v1';
result.protocolId = protocol.id;
result.protocolCanonicalSha256 = protocol.canonicalSha256;
result.baseProtocolCanonicalSha256 = ...
    protocol.baseProtocolCanonicalSha256;
result.generationGitCommit = gitCommit;
result.generationGitDirty = gitDirty;
result.generationRepoTopLevelVerified = true;
result.executableSourceManifest = executableSourceManifest;
result.presets = presets;
result.seeds = seeds;
result.requestedCaseIds = requestedCaseIds;
result.registeredCaseIds = registeredCaseIds;
result.registeredBatchComplete = registeredBatchComplete;
result.exploratorySubsetOnly = ~registeredBatchComplete;
result.cases = cases;
result.caseCount = caseCount;
result.allCasesTestedCyclicBlockOrderEquivariant = ...
    all([cases.testedCyclicBlockOrderEquivariancePassed]);
result.registeredBatchTestedCyclicBlockOrderEquivariant = ...
    registeredBatchComplete && ...
        result.allCasesTestedCyclicBlockOrderEquivariant;
result.anyIndexOrderConfoundingDetected = ...
    any([cases.indexOrderConfoundingDetected]);
result.fullFormationBlockPermutationFamilyCovered = false;
result.withinFormationSensorPermutationCovered = false;
result.physicalActionInterpretationAuthorized = false;
result.groundTruthGeneratorCalled = false;
result.targetTrajectoryGeneratorCalled = false;
result.measurementGeneratorCalled = false;
result.posteriorContentsRead = false;
result.trackingOutcomeScored = false;
result.futureOutcomeUsed = false;
result.realizedDeliveryUniformsUsed = false;
result.fullPlannedSensorGeometryMaterialized = true;
result.fullPlannedLinkProbabilityScheduleMaterialized = true;
result.formalRuntimeObservableBoundaryPassed = false;
result.sourceIdentityCapturedByCleanGitCommit = ~gitDirty;
result.compactReconstructableArtifact = ~gitDirty;
result.fullMatrixPayloadStored = false;
result.developmentEvidenceOnly = true;
result.m24TrackingAuthorized = false;
result.x36TrackingAuthorized = false;
result.validationClaimAllowed = false;
result.canonicalSha256 = computeCanonicalValueSha256(result);

save(matPath, 'result', '-mat7-binary');
writeReport(reportPath, result, matPath, protocol, repoRoot);
fprintf('V42 index-equivariance diagnostic complete: %s\n', reportPath);
end

function value = buildCase(presetName, seed, protocol)
[context, metadata] = ...
    buildFormationReliableKlaGeometryDevelopmentContext( ...
        presetName, seed);
groupIds = reshape(metadata.sensorGroupIds, 1, []);
physicalFormationIds = unique(groupIds, 'stable');
formationCount = numel(physicalFormationIds);
formationOrders = zeros(formationCount, formationCount);
for shiftIdx = 0:formationCount-1
    formationOrders(shiftIdx + 1, :) = ...
        circshift(physicalFormationIds, [0, -shiftIdx]);
end

shifts = repmat(emptyShift(), 1, formationCount);
baseline = struct();
for shiftIdx = 0:formationCount-1
    formationOrder = formationOrders(shiftIdx + 1, :);
    [permuted, permutation] = ...
        permuteFormationReliableKlaContextByBlockOrder( ...
            context, formationOrder);
    full = evaluateShift(permuted, permutation, ...
        physicalFormationIds, protocol);
    if shiftIdx == 0
        baseline = full;
    end
    shifts(shiftIdx + 1) = compactComparison( ...
        full, baseline, shiftIdx, formationOrder, protocol);
end

referenceAdjacencyInvariant = ...
    all([shifts.referenceAdjacencyEqualBaseline]);
referenceWeightsInvariant = ...
    all([shifts.referenceWeightMaxAbsoluteDifference] <= ...
        protocol.fusionWeightAbsoluteTolerance);
referenceFactorInvariant = ...
    all([shifts.referenceFactorAbsoluteDifference] <= ...
        protocol.meanSquareFactorAbsoluteTolerance);
horizonInvariant = all([shifts.evaluationHorizon] == ...
    shifts(1).evaluationHorizon);
candidateAvailabilityInvariant = all( ...
    [shifts.candidateAvailabilityEqualBaseline]);
candidateAdjacencyInvariant = all( ...
    [shifts.candidateAdjacencyEqualBaseline]);
candidateWeightDifferences = ...
    [shifts.candidateWeightMaxAbsoluteDifference];
candidateWeightsInvariant = all(candidateWeightDifferences <= ...
    protocol.fusionWeightAbsoluteTolerance);
candidateFactorDifferences = ...
    [shifts.candidateFactorAbsoluteDifference];
candidateFactorsInvariant = all(isfinite(candidateFactorDifferences)) && ...
    all(candidateFactorDifferences <= ...
        protocol.meanSquareFactorAbsoluteTolerance);
equivariancePassed = referenceAdjacencyInvariant && ...
    referenceWeightsInvariant && referenceFactorInvariant && ...
    horizonInvariant && candidateAvailabilityInvariant && ...
    candidateAdjacencyInvariant && candidateWeightsInvariant && ...
    candidateFactorsInvariant;
[failureLayers, primaryFailureLayer] = classifyFailureLayers( ...
    referenceAdjacencyInvariant, referenceWeightsInvariant, ...
    candidateAvailabilityInvariant, candidateAdjacencyInvariant, ...
    candidateWeightsInvariant, horizonInvariant, ...
    referenceFactorInvariant, candidateFactorsInvariant);

bestIds = [shifts.bestCandidatePhysicalFormationId];
bestPositions = [shifts.bestCandidateOrderPosition];
tieCounts = [shifts.bestCandidateTieCount];
pattern = classifyBestPattern( ...
    bestIds, bestPositions, tieCounts);

value = emptyCase();
value.caseId = sprintf('%s__seed%d__t%d', ...
    presetName, seed, metadata.currentTime);
value.presetName = presetName;
value.seed = seed;
value.currentTime = metadata.currentTime;
value.nodeCount = metadata.nodeCount;
value.formationCount = formationCount;
value.physicalFormationIds = physicalFormationIds;
value.originalInputCanonicalSha256 = ...
    metadata.inputCanonicalSha256;
value.formationOrders = formationOrders;
value.shifts = shifts;
value.referenceAdjacencyInvariant = referenceAdjacencyInvariant;
value.referenceWeightsInvariant = referenceWeightsInvariant;
value.referenceFactorInvariant = referenceFactorInvariant;
value.adaptiveHorizonInvariant = horizonInvariant;
value.candidateAvailabilityInvariant = ...
    candidateAvailabilityInvariant;
value.candidateAdjacencyInvariant = candidateAdjacencyInvariant;
value.candidateWeightsInvariant = candidateWeightsInvariant;
value.candidateFactorsInvariant = candidateFactorsInvariant;
value.referenceRouteUniqueCount = numel(unique( ...
    {shifts.referenceRouteCanonicalSha256}));
value.referenceWeightMaxAbsoluteDifference = max( ...
    [shifts.referenceWeightMaxAbsoluteDifference]);
value.referenceFactorMaxAbsoluteDifference = max( ...
    [shifts.referenceFactorAbsoluteDifference]);
value.candidateWeightMaxAbsoluteDifference = max( ...
    [0, candidateWeightDifferences]);
value.candidateFactorMaxAbsoluteDifference = max( ...
    [0, candidateFactorDifferences]);
value.bestCandidatePhysicalFormationIdsByShift = bestIds;
value.bestCandidateOrderPositionsByShift = bestPositions;
value.bestCandidateDeltasByShift = ...
    [shifts.bestCandidateDelta];
value.improvingCandidateCountsByShift = ...
    [shifts.improvingCandidateCount];
value.bestCandidatePattern = pattern;
value.samePhysicalBestFormationAcrossShifts = ...
    all(isfinite(bestIds)) && numel(unique(bestIds)) == 1;
value.sameBestOrderPositionAcrossShifts = ...
    all(isfinite(bestPositions)) && ...
        numel(unique(bestPositions)) == 1;
value.allBestCandidatesStrictlyImprove = all( ...
    [shifts.bestCandidateDelta] < ...
        -protocol.bestCandidateTieAbsoluteTolerance);
value.equivariancePassed = equivariancePassed;
value.testedCyclicBlockOrderEquivariancePassed = ...
    equivariancePassed;
value.indexOrderConfoundingDetected = ~equivariancePassed;
value.failureLayers = failureLayers;
value.primaryFailureLayer = primaryFailureLayer;
value.residualRouteIndexConfoundingDetected = ...
    ~referenceAdjacencyInvariant || ~referenceWeightsInvariant || ...
    ~candidateAdjacencyInvariant || ~candidateWeightsInvariant;
value.candidateAvailabilityIndexConfoundingDetected = ...
    ~candidateAvailabilityInvariant;
value.adaptiveHorizonIndexConfoundingDetected = ~horizonInvariant;
value.certificateFactorIndexConfoundingDetected = ...
    ~referenceFactorInvariant || ~candidateFactorsInvariant;
value.physicalActionInterpretationAllowed = false;
value.trackingInterpretationAllowed = false;
value.developmentEvidenceOnly = true;
end

function full = evaluateShift(context, permutation, ...
        physicalFormationIds, protocol)
runtime = validateReliableKlaMixingRuntimeSemantics( ...
    context.triggerConfig);
adaptiveOptions = struct();
adaptiveOptions.candidateFormationIds = physicalFormationIds;
adaptiveOptions.missingNeighborWeightModes = { ...
    runtime.missingNeighborWeightMode};
adaptive = buildFormationReliableKlaAdaptiveWindowRouteProbe( ...
    context, adaptiveOptions);
probe = adaptive.routeProbe;
modeIdx = find(probe.operationalMissingNeighborWeightModeMask);
if numel(modeIdx) ~= 1 || ~adaptive.calibrationPassed
    error('FormationKlaIndexEquivarianceRunner:InternalContract', ...
        'The registered adaptive probe did not expose one operational mode.');
end
newToOld = permutation.newToOldNodeOrder;
referenceAction = probe.actions(1);
referenceAdjacency = restoreMatrix( ...
    referenceAction.adjacency, newToOld);
referenceWeights = restoreMatrix( ...
    referenceAction.fusionWeights, newToOld);
referenceFactor = validateFormationReliableKlaContractionFactor( ...
    referenceAction.meanSquareCertificates{modeIdx}. ...
        worstCaseExpectedSquaredContractionFactor, ...
    'reference');
adaptiveReferenceFactor = ...
    validateFormationReliableKlaContractionFactor( ...
        adaptive.referenceSquaredFactorAtEvaluationHorizon, ...
        'adaptive-reference');
if abs(referenceFactor - adaptiveReferenceFactor) > ...
        protocol.meanSquareFactorAbsoluteTolerance
    error('FormationKlaIndexEquivarianceRunner:InternalContract', ...
        'The adaptive reference factor disagrees with its route probe.');
end

formationCount = numel(physicalFormationIds);
candidateAvailable = false(1, formationCount);
candidateAdjacency = cell(1, formationCount);
candidateWeights = cell(1, formationCount);
candidateFactor = nan(1, formationCount);
candidateDelta = nan(1, formationCount);
candidateRouteSha256 = cell(1, formationCount);
for formationIdx = 1:formationCount
    physicalId = physicalFormationIds(formationIdx);
    actionIdx = findCandidateAction(probe.actions, physicalId);
    action = probe.actions(actionIdx);
    candidateAvailable(formationIdx) = action.available;
    if ~action.available
        candidateAdjacency{formationIdx} = false(0);
        candidateWeights{formationIdx} = zeros(0);
        candidateRouteSha256{formationIdx} = '';
        continue;
    end
    candidateAdjacency{formationIdx} = restoreMatrix( ...
        action.adjacency, newToOld);
    candidateWeights{formationIdx} = restoreMatrix( ...
        action.fusionWeights, newToOld);
    candidateFactor(formationIdx) = ...
        validateFormationReliableKlaContractionFactor( ...
            action.meanSquareCertificates{modeIdx}. ...
                worstCaseExpectedSquaredContractionFactor, ...
            sprintf('candidate-f%g', physicalId));
    candidateDelta(formationIdx) = ...
        candidateFactor(formationIdx) - referenceFactor;
    candidateRouteSha256{formationIdx} = routeSha256( ...
        candidateAdjacency{formationIdx}, ...
        candidateWeights{formationIdx});
end

availableIndices = find(candidateAvailable & isfinite(candidateDelta));
if isempty(availableIndices)
    error('FormationKlaIndexEquivarianceRunner:InternalContract', ...
        'No registered formation action is available.');
end
[bestDelta, localBestIdx] = min(candidateDelta(availableIndices));
bestIdx = availableIndices(localBestIdx);
tieMask = candidateAvailable & isfinite(candidateDelta) & ...
    abs(candidateDelta - bestDelta) <= ...
        protocol.bestCandidateTieAbsoluteTolerance;
improvingMask = candidateAvailable & isfinite(candidateDelta) & ...
    candidateDelta < -protocol.bestCandidateTieAbsoluteTolerance;

full = struct();
full.permutation = permutation;
full.evaluationHorizon = adaptive.evaluationHorizon;
full.referenceFactor = referenceFactor;
full.referenceAdjacency = referenceAdjacency;
full.referenceWeights = referenceWeights;
full.referenceRouteCanonicalSha256 = routeSha256( ...
    referenceAdjacency, referenceWeights);
full.candidateAvailable = candidateAvailable;
full.candidateAdjacency = candidateAdjacency;
full.candidateWeights = candidateWeights;
full.candidateFactor = candidateFactor;
full.candidateDelta = candidateDelta;
full.candidateRouteCanonicalSha256 = candidateRouteSha256;
full.bestCandidatePhysicalFormationId = ...
    physicalFormationIds(bestIdx);
full.bestCandidateDelta = bestDelta;
full.bestCandidateTieIds = physicalFormationIds(tieMask);
full.improvingCandidateIds = physicalFormationIds(improvingMask);
end

function compact = compactComparison(full, baseline, shiftIndex, ...
        formationOrder, protocol)
formationCount = numel(formationOrder);
availabilityEqual = ...
    full.candidateAvailable == baseline.candidateAvailable;
adjacencyEqual = false(1, formationCount);
weightDifference = inf(1, formationCount);
factorDifference = inf(1, formationCount);
for formationIdx = 1:formationCount
    if full.candidateAvailable(formationIdx) && ...
            baseline.candidateAvailable(formationIdx)
        adjacencyEqual(formationIdx) = isequal( ...
            full.candidateAdjacency{formationIdx}, ...
            baseline.candidateAdjacency{formationIdx});
        weightDifference(formationIdx) = max(abs( ...
            full.candidateWeights{formationIdx}(:) - ...
            baseline.candidateWeights{formationIdx}(:)));
        factorDifference(formationIdx) = abs( ...
            full.candidateFactor(formationIdx) - ...
            baseline.candidateFactor(formationIdx));
    elseif ~full.candidateAvailable(formationIdx) && ...
            ~baseline.candidateAvailable(formationIdx)
        adjacencyEqual(formationIdx) = true;
        weightDifference(formationIdx) = 0;
        factorDifference(formationIdx) = 0;
    end
end

compact = emptyShift();
compact.shiftIndex = shiftIndex;
compact.formationOrder = formationOrder;
compact.permutationCanonicalSha256 = ...
    full.permutation.canonicalSha256;
compact.newToOldNodeOrder = ...
    full.permutation.newToOldNodeOrder;
compact.evaluationHorizon = full.evaluationHorizon;
compact.referenceFactor = full.referenceFactor;
compact.referenceRouteCanonicalSha256 = ...
    full.referenceRouteCanonicalSha256;
compact.referenceAdjacencyEqualBaseline = isequal( ...
    full.referenceAdjacency, baseline.referenceAdjacency);
compact.referenceWeightMaxAbsoluteDifference = max(abs( ...
    full.referenceWeights(:) - baseline.referenceWeights(:)));
compact.referenceFactorAbsoluteDifference = abs( ...
    full.referenceFactor - baseline.referenceFactor);
compact.candidatePhysicalFormationIds = ...
    baseline.permutation.originalFormationOrder;
compact.candidateAvailableMask = full.candidateAvailable;
compact.candidateMeanSquareFactors = full.candidateFactor;
compact.candidateFactorDeltas = full.candidateDelta;
compact.candidateRouteCanonicalSha256 = ...
    full.candidateRouteCanonicalSha256;
compact.candidateAvailabilityEqualBaseline = availabilityEqual;
compact.candidateAdjacencyEqualBaseline = adjacencyEqual;
compact.candidateWeightMaxAbsoluteDifference = weightDifference;
compact.candidateFactorAbsoluteDifference = factorDifference;
compact.bestCandidatePhysicalFormationId = ...
    full.bestCandidatePhysicalFormationId;
compact.bestCandidateOrderPosition = find( ...
    formationOrder == full.bestCandidatePhysicalFormationId, 1);
compact.bestCandidateDelta = full.bestCandidateDelta;
compact.bestCandidateTieIds = full.bestCandidateTieIds;
compact.bestCandidateTieCount = numel(full.bestCandidateTieIds);
compact.improvingCandidateIds = full.improvingCandidateIds;
compact.improvingCandidateCount = ...
    numel(full.improvingCandidateIds);
compact.bestCandidateWouldBeatReference = ...
    full.bestCandidateDelta < ...
        -protocol.bestCandidateTieAbsoluteTolerance;
end

function index = findCandidateAction(actions, physicalFormationId)
index = zeros(1, 0);
for actionIdx = 2:numel(actions)
    if isequal(actions(actionIdx).suspendedFormationIds, ...
            physicalFormationId)
        index(end + 1) = actionIdx; %#ok<AGROW>
    end
end
if numel(index) ~= 1
    error('FormationKlaIndexEquivarianceRunner:InternalContract', ...
        'A physical formation does not map to exactly one action.');
end
end

function restored = restoreMatrix(permuted, newToOld)
if islogical(permuted)
    restored = false(size(permuted));
else
    restored = zeros(size(permuted));
end
restored(newToOld, newToOld) = permuted;
end

function value = routeSha256(adjacency, weights)
value = computeCanonicalValueSha256(struct( ...
    'adjacency', logical(adjacency), ...
    'fusionWeights', weights));
end

function pattern = classifyBestPattern(ids, positions, tieCounts)
if any(~isfinite(ids)) || any(~isfinite(positions)) || ...
        any(tieCounts ~= 1)
    pattern = 'ambiguous-or-tied';
elseif numel(unique(ids)) == 1 && numel(unique(positions)) > 1
    pattern = 'physical-formation-identity';
elseif numel(unique(positions)) == 1 && numel(unique(ids)) > 1
    pattern = 'formation-order-position';
elseif numel(unique(ids)) == 1 && numel(unique(positions)) == 1
    pattern = 'degenerate-invariant-position';
else
    pattern = 'order-sensitive-irregular';
end
end

function [layers, primary] = classifyFailureLayers( ...
        referenceAdjacencyInvariant, referenceWeightsInvariant, ...
        candidateAvailabilityInvariant, candidateAdjacencyInvariant, ...
        candidateWeightsInvariant, horizonInvariant, ...
        referenceFactorInvariant, candidateFactorsInvariant)
layers = cell(1, 0);
if ~referenceAdjacencyInvariant || ~referenceWeightsInvariant
    layers{end + 1} = 'reference-route-or-weight'; %#ok<AGROW>
end
if ~candidateAvailabilityInvariant || ~candidateAdjacencyInvariant || ...
        ~candidateWeightsInvariant
    layers{end + 1} = 'candidate-construction-or-route'; %#ok<AGROW>
end
if ~horizonInvariant
    layers{end + 1} = 'adaptive-horizon'; %#ok<AGROW>
end
if ~referenceFactorInvariant || ~candidateFactorsInvariant
    layers{end + 1} = 'mean-square-certificate-factor'; %#ok<AGROW>
end
if isempty(layers)
    primary = 'none';
else
    primary = layers{1};
end
end

