fprintf(fileId, '\n## Shift-level evidence\n\n');
fprintf(fileId, [ ...
    '| Preset | Seed | Shift | Formation order | H | Ref rho ', ...
    '| Same restored ref route? | Best physical ID | Position ', ...
    '| Best delta | Improving IDs |\n']);
fprintf(fileId, [ ...
    '|:--|--:|--:|:--|--:|--:|:--:|--:|--:|--:|:--|\n']);
for caseIdx = 1:numel(result.cases)
    current = result.cases(caseIdx);
    for shiftIdx = 1:numel(current.shifts)
        shift = current.shifts(shiftIdx);
        fprintf(fileId, [ ...
            '| %s | %d | %d | %s | %d | %.10f | %d ', ...
            '| %g | %g | %+.10f | %s |\n'], ...
            current.presetName, current.seed, shift.shiftIndex, ...
            numericVectorText(shift.formationOrder), ...
            shift.evaluationHorizon, shift.referenceFactor, ...
            shift.referenceAdjacencyEqualBaseline, ...
            shift.bestCandidatePhysicalFormationId, ...
            shift.bestCandidateOrderPosition, ...
            shift.bestCandidateDelta, ...
            numericVectorText(shift.improvingCandidateIds));
    end
end

fprintf(fileId, '\n## Decision rule and claim boundary\n\n');
fprintf(fileId, [ ...
    '- Required weight tolerance: `%.3g`; factor tolerance: `%.3g`.\n', ...
    '- All requested cases equivariant over tested cyclic block orders: ', ...
    '`%d`; registered 8-case conclusion: `%d`; any ordering confound: ', ...
    '`%d`.\n', ...
    '- The diagnostic covers only `4/24` M24 and `6/720` X36 block ', ...
