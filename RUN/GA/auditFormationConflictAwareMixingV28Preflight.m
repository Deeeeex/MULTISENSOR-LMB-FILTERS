function [reportPath, audit] = ...
    auditFormationConflictAwareMixingV28Preflight(options)
% AUDITFORMATIONCONFLICTAWAREMIXINGV28PREFLIGHT
% Current-posterior-only v28 action and safety projection audit.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationConflictAwareMixingProbeProtocol();
screenPath = getField(options, 'v27ScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v27', 'scale_aware_residual_mixing', ...
    't72', 'screen', ...
    ['FORMATION_SCALE_AWARE_MIXING_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_CONFLICT_AWARE_SELECTIVE_MIXING_V28_', ...
     'PREFLIGHT_20260802.md']));
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V28Preflight:MissingScreen', ...
        'Frozen v27 screen is unavailable.');
end
screen = loaded.screen;
assertSourceProvenance(screen, protocol);
context = reconstructContext(screen);

timerId = tic;
bank = buildConflictAwareFormationMixingActionBank(context);
bankConstructionSeconds = toc(timerId);
if ~bank.messageCountParityWithReference || ...
        ~bank.allPhysical || ...
        ~bank.allCombinedOneStepStrongConnected || ...
        ~bank.allFormationStrongConnected || ...
        bank.truthUsed || bank.futureOutcomeUsed || ...
        ~bank.posteriorSafetyScored
    error('V28Preflight:BankContract', ...
        'v28 action bank violated a frozen preflight invariant.');
end

referenceIdx = bank.referenceActionIndex;
disagreementChangePercent = 100 * ( ...
    bank.networkDisagreementRisk - ...
        bank.networkDisagreementRisk(referenceIdx)) / max( ...
            bank.networkDisagreementRisk(referenceIdx), eps);
gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'formation-conflict-aware-v28-preflight-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.protocol = protocol;
audit.sourceV27ScreenPath = screenPath;
audit.sourceCachePath = screen.cachePath;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.presetName = screen.presetName;
audit.seed = screen.seed;
audit.currentTime = screen.currentTime;
audit.bankConstructionSeconds = bankConstructionSeconds;
audit.bank = bank;
audit.disagreementChangePercent = disagreementChangePercent;
audit.structuralActionCount = bank.actionCount;
audit.safeNonreferenceActionCount = ...
    bank.safeNonreferenceActionCount;
audit.safeNonreferenceActionIndices = setdiff( ...
    bank.safeActionIndices, referenceIdx);
audit.safeNonreferenceActionNames = ...
    bank.actionNames(audit.safeNonreferenceActionIndices);
audit.currentPosteriorUsed = true;
audit.currentLinkReliabilityUsed = true;
audit.truthUsed = false;
audit.futureMeasurementUsed = false;
audit.futureOutcomeUsed = false;
audit.trackingContinuationExecuted = false;
audit.newStateOpened = false;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.primaryTrackingScreenAuthorized = ...
    bank.safeNonreferenceActionCount > 0;
audit.evidenceBoundary = protocol.evidenceBoundary;

writeReport(reportPath, audit);
fprintf('V28 conflict-aware preflight: %s\n', reportPath);
end

function context = reconstructContext(screen)
inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
loaded = load(screen.cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V28Preflight:MissingCache', ...
        'Opened behavior cache is unavailable.');
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.presetName, screen.presetName) || ...
        bundle.seed ~= screen.seed || ...
        ~isequal(bundle.snapshotTimes, screen.currentTime) || ...
        ~isequaln(bundle.configSnapshot, inputs.config) || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        bundle.validationClaimAllowed
    error('V28Preflight:CacheProvenance', ...
        'Opened behavior cache provenance changed.');
end
history = bundle.preDecisionTopologyHistoryByTime{screen.currentTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{screen.currentTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = screen.currentTime;
context.previousAdjacencyHistory = previousHistory;
context.previousAdjacency = previousHistory(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, screen.currentTime));
context.positions = inputs.graphData.positions(:, :, screen.currentTime);
context.directedMessageBudget = 2 * ...
    inputs.config.numberOfSensors;
end

function assertSourceProvenance(screen, protocol)
if ~strcmp(screen.contractVersion, ...
        'formation-scale-aware-residual-mixing-v27-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            '9d9fc7e003a868f688718061aac5c01eebb0b78d') || ...
        ~strcmp(screen.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(screen.presetName, protocol.presetName) || ...
        screen.seed ~= protocol.seed || ...
        screen.currentTime ~= protocol.primarySnapshotTime || ...
        screen.strictStrongCandidateCount ~= 0 || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed
    error('V28Preflight:SourceProvenance', ...
        'Frozen v27 source provenance changed.');
end
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('V28Preflight:WriteFailed', ...
        'Could not open v28 preflight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bank = audit.bank;
protocol = audit.protocol;
fprintf(fid, '# V28 conflict-aware selective-mixing preflight\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Tracked worktree dirty: `%d`\n', ...
    audit.generationTrackedWorktreeDirty);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- Structural actions: `%d`\n', ...
    audit.structuralActionCount);
fprintf(fid, '- Safe nonreference actions: `%d`\n', ...
    audit.safeNonreferenceActionCount);
fprintf(fid, '- Tracking continuation executed: `0`\n');
fprintf(fid, '- New state / X36 / X48 opened: `0 / 0 / 0`\n');
fprintf(fid, '- Bank construction: `%.2f s`\n\n', ...
    audit.bankConstructionSeconds);

fprintf(fid, '## Frozen current-posterior safety gate\n\n');
fprintf(fid, [ ...
    '- Maximum reference-weighted retention risk: `%.3f`\n', ...
    '- Minimum formation-mean expected-cardinality change: `%.3f`\n', ...
    '- Minimum supported-label retention ratio: `%.2f`\n', ...
    '- Maximum 0.5-threshold label drops: `%d`\n', ...
    '- Maximum one-step disagreement increase: `%.1f%%`\n\n'], ...
    protocol.maximumRetentionRisk, ...
    protocol.minimumFormationMeanCardinalityChange, ...
    protocol.minimumSupportedLabelRetentionRatio, ...
    protocol.maximumDecisionThresholdCrossingCount, ...
    100 * protocol.maximumExpectedDisagreementIncreaseFraction);

fprintf(fid, [ ...
    '| Action | Formations | Cross edges | Cross trust | Mix gap | ', ...
    'Disagreement change | Retention risk | Min form. d-card | ', ...
    'Min label retention | Threshold drops | Safe |\n']);
fprintf(fid, [ ...
    '|:--|:--|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for actionIdx = 1:bank.actionCount
    fprintf(fid, [ ...
        '| `%s` | `%s` | %d | %.4f | %.6f | %+.3f%% | ', ...
        '%.6f | %+.6f | %.6f | %d | %d |\n'], ...
        bank.actionNames{actionIdx}, ...
        mat2str(bank.actionFormationIds{actionIdx}), ...
        bank.actionCrossFormationMessageCounts(actionIdx), ...
        bank.actionCrossResidualTrust(actionIdx), ...
        bank.actionFormationMixingSpectralGapProxy(actionIdx), ...
        audit.disagreementChangePercent(actionIdx), ...
        bank.retentionRisk(actionIdx), ...
        bank.minimumFormationCardinalityChange(actionIdx), ...
        bank.minimumSupportedLabelRetentionRatio(actionIdx), ...
        bank.decisionThresholdCrossingCount(actionIdx), ...
        bank.actionPosteriorSafetyMask(actionIdx));
end

fprintf(fid, '\n## Decision\n\n');
if audit.primaryTrackingScreenAuthorized
    fprintf(fid, [ ...
        'At least one nonreference action passes every frozen ', ...
        'current-posterior guard. The primary H=3 tracking screen may ', ...
        'execute only the reference and these pre-approved action ', ...
        'indices: `%s`. This authorization does not open another M24 ', ...
        'state or X36/X48.\n\n'], ...
        mat2str(audit.safeNonreferenceActionIndices));
else
    fprintf(fid, [ ...
        'No nonreference action passes the frozen current-posterior ', ...
        'guard. No v28 tracking continuation is authorized; redesign ', ...
        'must occur without opening another state.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
