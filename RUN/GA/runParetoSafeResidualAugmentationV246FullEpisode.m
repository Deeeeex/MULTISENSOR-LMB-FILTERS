function [reportPath, result] = ...
        runParetoSafeResidualAugmentationV246FullEpisode(options)
% RUNPARETOSAFERESIDUALAUGMENTATIONV246FULLEPISODE Run one V246 arm.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getParetoSafeResidualAugmentationV246Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('ParetoSafeResidualV246:DirtySource', ...
        'The V246 full episode requires clean tracked source.');
end
presetName = char(getField(options, 'presetName', ...
    'm24-formation-fov-coupled-formation-braid'));
seed = getField(options, 'seed', protocol.allowedSeeds(1));
referenceResultPath = char(getField( ...
    options, 'referenceResultPath', ''));
resume = logical(getField(options, 'resume', true));
if ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds) || ...
        isempty(referenceResultPath) || ...
        ~islogical(resume) || ~isscalar(resume)
    error('ParetoSafeResidualV246:InvalidOptions', ...
        'V246 requires one registered case and a completed V245 result.');
end
if exist(referenceResultPath, 'file') ~= 2
    error('ParetoSafeResidualV246:MissingReference', ...
        'The completed V245 reference result does not exist.');
end
envelope = load(referenceResultPath, 'result');
reference = envelope.result;
validateReference(reference, presetName, seed);

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v246', sprintf('%s_seed%d', ...
        strrep(presetName, '-', '_'), seed))));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'PARETO_SAFE_RESIDUAL_AUGMENTATION_V246_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'PARETO_SAFE_RESIDUAL_AUGMENTATION_V246_FULL_EPISODE.md');
result = initializeResult(protocol, gitState.commit, presetName, seed, ...
    referenceResultPath, reference, matPath, reportPath);
if resume && exist(matPath, 'file') == 2
    loaded = load(matPath, 'result');
    validateExisting(loaded.result, result);
    result = loaded.result;
end
if armComplete(result.candidate)
    fprintf('Reused completed V246 result: %s\n', reportPath);
    return;
end

fprintf('\nV246 Pareto-safe residual augmentation: %s seed %d\n', ...
    presetName, seed);
inputs = generateDynamicTopologyScenarioInputs(presetName, seed);
filterModel = ...
    removeRealizedTargetTruthFromDynamicTopologyModel(inputs.model);
representatives = selectFormationRepresentativesLocal( ...
    inputs.config.sensorGroupIds);
metricWindow = struct( ...
    'activationStartTime', inputs.config.focusWindow(1), ...
    'activationEndTime', inputs.config.focusWindow(end));
config = buildParetoSafeResidualAugmentationV246Config(inputs.config);
context = buildParetoSafeResidualAugmentationV246ExecutionContext( ...
    presetName, seed, inputs.config.simulationLength);
source = getCausalMinimumFormationBackboneV242Protocol();
rng(seed + source.filterSeedOffset, 'twister');
timerId = tic;
fprintf('  running exact-value residual full episode ...\n');
[estimates, diagnostics] = ...
    runEventTriggeredDistributedLmbFilter( ...
        filterModel, inputs.measurements, ...
        inputs.sensorTrajectories, inputs.neighborMap, ...
        inputs.commConfig, config, context);
candidate = summarizeRepeatedMultiGatewayFullEpisodeArm( ...
    protocol.armId, estimates, diagnostics, inputs.groundTruthRfs, ...
    inputs.config, representatives, metricWindow, toc(timerId));
candidate = attachTopologySummary( ...
    candidate, diagnostics, inputs.config);
assertRuntimeArm(candidate, inputs.config);
result.candidate = candidate;
result.candidateOverFixedTree = ...
    compareArm(candidate, reference.fixedTree);
result.candidateOverFullCausal = ...
    compareArm(candidate, reference.fullCausal);
result.candidateOverMinimumBackbone = ...
    compareArm(candidate, reference.minimumBackbone);
result.balancedDirectionOverFixedPassed = ...
    result.candidateOverFixedTree.meanDirectionPassed && ...
    result.candidateOverFixedTree.attemptedByteSavingPercent > 0;
result.incrementalDirectionOverMinimumPassed = ...
    result.candidateOverMinimumBackbone.meanDirectionPassed;
result.paperThresholdPassed = ...
    result.candidateOverFixedTree.fullHorizonEospaGainPercent >= 5 && ...
    result.candidateOverFixedTree.fullHorizonRmseGainPercent >= 5 && ...
    result.candidateOverFixedTree.focusConsensusGainPercent >= 2 && ...
    result.candidateOverFixedTree.attemptedByteSavingPercent >= 1 && ...
    result.candidateOverFixedTree.nonnegativeFormationTailPassed;
result.completedAt = datestr(now, 31);
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf(['  V246 E-OSPA %.3f; RMSE %.3f; focus consensus %.3f; ', ...
    'bytes %.0f; messages %d..%d; selected pages %.3f; %.1f s\n'], ...
    candidate.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionRmse, ...
    candidate.focusInterFormationPositionOspa, ...
    candidate.attemptedPayloadBytes, ...
    candidate.routeMessageCountMinimum, ...
    candidate.routeMessageCountMaximum, ...
    candidate.selectedResidualPageFraction, ...
    candidate.elapsedSeconds);
fprintf('V246 result: %s\n', reportPath);
end

function validateReference(reference, presetName, seed)
required = {'contractVersion', 'generationGitCommit', ...
    'presetName', 'seed', 'fixedTree', 'fullCausal', ...
    'minimumBackbone', 'balancedDirectionPassed'};
valid = isstruct(reference) && isscalar(reference) && ...
    all(isfield(reference, required)) && ...
    strcmp(reference.contractVersion, ...
        'information-coupled-formation-braid-v245-result-v1') && ...
    strcmp(reference.presetName, presetName) && ...
    reference.seed == seed && ...
    armComplete(reference.fixedTree) && ...
    armComplete(reference.fullCausal) && ...
    armComplete(reference.minimumBackbone);
if ~valid
    error('ParetoSafeResidualV246:InvalidReference', ...
        'The supplied V245 result is incomplete or belongs to another case.');
end
end

function result = initializeResult(protocol, commit, presetName, seed, ...
        referencePath, reference, matPath, reportPath)
result = struct();
result.contractVersion = ...
    'pareto-safe-residual-augmentation-v246-full-episode-result-v1';
result.protocolId = protocol.id;
result.protocol = protocol;
result.startedAt = datestr(now, 31);
result.completedAt = '';
result.generationGitCommit = commit;
result.presetName = presetName;
result.seed = seed;
result.v245ReferenceResultPath = referencePath;
result.v245ReferenceGenerationGitCommit = ...
    reference.generationGitCommit;
result.referenceFixedTree = reference.fixedTree;
result.referenceFullCausal = reference.fullCausal;
result.referenceMinimumBackbone = reference.minimumBackbone;
result.candidate = struct();
result.candidateOverFixedTree = struct();
result.candidateOverFullCausal = struct();
result.candidateOverMinimumBackbone = struct();
result.balancedDirectionOverFixedPassed = false;
result.incrementalDirectionOverMinimumPassed = false;
result.paperThresholdPassed = false;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.matPath = matPath;
result.reportPath = reportPath;
result.evidenceBoundary = protocol.evidenceBoundary;
end

function validateExisting(actual, expected)
required = {'contractVersion', 'protocolId', 'generationGitCommit', ...
    'presetName', 'seed', 'v245ReferenceResultPath', ...
    'v245ReferenceGenerationGitCommit', 'candidate'};
if ~isstruct(actual) || ~isscalar(actual) || ...
        ~all(isfield(actual, required)) || ...
        ~strcmp(actual.contractVersion, expected.contractVersion) || ...
        ~strcmp(actual.protocolId, expected.protocolId) || ...
        ~strcmp(actual.generationGitCommit, ...
            expected.generationGitCommit) || ...
        ~strcmp(actual.presetName, expected.presetName) || ...
        actual.seed ~= expected.seed || ...
        ~strcmp(actual.v245ReferenceResultPath, ...
            expected.v245ReferenceResultPath) || ...
        ~strcmp(actual.v245ReferenceGenerationGitCommit, ...
            expected.v245ReferenceGenerationGitCommit)
    error('ParetoSafeResidualV246:InvalidResumeState', ...
        'The V246 checkpoint belongs to another source or reference.');
end
end

function arm = attachTopologySummary(arm, diagnostics, config)
pages = logical(diagnostics.topologyActiveEdge);
arm.uniqueTopologyCount = uniquePageCount(pages);
arm.topologyChangeCount = pageChangeCount(pages);
arm.routeMessageCountByTime = reshape( ...
    diagnostics.topologyDirectedMessageCount, 1, []);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed);
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed);
strong = false(1, size(pages, 3));
for currentTime = 1:numel(strong)
    strong(currentTime) = ...
        isStronglyConnected(pages(:, :, currentTime)');
end
arm.instantaneousStrongFraction = mean(strong);
arm.instantaneousStrongAllTimes = all(strong);
formationCount = numel(unique(config.sensorGroupIds));
arm.minimumBackboneMessageCount = ...
    config.numberOfSensors + 2 * (formationCount - 1);
arm.maximumMessageBudget = ...
    arm.minimumBackboneMessageCount + ceil(formationCount / 2);
timeCount = numel(strong);
arm.selectedResidualCountByTime = zeros(1, timeCount);
arm.selectedResidualBytesByTime = zeros(1, timeCount);
arm.residualByteBudgetByTime = zeros(1, timeCount);
arm.currentStepParetoSafeByTime = false(1, timeCount);
for currentTime = 1:timeCount
    certificate = ...
        diagnostics.topologyPolicyScheduleCertificate{currentTime};
    if ~isstruct(certificate)
        continue;
    end
    arm.selectedResidualCountByTime(currentTime) = getField( ...
        certificate, 'selectedResidualCount', 0);
    arm.selectedResidualBytesByTime(currentTime) = getField( ...
        certificate, 'selectedAddedResidualBytes', 0);
    arm.residualByteBudgetByTime(currentTime) = getField( ...
        certificate, 'addedResidualByteBudget', 0);
    arm.currentStepParetoSafeByTime(currentTime) = logical(getField( ...
        certificate, 'currentStepParetoSafe', false));
end
arm.selectedResidualPageFraction = mean( ...
    arm.selectedResidualCountByTime > 0);
arm.meanSelectedResidualCount = mean( ...
    arm.selectedResidualCountByTime);
arm.maximumSelectedResidualCount = max( ...
    arm.selectedResidualCountByTime);
arm.currentStepParetoSafeAllTimes = ...
    all(arm.currentStepParetoSafeByTime);
selection = reshape(diagnostics.topologyPolicySeconds, 1, []);
selection = selection(isfinite(selection));
arm.meanPolicySelectionSeconds = meanOrNaN(selection);
arm.maximumPolicySelectionSeconds = maxOrNaN(selection);
valid = reshape( ...
    diagnostics.topologyPolicyValidCandidateCount, 1, []);
valid = valid(isfinite(valid));
arm.meanAdmissibleCandidateCount = meanOrNaN(valid);
arm.maximumAdmissibleCandidateCount = maxOrNaN(valid);
end

function assertRuntimeArm(arm, config)
formationCount = numel(unique(config.sensorGroupIds));
minimumMessages = config.numberOfSensors + 2 * (formationCount - 1);
maximumMessages = minimumMessages + ceil(formationCount / 2);
passed = arm.physicalFeasibilityPassed && ...
    ~arm.policyTruthUsed && ~arm.policyFutureOutcomeUsed && ...
    arm.routeMessageCountMinimum >= minimumMessages && ...
    arm.routeMessageCountMaximum <= maximumMessages && ...
    arm.instantaneousStrongAllTimes && ...
    arm.maximumSelectedResidualCount <= ceil(formationCount / 2) && ...
    arm.currentStepParetoSafeAllTimes;
if ~passed
    error('ParetoSafeResidualV246:RuntimeContractFailed', ...
        'The executed V246 arm violated a route or Pareto boundary.');
end
end

function comparison = compareArm(candidate, reference)
comparison = struct();
comparison.fullHorizonEospaGainPercent = lowerGain( ...
    reference.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionEospa);
comparison.focusWindowEospaGainPercent = lowerGain( ...
    reference.focusWindowPositionEospa, ...
    candidate.focusWindowPositionEospa);
comparison.fullHorizonRmseGainPercent = lowerGain( ...
    reference.fullHorizonPositionRmse, ...
    candidate.fullHorizonPositionRmse);
comparison.focusWindowRmseGainPercent = lowerGain( ...
    reference.focusWindowPositionRmse, ...
    candidate.focusWindowPositionRmse);
comparison.focusConsensusGainPercent = lowerGain( ...
    reference.focusInterFormationPositionOspa, ...
    candidate.focusInterFormationPositionOspa);
comparison.terminalConsensusGainPercent = lowerGain( ...
    reference.terminalInterFormationPositionOspa, ...
    candidate.terminalInterFormationPositionOspa);
comparison.attemptedByteSavingPercent = lowerGain( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
comparison.deliveredByteSavingPercent = lowerGain( ...
    reference.deliveredPayloadBytes, candidate.deliveredPayloadBytes);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.sensorEospaGainPercent = lowerGainVector( ...
    reference.perSensorPositionEospa, ...
    candidate.perSensorPositionEospa);
comparison.minimumSensorEospaGainPercent = ...
    min(comparison.sensorEospaGainPercent);
comparison.sensorRmseGainPercent = lowerGainVector( ...
    reference.perSensorPositionRmse, ...
    candidate.perSensorPositionRmse);
comparison.minimumSensorRmseGainPercent = ...
    min(comparison.sensorRmseGainPercent);
comparison.meanDirectionPassed = ...
    comparison.fullHorizonEospaGainPercent > 0 && ...
    comparison.fullHorizonRmseGainPercent > 0 && ...
    comparison.focusConsensusGainPercent > 0;
comparison.nonnegativeFormationTailPassed = ...
    comparison.minimumFormationEospaGainPercent >= 0 && ...
    comparison.minimumFormationRmseGainPercent >= 0;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ParetoSafeResidualV246:ReportOpenFailed', ...
        'Unable to write %s.', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
candidate = result.candidate;
fprintf(fid, '# V246 Pareto-safe residual augmentation\n\n');
fprintf(fid, '- Preset: `%s`\n', result.presetName);
fprintf(fid, '- Seed: `%d`\n', result.seed);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Balanced direction over fixed passed: `%d`\n', ...
    result.balancedDirectionOverFixedPassed);
fprintf(fid, '- Incremental direction over V242 passed: `%d`\n', ...
    result.incrementalDirectionOverMinimumPassed);
fprintf(fid, '- Paper threshold passed: `%d`\n\n', ...
    result.paperThresholdPassed);
fprintf(fid, [ ...
    '| Arm | Full E-OSPA | Full RMSE | Focus consistency | ', ...
    'Attempted bytes | Messages / step |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|\n');
writeArmRow(fid, 'Fixed formation tree', result.referenceFixedTree);
writeArmRow(fid, 'Full causal repair', result.referenceFullCausal);
writeArmRow(fid, 'Minimum causal backbone', ...
    result.referenceMinimumBackbone);
writeArmRow(fid, 'Pareto-safe residual augmentation', candidate);
writeComparison(fid, 'V246 over fixed tree', ...
    result.candidateOverFixedTree);
writeComparison(fid, 'V246 over V242 minimum backbone', ...
    result.candidateOverMinimumBackbone);
fprintf(fid, '\n## Runtime selection\n\n');
fprintf(fid, '- Pages with at least one residual: `%.3f`\n', ...
    candidate.selectedResidualPageFraction);
fprintf(fid, '- Mean / maximum selected residuals: `%.3f / %d`\n', ...
    candidate.meanSelectedResidualCount, ...
    candidate.maximumSelectedResidualCount);
fprintf(fid, '- Mean / maximum admissible candidates: `%.3f / %.0f`\n', ...
    candidate.meanAdmissibleCandidateCount, ...
    candidate.maximumAdmissibleCandidateCount);
fprintf(fid, '- Mean / maximum policy selection seconds: `%.3f / %.3f`\n', ...
    candidate.meanPolicySelectionSeconds, ...
    candidate.maximumPolicySelectionSeconds);
fprintf(fid, '- Current-step Pareto guard passed on every page: `%d`\n', ...
    candidate.currentStepParetoSafeAllTimes);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeArmRow(fid, name, arm)
fprintf(fid, '| %s | %.3f | %.3f | %.3f | %.0f | %d--%d |\n', ...
    name, arm.fullHorizonPositionEospa, ...
    arm.fullHorizonPositionRmse, ...
    arm.focusInterFormationPositionOspa, ...
    arm.attemptedPayloadBytes, arm.routeMessageCountMinimum, ...
    arm.routeMessageCountMaximum);
end

