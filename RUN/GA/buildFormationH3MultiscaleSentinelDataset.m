function [datasetPath, dataset] = ...
    buildFormationH3MultiscaleSentinelDataset(options)
% BUILDFORMATIONH3MULTISCALESENTINELDATASET Join frozen teacher shards.
%
% Features are rebuilt from each truth-free predecision cache.  Truth and
% future measurements remain confined to the already-generated H=3 targets.
% Seeds 211/223 form the sentinel-training split and seed 227 is retained as
% a disjoint sentinel-development split.  This dataset cannot support a
% final validation claim or open any reserved seed.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationH3MultiscaleTeacherProtocol();
shardRoot = getField(options, 'shardRoot', protocol.shardRoot);
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v13', 'multiscale_teacher_sentinel', 'dataset'));
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 multiscale dataset requires clean source.');
end

targetNames = { ...
    'mean_tracking_gain_percent', ...
    'minimum_formation_gain_percent', ...
    'worst_sensor_gain_percent', ...
    'consensus_gain_percent', ...
    'attempted_byte_saving_percent', ...
    'delivered_byte_saving_percent'};
blockCount = numel(protocol.presets) * numel(protocol.allSeeds) * ...
    numel(protocol.snapshotTimes);
blocks = repmat(emptyBlock(), 1, blockCount);
shardPaths = cell(1, ...
    numel(protocol.presets) * numel(protocol.allSeeds));
shardSha256 = shardPaths;
teacherCommits = shardPaths;
expectedFeatureNames = {};
expectedFeatureContract = '';
blockCursor = 0;
shardCursor = 0;
for presetIdx = 1:numel(protocol.presets)
    presetName = protocol.presets{presetIdx};
    for seed = protocol.allSeeds
        shardCursor = shardCursor + 1;
        shardPath = fullfile(shardRoot, presetName, ...
            sprintf('seed%d', seed), sprintf( ...
                'formation_h3_teacher_%s_seed%d_v1.mat', ...
                strrep(presetName, '-', '_'), seed));
        shard = loadAndValidateShard( ...
            shardPath, protocol, presetIdx, presetName, seed);
        shardPaths{shardCursor} = shardPath;
        shardSha256{shardCursor} = computeFileSha256(shardPath);
        teacherCommits{shardCursor} = shard.generationGitCommit;
        for timeIdx = 1:numel(protocol.snapshotTimes)
            currentTime = protocol.snapshotTimes(timeIdx);
            localScreen = shard.localScreens{timeIdx};
            pairScreen = shard.pairScreens{timeIdx};
            validateScreen(localScreen, ...
                'formation-local-h3-opened-return-screen-v1', ...
                presetName, seed, currentTime);
            validateScreen(pairScreen, ...
                ['formation-conservative-pair-h3-opened-', ...
                 'return-screen-v1'], ...
                presetName, seed, currentTime);
            assertReferenceOutcomesEqual(localScreen, pairScreen);
            state = loadFormationH3ObservableState( ...
                presetName, seed, currentTime, ...
                struct('cacheRoot', cacheRoot));
            if ~strcmp(state.cacheSha256, ...
                    localScreen.cacheSha256) || ...
                    ~strcmp(state.cacheSha256, ...
                        pairScreen.cacheSha256)
                error('Formation H=3 multiscale state cache differs.');
            end
            [localFeatures, localNames, localMetadata] = ...
                computeFormationH3ActionFeatures( ...
                    state.context, localScreen.bank, state.groupIds);
            [pairFeatures, pairNames, pairMetadata] = ...
                computeFormationH3ActionFeatures( ...
                    state.context, pairScreen.bank, state.groupIds);
            validateFeaturePair( ...
                localFeatures, pairFeatures, localNames, pairNames, ...
                localMetadata, pairMetadata);
            if isempty(expectedFeatureNames)
                expectedFeatureNames = localNames;
                expectedFeatureContract = ...
                    localMetadata.contractVersion;
            elseif ~isequal(expectedFeatureNames, localNames) || ...
                    ~strcmp(expectedFeatureContract, ...
                        localMetadata.contractVersion)
                error('Formation H=3 feature contract changed across scale.');
            end
            blockCursor = blockCursor + 1;
            blocks(blockCursor) = buildBlock( ...
                presetIdx, presetName, seed, currentTime, ...
                shard.evidenceSplit, state, localScreen, pairScreen, ...
                localFeatures, pairFeatures);
            fprintf([ ...
                'formation H=3 multiscale block %s seed %d t=%d: ', ...
                '%d actions, deployment oracle %s (%+.3f%%)\n'], ...
                presetName, seed, currentTime, ...
                size(blocks(blockCursor).features, 1), ...
                blocks(blockCursor).oracleDeploymentActionName, ...
                blocks(blockCursor).oracleDeploymentGainPercent);
        end
    end
end
if blockCursor ~= blockCount || shardCursor ~= numel(shardPaths) || ...
        numel(unique(teacherCommits)) ~= 1
    error('Formation H=3 multiscale dataset provenance is incomplete.');
end

scaleSummaries = repmat(emptyScaleSummary(), ...
    1, numel(protocol.presets));
scaleGatePassed = true(1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    mask = [blocks.scaleIndex] == presetIdx;
    gains = [blocks(mask).oracleDeploymentGainPercent];
    summary = emptyScaleSummary();
    summary.presetName = protocol.presets{presetIdx};
    summary.stateCount = nnz(mask);
    summary.positiveStateCount = nnz(gains > 1e-12);
    summary.strongStateCount = nnz(gains >= ...
        protocol.strongGainThresholdPercent - 1e-12);
    summary.meanOracleGainPercent = mean(gains);
    summary.positiveGatePassed = ...
        summary.positiveStateCount >= ...
            protocol.minimumPositiveStateCountPerScale;
    summary.strongGateRequired = presetIdx >= 2;
    summary.strongGatePassed = ~summary.strongGateRequired || ...
        summary.strongStateCount >= ...
            protocol.minimumStrongStateCountM24X36;
    summary.meanGateRequired = presetIdx >= 2;
    summary.meanGatePassed = ~summary.meanGateRequired || ...
        summary.meanOracleGainPercent >= ...
            protocol.minimumMeanOracleGainM24X36Percent - 1e-12;
    summary.gatePassed = summary.positiveGatePassed && ...
        summary.strongGatePassed && summary.meanGatePassed;
    scaleSummaries(presetIdx) = summary;
    scaleGatePassed(presetIdx) = summary.gatePassed;
end

dataset = struct();
dataset.contractVersion = ...
    'formation-h3-multiscale-sentinel-dataset-v1';
dataset.protocolId = protocol.id;
dataset.generatedAt = datestr(now, 31);
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.teacherGenerationCommit = teacherCommits{1};
dataset.shardPaths = shardPaths;
dataset.shardSha256 = shardSha256;
dataset.cacheRoot = cacheRoot;
dataset.featureContractVersion = expectedFeatureContract;
dataset.featureNames = expectedFeatureNames;
dataset.targetNames = targetNames;
dataset.blocks = blocks;
dataset.blockCount = numel(blocks);
dataset.trainingBlockCount = nnz(strcmp( ...
    {blocks.evidenceSplit}, 'sentinel-training'));
dataset.developmentBlockCount = nnz(strcmp( ...
    {blocks.evidenceSplit}, 'sentinel-development'));
dataset.actionCount = sum(arrayfun( ...
    @(block) size(block.features, 1), blocks));
dataset.featureCount = numel(expectedFeatureNames);
dataset.targetCount = numel(targetNames);
dataset.scaleSummaries = scaleSummaries;
dataset.oracleHeadroomGatePassed = all(scaleGatePassed);
dataset.featuresUseTruth = false;
dataset.featuresUseFutureMeasurements = false;
dataset.featuresUseFutureOutcome = false;
dataset.targetsUseTruth = true;
dataset.targetsUseFutureMeasurements = true;
dataset.seedIdentifierUsedAsFeature = false;
dataset.sensorIdentifierUsedAsFeature = false;
dataset.formationIdentifierUsedAsFeature = false;
dataset.openedSentinelDevelopmentOnly = true;
dataset.sharedRidgeAuditAuthorized = ...
    dataset.oracleHeadroomGatePassed;
dataset.finalModelTrainingAuthorized = false;
dataset.messagePassingModelAuthorized = false;
dataset.validationClaimAllowed = false;
dataset.reservedValidationSeeds = ...
    protocol.finalValidationSeedsReserved;
dataset.evidenceBoundary = protocol.evidenceBoundary;

if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    'formation_h3_multiscale_sentinel_dataset_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'FORMATION_H3_MULTISCALE_SENTINEL_DATASET_V1.md'));
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Formation H=3 multiscale sentinel dataset: %s\n', ...
    datasetPath);
end

function shard = loadAndValidateShard( ...
        path, protocol, presetIdx, presetName, seed)
if exist(path, 'file') ~= 2
    error('Missing formation H=3 multiscale shard: %s', path);
end
loaded = load(path, 'shard');
if ~isfield(loaded, 'shard')
    error('Formation H=3 multiscale shard variable is missing.');
end
shard = loaded.shard;
required = { ...
    'contractVersion', 'protocolId', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'presetName', 'seed', ...
    'evidenceSplit', 'snapshotTimes', 'cachePaths', ...
    'cacheSha256', 'localScreens', 'pairScreens', ...
    'expectedFormationCount', 'expectedLocalActionCount', ...
    'expectedPairActionCount', 'expectedAugmentedActionCount', ...
    'featuresUseTruth', 'featuresUseFutureMeasurements', ...
    'targetsUseTruth', 'targetsUseFutureMeasurements', ...
    'openedSentinelDevelopmentOnly', ...
    'finalModelTrainingAuthorized', 'validationClaimAllowed'};
expectedSplit = 'sentinel-development';
if ismember(seed, protocol.trainingSeeds)
    expectedSplit = 'sentinel-training';
end
if ~all(isfield(shard, required)) || ...
        ~strcmp(shard.contractVersion, ...
            'formation-h3-multiscale-teacher-shard-v1') || ...
        ~strcmp(shard.protocolId, protocol.id) || ...
        shard.generationTrackedWorktreeDirty || ...
        ~isempty(shard.generationUntrackedSourceFiles) || ...
        ~strcmp(shard.presetName, presetName) || ...
        shard.seed ~= seed || ...
        ~strcmp(shard.evidenceSplit, expectedSplit) || ...
        ~isequal(shard.snapshotTimes, protocol.snapshotTimes) || ...
        shard.expectedFormationCount ~= ...
            protocol.expectedFormationCounts(presetIdx) || ...
        shard.expectedLocalActionCount ~= ...
            protocol.expectedLocalActionCounts(presetIdx) || ...
        shard.expectedPairActionCount ~= ...
            protocol.expectedPairActionCounts(presetIdx) || ...
        shard.expectedAugmentedActionCount ~= ...
            protocol.expectedAugmentedActionCounts(presetIdx) || ...
        shard.featuresUseTruth || ...
        shard.featuresUseFutureMeasurements || ...
        ~shard.targetsUseTruth || ...
        ~shard.targetsUseFutureMeasurements || ...
        ~shard.openedSentinelDevelopmentOnly || ...
        shard.finalModelTrainingAuthorized || ...
        shard.validationClaimAllowed || ...
        numel(shard.localScreens) ~= ...
            numel(protocol.snapshotTimes) || ...
        numel(shard.pairScreens) ~= ...
            numel(protocol.snapshotTimes)
    error('Formation H=3 multiscale shard contract failed.');
end
end

function validateScreen(screen, contract, presetName, seed, currentTime)
required = { ...
    'contractVersion', 'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'cacheSha256', ...
    'presetName', 'seed', 'currentTime', 'horizonSteps', ...
    'bank', 'outcomes', 'records', 'referenceSubsetIndex', ...
    'featuresUseTruth', 'featuresUseFutureMeasurements', ...
    'featuresUseFutureOutcome', 'targetsUseTruth', ...
    'targetsUseFutureMeasurements', 'runtimePolicyUsesTruth', ...
    'openedDevelopmentEvidenceOnly', 'validationClaimAllowed'};
if ~all(isfield(screen, required)) || ...
        ~strcmp(screen.contractVersion, contract) || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.presetName, presetName) || ...
        screen.seed ~= seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= 3 || ...
        screen.featuresUseTruth || ...
        screen.featuresUseFutureMeasurements || ...
        screen.featuresUseFutureOutcome || ...
        ~screen.targetsUseTruth || ...
        ~screen.targetsUseFutureMeasurements || ...
        screen.runtimePolicyUsesTruth || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed || ...
        numel(screen.records) ~= numel(screen.outcomes)
    error('Formation H=3 multiscale screen contract failed.');
end
for outcome = screen.outcomes
    if ~outcome.firstActionExact || outcome.truthUseCount ~= 0 || ...
            outcome.repairCount ~= 0 || ...
            outcome.payloadEmergencyCount ~= 0 || ...
            outcome.infeasibleCount ~= 0 || ...
            ~all(outcome.selectedSensorB3Pass) || ...
            ~all(outcome.selectedFormationB3Pass)
        error('Formation H=3 multiscale runtime gate failed.');
    end
end
end

function validateFeaturePair( ...
        localFeatures, pairFeatures, localNames, pairNames, ...
        localMetadata, pairMetadata)
if ~isequal(localNames, pairNames) || ...
        ~isequal(localFeatures(1, :), pairFeatures(1, :)) || ...
        localMetadata.truthUsed || pairMetadata.truthUsed || ...
        localMetadata.futureOutcomeUsed || ...
        pairMetadata.futureOutcomeUsed || ...
        ~localMetadata.sensorPermutationInvariant || ...
        ~pairMetadata.sensorPermutationInvariant
    error('Formation H=3 multiscale feature contract failed.');
end
end

function block = buildBlock( ...
        scaleIndex, presetName, seed, currentTime, evidenceSplit, ...
        state, localScreen, pairScreen, localFeatures, pairFeatures)
localRecords = localScreen.records;
pairRecords = pairScreen.records(2:end);
actionFeatures = [localFeatures; pairFeatures(2:end, :)];
localTargets = targetMatrix(localScreen);
pairTargets = targetMatrix(pairScreen);
actionTargets = [localTargets; pairTargets(2:end, :)];
actionNames = [{localRecords.actionName}, {pairRecords.actionName}];
actionTypes = [ ...
    repmat({'singleton'}, 1, numel(localRecords)), ...
    repmat({'pair'}, 1, numel(pairRecords))];
actionTypes{localScreen.referenceSubsetIndex} = 'reference';
interventionOrder = [ ...
    double([localRecords.actionIndex] ~= ...
        localScreen.bank.referenceActionIndex), ...
    2 * ones(1, numel(pairRecords))];
trustWeights = [[localRecords.trustWeight], ...
    [pairRecords.trustWeight]];
formationIndices = zeros(numel(actionNames), 2);
for recordIdx = 1:numel(localRecords)
    if localRecords(recordIdx).formationIndex > 0
        formationIndices(recordIdx, 1) = ...
            localRecords(recordIdx).formationIndex;
    end
end
for pairIdx = 1:numel(pairRecords)
    formationIndices(numel(localRecords) + pairIdx, :) = ...
        pairRecords(pairIdx).formationIndices;
end
[additiveBaseTargets, interactionResidualTargets] = ...
    decomposePairTargets( ...
        actionTargets, interventionOrder, ...
        trustWeights, formationIndices);
deploymentFeasible = all(actionTargets >= -1e-12, 2);
feasibleIndices = find(deploymentFeasible);
[oracleGain, localOracleIdx] = max( ...
    actionTargets(feasibleIndices, 1));
oracleActionIdx = feasibleIndices(localOracleIdx);

block = emptyBlock();
block.scaleIndex = scaleIndex;
block.presetName = presetName;
block.seed = seed;
block.currentTime = currentTime;
block.evidenceSplit = evidenceSplit;
block.cachePath = state.cachePath;
block.cacheSha256 = state.cacheSha256;
block.actionNames = actionNames;
block.actionTypes = actionTypes;
block.interventionOrder = interventionOrder;
block.trustWeights = trustWeights;
block.formationIndicesAuditOnly = formationIndices;
block.features = actionFeatures;
block.targets = actionTargets;
block.additiveBaseTargets = additiveBaseTargets;
block.interactionResidualTargets = interactionResidualTargets;
block.deploymentFeasible = deploymentFeasible;
block.oracleDeploymentActionIndex = oracleActionIdx;
block.oracleDeploymentActionName = actionNames{oracleActionIdx};
block.oracleDeploymentGainPercent = oracleGain;
end

function targets = targetMatrix(screen)
records = screen.records;
outcomes = screen.outcomes;
referenceIdx = screen.referenceSubsetIndex;
referenceDelivered = outcomes(referenceIdx).deliveredBytes;
deliveredSaving = zeros(numel(outcomes), 1);
for idx = 1:numel(outcomes)
    deliveredSaving(idx) = 100 * ...
        (referenceDelivered - outcomes(idx).deliveredBytes) / ...
            max(referenceDelivered, eps);
end
targets = [ ...
    reshape([records.meanGainPercent], [], 1), ...
    reshape([records.minimumFormationGainPercent], [], 1), ...
    reshape([records.worstGainPercent], [], 1), ...
    reshape([records.consensusGainPercent], [], 1), ...
    reshape([records.attemptedByteSavingPercent], [], 1), ...
    deliveredSaving];
end

function [base, residual] = decomposePairTargets( ...
        targets, order, trust, formationIndices)
base = targets;
residual = zeros(size(targets));
for actionIdx = find(order == 2)
    formations = formationIndices(actionIdx, :);
    singletonIndices = zeros(1, 2);
    for cursor = 1:2
        match = find(order == 1 & ...
            formationIndices(:, 1)' == formations(cursor) & ...
            abs(trust - trust(actionIdx)) <= 1e-12);
        if numel(match) ~= 1
            error('Formation H=3 pair lacks matching singleton targets.');
        end
        singletonIndices(cursor) = match;
    end
    base(actionIdx, :) = sum(targets(singletonIndices, :), 1);
    residual(actionIdx, :) = targets(actionIdx, :) - ...
        base(actionIdx, :);
end
end

function assertReferenceOutcomesEqual(localScreen, pairScreen)
left = localScreen.outcomes(localScreen.referenceSubsetIndex);
right = pairScreen.outcomes(pairScreen.referenceSubsetIndex);
fields = setdiff(fieldnames(left), {'elapsedSeconds'});
for idx = 1:numel(fields)
    name = fields{idx};
    if ~isfield(right, name) || ...
            ~isequaln(left.(name), right.(name))
        error('Formation H=3 multiscale reference outcomes differ.');
    end
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 multiscale dataset report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 multiscale sentinel dataset\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    dataset.contractVersion, dataset.protocolId);
fprintf(fid, '- Dataset / teacher commit: `%s / %s`\n', ...
    dataset.generationGitCommit, dataset.teacherGenerationCommit);
fprintf(fid, '- Training / development states: `%d / %d`\n', ...
    dataset.trainingBlockCount, dataset.developmentBlockCount);
fprintf(fid, '- Actions / features / targets: `%d / %d / %d`\n', ...
    dataset.actionCount, dataset.featureCount, dataset.targetCount);
fprintf(fid, '- Oracle headroom gate: `%d`\n', ...
    dataset.oracleHeadroomGatePassed);
fprintf(fid, '- Shared ridge / final / GNN / validation authorized: `%d / %d / %d / %d`\n\n', ...
    dataset.sharedRidgeAuditAuthorized, ...
    dataset.finalModelTrainingAuthorized, ...
    dataset.messagePassingModelAuthorized, ...
    dataset.validationClaimAllowed);
fprintf(fid, '| Scale | States | Positive | Strong | Mean oracle | Gate |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|:--:|\n');
for summary = dataset.scaleSummaries
    fprintf(fid, '| `%s` | %d | %d | %d | %+.3f%% | %d |\n', ...
        summary.presetName, summary.stateCount, ...
        summary.positiveStateCount, summary.strongStateCount, ...
        summary.meanOracleGainPercent, summary.gatePassed);
end
fprintf(fid, '\n| Split | Preset | Seed-time | Actions | Oracle | Gain |\n');
fprintf(fid, '|:--|:--|:--|--:|:--|--:|\n');
for block = dataset.blocks
    fprintf(fid, '| `%s` | `%s` | `%d-%d` | %d | `%s` | %+.3f%% |\n', ...
        block.evidenceSplit, block.presetName, ...
        block.seed, block.currentTime, size(block.features, 1), ...
        block.oracleDeploymentActionName, ...
        block.oracleDeploymentGainPercent);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function block = emptyBlock()
block = struct( ...
    'scaleIndex', NaN, 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'evidenceSplit', '', ...
    'cachePath', '', 'cacheSha256', '', ...
    'actionNames', {{}}, 'actionTypes', {{}}, ...
    'interventionOrder', zeros(1, 0), ...
    'trustWeights', zeros(1, 0), ...
    'formationIndicesAuditOnly', zeros(0, 2), ...
    'features', zeros(0, 0), 'targets', zeros(0, 0), ...
    'additiveBaseTargets', zeros(0, 0), ...
    'interactionResidualTargets', zeros(0, 0), ...
    'deploymentFeasible', false(0, 1), ...
    'oracleDeploymentActionIndex', NaN, ...
    'oracleDeploymentActionName', '', ...
    'oracleDeploymentGainPercent', NaN, ...
    'featuresUseTruth', false, ...
    'featuresUseFutureMeasurements', false, ...
    'featuresUseFutureOutcome', false, ...
    'targetsUseTruth', true, ...
    'targetsUseFutureMeasurements', true, ...
    'openedSentinelDevelopmentOnly', true, ...
    'validationClaimAllowed', false);
end

function summary = emptyScaleSummary()
summary = struct( ...
    'presetName', '', 'stateCount', NaN, ...
    'positiveStateCount', NaN, 'strongStateCount', NaN, ...
    'meanOracleGainPercent', NaN, ...
    'positiveGatePassed', false, ...
    'strongGateRequired', false, 'strongGatePassed', false, ...
    'meanGateRequired', false, 'meanGatePassed', false, ...
    'gatePassed', false);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
