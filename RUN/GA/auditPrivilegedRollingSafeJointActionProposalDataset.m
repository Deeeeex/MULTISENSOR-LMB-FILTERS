function [reportPath, audit] = ...
    auditPrivilegedRollingSafeJointActionProposalDataset(options)
% AUDITPRIVILEGEDROLLINGSAFEJOINTACTIONPROPOSALDATASET Formal M24 audit.
%
% Independently replays graph, safety, truth-role, feature and exact-match
% attestations for the frozen offline proposal-distillation targets.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
datasetPath = getField(options, 'datasetPath', ...
    protocol.privilegedProposalDatasetRelativePath);
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
truthFreePath = getField(options, 'truthFreeProposalPath', ...
    protocol.proposalDatasetRelativePath);
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'PRIVILEGED_JOINT_ACTION_PROPOSAL_PREFLIGHT_M24.md'));
validateFrozenFile(datasetPath, ...
    protocol.privilegedProposalDatasetSha256, ...
    'privileged proposal dataset');
validateFrozenFile(sourcePath, ...
    protocol.proposalSourceStateSha256, 'source state');
validateFrozenFile(truthFreePath, ...
    protocol.proposalDatasetSha256, ...
    'truth-free proposal dataset');
loaded = load(datasetPath, 'dataset');
sourceLoaded = load(sourcePath, 'dataset');
truthFreeLoaded = load(truthFreePath, 'dataset');
if ~isfield(loaded, 'dataset') || ...
        ~isfield(sourceLoaded, 'dataset') || ...
        ~isfield(truthFreeLoaded, 'dataset')
    error('Privileged proposal audit MAT file lacks dataset.');
end
dataset = loaded.dataset;
source = sourceLoaded.dataset;
truthFree = truthFreeLoaded.dataset;
validateDatasetEnvelope( ...
    dataset, source, truthFree, protocol);

expectedPairs = frozenSeedTimePairs(protocol);
observedPairs = [[dataset.blocks.seed]', ...
    [dataset.blocks.currentTime]'];
if ~isequal(observedPairs, expectedPairs)
    error(['Privileged proposal blocks do not follow the frozen ', ...
        'seed-time grid.']);
end

maximumFeatureReplayDifference = 0;
minimumFeatureDistance = inf;
featureCollisionCount = 0;
totalDistinct = 0;
totalTargets = 0;
totalExactMatches = 0;
totalCachedDiverseTargets = 0;
blockRows = repmat(struct( ...
    'seed', NaN, 'currentTime', NaN, ...
    'distinctCount', NaN, 'targetCount', NaN, ...
    'exactTruthFreeMatchCount', NaN, ...
    'cachedDiverseTargetCount', NaN, ...
    'minimumFeatureDistance', NaN), ...
    1, numel(dataset.blocks));
for blockIdx = 1:numel(dataset.blocks)
    block = dataset.blocks(blockIdx);
    sourceBlock = source.blocks(block.sourceBlockIndex);
    truthFreeBlock = truthFree.blocks( ...
        block.truthFreeProposalBlockIndex);
    validateBlockIdentity( ...
        block, sourceBlock, truthFreeBlock);
    candidateCount = block.candidateCount;
    targetMask = [block.candidateRecords.eligibleForProposalDistillation];
    if candidateCount < ...
            protocol.privilegedProposalMinimumTargetsPerBlock || ...
            size(block.candidateAdjacency, 3) ~= candidateCount || ...
            size(block.candidateCrossMasks, 2) ~= candidateCount || ...
            size(block.jointFeatures, 1) ~= candidateCount || ...
            numel(block.candidateRecords) ~= candidateCount || ...
            numel(unique(block.candidateGraphSha256)) ~= ...
                candidateCount || ...
            block.distillationTargetCount ~= nnz(targetMask) || ...
            ~all(targetMask)
        error('Privileged proposal block candidate arrays are invalid.');
    end
    validateProposalMetadata( ...
        block.proposalMetadata, protocol);

    nodeCount = numel(sourceBlock.groupIds);
    edgeKeys = sub2ind([nodeCount, nodeCount], ...
        sourceBlock.receiverIndices, ...
        sourceBlock.senderIndices);
    truthFreeHashes = ...
        truthFreeBlock.candidateGraphSha256;
    blockMinimumDistance = inf;
    cachedDiverseCount = 0;
    for candidateIdx = 1:candidateCount
        adjacency = block.candidateAdjacency( ...
            :, :, candidateIdx);
        record = block.candidateRecords(candidateIdx);
        details = record.policyDetails;
        validateCandidateAttestation( ...
            adjacency, record, details, sourceBlock, ...
            candidateIdx);
        actionMask = reshape(logical( ...
            adjacency(edgeKeys)), [], 1);
        if ~isequal(actionMask, ...
                block.candidateCrossMasks(:, candidateIdx))
            error(['Privileged proposal cross mask does not match ', ...
                'its complete graph.']);
        end
        expectedGraphSha256 = computeTextSha256(sprintf( ...
            '%d,', details.selectedSourcesByReceiver));
        if ~strcmp(expectedGraphSha256, ...
                block.candidateGraphSha256{candidateIdx}) || ...
                ~strcmp(expectedGraphSha256, ...
                    record.graphSha256)
            error('Privileged proposal graph SHA-256 failed.');
        end
        featureOptions = struct( ...
            'referenceCrossMask', ...
                truthFreeBlock.candidateCrossMasks( ...
                    :, truthFreeBlock.referenceCandidateIndex), ...
            'actionProposalTruthUsed', true, ...
            'actionProposalOutcomeSelected', false, ...
            'actionProposalSource', ...
                protocol.privilegedProposalBankContractVersion);
        replayed = computeRollingSafeJointActionFeatures( ...
            sourceBlock, actionMask, featureOptions);
        replayDifference = max(abs( ...
            replayed - block.jointFeatures(candidateIdx, :)));
        maximumFeatureReplayDifference = max( ...
            maximumFeatureReplayDifference, replayDifference);

        exactMatches = find(strcmp( ...
            truthFreeHashes, expectedGraphSha256));
        expectedCaptured = ~isempty(exactMatches);
        if logical(block.capturedByTruthFreeBank(candidateIdx)) ~= ...
                expectedCaptured
            error('Truth-free exact-match flag is inconsistent.');
        end
        matchedIndex = ...
            block.matchedTruthFreeCandidateIndex(candidateIdx);
        if expectedCaptured
            if ~isscalar(matchedIndex) || ...
                    ~isfinite(matchedIndex) || ...
                    ~any(exactMatches == matchedIndex) || ...
                    ~isequal(adjacency, ...
                        truthFreeBlock.candidateAdjacency( ...
                            :, :, matchedIndex))
                error('Truth-free exact-match witness is invalid.');
            end
        elseif ~isnan(matchedIndex)
            error('Unmatched privileged graph has a match witness.');
        end
        if record.actionCode >= 90
            if ~isfield(details, ...
                    'diverseTeacherDefaultReused') || ...
                    ~details.diverseTeacherDefaultReused || ...
                    ~details.diverseTeacherScoreReuse
                error('Diverse privileged graph did not reuse scores.');
            end
            cachedDiverseCount = cachedDiverseCount + 1;
        end
        if candidateIdx < candidateCount
            distances = sqrt(sum(( ...
                block.jointFeatures( ...
                    candidateIdx + 1:end, :) - ...
                block.jointFeatures(candidateIdx, :)) .^ 2, 2));
            blockMinimumDistance = min( ...
                blockMinimumDistance, min(distances));
            featureCollisionCount = featureCollisionCount + ...
                nnz(distances <= ...
                    protocol.minimumRegisteredActionDistance);
        end
    end
    exactMatchCount = nnz( ...
        block.capturedByTruthFreeBank);
    minimumFeatureDistance = min( ...
        minimumFeatureDistance, blockMinimumDistance);
    totalDistinct = totalDistinct + candidateCount;
    totalTargets = totalTargets + nnz(targetMask);
    totalExactMatches = ...
        totalExactMatches + exactMatchCount;
    totalCachedDiverseTargets = ...
        totalCachedDiverseTargets + cachedDiverseCount;
    blockRows(blockIdx) = struct( ...
        'seed', block.seed, ...
        'currentTime', block.currentTime, ...
        'distinctCount', candidateCount, ...
        'targetCount', nnz(targetMask), ...
        'exactTruthFreeMatchCount', exactMatchCount, ...
        'cachedDiverseTargetCount', cachedDiverseCount, ...
        'minimumFeatureDistance', blockMinimumDistance);
end

accepted = ...
    totalTargets == ...
        protocol.privilegedProposalExpectedTargetCount && ...
    totalExactMatches == protocol. ...
        privilegedProposalExpectedTruthFreeExactMatchCount && ...
    featureCollisionCount == 0 && ...
    maximumFeatureReplayDifference <= 1e-12 && ...
    all([blockRows.targetCount] >= ...
        protocol.privilegedProposalMinimumTargetsPerBlock);
if ~accepted
    error('Privileged proposal preflight failed frozen gates.');
end
audit = struct();
audit.contractVersion = ...
    protocol.privilegedProposalAuditContractVersion;
audit.protocolId = protocol.id;
audit.datasetPath = datasetPath;
audit.datasetSha256 = ...
    protocol.privilegedProposalDatasetSha256;
audit.generationCommit = dataset.generationGitCommit;
audit.blockCount = numel(dataset.blocks);
audit.totalDistinctCandidateCount = totalDistinct;
audit.totalDistillationTargetCount = totalTargets;
audit.totalExactTruthFreeMatchCount = ...
    totalExactMatches;
audit.totalCachedDiverseTargetCount = ...
    totalCachedDiverseTargets;
audit.minimumTargetsPerBlock = ...
    min([blockRows.targetCount]);
audit.maximumTargetsPerBlock = ...
    max([blockRows.targetCount]);
audit.minimumDistinctGraphFeatureDistance = ...
    minimumFeatureDistance;
audit.featureCollisionCount = featureCollisionCount;
audit.maximumFeatureReplayDifference = ...
    maximumFeatureReplayDifference;
audit.blockRows = blockRows;
audit.acceptedForProposalDistillation = accepted;
audit.acceptedForPairedH3ReturnGeneration = accepted;
audit.acceptedForCriticTraining = false;
audit.acceptedForDeployment = false;
audit.acceptedForX36ZeroShot = false;
writeAuditReport(reportPath, audit, protocol);
fprintf(['Privileged proposal preflight: %d targets, ', ...
    '%d truth-free exact matches, min distance %.8g.\n', ...
    'Report: %s\n'], totalTargets, totalExactMatches, ...
    minimumFeatureDistance, reportPath);
end

function validateDatasetEnvelope( ...
        dataset, source, truthFree, protocol)
if ~strcmp(dataset.contractVersion, ...
        protocol.privilegedProposalDatasetContractVersion) || ...
        ~strcmp(dataset.proposalBankContractVersion, ...
            protocol.privilegedProposalBankContractVersion) || ...
        ~strcmp(dataset.generationGitCommit, ...
            protocol.privilegedProposalDatasetGenerationCommit) || ...
        dataset.generationTrackedWorktreeDirty || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        ~isequal(dataset.seeds, protocol.datasetSeeds) || ...
        ~isequal(dataset.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~isequal(dataset.actionCodes, ...
            protocol.privilegedProposalActionCodes) || ...
        ~strcmp(dataset.sourceStateSha256, ...
            protocol.proposalSourceStateSha256) || ...
        ~strcmp(dataset.truthFreeProposalSha256, ...
            protocol.proposalDatasetSha256) || ...
        ~dataset.truthUsed || dataset.futureOutcomeUsed || ...
        dataset.deployable || dataset.returnEvaluated || ...
        ~strcmp(source.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~strcmp(truthFree.contractVersion, ...
            protocol.proposalDatasetContractVersion)
    error(['Privileged proposal dataset envelope violates the ', ...
        'frozen protocol.']);
end
end

function validateBlockIdentity(block, sourceBlock, truthFreeBlock)
if block.seed ~= sourceBlock.seed || ...
        block.currentTime ~= sourceBlock.currentTime || ...
        block.seed ~= truthFreeBlock.seed || ...
        block.currentTime ~= truthFreeBlock.currentTime
    error('Privileged proposal block identity is misaligned.');
end
end

function validateProposalMetadata(metadata, protocol)
if ~strcmp(metadata.contractVersion, ...
        protocol.privilegedProposalBankContractVersion) || ...
        ~isequal(metadata.actionCodes, ...
            protocol.privilegedProposalActionCodes) || ...
        ~metadata.truthUsed || metadata.futureOutcomeUsed || ...
        metadata.deployable || ...
        metadata.distillationTargetCount < ...
            protocol.privilegedProposalMinimumTargetsPerBlock
    error('Privileged proposal metadata violates the frozen bank.');
end
end

function validateCandidateAttestation( ...
        adjacency, record, details, sourceBlock, candidateIdx)
if record.candidateIndex ~= candidateIdx || ...
        ~record.eligibleForProposalDistillation || ...
        ~ismember(record.actionCode, [0, 90:99]) || ...
        ~islogical(adjacency) || ...
        any(sum(adjacency, 2) ~= 1) || ...
        any(adjacency(:) & ...
            ~sourceBlock.physicalAdjacency(:)) || ...
        ~(details.truthUsed || ...
            details.actionSequenceTruthUsed) || ...
        ~details.oneStepJointProjectionUsed || ...
        ~details.sensorWindowStrongConnected || ...
        ~details.formationWindowStrongConnected || ...
        details.repairTriggered || ...
        details.payloadEmergencyUsed
    error('Privileged proposal safety/truth attestation failed.');
end
if details.oneStepTopologyReserveChecked && ...
        ~details.oneStepTopologyReservePassed
    error('Privileged proposal reserve witness failed.');
end
end

function pairs = frozenSeedTimePairs(protocol)
pairs = zeros(numel(protocol.datasetSeeds) * ...
    numel(protocol.snapshotTimes), 2);
cursor = 0;
for seed = protocol.datasetSeeds
    for currentTime = protocol.snapshotTimes
        cursor = cursor + 1;
        pairs(cursor, :) = [seed, currentTime];
    end
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function writeAuditReport(path, audit, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open privileged proposal audit: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# Privileged joint-action proposal preflight: M24\n\n');
fprintf(fid, '- Generated: %s\n', datestr(now, 31));
fprintf(fid, '- Audit contract: `%s`\n', ...
    audit.contractVersion);
fprintf(fid, '- Protocol: `%s`\n', audit.protocolId);
fprintf(fid, '- Dataset SHA-256: `%s`\n', ...
    audit.datasetSha256);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationCommit);
fprintf(fid, '- Blocks: `%d`\n', audit.blockCount);
fprintf(fid, '- Distinct graphs / targets: `%d / %d`\n', ...
    audit.totalDistinctCandidateCount, ...
    audit.totalDistillationTargetCount);
fprintf(fid, '- Targets per block min/max: `%d / %d`\n', ...
    audit.minimumTargetsPerBlock, ...
    audit.maximumTargetsPerBlock);
fprintf(fid, '- Truth-free exact graph matches: `%d / %d`\n', ...
    audit.totalExactTruthFreeMatchCount, ...
    audit.totalDistillationTargetCount);
fprintf(fid, '- Cached diverse targets: `%d`\n', ...
    audit.totalCachedDiverseTargetCount);
fprintf(fid, '- Minimum distinct-graph feature distance: `%.12g`\n', ...
    audit.minimumDistinctGraphFeatureDistance);
fprintf(fid, '- Feature collisions at <= %.3g: `%d`\n', ...
    protocol.minimumRegisteredActionDistance, ...
    audit.featureCollisionCount);
fprintf(fid, '- Maximum feature replay difference: `%.12g`\n', ...
    audit.maximumFeatureReplayDifference);
fprintf(fid, '- Accepted for proposal distillation: `%d`\n', ...
    audit.acceptedForProposalDistillation);
fprintf(fid, '- Accepted for paired H=3 returns: `%d`\n', ...
    audit.acceptedForPairedH3ReturnGeneration);
fprintf(fid, '- Accepted for critic training: `%d`\n', ...
    audit.acceptedForCriticTraining);
fprintf(fid, '- Accepted for deployment: `%d`\n', ...
    audit.acceptedForDeployment);
fprintf(fid, '- Accepted for X36 zero-shot: `%d`\n\n', ...
    audit.acceptedForX36ZeroShot);
fprintf(fid, '## State blocks\n\n');
fprintf(fid, ['| Seed | Time | Distinct | Targets | ', ...
    'Truth-free exact | Cached diverse | ', ...
    'Minimum feature distance |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
for row = audit.blockRows
    fprintf(fid, ...
        '| %d | %d | %d | %d | %d | %d | %.8g |\n', ...
        row.seed, row.currentTime, row.distinctCount, ...
        row.targetCount, row.exactTruthFreeMatchCount, ...
        row.cachedDiverseTargetCount, ...
        row.minimumFeatureDistance);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, ['PASS: all 18 frozen M24 states contain at least ', ...
    'three distinct, repair-free, exact rolling-B=3 privileged ', ...
    'targets; every action feature replays exactly and all diverse ', ...
    'targets reuse the state-matched teacher score. Paired H=3 ', ...
    'return generation may proceed.\n\n']);
fprintf(fid, '## Research finding and evidence boundary\n\n');
fprintf(fid, ['The frozen truth-free proposal bank exactly matches ', ...
    '0 of 70 privileged target graphs. This establishes an action-', ...
    'space coverage gap, not a tracking-return gap. The artifact ', ...
    'uses truth offline and is not deployable. This audit does not ', ...
    'establish H=3 gain, top-K proposal recall, critic accuracy, ', ...
    'X36 transfer or control-metadata traffic cost.\n']);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
