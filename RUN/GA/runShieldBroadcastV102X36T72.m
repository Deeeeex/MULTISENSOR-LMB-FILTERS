function [reportPath, result] = runShieldBroadcastV102X36T72(options)
% RUNSHIELDBROADCASTV102X36T72 Matched H=6 shield/broadcast probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getShieldBroadcastV102Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ShieldBroadcastV102:DirtySource', ...
        'The V102 probe requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
outputRoot = getField(options, 'outputRoot', ...
    fullfile(protocol.headroomOutputRoot, 'x36_t72_h6'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', 'v102-shield-broadcast', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', 'shield-broadcast-v102', ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', [1, 2], ...
    'receiverMode', protocol.receiverMode, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);

referenceIdx = screen.referenceSubsetIndex;
candidateIdx = find(strcmp({screen.records.actionName}, ...
    'v102-shield-broadcast-h6'), 1);
if isempty(candidateIdx)
    error('ShieldBroadcastV102:MissingPairedArm', ...
        'The V102 bank did not produce the shield/broadcast arm.');
end
reference = screen.records(referenceIdx);
candidate = screen.records(candidateIdx);
referenceOutcome = screen.outcomes(referenceIdx);
candidateOutcome = screen.outcomes(candidateIdx);
referenceByTime = mean(referenceOutcome.eospaBySensorTime, 1);
candidateByTime = mean(candidateOutcome.eospaBySensorTime, 1);
gainByTime = relativeGainPercent(referenceByTime, candidateByTime);
[formationGain, referenceByFormation, candidateByFormation] = ...
    formationGains(referenceOutcome.eospaBySensorTime, ...
        candidateOutcome.eospaBySensorTime, screen.sensorGroupIds);

result = struct();
result.contractVersion = 'shield-broadcast-v102-x36-t72-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.baselineName = protocol.baselineName;
result.receiverMode = protocol.receiverMode;
result.protectionFormationIdsByTime = ...
    protocol.protectionFormationIdsByTime;
result.broadcastFormationIdsByTime = ...
    protocol.broadcastFormationIdsByTime;
result.gatewayIndicesByFormation = ...
    screen.bank.v102Route.gatewayIndicesByFormation;
result.changedReceiverIndicesByTime = ...
    screen.bank.v102Route.changedReceiverIndicesByTime;
result.referenceMeanEospa = reference.meanEospa;
result.candidateMeanEospa = candidate.meanEospa;
result.meanGainPercent = candidate.meanGainPercent;
result.referenceMeanEospaByTime = referenceByTime;
result.candidateMeanEospaByTime = candidateByTime;
result.gainPercentByTime = gainByTime;
result.minimumPostPropagationGainPercent = min( ...
    gainByTime(protocol.formationPropagationDiameter:end));
result.referenceMeanEospaByFormation = referenceByFormation;
result.candidateMeanEospaByFormation = candidateByFormation;
result.formationGainPercent = formationGain;
result.worstSensorGainPercent = candidate.worstGainPercent;
result.minimumFormationGainPercent = candidate.minimumFormationGainPercent;
result.windowConsensusGainPercent = candidate.consensusGainPercent;
result.terminalConsensusGainPercent = ...
    candidate.terminalConsensusGainPercent;
result.attemptedByteSavingPercent = candidate.attemptedByteSavingPercent;
result.selectedB3Passed = candidate.selectedB3Passed;
result.referenceElapsedSeconds = referenceOutcome.elapsedSeconds;
result.candidateElapsedSeconds = candidateOutcome.elapsedSeconds;
result.gatePassed = ...
    result.meanGainPercent >= protocol.minimumMeanGainPercent - 1e-12 && ...
    result.minimumPostPropagationGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    result.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    result.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    result.windowConsensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    result.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    result.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    result.selectedB3Passed;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.screenReportPath = screenReportPath;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'SHIELD_BROADCAST_V102_X36_T72_H6_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'SHIELD_BROADCAST_V102_X36_T72_H6_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V102 X36-t72 H=6 result: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ShieldBroadcastV102:WriteFailed', ...
        'Could not create the V102 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V102 shield/broadcast: X36 t72 H=6\n\n');
fprintf(fid, '- Matched baseline: `%s`\n', result.baselineName);
fprintf(fid, '- Gateways by formation: `%s`\n\n', ...
    mat2str(result.gatewayIndicesByFormation));
fprintf(fid, '| Arm | Mean E-OSPA | Gain vs static | Bytes saving |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
fprintf(fid, '| Static full payload | %.6f | -- | -- |\n', ...
    result.referenceMeanEospa);
fprintf(fid, '| V102 shield/broadcast | %.6f | %+.3f%% | %+.3f%% |\n\n', ...
    result.candidateMeanEospa, result.meanGainPercent, ...
    result.attemptedByteSavingPercent);
fprintf(fid, '| t | Static | V102 | Gain | Broadcast formations |\n');
fprintf(fid, '|--:|--:|--:|--:|:--|\n');
for idx = 1:numel(result.returnTimes)
    fprintf(fid, '| %d | %.6f | %.6f | %+.3f%% | %s |\n', ...
        result.returnTimes(idx), result.referenceMeanEospaByTime(idx), ...
        result.candidateMeanEospaByTime(idx), ...
        result.gainPercentByTime(idx), ...
        mat2str(result.broadcastFormationIdsByTime{idx}));
end
fprintf(fid, '\n- Formation gains: `%s%%`\n', ...
    mat2str(result.formationGainPercent, 4));
fprintf(fid, '- Minimum post-propagation gain: `%+.3f%%`\n', ...
    result.minimumPostPropagationGainPercent);
fprintf(fid, '- Worst sensor / minimum formation: `%+.3f%% / %+.3f%%`\n', ...
    result.worstSensorGainPercent, result.minimumFormationGainPercent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    result.windowConsensusGainPercent, ...
    result.terminalConsensusGainPercent);
fprintf(fid, '- Static / V102 runtime: `%.2f / %.2f s`\n', ...
    result.referenceElapsedSeconds, result.candidateElapsedSeconds);
fprintf(fid, '- Registered gate passed: `%d`\n\n', result.gatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function [gain, referenceMeans, candidateMeans] = formationGains( ...
        referenceBySensorTime, candidateBySensorTime, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
referenceMeans = zeros(1, numel(groups));
candidateMeans = zeros(1, numel(groups));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    referenceValues = referenceBySensorTime(mask, :);
    candidateValues = candidateBySensorTime(mask, :);
    referenceMeans(idx) = mean(referenceValues(:));
    candidateMeans(idx) = mean(candidateValues(:));
end
gain = relativeGainPercent(referenceMeans, candidateMeans);
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
