function [reportPath, result] = ...
    runReliabilityBalancedHomotopyV80Anchors(options)
% RUNRELIABILITYBALANCEDHOMOTOPYV80ANCHORS One-step response curve.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getReliabilityBalancedHomotopyV80Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('BalancedHomotopyV80:DirtySource', ...
        'The V80 response curve requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

records = repmat(emptyCaseRecord(), 1, numel(protocol.cases));
for caseIdx = 1:numel(protocol.cases)
    caseInfo = protocol.cases(caseIdx);
    state = loadFormationH3ObservableState( ...
        caseInfo.presetName, caseInfo.seed, caseInfo.currentTime, ...
        struct('cacheRoot', cacheRoot));
    analysis = buildReceiverFusionAlignedProjectionV73( ...
        state.context, state.groupIds, struct( ...
            'fusionConfig', protocol.fusionConfig));
    referenceAdjacency = analysis.projection.referenceAdjacency;
    referenceWeights = analysis.projection.referenceFusionWeights;
    homotopy = buildReliabilityBalancedWeightHomotopyV80( ...
        state.context, referenceAdjacency, referenceWeights, ...
        protocol.alphaGrid, struct( ...
            'sinkhornTolerance', protocol.sinkhornTolerance, ...
            'sinkhornMaximumIterations', ...
                protocol.sinkhornMaximumIterations, ...
            'effectiveWeightTolerance', ...
                protocol.effectiveWeightTolerance));
    [referenceRound1, referenceRound2] = ...
        buildReferenceRounds( ...
            state, referenceAdjacency, referenceWeights, protocol);
    historicalTriples = caseInfo.v71SelectedSlotTriples;
    alignedTriples = selectedSlotTriples(analysis);
    [historicalAdjacency, historicalWeights, historicalApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            historicalTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    [alignedAdjacency, alignedWeights, alignedApplied] = ...
        buildCandidateRoute(referenceAdjacency, referenceWeights, ...
            alignedTriples, state.groupIds, ...
            caseInfo.directSafeFormationIds);
    historical = evaluateCurve( ...
        state, referenceRound1, referenceRound2, ...
        historicalAdjacency, historicalWeights, ...
        historicalApplied, homotopy, protocol);
    aligned = evaluateCurve( ...
        state, referenceRound1, referenceRound2, ...
        alignedAdjacency, alignedWeights, alignedApplied, ...
        homotopy, protocol);
    record = emptyCaseRecord();
    record.presetName = state.presetName;
    record.seed = state.seed;
    record.currentTime = state.currentTime;
    record.nodeCount = numel(state.groupIds);
    record.formationCount = numel(unique( ...
        state.groupIds, 'stable'));
    record.homotopy = homotopy;
    record.historical = historical;
    record.aligned = aligned;
    records(caseIdx) = record;
    fprintf(['V80 %s t=%d reference=%.4f balanced=%.4f ', ...
        'historical=%s aligned=%s\n'], ...
        state.presetName, state.currentTime, ...
        homotopy.referenceCenteredSpectralNorm, ...
        homotopy.balancedCenteredSpectralNorm, ...
        formatCurve(historical), formatCurve(aligned));
end

allHistoricalHeadroom = true;
allAlignedHeadroom = true;
allHistoricalContract = true;
allAlignedContract = true;
for caseIdx = 1:numel(records)
    allHistoricalHeadroom = allHistoricalHeadroom && ...
        records(caseIdx).historical.positiveBalancingHeadroom;
    allAlignedHeadroom = allAlignedHeadroom && ...
        records(caseIdx).aligned.positiveBalancingHeadroom;
    allHistoricalContract = allHistoricalContract && ...
        records(caseIdx).historical.selectedContractsFromPulse;
    allAlignedContract = allAlignedContract && ...
        records(caseIdx).aligned.selectedContractsFromPulse;
end
result = struct();
result.contractVersion = ...
    'reliability-balanced-homotopy-v80-anchor-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.records = records;
result.allHistoricalPositiveBalancingHeadroom = ...
    allHistoricalHeadroom;
result.allAlignedPositiveBalancingHeadroom = allAlignedHeadroom;
result.allHistoricalSelectedContract = allHistoricalContract;
result.allAlignedSelectedContract = allAlignedContract;
result.crossScaleHeadroomGatePassed = ...
    allHistoricalHeadroom && allAlignedHeadroom && ...
    allHistoricalContract && allAlignedContract;
result.routeExecuted = false;
result.trackingOutcomeRead = false;
result.truthUsed = false;
result.futureMeasurementUsed = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'RELIABILITY_BALANCED_HOMOTOPY_V80_ANCHORS.mat');
reportPath = fullfile(outputRoot, ...
    'RELIABILITY_BALANCED_HOMOTOPY_V80_ANCHORS.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V80 reliability-balanced homotopy: %s\n', reportPath);
end

function [round1, round2] = buildReferenceRounds( ...
        state, adjacency, weights, protocol)
options = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
round1 = fuseRound(state.context.localPosteriorBySensor, ...
    adjacency, weights, state, protocol, options);
round2 = fuseRound(round1, adjacency, weights, ...
    state, protocol, options);
end

function curve = evaluateCurve( ...
        state, referenceRound1, referenceRound2, ...
        candidateAdjacency, candidateWeights, appliedTriples, ...
        homotopy, protocol)
fusionOptions = struct( ...
    'expectedDeliveryWeighting', protocol.expectedDeliveryWeighting);
modeOptions = struct( ...
    'covarianceRegularization', protocol.covarianceRegularization);
rieOptions = struct( ...
    'conditionalEnergyLimit', protocol.recoveryCandidateRieLimit, ...
    'covarianceRegularization', protocol.covarianceRegularization);
initial = state.context.localPosteriorBySensor;
rie = computeReplacementInnovationEnergyV75( ...
    initial, appliedTriples, state.groupIds, ...
    state.context.model, state.context.commConfig, ...
    state.currentTime, rieOptions);
candidateRound1 = fuseRound(initial, candidateAdjacency, ...
    candidateWeights, state, protocol, fusionOptions);
round1 = scoreModes(referenceRound1, candidateRound1, ...
    state.context.model, modeOptions);
responses = repmat(emptyResponse(), 1, numel(homotopy.points));
for alphaIdx = 1:numel(homotopy.points)
    point = homotopy.points(alphaIdx);
    recovered = fuseRound(candidateRound1, homotopy.adjacency, ...
        point.fusionWeights, state, protocol, fusionOptions);
    modes = scoreModes(referenceRound2, recovered, ...
        state.context.model, modeOptions);
    response = emptyResponse();
    response.alpha = point.alpha;
    response.centeredSpectralNorm = ...
        point.centeredSpectralNorm;
    response.centeredOperatorDistanceFromReference = ...
        point.centeredOperatorDistanceFromReference;
    response.centeredEnergy = modes.centeredEnergy;
    response.existenceCenteredEnergy = ...
        modes.existenceCenteredEnergy;
    response.spatialCenteredEnergy = ...
        modes.spatialCenteredEnergy;
    response.commonEnergy = modes.commonEnergy;
    response.contractsFromPulse = ...
        modes.centeredEnergy <= round1.centeredEnergy + 1e-12;
    responses(alphaIdx) = response;
end
score = [[responses.centeredEnergy]', ...
    [responses.alpha]'];
[~, order] = sortrows(score, [1, 2]);
selectedIdx = order(1);
alphaZeroIdx = find(abs([responses.alpha]) <= 1e-12, 1);
positiveIndices = find([responses.alpha] > 0);
[bestPositiveEnergy, bestPositiveLocalIdx] = min( ...
    [responses(positiveIndices).centeredEnergy]);
bestPositiveIdx = positiveIndices(bestPositiveLocalIdx);
curve = struct();
curve.appliedSlotTriples = appliedTriples;
curve.maximumRound1Rie = max( ...
    [rie.formationRecords.maximumConditionalEnergy]);
curve.round1RieSafe = rie.allFormationsSafe;
curve.round1Modes = round1;
curve.responses = responses;
curve.alphaZeroIndex = alphaZeroIdx;
curve.alphaZeroCenteredEnergy = ...
    responses(alphaZeroIdx).centeredEnergy;
curve.bestPositiveAlpha = responses(bestPositiveIdx).alpha;
curve.bestPositiveCenteredEnergy = bestPositiveEnergy;
curve.positiveBalancingHeadroom = bestPositiveEnergy < ...
    curve.alphaZeroCenteredEnergy - 1e-12;
curve.selectedIndex = selectedIdx;
curve.selectedAlpha = responses(selectedIdx).alpha;
curve.selectedCenteredEnergy = ...
    responses(selectedIdx).centeredEnergy;
curve.selectedContractsFromPulse = ...
    responses(selectedIdx).contractsFromPulse;
curve.selectedUsesPositiveBalancing = ...
    responses(selectedIdx).alpha > 0;
curve.truthUsed = false;
curve.futureMeasurementUsed = false;
end

function aggregate = scoreModes( ...
        referencePosteriors, candidatePosteriors, model, options)
modes = computeLmbArmPerturbationModesV77( ...
    referencePosteriors, candidatePosteriors, model, options);
aggregate = modes.aggregate;
end

function posteriors = fuseRound( ...
        posteriors, adjacency, weights, state, protocol, options)
[posteriors, ~] = fuseLmbNetworkWithDirectedWeights( ...
    posteriors, adjacency, weights, state.context.model, ...
    state.context.commConfig, state.currentTime, ...
    protocol.fusionConfig, options);
end

function [adjacency, weights, applied] = buildCandidateRoute( ...
        referenceAdjacency, referenceWeights, triples, ...
        groupIds, safeFormationIds)
adjacency = referenceAdjacency;
weights = referenceWeights;
selected = ismember(groupIds(triples(:, 1)), safeFormationIds);
applied = triples(selected, :);
if isempty(applied)
    error('BalancedHomotopyV80:EmptyCandidate', ...
        'No direct-safe replacement slot was selected.');
end
for rowIdx = 1:size(applied, 1)
    receiverIdx = applied(rowIdx, 1);
    incumbentIdx = applied(rowIdx, 2);
    candidateIdx = applied(rowIdx, 3);
    sourceWeight = weights(receiverIdx, incumbentIdx);
    if sourceWeight <= 0 || ...
            weights(receiverIdx, candidateIdx) > 1e-12
        error('BalancedHomotopyV80:InvalidReplacement', ...
            'A registered replacement does not match the reference row.');
    end
    adjacency(receiverIdx, incumbentIdx) = false;
    adjacency(receiverIdx, candidateIdx) = true;
    weights(receiverIdx, incumbentIdx) = 0;
    weights(receiverIdx, candidateIdx) = sourceWeight;
end
if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        nnz(adjacency) ~= nnz(referenceAdjacency)
    error('BalancedHomotopyV80:BudgetDrift', ...
        'Candidate replacement changed row sums or message count.');
end
end

function triples = selectedSlotTriples(analysis)
indices = reshape(analysis.projection.selectedSlotIndices, 1, []);
triples = zeros(numel(indices), 3);
for outputIdx = 1:numel(indices)
    slot = analysis.transport.slotRecords(indices(outputIdx));
    triples(outputIdx, :) = [ ...
        slot.receiverIdx, slot.incumbentSenderIdx, ...
        slot.bestCandidateSenderIdx];
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('BalancedHomotopyV80:WriteFailed', ...
        'Cannot open V80 report for writing.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V80 reliability-balanced weight homotopy\n\n');
fprintf(fid, '- Cross-scale headroom gate passed: `%d`\n', ...
    result.crossScaleHeadroomGatePassed);
fprintf(fid, '- Tracking outcome available: `0`\n\n');
for caseIdx = 1:numel(result.records)
    record = result.records(caseIdx);
    fprintf(fid, '## %s / t=%d\n\n', ...
        record.presetName, record.currentTime);
    fprintf(fid, '- Nodes / formations: `%d / %d`\n', ...
        record.nodeCount, record.formationCount);
    fprintf(fid, ['- Reference / fully balanced centered norm: ', ...
        '`%.6f / %.6f`\n'], ...
        record.homotopy.referenceCenteredSpectralNorm, ...
        record.homotopy.balancedCenteredSpectralNorm);
    fprintf(fid, '- Sinkhorn iterations / column deviation: `%d / %.3g`\n\n', ...
        record.homotopy.sinkhornIterationCount, ...
        record.homotopy.balancedColumnDeviation);
    writeCurve(fid, 'Historical exact V71/V72 route', ...
        record.historical);
    writeCurve(fid, 'Prospective exact V73 route', ...
        record.aligned);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeCurve(fid, titleText, curve)
fprintf(fid, '### %s\n\n', titleText);
fprintf(fid, '- Applied slot triples: `%s`\n', ...
    mat2str(curve.appliedSlotTriples));
fprintf(fid, '- Round-1 centered energy / RIE maximum: `%.8g / %.6f`\n', ...
    curve.round1Modes.centeredEnergy, curve.maximumRound1Rie);
fprintf(fid, ['- Selected alpha / centered energy / contracts: ', ...
    '`%.3f / %.8g / %d`\n'], ...
    curve.selectedAlpha, curve.selectedCenteredEnergy, ...
    curve.selectedContractsFromPulse);
fprintf(fid, ['- Best positive alpha / headroom over alpha zero: ', ...
    '`%.3f / %d`\n\n'], ...
    curve.bestPositiveAlpha, curve.positiveBalancingHeadroom);
fprintf(fid, ['| Alpha | Operator norm | Distance from reference | ', ...
    'Centered | Existence | Spatial | Common | Contracts |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for responseIdx = 1:numel(curve.responses)
    response = curve.responses(responseIdx);
    fprintf(fid, ['| %.3f | %.6f | %.6f | %.8g | %.8g | ', ...
        '%.8g | %.8g | %d |\n'], ...
        response.alpha, response.centeredSpectralNorm, ...
        response.centeredOperatorDistanceFromReference, ...
        response.centeredEnergy, ...
        response.existenceCenteredEnergy, ...
        response.spatialCenteredEnergy, ...
        response.commonEnergy, response.contractsFromPulse);
end
fprintf(fid, '\n');
end

function text = formatCurve(curve)
text = sprintf('alpha=%.3f center=%.4g headroom=%d contract=%d', ...
    curve.selectedAlpha, curve.selectedCenteredEnergy, ...
    curve.positiveBalancingHeadroom, ...
    curve.selectedContractsFromPulse);
end

function response = emptyResponse()
response = struct( ...
    'alpha', NaN, ...
    'centeredSpectralNorm', NaN, ...
    'centeredOperatorDistanceFromReference', NaN, ...
    'centeredEnergy', NaN, ...
    'existenceCenteredEnergy', NaN, ...
    'spatialCenteredEnergy', NaN, ...
    'commonEnergy', NaN, ...
    'contractsFromPulse', false);
end

function record = emptyCaseRecord()
record = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'nodeCount', 0, ...
    'formationCount', 0, ...
    'homotopy', struct(), ...
    'historical', struct(), ...
    'aligned', struct());
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
