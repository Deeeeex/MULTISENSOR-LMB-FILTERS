function [reportPath, result] = ...
        analyzeTemporalNetworkSupportDwellV196(scaleName, options)
% ANALYZETEMPORALNETWORKSUPPORTDWELLV196 Replay causal support dwell.

if nargin < 2 || isempty(options)
    options = struct();
end
scaleName = upper(char(scaleName));
baseProtocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
entryIdx = find(strcmp({baseProtocol.cases.scaleName}, scaleName), 1);
if isempty(entryIdx)
    error('TemporalSetEntryV196:UnknownScale', ...
        'The requested V99 scale is not registered.');
end
entry = baseProtocol.cases(entryIdx);
if strcmp(scaleName, 'M24')
    currentTime = 104;
else
    currentTime = 72;
end
screenPath = char(getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v194', 'observation_supported_set_safe', ...
    sprintf('%s_seed%d_t%d_h3', ...
        lower(scaleName), entry.seed, currentTime), 'screen', ...
    sprintf( ...
        'TRACKING_ALIGNED_X36_SCHEDULE_H3_%s_SEED%d_T%d_D3.mat', ...
        upper(strrep(entry.presetName, '-', '_')), ...
        entry.seed, currentTime))));
if exist(screenPath, 'file') ~= 2
    error('TemporalSetEntryV196:MissingScreen', ...
        'The paired V194 screen is required.');
end
loaded = load(screenPath, 'screen');
screen = loaded.screen;
names = {screen.records.actionName};
candidateIdx = find(cellfun(@(name) strncmp( ...
    name, 'v99-online-positive-net-', 24), names), 1);
if isempty(candidateIdx) || ...
        ~screen.capturePosteriorSnapshotsEnabled
    error('TemporalSetEntryV196:MissingCandidate', ...
        'The V194 candidate state capture is unavailable.');
end
outcome = screen.outcomes(candidateIdx);
cache = load(screen.cachePath, 'behaviorBundle');
history = cache.behaviorBundle. ...
    preDecisionTopologyHistoryByTime{currentTime};
priorAdjacency = convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
    history.selectedDirectedEdgeHistory);
inputs = generateDynamicTopologyScenarioInputs( ...
    entry.presetName, entry.seed);
groupIds = reshape(inputs.config.sensorGroupIds, 1, []);
pageCount = numel(screen.returnTimes);
records = repmat(emptyRecord(), 1, pageCount);
for pageIdx = 1:pageCount
    time = screen.returnTimes(pageIdx);
    fprintf('V196 %s temporal support page %d/%d: t=%d ...\n', ...
        scaleName, pageIdx, pageCount, time);
    preceding = cat(3, priorAdjacency, ...
        outcome.selectedAdjacency(:, :, 1:max(pageIdx - 1, 0)));
    precedingTimes = [reshape(history.times, 1, []), ...
        screen.returnTimes(1:max(pageIdx - 1, 0))];
    firstHistoryIdx = max(1, size(preceding, 3) - 1);
    preceding = preceding(:, :, firstHistoryIdx:end);
    precedingTimes = precedingTimes(firstHistoryIdx:end);
    currentPosteriors = outcome.localPosteriorSnapshotsByTime{pageIdx};
    context = buildContext(inputs, currentPosteriors, time, ...
        preceding, precedingTimes, screen.missingLabelFusionMode);
    [~, control] = computeFormationRoutingLeverageSignature( ...
        context, groupIds);
    metrics = computeNetworkAdditiveFormationRiskV65( ...
        control, context, groupIds, ...
        baseProtocol.positiveSupportThreshold);
    proposal = selectPositiveNetAddressableRiskSetV97( ...
        metrics, baseProtocol);
    networkCurrent = projectWithSupport( ...
        control, context, groupIds, proposal.selectedFormationIds, ...
        currentPosteriors, baseProtocol.positiveSupportThreshold);
    temporal2 = projectWithSupport( ...
        control, context, groupIds, proposal.selectedFormationIds, ...
        aggregateSupport(outcome.localPosteriorSnapshotsByTime( ...
            max(1, pageIdx - 1):pageIdx)), ...
        baseProtocol.positiveSupportThreshold);
    temporal3 = projectWithSupport( ...
        control, context, groupIds, proposal.selectedFormationIds, ...
        aggregateSupport(outcome.localPosteriorSnapshotsByTime( ...
            max(1, pageIdx - 2):pageIdx)), ...
        baseProtocol.positiveSupportThreshold);
    records(pageIdx) = makeRecord(time, outcome, pageIdx, proposal, ...
        networkCurrent, temporal2, temporal3);
end

result = struct();
result.contractVersion = ...
    'temporal-network-support-dwell-v196-analysis-v1';
result.generatedAt = datestr(now, 31);
result.scaleName = scaleName;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.screenPath = screenPath;
result.records = records;
result.firstPageDesiredReleasePreservedW2 = isequal( ...
    records(1).temporal2ReleaseFormationIds, ...
    records(1).runtimeReleaseFormationIds);
result.firstPageDesiredReleasePreservedW3 = isequal( ...
    records(1).temporal3ReleaseFormationIds, ...
    records(1).runtimeReleaseFormationIds);
result.laterReleaseCountCurrent = totalLaterReleases( ...
    records, 'networkCurrentReleaseFormationIds');
result.laterReleaseCountW2 = totalLaterReleases( ...
    records, 'temporal2ReleaseFormationIds');
result.laterReleaseCountW3 = totalLaterReleases( ...
    records, 'temporal3ReleaseFormationIds');
result.truthUsed = false;
result.futureInformationUsed = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V196 replays the observable local-posterior sequence already visited ', ...
    'by the paired V194 arm. For each current contributing endpoint and ', ...
    'entered label, it takes the maximum detection-association mass over ', ...
    'the current and preceding one or two replay pages. The first page ', ...
    'has no pre-intervention support history and therefore falls back to ', ...
    'current support. No truth, future measurement or tracking outcome ', ...
    'enters the release decision.'];
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v196', 'temporal_network_support_dwell', ...
    lower(scaleName))));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, sprintf( ...
    'TEMPORAL_NETWORK_SUPPORT_DWELL_V196_%s.mat', scaleName));
reportPath = fullfile(outputRoot, sprintf( ...
    'TEMPORAL_NETWORK_SUPPORT_DWELL_V196_%s.md', scaleName));
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V196 %s report: %s\n', scaleName, reportPath);
end

function projection = projectWithSupport( ...
        control, context, groupIds, proposedFormationIds, ...
        supportPosteriors, threshold)
supportContext = context;
supportContext.localPosteriorBySensor = supportPosteriors;
projection = projectObservationSupportedSetSafeV194( ...
    control, supportContext, groupIds, proposedFormationIds, threshold, ...
    struct('supportMode', 'receiver-or-cross-sender'));
end

function aggregated = aggregateSupport(pages)
if isempty(pages) || any(cellfun(@isempty, pages))
    error('TemporalSetEntryV196:MissingPosteriorPage', ...
        'Every causal support page must contain local posteriors.');
end
aggregated = pages{end};
nodeCount = numel(aggregated);
for pageIdx = 1:numel(pages) - 1
    page = pages{pageIdx};
    if ~iscell(page) || numel(page) ~= nodeCount
        error('TemporalSetEntryV196:PosteriorShapeDrift', ...
            'A causal support page has the wrong sensor count.');
    end
    for sensorIdx = 1:nodeCount
        aggregated{sensorIdx} = mergeSensorSupport( ...
            aggregated{sensorIdx}, page{sensorIdx});
    end
end
end

function merged = mergeSensorSupport(current, previous)
merged = current;
for previousIdx = 1:numel(previous)
    matchIdx = find(arrayfun(@(object) ...
        object.birthTime == previous(previousIdx).birthTime && ...
        object.birthLocation == previous(previousIdx).birthLocation, ...
        merged), 1);
    if isempty(matchIdx)
        merged(end + 1) = previous(previousIdx); %#ok<AGROW>
        matchIdx = numel(merged);
    end
    merged(matchIdx).detectionAssociationMass = max( ...
        boundedMass(merged(matchIdx)), boundedMass(previous(previousIdx)));
end
end

function value = boundedMass(object)
value = 0;
if isstruct(object) && isfield(object, 'detectionAssociationMass') && ...
        isscalar(object.detectionAssociationMass) && ...
        isfinite(object.detectionAssociationMass)
    value = min(max(object.detectionAssociationMass, 0), 1);
end
end

function context = buildContext(inputs, localPosterior, currentTime, ...
        preceding, precedingTimes, receiverMode)
nodeCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = localPosterior;
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.triggerConfig.missingLabelFusionMode = receiverMode;
context.currentTime = currentTime;
context.previousAdjacencyHistory = preceding;
context.previousAdjacencyHistoryCount = size(preceding, 3);
context.previousAdjacencyHistoryTimes = precedingTimes;
context.previousAdjacencyHistoryConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
context.previousAdjacencyHistorySource = ...
    'v194-candidate-runtime-posterior-capture';
context.previousAdjacency = preceding(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = 2 * nodeCount;
context.positions = inputs.graphData.positions(:, :, currentTime);
context.edgeScores = [];
context.localInnovationHistory = [];
context.localAssociationConfidenceHistory = [];
context.localNisNormHistory = [];
context.localNisDeviationHistory = [];
context.localUpdateHistoryTimes = zeros(1, 0);
context = buildObservableTopologyPolicyContext(context);
end

function record = makeRecord( ...
        time, outcome, pageIdx, proposal, current, temporal2, temporal3)
record = emptyRecord();
record.currentTime = time;
record.proposedFormationIds = proposal.selectedFormationIds;
record.runtimeReleaseFormationIds = setdiff( ...
    outcome.retentionDebtRequestedFormationIdsByTime{pageIdx}, ...
    outcome.retentionDebtSelectedFormationIdsByTime{pageIdx}, 'stable');
record.networkCurrentReleaseFormationIds = current.releaseFormationIds;
record.temporal2ReleaseFormationIds = temporal2.releaseFormationIds;
record.temporal3ReleaseFormationIds = temporal3.releaseFormationIds;
record.networkCurrentUnsupportedEntryCountByFormation = ...
    current.unsupportedEntryCountByFormation;
record.temporal2UnsupportedEntryCountByFormation = ...
    temporal2.unsupportedEntryCountByFormation;
record.temporal3UnsupportedEntryCountByFormation = ...
    temporal3.unsupportedEntryCountByFormation;
end

function record = emptyRecord()
record = struct( ...
    'currentTime', NaN, ...
    'proposedFormationIds', zeros(1, 0), ...
    'runtimeReleaseFormationIds', zeros(1, 0), ...
    'networkCurrentReleaseFormationIds', zeros(1, 0), ...
    'temporal2ReleaseFormationIds', zeros(1, 0), ...
    'temporal3ReleaseFormationIds', zeros(1, 0), ...
    'networkCurrentUnsupportedEntryCountByFormation', zeros(1, 0), ...
    'temporal2UnsupportedEntryCountByFormation', zeros(1, 0), ...
    'temporal3UnsupportedEntryCountByFormation', zeros(1, 0));
end

function count = totalLaterReleases(records, fieldName)
count = 0;
for recordIdx = 2:numel(records)
    count = count + numel(records(recordIdx).(fieldName));
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('TemporalSetEntryV196:WriteFailed', ...
        'Could not create the V196 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V196 %s temporal network-support dwell replay\n\n', ...
    result.scaleName);
fprintf(fid, ['| t | V99 proposal | V194 release | Current network | ', ...
    '2-page dwell | 3-page dwell |\n']);
fprintf(fid, '|--:|:--|:--|:--|:--|:--|\n');
for record = result.records
    fprintf(fid, '| %d | `%s` | `%s` | `%s` | `%s` | `%s` |\n', ...
        record.currentTime, ...
        mat2str(record.proposedFormationIds), ...
        mat2str(record.runtimeReleaseFormationIds), ...
        mat2str(record.networkCurrentReleaseFormationIds), ...
        mat2str(record.temporal2ReleaseFormationIds), ...
        mat2str(record.temporal3ReleaseFormationIds));
end
fprintf(fid, '\n- First-page desired release preserved (W=2): `%d`\n', ...
    result.firstPageDesiredReleasePreservedW2);
fprintf(fid, '- First-page desired release preserved (W=3): `%d`\n', ...
    result.firstPageDesiredReleasePreservedW3);
fprintf(fid, '- Later current-network releases: `%d`\n', ...
    result.laterReleaseCountCurrent);
fprintf(fid, '- Later W=2 releases: `%d`\n', ...
    result.laterReleaseCountW2);
fprintf(fid, '- Later W=3 releases: `%d`\n\n', ...
    result.laterReleaseCountW3);
fprintf(fid, '## Per-formation unsupported-entry count\n\n');
for record = result.records
    fprintf(fid, '- t=%d current `%s`, W=2 `%s`, W=3 `%s`\n', ...
        record.currentTime, ...
        mat2str(record. ...
            networkCurrentUnsupportedEntryCountByFormation), ...
        mat2str(record.temporal2UnsupportedEntryCountByFormation), ...
        mat2str(record.temporal3UnsupportedEntryCountByFormation));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

