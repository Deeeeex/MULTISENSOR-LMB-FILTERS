function [reportPath, policyPath, summary] = ...
        analyzeCardinalityPressureReliefV175(options)
% ANALYZECARDINALITYPRESSURERELIEFV175 Conditional policy preflight.
%
% A high-confidence first label is followed by a second action only when
% the updated LMB cardinality distribution is sharply concentrated near a
% high-existence MAP boundary. The conditional classifier filters unsafe
% candidates; among survivors, the lowest source-existence label provides
% conservative cardinality relief. All thresholds are current-observable.

if nargin < 1 || isempty(options)
    options = struct();
end
v162 = getObservableOneHopRiskLabelV162Protocol();
v166Path = getField(options, 'v166DatasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v166', 'one_hop_action_value', ...
    'ONE_HOP_LABEL_ACTION_VALUE_DATASET_V166.mat'));
v173Path = getField(options, 'v173DatasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v173', 'conditional_second_action', ...
    'CONDITIONAL_SECOND_LABEL_ACTION_DATASET_V173.mat'));
secondModelPath = getField(options, 'secondModelPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v174', 'conditional_second_action', ...
    'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_MODEL.mat'));
v162ResultPath = getField(options, 'v162ResultPath', fullfile( ...
    v162.headroomOutputRoot, 'x36_t72_h8', ...
    [v162.resultFileStem, '.mat']));
v163SummaryPath = getField(options, 'v163SummaryPath', fullfile( ...
    v162.headroomOutputRoot, 'rmse_repair_preflight', ...
    'OBSERVABLE_ONE_HOP_RMSE_REPAIR_V163_PREFLIGHT.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v175', 'cardinality_pressure_relief'));
thresholds = struct( ...
    'minimumExpectedCardinalityFraction', 0.895, ...
    'minimumMapProbability', 0.60);
synopsisBytesPerLabel = 24;
responseHeaderBytes = 4 * 8;
paths = {v166Path, v173Path, secondModelPath, ...
    v162ResultPath, v163SummaryPath};
if any(cellfun(@(path) exist(path, 'file') ~= 2, paths))
    error('CardinalityPressureReliefV175:MissingInput', ...
        'The registered V166/V173/V174/V162/V163 inputs are required.');
end

v166 = load(v166Path, 'dataset').dataset;
v173 = load(v173Path, 'dataset').dataset;
secondModel = load(secondModelPath, 'model').model;
v162Result = load(v162ResultPath, 'result').result;
v163 = load(v163SummaryPath, 'summary').summary;
validateInputs(v166, v173, secondModel);
[lowerProbability, inSupport] = scoreModel(v173, secondModel);
policyRows = repmat(emptyPolicyRow(), 1, 0);
for cellRecord = reshape(v173.cells, 1, [])
    cellRows = find([v173.rows.cellId] == cellRecord.cellId);
    representative = v173.rows(cellRows(1));
    pressure = pressureReadout( ...
        representative.features, v173.featureNames, thresholds);
    row = emptyPolicyRow();
    row.cellId = cellRecord.cellId;
    row.split = cellRecord.split;
    row.time = cellRecord.time;
    row.formation = cellRecord.formation;
    row.receiver = cellRecord.receiver;
    row.pressureGate = pressure.passed;
    row.expectedCardinalityFraction = ...
        pressure.expectedCardinalityFraction;
    row.mapProbability = pressure.mapProbability;
    row.mapMargin = pressure.mapMargin;
    row.boundaryExistenceGap = pressure.boundaryExistenceGap;
    row.firstExistenceDelta = pressure.firstExistenceDelta;
    row.firstEospaGain = cellRecord.firstEospaGain;
    row.firstRmseGain = cellRecord.firstRmseGain;
    row.firstPayloadBytes = firstPayloadBytes( ...
        v166, cellRecord);
    if pressure.passed
        eligible = cellRows(all(lowerProbability(cellRows, :) > ...
            secondModel.probabilityThreshold, 2));
        if isempty(eligible)
            row.abstained = true;
        else
            sourceEvidenceQuality = featureColumn( ...
                v173.rows(eligible), v173.featureNames, ...
                'source_evidence_quality');
            safetyScore = min(lowerProbability(eligible, :), [], 2);
            labels = reshape([v173.rows(eligible).label], 2, [])';
            sources = [v173.rows(eligible).source]';
            [~, order] = sortrows( ...
                [sourceEvidenceQuality, -safetyScore, labels, sources], ...
                [1, 2, 3, 4, 5]);
            selectedIdx = eligible(order(1));
            selected = v173.rows(selectedIdx);
            row.selected = true;
            row.secondSource = selected.source;
            row.secondLabel = selected.label;
            row.secondSafetyScore = ...
                min(lowerProbability(selectedIdx, :));
            row.secondInAxisBox = inSupport(selectedIdx);
            row.secondEospaGain = selected.eospaGain;
            row.secondRmseGain = selected.rmseGain;
            row.secondPayloadBytes = selected.payloadBytes;
        end
    end
    cell166 = v166.cells([v166.cells.cellId] == cellRecord.cellId);
    row.synopsisBytes = ...
        cell166.physicalNeighborCount * 16 + ...
        cell166.rawCandidateCount * synopsisBytesPerLabel;
    if row.selected
        row.requestBytes = 2 * (16 + 16);
        row.responseBytes = ...
            2 * responseHeaderBytes + ...
            row.firstPayloadBytes + row.secondPayloadBytes;
    else
        row.requestBytes = 16 + 16;
        row.responseBytes = responseHeaderBytes + row.firstPayloadBytes;
    end
    row.totalBytes = row.synopsisBytes + ...
        row.requestBytes + row.responseBytes;
    policyRows(end + 1) = row; %#ok<AGROW>
end

f3Rows = v163.rows([v163.rows.formation] == 3);
f3RmseGain = sum([f3Rows.rmseGain]);
f3AttemptedBytes = sum([f3Rows.attemptedBytes]);
f5Rows = policyRows([policyRows.formation] == 5);
f5FirstRmseGain = sum([f5Rows.firstRmseGain]);
f5SecondRmseGain = sum([f5Rows.secondRmseGain]);
f5TotalRmseGain = f5FirstRmseGain + f5SecondRmseGain;
f5TotalEospaGain = sum([f5Rows.firstEospaGain]) + ...
    sum([f5Rows.secondEospaGain]);
f5AttemptedBytes = sum([f5Rows.totalBytes]);
referenceFormation = v162Result.referenceFormationMeanRmse;
projectedFormation = v162Result.candidateFormationMeanRmse;
groupCount = numel(referenceFormation);
f3Idx = 3;
f5Idx = 5;
windowCount = numel(v162Result.returnTimes);
membersPerFormation = numel(v162Result.targetPeerIndices) + 1;
if groupCount ~= 6 || membersPerFormation ~= 6
    error('CardinalityPressureReliefV175:FormationContractDrift', ...
        'The frozen X36 formation shape changed.');
end
projectedFormation(f3Idx) = projectedFormation(f3Idx) - ...
    f3RmseGain / (membersPerFormation * windowCount);
projectedFormation(f5Idx) = projectedFormation(f5Idx) - ...
    f5TotalRmseGain / (membersPerFormation * windowCount);
projectedFormationGain = 100 * (referenceFormation - ...
    projectedFormation) ./ max(abs(referenceFormation), eps);
additionalAttemptedBytes = f3AttemptedBytes + f5AttemptedBytes;
projectedByteSaving = 100 * ( ...
    v162Result.referenceAttemptedBytes - ...
    (v162Result.candidateMainPathAttemptedBytes + ...
        additionalAttemptedBytes)) / ...
    max(abs(v162Result.referenceAttemptedBytes), eps);
f3PolicyRows = policyRows([policyRows.formation] == 3);
policyGatePassed = ...
    all(~[f3PolicyRows.pressureGate]) && ...
    all([f5Rows.pressureGate]) && ...
    all([f5Rows.selected]) && ...
    all([f5Rows.secondEospaGain] > 0) && ...
    all([f5Rows.secondRmseGain] > 0) && ...
    all(projectedFormationGain >= -1e-12) && ...
    projectedByteSaving >= -1e-12;

summary = struct();
summary.contractVersion = ...
    'cardinality-pressure-relief-v175-preflight-v1';
summary.presetName = v173.presetName;
summary.seed = v173.seed;
summary.thresholds = thresholds;
summary.synopsisBytesPerLabel = synopsisBytesPerLabel;
summary.policyRows = policyRows;
summary.f3AnalyticRmseGain = f3RmseGain;
summary.f3AnalyticAttemptedBytes = f3AttemptedBytes;
summary.f5FirstRmseGain = f5FirstRmseGain;
summary.f5SecondRmseGain = f5SecondRmseGain;
summary.f5TotalRmseGain = f5TotalRmseGain;
summary.f5TotalEospaGain = f5TotalEospaGain;
summary.f5AttemptedBytes = f5AttemptedBytes;
summary.additionalAttemptedBytes = additionalAttemptedBytes;
summary.projectedFormationMeanRmse = projectedFormation;
summary.projectedFormationRmseGainPercent = projectedFormationGain;
summary.projectedByteSavingPercent = projectedByteSaving;
summary.policyGatePassed = policyGatePassed;
summary.truthUsedByPolicy = false;
summary.truthUsedForEvaluation = true;
summary.recursiveEvaluationRun = false;
summary.evidenceBoundary = [ ...
    'V175 is an opened, nonrecursive policy-composition screen. The ', ...
    'first and conditional classifiers use only present posterior and ', ...
    'topology summaries. A frozen high-cardinality-pressure gate enables ', ...
    'a second action; the conditional classifier filters candidates and ', ...
    'minimum source evidence quality is an analytic cardinality-relief ', ...
    'tie-break. ', ...
    'Truth only scores the chosen actions. Bytes conservatively charge ', ...
    'a 24-byte packed synopsis for every raw physical-neighbor label, two ', ...
    'sequential requests and both complete-label responses. Snapshot ', ...
    'deltas are added to V162, so a pass only authorizes an actual ', ...
    'recursive implementation and is not validation.'];

policy = struct();
policy.contractVersion = ...
    'cardinality-pressure-relief-policy-v175-v1';
policy.firstModelPath = v173.firstModelPath;
policy.secondModelPath = secondModelPath;
policy.thresholds = thresholds;
policy.secondCandidateGate = ...
    'raw-conditional-probability-all-heads';
policy.secondCandidateRanking = 'minimum-source-evidence-quality';
policy.maximumSequentialEdits = 2;
policy.synopsisBytesPerLabel = synopsisBytesPerLabel;
policy.featuresUseTruth = false;
policy.numericLabelIdentifiersUsedAsFeatures = false;
policy.preflightGatePassed = policyGatePassed;
policy.recursiveEvaluationRun = false;
policy.deployable = false;
policy.evidenceBoundary = summary.evidenceBoundary;

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
summaryPath = fullfile(outputRoot, ...
    'CARDINALITY_PRESSURE_RELIEF_V175_RESULT.mat');
policyPath = fullfile(outputRoot, ...
    'CARDINALITY_PRESSURE_RELIEF_V175_POLICY.mat');
reportPath = fullfile(outputRoot, ...
    'CARDINALITY_PRESSURE_RELIEF_V175.md');
summary.matPath = summaryPath;
summary.policyPath = policyPath;
summary.reportPath = reportPath;
policy.policyPath = policyPath;
save('-mat7-binary', summaryPath, 'summary');
save('-mat7-binary', policyPath, 'policy');
writeReport(reportPath, summary);
fprintf('V175 cardinality-pressure relief: %s\n', reportPath);
end

function validateInputs(v166, v173, model)
if ~strcmp(v166.contractVersion, ...
        'one-hop-label-action-value-dataset-v166-v1') || ...
        ~strcmp(v173.contractVersion, ...
            'conditional-second-label-action-dataset-v173-v1') || ...
        ~strcmp(model.contractVersion, ...
            'nonlinear-safe-one-hop-label-action-model-v168-v1') || ...
        v166.featuresUseTruth || v173.featuresUseTruth || ...
        model.featuresUseTruth || ...
        model.numericLabelIdentifiersUsedAsFeatures
    error('CardinalityPressureReliefV175:InputContract', ...
        'A registered input contract is invalid.');
end
end

function [lower, inSupport] = scoreModel(dataset, model)
X = vertcat(dataset.rows.features);
if isfield(model, 'featureMask')
    X = X(:, logical(model.featureMask));
end
Z = bsxfun(@rdivide, bsxfun(@minus, X, model.featureMean), ...
    model.featureScale);
inSupport = all(bsxfun(@ge, Z, model.supportLower) & ...
    bsxfun(@le, Z, model.supportUpper), 2);
probability = zeros(size(Z, 1), 3, numel(model.members));
for memberIdx = 1:numel(model.members)
    parameters = model.members{memberIdx}.parameters;
    hidden = tanh(bsxfun(@plus, ...
        Z * parameters{1}, parameters{2}));
    logits = bsxfun(@plus, ...
        hidden * parameters{3}, parameters{4});
    probability(:, :, memberIdx) = stableSigmoid(logits);
end
lower = mean(probability, 3) - ...
    model.uncertaintyPenalty * std(probability, 0, 3);
end

function readout = pressureReadout(features, names, thresholds)
readout = struct();
readout.expectedCardinalityFraction = featureValue( ...
    features, names, 'set_expected_cardinality_fraction');
readout.mapProbability = featureValue( ...
    features, names, 'set_cardinality_map_probability');
readout.mapMargin = featureValue( ...
    features, names, 'set_cardinality_margin');
readout.boundaryExistenceGap = featureValue( ...
    features, names, 'set_map_boundary_existence_gap');
readout.firstExistenceDelta = featureValue( ...
    features, names, 'first_existence_delta');
readout.passed = ...
    readout.expectedCardinalityFraction >= ...
        thresholds.minimumExpectedCardinalityFraction && ...
    readout.mapProbability >= thresholds.minimumMapProbability;
end

function values = featureColumn(rows, names, name)
idx = find(strcmp(names, name), 1);
values = vertcat(rows.features);
values = values(:, idx);
end

function value = featureValue(features, names, name)
idx = find(strcmp(names, name), 1);
value = features(idx);
end

function bytes = firstPayloadBytes(v166, cellRecord)
rows = v166.rows([v166.rows.cellId] == cellRecord.cellId & ...
    [v166.rows.source] == cellRecord.firstSource);
matched = rows(arrayfun(@(row) ...
    isequal(row.label, cellRecord.firstLabel), rows));
if isempty(matched)
    error('CardinalityPressureReliefV175:MissingFirstPayload', ...
        'The V166 first-action payload record is missing.');
end
bytes = matched(1).payloadBytes;
end

function row = emptyPolicyRow()
row = struct( ...
    'cellId', 0, 'split', 0, 'time', 0, 'formation', 0, ...
    'receiver', 0, 'pressureGate', false, 'abstained', false, ...
    'selected', false, 'expectedCardinalityFraction', NaN, ...
    'mapProbability', NaN, 'mapMargin', NaN, ...
    'boundaryExistenceGap', NaN, 'firstExistenceDelta', NaN, ...
    'firstEospaGain', 0, 'firstRmseGain', 0, ...
    'firstPayloadBytes', 0, 'secondSource', 0, ...
    'secondLabel', zeros(2, 1), 'secondSafetyScore', NaN, ...
    'secondInAxisBox', false, 'secondEospaGain', 0, ...
    'secondRmseGain', 0, 'secondPayloadBytes', 0, ...
    'synopsisBytes', 0, 'requestBytes', 0, ...
    'responseBytes', 0, 'totalBytes', 0);
end

function value = stableSigmoid(value)
positive = value >= 0;
negative = ~positive;
result = zeros(size(value));
result(positive) = 1 ./ (1 + exp(-value(positive)));
exponential = exp(value(negative));
result(negative) = exponential ./ (1 + exponential);
value = result;
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('CardinalityPressureReliefV175:ReportOpenFailed', ...
        'Could not open the V175 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V175 cardinality-pressure relief preflight\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    summary.presetName, summary.seed);
fprintf(fid, '- Synopsis bytes per raw source-label: `%d`\n', ...
    summary.synopsisBytesPerLabel);
fprintf(fid, '- Policy gate passed: `%d`\n\n', ...
    summary.policyGatePassed);
fprintf(fid, ['| t | F | Receiver | Pressure | Selected | ', ...
    'First R | Second E/R | Safety | Bytes |\n']);
fprintf(fid, '|--:|--:|--:|:--:|:--:|--:|:--|--:|--:|\n');
for row = summary.policyRows
    fprintf(fid, ['| %d | %d | %d | %d | %d | %+.3f | ', ...
        '%+.3f/%+.3f | %.3f | %d |\n'], ...
        row.time, row.formation, row.receiver, row.pressureGate, ...
        row.selected, row.firstRmseGain, row.secondEospaGain, ...
        row.secondRmseGain, row.secondSafetyScore, row.totalBytes);
end
fprintf(fid, '\n- F5 first / second / total RMSE gain: `%.6f / %.6f / %.6f`\n', ...
    summary.f5FirstRmseGain, summary.f5SecondRmseGain, ...
    summary.f5TotalRmseGain);
fprintf(fid, '- F5 total E-OSPA gain: `%.6f`\n', ...
    summary.f5TotalEospaGain);
fprintf(fid, '- Additional attempted bytes: `%d`\n', ...
    summary.additionalAttemptedBytes);
fprintf(fid, '- Projected byte saving: `%+.3f%%`\n', ...
    summary.projectedByteSavingPercent);
fprintf(fid, '- Projected formation RMSE gain: `%s%%`\n', ...
    mat2str(summary.projectedFormationRmseGainPercent, 5));
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
