function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantFullWindowM24(seed, options)
% RUNLABELSETADAPTIVEDOMINANTFULLWINDOWM24 Closed-loop M24 D-B arm.
%
% The first registered seed also reruns the frozen CCW reference.  The
% summary gate requires this sentinel to reproduce the registered trace
% before saved controls from the remaining seeds may be reused.

if nargin < 1 || isempty(seed)
    seed = 11;
end
if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol. ...
        adaptiveDominantFullWindowTrainingValidationAuthorized || ...
        ~ismember(seed, ...
            protocol.adaptiveDominantFullWindowTrainingSeeds)
    error('Seed is outside the registered adaptive-dominant training gate.');
end

rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_balanced_full_window_v1'));
seedDirectory = fullfile( ...
    rootDirectory, sprintf('seed%d', seed));
includeReference = logical(getField( ...
    options, 'includeReferenceControl', ...
    seed == protocol. ...
        adaptiveDominantFullWindowRestartSentinelSeed));
if includeReference
    armNames = { ...
        protocol.adaptiveDominantFullWindowReferenceArmName, ...
        protocol.adaptiveDominantFullWindowArmName};
else
    armNames = {protocol.adaptiveDominantFullWindowArmName};
end

screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantFullWindowTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantFullWindowTimes(1), ...
    'armNames', {armNames}, ...
    'writeReport', true, ...
    'outputDirectory', seedDirectory, ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'cache')), ...
    'generateMissingBehaviorCache', false, ...
    'evidenceSplit', 'training');
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    'm24-hard', seed, screenOptions);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
