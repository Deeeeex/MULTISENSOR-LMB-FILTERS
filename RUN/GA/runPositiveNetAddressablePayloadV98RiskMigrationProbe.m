function [reportPath, result] = ...
    runPositiveNetAddressablePayloadV98RiskMigrationProbe(options)
% RUNPOSITIVENETADDRESSABLEPAYLOADV98RISKMIGRATIONPROBE X36 t72 diagnosis.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getPositiveNetAddressablePayloadV97Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('PositiveNetAddressableV98:DirtySource', ...
        'The V98 migration probe requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v98', 'risk_migration_probe'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', ...
        'v97-positive-net-addressable-payload', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', 'positive-net-addressable-v97'), ...
    'receiverMode', protocol.receiverMode, ...
    'actionIndices', [1, 3], ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
[screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
    entry.presetName, entry.seed, currentTime, screenOptions);
candidateIdx = find(cellfun(@(name) strncmp( ...
    name, 'v97-positive-net-persistent-', 28), ...
    {screen.records.actionName}), 1);
if isempty(candidateIdx) || ...
        isempty(screen.outcomes(candidateIdx).positiveNetRiskMigrationByTime)
    error('PositiveNetAddressableV98:MissingMigration', ...
        'The V97 candidate did not publish its risk-migration trace.');
end
migration = ...
    screen.outcomes(candidateIdx).positiveNetRiskMigrationByTime;

selectedKeys = arrayfun(@(step) ...
    mat2str(step.selectedFormationIds), migration, ...
    'UniformOutput', false);
initialAddressable = migration(1).addressableFormationIds;
laterAddressable = unique([migration(2:end).addressableFormationIds]);
result = struct();
result.contractVersion = ...
    'positive-net-addressable-v98-risk-migration-result-v1';
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.receiverMode = protocol.receiverMode;
result.screenReportPath = screenReportPath;
result.migration = migration;
result.selectedSetChanged = numel(unique(selectedKeys)) > 1;
result.newlyAddressableFormationIds = ...
    setdiff(laterAddressable, initialAddressable);
result.onlineReselectionMechanismSupported = ...
    result.selectedSetChanged || ...
    ~isempty(result.newlyAddressableFormationIds);
result.truthUsedByMigrationFeatures = false;
result.futureMeasurementsUsedByMigrationFeatures = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;

matPath = fullfile(outputRoot, ...
    'POSITIVE_NET_ADDRESSABLE_V98_RISK_MIGRATION_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'POSITIVE_NET_ADDRESSABLE_V98_RISK_MIGRATION_RESULT.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V98 migration result: %s\n', reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('PositiveNetAddressableV98:WriteFailed', ...
        'Could not create the V98 migration report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V98 X36 t72 within-window risk migration\n\n');
fprintf(fid, '- Preset / seed / start: `%s / %d / %d`\n', ...
    result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Receiver semantics: `%s`\n', result.receiverMode);
fprintf(fid, ['- Features: current pre-fusion posterior, current ', ...
    'geometry and past selected graph only; no truth or future ', ...
    'measurement is used.\n\n']);
fprintf(fid, ['| t | Addressable | Selected positive-net | ', ...
    'Downward crossings | Total risk | Addressable risk | Net benefit |\n']);
fprintf(fid, '|--:|:--|:--|:--|--:|--:|--:|\n');
for step = result.migration
    fprintf(fid, '| %d | %s | %s | %s | %.5f | %.5f | %.5f |\n', ...
        step.time, mat2str(step.addressableFormationIds), ...
        mat2str(step.selectedFormationIds), ...
        mat2str(step.downwardCrossingsByFormation), ...
        step.totalRiskFraction, step.addressableRiskFraction, ...
        step.selectedNetBenefitFraction);
end
fprintf(fid, '\n- Selected set changed: `%d`\n', ...
    result.selectedSetChanged);
fprintf(fid, '- Newly addressable formations: `%s`\n', ...
    mat2str(result.newlyAddressableFormationIds));
fprintf(fid, '- Online re-selection mechanism supported: `%d`\n', ...
    result.onlineReselectionMechanismSupported);
fprintf(fid, '- Validation claim allowed: `0`\n');
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
