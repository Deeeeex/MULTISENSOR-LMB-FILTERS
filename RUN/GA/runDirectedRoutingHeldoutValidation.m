function [reportPath, validation] = ...
    runDirectedRoutingHeldoutValidation(seedList, options)
% RUNDIRECTEDROUTINGHELDOUTVALIDATION Incremental held-out M24/X36 gate.
%
% Each preset/seed pair is run separately so that a long validation leaves
% complete per-seed reports and reusable behavior caches if interrupted.
% The M24 seed-7 t=75 training checkpoint is intentionally excluded from
% the default seed list.

if nargin < 1 || isempty(seedList)
    seedList = [17, 27];
end
if nargin < 2 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
presets = getField(options, 'presets', ...
    {'m24-hard', 'x36-clean-scale'});
if ischar(presets)
    presets = {presets};
end
continuationStartTime = round(getField( ...
    options, 'continuationStartTime', 75));
maxTimeSteps = round(getField(options, 'maxTimeSteps', 77));
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
behaviorCacheDirectory = getField( ...
    options, 'behaviorCacheDirectory', ...
    fullfile(outputDirectory, 'cache'));
modelPath = getField(options, 'directedRoutingModelPath', ...
    fullfile(outputDirectory, 'models', ...
        'directed_routing_knn_m24_t75.mat'));
if ~exist(modelPath, 'file')
    error('Missing directed-routing model: %s', modelPath);
end

records = repmat(emptyRecord(), ...
    numel(seedList), numel(presets));
summaries = cell(numel(seedList), numel(presets));
for seedIdx = 1:numel(seedList)
    seed = seedList(seedIdx);
    for presetIdx = 1:numel(presets)
        presetName = presets{presetIdx};
        fprintf('\nHeld-out directed routing: %s seed %d\n', ...
            presetName, seed);
        screenOptions = struct( ...
            'maxTimeSteps', maxTimeSteps, ...
            'continuationStartTime', continuationStartTime, ...
            'armNames', {{ ...
                'local', 'robust-static', ...
                'learned-directed-routing'}}, ...
            'writeReport', true, ...
            'outputDirectory', outputDirectory, ...
            'behaviorCacheDirectory', behaviorCacheDirectory, ...
            'generateMissingBehaviorCache', true, ...
            'directedRoutingModelPath', modelPath, ...
            'scenarioOverrides', getField( ...
                options, 'scenarioOverrides', struct()), ...
            'fusionOverrides', getField( ...
                options, 'fusionOverrides', struct()));
        [armReportPath, summary] = ...
            runDynamicTopologyOracleGapScreen( ...
                presetName, seed, screenOptions);
        summaries{seedIdx, presetIdx} = summary;
        records(seedIdx, presetIdx) = makeRecord( ...
            presetName, seed, armReportPath, summary);
        record = records(seedIdx, presetIdx);
        fprintf(['HELDOUT_RESULT preset=%s seed=%d E=%.6f ', ...
            'gain_static=%.3f gain_local=%.3f ', ...
            'bytes_ratio=%.3f worst_static=%.3f ', ...
            'worst_local=%.3f status=%s\n'], ...
            record.presetName, record.seed, ...
            record.learnedEospa, record.gainVsStaticPercent, ...
            record.gainVsLocalPercent, ...
            record.attemptedByteRatioPercent, ...
            record.worstNodeGainVsStaticPercent, ...
            record.worstNodeGainVsLocalPercent, ...
            record.status);
    end
end

validation = struct();
validation.generatedAt = datestr(now, 31);
validation.seedList = seedList;
validation.presets = presets;
validation.continuationStartTime = continuationStartTime;
validation.maxTimeSteps = maxTimeSteps;
validation.modelPath = modelPath;
validation.records = records;
validation.summaries = summaries;
validation.allMeanTrackingGatesPass = all( ...
    reshape([records.passesMeanTrackingGate], 1, []));
validation.allStrictTailGatesPass = all( ...
    reshape([records.tailSafeVsStatic], 1, [])) && ...
    all(reshape([records.tailSafeVsLocal], 1, []));
validation.allFeasible = all( ...
    reshape([records.zeroInfeasibility], 1, []));

if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
timestamp = datestr(now, 'yyyymmdd_HHMMSS');
reportPath = fullfile(outputDirectory, sprintf( ...
    'DIRECTED_ROUTING_HELDOUT_T%d_T%d_N%d_%s.md', ...
    continuationStartTime, maxTimeSteps, ...
    numel(seedList), timestamp));
writeReport(reportPath, validation);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'validation');
fprintf('Held-out validation report: %s\n', reportPath);
end

function record = makeRecord( ...
    presetName, seed, reportPath, summary)
directed = summary.decision.directedRouting;
local = findArm(summary.aggregate, 'local');
static = findArm(summary.aggregate, 'robust-static');
learned = findArm(summary.aggregate, 'learned-directed-routing');
record = emptyRecord();
record.presetName = presetName;
record.seed = seed;
record.reportPath = reportPath;
record.status = summary.decision.status;
record.localEospa = local.focusEospa;
record.staticEospa = static.focusEospa;
record.learnedEospa = learned.focusEospa;
record.gainVsStaticPercent = directed.gainVsStaticPercent;
record.gainVsLocalPercent = directed.gainVsLocalPercent;
record.worstNodeGainVsStaticPercent = ...
    directed.worstNodeGainVsStaticPercent;
record.worstNodeGainVsLocalPercent = ...
    directed.worstNodeGainVsLocalPercent;
record.attemptedByteRatioPercent = ...
    directed.attemptedByteRatioPercent;
record.meanDirectedMessageCount = ...
    directed.meanDirectedMessageCount;
record.zeroInfeasibility = directed.zeroInfeasibility;
record.tailSafeVsStatic = directed.tailSafeVsStatic;
record.tailSafeVsLocal = directed.tailSafeVsLocal;
record.passesMeanTrackingGate = ...
    directed.passesMeanTrackingGate;
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Held-out validation is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function record = emptyRecord()
record = struct( ...
    'presetName', '', ...
    'seed', 0, ...
    'reportPath', '', ...
    'status', '', ...
    'localEospa', NaN, ...
    'staticEospa', NaN, ...
    'learnedEospa', NaN, ...
    'gainVsStaticPercent', NaN, ...
    'gainVsLocalPercent', NaN, ...
    'worstNodeGainVsStaticPercent', NaN, ...
    'worstNodeGainVsLocalPercent', NaN, ...
    'attemptedByteRatioPercent', NaN, ...
    'meanDirectedMessageCount', NaN, ...
    'zeroInfeasibility', false, ...
    'tailSafeVsStatic', false, ...
    'tailSafeVsLocal', false, ...
    'passesMeanTrackingGate', false);
end

function writeReport(path, validation)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open held-out report: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Directed-routing held-out validation\n\n');
fprintf(fid, '- Generated: %s\n', validation.generatedAt);
fprintf(fid, '- Seeds: `%s`\n', mat2str(validation.seedList));
fprintf(fid, '- Presets: `%s`\n', strjoin(validation.presets, ', '));
fprintf(fid, '- Window: `[%d %d]`\n', ...
    validation.continuationStartTime, validation.maxTimeSteps);
fprintf(fid, '- Model: `%s`\n', validation.modelPath);
fprintf(fid, '- All mean-tracking gates pass: `%d`\n', ...
    validation.allMeanTrackingGatesPass);
fprintf(fid, '- All strict tail gates pass: `%d`\n', ...
    validation.allStrictTailGatesPass);
fprintf(fid, '- All topology checks feasible: `%d`\n\n', ...
    validation.allFeasible);
fprintf(fid, ['| Preset | Seed | Local E-OSPA | Static E-OSPA | ', ...
    'Learned E-OSPA | Gain vs static | Gain vs local | ', ...
    'Worst gain vs static | Worst gain vs local | ', ...
    'Bytes/static | Routes | Status |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    '--:|--:|:--|\n']);
for record = reshape(validation.records, 1, [])
    fprintf(fid, ['| %s | %d | %.4f | %.4f | %.4f | ', ...
        '%.2f%% | %.2f%% | %.2f%% | %.2f%% | %.2f%% | ', ...
        '%.2f | `%s` |\n'], ...
        record.presetName, record.seed, ...
        record.localEospa, record.staticEospa, ...
        record.learnedEospa, record.gainVsStaticPercent, ...
        record.gainVsLocalPercent, ...
        record.worstNodeGainVsStaticPercent, ...
        record.worstNodeGainVsLocalPercent, ...
        record.attemptedByteRatioPercent, ...
        record.meanDirectedMessageCount, record.status);
end
fprintf(fid, '\n## Evidence boundary\n\n');
fprintf(fid, ['These seeds and time steps are excluded from model fitting. ', ...
    'The runs remain conditional continuations from a common static ', ...
    'prefix, not full-episode estimates. The model was selected on one ', ...
    'M24 seed-7 t=75 dataset, and the KLA path remains the repository ', ...
    'componentwise powered-GM approximation.\n']);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
