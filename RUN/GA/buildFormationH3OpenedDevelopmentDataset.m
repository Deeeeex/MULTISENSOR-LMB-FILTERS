function [datasetPath, dataset] = ...
    buildFormationH3OpenedDevelopmentDataset(options)
% BUILDFORMATIONH3OPENEDDEVELOPMENTDATASET Join observable features/returns.
%
% The five source states and all H=3 outcomes are already opened.  This
% artifact is therefore a representation-development dataset only.  It may
% diagnose feature/target alignment and define the later scalable generator,
% but it cannot train or validate the final online policy.

if nargin < 1 || isempty(options)
    options = struct();
end
presetName = getField(options, ...
    'presetName', 'm24-formation-fov');
seedTimes = getField(options, 'seedTimes', [ ...
    83, 71; 97, 71; 89, 72; 101, 72; 103, 73]);
localRoot = getField(options, 'localRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_mode_h3_v11', 'opened_return_screen', presetName));
pairRoot = getField(options, 'pairRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_pair_h3_v12', 'opened_return_screen', presetName));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v13', 'opened_dataset'));
if ~ischar(presetName) || size(seedTimes, 2) ~= 2 || ...
        isempty(seedTimes) || any(~isfinite(seedTimes(:))) || ...
        any(seedTimes(:) ~= round(seedTimes(:)))
    error('Formation H=3 opened dataset options are invalid.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 dataset requires clean source.');
end

targetNames = { ...
    'mean_tracking_gain_percent', ...
    'minimum_formation_gain_percent', ...
    'worst_sensor_gain_percent', ...
    'consensus_gain_percent', ...
    'attempted_byte_saving_percent', ...
    'delivered_byte_saving_percent'};
blocks = repmat(emptyBlock(), 1, size(seedTimes, 1));
expectedFeatureNames = {};
expectedFeatureContract = '';
localCommits = cell(1, size(seedTimes, 1));
pairCommits = localCommits;
for caseIdx = 1:size(seedTimes, 1)
    seed = seedTimes(caseIdx, 1);
    currentTime = seedTimes(caseIdx, 2);
    state = loadFormationH3ObservableState( ...
        presetName, seed, currentTime, options);
    localPath = fullfile(localRoot, sprintf('seed%d', seed), ...
        sprintf('FORMATION_MODE_H3_%s_SEED%d_T%d.mat', ...
            upper(strrep(presetName, '-', '_')), seed, currentTime));
    pairPath = fullfile(pairRoot, sprintf( ...
        'FORMATION_PAIR_H3_%s_SEED%d_T%d.mat', ...
        upper(strrep(presetName, '-', '_')), seed, currentTime));
    localScreen = loadAndValidateScreen( ...
        localPath, 'formation-local-h3-opened-return-screen-v1', ...
        presetName, seed, currentTime);
    pairScreen = loadAndValidateScreen( ...
        pairPath, ...
        ['formation-conservative-pair-h3-opened-', ...
         'return-screen-v1'], presetName, seed, currentTime);
    assertReferenceOutcomesEqual(localScreen, pairScreen);
    if ~strcmp(state.cacheSha256, localScreen.cacheSha256) || ...
            ~strcmp(state.cacheSha256, pairScreen.cacheSha256)
        error('Formation H=3 state and teacher caches differ.');
    end
    [localFeatures, localNames, localMetadata] = ...
        computeFormationH3ActionFeatures( ...
            state.context, localScreen.bank, state.groupIds);
    [pairFeatures, pairNames, pairMetadata] = ...
        computeFormationH3ActionFeatures( ...
            state.context, pairScreen.bank, state.groupIds);
    if ~isequal(localNames, pairNames) || ...
            ~isequal(localFeatures(1, :), pairFeatures(1, :)) || ...
            localMetadata.truthUsed || pairMetadata.truthUsed || ...
            localMetadata.futureOutcomeUsed || ...
            pairMetadata.futureOutcomeUsed
        error('Formation H=3 feature contracts or references differ.');
    end
    if isempty(expectedFeatureNames)
        expectedFeatureNames = localNames;
        expectedFeatureContract = localMetadata.contractVersion;
    elseif ~isequal(expectedFeatureNames, localNames) || ...
            ~strcmp(expectedFeatureContract, ...
                localMetadata.contractVersion)
        error('Formation H=3 feature contract changed across states.');
    end

    localRecords = localScreen.records;
    pairRecords = pairScreen.records(2:end);
    actionFeatures = [localFeatures; pairFeatures(2:end, :)];
    localTargets = targetMatrix(localScreen);
    pairTargets = targetMatrix(pairScreen);
    actionTargets = [localTargets; pairTargets(2:end, :)];
    actionNames = [ ...
        {localRecords.actionName}, {pairRecords.actionName}];
    actionTypes = [ ...
        repmat({'singleton'}, 1, numel(localRecords)), ...
        repmat({'pair'}, 1, numel(pairRecords))];
    actionTypes{localScreen.referenceSubsetIndex} = 'reference';
    interventionOrder = [ ...
        double([localRecords.actionIndex] ~= ...
            localScreen.bank.referenceActionIndex), ...
        2 * ones(1, numel(pairRecords))];
    trustWeights = [ ...
        [localRecords.trustWeight], [pairRecords.trustWeight]];
    formationIndices = zeros(numel(actionNames), 2);
    for recordIdx = 1:numel(localRecords)
        if localRecords(recordIdx).formationIndex > 0
            formationIndices(recordIdx, 1) = ...
                localRecords(recordIdx).formationIndex;
        end
    end
    for pairIdx = 1:numel(pairRecords)
        formationIndices(numel(localRecords) + pairIdx, :) = ...
            pairRecords(pairIdx).formationIndices;
    end
    [additiveBaseTargets, interactionResidualTargets] = ...
        decomposePairTargets( ...
            actionTargets, interventionOrder, ...
            trustWeights, formationIndices);
    deploymentFeasible = all( ...
        actionTargets >= -1e-12, 2);
    [oracleDeploymentGain, oracleLocalIdx] = max( ...
        actionTargets(deploymentFeasible, 1));
    feasibleIndices = find(deploymentFeasible);
    oracleActionIdx = feasibleIndices(oracleLocalIdx);

    block = emptyBlock();
    block.presetName = presetName;
    block.seed = seed;
    block.currentTime = currentTime;
    block.cachePath = state.cachePath;
    block.cacheSha256 = state.cacheSha256;
    block.localScreenPath = localPath;
    block.pairScreenPath = pairPath;
    block.actionNames = actionNames;
    block.actionTypes = actionTypes;
    block.interventionOrder = interventionOrder;
    block.trustWeights = trustWeights;
    block.formationIndicesAuditOnly = formationIndices;
    block.features = actionFeatures;
    block.targets = actionTargets;
    block.additiveBaseTargets = additiveBaseTargets;
    block.interactionResidualTargets = ...
        interactionResidualTargets;
    block.deploymentFeasible = deploymentFeasible;
    block.oracleDeploymentActionIndex = oracleActionIdx;
    block.oracleDeploymentActionName = actionNames{oracleActionIdx};
    block.oracleDeploymentGainPercent = oracleDeploymentGain;
    block.featuresUseTruth = false;
    block.featuresUseFutureMeasurements = false;
    block.featuresUseFutureOutcome = false;
    block.targetsUseTruth = true;
    block.targetsUseFutureMeasurements = true;
    block.openedDevelopmentEvidenceOnly = true;
    block.validationClaimAllowed = false;
    blocks(caseIdx) = block;
    localCommits{caseIdx} = localScreen.generationGitCommit;
    pairCommits{caseIdx} = pairScreen.generationGitCommit;
    fprintf(['formation H=3 dataset %d-%d: %d actions, ', ...
        'deployment oracle %s (%+.3f%%)\n'], ...
        seed, currentTime, numel(actionNames), ...
        block.oracleDeploymentActionName, ...
        block.oracleDeploymentGainPercent);
end
if numel(unique(localCommits)) ~= 1 || ...
        numel(unique(pairCommits)) ~= 1
    error('Formation H=3 teacher commits vary within a bank.');
end

oracleGains = [blocks.oracleDeploymentGainPercent];
dataset = struct();
dataset.contractVersion = ...
    'formation-h3-opened-development-dataset-v1';
dataset.generatedAt = datestr(now, 31);
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.presetName = presetName;
dataset.seedTimes = seedTimes;
dataset.localTeacherGenerationCommit = localCommits{1};
dataset.pairTeacherGenerationCommit = pairCommits{1};
dataset.featureContractVersion = expectedFeatureContract;
dataset.featureNames = expectedFeatureNames;
dataset.targetNames = targetNames;
dataset.blocks = blocks;
dataset.blockCount = numel(blocks);
dataset.actionCount = sum(arrayfun( ...
    @(block) size(block.features, 1), blocks));
dataset.featureCount = numel(expectedFeatureNames);
dataset.targetCount = numel(targetNames);
dataset.deploymentPositiveStateCount = nnz(oracleGains > 1e-12);
dataset.deploymentStrongStateCount = nnz(oracleGains >= 5 - 1e-12);
dataset.meanDeploymentOracleGainPercent = mean(oracleGains);
dataset.featuresUseTruth = false;
dataset.featuresUseFutureMeasurements = false;
dataset.featuresUseFutureOutcome = false;
dataset.targetsUseTruth = true;
dataset.targetsUseFutureMeasurements = true;
dataset.seedIdentifierUsedAsFeature = false;
dataset.formationIdentifierUsedAsFeature = false;
dataset.openedDevelopmentEvidenceOnly = true;
dataset.finalModelTrainingAuthorized = false;
dataset.validationClaimAllowed = false;
dataset.evidenceBoundary = [ ...
    'All five states and H=3 outcomes were opened before this ', ...
    'representation dataset was built. It may diagnose observable ', ...
    'feature and multi-output target alignment only. It cannot train ', ...
    'or validate the final selector; new disjoint D12, M24, and X36 ', ...
    'state/return datasets are required before model freezing.'];

if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, 'formation_h3_opened_development_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'FORMATION_H3_OPENED_DEVELOPMENT_DATASET_V1.md'));
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Formation H=3 opened dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);
end

function screen = loadAndValidateScreen( ...
        path, contract, presetName, seed, currentTime)
loaded = load(path, 'screen');
if ~isfield(loaded, 'screen')
    error('Formation H=3 teacher screen is missing: %s', path);
end
screen = loaded.screen;
required = { ...
    'contractVersion', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'cacheSha256', ...
    'presetName', 'seed', 'currentTime', 'horizonSteps', ...
    'bank', 'actionIndices', 'outcomes', 'records', ...
    'featuresUseTruth', 'featuresUseFutureMeasurements', ...
    'featuresUseFutureOutcome', 'targetsUseTruth', ...
    'targetsUseFutureMeasurements', 'runtimePolicyUsesTruth', ...
    'openedDevelopmentEvidenceOnly', 'validationClaimAllowed'};
if ~all(isfield(screen, required)) || ...
        ~strcmp(screen.contractVersion, contract) || ...
        ~strcmp(screen.presetName, presetName) || ...
        screen.seed ~= seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= 3 || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        screen.featuresUseTruth || ...
        screen.featuresUseFutureMeasurements || ...
        screen.featuresUseFutureOutcome || ...
        ~screen.targetsUseTruth || ...
        ~screen.targetsUseFutureMeasurements || ...
        screen.runtimePolicyUsesTruth || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed || ...
        numel(screen.records) ~= numel(screen.outcomes)
    error('Formation H=3 teacher screen contract failed.');
end
for outcome = screen.outcomes
    if ~outcome.firstActionExact || outcome.truthUseCount ~= 0 || ...
            outcome.repairCount ~= 0 || ...
            outcome.payloadEmergencyCount ~= 0 || ...
            outcome.infeasibleCount ~= 0 || ...
            ~all(outcome.selectedSensorB3Pass) || ...
            ~all(outcome.selectedFormationB3Pass)
        error('Formation H=3 teacher runtime gate failed.');
    end
end
end

function targets = targetMatrix(screen)
records = screen.records;
outcomes = screen.outcomes;
referenceIdx = screen.referenceSubsetIndex;
referenceDelivered = outcomes(referenceIdx).deliveredBytes;
deliveredSaving = zeros(numel(outcomes), 1);
for idx = 1:numel(outcomes)
    deliveredSaving(idx) = 100 * ...
        (referenceDelivered - outcomes(idx).deliveredBytes) / ...
            max(referenceDelivered, eps);
end
targets = [ ...
    reshape([records.meanGainPercent], [], 1), ...
    reshape([records.minimumFormationGainPercent], [], 1), ...
    reshape([records.worstGainPercent], [], 1), ...
    reshape([records.consensusGainPercent], [], 1), ...
    reshape([records.attemptedByteSavingPercent], [], 1), ...
    deliveredSaving];
end

function [base, residual] = decomposePairTargets( ...
        targets, order, trust, formationIndices)
base = targets;
residual = zeros(size(targets));
for actionIdx = find(order == 2)
    formations = formationIndices(actionIdx, :);
    singletonIndices = zeros(1, 2);
    for cursor = 1:2
        match = find(order == 1 & ...
            formationIndices(:, 1)' == formations(cursor) & ...
            abs(trust - trust(actionIdx)) <= 1e-12);
        if numel(match) ~= 1
            error('Formation H=3 pair lacks matching singleton targets.');
        end
        singletonIndices(cursor) = match;
    end
    base(actionIdx, :) = sum(targets(singletonIndices, :), 1);
    residual(actionIdx, :) = targets(actionIdx, :) - ...
        base(actionIdx, :);
end
end

function assertReferenceOutcomesEqual(localScreen, pairScreen)
left = localScreen.outcomes(localScreen.referenceSubsetIndex);
right = pairScreen.outcomes(pairScreen.referenceSubsetIndex);
fields = setdiff(fieldnames(left), {'elapsedSeconds'});
for idx = 1:numel(fields)
    name = fields{idx};
    if ~isfield(right, name) || ...
            ~isequaln(left.(name), right.(name))
        error('Formation H=3 teacher reference outcomes differ.');
    end
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 dataset report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 opened development dataset\n\n');
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Feature contract: `%s`\n', ...
    dataset.featureContractVersion);
fprintf(fid, '- States / actions / features / targets: `%d / %d / %d / %d`\n', ...
    dataset.blockCount, dataset.actionCount, ...
    dataset.featureCount, dataset.targetCount);
fprintf(fid, '- Deployment-positive states: `%d / %d`\n', ...
    dataset.deploymentPositiveStateCount, dataset.blockCount);
fprintf(fid, '- Deployment-strong states: `%d / %d`\n', ...
    dataset.deploymentStrongStateCount, dataset.blockCount);
fprintf(fid, '- Mean deployment-constrained oracle gain: `%+.3f%%`\n', ...
    dataset.meanDeploymentOracleGainPercent);
fprintf(fid, '- Feature truth/future use: `%d / %d`\n', ...
    dataset.featuresUseTruth, dataset.featuresUseFutureOutcome);
fprintf(fid, '- Final model training / validation authorized: `%d / %d`\n\n', ...
    dataset.finalModelTrainingAuthorized, ...
    dataset.validationClaimAllowed);
fprintf(fid, '| Seed-time | Actions | Deployment oracle | Gain |\n');
fprintf(fid, '|:--|--:|:--|--:|\n');
for block = dataset.blocks
    fprintf(fid, '| `%d-%d` | %d | `%s` | %+.3f%% |\n', ...
        block.seed, block.currentTime, size(block.features, 1), ...
        block.oracleDeploymentActionName, ...
        block.oracleDeploymentGainPercent);
end
fprintf(fid, '\n## Targets\n\n');
for idx = 1:numel(dataset.targetNames)
    fprintf(fid, '%d. `%s`\n', idx, dataset.targetNames{idx});
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function block = emptyBlock()
block = struct( ...
    'presetName', '', 'seed', NaN, 'currentTime', NaN, ...
    'cachePath', '', 'cacheSha256', '', ...
    'localScreenPath', '', 'pairScreenPath', '', ...
    'actionNames', {{}}, 'actionTypes', {{}}, ...
    'interventionOrder', zeros(1, 0), ...
    'trustWeights', zeros(1, 0), ...
    'formationIndicesAuditOnly', zeros(0, 2), ...
    'features', zeros(0, 0), 'targets', zeros(0, 0), ...
    'additiveBaseTargets', zeros(0, 0), ...
    'interactionResidualTargets', zeros(0, 0), ...
    'deploymentFeasible', false(0, 1), ...
    'oracleDeploymentActionIndex', NaN, ...
    'oracleDeploymentActionName', '', ...
    'oracleDeploymentGainPercent', NaN, ...
    'featuresUseTruth', false, ...
    'featuresUseFutureMeasurements', false, ...
    'featuresUseFutureOutcome', false, ...
    'targetsUseTruth', true, ...
    'targetsUseFutureMeasurements', true, ...
    'openedDevelopmentEvidenceOnly', true, ...
    'validationClaimAllowed', false);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
