function [selectionPath, selection] = ...
    runCounterfactualRegretGateV133BaselineSelection(options)
% RUNCOUNTERFACTUALREGRETGATEV133BASELINESELECTION Freeze static carriers.
%
% CW and CCW are paired on the same complete development trajectories.
% The lower full-trajectory mean E-OSPA carrier is frozen independently at
% each scale.  No per-state or per-seed direction selection is allowed.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCounterfactualRegretGateV133Protocol();
outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(protocol.outputRoot, 'baseline_selection'));
overwrite = logical(getField(options, 'overwrite', false));
selectionPath = fullfile(outputDirectory, ...
    'FROZEN_REFERENCE_CARRIER_V133.mat');
reportPath = fullfile(outputDirectory, ...
    'FROZEN_REFERENCE_CARRIER_V133.md');
if exist(selectionPath, 'file') == 2 && ~overwrite
    loaded = load(selectionPath, 'selection');
    if ~isfield(loaded, 'selection') || ...
            ~strcmp(loaded.selection.protocolId, protocol.id) || ...
            ~isequal(loaded.selection.developmentSeeds, ...
                protocol.developmentSeeds)
        error('CounterfactualRegretV133:BaselineSelectionDrift', ...
            'The existing carrier selection does not match V133.');
    end
    selection = loaded.selection;
    fprintf('Reused V133 carrier selection: %s\n', selectionPath);
    return;
end

caseSelections = repmat(emptyCaseSelection(), ...
    1, numel(protocol.scaleCases));
for caseIdx = 1:numel(protocol.scaleCases)
    caseInfo = protocol.scaleCases(caseIdx);
    record = repmat(emptyRecord(), ...
        numel(protocol.developmentSeeds), ...
        numel(protocol.referenceCarrierModes));
    for seedIdx = 1:numel(protocol.developmentSeeds)
        seed = protocol.developmentSeeds(seedIdx);
        inputs = generateDynamicTopologyScenarioInputs( ...
            caseInfo.presetName, seed);
        truth = inputs.groundTruthRfs;
        inputs = isolateRuntimeInputs(inputs);
        for carrierIdx = 1:numel(protocol.referenceCarrierModes)
            carrierMode = protocol.referenceCarrierModes{carrierIdx};
            context = ...
                buildCounterfactualRegretGateV133ExecutionContext( ...
                    caseInfo.presetName, seed, 'development', ...
                    'baseline-selection', inputs.config.simulationLength, ...
                    carrierMode, 0);
            config = buildConfig(inputs.config, carrierMode, protocol);
            rng(seed + protocol.filterSeedOffset);
            timerId = tic;
            [estimates, diagnostics] = ...
                runEventTriggeredDistributedLmbFilter( ...
                    inputs.model, inputs.measurements, ...
                    inputs.sensorTrajectories, inputs.neighborMap, ...
                    inputs.commConfig, config, context);
            elapsedSeconds = toc(timerId);
            auditRuntime(diagnostics, inputs.config.simulationLength);
            record(seedIdx, carrierIdx) = scoreRecord( ...
                estimates, diagnostics, inputs.model, truth, ...
                inputs.config, seed, carrierMode, elapsedSeconds);
            fprintf([ ...
                'V133 baseline %s seed %d %s: full %.4f, ', ...
                'focus %.4f, %.1f MB, %.2f s\n'], ...
                caseInfo.scaleName, seed, carrierMode, ...
                record(seedIdx, carrierIdx).meanEospa, ...
                record(seedIdx, carrierIdx).focusMeanEospa, ...
                record(seedIdx, carrierIdx).attemptedBytes / 1e6, ...
                elapsedSeconds);
        end
    end
    means = zeros(1, numel(protocol.referenceCarrierModes));
    focusMeans = means;
    for carrierIdx = 1:numel(protocol.referenceCarrierModes)
        means(carrierIdx) = mean([record(:, carrierIdx).meanEospa]);
        focusMeans(carrierIdx) = mean( ...
            [record(:, carrierIdx).focusMeanEospa]);
    end
    [~, selectedIdx] = min(means);
    rejectedIdx = setdiff(1:numel(means), selectedIdx);
    pairedGain = 100 * (means(rejectedIdx) - means(selectedIdx)) / ...
        max(means(rejectedIdx), eps);
    caseSelections(caseIdx) = struct( ...
        'scaleName', caseInfo.scaleName, ...
        'presetName', caseInfo.presetName, ...
        'carrierModes', {protocol.referenceCarrierModes}, ...
        'records', record, ...
        'meanEospaByCarrier', means, ...
        'focusMeanEospaByCarrier', focusMeans, ...
        'selectedCarrierMode', ...
            protocol.referenceCarrierModes{selectedIdx}, ...
        'selectedCarrierIndex', selectedIdx, ...
        'selectionGainPercent', pairedGain, ...
        'selectionRule', protocol.referenceCarrierSelectionRule, ...
        'perStateOracleSelectionUsed', false);
end

gitState = resolveResearchGitState();
selection = struct();
selection.contractVersion = ...
    'counterfactual-regret-gate-v133-frozen-carrier-selection-v1';
selection.protocolId = protocol.id;
selection.developmentSeeds = protocol.developmentSeeds;
selection.cases = caseSelections;
selection.selectionMetric = 'complete-trajectory-paired-mean-eospa';
selection.perStateOracleSelectionUsed = false;
selection.generationGitCommit = gitState.commit;
selection.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
selection.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
selection.validationClaimAllowed = false;
selection.reportingDisposition = ...
    'repository-method-record-until-final-tracking-gate-passes';
selection.evidenceBoundary = protocol.evidenceBoundary;
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
save('-mat7-binary', selectionPath, 'selection');
writeReport(reportPath, selection);
selection.reportPath = reportPath;
selection.selectionPath = selectionPath;
fprintf('V133 frozen carrier selection: %s\n', selectionPath);
end

function config = buildConfig(scenarioConfig, carrierMode, protocol)
config = buildMixtureAwareKlaReferenceConfig(struct( ...
    'missingLabelFusionMode', 'fov-aware-censored', ...
    'missingNeighborWeightMode', ...
        protocol.actionContract.primaryMissingNeighborWeightMode));
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenarioConfig.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * scenarioConfig.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicySensorObservationEnabled = true;
config.topologyPolicyName = protocol.outcomePolicyName;
config.v133ReferenceCarrierMode = carrierMode;
config.topologyPolicyFcn = @(context) ...
    selectBackboneResidualSplicedCyclePolicy( ...
        context, carrierMode, protocol.routeWeights);
config.receiverSafeLabelFusionEnabled = false;
end

function record = scoreRecord( ...
        estimates, diagnostics, model, truth, scenarioConfig, ...
        seed, carrierMode, elapsedSeconds)
nodeCount = numel(estimates);
timeCount = numel(truth.x);
eospa = zeros(nodeCount, timeCount);
for sensorIdx = 1:nodeCount
    [sensorEospa, ~, ~] = computeSimulationOspa( ...
        model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa;
end
focusWindow = scenarioConfig.focusWindow(1): ...
    scenarioConfig.focusWindow(2);
focusEospa = eospa(:, focusWindow);
record = struct( ...
    'seed', seed, ...
    'carrierMode', carrierMode, ...
    'meanEospa', mean(eospa(:)), ...
    'focusMeanEospa', mean(focusEospa(:)), ...
    'worstSensorEospa', max(mean(eospa, 2)), ...
    'attemptedBytes', sum(diagnostics.attemptedPayloadBytes(:)), ...
    'deliveredBytes', sum(diagnostics.payloadBytes(:)), ...
    'elapsedSeconds', elapsedSeconds, ...
    'policyTruthUsed', any(finiteLogical( ...
        diagnostics.topologyPolicyTruthUsed)), ...
    'policyFutureOutcomeUsed', false);
end

function auditRuntime(diagnostics, timeCount)
times = 1:timeCount;
if any(finiteLogical(diagnostics.topologyPolicyTruthUsed(times))) || ...
        any(finiteLogical( ...
            diagnostics.topologyPolicyRepairTriggered(times))) || ...
        any(finiteLogical( ...
            diagnostics.topologyPolicyPayloadEmergencyUsed(times))) || ...
        any(~diagnostics.topologyFeasible(times)) || ...
        any(finiteLogical(diagnostics. ...
            topologyPolicyTopologyInfeasible(times)))
    error('CounterfactualRegretV133:BaselineRuntimeGateFailure', ...
        'A V133 fixed carrier violated a hard runtime gate.');
end
end

function inputs = isolateRuntimeInputs(inputs)
inputs = rmfield(inputs, { ...
    'groundTruth', 'groundTruthRfs', 'targetTrajectories'});
model = inputs.model;
if isfield(model, 'explicitTargetTrajectories')
    model = rmfield(model, 'explicitTargetTrajectories');
end
present = intersect({'targetTrajectories', 'target'}, ...
    fieldnames(model.dynamicTopologyScenario), 'stable');
if ~isempty(present)
    model.dynamicTopologyScenario = rmfield( ...
        model.dynamicTopologyScenario, present);
end
inputs.model = model;
end

function writeReport(path, selection)
fileId = fopen(path, 'w');
if fileId < 0
    error('CounterfactualRegretV133:ReportWriteFailed', ...
        'Could not open the V133 baseline report.');
end
cleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
fprintf(fileId, '# V133 frozen reference carriers\n\n');
fprintf(fileId, ['Selection uses complete development trajectories, ', ...
    'paired inputs, and no per-state direction oracle.\n\n']);
fprintf(fileId, '| Scale | CW E-OSPA | CCW E-OSPA | Selected | Gain |\n');
fprintf(fileId, '|---|---:|---:|---|---:|\n');
for caseInfo = selection.cases
    fprintf(fileId, '| %s | %.4f | %.4f | %s | %.3f%% |\n', ...
        caseInfo.scaleName, caseInfo.meanEospaByCarrier(1), ...
        caseInfo.meanEospaByCarrier(2), ...
        caseInfo.selectedCarrierMode, ...
        caseInfo.selectionGainPercent);
end
fprintf(fileId, '\nThis is a repository method record, not a main-document result.\n');
end

function value = finiteLogical(value)
value = isfinite(value) & value ~= 0;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end

function value = emptyRecord()
value = struct( ...
    'seed', 0, 'carrierMode', '', ...
    'meanEospa', NaN, 'focusMeanEospa', NaN, ...
    'worstSensorEospa', NaN, ...
    'attemptedBytes', NaN, 'deliveredBytes', NaN, ...
    'elapsedSeconds', NaN, ...
    'policyTruthUsed', false, ...
    'policyFutureOutcomeUsed', false);
end

function value = emptyCaseSelection()
value = struct( ...
    'scaleName', '', 'presetName', '', ...
    'carrierModes', {cell(1, 0)}, ...
    'records', repmat(emptyRecord(), 0, 0), ...
    'meanEospaByCarrier', [], ...
    'focusMeanEospaByCarrier', [], ...
    'selectedCarrierMode', '', ...
    'selectedCarrierIndex', 0, ...
    'selectionGainPercent', NaN, ...
    'selectionRule', '', ...
    'perStateOracleSelectionUsed', false);
end
