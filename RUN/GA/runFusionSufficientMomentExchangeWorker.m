function workerResult = runFusionSufficientMomentExchangeWorker( ...
    batchPlanPath, seed, outputPath, testOverrides)
% RUNFUSIONSUFFICIENTMOMENTEXCHANGEWORKER Execute one frozen paired seed.

if nargin < 4 || isempty(testOverrides)
    testOverrides = struct();
end
testMode = isfield(testOverrides, 'enabled') && ...
    isequal(testOverrides.enabled, true);
batchPlanPath = char(batchPlanPath);
outputPath = char(outputPath);
validateSeed(seed);
if exist(batchPlanPath, 'file') ~= 2
    error('FusionSufficientWorker:MissingPlan', ...
        'Batch plan does not exist: %s', batchPlanPath);
end
if exist(outputPath, 'file') == 2
    error('FusionSufficientWorker:RefuseOverwrite', ...
        'Worker output already exists: %s', outputPath);
end
loaded = load(batchPlanPath);
if ~isfield(loaded, 'config') || ~isfield(loaded, 'parallelPlan')
    error('FusionSufficientWorker:InvalidPlan', ...
        'Batch plan must contain config and parallelPlan.');
end
config = loaded.config;
parallelPlan = loaded.parallelPlan;
validatePlan(config, parallelPlan, seed, outputPath, testMode);

scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDir));
addpath(projectRoot);
addpath(scriptDir);
setPath;
if ~strcmp(projectRoot, char(config.projectRoot))
    error('FusionSufficientWorker:ProjectRoot', ...
        'Worker project root differs from the frozen config.');
end

if testMode
    validateTestMode(config, testOverrides);
    provenance = struct( ...
        'head', config.gitCommit, ...
        'upstream', config.gitCommit, ...
        'runtimeClean', true, ...
        'requiredSourcesSha256', config.requiredSourcesSha256);
else
    if ~isempty(fieldnames(testOverrides))
        error('FusionSufficientWorker:TestOverride', ...
            'Production workers reject test overrides.');
    end
    provenance = assertFusionSufficientGitProvenance(projectRoot);
end
if ~strcmp(provenance.head, config.gitCommit) || ...
        ~strcmp(provenance.requiredSourcesSha256, ...
        config.requiredSourcesSha256)
    error('FusionSufficientWorker:ProvenanceMismatch', ...
        'Worker commit/source manifest differs from the batch plan.');
end
assertFusionSufficientExecutionEnvironment(config);
assertFinalTargetsAbsent(parallelPlan.finalPaths);

overrides = struct( ...
    'includeFinalPeriodicLightVariants', true, ...
    'includeDynamicTopologyVariants', false, ...
    'includeEffectiveKlaGraphVariants', false, ...
    'includeLightFloorVariants', false, ...
    'includePayloadRefinementVariants', false, ...
    'skipCalibrationForStaticPair', true, ...
    'paperStaticPair', true, ...
    'capturePosteriorSnapshots', true, ...
    'simulationLength', config.simulationLength);
[~, summary] = ...
    runMultisensorFilters_formation_4plus4_DualThresholdEventTriggerCompare( ...
        1, seed - 1, true, false, 'default', ...
        config.internalArmSelectors, overrides);
summary = canonicalizeArmNames(summary, config);
assertFusionSufficientFrozenRun(summary, config, seed);

workerResult = struct();
workerResult.workerSchema = config.workerSchema;
workerResult.evidenceSchema = config.evidenceSchema;
workerResult.gitCommit = config.gitCommit;
workerResult.requiredSourcesSha256 = config.requiredSourcesSha256;
workerResult.configSha256 = config.configSha256;
workerResult.summarySha256 = hashFusionSufficientValue(summary);
workerResult.octaveVersion = version();
workerResult.seed = seed;
workerResult.exactGatePassed = true;
workerResult.config = config;
workerResult.summary = summary;
writeWorkerResultAtomically(outputPath, workerResult);
end

function validatePlan(config, plan, seed, outputPath, testMode)
requiredConfig = {'evidenceSchema', 'workerSchema', 'testOnly', ...
    'gitCommit', ...
    'requiredSourcesSha256', 'configSha256', 'octaveVersion', ...
    'maxWorkers', 'firstSeed', 'lastSeed', 'numberOfTrials', ...
    'projectRoot', 'simulationLength', 'armSelection', ...
    'internalArmSelectors'};
for fieldIdx = 1:numel(requiredConfig)
    if ~isfield(config, requiredConfig{fieldIdx})
        error('FusionSufficientWorker:InvalidConfig', ...
            'Frozen config is missing %s.', requiredConfig{fieldIdx});
    end
end

if testMode
    validSchema = isequal(config.testOnly, true) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-test-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-test-v2') && ...
        strncmp(config.artifactStem, 'TEST_', 5) && ...
        strncmp(config.batchIdentity, 'test-', 5);
else
    validSchema = isequal(config.testOnly, false) && ...
        strcmp(config.evidenceSchema, ...
        'fusion-sufficient-moment-exchange-v2') && ...
        strcmp(config.workerSchema, ...
        'fusion-sufficient-seed-worker-v2');
end
if ~validSchema || config.maxWorkers ~= 6
    error('FusionSufficientWorker:InvalidConfig', ...
        'Worker schema or fixed worker limit differs from v2.');
end
if ~strcmp(hashFusionSufficientConfig(config), config.configSha256)
    error('FusionSufficientWorker:ConfigHash', ...
        'Frozen config SHA-256 does not match its content.');
end
expectedPlan = buildFusionSufficientParallelPlan(config);
if ~isstruct(plan) || ~strcmp(plan.schema, ...
        'fusion-sufficient-parallel-plan-v2') || ...
        ~strcmp(plan.configSha256, config.configSha256) || ...
        plan.maxWorkers ~= config.maxWorkers || ...
        ~isequal(plan.workerSeeds, ...
        config.firstSeed:config.lastSeed) || ...
        ~isequaln(orderfields(plan), orderfields(expectedPlan))
    error('FusionSufficientWorker:InvalidPlan', ...
        'Parallel plan differs from the frozen config.');
end
seedIdx = find(plan.workerSeeds == seed);
if ~isscalar(seedIdx)
    error('FusionSufficientWorker:UnexpectedSeed', ...
        'Seed %d is not a unique member of the frozen batch.', seed);
end
if ~strcmp(outputPath, plan.workerMatPaths{seedIdx})
    error('FusionSufficientWorker:OutputPath', ...
        'Worker output path differs from the deterministic plan.');
end
end

function summary = canonicalizeArmNames(summary, config)
if ~isequal(summary.armNames, config.internalArmSelectors) || ...
        numel(summary.arms) ~= numel(config.armSelection)
    error('FusionSufficientWorker:LegacyArmLookup', ...
        'Generic runner did not return the expected internal arm lookup.');
end
summary.armNames = config.armSelection;
for armIdx = 1:numel(summary.arms)
    summary.arms(armIdx).name = config.armSelection{armIdx};
end
summary.equivalence.baselineArm = config.armSelection{1};
end

function validateTestMode(config, testOverrides)
if ~isfield(config, 'testOnly') || ~isequal(config.testOnly, true) || ...
        ~isfield(testOverrides, 'skipGitProvenance') || ...
        ~isequal(testOverrides.skipGitProvenance, true) || ...
        config.numberOfTrials ~= 1 || ...
        config.firstSeed ~= config.lastSeed || ...
        config.simulationLength < 1 || config.simulationLength > 3
    error('FusionSufficientWorker:UnsafeTestOverride', ...
        ['Test mode requires an explicit test-only single-seed config, ', ...
        'skipGitProvenance=true, and T<=3.']);
end
end

function assertFinalTargetsAbsent(paths)
for pathIdx = 1:numel(paths)
    if exist(paths{pathIdx}, 'file') == 2
        error('FusionSufficientWorker:FinalArtifactExists', ...
            'Final evidence already exists: %s', paths{pathIdx});
    end
end
end

function writeWorkerResultAtomically(outputPath, workerResult)
directory = fileparts(outputPath);
if exist(directory, 'dir') ~= 7
    error('FusionSufficientWorker:MissingDirectory', ...
        'Worker output directory does not exist: %s', directory);
end
temporaryPath = [tempname(directory), '.mat'];
cleanup = onCleanup(@() deleteIfPresent(temporaryPath)); %#ok<NASGU>
save(temporaryPath, 'workerResult', '-v7');
verification = load(temporaryPath);
if ~isfield(verification, 'workerResult') || ...
        ~strcmp(verification.workerResult.summarySha256, ...
        hashFusionSufficientValue(verification.workerResult.summary))
    error('FusionSufficientWorker:TemporaryValidation', ...
        'Temporary worker result failed its content-hash check.');
end
if exist(outputPath, 'file') == 2
    error('FusionSufficientWorker:RefuseOverwrite', ...
        'Worker output appeared before publication: %s', outputPath);
end
linkFusionSufficientFileNoClobber(temporaryPath, outputPath);
delete(temporaryPath);
end

function validateSeed(seed)
if ~isnumeric(seed) || ~isscalar(seed) || ~isreal(seed) || ...
        ~isfinite(seed) || seed ~= floor(seed) || seed < 1
    error('FusionSufficientWorker:InvalidSeed', ...
        'Seed must be a positive integer scalar.');
end
end

function deleteIfPresent(path)
if exist(path, 'file') == 2
    delete(path);
end
end
