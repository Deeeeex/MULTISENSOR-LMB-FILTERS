end

function validateExisting(actual, expected)
required = {'contractVersion', 'protocolId', 'generationGitCommit', ...
    'presetName', 'seed', 'v248ReferenceResultPath', ...
    'v248ReferenceGenerationGitCommit', 'candidate'};
if ~isstruct(actual) || ~isscalar(actual) || ...
        ~all(isfield(actual, required)) || ...
        ~strcmp(actual.contractVersion, expected.contractVersion) || ...
        ~strcmp(actual.protocolId, expected.protocolId) || ...
        ~strcmp(actual.generationGitCommit, ...
            expected.generationGitCommit) || ...
        ~strcmp(actual.presetName, expected.presetName) || ...
        actual.seed ~= expected.seed || ...
        ~strcmp(actual.v248ReferenceResultPath, ...
            expected.v248ReferenceResultPath) || ...
        ~strcmp(actual.v248ReferenceGenerationGitCommit, ...
            expected.v248ReferenceGenerationGitCommit)
    error('EventWindowResidualV258:InvalidResumeState', ...
        'The V258 checkpoint belongs to another source or reference.');
end
end

function arm = attachTopologySummary( ...
        arm, diagnostics, config, protocol)
pages = logical(diagnostics.topologyActiveEdge);
arm.routeMessageCountByTime = reshape( ...
    diagnostics.topologyDirectedMessageCount, 1, []);
arm.routeMessageCountMinimum = min(arm.routeMessageCountByTime);
arm.routeMessageCountMaximum = max(arm.routeMessageCountByTime);
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed);
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed);
strong = false(1, size(pages, 3));
for currentTime = 1:numel(strong)
    strong(currentTime) = ...
        isStronglyConnected(pages(:, :, currentTime)');
end
arm.instantaneousStrongAllTimes = all(strong);
formationCount = numel(unique(config.sensorGroupIds));
arm.minimumBackboneMessageCount = ...
    config.numberOfSensors + 2 * (formationCount - 1);
arm.maximumMessageBudget = ...
    arm.minimumBackboneMessageCount + protocol.maximumTotalResiduals;
timeCount = numel(strong);
arm.eventActiveByTime = false(1, timeCount);
arm.selectedResidualCountByTime = zeros(1, timeCount);
arm.selectedResidualBytesByTime = zeros(1, timeCount);
arm.currentStepParetoSafeByTime = false(1, timeCount);
for currentTime = 1:timeCount
    certificate = ...
        diagnostics.topologyPolicyScheduleCertificate{currentTime};
    if ~isstruct(certificate)
        continue;
    end
    arm.eventActiveByTime(currentTime) = logical(getField( ...
        certificate, 'eventWindowActive', false));
    arm.selectedResidualCountByTime(currentTime) = getField( ...
        certificate, 'selectedResidualCount', 0);
    arm.selectedResidualBytesByTime(currentTime) = getField( ...
        certificate, 'selectedAddedResidualBytes', 0);
    arm.currentStepParetoSafeByTime(currentTime) = logical(getField( ...
        certificate, 'currentStepParetoSafe', false));
end
arm.selectedResidualTimes = find( ...
    arm.selectedResidualCountByTime > 0);
arm.eventResidualPageFraction = mean( ...
    arm.selectedResidualCountByTime(arm.eventActiveByTime) > 0);
arm.maximumSelectedResidualCount = max( ...
    arm.selectedResidualCountByTime);
arm.currentStepParetoSafeAllTimes = ...
    all(arm.currentStepParetoSafeByTime);
selection = reshape(diagnostics.topologyPolicySeconds, 1, []);
selection = selection(isfinite(selection));
arm.meanPolicySelectionSeconds = meanOrNaN(selection);
arm.maximumPolicySelectionSeconds = maxOrNaN(selection);
valid = reshape( ...
    diagnostics.topologyPolicyValidCandidateCount, 1, []);
valid = valid(isfinite(valid));
arm.meanAdmissibleCandidateCount = meanOrNaN(valid);
arm.maximumAdmissibleCandidateCount = maxOrNaN(valid);
end

function assertRuntimeArm(arm, config, protocol)
formationCount = numel(unique(config.sensorGroupIds));
minimumMessages = config.numberOfSensors + 2 * (formationCount - 1);
expectedEvent = false(1, config.simulationLength);
expectedEvent(protocol.activationWindow(1): ...
    protocol.activationWindow(2)) = true;
passed = arm.physicalFeasibilityPassed && ...
    ~arm.policyTruthUsed && ~arm.policyFutureOutcomeUsed && ...
    arm.routeMessageCountMinimum >= minimumMessages && ...
    arm.routeMessageCountMaximum <= ...
        minimumMessages + protocol.maximumTotalResiduals && ...
    arm.instantaneousStrongAllTimes && ...
    arm.maximumSelectedResidualCount <= ...
        protocol.maximumTotalResiduals && ...
    arm.currentStepParetoSafeAllTimes && ...
    isequal(arm.eventActiveByTime, expectedEvent) && ...
    ~any(arm.selectedResidualCountByTime(~expectedEvent));
if ~passed
    error('EventWindowResidualV258:RuntimeContractFailed', ...
        'The executed V258 arm violated its route or event boundary.');
end
end

function tail = summarizeEventTail(candidate, reference, config, protocol)
tail = struct();
tail.timeWindow = protocol.activationWindow;
tail.receiverFormationId = ...
    protocol.reinforcedReceiverFormationIds;
tail.fixedTree = eventMetrics(reference.fixedTree, config, protocol);
tail.fullCausal = eventMetrics(reference.fullCausal, config, protocol);
tail.minimumBackbone = eventMetrics( ...
    reference.minimumBackbone, config, protocol);
tail.candidate = eventMetrics(candidate, config, protocol);
tail.candidateOverFixed = compareEventMetrics( ...
    tail.candidate, tail.fixedTree);
tail.candidateOverMinimum = compareEventMetrics( ...
    tail.candidate, tail.minimumBackbone);
end

function metrics = eventMetrics(arm, config, protocol)
groupIds = reshape(config.sensorGroupIds, 1, []);
sensors = find(ismember(groupIds, ...
    protocol.reinforcedReceiverFormationIds));
times = protocol.activationWindow(1):protocol.activationWindow(2);
eospa = arm.positionEospaBySensorTime(sensors, times);
rmse = arm.positionRmseBySensorTime(sensors, times);
cardinality = ...
    arm.absoluteCardinalityErrorBySensorTime(sensors, times);
metrics = struct();
metrics.formationEospa = mean(eospa(:));
metrics.formationRmse = finiteMean(rmse(:));
metrics.formationAbsoluteCardinalityError = mean(cardinality(:));
metrics.maximumTimeMeanFormationRmse = max( ...
    finiteMeanRows(rmse));
end

function comparison = compareEventMetrics(candidate, reference)
comparison = struct();
comparison.formationEospaGainPercent = lowerGain( ...
    reference.formationEospa, candidate.formationEospa);
comparison.formationRmseGainPercent = lowerGain( ...
    reference.formationRmse, candidate.formationRmse);
comparison.formationCardinalityGainPercent = lowerGain( ...
    reference.formationAbsoluteCardinalityError, ...
    candidate.formationAbsoluteCardinalityError);
comparison.maximumTimeMeanRmseGainPercent = lowerGain( ...
    reference.maximumTimeMeanFormationRmse, ...
    candidate.maximumTimeMeanFormationRmse);
end

function comparison = compareArm(candidate, reference)
comparison = struct();
comparison.fullHorizonEospaGainPercent = lowerGain( ...
    reference.fullHorizonPositionEospa, ...
    candidate.fullHorizonPositionEospa);
comparison.fullHorizonRmseGainPercent = lowerGain( ...
    reference.fullHorizonPositionRmse, ...
    candidate.fullHorizonPositionRmse);
comparison.focusConsensusGainPercent = lowerGain( ...
    reference.focusInterFormationPositionOspa, ...
    candidate.focusInterFormationPositionOspa);
comparison.attemptedByteSavingPercent = lowerGain( ...
    reference.attemptedPayloadBytes, candidate.attemptedPayloadBytes);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.meanDirectionPassed = ...
    comparison.fullHorizonEospaGainPercent > 0 && ...
    comparison.fullHorizonRmseGainPercent > 0 && ...
    comparison.focusConsensusGainPercent > 0;
end

