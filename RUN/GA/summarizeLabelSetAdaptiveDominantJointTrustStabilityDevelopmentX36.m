function [reportPath, development] = ...
    summarizeLabelSetAdaptiveDominantJointTrustStabilityDevelopmentX36( ...
        options)
% SUMMARIZELABELSETADAPTIVEDOMINANTJOINTTRUSTSTABILITYDEVELOPMENTX36
% Gate the frozen v9 value floor on five opened X36 development pairs.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantJointTrustStabilityRedesignAuthorized
    error('Value-gated joint source-trust summarization is not authorized.');
end
seeds = protocol.adaptiveDominantJointTrustStabilityDevelopmentSeeds;
candidateRoot = getField(options, 'inputDirectory', ...
    protocol.adaptiveDominantJointTrustStabilityDevelopmentRoot);
rows = repmat(emptyRow(), 1, numel(seeds));
runCommits = cell(1, numel(seeds));
for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    candidatePath = findSingleEvidence(candidateRoot, seed);
    loadedCandidate = load(candidatePath, 'summary');
    validateCandidate(loadedCandidate.summary, seed, protocol);
    runCommits{seedIdx} = loadedCandidate.summary.generationGitCommit;
    candidate = findArm(loadedCandidate.summary.aggregate, ...
        protocol.adaptiveDominantJointTrustStabilityArmNames{1});

    baselinePath = protocol. ...
        adaptiveDominantCertifiedOverlapX36MatPaths{seedIdx};
    if ~strcmp(computeFileSha256(baselinePath), protocol. ...
            adaptiveDominantCertifiedOverlapX36MatSha256{seedIdx})
        error('Frozen X36 baseline hash mismatch for seed %d.', seed);
    end
    loadedBaseline = load(baselinePath, 'summary');
    baseline = findArm(loadedBaseline.summary.aggregate, ...
        protocol.adaptiveDominantFullWindowReferenceArmName);
    rows(seedIdx) = buildRow( ...
        seed, baseline, candidate, candidatePath, baselinePath);
    rows(seedIdx).hardSafetyPassed = ...
        hardSafetyPassed(rows(seedIdx), protocol);
end
if numel(unique(runCommits, 'stable')) ~= 1
    error('Value-gated X36 runs use multiple code commits.');
end

candidate = aggregateCandidate(rows, protocol);
gitState = resolveResearchGitState();
development = struct();
development.protocolId = protocol.id;
development.contractVersion = protocol. ...
    adaptiveDominantJointTrustStabilityContractVersion;
development.generatedAt = datestr(now, 31);
development.generationGitCommit = gitState.commit;
development.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
development.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
development.candidateRunGenerationGitCommit = runCommits{1};
development.baselineRunGenerationGitCommit = protocol. ...
    adaptiveDominantCertifiedOverlapX36RunGenerationCommit;
development.presetName = protocol. ...
    adaptiveDominantJointTrustStabilityDevelopmentPresetName;
development.seeds = seeds;
development.times = protocol. ...
    adaptiveDominantJointTrustStabilityDevelopmentTimes;
development.armName = protocol. ...
    adaptiveDominantJointTrustStabilityArmNames{1};
development.rows = rows;
development.candidate = candidate;
development.developmentGatePassed = candidate.developmentGatePassed;
development.selectedArmName = '';
if development.developmentGatePassed
    development.selectedArmName = development.armName;
end
development.openedDevelopmentEvidenceOnly = true;
development.validationClaimAllowed = false;
development.evidenceBoundary = protocol. ...
    adaptiveDominantJointTrustStabilityEvidenceBoundary;

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(candidateRoot, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    ['LABEL_SET_ADAPTIVE_DOMINANT_VALUE_GATED_JOINT_TRUST_', ...
     'X36_DEVELOPMENT_V9.md']);
writeReport(reportPath, development);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'development');
development.reportPath = reportPath;
development.matPath = matPath;
fprintf('Value-gated joint source-trust X36 summary: %s\n', reportPath);
end

function row = buildRow( ...
        seed, baseline, candidate, candidatePath, baselinePath)
row = emptyRow();
row.seed = seed;
row.candidateEvidencePath = candidatePath;
row.baselineEvidencePath = baselinePath;
row.baselineEospa = baseline.focusEospa;
row.candidateEospa = candidate.focusEospa;
row.gainPercent = relativeGain(row.baselineEospa, row.candidateEospa);
row.baselineWorstEospa = baseline.focusWorstSensorEospa;
row.candidateWorstEospa = candidate.focusWorstSensorEospa;
row.baselineConsensusOspa = baseline.focusMapSetDisagreement;
row.candidateConsensusOspa = candidate.focusMapSetDisagreement;
row.baselineAttemptedBytes = baseline.focusAttemptedBytes;
row.candidateAttemptedBytes = candidate.focusAttemptedBytes;
row.byteDeltaPercent = 100 * ...
    (row.candidateAttemptedBytes - row.baselineAttemptedBytes) / ...
        max(row.baselineAttemptedBytes, eps);
row.selectedSensorB3 = candidate. ...
    focusSelectedRollingB3SensorStrongFraction;
row.selectedFormationB3 = candidate. ...
    focusSelectedRollingB3FormationStrongFraction;
row.truthUseFraction = candidate.policyTruthUseFraction;
row.payloadLimitPassFraction = ...
    candidate.policyPayloadLimitPassFraction;
row.payloadConstraintFraction = ...
    candidate.policyPayloadConstraintEnforcedFraction;
row.repairRate = candidate.policyRepairRate;
row.payloadEmergencyRate = candidate.policyPayloadEmergencyRate;
row.topologyInfeasibleRate = candidate.focusTopologyInfeasibleRate;
row.oneStepConstraintPassFraction = ...
    candidate.policyOneStepTopologyReservePassFraction;
row.oneStepConstraintCheckCount = ...
    candidate.policyOneStepTopologyReserveCheckCount;
row.expectedOneStepConstraintCheckCount = ...
    candidate.policyExpectedOneStepTopologyReserveCheckCount;
row.referenceOneStepRisk = ...
    candidate.policyConsensusProjectionReferenceRisk;
row.selectedOneStepRisk = ...
    candidate.policyConsensusProjectionSelectedRisk;
row.selectedOneStepRiskGapPercent = ...
    candidate.policyConsensusProjectionSelectedRiskGapPercent;
row.minimumEvaluatedActionCount = ...
    candidate.policyConsensusProjectionEvaluatedCountMinimum;
row.minimumFeasibleActionCount = ...
    candidate.policyConsensusProjectionFeasibleCountMinimum;
row.minimumPrimaryFeasibleActionCount = ...
    candidate.policyConsensusProjectionPrimaryFeasibleCountMinimum;
row.payloadRelaxationRate = ...
    candidate.policyConsensusProjectionPayloadRelaxationRate;
row.meanSelectedDominantWeight = ...
    candidate.policyMeanSelectedDominantWeight;
row.minimumSelectedDominantWeight = ...
    candidate.policyMinimumSelectedDominantWeight;
row.referenceFormationMean = ...
    candidate.policyJointTrustReferenceFormationMean;
row.lowTrustFormationMean = ...
    candidate.policyJointTrustLowTrustFormationMean;
row.fullTrustCandidateFormationMean = ...
    candidate.policyJointTrustFullTrustCandidateFormationMean;
row.minimumSelectedObjectiveAdvantage = ...
    candidate.policyMinimumDominantObjectiveAdvantage;
row.elapsedSeconds = candidate.elapsedSeconds;
end

function passed = hardSafetyPassed(row, protocol)
weightGrid = protocol. ...
    adaptiveDominantJointTrustStabilityCandidateWeightGrid;
passed = ...
    row.selectedSensorB3 >= 1 - 1e-12 && ...
    row.selectedFormationB3 >= 1 - 1e-12 && ...
    row.truthUseFraction == 0 && ...
    row.payloadLimitPassFraction >= 1 - 1e-12 && ...
    row.payloadConstraintFraction >= 1 - 1e-12 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0 && ...
    row.oneStepConstraintPassFraction >= 1 - 1e-12 && ...
    row.oneStepConstraintCheckCount == ...
        row.expectedOneStepConstraintCheckCount && ...
    row.oneStepConstraintCheckCount == numel(protocol. ...
        adaptiveDominantJointTrustStabilityDevelopmentTimes) && ...
    row.minimumEvaluatedActionCount == protocol. ...
        adaptiveDominantJointTrustStabilityExactX36CandidateCount && ...
    row.minimumFeasibleActionCount >= 1 && ...
    row.selectedOneStepRisk <= row.referenceOneStepRisk + 1e-12 && ...
    row.minimumSelectedDominantWeight >= min(weightGrid) - 1e-12 && ...
    row.meanSelectedDominantWeight <= protocol. ...
        adaptiveDominantJointTrustStabilityReferenceWeight + 1e-12 && ...
    row.minimumSelectedObjectiveAdvantage >= protocol. ...
        adaptiveDominantJointTrustStabilityMinimumDynamicObjectiveAdvantage ...
            - 1e-12;
end

function candidate = aggregateCandidate(rows, protocol)
candidate = struct();
candidate.seedGainPercent = [rows.gainPercent];
candidate.seedByteDeltaPercent = [rows.byteDeltaPercent];
candidate.meanGainPercent = relativeGain( ...
    mean([rows.baselineEospa]), mean([rows.candidateEospa]));
candidate.positiveSeedFraction = mean(candidate.seedGainPercent > 0);
candidate.minimumSeedGainPercent = min(candidate.seedGainPercent);
candidate.aggregateWorstGainPercent = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
candidate.aggregateConsensusGainPercent = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
candidate.aggregateByteSavingPercent = 100 * ...
    (sum([rows.baselineAttemptedBytes]) - ...
     sum([rows.candidateAttemptedBytes])) / ...
        max(sum([rows.baselineAttemptedBytes]), eps);
candidate.maximumPositiveByteDeltaPercent = ...
    max([0, candidate.seedByteDeltaPercent]);
candidate.minimumOneStepConstraintPassFraction = ...
    min([rows.oneStepConstraintPassFraction]);
candidate.minimumEvaluatedActionCount = ...
    min([rows.minimumEvaluatedActionCount]);
candidate.minimumFeasibleActionCount = ...
    min([rows.minimumFeasibleActionCount]);
candidate.minimumSelectedObjectiveAdvantage = ...
    min([rows.minimumSelectedObjectiveAdvantage]);
candidate.meanSelectedOneStepRiskGapPercent = ...
    mean([rows.selectedOneStepRiskGapPercent]);
candidate.meanPayloadRelaxationRate = ...
    mean([rows.payloadRelaxationRate]);
candidate.meanSelectedDominantWeight = ...
    mean([rows.meanSelectedDominantWeight]);
candidate.meanReferenceFormationCount = ...
    mean([rows.referenceFormationMean]);
candidate.meanLowTrustFormationCount = ...
    mean([rows.lowTrustFormationMean]);
candidate.meanFullTrustCandidateFormationCount = ...
    mean([rows.fullTrustCandidateFormationMean]);
candidate.hardSafetyPassed = all([rows.hardSafetyPassed]);
candidate.trackingGatePassed = ...
    candidate.meanGainPercent >= protocol. ...
        adaptiveDominantJointTrustStabilityMinimumMeanGainPercent && ...
    candidate.positiveSeedFraction >= protocol. ...
        adaptiveDominantJointTrustStabilityMinimumPositiveSeedFraction;
candidate.tailGatePassed = ...
    candidate.aggregateWorstGainPercent >= -1e-12 && ...
    candidate.aggregateConsensusGainPercent >= -1e-12;
candidate.communicationGatePassed = ...
    candidate.aggregateByteSavingPercent >= protocol. ...
        adaptiveDominantJointTrustStabilityMinimumByteSavingPercent && ...
    candidate.maximumPositiveByteDeltaPercent <= protocol. ...
        adaptiveDominantJointTrustStabilityMaximumPositiveByteDeltaPercent ...
            + 1e-12;
candidate.developmentGatePassed = ...
    candidate.hardSafetyPassed && ...
    candidate.trackingGatePassed && ...
    candidate.tailGatePassed && ...
    candidate.communicationGatePassed;
end

function validateCandidate(summary, seed, protocol)
if ~strcmp(summary.presetName, protocol. ...
        adaptiveDominantJointTrustStabilityDevelopmentPresetName) || ...
        ~isequal(summary.seeds, seed) || ...
        numel(summary.aggregate) ~= 1 || ...
        ~strcmp(summary.aggregate(1).mode, protocol. ...
            adaptiveDominantJointTrustStabilityArmNames{1}) || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Value-gated X36 candidate provenance mismatch.');
end
end

function arm = findArm(aggregate, mode)
armIdx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(armIdx)
    error('Evidence lacks arm %s.', mode);
end
arm = aggregate(armIdx);
end

function path = findSingleEvidence(rootDirectory, seed)
matches = dir(fullfile(rootDirectory, sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one v9 X36 result for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

