function writeReport(path, development)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open v9 X36 development report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
candidate = development.candidate;
fprintf(fid, '# X36 value-gated joint source-trust v9 development\n\n');
fprintf(fid, '- Generated: `%s`\n', development.generatedAt);
fprintf(fid, '- Contract: `%s`\n', development.contractVersion);
fprintf(fid, '- Candidate run commit: `%s`\n', ...
    development.candidateRunGenerationGitCommit);
fprintf(fid, '- Frozen baseline commit: `%s`\n', ...
    development.baselineRunGenerationGitCommit);
fprintf(fid, '- Scenario: `%s`\n', development.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(development.seeds));
fprintf(fid, '- Development gate passed: `%d`\n\n', ...
    development.developmentGatePassed);
fprintf(fid, '## Aggregate candidate\n\n');
fprintf(fid, ['| Mean gain | Positive seeds | Minimum seed gain | ', ...
    'Worst-node gain | Consensus gain | Byte saving | ', ...
    'Minimum selected value | Payload relaxation | Gate |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
fprintf(fid, ['| %.3f%% | %d/%d | %.3f%% | %.3f%% | %.3f%% | ', ...
    '%.3f%% | %.6f | %.3f | %d |\n\n'], ...
    candidate.meanGainPercent, ...
    round(candidate.positiveSeedFraction * numel(development.seeds)), ...
    numel(development.seeds), candidate.minimumSeedGainPercent, ...
    candidate.aggregateWorstGainPercent, ...
    candidate.aggregateConsensusGainPercent, ...
    candidate.aggregateByteSavingPercent, ...
    candidate.minimumSelectedObjectiveAdvantage, ...
    candidate.meanPayloadRelaxationRate, ...
    candidate.developmentGatePassed);
fprintf(fid, '## Paired seed results\n\n');
fprintf(fid, ['| Seed | Baseline E-OSPA | Candidate E-OSPA | Gain | ', ...
    'Consensus gain | Byte delta | Minimum selected value | ', ...
    'Mean alpha | Reference formations | Safe |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for row = development.rows
    consensusGain = relativeGain( ...
        row.baselineConsensusOspa, row.candidateConsensusOspa);
    fprintf(fid, ['| %d | %.4f | %.4f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.6f | %.3f | %.3f | %d |\n'], ...
        row.seed, row.baselineEospa, row.candidateEospa, ...
        row.gainPercent, consensusGain, row.byteDeltaPercent, ...
        row.minimumSelectedObjectiveAdvantage, ...
        row.meanSelectedDominantWeight, row.referenceFormationMean, ...
        row.hardSafetyPassed);
end
fprintf(fid, '\n## Interpretation boundary\n\n%s\n', ...
    development.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
