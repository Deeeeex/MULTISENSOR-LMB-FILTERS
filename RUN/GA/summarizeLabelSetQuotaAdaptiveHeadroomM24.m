function [reportPath, summary] = ...
    summarizeLabelSetQuotaAdaptiveHeadroomM24(options)
% SUMMARIZELABELSETQUOTAADAPTIVEHEADROOMM24 Gate residual cross quotas.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.quotaAdaptiveRoutingImplementationAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 quota-adaptive headroom summary is not authorized.');
end
states = struct( ...
    'seed', {11, 19, 23, 27}, ...
    'time', {78, 78, 78, 78}, ...
    'behavior', {'learned', 'ccw', 'ccw', 'learned'}, ...
    'behaviorAction', { ...
        'label-set-message-passing-safe-fixed-e05-a70', ...
        'fixed-counter-clockwise', ...
        'fixed-counter-clockwise', ...
        'label-set-message-passing-safe-fixed-e05-a70'});
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'quota_adaptive_headroom_v1'));
rows = repmat(emptyRow(), 1, numel(states));
riskMatrix = inf(numel(states), size( ...
    protocol.quotaAdaptiveRoutingActionSequences, 1));
hardFailureMatrix = false(size(riskMatrix));
runCommit = '';
for stateIdx = 1:numel(states)
    state = states(stateIdx);
    path = fullfile(inputDirectory, ...
        sprintf('seed%d', state.seed), sprintf([ ...
            'label_set_causal_graph_option_h3_m24_', ...
            'seed%d_t%d_%s_source.mat'], ...
            state.seed, state.time, state.behavior));
    loaded = load(path, 'preflight');
    if ~isfield(loaded, 'preflight')
        error('Quota-adaptive artifact lacks preflight.');
    end
    preflight = loaded.preflight;
    validatePreflight(preflight, state, protocol);
    if isempty(runCommit)
        runCommit = preflight.generationGitCommit;
    elseif ~strcmp(runCommit, preflight.generationGitCommit)
        error('Quota-adaptive preflights use different source commits.');
    end
    risk = [preflight.outcomes.meanEospa];
    hardFailure = [preflight.outcomes.hardFailure];
    completed = [preflight.outcomes.executionCompleted];
    oldOracle = min(risk(1:2));
    [newOracle, bestIdx] = min(risk);
    row = emptyRow();
    row.seed = state.seed;
    row.currentTime = state.time;
    row.behavior = state.behavior;
    row.artifactPath = path;
    row.cccMeanEospa = risk(1);
    row.g1MeanEospa = risk(2);
    row.oldOracleMeanEospa = oldOracle;
    row.quotaOracleMeanEospa = newOracle;
    row.bestOption = preflight.actionSequenceNames{bestIdx};
    row.incrementalGainVsOldOraclePercent = ...
        relativeGain(oldOracle, newOracle);
    row.refreshesOldOracle = ...
        newOracle < oldOracle - 1e-12;
    row.completedActionCount = nnz(completed);
    row.hardFailureCount = nnz(hardFailure);
    row.hardFailureOptions = ...
        preflight.actionSequenceNames(hardFailure);
    row.maximumByteDeviationPercent = finiteMax(abs( ...
        preflight.attemptedByteDeviationPercent(completed)));
    row.restartEquivalencePassed = ...
        preflight.restartEquivalencePassed;
    row.completedActionsSafe = ...
        completedActionsSafe(preflight, protocol);
    rows(stateIdx) = row;
    riskMatrix(stateIdx, :) = risk;
    hardFailureMatrix(stateIdx, :) = hardFailure;
end

prior = loadPriorOracleSummaries(options, protocol);
meanOldOracle = mean([rows.oldOracleMeanEospa]);
meanQuotaOracle = mean([rows.quotaOracleMeanEospa]);
gainVsOldOraclePercent = ...
    relativeGain(meanOldOracle, meanQuotaOracle);
incrementalVsPersistentPercent = relativeGain( ...
    prior.meanPersistentOracle, meanQuotaOracle);
incrementalVsTemporalPercent = relativeGain( ...
    prior.meanTemporalOracle, meanQuotaOracle);
completedSafetyPassed = ...
    all([rows.restartEquivalencePassed]) && ...
    all([rows.completedActionsSafe]) && ...
    max([rows.maximumByteDeviationPercent]) <= ...
        protocol.macroActionMaximumByteDeviationPercent;
allActionsFeasible = ~any(hardFailureMatrix(:));
hardAuditPassed = ...
    completedSafetyPassed && allActionsFeasible;
headroomPassed = ...
    incrementalVsTemporalPercent >= ...
        protocol. ...
            quotaAdaptiveRoutingMinimumIncrementalOracleGainPercent;

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-label-set-quota-adaptive-headroom-summary-v1';
summary.auditContractVersion = ...
    protocol.quotaAdaptiveRoutingAuditContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.runGenerationGitCommit = runCommit;
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.rows = rows;
summary.actionNames = protocol.macroActionNames;
summary.actionSequences = ...
    protocol.quotaAdaptiveRoutingActionSequences;
summary.riskMatrix = riskMatrix;
summary.hardFailureMatrix = hardFailureMatrix;
summary.meanOldTwoOptionOracleEospa = meanOldOracle;
summary.meanQuotaOracleEospa = meanQuotaOracle;
summary.meanPersistentRankOracleEospa = ...
    prior.meanPersistentOracle;
summary.meanTemporalOracleEospa = ...
    prior.meanTemporalOracle;
summary.gainVsOldTwoOptionOraclePercent = ...
    gainVsOldOraclePercent;
summary.incrementalGainVsPersistentRankOraclePercent = ...
    incrementalVsPersistentPercent;
summary.incrementalGainVsTemporalOraclePercent = ...
    incrementalVsTemporalPercent;
summary.refreshedOldOracleStateCount = ...
    nnz([rows.refreshesOldOracle]);
summary.completedActionSafetyGatesPassed = ...
    completedSafetyPassed;
summary.allRegisteredActionsFeasible = ...
    allActionsFeasible;
summary.registeredHardFailureCount = ...
    nnz(hardFailureMatrix);
summary.q10HardFailureStateCount = ...
    nnz(hardFailureMatrix(:, 7));
summary.q12HardFailureStateCount = ...
    nnz(hardFailureMatrix(:, 8));
summary.maximumByteDeviationPercent = ...
    max([rows.maximumByteDeviationPercent]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.quotaHeadroomGatePassed = headroomPassed;
summary.quotaOnlyActionFamilyRejected = ...
    ~hardAuditPassed || ~headroomPassed;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
summary.nextMethodDirection = [ ...
    'joint-state-adaptive-cross-quota-and-residual-weight-', ...
    'with-a-physical-capacity-mask'];
summary.evidenceBoundary = [ ...
    'This opened-training audit evaluates a persistent H=3 offline ', ...
    'oracle over fixed residual cross-edge quotas on four adversarial ', ...
    'M24 behavior states. Failed actions retain infinite risk. It does ', ...
    'not establish a deployable selector, development, held-out M24 or ', ...
    'X36 result.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = 'label_set_quota_adaptive_headroom_m24_v1';
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Quota-adaptive summary already exists. Set ', ...
        'overwrite=true only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary, protocol);
fprintf('Quota-adaptive summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function validatePreflight(preflight, state, protocol)
if ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.auditMode, ...
            'quota-adaptive-headroom') || ...
        ~strcmp(preflight.auditContractVersion, ...
            protocol.quotaAdaptiveRoutingAuditContractVersion) || ...
        preflight.seed ~= state.seed || ...
        preflight.currentTime ~= state.time || ...
        ~strcmp(preflight.sourceBehaviorAction, ...
            state.behaviorAction) || ...
        ~isequal(preflight.actionSequences, ...
            protocol.quotaAdaptiveRoutingActionSequences) || ...
        preflight.exploratoryActionSubsetUsed || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.restartEquivalencePassed || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || ...
        preflight.x36Opened
    error('Quota-adaptive preflight violates the frozen contract.');
end
outcomes = preflight.outcomes;
hardFailure = [outcomes.hardFailure];
completed = [outcomes.executionCompleted];
if any(hardFailure & completed) || ...
        any(~hardFailure & ~completed) || ...
        any(~isinf([outcomes(hardFailure).meanEospa])) || ...
        preflight.registeredProjectionFailureCount ~= ...
            nnz(hardFailure) || ...
        preflight.allRegisteredActionsFeasible ~= ...
            ~any(hardFailure)
    error('Quota-adaptive hard-failure encoding is inconsistent.');
end
failedSequenceMask = all(ismember( ...
    preflight.actionSequences, ...
    protocol.quotaAdaptiveRoutingActionTokens), 2);
if any(hardFailure & ~failedSequenceMask')
    error('A non-quota reference action was encoded as infeasible.');
end
end

function passed = completedActionsSafe(preflight, protocol)
outcomes = preflight.outcomes;
completed = [outcomes.executionCompleted];
selected = outcomes(completed);
passed = ~preflight.runtimePolicyUsesTruth && ...
    all([selected.repairCount] == 0) && ...
    all([selected.payloadEmergencyCount] == 0) && ...
    all([selected.infeasibleCount] == 0) && ...
    all(arrayfun(@(outcome) ...
        outcome.firstActionExact && ...
        all(outcome.messageCounts == ...
            protocol.quotaAdaptiveRoutingExpectedMessageCount) && ...
        all(outcome.selectedSensorB3Pass) && ...
        all(outcome.selectedFormationB3Pass), selected));
end

function prior = loadPriorOracleSummaries(options, protocol)
defaultRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1');
persistentPath = getField(options, ...
    'persistentSummaryPath', fullfile(defaultRoot, ...
        'diverse_graph_option_sentinel_v1', 'summary', ...
        'label_set_diverse_graph_option_sentinel_m24_v1.mat'));
temporalPath = getField(options, ...
    'temporalSummaryPath', fullfile(defaultRoot, ...
        'diverse_temporal_upper_bound_v1', 'summary', ...
        'label_set_diverse_temporal_upper_bound_m24_v1.mat'));
persisted = load(persistentPath, 'summary');
temporal = load(temporalPath, 'summary');
if ~isfield(persisted, 'summary') || ...
        ~isfield(temporal, 'summary') || ...
        ~strcmp(persisted.summary.protocolId, protocol.id) || ...
        ~strcmp(temporal.summary.protocolId, protocol.id) || ...
        persisted.summary.developmentOpened || ...
        persisted.summary.heldoutM24Opened || ...
        persisted.summary.x36Opened || ...
        temporal.summary.developmentOpened || ...
        temporal.summary.heldoutM24Opened || ...
        temporal.summary.x36Opened
    error('Prior M24 action-space summaries violate the boundary.');
end
prior = struct( ...
    'meanPersistentOracle', ...
        persisted.summary.meanDiverseOracleEospa, ...
    'meanTemporalOracle', ...
        temporal.summary.meanTemporalOracleEospa);
end

function writeReport(path, summary, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write quota-adaptive report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 quota-adaptive H=3 headroom audit\n\n');
fprintf(fid, [ ...
    '- Mean old / quota / persistent-rank / temporal oracle E-OSPA: ', ...
    '`%.6f / %.6f / %.6f / %.6f`\n'], ...
    summary.meanOldTwoOptionOracleEospa, ...
    summary.meanQuotaOracleEospa, ...
    summary.meanPersistentRankOracleEospa, ...
    summary.meanTemporalOracleEospa);
fprintf(fid, '- Gain vs old two-option oracle: `%.3f%%`\n', ...
    summary.gainVsOldTwoOptionOraclePercent);
fprintf(fid, '- Incremental vs persistent-rank oracle: `%+.3f%%`\n', ...
    summary.incrementalGainVsPersistentRankOraclePercent);
fprintf(fid, [ ...
    '- Incremental vs temporal oracle: `%+.3f%%` ', ...
    '(gate `%.3f%%`)\n'], ...
    summary.incrementalGainVsTemporalOraclePercent, ...
    protocol. ...
        quotaAdaptiveRoutingMinimumIncrementalOracleGainPercent);
fprintf(fid, '- Refreshed old-oracle states: `%d / %d`\n', ...
    summary.refreshedOldOracleStateCount, ...
    numel(summary.rows));
fprintf(fid, [ ...
    '- Registered hard failures: `%d` ', ...
    '(Q10 states `%d`, Q12 states `%d`)\n'], ...
    summary.registeredHardFailureCount, ...
    summary.q10HardFailureStateCount, ...
    summary.q12HardFailureStateCount);
fprintf(fid, [ ...
    '- Completed-action safety / all-actions feasible / ', ...
    'headroom gates: `%d / %d / %d`\n\n'], ...
    summary.completedActionSafetyGatesPassed, ...
    summary.allRegisteredActionsFeasible, ...
    summary.quotaHeadroomGatePassed);
fprintf(fid, [ ...
    '| Seed | Source | Old oracle | Quota oracle | Best | ', ...
    'Incremental | Completed | Failed | Safe |\n']);
fprintf(fid, ...
    '|--:|:--|--:|--:|:--|--:|--:|--:|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, [ ...
        '| %d | %s | %.6f | %.6f | `%s` | %+.3f%% | ', ...
        '%d | %d | %d |\n'], ...
        row.seed, row.behavior, ...
        row.oldOracleMeanEospa, ...
        row.quotaOracleMeanEospa, row.bestOption, ...
        row.incrementalGainVsOldOraclePercent, ...
        row.completedActionCount, row.hardFailureCount, ...
        row.completedActionsSafe);
end
fprintf(fid, '\n## Decision\n\n');
fprintf(fid, [ ...
    'The quota-only action family is `%s`. The next opened ', ...
    'training-only method direction is `%s`.\n\n'], ...
    decisionText(summary.quotaOnlyActionFamilyRejected), ...
    summary.nextMethodDirection);
fprintf(fid, '## Boundary\n\n%s\n', summary.evidenceBoundary);
end

function text = decisionText(rejected)
if rejected
    text = 'rejected';
else
    text = 'accepted for selector fitting';
end
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = finiteMax(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behavior', '', ...
    'artifactPath', '', ...
    'cccMeanEospa', NaN, ...
    'g1MeanEospa', NaN, ...
    'oldOracleMeanEospa', NaN, ...
    'quotaOracleMeanEospa', NaN, ...
    'bestOption', '', ...
    'incrementalGainVsOldOraclePercent', NaN, ...
    'refreshesOldOracle', false, ...
    'completedActionCount', NaN, ...
    'hardFailureCount', NaN, ...
    'hardFailureOptions', {{}}, ...
    'maximumByteDeviationPercent', NaN, ...
    'restartEquivalencePassed', false, ...
    'completedActionsSafe', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
