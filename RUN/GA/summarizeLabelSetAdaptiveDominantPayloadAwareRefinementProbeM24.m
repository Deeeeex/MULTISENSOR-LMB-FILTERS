function [reportPath, probe] = ...
    summarizeLabelSetAdaptiveDominantPayloadAwareRefinementProbeM24(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTPAYLOADAWAREREFINEMENTPROBEM24
% Evaluate the preregistered seed-31 margin refinement in ascending order.
%
% Seed 31 was already opened by D-B v1.  This report is redesign evidence,
% not fresh validation.  The first token meeting the registered tracking,
% communication, and hard-safety gates would be selected.  If no token
% passes, the complete registered refinement is rejected.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantPayloadAwareRefinementAuthorized || ...
        protocol.adaptiveDominantPayloadAwareHeldoutM24Authorized || ...
        protocol.adaptiveDominantPayloadAwareX36Authorized
    error('Payload-aware refinement probe summary is not authorized.');
end

tokens = reshape(protocol. ...
    adaptiveDominantPayloadAwareRefinementMarginTokens, 1, []);
seed = protocol.adaptiveDominantPayloadAwareRefinementProbeSeed;
rootDirectory = getField(options, 'inputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_payload_aware_screen_v2'));
baseline = loadBaseline(seed, protocol);
rows = repmat(emptyRow(), 1, numel(tokens));
runCommit = '';
for tokenIdx = 1:numel(tokens)
    token = tokens(tokenIdx);
    evidencePath = findSingleEvidence(rootDirectory, token, seed);
    loaded = load(evidencePath, 'summary');
    summary = loaded.summary;
    candidateMode = sprintf([ ...
        'adaptive-dominant-composite-balanced-', ...
        'payload-margin%03d-e05-a70'], token);
    validateSummary(summary, seed, candidateMode, protocol);
    if isempty(runCommit)
        runCommit = summary.generationGitCommit;
    elseif ~strcmp(runCommit, summary.generationGitCommit)
        error('Payload-aware refinement runs use different commits.');
    end
    candidate = findArm(summary.aggregate, candidateMode);
    row = emptyRow();
    row.token = token;
    row.marginFraction = token / 1000;
    row.evidencePath = evidencePath;
    row.baselineEospa = baseline.focusEospa;
    row.candidateEospa = candidate.focusEospa;
    row.gainPercent = relativeGain( ...
        row.baselineEospa, row.candidateEospa);
    row.baselineWorstEospa = baseline.focusWorstSensorEospa;
    row.candidateWorstEospa = candidate.focusWorstSensorEospa;
    row.baselineConsensusOspa = baseline.focusMapSetDisagreement;
    row.candidateConsensusOspa = candidate.focusMapSetDisagreement;
    row.baselineAttemptedBytes = baseline.focusAttemptedBytes;
    row.candidateAttemptedBytes = candidate.focusAttemptedBytes;
    row.byteDeltaPercent = 100 * ...
        (row.candidateAttemptedBytes - row.baselineAttemptedBytes) / ...
            max(row.baselineAttemptedBytes, eps);
    row.meanMessageCount = candidate.meanDirectedMessageCount;
    row.selectedSensorB3 = candidate. ...
        focusSelectedRollingB3SensorStrongFraction;
    row.selectedFormationB3 = candidate. ...
        focusSelectedRollingB3FormationStrongFraction;
    row.truthUseFraction = candidate.policyTruthUseFraction;
    row.posteriorUseFraction = ...
        candidate.policyPosteriorContentUseFraction;
    row.payloadMetadataUseFraction = candidate. ...
        policyPosteriorPayloadMetadataUseFraction;
    row.currentLinkReliabilityUseFraction = candidate. ...
        policyCurrentLinkReliabilityUseFraction;
    row.payloadConstraintFraction = candidate. ...
        policyPayloadConstraintEnforcedFraction;
    row.payloadLimitPassFraction = candidate. ...
        policyPayloadLimitPassFraction;
    row.repairRate = candidate.policyRepairRate;
    row.payloadEmergencyRate = candidate.policyPayloadEmergencyRate;
    row.topologyInfeasibleRate = candidate.focusTopologyInfeasibleRate;
    row.hardSafetyPassed = hardSafetyPassed(row, protocol);
    row.trackingGatePassed = row.gainPercent >= ...
        protocol.adaptiveDominantPayloadAwareMinimumMeanGainPercent;
    row.communicationGatePassed = ...
        max(0, row.byteDeltaPercent) <= protocol. ...
            adaptiveDominantPayloadAwareMaximumPositiveByteDeltaPercent + ...
                1e-12 && ...
        abs(row.byteDeltaPercent) <= protocol. ...
            adaptiveDominantPayloadAwareMaximumAbsoluteByteDeltaPercent + ...
                1e-12;
    row.probeGatePassed = row.hardSafetyPassed && ...
        row.trackingGatePassed && row.communicationGatePassed;
    rows(tokenIdx) = row;
end

passingIndices = find([rows.probeGatePassed]);
if isempty(passingIndices)
    selectedToken = NaN;
    selectedMarginFraction = NaN;
    firstPassingTokenWasSelected = false;
    refinementGatePassed = false;
else
    selectedIdx = passingIndices(1);
    selectedToken = rows(selectedIdx).token;
    selectedMarginFraction = rows(selectedIdx).marginFraction;
    firstPassingTokenWasSelected = true;
    refinementGatePassed = true;
end

gitState = resolveResearchGitState();
probe = struct();
probe.protocolId = protocol.id;
probe.contractVersion = protocol. ...
    adaptiveDominantPayloadAwareRefinementContractVersion;
probe.generatedAt = datestr(now, 31);
probe.generationGitCommit = gitState.commit;
probe.runGenerationGitCommit = runCommit;
probe.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
probe.seed = seed;
probe.times = ...
    protocol.adaptiveDominantPayloadAwareDevelopmentTimes;
probe.tokens = tokens;
probe.rows = rows;
probe.selectedToken = selectedToken;
probe.selectedMarginFraction = selectedMarginFraction;
probe.firstPassingTokenWasSelected = ...
    firstPassingTokenWasSelected;
probe.refinementGatePassed = refinementGatePassed;
probe.allRegisteredTokensEvaluated = ...
    numel(rows) == numel(tokens);
probe.splitWasAlreadyOpened = true;
probe.validationClaimAllowed = false;
probe.heldoutM24Opened = false;
probe.x36Opened = false;
if refinementGatePassed
    probe.nextDirection = ...
        'freeze-selected-token-and-run-registered-confirmation';
else
    probe.nextDirection = [ ...
        'reject-global-margin-refinement-and-redesign-', ...
        'the-budget-feasibility-action-space'];
end
probe.evidenceBoundary = [ ...
    'Seed 31 was already opened by D-B v1 and is used only for ', ...
    'redesign. No result in this report is held-out M24 or X36 ', ...
    'validation evidence.'];

outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    rootDirectory, 'refinement_probe', 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_PAYLOAD_AWARE_REFINEMENT_PROBE_M24_V3.md');
writeReport(reportPath, probe, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'probe');
probe.reportPath = reportPath;
probe.matPath = matPath;
fprintf('Payload-aware refinement probe summary: %s\n', reportPath);
end

function baseline = loadBaseline(seed, protocol)
seedIdx = find( ...
    protocol.adaptiveDominantDevelopmentSeeds == seed, 1);
if isempty(seedIdx)
    error('Refinement probe seed has no frozen CCW baseline.');
end
path = protocol.adaptiveDominantDevelopmentMatPaths{seedIdx};
expectedHash = protocol.adaptiveDominantDevelopmentMatSha256{seedIdx};
if ~strcmp(computeFileSha256(path), expectedHash)
    error('Frozen development baseline hash mismatch.');
end
loaded = load(path, 'summary');
baseline = findArm(loaded.summary.aggregate, protocol. ...
    adaptiveDominantPayloadAwareDevelopmentReferenceArmName);
end

function path = findSingleEvidence(rootDirectory, token, seed)
matches = dir(fullfile(rootDirectory, sprintf('margin%03d', token), ...
    'development', sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one refinement MAT for token %03d.', token);
end
path = fullfile(matches.folder, matches.name);
end

function validateSummary(summary, seed, candidateMode, protocol)
if ~strcmp(summary.presetName, 'm24-hard') || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'development') || ...
        summary.options.continuationStartTime ~= protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTimes(1) || ...
        summary.options.maxTimeSteps ~= protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTimes(end) || ...
        ~any(strcmp({summary.aggregate.mode}, candidateMode)) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Payload-aware refinement provenance contract failed.');
end
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Refinement evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function passed = hardSafetyPassed(row, protocol)
passed = ...
    abs(row.meanMessageCount - protocol. ...
        adaptiveDominantPayloadAwareExpectedMessageCount) < 1e-12 && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.payloadMetadataUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.payloadConstraintFraction == 1 && ...
    row.payloadLimitPassFraction == 1 && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function row = emptyRow()
row = struct( ...
    'token', NaN, ...
    'marginFraction', NaN, ...
    'evidencePath', '', ...
    'baselineEospa', NaN, ...
    'candidateEospa', NaN, ...
    'gainPercent', NaN, ...
    'baselineWorstEospa', NaN, ...
    'candidateWorstEospa', NaN, ...
    'baselineConsensusOspa', NaN, ...
    'candidateConsensusOspa', NaN, ...
    'baselineAttemptedBytes', NaN, ...
    'candidateAttemptedBytes', NaN, ...
    'byteDeltaPercent', NaN, ...
    'meanMessageCount', NaN, ...
    'selectedSensorB3', NaN, ...
    'selectedFormationB3', NaN, ...
    'truthUseFraction', NaN, ...
    'posteriorUseFraction', NaN, ...
    'payloadMetadataUseFraction', NaN, ...
    'currentLinkReliabilityUseFraction', NaN, ...
    'payloadConstraintFraction', NaN, ...
    'payloadLimitPassFraction', NaN, ...
    'repairRate', NaN, ...
    'payloadEmergencyRate', NaN, ...
    'topologyInfeasibleRate', NaN, ...
    'hardSafetyPassed', false, ...
    'trackingGatePassed', false, ...
    'communicationGatePassed', false, ...
    'probeGatePassed', false);
end

function writeReport(path, probe, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Unable to write payload-aware refinement report.');
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 payload-aware adaptive-dominant refinement probe\n\n');
fprintf(fid, '- Contract: `%s`\n', probe.contractVersion);
fprintf(fid, '- Generated: %s\n', probe.generatedAt);
fprintf(fid, '- Run commit: `%s`\n', probe.runGenerationGitCommit);
fprintf(fid, '- Probe seed: `%d`\n', probe.seed);
fprintf(fid, '- Tokens: `%s`\n', mat2str(probe.tokens));
fprintf(fid, '- Window: `%s`\n\n', mat2str(probe.times));
fprintf(fid, ['| Margin | CCW E-OSPA | Candidate E-OSPA | Gain | ', ...
    'CCW bytes | Candidate bytes | Byte delta | Msgs | ', ...
    'Hard safe | Track | Comm | Pass |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|', ...
    ':--:|:--:|:--:|:--:|\n']);
for row = probe.rows
    fprintf(fid, ['| %.1f%% | %.6f | %.6f | %+.3f%% | %.0f | ', ...
        '%.0f | %+.3f%% | %.2f | %d | %d | %d | %d |\n'], ...
        100 * row.marginFraction, ...
        row.baselineEospa, row.candidateEospa, row.gainPercent, ...
        row.baselineAttemptedBytes, row.candidateAttemptedBytes, ...
        row.byteDeltaPercent, row.meanMessageCount, ...
        row.hardSafetyPassed, row.trackingGatePassed, ...
        row.communicationGatePassed, row.probeGatePassed);
end
fprintf(fid, '\n## Registered sequential gate\n\n');
fprintf(fid, '- Minimum E-OSPA gain: `%.3f%%`\n', ...
    protocol.adaptiveDominantPayloadAwareMinimumMeanGainPercent);
fprintf(fid, '- Maximum positive byte delta: `%.3f%%`\n', ...
    protocol. ...
        adaptiveDominantPayloadAwareMaximumPositiveByteDeltaPercent);
fprintf(fid, '- Maximum absolute byte delta: `%.3f%%`\n', ...
    protocol. ...
        adaptiveDominantPayloadAwareMaximumAbsoluteByteDeltaPercent);
fprintf(fid, '- All registered tokens evaluated: `%d`\n', ...
    probe.allRegisteredTokensEvaluated);
fprintf(fid, '- First passing token selected: `%d`\n', ...
    probe.firstPassingTokenWasSelected);
if isfinite(probe.selectedToken)
    fprintf(fid, '- Selected token: `%03d`\n', probe.selectedToken);
else
    fprintf(fid, '- Selected token: `none`\n');
end
fprintf(fid, '- Refinement gate passed: `%d`\n', ...
    probe.refinementGatePassed);
fprintf(fid, '- Fresh validation claim allowed: `%d`\n', ...
    probe.validationClaimAllowed);
fprintf(fid, '- Next: `%s`\n\n', probe.nextDirection);
fprintf(fid, '%s\n', probe.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
