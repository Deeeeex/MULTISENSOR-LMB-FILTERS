function [reportPath, summary] = ...
        analyzeRecursiveRolloutRankRulesV177(options)
% ANALYZERECURSIVEROLLOUTRANKRULESV177 Frozen univariate rule screen.

if nargin < 1 || isempty(options)
    options = struct();
end
datasetPath = getField(options, 'datasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v176', 'recursive_rollout_action_value', ...
    'RECURSIVE_ROLLOUT_LABEL_ACTION_VALUE_DATASET_V176.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v177', 'recursive_rollout_rank_rules'));
if exist(datasetPath, 'file') ~= 2
    error('RecursiveRolloutRankRulesV177:MissingDataset', ...
        'Generate the V176 recursive-rollout dataset first.');
end
dataset = load(datasetPath, 'dataset').dataset;
if ~strcmp(dataset.contractVersion, ...
        'recursive-rollout-label-action-value-dataset-v176-v1') || ...
        dataset.featuresUseTruth || dataset.featuresUseFutureInformation
    error('RecursiveRolloutRankRulesV177:DatasetContract', ...
        'The V176 dataset contract is invalid.');
end

rules = repmat(emptyRule(), 1, 0);
for featureIdx = 1:numel(dataset.featureNames)
    for directionSign = [-1, 1]
        rule = emptyRule();
        rule.feature = dataset.featureNames{featureIdx};
        if directionSign < 0
            rule.direction = 'maximum';
        else
            rule.direction = 'minimum';
        end
        [trainingE, trainingR, heldoutE, heldoutR] = ...
            selectByRule(dataset, featureIdx, directionSign);
        rule.training = readout(trainingE, trainingR);
        rule.heldout = readout(heldoutE, heldoutR);
        rules(end + 1) = rule; %#ok<AGROW>
    end
end
trainingSafe = find(arrayfun(@(rule) ...
    rule.training.harmfulCellCount == 0, rules));
if isempty(trainingSafe)
    selectedRuleIndex = 0;
else
    table = [-arrayfun(@(rule) ...
        rule.training.minimumRmseGain, rules(trainingSafe))', ...
        -arrayfun(@(rule) rule.training.totalRmseGain, ...
            rules(trainingSafe))', ...
        -arrayfun(@(rule) rule.training.totalEospaGain, ...
            rules(trainingSafe))', ...
        trainingSafe'];
    [~, order] = sortrows(table, 1:size(table, 2));
    trainingSafe = trainingSafe(order);
    selectedRuleIndex = trainingSafe(1);
end

summary = struct();
summary.contractVersion = ...
    'recursive-rollout-rank-rules-v177-result-v1';
summary.datasetPath = datasetPath;
summary.ruleCount = numel(rules);
summary.trainingSafeRuleIndices = trainingSafe;
summary.rules = rules;
summary.selectedRuleIndex = selectedRuleIndex;
summary.selectedRule = emptyRule();
if selectedRuleIndex > 0
    summary.selectedRule = rules(selectedRuleIndex);
end
summary.heldoutGatePassed = selectedRuleIndex > 0 && ...
    summary.selectedRule.heldout.harmfulCellCount == 0 && ...
    summary.selectedRule.heldout.totalEospaGain > 0 && ...
    summary.selectedRule.heldout.totalRmseGain > 0;
summary.truthUsedByRules = false;
summary.truthUsedForRuleSelection = true;
summary.truthUsedForHeldoutEvaluation = true;
summary.recursiveEvaluationRun = false;
summary.evidenceBoundary = [ ...
    'V177 is an opened univariate-rule screen on V176 rollout states. ', ...
    'Each rule chooses one shortlisted source-label action by maximizing ', ...
    'or minimizing one current observable feature, with label/source ', ...
    'keys used only for deterministic tie-breaking. The rule is frozen ', ...
    'using the six t=78 cells before the six t=79 cells are read. Current ', ...
    'truth supplies action-value targets and rule selection, so this is ', ...
    'a same-seed development diagnostic, not validation.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
summaryPath = fullfile(outputRoot, ...
    'RECURSIVE_ROLLOUT_RANK_RULES_V177_RESULT.mat');
reportPath = fullfile(outputRoot, ...
    'RECURSIVE_ROLLOUT_RANK_RULES_V177.md');
summary.matPath = summaryPath;
summary.reportPath = reportPath;
save('-mat7-binary', summaryPath, 'summary');
writeReport(reportPath, summary);
fprintf('V177 recursive-rollout rank rules: %s\n', reportPath);
end

function [trainingE, trainingR, heldoutE, heldoutR] = ...
        selectByRule(dataset, featureIdx, directionSign)
trainingE = zeros(1, 0);
trainingR = zeros(1, 0);
heldoutE = zeros(1, 0);
heldoutR = zeros(1, 0);
for cellRecord = dataset.cells
    rows = dataset.rows([dataset.rows.cellId] == cellRecord.cellId);
    features = vertcat(rows.features);
    labels = reshape([rows.label], 2, [])';
    sources = [rows.source]';
    [~, order] = sortrows( ...
        [directionSign * features(:, featureIdx), labels, sources], ...
        [1, 2, 3, 4]);
    selected = rows(order(1));
    if cellRecord.split == 1
        trainingE(end + 1) = selected.eospaGain; %#ok<AGROW>
        trainingR(end + 1) = selected.rmseGain; %#ok<AGROW>
    elseif cellRecord.split == 3
        heldoutE(end + 1) = selected.eospaGain; %#ok<AGROW>
        heldoutR(end + 1) = selected.rmseGain; %#ok<AGROW>
    end
end
end

function value = readout(eospa, rmse)
value = struct( ...
    'cellCount', numel(eospa), ...
    'harmfulCellCount', nnz(eospa < -1e-9 | rmse <= 1e-9), ...
    'totalEospaGain', sum(eospa), ...
    'totalRmseGain', sum(rmse), ...
    'minimumEospaGain', min(eospa), ...
    'minimumRmseGain', min(rmse));
end

function value = emptyRule()
value = struct( ...
    'feature', '', 'direction', '', ...
    'training', struct(), 'heldout', struct());
end

function writeReport(path, summary)
fid = fopen(path, 'w');
if fid < 0
    error('RecursiveRolloutRankRulesV177:ReportOpenFailed', ...
        'Could not open the V177 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V177 recursive-rollout univariate rank rules\n\n');
fprintf(fid, '- Rules / training-safe rules: `%d / %d`\n', ...
    summary.ruleCount, numel(summary.trainingSafeRuleIndices));
fprintf(fid, '- Heldout gate passed: `%d`\n\n', ...
    summary.heldoutGatePassed);
fprintf(fid, ['| Feature | Direction | Train harmful | Train E/R/minR | ', ...
    'Heldout harmful | Heldout E/R/minR |\n']);
fprintf(fid, '|:--|:--|--:|:--|--:|:--|\n');
for idx = summary.trainingSafeRuleIndices
    rule = summary.rules(idx);
    fprintf(fid, ['| %s | %s | %d | %+.3f/%+.3f/%+.3f | ', ...
        '%d | %+.3f/%+.3f/%+.3f |\n'], ...
        rule.feature, rule.direction, ...
        rule.training.harmfulCellCount, ...
        rule.training.totalEospaGain, rule.training.totalRmseGain, ...
        rule.training.minimumRmseGain, ...
        rule.heldout.harmfulCellCount, ...
        rule.heldout.totalEospaGain, rule.heldout.totalRmseGain, ...
        rule.heldout.minimumRmseGain);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    summary.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
