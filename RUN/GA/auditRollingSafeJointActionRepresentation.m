function [reportPath, result] = ...
    auditRollingSafeJointActionRepresentation( ...
        datasetPath, formalReferencePath, options)
% AUDITROLLINGSAFEJOINTACTIONREPRESENTATION Blocking critic preflight.
%
% This audit verifies the invariance and non-collision contract before
% any multi-action H=3 rollout dataset is generated. It intentionally does
% not claim X36 numerical support: the available local X36 continuation
% caches predate the required v3 joint-action state contract.

if nargin < 1 || isempty(datasetPath)
    datasetPath = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'datasets', ...
        ['rolling_safe_joint_action_state_', ...
         'm24_hard_t75_v3.mat']);
end
if nargin < 2 || isempty(formalReferencePath)
    formalReferencePath = fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'rollout_dataset', 'seed7_postfusion_b01of02', ...
        ['DYNAMIC_TOPOLOGY_CONTINUATION_M24_HARD_', ...
         'T75_N1_20260729_063121.mat']);
end
if nargin < 3 || isempty(options)
    options = struct();
end
if isfield(options, ...
        'maximumAuditRangeViolationFraction') || ...
        isfield(options, ...
            'maximumAuditStandardizedMagnitude')
    error(['Official joint-action preflight thresholds are frozen ', ...
        'and cannot be overridden.']);
end
criticProtocol = ...
    getRollingSafeJointActionCriticProtocol();
rolloutProtocol = getRollingSafeRolloutProtocol();

loaded = load(datasetPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Joint-action preflight dataset is missing.');
end
dataset = loaded.dataset;
validateDataset(dataset, criticProtocol, rolloutProtocol);
blocks = dataset.blocks;
referenceMasks = cell(1, numel(blocks));
actionFeatures = zeros(0, 0);
referenceFeatures = zeros(0, 0);
featureNames = {};
maximumPermutationDifference = 0;
registeredDistinctActionDistances = nan(1, numel(blocks));
permutationCountPerBlock = ...
    criticProtocol.relabellingsPerBlock;
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    referenceMasks{blockIdx} = ...
        computeCode24ReferenceMask(block, dataset);
    actionOptions = makeProvenanceOptions( ...
        referenceMasks{blockIdx}, ...
        logical(block.actionTruthUsed), ...
        logical(dataset.labelSelectionUsesFutureOutcome), ...
        block.labelSource);
    referenceOptions = makeProvenanceOptions( ...
        referenceMasks{blockIdx}, false, false, ...
        'registered-code24-reference');
    [actionRow, names, metadata] = ...
        computeRollingSafeJointActionFeatures( ...
            block, block.selectedCrossMask, ...
            actionOptions);
    [referenceRow, referenceNames, referenceMetadata] = ...
        computeRollingSafeJointActionFeatures( ...
            block, referenceMasks{blockIdx}, ...
            referenceOptions);
    if blockIdx == 1
        featureNames = names;
        actionFeatures = zeros( ...
            numel(blocks), numel(actionRow));
        referenceFeatures = zeros(size(actionFeatures));
    elseif ~isequal(featureNames, names) || ...
            ~isequal(featureNames, referenceNames)
        error('Joint-action feature names differ across blocks.');
    end
    if metadata.stateFeatureTruthUsed || ...
            metadata.actionProposalTruthUsed ~= ...
                logical(block.actionTruthUsed) || ...
            metadata.actionProposalOutcomeSelected ~= ...
                logical(dataset.labelSelectionUsesFutureOutcome) || ...
            referenceMetadata.stateFeatureTruthUsed || ...
            referenceMetadata.actionProposalTruthUsed || ...
            referenceMetadata.actionProposalOutcomeSelected
        error(['Joint-action preflight detected an invalid ', ...
            'state/action provenance contract.']);
    end
    actionFeatures(blockIdx, :) = actionRow;
    referenceFeatures(blockIdx, :) = referenceRow;
    if ~isequal(logical(block.selectedCrossMask), ...
            logical(referenceMasks{blockIdx}))
        registeredDistinctActionDistances(blockIdx) = ...
            norm(actionRow - referenceRow);
    end

    offsets = unique(max(1, round([ ...
        1, numel(block.groupIds) / 3, ...
        numel(block.groupIds) / 2])));
    if numel(offsets) ~= permutationCountPerBlock
        error('Could not construct three distinct audit permutations.');
    end
    for permutationIdx = 1:numel(offsets)
        [permutedBlock, permutedAction, permutedReference] = ...
            permuteBlockLabels(block, ...
                block.selectedCrossMask, ...
                referenceMasks{blockIdx}, ...
                offsets(permutationIdx));
        [permutedActionRow, permutedNames] = ...
            computeRollingSafeJointActionFeatures( ...
                permutedBlock, permutedAction, ...
                makeProvenanceOptions( ...
                    permutedReference, ...
                    logical(block.actionTruthUsed), ...
                    logical(dataset. ...
                        labelSelectionUsesFutureOutcome), ...
                    block.labelSource));
        [permutedReferenceRow, ...
            permutedReferenceNames] = ...
            computeRollingSafeJointActionFeatures( ...
                permutedBlock, permutedReference, ...
                makeProvenanceOptions( ...
                    permutedReference, false, false, ...
                    'registered-code24-reference'));
        if ~isequal(featureNames, permutedNames) || ...
                ~isequal(featureNames, ...
                    permutedReferenceNames)
            error('Joint-action relabelling changed feature names.');
        end
        maximumPermutationDifference = max([ ...
            maximumPermutationDifference, ...
            max(abs(actionRow - permutedActionRow)), ...
            max(abs(referenceRow - ...
                permutedReferenceRow))]);
    end
end

targetIdx = find( ...
    [blocks.seed] == 7 & ...
    [blocks.currentTime] == 75 & ...
    [blocks.actionCode] == 91, 1);
if isempty(targetIdx)
    error('The seed-7 code-91 non-collision block is missing.');
end
code91Code24Distance = norm( ...
    actionFeatures(targetIdx, :) - ...
    referenceFeatures(targetIdx, :));
referenceReplayMatchesFormal = compareFormalReference( ...
    formalReferencePath, blocks(targetIdx), ...
    referenceMasks{targetIdx});
distinctMask = isfinite(registeredDistinctActionDistances);
if ~any(distinctMask)
    error('Joint-action preflight has no distinct registered actions.');
end
minimumRegisteredDistinctActionDistance = min( ...
    registeredDistinctActionDistances(distinctMask));
registeredDistinctActionCollisionCount = nnz( ...
    registeredDistinctActionDistances(distinctMask) <= ...
        criticProtocol.minimumRegisteredActionDistance);

trainingMask = ismember([blocks.seed], ...
    rolloutProtocol.trainingSeeds);
auditMask = [blocks.seed] == 7;
trainingRows = [ ...
    actionFeatures(trainingMask, :); ...
    referenceFeatures(trainingMask, :)];
auditRows = [ ...
    actionFeatures(auditMask, :); ...
    referenceFeatures(auditMask, :)];
[auditRangeViolationFraction, ...
    auditStandardizedMaximum] = ...
        computeObservedSupport(trainingRows, auditRows);
syntheticScaleFixedDimensionPassed = ...
    testSyntheticScaleFixedDimension( ...
        blocks(1), featureNames, criticProtocol);
maximumAuditRangeViolationFraction = ...
    criticProtocol.maximumAuditRangeViolationFraction;
maximumAuditStandardizedMagnitude = ...
    criticProtocol.maximumAuditStandardizedMagnitude;

corePassed = ...
    all(isfinite(actionFeatures(:))) && ...
    all(isfinite(referenceFeatures(:))) && ...
    maximumPermutationDifference <= ...
        criticProtocol.maximumRelabellingDifference && ...
    code91Code24Distance > ...
        criticProtocol.minimumRegisteredActionDistance && ...
    registeredDistinctActionCollisionCount == 0 && ...
    referenceReplayMatchesFormal && ...
    syntheticScaleFixedDimensionPassed && ...
    auditRangeViolationFraction <= ...
        maximumAuditRangeViolationFraction && ...
    auditStandardizedMaximum <= ...
        maximumAuditStandardizedMagnitude;

result = struct();
result.generatedAt = datestr(now, 31);
result.datasetPath = datasetPath;
result.datasetSha256 = computeFileSha256(datasetPath);
result.datasetGenerationGitCommit = ...
    dataset.generationGitCommit;
result.datasetVariant = dataset.datasetVariant;
result.formalReferencePath = formalReferencePath;
result.formalReferenceSha256 = ...
    computeFileSha256(formalReferencePath);
result.protocolId = criticProtocol.id;
result.contractVersion = ...
    criticProtocol.preflightContractVersion;
result.featureContractVersion = ...
    criticProtocol.representationContractVersion;
result.featureCount = numel(featureNames);
result.featureNames = featureNames;
result.blockCount = numel(blocks);
result.maximumPermutationDifference = ...
    maximumPermutationDifference;
result.permutationCountPerBlock = ...
    permutationCountPerBlock;
result.code91Code24Distance = code91Code24Distance;
result.registeredDistinctActionPairCount = ...
    nnz(distinctMask);
result.minimumRegisteredDistinctActionDistance = ...
    minimumRegisteredDistinctActionDistance;
result.registeredDistinctActionCollisionCount = ...
    registeredDistinctActionCollisionCount;
result.referenceReplayMatchesFormal = ...
    referenceReplayMatchesFormal;
result.auditRangeViolationFraction = ...
    auditRangeViolationFraction;
result.auditStandardizedMaximum = ...
    auditStandardizedMaximum;
result.maximumAuditRangeViolationFraction = ...
    maximumAuditRangeViolationFraction;
result.maximumAuditStandardizedMagnitude = ...
    maximumAuditStandardizedMagnitude;
result.fixedDimensionAcrossSyntheticScalesTested = ...
    syntheticScaleFixedDimensionPassed;
result.x36NumericalRangeSupportTested = false;
result.x36NumericalRangeSupportPassed = false;
result.acceptedForM24MultiActionDataGeneration = corePassed;
result.acceptedForX36ZeroShot = false;
result.evidenceBoundary = [ ...
    'Conditional on consistently relabelled truth-free edge rows, ', ...
    'the preflight verifies M24 joint-pooling invariance, fixed ', ...
    'dimension and code-91/code-24 non-collision. The code-91 ', ...
    'action was selected using privileged future-outcome labels; ', ...
    'only its state features are truth-free. The code-24 reference ', ...
    'is truth-free and outcome-independent. The audit does not ', ...
    'feed global delivered-history ACKs to the critic; v3 stores ', ...
    'delivered history only to attest offline delivery outcomes, ', ...
    'while deployable features use selected history and current ', ...
    'link reliability. The audit does not ', ...
    'verify end-to-end edge-extractor/projector equivariance, ', ...
    'broad proposal-bank collision versus return gaps, candidate ', ...
    'coverage, tracking-return prediction or X36 numerical ', ...
    'support. X36 remains blocked until a separate frozen X36 ', ...
    'protocol, compatible state artifact and numerical-support ', ...
    'audit are available.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology'));
if ~exist(outputDirectory, 'dir')
    mkdir(outputDirectory);
end
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'JOINT_ACTION_REPRESENTATION_PREFLIGHT_M24.md'));
writeReport(reportPath, result);
fprintf('Report: %s\n', reportPath);
end

function validateDataset(dataset, criticProtocol, rolloutProtocol)
requiredFields = { ...
    'protocolId', 'sourceRolloutProtocolId', ...
    'contractVersion', 'datasetVariant', 'presetName', ...
    'seeds', 'actionCodeSequences', ...
    'continuationStartTime', 'snapshotTimes', ...
    'sourceWeight', 'payloadToleranceFraction', ...
    'featuresUseTruth', 'labelsUseTruth', ...
    'labelSelectionUsesFutureOutcome', 'blocks', ...
    'featureContextMode', 'featureNames', ...
    'behaviorCacheSha256', 'behaviorCacheRecords', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty'};
if ~isstruct(dataset) || ...
        ~all(isfield(dataset, requiredFields)) || ...
        ~strcmp(dataset.protocolId, criticProtocol.id) || ...
        ~strcmp(dataset.sourceRolloutProtocolId, ...
            criticProtocol.rolloutProtocolId) || ...
        ~strcmp(dataset.contractVersion, ...
            criticProtocol.datasetContractVersion) || ...
        ~strcmp(dataset.datasetVariant, ...
            'joint-action-state-v3') || ...
        dataset.featuresUseTruth || ...
        ~dataset.labelsUseTruth || ...
        ~dataset.labelSelectionUsesFutureOutcome || ...
        ~strcmp(dataset.presetName, ...
            criticProtocol.presetName) || ...
        ~strcmp(dataset.featureContextMode, ...
            criticProtocol.featureContextMode) || ...
        ~isequal(dataset.seeds, ...
            criticProtocol.datasetSeeds) || ...
        ~isequal(dataset.actionCodeSequences, ...
            criticProtocol.actionCodeSequences) || ...
        ~isequal(dataset.snapshotTimes, ...
            criticProtocol.snapshotTimes) || ...
        dataset.continuationStartTime ~= ...
            criticProtocol.snapshotTimes(1) || ...
        abs(dataset.sourceWeight - ...
            criticProtocol.sourceWeight) > 1e-12 || ...
        ~sameScalar(dataset.payloadToleranceFraction, ...
            criticProtocol.payloadToleranceFraction) || ...
        ~isequal(dataset.behaviorCacheSha256, ...
            criticProtocol.behaviorCacheSha256) || ...
        ~strcmp(computeTextSha256(strjoin( ...
            dataset.behaviorCacheSha256, char(31))), ...
            criticProtocol.behaviorCacheSetSha256) || ...
        logical(dataset. ...
            generationTrackedWorktreeDirty) || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        logical(dataset. ...
            generationResearchWorktreeDirty) || ...
        numel(dataset.blocks) ~= ...
            numel(criticProtocol.datasetSeeds) * ...
                numel(criticProtocol.snapshotTimes)
    error(['Invalid or non-clean v3 rolling-safe dataset for ', ...
        'joint-action preflight.']);
end
validateGenerationSourceCommit( ...
    dataset.generationGitCommit);
records = dataset.behaviorCacheRecords;
if numel(records) ~= ...
        numel(criticProtocol.datasetSeeds)
    error('Joint-action behavior-cache records are incomplete.');
end
for seedIdx = 1:numel(criticProtocol.datasetSeeds)
    if records(seedIdx).seed ~= ...
            criticProtocol.datasetSeeds(seedIdx) || ...
            ~strcmp(records(seedIdx).sha256, ...
                criticProtocol. ...
                    behaviorCacheSha256{seedIdx})
        error('Joint-action behavior-cache attestation mismatch.');
    end
end
blockIdx = 0;
for seedIdx = 1:numel(criticProtocol.datasetSeeds)
    for timeIdx = 1:numel(criticProtocol.snapshotTimes)
        blockIdx = blockIdx + 1;
        block = dataset.blocks(blockIdx);
        blockRequired = { ...
            'seed', 'currentTime', 'relativeTime', ...
            'actionCode', 'features', 'featureNames', ...
            'featureMetadata', 'selectedCrossMask', ...
            'previousAdjacencyHistory', ...
            'previousAdjacencyHistoryTimes', ...
            'previousDeliveredAdjacencyHistory', ...
            'previousDeliveredAdjacencyHistoryTimes', ...
            'labelTruthUsed', 'labelSource'};
        if ~all(isfield(block, blockRequired)) || ...
                block.seed ~= ...
                    criticProtocol.datasetSeeds(seedIdx) || ...
                block.currentTime ~= ...
                    criticProtocol.snapshotTimes(timeIdx) || ...
                block.relativeTime ~= timeIdx || ...
                block.actionCode ~= ...
                    criticProtocol. ...
                        actionCodeSequences(seedIdx, timeIdx) || ...
                ~isequal(block.featureNames, ...
                    dataset.featureNames) || ...
                ~logical(block.labelTruthUsed) || ...
                isempty(strtrim(block.labelSource))
            error('Joint-action block grid or contract mismatch.');
        end
        validateDeliveredHistoryAttestation(block);
    end
end
if ~strcmp(rolloutProtocol.id, ...
        criticProtocol.rolloutProtocolId)
    error('Joint-action source rollout protocol mismatch.');
end
end

function validateGenerationSourceCommit(commit)
commit = char(commit);
if isempty(regexp(commit, '^[0-9a-f]{40}$', 'once'))
    error('Joint-action dataset generation commit is invalid.');
end
[headStatus, head] = system('git rev-parse HEAD');
if headStatus ~= 0 || ...
        isempty(regexp(strtrim(head), ...
            '^[0-9a-f]{40}$', 'once'))
    error('Could not resolve the current audit commit.');
end
[ancestorStatus, ~] = system(sprintf( ...
    'git merge-base --is-ancestor %s %s', ...
    commit, strtrim(head)));
if ancestorStatus ~= 0
    error(['Joint-action dataset was not generated from an ', ...
        'ancestor of the current audit commit.']);
end
[diffStatus, changedSource] = system(sprintf( ...
    ['git diff --name-only %s..%s -- ', ...
     ''':(glob)**/*.m'''], ...
    commit, strtrim(head)));
if diffStatus ~= 0 || ~isempty(strtrim(changedSource))
    error(['Joint-action MATLAB/Octave source changed after ', ...
        'dataset generation. Regenerate the v3 artifact.']);
end
[localStatus, localSource] = system( ...
    ['git status --porcelain --untracked-files=all -- ', ...
     ''':(glob)**/*.m''']);
if localStatus ~= 0 || ~isempty(strtrim(localSource))
    error(['Joint-action audit requires a clean local ', ...
        'MATLAB/Octave source tree.']);
end
end

function validateDeliveredHistoryAttestation(block)
selected = block.previousAdjacencyHistory;
delivered = ...
    block.previousDeliveredAdjacencyHistory;
selectedTimes = reshape( ...
    block.previousAdjacencyHistoryTimes, 1, []);
deliveredTimes = reshape( ...
    block.previousDeliveredAdjacencyHistoryTimes, 1, []);
if ~isequal(size(selected), size(delivered)) || ...
        ~isequal(selectedTimes, deliveredTimes) || ...
        ~(islogical(selected) || isnumeric(selected)) || ...
        ~(islogical(delivered) || isnumeric(delivered)) || ...
        any(~ismember(double(selected(:)), [0, 1])) || ...
        any(~ismember(double(delivered(:)), [0, 1])) || ...
        any(logical(delivered(:)) & ...
            ~logical(selected(:)))
    error(['Joint-action delivered history is not an attested ', ...
        'subset of selected history.']);
end
end

function mask = computeCode24ReferenceMask(block, dataset)
nodeCount = numel(block.groupIds);
groupCount = numel(unique(block.groupIds));
if groupCount ~= 4
    error('The registered M24 code-24 replay requires four formations.');
end
context = struct();
context.localPosteriorBySensor = ...
    repmat({struct([])}, 1, nodeCount);
context.model = struct( ...
    'xDimension', 4, ...
    'dynamicTopologyScenario', struct( ...
        'config', struct( ...
            'sensorGroupIds', ...
                reshape(block.groupIds, 1, []))));
context.physicalAdjacency = ...
    logical(block.physicalAdjacency);
context.currentTime = block.currentTime;
context.previousAdjacencyHistory = ...
    logical(block.previousAdjacencyHistory);
context.previousAdjacencyHistoryCount = ...
    size(context.previousAdjacencyHistory, 3);
if isempty(context.previousAdjacencyHistory)
    context.previousAdjacency = false(nodeCount);
else
    context.previousAdjacency = ...
        context.previousAdjacencyHistory(:, :, end);
end
context.previousAdjacencyHistoryTimes = ...
    block.previousAdjacencyHistoryTimes;
context.directedMessageBudget = nodeCount;
context.commConfig = struct( ...
    'pDropByEdge', zeros(nodeCount));

[adjacency, details] = selectRollingSafeRoutingPolicy( ...
    context, 'scheduled-burst', struct( ...
        'sourceWeight', dataset.sourceWeight, ...
        'rootFormation', 4, ...
        'orientation', 'counter-clockwise', ...
        'temporalPhase', 2, ...
        'payloadToleranceFraction', ...
            dataset.payloadToleranceFraction, ...
        'senderPayloadBytes', ...
            block.senderPayloadBytes));
if details.topologyInfeasible
    error('Code-24 reference replay was infeasible.');
end
indices = sub2ind( ...
    [nodeCount, nodeCount], ...
    block.receiverIndices, block.senderIndices);
mask = reshape(logical(adjacency(indices)), [], 1);
end

function [permuted, actionMask, referenceMask] = ...
        permuteBlockLabels( ...
            block, actionMask, referenceMask, offset)
nodeCount = numel(block.groupIds);
if ~isscalar(offset) || ~isfinite(offset)
    error('Audit relabelling offset is invalid.');
end
offset = mod(round(offset), nodeCount);
if offset == 0
    error('Audit relabelling must be non-identity.');
end
oldToNew = circshift(1:nodeCount, [0, offset]);
groups = unique(block.groupIds);
rowOrder = circshift( ...
    size(block.features, 1):-1:1, [0, offset]);
permuted = block;
permuted.features = block.features(rowOrder, :);
permuted.receiverIndices = reshape(oldToNew( ...
    block.receiverIndices(rowOrder)), [], 1);
permuted.senderIndices = reshape(oldToNew( ...
    block.senderIndices(rowOrder)), [], 1);
permuted.featureMetadata.candidateEdgeKeys = ...
    permuted.receiverIndices + ...
    nodeCount * (permuted.senderIndices - 1);
permuted.groupIds = zeros(size(block.groupIds));
permuted.senderPayloadBytes = ...
    zeros(size(block.senderPayloadBytes));
permuted.previousAdjacencyHistory = ...
    transportPolicyHistory( ...
        block.previousAdjacencyHistory, oldToNew);
permuted.previousDeliveredAdjacencyHistory = ...
    transportPolicyHistory( ...
        block.previousDeliveredAdjacencyHistory, oldToNew);
labelMap = 100 + 17 * (numel(groups):-1:1);
for oldSensor = 1:nodeCount
    newSensor = oldToNew(oldSensor);
    oldGroupIdx = find( ...
        groups == block.groupIds(oldSensor), 1);
    permuted.groupIds(newSensor) = ...
        labelMap(oldGroupIdx);
    permuted.senderPayloadBytes(newSensor) = ...
        block.senderPayloadBytes(oldSensor);
end
actionMask = logical(reshape(actionMask(rowOrder), [], 1));
referenceMask = logical(reshape( ...
    referenceMask(rowOrder), [], 1));
end

function transported = transportPolicyHistory( ...
        history, oldToNew)
nodeCount = numel(oldToNew);
transported = false(size(history));
for pageIdx = 1:size(history, 3)
    [receivers, senders] = ...
        find(history(:, :, pageIdx));
    page = false(nodeCount);
    indices = sub2ind( ...
        [nodeCount, nodeCount], ...
        oldToNew(receivers), ...
        oldToNew(senders));
    page(indices) = true;
    transported(:, :, pageIdx) = page;
end
end

function options = makeProvenanceOptions( ...
        referenceMask, truthUsed, outcomeSelected, source)
options = struct( ...
    'referenceCrossMask', logical(referenceMask), ...
    'actionProposalTruthUsed', logical(truthUsed), ...
    'actionProposalOutcomeSelected', ...
        logical(outcomeSelected), ...
    'actionProposalSource', char(source));
end

function matched = compareFormalReference( ...
        path, block, expectedMask)
loaded = load(path, 'summary');
if ~isfield(loaded, 'summary')
    error('Formal code-24 reference summary is missing.');
end
summary = loaded.summary;
idx = find(strcmp( ...
    {summary.aggregate.mode}, ...
    'rolling-safe-sequence-t75-s242424-w70'), 1);
if isempty(idx)
    error('Formal summary has no code-24 reference arm.');
end
history = summary.aggregate(idx). ...
    focusSelectedDirectedEdgeHistoryBySeed{1};
policyAdjacency = ...
    convertDiagnosticEdgeMaskToPolicyAdjacency( ...
        history(:, :, 1));
nodeCount = numel(block.groupIds);
indices = sub2ind( ...
    [nodeCount, nodeCount], ...
    block.receiverIndices, block.senderIndices);
formalMask = reshape(logical( ...
    policyAdjacency(indices)), [], 1);
matched = isequal(formalMask, logical(expectedMask));
end

function [violationFraction, maximum] = ...
        computeObservedSupport(trainingRows, auditRows)
location = mean(trainingRows, 1);
scale = std(trainingRows, 0, 1);
scale(~isfinite(scale) | scale <= eps) = 1;
standardized = abs(bsxfun(@rdivide, ...
    bsxfun(@minus, auditRows, location), scale));
maximum = max(standardized(:));
lower = min(trainingRows, [], 1);
upper = max(trainingRows, [], 1);
violations = bsxfun(@lt, auditRows, lower - 1e-12) | ...
    bsxfun(@gt, auditRows, upper + 1e-12);
violationFraction = mean(violations(:));
end

function passed = testSyntheticScaleFixedDimension( ...
        templateBlock, expectedNames, protocol)
pairs = protocol.syntheticScaleSensorFormationPairs;
configurations = [ ...
    pairs(:, 2), pairs(:, 1) ./ pairs(:, 2)];
if any(mod(configurations(:, 2), 1) ~= 0)
    error('Synthetic scale protocol has nonuniform formations.');
end
passed = true;
for configurationIdx = 1:size(configurations, 1)
    groupCount = configurations(configurationIdx, 1);
    sensorCountPerGroup = ...
        configurations(configurationIdx, 2);
    block = makeSyntheticScaleBlock( ...
        templateBlock, groupCount, ...
        sensorCountPerGroup);
    [actionMask, referenceMask] = ...
        makeSyntheticScaleMasks( ...
            block, groupCount - 1);
    [row, names] = ...
        computeRollingSafeJointActionFeatures( ...
            block, actionMask, ...
            makeProvenanceOptions( ...
                referenceMask, false, false, ...
                sprintf('synthetic-s%d-g%d', ...
                    numel(block.groupIds), ...
                    groupCount)));
    passed = passed && ...
        isequal(names, expectedNames) && ...
        numel(row) == numel(expectedNames) && ...
        all(isfinite(row));
end
end

function block = makeSyntheticScaleBlock( ...
        templateBlock, groupCount, sensorCountPerGroup)
groupIds = repelem( ...
    1:groupCount, sensorCountPerGroup);
nodeCount = numel(groupIds);
receivers = zeros(0, 1);
senders = zeros(0, 1);
for receiverIdx = 1:nodeCount
    candidates = find(groupIds ~= groupIds(receiverIdx));
    receivers = [receivers; repmat( ...
        receiverIdx, numel(candidates), 1)]; %#ok<AGROW>
    senders = [senders; reshape( ...
        candidates, [], 1)]; %#ok<AGROW>
end
featureCount = numel(templateBlock.featureNames);
features = zeros(numel(receivers), featureCount);
for featureIdx = 1:featureCount
    features(:, featureIdx) = mod( ...
        0.137 * receivers + ...
        0.071 * senders + ...
        0.019 * featureIdx + ...
        0.011 * receivers .* senders, 1);
end
selectedHistory = false(nodeCount, nodeCount, 2);
for receiverIdx = 1:nodeCount
    sender1 = mod(receiverIdx, nodeCount) + 1;
    sender2 = mod(receiverIdx + 1, nodeCount) + 1;
    selectedHistory(receiverIdx, sender1, 1) = true;
    selectedHistory(receiverIdx, sender2, 2) = true;
end
deliveredHistory = selectedHistory;
deliveredHistory(1, :, 1) = false;
deliveredHistory(2, :, 2) = false;
featureMetadata = templateBlock.featureMetadata;
featureMetadata.nodeCount = nodeCount;
featureMetadata.crossFormationExampleCount = ...
    numel(receivers);
featureMetadata.historyDepth = 2;
featureMetadata.candidateEdgeKeys = receivers + ...
    nodeCount * (senders - 1);
block = struct( ...
    'features', features, ...
    'featureNames', {templateBlock.featureNames}, ...
    'featureMetadata', featureMetadata, ...
    'receiverIndices', receivers, ...
    'senderIndices', senders, ...
    'groupIds', groupIds, ...
    'currentTime', 3, ...
    'previousAdjacencyHistory', selectedHistory, ...
    'previousAdjacencyHistoryTimes', [1, 2], ...
    'previousDeliveredAdjacencyHistory', ...
        deliveredHistory, ...
    'previousDeliveredAdjacencyHistoryTimes', [1, 2], ...
    'senderPayloadBytes', ...
        500 + 37 * (1:nodeCount));
end

function [actionMask, referenceMask] = ...
        makeSyntheticScaleMasks(block, count)
actionMask = false(size(block.receiverIndices));
referenceMask = false(size(block.receiverIndices));
used = 0;
for receiverIdx = unique(reshape( ...
        block.receiverIndices, 1, []), 'stable')
    candidates = find( ...
        block.receiverIndices == receiverIdx);
    if numel(candidates) < 2
        continue;
    end
    used = used + 1;
    actionMask(candidates(1)) = true;
    referenceMask(candidates(end)) = true;
    if used >= count
        break;
    end
end
if nnz(actionMask) ~= count || ...
        nnz(referenceMask) ~= count
    error('Synthetic scale action construction failed.');
end
end

