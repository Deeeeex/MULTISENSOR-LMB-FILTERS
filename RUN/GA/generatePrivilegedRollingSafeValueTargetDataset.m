function [datasetPath, dataset] = ...
    generatePrivilegedRollingSafeValueTargetDataset(options)
% GENERATEPRIVILEGEDROLLINGSAFEVALUETARGETDATASET Freeze M24 value targets.
%
% Joins the frozen privileged proposal graphs to their paired H=3 returns.
% Truth and future outcomes are used only to construct offline supervision.
% The deployable proposal model may consume only the copied truth-free edge
% features and must still pass through the exact rolling-B=3 projector.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
sourcePath = getField(options, 'sourceStatePath', ...
    protocol.proposalSourceStateRelativePath);
proposalPath = getField(options, 'proposalDatasetPath', ...
    protocol.privilegedProposalDatasetRelativePath);
returnAuditPath = getField(options, 'returnAuditPath', ...
    protocol.privilegedReturnV2AuditRelativePath);
validateFrozenFile(sourcePath, ...
    protocol.proposalSourceStateSha256, 'source state');
validateFrozenFile(proposalPath, ...
    protocol.privilegedProposalDatasetSha256, ...
    'privileged proposal dataset');
validateFrozenFile(returnAuditPath, ...
    protocol.privilegedReturnV2AuditSha256, ...
    'privileged v2 return audit');

gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official value-target generation requires clean source.');
end

sourceLoaded = load(sourcePath, 'dataset');
proposalLoaded = load(proposalPath, 'dataset');
auditLoaded = load(returnAuditPath, 'audit');
if ~isfield(sourceLoaded, 'dataset') || ...
        ~isfield(proposalLoaded, 'dataset') || ...
        ~isfield(auditLoaded, 'audit')
    error('A frozen value-target input lacks its expected payload.');
end
source = sourceLoaded.dataset;
proposal = proposalLoaded.dataset;
returnAudit = auditLoaded.audit;
validateInputEnvelopes(source, proposal, returnAudit, protocol);

blockCount = numel(proposal.blocks);
blocks = repmat(emptyBlock(), 1, blockCount);
totalCandidateCount = 0;
totalValueTargetCount = 0;
targetStateCount = 0;
for blockIdx = 1:blockCount
    proposalBlock = proposal.blocks(blockIdx);
    sourceBlock = source.blocks(proposalBlock.sourceBlockIndex);
    stateRow = findStateRow(returnAudit.stateRows, ...
        proposalBlock.seed, proposalBlock.currentTime);
    candidateRows = findCandidateRows(returnAudit.candidateRows, ...
        proposalBlock.seed, proposalBlock.currentTime);
    [~, order] = sort([candidateRows.candidateIndex]);
    candidateRows = candidateRows(order);
    validateBlockJoin( ...
        sourceBlock, proposalBlock, stateRow, candidateRows);

    valueTargetMask = logical( ...
        [candidateRows.repairMonitoredAdmissibleFivePercentGain]);
    v2FeasibleMask = logical( ...
        [candidateRows.repairMonitoredFeasible]);
    hardFeasibleMask = logical( ...
        [candidateRows.hardFeasible]);
    hardValueTargetMask = logical( ...
        [candidateRows.admissibleFivePercentGain]);
    valueTargetIndices = find(valueTargetMask);
    valueOracleCandidateIndex = NaN;
    if ~isempty(valueTargetIndices)
        [~, localBest] = min( ...
            [candidateRows(valueTargetIndices).meanEospa]);
        valueOracleCandidateIndex = ...
            valueTargetIndices(localBest);
        targetStateCount = targetStateCount + 1;
    end

    block = emptyBlock();
    block.seed = proposalBlock.seed;
    block.currentTime = proposalBlock.currentTime;
    block.sourceBlockIndex = ...
        proposalBlock.sourceBlockIndex;
    block.privilegedProposalBlockIndex = blockIdx;
    block.edgeFeatures = sourceBlock.features;
    block.edgeFeatureNames = sourceBlock.featureNames;
    block.edgeFeatureMetadata = ...
        sourceBlock.featureMetadata;
    block.receiverIndices = sourceBlock.receiverIndices;
    block.senderIndices = sourceBlock.senderIndices;
    block.groupIds = sourceBlock.groupIds;
    block.physicalAdjacency = ...
        sourceBlock.physicalAdjacency;
    block.previousAdjacencyHistory = ...
        sourceBlock.previousAdjacencyHistory;
    block.previousAdjacencyHistoryTimes = ...
        sourceBlock.previousAdjacencyHistoryTimes;
    block.candidateCount = proposalBlock.candidateCount;
    block.candidateActionCodes = ...
        proposalBlock.candidateActionCodes;
    block.candidateGraphSha256 = ...
        proposalBlock.candidateGraphSha256;
    block.candidateAdjacency = ...
        proposalBlock.candidateAdjacency;
    block.candidateCrossMasks = ...
        proposalBlock.candidateCrossMasks;
    block.candidateJointFeatures = ...
        proposalBlock.jointFeatures;
    block.candidateMeanEospa = ...
        [candidateRows.meanEospa];
    block.candidateWorstSensorEospa = ...
        [candidateRows.worstSensorEospa];
    block.candidateAttemptedBytes = ...
        [candidateRows.attemptedBytes];
    block.candidateDeliveredBytes = ...
        [candidateRows.deliveredBytes];
    block.candidateGainFraction = ...
        [candidateRows.gainFraction];
    block.candidateAttemptedByteDeviationFraction = ...
        [candidateRows.attemptedByteDeviationFraction];
    block.candidateTailNondegrading = logical( ...
        [candidateRows.tailNondegrading]);
    block.candidateAdditionalRepairCount = ...
        [candidateRows.additionalRepairCount];
    block.candidateFirstActionRepair = logical( ...
        [candidateRows.firstActionRepair]);
    block.candidatePayloadEmergencyCount = ...
        [candidateRows.payloadEmergencyCount];
    block.candidateInfeasibleCount = ...
        [candidateRows.infeasibleCount];
    block.candidateSelectedRollingB3Passed = logical( ...
        [candidateRows.selectedRollingB3Passed]);
    block.candidateDeliveredRollingB3Passed = logical( ...
        [candidateRows.deliveredRollingB3Passed]);
    block.candidateHardFeasible = hardFeasibleMask;
    block.candidateV2Feasible = v2FeasibleMask;
    block.candidateHardValueTarget = ...
        hardValueTargetMask;
    block.candidateV2ValueTarget = valueTargetMask;
    block.valueTargetCount = nnz(valueTargetMask);
    block.valueTargetCandidateIndices = ...
        valueTargetIndices;
    block.valueTargetCrossMasks = ...
        proposalBlock.candidateCrossMasks( ...
            :, valueTargetMask);
    block.valueOracleCandidateIndex = ...
        valueOracleCandidateIndex;
    block.valueOracleActionCode = NaN;
    block.valueOracleGraphSha256 = '';
    if isfinite(valueOracleCandidateIndex)
        block.valueOracleActionCode = ...
            block.candidateActionCodes( ...
                valueOracleCandidateIndex);
        block.valueOracleGraphSha256 = ...
            block.candidateGraphSha256{ ...
                valueOracleCandidateIndex};
    end
    block.referenceMeanEospa = ...
        stateRow.referenceMeanEospa;
    block.referenceWorstSensorEospa = ...
        stateRow.referenceWorstSensorEospa;
    block.referenceAttemptedBytes = ...
        stateRow.referenceAttemptedBytes;
    block.referenceDeliveredBytes = ...
        stateRow.referenceDeliveredBytes;
    block.v2OracleCandidateIndex = ...
        stateRow.repairMonitoredOracleCandidateIndex;
    block.v2OracleActionCode = ...
        stateRow.repairMonitoredOracleActionCode;
    block.v2OracleMeanEospa = ...
        stateRow.repairMonitoredOracleMeanEospa;
    block.v2OracleGainFraction = ...
        stateRow.repairMonitoredOracleGainFraction;
    blocks(blockIdx) = block;

    totalCandidateCount = ...
        totalCandidateCount + block.candidateCount;
    totalValueTargetCount = ...
        totalValueTargetCount + block.valueTargetCount;
    fprintf(['value targets seed %d t=%d: ', ...
        '%d/%d v2 targets, oracle code %s\n'], ...
        block.seed, block.currentTime, ...
        block.valueTargetCount, block.candidateCount, ...
        formatOptionalCode(block.valueOracleActionCode));
end

if targetStateCount ~= ...
        protocol.privilegedReturnV2ExpectedTargetStateCount || ...
        totalValueTargetCount ~= ...
        protocol.privilegedReturnV2ExpectedValueTargetCount || ...
        totalCandidateCount ~= ...
        protocol.privilegedProposalExpectedTargetCount
    error('Joined value-target counts violate the frozen v2 audit.');
end

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'datasets'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
datasetPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    ['rolling_safe_privileged_value_targets_', ...
     'm24_hard_t75_v2.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    ['ROLLING_SAFE_PRIVILEGED_VALUE_TARGETS_', ...
     'M24_HARD_T75_V2.md']));

dataset = struct();
dataset.protocolId = protocol.id;
dataset.contractVersion = ...
    protocol.privilegedValueTargetDatasetContractVersion;
dataset.generatedAt = datestr(now, 31);
dataset.presetName = protocol.presetName;
dataset.seeds = protocol.datasetSeeds;
dataset.snapshotTimes = protocol.snapshotTimes;
dataset.sourceWeight = protocol.sourceWeight;
dataset.sourceStatePath = sourcePath;
dataset.sourceStateSha256 = ...
    protocol.proposalSourceStateSha256;
dataset.privilegedProposalDatasetPath = proposalPath;
dataset.privilegedProposalDatasetSha256 = ...
    protocol.privilegedProposalDatasetSha256;
dataset.returnAuditPath = returnAuditPath;
dataset.returnAuditSha256 = ...
    protocol.privilegedReturnV2AuditSha256;
dataset.edgeFeatureNames = source.featureNames;
dataset.jointFeatureNames = ...
    proposal.jointFeatureNames;
dataset.blocks = blocks;
dataset.totalCandidateCount = totalCandidateCount;
dataset.targetStateCount = targetStateCount;
dataset.totalValueTargetCount = ...
    totalValueTargetCount;
dataset.minimumValueGainFraction = ...
    protocol.minimumPrivilegedAdmissibleGain;
dataset.firstActionExactRequired = ...
    protocol.privilegedReturnV2FirstActionExactRequired;
dataset.firstActionRepairAllowed = ...
    protocol.privilegedReturnV2FirstActionRepairAllowed;
dataset.laterProjectionRepairAllowed = ...
    protocol.privilegedReturnV2LaterProjectionRepairAllowed;
dataset.truthUsed = true;
dataset.futureOutcomeUsed = true;
dataset.deployable = false;
dataset.designSeen = true;
dataset.proposalModelTrained = false;
dataset.topKCaptureEvaluated = false;
dataset.criticTrainingAuthorized = false;
dataset.x36Authorized = false;
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.evidenceBoundary = [ ...
    'This artifact joins offline truth-labelled safe graphs to ', ...
    'design-seen future H=3 returns. Only edgeFeatures and the ', ...
    'frozen histories are deployable inputs; value-target labels ', ...
    'use truth and future outcomes. The artifact authorizes ', ...
    'proposal-head development only and does not establish top-K ', ...
    'capture, critic accuracy, unseen-seed M24 or X36 benefit.'];
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Value-target dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);
end

function validateInputEnvelopes( ...
        source, proposal, returnAudit, protocol)
if ~strcmp(source.contractVersion, ...
        protocol.datasetContractVersion) || ...
        ~strcmp(proposal.contractVersion, ...
            protocol.privilegedProposalDatasetContractVersion) || ...
        ~strcmp(returnAudit.contractVersion, ...
            protocol.privilegedReturnV2AuditContractVersion) || ...
        ~returnAudit.candidateOracleReturnGatePassed || ...
        ~returnAudit.valueFilteredProposalDistillationAuthorized || ...
        ~returnAudit.developmentReanalysis || ...
        returnAudit.validationClaimAllowed || ...
        ~isequal(source.seeds, protocol.datasetSeeds) || ...
        ~isequal(proposal.seeds, protocol.datasetSeeds) || ...
        ~isequal(returnAudit.seeds, protocol.datasetSeeds) || ...
        ~isequal(source.snapshotTimes, protocol.snapshotTimes) || ...
        ~isequal(proposal.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~isequal(returnAudit.times, protocol.snapshotTimes)
    error('Value-target inputs violate the frozen contracts.');
end
end

function row = findStateRow(rows, seed, currentTime)
indices = find([rows.seed] == seed & ...
    [rows.currentTime] == currentTime);
if numel(indices) ~= 1
    error('Return audit lacks a unique seed-time state row.');
end
row = rows(indices);
end

function rows = findCandidateRows(rows, seed, currentTime)
indices = find([rows.seed] == seed & ...
    [rows.currentTime] == currentTime);
rows = rows(indices);
if isempty(rows)
    error('Return audit lacks seed-time candidate rows.');
end
end

function validateBlockJoin( ...
        sourceBlock, proposalBlock, stateRow, candidateRows)
candidateCount = proposalBlock.candidateCount;
if sourceBlock.seed ~= proposalBlock.seed || ...
        sourceBlock.currentTime ~= proposalBlock.currentTime || ...
        stateRow.seed ~= proposalBlock.seed || ...
        stateRow.currentTime ~= proposalBlock.currentTime || ...
        numel(candidateRows) ~= candidateCount || ...
        stateRow.candidateCount ~= candidateCount || ...
        ~isequal([candidateRows.candidateIndex], ...
            1:candidateCount) || ...
        ~isequal([candidateRows.actionCode], ...
            proposalBlock.candidateActionCodes) || ...
        ~isequal({candidateRows.graphSha256}, ...
            proposalBlock.candidateGraphSha256)
    error('Privileged proposals and return rows do not join exactly.');
end
if any([candidateRows.firstActionRepair]) || ...
        any(~[candidateRows.selectedRollingB3Passed]) || ...
        any([candidateRows.payloadEmergencyCount] > 0) || ...
        any([candidateRows.infeasibleCount] > 0)
    error('Value-target source violates first-action safety.');
end
end

function validateFrozenFile(path, expectedSha256, description)
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), expectedSha256)
    error('Missing or mismatched frozen %s.', description);
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open value-target report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# Privileged rolling-safe value targets: M24\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Truth used in labels: `%d`\n', ...
    dataset.truthUsed);
fprintf(fid, '- Future outcomes used in labels: `%d`\n', ...
    dataset.futureOutcomeUsed);
fprintf(fid, '- Deployable artifact: `%d`\n', ...
    dataset.deployable);
fprintf(fid, '- Design-seen: `%d`\n', dataset.designSeen);
fprintf(fid, '- Candidate graphs: `%d`\n', ...
    dataset.totalCandidateCount);
fprintf(fid, '- Value-filtered targets: `%d`\n', ...
    dataset.totalValueTargetCount);
fprintf(fid, '- Target-bearing states: `%d / %d`\n', ...
    dataset.targetStateCount, numel(dataset.blocks));
fprintf(fid, '- Minimum target gain: `%.1f%%`\n', ...
    100 * dataset.minimumValueGainFraction);
fprintf(fid, '- Proposal model trained: `%d`\n', ...
    dataset.proposalModelTrained);
fprintf(fid, '- Top-K capture evaluated: `%d`\n', ...
    dataset.topKCaptureEvaluated);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, '## State blocks\n\n');
fprintf(fid, ...
    ['| Seed | Time | Candidates | V2 targets | ', ...
     'Value oracle | Oracle gain | Target codes |\n']);
fprintf(fid, '|--:|--:|--:|--:|:--|--:|:--|\n');
for block = dataset.blocks
    fprintf(fid, '| %d | %d | %d | %d | `%s` | %.3f%% | `%s` |\n', ...
        block.seed, block.currentTime, ...
        block.candidateCount, block.valueTargetCount, ...
        formatOptionalCode(block.valueOracleActionCode), ...
        100 * block.v2OracleGainFraction, ...
        formatActionCodes(block.candidateActionCodes( ...
            block.candidateV2ValueTarget)));
end
end

function block = emptyBlock()
block = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'sourceBlockIndex', NaN, ...
    'privilegedProposalBlockIndex', NaN, ...
    'edgeFeatures', zeros(0, 0), ...
    'edgeFeatureNames', {cell(1, 0)}, ...
    'edgeFeatureMetadata', struct(), ...
    'receiverIndices', [], ...
    'senderIndices', [], ...
    'groupIds', [], ...
    'physicalAdjacency', false(0, 0), ...
    'previousAdjacencyHistory', false(0, 0, 0), ...
    'previousAdjacencyHistoryTimes', [], ...
    'candidateCount', 0, ...
    'candidateActionCodes', [], ...
    'candidateGraphSha256', {cell(1, 0)}, ...
    'candidateAdjacency', false(0, 0, 0), ...
    'candidateCrossMasks', false(0, 0), ...
    'candidateJointFeatures', zeros(0, 0), ...
    'candidateMeanEospa', [], ...
    'candidateWorstSensorEospa', [], ...
    'candidateAttemptedBytes', [], ...
    'candidateDeliveredBytes', [], ...
    'candidateGainFraction', [], ...
    'candidateAttemptedByteDeviationFraction', [], ...
    'candidateTailNondegrading', false(1, 0), ...
    'candidateAdditionalRepairCount', [], ...
    'candidateFirstActionRepair', false(1, 0), ...
    'candidatePayloadEmergencyCount', [], ...
    'candidateInfeasibleCount', [], ...
    'candidateSelectedRollingB3Passed', false(1, 0), ...
    'candidateDeliveredRollingB3Passed', false(1, 0), ...
    'candidateHardFeasible', false(1, 0), ...
    'candidateV2Feasible', false(1, 0), ...
    'candidateHardValueTarget', false(1, 0), ...
    'candidateV2ValueTarget', false(1, 0), ...
    'valueTargetCount', 0, ...
    'valueTargetCandidateIndices', [], ...
    'valueTargetCrossMasks', false(0, 0), ...
    'valueOracleCandidateIndex', NaN, ...
    'valueOracleActionCode', NaN, ...
    'valueOracleGraphSha256', '', ...
    'referenceMeanEospa', NaN, ...
    'referenceWorstSensorEospa', NaN, ...
    'referenceAttemptedBytes', NaN, ...
    'referenceDeliveredBytes', NaN, ...
    'v2OracleCandidateIndex', NaN, ...
    'v2OracleActionCode', NaN, ...
    'v2OracleMeanEospa', NaN, ...
    'v2OracleGainFraction', NaN);
end

function token = formatOptionalCode(actionCode)
if isfinite(actionCode)
    token = sprintf('%02d', actionCode);
else
    token = '-';
end
end

function token = formatActionCodes(actionCodes)
if isempty(actionCodes)
    token = '-';
    return
end
parts = arrayfun(@(code) sprintf('%02d', code), ...
    reshape(actionCodes, 1, []), 'UniformOutput', false);
token = strjoin(parts, '-');
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
