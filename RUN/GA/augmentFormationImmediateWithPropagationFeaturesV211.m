function [reportPath, augmented] = ...
        augmentFormationImmediateWithPropagationFeaturesV211(options)
% AUGMENTFORMATIONIMMEDIATEWITHPROPAGATIONFEATURESV211 Replay truth-free inputs.
%
% Reconstruct the deterministic V208 shortlisted actions from their captured
% screen, attach continuous H=3 propagation descriptors, and preserve the
% already computed immediate targets.  No action is rescored against truth.

if nargin < 1 || isempty(options)
    options = struct();
end
datasetPath = char(getField(options, 'datasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v208', ...
    'formation_label_kla_immediate_merged', ...
    'x36_seed211_t72_h8', ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208_MERGED.mat')));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v211', 'propagation_augmented_immediate', ...
    'x36_seed211_t72_h8')));
horizonSteps = getField(options, 'horizonSteps', 3);
receiverSummaryBytes = getField( ...
    options, 'receiverSummaryBytes', 24);
if exist(datasetPath, 'file') ~= 2 || ...
        ~isscalar(horizonSteps) || ~isfinite(horizonSteps) || ...
        horizonSteps < 1 || horizonSteps ~= round(horizonSteps)
    error('PropagationAugmentedImmediateV211:InvalidRequest', ...
        'A V208 immediate dataset and positive horizon are required.');
end
loaded = load(datasetPath, 'dataset');
source = loaded.dataset;
validateSourceDataset(source);
[screenPath, sourceMetadata] = ...
    resolveScreenAndMetadata(source);
screenLoaded = load(screenPath, 'screen');
screen = screenLoaded.screen;
validateScreen(source, screen);

names = {screen.records.actionName};
baseIdx = find(strncmp(names, ...
    'v99-online-positive-net-', 24));
if numel(baseIdx) ~= 1
    error('PropagationAugmentedImmediateV211:ScreenArm', ...
        'The captured screen must contain one V99 arm.');
end
baseOutcome = screen.outcomes(baseIdx);
inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
runtimeModel = removeRealizedTargetTruthFromDynamicTopologyModel( ...
    inputs.model);
groupIds = reshape(screen.sensorGroupIds, 1, []);
maximumPerCriterion = metadataField( ...
    source, sourceMetadata, 'maximumPerCriterion', 2);
receiverPresenceThreshold = metadataField( ...
    source, sourceMetadata, 'receiverPresenceThreshold', 1e-2);
minimumRiskReductionThreshold = metadataField( ...
    source, sourceMetadata, ...
    'minimumRiskReductionThreshold', -1);

rows = source.rows;
propagationFeatureNames = cell(1, 0);
costFeatureNames = { ...
    'propagation_feature_fraction_of_reference', ...
    'post_propagation_byte_credit_fraction'};
for blockIdx = 1:source.blockCount
    pageIdx = source.blocks(blockIdx).page;
    currentTime = source.blocks(blockIdx).currentTime;
    fprintf('V211 propagation augmentation block %d/%d: t=%d ...\n', ...
        blockIdx, source.blockCount, currentTime);
    fused = baseOutcome.fusedPosteriorSnapshotsByTime{pageIdx};
    local = baseOutcome.localPosteriorSnapshotsByTime{pageIdx};
    physical = logical(inputs.graphData. ...
        physicalAdjacency(:, :, currentTime));
    physical = physical | physical';
    physical(1:numel(groupIds)+1:end) = false;
    cache = buildFormationRepairLightSynopsisCacheV188( ...
        fused, local, runtimeModel, currentTime, struct());
    candidates = enumerateFormationCommonLabelRepairCandidatesV190( ...
        cache, physical, groupIds, struct( ...
            'receiverPresenceThreshold', receiverPresenceThreshold, ...
            'minimumRiskReductionThreshold', ...
                minimumRiskReductionThreshold));
    shortlisted = shortlistFormationLabelActionCandidatesV208( ...
        candidates, struct( ...
            'maximumPerCriterion', maximumPerCriterion));
    blockRowIndices = find([rows.blockId] == blockIdx);
    for localRowIdx = 1:numel(blockRowIndices)
        rowIdx = blockRowIndices(localRowIdx);
        candidate = matchCandidate(shortlisted, rows(rowIdx));
        [proposal, payloadDetails] = ...
            resolveFormationRepairCandidatePayloadV190( ...
                candidate, local, physical, runtimeModel, struct( ...
                    'minimumUtilityLowerBound', -1e6, ...
                    'rollingConnectivityPassed', true));
        if ~payloadDetails.completePayloadResolved || ...
                ~proposal.safetyPassed
            error('PropagationAugmentedImmediateV211:ProposalDrift', ...
                'A previously executable action no longer resolves.');
        end
        [features, featureNames, details] = ...
            buildFormationRepairPropagationFeaturesV211( ...
                proposal, fused, runtimeModel, struct( ...
                    'horizonSteps', horizonSteps, ...
                    'receiverSummaryBytes', receiverSummaryBytes));
        if isempty(propagationFeatureNames)
            propagationFeatureNames = featureNames;
        elseif ~isequal(propagationFeatureNames, featureNames)
            error('PropagationAugmentedImmediateV211:FeatureDrift', ...
                'The propagation feature contract changed between rows.');
        end
        featureBytes = details.attemptedFeatureBytes;
        postFeatureCredit = ...
            rows(rowIdx).chargedNetByteSaving - featureBytes;
        costFeatures = [ ...
            featureBytes / max(rows(rowIdx).referencePageBytes, 1), ...
            postFeatureCredit / ...
                max(rows(rowIdx).referencePageBytes, 1)];
        rows(rowIdx).propagationFeatures = features;
        rows(rowIdx).propagationFeatureAttemptedBytes = featureBytes;
        rows(rowIdx).postPropagationNetByteSaving = postFeatureCredit;
        rows(rowIdx).postPropagationNetByteSavingPercent = ...
            100 * postFeatureCredit / ...
                max(rows(rowIdx).referencePageBytes, 1);
        rows(rowIdx).postPropagationNetByteFeasible = ...
            postFeatureCredit >= 0;
        rows(rowIdx).features = [ ...
            rows(rowIdx).features, features, costFeatures];
    end
end

augmented = source;
augmented.contractVersion = ...
    'formation-label-kla-immediate-propagation-v211-v1';
augmented.sourceContractVersion = source.contractVersion;
augmented.generatedAt = datestr(now, 31);
augmented.sourceDatasetPath = datasetPath;
augmented.screenPath = screenPath;
augmented.propagationHorizonSteps = horizonSteps;
augmented.receiverSummaryBytes = receiverSummaryBytes;
augmented.propagationFeatureNames = propagationFeatureNames;
augmented.propagationCostFeatureNames = costFeatureNames;
augmented.actionFeatureNames = [ ...
    source.actionFeatureNames, propagationFeatureNames, ...
    costFeatureNames];
augmented.rows = rows;
augmented.rowCount = numel(rows);
augmented.postPropagationNetByteFeasibleRowCount = ...
    nnz([rows.postPropagationNetByteFeasible]);
augmented.featuresUseTruth = false;
augmented.featuresUseFutureInformation = false;
augmented.propagationUsesKnownMotionModel = true;
augmented.propagationUsesFutureMeasurements = false;
augmented.propagationHardGateApplied = false;
augmented.propagationFeatureCommunicationChargedPerRow = true;
augmented.recursiveTargetsIncluded = false;
augmented.validationClaimAllowed = false;
augmented.evidenceBoundary = [ ...
    'V211 deterministically reconstructs the V208 shortlisted actions ', ...
    'from captured policy inputs and appends continuous H=3 open-loop ', ...
    'moment-propagation descriptors.  It does not reopen or recompute ', ...
    'truth targets.  The descriptors use no truth or future measurement ', ...
    'and are not a hard safety gate.  This offline dataset evaluates ', ...
    'representation and proposal design only; a deployable controller ', ...
    'must compute them only for a small structural shortlist and charge ', ...
    'their fixed synopsis/receiver-summary bytes.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'FORMATION_LABEL_KLA_PROPAGATION_AUGMENTED_V211.mat');
reportPath = fullfile(outputRoot, ...
    'FORMATION_LABEL_KLA_PROPAGATION_AUGMENTED_V211.md');
augmented.matPath = matPath;
augmented.reportPath = reportPath;
dataset = augmented; %#ok<NASGU>
save('-mat7-binary', matPath, 'dataset');
writeReport(reportPath, augmented);
fprintf('V211 propagation-augmented immediate dataset: %s\n', ...
    reportPath);
end

function validateSourceDataset(dataset)
allowed = { ...
    'formation-label-kla-immediate-dataset-v208-v1', ...
    'formation-label-kla-immediate-dataset-v208-merged-v1'};
required = {'contractVersion', 'presetName', 'seed', ...
    'actionFeatureNames', 'targetNames', 'blocks', 'rows', ...
    'blockCount', 'rowCount', 'featuresUseTruth', ...
    'featuresUseFutureInformation', 'recursiveTargetsIncluded', ...
    'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~ismember(dataset.contractVersion, allowed) || ...
        numel(dataset.blocks) ~= dataset.blockCount || ...
        numel(dataset.rows) ~= dataset.rowCount || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed
    error('PropagationAugmentedImmediateV211:SourceContract', ...
        'The V208 immediate source dataset is invalid.');
end
end

function [screenPath, metadata] = resolveScreenAndMetadata(dataset)
metadata = dataset;
if isfield(dataset, 'screenPath') && ...
        exist(dataset.screenPath, 'file') == 2
    screenPath = char(dataset.screenPath);
    return;
end
if ~isfield(dataset, 'sourceRecords') || ...
        isempty(dataset.sourceRecords) || ...
        ~isfield(dataset.sourceRecords, 'path')
    error('PropagationAugmentedImmediateV211:MissingScreen', ...
        'The immediate dataset does not identify its captured screen.');
end
shardPath = char(dataset.sourceRecords(1).path);
if exist(shardPath, 'file') ~= 2
    error('PropagationAugmentedImmediateV211:MissingShard', ...
        'The first source shard is unavailable.');
end
loaded = load(shardPath, 'dataset');
metadata = loaded.dataset;
if ~isfield(metadata, 'screenPath') || ...
        exist(metadata.screenPath, 'file') ~= 2
    error('PropagationAugmentedImmediateV211:MissingScreen', ...
        'The source shard does not identify a captured screen.');
end
screenPath = char(metadata.screenPath);
end

function validateScreen(dataset, screen)
if ~isstruct(screen) || ~isscalar(screen) || ...
        ~strcmp(dataset.presetName, screen.presetName) || ...
        dataset.seed ~= screen.seed || ...
        any([dataset.blocks.page] < 1) || ...
        any([dataset.blocks.page] > numel(screen.returnTimes)) || ...
        any(screen.returnTimes([dataset.blocks.page]) ~= ...
            [dataset.blocks.currentTime])
    error('PropagationAugmentedImmediateV211:ScreenContract', ...
        'The captured screen does not match the immediate dataset.');
end
end

function value = metadataField(dataset, metadata, name, fallback)
if isfield(dataset, name)
    value = dataset.(name);
elseif isfield(metadata, name)
    value = metadata.(name);
else
    value = fallback;
end
end

function candidate = matchCandidate(candidates, row)
mask = [candidates.formationId] == row.receiverFormationId & ...
    [candidates.sourceId] == row.sourceId & ...
    arrayfun(@(current) isequal(current.label, row.label), ...
        candidates);
indices = find(mask);
if numel(indices) ~= 1
    error('PropagationAugmentedImmediateV211:CandidateKey', ...
        'Each immediate row must match exactly one shortlisted action.');
end
candidate = candidates(indices);
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('PropagationAugmentedImmediateV211:ReportOpen', ...
        'Could not write the V211 augmentation report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V211 propagation-augmented immediate dataset\n\n');
fprintf(fid, '- Preset / seed: `%s / %d`\n', ...
    dataset.presetName, dataset.seed);
fprintf(fid, '- Pages / actions: `%d / %d`\n', ...
    dataset.blockCount, dataset.rowCount);
fprintf(fid, '- Propagation horizon: `%d`\n', ...
    dataset.propagationHorizonSteps);
fprintf(fid, '- Added propagation features: `%d + 2 cost fields`\n', ...
    numel(dataset.propagationFeatureNames));
fprintf(fid, '- Post-feature byte-feasible rows: `%d / %d`\n\n', ...
    dataset.postPropagationNetByteFeasibleRowCount, dataset.rowCount);
fprintf(fid, '| Time | Actions | Feature bytes min / median / max |\n');
fprintf(fid, '|--:|--:|:--|\n');
for block = reshape(dataset.blocks, 1, [])
    blockRows = dataset.rows([dataset.rows.blockId] == block.blockId);
    bytes = [blockRows.propagationFeatureAttemptedBytes];
    fprintf(fid, '| %d | %d | %.0f / %.0f / %.0f B |\n', ...
        block.currentTime, numel(blockRows), ...
        min(bytes), median(bytes), max(bytes));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
