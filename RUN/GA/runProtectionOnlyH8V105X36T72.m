function [reportPath, result] = runProtectionOnlyH8V105X36T72(options)
% RUNPROTECTIONONLYH8V105X36T72 Matched H=8 protection-only attribution.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getField(options, 'protocolOverride', ...
    getProtectionOnlyH8V105Protocol());
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('ProtectionOnlyV105:DirtySource', ...
        'The V105 attribution requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
outputRoot = getField(options, 'outputRoot', ...
    fullfile(protocol.headroomOutputRoot, 'x36_t72_h8'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
scheduleBankOptions = struct( ...
    'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
    'bankVariant', getField(protocol, ...
        'bankVariant', 'protection-only-h8-v105'), ...
    'horizonSteps', protocol.horizonSteps);
if isfield(protocol, 'maximumLabelEdits')
    scheduleBankOptions.maximumLabelEdits = protocol.maximumLabelEdits;
end
reuseFrozenReferenceOutcome = logical(getField( ...
    protocol, 'reuseFrozenReferenceOutcome', true));
referenceOutcomeScreenPath = '';
if reuseFrozenReferenceOutcome
    referenceOutcomeScreenPath = protocol.referenceOutcomeScreenPath;
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', getField(protocol, ...
        'executionProfile', 'v105-protection-only-h8'), ...
    'trackingAlignedX36ScheduleBankOptions', scheduleBankOptions, ...
    'actionIndices', [1, 2], ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', ...
        referenceOutcomeScreenPath, ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
if ismember(getField(protocol, 'bankVariant', ''), { ...
        'shadow-state-rollback-v126', ...
        'sparse-reference-label-rollback-v156', ...
        'positive-value-reference-label-v157'})
    screenOptions.shadowStateRollbackPlan = ...
        loadExternalShadowStatePlan(protocol, entry);
end
if ismember(getField(protocol, 'bankVariant', ''), { ...
        'sparse-reference-label-rollback-v156', ...
        'positive-value-reference-label-v157'})
    screenOptions.captureFusedPosteriorSnapshotsEnabled = true;
end
[candidateScreenPath, candidateScreenExists] = deal( ...
    fullfile(screenOptions.outputDirectory, ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat']), false);
candidateScreenExists = exist(candidateScreenPath, 'file') == 2;
if logical(getField(options, 'reuseCompletedCandidateScreen', true)) && ...
        candidateScreenExists
    loadedScreen = load(candidateScreenPath, 'screen');
    screen = loadedScreen.screen;
    screenReportPath = screen.reportPath;
else
    [screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
        entry.presetName, entry.seed, currentTime, screenOptions);
end
if reuseFrozenReferenceOutcome && ~screen.referenceOutcomeReused
    error('ProtectionOnlyV105:ReferenceNotReused', ...
        'The frozen H=8 static outcome was unexpectedly rerun.');
end
if ~reuseFrozenReferenceOutcome && screen.referenceOutcomeReused
    error('ProtectionOnlyV105:ReferenceUnexpectedlyReused', ...
        'This protocol requires a same-run reference outcome.');
end

referenceIdx = screen.referenceSubsetIndex;
candidateActionName = getField(protocol, ...
    'candidateActionName', 'v105-protection-only-h8');
candidateIdx = find(strcmp({screen.records.actionName}, ...
    candidateActionName), 1);
if isempty(candidateIdx)
    error('ProtectionOnlyV105:MissingPairedArm', ...
        'The V105 bank did not produce the protection-only arm.');
end
reference = screen.records(referenceIdx);
candidate = screen.records(candidateIdx);
referenceOutcome = screen.outcomes(referenceIdx);
candidateOutcome = screen.outcomes(candidateIdx);
if ismember(getField(protocol, 'bankVariant', ''), { ...
        'shadow-state-rollback-v126', ...
        'local-posterior-rollback-v127', ...
        'independent-local-anchor-v128', ...
        'intermittent-light-network-anchor-v131', ...
        'risk-formation-light-network-anchor-v132', ...
        'sparse-reference-label-rollback-v156', ...
        'positive-value-reference-label-v157'})
    groupIdsForRollback = reshape(screen.sensorGroupIds, 1, []);
    expectedRollbackCountByTime = cellfun(@(formations) ...
        nnz(ismember(groupIdsForRollback, formations)), ...
        protocol.rollbackFormationIdsByTime);
    if ~isequal(candidateOutcome.shadowStateRollbackAppliedByTime, ...
            expectedRollbackCountByTime)
        error('StateRollback:ApplicationCountDrift', ...
            'The rollback was not applied to the frozen node-time cells.');
    end
    if ismember(getField(protocol, 'bankVariant', ''), { ...
            'independent-local-anchor-v128', ...
            'intermittent-light-network-anchor-v131', ...
            'risk-formation-light-network-anchor-v132'}) && ...
            ~isequal(candidateOutcome. ...
                shadowStateRollbackAnchorMaintainedByTime, ...
                numel(screen.sensorGroupIds) * ...
                    ones(1, protocol.horizonSteps))
        error('AuxiliaryAnchor:MaintenanceCountDrift', ...
            'The registered auxiliary anchor was not maintained at every node.');
    end
end
if strcmp(getField(protocol, 'bankVariant', ''), ...
        'observable-one-hop-risk-label-v162')
    groupIdsForTransfer = reshape(screen.sensorGroupIds, 1, []);
    expectedTriggerCountByTime = cellfun(@(formations) ...
        nnz(ismember(groupIdsForTransfer, formations)), ...
        protocol.rollbackFormationIdsByTime);
    if ~isequal(candidateOutcome. ...
            observableOneHopRiskLabelTriggeredByTime, ...
            expectedTriggerCountByTime)
        error('ObservableOneHopRiskLabelV162:TriggerCountDrift', ...
            'The recursive transfer did not visit the frozen cells.');
    end
end
referenceByTime = mean(referenceOutcome.eospaBySensorTime, 1);
candidateByTime = mean(candidateOutcome.eospaBySensorTime, 1);
gainByTime = relativeGainPercent(referenceByTime, candidateByTime);
[formationGain, referenceByFormation, candidateByFormation] = ...
    formationGains(referenceOutcome.eospaBySensorTime, ...
        candidateOutcome.eospaBySensorTime, screen.sensorGroupIds);

targetMembers = find( ...
    screen.sensorGroupIds == protocol.targetFormationId);
residualSources = reshape( ...
    screen.bank.referencePolicyDetails.residualSourcesByReceiver, 1, []);
gatewayCandidates = targetMembers( ...
    screen.sensorGroupIds(residualSources(targetMembers)) ~= ...
        protocol.targetFormationId);
if numel(gatewayCandidates) ~= 1
    error('ProtectionOnlyV105:GatewayDrift', ...
        'The target formation no longer has one cross-input gateway.');
end
targetGateway = gatewayCandidates(1);
targetPeers = setdiff(targetMembers, targetGateway, 'stable');
targetPeerTerminalGain = relativeGainPercent( ...
    mean(referenceOutcome.eospaBySensorTime(targetPeers, end)), ...
    mean(candidateOutcome.eospaBySensorTime(targetPeers, end)));

result = struct();
result.contractVersion = getField(protocol, 'resultContractVersion', ...
    'protection-only-h8-v105-x36-t72-result-v1');
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.outcomeGenerationGitCommit = getField( ...
    screen, 'generationGitCommit', gitState.commit);
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.baselineName = protocol.baselineName;
result.receiverMode = protocol.receiverMode;
result.referenceOutcomeReused = screen.referenceOutcomeReused;
result.referenceOutcomeScreenPath = screen.referenceOutcomeScreenPath;
result.protectionFormationIdsByTime = ...
    protocol.protectionFormationIdsByTime;
result.shadowStateRollbackAppliedByTime = ...
    candidateOutcome.shadowStateRollbackAppliedByTime;
result.shadowStateRollbackAnchorMaintainedByTime = ...
    candidateOutcome.shadowStateRollbackAnchorMaintainedByTime;
result.lightNetworkAnchorAttemptedMessagesByTime = ...
    getField(candidateOutcome, ...
        'lightNetworkAnchorAttemptedMessagesByTime', []);
result.lightNetworkAnchorDeliveredMessagesByTime = ...
    getField(candidateOutcome, ...
        'lightNetworkAnchorDeliveredMessagesByTime', []);
result.lightNetworkAnchorAttemptedBytesByTime = ...
    getField(candidateOutcome, 'lightNetworkAnchorAttemptedBytesByTime', []);
result.lightNetworkAnchorDeliveredBytesByTime = ...
    getField(candidateOutcome, 'lightNetworkAnchorDeliveredBytesByTime', []);
result.referenceMeanEospa = reference.meanEospa;
result.candidateMeanEospa = candidate.meanEospa;
result.meanGainPercent = candidate.meanGainPercent;
result.referenceMeanRmse = referenceOutcome.meanRmse;
result.candidateMeanRmse = candidateOutcome.meanRmse;
result.meanRmseGainPercent = relativeGainPercent( ...
    result.referenceMeanRmse, result.candidateMeanRmse);
result.referenceWorstSensorRmse = referenceOutcome.worstSensorRmse;
result.candidateWorstSensorRmse = candidateOutcome.worstSensorRmse;
result.worstRmseGainPercent = relativeGainPercent( ...
    result.referenceWorstSensorRmse, result.candidateWorstSensorRmse);
result.referenceFormationMeanRmse = ...
    referenceOutcome.formationMeanRmse;
result.candidateFormationMeanRmse = ...
    candidateOutcome.formationMeanRmse;
result.formationRmseGainPercent = relativeGainPercent( ...
    result.referenceFormationMeanRmse, ...
    result.candidateFormationMeanRmse);
result.minimumFormationRmseGainPercent = ...
    min(result.formationRmseGainPercent);
result.referenceMeanEospaByTime = referenceByTime;
result.candidateMeanEospaByTime = candidateByTime;
result.gainPercentByTime = gainByTime;
result.minimumPostMaturityGainPercent = min( ...
    gainByTime(protocol.firstHandoffTimeIndex:end));
result.referenceMeanEospaByFormation = referenceByFormation;
result.candidateMeanEospaByFormation = candidateByFormation;
result.formationGainPercent = formationGain;
result.targetFormationId = protocol.targetFormationId;
result.targetPeerIndices = targetPeers;
result.targetPeerTerminalGainPercent = targetPeerTerminalGain;
result.worstSensorGainPercent = candidate.worstGainPercent;
result.minimumFormationGainPercent = candidate.minimumFormationGainPercent;
[formationTimeGain, minimumFormationTimeGain] = formationTimeGains( ...
    referenceOutcome.eospaBySensorTime, ...
    candidateOutcome.eospaBySensorTime, screen.sensorGroupIds);
result.formationTimeGainPercent = formationTimeGain;
result.minimumFormationTimeGainPercent = minimumFormationTimeGain;
result.windowConsensusGainPercent = candidate.consensusGainPercent;
result.terminalConsensusGainPercent = ...
    candidate.terminalConsensusGainPercent;
result.attemptedByteSavingPercent = candidate.attemptedByteSavingPercent;
result.auxiliaryMaintenanceCostAccounted = logical(getField(protocol, ...
    'auxiliaryMaintenanceCostAccounted', true));
result.additionalPosteriorPayloadMessages = getField(protocol, ...
    'additionalPosteriorPayloadMessages', NaN);
result.additionalPosteriorPayloadBytes = getField(protocol, ...
    'additionalPosteriorPayloadBytes', NaN);
result.referenceAttemptedBytes = referenceOutcome.attemptedBytes;
result.candidateMainPathAttemptedBytes = candidateOutcome.attemptedBytes;
result.observableOneHopRiskLabelTriggeredByTime = getField( ...
    candidateOutcome, 'observableOneHopRiskLabelTriggeredByTime', []);
result.observableOneHopRiskLabelAppliedCellsByTime = getField( ...
    candidateOutcome, 'observableOneHopRiskLabelAppliedCellsByTime', []);
result.observableOneHopRiskLabelSelectedLabelsByTime = getField( ...
    candidateOutcome, 'observableOneHopRiskLabelSelectedLabelsByTime', []);
result.observableOneHopRiskLabelAppliedLabelsByTime = getField( ...
    candidateOutcome, 'observableOneHopRiskLabelAppliedLabelsByTime', []);
result.observableOneHopRiskLabelAttemptedSynopsisBytesByTime = getField( ...
    candidateOutcome, ...
    'observableOneHopRiskLabelAttemptedSynopsisBytesByTime', []);
result.observableOneHopRiskLabelAttemptedRequestBytesByTime = getField( ...
    candidateOutcome, ...
    'observableOneHopRiskLabelAttemptedRequestBytesByTime', []);
result.observableOneHopRiskLabelAttemptedResponseBytesByTime = getField( ...
    candidateOutcome, ...
    'observableOneHopRiskLabelAttemptedResponseBytesByTime', []);
result.observableOneHopRiskLabelDeliveredSynopsisBytesByTime = getField( ...
    candidateOutcome, ...
    'observableOneHopRiskLabelDeliveredSynopsisBytesByTime', []);
result.observableOneHopRiskLabelDeliveredRequestBytesByTime = getField( ...
    candidateOutcome, ...
    'observableOneHopRiskLabelDeliveredRequestBytesByTime', []);
result.observableOneHopRiskLabelDeliveredResponseBytesByTime = getField( ...
    candidateOutcome, ...
    'observableOneHopRiskLabelDeliveredResponseBytesByTime', []);
result.adjustedAttemptedByteSavingPercent = ...
    result.attemptedByteSavingPercent;
if strcmp(getField(protocol, 'bankVariant', ''), ...
        'sparse-reference-label-rollback-v156')
    [result.additionalPosteriorPayloadMessages, ...
     result.additionalPosteriorPayloadBytes, ...
     result.sparseReferenceLabelCountsByTime, ...
     result.sparseReferenceLabelBytesByTime] = ...
        estimateSparseReferenceLabelTransport( ...
            candidateOutcome.fusedPosteriorSnapshotsByTime, ...
            screenOptions.shadowStateRollbackPlan, protocol, ...
            screen.sensorGroupIds);
    result.adjustedAttemptedByteSavingPercent = 100 * ( ...
        result.referenceAttemptedBytes - ...
        (result.candidateMainPathAttemptedBytes + ...
         result.additionalPosteriorPayloadBytes)) / ...
        max(abs(result.referenceAttemptedBytes), eps);
end
if ~isfinite(result.additionalPosteriorPayloadBytes) && ...
        ~isempty(result.lightNetworkAnchorAttemptedMessagesByTime) && ...
        ~strcmp(getField(protocol, 'bankVariant', ''), ...
            'sparse-reference-label-rollback-v156')
    result.additionalPosteriorPayloadMessages = sum( ...
        result.lightNetworkAnchorAttemptedMessagesByTime);
    result.additionalPosteriorPayloadBytes = sum( ...
        result.lightNetworkAnchorAttemptedBytesByTime);
end
if isfinite(result.additionalPosteriorPayloadBytes)
    result.adjustedAttemptedByteSavingPercent = 100 * ( ...
        result.referenceAttemptedBytes - ...
        (result.candidateMainPathAttemptedBytes + ...
         result.additionalPosteriorPayloadBytes)) / ...
        max(abs(result.referenceAttemptedBytes), eps);
end
result.lightFusionWeightFactor = getField(protocol, ...
    'lightFusionWeightFactor', NaN);
result.lightCorrectionFormationIdsByTime = getField(protocol, ...
    'lightCorrectionFormationIdsByTime', cell(1, 0));
result.fullCorrectionFormationIdsByTime = getField(protocol, ...
    'fullCorrectionFormationIdsByTime', cell(1, 0));
result.auxiliaryRuntimeIncluded = logical(getField(protocol, ...
    'auxiliaryRuntimeIncluded', true));
result.auxiliaryMemoryQuantified = logical(getField(protocol, ...
    'auxiliaryMemoryQuantified', true));
result.selectedB3Passed = candidate.selectedB3Passed;
result.referenceElapsedSeconds = referenceOutcome.elapsedSeconds;
result.candidateElapsedSeconds = candidateOutcome.elapsedSeconds;
result.gatePassed = ...
    result.meanGainPercent >= protocol.minimumMeanGainPercent - 1e-12 && ...
    (~isfield(protocol, 'minimumMeanRmseGainPercent') || ...
     result.meanRmseGainPercent >= ...
        protocol.minimumMeanRmseGainPercent - 1e-12) && ...
    (~isfield(protocol, 'minimumWorstRmseGainPercent') || ...
     result.worstRmseGainPercent >= ...
        protocol.minimumWorstRmseGainPercent - 1e-12) && ...
    (~isfield(protocol, 'minimumFormationRmseGainPercent') || ...
     result.minimumFormationRmseGainPercent >= ...
        protocol.minimumFormationRmseGainPercent - 1e-12) && ...
    result.minimumPostMaturityGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    result.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    result.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    (~logical(getField(protocol, ...
        'requireNonnegativeFormationTime', false)) || ...
     result.minimumFormationTimeGainPercent >= ...
        getField(protocol, 'minimumFormationTimeGainPercent', 0) - 1e-12) && ...
    result.targetPeerTerminalGainPercent >= ...
        protocol.minimumTargetPeerTerminalGainPercent - 1e-12 && ...
    result.windowConsensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    result.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    result.adjustedAttemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    result.selectedB3Passed;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.screenReportPath = screenReportPath;
result.evidenceBoundary = protocol.evidenceBoundary;

resultFileStem = getField(protocol, 'resultFileStem', ...
    'PROTECTION_ONLY_H8_V105_X36_T72_RESULT');
matPath = fullfile(outputRoot, [resultFileStem, '.mat']);
reportPath = fullfile(outputRoot, [resultFileStem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('%s result: %s\n', getField(protocol, ...
    'runLabel', 'V105 X36-t72 H=8'), reportPath);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('ProtectionOnlyV105:WriteFailed', ...
        'Could not create the V105 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
isObservableRiskLabelV162 = strcmp(getField( ...
    result.protocol, 'bankVariant', ''), ...
    'observable-one-hop-risk-label-v162');
fprintf(fid, '# %s\n\n', getField(result.protocol, ...
    'reportTitle', 'V105 protection-only: X36 t72 H=8'));
fprintf(fid, '- Matched baseline: `%s`\n', result.baselineName);
fprintf(fid, '- Frozen H=8 reference reused: `%d`\n\n', ...
    result.referenceOutcomeReused);
if ~strcmp(result.outcomeGenerationGitCommit, ...
        result.generationGitCommit)
    fprintf(fid, ['- Outcome commit / accounting commit: `%s` / ', ...
        '`%s`\n\n'], result.outcomeGenerationGitCommit, ...
        result.generationGitCommit);
end
fprintf(fid, ['| Arm | Mean E-OSPA | E-OSPA gain | Mean RMSE | ', ...
    'RMSE gain | Bytes saving |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|\n');
fprintf(fid, '| Static full payload | %.6f | -- | %.6f | -- | -- |\n', ...
    result.referenceMeanEospa, result.referenceMeanRmse);
fprintf(fid, '| %s | %.6f | %+.3f%% | %.6f | %+.3f%% | %+.3f%% |\n\n', ...
    getField(result.protocol, 'armDisplayName', 'V105 protection only'), ...
    result.candidateMeanEospa, result.meanGainPercent, ...
    result.candidateMeanRmse, result.meanRmseGainPercent, ...
    result.attemptedByteSavingPercent);
if abs(result.adjustedAttemptedByteSavingPercent - ...
        result.attemptedByteSavingPercent) > 1e-12
    fprintf(fid, ['- Adjusted byte saving after reference-label payload: ', ...
        '`%+.3f%%`\n\n'], result.adjustedAttemptedByteSavingPercent);
end
fprintf(fid, '| t | Static | Candidate | Gain | Protected formations |\n');
fprintf(fid, '|--:|--:|--:|--:|:--|\n');
for idx = 1:numel(result.returnTimes)
    fprintf(fid, '| %d | %.6f | %.6f | %+.3f%% | %s |\n', ...
        result.returnTimes(idx), result.referenceMeanEospaByTime(idx), ...
        result.candidateMeanEospaByTime(idx), ...
        result.gainPercentByTime(idx), ...
        mat2str(result.protectionFormationIdsByTime{idx}));
end
fprintf(fid, '\n- Formation gains: `%s%%`\n', ...
    mat2str(result.formationGainPercent, 4));
fprintf(fid, '- Minimum after maturity: `%+.3f%%`\n', ...
    result.minimumPostMaturityGainPercent);
fprintf(fid, '- F%d non-gateway terminal gain: `%+.3f%%`\n', ...
    result.targetFormationId, result.targetPeerTerminalGainPercent);
fprintf(fid, '- Worst sensor / minimum formation: `%+.3f%% / %+.3f%%`\n', ...
    result.worstSensorGainPercent, result.minimumFormationGainPercent);
fprintf(fid, ['- RMSE mean / worst sensor / minimum formation: ', ...
    '`%+.3f%% / %+.3f%% / %+.3f%%`\n'], ...
    result.meanRmseGainPercent, result.worstRmseGainPercent, ...
    result.minimumFormationRmseGainPercent);
fprintf(fid, '- Minimum formation-time gain: `%+.3f%%`\n', ...
    result.minimumFormationTimeGainPercent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    result.windowConsensusGainPercent, ...
    result.terminalConsensusGainPercent);
fprintf(fid, '- Static / candidate runtime: `%.2f / %.2f s`\n', ...
    result.referenceElapsedSeconds, result.candidateElapsedSeconds);
fprintf(fid, '- Auxiliary-state maintenance cost included: `%d`\n', ...
    result.auxiliaryMaintenanceCostAccounted);
if isfinite(result.lightFusionWeightFactor)
    fprintf(fid, '- Protected-input light weight factor: `%.3f`\n', ...
        result.lightFusionWeightFactor);
end
if ~isempty(result.lightCorrectionFormationIdsByTime)
    fprintf(fid, '- Light-correction formations by page: `%s`\n', ...
        formatCellSchedule(result.lightCorrectionFormationIdsByTime));
    fprintf(fid, '- Full-correction formations by page: `%s`\n', ...
        formatCellSchedule(result.fullCorrectionFormationIdsByTime));
end
if isfinite(result.additionalPosteriorPayloadMessages) && ...
        ~isObservableRiskLabelV162
    fprintf(fid, ['- Additional posterior payload messages / bytes: ', ...
        '`%.0f / %.0f`\n'], result.additionalPosteriorPayloadMessages, ...
        result.additionalPosteriorPayloadBytes);
end
if isfield(result, 'sparseReferenceLabelCountsByTime')
    fprintf(fid, '- Reference-label counts by time: `%s`\n', ...
        mat2str(result.sparseReferenceLabelCountsByTime));
    fprintf(fid, '- Reference-label bytes by time: `%s`\n', ...
        mat2str(result.sparseReferenceLabelBytesByTime));
end
if ~isempty(result.lightNetworkAnchorAttemptedBytesByTime) && ...
        (any(result.lightNetworkAnchorAttemptedBytesByTime > 0) || ...
         any(result.lightNetworkAnchorDeliveredBytesByTime > 0))
    fprintf(fid, '- Anchor attempted bytes by time: `%s`\n', ...
        mat2str(result.lightNetworkAnchorAttemptedBytesByTime));
    fprintf(fid, '- Anchor delivered bytes by time: `%s`\n', ...
        mat2str(result.lightNetworkAnchorDeliveredBytesByTime));
end
if isObservableRiskLabelV162
    fprintf(fid, '- V162 trigger cells by time: `%s`\n', ...
        mat2str(result.observableOneHopRiskLabelTriggeredByTime));
    fprintf(fid, '- V162 applied cells by time: `%s`\n', ...
        mat2str(result.observableOneHopRiskLabelAppliedCellsByTime));
    fprintf(fid, '- V162 selected labels by time: `%s`\n', ...
        mat2str(result.observableOneHopRiskLabelSelectedLabelsByTime));
    fprintf(fid, '- V162 applied labels by time: `%s`\n', ...
        mat2str(result.observableOneHopRiskLabelAppliedLabelsByTime));
    fprintf(fid, ['- V162 attempted synopsis / request / response bytes ', ...
        'by time: `%s / %s / %s`\n'], ...
        mat2str(result. ...
            observableOneHopRiskLabelAttemptedSynopsisBytesByTime), ...
        mat2str(result. ...
            observableOneHopRiskLabelAttemptedRequestBytesByTime), ...
        mat2str(result. ...
            observableOneHopRiskLabelAttemptedResponseBytesByTime));
    fprintf(fid, ['- V162 delivered synopsis / request / response bytes ', ...
        'by time: `%s / %s / %s`\n'], ...
        mat2str(result. ...
            observableOneHopRiskLabelDeliveredSynopsisBytesByTime), ...
        mat2str(result. ...
            observableOneHopRiskLabelDeliveredRequestBytesByTime), ...
        mat2str(result. ...
            observableOneHopRiskLabelDeliveredResponseBytesByTime));
    fprintf(fid, ['- V162 control and response bytes are already included ', ...
        'in candidate attempted bytes.\n']);
end
fprintf(fid, '- Auxiliary runtime included / memory quantified: `%d / %d`\n', ...
    result.auxiliaryRuntimeIncluded, result.auxiliaryMemoryQuantified);
if ~isempty(result.shadowStateRollbackAnchorMaintainedByTime) && ...
        any(result.shadowStateRollbackAnchorMaintainedByTime > 0)
    fprintf(fid, '- Anchor-maintained nodes by time: `%s`\n', ...
        mat2str(result.shadowStateRollbackAnchorMaintainedByTime));
end
fprintf(fid, '- Registered gate passed: `%d`\n\n', result.gatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = formatCellSchedule(schedule)
tokens = cellfun(@(ids) mat2str(reshape(ids, 1, [])), schedule, ...
    'UniformOutput', false);
value = strjoin(tokens, ' | ');
end

function [gain, minimumGain] = formationTimeGains( ...
        referenceBySensorTime, candidateBySensorTime, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
gain = zeros(numel(groups), size(referenceBySensorTime, 2));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    gain(idx, :) = relativeGainPercent( ...
        mean(referenceBySensorTime(mask, :), 1), ...
        mean(candidateBySensorTime(mask, :), 1));
end
minimumGain = min(gain(:));
end

function plan = loadExternalShadowStatePlan(protocol, entry)
if exist(protocol.shadowCaptureScreenPath, 'file') ~= 2
    error('ShadowStateRollbackV126:MissingShadowCapture', ...
        'Run captureShadowStateRollbackV126X36T72 first.');
end

loaded = load(protocol.shadowCaptureScreenPath, 'screen');
screen = loaded.screen;
if ~screen.captureFusedPosteriorSnapshotsEnabled || ...
        ~strcmp(screen.presetName, entry.presetName) || ...
        screen.seed ~= entry.seed || screen.currentTime ~= 72
    error('ShadowStateRollbackV126:ShadowCaptureDrift', ...
        'The paired static fused-state capture is invalid.');
end
snapshots = screen.outcomes(screen.referenceSubsetIndex). ...
    fusedPosteriorSnapshotsByTime;
groupIds = reshape(screen.sensorGroupIds, 1, []);
sensorIdsByTime = cellfun(@(formations) ...
    find(ismember(groupIds, formations)), ...
    protocol.rollbackFormationIdsByTime, 'UniformOutput', false);
plan = struct( ...
    'times', protocol.rollbackTimes, ...
    'sensorIdsByTime', {sensorIdsByTime}, ...
    'fusedPosteriorByTime', {snapshots});
end

function [messageCount, byteCount, labelCountsByTime, bytesByTime] = ...
        estimateSparseReferenceLabelTransport( ...
            workingPages, plan, protocol, groupIds)
labelCountsByTime = zeros(1, protocol.horizonSteps);
bytesByTime = zeros(1, protocol.horizonSteps);
for pageIdx = 1:protocol.horizonSteps
    sensorIds = plan.sensorIdsByTime{pageIdx};
    for sensorIdx = sensorIds
        [~, details] = mergeSparseReferenceLmbLabels( ...
            workingPages{pageIdx}{sensorIdx}, ...
            plan.fusedPosteriorByTime{pageIdx}{sensorIdx}, ...
            protocol.maximumLabelEdits, 1e-2);
        labelCountsByTime(pageIdx) = ...
            labelCountsByTime(pageIdx) + details.selectedLabelCount;
        bytesByTime(pageIdx) = bytesByTime(pageIdx) + ...
            details.estimatedPayloadBytes;
    end
end
messageCount = sum(cellfun(@numel, plan.sensorIdsByTime));
byteCount = sum(bytesByTime);
if numel(groupIds) ~= 36
    error('SparseReferenceLabelV156:GroupBoundaryDrift', ...
        'The first V156 byte estimate is frozen to X36.');
end
end

function [gain, referenceMeans, candidateMeans] = formationGains( ...
        referenceBySensorTime, candidateBySensorTime, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
referenceMeans = zeros(1, numel(groups));
candidateMeans = zeros(1, numel(groups));
for idx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(idx);
    referenceValues = referenceBySensorTime(mask, :);
    candidateValues = candidateBySensorTime(mask, :);
    referenceMeans(idx) = mean(referenceValues(:));
    candidateMeans(idx) = mean(candidateValues(:));
end
gain = relativeGainPercent(referenceMeans, candidateMeans);
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
