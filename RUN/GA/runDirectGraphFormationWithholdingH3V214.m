function [reportPath, result] = ...
        runDirectGraphFormationWithholdingH3V214(options)
% RUNDIRECTGRAPHFORMATIONWITHHOLDINGH3V214 Exact paired H=3 screen.
%
% The reference sends complete posteriors.  Each candidate withholds the
% cross-formation posterior input of exactly one receiver formation for the
% current page and then returns to the reference for two pages.  This is the
% first causal target for a cheap graph controller; no V99 counterfactual is
% evaluated inside the runtime arm.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getDirectGraphPayloadRepairControllerV214Protocol();
presetName = char(getField(options, ...
    'presetName', 'm24-formation-fov'));
seed = getField(options, 'seed', 1301);
splitName = char(getField(options, 'splitName', 'training'));
windowIndex = getField(options, 'windowIndex', 1);
formationIds = reshape(getField( ...
    options, 'formationIds', zeros(1, 0)), 1, []);
capturePosteriorSnapshotsEnabled = logical(getField( ...
    options, 'capturePosteriorSnapshotsEnabled', false));
captureFusedPosteriorSnapshotsEnabled = logical(getField( ...
    options, 'captureFusedPosteriorSnapshotsEnabled', false));
trajectoryRoot = char(getField(options, 'trajectoryRoot', fullfile( ...
    protocol.outputRoot, 'trajectory_collection', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
trajectoryPath = fullfile(trajectoryRoot, ...
    'DIRECT_GRAPH_TRAJECTORY_V214.mat');
if exist(trajectoryPath, 'file') ~= 2 || ...
        ~isscalar(windowIndex) || ~isfinite(windowIndex) || ...
        windowIndex ~= round(windowIndex) || windowIndex < 1 || ...
        ~isnumeric(formationIds) || any(~isfinite(formationIds)) || ...
        any(formationIds ~= round(formationIds)) || ...
        any(formationIds < 1) || ...
        numel(unique(formationIds)) ~= numel(formationIds)
    error('DirectGraphPayloadRepairV214:InvalidWithholdingScreen', ...
        'A completed V214 trajectory and valid window are required.');
end
loaded = load(trajectoryPath, 'result');
trajectory = loaded.result;
if ~isfield(trajectory, 'selectedTimes') || ...
        windowIndex > numel(trajectory.selectedTimes) || ...
        ~strcmp(trajectory.presetName, presetName) || ...
        trajectory.seed ~= seed || ...
        ~strcmp(trajectory.splitName, splitName) || ...
        trajectory.posteriorCounterfactualEnumerationUsed
    error('DirectGraphPayloadRepairV214:TrajectoryProvenance', ...
        'The V214 trajectory does not match the requested H=3 screen.');
end
currentTime = trajectory.selectedTimes(windowIndex);
cachePath = resolveSourcePath( ...
    trajectoryPath, trajectory.cachePaths{windowIndex});
cacheRoot = fileparts(cachePath);
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    protocol.outputRoot, 'formation_withholding_h3', splitName, ...
    sprintf('%s_seed%d_t%d', ...
        strrep(presetName, '-', '_'), seed, currentTime))));
screenRoot = fullfile(outputRoot, 'screen');

screenOptions = struct();
screenOptions.horizonSteps = protocol.horizonSteps;
screenOptions.interventionDurationSteps = ...
    protocol.actions.maximumWithholdingDurationPages;
screenOptions.filterSeedOffset = protocol.filterSeedOffset;
screenOptions.cacheRoot = cacheRoot;
screenOptions.interventionBankType = ...
    'direct-graph-payload-repair-v214';
screenOptions.trackingAlignedExecutionProfile = ...
    'v214-direct-graph-payload-repair';
screenOptions.receiverMode = protocol.receiverMode;
screenOptions.directGraphSplitName = splitName;
if ~isempty(formationIds)
    screenOptions.directGraphPayloadRepairBankOptions = struct( ...
        'actionMode', 'withholding-only', ...
        'formationIds', formationIds);
end
screenOptions.outputDirectory = screenRoot;
screenOptions.writeReport = true;
screenOptions.capturePosteriorSnapshotsEnabled = ...
    capturePosteriorSnapshotsEnabled;
screenOptions.captureFusedPosteriorSnapshotsEnabled = ...
    captureFusedPosteriorSnapshotsEnabled;
[screenReportPath, screen] = ...
    runFormationModeOpenedReturnScreen( ...
        presetName, seed, currentTime, screenOptions);

records = screen.records;
nonreferenceMask = [records.actionIndex] ~= ...
    screen.bank.referenceActionIndex;
candidateRecords = records(nonreferenceMask);
strictPositiveMask = arrayfun(@strictPositive, candidateRecords);
tailTolerantMask = arrayfun( ...
    @(record) tailTolerant(record, protocol.risk), candidateRecords);
eligibleMask = strictPositiveMask & tailTolerantMask;
bestLocalIndex = selectBest(candidateRecords, eligibleMask, protocol);
bestRecord = emptyBestRecord();
if isfinite(bestLocalIndex)
    bestRecord = candidateRecords(bestLocalIndex);
end

result = struct();
result.contractVersion = ...
    'direct-graph-formation-withholding-h3-v214-v1';
result.generatedAt = datestr(now, 31);
result.protocolId = protocol.id;
result.presetName = presetName;
result.seed = seed;
result.splitName = splitName;
result.windowIndex = windowIndex;
result.requestedFormationIds = formationIds;
result.currentTime = currentTime;
result.windowTimes = currentTime + (0:(protocol.horizonSteps - 1));
result.trajectoryPath = trajectoryPath;
result.trajectoryGenerationGitCommit = ...
    trajectory.generationGitCommit;
result.cachePath = cachePath;
result.screenPath = screenReportPath;
result.screenMatPath = screen.matPath;
result.records = records;
result.strictPositiveMask = strictPositiveMask;
result.tailTolerantMask = tailTolerantMask;
result.eligibleMask = eligibleMask;
result.bestCandidateLocalIndex = bestLocalIndex;
result.bestRecord = bestRecord;
result.anyEligibleCandidate = any(eligibleMask);
result.posteriorCounterfactualEnumerationUsedAtRuntime = false;
result.momentMatchedLightPosteriorUsed = false;
result.retainedLabelsPreserveCompleteMixture = true;
result.capturePosteriorSnapshotsEnabled = ...
    capturePosteriorSnapshotsEnabled;
result.captureFusedPosteriorSnapshotsEnabled = ...
    captureFusedPosteriorSnapshotsEnabled;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'This training-split H=3 screen starts every arm from the same ', ...
    'truth-free V214 cache. One receiver formation withholds complete ', ...
    'cross-formation posterior input for one page, then the full-payload ', ...
    'reference resumes for two pages. Truth scores the return only. ', ...
    'This is action-value training evidence, not an online policy, ', ...
    'held-out result or generalization claim.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'DIRECT_GRAPH_FORMATION_WITHHOLDING_H3_V214.mat');
reportPath = fullfile(outputRoot, ...
    'DIRECT_GRAPH_FORMATION_WITHHOLDING_H3_V214.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result, candidateRecords);
fprintf('V214 direct-graph withholding H=3: %s\n', reportPath);
end

function path = resolveSourcePath(trajectoryPath, referencedPath)
path = char(referencedPath);
if isempty(path)
    error('DirectGraphPayloadRepairV214:MissingSourceCache', ...
        'The selected trajectory cache path is empty.');
end
if path(1) ~= filesep
    marker = [filesep, 'RUN', filesep, 'GA', filesep];
    positions = strfind(trajectoryPath, marker);
    if isempty(positions)
        error('DirectGraphPayloadRepairV214:TrajectoryRoot', ...
            'The trajectory path does not expose its repository root.');
    end
    repositoryRoot = trajectoryPath(1:(positions(end) - 1));
    path = fullfile(repositoryRoot, path);
end
if exist(path, 'file') ~= 2
    error('DirectGraphPayloadRepairV214:MissingSourceCache', ...
        'The selected trajectory cache is unavailable: %s.', path);
end
end

function passed = strictPositive(record)
passed = record.meanGainPercent > 0 && ...
    record.rmseGainPercent > 0 && ...
    record.consensusGainPercent >= 0 && ...
    record.terminalConsensusGainPercent >= 0 && ...
    record.attemptedByteSavingPercent > 0 && ...
    record.selectedB3Passed;
end

function passed = tailTolerant(record, risk)
names = risk.targetNames;
tolerance = risk.tolerancePercent;
worstSensorEospa = tolerance(strcmp( ...
    names, 'worst_sensor_eospa_gain_percent'));
worstSensorRmse = tolerance(strcmp( ...
    names, 'worst_sensor_rmse_gain_percent'));
minimumFormationEospa = tolerance(strcmp( ...
    names, 'minimum_formation_eospa_gain_percent'));
minimumFormationRmse = tolerance(strcmp( ...
    names, 'minimum_formation_rmse_gain_percent'));
passed = record.worstGainPercent >= worstSensorEospa && ...
    record.worstRmseGainPercent >= worstSensorRmse && ...
    record.minimumFormationGainPercent >= minimumFormationEospa && ...
    record.minimumFormationRmseGainPercent >= minimumFormationRmse;
end

function index = selectBest(records, eligibleMask, protocol)
index = NaN;
eligible = find(eligibleMask);
if isempty(eligible)
    return;
end
scale = [ ...
    protocol.promotion.minimumMeanEospaGainPercentByScale, ...
    protocol.promotion.minimumMeanRmseGainPercentByScale, ...
    protocol.promotion.minimumConsensusGainPercentByScale, ...
    protocol.promotion.minimumAttemptedByteSavingPercentByScale];
score = -inf(1, numel(records));
for recordIdx = eligible
    values = [ ...
        records(recordIdx).meanGainPercent, ...
        records(recordIdx).rmseGainPercent, ...
        records(recordIdx).consensusGainPercent, ...
        records(recordIdx).attemptedByteSavingPercent];
    score(recordIdx) = min(values ./ max(scale, eps));
end
[~, index] = max(score);
end

function record = emptyBestRecord()
record = struct('actionIndex', NaN, 'actionName', '', ...
    'formationIndices', zeros(1, 0), ...
    'meanGainPercent', NaN, 'rmseGainPercent', NaN, ...
    'consensusGainPercent', NaN, ...
    'terminalConsensusGainPercent', NaN, ...
    'attemptedByteSavingPercent', NaN, ...
    'minimumFormationGainPercent', NaN, ...
    'minimumFormationRmseGainPercent', NaN);
end

function writeReport(path, result, records)
fid = fopen(path, 'w');
if fid < 0
    error('DirectGraphPayloadRepairV214:WithholdingReport', ...
        'Could not write the V214 H=3 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V214 direct-graph formation withholding H=3\n\n');
fprintf(fid, '- Split / scene / seed / time: `%s / %s / %d / %d`\n', ...
    result.splitName, result.presetName, result.seed, result.currentTime);
fprintf(fid, '- Any multi-objective eligible candidate: `%d`\n', ...
    result.anyEligibleCandidate);
if result.anyEligibleCandidate
    fprintf(fid, '- Best candidate: `%s`\n', ...
        result.bestRecord.actionName);
end
fprintf(fid, '- Online posterior counterfactuals: `0`\n');
fprintf(fid, '- Moment-matched light posterior: `0`\n\n');
fprintf(fid, ['| Formation action | E-OSPA gain | RMSE gain | ', ...
    'Consensus gain | Terminal consensus | Byte saving | ', ...
    'Worst sensor E / R | Minimum formation E / R | Eligible |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(records)
    fprintf(fid, ['| %s | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f / %+.3f%% | ', ...
        '%+.3f / %+.3f%% | %d |\n'], ...
        records(idx).actionName, records(idx).meanGainPercent, ...
        records(idx).rmseGainPercent, ...
        records(idx).consensusGainPercent, ...
        records(idx).terminalConsensusGainPercent, ...
        records(idx).attemptedByteSavingPercent, ...
        records(idx).worstGainPercent, ...
        records(idx).worstRmseGainPercent, ...
        records(idx).minimumFormationGainPercent, ...
        records(idx).minimumFormationRmseGainPercent, ...
        result.eligibleMask(idx));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
