function [reportPath, result] = ...
        analyzePolicyStateProposalTransferV210(options)
% ANALYZEPOLICYSTATEPROPOSALTRANSFERV210 Cross-state top-K diagnostic.
%
% For each policy-induced page, remove the base-route page at the same time,
% fit the existing V208 frozen-representation probe on the remaining seven
% base pages, and rank the exact policy-state action bank.  This diagnoses a
% registered proposal-set size; it is not final model training or validation.

if nargin < 1 || isempty(options)
    options = struct();
end
baseDatasetPath = char(getField(options, 'baseDatasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v208', ...
    'formation_label_kla_immediate_merged', ...
    'x36_seed211_t72_h8', ...
    'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208_MERGED.mat')));
evidenceRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v209');
policySources = getField(options, 'policySources', ...
    defaultPolicySources(evidenceRoot));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    evidenceRoot, 'policy_state_proposal_transfer', ...
    'x36_seed211_t72_h8')));
encoderSeeds = reshape(getField(options, ...
    'encoderSeeds', 2081:2085), 1, []);
hiddenWidth = getField(options, 'hiddenWidth', 16);
ridgeLambda = getField(options, 'ridgeLambda', 10);
uncertaintyMultiplier = getField( ...
    options, 'uncertaintyMultiplier', 0.5);
topKValues = reshape(getField(options, ...
    'topKValues', [1, 2, 3, 5]), 1, []);

if exist(baseDatasetPath, 'file') ~= 2 || ...
        ~isstruct(policySources) || ...
        ~all(isfield(policySources, {'actionTime', 'path'})) || ...
        isempty(topKValues) || any(topKValues < 1) || ...
        any(topKValues ~= round(topKValues))
    error('PolicyStateProposalTransferV210:InvalidRequest', ...
        'A base dataset, policy manifest and positive top-K values are required.');
end
baseLoaded = load(baseDatasetPath, 'dataset');
base = baseLoaded.dataset;
validateBaseDataset(base);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

states = repmat(emptyState(), 1, numel(policySources));
for stateIdx = 1:numel(policySources)
    actionTime = policySources(stateIdx).actionTime;
    policyPath = char(policySources(stateIdx).path);
    policy = loadPolicyDataset(policyPath, base, actionTime);
    overlay = buildOverlayDataset(base, policy, policyPath);
    stateRoot = fullfile(outputRoot, sprintf('t%d', actionTime));
    if exist(stateRoot, 'dir') ~= 7
        mkdir(stateRoot);
    end
    overlayPath = fullfile(stateRoot, ...
        'POLICY_STATE_PROPOSAL_OVERLAY_V210.mat');
    dataset = overlay; %#ok<NASGU>
    save('-mat7-binary', overlayPath, 'dataset');

    common = struct( ...
        'datasetPath', overlayPath, ...
        'encoderSeeds', encoderSeeds, ...
        'hiddenWidth', hiddenWidth, ...
        'ridgeLambda', ridgeLambda, ...
        'uncertaintyMultiplier', uncertaintyMultiplier);
    graphOptions = common;
    graphOptions.representationMode = 'two-round-graph';
    graphOptions.outputRoot = fullfile(stateRoot, 'graph');
    [~, graphResult] = ...
        analyzeFormationActionValueLearnabilityV208(graphOptions);
    actionOptions = common;
    actionOptions.representationMode = 'action-only';
    actionOptions.outputRoot = fullfile(stateRoot, 'action_only');
    [~, actionResult] = ...
        analyzeFormationActionValueLearnabilityV208(actionOptions);

    heldoutBlock = overlay.blockCount;
    heldoutRows = overlay.rows( ...
        [overlay.rows.blockId] == heldoutBlock);
    teacherIndices = find([heldoutRows.teacherKey]);
    if numel(teacherIndices) ~= 1
        error('PolicyStateProposalTransferV210:TeacherKey', ...
            'Each policy page must contain exactly one teacher action.');
    end
    state = emptyState();
    state.actionTime = actionTime;
    state.policyDatasetPath = policyPath;
    state.overlayDatasetPath = overlayPath;
    state.actionCount = numel(heldoutRows);
    state.teacherLocalIndex = teacherIndices(1);
    teacher = heldoutRows(teacherIndices);
    state.teacherFormationId = teacher.receiverFormationId;
    state.teacherSourceId = teacher.sourceId;
    state.teacherLabel = teacher.label;
    state.teacherImmediateTargets = teacher.targets;
    state.teacherImmediateAggregatePositive = ...
        teacher.jointAggregatePositive;
    state.teacherImmediateStrictPositive = ...
        strictTailPositive(teacher.targets);
    state.graph = summarizeFold(graphResult, heldoutBlock, ...
        teacherIndices, teacher.targets, topKValues);
    state.actionOnly = summarizeFold(actionResult, heldoutBlock, ...
        teacherIndices, teacher.targets, topKValues);
    states(stateIdx) = state;
end

result = struct();
result.contractVersion = ...
    'policy-state-proposal-transfer-v210-v1';
result.generatedAt = datestr(now, 31);
result.baseDatasetPath = baseDatasetPath;
result.policySources = policySources;
result.encoderSeeds = encoderSeeds;
result.hiddenWidth = hiddenWidth;
result.ridgeLambda = ridgeLambda;
result.uncertaintyMultiplier = uncertaintyMultiplier;
result.topKValues = topKValues;
result.actionFeatureCount = numel(base.actionFeatureNames);
result.propagationAugmented = ...
    isfield(base, 'propagationFeatureNames') && ...
    ~isempty(base.propagationFeatureNames);
result.states = states;
result.stateCount = numel(states);
result.graphTeacherTopKRecovery = topKRecovery(states, 'graph');
result.actionTeacherTopKRecovery = ...
    topKRecovery(states, 'actionOnly');
result.baseSameTimePageExcluded = true;
result.featuresUseTruth = false;
result.targetsUseCurrentTruth = true;
result.recursiveTargetsUsed = false;
result.completeTrajectoryHeldOut = false;
result.proposalSetFrozen = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'For each X36 seed-211 policy-induced page, V210 removes the ', ...
    'base-route page at the same time and fits the V208 diagnostic ', ...
    'readout on the other seven opened pages.  Graph and action features ', ...
    'are truth-free; current truth only evaluates ranking.  The pages ', ...
    'share one development trajectory and the encoder is still a frozen ', ...
    'random representation.  The result may size a later proposal set, ', ...
    'but it is not a trained selector, recursive test, held-out seed, ', ...
    'calibration result or performance claim.'];
matPath = fullfile(outputRoot, ...
    'POLICY_STATE_PROPOSAL_TRANSFER_V210.mat');
reportPath = fullfile(outputRoot, ...
    'POLICY_STATE_PROPOSAL_TRANSFER_V210.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V210 policy-state proposal transfer: %s\n', reportPath);
end

function sources = defaultPolicySources(evidenceRoot)
template = struct('actionTime', 0, 'path', '');
times = [73, 76, 77];
leaves = {'t73_after_v206_prefix', ...
    't76_after_v206_prefix', 't77_after_v204_prefix'};
sources = repmat(template, 1, numel(times));
for idx = 1:numel(times)
    sources(idx).actionTime = times(idx);
    sources(idx).path = fullfile(evidenceRoot, ...
        'policy_induced_immediate', leaves{idx}, ...
        'FORMATION_LABEL_KLA_IMMEDIATE_DATASET_V208.mat');
end
end

function validateBaseDataset(dataset)
allowedContracts = { ...
    'formation-label-kla-immediate-dataset-v208-merged-v1', ...
    'formation-label-kla-immediate-propagation-v211-v1'};
required = {'contractVersion', 'presetName', 'seed', ...
    'returnTimes', 'actionFeatureNames', 'targetNames', ...
    'blocks', 'rows', 'blockCount', 'rowCount', ...
    'featuresUseTruth', 'featuresUseFutureInformation', ...
    'recursiveTargetsIncluded', 'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~ismember(dataset.contractVersion, allowedContracts) || ...
        dataset.blockCount ~= 8 || ...
        numel(dataset.returnTimes) ~= dataset.blockCount || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed
    error('PolicyStateProposalTransferV210:BaseContract', ...
        'The V208 merged base dataset is invalid.');
end
end

function dataset = loadPolicyDataset(path, base, actionTime)
if exist(path, 'file') ~= 2
    error('PolicyStateProposalTransferV210:MissingPolicyState', ...
        'Missing policy-state dataset: %s', path);
end
loaded = load(path, 'dataset');
dataset = loaded.dataset;
allowedContracts = { ...
    'formation-label-kla-immediate-dataset-v208-v1', ...
    'formation-label-kla-immediate-propagation-v211-v1'};
required = {'contractVersion', 'presetName', 'seed', ...
    'returnTimes', 'actionFeatureNames', 'targetNames', ...
    'blocks', 'rows', 'blockCount', 'featuresUseTruth', ...
    'featuresUseFutureInformation', 'recursiveTargetsIncluded', ...
    'validationClaimAllowed'};
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~ismember(dataset.contractVersion, allowedContracts) || ...
        dataset.blockCount ~= 1 || ...
        numel(dataset.returnTimes) ~= 1 || ...
        dataset.returnTimes ~= actionTime || ...
        ~strcmp(dataset.presetName, base.presetName) || ...
        dataset.seed ~= base.seed || ...
        ~isequal(dataset.actionFeatureNames, ...
            base.actionFeatureNames) || ...
        ~isequal(dataset.targetNames, base.targetNames) || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureInformation || ...
        dataset.recursiveTargetsIncluded || ...
        dataset.validationClaimAllowed
    error('PolicyStateProposalTransferV210:PolicyContract', ...
        'The policy-state immediate dataset is invalid.');
end
end

function overlay = buildOverlayDataset(base, policy, policyPath)
excludedTime = policy.returnTimes(1);
baseBlockIndices = find(base.returnTimes ~= excludedTime);
if numel(baseBlockIndices) ~= base.blockCount - 1
    error('PolicyStateProposalTransferV210:BaseTime', ...
        'The base dataset must contain exactly one matching-time page.');
end
blocks = repmat(struct(), 1, 0);
rows = repmat(struct(), 1, 0);
for sourceBlockIdx = reshape(baseBlockIndices, 1, [])
    [blocks, rows] = appendBlock(blocks, rows, ...
        base.blocks(sourceBlockIdx), ...
        base.rows([base.rows.blockId] == sourceBlockIdx));
end
[blocks, rows] = appendBlock(blocks, rows, ...
    policy.blocks(1), policy.rows);
targets = vertcat(rows.targets);
overlay = base;
overlay.generatedAt = datestr(now, 31);
overlay.blocks = blocks;
overlay.rows = rows;
overlay.blockCount = numel(blocks);
overlay.rowCount = numel(rows);
overlay.pageIndices = 1:overlay.blockCount;
overlay.returnTimes = [blocks.currentTime];
overlay.sourceRecords = struct( ...
    'baseDatasetPath', base.matPath, ...
    'policyDatasetPath', policyPath, ...
    'excludedBaseTime', excludedTime);
overlay.netByteFeasibleRowCount = nnz([rows.netByteFeasible]);
overlay.jointTrackingPositiveRowCount = ...
    nnz([rows.jointTrackingPositive]);
overlay.jointAggregatePositiveRowCount = ...
    nnz([rows.jointAggregatePositive]);
overlay.strictZeroToleranceTailPositiveRowCount = ...
    nnz(arrayfun(@(idx) strictTailPositive( ...
        targets(idx, :)), 1:size(targets, 1)));
overlay.teacherKeyRowCount = nnz([rows.teacherKey]);
overlay.evidenceBoundary = ...
    'Development-only policy-state proposal overlay.';
end

function [blocks, rows] = appendBlock( ...
        blocks, rows, sourceBlock, sourceRows)
blockId = numel(blocks) + 1;
sourceBlock.blockId = blockId;
sourceBlock.page = blockId;
if isempty(blocks)
    blocks = sourceBlock;
else
    blocks(end + 1) = sourceBlock; %#ok<AGROW>
end
sourceRows = reshape(sourceRows, 1, []);
for rowIdx = 1:numel(sourceRows)
    sourceRows(rowIdx).rowId = numel(rows) + rowIdx;
    sourceRows(rowIdx).blockId = blockId;
    sourceRows(rowIdx).page = blockId;
end
if isempty(rows)
    rows = sourceRows;
else
    rows = [rows, sourceRows]; %#ok<AGROW>
end
end

function summary = summarizeFold( ...
        analysis, heldoutBlock, teacherIndex, teacherTargets, topKValues)
fold = analysis.folds(heldoutBlock);
[~, ranking] = sort(fold.score, 'descend');
rank = find(ranking == teacherIndex, 1);
summary = struct();
summary.representationMode = analysis.representationMode;
summary.teacherRank = rank;
summary.teacherTopK = arrayfun(@(k) ...
    rank <= min(k, numel(ranking)), topKValues);
summary.teacherScore = fold.score(teacherIndex);
summary.teacherPrediction = fold.predictionMean(teacherIndex, :);
summary.teacherPredictionStd = fold.predictionStd(teacherIndex, :);
summary.teacherLowerBound = fold.lowerBound(teacherIndex, :);
summary.teacherPredictedAdmissible = ...
    all(summary.teacherLowerBound(1:5) > 0) && ...
    all(summary.teacherLowerBound(6:9) >= 0) && ...
    teacherTargets(11) >= 0;
summary.selected = fold.selected;
summary.selectedTeacher = ...
    fold.selected && fold.selectedLocalIndex == teacherIndex;
summary.selectedLocalIndex = fold.selectedLocalIndex;
summary.topRankedLocalIndex = ranking(1);
summary.topRankedTrueStrict = fold.trueStrictMask(ranking(1));
end

function counts = topKRecovery(states, fieldName)
if isempty(states)
    counts = zeros(1, 0);
    return;
end
matrix = vertcat(states.(fieldName)); %#ok<VTCAT>
topK = vertcat(matrix.teacherTopK);
counts = sum(topK, 1);
end

function value = strictTailPositive(targets)
value = targets(1) > 0 && targets(2) > 0 && ...
    targets(3) >= 0 && targets(5) > 0 && ...
    targets(6) > 0 && targets(7) >= 0 && ...
    targets(8) >= 0 && targets(9) >= 0 && ...
    targets(10) >= 0 && targets(11) >= 0;
end

function state = emptyState()
state = struct( ...
    'actionTime', 0, 'policyDatasetPath', '', ...
    'overlayDatasetPath', '', 'actionCount', 0, ...
    'teacherLocalIndex', 0, 'teacherFormationId', 0, ...
    'teacherSourceId', 0, 'teacherLabel', zeros(2, 1), ...
    'teacherImmediateTargets', zeros(1, 0), ...
    'teacherImmediateAggregatePositive', false, ...
    'teacherImmediateStrictPositive', false, ...
    'graph', struct(), 'actionOnly', struct());
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('PolicyStateProposalTransferV210:ReportOpen', ...
        'Could not write the proposal-transfer report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V210 policy-state proposal transfer\n\n');
fprintf(fid, '- Same-time base page excluded: `1`\n');
fprintf(fid, '- Policy states: `%d`\n', result.stateCount);
fprintf(fid, '- Top-K values: `%s`\n\n', mat2str(result.topKValues));
fprintf(fid, '- Action features / propagation augmented: `%d / %d`\n\n', ...
    result.actionFeatureCount, result.propagationAugmented);
fprintf(fid, ['| Time | Actions | Teacher | Immediate E / R / C | ', ...
    'Graph rank | Action-only rank | Graph admit | Action admit |\n']);
fprintf(fid, '|--:|--:|:--|:--|--:|--:|:--:|:--:|\n');
for state = reshape(result.states, 1, [])
    target = state.teacherImmediateTargets;
    fprintf(fid, ['| %d | %d | F%d<-S%d [%d,%d] | ', ...
        '%+.3f / %+.3f / %+.3f | %d | %d | %d | %d |\n'], ...
        state.actionTime, state.actionCount, ...
        state.teacherFormationId, state.teacherSourceId, ...
        state.teacherLabel(1), state.teacherLabel(2), ...
        target(1), target(2), target(3), ...
        state.graph.teacherRank, state.actionOnly.teacherRank, ...
        state.graph.teacherPredictedAdmissible, ...
        state.actionOnly.teacherPredictedAdmissible);
end
fprintf(fid, '\n## Teacher top-K recovery\n\n');
fprintf(fid, '| K | Graph | Action-only |\n|--:|--:|--:|\n');
for idx = 1:numel(result.topKValues)
    fprintf(fid, '| %d | %d/%d | %d/%d |\n', ...
        result.topKValues(idx), ...
        result.graphTeacherTopKRecovery(idx), result.stateCount, ...
        result.actionTeacherTopKRecovery(idx), result.stateCount);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
