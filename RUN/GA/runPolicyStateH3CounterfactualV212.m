function [reportPath, result] = ...
        runPolicyStateH3CounterfactualV212(options)
% RUNPOLICYSTATEH3COUNTERFACTUALV212 Short exact branch continuation.
%
% Reuse one captured policy-induced pre-action state, reproduce its no-op
% H=3 continuation, and run one forced complete-label KLA action from the
% identical state.  The first pilot defaults to the known t=73 F6 action so
% the short path can be checked against the completed H=8 branches.

if nargin < 1 || isempty(options)
    options = struct();
end
sourceScreenPath = char(getField(options, ...
    'sourceScreenPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v209', ...
        'sparse_recursive_counterfactuals', ...
        'x36_seed211_t72_h8', ...
        't73_noop_after_v206_prefix', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat'])));
expectedCandidateScreenPath = char(getField(options, ...
    'expectedCandidateScreenPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v206', 'support_aware_complete_teacher', ...
        'x36_seed211_t72_h8', 'screen', ...
        ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
         'X36_FORMATION_FOV_SEED211_T72_D8.mat'])));
branchTime = getField(options, 'branchTime', 73);
receiverFormationId = getField( ...
    options, 'receiverFormationId', 6);
sourceId = getField(options, 'sourceId', 19);
label = reshape(getField(options, 'label', [7; 5]), [], 1);
sourceWeight = getField(options, 'sourceWeight', 0.5);
reuseExistingScreens = logical(getField( ...
    options, 'reuseExistingScreens', true));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v212', 'policy_state_h3_replay', ...
    'x36_seed211_t73_f6')));
if exist(sourceScreenPath, 'file') ~= 2 || ...
        (~isempty(expectedCandidateScreenPath) && ...
         exist(expectedCandidateScreenPath, 'file') ~= 2) || ...
        ~isscalar(branchTime) || branchTime < 1 || ...
        branchTime ~= round(branchTime) || ...
        ~isscalar(receiverFormationId) || ...
        receiverFormationId < 1 || ...
        receiverFormationId ~= round(receiverFormationId) || ...
        ~isscalar(sourceId) || sourceId < 1 || ...
        sourceId ~= round(sourceId) || numel(label) ~= 2 || ...
        any(~isfinite(label)) || any(label ~= round(label)) || ...
        ~isscalar(sourceWeight) || ~isfinite(sourceWeight) || ...
        sourceWeight <= 0 || sourceWeight >= 1
    error('PolicyStateH3V212:InvalidRequest', ...
        'A captured state and valid complete-label KLA action are required.');
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
sourceLoaded = load(sourceScreenPath, 'screen');
sourceScreen = sourceLoaded.screen;
state = buildPolicyInducedContinuationStateV212( ...
    sourceScreenPath, branchTime);
protocol = getOnlinePositiveNetAddressablePayloadV99Protocol(3);
caseIdx = find(strcmp({protocol.cases.presetName}, ...
    sourceScreen.presetName));
if numel(caseIdx) ~= 1 || ...
        protocol.cases(caseIdx).seed ~= sourceScreen.seed
    error('PolicyStateH3V212:ProtocolCase', ...
        'The source screen is not a registered V99 development case.');
end
entry = protocol.cases(caseIdx);
screenStem = sprintf( ...
    'TRACKING_ALIGNED_X36_SCHEDULE_H3_%s_SEED%d_T%d_D3', ...
    upper(strrep(sourceScreen.presetName, '-', '_')), ...
    sourceScreen.seed, branchTime);
noOpRoot = fullfile(outputRoot, 'no_op', 'screen');
candidateRoot = fullfile(outputRoot, 'candidate', 'screen');
noOpScreenPath = fullfile(noOpRoot, [screenStem, '.mat']);
candidateScreenPath = fullfile(candidateRoot, [screenStem, '.mat']);

common = struct( ...
    'horizonSteps', 3, ...
    'interventionDurationSteps', 3, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', fileparts(state.cachePath), ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', ...
            protocol.positiveSupportThreshold, ...
        'bankVariant', 'online-positive-net-addressable-v99', ...
        'horizonSteps', 3), ...
    'receiverMode', protocol.receiverMode, ...
    'actionIndices', [1, 3], ...
    'writeReport', true, ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'captureFusedPosteriorSnapshotsEnabled', true, ...
    'continuationStateOverride', state);

if reuseExistingScreens && exist(noOpScreenPath, 'file') == 2
    loaded = load(noOpScreenPath, 'screen');
    noOpScreen = loaded.screen;
else
    noOpOptions = common;
    noOpOptions.outputDirectory = noOpRoot;
    noOpOptions.trackingAlignedExecutionProfile = ...
        'v99-online-positive-net-addressable-payload';
    [~, noOpScreen] = runFormationModeOpenedReturnScreen( ...
        sourceScreen.presetName, sourceScreen.seed, ...
        branchTime, noOpOptions);
end
noOpIdx = candidateOutcomeIndex(noOpScreen);
sourceIdx = state.sourceOutcomeIndex;
sourcePages = state.sourcePageIndex: ...
    (state.sourcePageIndex + 2);
noOpReproduction = compareOutcomeWindow( ...
    noOpScreen.outcomes(noOpIdx), 1:3, ...
    sourceScreen.outcomes(sourceIdx), sourcePages);
if ~noOpReproduction.matched
    error('PolicyStateH3V212:NoOpReproduction', ...
        'The short continuation does not reproduce its source no-op branch.');
end

referenceIdx = noOpScreen.referenceSubsetIndex;
repairPlan = struct();
repairPlan.times = branchTime;
repairPlan.referenceAttemptedBytes = ...
    noOpScreen.outcomes(referenceIdx).attemptedBytesByTime(1);
repairPlan.idealDeliveryTeacherMode = true;
repairPlan.maximumActions = 1;
repairPlan.forcedFormationId = receiverFormationId;
repairPlan.forcedSourceId = sourceId;
repairPlan.forcedLabel = label;
repairPlan.updateMode = 'label-kla';
repairPlan.sourceWeight = sourceWeight;
if reuseExistingScreens && exist(candidateScreenPath, 'file') == 2
    loaded = load(candidateScreenPath, 'screen');
    candidateScreen = loaded.screen;
else
    candidateOptions = common;
    candidateOptions.outputDirectory = candidateRoot;
    candidateOptions.trackingAlignedExecutionProfile = ...
        'v188-budget-recycled-formation-repair';
    candidateOptions.budgetRecycledFormationRepairPlan = repairPlan;
    candidateOptions.referenceOutcomeScreenPath = noOpScreenPath;
    [~, candidateScreen] = runFormationModeOpenedReturnScreen( ...
        sourceScreen.presetName, sourceScreen.seed, ...
        branchTime, candidateOptions);
end
candidateIdx = candidateOutcomeIndex(candidateScreen);
candidateOutcome = candidateScreen.outcomes(candidateIdx);
if candidateOutcome. ...
        budgetRecycledFormationRepairAppliedActionCountByTime(1) ~= 1
    error('PolicyStateH3V212:ActionNotApplied', ...
        'The forced complete-label KLA action did not execute exactly once.');
end
candidateReproduction = emptyComparison();
if ~isempty(expectedCandidateScreenPath)
    expectedLoaded = load(expectedCandidateScreenPath, 'screen');
    expectedScreen = expectedLoaded.screen;
    expectedIdx = candidateOutcomeIndex(expectedScreen);
    expectedPage = find(expectedScreen.returnTimes == branchTime);
    if numel(expectedPage) ~= 1 || ...
            expectedPage + 2 > numel(expectedScreen.returnTimes)
        error('PolicyStateH3V212:ExpectedWindow', ...
            'The expected candidate screen lacks the H=3 window.');
    end
    candidateReproduction = compareOutcomeWindow( ...
        candidateOutcome, 1:3, ...
        expectedScreen.outcomes(expectedIdx), ...
        expectedPage:(expectedPage + 2));
    if ~candidateReproduction.matched
        error('PolicyStateH3V212:CandidateReproduction', ...
            'The short action branch does not reproduce the completed branch.');
    end
end

noOpOutcome = noOpScreen.outcomes(noOpIdx);
groupIds = noOpScreen.sensorGroupIds;
noOpMetrics = windowMetrics( ...
    noOpOutcome, groupIds, 1:3, receiverFormationId);
candidateMetrics = windowMetrics( ...
    candidateOutcome, groupIds, 1:3, receiverFormationId);
staticMetrics = windowMetrics( ...
    noOpScreen.outcomes(referenceIdx), ...
    groupIds, 1:3, receiverFormationId);
result = struct();
result.contractVersion = ...
    'policy-state-h3-counterfactual-v212-v1';
result.generatedAt = datestr(now, 31);
result.presetName = sourceScreen.presetName;
result.seed = sourceScreen.seed;
result.branchTime = branchTime;
result.windowTimes = branchTime:(branchTime + 2);
result.receiverFormationId = receiverFormationId;
result.sourceId = sourceId;
result.label = label;
result.sourceWeight = sourceWeight;
result.continuationState = state;
result.noOpScreenPath = noOpScreenPath;
result.candidateScreenPath = candidateScreenPath;
result.noOpReproduction = noOpReproduction;
result.candidateReproduction = candidateReproduction;
result.noOpMetrics = noOpMetrics;
result.candidateMetrics = candidateMetrics;
result.meanEospaGainPercent = relativeGain( ...
    noOpMetrics.meanEospa, candidateMetrics.meanEospa);
result.meanRmseGainPercent = relativeGain( ...
    noOpMetrics.meanRmse, candidateMetrics.meanRmse);
result.consensusGainPercent = relativeGain( ...
    noOpMetrics.consensusOspa, candidateMetrics.consensusOspa);
result.terminalConsensusGainPercent = relativeGain( ...
    noOpMetrics.terminalConsensusOspa, ...
    candidateMetrics.terminalConsensusOspa);
result.receiverFormationEospaGainPercent = relativeGain( ...
    noOpMetrics.receiverFormationEospa, ...
    candidateMetrics.receiverFormationEospa);
result.receiverFormationRmseGainPercent = relativeGain( ...
    noOpMetrics.receiverFormationRmse, ...
    candidateMetrics.receiverFormationRmse);
result.minimumAffectedSensorEospaGainPercent = min( ...
    relativeGainVector(noOpMetrics.receiverSensorEospa, ...
        candidateMetrics.receiverSensorEospa));
result.minimumAffectedSensorRmseGainPercent = min( ...
    relativeGainVector(noOpMetrics.receiverSensorRmse, ...
        candidateMetrics.receiverSensorRmse));
result.worstSensorEospaGainPercent = relativeGain( ...
    noOpMetrics.worstSensorEospa, ...
    candidateMetrics.worstSensorEospa);
result.worstSensorRmseGainPercent = relativeGain( ...
    noOpMetrics.worstSensorRmse, ...
    candidateMetrics.worstSensorRmse);
result.minimumFormationEospaGainPercent = min( ...
    relativeGainVector(noOpMetrics.formationEospa, ...
        candidateMetrics.formationEospa));
result.minimumFormationRmseGainPercent = min( ...
    relativeGainVector(noOpMetrics.formationRmse, ...
        candidateMetrics.formationRmse));
result.incrementalAttemptedBytes = ...
    candidateMetrics.attemptedBytes - noOpMetrics.attemptedBytes;
result.candidateStaticByteSaving = ...
    staticMetrics.attemptedBytes - candidateMetrics.attemptedBytes;
result.candidateStaticByteSavingPercent = 100 * ...
    result.candidateStaticByteSaving / ...
        max(staticMetrics.attemptedBytes, eps);
result.aggregateReturnPositive = ...
    result.meanEospaGainPercent > 0 && ...
    result.meanRmseGainPercent > 0 && ...
    result.consensusGainPercent >= 0 && ...
    result.candidateStaticByteSaving >= 0;
result.noOpElapsedSeconds = noOpOutcome.elapsedSeconds;
result.candidateElapsedSeconds = candidateOutcome.elapsedSeconds;
result.truthUsedForTargets = true;
result.truthUsedAtRuntime = false;
result.futureMeasurementsUsedForFeatures = false;
result.completeTrajectoryHeldOut = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'V212 starts both arms from the same captured policy-induced local ', ...
    'posterior and two-page topology history.  It first requires the ', ...
    'short no-op continuation to reproduce its completed source window; ', ...
    'the pilot also reproduces the known action branch.  Truth scores ', ...
    'the H=3 return only.  This validates a faster development label ', ...
    'path, not a held-out policy or performance claim.'];
matPath = fullfile(outputRoot, ...
    'POLICY_STATE_H3_COUNTERFACTUAL_V212.mat');
reportPath = fullfile(outputRoot, ...
    'POLICY_STATE_H3_COUNTERFACTUAL_V212.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V212 policy-state H=3 counterfactual: %s\n', reportPath);
end

function index = candidateOutcomeIndex(screen)
index = find(strncmp({screen.records.actionName}, ...
    'v99-online-positive-net-', 24));
if numel(index) ~= 1
    error('PolicyStateH3V212:CandidateArm', ...
        'Each screen must contain one V99 candidate arm.');
end
end

function comparison = compareOutcomeWindow( ...
        first, firstPages, second, secondPages)
comparison = emptyComparison();
comparison.eospaMaximumDifference = maximumAbsoluteDifference( ...
    first.eospaBySensorTime(:, firstPages), ...
    second.eospaBySensorTime(:, secondPages));
comparison.rmseMaximumDifference = maximumAbsoluteDifference( ...
    first.rmseBySensorTime(:, firstPages), ...
    second.rmseBySensorTime(:, secondPages));
comparison.consensusMaximumDifference = maximumAbsoluteDifference( ...
    first.consensusOspaByTime(firstPages), ...
    second.consensusOspaByTime(secondPages));
comparison.attemptedBytesExact = isequal( ...
    first.attemptedBytesByTime(firstPages), ...
    second.attemptedBytesByTime(secondPages));
comparison.matched = ...
    comparison.eospaMaximumDifference <= 1e-10 && ...
    comparison.rmseMaximumDifference <= 1e-10 && ...
    comparison.consensusMaximumDifference <= 1e-10 && ...
    comparison.attemptedBytesExact;
end

function comparison = emptyComparison()
comparison = struct( ...
    'matched', false, ...
    'eospaMaximumDifference', NaN, ...
    'rmseMaximumDifference', NaN, ...
    'consensusMaximumDifference', NaN, ...
    'attemptedBytesExact', false);
end

function value = maximumAbsoluteDifference(first, second)
if ~isequal(size(first), size(second)) || ...
        any(xor(isfinite(first(:)), isfinite(second(:))))
    value = inf;
    return;
end
mask = isfinite(first) & isfinite(second);
if any(mask(:))
    value = max(abs(first(mask) - second(mask)));
else
    value = 0;
end
end

function metrics = windowMetrics( ...
        outcome, groupIds, pages, receiverFormationId)
eospa = outcome.eospaBySensorTime(:, pages);
rmse = outcome.rmseBySensorTime(:, pages);
sensorEospa = finiteMeanRows(eospa);
sensorRmse = finiteMeanRows(rmse);
formationIds = unique(reshape(groupIds, 1, []), 'stable');
formationEospa = NaN(1, numel(formationIds));
formationRmse = NaN(1, numel(formationIds));
for formationIdx = 1:numel(formationIds)
    sensorMask = groupIds == formationIds(formationIdx);
    formationEospa(formationIdx) = ...
        finiteMean(eospa(sensorMask, :));
    formationRmse(formationIdx) = ...
        finiteMean(rmse(sensorMask, :));
end
receiverMask = groupIds == receiverFormationId;
metrics = struct();
metrics.meanEospa = finiteMean(eospa);
metrics.meanRmse = finiteMean(rmse);
metrics.consensusOspa = finiteMean( ...
    outcome.consensusOspaByTime(pages));
metrics.terminalConsensusOspa = ...
    outcome.consensusOspaByTime(pages(end));
metrics.sensorEospa = sensorEospa;
metrics.sensorRmse = sensorRmse;
metrics.worstSensorEospa = max(sensorEospa);
metrics.worstSensorRmse = max(sensorRmse);
metrics.formationEospa = formationEospa;
metrics.formationRmse = formationRmse;
metrics.receiverFormationEospa = ...
    finiteMean(eospa(receiverMask, :));
metrics.receiverFormationRmse = ...
    finiteMean(rmse(receiverMask, :));
metrics.receiverSensorEospa = sensorEospa(receiverMask);
metrics.receiverSensorRmse = sensorRmse(receiverMask);
metrics.attemptedBytes = sum(outcome.attemptedBytesByTime(pages));
end

function means = finiteMeanRows(values)
means = NaN(size(values, 1), 1);
for rowIdx = 1:size(values, 1)
    means(rowIdx) = finiteMean(values(rowIdx, :));
end
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(abs(reference), eps);
end

function gains = relativeGainVector(reference, candidate)
gains = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('PolicyStateH3V212:ReportOpen', ...
        'Could not write the V212 H=3 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V212 policy-state H=3 counterfactual\n\n');
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    result.presetName, result.seed, result.branchTime);
fprintf(fid, '- Action: `F%d <- S%d [%d,%d]`\n', ...
    result.receiverFormationId, result.sourceId, ...
    result.label(1), result.label(2));
fprintf(fid, '- No-op source reproduction: `%d`\n', ...
    result.noOpReproduction.matched);
fprintf(fid, '- Known candidate reproduction: `%d`\n', ...
    result.candidateReproduction.matched);
fprintf(fid, '- No-op / candidate elapsed: `%.2f / %.2f s`\n\n', ...
    result.noOpElapsedSeconds, result.candidateElapsedSeconds);
fprintf(fid, '| E-OSPA | RMSE | Consensus | Receiver E / R | Added bytes | Static saving | Aggregate |\n');
fprintf(fid, '|--:|--:|--:|:--|--:|--:|:--:|\n');
fprintf(fid, ['| %+.3f%% | %+.3f%% | %+.3f%% | ', ...
    '%+.3f%% / %+.3f%% | %+.0f B | %+.3f%% | %d |\n'], ...
    result.meanEospaGainPercent, result.meanRmseGainPercent, ...
    result.consensusGainPercent, ...
    result.receiverFormationEospaGainPercent, ...
    result.receiverFormationRmseGainPercent, ...
    result.incrementalAttemptedBytes, ...
    result.candidateStaticByteSavingPercent, ...
    result.aggregateReturnPositive);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
