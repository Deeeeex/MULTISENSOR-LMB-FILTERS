function [reportPath, result] = ...
        runCrossScaleMinimumBackboneV274FullEpisode(options)
% RUNCROSSSCALEMINIMUMBACKBONEV274FULLEPISODE Paired X36 baseline.

if nargin < 1 || isempty(options)
    options = struct();
end
presetName = 'x36-formation-fov-temporal-coupled-formation-braid';
seed = getField(options, 'seed', 1301);
resume = logical(getField(options, 'resume', true));
if ~isscalar(seed) || ~isfinite(seed) || seed ~= 1301 || ...
        ~isscalar(resume)
    error('CrossScaleMinimumBackboneV274:InvalidOptions', ...
        'V274 is frozen to X36 seed 1301 and one scalar resume flag.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('CrossScaleMinimumBackboneV274:DirtySource', ...
        'Official V274 execution requires clean source.');
end

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    repoRoot, 'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v274', 'x36_minimum_backbone_seed1301')));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

[~, scene] = runTemporalTaskCoupledFormationBraidV247Preflight( ...
    struct('presets', {{presetName}}, 'seed', seed, ...
        'writeReport', false, 'failOnGate', true));
if ~scene.crossScaleGatePassed
    error('CrossScaleMinimumBackboneV274:SceneGateFailed', ...
        'The registered temporal-coupled X36 scene failed preflight.');
end

fullRouteRoot = fullfile(outputRoot, 'fixed_and_full_causal');
[fullReportPath, fullResult] = ...
    runFormationBraidRoutingComparisonV241FullEpisode(struct( ...
        'presetName', presetName, 'seed', seed, ...
        'armNames', {{'static-dropout', 'causal'}}, ...
        'resume', resume, 'outputRoot', fullRouteRoot));
fullMatPath = fullfile(fullRouteRoot, ...
    'FORMATION_BRAID_ROUTING_COMPARISON_V241_FULL_EPISODE.mat');
if ~logical(fullResult.causalStaticPairAvailable)
    error('CrossScaleMinimumBackboneV274:MissingFullPair', ...
        'The X36 fixed-route and full-causal pair is incomplete.');
end

sparseRoot = fullfile(outputRoot, 'minimum_causal_backbone');
[sparseReportPath, sparseResult] = ...
    runCausalMinimumFormationBackboneV242FullEpisode(struct( ...
        'presetName', presetName, 'seed', seed, ...
        'referenceResultPath', fullMatPath, ...
        'requirePositiveReference', false, ...
        'resume', resume, 'outputRoot', sparseRoot));
if ~isfield(sparseResult, 'candidate') || ...
        ~isstruct(sparseResult.candidate) || ...
        ~isfield(sparseResult.candidate, 'fullHorizonPositionEospa')
    error('CrossScaleMinimumBackboneV274:MissingSparseArm', ...
        'The X36 V242 arm is incomplete.');
end

v242OverFixed = sparseResult.candidateOverFixedTree;
v242OverFull = sparseResult.candidateOverFullCausal;
materialPassed = ...
    v242OverFixed.fullHorizonEospaGainPercent >= 2 && ...
    v242OverFixed.fullHorizonRmseGainPercent >= 5 && ...
    v242OverFixed.focusConsensusGainPercent >= 0 && ...
    v242OverFixed.attemptedByteSavingPercent >= 5 && ...
    v242OverFixed.minimumFormationEospaGainPercent >= -1 && ...
    v242OverFixed.minimumFormationRmseGainPercent >= -5;

result = struct();
result.contractVersion = ...
    'cross-scale-minimum-backbone-v274-result-v1';
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = presetName;
result.seed = seed;
result.scenePreflight = scene;
result.fullRouteReportPath = fullReportPath;
result.sparseReportPath = sparseReportPath;
result.fixedTree = fullResult.staticDropout;
result.fullCausal = fullResult.causal;
result.minimumBackbone = sparseResult.candidate;
result.fullCausalOverFixed = fullResult.causalOverStaticDropout;
result.minimumBackboneOverFixed = v242OverFixed;
result.minimumBackboneOverFullCausal = v242OverFull;
result.directionPassed = v242OverFixed.meanDirectionPassed && ...
    v242OverFixed.attemptedByteSavingPercent > 0;
result.materialX36ValuePassed = materialPassed;
result.inheritedPaperThresholdPassed = ...
    sparseResult.paperThresholdPassed;
result.nextMethodDecision = decideNextMethod(result);
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.evidenceBoundary = [ ...
    'V274 is one paired complete-episode X36 development result. Fixed ', ...
    'routing, full causal repair and the V242 minimum backbone use the ', ...
    'same scene, measurements, truth, communication schedule, fusion ', ...
    'implementation and filter RNG. The fixed arm is the no-dynamic-', ...
    'routing baseline. This result may establish cross-scale headroom on ', ...
    'the executed case only; it is not multiseed, multistyle, validation ', ...
    'or paper-level evidence.'];

matPath = fullfile(outputRoot, ...
    'CROSS_SCALE_MINIMUM_BACKBONE_V274_FULL_EPISODE.mat');
reportPath = fullfile(outputRoot, ...
    'CROSS_SCALE_MINIMUM_BACKBONE_V274_FULL_EPISODE.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReportFile(reportPath, result);
fprintf('V274 result: %s\n', reportPath);
end

function decision = decideNextMethod(result)
if result.materialX36ValuePassed
    decision = ...
        'freeze-v242-and-run-independent-m24-x36-multistyle-validation';
elseif result.directionPassed
    decision = ...
        'retain-v242-as-cross-scale-incumbent-but-seek-tail-safe-value';
elseif result.fullCausalOverFixed.meanDirectionPassed
    decision = ...
        'dynamic-repair-scales-but-minimum-backbone-removes-useful-inputs';
else
    decision = ...
        'dynamic-formation-tree-repair-does-not-scale-on-this-x36-case';
end
end

function writeReportFile(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CrossScaleMinimumBackboneV274:ReportOpen', ...
        'Could not write the V274 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V274 X36 minimum-backbone baseline\n\n');
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
fprintf(fid, '- Direction / material / inherited paper gate: `%d / %d / %d`\n', ...
    result.directionPassed, result.materialX36ValuePassed, ...
    result.inheritedPaperThresholdPassed);
fprintf(fid, '- Next decision: `%s`\n\n', result.nextMethodDecision);
fprintf(fid, ['| Arm | Full E-OSPA | Full RMSE | Focus consistency | ', ...
    'Attempted bytes | Messages / step |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|:--:|\n');
writeArmRow(fid, 'Fixed formation tree', result.fixedTree);
writeArmRow(fid, 'Full causal repair', result.fullCausal);
writeArmRow(fid, 'V242 minimum causal backbone', ...
    result.minimumBackbone);
fprintf(fid, ['\n| Comparison | E-OSPA | RMSE | Focus consistency | ', ...
    'Attempted-byte saving | Weakest formation E / RMSE |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|:--|\n');
writeGainRow(fid, 'Full causal over fixed', ...
    result.fullCausalOverFixed);
writeGainRow(fid, 'V242 over fixed', ...
    result.minimumBackboneOverFixed);
writeGainRow(fid, 'V242 over full causal', ...
    result.minimumBackboneOverFullCausal);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function writeArmRow(fid, name, arm)
fprintf(fid, '| %s | %.3f | %.3f | %.3f | %.0f | %d--%d |\n', ...
    name, arm.fullHorizonPositionEospa, ...
    arm.fullHorizonPositionRmse, ...
    arm.focusInterFormationPositionOspa, ...
    arm.attemptedPayloadBytes, arm.routeMessageCountMinimum, ...
    arm.routeMessageCountMaximum);
end

function writeGainRow(fid, name, gain)
fprintf(fid, '| %s | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
    name, gain.fullHorizonEospaGainPercent, ...
    gain.fullHorizonRmseGainPercent, ...
    gain.focusConsensusGainPercent, ...
    gain.attemptedByteSavingPercent);
fprintf(fid, '%+.3f%% / %+.3f%% |\n', ...
    gain.minimumFormationEospaGainPercent, ...
    gain.minimumFormationRmseGainPercent);
end

function absolute = isAbsolutePath(path)
absolute = ~isempty(path) && (path(1) == '/' || ...
    ~isempty(regexp(path, '^[A-Za-z]:[\\/]', 'once')));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
