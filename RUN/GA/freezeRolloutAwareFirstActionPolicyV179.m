function [policyPath, reportPath, policy] = ...
        freezeRolloutAwareFirstActionPolicyV179(options)
% FREEZEROLLOUTAWAREFIRSTACTIONPOLICYV179 Freeze the V178 safe selector.

if nargin < 1 || isempty(options)
    options = struct();
end
modelPath = getField(options, 'modelPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v178', 'rollout_aware_model', 'compact_scalar', ...
    'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_MODEL.mat'));
resultPath = getField(options, 'resultPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v178', 'rollout_aware_model', 'compact_scalar', ...
    'NONLINEAR_SAFE_ONE_HOP_ACTION_V168_RESULT.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v179', 'rollout_aware_policy'));
if exist(modelPath, 'file') ~= 2 || exist(resultPath, 'file') ~= 2
    error('RolloutAwarePolicyV179:MissingModel', ...
        'The V178 compact model and result are required.');
end
model = load(modelPath, 'model').model;
result = load(resultPath, 'result').result;
if ~strcmp(model.contractVersion, ...
        'nonlinear-safe-one-hop-label-action-model-v168-v1') || ...
        ~strcmp(model.datasetContractVersion, ...
            'rollout-aggregated-label-action-value-dataset-v178-v1') || ...
        model.featuresUseTruth || ...
        model.numericLabelIdentifiersUsedAsFeatures || ...
        ~result.heldoutSafetyGatePassed || ...
        result.heldout.harmfulCellCount ~= 0 || ...
        result.heldout.selectedCellCount ~= 6 || ...
        any(result.heldout.totalGain <= 0)
    error('RolloutAwarePolicyV179:SafetyGate', ...
        'The V178 compact model did not pass the frozen safety gate.');
end
policy = struct();
policy.contractVersion = ...
    'rollout-aware-first-action-policy-v179-v1';
policy.firstModelPath = modelPath;
policy.secondModelPath = '';
policy.thresholds = struct();
policy.maximumSequentialEdits = 1;
policy.synopsisBytesPerLabel = 24;
policy.featuresUseTruth = false;
policy.numericLabelIdentifiersUsedAsFeatures = false;
policy.preflightGatePassed = true;
policy.efficiencyGatePassed = result.heldoutGatePassed;
policy.heldoutSelectedCellCount = result.heldout.selectedCellCount;
policy.heldoutHarmfulCellCount = result.heldout.harmfulCellCount;
policy.heldoutTotalGain = result.heldout.totalGain;
policy.heldoutJointUtilityCaptureFraction = ...
    result.heldout.jointUtilityCaptureFraction;
policy.recursiveEvaluationRun = false;
policy.deployable = false;
policy.evidenceBoundary = [ ...
    'V179 freezes the compact V178 classifier after it selects one ', ...
    'joint-positive action in each of six V176 t=79 rollout cells. The ', ...
    'older 25-percent utility-capture efficiency gate is not required ', ...
    'for this single recursive safety probe. This is opened same-seed ', ...
    'development authorization only.'];
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
policyPath = fullfile(outputRoot, ...
    'ROLLOUT_AWARE_FIRST_ACTION_POLICY_V179.mat');
reportPath = fullfile(outputRoot, ...
    'ROLLOUT_AWARE_FIRST_ACTION_POLICY_V179.md');
policy.policyPath = policyPath;
policy.reportPath = reportPath;
save('-mat7-binary', policyPath, 'policy');
writeReport(reportPath, policy);
fprintf('V179 rollout-aware policy: %s\n', reportPath);
end

function writeReport(path, policy)
fid = fopen(path, 'w');
if fid < 0
    error('RolloutAwarePolicyV179:ReportOpenFailed', ...
        'Could not open the V179 policy report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V179 rollout-aware first-action policy\n\n');
fprintf(fid, '- Maximum complete-label requests per receiver: `%d`\n', ...
    policy.maximumSequentialEdits);
fprintf(fid, '- Heldout selected / harmful cells: `%d / %d`\n', ...
    policy.heldoutSelectedCellCount, policy.heldoutHarmfulCellCount);
fprintf(fid, '- Heldout immediate E-OSPA / RMSE gain: `%+.4f / %+.4f`\n', ...
    policy.heldoutTotalGain(1), policy.heldoutTotalGain(2));
fprintf(fid, '- Heldout utility capture: `%.3f`\n', ...
    policy.heldoutJointUtilityCaptureFraction);
fprintf(fid, '- Safety / legacy efficiency gate: `%d / %d`\n\n', ...
    policy.preflightGatePassed, policy.efficiencyGatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    policy.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
