function [auditPath, audit] = ...
    auditFormationH3OpenedValueRepresentation(options)
% AUDITFORMATIONH3OPENEDVALUEREPRESENTATION Small-sample LOSO diagnostic.
%
% Compares a direct multi-output ridge model with a structured model whose
% pair value is the sum of two singleton predictions plus a learned residual.
% Every prediction is out-of-state under leave-one-seed-out replay, but all
% five states were already opened.  No fitted model is deployable or frozen.

if nargin < 1 || isempty(options)
    options = struct();
end
datasetPath = getField(options, 'datasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v13', 'opened_dataset', ...
    'formation_h3_opened_development_v1.mat'));
outputDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v13', 'opened_representation_audit'));
lambdaGrid = getField(options, 'lambdaGrid', ...
    [1e-4, 1e-3, 1e-2, 0.1, 1, 10, 100, 1000]);
minimumMeanGainPearson = getField( ...
    options, 'minimumMeanGainPearson', 0.20);
minimumTop3OracleCaptureFraction = getField( ...
    options, 'minimumTop3OracleCaptureFraction', 0.60);
minimumSafeSelectionFraction = getField( ...
    options, 'minimumSafeSelectionFraction', 0.60);
if exist(datasetPath, 'file') ~= 2 || ...
        isempty(lambdaGrid) || any(~isfinite(lambdaGrid)) || ...
        any(lambdaGrid <= 0) || ...
        minimumMeanGainPearson < -1 || ...
        minimumMeanGainPearson > 1 || ...
        minimumTop3OracleCaptureFraction < 0 || ...
        minimumTop3OracleCaptureFraction > 1 || ...
        minimumSafeSelectionFraction < 0 || ...
        minimumSafeSelectionFraction > 1
    error('Formation H=3 representation-audit options are invalid.');
end
loaded = load(datasetPath, 'dataset');
if ~isfield(loaded, 'dataset')
    error('Formation H=3 representation dataset is missing.');
end
dataset = loaded.dataset;
validateDataset(dataset);
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official formation H=3 representation audit requires clean source.');
end

architectures = {'direct', 'additive-pair-residual'};
candidates = repmat(emptyCandidate(), 1, ...
    numel(architectures) * numel(lambdaGrid));
cursor = 0;
for architectureIdx = 1:numel(architectures)
    for lambda = lambdaGrid
        cursor = cursor + 1;
        candidates(cursor) = evaluateCandidate( ...
            dataset, architectures{architectureIdx}, lambda);
        candidates(cursor).architectureOrder = architectureIdx;
        fprintf(['formation H=3 %s lambda %.4g: ', ...
            'NRMSE %.3f, mean-r %.3f, top3 %.1f%%, ', ...
            'safe selection %.1f%%, selected gain %+.3f%%\n'], ...
            architectures{architectureIdx}, lambda, ...
            candidates(cursor).meanNormalizedRmse, ...
            candidates(cursor).targetPearson(1), ...
            100 * candidates(cursor).top3OracleCaptureFraction, ...
            100 * candidates(cursor).safeSelectionFraction, ...
            candidates(cursor).meanSelectedRealizedGainPercent);
    end
end
keys = zeros(numel(candidates), 6);
for idx = 1:numel(candidates)
    item = candidates(idx);
    keys(idx, :) = [ ...
        item.meanNormalizedRmse, ...
        -item.top3OracleCaptureFraction, ...
        -item.safeSelectionFraction, ...
        -item.targetPearson(1), ...
        item.architectureOrder, log10(item.lambda)];
end
[~, order] = sortrows(keys);
candidates = candidates(order);
selected = candidates(1);
smallSamplePredictiveSignalGatePassed = ...
    selected.targetPearson(1) >= minimumMeanGainPearson - 1e-12 && ...
    selected.top3OracleCaptureFraction >= ...
        minimumTop3OracleCaptureFraction - 1e-12 && ...
    selected.safeSelectionFraction >= ...
        minimumSafeSelectionFraction - 1e-12 && ...
    selected.meanSelectedRealizedGainPercent >= -1e-12;

audit = struct();
audit.contractVersion = ...
    'formation-h3-opened-value-representation-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.datasetPath = datasetPath;
audit.datasetSha256 = computeFileSha256(datasetPath);
audit.datasetGenerationCommit = dataset.generationGitCommit;
audit.featureContractVersion = dataset.featureContractVersion;
audit.targetNames = dataset.targetNames;
audit.lambdaGrid = lambdaGrid;
audit.candidates = candidates;
audit.selected = selected;
audit.minimumMeanGainPearson = minimumMeanGainPearson;
audit.minimumTop3OracleCaptureFraction = ...
    minimumTop3OracleCaptureFraction;
audit.minimumSafeSelectionFraction = minimumSafeSelectionFraction;
audit.smallSamplePredictiveSignalGatePassed = ...
    smallSamplePredictiveSignalGatePassed;
audit.scaledTeacherDatasetDesignAuthorized = ...
    dataset.deploymentPositiveStateCount >= 3 && ...
    dataset.deploymentStrongStateCount >= 2 && ...
    dataset.meanDeploymentOracleGainPercent >= 2 && ...
    dataset.featureCount > 0;
audit.finalModelTrainingAuthorized = false;
audit.messagePassingModelAuthorized = false;
audit.validationClaimAllowed = false;
audit.openedDevelopmentEvidenceOnly = true;
audit.evidenceBoundary = [ ...
    'All feature choices, states, and outcomes are opened. LOSO ', ...
    'only tests whether the invariant representation contains a ', ...
    'small-sample predictive signal and whether explicit pair ', ...
    'residuals help. The fitted ridge heads are not deployable; ', ...
    'disjoint multi-scale teacher data and calibration are required ', ...
    'before final model training, GNN escalation, or validation.'];

if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
auditPath = getField(options, 'outputPath', fullfile( ...
    outputDirectory, ...
    'formation_h3_opened_value_representation_audit_v1.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    outputDirectory, ...
    'FORMATION_H3_OPENED_VALUE_REPRESENTATION_AUDIT_V1.md'));
audit.auditPath = auditPath;
audit.reportPath = reportPath;
save('-mat7-binary', auditPath, 'audit');
writeReport(reportPath, audit);
fprintf('Formation H=3 representation audit: %s\nReport: %s\n', ...
    auditPath, reportPath);
end

function candidate = evaluateCandidate(dataset, architecture, lambda)
blockCount = numel(dataset.blocks);
predictions = cell(1, blockCount);
for heldoutIdx = 1:blockCount
    fitIndices = setdiff(1:blockCount, heldoutIdx, 'stable');
    model = fitArchitecture( ...
        dataset.blocks(fitIndices), architecture, lambda);
    predictions{heldoutIdx} = predictBlock( ...
        model, dataset.blocks(heldoutIdx));
end
[targetRmse, targetNormalizedRmse, targetPearson, rows] = ...
    summarizePredictions(dataset.blocks, predictions);
candidate = emptyCandidate();
candidate.architecture = architecture;
candidate.lambda = lambda;
candidate.targetRmse = targetRmse;
candidate.targetNormalizedRmse = targetNormalizedRmse;
candidate.targetPearson = targetPearson;
candidate.meanNormalizedRmse = mean(targetNormalizedRmse);
candidate.rows = rows;
candidate.top1OracleCaptureFraction = ...
    mean([rows.oracleMeanRank] <= 1);
candidate.top3OracleCaptureFraction = ...
    mean([rows.oracleMeanRank] <= 3);
candidate.safeSelectionFraction = ...
    mean([rows.selectedRealizedSafe]);
candidate.dynamicSelectionFraction = ...
    mean([rows.selectedActionIndex] ~= 1);
candidate.meanSelectedRealizedGainPercent = ...
    mean([rows.selectedRealizedGainPercent]);
candidate.positiveSelectedStateFraction = ...
    mean([rows.selectedRealizedGainPercent] > 1e-12);
end

function model = fitArchitecture(blocks, architecture, lambda)
model = struct('architecture', architecture, 'lambda', lambda);
switch architecture
    case 'direct'
        [X, Y] = collectRows(blocks, 'all');
        model.direct = fitRidge(X, Y, lambda);
    case 'additive-pair-residual'
        [localX, localY] = collectRows(blocks, 'local');
        [pairX, pairResidual] = collectRows(blocks, 'pair-residual');
        model.local = fitRidge(localX, localY, lambda);
        model.residual = fitRidge(pairX, pairResidual, lambda);
    otherwise
        error('Unknown formation H=3 representation architecture.');
end
end

function prediction = predictBlock(model, block)
switch model.architecture
    case 'direct'
        prediction = predictRidge(model.direct, block.features);
    case 'additive-pair-residual'
        prediction = zeros(size(block.targets));
        localMask = block.interventionOrder <= 1;
        prediction(localMask, :) = predictRidge( ...
            model.local, block.features(localMask, :));
        pairIndices = find(block.interventionOrder == 2);
        residual = predictRidge( ...
            model.residual, block.features(pairIndices, :));
        for cursor = 1:numel(pairIndices)
            actionIdx = pairIndices(cursor);
            formations = block.formationIndicesAuditOnly(actionIdx, :);
            singletonIndices = matchingSingletons(block, ...
                formations, block.trustWeights(actionIdx));
            prediction(actionIdx, :) = ...
                sum(prediction(singletonIndices, :), 1) + ...
                residual(cursor, :);
        end
end
referenceIdx = find(block.interventionOrder == 0);
if numel(referenceIdx) ~= 1
    error('Formation H=3 block lacks a unique reference action.');
end
prediction(referenceIdx, :) = 0;
if any(~isfinite(prediction(:)))
    error('Formation H=3 LOSO prediction is non-finite.');
end
end

function indices = matchingSingletons(block, formations, trust)
indices = zeros(1, 2);
for cursor = 1:2
    match = find(block.interventionOrder == 1 & ...
        block.formationIndicesAuditOnly(:, 1)' == formations(cursor) & ...
        abs(block.trustWeights - trust) <= 1e-12);
    if numel(match) ~= 1
        error('Formation H=3 pair lacks a unique singleton action.');
    end
    indices(cursor) = match;
end
end

function [X, Y] = collectRows(blocks, mode)
X = zeros(0, size(blocks(1).features, 2));
Y = zeros(0, size(blocks(1).targets, 2));
for block = blocks
    switch mode
        case 'all'
            mask = true(size(block.features, 1), 1);
            target = block.targets;
        case 'local'
            mask = block.interventionOrder <= 1;
            target = block.targets;
        case 'pair-residual'
            mask = block.interventionOrder == 2;
            target = block.interactionResidualTargets;
        otherwise
            error('Unknown formation H=3 row collection mode.');
    end
    X = [X; block.features(mask, :)]; %#ok<AGROW>
    Y = [Y; target(mask, :)]; %#ok<AGROW>
end
end

function model = fitRidge(X, Y, lambda)
if isempty(X) || size(X, 1) ~= size(Y, 1) || ...
        any(~isfinite(X(:))) || any(~isfinite(Y(:)))
    error('Formation H=3 ridge training rows are invalid.');
end
xMean = mean(X, 1);
xScale = std(X, 0, 1);
xScale(~isfinite(xScale) | xScale < 1e-12) = 1;
yMean = mean(Y, 1);
yScale = std(Y, 0, 1);
yScale(~isfinite(yScale) | yScale < 1e-12) = 1;
Xn = bsxfun(@rdivide, bsxfun(@minus, X, xMean), xScale);
Yn = bsxfun(@rdivide, bsxfun(@minus, Y, yMean), yScale);
design = [ones(size(Xn, 1), 1), Xn];
regularizer = diag([0, ones(1, size(Xn, 2))]);
coefficients = (design' * design + lambda * regularizer) \ ...
    (design' * Yn);
model = struct( ...
    'xMean', xMean, 'xScale', xScale, ...
    'yMean', yMean, 'yScale', yScale, ...
    'coefficients', coefficients);
end

function prediction = predictRidge(model, X)
Xn = bsxfun(@rdivide, ...
    bsxfun(@minus, X, model.xMean), model.xScale);
normalized = [ones(size(Xn, 1), 1), Xn] * ...
    model.coefficients;
prediction = bsxfun(@plus, ...
    bsxfun(@times, normalized, model.yScale), model.yMean);
end

function [rmse, normalizedRmse, correlation, rows] = ...
    summarizePredictions(blocks, predictions)
allTarget = zeros(0, size(blocks(1).targets, 2));
allPrediction = allTarget;
rows = repmat(emptyRow(), 1, numel(blocks));
for blockIdx = 1:numel(blocks)
    block = blocks(blockIdx);
    prediction = predictions{blockIdx};
    nonreference = block.interventionOrder > 0;
    allTarget = [allTarget; block.targets(nonreference, :)]; %#ok<AGROW>
    allPrediction = [ ...
        allPrediction; prediction(nonreference, :)]; %#ok<AGROW>
    [~, predictedOrder] = sort(prediction(:, 1), 'descend');
    oracleRank = find(predictedOrder == ...
        block.oracleDeploymentActionIndex, 1);
    predictedFeasible = all(prediction >= 0, 2);
    referenceIdx = find(block.interventionOrder == 0, 1);
    predictedFeasible(referenceIdx) = true;
    feasibleIndices = find(predictedFeasible);
    [~, localBest] = max(prediction(feasibleIndices, 1));
    selectedIdx = feasibleIndices(localBest);
    realized = block.targets(selectedIdx, :);
    row = emptyRow();
    row.seed = block.seed;
    row.currentTime = block.currentTime;
    row.oracleActionIndex = block.oracleDeploymentActionIndex;
    row.oracleActionName = block.oracleDeploymentActionName;
    row.oracleMeanRank = oracleRank;
    row.selectedActionIndex = selectedIdx;
    row.selectedActionName = block.actionNames{selectedIdx};
    row.selectedPredictedGainPercent = prediction(selectedIdx, 1);
    row.selectedRealizedGainPercent = realized(1);
    row.selectedRealizedSafe = all(realized >= -1e-12);
    rows(blockIdx) = row;
end
errorValues = allPrediction - allTarget;
rmse = sqrt(mean(errorValues.^2, 1));
targetScale = std(allTarget, 0, 1);
targetScale(~isfinite(targetScale) | targetScale < 1e-12) = 1;
normalizedRmse = rmse ./ targetScale;
correlation = zeros(1, size(allTarget, 2));
for targetIdx = 1:size(allTarget, 2)
    correlation(targetIdx) = pearson( ...
        allPrediction(:, targetIdx), allTarget(:, targetIdx));
end
end

function value = pearson(left, right)
left = left(:) - mean(left);
right = right(:) - mean(right);
denominator = norm(left) * norm(right);
if denominator <= eps
    value = 0;
else
    value = (left' * right) / denominator;
end
end

function validateDataset(dataset)
required = { ...
    'contractVersion', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'featureContractVersion', ...
    'featureNames', 'targetNames', 'blocks', ...
    'deploymentPositiveStateCount', ...
    'deploymentStrongStateCount', ...
    'meanDeploymentOracleGainPercent', ...
    'featuresUseTruth', 'featuresUseFutureMeasurements', ...
    'featuresUseFutureOutcome', 'targetsUseTruth', ...
    'targetsUseFutureMeasurements', ...
    'openedDevelopmentEvidenceOnly', ...
    'finalModelTrainingAuthorized', 'validationClaimAllowed'};
if ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.contractVersion, ...
            'formation-h3-opened-development-dataset-v1') || ...
        dataset.generationTrackedWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureMeasurements || ...
        dataset.featuresUseFutureOutcome || ...
        ~dataset.targetsUseTruth || ...
        ~dataset.targetsUseFutureMeasurements || ...
        ~dataset.openedDevelopmentEvidenceOnly || ...
        dataset.finalModelTrainingAuthorized || ...
        dataset.validationClaimAllowed || ...
        numel(dataset.blocks) ~= 5
    error('Formation H=3 representation dataset contract failed.');
end
for block = dataset.blocks
    if size(block.features, 2) ~= numel(dataset.featureNames) || ...
            size(block.targets, 2) ~= numel(dataset.targetNames) || ...
            size(block.features, 1) ~= size(block.targets, 1) || ...
            any(~isfinite(block.features(:))) || ...
            any(~isfinite(block.targets(:))) || ...
            block.featuresUseTruth || ...
            block.featuresUseFutureOutcome
        error('Formation H=3 representation block is invalid.');
    end
end
end

function candidate = emptyCandidate()
candidate = struct( ...
    'architecture', '', 'architectureOrder', NaN, 'lambda', NaN, ...
    'targetRmse', zeros(1, 0), ...
    'targetNormalizedRmse', zeros(1, 0), ...
    'targetPearson', zeros(1, 0), ...
    'meanNormalizedRmse', NaN, 'rows', repmat(emptyRow(), 1, 0), ...
    'top1OracleCaptureFraction', NaN, ...
    'top3OracleCaptureFraction', NaN, ...
    'safeSelectionFraction', NaN, ...
    'dynamicSelectionFraction', NaN, ...
    'meanSelectedRealizedGainPercent', NaN, ...
    'positiveSelectedStateFraction', NaN);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, 'currentTime', NaN, ...
    'oracleActionIndex', NaN, 'oracleActionName', '', ...
    'oracleMeanRank', NaN, 'selectedActionIndex', NaN, ...
    'selectedActionName', '', ...
    'selectedPredictedGainPercent', NaN, ...
    'selectedRealizedGainPercent', NaN, ...
    'selectedRealizedSafe', false);
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 representation report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
selected = audit.selected;
fprintf(fid, '# Formation H=3 opened value-representation audit\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Dataset SHA-256: `%s`\n', audit.datasetSha256);
fprintf(fid, '- Selected architecture / lambda: `%s / %.4g`\n', ...
    selected.architecture, selected.lambda);
fprintf(fid, '- Mean normalized RMSE: `%.4f`\n', ...
    selected.meanNormalizedRmse);
fprintf(fid, '- Mean-gain Pearson: `%+.4f` (gate `%+.2f`)\n', ...
    selected.targetPearson(1), audit.minimumMeanGainPearson);
fprintf(fid, '- Oracle top-1 / top-3 capture: `%.1f%% / %.1f%%`\n', ...
    100 * selected.top1OracleCaptureFraction, ...
    100 * selected.top3OracleCaptureFraction);
fprintf(fid, '- Raw predicted-constraint safe selection: `%.1f%%`\n', ...
    100 * selected.safeSelectionFraction);
fprintf(fid, '- Mean selected realized gain: `%+.3f%%`\n', ...
    selected.meanSelectedRealizedGainPercent);
fprintf(fid, '- Small-sample predictive signal gate: `%d`\n', ...
    audit.smallSamplePredictiveSignalGatePassed);
fprintf(fid, '- Scaled teacher-dataset design authorized: `%d`\n', ...
    audit.scaledTeacherDatasetDesignAuthorized);
fprintf(fid, '- Final model / GNN / validation authorized: `%d / %d / %d`\n\n', ...
    audit.finalModelTrainingAuthorized, ...
    audit.messagePassingModelAuthorized, ...
    audit.validationClaimAllowed);

fprintf(fid, '| Architecture | Lambda | NRMSE | Mean r | Top-3 | Safe select | Realized gain |\n');
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|\n');
for candidate = audit.candidates
    fprintf(fid, '| `%s` | %.4g | %.3f | %+.3f | %.1f%% | %.1f%% | %+.3f%% |\n', ...
        candidate.architecture, candidate.lambda, ...
        candidate.meanNormalizedRmse, candidate.targetPearson(1), ...
        100 * candidate.top3OracleCaptureFraction, ...
        100 * candidate.safeSelectionFraction, ...
        candidate.meanSelectedRealizedGainPercent);
end

fprintf(fid, '\n## Selected target diagnostics\n\n');
fprintf(fid, '| Target | RMSE | Normalized RMSE | Pearson |\n');
fprintf(fid, '|:--|--:|--:|--:|\n');
for targetIdx = 1:numel(audit.targetNames)
    fprintf(fid, '| `%s` | %.4f | %.4f | %+.4f |\n', ...
        audit.targetNames{targetIdx}, ...
        selected.targetRmse(targetIdx), ...
        selected.targetNormalizedRmse(targetIdx), ...
        selected.targetPearson(targetIdx));
end

fprintf(fid, '\n## Selected LOSO decisions\n\n');
fprintf(fid, '| Seed-time | Oracle | Rank | Selected | Predicted | Realized | Safe |\n');
fprintf(fid, '|:--|:--|--:|:--|--:|--:|:--:|\n');
for row = selected.rows
    fprintf(fid, '| `%d-%d` | `%s` | %d | `%s` | %+.3f%% | %+.3f%% | %d |\n', ...
        row.seed, row.currentTime, row.oracleActionName, ...
        row.oracleMeanRank, row.selectedActionName, ...
        row.selectedPredictedGainPercent, ...
        row.selectedRealizedGainPercent, ...
        row.selectedRealizedSafe);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
