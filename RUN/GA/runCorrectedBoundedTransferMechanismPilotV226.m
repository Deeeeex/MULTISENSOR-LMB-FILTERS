function [reportPath, result] = ...
        runCorrectedBoundedTransferMechanismPilotV226(options)
% RUNCORRECTEDBOUNDEDTRANSFERMECHANISMPILOTV226 One-click paired pilot.
%
% The pilot consumes a canonical-mixture V214 trajectory, captures one
% ordinary current-physical reference plus all one-page donor-withholding
% arms, selects a small teacher-ranked donor set, builds causal V220 label
% banks, and evaluates V226 against both the ordinary reference and its
% paired donor-only arm.  This is mechanism evidence; it does not include
% the fixed-static-route baseline required by the end-to-end paper claim.

if nargin < 1 || isempty(options)
    options = struct();
end
v226 = getBoundedDominantEdgeTransferV226Protocol();
base = getDirectGraphPayloadRepairControllerV214Protocol();
presetName = char(getField(options, ...
    'presetName', 'x36-formation-fov'));
seed = getField(options, 'seed', 1301);
splitName = char(getField(options, 'splitName', 'training'));
trajectoryRoot = char(getField(options, 'trajectoryRoot', fullfile( ...
    base.outputRoot, 'trajectory_collection', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
trajectoryPath = fullfile(trajectoryRoot, ...
    'DIRECT_GRAPH_TRAJECTORY_V214.mat');
windowIndices = reshape(getField( ...
    options, 'windowIndices', zeros(1, 0)), 1, []);
donorLimit = getField(options, 'donorLimit', 2);
candidateLimitPerDonor = getField( ...
    options, 'candidateLimitPerDonor', 3);
topPerMode = getField(options, 'topPerMode', 1);
maximumBeneficiaries = getField(options, ...
    'maximumBeneficiaries', 2);
reuseExistingDonorScreens = logical(getField( ...
    options, 'reuseExistingDonorScreens', true));
outputRoot = char(getField(options, 'outputRoot', fullfile( ...
    v226.outputRoot, 'corrected_mechanism_pilot', splitName, ...
    sprintf('%s_seed%d', strrep(presetName, '-', '_'), seed))));
if exist(trajectoryPath, 'file') ~= 2 || ...
        ~validPositiveInteger(seed) || ...
        ~validPositiveInteger(donorLimit) || ...
        ~validPositiveInteger(candidateLimitPerDonor) || ...
        ~validPositiveInteger(topPerMode) || ...
        ~validPositiveInteger(maximumBeneficiaries) || ...
        ~isscalar(reuseExistingDonorScreens)
    error('CorrectedBoundedTransferV226:InvalidRequest', ...
        ['A completed corrected trajectory and positive frozen pilot ', ...
         'limits are required.']);
end

loaded = load(trajectoryPath, 'result');
trajectory = loaded.result;
validateTrajectory(trajectory, presetName, seed, splitName);
if isempty(windowIndices)
    windowIndices = 1:numel(trajectory.selectedTimes);
elseif any(~isfinite(windowIndices)) || ...
        any(windowIndices ~= round(windowIndices)) || ...
        any(windowIndices < 1) || ...
        any(windowIndices > numel(trajectory.selectedTimes)) || ...
        numel(unique(windowIndices)) ~= numel(windowIndices)
    error('CorrectedBoundedTransferV226:WindowSubset', ...
        'Window indices must be unique entries in the trajectory.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('CorrectedBoundedTransferV226:DirtySource', ...
        'The official corrected V226 pilot requires clean source.');
end
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

states = repmat(emptyState(), 1, numel(windowIndices));
best = emptyBest();
bestScore = -inf;
for statePosition = 1:numel(windowIndices)
    windowIndex = windowIndices(statePosition);
    currentTime = trajectory.selectedTimes(windowIndex);
    stateRoot = fullfile(outputRoot, sprintf( ...
        'w%02d_t%d', windowIndex, currentTime));
    donorRoot = fullfile(stateRoot, 'donor_capture');
    donorResult = loadOrRunDonorCapture( ...
        trajectoryRoot, presetName, seed, splitName, windowIndex, ...
        donorRoot, reuseExistingDonorScreens, gitState.commit);
    sourceScreenPath = donorResult.screenMatPath;
    screenLoaded = load(sourceScreenPath, 'screen');
    sourceScreen = screenLoaded.screen;
    donorRecords = sourceScreen.records( ...
        [sourceScreen.records.actionIndex] ~= ...
            sourceScreen.bank.referenceActionIndex);
    [selectedDonorIds, selectedDonorScores] = ...
        selectTeacherDonors(donorRecords, donorLimit);

    donorRuns = repmat(emptyDonorRun(), 1, numel(selectedDonorIds));
    for donorPosition = 1:numel(selectedDonorIds)
        donorFormationId = selectedDonorIds(donorPosition);
        leaf = sprintf('donor_f%d', donorFormationId);
        [~, bank] = buildDecoupledSemanticShortcutCandidateBankV220( ...
            struct('sourceScreenPath', sourceScreenPath, ...
                'donorFormationId', donorFormationId, ...
                'topPerMode', topPerMode, ...
                'maximumBeneficiaries', maximumBeneficiaries, ...
                'outputRoot', fullfile(stateRoot, leaf, ...
                    'candidate_bank')));
        selectedRecordIndices = selectCausalCandidateRows( ...
            bank, candidateLimitPerDonor);
        boundedResult = emptyBoundedResult();
        if ~isempty(selectedRecordIndices)
            [~, boundedResult] = ...
                runBoundedDominantEdgeTransferH3V226(struct( ...
                    'candidateBankPath', bank.matPath, ...
                    'recordIndices', selectedRecordIndices, ...
                    'outputRoot', fullfile(stateRoot, leaf, ...
                        'bounded_transfer_h3')));
            [best, bestScore] = updateBest( ...
                best, bestScore, boundedResult, ...
                windowIndex, currentTime, donorFormationId, base.risk);
        end
        item = emptyDonorRun();
        item.donorFormationId = donorFormationId;
        item.teacherDonorScore = selectedDonorScores(donorPosition);
        item.candidateBankPath = bank.matPath;
        item.creditFeasibleCandidateCount = ...
            bank.creditFeasibleCount;
        item.selectedRecordIndices = selectedRecordIndices;
        item.boundedResultPath = getField( ...
            boundedResult, 'matPath', '');
        item.records = getField( ...
            boundedResult, 'records', repmat(emptyV226Record(), 1, 0));
        donorRuns(donorPosition) = item;
    end

    state = emptyState();
    state.windowIndex = windowIndex;
    state.currentTime = currentTime;
    state.sourceScreenPath = sourceScreenPath;
    state.selectedDonorFormationIds = selectedDonorIds;
    state.selectedDonorScores = selectedDonorScores;
    state.donorRuns = donorRuns;
    states(statePosition) = state;
end

result = struct();
result.contractVersion = ...
    'corrected-bounded-transfer-mechanism-pilot-v226-v1';
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.trajectoryPath = trajectoryPath;
result.trajectoryGenerationGitCommit = ...
    trajectory.generationGitCommit;
result.presetName = presetName;
result.seed = seed;
result.splitName = splitName;
result.windowIndices = windowIndices;
result.donorLimit = donorLimit;
result.candidateLimitPerDonor = candidateLimitPerDonor;
result.topPerMode = topPerMode;
result.maximumBeneficiaries = maximumBeneficiaries;
result.states = states;
result.best = best;
result.anyJointTailSafeBytePositiveCandidate = best.present;
result.referenceArm = ...
    'direct-graph-current-physical-reference-v214-v1';
result.fixedStaticRouteBaselineIncluded = false;
result.endToEndStaticBaselineClaimAllowed = false;
result.truthUsedForDonorSelection = true;
result.truthUsedForCandidateRowSelection = false;
result.truthUsedAtRuntime = false;
result.futureInformationUsedAtRuntime = false;
result.validationClaimAllowed = false;
result.evidenceBoundary = [ ...
    'This corrected-code pilot is a paired H=3 mechanism screen. ', ...
    'Donors are teacher-ranked with realized H=3 outcomes; beneficiary, ', ...
    'source, label and shortlist features are current-state causal. ', ...
    'The ordinary reference is the V214 current-physical route, not the ', ...
    'fixed static route required by the end-to-end paper comparison. ', ...
    'A positive pilot authorizes policy design only; it is not deployment, ', ...
    'generalization or paper-level evidence.'];
matPath = fullfile(outputRoot, ...
    'CORRECTED_BOUNDED_TRANSFER_MECHANISM_PILOT_V226.mat');
reportPath = fullfile(outputRoot, ...
    'CORRECTED_BOUNDED_TRANSFER_MECHANISM_PILOT_V226.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('Corrected V226 mechanism pilot: %s\n', reportPath);
end

function donorResult = loadOrRunDonorCapture( ...
        trajectoryRoot, presetName, seed, splitName, windowIndex, ...
        outputRoot, reuseExisting, currentCommit)
resultPath = fullfile(outputRoot, ...
    'DIRECT_GRAPH_FORMATION_WITHHOLDING_H3_V214.mat');
if reuseExisting && exist(resultPath, 'file') == 2
    loaded = load(resultPath, 'result');
    donorResult = loaded.result;
    if reusableDonorCapture(donorResult, currentCommit)
        return;
    end
end
[~, donorResult] = runDirectGraphFormationWithholdingH3V214(struct( ...
    'presetName', presetName, 'seed', seed, ...
    'splitName', splitName, 'windowIndex', windowIndex, ...
    'trajectoryRoot', trajectoryRoot, 'outputRoot', outputRoot, ...
    'capturePosteriorSnapshotsEnabled', true, ...
    'captureFusedPosteriorSnapshotsEnabled', true));
if ~reusableDonorCapture(donorResult, currentCommit)
    error('CorrectedBoundedTransferV226:DonorCaptureReadback', ...
        'The generated donor capture failed its provenance check.');
end
end

function reusable = reusableDonorCapture(result, currentCommit)
reusable = false;
required = {'contractVersion', 'screenMatPath', ...
    'capturePosteriorSnapshotsEnabled', ...
    'captureFusedPosteriorSnapshotsEnabled'};
if ~isstruct(result) || ~isscalar(result) || ...
        any(~isfield(result, required)) || ...
        ~strcmp(result.contractVersion, ...
            'direct-graph-formation-withholding-h3-v214-v1') || ...
        ~result.capturePosteriorSnapshotsEnabled || ...
        ~result.captureFusedPosteriorSnapshotsEnabled || ...
        exist(result.screenMatPath, 'file') ~= 2
    return;
end
loaded = load(result.screenMatPath, 'screen');
screen = loaded.screen;
if ~isfield(screen, 'generationGitCommit') || ...
        ~strcmp(screen.generationGitCommit, currentCommit) || ...
        ~screen.capturePosteriorSnapshotsEnabled || ...
        ~screen.captureFusedPosteriorSnapshotsEnabled
    return;
end
reusable = true;
end

function [formationIds, scores] = ...
        selectTeacherDonors(records, donorLimit)
if isempty(records)
    error('CorrectedBoundedTransferV226:MissingDonorArms', ...
        'The donor capture contains no withholding arms.');
end
scoresAll = -inf(1, numel(records));
formationIdsAll = zeros(1, numel(records));
for idx = 1:numel(records)
    record = records(idx);
    if numel(record.formationIndices) ~= 1 || ...
            ~validPositiveInteger(record.formationIndices)
        error('CorrectedBoundedTransferV226:DonorFormation', ...
            'Every withholding arm must identify one formation.');
    end
    formationIdsAll(idx) = record.formationIndices;
    values = [record.meanGainPercent, record.rmseGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent];
    if all(isfinite(values)) && record.attemptedByteSavingPercent > 0
        scoresAll(idx) = min(values);
    end
end
orderTable = [-scoresAll(:), formationIdsAll(:)];
[~, order] = sortrows(orderTable, [1, 2]);
keep = order(1:min(donorLimit, numel(order)));
formationIds = formationIdsAll(keep);
scores = scoresAll(keep);
end

function recordIndices = selectCausalCandidateRows(bank, limit)
feasible = find(bank.creditFeasibleMask);
if isempty(feasible)
    recordIndices = zeros(1, 0);
    return;
end
score = -inf(1, numel(feasible));
bytes = inf(1, numel(feasible));
recordIds = zeros(1, numel(feasible));
for position = 1:numel(feasible)
    record = bank.records(feasible(position));
    score(position) = record.candidate.minimumRiskReduction;
    bytes(position) = record.payloadAttemptedBytes;
    recordIds(position) = record.recordIndex;
end
orderTable = [-score(:), bytes(:), recordIds(:)];
[~, order] = sortrows(orderTable, [1, 2, 3]);
keep = order(1:min(limit, numel(order)));
recordIndices = recordIds(keep);
end

function [best, bestScore] = updateBest( ...
        best, bestScore, boundedResult, windowIndex, currentTime, ...
        donorFormationId, risk)
for record = boundedResult.records
    gains = reshape(record.jointGainVectorPercent, 1, []);
    eligible = numel(gains) == numel(risk.tolerancePercent) && ...
        all(isfinite(gains)) && ...
        all(gains >= risk.tolerancePercent - 1e-12) && ...
        record.jointCorePositive && record.byteConservationPassed;
    if ~eligible
        continue;
    end
    score = min([gains(1:4), record.attemptedByteSavingPercent]);
    if score > bestScore
        bestScore = score;
        best.present = true;
        best.windowIndex = windowIndex;
        best.currentTime = currentTime;
        best.donorFormationId = donorFormationId;
        best.recordIndex = record.recordIndex;
        best.sourceId = record.sourceId;
        best.label = record.label;
        best.beneficiaryFormationId = ...
            record.beneficiaryFormationId;
        best.jointGainVectorPercent = gains;
        best.attemptedByteSavingPercent = ...
            record.attemptedByteSavingPercent;
        best.score = score;
        best.screenPath = record.screenPath;
    end
end
end

function validateTrajectory(trajectory, presetName, seed, splitName)
required = {'contractVersion', 'generationGitCommit', 'presetName', ...
    'seed', 'splitName', 'selectedTimes', 'cachePaths', ...
    'posteriorCounterfactualEnumerationUsed'};
if ~isstruct(trajectory) || ~isscalar(trajectory) || ...
        any(~isfield(trajectory, required)) || ...
        ~strcmp(trajectory.contractVersion, ...
            'direct-graph-trajectory-v214-v1') || ...
        ~strcmp(trajectory.presetName, presetName) || ...
        trajectory.seed ~= seed || ...
        ~strcmp(trajectory.splitName, splitName) || ...
        trajectory.posteriorCounterfactualEnumerationUsed || ...
        isempty(trajectory.selectedTimes) || ...
        numel(trajectory.selectedTimes) ~= numel(trajectory.cachePaths)
    error('CorrectedBoundedTransferV226:TrajectoryProvenance', ...
        'The selected trajectory does not satisfy the V214 contract.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('CorrectedBoundedTransferV226:WriteReport', ...
        'Could not write the corrected V226 pilot report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Corrected V226 bounded-transfer mechanism pilot\n\n');
fprintf(fid, '- Scene / seed / split: `%s / %d / %s`\n', ...
    result.presetName, result.seed, result.splitName);
fprintf(fid, '- Source / pilot commits: `%s / %s`\n', ...
    result.trajectoryGenerationGitCommit, result.generationGitCommit);
fprintf(fid, '- Ordinary reference: `%s`\n', result.referenceArm);
fprintf(fid, '- Fixed static-route baseline included: `%d`\n', ...
    result.fixedStaticRouteBaselineIncluded);
fprintf(fid, '- Any joint tail-safe byte-positive candidate: `%d`\n\n', ...
    result.anyJointTailSafeBytePositiveCandidate);
fprintf(fid, ['| Window | Donor | Row | Beneficiary | Source / label | ', ...
    'Joint E / R / C / terminal | Worst sensor E / R | ', ...
    'Minimum formation E / R | Byte saving | Gate |\n']);
fprintf(fid, '|--:|--:|--:|--:|:--|:--|:--|:--|--:|:--:|\n');
for state = result.states
    for donor = state.donorRuns
        for record = donor.records
            gains = record.jointGainVectorPercent;
            gate = record.jointCorePositive && ...
                record.byteConservationPassed;
            fprintf(fid, ...
                ['| %d (t=%d) | F%d | %d | F%d | S%d / `[%d,%d]` | ', ...
                 '`%+.3f / %+.3f / %+.3f / %+.3f%%` | ', ...
                 '`%+.3f / %+.3f%%` | `%+.3f / %+.3f%%` | ', ...
                 '%+.3f%% | %d |\n'], ...
                state.windowIndex, state.currentTime, ...
                donor.donorFormationId, record.recordIndex, ...
                record.beneficiaryFormationId, record.sourceId, ...
                record.label(1), record.label(2), gains(1), gains(2), ...
                gains(3), gains(4), gains(9), gains(10), ...
                gains(11), gains(12), ...
                record.attemptedByteSavingPercent, gate);
        end
    end
end
if result.best.present
    fprintf(fid, '\n## Best bounded candidate\n\n');
    fprintf(fid, ...
        ['Window %d at t=%d, donor F%d, beneficiary F%d, ', ...
         'S%d / `[%d,%d]`, byte saving `%+.3f%%`.\n'], ...
        result.best.windowIndex, result.best.currentTime, ...
        result.best.donorFormationId, ...
        result.best.beneficiaryFormationId, result.best.sourceId, ...
        result.best.label(1), result.best.label(2), ...
        result.best.attemptedByteSavingPercent);
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyState()
value = struct('windowIndex', 0, 'currentTime', 0, ...
    'sourceScreenPath', '', ...
    'selectedDonorFormationIds', zeros(1, 0), ...
    'selectedDonorScores', zeros(1, 0), ...
    'donorRuns', repmat(emptyDonorRun(), 1, 0));
end

function value = emptyDonorRun()
value = struct('donorFormationId', 0, 'teacherDonorScore', -inf, ...
    'candidateBankPath', '', 'creditFeasibleCandidateCount', 0, ...
    'selectedRecordIndices', zeros(1, 0), ...
    'boundedResultPath', '', ...
    'records', repmat(emptyV226Record(), 1, 0));
end

function value = emptyBoundedResult()
value = struct('matPath', '', ...
    'records', repmat(emptyV226Record(), 1, 0));
end

function value = emptyV226Record()
value = struct('recordIndex', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'jointGainVectorPercent', zeros(1, 12), ...
    'attemptedByteSavingPercent', 0, ...
    'jointCorePositive', false, ...
    'byteConservationPassed', false, 'screenPath', '');
end

function value = emptyBest()
value = struct('present', false, 'windowIndex', 0, ...
    'currentTime', 0, 'donorFormationId', 0, ...
    'beneficiaryFormationId', 0, 'recordIndex', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), ...
    'jointGainVectorPercent', zeros(1, 12), ...
    'attemptedByteSavingPercent', 0, ...
    'score', -inf, 'screenPath', '');
end

function valid = validPositiveInteger(value)
valid = isnumeric(value) && isscalar(value) && isfinite(value) && ...
    value >= 1 && value == round(value);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
