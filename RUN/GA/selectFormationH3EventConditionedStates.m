function [reportPath, manifest] = ...
    selectFormationH3EventConditionedStates( ...
        presetName, seed, options)
% SELECTFORMATIONH3EVENTCONDITIONEDSTATES Truth-free M24 event screen.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getFormationH3EventConditionedProtocol();
if ~ischar(presetName) || ...
        ~ismember(presetName, protocol.presets) || ...
        ~isscalar(seed) || ~ismember(seed, protocol.allSeeds)
    error('Formation H=3 event-conditioned request violates protocol.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official event-conditioned state selection requires clean source.');
end

manifestRoot = getField( ...
    options, 'manifestRoot', protocol.manifestRoot);
seedDirectory = fullfile( ...
    manifestRoot, presetName, sprintf('seed%d', seed));
manifestPath = fullfile(seedDirectory, sprintf( ...
    'formation_h3_event_manifest_%s_seed%d_v1.mat', ...
    strrep(presetName, '-', '_'), seed));
reportPath = fullfile(seedDirectory, sprintf( ...
    'FORMATION_H3_EVENT_MANIFEST_%s_SEED%d_V1.md', ...
    upper(strrep(presetName, '-', '_')), seed));
manifestExists = exist(manifestPath, 'file') == 2;
reportExists = exist(reportPath, 'file') == 2;
if xor(manifestExists, reportExists)
    error('Formation H=3 event manifest artifact set is partial.');
elseif manifestExists
    loaded = load(manifestPath, 'manifest');
    if ~isfield(loaded, 'manifest')
        error('Formation H=3 event manifest is missing.');
    end
    manifest = loaded.manifest;
    validateManifest( ...
        manifest, protocol, presetName, seed, gitState.commit);
    fprintf('Reused formation H=3 event manifest: %s\n', ...
        manifestPath);
    return;
end

[cachePaths, cacheSummary] = ...
    generateFormationH3ReferenceStateCaches( ...
        presetName, seed, protocol.candidateTimes, struct( ...
            'cacheRoot', protocol.cacheRoot, ...
            'protocol', protocol));
if ~strcmp(cacheSummary.protocolId, protocol.id) || ...
        ~strcmp(cacheSummary.generationGitCommit, gitState.commit)
    error('Formation H=3 event cache provenance is invalid.');
end

eventMetrics = repmat(emptyEventMetrics(), ...
    1, numel(protocol.candidateTimes));
scores = zeros(1, numel(protocol.candidateTimes));
for timeIdx = 1:numel(protocol.candidateTimes)
    currentTime = protocol.candidateTimes(timeIdx);
    state = loadFormationH3ObservableState( ...
        presetName, seed, currentTime, struct( ...
            'cacheRoot', protocol.cacheRoot));
    metrics = computeFormationH3ObservableEventScore( ...
        state.context, state.groupIds, struct( ...
            'tailFraction', protocol.eventScoreTailFraction, ...
            'tailWeight', protocol.eventScoreTailWeight));
    if ~strcmp(metrics.contractVersion, ...
            protocol.eventScoreContractVersion) || ...
            metrics.truthUsed || ...
            metrics.futureMeasurementsUsed || ...
            metrics.futureLinkOutcomesUsed
        error('Formation H=3 event score violates its evidence boundary.');
    end
    eventMetrics(timeIdx) = metrics;
    scores(timeIdx) = metrics.score;
    fprintf([ ...
        '  event state %s seed %d t=%d score=%.6f ', ...
        'contrast=%.6f link=%.6f\n'], ...
        presetName, seed, currentTime, metrics.score, ...
        metrics.posteriorContrast, ...
        metrics.robustSelectedCrossLinkStress);
end
[selectedTimes, selectedIndices] = ...
    selectFormationH3EventTimes( ...
        protocol.candidateTimes, scores, ...
        protocol.selectedStateCount, ...
        protocol.minimumSelectedTimeSeparation);

manifest = struct();
manifest.contractVersion = ...
    'formation-h3-event-conditioned-state-manifest-v1';
manifest.protocolId = protocol.id;
manifest.generatedAt = datestr(now, 31);
manifest.generationGitCommit = gitState.commit;
manifest.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
manifest.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
manifest.presetName = presetName;
manifest.seed = seed;
manifest.evidenceSplit = splitForSeed(seed, protocol);
manifest.candidateTimes = protocol.candidateTimes;
manifest.cachePaths = cachePaths;
manifest.cacheSha256 = cacheSummary.cacheSha256;
manifest.eventMetrics = eventMetrics;
manifest.scores = scores;
manifest.selectedIndices = selectedIndices;
manifest.selectedTimes = selectedTimes;
manifest.selectedScores = scores(selectedIndices);
manifest.selectedCachePaths = cachePaths(selectedIndices);
manifest.selectedCacheSha256 = ...
    cacheSummary.cacheSha256(selectedIndices);
manifest.minimumSelectedTimeSeparation = ...
    protocol.minimumSelectedTimeSeparation;
manifest.eventSelectionUsesTruth = false;
manifest.eventSelectionUsesFutureMeasurements = false;
manifest.eventSelectionUsesFutureLinkOutcomes = false;
manifest.teacherTargetsInspected = false;
manifest.openedSentinelDevelopmentOnly = true;
manifest.finalModelTrainingAuthorized = false;
manifest.validationClaimAllowed = false;
manifest.evidenceBoundary = protocol.evidenceBoundary;
manifest.manifestPath = manifestPath;
manifest.reportPath = reportPath;

if exist(seedDirectory, 'dir') ~= 7
    mkdir(seedDirectory);
end
save('-mat7-binary', manifestPath, 'manifest');
writeReport(reportPath, manifest);
validateManifest( ...
    manifest, protocol, presetName, seed, gitState.commit);
fprintf('Formation H=3 event manifest: %s\n', manifestPath);
end

function validateManifest( ...
        manifest, protocol, presetName, seed, expectedCommit)
required = { ...
    'contractVersion', 'protocolId', 'generationGitCommit', ...
    'presetName', 'seed', 'candidateTimes', 'cachePaths', ...
    'cacheSha256', 'eventMetrics', 'scores', ...
    'selectedIndices', 'selectedTimes', 'selectedScores', ...
    'selectedCachePaths', 'selectedCacheSha256', ...
    'eventSelectionUsesTruth', ...
    'eventSelectionUsesFutureMeasurements', ...
    'eventSelectionUsesFutureLinkOutcomes', ...
    'teacherTargetsInspected', 'validationClaimAllowed'};
if ~isstruct(manifest) || ~all(isfield(manifest, required)) || ...
        ~strcmp(manifest.contractVersion, ...
            'formation-h3-event-conditioned-state-manifest-v1') || ...
        ~strcmp(manifest.protocolId, protocol.id) || ...
        ~strcmp(manifest.generationGitCommit, expectedCommit) || ...
        ~strcmp(manifest.presetName, presetName) || ...
        manifest.seed ~= seed || ...
        ~isequal(manifest.candidateTimes, protocol.candidateTimes) || ...
        ~isequal(manifest.selectedTimes, sort(manifest.selectedTimes)) || ...
        numel(manifest.selectedTimes) ~= protocol.selectedStateCount || ...
        any(diff(manifest.selectedTimes) < ...
            protocol.minimumSelectedTimeSeparation) || ...
        manifest.eventSelectionUsesTruth || ...
        manifest.eventSelectionUsesFutureMeasurements || ...
        manifest.eventSelectionUsesFutureLinkOutcomes || ...
        manifest.teacherTargetsInspected || ...
        manifest.validationClaimAllowed
    error('Formation H=3 event manifest failed validation.');
end
for idx = 1:numel(manifest.cachePaths)
    if exist(manifest.cachePaths{idx}, 'file') ~= 2 || ...
            ~strcmp(computeFileSha256(manifest.cachePaths{idx}), ...
                manifest.cacheSha256{idx})
        error('Formation H=3 event manifest cache hash mismatch.');
    end
end
[times, indices] = selectFormationH3EventTimes( ...
    manifest.candidateTimes, manifest.scores, ...
    protocol.selectedStateCount, ...
    protocol.minimumSelectedTimeSeparation);
if ~isequal(times, manifest.selectedTimes) || ...
        ~isequal(indices, manifest.selectedIndices)
    error('Formation H=3 event manifest selection is not reproducible.');
end
end

function split = splitForSeed(seed, protocol)
if ismember(seed, protocol.trainingSeeds)
    split = 'sentinel-training';
elseif ismember(seed, protocol.developmentSeeds)
    split = 'sentinel-development';
else
    error('Formation H=3 event seed has no split.');
end
end

function metrics = emptyEventMetrics()
metrics = struct( ...
    'contractVersion', '', 'score', NaN, ...
    'posteriorContrast', NaN, ...
    'withinFormationMeanDisagreement', NaN, ...
    'crossFormationMeanDisagreement', NaN, ...
    'crossFormationTailDisagreement', NaN, ...
    'robustCrossFormationDisagreement', NaN, ...
    'selectedCrossLinkDropMean', NaN, ...
    'selectedCrossLinkDropTail', NaN, ...
    'robustSelectedCrossLinkStress', NaN, ...
    'selectedCrossEdgeCount', NaN, ...
    'sensorCount', NaN, 'formationCount', NaN, ...
    'formationPairCount', NaN, ...
    'tailFraction', NaN, 'tailWeight', NaN, ...
    'sensorPermutationInvariant', false, ...
    'formationLabelPermutationInvariant', false, ...
    'truthUsed', false, ...
    'futureMeasurementsUsed', false, ...
    'futureLinkOutcomesUsed', false);
end

function writeReport(path, manifest)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open formation H=3 event-manifest report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# Formation H=3 event-conditioned state manifest\n\n');
fprintf(fid, '- Contract / protocol: `%s / %s`\n', ...
    manifest.contractVersion, manifest.protocolId);
fprintf(fid, '- Generation commit: `%s`\n', ...
    manifest.generationGitCommit);
fprintf(fid, '- Preset / seed / split: `%s / %d / %s`\n', ...
    manifest.presetName, manifest.seed, manifest.evidenceSplit);
fprintf(fid, '- Candidate times: `%s`\n', ...
    mat2str(manifest.candidateTimes));
fprintf(fid, '- Selected times / scores: `%s / %s`\n', ...
    mat2str(manifest.selectedTimes), ...
    mat2str(manifest.selectedScores, 6));
fprintf(fid, ['- Truth / future measurement / future link outcome ', ...
    'use: `%d / %d / %d`\n\n'], ...
    manifest.eventSelectionUsesTruth, ...
    manifest.eventSelectionUsesFutureMeasurements, ...
    manifest.eventSelectionUsesFutureLinkOutcomes);
fprintf(fid, '| Time | Score | Posterior contrast | Cross robust |');
fprintf(fid, ' Within mean | Link stress | Selected |\n');
fprintf(fid, '|--:|--:|--:|--:|--:|--:|:--:|\n');
for idx = 1:numel(manifest.candidateTimes)
    metrics = manifest.eventMetrics(idx);
    fprintf(fid, '| %d | %.6f | %.6f | %.6f | %.6f | %.6f | %s |\n', ...
        manifest.candidateTimes(idx), metrics.score, ...
        metrics.posteriorContrast, ...
        metrics.robustCrossFormationDisagreement, ...
        metrics.withinFormationMeanDisagreement, ...
        metrics.robustSelectedCrossLinkStress, ...
        yesNo(ismember(idx, manifest.selectedIndices)));
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    manifest.evidenceBoundary);
end

function value = yesNo(flag)
if flag
    value = 'yes';
else
    value = 'no';
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
