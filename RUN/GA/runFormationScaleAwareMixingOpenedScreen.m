function [reportPath, screen] = ...
    runFormationScaleAwareMixingOpenedScreen(options)
% RUNFORMATIONSCALEAWAREMIXINGOPENEDSCREEN Frozen v27 H=3 screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationScaleAwareMixingProbeProtocol();
currentTime = getField(options, ...
    'currentTime', protocol.primarySnapshotTime);
if ~isscalar(currentTime) || ...
        ~ismember(currentTime, protocol.openedSnapshotTimes)
    error('ScaleMixing:InvalidProtocol', ...
        'v27 may use only the four preregistered opened states.');
end
writeReportEnabled = logical(getField(options, ...
    'writeReport', true));
outputDirectory = getField(options, ...
    'outputDirectory', fullfile(protocol.outputRoot, ...
        sprintf('t%d', currentTime), 'screen'));

bankOptions = struct( ...
    'actionModes', {protocol.actionModes}, ...
    'actionCrossResidualWeights', ...
        protocol.actionCrossResidualWeights, ...
    'dominantWeight', protocol.dominantWeight, ...
    'residualWeight', protocol.residualWeight, ...
    'orientation', protocol.orientation, ...
    'maximumActionCount', protocol.maximumActionCount);
executorOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'cacheRoot', protocol.cacheRoot, ...
    'interventionBankType', ...
        'scale-aware-formation-mixing', ...
    'scaleAwareBankOptions', bankOptions, ...
    'writeReport', false, ...
    'allowDirtySource', logical(getField( ...
        options, 'allowDirtySource', false)));
if isfield(options, 'actionIndices')
    executorOptions.actionIndices = options.actionIndices;
end
[~, screen] = runFormationModeOpenedReturnScreen( ...
    protocol.presetName, protocol.seed, currentTime, ...
    executorOptions);
assertCacheProvenance(screen.cachePath, protocol);
assertScreenContract(screen, protocol);

recordCount = numel(screen.records);
strictStrongMask = false(1, recordCount);
structuralMixingImproved = false(1, recordCount);
referenceIdx = screen.referenceSubsetIndex;
referenceActionIdx = screen.records(referenceIdx).actionIndex;
referenceGap = screen.bank. ...
    actionFormationMixingSpectralGapProxy(referenceActionIdx);
for recordIdx = 1:recordCount
    record = screen.records(recordIdx);
    actionIdx = record.actionIndex;
    structuralMixingImproved(recordIdx) = ...
        screen.bank.actionFormationMixingSpectralGapProxy(actionIdx) > ...
            referenceGap + 1e-12;
    strictStrongMask(recordIdx) = ...
        recordIdx ~= referenceIdx && ...
        record.meanGainPercent >= ...
            protocol.meanTrackingGainThresholdPercent - 1e-12 && ...
        record.minimumFormationGainPercent >= ...
            protocol.minimumFormationGainThresholdPercent - 1e-12 && ...
        record.worstGainPercent >= ...
            protocol.worstSensorGainThresholdPercent - 1e-12 && ...
        record.consensusGainPercent >= ...
            protocol.windowConsensusGainThresholdPercent - 1e-12 && ...
        record.attemptedByteSavingPercent >= ...
            -protocol.maximumAttemptedPayloadIncreasePercent - 1e-12 && ...
        record.selectedB3Passed;
end

screen.contractVersion = ...
    'formation-scale-aware-residual-mixing-v27-screen-v1';
screen.protocol = protocol;
screen.strictStrongMask = strictStrongMask;
screen.strictStrongCandidateCount = nnz(strictStrongMask);
screen.strongCandidateFound = any(strictStrongMask);
screen.structuralMixingImprovedMask = structuralMixingImproved;
screen.structuralMixingImprovedCount = ...
    nnz(structuralMixingImproved & ...
        (1:recordCount) ~= referenceIdx);
screen.referenceFormationMixingSpectralGapProxy = referenceGap;
screen.bestStrictStrongMeanGainPercent = maximumOrNaN( ...
    [screen.records(strictStrongMask).meanGainPercent]);
screen.bestStrictStrongRecordIndex = bestRecordIndex( ...
    screen.records, strictStrongMask);
screen.primaryOpenedState = ...
    currentTime == protocol.primarySnapshotTime;
screen.outcomeRankingUsesTruth = true;
screen.teacherCollectionAllowed = false;
screen.gnnTrainingAuthorized = false;
screen.x36OutcomeOpeningAuthorized = false;
screen.x48OutcomeOpeningAuthorized = false;
screen.validationClaimAllowed = false;
screen.evidenceBoundary = protocol.evidenceBoundary;

reportPath = '';
if writeReportEnabled
    if exist(outputDirectory, 'dir') ~= 7
        mkdir(outputDirectory);
    end
    stem = sprintf( ...
        'FORMATION_SCALE_AWARE_MIXING_H3_%s_SEED%d_T%d', ...
        upper(strrep(protocol.presetName, '-', '_')), ...
        protocol.seed, currentTime);
    reportPath = fullfile(outputDirectory, [stem, '.md']);
    matPath = fullfile(outputDirectory, [stem, '.mat']);
    screen.reportPath = reportPath;
    screen.matPath = matPath;
    save('-mat7-binary', matPath, 'screen');
    writeReport(reportPath, screen);
    fprintf('Scale-aware formation-mixing screen: %s\n', ...
        reportPath);
end
end

function assertCacheProvenance(cachePath, protocol)
loaded = load(cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('ScaleMixing:CacheProvenance', ...
        'Opened cache lacks behaviorBundle.');
end
bundle = loaded.behaviorBundle;
if ~isfield(bundle, 'protocolId') || ...
        ~strcmp(bundle.protocolId, protocol.cacheProtocolId) || ...
        ~isfield(bundle, 'generationGitCommit') || ...
        ~strcmp(bundle.generationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~isfield(bundle, 'openedDevelopmentEvidenceOnly') || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        ~isfield(bundle, 'validationClaimAllowed') || ...
        bundle.validationClaimAllowed
    error('ScaleMixing:CacheProvenance', ...
        'Opened cache provenance differs from the frozen v27 protocol.');
end
end

function assertScreenContract(screen, protocol)
bank = screen.bank;
if screen.horizonSteps ~= protocol.horizonSteps || ...
        screen.currentTime ~= screen.returnTimes(1) || ...
        bank.nodeCount ~= protocol.expectedNodeCount || ...
        bank.formationCount ~= protocol.expectedFormationCount || ...
        bank.actionCount ~= protocol.maximumActionCount || ...
        ~bank.messageCountParityWithReference || ...
        ~bank.allPhysical || ...
        ~bank.allCombinedOneStepStrongConnected || ...
        ~bank.allFormationStrongConnected || ...
        bank.truthUsed || bank.futureOutcomeUsed || ...
        any([screen.outcomes.truthUseCount] ~= 0) || ...
        any([screen.outcomes.repairCount] ~= 0) || ...
        any([screen.outcomes.payloadEmergencyCount] ~= 0) || ...
        any([screen.outcomes.infeasibleCount] ~= 0) || ...
        ~all([screen.records.selectedB3Passed])
    error('ScaleMixing:ScreenContract', ...
        'v27 screen violated its frozen causal or safety contract.');
end
end

function index = bestRecordIndex(records, mask)
indices = find(mask);
if isempty(indices)
    index = NaN;
    return;
end
[~, cursor] = max([records(indices).meanGainPercent]);
index = indices(cursor);
end

function writeReport(path, screen)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open v27 scale-aware report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
protocol = screen.protocol;
fprintf(fid, '# V27 scale-aware residual mixing H=3 screen\n\n');
fprintf(fid, '- Contract: `%s`\n', screen.contractVersion);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    screen.presetName, screen.seed, screen.currentTime);
fprintf(fid, '- Return times: `%s`\n', ...
    mat2str(screen.returnTimes));
fprintf(fid, '- Generation commit: `%s`\n', ...
    screen.generationGitCommit);
fprintf(fid, '- Cache SHA-256: `%s`\n', screen.cacheSha256);
fprintf(fid, '- Reference directed messages per step: `%d`\n', ...
    screen.bank.actionMessageCounts(1));
fprintf(fid, '- Equal-message parity: `%d`\n', ...
    screen.bank.messageCountParityWithReference);
fprintf(fid, '- Strong candidates: `%d / %d` nonreference actions\n', ...
    screen.strictStrongCandidateCount, numel(screen.records) - 1);
fprintf(fid, '- Best strict mean gain: `%+.3f%%`\n\n', ...
    screen.bestStrictStrongMeanGainPercent);

fprintf(fid, [ ...
    '| Action | Lanes | Cross edges | Cross w. | Mix gap | ', ...
    'Mean gain | Worst gain | Min form. | Window cons. | ', ...
    'Final cons. | Byte saving | Strong |\n']);
fprintf(fid, [ ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for recordIdx = 1:numel(screen.records)
    record = screen.records(recordIdx);
    actionIdx = record.actionIndex;
    fprintf(fid, [ ...
        '| `%s` | %d | %d | %.2f | %.6f | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d |\n'], ...
        record.actionName, ...
        screen.bank.actionGatewayLaneCounts(actionIdx), ...
        screen.bank.actionCrossFormationMessageCounts(actionIdx), ...
        screen.bank.actionCrossResidualWeights(actionIdx), ...
        screen.bank. ...
            actionFormationMixingSpectralGapProxy(actionIdx), ...
        record.meanGainPercent, record.worstGainPercent, ...
        record.minimumFormationGainPercent, ...
        record.consensusGainPercent, ...
        record.terminalConsensusGainPercent, ...
        record.attemptedByteSavingPercent, ...
        screen.strictStrongMask(recordIdx));
end

fprintf(fid, '\n## Frozen strong gate\n\n');
fprintf(fid, [ ...
    'A strong action requires mean tracking gain >= %.1f%%, minimum ', ...
    'formation gain >= %.1f%%, worst-sensor gain >= %.1f%%, window ', ...
    'consensus gain >= %.1f%%, attempted-byte increase <= %.1f%%, ', ...
    'and selected rolling-B3 pass.\n'], ...
    protocol.meanTrackingGainThresholdPercent, ...
    protocol.minimumFormationGainThresholdPercent, ...
    protocol.worstSensorGainThresholdPercent, ...
    protocol.windowConsensusGainThresholdPercent, ...
    protocol.maximumAttemptedPayloadIncreasePercent);
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    screen.evidenceBoundary);
end

function value = maximumOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
