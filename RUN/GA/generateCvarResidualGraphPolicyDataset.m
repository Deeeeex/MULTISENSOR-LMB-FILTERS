function token = formatTimeToken(labelTimes)
labelTimes = reshape(labelTimes, 1, []);
if numel(labelTimes) > 1 && ...
        all(diff(labelTimes) == 1)
    token = sprintf('%d_t%d', ...
        labelTimes(1), labelTimes(end));
else
    token = sprintf('%d_', labelTimes);
    token(end) = [];
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
