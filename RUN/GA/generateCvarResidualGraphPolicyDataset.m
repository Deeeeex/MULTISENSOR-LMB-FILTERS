function [datasetPath, dataset] = ...
    generateCvarResidualGraphPolicyDataset(options)
% GENERATECVARRESIDUALGRAPHPOLICYDATASET Relational M24 supervision.
%
% Truth-free posterior/link/history states are collected under the frozen
% analytic behavior policy. Current target truth is used only inside the
% offline CVaR teacher to produce node-tail and edge-weight supervision.

if nargin < 1 || isempty(options)
    options = struct();
end
frozenProtocol = ...
    getCvarResidualGraphPolicyDatasetProtocol();
protocol = getField(options, 'protocol', frozenProtocol);
if ~isequaln(protocol, frozenProtocol)
    error(['Official CVaR residual graph generation requires the ', ...
        'canonical frozen protocol without overrides.']);
end
if ~protocol.datasetGenerationAuthorized
    error('CVaR residual graph dataset generation is not authorized.');
end
seedList = round(reshape(getField( ...
    options, 'seedList', protocol.trainingSeeds), 1, []));
[registeredSeeds, registeredSeedIndices] = ismember( ...
    seedList, protocol.datasetSeeds);
if isempty(seedList) || any(~registeredSeeds) || ...
        ~issorted(registeredSeedIndices) || ...
        numel(unique(seedList)) ~= numel(seedList) || ...
        any(ismember(seedList, ...
            protocol.lockedHeldoutM24Seeds))
    error('CVaR residual graph seedList violates the frozen split.');
end
labelTimes = round(reshape(getField( ...
    options, 'labelTimes', protocol.snapshotTimes), 1, []));
if isempty(labelTimes) || ...
        any(~ismember(labelTimes, protocol.snapshotTimes)) || ...
        ~issorted(labelTimes) || ...
        numel(unique(labelTimes)) ~= numel(labelTimes)
    error('CVaR residual graph labelTimes are not a registered subset.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error(['Official CVaR residual graph generation requires ', ...
        'clean tracked source.']);
end

actionCodeSequences = ...
    protocol.actionCodeSequences(registeredSeedIndices, :);
graphBlocks = repmat(emptyGraphBlock(), ...
    1, numel(seedList) * numel(labelTimes));
graphCursor = 0;
rolloutOptions = struct( ...
    'datasetVariant', protocol.datasetVariant, ...
    'continuationStartTime', ...
        protocol.continuationStartTime, ...
    'sourceWeight', protocol.sourceWeight, ...
    'payloadToleranceFraction', ...
        protocol.payloadToleranceFraction, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'featureContextMode', protocol.featureContextMode, ...
    'proposalDistillationProtocol', protocol, ...
    'blockObserverFcn', @captureGraphTargets, ...
    'skipArtifactWrite', true);
[~, behaviorDataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        protocol.presetName, seedList, ...
        actionCodeSequences, rolloutOptions);
if graphCursor ~= numel(graphBlocks)
    error('CVaR residual graph target collection is incomplete.');
end
behaviorDataset.fullBehaviorSnapshotTimes = ...
    behaviorDataset.snapshotTimes;
behaviorDataset.fullBehaviorActionCodeSequences = ...
    behaviorDataset.actionCodeSequences;
behaviorMask = ismember( ...
    [behaviorDataset.blocks.currentTime], labelTimes);
behaviorDataset.blocks = behaviorDataset.blocks(behaviorMask);
labelTimeIndices = labelTimes - ...
    protocol.continuationStartTime + 1;
behaviorDataset.actionCodeSequences = ...
    behaviorDataset.actionCodeSequences( ...
        :, labelTimeIndices);
behaviorDataset.snapshotTimes = labelTimes;
validateBehaviorDataset(behaviorDataset, protocol, ...
    seedList, labelTimes);
validateBlockOrder( ...
    behaviorDataset.blocks, graphBlocks);

outputDirectory = getField(options, 'outputDirectory', ...
    protocol.defaultOutputDirectory);
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
seedToken = sprintf('%d_', seedList);
seedToken(end) = [];
timeToken = sprintf('%d_', labelTimes);
timeToken(end) = [];
defaultDatasetName = sprintf( ...
    'cvar_residual_graph_m24_seed%s_t%s_v1.mat', ...
    seedToken, timeToken);
defaultReportName = sprintf( ...
    'CVAR_RESIDUAL_GRAPH_M24_SEED%s_T%s_V1.md', ...
    seedToken, timeToken);
datasetPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, defaultDatasetName));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, defaultReportName));

dataset = struct();
dataset.protocolId = protocol.id;
dataset.contractVersion = ...
    protocol.datasetContractVersion;
dataset.predecessorProtocolId = ...
    protocol.predecessorProtocolId;
dataset.generatedAt = datestr(now, 31);
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.presetName = protocol.presetName;
dataset.seeds = seedList;
dataset.labelTimes = labelTimes;
dataset.behaviorCacheRecords = ...
    behaviorDataset.behaviorCacheRecords;
dataset.behaviorDataset = behaviorDataset;
dataset.graphBlocks = graphBlocks;
dataset.featureContractSha256 = ...
    uniqueContract(graphBlocks, ...
        'featureContractSha256');
dataset.featuresUseTruth = false;
dataset.featuresUseFutureOutcome = false;
dataset.behaviorUsesTruth = false;
dataset.behaviorUsesFutureOutcome = false;
dataset.teacherTargetsUseTruth = true;
dataset.teacherTargetsUseFutureOutcome = false;
dataset.deployable = false;
dataset.developmentOnly = true;
dataset.modelTrainingAuthorized = false;
dataset.heldoutM24Authorized = false;
dataset.x36Authorized = false;
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
dataset.evidenceBoundary = [ ...
    'Behavior, edge features, node features and histories are ', ...
    'deployment-observable and truth-free. Current ground truth ', ...
    'appears only in offline node-risk, CVaR-membership and ', ...
    'edge-safety labels. The dataset alone does not authorize model ', ...
    'training, held-out M24 claims, or X36 execution.'];
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('CVaR residual graph dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);

    function captureGraphTargets(context, behaviorBlock)
        if ~ismember(behaviorBlock.currentTime, labelTimes)
            return;
        end
        featureOptions = struct( ...
            'dominantWeight', protocol.dominantWeight, ...
            'localResidualWeight', ...
                protocol.localResidualWeight, ...
            'residualWeightGrid', ...
                protocol.residualWeightGrid, ...
            'featureContextMode', ...
                protocol.featureContextMode);
        observableContext = ...
            removeTargetTruthFromContext(context);
        examples = ...
            computeCvarResidualGraphPolicyExamples( ...
                observableContext, featureOptions);
        teacherOptions = struct( ...
            'dominantWeight', protocol.dominantWeight, ...
            'localResidualWeight', ...
                protocol.localResidualWeight, ...
            'crossResidualWeightGrid', ...
                protocol.residualWeightGrid, ...
            'protectedReceiverFraction', ...
                protocol.protectedReceiverFraction, ...
            'referenceAdvantageTolerance', ...
                protocol.referenceAdvantageTolerance);
        [teacherAdjacency, teacherDetails] = ...
            selectCvarTailGuardBackboneResidualSplicedCyclePolicy( ...
                context, teacherOptions);
        scoreDetails = teacherDetails.scoreDetails;
        selectedEdgeWeightTarget = ...
            buildSelectedEdgeWeightTarget( ...
                examples, teacherDetails);
        validateAlignment(examples, scoreDetails, ...
            teacherDetails, teacherAdjacency, ...
            selectedEdgeWeightTarget, ...
            context, behaviorBlock, protocol);

        graphCursor = graphCursor + 1;
        block = emptyGraphBlock();
        block.seed = behaviorBlock.seed;
        block.currentTime = behaviorBlock.currentTime;
        block.behaviorBlockIndex = graphCursor;
        block.featureContractSha256 = ...
            examples.featureContractSha256;
        block.edgeFeatures = examples.edgeFeatures;
        block.edgeFeatureNames = ...
            examples.edgeFeatureNames;
        block.nodeFeatures = examples.nodeFeatures;
        block.nodeFeatureNames = ...
            examples.nodeFeatureNames;
        block.receiverIndices = examples.receiverIndices;
        block.senderIndices = examples.senderIndices;
        block.residualWeightGrid = ...
            examples.residualWeightGrid;
        block.residualBaselineSourcesByReceiver = ...
            examples.residualBaselineSourcesByReceiver;
        block.nodeRiskTarget = ...
            scoreDetails. ...
                protectionBaselineRiskByReceiver;
        block.nodeCvarMaskTarget = ...
            scoreDetails.protectedReceiverMask;
        block.edgeTaskAdvantageTarget = ...
            scoreDetails.rawReferenceAdvantageByWeight;
        block.edgeProtectionAdvantageTarget = ...
            scoreDetails. ...
                protectionReferenceAdvantageByWeight;
        block.edgeProtectionObservedMask = ...
            isfinite(block.edgeProtectionAdvantageTarget);
        block.edgeReferenceSafeTarget = ...
            scoreDetails.referenceSafeWeightMask;
        block.selectedEdgeWeightTarget = ...
            selectedEdgeWeightTarget;
        block.teacherAdjacency = teacherAdjacency;
        block.teacherResidualAdjacency = ...
            teacherDetails.residualAdjacency;
        block.teacherCrossReceivers = ...
            teacherDetails.spliceSelection.crossReceivers;
        block.teacherCrossSenders = ...
            teacherDetails.spliceSelection.crossSenders;
        block.teacherCrossResidualWeights = ...
            teacherDetails.crossResidualWeights;
        block.teacherDetails = teacherDetails;
        block.featuresUseTruth = false;
        block.featuresUseFutureOutcome = false;
        block.targetsUseTruth = true;
        block.targetsUseFutureOutcome = false;
        block.deployable = false;
        graphBlocks(graphCursor) = block;
        fprintf(['  CVaR graph teacher seed %d t=%d: ', ...
            '%d candidates x %d weights, tail=%s\n'], ...
            block.seed, block.currentTime, ...
            numel(block.receiverIndices), ...
            numel(block.residualWeightGrid), ...
            mat2str(find(block.nodeCvarMaskTarget)));
    end
end

function validateAlignment( ...
        examples, scoreDetails, teacherDetails, ...
        teacherAdjacency, selectedEdgeWeightTarget, ...
        context, behaviorBlock, protocol)
candidateCount = numel(examples.receiverIndices);
weightCount = numel(examples.residualWeightGrid);
nodeCount = examples.nodeCount;
if examples.truthUsed || examples.futureOutcomeUsed || ...
        examples.referenceEdgeFeatureMetadata.truthUsed || ...
        examples.referenceEdgeFeatureMetadata. ...
            groundTruthUsed || ...
        examples.referenceEdgeFeatureMetadata. ...
            futureOutcomeUsed || ...
        ~isequal(examples.receiverIndices, ...
            scoreDetails.receiverIndices) || ...
        ~isequal(examples.senderIndices, ...
            scoreDetails.senderIndices) || ...
        ~isequal(examples.residualWeightGrid, ...
            scoreDetails.residualWeightGrid) || ...
        ~scoreDetails.truthUsed || ...
        scoreDetails.futureOutcomeUsed || ...
        ~teacherDetails.truthUsed || ...
        teacherDetails.tailSafeFallbackUsed || ...
        teacherDetails.topologyInfeasible || ...
        teacherDetails.repairTriggered || ...
        teacherDetails.payloadEmergencyUsed || ...
        context.currentTime ~= behaviorBlock.currentTime || ...
        numel(scoreDetails. ...
            protectionBaselineRiskByReceiver) ~= nodeCount || ...
        numel(scoreDetails.protectedReceiverMask) ~= nodeCount || ...
        ~isequal(size(scoreDetails. ...
            rawReferenceAdvantageByWeight), ...
            [candidateCount, weightCount]) || ...
        ~isequal(size(scoreDetails. ...
            protectionReferenceAdvantageByWeight), ...
            [candidateCount, weightCount]) || ...
        ~isequal(size(scoreDetails.referenceSafeWeightMask), ...
            [candidateCount, weightCount]) || ...
        ~isequal(size(selectedEdgeWeightTarget), ...
            [candidateCount, weightCount]) || ...
        ~isequal(size(teacherAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(teacherDetails.residualAdjacency), ...
            [nodeCount, nodeCount]) || ...
        nnz(scoreDetails.protectedReceiverMask) ~= ...
            protocol.expectedProtectedReceiverCount || ...
        teacherDetails.crossFormationMessageCount ~= ...
            protocol.expectedCrossCycleEdgeCount || ...
        nnz(teacherAdjacency) ~= ...
            nnz(teacherDetails.baselineAdjacency)
    error('CVaR residual graph teacher/feature alignment failed.');
end
end

function observableContext = ...
    removeTargetTruthFromContext(context)
observableContext = context;
if isfield(observableContext.model, ...
        'explicitTargetTrajectories')
    observableContext.model = rmfield( ...
        observableContext.model, ...
        'explicitTargetTrajectories');
end
if isfield(observableContext.model, ...
        'dynamicTopologyScenario') && ...
        isfield(observableContext.model. ...
            dynamicTopologyScenario, ...
            'targetTrajectories')
    observableContext.model.dynamicTopologyScenario = ...
        rmfield(observableContext.model. ...
            dynamicTopologyScenario, ...
            'targetTrajectories');
end
if isfield(observableContext.model, ...
        'explicitTargetTrajectories') || ...
        (isfield(observableContext.model, ...
            'dynamicTopologyScenario') && ...
         isfield(observableContext.model. ...
            dynamicTopologyScenario, ...
            'targetTrajectories'))
    error('Could not remove target truth from feature context.');
end
end

function target = ...
    buildSelectedEdgeWeightTarget(examples, teacherDetails)
target = false(examples.candidateCount, ...
    examples.weightCount);
crossReceivers = reshape( ...
    teacherDetails.spliceSelection.crossReceivers, [], 1);
crossSenders = reshape( ...
    teacherDetails.spliceSelection.crossSenders, [], 1);
crossWeights = reshape( ...
    teacherDetails.crossResidualWeights, [], 1);
for crossIdx = 1:numel(crossReceivers)
    edgeIdx = find( ...
        examples.receiverIndices == ...
            crossReceivers(crossIdx) & ...
        examples.senderIndices == ...
            crossSenders(crossIdx), 1);
    weightIdx = find(abs( ...
        examples.residualWeightGrid - ...
            crossWeights(crossIdx)) <= 1e-12, 1);
    if isempty(edgeIdx) || isempty(weightIdx)
        error('Teacher selected an unregistered residual action.');
    end
    target(edgeIdx, weightIdx) = true;
end
if nnz(target) ~= numel(crossReceivers)
    error('Teacher edge-weight target is not a bijection.');
end
end

function validateBehaviorDataset( ...
        dataset, protocol, seedList, labelTimes)
if ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~isequal(dataset.seeds, seedList) || ...
        ~isequal(dataset.snapshotTimes, labelTimes) || ...
        size(dataset.actionCodeSequences, 2) ~= ...
            numel(labelTimes) || ...
        any(dataset.actionCodeSequences(:) ~= ...
            protocol.behaviorActionCode) || ...
        dataset.featuresUseTruth || ...
        dataset.labelsUseTruth || ...
        dataset.labelSelectionUsesFutureOutcome || ...
        dataset.behaviorTruthUsed || ...
        dataset.behaviorFutureOutcomeUsed
    error('CVaR residual graph behavior state is not truth-free.');
end
for block = dataset.blocks
    if block.actionTruthUsed || block.labelTruthUsed || ...
            block.featureMetadata.truthUsed || ...
            block.featureMetadata.futureOutcomeUsed
        error('CVaR residual graph behavior block leaked truth.');
    end
end
end

function validateBlockOrder(behaviorBlocks, graphBlocks)
if numel(behaviorBlocks) ~= numel(graphBlocks)
    error('Behavior and CVaR graph block counts differ.');
end
for blockIdx = 1:numel(graphBlocks)
    if behaviorBlocks(blockIdx).seed ~= ...
            graphBlocks(blockIdx).seed || ...
            behaviorBlocks(blockIdx).currentTime ~= ...
                graphBlocks(blockIdx).currentTime || ...
            graphBlocks(blockIdx).behaviorBlockIndex ~= blockIdx
        error(['Behavior and CVaR graph blocks are not in exact ', ...
            'seed-major/time-major order.']);
    end
end
end

function value = uniqueContract(blocks, fieldName)
values = {blocks.(fieldName)};
uniqueValues = unique(values);
if numel(uniqueValues) ~= 1
    error('CVaR residual graph feature contracts differ across blocks.');
end
value = uniqueValues{1};
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open CVaR residual graph report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 CVaR residual graph supervision\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%s`\n', mat2str(dataset.labelTimes));
fprintf(fid, '- State blocks: `%d`\n', ...
    numel(dataset.graphBlocks));
fprintf(fid, '- Feature contract SHA-256: `%s`\n', ...
    dataset.featureContractSha256);
fprintf(fid, '- Feature truth/future use: `%d / %d`\n', ...
    dataset.featuresUseTruth, ...
    dataset.featuresUseFutureOutcome);
fprintf(fid, '- Teacher truth/future use: `%d / %d`\n', ...
    dataset.teacherTargetsUseTruth, ...
    dataset.teacherTargetsUseFutureOutcome);
fprintf(fid, '- Deployable: `%d`\n', dataset.deployable);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, ...
    '| Seed | Time | Candidates | Weights | Tail nodes | Selected |\n');
fprintf(fid, '|--:|--:|--:|--:|:--|--:|\n');
for block = dataset.graphBlocks
    fprintf(fid, '| %d | %d | %d | %d | `%s` | %d |\n', ...
        block.seed, block.currentTime, ...
        numel(block.receiverIndices), ...
        numel(block.residualWeightGrid), ...
        mat2str(find(block.nodeCvarMaskTarget)), ...
        nnz(block.selectedEdgeWeightTarget));
end
end

function block = emptyGraphBlock()
block = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behaviorBlockIndex', NaN, ...
    'featureContractSha256', '', ...
    'edgeFeatures', zeros(0, 0, 0), ...
    'edgeFeatureNames', {cell(1, 0)}, ...
    'nodeFeatures', zeros(0, 0), ...
    'nodeFeatureNames', {cell(1, 0)}, ...
    'receiverIndices', zeros(0, 1), ...
    'senderIndices', zeros(0, 1), ...
    'residualWeightGrid', [], ...
    'residualBaselineSourcesByReceiver', [], ...
    'nodeRiskTarget', [], ...
    'nodeCvarMaskTarget', false(1, 0), ...
    'edgeTaskAdvantageTarget', zeros(0, 0), ...
    'edgeProtectionAdvantageTarget', zeros(0, 0), ...
    'edgeProtectionObservedMask', false(0, 0), ...
    'edgeReferenceSafeTarget', false(0, 0), ...
    'selectedEdgeWeightTarget', false(0, 0), ...
    'teacherAdjacency', false(0), ...
    'teacherResidualAdjacency', false(0), ...
    'teacherCrossReceivers', [], ...
    'teacherCrossSenders', [], ...
    'teacherCrossResidualWeights', [], ...
    'teacherDetails', struct(), ...
    'featuresUseTruth', false, ...
    'featuresUseFutureOutcome', false, ...
    'targetsUseTruth', true, ...
    'targetsUseFutureOutcome', false, ...
    'deployable', false);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
