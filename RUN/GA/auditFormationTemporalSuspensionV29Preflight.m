function [reportPath, audit] = ...
    auditFormationTemporalSuspensionV29Preflight(options)
% AUDITFORMATIONTEMPORALSUSPENSIONV29PREFLIGHT No-continuation gate.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationTemporalSuspensionProbeProtocol();
v28ScreenPath = getField(options, 'v28ScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v28', 'conflict_aware_selective_mixing', ...
    't72', 'screen', ...
    ['FORMATION_CONFLICT_AWARE_MIXING_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_TEMPORAL_CROSS_EDGE_SUSPENSION_V29_', ...
     'PREFLIGHT_20260802.md']));
loaded = load(v28ScreenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V29Preflight:MissingSource', ...
        'Frozen v28 primary screen is unavailable.');
end
source = loaded.screen;
assertSourceProvenance(source, protocol);
context = reconstructContext(source);

timerId = tic;
bank = buildTemporalCrossEdgeSuspensionActionBank(context);
bankConstructionSeconds = toc(timerId);
if ~bank.allPhysical || ~bank.allRowStochastic || ...
        ~bank.allMessageCountsNoGreaterThanReference || ...
        ~bank.allRollingB3SensorStrongConnected || ...
        ~bank.allRollingB3FormationStrongConnected || ...
        bank.oneStepStrongConnectivityRequired || ...
        bank.oneStepDisagreementHardGateEnabled || ...
        bank.truthUsed || bank.futureOutcomeUsed || ...
        ~bank.posteriorSafetyScored
    error('V29Preflight:BankContract', ...
        'v29 action bank violated a frozen preflight invariant.');
end

referenceIdx = bank.referenceActionIndex;
disagreementChangePercent = 100 * ( ...
    bank.networkDisagreementRisk - ...
        bank.networkDisagreementRisk(referenceIdx)) / max( ...
            bank.networkDisagreementRisk(referenceIdx), eps);
horizonMessageSavingPercent = 100 * ...
    bank.actionMessageSavingCounts ./ max( ...
        protocol.horizonSteps * bank.actionMessageCounts(referenceIdx), 1);
gitState = resolveResearchGitState();
audit = struct();
audit.contractVersion = ...
    'formation-temporal-suspension-v29-preflight-v1';
audit.generatedAt = datestr(now, 31);
audit.generationGitCommit = gitState.commit;
audit.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
audit.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
audit.protocol = protocol;
audit.sourceV28ScreenPath = v28ScreenPath;
audit.sourceCachePath = source.cachePath;
audit.sourceCacheSha256 = source.cacheSha256;
audit.presetName = source.presetName;
audit.seed = source.seed;
audit.currentTime = source.currentTime;
audit.bankConstructionSeconds = bankConstructionSeconds;
audit.bank = bank;
audit.disagreementChangePercent = disagreementChangePercent;
audit.horizonMessageSavingPercent = horizonMessageSavingPercent;
audit.safeNonreferenceActionCount = ...
    bank.safeNonreferenceActionCount;
audit.safeNonreferenceActionIndices = setdiff( ...
    bank.safeActionIndices, referenceIdx);
audit.safeNonreferenceActionNames = ...
    bank.actionNames(audit.safeNonreferenceActionIndices);
audit.trackingContinuationExecuted = false;
audit.newStateOpened = false;
audit.truthUsed = false;
audit.futureOutcomeUsed = false;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.primaryTrackingScreenAuthorized = ...
    bank.safeNonreferenceActionCount > 0;
audit.evidenceBoundary = protocol.evidenceBoundary;

writeReport(reportPath, audit);
fprintf('V29 temporal-suspension preflight: %s\n', reportPath);
end

function context = reconstructContext(source)
inputs = generateDynamicTopologyScenarioInputs( ...
    source.presetName, source.seed);
loaded = load(source.cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V29Preflight:MissingCache', ...
        'Opened behavior cache is unavailable.');
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.presetName, source.presetName) || ...
        bundle.seed ~= source.seed || ...
        ~isequal(bundle.snapshotTimes, source.currentTime) || ...
        ~isequaln(bundle.configSnapshot, inputs.config) || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        bundle.validationClaimAllowed
    error('V29Preflight:CacheProvenance', ...
        'Opened behavior cache provenance changed.');
end
history = bundle.preDecisionTopologyHistoryByTime{source.currentTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{source.currentTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = source.currentTime;
context.previousAdjacencyHistory = previousHistory;
context.previousAdjacency = previousHistory(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, source.currentTime));
context.positions = inputs.graphData.positions(:, :, source.currentTime);
context.directedMessageBudget = 2 * ...
    inputs.config.numberOfSensors;
end

function assertSourceProvenance(source, protocol)
if ~strcmp(source.contractVersion, ...
        'formation-conflict-aware-selective-mixing-v28-screen-v1') || ...
        ~strcmp(source.generationGitCommit, ...
            'bf641fec9f34f8a432daab4b91e259701fd2c7c2') || ...
        ~strcmp(source.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(source.presetName, protocol.presetName) || ...
        source.seed ~= protocol.seed || ...
        source.currentTime ~= protocol.primarySnapshotTime || ...
        source.strictStrongCandidateCount ~= 0 || ...
        source.additionalOpenedStateScreenAuthorized || ...
        source.gnnTrainingAuthorized || ...
        source.validationClaimAllowed
    error('V29Preflight:SourceProvenance', ...
        'Frozen v28 source provenance changed.');
end
end

function writeReport(path, audit)
fid = fopen(path, 'w');
if fid < 0
    error('V29Preflight:WriteFailed', ...
        'Could not open v29 preflight report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bank = audit.bank;
protocol = audit.protocol;
fprintf(fid, '# V29 temporal cross-edge suspension preflight\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    audit.generationGitCommit);
fprintf(fid, '- Tracked worktree dirty: `%d`\n', ...
    audit.generationTrackedWorktreeDirty);
fprintf(fid, '- Preset / seed / time: `%s / %d / %d`\n', ...
    audit.presetName, audit.seed, audit.currentTime);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- Structural actions: `%d`\n', bank.actionCount);
fprintf(fid, '- Safe nonreference actions: `%d`\n', ...
    audit.safeNonreferenceActionCount);
fprintf(fid, '- Tracking continuation executed: `0`\n');
fprintf(fid, '- New state / X36 / X48 opened: `0 / 0 / 0`\n');
fprintf(fid, '- Bank construction: `%.2f s`\n\n', ...
    audit.bankConstructionSeconds);

fprintf(fid, '## Frozen safety boundary\n\n');
fprintf(fid, [ ...
    'The action is applied for one step and followed by two reference ', ...
    'steps. Label-retention thresholds are unchanged from v28. All ', ...
    'selected three-step sensor and formation windows must be strongly ', ...
    'connected, and every candidate sends fewer messages than reference. ', ...
    'One-step disagreement is recorded but is not a hard gate.\n\n']);
fprintf(fid, [ ...
    '| Action | Suspended formations | Dropped messages | H3 message ', ...
    'saving | One-step disagreement change | Retention risk | ', ...
    'Min form. d-card | Min label retention | Threshold drops | Safe |\n']);
fprintf(fid, [ ...
    '|:--|:--|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for actionIdx = 1:bank.actionCount
    fprintf(fid, [ ...
        '| `%s` | `%s` | %d | %.3f%% | %+.3f%% | %.6f | ', ...
        '%+.6f | %.6f | %d | %d |\n'], ...
        bank.actionNames{actionIdx}, ...
        mat2str(bank.actionSuspendedFormationIds{actionIdx}), ...
        bank.actionMessageSavingCounts(actionIdx), ...
        audit.horizonMessageSavingPercent(actionIdx), ...
        audit.disagreementChangePercent(actionIdx), ...
        bank.retentionRisk(actionIdx), ...
        bank.minimumFormationCardinalityChange(actionIdx), ...
        bank.minimumSupportedLabelRetentionRatio(actionIdx), ...
        bank.decisionThresholdCrossingCount(actionIdx), ...
        bank.actionPosteriorSafetyMask(actionIdx));
end

fprintf(fid, '\n## Decision\n\n');
if audit.primaryTrackingScreenAuthorized
    fprintf(fid, [ ...
        'At least one nonreference subset passes all frozen causal and ', ...
        'rolling-connectivity gates. The primary H=3 continuation may ', ...
        'execute only the reference and safe indices `%s`. No other ', ...
        'M24 state or X36/X48 is authorized.\n\n'], ...
        mat2str(audit.safeNonreferenceActionIndices));
else
    fprintf(fid, [ ...
        'No nonreference subset passes. No v29 tracking continuation ', ...
        'or additional state is authorized.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    audit.evidenceBoundary);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
