function [modelPath, result] = ...
    trainCvarResidualGraphPolicy(options)
% TRAINCVARRESIDUALGRAPHPOLICY Frozen M24 training-only model selection.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getCvarResidualGraphPolicyDatasetProtocol();
if ~protocol.modelTrainingAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.trainingLosoPassed
    error(['CVaR graph training requires audited shards and sealed ', ...
        'development labels.']);
end
bundle = loadCvarResidualGraphPolicyShards('training');
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official CVaR graph training requires clean source.');
end

families = protocol.modelFamilies;
candidates = repmat(emptyCandidate(), 1, numel(families));
for familyIdx = 1:numel(families)
    family = families{familyIdx};
    rows = repmat(emptyEvaluationRow(), 1, 0);
    folds = repmat(emptyFold(), 1, ...
        numel(protocol.outerLosoHeldoutSeeds));
    for foldIdx = 1:numel( ...
            protocol.outerLosoHeldoutSeeds)
        heldoutSeed = ...
            protocol.outerLosoHeldoutSeeds(foldIdx);
        calibrationSeed = ...
            protocol.outerLosoCalibrationSeeds(foldIdx);
        fitSeeds = setdiff(protocol.trainingSeeds, ...
            [heldoutSeed, calibrationSeed], 'stable');
        if numel(fitSeeds) ~= 4 || ...
                ismember(heldoutSeed, fitSeeds) || ...
                ismember(calibrationSeed, fitSeeds)
            error('CVaR graph LOSO split is invalid.');
        end
        fprintf(['CVaR graph %s fold %d/%d: fit=%s, ', ...
            'calibrate=%d, test=%d\n'], ...
            family, foldIdx, ...
            numel(protocol.outerLosoHeldoutSeeds), ...
            mat2str(fitSeeds), calibrationSeed, ...
            heldoutSeed);
        foldModel = fitCvarResidualGraphPolicyModel( ...
            bundle.graphBlocks, fitSeeds, ...
            family, protocol);
        calibrationBlocks = bundle.graphBlocks( ...
            [bundle.graphBlocks.seed] == ...
                calibrationSeed);
        calibration = ...
            calibrateCvarResidualGraphSafetyMargin( ...
                foldModel, calibrationBlocks, protocol);
        testMask = [bundle.graphBlocks.seed] == ...
            heldoutSeed;
        foldRows = ...
            evaluateCvarResidualGraphPolicyBlocks( ...
                foldModel, calibration, ...
                bundle.graphBlocks(testMask), ...
                bundle.behaviorBlocks(testMask), ...
                protocol);
        foldMetrics = ...
            summarizeCvarResidualGraphPolicyRows( ...
                foldRows, protocol);
        folds(foldIdx) = struct( ...
            'heldoutSeed', heldoutSeed, ...
            'calibrationSeed', calibrationSeed, ...
            'fitSeeds', fitSeeds, ...
            'safetyMargin', calibration.margin, ...
            'metrics', foldMetrics);
        rows = [rows, foldRows]; %#ok<AGROW>
        fprintf(['  recall=%.3f, rho=%.3f, ', ...
            'median regret=%.3f, false-safe=%.3f, ', ...
            'fallback=%d\n'], ...
            foldMetrics.nodeTailRecall, ...
            foldMetrics.edgeTaskSpearman, ...
            foldMetrics.medianNormalizedRegret, ...
            foldMetrics. ...
                observedTailFalseSafeFraction, ...
            foldMetrics.staticFallbackCount);
    end
    metrics = summarizeCvarResidualGraphPolicyRows( ...
        rows, protocol);
    candidate = emptyCandidate();
    candidate.family = family;
    candidate.rows = rows;
    candidate.folds = folds;
    candidate.metrics = metrics;
    candidates(familyIdx) = candidate;
    fprintf(['CVaR graph %s LOSO: hard=%d, recall=%.3f ', ...
        '(min %.3f), rho=%.3f (min %.3f), ', ...
        'regret=%.3f/%.3f, safe=%d\n'], ...
        family, metrics.allHardGatesPassed, ...
        metrics.nodeTailRecall, ...
        metrics.minimumSeedNodeTailRecall, ...
        metrics.edgeTaskSpearman, ...
        metrics.minimumSeedEdgeTaskSpearman, ...
        metrics.medianNormalizedRegret, ...
        metrics.p90NormalizedRegret, ...
        metrics.safetyGatePassed);
end

[selectedIdx, selectionReason] = ...
    selectCandidate(candidates, protocol);
selected = candidates(selectedIdx);
finalCalibrationSeed = ...
    protocol.finalModelCalibrationSeed;
finalFitSeeds = setdiff(protocol.trainingSeeds, ...
    finalCalibrationSeed, 'stable');
finalCoreModel = fitCvarResidualGraphPolicyModel( ...
    bundle.graphBlocks, finalFitSeeds, ...
    selected.family, protocol);
calibrationBlocks = bundle.graphBlocks( ...
    [bundle.graphBlocks.seed] == ...
        finalCalibrationSeed);
finalCalibration = ...
    calibrateCvarResidualGraphSafetyMargin( ...
        finalCoreModel, calibrationBlocks, protocol);

model = struct();
model.kind = ...
    'frozen-cvar-residual-graph-policy-m24-v2';
model.contractVersion = protocol.modelContractVersion;
model.protocolId = protocol.id;
model.generatedAt = datestr(now, 31);
model.family = selected.family;
model.selectionReason = selectionReason;
model.coreModel = finalCoreModel;
model.safetyCalibration = finalCalibration;
model.trainingSeeds = protocol.trainingSeeds;
model.fitSeeds = finalFitSeeds;
model.calibrationSeed = finalCalibrationSeed;
model.outerLosoHeldoutSeeds = ...
    protocol.outerLosoHeldoutSeeds;
model.outerLosoCalibrationSeeds = ...
    protocol.outerLosoCalibrationSeeds;
model.trainingEvaluationMode = ...
    protocol.trainingEvaluationMode;
model.candidateMetrics = stripRows(candidates);
model.selectedTrainingLosoMetrics = ...
    selected.metrics;
model.trainingLosoPassed = ...
    selected.metrics.allHardGatesPassed;
model.trainingGitCommit = gitState.commit;
model.trainingTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
model.trainingUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
model.trainingResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
model.datasetSetSha256 = ...
    protocol.fullShardDatasetSetSha256;
model.featureContractSha256 = ...
    protocol.fullShardFeatureContractSha256;
model.featuresUseTruth = false;
model.trainingTargetsUseTruth = true;
model.trainingTargetsUseFutureOutcome = false;
model.developmentLabelsOpened = false;
model.developmentEvaluationAuthorized = ...
    model.trainingLosoPassed;
model.proposalH3ReturnGenerationAuthorized = false;
model.criticTrainingAuthorized = false;
model.heldoutM24Authorized = false;
model.x36Authorized = false;
model.deployable = false;
model.developmentOnly = true;
model.evidenceBoundary = [ ...
    'Selection uses only whole-seed training LOSO with a disjoint ', ...
    'whole-seed safety calibration split. Development seeds 31 ', ...
    'and 37 were not loaded. A passing result authorizes only ', ...
    'registration of this frozen model and one development-gate ', ...
    'evaluation; it does not authorize H=3 returns, held-out M24, ', ...
    'X36, or an effect claim.'];

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'models'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
modelPath = getField(options, 'modelPath', fullfile( ...
    outputDirectory, ...
    'cvar_residual_graph_policy_m24_training_loso_v2.mat'));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'CVAR_RESIDUAL_GRAPH_POLICY_TRAINING_LOSO_M24.md'));
model.modelPath = modelPath;
model.reportPath = reportPath;
save('-mat7-binary', modelPath, 'model');
writeReport(reportPath, model, candidates, protocol);

result = struct();
result.modelPath = modelPath;
result.reportPath = reportPath;
result.selectedFamily = selected.family;
result.selectionReason = selectionReason;
result.selectedMetrics = selected.metrics;
result.trainingLosoPassed = ...
    model.trainingLosoPassed;
result.developmentEvaluationAuthorized = ...
    model.developmentEvaluationAuthorized;
result.proposalH3ReturnGenerationAuthorized = false;
result.heldoutM24Authorized = false;
result.x36Authorized = false;
fprintf(['CVaR graph selected %s (%s): LOSO hard=%d, ', ...
    'development evaluation authorized=%d\n', ...
    'Model: %s\nReport: %s\n'], ...
    selected.family, selectionReason, ...
    model.trainingLosoPassed, ...
    model.developmentEvaluationAuthorized, ...
    modelPath, reportPath);
end

function [selectedIdx, reason] = ...
        selectCandidate(candidates, protocol)
ridgeIdx = find(strcmp( ...
    {candidates.family}, 'ridge'), 1);
mlpIdx = find(strcmp( ...
    {candidates.family}, 'mlp'), 1);
if isempty(ridgeIdx) || isempty(mlpIdx)
    error('CVaR graph candidate registry is incomplete.');
end
ridge = candidates(ridgeIdx).metrics;
mlp = candidates(mlpIdx).metrics;
mlpSafetyNoWorse = ...
    mlp.observedTailFalseSafeFraction <= ...
        ridge.observedTailFalseSafeFraction + 1e-12 && ...
    mlp.selectedSafeStateFraction + 1e-12 >= ...
        ridge.selectedSafeStateFraction && ...
    mlp.staticFallbackCount <= ...
        ridge.staticFallbackCount;
mlpNodeImproved = ...
    mlp.minimumSeedNodeTailRecall + 1e-12 >= ...
        ridge.minimumSeedNodeTailRecall + ...
        protocol. ...
            minimumMlpWorstSeedNodeRecallImprovement;
mlpRegretImproved = ...
    mlp.medianNormalizedRegret <= ...
        ridge.medianNormalizedRegret - ...
        protocol.minimumMlpMedianRegretImprovement + 1e-12;
if ~ridge.allHardGatesPassed && ...
        mlp.allHardGatesPassed
    selectedIdx = mlpIdx;
    reason = 'ridge-failed-mlp-passed-all-hard-gates';
elseif mlp.allHardGatesPassed && ...
        mlpSafetyNoWorse && mlpNodeImproved && ...
        mlpRegretImproved
    selectedIdx = mlpIdx;
    reason = ...
        'mlp-preregistered-safety-node-regret-dominance';
else
    selectedIdx = ridgeIdx;
    reason = 'deterministic-ridge-sentinel-retained';
end
end

function stripped = stripRows(candidates)
stripped = repmat(struct( ...
    'family', '', 'folds', [], 'metrics', struct()), ...
    1, numel(candidates));
for idx = 1:numel(candidates)
    stripped(idx).family = candidates(idx).family;
    stripped(idx).folds = candidates(idx).folds;
    stripped(idx).metrics = candidates(idx).metrics;
end
end

function writeReport(path, model, candidates, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open CVaR graph training report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# M24 CVaR relational graph policy: training LOSO\n\n');
fprintf(fid, '- Generated: %s\n', model.generatedAt);
fprintf(fid, '- Training commit: `%s`\n', ...
    model.trainingGitCommit);
fprintf(fid, '- Dataset-set SHA-256: `%s`\n', ...
    model.datasetSetSha256);
fprintf(fid, '- Feature contract SHA-256: `%s`\n', ...
    model.featureContractSha256);
fprintf(fid, '- Training seeds: `%s`\n', ...
    mat2str(model.trainingSeeds));
fprintf(fid, '- Evaluation: `%s`\n', ...
    model.trainingEvaluationMode);
fprintf(fid, '- Selected family: `%s`\n', model.family);
fprintf(fid, '- Selection reason: `%s`\n', ...
    model.selectionReason);
fprintf(fid, '- Final fit seeds: `%s`\n', ...
    mat2str(model.fitSeeds));
fprintf(fid, '- Final calibration seed: `%d`\n', ...
    model.calibrationSeed);
fprintf(fid, '- Safety margin: `%.9g`\n', ...
    model.safetyCalibration.margin);
fprintf(fid, '- Training LOSO passed: `%d`\n', ...
    model.trainingLosoPassed);
fprintf(fid, ...
    '- Development labels opened: `%d`\n', ...
    model.developmentLabelsOpened);
fprintf(fid, ...
    '- Development evaluation authorized: `%d`\n', ...
    model.developmentEvaluationAuthorized);
fprintf(fid, ...
    '- H=3 return generation authorized: `%d`\n\n', ...
    model.proposalH3ReturnGenerationAuthorized);

fprintf(fid, ['| Family | Hard | Tail recall | Min seed | ', ...
    'Tail Jaccard | Task rho | Min seed | Regret med | ', ...
    'Regret P90 | False-safe | Safe recall | ', ...
    'Selected safe | Fallback |\n']);
fprintf(fid, ...
    '|:--|:--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for candidate = candidates
    metric = candidate.metrics;
    fprintf(fid, ...
        ['| %s | %d | %.3f | %.3f | %.3f | %.3f | ', ...
         '%.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %d |\n'], ...
        candidate.family, metric.allHardGatesPassed, ...
        metric.nodeTailRecall, ...
        metric.minimumSeedNodeTailRecall, ...
        metric.nodeTailJaccard, ...
        metric.edgeTaskSpearman, ...
        metric.minimumSeedEdgeTaskSpearman, ...
        metric.medianNormalizedRegret, ...
        metric.p90NormalizedRegret, ...
        metric.observedTailFalseSafeFraction, ...
        metric.observedTailTrueSafeRecall, ...
        metric.selectedSafeStateFraction, ...
        metric.staticFallbackCount);
end
fprintf(fid, '\n## Selected-family seed macro\n\n');
fprintf(fid, ['| Seed | States | Tail recall | Jaccard | ', ...
    'Task rho | Regret med | Regret P90 | ', ...
    'Mean task gain | Nonnegative states | Fallback |\n']);
fprintf(fid, ...
    '|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n');
for seed = model.selectedTrainingLosoMetrics.seedMetrics
    fprintf(fid, ...
        ['| %d | %d | %.3f | %.3f | %.3f | %.3f | ', ...
         '%.3f | %.6g | %d | %d |\n'], ...
        seed.seed, seed.stateCount, ...
        seed.nodeTailRecall, seed.nodeTailJaccard, ...
        seed.edgeTaskSpearman, ...
        seed.medianNormalizedRegret, ...
        seed.p90NormalizedRegret, ...
        seed.meanSelectedTaskAdvantage, ...
        seed.nonnegativeSelectedTaskStateCount, ...
        seed.staticFallbackCount);
end
fprintf(fid, '\n## Frozen gates\n\n');
fprintf(fid, ...
    '- Tail recall: overall >= %.2f; every seed >= %.3f\n', ...
    protocol.minimumNodeTailRecall, ...
    protocol.minimumPerSeedNodeTailRecall);
fprintf(fid, ...
    '- Tail Jaccard: overall >= %.2f; every seed >= %.2f\n', ...
    protocol.minimumNodeTailJaccard, ...
    protocol.minimumPerSeedNodeTailJaccard);
fprintf(fid, ...
    '- Edge task Spearman: overall >= %.2f; every seed >= %.2f\n', ...
    protocol.minimumEdgeTaskSpearman, ...
    protocol.minimumPerSeedEdgeTaskSpearman);
fprintf(fid, ...
    '- Normalized regret: median <= %.2f; P90 <= %.2f\n', ...
    protocol.maximumMedianNormalizedRegret, ...
    protocol.maximumP90NormalizedRegret);
fprintf(fid, ...
    '- Observed-tail false-safe <= %.2f; true-safe recall >= %.2f\n', ...
    protocol.maximumObservedTailFalseSafeFraction, ...
    protocol.minimumObservedTailTrueSafeRecall);
fprintf(fid, '\nEvidence boundary: %s\n', ...
    model.evidenceBoundary);
end

function candidate = emptyCandidate()
candidate = struct( ...
    'family', '', 'rows', [], ...
    'folds', [], 'metrics', struct());
end

function fold = emptyFold()
fold = struct( ...
    'heldoutSeed', 0, ...
    'calibrationSeed', 0, ...
    'fitSeeds', zeros(1, 0), ...
    'safetyMargin', NaN, ...
    'metrics', struct());
end

function row = emptyEvaluationRow()
row = struct( ...
    'seed', 0, 'currentTime', 0, ...
    'family', '', 'calibrationSeed', 0, ...
    'safetyMargin', NaN, ...
    'nodeTailRecall', NaN, ...
    'nodeTailJaccard', NaN, ...
    'nodeTailExact', false, ...
    'edgeTaskSpearman', NaN, ...
    'observedTailFalseSafeCount', 0, ...
    'observedTailPredictedSafeCount', 0, ...
    'observedTailTrueSafeCount', 0, ...
    'observedTailTrueSafeSelectedCount', 0, ...
    'selectedTailSafe', false, ...
    'projectionFeasible', false, ...
    'staticFallbackUsed', false, ...
    'topologyInfeasible', false, ...
    'repairTriggered', false, ...
    'payloadEmergencyUsed', false, ...
    'selectedCrossEdgeCount', 0, ...
    'expectedCrossEdgeCountPassed', false, ...
    'messageCountPassed', false, ...
    'dominantBackbonePreserved', false, ...
    'weightGridPassed', false, ...
    'selectedTrueTaskAdvantage', NaN, ...
    'maximumTrueTaskAdvantage', NaN, ...
    'minimumTrueTaskAdvantage', NaN, ...
    'normalizedRegret', NaN, ...
    'nonnegativeSelectedTask', false);
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
