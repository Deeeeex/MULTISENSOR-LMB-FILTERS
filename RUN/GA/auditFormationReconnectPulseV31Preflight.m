function [reportPath, preflight] = ...
    auditFormationReconnectPulseV31Preflight(options)
% AUDITFORMATIONRECONNECTPULSEV31PREFLIGHT Source-only t=74 probe.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getFormationReconnectPulseProbeProtocol();
gitState = resolveResearchGitState();
allowDirtySource = logical(getField( ...
    options, 'allowDirtySource', false));
if ~allowDirtySource && ...
        (gitState.trackedWorktreeDirty || ...
         ~isempty(gitState.untrackedSourceFiles))
    error(['Official v31 preflight requires a clean tracked and ', ...
        'MATLAB/Octave source state.']);
end
sourceScreenPath = getField(options, 'sourceScreenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v30', 'causal_isolate_reconnect', ...
    't72', 'screen', ...
    ['FORMATION_ISOLATE_RECONNECT_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
sourcePreflightPath = getField(options, ...
    'sourcePreflightPath', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'formation_value_v30', 'causal_isolate_reconnect', ...
        'preflight', ...
        ['FORMATION_CAUSAL_ISOLATE_RECONNECT_V30_', ...
         'PREFLIGHT.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_SAFE_RECONNECT_PULSE_V31_', ...
     'PREFLIGHT_20260802.md']));
matPath = getField(options, 'matPath', fullfile( ...
    protocol.outputRoot, 'preflight', ...
    'FORMATION_SAFE_RECONNECT_PULSE_V31_PREFLIGHT.mat'));

loadedScreen = load(sourceScreenPath, 'screen');
loadedPreflight = load(sourcePreflightPath, 'preflight');
if ~isfield(loadedScreen, 'screen') || ...
        ~isfield(loadedPreflight, 'preflight')
    error('V31Preflight:MissingSource', ...
        'Frozen v30 source evidence is unavailable.');
end
sourceScreen = loadedScreen.screen;
sourcePreflight = loadedPreflight.preflight;
assertSourceProvenance( ...
    sourceScreen, sourcePreflight, protocol);

replayTimer = tic;
[context, replay] = replayV30SourceTrajectory( ...
    sourceScreen, sourcePreflight, protocol);
replaySeconds = toc(replayTimer);
assertReplayMatchesFrozenScreen(replay, sourceScreen);

controlTimer = tic;
control = buildFormationReconnectPulseControl(context);
controlSeconds = toc(controlTimer);
assertControlContract(control, protocol);

cleanSource = ~gitState.trackedWorktreeDirty && ...
    isempty(gitState.untrackedSourceFiles);
preflight = struct();
preflight.contractVersion = ...
    'formation-safe-reconnect-pulse-v31-preflight-v1';
preflight.generatedAt = datestr(now, 31);
preflight.generationGitCommit = gitState.commit;
preflight.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
preflight.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
preflight.protocol = protocol;
preflight.sourceScreenPath = sourceScreenPath;
preflight.sourceScreenGenerationCommit = ...
    sourceScreen.generationGitCommit;
preflight.sourceCachePath = sourceScreen.cachePath;
preflight.sourceCacheSha256 = sourceScreen.cacheSha256;
preflight.presetName = sourceScreen.presetName;
preflight.seed = sourceScreen.seed;
preflight.anchorTime = protocol.anchorTime;
preflight.reconnectTime = protocol.reconnectTime;
preflight.sourceTrajectoryReplaySeconds = replaySeconds;
preflight.controlConstructionSeconds = controlSeconds;
preflight.sourceTrajectoryReplay = replay;
preflight.reconnectControl = control;
preflight.referenceNetworkRisk = ...
    control.referenceScore.networkRisk;
preflight.selectedNetworkRisk = ...
    control.selectedScore.networkRisk;
preflight.selectedDisagreementImprovementFraction = ...
    control.selectedDisagreementImprovementFraction;
preflight.safeSingleActionCount = ...
    control.safeSingleActionCount;
preflight.eligibleSingleActionCount = ...
    control.eligibleSingleActionCount;
preflight.requestedFormationIds = ...
    control.requestedFormationIds;
preflight.requestedPulseWeightByFormation = ...
    control.requestedPulseWeightByFormation;
preflight.selectedFormationIds = ...
    control.selectedFormationIds;
preflight.selectedPulseWeightByFormation = ...
    control.selectedPulseWeightByFormation;
preflight.selectedActionName = control.selectedActionName;
preflight.referenceFallbackUsed = ...
    control.referenceFallbackUsed;
preflight.sourceTrajectoryUsesTruth = false;
preflight.sourceTrajectoryUsesFutureOutcome = false;
preflight.trackingOutcomeScored = false;
preflight.newTrackingStateOpened = false;
preflight.additionalM24StateAuthorized = false;
preflight.gnnTrainingAuthorized = false;
preflight.x36Opened = false;
preflight.x48Opened = false;
preflight.validationClaimAllowed = false;
preflight.trackingOutcomeRerunAuthorized = ...
    protocol.trackingOutcomeRerunAuthorized && ...
    cleanSource && ...
    ~control.referenceFallbackUsed && ...
    control.selectedScore.safe && ...
    control.selectedDisagreementImprovementFraction >= ...
        protocol.minimumDisagreementImprovementFraction - 1e-12 && ...
    all(control.selectedRollingB3SensorPass) && ...
    all(control.selectedRollingB3FormationPass);
preflight.evidenceBoundary = protocol.evidenceBoundary;

if exist(fileparts(matPath), 'dir') ~= 7
    mkdir(fileparts(matPath));
end
preflight.matPath = matPath;
preflight.reportPath = reportPath;
save('-mat7-binary', matPath, 'preflight');
writeReport(reportPath, preflight);
fprintf('V31 reconnect-pulse preflight: %s\n', reportPath);
end

function [context, replay] = replayV30SourceTrajectory( ...
        sourceScreen, sourcePreflight, protocol)
inputs = generateDynamicTopologyScenarioInputs( ...
    protocol.presetName, protocol.seed);
loaded = load(sourceScreen.cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V31Preflight:MissingCache', ...
        'Opened behavior cache is unavailable.');
end
bundle = loaded.behaviorBundle;
returnTimes = protocol.anchorTime:protocol.reconnectTime;
inputs = cropInputs(inputs, protocol.reconnectTime);
history = bundle.preDecisionTopologyHistoryByTime{ ...
    protocol.anchorTime};
previousHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
initialBank = sourcePreflight.initialBank;
actionSequence = [ ...
    sourcePreflight.selectedInitialActionIndex, ...
    initialBank.referenceActionIndex, ...
    initialBank.referenceActionIndex];

config = buildMixtureAwareKlaReferenceConfig();
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = inputs.config.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    2 * inputs.config.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyName = ...
    'formation-h3-causal-isolate-reconnect-v1';
config.topologyPosteriorCaptureTimes = returnTimes;
config.topologyPolicyFcn = @(currentContext) ...
    selectFormationIsolateReconnectRuntimePolicy( ...
        currentContext, protocol.anchorTime, ...
        initialBank, actionSequence);
config.filterInitialLocalPosteriorBySensor = ...
    bundle.posteriorSnapshots{protocol.anchorTime};
config.filterInitialLocalPosteriorTime = protocol.anchorTime;
config.filterInitialPreviousAdjacencyHistory = previousHistory;
config.filterInitialPreviousAdjacencyTimes = history.times;
config.filterInitialPreviousAdjacencyHistorySource = ...
    'opened-reference-continuation-cache-v1';

rng(protocol.seed + 100000);
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    inputs.model, inputs.measurements, ...
    inputs.sensorTrajectories, inputs.neighborMap, ...
    inputs.commConfig, config);
selected = false(inputs.config.numberOfSensors, ...
    inputs.config.numberOfSensors, numel(returnTimes));
for timeIdx = 1:numel(returnTimes)
    selected(:, :, timeIdx) = ...
        convertDiagnosticEdgeMaskToPolicyAdjacency( ...
            diagnostics.topologyActiveEdge( ...
                :, :, returnTimes(timeIdx)));
end
attemptedBytesByTime = reshape(sum(sum( ...
    diagnostics.attemptedPayloadBytes( ...
        :, :, returnTimes), 1), 2), 1, []);
truthUsed = isfinite( ...
    diagnostics.topologyPolicyTruthUsed(returnTimes)) & ...
    diagnostics.topologyPolicyTruthUsed(returnTimes) ~= 0;
if any(truthUsed) || any(~diagnostics.topologyFeasible(returnTimes)) || ...
        any(cellfun(@isempty, ...
            diagnostics.topologyLocalPosteriorSnapshot(returnTimes)))
    error('V31Preflight:InvalidReplay', ...
        'The v30 causal source trajectory replay failed.');
end

previousSelected = selected(:, :, 1:2);
currentTime = protocol.reconnectTime;
context = struct();
context.localPosteriorBySensor = ...
    diagnostics.topologyLocalPosteriorSnapshot{currentTime};
context.model = inputs.model;
context.sensorTrajectories = inputs.sensorTrajectories;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = currentTime;
context.previousAdjacencyHistory = previousSelected;
context.previousAdjacencyHistoryCount = ...
    size(previousSelected, 3);
context.previousAdjacencyHistoryTimes = returnTimes(1:2);
context.previousAdjacency = previousSelected(:, :, end);
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, currentTime));
context.edgeBudget = inputs.config.edgeBudget;
context.directedMessageBudget = ...
    2 * inputs.config.numberOfSensors;
context.positions = ...
    inputs.graphData.positions(:, :, currentTime);

replay = struct();
replay.contractVersion = ...
    'formation-retention-debt-v30-source-replay-v1';
replay.returnTimes = returnTimes;
replay.actionSequenceIndices = actionSequence;
replay.selectedAdjacency = selected;
replay.policyBackboneModeByTime = ...
    diagnostics.topologyPolicyBackboneMode(returnTimes);
replay.attemptedBytesByTime = attemptedBytesByTime;
replay.retentionDebtFractionByTime = ...
    diagnostics. ...
        topologyPolicyRetentionDebtFractionByFormation(returnTimes);
replay.retentionDebtSelectedFormationIdsByTime = ...
    diagnostics. ...
        topologyPolicyRetentionDebtSelectedFormationIds(returnTimes);
replay.posteriorContentUsedByTime = logical( ...
    diagnostics.topologyPolicyPosteriorContentUsed(returnTimes));
replay.currentLinkReliabilityUsedByTime = logical( ...
    diagnostics. ...
        topologyPolicyCurrentLinkReliabilityUsed(returnTimes));
replay.truthUsed = false;
replay.futureOutcomeUsed = false;
replay.trackingOutcomeScored = false;
end

function assertReplayMatchesFrozenScreen(replay, screen)
candidateIdx = setdiff(1:numel(screen.outcomes), ...
    screen.referenceSubsetIndex);
if numel(candidateIdx) ~= 1
    error('V31Preflight:ReplayDrift', ...
        'Frozen v30 candidate is ambiguous.');
end
source = screen.outcomes(candidateIdx);
if ~isequal(replay.returnTimes, screen.returnTimes) || ...
        ~isequal(replay.selectedAdjacency, ...
            source.selectedAdjacency) || ...
        ~isequal(replay.policyBackboneModeByTime, ...
            source.policyBackboneModeByTime) || ...
        ~isequal(replay.attemptedBytesByTime, ...
            source.attemptedBytesByTime) || ...
        ~isequaln(replay.retentionDebtFractionByTime, ...
            source.retentionDebtFractionByTime) || ...
        ~isequal(replay.retentionDebtSelectedFormationIdsByTime, ...
            source.retentionDebtSelectedFormationIdsByTime) || ...
        ~all(replay.posteriorContentUsedByTime) || ...
        ~all(replay.currentLinkReliabilityUsedByTime) || ...
        replay.truthUsed || replay.futureOutcomeUsed || ...
        replay.trackingOutcomeScored
    error('V31Preflight:ReplayDrift', ...
        'Source-only replay does not match the frozen v30 trajectory.');
end
end

function assertSourceProvenance(screen, preflight, protocol)
if ~strcmp(screen.contractVersion, ...
        'formation-causal-isolate-reconnect-v30-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            protocol.sourceV30ScreenGenerationCommit) || ...
        screen.generationTrackedWorktreeDirty || ...
        ~isempty(screen.generationUntrackedSourceFiles) || ...
        ~strcmp(screen.cacheSha256, ...
            protocol.sourceCacheSha256) || ...
        ~strcmp(screen.presetName, protocol.presetName) || ...
        screen.seed ~= protocol.seed || ...
        screen.currentTime ~= protocol.anchorTime || ...
        screen.strictStrongCandidateCount ~= 0 || ...
        screen.strongCandidateFound || ...
        screen.additionalOpenedStateScreenAuthorized || ...
        screen.gnnTrainingAuthorized || ...
        screen.x36OutcomeOpeningAuthorized || ...
        screen.x48OutcomeOpeningAuthorized || ...
        screen.validationClaimAllowed || ...
        ~strcmp(preflight.contractVersion, ...
            'formation-causal-isolate-reconnect-v30-preflight-v1') || ...
        ~preflight.primaryTrackingScreenAuthorized || ...
        preflight.selectedInitialActionIndex ~= 15 || ...
        ~isequal(preflight.selectedFormationIdsAtAnchor, [2, 3, 4])
    error('V31Preflight:SourceProvenance', ...
        'Frozen v30 source provenance changed.');
end
end

function assertControlContract(control, protocol)
if ~strcmp(control.contractVersion, ...
        'formation-reconnect-pulse-control-v1') || ...
        ~strcmp(control.protocolId, protocol.id) || ...
        control.nodeCount ~= protocol.expectedNodeCount || ...
        control.formationCount ~= protocol.expectedFormationCount || ...
        control.evaluatedRouteCount > ...
            protocol.maximumControlRouteEvaluations || ...
        ~control.referenceScore.safe || ...
        ~control.selectedScore.safe || ...
        ~control.messageCountParityWithReference || ...
        ~control.selectionUsesCurrentPosterior || ...
        ~control.selectionUsesCurrentLinkReliability || ...
        ~control.selectionUsesSelectedTopologyHistory || ...
        ~isequal(control.singleActionSafetyMask, ...
            protocol.expectedSingleSafetyMask) || ...
        ~isequal(control.singleActionEligibleMask, ...
            protocol.expectedSingleEligibleMask) || ...
        control.referenceFallbackUsed ~= ...
            protocol.expectedReferenceFallback || ...
        ~all(control.selectedRollingB3SensorPass) || ...
        ~all(control.selectedRollingB3FormationPass) || ...
        control.truthUsed || control.futureOutcomeUsed || ...
        control.validationClaimAllowed
    error('V31Preflight:ControlContract', ...
        'Reconnect-pulse controller violated a frozen invariant.');
end
end

function writeReport(path, preflight)
control = preflight.reconnectControl;
fid = fopen(path, 'w');
if fid < 0
    error('V31Preflight:WriteFailed', ...
        'Could not open v31 preflight report path.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V31 safe reconnect-pulse preflight\n\n');
fprintf(fid, '- Contract: `%s`\n', preflight.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    preflight.generationGitCommit);
fprintf(fid, '- Tracked worktree dirty: `%d`\n', ...
    preflight.generationTrackedWorktreeDirty);
fprintf(fid, '- Untracked source files: `%d`\n', ...
    numel(preflight.generationUntrackedSourceFiles));
fprintf(fid, '- Preset / seed / reconnect time: `%s / %d / %d`\n', ...
    preflight.presetName, preflight.seed, ...
    preflight.reconnectTime);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    preflight.sourceCacheSha256);
fprintf(fid, '- Source trajectory replay matched frozen v30: `1`\n');
fprintf(fid, '- Tracking outcome scored: `0`\n');
fprintf(fid, '- Safe / eligible single pulses: `%d / %d`\n', ...
    preflight.safeSingleActionCount, ...
    preflight.eligibleSingleActionCount);
fprintf(fid, '- Requested / selected formations: `%s / %s`\n', ...
    mat2str(preflight.requestedFormationIds), ...
    mat2str(preflight.selectedFormationIds));
fprintf(fid, '- Selected action: `%s`\n', ...
    preflight.selectedActionName);
fprintf(fid, '- Predicted disagreement improvement: `%+.4f%%`\n', ...
    100 * preflight.selectedDisagreementImprovementFraction);
fprintf(fid, '- Tracking rerun authorized: `%d`\n', ...
    preflight.trackingOutcomeRerunAuthorized);
fprintf(fid, '- Replay / control construction: `%.2f / %.2f s`\n\n', ...
    preflight.sourceTrajectoryReplaySeconds, ...
    preflight.controlConstructionSeconds);

fprintf(fid, '## t=74 pulse diagnostics\n\n');
fprintf(fid, [ ...
    '| Formation | Pulse weight | Disagreement improvement | ', ...
    'Retention risk | Min form. d-card | Min label retention | ', ...
    'Threshold drops | Safe | Eligible |\n']);
fprintf(fid, ...
    '|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|\n');
for formationIdx = 1:control.formationCount
    for levelIdx = 1:numel(control.pulseResidualWeights)
        score = control.singleActionScores{formationIdx, levelIdx};
        retentionRisk = NaN;
        minimumCardinality = NaN;
        minimumRetention = NaN;
        thresholdDrops = NaN;
        if ~isempty(score)
            retentionRisk = score.retentionRisk;
            minimumCardinality = ...
                score.minimumFormationCardinalityChange;
            minimumRetention = ...
                score.minimumSupportedLabelRetentionRatio;
            thresholdDrops = ...
                score.decisionThresholdCrossingCount;
        end
        fprintf(fid, [ ...
            '| %d | %.3f | %+.4f%% | %.6f | %+.6f | %.6f ', ...
            '| %.0f | %d | %d |\n'], ...
            control.groups(formationIdx), ...
            control.pulseResidualWeights(levelIdx), ...
            100 * control. ...
                singleDisagreementImprovementFraction( ...
                    formationIdx, levelIdx), ...
            retentionRisk, minimumCardinality, ...
            minimumRetention, thresholdDrops, ...
            control.singleActionSafetyMask(formationIdx, levelIdx), ...
            control.singleActionEligibleMask(formationIdx, levelIdx));
    end
end

fprintf(fid, '\n## Decision\n\n');
if control.referenceFallbackUsed
    fprintf(fid, [ ...
        'No nonreference pulse is both label-safe and predicted to ', ...
        'reduce one-round disagreement by the registered margin. Stop ', ...
        'before rerunning the t=72 tracking outcome.\n\n']);
elseif preflight.trackingOutcomeRerunAuthorized
    fprintf(fid, [ ...
        'The clean frozen source-only controller selects `%s`; the same ', ...
        't=72 paired outcome may be rerun with this pulse only. No other ', ...
        'M24 state, GNN, X36, or X48 is authorized.\n\n'], ...
        control.selectedActionName);
else
    fprintf(fid, [ ...
        'A source-only nonreference pulse exists, but this exploratory ', ...
        'or dirty preflight does not authorize a tracking rerun. Freeze ', ...
        'the selection contract and reproduce it on clean source first.\n\n']);
end
fprintf(fid, '## Evidence boundary\n\n%s\n', ...
    preflight.evidenceBoundary);
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
if isfield(inputs.commConfig, 'pDropByEdge') && ...
        ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
end
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
inputs.model.simulationLength = maximumTime;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
