function [reportPath, audit] = ...
    auditFormationScaleAwareMixingV27RetentionSignal(options)
% AUDITFORMATIONSCALEAWAREMIXINGV27RETENTIONSIGNAL
% Re-score the frozen v27 action bank using current-posterior-only signals.
%
% No tracking continuation is executed.  The audit reconstructs the same
% already-opened t=72 posterior, integrates one-round link outcomes, and
% compares each action with the registered reference using the v28
% existence-retention diagnostic.

if nargin < 1 || isempty(options)
    options = struct();
end
screenPath = getField(options, 'screenPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v27', 'scale_aware_residual_mixing', ...
    't72', 'screen', ...
    ['FORMATION_SCALE_AWARE_MIXING_H3_M24_FORMATION_FOV_', ...
     'SEED211_T72.mat']));
reportPath = getField(options, 'reportPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    ['FORMATION_SCALE_AWARE_RESIDUAL_MIXING_V27_', ...
     'RETENTION_SIGNAL_AUDIT_20260802.md']));
loaded = load(screenPath, 'screen');
if ~isfield(loaded, 'screen')
    error('V27RetentionAudit:MissingScreen', ...
        'Frozen v27 screen is unavailable.');
end
screen = loaded.screen;
assertScreenProvenance(screen);
context = reconstructContext(screen);
groupIds = reshape(screen.sensorGroupIds, 1, []);
actionCount = screen.bank.actionCount;
referenceActionIndex = screen.bank.referenceActionIndex;

receiverDistributionsByAction = cell(1, actionCount);
networkDisagreementRisk = zeros(1, actionCount);
networkDisagreementDetails = cell(1, actionCount);
for actionIdx = 1:actionCount
    fprintf('v27 retention signal action %d/%d: %s\n', ...
        actionIdx, actionCount, screen.bank.actionNames{actionIdx});
    [networkDisagreementRisk(actionIdx), ...
        networkDisagreementDetails{actionIdx}] = ...
            computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
                context, ...
                screen.bank.actionAdjacency(:, :, actionIdx), ...
                screen.bank.actionFusionWeights(:, :, actionIdx), ...
                struct('maximumIncomingCount', 4));
    receiverDistributionsByAction{actionIdx} = ...
        networkDisagreementDetails{actionIdx}.receiverDistributions;
end

referenceDistributions = ...
    receiverDistributionsByAction{referenceActionIndex};
retentionRisk = zeros(1, actionCount);
retentionDetails = cell(1, actionCount);
minimumFormationCardinalityChange = zeros(1, actionCount);
minimumReceiverCardinalityChange = zeros(1, actionCount);
minimumSupportedLabelRetentionRatio = ones(1, actionCount);
thresholdCrossingCount = zeros(1, actionCount);
maximumExistenceDrift = zeros(1, actionCount);
for actionIdx = 1:actionCount
    [retentionRisk(actionIdx), retentionDetails{actionIdx}] = ...
        computeLmbReferenceExistenceRetentionRisk( ...
            referenceDistributions, ...
            receiverDistributionsByAction{actionIdx}, ...
            groupIds);
    current = retentionDetails{actionIdx};
    minimumFormationCardinalityChange(actionIdx) = min( ...
        current.formationMeanCardinalityChange);
    minimumReceiverCardinalityChange(actionIdx) = min( ...
        current.expectedCardinalityChange);
    minimumSupportedLabelRetentionRatio(actionIdx) = min( ...
        current.minimumSupportedLabelRetentionRatio);
    thresholdCrossingCount(actionIdx) = sum( ...
        current.decisionThresholdCrossingCount);
    maximumExistenceDrift(actionIdx) = max( ...
        current.normalizedExistenceDrift);
end

[posteriorBayesRiskObjectives, posteriorBayesRiskDetails] = ...
    computeFormationModePosteriorBayesRiskObjectives( ...
        receiverDistributionsByAction, groupIds, struct( ...
            'referenceModeIndex', referenceActionIndex, ...
            'receiverTailFraction', 0.34, ...
            'receiverTailWeight', 0.50));
meanPosteriorBayesRiskAdvantage = mean( ...
    posteriorBayesRiskObjectives, 1);
minimumPosteriorBayesRiskAdvantage = min( ...
    posteriorBayesRiskObjectives, [], 1);

meanGainPercent = [screen.records.meanGainPercent];
trackingLossPercent = -meanGainPercent;
actualMeanCardinalityError = ...
    [screen.outcomes.meanCardinalityError];
nonreference = true(1, actionCount);
nonreference(referenceActionIndex) = false;
correlations = struct();
correlations.retentionRiskVsTrackingLoss = pearsonCorrelation( ...
    retentionRisk(nonreference), trackingLossPercent(nonreference));
correlations.minimumFormationCardinalityChangeVsTrackingGain = ...
    pearsonCorrelation( ...
        minimumFormationCardinalityChange(nonreference), ...
        meanGainPercent(nonreference));
correlations.posteriorBayesRiskAdvantageVsTrackingGain = ...
    pearsonCorrelation( ...
        meanPosteriorBayesRiskAdvantage(nonreference), ...
        meanGainPercent(nonreference));
correlations.networkDisagreementImprovementVsTrackingGain = ...
    pearsonCorrelation( ...
        networkDisagreementRisk(referenceActionIndex) - ...
            networkDisagreementRisk(nonreference), ...
        meanGainPercent(nonreference));
correlations.retentionRiskVsActualCardinalityErrorIncrease = ...
    pearsonCorrelation( ...
        retentionRisk(nonreference), ...
        actualMeanCardinalityError(nonreference) - ...
            actualMeanCardinalityError(referenceActionIndex));

audit = struct();
audit.contractVersion = ...
    'formation-v27-reference-retention-signal-audit-v1';
audit.generatedAt = datestr(now, 31);
audit.sourceScreenPath = screenPath;
audit.sourceGenerationCommit = screen.generationGitCommit;
audit.sourceCacheSha256 = screen.cacheSha256;
audit.actionNames = screen.bank.actionNames;
audit.actionMixingGap = ...
    screen.bank.actionFormationMixingSpectralGapProxy;
audit.networkDisagreementRisk = networkDisagreementRisk;
audit.retentionRisk = retentionRisk;
audit.retentionDetails = retentionDetails;
audit.minimumFormationCardinalityChange = ...
    minimumFormationCardinalityChange;
audit.minimumReceiverCardinalityChange = ...
    minimumReceiverCardinalityChange;
audit.minimumSupportedLabelRetentionRatio = ...
    minimumSupportedLabelRetentionRatio;
audit.thresholdCrossingCount = thresholdCrossingCount;
audit.maximumExistenceDrift = maximumExistenceDrift;
audit.meanPosteriorBayesRiskAdvantage = ...
    meanPosteriorBayesRiskAdvantage;
audit.minimumPosteriorBayesRiskAdvantage = ...
    minimumPosteriorBayesRiskAdvantage;
audit.posteriorBayesRiskDetails = posteriorBayesRiskDetails;
audit.meanGainPercent = meanGainPercent;
audit.actualMeanCardinalityError = actualMeanCardinalityError;
audit.correlations = correlations;
audit.currentPosteriorUsed = true;
audit.currentLinkReliabilityUsed = true;
audit.truthUsedForSignals = false;
audit.futureOutcomeUsedForSignals = false;
audit.savedOutcomeUsedForDiagnosticCorrelationOnly = true;
audit.newTrackingStateOpened = false;
audit.gnnTrainingAuthorized = false;
audit.x36Opened = false;
audit.x48Opened = false;
audit.validationClaimAllowed = false;
audit.evidenceBoundary = [ ...
    'All candidate signals use only the already-opened current posterior, ', ...
    'current physical graph, and current delivery probabilities. Saved ', ...
    'tracking outcomes are read only after scoring to diagnose alignment. ', ...
    'The action-level correlations share one state and are not ', ...
    'generalization evidence or independent samples.'];

writeReport(reportPath, audit, screen);
fprintf('V27 retention-signal audit: %s\n', reportPath);
end

function context = reconstructContext(screen)
inputs = generateDynamicTopologyScenarioInputs( ...
    screen.presetName, screen.seed);
loaded = load(screen.cachePath, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    error('V27RetentionAudit:MissingCache', ...
        'Opened behavior cache is unavailable.');
end
bundle = loaded.behaviorBundle;
if ~strcmp(bundle.presetName, screen.presetName) || ...
        bundle.seed ~= screen.seed || ...
        ~isequal(bundle.snapshotTimes, screen.currentTime) || ...
        ~isequaln(bundle.configSnapshot, inputs.config) || ...
        ~bundle.openedDevelopmentEvidenceOnly || ...
        bundle.validationClaimAllowed
    error('V27RetentionAudit:CacheProvenance', ...
        'Opened behavior cache provenance changed.');
end
context = struct();
context.localPosteriorBySensor = ...
    bundle.posteriorSnapshots{screen.currentTime};
context.model = inputs.model;
context.commConfig = inputs.commConfig;
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.currentTime = screen.currentTime;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = logical( ...
    inputs.graphData.physicalAdjacency(:, :, screen.currentTime));
context.positions = inputs.graphData.positions(:, :, screen.currentTime);
end

function assertScreenProvenance(screen)
if ~strcmp(screen.contractVersion, ...
        'formation-scale-aware-residual-mixing-v27-screen-v1') || ...
        ~strcmp(screen.generationGitCommit, ...
            '9d9fc7e003a868f688718061aac5c01eebb0b78d') || ...
        ~strcmp(screen.cacheSha256, ...
            ['60dfbf2615181cde046af15f42bba37c415ea0034cb7ce536', ...
             '85b79042bfaf762']) || ...
        ~strcmp(screen.presetName, 'm24-formation-fov') || ...
        screen.seed ~= 211 || screen.currentTime ~= 72 || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed || ...
        screen.strictStrongCandidateCount ~= 0
    error('V27RetentionAudit:ScreenProvenance', ...
        'Frozen v27 screen provenance changed.');
end
end

function correlation = pearsonCorrelation(left, right)
left = reshape(left, [], 1);
right = reshape(right, [], 1);
if numel(left) ~= numel(right) || numel(left) < 2 || ...
        any(~isfinite(left)) || any(~isfinite(right))
    error('V27RetentionAudit:InvalidCorrelation', ...
        'Correlation inputs are invalid.');
end
left = left - mean(left);
right = right - mean(right);
denominator = sqrt(sum(left.^2) * sum(right.^2));
if denominator <= eps
    correlation = NaN;
else
    correlation = sum(left .* right) / denominator;
end
end

function writeReport(path, audit, screen)
fid = fopen(path, 'w');
if fid < 0
    error('V27RetentionAudit:WriteFailed', ...
        'Could not open retention-signal report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V27 reference-retention signal audit\n\n');
fprintf(fid, '- Contract: `%s`\n', audit.contractVersion);
fprintf(fid, '- Source generation commit: `%s`\n', ...
    audit.sourceGenerationCommit);
fprintf(fid, '- Source cache SHA-256: `%s`\n', ...
    audit.sourceCacheSha256);
fprintf(fid, '- New tracking state opened: `0`\n');
fprintf(fid, '- Signal truth/future use: `0 / 0`\n\n');
fprintf(fid, [ ...
    '| Action | Mix gap | One-step disagreement | Retention risk | ', ...
    'Min formation d-card | Min label retention | Threshold drops | ', ...
    'Bayes-risk advantage | Tracking gain | Actual card. error |\n']);
fprintf(fid, [ ...
    '|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n']);
for actionIdx = 1:numel(audit.actionNames)
    fprintf(fid, [ ...
        '| `%s` | %.6f | %.6f | %.6f | %+.6f | %.6f | ', ...
        '%d | %+.6f | %+.3f%% | %.6f |\n'], ...
        audit.actionNames{actionIdx}, ...
        audit.actionMixingGap(actionIdx), ...
        audit.networkDisagreementRisk(actionIdx), ...
        audit.retentionRisk(actionIdx), ...
        audit.minimumFormationCardinalityChange(actionIdx), ...
        audit.minimumSupportedLabelRetentionRatio(actionIdx), ...
        audit.thresholdCrossingCount(actionIdx), ...
        audit.meanPosteriorBayesRiskAdvantage(actionIdx), ...
        audit.meanGainPercent(actionIdx), ...
        audit.actualMeanCardinalityError(actionIdx));
end

c = audit.correlations;
fprintf(fid, '\n## Within-state diagnostic alignment\n\n');
fprintf(fid, [ ...
    '- Retention risk vs. tracking loss: `r = %.6f`\n', ...
    '- Minimum formation expected-cardinality change vs. tracking gain: ', ...
    '`r = %.6f`\n', ...
    '- Existing posterior Bayes-risk advantage vs. tracking gain: ', ...
    '`r = %.6f`\n', ...
    '- One-step disagreement improvement vs. tracking gain: ', ...
    '`r = %.6f`\n', ...
    '- Retention risk vs. actual cardinality-error increase: ', ...
    '`r = %.6f`\n\n'], ...
    c.retentionRiskVsTrackingLoss, ...
    c.minimumFormationCardinalityChangeVsTrackingGain, ...
    c.posteriorBayesRiskAdvantageVsTrackingGain, ...
    c.networkDisagreementImprovementVsTrackingGain, ...
    c.retentionRiskVsActualCardinalityErrorIncrease);

fprintf(fid, '## Interpretation boundary\n\n');
fprintf(fid, '%s\n\n', audit.evidenceBoundary);
fprintf(fid, [ ...
    'The new signal is an asymmetric safety diagnostic: it penalizes ', ...
    'loss of reference-supported existence mass but does not claim the ', ...
    'reference is ground truth. It is eligible for v28 only if this ', ...
    'audit shows materially better mechanism alignment than the existing ', ...
    'internal Bayes-risk and disagreement objectives. Thresholds and the ', ...
    'new pairwise action space must be frozen before another tracking ', ...
    'continuation is executed.\n\n']);
fprintf(fid, 'Frozen v27 strong candidates remain `%d/%d`.\n', ...
    screen.strictStrongCandidateCount, ...
    numel(screen.records) - 1);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
