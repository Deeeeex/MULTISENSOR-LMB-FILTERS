function [reportPath, result] = ...
        runLabelSelectiveRiskShortcutV265Continuation(options)
% RUNLABELSELECTIVERISKSHORTCUTV265CONTINUATION One causal M24 arm.

if nargin < 1 || isempty(options), options = struct(); end
variant = lower(char(getField(options, 'variant', 'v265')));
if strcmp(variant, 'v266')
    protocol = getEtaProjectedLabelTrustV266Protocol();
elseif strcmp(variant, 'v267')
    protocol = getAsymmetricEtaRetentionV267Protocol();
elseif strcmp(variant, 'v265')
    protocol = getLabelSelectiveRiskShortcutV265Protocol();
else
    error('LabelSelectiveRiskShortcut:UnknownVariant', ...
        'The continuation variant must be v265, v266 or v267.');
end
tracePath = char(getField(options, 'tracePath', ''));
resume = logical(getField(options, 'resume', true));
if isempty(tracePath) || exist(tracePath, 'file') ~= 2 || ...
        ~islogical(resume) || ~isscalar(resume)
    error('LabelSelectiveRiskShortcutV265:InvalidRunRequest', ...
        'V265 requires the completed V259 trace and a scalar resume flag.');
end
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('LabelSelectiveRiskShortcutV265:DirtySource', ...
        'Official V265 execution requires clean source.');
end

loaded = load(tracePath, 'result', 'behaviorBundle');
if ~isfield(loaded, 'result') || ~isfield(loaded, 'behaviorBundle')
    error('LabelSelectiveRiskShortcutV265:MalformedTrace', ...
        'The V259 trace lacks its result or behavior bundle.');
end
trace = loaded.result;
bundle = loaded.behaviorBundle;
validateTrace(trace, bundle, protocol);
referenceEnvelope = load(trace.referenceResultPath, 'result');
reference = referenceEnvelope.result;

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outputRoot = char(getField(options, 'outputRoot', protocol.outputRoot));
if ~isAbsolutePath(outputRoot)
    outputRoot = fullfile(repoRoot, outputRoot);
end
if exist(outputRoot, 'dir') ~= 7, mkdir(outputRoot); end
matPath = fullfile(outputRoot, ...
    protocol.resultFileName);
reportPath = fullfile(outputRoot, ...
    protocol.reportFileName);
if resume && exist(matPath, 'file') == 2
    checkpoint = load(matPath, 'result');
    if isfield(checkpoint, 'result') && ...
            isCompleteResult(checkpoint.result, protocol) && ...
            strcmp(checkpoint.result.generationGitCommit, gitState.commit) && ...
            strcmp(checkpoint.result.tracePath, tracePath)
        result = checkpoint.result;
        writeReport(reportPath, result);
        fprintf('Reused completed %s continuation: %s\n', ...
            upper(variant), reportPath);
        return;
    end
end

inputs = generateDynamicTopologyScenarioInputs( ...
    bundle.presetName, bundle.seed);
inputs = cropInputs(inputs, protocol.continuationEndTime);
times = protocol.continuationStartTime:protocol.continuationEndTime;
initialPosteriors = ...
    bundle.posteriorSnapshots{protocol.continuationStartTime};
initialHistory = bundle.preDecisionTopologyHistoryByTime{ ...
    protocol.continuationStartTime};
referenceWindowBytes = reconstructReferenceWindowBytes( ...
    inputs, bundle, times);
v242 = scoreStoredArm(trace.passiveArm, inputs.config, ...
    times, referenceWindowBytes, 'V242 minimum backbone', protocol);
v242.splicedStaticByteSavingPercent = 100 * ...
    (reference.fixedTree.attemptedPayloadBytes - ...
    trace.passiveArm.attemptedPayloadBytes) / ...
    reference.fixedTree.attemptedPayloadBytes;

if strcmp(variant, 'v266')
    config = buildEtaProjectedLabelTrustV266Config(inputs.config);
elseif strcmp(variant, 'v267')
    config = buildAsymmetricEtaRetentionV267Config(inputs.config);
else
    config = buildLabelSelectiveRiskShortcutV265Config(inputs.config);
end
config = attachContinuation(config, initialPosteriors, initialHistory, ...
    protocol.continuationStartTime, tracePath);
if strcmp(variant, 'v266')
    execution = buildEtaProjectedLabelTrustV266ExecutionContext( ...
        bundle.presetName, bundle.seed, protocol.continuationEndTime);
elseif strcmp(variant, 'v267')
    execution = buildAsymmetricEtaRetentionV267ExecutionContext( ...
        bundle.presetName, bundle.seed, protocol.continuationEndTime);
else
    execution = buildLabelSelectiveRiskShortcutV265ExecutionContext( ...
        bundle.presetName, bundle.seed, protocol.continuationEndTime);
end
filterModel = removeRealizedTargetTruthFromDynamicTopologyModel( ...
    inputs.model);
rng(bundle.seed + protocol.filterSeedOffset, 'twister');
fprintf('%s continuation, t=%d--%d ...\n', ...
    upper(variant), ...
    protocol.continuationStartTime, protocol.continuationEndTime);
timerId = tic;
[estimates, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    filterModel, inputs.measurements, inputs.sensorTrajectories, ...
    inputs.neighborMap, inputs.commConfig, config, execution);
candidate = scoreCandidate(estimates, diagnostics, ...
    inputs.groundTruthRfs, inputs.config, times, toc(timerId), ...
    trace, reference, referenceWindowBytes, protocol);
comparison = compareArms(candidate, v242, protocol);
assertCandidate(candidate, comparison, inputs.config, protocol);

result = struct();
result.contractVersion = protocol.resultContractVersion;
result.protocolId = protocol.id;
result.protocol = protocol;
result.generationGitCommit = gitState.commit;
result.tracePath = tracePath;
result.traceGenerationGitCommit = trace.generationGitCommit;
result.referenceGenerationGitCommit = reference.generationGitCommit;
result.presetName = bundle.presetName;
result.seed = bundle.seed;
result.v242 = v242;
result.candidate = candidate;
result.comparison = comparison;
result.actionMechanismPassed = comparison.shortHorizonGatePassed;
result.fullM24RunAuthorized = result.actionMechanismPassed;
result.nextMethodDecision = conditionalValue( ...
    result.actionMechanismPassed, ...
    protocol.passDecision, protocol.failDecision);
result.completedAt = datestr(now, 31);
result.matPath = matPath;
result.reportPath = reportPath;
result.developmentEvidenceOnly = true;
result.validationClaimAllowed = false;
result.evidenceBoundary = protocol.evidenceBoundary;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf(['%s complete: E/R/C %+.3f%%/%+.3f%%/%+.3f%%; ', ...
    'F4 event E/R %+.3f%%/%+.3f%%; gate %d\n'], ...
    upper(variant), ...
    comparison.eospaGainPercent, comparison.rmseGainPercent, ...
    comparison.consistencyGainPercent, ...
    comparison.eventFormationEospaGainPercent, ...
    comparison.eventFormationRmseGainPercent, ...
    comparison.shortHorizonGatePassed);
fprintf('%s report: %s\n', upper(variant), reportPath);
end

function validateTrace(trace, bundle, protocol)
valid = isstruct(trace) && isscalar(trace) && ...
    isfield(trace, 'contractVersion') && ...
    strcmp(trace.contractVersion, ...
        'risk-decomposed-horizon-v259-passive-trace-result-v1') && ...
    isfield(trace, 'passiveComparison') && ...
    trace.passiveComparison.exactOutcomeReproductionPassed && ...
    isstruct(bundle) && isscalar(bundle) && ...
    strcmp(bundle.presetName, protocol.allowedPresets{1}) && ...
    bundle.seed == protocol.allowedSeeds(1) && ...
    numel(bundle.posteriorSnapshots) >= protocol.continuationEndTime && ...
    numel(bundle.preDecisionTopologyHistoryByTime) >= ...
        protocol.continuationEndTime;
if ~valid
    error('LabelSelectiveRiskShortcutV265:TraceContract', ...
        'The V259 trace does not satisfy the V265 source contract.');
end
end

function arm = scoreStoredArm(source, config, times, bytes, name, protocol)
eospa = source.positionEospaBySensorTime(:, times);
rmse = source.positionRmseBySensorTime(:, times);
cardinality = source.absoluteCardinalityErrorBySensorTime(:, times);
arm = scoreMatrices(eospa, rmse, cardinality, config);
arm.name = name;
arm.windowAttemptedPayloadBytes = bytes;
arm.interFormationPositionOspa = mean( ...
    source.interFormationPositionOspaByTime(times));
[arm.eventFormationEospa, arm.eventFormationRmse, ...
 arm.eventFormationCardinality] = eventFormationMetrics( ...
    eospa, rmse, cardinality, times, config, protocol);
arm.labelShortcutActiveTimes = zeros(1, 0);
arm.completed = true;
end

function arm = scoreCandidate(estimates, diagnostics, truth, config, ...
        times, elapsedSeconds, trace, reference, ...
        referenceWindowBytes, protocol)
sensorCount = numel(estimates);
eospa = zeros(sensorCount, numel(times));
rmse = nan(sensorCount, numel(times));
cardinality = zeros(sensorCount, numel(times));
for sensorIdx = 1:sensorCount
    allRmse = computeSetRmseOverTime(estimates{sensorIdx}, truth);
    rmse(sensorIdx, :) = allRmse(times);
    for localTime = 1:numel(times)
        currentTime = times(localTime);
        components = computePositionEuclideanOspa( ...
            truth.x{currentTime}, estimates{sensorIdx}.mu{currentTime}, ...
            config.ospaPositionCutoff, 2, [1, 2]);
        eospa(sensorIdx, localTime) = components(1);
        cardinality(sensorIdx, localTime) = abs( ...
            numel(estimates{sensorIdx}.mu{currentTime}) - ...
            numel(truth.x{currentTime}));
    end
end
arm = scoreMatrices(eospa, rmse, cardinality, config);
arm.name = protocol.displayName;
arm.elapsedSeconds = elapsedSeconds;
arm.interFormationPositionOspa = candidateConsistency( ...
    estimates, config.sensorGroupIds, config.ospaPositionCutoff, times);
attempted = diagnostics.attemptedPayloadBytes(:, :, times);
arm.windowAttemptedPayloadBytes = sum(attempted(:));
arm.referenceWindowAttemptedPayloadBytes = referenceWindowBytes;
arm.windowByteChangeOverV242Percent = 100 * ...
    (referenceWindowBytes - arm.windowAttemptedPayloadBytes) / ...
        max(referenceWindowBytes, eps);
arm.splicedFullTraceAttemptedPayloadBytes = ...
    trace.passiveArm.attemptedPayloadBytes - referenceWindowBytes + ...
        arm.windowAttemptedPayloadBytes;
arm.splicedStaticByteSavingPercent = 100 * ...
    (reference.fixedTree.attemptedPayloadBytes - ...
        arm.splicedFullTraceAttemptedPayloadBytes) / ...
        max(reference.fixedTree.attemptedPayloadBytes, eps);
arm.messageCountByTime = reshape( ...
    diagnostics.topologyDirectedMessageCount(times), 1, []);
arm.physicalFeasibilityPassed = all(diagnostics.topologyFeasible(times));
arm.policyTruthUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyTruthUsed(times));
arm.policyFutureOutcomeUsed = anyFiniteNonzero( ...
    diagnostics.topologyPolicyFutureOutcomeUsed(times));
arm.instantaneousStrongPassed = true;
for currentTime = times
    arm.instantaneousStrongPassed = ...
        arm.instantaneousStrongPassed && isStronglyConnected( ...
            logical(diagnostics.topologyActiveEdge(:, :, currentTime)));
end
arm.labelShortcutActiveByTime = false(1, numel(times));
arm.gatewayAlignedByTime = false(1, numel(times));
arm.sourceSensorIdByTime = zeros(1, numel(times));
arm.receiverSensorIdByTime = zeros(1, numel(times));
arm.targetFormationIdByTime = zeros(1, numel(times));
arm.donorFormationIdByTime = zeros(1, numel(times));
arm.selectedLabelByTime = repmat({zeros(2, 0)}, 1, numel(times));
arm.sourceLabelExistenceByTime = nan(1, numel(times));
arm.sourceLabelLocalizationRiskByTime = nan(1, numel(times));
arm.targetLabelLocalizationRiskByTime = nan(1, numel(times));
arm.donorLabelLocalizationRiskByTime = nan(1, numel(times));
arm.etaProjectionRejectionReasonByTime = repmat({''}, 1, numel(times));
arm.etaReferenceExistenceByTime = nan(1, numel(times));
arm.etaCandidateExistenceByTime = nan(1, numel(times));
arm.etaLogOddsChangeByTime = nan(1, numel(times));
arm.etaLogNormalizerByTime = nan(1, numel(times));
arm.etaLowerLogOddsMarginByTime = nan(1, numel(times));
arm.etaUpperLogOddsMarginByTime = nan(1, numel(times));
arm.selectedSourceWeightByTime = zeros(1, numel(times));
for localTime = 1:numel(times)
    currentTime = times(localTime);
    schedule = diagnostics.topologyPolicyScheduleCertificate{currentTime};
    arm.labelShortcutActiveByTime(localTime) = logical(getField( ...
        schedule, 'labelShortcutActive', false));
    arm.gatewayAlignedByTime(localTime) = logical(getField( ...
        schedule, 'labelShortcutGatewayAligned', false));
    arm.sourceSensorIdByTime(localTime) = getField( ...
        schedule, 'labelShortcutSourceSensorId', 0);
    arm.receiverSensorIdByTime(localTime) = getField( ...
        schedule, 'labelShortcutReceiverSensorId', 0);
    arm.targetFormationIdByTime(localTime) = getField( ...
        schedule, 'selectedLocalizationFormationId', 0);
    arm.donorFormationIdByTime(localTime) = getField( ...
        schedule, 'selectedDonorFormationId', 0);
    arm.selectedLabelByTime{localTime} = getField( ...
        schedule, 'selectedLocalizationLabel', zeros(2, 0));
    arm.sourceLabelExistenceByTime(localTime) = getField( ...
        schedule, 'labelShortcutSourceExistence', NaN);
    arm.sourceLabelLocalizationRiskByTime(localTime) = getField( ...
        schedule, 'labelShortcutSourceLocalizationRisk', NaN);
    arm.targetLabelLocalizationRiskByTime(localTime) = getField( ...
        schedule, 'targetLabelLocalizationRisk', NaN);
    arm.donorLabelLocalizationRiskByTime(localTime) = getField( ...
        schedule, 'donorLabelLocalizationRisk', NaN);
    pageDetails = diagnostics. ...
        topologyPolicyLabelInputRouteDetails{currentTime};
    receiverId = arm.receiverSensorIdByTime(localTime);
    if isstruct(pageDetails) && isscalar(pageDetails) && ...
            receiverId >= 1 && ...
            receiverId <= numel(pageDetails.etaProjectionByReceiver)
        evaluation = ...
            pageDetails.etaProjectionByReceiver{receiverId};
        if isstruct(evaluation) && isscalar(evaluation) && ...
                ~isempty(fieldnames(evaluation))
            arm.selectedSourceWeightByTime(localTime) = getField( ...
                evaluation, 'selectedSourceWeight', ...
                getField(schedule, 'labelShortcutSourceWeight', 0));
            selectedEvaluation = getField( ...
                evaluation, 'selectedEvaluation', evaluation);
            arm.etaProjectionRejectionReasonByTime{localTime} = ...
                getField(evaluation, 'rejectionReason', ...
                getField(selectedEvaluation, 'rejectionReason', ''));
            arm.etaReferenceExistenceByTime(localTime) = ...
                getField(selectedEvaluation, 'referenceExistence', NaN);
            arm.etaCandidateExistenceByTime(localTime) = ...
                getField(selectedEvaluation, 'candidateExistence', NaN);
            projection = getField( ...
                selectedEvaluation, 'projection', struct());
            if isstruct(projection) && isscalar(projection)
                candidateLogOdds = getField( ...
                    projection, 'candidateLogOdds', NaN);
                referenceLogOdds = getField( ...
                    projection, 'referenceLogOdds', NaN);
                arm.etaLogOddsChangeByTime(localTime) = ...
                    candidateLogOdds - referenceLogOdds;
                arm.etaLogNormalizerByTime(localTime) = getField( ...
                    projection, 'logEta', NaN);
                arm.etaLowerLogOddsMarginByTime(localTime) = getField( ...
                    projection, 'lowerLogOddsMargin', NaN);
                arm.etaUpperLogOddsMarginByTime(localTime) = getField( ...
                    projection, 'upperLogOddsMargin', NaN);
            end
        end
    end
end
arm.labelShortcutActiveTimes = times(arm.labelShortcutActiveByTime);
arm.scheduledByTime = reshape( ...
    diagnostics.topologyPolicyLabelInputRouteScheduled(times), 1, []);
arm.transportDeliveredByTime = reshape( ...
    diagnostics.topologyPolicyLabelInputRouteTransportDelivered(times), ...
    1, []);
arm.appliedByTime = reshape( ...
    diagnostics.topologyPolicyLabelInputRouteApplied(times), 1, []);
arm.labelPayloadAttemptedBytesByTime = reshape( ...
    diagnostics.topologyPolicyLabelInputRouteAttemptedBytes(times), 1, []);
arm.labelPayloadDeliveredBytesByTime = reshape( ...
    diagnostics.topologyPolicyLabelInputRouteDeliveredBytes(times), 1, []);
arm.labelPayloadAttemptedBytes = ...
    sum(arm.labelPayloadAttemptedBytesByTime);
arm.labelPayloadDeliveredBytes = ...
    sum(arm.labelPayloadDeliveredBytesByTime);
arm.centralizedDevelopmentController = true;
arm.distributedControlSynopsisCostIncluded = false;
[arm.eventFormationEospa, arm.eventFormationRmse, ...
 arm.eventFormationCardinality] = eventFormationMetrics( ...
    eospa, rmse, cardinality, times, config, protocol);
arm.completed = true;
end

function arm = scoreMatrices(eospa, rmse, cardinality, config)
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
arm = struct();
arm.positionEospa = mean(eospa(:));
arm.positionRmse = finiteMean(rmse(:));
arm.meanAbsoluteCardinalityError = mean(cardinality(:));
arm.positionEospaByTime = mean(eospa, 1);
arm.positionRmseByTime = nan(1, size(rmse, 2));
for timeIdx = 1:size(rmse, 2)
    arm.positionRmseByTime(timeIdx) = finiteMean(rmse(:, timeIdx));
end
arm.meanAbsoluteCardinalityErrorByTime = mean(cardinality, 1);
arm.perFormationPositionEospa = zeros(1, numel(groups));
arm.perFormationPositionRmse = zeros(1, numel(groups));
arm.perFormationPositionEospaByTime = ...
    zeros(numel(groups), size(eospa, 2));
arm.perFormationPositionRmseByTime = ...
    nan(numel(groups), size(rmse, 2));
for formationIdx = 1:numel(groups)
    rows = groupIds == groups(formationIdx);
    arm.perFormationPositionEospa(formationIdx) = mean( ...
        reshape(eospa(rows, :), 1, []));
    arm.perFormationPositionRmse(formationIdx) = finiteMean( ...
        reshape(rmse(rows, :), 1, []));
    arm.perFormationPositionEospaByTime(formationIdx, :) = ...
        mean(eospa(rows, :), 1);
    for timeIdx = 1:size(rmse, 2)
        arm.perFormationPositionRmseByTime(formationIdx, timeIdx) = ...
            finiteMean(rmse(rows, timeIdx));
    end
end
end

function [eventE, eventR, eventC] = eventFormationMetrics( ...
        eospa, rmse, cardinality, times, config, protocol)
eventTimes = max(protocol.localizationEventWindow(1), times(1)): ...
    min(protocol.localizationEventWindow(2), times(end));
eventColumns = eventTimes - times(1) + 1;
members = config.sensorGroupIds == protocol.localizationEventFormation;
eventE = mean(reshape(eospa(members, eventColumns), 1, []));
eventR = finiteMean(reshape(rmse(members, eventColumns), 1, []));
eventC = mean(reshape(cardinality(members, eventColumns), 1, []));
end

function value = candidateConsistency(estimates, groupIds, cutoff, times)
groups = unique(groupIds, 'stable');
representatives = zeros(1, numel(groups));
for groupIdx = 1:numel(groups)
    representatives(groupIdx) = find(groupIds == groups(groupIdx), 1);
end
values = zeros(1, numel(times));
for localTime = 1:numel(times)
    currentTime = times(localTime);
    pairs = zeros(1, nchoosek(numel(representatives), 2));
    cursor = 0;
    for left = 1:numel(representatives)-1
        for right = left+1:numel(representatives)
            cursor = cursor + 1;
            components = computePositionEuclideanOspa( ...
                estimates{representatives(left)}.mu{currentTime}, ...
                estimates{representatives(right)}.mu{currentTime}, ...
                cutoff, 2, [1, 2]);
            pairs(cursor) = components(1);
        end
    end
    values(localTime) = mean(pairs);
end
value = mean(values);
end

function comparison = compareArms(candidate, reference, protocol)
comparison = struct();
comparison.eospaGainPercent = lowerGain( ...
    reference.positionEospa, candidate.positionEospa);
comparison.rmseGainPercent = lowerGain( ...
    reference.positionRmse, candidate.positionRmse);
comparison.consistencyGainPercent = lowerGain( ...
    reference.interFormationPositionOspa, ...
    candidate.interFormationPositionOspa);
comparison.formationEospaGainPercent = lowerGainVector( ...
    reference.perFormationPositionEospa, ...
    candidate.perFormationPositionEospa);
comparison.formationRmseGainPercent = lowerGainVector( ...
    reference.perFormationPositionRmse, ...
    candidate.perFormationPositionRmse);
comparison.minimumFormationEospaGainPercent = ...
    min(comparison.formationEospaGainPercent);
comparison.minimumFormationRmseGainPercent = ...
    min(comparison.formationRmseGainPercent);
comparison.eventFormationEospaGainPercent = lowerGain( ...
    reference.eventFormationEospa, candidate.eventFormationEospa);
comparison.eventFormationRmseGainPercent = lowerGain( ...
    reference.eventFormationRmse, candidate.eventFormationRmse);
comparison.shortHorizonGatePassed = ...
    comparison.eventFormationEospaGainPercent >= ...
        protocol.minimumEventFormationEospaGainPercent && ...
    comparison.eventFormationRmseGainPercent > ...
        protocol.minimumEventFormationRmseGainPercent && ...
    min([comparison.eospaGainPercent, comparison.rmseGainPercent, ...
         comparison.consistencyGainPercent]) >= ...
        -protocol.maximumNetworkRegressionPercent && ...
    comparison.minimumFormationEospaGainPercent >= ...
        -protocol.maximumFormationRegressionPercent && ...
    comparison.minimumFormationRmseGainPercent >= ...
        -protocol.maximumFormationRegressionPercent && ...
    candidate.splicedStaticByteSavingPercent > 0;
end

function bytes = reconstructReferenceWindowBytes(inputs, bundle, times)
identity = buildDynamicTopologyPhysicalIdentityRegistry(inputs.config);
nodeCount = inputs.config.numberOfSensors;
bytes = 0;
for currentTime = times
    history = bundle.preDecisionTopologyHistoryByTime{currentTime};
    context = struct();
    context.localPosteriorBySensor = ...
        bundle.posteriorSnapshots{currentTime};
    context.model = inputs.model;
    context.baseAdjacency = logical(inputs.graphData.staticAdjacency);
    context.physicalAdjacency = logical( ...
        inputs.graphData.physicalAdjacency(:, :, currentTime));
    context.positions = inputs.graphData.positions(:, :, currentTime);
    context.currentTime = currentTime;
    context.commConfig = struct('pDropByEdge', ...
        inputs.commConfig.pDropByEdge(:, :, currentTime));
    context.directedMessageBudget = 2 * nodeCount;
    context.sensorPhysicalUids = identity.sensorPhysicalUids;
    context.formationPhysicalUidsBySensor = ...
        identity.formationPhysicalUidsBySensor;
    context.previousAdjacencyHistory = ...
        convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
            history.selectedDirectedEdgeHistory);
    adjacency = selectCausalMinimumFormationBackboneV242Policy(context);
    senderBytes = zeros(1, nodeCount);
    for sender = 1:nodeCount
        stats = estimateLmbPayloadSize( ...
            bundle.posteriorSnapshots{currentTime}{sender}, ...
            inputs.model, 2);
        senderBytes(sender) = stats.estimatedBytes;
    end
    bytes = bytes + sum(sum(adjacency, 1) .* senderBytes);
end
end

function config = attachContinuation( ...
        config, posteriors, history, anchorTime, source)
config.filterInitialLocalPosteriorBySensor = posteriors;
config.filterInitialLocalPosteriorTime = anchorTime;
config.filterInitialPreviousAdjacencyHistory = ...
    convertDiagnosticEdgeHistoryToPolicyAdjacencyHistory( ...
        history.selectedDirectedEdgeHistory);
config.filterInitialPreviousAdjacencyTimes = history.times;
config.filterInitialPreviousAdjacencyHistorySource = source;
end

function inputs = cropInputs(inputs, maximumTime)
inputs.measurements = inputs.measurements(:, 1:maximumTime);
inputs.config.simulationLength = maximumTime;
inputs.model.simulationLength = maximumTime;
inputs.model.dynamicTopologyScenario.config.simulationLength = maximumTime;
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:maximumTime);
end
for name = {'x', 'mu', 'Sigma'}
    inputs.groundTruthRfs.(name{1}) = ...
        inputs.groundTruthRfs.(name{1})(1:maximumTime);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:maximumTime);
inputs.commConfig.pDropByEdge = ...
    inputs.commConfig.pDropByEdge(:, :, 1:maximumTime);
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:maximumTime);
inputs.graphData.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, 1:maximumTime);
inputs.graphData.positions = ...
    inputs.graphData.positions(:, :, 1:maximumTime);
end

function assertCandidate(candidate, comparison, config, protocol)
formationCount = numel(unique(config.sensorGroupIds));
treeMessages = config.numberOfSensors + 2 * (formationCount - 1);
passed = candidate.completed && candidate.physicalFeasibilityPassed && ...
    candidate.instantaneousStrongPassed && ~candidate.policyTruthUsed && ...
    ~candidate.policyFutureOutcomeUsed && ...
    all(candidate.messageCountByTime == treeMessages) && ...
    ~isempty(candidate.labelShortcutActiveTimes) && ...
    isequal(candidate.labelShortcutActiveByTime, ...
        candidate.scheduledByTime) && ...
    all(candidate.gatewayAlignedByTime( ...
        candidate.labelShortcutActiveByTime)) && ...
    all(~candidate.appliedByTime | candidate.transportDeliveredByTime) && ...
    candidate.labelPayloadAttemptedBytes > 0 && ...
    islogical(comparison.shortHorizonGatePassed);
if ~passed
    error('LabelSelectiveRiskShortcutV265:RuntimeContract', ...
        'The V265 continuation violated its route or evidence contract.');
end
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('LabelSelectiveRiskShortcutV265:ReportOpen', ...
        'Unable to write the V265 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
base = result.v242;
candidate = result.candidate;
comparison = result.comparison;
fprintf(fid, '# %s\n\n', result.protocol.reportTitle);
fprintf(fid, '- Scene / seed: `%s / %d`\n', ...
    result.presetName, result.seed);
fprintf(fid, '- Generation commit: `%s`\n', ...
    result.generationGitCommit);
