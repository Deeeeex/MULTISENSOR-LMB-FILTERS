function [datasetPath, dataset] = ...
    generateTruthFreeBehaviorProposalDistillationDataset(options)
% GENERATETRUTHFREEBEHAVIORPROPOSALDISTILLATIONDATASET Expanded M24 data.
%
% Runs the truth-free posterior-analytic policy for 26 decisions from each
% frozen continuation cache. At every predecision state it attaches the
% current-risk teacher and its three one-edge exclusion alternatives.
% Teacher graphs use current truth offline; behavior, features and history
% do not use truth or future outcomes.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getRollingSafeProposalDistillationProtocol();
seedList = round(reshape(getField( ...
    options, 'seedList', protocol.datasetSeeds), 1, []));
[registeredSeeds, registeredSeedIndices] = ismember( ...
    seedList, protocol.datasetSeeds);
if isempty(seedList) || any(~registeredSeeds) || ...
        ~issorted(registeredSeedIndices) || ...
        numel(unique(seedList)) ~= numel(seedList)
    error('Proposal-distillation seedList is not a registered subset.');
end
actionCodeSequences = ...
    protocol.actionCodeSequences(registeredSeedIndices, :);
expectedBlockCount = numel(seedList) * ...
    numel(protocol.snapshotTimes);
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('Official proposal-distillation generation requires clean source.');
end

teacherBlocks = repmat(emptyTeacherBlock(), ...
    1, expectedBlockCount);
teacherCursor = 0;
rolloutOptions = struct( ...
    'datasetVariant', protocol.datasetVariant, ...
    'continuationStartTime', ...
        protocol.continuationStartTime, ...
    'sourceWeight', protocol.sourceWeight, ...
    'payloadToleranceFraction', ...
        protocol.payloadToleranceFraction, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'featureContextMode', protocol.featureContextMode, ...
    'blockObserverFcn', @captureTeacherTargets, ...
    'skipArtifactWrite', true);
[~, behaviorDataset] = ...
    generateRollingSafeRolloutImitationDataset( ...
        protocol.presetName, seedList, ...
        actionCodeSequences, rolloutOptions);
if teacherCursor ~= expectedBlockCount || ...
        numel(behaviorDataset.blocks) ~= ...
            expectedBlockCount
    error('Proposal-distillation block collection is incomplete.');
end
validateBehaviorDataset(behaviorDataset, protocol);

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology', 'datasets'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
if isequal(seedList, protocol.datasetSeeds)
    defaultDatasetName = ...
        ['rolling_safe_proposal_distillation_', ...
         'm24_hard_t75_t83_v1.mat'];
    defaultReportName = ...
        ['ROLLING_SAFE_PROPOSAL_DISTILLATION_', ...
         'M24_HARD_T75_T83_V1.md'];
else
    seedToken = sprintf('%d_', seedList);
    seedToken(end) = [];
    defaultDatasetName = sprintf( ...
        ['rolling_safe_proposal_distillation_', ...
         'm24_hard_t75_t83_seed%s_v1.mat'], seedToken);
    defaultReportName = sprintf( ...
        ['ROLLING_SAFE_PROPOSAL_DISTILLATION_', ...
         'M24_HARD_T75_T83_SEED%s_V1.md'], seedToken);
end
datasetPath = getField(options, 'outputPath', ...
    fullfile(outputDirectory, defaultDatasetName));
reportPath = getField(options, 'reportPath', ...
    fullfile(outputDirectory, defaultReportName));

dataset = behaviorDataset;
dataset.teacherBlocks = teacherBlocks;
dataset.completeOfficialGrid = ...
    isequal(seedList, protocol.datasetSeeds);
dataset.shardSeedSubset = seedList;
dataset.totalTeacherTargetCount = ...
    sum([teacherBlocks.targetCount]);
dataset.minimumTeacherTargetsPerBlock = ...
    min([teacherBlocks.targetCount]);
dataset.maximumTeacherTargetsPerBlock = ...
    max([teacherBlocks.targetCount]);
dataset.behaviorTruthUsed = false;
dataset.behaviorFutureOutcomeUsed = false;
dataset.featuresUseTruth = false;
dataset.featureFutureOutcomeUsed = false;
dataset.teacherTargetsUseTruth = true;
dataset.teacherTargetsUseFutureOutcome = false;
dataset.stateCollectionBehavior = ...
    'truth-free-posterior-analytic-action-80';
dataset.deployable = false;
dataset.developmentOnly = true;
dataset.validationClaimAllowed = false;
dataset.proposalModelTrained = false;
dataset.valueReturnEvaluated = false;
dataset.criticTrainingAuthorized = false;
dataset.x36Authorized = false;
dataset.generationGitCommit = gitState.commit;
dataset.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
dataset.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
dataset.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
dataset.datasetPath = datasetPath;
dataset.reportPath = reportPath;
dataset.evidenceBoundary = [ ...
    'All state features, executed behavior graphs and selected ', ...
    'histories are collected under a frozen truth-free policy. ', ...
    'The attached safe target graphs use current ground truth ', ...
    'offline and are nondeployable proposal-distillation labels. ', ...
    'No H=3 value filtering was run on these expanded states; ', ...
    'model capture, critic accuracy, M24 effect and X36 remain ', ...
    'unevaluated.'];
save('-mat7-binary', datasetPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('Proposal-distillation dataset: %s\nReport: %s\n', ...
    datasetPath, reportPath);

    function captureTeacherTargets(context, behaviorBlock)
        [candidateAdjacency, candidateRecords, metadata] = ...
            buildPrivilegedRollingSafeJointActionProposalBank(context);
        candidateCount = size(candidateAdjacency, 3);
        actionCodes = [candidateRecords.actionCode];
        if candidateCount < protocol.minimumTargetsPerBlock || ...
                candidateCount > ...
                    protocol.maximumTargetsPerBlock || ...
                ~all(ismember(actionCodes, ...
                    protocol.privilegedTargetActionCodes)) || ...
                ~metadata.truthUsed || ...
                metadata.futureOutcomeUsed || ...
                metadata.deployable
            error('Expanded privileged teacher target contract failed.');
        end
        nodeCount = numel(behaviorBlock.groupIds);
        edgeKeys = sub2ind([nodeCount, nodeCount], ...
            behaviorBlock.receiverIndices, ...
            behaviorBlock.senderIndices);
        candidateCrossMasks = false( ...
            numel(edgeKeys), candidateCount);
        for candidateIdx = 1:candidateCount
            adjacency = ...
                candidateAdjacency(:, :, candidateIdx);
            candidateCrossMasks(:, candidateIdx) = ...
                reshape(logical(adjacency(edgeKeys)), [], 1);
            details = ...
                candidateRecords(candidateIdx).policyDetails;
            if details.repairTriggered || ...
                    details.payloadEmergencyUsed || ...
                    ~details.oneStepJointProjectionUsed || ...
                    ~details.sensorWindowStrongConnected || ...
                    ~details.formationWindowStrongConnected
                error('Expanded teacher graph violates safety.');
            end
        end
        teacherCursor = teacherCursor + 1;
        block = emptyTeacherBlock();
        block.seed = behaviorBlock.seed;
        block.currentTime = behaviorBlock.currentTime;
        block.behaviorBlockIndex = teacherCursor;
        block.targetCount = candidateCount;
        block.targetActionCodes = actionCodes;
        block.targetGraphSha256 = ...
            {candidateRecords.graphSha256};
        block.targetAdjacency = candidateAdjacency;
        block.targetCrossMasks = ...
            candidateCrossMasks;
        block.targetRecords = candidateRecords;
        block.targetMetadata = metadata;
        block.truthUsed = true;
        block.futureOutcomeUsed = false;
        block.deployable = false;
        teacherBlocks(teacherCursor) = block;
        fprintf(['  teacher seed %d t=%d: %d safe targets ', ...
            'codes=%s\n'], block.seed, block.currentTime, ...
            block.targetCount, ...
            formatActionCodes(block.targetActionCodes));
    end
end

function validateBehaviorDataset(dataset, protocol)
[registeredSeeds, registeredSeedIndices] = ismember( ...
    dataset.seeds, protocol.datasetSeeds);
if ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~strcmp(dataset.datasetVariant, ...
            protocol.datasetVariant) || ...
        any(~registeredSeeds) || ...
        ~issorted(registeredSeedIndices) || ...
        ~isequal(dataset.snapshotTimes, ...
            protocol.snapshotTimes) || ...
        ~isequal(dataset.actionCodeSequences, ...
            protocol.actionCodeSequences( ...
                registeredSeedIndices, :)) || ...
        dataset.featuresUseTruth || dataset.labelsUseTruth || ...
        dataset.labelSelectionUsesFutureOutcome || ...
        ~isfield(dataset, 'behaviorTruthUsed') || ...
        dataset.behaviorTruthUsed || ...
        dataset.behaviorFutureOutcomeUsed
    error('Truth-free behavior dataset violates its protocol.');
end
for block = dataset.blocks
    if block.actionCode ~= protocol.behaviorActionCode || ...
            block.actionTruthUsed || block.labelTruthUsed || ...
            block.featureMetadata.truthUsed || ...
            block.featureMetadata.groundTruthUsed || ...
            block.featureMetadata.futureOutcomeUsed || ...
            ~strcmp(block.labelSource, ...
                'truth-free-posterior-analytic-behavior-graph')
        error('Truth-free behavior block contains privileged data.');
    end
end
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('Could not open proposal-distillation report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ...
    '# Truth-free-behavior proposal distillation: M24\n\n');
fprintf(fid, '- Generated: %s\n', dataset.generatedAt);
fprintf(fid, '- Contract: `%s`\n', dataset.contractVersion);
fprintf(fid, '- Generation commit: `%s`\n', ...
    dataset.generationGitCommit);
fprintf(fid, '- Seeds: `%s`\n', mat2str(dataset.seeds));
fprintf(fid, '- Times: `%d:%d`\n', ...
    dataset.snapshotTimes(1), dataset.snapshotTimes(end));
fprintf(fid, '- State blocks: `%d`\n', ...
    numel(dataset.blocks));
fprintf(fid, '- Behavior action code: `%d`\n', ...
    dataset.actionCodeSequences(1, 1));
fprintf(fid, '- Behavior truth/future use: `%d / %d`\n', ...
    dataset.behaviorTruthUsed, ...
    dataset.behaviorFutureOutcomeUsed);
fprintf(fid, '- Feature truth/future use: `%d / %d`\n', ...
    dataset.featuresUseTruth, ...
    dataset.featureFutureOutcomeUsed);
fprintf(fid, '- Teacher truth/future use: `%d / %d`\n', ...
    dataset.teacherTargetsUseTruth, ...
    dataset.teacherTargetsUseFutureOutcome);
fprintf(fid, '- Teacher targets: `%d`\n', ...
    dataset.totalTeacherTargetCount);
fprintf(fid, '- Targets per block min/max: `%d / %d`\n', ...
    dataset.minimumTeacherTargetsPerBlock, ...
    dataset.maximumTeacherTargetsPerBlock);
fprintf(fid, '- Deployable dataset: `%d`\n', ...
    dataset.deployable);
fprintf(fid, '- Evidence boundary: %s\n\n', ...
    dataset.evidenceBoundary);
fprintf(fid, '## Seed summary\n\n');
fprintf(fid, ...
    ['| Seed | Blocks | Targets | Behavior E-OSPA | ', ...
     'Worst node | Attempted bytes | Truth-used actions |\n']);
fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
for seed = dataset.seeds
    blockMask = [dataset.blocks.seed] == seed;
    outcome = dataset.outcomes( ...
        [dataset.outcomes.seed] == seed);
    teacherMask = [dataset.teacherBlocks.seed] == seed;
    fprintf(fid, ...
        '| %d | %d | %d | %.4f | %.4f | %.0f | %d |\n', ...
        seed, nnz(blockMask), ...
        sum([dataset.teacherBlocks(teacherMask).targetCount]), ...
        outcome.meanEospa, outcome.worstSensorEospa, ...
        outcome.attemptedBytes, ...
        round(numel(dataset.snapshotTimes) * ...
            outcome.policyTruthUseFraction));
end
end

function block = emptyTeacherBlock()
block = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'behaviorBlockIndex', NaN, ...
    'targetCount', 0, ...
    'targetActionCodes', [], ...
    'targetGraphSha256', {cell(1, 0)}, ...
    'targetAdjacency', false(0, 0, 0), ...
    'targetCrossMasks', false(0, 0), ...
    'targetRecords', repmat(struct(), 1, 0), ...
    'targetMetadata', struct(), ...
    'truthUsed', true, ...
    'futureOutcomeUsed', false, ...
    'deployable', false);
end

function token = formatActionCodes(actionCodes)
parts = arrayfun(@(code) sprintf('%02d', code), ...
    reshape(actionCodes, 1, []), 'UniformOutput', false);
token = strjoin(parts, '-');
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
