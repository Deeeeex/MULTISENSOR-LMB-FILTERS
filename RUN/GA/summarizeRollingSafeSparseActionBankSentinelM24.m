function [reportPath, summary] = ...
    summarizeRollingSafeSparseActionBankSentinelM24(options)
% SUMMARIZEROLLINGSAFESPARSEACTIONBANKSENTINELM24 Gate sparse headroom.
%
% This summary consumes the four registered opened-training sentinel
% preflights. It only authorizes selector design when the equal-message
% action bank has paired H=3 headroom while preserving the registered
% worst-node, consensus, byte-budget, and rolling-B3 constraints.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.rollingSafeSparsePreflightAuthorized || ...
        protocol.developmentEvaluationAuthorized || ...
        protocol.heldoutM24Authorized || ...
        protocol.x36PolicyRunAuthorized
    error('M24 sparse action-bank sentinel is not authorized.');
end

states = protocol.rollingSafeSparseSentinelSeedTimes;
inputDirectory = getField(options, ...
    'inputDirectory', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'label_set_policy_m24_v1', ...
        'rolling_safe_sparse_action_bank_sentinel_v1'));
artifactSuffix = getField(options, 'artifactSuffix', 'bank_v1');
if ~ischar(artifactSuffix) || ...
        isempty(regexp(artifactSuffix, ...
            '^[A-Za-z0-9_-]+$', 'once'))
    error('artifactSuffix is invalid.');
end

rows = repmat(emptyRow(), 1, size(states, 1));
for stateIdx = 1:size(states, 1)
    seed = states(stateIdx, 1);
    currentTime = states(stateIdx, 2);
    stem = sprintf( ...
        'rolling_safe_sparse_h3_m24_seed%d_t%d_%s', ...
        seed, currentTime, artifactSuffix);
    path = fullfile(inputDirectory, [stem, '.mat']);
    loaded = load(path, 'preflight');
    if ~isfield(loaded, 'preflight')
        error('Sparse sentinel artifact lacks preflight: %s', path);
    end
    preflight = loaded.preflight;
    validatePreflight( ...
        preflight, seed, currentTime, protocol);

    bestIdx = find(preflight.actionCodes == ...
        preflight.bestAdmissibleActionCode);
    if numel(bestIdx) ~= 1
        error('Sparse sentinel best admissible action is not unique.');
    end
    completed = strcmp(preflight.actionStatus, 'completed');
    byteDeviation = preflight.attemptedByteDeviationPercent(completed);
    row = emptyRow();
    row.seed = seed;
    row.currentTime = currentTime;
    row.artifactPath = path;
    row.generationGitCommit = preflight.generationGitCommit;
    row.referenceMeanEospa = preflight.referenceMeanEospa;
    row.bestAdmissibleMeanEospa = ...
        preflight.bestAdmissibleMeanEospa;
    row.bestAdmissibleActionCode = ...
        preflight.bestAdmissibleActionCode;
    row.bestAdmissibleGainPercent = ...
        preflight.bestAdmissibleGainVsReferencePercent;
    row.bestAdmissibleWorstGainPercent = ...
        preflight.bestAdmissibleWorstGainVsReferencePercent;
    row.bestAdmissibleConsensusGainPercent = ...
        preflight.bestAdmissibleConsensusGainVsReferencePercent;
    row.bestAdmissibleByteDeviationPercent = ...
        preflight.bestAdmissibleAttemptedByteDeviationPercent;
    row.completedActionCount = preflight.completedActionCount;
    row.unavailableActionCount = preflight.unavailableActionCount;
    row.uniqueCompletedGraphCount = ...
        preflight.uniqueCompletedGraphCount;
    row.maximumByteDeviationPercent = finiteMax(byteDeviation);
    row.improvesReference = ...
        row.bestAdmissibleGainPercent > 1e-9;
    row.isExcludedOutlier = isequal( ...
        [seed, currentTime], ...
        protocol.rollingSafeSparseExcludedOutlierSeedTime);
    row.isStrongNonOutlier = ...
        ~row.isExcludedOutlier && ...
        row.bestAdmissibleGainPercent >= ...
            protocol.rollingSafeSparseMinimumNonOutlierGainPercent;
    row.safetyPassed = ...
        preflight.completedActionCount >= 2 && ...
        preflight.uniqueCompletedGraphCount >= 2 && ...
        all(preflight.hardRuntimeGatePassed(completed)) && ...
        row.maximumByteDeviationPercent <= ...
            protocol.rollingSafeSparseMaximumByteDeviationPercent && ...
        row.bestAdmissibleWorstGainPercent >= -1e-9 && ...
        row.bestAdmissibleConsensusGainPercent >= -1e-9;
    rows(stateIdx) = row;
end

generationCommits = unique({rows.generationGitCommit});
if numel(generationCommits) ~= 1
    error('Sparse sentinel artifacts use different code commits.');
end
meanReferenceEospa = mean([rows.referenceMeanEospa]);
meanBestAdmissibleEospa = ...
    mean([rows.bestAdmissibleMeanEospa]);
aggregateGainPercent = relativeGain( ...
    meanReferenceEospa, meanBestAdmissibleEospa);
improvedStateCount = nnz([rows.improvesReference]);
strongNonOutlierStateCount = nnz([rows.isStrongNonOutlier]);
hardAuditPassed = all([rows.safetyPassed]);
headroomGatePassed = ...
    improvedStateCount >= ...
        protocol.rollingSafeSparseMinimumSentinelImprovedStateCount && ...
    strongNonOutlierStateCount >= 1;
selectorDesignAuthorized = ...
    hardAuditPassed && headroomGatePassed;

gitState = resolveResearchGitState();
summary = struct();
summary.protocolId = protocol.id;
summary.contractVersion = ...
    'm24-rolling-safe-sparse-action-bank-sentinel-summary-v1';
summary.actionBankContractVersion = ...
    protocol.rollingSafeSparseActionBankContractVersion;
summary.generatedAt = datestr(now, 31);
summary.generationGitCommit = gitState.commit;
summary.preflightGenerationGitCommit = generationCommits{1};
summary.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
summary.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
summary.generationResearchWorktreeDirty = ...
    gitState.researchWorktreeDirty;
summary.actionCodes = ...
    protocol.rollingSafeSparseActionBankCodes;
summary.rows = rows;
summary.meanReferenceEospa = meanReferenceEospa;
summary.meanBestAdmissibleEospa = ...
    meanBestAdmissibleEospa;
summary.aggregateBestAdmissibleGainPercent = ...
    aggregateGainPercent;
summary.improvedStateCount = improvedStateCount;
summary.strongNonOutlierStateCount = ...
    strongNonOutlierStateCount;
summary.maximumByteDeviationPercent = ...
    max([rows.maximumByteDeviationPercent]);
summary.hardAuditGatesPassed = hardAuditPassed;
summary.sentinelHeadroomGatePassed = headroomGatePassed;
summary.selectorDesignAuthorized = selectorDesignAuthorized;
summary.actionBankRejectedForSelectorDesign = ...
    ~selectorDesignAuthorized;
summary.trainingOnlyDiagnostic = true;
summary.developmentOpened = false;
summary.heldoutM24Opened = false;
summary.x36Opened = false;
if selectorDesignAuthorized
    summary.nextMethodDirection = [ ...
        'safe-finite-horizon-graph-option-value-learning'];
else
    summary.nextMethodDirection = [ ...
        'redesign-equal-budget-graph-options-before-learning'];
end
summary.evidenceBoundary = [ ...
    'This four-state opened-training sentinel tests offline oracle ', ...
    'headroom within a truth-free 24-message sparse action bank. The ', ...
    'frozen predecision states were generated by the earlier 40-message ', ...
    'dense CCW behavior trajectory. It neither compares sparse and dense ', ...
    'policies at equal budget nor validates the new formation-FoV M24, ', ...
    'X36, or X48 scenes.'];

outputDirectory = getField(options, ...
    'outputDirectory', fullfile(inputDirectory, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
stem = 'rolling_safe_sparse_action_bank_sentinel_m24_v1';
matPath = fullfile(outputDirectory, [stem, '.mat']);
reportPath = fullfile(outputDirectory, [upper(stem), '.md']);
overwrite = logical(getField(options, 'overwrite', false));
if ~overwrite && ...
        (exist(matPath, 'file') == 2 || ...
         exist(reportPath, 'file') == 2)
    error(['Sparse sentinel summary already exists. Set overwrite=true ', ...
        'only for intentional regeneration.']);
end
summary.matPath = matPath;
summary.reportPath = reportPath;
save('-mat7-binary', matPath, 'summary');
writeReport(reportPath, summary, protocol);
fprintf('Sparse action-bank sentinel summary: %s\nReport: %s\n', ...
    matPath, reportPath);
end

function validatePreflight(preflight, seed, currentTime, protocol)
if ~isstruct(preflight) || ...
        ~strcmp(preflight.protocolId, protocol.id) || ...
        ~strcmp(preflight.contractVersion, ...
            'm24-rolling-safe-truth-free-action-bank-h3-preflight-v2') || ...
        ~strcmp(preflight.actionBankContractVersion, ...
            protocol.rollingSafeSparseActionBankContractVersion) || ...
        preflight.seed ~= seed || ...
        preflight.currentTime ~= currentTime || ...
        ~isequal(preflight.actionCodes, ...
            protocol.rollingSafeSparseActionBankCodes) || ...
        preflight.referenceActionCode ~= ...
            protocol.rollingSafeSparseReferenceActionCode || ...
        preflight.generationTrackedWorktreeDirty || ...
        ~isempty(preflight.generationUntrackedSourceFiles) || ...
        preflight.generationResearchWorktreeDirty || ...
        ~preflight.commonRandomNumbers || ...
        ~preflight.firstActionGraphAndWeightsFrozen || ...
        preflight.runtimePolicyUsesTruth || ...
        ~preflight.trainingOnlyDiagnostic || ...
        preflight.developmentOpened || ...
        preflight.heldoutM24Opened || ...
        preflight.x36Opened
    error('Sparse action-bank preflight violates the frozen contract.');
end
end

function writeReport(path, summary, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Could not write sparse sentinel report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# M24 24-message sparse action-bank sentinel\n\n');
fprintf(fid, '- Action codes: `%s`\n', mat2str(summary.actionCodes));
fprintf(fid, '- States: `%d`\n', numel(summary.rows));
fprintf(fid, '- Reference / admissible oracle mean E-OSPA: `%.6f / %.6f`\n', ...
    summary.meanReferenceEospa, ...
    summary.meanBestAdmissibleEospa);
fprintf(fid, '- Aggregate admissible gain: `%+.3f%%`\n', ...
    summary.aggregateBestAdmissibleGainPercent);
fprintf(fid, '- Improved states: `%d / %d` (gate `>=%d`)\n', ...
    summary.improvedStateCount, numel(summary.rows), ...
    protocol.rollingSafeSparseMinimumSentinelImprovedStateCount);
fprintf(fid, ['- Non-outlier states with `>=%.1f%%` gain: ', ...
    '`%d / %d` (gate `>=1`)\n'], ...
    protocol.rollingSafeSparseMinimumNonOutlierGainPercent, ...
    summary.strongNonOutlierStateCount, numel(summary.rows) - 1);
fprintf(fid, '- Hard audit / headroom / selector-design gates: `%d / %d / %d`\n\n', ...
    summary.hardAuditGatesPassed, ...
    summary.sentinelHeadroomGatePassed, ...
    summary.selectorDesignAuthorized);
fprintf(fid, ...
    ['| Seed-time | Ref. | Best admissible | Code | Mean gain | ', ...
     'Worst gain | Consensus gain | Completed/unique | Max byte dev. | Safe |\n']);
fprintf(fid, ...
    '|:--|--:|--:|--:|--:|--:|--:|:--:|--:|--:|\n');
for rowIdx = 1:numel(summary.rows)
    row = summary.rows(rowIdx);
    fprintf(fid, ...
        ['| %d-%d | %.6f | %.6f | %d | %+.3f%% | %+.3f%% | ', ...
         '%+.3f%% | %d/%d | %.3f%% | %d |\n'], ...
        row.seed, row.currentTime, row.referenceMeanEospa, ...
        row.bestAdmissibleMeanEospa, ...
        row.bestAdmissibleActionCode, ...
        row.bestAdmissibleGainPercent, ...
        row.bestAdmissibleWorstGainPercent, ...
        row.bestAdmissibleConsensusGainPercent, ...
        row.completedActionCount, ...
        row.uniqueCompletedGraphCount, ...
        row.maximumByteDeviationPercent, row.safetyPassed);
end
fprintf(fid, '\n## Decision\n\n');
if summary.selectorDesignAuthorized
    fprintf(fid, ['The bank passes the sentinel and authorizes ', ...
        'safe finite-horizon graph-option value-learning design.\n\n']);
else
    fprintf(fid, ['The bank is rejected for selector training; redesign ', ...
        'the equal-budget graph options before fitting a model.\n\n']);
end
fprintf(fid, '## Boundary\n\n%s\n', summary.evidenceBoundary);
end

function row = emptyRow()
row = struct( ...
    'seed', NaN, ...
    'currentTime', NaN, ...
    'artifactPath', '', ...
    'generationGitCommit', '', ...
    'referenceMeanEospa', NaN, ...
    'bestAdmissibleMeanEospa', NaN, ...
    'bestAdmissibleActionCode', NaN, ...
    'bestAdmissibleGainPercent', NaN, ...
    'bestAdmissibleWorstGainPercent', NaN, ...
    'bestAdmissibleConsensusGainPercent', NaN, ...
    'bestAdmissibleByteDeviationPercent', NaN, ...
    'completedActionCount', NaN, ...
    'unavailableActionCount', NaN, ...
    'uniqueCompletedGraphCount', NaN, ...
    'maximumByteDeviationPercent', NaN, ...
    'improvesReference', false, ...
    'isExcludedOutlier', false, ...
    'isStrongNonOutlier', false, ...
    'safetyPassed', false);
end

function value = finiteMax(values)
values = values(isfinite(values));
if isempty(values)
    value = inf;
else
    value = max(values);
end
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(reference, eps);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
