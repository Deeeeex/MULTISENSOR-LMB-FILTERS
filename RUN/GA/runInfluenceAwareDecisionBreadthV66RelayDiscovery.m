function [reportPath, result] = ...
    runInfluenceAwareDecisionBreadthV66RelayDiscovery(options)
% RUNINFLUENCEAWAREDECISIONBREADTHV66RELAYDISCOVERY Current-only scan.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = ...
    getInfluenceAwareDecisionBreadthV66SceneDiscoveryProtocol();
method = getInfluenceAwareDecisionBreadthV66Protocol();
v65 = getNetworkAdditiveFormationRiskV65Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('InfluenceAwareRelayV66:DirtySource', ...
        'V66 relay discovery requires a clean source checkout.');
end
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

times = protocol.snapshotTimes;
records = repmat(emptyRecord(), 1, numel(times));
selectorOptions = v65;
selectorOptions.minimumNormalizedRobustMarginExposure = ...
    method.minimumNormalizedRobustMarginExposure;
for timeIdx = 1:numel(times)
    currentTime = times(timeIdx);
    state = loadFormationH3ObservableState( ...
        protocol.presets{1}, protocol.allSeeds, currentTime, ...
        struct('cacheRoot', protocol.cacheRoot));
    [~, control] = computeFormationRoutingLeverageSignature( ...
        state.context, state.groupIds);
    baseMetrics = computeNetworkAdditiveFormationRiskV65( ...
        control, state.context, state.groupIds, ...
        method.positiveSupportThreshold);
    influenceMetrics = computeInfluenceAwareDecisionBreadthV66( ...
        control, state.context, state.groupIds, struct( ...
            'positiveSupportThreshold', ...
                method.positiveSupportThreshold, ...
            'horizonSteps', method.horizonSteps));
    selection = selectInfluenceAwareDecisionBreadthV66( ...
        baseMetrics, influenceMetrics, selectorOptions);
    records(timeIdx) = makeRecord( ...
        currentTime, baseMetrics, selection);
    fprintf(['V66 relay t=%d risk=%.3f%% base=%s ', ...
        'exposure=%.4f action=%d fallback=%s\n'], ...
        currentTime, 100 * baseMetrics.totalNetworkRescueFraction, ...
        mat2str(selection.baseSelectedFormationIds), ...
        selection.selectedNormalizedRobustMarginExposure, ...
        selection.actionEnabled, selection.fallbackReason);
end

eligible = find([records.actionEnabled]);
selectedIdx = [];
if ~isempty(eligible)
    table = [ ...
        -[records(eligible).normalizedRobustMarginExposure]', ...
        -[records(eligible).networkRiskFraction]', ...
        [records(eligible).currentTime]'];
    [~, order] = sortrows(table, [1, 2, 3]);
    selectedIdx = eligible(order(1));
end

result = struct();
result.contractVersion = ...
    'influence-aware-decision-breadth-v66-relay-discovery-v1';
result.protocol = protocol;
result.methodProtocol = method;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.records = records;
result.eligibleTimeCount = numel(eligible);
result.eligibleTimes = [records(eligible).currentTime];
result.selectedFreshTime = NaN;
result.selectedFreshRecord = emptyRecord();
if ~isempty(selectedIdx)
    result.selectedFreshTime = records(selectedIdx).currentTime;
    result.selectedFreshRecord = records(selectedIdx);
end
result.trackingOutcomeRead = false;
result.trackingOutcomeScoringAuthorized = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;

matPath = fullfile(outputRoot, ...
    'INFLUENCE_AWARE_DECISION_BREADTH_V66_RELAY_DISCOVERY.mat');
reportPath = fullfile(outputRoot, ...
    'INFLUENCE_AWARE_DECISION_BREADTH_V66_RELAY_DISCOVERY.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V66 relay discovery: %s\n', reportPath);
end

function record = makeRecord(currentTime, baseMetrics, selection)
record = emptyRecord();
record.currentTime = currentTime;
record.networkRiskFraction = baseMetrics.totalNetworkRescueFraction;
record.baseActionEnabled = selection.baseSelection.actionEnabled;
record.baseSelectedFormationIds = ...
    selection.baseSelectedFormationIds;
record.normalizedRobustMarginExposure = ...
    selection.selectedNormalizedRobustMarginExposure;
record.normalizedDecisionExposure = ...
    selection.selectedNormalizedDecisionExposure;
record.upwardCrossings = selection.selectedUpwardCrossings;
record.affectedReceiverCount = ...
    selection.selectedAffectedReceiverCount;
record.actionEnabled = selection.actionEnabled;
record.selectedFormationIds = selection.selectedFormationIds;
record.fallbackReason = selection.fallbackReason;
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'networkRiskFraction', NaN, ...
    'baseActionEnabled', false, ...
    'baseSelectedFormationIds', zeros(1, 0), ...
    'normalizedRobustMarginExposure', NaN, ...
    'normalizedDecisionExposure', NaN, ...
    'upwardCrossings', NaN, ...
    'affectedReceiverCount', NaN, ...
    'actionEnabled', false, ...
    'selectedFormationIds', zeros(1, 0), ...
    'fallbackReason', 'not-evaluated');
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('InfluenceAwareRelayV66:WriteFailed', ...
        'Could not create the V66 relay discovery report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V66 M24 relay current-only discovery\n\n');
fprintf(fid, ['| Time | V65 risk | V65 action | V65 set | ', ...
    'Robust exposure | Crossings | Receivers | V66 action | Fallback |\n']);
fprintf(fid, '|--:|--:|:--:|:--|--:|--:|--:|:--:|:--|\n');
for record = result.records
    fprintf(fid, ['| %d | %.3f%% | %d | `%s` | %.4f | %.0f | ', ...
        '%.0f | %d | `%s` |\n'], ...
        record.currentTime, 100 * record.networkRiskFraction, ...
        record.baseActionEnabled, ...
        mat2str(record.baseSelectedFormationIds), ...
        record.normalizedRobustMarginExposure, ...
        record.upwardCrossings, record.affectedReceiverCount, ...
        record.actionEnabled, record.fallbackReason);
end
fprintf(fid, '\n- Eligible times: `%s`\n', ...
    mat2str(result.eligibleTimes));
fprintf(fid, '- Selected fresh time: `%g`\n', ...
    result.selectedFreshTime);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
