function [reportPath, result] = ...
        runAlternativeSourceV118X36T72(options)
% RUNALTERNATIVESOURCEV118X36T72 Fixed-entry F5 source screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getAlternativeSourceV118Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('AlternativeSourceV118:DirtySource', ...
        'The V118 screen requires clean frozen source.');
end
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
currentTime = 72;
v113 = loadScreen(protocol.v113ScreenPath, protocol, entry, currentTime);
v114 = loadScreen(protocol.v114ScreenPath, protocol, entry, currentTime);
v116 = loadScreen(protocol.v116ScreenPath, protocol, entry, currentTime);
outputRoot = getField(options, 'outputRoot', fullfile( ...
    protocol.headroomOutputRoot, 'x36_t72_h8'));
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
screenOptions = struct( ...
    'horizonSteps', protocol.horizonSteps, ...
    'interventionDurationSteps', protocol.horizonSteps, ...
    'filterSeedOffset', protocol.filterSeedOffset, ...
    'cacheRoot', entry.cacheRoot, ...
    'interventionBankType', 'tracking-aligned-x36-schedule', ...
    'trackingAlignedExecutionProfile', protocol.executionProfile, ...
    'trackingAlignedX36ScheduleBankOptions', struct( ...
        'positiveSupportThreshold', protocol.positiveSupportThreshold, ...
        'bankVariant', protocol.bankVariant, ...
        'horizonSteps', protocol.horizonSteps), ...
    'actionIndices', 1:(1 + numel(protocol.candidateActionNames)), ...
    'receiverMode', protocol.receiverMode, ...
    'referenceOutcomeScreenPath', protocol.v113ScreenPath, ...
    'capturePosteriorSnapshotsEnabled', false, ...
    'outputDirectory', fullfile(outputRoot, 'screen'), ...
    'writeReport', true);
screenMatPath = fullfile(screenOptions.outputDirectory, ...
    ['TRACKING_ALIGNED_X36_SCHEDULE_H8_', ...
     'X36_FORMATION_FOV_SEED211_T72_D8.mat']);
if logical(getField(options, 'reuseCompletedCandidateScreen', true)) && ...
        exist(screenMatPath, 'file') == 2
    loaded = load(screenMatPath, 'screen');
    if ~isfield(loaded, 'screen')
        error('AlternativeSourceV118:InvalidCandidateScreen', ...
            'The saved V118 screen lacks the screen variable.');
    end
    screen = loaded.screen;
    validateCandidateScreen(screen, protocol, entry, currentTime);
    screenReportPath = screen.reportPath;
    candidateScreenReused = true;
else
    [screenReportPath, screen] = runFormationModeOpenedReturnScreen( ...
        entry.presetName, entry.seed, currentTime, screenOptions);
    candidateScreenReused = false;
end
if ~screen.referenceOutcomeReused || ...
        ~strcmp(screen.cacheSha256, v113.cacheSha256) || ...
        ~isequal(screen.sensorGroupIds, v113.sensorGroupIds)
    error('AlternativeSourceV118:PairingDrift', ...
        'The V118 screen did not preserve the V113 paired baseline.');
end

[ccwRecord, ~] = findArm(v113, 'reference-full-payload');
[cwRecord, cwOutcome] = findArm(v113, protocol.clockwiseFullActionName);
[baseRecord, ~] = findArm(v113, protocol.baseMechanismActionName);
[shieldRecord, ~] = findArm(v114, protocol.earlyShieldActionName);
[top5Record, ~] = findArm(v116, protocol.v116Top5ActionName);
groupIds = reshape(screen.sensorGroupIds, 1, []);
targetMembers = find(groupIds == protocol.boundaryFormationId);
cwByTime = mean(cwOutcome.eospaBySensorTime, 1);

labels = repmat(emptyLabel(), 1, numel(protocol.candidateActionNames));
for candidateIdx = 1:numel(protocol.candidateActionNames)
    actionName = protocol.candidateActionNames{candidateIdx};
    [candidate, outcome, recordIdx] = findArm(screen, actionName);
    candidateByTime = mean(outcome.eospaBySensorTime, 1);
    gainByTime = relativeGainPercent(cwByTime, candidateByTime);
    [formationGain, formationGainByTime] = formationGains( ...
        cwOutcome.eospaBySensorTime, outcome.eospaBySensorTime, groupIds);
    rewire = screen.bank.actionPolicyDetails{recordIdx}.v118SourceRewire;
    label = emptyLabel();
    label.actionName = actionName;
    label.sourceSensorId = ...
        protocol.candidateSourceSensorIds(candidateIdx);
    label.targetPeerIndices = setdiff(targetMembers, ...
        protocol.receiverSensorId, 'stable');
    label.recordIndex = recordIdx;
    label.meanEospa = candidate.meanEospa;
    label.meanGainPercent = relativeGainPercent( ...
        cwRecord.meanEospa, candidate.meanEospa);
    label.marginalVsV113Percent = relativeGainPercent( ...
        baseRecord.meanEospa, candidate.meanEospa);
    label.marginalVsV114Percent = relativeGainPercent( ...
        shieldRecord.meanEospa, candidate.meanEospa);
    label.marginalVsV116Top5Percent = relativeGainPercent( ...
        top5Record.meanEospa, candidate.meanEospa);
    label.gainPercentByTime = gainByTime;
    label.formationGainPercent = formationGain;
    label.formationGainPercentByTime = formationGainByTime;
    label.minimumAfterMaturityGainPercent = min( ...
        gainByTime(protocol.firstHandoffTimeIndex:end));
    label.minimumFormationGainPercent = min(formationGain);
    label.targetPeerTerminalGainPercent = relativeGainPercent( ...
        mean(cwOutcome.eospaBySensorTime( ...
            label.targetPeerIndices, end)), ...
        mean(outcome.eospaBySensorTime( ...
            label.targetPeerIndices, end)));
    label.receiverTerminalGainPercent = relativeGainPercent( ...
        cwOutcome.eospaBySensorTime( ...
            protocol.receiverSensorId, end), ...
        outcome.eospaBySensorTime( ...
            protocol.receiverSensorId, end));
    label.worstSensorGainPercent = relativeGainPercent( ...
        cwRecord.worstSensorEospa, candidate.worstSensorEospa);
    label.windowConsensusGainPercent = relativeGainPercent( ...
        cwRecord.consensusOspa, candidate.consensusOspa);
    label.terminalConsensusGainPercent = relativeGainPercent( ...
        cwRecord.terminalConsensusOspa, candidate.terminalConsensusOspa);
    label.attemptedByteSavingPercent = relativeGainPercent( ...
        cwRecord.attemptedBytes, candidate.attemptedBytes);
    label.messageParityPassed = rewire.messageParityPassed;
    label.rowSumPassed = rewire.rowSumPassed;
    label.weightMultisetPassed = rewire.weightMultisetPassed;
    label.strongConnectivityPassed = rewire.strongConnectivityPassed;
    label.selectedB3Passed = candidate.selectedB3Passed;
    label.elapsedSeconds = outcome.elapsedSeconds;
    label.gatePassed = passesGate(label, protocol);
    labels(candidateIdx) = label;
end

passing = find([labels.gatePassed]);
if isempty(passing)
    regret = max(0, -[labels.minimumFormationGainPercent]) + ...
        max(0, -[labels.targetPeerTerminalGainPercent]);
    bestRegret = min(regret);
    tied = find(abs(regret - bestRegret) <= 1e-12);
    [~, localBest] = max([labels(tied).meanGainPercent]);
    oracleIndex = tied(localBest);
else
    [~, localBest] = max([labels(passing).meanGainPercent]);
    oracleIndex = passing(localBest);
end

result = struct();
result.contractVersion = protocol.resultContractVersion;
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.presetName = entry.presetName;
result.seed = entry.seed;
result.currentTime = currentTime;
result.returnTimes = screen.returnTimes;
result.referenceOutcomeReused = screen.referenceOutcomeReused;
result.v113BaselinesReused = true;
result.v114ShieldReused = true;
result.v116Top5Reused = true;
result.v118CandidateScreenReused = candidateScreenReused;
result.candidateScreenGenerationGitCommit = screen.generationGitCommit;
result.ccwFullRecord = ccwRecord;
result.clockwiseFullRecord = cwRecord;
result.unshieldedMechanismRecord = baseRecord;
result.earlyWholeShieldRecord = shieldRecord;
result.v116Top5Record = top5Record;
result.labels = labels;
result.oracleIndex = oracleIndex;
result.oracleActionName = labels(oracleIndex).actionName;
result.anyGatePassed = any([labels.gatePassed]);
result.originalSourceSensorId = protocol.originalSourceSensorId;
result.receiverSensorId = protocol.receiverSensorId;
result.targetPeerIndicesByCandidate = {labels.targetPeerIndices};
result.screenReportPath = screenReportPath;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, [protocol.resultFileStem, '.mat']);
reportPath = fullfile(outputRoot, [protocol.resultFileStem, '.md']);
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('%s result: %s\n', protocol.runLabel, reportPath);
end

function validateCandidateScreen(screen, protocol, entry, currentTime)
requiredActions = [{'reference-full-payload'}, ...
    protocol.candidateActionNames];
valid = isstruct(screen) && isscalar(screen) && ...
    strcmp(screen.presetName, entry.presetName) && ...
    screen.seed == entry.seed && screen.currentTime == currentTime && ...
    screen.horizonSteps == protocol.horizonSteps && ...
    strcmp(screen.missingLabelFusionMode, protocol.receiverMode) && ...
    strcmp(screen.bank.bankVariant, protocol.bankVariant) && ...
    isequal(screen.bank.actionNames, requiredActions) && ...
    numel(screen.outcomes) == numel(requiredActions) && ...
    ~screen.generationTrackedWorktreeDirty && ...
    isempty(screen.generationUntrackedSourceFiles) && ...
    screen.openedDevelopmentEvidenceOnly && ...
    ~screen.validationClaimAllowed;
if ~valid
    error('AlternativeSourceV118:CandidateScreenDrift', ...
        'The saved V118 candidate screen does not match the protocol.');
end
end

function screen = loadScreen(path, protocol, entry, currentTime)
if exist(path, 'file') ~= 2
    error('AlternativeSourceV118:MissingReferenceScreen', ...
        'A required frozen reference screen is missing.');
end
loaded = load(path, 'screen');
if ~isfield(loaded, 'screen')
    error('AlternativeSourceV118:InvalidReferenceScreen', ...
        'A required reference file lacks the screen variable.');
end
screen = loaded.screen;
if ~strcmp(screen.presetName, entry.presetName) || ...
        screen.seed ~= entry.seed || screen.currentTime ~= currentTime || ...
        screen.horizonSteps ~= protocol.horizonSteps || ...
        ~strcmp(screen.missingLabelFusionMode, protocol.receiverMode) || ...
        ~screen.openedDevelopmentEvidenceOnly || ...
        screen.validationClaimAllowed
    error('AlternativeSourceV118:ReferenceProvenanceDrift', ...
        'A frozen reference screen does not match V118.');
end
end

function [record, outcome, recordIdx] = findArm(screen, actionName)
recordIdx = find(strcmp({screen.records.actionName}, actionName), 1);
if isempty(recordIdx)
    error('AlternativeSourceV118:MissingArm', ...
        'Required arm %s is missing.', actionName);
end
record = screen.records(recordIdx);
outcome = screen.outcomes(recordIdx);
end

function passed = passesGate(label, protocol)
passed = label.meanGainPercent >= protocol.minimumMeanGainPercent - 1e-12 && ...
    label.minimumAfterMaturityGainPercent >= ...
        protocol.minimumMeanGainPercent - 1e-12 && ...
    label.worstSensorGainPercent >= ...
        protocol.minimumWorstSensorGainPercent - 1e-12 && ...
    label.minimumFormationGainPercent >= ...
        protocol.minimumFormationGainPercent - 1e-12 && ...
    label.targetPeerTerminalGainPercent >= ...
        protocol.minimumTargetPeerTerminalGainPercent - 1e-12 && ...
    label.windowConsensusGainPercent >= ...
        protocol.minimumWindowConsensusGainPercent - 1e-12 && ...
    label.terminalConsensusGainPercent >= ...
        protocol.minimumTerminalConsensusGainPercent - 1e-12 && ...
    label.attemptedByteSavingPercent >= ...
        protocol.minimumAttemptedByteSavingPercent - 1e-12 && ...
    label.messageParityPassed && label.rowSumPassed && ...
    label.weightMultisetPassed && label.strongConnectivityPassed && ...
    label.selectedB3Passed;
end

function label = emptyLabel()
label = struct('actionName', '', 'sourceSensorId', 0, ...
    'targetPeerIndices', [], ...
    'recordIndex', 0, 'meanEospa', nan, 'meanGainPercent', nan, ...
    'marginalVsV113Percent', nan, 'marginalVsV114Percent', nan, ...
    'marginalVsV116Top5Percent', nan, ...
    'gainPercentByTime', [], 'formationGainPercent', [], ...
    'formationGainPercentByTime', [], ...
    'minimumAfterMaturityGainPercent', nan, ...
    'minimumFormationGainPercent', nan, ...
    'targetPeerTerminalGainPercent', nan, ...
    'receiverTerminalGainPercent', nan, ...
    'worstSensorGainPercent', nan, ...
    'windowConsensusGainPercent', nan, ...
    'terminalConsensusGainPercent', nan, ...
    'attemptedByteSavingPercent', nan, ...
    'messageParityPassed', false, 'rowSumPassed', false, ...
    'weightMultisetPassed', false, ...
    'strongConnectivityPassed', false, 'selectedB3Passed', false, ...
    'elapsedSeconds', nan, 'gatePassed', false);
end

function [gain, gainByTime] = formationGains(reference, candidate, groupIds)
groups = unique(reshape(groupIds, 1, []), 'stable');
referenceMeans = zeros(1, numel(groups));
candidateMeans = zeros(1, numel(groups));
gainByTime = zeros(numel(groups), size(reference, 2));
for groupIdx = 1:numel(groups)
    mask = reshape(groupIds, 1, []) == groups(groupIdx);
    referenceValues = reference(mask, :);
    candidateValues = candidate(mask, :);
    referenceMeans(groupIdx) = mean(referenceValues(:));
    candidateMeans(groupIdx) = mean(candidateValues(:));
    gainByTime(groupIdx, :) = relativeGainPercent( ...
        mean(reference(mask, :), 1), mean(candidate(mask, :), 1));
end
gain = relativeGainPercent(referenceMeans, candidateMeans);
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('AlternativeSourceV118:WriteFailed', ...
        'Could not create the V118 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# %s\n\n', result.protocol.reportTitle);
fprintf(fid, '- V113/V114/V116 endpoints reused: `1 / 1 / 1`\n');
fprintf(fid, '- V118 candidate screen reused: `%d`\n', ...
    result.v118CandidateScreenReused);
fprintf(fid, '- Original source / receiver: `%d -> %d`\n', ...
    result.originalSourceSensorId, result.receiverSensorId);
fprintf(fid, '- Any candidate passed: `%d`\n', result.anyGatePassed);
fprintf(fid, '- Oracle action: `%s`\n\n', result.oracleActionName);
fprintf(fid, ['| Arm | Mean E-OSPA | Gain vs CW | vs V113 | vs V114 | ', ...
    'vs V116-5 | Mature min | Min form. | F6 peers | Worst | Bytes | Gate |\n']);
fprintf(fid, ['|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
fprintf(fid, '| CCW full | %.6f | -- | -- | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.ccwFullRecord.meanEospa, result.ccwFullRecord.selectedB3Passed);
fprintf(fid, '| CW full | %.6f | -- | -- | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.clockwiseFullRecord.meanEospa, ...
    result.clockwiseFullRecord.selectedB3Passed);
fprintf(fid, '| V113 source-27 full | %.6f | -- | -- | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.unshieldedMechanismRecord.meanEospa, ...
    result.unshieldedMechanismRecord.selectedB3Passed);
fprintf(fid, '| V114 source-27 empty | %.6f | -- | -- | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.earlyWholeShieldRecord.meanEospa, ...
    result.earlyWholeShieldRecord.selectedB3Passed);
fprintf(fid, '| V116 source-27 top-5 | %.6f | -- | -- | -- | -- | -- | -- | -- | -- | -- | %d |\n', ...
    result.v116Top5Record.meanEospa, ...
    result.v116Top5Record.selectedB3Passed);
for idx = 1:numel(result.labels)
    item = result.labels(idx);
    fprintf(fid, ['| source-%d | %.6f | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d |\n'], ...
        item.sourceSensorId, item.meanEospa, ...
        item.meanGainPercent, item.marginalVsV113Percent, ...
        item.marginalVsV114Percent, item.marginalVsV116Top5Percent, ...
        item.minimumAfterMaturityGainPercent, ...
        item.minimumFormationGainPercent, ...
        item.targetPeerTerminalGainPercent, ...
        item.worstSensorGainPercent, item.attemptedByteSavingPercent, ...
        item.gatePassed);
end
oracle = result.labels(result.oracleIndex);
fprintf(fid, '\n## Oracle diagnostics\n\n');
fprintf(fid, '- Source / receiver / action: `%d / %d / %s`\n', ...
    oracle.sourceSensorId, result.receiverSensorId, oracle.actionName);
fprintf(fid, '- Formation gains: `%s%%`\n', ...
    mat2str(oracle.formationGainPercent, 4));
fprintf(fid, '- Per-page gains: `%s%%`\n', ...
    mat2str(oracle.gainPercentByTime, 4));
fprintf(fid, '- Receiver terminal gain: `%+.3f%%`\n', ...
    oracle.receiverTerminalGainPercent);
fprintf(fid, '- Window / terminal consensus: `%+.3f%% / %+.3f%%`\n', ...
    oracle.windowConsensusGainPercent, ...
    oracle.terminalConsensusGainPercent);
fprintf(fid, ['- Message / row / weight / strong invariants: ', ...
    '`%d / %d / %d / %d`\n'], ...
    oracle.messageParityPassed, oracle.rowSumPassed, ...
    oracle.weightMultisetPassed, oracle.strongConnectivityPassed);
fprintf(fid, '- Gate passed: `%d`\n\n', oracle.gatePassed);
fprintf(fid, '## Evidence boundary\n\n%s\n', result.evidenceBoundary);
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
