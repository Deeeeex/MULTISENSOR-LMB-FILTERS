function [cachePath, summary] = ...
    generateSafeGraphCodebookOracleV152Cache( ...
        presetName, seed, options)
% GENERATESAFEGRAPHCODEBOOKORACLEV152CACHE Create one paired prefix cache.

if nargin < 1 || isempty(presetName)
    presetName = 'm24-formation-fov';
end
if nargin < 2 || isempty(seed)
    seed = 83;
end
if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getSafeGraphCodebookOracleV152Protocol();
presetIdx = find(strcmp(protocol.presetNames, presetName));
if numel(presetIdx) ~= 1 || ...
        ~ismember(seed, protocol.openedDevelopmentSeeds)
    error('The requested V152 cache is outside the opened matrix.');
end
cacheDirectory = getField(options, 'cacheDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v152', 'safe_graph_codebook_oracle', 'cache'));
executionContext = ...
    buildSafeGraphCodebookOracleV152ExecutionContext( ...
        presetName, seed, 'reference-cache', ...
        'static-full-posterior-reference-cache');
teacherOptions = struct( ...
    'snapshotTimes', protocol.anchorTimes(presetIdx), ...
    'teacherHorizonSteps', 0, ...
    'closedLoopHorizonSteps', 0, ...
    'behaviorCacheOnly', true, ...
    'behaviorCacheDirectory', cacheDirectory, ...
    'filterExecutionContext', executionContext, ...
    'writeReport', false);
[~, summary] = runDynamicTopologyTeacherSignalScreen( ...
    presetName, seed, teacherOptions);
cachePath = fullfile(cacheDirectory, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', ...
    strrep(presetName, '-', '_'), seed, ...
    protocol.anchorTimes(presetIdx)));
if exist(cachePath, 'file') ~= 2
    error('V152 reference cache was not created.');
end
fprintf('V152 reference cache: %s\n', cachePath);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
