function [reportPath, result] = ...
        runSupportAwareFormationControllerV206X36T72(options)
% RUNSUPPORTAWAREFORMATIONCONTROLLERV206X36T72 Release plus sparse repair.
%
% V205 showed that a final hard F5 label insertion cannot remove the F5
% RMSE tail created earlier by the V99 withholding decision.  This teacher
% releases F5 back to the ordinary full-posterior route at t=72 and retains
% only the already positive supported-label KLA actions for F1/F2/F3/F6.

if nargin < 1 || isempty(options)
    options = struct();
end
releasePlan = struct( ...
    'contractVersion', ...
        'online-positive-net-formation-release-v191-plan-v1', ...
    'times', 72, ...
    'formationIdsByTime', {{5}}, ...
    'teacherMode', true);
defaults = struct( ...
    'horizonSteps', 8, ...
    'currentTime', 72, ...
    'repairPageOffsets', [0, 1, 4, 5, 6], ...
    'forcedFormationId', [2, 6, 3, 1, 3], ...
    'forcedSourceId', [19, 19, 23, 13, 23], ...
    'forcedLabel', [13, 7, 19, 7, 19; ...
                    12, 5, 13, 7, 13], ...
    'maximumActions', 1, ...
    'updateMode', 'label-kla', ...
    'sourceWeight', 0.5, ...
    'idealDeliveryTeacherMode', true, ...
    'onlinePositiveNetFormationReleasePlan', releasePlan, ...
    'outputRoot', fullfile( ...
        'RUN', 'GA', 'dynamic_topology', 'evidence', ...
        'tracking_aligned_v206', 'support_aware_complete_teacher', ...
        'x36_seed211_t72_h8'));
names = fieldnames(defaults);
for fieldIdx = 1:numel(names)
    name = names{fieldIdx};
    if ~isfield(options, name)
        options.(name) = defaults.(name);
    end
end

[reportPath, result] = ...
    runBudgetRecycledFormationRepairV188RecursivePilot( ...
        'X36', options);
