function [reportPath, summary] = ...
    runLabelSetAdaptiveDominantPayloadAwareM24( ...
        seed, payloadMarginToken, options)
% RUNLABELSETADAPTIVEDOMINANTPAYLOADAWAREM24 M24 payload-budget screen.
%
% The token is the payload-margin fraction in thousandths: 025 means
% 2.5%, and 050 means 5%.  Training and the already-opened development
% split are redesign data.  Neither is reported as held-out evidence.

if nargin < 1 || isempty(seed)
    seed = 11;
end
if nargin < 2 || isempty(payloadMarginToken)
    payloadMarginToken = 50;
end
if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
evidenceSplit = lower(strrep(char(getField( ...
    options, 'evidenceSplit', 'training')), '_', '-'));
registeredTokens = ...
    protocol.adaptiveDominantPayloadAwareMarginTokens;
if protocol.adaptiveDominantPayloadAwareRefinementAuthorized
    registeredTokens = unique([ ...
        registeredTokens, ...
        protocol.adaptiveDominantPayloadAwareRefinementMarginTokens], ...
        'stable');
end
if ~protocol.adaptiveDominantPayloadAwareRedesignAuthorized || ...
        ~ismember(payloadMarginToken, registeredTokens)
    error('Payload-aware M24 redesign token is not registered.');
end
if strcmp(evidenceSplit, 'training')
    splitSeeds = ...
        protocol.adaptiveDominantFullWindowTrainingSeeds;
elseif strcmp(evidenceSplit, 'development') && ...
        protocol. ...
            adaptiveDominantPayloadAwareDevelopmentTuningAuthorized
    splitSeeds = protocol.adaptiveDominantDevelopmentSeeds;
else
    error('Payload-aware M24 redesign split is not authorized.');
end
if ~ismember(seed, splitSeeds)
    error('Seed is outside the selected payload-aware redesign split.');
end

candidateArm = sprintf([ ...
    'adaptive-dominant-composite-balanced-', ...
    'payload-margin%03d-e05-a70'], payloadMarginToken);
registeredArmNames = arrayfun(@(token) sprintf([ ...
    'adaptive-dominant-composite-balanced-', ...
    'payload-margin%03d-e05-a70'], token), ...
    registeredTokens, 'UniformOutput', false);
if ~ismember(candidateArm, registeredArmNames)
    error('Payload-aware arm name differs from the protocol grid.');
end
includeReference = logical(getField( ...
    options, 'includeReferenceControl', false));
if includeReference
    armNames = { ...
        protocol.adaptiveDominantFullWindowReferenceArmName, ...
        candidateArm};
else
    armNames = {candidateArm};
end
rootDirectory = getField(options, 'outputDirectory', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'label_set_policy_m24_v1', ...
    'adaptive_dominant_payload_aware_screen_v2', ...
    sprintf('margin%03d', payloadMarginToken)));
screenOptions = struct( ...
    'maxTimeSteps', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(end), ...
    'continuationStartTime', ...
        protocol.adaptiveDominantPayloadAwareScreenTimes(1), ...
    'armNames', {armNames}, ...
    'writeReport', true, ...
    'outputDirectory', fullfile( ...
        rootDirectory, evidenceSplit, sprintf('seed%d', seed)), ...
    'behaviorCacheDirectory', getField(options, ...
        'behaviorCacheDirectory', fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'cache')), ...
    'generateMissingBehaviorCache', false, ...
    'evidenceSplit', evidenceSplit);
[reportPath, summary] = runDynamicTopologyOracleGapScreen( ...
    'm24-hard', seed, screenOptions);
end

function value = getField(data, name, fallback)
if isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
