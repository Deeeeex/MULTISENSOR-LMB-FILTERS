function [reportPath, dataset] = ...
        buildRolloutAggregatedActionDatasetV178(options)
% BUILDROLLOUTAGGREGATEDACTIONDATASETV178 Aggregate static and rollout states.
%
% Training receives the V166 early/static training cells and the V176 t=78
% on-policy rollout cells.  Calibration remains the V166 F3 t=79 group.
% The V176 F5 t=79 rollout cells stay held out until model selection is
% frozen.  Rows are never split independently from receiver-time cells.

if nargin < 1 || isempty(options)
    options = struct();
end
staticPath = getField(options, 'staticDatasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v166', 'one_hop_action_value', ...
    'ONE_HOP_LABEL_ACTION_VALUE_DATASET_V166.mat'));
rolloutPath = getField(options, 'rolloutDatasetPath', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v176', 'recursive_rollout_action_value', ...
    'RECURSIVE_ROLLOUT_LABEL_ACTION_VALUE_DATASET_V176.mat'));
outputRoot = getField(options, 'outputRoot', fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v178', 'rollout_aggregated_action_value'));
if exist(staticPath, 'file') ~= 2 || exist(rolloutPath, 'file') ~= 2
    error('RolloutAggregatedDatasetV178:MissingInput', ...
        'Both V166 and V176 action datasets are required.');
end

staticDataset = load(staticPath, 'dataset').dataset;
rolloutDataset = load(rolloutPath, 'dataset').dataset;
validateInputs(staticDataset, rolloutDataset);

rows = repmat(staticDataset.rows(1), 1, 0);
cells = repmat(staticDataset.cells(1), 1, 0);
provenance = repmat(emptyProvenance(), 1, 0);
[rows, cells, provenance] = appendCells( ...
    rows, cells, provenance, staticDataset, ...
    ismember([staticDataset.cells.split], [1, 2]), 'V166-static');
[rows, cells, provenance] = appendCells( ...
    rows, cells, provenance, rolloutDataset, ...
    ismember([rolloutDataset.cells.split], [1, 3]), 'V176-rollout');

dataset = struct();
dataset.contractVersion = ...
    'rollout-aggregated-label-action-value-dataset-v178-v1';
dataset.featureContractVersion = staticDataset.featureContractVersion;
dataset.presetName = staticDataset.presetName;
dataset.seed = staticDataset.seed;
dataset.sourceDatasetPaths = {staticPath, rolloutPath};
dataset.sourceDatasetContracts = { ...
    staticDataset.contractVersion, rolloutDataset.contractVersion};
dataset.featureNames = staticDataset.featureNames;
dataset.featureCount = numel(dataset.featureNames);
dataset.rows = rows;
dataset.cells = cells;
dataset.cellProvenance = provenance;
dataset.splitNames = {'training', 'calibration', 'heldout'};
dataset.trainingCellIds = [cells([cells.split] == 1).cellId];
dataset.calibrationCellIds = [cells([cells.split] == 2).cellId];
dataset.heldoutCellIds = [cells([cells.split] == 3).cellId];
dataset.featuresUseTruth = false;
dataset.featuresUseFutureInformation = false;
dataset.numericLabelIdentifiersUsedAsFeatures = false;
dataset.targetsUseCurrentTruth = true;
dataset.targetsUseFutureOutcome = false;
dataset.policyTrained = false;
dataset.recursiveEvaluationRun = false;
dataset.deployable = false;
dataset.evidenceBoundary = [ ...
    'V178 is an opened seed-211 policy-iteration dataset. Training joins ', ...
    'the V166 t=76/78 static-snapshot cells with the V176 t=78 states ', ...
    'actually visited by recursive V169. Hyperparameter and threshold ', ...
    'selection may use only the V166 F3 t=79 calibration cells. The V176 ', ...
    'F5 t=79 rollout cells remain grouped heldout until selection is ', ...
    'frozen. Features use only present posterior, topology and FoV ', ...
    'summaries; current truth supplies immediate action targets. Since ', ...
    'all states come from opened X36 seed 211 and the rollout was induced ', ...
    'by a previously developed policy, this supports recursive method ', ...
    'development only, not validation or generalization.'];

if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end
matPath = fullfile(outputRoot, ...
    'ROLLOUT_AGGREGATED_ACTION_VALUE_DATASET_V178.mat');
reportPath = fullfile(outputRoot, ...
    'ROLLOUT_AGGREGATED_ACTION_VALUE_DATASET_V178.md');
dataset.matPath = matPath;
dataset.reportPath = reportPath;
save('-mat7-binary', matPath, 'dataset');
writeReport(reportPath, dataset);
fprintf('V178 rollout-aggregated dataset: %s\n', reportPath);
end

function validateInputs(staticDataset, rolloutDataset)
required = {'contractVersion', 'featureContractVersion', 'featureNames', ...
    'rows', 'cells', 'splitNames', 'featuresUseTruth', ...
    'featuresUseFutureInformation', ...
    'numericLabelIdentifiersUsedAsFeatures', ...
    'targetsUseCurrentTruth', 'targetsUseFutureOutcome'};
if ~all(isfield(staticDataset, required)) || ...
        ~all(isfield(rolloutDataset, required)) || ...
        ~strcmp(staticDataset.contractVersion, ...
            'one-hop-label-action-value-dataset-v166-v1') || ...
        ~strcmp(rolloutDataset.contractVersion, ...
            'recursive-rollout-label-action-value-dataset-v176-v1') || ...
        ~strcmp(staticDataset.featureContractVersion, ...
            rolloutDataset.featureContractVersion) || ...
        ~isequal(staticDataset.featureNames, rolloutDataset.featureNames) || ...
        ~isequal(fieldnames(staticDataset.rows), ...
            fieldnames(rolloutDataset.rows)) || ...
        ~isequal(fieldnames(staticDataset.cells), ...
            fieldnames(rolloutDataset.cells)) || ...
        any([staticDataset.featuresUseTruth, ...
             rolloutDataset.featuresUseTruth, ...
             staticDataset.featuresUseFutureInformation, ...
             rolloutDataset.featuresUseFutureInformation, ...
             staticDataset.numericLabelIdentifiersUsedAsFeatures, ...
             rolloutDataset.numericLabelIdentifiersUsedAsFeatures]) || ...
        ~all([staticDataset.targetsUseCurrentTruth, ...
              rolloutDataset.targetsUseCurrentTruth]) || ...
        any([staticDataset.targetsUseFutureOutcome, ...
             rolloutDataset.targetsUseFutureOutcome])
    error('RolloutAggregatedDatasetV178:Contract', ...
        'The V166/V176 dataset contracts are incompatible.');
end
end

function [rows, cells, provenance] = appendCells( ...
        rows, cells, provenance, source, includeMask, sourceName)
sourceCells = source.cells(includeMask);
for sourceCell = reshape(sourceCells, 1, [])
    originalCellId = sourceCell.cellId;
    sourceRows = source.rows([source.rows.cellId] == originalCellId);
    newCellId = numel(cells) + 1;
    for idx = 1:numel(sourceRows)
        sourceRows(idx).cellId = newCellId;
    end
    sourceCell.cellId = newCellId;
    rows = [rows, sourceRows]; %#ok<AGROW>
    cells(end + 1) = sourceCell; %#ok<AGROW>
    item = emptyProvenance();
    item.cellId = newCellId;
    item.sourceName = sourceName;
    item.sourceContract = source.contractVersion;
    item.sourceCellId = originalCellId;
    item.split = sourceCell.split;
    item.time = sourceCell.time;
    item.formation = sourceCell.formation;
    item.receiver = sourceCell.receiver;
    provenance(end + 1) = item; %#ok<AGROW>
end
end

function item = emptyProvenance()
item = struct('cellId', 0, 'sourceName', '', 'sourceContract', '', ...
    'sourceCellId', 0, 'split', 0, 'time', 0, 'formation', 0, ...
    'receiver', 0);
end

function writeReport(path, dataset)
fid = fopen(path, 'w');
if fid < 0
    error('RolloutAggregatedDatasetV178:ReportOpenFailed', ...
        'Could not open the V178 report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V178 rollout-aggregated label-action dataset\n\n');
fprintf(fid, '- Features / rows / cells: `%d / %d / %d`\n', ...
    dataset.featureCount, numel(dataset.rows), numel(dataset.cells));
fprintf(fid, '- Sources: `V166 static + V176 recursive rollout`\n\n');
fprintf(fid, ['| Split | Source | Cells | Rows | Joint-positive | ', ...
    'Cells with safe actions |\n']);
fprintf(fid, '|:--|:--|--:|--:|--:|--:|\n');
for split = 1:3
    for sourceName = {'V166-static', 'V176-rollout'}
        sourceMask = strcmp({dataset.cellProvenance.sourceName}, ...
            sourceName{1}) & [dataset.cellProvenance.split] == split;
        cellIds = [dataset.cellProvenance(sourceMask).cellId];
        rowMask = ismember([dataset.rows.cellId], cellIds);
        selectedRows = dataset.rows(rowMask);
        selectedCells = dataset.cells(ismember( ...
            [dataset.cells.cellId], cellIds));
        fprintf(fid, '| %s | %s | %d | %d | %d | %d |\n', ...
            dataset.splitNames{split}, sourceName{1}, ...
            numel(selectedCells), numel(selectedRows), ...
            nnz([selectedRows.eospaGain] > 0 & ...
                [selectedRows.rmseGain] > 0), ...
            nnz([selectedCells.safeCandidateCount] > 0));
    end
end
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    dataset.evidenceBoundary);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
