function [reportPath, result] = ...
    runTaskRiskInputProtectionV92HeadroomScan(options)
% RUNTASKRISKINPUTPROTECTIONV92HEADROOMSCAN Cached current-only screen.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getTaskRiskInputProtectionV92Protocol();
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles) || ...
        gitState.researchWorktreeDirty
    error('TaskRiskV92:DirtySource', ...
        'The V92 headroom scan requires clean frozen source.');
end
cacheRoot = getField(options, 'cacheRoot', protocol.cacheRoot);
outputRoot = getField(options, 'outputRoot', protocol.outputRoot);
if exist(outputRoot, 'dir') ~= 7
    mkdir(outputRoot);
end

scenes = repmat(emptyScene(), 1, numel(protocol.presets));
for presetIdx = 1:numel(protocol.presets)
    presetName = protocol.presets{presetIdx};
    records = repmat(emptyRecord(), 1, numel(protocol.snapshotTimes));
    for timeIdx = 1:numel(protocol.snapshotTimes)
        currentTime = protocol.snapshotTimes(timeIdx);
        state = loadFormationH3ObservableState( ...
            presetName, protocol.allSeeds, currentTime, ...
            struct('cacheRoot', cacheRoot));
        nodeCount = numel(state.groupIds);
        if nodeCount ~= protocol.expectedNodeCounts(presetIdx) || ...
                numel(unique(state.groupIds, 'stable')) ~= ...
                    protocol.expectedFormationCounts(presetIdx)
            error('TaskRiskV92:ScaleDrift', ...
                'A V92 cached state changed its registered scale.');
        end
        context = state.context;
        context.triggerConfig = ...
            buildPartialLabelFusionSemanticsV90TriggerConfig( ...
                protocol.referenceArmId, nodeCount, ...
                protocol.receiverMode);
        records(timeIdx) = evaluateState( ...
            context, state.groupIds, protocol);
        fprintf([ ...
            'V92 %s t=%d safe=%d best=%s task=%+.3f%% ', ...
            'worst=%+.3f%% formation=%+.3f%% messages=%d\n'], ...
            presetName, currentTime, ...
            records(timeIdx).safeCandidateCount, ...
            formatFormation(records(timeIdx).bestFormationId), ...
            records(timeIdx).bestTaskRiskGainPercent, ...
            records(timeIdx).bestWorstReceiverRiskGainPercent, ...
            records(timeIdx).bestWorstFormationRiskGainPercent, ...
            records(timeIdx).bestMessageSavingCount);
    end
    scenes(presetIdx) = summarizeScene( ...
        presetName, protocol.allSeeds, records, protocol);
end

result = struct();
result.contractVersion = ...
    'task-risk-input-protection-v92-headroom-result-v1';
result.protocol = protocol;
result.generatedAt = datestr(now, 31);
result.generationGitCommit = gitState.commit;
result.cacheRoot = cacheRoot;
result.scenes = scenes;
result.bothScalesHeadroomGatePassed = ...
    all([scenes.headroomGatePassed]);
result.fullEpisodeImplementationAuthorized = ...
    result.bothScalesHeadroomGatePassed;
result.routeExecutionAuthorized = false;
result.trackingOutcomeRead = false;
result.modelTrainingAuthorized = false;
result.validationClaimAllowed = false;
result.openedDevelopmentEvidenceOnly = true;
result.evidenceBoundary = protocol.evidenceBoundary;
matPath = fullfile(outputRoot, ...
    'TASK_RISK_INPUT_PROTECTION_V92_HEADROOM.mat');
reportPath = fullfile(outputRoot, ...
    'TASK_RISK_INPUT_PROTECTION_V92_HEADROOM.md');
result.matPath = matPath;
result.reportPath = reportPath;
save('-mat7-binary', matPath, 'result');
writeReport(reportPath, result);
fprintf('V92 task-risk input-protection headroom: %s\n', reportPath);
end

function record = evaluateState(context, groupIds, protocol)
policyOptions = struct( ...
    'policyConfig', protocol.protectionPolicy, ...
    'referenceMode', protocol.referenceMode);
[referenceAdjacency, referenceDetails] = ...
    selectTemporalFormationBackboneInputBundleSuspensionPolicy( ...
        context, zeros(1, 0), policyOptions);
referenceScore = scoreTaskRiskInputProtectionRouteV92( ...
    context, referenceAdjacency, ...
    referenceDetails.fusionWeightMatrix, [], ...
    groupIds, protocol, struct());
incrementalReference = struct( ...
    'networkDetails', referenceScore.networkDetails, ...
    'adjacency', referenceAdjacency, ...
    'fusionWeights', referenceDetails.fusionWeightMatrix);
groups = unique(groupIds, 'stable');
candidates = repmat(emptyCandidate(), 1, numel(groups));
for formationIdx = 1:numel(groups)
    candidate = emptyCandidate();
    candidate.formationId = groups(formationIdx);
    try
        [adjacency, details] = ...
            selectTemporalFormationBackboneInputBundleSuspensionPolicy( ...
                context, groups(formationIdx), policyOptions);
        score = scoreTaskRiskInputProtectionRouteV92( ...
            context, adjacency, details.fusionWeightMatrix, ...
            referenceScore, groupIds, protocol, incrementalReference);
        candidate.available = true;
        candidate.safe = score.safe && ...
            all(details.rollingB3SensorPass) && ...
            all(details.rollingB3FormationPass);
        candidate.taskRiskGainPercent = score.taskRiskGainPercent;
        candidate.worstReceiverRiskGainPercent = ...
            score.worstReceiverRiskGainPercent;
        candidate.worstFormationRiskGainPercent = ...
            score.worstFormationRiskGainPercent;
        candidate.existenceRetentionRisk = ...
            score.existenceRetentionRisk;
        candidate.minimumSupportedLabelRetentionRatio = ...
            score.minimumSupportedLabelRetentionRatio;
        candidate.decisionThresholdCrossingCount = ...
            score.decisionThresholdCrossingCount;
        candidate.messageSavingCount = details.messageSavingCount;
        candidate.score = score;
        candidate.policyDetails = details;
    catch errorInfo
        if ~isExpectedUnavailable(errorInfo)
            rethrow(errorInfo);
        end
        candidate.failureIdentifier = errorInfo.identifier;
        candidate.failureMessage = errorInfo.message;
    end
    candidates(formationIdx) = candidate;
end

safeIndices = find([candidates.safe]);
bestIdx = [];
if ~isempty(safeIndices)
    ranking = [ ...
        -[candidates(safeIndices).taskRiskGainPercent]', ...
        -[candidates(safeIndices).worstReceiverRiskGainPercent]', ...
        -[candidates(safeIndices).worstFormationRiskGainPercent]', ...
        [candidates(safeIndices).formationId]'];
    [~, order] = sortrows(ranking, 1:size(ranking, 2));
    bestIdx = safeIndices(order(1));
end
record = emptyRecord();
record.currentTime = context.currentTime;
record.referenceTaskRisk = referenceScore.taskRisk;
record.referenceWorstReceiverRisk = ...
    referenceScore.taskRiskDetails.maximumReceiverRisk;
record.referenceWorstFormationRisk = ...
    referenceScore.taskRiskDetails.maximumFormationMeanRisk;
record.candidates = candidates;
record.availableCandidateCount = nnz([candidates.available]);
record.safeCandidateCount = nnz([candidates.safe]);
if ~isempty(bestIdx)
    best = candidates(bestIdx);
    record.bestFormationId = best.formationId;
    record.bestTaskRiskGainPercent = best.taskRiskGainPercent;
    record.bestWorstReceiverRiskGainPercent = ...
        best.worstReceiverRiskGainPercent;
    record.bestWorstFormationRiskGainPercent = ...
        best.worstFormationRiskGainPercent;
    record.bestMessageSavingCount = best.messageSavingCount;
    record.actionable = best.taskRiskGainPercent > 1e-12;
end
end

function scene = summarizeScene(presetName, seed, records, protocol)
actionable = [records.actionable];
positiveGains = [records(actionable).bestTaskRiskGainPercent];
scene = emptyScene();
scene.presetName = presetName;
scene.seed = seed;
scene.records = records;
scene.snapshotCount = numel(records);
scene.actionableTimeCount = nnz(actionable);
scene.actionableTimeFraction = mean(actionable);
scene.medianPositiveTaskRiskGainPercent = ...
    medianOrZero(positiveGains);
scene.peakSafeTaskRiskGainPercent = maxOrZero(positiveGains);
scene.minimumSafeWorstReceiverGainPercent = minOrZero( ...
    [records(actionable).bestWorstReceiverRiskGainPercent]);
scene.minimumSafeWorstFormationGainPercent = minOrZero( ...
    [records(actionable).bestWorstFormationRiskGainPercent]);
scene.totalBestMessageSavingCount = sum( ...
    [records(actionable).bestMessageSavingCount]);
scene.headroomGatePassed = ...
    scene.actionableTimeFraction >= ...
        protocol.minimumActionableTimeFraction - 1e-12 && ...
    scene.medianPositiveTaskRiskGainPercent >= ...
        protocol.minimumMedianPositiveTaskRiskGainPercent - 1e-12 && ...
    scene.peakSafeTaskRiskGainPercent >= ...
        protocol.minimumPeakSafeTaskRiskGainPercent - 1e-12;
end

function writeReport(path, result)
fid = fopen(path, 'w');
if fid < 0
    error('TaskRiskV92:WriteFailed', ...
        'Could not create the V92 headroom report.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '# V92 task-risk input-protection headroom\n\n');
fprintf(fid, ['This current-only scan compares the static physical-tree ', ...
    'reference with one protected formation input bundle at a time. ', ...
    'Positive percentages mean lower posterior task risk.\n\n']);
fprintf(fid, ['| Scale | Actionable times | Median positive | Peak | ', ...
    'Minimum worst receiver | Minimum worst formation | ', ...
    'Best-message savings | Gate |\n']);
fprintf(fid, '|:--|--:|--:|--:|--:|--:|--:|:--:|\n');
for scene = result.scenes
    fprintf(fid, ['| %s | %d/%d (%.1f%%) | %+.3f%% | %+.3f%% | ', ...
        '%+.3f%% | %+.3f%% | %d | %d |\n'], ...
        scene.presetName, scene.actionableTimeCount, ...
        scene.snapshotCount, 100 * scene.actionableTimeFraction, ...
        scene.medianPositiveTaskRiskGainPercent, ...
        scene.peakSafeTaskRiskGainPercent, ...
        scene.minimumSafeWorstReceiverGainPercent, ...
        scene.minimumSafeWorstFormationGainPercent, ...
        scene.totalBestMessageSavingCount, ...
        scene.headroomGatePassed);
end
fprintf(fid, '\n## Time-resolved best safe actions\n\n');
for scene = result.scenes
    fprintf(fid, '### %s\n\n', scene.presetName);
    fprintf(fid, ['| Time | Safe candidates | Formation | Task | ', ...
        'Worst receiver | Worst formation | Messages |\n']);
    fprintf(fid, '|--:|--:|--:|--:|--:|--:|--:|\n');
    for record = scene.records
        fprintf(fid, '| %d | %d | %s | %+.3f%% | %+.3f%% | %+.3f%% | %d |\n', ...
            record.currentTime, record.safeCandidateCount, ...
            formatFormation(record.bestFormationId), ...
            record.bestTaskRiskGainPercent, ...
            record.bestWorstReceiverRiskGainPercent, ...
            record.bestWorstFormationRiskGainPercent, ...
            record.bestMessageSavingCount);
    end
    fprintf(fid, '\n');
end
fprintf(fid, '- Both scales pass the headroom gate: `%d`\n', ...
    result.bothScalesHeadroomGatePassed);
fprintf(fid, '- Full-episode implementation authorized: `%d`\n', ...
    result.fullEpisodeImplementationAuthorized);
fprintf(fid, '- Tracking outcome read: `0`\n');
fprintf(fid, '- Route execution authorized: `0`\n');
fprintf(fid, '\n## Evidence boundary\n\n%s\n', ...
    result.evidenceBoundary);
end

function value = emptyCandidate()
value = struct( ...
    'formationId', NaN, ...
    'available', false, ...
    'safe', false, ...
    'taskRiskGainPercent', NaN, ...
    'worstReceiverRiskGainPercent', NaN, ...
    'worstFormationRiskGainPercent', NaN, ...
    'existenceRetentionRisk', NaN, ...
    'minimumSupportedLabelRetentionRatio', NaN, ...
    'decisionThresholdCrossingCount', NaN, ...
    'messageSavingCount', 0, ...
    'score', struct(), ...
    'policyDetails', struct(), ...
    'failureIdentifier', '', ...
    'failureMessage', '');
end

function value = emptyRecord()
value = struct( ...
    'currentTime', NaN, ...
    'referenceTaskRisk', NaN, ...
    'referenceWorstReceiverRisk', NaN, ...
    'referenceWorstFormationRisk', NaN, ...
    'candidates', repmat(emptyCandidate(), 1, 0), ...
    'availableCandidateCount', 0, ...
    'safeCandidateCount', 0, ...
    'bestFormationId', NaN, ...
    'bestTaskRiskGainPercent', 0, ...
    'bestWorstReceiverRiskGainPercent', 0, ...
    'bestWorstFormationRiskGainPercent', 0, ...
    'bestMessageSavingCount', 0, ...
    'actionable', false);
end

function value = emptyScene()
value = struct( ...
    'presetName', '', ...
    'seed', NaN, ...
    'records', repmat(emptyRecord(), 1, 0), ...
    'snapshotCount', 0, ...
    'actionableTimeCount', 0, ...
    'actionableTimeFraction', 0, ...
    'medianPositiveTaskRiskGainPercent', 0, ...
    'peakSafeTaskRiskGainPercent', 0, ...
    'minimumSafeWorstReceiverGainPercent', 0, ...
    'minimumSafeWorstFormationGainPercent', 0, ...
    'totalBestMessageSavingCount', 0, ...
    'headroomGatePassed', false);
end

function value = isExpectedUnavailable(errorInfo)
value = any(strcmp(errorInfo.identifier, { ...
    'FormationBundleSuspension:Infeasible', ...
    'FormationBundleSuspension:InvalidCandidate', ...
    'FormationBackboneTour:NonphysicalTour'}));
end

function value = formatFormation(id)
if isfinite(id)
    value = sprintf('%d', id);
else
    value = '--';
end
end

function value = medianOrZero(values)
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = median(values);
end
end

function value = maxOrZero(values)
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = max(values);
end
end

function value = minOrZero(values)
values = values(isfinite(values));
if isempty(values)
    value = 0;
else
    value = min(values);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
