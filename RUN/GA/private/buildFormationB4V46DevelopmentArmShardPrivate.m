function connected = isStronglyConnectedLocal(adjacency)
adjacency = logical(adjacency);
if size(adjacency, 1) ~= size(adjacency, 2) || isempty(adjacency)
    connected = false;
    return;
end
connected = all(reachableFromOne(adjacency)) && ...
    all(reachableFromOne(adjacency'));
end

function visited = reachableFromOne(adjacency)
nodeCount = size(adjacency, 1);
visited = false(1, nodeCount);
queue = zeros(1, nodeCount);
head = 1;
tail = 1;
queue(1) = 1;
visited(1) = true;
while head <= tail
    node = queue(head);
    head = head + 1;
    neighbors = find(adjacency(node, :) & ~visited);
    for neighborIdx = 1:numel(neighbors)
        neighbor = neighbors(neighborIdx);
        if ~visited(neighbor)
            visited(neighbor) = true;
            tail = tail + 1;
            queue(tail) = neighbor;
        end
    end
end
end
