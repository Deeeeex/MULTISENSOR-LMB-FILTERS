function result = containsForbiddenTargetTruth(value)
result = false;
if iscell(value)
    for valueIdx = 1:numel(value)
        if containsForbiddenTargetTruth(value{valueIdx})
            result = true;
            return;
        end
    end
    return;
end
if ~isstruct(value)
    return;
end
names = fieldnames(value);
for valueIdx = 1:numel(value)
    for fieldIdx = 1:numel(names)
        lowerName = lower(names{fieldIdx});
        if any(strcmp(lowerName, { ...
                'groundtruth', 'groundtruthrfs', 'truth', ...
                'trackingtruth', 'trackingtruthrfs', ...
                'targettrajectories', ...
                'explicittargettrajectories'})) || ...
                ~isempty(strfind(lowerName, 'groundtruth')) || ... %#ok<STREMP>
                ~isempty(strfind(lowerName, 'targettrajector')) %#ok<STREMP>
            result = true;
            return;
        end
        if containsForbiddenTargetTruth(value(valueIdx).(names{fieldIdx}))
            result = true;
            return;
        end
    end
end
end

function value = exactFields(value, expected)
value = isstruct(value) && isscalar(value) && ...
    isequal(sort(fieldnames(value)), sort(reshape(expected, [], 1)));
end

function value = isTrue(value)
value = islogical(value) && isscalar(value) && value;
end

function value = isFalse(value)
value = islogical(value) && isscalar(value) && ~value;
end

function value = isOrderedTimestampPair(startedAt, completedAt)
value = false;
if ~ischar(startedAt) || ~isrow(startedAt) || isempty(startedAt) || ...
        ~ischar(completedAt) || ~isrow(completedAt) || isempty(completedAt)
    return;
end

try
    startedValue = datenum(startedAt, 31);
    completedValue = datenum(completedAt, 31);
    value = isfinite(startedValue) && isfinite(completedValue) && ...
        completedValue >= startedValue;
catch
    value = false;
end
end

