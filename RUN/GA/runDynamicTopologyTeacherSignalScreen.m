function summary = aggregateSummary( ...
    presetName, seeds, records, validations, options)
summary = struct();
summary.generatedAt = datestr(now, 31);
summary.presetName = presetName;
summary.seeds = seeds;
summary.records = records;
summary.validationBySeed = validations;
summary.options = options;
summary.meanPredictiveGainVsStatic = finiteMean( ...
    [records.predictiveGainVsStatic]);
summary.medianPredictiveGainVsStatic = finiteMedian( ...
    [records.predictiveGainVsStatic]);
summary.positiveGainVsStaticRate = finiteMean( ...
    [records.predictiveGainVsStatic] > 1e-9);
summary.meanPredictiveGainVsCurrent = finiteMean( ...
    [records.predictiveGainVsCurrent]);
summary.medianPredictiveGainVsCurrent = finiteMedian( ...
    [records.predictiveGainVsCurrent]);
summary.positiveGainVsCurrentRate = finiteMean( ...
    [records.predictiveGainVsCurrent] > 1e-9);
summary.changedTopologyRate = mean( ...
    [records.selectedDifferentTopology]);
summary.meanPredictiveRelativeRiskSpread = finiteMean( ...
    [records.predictiveRelativeRiskSpread]);
summary.meanValidCandidateCount = finiteMean( ...
    [records.validCandidateCount]);
summary.meanBehaviorEospa = finiteMean( ...
    [records.behaviorEospa]);
summary.meanBehaviorCardinalityError = finiteMean( ...
    [records.behaviorCardinalityError]);
normalizedEospa = [records.behaviorEospa] ./ max( ...
    [records.behaviorOspaCutoff], eps);
normalizedCardinalityError = ...
    [records.behaviorCardinalityError] ./ max( ...
        [records.behaviorActiveTargetCount], 1);
summary.maxNormalizedBehaviorEospa = max(normalizedEospa);
summary.maxNormalizedBehaviorCardinalityError = ...
    max(normalizedCardinalityError);
summary.behaviorHealthPass = ...
    all(normalizedEospa <= ...
        options.behaviorHealthMaxNormalizedEospa + 1e-12) && ...
    all(normalizedCardinalityError <= ...
        options.behaviorHealthMaxNormalizedCardinalityError + 1e-12);
summary.closedLoopEnabled = options.closedLoopHorizonSteps > 0;
summary.currentOnly = isequal(options.teacherHorizonSteps, 0) && ...
    ~summary.closedLoopEnabled;
summary.meanClosedLoopGainVsStatic = finiteMean( ...
    [records.closedLoopGainVsStatic]);
summary.meanClosedLoopGainVsCurrent = finiteMean( ...
    [records.closedLoopGainVsCurrent]);
summary.positiveClosedLoopGainVsCurrentRate = ...
    positiveFiniteRate([records.closedLoopGainVsCurrent]);
closedValid = isfinite([records.closedLoopCandidateIndex]);
if any(closedValid)
    summary.closedLoopChangedTopologyRate = mean( ...
        [records(closedValid).closedLoopSelectedDifferentTopology]);
else
    summary.closedLoopChangedTopologyRate = NaN;
end
summary.meanClosedLoopRelativeRiskSpread = finiteMean( ...
    [records.closedLoopRelativeRiskSpread]);
summary.meanClosedLoopTeacherSeconds = finiteMean( ...
    [records.closedLoopTeacherSeconds]);
summary.strongFixed = summarizeStrongFixedBaseline( ...
    records, options.staticTrainingSeeds);
summary.decision = decideSignal(summary, numel(seeds));
summary.claimBoundary = [ ...
    'This paired snapshot test validates counterfactual label ', ...
    'separation and action sensitivity only. Closed-loop tracking ', ...
    'improvement requires a separate paired policy experiment.'];
end

function decision = decideSignal(summary, seedCount)
decision = struct( ...
    'status', 'screening-only', ...
    'recommendation', [ ...
        'Run a paired closed-loop policy comparison before making ', ...
        'a tracking-performance claim.']);
if ~summary.behaviorHealthPass
    decision.status = 'stop-unhealthy-behavior-state';
    decision.recommendation = sprintf([ ...
        'The shared behavior snapshot fails the registered filter-health ', ...
        'gate (normalized E-OSPA %.3f, normalized cardinality error ', ...
        '%.3f); redesign the scale scene or filter before comparing ', ...
        'topology policies.'], ...
        summary.maxNormalizedBehaviorEospa, ...
        summary.maxNormalizedBehaviorCardinalityError);
    return;
end
if summary.currentOnly
    if summary.meanPredictiveRelativeRiskSpread < 0.005
        decision.status = 'stop-weak-current-task-signal';
        decision.recommendation = [ ...
            'Current task risk changes by less than 0.5 percent ', ...
            'across feasible actions; do not generate labels yet.'];
    elseif summary.meanPredictiveGainVsStatic <= 0
        decision.status = 'stop-current-task-dominated';
        decision.recommendation = [ ...
            'The best current task-risk action does not improve on ', ...
            'the registered static graph at this snapshot.'];
    else
        decision.status = 'current-task-signal';
        decision.recommendation = [ ...
            'Current task risk separates feasible actions at this ', ...
            'scale; validate realized closed-loop performance next.'];
    end
elseif summary.closedLoopEnabled
    if summary.meanClosedLoopRelativeRiskSpread < 0.005
        decision.status = 'stop-weak-closed-loop-signal';
        decision.recommendation = [ ...
            'Future-measurement rollouts change task risk by less ', ...
            'than 0.5 percent; redesign the scene or teacher target.'];
    elseif summary.positiveClosedLoopGainVsCurrentRate < 0.50
        decision.status = 'stop-closed-loop-redundant';
        decision.recommendation = [ ...
            'The future-measurement rollout rarely improves on the ', ...
            'current-risk action; do not train on these labels.'];
    elseif seedCount < 3
        decision.status = 'screening-only';
        decision.recommendation = [ ...
            'Closed-loop labels differ on this runtime screen; ', ...
            'repeat on at least three paired seeds before training.'];
    else
        decision.status = 'continue-held-out-validation';
        decision.recommendation = [ ...
            'Closed-loop labels are action-sensitive and improve on ', ...
            'current-risk actions; test a frozen policy on held-out seeds.'];
    end
elseif summary.meanPredictiveRelativeRiskSpread < 0.005
    decision.status = 'stop-weak-action-signal';
    decision.recommendation = [ ...
        'Candidate actions change predictive task risk by less than ', ...
        '0.5 percent on average; redesign the scene or horizon.'];
elseif summary.positiveGainVsCurrentRate < 0.50
    decision.status = 'stop-lookahead-redundant';
    decision.recommendation = [ ...
        'Look-ahead rarely changes the action value relative to the ', ...
        'current-risk teacher; do not train on the predictive labels.'];
elseif seedCount < 3
    decision.status = 'screening-only';
else
    decision.status = 'continue-closed-loop-validation';
    decision.recommendation = [ ...
        'The predictive labels are action-sensitive and differ from ', ...
        'the current-risk labels. Compare policies on held-out seeds.'];
end
end

