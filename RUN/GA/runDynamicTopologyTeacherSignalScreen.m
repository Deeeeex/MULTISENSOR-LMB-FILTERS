function [reportPath, summary] = ...
    runDynamicTopologyTeacherSignalScreen(presetName, seedList, options)
% RUNDYNAMICTOPOLOGYTEACHERSIGNALSCREEN Paired teacher-label diagnostic.
%
% The screen first runs one fixed-topology behavior trajectory and captures
% local LMB posteriors at registered times. Current-risk and predictive-risk
% teachers then score exactly the same candidate pool and posterior state.
% This isolates whether look-ahead changes the counterfactual action labels;
% it is not, by itself, evidence of realized closed-loop tracking gains.
%
% Example:
%   opts = struct('snapshotTimes', 35:10:95);
%   runDynamicTopologyTeacherSignalScreen('d12-hard', 1:3, opts);

if nargin < 1 || isempty(presetName)
    presetName = 'd12-hard';
end
if nargin < 2 || isempty(seedList)
    seedList = 1:3;
end
if nargin < 3 || isempty(options)
    options = struct();
end
seedList = reshape(seedList, 1, []);
options = resolveOptions(options);
records = repmat(emptyRecord(), 0, 1);
validationBySeed = cell(1, numel(seedList));

fprintf('Teacher-signal screen: %s, %d seed(s)\n', ...
    presetName, numel(seedList));
for seedIdx = 1:numel(seedList)
    seed = seedList(seedIdx);
    fprintf('Generating paired input for seed %d...\n', seed);
    inputs = generateDynamicTopologyScenarioInputs( ...
        presetName, seed, options.scenarioOverrides);
    validationBySeed{seedIdx} = inputs.validation;
    snapshotTimes = resolveSnapshotTimes( ...
        options.snapshotTimes, inputs.config);
    behaviorInputs = cropInputs( ...
        inputs, max(snapshotTimes));
    behaviorConfig = buildMixtureAwareKlaReferenceConfig( ...
        options.fusionOverrides);
    behaviorConfig.dynamicTopologyEnabled = false;
    behaviorConfig.topologyPosteriorCaptureTimes = snapshotTimes;
    cachePath = resolveBehaviorCachePath( ...
        options.behaviorCacheDirectory, presetName, seed, ...
        snapshotTimes);
    [cacheHit, behaviorBundle] = loadBehaviorBundle( ...
        cachePath, presetName, seed, snapshotTimes, inputs.config, ...
        behaviorConfig);
    if cacheHit
        behaviorSeconds = behaviorBundle.behaviorSeconds;
        behaviorEospaByTime = behaviorBundle.behaviorEospaByTime;
        behaviorCardinalityErrorByTime = ...
            behaviorBundle.behaviorCardinalityErrorByTime;
        posteriorSnapshots = behaviorBundle.posteriorSnapshots;
        fprintf('  reused behavior cache: %s\n', cachePath);
    else
        rng(seed + options.filterSeedOffset);
        behaviorTimer = tic;
        filterModel = behaviorInputs.model;
        if isSafeGraphCodebookOracleV152ExecutionContext( ...
                options.filterExecutionContext)
            filterModel = ...
                removeRealizedTargetTruthFromDynamicTopologyModel( ...
                    filterModel);
        end
        [behaviorEstimates, behaviorDiagnostics] = ...
            runEventTriggeredDistributedLmbFilter( ...
                filterModel, behaviorInputs.measurements, ...
                behaviorInputs.sensorTrajectories, ...
                behaviorInputs.neighborMap, ...
                behaviorInputs.commConfig, behaviorConfig, ...
                options.filterExecutionContext);
        behaviorSeconds = toc(behaviorTimer);
        [behaviorEospaByTime, behaviorCardinalityErrorByTime] = ...
            scoreBehavior( ...
                behaviorEstimates, behaviorInputs.model, ...
                behaviorInputs.groundTruthRfs);
        posteriorSnapshots = ...
            behaviorDiagnostics.topologyLocalPosteriorSnapshot;
        cacheContract = behaviorContinuationCacheContract();
        preDecisionTopologyHistoryByTime = ...
            buildBehaviorContinuationHistoryRecords( ...
                behaviorDiagnostics, snapshotTimes, ...
                cacheContract.topologyHistoryDepth);
        behaviorBundle = struct( ...
            'cacheContractVersion', cacheContract.version, ...
            'posteriorSnapshotConvention', ...
                cacheContract.posteriorSnapshotConvention, ...
            'topologyHistoryDepth', ...
                cacheContract.topologyHistoryDepth, ...
            'topologyHistoryConvention', ...
                cacheContract.topologyHistoryConvention, ...
            'presetName', presetName, ...
            'seed', seed, ...
            'snapshotTimes', snapshotTimes, ...
            'configSnapshot', inputs.config, ...
            'behaviorConfigSnapshot', behaviorConfig, ...
            'behaviorSeconds', behaviorSeconds, ...
            'behaviorEospaByTime', behaviorEospaByTime, ...
            'behaviorCardinalityErrorByTime', ...
                behaviorCardinalityErrorByTime, ...
            'posteriorSnapshots', {posteriorSnapshots}, ...
            'preDecisionTopologyHistoryByTime', ...
                {preDecisionTopologyHistoryByTime});
        saveBehaviorBundle(cachePath, behaviorBundle);
    end
    fprintf('  behavior trajectory %.2f s; %d snapshots\n', ...
        behaviorSeconds, numel(snapshotTimes));
    if options.behaviorCacheOnly
        continue;
    end

    for snapshotIdx = 1:numel(snapshotTimes)
        currentTime = snapshotTimes(snapshotIdx);
        localPosteriors = posteriorSnapshots{currentTime};
        if isempty(localPosteriors)
            error('Missing posterior snapshot at time %d.', currentTime);
        end
        context = buildTeacherContext( ...
            inputs, localPosteriors, currentTime, behaviorConfig);

        context.triggerConfig.topologyTeacherHorizonSteps = 0;
        [currentAdjacency, currentDetails] = ...
            selectCounterfactualTopologyTeacher(context, 'current');
        context.triggerConfig.topologyTeacherHorizonSteps = ...
            options.teacherHorizonSteps;
        context.triggerConfig.topologyTeacherDiscountFactor = ...
            options.teacherDiscountFactor;
        if isequal(options.teacherHorizonSteps, 0)
            predictiveAdjacency = currentAdjacency;
            predictiveDetails = currentDetails;
        else
            [predictiveAdjacency, predictiveDetails] = ...
                selectCounterfactualTopologyTeacher( ...
                    context, 'predictive');
        end

        record = buildRecord( ...
            seed, currentTime, currentAdjacency, currentDetails, ...
            predictiveAdjacency, predictiveDetails, behaviorSeconds, ...
            behaviorEospaByTime(currentTime), ...
            behaviorCardinalityErrorByTime(currentTime), ...
            inputs.model.ospaParameters.eC, ...
            inputs.groundTruthRfs.cardinality(currentTime));
        if options.closedLoopHorizonSteps > 0
            context.triggerConfig. ...
                topologyTeacherClosedLoopHorizonSteps = ...
                options.closedLoopHorizonSteps;
            context.triggerConfig. ...
                topologyTeacherCandidatePersistenceSteps = ...
                options.closedLoopPersistenceSteps;
            rolloutData = struct( ...
                'measurements', {inputs.measurements}, ...
                'continuationAdjacency', ...
                    inputs.graphData.staticAdjacency);
            [closedLoopAdjacency, closedLoopDetails] = ...
                selectClosedLoopCounterfactualTopologyTeacher( ...
                    context, rolloutData);
            record = attachClosedLoopRecord( ...
                record, currentAdjacency, currentDetails, ...
                closedLoopAdjacency, closedLoopDetails);
        end
        records(end+1, 1) = record; %#ok<AGROW>
        if isequal(options.teacherHorizonSteps, 0)
            fprintf(['  t=%d current gain vs static %.3f%%, ', ...
                'spread %.3f%%, candidates %d\n'], ...
                currentTime, 100 * record.predictiveGainVsStatic, ...
                100 * record.predictiveRelativeRiskSpread, ...
                record.validCandidateCount);
        else
            fprintf(['  t=%d predictive gain vs static %.3f%%, ', ...
                'vs current %.3f%%, spread %.3f%%, candidates %d\n'], ...
                currentTime, 100 * record.predictiveGainVsStatic, ...
                100 * record.predictiveGainVsCurrent, ...
                100 * record.predictiveRelativeRiskSpread, ...
                record.validCandidateCount);
        end
        if options.closedLoopHorizonSteps > 0
            fprintf(['       closed-loop gain vs static %.3f%%, ', ...
                'vs current %.3f%%, spread %.3f%%, %.2f s\n'], ...
                100 * record.closedLoopGainVsStatic, ...
                100 * record.closedLoopGainVsCurrent, ...
                100 * record.closedLoopRelativeRiskSpread, ...
                record.closedLoopTeacherSeconds);
        end
    end
end

if options.behaviorCacheOnly
    reportPath = '';
    summary = struct( ...
        'generatedAt', datestr(now, 31), ...
        'presetName', presetName, ...
        'seeds', seedList, ...
        'behaviorCacheOnly', true, ...
        'options', options, ...
        'validationBySeed', {validationBySeed});
    return;
end
summary = aggregateSummary( ...
    presetName, seedList, records, validationBySeed, options);
reportPath = '';
if options.writeReport
    if ~exist(options.outputDirectory, 'dir')
        mkdir(options.outputDirectory);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS');
    stem = sprintf('DYNAMIC_TOPOLOGY_TEACHER_SIGNAL_%s_N%d_%s', ...
        upper(strrep(char(presetName), '-', '_')), ...
        numel(seedList), timestamp);
    reportPath = fullfile( ...
        options.outputDirectory, [stem, '.md']);
    matPath = fullfile( ...
        options.outputDirectory, [stem, '.mat']);
    writeReport(reportPath, summary);
    save(matPath, 'summary');
    summary.reportPath = reportPath;
    summary.matPath = matPath;
    fprintf('Report: %s\n', reportPath);
end
end

function options = resolveOptions(options)
options.snapshotTimes = getField(options, 'snapshotTimes', []);
options.teacherHorizonSteps = getField( ...
    options, 'teacherHorizonSteps', [0, 3, 6]);
options.teacherDiscountFactor = getField( ...
    options, 'teacherDiscountFactor', 0.9);
options.closedLoopHorizonSteps = max(0, round(getField( ...
    options, 'closedLoopHorizonSteps', 0)));
options.closedLoopPersistenceSteps = max(1, round(getField( ...
    options, 'closedLoopPersistenceSteps', 1)));
options.staticTrainingSeeds = reshape(getField( ...
    options, 'staticTrainingSeeds', []), 1, []);
options.behaviorCacheOnly = logical(getField( ...
    options, 'behaviorCacheOnly', false));
options.writeReport = getField(options, 'writeReport', true);
options.scenarioOverrides = getField( ...
    options, 'scenarioOverrides', struct());
options.fusionOverrides = getField( ...
    options, 'fusionOverrides', struct());
options.outputDirectory = getField(options, 'outputDirectory', ...
    fullfile('RUN', 'GA', 'dynamic_topology'));
options.behaviorCacheDirectory = getField( ...
    options, 'behaviorCacheDirectory', '');
options.filterExecutionContext = getField( ...
    options, 'filterExecutionContext', struct());
if ~isstruct(options.filterExecutionContext) || ...
        ~isscalar(options.filterExecutionContext)
    error('filterExecutionContext must be a scalar structure.');
end
options.filterSeedOffset = getField( ...
    options, 'filterSeedOffset', 200000);
options.behaviorHealthMaxNormalizedEospa = max(0, getField( ...
    options, 'behaviorHealthMaxNormalizedEospa', 0.50));
options.behaviorHealthMaxNormalizedCardinalityError = max(0, getField( ...
    options, 'behaviorHealthMaxNormalizedCardinalityError', 0.25));
end

function times = resolveSnapshotTimes(requested, config)
if isempty(requested)
    times = unique(round(linspace( ...
        config.focusWindow(1), config.focusWindow(end), 7)));
else
    times = unique(round(reshape(requested, 1, [])));
end
times = times(times >= 1 & times <= config.simulationLength);
if isempty(times)
    error('No requested teacher snapshot lies inside the scenario.');
end
end

function path = resolveBehaviorCachePath( ...
    directory, presetName, seed, snapshotTimes)
if isempty(directory)
    path = '';
    return;
end
signature = sum(snapshotTimes .* (1:numel(snapshotTimes)));
stem = sprintf('%s_seed%d_n%d_sig%d.mat', ...
    lower(strrep(char(presetName), '-', '_')), ...
    seed, numel(snapshotTimes), signature);
path = fullfile(directory, stem);
end

function [hit, bundle] = loadBehaviorBundle( ...
    path, presetName, seed, snapshotTimes, configSnapshot, ...
    behaviorConfigSnapshot)
hit = false;
bundle = struct();
if isempty(path) || ~exist(path, 'file')
    return;
end
loaded = load(path, 'behaviorBundle');
if ~isfield(loaded, 'behaviorBundle')
    return;
end
bundle = loaded.behaviorBundle;
required = { ...
    'cacheContractVersion', 'posteriorSnapshotConvention', ...
    'topologyHistoryDepth', 'topologyHistoryConvention', ...
    'presetName', 'seed', 'snapshotTimes', 'configSnapshot', ...
    'behaviorConfigSnapshot', ...
    'behaviorSeconds', ...
    'behaviorEospaByTime', 'behaviorCardinalityErrorByTime', ...
    'posteriorSnapshots', 'preDecisionTopologyHistoryByTime'};
if ~all(isfield(bundle, required))
    return;
end
hit = strcmp(bundle.presetName, presetName) && ...
    bundle.seed == seed && ...
    isequal(bundle.snapshotTimes, snapshotTimes) && ...
    isequaln(bundle.configSnapshot, configSnapshot) && ...
    isequaln( ...
        bundle.behaviorConfigSnapshot, behaviorConfigSnapshot);
if ~hit
    return;
end
try
    for snapshotTime = snapshotTimes
        extractBehaviorContinuationSnapshot( ...
            bundle, snapshotTime, configSnapshot.numberOfSensors);
    end
catch
    hit = false;
end
end

function saveBehaviorBundle(path, behaviorBundle)
if isempty(path)
    return;
end
directory = fileparts(path);
if ~isempty(directory) && ~exist(directory, 'dir')
    mkdir(directory);
end
save(path, 'behaviorBundle', '-v7');
fprintf('  saved behavior cache: %s\n', path);
end

function inputs = cropInputs(inputs, timeCount)
availableTime = size(inputs.measurements, 2);
timeCount = min(max(1, round(timeCount)), availableTime);
inputs.measurements = inputs.measurements(:, 1:timeCount);
for sensorIdx = 1:numel(inputs.sensorTrajectories)
    inputs.sensorTrajectories{sensorIdx} = ...
        inputs.sensorTrajectories{sensorIdx}(:, 1:timeCount);
end
if ndims(inputs.commConfig.pDropByEdge) >= 3
    inputs.commConfig.pDropByEdge = ...
        inputs.commConfig.pDropByEdge(:, :, 1:timeCount);
end
inputs.commConfig.linkUniforms = ...
    inputs.commConfig.linkUniforms(:, :, 1:timeCount);
fields = {'x', 'mu', 'Sigma'};
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    inputs.groundTruthRfs.(fieldName) = ...
        inputs.groundTruthRfs.(fieldName)(1:timeCount);
end
inputs.groundTruthRfs.cardinality = ...
    inputs.groundTruthRfs.cardinality(1:timeCount);
inputs.model.simulationLength = timeCount;
end

function context = buildTeacherContext( ...
    inputs, localPosteriors, currentTime, triggerConfig)
sensorCount = inputs.config.numberOfSensors;
context = struct();
context.localPosteriorBySensor = localPosteriors;
context.model = inputs.model;
context.commConfig = inputs.commConfig;
context.triggerConfig = triggerConfig;
context.currentTime = currentTime;
context.previousAdjacency = inputs.graphData.staticAdjacency;
context.baseAdjacency = inputs.graphData.staticAdjacency;
context.physicalAdjacency = ...
    inputs.graphData.physicalAdjacency(:, :, currentTime);
context.edgeScores = buildReliabilityScores( ...
    inputs.commConfig, currentTime, sensorCount);
context.edgeBudget = inputs.config.edgeBudget;
context.positions = zeros(2, sensorCount);
for sensorIdx = 1:sensorCount
    context.positions(:, sensorIdx) = ...
        inputs.sensorTrajectories{sensorIdx}(1:2, currentTime);
end
end

function scores = buildReliabilityScores(commConfig, currentTime, nodeCount)
scores = -inf(nodeCount);
for leftIdx = 1:nodeCount-1
    for rightIdx = leftIdx+1:nodeCount
        value = 1 - 0.5 * ( ...
            edgeDrop(commConfig, leftIdx, rightIdx, currentTime) + ...
            edgeDrop(commConfig, rightIdx, leftIdx, currentTime));
        scores(leftIdx, rightIdx) = value;
        scores(rightIdx, leftIdx) = value;
    end
end
end

function record = buildRecord( ...
    seed, currentTime, currentAdjacency, currentDetails, ...
    predictiveAdjacency, predictiveDetails, behaviorSeconds, ...
    behaviorEospa, behaviorCardinalityError, ospaCutoff, ...
    activeTargetCount)
currentIdx = currentDetails.candidateIndex;
currentRiskUnderPredictive = NaN;
if isfinite(currentIdx) && currentIdx >= 1 && ...
        currentIdx <= numel(predictiveDetails.candidateTaskRisks)
    currentRiskUnderPredictive = ...
        predictiveDetails.candidateTaskRisks(currentIdx);
end
staticRisk = predictiveDetails.baselineTaskRisk;
predictiveRisk = predictiveDetails.taskRisk;

record = emptyRecord();
record.seed = seed;
record.currentTime = currentTime;
record.currentCandidateIndex = currentIdx;
record.predictiveCandidateIndex = ...
    predictiveDetails.candidateIndex;
record.selectedDifferentTopology = ...
    ~isequal(currentAdjacency, predictiveAdjacency);
record.currentTaskRisk = currentDetails.taskRisk;
record.currentRiskUnderPredictive = currentRiskUnderPredictive;
record.predictiveTaskRisk = predictiveRisk;
record.staticPredictiveTaskRisk = staticRisk;
record.predictiveGainVsStatic = relativeGain( ...
    staticRisk, predictiveRisk);
record.predictiveGainVsCurrent = relativeGain( ...
    currentRiskUnderPredictive, predictiveRisk);
record.currentRelativeRiskSpread = relativeSpread( ...
    currentDetails.taskRiskSpread, currentDetails.baselineTaskRisk);
record.predictiveRelativeRiskSpread = relativeSpread( ...
    predictiveDetails.taskRiskSpread, staticRisk);
record.validCandidateCount = ...
    predictiveDetails.validCandidateCount;
record.baselineCandidateIndex = ...
    predictiveDetails.baselineCandidateIndex;
record.candidateSource = predictiveDetails.candidateSource;
record.predictiveCandidateTaskRisks = ...
    predictiveDetails.candidateTaskRisks;
record.behaviorSeconds = behaviorSeconds;
record.behaviorEospa = behaviorEospa;
record.behaviorCardinalityError = behaviorCardinalityError;
record.behaviorOspaCutoff = ospaCutoff;
record.behaviorActiveTargetCount = activeTargetCount;
record.currentTeacherSeconds = ...
    currentDetails.selectionSeconds;
record.predictiveTeacherSeconds = ...
    predictiveDetails.selectionSeconds;
end

function record = attachClosedLoopRecord( ...
    record, currentAdjacency, currentDetails, ...
    closedLoopAdjacency, closedLoopDetails)
currentIdx = currentDetails.candidateIndex;
currentRiskUnderClosedLoop = NaN;
if isfinite(currentIdx) && currentIdx >= 1 && ...
        currentIdx <= numel(closedLoopDetails.candidateTaskRisks)
    currentRiskUnderClosedLoop = ...
        closedLoopDetails.candidateTaskRisks(currentIdx);
end
record.closedLoopCandidateIndex = ...
    closedLoopDetails.candidateIndex;
record.closedLoopSelectedDifferentTopology = ...
    ~isequal(currentAdjacency, closedLoopAdjacency);
record.closedLoopTaskRisk = closedLoopDetails.taskRisk;
record.closedLoopBaselineTaskRisk = ...
    closedLoopDetails.baselineTaskRisk;
record.currentRiskUnderClosedLoop = currentRiskUnderClosedLoop;
record.closedLoopGainVsStatic = relativeGain( ...
    closedLoopDetails.baselineTaskRisk, ...
    closedLoopDetails.taskRisk);
record.closedLoopGainVsCurrent = relativeGain( ...
    currentRiskUnderClosedLoop, closedLoopDetails.taskRisk);
record.closedLoopRelativeRiskSpread = relativeSpread( ...
    closedLoopDetails.taskRiskSpread, ...
    closedLoopDetails.baselineTaskRisk);
record.closedLoopValidCandidateCount = ...
    closedLoopDetails.validCandidateCount;
record.closedLoopTeacherSeconds = ...
    closedLoopDetails.selectionSeconds;
record.closedLoopCandidateTaskRisks = ...
    closedLoopDetails.candidateTaskRisks;
end

