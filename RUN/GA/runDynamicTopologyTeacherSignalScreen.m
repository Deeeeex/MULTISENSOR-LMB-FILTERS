    'candidateSource', '', ...
    'predictiveCandidateTaskRisks', [], ...
    'closedLoopCandidateIndex', NaN, ...
    'closedLoopSelectedDifferentTopology', false, ...
    'closedLoopTaskRisk', NaN, ...
    'closedLoopBaselineTaskRisk', NaN, ...
    'currentRiskUnderClosedLoop', NaN, ...
    'closedLoopGainVsStatic', NaN, ...
    'closedLoopGainVsCurrent', NaN, ...
    'closedLoopRelativeRiskSpread', NaN, ...
    'closedLoopValidCandidateCount', NaN, ...
    'closedLoopTeacherSeconds', NaN, ...
    'closedLoopCandidateTaskRisks', [], ...
    'behaviorSeconds', NaN, ...
    'behaviorEospa', NaN, ...
