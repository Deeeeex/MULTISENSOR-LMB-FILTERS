function [meanEospa, meanCardinalityError] = ...
    scoreBehavior(estimates, model, truth)
sensorCount = numel(estimates);
timeCount = numel(truth.x);
eospa = zeros(sensorCount, timeCount);
cardinalityError = zeros(sensorCount, timeCount);
for sensorIdx = 1:sensorCount
    [sensorEospa, ~, cardinality] = ...
        computeSimulationOspa(model, truth, estimates{sensorIdx});
    eospa(sensorIdx, :) = sensorEospa;
    cardinalityError(sensorIdx, :) = abs( ...
        cardinality - truth.cardinality);
end
meanEospa = mean(eospa, 1);
meanCardinalityError = mean(cardinalityError, 1);
end

function result = summarizeStrongFixedBaseline(records, trainingSeeds)
result = struct( ...
    'available', false, ...
    'candidateIndex', NaN, ...
    'trainingSeeds', trainingSeeds, ...
    'evaluationSeeds', [], ...
    'evaluationSplit', 'unavailable', ...
    'bestFixedTaskRisk', NaN, ...
    'predictiveTaskRisk', NaN, ...
    'predictiveGainVsBestFixed', NaN);
if isempty(records) || ...
        ~all(strcmp({records.candidateSource}, 'registered-exact'))
    return;
end
lengths = cellfun(@numel, ...
    {records.predictiveCandidateTaskRisks});
if isempty(lengths) || any(lengths ~= lengths(1)) || lengths(1) < 1
    return;
end
riskMatrix = vertcat(records.predictiveCandidateTaskRisks);
recordSeeds = [records.seed];
if isempty(trainingSeeds)
    trainingMask = true(size(recordSeeds));
    evaluationMask = true(size(recordSeeds));
    result.evaluationSplit = 'in-sample diagnostic';
    result.trainingSeeds = unique(recordSeeds);
    result.evaluationSeeds = unique(recordSeeds);
else
    trainingMask = ismember(recordSeeds, trainingSeeds);
    evaluationMask = ~trainingMask;
    result.evaluationSplit = 'held-out seeds';
    result.evaluationSeeds = unique(recordSeeds(evaluationMask));
    if ~any(evaluationMask)
        evaluationMask = trainingMask;
        result.evaluationSplit = 'training-only diagnostic';
        result.evaluationSeeds = unique(recordSeeds(evaluationMask));
    end
end
if ~any(trainingMask) || ~any(evaluationMask)
    return;
end
trainingRisk = finiteColumnMean(riskMatrix(trainingMask, :));
[~, candidateIdx] = min(trainingRisk);
evaluationFixedRisk = finiteMean( ...
    riskMatrix(evaluationMask, candidateIdx));
evaluationPredictiveRisk = finiteMean( ...
    [records(evaluationMask).predictiveTaskRisk]);
result.available = isfinite(evaluationFixedRisk) && ...
    isfinite(evaluationPredictiveRisk);
result.candidateIndex = candidateIdx;
result.bestFixedTaskRisk = evaluationFixedRisk;
result.predictiveTaskRisk = evaluationPredictiveRisk;
result.predictiveGainVsBestFixed = relativeGain( ...
    evaluationFixedRisk, evaluationPredictiveRisk);
end

function means = finiteColumnMean(values)
means = inf(1, size(values, 2));
for columnIdx = 1:size(values, 2)
    column = values(:, columnIdx);
    column = column(isfinite(column));
    if ~isempty(column)
        means(columnIdx) = mean(column);
    end
end
end

function gain = relativeGain(reference, candidate)
if ~isfinite(reference) || ~isfinite(candidate)
    gain = NaN;
else
    gain = (reference - candidate) / max(abs(reference), eps);
end
end

function spread = relativeSpread(absoluteSpread, reference)
if ~isfinite(absoluteSpread) || ~isfinite(reference)
    spread = NaN;
else
    spread = absoluteSpread / max(abs(reference), eps);
end
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = finiteMedian(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end

function value = positiveFiniteRate(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values > 1e-9);
end
end

function probability = edgeDrop(config, senderIdx, receiverIdx, currentTime)
if isfield(config, 'pDropByEdge') && ~isempty(config.pDropByEdge)
    if ndims(config.pDropByEdge) >= 3
        probability = config.pDropByEdge( ...
            senderIdx, receiverIdx, currentTime);
    else
        probability = config.pDropByEdge(senderIdx, receiverIdx);
    end
elseif isfield(config, 'pDropBySensor') && ...
        numel(config.pDropBySensor) >= senderIdx
    probability = config.pDropBySensor(senderIdx);
else
    probability = 0;
end
probability = min(max(probability, 0), 1);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
