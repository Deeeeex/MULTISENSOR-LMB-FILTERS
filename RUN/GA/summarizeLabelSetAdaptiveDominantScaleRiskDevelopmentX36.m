function [reportPath, development] = ...
    summarizeLabelSetAdaptiveDominantScaleRiskDevelopmentX36(options)
% SUMMARIZELABELSETADAPTIVEDOMINANTSCALERISKDEVELOPMENTX36
% Select a v5 regret token on the five already-opened X36 pairs.
%
% Candidate runs are joined to the immutable v4 reference artifacts.  This
% avoids rerunning a deterministic paired baseline and keeps these five
% scenario-seed pairs explicitly in the development, not validation, split.

if nargin < 1 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.adaptiveDominantScaleRiskGatedRedesignAuthorized
    error('Scale-risk X36 development summarization is not authorized.');
end

seeds = protocol.adaptiveDominantScaleRiskGatedDevelopmentSeeds;
tokens = protocol.adaptiveDominantScaleRiskGatedRegretTokens;
armNames = protocol.adaptiveDominantScaleRiskGatedArmNames;
candidateRoot = getField(options, 'inputDirectory', ...
    protocol.adaptiveDominantScaleRiskGatedDevelopmentRoot);
baselineRoot = getField(options, 'baselineDirectory', ...
    protocol.adaptiveDominantScaleRiskGatedBaselineRoot);
rows = repmat(emptyRow(), numel(tokens), numel(seeds));
candidateRunCommits = cell(1, numel(seeds));

for seedIdx = 1:numel(seeds)
    seed = seeds(seedIdx);
    candidatePath = findSingleEvidence(candidateRoot, seed);
    candidateLoaded = load(candidatePath, 'summary');
    candidateSummary = candidateLoaded.summary;
    validateCandidateSummary( ...
        candidateSummary, seed, armNames, protocol);
    candidateRunCommits{seedIdx} = ...
        candidateSummary.generationGitCommit;

    baselinePath = findSingleEvidence(baselineRoot, seed);
    validateFrozenBaselineHash(baselinePath, seedIdx, protocol);
    baselineLoaded = load(baselinePath, 'summary');
    baselineSummary = baselineLoaded.summary;
    validateBaselineSummary(baselineSummary, seed, protocol);
    baseline = findArm(baselineSummary.aggregate, protocol. ...
        adaptiveDominantFullWindowReferenceArmName);

    for tokenIdx = 1:numel(tokens)
        candidate = findArm( ...
            candidateSummary.aggregate, armNames{tokenIdx});
        row = buildRow( ...
            seed, tokens(tokenIdx), baseline, candidate, ...
            candidatePath, baselinePath);
        row.hardSafetyPassed = ...
            hardSafetyPassed(row, protocol);
        rows(tokenIdx, seedIdx) = row;
    end
end

if numel(unique(candidateRunCommits, 'stable')) ~= 1
    error('Scale-risk X36 development seeds use multiple code commits.');
end
candidates = repmat(emptyCandidate(), 1, numel(tokens));
for tokenIdx = 1:numel(tokens)
    candidates(tokenIdx) = aggregateCandidate( ...
        tokens(tokenIdx), armNames{tokenIdx}, ...
        rows(tokenIdx, :), protocol);
end
selectedIndex = selectCandidate(candidates);

gitState = resolveResearchGitState();
development = struct();
development.protocolId = protocol.id;
development.contractVersion = protocol. ...
    adaptiveDominantScaleRiskGatedContractVersion;
development.generatedAt = datestr(now, 31);
development.generationGitCommit = gitState.commit;
development.generationTrackedWorktreeDirty = ...
    gitState.trackedWorktreeDirty;
development.generationUntrackedSourceFiles = ...
    gitState.untrackedSourceFiles;
development.candidateRunGenerationGitCommit = ...
    candidateRunCommits{1};
development.baselineRunGenerationGitCommit = protocol. ...
    adaptiveDominantCertifiedOverlapX36RunGenerationCommit;
development.presetName = protocol. ...
    adaptiveDominantScaleRiskGatedDevelopmentPresetName;
development.seeds = seeds;
development.times = protocol. ...
    adaptiveDominantScaleRiskGatedDevelopmentTimes;
development.regretTokens = tokens;
development.armNames = armNames;
development.rows = rows;
development.candidates = candidates;
development.selectionRule = protocol. ...
    adaptiveDominantScaleRiskGatedSelectionRule;
development.selectedCandidateIndex = selectedIndex;
development.developmentGatePassed = ~isempty(selectedIndex);
if isempty(selectedIndex)
    development.selectedRegretToken = NaN;
    development.selectedBaseRegretAllowance = NaN;
    development.selectedArmName = '';
    development.nextDirection = ...
        'redesign-before-freezing-any-X36-confirmation';
else
    development.selectedRegretToken = ...
        candidates(selectedIndex).regretToken;
    development.selectedBaseRegretAllowance = ...
        candidates(selectedIndex).baseRegretAllowance;
    development.selectedArmName = ...
        candidates(selectedIndex).armName;
    development.nextDirection = [ ...
        'freeze-selected-v5-token-before-registering-fresh-X36-', ...
        'and-larger-scale-confirmation-pairs'];
end
development.openedDevelopmentEvidenceOnly = true;
development.validationClaimAllowed = false;
development.evidenceBoundary = protocol. ...
    adaptiveDominantScaleRiskGatedEvidenceBoundary;

outputDirectory = getField(options, 'outputDirectory', ...
    fullfile(candidateRoot, 'summary'));
if exist(outputDirectory, 'dir') ~= 7
    mkdir(outputDirectory);
end
reportPath = fullfile(outputDirectory, ...
    'LABEL_SET_ADAPTIVE_DOMINANT_SCALE_RISK_X36_DEVELOPMENT_V5.md');
writeReport(reportPath, development, protocol);
matPath = strrep(reportPath, '.md', '.mat');
save('-mat7-binary', matPath, 'development');
development.reportPath = reportPath;
development.matPath = matPath;
fprintf('Scale-risk X36 development summary: %s\n', reportPath);
end

function row = buildRow( ...
        seed, token, baseline, candidate, candidatePath, baselinePath)
row = emptyRow();
row.seed = seed;
row.regretToken = token;
row.baseRegretAllowance = token / 100;
row.candidateEvidencePath = candidatePath;
row.baselineEvidencePath = baselinePath;
row.baselineEospa = baseline.focusEospa;
row.candidateEospa = candidate.focusEospa;
row.gainPercent = relativeGain( ...
    row.baselineEospa, row.candidateEospa);
row.baselineWorstEospa = baseline.focusWorstSensorEospa;
row.candidateWorstEospa = candidate.focusWorstSensorEospa;
row.baselineConsensusOspa = baseline.focusMapSetDisagreement;
row.candidateConsensusOspa = candidate.focusMapSetDisagreement;
row.baselineAttemptedBytes = baseline.focusAttemptedBytes;
row.candidateAttemptedBytes = candidate.focusAttemptedBytes;
row.byteDeltaPercent = 100 * ...
    (row.candidateAttemptedBytes - row.baselineAttemptedBytes) / ...
        max(row.baselineAttemptedBytes, eps);
row.meanMessageCount = candidate.meanDirectedMessageCount;
row.selectedSensorB3 = candidate. ...
    focusSelectedRollingB3SensorStrongFraction;
row.selectedFormationB3 = candidate. ...
    focusSelectedRollingB3FormationStrongFraction;
row.truthUseFraction = candidate.policyTruthUseFraction;
row.posteriorUseFraction = ...
    candidate.policyPosteriorContentUseFraction;
row.payloadMetadataUseFraction = candidate. ...
    policyPosteriorPayloadMetadataUseFraction;
row.currentLinkReliabilityUseFraction = candidate. ...
    policyCurrentLinkReliabilityUseFraction;
row.payloadConstraintFraction = candidate. ...
    policyPayloadConstraintEnforcedFraction;
row.payloadLimitPassFraction = candidate. ...
    policyPayloadLimitPassFraction;
row.repairRate = candidate.policyRepairRate;
row.payloadEmergencyRate = candidate.policyPayloadEmergencyRate;
row.topologyInfeasibleRate = candidate.focusTopologyInfeasibleRate;
row.minimumObjectiveAdvantage = candidate. ...
    policyMinimumDominantObjectiveAdvantage;
row.meanObjectiveAdvantage = candidate. ...
    policyMeanDominantObjectiveAdvantage;
row.fallbackMean = candidate.policyScaleRiskGateFallbackMean;
row.fallbackMaximum = candidate. ...
    policyScaleRiskGateFallbackMaximum;
row.fallbackActivationFraction = candidate. ...
    policyScaleRiskGateActivationFraction;
row.fallbackRejectedMean = candidate. ...
    policyScaleRiskGateFallbackRejectedMean;
row.objectiveFloor = candidate. ...
    policyScaleRiskGateObjectiveFloor;
row.globalPayloadPassFraction = candidate. ...
    policyScaleRiskGateGlobalPayloadPassFraction;
end

function candidate = aggregateCandidate(token, armName, rows, protocol)
candidate = emptyCandidate();
candidate.regretToken = token;
candidate.baseRegretAllowance = token / 100;
candidate.armName = armName;
candidate.seedGainPercent = [rows.gainPercent];
candidate.seedByteDeltaPercent = [rows.byteDeltaPercent];
candidate.baselineMeanEospa = mean([rows.baselineEospa]);
candidate.candidateMeanEospa = mean([rows.candidateEospa]);
candidate.meanGainPercent = relativeGain( ...
    candidate.baselineMeanEospa, candidate.candidateMeanEospa);
candidate.positiveSeedFraction = ...
    mean(candidate.seedGainPercent > 0);
candidate.minimumSeedGainPercent = ...
    min(candidate.seedGainPercent);
candidate.aggregateWorstGainPercent = relativeGain( ...
    mean([rows.baselineWorstEospa]), ...
    mean([rows.candidateWorstEospa]));
candidate.aggregateConsensusGainPercent = relativeGain( ...
    mean([rows.baselineConsensusOspa]), ...
    mean([rows.candidateConsensusOspa]));
baselineBytes = sum([rows.baselineAttemptedBytes]);
candidateBytes = sum([rows.candidateAttemptedBytes]);
candidate.aggregateByteSavingPercent = 100 * ...
    (baselineBytes - candidateBytes) / max(baselineBytes, eps);
candidate.maximumPositiveByteDeltaPercent = ...
    max([0, candidate.seedByteDeltaPercent]);
candidate.hardSafetyPassed = all([rows.hardSafetyPassed]);
candidate.trackingGatePassed = ...
    candidate.meanGainPercent >= protocol. ...
        adaptiveDominantScaleRiskGatedMinimumMeanGainPercent && ...
    candidate.positiveSeedFraction >= protocol. ...
        adaptiveDominantScaleRiskGatedMinimumPositiveSeedFraction;
candidate.tailGatePassed = ...
    (~protocol. ...
        adaptiveDominantScaleRiskGatedRequireNoAggregateWorstRegression || ...
        candidate.aggregateWorstGainPercent >= -1e-12) && ...
    (~protocol. ...
        adaptiveDominantScaleRiskGatedRequireNoAggregateConsensusRegression || ...
        candidate.aggregateConsensusGainPercent >= -1e-12);
candidate.communicationGatePassed = ...
    candidate.aggregateByteSavingPercent >= protocol. ...
        adaptiveDominantScaleRiskGatedMinimumByteSavingPercent && ...
    candidate.maximumPositiveByteDeltaPercent <= protocol. ...
        adaptiveDominantScaleRiskGatedMaximumPositiveByteDeltaPercent + ...
            1e-12;
candidate.developmentGatePassed = ...
    candidate.hardSafetyPassed && ...
    candidate.trackingGatePassed && ...
    candidate.tailGatePassed && ...
    candidate.communicationGatePassed;
candidate.meanFallbackCount = mean([rows.fallbackMean]);
candidate.maximumFallbackCount = max([rows.fallbackMaximum]);
candidate.meanFallbackActivationFraction = ...
    mean([rows.fallbackActivationFraction]);
candidate.meanRejectedFallbackCount = ...
    mean([rows.fallbackRejectedMean]);
end

function selectedIndex = selectCandidate(candidates)
eligible = find([candidates.developmentGatePassed]);
if isempty(eligible)
    selectedIndex = [];
    return;
end
selectedIndex = eligible(1);
for cursor = 2:numel(eligible)
    challenger = eligible(cursor);
    if isBetterCandidate( ...
            candidates(challenger), candidates(selectedIndex))
        selectedIndex = challenger;
    end
end
end

function better = isBetterCandidate(left, right)
tolerance = 1e-12;
leftValues = [ ...
    left.minimumSeedGainPercent, ...
    left.meanGainPercent, ...
    left.aggregateByteSavingPercent, ...
    -left.regretToken];
rightValues = [ ...
    right.minimumSeedGainPercent, ...
    right.meanGainPercent, ...
    right.aggregateByteSavingPercent, ...
    -right.regretToken];
better = false;
for valueIdx = 1:numel(leftValues)
    if leftValues(valueIdx) > rightValues(valueIdx) + tolerance
        better = true;
        return;
    elseif leftValues(valueIdx) < rightValues(valueIdx) - tolerance
        return;
    end
end
end

function passed = hardSafetyPassed(row, protocol)
expectedFloor = -row.baseRegretAllowance * sqrt( ...
    protocol.adaptiveDominantScaleRiskGatedReferenceFormationCount / ...
        protocol.adaptiveDominantCertifiedOverlapX36ExpectedFormationCount);
passed = ...
    row.meanMessageCount >= protocol. ...
        adaptiveDominantCertifiedOverlapX36MinimumMessageCount && ...
    row.meanMessageCount <= protocol. ...
        adaptiveDominantCertifiedOverlapX36MaximumMessageCount && ...
    row.selectedSensorB3 == 1 && ...
    row.selectedFormationB3 == 1 && ...
    row.truthUseFraction == 0 && ...
    row.posteriorUseFraction == 1 && ...
    row.payloadMetadataUseFraction == 1 && ...
    row.currentLinkReliabilityUseFraction == 1 && ...
    row.payloadConstraintFraction == 1 && ...
    row.payloadLimitPassFraction == 1 && ...
    row.globalPayloadPassFraction == 1 && ...
    abs(row.objectiveFloor - expectedFloor) < 1e-12 && ...
    isfinite(row.fallbackMean) && ...
    isfinite(row.fallbackMaximum) && ...
    (~protocol.adaptiveDominantScaleRiskGatedRequireNoRejectedFallback || ...
        row.fallbackRejectedMean == 0) && ...
    row.repairRate == 0 && ...
    row.payloadEmergencyRate == 0 && ...
    row.topologyInfeasibleRate == 0;
end

function validateCandidateSummary(summary, seed, armNames, protocol)
if ~strcmp(summary.presetName, protocol. ...
            adaptiveDominantScaleRiskGatedDevelopmentPresetName) || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'development') || ...
        summary.options.filterSeedOffset ~= protocol.filterSeedOffset || ...
        summary.options.continuationStartTime ~= protocol. ...
            adaptiveDominantScaleRiskGatedDevelopmentTimes(1) || ...
        summary.options.maxTimeSteps ~= protocol. ...
            adaptiveDominantScaleRiskGatedDevelopmentTimes(end) || ...
        numel(summary.aggregate) ~= numel(armNames) || ...
        ~all(ismember(armNames, {summary.aggregate.mode})) || ...
        ~isfield(summary, 'generationGitCommit') || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Scale-risk X36 candidate provenance contract failed.');
end
end

function validateBaselineSummary(summary, seed, protocol)
if ~strcmp(summary.presetName, protocol. ...
            adaptiveDominantScaleRiskGatedDevelopmentPresetName) || ...
        ~isequal(summary.seeds, seed) || ...
        ~strcmp(summary.options.evidenceSplit, 'scale-validation') || ...
        summary.options.filterSeedOffset ~= protocol.filterSeedOffset || ...
        ~any(strcmp({summary.aggregate.mode}, protocol. ...
            adaptiveDominantFullWindowReferenceArmName)) || ...
        ~strcmp(summary.generationGitCommit, protocol. ...
            adaptiveDominantCertifiedOverlapX36RunGenerationCommit) || ...
        summary.generationTrackedWorktreeDirty || ...
        ~isempty(summary.generationUntrackedSourceFiles)
    error('Frozen v4 X36 baseline provenance contract failed.');
end
end

function validateFrozenBaselineHash(path, seedIdx, protocol)
observed = computeFileSha256(path);
expected = protocol. ...
    adaptiveDominantCertifiedOverlapX36MatSha256{seedIdx};
if ~strcmp(observed, expected)
    error('Frozen X36 baseline MAT hash mismatch: %s', path);
end
end

function path = findSingleEvidence(rootDirectory, seed)
matches = dir(fullfile(rootDirectory, ...
    sprintf('seed%d', seed), '*.mat'));
if numel(matches) ~= 1
    error('Expected one MAT evidence file for seed %d.', seed);
end
path = fullfile(matches.folder, matches.name);
end

function arm = findArm(aggregate, mode)
idx = find(strcmp({aggregate.mode}, mode), 1);
if isempty(idx)
    error('Evidence is missing arm: %s', mode);
end
arm = aggregate(idx);
end

function gain = relativeGain(reference, candidate)
gain = 100 * (reference - candidate) / max(reference, eps);
end

function writeReport(path, development, protocol)
fid = fopen(path, 'w');
if fid < 0
    error('Unable to write report: %s', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# X36 scale-risk v5 development\n\n');
fprintf(fid, '- Generated: `%s`\n', development.generatedAt);
fprintf(fid, '- Contract: `%s`\n', development.contractVersion);
fprintf(fid, '- Candidate run commit: `%s`\n', ...
    development.candidateRunGenerationGitCommit);
fprintf(fid, '- Frozen baseline run commit: `%s`\n', ...
    development.baselineRunGenerationGitCommit);
fprintf(fid, '- Scenario: `%s`\n', development.presetName);
fprintf(fid, '- Seeds: `%s`\n', mat2str(development.seeds));
fprintf(fid, '- Times: `%s`\n', mat2str(development.times));
fprintf(fid, '- Selection rule: `%s`\n', development.selectionRule);
fprintf(fid, '- Development gate passed: `%d`\n', ...
    development.developmentGatePassed);
if development.developmentGatePassed
    fprintf(fid, '- Selected regret token: `%03d` (%.2f)\n', ...
        development.selectedRegretToken, ...
        development.selectedBaseRegretAllowance);
else
    fprintf(fid, '- Selected regret token: `none`\n');
end

fprintf(fid, '\n## Aggregate candidate comparison\n\n');
fprintf(fid, ['| Token | Mean E-OSPA gain | Positive seeds | Minimum ', ...
    'seed gain | Worst-node gain | Consensus gain | Byte saving | ', ...
    'Hard safety | Tracking | Tail | Communication | Gate |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|:--:|:--:|:--:|\n']);
for candidate = development.candidates
    fprintf(fid, ['| %03d | %.3f%% | %.0f/%d | %.3f%% | %.3f%% | ', ...
        '%.3f%% | %.3f%% | %d | %d | %d | %d | %d |\n'], ...
        candidate.regretToken, candidate.meanGainPercent, ...
        candidate.positiveSeedFraction * numel(development.seeds), ...
        numel(development.seeds), candidate.minimumSeedGainPercent, ...
        candidate.aggregateWorstGainPercent, ...
        candidate.aggregateConsensusGainPercent, ...
        candidate.aggregateByteSavingPercent, ...
        candidate.hardSafetyPassed, candidate.trackingGatePassed, ...
        candidate.tailGatePassed, ...
        candidate.communicationGatePassed, ...
        candidate.developmentGatePassed);
end

fprintf(fid, '\n## Paired seed results\n\n');
fprintf(fid, ['| Token | Seed | Baseline E-OSPA | Candidate E-OSPA | ', ...
    'Gain | Worst baseline | Worst candidate | Consensus baseline | ', ...
    'Consensus candidate | Byte delta | Safe |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|\n']);
for tokenIdx = 1:size(development.rows, 1)
    for row = development.rows(tokenIdx, :)
        fprintf(fid, ['| %03d | %d | %.4f | %.4f | %.3f%% | ', ...
            '%.4f | %.4f | %.4f | %.4f | %.3f%% | %d |\n'], ...
            row.regretToken, row.seed, row.baselineEospa, ...
            row.candidateEospa, row.gainPercent, ...
            row.baselineWorstEospa, row.candidateWorstEospa, ...
            row.baselineConsensusOspa, row.candidateConsensusOspa, ...
            row.byteDeltaPercent, row.hardSafetyPassed);
    end
end

fprintf(fid, '\n## Gate activity\n\n');
fprintf(fid, ['| Token | Seed | Min objective advantage | Mean objective ', ...
    'advantage | Floor | Fallbacks / step | Max fallbacks | ', ...
    'Activation | Rejected / step | Global payload pass |\n']);
fprintf(fid, ['|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n']);
for tokenIdx = 1:size(development.rows, 1)
    for row = development.rows(tokenIdx, :)
        fprintf(fid, ['| %03d | %d | %.4f | %.4f | %.4f | %.3f | ', ...
            '%.0f | %.3f | %.3f | %.3f |\n'], ...
            row.regretToken, row.seed, ...
            row.minimumObjectiveAdvantage, ...
            row.meanObjectiveAdvantage, row.objectiveFloor, ...
            row.fallbackMean, row.fallbackMaximum, ...
            row.fallbackActivationFraction, ...
            row.fallbackRejectedMean, ...
            row.globalPayloadPassFraction);
    end
end

fprintf(fid, '\n## Interpretation boundary\n\n');
fprintf(fid, ['These five X36 pairs were already opened by the failed v4 ', ...
    'zero-shot test. They may select a v5 regret token, but cannot support ', ...
    'an X36 confirmation claim. The v4 reference rows are reused from ', ...
    'hash-checked immutable artifacts; only the new candidate arms were ', ...
    'rerun from the same continuation caches and RNG offset. The gate ', ...
    'uses current posterior and link features only, with no truth or ', ...
    'future outcome. A passing token must be frozen before testing ', ...
    'distinct X36 and larger-than-X36 pairs.\n']);
fprintf(fid, '\nProtocol boundary: %s\n', ...
    protocol.adaptiveDominantScaleRiskGatedEvidenceBoundary);
end

