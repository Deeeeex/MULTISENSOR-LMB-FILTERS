function [effectiveFormationIds, details] = ...
        applyOnlinePositiveNetFormationReleaseV191( ...
            selectedFormationIds, currentTime, formationCount, plan)
% APPLYONLINEPOSITIVENETFORMATIONRELEASEV191 Restore ordinary full payload.

selectedFormationIds = reshape(selectedFormationIds, 1, []);
if ~isnumeric(selectedFormationIds) || ...
        any(~isfinite(selectedFormationIds)) || ...
        any(selectedFormationIds < 1) || ...
        any(selectedFormationIds > formationCount) || ...
        any(selectedFormationIds ~= round(selectedFormationIds)) || ...
        numel(unique(selectedFormationIds)) ~= ...
            numel(selectedFormationIds) || ...
        ~isscalar(currentTime) || ~isnumeric(currentTime) || ...
        ~isfinite(currentTime) || currentTime < 1 || ...
        currentTime ~= round(currentTime) || ...
        ~isValidOnlinePositiveNetFormationReleaseV191Plan( ...
            plan, formationCount)
    error('OnlinePositiveNetReleaseV191:InvalidPlan', ...
        'The V191 selection or release plan is malformed.');
end

pageIdx = find(reshape(plan.times, 1, []) == currentTime, 1);
requestedFormationIds = zeros(1, 0);
if ~isempty(pageIdx)
    requestedFormationIds = reshape( ...
        plan.formationIdsByTime{pageIdx}, 1, []);
end
appliedFormationIds = intersect( ...
    selectedFormationIds, requestedFormationIds, 'stable');
effectiveFormationIds = setdiff( ...
    selectedFormationIds, appliedFormationIds, 'stable');

details = struct();
details.contractVersion = ...
    'online-positive-net-formation-release-v191-page-v1';
details.currentTime = currentTime;
details.selectedFormationIdsBeforeRelease = selectedFormationIds;
details.requestedFormationIds = requestedFormationIds;
details.appliedFormationIds = appliedFormationIds;
details.effectiveWithheldFormationIds = effectiveFormationIds;
details.releaseApplied = ~isempty(appliedFormationIds);
details.teacherMode = plan.teacherMode;
details.truthUsed = false;
details.futureInformationUsed = false;
end
