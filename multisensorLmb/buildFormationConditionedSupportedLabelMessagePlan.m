function plan = buildFormationConditionedSupportedLabelMessagePlan( ...
        localPosteriorBySensor, crossResidualEdgeMask, ...
        updateDiagnostics, model, triggerConfig, currentTime, ...
        scheduledFormationIdsOverride)
% BUILDFORMATIONCONDITIONEDSUPPORTEDLABELMESSAGEPLAN V62 layered payload.
%
% A frozen observable formation schedule selects where cross-formation input
% is restricted.  Within those physical carrier edges, the payload mode uses
% current sender/receiver association support to decide which complete
% Bernoulli Gaussian mixtures remain in the effective per-label graph.

sensorCount = numel(localPosteriorBySensor);
if ~iscell(localPosteriorBySensor) || ...
        ~isequal(size(crossResidualEdgeMask), ...
            [sensorCount, sensorCount]) || ...
        ~iscell(updateDiagnostics) || ...
        numel(updateDiagnostics) ~= sensorCount || ...
        ~isscalar(currentTime) || ~isfinite(currentTime)
    error('FormationSupportedLabelPlan:InvalidInput', ...
        'The posterior, carrier edge mask, diagnostics, or time is invalid.');
end
timeIdx = [];
if nargin >= 7
    scheduledFormationIds = reshape( ...
        scheduledFormationIdsOverride, 1, []);
    if ~isnumeric(scheduledFormationIds) || ...
            any(~isfinite(scheduledFormationIds)) || ...
            any(scheduledFormationIds < 1) || ...
            any(scheduledFormationIds ~= round(scheduledFormationIds))
        error('FormationSupportedLabelPlan:InvalidOnlineSelection', ...
            'The online formation selection is malformed.');
    end
    scheduledFormationIds = unique( ...
        scheduledFormationIds, 'stable');
    scheduleSource = 'current-observable-online-policy';
else
    times = reshape(triggerConfig. ...
        receiverSafeFormationConditionedTimes, 1, []);
    schedules = triggerConfig. ...
        receiverSafeFormationConditionedSchedule;
    timeIdx = find(times == currentTime, 1);
    if isempty(timeIdx) || timeIdx > numel(schedules)
        error('FormationSupportedLabelPlan:ScheduleMissing', ...
            'The current time is absent from the V62 formation schedule.');
    end
    scheduledFormationIds = reshape(schedules{timeIdx}, 1, []);
    scheduleSource = 'frozen-formation-schedule';
end
groupIds = resolveFormationGroups(model, sensorCount);
payloadMode = lower(strrep(char(triggerConfig. ...
    receiverSafeFormationConditionedPayloadMode), '_', '-'));
fullPosteriorTrustMode = any(strcmp(payloadMode, { ...
    'full-posterior-trust', ...
    'binary-full-posterior-admission'}));
binaryAdmissionMode = strcmp( ...
    payloadMode, 'binary-full-posterior-admission');
formationTrustFactors = zeros(1, 0);
if fullPosteriorTrustMode
    if nargin >= 7 || isempty(timeIdx) || ...
            ~isfield(triggerConfig, ...
                'receiverSafeFormationConditionedTrustFactorsByTime') || ...
            ~iscell(triggerConfig. ...
                receiverSafeFormationConditionedTrustFactorsByTime) || ...
            numel(triggerConfig. ...
                receiverSafeFormationConditionedTrustFactorsByTime) < timeIdx
        error('FormationSupportedLabelPlan:MissingTrustSchedule', ...
            ['Full-posterior trust requires one frozen factor vector ', ...
             'for every formation schedule page.']);
    end
    formationTrustFactors = reshape(triggerConfig. ...
        receiverSafeFormationConditionedTrustFactorsByTime{timeIdx}, 1, []);
    if numel(formationTrustFactors) ~= numel(scheduledFormationIds) || ...
            any(~isfinite(formationTrustFactors)) || ...
            any(formationTrustFactors < 0) || ...
            any(formationTrustFactors > 1) || ...
            (binaryAdmissionMode && ...
             any(~ismember(formationTrustFactors, [0, 1])))
        error('FormationSupportedLabelPlan:InvalidTrustSchedule', ...
            ['Formation factors must match the scheduled formations; ', ...
             'the binary-admission mode permits only 0 or 1.']);
    end
end
hybridCorrectionMode = strcmp( ...
    payloadMode, 'hybrid-posterior-correction');
lightCorrectionFormationIds = zeros(1, 0);
fullCorrectionFormationIds = zeros(1, 0);
if hybridCorrectionMode
    if nargin >= 7 || isempty(timeIdx) || ...
            ~isfield(triggerConfig, ...
                'receiverSafeLightCorrectionFormationIdsByTime') || ...
            ~isfield(triggerConfig, ...
                'receiverSafeFullCorrectionFormationIdsByTime') || ...
            ~iscell(triggerConfig. ...
                receiverSafeLightCorrectionFormationIdsByTime) || ...
            ~iscell(triggerConfig. ...
                receiverSafeFullCorrectionFormationIdsByTime) || ...
            numel(triggerConfig. ...
                receiverSafeLightCorrectionFormationIdsByTime) < timeIdx || ...
            numel(triggerConfig. ...
                receiverSafeFullCorrectionFormationIdsByTime) < timeIdx
        error('FormationSupportedLabelPlan:MissingCorrectionSchedule', ...
            'The hybrid payload mode requires two frozen correction plans.');
    end
    lightCorrectionFormationIds = validateCorrectionFormations( ...
        triggerConfig.receiverSafeLightCorrectionFormationIdsByTime{ ...
            timeIdx}, scheduledFormationIds, 'light');
    fullCorrectionFormationIds = validateCorrectionFormations( ...
        triggerConfig.receiverSafeFullCorrectionFormationIdsByTime{ ...
            timeIdx}, scheduledFormationIds, 'full');
    if any(ismember(lightCorrectionFormationIds, ...
            fullCorrectionFormationIds))
        error('FormationSupportedLabelPlan:OverlappingCorrectionSchedule', ...
            'Light and full correction formations must be disjoint.');
    end
end
boundaryLabelModes = { ...
    'boundary-label-sender-supported-only', ...
    'boundary-label-sender-supported-or-high-existence', ...
    'boundary-label-receiver-need-aware', ...
    'boundary-label-frozen-whitelist'};
boundaryLabelMode = any(strcmp(payloadMode, boundaryLabelModes));
boundaryFormationId = 0;
if boundaryLabelMode
    boundaryFormationId = triggerConfig. ...
        receiverSafeBoundaryLabelFormationId;
    if ~isscalar(boundaryFormationId) || ...
            ~isfinite(boundaryFormationId) || ...
            boundaryFormationId ~= round(boundaryFormationId) || ...
            ~ismember(boundaryFormationId, groupIds)
        error('FormationSupportedLabelPlan:InvalidBoundaryFormation', ...
            'The label-wise boundary formation is invalid.');
    end
end
exceptionLabelsByReceiverSender = cell(sensorCount);
if ismember(payloadMode, { ...
        'signed-complete-label-exceptions', ...
        'boundary-label-frozen-whitelist'})
    if nargin >= 7 || isempty(timeIdx) || ...
            ~isfield(triggerConfig, ...
                'receiverSafeCompleteLabelExceptionsByTime') || ...
            ~iscell(triggerConfig. ...
                receiverSafeCompleteLabelExceptionsByTime) || ...
            numel(triggerConfig. ...
                receiverSafeCompleteLabelExceptionsByTime) < timeIdx
        error('FormationSupportedLabelPlan:MissingExceptionSchedule', ...
            'The complete-label whitelist mode requires a frozen time plan.');
    end
    exceptionLabelsByReceiverSender = triggerConfig. ...
        receiverSafeCompleteLabelExceptionsByTime{timeIdx};
    if ~iscell(exceptionLabelsByReceiverSender) || ...
            ~isequal(size(exceptionLabelsByReceiverSender), ...
                [sensorCount, sensorCount])
        error('FormationSupportedLabelPlan:InvalidExceptionSchedule', ...
            'One V108 exception page must be a sensor-by-sensor cell array.');
    end
end
supportThreshold = triggerConfig. ...
    receiverSafeExternalPositiveSupportThreshold;
existenceThreshold = triggerConfig. ...
    receiverSafeFormationConditionedHighExistenceThreshold;
activeThreshold = triggerConfig.payloadExistenceThreshold;

crossResidualEdgeMask = logical(crossResidualEdgeMask);
crossResidualEdgeMask(1:sensorCount+1:end) = false;
selectiveEdgeMask = false(sensorCount);
for receiverIdx = 1:sensorCount
    if ismember(groupIds(receiverIdx), scheduledFormationIds)
        selectiveEdgeMask(:, receiverIdx) = ...
            crossResidualEdgeMask(:, receiverIdx);
    end
end

plan = struct();
plan.contractVersion = ...
    'formation-conditioned-supported-label-message-plan-v62-v2';
plan.mode = 'formation-supported-label-plan';
plan.payloadMode = payloadMode;
plan.currentTime = currentTime;
plan.scheduledFormationIds = scheduledFormationIds;
plan.formationTrustFactors = formationTrustFactors;
plan.lightCorrectionFormationIds = lightCorrectionFormationIds;
plan.fullCorrectionFormationIds = fullCorrectionFormationIds;
plan.scheduleSource = scheduleSource;
plan.completeLabelExceptionsByReceiverSender = ...
    exceptionLabelsByReceiverSender;
plan.selectiveEdgeMask = selectiveEdgeMask;
plan.abstainFromFusionEdgeMask = false(sensorCount);
plan.labelWhitelistRestrictedEdgeMask = false(sensorCount);
plan.fusionTrustFactorByReceiverSender = ones(sensorCount);
plan.eventTypeByReceiverSender = 2 * ones(sensorCount);
if strcmp(payloadMode, 'abstention-only')
    plan.abstainFromFusionEdgeMask = selectiveEdgeMask;
elseif fullPosteriorTrustMode
    for receiverIdx = reshape(find(any(selectiveEdgeMask, 1)), 1, [])
        trustIdx = find(scheduledFormationIds == ...
            groupIds(receiverIdx), 1);
        senders = reshape(find(selectiveEdgeMask(:, receiverIdx)), 1, []);
        plan.fusionTrustFactorByReceiverSender( ...
            senders, receiverIdx) = formationTrustFactors(trustIdx);
        if formationTrustFactors(trustIdx) <= 1e-12
            plan.abstainFromFusionEdgeMask(senders, receiverIdx) = true;
        end
    end
elseif boundaryLabelMode
    for receiverIdx = reshape(find(any(selectiveEdgeMask, 1)), 1, [])
        senders = reshape(find(selectiveEdgeMask(:, receiverIdx)), 1, []);
        if groupIds(receiverIdx) == boundaryFormationId
            plan.labelWhitelistRestrictedEdgeMask( ...
                senders, receiverIdx) = true;
        else
            plan.abstainFromFusionEdgeMask(senders, receiverIdx) = true;
        end
    end
end
plan.payloadByReceiverSender = cell(sensorCount);
plan.synopsisByReceiverSender = cell(sensorCount);
plan.receiverDetails = repmat(makeReceiverDetails(), 1, sensorCount);
plan.activeLabelCountBySender = zeros(1, sensorCount);
plan.usesFullSenderPosteriors = fullPosteriorTrustMode && ...
    any(formationTrustFactors > 1e-12);
plan.isOnlineDeployable = ~ismember(payloadMode, { ...
    'signed-complete-label-exceptions', ...
    'boundary-label-frozen-whitelist', ...
    'hybrid-posterior-correction'});
plan.evidenceLabelInputCounts = struct( ...
    'positiveSupport', 0, ...
    'credibleNegative', 0, ...
    'unsupportedAbsence', 0, ...
    'ambiguous', 0, ...
    'missing', 0);

for receiverIdx = reshape(find(any(selectiveEdgeMask, 1)), 1, [])
    senders = reshape(find(selectiveEdgeMask(:, receiverIdx)), 1, []);
    receiverObjects = activeObjects( ...
        localPosteriorBySensor{receiverIdx}, activeThreshold);
    details = makeReceiverDetails();
    details.receiverIdx = receiverIdx;
    details.senders = senders;
    for localSenderIdx = 1:numel(senders)
        senderIdx = senders(localSenderIdx);
        senderObjects = activeObjects( ...
            localPosteriorBySensor{senderIdx}, activeThreshold);
        edgePayloadMode = payloadMode;
        if fullPosteriorTrustMode
            trustIdx = find(scheduledFormationIds == ...
                groupIds(receiverIdx), 1);
            if formationTrustFactors(trustIdx) <= 1e-12
                edgePayloadMode = 'control-only';
            else
                edgePayloadMode = 'full-posterior';
            end
        elseif hybridCorrectionMode
            receiverFormationId = groupIds(receiverIdx);
            if ismember(receiverFormationId, ...
                    fullCorrectionFormationIds)
                edgePayloadMode = 'full-posterior';
            elseif ismember(receiverFormationId, ...
                    lightCorrectionFormationIds)
                edgePayloadMode = 'light-posterior';
            else
                edgePayloadMode = 'control-only';
            end
        end
        if ismember(edgePayloadMode, { ...
                'light-posterior', 'full-posterior'})
            keepMask = true(1, numel(senderObjects));
        elseif strcmp(payloadMode, 'signed-complete-label-exceptions')
            keepMask = selectExplicitLabels( ...
                senderObjects, exceptionLabelsByReceiverSender{ ...
                    receiverIdx, senderIdx});
        elseif boundaryLabelMode
            if groupIds(receiverIdx) == boundaryFormationId
                if strcmp(payloadMode, ...
                        'boundary-label-frozen-whitelist')
                    keepMask = selectExplicitLabels( ...
                        senderObjects, ...
                        exceptionLabelsByReceiverSender{ ...
                            receiverIdx, senderIdx}, true);
                else
                    labelRule = strrep( ...
                        payloadMode, 'boundary-label-', '');
                    keepMask = selectLabels( ...
                        senderObjects, receiverObjects, labelRule, ...
                        supportThreshold, existenceThreshold);
                end
            else
                keepMask = false(1, numel(senderObjects));
            end
        else
            keepMask = selectLabels( ...
                senderObjects, receiverObjects, edgePayloadMode, ...
                supportThreshold, existenceThreshold);
        end
        payload = senderObjects(keepMask);
        selectedEventType = 2;
        if strcmp(edgePayloadMode, 'light-posterior')
            payload = compressLmbPosterior( ...
                payload, model, activeThreshold, triggerConfig, ...
                updateDiagnostics{senderIdx});
            selectedEventType = 1;
        end
        baselineStats = estimateLmbPayloadSize( ...
            senderObjects, model, 2, updateDiagnostics{senderIdx});
        selectedStats = estimateLmbPayloadSize( ...
            payload, model, selectedEventType, ...
            updateDiagnostics{senderIdx});
        if ismember(edgePayloadMode, { ...
                'light-posterior', 'full-posterior'})
            synopsis = emptySynopsis();
        else
            synopsis = compactSynopsis( ...
                numel(senderObjects), model.xDimension);
        end
        plan.payloadByReceiverSender{receiverIdx, senderIdx} = payload;
        plan.synopsisByReceiverSender{receiverIdx, senderIdx} = synopsis;
        plan.eventTypeByReceiverSender(senderIdx, receiverIdx) = ...
            selectedEventType;
        plan.activeLabelCountBySender(senderIdx) = max( ...
            plan.activeLabelCountBySender(senderIdx), ...
            numel(senderObjects));
        plan.evidenceLabelInputCounts = accumulateSupportCounts( ...
            plan.evidenceLabelInputCounts, senderObjects, ...
            supportThreshold);
        details.baselineFullBytesBySender(localSenderIdx) = ...
            baselineStats.estimatedBytes;
        details.controlSynopsisBytesBySender(localSenderIdx) = ...
            synopsis.estimatedBytes;
        details.selectedPayloadBytesBySender(localSenderIdx) = ...
            selectedStats.estimatedBytes;
        details.candidateLabelCount = ...
            details.candidateLabelCount + numel(senderObjects);
        details.selectedLabelCount = ...
            details.selectedLabelCount + nnz(keepMask);
    end
    details.baselineFullBytes = sum(details.baselineFullBytesBySender);
    details.controlSynopsisBytes = sum( ...
        details.controlSynopsisBytesBySender);
    details.selectedPayloadBytes = sum( ...
        details.selectedPayloadBytesBySender);
    details.totalAttemptedBytes = ...
        details.controlSynopsisBytes + details.selectedPayloadBytes;
    details.byteBudget = details.baselineFullBytes;
    details.byteBudgetSatisfied = ...
        details.totalAttemptedBytes <= details.byteBudget + 1e-9;
    plan.receiverDetails(receiverIdx) = details;
end

details = plan.receiverDetails;
plan.totalBaselineFullBytes = sum([details.baselineFullBytes]);
plan.totalControlSynopsisBytes = sum([details.controlSynopsisBytes]);
plan.totalSelectedPayloadBytes = sum([details.selectedPayloadBytes]);
plan.totalAttemptedBytes = sum([details.totalAttemptedBytes]);
plan.totalSelectedLabelCount = sum([details.selectedLabelCount]);
plan.totalCandidateLabelCount = sum([details.candidateLabelCount]);
plan.byteBudgetSatisfied = plan.totalAttemptedBytes <= ...
    plan.totalBaselineFullBytes + 1e-9;
end

function ids = validateCorrectionFormations(ids, protectedIds, name)
ids = reshape(ids, 1, []);
if ~isnumeric(ids) || any(~isfinite(ids)) || ...
        any(ids < 1) || any(ids ~= round(ids)) || ...
        numel(unique(ids)) ~= numel(ids) || ...
        any(~ismember(ids, protectedIds))
    error('FormationSupportedLabelPlan:InvalidCorrectionSchedule', ...
        'The %s correction formations must be unique protected IDs.', name);
end
end

function synopsis = emptySynopsis()
synopsis = struct( ...
    'contractVersion', 'lmb-no-separate-control-synopsis-v1', ...
    'labelCount', 0, ...
    'estimatedBytes', 0, ...
    'scalarCount', 0);
end

function keep = selectExplicitLabels(senderObjects, labels, allowMissing)
if nargin < 3
    allowMissing = false;
end
if isempty(labels)
    labels = zeros(2, 0);
end
if ~isnumeric(labels) || size(labels, 1) ~= 2 || ...
        any(~isfinite(labels(:))) || ...
        any(labels(:) ~= round(labels(:))) || ...
        size(unique(labels', 'rows'), 1) ~= size(labels, 2)
    error('FormationSupportedLabelPlan:InvalidExceptionLabels', ...
        'Every V108 exception list must be a unique 2-by-K label matrix.');
end
keep = false(1, numel(senderObjects));
for objectIdx = 1:numel(senderObjects)
    label = [senderObjects(objectIdx).birthTime; ...
        senderObjects(objectIdx).birthLocation];
    keep(objectIdx) = ~isempty(labels) && ...
        any(all(bsxfun(@eq, labels, label), 1));
end
if ~allowMissing && nnz(keep) ~= size(labels, 2)
    error('FormationSupportedLabelPlan:ExceptionLabelMissing', ...
        'A required frozen label is absent from the current sender payload.');
end
end

function keep = selectLabels( ...
        senderObjects, receiverObjects, mode, supportThreshold, ...
        existenceThreshold)
keep = false(1, numel(senderObjects));
for objectIdx = 1:numel(senderObjects)
    senderObject = senderObjects(objectIdx);
    label = [senderObject.birthTime; senderObject.birthLocation];
    receiverObject = findObject(receiverObjects, label);
    senderSupport = supportOf(senderObject);
    receiverSupport = supportOf(receiverObject);
    switch mode
        case 'control-only'
            keep(objectIdx) = false;
        case 'abstention-only'
            keep(objectIdx) = false;
        case 'sender-supported-only'
            keep(objectIdx) = senderSupport >= supportThreshold - 1e-12;
        case 'sender-supported-or-high-existence'
            keep(objectIdx) = ...
                senderSupport >= supportThreshold - 1e-12 || ...
                senderObject.r >= existenceThreshold - 1e-12;
        case 'receiver-need-aware'
            keep(objectIdx) = ...
                senderSupport >= supportThreshold - 1e-12 || ...
                receiverSupport < supportThreshold - 1e-12;
        otherwise
            error('FormationSupportedLabelPlan:UnknownPayloadMode', ...
                'Unknown V62 payload mode: %s.', mode);
    end
end
end

function groups = resolveFormationGroups(model, sensorCount)
if ~isstruct(model) || ~isfield(model, 'dynamicTopologyScenario') || ...
        ~isfield(model.dynamicTopologyScenario, 'config') || ...
        ~isfield(model.dynamicTopologyScenario.config, 'sensorGroupIds')
    error('FormationSupportedLabelPlan:MissingFormationGroups', ...
        'The V62 runtime model lacks formation membership.');
end
groups = reshape( ...
    model.dynamicTopologyScenario.config.sensorGroupIds, 1, []);
if numel(groups) ~= sensorCount
    error('FormationSupportedLabelPlan:InvalidFormationGroups', ...
        'The V62 formation membership does not match the sensor count.');
end
end

function objects = activeObjects(objects, threshold)
if isempty(objects)
    return;
end
objects = objects([objects.r] > threshold & ...
    [objects.numberOfGmComponents] > 0);
end

function object = findObject(objects, label)
object = [];
for objectIdx = 1:numel(objects)
    if objects(objectIdx).birthTime == label(1) && ...
            objects(objectIdx).birthLocation == label(2)
        object = objects(objectIdx);
        return;
    end
end
end

function value = supportOf(object)
value = 0;
if isstruct(object) && isscalar(object) && ...
        isfield(object, 'detectionAssociationMass') && ...
        isscalar(object.detectionAssociationMass) && ...
        isfinite(object.detectionAssociationMass)
    value = min(max(object.detectionAssociationMass, 0), 1);
end
end

function synopsis = compactSynopsis(labelCount, stateDimension)
positionDimension = min(2, stateDimension);
velocityDimension = stateDimension - positionDimension;
positionCovarianceScalars = ...
    positionDimension * (positionDimension + 1) / 2;
floatCount = 5 + stateDimension + ...
    positionCovarianceScalars + velocityDimension;
rawPerLabelBytes = 4 + 4 * floatCount + 2;
perLabelBytes = 4 * ceil(rawPerLabelBytes / 4);
estimatedBytes = 16 + labelCount * perLabelBytes;
synopsis = struct( ...
    'contractVersion', 'lmb-label-control-synopsis-v2-compact-cost', ...
    'labelCount', labelCount, ...
    'estimatedBytes', estimatedBytes, ...
    'scalarCount', estimatedBytes / 8);
end

function counts = accumulateSupportCounts(counts, objects, threshold)
for objectIdx = 1:numel(objects)
    if supportOf(objects(objectIdx)) >= threshold - 1e-12
        counts.positiveSupport = counts.positiveSupport + 1;
    else
        counts.ambiguous = counts.ambiguous + 1;
    end
end
end

function details = makeReceiverDetails()
details = struct( ...
    'receiverIdx', 0, ...
    'senders', [], ...
    'baselineFullBytesBySender', [], ...
    'controlSynopsisBytesBySender', [], ...
    'selectedPayloadBytesBySender', [], ...
    'baselineFullBytes', 0, ...
    'controlSynopsisBytes', 0, ...
    'selectedPayloadBytes', 0, ...
    'totalAttemptedBytes', 0, ...
    'selectedLabelCount', 0, ...
    'candidateLabelCount', 0, ...
    'byteBudget', 0, ...
    'byteBudgetSatisfied', true);
end
