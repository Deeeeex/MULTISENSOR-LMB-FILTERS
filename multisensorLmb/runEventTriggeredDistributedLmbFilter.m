end

function counts = ...
    resolveSensorTrajectoryTimeCountsForAuthorization(trajectories)
if isempty(trajectories)
    counts = zeros(1, 0);
elseif iscell(trajectories)
    counts = zeros(1, numel(trajectories));
    for sensorIdx = 1:numel(trajectories)
        value = trajectories{sensorIdx};
        if ~isnumeric(value) || ndims(value) ~= 2
            error('DynamicTopology:InvalidSensorTrajectories', ...
                'Each sensor trajectory must be a numeric matrix.');
        end
        counts(sensorIdx) = size(value, 2);
    end
elseif isnumeric(trajectories) && ndims(trajectories) <= 3
    counts = size(trajectories, 2);
else
    error('DynamicTopology:InvalidSensorTrajectories', ...
        'Sensor trajectories have an unsupported container.');
end
end

