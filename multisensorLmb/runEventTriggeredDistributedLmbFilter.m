function delta = compareLmbObjectCollections(leftObjects, rightObjects, model)
labels = collectObjectLabelsForComparison(leftObjects, rightObjects);
delta = struct( ...
    'objectCount', 0, ...
    'missingLabelCount', 0, ...
    'maxExistenceAbsDiff', 0, ...
    'maxMeanNormDiff', 0, ...
    'maxCovFroDiff', 0);
for labelIdx = 1:size(labels, 2)
    label = labels(:, labelIdx);
    leftObject = findObjectByLabelForComparison(leftObjects, label);
    rightObject = findObjectByLabelForComparison(rightObjects, label);
    if isempty(leftObject) || isempty(rightObject)
        delta.missingLabelCount = delta.missingLabelCount + 1;
        continue;
    end
    delta.objectCount = delta.objectCount + 1;
    [leftMean, leftCovariance] = momentMatchForComparison( ...
        leftObject, model.xDimension);
    [rightMean, rightCovariance] = momentMatchForComparison( ...
        rightObject, model.xDimension);
    delta.maxExistenceAbsDiff = max( ...
        delta.maxExistenceAbsDiff, abs(leftObject.r - rightObject.r));
    delta.maxMeanNormDiff = max( ...
        delta.maxMeanNormDiff, norm(leftMean - rightMean));
    delta.maxCovFroDiff = max( ...
        delta.maxCovFroDiff, norm(leftCovariance - rightCovariance, 'fro'));
end
end

function labels = collectObjectLabelsForComparison(leftObjects, rightObjects)
labels = zeros(2, 0);
labels = appendObjectLabelsForComparison(labels, leftObjects);
labels = appendObjectLabelsForComparison(labels, rightObjects);
if ~isempty(labels)
    labels = sortrows(labels')';
end
end

function labels = appendObjectLabelsForComparison(labels, objects)
for objectIdx = 1:numel(objects)
    if objects(objectIdx).numberOfGmComponents < 1
        continue;
    end
    label = [objects(objectIdx).birthTime; objects(objectIdx).birthLocation];
    if isempty(labels) || ~any(all(labels == label, 1))
        labels(:, end+1) = label; %#ok<AGROW>
    end
end
end

function object = findObjectByLabelForComparison(objects, label)
object = [];
for objectIdx = 1:numel(objects)
    if objects(objectIdx).numberOfGmComponents > 0 && ...
            objects(objectIdx).birthTime == label(1) && ...
            objects(objectIdx).birthLocation == label(2)
        object = objects(objectIdx);
        return;
    end
end
end

function [meanVector, covariance] = momentMatchForComparison( ...
    object, stateDimension)
weights = reshape(object.w, 1, []);
weights(~isfinite(weights)) = 0;
weights = max(weights, 0);
if sum(weights) <= 0
    weights = ones(1, max(1, object.numberOfGmComponents)) / ...
        max(1, object.numberOfGmComponents);
else
    weights = weights / sum(weights);
end
meanVector = zeros(stateDimension, 1);
for componentIdx = 1:object.numberOfGmComponents
    meanVector = meanVector + weights(componentIdx) * ...
        object.mu{componentIdx};
end
covariance = zeros(stateDimension);
for componentIdx = 1:object.numberOfGmComponents
    delta = object.mu{componentIdx} - meanVector;
    covariance = covariance + weights(componentIdx) * ...
        (object.Sigma{componentIdx} + delta * delta');
end
covariance = (covariance + covariance') / 2;
end

function delivered = simulateDelivery( ...
    commConfig, senderIdx, receiverIdx, currentTime, isOutage)
if isOutage
    delivered = false;
    return;
end
if commConfig.forceDelivery
    delivered = true;
    return;
end
pDrop = resolveEdgeDropProbability( ...
    commConfig, senderIdx, receiverIdx, currentTime);
if isempty(commConfig.linkUniforms)
    uniformValue = rand;
else
    uniformValue = commConfig.linkUniforms( ...
        senderIdx, receiverIdx, currentTime);
end
delivered = uniformValue >= pDrop;
end

function pDrop = resolveEdgeDropProbability( ...
    config, senderIdx, receiverIdx, currentTime)
if nargin < 4 || isempty(currentTime)
    currentTime = 1;
end
if ~isempty(config.pDropByEdge)
    if ndims(config.pDropByEdge) >= 3
        timeIdx = min(max(1, currentTime), ...
            size(config.pDropByEdge, 3));
        pDrop = config.pDropByEdge( ...
            senderIdx, receiverIdx, timeIdx);
    else
        pDrop = config.pDropByEdge(senderIdx, receiverIdx);
    end
else
    pDrop = config.pDropBySensor(senderIdx);
end
pDrop = min(max(pDrop, 0), 1);
end

function isOutage = isSensorOutage(schedule, sensorIdx, currentTime)
isOutage = false;
if isempty(schedule)
    return;
end
for idx = 1:numel(schedule)
    if schedule(idx).sensor == sensorIdx && ...
            currentTime >= schedule(idx).start && ...
            currentTime <= schedule(idx).end
        isOutage = true;
        return;
    end
end
end

