function [startTime, initialLocalPosteriors, previousHistory, ...
        previousTimes, historyWasProvided] = ...
    resolveContinuationState(config, sensorCount, simulationLength)
initialLocalPosteriors = config.filterInitialLocalPosteriorBySensor;
previousHistory = false(sensorCount, sensorCount, 0);
previousTimes = [];
startTime = 1;
legacyWasProvided = ...
    config.filterInitialPreviousAdjacencyWasProvided;
historyWasProvided = ...
    config.filterInitialPreviousAdjacencyHistoryWasProvided;
if legacyWasProvided && historyWasProvided
    error(['Specify either filterInitialPreviousAdjacency or ', ...
        'filterInitialPreviousAdjacencyHistory, not both.']);
end
if isempty(initialLocalPosteriors)
    if legacyWasProvided || ...
            (historyWasProvided && ...
            initialHistoryPageCount( ...
                config.filterInitialPreviousAdjacencyHistory, ...
                sensorCount) > 0)
        error(['Initial topology history requires a continuation ', ...
            'posterior snapshot. Fresh runs must start with empty ', ...
            'executed-topology history.']);
    end
    return;
end
if ~iscell(initialLocalPosteriors) || ...
        numel(initialLocalPosteriors) ~= sensorCount
    error(['filterInitialLocalPosteriorBySensor must contain one ', ...
        'posterior per sensor.']);
end
initialLocalPosteriors = reshape(initialLocalPosteriors, 1, []);
startTime = config.filterInitialLocalPosteriorTime;
if startTime < 1 || startTime > simulationLength
    error(['filterInitialLocalPosteriorTime must lie inside the ', ...
        'measurement sequence.']);
end
if legacyWasProvided
    policyHistory = normalizeInitialPolicyHistory( ...
        config.filterInitialPreviousAdjacency, sensorCount);
elseif historyWasProvided
    policyHistory = normalizeInitialPolicyHistory( ...
        config.filterInitialPreviousAdjacencyHistory, sensorCount);
else
    policyHistory = false(sensorCount, sensorCount, 0);
end
historyCount = size(policyHistory, 3);
if historyCount > config.topologyPolicyHistoryDepth
    error(['Initial topology history exceeds ', ...
        'topologyPolicyHistoryDepth.']);
end
if historyCount > max(0, startTime - 1)
    error(['Initial topology history contains more graph pages than ', ...
        'can precede the continuation time.']);
end
if historyCount > 0 && startTime <= 1
    error(['Initial topology history requires ', ...
        'filterInitialLocalPosteriorTime > 1.']);
end
if legacyWasProvided
    previousTimes = startTime - 1;
else
    previousTimes = config.filterInitialPreviousAdjacencyTimes;
end
if historyCount == 0
    if ~isempty(previousTimes)
        error(['filterInitialPreviousAdjacencyTimes must be empty ', ...
            'when the initial topology history is empty.']);
    end
else
    if numel(previousTimes) ~= historyCount || ...
            any(~isfinite(previousTimes)) || ...
            any(mod(previousTimes, 1) ~= 0)
        error(['filterInitialPreviousAdjacencyTimes must contain one ', ...
            'integer timestamp per history page.']);
    end
    expectedTimes = ...
        (startTime - historyCount):(startTime - 1);
    if ~isequal(previousTimes, expectedTimes)
        error(['Initial topology history timestamps must be ', ...
            'consecutive and end immediately before the ', ...
            'continuation time.']);
    end
end
if config.topologyDirectedEnabled
    previousHistory = permute(policyHistory, [2, 1, 3]);
else
    previousHistory = ...
        policyHistory | permute(policyHistory, [2, 1, 3]);
end
for historyIdx = 1:size(previousHistory, 3)
    page = previousHistory(:, :, historyIdx);
    page(1:sensorCount+1:end) = false;
    previousHistory(:, :, historyIdx) = page;
end
previousTimes = reshape(previousTimes, 1, []);
end

function [history, wasProvided] = ...
