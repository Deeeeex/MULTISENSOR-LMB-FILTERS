function [bytes, stats] = encodeLmbWireMessage(objects, metadata, model)
% ENCODELMBWIREMESSAGE Encode a full or projected LMB application message.
%
% The v1 wire format is little-endian and uses binary64 for posterior
% values. It transports only fields consumed by label-wise fusion; local
% trajectory bookkeeping is deliberately excluded.

schema = getLmbWireSchema();
stateDimension = validateModel(model, schema);
[eventType, sender, receiver, timeIndex] = ...
    validateMetadata(metadata, schema);
objects = normalizeEmptySentinel(objects, model);
if ~isstruct(objects)
    error('encodeLmbWireMessage:InvalidObjects', ...
        'objects must be an LMB struct array.');
end

objectCount = numel(objects);
if objectCount > schema.maxObjectCount
    error('encodeLmbWireMessage:ObjectCountOverflow', ...
        'Object count does not fit uint32.');
end
componentBytes = schema.floatBytes * (1 + stateDimension + ...
    stateDimension * (stateDimension + 1) / 2);
componentCounts = zeros(1, objectCount);
canonicalCovariances = cell(1, objectCount);
totalComponentCount = 0;
for objectIdx = 1:objectCount
    [componentCounts(objectIdx), canonicalCovariances{objectIdx}] = ...
        validateObject(objects(objectIdx), eventType, ...
            stateDimension, schema, objectIdx);
    totalComponentCount = totalComponentCount + ...
        componentCounts(objectIdx);
end

totalBytes = schema.headerBytes + ...
    objectCount * schema.objectHeaderBytes + ...
    totalComponentCount * componentBytes;
if totalBytes > schema.maxTotalBytes
    error('encodeLmbWireMessage:MessageTooLarge', ...
        'Encoded message length does not fit uint32.');
end

chunkCount = 7 + 5 * objectCount + 3 * totalComponentCount;
chunks = cell(1, chunkCount);
chunkIdx = 0;
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, schema.magic);
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, uint8([ ...
    double(schema.version), eventType, stateDimension, ...
    double(schema.flags)]));
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
    packLittleEndian(uint16(sender), 'uint16'));
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
    packLittleEndian(uint16(receiver), 'uint16'));
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
    packLittleEndian(uint32(timeIndex), 'uint32'));
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
    packLittleEndian(uint32(objectCount), 'uint32'));
[chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
    packLittleEndian(uint32(totalBytes), 'uint32'));

upperMask = triu(true(stateDimension));
for objectIdx = 1:objectCount
    object = objects(objectIdx);
    componentCount = componentCounts(objectIdx);
    [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
        packLittleEndian(uint32(object.birthTime), 'uint32'));
    [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
        packLittleEndian(uint32(object.birthLocation), 'uint32'));
    [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
        packLittleEndian(double(object.r), 'double'));
    [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
        packLittleEndian(uint16(componentCount), 'uint16'));
    [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
        packLittleEndian(uint16(0), 'uint16'));
    weights = reshape(double(object.w), 1, []);
    for componentIdx = 1:componentCount
        [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
            packLittleEndian(weights(componentIdx), 'double'));
        componentMean = reshape( ...
            double(object.mu{componentIdx}), stateDimension, 1);
        [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
            packLittleEndian(componentMean, 'double'));
        componentCovariance = ...
            canonicalCovariances{objectIdx}{componentIdx};
        [chunks, chunkIdx] = addChunk(chunks, chunkIdx, ...
            packLittleEndian(componentCovariance(upperMask), 'double'));
    end
end

if chunkIdx ~= chunkCount
    error('encodeLmbWireMessage:InternalChunkCount', ...
        'Internal chunk count did not match the schema calculation.');
end
bytes = reshape(uint8([chunks{:}]), 1, []);
if numel(bytes) ~= totalBytes
    error('encodeLmbWireMessage:InternalLength', ...
        'Encoded message length did not match its header.');
end
stats = struct( ...
    'encodedBytes', numel(bytes), ...
    'objectCount', objectCount, ...
    'componentCount', totalComponentCount, ...
    'eventType', double(eventType), ...
    'schemaVersion', double(schema.version));
end

function stateDimension = validateModel(model, schema)
if ~isstruct(model) || ~isfield(model, 'xDimension') || ...
        ~isfield(model, 'object') || ~isstruct(model.object) || ...
        numel(model.object) > 1
    error('encodeLmbWireMessage:InvalidModel', ...
        'model must provide scalar xDimension and object template fields.');
end
stateDimension = validateUnsignedInteger( ...
    model.xDimension, 1, schema.maxStateDimension, ...
    'encodeLmbWireMessage:InvalidStateDimension', 'state dimension');
end

function [eventType, sender, receiver, timeIndex] = ...
    validateMetadata(metadata, schema)
if ~isstruct(metadata) || numel(metadata) ~= 1
    error('encodeLmbWireMessage:InvalidMetadata', ...
        'metadata must be a scalar struct.');
end
required = {'eventType', 'sender', 'receiver', 'timeIndex'};
for fieldIdx = 1:numel(required)
    if ~isfield(metadata, required{fieldIdx})
        error('encodeLmbWireMessage:MissingMetadata', ...
            'metadata is missing field %s.', required{fieldIdx});
    end
end
eventType = validateUnsignedInteger(metadata.eventType, ...
    double(schema.lightEventType), double(schema.fullEventType), ...
    'encodeLmbWireMessage:InvalidEventType', 'event type');
sender = validateUnsignedInteger(metadata.sender, 0, ...
    schema.maxSensorIndex, 'encodeLmbWireMessage:InvalidSender', 'sender');
receiver = validateUnsignedInteger(metadata.receiver, 0, ...
    schema.maxSensorIndex, ...
    'encodeLmbWireMessage:InvalidReceiver', 'receiver');
timeIndex = validateUnsignedInteger(metadata.timeIndex, 0, ...
    schema.maxTimeIndex, ...
    'encodeLmbWireMessage:InvalidTimeIndex', 'time index');
end

function objects = normalizeEmptySentinel(objects, model)
if isempty(objects)
    objects = model.object([]);
end
end

function [componentCount, canonicalCovariances] = ...
    validateObject(object, eventType, stateDimension, schema, objectIdx)
required = {'birthTime', 'birthLocation', 'r', ...
    'numberOfGmComponents', 'w', 'mu', 'Sigma'};
for fieldIdx = 1:numel(required)
    if ~isfield(object, required{fieldIdx})
        error('encodeLmbWireMessage:MissingObjectField', ...
            'Object %d is missing field %s.', objectIdx, required{fieldIdx});
    end
end
validateUnsignedInteger(object.birthTime, 0, schema.maxTimeIndex, ...
    'encodeLmbWireMessage:InvalidBirthTime', 'birth time');
validateUnsignedInteger(object.birthLocation, 0, schema.maxTimeIndex, ...
    'encodeLmbWireMessage:InvalidBirthLocation', 'birth location');
if ~isRealFiniteScalar(object.r) || object.r < 0 || object.r > 1
    error('encodeLmbWireMessage:InvalidExistence', ...
        'Object %d existence must be finite and in [0,1].', objectIdx);
end
componentCount = validateUnsignedInteger( ...
    object.numberOfGmComponents, 1, schema.maxComponentCount, ...
    'encodeLmbWireMessage:InvalidComponentCount', 'component count');
if eventType == double(schema.lightEventType) && componentCount ~= 1
    error('encodeLmbWireMessage:LightComponentCount', ...
        'Light messages require exactly one component per object.');
end
if ~isnumeric(object.w) || ~isreal(object.w) || ...
        numel(object.w) ~= componentCount || ...
        any(~isfinite(object.w(:))) || any(object.w(:) < 0) || ...
        sum(double(object.w(:))) <= 0
    error('encodeLmbWireMessage:InvalidWeights', ...
        'Object %d requires finite nonnegative weights with positive sum.', ...
        objectIdx);
end
if ~iscell(object.mu) || ~iscell(object.Sigma) || ...
        numel(object.mu) ~= componentCount || ...
        numel(object.Sigma) ~= componentCount
    error('encodeLmbWireMessage:InconsistentComponents', ...
        'Object %d component fields do not match its count.', objectIdx);
end
canonicalCovariances = cell(1, componentCount);
for componentIdx = 1:componentCount
    componentMean = object.mu{componentIdx};
    componentCovariance = object.Sigma{componentIdx};
    if ~isnumeric(componentMean) || ~isreal(componentMean) || ...
            numel(componentMean) ~= stateDimension || ...
            any(~isfinite(componentMean(:)))
        error('encodeLmbWireMessage:InvalidMean', ...
            'Object %d component %d mean must be a finite d-vector.', ...
            objectIdx, componentIdx);
    end
    if ~isnumeric(componentCovariance) || ...
            ~isreal(componentCovariance) || ...
            ~isequal(size(componentCovariance), ...
                [stateDimension, stateDimension]) || ...
            any(~isfinite(componentCovariance(:)))
        error('encodeLmbWireMessage:InvalidCovariance', ...
            'Object %d component %d covariance must be finite d-by-d.', ...
            objectIdx, componentIdx);
    end
    componentCovariance = double(componentCovariance);
    symmetryScale = max(1, norm(componentCovariance, 'fro'));
    if norm(componentCovariance - componentCovariance', 'fro') > ...
            schema.covarianceSymmetryTolerance * symmetryScale
        error('encodeLmbWireMessage:AsymmetricCovariance', ...
            'Object %d component %d covariance is not symmetric.', ...
            objectIdx, componentIdx);
    end
    canonicalCovariances{componentIdx} = ...
        (componentCovariance + componentCovariance') / 2;
end
end

function value = validateUnsignedInteger( ...
    value, minimumValue, maximumValue, errorId, fieldDescription)
if ~(isnumeric(value) || islogical(value)) || ~isreal(value) || ...
        ~isscalar(value) || ~isfinite(value) || value ~= floor(value) || ...
        value < minimumValue || value > maximumValue
    error(errorId, '%s must be an integer in [%g,%g].', ...
        fieldDescription, minimumValue, maximumValue);
end
value = double(value);
end

function value = isRealFiniteScalar(candidate)
value = (isnumeric(candidate) || islogical(candidate)) && ...
    isreal(candidate) && isscalar(candidate) && isfinite(candidate);
end

function [chunks, chunkIdx] = addChunk(chunks, chunkIdx, chunk)
chunkIdx = chunkIdx + 1;
chunks{chunkIdx} = reshape(uint8(chunk), 1, []);
end

function bytes = packLittleEndian(value, className)
value = cast(value, className);
if ~hostIsLittleEndian()
    value = swapbytes(value);
end
bytes = reshape(typecast(value(:), 'uint8'), 1, []);
end

function value = hostIsLittleEndian()
persistent cachedValue;
if isempty(cachedValue)
    probe = typecast(uint16(1), 'uint8');
    cachedValue = probe(1) == 1;
end
value = cachedValue;
end
