function [route, packetCache, details] = ...
        prepareSourcePreservingLabelPacketRouteV268( ...
            localPosteriorBySensor, physicalAdjacency, ...
            directedLinkDelivered, currentDirectedEdgeMask, schedule, ...
            model, currentTime, packetCache, config)
% PREPARESOURCEPRESERVINGLABELPACKETROUTEV268 Route without relay fusion.
%
% A newly scheduled complete Bernoulli-GM label is transported from its
% source to one relay and cached there without changing the relay LMB.  A
% packet cached on the previous page is predicted to the current time,
% transported from the relay to the target formation, and exposed as one
% source-preserving input to the final receiver's ordinary label-wise KLA.

sensorCount = numel(localPosteriorBySensor);
validateInputs(localPosteriorBySensor, physicalAdjacency, ...
    directedLinkDelivered, currentDirectedEdgeMask, model, currentTime, ...
    packetCache, config);
route = emptyRoute();
details = emptyDetails(sensorCount);
details.currentTime = currentTime;

% Complete at most one previously admitted packet before admitting the
% current page's first hop.  Packets are single-shot: a failed/blocked
% second hop is not retried, so latency and communication are explicit.
if isActivePacket(packetCache)
    [route, secondHop, packetCache] = completeSecondHop( ...
        packetCache, localPosteriorBySensor, physicalAdjacency, ...
        directedLinkDelivered, currentDirectedEdgeMask, model, ...
        currentTime, config);
    details = mergeSecondHop(details, secondHop);
end

if isstruct(schedule) && isscalar(schedule) && ...
        logical(getField(schedule, 'labelShortcutActive', false))
    [packetCache, firstHop] = admitFirstHop( ...
        packetCache, localPosteriorBySensor, physicalAdjacency, ...
        directedLinkDelivered, schedule, model, currentTime, config);
    details = mergeFirstHop(details, firstHop);
end

details.scheduled = details.firstHopScheduled || ...
    details.secondHopScheduled;
details.transportDelivered = details.secondHopDelivered;
details.attemptedPayloadScalars = sum( ...
    details.attemptedPayloadScalarsByEdge(:));
details.attemptedPayloadBytes = sum( ...
    details.attemptedPayloadBytesByEdge(:));
details.deliveredPayloadScalars = sum( ...
    details.deliveredPayloadScalarsByEdge(:));
details.deliveredPayloadBytes = sum( ...
    details.deliveredPayloadBytesByEdge(:));
details.packetCacheActiveAfterPage = isActivePacket(packetCache);
end

function [route, hop, packetCache] = completeSecondHop( ...
        packetCache, localPosteriorBySensor, physicalAdjacency, ...
        directedLinkDelivered, currentDirectedEdgeMask, model, ...
        currentTime, config)
sensorCount = numel(localPosteriorBySensor);
route = emptyRoute();
hop = emptySecondHop(sensorCount);
hop.scheduled = true;
hop.originalSourceId = packetCache.originalSourceId;
hop.senderId = packetCache.relaySensorId;
hop.sourceTime = packetCache.sourceTime;
hop.age = currentTime - packetCache.sourceTime;
hop.label = packetCache.label;
hop.targetFormationId = packetCache.targetFormationId;
hop.sourceWeight = packetCache.sourceWeight;
hop.sourceWeightGrid = packetCache.sourceWeightGrid;
hop.weightMode = packetCache.weightMode;

% Consume the packet irrespective of second-hop outcome.  V268 deliberately
% screens a bounded one-page delay rather than an implicit retry protocol.
packet = packetCache;
packetCache = emptyPacket();
if hop.age < 1 || hop.age > config. ...
        topologyPolicySourcePreservingLabelPacketMaximumAge
    hop.expired = true;
    hop.rejectionReason = 'packet-age-outside-registered-window';
    return;
end

groupIds = reshape(model.dynamicTopologyScenario.config.sensorGroupIds, ...
    1, []);
targetMembers = find(groupIds == packet.targetFormationId);
relayId = packet.relaySensorId;
physicalCandidates = targetMembers(logical( ...
    physicalAdjacency(targetMembers, relayId)));
if isempty(physicalCandidates)
    hop.rejectionReason = 'no-current-physical-second-hop';
    return;
end
beneficiaryMode = getField(config, ...
    'topologyPolicySourcePreservingLabelPacketBeneficiaryMode', ...
    'backbone-first');
[receiverId, receiverExistence, backboneAligned] = selectBeneficiary( ...
    beneficiaryMode, physicalCandidates, relayId, packet.label, ...
    localPosteriorBySensor, currentDirectedEdgeMask);
hop.beneficiaryMode = beneficiaryMode;
hop.receiverExistence = receiverExistence;
hop.backboneAligned = backboneAligned;
hop.receiverId = receiverId;
hop.physicalPassed = true;

predictedObject = predictPacketObject(packet.sourceObject, model, hop.age);
hop.payloadPresent = ~isempty(predictedObject);
if ~hop.payloadPresent
    hop.rejectionReason = 'predicted-packet-payload-empty';
    return;
end
payloadStats = packetPayloadStats(predictedObject, model, config);
hop.attemptedPayloadScalarsByEdge(relayId, receiverId) = ...
    payloadStats.scalarCount;
hop.attemptedPayloadBytesByEdge(relayId, receiverId) = ...
    payloadStats.estimatedBytes;
hop.delivered = logical(directedLinkDelivered(relayId, receiverId));
if ~hop.delivered
    hop.rejectionReason = 'second-hop-transport-drop';
    return;
end
hop.deliveredPayloadScalarsByEdge(relayId, receiverId) = ...
    payloadStats.scalarCount;
hop.deliveredPayloadBytesByEdge(relayId, receiverId) = ...
    payloadStats.estimatedBytes;

route.active = true;
route.currentTime = currentTime;
route.targetFormationId = packet.targetFormationId;
route.receiverIds = receiverId;
route.sourceId = packet.originalSourceId;
route.transportSenderId = relayId;
route.sourceTimestamp = packet.sourceTime;
route.packetAge = hop.age;
route.label = packet.label;
route.sourceObject = predictedObject;
route.sourceWeight = packet.sourceWeight;
route.sourceWeightGrid = packet.sourceWeightGrid;
route.weightMode = packet.weightMode;
route.forceAppendPreservedSource = true;
route.etaProjectionEnabled = logical(config. ...
    topologyPolicyLabelInputRouteEtaProjectionEnabled);
route.minimumMapExistence = config. ...
    topologyPolicyLabelInputRouteMinimumMapExistence;
route.maximumReferenceLogOddsDrop = config. ...
    topologyPolicyLabelInputRouteMaximumReferenceLogOddsDrop;
route.maximumSubMapReferenceLogOddsDrop = config. ...
    topologyPolicyLabelInputRouteMaximumSubMapReferenceLogOddsDrop;
route.maximumReferenceLogOddsIncrease = config. ...
    topologyPolicyLabelInputRouteMaximumReferenceLogOddsIncrease;
route.transferFractionGrid = 1;
route.etaIdentityTolerance = config. ...
    topologyPolicyLabelInputRouteEtaIdentityTolerance;
hop.routeActive = true;
end

function [packetCache, hop] = admitFirstHop( ...
        packetCache, localPosteriorBySensor, physicalAdjacency, ...
        directedLinkDelivered, schedule, model, currentTime, config)
sensorCount = numel(localPosteriorBySensor);
hop = emptyFirstHop(sensorCount);
validateSchedule(schedule, sensorCount);
hop.scheduled = true;
hop.sourceId = schedule.labelShortcutSourceSensorId;
hop.receiverId = schedule.labelShortcutReceiverSensorId;
hop.label = reshape(schedule.selectedLocalizationLabel, 2, 1);
hop.targetFormationId = schedule.selectedLocalizationFormationId;
hop.sourceWeight = schedule.labelShortcutSourceWeight;
hop.sourceWeightGrid = reshape(getField(schedule, ...
    'labelShortcutSourceWeightGrid', hop.sourceWeight), 1, []);
hop.weightMode = lower(strrep(getField(schedule, ...
    'labelShortcutWeightMode', 'bounded-proportional-share'), '_', '-'));
hop.physicalPassed = logical( ...
    physicalAdjacency(hop.receiverId, hop.sourceId));
sourceObject = findLabelObject( ...
    localPosteriorBySensor{hop.sourceId}, hop.label);
hop.payloadPresent = ~isempty(sourceObject);
if hop.payloadPresent
    payloadStats = packetPayloadStats(sourceObject, model, config);
else
    payloadStats = struct('scalarCount', 0, 'estimatedBytes', 0);
end
if hop.payloadPresent && hop.physicalPassed
    hop.attemptedPayloadScalarsByEdge( ...
        hop.sourceId, hop.receiverId) = payloadStats.scalarCount;
    hop.attemptedPayloadBytesByEdge( ...
        hop.sourceId, hop.receiverId) = payloadStats.estimatedBytes;
end
hop.delivered = hop.payloadPresent && hop.physicalPassed && ...
    logical(directedLinkDelivered(hop.sourceId, hop.receiverId));
if ~hop.delivered
    if ~hop.payloadPresent
        hop.rejectionReason = 'first-hop-payload-missing';
    elseif ~hop.physicalPassed
        hop.rejectionReason = 'first-hop-not-physical';
    else
        hop.rejectionReason = 'first-hop-transport-drop';
    end
    return;
end
hop.deliveredPayloadScalarsByEdge( ...
    hop.sourceId, hop.receiverId) = payloadStats.scalarCount;
hop.deliveredPayloadBytesByEdge( ...
    hop.sourceId, hop.receiverId) = payloadStats.estimatedBytes;

% A second-hop completion is processed before this admission, so a cache
% collision would signal an unregistered latency/retry behavior.
if isActivePacket(packetCache)
    error('SourcePreservingLabelPacketV268:PacketCacheCollision', ...
        'The single-slot source-preserving packet cache is occupied.');
end
packetCache = struct( ...
    'contractVersion', 'source-preserving-label-packet-v268-v1', ...
    'active', true, ...
    'sourceTime', currentTime, ...
    'originalSourceId', hop.sourceId, ...
    'relaySensorId', hop.receiverId, ...
    'targetFormationId', hop.targetFormationId, ...
    'label', hop.label, ...
    'sourceObject', sourceObject, ...
    'sourceWeight', hop.sourceWeight, ...
    'sourceWeightGrid', hop.sourceWeightGrid, ...
    'weightMode', hop.weightMode, ...
    'truthUsed', false, ...
    'futureInformationUsed', false);
hop.packetStored = true;
end

