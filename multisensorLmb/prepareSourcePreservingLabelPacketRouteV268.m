function stats = packetPayloadStats(object, model, config)
stats = estimateLmbPayloadSize(object, model, 2, struct());
metadataScalars = config. ...
    topologyPolicySourcePreservingLabelPacketMetadataScalars;
stats.scalarCount = stats.scalarCount + metadataScalars;
stats.estimatedBytes = stats.estimatedBytes + 8 * metadataScalars;
end

function [receiverId, existence, backboneAligned] = selectBeneficiary( ...
        mode, candidates, relayId, label, localPosteriorBySensor, ...
        currentDirectedEdgeMask)
backboneMask = logical(currentDirectedEdgeMask(relayId, candidates));
if strcmp(mode, 'backbone-first')
    preferred = candidates(backboneMask);
    if isempty(preferred)
        preferred = candidates;
    end
    receiverId = min(preferred);
else
    existences = -inf(1, numel(candidates));
    for candidateIdx = 1:numel(candidates)
        object = findLabelObject( ...
            localPosteriorBySensor{candidates(candidateIdx)}, label);
        if ~isempty(object) && isfinite(object.r)
            existences(candidateIdx) = object.r;
        end
    end
    rows = [-reshape(existences, [], 1), ...
        -reshape(double(backboneMask), [], 1), ...
        reshape(candidates, [], 1)];
    [~, order] = sortrows(rows, [1, 2, 3]);
    receiverId = candidates(order(1));
end
object = findLabelObject(localPosteriorBySensor{receiverId}, label);
if isempty(object)
    existence = NaN;
else
    existence = object.r;
end
backboneAligned = logical(currentDirectedEdgeMask(relayId, receiverId));
end

function object = predictPacketObject(object, model, age)
for stepIdx = 1:age
    object.r = model.survivalProbability * object.r;
    for componentIdx = 1:object.numberOfGmComponents
        object.mu{componentIdx} = ...
            model.A * object.mu{componentIdx} + model.u;
        object.Sigma{componentIdx} = ...
            model.A * object.Sigma{componentIdx} * model.A' + model.R;
    end
end
if object.numberOfGmComponents < 1 || ...
        object.r <= getField(model, 'existenceThreshold', 0)
    object = [];
end
end

function object = findLabelObject(objects, label)
object = [];
objects = reshape(objects, 1, []);
for objectIdx = 1:numel(objects)
    candidate = objects(objectIdx);
    if candidate.numberOfGmComponents > 0 && ...
            candidate.birthTime == label(1) && ...
            candidate.birthLocation == label(2)
        object = candidate;
        return;
    end
end
end

function validateInputs(localPosteriorBySensor, physicalAdjacency, ...
        directedLinkDelivered, currentDirectedEdgeMask, model, ...
        currentTime, packetCache, config)
sensorCount = numel(localPosteriorBySensor);
valid = iscell(localPosteriorBySensor) && sensorCount >= 1 && ...
    isequal(size(physicalAdjacency), [sensorCount, sensorCount]) && ...
    isequal(size(directedLinkDelivered), [sensorCount, sensorCount]) && ...
    isequal(size(currentDirectedEdgeMask), [sensorCount, sensorCount]) && ...
    isstruct(model) && isscalar(model) && ...
    isfield(model, 'dynamicTopologyScenario') && ...
    isfield(model.dynamicTopologyScenario, 'config') && ...
    isfield(model.dynamicTopologyScenario.config, 'sensorGroupIds') && ...
    numel(model.dynamicTopologyScenario.config.sensorGroupIds) == ...
        sensorCount && ...
    isscalar(currentTime) && isfinite(currentTime) && ...
    currentTime == round(currentTime) && currentTime >= 1 && ...
    (isempty(packetCache) || (isstruct(packetCache) && ...
        isscalar(packetCache))) && ...
    isstruct(config) && isscalar(config) && ...
    isfield(config, ...
        'topologyPolicySourcePreservingLabelPacketMaximumAge') && ...
    isfield(config, ...
        'topologyPolicySourcePreservingLabelPacketMetadataScalars');
if ~valid
    error('SourcePreservingLabelPacketV268:InvalidInputs', ...
        'The source-preserving label packet inputs are malformed.');
end
end

function validateSchedule(schedule, sensorCount)
required = {'contractVersion', 'selectedLocalizationLabel', ...
    'selectedLocalizationFormationId', ...
    'labelShortcutSourceSensorId', 'labelShortcutReceiverSensorId', ...
    'labelShortcutSourceWeight'};
sourceId = getField(schedule, 'labelShortcutSourceSensorId', 0);
receiverId = getField(schedule, 'labelShortcutReceiverSensorId', 0);
label = reshape(getField(schedule, ...
    'selectedLocalizationLabel', zeros(2, 0)), [], 1);
weight = getField(schedule, 'labelShortcutSourceWeight', 0);
grid = reshape(getField(schedule, ...
    'labelShortcutSourceWeightGrid', weight), 1, []);
valid = all(isfield(schedule, required)) && ...
    ismember(schedule.contractVersion, { ...
        'source-preserving-label-packet-v268-schedule-v1', ...
        'existence-margin-beneficiary-v269-schedule-v1'}) && ...
    validSensorId(sourceId, sensorCount) && ...
    validSensorId(receiverId, sensorCount) && sourceId ~= receiverId && ...
    numel(label) == 2 && all(isfinite(label)) && ...
    all(label == round(label)) && all(label >= 1) && ...
    isscalar(weight) && isfinite(weight) && weight > 0 && weight < 1 && ...
    ~isempty(grid) && all(isfinite(grid)) && ...
    all(grid > 0) && all(grid < 1) && max(grid) <= weight + 1e-12;
if ~valid
    error('SourcePreservingLabelPacketV268:InvalidSchedule', ...
        'The V268 source-preserving label packet schedule is malformed.');
end
end

