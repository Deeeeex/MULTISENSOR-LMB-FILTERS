details.firstHopTargetFormationId = hop.targetFormationId;
details.firstHopPhysicalPassed = hop.physicalPassed;
details.firstHopPayloadPresent = hop.payloadPresent;
details.firstHopDelivered = hop.delivered;
details.firstHopPacketStored = hop.packetStored;
details.firstHopRejectionReason = hop.rejectionReason;
details.attemptedPayloadScalarsByEdge = ...
    details.attemptedPayloadScalarsByEdge + ...
    hop.attemptedPayloadScalarsByEdge;
details.attemptedPayloadBytesByEdge = ...
    details.attemptedPayloadBytesByEdge + ...
    hop.attemptedPayloadBytesByEdge;
details.deliveredPayloadScalarsByEdge = ...
    details.deliveredPayloadScalarsByEdge + ...
    hop.deliveredPayloadScalarsByEdge;
details.deliveredPayloadBytesByEdge = ...
    details.deliveredPayloadBytesByEdge + ...
    hop.deliveredPayloadBytesByEdge;
if ~details.secondHopScheduled
    details.sourceId = hop.sourceId;
    details.receiverId = hop.receiverId;
    details.label = hop.label;
    details.sourceWeight = hop.sourceWeight;
    details.sourceWeightGrid = hop.sourceWeightGrid;
    details.weightMode = hop.weightMode;
end
end

