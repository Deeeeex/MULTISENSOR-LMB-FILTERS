#!/usr/bin/env python3
"""Generate contextual GA reference rows for the TAES manuscript.

The main paired tests are generated from the AA validation report. This script
adds a separate context table from a tracked GA validation report that used the
same trial seeds and tiered packet-loss profile. These rows are reference
baselines only, not inputs to the paired AA sign tests.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from evidence_sources import REPO, ROOT, evidence_path

OUT = ROOT / "generated"

AA_REPORT = evidence_path("n50_aa_report")
GA_REPORT = evidence_path("reference_ga_report")

NETWORK_METRICS = ["OSPA", "Loc. disag.", "Card. disp."]
GA_NETWORK_METRICS = ["OSPA", "RMSE", "Cardinality"]
LOCAL_METRICS = ["E-OSPA", "RMSE", "CardErr"]

ROWS = [
    ("GA +structure-aware KLA", GA_REPORT, "+structure-aware decoupled KLA", GA_NETWORK_METRICS),
    ("GA +FID-FIA refinement", GA_REPORT, "+FID-FIA existence refinement", GA_NETWORK_METRICS),
    ("Neighborhood label-barycenter", AA_REPORT, "Neighborhood label-barycenter spatial-KLA AA", NETWORK_METRICS),
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_text(path: Path) -> str:
    if not path.exists():
        raise FileNotFoundError(f"Missing report: {path}")
    return path.read_text(encoding="utf-8")


def markdown_table_after(text: str, heading: str) -> list[list[str]]:
    idx = text.find(heading)
    if idx < 0:
        raise ValueError(f"Missing heading: {heading}")
    lines = text[idx:].splitlines()
    table_lines: list[str] = []
    in_table = False
    for line in lines[1:]:
        if line.startswith("|"):
            table_lines.append(line)
            in_table = True
        elif in_table:
            break
    if len(table_lines) < 3:
        raise ValueError(f"No Markdown table after heading: {heading}")
    rows: list[list[str]] = []
    for line in table_lines:
        parts = [part.strip() for part in line.strip().strip("|").split("|")]
        if all(set(part) <= {":", "-"} for part in parts):
            continue
        rows.append(parts)
    return rows


def parse_metric_table(text: str, heading: str, expected_metrics: list[str]) -> dict[str, dict[str, float]]:
    rows = markdown_table_after(text, heading)
    expected = ["Arm", *expected_metrics]
    if rows[0] != expected:
        raise ValueError(f"Unexpected header under {heading}: {rows[0]}")
    return {
        row[0]: {metric: float(value) for metric, value in zip(expected_metrics, row[1:])}
        for row in rows[1:]
    }


def load_row(report: Path, arm: str, network_metrics: list[str]) -> dict[str, float]:
    text = read_text(report)
    network_heading = "## Network Disagreement Metrics"
    local_heading = "## Local Tracking Metrics"
    network = parse_metric_table(text, network_heading, network_metrics)
    local = parse_metric_table(text, local_heading, LOCAL_METRICS)
    if arm not in network:
        raise ValueError(f"Missing network arm {arm} in {report}")
    if arm not in local:
        raise ValueError(f"Missing local arm {arm} in {report}")
    return {
        "net_ospa": network[arm][network_metrics[0]],
        "loc_disag": network[arm][network_metrics[1]],
        "card_disp": network[arm][network_metrics[2]],
        "e_ospa": local[arm]["E-OSPA"],
        "rmse": local[arm]["RMSE"],
        "card_err": local[arm]["CardErr"],
    }


def tex_num(value: float) -> str:
    return f"{value:.3f}"


def write_rows(values: dict[str, dict[str, float]]) -> None:
    lines = [
        "% Auto-generated by scripts/extract_reference_baselines.py.\n",
        "% Do not edit by hand; rerun ./build.sh from the manuscript directory.\n",
    ]
    for label, _, _, _ in ROWS:
        row = values[label]
        cells = [
            tex_num(row["net_ospa"]),
            tex_num(row["loc_disag"]),
            tex_num(row["card_disp"]),
            tex_num(row["e_ospa"]),
            tex_num(row["rmse"]),
            tex_num(row["card_err"]),
        ]
        if label == "Neighborhood label-barycenter":
            cells = [f"\\textbf{{{cell}}}" for cell in cells]
        lines.append(f"{label} & {' & '.join(cells)}\\\\\n")
    lines.append("\\bottomrule\n")
    (OUT / "reference_baseline_rows.tex").write_text("".join(lines), encoding="utf-8")


def write_manifest(values: dict[str, dict[str, float]]) -> None:
    payload = {
        "aa_report": str(AA_REPORT.relative_to(REPO)),
        "aa_sha256": sha256(AA_REPORT),
        "ga_report": str(GA_REPORT.relative_to(REPO)),
        "ga_sha256": sha256(GA_REPORT),
        "note": (
            "GA rows are contextual reference baselines from the tracked GA validation "
            "path. They use the same base seed, trial seeds, and tiered packet-loss "
            "profile, but they are not part of the paired AA sign tests."
        ),
        "rows": values,
    }
    (OUT / "reference_baseline_evidence.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    lines = [
        "# Reference Baseline Evidence Manifest\n\n",
        "Generated by `docs/paper/taes/manuscript/scripts/extract_reference_baselines.py`.\n\n",
        f"- AA source report: `{AA_REPORT.relative_to(REPO)}`\n",
        f"- AA SHA256: `{sha256(AA_REPORT)}`\n",
        f"- GA source report: `{GA_REPORT.relative_to(REPO)}`\n",
        f"- GA SHA256: `{sha256(GA_REPORT)}`\n",
        "- Trial profile: base seed 1, trial seeds 2--51, tiered packet loss `[0, 0.1, 0.2, 0.5]` with counts `[1, 4, 1, 2]`.\n",
        "- Interpretation: GA rows are contextual reference baselines and are not used for the paired AA sign tests.\n\n",
        "## Key Check\n\n",
        "- The neighborhood label-barycenter row is lower than both GA reference rows on all six reported disagreement/tracking metrics in this scenario.\n",
    ]
    (OUT / "REFERENCE_BASELINE_MANIFEST.md").write_text("".join(lines), encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    values = {label: load_row(report, arm, metrics) for label, report, arm, metrics in ROWS}
    write_rows(values)
    write_manifest(values)


if __name__ == "__main__":
    main()
