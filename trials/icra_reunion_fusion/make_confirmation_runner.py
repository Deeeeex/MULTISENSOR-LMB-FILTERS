"""Derive a cache-only confirmation ablation without mutating v1/v2."""
from pathlib import Path
import hashlib
import json

out = Path(__file__).resolve().parent
root = out.parents[1]
original = (out/'runRobotReunionPilot.m').read_text()
helpers = original[original.index('function run=runArm('):]

def replace(old, new):
    global helpers
    assert helpers.count(old) == 1, old
    helpers = helpers.replace(old, new)

replace('directTimes=zeros(N,K);', 'directTimes=zeros(N,K); localHits=zeros(N,K);')
replace("'observableAbsences',zeros(N,T),'runtimeSeconds'", "'observableAbsences',zeros(N,T), ...\n    'localAssociationMass',zeros(N,K,T),'confirmation',false(N,K,T), ...\n    'runtimeSeconds'")
replace('        local{n}=pruneValidate(local{n},model);', '''        previousHits=localHits(n,:); localHits(n,:)=0;
        for j=1:numel(local{n})
            region=local{n}(j).birthLocation; mass=0;
            if ~isempty(measurements{n,t}) && directTimes(n,region)==t
                mass=local{n}(j).detectionAssociationMass;
            end
            if mass>=.5, localHits(n,region)=min(2,previousHits(region)+1); end
            local{n}(j).positiveConfirmation=local{n}(j).positiveConfirmation || localHits(n,region)>=2;
            run.localAssociationMass(n,region,t)=mass;
        end
        local{n}=pruneValidate(local{n},model);''')
replace('fuseRobotReunionInputs(', 'fuseConfirmedReunionInputs(')
replace('            run.labelExistence(n,j,t)=posterior{n}(k).r;', '''            run.labelExistence(n,j,t)=posterior{n}(k).r;
            run.confirmation(n,j,t)=posterior{n}(k).positiveConfirmation;''')
replace('double(o.hasObservationLineage),o.lastDirectOpportunity];', 'double(o.hasObservationLineage),o.lastDirectOpportunity,double(o.positiveConfirmation)];')
replace('o.lastDirectOpportunity=v(cursor+5); cursor=cursor+6;', 'o.lastDirectOpportunity=v(cursor+5); o.positiveConfirmation=logical(v(cursor+6)); cursor=cursor+7;')
replace('    assert(a(k).lastDirectOpportunity==b(k).lastDirectOpportunity);', '''    assert(a(k).lastDirectOpportunity==b(k).lastDirectOpportunity);
    assert(a(k).positiveConfirmation==b(k).positiveConfirmation);''')

entry = '''function runRobotReunionConfirmation()
% Generated by make_confirmation_runner.py. All stochastic inputs are reused.
out=fileparts(mfilename('fullpath')); root=fileparts(fileparts(out));
addpath(fullfile(root,'common'),fullfile(root,'lmb'),fullfile(root,'multisensorLmb'));
names={'split_latebirth','churn_departure','split_no_new'};
arms={'qualified_exist','confirmed_lineage','confirmed_exist'};
for sc=1:numel(names)
    for seed=[2801,2802,2803]
        sourceMat=fullfile(out,'results',sprintf('%s_seed%d_full.mat',names{sc},seed));
        cached=load(sourceMat); cells=cell(1,numel(arms));
        [cached.model.birthParameters.positiveConfirmation]=deal(false);
        cached.model.object=cached.model.birthParameters([]);
        for a=1:numel(arms)
            fprintf('START confirmation %s seed %d arm %s\\n',names{sc},seed,arms{a});
            cells{a}=runArm(cached.model,cached.truth,cached.measurements,cached.uniforms, ...
                cached.scene,cached.adjacency,arms{a},cached.scene.T);
            r=cells{a};
            assert(r.totalWireBytes==cached.result.runs(2).totalWireBytes);
            assert(isequal(r.deliveredMessages,cached.result.runs(2).deliveredMessages));
            if a==1
                old=load(strrep(sourceMat,'_full.mat','_extension.mat'));
                assert(isequal(r.estimates,old.result.runs(2).estimates));
                assert(isequal(r.ospa,old.result.runs(2).ospa));
            end
            fprintf('DONE OSPA %.6f count %.6f runtime %.2fs\\n', ...
                mean(r.ospa,'all'),mean(r.countError,'all'),r.runtimeSeconds);
        end
        result=cached.result; result.runs=[cells{:}]; result.mode='confirmation';
        result.protocol='robot-reunion-fusion-v3';
        prefix=fullfile(out,'results',sprintf('%s_seed%d_confirmation',names{sc},seed));
        writeJson([prefix,'.json'],result); gzip([prefix,'.json']);
        save([prefix,'.mat'],'result','sourceMat','-v7');
    end
end
fprintf('COMPLETED confirmation\\n');
end

'''
(out/'runRobotReunionConfirmation.m').write_text(entry+helpers)
files=[out/'CONFIRMATION_PROTOCOL.md',out/'fuseConfirmedReunionInputs.m',
       out/'runRobotReunionConfirmation.m',out/'make_confirmation_runner.py']
files += list((out/'results').glob('*_full.mat'))
manifest={str(f.relative_to(root)): hashlib.sha256(f.read_bytes()).hexdigest() for f in files}
(out/'confirmation_source_sha256.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Generated confirmation runner and froze',len(manifest),'source/input hashes.')
