function context = buildCausalGatewayEmbeddingV250ExecutionContext( ...
        presetName, seed, measurementTimeCount, anchorTime, ...
        candidateIndex)
% BUILDCAUSALGATEWAYEMBEDDINGV250EXECUTIONCONTEXT H=3 development run.

protocol = getCausalGatewayEmbeddingV250Protocol();
if ~ischar(presetName) || ...
        ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds) || ...
        ~isscalar(measurementTimeCount) || ...
        ~isfinite(measurementTimeCount) || ...
        measurementTimeCount < 1 || ...
        measurementTimeCount ~= round(measurementTimeCount) || ...
        ~ismember(anchorTime, protocol.anchorTimes) || ...
        measurementTimeCount ~= ...
            anchorTime + protocol.horizonSteps - 1 || ...
        ~isscalar(candidateIndex) || candidateIndex < 2 || ...
        candidateIndex > protocol.maximumCandidateCount || ...
        candidateIndex ~= round(candidateIndex)
    error('CausalGatewayEmbeddingV250:InvalidExecutionContextInput', ...
        'V250 requires a registered H=3 candidate continuation.');
end
context = struct();
context.contractVersion = ...
    'causal-gateway-embedding-v250-context-v1';
context.capability = ...
    'causal-gateway-embedding-v250-h3-development';
context.action = ...
    'filter-causal-gateway-embedding-v250-h3-development';
context.protocolId = protocol.id;
context.presetName = presetName;
context.seed = seed;
context.armId = protocol.armId;
context.measurementTimeCount = measurementTimeCount;
context.anchorTime = anchorTime;
context.candidateIndex = candidateIndex;
context.policyName = protocol.policyName;
context.developmentEvidenceOnly = true;
end
