function runtimeModel = ...
    sanitizeFormationB4V46RuntimeFilterModel( ...
        sourceModel, caseContract, registry)
% SANITIZEFORMATIONB4V46RUNTIMEFILTERMODEL Build the filter-visible model.
%
% The deterministic scenario generator necessarily materializes target
% truth before measurements are produced.  The tracking filter must not
% receive that truth-bearing generator object.  This function therefore
% constructs an exact-schema runtime model containing only the LMB model,
% one canonical registered birth prior, sensing model, and minimal identity
% metadata used by the V46 route.  Target trajectories, target metadata,
% full scenario geometry, and duplicate sensor-trajectory copies are not
% carried across the boundary.

official = getFormationB4V46TrackingSourceRegistry();
validateAuthority(caseContract, registry, official);
validateSourceModel(sourceModel, caseContract);

sourceScenario = sourceModel.dynamicTopologyScenario;
sourceConfig = sourceScenario.config;
identity = buildDynamicTopologyPhysicalIdentityRegistry(sourceConfig);
validateEmbeddedIdentity(sourceConfig, identity, caseContract);

modelFields = directRuntimeModelFieldNames();
runtimeModel = struct();
for fieldIdx = 1:numel(modelFields)
    fieldName = modelFields{fieldIdx};
    if ~isfield(sourceModel, fieldName)
        error('FormationB4V46RuntimeModel:MissingFilterField', ...
            'The source model is missing runtime field %s.', fieldName);
    end
    runtimeModel.(fieldName) = sourceModel.(fieldName);
end
runtimeModel.object = buildEmptyRuntimeObject(sourceModel.object);
runtimeModel.birthParameters = buildRuntimeBirthParameters( ...
    sourceModel.birthParameters, sourceModel.xDimension, ...
    caseContract.simulationLength, sourceModel.numberOfBirthLocations);
runtimeModel.sensorQuality = ...
    buildRuntimeSensorQuality(sourceModel.sensorQuality);
validateNumericCellModels(runtimeModel, caseContract.simulationLength);

runtimeConfig = buildRuntimeConfig(sourceConfig);
runtimeScenario = struct();
runtimeScenario.presetName = sourceScenario.presetName;
runtimeScenario.seed = sourceScenario.seed;
runtimeScenario.config = runtimeConfig;
runtimeModel.dynamicTopologyScenario = runtimeScenario;

envelope = struct();
envelope.contractVersion = ...
    'formation-b4-v46-runtime-filter-model-envelope-v1';
envelope.registryId = registry.id;
envelope.registryCanonicalSha256 = registry.canonicalSha256;
envelope.caseId = caseContract.id;
envelope.caseOrdinal = caseContract.ordinal;
envelope.caseCanonicalSha256 = caseContract.caseCanonicalSha256;
envelope.presetName = caseContract.presetName;
envelope.seed = caseContract.seed;
envelope.registeredBirthPriorCanonicalSha256 = ...
    computeCanonicalValueSha256(struct( ...
        'numberOfBirthLocations', ...
            runtimeModel.numberOfBirthLocations, ...
        'birthTimeByLocation', runtimeModel.birthTimeByLocation, ...
        'birthParameters', runtimeModel.birthParameters));
envelope.targetTrajectoryRealizationAbsent = true;
envelope.groundTruthAbsent = true;
envelope.fullScenarioTargetMetadataAbsent = true;
envelope.duplicateSensorTrajectoryCopiesAbsent = true;
envelope.registeredBirthPriorRetained = true;
envelope.sensorTrajectorySuppliedAsSeparateRuntimeInput = true;
envelope.trackingOutcomeAuthorizationGranted = false;
envelope.validationClaimAllowed = false;
runtimeModel.formationB4V46RuntimeSourceEnvelope = envelope;

assertExactRuntimeSchema(runtimeModel, caseContract, identity);
end

function validateAuthority(caseContract, registry, official)
if ~isstruct(caseContract) || ~isscalar(caseContract) || ...
        ~isstruct(registry) || ~isscalar(registry) || ...
        ~isequaln(registry, official)
    error('FormationB4V46RuntimeModel:AuthorityDrift', ...
        'The runtime sanitizer requires the official source registry.');
end
matching = strcmp({official.cases.id}, caseContract.id) & ...
    [official.cases.ordinal] == caseContract.ordinal;
if nnz(matching) ~= 1 || ...
        ~isequaln(caseContract, official.cases(matching))
    error('FormationB4V46RuntimeModel:AuthorityDrift', ...
        'The runtime sanitizer case is not registered.');
end
end

function validateSourceModel(model, caseContract)
requiredScenarioFields = { ...
    'presetName', 'seed', 'config'};
if ~isstruct(model) || ~isscalar(model) || ...
        ~isfield(model, 'dynamicTopologyScenario') || ...
        ~isstruct(model.dynamicTopologyScenario) || ...
        ~isscalar(model.dynamicTopologyScenario) || ...
        ~all(isfield(model.dynamicTopologyScenario, ...
            requiredScenarioFields))
    error('FormationB4V46RuntimeModel:MalformedSourceModel', ...
        'The generator source model is malformed.');
end
scenario = model.dynamicTopologyScenario;
config = scenario.config;
if ~isstruct(config) || ~isscalar(config) || ...
        ~ischar(scenario.presetName) || ...
        ~strcmp(scenario.presetName, caseContract.presetName) || ...
        scenario.seed ~= caseContract.seed || ...
        ~isfield(config, 'presetName') || ...
        ~strcmp(config.presetName, caseContract.presetName) || ...
        ~strcmp(computeCanonicalValueSha256(config), ...
            caseContract.configSnapshotSha256)
    error('FormationB4V46RuntimeModel:SourceCaseDrift', ...
        'The source model does not belong to the registered case.');
end
end

function validateEmbeddedIdentity(config, identity, caseContract)
required = { ...
    'sensorGroupIds', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', ...
    'physicalIdentityRegistryCanonicalSha256'};
if ~all(isfield(config, required)) || ...
        numel(config.sensorGroupIds) ~= caseContract.numberOfSensors || ...
        ~isequal(reshape(config.sensorPhysicalUids, 1, []), ...
            identity.sensorPhysicalUids) || ...
        ~isequal(reshape(config.formationPhysicalUidsBySensor, 1, []), ...
            identity.formationPhysicalUidsBySensor) || ...
        ~strcmp(config.physicalIdentityRegistryCanonicalSha256, ...
            identity.canonicalSha256)
    error('FormationB4V46RuntimeModel:PhysicalIdentityDrift', ...
        'The source physical-identity registry is inconsistent.');
end
end

function config = buildRuntimeConfig(source)
initialCenterWaypoints = cell(1, source.formationCount);
for formationIdx = 1:source.formationCount
    initialCenterWaypoints{formationIdx} = ...
        source.sensorCenterWaypoints{formationIdx}(:, 1);
end
config = struct();
config.presetName = source.presetName;
config.formationCount = source.formationCount;
config.sensorsPerFormation = source.sensorsPerFormation;
config.numberOfSensors = source.numberOfSensors;
config.sensorCenterWaypoints = initialCenterWaypoints;
config.sensorGroupIds = reshape(source.sensorGroupIds, 1, []);
config.formationStochasticRoleUidsByFormation = reshape( ...
    source.formationStochasticRoleUidsByFormation, 1, []);
config.sensorLocalRoleUidsByFormation = ...
    source.sensorLocalRoleUidsByFormation;
config.sensorPhysicalUids = reshape(source.sensorPhysicalUids, 1, []);
config.formationPhysicalUidsBySensor = reshape( ...
    source.formationPhysicalUidsBySensor, 1, []);
config.physicalIdentityRegistryContractVersion = ...
    source.physicalIdentityRegistryContractVersion;
config.physicalIdentityRegistryCanonicalSha256 = ...
    source.physicalIdentityRegistryCanonicalSha256;
end

function object = buildEmptyRuntimeObject(sourceObject)
fields = runtimeObjectFieldNames();
if ~isstruct(sourceObject) || ~isempty(sourceObject) || ...
        ~isequal(sort(fieldnames(sourceObject)), sort(fields(:)))
    error('FormationB4V46RuntimeModel:ObjectSchemaDrift', ...
        'The source empty-object template has an unexpected schema.');
end
object = runtimeObjectTemplate(0, 0);
object = repmat(object, 0, 1);
end

function births = buildRuntimeBirthParameters( ...
        sourceBirths, stateDimension, timeCount, birthCount)
fields = runtimeObjectFieldNames();
if ~isstruct(sourceBirths) || numel(sourceBirths) ~= birthCount || ...
        ~isequal(sort(fieldnames(sourceBirths)), sort(fields(:)))
    error('FormationB4V46RuntimeModel:BirthSchemaDrift', ...
        'The source birth prior has an unexpected schema.');
end
births = repmat(runtimeObjectTemplate( ...
    stateDimension, timeCount), birthCount, 1);
for birthIdx = 1:birthCount
    source = sourceBirths(birthIdx);
    if ~isa(source.birthLocation, 'double') || ...
            ~isscalar(source.birthLocation) || ...
            ~isfinite(source.birthLocation) || ...
            source.birthLocation < 1 || ...
            source.birthLocation ~= round(source.birthLocation) || ...
            ~isa(source.r, 'double') || ~isscalar(source.r) || ...
            ~isfinite(source.r) || source.r < 0 || source.r > 1 || ...
            ~isa(source.numberOfGmComponents, 'double') || ...
            ~isequal(source.numberOfGmComponents, 1) || ...
            ~isa(source.w, 'double') || ~isscalar(source.w) || ...
            ~isfinite(source.w) || abs(source.w - 1) > 1e-12 || ...
            ~iscell(source.mu) || numel(source.mu) ~= 1 || ...
            ~isa(source.mu{1}, 'double') || ...
            ~isreal(source.mu{1}) || ...
            ~isequal(size(source.mu{1}), [stateDimension, 1]) || ...
            any(~isfinite(source.mu{1}(:))) || ...
            ~iscell(source.Sigma) || numel(source.Sigma) ~= 1 || ...
            ~isa(source.Sigma{1}, 'double') || ...
            ~isreal(source.Sigma{1}) || ...
            ~isequal(size(source.Sigma{1}), ...
                [stateDimension, stateDimension]) || ...
            any(~isfinite(source.Sigma{1}(:))) || ...
            norm(source.Sigma{1} - source.Sigma{1}', 'fro') > 1e-10
        error('FormationB4V46RuntimeModel:BirthPriorDrift', ...
            'A registered birth Bernoulli is malformed.');
    end
    births(birthIdx).birthLocation = source.birthLocation;
    births(birthIdx).r = source.r;
    births(birthIdx).numberOfGmComponents = 1;
    births(birthIdx).w = 1;
    births(birthIdx).mu = {source.mu{1}};
    births(birthIdx).Sigma = {source.Sigma{1}};
end
end

function object = runtimeObjectTemplate(stateDimension, timeCount)
object = struct();
object.birthLocation = 0;
object.birthTime = 0;
object.r = 0;
object.numberOfGmComponents = 0;
object.w = zeros(0, 1);
object.mu = cell(0, 1);
object.Sigma = cell(0, 1);
object.associationEntropy = 0;
object.detectionAssociationEntropy = 0;
object.detectionAssociationMass = 0;
object.associationAmbiguity = 0;
object.associationConfidence = 1;
object.trajectoryLength = 0;
object.trajectory = nan(stateDimension, timeCount);
object.timestamps = zeros(1, timeCount);
end

function quality = buildRuntimeSensorQuality(source)
fields = { ...
    'enabled', 'referenceRange', 'detectionRangeDecay', ...
    'detectionRangePower', 'edgeDetectionPenalty', 'anglePower', ...
    'minDetectionProbability', 'rangeNoiseScale', ...
    'edgeNoiseScale', 'minCovarianceScale', 'maxCovarianceScale'};
if ~isstruct(source) || ~isscalar(source) || ...
        ~isequal(sort(fieldnames(source)), sort(fields(:))) || ...
        ~islogical(source.enabled) || ~isscalar(source.enabled)
    error('FormationB4V46RuntimeModel:SensorQualityDrift', ...
        'The registered sensing-quality model is malformed.');
end
quality = struct();
quality.enabled = source.enabled;
for fieldIdx = 2:numel(fields)
    fieldName = fields{fieldIdx};
    value = source.(fieldName);
    if ~isa(value, 'double') || ~isreal(value) || ...
            ~isscalar(value) || ~isfinite(value)
        error('FormationB4V46RuntimeModel:SensorQualityDrift', ...
            'A sensing-quality parameter is malformed.');
    end
    quality.(fieldName) = value;
end
end

function validateNumericCellModels(model, timeCount)
sensorCount = model.numberOfSensors;
birthCount = model.numberOfBirthLocations;
if ~islogical(model.sensorMotionEnabled) || ...
        ~isequal(model.sensorMotionEnabled, true) || ...
        ~isa(model.xDimension, 'double') || ...
        ~isequal(model.xDimension, 4) || ...
        ~isa(model.zDimension, 'double') || ...
        ~isequal(model.zDimension, 2) || ...
        ~isFiniteScalar(model.survivalProbability) || ...
        model.survivalProbability < 0 || ...
        model.survivalProbability > 1 || ...
        ~isFiniteScalar(model.existenceThreshold) || ...
        model.existenceThreshold < 0 || ...
        model.existenceThreshold > 1 || ...
        ~isFiniteMatrix(model.A, [4, 4]) || ...
        ~isFiniteMatrix(model.u, [4, 1]) || ...
        ~isFiniteMatrix(model.R, [4, 4]) || ...
        norm(model.R - model.R', 'fro') > 1e-10 || ...
        ~isFiniteScalar(model.numberOfSensors) || ...
        ~any(sensorCount == [24, 36]) || ...
        sensorCount ~= round(sensorCount) || ...
        ~iscell(model.C) || numel(model.C) ~= sensorCount || ...
        ~iscell(model.Q) || numel(model.Q) ~= sensorCount || ...
        ~all(cellfun(@(value) isa(value, 'double') && ...
            isreal(value) && ...
            isequal(size(value), [model.zDimension, model.xDimension]) && ...
            all(isfinite(value(:))), model.C)) || ...
        ~all(cellfun(@(value) isa(value, 'double') && ...
            isreal(value) && ...
            isequal(size(value), [model.zDimension, model.zDimension]) && ...
            all(isfinite(value(:))), model.Q)) || ...
        ~isFiniteVector(model.detectionProbability, sensorCount) || ...
        any(model.detectionProbability(:) < 0) || ...
        any(model.detectionProbability(:) > 1) || ...
        ~isFiniteVector(model.clutterRate, sensorCount) || ...
        any(model.clutterRate(:) < 0) || ...
        ~isFiniteVector(model.clutterPerUnitVolume, sensorCount) || ...
        any(model.clutterPerUnitVolume(:) < 0) || ...
        ~isFiniteScalar(birthCount) || birthCount < 1 || ...
        birthCount ~= round(birthCount) || ...
        ~isFiniteScalar(model.gmWeightThreshold) || ...
        model.gmWeightThreshold < 0 || ...
        ~isFiniteScalar(model.maximumNumberOfGmComponents) || ...
        model.maximumNumberOfGmComponents < 1 || ...
        model.maximumNumberOfGmComponents ~= ...
            round(model.maximumNumberOfGmComponents) || ...
        ~isFiniteScalar(model.minimumTrajectoryLength) || ...
        model.minimumTrajectoryLength < 0 || ...
        model.minimumTrajectoryLength ~= ...
            round(model.minimumTrajectoryLength) || ...
        ~ischar(model.dataAssociationMethod) || ...
        ~strcmp(model.dataAssociationMethod, 'LBP') || ...
        ~isFiniteScalar(model.maximumNumberOfLbpIterations) || ...
        model.maximumNumberOfLbpIterations < 1 || ...
        model.maximumNumberOfLbpIterations ~= ...
            round(model.maximumNumberOfLbpIterations) || ...
        ~isFiniteScalar(model.lbpConvergenceTolerance) || ...
        model.lbpConvergenceTolerance <= 0 || ...
        ~isa(model.sensorCommRange, 'double') || ...
        ~isscalar(model.sensorCommRange) || ...
        ~isfinite(model.sensorCommRange) || ...
        model.sensorCommRange <= 0 || ...
        ~islogical(model.sensorFovEnabled) || ...
        ~isequal(model.sensorFovEnabled, true) || ...
        ~isFiniteVector(model.sensorFovHalfAngleDeg, sensorCount) || ...
        any(abs(model.sensorFovHalfAngleDeg(:) - 60) > 1e-12) || ...
        ~isFiniteVector(model.sensorFovRange, sensorCount) || ...
        any(abs(model.sensorFovRange(:) - 300) > 1e-12) || ...
        ~isFiniteMatrix(model.sensorFovHeadingRad, ...
            [sensorCount, timeCount]) || ...
        ~isFiniteScalar(timeCount) || timeCount < 1 || ...
        ~isa(model.birthTimeByLocation, 'double') || ...
        numel(model.birthTimeByLocation) ~= birthCount || ...
        any(~isfinite(model.birthTimeByLocation(:))) || ...
        any(model.birthTimeByLocation(:) < 1) || ...
        any(model.birthTimeByLocation(:) > timeCount) || ...
        any(model.birthTimeByLocation(:) ~= ...
            round(model.birthTimeByLocation(:)))
    error('FormationB4V46RuntimeModel:FilterModelDrift', ...
        'The frozen LBP filter model is malformed.');
end
end

function valid = isFiniteScalar(value)
valid = isa(value, 'double') && isreal(value) && ...
    isscalar(value) && isfinite(value);
end

function valid = isFiniteVector(value, count)
valid = isa(value, 'double') && isreal(value) && ...
    isvector(value) && numel(value) == count && ...
    all(isfinite(value(:)));
end

function valid = isFiniteMatrix(value, expectedSize)
valid = isa(value, 'double') && isreal(value) && ...
    isequal(size(value), expectedSize) && all(isfinite(value(:)));
end

function assertExactRuntimeSchema(model, caseContract, expectedIdentity)
expectedTopLevel = [directRuntimeModelFieldNames(), { ...
    'object', 'birthParameters', 'sensorQuality', ...
    'dynamicTopologyScenario', ...
    'formationB4V46RuntimeSourceEnvelope'}];
expectedScenario = { ...
    'presetName', 'seed', 'config'};
expectedConfig = { ...
    'presetName', 'formationCount', 'sensorsPerFormation', ...
    'numberOfSensors', 'sensorCenterWaypoints', 'sensorGroupIds', ...
    'formationStochasticRoleUidsByFormation', ...
    'sensorLocalRoleUidsByFormation', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', ...
    'physicalIdentityRegistryContractVersion', ...
    'physicalIdentityRegistryCanonicalSha256'};
expectedEnvelope = { ...
    'contractVersion', 'registryId', 'registryCanonicalSha256', ...
    'caseId', 'caseOrdinal', 'caseCanonicalSha256', 'presetName', ...
    'seed', 'registeredBirthPriorCanonicalSha256', ...
    'targetTrajectoryRealizationAbsent', 'groundTruthAbsent', ...
    'fullScenarioTargetMetadataAbsent', ...
    'duplicateSensorTrajectoryCopiesAbsent', ...
    'registeredBirthPriorRetained', ...
    'sensorTrajectorySuppliedAsSeparateRuntimeInput', ...
    'trackingOutcomeAuthorizationGranted', ...
    'validationClaimAllowed'};
scenario = model.dynamicTopologyScenario;
config = scenario.config;
envelope = model.formationB4V46RuntimeSourceEnvelope;
identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
if ~isequal(sort(fieldnames(model)), sort(expectedTopLevel(:))) || ...
        ~isequal(sort(fieldnames(scenario)), ...
            sort(expectedScenario(:))) || ...
        ~isequal(sort(fieldnames(config)), sort(expectedConfig(:))) || ...
        ~isequal(sort(fieldnames(envelope)), ...
            sort(expectedEnvelope(:))) || ...
        model.numberOfSensors ~= caseContract.numberOfSensors || ...
        scenario.seed ~= caseContract.seed || ...
        ~strcmp(scenario.presetName, caseContract.presetName) || ...
        ~strcmp(identity.canonicalSha256, ...
            expectedIdentity.canonicalSha256) || ...
        ~strcmp(config.physicalIdentityRegistryCanonicalSha256, ...
            identity.canonicalSha256) || ...
        ~all(cellfun(@(value) isnumeric(value) && ...
            isreal(value) && isequal(size(value), [2, 1]) && ...
            all(isfinite(value(:))), config.sensorCenterWaypoints))
    error('FormationB4V46RuntimeModel:SanitizedSchemaDrift', ...
        'The sanitized runtime model violated its exact schema.');
end
end

function fields = directRuntimeModelFieldNames()
fields = { ...
    'sensorMotionEnabled', 'xDimension', 'zDimension', ...
    'survivalProbability', 'existenceThreshold', 'A', 'u', 'R', ...
    'numberOfSensors', 'C', 'Q', 'detectionProbability', ...
    'clutterRate', 'clutterPerUnitVolume', ...
    'numberOfBirthLocations', ...
    'gmWeightThreshold', 'maximumNumberOfGmComponents', ...
    'minimumTrajectoryLength', 'dataAssociationMethod', ...
    'maximumNumberOfLbpIterations', 'lbpConvergenceTolerance', ...
    'sensorCommRange', 'sensorFovEnabled', ...
    'sensorFovHalfAngleDeg', 'sensorFovRange', ...
    'sensorFovHeadingRad', 'birthTimeByLocation'};
end

function fields = runtimeObjectFieldNames()
fields = { ...
    'birthLocation', 'birthTime', 'r', 'numberOfGmComponents', ...
    'w', 'mu', 'Sigma', 'associationEntropy', ...
    'detectionAssociationEntropy', 'detectionAssociationMass', ...
    'associationAmbiguity', 'associationConfidence', ...
    'trajectoryLength', 'trajectory', 'timestamps'};
end
