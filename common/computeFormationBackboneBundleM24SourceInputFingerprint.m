function fingerprint = ...
    computeFormationBackboneBundleM24SourceInputFingerprint( ...
        model, measurements, sensorTrajectories, neighborMap, ...
        commConfig)
% COMPUTEFORMATIONBACKBONEBUNDLEM24SOURCEINPUTFINGERPRINT Exact input bind.

payload = struct();
payload.contractVersion = ...
    'formation-backbone-bundle-m24-source-input-fingerprint-v1';
try
    payload.modelCanonicalSha256 = ...
        computeCanonicalValueSha256(model);
    payload.measurementsCanonicalSha256 = ...
        computeCanonicalValueSha256(measurements);
    payload.sensorTrajectoriesCanonicalSha256 = ...
        computeCanonicalValueSha256(sensorTrajectories);
    payload.neighborMapCanonicalSha256 = ...
        computeCanonicalValueSha256(neighborMap);
    payload.commConfigCanonicalSha256 = ...
        computeCanonicalValueSha256(commConfig);
    canonicalSha256 = computeCanonicalValueSha256(payload);
catch errorInfo
    error('FormationBundleSourcePermit:InputFingerprintFailed', ...
        'The exact source input fingerprint could not be built: %s', ...
        errorInfo.message);
end
fingerprint = payload;
fingerprint.canonicalSha256 = canonicalSha256;
end
