function [adjacency, details] = ...
    selectRollingSafeActionSequencePolicy( ...
        context, actionCodes, anchorTime, options)
% SELECTROLLINGSAFEACTIONSEQUENCEPOLICY Closed-loop action-code probe.
%
% Code 0 recomputes the privileged current-risk teacher from the actual
% trajectory state. Codes 1:(6 * formationCount) select a rolling-B3 burst:
% three temporal phases for each clockwise/counter-clockwise root. Every
% branch is passed through selectRollingSafeRoutingPolicy, so a sequence
% changes the proposal objective but never bypasses the common safety layer.
%
% The code sequence is a finite-horizon attainability/search primitive. Any
% sequence containing code 0 reads truth and must remain excluded from a
% deployable or validation strategy.

actionCodes = round(reshape(actionCodes, 1, []));
if isempty(actionCodes) || any(~isfinite(actionCodes)) || ...
        any(actionCodes < 0)
    error('Action sequence codes must be finite nonnegative integers.');
end
anchorTime = round(anchorTime);
relativeTime = context.currentTime - anchorTime + 1;
if relativeTime >= 1 && relativeTime <= numel(actionCodes)
    actionCode = actionCodes(relativeTime);
else
    actionCode = getField(options, ...
        'fallbackActionCode', actionCodes(end));
end

sourceWeight = getField(options, 'sourceWeight', 0.70);
payloadToleranceFraction = getField( ...
    options, 'payloadToleranceFraction', inf);
if actionCode == 0
    scoreOptions = getField(options, 'scoreOptions', struct());
    scoreOptions.sourceWeight = sourceWeight;
    policyOptions = struct( ...
        'sourceWeight', sourceWeight, ...
        'payloadToleranceFraction', payloadToleranceFraction, ...
        'edgeScoreFcnReturnsDetails', true, ...
        'edgeScoreFcn', ...
            @(scoreContext, receiverIndices, ...
                senderIndices, cycleSources) ...
                computeRollingSafeTaskTeacherEdgeScores( ...
                    scoreContext, receiverIndices, ...
                    senderIndices, cycleSources, scoreOptions), ...
        'posteriorUsed', true, ...
        'truthUsed', true, ...
        'currentLinkReliabilityUsed', true, ...
        'teacherRequestedHorizonSteps', getField( ...
            scoreOptions, 'horizonSteps', 0));
    [adjacency, details] = selectRollingSafeRoutingPolicy( ...
        context, 'external-scores', policyOptions);
    branch = 'privileged-current-risk';
elseif actionCode >= 90 && actionCode <= 99
    alternativeIndex = actionCode - 89;
    diverseOptions = struct( ...
        'sourceWeight', sourceWeight, ...
        'payloadToleranceFraction', payloadToleranceFraction, ...
        'scoreOptions', getField( ...
            options, 'scoreOptions', struct()));
    [adjacency, details] = ...
        selectRollingSafeDiverseTeacherPolicy( ...
            context, alternativeIndex, diverseOptions);
    branch = sprintf( ...
        'privileged-diverse-current-risk-%d', ...
        alternativeIndex);
else
    groupIds = reshape(context.model. ...
        dynamicTopologyScenario.config.sensorGroupIds, 1, []);
    formationCount = numel(unique(groupIds, 'stable'));
    [rootFormation, orientation, temporalPhase] = ...
        decodeBurstAction(actionCode, formationCount);
    policyOptions = struct( ...
        'sourceWeight', sourceWeight, ...
        'rootFormation', rootFormation, ...
        'orientation', orientation, ...
        'temporalPhase', temporalPhase, ...
        'payloadToleranceFraction', payloadToleranceFraction);
    [adjacency, details] = selectRollingSafeRoutingPolicy( ...
        context, 'scheduled-burst', policyOptions);
    branch = sprintf( ...
        'scheduled-burst-r%d-%s-p%d', rootFormation, ...
        orientationToken(orientation), temporalPhase);
end

details.actionSequenceCodes = actionCodes;
details.actionSequenceCode = actionCode;
details.actionSequenceBranch = branch;
details.actionSequenceAnchorTime = anchorTime;
details.actionSequenceRelativeTime = relativeTime;
details.actionSequenceTruthUsed = ...
    actionCode == 0 || (actionCode >= 90 && actionCode <= 99);
end

function [rootFormation, orientation, temporalPhase] = ...
        decodeBurstAction(actionCode, formationCount)
maximumCode = 6 * formationCount;
if actionCode < 1 || actionCode > maximumCode
    error(['Scheduled action code must be in 1:%d for a %d-formation ', ...
        'scenario; received %d.'], ...
        maximumCode, formationCount, actionCode);
end
zeroBased = actionCode - 1;
rootFormation = floor(zeroBased / 6) + 1;
withinRoot = mod(zeroBased, 6);
if withinRoot < 3
    orientation = 'clockwise';
else
    orientation = 'counter-clockwise';
end
temporalPhase = mod(withinRoot, 3);
end

function token = orientationToken(orientation)
if strcmp(orientation, 'clockwise')
    token = 'cw';
else
    token = 'ccw';
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
