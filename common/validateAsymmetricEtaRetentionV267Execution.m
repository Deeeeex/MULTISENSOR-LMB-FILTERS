function authorization = validateAsymmetricEtaRetentionV267Execution( ...
        model, context, request)
% VALIDATEASYMMETRICETARETENTIONV267EXECUTION Matched V266-derived gate.

protocol = getAsymmetricEtaRetentionV267Protocol();
expectedFields = { ...
    'contractVersion', 'capability', 'action', 'protocolId', ...
    'presetName', 'seed', 'armId', 'measurementTimeCount', ...
    'continuationStartTime', 'policyName', 'developmentEvidenceOnly'};
valid = isstruct(context) && isscalar(context) && ...
    isequal(sort(fieldnames(context)), sort(expectedFields(:))) && ...
    strcmp(context.capability, ...
        'asymmetric-eta-retention-v267-development') && ...
    strcmp(context.action, ...
        'filter-asymmetric-eta-retention-v267-development') && ...
    strcmp(context.protocolId, protocol.id) && ...
    ismember(context.presetName, protocol.allowedPresets) && ...
    ismember(context.seed, protocol.allowedSeeds) && ...
    strcmp(context.armId, protocol.armId) && ...
    context.measurementTimeCount == protocol.continuationEndTime && ...
    context.continuationStartTime == protocol.continuationStartTime && ...
    strcmp(context.policyName, protocol.policyName) && ...
    isequal(context.developmentEvidenceOnly, true) && ...
    isstruct(request) && isscalar(request) && ...
    isfield(request, 'triggerConfig') && ...
    isfield(request.triggerConfig, ...
        'topologyPolicyLabelInputRouteMaximumSubMapReferenceLogOddsDrop') && ...
    abs(request.triggerConfig. ...
        topologyPolicyLabelInputRouteMaximumSubMapReferenceLogOddsDrop - ...
        protocol.maximumSubMapReferenceLogOddsDrop) <= 1e-12;
if ~valid
    error('AsymmetricEtaRetentionV267:InvalidExecutionContext', ...
        'The V267 execution request changed its matched boundary.');
end

source = getEtaProjectedLabelTrustV266Protocol();
sourceContext = context;
sourceContext.contractVersion = ...
    'eta-projected-label-trust-v266-context-v1';
sourceContext.capability = 'eta-projected-label-trust-v266-development';
sourceContext.action = ...
    'filter-eta-projected-label-trust-v266-development';
sourceContext.protocolId = source.id;
sourceContext.armId = source.armId;
sourceContext.policyName = source.policyName;
sourceRequest = request;
sourceRequest.triggerConfig.topologyPolicyName = source.policyName;
authorization = validateEtaProjectedLabelTrustV266Execution( ...
    model, sourceContext, sourceRequest);
authorization.mode = 'asymmetric-eta-retention-v267-development';
authorization.capability = context.capability;
authorization.action = context.action;
authorization.protocolId = protocol.id;
authorization.armId = context.armId;
end
