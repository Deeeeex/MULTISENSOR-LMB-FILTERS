function [config, details] = ...
    buildFormationB4V47FixedTriggerConfig(armId, nodeCount)
% BUILDFORMATIONB4V47FIXEDTRIGGERCONFIG Frozen reference/candidate runtime.

if nargin ~= 2 || ~ischar(armId) || ~isrow(armId) || ...
        ~isa(nodeCount, 'double') || ~isreal(nodeCount) || ...
        ~isscalar(nodeCount) || ~isfinite(nodeCount) || ...
        nodeCount < 1 || nodeCount ~= round(nodeCount)
    error('FormationB4V47TriggerConfig:InvalidInput', ...
        'A frozen V47 arm and positive integer node count are required.');
end
protocol = getFormationGatewayDebtV47Protocol();
switch armId
    case 'v46-repaired-reference-a70-e05'
        armOrdinal = 1;
        [config, parentDetails] = ...
            buildFormationB4V46FixedTriggerConfig(armId, nodeCount);
        policyFunctionName = ...
            'selectFormationB4V46ReferenceRuntimePolicy';
    case 'v47-repaired-gateway-debt-b4-e20'
        armOrdinal = 2;
        [config, parentDetails] = ...
            buildFormationB4V46FixedTriggerConfig( ...
                'v46-repaired-sync-all-b4-e20-mc', nodeCount);
        policyFunctionName = ...
            'selectFormationB4V47GatewayDebtRuntimePolicy';
        policyFunction = ...
            @selectFormationB4V47GatewayDebtRuntimePolicy;
        config.topologyPolicyName = policyFunctionName;
        config.topologyPolicyFcn = policyFunction;
        config.topologyPolicyDeliveryHistoryEnabled = true;
    otherwise
        error('FormationB4V47TriggerConfig:UnknownArm', ...
            'Only the frozen V47 reference and candidate are allowed.');
end
config.topologyPolicyHistoryDepth = max( ...
    getField(config, 'topologyPolicyHistoryDepth', 0), 8);
if ~strcmp(protocol.primaryArms{armOrdinal}, armId)
    error('FormationB4V47TriggerConfig:ProtocolDrift', ...
        'The V47 primary-arm registry changed or reordered.');
end

snapshot = rmfield(config, 'topologyPolicyFcn');
snapshot.topologyPolicyFunctionName = policyFunctionName;
payload = struct( ...
    'contractVersion', 'formation-b4-v47-fixed-trigger-config-v1', ...
    'armId', armId, 'armOrdinal', armOrdinal, ...
    'parentConfigCanonicalSha256', parentDetails.canonicalSha256, ...
    'protocolId', protocol.id, ...
    'protocolCanonicalSha256', protocol.canonicalSha256, ...
    'nodeCount', nodeCount, 'configSnapshot', snapshot);
details = payload;
details.policyFunctionHandleExcluded = true;
details.overridesAccepted = false;
details.canonicalSha256 = computeCanonicalValueSha256(payload);
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
