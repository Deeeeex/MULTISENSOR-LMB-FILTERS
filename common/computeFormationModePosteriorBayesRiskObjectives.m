function [objectives, details] = ...
    computeFormationModePosteriorBayesRiskObjectives( ...
        receiverDistributionsByMode, groupIds, options)
% COMPUTEFORMATIONMODEPOSTERIORBAYESRISKOBJECTIVES Truth-free mode value.
%
% Each receiver-mode value is evaluated after fusion and after integrating
% link delivery outcomes.  Formation value is the reduction in a robust
% mean-tail posterior Bayes risk relative to the registered reference mode.

if nargin < 3 || isempty(options)
    options = struct();
end
if ~iscell(receiverDistributionsByMode) || ...
        numel(receiverDistributionsByMode) < 2
    error('Formation Bayes-risk objectives require at least two modes.');
end
modeCount = numel(receiverDistributionsByMode);
nodeCount = numel(receiverDistributionsByMode{1});
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
referenceModeIndex = round(getField( ...
    options, 'referenceModeIndex', 1));
tailFraction = getField(options, 'receiverTailFraction', 0.34);
tailWeight = getField(options, 'receiverTailWeight', 0.5);
if nodeCount < 1 || numel(groupIds) ~= nodeCount || ...
        any(~isfinite(groupIds)) || any(groupIds < 1) || ...
        any(mod(groupIds, 1) ~= 0) || ...
        any(cellfun(@numel, receiverDistributionsByMode) ~= nodeCount) || ...
        referenceModeIndex < 1 || referenceModeIndex > modeCount || ...
        ~isscalar(tailFraction) || ~isfinite(tailFraction) || ...
        tailFraction <= 0 || tailFraction > 1 || ...
        ~isscalar(tailWeight) || ~isfinite(tailWeight) || ...
        tailWeight < 0 || tailWeight > 1
    error('Formation posterior Bayes-risk objective inputs are invalid.');
end

receiverRiskByMode = zeros(nodeCount, modeCount);
receiverDetailsByMode = cell(nodeCount, modeCount);
for receiverIdx = 1:nodeCount
    labelUniverse = receiverLabelUniverse( ...
        receiverDistributionsByMode, receiverIdx);
    scoreOptions = options;
    scoreOptions.labelUniverse = labelUniverse;
    for modeIdx = 1:modeCount
        [receiverRiskByMode(receiverIdx, modeIdx), ...
            receiverDetailsByMode{receiverIdx, modeIdx}] = ...
                computeExpectedLmbPosteriorBayesRisk( ...
                    receiverDistributionsByMode{modeIdx}{receiverIdx}, ...
                    scoreOptions);
    end
end

formationRiskByMode = zeros(formationCount, modeCount);
for formationIdx = 1:formationCount
    members = reshape(find( ...
        groupIds == groups(formationIdx)), 1, []);
    for modeIdx = 1:modeCount
        values = receiverRiskByMode(members, modeIdx);
        tailCount = max(1, ceil(tailFraction * numel(values)));
        sorted = sort(values, 'descend');
        meanRisk = mean(values);
        tailRisk = mean(sorted(1:tailCount));
        formationRiskByMode(formationIdx, modeIdx) = ...
            (1 - tailWeight) * meanRisk + tailWeight * tailRisk;
    end
end
referenceRisk = formationRiskByMode(:, referenceModeIndex);
objectives = repmat(referenceRisk, 1, modeCount) - ...
    formationRiskByMode;

details = struct( ...
    'contractVersion', ...
        'formation-mode-posterior-bayes-risk-objectives-v1', ...
    'referenceModeIndex', referenceModeIndex, ...
    'receiverTailFraction', tailFraction, ...
    'receiverTailWeight', tailWeight, ...
    'receiverRiskByMode', receiverRiskByMode, ...
    'receiverDetailsByMode', {receiverDetailsByMode}, ...
    'formationRiskByMode', formationRiskByMode, ...
    'objectives', objectives, ...
    'truthUsed', false, ...
    'groundTruthUsed', false, ...
    'futureOutcomeUsed', false);
end

function labels = receiverLabelUniverse( ...
        distributionsByMode, receiverIdx)
labels = zeros(2, 0);
for modeIdx = 1:numel(distributionsByMode)
    distribution = distributionsByMode{modeIdx}{receiverIdx};
    for outcomeIdx = 1:numel(distribution.summary)
        current = distribution.summary{outcomeIdx}.labels;
        for labelIdx = 1:size(current, 2)
            if isempty(labels) || ...
                    ~any(all(labels == current(:, labelIdx), 1))
                labels(:, end + 1) = ...
                    current(:, labelIdx); %#ok<AGROW>
            end
        end
    end
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
