function details = resolveValueGatedFormationFovValidationCase( ...
        protocol, presetName, seed, scenarioConfig)
% RESOLVEVALUEGATEDFORMATIONFOVVALIDATIONCASE Validate a frozen test case.

% This helper is intentionally outcome-free.  It checks only the frozen
% scene, seed, hardware and scale contract before the tracking run opens.

if nargin < 1 || isempty(protocol)
    protocol = getLabelSetSimulatorPolicyProtocol();
end
if nargin < 4 || isempty(scenarioConfig)
    scenarioConfig = buildDynamicTopologyScenarioConfig(presetName);
end
presetName = char(presetName);
sceneIdx = find(strcmp( ...
    protocol.valueGatedFormationFovValidationPresets, presetName), 1);
if ~protocol.valueGatedFormationFovValidationAuthorized || ...
        isempty(sceneIdx) || ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= round(seed) || ...
        ~ismember(seed, ...
            protocol.valueGatedFormationFovValidationSeeds)
    error('FormationFovValidation:UnauthorizedCase', ...
        'Formation-FoV validation preset or seed is not registered.');
end

requiredFields = { ...
    'presetName', 'numberOfSensors', 'formationCount', ...
    'sensorsPerFormation', 'sensorHardwareProfile', ...
    'fovTotalAngleDeg', 'fovRange', 'sensorFovHeadingMode'};
if ~all(isfield(scenarioConfig, requiredFields)) || ...
        ~strcmp(scenarioConfig.presetName, presetName) || ...
        scenarioConfig.numberOfSensors ~= protocol. ...
            valueGatedFormationFovValidationExpectedNodeCounts(sceneIdx) || ...
        scenarioConfig.formationCount ~= protocol. ...
            valueGatedFormationFovValidationExpectedFormationCounts(sceneIdx) || ...
        scenarioConfig.sensorsPerFormation ~= protocol. ...
            valueGatedFormationFovValidationExpectedSensorsPerFormation(sceneIdx) || ...
        ~strcmp(scenarioConfig.sensorHardwareProfile, protocol. ...
            valueGatedFormationFovValidationHardwareProfile) || ...
        abs(scenarioConfig.fovTotalAngleDeg - protocol. ...
            valueGatedFormationFovValidationFovTotalAngleDeg) > 1e-12 || ...
        abs(scenarioConfig.fovRange - protocol. ...
            valueGatedFormationFovValidationFovRange) > 1e-12 || ...
        ~strcmp(scenarioConfig.sensorFovHeadingMode, protocol. ...
            valueGatedFormationFovValidationBoresightMode)
    error('FormationFovValidation:ScenarioContractMismatch', ...
        'Formation-FoV validation scene differs from the frozen contract.');
end

details = struct( ...
    'sceneIndex', sceneIdx, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'window', protocol. ...
        valueGatedFormationFovValidationWindows(sceneIdx, :), ...
    'expectedNodeCount', protocol. ...
        valueGatedFormationFovValidationExpectedNodeCounts(sceneIdx), ...
    'expectedFormationCount', protocol. ...
        valueGatedFormationFovValidationExpectedFormationCounts(sceneIdx), ...
    'expectedCandidateCount', protocol. ...
        valueGatedFormationFovValidationExpectedCandidateCounts(sceneIdx));
end
