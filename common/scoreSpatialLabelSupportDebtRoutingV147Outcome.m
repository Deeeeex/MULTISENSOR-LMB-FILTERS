function metrics = scoreSpatialLabelSupportDebtRoutingV147Outcome( ...
        referenceOutcome, candidateOutcome, groupIds, ...
        recoveryTailSteps, actionSpec, protocol)
% SCORESPATIALLABELSUPPORTDEBTROUTINGV147OUTCOME Joint safety gate.

required = { ...
    'eospaBySensorTime', 'posteriorConsensusByTime', ...
    'attemptedBytesByTime', 'selectedAdjacencyByTime', ...
    'nominalFusionWeightsByTime'};
if ~isstruct(referenceOutcome) || ~isscalar(referenceOutcome) || ...
        ~isstruct(candidateOutcome) || ~isscalar(candidateOutcome) || ...
        ~all(isfield(referenceOutcome, required)) || ...
        ~all(isfield(candidateOutcome, required)) || ...
        ~isequal(size(referenceOutcome.eospaBySensorTime), ...
            size(candidateOutcome.eospaBySensorTime)) || ...
        ~isstruct(actionSpec) || ~isscalar(actionSpec) || ...
        ~isfield(actionSpec, 'activeOffsets') || ...
        ~isfield(actionSpec, 'gateEligible') || ...
        ~isstruct(protocol) || ~isscalar(protocol) || ...
        ~strcmp(protocol.id, ...
            'spatial-label-support-debt-routing-v147-v1')
    error('SpatialDebtV147:InvalidOutcome', ...
        'The V147 paired outcomes are malformed.');
end
reference = double(referenceOutcome.eospaBySensorTime);
candidate = double(candidateOutcome.eospaBySensorTime);
[sensorCount, horizonSteps] = size(reference);
groupIds = reshape(groupIds, 1, []);
activeOffsets = reshape(actionSpec.activeOffsets, 1, []);
if numel(groupIds) ~= sensorCount || isempty(activeOffsets) || ...
        any(activeOffsets < 1) || any(activeOffsets > horizonSteps) || ...
        recoveryTailSteps < 1 || recoveryTailSteps >= horizonSteps
    error('SpatialDebtV147:InvalidScale', ...
        'The V147 action offsets or scale are invalid.');
end
interventionColumns = 1:max(activeOffsets);
matureColumns = ...
    (horizonSteps - recoveryTailSteps + 1):horizonSteps;

sensorGain = safeGain(mean(reference, 2), mean(candidate, 2));
sensorInterventionGain = safeGain( ...
    mean(reference(:, interventionColumns), 2), ...
    mean(candidate(:, interventionColumns), 2));
sensorMatureGain = safeGain( ...
    mean(reference(:, matureColumns), 2), ...
    mean(candidate(:, matureColumns), 2));
formationIds = unique(groupIds, 'stable');
formationGain = zeros(1, numel(formationIds));
formationInterventionGain = zeros(1, numel(formationIds));
formationMatureGain = zeros(1, numel(formationIds));
for formationIdx = 1:numel(formationIds)
    members = groupIds == formationIds(formationIdx);
    formationGain(formationIdx) = safeGain( ...
        mean(reference(members, :), 'all'), ...
        mean(candidate(members, :), 'all'));
    formationInterventionGain(formationIdx) = safeGain( ...
        mean(reference(members, interventionColumns), 'all'), ...
        mean(candidate(members, interventionColumns), 'all'));
    formationMatureGain(formationIdx) = safeGain( ...
        mean(reference(members, matureColumns), 'all'), ...
        mean(candidate(members, matureColumns), 'all'));
end

referenceConsensus = reshape( ...
    referenceOutcome.posteriorConsensusByTime, 1, []);
candidateConsensus = reshape( ...
    candidateOutcome.posteriorConsensusByTime, 1, []);
referenceAdjacency = logical( ...
    referenceOutcome.selectedAdjacencyByTime);
candidateAdjacency = logical( ...
    candidateOutcome.selectedAdjacencyByTime);
referenceWeights = referenceOutcome.nominalFusionWeightsByTime;
candidateWeights = candidateOutcome.nominalFusionWeightsByTime;
activeExecuted = false(1, numel(activeOffsets));
for offsetIdx = 1:numel(activeOffsets)
    page = activeOffsets(offsetIdx);
    activeExecuted(offsetIdx) = ~isequal( ...
        candidateAdjacency(:, :, page), ...
        referenceAdjacency(:, :, page));
end
rejoinColumns = (max(activeOffsets) + 1):horizonSteps;
rejoined = true(1, numel(rejoinColumns));
for pageIdx = 1:numel(rejoinColumns)
    page = rejoinColumns(pageIdx);
    rejoined(pageIdx) = isequal( ...
        candidateAdjacency(:, :, page), ...
        referenceAdjacency(:, :, page)) && ...
        max(abs(candidateWeights(:, :, page) - ...
            referenceWeights(:, :, page)), [], 'all') <= 1e-12;
end
messageParity = true(1, horizonSteps);
weightMultisetParity = true(1, horizonSteps);
for page = 1:horizonSteps
    messageParity(page) = ...
        nnz(candidateAdjacency(:, :, page)) == ...
        nnz(referenceAdjacency(:, :, page)) && ...
        isequal(sum(candidateAdjacency(:, :, page), 2), ...
            sum(referenceAdjacency(:, :, page), 2));
    weightMultisetParity(page) = rowWeightMultisetParity( ...
        candidateWeights(:, :, page), referenceWeights(:, :, page));
end
[sensorB3, formationB3] = rollingB3Pass( ...
    candidateAdjacency, groupIds);

referenceBytes = sum(referenceOutcome.attemptedBytesByTime);
candidateBytes = sum(candidateOutcome.attemptedBytesByTime);
gate = protocol.gate;
metrics = struct();
metrics.contractVersion = ...
    'v147-spatial-label-support-debt-routing-metrics-v1';
metrics.interventionGainFraction = safeGain( ...
    mean(reference(:, interventionColumns), 'all'), ...
    mean(candidate(:, interventionColumns), 'all'));
metrics.meanGainFraction = safeGain( ...
    mean(reference(:)), mean(candidate(:)));
metrics.matureGainFraction = safeGain( ...
    mean(reference(:, matureColumns), 'all'), ...
    mean(candidate(:, matureColumns), 'all'));
metrics.minimumSensorGainFraction = min(sensorGain);
metrics.minimumInterventionSensorGainFraction = ...
    min(sensorInterventionGain);
metrics.minimumMatureSensorGainFraction = min(sensorMatureGain);
metrics.formationIds = formationIds;
metrics.formationGainFraction = formationGain;
metrics.formationInterventionGainFraction = formationInterventionGain;
metrics.formationMatureGainFraction = formationMatureGain;
metrics.minimumFormationGainFraction = min(formationGain);
metrics.minimumInterventionFormationGainFraction = ...
    min(formationInterventionGain);
metrics.minimumMatureFormationGainFraction = ...
    min(formationMatureGain);
metrics.consensusGainFraction = safeGain( ...
    mean(referenceConsensus), mean(candidateConsensus));
metrics.interventionConsensusGainFraction = safeGain( ...
    mean(referenceConsensus(interventionColumns)), ...
    mean(candidateConsensus(interventionColumns)));
metrics.matureConsensusGainFraction = safeGain( ...
    mean(referenceConsensus(matureColumns)), ...
    mean(candidateConsensus(matureColumns)));
metrics.referenceAttemptedBytes = referenceBytes;
metrics.candidateAttemptedBytes = candidateBytes;
metrics.attemptedByteDeltaFraction = ...
    (candidateBytes - referenceBytes) / max(referenceBytes, eps);
metrics.interventionAttemptedByteDeltaFraction = ( ...
    sum(candidateOutcome.attemptedBytesByTime(interventionColumns)) - ...
    sum(referenceOutcome.attemptedBytesByTime(interventionColumns))) / ...
    max(sum(referenceOutcome.attemptedBytesByTime( ...
        interventionColumns)), eps);
metrics.activeOffsets = activeOffsets;
metrics.interventionColumns = interventionColumns;
metrics.matureColumns = matureColumns;
metrics.activeExecutedFraction = mean(activeExecuted);
metrics.rejoinedReferenceFraction = mean(rejoined);
metrics.messageParityPassed = all(messageParity);
metrics.weightMultisetParityPassed = all(weightMultisetParity);
metrics.rollingB3SensorPassed = all(sensorB3);
metrics.rollingB3FormationPassed = all(formationB3);
metrics.passesInterventionGate = ...
    metrics.interventionGainFraction >= ...
        gate.minimumInterventionGainFraction - 1e-12;
metrics.passesFullWindowGate = metrics.meanGainFraction >= ...
    gate.minimumFullWindowGainFraction - 1e-12;
metrics.passesMatureGate = metrics.matureGainFraction >= ...
    gate.minimumMatureGainFraction - 1e-12;
metrics.passesSensorGate = min([ ...
    metrics.minimumSensorGainFraction, ...
    metrics.minimumInterventionSensorGainFraction, ...
    metrics.minimumMatureSensorGainFraction]) >= ...
        gate.minimumSensorGainFraction - 1e-12;
metrics.passesFormationGate = min([ ...
    metrics.minimumFormationGainFraction, ...
    metrics.minimumInterventionFormationGainFraction, ...
    metrics.minimumMatureFormationGainFraction]) >= ...
        gate.minimumFormationGainFraction - 1e-12;
metrics.passesConsensusGate = min([ ...
    metrics.consensusGainFraction, ...
    metrics.interventionConsensusGainFraction, ...
    metrics.matureConsensusGainFraction]) >= ...
        gate.minimumConsensusGainFraction - 1e-12;
metrics.passesByteGate = metrics.attemptedByteDeltaFraction <= ...
    gate.maximumAttemptedByteDeltaFraction + 1e-12 && ...
    metrics.interventionAttemptedByteDeltaFraction <= ...
        gate.maximumAttemptedByteDeltaFraction + 1e-12;
metrics.passesExecutionGate = ...
    metrics.activeExecutedFraction >= 1 - 1e-12 && ...
    metrics.rejoinedReferenceFraction >= ...
        gate.minimumRejoinedReferenceFraction - 1e-12 && ...
    metrics.messageParityPassed && ...
    metrics.weightMultisetParityPassed && ...
    metrics.rollingB3SensorPassed && ...
    metrics.rollingB3FormationPassed;
metrics.actionGateEligible = logical(actionSpec.gateEligible);
metrics.passesHeadroomGate = ...
    metrics.actionGateEligible && ...
    metrics.passesInterventionGate && ...
    metrics.passesFullWindowGate && metrics.passesMatureGate && ...
    metrics.passesSensorGate && metrics.passesFormationGate && ...
    metrics.passesConsensusGate && metrics.passesByteGate && ...
    metrics.passesExecutionGate;
end

function pass = rowWeightMultisetParity(first, second)
pass = true;
for receiverIdx = 1:size(first, 1)
    a = sort(first(receiverIdx, first(receiverIdx, :) > 1e-12));
    b = sort(second(receiverIdx, second(receiverIdx, :) > 1e-12));
    if numel(a) ~= numel(b) || any(abs(a - b) > 1e-12)
        pass = false;
        return;
    end
end
end

function [sensorPass, formationPass] = rollingB3Pass(pages, groupIds)
horizonSteps = size(pages, 3);
sensorPass = true(1, horizonSteps);
formationPass = true(1, horizonSteps);
for page = 1:horizonSteps
    first = max(1, page - 2);
    unionPage = any(pages(:, :, first:page), 3);
    sensorPass(page) = isStronglyConnected(unionPage);
    formationPass(page) = isStronglyConnected( ...
        collapseToFormations(unionPage, groupIds));
end
end

function formation = collapseToFormations(adjacency, groupIds)
formationIds = unique(groupIds, 'stable');
formation = false(numel(formationIds));
for receiverIdx = 1:numel(formationIds)
    receivers = groupIds == formationIds(receiverIdx);
    for senderIdx = 1:numel(formationIds)
        senders = groupIds == formationIds(senderIdx);
        formation(receiverIdx, senderIdx) = ...
            any(any(adjacency(receivers, senders)));
    end
end
formation(1:numel(formationIds)+1:end) = false;
end

function connected = isStronglyConnected(adjacency)
senderAdjacency = logical(adjacency');
connected = reachesAll(senderAdjacency) && reachesAll(senderAdjacency');
end

function connected = reachesAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
connected = all(visited);
end

function gain = safeGain(reference, candidate)
gain = (reference - candidate) ./ max(abs(reference), eps);
end
