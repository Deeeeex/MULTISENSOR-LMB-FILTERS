function [nextState, decision] = ...
        preflightBudgetRecycledRepairSynopsisV188( ...
            previousState, admissionNetSavingBytes, ...
            lightSynopsisBytes, referencePageBytes)
% PREFLIGHTBUDGETRECYCLEDREPAIRSYNOPSISV188 Lock savings before control.
%
% The admission layer reports a nonnegative *net* attempted-byte saving
% relative to the matched full-posterior reference after its own control
% costs have been charged.  A fixed fraction of every newly earned byte is
% moved into a protected balance that can never be spent.  Only the
% remaining spendable balance may authorize the current light synopsis.
% This preflight runs before any synopsis is transmitted.

protocol = getBudgetRecycledFormationRepairV188Protocol();
previousState = normalizeState(previousState, protocol);
if ~validNonnegativeScalar(admissionNetSavingBytes) || ...
        ~validNonnegativeScalar(lightSynopsisBytes) || ...
        ~validNonnegativeScalar(referencePageBytes)
    error('BudgetRecycledRepairV188:InvalidCreditInput', ...
        'The admission saving, synopsis cost, or reference cost is invalid.');
end

reserveFraction = protocol.communicationCreditReserveFraction;
creditCapBytes = protocol.communicationCreditCapReferencePageFraction * ...
    referencePageBytes;
newProtectedSavingBytes = reserveFraction * admissionNetSavingBytes;
newSpendableCreditBytes = ...
    (1 - reserveFraction) * admissionNetSavingBytes;
uncappedSpendableCreditBytes = ...
    previousState.spendableCreditBytes + newSpendableCreditBytes;
capOverflowBytes = max(uncappedSpendableCreditBytes - creditCapBytes, 0);

nextState = previousState;
nextState.protectedSavingBytes = ...
    previousState.protectedSavingBytes + ...
    newProtectedSavingBytes + capOverflowBytes;
nextState.spendableCreditBytes = min( ...
    uncappedSpendableCreditBytes, creditCapBytes);
nextState.cumulativeAdmissionNetSavingBytes = ...
    previousState.cumulativeAdmissionNetSavingBytes + ...
    admissionNetSavingBytes;
nextState.pagesProcessed = previousState.pagesProcessed + 1;

authorized = lightSynopsisBytes <= ...
    nextState.spendableCreditBytes + 1e-9;
chargedSynopsisBytes = 0;
if authorized
    chargedSynopsisBytes = lightSynopsisBytes;
    nextState.spendableCreditBytes = ...
        nextState.spendableCreditBytes - chargedSynopsisBytes;
    nextState.cumulativeControlAndRepairSpendBytes = ...
        previousState.cumulativeControlAndRepairSpendBytes + ...
        chargedSynopsisBytes;
    nextState.synopsisPagesAuthorized = ...
        previousState.synopsisPagesAuthorized + 1;
end
nextState.certifiedCumulativeSavingBytes = ...
    nextState.protectedSavingBytes + nextState.spendableCreditBytes;
assertConservation( ...
    previousState, nextState, admissionNetSavingBytes, ...
    chargedSynopsisBytes);

decision = struct();
decision.contractVersion = ...
    'budget-recycled-repair-synopsis-preflight-v188-v1';
decision.admissionNetSavingBytes = admissionNetSavingBytes;
decision.newProtectedSavingBytes = newProtectedSavingBytes;
decision.newSpendableCreditBytes = newSpendableCreditBytes;
decision.creditCapBytes = creditCapBytes;
decision.capOverflowLockedBytes = capOverflowBytes;
decision.lightSynopsisBytes = lightSynopsisBytes;
decision.lightSynopsisAuthorized = authorized;
decision.chargedSynopsisBytes = chargedSynopsisBytes;
decision.certifiedCumulativeSavingBytes = ...
    nextState.certifiedCumulativeSavingBytes;
decision.cumulativeByteSafetyPassed = ...
    nextState.certifiedCumulativeSavingBytes >= -1e-9 && ...
    nextState.protectedSavingBytes >= ...
        previousState.protectedSavingBytes - 1e-9;
decision.fallbackReason = '';
if ~authorized
    decision.fallbackReason = 'insufficient-spendable-credit-for-synopsis';
end
decision.truthUsed = false;
decision.futureInformationUsed = false;
decision.modelMayOverridePreflight = false;
end

function state = normalizeState(state, protocol)
if isempty(state)
    state = struct( ...
        'contractVersion', protocol.creditLedgerContractVersion, ...
        'reserveFraction', ...
            protocol.communicationCreditReserveFraction, ...
        'spendableCreditBytes', 0, ...
        'protectedSavingBytes', 0, ...
        'cumulativeAdmissionNetSavingBytes', 0, ...
        'cumulativeControlAndRepairSpendBytes', 0, ...
        'certifiedCumulativeSavingBytes', 0, ...
        'pagesProcessed', 0, ...
        'synopsisPagesAuthorized', 0, ...
        'repairActionsAuthorized', 0);
    return;
end
required = { ...
    'contractVersion', 'reserveFraction', 'spendableCreditBytes', ...
    'protectedSavingBytes', 'cumulativeAdmissionNetSavingBytes', ...
    'cumulativeControlAndRepairSpendBytes', ...
    'certifiedCumulativeSavingBytes', 'pagesProcessed', ...
    'synopsisPagesAuthorized', 'repairActionsAuthorized'};
if ~isstruct(state) || any(~isfield(state, required)) || ...
        ~strcmp(state.contractVersion, protocol.creditLedgerContractVersion) || ...
        abs(state.reserveFraction - ...
            protocol.communicationCreditReserveFraction) > 1e-12
    error('BudgetRecycledRepairV188:CreditContractDrift', ...
        'The previous communication-credit state is incompatible.');
end
scalarFields = required(3:end);
for fieldIdx = 1:numel(scalarFields)
    value = state.(scalarFields{fieldIdx});
    if ~validNonnegativeScalar(value)
        error('BudgetRecycledRepairV188:InvalidPreviousCreditState', ...
            'The previous communication-credit state is malformed.');
    end
end
integerFields = {'pagesProcessed', 'synopsisPagesAuthorized', ...
    'repairActionsAuthorized'};
for fieldIdx = 1:numel(integerFields)
    value = state.(integerFields{fieldIdx});
    if value ~= round(value)
        error('BudgetRecycledRepairV188:InvalidPreviousCreditState', ...
            'Credit-ledger counters must be nonnegative integers.');
    end
end
if abs(state.certifiedCumulativeSavingBytes - ...
        (state.protectedSavingBytes + state.spendableCreditBytes)) > 1e-8 || ...
        abs(state.certifiedCumulativeSavingBytes - ...
        (state.cumulativeAdmissionNetSavingBytes - ...
        state.cumulativeControlAndRepairSpendBytes)) > 1e-8
    error('BudgetRecycledRepairV188:CreditConservationDrift', ...
        'The previous credit state does not conserve attempted bytes.');
end
end

function assertConservation(previous, next, earned, spent)
expected = previous.certifiedCumulativeSavingBytes + earned - spent;
if abs(next.certifiedCumulativeSavingBytes - expected) > 1e-8 || ...
        next.spendableCreditBytes < -1e-9 || ...
        next.protectedSavingBytes < previous.protectedSavingBytes - 1e-9
    error('BudgetRecycledRepairV188:InternalCreditViolation', ...
        'The synopsis preflight violated byte conservation.');
end
end

function valid = validNonnegativeScalar(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value >= 0;
end
