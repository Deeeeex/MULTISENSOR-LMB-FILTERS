function protocol = getCausalMinimalEditFormationTreeV240Protocol()
% GETCAUSALMINIMALEDITFORMATIONTREEV240PROTOCOL Dynamic formation routing.

source = getCorrectedStaticRoutingBaselineV227Protocol();
protocol = struct();
protocol.id = 'causal-minimal-edit-formation-tree-v240-v1';
protocol.contractVersion = ...
    'causal-minimal-edit-formation-tree-v240-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.armId = 'v240-causal-minimal-edit-formation-tree';
protocol.policyName = ...
    'causal-minimal-edit-formation-tree-v240-policy';
protocol.allowedPresets = { ...
    'm24-formation-fov-formation-braid', ...
    'm24-formation-fov-coupled-formation-braid', ...
    'x36-formation-fov-formation-braid', ...
    'x36-formation-fov-coupled-formation-braid', ...
    'x48-formation-fov-formation-braid', ...
    'x48-formation-fov-coupled-formation-braid'};
protocol.dominantWeight = source.dominantWeight;
protocol.residualWeight = source.residualWeight;
protocol.directedInputsPerReceiver = source.directedInputsPerReceiver;
protocol.maximumTreeEnumerationCount = 100000;
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V240 is a causal development policy for the exploratory formation-', ...
    'braid scene family. It preserves the preceding formation tree whenever ', ...
    'that tree remains physically feasible. On physical infeasibility ', ...
    'only, it selects a current spanning tree lexicographically by ', ...
    'minimum formation-edge replacement, maximum bottleneck reliability, ', ...
    'maximum total log reliability and minimum distance. It reads no ', ...
    'truth, future outcome or posterior payload. Every receiver retains ', ...
    'the V227 two-input KLA weight contract. Structural results do not ', ...
    'establish tracking gain or generalization.'];

if protocol.directedInputsPerReceiver ~= 2 || ...
        protocol.dominantWeight <= 0 || ...
        protocol.residualWeight <= 0 || ...
        protocol.dominantWeight + protocol.residualWeight >= 1
    error('CausalMinimalEditFormationTreeV240:InvalidProtocol', ...
        'The V240 matched routing contract is inconsistent.');
end
end
