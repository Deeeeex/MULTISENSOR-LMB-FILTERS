function [candidateAdjacency, candidateDetails, metadata] = ...
    buildDiverseLabelSetMessagePassingProposalBank( ...
        context, model, options)
% BUILDDIVERSELABELSETMESSAGEPASSINGPROPOSALBANK Safe GNN graph bank.
%
% The first proposal is the ordinary maximum-score label-set GNN graph.
% Later proposals repeatedly solve the same exact structural projection
% after subtracting a cumulative edge-reuse penalty.  The penalty exceeds
% the largest possible base-score difference between two feasible cycles,
% so every later solve first minimizes aggregate reuse of already selected
% cross-formation edges and then maximizes the original GNN score.
%
% No target truth, future measurement, future return, seed identifier or
% numeric label identifier is used.  Every admitted candidate preserves
% the fixed dominant backbone, the registered message count, the physical
% action set and the strong residual sensor cycle.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getField(options, 'protocol', ...
    getLabelSetSimulatorPolicyProtocol());
if ~protocol.messagePassingImplementationAuthorized || ...
        ~protocol.diverseGraphOptionImplementationAuthorized
    error('Diverse label-set graph proposals are not authorized.');
end
proposalCount = round(getField(options, 'proposalCount', ...
    protocol.diverseGraphOptionProposalCount));
if ~isscalar(proposalCount) || ~isfinite(proposalCount) || ...
        proposalCount < 1
    error('Diverse proposalCount must be a positive integer.');
end
expectedSelectedMessageCount = round(getField(options, ...
    'expectedSelectedMessageCount', ...
    protocol.diverseGraphOptionExpectedSelectedMessageCount));
if ~isscalar(expectedSelectedMessageCount) || ...
        ~isfinite(expectedSelectedMessageCount) || ...
        expectedSelectedMessageCount < 1
    error('Expected selected message count must be a positive integer.');
end
fixedResidualWeight = getField(options, ...
    'fixedResidualWeight', protocol.localResidualWeight);
block = computeLabelSetMessagePassingPolicyBlock( ...
    context, struct('protocol', protocol));
scoreOutput = scoreLabelSetMessagePassingPolicyModel( ...
    model, block);
weightIdx = find(abs(block.residualWeightGrid - ...
    fixedResidualWeight) <= 1e-12);
if numel(weightIdx) ~= 1
    error('Fixed diverse label-set residual weight is not registered.');
end
baseScores = reshape( ...
    scoreOutput.edgeTaskScore(:, weightIdx), [], 1);
candidateCount = numel(baseScores);
groupCount = numel(unique(context.model. ...
    dynamicTopologyScenario.config.sensorGroupIds));
scoreSpan = max(baseScores) - min(baseScores);
reusePenalty = groupCount * max(scoreSpan, 0) + 1;
reuseCount = zeros(candidateCount, 1);
candidateAdjacency = false( ...
    numel(context.localPosteriorBySensor), ...
    numel(context.localPosteriorBySensor), 0);
candidateDetails = cell(1, 0);
graphKeys = cell(1, 0);
selectedExampleIndices = cell(1, 0);
maximumRetryCount = max(256, ...
    proposalCount * candidateCount);

for proposalIdx = 1:proposalCount
    adjustedScores = baseScores - reusePenalty * reuseCount;
    banQueue = {false(candidateCount, 1)};
    seenBanKeys = {sprintf('%d,', false(candidateCount, 1))};
    accepted = false;
    retryCount = 0;
    while ~accepted && ~isempty(banQueue) && ...
            retryCount < maximumRetryCount
        retryCount = retryCount + 1;
        retryBanned = banQueue{1};
        banQueue(1) = [];
        projectedScores = adjustedScores;
        projectedScores(retryBanned) = -inf;
        policyOptions = struct( ...
            'dominantWeight', protocol.dominantWeight, ...
            'residualWeight', protocol.localResidualWeight, ...
            'edgeScoreFcn', @provideScores, ...
            'edgeScoreFcnReturnsDetails', true, ...
            'posteriorUsed', true, ...
            'truthUsed', false, ...
            'currentLinkReliabilityUsed', true);
        try
            [adjacency, details] = ...
                selectBackboneResidualSplicedCyclePolicy( ...
                    context, 'external-scores', policyOptions);
        catch errorInfo
            if proposalIdx == 1 || ...
                    ~isResidualCycleInfeasible(errorInfo)
                rethrow(errorInfo);
            end
            continue;
        end
        validateCandidate( ...
            context, adjacency, details, ...
            expectedSelectedMessageCount);
        graphKey = sprintf('%d,', adjacency(:));
        duplicateIdx = find(strcmp(graphKeys, graphKey), 1);
        examples = selectedExamples(details);
        if isempty(duplicateIdx)
            accepted = true;
            candidateIdx = size(candidateAdjacency, 3) + 1;
            candidateAdjacency(:, :, candidateIdx) = adjacency;
            details.mode = ...
                'diverse-label-set-message-passing-safe-residual-cycle';
            details.modelContractVersion = model.contractVersion;
            details.labelFeatureContractSha256 = ...
                block.labelFeatureContractSha256;
            details.aggregateFeatureContractSha256 = ...
                block.aggregateFeatureContractSha256;
            details.messagePassingRoundCount = ...
                protocol.messagePassingRoundCount;
            details.residualWeightMode = ...
                'fixed-registered-weight';
            details.fixedResidualWeight = fixedResidualWeight;
            details.numericLabelIdentifiersUsedAsFeatures = false;
            details.safeProjectorUsed = true;
            details.nominalGuaranteeScope = ...
                protocol.nominalGuaranteeScope;
            details.diverseProposalIndex = proposalIdx;
            details.diverseProposalCountRequested = proposalCount;
            details.diversityObjective = ...
                protocol.diverseGraphOptionObjective;
            details.diversityReusePenalty = reusePenalty;
            details.diversityScoreSpan = scoreSpan;
            details.diversityRetryCount = retryCount - 1;
            details.diversityBaseEdgeScores = baseScores;
            details.diversityAdjustedEdgeScores = ...
                adjustedScores;
            details.diversityEdgeReuseCountBefore = reuseCount;
            details.diversitySelectedExampleIndices = examples;
            details.graphSha256 = computeTextSha256(graphKey);
            details.truthUsed = false;
            details.groundTruthUsed = false;
            details.futureOutcomeUsed = false;
            candidateDetails{candidateIdx} = details;
            graphKeys{candidateIdx} = graphKey;
            selectedExampleIndices{candidateIdx} = examples;
            reuseCount(examples) = reuseCount(examples) + 1;
        else
            duplicateExamples = selectedExampleIndices{duplicateIdx};
            banCandidates = duplicateExamples( ...
                ~retryBanned(duplicateExamples));
            banTable = [ ...
                -reuseCount(banCandidates), ...
                baseScores(banCandidates), ...
                reshape(banCandidates, [], 1)];
            [~, banOrder] = sortrows(banTable, [1, 2, 3]);
            for banCursor = reshape(banOrder, 1, [])
                childBan = retryBanned;
                childBan(banCandidates(banCursor)) = true;
                banKey = sprintf('%d,', childBan);
                if ~any(strcmp(seenBanKeys, banKey))
                    seenBanKeys{end + 1} = banKey; %#ok<AGROW>
                    banQueue{end + 1} = childBan; %#ok<AGROW>
                end
            end
        end
    end
    if ~accepted
        break;
    end
end

distinctCount = size(candidateAdjacency, 3);
if distinctCount < proposalCount
    error('ResidualCycle:Infeasible', [ ...
        'Only %d/%d distinct safe diverse label-set proposals exist.'], ...
        distinctCount, proposalCount);
end
crossJaccard = eye(distinctCount);
for leftIdx = 1:distinctCount
    left = selectedExampleIndices{leftIdx};
    for rightIdx = (leftIdx + 1):distinctCount
        right = selectedExampleIndices{rightIdx};
        overlap = numel(intersect(left, right));
        unionCount = numel(union(left, right));
        crossJaccard(leftIdx, rightIdx) = overlap / unionCount;
        crossJaccard(rightIdx, leftIdx) = ...
            crossJaccard(leftIdx, rightIdx);
    end
end
offDiagonal = crossJaccard(~eye(distinctCount));
if isempty(offDiagonal)
    maximumPairwiseCrossEdgeJaccard = 0;
    meanPairwiseCrossEdgeJaccard = 0;
else
    maximumPairwiseCrossEdgeJaccard = max(offDiagonal);
    meanPairwiseCrossEdgeJaccard = mean(offDiagonal);
end
metadata = struct();
metadata.contractVersion = ...
    protocol.diverseGraphOptionContractVersion;
metadata.proposalCount = distinctCount;
metadata.requestedProposalCount = proposalCount;
metadata.expectedSelectedMessageCount = ...
    expectedSelectedMessageCount;
metadata.fixedResidualWeight = fixedResidualWeight;
metadata.baseScoreSpan = scoreSpan;
metadata.reusePenalty = reusePenalty;
metadata.diversityObjective = ...
    protocol.diverseGraphOptionObjective;
metadata.graphSha256 = cellfun(@(details) ...
    details.graphSha256, candidateDetails, ...
    'UniformOutput', false);
metadata.selectedExampleIndices = selectedExampleIndices;
metadata.crossEdgeJaccard = crossJaccard;
metadata.maximumPairwiseCrossEdgeJaccard = ...
    maximumPairwiseCrossEdgeJaccard;
metadata.meanPairwiseCrossEdgeJaccard = ...
    meanPairwiseCrossEdgeJaccard;
metadata.finalEdgeReuseCount = reuseCount;
metadata.allCandidatesDistinct = ...
    numel(unique(metadata.graphSha256)) == distinctCount;
metadata.allCandidatesTruthFree = ...
    all(cellfun(@(details) ~details.truthUsed, candidateDetails));
metadata.allCandidatesSafe = ...
    all(cellfun(@candidateSafe, candidateDetails));
metadata.candidatePermutationEquivariantScores = ...
    scoreOutput.candidatePermutationEquivariant;
metadata.permutationInvariantLabelPooling = ...
    scoreOutput.permutationInvariantLabelPooling;
metadata.numericLabelIdentifiersUsedAsFeatures = false;
metadata.truthUsed = false;
metadata.futureOutcomeUsed = false;

    function [edgeScores, scoreDetails] = provideScores( ...
            ~, receiverIndices, senderIndices, ~)
        if ~isequal(reshape(receiverIndices, [], 1), ...
                reshape(block.receiverIndices, [], 1)) || ...
                ~isequal(reshape(senderIndices, [], 1), ...
                reshape(block.senderIndices, [], 1))
            error('Safe projector candidate order changed.');
        end
        edgeScores = projectedScores;
        scoreDetails = struct( ...
            'selectedResidualWeightByExample', ...
                fixedResidualWeight * ...
                    ones(candidateCount, 1), ...
            'posteriorUsed', true, ...
            'truthUsed', false, ...
            'groundTruthUsed', false, ...
            'futureOutcomeUsed', false, ...
            'currentLinkReliabilityUsed', true, ...
            'numericLabelIdentifiersUsedAsFeatures', false, ...
            'modelContractVersion', model.contractVersion, ...
            'receiverIndices', block.receiverIndices, ...
            'senderIndices', block.senderIndices);
    end
end

function examples = selectedExamples(details)
receivers = reshape( ...
    details.spliceSelection.crossReceivers, [], 1);
senders = reshape( ...
    details.spliceSelection.crossSenders, [], 1);
blockReceivers = reshape( ...
    details.scoreDetails.receiverIndices, [], 1);
blockSenders = reshape( ...
    details.scoreDetails.senderIndices, [], 1);
examples = zeros(numel(receivers), 1);
for edgeIdx = 1:numel(receivers)
    match = find(blockReceivers == receivers(edgeIdx) & ...
        blockSenders == senders(edgeIdx));
    if numel(match) ~= 1
        error('Projected cross edge is absent from the score block.');
    end
    examples(edgeIdx) = match;
end
examples = reshape(examples, [], 1);
end

function validateCandidate( ...
        context, adjacency, details, expectedSelectedMessageCount)
if details.truthUsed || ...
        details.crossFormationMessageCount ~= ...
            numel(unique(context.model.dynamicTopologyScenario. ...
                config.sensorGroupIds)) || ...
        nnz(adjacency) ~= expectedSelectedMessageCount || ...
        nnz(adjacency) ~= nnz(details.baselineAdjacency) || ...
        any(adjacency(:) & ...
            ~logical(context.physicalAdjacency(:))) || ...
        ~details.sensorWindowStrongConnected || ...
        ~details.formationWindowStrongConnected || ...
        details.repairTriggered || ...
        details.payloadEmergencyUsed || ...
        details.topologyInfeasible
    error('Diverse label-set safe projection contract failed.');
end
end

function value = candidateSafe(details)
value = ~details.truthUsed && ...
    details.sensorWindowStrongConnected && ...
    details.formationWindowStrongConnected && ...
    ~details.repairTriggered && ...
    ~details.payloadEmergencyUsed && ...
    ~details.topologyInfeasible;
end

function value = isResidualCycleInfeasible(errorInfo)
value = strcmp(errorInfo.identifier, 'ResidualCycle:Infeasible') || ...
    ~isempty(strfind(lower(errorInfo.message), ...
        'residual splice')); %#ok<STREMP>
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
