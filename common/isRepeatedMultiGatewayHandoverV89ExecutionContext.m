function detected = ...
    isRepeatedMultiGatewayHandoverV89ExecutionContext(context)
% ISREPEATEDMULTIGATEWAYHANDOVERV89EXECUTIONCONTEXT Identify V89 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'repeated-multi-gateway-handover-v89-full-episode-context-v1');
end
