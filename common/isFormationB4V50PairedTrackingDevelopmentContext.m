function detected = ...
    isFormationB4V50PairedTrackingDevelopmentContext(context)
% ISFORMATIONB4V50PAIREDTRACKINGDEVELOPMENTCONTEXT Detect V50 execution.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'formation-b4-v50-paired-tracking-development-context-v1');
end
