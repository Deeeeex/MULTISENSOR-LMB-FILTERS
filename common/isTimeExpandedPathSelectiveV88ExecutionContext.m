    isTimeExpandedPathSelectiveV88ExecutionContext(context)
% ISTIMEEXPANDEDPATHSELECTIVEV88EXECUTIONCONTEXT Identify V88 requests.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'time-expanded-path-selective-primary-h3-v88-context-v1');
end
