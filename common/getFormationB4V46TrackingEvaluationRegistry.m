function matrix = buildCaseOrdinalMatrix(source, seeds, sceneOrdinals)
matrix = zeros(numel(seeds), numel(sceneOrdinals));
for seedIdx = 1:numel(seeds)
    for sceneIdx = 1:numel(sceneOrdinals)
        match = find([source.cases.seed] == seeds(seedIdx) & ...
            [source.cases.sceneOrdinal] == sceneOrdinals(sceneIdx));
        if numel(match) ~= 1
            error('FormationB4V46TrackingEvaluation:CaseGrouping', ...
                'A confirmation seed/scene pair is missing or duplicated.');
        end
        matrix(seedIdx, sceneIdx) = source.cases(match).ordinal;
    end
end
end

function ordinals = selectCaseOrdinals(source, seed, primary)
matchesSeed = [source.cases.seed] == seed;
if primary
    matchesMatrix = [source.cases.primaryMatrix];
else
    matchesMatrix = [source.cases.stressMatrix];
end
ordinals = [source.cases(matchesSeed & matchesMatrix).ordinal];
end

function cases = buildCases(source)
template = struct( ...
    'caseOrdinal', NaN, 'caseId', '', ...
    'coreCaseCanonicalSha256', '', 'sceneOrdinal', NaN, ...
    'sceneId', '', 'presetName', '', 'scale', NaN, 'style', '', ...
    'seed', NaN, 'seedRole', '', 'primaryMatrix', false, ...
    'stressMatrix', false, 'simulationLength', NaN, ...
    'focusWindow', zeros(1, 0), ...
    'positionOspaParameters', struct());
cases = repmat(template, 1, source.caseCount);
for caseIdx = 1:source.caseCount
    contract = source.cases(caseIdx);
    scene = source.scenes(contract.sceneOrdinal);
    config = buildDynamicTopologyScenarioConfig(contract.presetName);
    if ~strcmp(computeCanonicalValueSha256(config), ...
            contract.configSnapshotSha256) || ...
            ~isfield(config, 'ospaPositionCutoff') || ...
            ~isa(config.ospaPositionCutoff, 'double') || ...
            ~isreal(config.ospaPositionCutoff) || ...
            ~isscalar(config.ospaPositionCutoff) || ...
            ~isfinite(config.ospaPositionCutoff) || ...
            config.ospaPositionCutoff <= 0 || ...
            numel(contract.focusWindow) ~= 2 || ...
            any(contract.focusWindow ~= floor(contract.focusWindow)) || ...
            contract.focusWindow(1) < 1 || ...
            contract.focusWindow(2) > contract.simulationLength || ...
            contract.focusWindow(1) > contract.focusWindow(2)
        error('FormationB4V46TrackingEvaluation:CaseDrift', ...
            'The registered evaluation config changed for case %d.', ...
            contract.ordinal);
    end
    value = template;
    value.caseOrdinal = contract.ordinal;
    value.caseId = contract.id;
    value.coreCaseCanonicalSha256 = contract.caseCanonicalSha256;
    value.sceneOrdinal = contract.sceneOrdinal;
    value.sceneId = contract.sceneId;
    value.presetName = contract.presetName;
    value.scale = scene.scale;
    value.style = scene.style;
    value.seed = contract.seed;
    value.seedRole = contract.seedRole;
    value.primaryMatrix = contract.primaryMatrix;
    value.stressMatrix = contract.stressMatrix;
    value.simulationLength = contract.simulationLength;
    value.focusWindow = contract.focusWindow;
    value.positionOspaParameters = struct( ...
        'cutoffMetres', config.ospaPositionCutoff, ...
        'order', 2.0, 'positionStateIndices', [1.0, 2.0]);
    cases(caseIdx) = value;
end
end
