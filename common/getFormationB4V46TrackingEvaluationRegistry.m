function digest = requireFunctionSha256(functionName, expectedSha256)
path = which(functionName);
if isempty(path)
    error('FormationB4V46TrackingEvaluation:MissingFunction', ...
        'The frozen function is not on the path: %s.', functionName);
end
digest = computeFileSha256(path);
if ~strcmp(digest, expectedSha256)
    error('FormationB4V46TrackingEvaluation:FunctionDrift', ...
        'The frozen function changed: %s.', functionName);
end
end

