function [features, featureNames, metadata] = ...
    computeFormationH3ActionFeatures(context, bank, groupIds)
% COMPUTEFORMATIONH3ACTIONFEATURES Invariant observable action features.
%
% One row describes the reference, singleton, or conservative-pair action.
% Sensor indices, formation identifiers, seed identifiers, truth, and future
% outcomes are not retained.  Changed receivers and their dominant sources
% are pooled so the same feature contract applies to D12, M24, and X36.

requiredBank = { ...
    'nodeCount', 'formationCount', 'actionCount', ...
    'referenceActionIndex', 'modeTrustWeights', 'actionModes', ...
    'actionModeIndex', 'actionAdjacency', 'actionFusionWeights', ...
    'actionDominantSources', 'actionPosteriorProxyAllowed', ...
    'actionPosteriorObjective', 'actionPayloadBytes', ...
    'referencePayloadBytes', 'truthUsed', 'futureOutcomeUsed'};
if ~isstruct(context) || ~isstruct(bank) || ...
        ~all(isfield(bank, requiredBank)) || ...
        bank.truthUsed || bank.futureOutcomeUsed
    error('Formation H=3 action-feature input is incomplete.');
end
groupIds = reshape(groupIds, 1, []);
nodeCount = numel(groupIds);
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
if nodeCount ~= bank.nodeCount || ...
        formationCount ~= bank.formationCount || ...
        ~isequal(size(bank.actionModes), ...
            [bank.actionCount, formationCount]) || ...
        ~isequal(size(bank.actionAdjacency), ...
            [nodeCount, nodeCount, bank.actionCount]) || ...
        ~isequal(size(bank.actionFusionWeights), ...
            [nodeCount, nodeCount, bank.actionCount]) || ...
        ~isequal(size(bank.actionDominantSources), ...
            [bank.actionCount, nodeCount]) || ...
        bank.referenceActionIndex ~= 1
    error('Formation H=3 action-feature dimensions are invalid.');
end
assertObservableContext(context, nodeCount, groupIds);

[raw, rawNames, nodeSummary] = ...
    computeDirectedRoutingFeatures(context);
semanticNames = { ...
    'link_reliability', ...
    'normalized_sensor_distance', ...
    'source_expected_cardinality', ...
    'receiver_expected_cardinality', ...
    'source_cardinality_variance', ...
    'receiver_cardinality_variance', ...
    'source_position_variance', ...
    'receiver_position_variance', ...
    'source_association_confidence', ...
    'receiver_association_confidence', ...
    'positive_existence_gain', ...
    'negative_existence_gap', ...
    'positive_precision_gain', ...
    'negative_precision_gap', ...
    'normalized_state_discrepancy', ...
    'active_label_overlap', ...
    'node_quality_advantage', ...
    'receiver_need'};
semanticIndices = nameIndices(rawNames, semanticNames);
targetCapacity = max(resolveTargetCapacity(context.model), 1);
cardinalitySemanticMask = ismember(semanticNames, { ...
    'source_expected_cardinality', ...
    'receiver_expected_cardinality', ...
    'source_cardinality_variance', ...
    'receiver_cardinality_variance'});
tailSemanticNames = { ...
    'link_reliability', ...
    'normalized_sensor_distance', ...
    'negative_existence_gap', ...
    'negative_precision_gap', ...
    'normalized_state_discrepancy', ...
    'active_label_overlap', ...
    'node_quality_advantage', ...
    'receiver_need'};
tailSemanticIndices = nameIndices( ...
    semanticNames, tailSemanticNames);
tailDirections = [-1, 1, 1, 1, 1, -1, -1, 1];
nodeNames = { ...
    'expected_cardinality_fraction', ...
    'cardinality_variance_fraction', ...
    'position_variance', ...
    'association_confidence', ...
    'detection_mass', ...
    'active_label_fraction', ...
    'quality', 'need'};

metaNames = { ...
    'bias', 'log_node_count', 'log_formation_count', ...
    'mean_formation_size_fraction', ...
    'action_formation_fraction', 'action_order_fraction', ...
    'trust_weight', 'trust_weight_squared', ...
    'predicted_payload_saving_fraction', ...
    'asinh_posterior_proxy_objective_per_formation', ...
    'posterior_proxy_allowed', ...
    'dominant_source_change_fraction', ...
    'row_edge_change_fraction', 'row_edge_saving_fraction', ...
    'row_weight_l1_mean', ...
    'candidate_previous_edge_overlap', ...
    'reference_previous_edge_overlap', ...
    'previous_overlap_delta', ...
    'changed_pair_direct_physical_fraction', ...
    'changed_pair_link_reliability_mean'};
featureNames = [ ...
    metaNames, ...
    prefixNames(semanticNames, 'candidate_mean_'), ...
    prefixNames(semanticNames, 'reference_mean_'), ...
    prefixNames(semanticNames, ...
        'candidate_minus_reference_mean_'), ...
    prefixNames(tailSemanticNames, 'candidate_tail_'), ...
    prefixNames(tailSemanticNames, ...
        'candidate_minus_reference_tail_'), ...
    prefixNames(nodeNames, 'changed_receiver_mean_'), ...
    prefixNames(nodeNames, 'changed_receiver_max_')];
features = zeros(bank.actionCount, numel(featureNames));

referenceAdjacency = logical(bank.actionAdjacency(:, :, 1));
referenceWeights = bank.actionFusionWeights(:, :, 1);
referenceSources = bank.actionDominantSources(1, :);
physical = logical(context.physicalAdjacency);
previous = logical(context.previousAdjacency);
reliability = reshape(raw(:, :, nameIndices( ...
    rawNames, {'link_reliability'})), nodeCount, nodeCount);
formationSizes = arrayfun(@(group) ...
    nnz(groupIds == group), groups);
for actionIdx = 1:bank.actionCount
    actionModes = bank.actionModes(actionIdx, :);
    changedFormationMask = actionModes ~= ...
        bank.actionModes(1, :);
    changedFormationIndices = find(changedFormationMask);
    actionOrder = numel(changedFormationIndices);
    if actionOrder == 0
        receivers = 1:nodeCount;
    else
        receivers = find(ismember( ...
            groupIds, groups(changedFormationIndices)));
    end
    actionAdjacency = logical( ...
        bank.actionAdjacency(:, :, actionIdx));
    actionWeights = bank.actionFusionWeights(:, :, actionIdx);
    actionSources = bank.actionDominantSources(actionIdx, :);
    candidateRows = semanticEdgeRows( ...
        raw, semanticIndices, receivers, ...
        actionSources(receivers), targetCapacity, ...
        cardinalitySemanticMask);
    referenceRows = semanticEdgeRows( ...
        raw, semanticIndices, receivers, ...
        referenceSources(receivers), targetCapacity, ...
        cardinalitySemanticMask);
    candidateMean = mean(candidateRows, 1);
    referenceMean = mean(referenceRows, 1);
    candidateTail = directedTails( ...
        candidateRows(:, tailSemanticIndices), tailDirections);
    referenceTail = directedTails( ...
        referenceRows(:, tailSemanticIndices), tailDirections);
    nodeRows = nodeSummaryRows( ...
        nodeSummary(receivers), targetCapacity);

    actionRows = actionAdjacency(receivers, :);
    referenceRowsMask = referenceAdjacency(receivers, :);
    physicalRows = physical(receivers, :);
    diagonalMask = false(size(actionRows));
    for receiverCursor = 1:numel(receivers)
        diagonalMask(receiverCursor, receivers(receiverCursor)) = true;
    end
    actionRows(diagonalMask) = false;
    referenceRowsMask(diagonalMask) = false;
    physicalRows(diagonalMask) = false;
    rowDenominator = max(nnz(physicalRows), 1);
    previousRows = previous(receivers, :);
    previousRows(diagonalMask) = false;
    candidatePreviousOverlap = overlapFraction( ...
        actionRows, previousRows);
    referencePreviousOverlap = overlapFraction( ...
        referenceRowsMask, previousRows);
    weightDifference = actionWeights(receivers, :) - ...
        referenceWeights(receivers, :);
    trustWeight = bank.modeTrustWeights( ...
        bank.actionModeIndex(actionIdx));
    if actionOrder > 0
        objectivePerFormation = ...
            bank.actionPosteriorObjective(actionIdx) / actionOrder;
    else
        objectivePerFormation = 0;
    end
    [pairPhysicalFraction, pairReliabilityMean] = ...
        changedPairFeatures(changedFormationIndices, groups, ...
            groupIds, physical, reliability);
    meta = [ ...
        1, log1p(nodeCount), log1p(formationCount), ...
        mean(formationSizes) / nodeCount, ...
        sum(formationSizes(changedFormationMask)) / nodeCount, ...
        actionOrder / 2, trustWeight, trustWeight^2, ...
        (bank.referencePayloadBytes - ...
            bank.actionPayloadBytes(actionIdx)) / ...
                max(bank.referencePayloadBytes, eps), ...
        asinh(objectivePerFormation), ...
        double(bank.actionPosteriorProxyAllowed(actionIdx)), ...
        mean(actionSources(receivers) ~= ...
            referenceSources(receivers)), ...
        nnz(xor(actionRows, referenceRowsMask)) / rowDenominator, ...
        (nnz(referenceRowsMask) - nnz(actionRows)) / rowDenominator, ...
        sum(abs(weightDifference(:))) / max(numel(receivers), 1), ...
        candidatePreviousOverlap, referencePreviousOverlap, ...
        candidatePreviousOverlap - referencePreviousOverlap, ...
        pairPhysicalFraction, pairReliabilityMean];
    row = [ ...
        meta, candidateMean, referenceMean, ...
        candidateMean - referenceMean, ...
        candidateTail, candidateTail - referenceTail, ...
        mean(nodeRows, 1), max(nodeRows, [], 1)];
    if numel(row) ~= numel(featureNames) || ...
            any(~isfinite(row))
        error('Formation H=3 action features are non-finite or misaligned.');
    end
    features(actionIdx, :) = row;
end

metadata = struct();
metadata.contractVersion = ...
    'formation-h3-observable-action-features-v1';
metadata.featureNames = featureNames;
metadata.featureCount = numel(featureNames);
metadata.nodeCount = nodeCount;
metadata.formationCount = formationCount;
metadata.actionCount = bank.actionCount;
metadata.targetCapacity = targetCapacity;
metadata.sensorPermutationInvariant = true;
metadata.formationLabelPermutationInvariant = true;
metadata.scaleNormalizedCardinality = true;
metadata.truthUsed = false;
metadata.futureMeasurementsUsed = false;
metadata.futureOutcomeUsed = false;
metadata.seedIdentifierUsed = false;
metadata.formationIdentifierUsed = false;
end

function assertObservableContext(context, nodeCount, groupIds)
required = { ...
    'localPosteriorBySensor', 'model', 'commConfig', ...
    'currentTime', 'previousAdjacency', ...
    'previousAdjacencyHistory', 'physicalAdjacency', 'positions'};
if ~all(isfield(context, required)) || ...
        numel(context.localPosteriorBySensor) ~= nodeCount || ...
        ~isequal(size(context.previousAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        size(context.positions, 2) ~= nodeCount || ...
        isfield(context.commConfig, 'linkUniforms') || ...
        (isfield(context.commConfig, 'pDropByEdge') && ...
         ndims(context.commConfig.pDropByEdge) >= 3) || ...
        isfield(context.model, 'explicitTargetTrajectories') || ...
        (isfield(context.model, 'dynamicTopologyScenario') && ...
         isfield(context.model.dynamicTopologyScenario, ...
            'targetTrajectories'))
    error('Formation H=3 feature context exposes invalid information.');
end
if isfield(context.model, 'dynamicTopologyScenario') && ...
        isfield(context.model.dynamicTopologyScenario, 'config') && ...
        isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds')
    configured = reshape(context.model.dynamicTopologyScenario. ...
        config.sensorGroupIds, 1, []);
    if ~isequal(configured, groupIds)
        error('Formation H=3 feature group assignments differ.');
    end
end
end

function rows = semanticEdgeRows( ...
        raw, semanticIndices, receivers, sources, ...
        targetCapacity, cardinalityMask)
rows = zeros(numel(receivers), numel(semanticIndices));
for rowIdx = 1:numel(receivers)
    rows(rowIdx, :) = reshape(raw( ...
        receivers(rowIdx), sources(rowIdx), semanticIndices), 1, []);
end
rows(:, cardinalityMask) = ...
    rows(:, cardinalityMask) / targetCapacity;
if any(~isfinite(rows(:)))
    error('Formation H=3 dominant-source feature is unavailable.');
end
end

function tails = directedTails(values, directions)
tails = zeros(1, size(values, 2));
for featureIdx = 1:size(values, 2)
    if directions(featureIdx) < 0
        tails(featureIdx) = min(values(:, featureIdx));
    else
        tails(featureIdx) = max(values(:, featureIdx));
    end
end
end

function rows = nodeSummaryRows(summaries, targetCapacity)
rows = zeros(numel(summaries), 8);
for nodeIdx = 1:numel(summaries)
    item = summaries(nodeIdx);
    rows(nodeIdx, :) = [ ...
        item.expectedCardinality / targetCapacity, ...
        item.cardinalityVariance / targetCapacity, ...
        item.positionVariance, item.associationConfidence, ...
        item.detectionMass, item.activeLabelCount / targetCapacity, ...
        item.quality, item.need];
end
end

function fraction = overlapFraction(selected, previous)
selectedCount = nnz(selected);
if selectedCount == 0
    fraction = 0;
else
    fraction = nnz(selected & previous) / selectedCount;
end
end

function [fraction, reliabilityMean] = changedPairFeatures( ...
        changedFormationIndices, groups, groupIds, physical, reliability)
fraction = 0;
reliabilityMean = 0;
if numel(changedFormationIndices) ~= 2
    return;
end
first = groupIds == groups(changedFormationIndices(1));
second = groupIds == groups(changedFormationIndices(2));
mask = false(size(physical));
mask(first, second) = true;
mask(second, first) = true;
possible = nnz(mask);
selected = mask & physical;
fraction = nnz(selected) / max(possible, 1);
values = reliability(selected);
if ~isempty(values)
    reliabilityMean = mean(values);
end
end

function indices = nameIndices(names, requested)
indices = zeros(1, numel(requested));
for idx = 1:numel(requested)
    match = find(strcmp(names, requested{idx}));
    if numel(match) ~= 1
        error('Missing or ambiguous feature: %s', requested{idx});
    end
    indices(idx) = match;
end
end

function names = prefixNames(base, prefix)
names = cell(size(base));
for idx = 1:numel(base)
    names{idx} = [prefix, base{idx}];
end
end

function count = resolveTargetCapacity(model)
count = 0;
if isfield(model, 'dynamicTopologyScenario') && ...
        isfield(model.dynamicTopologyScenario, 'config') && ...
        isfield(model.dynamicTopologyScenario.config, 'numberOfTargets')
    count = model.dynamicTopologyScenario.config.numberOfTargets;
elseif isfield(model, 'birthTimeByLocation')
    count = numel(model.birthTimeByLocation);
elseif isfield(model, 'birthParameters')
    count = numel(model.birthParameters);
end
if ~isscalar(count) || ~isfinite(count) || count < 1
    count = 1;
end
end
