function [adjacency, details] = ...
    selectRollingSafeDiverseTeacherPolicy( ...
        context, alternativeIndex, options)
% SELECTROLLINGSAFEDIVERSETEACHERPOLICY Nearby safe teacher action.
%
% The default current-risk teacher is solved once. Alternative k forbids
% the k-th selected cross-formation edge, ordered from the smallest to the
% largest teacher-score contribution, and resolves the exact joint
% current/successor rolling-B3 projection with all other constraints
% unchanged. The expensive labelled edge scores are replayed, not
% recomputed.
%
% This is a privileged action-space diagnostic. It reads truth through the
% default teacher score and cannot be used as a deployable strategy.

if nargin < 3 || isempty(options)
    options = struct();
end
alternativeIndex = round(alternativeIndex);
if ~isscalar(alternativeIndex) || ...
        ~isfinite(alternativeIndex) || alternativeIndex < 1
    error('Diverse teacher alternativeIndex must be a positive integer.');
end
sourceWeight = getField(options, 'sourceWeight', 0.70);
scoreOptions = getField(options, 'scoreOptions', struct());
scoreOptions.sourceWeight = sourceWeight;
basePolicyOptions = struct( ...
    'sourceWeight', sourceWeight, ...
    'payloadToleranceFraction', getField( ...
        options, 'payloadToleranceFraction', inf), ...
    'edgeScoreFcnReturnsDetails', true, ...
    'edgeScoreFcn', ...
        @(scoreContext, receiverIndices, ...
            senderIndices, cycleSources) ...
            computeRollingSafeTaskTeacherEdgeScores( ...
                scoreContext, receiverIndices, ...
                senderIndices, cycleSources, scoreOptions), ...
    'posteriorUsed', true, ...
    'truthUsed', true, ...
    'currentLinkReliabilityUsed', true, ...
    'teacherRequestedHorizonSteps', getField( ...
        scoreOptions, 'horizonSteps', 0));
hasCachedAdjacency = isfield(options, ...
    'cachedDefaultAdjacency');
hasCachedDetails = isfield(options, ...
    'cachedDefaultDetails');
if xor(hasCachedAdjacency, hasCachedDetails)
    error(['cachedDefaultAdjacency and cachedDefaultDetails must be ', ...
        'provided together.']);
end
if hasCachedAdjacency
    defaultAdjacency = ...
        options.cachedDefaultAdjacency;
    defaultDetails = options.cachedDefaultDetails;
    nodeCount = numel(context.localPosteriorBySensor);
    if ~isequal(size(defaultAdjacency), ...
            [nodeCount, nodeCount]) || ...
            ~islogical(defaultAdjacency) || ...
            any(sum(defaultAdjacency, 2) ~= 1)
        error('Cached diverse-teacher default graph is invalid.');
    end
    defaultReused = true;
else
    [defaultAdjacency, defaultDetails] = ...
        selectRollingSafeRoutingPolicy( ...
            context, 'external-scores', basePolicyOptions);
    defaultReused = false;
end

scoreDetails = requireTeacherScoreDetails(defaultDetails);
selectedExamples = reshape( ...
    defaultDetails.selectedCrossExampleIndices, 1, []);
selectedScores = reshape( ...
    scoreDetails.residualScores(selectedExamples), 1, []);
[~, order] = sort(selectedScores, 'ascend');
orderedExamples = selectedExamples(order);
if alternativeIndex > numel(orderedExamples)
    error(['Diverse teacher requested alternative %d, but the default ', ...
        'projection selected only %d cross-formation edges.'], ...
        alternativeIndex, numel(orderedExamples));
end

bannedExample = orderedExamples(alternativeIndex);
allowedMask = true(numel(scoreDetails.residualScores), 1);
allowedMask(bannedExample) = false;
replayOptions = basePolicyOptions;
replayOptions.currentAllowedExampleMask = allowedMask;
replayOptions.edgeScoreFcn = ...
    @(unusedContext, receiverIndices, senderIndices, ...
        unusedCycleSources) replayTeacherScores( ...
            receiverIndices, senderIndices, scoreDetails);

alternativeFeasible = true;
try
    [adjacency, details] = ...
        selectRollingSafeRoutingPolicy( ...
            context, 'external-scores', replayOptions);
catch errorInfo
    if ~isProjectionInfeasible(errorInfo)
        rethrow(errorInfo);
    end
    adjacency = defaultAdjacency;
    details = defaultDetails;
    alternativeFeasible = false;
end

details.diverseTeacherAlternativeRequested = alternativeIndex;
details.diverseTeacherAlternativeFeasible = alternativeFeasible;
details.diverseTeacherBannedExampleIndex = bannedExample;
details.diverseTeacherBannedReceiver = ...
    scoreDetails.receiverIndices(bannedExample);
details.diverseTeacherBannedSender = ...
    scoreDetails.senderIndices(bannedExample);
details.diverseTeacherDefaultSelectedSources = ...
    defaultDetails.selectedSourcesByReceiver;
details.diverseTeacherDefaultSelectedCrossExampleIndices = ...
    selectedExamples;
details.diverseTeacherChangedAction = ...
    ~isequal(adjacency, defaultAdjacency);
details.diverseTeacherScoreReuse = true;
details.diverseTeacherDefaultReused = defaultReused;
end

function scoreDetails = requireTeacherScoreDetails(details)
if ~isfield(details, 'scoreDetails') || ...
        ~isstruct(details.scoreDetails) || ...
        ~isfield(details.scoreDetails, 'injectedScoreDetails')
    error('Diverse teacher could not recover injected score details.');
end
scoreDetails = details.scoreDetails.injectedScoreDetails;
required = {'receiverIndices', 'senderIndices', 'residualScores'};
for fieldIdx = 1:numel(required)
    if ~isfield(scoreDetails, required{fieldIdx})
        error('Diverse teacher score details lack %s.', ...
            required{fieldIdx});
    end
end
end

function [scores, details] = replayTeacherScores( ...
        receiverIndices, senderIndices, cachedDetails)
if ~isequal(reshape(receiverIndices, [], 1), ...
        reshape(cachedDetails.receiverIndices, [], 1)) || ...
        ~isequal(reshape(senderIndices, [], 1), ...
        reshape(cachedDetails.senderIndices, [], 1))
    error('Diverse teacher cached scores do not match the action set.');
end
scores = reshape(cachedDetails.residualScores, [], 1);
details = cachedDetails;
details.replayedWithoutTruthRecomputation = true;
end

function infeasible = isProjectionInfeasible(errorInfo)
infeasible = strcmp(errorInfo.identifier, ...
    'RollingMatching:Infeasible') || ...
    ~isempty(strfind(lower(errorInfo.message), 'infeasible'));
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
