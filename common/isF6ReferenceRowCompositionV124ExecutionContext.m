function detected = isF6ReferenceRowCompositionV124ExecutionContext(context)
% ISF6REFERENCEROWCOMPOSITIONV124EXECUTIONCONTEXT Identify V124.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'f6-reference-row-composition-v124-context-v1');
end
