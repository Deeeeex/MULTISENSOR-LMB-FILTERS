function protocol = getSafeGraphOptionDwellV154Protocol()
% GETSAFEGRAPHOPTIONDWELLV154PROTOCOL Frozen graph-option headroom gate.

generator = getSafeGraphCodebookOracleV152Protocol();
pareto = getSafeGraphParetoOracleV153Protocol();

protocol = struct();
protocol.id = 'propagation-coherent-safe-graph-options-v154';
protocol.contractVersion = 'safe-graph-option-dwell-v154-v1';
protocol.evidenceSplit = generator.evidenceSplit;
protocol.presetNames = generator.presetNames;
protocol.nodeCounts = generator.nodeCounts;
protocol.formationCounts = generator.formationCounts;
protocol.sensorsPerFormation = generator.sensorsPerFormation;
protocol.openedDevelopmentSeeds = generator.openedDevelopmentSeeds;
protocol.pilotSeeds = generator.pilotSeeds;
protocol.anchorTimes = generator.anchorTimes;
protocol.horizon = generator.horizon;
protocol.filterSeedOffset = generator.filterSeedOffset;
protocol.staticArmModes = generator.staticArmModes;
protocol.optionArmPrefix = 'v154-safe-graph-option-rank';
protocol.optionCount = generator.proposalCount;
protocol.optionRanks = generator.proposalRanks;
protocol.optionDwellPages = generator.formationCounts;
protocol.fallbackMode = 'fixed-clockwise';
protocol.dominantWeight = generator.dominantWeight;
protocol.residualWeight = generator.residualWeight;
protocol.exactSelectedMessageCount = ...
    generator.exactSelectedMessageCount;
protocol.actionGeneratorProtocolId = generator.id;
protocol.actionGeneratorContractVersion = generator.contractVersion;
protocol.modelPath = generator.modelPath;
protocol.modelSha256 = generator.modelSha256;
protocol.modelContractVersion = generator.modelContractVersion;
protocol.minimumMeanGainPercent = pareto.minimumMeanGainPercent;
protocol.minimumPositiveSeedCount = pareto.minimumPositiveSeedCount;
protocol.maximumWorstSensorRegressionPercent = ...
    pareto.maximumWorstSensorRegressionPercent;
protocol.maximumMinimumFormationRegressionPercent = ...
    pareto.maximumMinimumFormationRegressionPercent;
protocol.maximumConsensusRegressionPercent = ...
    pareto.maximumConsensusRegressionPercent;
protocol.maximumAttemptedByteIncreasePercent = ...
    pareto.maximumAttemptedByteIncreasePercent;
protocol.requireX36PilotFirst = true;
protocol.gnnTrainingAuthorized = false;
protocol.truthUsedForOptionGeneration = false;
protocol.futureOutcomeUsedForOptionGeneration = false;
protocol.claimBoundary = [ ...
    'Opened-development graph-option headroom only. A complete ', ...
    'projector-safe graph is regenerated only at formation-scale ', ...
    'option boundaries and is held between them while physical. ', ...
    'Truth and future outcomes score the offline oracle only.'];

if numel(protocol.presetNames) ~= numel(protocol.nodeCounts) || ...
        numel(protocol.nodeCounts) ~= ...
            numel(protocol.formationCounts) || ...
        numel(protocol.optionDwellPages) ~= ...
            numel(protocol.formationCounts) || ...
        any(protocol.optionDwellPages ~= ...
            protocol.formationCounts) || ...
        numel(protocol.anchorTimes) ~= ...
            numel(protocol.nodeCounts) || ...
        any(protocol.exactSelectedMessageCount ~= ...
            2 * protocol.nodeCounts - ...
                2 * protocol.formationCounts) || ...
        protocol.gnnTrainingAuthorized || ...
        protocol.truthUsedForOptionGeneration || ...
        protocol.futureOutcomeUsedForOptionGeneration
    error('V154 safe graph-option protocol is inconsistent.');
end
end
