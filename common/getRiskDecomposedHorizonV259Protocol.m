function protocol = getRiskDecomposedHorizonV259Protocol()
% GETRISKDECOMPOSEDHORIZONV259PROTOCOL Passive causal-risk trace.

source = getCausalMinimumFormationBackboneV242Protocol();
protocol = struct();
protocol.id = 'risk-decomposed-horizon-v259-v1';
protocol.contractVersion = ...
    'risk-decomposed-horizon-v259-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.referenceArmId = source.armId;
protocol.allowedPresets = { ...
    'm24-formation-fov-temporal-coupled-formation-braid'};
protocol.allowedSeeds = 1301;
protocol.diagnosticAnchorTimes = [70, 84, 151];
protocol.activeExistenceThreshold = 0.50;
protocol.networkSupportThreshold = 0.50;
protocol.localizationTailFraction = 0.20;
protocol.minimumLocalizationFormationCoverage = 0.80;
protocol.localizationSensorLowerQuantile = 0.25;
protocol.supportTailFraction = 0.20;
protocol.existenceClip = 1e-6;
protocol.filterSeedOffset = source.filterSeedOffset;
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V259 passively captures every pre-topology V242 local posterior on ', ...
    'the already opened corrected M24 seed. Formation risk summaries use ', ...
    'only current LMB posteriors, formation membership and the registered ', ...
    'OSPA cutoff. Recorded truth-level errors are joined only offline. ', ...
    'The trace may guide a causal controller but cannot establish tracking ', ...
    'gain, held-out generalization or a paper claim.'];

if protocol.activeExistenceThreshold <= 0 || ...
        protocol.activeExistenceThreshold >= 1 || ...
        protocol.networkSupportThreshold <= 0 || ...
        protocol.networkSupportThreshold >= 1 || ...
        protocol.localizationTailFraction <= 0 || ...
        protocol.localizationTailFraction > 1 || ...
        protocol.minimumLocalizationFormationCoverage <= 0.5 || ...
        protocol.minimumLocalizationFormationCoverage > 1 || ...
        protocol.localizationSensorLowerQuantile < 0 || ...
        protocol.localizationSensorLowerQuantile > 0.5 || ...
        protocol.supportTailFraction <= 0 || ...
        protocol.supportTailFraction > 1 || ...
        protocol.existenceClip <= 0 || ...
        protocol.existenceClip >= 0.5
    error('RiskDecomposedV259:InvalidProtocol', ...
        'The V259 thresholds or tail fractions are invalid.');
end
if any(protocol.diagnosticAnchorTimes < 1) || ...
        any(protocol.diagnosticAnchorTimes ~= ...
            round(protocol.diagnosticAnchorTimes))
    error('RiskDecomposedV259:InvalidProtocol', ...
        'The V259 diagnostic anchors must be positive integer pages.');
end
end
