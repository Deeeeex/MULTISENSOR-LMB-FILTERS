function protocol = getReliabilityBalancedHomotopyV80Protocol()
% GETRELIABILITYBALANCEDHOMOTOPYV80PROTOCOL Frozen one-step headroom.

v79 = getBalancedRecoveryOperatorV79Protocol();
protocol = struct();
protocol.id = 'reliability-balanced-homotopy-v80-v1';
protocol.contractVersion = ...
    'reliability-balanced-homotopy-v80-protocol-v1';
protocol.baseProtocolId = v79.id;
protocol.cases = v79.cases;
protocol.cacheRoot = v79.cacheRoot;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v80', 'reliability_balanced_homotopy');
protocol.fusionConfig = v79.fusionConfig;
protocol.expectedDeliveryWeighting = true;
protocol.dominantWeight = v79.dominantWeight;
protocol.residualWeight = v79.residualWeight;
protocol.covarianceRegularization = ...
    v79.covarianceRegularization;
protocol.recoveryCandidateRieLimit = ...
    v79.recoveryCandidateRieLimit;
protocol.alphaGrid = [ ...
    0, 0.02, 0.05, 0.10, 0.20, ...
    0.40, 0.60, 0.80, 1.00];
protocol.sinkhornTolerance = 1e-12;
protocol.sinkhornMaximumIterations = 20000;
protocol.effectiveWeightTolerance = 2e-11;
protocol.requireExactSupportParity = true;
protocol.requireExactMessageCountParity = true;
protocol.selectionOrder = { ...
    'minimum-next-round-centered-energy', ...
    'minimum-balancing-alpha'};
protocol.positiveHeadroomRequiresStrictImprovementOverAlphaZero = true;
protocol.contractionRequiresNoIncreaseFromCandidatePulse = true;
protocol.routeExecutionAuthorized = false;
protocol.trackingOutcomeScoringAuthorized = false;
protocol.modelTrainingAuthorized = false;
protocol.validationClaimAllowed = false;
protocol.openedDevelopmentEvidenceOnly = true;
protocol.evidenceBoundary = [ ...
    'V80 keeps the V75-safe first-round pulse and the exact reference ', ...
    'topology. It constructs the reliability-adjusted effective ', ...
    'reference matrix, obtains its support-preserving Sinkhorn ', ...
    'projection onto the doubly stochastic matrices, and evaluates a ', ...
    'frozen homotopy between the two. Every homotopy point is converted ', ...
    'back to nominal directed weights so that deterministic current-link ', ...
    'reliability produces exactly the requested effective operator. ', ...
    'The source-only one-round response curve uses current posteriors ', ...
    'only to measure recovery headroom after the pulse; weight ', ...
    'construction uses no posterior. No prediction, new measurement, ', ...
    'truth, future link, packet draw, route execution, tracking outcome, ', ...
    'or model training is used.'];
end
