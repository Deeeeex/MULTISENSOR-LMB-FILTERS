function [adjacencySequence, fusionWeightSequence, details] = ...
    buildFormationB4V48ContractionOptimizedSchedule( ...
        context, referenceDetails, options)
% BUILDFORMATIONB4V48CONTRACTIONOPTIMIZEDSCHEDULE
% Select one activation phase for every residual receiver by minimizing the
% exact four-page expected centered-L2 propagation factor.  The search reads
% only the current reference graph, current link reliability and immutable
% physical identities.  It never reads posterior contents or delivery draws.

if nargin < 3 || isempty(options)
    options = struct();
end
allowed = {'period', 'dominantWeight', 'activeResidualWeight', ...
    'missingNeighborWeightMode', 'maximumIncomingCount', ...
    'maximumCoordinateSweeps', 'improvementTolerance', ...
    'minimumRelativeImprovementVsBestSynchronized'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowed))
    error('FormationB4V48:InvalidOptions', ...
        'The contraction-schedule options are malformed.');
end
period = getField(options, 'period', 4);
dominantWeight = getField(options, 'dominantWeight', 0.70);
activeResidualWeight = getField( ...
    options, 'activeResidualWeight', 0.20);
missingMode = lower(char(getField( ...
    options, 'missingNeighborWeightMode', 'renormalize')));
maximumIncomingCount = getField(options, 'maximumIncomingCount', 2);
maximumSweeps = getField(options, 'maximumCoordinateSweeps', 2);
tolerance = getField(options, 'improvementTolerance', 1e-12);
minimumRelativeImprovement = getField(options, ...
    'minimumRelativeImprovementVsBestSynchronized', 0.01);
if period ~= 4 || ~isscalar(period) || ~isfinite(period) || ...
        dominantWeight <= 0 || activeResidualWeight <= 0 || ...
        dominantWeight + activeResidualWeight >= 1 || ...
        ~ismember(missingMode, {'renormalize', 'self'}) || ...
        maximumIncomingCount ~= 2 || ...
        maximumSweeps < 0 || maximumSweeps ~= round(maximumSweeps) || ...
        tolerance < 0 || ~isfinite(tolerance) || ...
        ~isscalar(minimumRelativeImprovement) || ...
        ~isfinite(minimumRelativeImprovement) || ...
        minimumRelativeImprovement < 0 || ...
        minimumRelativeImprovement > 1
    error('FormationB4V48:InvalidOptions', ...
        'The frozen B4 search domain or weight rule is invalid.');
end

requiredContext = {'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'physicalAdjacency', ...
    'commConfig', 'currentTime'};
requiredReference = {'dominantAdjacency', 'residualAdjacency', ...
    'referenceAdjacency', 'referenceFusionWeights'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~hasExactFields(context, requiredContext) || ...
        ~isstruct(context.commConfig) || ...
        ~hasExactFields(context.commConfig, {'pDropByEdge'}) || ...
        ~isstruct(referenceDetails) || ~isscalar(referenceDetails) || ...
        ~hasExactFields(referenceDetails, requiredReference)
    error('FormationB4V48:InvalidContext', ...
        'The current graph or reference route is incomplete.');
end

sensorUids = reshape(context.sensorPhysicalUids, 1, []);
formationUids = reshape( ...
    context.formationPhysicalUidsBySensor, 1, []);
nodeCount = numel(sensorUids);
dominant = logical(referenceDetails.dominantAdjacency);
residual = logical(referenceDetails.residualAdjacency);
reference = logical(referenceDetails.referenceAdjacency);
reliability = 1 - context.commConfig.pDropByEdge';
if nodeCount < period || ...
        ~isa(sensorUids, 'double') || ~isreal(sensorUids) || ...
        any(~isfinite(sensorUids)) || any(sensorUids <= 0) || ...
        any(sensorUids ~= round(sensorUids)) || ...
        numel(unique(sensorUids)) ~= nodeCount || ...
        ~isa(formationUids, 'double') || ~isreal(formationUids) || ...
        any(~isfinite(formationUids)) || any(formationUids <= 0) || ...
        any(formationUids ~= round(formationUids)) || ...
        numel(formationUids) ~= nodeCount || ...
        ~(islogical(context.physicalAdjacency) || ...
            isnumeric(context.physicalAdjacency)) || ...
        any(~isfinite(context.physicalAdjacency(:))) || ...
        any(context.physicalAdjacency(:) ~= 0 & ...
            context.physicalAdjacency(:) ~= 1) || ...
        any(diag(logical(context.physicalAdjacency))) || ...
        ~isequal(size(dominant), [nodeCount, nodeCount]) || ...
        ~isequal(size(residual), [nodeCount, nodeCount]) || ...
        ~isequal(reference, dominant | residual) || ...
        any(dominant(:) & residual(:)) || ...
        any(sum(dominant, 2) ~= 1) || ...
        any(sum(residual, 2) ~= 1) || ...
        nnz(reference) ~= 2 * nodeCount || ...
        ndims(context.commConfig.pDropByEdge) ~= 2 || ...
        ~isequal(size(reliability), [nodeCount, nodeCount]) || ...
        any(~isfinite(reliability(:))) || ...
        any(reliability(:) < 0) || any(reliability(:) > 1) || ...
        any(reference(:) & ~logical(context.physicalAdjacency(:)))
    error('FormationB4V48:InvalidReference', ...
        'The V48 reference route or current reliability page is invalid.');
end

seedSchedules = buildSeedSchedules( ...
    sensorUids, formationUids, period);
seedCount = size(seedSchedules, 1);
seedScores = inf(1, seedCount);
optimizedSchedules = zeros(seedCount, nodeCount);
optimizedScores = inf(1, seedCount);
evaluationCounts = zeros(1, seedCount);
acceptedMoveCounts = zeros(1, seedCount);
for seedIdx = 1:seedCount
    phases = seedSchedules(seedIdx, :);
    [seedScores(seedIdx), evaluationCounts(seedIdx)] = ...
        scoreSchedule(phases, dominant, residual, reliability, ...
            period, dominantWeight, activeResidualWeight, ...
            missingMode, maximumIncomingCount);
    [phases, optimizedScores(seedIdx), searchEvidence] = ...
        coordinateDescent(phases, seedScores(seedIdx), ...
            sensorUids, dominant, residual, reliability, period, ...
            dominantWeight, activeResidualWeight, missingMode, ...
            maximumIncomingCount, maximumSweeps, tolerance);
    optimizedSchedules(seedIdx, :) = phases;
    evaluationCounts(seedIdx) = evaluationCounts(seedIdx) + ...
        searchEvidence.evaluationCount;
    acceptedMoveCounts(seedIdx) = searchEvidence.acceptedMoveCount;
end

physicalSchedules = zeros(size(optimizedSchedules));
[sortedUids, physicalOrder] = sort(sensorUids);
for seedIdx = 1:seedCount
    physicalSchedules(seedIdx, :) = ...
        optimizedSchedules(seedIdx, physicalOrder);
end
keys = [reshape(optimizedScores, [], 1), physicalSchedules];
[~, order] = sortrows(keys, 1:size(keys, 2));
unconstrainedSelectedSeed = order(1);
unconstrainedSelectedPhases = ...
    optimizedSchedules(unconstrainedSelectedSeed, :);
unconstrainedSelectedScore = ...
    optimizedScores(unconstrainedSelectedSeed);

phaseOneSyncMask = all(seedSchedules == 1, 2);
phaseOneSyncScore = seedScores(find(phaseOneSyncMask, 1));
constantSyncMask = all(seedSchedules == ...
    repmat(seedSchedules(:, 1), 1, nodeCount), 2);
constantSyncRows = find(constantSyncMask);
[bestSyncScore, bestSyncLocalIdx] = ...
    min(seedScores(constantSyncRows));
bestSyncSeed = constantSyncRows(bestSyncLocalIdx);
bestSyncPhase = seedSchedules(bestSyncSeed, 1);
unconstrainedRelativeImprovement = safeRelativeImprovement( ...
    bestSyncScore, unconstrainedSelectedScore);
unconstrainedIsSynchronized = ...
    numel(unique(unconstrainedSelectedPhases)) == 1;
materialityGateTriggered = ~unconstrainedIsSynchronized && ...
    unconstrainedRelativeImprovement + tolerance < ...
        minimumRelativeImprovement;
if materialityGateTriggered
    selectedSeed = bestSyncSeed;
    selectedPhases = seedSchedules(bestSyncSeed, :);
    selectedScore = bestSyncScore;
else
    selectedSeed = unconstrainedSelectedSeed;
    selectedPhases = unconstrainedSelectedPhases;
    selectedScore = unconstrainedSelectedScore;
end
[adjacencySequence, fusionWeightSequence] = materializeSchedule( ...
    selectedPhases, dominant, residual, period, ...
    dominantWeight, activeResidualWeight);
selectedCertificate = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        adjacencySequence, fusionWeightSequence, ...
        repmat(reliability, 1, 1, period), struct( ...
            'missingNeighborWeightMode', missingMode, ...
            'maximumIncomingCount', maximumIncomingCount));
messageCountByPhase = reshape(sum(sum( ...
    adjacencySequence, 1), 2), 1, []);
referenceMessagesPerPeriod = period * nnz(reference);
actualMessagesPerPeriod = sum(messageCountByPhase);
formationSequence = collapseToFormations( ...
    adjacencySequence, formationUids);
if ~isequal(any(adjacencySequence, 3), reference) || ...
        ~isStronglyConnected(any(adjacencySequence, 3)) || ...
        ~isStronglyConnected(any(formationSequence, 3)) || ...
        actualMessagesPerPeriod ~= 5 * nodeCount || ...
        referenceMessagesPerPeriod ~= 8 * nodeCount || ...
        any(abs(reshape(sum(fusionWeightSequence, 2), [], 1) - 1) ...
            > 1e-12) || ...
        selectedScore > bestSyncScore + tolerance
    error('FormationB4V48:InvalidSchedule', ...
        'The selected schedule violates its budget, union, or fallback bound.');
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v48-contraction-optimized-schedule-v1';
payload.currentTime = context.currentTime;
payload.period = period;
payload.sensorPhysicalUids = sortedUids;
payload.selectedPhaseByPhysicalUid = ...
    selectedPhases(physicalOrder);
payload.selectedSeedOrdinal = selectedSeed;
payload.seedScheduleCount = seedCount;
payload.maximumCoordinateSweeps = maximumSweeps;
payload.improvementTolerance = tolerance;
payload.minimumRelativeImprovementVsBestSynchronized = ...
    minimumRelativeImprovement;
payload.seedSquaredFactors = seedScores;
payload.optimizedSquaredFactors = optimizedScores;
payload.evaluationCountBySeed = evaluationCounts;
payload.acceptedMoveCountBySeed = acceptedMoveCounts;
payload.phaseOneSynchronizedB4SquaredFactor = phaseOneSyncScore;
payload.bestSynchronizedB4SquaredFactor = bestSyncScore;
payload.bestSynchronizedPulsePhase = bestSyncPhase;
payload.unconstrainedSelectedSeedOrdinal = ...
    unconstrainedSelectedSeed;
payload.unconstrainedSelectedSquaredFactor = ...
    unconstrainedSelectedScore;
payload.unconstrainedRelativeSquaredFactorImprovementVsBestSynchronized = ...
    unconstrainedRelativeImprovement;
payload.unconstrainedNonSynchronizedSchedule = ...
    ~unconstrainedIsSynchronized;
payload.materialityGateTriggered = materialityGateTriggered;
payload.selectedSquaredFactor = selectedScore;
payload.selectedRmsFactor = sqrt(payload.selectedSquaredFactor);
payload.relativeSquaredFactorImprovementVsPhaseOne = ...
    safeRelativeImprovement( ...
        phaseOneSyncScore, payload.selectedSquaredFactor);
payload.relativeSquaredFactorImprovementVsBestSynchronized = ...
    safeRelativeImprovement( ...
        bestSyncScore, payload.selectedSquaredFactor);
payload.messageCountByPhase = messageCountByPhase;
payload.messagesPerPeriod = actualMessagesPerPeriod;
payload.referenceMessagesPerPeriod = referenceMessagesPerPeriod;
payload.posteriorMessageSavingFraction = ...
    (referenceMessagesPerPeriod - actualMessagesPerPeriod) / ...
        referenceMessagesPerPeriod;
payload.periodUnionEqualsReference = true;
payload.periodUnionSensorStrongConnected = true;
payload.periodUnionFormationStrongConnected = true;
payload.synchronizedCandidateIncluded = true;
payload.selectedNoWorseThanBestSynchronizedProxy = true;
payload.nonSynchronizedExecutionRequiresMaterialImprovement = true;
payload.frozenSnapshotRouteAndReliabilityAssumed = true;
payload.timeVaryingRuntimeRouteCertified = false;
payload.samePhysicalResidualEdgeServedOnceAtRuntime = false;
payload.runtimeReceiverPhaseExecutionImplemented = false;
payload.runtimeRollingConnectivityCertified = false;
payload.currentGraphUsed = true;
payload.currentLinkReliabilityUsed = true;
payload.immutablePhysicalIdentityUsedForDeterministicSearch = true;
payload.posteriorUsed = false;
payload.deliveryAcknowledgmentUsed = false;
payload.truthUsed = false;
payload.measurementUsed = false;
payload.futureGeometryUsed = false;
payload.futureOutcomeUsed = false;
payload.realizedDeliveryUniformsUsed = false;
payload.trackingOutcomeScored = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
physicalCertificate = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        adjacencySequence(physicalOrder, physicalOrder, :), ...
        fusionWeightSequence(physicalOrder, physicalOrder, :), ...
        repmat(reliability(physicalOrder, physicalOrder), ...
            1, 1, period), struct( ...
            'missingNeighborWeightMode', missingMode, ...
            'maximumIncomingCount', maximumIncomingCount));
payload.selectedPhysicalUidOrderCertificateCanonicalSha256 = ...
    computeCanonicalValueSha256(physicalCertificate);
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
details = payload;
details.selectedCertificate = selectedCertificate;
details.selectedCertificateArrayOrderCanonicalSha256 = ...
    computeCanonicalValueSha256(selectedCertificate);
details.referenceAdjacency = reference;
details.dominantAdjacency = dominant;
details.residualAdjacency = residual;
details.referenceFusionWeights = ...
    referenceDetails.referenceFusionWeights;
details.adjacencySequence = adjacencySequence;
details.fusionWeightSequence = fusionWeightSequence;
end

function schedules = buildSeedSchedules(sensorUids, formationUids, period)
nodeCount = numel(sensorUids);
schedules = zeros(0, nodeCount);
for phase = 1:period
    schedules(end + 1, :) = phase * ones(1, nodeCount); %#ok<AGROW>
end
[~, physicalOrder] = sort(sensorUids);
uidBalanced = zeros(1, nodeCount);
uidBalanced(physicalOrder) = mod(0:(nodeCount - 1), period) + 1;
schedules(end + 1, :) = uidBalanced;
uniqueFormations = sort(unique(formationUids));
formationStaggered = zeros(1, nodeCount);
receiverStaggered = zeros(1, nodeCount);
for formationIdx = 1:numel(uniqueFormations)
    members = find(formationUids == uniqueFormations(formationIdx));
    [~, memberOrder] = sort(sensorUids(members));
    orderedMembers = members(memberOrder);
    formationStaggered(members) = ...
        mod(formationIdx - 1, period) + 1;
    receiverStaggered(orderedMembers) = mod( ...
        (formationIdx - 1) + (0:(numel(members) - 1)), period) + 1;
end
schedules(end + 1, :) = formationStaggered;
schedules(end + 1, :) = receiverStaggered;
schedules = unique(schedules, 'rows', 'stable');
end

function [phases, score, evidence] = coordinateDescent( ...
        phases, score, sensorUids, dominant, residual, reliability, ...
        period, dominantWeight, activeResidualWeight, missingMode, ...
        maximumIncomingCount, maximumSweeps, tolerance)
[~, receiverOrder] = sort(sensorUids);
evaluationCount = 0;
acceptedMoveCount = 0;
completedSweeps = 0;
for sweepIdx = 1:maximumSweeps
    changed = false;
    completedSweeps = sweepIdx;
    for receiverIdx = receiverOrder
        currentPhase = phases(receiverIdx);
        bestPhase = currentPhase;
        bestScore = score;
        for phase = 1:period
            if phase == currentPhase
                continue;
            end
            proposal = phases;
            proposal(receiverIdx) = phase;
            [proposalScore, count] = scoreSchedule( ...
                proposal, dominant, residual, reliability, period, ...
                dominantWeight, activeResidualWeight, missingMode, ...
                maximumIncomingCount);
            evaluationCount = evaluationCount + count;
            if proposalScore < bestScore - tolerance || ...
                    (abs(proposalScore - bestScore) <= tolerance && ...
                     phase < bestPhase)
                bestScore = proposalScore;
                bestPhase = phase;
            end
        end
        if bestPhase ~= currentPhase && bestScore < score - tolerance
            phases(receiverIdx) = bestPhase;
            score = bestScore;
            changed = true;
            acceptedMoveCount = acceptedMoveCount + 1;
        end
    end
    if ~changed
        break;
    end
end
evidence = struct('evaluationCount', evaluationCount, ...
    'acceptedMoveCount', acceptedMoveCount, ...
    'completedSweepCount', completedSweeps);
end

function [score, count] = scoreSchedule( ...
        phases, dominant, residual, reliability, period, ...
        dominantWeight, activeResidualWeight, missingMode, ...
        maximumIncomingCount)
[adjacency, weights] = materializeSchedule( ...
    phases, dominant, residual, period, ...
    dominantWeight, activeResidualWeight);
certificate = ...
    computeReliableKlaWindowMeanSquareContractionCertificate( ...
        adjacency, weights, repmat(reliability, 1, 1, period), ...
        struct('missingNeighborWeightMode', missingMode, ...
            'maximumIncomingCount', maximumIncomingCount));
score = certificate.worstCaseExpectedSquaredContractionFactor;
count = 1;
end

function [adjacency, weights] = materializeSchedule( ...
        phases, dominant, residual, period, ...
        dominantWeight, activeResidualWeight)
nodeCount = size(dominant, 1);
adjacency = false(nodeCount, nodeCount, period);
weights = zeros(nodeCount, nodeCount, period);
for phase = 1:period
    activeRows = reshape(phases == phase, [], 1);
    activeResidual = residual & repmat(activeRows, 1, nodeCount);
    page = dominant | activeResidual;
    pageWeights = zeros(nodeCount);
    pageWeights(dominant) = dominantWeight;
    pageWeights(activeResidual) = activeResidualWeight;
    pageWeights(1:nodeCount+1:end) = 1 - sum(pageWeights, 2)';
    adjacency(:, :, phase) = page;
    weights(:, :, phase) = pageWeights;
end
end

function pages = collapseToFormations(sensorPages, formationUids)
uids = sort(unique(formationUids));
pages = false(numel(uids), numel(uids), size(sensorPages, 3));
for timeIdx = 1:size(sensorPages, 3)
    for receiverIdx = 1:numel(uids)
        receivers = formationUids == uids(receiverIdx);
        for senderIdx = 1:numel(uids)
            senders = formationUids == uids(senderIdx);
            pages(receiverIdx, senderIdx, timeIdx) = any(any( ...
                sensorPages(receivers, senders, timeIdx)));
        end
    end
end
end

function connected = isStronglyConnected(adjacency)
senderAdjacency = logical(adjacency');
connected = reachableAll(senderAdjacency) && ...
    reachableAll(senderAdjacency');
end

function connected = reachableAll(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node)
        continue;
    end
    visited(node) = true;
    frontier = [frontier, reshape(find( ...
        adjacency(node, :) & ~visited), 1, [])]; %#ok<AGROW>
end
connected = all(visited);
end

function value = safeRelativeImprovement(reference, candidate)
if reference > 0
    value = (reference - candidate) / reference;
elseif candidate == 0
    value = 0;
else
    value = -inf;
end
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end

function matched = hasExactFields(structure, names)
matched = isstruct(structure) && isscalar(structure) && ...
    numel(fieldnames(structure)) == numel(names) && ...
    all(isfield(structure, names));
end
