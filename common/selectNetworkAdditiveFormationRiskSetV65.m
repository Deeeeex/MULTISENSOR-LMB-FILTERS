function selection = selectNetworkAdditiveFormationRiskSetV65( ...
        metrics, options)
% SELECTNETWORKADDITIVEFORMATIONRISKSETV65 Exact guarded covering action.

if nargin < 2 || isempty(options)
    options = struct();
end
coverageTarget = getField(options, 'coverageTargetFraction', 0.80);
minimumRisk = getField(options, 'minimumNetworkRiskFraction', 0.01);
maximumUsefulLossRatio = getField( ...
    options, 'maximumUsefulLossToRescueRatio', 1.0);
requireZeroDownwardCrossings = logical(getField( ...
    options, 'requireZeroCrossSupportedDownwardCrossings', true));
if ~isstruct(metrics) || ...
        ~isfield(metrics, 'groups') || ...
        ~isfield(metrics, 'networkRescueFractionByFormation') || ...
        ~isfield(metrics, 'networkUsefulLossFractionByFormation') || ...
        ~isfield(metrics, 'singleActionAvailableMask') || ...
        ~isfield(metrics, 'singleActionSafetyMask') || ...
        ~isfield(metrics, 'crossSupportedDownwardCrossingsByFormation') || ...
        ~isscalar(coverageTarget) || ~isfinite(coverageTarget) || ...
        coverageTarget <= 0 || coverageTarget > 1 || ...
        ~isscalar(minimumRisk) || ~isfinite(minimumRisk) || ...
        minimumRisk < 0 || ...
        ~isscalar(maximumUsefulLossRatio) || ...
        ~isfinite(maximumUsefulLossRatio) || ...
        maximumUsefulLossRatio < 0
    error('NetworkAdditiveSelectorV65:InvalidInput', ...
        'The additive risk metrics or selector options are invalid.');
end

groups = reshape(metrics.groups, 1, []);
rescue = reshape(metrics.networkRescueFractionByFormation, 1, []);
usefulLoss = reshape( ...
    metrics.networkUsefulLossFractionByFormation, 1, []);
downward = reshape( ...
    metrics.crossSupportedDownwardCrossingsByFormation, 1, []);
available = reshape(metrics.singleActionAvailableMask, 1, []);
formationCount = numel(groups);
if formationCount < 1 || formationCount > 20 || ...
        numel(rescue) ~= formationCount || ...
        numel(usefulLoss) ~= formationCount || ...
        numel(downward) ~= formationCount || ...
        numel(available) ~= formationCount
    error('NetworkAdditiveSelectorV65:FormationMismatch', ...
        'Formation-level selector inputs do not align.');
end

finiteMask = isfinite(rescue) & isfinite(usefulLoss) & ...
    isfinite(downward);
riskBasis = available & finiteMask;
% Do not reuse the earlier reference-retention mask here.  That mask treats
% every reference-supported label as ground for rejection even when no active
% cross sender currently supports it; V60 showed that this admits stale-label
% false positives.  V65 replaces it with the measurement-conditioned useful
% loss and downward-crossing guards below.
candidateBasis = riskBasis;
if requireZeroDownwardCrossings
    candidateBasis = candidateBasis & downward == 0;
end
totalRisk = sum(max(rescue(riskBasis), 0));

selection = emptySelection();
selection.coverageTargetFraction = coverageTarget;
selection.minimumNetworkRiskFraction = minimumRisk;
selection.maximumUsefulLossToRescueRatio = maximumUsefulLossRatio;
selection.requireZeroCrossSupportedDownwardCrossings = ...
    requireZeroDownwardCrossings;
selection.totalNetworkRiskFraction = totalRisk;
selection.totalNetworkUsefulLossFraction = ...
    sum(max(usefulLoss(riskBasis), 0));
selection.riskBasisFormationIds = groups(riskBasis);
selection.candidateBasisFormationIds = groups(candidateBasis);

if totalRisk < minimumRisk - 1e-12
    selection.fallbackReason = 'below-network-risk-budget';
    return;
end
if ~any(candidateBasis)
    selection.fallbackReason = 'no-safe-formation-action';
    return;
end

indices = find(candidateBasis);
bestKey = [];
bestMask = false(1, formationCount);
for code = 1:(2 ^ numel(indices) - 1)
    localMask = logical(bitget(code, 1:numel(indices)));
    selectedIndices = indices(localMask);
    selectedRescue = sum(max(rescue(selectedIndices), 0));
    selectedLoss = sum(max(usefulLoss(selectedIndices), 0));
    if selectedRescue < coverageTarget * totalRisk - 1e-12 || ...
            selectedLoss > maximumUsefulLossRatio * selectedRescue + 1e-12
        continue;
    end
    key = [numel(selectedIndices), selectedLoss, -selectedRescue, code];
    if isempty(bestKey) || lexicographicallyLess(key, bestKey)
        bestKey = key;
        bestMask = false(1, formationCount);
        bestMask(selectedIndices) = true;
    end
end

if isempty(bestKey)
    selection.fallbackReason = 'no-guarded-risk-cover';
    return;
end

selection.actionEnabled = true;
selection.selectedFormationMask = bestMask;
selection.selectedFormationIds = groups(bestMask);
selection.selectedNetworkRescueFraction = ...
    sum(max(rescue(bestMask), 0));
selection.selectedNetworkUsefulLossFraction = ...
    sum(max(usefulLoss(bestMask), 0));
selection.achievedCoverageFraction = ...
    selection.selectedNetworkRescueFraction / max(totalRisk, eps);
selection.usefulLossToRescueRatio = ...
    selection.selectedNetworkUsefulLossFraction / max( ...
        selection.selectedNetworkRescueFraction, eps);
selection.fallbackReason = '';
end

function value = emptySelection()
value = struct( ...
    'contractVersion', 'network-additive-formation-selector-v65-v1', ...
    'actionEnabled', false, ...
    'selectedFormationMask', false(1, 0), ...
    'selectedFormationIds', zeros(1, 0), ...
    'coverageTargetFraction', NaN, ...
    'minimumNetworkRiskFraction', NaN, ...
    'maximumUsefulLossToRescueRatio', NaN, ...
    'requireZeroCrossSupportedDownwardCrossings', true, ...
    'totalNetworkRiskFraction', NaN, ...
    'totalNetworkUsefulLossFraction', NaN, ...
    'selectedNetworkRescueFraction', 0, ...
    'selectedNetworkUsefulLossFraction', 0, ...
    'achievedCoverageFraction', 0, ...
    'usefulLossToRescueRatio', NaN, ...
    'riskBasisFormationIds', zeros(1, 0), ...
    'candidateBasisFormationIds', zeros(1, 0), ...
    'fallbackReason', 'not-evaluated', ...
    'truthUsed', false, ...
    'futureMeasurementsUsed', false, ...
    'futureOutcomesUsed', false);
end

function value = lexicographicallyLess(left, right)
value = false;
for idx = 1:numel(left)
    if left(idx) < right(idx) - 1e-15
        value = true;
        return;
    elseif left(idx) > right(idx) + 1e-15
        return;
    end
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
