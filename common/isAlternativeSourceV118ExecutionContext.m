function detected = isAlternativeSourceV118ExecutionContext(context)
% ISALTERNATIVESOURCEV118EXECUTIONCONTEXT Identify V118.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'alternative-source-v118-context-v1');
end
