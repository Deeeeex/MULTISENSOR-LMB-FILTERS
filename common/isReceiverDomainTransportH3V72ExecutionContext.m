function detected = ...
    isReceiverDomainTransportH3V72ExecutionContext(context)
% ISRECEIVERDOMAINTRANSPORTH3V72EXECUTIONCONTEXT Identify V72 requests.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'receiver-domain-transport-h3-v72-context-v1');
end
