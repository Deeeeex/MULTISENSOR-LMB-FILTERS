function protocol = getScaleEquivariantGatewayRidgeV254Protocol()
% GETSCALEEQUIVARIANTGATEWAYRIDGEV254PROTOCOL Frozen additive ridge screen.

policy = getScaleEquivariantSafeGatewayV254Protocol();
teacher = getIndependentM24GatewayTeacherV252Protocol();
protocol = struct();
protocol.id = 'scale-equivariant-gateway-ridge-v254-v1';
protocol.contractVersion = ...
    'scale-equivariant-gateway-ridge-v254-protocol-v1';
protocol.policyProtocolId = policy.id;
protocol.teacherProtocolId = teacher.id;
protocol.trainingSeeds = teacher.trainingSeeds;
protocol.developmentHoldoutSeeds = teacher.developmentHoldoutSeeds;
protocol.untouchedM24Seeds = teacher.untouchedFullEpisodeSeeds;
protocol.anchorTimes = teacher.anchorTimes;
protocol.horizonSteps = teacher.horizonSteps;
protocol.featureSetName = 'compact-additive-16';
protocol.controlSynopsisMode = 'compact-node-32';
protocol.ridgeLambdaGrid = teacher.ridgeLambdaGrid;
protocol.activationThresholdGrid = [0, 0.02, 0.05, 0.1, 0.2];
protocol.calibrationMargin = 0;
protocol.switchingPenalty = 0;
protocol.tieTolerance = 1e-10;
protocol.formationRegressionTolerancePercent = ...
    teacher.maximumFormationRegressionPercent;
protocol.minimumHoldoutSafeSelectionFraction = ...
    teacher.minimumDevelopmentHoldoutTailAlignedFraction;
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v254', ...
    'compact_additive_gateway_ridge');
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V254 fits one reference-centered additive ridge on V252 seeds 1302 ', ...
    'and 1303. Hyperparameters are chosen by leave-one-training-seed-out ', ...
    'evaluation before seed 1304 is evaluated once. Only the fixed ', ...
    '32-byte-per-sensor compact telemetry contract is eligible for the ', ...
    'primary model. Every selected or fallback window is charged the ', ...
    'compact synopsis and route-command bytes, while the V242 comparator ', ...
    'pays no learned-policy overhead. Candidate-bank holdout performance ', ...
    'may authorize a frozen H=3 evaluation of the exact projected action; ', ...
    'it does not by itself authorize a complete episode, X36, a GNN or a ', ...
    'paper claim.'];

valid = isempty(intersect(protocol.trainingSeeds, ...
        protocol.developmentHoldoutSeeds)) && ...
    isempty(intersect([protocol.trainingSeeds, ...
        protocol.developmentHoldoutSeeds], ...
        protocol.untouchedM24Seeds)) && ...
    all(protocol.ridgeLambdaGrid > 0) && ...
    all(protocol.activationThresholdGrid >= 0) && ...
    ismember(protocol.controlSynopsisMode, policy.controlSynopsisModes) && ...
    protocol.calibrationMargin >= 0 && ...
    protocol.switchingPenalty >= 0 && ...
    protocol.tieTolerance >= 0;
if ~valid
    error('ScaleEquivariantGatewayV254:InvalidRidgeProtocol', ...
        'The V254 additive-ridge split or gate is inconsistent.');
end
end
