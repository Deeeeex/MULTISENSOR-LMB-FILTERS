function valid = ...
        isValidOnlinePositiveNetFormationReleaseV191Plan( ...
            plan, formationCount)
% ISVALIDONLINEPOSITIVENETFORMATIONRELEASEV191PLAN Validate teacher plan.

requiredFields = { ...
    'contractVersion', 'times', 'formationIdsByTime', 'teacherMode'};
valid = isstruct(plan) && isscalar(plan) && ...
    isequal(sort(fieldnames(plan)), sort(requiredFields(:))) && ...
    ischar(plan.contractVersion) && ...
    strcmp(plan.contractVersion, ...
        'online-positive-net-formation-release-v191-plan-v1') && ...
    isscalar(formationCount) && isnumeric(formationCount) && ...
    isfinite(formationCount) && formationCount >= 1 && ...
    formationCount == round(formationCount) && ...
    isnumeric(plan.times) && ~isempty(plan.times) && ...
    all(isfinite(plan.times)) && ...
    all(plan.times >= 1) && ...
    all(plan.times == round(plan.times)) && ...
    numel(unique(plan.times)) == numel(plan.times) && ...
    iscell(plan.formationIdsByTime) && ...
    numel(plan.formationIdsByTime) == numel(plan.times) && ...
    islogical(plan.teacherMode) && isscalar(plan.teacherMode) && ...
    plan.teacherMode;
if ~valid
    return;
end
protocol = getOnlinePositiveNetFormationReleaseV191Protocol();
for pageIdx = 1:numel(plan.formationIdsByTime)
    formationIds = plan.formationIdsByTime{pageIdx};
    if ~isnumeric(formationIds) || isempty(formationIds) || ...
            any(~isfinite(formationIds)) || ...
            any(formationIds < 1) || ...
            any(formationIds > formationCount) || ...
            any(formationIds ~= round(formationIds)) || ...
            numel(unique(formationIds)) ~= numel(formationIds) || ...
            numel(formationIds) > ...
                protocol.maximumReleaseFormationsPerPage
        valid = false;
        return;
    end
end
end
