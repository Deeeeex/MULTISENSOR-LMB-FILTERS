protocol.minimumWorstSensorGainPercent = 0.0;
protocol.minimumFormationGainPercent = 0.0;
protocol.minimumWindowConsensusGainPercent = 0.0;
protocol.minimumTerminalConsensusGainPercent = 0.0;
protocol.minimumAttemptedByteSavingPercent = -2.0;
protocol.requireSelectedRollingB3 = true;
protocol.requireExactMessageCountParity = true;
protocol.trackingOutcomeScoringAuthorized = true;
protocol.modelTrainingAuthorized = false;
protocol.validationClaimAllowed = false;
protocol.openedDevelopmentEvidenceOnly = true;
protocol.evidenceBoundary = [ ...
    'V83 is a paired H=3 action-space headroom screen on the two ', ...
    'already opened merge-split anchors. It retains only the V75 ', ...
    'direct-safe V71 receiver-domain sender replacements. Every ', ...
    'candidate preserves the 0.70 within-formation dominant input, ', ...
    'the physical route, and the exact directed-message count, but ', ...
    'raises the selected cross-formation trust from 0.05 to one frozen ', ...
    'point in {0.05,0.10,0.15,0.20}; additional trust is funded only ', ...
    'from receiver self-weight. The candidate route is used in rounds ', ...
    'one and three, with a current-physical-tree reference round ', ...
    'between them so rolling-B3 remains valid. The complete sequence ', ...
    'is frozen before ', ...
    'truth and future measurements score paired H=3 tracking returns. ', ...
    'This measures action-family headroom only and is not an online ', ...
    'selector, model-training result, or validation claim.'];
end
