function [adjacency, weights, details] = ...
        rewireInfluenceConeGatewayV117( ...
            baseAdjacency, baseWeights, baseDetails, ...
            sourceId, oldReceiverId, newReceiverId)
% REWIREINFLUENCECONEGATEWAYV117 Move one cross residual receiver.

adjacency = logical(baseAdjacency);
weights = double(baseWeights);
nodeCount = size(adjacency, 1);
if ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(weights), [nodeCount, nodeCount]) || ...
        ~isstruct(baseDetails) || ~isscalar(baseDetails) || ...
        ~isfield(baseDetails, 'residualAdjacency') || ...
        ~isfield(baseDetails, 'residualBaselineAdjacency') || ...
        ~isfield(baseDetails, 'dominantAdjacency') || ...
        ~isfield(baseDetails, 'residualWeight') || ...
        any([sourceId, oldReceiverId, newReceiverId] < 1) || ...
        any([sourceId, oldReceiverId, newReceiverId] > nodeCount) || ...
        numel(unique([sourceId, oldReceiverId, newReceiverId])) < 3
    error('AlternativeGatewayV117:InvalidRewireInput', ...
        'The gateway rewire input is malformed.');
end
residualWeight = baseDetails.residualWeight;
residual = logical(baseDetails.residualAdjacency);
baselineResidual = logical(baseDetails.residualBaselineAdjacency);
dominant = logical(baseDetails.dominantAdjacency);
if ~adjacency(oldReceiverId, sourceId) || ...
        ~residual(oldReceiverId, sourceId) || ...
        abs(weights(oldReceiverId, sourceId) - residualWeight) > 1e-12
    error('AlternativeGatewayV117:MissingOriginalGateway', ...
        'The registered cross residual gateway changed.');
end
oldInternalSource = find(baselineResidual(oldReceiverId, :));
newInternalSource = find(baselineResidual(newReceiverId, :));
if numel(oldInternalSource) ~= 1 || numel(newInternalSource) ~= 1 || ...
        newInternalSource == sourceId || ...
        adjacency(newReceiverId, sourceId)
    error('AlternativeGatewayV117:AmbiguousInternalResidual', ...
        'The F6 internal residual slot is not unique.');
end

adjacency(oldReceiverId, sourceId) = false;
weights(oldReceiverId, sourceId) = 0;
residual(oldReceiverId, sourceId) = false;
[adjacency, weights, residual] = addResidualContribution( ...
    adjacency, weights, residual, dominant, oldReceiverId, ...
    oldInternalSource, residualWeight);
[adjacency, weights, residual] = removeResidualContribution( ...
    adjacency, weights, residual, dominant, newReceiverId, ...
    newInternalSource, residualWeight);
adjacency(newReceiverId, sourceId) = true;
weights(newReceiverId, sourceId) = residualWeight;
residual(newReceiverId, sourceId) = true;

if max(abs(sum(weights, 2) - 1)) > 1e-12 || ...
        nnz(adjacency) ~= nnz(baseAdjacency) || ...
        max(abs(sort(weights(weights > 0)) - ...
            sort(baseWeights(baseWeights > 0)))) > 1e-12
    error('AlternativeGatewayV117:RewireInvariantFailed', ...
        'The gateway rewire changed row sums, messages, or weights.');
end
details = baseDetails;
details.fusionWeightMatrix = weights;
details.residualAdjacency = residual;
details.messageCount = nnz(adjacency);
details.crossResidualWeights = ...
    residualWeight * ones(size(baseDetails.crossResidualWeights));
if isfield(details, 'selectedSourcesByReceiver') && ...
        iscell(details.selectedSourcesByReceiver)
    details.selectedSourcesByReceiver{oldReceiverId} = ...
        find(adjacency(oldReceiverId, :));
    details.selectedSourcesByReceiver{newReceiverId} = ...
        find(adjacency(newReceiverId, :));
end
details.v117GatewayRewire = struct( ...
    'sourceId', sourceId, ...
    'oldReceiverId', oldReceiverId, ...
    'newReceiverId', newReceiverId, ...
    'restoredInternalSourceId', oldInternalSource, ...
    'displacedInternalSourceId', newInternalSource, ...
    'messageParityPassed', nnz(adjacency) == nnz(baseAdjacency), ...
    'rowSumPassed', max(abs(sum(weights, 2) - 1)) <= 1e-12, ...
    'weightMultisetPassed', true);
end

function [adjacency, weights, residual] = addResidualContribution( ...
        adjacency, weights, residual, dominant, receiver, source, amount)
adjacency(receiver, source) = true;
weights(receiver, source) = weights(receiver, source) + amount;
residual(receiver, source) = true;
end

function [adjacency, weights, residual] = removeResidualContribution( ...
        adjacency, weights, residual, dominant, receiver, source, amount)
weights(receiver, source) = weights(receiver, source) - amount;
if weights(receiver, source) < -1e-12
    error('AlternativeGatewayV117:NegativeWeight', ...
        'The displaced residual weight is absent.');
end
if dominant(receiver, source)
    adjacency(receiver, source) = true;
else
    adjacency(receiver, source) = false;
end
residual(receiver, source) = false;
end
