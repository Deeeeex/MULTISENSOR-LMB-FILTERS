function [adjacency, details] = ...
    replayRollingSafeRolloutProjection( ...
        block, scores, sourceWeight, ...
        payloadToleranceFraction, options)
% REPLAYROLLINGSAFEROLLOUTPROJECTION Replay the online safety projector.
%
% The replay consumes one recorded predecision block and an aligned vector
% of observable edge scores. Optional current/successor cardinality bounds
% are forwarded to the exact joint rolling-B3 projector. This helper keeps
% offline structured-learning diagnostics on the same admissible action
% set as deployment.

if nargin < 5 || isempty(options)
    options = struct();
end
requiredFields = { ...
    'groupIds', 'receiverIndices', 'senderIndices', ...
    'physicalAdjacency', 'currentTime', ...
    'previousAdjacencyHistory', 'senderPayloadBytes'};
if ~isstruct(block) || ~all(isfield(block, requiredFields))
    error('Rolling-safe replay block is incomplete.');
end
scores = reshape(scores, [], 1);
receiverIndices = reshape(block.receiverIndices, [], 1);
senderIndices = reshape(block.senderIndices, [], 1);
if numel(scores) ~= numel(receiverIndices) || ...
        numel(senderIndices) ~= numel(receiverIndices) || ...
        any(~isfinite(scores))
    error('Rolling-safe replay scores are invalid or misaligned.');
end
nodeCount = numel(block.groupIds);
if ~isequal(size(block.physicalAdjacency), ...
        [nodeCount, nodeCount])
    error('Rolling-safe replay physical adjacency is invalid.');
end
scoreMatrix = -inf(nodeCount);
indices = sub2ind( ...
    [nodeCount, nodeCount], receiverIndices, senderIndices);
scoreMatrix(indices) = scores;

context = struct();
context.localPosteriorBySensor = cell(1, nodeCount);
context.model = struct('dynamicTopologyScenario', ...
    struct('config', struct( ...
        'sensorGroupIds', reshape(block.groupIds, 1, []))));
context.physicalAdjacency = logical(block.physicalAdjacency);
context.currentTime = block.currentTime;
context.previousAdjacencyHistory = ...
    logical(block.previousAdjacencyHistory);
context.previousAdjacencyHistoryCount = ...
    size(block.previousAdjacencyHistory, 3);
if isempty(block.previousAdjacencyHistory)
    context.previousAdjacency = false(nodeCount);
else
    context.previousAdjacency = ...
        block.previousAdjacencyHistory(:, :, end);
end
context.directedMessageBudget = nodeCount;

policyOptions = struct( ...
    'sourceWeight', sourceWeight, ...
    'edgeScoreMatrix', scoreMatrix, ...
    'senderPayloadBytes', block.senderPayloadBytes, ...
    'payloadToleranceFraction', payloadToleranceFraction, ...
    'posteriorUsed', true, ...
    'truthUsed', false, ...
    'currentLinkReliabilityUsed', true, ...
    'minimumCurrentCrossEdges', getField( ...
        options, 'minimumCurrentCrossEdges', 0), ...
    'maximumCurrentCrossEdges', getField( ...
        options, 'maximumCurrentCrossEdges', ...
        numel(unique(block.groupIds, 'stable')) - 1), ...
    'minimumSuccessorCrossEdges', getField( ...
        options, 'minimumSuccessorCrossEdges', 0), ...
    'maximumSuccessorCrossEdges', getField( ...
        options, 'maximumSuccessorCrossEdges', ...
        numel(unique(block.groupIds, 'stable')) - 1));
[adjacency, details] = selectRollingSafeRoutingPolicy( ...
    context, 'external-scores', policyOptions);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
