function [reduced, contract] = ...
    buildFormationB4V48GraphOnlyContext(context)
% BUILDFORMATIONB4V48GRAPHONLYCONTEXT Exact current-page optimizer input.

required = {'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'physicalAdjacency', ...
    'commConfig', 'currentTime'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isstruct(context.commConfig) || ...
        ~isscalar(context.commConfig) || ...
        ~isfield(context.commConfig, 'pDropByEdge') || ...
        ~isa(context.currentTime, 'double') || ...
        ~isscalar(context.currentTime) || ...
        ~isfinite(context.currentTime) || ...
        context.currentTime < 1 || ...
        context.currentTime ~= round(context.currentTime)
    error('FormationB4V48GraphContext:InvalidInput', ...
        'The full current-page graph context is incomplete.');
end
pDrop = context.commConfig.pDropByEdge;
if ~isa(pDrop, 'double') || ~isreal(pDrop) || ...
        ndims(pDrop) ~= 2 || any(~isfinite(pDrop(:))) || ...
        any(pDrop(:) < 0) || any(pDrop(:) > 1)
    error('FormationB4V48GraphContext:FuturePageOrInvalidLinkState', ...
        'V48 requires exactly one finite current pDrop page.');
end

reduced = struct();
reduced.sensorPhysicalUids = ...
    reshape(context.sensorPhysicalUids, 1, []);
reduced.formationPhysicalUidsBySensor = ...
    reshape(context.formationPhysicalUidsBySensor, 1, []);
reduced.physicalAdjacency = logical(context.physicalAdjacency);
reduced.commConfig = struct('pDropByEdge', pDrop);
reduced.currentTime = context.currentTime;

forbiddenNames = {'localPosteriorBySensor', 'posteriorSummaryBySensor', ...
    'previousDeliveryHistory', 'measurements', 'measurement', ...
    'groundTruth', 'targetTrajectories', 'linkUniforms', ...
    'sensorTrajectories', 'futurePolicyData'};
outputFieldNames = fieldnames(reduced);
commFieldNames = fieldnames(reduced.commConfig);
passed = numel(outputFieldNames) == 5 && ...
    all(isfield(reduced, required)) && ...
    numel(commFieldNames) == 1 && ...
    strcmp(commFieldNames{1}, 'pDropByEdge') && ...
    ~any(isfield(reduced, forbiddenNames));
if ~passed
    error('FormationB4V48GraphContext:InternalBoundaryFailure', ...
        'The graph-only context retained a forbidden side channel.');
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v48-graph-only-current-page-context-v1';
payload.currentTime = reduced.currentTime;
payload.outputFieldNames = sort(outputFieldNames)';
payload.communicationFieldNames = sort(commFieldNames)';
payload.currentPDropPageOnly = true;
payload.posteriorPresent = false;
payload.posteriorSummaryPresent = false;
payload.deliveryAcknowledgmentPresent = false;
payload.measurementPresent = false;
payload.truthPresent = false;
payload.futurePagePresent = false;
payload.realizedDeliveryUniformPresent = false;
payload.passed = true;
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
contract = payload;
end
