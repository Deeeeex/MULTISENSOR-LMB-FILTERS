function detected = ...
        isBudgetRecycledFormationRepairV188ExecutionContext(context)
% ISBUDGETRECYCLEDFORMATIONREPAIRV188EXECUTIONCONTEXT Identify V188.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'budget-recycled-formation-repair-v188-context-v1');
end
