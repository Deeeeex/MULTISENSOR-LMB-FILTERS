function validateRegisteredCases(payload)
expectedCount = numel(payload.registeredPresets) * ...
    numel(payload.registeredSeeds);
if payload.registeredCartesianCaseCount ~= expectedCount || ...
        numel(payload.registeredCases) ~= expectedCount || ...
        numel(unique({payload.registeredCases.caseId})) ~= expectedCount || ...
        ~isequal([payload.registeredCases.ordinal], 1:expectedCount)
    error('FormationIndexEquivariantV43:CaseRegistryDrift', ...
        'The v43 case registry is not the frozen Cartesian batch.');
end
cursor = 0;
for presetIdx = 1:numel(payload.registeredPresets)
    for seedIdx = 1:numel(payload.registeredSeeds)
        cursor = cursor + 1;
        item = payload.registeredCases(cursor);
        expectedId = sprintf('%s__seed%d__t%d', ...
            payload.registeredPresets{presetIdx}, ...
            payload.registeredSeeds(seedIdx), item.currentTime);
        if ~strcmp(item.presetName, ...
                payload.registeredPresets{presetIdx}) || ...
                item.seed ~= payload.registeredSeeds(seedIdx) || ...
                ~strcmp(item.sceneRole, payload.sceneRoles{presetIdx}) || ...
                ~strcmp(item.caseId, expectedId) || ...
                numel(item.inputCanonicalSha256) ~= 64 || ...
                numel(item.physicalUidRegistryCanonicalSha256) ~= 64
            error('FormationIndexEquivariantV43:CaseRegistryDrift', ...
                'A v43 case identity record changed or reordered.');
        end
    end
end
end

