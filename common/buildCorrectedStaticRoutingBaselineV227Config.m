function config = buildCorrectedStaticRoutingBaselineV227Config( ...
        armId, scenario, staticRegistration)
% BUILDCORRECTEDSTATICROUTINGBASELINEV227CONFIG Matched KLA arms.

if nargin < 3
    staticRegistration = struct();
end

protocol = getCorrectedStaticRoutingBaselineV227Protocol();
if ~ischar(armId) || ...
        ~any(strcmp(armId, {protocol.dynamicArmId, protocol.staticArmId})) || ...
        ~isstruct(scenario) || ~isscalar(scenario) || ...
        ~all(isfield(scenario, {'numberOfSensors', 'edgeBudget'}))
    error('CorrectedStaticRoutingV227:InvalidConfigInput', ...
        'V227 requires one registered arm and one scenario config.');
end

config = buildMixtureAwareKlaReferenceConfig();
config.missingLabelFusionMode = protocol.receiverMode;
config.eventPolicy = 'alwaysHeavy';
config.dynamicTopologyEnabled = true;
config.dynamicTopologyEdgeBudget = scenario.edgeBudget;
config.topologyMaxEdgeChangeFraction = inf;
config.topologyDirectedEnabled = true;
config.topologyDirectedMessageBudget = ...
    protocol.directedInputsPerReceiver * scenario.numberOfSensors;
config.topologyPolicyHistoryDepth = 2;
config.topologyPolicyObservableContextOnly = true;
config.topologyPolicyPhysicalIdentityEnabled = true;
config.receiverSafeLabelFusionEnabled = false;
config.receiverSafeFormationConditionedOnlinePolicyEnabled = false;
if strcmp(armId, protocol.dynamicArmId)
    config.topologyPolicyName = protocol.dynamicPolicyName;
    config.topologyPolicyFcn = ...
        @selectCorrectedDynamicFormationBackboneV227Policy;
else
    validateStaticRegistration(staticRegistration, ...
        scenario.numberOfSensors, protocol);
    config.topologyPolicyName = protocol.staticPolicyName;
    config.topologyPolicyFcn = @(context) ...
        selectCorrectedFixedStaticFormationBackboneV227Policy( ...
            context, staticRegistration);
end
end

function validateStaticRegistration(registration, nodeCount, protocol)
required = {'contractVersion', 'adjacency', 'fusionWeightMatrix', ...
    'selectionDetails', 'messageCount'};
if ~isstruct(registration) || ~isscalar(registration) || ...
        ~all(isfield(registration, required)) || ...
        ~strcmp(registration.contractVersion, ...
            'corrected-static-routing-v227-registration-v1') || ...
        ~isequal(size(registration.adjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(registration.fusionWeightMatrix), ...
            [nodeCount, nodeCount]) || ...
        registration.messageCount ~= ...
            protocol.directedInputsPerReceiver * nodeCount
    error('CorrectedStaticRoutingV227:InvalidStaticRegistration', ...
        'The fixed route registration is missing or malformed.');
end
end
