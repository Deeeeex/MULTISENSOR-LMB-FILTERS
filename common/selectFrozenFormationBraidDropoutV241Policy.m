function [adjacency, details] = ...
        selectFrozenFormationBraidDropoutV241Policy(context, registration)
% SELECTFROZENFORMATIONBRAIDDROPOUTV241POLICY Fixed formation-tree baseline.
%
% The formation-level tree selected at t=1 is never changed.  While every
% fixed formation pair remains feasible, the sensor gateways are rebuilt
% from the current physical graph.  If that fixed tree is no longer
% realizable, the baseline keeps only still-physical edges from the initial
% sensor route and returns the unavailable KLA mass to each receiver's self
% weight.  This separates formation-tree rerouting from gateway churn.

protocol = getFormationBraidRoutingComparisonV241Protocol();
nodeCount = numel(context.localPosteriorBySensor);
validateRegistration(registration, nodeCount);
[groupIds, members, tree] = fixedFormationContract( ...
    context, registration, nodeCount);
physical = logical(context.physicalAdjacency);
physical(1:nodeCount+1:end) = false;

dropoutUsed = false;
try
    currentRegistration = sensorRegistrationForTree( ...
        tree, physical, members);
    [dominantAdjacency, residualAdjacency, construction] = ...
        buildIndexEquivariantFormationBackboneReference( ...
            groupIds, context.sensorPhysicalUids, ...
            context.formationPhysicalUidsBySensor, context.positions, ...
            currentRegistration, physical, ...
            context.commConfig.pDropByEdge);
    [adjacency, weights, route] = ...
        buildBackbonePreservingResidualRoute( ...
            context, dominantAdjacency, residualAdjacency, ...
            protocol.dominantWeight, protocol.residualWeight);
    if route.duplicateSourceFraction ~= 0 || ...
            nnz(adjacency) ~= 2 * nodeCount || ...
            route.maximumMessagesPerReceiver ~= 2
        error('FormationBraidRoutingV241:InvalidFixedTreeRoute', ...
            'The feasible fixed-tree route violates the two-input contract.');
    end
    dropped = false(nodeCount);
    details = route;
    details.dominantAdjacency = dominantAdjacency;
    details.residualAdjacency = residualAdjacency;
    details.construction = construction;
catch routeError
    fixedTreeInfeasibility = any(strcmp(routeError.identifier, { ...
        'IndexEquivariantFormationRoute:NoCrossAssignment', ...
        'IndexEquivariantFormationRoute:InvalidBackbone'}));
    if ~fixedTreeInfeasibility
        rethrow(routeError);
    end
    dropoutUsed = true;
    adjacency = logical(registration.adjacency) & physical;
    weights = registration.fusionWeightMatrix;
    dropped = logical(registration.adjacency) & ~physical;
    for receiver = 1:nodeCount
        unavailable = find(dropped(receiver, :));
        returnedMass = sum(weights(receiver, unavailable));
        weights(receiver, unavailable) = 0;
        weights(receiver, receiver) = ...
            weights(receiver, receiver) + returnedMass;
    end
    positiveAllowed = adjacency | logical(eye(nodeCount));
    if any(abs(sum(weights, 2) - 1) > 1e-12) || ...
            any(weights(:) < 0) || ...
            any(weights(:) > 0 & ~positiveAllowed(:))
        error('FormationBraidRoutingV241:InvalidDropoutWeights', ...
            'Unavailable route mass was not returned to self weight.');
    end
    details = registration.selectionDetails;
end

details.contractVersion = ...
    'formation-braid-v241-fixed-formation-tree-policy-v1';
details.protocolId = protocol.id;
details.armId = protocol.staticDropoutArmId;
details.mode = ...
    'fixed-formation-tree-current-gateways-with-physical-dropout';
details.backboneMode = details.mode;
details.fusionWeightMatrix = weights;
details.currentFormationTreeAdjacency = tree;
details.previousFormationTreeAdjacency = tree;
details.referenceMessageCount = registration.messageCount;
details.currentMessageCount = nnz(adjacency);
details.dropoutMessageCount = nnz(dropped);
details.dropoutReceiverCount = nnz(any(dropped, 2));
details.returnedFusionMass = sum( ...
    registration.fusionWeightMatrix(dropped));
details.fixedFormationTreeUsed = true;
details.currentGatewayReassignmentUsed = ~dropoutUsed;
details.fixedFormationTreeInfeasible = dropoutUsed;
details.incumbentTreeAvailable = ~dropoutUsed;
details.incumbentAssignmentFeasible = ~dropoutUsed;
details.incumbentTreePreserved = true;
details.treeReselectionUsed = false;
details.initialTreeSelectionUsed = false;
details.routeReselectionUsed = ~dropoutUsed;
details.physicalInfeasibilityFallbackUsed = false;
details.assignmentInfeasibilityFallbackUsed = dropoutUsed;
details.formationEdgeReplacementCount = 0;
details.currentPhysicalActionSetUsed = true;
details.currentPhysicalFeasibilityChecked = true;
details.currentGeometryUsed = ~dropoutUsed;
details.currentLinkReliabilityUsed = ~dropoutUsed;
details.previousPolicyHistoryUsed = false;
details.posteriorUsed = false;
details.posteriorPayloadMetadataUsed = false;
details.truthUsed = false;
details.measurementUsed = false;
details.futureOutcomeUsed = false;
details.realizedDeliveryUniformsUsed = false;
details.trackingOutcomeScored = false;
details.referenceFallbackUsed = false;
if dropoutUsed
    phase = 'fixed-formation-tree-physical-dropout';
else
    phase = 'fixed-formation-tree-current-gateways';
end
details.scheduleCertificate = buildSchedule( ...
    context.currentTime, nnz(adjacency), 2 * nodeCount, ...
    nnz(dropped), phase, ~dropoutUsed);
end

function validateRegistration(registration, nodeCount)
required = {'contractVersion', 'adjacency', 'fusionWeightMatrix', ...
    'selectionDetails', 'messageCount'};
if ~isstruct(registration) || ~isscalar(registration) || ...
        ~all(isfield(registration, required)) || ...
        ~strcmp(registration.contractVersion, ...
            'formation-braid-v241-initial-route-registration-v1') || ...
        ~isequal(size(registration.adjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(registration.fusionWeightMatrix), ...
            [nodeCount, nodeCount]) || ...
        registration.messageCount ~= 2 * nodeCount
    error('FormationBraidRoutingV241:InvalidRegistration', ...
        'The fixed-tree registration is malformed.');
end
end

function [groupIds, members, tree] = fixedFormationContract( ...
        context, registration, nodeCount)
required = {'model', 'physicalAdjacency', 'positions', ...
    'sensorPhysicalUids', 'formationPhysicalUidsBySensor', 'commConfig'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds') || ...
        ~isfield(context.commConfig, 'pDropByEdge')
    error('FormationBraidRoutingV241:InvalidContext', ...
        'The fixed-tree current physical context is incomplete.');
end
rawGroupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
formationUidsBySensor = reshape( ...
    context.formationPhysicalUidsBySensor, 1, []);
if numel(rawGroupIds) ~= nodeCount || ...
        numel(formationUidsBySensor) ~= nodeCount || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(context.positions), [2, nodeCount]) || ...
        ~isequal(size(context.commConfig.pDropByEdge), ...
            [nodeCount, nodeCount])
    error('FormationBraidRoutingV241:InvalidContext', ...
        'The fixed-tree matrices or formation membership are malformed.');
end

labels = unique(rawGroupIds);
formationCount = numel(labels);
members = cell(1, formationCount);
uids = zeros(1, formationCount);
for formationIdx = 1:formationCount
    currentMembers = find(rawGroupIds == labels(formationIdx));
    currentUids = unique(formationUidsBySensor(currentMembers));
    if numel(currentMembers) < 3 || numel(currentUids) ~= 1
        error('FormationBraidRoutingV241:InvalidContext', ...
            'Each fixed-tree formation needs one UID and three sensors.');
    end
    members{formationIdx} = currentMembers;
    uids(formationIdx) = currentUids;
end
[~, order] = sort(uids);
members = members(order);
groupIds = zeros(1, nodeCount);
for formationIdx = 1:formationCount
    groupIds(members{formationIdx}) = formationIdx;
end

selection = registration.selectionDetails;
if ~isstruct(selection) || ...
        ~isfield(selection, 'currentFormationTreeAdjacency')
    error('FormationBraidRoutingV241:InvalidRegistration', ...
        'The initial formation tree is absent from the registration.');
end
tree = logical(selection.currentFormationTreeAdjacency);
if ~isequal(size(tree), [formationCount, formationCount]) || ...
        ~isequal(tree, tree') || ...
        nnz(triu(tree, 1)) ~= formationCount - 1 || ...
        ~isConnected(tree)
    error('FormationBraidRoutingV241:InvalidRegistration', ...
        'The registered formation adjacency is not a tree.');
end
end

function registration = sensorRegistrationForTree(tree, physical, members)
nodeCount = size(physical, 1);
registration = false(nodeCount);
for left = 1:numel(members)-1
    for right = left+1:numel(members)
        if ~tree(left, right)
            continue;
        end
        leftMembers = members{left};
        rightMembers = members{right};
        block = physical(leftMembers, rightMembers);
        registration(leftMembers, rightMembers) = block;
        registration(rightMembers, leftMembers) = block';
    end
end
end

function connected = isConnected(adjacency)
visited = false(1, size(adjacency, 1));
frontier = 1;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if visited(node), continue; end
    visited(node) = true;
    frontier = [frontier, find(adjacency(node, :) & ~visited)]; %#ok<AGROW>
end
connected = all(visited);
end

function schedule = buildSchedule(currentTime, currentMessages, ...
        referenceMessages, dropoutMessages, phase, gatewaysCurrent)
schedule = struct( ...
    'contractVersion', ...
        'formation-braid-v241-fixed-formation-tree-schedule-v1', ...
    'currentTime', currentTime, 'phase', phase, ...
    'phaseIndex', 1, 'gatewayIndices', zeros(1, 0), ...
    'formationIds', zeros(1, 0), 'sourceIndices', zeros(1, 0), ...
    'proposalGatewayCount', 0, 'selectedGatewayCount', 0, ...
    'pendingAcquisitionTime', NaN, ...
    'messageParityPassed', currentMessages == referenceMessages, ...
    'rollingSensorStrong', dropoutMessages == 0, ...
    'rollingFormationStrong', dropoutMessages == 0, ...
    'referenceFallbackUsed', false, 'cycleSelected', true, ...
    'fixedFormationTreeUsed', true, ...
    'currentGatewayReassignmentUsed', gatewaysCurrent, ...
    'treeReselectionUsed', false, ...
    'routeReselectionUsed', gatewaysCurrent, ...
    'dropoutMessageCount', dropoutMessages, ...
    'truthReadAtRuntime', false, ...
    'futureOutcomeReadAtRuntime', false);
end
