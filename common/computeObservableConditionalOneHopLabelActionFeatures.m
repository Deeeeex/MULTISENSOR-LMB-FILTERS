function [values, names, details] = ...
        computeObservableConditionalOneHopLabelActionFeatures( ...
            receiverPosteriorBeforeFirst, receiverPosteriorAfterFirst, ...
            firstAction, secondSourceObject, peerSecondObjects, model, ...
            receiverIdx, secondSourceIdx, currentTime, context)
% COMPUTEOBSERVABLECONDITIONALONEHOPLABELACTIONFEATURES Set-aware stage two.
%
% The feature vector augments the ordinary source-label summary with the
% receiver's post-first-action LMB cardinality distribution. It reads no
% truth, future measurements, or numeric label identifier as a feature.

requiredFirst = {'label', 'source', 'sourceObject', ...
    'safetyScore', 'payloadBytes'};
if ~isstruct(firstAction) || ~isscalar(firstAction) || ...
        ~all(isfield(firstAction, requiredFirst)) || ...
        isempty(secondSourceObject) || ...
        secondSourceObject.numberOfGmComponents <= 0
    error('ConditionalOneHopFeatures:InvalidInput', ...
        'A complete first action and second source label are required.');
end
secondLabel = [secondSourceObject.birthTime; ...
    secondSourceObject.birthLocation];
receiverSecondObject = findLabelObject( ...
    receiverPosteriorAfterFirst, secondLabel);
[baseValues, baseNames, baseDetails] = ...
    computeObservableOneHopLabelActionFeatures( ...
        receiverSecondObject, secondSourceObject, peerSecondObjects, ...
        model, receiverIdx, secondSourceIdx, currentTime, context);
before = posteriorCardinalitySummary( ...
    receiverPosteriorBeforeFirst, resolveActiveThreshold(context));
after = posteriorCardinalitySummary( ...
    receiverPosteriorAfterFirst, resolveActiveThreshold(context));
firstReceiverObject = findLabelObject( ...
    receiverPosteriorBeforeFirst, firstAction.label);
firstReceiverExistence = 0;
if ~isempty(firstReceiverObject)
    firstReceiverExistence = firstReceiverObject.r;
end
firstRiskReduction = ...
    computeObservableLmbLabelBayesRisk(firstReceiverObject, model) - ...
    computeObservableLmbLabelBayesRisk(firstAction.sourceObject, model);
ageGap = abs(firstAction.sourceObject.birthTime - ...
    secondSourceObject.birthTime) / max(currentTime, 1);
setNames = { ...
    'set_expected_cardinality_fraction', ...
    'set_map_cardinality_fraction', ...
    'set_cardinality_map_probability', ...
    'set_cardinality_margin', ...
    'set_mean_existence_entropy', ...
    'set_map_boundary_existence_gap', ...
    'first_expected_cardinality_delta_fraction', ...
    'first_existence_delta', ...
    'first_risk_reduction', ...
    'first_safety_score', ...
    'same_source_as_first', ...
    'first_second_label_age_gap', ...
    'combined_log_payload_kib'};
setValues = [ ...
    after.expectedFraction, ...
    after.mapFraction, ...
    after.mapProbability, ...
    after.mapMargin, ...
    after.meanExistenceEntropy, ...
    after.boundaryExistenceGap, ...
    after.expectedFraction - before.expectedFraction, ...
    firstAction.sourceObject.r - firstReceiverExistence, ...
    firstRiskReduction, ...
    firstAction.safetyScore, ...
    double(firstAction.source == secondSourceIdx), ...
    ageGap, ...
    log1p((firstAction.payloadBytes + ...
        baseDetails.payloadBytes) / 1024)];
values = [baseValues, setValues];
names = [baseNames, setNames];
if any(~isfinite(values)) || numel(values) ~= numel(names)
    error('ConditionalOneHopFeatures:InvalidValues', ...
        'Conditional one-hop features became invalid.');
end
details = struct();
details.contractVersion = ...
    'conditional-observable-one-hop-label-action-features-v173-v1';
details.payloadBytes = baseDetails.payloadBytes;
details.expectedCardinalityFraction = after.expectedFraction;
details.mapCardinalityFraction = after.mapFraction;
details.mapProbability = after.mapProbability;
details.mapMargin = after.mapMargin;
details.boundaryExistenceGap = after.boundaryExistenceGap;
details.firstExistenceDelta = ...
    firstAction.sourceObject.r - firstReceiverExistence;
details.truthUsed = false;
details.futureInformationUsed = false;
details.numericLabelIdentifiersUsedAsFeatures = false;
end

function summary = posteriorCardinalitySummary(posterior, threshold)
objects = reshape(posterior, 1, []);
if ~isempty(objects)
    objects = objects([objects.r] > threshold & ...
        [objects.numberOfGmComponents] > 0);
end
r = min(max(reshape([objects.r], 1, []), 1e-9), 1 - 1e-9);
count = numel(r);
if count == 0
    summary = struct( ...
        'expectedFraction', 0, 'mapFraction', 0, ...
        'mapProbability', 1, 'mapMargin', 1, ...
        'meanExistenceEntropy', 0, 'boundaryExistenceGap', 1);
    return;
end
pmf = 1;
for value = r
    pmf = conv(pmf, [1 - value, value]);
end
[sortedProbability, order] = sort(pmf, 'descend');
mapCardinality = order(1) - 1;
runnerUp = 0;
if numel(sortedProbability) > 1
    runnerUp = sortedProbability(2);
end
sortedR = sort(r, 'descend');
if mapCardinality == 0
    boundaryGap = 1 - sortedR(1);
elseif mapCardinality >= count
    boundaryGap = sortedR(end);
else
    boundaryGap = sortedR(mapCardinality) - ...
        sortedR(mapCardinality + 1);
end
summary = struct();
summary.expectedFraction = sum(r) / count;
summary.mapFraction = mapCardinality / count;
summary.mapProbability = sortedProbability(1);
summary.mapMargin = sortedProbability(1) - runnerUp;
summary.meanExistenceEntropy = mean( ...
    -r .* log(r) - (1 - r) .* log(1 - r));
summary.boundaryExistenceGap = boundaryGap;
end

function object = findLabelObject(objects, label)
object = [];
for idx = 1:numel(objects)
    if objects(idx).birthTime == label(1) && ...
            objects(idx).birthLocation == label(2)
        object = objects(idx);
        return;
    end
end
end

function threshold = resolveActiveThreshold(context)
threshold = 1e-2;
if isstruct(context) && ...
        isfield(context, 'activeExistenceThreshold') && ...
        isscalar(context.activeExistenceThreshold) && ...
        isfinite(context.activeExistenceThreshold)
    threshold = context.activeExistenceThreshold;
end
end
