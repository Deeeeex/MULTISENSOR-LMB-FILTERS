function protocol = getEtaSafeDominantEdgeReplacementV225Protocol()
% GETETASAFEDOMINANTEDGEREPLACEMENTV225PROTOCOL Label-graph rewiring.

base = getEtaSafeSemanticInputRoutingV223Protocol();
protocol = base;
protocol.id = 'eta-safe-dominant-edge-replacement-v225-v1';
protocol.contractVersion = ...
    'eta-safe-dominant-edge-replacement-v225-protocol-v1';
protocol.baseProtocolId = base.id;
protocol.inputRouteWeightMode = 'dominant-nonself-transfer';
protocol.semanticFusionMode = ...
    'single-ordinary-label-wise-kla-with-dominant-nonself-edge-transfer';
protocol.replacedInputSelection = ...
    'largest-positive-topology-weight-nonself-input-carrying-label';
protocol.selfInputReplacementAllowed = false;
protocol.totalLabelWeightPreserved = true;
protocol.receiverSpecificApplication = true;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v225');
protocol.evidenceBoundary = [ ...
    'V225 is a frozen development mechanism screen for receiver-specific ', ...
    'effective label-graph rewiring. For the selected complete Bernoulli ', ...
    'Gaussian-mixture label, each receiver preserves its self input and ', ...
    'all other ordinary inputs, transfers the largest positive nonself ', ...
    'label-input weight to one physically delivered external source, and ', ...
    'executes the ordinary KLA once. Total label-wise KLA weight and the ', ...
    'V223 communication ledger are preserved. The receiver falls back ', ...
    'after paying the transmitted bytes when no replaceable input exists ', ...
    'or the powered-GM eta/existence gate fails. The source and label are ', ...
    'offline teacher choices, so this screen cannot support deployment or ', ...
    'generalization claims.'];

if ~strcmp(protocol.inputRouteWeightMode, ...
        'dominant-nonself-transfer') || ...
        protocol.selfInputReplacementAllowed || ...
        ~protocol.totalLabelWeightPreserved || ...
        ~protocol.etaProjectionEnabled || ...
        ~protocol.receiverSpecificApplication || ...
        protocol.postFusionResidualUpdateAllowed || ...
        protocol.onlinePolicyImplemented || ...
        protocol.validationClaimAllowed
    error('EtaSafeDominantEdgeReplacementV225:ProtocolDrift', ...
        'The frozen V225 protocol is inconsistent.');
end
end
