function [adjacency, details] = ...
        selectParetoSafeResidualAugmentationV246Policy(context)
% SELECTPARETOSAFERESIDUALAUGMENTATIONV246POLICY Add exact-value residuals.

timerId = tic;
protocol = getParetoSafeResidualAugmentationV246Protocol();
[minimumAdjacency, minimumDetails] = ...
    selectCausalMinimumFormationBackboneV242Policy(context);
nodeCount = numel(context.localPosteriorBySensor);
groupIds = resolveGroupIds(context, nodeCount);
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
residualQuota = ceil(formationCount / 2);
candidateMask = logical(minimumDetails.localResidualAdjacency);
candidateMask = candidateMask & logical(context.physicalAdjacency);
referenceWeights = minimumDetails.referenceFusionWeights;
minimumWeights = minimumDetails.fusionWeightMatrix;
senderBytes = estimateSenderBytes(context);
minimumBytes = routeBytes(minimumAdjacency, senderBytes);
fullBytes = routeBytes(minimumDetails.referenceAdjacency, senderBytes);
byteGap = max(fullBytes - minimumBytes, 0);
addedByteBudget = protocol.byteGapSpendFraction * byteGap;

base = evaluateRoute(context, minimumAdjacency, minimumWeights, ...
    groupIds, protocol, struct());
records = enumerateCandidates(context, candidateMask, ...
    minimumAdjacency, minimumWeights, referenceWeights, ...
    senderBytes, addedByteBudget, groupIds, base, protocol);
[proposalMask, selectionOrder] = selectProposal( ...
    records, groupIds, residualQuota, addedByteBudget, ...
    previousAdjacency(context, nodeCount), protocol);
[adjacency, fusionWeights, selectedMask, final, ...
    jointBackoffCount] = validateJointProposal(context, ...
        minimumAdjacency, minimumWeights, referenceWeights, ...
        proposalMask, selectionOrder, records, groupIds, base, protocol);

selectedAddedBytes = routeBytes(selectedMask, senderBytes);
assertFinalRoute(adjacency, fusionWeights, minimumAdjacency, ...
    candidateMask, selectedMask, context, groupIds, ...
    residualQuota, selectedAddedBytes, addedByteBudget, protocol);
details = buildDetails(minimumDetails, minimumAdjacency, ...
    adjacency, fusionWeights, candidateMask, selectedMask, records, ...
    selectionOrder, base, final, senderBytes, minimumBytes, fullBytes, ...
    addedByteBudget, selectedAddedBytes, residualQuota, ...
    jointBackoffCount, protocol, toc(timerId), context.currentTime, ...
    groupIds);
end

function records = enumerateCandidates(context, candidateMask, ...
        baseAdjacency, baseWeights, referenceWeights, senderBytes, ...
        addedByteBudget, groupIds, base, protocol)
[receivers, senders] = find(candidateMask);
records = repmat(emptyRecord(), 1, numel(receivers));
for candidateIdx = 1:numel(receivers)
    receiver = receivers(candidateIdx);
    sender = senders(candidateIdx);
    payloadBytes = senderBytes(sender);
    candidateAdjacency = baseAdjacency;
    candidateAdjacency(receiver, sender) = true;
    candidateWeights = restoreReferenceWeight( ...
        baseWeights, referenceWeights, receiver, sender);
    evaluated = emptyEvaluation();
    if payloadBytes <= addedByteBudget + protocol.numericalTolerance
        evaluated = evaluateRoute(context, candidateAdjacency, ...
            candidateWeights, groupIds, protocol, ...
            incrementalOptions(base, baseAdjacency, baseWeights));
    end
    [admissible, score, gains] = assessCandidate( ...
        base, evaluated, payloadBytes, protocol);
    records(candidateIdx) = struct( ...
        'receiver', receiver, ...
        'sender', sender, ...
        'formationId', groupIds(receiver), ...
        'payloadBytes', payloadBytes, ...
        'admissible', admissible, ...
        'score', score, ...
        'relativeTaskGain', gains(1), ...
        'relativeDisagreementGain', gains(2), ...
        'taskRisk', evaluated.taskRisk, ...
        'disagreementRisk', evaluated.disagreementRisk, ...
        'maximumFormationTaskIncrease', ...
            maximumIncrease(evaluated.formationTaskRisk, ...
                base.formationTaskRisk), ...
        'maximumFormationDisagreementIncrease', ...
            maximumIncrease(evaluated.formationDisagreementRisk, ...
                base.formationDisagreementRisk), ...
        'existenceRetentionRisk', ...
            evaluated.existenceRetentionRisk, ...
        'protectedDownwardCrossingCount', ...
            evaluated.protectedDownwardCrossingCount);
end
end

function [mask, order] = selectProposal(records, groupIds, quota, ...
        byteBudget, previous, protocol)
nodeCount = numel(groupIds);
mask = false(nodeCount);
order = zeros(1, 0);
if isempty(records)
    return;
end
rows = zeros(numel(records), 6);
for idx = 1:numel(records)
    incumbent = previous(records(idx).receiver, records(idx).sender);
    rows(idx, :) = [ ...
        -records(idx).score, -double(incumbent), ...
        records(idx).formationId, records(idx).receiver, ...
        records(idx).sender, idx];
end
rows = sortrows(rows, [1, 2, 3, 4, 5]);
usedFormations = zeros(1, 0);
usedBytes = 0;
for cursor = 1:size(rows, 1)
    idx = rows(cursor, 6);
    record = records(idx);
    if ~record.admissible || numel(order) >= quota || ...
            sum(usedFormations == record.formationId) >= ...
                protocol.maximumResidualsPerFormation || ...
            usedBytes + record.payloadBytes > ...
                byteBudget + protocol.numericalTolerance
        continue;
    end
    mask(record.receiver, record.sender) = true;
    order(end + 1) = idx; %#ok<AGROW>
    usedFormations(end + 1) = record.formationId; %#ok<AGROW>
    usedBytes = usedBytes + record.payloadBytes;
end
end

function [adjacency, weights, selectedMask, final, backoffCount] = ...
        validateJointProposal(context, baseAdjacency, baseWeights, ...
            referenceWeights, proposalMask, selectionOrder, records, ...
            groupIds, base, protocol)
selectedMask = proposalMask;
backoffCount = 0;
while true
    [adjacency, weights] = applyResidualMask( ...
        baseAdjacency, baseWeights, referenceWeights, selectedMask);
    if ~any(selectedMask(:))
        final = base;
        return;
    end
    final = evaluateRoute(context, adjacency, weights, ...
        groupIds, protocol, incrementalOptions( ...
            base, baseAdjacency, baseWeights));
    if routeParetoSafe(base, final, protocol)
        return;
    end
    lastRecordIdx = selectionOrder(end - backoffCount);
    receiver = records(lastRecordIdx).receiver;
    sender = records(lastRecordIdx).sender;
    if ~selectedMask(receiver, sender)
        error('ParetoSafeResidualV246:InvalidBackoffOrder', ...
            'The joint residual backoff order is malformed.');
    end
    selectedMask(receiver, sender) = false;
    backoffCount = backoffCount + 1;
end
end

function evaluation = evaluateRoute(context, adjacency, weights, ...
        groupIds, protocol, incremental)
options = struct( ...
    'aggregationMode', 'mean', ...
    'tailFraction', protocol.disagreementTailFraction, ...
    'maximumIncomingCount', protocol.maximumIncomingCount);
if ~isempty(fieldnames(incremental))
    options.referenceNetworkDetails = incremental.details;
    options.referenceAdjacency = incremental.adjacency;
    options.referenceFusionWeights = incremental.weights;
end
[disagreementRisk, disagreementDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, adjacency, weights, options);
taskOptions = struct( ...
    'receiverTailFraction', protocol.receiverTailFraction, ...
    'receiverTailWeight', protocol.receiverTailWeight);
[taskRisk, taskDetails] = computeExpectedLmbPosteriorTaskRiskV92( ...
    disagreementDetails, groupIds, context.model, taskOptions);
formationOptions = struct( ...
    'referenceModeIndex', 1, ...
    'receiverTailFraction', protocol.receiverTailFraction, ...
    'receiverTailWeight', protocol.receiverTailWeight);
[~, formationDetails] = ...
    computeFormationModePosteriorBayesRiskObjectives( ...
        {disagreementDetails.receiverDistributions, ...
         disagreementDetails.receiverDistributions}, ...
        groupIds, formationOptions);
evaluation = struct( ...
    'valid', true, ...
    'adjacency', logical(adjacency), ...
    'weights', weights, ...
    'disagreementRisk', disagreementRisk, ...
    'disagreementDetails', disagreementDetails, ...
    'taskRisk', taskRisk, ...
    'taskDetails', taskDetails, ...
    'formationTaskRisk', ...
        formationDetails.formationRiskByMode(:, 1), ...
    'formationDisagreementRisk', formationDisagreementRisk( ...
        disagreementDetails.expectedPairRisk, groupIds, protocol), ...
    'existenceRetentionRisk', 0, ...
    'protectedDownwardCrossingCount', 0);
if ~isempty(fieldnames(incremental))
    [retentionRisk, retention] = ...
        computeLmbReferenceExistenceRetentionRisk( ...
            incremental.details.receiverDistributions, ...
            disagreementDetails.receiverDistributions, ...
            groupIds, struct( ...
                'referenceSupportThreshold', ...
                    protocol.protectedReferenceExistence, ...
                'decisionExistenceThreshold', ...
                    protocol.decisionExistenceThreshold, ...
                'receiverTailFraction', ...
                    protocol.receiverTailFraction, ...
                'receiverTailWeight', protocol.receiverTailWeight));
    evaluation.existenceRetentionRisk = retentionRisk;
    evaluation.protectedDownwardCrossingCount = ...
        protectedCrossingCount(retention, protocol);
end
end

function options = incrementalOptions(base, adjacency, weights)
options = struct( ...
    'details', base.disagreementDetails, ...
    'adjacency', logical(adjacency), ...
    'weights', weights);
end

function [allowed, score, gains] = assessCandidate( ...
        base, candidate, payloadBytes, protocol)
gains = [-inf, -inf];
score = -inf;
allowed = candidate.valid && payloadBytes > 0;
if ~allowed
    return;
end
gains(1) = relativeLowerGain(base.taskRisk, candidate.taskRisk);
gains(2) = relativeLowerGain( ...
    base.disagreementRisk, candidate.disagreementRisk);
allowed = routeParetoSafe(base, candidate, protocol) && ...
    gains(1) >= protocol.minimumRelativeTaskGain && ...
    gains(2) >= protocol.minimumRelativeDisagreementGain;
if allowed
    score = min(gains) / payloadBytes;
end
end

function allowed = routeParetoSafe(base, candidate, protocol)
tol = protocol.numericalTolerance;
allowed = candidate.valid && ...
    candidate.taskRisk <= base.taskRisk + tol && ...
    candidate.disagreementRisk <= base.disagreementRisk + tol && ...
    all(candidate.formationTaskRisk <= ...
        base.formationTaskRisk + tol) && ...
    all(candidate.formationDisagreementRisk <= ...
        base.formationDisagreementRisk + tol) && ...
    candidate.existenceRetentionRisk <= ...
        protocol.maximumExistenceRetentionRisk + tol && ...
    candidate.protectedDownwardCrossingCount == 0;
end

function [adjacency, weights] = applyResidualMask( ...
        baseAdjacency, baseWeights, referenceWeights, selectedMask)
adjacency = logical(baseAdjacency | selectedMask);
weights = baseWeights;
[receivers, senders] = find(selectedMask);
for idx = 1:numel(receivers)
    weights = restoreReferenceWeight( ...
        weights, referenceWeights, receivers(idx), senders(idx));
end
end

function weights = restoreReferenceWeight( ...
        weights, referenceWeights, receiver, sender)
value = referenceWeights(receiver, sender);
if value <= 0 || weights(receiver, sender) > 0 || ...
        weights(receiver, receiver) + 1e-12 < value
    error('ParetoSafeResidualV246:InvalidReferenceResidual', ...
        'A candidate residual cannot restore its V240 KLA mass.');
end
weights(receiver, sender) = value;
weights(receiver, receiver) = ...
    weights(receiver, receiver) - value;
end

function count = protectedCrossingCount(retention, protocol)
count = 0;
for receiver = 1:numel( ...
        retention.expectedReferenceExistenceByReceiver)
    reference = retention. ...
        expectedReferenceExistenceByReceiver{receiver};
    candidate = retention. ...
        expectedCandidateExistenceByReceiver{receiver};
    count = count + nnz( ...
        reference >= protocol.protectedReferenceExistence & ...
        candidate < protocol.decisionExistenceThreshold);
end
end

function risk = formationDisagreementRisk(pairRisk, groupIds, protocol)
groups = unique(groupIds, 'stable');
risk = zeros(numel(groups), 1);
for formationIdx = 1:numel(groups)
    members = find(groupIds == groups(formationIdx));
    block = pairRisk(members, members);
    values = block(triu(true(numel(members)), 1));
    if isempty(values)
        continue;
    end
    sorted = sort(values, 'descend');
    tailCount = max(1, ceil( ...
        protocol.disagreementTailFraction * numel(values)));
    risk(formationIdx) = ...
        (1 - protocol.disagreementTailWeight) * mean(values) + ...
        protocol.disagreementTailWeight * mean(sorted(1:tailCount));
end
end

function bytes = estimateSenderBytes(context)
nodeCount = numel(context.localPosteriorBySensor);
bytes = zeros(1, nodeCount);
for sender = 1:nodeCount
    stats = estimateLmbPayloadSize( ...
        context.localPosteriorBySensor{sender}, context.model, 2);
    bytes(sender) = stats.estimatedBytes;
end
end

function value = routeBytes(adjacency, senderBytes)
value = sum(sum(logical(adjacency), 1) .* senderBytes);
end

function value = relativeLowerGain(reference, candidate)
value = (reference - candidate) / max(abs(reference), eps);
end

function value = maximumIncrease(candidate, reference)
if isempty(candidate) || isempty(reference) || ...
        numel(candidate) ~= numel(reference)
    value = inf;
else
    value = max(candidate(:) - reference(:));
end
end

function previous = previousAdjacency(context, nodeCount)
previous = false(nodeCount);
if isfield(context, 'previousAdjacencyHistory') && ...
        ~isempty(context.previousAdjacencyHistory)
    previous = logical(context.previousAdjacencyHistory(:, :, end));
end
end

function groupIds = resolveGroupIds(context, nodeCount)
config = context.model.dynamicTopologyScenario.config;
groupIds = reshape(config.sensorGroupIds, 1, []);
if numel(groupIds) ~= nodeCount || any(~isfinite(groupIds))
    error('ParetoSafeResidualV246:InvalidFormationIds', ...
        'The observable formation identities are malformed.');
end
end

function assertFinalRoute(adjacency, weights, minimumAdjacency, ...
        candidateMask, selectedMask, context, groupIds, quota, ...
        addedBytes, byteBudget, protocol)
nodeCount = size(adjacency, 1);
groups = unique(groupIds, 'stable');
formationCounts = zeros(1, numel(groups));
for formationIdx = 1:numel(groups)
    formationCounts(formationIdx) = nnz( ...
        selectedMask(groupIds == groups(formationIdx), :));
end
passed = all(all(adjacency | ~minimumAdjacency)) && ...
    ~any(selectedMask(:) & ~candidateMask(:)) && ...
    nnz(selectedMask) <= quota && ...
    all(formationCounts <= protocol.maximumResidualsPerFormation) && ...
    addedBytes <= byteBudget + protocol.numericalTolerance && ...
    ~any(adjacency(:) & ~logical(context.physicalAdjacency(:))) && ...
    isStronglyConnected(adjacency) && ...
    all(abs(sum(weights, 2) - 1) <= 1e-10) && ...
    all(weights(:) >= -protocol.numericalTolerance);
allowedWeights = adjacency | logical(eye(nodeCount));
passed = passed && ...
    ~any(weights(:) > 0 & ~allowedWeights(:));
if ~passed
    error('ParetoSafeResidualV246:InvalidFinalRoute', ...
        'The selected residual route violates a hard invariant.');
end
end

