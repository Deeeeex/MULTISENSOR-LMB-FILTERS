function detected = isReceiverSelectiveHandoffV104ExecutionContext(context)
% ISRECEIVERSELECTIVEHANDOFFV104EXECUTIONCONTEXT Identify V104.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'receiver-selective-v104-context-v1');
end
