function bundle = loadCvarResidualGraphPolicyShards(splitName)
% LOADCVARRESIDUALGRAPHPOLICYSHARDS Load only an authorized frozen split.

if nargin < 1 || isempty(splitName)
    splitName = 'training';
end
protocol = getCvarResidualGraphPolicyDatasetProtocol();
splitName = lower(strrep(char(splitName), '_', '-'));
switch splitName
    case 'training'
        if ~protocol.modelTrainingAuthorized
            error('CVaR graph model training is not authorized.');
        end
        requestedSeeds = protocol.trainingSeeds;
    case {'development', 'development-validation'}
        if ~protocol.developmentEvaluationAuthorized
            error(['CVaR graph development labels remain sealed ', ...
                'until a frozen training-only model is registered.']);
        end
        splitName = 'development-validation';
        requestedSeeds = ...
            protocol.developmentValidationSeeds;
    otherwise
        error('Unknown CVaR graph dataset split: %s.', splitName);
end

validateAudit(protocol);
[registered, shardIndices] = ismember( ...
    requestedSeeds, protocol.registeredShardSeeds);
if any(~registered) || ...
        numel(unique(shardIndices)) ~= numel(shardIndices)
    error('CVaR graph split is not fully registered.');
end

graphBlocks = repmat(emptyGraphBlock(), 1, 0);
behaviorBlocks = repmat(emptyBehaviorBlock(), 1, 0);
records = repmat(emptyRecord(), 1, numel(shardIndices));
edgeFeatureNames = {};
nodeFeatureNames = {};
for requestedIdx = 1:numel(shardIndices)
    shardIdx = shardIndices(requestedIdx);
    path = protocol.registeredShardPaths{shardIdx};
    expectedSha256 = ...
        protocol.registeredShardSha256{shardIdx};
    if exist(path, 'file') ~= 2 || ...
            ~strcmp(computeFileSha256(path), expectedSha256)
        error('CVaR graph shard hash mismatch: %s', path);
    end
    loaded = load(path, 'dataset');
    if ~isfield(loaded, 'dataset')
        error('CVaR graph shard has no dataset: %s', path);
    end
    dataset = loaded.dataset;
    validateDataset(dataset, requestedSeeds(requestedIdx), ...
        protocol);
    [edgeFeatureNames, nodeFeatureNames] = ...
        validateFeatureNames(dataset.graphBlocks, ...
            edgeFeatureNames, nodeFeatureNames);
    graphBlocks = [graphBlocks, ...
        dataset.graphBlocks]; %#ok<AGROW>
    behaviorBlocks = [behaviorBlocks, ...
        dataset.behaviorDataset.blocks]; %#ok<AGROW>
    records(requestedIdx) = struct( ...
        'seed', requestedSeeds(requestedIdx), ...
        'path', path, ...
        'sha256', expectedSha256, ...
        'generationCommit', ...
            dataset.generationGitCommit, ...
        'stateCount', numel(dataset.graphBlocks));
end

stateKeys = [[graphBlocks.seed]', ...
    [graphBlocks.currentTime]'];
[~, order] = sortrows(stateKeys, [1, 2]);
graphBlocks = graphBlocks(order);
behaviorBlocks = behaviorBlocks(order);
expectedStateCount = numel(requestedSeeds) * ...
    numel(protocol.learningLabelTimes);
if numel(graphBlocks) ~= expectedStateCount || ...
        numel(behaviorBlocks) ~= expectedStateCount
    error('CVaR graph split has incomplete state coverage.');
end
for blockIdx = 1:numel(graphBlocks)
    graphBlock = graphBlocks(blockIdx);
    behaviorBlock = behaviorBlocks(blockIdx);
    if graphBlock.seed ~= behaviorBlock.seed || ...
            graphBlock.currentTime ~= ...
                behaviorBlock.currentTime
        error('CVaR graph/behavior block order is inconsistent.');
    end
end

bundle = struct();
bundle.protocolId = protocol.id;
bundle.contractVersion = ...
    protocol.datasetContractVersion;
bundle.splitName = splitName;
bundle.seeds = requestedSeeds;
bundle.snapshotTimes = protocol.learningLabelTimes;
bundle.graphBlocks = graphBlocks;
bundle.behaviorBlocks = behaviorBlocks;
bundle.edgeFeatureNames = edgeFeatureNames;
bundle.nodeFeatureNames = nodeFeatureNames;
bundle.featureContractSha256 = ...
    protocol.fullShardFeatureContractSha256;
bundle.datasetSetSha256 = ...
    protocol.fullShardDatasetSetSha256;
bundle.shardRecords = records;
bundle.featuresUseTruth = false;
bundle.targetsUseTruth = true;
bundle.developmentLabelsOpened = ...
    strcmp(splitName, 'development-validation');
end

function validateAudit(protocol)
path = protocol.fullShardAuditPath;
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), ...
            protocol.fullShardAuditSha256)
    error('CVaR graph aggregate audit hash mismatch.');
end
loaded = load(path, 'audit');
if ~isfield(loaded, 'audit')
    error('CVaR graph aggregate audit is missing.');
end
audit = loaded.audit;
if ~audit.allGatesPassed || audit.preflightOnly || ...
        ~strcmp(audit.protocolId, protocol.id) || ...
        ~strcmp(audit.datasetSetSha256, ...
            protocol.fullShardDatasetSetSha256) || ...
        ~strcmp(audit.featureContractSha256, ...
            protocol.fullShardFeatureContractSha256) || ...
        ~isequal(sort(audit.seeds), ...
            sort(protocol.registeredShardSeeds))
    error('CVaR graph aggregate audit registry is invalid.');
end
end

function validateDataset(dataset, expectedSeed, protocol)
required = { ...
    'protocolId', 'contractVersion', ...
    'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', ...
    'generationResearchWorktreeDirty', ...
    'seeds', 'labelTimes', 'graphBlocks', ...
    'behaviorDataset', 'featureContractSha256', ...
    'featuresUseTruth', 'featuresUseFutureOutcome', ...
    'behaviorUsesTruth', 'behaviorUsesFutureOutcome', ...
    'teacherTargetsUseTruth', ...
    'teacherTargetsUseFutureOutcome'};
if ~isstruct(dataset) || ...
        ~all(isfield(dataset, required)) || ...
        ~strcmp(dataset.protocolId, protocol.id) || ...
        ~strcmp(dataset.contractVersion, ...
            protocol.datasetContractVersion) || ...
        ~strcmp(dataset.generationGitCommit, ...
            protocol.shardGenerationCommit) || ...
        dataset.generationTrackedWorktreeDirty || ...
        ~isempty(dataset.generationUntrackedSourceFiles) || ...
        dataset.generationResearchWorktreeDirty || ...
        ~isequal(dataset.seeds, expectedSeed) || ...
        ~isequal(dataset.labelTimes, ...
            protocol.learningLabelTimes) || ...
        ~strcmp(dataset.featureContractSha256, ...
            protocol.fullShardFeatureContractSha256) || ...
        dataset.featuresUseTruth || ...
        dataset.featuresUseFutureOutcome || ...
        dataset.behaviorUsesTruth || ...
        dataset.behaviorUsesFutureOutcome || ...
        ~dataset.teacherTargetsUseTruth || ...
        dataset.teacherTargetsUseFutureOutcome || ...
        numel(dataset.graphBlocks) ~= ...
            numel(protocol.learningLabelTimes) || ...
        numel(dataset.behaviorDataset.blocks) ~= ...
            numel(protocol.learningLabelTimes)
    error('CVaR graph registered shard envelope is invalid.');
end
end

function [edgeNames, nodeNames] = validateFeatureNames( ...
        blocks, edgeNames, nodeNames)
for block = blocks
    currentEdgeNames = ...
        reshape(block.edgeFeatureNames, 1, []);
    currentNodeNames = ...
        reshape(block.nodeFeatureNames, 1, []);
    if isempty(edgeNames)
        edgeNames = currentEdgeNames;
        nodeNames = currentNodeNames;
    elseif ~isequal(edgeNames, currentEdgeNames) || ...
            ~isequal(nodeNames, currentNodeNames)
        error('CVaR graph feature names differ across blocks.');
    end
end
end

function block = emptyGraphBlock()
block = struct( ...
    'seed', 0, 'currentTime', 0, ...
    'behaviorBlockIndex', 0, ...
    'featureContractSha256', '', ...
    'edgeFeatures', zeros(0, 0, 0), ...
    'edgeFeatureNames', {{}}, ...
    'nodeFeatures', zeros(0, 0), ...
    'nodeFeatureNames', {{}}, ...
    'receiverIndices', zeros(0, 1), ...
    'senderIndices', zeros(0, 1), ...
    'residualWeightGrid', zeros(1, 0), ...
    'residualBaselineSourcesByReceiver', zeros(1, 0), ...
    'nodeRiskTarget', zeros(1, 0), ...
    'nodeCvarMaskTarget', false(1, 0), ...
    'edgeTaskAdvantageTarget', zeros(0, 0), ...
    'edgeProtectionAdvantageTarget', zeros(0, 0), ...
    'edgeProtectionObservedMask', false(0, 0), ...
    'edgeReferenceSafeTarget', false(0, 0), ...
    'selectedEdgeWeightTarget', false(0, 0), ...
    'teacherAdjacency', false(0, 0), ...
    'teacherResidualAdjacency', false(0, 0), ...
    'teacherCrossReceivers', zeros(1, 0), ...
    'teacherCrossSenders', zeros(1, 0), ...
    'teacherCrossResidualWeights', zeros(1, 0), ...
    'teacherDetails', struct(), ...
    'featuresUseTruth', false, ...
    'featuresUseFutureOutcome', false, ...
    'targetsUseTruth', true, ...
    'targetsUseFutureOutcome', false, ...
    'deployable', false);
end

