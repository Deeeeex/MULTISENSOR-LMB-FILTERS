    'seed', 0, 'currentTime', 0, ...
    'relativeTime', 0, 'actionCode', 0, ...
    'actionTruthUsed', false, ...
    'features', zeros(0, 0), ...
    'featureNames', {{}}, ...
    'featureMetadata', struct(), ...
    'receiverIndices', zeros(0, 1), ...
    'senderIndices', zeros(0, 1), ...
    'selectedCrossMask', false(0, 1), ...
    'selectedCrossEdgeCount', 0, ...
    'selectedSourcesByReceiver', zeros(1, 0), ...
    'selectedAdjacency', false(0, 0), ...
