function detected = isTimeExpandedCarrierSwitchV120ExecutionContext(context)
% ISTIMEEXPANDEDCARRIERSWITCHV120EXECUTIONCONTEXT Identify V120.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'time-expanded-carrier-switch-v120-context-v1');
end
