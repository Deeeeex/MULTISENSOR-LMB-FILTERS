function [values, names, details] = ...
        buildFormationLabelActionModeFeaturesV202(candidate)
% BUILDFORMATIONLABELACTIONMODEFEATURESV202 Separate label failure modes.
%
% This transform consumes one truth-free V190 formation-label candidate.
% It exposes bounded primitives and two interpretable mode-evidence terms.
% The terms classify the kind of opportunity; they are not action values or
% admission thresholds.

required = { ...
    'minimumRiskReduction', 'minimumReceiverExistence', ...
    'receiverCompatibilityMedian', 'sourceQuality', ...
    'sourceObservationOpportunity', 'opportunityMedian', ...
    'peerConsensusMinimum', 'peerConsensusMedian', ...
    'sourcePositionTraceNormalized', ...
    'receiverPositionTraceMedianNormalized', ...
    'positionDistanceMedianNormalized', ...
    'positionDistanceMaximumNormalized', ...
    'formationSizeFraction', 'sourcePhysicalDegreeFraction'};
if ~isstruct(candidate) || ~isscalar(candidate) || ...
        any(~isfield(candidate, required))
    error('FormationLabelActionModeV202:InvalidCandidate', ...
        'A scalar V190 candidate with the mode primitives is required.');
end
raw = cellfun(@(name) candidate.(name), required);
if any(~isnumeric(raw)) || any(~isfinite(raw)) || ...
        candidate.sourcePositionTraceNormalized < 0 || ...
        candidate.receiverPositionTraceMedianNormalized < 0 || ...
        candidate.positionDistanceMedianNormalized < 0 || ...
        candidate.positionDistanceMaximumNormalized < 0
    error('FormationLabelActionModeV202:InvalidCandidate', ...
        'The mode primitives must be finite and physically valid.');
end

risk = positiveBound(candidate.minimumRiskReduction);
receiverExistence = clamp01(candidate.minimumReceiverExistence);
receiverDeficit = 1 - receiverExistence;
compatibility = clamp01(candidate.receiverCompatibilityMedian);
sourceQuality = clamp01(candidate.sourceQuality);
sourceOpportunity = clamp01(candidate.sourceObservationOpportunity);
handoverOpportunity = clamp01(candidate.opportunityMedian);
peerMinimum = clamp01(candidate.peerConsensusMinimum);
peerMedian = clamp01(candidate.peerConsensusMedian);

traceRatio = (candidate.receiverPositionTraceMedianNormalized + eps) / ...
    (candidate.sourcePositionTraceNormalized + eps);
logPrecisionGain = max(log(traceRatio), 0);
boundedPrecisionGain = logPrecisionGain / (1 + logPrecisionGain);
medianDistance = positiveBound( ...
    candidate.positionDistanceMedianNormalized);
maximumDistance = positiveBound( ...
    candidate.positionDistanceMaximumNormalized);
formationSize = clamp01(candidate.formationSizeFraction);
sourceDegree = clamp01(candidate.sourcePhysicalDegreeFraction);

handoverPressure = max(receiverDeficit, handoverOpportunity);
handoverEvidence = risk * sourceQuality * ...
    (1 - compatibility) * handoverPressure;
precisionEvidence = risk * sourceQuality * compatibility * ...
    boundedPrecisionGain;

names = { ...
    'bounded_risk_reduction', ...
    'receiver_existence', ...
    'receiver_existence_deficit', ...
    'receiver_source_compatibility', ...
    'bounded_log_precision_gain', ...
    'source_quality', ...
    'source_observation_opportunity', ...
    'handover_opportunity', ...
    'peer_consensus_minimum', ...
    'peer_consensus_median', ...
    'bounded_position_distance_median', ...
    'bounded_position_distance_maximum', ...
    'formation_size_fraction', ...
    'source_physical_degree_fraction', ...
    'observation_handover_evidence', ...
    'precision_refresh_evidence'};
values = [ ...
    risk, receiverExistence, receiverDeficit, compatibility, ...
    boundedPrecisionGain, sourceQuality, sourceOpportunity, ...
    handoverOpportunity, peerMinimum, peerMedian, medianDistance, ...
    maximumDistance, formationSize, sourceDegree, ...
    handoverEvidence, precisionEvidence];
if any(~isfinite(values)) || any(values < 0) || any(values > 1)
    error('FormationLabelActionModeV202:InvalidFeatureRange', ...
        'Every V202 mode feature must lie in [0,1].');
end

details = struct();
details.contractVersion = ...
    'formation-label-action-mode-features-v202-v1';
details.featureNames = names;
details.logPrecisionGain = logPrecisionGain;
details.traceRatio = traceRatio;
details.handoverPressure = handoverPressure;
details.observationHandoverEvidence = handoverEvidence;
details.precisionRefreshEvidence = precisionEvidence;
details.modeEvidenceIsActionValue = false;
details.thresholdApplied = false;
details.truthUsed = false;
details.futureInformationUsed = false;
details.numericIdentifiersUsed = false;
end

function value = positiveBound(value)
value = max(value, 0);
value = value / (1 + value);
end

function value = clamp01(value)
value = min(max(value, 0), 1);
end
