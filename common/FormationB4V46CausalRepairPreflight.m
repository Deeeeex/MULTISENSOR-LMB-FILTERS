function result = FormationB4V46CausalRepairPreflight(options)
% FORMATIONB4V46CAUSALREPAIRPREFLIGHT Structural-only repaired-route audit.
%
% Every audited step exposes exactly one current geometry/physical/pDrop
% page plus the immutable t=1 registered graph, physical UIDs, group IDs,
% and absolute time.  The fixed V46 projector repairs that registered graph
% before the existing V43 reference and synchronized B=4 schedule builders
% are called.  Executed pages, rather than same-snapshot schedule pages, are
% retained for all rolling-window checks.
%
% This development preflight never generates or reads tracking data or
% realized delivery draws and cannot authorize a tracking claim.

if nargin < 1 || isempty(options)
    options = struct();
end
allowedFields = {'presets', 'seeds', 'timeIndices', ...
    'progressEvery', 'testTamperMode'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationB4V46Preflight:InvalidOptions', ...
        'The V46 causal-repair preflight options are malformed.');
end

protocol = getFormationCausalMinimalEditV46Protocol();
presets = getField(options, 'presets', protocol.registeredPresets);
seeds = getField(options, 'seeds', protocol.registeredSeeds);
timeIndices = getField(options, 'timeIndices', []);
progressEvery = getField(options, 'progressEvery', 20);
testTamperMode = lower(char(getField(options, 'testTamperMode', '')));
validateRequestedCases(presets, seeds, protocol);
seeds = reshape(seeds, 1, []);
if ~isempty(timeIndices) && (~isnumeric(timeIndices) || ...
        ~isreal(timeIndices) || any(~isfinite(timeIndices)) || ...
        any(timeIndices ~= round(timeIndices)) || any(timeIndices < 1) || ...
        numel(unique(timeIndices)) ~= numel(timeIndices) || ...
        ~isequal(reshape(timeIndices, 1, []), ...
            sort(reshape(timeIndices, 1, []))) || ...
        (numel(timeIndices) > 1 && any(diff(timeIndices) ~= 1)))
    error('FormationB4V46Preflight:InvalidOptions', ...
        ['timeIndices must be a strictly contiguous increasing ', ...
         'integer interval.']);
end
if ~isscalar(progressEvery) || ~isnumeric(progressEvery) || ...
        ~isreal(progressEvery) || ~isfinite(progressEvery) || ...
        progressEvery < 1 || progressEvery ~= round(progressEvery) || ...
        ~ismember(testTamperMode, {'', 'uniform-field', 'future-page', ...
            'negative-weight', 'non-subset', 'zero-weight-edge', ...
            'projection-certificate', 'projection-no-feasible'})
    error('FormationB4V46Preflight:InvalidOptions', ...
        'The progress or test-tamper option is invalid.');
end

caseCount = numel(presets) * numel(seeds);
cases = repmat(emptyCase(), 1, caseCount);
cursor = 0;
for presetIdx = 1:numel(presets)
    for seedIdx = 1:numel(seeds)
        cursor = cursor + 1;
        presetName = presets{presetIdx};
        seed = seeds(seedIdx);
        fprintf(['FormationB4V46 preflight case %d/%d: ', ...
            '%s seed=%d\n'], cursor, caseCount, presetName, seed);
        [caseItem, failure] = buildCase(presetName, seed, ...
            timeIndices, progressEvery, testTamperMode, protocol);
        if ~isempty(failure.identifier)
            fprintf(2, ['FormationB4V46 FAIL-CLOSED preset=%s ', ...
                'seed=%d time=%d phase=%s cause=%s message=%s\n'], ...
                failure.presetName, failure.seed, failure.currentTime, ...
                failure.phase, failure.identifier, failure.message);
            error('FormationB4V46Preflight:FailedClosed', ...
                ['preset=%s seed=%d time=%d phase=%s cause=%s ', ...
                 'message=%s'], failure.presetName, failure.seed, ...
                failure.currentTime, failure.phase, failure.identifier, ...
                failure.message);
        end
        cases(cursor) = caseItem;
    end
end

fullRegistryRequested = isequal(presets, protocol.registeredPresets) && ...
    isequal(seeds, protocol.registeredSeeds);
allFullHorizon = all([cases.fullHorizonCovered]);
allStructuralChecksPassed = all([cases.structuralChecksPassed]);
result = struct();
result.contractVersion = ...
    'formation-b4-v46-causal-repair-preflight-development-v1';
result.protocolId = protocol.id;
result.protocolCanonicalSha256 = protocol.canonicalSha256;
result.presets = presets;
result.seeds = seeds;
result.caseCount = caseCount;
result.period = protocol.period;
result.arms = protocol.primaryArms;
result.cases = cases;
result.failureRecords = repmat(emptyFailure(), 1, 0);
result.fullRegistryRequested = fullRegistryRequested;
result.allCasesFullHorizonCovered = allFullHorizon;
result.allStructuralChecksPassed = allStructuralChecksPassed;
result.projectionCertificateScope = ...
    'cross-backbone-connectivity-and-distinct-receiver-matching-only';
result.fullV43RouteCompositionPassed = ...
    all([cases.fullV43RouteCompositionPassed]);
result.requiredFull32CaseCount = protocol.registeredCartesianCaseCount;
result.dynamicMatrixProductAuditPerformed = ...
    all([cases.dynamicMatrixProductAuditPerformed]);
result.full32CasePreflightPassed = fullRegistryRequested && ...
    caseCount == protocol.registeredCartesianCaseCount && ...
    allFullHorizon && allStructuralChecksPassed && ...
    result.fullV43RouteCompositionPassed && ...
    result.dynamicMatrixProductAuditPerformed && isempty(testTamperMode);
result.routeReceivesCurrentPageOnly = true;
result.registeredBaseImmutableAcrossEpisode = true;
result.posteriorUsed = false;
result.truthUsed = false;
result.measurementUsed = false;
result.futurePagePassedToProjectionOrRoute = false;
result.realizedDeliveryUniformsUsed = false;
result.trackingOutcomeScored = false;
result.trackingOutcomeAuthorized = false;
result.validationClaimAllowed = false;
result.developmentEvidenceOnly = true;
result.testTamperMode = testTamperMode;
result.canonicalSha256 = '';
result.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(result, 'canonicalSha256'));
fprintf(['FormationB4V46 preflight complete: cases=%d ', ...
    'full32=%d sha256=%s\n'], caseCount, ...
    result.full32CasePreflightPassed, result.canonicalSha256);
end

function [value, failure] = buildCase(presetName, seed, ...
        requestedTimes, progressEvery, testTamperMode, protocol)
value = emptyCase();
failure = emptyFailure();
failure.presetName = presetName;
failure.seed = seed;
failure.currentTime = 0;
failure.phase = 'scenario-materialization';
try
    rng(seed, 'twister');
    config = buildDynamicTopologyScenarioConfig(presetName);
    [sensorTrajectories, trajectoryMetadata] = ...
        generateMultiFormationTrajectories(config);
    graph = materializeCausalPhysicalGraph(config, sensorTrajectories);
    registeredBase = FormationB4V45BuildCausalRegisteredBaseGraph( ...
        config.formationBackboneMode, config.sensorGroupIds, ...
        trajectoryMetadata.sensorPhysicalUids, ...
        trajectoryMetadata.formationPhysicalUidsBySensor, ...
        graph.positions(:, :, 1), graph.physicalAdjacency(:, :, 1));
    graph.formationBackbonePairs = ...
        registeredBase.formationGroupLabelPairs;
    [pDropByEdge, ~] = buildDynamicTopologyLinkSchedule(config, graph);
    identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
    validateMaterializedScenario(config, sensorTrajectories, ...
        trajectoryMetadata, graph, pDropByEdge, identity, registeredBase);
catch errorInfo
    failure.identifier = nonemptyIdentifier(errorInfo.identifier);
    failure.message = errorInfo.message;
    return;
end

if isempty(requestedTimes)
    auditedTimes = 1:config.simulationLength;
else
    auditedTimes = reshape(requestedTimes, 1, []);
    if any(auditedTimes > config.simulationLength)
        failure.identifier = 'FormationB4V46Preflight:InvalidTimeRange';
        failure.message = sprintf( ...
            'Requested time exceeds simulationLength=%d.', ...
            config.simulationLength);
        return;
    end
end

nodeCount = config.numberOfSensors;
formationCount = config.formationCount;
timeCount = numel(auditedTimes);
window = protocol.period;
syncAdjacencyHistory = false(nodeCount, nodeCount, 0);
syncWeightHistory = zeros(nodeCount, nodeCount, 0);
referenceCounts = zeros(1, timeCount);
syncCounts = zeros(1, timeCount);
registeredRemovalCounts = zeros(1, timeCount);
nonregisteredAdditionCounts = zeros(1, timeCount);
forcedRemovalCounts = zeros(1, timeCount);
topologyCandidateCounts = zeros(1, timeCount);
assignmentCandidateCounts = zeros(1, timeCount);
projectionWorkCounts = zeros(1, timeCount);
currentInputHashes = cell(1, timeCount);
projectedBaseHashes = cell(1, timeCount);
projectionEditHashes = cell(1, timeCount);
projectionCandidateHashes = cell(1, timeCount);
projectionCertificateHashes = cell(1, timeCount);
referenceHashes = cell(1, timeCount);
syncHashes = cell(1, timeCount);
projectedPairUids = cell(1, timeCount);
removedPairUids = cell(1, timeCount);
addedPairUids = cell(1, timeCount);
rollingProductHashes = cell(1, 0);
rollingProductDobrushin = zeros(1, 0);
rollingProductCenteredSpectralNorm = zeros(1, 0);
rollingProductMaximumCenteredRowL2 = zeros(1, 0);
rollingWindowCount = 0;
alignedCycleCount = 0;

for localTimeIdx = 1:timeCount
    currentTime = auditedTimes(localTimeIdx);
    failure.currentTime = currentTime;
    failure.phase = 'current-page-input';
    try
        routeInput = struct( ...
            'positions', graph.positions(:, :, currentTime), ...
            'physicalAdjacency', logical( ...
                graph.physicalAdjacency(:, :, currentTime)), ...
            'pDropByEdge', pDropByEdge(:, :, currentTime), ...
            'registeredBaseAdjacency', logical( ...
                registeredBase.baseAdjacency), ...
            'sensorPhysicalUids', ...
                trajectoryMetadata.sensorPhysicalUids, ...
            'formationPhysicalUidsBySensor', ...
                trajectoryMetadata.formationPhysicalUidsBySensor, ...
            'sensorGroupIds', config.sensorGroupIds, ...
            'currentTime', currentTime);
        if localTimeIdx == 1
            routeInput = applyInputTamper(routeInput, testTamperMode);
        end
        validateCurrentPageInput(routeInput, nodeCount);

        failure.phase = 'current-page-projection';
        [projectedBaseAdjacency, certificate] = ...
            projectCausalMinimalEditFormationBackbone( ...
                routeInput.sensorGroupIds, ...
                routeInput.sensorPhysicalUids, ...
                routeInput.formationPhysicalUidsBySensor, ...
                routeInput.positions, ...
                routeInput.registeredBaseAdjacency, ...
                routeInput.physicalAdjacency, ...
                routeInput.pDropByEdge);
        if localTimeIdx == 1 && ...
                strcmp(testTamperMode, 'projection-certificate')
            certificate.canonicalSha256(1) = ...
                replacementHex(certificate.canonicalSha256(1));
        end
        projectionEvidence = assertProjectionCertificate( ...
            routeInput, projectedBaseAdjacency, certificate, protocol);

        failure.phase = 'repaired-reference-and-sync-page';
        context = adaptCurrentPageToV43Context( ...
            routeInput, projectedBaseAdjacency);
        [syncSequence, syncWeightSequence, syncDetails] = ...
            buildIndexEquivariantResidualDutyCycleSchedule( ...
                context, dutyOptions(protocol));
        assertBoundaryDetails(syncDetails, protocol);
        currentPhase = mod(currentTime - 1, window) + 1;
        if syncDetails.currentAbsolutePhase ~= currentPhase
            error('FormationB4V46Preflight:PhaseMismatch', ...
                'The synchronized B=4 absolute phase drifted.');
        end
        referenceAdjacency = logical(syncDetails.referenceAdjacency);
        referenceWeights = syncDetails.referenceFusionWeights;
        syncAdjacency = logical(syncSequence(:, :, currentPhase));
        syncWeights = syncWeightSequence(:, :, currentPhase);
        if localTimeIdx == 1
            [syncAdjacency, syncWeights] = applyPageTamper( ...
                syncAdjacency, syncWeights, referenceAdjacency, ...
                routeInput.physicalAdjacency, testTamperMode);
        end
        assertRoutePage(referenceAdjacency, referenceWeights, ...
            routeInput.physicalAdjacency, [], ...
            routeInput.formationPhysicalUidsBySensor, ...
            'v46-repaired-reference', true);
        assertRoutePage(syncAdjacency, syncWeights, ...
            routeInput.physicalAdjacency, referenceAdjacency, ...
            routeInput.formationPhysicalUidsBySensor, ...
            'v46-repaired-sync-b4', false);
        if nnz(referenceAdjacency) ~= 2 * nodeCount
            error('FormationB4V46Preflight:ReferenceMessageCount', ...
                'The repaired V43 reference does not have exactly 2N messages.');
        end

        syncAdjacencyHistory = appendWindowPage( ...
            syncAdjacencyHistory, syncAdjacency, window);
        syncWeightHistory = appendWindowPage( ...
            syncWeightHistory, syncWeights, window);
        if size(syncAdjacencyHistory, 3) == window
            rollingWindowCount = rollingWindowCount + 1;
            windowTimes = auditedTimes( ...
                localTimeIdx - window + 1:localTimeIdx);
            productAudit = assertRollingWindow( ...
                syncAdjacencyHistory, syncWeightHistory, ...
                routeInput.formationPhysicalUidsBySensor, windowTimes);
            rollingProductHashes{rollingWindowCount} = ...
                productAudit.canonicalSha256;
            rollingProductDobrushin(rollingWindowCount) = ...
                productAudit.dobrushin;
            rollingProductCenteredSpectralNorm(rollingWindowCount) = ...
                productAudit.centeredSpectralNorm;
            rollingProductMaximumCenteredRowL2(rollingWindowCount) = ...
                productAudit.maximumCenteredRowL2;
        end

        referenceCounts(localTimeIdx) = nnz(referenceAdjacency);
        syncCounts(localTimeIdx) = nnz(syncAdjacency);
        if mod(currentTime, window) == 0
            cycleMask = auditedTimes >= currentTime - window + 1 & ...
                auditedTimes <= currentTime;
            if nnz(cycleMask) == window && ...
                    isequal(auditedTimes(cycleMask), ...
                        currentTime - window + 1:currentTime)
                alignedCycleCount = alignedCycleCount + 1;
                assertAlignedSaving(referenceCounts(cycleMask), ...
                    syncCounts(cycleMask));
            end
        end

        registeredRemovalCounts(localTimeIdx) = ...
            certificate.registeredRemovalCount;
        nonregisteredAdditionCounts(localTimeIdx) = ...
            certificate.nonregisteredAdditionCount;
        forcedRemovalCounts(localTimeIdx) = ...
            certificate.forcedRegisteredRemovalCount;
        topologyCandidateCounts(localTimeIdx) = ...
            certificate.searchCandidateCounts.topologyCandidateCount;
        assignmentCandidateCounts(localTimeIdx) = ...
            certificate.searchCandidateCounts. ...
                receiverAssignmentCandidateCount;
        projectionWorkCounts(localTimeIdx) = ...
            certificate.searchCandidateCounts.workUnitCount;
        currentInputHashes{localTimeIdx} = ...
            projectionEvidence.currentInputCanonicalSha256;
        projectedBaseHashes{localTimeIdx} = ...
            projectionEvidence.projectedBaseCanonicalSha256;
        projectionEditHashes{localTimeIdx} = ...
            projectionEvidence.editCanonicalSha256;
        projectionCandidateHashes{localTimeIdx} = ...
            projectionEvidence.selectedCandidateCanonicalSha256;
        projectionCertificateHashes{localTimeIdx} = ...
            certificate.canonicalSha256;
        referenceHashes{localTimeIdx} = routePageHash( ...
            referenceAdjacency, referenceWeights);
        syncHashes{localTimeIdx} = routePageHash( ...
            syncAdjacency, syncWeights);
        projectedPairUids{localTimeIdx} = ...
            certificate.projectedPairPhysicalUids;
        removedPairUids{localTimeIdx} = ...
            certificate.removedRegisteredPairPhysicalUids;
        addedPairUids{localTimeIdx} = ...
            certificate.addedNonregisteredPairPhysicalUids;
        if localTimeIdx == 1 || localTimeIdx == timeCount || ...
                mod(localTimeIdx, progressEvery) == 0
            fprintf('  %s seed=%d t=%d/%d passed\n', ...
                presetName, seed, currentTime, config.simulationLength);
        end
    catch errorInfo
        failure.identifier = nonemptyIdentifier(errorInfo.identifier);
        failure.message = errorInfo.message;
        return;
    end
end

fullHorizonCovered = isequal(auditedTimes, 1:config.simulationLength);
expectedRollingWindows = max(timeCount - window + 1, 0);
if rollingWindowCount ~= expectedRollingWindows
    failure.currentTime = auditedTimes(end);
    failure.phase = 'coverage-accounting';
    failure.identifier = 'FormationB4V46Preflight:CoverageDrift';
    failure.message = 'The actual rolling-window count drifted.';
    return;
end
if fullHorizonCovered && alignedCycleCount ~= ...
        config.simulationLength / window
    failure.currentTime = config.simulationLength;
    failure.phase = 'coverage-accounting';
    failure.identifier = 'FormationB4V46Preflight:CoverageDrift';
    failure.message = 'The full-horizon aligned-cycle count drifted.';
    return;
end

repairMask = registeredRemovalCounts > 0 | ...
    nonregisteredAdditionCounts > 0;
repairPageCount = nnz(repairMask);
firstRepairTime = NaN;
if repairPageCount > 0
    firstRepairTime = auditedTimes(find(repairMask, 1, 'first'));
end
value = emptyCase();
value.caseId = sprintf('%s__seed%d__v46-repaired-route', ...
    presetName, seed);
value.presetName = presetName;
value.seed = seed;
value.simulationLength = config.simulationLength;
value.auditedTimes = auditedTimes;
value.auditedTimeCount = timeCount;
value.fullHorizonCovered = fullHorizonCovered;
value.nodeCount = nodeCount;
value.formationCount = formationCount;
value.physicalUidRegistryCanonicalSha256 = identity.canonicalSha256;
value.registeredBaseGraphCanonicalSha256 = registeredBase.canonicalSha256;
value.registeredBaseGraphSelectionMode = registeredBase.selectionMode;
value.registeredFormationPairPhysicalUids = ...
    registeredBase.formationPairPhysicalUids;
value.currentPageInputCanonicalSha256ByTime = currentInputHashes;
value.projectedBaseCanonicalSha256ByTime = projectedBaseHashes;
value.projectionEditCanonicalSha256ByTime = projectionEditHashes;
value.selectedProjectionCandidateCanonicalSha256ByTime = ...
    projectionCandidateHashes;
value.projectionCertificateCanonicalSha256ByTime = ...
    projectionCertificateHashes;
value.projectedFormationPairPhysicalUidsByTime = projectedPairUids;
value.removedRegisteredPairPhysicalUidsByTime = removedPairUids;
value.addedNonregisteredPairPhysicalUidsByTime = addedPairUids;
value.projectionRegisteredRemovalCountByTime = registeredRemovalCounts;
value.projectionForcedRemovalCountByTime = forcedRemovalCounts;
value.projectionNonregisteredAdditionCountByTime = ...
    nonregisteredAdditionCounts;
value.projectionTopologyCandidateCountByTime = topologyCandidateCounts;
value.projectionReceiverAssignmentCandidateCountByTime = ...
    assignmentCandidateCounts;
value.projectionWorkUnitCountByTime = projectionWorkCounts;
value.repairPageCount = repairPageCount;
value.firstRepairTime = firstRepairTime;
value.totalRegisteredRemovalCount = sum(registeredRemovalCounts);
value.totalNonregisteredAdditionCount = ...
    sum(nonregisteredAdditionCounts);
value.referencePageCanonicalSha256ByTime = referenceHashes;
value.syncB4PageCanonicalSha256ByTime = syncHashes;
value.referenceMessageCountByTime = referenceCounts;
value.syncB4MessageCountByTime = syncCounts;
value.rollingWindowCount = rollingWindowCount;
value.expectedRollingWindowCountForAuditedSpan = expectedRollingWindows;
value.rollingB4MatrixProductCanonicalSha256ByWindow = ...
    rollingProductHashes;
value.rollingB4MatrixProductDobrushinByWindow = ...
    rollingProductDobrushin;
value.rollingB4MatrixProductCenteredSpectralNormByWindow = ...
    rollingProductCenteredSpectralNorm;
value.rollingB4MatrixProductMaximumCenteredRowL2ByWindow = ...
    rollingProductMaximumCenteredRowL2;
value.rollingB4MatrixProductMultiplicationOrder = ...
    'P(t:t-3)=W(t)*W(t-1)*W(t-2)*W(t-3)';
value.rollingB4MatrixProductCentering = [ ...
    'spectral=H*P*H;row-dispersion=P-mean(P,1);', ...
    'H=I-ones(N)/N'];
value.worstRollingB4MatrixProductDobrushin = ...
    finiteWorst(rollingProductDobrushin);
value.medianRollingB4MatrixProductDobrushin = ...
    finiteMedian(rollingProductDobrushin);
value.worstRollingB4MatrixProductCenteredSpectralNorm = ...
    finiteWorst(rollingProductCenteredSpectralNorm);
value.medianRollingB4MatrixProductCenteredSpectralNorm = ...
    finiteMedian(rollingProductCenteredSpectralNorm);
value.worstRollingB4MatrixProductMaximumCenteredRowL2 = ...
    finiteWorst(rollingProductMaximumCenteredRowL2);
value.medianRollingB4MatrixProductMaximumCenteredRowL2 = ...
    finiteMedian(rollingProductMaximumCenteredRowL2);
value.alignedCycleCount = alignedCycleCount;
value.everyAlignedCycleSavingFraction = ...
    protocol.candidateAlignedMessageSavingFraction;
value.noOpPagesExactlyPreservedRegisteredBase = all( ...
    repairMask | cellfun(@(hash) strcmp(hash, ...
        computeCanonicalValueSha256(logical( ...
            registeredBase.baseAdjacency))), projectedBaseHashes));
value.projectionCertificateScope = ...
    'cross-backbone-connectivity-and-distinct-receiver-matching-only';
value.projectionBackboneCertificatePassed = true;
value.fullV43RouteCompositionPassed = true;
value.dynamicMatrixProductAuditPerformed = rollingWindowCount > 0;
value.structuralChecksPassed = true;
value.routeReceivesCurrentPageOnly = true;
value.registeredBaseImmutableAcrossEpisode = true;
value.posteriorUsed = false;
value.truthUsed = false;
value.measurementUsed = false;
value.futurePagePassedToProjectionOrRoute = false;
value.realizedDeliveryUniformsUsed = false;
value.trackingOutcomeScored = false;
value.trackingOutcomeAuthorized = false;
value.validationClaimAllowed = false;
value.developmentEvidenceOnly = true;
value.canonicalSha256 = '';
value.canonicalSha256 = computeCanonicalValueSha256( ...
    rmfield(value, 'canonicalSha256'));
end

function routeInput = applyInputTamper(routeInput, mode)
switch mode
    case 'uniform-field'
        routeInput.realizedDeliveryUniforms = ...
            zeros(size(routeInput.physicalAdjacency));
    case 'future-page'
        routeInput.physicalAdjacency = repmat( ...
            routeInput.physicalAdjacency, 1, 1, 2);
    case 'projection-no-feasible'
        routeInput.physicalAdjacency(:) = false;
end
end

function [adjacency, weights] = applyPageTamper(adjacency, weights, ...
        referenceAdjacency, physicalAdjacency, mode)
switch mode
    case 'negative-weight'
        weights(1, 1) = -0.01;
    case 'zero-weight-edge'
        [receiver, sender] = find(adjacency, 1);
        removedWeight = weights(receiver, sender);
        weights(receiver, sender) = 0;
        weights(receiver, receiver) = ...
            weights(receiver, receiver) + removedWeight;
    case 'non-subset'
        nodeCount = size(referenceAdjacency, 1);
        candidates = physicalAdjacency & ~referenceAdjacency & ...
            ~logical(eye(nodeCount));
        linear = find(candidates, 1);
        if isempty(linear)
            error('FormationB4V46Preflight:TamperUnavailable', ...
                'No current physical non-reference edge exists to tamper.');
        end
        adjacency(linear) = true;
end
end

function validateMaterializedScenario(config, trajectories, metadata, ...
        graph, pDropByEdge, identity, registeredBase)
nodeCount = config.numberOfSensors;
timeCount = config.simulationLength;
if numel(trajectories) ~= nodeCount || ...
        ~isequal(size(graph.physicalAdjacency), ...
            [nodeCount, nodeCount, timeCount]) || ...
        ~isequal(size(pDropByEdge), ...
            [nodeCount, nodeCount, timeCount]) || ...
        ~isequal(size(graph.positions), [2, nodeCount, timeCount]) || ...
        ~isequal(metadata.sensorPhysicalUids, ...
            identity.sensorPhysicalUids) || ...
        ~isequal(metadata.formationPhysicalUidsBySensor, ...
            identity.formationPhysicalUidsBySensor) || ...
        ~strcmp(metadata.physicalIdentityRegistryCanonicalSha256, ...
            identity.canonicalSha256) || ...
        ~isstruct(registeredBase) || ...
        ~strcmp(registeredBase.contractVersion, ...
            'formation-b4-v45-causal-registered-base-graph-v1') || ...
        registeredBase.futureGeometryUsed || ...
        registeredBase.futurePhysicalPageUsed || ...
        registeredBase.linkProbabilityUsed || ...
        registeredBase.posteriorUsed || registeredBase.truthUsed || ...
        registeredBase.measurementUsed || ...
        registeredBase.realizedDeliveryUniformsUsed
    error('FormationB4V46Preflight:ScenarioIdentityDrift', ...
        'The planned sensor/link scenario or immutable UID registry drifted.');
end
end

function graph = materializeCausalPhysicalGraph(config, trajectories)
nodeCount = config.numberOfSensors;
timeCount = config.simulationLength;
positions = zeros(2, nodeCount, timeCount);
for sensorIdx = 1:nodeCount
    positions(:, sensorIdx, :) = reshape( ...
        trajectories{sensorIdx}(1:2, :), 2, 1, timeCount);
end
distances = zeros(nodeCount, nodeCount, timeCount);
physical = false(nodeCount, nodeCount, timeCount);
for currentTime = 1:timeCount
    page = positions(:, :, currentTime);
    for leftIdx = 1:nodeCount-1
        delta = page(:, leftIdx+1:end) - page(:, leftIdx);
        values = sqrt(sum(delta.^2, 1));
        distances(leftIdx, leftIdx+1:end, currentTime) = values;
        distances(leftIdx+1:end, leftIdx, currentTime) = values';
        if isfinite(config.commRange)
            available = values <= config.commRange;
        else
            available = true(size(values));
        end
        physical(leftIdx, leftIdx+1:end, currentTime) = available;
        physical(leftIdx+1:end, leftIdx, currentTime) = available';
    end
end
graph = struct('positions', positions, ...
    'distanceByTime', distances, 'physicalAdjacency', physical);
end

function validateCurrentPageInput(routeInput, nodeCount)
required = {'positions', 'physicalAdjacency', 'pDropByEdge', ...
    'registeredBaseAdjacency', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'sensorGroupIds', 'currentTime'};
actual = fieldnames(routeInput);
matrixInputs = {'physicalAdjacency', 'pDropByEdge', ...
    'registeredBaseAdjacency'};
matricesValid = true;
for idx = 1:numel(matrixInputs)
    value = routeInput.(matrixInputs{idx});
    matricesValid = matricesValid && (isnumeric(value) || islogical(value)) && ...
        isreal(value) && all(isfinite(value(:))) && ...
        isequal(size(value), [nodeCount, nodeCount]);
end
if numel(actual) ~= numel(required) || ...
