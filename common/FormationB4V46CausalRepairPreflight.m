function audit = assertRollingWindow(adjacencyPages, weightPages, ...
        formationUidsBySensor, windowTimes)
sensorUnion = any(adjacencyPages, 3);
formationUnion = collapseToPhysicalFormations( ...
    sensorUnion, formationUidsBySensor);
if ~isStronglyConnected(sensorUnion)
    error('FormationB4V46Preflight:RollingSensorDisconnected', ...
        'The actual executed rolling-B4 sensor union is disconnected.');
end
if ~isStronglyConnected(formationUnion)
    error('FormationB4V46Preflight:RollingFormationDisconnected', ...
        'The actual executed rolling-B4 formation union is disconnected.');
end

% Receiver-row matrices act on a column of node states.  Chronological
% pages W(t-3),...,W(t) therefore compose newest-on-the-left:
% P(t:t-3) = W(t) W(t-1) W(t-2) W(t-3).
nodeCount = size(weightPages, 1);
product = eye(nodeCount);
for chronologicalIdx = 1:size(weightPages, 3)
    product = weightPages(:, :, chronologicalIdx) * product;
end
if any(~isfinite(product(:))) || any(product(:) < -1e-12) || ...
        any(product(:) > 1 + 1e-12) || ...
        any(abs(sum(product, 2) - 1) > 1e-11)
    error('FormationB4V46Preflight:MatrixProductViolation', ...
        'The chronological rolling-B4 product is not row-stochastic.');
end
mixing = computeStochasticMixingDiagnostics(product);
dobrushin = mixing.dobrushinCoefficient;
centeredSpectralNorm = mixing.centeredSpectralNorm;
maximumCenteredRowL2 = mixing.maximumCenteredRowL2;
spectralUpperBound = sqrt(nodeCount);
rowUpperBound = sqrt(2);
if ~isfinite(dobrushin) || dobrushin < -1e-12 || ...
        dobrushin > 1 + 1e-12 || ...
        ~isfinite(centeredSpectralNorm) || ...
        centeredSpectralNorm < -1e-12 || ...
        centeredSpectralNorm > spectralUpperBound + 1e-10 || ...
        ~isfinite(maximumCenteredRowL2) || ...
        maximumCenteredRowL2 < -1e-12 || ...
        maximumCenteredRowL2 > rowUpperBound + 1e-10
    error('FormationB4V46Preflight:MatrixProductMetricViolation', ...
        'A rolling-B4 product metric is outside its mathematical bound.');
end
payload = struct( ...
    'contractVersion', 'v46-actual-rolling-b4-product-audit-v1', ...
    'matrixConvention', 'receiver-row-state-column', ...
    'multiplicationOrder', ...
        'P(t:t-3)=W(t)*W(t-1)*W(t-2)*W(t-3)', ...
    'centeringDefinition', [ ...
        'spectral=H*P*H;row-dispersion=P-mean(P,1);', ...
        'H=I-ones(N)/N'], ...
    'windowTimes', reshape(windowTimes, 1, []), ...
    'product', product, 'dobrushin', dobrushin, ...
    'centeredSpectralNorm', centeredSpectralNorm, ...
    'maximumCenteredRowL2', maximumCenteredRowL2);
audit = payload;
audit.canonicalSha256 = computeCanonicalValueSha256(payload);
end

