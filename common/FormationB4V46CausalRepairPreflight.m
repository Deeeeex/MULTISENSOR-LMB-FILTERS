function pairs = collapsePairPhysicalUids(adjacency, uidBySensor, ...
        requireBidirectional)
uids = sort(unique(reshape(uidBySensor, 1, [])));
pairs = zeros(0, 2);
adjacency = logical(adjacency);
for leftIdx = 1:numel(uids)-1
    left = uidBySensor == uids(leftIdx);
    for rightIdx = leftIdx+1:numel(uids)
        right = uidBySensor == uids(rightIdx);
        forward = any(any(adjacency(left, right)));
        reverse = any(any(adjacency(right, left)));
        if (requireBidirectional && forward && reverse) || ...
                (~requireBidirectional && (forward || reverse))
            pairs(end + 1, :) = [uids(leftIdx), uids(rightIdx)]; %#ok<AGROW>
        end
    end
end
pairs = sortrows(pairs, [1, 2]);
end

function pairs = sensorPairPhysicalUids(adjacency, sensorUids)
[receiver, sender] = find(triu(logical(adjacency), 1));
if isempty(receiver)
    pairs = zeros(0, 2);
else
    sensorUids = reshape(sensorUids, 1, []);
    pairs = [sensorUids(receiver)', sensorUids(sender)'];
    pairs = sortrows(sort(pairs, 2), [1, 2]);
end
end

function connected = isConnectedFormationPairs(pairs, formationUids)
formationUids = sort(reshape(formationUids, 1, []));
adjacency = false(numel(formationUids));
for pairIdx = 1:size(pairs, 1)
    left = find(formationUids == pairs(pairIdx, 1), 1);
    right = find(formationUids == pairs(pairIdx, 2), 1);
    if isempty(left) || isempty(right)
        connected = false;
        return;
    end
    adjacency(left, right) = true;
    adjacency(right, left) = true;
end
connected = isStronglyConnected(adjacency);
end

