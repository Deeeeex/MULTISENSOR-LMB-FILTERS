function validateStructuredFormationTreeModelContract( ...
        model, expectedSourceWeight)
% VALIDATESTRUCTUREDFORMATIONTREEMODELCONTRACT Fail closed on provenance.

if nargin < 2
    expectedSourceWeight = [];
end
requiredFields = { ...
    'kind', 'artifactContractVersion', 'sourceWeight', ...
    'teacherSeriesContractVersion', ...
    'previousAdjacencyConvention', ...
    'baselineMode', 'requirePreviousUnionStrongConnectivity', ...
    'proxyValidatedOnly', 'proxyTrainingGatePassed', ...
    'proxyValidationGatePassed', ...
    'closedLoopValidated', 'actionFeaturesUseTruth'};
for fieldIdx = 1:numel(requiredFields)
    if ~isfield(model, requiredFields{fieldIdx})
        error('Structured tree-routing model lacks %s.', ...
            requiredFields{fieldIdx});
    end
end
if ~strcmp(model.kind, 'structured-formation-tree-routing-v1') || ...
        ~strcmp(model.artifactContractVersion, ...
            'structured-formation-tree-proxy-candidate-v2-ctxv2') || ...
        ~strcmp(model.teacherSeriesContractVersion, ...
            ['directed-teacher-series-v2-receiver-row-', ...
             'previous-adjacency']) || ...
        ~strcmp(model.previousAdjacencyConvention, ...
            'receiver-row-sender-column-directed')
    error('Unsupported structured tree-routing artifact contract.');
end
baselineMode = lower(strrep(char(model.baselineMode), '_', '-'));
if ~strcmp(baselineMode, 'fixed-index-star') || ...
        ~logical(model.requirePreviousUnionStrongConnectivity) || ...
        ~logical(model.proxyValidatedOnly) || ...
        ~logical(model.proxyTrainingGatePassed) || ...
        ~logical(model.proxyValidationGatePassed) || ...
        logical(model.closedLoopValidated) || ...
        logical(model.actionFeaturesUseTruth)
    error('Structured tree-routing artifact provenance gate failed.');
end
if ~isempty(expectedSourceWeight) && ...
        abs(model.sourceWeight - expectedSourceWeight) > 1e-12
    error('Structured tree-routing model weight mismatch.');
end
end
