function detected = ...
        isProtectionEarlyReleaseOracleV107ExecutionContext(context)
% ISPROTECTIONEARLYRELEASEORACLEV107EXECUTIONCONTEXT Identify V107.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'protection-early-release-oracle-v107-context-v1');
end
