function detected = isPredictiveEvidenceFallbackV137ExecutionContext(context)
% ISPREDICTIVEEVIDENCEFALLBACKV137EXECUTIONCONTEXT Identify V137 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'predictive-evidence-fallback-v137-execution-context-v1');
end
