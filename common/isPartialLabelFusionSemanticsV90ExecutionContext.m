function detected = ...
    isPartialLabelFusionSemanticsV90ExecutionContext(context)
% ISPARTIALLABELFUSIONSEMANTICSV90EXECUTIONCONTEXT Identify V90 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'partial-label-fusion-semantics-v90-full-episode-context-v1');
end
