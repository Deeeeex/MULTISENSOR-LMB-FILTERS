function protocol = getDecoupledSemanticShortcutV220Protocol()
% GETDECOUPLEDSEMANTICSHORTCUTV220PROTOCOL Byte-safe semantic graph action.
%
% A one-page full-posterior receiver suspension earns exact attempted-byte
% credit.  A different beneficiary formation may spend that credit on one
% current-state, complete-label Bernoulli GM KLA shortcut.  The static
% full-posterior cycle is always the fallback.

base = getDirectGraphCreditRepairControllerV216Protocol();
repair = getBudgetRecycledFormationRepairV188Protocol();
protocol = struct();
protocol.id = 'decoupled-semantic-shortcut-v220-v1';
protocol.contractVersion = ...
    'decoupled-semantic-shortcut-v220-protocol-v1';
protocol.baseProtocolId = base.id;
protocol.repairProtocolId = repair.id;
protocol.horizonSteps = base.horizonSteps;
protocol.filterSeedOffset = base.filterSeedOffset;
protocol.receiverMode = base.receiverMode;
protocol.actionMode = base.actionMode;
protocol.repairSourceWeight = base.repairSourceWeight;
protocol.candidateReceiverPresenceThreshold = ...
    base.candidateReceiverPresenceThreshold;
protocol.maximumDonorFormationsPerPage = 1;
protocol.maximumBeneficiaryFormationsPerPage = 1;
protocol.donorDecisionPhase = 'pre-communication-current-page';
protocol.beneficiaryDecisionPhase = ...
    'post-ordinary-fusion-current-page';
protocol.donorSafetyRule = ...
    'noninferior-core-and-tail-with-positive-byte-saving';
protocol.formationScope = ...
    'donor-and-beneficiary-selected-independently';
protocol.semanticPayload = ...
    'complete-label-bernoulli-gaussian-mixture';
protocol.communicationCreditReserveFraction = ...
    repair.communicationCreditReserveFraction;
protocol.communicationCreditMayCarryAcrossPages = ...
    repair.creditMayCarryAcrossPages;
protocol.zeroSupportKlaAllowed = false;
protocol.actualDeliverySampledForDeployment = true;
protocol.idealDeliveryAllowedForConditionalTeacher = true;
protocol.retainedLabelsPreserveCompleteMixture = true;
protocol.posteriorCounterfactualEnumerationUsed = false;
protocol.truthUsedAtRuntime = false;
protocol.futureInformationUsedAtRuntime = false;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v220');
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V220 is a development two-stage semantic-routing controller. A ', ...
    'truth-free donor action first suspends one receiver formation from ', ...
    'ordinary cross-formation full-posterior consumption for one page. ', ...
    'Only its exact remaining communication credit may fund one ', ...
    'complete-mixture label KLA shortcut to an independently selected ', ...
    'beneficiary. Donor-only safety and shortcut incremental value are ', ...
    'scored by paired H=3 counterfactuals; truth and future outcomes are ', ...
    'offline targets only.'];

if protocol.horizonSteps ~= 3 || ...
        protocol.maximumDonorFormationsPerPage ~= 1 || ...
        protocol.maximumBeneficiaryFormationsPerPage ~= 1 || ...
        protocol.communicationCreditReserveFraction <= 0 || ...
        protocol.communicationCreditReserveFraction >= 1 || ...
        ~protocol.communicationCreditMayCarryAcrossPages || ...
        protocol.zeroSupportKlaAllowed || ...
        ~protocol.retainedLabelsPreserveCompleteMixture || ...
        protocol.posteriorCounterfactualEnumerationUsed || ...
        protocol.truthUsedAtRuntime || ...
        protocol.futureInformationUsedAtRuntime
    error('DecoupledSemanticShortcutV220:ProtocolDrift', ...
        'The frozen V220 protocol is malformed.');
end
end
