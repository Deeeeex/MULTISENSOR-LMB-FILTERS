function [candidates, details] = ...
        enumerateFormationCommonLabelRepairCandidatesV190( ...
            cache, physicalAdjacency, sensorGroupIds, options)
% ENUMERATEFORMATIONCOMMONLABELREPAIRCANDIDATESV190 Keep the action bank.
%
% V188 reduces every formation to one analytic source-label pair.  V190
% keeps every causal, directly executable candidate and exports a numeric
% feature row for coarse Top-K selection.  Semantic label values remain
% routing keys and are never returned as learned features.

if nargin < 4 || isempty(options)
    options = struct();
end
validateCache(cache);
sensorCount = cache.sensorCount;
groupIds = reshape(sensorGroupIds, 1, []);
sourceExistenceThreshold = getField( ...
    options, 'sourceExistenceThreshold', 1e-2);
receiverPresenceThreshold = getField( ...
    options, 'receiverPresenceThreshold', 0.5);
minimumPeerCount = getField(options, 'minimumPeerCount', 1);
minimumRiskReductionThreshold = getField( ...
    options, 'minimumRiskReductionThreshold', 0);
if ~isequal(size(physicalAdjacency), [sensorCount, sensorCount]) || ...
        numel(groupIds) ~= sensorCount || ...
        any(~isfinite(groupIds)) || any(groupIds ~= round(groupIds)) || ...
        any(groupIds < 1) || ...
        ~validUnitWeight(sourceExistenceThreshold, false) || ...
        ~validUnitWeight(receiverPresenceThreshold, true) || ...
        ~isscalar(minimumPeerCount) || ~isfinite(minimumPeerCount) || ...
        minimumPeerCount < 0 || minimumPeerCount ~= round(minimumPeerCount) || ...
        ~isscalar(minimumRiskReductionThreshold) || ...
        ~isfinite(minimumRiskReductionThreshold)
    error('FormationRepairCandidatesV190:InvalidInput', ...
        'The candidate-bank input is malformed.');
end

physicalAdjacency = logical(physicalAdjacency);
[labels, local, fused] = alignByLabel( ...
    cache.localBySensor, cache.fusedBySensor, sensorCount);
formationIds = unique(groupIds, 'stable');
candidates = repmat(emptyCandidate(), 1, 0);
rejectedReceiverPresence = 0;
rejectedPeerSupport = 0;
rejectedRisk = 0;
for formationIdx = 1:numel(formationIds)
    formationId = formationIds(formationIdx);
    receivers = find(groupIds == formationId);
    commonSources = find(all(physicalAdjacency(receivers, :), 1));
    for sourceIdx = reshape(commonSources, 1, [])
        sourceLabels = find(local.existence(sourceIdx, :) >= ...
            sourceExistenceThreshold);
        for labelIdx = reshape(sourceLabels, 1, [])
            if any(fused.existence(receivers, labelIdx) < ...
                    receiverPresenceThreshold)
                rejectedReceiverPresence = rejectedReceiverPresence + 1;
                continue;
            end
            sourceCompatibility = compatibilityToSource( ...
                local, sourceIdx, labelIdx);
            peerConsensus = zeros(1, numel(receivers));
            complete = true;
            for receiverPosition = 1:numel(receivers)
                receiverIdx = receivers(receiverPosition);
                peers = find(physicalAdjacency(receiverIdx, :));
                peers(peers == sourceIdx) = [];
                peers = peers(local.existence(peers, labelIdx) >= ...
                    sourceExistenceThreshold);
                if numel(peers) < minimumPeerCount
                    complete = false;
                    break;
                end
                peerConsensus(receiverPosition) = mean( ...
                    sourceCompatibility(peers));
            end
            if ~complete
                rejectedPeerSupport = rejectedPeerSupport + 1;
                continue;
            end

            receiverCompatibility = compatibilityToFusedReceivers( ...
                local, fused, sourceIdx, receivers, labelIdx);
            sourceQuality = local.existence(sourceIdx, labelIdx) * ...
                local.evidenceQuality(sourceIdx, labelIdx);
            rescue = peerConsensus .* ...
                max(1 - receiverCompatibility, 0) * max(sourceQuality, 0);
            riskReduction = fused.bayesRisk(receivers, labelIdx)' - ...
                local.bayesRisk(sourceIdx, labelIdx);
            if min(riskReduction) < ...
                    minimumRiskReductionThreshold - 1e-15
                rejectedRisk = rejectedRisk + 1;
                continue;
            end

            receiverTrace = fused.positionTrace(receivers, labelIdx);
            sourceTrace = local.positionTrace(sourceIdx, labelIdx);
            positionDelta = fused.positionMean(receivers, :, labelIdx) - ...
                repmat(local.positionMean(sourceIdx, :, labelIdx), ...
                    numel(receivers), 1);
            positionDistance = sqrt(sum(positionDelta .^ 2, 2));
            cutoffSquared = max(cache.positionCutoff ^ 2, eps);
            candidate = emptyCandidate();
            candidate.candidateIndex = numel(candidates) + 1;
            candidate.formationId = formationId;
            candidate.receiverIds = reshape(receivers, 1, []);
            candidate.sourceId = sourceIdx;
            candidate.label = labels(labelIdx, :)';
            candidate.opportunityMedian = median(rescue);
            candidate.minimumRiskReduction = min(riskReduction);
            candidate.medianRiskReduction = median(riskReduction);
            candidate.minimumReceiverExistence = min( ...
                fused.existence(receivers, labelIdx));
            candidate.peerConsensusMinimum = min(peerConsensus);
            candidate.peerConsensusMedian = median(peerConsensus);
            candidate.receiverCompatibilityMedian = ...
                median(receiverCompatibility);
            candidate.receiverCompatibilityMaximum = ...
                max(receiverCompatibility);
            candidate.receiverDisagreementMedian = ...
                1 - candidate.receiverCompatibilityMedian;
            candidate.sourceExistence = ...
                local.existence(sourceIdx, labelIdx);
            candidate.sourceEvidenceQuality = ...
                local.evidenceQuality(sourceIdx, labelIdx);
            candidate.sourceAssociationSupport = ...
                local.associationSupport(sourceIdx, labelIdx);
            candidate.sourceObservationOpportunity = ...
                local.observationOpportunity(sourceIdx, labelIdx);
            candidate.sourceQuality = sourceQuality;
            candidate.sourcePositionTraceNormalized = ...
                sourceTrace / cutoffSquared;
            candidate.receiverPositionTraceMedianNormalized = ...
                median(receiverTrace) / cutoffSquared;
            candidate.precisionGainNormalized = ...
                (median(receiverTrace) - sourceTrace) / cutoffSquared;
            candidate.positionDistanceMedianNormalized = ...
                median(positionDistance) / cache.positionCutoff;
            candidate.positionDistanceMaximumNormalized = ...
                max(positionDistance) / cache.positionCutoff;
            candidate.formationSizeFraction = ...
                numel(receivers) / sensorCount;
            candidate.sourcePhysicalDegreeFraction = ...
                sum(physicalAdjacency(:, sourceIdx)) / ...
                max(sensorCount - 1, 1);
            candidate.directCommonSourcePassed = true;
            candidate.featureVector = candidateFeatures(candidate);
            candidates(end + 1) = candidate; %#ok<AGROW>
        end
    end
end

featureNames = candidateFeatureNames();
if isempty(candidates)
    featureMatrix = zeros(0, numel(featureNames));
else
    featureMatrix = vertcat(candidates.featureVector);
end
if size(featureMatrix, 2) ~= numel(featureNames) || ...
        any(~isfinite(featureMatrix(:)))
    error('FormationRepairCandidatesV190:InvalidFeatures', ...
        'The candidate feature matrix is invalid.');
end

details = struct();
details.contractVersion = ...
    'formation-common-label-candidate-bank-v190-v1';
details.currentTime = cache.currentTime;
details.formationIds = formationIds;
details.candidateCount = numel(candidates);
details.candidateCountByFormation = zeros(1, numel(formationIds));
for formationIdx = 1:numel(formationIds)
    details.candidateCountByFormation(formationIdx) = nnz( ...
        [candidates.formationId] == formationIds(formationIdx));
end
details.featureNames = featureNames;
details.featureMatrix = featureMatrix;
details.rejectedReceiverPresence = rejectedReceiverPresence;
details.rejectedPeerSupport = rejectedPeerSupport;
details.rejectedRisk = rejectedRisk;
details.transportMode = 'direct-common-source-v188';
details.multihopAtomicTransportImplemented = false;
details.lightSynopsisContractVersion = cache.contractVersion;
details.truthUsed = false;
details.futureInformationUsed = false;
details.numericLabelIdentifiersUsedAsFeatures = false;
details.completePayloadRequested = false;
details.trackingBenefitClaimed = false;
end

