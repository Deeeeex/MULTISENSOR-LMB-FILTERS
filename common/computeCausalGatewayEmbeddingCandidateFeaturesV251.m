function [features, names, details] = ...
        computeCausalGatewayEmbeddingCandidateFeaturesV251( ...
            context, candidateAssignments, referenceAssignment, ...
            identity, options)
% COMPUTECAUSALGATEWAYEMBEDDINGCANDIDATEFEATURESV251
% Permutation-invariant, truth-free features for fixed-budget gateways.

if nargin < 5 || isempty(options)
    options = struct();
end
if isnumeric(candidateAssignments)
    candidateAssignments = {candidateAssignments};
end
candidateTypes = getField(options, 'candidateTypes', ...
    repmat({'alternative'}, 1, numel(candidateAssignments)));
candidateTypes = reshape(candidateTypes, 1, []);
requiredContext = {'localPosteriorBySensor', 'model', ...
    'physicalAdjacency', 'positions', 'commConfig', 'currentTime'};
requiredIdentity = {'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, requiredContext)) || ...
        ~iscell(candidateAssignments) || isempty(candidateAssignments) || ...
        numel(candidateTypes) ~= numel(candidateAssignments) || ...
        ~isnumeric(referenceAssignment) || ...
        size(referenceAssignment, 2) ~= 4 || ...
        ~isstruct(identity) || ~isscalar(identity) || ...
        ~all(isfield(identity, requiredIdentity))
    error('CausalGatewayEmbeddingV251:InvalidFeatureInput', ...
        'The V251 candidate feature input is incomplete.');
end

nodeCount = numel(context.localPosteriorBySensor);
sensorUids = reshape(identity.sensorPhysicalUids, 1, []);
formationUidsBySensor = reshape( ...
    identity.formationPhysicalUidsBySensor, 1, []);
if numel(sensorUids) ~= nodeCount || ...
        numel(formationUidsBySensor) ~= nodeCount || ...
        numel(unique(sensorUids)) ~= nodeCount || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(context.positions), [2, nodeCount])
    error('CausalGatewayEmbeddingV251:InvalidFeatureIdentity', ...
        'The V251 physical identity or current page is malformed.');
end

[edgeFeatures, edgeNames] = computeDirectedRoutingFeatures( ...
    context, struct());
selectedEdgeFeatureNames = { ...
    'link_reliability', ...
    'normalized_sensor_distance', ...
    'source_expected_cardinality', ...
    'receiver_expected_cardinality', ...
    'source_cardinality_variance', ...
    'receiver_cardinality_variance', ...
    'source_position_variance', ...
    'receiver_position_variance', ...
    'source_association_confidence', ...
    'receiver_association_confidence', ...
    'source_detection_mass', ...
    'receiver_detection_mass', ...
    'positive_existence_gain', ...
    'negative_existence_gap', ...
    'positive_precision_gain', ...
    'negative_precision_gap', ...
    'normalized_state_discrepancy', ...
    'active_label_overlap', ...
    'node_quality_advantage', ...
    'receiver_need'};
selectedIndices = zeros(1, numel(selectedEdgeFeatureNames));
for featureIdx = 1:numel(selectedEdgeFeatureNames)
    match = find(strcmp(edgeNames, ...
        selectedEdgeFeatureNames{featureIdx}), 1);
    if isempty(match)
        error('CausalGatewayEmbeddingV251:MissingEdgeFeature', ...
            'The required edge feature %s is unavailable.', ...
            selectedEdgeFeatureNames{featureIdx});
    end
    selectedIndices(featureIdx) = match;
end

referenceAssignment = normalizeAssignment(referenceAssignment);
referenceRows = assignmentEdgeRows( ...
    referenceAssignment, sensorUids, edgeFeatures, selectedIndices);
referencePersistence = assignmentPersistence( ...
    referenceAssignment, sensorUids, context);
baseNameCount = numel(selectedEdgeFeatureNames);
names = cell(1, 2 * baseNameCount + 7);
cursor = 0;
for featureIdx = 1:baseNameCount
    cursor = cursor + 1;
    names{cursor} = ['assignment_mean_', ...
        selectedEdgeFeatureNames{featureIdx}];
end
for featureIdx = 1:baseNameCount
    cursor = cursor + 1;
    names{cursor} = ['changed_delta_', ...
        selectedEdgeFeatureNames{featureIdx}];
end
tailNames = {'changed_arc_fraction', ...
    'history_overlap_mean', 'history_overlap_delta', ...
    'type_global_rank_profile', ...
    'type_receiver_local_assignment', ...
    'type_single_directed_arc', ...
    'type_reference'};
names(cursor + (1:numel(tailNames))) = tailNames;

features = zeros(numel(candidateAssignments), numel(names));
changedRowsByCandidate = cell(1, numel(candidateAssignments));
edgeRowsByCandidate = cell(1, numel(candidateAssignments));
for candidateIdx = 1:numel(candidateAssignments)
    assignment = normalizeAssignment(candidateAssignments{candidateIdx});
    validateAssignmentPairing(assignment, referenceAssignment, ...
        formationUidsBySensor, sensorUids, context.physicalAdjacency);
    rows = assignmentEdgeRows( ...
        assignment, sensorUids, edgeFeatures, selectedIndices);
    edgeRowsByCandidate{candidateIdx} = rows;
    changed = find(any(assignment(:, 3:4) ~= ...
        referenceAssignment(:, 3:4), 2));
    changedRowsByCandidate{candidateIdx} = changed;
    assignmentMean = mean(rows, 1);
    if isempty(changed)
        changedDelta = zeros(1, baseNameCount);
    else
        changedDelta = mean(rows(changed, :) - ...
            referenceRows(changed, :), 1);
    end
    persistence = assignmentPersistence( ...
        assignment, sensorUids, context);
    type = char(candidateTypes{candidateIdx});
    typeVector = [strcmp(type, 'global-rank-profile'), ...
        strcmp(type, 'receiver-local-assignment'), ...
        strcmp(type, 'single-directed-arc'), ...
        strcmp(type, 'v242-reference')];
    features(candidateIdx, :) = [assignmentMean, changedDelta, ...
        numel(changed) / size(assignment, 1), ...
        persistence, persistence - referencePersistence, typeVector];
end
if any(~isfinite(features(:)))
    error('CausalGatewayEmbeddingV251:InvalidFeatureValues', ...
        'The V251 candidate feature matrix contains invalid values.');
end

linkOnlyMask = containsAny(names, { ...
    'link_reliability', 'normalized_sensor_distance', ...
    'changed_arc_fraction', 'history_overlap', 'type_'});
posteriorMask = ~linkOnlyMask;
details = struct();
details.contractVersion = ...
    'causal-gateway-embedding-v251-candidate-features-v1';
details.featureNames = names;
details.selectedDirectedEdgeFeatureNames = ...
    selectedEdgeFeatureNames;
details.linkOnlyMask = linkOnlyMask;
details.posteriorFeatureMask = posteriorMask;
details.changedRowsByCandidate = changedRowsByCandidate;
details.edgeRowsByCandidate = edgeRowsByCandidate;
details.referenceEdgeRows = referenceRows;
details.sensorPermutationInvariant = true;
details.formationLabelPermutationInvariant = true;
details.scaleNormalizedWhereApplicable = true;
details.numericSensorIdentifiersUsedAsFeatures = false;
details.numericFormationIdentifiersUsedAsFeatures = false;
details.truthUsed = false;
details.futureInformationUsed = false;
details.futurePhysicalPageUsed = false;
end

function rows = assignmentEdgeRows( ...
        assignment, sensorUids, edgeFeatures, selectedIndices)
rows = zeros(size(assignment, 1), numel(selectedIndices));
for edgeIdx = 1:size(assignment, 1)
    senderIdx = find(sensorUids == assignment(edgeIdx, 3), 1);
    receiverIdx = find(sensorUids == assignment(edgeIdx, 4), 1);
    if isempty(senderIdx) || isempty(receiverIdx)
        error('CausalGatewayEmbeddingV251:UnknownGatewayUid', ...
            'A gateway assignment references an unknown sensor UID.');
    end
    row = reshape(edgeFeatures( ...
        receiverIdx, senderIdx, selectedIndices), 1, []);
    if any(~isfinite(row))
        error('CausalGatewayEmbeddingV251:UnavailableGatewayFeature', ...
            'A requested gateway does not have current edge features.');
    end
    rows(edgeIdx, :) = row;
end
end

function persistence = assignmentPersistence( ...
        assignment, sensorUids, context)
history = getField(context, 'previousAdjacencyHistory', false( ...
    numel(sensorUids), numel(sensorUids), 0));
if isempty(history)
    persistence = 0;
    return;
end
if size(history, 1) ~= numel(sensorUids) || ...
        size(history, 2) ~= numel(sensorUids)
    error('CausalGatewayEmbeddingV251:InvalidHistory', ...
        'The previous adjacency history has invalid dimensions.');
end
values = zeros(size(assignment, 1), size(history, 3));
for edgeIdx = 1:size(assignment, 1)
    senderIdx = find(sensorUids == assignment(edgeIdx, 3), 1);
    receiverIdx = find(sensorUids == assignment(edgeIdx, 4), 1);
    values(edgeIdx, :) = reshape( ...
        history(receiverIdx, senderIdx, :), 1, []);
end
persistence = mean(values(:));
end

function validateAssignmentPairing( ...
        assignment, reference, formationUidsBySensor, sensorUids, physical)
if ~isequal(size(assignment), size(reference)) || ...
        ~isequal(assignment(:, 1:2), reference(:, 1:2)) || ...
        any(~isfinite(assignment(:))) || ...
        size(unique(assignment(:, 1:2), 'rows'), 1) ~= ...
            size(assignment, 1)
    error('CausalGatewayEmbeddingV251:AssignmentPairing', ...
        'A candidate does not preserve the directed formation tree.');
end
for edgeIdx = 1:size(assignment, 1)
    senderIdx = find(sensorUids == assignment(edgeIdx, 3), 1);
    receiverIdx = find(sensorUids == assignment(edgeIdx, 4), 1);
    valid = ~isempty(senderIdx) && ~isempty(receiverIdx) && ...
        formationUidsBySensor(senderIdx) == assignment(edgeIdx, 1) && ...
        formationUidsBySensor(receiverIdx) == assignment(edgeIdx, 2) && ...
        logical(physical(receiverIdx, senderIdx));
    if ~valid
        error('CausalGatewayEmbeddingV251:InvalidGatewayEdge', ...
            'A candidate gateway is not current-physical or identity-safe.');
    end
end
end

function assignment = normalizeAssignment(assignment)
assignment = sortrows(assignment, [2, 1, 4, 3]);
end

function mask = containsAny(names, patterns)
mask = false(1, numel(names));
for nameIdx = 1:numel(names)
    for patternIdx = 1:numel(patterns)
        if ~isempty(strfind(names{nameIdx}, patterns{patternIdx})) %#ok<STREMP>
            mask(nameIdx) = true;
            break;
        end
    end
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
