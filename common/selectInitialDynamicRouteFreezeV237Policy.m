function [adjacency, details] = ...
        selectInitialDynamicRouteFreezeV237Policy(context, registration)
% SELECTINITIALDYNAMICROUTEFREEZEV237POLICY Fixed t=1 dynamic route.

protocol = getInitialDynamicRouteFreezeV237Protocol();
[adjacency, details] = ...
    selectCorrectedFixedStaticFormationBackboneV227Policy( ...
        context, registration);
details.contractVersion = ...
    'initial-dynamic-route-freeze-v237-policy-v1';
details.protocolId = protocol.id;
details.armId = protocol.armId;
details.mode = 'initial-current-physical-route-frozen';
details.backboneMode = details.mode;
details.referenceFallbackUsed = false;
details.currentPhysicalActionSetUsed = false;
details.currentPhysicalFeasibilityChecked = true;
details.currentGeometryUsed = context.currentTime == 1;
details.currentLinkReliabilityUsed = context.currentTime == 1;
details.posteriorUsed = false;
details.truthUsed = false;
details.futureOutcomeUsed = false;
details.initialSelectionTime = 1;
details.routeReselectionUsed = false;
details.scheduleCertificate = buildSchedule(context.currentTime);
end

function schedule = buildSchedule(currentTime)
schedule = struct( ...
    'contractVersion', 'initial-dynamic-route-freeze-v237-schedule-v1', ...
    'currentTime', currentTime, 'phase', 'initial-route-frozen', ...
    'phaseIndex', 1, 'gatewayIndices', zeros(1, 0), ...
    'formationIds', zeros(1, 0), 'sourceIndices', zeros(1, 0), ...
    'proposalGatewayCount', 0, 'selectedGatewayCount', 0, ...
    'pendingAcquisitionTime', NaN, 'messageParityPassed', true, ...
    'rollingSensorStrong', true, 'rollingFormationStrong', true, ...
    'referenceFallbackUsed', false, 'cycleSelected', true, ...
    'routeReselectionUsed', false, 'truthReadAtRuntime', false, ...
    'futureOutcomeReadAtRuntime', false);
end
