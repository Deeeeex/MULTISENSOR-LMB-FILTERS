function block = buildTrackingAlignedFormationValueBlock( ...
        context, groupIds, screen)
% BUILDTRACKINGALIGNEDFORMATIONVALUEBLOCK Join V56 graph and H-step targets.
%
% Observable graph inputs are constructed before the already-computed
% counterfactual tracking outcomes are attached.  The resulting block is an
% offline teacher object; a runtime policy may consume block.graph but must
% never receive block.targets or any target-derived mask.

requiredScreen = { ...
    'bank', 'records', 'outcomes', 'referenceSubsetIndex', ...
    'actionIndices', 'horizonSteps', ...
    'featuresUseTruth', 'featuresUseFutureMeasurements', ...
    'featuresUseFutureOutcome', 'targetsUseTruth', ...
    'targetsUseFutureMeasurements', 'runtimePolicyUsesTruth'};
if ~isstruct(screen) || ~all(isfield(screen, requiredScreen)) || ...
        screen.featuresUseTruth || ...
        screen.featuresUseFutureMeasurements || ...
        screen.featuresUseFutureOutcome || ...
        ~screen.targetsUseTruth || ...
        ~screen.targetsUseFutureMeasurements || ...
        screen.runtimePolicyUsesTruth || ...
        numel(screen.records) ~= numel(screen.outcomes) || ...
        numel(screen.records) ~= numel(screen.actionIndices)
    error('Tracking-aligned value screen contract is invalid.');
end

graph = computeTrackingAlignedFormationGraphFeatures( ...
    context, screen.bank, groupIds);
targetNames = { ...
    'mean_tracking_gain_percent', ...
    'cardinality_error_reduction_fraction', ...
    'affected_formation_gain_percent', ...
    'minimum_formation_gain_percent', ...
    'worst_sensor_gain_percent', ...
    'consensus_gain_percent', ...
    'attempted_byte_saving_percent', ...
    'delivered_byte_saving_percent'};
targetCount = numel(targetNames);
formationCount = graph.formationCount;
modeCount = graph.modeCount;
targets = nan(formationCount, modeCount, targetCount);
targetAvailableMask = false(formationCount, modeCount);
executionSafeMask = false(formationCount, modeCount);

referenceRecordIdx = screen.referenceSubsetIndex;
if referenceRecordIdx < 1 || ...
        referenceRecordIdx > numel(screen.records) || ...
        screen.actionIndices(referenceRecordIdx) ~= ...
            screen.bank.referenceActionIndex
    error('Tracking-aligned value reference is invalid.');
end
referenceOutcome = screen.outcomes(referenceRecordIdx);
for formationIdx = 1:formationCount
    targets(formationIdx, 1, :) = zeros(1, 1, targetCount);
    targetAvailableMask(formationIdx, 1) = true;
    executionSafeMask(formationIdx, 1) = ...
        actionExecutionSafe(referenceOutcome, ...
            screen.records(referenceRecordIdx));
end

for formationIdx = 1:formationCount
    for modeIdx = 2:modeCount
        actionIdx = graph.modeActionIndex(formationIdx, modeIdx);
        if actionIdx == 0
            continue;
        end
        recordIdx = find(screen.actionIndices == actionIdx);
        if isempty(recordIdx) && ...
                ~screen.bank.actionPosteriorProxyAllowed(actionIdx)
            continue;
        elseif numel(recordIdx) ~= 1
            error('Tracking-aligned local mode lacks one teacher outcome.');
        end
        record = screen.records(recordIdx);
        outcome = screen.outcomes(recordIdx);
        if record.formationIndex ~= formationIdx || ...
                record.modeIndex ~= modeIdx
            error('Tracking-aligned teacher action mapping changed.');
        end
        affectedGain = record.formationGainPercent(formationIdx);
        cardinalityReduction = ...
            (referenceOutcome.meanCardinalityError - ...
             outcome.meanCardinalityError) / ...
                max(graph.targetCapacity, 1);
        deliveredSaving = 100 * ...
            (referenceOutcome.deliveredBytes - outcome.deliveredBytes) / ...
                max(referenceOutcome.deliveredBytes, eps);
        targets(formationIdx, modeIdx, :) = [ ...
            record.meanGainPercent, cardinalityReduction, ...
            affectedGain, record.minimumFormationGainPercent, ...
            record.worstGainPercent, record.consensusGainPercent, ...
            record.attemptedByteSavingPercent, deliveredSaving];
        targetAvailableMask(formationIdx, modeIdx) = true;
        executionSafeMask(formationIdx, modeIdx) = ...
            actionExecutionSafe(outcome, record);
    end
end
targetMask3d = repmat(targetAvailableMask, 1, 1, targetCount);
if any(~isfinite(targets(targetMask3d)))
    error('Tracking-aligned value targets are non-finite.');
end

block = struct();
block.contractVersion = ...
    'tracking-aligned-formation-value-block-v56-v2';
block.graph = graph;
block.presetName = optionalField(screen, 'presetName', 'unknown');
block.seed = optionalField(screen, 'seed', NaN);
block.currentTime = optionalField(screen, 'currentTime', NaN);
block.targetNames = targetNames;
block.targets = targets;
block.targetAvailableMask = targetAvailableMask;
block.executionSafeMask = executionSafeMask;
block.horizonSteps = screen.horizonSteps;
block.featuresUseTruth = false;
block.featuresUseFutureMeasurements = false;
block.featuresUseFutureOutcome = false;
block.targetsUseTruth = true;
block.targetsUseFutureMeasurements = true;
block.runtimeEligibleFields = {'graph'};
block.offlineOnlyFields = { ...
    'targets', 'targetAvailableMask', 'executionSafeMask'};
end

function value = optionalField(structure, name, fallback)
if isfield(structure, name)
    value = structure.(name);
else
    value = fallback;
end
end

function safe = actionExecutionSafe(outcome, record)
requiredOutcome = { ...
    'truthUseCount', 'repairCount', 'payloadEmergencyCount', ...
    'infeasibleCount', 'firstActionExact', ...
    'selectedSensorB3Pass', 'selectedFormationB3Pass'};
safe = all(isfield(outcome, requiredOutcome)) && ...
    outcome.truthUseCount == 0 && ...
    outcome.repairCount == 0 && ...
    outcome.payloadEmergencyCount == 0 && ...
    outcome.infeasibleCount == 0 && ...
    logical(outcome.firstActionExact) && ...
    all(logical(outcome.selectedSensorB3Pass)) && ...
    all(logical(outcome.selectedFormationB3Pass)) && ...
    isfield(record, 'selectedB3Passed') && ...
    logical(record.selectedB3Passed);
end
