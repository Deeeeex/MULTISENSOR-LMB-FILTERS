function adaptive = ...
    buildFormationReliableKlaAdaptiveWindowRouteProbe(context, options)
% BUILDFORMATIONRELIABLEKLAADAPTIVEWINDOWROUTEPROBE
% Calibrate a causal scale-aware window on the registered reference route.

if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = { ...
    'targetSquaredContractionFactor', ...
    'maximumHorizonMultiplier', 'candidateFormationIds', ...
    'missingNeighborWeightModes', 'maximumIncomingCount'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationKlaAdaptiveWindow:InvalidOptions', ...
        'The adaptive formation-window options are malformed.');
end
protocol = getReliableKlaWindowContractionProtocol();
if ~isstruct(context) || ~isscalar(context) || ...
        ~isfield(context, 'triggerConfig')
    error('FormationKlaAdaptiveWindow:InvalidContext', ...
        'The adaptive formation-window context is malformed.');
end
runtimeSemantics = ...
    validateReliableKlaMixingRuntimeSemantics(context.triggerConfig);
calibrationMode = runtimeSemantics.missingNeighborWeightMode;
target = getField(options, 'targetSquaredContractionFactor', ...
    protocol.adaptiveReferenceSquaredContractionTarget);
maximumMultiplier = getField(options, 'maximumHorizonMultiplier', ...
    protocol.adaptiveMaximumHorizonMultiplier);
maximumIncomingCount = getField(options, 'maximumIncomingCount', ...
    protocol.maximumIncomingCount);
if ~isscalar(target) || ~isfinite(target) || target <= 0 || ...
        target >= 1 || ~isscalar(maximumMultiplier) || ...
        ~isfinite(maximumMultiplier) || maximumMultiplier < 1 || ...
        maximumMultiplier ~= round(maximumMultiplier)
    error('FormationKlaAdaptiveWindow:InvalidOptions', ...
        'The adaptive formation-window target or cap is invalid.');
end

calibrationProbe = ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        context, struct( ...
            'horizon', numel(context.model.dynamicTopologyScenario. ...
                config.sensorGroupIds) - 1, ...
            'candidateFormationIds', zeros(1, 0), ...
            'missingNeighborWeightModes', {{calibrationMode}}, ...
            'maximumIncomingCount', maximumIncomingCount, ...
            'includeSingleEventDobrushinDiagnostic', false));
nodeCount = calibrationProbe.nodeCount;
maximumHorizon = maximumMultiplier * (nodeCount - 1);
referenceProfile = ...
    computeStaticReliableKlaMeanSquareHorizonProfile( ...
        calibrationProbe.referenceAdjacency, ...
        calibrationProbe.referenceFusionWeights, ...
        calibrationProbe.currentReliabilityReceiverSender, ...
        maximumHorizon, struct( ...
            'missingNeighborWeightMode', calibrationMode, ...
            'maximumIncomingCount', maximumIncomingCount, ...
            'targetSquaredFactors', target));
targetHorizon = referenceProfile.firstTargetHorizon(1);
calibrationPassed = isfinite(targetHorizon);
if ~calibrationPassed
    evaluationHorizon = maximumHorizon;
else
    evaluationHorizon = targetHorizon;
end

routeOptions = struct();
routeOptions.horizon = evaluationHorizon;
requestedCandidateFormationIds = getField(options, ...
    'candidateFormationIds', calibrationProbe.groups);
if calibrationPassed
    routeOptions.candidateFormationIds = requestedCandidateFormationIds;
else
    routeOptions.candidateFormationIds = zeros(1, 0);
end
routeOptions.missingNeighborWeightModes = getField(options, ...
    'missingNeighborWeightModes', ...
    protocol.allowedMissingNeighborWeightModes);
routeOptions.maximumIncomingCount = maximumIncomingCount;
routeOptions.includeSingleEventDobrushinDiagnostic = false;
routeProbe = ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        context, routeOptions);

adaptive = struct();
adaptive.contractVersion = ...
    'formation-reliable-kla-adaptive-window-route-probe-v1';
adaptive.protocolId = protocol.id;
adaptive.protocolCanonicalSha256 = protocol.canonicalSha256;
adaptive.targetSquaredContractionFactor = target;
adaptive.maximumHorizonMultiplier = maximumMultiplier;
adaptive.maximumHorizon = maximumHorizon;
adaptive.calibrationMissingNeighborWeightMode = ...
    calibrationMode;
adaptive.runtimeSemantics = runtimeSemantics;
adaptive.calibrationPassed = calibrationPassed;
adaptive.candidateActionsAuthorized = calibrationPassed;
adaptive.candidateEvaluationPerformed = ...
    calibrationPassed && ~isempty(requestedCandidateFormationIds);
adaptive.requestedCandidateFormationIds = ...
    requestedCandidateFormationIds;
adaptive.targetHorizon = targetHorizon;
adaptive.evaluationHorizon = evaluationHorizon;
adaptive.referenceHorizonProfile = referenceProfile;
adaptive.routeProbe = routeProbe;
adaptive.referenceSquaredFactorAtEvaluationHorizon = ...
    referenceProfile. ...
        worstCaseExpectedSquaredFactorByHorizon(evaluationHorizon + 1);
adaptive.failClosedAtMaximumHorizon = ~calibrationPassed;
adaptive.posteriorContentsRead = false;
adaptive.truthUsed = false;
adaptive.futureOutcomeUsed = false;
adaptive.trackingOutcomeScored = false;
adaptive.developmentEvidenceOnly = true;
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
