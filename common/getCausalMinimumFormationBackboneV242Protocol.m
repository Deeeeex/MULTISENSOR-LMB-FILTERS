function protocol = getCausalMinimumFormationBackboneV242Protocol()
% GETCAUSALMINIMUMFORMATIONBACKBONEV242PROTOCOL Sparse dynamic backbone.

source = getCausalMinimalEditFormationTreeV240Protocol();
tracking = getCorrectedStaticRoutingBaselineV227Protocol();
protocol = struct();
protocol.id = 'causal-minimum-formation-backbone-v242-v1';
protocol.contractVersion = ...
    'causal-minimum-formation-backbone-v242-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.armId = 'v242-causal-minimum-formation-backbone';
protocol.policyName = ...
    'causal-minimum-formation-backbone-v242-policy';
protocol.allowedPresets = source.allowedPresets;
protocol.allowedSeeds = 1301;
protocol.dominantWeight = source.dominantWeight;
protocol.crossResidualWeight = source.residualWeight;
protocol.localResidualWeight = 0;
protocol.receiverMode = tracking.receiverMode;
protocol.filterSeedOffset = tracking.filterSeedOffset;
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v242', ...
    'causal_minimum_formation_backbone');
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V242 is a structural development policy on the opened formation-', ...
    'braid seed. It inherits the causal V240 formation-tree repair, keeps ', ...
    'one current physical directed cycle inside each formation, and keeps ', ...
    'only the two directed cross-formation gateway messages associated ', ...
    'with every undirected formation-tree edge. Omitted local residual ', ...
    'mass returns to receiver self weight. Its N+2(F-1) message count is ', ...
    'minimal only under this local-cycle plus bidirectional-tree ', ...
    'architecture; it is not a global directed-graph lower bound. ', ...
    'Structural results do not establish tracking gain, held-out ', ...
    'generalization or a paper claim.'];

if protocol.dominantWeight <= 0 || ...
        protocol.crossResidualWeight <= 0 || ...
        protocol.dominantWeight + ...
            protocol.crossResidualWeight >= 1
    error('CausalMinimumFormationBackboneV242:InvalidProtocol', ...
        'The V242 fusion-weight contract is inconsistent.');
end
end
