function protocol = getTrackingAlignedRoutingLeverageV58Protocol()
% GETTRACKINGALIGNEDROUTINGLEVERAGEV58PROTOCOL V58 attribution boundary.

protocol = struct();
protocol.id = 'tracking-aligned-routing-leverage-v58-v1';
protocol.contractVersion = ...
    'tracking-aligned-routing-leverage-v58-protocol-v1';
protocol.referencePolicyName = ...
    'formation-h3-fixed-ccw-reference-v1';
protocol.filterSeedOffset = 100000;
protocol.horizonSteps = 3;
protocol.retentionDebtOnFraction = 0.02;
protocol.eventScoreTailFraction = 0.34;
protocol.eventScoreTailWeight = 0.50;
protocol.selectedConvoyEventCount = 3;
protocol.minimumSelectedEventSeparation = 12;
protocol.excludedOpenedConvoyTimes = [60, 100, 132];
protocol.cases = [ ...
    caseEntry( ...
        'radial-opened-attribution', ...
        'm24-formation-fov', 211, 24, 4, ...
        [60, 72, 104, 124], 'cache_old_formation_fov'), ...
    caseEntry( ...
        'convoy-opened-development', ...
        'm24-formation-fov-convoy', 1201, 24, 4, ...
        40:4:136, 'cache_convoy_grid')];
protocol.presets = {protocol.cases.presetName};
protocol.allSeeds = unique([protocol.cases.seed], 'stable');
protocol.snapshotTimes = sort(unique([protocol.cases.snapshotTimes]));
protocol.cacheRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v58', 'leverage_attribution', 'cache');
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v58', 'leverage_attribution');
for caseIdx = 1:numel(protocol.cases)
    protocol.cases(caseIdx).cacheRoot = fullfile( ...
        protocol.outputRoot, ...
        protocol.cases(caseIdx).cacheSubdirectory);
end
protocol.openedTrackingTargets = [ ...
    targetEntry('m24-formation-fov', 211, 60, 1.4017, ...
        'V36 staggered recovery'), ...
    targetEntry('m24-formation-fov', 211, 72, 4.2952, ...
        'V35 staggered recovery'), ...
    targetEntry('m24-formation-fov', 211, 104, 10.3944, ...
        'V36 staggered recovery'), ...
    targetEntry('m24-formation-fov', 211, 124, 7.7641, ...
        'V36 staggered recovery'), ...
    targetEntry('m24-formation-fov-convoy', 1201, 60, 1.4820, ...
        'V57 best known formation-level action'), ...
    targetEntry('m24-formation-fov-convoy', 1201, 100, 0.304464, ...
        'V57 complete protection subset'), ...
    targetEntry('m24-formation-fov-convoy', 1201, 132, 0.104113, ...
        'V57 complete protection subset')];
protocol.referenceStateGenerationAuthorized = true;
protocol.trackingOutcomeScoringAuthorized = false;
protocol.x36OutcomeOpeningAuthorized = false;
protocol.modelTrainingAuthorized = false;
protocol.validationClaimAllowed = false;
protocol.openedDevelopmentEvidenceOnly = true;
protocol.evidenceBoundary = [ ...
    'V58 may reconstruct fixed-reference posterior states only for the ', ...
    'registered radial seed-211 attribution anchors and the opened M24 ', ...
    'convoy seed-1201 candidate grid. The runtime receives no target ', ...
    'truth and this protocol does not authorize tracking scoring, X36 ', ...
    'outcomes, model training, held-out seeds, or validation claims.'];
end

function value = caseEntry( ...
        caseId, presetName, seed, nodeCount, formationCount, ...
        snapshotTimes, cacheSubdirectory)
value = struct( ...
    'caseId', caseId, ...
    'presetName', presetName, ...
    'seed', seed, ...
    'nodeCount', nodeCount, ...
    'formationCount', formationCount, ...
    'snapshotTimes', reshape(snapshotTimes, 1, []), ...
    'cacheSubdirectory', cacheSubdirectory, ...
    'cacheRoot', '');
end

function value = targetEntry( ...
        presetName, seed, currentTime, meanGainPercent, source)
value = struct( ...
    'presetName', presetName, ...
    'seed', seed, ...
    'currentTime', currentTime, ...
    'meanGainPercent', meanGainPercent, ...
    'source', source);
end
