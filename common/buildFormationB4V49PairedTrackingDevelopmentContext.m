function context = ...
    buildFormationB4V49PairedTrackingDevelopmentContext( ...
        presetName, seed, armId)
% BUILDFORMATIONB4V49PAIREDTRACKINGDEVELOPMENTCONTEXT Minimal experiment gate.

protocol = getFormationB4V49RuntimeProtocol();
allowedPresets = { ...
    'm24-formation-fov', ...
    'm24-formation-fov-convoy', ...
    'm24-formation-fov-relay', ...
    'm24-formation-fov-crossing', ...
    'x36-formation-fov', ...
    'x36-formation-fov-convoy', ...
    'x36-formation-fov-relay', ...
    'x36-formation-fov-crossing'};
if ~ischar(presetName) || ~isrow(presetName) || ...
        ~any(strcmp(presetName, allowedPresets)) || ...
        ~isa(seed, 'double') || ~isreal(seed) || ...
        ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= floor(seed) || ...
        ~ischar(armId) || ~isrow(armId) || ...
        ~any(strcmp(armId, protocol.primaryArms))
    error('FormationB4V49Tracking:InvalidContextInput', ...
        'A registered M24/X36 preset, integer seed, and V46/V49 arm are required.');
end

context = struct();
context.contractVersion = ...
    'formation-b4-v49-paired-tracking-development-context-v1';
context.capability = 'paired-tracking-development';
context.action = 'filter-paired-tracking-development';
context.presetName = presetName;
context.seed = seed;
context.armId = armId;
context.developmentEvidenceOnly = true;
end
