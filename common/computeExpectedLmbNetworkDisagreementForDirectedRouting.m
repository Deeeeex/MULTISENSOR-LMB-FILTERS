function [networkRisk, details] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, adjacency, fusionWeights, options)
% COMPUTEEXPECTEDLMBNETWORKDISAGREEMENTFORDIRECTEDROUTING
% Exact one-round posterior-summary disagreement under link uncertainty.
%
% For each receiver, this function enumerates every independent delivery
% outcome on its selected incoming edges, executes the same heavy-payload
% LMB fusion and missing-message weight normalization as the controlled
% runtime, and caches the resulting label-wise posterior moments. It then
% integrates every receiver-pair disagreement over the two independent
% receiver outcome distributions.
%
% The result is exact for the registered one-round fusion-summary model.
% It is not a recursive tracking guarantee and it requires centralized
% access to the current posteriors used by the topology controller.
%
% When options supplies referenceNetworkDetails, referenceAdjacency and
% referenceFusionWeights together, receiver distributions and receiver-pair
% risks are reused only for rows unchanged from that reference.  Every pair
% touching a changed receiver is recomputed, so the incremental path is
% numerically equivalent to a complete evaluation.  Reuse details are a
% same-process optimization artifact, not externally authenticated
% provenance; persisted artifacts require an independent full-recompute
% audit before they can support a formal claim.

if nargin < 4 || isempty(options)
    options = struct();
end
aggregationMode = lower(strrep(char(getField( ...
    options, 'aggregationMode', 'mean')), '_', '-'));
tailFraction = getField(options, 'tailFraction', 0.25);
if ~ismember(aggregationMode, {'mean', 'tail'}) || ...
        ~isscalar(tailFraction) || ~isfinite(tailFraction) || ...
        tailFraction <= 0 || tailFraction > 1
    error('Expected-disagreement aggregation options are invalid.');
end
if ~isfield(context, 'localPosteriorBySensor') || ...
        ~iscell(context.localPosteriorBySensor) || ...
        ~isfield(context, 'model') || ...
        ~isfield(context, 'commConfig') || ...
        ~isfield(context, 'currentTime')
    error('Expected-disagreement context is incomplete.');
end
nodeCount = numel(context.localPosteriorBySensor);
adjacency = logical(adjacency);
if nodeCount < 2 || ...
        ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(fusionWeights), [nodeCount, nodeCount]) || ...
        any(~isfinite(fusionWeights(:))) || ...
        any(fusionWeights(:) < 0)
    error('Expected-disagreement routing inputs are invalid.');
end
adjacency(1:nodeCount+1:end) = false;
allowedWeights = adjacency | logical(eye(nodeCount));
if any(fusionWeights(:) > 0 & ~allowedWeights(:)) || ...
        any(abs(sum(fusionWeights, 2) - 1) > 1e-12) || ...
        any(diag(fusionWeights) <= 0)
    error('Expected-disagreement fusion weights violate the route.');
end

triggerConfig = getField(context, ...
    'triggerConfig', buildMixtureAwareKlaReferenceConfig());
validateRuntimeContract(triggerConfig);
fusionContext = context;
if isfield(context.model, 'sensorObservation')
    fusionContext.model = materializeObservableSensorFusionModel( ...
        context.model, context.currentTime);
end
maximumIncomingCount = getField( ...
    options, 'maximumIncomingCount', 4);
if ~isscalar(maximumIncomingCount) || ...
        ~isfinite(maximumIncomingCount) || ...
        maximumIncomingCount < 1 || ...
        maximumIncomingCount ~= round(maximumIncomingCount)
    error('ExpectedDirectedDisagreement:InvalidMaximumIncomingCount', ...
        'maximumIncomingCount must be a positive integer.');
end
reuseInputCanonicalSha256 = computeReuseInputCanonicalSha256( ...
    context, triggerConfig, aggregationMode, tailFraction, ...
    maximumIncomingCount);
routeCanonicalSha256 = computeRouteCanonicalSha256( ...
    adjacency, fusionWeights);

[incrementalReuseApplied, referenceDetails, changedReceiverMask] = ...
    resolveIncrementalReference( ...
        options, adjacency, fusionWeights, nodeCount, ...
        aggregationMode, tailFraction, maximumIncomingCount, ...
        reuseInputCanonicalSha256);
if incrementalReuseApplied
    receiverDistributions = referenceDetails.receiverDistributions;
    receiverOutcomeCounts = referenceDetails.receiverOutcomeCounts;
else
    receiverDistributions = cell(1, nodeCount);
    receiverOutcomeCounts = zeros(1, nodeCount);
    changedReceiverMask = true(1, nodeCount);
end
for receiverIdx = 1:nodeCount
    if ~changedReceiverMask(receiverIdx)
        continue;
    end
    senders = reshape(find(adjacency(receiverIdx, :)), 1, []);
    if numel(senders) > maximumIncomingCount
        error(['Expected-disagreement route exceeds the registered ', ...
            'incoming-edge enumeration limit.']);
    end
    receiverDistributions{receiverIdx} = ...
        enumerateReceiverOutcomes( ...
            fusionContext, receiverIdx, senders, ...
            fusionWeights(receiverIdx, :), triggerConfig);
    receiverOutcomeCounts(receiverIdx) = numel( ...
        receiverDistributions{receiverIdx}.probability);
end

if incrementalReuseApplied
    expectedPairRisk = referenceDetails.expectedPairRisk;
else
    expectedPairRisk = zeros(nodeCount);
end
for leftIdx = 1:nodeCount-1
    left = receiverDistributions{leftIdx};
    for rightIdx = leftIdx+1:nodeCount
        if incrementalReuseApplied && ...
                ~changedReceiverMask(leftIdx) && ...
                ~changedReceiverMask(rightIdx)
            continue;
        end
        right = receiverDistributions{rightIdx};
        value = 0;
        for leftOutcome = 1:numel(left.probability)
            for rightOutcome = 1:numel(right.probability)
                pair = computeLmbPosteriorSummaryDisagreement( ...
                    left.summary{leftOutcome}, ...
                    right.summary{rightOutcome});
                value = value + ...
                    left.probability(leftOutcome) * ...
                    right.probability(rightOutcome) * ...
                    pair.combined;
            end
        end
        expectedPairRisk(leftIdx, rightIdx) = value;
        expectedPairRisk(rightIdx, leftIdx) = value;
    end
end
networkRisk = aggregatePairMatrix( ...
    expectedPairRisk, aggregationMode, tailFraction);
if ~isfinite(networkRisk)
    error('Expected one-step network disagreement is non-finite.');
end
reuseCacheCanonicalSha256 = computeReuseCacheCanonicalSha256( ...
    reuseInputCanonicalSha256, routeCanonicalSha256, ...
    receiverOutcomeCounts, receiverDistributions, ...
    expectedPairRisk, networkRisk);

details = struct( ...
    'contractVersion', ...
        'directed-lmb-one-step-expected-disagreement-v1', ...
    'aggregationMode', aggregationMode, ...
    'tailFraction', tailFraction, ...
    'networkRisk', networkRisk, ...
    'expectedPairRisk', expectedPairRisk, ...
    'receiverOutcomeCounts', receiverOutcomeCounts, ...
    'receiverDistributions', {receiverDistributions}, ...
    'maximumIncomingCount', maximumIncomingCount, ...
    'incrementalReuseApplied', incrementalReuseApplied, ...
    'recomputedReceiverIndices', find(changedReceiverMask), ...
    'reusedReceiverIndices', find(~changedReceiverMask), ...
    'reuseInputCanonicalSha256', reuseInputCanonicalSha256, ...
    'routeCanonicalSha256', routeCanonicalSha256, ...
    'reuseCacheCanonicalSha256', reuseCacheCanonicalSha256, ...
    'incrementalCacheTrustModel', ...
        'same-process-produced-reference-details', ...
    'externalCacheVerificationClaimed', false, ...
    'externalArtifactFullRecomputeAuditRequired', true, ...
    'deliveryModel', ...
        'independent-bernoulli-current-link-reliability', ...
    'fusionModel', ...
        'runtime-heavy-payload-with-missing-weight-normalization', ...
    'singleRoundExact', true, ...
    'recursiveSafetyClaimed', false, ...
    'centralizedCurrentPosteriorRequired', true, ...
    'posteriorUsed', true, ...
    'currentLinkReliabilityUsed', true, ...
    'truthUsed', false, ...
    'groundTruthUsed', false, ...
    'futureMeasurementUsed', false, ...
    'futureOutcomeUsed', false);
end

function [enabled, details, changedReceiverMask] = ...
        resolveIncrementalReference( ...
            options, adjacency, fusionWeights, nodeCount, ...
            aggregationMode, tailFraction, maximumIncomingCount, ...
            reuseInputCanonicalSha256)
enabled = false;
details = struct();
changedReceiverMask = true(1, nodeCount);
requiredOptionFields = { ...
    'referenceNetworkDetails', ...
    'referenceAdjacency', ...
    'referenceFusionWeights'};
present = isfield(options, requiredOptionFields);
if ~any(present)
    return;
end
if ~all(present)
    error('ExpectedDirectedDisagreement:IncompleteIncrementalReference', ...
        ['Incremental expected-disagreement reuse requires ', ...
        'reference details, adjacency and fusion weights together.']);
end
details = options.referenceNetworkDetails;
referenceAdjacencyInput = options.referenceAdjacency;
referenceFusionWeights = options.referenceFusionWeights;
requiredDetailFields = { ...
    'contractVersion', 'expectedPairRisk', 'receiverOutcomeCounts', ...
    'receiverDistributions', 'networkRisk', ...
    'aggregationMode', 'tailFraction', ...
    'maximumIncomingCount', 'singleRoundExact', ...
    'truthUsed', 'futureOutcomeUsed', ...
    'reuseInputCanonicalSha256', 'routeCanonicalSha256', ...
    'reuseCacheCanonicalSha256', 'incrementalCacheTrustModel', ...
    'externalCacheVerificationClaimed', ...
    'externalArtifactFullRecomputeAuditRequired'};
if ~isstruct(details) || ~isscalar(details) || ...
        ~all(isfield(details, requiredDetailFields)) || ...
        ~strcmp(details.contractVersion, ...
            'directed-lmb-one-step-expected-disagreement-v1') || ...
        ~strcmp(details.incrementalCacheTrustModel, ...
            'same-process-produced-reference-details') || ...
        ~isequal(details.externalCacheVerificationClaimed, false) || ...
        ~isequal(details. ...
            externalArtifactFullRecomputeAuditRequired, true) || ...
        ~(isnumeric(referenceAdjacencyInput) || ...
          islogical(referenceAdjacencyInput)) || ...
        ~isequal(size(referenceAdjacencyInput), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(referenceFusionWeights), [nodeCount, nodeCount]) || ...
        ~isnumeric(referenceFusionWeights) || ...
        any(~isfinite(referenceFusionWeights(:))) || ...
        ~isequal(size(details.expectedPairRisk), ...
            [nodeCount, nodeCount]) || ...
        ~isnumeric(details.expectedPairRisk) || ...
        any(~isfinite(details.expectedPairRisk(:))) || ...
        ~isnumeric(details.receiverOutcomeCounts) || ...
        ~isequal(size(details.receiverOutcomeCounts), [1, nodeCount]) || ...
        any(~isfinite(details.receiverOutcomeCounts)) || ...
        any(details.receiverOutcomeCounts < 1) || ...
        any(details.receiverOutcomeCounts ~= ...
            round(details.receiverOutcomeCounts)) || ...
        ~iscell(details.receiverDistributions) || ...
        numel(details.receiverDistributions) ~= nodeCount || ...
        ~isscalar(details.networkRisk) || ...
        ~isfinite(details.networkRisk) || ...
        ~ischar(details.aggregationMode) || ...
        ~strcmp(details.aggregationMode, aggregationMode) || ...
        ~isscalar(details.tailFraction) || ...
        abs(details.tailFraction - tailFraction) > 1e-15 || ...
        ~isscalar(details.maximumIncomingCount) || ...
        details.maximumIncomingCount ~= maximumIncomingCount || ...
        ~isequal(details.singleRoundExact, true) || ...
        ~isequal(details.truthUsed, false) || ...
        ~isequal(details.futureOutcomeUsed, false) || ...
        ~isValidSha256(details.reuseInputCanonicalSha256) || ...
        ~isValidSha256(details.routeCanonicalSha256) || ...
        ~isValidSha256(details.reuseCacheCanonicalSha256)
    error('ExpectedDirectedDisagreement:MalformedIncrementalReference', ...
        'Incremental expected-disagreement reference is malformed.');
end
if ~strcmp(details.reuseInputCanonicalSha256, ...
        reuseInputCanonicalSha256)
    error('ExpectedDirectedDisagreement:IncrementalInputDrift', ...
        ['Incremental expected-disagreement reuse is invalid because ', ...
        'the posterior, model, link, trigger, time or scoring context ', ...
        'changed.']);
end
referenceAdjacency = logical(referenceAdjacencyInput);
referenceWeightSupport = ...
    referenceAdjacency | logical(eye(nodeCount));
if any(diag(referenceAdjacency)) || ...
        any(referenceFusionWeights(:) < 0) || ...
        any(referenceFusionWeights(:) > 0 & ...
            ~referenceWeightSupport(:)) || ...
        any(abs(sum(referenceFusionWeights, 2) - 1) > 1e-12)
    error('ExpectedDirectedDisagreement:MalformedIncrementalReference', ...
        'Incremental expected-disagreement reference route is malformed.');
end
if ~strcmp(computeRouteCanonicalSha256( ...
        referenceAdjacency, referenceFusionWeights), ...
        details.routeCanonicalSha256)
    error('ExpectedDirectedDisagreement:IncrementalRouteDrift', ...
        ['Incremental expected-disagreement reference route ', ...
        'identity drifted.']);
end
if any(any(abs(details.expectedPairRisk - ...
        details.expectedPairRisk.') > 1e-12)) || ...
        any(abs(diag(details.expectedPairRisk)) > 1e-12) || ...
        any(details.expectedPairRisk(:) < 0)
    error('ExpectedDirectedDisagreement:MalformedIncrementalReference', ...
        'Incremental expected-disagreement pair matrix is malformed.');
end
validateReceiverDistributions( ...
    details.receiverDistributions, details.receiverOutcomeCounts, ...
    referenceAdjacency);
referenceRisk = aggregatePairMatrix( ...
    details.expectedPairRisk, aggregationMode, tailFraction);
if abs(referenceRisk - details.networkRisk) > ...
        1e-12 * max(1, abs(details.networkRisk))
    error('ExpectedDirectedDisagreement:MalformedIncrementalReference', ...
        'Incremental expected-disagreement reference risk drifted.');
end
actualCacheSha256 = computeReuseCacheCanonicalSha256( ...
    details.reuseInputCanonicalSha256, ...
    details.routeCanonicalSha256, ...
    details.receiverOutcomeCounts, details.receiverDistributions, ...
    details.expectedPairRisk, details.networkRisk);
if ~strcmp(actualCacheSha256, details.reuseCacheCanonicalSha256)
    error('ExpectedDirectedDisagreement:IncrementalCacheDrift', ...
        ['Incremental expected-disagreement receiver or pair cache ', ...
        'identity drifted.']);
end
changedReceiverMask = reshape(any( ...
    adjacency ~= referenceAdjacency, 2) | ...
    any(fusionWeights ~= referenceFusionWeights, 2), ...
    1, []);
enabled = true;
end

function sha256 = computeReuseInputCanonicalSha256( ...
        context, triggerConfig, aggregationMode, tailFraction, ...
        maximumIncomingCount)
payload = struct();
payload.contractVersion = ...
    'directed-lmb-one-step-incremental-reuse-input-v1';
payload.localPosteriorBySensor = projectLmbPosteriorSemantics( ...
    context.localPosteriorBySensor);
payload.model = struct( ...
    'xDimension', context.model.xDimension, ...
    'existenceThreshold', context.model.existenceThreshold, ...
    'object', projectLmbObjectArray(context.model.object));
if isfield(context.model, 'sensorObservation')
    payload.model.sensorObservation = ...
        context.model.sensorObservation;
end
payload.currentLinkReliability = buildCurrentLinkReliability( ...
    context.commConfig, numel(context.localPosteriorBySensor), ...
    context.currentTime);
payload.triggerConfig = buildFusionSemanticTriggerConfig(triggerConfig);
payload.currentTime = context.currentTime;
payload.aggregationMode = aggregationMode;
payload.tailFraction = tailFraction;
payload.maximumIncomingCount = maximumIncomingCount;
sha256 = computeCanonicalValueSha256(payload);
end

function projected = projectLmbPosteriorSemantics(posteriors)
projected = cell(size(posteriors));
for sensorIdx = 1:numel(posteriors)
    projected{sensorIdx} = projectLmbObjectArray(posteriors{sensorIdx});
end
end

function projected = projectLmbObjectArray(objects)
template = struct( ...
    'birthTime', 0, ...
    'birthLocation', 0, ...
    'r', 0, ...
    'numberOfGmComponents', 0, ...
    'w', zeros(1, 0), ...
    'mu', {cell(1, 0)}, ...
    'Sigma', {cell(1, 0)}, ...
    'associationAmbiguity', 0, ...
    'detectionAssociationMass', 0);
projected = repmat(template, size(objects));
for objectIdx = 1:numel(objects)
    object = objects(objectIdx);
    requiredFields = { ...
        'birthTime', 'birthLocation', 'r', ...
        'numberOfGmComponents', 'w', 'mu', 'Sigma'};
    if ~isstruct(object) || ~all(isfield(object, requiredFields))
        error('ExpectedDirectedDisagreement:InvalidPosterior', ...
            'An LMB posterior object is missing a fusion-semantic field.');
    end
    projected(objectIdx).birthTime = object.birthTime;
    projected(objectIdx).birthLocation = object.birthLocation;
    projected(objectIdx).r = object.r;
    projected(objectIdx).numberOfGmComponents = ...
        object.numberOfGmComponents;
    projected(objectIdx).w = object.w;
    projected(objectIdx).mu = object.mu;
    projected(objectIdx).Sigma = object.Sigma;
    projected(objectIdx).associationAmbiguity = ...
        normalizedOptionalUnitField(object, 'associationAmbiguity');
    projected(objectIdx).detectionAssociationMass = ...
        normalizedOptionalUnitField(object, 'detectionAssociationMass');
end
end

function value = normalizedOptionalUnitField(object, fieldName)
value = getField(object, fieldName, 0);
if isempty(value) || ~isscalar(value) || ~isfinite(value)
    value = 0;
end
value = min(max(value, 0), 1);
end

function reliability = buildCurrentLinkReliability( ...
        commConfig, nodeCount, currentTime)
reliability = zeros(nodeCount);
for senderIdx = 1:nodeCount
    for receiverIdx = 1:nodeCount
        if senderIdx ~= receiverIdx
            reliability(senderIdx, receiverIdx) = edgeReliability( ...
                commConfig, senderIdx, receiverIdx, currentTime);
        end
    end
end
end

