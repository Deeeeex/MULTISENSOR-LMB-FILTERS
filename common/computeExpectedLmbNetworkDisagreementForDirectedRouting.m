function validateReceiverDistributions( ...
        distributions, outcomeCounts, referenceAdjacency)
requiredFields = sort({ ...
    'receiverIndex', 'senderIndices', 'senderReliabilities', ...
    'deliveryMask', 'probability', 'effectiveWeights', 'summary'});
nodeCount = numel(distributions);
for receiverIdx = 1:nodeCount
    distribution = distributions{receiverIdx};
    senders = reshape(find(referenceAdjacency(receiverIdx, :)), 1, []);
    outcomeCount = 2^numel(senders);
    if ~isstruct(distribution) || ~isscalar(distribution) || ...
            ~isequal(sort(fieldnames(distribution)), requiredFields(:)) || ...
            ~isscalar(distribution.receiverIndex) || ...
            distribution.receiverIndex ~= receiverIdx || ...
            ~isequal(reshape(distribution.senderIndices, 1, []), senders) || ...
            ~isnumeric(distribution.senderReliabilities) || ...
            ~isequal(size(distribution.senderReliabilities), ...
                size(senders)) || ...
            any(~isfinite(distribution.senderReliabilities)) || ...
            any(distribution.senderReliabilities < 0) || ...
            any(distribution.senderReliabilities > 1) || ...
            outcomeCounts(receiverIdx) ~= outcomeCount || ...
            ~(islogical(distribution.deliveryMask) || ...
              isnumeric(distribution.deliveryMask)) || ...
            ~isequal(size(distribution.deliveryMask), ...
                [outcomeCount, numel(senders)]) || ...
            ~isnumeric(distribution.probability) || ...
            ~isequal(size(distribution.probability), [1, outcomeCount]) || ...
            any(~isfinite(distribution.probability)) || ...
            any(distribution.probability < 0) || ...
            abs(sum(distribution.probability) - 1) > 1e-12 || ...
            ~iscell(distribution.effectiveWeights) || ...
            ~isequal(size(distribution.effectiveWeights), ...
                [1, outcomeCount]) || ...
            ~iscell(distribution.summary) || ...
            ~isequal(size(distribution.summary), [1, outcomeCount])
        malformedDistribution();
    end
    expectedMask = false(outcomeCount, numel(senders));
    for outcomeIdx = 0:(outcomeCount - 1)
        expectedMask(outcomeIdx + 1, :) = logical(bitget( ...
            outcomeIdx, 1:numel(senders)));
    end
    if ~isequal(logical(distribution.deliveryMask), expectedMask)
        malformedDistribution();
    end
    for outcomeIdx = 1:outcomeCount
        deliveredCount = nnz(expectedMask(outcomeIdx, :));
        weights = distribution.effectiveWeights{outcomeIdx};
        if ~isnumeric(weights) || ...
                ~isequal(size(weights), [1, 1 + deliveredCount]) || ...
                any(~isfinite(weights)) || any(weights < 0) || ...
                abs(sum(weights) - 1) > 1e-12
            malformedDistribution();
        end
        validateDisagreementSummary(distribution.summary{outcomeIdx});
    end
end
end

function validateDisagreementSummary(summary)
requiredFields = sort({ ...
    'contractVersion', 'labels', 'existence', ...
    'positionMean', 'positionCovariance'});
if ~isstruct(summary) || ~isscalar(summary) || ...
        ~isequal(sort(fieldnames(summary)), requiredFields(:)) || ...
        ~strcmp(summary.contractVersion, 'lmb-disagreement-summary-v1') || ...
        ~isnumeric(summary.labels) || size(summary.labels, 1) ~= 2 || ...
        ~isnumeric(summary.existence) || ...
        ~isequal(size(summary.existence), [1, size(summary.labels, 2)]) || ...
        ~isnumeric(summary.positionMean) || ...
        ~isequal(size(summary.positionMean), size(summary.labels)) || ...
        ~isnumeric(summary.positionCovariance) || ...
        size(summary.positionCovariance, 1) ~= 2 || ...
        size(summary.positionCovariance, 2) ~= 2 || ...
        size(summary.positionCovariance, 3) ~= size(summary.labels, 2) || ...
        any(~isfinite(summary.labels(:))) || ...
        any(~isfinite(summary.existence(:))) || ...
        any(summary.existence(:) < 0) || ...
        any(summary.existence(:) > 1) || ...
        any(~isfinite(summary.positionMean(:))) || ...
        any(~isfinite(summary.positionCovariance(:)))
    malformedDistribution();
end
end

function malformedDistribution()
error('ExpectedDirectedDisagreement:MalformedIncrementalReference', ...
    ['Incremental expected-disagreement receiver distribution ', ...
    'cache is malformed.']);
end

