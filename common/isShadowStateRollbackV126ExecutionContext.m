function detected = isShadowStateRollbackV126ExecutionContext(context)
% ISSHADOWSTATEROLLBACKV126EXECUTIONCONTEXT Identify V126.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'shadow-state-rollback-v126-context-v1');
end
