function selection = ...
    buildCounterfactualRegretGateV133BaselineSelection( ...
        shards, protocol, gitState)
% BUILDCOUNTERFACTUALREGRETGATEV133BASELINESELECTION Pure shard reducer.

if nargin < 2 || isempty(protocol)
    protocol = getCounterfactualRegretGateV133Protocol();
end
if nargin < 3 || isempty(gitState)
    gitState = resolveResearchGitState();
end
expectedCount = numel(protocol.scaleCases) * ...
    numel(protocol.developmentSeeds) * ...
    numel(protocol.referenceCarrierModes);
if ~isstruct(shards) || numel(shards) ~= expectedCount
    error('CounterfactualRegretV133:IncompleteBaselineShards', ...
        'V133 carrier selection requires every registered baseline shard.');
end

caseSelections = repmat(emptyCaseSelection(), ...
    1, numel(protocol.scaleCases));
used = false(1, numel(shards));
for caseIdx = 1:numel(protocol.scaleCases)
    caseInfo = protocol.scaleCases(caseIdx);
    records = repmat(emptyRecord(), ...
        numel(protocol.developmentSeeds), ...
        numel(protocol.referenceCarrierModes));
    for seedIdx = 1:numel(protocol.developmentSeeds)
        seed = protocol.developmentSeeds(seedIdx);
        for carrierIdx = 1:numel(protocol.referenceCarrierModes)
            carrierMode = protocol.referenceCarrierModes{carrierIdx};
            match = find(arrayfun(@(shard) ...
                strcmp(shard.presetName, caseInfo.presetName) && ...
                shard.seed == seed && ...
                strcmp(shard.carrierMode, carrierMode), shards));
            if numel(match) ~= 1 || used(match) || ...
                    ~validShard(shards(match), protocol, caseInfo, ...
                        seed, carrierMode, gitState)
                error('CounterfactualRegretV133:InvalidBaselineShard', ...
                    ['V133 baseline shards are incomplete, duplicated, ', ...
                     'or provenance-incompatible.']);
            end
            used(match) = true;
            records(seedIdx, carrierIdx) = shards(match).record;
        end
    end
    means = zeros(1, numel(protocol.referenceCarrierModes));
    focusMeans = means;
    for carrierIdx = 1:numel(protocol.referenceCarrierModes)
        means(carrierIdx) = mean([records(:, carrierIdx).meanEospa]);
        focusMeans(carrierIdx) = mean( ...
            [records(:, carrierIdx).focusMeanEospa]);
    end
    [~, selectedIdx] = min(means);
    rejectedIdx = setdiff(1:numel(means), selectedIdx);
    pairedGain = 100 * (means(rejectedIdx) - means(selectedIdx)) / ...
        max(means(rejectedIdx), eps);
    caseSelections(caseIdx) = struct( ...
        'scaleName', caseInfo.scaleName, ...
        'presetName', caseInfo.presetName, ...
        'carrierModes', {protocol.referenceCarrierModes}, ...
        'records', records, ...
        'meanEospaByCarrier', means, ...
        'focusMeanEospaByCarrier', focusMeans, ...
        'selectedCarrierMode', ...
            protocol.referenceCarrierModes{selectedIdx}, ...
        'selectedCarrierIndex', selectedIdx, ...
        'selectionGainPercent', pairedGain, ...
        'selectionRule', protocol.referenceCarrierSelectionRule, ...
        'perStateOracleSelectionUsed', false);
end
if ~all(used)
    error('CounterfactualRegretV133:InvalidBaselineShard', ...
        'At least one baseline shard is outside the registered matrix.');
end

selection = struct( ...
    'contractVersion', ...
        'counterfactual-regret-gate-v133-frozen-carrier-selection-v1', ...
    'protocolId', protocol.id, ...
    'developmentSeeds', protocol.developmentSeeds, ...
    'cases', caseSelections, ...
    'selectionMetric', 'complete-trajectory-paired-mean-eospa', ...
    'perStateOracleSelectionUsed', false, ...
    'generationGitCommit', gitState.commit, ...
    'generationTrackedWorktreeDirty', ...
        gitState.trackedWorktreeDirty, ...
    'generationUntrackedSourceFiles', ...
        {gitState.untrackedSourceFiles}, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', ...
        'repository-method-record-until-final-tracking-gate-passes', ...
    'evidenceBoundary', protocol.evidenceBoundary);
end

function valid = validShard( ...
        shard, protocol, caseInfo, seed, carrierMode, gitState)
required = { ...
    'contractVersion', 'protocolId', 'scaleName', 'presetName', ...
    'seed', 'carrierMode', 'record', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles'};
recordRequired = { ...
    'seed', 'carrierMode', 'meanEospa', 'focusMeanEospa', ...
    'worstSensorEospa', 'attemptedBytes', 'deliveredBytes', ...
    'elapsedSeconds', 'policyTruthUsed', 'policyFutureOutcomeUsed'};
valid = isscalar(shard) && all(isfield(shard, required)) && ...
    strcmp(shard.contractVersion, ...
        'counterfactual-regret-gate-v133-baseline-shard-v1') && ...
    strcmp(shard.protocolId, protocol.id) && ...
    strcmp(shard.scaleName, caseInfo.scaleName) && ...
    strcmp(shard.presetName, caseInfo.presetName) && ...
    shard.seed == seed && strcmp(shard.carrierMode, carrierMode) && ...
    strcmp(shard.generationGitCommit, gitState.commit) && ...
    ~shard.generationTrackedWorktreeDirty && ...
    isempty(shard.generationUntrackedSourceFiles) && ...
    isstruct(shard.record) && isscalar(shard.record) && ...
    all(isfield(shard.record, recordRequired)) && ...
    shard.record.seed == seed && ...
    strcmp(shard.record.carrierMode, carrierMode) && ...
    all(isfinite([ ...
        shard.record.meanEospa, shard.record.focusMeanEospa, ...
        shard.record.worstSensorEospa, shard.record.attemptedBytes, ...
        shard.record.deliveredBytes, shard.record.elapsedSeconds])) && ...
    ~shard.record.policyTruthUsed && ...
    ~shard.record.policyFutureOutcomeUsed;
end

function value = emptyRecord()
value = struct( ...
    'seed', 0, 'carrierMode', '', ...
    'meanEospa', NaN, 'focusMeanEospa', NaN, ...
    'worstSensorEospa', NaN, ...
    'attemptedBytes', NaN, 'deliveredBytes', NaN, ...
    'elapsedSeconds', NaN, ...
    'policyTruthUsed', false, ...
    'policyFutureOutcomeUsed', false);
end

function value = emptyCaseSelection()
value = struct( ...
    'scaleName', '', 'presetName', '', ...
    'carrierModes', {cell(1, 0)}, ...
    'records', repmat(emptyRecord(), 0, 0), ...
    'meanEospaByCarrier', [], ...
    'focusMeanEospaByCarrier', [], ...
    'selectedCarrierMode', '', ...
    'selectedCarrierIndex', 0, ...
    'selectionGainPercent', NaN, ...
    'selectionRule', '', ...
    'perStateOracleSelectionUsed', false);
end
