function [scores, details] = ...
    computeRollingSafeCounterfactualConsensusEdgeScores( ...
        context, receiverIndices, senderIndices, ...
        baselineSources, options)
% COMPUTEROLLINGSAFECOUNTERFACTUALCONSENSUSEDGESCORES Offline KLA teacher.
%
% The baseline joint action lets every receiver attempt its registered
% cycle edge. For every candidate sender->receiver replacement, this
% function executes the same heavy-payload LMB fusion as the controlled
% runtime and computes its single-replacement marginal relative to the
% baseline joint action. Link deliveries are independent Bernoulli events.
%
% Mean mode is the exact expected global pair-disagreement marginal for
% one replaced receiver. Tail mode is the global CVaR of expected pair
% risks, not the expectation of realized-network CVaR. When a downstream
% projector selects k>1 candidates additively, both modes are a
% baseline-linearized proxy because interactions between two replaced
% receivers are omitted.
%
% The function is truth-free, but not deployment-observable: evaluating all
% candidates requires centralized access to every current full posterior.
% It is intended as a diagnostic/offline teacher for a later summary-only
% learned scorer.

if nargin < 5 || isempty(options)
    options = struct();
end
sourceWeight = getField(options, 'sourceWeight', 0.70);
aggregationMode = lower(strrep(char(getField( ...
    options, 'aggregationMode', 'mean')), '_', '-'));
tailFraction = min(max(getField( ...
    options, 'tailFraction', 0.25), eps), 1);
if ~ismember(aggregationMode, {'mean', 'tail'})
    error('Counterfactual consensus aggregation must be mean or tail.');
end
receiverIndices = reshape(receiverIndices, [], 1);
senderIndices = reshape(senderIndices, [], 1);
baselineSources = reshape(baselineSources, 1, []);
nodeCount = numel(context.localPosteriorBySensor);
if nodeCount < 2 || ...
        numel(receiverIndices) ~= numel(senderIndices) || ...
        numel(baselineSources) ~= nodeCount || ...
        any(receiverIndices < 1 | receiverIndices > nodeCount) || ...
        any(senderIndices < 1 | senderIndices > nodeCount) || ...
        any(baselineSources < 1 | baselineSources > nodeCount)
    error('Counterfactual consensus action indices are invalid.');
end
if any(receiverIndices == senderIndices) || ...
        any((1:nodeCount) == baselineSources)
    error('Counterfactual consensus requires non-self routes.');
end

triggerConfig = getField(context, ...
    'triggerConfig', buildMixtureAwareKlaReferenceConfig());
validateRuntimeContract(triggerConfig);
posteriors = reshape(context.localPosteriorBySensor, 1, []);
failurePosteriors = cell(1, nodeCount);
failureSummaries = cell(1, nodeCount);
baselinePosteriors = cell(1, nodeCount);
baselineSummaries = cell(1, nodeCount);
baselineReliability = zeros(1, nodeCount);
for receiverIdx = 1:nodeCount
    % With no delivered neighbor, runtime still finalizes its single local
    % input and removes Bernoulli components below the state threshold.
    % A one-input moment match preserves exactly the moments consumed by
    % this metric, so explicit pruning is the sufficient cached form.
    failurePosteriors{receiverIdx} = selectActiveObjects( ...
        posteriors{receiverIdx}, context.model.existenceThreshold);
    failureSummaries{receiverIdx} = ...
        summarizeLmbPosteriorForDisagreement( ...
            failurePosteriors{receiverIdx}, context.model);
    baselineSender = baselineSources(receiverIdx);
    baselinePosteriors{receiverIdx} = fuseCandidate( ...
        posteriors{receiverIdx}, posteriors{baselineSender}, ...
        sourceWeight, context.model, triggerConfig);
    baselineSummaries{receiverIdx} = ...
        summarizeLmbPosteriorForDisagreement( ...
            baselinePosteriors{receiverIdx}, context.model);
    baselineReliability(receiverIdx) = edgeReliability( ...
        context.commConfig, baselineSender, receiverIdx, ...
        context.currentTime);
end

baselineExpectedPairRisk = zeros(nodeCount);
for leftIdx = 1:nodeCount-1
    for rightIdx = leftIdx+1:nodeCount
        value = expectedPairRisk( ...
            failureSummaries{leftIdx}, ...
            baselineSummaries{leftIdx}, ...
            baselineReliability(leftIdx), ...
            failureSummaries{rightIdx}, ...
            baselineSummaries{rightIdx}, ...
            baselineReliability(rightIdx));
        baselineExpectedPairRisk(leftIdx, rightIdx) = value;
        baselineExpectedPairRisk(rightIdx, leftIdx) = value;
    end
end
baselineNetworkRisk = aggregatePairMatrix( ...
    baselineExpectedPairRisk, aggregationMode, tailFraction);

exampleCount = numel(receiverIndices);
candidateReliability = zeros(exampleCount, 1);
candidateExpectedNetworkRisk = zeros(exampleCount, 1);
candidateExpectedPairRisks = ...
    zeros(nodeCount, nodeCount, exampleCount);
scores = zeros(exampleCount, 1);
for exampleIdx = 1:exampleCount
    receiverIdx = receiverIndices(exampleIdx);
    senderIdx = senderIndices(exampleIdx);
    candidatePosterior = fuseCandidate( ...
        posteriors{receiverIdx}, posteriors{senderIdx}, ...
        sourceWeight, context.model, triggerConfig);
    candidateSummary = summarizeLmbPosteriorForDisagreement( ...
        candidatePosterior, context.model);
    candidateReliability(exampleIdx) = edgeReliability( ...
        context.commConfig, senderIdx, receiverIdx, ...
        context.currentTime);
    candidateExpectedPairRisk = baselineExpectedPairRisk;
    for referenceIdx = 1:nodeCount
        if referenceIdx == receiverIdx
            continue;
        end
        value = expectedPairRisk( ...
            failureSummaries{receiverIdx}, candidateSummary, ...
            candidateReliability(exampleIdx), ...
            failureSummaries{referenceIdx}, ...
            baselineSummaries{referenceIdx}, ...
            baselineReliability(referenceIdx));
        candidateExpectedPairRisk(receiverIdx, referenceIdx) = value;
        candidateExpectedPairRisk(referenceIdx, receiverIdx) = value;
    end
    candidateExpectedNetworkRisk(exampleIdx) = aggregatePairMatrix( ...
        candidateExpectedPairRisk, aggregationMode, tailFraction);
    candidateExpectedPairRisks(:, :, exampleIdx) = ...
        candidateExpectedPairRisk;
    scores(exampleIdx) = baselineNetworkRisk - ...
        candidateExpectedNetworkRisk(exampleIdx);
end
if any(~isfinite(scores))
    error('Counterfactual consensus scores are non-finite.');
end

details = struct( ...
    'contractVersion', ...
        'rolling-safe-counterfactual-joint-baseline-teacher-v2', ...
    'aggregationMode', aggregationMode, ...
    'tailFraction', tailFraction, ...
    'tailSemantics', ...
        'global-cvar-of-expected-pair-risk', ...
    'sourceWeight', sourceWeight, ...
    'receiverIndices', receiverIndices, ...
    'senderIndices', senderIndices, ...
    'baselineSources', baselineSources, ...
    'failurePosteriorFinalization', ...
        'existence-threshold-pruned-local', ...
    'baselineReliability', baselineReliability, ...
    'candidateReliability', candidateReliability, ...
    'baselineExpectedPairRisk', baselineExpectedPairRisk, ...
    'baselineExpectedNetworkRisk', baselineNetworkRisk, ...
    'candidateExpectedNetworkRisk', ...
        candidateExpectedNetworkRisk, ...
    'candidateExpectedPairRisks', ...
        candidateExpectedPairRisks, ...
    'residualScores', scores, ...
    'singleReplacementMarginalExact', true, ...
    'multiReplacementCombination', ...
        'baseline-linearized-additive-proxy', ...
    'centralizedOfflineTeacher', true, ...
    'deploymentObservable', false, ...
    'requiresAllCurrentFullPosteriors', true, ...
    'posteriorUsed', true, ...
    'currentLinkReliabilityUsed', true, ...
    'currentGeometryUsed', false, ...
    'truthUsed', false, ...
    'groundTruthUsed', false, ...
    'futureMeasurementUsed', false, ...
    'futureGeometryUsed', false, ...
    'futureOutcomeUsed', false);
end

function expected = expectedPairRisk( ...
        leftFailure, leftSuccess, leftReliability, ...
        rightFailure, rightSuccess, rightReliability)
successSuccess = summaryDistance(leftSuccess, rightSuccess);
successFailure = summaryDistance(leftSuccess, rightFailure);
failureSuccess = summaryDistance(leftFailure, rightSuccess);
failureFailure = summaryDistance(leftFailure, rightFailure);
expected = ...
    leftReliability * rightReliability * successSuccess + ...
    leftReliability * (1 - rightReliability) * successFailure + ...
    (1 - leftReliability) * rightReliability * failureSuccess + ...
    (1 - leftReliability) * (1 - rightReliability) * failureFailure;
end

function value = summaryDistance(left, right)
metrics = computeLmbPosteriorSummaryDisagreement(left, right);
value = metrics.combined;
end

function risk = aggregatePairMatrix( ...
        pairRisk, aggregationMode, tailFraction)
values = pairRisk(triu(true(size(pairRisk)), 1));
if isempty(values)
    risk = 0;
elseif strcmp(aggregationMode, 'mean')
    risk = mean(values);
else
    values = sort(values, 'descend');
    tailCount = max(1, ceil(tailFraction * numel(values)));
    risk = mean(values(1:tailCount));
end
end

function fused = fuseCandidate( ...
        receiverPosterior, senderPosterior, sourceWeight, ...
        model, triggerConfig)
payload = selectActiveObjects( ...
    senderPosterior, triggerConfig.payloadExistenceThreshold);
weights = [1 - sourceWeight, sourceWeight];
fusionDetails = struct('eventType', [0, 2]);
fused = fuseLmbPosteriorsByLabel( ...
    {receiverPosterior, payload}, weights, ...
    model, weights, fusionDetails, triggerConfig);
fused = selectActiveObjects(fused, model.existenceThreshold);
end

function selected = selectActiveObjects(objects, threshold)
if isempty(objects)
    selected = objects;
    return;
end
active = [objects.r] > threshold & ...
    [objects.numberOfGmComponents] > 0;
selected = objects(active);
end

function reliability = edgeReliability( ...
        config, senderIdx, receiverIdx, currentTime)
if sensorOutageAtCurrentTime(config, senderIdx, currentTime)
    reliability = 0;
    return;
end
if getField(config, 'forceDelivery', false)
    reliability = 1;
    return;
end
if isfield(config, 'pDropByEdge') && ~isempty(config.pDropByEdge)
    if ndims(config.pDropByEdge) >= 3
        timeIdx = min(max(1, currentTime), ...
            size(config.pDropByEdge, 3));
        dropProbability = config.pDropByEdge( ...
            senderIdx, receiverIdx, timeIdx);
    else
        dropProbability = config.pDropByEdge(senderIdx, receiverIdx);
    end
elseif isfield(config, 'pDropBySensor') && ...
        numel(config.pDropBySensor) >= senderIdx
    dropProbability = config.pDropBySensor(senderIdx);
else
    dropProbability = getField(config, 'pDrop', 0);
end
reliability = 1 - min(max(dropProbability, 0), 1);
end

function active = sensorOutageAtCurrentTime( ...
        config, sensorIdx, currentTime)
active = false;
schedule = getField(config, 'outageSchedule', []);
for windowIdx = 1:numel(schedule)
    if schedule(windowIdx).sensor == sensorIdx && ...
            currentTime >= schedule(windowIdx).start && ...
            currentTime <= schedule(windowIdx).end
        active = true;
        return;
    end
end
end

function validateRuntimeContract(config)
if ~strcmpi(getField(config, 'eventPolicy', ''), 'alwaysHeavy')
    unsupported('eventPolicy must be alwaysHeavy');
end
if getField(config, 'linkGateEnabled', true)
    unsupported('linkGateEnabled must be false');
end
if getField(config, 'useStaleNeighborCache', false)
    unsupported('stale-cache fusion is not modeled');
end
if getField(config, 'mixedPayloadEnabled', false)
    unsupported('mixed heavy/light payloads are not modeled');
end
if getField(config, 'modeAwareFusionWeights', false)
    unsupported('mode-aware fusion weights are not modeled');
end
if getField(config, 'nonStaticFusionWeightFactor', 1) ~= 1 || ...
        isfinite(getField(config, 'maxSelfFusionWeight', inf)) || ...
        isfinite(getField(config, 'maxNonStaticFusionWeight', inf))
    unsupported('runtime weight factors or caps are not modeled');
end
if strcmpi(getField(config, 'fusionWeightMode', 'metropolis'), ...
        'balanced')
    unsupported('adaptive balanced fusion weights are not modeled');
end
if getField(config, 'mixtureAwareExistenceFromLightEnabled', false)
    unsupported('light-equivalent existence replacement is not modeled');
end
if getField(config, ...
        'mixtureAwarePredictionConsistencyEnabled', false) || ...
        getField(config, ...
            'mixtureAwareTrajectoryConsistencyEnabled', false)
    unsupported('post-fusion component reweighting is not modeled');
end
end

function unsupported(reason)
error('CounterfactualConsensus:UnsupportedRuntime', ...
    'Unsupported counterfactual runtime: %s.', reason);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
