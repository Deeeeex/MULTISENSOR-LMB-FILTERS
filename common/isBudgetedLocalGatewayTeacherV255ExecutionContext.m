function detected = ...
        isBudgetedLocalGatewayTeacherV255ExecutionContext(context)
% ISBUDGETEDLOCALGATEWAYTEACHERV255EXECUTIONCONTEXT Recognize V255.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'budgeted-local-gateway-teacher-v255-context-v1');
end
