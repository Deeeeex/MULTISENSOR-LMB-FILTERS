    'observation-supported-routing-leverage-v60-protocol-v1';
protocol.positiveSupportThreshold = 0.20;
protocol.strongGainPercent = 5;
protocol.weakGainPercent = 2;
protocol.selectedConvoyEventCount = 3;
protocol.minimumSelectedEventSeparation = 12;
protocol.cases = v58.cases;
