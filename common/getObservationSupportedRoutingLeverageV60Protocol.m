    'V60 reuses the registered V58 M24 reference caches and current ', ...
    'posterior association metadata. Opened H=3 tracking gains are joined ', ...
    'only after observable features are computed. No new tracking outcome, ', ...
    'X36 result, model training or validation claim is authorized.'];
end

