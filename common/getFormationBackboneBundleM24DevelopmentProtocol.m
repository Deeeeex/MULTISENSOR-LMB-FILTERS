function protocol = getFormationBackboneBundleM24DevelopmentProtocol()
% GETFORMATIONBACKBONEBUNDLEM24DEVELOPMENTPROTOCOL Frozen source core.
%
% This core authorizes only truth-free fixed-reference source trajectories.
% Candidate continuation and every tracking outcome remain sealed until a
% cache/source manifest is frozen by a later, data-only gate.

method = getFormationBackboneBundleStaggeredRecoveryPolicyConfig();
payload = struct();
payload.id = 'formation-backbone-bundle-m24-development-v1';
payload.contractVersion = ...
    'formation-backbone-bundle-m24-development-protocol-core-v1';
payload.methodPolicyConfigSha256 = method.canonicalSha256;
payload.methodSourceCommit = ...
    '5de0aa61a271b6999e8723af3b7378d8c7fd2aa0';
payload.filterSeedOffset = 100000;
payload.seeds = [41, 43, 47, 53, 59];
payload.caseOrdering = 'scene-major-then-seed-ascending';
payload.sourceCapability = 'source-posterior-only';
payload.sourceFilterAction = 'filter-source-posterior';
payload.sourcePreparationContractVersion = ...
    'formation-backbone-bundle-m24-prepared-source-input-v1';
payload.sourceInputFingerprintContractVersion = ...
    'formation-backbone-bundle-m24-source-input-fingerprint-v1';
payload.executableSourceManifestContractVersion = ...
    'formation-backbone-bundle-m24-executable-source-manifest-v1';
payload.executableSourceFrozen = false;
payload.executableSourceCommit = '';
payload.executableSourceManifestSha256 = '';
payload.sourceInputFingerprintsFrozen = false;
payload.sourceArm = struct( ...
    'id', 'formation-backbone-residual-tour-reference-v38-v1', ...
    'ordinal', 1, ...
    'role', 'fixed-reference-source', ...
    'topologyPolicyFunction', ...
        'selectFormationBackboneReferenceRuntimePolicy', ...
    'policyContractVersion', ...
        'formation-backbone-reference-runtime-policy-v1', ...
    'routeId', ...
        ['fixed-index-plus-registered-formation-', ...
         'backbone-residual-tour-v1'], ...
    'posteriorAdaptive', false, ...
    'currentPhysicalActionSetRequired', true, ...
    'currentLinkReliabilityAdaptive', false);
payload.futureOrderedArmIds = { ...
    payload.sourceArm.id, ...
    'formation-backbone-bundle-staggered-recovery-v38-v1'};
payload.sourcePosteriorAuthorized = false;
payload.candidateContinuationAuthorized = false;
payload.pairedTrackingAuthorized = false;
payload.trackingOutcomeScoringAuthorized = false;
payload.groundTruthAccessAuthorized = false;
payload.futureOutcomeAccessAuthorized = false;
payload.validationClaimAllowed = false;
payload.developmentEvidenceOnly = true;
payload.sourceExecutionMultiplicity = ...
    'deterministic-reproduction-allowed-nonoverwriting-output';
payload.continuationCacheBaseContractVersion = ...
    behaviorContinuationCacheContract().version;

payload.scenes = buildScenes();
payload.cases = buildCases(payload.scenes, payload.seeds);
payload.caseCount = numel(payload.cases);
payload.sourcePermitCount = payload.caseCount;
payload.caseSetCanonicalSha256 = ...
    computeCanonicalValueSha256(payload.cases);
payload.evidenceBoundary = [ ...
    'This protocol core registers one fixed-reference, source-only ', ...
    'filter trajectory for each of fifteen M24 development cases. ', ...
    'It does not authorize candidate continuation, tracking scoring, ', ...
    'arm selection, held-out claims, X36 outcomes, or validation claims.'];

actualSha256 = computeCanonicalValueSha256(payload);
expectedSha256 = ...
    '6ebadb7b583b9a70156185af8e50ca6edce56b09fe8ef169f7c67cb36214ac5b';
if ~strcmp(actualSha256, expectedSha256)
    error('FormationBundleSourcePermit:ProtocolDrift', [ ...
        'The M24 development protocol core changed: actual=%s ', ...
        'expected=%s.'], actualSha256, expectedSha256);
end
protocol = payload;
protocol.canonicalSha256 = actualSha256;
end

function scenes = buildScenes()
presetNames = { ...
    'm24-formation-fov', ...
    'm24-formation-fov-convoy', ...
    'm24-formation-fov-relay'};
sceneIds = {'radial', 'convoy', 'relay'};
expectedConfigSha256 = { ...
    '2c25ad410e645ebbe6ef3b52211a5a52ac99d3438fd9e03653db6f17e152b512', ...
    'ee6244a8baf0fe3b7a7ac34715a10f71c61428a2da942939d834eef2b16685b2', ...
    '902fd9a6b90d1d5eba64512ff4b815dc9a08cba40be1a7f2b3821950eba306de'};
expectedSceneSha256 = { ...
    expectedConfigSha256{1}, ...
    '666def7dbed41c47b9f29e536a369ef24a52077059429e45e5a41852e4071726', ...
    '49005834d31fcc6c729d546e725e79be7ae1c5b542209ea599a944187a31f2a0'};
sceneContractKinds = { ...
    'full-config-snapshot-v1', ...
    'formation-fov-multistyle-scene-contract-v5', ...
    'formation-fov-multistyle-scene-contract-v5'};
scenes = repmat(struct(), 1, numel(presetNames));
for sceneIdx = 1:numel(presetNames)
    config = buildDynamicTopologyScenarioConfig( ...
        presetNames{sceneIdx});
    configSha256 = computeCanonicalValueSha256(config);
    if ~strcmp(configSha256, expectedConfigSha256{sceneIdx}) || ...
            ~isequal(config.numberOfSensors, 24) || ...
            ~isequal(config.formationCount, 4)
        error('FormationBundleSourcePermit:SceneConfigDrift', ...
            'Registered M24 config drifted: %s.', ...
            presetNames{sceneIdx});
    end
    if sceneIdx > 1 && ...
            (~isfield(config, 'sceneContractSha256') || ...
             ~strcmp(config.sceneContractSha256, ...
                expectedSceneSha256{sceneIdx}) || ...
             ~strcmp(computeFormationFovMultistyleSceneContractSha256( ...
                config), expectedSceneSha256{sceneIdx}) || ...
             ~strcmp(getExpectedFormationFovMultistyleSceneContractSha256( ...
                config), expectedSceneSha256{sceneIdx}) || ...
             ~isequal(config.trackingOutcomeAuthorized, false))
        error('FormationBundleSourcePermit:SceneContractDrift', ...
            'Registered v5 scene contract drifted: %s.', ...
            presetNames{sceneIdx});
    end
    [~, triggerFingerprint] = ...
        buildFormationBackboneBundleM24SourceTriggerConfig( ...
            presetNames{sceneIdx});
    scene = struct();
    scene.ordinal = sceneIdx;
    scene.id = sceneIds{sceneIdx};
    scene.presetName = presetNames{sceneIdx};
    scene.numberOfSensors = config.numberOfSensors;
    scene.formationCount = config.formationCount;
    scene.focusWindow = reshape(config.focusWindow, 1, []);
    scene.sourceWindow = [1, config.focusWindow(2)];
    scene.continuationSnapshotTime = config.focusWindow(1);
    scene.configSnapshotSha256 = configSha256;
    scene.sceneContractKind = sceneContractKinds{sceneIdx};
    scene.sceneContractSha256 = expectedSceneSha256{sceneIdx};
    scene.sourceTriggerFingerprintSha256 = ...
        triggerFingerprint.canonicalSha256;
    scenes(sceneIdx) = scene;
end
end

function cases = buildCases(scenes, seeds)
cases = repmat(struct(), 1, numel(scenes) * numel(seeds));
caseOrdinal = 0;
for sceneIdx = 1:numel(scenes)
    for seedIdx = 1:numel(seeds)
        caseOrdinal = caseOrdinal + 1;
        casePayload = struct();
        casePayload.ordinal = caseOrdinal;
        casePayload.id = sprintf('%s__seed%d__w%d-%d', ...
            scenes(sceneIdx).presetName, seeds(seedIdx), ...
            scenes(sceneIdx).focusWindow(1), ...
            scenes(sceneIdx).focusWindow(2));
        casePayload.sceneOrdinal = scenes(sceneIdx).ordinal;
        casePayload.sceneId = scenes(sceneIdx).id;
        casePayload.presetName = scenes(sceneIdx).presetName;
        casePayload.seed = seeds(seedIdx);
        casePayload.focusWindow = scenes(sceneIdx).focusWindow;
        casePayload.sourceWindow = scenes(sceneIdx).sourceWindow;
        casePayload.continuationSnapshotTime = ...
            scenes(sceneIdx).continuationSnapshotTime;
        casePayload.configSnapshotSha256 = ...
            scenes(sceneIdx).configSnapshotSha256;
        casePayload.sceneContractKind = ...
            scenes(sceneIdx).sceneContractKind;
        casePayload.sceneContractSha256 = ...
            scenes(sceneIdx).sceneContractSha256;
        casePayload.sourceTriggerFingerprintSha256 = ...
            scenes(sceneIdx).sourceTriggerFingerprintSha256;
        casePayload.sourceInputFingerprint = ...
            emptySourceInputFingerprint();
        casePayload.caseCanonicalSha256 = ...
            computeCanonicalValueSha256(casePayload);
        cases(caseOrdinal) = casePayload;
    end
end
end

