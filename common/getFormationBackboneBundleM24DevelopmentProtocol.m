function scenes = buildScenes()
presetNames = { ...
    'm24-formation-fov', ...
    'm24-formation-fov-convoy', ...
    'm24-formation-fov-relay'};
sceneIds = {'radial', 'convoy', 'relay'};
expectedConfigSha256 = { ...
    '2c25ad410e645ebbe6ef3b52211a5a52ac99d3438fd9e03653db6f17e152b512', ...
    'ee6244a8baf0fe3b7a7ac34715a10f71c61428a2da942939d834eef2b16685b2', ...
    '902fd9a6b90d1d5eba64512ff4b815dc9a08cba40be1a7f2b3821950eba306de'};
expectedSceneSha256 = { ...
    expectedConfigSha256{1}, ...
    '666def7dbed41c47b9f29e536a369ef24a52077059429e45e5a41852e4071726', ...
    '49005834d31fcc6c729d546e725e79be7ae1c5b542209ea599a944187a31f2a0'};
sceneContractKinds = { ...
    'full-config-snapshot-v1', ...
    'formation-fov-multistyle-scene-contract-v5', ...
    'formation-fov-multistyle-scene-contract-v5'};
scenes = repmat(struct(), 1, numel(presetNames));
for sceneIdx = 1:numel(presetNames)
    config = buildDynamicTopologyScenarioConfig( ...
        presetNames{sceneIdx});
    configSha256 = computeCanonicalValueSha256(config);
    if ~strcmp(configSha256, expectedConfigSha256{sceneIdx}) || ...
            ~isequal(config.numberOfSensors, 24) || ...
            ~isequal(config.formationCount, 4)
        error('FormationBundleSourcePermit:SceneConfigDrift', ...
            'Registered M24 config drifted: %s.', ...
            presetNames{sceneIdx});
    end
    if sceneIdx > 1 && ...
            (~isfield(config, 'sceneContractSha256') || ...
             ~strcmp(config.sceneContractSha256, ...
                expectedSceneSha256{sceneIdx}) || ...
             ~strcmp(computeFormationFovMultistyleSceneContractSha256( ...
                config), expectedSceneSha256{sceneIdx}) || ...
             ~strcmp(getExpectedFormationFovMultistyleSceneContractSha256( ...
                config), expectedSceneSha256{sceneIdx}) || ...
             ~isequal(config.trackingOutcomeAuthorized, false))
        error('FormationBundleSourcePermit:SceneContractDrift', ...
            'Registered v5 scene contract drifted: %s.', ...
            presetNames{sceneIdx});
    end
    [~, triggerFingerprint] = ...
        buildFormationBackboneBundleM24SourceTriggerConfig( ...
            presetNames{sceneIdx});
    scene = struct();
    scene.ordinal = sceneIdx;
    scene.id = sceneIds{sceneIdx};
    scene.presetName = presetNames{sceneIdx};
    scene.numberOfSensors = config.numberOfSensors;
    scene.formationCount = config.formationCount;
    scene.focusWindow = reshape(config.focusWindow, 1, []);
    scene.sourceWindow = [1, config.focusWindow(2)];
    scene.continuationSnapshotTime = config.focusWindow(1);
    scene.configSnapshotSha256 = configSha256;
    scene.sceneContractKind = sceneContractKinds{sceneIdx};
    scene.sceneContractSha256 = expectedSceneSha256{sceneIdx};
    scene.sourceTriggerFingerprintSha256 = ...
        triggerFingerprint.canonicalSha256;
    scenes(sceneIdx) = scene;
end
end

function cases = buildCases(scenes, seeds)
inputRegistry = registeredSourceInputFingerprintRegistry();
registryUsed = false(1, numel(inputRegistry));
cases = repmat(struct(), 1, numel(scenes) * numel(seeds));
caseOrdinal = 0;
for sceneIdx = 1:numel(scenes)
    for seedIdx = 1:numel(seeds)
        caseOrdinal = caseOrdinal + 1;
        casePayload = struct();
        casePayload.ordinal = caseOrdinal;
        casePayload.id = sprintf('%s__seed%d__w%d-%d', ...
            scenes(sceneIdx).presetName, seeds(seedIdx), ...
            scenes(sceneIdx).focusWindow(1), ...
            scenes(sceneIdx).focusWindow(2));
        casePayload.sceneOrdinal = scenes(sceneIdx).ordinal;
        casePayload.sceneId = scenes(sceneIdx).id;
        casePayload.presetName = scenes(sceneIdx).presetName;
        casePayload.seed = seeds(seedIdx);
        casePayload.focusWindow = scenes(sceneIdx).focusWindow;
        casePayload.sourceWindow = scenes(sceneIdx).sourceWindow;
        casePayload.continuationSnapshotTime = ...
            scenes(sceneIdx).continuationSnapshotTime;
        casePayload.configSnapshotSha256 = ...
            scenes(sceneIdx).configSnapshotSha256;
        casePayload.sceneContractKind = ...
            scenes(sceneIdx).sceneContractKind;
        casePayload.sceneContractSha256 = ...
            scenes(sceneIdx).sceneContractSha256;
        casePayload.sourceTriggerFingerprintSha256 = ...
            scenes(sceneIdx).sourceTriggerFingerprintSha256;
        matchingFingerprint = strcmp( ...
            {inputRegistry.caseId}, casePayload.id);
        if nnz(matchingFingerprint) ~= 1
            error('FormationBundleSourcePermit:MissingInputFingerprint', ...
                'No unique input fingerprint exists for case %s.', ...
                casePayload.id);
        end
        registryUsed(matchingFingerprint) = true;
        casePayload.sourceInputFingerprint = ...
            inputRegistry(matchingFingerprint).fingerprint;
        casePayload.caseCanonicalSha256 = ...
            computeCanonicalValueSha256(casePayload);
        cases(caseOrdinal) = casePayload;
    end
end
if ~all(registryUsed)
    error('FormationBundleSourcePermit:UnusedInputFingerprint', ...
        'The frozen input registry contains an unused case.');
end
end

