fingerprint = struct();
fingerprint.contractVersion = ...
    'formation-backbone-bundle-m24-source-input-fingerprint-v1';
fingerprint.modelCanonicalSha256 = '';
fingerprint.measurementsCanonicalSha256 = '';
fingerprint.sensorTrajectoriesCanonicalSha256 = '';
fingerprint.neighborMapCanonicalSha256 = '';
fingerprint.commConfigCanonicalSha256 = '';
fingerprint.canonicalSha256 = '';
end
