    '6d4017abf6c8d3baf86596fa0ee21520cf6a2aee60357e0127e11d54bfe3b702';
payload.sourceInputFingerprintsFrozen = true;
payload.sourceArm = struct( ...
    'id', 'formation-backbone-residual-tour-reference-v38-v1', ...
    'ordinal', 1, ...
    'role', 'fixed-reference-source', ...
    'topologyPolicyFunction', ...
        'selectFormationBackboneReferenceRuntimePolicy', ...
    'policyContractVersion', ...
        'formation-backbone-reference-runtime-policy-v1', ...
    'routeId', ...
        ['fixed-index-plus-registered-formation-', ...
         'backbone-residual-tour-v1'], ...
    'posteriorAdaptive', false, ...
    'currentPhysicalActionSetRequired', true, ...
    'currentLinkReliabilityAdaptive', false);
