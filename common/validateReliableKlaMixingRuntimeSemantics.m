function semantics = ...
    validateReliableKlaMixingRuntimeSemantics(triggerConfig)
% VALIDATERELIABLEKLAMIXINGRUNTIMESEMANTICS Bind linear row semantics.
%
% The structural certificates model current heavy messages only, with no
% stale substitution, mode-dependent reweighting or post-normalization
% weight caps.  Label-specific fusion still requires common label support
% and is outside this runtime-weight validation.

if ~isstruct(triggerConfig) || ~isscalar(triggerConfig)
    error('ReliableKlaRuntime:UnsupportedSemantics', ...
        'The fusion runtime configuration is malformed.');
end
snapshot = struct();
snapshot.eventPolicy = lower(char(getField( ...
    triggerConfig, 'eventPolicy', '')));
snapshot.linkGateEnabled = logical(getField( ...
    triggerConfig, 'linkGateEnabled', true));
snapshot.useStaleNeighborCache = logical(getField( ...
    triggerConfig, 'useStaleNeighborCache', false));
snapshot.mixedPayloadEnabled = logical(getField( ...
    triggerConfig, 'mixedPayloadEnabled', false));
snapshot.modeAwareFusionWeights = logical(getField( ...
    triggerConfig, 'modeAwareFusionWeights', false));
snapshot.nonStaticFusionWeightFactor = getField( ...
    triggerConfig, 'nonStaticFusionWeightFactor', 1);
snapshot.maxSelfFusionWeight = getField( ...
    triggerConfig, 'maxSelfFusionWeight', inf);
snapshot.maxNonStaticFusionWeight = getField( ...
    triggerConfig, 'maxNonStaticFusionWeight', inf);
snapshot.missingNeighborWeightMode = lower(char(getField( ...
    triggerConfig, 'missingNeighborWeightMode', 'renormalize')));

logicalFields = { ...
    'linkGateEnabled', 'useStaleNeighborCache', ...
    'mixedPayloadEnabled', 'modeAwareFusionWeights'};
for fieldIdx = 1:numel(logicalFields)
    value = snapshot.(logicalFields{fieldIdx});
    if ~isscalar(value)
        error('ReliableKlaRuntime:UnsupportedSemantics', ...
            'A fusion runtime flag is not scalar.');
    end
end
if ~strcmp(snapshot.eventPolicy, 'alwaysheavy') || ...
        snapshot.linkGateEnabled || ...
        snapshot.useStaleNeighborCache || ...
        snapshot.mixedPayloadEnabled || ...
        snapshot.modeAwareFusionWeights || ...
        ~isscalar(snapshot.nonStaticFusionWeightFactor) || ...
        ~isfinite(snapshot.nonStaticFusionWeightFactor) || ...
        abs(snapshot.nonStaticFusionWeightFactor - 1) > 1e-12 || ...
        ~isUncapped(snapshot.maxSelfFusionWeight) || ...
        ~isUncapped(snapshot.maxNonStaticFusionWeight) || ...
        ~ismember(snapshot.missingNeighborWeightMode, ...
            {'renormalize', 'self'})
    error('ReliableKlaRuntime:UnsupportedSemantics', [ ...
        'The runtime applies communication or fusion-weight semantics ', ...
        'that are absent from the structural certificate.']);
end

semantics = snapshot;
semantics.contractVersion = ...
    'reliable-kla-linear-mixing-runtime-semantics-v1';
semantics.passed = true;
semantics.everySelectedEdgeAttemptsHeavyPayload = true;
semantics.missingDeliveryRedistributionModeled = true;
semantics.labelSpecificSupportRenormalizationModeled = false;
semantics.canonicalSha256 = computeCanonicalValueSha256(snapshot);
end

function value = isUncapped(input)
value = isscalar(input) && isnumeric(input) && isreal(input) && ...
     isinf(input) && input > 0;
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end
