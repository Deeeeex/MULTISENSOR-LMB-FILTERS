    'sameTruth', true, ...
    'sameMeasurements', true, ...
    'sameLinkUniforms', true, ...
    'sameFilterRandomness', true, ...
    'samePhysicalReachability', true, ...
    'sameNominalKlaWeights', true, ...
    'chargeControlSynopsis', true);

payload.radialGate = commonGate(0.05, 0.05, 0.05, -0.01);
payload.transferGate = commonGate(0.05, 0.05, 0.02, -0.02);
payload.radialGate.requireEachScaleIndependently = true;
