payload.transferGate.crossScaleCompensationAllowed = false;
payload.transferGate.crossStyleCompensationAllowed = false;
payload.transferGate.minimumPassingStyleFraction = 1.0;

payload.factorialAttribution = struct( ...
    'stage', 'radial-validation-after-primary-gate', ...
    'arms', {{ ...
        'static-full-fixed-kla', ...
        'static-full-adaptive-kla', ...
        'binary-admission-fixed-kla', ...
        'binary-admission-adaptive-kla'}}, ...
    'usedForPolicySelection', false, ...
    'requiredForNoveltyAttribution', true);
