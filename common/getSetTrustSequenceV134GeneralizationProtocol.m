    'minimumPooledFullEpisodeGainFraction', minimumFullGain, ...
    'minimumPooledFocusGainFraction', minimumFocusGain, ...
    'minimumStyleMeanGainFraction', minimumStyleMeanGain, ...
    'minimumPositiveSeedFraction', 2 / 3, ...
    'minimumWorstSeedGainFraction', minimumWorstSeedGain, ...
    'minimumWorstSensorAggregateGainFraction', 0.0, ...
    'minimumWorstFormationAggregateGainFraction', 0.0, ...
    'minimumWindowConsensusGainFraction', 0.0, ...
    'minimumTerminalConsensusGainFraction', 0.0, ...
    'requirePositiveAttemptedByteSaving', true, ...
    'requireCompleteTrajectories', true, ...
    'requireAllRegisteredSeeds', true);
end
