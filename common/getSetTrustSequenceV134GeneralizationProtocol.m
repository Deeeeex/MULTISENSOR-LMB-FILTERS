expectedSha256 = ...
    '4d6a177fd5eae7ed58bab585367195fcc54923fb045b9b3ee0c5c2472ec979a7';
if ~strcmp(actualSha256, expectedSha256)
    error('V134GeneralizationProtocol:UnregisteredDrift', [ ...
        'The V134 generalization protocol changed without registry ', ...
        'update: actual=%s expected=%s.'], ...
        actualSha256, expectedSha256);
end
protocol = payload;
protocol.canonicalSha256 = actualSha256;
end

function entry = presetEntry(scaleName, presetName, styleName)
entry = struct( ...
    'scaleName', scaleName, ...
    'presetName', presetName, ...
    'styleName', styleName);
end

function gate = commonGate( ...
        minimumFullGain, minimumFocusGain, ...
        minimumStyleMeanGain, minimumWorstSeedGain)
