payload.contractVersion = ...
    'v134-policy-generalization-protocol-v1';
payload.methodProtocolId = method.id;
payload.requiredMethodJointGate = ...
    'JOINT_HEADROOM_GATE_V134.jointCrossScaleGatePassed';
payload.requiredGeometryProtocolSha256 = geometry.canonicalSha256;
payload.requiredGeometryGateDecision = ...
    'all-absolute-and-cross-scale-geometry-gates-pass';
payload.trackingOutcomePermit = struct( ...
    'required', true, ...
    'issueBeforeMethodJointGate', false, ...
    'issueBeforePolicyFreeze', false, ...
    'issueBeforeGeometryGate', false, ...
    'bindMethodSourceCommit', true, ...
    'bindPolicyCheckpointSha256', true, ...
    'bindFeatureNormalizerSha256', true, ...
    'bindProtocolSha256', true, ...
    'bindExactPresetSeedManifest', true, ...
    'authorizeTruthForScoringOnly', true, ...
    'authorizeTruthForPolicy', false, ...
    'authorizeValidationClaimBeforeAggregateGate', false);
payload.evaluationUnit = 'complete-trajectory-paired-seed';
payload.developmentSeeds = method.developmentSeeds;
payload.radialValidationSeeds = [2203, 2207, 2221];
payload.convoyTransferSeeds = [2309, 2341, 2351];
payload.relayTransferSeeds = [2401, 2411, 2417];
payload.crossingStressSeeds = [2503, 2521];
payload.requireExactSeedManifest = true;
payload.requireDisjointSeedSplits = true;
payload.validationSeedsMayEnterTraining = false;
payload.validationOutcomesMayChangePolicy = false;

payload.radialPresets = [ ...
    presetEntry('M24', 'm24-formation-fov', 'radial-surround'), ...
    presetEntry('X36', 'x36-formation-fov', 'radial-surround')];
payload.transferPresets = [ ...
    presetEntry('M24', 'm24-formation-fov-convoy', ...
        'parallel-convoy'), ...
    presetEntry('X36', 'x36-formation-fov-convoy', ...
        'parallel-convoy'), ...
    presetEntry('M24', 'm24-formation-fov-relay', ...
        'linear-relay'), ...
    presetEntry('X36', 'x36-formation-fov-relay', ...
        'linear-relay')];
payload.stressPresets = [ ...
    presetEntry('M24', 'm24-formation-fov-crossing', ...
        'orthogonal-crossing'), ...
    presetEntry('X36', 'x36-formation-fov-crossing', ...
        'orthogonal-crossing')];

payload.policyFreeze = struct( ...
    'oneSharedScaleNormalizedCheckpoint', true, ...
    'perScalePolicyCheckpointAllowed', false, ...
    'perPresetTuningAllowed', false, ...
    'perScaleThresholdTuningAllowed', false, ...
    'sceneIdentityInputAllowed', false, ...
    'sensorIndexInputAllowed', false, ...
    'formationIndexInputAllowed', false, ...
    'truthInputAllowed', false, ...
    'futureMeasurementInputAllowed', false, ...
    'futureDeliveryInputAllowed', false, ...
    'unseenOutcomeFeedbackAllowed', false, ...
    'freezeBeforeRadialValidation', true, ...
    'radialValidationPassRequiredBeforeTransfer', true);

payload.reference = struct( ...
    'name', 'frozen-full-posterior-static-carrier', ...
    'selectionArtifact', 'FROZEN_REFERENCE_CARRIER_V133.mat', ...
    'selectionRule', ...
        'stronger-radial-development-direction-per-scale', ...
    'perSceneDirectionOracleAllowed', false, ...
    'perSeedDirectionOracleAllowed', false, ...
    'fullMixtureAwareLmbPosterior', true, ...
    'nominalKlaWeightMode', 'metropolis', ...
    'stalePosteriorSubstitutionAllowed', false);
