    'mainDocumentRequiresRadialAndTransferGates', true, ...
    'singleScaleSuccessMainDocument', false, ...
    'singleStyleSuccessMainDocument', false, ...
    'stressResultCanSubstituteFormalGate', false, ...
    'reportWorstSeedAndLocalUnits', true);
