function config = buildLabelSelectiveRiskShortcutV265Config(scenario)
% BUILDLABELSELECTIVERISKSHORTCUTV265CONFIG V242 plus one label route.

protocol = getLabelSelectiveRiskShortcutV265Protocol();
if ~isstruct(scenario) || ~isscalar(scenario) || ...
        ~isfield(scenario, 'presetName') || ...
        ~ismember(scenario.presetName, protocol.allowedPresets) || ...
        ~isfield(scenario, 'numberOfSensors') || ...
        ~isfield(scenario, 'sensorGroupIds')
    error('LabelSelectiveRiskShortcutV265:InvalidConfigInput', ...
        'V265 requires its registered M24 formation-braid scene.');
end
config = buildCausalMinimumFormationBackboneV242Config(scenario);
config.topologyPolicyName = protocol.policyName;
config.topologyPolicyFcn = @selectLabelSelectiveRiskShortcutV265Policy;
config.topologyPolicyLabelInputRouteEnabled = true;
config.topologyPolicyLabelInputRouteSourceWeight = protocol.sourceWeight;
config.topologyPolicyLabelInputRouteSourceWeightGrid = ...
    protocol.sourceWeightGrid;
config.topologyPolicyLabelInputRouteEtaProjectionEnabled = true;
config.topologyPolicyLabelInputRouteMinimumMapExistence = ...
    protocol.minimumMapExistence;
config.topologyPolicyLabelInputRouteMaximumReferenceLogOddsDrop = ...
    protocol.maximumReferenceLogOddsDrop;
config.topologyPolicyLabelInputRouteMaximumSubMapReferenceLogOddsDrop = ...
    protocol.maximumSubMapReferenceLogOddsDrop;
config.topologyPolicyLabelInputRouteMaximumReferenceLogOddsIncrease = ...
    protocol.maximumReferenceLogOddsIncrease;
config.topologyPolicyLabelInputRouteEtaIdentityTolerance = ...
    protocol.etaIdentityTolerance;
end
