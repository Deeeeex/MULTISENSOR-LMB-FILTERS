function selection = selectPositiveNetAddressableRiskSetV97(metrics, options)
% SELECTPOSITIVENETADDRESSABLERISKSETV97 Keep every safe positive-net action.

if nargin < 2 || isempty(options)
    options = struct();
end
requireZeroDownwardCrossings = logical(getField( ...
    options, 'requireZeroCrossSupportedDownwardCrossings', true));
netBenefitTolerance = getField(options, 'netBenefitTolerance', 1e-12);
requiredFields = { ...
    'groups', 'networkRescueFractionByFormation', ...
    'networkUsefulLossFractionByFormation', ...
    'singleActionAvailableMask', ...
    'crossSupportedDownwardCrossingsByFormation'};
if ~isstruct(metrics) || ~all(isfield(metrics, requiredFields)) || ...
        ~isscalar(netBenefitTolerance) || ...
        ~isfinite(netBenefitTolerance) || netBenefitTolerance < 0
    error('PositiveNetAddressableV97:InvalidInput', ...
        'The positive-net addressable-risk inputs are invalid.');
end

groups = reshape(metrics.groups, 1, []);
rescue = reshape(metrics.networkRescueFractionByFormation, 1, []);
usefulLoss = reshape( ...
    metrics.networkUsefulLossFractionByFormation, 1, []);
downward = reshape( ...
    metrics.crossSupportedDownwardCrossingsByFormation, 1, []);
available = logical(reshape(metrics.singleActionAvailableMask, 1, []));
formationCount = numel(groups);
if formationCount < 1 || formationCount > 20 || ...
        numel(rescue) ~= formationCount || ...
        numel(usefulLoss) ~= formationCount || ...
        numel(downward) ~= formationCount || ...
        numel(available) ~= formationCount
    error('PositiveNetAddressableV97:FormationMismatch', ...
        'Formation-level positive-net inputs do not align.');
end

finiteMask = isfinite(rescue) & isfinite(usefulLoss) & ...
    isfinite(downward);
riskBasis = available & finiteMask;
addressableBasis = riskBasis;
if requireZeroDownwardCrossings
    addressableBasis = addressableBasis & downward == 0;
end
positiveRescue = max(rescue, 0);
positiveLoss = max(usefulLoss, 0);
netBenefit = positiveRescue - positiveLoss;
selectedMask = addressableBasis & ...
    positiveRescue > netBenefitTolerance & ...
    netBenefit > netBenefitTolerance;

selection = emptySelection();
selection.netBenefitTolerance = netBenefitTolerance;
selection.requireZeroCrossSupportedDownwardCrossings = ...
    requireZeroDownwardCrossings;
selection.totalNetworkRiskFraction = sum(positiveRescue(riskBasis));
selection.addressableNetworkRiskFraction = ...
    sum(positiveRescue(addressableBasis));
selection.unaddressableNetworkRiskFraction = max( ...
    selection.totalNetworkRiskFraction - ...
        selection.addressableNetworkRiskFraction, 0);
selection.riskBasisFormationIds = groups(riskBasis);
selection.addressableBasisFormationIds = groups(addressableBasis);
selection.nonpositiveNetFormationIds = groups( ...
    addressableBasis & ~selectedMask);
selection.selectedFormationMask = selectedMask;
selection.selectedFormationIds = groups(selectedMask);

if ~any(selectedMask)
    selection.fallbackReason = 'no-positive-net-addressable-risk';
    return;
end

selection.actionEnabled = true;
selection.selectedNetworkRescueFraction = ...
    sum(positiveRescue(selectedMask));
selection.selectedNetworkUsefulLossFraction = ...
    sum(positiveLoss(selectedMask));
selection.selectedNetworkNetBenefitFraction = ...
    sum(netBenefit(selectedMask));
selection.achievedAddressableCoverageFraction = ...
    selection.selectedNetworkRescueFraction / max( ...
        selection.addressableNetworkRiskFraction, eps);
selection.usefulLossToRescueRatio = ...
    selection.selectedNetworkUsefulLossFraction / max( ...
        selection.selectedNetworkRescueFraction, eps);
selection.fallbackReason = '';
end

function value = emptySelection()
value = struct( ...
    'contractVersion', ...
        'positive-net-addressable-risk-selector-v97-v1', ...
    'actionEnabled', false, ...
    'selectedFormationMask', false(1, 0), ...
    'selectedFormationIds', zeros(1, 0), ...
    'netBenefitTolerance', NaN, ...
    'requireZeroCrossSupportedDownwardCrossings', true, ...
    'totalNetworkRiskFraction', NaN, ...
    'addressableNetworkRiskFraction', NaN, ...
    'unaddressableNetworkRiskFraction', NaN, ...
    'selectedNetworkRescueFraction', 0, ...
    'selectedNetworkUsefulLossFraction', 0, ...
    'selectedNetworkNetBenefitFraction', 0, ...
    'achievedAddressableCoverageFraction', 0, ...
    'usefulLossToRescueRatio', NaN, ...
    'riskBasisFormationIds', zeros(1, 0), ...
    'addressableBasisFormationIds', zeros(1, 0), ...
    'nonpositiveNetFormationIds', zeros(1, 0), ...
    'fallbackReason', 'not-evaluated', ...
    'truthUsed', false, ...
    'futureMeasurementsUsed', false, ...
    'futureOutcomesUsed', false);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
