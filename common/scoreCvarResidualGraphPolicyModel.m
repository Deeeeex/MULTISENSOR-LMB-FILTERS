function scores = scoreCvarResidualGraphPolicyModel(model, block)
% SCORECVARRESIDUALGRAPHPOLICYMODEL Predict node risk and edge values.

if ~strcmp(model.kind, ...
        'cvar-residual-relational-three-head-m24-v1') || ...
        ~isequal(model.nodeFeatureNames, ...
            reshape(block.nodeFeatureNames, 1, [])) || ...
        ~isequal(model.edgeFeatureNames, ...
            reshape(block.edgeFeatureNames, 1, [])) || ...
        block.featuresUseTruth || ...
        block.featuresUseFutureOutcome
    error('CVaR graph model/feature contract mismatch.');
end
nodeCount = size(block.nodeFeatures, 1);
candidateCount = size(block.edgeFeatures, 1);
weightCount = size(block.edgeFeatures, 2);
edgeFeatureCount = size(block.edgeFeatures, 3);
flatEdgeX = reshape(block.edgeFeatures, ...
    candidateCount * weightCount, edgeFeatureCount);
receiverRows = repmat( ...
    reshape(block.receiverIndices, [], 1), ...
    weightCount, 1);
senderRows = repmat( ...
    reshape(block.senderIndices, [], 1), ...
    weightCount, 1);
if any(receiverRows < 1 | receiverRows > nodeCount) || ...
        any(senderRows < 1 | senderRows > nodeCount)
    error('CVaR graph endpoint indices are invalid.');
end

switch model.family
    case 'ridge'
        nodeRisk = scoreRidgeHead( ...
            model.nodeHead, block.nodeFeatures);
        receiverX = block.nodeFeatures(receiverRows, :);
        senderX = block.nodeFeatures(senderRows, :);
        relational = [flatEdgeX, receiverX, senderX, ...
            receiverX - senderX];
        task = scoreRidgeHead( ...
            model.edgeTaskHead, relational);
        safety = scoreRidgeHead( ...
            model.edgeSafetyHead, relational);
    case 'mlp'
        nodeZ = applyScaler(block.nodeFeatures, ...
            model.nodeFeatureMean, ...
            model.nodeFeatureScale);
        nodeHidden = tanh(bsxfun(@plus, ...
            nodeZ * model.nodeEncoder.weight, ...
            model.nodeEncoder.bias));
        nodeRiskStandardized = nodeHidden * ...
            model.nodeRiskHead.weight + ...
            model.nodeRiskHead.bias;
        nodeRisk = model.nodeTargetMean + ...
            model.nodeTargetScale * ...
            nodeRiskStandardized;
        edgeZ = applyScaler(flatEdgeX, ...
            model.edgeFeatureMean, ...
            model.edgeFeatureScale);
        receiverHidden = nodeHidden(receiverRows, :);
        senderHidden = nodeHidden(senderRows, :);
        relational = [edgeZ, receiverHidden, senderHidden, ...
            receiverHidden - senderHidden, ...
            receiverHidden .* senderHidden];
        relationalZ = applyScaler(relational, ...
            model.relationalFeatureMean, ...
            model.relationalFeatureScale);
        edgeHidden = tanh(bsxfun(@plus, ...
            relationalZ * model.edgeEncoder.weight, ...
            model.edgeEncoder.bias));
        standardized = bsxfun(@plus, ...
            edgeHidden * model.edgeHeads.weight, ...
            model.edgeHeads.bias);
        task = model.edgeTaskTargetMean + ...
            model.edgeTaskTargetScale * standardized(:, 1);
        safety = model.edgeSafetyTargetMean + ...
            model.edgeSafetyTargetScale * standardized(:, 2);
    otherwise
        error('Unknown CVaR graph model family.');
end
if any(~isfinite(nodeRisk(:))) || ...
        any(~isfinite(task(:))) || ...
        any(~isfinite(safety(:)))
    error('CVaR graph model produced non-finite scores.');
end
scores = struct();
scores.nodeRisk = reshape(nodeRisk, 1, []);
scores.edgeTaskAdvantage = ...
    reshape(task, candidateCount, weightCount);
scores.edgeProtectionAdvantage = ...
    reshape(safety, candidateCount, weightCount);
scores.featuresUseTruth = false;
scores.futureOutcomeUsed = false;
end

function prediction = scoreRidgeHead(head, X)
Z = applyScaler(X, head.featureMean, ...
    head.featureScale);
standardized = [ones(size(Z, 1), 1), Z] * ...
    head.coefficients;
prediction = head.targetMean + ...
    head.targetScale * standardized;
end

function Z = applyScaler(X, meanValue, scaleValue)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, meanValue), scaleValue);
end
