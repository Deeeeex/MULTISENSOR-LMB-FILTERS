function detected = isMaturedHandoffV103ExecutionContext(context)
% ISMATUREDHANDOFFV103EXECUTIONCONTEXT Identify V103.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'matured-handoff-v103-context-v1');
end
