function protocol = getIidClusterRewardActionAlignmentProtocol()
% GETIIDCLUSTERREWARDACTIONALIGNMENTPROTOCOL Frozen second score gate.

predecessor = getPredictiveRewardActionAlignmentProtocol();
if ~predecessor.poissonActionAlignmentRejected || ...
        ~predecessor. ...
            iidClusterRewardActionAlignmentAuditAuthorized
    error('IID-cluster action alignment is not authorized.');
end

protocol = predecessor;
removeFields = { ...
    'evidenceRoot', 'evidenceAnalysisPath', ...
    'evidenceAnalysisSha256', 'evidenceReportPath', ...
    'evidenceReportSha256', 'evidenceLogPath', ...
    'evidenceLogSha256', 'evidenceGenerationCommit', ...
    'observedTeacherPositiveScoreFraction', ...
    'observedGlobalScoreTaskSpearman', ...
    'observedPairwisePreferenceAccuracy', ...
    'observedPositivePerSeedSpearmanFraction', ...
    'poissonActionAlignmentRejected', ...
    'iidClusterRewardActionAlignmentAuditAuthorized'};
protocol = rmfield(protocol, removeFields);
protocol.id = ...
    'iid-cluster-reward-action-alignment-m24-training-states-v1';
protocol.predecessorProtocolId = predecessor.id;
protocol.predecessorEvidenceAnalysisPath = ...
    predecessor.evidenceAnalysisPath;
protocol.predecessorEvidenceAnalysisSha256 = ...
    predecessor.evidenceAnalysisSha256;
protocol.predecessorEvidenceReportPath = ...
    predecessor.evidenceReportPath;
protocol.predecessorEvidenceReportSha256 = ...
    predecessor.evidenceReportSha256;
protocol.predecessorGenerationCommit = ...
    predecessor.evidenceGenerationCommit;
protocol.predecessorTeacherPositiveScoreFraction = ...
    predecessor.observedTeacherPositiveScoreFraction;
protocol.predecessorGlobalScoreTaskSpearman = ...
    predecessor.observedGlobalScoreTaskSpearman;
protocol.predecessorPairwisePreferenceAccuracy = ...
    predecessor.observedPairwisePreferenceAccuracy;
protocol.analysisContractVersion = ...
    'iid-cluster-reward-action-alignment-m24-v1';
protocol.scoreMode = 'iid-cluster';
protocol.scoreType = ...
    'lmb-cardinality-matched-iid-cluster-measurement-log-score';
protocol.scoreExactMeasurementCardinality = true;
protocol.scoreIidClusterProjection = true;
protocol.scoreExactLmbMeasurementSetLikelihood = false;
protocol.gatesInheritedWithoutRelaxation = ...
    isequal([ ...
        protocol.minimumTeacherPositiveScoreFraction, ...
        protocol.minimumGlobalScoreTaskSpearman, ...
        protocol.minimumPairwisePreferenceAccuracy, ...
        protocol.minimumPositivePerSeedSpearmanFraction], ...
        [ ...
        predecessor.minimumTeacherPositiveScoreFraction, ...
        predecessor.minimumGlobalScoreTaskSpearman, ...
        predecessor.minimumPairwisePreferenceAccuracy, ...
        predecessor.minimumPositivePerSeedSpearmanFraction]);
protocol.evidenceBoundary = [ ...
    'The delayed score uses the exact LMB-induced measurement ', ...
    'cardinality law and normalized measurement intensity, with no ', ...
    'target truth. It is a log score for the IID-cluster projection, ', ...
    'not the exact label-to-measurement association likelihood. ', ...
    'Registered current-truth advantages are used only for alignment ', ...
    'audit on already-opened training states. A pass may authorize a ', ...
    'full observable reward dataset, but not bandit deployment, ', ...
    'development evaluation, held-out M24, or X36.'];
protocol.iidClusterActionAlignmentRejected = false;
protocol.fullActionRewardDatasetAuthorized = false;
protocol.banditImplementationAuthorized = false;
protocol.developmentEvaluationAuthorized = false;
protocol.heldoutM24Authorized = false;
protocol.x36PolicyRunAuthorized = false;
protocol.defaultOutputPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'iid_cluster_reward_action_alignment_m24_training_states.mat');
protocol.defaultReportPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'IID_CLUSTER_REWARD_ACTION_ALIGNMENT_M24_TRAINING_STATES.md');
end
