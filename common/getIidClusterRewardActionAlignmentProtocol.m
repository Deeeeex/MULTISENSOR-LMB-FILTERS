    protocol.evidenceRoot, ...
    'iid_cluster_reward_action_alignment_m24_training_states.log');
protocol.evidenceLogSha256 = ...
    '1dbabda79b72641f50d1e4400ff117e766dff5e175d3a0cacb17fa57e3ff3f10';
protocol.evidenceGenerationCommit = ...
    '9872c25a7d0243a40c67f5a360a2061ce706c046';
protocol.observedTeacherPositiveScoreFraction = ...
    0.53472222222222221;
protocol.observedGlobalScoreTaskSpearman = ...
    0.43835575837221552;
protocol.observedPairwisePreferenceAccuracy = ...
    0.61111111111111116;
protocol.observedPositivePerSeedSpearmanFraction = 1;
protocol.compositeAuditPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'IID_CLUSTER_PROPER_SCORE_COMPOSITE_REJECTION_M24.md');
protocol.compositeAuditSha256 = ...
    '17513fb67a02af5d346f4705530c79b4101a177d26fbfe2a6d5d01ac5534b9fb';
