function matched = ...
    isFormationB4V51PairedTrackingDevelopmentContext(context)
% ISFORMATIONB4V51PAIREDTRACKINGDEVELOPMENTCONTEXT Identify V51 context.

matched = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'formation-b4-v51-paired-tracking-development-context-v1');
end
