function protocol = getBoundedDominantEdgeTransferV226Protocol()
% GETBOUNDEDDOMINANTEDGETRANSFERV226PROTOCOL Two-sided safe rewiring.

base = getEtaSafeDominantEdgeReplacementV225Protocol();
protocol = base;
protocol.id = 'bounded-dominant-edge-transfer-v226-v1';
protocol.contractVersion = ...
    'bounded-dominant-edge-transfer-v226-protocol-v1';
protocol.baseProtocolId = base.id;
protocol.inputRouteWeightMode = ...
    'bounded-dominant-nonself-transfer';
protocol.semanticFusionMode = ...
    'single-ordinary-label-wise-kla-with-bounded-nonself-edge-transfer';
protocol.maximumReferenceLogOddsIncrease = 0.25;
protocol.transferFractionGrid = ...
    [1, 0.75, 0.50, 0.40, 0.30, 0.25, ...
     0.20, 0.15, 0.10, 0.075, 0.05, 0.025];
protocol.transferFractionSelection = ...
    'largest-two-sided-envelope-safe-fraction-after-evaluating-full-grid';
protocol.transferFractionReducesPayloadCharge = false;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v226');
protocol.evidenceBoundary = [ ...
    'V226 is a frozen development mechanism screen for receiver-specific ', ...
    'partial label-graph rewiring. Each receiver preserves self evidence ', ...
    'and total label-wise KLA weight, evaluates every registered transfer ', ...
    'fraction, and selects the largest fraction whose fused label remains ', ...
    'inside the two-sided ordinary-reference log-odds envelope. If no ', ...
    'fraction passes, the receiver uses ordinary fusion. The complete ', ...
    'Bernoulli Gaussian-mixture payload is charged before projection, so ', ...
    'a smaller transfer fraction never creates artificial communication ', ...
    'savings. The source and label remain offline teacher choices; this ', ...
    'screen cannot support deployment or generalization claims.'];

if ~strcmp(protocol.inputRouteWeightMode, ...
        'bounded-dominant-nonself-transfer') || ...
        protocol.maximumReferenceLogOddsIncrease < 0 || ...
        isempty(protocol.transferFractionGrid) || ...
        any(~isfinite(protocol.transferFractionGrid)) || ...
        any(protocol.transferFractionGrid <= 0) || ...
        any(protocol.transferFractionGrid > 1) || ...
        numel(unique(protocol.transferFractionGrid)) ~= ...
            numel(protocol.transferFractionGrid) || ...
        protocol.selfInputReplacementAllowed || ...
        ~protocol.totalLabelWeightPreserved || ...
        ~protocol.etaProjectionEnabled || ...
        protocol.transferFractionReducesPayloadCharge || ...
        protocol.postFusionResidualUpdateAllowed || ...
        protocol.onlinePolicyImplemented || ...
        protocol.validationClaimAllowed
    error('BoundedDominantEdgeTransferV226:ProtocolDrift', ...
        'The frozen V226 protocol is inconsistent.');
end
end
