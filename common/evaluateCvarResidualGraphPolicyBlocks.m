function rows = evaluateCvarResidualGraphPolicyBlocks( ...
        model, calibration, graphBlocks, ...
        behaviorBlocks, protocol)
% EVALUATECVARRESIDUALGRAPHPOLICYBLOCKS Evaluate frozen block decisions.

if nargin < 5 || isempty(protocol)
    protocol = getCvarResidualGraphPolicyDatasetProtocol();
end
if numel(graphBlocks) ~= numel(behaviorBlocks) || ...
        isempty(graphBlocks) || ...
        ~isfield(calibration, 'margin') || ...
        ~isfinite(calibration.margin) || ...
        calibration.margin < 0
    error('CVaR graph evaluation inputs are invalid.');
end
rows = repmat(emptyRow(), 1, numel(graphBlocks));
for blockIdx = 1:numel(graphBlocks)
    block = graphBlocks(blockIdx);
    behaviorBlock = behaviorBlocks(blockIdx);
    scores = scoreCvarResidualGraphPolicyModel( ...
        model, block);
    projection = projectCvarResidualGraphPolicyScores( ...
        scores, block, behaviorBlock, ...
        calibration.margin, protocol);
    trueTail = logical(reshape( ...
        block.nodeCvarMaskTarget, 1, []));
    predictedTail = projection.predictedTailMask;
    intersectionCount = nnz(trueTail & predictedTail);
    unionCount = nnz(trueTail | predictedTail);
    observed = logical( ...
        block.edgeProtectionObservedMask);
    predictedSafe = scores.edgeProtectionAdvantage - ...
        calibration.margin >= 0;
    trueSafe = logical(block.edgeReferenceSafeTarget);
    predictedObservedSafe = predictedSafe & observed;
    falseSafeCount = nnz( ...
        predictedObservedSafe & ~trueSafe);
    predictedObservedSafeCount = ...
        nnz(predictedObservedSafe);
    trueSafeCount = nnz(observed & trueSafe);
    trueSafeSelectedCount = nnz( ...
        predictedObservedSafe & trueSafe);

    selectedMask = ...
        projection.selectedEdgeWeightMask;
    selectedRows = find(any(selectedMask, 2));
    selectedTailRows = selectedRows( ...
        trueTail(block.receiverIndices(selectedRows)));
    selectedTailSafe = true;
    for rowIdx = reshape(selectedTailRows, 1, [])
        weightIdx = find(selectedMask(rowIdx, :), 1);
        selectedTailSafe = selectedTailSafe && ...
            observed(rowIdx, weightIdx) && ...
            trueSafe(rowIdx, weightIdx);
    end
    selectedTrueTask = sum( ...
        block.edgeTaskAdvantageTarget(selectedMask));
    [maximumTrueTask, minimumTrueTask] = ...
        trueSafeTaskExtrema(block, behaviorBlock, protocol);
    denominator = maximumTrueTask - minimumTrueTask;
    if denominator <= eps
        normalizedRegret = double( ...
            selectedTrueTask + 1e-12 < maximumTrueTask);
    else
        normalizedRegret = ...
            (maximumTrueTask - selectedTrueTask) / ...
            denominator;
    end

    row = emptyRow();
    row.seed = block.seed;
    row.currentTime = block.currentTime;
    row.family = model.family;
    row.calibrationSeed = calibration.seed;
    row.safetyMargin = calibration.margin;
    row.nodeTailRecall = intersectionCount / ...
        max(nnz(trueTail), 1);
    row.nodeTailJaccard = intersectionCount / ...
        max(unionCount, 1);
    row.nodeTailExact = isequal(trueTail, predictedTail);
    row.edgeTaskSpearman = rankCorrelation( ...
        scores.edgeTaskAdvantage(:), ...
        block.edgeTaskAdvantageTarget(:));
    row.observedTailFalseSafeCount = falseSafeCount;
    row.observedTailPredictedSafeCount = ...
        predictedObservedSafeCount;
    row.observedTailTrueSafeCount = trueSafeCount;
    row.observedTailTrueSafeSelectedCount = ...
        trueSafeSelectedCount;
    row.selectedTailSafe = selectedTailSafe;
    row.projectionFeasible = ~projection.fallbackUsed;
    row.staticFallbackUsed = projection.fallbackUsed;
    row.topologyInfeasible = ...
        projection.topologyInfeasible;
    row.repairTriggered = ...
        projection.repairTriggered;
    row.payloadEmergencyUsed = ...
        projection.payloadEmergencyUsed;
    row.selectedCrossEdgeCount = ...
        projection.crossFormationEdgeCount;
    row.expectedCrossEdgeCountPassed = ...
        projection.fallbackUsed || ...
        projection.crossFormationEdgeCount == ...
            protocol.expectedCrossCycleEdgeCount;
    row.messageCountPassed = ...
        projection.messageCountPassed;
    row.dominantBackbonePreserved = ...
        projection.dominantBackbonePreserved;
    row.weightGridPassed = ...
        projection.weightGridPassed;
    row.selectedTrueTaskAdvantage = ...
        selectedTrueTask;
    row.maximumTrueTaskAdvantage = ...
        maximumTrueTask;
    row.minimumTrueTaskAdvantage = ...
        minimumTrueTask;
    row.normalizedRegret = normalizedRegret;
    row.nonnegativeSelectedTask = ...
        selectedTrueTask >= -1e-12;
    rows(blockIdx) = row;
end
end

function [maximumValue, minimumValue] = ...
        trueSafeTaskExtrema(block, behaviorBlock, protocol)
safeScores = 2 * double( ...
    block.edgeReferenceSafeTarget) - 1;
oracleScores = struct();
oracleScores.nodeRisk = ...
    reshape(block.nodeRiskTarget, 1, []);
oracleScores.edgeProtectionAdvantage = safeScores;
oracleScores.featuresUseTruth = true;
oracleScores.futureOutcomeUsed = false;
oracleScores.edgeTaskAdvantage = ...
    block.edgeTaskAdvantageTarget;
maximumProjection = ...
    projectCvarResidualGraphPolicyScores( ...
        oracleScores, block, behaviorBlock, 0, protocol);
oracleScores.edgeTaskAdvantage = ...
    -block.edgeTaskAdvantageTarget;
minimumProjection = ...
    projectCvarResidualGraphPolicyScores( ...
        oracleScores, block, behaviorBlock, 0, protocol);
if maximumProjection.fallbackUsed || ...
        minimumProjection.fallbackUsed
    error('CVaR graph true-safe regret oracle is infeasible.');
end
maximumValue = sum(block.edgeTaskAdvantageTarget( ...
    maximumProjection.selectedEdgeWeightMask));
minimumValue = sum(block.edgeTaskAdvantageTarget( ...
    minimumProjection.selectedEdgeWeightMask));
if maximumValue + 1e-10 < minimumValue
    error('CVaR graph regret extrema are inconsistent.');
end
end

function correlation = rankCorrelation(first, second)
firstRanks = tiedRanks(first);
secondRanks = tiedRanks(second);
firstCentered = firstRanks - mean(firstRanks);
secondCentered = secondRanks - mean(secondRanks);
denominator = sqrt(sum(firstCentered.^2) * ...
    sum(secondCentered.^2));
if denominator <= eps
    correlation = 0;
else
    correlation = sum(firstCentered .* ...
        secondCentered) / denominator;
end
end

function ranks = tiedRanks(values)
values = reshape(values, [], 1);
[sorted, order] = sort(values);
ranks = zeros(size(values));
cursor = 1;
while cursor <= numel(values)
    last = cursor;
    while last < numel(values) && ...
            sorted(last + 1) == sorted(cursor)
        last = last + 1;
    end
    ranks(order(cursor:last)) = ...
        0.5 * (cursor + last);
    cursor = last + 1;
end
end

function row = emptyRow()
row = struct( ...
    'seed', 0, 'currentTime', 0, ...
    'family', '', 'calibrationSeed', 0, ...
    'safetyMargin', NaN, ...
    'nodeTailRecall', NaN, ...
    'nodeTailJaccard', NaN, ...
    'nodeTailExact', false, ...
    'edgeTaskSpearman', NaN, ...
    'observedTailFalseSafeCount', 0, ...
    'observedTailPredictedSafeCount', 0, ...
    'observedTailTrueSafeCount', 0, ...
    'observedTailTrueSafeSelectedCount', 0, ...
    'selectedTailSafe', false, ...
    'projectionFeasible', false, ...
    'staticFallbackUsed', false, ...
    'topologyInfeasible', false, ...
    'repairTriggered', false, ...
    'payloadEmergencyUsed', false, ...
    'selectedCrossEdgeCount', 0, ...
    'expectedCrossEdgeCountPassed', false, ...
    'messageCountPassed', false, ...
    'dominantBackbonePreserved', false, ...
    'weightGridPassed', false, ...
    'selectedTrueTaskAdvantage', NaN, ...
    'maximumTrueTaskAdvantage', NaN, ...
    'minimumTrueTaskAdvantage', NaN, ...
    'normalizedRegret', NaN, ...
    'nonnegativeSelectedTask', false);
end
