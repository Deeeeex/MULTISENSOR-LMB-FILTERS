function detected = isAttenuatedLightPayloadV129ExecutionContext(context)
% ISATTENUATEDLIGHTPAYLOADV129EXECUTIONCONTEXT Identify V129.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'attenuated-light-payload-v129-context-v1');
end
