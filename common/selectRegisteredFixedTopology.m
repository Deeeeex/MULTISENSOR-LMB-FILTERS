function [adjacency, details] = ...
    selectRegisteredFixedTopology(context, candidateIndex)
% SELECTREGISTEREDFIXEDTOPOLOGY Freeze one registered candidate graph.

candidates = context.model.dynamicTopologyScenario.candidateAdjacency;
candidateIndex = round(candidateIndex);
if candidateIndex < 1 || candidateIndex > size(candidates, 3)
    error('Registered fixed candidate index is out of range.');
end
adjacency = logical(candidates(:, :, candidateIndex));
details = struct( ...
    'objective', NaN, ...
    'candidateIndex', candidateIndex, ...
    'mode', 'registered-fixed', ...
    'validCandidateCount', 1, ...
    'selectionSeconds', 0);
end
