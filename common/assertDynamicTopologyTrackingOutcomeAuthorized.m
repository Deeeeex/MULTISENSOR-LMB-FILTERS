function rejectTrackingOutcome(config)
presetName = '<unknown>';
if isstruct(config) && isscalar(config) && ...
        isfield(config, 'presetName') && ischar(config.presetName)
    presetName = config.presetName;
end
error('DynamicTopology:TrackingOutcomeNotAuthorized', [ ...
    'Scenario %s is calibration-only or has incomplete outcome-gate ', ...
    'metadata and may not enter the tracking filter. Freeze a new named ', ...
    'scene contract with explicit tracking outcome authorization first.'], ...
    presetName);
end

function authorization = validateFormationB4V49DevelopmentExecution( ...
        model, context, request)
expectedFields = { ...
    'contractVersion', 'capability', 'action', 'presetName', ...
    'seed', 'armId', 'developmentEvidenceOnly'};
if ~isequal(sort(fieldnames(context)), sort(expectedFields(:))) || ...
        ~strcmp(context.capability, 'paired-tracking-development') || ...
        ~strcmp(context.action, 'filter-paired-tracking-development') || ...
        ~isequal(context.developmentEvidenceOnly, true)
    error('FormationB4V49Tracking:InvalidContext', ...
        'The V49 paired-tracking development context is malformed.');
end

protocol = getFormationB4V49RuntimeProtocol();
if ~any(strcmp(context.armId, protocol.primaryArms)) || ...
        ~isstruct(model) || ~isscalar(model) || ...
        ~isfield(model, 'numberOfSensors') || ...
        ~any(model.numberOfSensors == [24, 36]) || ...
        ~isfield(model, 'dynamicTopologyScenario') || ...
        ~isstruct(model.dynamicTopologyScenario) || ...
        ~isscalar(model.dynamicTopologyScenario) || ...
        ~isfield(model.dynamicTopologyScenario, 'presetName') || ...
        ~strcmp(model.dynamicTopologyScenario.presetName, ...
            context.presetName) || ...
        ~isfield(model.dynamicTopologyScenario, 'seed') || ...
        model.dynamicTopologyScenario.seed ~= context.seed || ...
        isfield(model, 'explicitTargetTrajectories') || ...
        isfield(model.dynamicTopologyScenario, 'targetTrajectories') || ...
        isfield(model.dynamicTopologyScenario, 'target')
    error('FormationB4V49Tracking:InvalidRuntimeModel', ...
        'The V49 development model is mismatched or contains target truth.');
end

requiredRequestFields = { ...
    'contractVersion', 'operation', 'measurementTimeCount', ...
    'sensorTrajectoryTimeCounts', 'triggerConfig'};
if ~isequal(sort(fieldnames(request)), ...
            sort(requiredRequestFields(:))) || ...
        ~strcmp(request.operation, 'filter-execution') || ...
        request.measurementTimeCount < 1 || ...
        numel(request.sensorTrajectoryTimeCounts) ~= ...
            model.numberOfSensors || ...
        any(request.sensorTrajectoryTimeCounts ~= ...
            request.measurementTimeCount) || ...
        ~isstruct(request.triggerConfig) || ...
        ~isfield(request.triggerConfig, 'topologyPolicyName')
    error('FormationB4V49Tracking:InvalidRuntimeRequest', ...
        'The V49 development runtime dimensions are inconsistent.');
end
if strcmp(context.armId, protocol.referenceArmId)
    expectedPolicy = 'selectFormationB4V46SynchronizedRuntimePolicy';
else
    expectedPolicy = 'selectFormationB4V49SynchronizedRuntimePolicy';
end
if ~strcmp(request.triggerConfig.topologyPolicyName, expectedPolicy)
    error('FormationB4V49Tracking:WrongArmPolicy', ...
