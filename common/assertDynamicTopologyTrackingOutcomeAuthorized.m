    isfield(model, 'explicitSensorTrajectories') || ...
    isfield(model, 'sensorTrajectories') || ...
    isfield(model, 'explicitTargetTrajectories');
hasRegisteredFormationRuntimeTrace = ...
    detectRegisteredFormationRuntimeTrace(model, runtimeRequest);
if ~hasScenario && ~hasGateEnvelope
    if hasExplicitDynamicTrace || hasRegisteredFormationRuntimeTrace
        error('DynamicTopology:IncompleteScenarioMetadata', [ ...
            'A model with explicit dynamic trajectories cannot be ', ...
            'treated as legacy after its scenario and gate metadata ', ...
            'have been removed.']);
    end
    return;
end

% A surviving model-level envelope means that deleting the nested scenario
% cannot bypass the gate.  Conversely, malformed scenario metadata is not a
% valid legacy model and therefore fails closed.
if ~hasScenario || ...
        ~isstruct(model.dynamicTopologyScenario) || ...
        ~isscalar(model.dynamicTopologyScenario) || ...
        ~isfield(model.dynamicTopologyScenario, 'config') || ...
        ~isstruct(model.dynamicTopologyScenario.config) || ...
        ~isscalar(model.dynamicTopologyScenario.config)
    rejectTrackingOutcome(struct());
end

