function assertDynamicTopologyTrackingOutcomeAuthorized(model)
% ASSERTDYNAMICTOPOLOGYTRACKINGOUTCOMEAUTHORIZED Enforce scene outcome gate.
%
% Geometry-calibration scenes may generate truth, measurements and graph
% diagnostics, but they must not reach the tracking filter until a new named
% scene contract explicitly authorizes outcomes.  Legacy models without a
% protected multistyle trace retain their historical behavior.

if ~isstruct(model) || ~isscalar(model)
    return;
end

hasScenario = isfield(model, 'dynamicTopologyScenario');
hasGateEnvelope = isfield(model, ...
    'dynamicTopologyTrackingOutcomeGate');
if ~hasScenario && ~hasGateEnvelope
    return;
end

% A surviving model-level envelope means that deleting the nested scenario
% cannot bypass the gate.  Conversely, malformed scenario metadata is not a
% valid legacy model and therefore fails closed.
if ~hasScenario || ...
        ~isstruct(model.dynamicTopologyScenario) || ...
        ~isscalar(model.dynamicTopologyScenario) || ...
        ~isfield(model.dynamicTopologyScenario, 'config') || ...
        ~isstruct(model.dynamicTopologyScenario.config) || ...
        ~isscalar(model.dynamicTopologyScenario.config)
    rejectTrackingOutcome(struct());
end

config = model.dynamicTopologyScenario.config;
protectedTraceFields = { ...
    'sceneGeometryVersion', 'sceneCalibrationStatus', ...
    'formalValidationAuthorized', 'trackingOutcomeAuthorized', ...
    'sceneContractSha256'};
hasProtectedTrace = hasGateEnvelope || ...
    any(isfield(config, protectedTraceFields));
if ~hasProtectedTrace
    % Historical dynamic-topology models predate the multistyle outcome
    % contract.  Their behavior remains unchanged.
    return;
end

prefix = 'formation-fov-multistyle-';
isVersionedMultistyle = ...
    isfield(config, 'sceneGeometryVersion') && ...
    ischar(config.sceneGeometryVersion) && ...
    strncmp(config.sceneGeometryVersion, prefix, numel(prefix));
declaresGate = isfield(config, 'trackingOutcomeAuthorized');

validGateEnvelope = false;
if hasGateEnvelope
    envelope = model.dynamicTopologyTrackingOutcomeGate;
    validGateEnvelope = isstruct(envelope) && isscalar(envelope) && ...
        isfield(envelope, 'contractVersion') && ...
        ischar(envelope.contractVersion) && ...
        strcmp(envelope.contractVersion, ...
            'dynamic-topology-tracking-outcome-gate-v1') && ...
        isfield(envelope, 'required') && ...
        isequal(envelope.required, true) && ...
        isfield(envelope, 'sceneContractSha256') && ...
        ischar(envelope.sceneContractSha256) && ...
        isfield(config, 'sceneContractSha256') && ...
        ischar(config.sceneContractSha256) && ...
        strcmp(envelope.sceneContractSha256, ...
            config.sceneContractSha256);
end

registeredContract = false;
if isVersionedMultistyle && declaresGate && validGateEnvelope
    try
        registeredContract = strcmp( ...
            config.sceneContractSha256, ...
            computeFormationFovMultistyleSceneContractSha256( ...
                config)) && ...
            strcmp(config.sceneContractSha256, ...
                getExpectedFormationFovMultistyleSceneContractSha256( ...
                    config));
    catch
        registeredContract = false;
    end
end
authorized = declaresGate && registeredContract && ...
    isequal(config.trackingOutcomeAuthorized, true);
if ~authorized
    rejectTrackingOutcome(config);
end
end

function rejectTrackingOutcome(config)
presetName = '<unknown>';
if isstruct(config) && isscalar(config) && ...
        isfield(config, 'presetName') && ischar(config.presetName)
    presetName = config.presetName;
end
error('DynamicTopology:TrackingOutcomeNotAuthorized', [ ...
    'Scenario %s is calibration-only or has incomplete outcome-gate ', ...
    'metadata and may not enter the tracking filter. Freeze a new named ', ...
    'scene contract with explicit tracking outcome authorization first.'], ...
    presetName);
end
