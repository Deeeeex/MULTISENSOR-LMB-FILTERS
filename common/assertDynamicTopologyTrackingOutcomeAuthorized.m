function authorization = validateTrackingAlignedFormationH3Execution( ...
        model, context, request)
expectedFields = { ...
    'contractVersion', 'capability', 'action', 'protocolId', ...
    'phase', 'presetName', 'seed', 'currentTime', ...
    'measurementTimeCount', 'policyName', ...
    'interventionDurationSteps', ...
    'developmentEvidenceOnly'};
protocol = getTrackingAlignedFormationH3HeadroomProtocol();
if ~isequal(sort(fieldnames(context)), sort(expectedFields(:))) || ...
        ~strcmp(context.capability, ...
            'tracking-aligned-headroom-development') || ...
        ~strcmp(context.action, ...
            'filter-tracking-aligned-headroom-development') || ...
        ~strcmp(context.protocolId, protocol.id) || ...
        ~isequal(context.developmentEvidenceOnly, true)
    error('TrackingAlignedV56:InvalidExecutionContext', ...
        'The V56 tracking-aligned execution context is malformed.');
end

presetIdx = find(strcmp(context.presetName, protocol.presets), 1);
validModel = ~isempty(presetIdx) && ...
    isstruct(model) && isscalar(model) && ...
    isfield(model, 'numberOfSensors') && ...
    model.numberOfSensors == protocol.expectedNodeCounts(presetIdx) && ...
    isfield(model, 'dynamicTopologyScenario') && ...
    isstruct(model.dynamicTopologyScenario) && ...
    isscalar(model.dynamicTopologyScenario) && ...
    isfield(model.dynamicTopologyScenario, 'presetName') && ...
    strcmp(model.dynamicTopologyScenario.presetName, ...
        context.presetName) && ...
    isfield(model.dynamicTopologyScenario, 'seed') && ...
    model.dynamicTopologyScenario.seed == context.seed && ...
    ~isfield(model, 'explicitTargetTrajectories') && ...
    ~isfield(model.dynamicTopologyScenario, 'targetTrajectories');
if ~validModel || ~ismember(context.seed, protocol.allSeeds)
    error('TrackingAlignedV56:InvalidRuntimeModel', ...
        'The V56 model is mismatched or contains target truth.');
end

requiredRequestFields = { ...
    'contractVersion', 'operation', 'measurementTimeCount', ...
    'sensorTrajectoryTimeCounts', 'triggerConfig'};
validRequest = isequal(sort(fieldnames(request)), ...
        sort(requiredRequestFields(:))) && ...
    strcmp(request.operation, 'filter-execution') && ...
    request.measurementTimeCount == context.measurementTimeCount && ...
    numel(request.sensorTrajectoryTimeCounts) == model.numberOfSensors && ...
    all(request.sensorTrajectoryTimeCounts == ...
        context.measurementTimeCount) && ...
    isstruct(request.triggerConfig) && ...
    isfield(request.triggerConfig, 'topologyPolicyName') && ...
    strcmp(request.triggerConfig.topologyPolicyName, ...
        context.policyName) && ...
    isfield(request.triggerConfig, 'topologyPolicyHistoryDepth') && ...
    request.triggerConfig.topologyPolicyHistoryDepth >= 2;
if ~validRequest
    error('TrackingAlignedV56:InvalidRuntimeRequest', ...
        'The V56 runtime dimensions or policy name changed.');
end

switch context.phase
    case 'reference-cache'
        validPhase = ...
            context.currentTime == max(protocol.snapshotTimes) && ...
            context.measurementTimeCount == context.currentTime && ...
            context.interventionDurationSteps == 0 && ...
            strcmp(context.policyName, ...
                'formation-h3-fixed-ccw-reference-v1');
    case 'opened-return'
        validPhase = ismember( ...
                context.currentTime, protocol.snapshotTimes) && ...
            context.measurementTimeCount == ...
                context.currentTime + protocol.horizonSteps - 1;
        if validPhase && isnan(context.interventionDurationSteps)
            validPhase = strcmp(context.policyName, sprintf( ...
                'formation-h%d-frozen-action-sequence-v1', ...
                protocol.horizonSteps));
        elseif validPhase
            duration = context.interventionDurationSteps;
            validPhase = isa(duration, 'double') && isreal(duration) && ...
                isscalar(duration) && isfinite(duration) && ...
                duration == floor(duration) && duration >= 1 && ...
                duration <= protocol.horizonSteps && ...
                strcmp(context.policyName, sprintf( ...
                    ['formation-h%d-frozen-duration-%d-', ...
                     'then-reference-v1'], ...
                    protocol.horizonSteps, duration));
        end
    otherwise
        validPhase = false;
end
if ~validPhase
    error('TrackingAlignedV56:InvalidExecutionPhase', ...
        'The V56 execution phase does not match the frozen protocol.');
end

authorization = buildLegacyAuthorization();
authorization.mode = 'tracking-aligned-formation-h3-development';
authorization.capability = context.capability;
authorization.action = context.action;
authorization.protocolId = protocol.id;
authorization.presetName = context.presetName;
authorization.seed = context.seed;
authorization.sourceWindow = [1, context.measurementTimeCount];
authorization.armId = context.policyName;
authorization.stateEstimateOutputAuthorized = true;
authorization.trackingOutcomeScoringAuthorized = true;
authorization.groundTruthAccessAuthorized = false;
authorization.futureOutcomeAccessAuthorized = false;
authorization.validationClaimAllowed = false;
authorization.developmentEvidenceOnly = true;
end
