function readout = computeRollingSafeAttributionReadout( ...
        aggregates, scenarioConfig, minimumGainPercent)
% COMPUTEROLLINGSAFEATTRIBUTIONREADOUT Evidence gate for rolling-safe arms.
%
% A candidate is compared per seed with the strongest tracking value in
% the complete same-weight registered control set.  If controls tie on
% tracking, tail, bytes and delivered safety are evaluated conservatively
% against every tied arm.  The gate also verifies schedule execution,
% complete maturity denominators and selected-route safety.

if nargin < 3 || isempty(minimumGainPercent)
    minimumGainPercent = 5;
end
readout = emptyRollingSafeAttributionReadout();
[scenarioValid, formationCount] = ...
    resolveScenarioContract(scenarioConfig);
readout.scenarioContractValid = scenarioValid;
readout.formationCount = formationCount;
if isempty(aggregates)
    return;
end

modes = cellfun(@canonicalMode, {aggregates.mode}, ...
    'UniformOutput', false);
observedCandidateIdx = find(cellfun(@isCandidateMode, modes));
readout.observedCandidateCount = numel(observedCandidateIdx);
if isempty(observedCandidateIdx)
    return;
end
[candidateIdx, duplicateCandidateModes] = ...
    uniqueCandidateModes(observedCandidateIdx, modes);
readout.availableCandidateCount = numel(candidateIdx);
readout.duplicateCandidateModes = duplicateCandidateModes;

evaluations = repmat(emptyRollingSafeAttributionReadout(), ...
    1, numel(candidateIdx));
for cursor = 1:numel(candidateIdx)
    candidateModeDuplicate = any(strcmp( ...
        duplicateCandidateModes, modes{candidateIdx(cursor)}));
    evaluations(cursor) = evaluateCandidate( ...
        aggregates, modes, candidateIdx(cursor), ...
        scenarioValid, formationCount, minimumGainPercent, ...
        candidateModeDuplicate);
    evaluations(cursor).observedCandidateCount = ...
        numel(observedCandidateIdx);
    evaluations(cursor).availableCandidateCount = ...
        numel(candidateIdx);
    evaluations(cursor).duplicateCandidateModes = ...
        duplicateCandidateModes;
end
selected = selectCandidateEvaluation( ...
    evaluations, aggregates, candidateIdx);
readout = evaluations(selected);
end

function [indices, duplicates] = ...
        uniqueCandidateModes(observedIndices, modes)
indices = zeros(1, 0);
duplicates = {};
seen = {};
for cursor = 1:numel(observedIndices)
    index = observedIndices(cursor);
    mode = modes{index};
    if any(strcmp(seen, mode))
        if ~any(strcmp(duplicates, mode))
            duplicates{end + 1} = mode; %#ok<AGROW>
        end
        continue;
    end
    seen{end + 1} = mode; %#ok<AGROW>
    indices(end + 1) = index; %#ok<AGROW>
end
end

function selected = selectCandidateEvaluation( ...
        evaluations, aggregates, candidateIdx)
passing = [evaluations.passesAttributionGate];
valid = [evaluations.completeControlSet] & ...
    [evaluations.candidateContractPassed];
complete = [evaluations.completeControlSet];
if any(passing)
    pool = find(passing);
elseif any(valid)
    pool = find(valid);
elseif any(complete)
    pool = find(complete);
else
    focus = arrayfun(@(idx) meanMetric( ...
        aggregates(idx), 'focusEospaBySeed'), candidateIdx);
    [~, selected] = min(focus);
    return;
end
minimumGains = arrayfun(@minimumFiniteGain, evaluations(pool));
bestMinimum = max(minimumGains);
pool = pool(abs(minimumGains - bestMinimum) <= 1e-12);
meanGains = [evaluations(pool).gainVsMatchedControlPercent];
meanGains(~isfinite(meanGains)) = -inf;
[~, cursor] = max(meanGains);
selected = pool(cursor);
end

function value = minimumFiniteGain(readout)
values = readout.gainVsMatchedControlBySeedPercent;
if isempty(values) || any(~isfinite(values))
    value = -inf;
else
    value = min(values);
end
end

function readout = evaluateCandidate( ...
        aggregates, modes, candidateIdx, ...
        scenarioValid, formationCount, minimumGainPercent, ...
        candidateModeDuplicate)
readout = emptyRollingSafeAttributionReadout();
candidate = aggregates(candidateIdx);
token = regexp(modes{candidateIdx}, ...
    ['^(rolling-safe-analytic|', ...
     'learned-rolling-safe-rollout)-w([0-9]+)$'], ...
    'tokens', 'once');
if isempty(token)
    return;
end
sourceWeight = str2double(token{2}) / 100;
candidateEospa = getMetric( ...
    candidate, 'focusEospaBySeed', NaN);
seedCount = numel(candidateEospa);
payloadConstraintEnforced = uniformBinaryMetric( ...
    candidate, ...
    'policyPayloadConstraintEnforcedFractionBySeed', ...
    seedCount);

readout.available = true;
readout.arm = candidate.name;
readout.candidateMode = modes{candidateIdx};
readout.candidateModeDuplicate = candidateModeDuplicate;
readout.candidateSourceWeight = sourceWeight;
readout.scenarioContractValid = scenarioValid;
readout.formationCount = formationCount;
readout.minimumPracticalGainPercent = minimumGainPercent;
readout.payloadConstraintEnforced = ...
    payloadConstraintEnforced;
readout.jointProjectionUsed = uniformBinaryMetric( ...
    candidate, ...
    'policyOneStepJointProjectionUseFractionBySeed', ...
    seedCount) == 1;
if ~scenarioValid
    return;
end

controls = buildRollingSafeMatchedControlArmNames( ...
    formationCount, sourceWeight);
expectedModes = controls.allArmNames;
readout.expectedControlModes = expectedModes;
readout.expectedControlCount = numel(expectedModes);
validControlIdx = zeros(1, 0);
for expectedIdx = 1:numel(expectedModes)
    mode = expectedModes{expectedIdx};
    observedIdx = find(strcmp(modes, mode));
    readout.observedControlCount = ...
        readout.observedControlCount + numel(observedIdx);
    if isempty(observedIdx)
        readout.missingControlModes{end + 1} = mode;
        continue;
    end
    if numel(observedIdx) > 1
        readout.duplicateControlModes{end + 1} = mode;
        continue;
    end
    readout.uniquelyObservedControlCount = ...
        readout.uniquelyObservedControlCount + 1;
    expectedLinkUse = strcmp(mode, controls.linkAwareArmName);
    contract = validateRollingArmContract( ...
        aggregates(observedIdx), seedCount, sourceWeight, ...
        false, expectedLinkUse, ...
        payloadConstraintEnforced, mode, formationCount);
    if ~contract.allPassed
        readout.invalidControlModes{end + 1} = mode;
        continue;
    end
    validControlIdx(end + 1) = observedIdx; %#ok<AGROW>
end
readout.validControlCount = numel(validControlIdx);

candidateContract = validateRollingArmContract( ...
    candidate, seedCount, sourceWeight, true, true, ...
    payloadConstraintEnforced, modes{candidateIdx}, formationCount);
readout.candidateContractPassed = ...
    candidateContract.allPassed && ~candidateModeDuplicate;
readout.maturityCountsComplete = ...
    candidateContract.maturityContractPassed;
readout.selectedSafetyPassed = ...
    candidateContract.selectedSafetyPassed && ...
    readout.validControlCount == readout.expectedControlCount;
readout.policyContractPassed = ...
    candidateContract.policyContractPassed && ...
    readout.validControlCount == readout.expectedControlCount;
[readout.scheduledBehaviorContractPassed, ...
    readout.collapsedControlBehaviorPairs, ...
    readout.scheduleSignatureAuditLines] = ...
    validateScheduledBehaviorDiversity( ...
        aggregates(validControlIdx), modes(validControlIdx), seedCount);
readout.controlContractPassed = ...
    isempty(readout.missingControlModes) && ...
    isempty(readout.duplicateControlModes) && ...
    isempty(readout.invalidControlModes) && ...
    readout.validControlCount == readout.expectedControlCount && ...
    readout.scheduledBehaviorContractPassed;
readout.completeControlSet = ...
    scenarioValid && readout.controlContractPassed;
if ~readout.completeControlSet
    return;
end

readout.maturityCountsMatched = ...
    maturityCountsMatch( ...
        candidate, aggregates(validControlIdx), seedCount);
[readout.maturityFieldNames, ...
    readout.candidateMaturityCountsByField, ...
    readout.controlMaturityCountsByField] = ...
    maturityAuditMatrices( ...
        candidate, aggregates(validControlIdx(1)), seedCount);
controlEospa = metricMatrix( ...
    aggregates, validControlIdx, ...
    'focusEospaBySeed', seedCount);
controlWorst = metricMatrix( ...
    aggregates, validControlIdx, ...
    'focusWorstSensorEospaBySeed', seedCount);
controlBytes = metricMatrix( ...
    aggregates, validControlIdx, ...
    'focusAttemptedBytesBySeed', seedCount);
controlDeliveredSensor = metricMatrix( ...
    aggregates, validControlIdx, ...
    'focusDeliveredRollingB3SensorStrongFractionBySeed', ...
    seedCount);
controlDeliveredFormation = metricMatrix( ...
    aggregates, validControlIdx, ...
    'focusDeliveredRollingB3FormationStrongFractionBySeed', ...
    seedCount);
referenceWorst = nan(1, seedCount);
referenceBytes = nan(1, seedCount);
referenceDeliveredSensor = nan(1, seedCount);
referenceDeliveredFormation = nan(1, seedCount);
referenceEospa = nan(1, seedCount);
referenceTieCount = zeros(1, seedCount);
referenceNames = cell(1, seedCount);
for seedIdx = 1:seedCount
    referenceEospa(seedIdx) = min(controlEospa(:, seedIdx));
    tolerance = 1e-10 * max( ...
        1, abs(referenceEospa(seedIdx)));
    tied = abs(controlEospa(:, seedIdx) - ...
        referenceEospa(seedIdx)) <= tolerance;
    referenceTieCount(seedIdx) = nnz(tied);
    referenceWorst(seedIdx) = ...
        min(controlWorst(tied, seedIdx));
    referenceBytes(seedIdx) = ...
        min(controlBytes(tied, seedIdx));
    referenceDeliveredSensor(seedIdx) = ...
        max(controlDeliveredSensor(tied, seedIdx));
    referenceDeliveredFormation(seedIdx) = ...
        max(controlDeliveredFormation(tied, seedIdx));
    tiedIndices = validControlIdx(tied);
    referenceNames{seedIdx} = strjoin( ...
        {aggregates(tiedIndices).name}, ' || ');
end
readout.referenceArm = [ ...
    'all tracking-minimal per-seed same-weight registered controls'];
readout.referenceArmBySeed = referenceNames;
readout.referenceTrackingTieCountBySeed = referenceTieCount;

candidateWorst = getMetric( ...
    candidate, 'focusWorstSensorEospaBySeed', NaN);
candidateBytes = getMetric( ...
    candidate, 'focusAttemptedBytesBySeed', NaN);
candidateDeliveredSensor = getMetric( ...
    candidate, ...
    'focusDeliveredRollingB3SensorStrongFractionBySeed', NaN);
candidateDeliveredFormation = getMetric( ...
    candidate, ...
    'focusDeliveredRollingB3FormationStrongFractionBySeed', NaN);
readout.referenceEospaBySeed = referenceEospa;
readout.referenceWorstSensorEospaBySeed = referenceWorst;
readout.referenceAttemptedBytesBySeed = referenceBytes;
readout.referenceDeliveredSensorSafetyBySeed = ...
    referenceDeliveredSensor;
readout.referenceDeliveredFormationSafetyBySeed = ...
    referenceDeliveredFormation;
readout.candidateEospaBySeed = candidateEospa;
readout.candidateWorstSensorEospaBySeed = candidateWorst;
readout.candidateAttemptedBytesBySeed = candidateBytes;
readout.candidateDeliveredSensorSafetyBySeed = ...
    candidateDeliveredSensor;
readout.candidateDeliveredFormationSafetyBySeed = ...
    candidateDeliveredFormation;
gainBySeed = 100 * ( ...
    referenceEospa - candidateEospa) ./ ...
    max(abs(referenceEospa), eps);
readout.gainVsMatchedControlBySeedPercent = gainBySeed;
readout.gainVsMatchedControlPercent = 100 * ( ...
    mean(referenceEospa) - mean(candidateEospa)) / ...
    max(abs(mean(referenceEospa)), eps);
readout.positiveGainEverySeed = all(gainBySeed > 0);
readout.minimumGainEverySeed = all( ...
    gainBySeed + 1e-12 >= minimumGainPercent);
readout.tailSafeVsMatchedControl = all( ...
    candidateWorst <= referenceWorst + 1e-12);
byteMismatch = 100 * abs( ...
    candidateBytes - referenceBytes) ./ ...
    max(referenceBytes, 1);
readout.maximumAttemptedByteMismatchPercent = max(byteMismatch);
readout.communicationMatchedWithinTwoPercent = all( ...
    byteMismatch <= 2 + 1e-12);
readout.withinReferenceAttemptedBytesEverySeed = all( ...
    candidateBytes <= 1.02 * referenceBytes + 1e-12);
readout.noMoreAttemptedBytesEverySeed = all( ...
    candidateBytes <= referenceBytes + 1e-12);
readout.strictParetoEverySeed = ...
    readout.positiveGainEverySeed && ...
    readout.noMoreAttemptedBytesEverySeed;
readout.communicationFair = ...
    readout.withinReferenceAttemptedBytesEverySeed;
readout.deliveredSafetyNoRegression = ...
    readout.maturityCountsMatched && ...
    all(candidateDeliveredSensor + 1e-12 >= ...
        referenceDeliveredSensor) && ...
    all(candidateDeliveredFormation + 1e-12 >= ...
        referenceDeliveredFormation);
readout.passesAttributionGate = ...
    readout.completeControlSet && ...
    readout.candidateContractPassed && ...
    readout.selectedSafetyPassed && ...
    readout.policyContractPassed && ...
    readout.maturityCountsComplete && ...
    readout.maturityCountsMatched && ...
    readout.deliveredSafetyNoRegression && ...
    readout.gainVsMatchedControlPercent + 1e-12 >= ...
        minimumGainPercent && ...
    readout.minimumGainEverySeed && ...
    readout.tailSafeVsMatchedControl && ...
    readout.communicationFair;
end

function contract = validateRollingArmContract( ...
        arm, seedCount, sourceWeight, ...
        expectedPosteriorContentUse, expectedLinkUse, ...
        expectedPayloadConstraintEnforcement, registeredMode, ...
        formationCount)
trackingPassed = ...
    finiteMetric(arm, 'focusEospaBySeed', seedCount) && ...
    finiteMetric(arm, ...
        'focusWorstSensorEospaBySeed', seedCount) && ...
    positiveMetric(arm, ...
        'focusAttemptedBytesBySeed', seedCount);
selectedSafetyPassed = ...
    equalsMetric(arm, ...
        'focusReceiverCoverageFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'focusDirectedMessageCountExactFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'focusSelectedRollingB3SensorStrongFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'focusSelectedRollingB3FormationStrongFractionBySeed', ...
        seedCount, 1);
deliveredMetricsPresent = ...
    boundedMetric(arm, ...
        'focusDeliveredRollingB3SensorStrongFractionBySeed', ...
        seedCount, 0, 1) && ...
    boundedMetric(arm, ...
        'focusDeliveredRollingB3FormationStrongFractionBySeed', ...
        seedCount, 0, 1);
maturityContractPassed = ...
    matchingMetricFields(arm, ...
        'focusSelectedRollingB3SensorMatureWindowCountBySeed', ...
        'focusExpectedSelectedRollingB3MatureWindowCountBySeed', ...
        seedCount, true) && ...
    matchingMetricFields(arm, ...
        'focusSelectedRollingB3FormationMatureWindowCountBySeed', ...
        'focusExpectedSelectedRollingB3MatureWindowCountBySeed', ...
        seedCount, true) && ...
    matchingMetricFields(arm, ...
        'focusDeliveredRollingB3SensorMatureWindowCountBySeed', ...
        'focusExpectedDeliveredRollingB3MatureWindowCountBySeed', ...
        seedCount, true) && ...
    matchingMetricFields(arm, ...
        'focusDeliveredRollingB3FormationMatureWindowCountBySeed', ...
        'focusExpectedDeliveredRollingB3MatureWindowCountBySeed', ...
        seedCount, true) && ...
    matchingMetricFields(arm, ...
        'policyFormationWindowMatureCountBySeed', ...
        'policyExpectedFormationWindowMatureCountBySeed', ...
        seedCount, true) && ...
    matchingMetricFields(arm, ...
        'policySensorWindowMatureCountBySeed', ...
        'policyExpectedSensorWindowMatureCountBySeed', ...
        seedCount, true) && ...
    matchingMetricFields(arm, ...
        'policyOneStepTopologyReserveCheckCountBySeed', ...
        'policyExpectedOneStepTopologyReserveCheckCountBySeed', ...
        seedCount, true);
scheduledMode = isScheduledControlMode(registeredMode);
registeredBehaviorPassed = ...
    equalsMetric(arm, ...
        'policyRegisteredCrossCapExactFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policyFormationPairCapPassFractionBySeed', ...
        seedCount, 1) && ...
    atMostMetric(arm, ...
        'policyMaximumActualCrossEdgeCountBySeed', ...
        seedCount, formationCount - 1);
if scheduledMode
    registeredBehaviorPassed = ...
        registeredBehaviorPassed && ...
        equalsMetric(arm, ...
            'policyRegisteredScheduleMetadataMatchFractionBySeed', ...
            seedCount, 1) && ...
        equalsMetric(arm, ...
            'policyRegisteredProposalMatchFractionBySeed', ...
            seedCount, 1) && ...
        signatureMetricsPresent(arm, seedCount);
end
policyContractPassed = ...
    equalsMetric(arm, ...
        'policyFormationWindowStrongFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policySensorWindowStrongFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policySuccessorSensorStrongFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policyOneStepTopologyReservePassFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policyOneStepJointProjectionUseFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policyPayloadLimitPassFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policyPayloadConstraintEnforcedFractionBySeed', ...
        seedCount, expectedPayloadConstraintEnforcement) && ...
    equalsMetric(arm, ...
        'policyPayloadEmergencyRateBySeed', ...
        seedCount, 0) && ...
    atMostMetric(arm, ...
        'policyMaximumCrossSourceLoadBySeed', ...
        seedCount, 1) && ...
    atMostMetric(arm, ...
        'policyMaximumCrossReceiverLoadBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policyCrossCountCapPassFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'policySourceWeightMeanBySeed', ...
        seedCount, sourceWeight) && ...
    equalsMetric(arm, ...
        'policySourceWeightSpreadBySeed', ...
        seedCount, 0) && ...
    equalsMetric(arm, ...
        'policyPosteriorContentUseFractionBySeed', ...
        seedCount, double(expectedPosteriorContentUse)) && ...
    equalsMetric(arm, ...
        'policyPosteriorPayloadMetadataUseFractionBySeed', ...
        seedCount, expectedPayloadConstraintEnforcement) && ...
    equalsMetric(arm, ...
        'policyTruthUseFractionBySeed', ...
        seedCount, 0) && ...
    equalsMetric(arm, ...
        'policyCurrentLinkReliabilityUseFractionBySeed', ...
        seedCount, double(expectedLinkUse)) && ...
    equalsMetric(arm, ...
        'policyRecursiveSafetyClaimRateBySeed', ...
        seedCount, 0) && ...
    equalsMetric(arm, ...
        'policyBalancedCycleBackboneFractionBySeed', ...
        seedCount, 1) && ...
    equalsMetric(arm, ...
        'focusTopologyInfeasibleRateBySeed', ...
        seedCount, 0) && ...
    equalsMetric(arm, ...
        'topologyInfeasibleRateBySeed', ...
        seedCount, 0) && ...
    registeredBehaviorPassed && ...
    maturityContractPassed;
contract = struct( ...
    'selectedSafetyPassed', selectedSafetyPassed, ...
    'maturityContractPassed', maturityContractPassed, ...
    'registeredBehaviorPassed', registeredBehaviorPassed, ...
    'policyContractPassed', policyContractPassed, ...
    'allPassed', trackingPassed && selectedSafetyPassed && ...
        deliveredMetricsPresent && maturityContractPassed && ...
        policyContractPassed);
end

function matched = maturityCountsMatch( ...
        candidate, controls, seedCount)
fields = { ...
    'focusSelectedRollingB3SensorMatureWindowCountBySeed', ...
    'focusSelectedRollingB3FormationMatureWindowCountBySeed', ...
    'focusExpectedSelectedRollingB3MatureWindowCountBySeed', ...
    'focusDeliveredRollingB3SensorMatureWindowCountBySeed', ...
    'focusDeliveredRollingB3FormationMatureWindowCountBySeed', ...
    'focusExpectedDeliveredRollingB3MatureWindowCountBySeed', ...
    'policyFormationWindowMatureCountBySeed', ...
    'policySensorWindowMatureCountBySeed', ...
    'policyExpectedFormationWindowMatureCountBySeed', ...
    'policyExpectedSensorWindowMatureCountBySeed', ...
    'policyOneStepTopologyReserveCheckCountBySeed', ...
    'policyExpectedOneStepTopologyReserveCheckCountBySeed'};
matched = true;
for fieldIdx = 1:numel(fields)
    candidateValues = getMetric( ...
        candidate, fields{fieldIdx}, NaN);
    if numel(candidateValues) ~= seedCount || ...
            any(~isfinite(candidateValues))
        matched = false;
        return;
    end
    for controlIdx = 1:numel(controls)
        controlValues = getMetric( ...
            controls(controlIdx), fields{fieldIdx}, NaN);
        if numel(controlValues) ~= seedCount || ...
                any(~isfinite(controlValues)) || ...
                any(abs(controlValues - candidateValues) > 1e-12)
            matched = false;
            return;
        end
    end
end
end

function [fieldNames, candidateMatrix, controlMatrix] = ...
        maturityAuditMatrices(candidate, control, seedCount)
fieldNames = { ...
    'selected sensor', 'selected formation', ...
    'expected selected', 'delivered sensor', ...
    'delivered formation', 'expected delivered', ...
    'policy formation', 'policy sensor', ...
    'expected policy formation', 'expected policy sensor', ...
    'one-step checks', 'expected one-step checks'};
fields = { ...
    'focusSelectedRollingB3SensorMatureWindowCountBySeed', ...
    'focusSelectedRollingB3FormationMatureWindowCountBySeed', ...
    'focusExpectedSelectedRollingB3MatureWindowCountBySeed', ...
    'focusDeliveredRollingB3SensorMatureWindowCountBySeed', ...
    'focusDeliveredRollingB3FormationMatureWindowCountBySeed', ...
    'focusExpectedDeliveredRollingB3MatureWindowCountBySeed', ...
    'policyFormationWindowMatureCountBySeed', ...
    'policySensorWindowMatureCountBySeed', ...
    'policyExpectedFormationWindowMatureCountBySeed', ...
    'policyExpectedSensorWindowMatureCountBySeed', ...
    'policyOneStepTopologyReserveCheckCountBySeed', ...
    'policyExpectedOneStepTopologyReserveCheckCountBySeed'};
candidateMatrix = nan(numel(fields), seedCount);
controlMatrix = nan(numel(fields), seedCount);
for fieldIdx = 1:numel(fields)
    candidateMatrix(fieldIdx, :) = getMetric( ...
        candidate, fields{fieldIdx}, NaN);
    controlMatrix(fieldIdx, :) = getMetric( ...
        control, fields{fieldIdx}, NaN);
end
end

function [passed, collapsedPairs, auditLines] = ...
        validateScheduledBehaviorDiversity( ...
            controls, modes, seedCount)
scheduled = find(cellfun(@isScheduledControlMode, modes));
collapsedPairs = {};
auditLines = {};
if isempty(scheduled)
    passed = false;
    return;
end
expected = cell(numel(scheduled), seedCount);
observed = cell(numel(scheduled), seedCount);
selected = cell(numel(scheduled), seedCount);
passed = true;
for cursor = 1:numel(scheduled)
    control = controls(scheduled(cursor));
    expected(cursor, :) = getCellMetric( ...
        control, 'policyExpectedProposalSignatureBySeed', seedCount);
    observed(cursor, :) = getCellMetric( ...
        control, 'policyObservedProposalSignatureBySeed', seedCount);
    selected(cursor, :) = getCellMetric( ...
        control, 'policySelectedRouteSignatureBySeed', seedCount);
    if any(cellfun(@isempty, expected(cursor, :))) || ...
            any(cellfun(@isempty, observed(cursor, :))) || ...
            any(cellfun(@isempty, selected(cursor, :)))
        passed = false;
    end
    auditLines{end + 1} = sprintf( ...
        '%s | expected=%s | observed=%s | selected=%s', ...
        modes{scheduled(cursor)}, ...
        strjoin(expected(cursor, :), '/'), ...
        strjoin(observed(cursor, :), '/'), ...
        strjoin(selected(cursor, :), '/')); %#ok<AGROW>
end
for seedIdx = 1:seedCount
    for left = 1:(numel(scheduled) - 1)
        for right = (left + 1):numel(scheduled)
            if strcmp(expected{left, seedIdx}, ...
                    expected{right, seedIdx})
                continue;
            end
            if strcmp(selected{left, seedIdx}, ...
                    selected{right, seedIdx})
                passed = false;
                collapsedPairs{end + 1} = sprintf( ...
                    'seed %d: %s == %s', seedIdx, ...
                    modes{scheduled(left)}, ...
                    modes{scheduled(right)}); %#ok<AGROW>
            end
        end
    end
end
end

function matrix = metricMatrix( ...
        aggregates, indices, fieldName, seedCount)
matrix = nan(numel(indices), seedCount);
for cursor = 1:numel(indices)
    values = getMetric( ...
        aggregates(indices(cursor)), fieldName, NaN);
    if numel(values) ~= seedCount
        error('Rolling-attribution metric seed counts differ.');
    end
    matrix(cursor, :) = values;
end
end

function passed = finiteMetric(arm, fieldName, seedCount)
values = getMetric(arm, fieldName, NaN);
passed = numel(values) == seedCount && all(isfinite(values));
end

function passed = boundedMetric( ...
        arm, fieldName, seedCount, minimum, maximum)
values = getMetric(arm, fieldName, NaN);
passed = numel(values) == seedCount && ...
    all(isfinite(values)) && ...
    all(values >= minimum - 1e-12) && ...
    all(values <= maximum + 1e-12);
end

function passed = positiveMetric(arm, fieldName, seedCount)
values = getMetric(arm, fieldName, NaN);
passed = numel(values) == seedCount && ...
    all(isfinite(values)) && all(values > 0);
end

function passed = matchingMetricFields( ...
        arm, actualField, expectedField, seedCount, requirePositive)
actual = getMetric(arm, actualField, NaN);
expected = getMetric(arm, expectedField, NaN);
passed = numel(actual) == seedCount && ...
    numel(expected) == seedCount && ...
    all(isfinite(actual)) && all(isfinite(expected)) && ...
    all(abs(actual - expected) <= 1e-12);
if requirePositive
    passed = passed && all(expected > 0);
end
end

function passed = signatureMetricsPresent(arm, seedCount)
fields = { ...
    'policyExpectedProposalSignatureBySeed', ...
    'policyObservedProposalSignatureBySeed', ...
    'policySelectedRouteSignatureBySeed'};
passed = true;
for fieldIdx = 1:numel(fields)
    values = getCellMetric(arm, fields{fieldIdx}, seedCount);
    if numel(values) ~= seedCount || any(cellfun(@isempty, values))
        passed = false;
        return;
    end
end
end

function values = getCellMetric(arm, fieldName, seedCount)
if ~isfield(arm, fieldName) || ~iscell(arm.(fieldName))
    values = repmat({''}, 1, seedCount);
    return;
end
values = reshape(arm.(fieldName), 1, []);
if numel(values) ~= seedCount
    values = repmat({''}, 1, seedCount);
end
end

function value = isScheduledControlMode(mode)
mode = canonicalMode(mode);
value = ~isempty(regexp(mode, ...
    ['^directed-rolling-(chunk-q[0-9]+-d(cw|ccw)-c[0-9]+|', ...
     'burst-r[0-9]+-d(cw|ccw)-p[0-2])-w[0-9]+$'], ...
    'once'));
end

function passed = equalsMetric( ...
        arm, fieldName, seedCount, expected)
values = getMetric(arm, fieldName, NaN);
passed = numel(values) == seedCount && ...
    all(isfinite(values)) && ...
    all(abs(values - expected) <= 1e-12);
end

function passed = atMostMetric( ...
        arm, fieldName, seedCount, maximum)
values = getMetric(arm, fieldName, NaN);
passed = numel(values) == seedCount && ...
    all(isfinite(values)) && ...
    all(values <= maximum + 1e-12);
end

function value = uniformBinaryMetric( ...
        arm, fieldName, seedCount)
values = getMetric(arm, fieldName, NaN);
if numel(values) ~= seedCount || ...
        any(~isfinite(values)) || ...
        any(abs(values - round(values)) > 1e-12) || ...
        any(values < 0 | values > 1) || ...
        any(abs(values - values(1)) > 1e-12)
    value = NaN;
else
    value = values(1);
end
end

function values = getMetric(arm, fieldName, defaultValue)
if isfield(arm, fieldName)
    values = reshape(arm.(fieldName), 1, []);
else
    values = defaultValue;
end
end

function value = meanMetric(arm, fieldName)
values = getMetric(arm, fieldName, inf);
values = values(isfinite(values));
if isempty(values)
    value = inf;
else
    value = mean(values);
end
end

function mode = canonicalMode(mode)
mode = lower(strrep(char(mode), '_', '-'));
end

function matched = isCandidateMode(mode)
matched = ~isempty(regexp(mode, ...
    ['^(rolling-safe-analytic|', ...
     'learned-rolling-safe-rollout)-w[0-9]+$'], 'once'));
end

function [valid, formationCount] = ...
        resolveScenarioContract(config)
valid = false;
formationCount = NaN;
if ~isstruct(config) || ~isfield(config, 'sensorGroupIds')
    return;
end
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
counts = arrayfun(@(group) nnz(groupIds == group), groups);
if numel(groups) < 2 || isempty(counts) || ...
        any(counts ~= counts(1))
    return;
end
if isfield(config, 'numberOfSensors') && ...
        config.numberOfSensors ~= numel(groupIds)
    return;
end
formationCount = numel(groups);
valid = true;
end
