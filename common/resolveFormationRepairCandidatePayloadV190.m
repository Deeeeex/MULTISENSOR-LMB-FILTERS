function [proposal, details] = ...
        resolveFormationRepairCandidatePayloadV190( ...
            candidate, localPosteriorBySensor, physicalAdjacency, ...
            model, options)
% RESOLVEFORMATIONREPAIRCANDIDATEPAYLOADV190 Build one exact GM action.
%
% Candidate enumeration and payload access stay separate: the causal light
% synopsis chooses a routing key, then this function resolves that key to
% the complete Bernoulli Gaussian-mixture object held by the source.  It
% does not rank candidates or read truth/future measurements.

if nargin < 5 || isempty(options)
    options = struct();
end
protocol = getBudgetRecycledFormationRepairV188Protocol();
sensorCount = numel(localPosteriorBySensor);
minimumUtilityLowerBound = getField( ...
    options, 'minimumUtilityLowerBound', 0);
rollingConnectivityPassed = logical(getField( ...
    options, 'rollingConnectivityPassed', true));
validateInputs(candidate, localPosteriorBySensor, ...
    physicalAdjacency, model, minimumUtilityLowerBound, ...
    rollingConnectivityPassed);

sourceObject = findLabelObject( ...
    localPosteriorBySensor{candidate.sourceId}, candidate.label);
payloadPresent = ~isempty(sourceObject);
responseBytesPerReceiver = 0;
if payloadPresent
    responseStats = estimateLmbPayloadSize( ...
        sourceObject, model, 2, struct());
    payloadPresent = responseStats.objectCount == 1 && ...
        responseStats.estimatedBytes > 0;
    if payloadPresent
        responseBytesPerReceiver = responseStats.estimatedBytes;
    end
end

receivers = reshape(candidate.receiverIds, 1, []);
commonSourcePassed = all(logical(physicalAdjacency( ...
    receivers, candidate.sourceId)));
utilityPassed = candidate.minimumRiskReduction > ...
    minimumUtilityLowerBound;
proposal = emptyProposal();
proposal.formationId = candidate.formationId;
proposal.receiverIds = receivers;
proposal.sourceId = candidate.sourceId;
proposal.label = reshape(candidate.label, 2, 1);
proposal.sourceObject = sourceObject;
proposal.richSynopsisBytes = ...
    protocol.richSynopsisBytesPerShortlistedLabel;
proposal.requestBytes = protocol.completeLabelRequestBytes;
proposal.completeResponseBytesPerReceiver = ...
    responseBytesPerReceiver;
proposal.responseBytes = numel(receivers) * ...
    responseBytesPerReceiver;
proposal.attemptedBytes = proposal.richSynopsisBytes + ...
    proposal.requestBytes + proposal.responseBytes;
proposal.estimatedUtilityLowerBound = ...
    candidate.minimumRiskReduction;
proposal.rankingOpportunity = candidate.opportunityMedian;
proposal.minimumRiskReduction = ...
    candidate.minimumRiskReduction;
proposal.minimumReceiverExistence = ...
    candidate.minimumReceiverExistence;
proposal.peerConsensus = candidate.peerConsensusMedian;
proposal.receiverCompatibility = ...
    candidate.receiverCompatibilityMedian;
proposal.commonSourcePassed = commonSourcePassed;
proposal.safetyPassed = payloadPresent && commonSourcePassed && ...
    utilityPassed;
proposal.rollingConnectivityPassed = ...
    rollingConnectivityPassed;

details = struct();
details.contractVersion = ...
    'formation-repair-candidate-payload-v190-v1';
details.candidateIndex = candidate.candidateIndex;
details.payloadPresent = payloadPresent;
details.commonSourcePassed = commonSourcePassed;
details.utilityPassed = utilityPassed;
details.completePayloadResolved = payloadPresent;
details.truthUsed = false;
details.futureInformationUsed = false;
details.trackingBenefitClaimed = false;
end

function validateInputs(candidate, localPosteriorBySensor, ...
        physicalAdjacency, model, minimumUtilityLowerBound, ...
        rollingConnectivityPassed)
required = { ...
    'candidateIndex', 'formationId', 'receiverIds', 'sourceId', ...
    'label', 'minimumRiskReduction', 'opportunityMedian', ...
    'minimumReceiverExistence', 'peerConsensusMedian', ...
    'receiverCompatibilityMedian'};
sensorCount = numel(localPosteriorBySensor);
if ~isstruct(candidate) || ~isscalar(candidate) || ...
        any(~isfield(candidate, required)) || ...
        ~iscell(localPosteriorBySensor) || sensorCount < 1 || ...
        ~isequal(size(physicalAdjacency), ...
            [sensorCount, sensorCount]) || ...
        ~isstruct(model) || ~isfield(model, 'xDimension') || ...
        ~isscalar(model.xDimension) || ~isfinite(model.xDimension) || ...
        model.xDimension < 1 || model.xDimension ~= round(model.xDimension) || ...
        ~validPositiveInteger(candidate.candidateIndex) || ...
        ~validPositiveInteger(candidate.formationId) || ...
        ~validPositiveInteger(candidate.sourceId) || ...
        candidate.sourceId > sensorCount || ...
        ~isequal(size(candidate.label), [2, 1]) || ...
        any(~isfinite(candidate.label)) || ...
        ~isscalar(candidate.minimumRiskReduction) || ...
        ~isfinite(candidate.minimumRiskReduction) || ...
        ~isscalar(candidate.opportunityMedian) || ...
        ~isfinite(candidate.opportunityMedian) || ...
        ~isscalar(candidate.minimumReceiverExistence) || ...
        ~isfinite(candidate.minimumReceiverExistence) || ...
        ~isscalar(candidate.peerConsensusMedian) || ...
        ~isfinite(candidate.peerConsensusMedian) || ...
        ~isscalar(candidate.receiverCompatibilityMedian) || ...
        ~isfinite(candidate.receiverCompatibilityMedian) || ...
        ~isscalar(minimumUtilityLowerBound) || ...
        ~isfinite(minimumUtilityLowerBound) || ...
        ~validBoolean(rollingConnectivityPassed)
    error('FormationRepairCandidatePayloadV190:InvalidInput', ...
        'The candidate or payload resolver input is malformed.');
end
receivers = reshape(candidate.receiverIds, 1, []);
if isempty(receivers) || any(~isfinite(receivers)) || ...
        any(receivers ~= round(receivers)) || any(receivers < 1) || ...
        any(receivers > sensorCount) || ...
        numel(unique(receivers)) ~= numel(receivers)
    error('FormationRepairCandidatePayloadV190:InvalidReceivers', ...
        'The candidate receiver set is malformed.');
end
end

function object = findLabelObject(objects, label)
object = [];
objects = reshape(objects, 1, []);
for objectIdx = 1:numel(objects)
    if objects(objectIdx).birthTime == label(1) && ...
            objects(objectIdx).birthLocation == label(2)
        object = objects(objectIdx);
        return;
    end
end
end

function proposal = emptyProposal()
proposal = struct( ...
    'formationId', 0, ...
    'receiverIds', zeros(1, 0), ...
    'sourceId', 0, ...
    'label', zeros(2, 1), ...
    'sourceObject', [], ...
    'richSynopsisBytes', 0, ...
    'requestBytes', 0, ...
    'completeResponseBytesPerReceiver', 0, ...
    'responseBytes', 0, ...
    'attemptedBytes', 0, ...
    'estimatedUtilityLowerBound', 0, ...
    'rankingOpportunity', 0, ...
    'minimumRiskReduction', 0, ...
    'minimumReceiverExistence', 0, ...
    'peerConsensus', 0, ...
    'receiverCompatibility', 1, ...
    'commonSourcePassed', false, ...
    'safetyPassed', false, ...
    'rollingConnectivityPassed', false);
end

function valid = validPositiveInteger(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value >= 1 && value == round(value);
end

function valid = validBoolean(value)
valid = isscalar(value) && ...
    (islogical(value) || (isnumeric(value) && isfinite(value) && ...
    (value == 0 || value == 1)));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
