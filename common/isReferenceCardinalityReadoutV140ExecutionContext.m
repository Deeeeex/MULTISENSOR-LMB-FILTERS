function detected = ...
        isReferenceCardinalityReadoutV140ExecutionContext(context)
% ISREFERENCECARDINALITYREADOUTV140EXECUTIONCONTEXT Identify V140 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'reference-cardinality-readout-v140-execution-context-v1');
end
