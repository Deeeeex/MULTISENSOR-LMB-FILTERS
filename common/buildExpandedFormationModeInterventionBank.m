function bank = buildExpandedFormationModeInterventionBank( ...
        projection, groupIds, options)
% BUILDEXPANDEDFORMATIONMODEINTERVENTIONBANK Local, pair, subset actions.
%
% Preserves the local-plus-pair action prefix exactly and appends the
% requested higher-order coordinated subsets.  Stable prefix indices let a
% frozen temporal sequence be replayed against an expanded repair bank.

if nargin < 3 || isempty(options)
    options = struct();
end
pairTrustWeight = getField(options, 'pairTrustWeight', 0.30);
subsetTrustWeight = getField(options, 'subsetTrustWeight', 0.30);
subsetOrders = getField(options, 'subsetOrders', []);
base = buildCombinedFormationModeInterventionBank( ...
    projection, groupIds, struct( ...
        'pairTrustWeight', pairTrustWeight));
if isempty(subsetOrders)
    subsetOrders = 3:base.formationCount;
end
subset = buildCoordinatedSubsetFormationModeInterventionBank( ...
    projection, groupIds, struct( ...
        'subsetTrustWeight', subsetTrustWeight, ...
        'subsetOrders', subsetOrders));
assertReferenceEqual(base, subset);
if base.nodeCount ~= subset.nodeCount || ...
        base.formationCount ~= subset.formationCount || ...
        base.modeCount ~= subset.modeCount || ...
        ~isequal(base.modeTrustWeights, subset.modeTrustWeights)
    error('Expanded formation bank dimensions are inconsistent.');
end

subsetNonreference = 2:subset.actionCount;
baseCount = base.actionCount;
actionCount = baseCount + numel(subsetNonreference);
formationIndexWidth = max( ...
    size(base.actionFormationIndices, 2), ...
    size(subset.actionFormationIndices, 2));
baseFormationIndices = zeros(baseCount, formationIndexWidth);
baseFormationIndices(:, 1:size( ...
    base.actionFormationIndices, 2)) = ...
        base.actionFormationIndices;
subsetFormationIndices = zeros( ...
    numel(subsetNonreference), formationIndexWidth);
subsetFormationIndices(:, 1:size( ...
    subset.actionFormationIndices, 2)) = ...
        subset.actionFormationIndices(subsetNonreference, :);

bank = struct();
bank.contractVersion = ...
    'formation-local-pair-coordinated-subset-intervention-bank-v1';
bank.nodeCount = base.nodeCount;
bank.formationCount = base.formationCount;
bank.modeCount = base.modeCount;
bank.actionCount = actionCount;
bank.referenceActionIndex = base.referenceActionIndex;
bank.baseActionCount = baseCount;
bank.localActionCount = base.localActionCount;
bank.pairActionCount = base.pairActionCount;
bank.coordinatedSubsetActionCount = numel(subsetNonreference);
bank.pairTrustWeight = pairTrustWeight;
bank.subsetTrustWeight = subsetTrustWeight;
bank.subsetOrders = subset.subsetOrders;
bank.modeTrustWeights = base.modeTrustWeights;
bank.actionNames = [ ...
    base.actionNames, subset.actionNames(subsetNonreference)];
bank.actionModes = [ ...
    base.actionModes; subset.actionModes(subsetNonreference, :)];
bank.actionFormationIndices = [ ...
    baseFormationIndices; subsetFormationIndices];
bank.actionFormationIndex = [ ...
    base.actionFormationIndex; ...
    subset.actionFormationIndex(subsetNonreference)];
bank.actionModeIndex = [ ...
    base.actionModeIndex; subset.actionModeIndex(subsetNonreference)];
bank.actionInterventionOrder = [ ...
    base.actionInterventionOrder; ...
    subset.actionInterventionOrder(subsetNonreference)];
bank.actionAdjacency = cat(3, ...
    base.actionAdjacency, ...
    subset.actionAdjacency(:, :, subsetNonreference));
bank.actionFusionWeights = cat(3, ...
    base.actionFusionWeights, ...
    subset.actionFusionWeights(:, :, subsetNonreference));
bank.actionDominantSources = [ ...
    base.actionDominantSources; ...
    subset.actionDominantSources(subsetNonreference, :)];
bank.actionPosteriorProxyAllowed = [ ...
    base.actionPosteriorProxyAllowed; ...
    subset.actionPosteriorProxyAllowed(subsetNonreference)];
bank.actionPosteriorObjective = [ ...
    base.actionPosteriorObjective; ...
    subset.actionPosteriorObjective(subsetNonreference)];
bank.actionPayloadBytes = [ ...
    base.actionPayloadBytes; ...
    subset.actionPayloadBytes(subsetNonreference)];
bank.referencePayloadBytes = base.referencePayloadBytes;
bank.actionWithinReferencePayload = [ ...
    base.actionWithinReferencePayload; ...
    subset.actionWithinReferencePayload(subsetNonreference)];
bank.truthUsed = false;
bank.futureOutcomeUsed = false;
bank.trainingTargetStored = false;

if numel(bank.actionNames) ~= actionCount || ...
        size(bank.actionAdjacency, 3) ~= actionCount || ...
        size(bank.actionFusionWeights, 3) ~= actionCount || ...
        size(bank.actionFormationIndices, 1) ~= actionCount || ...
        ~isequal(bank.actionNames(1:baseCount), base.actionNames) || ...
        ~isequal(bank.actionModes(1:baseCount, :), base.actionModes)
    error('Expanded formation bank enumeration is incomplete.');
end
end

function assertReferenceEqual(base, subset)
fields = { ...
    'actionAdjacency', 'actionFusionWeights', ...
    'actionDominantSources', 'actionPayloadBytes'};
for idx = 1:numel(fields)
    name = fields{idx};
    if ndims(base.(name)) == 3
        baseValue = base.(name)(:, :, base.referenceActionIndex);
        subsetValue = subset.(name)(:, :, subset.referenceActionIndex);
    elseif ismatrix(base.(name)) && ...
            size(base.(name), 1) == base.actionCount
        baseValue = base.(name)(base.referenceActionIndex, :);
        subsetValue = subset.(name)(subset.referenceActionIndex, :);
    else
        baseValue = base.(name)(base.referenceActionIndex);
        subsetValue = subset.(name)(subset.referenceActionIndex);
    end
    if ~isequaln(baseValue, subsetValue)
        error('Expanded formation bank reference mismatch in %s.', name);
    end
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
