function context = ...
        buildHierarchicalDelayedValueCollectionV213ExecutionContext( ...
            presetName, seed, phase, currentTime, ...
            measurementTimeCount, actionName, scheduleEnabled, ...
            onlineReselectionEnabled, repairPlan)
% BUILDHIERARCHICALDELAYEDVALUECOLLECTIONV213EXECUTIONCONTEXT Scope V213.

if nargin < 9 || isempty(repairPlan)
    repairPlan = struct();
end
protocol = getHierarchicalDelayedValueControllerV213Protocol();
base = getOnlinePositiveNetAddressablePayloadV99Protocol();
if ~ischar(presetName) || isempty(presetName) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~ischar(phase) || isempty(phase) || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || currentTime < 1 || ...
        ~isscalar(measurementTimeCount) || ...
        ~isfinite(measurementTimeCount) || ...
        measurementTimeCount ~= round(measurementTimeCount) || ...
        measurementTimeCount < currentTime || ...
        ~ischar(actionName) || isempty(actionName) || ...
        ~isscalar(scheduleEnabled) || ...
        ~(islogical(scheduleEnabled) || isnumeric(scheduleEnabled)) || ...
        ~isscalar(onlineReselectionEnabled) || ...
        ~(islogical(onlineReselectionEnabled) || ...
            isnumeric(onlineReselectionEnabled)) || ...
        ~isstruct(repairPlan) || ~isscalar(repairPlan)
    error('HierarchicalDelayedValueV213:InvalidExecutionContext', ...
        'The V213 collection execution-context input is invalid.');
end

context = struct();
context.contractVersion = ...
    'hierarchical-delayed-value-collection-v213-context-v1';
context.capability = ...
    'hierarchical-delayed-value-collection-v213-development';
context.action = ...
    'filter-hierarchical-delayed-value-collection-v213-development';
context.protocolId = protocol.id;
context.phase = phase;
context.presetName = presetName;
context.seed = seed;
context.currentTime = currentTime;
context.measurementTimeCount = measurementTimeCount;
context.policyName = base.outcomePolicyName;
context.actionName = actionName;
context.scheduleEnabled = logical(scheduleEnabled);
context.onlineReselectionEnabled = logical(onlineReselectionEnabled);
context.budgetRecycledFormationRepairPlan = repairPlan;
context.developmentEvidenceOnly = true;
end
