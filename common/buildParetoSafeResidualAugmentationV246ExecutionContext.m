function context = ...
        buildParetoSafeResidualAugmentationV246ExecutionContext( ...
            presetName, seed, measurementTimeCount)
% BUILDPARETOSAFERESIDUALAUGMENTATIONV246EXECUTIONCONTEXT Development run.

protocol = getParetoSafeResidualAugmentationV246Protocol();
if ~ischar(presetName) || ...
        ~ismember(presetName, protocol.allowedPresets) || ...
        ~ismember(seed, protocol.allowedSeeds) || ...
        ~isscalar(measurementTimeCount) || ...
        ~isfinite(measurementTimeCount) || ...
        measurementTimeCount < 1 || ...
        measurementTimeCount ~= round(measurementTimeCount)
    error('ParetoSafeResidualV246:InvalidExecutionContextInput', ...
        'V246 requires a registered scene, seed and time axis.');
end
context = struct();
context.contractVersion = ...
    'pareto-safe-residual-augmentation-v246-context-v1';
context.capability = ...
    'pareto-safe-residual-augmentation-v246-development';
context.action = ...
    'filter-pareto-safe-residual-augmentation-v246-development';
context.protocolId = protocol.id;
context.presetName = presetName;
context.seed = seed;
context.armId = protocol.armId;
context.measurementTimeCount = measurementTimeCount;
context.policyName = protocol.policyName;
context.developmentEvidenceOnly = true;
end
