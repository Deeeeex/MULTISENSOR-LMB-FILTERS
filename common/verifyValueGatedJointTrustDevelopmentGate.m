function development = verifyValueGatedJointTrustDevelopmentGate(protocol)
% VERIFYVALUEGATEDJOINTTRUSTDEVELOPMENTGATE Bind validation to frozen v9.

if nargin < 1 || isempty(protocol)
    protocol = getLabelSetSimulatorPolicyProtocol();
end
path = protocol. ...
    valueGatedFormationFovValidationDevelopmentSummaryPath;
if exist(path, 'file') ~= 2 || ...
        ~strcmp(computeFileSha256(path), protocol. ...
            valueGatedFormationFovValidationDevelopmentSummarySha256)
    error('FormationFovValidation:DevelopmentEvidenceMismatch', ...
        'Frozen v9 development evidence is missing or has changed.');
end
loaded = load(path, 'development');
if ~isfield(loaded, 'development')
    error('FormationFovValidation:DevelopmentEvidenceMismatch', ...
        'Frozen v9 development summary is missing.');
end
development = loaded.development;
requiredFields = { ...
    'contractVersion', 'developmentGatePassed', ...
    'openedDevelopmentEvidenceOnly', 'validationClaimAllowed', ...
    'candidate'};
if ~all(isfield(development, requiredFields)) || ...
        ~strcmp(development.contractVersion, protocol. ...
            adaptiveDominantJointTrustStabilityContractVersion) || ...
        ~development.developmentGatePassed || ...
        ~development.openedDevelopmentEvidenceOnly || ...
        development.validationClaimAllowed || ...
        ~isfield(development.candidate, 'hardSafetyPassed') || ...
        ~development.candidate.hardSafetyPassed || ...
        development.candidate.meanGainPercent < protocol. ...
            adaptiveDominantJointTrustStabilityMinimumMeanGainPercent || ...
        development.candidate.positiveSeedFraction < protocol. ...
            adaptiveDominantJointTrustStabilityMinimumPositiveSeedFraction
    error('FormationFovValidation:DevelopmentGateNotPassed', ...
        'Frozen v9 evidence does not authorize fresh validation.');
end
end
