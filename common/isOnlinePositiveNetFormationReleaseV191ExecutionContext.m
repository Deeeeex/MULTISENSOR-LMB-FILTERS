function detected = ...
        isOnlinePositiveNetFormationReleaseV191ExecutionContext(context)
% ISONLINEPOSITIVENETFORMATIONRELEASEV191EXECUTIONCONTEXT Identify V191.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'online-positive-net-formation-release-v191-context-v1');
end
