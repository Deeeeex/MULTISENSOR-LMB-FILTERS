function context = ...
        buildBudgetedLocalGatewayTeacherV255ExecutionContext( ...
            presetName, seed, measurementTimeCount, phase, ...
            anchorTime, candidateIndex)
% BUILDBUDGETEDLOCALGATEWAYTEACHERV255EXECUTIONCONTEXT Paired local data.

protocol = getBudgetedLocalGatewayTeacherV255Protocol();
source = getCausalMinimumFormationBackboneV242Protocol();
action = getCausalGatewayEmbeddingV250Protocol();
validPhase = ischar(phase) && any(strcmp(phase, { ...
    'reference-prefix', 'candidate-reference', 'candidate-action'}));
validCommon = ischar(presetName) && ...
    ismember(presetName, protocol.allowedPresets) && ...
    ismember(seed, protocol.allowedSeeds) && ...
    isscalar(measurementTimeCount) && ...
    isfinite(measurementTimeCount) && ...
    measurementTimeCount >= 1 && ...
    measurementTimeCount == round(measurementTimeCount) && ...
    isscalar(anchorTime) && isfinite(anchorTime) && ...
    isscalar(candidateIndex) && isfinite(candidateIndex) && ...
    candidateIndex == round(candidateIndex);
if ~validPhase || ~validCommon
    error('BudgetedLocalGatewayTeacherV255:InvalidContextInput', ...
        'V255 requires a registered seed, phase and time axis.');
end

switch phase
    case 'reference-prefix'
        validSpecific = anchorTime == 0 && candidateIndex == 1 && ...
            measurementTimeCount == max(protocol.anchorTimes);
        policyName = source.policyName;
        armId = source.armId;
    case 'candidate-reference'
        validSpecific = ismember(anchorTime, protocol.anchorTimes) && ...
            candidateIndex == 1 && measurementTimeCount == ...
                anchorTime + protocol.horizonSteps - 1;
        policyName = source.policyName;
        armId = source.armId;
    otherwise
        validSpecific = ismember(anchorTime, protocol.anchorTimes) && ...
            candidateIndex >= 2 && ...
            candidateIndex <= protocol.maximumRestrictedCandidateCount && ...
            measurementTimeCount == ...
                anchorTime + protocol.horizonSteps - 1;
        policyName = action.policyName;
        armId = protocol.armId;
end
if ~validSpecific
    error('BudgetedLocalGatewayTeacherV255:InvalidContextPhase', ...
        'The V255 phase does not match its anchor or candidate index.');
end

context = struct();
context.contractVersion = ...
    'budgeted-local-gateway-teacher-v255-context-v1';
context.capability = ...
    'budgeted-local-gateway-teacher-v255-development';
context.action = ...
    'filter-budgeted-local-gateway-teacher-v255-development';
context.protocolId = protocol.id;
context.presetName = presetName;
context.seed = seed;
context.seedRole = seedRole(protocol, seed);
context.armId = armId;
context.measurementTimeCount = measurementTimeCount;
context.phase = phase;
context.anchorTime = anchorTime;
context.candidateIndex = candidateIndex;
context.policyName = policyName;
context.developmentEvidenceOnly = true;
end

function role = seedRole(protocol, seed)
if ismember(seed, protocol.additionalTrainingSeeds)
    role = 'additional-training';
elseif ismember(seed, protocol.calibrationSeeds)
    role = 'calibration';
elseif ismember(seed, protocol.developmentHoldoutSeeds)
    role = 'development-holdout';
else
    error('BudgetedLocalGatewayTeacherV255:UnknownSeedRole', ...
        'The V255 seed has no registered evidence role.');
end
end
