function [adjacency, details] = ...
    selectRollingSafeReferencePreferredSwitchPolicy( ...
        context, candidateActionCode, referenceActionCode, options)
% SELECTROLLINGSAFEREFERENCEPREFERREDSWITCHPOLICY Causal safe switch.
%
% At every call, both the candidate action and the registered reference
% action are recomputed from the same current posterior, physical graph and
% selected-topology history.  The reference is preferred whenever it can
% be executed by the nominal rolling-safe projection.  Otherwise, the
% candidate is selected only if its own nominal projection is repair-free.
% If neither action is nominal-free, the controller fails closed.
%
% This is deliberately a switching policy rather than an absorbing
% termination rule: a later state may require switching back from the
% reference to the candidate.  No future geometry or outcome is inspected.

if nargin < 4 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
if ~protocol.rollingSafeReferencePreferredSwitchAuthorized || ...
        ~protocol.rollingSafeReferencePreferredSwitchRequireStrictNominalFree || ...
        ~protocol.rollingSafeReferencePreferredSwitchRequireExactMessageBudget || ...
        ~protocol.rollingSafeReferencePreferredSwitchRequireMatureReserveAudit || ...
        protocol.rollingSafeReferencePreferredSwitchAbsorbingExitClaimed || ...
        protocol.rollingSafeReferencePreferredSwitchTruthUsed || ...
        protocol.rollingSafeReferencePreferredSwitchFutureOutcomeUsed
    error('RollingSafeReferenceSwitch:Unauthorized', ...
        'Reference-preferred switching is not authorized.');
end
candidateActionCode = validateActionCode( ...
    candidateActionCode, protocol, 'candidateActionCode');
referenceActionCode = validateActionCode( ...
    referenceActionCode, protocol, 'referenceActionCode');
if referenceActionCode ~= ...
        protocol.rollingSafeReferencePreferredSwitchReferenceActionCode
    error('RollingSafeReferenceSwitch:ReferenceDrift', ...
        'The reference action code differs from the frozen contract.');
end
if ~isstruct(context) || ~isfield(context, 'currentTime') || ...
        ~isscalar(context.currentTime) || ...
        ~isfinite(context.currentTime) || ...
        context.currentTime ~= round(context.currentTime)
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The switching context lacks a valid current time.');
end
if ~strcmp(protocol.rollingSafeReferencePreferredSwitchEvaluationOrder, ...
        'candidate-then-reference')
    error('RollingSafeReferenceSwitch:EvaluationOrderDrift', ...
        'The registered alternative-evaluation order changed.');
end

timerId = tic;
candidate = evaluateAlternative( ...
    context, candidateActionCode, options, protocol);
if candidateActionCode == referenceActionCode
    reference = candidate;
else
    reference = evaluateAlternative( ...
        context, referenceActionCode, options, protocol);
end

if reference.nominalFree
    selected = reference;
    selectedActionCode = referenceActionCode;
    selectedCandidate = false;
    decisionReason = 'reference-nominal-free';
elseif candidate.nominalFree
    selected = candidate;
    selectedActionCode = candidateActionCode;
    selectedCandidate = true;
    decisionReason = ...
        'reference-not-nominal-free-candidate-selected';
else
    error('RollingSafeReferenceSwitch:NoNominalFreeAction', ...
        ['Neither candidate code %d nor reference code %d has a ', ...
         'strict nominal-free rolling-safe projection at t=%d ', ...
         '(candidate=%s, reference=%s).'], ...
        candidateActionCode, referenceActionCode, ...
        context.currentTime, statusToken(candidate), ...
        statusToken(reference));
end

adjacency = selected.adjacency;
details = selected.details;
details.selectionSeconds = toc(timerId);
details.referenceSwitchContractVersion = ...
    protocol.rollingSafeReferencePreferredSwitchContractVersion;
details.referenceSwitchApplied = true;
details.referenceSwitchSelectedCandidate = selectedCandidate;
details.referenceSwitchCandidateActionCode = candidateActionCode;
details.referenceSwitchReferenceActionCode = referenceActionCode;
details.referenceSwitchSelectedActionCode = selectedActionCode;
details.referenceSwitchCandidateAvailable = candidate.available;
details.referenceSwitchReferenceAvailable = reference.available;
details.referenceSwitchCandidateNominalFree = candidate.nominalFree;
details.referenceSwitchReferenceNominalFree = reference.nominalFree;
details.referenceSwitchCandidateRequestedActionRealized = ...
    candidate.requestedActionRealized;
details.referenceSwitchReferenceRequestedActionRealized = ...
    reference.requestedActionRealized;
details.referenceSwitchCandidateAttestation = ...
    candidate.attestation;
details.referenceSwitchReferenceAttestation = ...
    reference.attestation;
details.referenceSwitchCandidateFailureIdentifier = ...
    candidate.failureIdentifier;
details.referenceSwitchReferenceFailureIdentifier = ...
    reference.failureIdentifier;
details.referenceSwitchCandidateAdjacencySha256 = ...
    candidate.adjacencySha256;
details.referenceSwitchReferenceAdjacencySha256 = ...
    reference.adjacencySha256;
details.referenceSwitchSelectedAdjacencySha256 = ...
    selected.adjacencySha256;
details.referenceSwitchCandidateFusionWeightSha256 = ...
    candidate.fusionWeightSha256;
details.referenceSwitchReferenceFusionWeightSha256 = ...
    reference.fusionWeightSha256;
details.referenceSwitchSelectedFusionWeightSha256 = ...
    selected.fusionWeightSha256;
details.referenceSwitchCandidateSelectionSeconds = ...
    candidate.selectionSeconds;
details.referenceSwitchReferenceSelectionSeconds = ...
    reference.selectionSeconds;
details.referenceSwitchAlternativeGraphEqual = ...
    candidate.available && reference.available && ...
    isequal(candidate.adjacency, reference.adjacency);
if candidate.available && reference.available
    details.referenceSwitchAlternativeGraphHammingDistance = ...
        nnz(xor(candidate.adjacency, reference.adjacency));
else
    details.referenceSwitchAlternativeGraphHammingDistance = NaN;
end
details.referenceSwitchContextSha256 = ...
    computeSwitchContextSha256( ...
        context, candidateActionCode, referenceActionCode, ...
        options, protocol);
details.referenceSwitchHistorySha256 = computeTextSha256( ...
    serializeHashValue(context.previousAdjacencyHistory));
details.referenceSwitchPhysicalAdjacencySha256 = computeTextSha256( ...
    serializeHashValue(logical(context.physicalAdjacency)));
details.referenceSwitchDecisionReason = decisionReason;
details.referenceSwitchEvaluationOrder = ...
    protocol.rollingSafeReferencePreferredSwitchEvaluationOrder;
details.referenceSwitchAlternativeTruthUsed = false;
details.referenceSwitchFutureOutcomeUsed = false;
details.referenceSwitchAbsorbingExit = false;
details.truthUsed = false;
details.actionSequenceTruthUsed = false;
end

function alternative = evaluateAlternative( ...
        context, actionCode, options, protocol)
alternative = emptyAlternative();
try
    [adjacency, details] = ...
        selectRollingSafeActionSequencePolicy( ...
            context, actionCode, context.currentTime, options);
    assertTruthFreeRollingSafePolicyDetails(details);
    validateAlternativeExecution( ...
        adjacency, details, actionCode, context, protocol);
catch errorInfo
    if ~isExpectedRollingSafeReferenceSwitchAlternativeUnavailable( ...
            errorInfo, actionCode, protocol)
        rethrow(errorInfo);
    end
    alternative.failureIdentifier = errorInfo.identifier;
    alternative.failureMessage = errorInfo.message;
    return;
end
alternative.adjacency = logical(adjacency);
alternative.details = details;
alternative.attestation = buildRollingSafeReferenceSwitchAttestation( ...
    alternative.adjacency, details, actionCode, ...
    logical(context.physicalAdjacency));
rawAudit = auditRollingSafeReferenceSwitchAttestation( ...
    alternative.attestation, actionCode);
if ~rawAudit.available
    error('RollingSafeReferenceSwitch:InvalidAlternativeSafety', ...
        'An evaluated alternative is not independently available.');
end
alternative.available = true;
alternative.nominalFree = rawAudit.strictNominalFree;
alternative.requestedActionRealized = ...
    rawAudit.requestedActionRealized;
alternative.adjacencySha256 = computeTextSha256( ...
    serializeHashValue(alternative.adjacency));
alternative.fusionWeightSha256 = computeTextSha256( ...
    serializeHashValue(details.fusionWeightMatrix));
alternative.selectionSeconds = details.selectionSeconds;
end

function validateAlternativeExecution( ...
        adjacency, details, actionCode, context, protocol)
nodeCount = numel(context.localPosteriorBySensor);
if ~(isnumeric(adjacency) || islogical(adjacency)) || ...
        ~isreal(adjacency) || ...
        ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        any(~isfinite(adjacency(:))) || ...
        any(adjacency(:) ~= 0 & adjacency(:) ~= 1)
    error('RollingSafeReferenceSwitch:InvalidAlternative', ...
        'An alternative returned a non-binary adjacency.');
end
adjacency = logical(adjacency);
physical = context.physicalAdjacency;
if ~(isnumeric(physical) || islogical(physical)) || ...
        ~isreal(physical) || ...
        ~isequal(size(physical), [nodeCount, nodeCount]) || ...
        any(~isfinite(physical(:))) || ...
        any(physical(:) ~= 0 & physical(:) ~= 1)
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The switching context has a non-binary physical adjacency.');
end
physical = logical(physical);
if any(diag(adjacency)) || any(sum(adjacency, 2) ~= 1) || ...
        nnz(adjacency) ~= nodeCount || ...
        any(adjacency(:) & ~physical(:))
    error('RollingSafeReferenceSwitch:InvalidAlternative', ...
        'An alternative violates the exact one-source route contract.');
end
if protocol.rollingSafeReferencePreferredSwitchRequireExactMessageBudget && ...
        (~isfield(context, 'directedMessageBudget') || ...
         context.directedMessageBudget ~= nodeCount || ...
         nodeCount ~= protocol.rollingSafeCausalOptionMessageBudget)
    error('RollingSafeReferenceSwitch:MessageBudgetDrift', ...
        'The exact directed-message budget changed.');
end
requiredFields = { ...
    'actionSequenceCode', 'actionSequenceRelativeTime', ...
    'messageCount', 'fusionWeightMatrix', 'sourceWeight', ...
    'selectedSourcesByReceiver', ...
    'nominalProjectionFeasible', 'repairProjectionAttempted', ...
    'repairTriggered', 'payloadEmergencyUsed', ...
    'payloadLimitPassed', 'topologyInfeasible', ...
    'sensorWindowStrongConnected', ...
    'formationWindowStrongConnected', ...
    'successorSensorStrongConnected', ...
    'successorFormationStrongConnected', ...
    'oneStepTopologyReserveChecked', ...
    'oneStepTopologyReservePassed'};
if ~isstruct(details) || ~all(isfield(details, requiredFields))
    error('RollingSafeReferenceSwitch:InvalidAlternativeDiagnostics', ...
        'An alternative lacks strict safety diagnostics.');
end
if details.actionSequenceCode ~= actionCode || ...
        details.actionSequenceRelativeTime ~= 1 || ...
        details.messageCount ~= nodeCount
    error('RollingSafeReferenceSwitch:ActionIdentityDrift', ...
        'An alternative did not execute the requested current action.');
end
assertRollingSafeReferenceSwitchActionRealized(details, actionCode);
binaryFields = { ...
    'nominalProjectionFeasible', 'repairProjectionAttempted', ...
    'repairTriggered', 'payloadEmergencyUsed', ...
    'payloadLimitPassed', 'topologyInfeasible', ...
    'sensorWindowStrongConnected', ...
    'formationWindowStrongConnected', ...
    'successorSensorStrongConnected', ...
    'successorFormationStrongConnected', ...
    'oneStepTopologyReserveChecked', ...
    'oneStepTopologyReservePassed'};
for fieldIdx = 1:numel(binaryFields)
    fieldName = binaryFields{fieldIdx};
    requireFiniteBinaryDiagnostic( ...
        details.(fieldName), 1, fieldName);
end
if protocol.rollingSafeReferencePreferredSwitchRequireMatureReserveAudit && ...
        (~logical(details.oneStepTopologyReserveChecked) || ...
         ~logical(details.oneStepTopologyReservePassed))
    error('RollingSafeReferenceSwitch:ImmatureReserveAudit', ...
        'An alternative lacks a mature passing one-step reserve audit.');
end
if ~logical(details.sensorWindowStrongConnected) || ...
        ~logical(details.formationWindowStrongConnected) || ...
        ~logical(details.successorSensorStrongConnected) || ...
        ~logical(details.successorFormationStrongConnected) || ...
        ~logical(details.payloadLimitPassed) || ...
        logical(details.topologyInfeasible)
    error('RollingSafeReferenceSwitch:InvalidAlternativeSafety', ...
        'An alternative failed a selected-topology safety invariant.');
end
weights = details.fusionWeightMatrix;
sourceWeight = details.sourceWeight;
registeredSourceWeight = ...
    protocol.rollingSafeCausalOptionSourceWeight;
selectedSources = reshape(details.selectedSourcesByReceiver, [], 1);
if ~isscalar(sourceWeight) || ~isfinite(sourceWeight) || ...
        sourceWeight ~= registeredSourceWeight || ...
        numel(selectedSources) ~= nodeCount || ...
        any(~isfinite(selectedSources)) || ...
        any(selectedSources ~= round(selectedSources)) || ...
        any(selectedSources < 1) || any(selectedSources > nodeCount)
    error('RollingSafeReferenceSwitch:InvalidFusionWeights', ...
        'An alternative changed the registered source-weight contract.');
end
expectedAdjacency = false(nodeCount);
expectedAdjacency(sub2ind([nodeCount, nodeCount], ...
    (1:nodeCount)', selectedSources)) = true;
expectedWeights = eye(nodeCount);
expectedWeights(1:(nodeCount + 1):end) = 1 - registeredSourceWeight;
expectedWeights(sub2ind([nodeCount, nodeCount], ...
    (1:nodeCount)', selectedSources)) = registeredSourceWeight;
if ~isequal(expectedAdjacency, adjacency) || ...
        ~isnumeric(weights) || ~isreal(weights) || ...
        ~isequal(size(weights), [nodeCount, nodeCount]) || ...
        any(~isfinite(weights(:))) || any(weights(:) < 0) || ...
        ~isequal(weights, expectedWeights)
    error('RollingSafeReferenceSwitch:InvalidFusionWeights', ...
        ['An alternative did not execute the exact registered ', ...
         '0.30/0.70 fusion weights on its selected sources.']);
end
end

function actionCode = validateActionCode(actionCode, protocol, fieldName)
if ~isscalar(actionCode) || ~isfinite(actionCode) || ...
        actionCode ~= round(actionCode) || ...
        ~ismember(actionCode, ...
            protocol.rollingSafeSparseTruthFreeActionCodes)
    error('RollingSafeReferenceSwitch:InvalidActionCode', ...
        '%s is not a registered truth-free action code.', fieldName);
end
actionCode = round(actionCode);
end

function alternative = emptyAlternative()
alternative = struct( ...
    'available', false, ...
    'nominalFree', false, ...
    'requestedActionRealized', false, ...
    'adjacency', [], ...
    'details', struct(), ...
    'attestation', struct([]), ...
    'adjacencySha256', '', ...
    'fusionWeightSha256', '', ...
    'selectionSeconds', NaN, ...
    'failureIdentifier', '', ...
    'failureMessage', '');
end

function sha256 = computeSwitchContextSha256( ...
        context, candidateActionCode, referenceActionCode, ...
        options, protocol)
requiredFields = { ...
    'currentTime', 'physicalAdjacency', 'positions', ...
    'commConfig', 'model', 'directedMessageBudget', ...
    'previousAdjacency', ...
    'previousAdjacencyHistory', 'previousAdjacencyHistoryTimes', ...
    'localPosteriorBySensor', 'localInnovationHistory', ...
    'localAssociationConfidenceHistory', ...
    'localNisNormHistory', 'localNisDeviationHistory', ...
    'localUpdateHistoryTimes'};
if ~all(isfield(context, requiredFields)) || ...
        ~isstruct(context.model) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds')
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The switching context lacks fields required for provenance.');
end
nodeCount = numel(context.localPosteriorBySensor);
previousAdjacency = requireCanonicalPreviousAdjacency( ...
    context, nodeCount);
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
if numel(groupIds) ~= nodeCount || any(~isfinite(groupIds)) || ...
        any(groupIds ~= round(groupIds))
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The switching context has invalid formation identifiers.');
end
modelInputs = struct( ...
    'xDimension', getField(context.model, 'xDimension', NaN), ...
    'existenceThreshold', getField( ...
        context.model, 'existenceThreshold', NaN), ...
    'sensorCommRange', getField( ...
        context.model, 'sensorCommRange', NaN), ...
    'ospaPositionScale', resolveOspaPositionScale(context.model), ...
    'targetCapacity', resolveSwitchTargetCapacity(context.model));
scoreOptions = getField(options, 'scoreOptions', struct());
optionInputs = struct( ...
    'sourceWeight', getField(options, 'sourceWeight', 0.70), ...
    'payloadToleranceFraction', getField( ...
        options, 'payloadToleranceFraction', inf), ...
    'fallbackActionCode', getField(options, 'fallbackActionCode', []), ...
    'solverTimeLimitSeconds', getField( ...
        options, 'solverTimeLimitSeconds', 10), ...
    'reliabilityWeight', getField(options, 'reliabilityWeight', 1.0), ...
    'qualityWeight', getField(options, 'qualityWeight', 0.5), ...
    'discrepancyWeight', getField( ...
        options, 'discrepancyWeight', 0.25), ...
    'scoreSourceWeight', getField(scoreOptions, 'sourceWeight', NaN), ...
    'scoreHorizonSteps', getField(scoreOptions, 'horizonSteps', []), ...
    'scoreDiscountFactor', getField( ...
        scoreOptions, 'discountFactor', NaN));
decisionInputs = struct( ...
    'hashContractVersion', ...
        'reference-preferred-switch-decision-inputs-v2', ...
    'switchContractVersion', protocol. ...
        rollingSafeReferencePreferredSwitchContractVersion, ...
    'evaluationOrder', protocol. ...
        rollingSafeReferencePreferredSwitchEvaluationOrder, ...
    'candidateActionCode', candidateActionCode, ...
    'referenceActionCode', referenceActionCode, ...
    'currentTime', context.currentTime, ...
    'directedMessageBudget', context.directedMessageBudget, ...
    'physicalAdjacency', context.physicalAdjacency, ...
    'positions', context.positions, ...
    'formationGroupIds', groupIds, ...
    'currentDropProbabilityBySenderReceiver', ...
        resolveCurrentDropMatrix( ...
            context.commConfig, context.currentTime, nodeCount), ...
    'previousAdjacency', previousAdjacency, ...
    'previousAdjacencyHistory', context.previousAdjacencyHistory, ...
    'previousAdjacencyHistoryTimes', ...
        context.previousAdjacencyHistoryTimes, ...
    'localPosteriorBySensor', context.localPosteriorBySensor, ...
    'localInnovationHistory', context.localInnovationHistory, ...
    'localAssociationConfidenceHistory', ...
        context.localAssociationConfidenceHistory, ...
    'localNisNormHistory', context.localNisNormHistory, ...
    'localNisDeviationHistory', context.localNisDeviationHistory, ...
    'localUpdateHistoryTimes', context.localUpdateHistoryTimes, ...
    'modelInputs', modelInputs, ...
    'optionInputs', optionInputs);
sha256 = computeTextSha256(serializeHashValue(decisionInputs));
end

function matrix = resolveCurrentDropMatrix(config, currentTime, nodeCount)
if ~isstruct(config)
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The switching communication configuration is invalid.');
end
matrix = zeros(nodeCount);
for senderIdx = 1:nodeCount
    for receiverIdx = 1:nodeCount
        if isfield(config, 'pDropByEdge') && ...
                ~isempty(config.pDropByEdge)
            if ndims(config.pDropByEdge) >= 3
                timeIdx = min(currentTime, ...
                    size(config.pDropByEdge, 3));
                value = config.pDropByEdge( ...
                    senderIdx, receiverIdx, timeIdx);
            else
                value = config.pDropByEdge(senderIdx, receiverIdx);
            end
        elseif isfield(config, 'pDropBySensor') && ...
                numel(config.pDropBySensor) >= senderIdx
            value = config.pDropBySensor(senderIdx);
        else
            value = 0;
        end
        if ~isscalar(value) || ~isfinite(value)
            error('RollingSafeReferenceSwitch:InvalidContext', ...
                'The current link-drop matrix is invalid.');
        end
        matrix(senderIdx, receiverIdx) = min(max(value, 0), 1);
    end
end
end

function value = resolveOspaPositionScale(model)
value = 100;
if isfield(model, 'ospaParameters') && ...
        isstruct(model.ospaParameters) && ...
        isfield(model.ospaParameters, 'eC')
    value = model.ospaParameters.eC;
end
end

function previous = requireCanonicalPreviousAdjacency(context, nodeCount)
previous = context.previousAdjacency;
if ~(isnumeric(previous) || islogical(previous)) || ...
        ~isreal(previous) || ...
        ~isequal(size(previous), [nodeCount, nodeCount]) || ...
        any(~isfinite(previous(:))) || ...
        any(previous(:) ~= 0 & previous(:) ~= 1)
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The previous adjacency must be a finite binary square matrix.');
end
previous = logical(previous);
history = context.previousAdjacencyHistory;
if ~(isnumeric(history) || islogical(history)) || ~isreal(history) || ...
        size(history, 1) ~= nodeCount || size(history, 2) ~= nodeCount || ...
        any(~isfinite(history(:))) || ...
        any(history(:) ~= 0 & history(:) ~= 1)
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        'The selected-topology history is not finite binary evidence.');
end
if ~isempty(history) && ...
        ~isequal(previous, logical(history(:, :, end)))
    error('RollingSafeReferenceSwitch:InvalidContext', ...
        ['previousAdjacency disagrees with the last selected-topology ', ...
         'history page.']);
end
end

function count = resolveSwitchTargetCapacity(model)
count = 0;
if isfield(model, 'birthTimeByLocation')
    count = numel(model.birthTimeByLocation);
elseif isfield(model, 'dynamicTopologyScenario') && ...
        isfield(model.dynamicTopologyScenario, 'config') && ...
        isfield(model.dynamicTopologyScenario.config, 'numberOfTargets')
    count = model.dynamicTopologyScenario.config.numberOfTargets;
elseif isfield(model, 'birthParameters')
    count = numel(model.birthParameters);
end
if ~isscalar(count) || ~isfinite(count) || count < 1
    count = 1;
end
end

function text = serializeHashValue(value)
if isnumeric(value) || islogical(value)
    if ~isreal(value)
        error('RollingSafeReferenceSwitch:UnhashableContext', ...
            'Complex context values are not supported.');
    end
    sizeText = sprintf('%d,', size(value));
    if islogical(value)
        valueText = sprintf('%d,', value(:));
    else
        valueText = sprintf('%.17g,', value(:));
    end
    text = sprintf('%s:%s:%s', class(value), sizeText, valueText);
elseif ischar(value)
    text = sprintf('char:%d:%s', numel(value), value);
elseif iscell(value)
    parts = cell(1, numel(value) + 1);
    parts{1} = sprintf('cell:%s:', sprintf('%d,', size(value)));
    for valueIdx = 1:numel(value)
        parts{valueIdx + 1} = [ ...
            serializeHashValue(value{valueIdx}), '|'];
    end
    text = [parts{:}];
elseif isstruct(value)
    names = sort(fieldnames(value));
    parts = cell(1, 1 + numel(value) * numel(names));
    parts{1} = sprintf('struct:%s:%s:', ...
        sprintf('%d,', size(value)), strjoin(names, ','));
    partIdx = 1;
    for valueIdx = 1:numel(value)
        for fieldIdx = 1:numel(names)
            partIdx = partIdx + 1;
            fieldName = names{fieldIdx};
            parts{partIdx} = [fieldName, '=', ...
                serializeHashValue(value(valueIdx).(fieldName)), '|'];
        end
    end
    text = [parts{1:partIdx}];
else
    error('RollingSafeReferenceSwitch:UnhashableContext', ...
        'Unsupported switching-context value class: %s.', class(value));
end
end

function token = statusToken(alternative)
if alternative.nominalFree
    token = 'nominal-free';
elseif alternative.available
    token = 'available-but-not-nominal-free';
elseif isempty(alternative.failureIdentifier)
    token = 'unavailable';
else
    token = alternative.failureIdentifier;
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
