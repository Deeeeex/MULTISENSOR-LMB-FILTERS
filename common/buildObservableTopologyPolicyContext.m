function [commConfig, source] = buildCurrentCommunicationPage( ...
        fullConfig, sensorCount, currentTime)
if ~isstruct(fullConfig) || ~isscalar(fullConfig) || ...
        sensorCount < 1
    error('ObservableTopologyContext:InvalidCommunication', ...
        'The full communication configuration is malformed.');
end
if isfield(fullConfig, 'pDropByEdge') && ...
        ~isempty(fullConfig.pDropByEdge)
    pDrop = fullConfig.pDropByEdge;
    if ndims(pDrop) > 3 || ...
            size(pDrop, 1) ~= sensorCount || ...
            size(pDrop, 2) ~= sensorCount
        error('ObservableTopologyContext:InvalidCommunication', ...
            'pDropByEdge has an invalid shape.');
    end
    if ndims(pDrop) == 3
        pageIdx = min(currentTime, size(pDrop, 3));
        pDrop = pDrop(:, :, pageIdx);
    end
    source = 'current-pDropByEdge-page';
elseif isfield(fullConfig, 'pDropBySensor') && ...
        numel(fullConfig.pDropBySensor) == sensorCount
    rates = reshape(fullConfig.pDropBySensor, [], 1);
    pDrop = repmat(rates, 1, sensorCount);
    source = 'current-pDropBySensor-expanded-page';
else
    pDrop = zeros(sensorCount);
    source = 'zero-fallback-page';
end
if ~isa(pDrop, 'double') || ...
        ~isequal(size(pDrop), [sensorCount, sensorCount]) || ...
        any(~isfinite(pDrop(:)))
    error('ObservableTopologyContext:InvalidCommunication', ...
        'The current drop-probability page is invalid.');
end
commConfig = struct('pDropByEdge', min(max(pDrop, 0), 1));
end

function triggerConfig = sanitizeTriggerConfig( ...
        fullConfig, includeDirectedRuntimeSemantics)
if ~isstruct(fullConfig) || ~isscalar(fullConfig)
    error('ObservableTopologyContext:InvalidTriggerConfig', ...
        'The topology-policy trigger configuration is malformed.');
end
permittedFields = permittedTriggerConfigFields( ...
    includeDirectedRuntimeSemantics);
if ~isfield(fullConfig, 'payloadExistenceThreshold')
    error('ObservableTopologyContext:InvalidTriggerConfig', ...
        'The causal fusion configuration lacks its payload threshold.');
end
triggerConfig = struct();
for fieldIdx = 1:numel(permittedFields)
    fieldName = permittedFields{fieldIdx};
    if isfield(fullConfig, fieldName)
        value = fullConfig.(fieldName);
        if ~isPermittedTriggerConfigValue(fieldName, value)
            error('ObservableTopologyContext:InvalidTriggerConfig', ...
                ['A nonprimitive or malformed value cannot enter the ', ...
                 'causal policy config.']);
        end
        triggerConfig.(fieldName) = value;
    end
end
end

function valid = isPermittedTriggerConfigValue(fieldName, value)
if strcmp(fieldName, 'topologyDirectedMessageBudget') && isempty(value)
    valid = true;
    return;
end
textFields = { ...
    'eventPolicy', 'missingNeighborWeightMode', ...
    'mixtureAwareExistenceEtaMode'};
if any(strcmp(fieldName, textFields))
    valid = ischar(value) && isrow(value) && ~isempty(value);
    return;
end
valid = (isa(value, 'double') || islogical(value)) && ...
    isreal(value) && isscalar(value) && ~isnan(double(value));
if valid && isinf(double(value))
    valid = any(strcmp(fieldName, { ...
        'maxSelfFusionWeight', 'maxNonStaticFusionWeight'}));
end
end

