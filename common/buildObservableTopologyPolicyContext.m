function result = containsFunctionHandle(value)
if isa(value, 'function_handle')
    result = true;
    return;
end
result = false;
if iscell(value)
    for valueIdx = 1:numel(value)
        if containsFunctionHandle(value{valueIdx})
            result = true;
            return;
        end
    end
elseif isstruct(value)
    names = fieldnames(value);
    for valueIdx = 1:numel(value)
        for fieldIdx = 1:numel(names)
            if containsFunctionHandle(value(valueIdx).(names{fieldIdx}))
                result = true;
                return;
            end
        end
    end
end
end

function valid = usesPrimitiveContainersOnly(value)
if isnumeric(value) || islogical(value) || ischar(value)
    valid = true;
    return;
end
if iscell(value)
    valid = true;
    for valueIdx = 1:numel(value)
        if ~usesPrimitiveContainersOnly(value{valueIdx})
            valid = false;
            return;
        end
    end
    return;
end
if isstruct(value)
    valid = true;
    names = fieldnames(value);
    for valueIdx = 1:numel(value)
        for fieldIdx = 1:numel(names)
            if ~usesPrimitiveContainersOnly( ...
                    value(valueIdx).(names{fieldIdx}))
                valid = false;
                return;
            end
        end
    end
    return;
end
valid = false;
end

