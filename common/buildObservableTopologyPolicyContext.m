function observable = buildObservableTopologyPolicyContext(context)
% BUILDOBSERVABLETOPOLOGYPOLICYCONTEXT Isolate causal policy inputs.

requiredFields = { ...
    'localPosteriorBySensor', 'model', 'commConfig', ...
    'triggerConfig', 'currentTime', 'previousAdjacency', ...
    'previousAdjacencyHistory', 'previousAdjacencyHistoryCount', ...
    'previousAdjacencyHistoryTimes', ...
    'previousAdjacencyHistoryConvention', ...
    'previousAdjacencyHistorySource', 'baseAdjacency', ...
    'physicalAdjacency', 'edgeScores', 'edgeBudget', ...
    'directedMessageBudget', 'positions', ...
    'localInnovationHistory', ...
    'localAssociationConfidenceHistory', 'localNisNormHistory', ...
    'localNisDeviationHistory', 'localUpdateHistoryTimes'};
physicalIdentityFields = { ...
    'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', ...
    'physicalIdentityRegistryCanonicalSha256'};
deliveryHistoryFields = { ...
    'previousDeliveryHistory', ...
    'previousDeliveryHistoryCount', ...
    'previousDeliveryHistoryTimes', ...
    'previousDeliveryHistoryConvention', ...
    'previousDeliveryHistorySource'};
payloadReleaseHistoryFields = { ...
    'previousPayloadReleaseHistory', ...
    'previousPayloadReleaseHistoryCount', ...
    'previousPayloadReleaseHistoryTimes', ...
    'previousPayloadReleaseHistoryConvention', ...
    'previousPayloadReleaseHistorySource'};
localPosteriorHistoryFields = { ...
    'previousLocalPosteriorHistory', ...
    'previousLocalPosteriorHistoryCount', ...
    'previousLocalPosteriorHistoryTimes', ...
    'previousLocalPosteriorHistoryConvention', ...
    'previousLocalPosteriorHistorySource'};
if ~isstruct(context) || ~isscalar(context)
    error('ObservableTopologyContext:InvalidInput', ...
        'The full topology-policy context is malformed.');
end
physicalIdentityMask = isfield(context, physicalIdentityFields);
if any(physicalIdentityMask) && ~all(physicalIdentityMask)
    error('ObservableTopologyContext:IncompletePhysicalIdentity', ...
        ['Physical identity metadata must be supplied as one complete ', ...
         'runtime-bound tuple.']);
end
physicalIdentityEnabled = all(physicalIdentityMask);
if physicalIdentityEnabled
    requiredFields = [requiredFields, physicalIdentityFields];
end
deliveryHistoryMask = isfield(context, deliveryHistoryFields);
if any(deliveryHistoryMask) && ~all(deliveryHistoryMask)
    error('ObservableTopologyContext:IncompleteDeliveryHistory', ...
        ['Past delivery acknowledgments must be supplied as one ', ...
         'complete causal-history tuple.']);
end
deliveryHistoryEnabled = all(deliveryHistoryMask);
if deliveryHistoryEnabled
    requiredFields = [requiredFields, deliveryHistoryFields];
end
payloadReleaseHistoryMask = isfield( ...
    context, payloadReleaseHistoryFields);
if any(payloadReleaseHistoryMask) && ...
        ~all(payloadReleaseHistoryMask)
    error('ObservableTopologyContext:IncompletePayloadReleaseHistory', ...
        ['Past payload releases must be supplied as one complete ', ...
         'causal-history tuple.']);
end
payloadReleaseHistoryEnabled = all(payloadReleaseHistoryMask);
if payloadReleaseHistoryEnabled
    requiredFields = [requiredFields, payloadReleaseHistoryFields];
end
localPosteriorHistoryMask = isfield( ...
    context, localPosteriorHistoryFields);
if any(localPosteriorHistoryMask) && ...
        ~all(localPosteriorHistoryMask)
    error('ObservableTopologyContext:IncompleteLocalPosteriorHistory', ...
        ['Past local posteriors must be supplied as one complete ', ...
         'causal-history tuple.']);
end
localPosteriorHistoryEnabled = all(localPosteriorHistoryMask);
if localPosteriorHistoryEnabled
    requiredFields = [requiredFields, localPosteriorHistoryFields];
end
if ~all(isfield(context, requiredFields)) || ...
        ~isa(context.currentTime, 'double') || ...
        ~isscalar(context.currentTime) || ...
        ~isfinite(context.currentTime) || ...
        context.currentTime < 1 || ...
        context.currentTime ~= round(context.currentTime)
    error('ObservableTopologyContext:InvalidInput', ...
        'The full topology-policy context is malformed.');
end

observable = struct();
for fieldIdx = 1:numel(requiredFields)
    fieldName = requiredFields{fieldIdx};
    observable.(fieldName) = context.(fieldName);
end
observable = rmfield(observable, {'model', 'commConfig', ...
    'triggerConfig'});
sensorCount = numel(context.localPosteriorBySensor);
sensorObservationEnabled = resolveSensorObservationEnabled( ...
    context.triggerConfig);
observable.model = sanitizeModel( ...
    context.model, sensorCount, sensorObservationEnabled);
if physicalIdentityEnabled
    [observable.sensorPhysicalUids, ...
        observable.formationPhysicalUidsBySensor, ...
        observable.physicalIdentityRegistryCanonicalSha256] = ...
        sanitizePhysicalIdentity( ...
            observable.sensorPhysicalUids, ...
            observable.formationPhysicalUidsBySensor, ...
            observable.physicalIdentityRegistryCanonicalSha256, ...
            observable.model, sensorCount);
end
observable.localPosteriorBySensor = sanitizePosteriorBySensor( ...
    context.localPosteriorBySensor, observable.model.xDimension, ...
    context.currentTime);
if localPosteriorHistoryEnabled
    previousPages = context.previousLocalPosteriorHistory;
    previousTimes = reshape( ...
        context.previousLocalPosteriorHistoryTimes, 1, []);
    sanitizedPages = cell(1, numel(previousPages));
    for pageIdx = 1:numel(previousPages)
        sanitizedPages{pageIdx} = sanitizePosteriorBySensor( ...
            previousPages{pageIdx}, observable.model.xDimension, ...
            previousTimes(pageIdx));
    end
    observable.previousLocalPosteriorHistory = sanitizedPages;
end
[observable.commConfig, pDropSource] = ...
    buildCurrentCommunicationPage( ...
        context.commConfig, ...
        sensorCount, ...
        context.currentTime);
observable.triggerConfig = sanitizeTriggerConfig( ...
    context.triggerConfig, physicalIdentityEnabled, ...
    sensorObservationEnabled, payloadReleaseHistoryEnabled);

contract = validateObservableContext(observable, requiredFields);
contract.pDropSource = pDropSource;
observable.observableInputContract = contract;
end

function [sensorUids, formationUidsBySensor, registrySha256] = ...
        sanitizePhysicalIdentity( ...
            sensorUids, formationUidsBySensor, registrySha256, ...
            model, sensorCount)
sensorUids = reshape(sensorUids, 1, []);
formationUidsBySensor = reshape(formationUidsBySensor, 1, []);
shaPattern = '^[0-9a-f]{64}$';
if ~isa(sensorUids, 'double') || ~isreal(sensorUids) || ...
        numel(sensorUids) ~= sensorCount || ...
        any(~isfinite(sensorUids)) || ...
        any(sensorUids <= 0) || ...
        any(sensorUids ~= round(sensorUids)) || ...
        numel(unique(sensorUids)) ~= sensorCount || ...
        ~isa(formationUidsBySensor, 'double') || ...
        ~isreal(formationUidsBySensor) || ...
        numel(formationUidsBySensor) ~= sensorCount || ...
        any(~isfinite(formationUidsBySensor)) || ...
        any(formationUidsBySensor <= 0) || ...
        any(formationUidsBySensor ~= round(formationUidsBySensor)) || ...
        ~ischar(registrySha256) || ~isrow(registrySha256) || ...
        isempty(regexp(registrySha256, shaPattern, 'once'))
    error('ObservableTopologyContext:InvalidPhysicalIdentity', ...
        'The runtime physical-identity tuple is malformed.');
end
if ~isfield(model, 'dynamicTopologyScenario') || ...
        ~isfield(model.dynamicTopologyScenario, 'config') || ...
        ~isfield(model.dynamicTopologyScenario.config, 'sensorGroupIds')
    error('ObservableTopologyContext:InvalidPhysicalIdentity', ...
        'Physical identities require registered formation membership.');
end
groupIds = reshape(model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
groupLabels = unique(groupIds);
seenFormationUids = zeros(1, numel(groupLabels));
for groupIdx = 1:numel(groupLabels)
    members = groupIds == groupLabels(groupIdx);
    groupFormationUids = unique(formationUidsBySensor(members));
    if numel(groupFormationUids) ~= 1
        error('ObservableTopologyContext:InvalidPhysicalIdentity', ...
            'A formation membership maps to multiple physical UIDs.');
    end
    seenFormationUids(groupIdx) = groupFormationUids;
end
if numel(unique(seenFormationUids)) ~= numel(groupLabels)
    error('ObservableTopologyContext:InvalidPhysicalIdentity', ...
        'Distinct formations must have distinct physical UIDs.');
end
end

function enabled = resolveSensorObservationEnabled(triggerConfig)
enabled = false;
if ~isstruct(triggerConfig) || ~isscalar(triggerConfig) || ...
        ~isfield(triggerConfig, ...
            'topologyPolicySensorObservationEnabled')
    return;
end
value = triggerConfig.topologyPolicySensorObservationEnabled;
if ~(islogical(value) || isa(value, 'double')) || ...
        ~isscalar(value) || ~isfinite(double(value)) || ...
        ~any(double(value) == [0, 1])
    error('ObservableTopologyContext:InvalidTriggerConfig', ...
        ['topologyPolicySensorObservationEnabled must be a ', ...
         'logical scalar.']);
end
enabled = logical(value);
end

function model = sanitizeModel( ...
        model, sensorCount, sensorObservationEnabled)
if ~isstruct(model) || ~isscalar(model)
    error('ObservableTopologyContext:InvalidModel', ...
        'The topology-policy model must be a scalar structure.');
end
requiredModelFields = { ...
    'xDimension', 'existenceThreshold', 'object', 'ospaParameters'};
if ~all(isfield(model, requiredModelFields)) || ...
        ~isa(model.xDimension, 'double') || ...
        ~isscalar(model.xDimension) || ...
        ~isfinite(model.xDimension) || ...
        model.xDimension < 2 || ...
        model.xDimension ~= round(model.xDimension) || ...
        ~isa(model.existenceThreshold, 'double') || ...
        ~isscalar(model.existenceThreshold) || ...
        ~isfinite(model.existenceThreshold) || ...
        model.existenceThreshold < 0 || ...
        model.existenceThreshold > 1 || ...
        ~isstruct(model.object) || ~isempty(model.object) || ...
        ~isstruct(model.ospaParameters) || ...
        ~isscalar(model.ospaParameters) || ...
        ~isfield(model.ospaParameters, 'eC') || ...
        ~isa(model.ospaParameters.eC, 'double') || ...
        ~isscalar(model.ospaParameters.eC) || ...
        ~isfinite(model.ospaParameters.eC) || ...
        model.ospaParameters.eC <= 0
    error('ObservableTopologyContext:InvalidModel', ...
        'The topology-policy fusion-model inputs are malformed.');
end
scenario = struct([]);
if isfield(model, 'dynamicTopologyScenario') && ...
        isstruct(model.dynamicTopologyScenario) && ...
        isscalar(model.dynamicTopologyScenario) && ...
        isfield(model.dynamicTopologyScenario, 'config') && ...
        isstruct(model.dynamicTopologyScenario.config) && ...
        isscalar(model.dynamicTopologyScenario.config) && ...
        isfield(model.dynamicTopologyScenario.config, 'sensorGroupIds')
    groupIds = reshape(model.dynamicTopologyScenario. ...
        config.sensorGroupIds, 1, []);
    if ~isa(groupIds, 'double') || ...
            numel(groupIds) ~= sensorCount || ...
            any(~isfinite(groupIds)) || ...
            any(groupIds < 1) || ...
            any(groupIds ~= round(groupIds))
        error('ObservableTopologyContext:InvalidModel', ...
            'The observable sensor-formation identifiers are invalid.');
    end
    scenario = struct('config', struct( ...
        'sensorGroupIds', groupIds));
end
sensorObservation = struct([]);
if sensorObservationEnabled
    sensorObservation = sanitizeCurrentSensorObservationModel( ...
        model, sensorCount);
end
sanitizedTemplate = sanitizePosteriorBySensor( ...
    {model.object}, model.xDimension, inf);
model = struct( ...
    'xDimension', model.xDimension, ...
    'existenceThreshold', model.existenceThreshold, ...
    'object', sanitizedTemplate{1}, ...
    'ospaParameters', struct('eC', model.ospaParameters.eC));
if sensorObservationEnabled
    model.numberOfSensors = sensorCount;
    model.sensorObservation = sensorObservation;
end
if ~isempty(scenario)
    model.dynamicTopologyScenario = scenario;
end
end

function observation = sanitizeCurrentSensorObservationModel( ...
        model, sensorCount)
% Keep only current/static sensing parameters needed by a causal policy.
required = { ...
    'detectionProbability', 'Q', 'sensorMotionEnabled', ...
    'sensorFovEnabled', 'sensorFovHalfAngleDeg', 'sensorFovRange', ...
    'currentSensorPosition', 'currentSensorFovHeadingRad'};
if ~all(isfield(model, required))
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        ['The causal policy requires the registered current sensing ', ...
         'hardware parameters.']);
end
detection = expandSensorVector( ...
    model.detectionProbability, sensorCount, ...
    'detectionProbability');
halfAngle = expandSensorVector( ...
    model.sensorFovHalfAngleDeg, sensorCount, ...
    'sensorFovHalfAngleDeg');
range = expandSensorVector( ...
    model.sensorFovRange, sensorCount, 'sensorFovRange');
if any(detection < 0 | detection > 1) || ...
        any(halfAngle <= 0 | halfAngle > 180) || ...
        any(range <= 0)
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        'A causal sensing parameter is outside its domain.');
end
if ~iscell(model.Q) || numel(model.Q) ~= sensorCount
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        'The current measurement covariances do not match the sensors.');
end
measurementCovariance = cell(1, sensorCount);
for sensorIdx = 1:sensorCount
    covariance = model.Q{sensorIdx};
    if ~isa(covariance, 'double') || ~isreal(covariance) || ...
            size(covariance, 1) ~= size(covariance, 2) || ...
            size(covariance, 1) < 1 || ...
            any(~isfinite(covariance(:)))
        error('ObservableTopologyContext:InvalidSensorObservation', ...
            'A current measurement covariance is malformed.');
    end
    measurementCovariance{sensorIdx} = covariance;
end
quality = defaultSensorQuality();
if isfield(model, 'sensorQuality') && ...
        isstruct(model.sensorQuality) && ...
        isscalar(model.sensorQuality)
    quality = sanitizeSensorQuality(model.sensorQuality, quality);
end
positions = model.currentSensorPosition;
headings = reshape(model.currentSensorFovHeadingRad, 1, []);
if ~isa(positions, 'double') || ~isreal(positions) || ...
        ~isequal(size(positions), [2, sensorCount]) || ...
        any(~isfinite(positions(:))) || ...
        ~isa(headings, 'double') || ~isreal(headings) || ...
        numel(headings) ~= sensorCount || any(~isfinite(headings))
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        'The current sensor positions or headings are malformed.');
end
observation = struct( ...
    'contractVersion', ...
        'topology-policy-current-sensor-observation-model-v1', ...
    'detectionProbability', detection, ...
    'measurementCovariance', {measurementCovariance}, ...
    'sensorMotionEnabled', logicalScalar( ...
        model.sensorMotionEnabled, 'sensorMotionEnabled'), ...
    'sensorFovEnabled', logicalScalar( ...
        model.sensorFovEnabled, 'sensorFovEnabled'), ...
    'sensorFovHalfAngleDeg', halfAngle, ...
    'sensorFovRange', range, ...
    'sensorQuality', quality, ...
    'currentPosition', positions, ...
    'currentFovHeadingRad', headings, ...
    'usesFutureSensorTrajectory', false, ...
    'usesFutureSensorHeading', false, ...
    'usesTargetTruth', false);
end

function values = expandSensorVector(value, sensorCount, fieldName)
if ~isa(value, 'double') || ~isreal(value) || ...
        isempty(value) || any(~isfinite(value(:))) || ...
        ~(isscalar(value) || numel(value) == sensorCount)
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        'The current %s field is malformed.', fieldName);
end
if isscalar(value)
    values = repmat(value, 1, sensorCount);
else
    values = reshape(value, 1, []);
end
end

function value = logicalScalar(value, fieldName)
if ~(islogical(value) || isa(value, 'double')) || ...
        ~isscalar(value) || ~isfinite(double(value)) || ...
        ~any(double(value) == [0, 1])
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        'The current %s flag is malformed.', fieldName);
end
value = logical(value);
end

function quality = defaultSensorQuality()
quality = struct( ...
    'enabled', false, ...
    'referenceRange', 120, ...
    'detectionRangeDecay', 0.45, ...
    'detectionRangePower', 1.5, ...
    'edgeDetectionPenalty', 0.35, ...
    'anglePower', 2.0, ...
    'minDetectionProbability', 0.05, ...
    'rangeNoiseScale', 1.2, ...
    'edgeNoiseScale', 1.5, ...
    'minCovarianceScale', 1.0, ...
    'maxCovarianceScale', 8.0);
end

function output = sanitizeSensorQuality(input, defaults)
fields = fieldnames(defaults);
output = defaults;
for fieldIdx = 1:numel(fields)
    fieldName = fields{fieldIdx};
    if ~isfield(input, fieldName)
        continue;
    end
    value = input.(fieldName);
    if strcmp(fieldName, 'enabled')
        output.(fieldName) = logicalScalar(value, fieldName);
    elseif ~isa(value, 'double') || ~isreal(value) || ...
            ~isscalar(value) || ~isfinite(value) || value < 0
        error('ObservableTopologyContext:InvalidSensorObservation', ...
            'A current sensor-quality field is malformed.');
    else
        output.(fieldName) = value;
    end
end
if output.minDetectionProbability > 1 || ...
        output.edgeDetectionPenalty > 1 || ...
        output.maxCovarianceScale < output.minCovarianceScale || ...
        output.referenceRange <= 0 || ...
        output.detectionRangePower <= 0 || output.anglePower <= 0
    error('ObservableTopologyContext:InvalidSensorObservation', ...
        'A current sensor-quality field is outside its domain.');
end
end

function posteriors = sanitizePosteriorBySensor( ...
        fullPosteriors, stateDimension, currentTime)
if ~iscell(fullPosteriors) || isempty(fullPosteriors)
    error('ObservableTopologyContext:InvalidPosterior', ...
        'The current local posterior collection is malformed.');
end
requiredFields = observablePosteriorFields();
droppedFields = { ...
    'trajectoryLength', 'trajectory', 'timestamps'};
allowedInputFields = [requiredFields, droppedFields];
posteriors = cell(size(fullPosteriors));
for sensorIdx = 1:numel(fullPosteriors)
    objects = fullPosteriors{sensorIdx};
    if ~isstruct(objects) || ...
            ~all(isfield(objects, requiredFields)) || ...
            ~all(ismember(fieldnames(objects), ...
                reshape(allowedInputFields, [], 1)))
        error('ObservableTopologyContext:InvalidPosterior', ...
            ['A current local posterior does not match the ', ...
             'registered LMB object schema.']);
    end
    for objectIdx = 1:numel(objects)
        validatePosteriorObject( ...
            objects(objectIdx), stateDimension, currentTime);
    end
    fieldsToDrop = intersect( ...
        droppedFields, fieldnames(objects), 'stable');
    if isempty(fieldsToDrop)
        posteriors{sensorIdx} = objects;
    else
        posteriors{sensorIdx} = rmfield(objects, fieldsToDrop);
    end
end
end

function validatePosteriorObject(object, stateDimension, currentTime)
if isfield(object, 'timestamps') && ~isempty(object.timestamps) && ...
        (~isa(object.timestamps, 'double') || ...
         ~isreal(object.timestamps) || ...
         any(~isfinite(object.timestamps(:))) || ...
         any(object.timestamps(:) > currentTime))
    error('ObservableTopologyContext:InvalidPosterior', ...
        'A current LMB posterior contains a future timestamp.');
end
scalarFiniteFields = { ...
    'birthLocation', 'birthTime', 'r', ...
    'numberOfGmComponents'};
for fieldIdx = 1:numel(scalarFiniteFields)
    value = object.(scalarFiniteFields{fieldIdx});
    if ~isa(value, 'double') || ~isreal(value) || ...
            ~isscalar(value) || ~isfinite(value)
        error('ObservableTopologyContext:InvalidPosterior', ...
        'A current LMB posterior scalar field is malformed.');
    end
end
nonnegativeOptionalFields = { ...
    'associationEntropy', 'detectionAssociationEntropy'};
for fieldIdx = 1:numel(nonnegativeOptionalFields)
    value = object.(nonnegativeOptionalFields{fieldIdx});
    if ~isa(value, 'double') || ~isreal(value) || ...
            (~isempty(value) && (~isscalar(value) || ...
                ~isfinite(value) || value < 0))
        error('ObservableTopologyContext:InvalidPosterior', ...
            'An LMB posterior association field is malformed.');
    end
end
boundedOptionalFields = { ...
    'detectionAssociationMass', 'associationAmbiguity', ...
    'associationConfidence'};
for fieldIdx = 1:numel(boundedOptionalFields)
    value = object.(boundedOptionalFields{fieldIdx});
    if ~isa(value, 'double') || ~isreal(value) || ...
            (~isempty(value) && (~isscalar(value) || ...
                ~isfinite(value) || value < 0 || value > 1))
        error('ObservableTopologyContext:InvalidPosterior', ...
            'An LMB posterior bounded association field is malformed.');
    end
end
if object.birthLocation < 0 || ...
        object.birthLocation ~= round(object.birthLocation) || ...
        object.birthTime < 0 || ...
        object.birthTime ~= round(object.birthTime) || ...
        object.birthTime > currentTime || ...
        object.r < 0 || object.r > 1 || ...
        object.numberOfGmComponents < 0 || ...
        object.numberOfGmComponents ~= ...
            round(object.numberOfGmComponents)
    error('ObservableTopologyContext:InvalidPosterior', ...
        'A current LMB posterior scalar value is outside its domain.');
end
componentCount = object.numberOfGmComponents;
weights = object.w;
if ~isa(weights, 'double') || ~isreal(weights) || ...
        (componentCount > 0 && ~isvector(weights)) || ...
        numel(weights) ~= componentCount || ...
        any(~isfinite(weights(:))) || any(weights(:) < 0) || ...
        (componentCount > 0 && sum(weights) <= 0) || ...
        ~iscell(object.mu) || ...
        (componentCount > 0 && ~isvector(object.mu)) || ...
        numel(object.mu) ~= componentCount || ...
        ~iscell(object.Sigma) || ...
        (componentCount > 0 && ~isvector(object.Sigma)) || ...
        numel(object.Sigma) ~= componentCount
    error('ObservableTopologyContext:InvalidPosterior', ...
        'The current LMB posterior mixture is malformed.');
end
for componentIdx = 1:componentCount
    meanVector = object.mu{componentIdx};
    covariance = object.Sigma{componentIdx};
    if ~isa(meanVector, 'double') || ~isreal(meanVector) || ...
            ~isequal(size(meanVector), [stateDimension, 1]) || ...
            any(~isfinite(meanVector(:))) || ...
            ~isa(covariance, 'double') || ~isreal(covariance) || ...
            ~isequal(size(covariance), ...
                [stateDimension, stateDimension]) || ...
            any(~isfinite(covariance(:)))
        error('ObservableTopologyContext:InvalidPosterior', ...
            'A current LMB posterior GM component is malformed.');
    end
end
end

function fields = observablePosteriorFields()
fields = { ...
    'birthLocation', 'birthTime', 'r', ...
    'numberOfGmComponents', 'w', 'mu', 'Sigma', ...
    'associationEntropy', 'detectionAssociationEntropy', ...
    'detectionAssociationMass', 'associationAmbiguity', ...
    'associationConfidence'};
end

function [commConfig, source] = buildCurrentCommunicationPage( ...
        fullConfig, sensorCount, currentTime)
if ~isstruct(fullConfig) || ~isscalar(fullConfig) || ...
        sensorCount < 1
    error('ObservableTopologyContext:InvalidCommunication', ...
        'The full communication configuration is malformed.');
end
if isfield(fullConfig, 'pDropByEdge') && ...
        ~isempty(fullConfig.pDropByEdge)
    pDrop = fullConfig.pDropByEdge;
    if ndims(pDrop) > 3 || ...
            size(pDrop, 1) ~= sensorCount || ...
            size(pDrop, 2) ~= sensorCount
        error('ObservableTopologyContext:InvalidCommunication', ...
            'pDropByEdge has an invalid shape.');
    end
    if ndims(pDrop) == 3
        pageIdx = min(currentTime, size(pDrop, 3));
        pDrop = pDrop(:, :, pageIdx);
    end
    source = 'current-pDropByEdge-page';
elseif isfield(fullConfig, 'pDropBySensor') && ...
        numel(fullConfig.pDropBySensor) == sensorCount
    rates = reshape(fullConfig.pDropBySensor, [], 1);
    pDrop = repmat(rates, 1, sensorCount);
    source = 'current-pDropBySensor-expanded-page';
else
    pDrop = zeros(sensorCount);
    source = 'zero-fallback-page';
end
if ~isa(pDrop, 'double') || ...
        ~isequal(size(pDrop), [sensorCount, sensorCount]) || ...
        any(~isfinite(pDrop(:)))
    error('ObservableTopologyContext:InvalidCommunication', ...
        'The current drop-probability page is invalid.');
end
commConfig = struct('pDropByEdge', min(max(pDrop, 0), 1));
end

function triggerConfig = sanitizeTriggerConfig( ...
        fullConfig, includeDirectedRuntimeSemantics, ...
        includeSensorObservationSemantics, ...
        includePayloadReleaseHistorySemantics)
if ~isstruct(fullConfig) || ~isscalar(fullConfig)
    error('ObservableTopologyContext:InvalidTriggerConfig', ...
        'The topology-policy trigger configuration is malformed.');
end
permittedFields = permittedTriggerConfigFields( ...
    includeDirectedRuntimeSemantics, ...
    includeSensorObservationSemantics, ...
    includePayloadReleaseHistorySemantics);
if ~isfield(fullConfig, 'payloadExistenceThreshold')
    error('ObservableTopologyContext:InvalidTriggerConfig', ...
        'The causal fusion configuration lacks its payload threshold.');
end
triggerConfig = struct();
for fieldIdx = 1:numel(permittedFields)
    fieldName = permittedFields{fieldIdx};
    if isfield(fullConfig, fieldName)
        value = fullConfig.(fieldName);
        if ~isPermittedTriggerConfigValue(fieldName, value)
            error('ObservableTopologyContext:InvalidTriggerConfig', ...
                ['A nonprimitive or malformed value cannot enter the ', ...
                 'causal policy config.']);
        end
        triggerConfig.(fieldName) = value;
    end
end
end

function valid = isPermittedTriggerConfigValue(fieldName, value)
if strcmp(fieldName, 'topologyDirectedMessageBudget') && isempty(value)
    valid = true;
    return;
end
textFields = { ...
    'eventPolicy', 'missingNeighborWeightMode', ...
    'mixtureAwareExistenceEtaMode', 'missingLabelFusionMode'};
if any(strcmp(fieldName, textFields))
    valid = ischar(value) && isrow(value) && ~isempty(value);
    return;
end
