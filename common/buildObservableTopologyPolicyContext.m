function valid = posteriorMatchesObservableSchema(posteriorBySensor)
valid = iscell(posteriorBySensor) && ~isempty(posteriorBySensor);
if ~valid
    return;
end
expectedFields = sort(reshape(observablePosteriorFields(), [], 1));
for sensorIdx = 1:numel(posteriorBySensor)
    objects = posteriorBySensor{sensorIdx};
    if ~isstruct(objects) || ...
            ~isequal(sort(fieldnames(objects)), expectedFields)
        valid = false;
        return;
    end
end
end

function valid = posteriorHasNoTrajectoryFields(posteriorBySensor)
valid = iscell(posteriorBySensor);
if ~valid
    return;
end
for sensorIdx = 1:numel(posteriorBySensor)
    objects = posteriorBySensor{sensorIdx};
    if ~isstruct(objects) || ...
            any(isfield(objects, { ...
                'trajectoryLength', 'trajectory', 'timestamps'}))
        valid = false;
        return;
    end
end
end

function valid = posteriorHasNoFutureTimestamps( ...
        posteriorBySensor, currentTime)
valid = iscell(posteriorBySensor);
if ~valid
    return;
end
for sensorIdx = 1:numel(posteriorBySensor)
    objects = posteriorBySensor{sensorIdx};
    if ~isstruct(objects)
        valid = false;
        return;
    end
    for objectIdx = 1:numel(objects)
        object = objects(objectIdx);
        if isfield(object, 'birthTime') && ...
                ~isempty(object.birthTime) && ...
                (~isscalar(object.birthTime) || ...
                 ~isfinite(object.birthTime) || ...
                 object.birthTime > currentTime)
            valid = false;
            return;
        end
        if isfield(object, 'timestamps') && ...
                ~isempty(object.timestamps)
            timestamps = object.timestamps;
            if ~isnumeric(timestamps) || ...
                    any(~isfinite(timestamps(:))) || ...
                    any(timestamps(:) > currentTime)
                valid = false;
                return;
            end
        end
    end
end
end

function paths = findForbiddenFieldPaths(value, prefix)
paths = cell(1, 0);
if iscell(value)
    for valueIdx = 1:numel(value)
        childPrefix = sprintf('%s{%d}', prefix, valueIdx);
        paths = [paths, findForbiddenFieldPaths( ...
            value{valueIdx}, childPrefix)]; %#ok<AGROW>
    end
    return;
end
if ~isstruct(value)
    return;
end
names = fieldnames(value);
for valueIdx = 1:numel(value)
    for fieldIdx = 1:numel(names)
        fieldName = names{fieldIdx};
        childPrefix = sprintf('%s.%s', prefix, fieldName);
        if isForbiddenFieldName(fieldName)
            paths{end + 1} = childPrefix; %#ok<AGROW>
        else
            paths = [paths, findForbiddenFieldPaths( ...
                value(valueIdx).(fieldName), ...
                childPrefix)]; %#ok<AGROW>
        end
    end
end
end

function paths = findNamedFieldPaths(value, targetName, prefix)
paths = cell(1, 0);
if iscell(value)
    for valueIdx = 1:numel(value)
        paths = [paths, findNamedFieldPaths( ...
            value{valueIdx}, targetName, ...
            sprintf('%s{%d}', prefix, valueIdx))]; %#ok<AGROW>
    end
    return;
end
if ~isstruct(value)
    return;
end
names = fieldnames(value);
for valueIdx = 1:numel(value)
    for fieldIdx = 1:numel(names)
        fieldName = names{fieldIdx};
        childPrefix = sprintf('%s.%s', prefix, fieldName);
        if strcmp(fieldName, targetName)
            paths{end + 1} = childPrefix; %#ok<AGROW>
        end
        paths = [paths, findNamedFieldPaths( ...
            value(valueIdx).(fieldName), targetName, ...
            childPrefix)]; %#ok<AGROW>
    end
end
end

function result = isForbiddenFieldName(fieldName)
lowerName = lower(fieldName);
exactNames = { ...
    'groundtruth', 'groundtruthrfs', 'truth', ...
    'trackingtruth', 'trackingtruthrfs', ...
    'targettrajectories', 'sensortrajectories', ...
    'linkuniforms', 'measurements', 'topologypolicyfcn'};
result = any(strcmp(lowerName, exactNames)) || ...
    strncmp(lowerName, 'future', 6) || ...
    ~isempty(strfind(lowerName, 'groundtruth')) || ... %#ok<STREMP>
    ~isempty(strfind(lowerName, 'targettrajector')); %#ok<STREMP>
end

function result = anyFieldPathEndsWith(paths, suffix)
result = false;
for pathIdx = 1:numel(paths)
    path = paths{pathIdx};
    if numel(path) >= numel(suffix) && ...
            strcmp(path(end - numel(suffix) + 1:end), suffix)
        result = true;
        return;
    end
end
