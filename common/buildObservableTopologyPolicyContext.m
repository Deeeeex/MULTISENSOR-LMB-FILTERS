function result = containsFunctionHandle(value)
if isa(value, 'function_handle')
    result = true;
    return;
end
result = false;
if iscell(value)
    for valueIdx = 1:numel(value)
        if containsFunctionHandle(value{valueIdx})
            result = true;
            return;
        end
    end
elseif isstruct(value)
    names = fieldnames(value);
    for valueIdx = 1:numel(value)
        for fieldIdx = 1:numel(names)
            if containsFunctionHandle(value(valueIdx).(names{fieldIdx}))
                result = true;
                return;
            end
        end
    end
end
end

function valid = usesPrimitiveContainersOnly(value)
if isnumeric(value) || islogical(value) || ischar(value)
    valid = true;
    return;
end
if iscell(value)
    valid = true;
    for valueIdx = 1:numel(value)
        if ~usesPrimitiveContainersOnly(value{valueIdx})
            valid = false;
            return;
        end
    end
    return;
end
if isstruct(value)
    valid = true;
    names = fieldnames(value);
    for valueIdx = 1:numel(value)
        for fieldIdx = 1:numel(names)
            if ~usesPrimitiveContainersOnly( ...
                    value(valueIdx).(names{fieldIdx}))
                valid = false;
                return;
            end
        end
    end
    return;
end
valid = false;
end

function valid = causalArraySchemaIsRestricted(context, sensorCount)
historyCount = context.previousAdjacencyHistoryCount;
historyTimes = reshape(context.previousAdjacencyHistoryTimes, 1, []);
updateTimes = reshape(context.localUpdateHistoryTimes, 1, []);
valid = isa(historyCount, 'double') && isscalar(historyCount) && ...
    isfinite(historyCount) && historyCount >= 0 && ...
    historyCount == round(historyCount) && ...
    isAdjacencyPage(context.previousAdjacency, sensorCount) && ...
    isAdjacencyPage(context.baseAdjacency, sensorCount) && ...
    isAdjacencyPage(context.physicalAdjacency, sensorCount) && ...
    (ischar(context.previousAdjacencyHistoryConvention) && ...
        isrow(context.previousAdjacencyHistoryConvention)) && ...
    (ischar(context.previousAdjacencyHistorySource) && ...
        isrow(context.previousAdjacencyHistorySource)) && ...
    (isa(context.previousAdjacencyHistory, 'double') || ...
        islogical(context.previousAdjacencyHistory)) && ...
    isreal(context.previousAdjacencyHistory) && ...
    size(context.previousAdjacencyHistory, 1) == sensorCount && ...
    size(context.previousAdjacencyHistory, 2) == sensorCount && ...
    size(context.previousAdjacencyHistory, 3) == historyCount && ...
    all(isfinite(context.previousAdjacencyHistory(:))) && ...
    isa(context.previousAdjacencyHistoryTimes, 'double') && ...
    isreal(context.previousAdjacencyHistoryTimes) && ...
    (isempty(historyTimes) || isvector(historyTimes)) && ...
    numel(historyTimes) == historyCount && ...
    all(isfinite(historyTimes)) && ...
    all(historyTimes == round(historyTimes)) && ...
    (numel(historyTimes) < 2 || all(diff(historyTimes) > 0)) && ...
    (isempty(context.edgeScores) || ...
        (isa(context.edgeScores, 'double') && ...
         isreal(context.edgeScores) && ...
         isequal(size(context.edgeScores), ...
            [sensorCount, sensorCount]) && ...
         ~any(isnan(context.edgeScores(:))))) && ...
    isa(context.edgeBudget, 'double') && ...
    isscalar(context.edgeBudget) && ...
    isfinite(context.edgeBudget) && context.edgeBudget >= 0 && ...
    context.edgeBudget == round(context.edgeBudget) && ...
    (isempty(context.directedMessageBudget) || ...
        (isa(context.directedMessageBudget, 'double') && ...
         isscalar(context.directedMessageBudget) && ...
         isfinite(context.directedMessageBudget) && ...
         context.directedMessageBudget >= 0 && ...
         context.directedMessageBudget == ...
            round(context.directedMessageBudget))) && ...
    isa(context.localUpdateHistoryTimes, 'double') && ...
    isreal(context.localUpdateHistoryTimes) && ...
    (isempty(updateTimes) || isvector(updateTimes)) && ...
    all(isfinite(updateTimes)) && ...
    all(updateTimes == round(updateTimes)) && ...
    (numel(updateTimes) < 2 || all(diff(updateTimes) > 0));
if ~valid
    return;
end
historyFields = { ...
    'localInnovationHistory', ...
    'localAssociationConfidenceHistory', ...
    'localNisNormHistory', 'localNisDeviationHistory'};
for fieldIdx = 1:numel(historyFields)
    values = context.(historyFields{fieldIdx});
    if isempty(updateTimes)
        fieldValid = isnumeric(values) && isreal(values) && ...
            isempty(values);
    else
        fieldValid = isa(values, 'double') && isreal(values) && ...
            isequal(size(values), [sensorCount, numel(updateTimes)]) && ...
            ~any(isinf(values(:)));
    end
    if ~fieldValid
        valid = false;
        return;
    end
end
deliveryHistoryFields = { ...
    'previousDeliveryHistory', ...
    'previousDeliveryHistoryCount', ...
    'previousDeliveryHistoryTimes', ...
    'previousDeliveryHistoryConvention', ...
    'previousDeliveryHistorySource'};
deliveryHistoryMask = isfield(context, deliveryHistoryFields);
if any(deliveryHistoryMask) && ~all(deliveryHistoryMask)
    valid = false;
    return;
end
if all(deliveryHistoryMask)
    deliveryCount = context.previousDeliveryHistoryCount;
    deliveryTimes = reshape( ...
        context.previousDeliveryHistoryTimes, 1, []);
    delivery = context.previousDeliveryHistory;
    valid = valid && ...
        isa(deliveryCount, 'double') && isscalar(deliveryCount) && ...
        isfinite(deliveryCount) && deliveryCount >= 0 && ...
        deliveryCount == round(deliveryCount) && ...
        (isa(delivery, 'double') || islogical(delivery)) && ...
        isreal(delivery) && ...
        size(delivery, 1) == sensorCount && ...
        size(delivery, 2) == sensorCount && ...
        size(delivery, 3) == deliveryCount && ...
        all(isfinite(delivery(:))) && ...
        all(delivery(:) == 0 | delivery(:) == 1) && ...
        isa(context.previousDeliveryHistoryTimes, 'double') && ...
        isreal(context.previousDeliveryHistoryTimes) && ...
        numel(deliveryTimes) == deliveryCount && ...
        all(isfinite(deliveryTimes)) && ...
        all(deliveryTimes == round(deliveryTimes)) && ...
        (numel(deliveryTimes) < 2 || all(diff(deliveryTimes) > 0)) && ...
        ischar(context.previousDeliveryHistoryConvention) && ...
        isrow(context.previousDeliveryHistoryConvention) && ...
        ischar(context.previousDeliveryHistorySource) && ...
        isrow(context.previousDeliveryHistorySource) && ...
        deliveryCount == historyCount && ...
        isequal(deliveryTimes, historyTimes) && ...
        all(~logical(delivery(:)) | ...
            logical(context.previousAdjacencyHistory(:)));
end
end

function valid = isAdjacencyPage(value, sensorCount)
valid = (isa(value, 'double') || islogical(value)) && ...
    isreal(value) && ...
    isequal(size(value), [sensorCount, sensorCount]) && ...
    all(isfinite(value(:)));
end

function contract = validateObservableContext(context, requiredFields)
sensorCount = numel(context.localPosteriorBySensor);
physicalIdentityFields = { ...
    'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', ...
    'physicalIdentityRegistryCanonicalSha256'};
physicalIdentityEnabled = ...
    all(isfield(context, physicalIdentityFields));
deliveryHistoryFields = { ...
    'previousDeliveryHistory', ...
    'previousDeliveryHistoryCount', ...
    'previousDeliveryHistoryTimes', ...
    'previousDeliveryHistoryConvention', ...
    'previousDeliveryHistorySource'};
deliveryHistoryEnabled = ...
    all(isfield(context, deliveryHistoryFields));
allowedFields = setdiff(requiredFields, { ...
    'model', 'commConfig', 'triggerConfig'}, 'stable');
allowedFields = [allowedFields, {'model', 'commConfig', ...
    'triggerConfig'}];
if ~isequal(sort(fieldnames(context)), ...
        sort(reshape(allowedFields, [], 1))) || ...
        ~iscell(context.localPosteriorBySensor) || ...
        sensorCount < 1 || ...
        ~isequal(size(context.commConfig.pDropByEdge), ...
            [sensorCount, sensorCount]) || ...
        ndims(context.commConfig.pDropByEdge) ~= 2 || ...
        ~isequal(size(context.positions), [2, sensorCount])
    error('ObservableTopologyContext:ContractViolation', ...
        'The observable context field or current-page shape changed.');
end
if ~isequal(fieldnames(context.commConfig), {'pDropByEdge'})
    error('ObservableTopologyContext:ContractViolation', ...
        'Only the current pDropByEdge page may reach the policy.');
end

scenarioGroupIdsOnly = true;
if isfield(context.model, 'dynamicTopologyScenario')
    scenario = context.model.dynamicTopologyScenario;
    scenarioGroupIdsOnly = isstruct(scenario) && isscalar(scenario) && ...
        isequal(fieldnames(scenario), {'config'}) && ...
        isstruct(scenario.config) && isscalar(scenario.config) && ...
        isequal(fieldnames(scenario.config), {'sensorGroupIds'});
end
expectedModelFields = { ...
    'xDimension'; 'existenceThreshold'; 'object'};
if isfield(context.model, 'dynamicTopologyScenario')
    expectedModelFields{end + 1, 1} = ...
        'dynamicTopologyScenario';
end
modelStaticFusionInputsOnly = ...
    isequal(fieldnames(context.model), expectedModelFields);
modelObjectTemplateEmpty = ...
    isstruct(context.model.object) && isempty(context.model.object);
permittedTriggerFields = permittedTriggerConfigFields( ...
    physicalIdentityEnabled);
actualTriggerFields = fieldnames(context.triggerConfig);
triggerConfigStaticFusionInputsOnly = ...
    isfield(context.triggerConfig, 'payloadExistenceThreshold') && ...
    all(ismember(actualTriggerFields, permittedTriggerFields')) && ...
    ~containsFunctionHandle(context.triggerConfig);
triggerConfigPrimitiveValuesOnly = true;
for triggerFieldIdx = 1:numel(actualTriggerFields)
    triggerFieldName = actualTriggerFields{triggerFieldIdx};
    triggerConfigPrimitiveValuesOnly = ...
        triggerConfigPrimitiveValuesOnly && ...
        isPermittedTriggerConfigValue(triggerFieldName, ...
            context.triggerConfig.(triggerFieldName));
end
posteriorSchemaRestricted = posteriorMatchesObservableSchema( ...
    context.localPosteriorBySensor);
posteriorTrajectoryFieldsAbsent = ...
    posteriorHasNoTrajectoryFields( ...
        context.localPosteriorBySensor);
contextUsesPrimitiveContainersOnly = ...
    usesPrimitiveContainersOnly(context);
contextHasNoFunctionHandles = ...
    ~containsFunctionHandle(context) && ...
    contextUsesPrimitiveContainersOnly;
causalArraySchemaRestricted = ...
    causalArraySchemaIsRestricted(context, sensorCount);
physicalIdentitySchemaRestricted = true;
if physicalIdentityEnabled
    physicalIdentitySchemaRestricted = ...
        physicalIdentitySchemaIsRestricted(context, sensorCount);
end
forbiddenPaths = findForbiddenFieldPaths(context, 'context');
pDropPaths = findNamedFieldPaths(context, 'pDropByEdge', 'context');
expectedPDropPath = {'context.commConfig.pDropByEdge'};
previousTimes = reshape(context.previousAdjacencyHistoryTimes, 1, []);
updateTimes = reshape(context.localUpdateHistoryTimes, 1, []);
topologyHistoryOnly = ...
    context.previousAdjacencyHistoryCount == ...
        size(context.previousAdjacencyHistory, 3) && ...
    numel(previousTimes) == context.previousAdjacencyHistoryCount && ...
    all(previousTimes < context.currentTime);
updateHistoryOnly = all(updateTimes <= context.currentTime);
pastDeliveryHistoryOnly = true;
deliveryHistoryAligned = true;
deliveryHistoryAttemptSubset = true;
if deliveryHistoryEnabled
    deliveryTimes = reshape( ...
        context.previousDeliveryHistoryTimes, 1, []);
    pastDeliveryHistoryOnly = ...
        context.previousDeliveryHistoryCount == ...
            size(context.previousDeliveryHistory, 3) && ...
        numel(deliveryTimes) == ...
            context.previousDeliveryHistoryCount && ...
        all(deliveryTimes < context.currentTime);
    deliveryHistoryAligned = ...
        context.previousDeliveryHistoryCount == ...
            context.previousAdjacencyHistoryCount && ...
        isequal(deliveryTimes, previousTimes);
    deliveryHistoryAttemptSubset = all( ...
        ~logical(context.previousDeliveryHistory(:)) | ...
        logical(context.previousAdjacencyHistory(:)));
end

contract = struct();
if physicalIdentityEnabled && deliveryHistoryEnabled
    contract.contractVersion = ...
        ['topology-policy-observable-input-v4-', ...
         'physical-uid-delivery-history'];
elseif physicalIdentityEnabled
    contract.contractVersion = ...
        'topology-policy-observable-input-v3-physical-uid';
else
    contract.contractVersion = ...
        'topology-policy-observable-input-v2';
end
contract.enforced = true;
contract.currentTime = context.currentTime;
contract.allowedContextFields = allowedFields;
contract.commConfigFields = {'pDropByEdge'};
contract.dynamicTopologyScenarioFields = {'config'};
contract.dynamicTopologyScenarioConfigFields = {'sensorGroupIds'};
contract.modelFields = reshape(expectedModelFields, 1, []);
contract.triggerConfigFields = ...
    reshape(actualTriggerFields, 1, []);
contract.targetTruthAbsent = isempty(forbiddenPaths);
contract.fullDynamicScenarioAbsent = scenarioGroupIdsOnly;
contract.modelStaticFusionInputsOnly = modelStaticFusionInputsOnly;
contract.modelObjectTemplateEmpty = modelObjectTemplateEmpty;
contract.triggerConfigStaticFusionInputsOnly = ...
    triggerConfigStaticFusionInputsOnly;
contract.triggerConfigPrimitiveValuesOnly = ...
    triggerConfigPrimitiveValuesOnly;
contract.linkUniformsAbsent = ~anyFieldPathEndsWith( ...
    forbiddenPaths, '.linkUniforms');
contract.futurePDropPagesAbsent = ...
    ndims(context.commConfig.pDropByEdge) == 2 && ...
    isequal(pDropPaths, expectedPDropPath);
contract.sensorTrajectoriesAbsent = ~anyFieldPathEndsWith( ...
    forbiddenPaths, '.sensorTrajectories');
contract.currentPositionsOnly = ...
    isa(context.positions, 'double') && ...
    isreal(context.positions) && ...
    isequal(size(context.positions), [2, sensorCount]) && ...
    all(isfinite(context.positions(:)));
contract.currentPosteriorPresent = ...
    iscell(context.localPosteriorBySensor) && ...
    numel(context.localPosteriorBySensor) == sensorCount;
contract.posteriorSchemaFields = observablePosteriorFields();
contract.posteriorSchemaRestricted = posteriorSchemaRestricted;
contract.posteriorTrajectoryFieldsAbsent = ...
    posteriorTrajectoryFieldsAbsent;
contract.contextHasNoFunctionHandles = ...
    contextHasNoFunctionHandles;
contract.contextUsesPrimitiveContainersOnly = ...
    contextUsesPrimitiveContainersOnly;
contract.causalArraySchemaRestricted = ...
    causalArraySchemaRestricted;
contract.currentPosteriorHasNoFutureTimestamps = ...
    posteriorHasNoFutureTimestamps( ...
        context.localPosteriorBySensor, context.currentTime);
contract.pastTopologyHistoryOnly = topologyHistoryOnly;
contract.deliveryHistoryPresent = deliveryHistoryEnabled;
contract.pastDeliveryHistoryOnly = pastDeliveryHistoryOnly;
contract.deliveryHistoryAlignedToTopologyHistory = ...
    deliveryHistoryAligned;
contract.deliveryHistoryAttemptSubset = ...
    deliveryHistoryAttemptSubset;
contract.nonfutureUpdateHistoryOnly = updateHistoryOnly;
contract.modelScenarioGroupIdsOnly = scenarioGroupIdsOnly;
if physicalIdentityEnabled
    contract.physicalIdentityPresent = true;
    contract.physicalIdentitySchemaRestricted = ...
        physicalIdentitySchemaRestricted;
    contract.physicalIdentityFields = physicalIdentityFields;
    contract.physicalIdentityRegistryCanonicalSha256 = ...
        context.physicalIdentityRegistryCanonicalSha256;
    directedFields = { ...
        'topologyDirectedEnabled', ...
        'topologyDirectedMessageBudget'};
    contract.directedTopologyRuntimeSemanticsPresent = ...
        all(isfield(context.triggerConfig, directedFields));
    if contract.directedTopologyRuntimeSemanticsPresent
        contract.topologyDirectedEnabled = ...
            context.triggerConfig.topologyDirectedEnabled;
        contract.topologyDirectedMessageBudget = ...
            context.triggerConfig.topologyDirectedMessageBudget;
    end
end
contract.forbiddenFieldPaths = forbiddenPaths;
passedChecks = [ ...
    contract.targetTruthAbsent, ...
    contract.fullDynamicScenarioAbsent, ...
    contract.modelStaticFusionInputsOnly, ...
    contract.modelObjectTemplateEmpty, ...
    contract.triggerConfigStaticFusionInputsOnly, ...
    contract.triggerConfigPrimitiveValuesOnly, ...
    contract.linkUniformsAbsent, ...
    contract.futurePDropPagesAbsent, ...
    contract.sensorTrajectoriesAbsent, ...
    contract.currentPositionsOnly, ...
    contract.currentPosteriorPresent, ...
    contract.posteriorSchemaRestricted, ...
    contract.posteriorTrajectoryFieldsAbsent, ...
    contract.contextHasNoFunctionHandles, ...
    contract.contextUsesPrimitiveContainersOnly, ...
    contract.causalArraySchemaRestricted, ...
    contract.currentPosteriorHasNoFutureTimestamps, ...
    contract.pastTopologyHistoryOnly, ...
    contract.pastDeliveryHistoryOnly, ...
    contract.deliveryHistoryAlignedToTopologyHistory, ...
    contract.deliveryHistoryAttemptSubset, ...
    contract.nonfutureUpdateHistoryOnly, ...
    contract.modelScenarioGroupIdsOnly];
if physicalIdentityEnabled
    passedChecks(end + 1) = ...
        contract.physicalIdentitySchemaRestricted;
end
contract.passed = all(passedChecks);
if ~contract.passed
    error('ObservableTopologyContext:ContractViolation', ...
        'A nonobservable value remained in the policy context.');
end
end

function valid = physicalIdentitySchemaIsRestricted(context, sensorCount)
valid = false;
try
    [sensorUids, formationUidsBySensor, registrySha256] = ...
        sanitizePhysicalIdentity( ...
            context.sensorPhysicalUids, ...
            context.formationPhysicalUidsBySensor, ...
            context.physicalIdentityRegistryCanonicalSha256, ...
            context.model, sensorCount);
catch
    return;
end
valid = isequal(sensorUids, context.sensorPhysicalUids) && ...
    isequal(formationUidsBySensor, ...
        context.formationPhysicalUidsBySensor) && ...
    strcmp(registrySha256, ...
        context.physicalIdentityRegistryCanonicalSha256);
end

function valid = posteriorMatchesObservableSchema(posteriorBySensor)
valid = iscell(posteriorBySensor) && ~isempty(posteriorBySensor);
if ~valid
    return;
end
expectedFields = sort(reshape(observablePosteriorFields(), [], 1));
for sensorIdx = 1:numel(posteriorBySensor)
    objects = posteriorBySensor{sensorIdx};
    if ~isstruct(objects) || ...
            ~isequal(sort(fieldnames(objects)), expectedFields)
        valid = false;
        return;
    end
end
end

function valid = posteriorHasNoTrajectoryFields(posteriorBySensor)
valid = iscell(posteriorBySensor);
if ~valid
    return;
end
for sensorIdx = 1:numel(posteriorBySensor)
    objects = posteriorBySensor{sensorIdx};
    if ~isstruct(objects) || ...
            any(isfield(objects, { ...
                'trajectoryLength', 'trajectory', 'timestamps'}))
        valid = false;
        return;
    end
end
end

function valid = posteriorHasNoFutureTimestamps( ...
        posteriorBySensor, currentTime)
valid = iscell(posteriorBySensor);
if ~valid
    return;
end
for sensorIdx = 1:numel(posteriorBySensor)
    objects = posteriorBySensor{sensorIdx};
    if ~isstruct(objects)
        valid = false;
        return;
    end
    for objectIdx = 1:numel(objects)
        object = objects(objectIdx);
        if isfield(object, 'birthTime') && ...
                ~isempty(object.birthTime) && ...
                (~isscalar(object.birthTime) || ...
                 ~isfinite(object.birthTime) || ...
                 object.birthTime > currentTime)
            valid = false;
            return;
        end
        if isfield(object, 'timestamps') && ...
                ~isempty(object.timestamps)
            timestamps = object.timestamps;
            if ~isnumeric(timestamps) || ...
                    any(~isfinite(timestamps(:))) || ...
                    any(timestamps(:) > currentTime)
                valid = false;
                return;
            end
        end
    end
end
end

function paths = findForbiddenFieldPaths(value, prefix)
paths = cell(1, 0);
if iscell(value)
    for valueIdx = 1:numel(value)
        childPrefix = sprintf('%s{%d}', prefix, valueIdx);
        paths = [paths, findForbiddenFieldPaths( ...
            value{valueIdx}, childPrefix)]; %#ok<AGROW>
    end
    return;
end
if ~isstruct(value)
    return;
end
names = fieldnames(value);
for valueIdx = 1:numel(value)
    for fieldIdx = 1:numel(names)
        fieldName = names{fieldIdx};
        childPrefix = sprintf('%s.%s', prefix, fieldName);
        if isForbiddenFieldName(fieldName)
            paths{end + 1} = childPrefix; %#ok<AGROW>
        else
            paths = [paths, findForbiddenFieldPaths( ...
                value(valueIdx).(fieldName), ...
                childPrefix)]; %#ok<AGROW>
        end
    end
end
end

function paths = findNamedFieldPaths(value, targetName, prefix)
paths = cell(1, 0);
if iscell(value)
    for valueIdx = 1:numel(value)
        paths = [paths, findNamedFieldPaths( ...
            value{valueIdx}, targetName, ...
            sprintf('%s{%d}', prefix, valueIdx))]; %#ok<AGROW>
    end
    return;
end
if ~isstruct(value)
    return;
end
names = fieldnames(value);
for valueIdx = 1:numel(value)
    for fieldIdx = 1:numel(names)
        fieldName = names{fieldIdx};
        childPrefix = sprintf('%s.%s', prefix, fieldName);
        if strcmp(fieldName, targetName)
            paths{end + 1} = childPrefix; %#ok<AGROW>
        end
        paths = [paths, findNamedFieldPaths( ...
            value(valueIdx).(fieldName), targetName, ...
            childPrefix)]; %#ok<AGROW>
    end
end
end

function result = isForbiddenFieldName(fieldName)
lowerName = lower(fieldName);
exactNames = { ...
    'groundtruth', 'groundtruthrfs', 'truth', ...
    'trackingtruth', 'trackingtruthrfs', ...
    'targettrajectories', 'sensortrajectories', ...
    'linkuniforms', 'measurements', 'topologypolicyfcn'};
result = any(strcmp(lowerName, exactNames)) || ...
    strncmp(lowerName, 'future', 6) || ...
    ~isempty(strfind(lowerName, 'groundtruth')) || ... %#ok<STREMP>
    ~isempty(strfind(lowerName, 'targettrajector')); %#ok<STREMP>
end

function result = anyFieldPathEndsWith(paths, suffix)
result = false;
for pathIdx = 1:numel(paths)
    path = paths{pathIdx};
    if numel(path) >= numel(suffix) && ...
            strcmp(path(end - numel(suffix) + 1:end), suffix)
        result = true;
        return;
    end
end
