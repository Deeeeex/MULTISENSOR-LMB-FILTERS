function valid = sensorObservationIsRestricted( ...
        model, sensorCount, currentPositions)
valid = ~isfield(model, 'sensorObservation');
if valid
    return;
end
observation = model.sensorObservation;
expectedFields = { ...
    'contractVersion'; 'detectionProbability'; ...
    'measurementCovariance'; 'sensorMotionEnabled'; ...
    'sensorFovEnabled'; 'sensorFovHalfAngleDeg'; ...
    'sensorFovRange'; 'sensorQuality'; 'currentPosition'; ...
    'currentFovHeadingRad'; 'usesFutureSensorTrajectory'; ...
    'usesFutureSensorHeading'; 'usesTargetTruth'};
valid = isstruct(observation) && isscalar(observation) && ...
    isequal(fieldnames(observation), expectedFields) && ...
    strcmp(observation.contractVersion, ...
        'topology-policy-current-sensor-observation-model-v1') && ...
    isequal(size(observation.currentPosition), [2, sensorCount]) && ...
    isequal(observation.currentPosition, currentPositions) && ...
    numel(observation.currentFovHeadingRad) == sensorCount && ...
    numel(observation.detectionProbability) == sensorCount && ...
    numel(observation.measurementCovariance) == sensorCount && ...
    numel(observation.sensorFovHalfAngleDeg) == sensorCount && ...
    numel(observation.sensorFovRange) == sensorCount && ...
    ~observation.usesFutureSensorTrajectory && ...
    ~observation.usesFutureSensorHeading && ...
    ~observation.usesTargetTruth;
end

