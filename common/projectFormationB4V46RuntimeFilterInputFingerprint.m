function fingerprint = ...
    projectFormationB4V46RuntimeFilterInputFingerprint(sourceFingerprint)
% PROJECTFORMATIONB4V46RUNTIMEFILTERINPUTFINGERPRINT Truth-free projection.

expectedFields = { ...
    'contractVersion', 'seed', 'registryId', ...
    'registryCanonicalSha256', 'caseId', 'caseOrdinal', ...
    'caseCanonicalSha256', 'seedRole', 'primaryMatrix', ...
    'stressMatrix', 'configSha256', 'sourceModelSha256', ...
    'runtimeFilterModelSha256', ...
    'runtimeFilterModelContractVersion', ...
    'runtimeFilterBirthPriorSha256', ...
    'measurementsSha256', 'groundTruthSha256', ...
    'groundTruthRfsSha256', 'sensorTrajectoriesSha256', ...
    'targetTrajectoriesSha256', 'neighborMapSha256', ...
    'communicationConfigSha256', 'graphDataSha256', ...
    'linkMetadataSha256', 'validationSha256', ...
    'physicalIdentityRegistrySha256', ...
    'deliveryUniformMetadataSha256', ...
    'deliveryUniformCanonicalTensorSha256', ...
    'deliveryUniformMaterializedTensorSha256', 'canonicalSha256'};
if ~isstruct(sourceFingerprint) || ~isscalar(sourceFingerprint) || ...
        ~isequal(sort(fieldnames(sourceFingerprint)), ...
            sort(expectedFields(:))) || ...
        ~strcmp(sourceFingerprint.contractVersion, ...
            ['formation-b4-v46-tracking-source-input-', ...
             'fingerprint-v2']) || ...
        ~strcmp(computeCanonicalValueSha256( ...
            rmfield(sourceFingerprint, 'canonicalSha256')), ...
            sourceFingerprint.canonicalSha256)
    error('FormationB4V46RuntimeFingerprint:InvalidSource', ...
        'A self-verifying exact-schema source fingerprint is required.');
end

payload = sourceProjectionPayload(sourceFingerprint);
fingerprint = payload;
fingerprint.canonicalSha256 = computeCanonicalValueSha256(payload);
end

