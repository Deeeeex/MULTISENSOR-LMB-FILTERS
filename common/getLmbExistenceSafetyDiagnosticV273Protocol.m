function protocol = getLmbExistenceSafetyDiagnosticV273Protocol()
% GETLMBEXISTENCESAFETYDIAGNOSTICV273PROTOCOL Frozen post-hoc gate.

source = getCausalGatewayEmbeddingV250Protocol();
protocol = struct();
protocol.id = 'lmb-existence-safety-diagnostic-v273-v1';
protocol.contractVersion = ...
    'lmb-existence-safety-diagnostic-v273-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.allowedPreset = source.allowedPresets{1};
protocol.allowedSeed = source.allowedSeeds(1);
protocol.anchorTimes = source.anchorTimes;
protocol.maximumIncomingCount = 2;
protocol.referenceSupportThreshold = 0.10;
protocol.decisionExistenceThreshold = 0.50;
protocol.retentionReceiverTailFraction = 0.34;
protocol.retentionReceiverTailWeight = 0.50;

% Outcome labels are frozen before inspecting V273 predictor values.  A
% positive cardinality-error change is discrete and is therefore not given
% an additional numerical margin.  Small E-OSPA fluctuations below the
% registered percentage margins are not called material harm.
protocol.materialNetworkEospaRegressionPercent = 0.01;
protocol.materialFormationEospaRegressionPercent = 0.05;
protocol.usefulMinimumNetworkEospaGainPercent = 0.001;
protocol.usefulMaximumFormationEospaRegressionPercent = 0.01;
protocol.numericTolerance = 1e-12;

% A monotone scalar safety signal must generalize as a gate, not merely
% correlate in the pooled development sample.
protocol.minimumLoaoBalancedAccuracy = 0.70;
protocol.minimumLoaoHarmRecall = 0.75;
protocol.minimumLoaoHarmlessSpecificity = 0.55;
protocol.minimumMedianCardinalityRankCorrelation = 0.25;
protocol.minimumMedianEospaHarmRankCorrelation = 0.25;
protocol.minimumNonnegativeAnchorCorrelationCount = 2;
protocol.requireUsefulActionRetainedAtEveryAnchor = true;

protocol.riskFeatureNames = { ...
    'reference_weighted_retention_risk', ...
    'maximum_receiver_retention_risk', ...
    'maximum_formation_retention_risk', ...
    'receiver_cardinality_loss', ...
    'formation_mean_cardinality_loss', ...
    'supported_label_retention_loss', ...
    'map_threshold_crossing_count', ...
    'map_threshold_crossing_mass', ...
    'maximum_reference_weighted_shortfall', ...
    'mean_reference_weighted_shortfall', ...
    'maximum_normalized_existence_drift', ...
    'mean_normalized_existence_drift', ...
    'one_round_disagreement_increase_fraction'};
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v273', ...
    'lmb_existence_safety', 'm24_seed1301_v250_h3');
protocol.reportFileName = 'LMB_EXISTENCE_SAFETY_V273.md';
protocol.matFileName = 'LMB_EXISTENCE_SAFETY_V273.mat';
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.newTrackingOutcomeAuthorized = false;
protocol.gnnAuthorized = false;
protocol.evidenceBoundary = [ ...
    'V273 reuses the completed V250 H=3 candidate outcomes from one M24 ', ...
    'development seed. Predictor inputs contain current local LMB ', ...
    'posteriors, current physical topology and link reliabilities, and ', ...
    'past selected-topology history. The predictor executes the same ', ...
    'mixture-aware label-wise fusion operator used by the tracker while ', ...
    'enumerating current independent link deliveries. It uses no truth or ', ...
    'future measurement, but it requires centralized current posteriors ', ...
    'and does not charge a deployable control synopsis. Truth appears only ', ...
    'in the already opened H=3 outcome labels. This is post-hoc method ', ...
    'diagnosis, not full-episode, X36, multistyle, deployment or paper ', ...
    'evidence.'];

if numel(protocol.riskFeatureNames) < 1 || ...
        protocol.minimumLoaoBalancedAccuracy < 0.5 || ...
        protocol.minimumLoaoBalancedAccuracy > 1 || ...
        protocol.minimumLoaoHarmRecall < 0 || ...
        protocol.minimumLoaoHarmRecall > 1 || ...
        protocol.minimumLoaoHarmlessSpecificity < 0 || ...
        protocol.minimumLoaoHarmlessSpecificity > 1 || ...
        protocol.minimumNonnegativeAnchorCorrelationCount < 1 || ...
        protocol.minimumNonnegativeAnchorCorrelationCount > ...
            numel(protocol.anchorTimes)
    error('LmbExistenceSafetyV273:InvalidProtocol', ...
        'The V273 diagnostic protocol is inconsistent.');
end
end
