function actionIndices = formationModeVectorToActionIndex( ...
        modeVectors, modeCount)
% FORMATIONMODEVECTORTOACTIONINDEX Base-modeCount lexicographic index.

if ~isnumeric(modeVectors) || ndims(modeVectors) ~= 2 || ...
        isempty(modeVectors) || ~isscalar(modeCount) || ...
        ~isfinite(modeCount) || modeCount ~= round(modeCount) || ...
        modeCount < 2 || any(~isfinite(modeVectors(:))) || ...
        any(modeVectors(:) ~= round(modeVectors(:))) || ...
        any(modeVectors(:) < 1) || ...
        any(modeVectors(:) > modeCount)
    error('Formation mode-vector index request is invalid.');
end
formationCount = size(modeVectors, 2);
powers = modeCount .^ ((formationCount - 1):-1:0);
actionIndices = 1 + (modeVectors - 1) * powers';
actionIndices = round(actionIndices);
end
