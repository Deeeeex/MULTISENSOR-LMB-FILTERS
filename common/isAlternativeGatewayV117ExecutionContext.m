function detected = isAlternativeGatewayV117ExecutionContext(context)
% ISALTERNATIVEGATEWAYV117EXECUTIONCONTEXT Identify V117.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'alternative-gateway-v117-context-v1');
end
