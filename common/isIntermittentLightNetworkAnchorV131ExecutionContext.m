function detected = ...
        isIntermittentLightNetworkAnchorV131ExecutionContext(context)
% ISINTERMITTENTLIGHTNETWORKANCHORV131EXECUTIONCONTEXT Identify V131.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'intermittent-light-network-anchor-v131-context-v1');
end
