function detected = isEtaProjectedLabelTrustV266ExecutionContext(context)
% ISETAPROJECTEDLABELTRUSTV266EXECUTIONCONTEXT Recognize V266.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'eta-projected-label-trust-v266-context-v1');
end
