function detected = isTemporalAcquireBroadcastV86ExecutionContext(context)
% ISTEMPORALACQUIREBROADCASTV86EXECUTIONCONTEXT Identify V86 requests.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'temporal-acquire-broadcast-primary-h3-v86-context-v1');
end
