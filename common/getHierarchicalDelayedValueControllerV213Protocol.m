split.contractVersion = ...
    'multistyle-complete-trajectory-split-v213-v1';
split.mainSceneStyles = {'radial', 'convoy', 'relay'};
split.mainPresets = { ...
    'm24-formation-fov', 'x36-formation-fov', ...
    'm24-formation-fov-convoy', 'x36-formation-fov-convoy', ...
    'm24-formation-fov-relay', 'x36-formation-fov-relay'};
split.trainingSeeds = [1301, 1303];
split.calibrationSeeds = [1409, 1423];
split.evaluationSeeds = [1511, 1523];
split.stressSeeds = [1601, 1607];
split.scaleExtrapolationSeeds = [1709, 1721];
split.stressPresets = { ...
    'm24-formation-fov-crossing', ...
    'x36-formation-fov-crossing', ...
    'm24-formation-fov-braided-handover', ...
    'x36-formation-fov-braided-handover', ...
    'm24-formation-fov-merge-split', ...
    'x36-formation-fov-merge-split', ...
    'm24-formation-fov-target-overlap', ...
    'x36-formation-fov-target-overlap', ...
    'm24-formation-fov-curved-corridor', ...
    'x36-formation-fov-curved-corridor'};
