function protocol = getHierarchicalDelayedValueControllerV213Protocol()
% GETHIERARCHICALDELAYEDVALUECONTROLLERV213PROTOCOL Freeze V213 design.
%
% V213 is the first protocol registered before opening new recursive
% M24/X36 trajectories.  It keeps the generic V99 route as no-op, proposes
% a bounded mode-diverse complete-label/release action set, and reserves
% final action admission for an H=3 vector lower-bound model.

