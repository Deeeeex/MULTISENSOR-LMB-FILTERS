promotion = struct();
promotion.minimumMeanEospaGainPercentByScale = 5;
promotion.minimumMeanRmseGainPercentByScale = 5;
promotion.minimumConsensusGainPercentByScale = 2;
promotion.minimumAttemptedByteSavingPercentByScale = 1;
promotion.currentBestTableUpdatedBelowPromotionGate = true;
protocol.promotion = promotion;

protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v213');
protocol.developmentAnchorSeeds = 211;
protocol.developmentAnchorsMayTrain = false;
protocol.developmentAnchorsMayCalibrate = false;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V213 freezes the proposal cap, risk tolerances, H=3 target, ', ...
    'communication reserve and complete-trajectory split after the ', ...
    'seed-211 mechanism anchors but before opening seeds 1301 and ', ...
    'above. Seed 211 may test contracts only and cannot train, ', ...
    'calibrate or validate the selector. The current-best table may ', ...
    'still record a below-promotion result with its evidence boundary.'];

assertProtocol(protocol);
end

function assertProtocol(protocol)
split = protocol.split;
seedSets = {split.trainingSeeds, split.calibrationSeeds, ...
    split.evaluationSeeds, split.stressSeeds, ...
    split.scaleExtrapolationSeeds};
for leftIdx = 1:numel(seedSets)
    if numel(unique(seedSets{leftIdx})) ~= numel(seedSets{leftIdx})
        error('V213Protocol:DuplicateSeed', ...
            'Every split must contain unique seeds.');
    end
    for rightIdx = leftIdx + 1:numel(seedSets)
        if ~isempty(intersect(seedSets{leftIdx}, seedSets{rightIdx}))
            error('V213Protocol:SplitLeakage', ...
                'Complete-trajectory seed splits must be disjoint.');
        end
    end
end
if ismember(protocol.developmentAnchorSeeds, ...
        [seedSets{:}]) || ...
        numel(protocol.risk.targetNames) ~= ...
            numel(protocol.risk.tolerancePercent) || ...
        protocol.proposal.relativeNeedFloor <= 0 || ...
        protocol.proposal.relativeNeedFloor > 1 || ...
        protocol.proposal.maximumFormationCount < 1 || ...
        protocol.proposal.topPerMode < 1 || ...
        protocol.horizonSteps ~= 3
    error('V213Protocol:InvalidContract', ...
        'The frozen V213 protocol is internally inconsistent.');
end
end
