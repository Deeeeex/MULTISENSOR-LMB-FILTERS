protocol.id = 'hierarchical-delayed-value-controller-v213-v1';
protocol.contractVersion = ...
    'hierarchical-delayed-value-controller-v213-protocol-v1';
protocol.basePolicyName = ...
    'online-positive-net-addressable-payload-v99-v1';
protocol.horizonSteps = 3;
protocol.maximumExecutedActionsPerPage = 1;
protocol.completeLabelSourceWeight = 0.5;

proposal = struct();
proposal.contractVersion = ...
    'hierarchical-formation-proposal-v213-v1';
proposal.formationFeatureName = 'need_max';
proposal.relativeNeedFloor = 0.90;
proposal.maximumFormationCount = 2;
proposal.modeFeatureNames = { ...
    'precision_refresh_evidence', ...
    'receiver_existence_deficit', ...
    'observation_handover_evidence'};
proposal.topPerMode = 3;
proposal.semanticCooldownPages = 1;
proposal.includeFormationRelease = true;
proposal.releaseFeasibilityContract = ...
    'explicit-current-route-state-releasable-formations';
proposal.sourceSynopsisBytes = 64;
proposal.receiverPropagationBytes = 24;
proposal.propagationFeatureCostChargedForEveryLabelProposal = true;
proposal.maximumLabelProposalCount = ...
    proposal.maximumFormationCount * ...
        proposal.topPerMode * numel(proposal.modeFeatureNames);
proposal.maximumProposalCount = proposal.maximumLabelProposalCount + ...
    proposal.maximumFormationCount;
proposal.tieBreakContract = ...
    'descending-score-then-enumerator-order';
proposal.truthUsed = false;
proposal.futureMeasurementsUsed = false;
protocol.proposal = proposal;

targetNames = { ...
    'mean_eospa_gain_percent', ...
    'mean_rmse_gain_percent', ...
    'consensus_gain_percent', ...
    'terminal_consensus_gain_percent', ...
    'receiver_formation_eospa_gain_percent', ...
    'receiver_formation_rmse_gain_percent', ...
    'minimum_affected_sensor_eospa_gain_percent', ...
    'minimum_affected_sensor_rmse_gain_percent', ...
    'worst_sensor_eospa_gain_percent', ...
    'worst_sensor_rmse_gain_percent', ...
    'minimum_formation_eospa_gain_percent', ...
    'minimum_formation_rmse_gain_percent'};
risk = struct();
risk.contractVersion = 'pareto-risk-budget-v213-v1';
risk.targetNames = targetNames;
% Aggregate tracking and both consistency coordinates must not regress.
% Formation/network tails receive a small visible redistribution budget;
% the affected-sensor RMSE coordinate receives only a catastrophe cap.
risk.tolerancePercent = [ ...
    0, 0, 0, 0, ...
    -1.5, -1.5, -5, -10, ...
    -1.5, -1.5, -1.5, -1.5];
risk.minimumStaticAttemptedByteSavingPercent = 1.0;
risk.conformalMiscoverage = 0.10;
risk.calibrationUnit = ...
    'complete-scene-seed-trajectory-maximum';
risk.selectionRule = ...
    'maximum-minimum-normalized-lower-bound-margin';
risk.noOpFallbackRequired = true;
risk.truthUsedAtRuntime = false;
protocol.risk = risk;

model = struct();
model.contractVersion = ...
    'dense-immediate-sparse-h3-residual-v213-v1';
model.immediateTarget = 'current-page-vector-gain';
model.recursiveTarget = 'same-state-no-op-relative-h3-vector-gain';
model.residualTarget = 'recursive-minus-immediate';
model.targetTransform = ...
    'tanh-log-reference-error-over-candidate-error';
model.propagationFeatureContract = ...
    'formation-repair-propagation-features-v211-v1';
model.candidateArchitectures = { ...
    'action-only-ridge', ...
    'frozen-two-round-graph-ridge', ...
    'trainable-two-round-formation-gnn'};
model.architectureSelectionUnit = ...
    'leave-one-complete-training-trajectory-out';
model.calibrationUsedForArchitectureSelection = false;
protocol.model = model;

