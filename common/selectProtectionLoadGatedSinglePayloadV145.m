function [role, details] = ...
        selectProtectionLoadGatedSinglePayloadV145( ...
            config, sensorGroupIds, senderIdx, receiverIdx, ...
            currentTime, receiverProtected, ...
            protectedFormationFraction, referenceLatchedBefore)
% SELECTPROTECTIONLOADGATEDSINGLEPAYLOADV145 Choose one observable role.

required = { ...
    'lineageRelayRoleMultiplexedSinglePayloadEnabled', ...
    'lineageRelayRoleMultiplexedProtectionLoadGateEnabled', ...
    'lineageRelayRoleMultiplexedAnchorTime', ...
    'lineageRelayRoleMultiplexedMinimumWorkingProtectedFraction'};
if ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config, required)) || ...
        ~logical(config.lineageRelayRoleMultiplexedSinglePayloadEnabled) || ...
        ~logical(config. ...
            lineageRelayRoleMultiplexedProtectionLoadGateEnabled)
    error('ProtectionLoadGatedRoleV145:InvalidRoleRequest', ...
        'The role selector requires the registered V145 runtime.');
end
groups = reshape(sensorGroupIds, 1, []);
sensorCount = numel(groups);
anchorTime = config.lineageRelayRoleMultiplexedAnchorTime;
threshold = config. ...
    lineageRelayRoleMultiplexedMinimumWorkingProtectedFraction;
if sensorCount < 1 || any(~isfinite(groups)) || ...
        ~isscalar(senderIdx) || ~isscalar(receiverIdx) || ...
        senderIdx < 1 || senderIdx > sensorCount || ...
        receiverIdx < 1 || receiverIdx > sensorCount || ...
        senderIdx == receiverIdx || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || currentTime < anchorTime || ...
        ~isscalar(receiverProtected) || ...
        ~any(double(receiverProtected) == [0, 1]) || ...
        ~isscalar(protectedFormationFraction) || ...
        ~isfinite(protectedFormationFraction) || ...
        protectedFormationFraction < 0 || ...
        protectedFormationFraction > 1 || ...
        ~isscalar(referenceLatchedBefore) || ...
        ~any(double(referenceLatchedBefore) == [0, 1]) || ...
        ~isscalar(threshold) || ~isfinite(threshold) || ...
        threshold <= 0 || threshold >= 1
    error('ProtectionLoadGatedRoleV145:InvalidRoleRequest', ...
        'The V145 role-selector input violates its observable gate.');
end

initialReferencePage = currentTime == anchorTime;
referenceLatchTriggered = protectedFormationFraction <= threshold;
referenceLatched = logical(referenceLatchedBefore) || ...
    referenceLatchTriggered;
intraFormation = groups(senderIdx) == groups(receiverIdx);
workingRole = ~initialReferencePage && ~referenceLatched && ...
    logical(receiverProtected) && intraFormation;
if workingRole
    role = 'working';
else
    role = 'reference';
end
details = struct( ...
    'referencePhase', ~workingRole, ...
    'workingPhase', workingRole, ...
    'initialReferencePage', initialReferencePage, ...
    'intraFormation', intraFormation, ...
    'receiverProtected', logical(receiverProtected), ...
    'protectedFormationFraction', protectedFormationFraction, ...
    'referenceLatchTriggered', referenceLatchTriggered, ...
    'referenceLatchedBefore', logical(referenceLatchedBefore), ...
    'referenceLatched', referenceLatched, ...
    'workingRole', workingRole, ...
    'referenceRole', ~workingRole);
end

