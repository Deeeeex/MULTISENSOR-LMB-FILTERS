function metrics = computeReceiverDomainNormalizedOpportunityV70( ...
        base, influence, control, transport, groupIds, options)
% COMPUTERECEIVERDOMAINNORMALIZEDOPPORTUNITYV70 Local intensive scores.
%
% V65--V69 divide a formation-local counterfactual by one network-wide
% existence mass.  That quantity is useful for predicting an immediate
% network-average effect, but it is not a scale-consistent trigger: adding
% unrelated formations increases the denominator without changing the
% action or its affected receivers.  V70 separates the two roles.  Local
% action materiality is measured against the affected formation's own
% reference mass; the later graph projection remains responsible for the
% global message and connectivity constraints.

if nargin < 6 || isempty(options)
    options = getReceiverDomainNormalizedOpportunityV70Protocol();
end
requiredBase = { ...
    'groups', 'singleActionAvailableMask', ...
    'referenceExistenceMassByFormation', ...
    'receiverSupportedRescueMassByFormation', ...
    'crossSupportedUsefulLossMassByFormation', ...
    'crossSupportedDownwardCrossingsByFormation', ...
    'networkReferenceExistenceMass'};
requiredInfluence = { ...
    'groups', 'horizonSteps', 'formationReceiverCount', ...
    'formationWeightedRobustMarginExposure'};
requiredControl = {'referenceScore'};
requiredTransport = { ...
    'networkReferenceExistenceMass', 'slotRecords', ...
    'routeConnectivityProjected'};
if ~isstruct(base) || ~isscalar(base) || ...
        ~all(isfield(base, requiredBase)) || ...
        ~isstruct(influence) || ~isscalar(influence) || ...
        ~all(isfield(influence, requiredInfluence)) || ...
        ~isstruct(control) || ~isscalar(control) || ...
        ~all(isfield(control, requiredControl)) || ...
        ~isstruct(transport) || ~isscalar(transport) || ...
        ~all(isfield(transport, requiredTransport))
    error('ReceiverDomainV70:InvalidInput', ...
        'V70 requires aligned V65, V66, control, and V68 records.');
end

groups = reshape(base.groups, 1, []);
groupIds = reshape(groupIds, 1, []);
formationCount = numel(groups);
if formationCount < 1 || ...
        ~isequal(groups, reshape(influence.groups, 1, [])) || ...
        numel(groupIds) < formationCount || ...
        any(~ismember(groupIds, groups))
    error('ReceiverDomainV70:FormationMismatch', ...
        'The V70 formation identities do not align.');
end

referenceMass = referenceMassByFormation( ...
    control, groups, groupIds);
baseReferenceMass = reshape( ...
    base.referenceExistenceMassByFormation, 1, []);
rescueMass = reshape( ...
    base.receiverSupportedRescueMassByFormation, 1, []);
usefulLossMass = reshape( ...
    base.crossSupportedUsefulLossMassByFormation, 1, []);
downward = reshape( ...
    base.crossSupportedDownwardCrossingsByFormation, 1, []);
available = reshape(base.singleActionAvailableMask, 1, []);
receiverCount = reshape(influence.formationReceiverCount, 1, []);
robustMass = reshape( ...
    influence.formationWeightedRobustMarginExposure, 1, []);
if any([numel(referenceMass), numel(rescueMass), ...
        numel(usefulLossMass), numel(downward), numel(available), ...
        numel(receiverCount), numel(robustMass), ...
        numel(baseReferenceMass)] ~= formationCount) || ...
        any(~isfinite(referenceMass)) || any(referenceMass <= eps) || ...
        any(~isfinite(receiverCount)) || any(receiverCount <= 0) || ...
        ~isscalar(influence.horizonSteps) || ...
        influence.horizonSteps < 1
    error('ReceiverDomainV70:InvalidFormationMass', ...
        'Formation-local denominators are invalid.');
end
comparableReference = available & isfinite(baseReferenceMass);
if any(abs(baseReferenceMass(comparableReference) - ...
        referenceMass(comparableReference)) > ...
        1e-10 * max(referenceMass(comparableReference), 1))
    error('ReceiverDomainV70:ReferenceMassMismatch', ...
        'The V65 and receiver-derived formation masses differ.');
end

minimumQuarantineNet = getField( ...
    options, 'minimumLocalQuarantineNetFraction', 0.01);
minimumAlternative = getField( ...
    options, 'minimumLocalAlternativeNetFraction', 0.01);
minimumRobust = getField( ...
    options, 'minimumLocalRobustMarginExposure', 0.10);
maximumLossRatio = getField( ...
    options, 'maximumUsefulLossToRescueRatio', 1.0);
requireZeroDownward = logical(getField( ...
    options, 'requireZeroSupportedDownwardCrossings', true));
validateThresholds(minimumQuarantineNet, minimumAlternative, minimumRobust, ...
    maximumLossRatio);

localRescue = rescueMass ./ referenceMass;
localUsefulLoss = usefulLossMass ./ referenceMass;
localQuarantineNet = (rescueMass - usefulLossMass) ./ referenceMass;
localRobust = robustMass ./ ...
    (receiverCount * influence.horizonSteps);
finiteQuarantine = available & isfinite(localRescue) & ...
    isfinite(localUsefulLoss) & isfinite(localRobust) & ...
    isfinite(downward);
quarantineMask = finiteQuarantine & ...
    localQuarantineNet >= minimumQuarantineNet - 1e-12 & ...
    localUsefulLoss <= maximumLossRatio * localRescue + 1e-12 & ...
    localRobust >= minimumRobust - 1e-12;
if requireZeroDownward
    quarantineMask = quarantineMask & downward == 0;
end

[alternativeGainMass, alternativeHarmMass, alternativeNetMass, ...
    positiveSlotCount] = aggregateAlternativeMass( ...
        transport, groups, groupIds, base.networkReferenceExistenceMass);
localAlternativeGain = alternativeGainMass ./ referenceMass;
localAlternativeHarm = alternativeHarmMass ./ referenceMass;
localAlternativeNet = alternativeNetMass ./ referenceMass;
transportMask = isfinite(localAlternativeNet) & ...
    localAlternativeNet >= minimumAlternative - 1e-12;

preferredAction = repmat({'fallback'}, 1, formationCount);
for formationIdx = 1:formationCount
    if quarantineMask(formationIdx) && transportMask(formationIdx)
        if localAlternativeNet(formationIdx) > ...
                localQuarantineNet(formationIdx) + 1e-12
            preferredAction{formationIdx} = 'transport';
        else
            preferredAction{formationIdx} = 'quarantine';
        end
    elseif quarantineMask(formationIdx)
        preferredAction{formationIdx} = 'quarantine';
    elseif transportMask(formationIdx)
        preferredAction{formationIdx} = 'transport';
    end
end

metrics = struct();
metrics.contractVersion = ...
    'receiver-domain-normalized-opportunity-v70-v1';
metrics.groups = groups;
metrics.groupIds = groupIds;
metrics.referenceExistenceMassByFormation = referenceMass;
metrics.localQuarantineRescueFractionByFormation = localRescue;
metrics.localQuarantineUsefulLossFractionByFormation = localUsefulLoss;
metrics.localQuarantineNetFractionByFormation = localQuarantineNet;
metrics.localRobustMarginExposureByFormation = localRobust;
metrics.quarantineActionMask = quarantineMask;
metrics.quarantineActionFormationIds = groups(quarantineMask);
metrics.alternativeTransportGainMassByFormation = alternativeGainMass;
metrics.alternativeTransportHarmMassByFormation = alternativeHarmMass;
metrics.alternativeTransportNetMassByFormation = alternativeNetMass;
metrics.localAlternativeTransportGainFractionByFormation = ...
    localAlternativeGain;
metrics.localAlternativeTransportHarmFractionByFormation = ...
    localAlternativeHarm;
metrics.localAlternativeTransportNetFractionByFormation = ...
    localAlternativeNet;
metrics.alternativePositiveSlotCountByFormation = positiveSlotCount;
metrics.alternativeTransportActionMask = transportMask;
metrics.alternativeTransportActionFormationIds = groups(transportMask);
metrics.actionableFormationMask = quarantineMask | transportMask;
metrics.actionableFormationIds = groups(metrics.actionableFormationMask);
metrics.preferredActionByFormation = preferredAction;
metrics.maximumLocalQuarantineRescueFraction = ...
    finiteMaximum(localRescue);
metrics.maximumLocalQuarantineNetFraction = ...
    finiteMaximum(localQuarantineNet);
metrics.maximumLocalAlternativeTransportNetFraction = ...
    finiteMaximum(localAlternativeNet);
metrics.minimumLocalQuarantineNetFraction = minimumQuarantineNet;
metrics.minimumLocalAlternativeNetFraction = minimumAlternative;
metrics.minimumLocalRobustMarginExposure = minimumRobust;
metrics.maximumUsefulLossToRescueRatio = maximumLossRatio;
metrics.requireZeroSupportedDownwardCrossings = requireZeroDownward;
metrics.receiverDomainNormalizationUsed = true;
metrics.routeConnectivityProjected = false;
metrics.messageBudgetProjected = false;
metrics.routeExecuted = false;
metrics.truthUsed = false;
metrics.futureMeasurementsUsed = false;
metrics.futureOutcomesUsed = false;
end

function massByFormation = referenceMassByFormation( ...
        control, groups, groupIds)
details = control.referenceScore.retentionDetails;
if ~isstruct(details) || ...
        ~isfield(details, 'expectedReferenceExistenceByReceiver') || ...
        numel(details.expectedReferenceExistenceByReceiver) ~= ...
            numel(groupIds)
    error('ReceiverDomainV70:MissingReferenceExistence', ...
        'Receiver-level reference existence is unavailable.');
end
massByFormation = zeros(1, numel(groups));
for receiverIdx = 1:numel(groupIds)
    formationIdx = find(groups == groupIds(receiverIdx), 1);
    values = reshape( ...
        details.expectedReferenceExistenceByReceiver{receiverIdx}, 1, []);
    if any(~isfinite(values)) || any(values < -1e-12)
        error('ReceiverDomainV70:InvalidReferenceExistence', ...
            'Receiver-level reference existence is invalid.');
    end
    massByFormation(formationIdx) = ...
        massByFormation(formationIdx) + sum(max(values, 0));
end
end

function [gainByFormation, harmByFormation, netByFormation, slotCount] = ...
        aggregateAlternativeMass(transport, groups, groupIds, networkMass)
formationCount = numel(groups);
gainByFormation = zeros(1, formationCount);
harmByFormation = zeros(1, formationCount);
netByFormation = zeros(1, formationCount);
slotCount = zeros(1, formationCount);
if abs(transport.networkReferenceExistenceMass - networkMass) > ...
        1e-10 * max(networkMass, 1)
    error('ReceiverDomainV70:TransportDenominatorMismatch', ...
        'V68 and V65 network denominators differ.');
end
for slot = reshape(transport.slotRecords, 1, [])
    if ~isfield(slot, 'bestSafe') || ~slot.bestSafe || ...
            ~isfield(slot, 'bestNetHeadroomFraction') || ...
            ~isfinite(slot.bestNetHeadroomFraction) || ...
            slot.bestNetHeadroomFraction <= 0
        continue;
    end
    receiverIdx = slot.receiverIdx;
    if ~isscalar(receiverIdx) || receiverIdx < 1 || ...
            receiverIdx > numel(groupIds) || receiverIdx ~= round(receiverIdx)
        error('ReceiverDomainV70:InvalidTransportReceiver', ...
            'A V68 residual slot has an invalid receiver.');
    end
    formationIdx = find(groups == groupIds(receiverIdx), 1);
    gainByFormation(formationIdx) = gainByFormation(formationIdx) + ...
        networkMass * slot.bestTransportGainFraction;
    harmByFormation(formationIdx) = harmByFormation(formationIdx) + ...
        networkMass * slot.bestSupportedHarmFraction;
    netByFormation(formationIdx) = netByFormation(formationIdx) + ...
        networkMass * slot.bestNetHeadroomFraction;
    slotCount(formationIdx) = slotCount(formationIdx) + 1;
end
end

function validateThresholds(rescue, alternative, robust, lossRatio)
values = [rescue, alternative, robust, lossRatio];
if any(~isfinite(values)) || any(values < 0)
    error('ReceiverDomainV70:InvalidThreshold', ...
        'V70 materiality thresholds must be finite and nonnegative.');
end
end

function value = finiteMaximum(values)
values = reshape(values, 1, []);
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
