function gate = ...
    evaluateFormationIndexEquivariantRouteV43DevelopmentGate( ...
        cases, execution, protocol)
% EVALUATE...GATE Pure, fail-closed aggregation for v43 evidence.

requiredExecution = {'registeredBatchComplete', ...
    'cleanSourceEvidence', 'postHocExecutableFreezeEvidence'};
requiredCase = {'caseId', 'presetName', 'sceneRole', 'seed', ...
    'currentTime', 'nodeCount', 'formationCount', ...
    'inputCanonicalSha256', ...
    'physicalUidRegistryCanonicalSha256', ...
    'legacyTargetHorizon', ...
    'v43TargetHorizon', 'targetHorizonRatio', ...
    'fixedHorizonFactorDelta', 'sameDirectedMessageBudget', ...
    'sameCrossFormationMessageBudget', 'fusionWeightsMatched', ...
    'protocolWeightsMatched', 'registeredInputIdentityMatched', ...
    'sparseFallbackContractPassed', 'executionBoundaryVerified', ...
    'posteriorUsed', 'truthUsed', 'measurementUsed', ...
    'futureOutcomeUsed', 'realizedDeliveryUniformsUsed', ...
    'trackingOutcomeScored', 'trackingOutcomeAuthorized', ...
    'validationClaimAllowed', 'developmentEvidenceOnly'};
if ~isstruct(cases) || isempty(cases) || ...
        ~isstruct(execution) || ~isscalar(execution) || ...
        ~all(isfield(execution, requiredExecution)) || ...
        ~isstruct(protocol) || ~isscalar(protocol) || ...
        ~all(isfield(cases, requiredCase))
    error('FormationIndexEquivariantV43Gate:InvalidInput', ...
        'The v43 aggregate gate input is incomplete.');
end
validateLogicalFields(cases, { ...
    'sameDirectedMessageBudget', 'sameCrossFormationMessageBudget', ...
    'fusionWeightsMatched', 'protocolWeightsMatched', ...
    'registeredInputIdentityMatched', ...
    'sparseFallbackContractPassed', 'executionBoundaryVerified', ...
    'posteriorUsed', 'truthUsed', 'measurementUsed', ...
    'futureOutcomeUsed', 'realizedDeliveryUniformsUsed', ...
    'trackingOutcomeScored', 'trackingOutcomeAuthorized', ...
    'validationClaimAllowed', 'developmentEvidenceOnly'});
if ~isScalarLogical(execution.registeredBatchComplete)
    error('FormationIndexEquivariantV43Gate:InvalidBoolean', ...
        'The registered-batch flag must be scalar logical.');
end
[registeredIdentityComplete, caseIdentitiesMatched] = ...
    verifyRegisteredCaseIdentities(cases, protocol);
if execution.registeredBatchComplete ~= registeredIdentityComplete
    error('FormationIndexEquivariantV43Gate:BatchIdentityMismatch', ...
        'The supplied registered-batch flag disagrees with case identity.');
end
cleanSourcePassed = validateCleanSourceEvidence( ...
    execution.cleanSourceEvidence);
postHocFreezePassed = validatePostHocFreezeEvidence( ...
    execution.postHocExecutableFreezeEvidence);

gate = struct();
gate.contractVersion = ...
    'formation-index-equivariant-route-v43-development-gate-v2';
gate.registeredBatchComplete = registeredIdentityComplete;
gate.officialCleanSourcePassed = cleanSourcePassed;
gate.postHocExecutableFreezeAuditPassed = postHocFreezePassed;
gate.sameMessageAndWeightBudget = ...
    all([cases.sameDirectedMessageBudget]) && ...
    all([cases.sameCrossFormationMessageBudget]) && ...
    all([cases.fusionWeightsMatched]) && ...
    all([cases.protocolWeightsMatched]);
gate.registeredInputIdentityPassed = ...
    caseIdentitiesMatched && ...
    all([cases.registeredInputIdentityMatched]);
gate.everyCaseFiniteTargetHorizon = ...
    all(isfinite([cases.legacyTargetHorizon])) && ...
    all(isfinite([cases.v43TargetHorizon]));
gate.everyCaseV43TargetHorizonNotWorse = ...
    all([cases.v43TargetHorizon] <= [cases.legacyTargetHorizon]);
gate.everyCaseFixedNMinusOneFactorLower = ...
    all([cases.fixedHorizonFactorDelta] < -1e-12);
gate.sparseFallbackContractPassed = ...
    all([cases.sparseFallbackContractPassed]);
gate.executionBoundaryPassed = ...
    all([cases.executionBoundaryVerified]) && ...
    ~any([cases.posteriorUsed]) && ~any([cases.truthUsed]) && ...
    ~any([cases.measurementUsed]) && ...
    ~any([cases.futureOutcomeUsed]) && ...
    ~any([cases.realizedDeliveryUniformsUsed]) && ...
    ~any([cases.trackingOutcomeScored]) && ...
    ~any([cases.trackingOutcomeAuthorized]) && ...
    ~any([cases.validationClaimAllowed]) && ...
    all([cases.developmentEvidenceOnly]);

names = {cases.presetName};
nonCrossing = cellfun(@(name) isempty(strfind(name, 'crossing')), ...
    names); %#ok<STREMP>
m24Mask = cellfun(@(name) strncmp(name, 'm24-', 4), names) & ...
    nonCrossing;
x36Mask = cellfun(@(name) strncmp(name, 'x36-', 4), names) & ...
    nonCrossing;
gate.m24NonCrossingCaseCount = nnz(m24Mask);
gate.x36NonCrossingCaseCount = nnz(x36Mask);
gate.m24NonCrossingMedianTargetHorizonRatio = ...
    safeMedian([cases(m24Mask).targetHorizonRatio]);
gate.x36NonCrossingMedianTargetHorizonRatio = ...
    safeMedian([cases(x36Mask).targetHorizonRatio]);
expectedPerScale = 3 * numel(protocol.registeredSeeds);
gate.scaleMedianTargetHorizonRatioGatePassed = ...
    gate.m24NonCrossingCaseCount == expectedPerScale && ...
    gate.x36NonCrossingCaseCount == expectedPerScale && ...
    gate.m24NonCrossingMedianTargetHorizonRatio <= ...
        protocol.scaleMedianTargetHorizonRatioMaximum && ...
    gate.x36NonCrossingMedianTargetHorizonRatio <= ...
        protocol.scaleMedianTargetHorizonRatioMaximum;

gate.routeReferenceAdvanceCriteriaPassed = ...
    gate.registeredBatchComplete && gate.officialCleanSourcePassed && ...
    gate.sameMessageAndWeightBudget && ...
    gate.registeredInputIdentityPassed && ...
    gate.everyCaseFiniteTargetHorizon && ...
    gate.everyCaseV43TargetHorizonNotWorse && ...
    gate.everyCaseFixedNMinusOneFactorLower && ...
    gate.scaleMedianTargetHorizonRatioGatePassed && ...
    gate.sparseFallbackContractPassed && ...
    gate.executionBoundaryPassed;
% A generation runner cannot attest its own frozen executable identity.
% A post-hoc auditor, committed after the artifact exists, supplies this bit.
gate.routeReferenceAdvancePassed = ...
    gate.routeReferenceAdvanceCriteriaPassed && ...
    gate.postHocExecutableFreezeAuditPassed;
gate.canonicalSha256 = computeCanonicalValueSha256(gate);
end

function [complete, matched] = verifyRegisteredCaseIdentities( ...
        cases, protocol)
registered = protocol.registeredCases;
caseIds = {cases.caseId};
registeredIds = {registered.caseId};
if numel(unique(caseIds)) ~= numel(caseIds)
    error('FormationIndexEquivariantV43Gate:DuplicateCase', ...
        'The v43 gate received duplicate case identities.');
end
matched = true;
for caseIdx = 1:numel(cases)
    matches = strcmp(registeredIds, cases(caseIdx).caseId);
    if nnz(matches) ~= 1
        matched = false;
        continue;
    end
    expected = registered(matches);
    actual = cases(caseIdx);
    matched = matched && ...
        strcmp(actual.presetName, expected.presetName) && ...
        strcmp(actual.sceneRole, expected.sceneRole) && ...
        isequal(actual.seed, expected.seed) && ...
        isequal(actual.currentTime, expected.currentTime) && ...
        isequal(actual.nodeCount, expected.nodeCount) && ...
        isequal(actual.formationCount, expected.formationCount) && ...
        strcmp(actual.inputCanonicalSha256, ...
            expected.inputCanonicalSha256) && ...
        strcmp(actual.physicalUidRegistryCanonicalSha256, ...
            expected.physicalUidRegistryCanonicalSha256);
end
complete = matched && numel(cases) == numel(registered) && ...
    isequal(caseIds, registeredIds);
end

function passed = validateCleanSourceEvidence(evidence)
required = {'contractVersion', 'requireCleanGit', ...
    'initialGitDirty', 'endingGitDirty', 'generationCommitStable', ...
    'executableManifestStable', 'pathResolutionPassed', ...
    'allEntriesTrackedByHead', 'allWorkingFilesMatchHead'};
if ~isstruct(evidence) || ~isscalar(evidence) || ...
        ~all(isfield(evidence, required)) || ...
        ~strcmp(evidence.contractVersion, ...
            'formation-index-equivariant-route-v43-clean-source-evidence-v1')
    error('FormationIndexEquivariantV43Gate:CleanEvidenceMalformed', ...
        'The clean-source evidence structure is malformed.');
end
logicalFields = required(2:end);
validateLogicalFields(evidence, logicalFields);
passed = evidence.requireCleanGit && ~evidence.initialGitDirty && ...
    ~evidence.endingGitDirty && evidence.generationCommitStable && ...
    evidence.executableManifestStable && ...
    evidence.pathResolutionPassed && ...
    evidence.allEntriesTrackedByHead && ...
    evidence.allWorkingFilesMatchHead;
end

function passed = validatePostHocFreezeEvidence(evidence)
required = {'contractVersion', 'generationCommitPinned', ...
    'protocolShaMatched', 'resultCanonicalShaRecomputed', ...
    'executableManifestShaPinned', 'artifactFilesShaPinned', ...
    'independentAuditCommitted', 'auditSourceClean'};
if ~isstruct(evidence) || ~isscalar(evidence) || ...
        ~all(isfield(evidence, required)) || ...
        ~strcmp(evidence.contractVersion, ...
            ['formation-index-equivariant-route-v43-', ...
             'posthoc-freeze-evidence-v1'])
    error('FormationIndexEquivariantV43Gate:PostHocEvidenceMalformed', ...
        'The post-hoc freeze evidence structure is malformed.');
end
logicalFields = required(2:end);
validateLogicalFields(evidence, logicalFields);
passed = evidence.generationCommitPinned && ...
    evidence.protocolShaMatched && ...
    evidence.resultCanonicalShaRecomputed && ...
    evidence.executableManifestShaPinned && ...
    evidence.artifactFilesShaPinned && ...
    evidence.independentAuditCommitted && evidence.auditSourceClean;
end

function validateLogicalFields(structures, fieldNames)
for itemIdx = 1:numel(structures)
    for fieldIdx = 1:numel(fieldNames)
        if ~isScalarLogical(structures(itemIdx).(fieldNames{fieldIdx}))
            error('FormationIndexEquivariantV43Gate:InvalidBoolean', ...
                'Every gate boolean must be scalar logical.');
        end
    end
end
end

function yes = isScalarLogical(value)
yes = islogical(value) && isscalar(value);
end

function value = safeMedian(values)
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end
