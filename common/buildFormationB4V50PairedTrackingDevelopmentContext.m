function context = ...
    buildFormationB4V50PairedTrackingDevelopmentContext( ...
        presetName, seed, armId)
% BUILDFORMATIONB4V50PAIREDTRACKINGDEVELOPMENTCONTEXT Experiment gate.

protocol = getFormationB4V50RuntimeProtocol();
allowedPresets = { ...
    'm24-formation-fov', ...
    'm24-formation-fov-convoy', ...
    'm24-formation-fov-relay', ...
    'm24-formation-fov-crossing', ...
    'x36-formation-fov', ...
    'x36-formation-fov-convoy', ...
    'x36-formation-fov-relay', ...
    'x36-formation-fov-crossing', ...
    'm24-formation-fov-merge-split', ...
    'm24-formation-fov-curved-corridor', ...
    'x36-formation-fov-merge-split', ...
    'x36-formation-fov-curved-corridor'};
if ~ischar(presetName) || ~any(strcmp(presetName, allowedPresets)) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~ischar(armId) || ~any(strcmp(armId, protocol.primaryArms))
    error('FormationB4V50Tracking:InvalidContextInput', ...
        'A registered M24/X36 preset, seed and V46/V50 arm are required.');
end
context = struct();
context.contractVersion = ...
    'formation-b4-v50-paired-tracking-development-context-v1';
context.capability = 'paired-tracking-development-v50';
context.action = 'filter-paired-tracking-development-v50';
context.presetName = presetName;
context.seed = seed;
context.armId = armId;
context.developmentEvidenceOnly = true;
end
