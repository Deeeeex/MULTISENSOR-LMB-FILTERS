function detected = isProtectionOnlyH8V105ExecutionContext(context)
% ISPROTECTIONONLYH8V105EXECUTIONCONTEXT Identify V105.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'protection-only-h8-v105-context-v1');
end
