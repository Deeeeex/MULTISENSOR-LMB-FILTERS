function detected = ...
        isObservableOneHopRiskLabelV162ExecutionContext(context)
% ISOBSERVABLEONEHOPRISKLABELV162EXECUTIONCONTEXT Detect V162 context.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'observable-one-hop-risk-label-v162-context-v1');
end
