function requirements = ...
    getFormationFovMultistyleAbsoluteDifficultyRequirements(config)
% GETFORMATIONFOVMULTISTYLEABSOLUTEDIFFICULTYREQUIREMENTS Frozen v5 gates.

requiredFields = { ...
    'sceneStyle', 'formationCount', 'targetGroupCount', ...
    'targetsPerTargetGroup'};
if ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config, requiredFields))
    error('A complete multistyle config is required for difficulty gates.');
end
targetCount = config.targetGroupCount * config.targetsPerTargetGroup;

if strcmp(config.sceneStyle, 'orthogonal-crossing')
    requirements = struct();
    return;
end
gate = getFormationFovMultistyleAbsoluteGeometryGate(config.sceneStyle);
switch gate.handoverNormalization
    case 'targets'
        handoverDenominator = targetCount;
    case 'targets-times-formation-transitions'
        handoverDenominator = targetCount * (config.formationCount - 1);
    otherwise
        error('Unknown multistyle handover normalization: %s', ...
            gate.handoverNormalization);
end
minimumHandovers = ceil( ...
    gate.minNormalizedHandovers * handoverDenominator);
requirements = struct( ...
    'maxBlackoutFraction', gate.maxBlackoutFraction, ...
    'maxFocusBlackoutFraction', gate.maxFocusBlackoutFraction, ...
    'maxPerTargetBlackoutFraction', gate.maxPerTargetBlackoutFraction, ...
    'maxConsecutiveBlackoutSteps', gate.maxConsecutiveBlackoutSteps, ...
    'minSingleFormationFraction', gate.minSingleFormationFraction, ...
    'minMultiFormationFraction', gate.minMultiFormationFraction, ...
    'maxFocusVisibleTargetsPerSensorTime', ...
        gate.maxFocusVisibleTargetsPerSensorTime, ...
    'minFocusHandovers', minimumHandovers, ...
    'minCrossGroupCloseEncounterFraction', ...
        gate.minCrossGroupCloseEncounterFraction, ...
    'minFormationOwnershipEntropy', ...
        gate.minFormationOwnershipEntropy, ...
    'minBlockageFocusOverlapFraction', ...
        gate.minBlockageFocusOverlapFraction);
end
