function context = buildRepeatedMultiGatewayHandoverV89ExecutionContext( ...
        presetName, seed, armId, measurementTimeCount)
% BUILDREPEATEDMULTIGATEWAYHANDOVERV89EXECUTIONCONTEXT Full episode gate.

protocol = getRepeatedMultiGatewayHandoverV89Protocol();
if ~ischar(presetName) || ~isrow(presetName) || ...
        ~any(strcmp(presetName, protocol.presets)) || ...
        ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= protocol.allSeeds || ...
        ~ischar(armId) || ~isrow(armId) || ...
        ~any(strcmp(armId, {protocol.referenceArmId, ...
            protocol.candidateArmId})) || ...
        ~isscalar(measurementTimeCount) || ...
        ~isfinite(measurementTimeCount) || ...
        measurementTimeCount < protocol.activationEndTime || ...
        measurementTimeCount ~= round(measurementTimeCount)
    error('RepeatedMultiGatewayV89:InvalidExecutionContextInput', ...
        'V89 requires a registered scale, seed, arm and full time axis.');
end
if strcmp(armId, protocol.referenceArmId)
    policyName = protocol.referencePolicyName;
else
    policyName = protocol.candidatePolicyName;
end
context = struct();
context.contractVersion = ...
    'repeated-multi-gateway-handover-v89-full-episode-context-v1';
context.capability = ...
    'repeated-multi-gateway-handover-full-episode-development';
context.action = ...
    'filter-repeated-multi-gateway-handover-full-episode-development';
context.protocolId = protocol.id;
context.presetName = presetName;
context.seed = seed;
context.armId = armId;
context.measurementTimeCount = measurementTimeCount;
context.policyName = policyName;
context.developmentEvidenceOnly = true;
end
