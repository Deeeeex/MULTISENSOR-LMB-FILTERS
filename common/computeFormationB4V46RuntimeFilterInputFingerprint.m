function fingerprint = ...
    computeFormationB4V46RuntimeFilterInputFingerprint( ...
        model, measurements, sensorTrajectories, neighborMap, ...
        commConfig, sourceFingerprint, caseContract, registry)
% COMPUTEFORMATIONB4V46RUNTIMEFILTERINPUTFINGERPRINT Filter boundary hash.

projected = ...
    projectFormationB4V46RuntimeFilterInputFingerprint(sourceFingerprint);
official = getFormationB4V46TrackingSourceRegistry();
validateAuthority(caseContract, registry, official, projected);
validateRuntimeInputs(model, measurements, sensorTrajectories, ...
    neighborMap, commConfig, caseContract, projected);

payload = rmfield(projected, 'canonicalSha256');
payload.modelSha256 = computeCanonicalValueSha256(model);
payload.measurementsSha256 = computeCanonicalValueSha256(measurements);
payload.sensorTrajectoriesSha256 = ...
    computeCanonicalValueSha256(sensorTrajectories);
payload.neighborMapSha256 = computeCanonicalValueSha256(neighborMap);
payload.communicationConfigSha256 = ...
    computeCanonicalValueSha256(commConfig);
fingerprint = payload;
fingerprint.canonicalSha256 = computeCanonicalValueSha256(payload);
if ~isequaln(fingerprint, projected)
    error('FormationB4V46RuntimeFingerprint:RuntimeInputDrift', ...
        'The runtime filter inputs differ from the sealed source.');
end
end

function validateAuthority(caseContract, registry, official, projected)
matching = strcmp({official.cases.id}, caseContract.id) & ...
    [official.cases.ordinal] == caseContract.ordinal;
if ~isequaln(registry, official) || nnz(matching) ~= 1 || ...
        ~isequaln(caseContract, official.cases(matching)) || ...
        ~strcmp(projected.registryId, official.id) || ...
        ~strcmp(projected.registryCanonicalSha256, ...
            official.canonicalSha256) || ...
        ~strcmp(projected.caseId, caseContract.id) || ...
        projected.caseOrdinal ~= caseContract.ordinal || ...
        ~strcmp(projected.caseCanonicalSha256, ...
            caseContract.caseCanonicalSha256) || ...
        projected.seed ~= caseContract.seed || ...
        ~strcmp(projected.seedRole, caseContract.seedRole) || ...
        projected.primaryMatrix ~= caseContract.primaryMatrix || ...
        projected.stressMatrix ~= caseContract.stressMatrix
    error('FormationB4V46RuntimeFingerprint:AuthorityDrift', ...
        'The runtime fingerprint authority differs from the core registry.');
end
end

function validateRuntimeInputs(model, measurements, trajectories, ...
        neighborMap, commConfig, caseContract, projected)
if ~isstruct(model) || ~isscalar(model) || ...
        ~isfield(model, 'dynamicTopologyScenario') || ...
        ~isstruct(model.dynamicTopologyScenario) || ...
        ~isscalar(model.dynamicTopologyScenario) || ...
        ~isfield(model.dynamicTopologyScenario, 'config') || ...
        ~isfield(model.dynamicTopologyScenario, 'seed') || ...
        ~isfield(model, 'formationB4V46RuntimeSourceEnvelope') || ...
        ~isstruct(model.formationB4V46RuntimeSourceEnvelope) || ...
        ~isscalar(model.formationB4V46RuntimeSourceEnvelope) || ...
        ~isstruct(commConfig) || ~isscalar(commConfig) || ...
        ~isfield(commConfig, 'linkUniforms')
    error('FormationB4V46RuntimeFingerprint:MalformedRuntimeInput', ...
        'The runtime filter input boundary is malformed.');
end
config = model.dynamicTopologyScenario.config;
envelope = model.formationB4V46RuntimeSourceEnvelope;
if ~isfield(config, 'presetName') || ...
        ~isfield(envelope, 'contractVersion') || ...
        ~strcmp(envelope.contractVersion, ...
            projected.runtimeFilterModelContractVersion) || ...
        ~isfield(envelope, 'registryId') || ...
        ~strcmp(envelope.registryId, projected.registryId) || ...
        ~isfield(envelope, 'registryCanonicalSha256') || ...
        ~strcmp(envelope.registryCanonicalSha256, ...
            projected.registryCanonicalSha256) || ...
        ~isfield(envelope, 'caseId') || ...
        ~strcmp(envelope.caseId, caseContract.id) || ...
        ~isfield(envelope, 'caseOrdinal') || ...
        envelope.caseOrdinal ~= caseContract.ordinal || ...
        ~isfield(envelope, 'caseCanonicalSha256') || ...
        ~strcmp(envelope.caseCanonicalSha256, ...
            caseContract.caseCanonicalSha256) || ...
        ~isfield(envelope, ...
            'registeredBirthPriorCanonicalSha256') || ...
        ~strcmp(envelope.registeredBirthPriorCanonicalSha256, ...
            projected.runtimeFilterBirthPriorSha256) || ...
        ~isfield(envelope, 'targetTrajectoryRealizationAbsent') || ...
        ~isequal(envelope.targetTrajectoryRealizationAbsent, true) || ...
        ~isfield(envelope, 'groundTruthAbsent') || ...
        ~isequal(envelope.groundTruthAbsent, true) || ...
        ~isfield(envelope, 'fullScenarioTargetMetadataAbsent') || ...
        ~isequal(envelope.fullScenarioTargetMetadataAbsent, true) || ...
        ~isfield(envelope, 'duplicateSensorTrajectoryCopiesAbsent') || ...
        ~isequal(envelope.duplicateSensorTrajectoryCopiesAbsent, true) || ...
        ~isfield(envelope, 'registeredBirthPriorRetained') || ...
        ~isequal(envelope.registeredBirthPriorRetained, true) || ...
        ~isfield(envelope, 'trackingOutcomeAuthorizationGranted') || ...
        ~isequal(envelope.trackingOutcomeAuthorizationGranted, false) || ...
        model.dynamicTopologyScenario.seed ~= caseContract.seed || ...
        ~strcmp(config.presetName, caseContract.presetName)
    error('FormationB4V46RuntimeFingerprint:CaseDrift', ...
        'The runtime model does not belong to the registered case.');
end
birthPayload = struct( ...
    'numberOfBirthLocations', model.numberOfBirthLocations, ...
    'birthTimeByLocation', model.birthTimeByLocation, ...
    'birthParameters', model.birthParameters);
if ~strcmp(computeCanonicalValueSha256(birthPayload), ...
        projected.runtimeFilterBirthPriorSha256)
    error('FormationB4V46RuntimeFingerprint:BirthPriorDrift', ...
        'The runtime birth prior differs from the sealed source.');
end
identity = buildDynamicTopologyPhysicalIdentityRegistry(config);
[expectedUniforms, expectedMetadata] = ...
    materializePhysicalUidDirectedDeliveryUniforms( ...
        caseContract.deliverySeed, identity.sensorPhysicalUids, ...
        caseContract.simulationLength);
if ~isequaln(commConfig.linkUniforms, expectedUniforms) || ...
        ~strcmp(identity.canonicalSha256, ...
            projected.physicalIdentityRegistrySha256) || ...
        ~strcmp(expectedMetadata.canonicalSha256, ...
            projected.deliveryUniformMetadataSha256) || ...
        ~strcmp(expectedMetadata.canonicalTensorSha256, ...
            projected.deliveryUniformCanonicalTensorSha256) || ...
        ~strcmp(expectedMetadata.materializedTensorSha256, ...
            projected.deliveryUniformMaterializedTensorSha256)
    error('FormationB4V46RuntimeFingerprint:DeliveryDrift', ...
        'The runtime delivery tensor is not the registered UID-keyed draw.');
end
if ~iscell(measurements) || ~iscell(trajectories) || ...
        ~iscell(neighborMap) || ...
        size(measurements, 1) ~= caseContract.numberOfSensors || ...
        size(measurements, 2) ~= caseContract.simulationLength || ...
        numel(trajectories) ~= caseContract.numberOfSensors || ...
        numel(neighborMap) ~= caseContract.numberOfSensors
    error('FormationB4V46RuntimeFingerprint:MalformedRuntimeInput', ...
        'Runtime dimensions differ from the registered case.');
end
end
