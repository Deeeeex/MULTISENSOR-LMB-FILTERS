function [selectedIndex, details] = ...
    selectReferenceConstrainedParetoCandidateIndex( ...
        messageSavingCount, networkRisk, switchCount, ordinal, ...
        referenceRisk, minimumMessageSavingCount)
% SELECTREFERENCECONSTRAINEDPARETOCANDIDATEINDEX Pure v39 selector.
%
% Candidate 1 must be the registered reference. Sparse candidates are
% eligible only when they meet the minimum saving and their exact risk is no
% larger than the reference. The selector then lexicographically maximizes
% saving, minimizes risk, minimizes switching, and minimizes stable ordinal.

messageSavingCount = reshape(messageSavingCount, 1, []);
networkRisk = reshape(networkRisk, 1, []);
switchCount = reshape(switchCount, 1, []);
ordinal = reshape(ordinal, 1, []);
candidateCount = numel(messageSavingCount);
if candidateCount < 1 || ...
        numel(networkRisk) ~= candidateCount || ...
        numel(switchCount) ~= candidateCount || ...
        numel(ordinal) ~= candidateCount || ...
        any(~isfinite(messageSavingCount)) || ...
        any(messageSavingCount < 0) || ...
        any(messageSavingCount ~= round(messageSavingCount)) || ...
        any(~isfinite(networkRisk)) || any(networkRisk < 0) || ...
        any(~isfinite(switchCount)) || any(switchCount < 0) || ...
        any(switchCount ~= round(switchCount)) || ...
        any(~isfinite(ordinal)) || any(ordinal < 1) || ...
        any(ordinal ~= round(ordinal)) || ...
        numel(unique(ordinal)) ~= candidateCount || ...
        ~isscalar(referenceRisk) || ~isfinite(referenceRisk) || ...
        referenceRisk < 0 || ...
        ~isscalar(minimumMessageSavingCount) || ...
        ~isfinite(minimumMessageSavingCount) || ...
        minimumMessageSavingCount < 1 || ...
        minimumMessageSavingCount ~= ...
            round(minimumMessageSavingCount) || ...
        messageSavingCount(1) ~= 0 || ...
        networkRisk(1) ~= referenceRisk
    error('ReferenceConstrainedPareto:InvalidCandidateBank', ...
        'The reference-constrained candidate summary is invalid.');
end

sparseMask = messageSavingCount >= minimumMessageSavingCount;
riskConstraintPassed = networkRisk <= referenceRisk;
selectableMask = sparseMask & riskConstraintPassed;
selectableMask(1) = true;
selectedIndex = 1;
for candidateIndex = 2:candidateCount
    if ~selectableMask(candidateIndex)
        continue;
    end
    if lexicographicallyBetter( ...
            candidateIndex, selectedIndex, messageSavingCount, ...
            networkRisk, switchCount, ordinal)
        selectedIndex = candidateIndex;
    end
end

details = struct( ...
    'contractVersion', ...
        'reference-constrained-pareto-candidate-selection-v1', ...
    'candidateCount', candidateCount, ...
    'referenceIndex', 1, ...
    'sparseMask', sparseMask, ...
    'riskConstraintPassedMask', riskConstraintPassed, ...
    'selectableMask', selectableMask, ...
    'riskRejectedSparseMask', sparseMask & ~riskConstraintPassed, ...
    'selectedIndex', selectedIndex, ...
    'selectionRule', ...
        'max-saving-min-risk-min-switch-min-stable-ordinal', ...
    'referenceRiskConstraint', ...
        'candidate-risk-less-than-or-equal-reference-exactly');
end

function better = lexicographicallyBetter( ...
        candidateIndex, incumbentIndex, messageSavingCount, ...
        networkRisk, switchCount, ordinal)
better = ...
    messageSavingCount(candidateIndex) > ...
        messageSavingCount(incumbentIndex) || ...
    (messageSavingCount(candidateIndex) == ...
        messageSavingCount(incumbentIndex) && ...
     networkRisk(candidateIndex) < networkRisk(incumbentIndex)) || ...
    (messageSavingCount(candidateIndex) == ...
        messageSavingCount(incumbentIndex) && ...
     networkRisk(candidateIndex) == networkRisk(incumbentIndex) && ...
     switchCount(candidateIndex) < switchCount(incumbentIndex)) || ...
    (messageSavingCount(candidateIndex) == ...
        messageSavingCount(incumbentIndex) && ...
     networkRisk(candidateIndex) == networkRisk(incumbentIndex) && ...
     switchCount(candidateIndex) == switchCount(incumbentIndex) && ...
     ordinal(candidateIndex) < ordinal(incumbentIndex));
end
