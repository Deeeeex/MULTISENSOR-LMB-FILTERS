function detected = ...
    isPositiveNetAddressablePayloadV97ExecutionContext(context)
% ISPOSITIVENETADDRESSABLEPAYLOADV97EXECUTIONCONTEXT Identify V97.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'positive-net-addressable-payload-v97-context-v1');
end
