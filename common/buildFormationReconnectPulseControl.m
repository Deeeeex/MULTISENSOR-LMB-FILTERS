function control = buildFormationReconnectPulseControl(context, options)
% BUILDFORMATIONRECONNECTPULSECONTROL Source-only v31 pulse projector.
%
% The selected graph remains the registered reference graph. Candidate
% actions temporarily increase selected formations' registered cross-edge
% weights while reducing receiver self weight by the same amount. Each
% single pulse and the requested joint pulse must preserve reference-
% supported label existence. No truth or future outcome is used.

if nargin < 2 || isempty(options)
    options = struct();
end
if ~isstruct(options) || ~isempty(fieldnames(options))
    error('ReconnectPulse:InvalidOptions', ...
        'The v31 probe does not accept option overrides.');
end
protocol = getFormationReconnectPulseProbeProtocol();
nodeCount = numel(context.localPosteriorBySensor);
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
if nodeCount < 2 || numel(groupIds) ~= nodeCount || ...
        formationCount < 2 || ...
        formationCount > protocol.maximumFormationCount || ...
        ~isfield(context, 'previousAdjacencyHistory') || ...
        size(context.previousAdjacencyHistory, 1) ~= nodeCount || ...
        size(context.previousAdjacencyHistory, 2) ~= nodeCount || ...
        size(context.previousAdjacencyHistory, 3) < 2
    error('ReconnectPulse:InvalidContext', ...
        'Reconnect-pulse context is invalid.');
end

[referenceAdjacency, referenceDetails] = ...
    selectTemporalCrossEdgeSuspensionPolicy( ...
        context, zeros(1, 0), struct( ...
            'dominantWeight', protocol.dominantWeight, ...
            'residualWeight', ...
                protocol.referenceResidualWeight));
referenceWeights = referenceDetails.fusionWeightMatrix;
referenceScore = scoreRoute( ...
    context, referenceAdjacency, referenceWeights, ...
    [], groupIds, protocol);
if ~referenceScore.safe || ...
        ~all(referenceDetails.rollingB3SensorPass) || ...
        ~all(referenceDetails.rollingB3FormationPass)
    error('ReconnectPulse:InvalidReference', ...
        'Registered reconnect reference failed its own safety gate.');
end
referenceDistributions = ...
    referenceScore.networkDetails.receiverDistributions;

pulseLevels = reshape(protocol.pulseResidualWeights, 1, []);
levelCount = numel(pulseLevels);
singleScores = cell(formationCount, levelCount);
singleWeights = cell(formationCount, levelCount);
singleAvailable = false(formationCount, levelCount);
singleSafe = false(formationCount, levelCount);
singleEligible = false(formationCount, levelCount);
singleImprovement = nan(formationCount, levelCount);
singleFailureIdentifier = repmat({''}, formationCount, levelCount);
singleFailureMessage = repmat({''}, formationCount, levelCount);
for formationIdx = 1:formationCount
    for levelIdx = 1:levelCount
        try
            weights = applyPulseWeights( ...
                referenceWeights, referenceDetails, groupIds, ...
                groups(formationIdx), pulseLevels(levelIdx));
            score = scoreRoute( ...
                context, referenceAdjacency, weights, ...
                referenceDistributions, groupIds, protocol);
            improvement = disagreementImprovement( ...
                referenceScore.networkRisk, score.networkRisk);
            singleWeights{formationIdx, levelIdx} = weights;
            singleScores{formationIdx, levelIdx} = score;
            singleAvailable(formationIdx, levelIdx) = true;
            singleSafe(formationIdx, levelIdx) = score.safe;
            singleImprovement(formationIdx, levelIdx) = improvement;
            singleEligible(formationIdx, levelIdx) = ...
                score.safe && improvement >= ...
                    protocol.minimumDisagreementImprovementFraction - ...
                        1e-12;
        catch errorInfo
            if ~isExpectedUnavailable(errorInfo)
                rethrow(errorInfo);
            end
            singleFailureIdentifier{formationIdx, levelIdx} = ...
                getErrorField(errorInfo, 'identifier');
            singleFailureMessage{formationIdx, levelIdx} = ...
                getErrorField(errorInfo, 'message');
        end
    end
end

requestedMask = false(1, formationCount);
requestedPulseWeight = nan(1, formationCount);
requestedImprovement = nan(1, formationCount);
for formationIdx = 1:formationCount
    eligibleLevels = find(singleEligible(formationIdx, :));
    if isempty(eligibleLevels)
        continue;
    end
    [bestImprovement, localIdx] = max( ...
        singleImprovement(formationIdx, eligibleLevels));
    selectedLevel = eligibleLevels(localIdx);
    requestedMask(formationIdx) = true;
    requestedPulseWeight(formationIdx) = ...
        pulseLevels(selectedLevel);
    requestedImprovement(formationIdx) = bestImprovement;
end

selectedMask = requestedMask;
projectionRemovalOrder = zeros(1, 0);
selectedWeights = referenceWeights;
selectedScore = referenceScore;
jointEvaluationCount = 0;
while any(selectedMask)
    jointEvaluationCount = jointEvaluationCount + 1;
    candidateWeights = referenceWeights;
    selectedIndices = find(selectedMask);
    for localIdx = 1:numel(selectedIndices)
        formationIdx = selectedIndices(localIdx);
        candidateWeights = applyPulseWeights( ...
            candidateWeights, referenceDetails, groupIds, ...
            groups(formationIdx), ...
            requestedPulseWeight(formationIdx));
    end
    candidateScore = scoreRoute( ...
        context, referenceAdjacency, candidateWeights, ...
        referenceDistributions, groupIds, protocol);
    candidateImprovement = disagreementImprovement( ...
        referenceScore.networkRisk, candidateScore.networkRisk);
    if candidateScore.safe && candidateImprovement >= ...
            protocol.minimumDisagreementImprovementFraction - 1e-12
        selectedWeights = candidateWeights;
        selectedScore = candidateScore;
        break;
    end
    [~, removeLocalIdx] = min( ...
        requestedImprovement(selectedIndices));
    removeIdx = selectedIndices(removeLocalIdx);
    projectionRemovalOrder(end + 1) = ...
        groups(removeIdx); %#ok<AGROW>
    selectedMask(removeIdx) = false;
end
selectedFormationIds = groups(selectedMask);
selectedPulseWeight = requestedPulseWeight;
selectedPulseWeight(~selectedMask) = NaN;
selectedImprovement = disagreementImprovement( ...
    referenceScore.networkRisk, selectedScore.networkRisk);

weightSupport = referenceAdjacency | logical(eye(nodeCount));
if any(~isfinite(selectedWeights(:))) || ...
        any(selectedWeights(:) < -1e-12) || ...
        any(selectedWeights(:) > 1e-12 & ~weightSupport(:)) || ...
        any(abs(sum(selectedWeights, 2) - 1) > 1e-12) || ...
        ~selectedScore.safe || ...
        (~isempty(selectedFormationIds) && ...
         selectedImprovement < ...
            protocol.minimumDisagreementImprovementFraction - 1e-12)
    error('ReconnectPulse:InvalidSelection', ...
        'Selected reconnect pulse violates a frozen invariant.');
end

evaluatedRouteCount = 1 + formationCount * levelCount + ...
    jointEvaluationCount;
if evaluatedRouteCount > protocol.maximumControlRouteEvaluations
    error('ReconnectPulse:EvaluationBudgetExceeded', ...
        'Reconnect-pulse evaluation exceeded its frozen budget.');
end

control = struct();
control.contractVersion = ...
    'formation-reconnect-pulse-control-v1';
control.protocolId = protocol.id;
control.nodeCount = nodeCount;
control.formationCount = formationCount;
control.groupIds = groupIds;
control.groups = groups;
control.referenceAdjacency = referenceAdjacency;
control.referenceFusionWeights = referenceWeights;
control.referencePolicyDetails = referenceDetails;
control.referenceScore = referenceScore;
control.pulseResidualWeights = pulseLevels;
control.singleActionScores = singleScores;
control.singleActionFusionWeights = singleWeights;
control.singleActionAvailableMask = singleAvailable;
control.singleActionSafetyMask = singleSafe;
control.singleActionEligibleMask = singleEligible;
control.singleDisagreementImprovementFraction = singleImprovement;
control.singleFailureIdentifier = singleFailureIdentifier;
control.singleFailureMessage = singleFailureMessage;
control.requestedFormationIds = groups(requestedMask);
control.requestedPulseWeightByFormation = requestedPulseWeight;
control.requestedDisagreementImprovementByFormation = ...
    requestedImprovement;
control.selectedFormationIds = selectedFormationIds;
control.selectedPulseWeightByFormation = selectedPulseWeight;
control.projectionRemovalOrder = projectionRemovalOrder;
control.selectedAdjacency = referenceAdjacency;
control.selectedFusionWeights = selectedWeights;
control.selectedScore = selectedScore;
control.selectedDisagreementImprovementFraction = ...
    selectedImprovement;
control.selectedActionName = buildActionName( ...
    groups, selectedPulseWeight);
control.referenceFallbackUsed = isempty(selectedFormationIds);
control.referenceMessageCount = nnz(referenceAdjacency);
control.selectedMessageCount = nnz(referenceAdjacency);
control.messageCountParityWithReference = true;
control.evaluatedRouteCount = evaluatedRouteCount;
control.safeSingleActionCount = nnz(singleSafe);
control.eligibleSingleActionCount = nnz(singleEligible);
control.selectionUsesCurrentPosterior = true;
control.selectionUsesCurrentLinkReliability = true;
control.selectionUsesSelectedTopologyHistory = true;
control.selectedRollingB3SensorPass = ...
    referenceDetails.rollingB3SensorPass;
control.selectedRollingB3FormationPass = ...
    referenceDetails.rollingB3FormationPass;
control.truthUsed = false;
control.futureOutcomeUsed = false;
control.openedDevelopmentEvidenceOnly = true;
control.validationClaimAllowed = false;
end

function weights = applyPulseWeights( ...
        weights, referenceDetails, groupIds, formationId, pulseWeight)
sources = reshape(referenceDetails.residualSourcesByReceiver, 1, []);
crossMask = groupIds ~= groupIds(sources);
receiver = find(crossMask & groupIds == formationId);
if numel(receiver) ~= 1
    error('ReconnectPulse:InvalidCandidate', ...
        'Registered cross receiver is ambiguous.');
end
sender = sources(receiver);
currentWeight = weights(receiver, sender);
delta = pulseWeight - currentWeight;
if delta <= 0 || weights(receiver, receiver) - delta < -1e-12
    error('ReconnectPulse:InvalidCandidate', ...
        'Reconnect pulse cannot be assigned from receiver self weight.');
end
weights(receiver, receiver) = ...
    weights(receiver, receiver) - delta;
weights(receiver, sender) = pulseWeight;
end

function score = scoreRoute( ...
        context, adjacency, weights, referenceDistributions, ...
        groupIds, protocol)
enumerationOptions = struct( ...
    'maximumIncomingCount', ...
        protocol.maximumIncomingCountForOutcomeEnumeration);
[networkRisk, networkDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, adjacency, weights, enumerationOptions);
if isempty(referenceDistributions)
    referenceDistributions = networkDetails.receiverDistributions;
end
retentionOptions = struct( ...
    'referenceSupportThreshold', ...
        protocol.referenceSupportThreshold, ...
    'decisionExistenceThreshold', ...
        protocol.decisionExistenceThreshold, ...
    'receiverTailFraction', ...
        protocol.retentionReceiverTailFraction, ...
    'receiverTailWeight', ...
        protocol.retentionReceiverTailWeight);
[retentionRisk, retentionDetails] = ...
    computeLmbReferenceExistenceRetentionRisk( ...
        referenceDistributions, ...
        networkDetails.receiverDistributions, ...
        groupIds, retentionOptions);
minimumFormationCardinalityChange = min( ...
    retentionDetails.formationMeanCardinalityChange);
minimumSupportedLabelRetentionRatio = min( ...
    retentionDetails.minimumSupportedLabelRetentionRatio);
decisionThresholdCrossingCount = sum( ...
    retentionDetails.decisionThresholdCrossingCount);
safe = ...
    retentionRisk <= protocol.maximumRetentionRisk + 1e-12 && ...
    minimumFormationCardinalityChange >= protocol. ...
        minimumFormationMeanCardinalityChange - 1e-12 && ...
    minimumSupportedLabelRetentionRatio >= protocol. ...
        minimumSupportedLabelRetentionRatio - 1e-12 && ...
    decisionThresholdCrossingCount <= protocol. ...
        maximumDecisionThresholdCrossingCount;
score = struct( ...
    'networkRisk', networkRisk, ...
    'networkDetails', networkDetails, ...
    'retentionRisk', retentionRisk, ...
    'retentionDetails', retentionDetails, ...
    'minimumFormationCardinalityChange', ...
        minimumFormationCardinalityChange, ...
    'minimumSupportedLabelRetentionRatio', ...
        minimumSupportedLabelRetentionRatio, ...
    'decisionThresholdCrossingCount', ...
        decisionThresholdCrossingCount, ...
    'safe', safe, ...
    'truthUsed', false, ...
    'futureOutcomeUsed', false);
end

function value = disagreementImprovement(referenceRisk, candidateRisk)
value = (referenceRisk - candidateRisk) / max(referenceRisk, eps);
end

function name = buildActionName(groups, weights)
selected = find(isfinite(weights));
if isempty(selected)
    name = 'reference';
    return;
end
parts = cell(1, numel(selected));
for idx = 1:numel(selected)
    formationIdx = selected(idx);
    weightText = strrep(sprintf('%.3f', ...
        weights(formationIdx)), '.', 'p');
    parts{idx} = sprintf('f%d-w%s', ...
        groups(formationIdx), weightText);
end
name = ['reconnect-pulse-', strjoin(parts, '-')];
end

function value = isExpectedUnavailable(errorInfo)
identifier = getErrorField(errorInfo, 'identifier');
value = strcmp(identifier, 'ReconnectPulse:InvalidCandidate');
end

function value = getErrorField(errorInfo, fieldName)
value = '';
try
    value = errorInfo.(fieldName);
catch
    value = '';
end
if isempty(value)
    value = '';
end
end
