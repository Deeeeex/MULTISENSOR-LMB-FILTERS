function [adjacency, details] = ...
        selectCorrectedFixedStaticFormationBackboneV227Policy( ...
            context, registration)
% SELECTCORRECTEDFIXEDSTATICFORMATIONBACKBONEV227POLICY Frozen route.

protocol = getCorrectedStaticRoutingBaselineV227Protocol();
required = {'contractVersion', 'adjacency', 'fusionWeightMatrix', ...
    'selectionDetails', 'messageCount'};
nodeCount = numel(context.localPosteriorBySensor);
if ~isstruct(registration) || ~isscalar(registration) || ...
        ~all(isfield(registration, required)) || ...
        ~strcmp(registration.contractVersion, ...
            'corrected-static-routing-v227-registration-v1') || ...
        ~isequal(size(registration.adjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(registration.fusionWeightMatrix), ...
            [nodeCount, nodeCount]) || ...
        registration.messageCount ~= ...
            protocol.directedInputsPerReceiver * nodeCount
    error('CorrectedStaticRoutingV227:InvalidStaticRegistration', ...
        'The fixed-static route registration is malformed.');
end
adjacency = logical(registration.adjacency);
if any(adjacency(:) & ~logical(context.physicalAdjacency(:)))
    error('CorrectedStaticRoutingV227:StaticRouteNotPhysical', ...
        'The registered fixed route is not physical on the current page.');
end

details = registration.selectionDetails;
details.routeObjectiveComponents = reshape(details.objective, 1, []);
details.objective = min(details.routeObjectiveComponents);
details.contractVersion = ...
    'corrected-static-routing-v227-fixed-policy-v1';
details.protocolId = protocol.id;
details.armId = protocol.staticArmId;
details.fusionWeightMatrix = registration.fusionWeightMatrix;
details.currentPhysicalActionSetUsed = false;
details.currentPhysicalFeasibilityChecked = true;
details.currentGeometryUsed = false;
details.currentLinkReliabilityUsed = false;
details.posteriorUsed = false;
details.truthUsed = false;
details.futureOutcomeUsed = false;
details.referenceMessageCount = nnz(adjacency);
details.currentMessageCount = nnz(adjacency);
details.referenceFallbackUsed = false;
details.selectionSeconds = 0;
details.scheduleCertificate = buildSchedule( ...
    context.currentTime, 'static-all-time-physical');
end

function schedule = buildSchedule(currentTime, phase)
schedule = struct( ...
    'contractVersion', ...
        'corrected-static-routing-v227-schedule-v1', ...
    'currentTime', currentTime, 'phase', phase, 'phaseIndex', 2, ...
    'gatewayIndices', zeros(1, 0), ...
    'formationIds', zeros(1, 0), ...
    'sourceIndices', zeros(1, 0), ...
    'proposalGatewayCount', 0, 'selectedGatewayCount', 0, ...
    'pendingAcquisitionTime', NaN, 'messageParityPassed', true, ...
    'rollingSensorStrong', true, 'rollingFormationStrong', true, ...
    'referenceFallbackUsed', false, 'cycleSelected', true);
end
