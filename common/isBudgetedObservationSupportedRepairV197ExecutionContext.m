function detected = ...
    isBudgetedObservationSupportedRepairV197ExecutionContext(context)
% ISBUDGETEDOBSERVATIONSUPPORTEDREPAIRV197EXECUTIONCONTEXT Identify V197.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'budgeted-observation-supported-repair-v197-context-v1');
end

