function detected = ...
        isLearnedOneHopSafeLabelV169ExecutionContext(context)
% ISLEARNEDONEHOPSAFELABELV169EXECUTIONCONTEXT Detect V169 context.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'learned-one-hop-safe-label-v169-context-v1');
end
