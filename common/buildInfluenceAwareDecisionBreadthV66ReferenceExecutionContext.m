function context = ...
    buildInfluenceAwareDecisionBreadthV66ReferenceExecutionContext( ...
        presetName, seed, currentTime)
% BUILDINFLUENCEAWAREDECISIONBREADTHV66REFERENCEEXECUTIONCONTEXT Source only.

protocol = ...
    getInfluenceAwareDecisionBreadthV66SceneDiscoveryProtocol();
if ~ischar(presetName) || ~ismember(presetName, protocol.presets) || ...
        ~isscalar(seed) || ~ismember(seed, protocol.allSeeds) || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= max(protocol.snapshotTimes)
    error('InfluenceAwareSceneV66:InvalidReferenceWindow', ...
        'The V66 relay reference request is not registered.');
end
context = struct();
context.contractVersion = ...
    'influence-aware-decision-breadth-v66-reference-context-v1';
context.capability = ...
    'influence-aware-decision-breadth-reference-development';
context.action = ...
    'filter-influence-aware-decision-breadth-reference-development';
context.protocolId = protocol.id;
context.phase = 'reference-cache';
context.presetName = presetName;
context.seed = seed;
context.currentTime = currentTime;
context.measurementTimeCount = currentTime;
context.policyName = protocol.referencePolicyName;
context.developmentEvidenceOnly = true;
end
