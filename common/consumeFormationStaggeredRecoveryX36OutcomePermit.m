function [claim, metadataPath] = ...
    consumeFormationStaggeredRecoveryX36OutcomePermit( ...
        permit, releaseDescriptor, generationGitCommit, ...
        reportPath, matPath, completionMarkerPath)
% CONSUMEFORMATIONSTAGGEREDRECOVERYX36OUTCOMEPERMIT Global one-shot claim.
%
% The authorization-consumption event is creation of one fixed annotated tag
% on the pinned remote. Git receive-pack serializes ref creation, so only one
% worktree, clone, or host can win. A git-common-dir mirror records the winner
% across local worktrees. Neither record is removed by any error path.

assertClaimInputs( ...
    permit, releaseDescriptor, generationGitCommit, ...
    reportPath, matPath, completionMarkerPath);

repoRoot = fileparts(fileparts(mfilename('fullpath')));
originalDirectory = cd(repoRoot);
directoryCleanup = onCleanup( ...
    @() cd(originalDirectory)); %#ok<NASGU>
assertNoRemoteUrlRewrite();

[commonStatus, gitCommonDirectory] = system( ...
    'git --no-replace-objects rev-parse --git-common-dir');
gitCommonDirectory = strtrim(gitCommonDirectory);
if commonStatus ~= 0 || isempty(gitCommonDirectory)
    error('X36OutcomePermit:ClaimCreationFailed', ...
        'Could not resolve the repository common Git directory.');
end
if ~isAbsolutePath(gitCommonDirectory)
    gitCommonDirectory = fullfile(repoRoot, gitCommonDirectory);
end
claimDirectory = fullfile(gitCommonDirectory, ...
    permit.outcomeClaimCommonDirectoryRelativePath);
metadataPath = fullfile( ...
    claimDirectory, permit.outcomeClaimMetadataFileName);
parentDirectory = fileparts(claimDirectory);
if exist(parentDirectory, 'file') == 2
    error('X36OutcomePermit:ClaimCreationFailed', ...
        'The outcome-claim parent path is a file.');
end
if exist(parentDirectory, 'dir') ~= 7
    [created, message] = mkdir(parentDirectory);
    if ~created || exist(parentDirectory, 'dir') ~= 7
        error('X36OutcomePermit:ClaimCreationFailed', ...
            'Could not create the outcome-claim parent: %s', message);
    end
end
if exist(claimDirectory, 'file') ~= 0 || ...
        exist(claimDirectory, 'dir') == 7
    error('X36OutcomePermit:AlreadyConsumed', ...
        ['The local common-dir mirror records this exact X36 outcome ', ...
         'permit as already consumed.']);
end

remoteClaim = createRemoteAtomicClaim( ...
    permit, generationGitCommit);

% The remote tag above is the global consumption event. From this point on,
% every failure is deliberately irreversible. POSIX mkdir provides a second
% atomic claim shared by every worktree in this local repository.
if ~isShellSafePath(claimDirectory)
    error('X36OutcomePermit:ClaimMetadataWriteFailed', ...
        ['The remote permit is consumed, but the local common-dir ', ...
         'claim path is not shell-safe.']);
end
[claimStatus, claimMessage] = system(sprintf( ...
    'mkdir ''%s'' 2>&1', claimDirectory));
if claimStatus ~= 0
    if exist(claimDirectory, 'dir') == 7 || ...
            exist(claimDirectory, 'file') ~= 0
        error('X36OutcomePermit:AlreadyConsumed', ...
            ['The remote permit is consumed and another local worktree ', ...
             'owns the common-dir mirror.']);
    end
    error('X36OutcomePermit:ClaimMetadataWriteFailed', ...
        ['The remote permit is consumed, but local atomic claim ', ...
         'creation failed: %s'], strtrim(claimMessage));
end

claim = struct();
claim.contractVersion = permit.outcomeClaimContractVersion;
claim.claimedAt = datestr(now, 31);
claim.generationGitCommit = generationGitCommit;
claim.permitCanonicalSha256 = permit.permitCanonicalSha256;
claim.releaseDescriptorCanonicalSha256 = ...
    releaseDescriptor.descriptorCanonicalSha256;
claim.releaseTagName = releaseDescriptor.releaseTagName;
claim.releaseTagObjectId = releaseDescriptor.releaseTagObjectId;
claim.gateGitCommit = releaseDescriptor.gateGitCommit;
claim.releaseRemoteUrl = permit.releaseRemoteUrl;
claim.releaseBranchRef = permit.releaseBranchRef;
claim.remoteClaimTagName = permit.outcomeClaimRemoteTagName;
claim.remoteClaimRef = permit.outcomeClaimRemoteRef;
claim.remoteClaimTagObjectId = remoteClaim.tagObjectId;
claim.remoteClaimTargetCommit = remoteClaim.targetCommit;
claim.remoteClaimCreatedAtomically = true;
claim.remoteClaimVerifiedAfterPush = true;
claim.remoteClaimPushPorcelainNewTagConfirmed = ...
    remoteClaim.pushPorcelainNewTagConfirmed;
claim.authorizedPairCount = permit.authorizedPairCount;
claim.exactArmCountPerPair = permit.exactArmCountPerPair;
claim.maximumPairedRunCountPerPair = ...
    permit.maximumPairedRunCountPerPair;
claim.maximumOfficialAggregateRunCount = ...
    permit.maximumOfficialAggregateRunCount;
claim.reportPath = reportPath;
claim.matPath = matPath;
claim.completionMarkerPath = completionMarkerPath;
claim.gitCommonDirectory = gitCommonDirectory;
claim.claimDirectory = claimDirectory;
claim.metadataPath = metadataPath;
claim.localCommonDirectoryCreatedAtomically = true;
claim.claimConsumedBeforeTrackingOutcome = true;
claim.failedOrInterruptedRunConsumesAuthorization = true;
claim.outcomeSelectionOrRankingAuthorized = false;
claim.recoveryRerunAuthorized = false;

temporaryMetadataPath = [tempname(claimDirectory), '.mat'];
temporaryCleanup = onCleanup( ...
    @() deleteIfPresent(temporaryMetadataPath)); %#ok<NASGU>
try
    save('-mat7-binary', temporaryMetadataPath, 'claim');
    if exist(metadataPath, 'file') ~= 0
        error('X36OutcomePermit:ClaimMetadataWriteFailed', ...
            'The fixed common-dir claim metadata already exists.');
    end
    [moved, message] = movefile(temporaryMetadataPath, metadataPath);
    if ~moved || exist(metadataPath, 'file') ~= 2
        error('X36OutcomePermit:ClaimMetadataWriteFailed', ...
            'Could not publish common-dir claim metadata: %s', message);
    end
catch claimError
    deleteIfPresent(temporaryMetadataPath);
    if strcmp(claimError.identifier, ...
            'X36OutcomePermit:ClaimMetadataWriteFailed')
        rethrow(claimError);
    end
    error('X36OutcomePermit:ClaimMetadataWriteFailed', ...
        ['The remote permit is consumed, but its local metadata could ', ...
         'not be published: %s'], claimError.message);
end
end

function remoteClaim = createRemoteAtomicClaim( ...
        permit, generationGitCommit)
remoteUrl = permit.releaseRemoteUrl;
claimTagName = permit.outcomeClaimRemoteTagName;
claimRef = permit.outcomeClaimRemoteRef;
if ~isShellSafePath(remoteUrl) || ...
        ~isShellSafePath(claimTagName) || ...
        ~isShellSafePath(claimRef)
    error('X36OutcomePermit:InvalidClaimContract', ...
        'The fixed remote-claim coordinates are not shell-safe.');
end

[remoteStatus, remoteListing] = system(sprintf([ ...
    remoteGitEnvironment(), ...
    'git ls-remote --tags ''%s'' ''%s'''], ...
    remoteUrl, claimRef));
if remoteStatus ~= 0
    error('X36OutcomePermit:RemoteClaimUnavailable', ...
        ['The remote one-shot claim cannot be checked; refusing to ', ...
         'open any tracking outcome.']);
end
if ~isempty(strtrim(remoteListing))
    error('X36OutcomePermit:AlreadyConsumed', ...
        'The pinned remote already contains the one-shot outcome claim.');
end

[localTagStatus, ~] = system(sprintf( ...
    'git show-ref --verify --quiet ''%s''', claimRef));
if localTagStatus == 0
    error('X36OutcomePermit:AlreadyConsumed', ...
        'The local repository already contains the one-shot claim tag.');
end
nonce = computeCanonicalValueSha256(struct( ...
    'tempname', tempname, 'claimedAt', datestr(now, 31), ...
    'generationGitCommit', generationGitCommit));
tagMessage = sprintf([ ...
    'Irreversible X36 v37 v3 outcome claim. ', ...
    'Generation commit %s. Nonce %s.'], ...
    generationGitCommit, nonce);
if ~isShellSafePath(tagMessage)
    error('X36OutcomePermit:InvalidClaimContract', ...
        'The generated one-shot claim message is not shell-safe.');
end
[tagStatus, tagOutput] = system(sprintf([ ...
    'git -c core.hooksPath=/dev/null -c tag.gpgSign=false ', ...
    'tag -a ''%s'' ''%s'' -m ''%s'' 2>&1'], ...
    claimTagName, generationGitCommit, tagMessage));
if tagStatus ~= 0
    error('X36OutcomePermit:AlreadyConsumed', ...
        'Could not create the unique local claim tag: %s', ...
        strtrim(tagOutput));
end
[objectStatus, tagObjectId] = system(sprintf( ...
    'git --no-replace-objects rev-parse --verify ''%s''', claimRef));
tagObjectId = strtrim(tagObjectId);
if objectStatus ~= 0 || ~isGitObjectId(tagObjectId)
    error('X36OutcomePermit:RemoteClaimUnavailable', ...
        ['The local one-shot tag exists but its object cannot be ', ...
         'resolved; refusing any outcome.']);
end

[pushStatus, pushOutput] = system(sprintf([ ...
    remoteGitEnvironment(), ...
    'git -c core.hooksPath=/dev/null -c push.gpgSign=false ', ...
    'push --no-verify --porcelain ''%s'' ', ...
    '''%s:%s'' 2>&1'], ...
    remoteUrl, claimRef, claimRef));
[verifyStatus, verifiedListing] = system(sprintf([ ...
    remoteGitEnvironment(), ...
    'git ls-remote --tags ''%s'' ', ...
    '''%s'' ''%s^{}'''], ...
    remoteUrl, claimRef, claimRef));
actualLines = sort(splitNonemptyLines(verifiedListing));
pushLines = splitNonemptyLines(pushOutput);
expectedNewTagLine = sprintf( ...
    '*\t%s:%s\t[new tag]', claimRef, claimRef);
newTagConfirmed = any(strcmp(pushLines, expectedNewTagLine));
expectedLines = sort({ ...
    sprintf('%s\t%s', tagObjectId, claimRef), ...
    sprintf('%s\t%s^{}', generationGitCommit, claimRef)});
if pushStatus ~= 0 || ~newTagConfirmed || ...
        verifyStatus ~= 0 || ~isequal(actualLines, expectedLines)
    if verifyStatus == 0 && ~isempty(actualLines)
        error('X36OutcomePermit:AlreadyConsumed', ...
            ['Another worktree, clone, or host won the remote ', ...
             'one-shot claim.']);
    end
    error('X36OutcomePermit:RemoteClaimUnavailable', ...
        ['The local tag may exist, but exclusive remote claim creation ', ...
         'was not confirmed; refusing any outcome.']);
end
remoteClaim = struct( ...
    'tagObjectId', tagObjectId, ...
    'targetCommit', generationGitCommit, ...
    'pushPorcelainNewTagConfirmed', true);
end

function assertClaimInputs( ...
        permit, releaseDescriptor, generationGitCommit, ...
        reportPath, matPath, completionMarkerPath)
requiredPermitFields = { ...
    'contractVersion', 'permitCanonicalSha256', ...
    'releaseRemoteUrl', 'releaseBranchRef', ...
    'outcomeClaimContractVersion', ...
    'outcomeClaimCommonDirectoryRelativePath', ...
    'outcomeClaimMetadataFileName', ...
    'outcomeClaimRemoteTagName', 'outcomeClaimRemoteRef', ...
    'outcomeClaimRemoteMustBeCreatedAtomically', ...
    'outcomeClaimMustCoverAllWorktreesAndClones', ...
    'outcomeClaimMustPrecedeTrackingOutcome', ...
    'failedClaimConsumesAuthorization', ...
    'authorizedPairCount', 'exactArmCountPerPair', ...
    'maximumPairedRunCountPerPair', ...
    'maximumOfficialAggregateRunCount'};
requiredReleaseFields = { ...
    'contractVersion', 'descriptorCanonicalSha256', ...
    'releaseTagName', 'releaseTagObjectId', 'gateGitCommit', ...
    'releaseRemoteUrl', 'releaseBranchRef', ...
    'remotePublicationRequired'};
if ~isstruct(permit) || ~isscalar(permit) || ...
        ~all(isfield(permit, requiredPermitFields)) || ...
        ~isstruct(releaseDescriptor) || ...
        ~isscalar(releaseDescriptor) || ...
        ~all(isfield(releaseDescriptor, requiredReleaseFields)) || ...
        ~strcmp(permit.contractVersion, ...
            'formation-staggered-recovery-x36-outcome-permit-v3') || ...
        ~strcmp(permit.outcomeClaimContractVersion, [ ...
            'formation-staggered-recovery-x36-', ...
            'outcome-claim-v1']) || ...
        ~strcmp(releaseDescriptor.contractVersion, [ ...
            'formation-staggered-recovery-x36-', ...
            'outcome-release-descriptor-v1']) || ...
        ~isSha256(permit.permitCanonicalSha256) || ...
        ~isSha256(releaseDescriptor.descriptorCanonicalSha256) || ...
        ~isGitObjectId(generationGitCommit) || ...
        ~isGitObjectId(releaseDescriptor.gateGitCommit) || ...
        ~isGitObjectId(releaseDescriptor.releaseTagObjectId) || ...
        ~strcmp(releaseDescriptor.releaseRemoteUrl, ...
            permit.releaseRemoteUrl) || ...
        ~strcmp(releaseDescriptor.releaseBranchRef, ...
            permit.releaseBranchRef) || ...
        ~isequal(releaseDescriptor.remotePublicationRequired, true) || ...
        ~strcmp(permit.outcomeClaimRemoteRef, ...
            ['refs/tags/', permit.outcomeClaimRemoteTagName]) || ...
        ~isequal(permit. ...
            outcomeClaimRemoteMustBeCreatedAtomically, true) || ...
        ~isequal(permit. ...
            outcomeClaimMustCoverAllWorktreesAndClones, true) || ...
        ~isequal(permit.outcomeClaimMustPrecedeTrackingOutcome, true) || ...
        ~isequal(permit.failedClaimConsumesAuthorization, true) || ...
        ~isequal(permit.authorizedPairCount, 3) || ...
        ~isequal(permit.exactArmCountPerPair, 2) || ...
        ~isequal(permit.maximumPairedRunCountPerPair, 1) || ...
        ~isequal(permit.maximumOfficialAggregateRunCount, 1) || ...
        ~ischar(permit.outcomeClaimCommonDirectoryRelativePath) || ...
        ~isrow(permit.outcomeClaimCommonDirectoryRelativePath) || ...
        isempty(permit.outcomeClaimCommonDirectoryRelativePath) || ...
        isAbsolutePath(permit.outcomeClaimCommonDirectoryRelativePath) || ...
        ~isempty(regexp( ...
            permit.outcomeClaimCommonDirectoryRelativePath, ...
            '(^|[/\\])\.\.([/\\]|$)', 'once')) || ...
        ~strcmp(permit.outcomeClaimMetadataFileName, 'claim.mat') || ...
        ~ischar(reportPath) || ~isrow(reportPath) || ...
        ~ischar(matPath) || ~isrow(matPath) || ...
        ~ischar(completionMarkerPath) || ...
        ~isrow(completionMarkerPath) || ...
        ~strcmp(completionMarkerPath, [matPath, '.complete'])
    error('X36OutcomePermit:InvalidClaimContract', ...
        'The global atomic outcome-claim contract is malformed.');
end
end

function result = isAbsolutePath(path)
result = ~isempty(regexp(path, '^(/|[A-Za-z]:[/\\])', 'once'));
end

function assertNoRemoteUrlRewrite()
[status, listing] = system([ ...
    'git config --show-origin --get-regexp ', ...
    '''^url\..*\.(insteadOf|pushInsteadOf)$''']);
if ~(status == 0 || status == 1) || ~isempty(strtrim(listing))
    error('X36OutcomePermit:RemoteUrlRewriteRejected', ...
        ['Git URL insteadOf/pushInsteadOf rewrites are forbidden for ', ...
         'the global one-shot claim transport.']);
end
[hookStatus, hookListing] = system( ...
    'git config --show-origin --get-all core.hooksPath');
if ~(hookStatus == 0 || hookStatus == 1) || ...
        ~isempty(strtrim(hookListing))
    error('X36OutcomePermit:GitHookOverrideRejected', ...
        ['A custom core.hooksPath is forbidden around the global ', ...
         'one-shot claim.']);
end
end

function value = remoteGitEnvironment()
value = [ ...
    'GIT_TERMINAL_PROMPT=0 ', ...
    ['GIT_SSH_COMMAND=''ssh -oBatchMode=yes -oHostname=github.com ', ...
     '-oHostKeyAlias=github.com'' ']];
end

function result = isShellSafePath(value)
result = ischar(value) && isrow(value) && ...
    isempty(strfind(value, '''')) && ...
    isempty(regexp(value, '[\r\n]', 'once'));
end

function lines = splitNonemptyLines(value)
value = strtrim(value);
if isempty(value)
    lines = cell(1, 0);
else
    lines = regexp(value, '\r?\n', 'split');
    lines = reshape(lines, 1, []);
end
end

function result = isSha256(value)
result = ischar(value) && isrow(value) && ...
    ~isempty(regexp(value, '^[0-9a-f]{64}$', 'once'));
end

function result = isGitObjectId(value)
result = ischar(value) && isrow(value) && ...
    ~isempty(regexp(value, '^[0-9a-f]{40}$', 'once'));
end

function deleteIfPresent(path)
if exist(path, 'file') == 2
    delete(path);
end
end
