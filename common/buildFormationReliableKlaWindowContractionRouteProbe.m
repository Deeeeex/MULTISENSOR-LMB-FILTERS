function probe = ...
    buildFormationReliableKlaWindowContractionRouteProbe(context, options)
% BUILDFORMATIONRELIABLEKLAWINDOWCONTRACTIONROUTEPROBE
% Compare reference recovery windows without reading posterior contents.
%
% The repository communication matrix pDropByEdge uses sender rows and
% receiver columns.  Routing and fusion matrices use receiver rows and
% sender columns, so the current reliability page is transposed exactly
% once before it reaches the certificate.

if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = { ...
    'horizon', 'candidateFormationIds', ...
    'missingNeighborWeightModes', 'maximumIncomingCount', ...
    'includeSingleEventDobrushinDiagnostic'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('FormationKlaWindowProbe:InvalidOptions', ...
        'The formation window-probe options are malformed.');
end
protocol = getReliableKlaWindowContractionProtocol();

[routeContext, pDropSenderReceiver, groupIds, groups, runtimeSemantics, ...
        communicationSemantics] = ...
    buildRestrictedRouteContext(context);
nodeCount = numel(groupIds);
horizon = getField(options, 'horizon', nodeCount - 1);
candidateFormationIds = reshape(getField( ...
    options, 'candidateFormationIds', groups), 1, []);
missingModes = getField(options, ...
    'missingNeighborWeightModes', ...
    protocol.allowedMissingNeighborWeightModes);
maximumIncomingCount = getField(options, ...
    'maximumIncomingCount', protocol.maximumIncomingCount);
includeEventDiagnostic = logical(getField(options, ...
    'includeSingleEventDobrushinDiagnostic', true));
validateOptions(horizon, candidateFormationIds, missingModes, ...
    maximumIncomingCount, groups, includeEventDiagnostic, ...
    runtimeSemantics.missingNeighborWeightMode);

policy = getFormationBackboneBundleStaggeredRecoveryPolicyConfig();
[referenceAdjacency, referenceDetails] = ...
    selectFormationBackboneResidualTourPolicy(routeContext, struct( ...
        'dominantWeight', policy.dominantWeight, ...
        'residualWeight', policy.residualWeight));
referenceWeights = referenceDetails.fusionWeightMatrix;

actionCount = 1 + numel(candidateFormationIds);
actions = repmat(emptyAction(), 1, actionCount);
actions(1) = buildAvailableAction( ...
    'reference', zeros(1, 0), referenceAdjacency, ...
    referenceWeights, referenceDetails, groupIds);
for actionIdx = 2:actionCount
    formationId = candidateFormationIds(actionIdx - 1);
    try
        [adjacency, details] = ...
            selectTemporalFormationBackboneInputBundleSuspensionPolicy( ...
                routeContext, formationId, struct( ...
                    'policyConfig', policy));
        actions(actionIdx) = buildAvailableAction( ...
            details.actionName, formationId, adjacency, ...
            details.fusionWeightMatrix, details, groupIds);
    catch errorInfo
        if ~isExpectedUnavailable(errorInfo)
            rethrow(errorInfo);
        end
        actions(actionIdx).actionName = sprintf( ...
            'suspend-input-bundle-f%d', formationId);
        actions(actionIdx).suspendedFormationIds = formationId;
        actions(actionIdx).available = false;
        actions(actionIdx).failureIdentifier = errorInfo.identifier;
        actions(actionIdx).failureMessage = errorInfo.message;
    end
end
referencePageMessageCount = actions(1).directedMessageCount;
referencePageCrossMessageCount = ...
    actions(1).crossFormationMessageCount;
for actionIdx = 1:actionCount
    if ~actions(actionIdx).available
        continue;
    end
    actions(actionIdx).decisionActionPageCount = 1;
    actions(actionIdx).referenceRecoveryPageCount = horizon - 1;
    actions(actionIdx).windowDirectedMessageCount = ...
        actions(actionIdx).directedMessageCount + ...
        (horizon - 1) * referencePageMessageCount;
    actions(actionIdx).referenceWindowDirectedMessageCount = ...
        horizon * referencePageMessageCount;
    actions(actionIdx).incrementalWindowDirectedMessageCount = ...
        actions(actionIdx).windowDirectedMessageCount - ...
        actions(actionIdx).referenceWindowDirectedMessageCount;
    actions(actionIdx).windowCrossFormationMessageCount = ...
        actions(actionIdx).crossFormationMessageCount + ...
        (horizon - 1) * referencePageCrossMessageCount;
end

reliabilityPage = 1 - pDropSenderReceiver';
reliabilitySequence = repmat( ...
    reliabilityPage, 1, 1, horizon);
certificateOptions = struct( ...
    'maximumIncomingCount', maximumIncomingCount);
modeCount = numel(missingModes);
gainByActionMode = nan(actionCount, modeCount);
upperBoundByActionMode = nan(actionCount, modeCount);
meanSquareFactorByActionMode = nan(actionCount, modeCount);
meanSquareGainByActionMode = nan(actionCount, modeCount);
for actionIdx = 1:actionCount
    if ~actions(actionIdx).available
        continue;
    end
    adjacencySequence = repmat( ...
        referenceAdjacency, 1, 1, horizon);
    weightSequence = repmat(referenceWeights, 1, 1, horizon);
    if actionIdx > 1
        adjacencySequence(:, :, 1) = actions(actionIdx).adjacency;
        weightSequence(:, :, 1) = actions(actionIdx).fusionWeights;
    end
    certificates = cell(1, modeCount);
    meanSquareCertificates = cell(1, modeCount);
    selectedRequiredMask = [];
    for modeIdx = 1:modeCount
        if includeEventDiagnostic
            modeOptions = certificateOptions;
            modeOptions.missingNeighborWeightMode = missingModes{modeIdx};
            % The rigorous schedule depends only on route weights and link
            % reliabilities, not on the missing-message redistribution
            % rule. Reuse the first selected mask across modes.
            if ~isempty(selectedRequiredMask)
                modeOptions.requiredDeliveryMask = selectedRequiredMask;
            end
            certificate = ...
                computeReliableKlaWindowContractionCertificate( ...
                    adjacencySequence, weightSequence, ...
                    reliabilitySequence, modeOptions);
            if isempty(selectedRequiredMask)
                selectedRequiredMask = certificate.requiredDeliveryMask;
            end
            certificates{modeIdx} = certificate;
            gainByActionMode(actionIdx, modeIdx) = ...
                certificate.expectedContractionGainLowerBound;
            upperBoundByActionMode(actionIdx, modeIdx) = ...
                certificate.expectedDobrushinUpperBound;
        end
        meanSquareCertificate = ...
            computeReliableKlaWindowMeanSquareContractionCertificate( ...
                adjacencySequence, weightSequence, ...
                reliabilitySequence, struct( ...
                    'missingNeighborWeightMode', ...
                        missingModes{modeIdx}, ...
                    'maximumIncomingCount', maximumIncomingCount));
        meanSquareCertificates{modeIdx} = meanSquareCertificate;
        meanSquareFactorByActionMode(actionIdx, modeIdx) = ...
            meanSquareCertificate. ...
                worstCaseExpectedSquaredContractionFactor;
        meanSquareGainByActionMode(actionIdx, modeIdx) = ...
            1 - meanSquareFactorByActionMode(actionIdx, modeIdx);
    end
    actions(actionIdx).certificates = certificates;
    actions(actionIdx).meanSquareCertificates = ...
        meanSquareCertificates;
end

referenceGain = gainByActionMode(1, :);
gainRatio = gainByActionMode ./ referenceGain;
gainRatio(:, referenceGain == 0) = nan;
referenceMeanSquareGain = meanSquareGainByActionMode(1, :);
meanSquareGainRatio = meanSquareGainByActionMode ./ ...
    referenceMeanSquareGain;
meanSquareGainRatio(:, referenceMeanSquareGain <= 0) = nan;
referenceMeanSquareFactor = meanSquareFactorByActionMode(1, :);
meanSquareFactorRatio = meanSquareFactorByActionMode ./ ...
    referenceMeanSquareFactor;
meanSquareFactorDelta = meanSquareFactorByActionMode - ...
    referenceMeanSquareFactor;
for actionIdx = 1:actionCount
    actions(actionIdx).referenceCertifiedGainRatioByMode = ...
        gainRatio(actionIdx, :);
    actions(actionIdx). ...
        referenceMeanSquareContractionGainRatioByMode = ...
            meanSquareGainRatio(actionIdx, :);
    actions(actionIdx).referenceMeanSquareFactorRatioByMode = ...
        meanSquareFactorRatio(actionIdx, :);
    actions(actionIdx).referenceMeanSquareFactorDeltaByMode = ...
        meanSquareFactorDelta(actionIdx, :);
end

probe = struct();
probe.contractVersion = ...
    'formation-reliable-kla-window-contraction-route-probe-v1';
probe.protocolId = protocol.id;
probe.protocolCanonicalSha256 = protocol.canonicalSha256;
probe.nodeCount = nodeCount;
probe.formationCount = numel(groups);
probe.groupIds = groupIds;
probe.groups = groups;
probe.currentTime = routeContext.currentTime;
probe.horizon = horizon;
probe.horizonRule = iff(horizon == nodeCount - 1, ...
    protocol.staticPageDevelopmentProbeHorizonRule, ...
    'caller-supplied-causal-window');
probe.missingNeighborWeightModes = missingModes;
probe.operationalMissingNeighborWeightMode = ...
    runtimeSemantics.missingNeighborWeightMode;
probe.operationalMissingNeighborWeightModeMask = ...
    strcmp(missingModes, runtimeSemantics.missingNeighborWeightMode);
probe.currentReliabilityReceiverSender = reliabilityPage;
probe.reliabilityForecast = 'repeat-current-page';
probe.routePlan = 'candidate-once-then-registered-reference';
probe.windowOperationalUnit = protocol.windowOperationalUnit;
probe.decisionActionPageCount = protocol.decisionActionPageCount;
probe.additionalWithinStepFusionRounds = ...
    protocol.additionalWithinStepFusionRounds;
probe.referenceAdjacency = referenceAdjacency;
probe.referenceFusionWeights = referenceWeights;
probe.actions = actions;
probe.gainByActionMode = gainByActionMode;
probe.expectedDobrushinUpperBoundByActionMode = ...
    upperBoundByActionMode;
probe.referenceCertifiedGainRatioByActionMode = gainRatio;
probe.meanSquareContractionFactorByActionMode = ...
    meanSquareFactorByActionMode;
probe.meanSquareContractionGainByActionMode = ...
    meanSquareGainByActionMode;
probe.referenceMeanSquareContractionGainRatioByActionMode = ...
    meanSquareGainRatio;
probe.referenceMeanSquareFactorRatioByActionMode = ...
    meanSquareFactorRatio;
probe.referenceMeanSquareFactorDeltaByActionMode = ...
    meanSquareFactorDelta;
probe.singleEventDobrushinDiagnosticIncluded = ...
    includeEventDiagnostic;
probe.availableActionMask = [actions.available];
probe.posteriorContentsRead = false;
probe.truthUsed = false;
probe.futureOutcomeUsed = false;
probe.realizedDeliveryUniformsUsed = false;
probe.currentPDropPageOnly = true;
probe.selectedTopologyHistoryUsed = true;
probe.plannedReferenceRecoveryUsed = true;
probe.runtimeSemantics = runtimeSemantics;
probe.runtimeSemanticsValidated = runtimeSemantics.passed;
probe.communicationSemantics = communicationSemantics;
probe.communicationSemanticsValidated = ...
    communicationSemantics.passed;
probe.trackingOutcomeScored = false;
probe.developmentEvidenceOnly = true;
end

function [restricted, pDrop, groupIds, groups, runtimeSemantics, ...
        communicationSemantics] = ...
        buildRestrictedRouteContext(context)
required = { ...
    'model', 'baseAdjacency', 'physicalAdjacency', ...
    'previousAdjacencyHistory', 'currentTime', 'commConfig', ...
    'triggerConfig'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds') || ...
        ~isfield(context.commConfig, 'pDropByEdge')
    error('FormationKlaWindowProbe:InvalidContext', ...
        'The observable route context is incomplete.');
end
runtimeSemantics = ...
    validateReliableKlaMixingRuntimeSemantics(context.triggerConfig);
communicationSemantics = ...
    validateReliableKlaCommunicationRuntimeSemantics(context.commConfig);
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
nodeCount = numel(groupIds);
pDrop = context.commConfig.pDropByEdge;
if nodeCount < 2 || numel(groups) < 2 || ...
        ~((isnumeric(context.baseAdjacency) || ...
            islogical(context.baseAdjacency)) && ...
          isreal(context.baseAdjacency) && ...
          all(isfinite(context.baseAdjacency(:))) && ...
          all(context.baseAdjacency(:) == 0 | ...
              context.baseAdjacency(:) == 1)) || ...
        ~((isnumeric(context.physicalAdjacency) || ...
            islogical(context.physicalAdjacency)) && ...
          isreal(context.physicalAdjacency) && ...
          all(isfinite(context.physicalAdjacency(:))) && ...
          all(context.physicalAdjacency(:) == 0 | ...
              context.physicalAdjacency(:) == 1)) || ...
        ~((isnumeric(context.previousAdjacencyHistory) || ...
            islogical(context.previousAdjacencyHistory)) && ...
          isreal(context.previousAdjacencyHistory) && ...
          all(isfinite(context.previousAdjacencyHistory(:))) && ...
          all(context.previousAdjacencyHistory(:) == 0 | ...
              context.previousAdjacencyHistory(:) == 1)) || ...
        ~isequal(size(context.baseAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        size(context.previousAdjacencyHistory, 1) ~= nodeCount || ...
        size(context.previousAdjacencyHistory, 2) ~= nodeCount || ...
        ndims(context.previousAdjacencyHistory) ~= 3 || ...
        size(context.previousAdjacencyHistory, 3) < 2 || ...
        ~isequal(size(pDrop), [nodeCount, nodeCount]) || ...
        ~isnumeric(pDrop) || ~isreal(pDrop) || ...
        any(~isfinite(pDrop(:))) || ...
        any(pDrop(:) < 0) || any(pDrop(:) > 1) || ...
        ~isscalar(context.currentTime) || ...
        ~isfinite(context.currentTime) || context.currentTime < 1
    error('FormationKlaWindowProbe:InvalidContext', ...
        'The observable route context dimensions are invalid.');
end
scenario = struct( ...
    'config', struct('sensorGroupIds', groupIds), ...
    'staticAdjacency', logical(context.baseAdjacency));
restricted = struct();
restricted.localPosteriorBySensor = cell(1, nodeCount);
restricted.model = struct('dynamicTopologyScenario', scenario);
restricted.baseAdjacency = logical(context.baseAdjacency);
restricted.physicalAdjacency = logical(context.physicalAdjacency);
restricted.previousAdjacencyHistory = logical( ...
    context.previousAdjacencyHistory(:, :, end-1:end));
restricted.currentTime = context.currentTime;
restricted.directedMessageBudget = 2 * nodeCount;
end

function validateOptions(horizon, formationIds, modes, ...
        maximumIncomingCount, groups, includeEventDiagnostic, ...
        operationalMode)
if ~isscalar(horizon) || ~isfinite(horizon) || horizon < 1 || ...
        horizon ~= round(horizon) || ...
        ~isnumeric(formationIds) || ~isreal(formationIds) || ...
        any(~isfinite(formationIds)) || ...
        numel(unique(formationIds)) ~= numel(formationIds) || ...
        any(~ismember(formationIds, groups)) || ...
        ~iscell(modes) || isempty(modes) || ...
        any(~cellfun(@ischar, modes)) || ...
        any(~ismember(modes, {'renormalize', 'self'})) || ...
        numel(unique(modes)) ~= numel(modes) || ...
        sum(strcmp(modes, operationalMode)) ~= 1 || ...
        ~isscalar(maximumIncomingCount) || ...
        ~isfinite(maximumIncomingCount) || ...
        maximumIncomingCount < 1 || ...
        maximumIncomingCount ~= round(maximumIncomingCount) || ...
        ~isscalar(includeEventDiagnostic)
    error('FormationKlaWindowProbe:InvalidOptions', ...
        'The formation window-probe options are invalid.');
end
end

function action = buildAvailableAction(name, suspendedIds, ...
        adjacency, weights, details, groupIds)
crossMask = groupIds(:) ~= groupIds(:)';
action = emptyAction();
action.actionName = name;
action.suspendedFormationIds = reshape(suspendedIds, 1, []);
action.available = true;
action.adjacency = logical(adjacency);
action.fusionWeights = weights;
action.directedMessageCount = nnz(adjacency);
action.crossFormationMessageCount = nnz(adjacency & crossMask);
action.totalCrossFormationFusionWeight = sum(weights(crossMask));
action.policyDetailsContractVersion = details.contractVersion;
end

function action = emptyAction()
action = struct( ...
    'actionName', '', ...
    'suspendedFormationIds', zeros(1, 0), ...
    'available', false, ...
    'failureIdentifier', '', ...
    'failureMessage', '', ...
    'adjacency', false(0), ...
    'fusionWeights', zeros(0), ...
    'directedMessageCount', nan, ...
    'crossFormationMessageCount', nan, ...
    'totalCrossFormationFusionWeight', nan, ...
    'policyDetailsContractVersion', '', ...
    'certificates', {{}}, ...
    'meanSquareCertificates', {{}}, ...
    'referenceCertifiedGainRatioByMode', zeros(1, 0), ...
    'referenceMeanSquareContractionGainRatioByMode', zeros(1, 0), ...
    'referenceMeanSquareFactorRatioByMode', zeros(1, 0), ...
    'referenceMeanSquareFactorDeltaByMode', zeros(1, 0), ...
    'decisionActionPageCount', nan, ...
    'referenceRecoveryPageCount', nan, ...
    'windowDirectedMessageCount', nan, ...
    'referenceWindowDirectedMessageCount', nan, ...
    'incrementalWindowDirectedMessageCount', nan, ...
    'windowCrossFormationMessageCount', nan);
end

function value = isExpectedUnavailable(errorInfo)
value = ismember(errorInfo.identifier, { ...
    'FormationBundleSuspension:Infeasible', ...
    'FormationBundleSuspension:InvalidCandidate', ...
    'FormationBackboneTour:NonphysicalTour'});
end

function value = getField(structure, name, defaultValue)
if isfield(structure, name)
    value = structure.(name);
else
    value = defaultValue;
end
end

function value = iff(condition, trueValue, falseValue)
if condition
    value = trueValue;
else
    value = falseValue;
end
end
