function protocol = getShieldBroadcastV102Protocol()
% GETSHIELDBROADCASTV102PROTOCOL Protect gateways, then broadcast them.

source = getPropagationAwareDwellV101Protocol();
route = getFormationIsolateReconnectProbeProtocol();
protocol = source;
protocol.id = 'shield-broadcast-v102-v1';
protocol.contractVersion = 'shield-broadcast-v102-protocol-v1';
protocol.outcomePolicyName = 'shield-broadcast-v102-v1';
protocol.protectionFormationIdsByTime = ...
    source.dwellFormationIdsByTime;
protocol.broadcastFormationIdsByTime = [ ...
    {zeros(1, 0)}, source.dwellFormationIdsByTime(1:end-1)];
protocol.broadcastDelaySteps = 1;
protocol.dominantWeight = route.dominantWeight;
protocol.residualWeight = route.residualWeight;
protocol.minimumFormationGainPercent = 1;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v102', 'shield_broadcast');
protocol.headroomOutputRoot = fullfile( ...
    protocol.outputRoot, 'matched_static_headroom');
protocol.evidenceBoundary = [ ...
    'V102 is a frozen matched-static headroom probe that composes V101 ', ...
    'cross-formation control-only protection with a one-step-delayed ', ...
    'within-formation broadcast. For every protected formation, the ', ...
    'registered cross-input gateway becomes the 0.70 dominant sender of ', ...
    'physically reachable peers on the next page; the displaced dominant ', ...
    'sender is retained at 0.05 and the old residual is removed. Every ', ...
    'row preserves its message count and positive-weight multiset. Static ', ...
    'and candidate arms share the cached posterior, measurements, delivery ', ...
    'uniforms, filter RNG and communication model. The schedule is frozen ', ...
    'before V102 outcomes are opened and is not yet an online policy or ', ...
    'validation claim.'];
end
