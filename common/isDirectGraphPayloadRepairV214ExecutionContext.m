function detected = ...
        isDirectGraphPayloadRepairV214ExecutionContext(context)
% ISDIRECTGRAPHPAYLOADREPAIRV214EXECUTIONCONTEXT Identify V214.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'direct-graph-payload-repair-v214-context-v1');
end
