function detected = ...
        isHierarchicalDelayedValueCollectionV213ExecutionContext(context)
% ISHIERARCHICALDELAYEDVALUECOLLECTIONV213EXECUTIONCONTEXT Identify V213.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'hierarchical-delayed-value-collection-v213-context-v1');
end
