function context = ...
        buildSparseReferenceLabelRollbackV156ExecutionContext( ...
            presetName, seed, currentTime, actionName, ...
            scheduleEnabled, maximumLabelEdits)
% BUILDSPARSEREFERENCELABELROLLBACKV156EXECUTIONCONTEXT Frozen V156 context.

protocol = getSparseReferenceLabelRollbackV156Protocol(maximumLabelEdits);
if ~ischar(presetName) || isempty(presetName) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || ...
        ~ischar(actionName) || isempty(actionName) || ...
        ~isscalar(scheduleEnabled) || ...
        ~(islogical(scheduleEnabled) || isnumeric(scheduleEnabled))
    error('SparseReferenceLabelV156:InvalidExecutionContext', ...
        'The V156 execution-context input is invalid.');
end
context = struct();
context.contractVersion = ...
    'sparse-reference-label-rollback-v156-context-v1';
context.capability = ...
    'sparse-reference-label-rollback-v156-development';
context.action = ...
    'filter-sparse-reference-label-rollback-v156-development';
context.protocolId = protocol.id;
context.phase = 'opened-return';
context.presetName = presetName;
context.seed = seed;
context.currentTime = currentTime;
context.measurementTimeCount = ...
    currentTime + protocol.horizonSteps - 1;
context.policyName = protocol.outcomePolicyName;
context.actionName = actionName;
context.scheduleEnabled = logical(scheduleEnabled);
context.onlineReselectionEnabled = false;
context.developmentEvidenceOnly = true;
end
