function joint = buildSetTrustSequenceV134JointGate( ...
        pilots, protocol, generationGitCommit)
% BUILDSETTRUSTSEQUENCEV134JOINTGATE Recompute the two-scale headroom gate.
%
% Each scale must independently contain at least one deployable action that
% passes every empirical and recovery-certificate condition.  Improvements
% are never averaged across scales.

if nargin < 2 || isempty(protocol)
    protocol = getSetTrustSequenceV134Protocol();
end
if nargin < 3 || isempty(generationGitCommit)
    error('V134JointGate:MissingProvenance', ...
        'The joint gate requires one explicit source commit.');
end
if ~isstruct(pilots) || ...
        numel(pilots) ~= numel(protocol.scaleCases) || ...
        ~ischar(generationGitCommit) || isempty(generationGitCommit) || ...
        ~isstruct(protocol) || ~isscalar(protocol) || ...
        ~strcmp(protocol.id, 'formation-admission-sequence-v134-v3') || ...
        ~logical(protocol.preLearningGate.requireBothScales)
    error('V134JointGate:InvalidInput', ...
        'The V134 pilots, protocol, or provenance are malformed.');
end

caseSummaries = repmat(emptyCaseSummary(), ...
    1, numel(protocol.scaleCases));
for caseIdx = 1:numel(protocol.scaleCases)
    caseInfo = protocol.scaleCases(caseIdx);
    matches = find(strcmp({pilots.presetName}, caseInfo.presetName));
    if numel(matches) ~= 1
        error('V134JointGate:ScaleCoverageDrift', ...
            'Every registered scale must occur exactly once.');
    end
    caseSummaries(caseIdx) = auditScalePilot( ...
        pilots(matches), caseInfo, protocol, generationGitCommit);
end

scalePass = [caseSummaries.scaleGatePassed];
jointPassed = all(scalePass);
joint = struct();
joint.contractVersion = ...
    'v134-binary-admission-joint-headroom-gate-v1';
joint.protocolId = protocol.id;
joint.pilotSeed = protocol.pilotSeed;
joint.scaleCases = caseSummaries;
joint.scaleGatePassed = scalePass;
joint.jointCrossScaleGatePassed = jointPassed;
joint.crossScaleAveragingAllowed = false;
joint.onPolicyTeacherDevelopmentAuthorized = jointPassed;
joint.gnnAuthorized = false;
joint.validationClaimAllowed = false;
joint.mainDocumentResultAuthorized = false;
joint.developmentEvidenceOnly = true;
joint.generationGitCommit = generationGitCommit;
joint.reportingDisposition = ...
    'repository-only-development-headroom-evidence';
end

function summary = auditScalePilot( ...
        pilot, caseInfo, protocol, generationGitCommit)
required = {'contractVersion', 'protocolId', 'scaleName', ...
    'presetName', 'seed', 'anchorTime', 'referenceCarrierMode', ...
    'records', 'passingRecordIndices', ...
    'pilotScaleHeadroomObserved', 'jointCrossScaleGateClaimed', ...
    'generationGitCommit', 'developmentEvidenceOnly', ...
    'validationClaimAllowed'};
expectedAnchor = ...
    resolveSetTrustSequenceV134PilotAnchor(caseInfo, protocol);
if ~isstruct(pilot) || ~isscalar(pilot) || ...
        ~all(isfield(pilot, required)) || ...
        ~strcmp(pilot.contractVersion, ...
            'v134-binary-admission-pilot-result-v3') || ...
        ~strcmp(pilot.protocolId, protocol.id) || ...
        ~strcmp(pilot.scaleName, caseInfo.scaleName) || ...
        ~strcmp(pilot.presetName, caseInfo.presetName) || ...
        pilot.seed ~= protocol.pilotSeed || ...
        pilot.anchorTime ~= expectedAnchor || ...
        ~ismember(pilot.referenceCarrierMode, ...
            protocol.referenceCarrierModes) || ...
        ~strcmp(pilot.generationGitCommit, generationGitCommit) || ...
        ~logical(pilot.developmentEvidenceOnly) || ...
        logical(pilot.validationClaimAllowed) || ...
        logical(pilot.jointCrossScaleGateClaimed) || ...
        ~isstruct(pilot.records) || isempty(pilot.records)
    error('V134JointGate:PilotProvenanceDrift', ...
        'A scale pilot differs from the registered joint-gate contract.');
end

records = reshape(pilot.records, 1, []);
actionIndices = [records.actionIndex];
if any(~isfinite(actionIndices)) || ...
        any(actionIndices < 1) || ...
        numel(unique(actionIndices)) ~= numel(actionIndices)
    error('V134JointGate:InvalidRecord', ...
        'Pilot action indices must be unique positive integers.');
end
computedPass = false(1, numel(records));
robustMargin = -inf(1, numel(records));
for recordIdx = 1:numel(records)
    [computedPass(recordIdx), robustMargin(recordIdx)] = ...
        auditRecord(records(recordIdx), protocol.preLearningGate);
end
storedPassing = reshape(pilot.passingRecordIndices, 1, []);
computedPassing = reshape(find(computedPass), 1, []);
if ~isequal(storedPassing, computedPassing) || ...
        logical(pilot.pilotScaleHeadroomObserved) ~= ...
            ~isempty(computedPassing)
    error('V134JointGate:StoredGateDrift', ...
        'Stored scale-gate fields disagree with recomputed metrics.');
end

summary = emptyCaseSummary();
summary.scaleName = caseInfo.scaleName;
summary.presetName = caseInfo.presetName;
summary.referenceCarrierMode = pilot.referenceCarrierMode;
summary.passingRecordIndices = computedPassing;
summary.passingActionIndices = actionIndices(computedPassing);
summary.passingActionNames = {records(computedPassing).actionName};
summary.scaleGatePassed = ~isempty(computedPassing);
if summary.scaleGatePassed
    [~, localBest] = max(robustMargin(computedPassing));
    bestRecordIdx = computedPassing(localBest);
    summary.bestPassingRecordIndex = bestRecordIdx;
    summary.bestPassingActionIndex = ...
        records(bestRecordIdx).actionIndex;
    summary.bestPassingActionName = records(bestRecordIdx).actionName;
    summary.bestPassingMetrics = records(bestRecordIdx).metrics;
end
end

function [passed, robustMargin] = auditRecord(record, gate)
requiredRecord = {'actionIndex', 'actionName', 'scheduleKind', ...
    'formationSet', 'metrics'};
requiredMetrics = { ...
    'interventionGainFraction', 'meanGainFraction', ...
    'matureGainFraction', ...
    'minimumInterventionSensorGainFraction', ...
    'minimumSensorGainFraction', ...
    'minimumMatureSensorGainFraction', ...
    'minimumInterventionFormationGainFraction', ...
    'minimumFormationGainFraction', ...
    'minimumMatureFormationGainFraction', ...
    'attemptedByteSavingFraction', ...
    'recoverySquaredContractionFactor', ...
    'actionGateEligible', 'actionDiagnosticOnly', ...
    'actionReturnsToFullTrust', ...
    'passesRecoveryCertificateGate', ...
    'passesPreLearningGate', 'recoveryCertificate'};
if ~isstruct(record) || ~isscalar(record) || ...
        ~all(isfield(record, requiredRecord)) || ...
        ~ischar(record.actionName) || isempty(record.actionName) || ...
        ~ischar(record.scheduleKind) || ...
        ~isstruct(record.metrics) || ~isscalar(record.metrics) || ...
        ~all(isfield(record.metrics, requiredMetrics))
    error('V134JointGate:InvalidRecord', ...
        'A pilot action record is malformed.');
end
metrics = record.metrics;
numericNames = requiredMetrics(1:11);
numericValues = zeros(1, numel(numericNames));
for valueIdx = 1:numel(numericNames)
    value = metrics.(numericNames{valueIdx});
    if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value)
        error('V134JointGate:InvalidMetric', ...
            'Every joint-gate metric must be a finite scalar.');
    end
    numericValues(valueIdx) = value;
end
logicalNames = {'actionGateEligible', 'actionDiagnosticOnly', ...
    'actionReturnsToFullTrust', 'passesRecoveryCertificateGate', ...
    'passesPreLearningGate'};
for valueIdx = 1:numel(logicalNames)
    value = metrics.(logicalNames{valueIdx});
    if ~(islogical(value) || isnumeric(value)) || ...
            ~isscalar(value) || ~isfinite(value) || ...
            ~ismember(value, [0, 1])
        error('V134JointGate:InvalidMetric', ...
            'Every joint-gate decision flag must be a binary scalar.');
    end
end

certificate = metrics.recoveryCertificate;
requiredCertificate = {'candidateSquaredContractionFactor', ...
    'maximumAllowedSquaredContractionFactor', ...
    'strictMeanSquareContractionCertified', ...
    'targetContractionCertified', ...
    'referenceAndCandidateTailIdentical', 'passesRecoveryGate'};
if ~isstruct(certificate) || ~isscalar(certificate) || ...
        ~all(isfield(certificate, requiredCertificate))
    error('V134JointGate:RecoveryCertificateDrift', ...
        'The recovery certificate differs from the registered gate.');
end
certificateFlags = {'strictMeanSquareContractionCertified', ...
    'targetContractionCertified', ...
    'referenceAndCandidateTailIdentical', 'passesRecoveryGate'};
validCertificateFlags = all(cellfun(@(name) ...
    (islogical(certificate.(name)) || ...
     isnumeric(certificate.(name))) && ...
    isscalar(certificate.(name)) && ...
    isfinite(certificate.(name)) && ...
    ismember(certificate.(name), [0, 1]), certificateFlags));
if ~isnumeric(certificate.candidateSquaredContractionFactor) || ...
        ~isscalar(certificate.candidateSquaredContractionFactor) || ...
        ~isfinite(certificate.candidateSquaredContractionFactor) || ...
        ~isnumeric(certificate.maximumAllowedSquaredContractionFactor) || ...
        ~isscalar(certificate.maximumAllowedSquaredContractionFactor) || ...
        ~isfinite(certificate.maximumAllowedSquaredContractionFactor) || ...
        ~validCertificateFlags || ...
        abs(certificate.candidateSquaredContractionFactor - ...
            metrics.recoverySquaredContractionFactor) > 1e-12 || ...
        abs(certificate.maximumAllowedSquaredContractionFactor - ...
            gate.maximumRecoverySquaredContractionFactor) > 1e-12
    error('V134JointGate:RecoveryCertificateDrift', ...
        'The recovery certificate differs from the registered gate.');
end
certificatePassed = logical(certificate.passesRecoveryGate) && ...
    logical(certificate.strictMeanSquareContractionCertified) && ...
    logical(certificate.targetContractionCertified) && ...
    logical(certificate.referenceAndCandidateTailIdentical) && ...
    metrics.recoverySquaredContractionFactor <= ...
        gate.maximumRecoverySquaredContractionFactor + 1e-12;

margins = [ ...
    metrics.interventionGainFraction - ...
        gate.minimumPairedInterventionEospGainFraction, ...
    metrics.meanGainFraction - ...
        gate.minimumPairedMeanEospGainFraction, ...
    metrics.matureGainFraction - ...
        gate.minimumPairedMatureEospGainFraction, ...
    metrics.minimumInterventionSensorGainFraction - ...
        gate.minimumInterventionSensorGainFraction, ...
    metrics.minimumSensorGainFraction - ...
        gate.minimumSensorGainFraction, ...
    metrics.minimumMatureSensorGainFraction - ...
        gate.minimumMatureSensorGainFraction, ...
    metrics.minimumInterventionFormationGainFraction - ...
        gate.minimumInterventionFormationGainFraction, ...
    metrics.minimumFormationGainFraction - ...
        gate.minimumFormationGainFraction, ...
    metrics.minimumMatureFormationGainFraction - ...
        gate.minimumMatureFormationGainFraction, ...
    metrics.attemptedByteSavingFraction, ...
    gate.maximumRecoverySquaredContractionFactor - ...
        metrics.recoverySquaredContractionFactor];
rawPassed = all(margins(1:9) >= -1e-12) && ...
    (~gate.requirePositiveAttemptedByteSaving || ...
        metrics.attemptedByteSavingFraction > 1e-12) && ...
    logical(metrics.actionGateEligible) && ...
    ~logical(metrics.actionDiagnosticOnly) && ...
    (~gate.requireFullyRestoredGateEligibleAction || ...
        logical(metrics.actionReturnsToFullTrust)) && ...
    (~gate.requireRecoveryMeanSquareCertificate || certificatePassed) && ...
    logical(metrics.passesRecoveryCertificateGate) == ...
        (~gate.requireRecoveryMeanSquareCertificate || certificatePassed);
if logical(metrics.passesPreLearningGate) ~= rawPassed
    error('V134JointGate:RecordGateDrift', ...
        'A stored action pass flag disagrees with recomputed metrics.');
end
passed = rawPassed;
robustMargin = min(margins);
end

function value = emptyCaseSummary()
value = struct( ...
    'scaleName', '', ...
    'presetName', '', ...
    'referenceCarrierMode', '', ...
    'passingRecordIndices', zeros(1, 0), ...
    'passingActionIndices', zeros(1, 0), ...
    'passingActionNames', {{}}, ...
    'scaleGatePassed', false, ...
    'bestPassingRecordIndex', 0, ...
    'bestPassingActionIndex', 0, ...
    'bestPassingActionName', '', ...
    'bestPassingMetrics', struct());
end
