function detected = ...
    isPropagationAwareDwellV101ExecutionContext(context)
% ISPROPAGATIONAWAREDWELLV101EXECUTIONCONTEXT Identify V101.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'propagation-aware-dwell-v101-context-v1');
end
