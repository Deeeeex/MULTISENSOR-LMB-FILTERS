function [risk, details] = ...
    computeExpectedLmbPosteriorBayesRisk(distribution, options)
% COMPUTEEXPECTEDLMBPOSTERIORBAYESRISK Average over link outcomes.

if nargin < 2 || isempty(options)
    options = struct();
end
if ~isstruct(distribution) || ...
        ~isfield(distribution, 'probability') || ...
        ~isfield(distribution, 'summary') || ...
        ~iscell(distribution.summary)
    error('Expected posterior Bayes risk needs an outcome distribution.');
end
probability = reshape(distribution.probability, 1, []);
outcomeCount = numel(probability);
if outcomeCount < 1 || numel(distribution.summary) ~= outcomeCount || ...
        any(~isfinite(probability)) || any(probability < 0) || ...
        abs(sum(probability) - 1) > 1e-10
    error('Posterior Bayes-risk outcome probabilities are invalid.');
end

if isfield(options, 'labelUniverse')
    labelUniverse = options.labelUniverse;
else
    labelUniverse = zeros(2, 0);
    for outcomeIdx = 1:outcomeCount
        labelUniverse = unionLabels( ...
            labelUniverse, distribution.summary{outcomeIdx}.labels);
    end
end
scoreOptions = options;
scoreOptions.labelUniverse = labelUniverse;
outcomeRisk = zeros(1, outcomeCount);
outcomeDetails = cell(1, outcomeCount);
for outcomeIdx = 1:outcomeCount
    [outcomeRisk(outcomeIdx), outcomeDetails{outcomeIdx}] = ...
        computeLmbPosteriorSummaryBayesRisk( ...
            distribution.summary{outcomeIdx}, scoreOptions);
end
risk = sum(probability .* outcomeRisk);

details = struct( ...
    'contractVersion', 'expected-lmb-posterior-bayes-risk-v1', ...
    'probability', probability, ...
    'labelUniverse', labelUniverse, ...
    'outcomeRisk', outcomeRisk, ...
    'outcomeDetails', {outcomeDetails}, ...
    'risk', risk, ...
    'maximumOutcomeRisk', max(outcomeRisk), ...
    'riskVariance', sum(probability .* (outcomeRisk - risk).^2), ...
    'truthUsed', false, ...
    'groundTruthUsed', false, ...
    'futureOutcomeUsed', false);
end

function labels = unionLabels(left, right)
labels = left;
for labelIdx = 1:size(right, 2)
    if isempty(labels) || ...
            ~any(all(labels == right(:, labelIdx), 1))
        labels(:, end + 1) = right(:, labelIdx); %#ok<AGROW>
    end
end
end
