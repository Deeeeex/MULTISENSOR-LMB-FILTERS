function protocol = getTemporallyBalancedMinimumBackboneV272Protocol()
% GETTEMPORALLYBALANCEDMINIMUMBACKBONEV272PROTOCOL Temporal gateways.

source = getCausalMinimumFormationBackboneV242Protocol();
protocol = struct();
protocol.id = 'temporally-balanced-minimum-backbone-v272-v1';
protocol.contractVersion = ...
    'temporally-balanced-minimum-backbone-v272-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.armId = 'v272-temporally-balanced-minimum-backbone';
protocol.policyName = ...
    'temporally-balanced-minimum-backbone-v272-policy';
protocol.allowedPresets = source.allowedPresets;
protocol.allowedSeeds = source.allowedSeeds;
protocol.historyDepth = 12;
protocol.minimumReliabilityRatio = 0.90;
protocol.maximumReliabilityDrop = 0.05;
protocol.balanceSenderRoles = true;
protocol.senderSelectionMode = ...
    'causal-external-influence-then-service-age';
protocol.dominantWeight = source.dominantWeight;
protocol.crossResidualWeight = source.crossResidualWeight;
protocol.receiverMode = source.receiverMode;
protocol.filterSeedOffset = source.filterSeedOffset;
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v272', ...
    'temporally_balanced_minimum_backbone');
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V272 is a causal development policy derived from V242. It keeps ', ...
    'the current physical formation tree, local directed cycles, KLA ', ...
    'weights and exact N+2(F-1) message count. It changes only the ', ...
    'sensor-level embedding of the cross-formation arcs. Within a ', ...
    'per-edge reliability floor relative to the current V242 route, it ', ...
    'serves the least-recently used cross receivers over a bounded ', ...
    'past-topology window, while preferring senders whose causal route-', ...
    'product profile carries broader external-formation influence. It ', ...
    'reads no posterior, measurement, ', ...
    'truth, future outcome or realized delivery. Structural contraction ', ...
    'is not a tracking-gain or generalization claim.'];

if protocol.historyDepth < 1 || ...
        protocol.minimumReliabilityRatio <= 0 || ...
        protocol.minimumReliabilityRatio > 1 || ...
        protocol.maximumReliabilityDrop < 0 || ...
        protocol.maximumReliabilityDrop > 1 || ...
        ~isscalar(protocol.balanceSenderRoles)
    error('TemporallyBalancedBackboneV272:InvalidProtocol', ...
        'The temporal balancing protocol is inconsistent.');
end
end
