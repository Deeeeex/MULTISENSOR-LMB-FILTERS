function features = extractCounterfactualRegretFeaturesV133( ...
        context, referenceAdjacency, referenceWeights, groupIds, ...
        protectedFormationId, protocol, protectionHistory, ...
        referenceScore)
% EXTRACTCOUNTERFACTUALREGRETFEATURESV133 Observable action features.
%
% The feature row is invariant to seed, absolute time and numeric formation
% identity.  It combines the exact current-page abstention model with
% mixture, sensing, link-history, update-history and propagation summaries.

if nargin < 7 || isempty(protectionHistory)
    protectionHistory = struct();
end
if nargin < 8
    referenceScore = struct([]);
end
score = scorePayloadAbstentionCounterfactualV133( ...
    context, referenceAdjacency, referenceWeights, groupIds, ...
    protectedFormationId, protocol, referenceScore);
nodeCount = numel(context.localPosteriorBySensor);
groupIds = reshape(groupIds, 1, []);
protectedSensors = groupIds == protectedFormationId;
[receiverIndices, senderIndices] = find(score.abstainedInputMask);
upstreamSensors = false(1, nodeCount);
upstreamSensors(senderIndices) = true;

[protectedPosterior, posteriorNames] = posteriorSummary( ...
    context.localPosteriorBySensor(protectedSensors));
[upstreamPosterior, ~] = posteriorSummary( ...
    context.localPosteriorBySensor(upstreamSensors));
posteriorDelta = upstreamPosterior - protectedPosterior;

[linkValues, linkNames] = linkFeatures( ...
    context, receiverIndices, senderIndices);
[updateValues, updateNames] = updateFeatures( ...
    context, protectedSensors, upstreamSensors);
[sensorValues, sensorNames] = sensorFeatures( ...
    context, protectedSensors, upstreamSensors, ...
    receiverIndices, senderIndices);
[historyValues, historyNames] = protectionFeatures(protectionHistory);
[propagationValues, propagationNames] = propagationFeatures( ...
    referenceAdjacency, groupIds, protectedFormationId, ...
    receiverIndices, senderIndices);

exactValues = [ ...
    score.referenceTaskRisk, ...
    score.counterfactualTaskRisk, ...
    score.taskRiskChange, ...
    score.referenceNetworkDisagreement, ...
    score.counterfactualNetworkDisagreement, ...
    score.networkDisagreementChange, ...
    score.existenceRetentionRisk, ...
    score.minimumFormationCardinalityChange, ...
    score.minimumReceiverCardinalityChange, ...
    score.minimumSupportedLabelRetentionRatio, ...
    score.decisionThresholdCrossingCount, ...
    score.decisionThresholdCrossingCount / ...
        max(nnz(protectedSensors), 1), ...
    score.abstainedInputCount / max(nodeCount, 1)];
exactNames = { ...
    'exact_reference_task_risk', ...
    'exact_candidate_task_risk', ...
    'exact_task_risk_change', ...
    'exact_reference_network_disagreement', ...
    'exact_candidate_network_disagreement', ...
    'exact_network_disagreement_change', ...
    'exact_existence_retention_risk', ...
    'exact_minimum_formation_cardinality_change', ...
    'exact_minimum_receiver_cardinality_change', ...
    'exact_minimum_supported_label_retention_ratio', ...
    'exact_decision_threshold_crossing_count', ...
    'exact_decision_threshold_crossing_fraction_protected', ...
    'exact_abstained_input_fraction_per_sensor'};

featureNames = [ ...
    exactNames, ...
    addPrefix(posteriorNames, 'protected_'), ...
    addPrefix(posteriorNames, 'upstream_'), ...
    addPrefix(posteriorNames, 'upstream_minus_protected_'), ...
    linkNames, updateNames, sensorNames, historyNames, ...
    propagationNames];
featureRow = [ ...
    exactValues, protectedPosterior, upstreamPosterior, ...
    posteriorDelta, linkValues, updateValues, sensorValues, ...
    historyValues, propagationValues];
if numel(featureNames) ~= numel(featureRow) || ...
        any(~isfinite(featureRow))
    error('CounterfactualRegretV133:InvalidFeatureRow', ...
        'The observable V133 feature row is incomplete or non-finite.');
end

features = struct();
features.contractVersion = ...
    'counterfactual-regret-gate-v133-observable-features-v1';
features.names = featureNames;
features.values = reshape(featureRow, 1, []);
features.featureContractSha256 = computeTextSha256( ...
    strjoin(featureNames, char(31)));
features.exactCounterfactualSummary = struct( ...
    'taskRiskChange', score.taskRiskChange, ...
    'networkDisagreementChange', score.networkDisagreementChange, ...
    'existenceRetentionRisk', score.existenceRetentionRisk, ...
    'minimumFormationCardinalityChange', ...
        score.minimumFormationCardinalityChange, ...
    'minimumReceiverCardinalityChange', ...
        score.minimumReceiverCardinalityChange, ...
    'minimumSupportedLabelRetentionRatio', ...
        score.minimumSupportedLabelRetentionRatio, ...
    'decisionThresholdCrossingCount', ...
        score.decisionThresholdCrossingCount, ...
    'abstainedInputCount', score.abstainedInputCount, ...
    'singleRoundExact', score.singleRoundExact);
features.truthUsed = false;
features.futureMeasurementUsed = false;
features.futureOutcomeUsed = false;
features.realizedCurrentDeliveryUsed = false;
features.seedIdentifierUsed = false;
features.absoluteTimeUsed = false;
features.fixedFormationIdentifierUsed = false;
features.posteriorUsed = true;
features.currentSensorObservationUsed = true;
features.currentLinkReliabilityUsed = true;
features.causalHistoryUsed = true;
features.centralizedCurrentPosteriorRequired = true;
end

function [values, names] = posteriorSummary(posteriors)
labelCount = zeros(1, numel(posteriors));
componentPerLabel = zeros(1, numel(posteriors));
existence = zeros(1, numel(posteriors));
existenceEntropy = zeros(1, numel(posteriors));
associationMass = zeros(1, numel(posteriors));
associationEntropy = zeros(1, numel(posteriors));
positionVariance = zeros(1, numel(posteriors));
for sensorIdx = 1:numel(posteriors)
    objects = posteriors{sensorIdx};
    labelCount(sensorIdx) = numel(objects);
    if isempty(objects)
        continue;
    end
    components = arrayfun(@componentCount, objects);
    componentPerLabel(sensorIdx) = mean(components);
    r = min(max([objects.r], eps), 1 - eps);
    existence(sensorIdx) = mean(r);
    existenceEntropy(sensorIdx) = mean( ...
        -r .* log(r) - (1 - r) .* log(1 - r));
    associationMass(sensorIdx) = mean(arrayfun( ...
        @(object) scalarField(object, ...
            'detectionAssociationMass', 0), objects));
    associationEntropy(sensorIdx) = mean(arrayfun( ...
        @(object) scalarField(object, 'associationEntropy', 0), ...
        objects));
    traces = zeros(1, numel(objects));
    for objectIdx = 1:numel(objects)
        traces(objectIdx) = objectPositionVariance(objects(objectIdx));
    end
    positionVariance(sensorIdx) = mean(traces);
end
values = [ ...
    finiteMean(labelCount), ...
    finiteMean(componentPerLabel), ...
    finiteMean(existence), ...
    finiteMean(existenceEntropy), ...
    finiteMean(associationMass), ...
    finiteMean(associationEntropy), ...
    finiteMean(positionVariance)];
names = { ...
    'posterior_label_count_mean', ...
    'posterior_components_per_label_mean', ...
    'posterior_existence_mean', ...
    'posterior_existence_entropy_mean', ...
    'posterior_association_mass_mean', ...
    'posterior_association_entropy_mean', ...
    'posterior_position_variance_mean'};
end

function value = componentCount(object)
value = scalarField(object, 'numberOfGmComponents', 0);
if value <= 0 && isfield(object, 'w')
    value = numel(object.w);
end
end

function value = objectPositionVariance(object)
value = 0;
if ~isfield(object, 'Sigma') || isempty(object.Sigma)
    return;
end
covariances = object.Sigma;
if ~iscell(covariances)
    covariances = {covariances};
end
weights = ones(1, numel(covariances));
if isfield(object, 'w') && numel(object.w) == numel(covariances)
    weights = max(reshape(double(object.w), 1, []), 0);
end
weights = weights / max(sum(weights), eps);
for componentIdx = 1:numel(covariances)
    covariance = covariances{componentIdx};
    if isnumeric(covariance) && size(covariance, 1) >= 2 && ...
            size(covariance, 2) >= 2 && ...
            all(all(isfinite(covariance(1:2, 1:2))))
        value = value + weights(componentIdx) * ...
            max(trace(covariance(1:2, 1:2)), 0);
    end
end
end

function [values, names] = linkFeatures( ...
        context, receiverIndices, senderIndices)
nodeCount = numel(context.localPosteriorBySensor);
pDrop = zeros(nodeCount);
if isfield(context.commConfig, 'pDropByEdge')
    pDrop = context.commConfig.pDropByEdge;
elseif isfield(context.commConfig, 'pDropBySensor')
    pDrop = repmat(reshape( ...
        context.commConfig.pDropBySensor, 1, []), nodeCount, 1);
end
indices = sub2ind([nodeCount, nodeCount], senderIndices, receiverIndices);
success = 1 - min(max(pDrop(indices), 0), 1);
selectedRate = historyEdgeRate( ...
    context, 'previousAdjacencyHistory', ...
    receiverIndices, senderIndices);
deliveryRate = historyEdgeRate( ...
    context, 'previousDeliveryHistory', ...
    receiverIndices, senderIndices);
values = [ ...
    finiteMean(success), finiteMinimum(success), ...
    selectedRate, deliveryRate, deliveryRate - selectedRate];
names = { ...
    'abstained_edge_current_success_mean', ...
    'abstained_edge_current_success_min', ...
    'abstained_edge_past_selected_rate', ...
    'abstained_edge_past_delivery_rate', ...
    'abstained_edge_past_delivery_minus_selected_rate'};
end

function value = historyEdgeRate( ...
        context, fieldName, receiverIndices, senderIndices)
value = 0;
if ~isfield(context, fieldName) || isempty(context.(fieldName))
    return;
end
history = logical(context.(fieldName));
samples = false(numel(receiverIndices), size(history, 3));
for edgeIdx = 1:numel(receiverIndices)
    samples(edgeIdx, :) = reshape(history( ...
        receiverIndices(edgeIdx), senderIndices(edgeIdx), :), 1, []);
end
value = mean(samples(:));
end

function [values, names] = updateFeatures( ...
        context, protectedSensors, upstreamSensors)
fields = { ...
    'localInnovationHistory', ...
    'localAssociationConfidenceHistory', ...
    'localNisNormHistory', ...
    'localNisDeviationHistory'};
baseNames = { ...
    'innovation', 'association_confidence', ...
    'nis_norm', 'nis_deviation'};
values = zeros(1, 4 * numel(fields));
names = cell(1, numel(values));
cursor = 0;
for fieldIdx = 1:numel(fields)
    history = context.(fields{fieldIdx});
    [protectedCurrent, protectedTrend] = ...
        summarizeHistory(history(protectedSensors, :));
    [upstreamCurrent, upstreamTrend] = ...
        summarizeHistory(history(upstreamSensors, :));
    currentValues = [ ...
        protectedCurrent, upstreamCurrent, ...
        upstreamCurrent - protectedCurrent, ...
        upstreamTrend - protectedTrend];
    currentNames = { ...
        ['protected_update_', baseNames{fieldIdx}, '_current'], ...
        ['upstream_update_', baseNames{fieldIdx}, '_current'], ...
        ['upstream_minus_protected_update_', ...
            baseNames{fieldIdx}, '_current'], ...
        ['upstream_minus_protected_update_', ...
            baseNames{fieldIdx}, '_trend']};
    values(cursor + (1:4)) = currentValues;
    names(cursor + (1:4)) = currentNames;
    cursor = cursor + 4;
end
end

function [current, trend] = summarizeHistory(history)
if isempty(history)
    current = 0;
    trend = 0;
    return;
end
latest = history(:, end);
first = history(:, 1);
current = finiteMean(latest);
trend = finiteMean(latest - first);
end

function [values, names] = sensorFeatures( ...
        context, protectedSensors, upstreamSensors, ...
        receiverIndices, senderIndices)
if ~isfield(context.model, 'sensorObservation')
    error('CounterfactualRegretV133:MissingSensorObservation', ...
        'The V133 feature row requires current sensor observations.');
end
observation = context.model.sensorObservation;
detection = reshape(observation.detectionProbability, 1, []);
range = reshape(observation.sensorFovRange, 1, []);
noiseTrace = cellfun(@trace, observation.measurementCovariance);
positions = observation.currentPosition;
edgeDistance = sqrt(sum(( ...
    positions(:, receiverIndices) - positions(:, senderIndices)).^2, 1));
edgeRange = max(range(receiverIndices), eps);
normalizedDistance = edgeDistance ./ edgeRange;
values = [ ...
    finiteMean(detection(protectedSensors)), ...
    finiteMean(detection(upstreamSensors)), ...
    finiteMean(noiseTrace(protectedSensors)), ...
    finiteMean(noiseTrace(upstreamSensors)), ...
    finiteMean(range(protectedSensors)), ...
    finiteMean(range(upstreamSensors)), ...
    finiteMean(edgeDistance), finiteMaximum(edgeDistance), ...
    finiteMean(normalizedDistance), finiteMaximum(normalizedDistance)];
names = { ...
    'protected_detection_probability_mean', ...
    'upstream_detection_probability_mean', ...
    'protected_measurement_noise_trace_mean', ...
    'upstream_measurement_noise_trace_mean', ...
    'protected_fov_range_mean', ...
    'upstream_fov_range_mean', ...
    'abstained_edge_sensor_distance_mean', ...
    'abstained_edge_sensor_distance_max', ...
    'abstained_edge_distance_over_receiver_range_mean', ...
    'abstained_edge_distance_over_receiver_range_max'};
end

function [values, names] = protectionFeatures(history)
age = scalarField(history, 'consecutiveAge', 0);
duty = scalarField(history, 'recentDutyCycle', 0);
sinceRelease = scalarField(history, 'timeSinceRelease', 0);
available = scalarField(history, 'available', 0);
values = [age, duty, sinceRelease, available];
names = { ...
    'protection_consecutive_age', ...
    'protection_recent_duty_cycle', ...
    'protection_time_since_release', ...
    'protection_history_available'};
end

function [values, names] = propagationFeatures( ...
        adjacency, groupIds, protectedFormationId, ...
        receiverIndices, senderIndices)
formationIds = unique(groupIds, 'stable');
formationCount = numel(formationIds);
formationAdjacency = false(formationCount);
for receiverFormationIdx = 1:formationCount
    receiverMembers = groupIds == formationIds(receiverFormationIdx);
    for senderFormationIdx = 1:formationCount
        senderMembers = groupIds == formationIds(senderFormationIdx);
        formationAdjacency(receiverFormationIdx, senderFormationIdx) = ...
            any(any(adjacency(receiverMembers, senderMembers)));
    end
end
sourceIdx = find(formationIds == protectedFormationId, 1);
distances = graphDistances(formationAdjacency, sourceIdx);
finiteDownstream = distances(isfinite(distances) & distances > 0);
diameter = max(formationCount - 1, 1);
values = [ ...
    formationCount, ...
    numel(finiteDownstream) / max(formationCount - 1, 1), ...
    finiteMean(finiteDownstream), finiteMaximum(finiteDownstream), ...
    finiteMean(finiteDownstream) / diameter, ...
    finiteMaximum(finiteDownstream) / diameter, ...
    numel(receiverIndices) / max(nnz(adjacency), 1), ...
    numel(unique(senderIndices)) / max(sum(groupIds ~= ...
        protectedFormationId), 1)];
names = { ...
    'formation_count', ...
    'downstream_formation_fraction', ...
    'downstream_hop_distance_mean', ...
    'downstream_hop_distance_max', ...
    'downstream_hop_distance_mean_normalized', ...
    'downstream_hop_distance_max_normalized', ...
    'abstained_edge_fraction_of_route', ...
    'abstained_unique_sender_fraction'};
end

function distances = graphDistances(adjacency, sourceIdx)
distances = inf(1, size(adjacency, 1));
distances(sourceIdx) = 0;
queue = sourceIdx;
while ~isempty(queue)
    current = queue(1);
    queue(1) = [];
    receivers = reshape(find(adjacency(:, current)), 1, []);
    for receiverIdx = receivers
        if isfinite(distances(receiverIdx))
            continue;
        end
        distances(receiverIdx) = distances(current) + 1;
        queue(end + 1) = receiverIdx; %#ok<AGROW>
    end
end
end

function output = addPrefix(names, prefix)
output = cellfun(@(name) [prefix, name], names, ...
    'UniformOutput', false);
end

function value = scalarField(data, name, fallback)
value = fallback;
if isstruct(data) && isscalar(data) && isfield(data, name)
    candidate = data.(name);
    if isnumeric(candidate) && isscalar(candidate) && isfinite(candidate)
        value = double(candidate);
    elseif islogical(candidate) && isscalar(candidate)
        value = double(candidate);
    end
end
end

function value = finiteMean(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = 0;
else
    value = mean(values);
end
end

function value = finiteMinimum(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = 0;
else
    value = min(values);
end
end

function value = finiteMaximum(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = 0;
else
    value = max(values);
end
end
