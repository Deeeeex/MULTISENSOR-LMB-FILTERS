function protocol = getMaturedHandoffV103Protocol()
% GETMATUREDHANDOFFV103PROTOCOL Protect first, transport matured output later.

source = getPropagationAwareDwellV101Protocol();
route = getFormationIsolateReconnectProbeProtocol();
protocol = source;
protocol.id = 'matured-handoff-v103-v1';
protocol.contractVersion = 'matured-handoff-v103-protocol-v1';
protocol.outcomePolicyName = 'matured-handoff-v103-v1';
protocol.horizonSteps = 8;
protocol.protectionMaturitySteps = source.minimumDwellSteps;
allFormations = 1:6;
protocol.protectionFormationIdsByTime = [ ...
    source.dwellFormationIdsByTime, ...
    {allFormations, allFormations}];
protocol.handoffFormationIdsByTime = { ...
    zeros(1, 0), ...                         % t=72: protect
    zeros(1, 0), ...                         % t=73: protect
    zeros(1, 0), ...                         % t=74: third protected output
    [1, 2, 4, 5], ...                        % t=75: first matured handoff
    zeros(1, 0), ...                         % t=76: reference recovery
    3, ...                                   % t=77: delayed F3 handoff
    zeros(1, 0), ...                         % t=78: reference recovery
    6};                                      % t=79: delayed F6 handoff
protocol.handoffCadence = 'matured-once-reference-recovery-v1';
protocol.firstHandoffTimeIndex = 4;
protocol.targetFormationId = 6;
protocol.dominantWeight = route.dominantWeight;
protocol.residualWeight = route.residualWeight;
protocol.minimumFormationGainPercent = 1;
protocol.minimumTargetPeerTerminalGainPercent = 1;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v103', 'matured_handoff');
protocol.headroomOutputRoot = fullfile( ...
    protocol.outputRoot, 'matched_static_headroom');
protocol.evidenceBoundary = [ ...
    'V103 is a frozen matched-static causal headroom probe. It retains ', ...
    'V101 protection for three complete fusion pages before a gateway ', ...
    'posterior is eligible for one later within-formation handoff. ', ...
    'Different formation activation times determine the handoff pages; ', ...
    'reference-recovery pages separate all handoffs so rolling three-page ', ...
    'sensor- and formation-level reachability is retained. Every changed ', ...
    'row preserves its reference message count and positive-weight ', ...
    'multiset. Static and candidate arms share the cached posterior, ', ...
    'measurements, delivery uniforms, filter RNG, carrier graph, ', ...
    'communication model and horizon. The schedule is frozen before V103 ', ...
    'outcomes are opened and is not an online policy or validation claim.'];
end
