function artifactId = computeRollingSafeRolloutArtifactId(model)
% COMPUTEROLLINGSAFEROLLOUTARTIFACTID Hash model, split and gate metadata.

required = { ...
    'artifactIdVersion', 'protocolId', 'kind', ...
    'sourceWeight', 'payloadToleranceFraction', ...
    'filterSeedOffset', 'behaviorCacheSha256', ...
    'featureContextMode', 'allFeatureNames', ...
    'trainingSeeds', 'auditSeeds', ...
    'designSeeds', 'datasetSeeds', ...
    'datasetGenerationGitCommit', ...
    'datasetGenerationResearchWorktreeDirty', ...
    'featuresUseTruth', 'labelsUseTruth', ...
    'labelSelectionUsesFutureOutcome', ...
    'datasetContractVersion', 'datasetSha256', ...
    'featureContractSha256', 'trainingConfigSha256', ...
    'trainingGitCommit', 'trainingWorktreeDirty', ...
    'frozen', 'acceptedForClosedLoopScreen', ...
    'acceptanceThresholds', 'imitationGateMetrics', ...
    'featureMean', 'featureScale', 'featureMask', ...
    'hiddenWeight', 'hiddenBias', 'outputWeight', 'outputBias'};
if ~isstruct(model) || ~all(isfield(model, required))
    error('Rolling-safe rollout artifact hash contract is invalid.');
end
thresholds = model.acceptanceThresholds;
metrics = model.imitationGateMetrics;
thresholdFields = { ...
    'minimumSeedProjectedEdgeF1', ...
    'minimumMeanProjectedEdgeF1', ...
    'minimumBlockProjectedEdgeF1', ...
    'minimumSeedProjectedEdgeRecall', ...
    'minimumMeanProjectedEdgeRecall', ...
    'minimumSeedProjectedExactGraphFraction', ...
    'minimumMeanProjectedExactGraphFraction', ...
    'minimumZeroEdgeExactFraction', ...
    'minimumSingleEdgeExactFraction', ...
    'minimumZeroEdgeBlockCount', ...
    'minimumSingleEdgeBlockCount'};
metricFields = { ...
    'minimumHeldoutSeedProjectedEdgeF1', ...
    'meanHeldoutProjectedEdgeF1', ...
    'minimumHeldoutBlockProjectedEdgeF1', ...
    'minimumHeldoutSeedProjectedEdgeRecall', ...
    'meanHeldoutProjectedEdgeRecall', ...
    'minimumHeldoutProjectedExactGraphFraction', ...
    'meanHeldoutProjectedExactGraphFraction', ...
    'minimumHeldoutZeroEdgeExactFraction', ...
    'minimumHeldoutSingleEdgeExactFraction', ...
    'heldoutZeroEdgeBlockCount', ...
    'heldoutSingleEdgeBlockCount'};
if ~all(isfield(thresholds, thresholdFields)) || ...
        ~all(isfield(metrics, metricFields))
    error('Rolling-safe rollout artifact gate metadata is invalid.');
end

numericParameters = [ ...
    model.hiddenWeight(:); model.hiddenBias(:); ...
    model.outputWeight(:); model.outputBias(:); ...
    model.featureMean(:); model.featureScale(:); ...
    double(model.featureMask(:))];
if any(~isfinite(numericParameters))
    error('Rolling-safe rollout artifact parameters are non-finite.');
end
parameterText = sprintf('%.17g,', numericParameters);
metadataText = sprintf( ...
    ['version=%s|protocol=%s|kind=%s|weight=%.17g|payload=%s|', ...
     'filterseedoffset=%d|cache=%s|', ...
     'context=%s|features=%s|train=%s|audit=%s|design=%s|', ...
     'datasetseeds=%s|datasetgit=%s|datasetdirty=%d|featuretruth=%d|', ...
     'labeltruth=%d|futurelabels=%d|datasetcontract=%s|', ...
     'dataset=%s|feature=%s|config=%s|git=%s|dirty=%d|', ...
     'frozen=%d|accepted=%d|minseedf1=%.17g|', ...
     'meanf1=%.17g|minblockf1=%.17g|minseedrecall=%.17g|', ...
     'meanrecall=%.17g|minseedexact=%.17g|meanexact=%.17g|', ...
     'zeroexact=%.17g|singleexact=%.17g|', ...
     'zerocount=%d|singlecount=%d|', ...
     'observedminseedf1=%.17g|observedmeanf1=%.17g|', ...
     'observedminblockf1=%.17g|observedminseedrecall=%.17g|', ...
     'observedmeanrecall=%.17g|observedminseedexact=%.17g|', ...
     'observedmeanexact=%.17g|observedzeroexact=%s|', ...
     'observedsingleexact=%s|observedzerocount=%d|', ...
     'observedsinglecount=%d|parameters=%s'], ...
    char(model.artifactIdVersion), char(model.protocolId), ...
    char(model.kind), model.sourceWeight, ...
    formatScalar(model.payloadToleranceFraction), ...
    model.filterSeedOffset, ...
    strjoin(reshape(model.behaviorCacheSha256, 1, []), ...
        char(31)), ...
    char(model.featureContextMode), ...
    strjoin(reshape(model.allFeatureNames, 1, []), char(31)), ...
    mat2str(reshape(model.trainingSeeds, 1, [])), ...
    mat2str(reshape(model.auditSeeds, 1, [])), ...
    mat2str(reshape(model.designSeeds, 1, [])), ...
    mat2str(reshape(model.datasetSeeds, 1, [])), ...
    char(model.datasetGenerationGitCommit), ...
    logical(model.datasetGenerationResearchWorktreeDirty), ...
    logical(model.featuresUseTruth), ...
    logical(model.labelsUseTruth), ...
    logical(model.labelSelectionUsesFutureOutcome), ...
    char(model.datasetContractVersion), ...
    char(model.datasetSha256), ...
    char(model.featureContractSha256), ...
    char(model.trainingConfigSha256), ...
    char(model.trainingGitCommit), ...
    logical(model.trainingWorktreeDirty), ...
    logical(model.frozen), ...
    logical(model.acceptedForClosedLoopScreen), ...
    thresholds.minimumSeedProjectedEdgeF1, ...
    thresholds.minimumMeanProjectedEdgeF1, ...
    thresholds.minimumBlockProjectedEdgeF1, ...
    thresholds.minimumSeedProjectedEdgeRecall, ...
    thresholds.minimumMeanProjectedEdgeRecall, ...
    thresholds.minimumSeedProjectedExactGraphFraction, ...
    thresholds.minimumMeanProjectedExactGraphFraction, ...
    thresholds.minimumZeroEdgeExactFraction, ...
    thresholds.minimumSingleEdgeExactFraction, ...
    thresholds.minimumZeroEdgeBlockCount, ...
    thresholds.minimumSingleEdgeBlockCount, ...
    metrics.minimumHeldoutSeedProjectedEdgeF1, ...
    metrics.meanHeldoutProjectedEdgeF1, ...
    metrics.minimumHeldoutBlockProjectedEdgeF1, ...
    metrics.minimumHeldoutSeedProjectedEdgeRecall, ...
    metrics.meanHeldoutProjectedEdgeRecall, ...
    metrics.minimumHeldoutProjectedExactGraphFraction, ...
    metrics.meanHeldoutProjectedExactGraphFraction, ...
    formatScalar(metrics.minimumHeldoutZeroEdgeExactFraction), ...
    formatScalar(metrics.minimumHeldoutSingleEdgeExactFraction), ...
    metrics.heldoutZeroEdgeBlockCount, ...
    metrics.heldoutSingleEdgeBlockCount, ...
    parameterText);
artifactId = computeTextSha256(metadataText);
end

function token = formatScalar(value)
if isnan(value)
    token = 'nan';
elseif isinf(value)
    token = 'inf';
else
    token = sprintf('%.17g', value);
end
end
