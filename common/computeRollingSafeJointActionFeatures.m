end
end

function value = boundedRatio(ratio)
if ratio <= 0
    value = 0;
else
    value = ratio / (1 + ratio);
end
end

function value = setJaccard(left, right)
left = unique(reshape(left, 1, []));
right = unique(reshape(right, 1, []));
unionCount = numel(union(left, right));
if unionCount == 0
    value = 1;
else
    value = numel(intersect(left, right)) / unionCount;
end
end

function value = safeMean(values, columnCount)
if isempty(values)
    value = zeros(1, columnCount);
else
    value = mean(values, 1);
end
end

