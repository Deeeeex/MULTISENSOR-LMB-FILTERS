function [features, featureNames, metadata] = ...
    computeRollingSafeJointActionFeatures( ...
        block, selectedCrossMask, options)
% COMPUTEROLLINGSAFEJOINTACTIONFEATURES Invariant state-action summary.
%
% The critic consumes one complete safe cross-formation action, not
% independent edge labels. Candidate-edge features are first reduced to
% seventeen semantic channels, pooled within formation pairs, and then pooled
% across the whole state/action. No sensor index or formation identifier is
% retained, so consistent sensor and formation relabellings leave the
% representation unchanged.

if nargin < 3 || isempty(options)
    options = struct();
end
requiredFields = { ...
    'features', 'featureNames', 'receiverIndices', ...
    'senderIndices', 'groupIds', 'senderPayloadBytes', ...
    'featureMetadata', 'currentTime', ...
    'previousAdjacencyHistory', ...
    'previousAdjacencyHistoryTimes'};
if ~isstruct(block) || ~all(isfield(block, requiredFields))
    error('Joint-action feature block is incomplete.');
end

rawFeatures = block.features;
rawNames = reshape(block.featureNames, 1, []);
if ~iscell(rawNames) || isempty(rawNames) || ...
        any(cellfun(@(value) ...
            ~ischar(value) || isempty(strtrim(value)), ...
            rawNames)) || ...
        numel(unique(rawNames)) ~= numel(rawNames)
    error('Joint-action raw feature names are invalid.');
end
validateStateFeatureMetadata( ...
    block.featureMetadata, rawNames);
actionProposalTruthUsed = requireLogicalOption( ...
    options, 'actionProposalTruthUsed');
actionProposalOutcomeSelected = requireLogicalOption( ...
    options, 'actionProposalOutcomeSelected');
actionProposalSource = requireTextOption( ...
    options, 'actionProposalSource');
receiverIndices = reshape(block.receiverIndices, [], 1);
senderIndices = reshape(block.senderIndices, [], 1);
selectedCrossMask = validateBinaryMask( ...
    selectedCrossMask, 'selected cross');
exampleCount = numel(receiverIndices);
if size(rawFeatures, 1) ~= exampleCount || ...
        numel(senderIndices) ~= exampleCount || ...
        numel(selectedCrossMask) ~= exampleCount || ...
        size(rawFeatures, 2) ~= numel(rawNames) || ...
        isempty(rawFeatures) || any(~isfinite(rawFeatures(:)))
    error('Joint-action edge features are invalid or misaligned.');
end

groupIds = reshape(block.groupIds, 1, []);
nodeCount = numel(groupIds);
if nodeCount < 2 || ...
        ~isnumeric(groupIds) || ...
        any(~isfinite(groupIds)) || ...
        any(mod(groupIds, 1) ~= 0) || ...
        any(receiverIndices < 1 | receiverIndices > nodeCount | ...
            senderIndices < 1 | senderIndices > nodeCount | ...
            mod(receiverIndices, 1) ~= 0 | ...
            mod(senderIndices, 1) ~= 0) || ...
        any(groupIds(receiverIndices) == groupIds(senderIndices))
    error('Joint-action edge indices or formation assignments are invalid.');
end
keys = receiverIndices + nodeCount * (senderIndices - 1);
if numel(unique(keys)) ~= numel(keys)
    error('Joint-action candidate edges must be unique.');
end
validateReceiverUniqueness(receiverIndices, selectedCrossMask);
[selectedHistory, selectedHistoryTimes] = ...
    validateTemporalState(block, nodeCount);
validateStateFeatureAlignment( ...
    block.featureMetadata, receiverIndices, ...
    senderIndices, nodeCount, ...
    size(selectedHistory, 3));

referenceCrossMask = validateBinaryMask(getField( ...
    options, 'referenceCrossMask', ...
    false(exampleCount, 1)), 'reference cross');
if numel(referenceCrossMask) ~= exampleCount
    error('Joint-action reference mask is misaligned.');
end
validateReceiverUniqueness(receiverIndices, referenceCrossMask);

payloadBytes = reshape(block.senderPayloadBytes, 1, []);
if numel(payloadBytes) ~= nodeCount || ...
        any(~isfinite(payloadBytes)) || any(payloadBytes < 0)
    error('Joint-action sender payload estimates are invalid.');
end

[semantic, semanticNames] = buildSemanticChannels( ...
    rawFeatures, rawNames, senderIndices, payloadBytes);
[canonicalGroups, groupCount] = canonicalizeGroups(groupIds);
if nnz(selectedCrossMask) > groupCount - 1 || ...
        nnz(referenceCrossMask) > groupCount - 1
    error(['Joint safe actions may use at most one fewer cross edge ', ...
        'than the formation count.']);
end
receiverGroups = reshape( ...
    canonicalGroups(receiverIndices), [], 1);
senderGroups = reshape( ...
    canonicalGroups(senderIndices), [], 1);
pairKeys = receiverGroups + groupCount * (senderGroups - 1);

parts = {};
names = {};
[parts, names] = appendPool( ...
    parts, names, semantic, 'state_edge_', semanticNames);
[parts, names] = appendPool( ...
    parts, names, poolWithinKeys(semantic, pairKeys), ...
    'state_formation_pair_', semanticNames);
[parts, names] = appendPool( ...
    parts, names, semantic(selectedCrossMask, :), ...
    'action_edge_', semanticNames);
[parts, names] = appendPool( ...
    parts, names, poolWithinKeys( ...
        semantic(selectedCrossMask, :), ...
        pairKeys(selectedCrossMask)), ...
    'action_formation_pair_', semanticNames);
[parts, names] = appendPool( ...
    parts, names, semantic(referenceCrossMask, :), ...
    'reference_edge_', semanticNames);
addedMask = selectedCrossMask & ~referenceCrossMask;
removedMask = referenceCrossMask & ~selectedCrossMask;
[parts, names] = appendPool( ...
    parts, names, semantic(addedMask, :), ...
    'added_edge_', semanticNames);
[parts, names] = appendPool( ...
    parts, names, semantic(removedMask, :), ...
    'removed_edge_', semanticNames);
[parts, names] = appendCrossMoments( ...
    parts, names, semantic(selectedCrossMask, 1:11), ...
    'action_edge_', semanticNames(1:11));
[parts, names] = appendCrossMoments( ...
    parts, names, semantic(referenceCrossMask, 1:11), ...
    'reference_edge_', semanticNames(1:11));
[parts, names] = appendCrossMoments( ...
    parts, names, semantic(addedMask, 1:11), ...
    'added_edge_', semanticNames(1:11));
[parts, names] = appendCrossMoments( ...
    parts, names, semantic(removedMask, 1:11), ...
    'removed_edge_', semanticNames(1:11));

actionMean = safeMean(semantic(selectedCrossMask, :), ...
    numel(semanticNames));
referenceMean = safeMean( ...
    semantic(referenceCrossMask, :), numel(semanticNames));
parts{end + 1} = actionMean - referenceMean;
names = [names, prefixNames( ...
    semanticNames, 'action_minus_reference_mean_')]; %#ok<AGROW>

[structureFeatures, structureNames] = ...
    computeInvariantStructureFeatures( ...
        selectedCrossMask, referenceCrossMask, ...
        receiverIndices, senderIndices, receiverGroups, ...
        senderGroups, pairKeys, canonicalGroups, ...
        groupCount, nodeCount, ...
        payloadBytes);
parts{end + 1} = structureFeatures;
names = [names, structureNames]; %#ok<AGROW>
[temporalFeatures, temporalNames] = ...
    computeTemporalSafetyFeatures( ...
        selectedCrossMask, receiverIndices, ...
        senderIndices, canonicalGroups, ...
        groupCount, nodeCount, ...
        selectedHistory, selectedHistoryTimes, ...
        block.currentTime);
parts{end + 1} = temporalFeatures;
names = [names, temporalNames]; %#ok<AGROW>

features = [parts{:}];
featureNames = reshape(names, 1, []);
if numel(features) ~= numel(featureNames) || ...
        any(~isfinite(features))
    error('Joint-action representation is non-finite or misaligned.');
end

metadata = struct( ...
    'contractVersion', ...
        'rolling-safe-joint-action-features-v2', ...
    'semanticChannelNames', {semanticNames}, ...
    'featureNames', {featureNames}, ...
    'featureCount', numel(features), ...
    'nodeCount', nodeCount, ...
    'formationCount', groupCount, ...
    'candidateEdgeCount', exampleCount, ...
    'selectedCrossEdgeCount', nnz(selectedCrossMask), ...
    'referenceCrossEdgeCount', nnz(referenceCrossMask), ...
    'sensorPermutationInvariant', true, ...
    'formationLabelPermutationInvariant', true, ...
    'scaleNormalizedCounts', true, ...
    'posteriorUsed', true, ...
    'historyUsed', true, ...
    'selectedHistoryUsed', true, ...
    'deliveredHistoryUsed', false, ...
    'crossChannelMomentsUsed', true, ...
    'rollingB3SafetyStateUsed', true, ...
    'deploymentRequiresGlobalDeliveryAcknowledgements', false, ...
    'centralizedTruthFreeCoordinatorAssumed', true, ...
    'controlMetadataTrafficAccounted', false, ...
    'payloadMetadataUsed', true, ...
    'stateFeatureTruthUsed', false, ...
    'actionProposalTruthUsed', ...
        actionProposalTruthUsed, ...
    'actionProposalOutcomeSelected', ...
        actionProposalOutcomeSelected, ...
    'actionProposalSource', actionProposalSource, ...
    'truthUsed', actionProposalTruthUsed || ...
        actionProposalOutcomeSelected, ...
    'groundTruthUsed', actionProposalTruthUsed, ...
    'futureOutcomeUsed', ...
        actionProposalOutcomeSelected);
metadata.featureContractSha256 = computeTextSha256(sprintf( ...
    '%s|%s', metadata.contractVersion, ...
    strjoin(featureNames, char(31))));
end

function validateStateFeatureMetadata(metadata, featureNames)
required = { ...
    'contractVersion', 'sourceWeight', ...
    'featureContextMode', 'featureNames', ...
    'featureContractSha256', 'truthUsed', ...
    'groundTruthUsed', 'futureOutcomeUsed', ...
    'rawFeatureNames', 'posteriorUsed', ...
    'currentLinkReliabilityUsed', 'historyUsed', ...
    'currentGeometryUsed', ...
    'previousAdjacencyConvention', ...
    'historyDepth', 'nodeCount', ...
    'crossFormationExampleCount', ...
    'candidateEdgeKeys'};
if ~isstruct(metadata) || ~all(isfield(metadata, required)) || ...
        ~strcmp(metadata.contractVersion, ...
            'rolling-safe-directed-action-features-v1') || ...
        ~strcmp(lower(strrep(char( ...
            metadata.featureContextMode), '_', '-')), 'raw') || ...
        ~isequal(reshape(metadata.featureNames, 1, []), ...
            reshape(featureNames, 1, [])) || ...
        ~isscalar(metadata.sourceWeight) || ...
        ~isfinite(metadata.sourceWeight) || ...
        metadata.sourceWeight <= 0 || ...
        metadata.sourceWeight >= 1 || ...
        ~isequal(reshape(metadata.rawFeatureNames, 1, []), ...
            reshape(featureNames, 1, [])) || ...
        ~logical(metadata.posteriorUsed) || ...
        ~logical(metadata.currentLinkReliabilityUsed) || ...
        ~logical(metadata.historyUsed) || ...
        ~logical(metadata.currentGeometryUsed) || ...
        ~strcmp(metadata.previousAdjacencyConvention, ...
            ['receiver-row-sender-column-directed-', ...
             'oldest-to-newest']) || ...
        logical(metadata.truthUsed) || ...
        logical(metadata.groundTruthUsed) || ...
        logical(metadata.futureOutcomeUsed)
    error(['Joint-action state features violate the truth-free raw ', ...
        'feature contract.']);
end
expected = computeTextSha256(sprintf( ...
    '%s|%.17g|%s', metadata.contractVersion, ...
    metadata.sourceWeight, ...
    strjoin(featureNames, char(31))));
if ~strcmp(metadata.featureContractSha256, expected)
    error('Joint-action state feature contract hash mismatch.');
end
end

function validateStateFeatureAlignment( ...
        metadata, receiverIndices, senderIndices, ...
        nodeCount, historyDepth)
expectedKeys = receiverIndices + ...
    nodeCount * (senderIndices - 1);
if ~isscalar(metadata.nodeCount) || ...
        metadata.nodeCount ~= nodeCount || ...
        ~isscalar(metadata.crossFormationExampleCount) || ...
        metadata.crossFormationExampleCount ~= ...
            numel(receiverIndices) || ...
        ~isscalar(metadata.historyDepth) || ...
        metadata.historyDepth ~= historyDepth || ...
        ~isequal(reshape(metadata.candidateEdgeKeys, [], 1), ...
            reshape(expectedKeys, [], 1))
    error('Joint-action state feature edge/history alignment mismatch.');
end
end

function [semantic, names] = buildSemanticChannels( ...
        rawFeatures, rawNames, senderIndices, payloadBytes)
value = @(name) rawFeatures(:, requireFeature(rawNames, name));
sourceQuality = mean([ ...
    value('source_expected_cardinality_fraction'), ...
    value('source_association_confidence'), ...
    value('source_detection_mass'), ...
    value('node_quality_advantage')], 2);
receiverNeed = mean([ ...
    value('receiver_need'), ...
    value('receiver_cardinality_variance_fraction'), ...
    value('receiver_position_variance'), ...
    1 - value('receiver_association_confidence')], 2);
existenceTransfer = value('positive_existence_gain') - ...
    value('negative_existence_gap');
precisionTransfer = value('positive_precision_gain') - ...
    value('negative_precision_gap');
compatibility = mean([ ...
    value('active_label_overlap'), ...
    value('moment_compatibility_score')], 2);
edgeHistory = mean([ ...
    value('history_edge_frequency'), ...
    value('previous_edge')], 2);
pairHistory = mean([ ...
    value('formation_pair_history_frequency'), ...
    value('latest_formation_pair_active')], 2);
meanPayload = max(mean(payloadBytes), eps);
payloadRatio = payloadBytes(senderIndices)' / meanPayload;
payloadEfficiency = 1 ./ (1 + payloadRatio);

semantic = [ ...
    value('link_reliability'), ...
    1 - value('normalized_sensor_distance'), ...
    sourceQuality, receiverNeed, ...
    existenceTransfer, precisionTransfer, ...
    compatibility, ...
    -value('normalized_state_discrepancy'), ...
    edgeHistory, pairHistory, payloadEfficiency, ...
    value('receiver_history_source_diversity'), ...
    value('receiver_cross_degree_fraction'), ...
    value('sender_cross_reach_fraction'), ...
    value('history_depth_fraction'), ...
    value('rolling_phase_sin'), ...
    value('rolling_phase_cos')];
names = { ...
    'link_reliability', ...
    'proximity', ...
    'source_posterior_quality', ...
    'receiver_need', ...
    'existence_transfer', ...
    'precision_transfer', ...
    'posterior_compatibility', ...
    'negative_state_discrepancy', ...
    'edge_history', ...
    'formation_pair_history', ...
    'payload_efficiency', ...
    'receiver_history_source_diversity', ...
    'receiver_cross_degree_fraction', ...
    'sender_cross_reach_fraction', ...
    'history_depth_fraction', ...
    'rolling_phase_sin', ...
    'rolling_phase_cos'};
if any(~isfinite(semantic(:)))
    error('Joint-action semantic channels are non-finite.');
end
end

function [parts, names] = appendCrossMoments( ...
        parts, names, values, prefix, channelNames)
channelCount = numel(channelNames);
moments = zeros(1, channelCount * ...
    (channelCount - 1) / 2);
momentNames = cell(1, numel(moments));
cursor = 0;
for leftIdx = 1:channelCount
    for rightIdx = (leftIdx + 1):channelCount
        cursor = cursor + 1;
        if ~isempty(values)
            moments(cursor) = mean( ...
                values(:, leftIdx) .* ...
                values(:, rightIdx));
        end
        momentNames{cursor} = sprintf( ...
            '%scross_moment_%s_x_%s', ...
            prefix, channelNames{leftIdx}, ...
            channelNames{rightIdx});
    end
end
if cursor ~= numel(moments) || ...
        any(~isfinite(moments))
    error('Joint-action cross-channel moments are invalid.');
end
parts{end + 1} = moments;
names = [names, momentNames]; %#ok<AGROW>
end

function [parts, names] = appendPool( ...
        parts, names, values, prefix, channelNames)
[pooled, statistics] = invariantPool(values, numel(channelNames));
parts{end + 1} = pooled;
for statisticIdx = 1:numel(statistics)
    names = [names, prefixNames(channelNames, ...
        [prefix, statistics{statisticIdx}, '_'])]; %#ok<AGROW>
end
end

function [pooled, statistics] = invariantPool(values, channelCount)
statistics = {'mean', 'min', 'max', 'std', ...
    'pair_interaction'};
if isempty(values)
    pooled = zeros(1, numel(statistics) * channelCount);
    return;
end
if size(values, 2) ~= channelCount || ...
        any(~isfinite(values(:)))
    error('Joint-action set pool is invalid.');
end
count = size(values, 1);
location = mean(values, 1);
minimum = min(values, [], 1);
maximum = max(values, [], 1);
spread = std(values, 0, 1);
if count <= 1
    pairInteraction = zeros(1, channelCount);
else
    sums = sum(values, 1);
    pairInteraction = (sums .^ 2 - ...
        sum(values .^ 2, 1)) / (count * (count - 1));
end
pooled = [location, minimum, maximum, spread, pairInteraction];
end

function pooled = poolWithinKeys(values, keys)
if isempty(values)
    pooled = zeros(0, size(values, 2));
    return;
end
keys = reshape(keys, [], 1);
if numel(keys) ~= size(values, 1)
    error('Formation-pair pool keys are misaligned.');
end
uniqueKeys = unique(keys);
pooled = zeros(numel(uniqueKeys), size(values, 2));
for keyIdx = 1:numel(uniqueKeys)
    pooled(keyIdx, :) = mean( ...
        values(keys == uniqueKeys(keyIdx), :), 1);
end
end

function [features, names] = computeInvariantStructureFeatures( ...
        actionMask, referenceMask, receiverIndices, senderIndices, ...
        receiverGroups, senderGroups, pairKeys, allSensorGroups, ...
        groupCount, nodeCount, payloadBytes)
actionCount = nnz(actionMask);
referenceCount = nnz(referenceMask);
edgeDenominator = max(groupCount - 1, 1);
pairDenominator = max(groupCount * (groupCount - 1), 1);
exampleCount = numel(actionMask);

actionPairs = unique(pairKeys(actionMask));
referencePairs = unique(pairKeys(referenceMask));
actionSources = senderIndices(actionMask);
actionReceivers = receiverIndices(actionMask);
actionSourceGroups = senderGroups(actionMask);
actionReceiverGroups = receiverGroups(actionMask);

[sourceFormationCoverage, receiverFormationCoverage, ...
    sourceSensorCoverage, receiverSensorCoverage, ...
    maxSourceSensorLoad, maxReceiverSensorLoad, ...
    maxSourceFormationLoad, maxReceiverFormationLoad, ...
    normalizedOutDegreeMaximum, normalizedInDegreeMaximum, ...
    normalizedDegreeSpread] = actionLoadSummary( ...
        actionSources, actionReceivers, actionSourceGroups, ...
        actionReceiverGroups, groupCount, nodeCount);

actionReferenceJaccard = setJaccard( ...
    find(actionMask), find(referenceMask));
actionPairReferenceJaccard = setJaccard( ...
    actionPairs, referencePairs);
meanPayload = max(mean(payloadBytes), eps);
actionPayload = safeIndexedMean( ...
    payloadBytes, actionSources) / meanPayload;
referencePayload = safeIndexedMean( ...
    payloadBytes, senderIndices(referenceMask)) / meanPayload;
feasiblePairs = numel(unique(pairKeys));
groupSizes = accumarray( ...
    reshape(allSensorGroups, [], 1), 1, [groupCount, 1]);
groupSizeVariation = std(groupSizes, 0, 1) / ...
    max(mean(groupSizes), eps);

features = [ ...
    double(actionCount > 0), ...
    double(referenceCount > 0), ...
    actionCount / edgeDenominator, ...
    referenceCount / edgeDenominator, ...
    nnz(actionMask & ~referenceMask) / edgeDenominator, ...
    nnz(referenceMask & ~actionMask) / edgeDenominator, ...
    numel(actionPairs) / pairDenominator, ...
    numel(referencePairs) / pairDenominator, ...
    sourceFormationCoverage, receiverFormationCoverage, ...
    sourceSensorCoverage, receiverSensorCoverage, ...
    maxSourceSensorLoad, maxReceiverSensorLoad, ...
    maxSourceFormationLoad, maxReceiverFormationLoad, ...
    normalizedOutDegreeMaximum, normalizedInDegreeMaximum, ...
    normalizedDegreeSpread, ...
    actionReferenceJaccard, actionPairReferenceJaccard, ...
    boundedRatio(actionPayload), boundedRatio(referencePayload), ...
    exampleCount / max(nodeCount * (nodeCount - 1), 1), ...
    feasiblePairs / pairDenominator, ...
    groupSizeVariation, 1 / groupCount];
names = { ...
    'action_nonempty', ...
    'reference_nonempty', ...
    'action_cross_count_fraction', ...
    'reference_cross_count_fraction', ...
    'added_cross_count_fraction', ...
    'removed_cross_count_fraction', ...
    'action_formation_pair_fraction', ...
    'reference_formation_pair_fraction', ...
    'action_source_formation_coverage', ...
    'action_receiver_formation_coverage', ...
    'action_source_sensor_coverage', ...
    'action_receiver_sensor_coverage', ...
    'action_max_source_sensor_load', ...
    'action_max_receiver_sensor_load', ...
    'action_max_source_formation_load', ...
    'action_max_receiver_formation_load', ...
    'action_max_formation_out_degree', ...
    'action_max_formation_in_degree', ...
    'action_formation_degree_spread', ...
    'action_reference_edge_jaccard', ...
    'action_reference_pair_jaccard', ...
    'action_payload_ratio_bounded', ...
    'reference_payload_ratio_bounded', ...
    'feasible_cross_edge_density', ...
    'feasible_formation_pair_fraction', ...
    'formation_size_coefficient_of_variation', ...
    'inverse_formation_count'};
end

function [features, names] = computeTemporalSafetyFeatures( ...
        actionMask, receiverIndices, senderIndices, ...
        sensorGroups, groupCount, nodeCount, ...
        selectedHistory, selectedTimes, currentTime)
actionAdjacency = false(groupCount);
selectedRows = find(actionMask);
for rowIdx = reshape(selectedRows, 1, [])
    receiverGroup = sensorGroups( ...
        receiverIndices(rowIdx));
    senderGroup = sensorGroups( ...
        senderIndices(rowIdx));
    actionAdjacency(senderGroup, receiverGroup) = true;
end
selectedUnion = formationUnionFromHistory( ...
    selectedHistory, sensorGroups, ...
    groupCount, nodeCount);
candidateSelectedUnion = ...
    selectedUnion | actionAdjacency;
[actionReach, actionStrong, actionWeak, actionScc] = ...
    formationReachabilityStats(actionAdjacency);
[selectedReach, selectedStrong, ~, selectedScc] = ...
    formationReachabilityStats(selectedUnion);
[candidateSelectedReach, candidateSelectedStrong, ...
    ~, candidateSelectedScc] = ...
        formationReachabilityStats( ...
            candidateSelectedUnion);
pairDenominator = max(groupCount * (groupCount - 1), 1);
selectedDepth = size(selectedHistory, 3);
selectedMature = double(selectedDepth >= 2);
selectedSpan = historySpanFraction( ...
    selectedTimes, currentTime);
selectedOrderJaccard = historyEndpointJaccard( ...
    selectedHistory);
latestSelectedAdjacency = latestFormationAdjacency( ...
    selectedHistory, sensorGroups, ...
    groupCount, nodeCount);
actionLatestSelectedJaccard = setJaccard( ...
    find(actionAdjacency), find(latestSelectedAdjacency));
edgeRemovalStrongFraction = ...
    computeEdgeRemovalStrongFraction( ...
        actionAdjacency, selectedUnion);
phase = mod(currentTime, 3);

features = [ ...
    sin(2 * pi * phase / 3), ...
    cos(2 * pi * phase / 3), ...
    min(selectedDepth, 2) / 2, ...
    selectedMature, selectedSpan, ...
    nnz(actionAdjacency) / pairDenominator, ...
    actionReach, actionStrong, actionWeak, actionScc, ...
    nnz(selectedUnion) / pairDenominator, ...
    selectedReach, selectedStrong, selectedScc, ...
    nnz(candidateSelectedUnion) / pairDenominator, ...
    candidateSelectedReach, candidateSelectedStrong, ...
    candidateSelectedScc, ...
    edgeRemovalStrongFraction, ...
    selectedOrderJaccard, ...
    actionLatestSelectedJaccard];
names = { ...
    'rolling_b3_phase_sin', ...
    'rolling_b3_phase_cos', ...
    'selected_history_depth_fraction', ...
    'selected_history_mature', ...
    'selected_history_span_fraction', ...
    'action_formation_pair_fraction_temporal', ...
    'action_formation_reachability_fraction', ...
    'action_formation_strongly_connected', ...
    'action_formation_weakly_connected', ...
    'action_largest_scc_fraction', ...
    'selected_history_pair_fraction', ...
    'selected_history_reachability_fraction', ...
    'selected_history_strongly_connected', ...
    'selected_history_largest_scc_fraction', ...
    'candidate_selected_b3_pair_fraction', ...
    'candidate_selected_b3_reachability_fraction', ...
    'candidate_selected_b3_strongly_connected', ...
    'candidate_selected_b3_largest_scc_fraction', ...
    'candidate_selected_b3_edge_removal_strong_fraction', ...
    'selected_history_oldest_latest_jaccard', ...
    'action_latest_selected_pair_jaccard'};
if numel(features) ~= numel(names) || ...
        any(~isfinite(features))
    error('Joint-action temporal safety features are invalid.');
end
end

function unionAdjacency = formationUnionFromHistory( ...
        history, sensorGroups, groupCount, nodeCount)
unionAdjacency = false(groupCount);
for pageIdx = 1:size(history, 3)
    unionAdjacency = unionAdjacency | ...
        formationAdjacencyFromSensorPage( ...
            history(:, :, pageIdx), ...
            sensorGroups, groupCount, nodeCount);
end
end

function adjacency = latestFormationAdjacency( ...
        history, sensorGroups, groupCount, nodeCount)
if isempty(history)
    adjacency = false(groupCount);
else
    adjacency = formationAdjacencyFromSensorPage( ...
        history(:, :, end), sensorGroups, ...
        groupCount, nodeCount);
end
end

function adjacency = formationAdjacencyFromSensorPage( ...
        page, sensorGroups, groupCount, nodeCount)
if ~isequal(size(page), [nodeCount, nodeCount])
    error('Joint-action history page has an invalid shape.');
end
adjacency = false(groupCount);
[receivers, senders] = find(page);
for edgeIdx = 1:numel(receivers)
    receiverGroup = sensorGroups(receivers(edgeIdx));
    senderGroup = sensorGroups(senders(edgeIdx));
    if receiverGroup ~= senderGroup
        adjacency(senderGroup, receiverGroup) = true;
    end
end
end

function [reachabilityFraction, stronglyConnected, ...
        weaklyConnected, largestSccFraction] = ...
        formationReachabilityStats(adjacency)
groupCount = size(adjacency, 1);
reach = transitiveClosure(adjacency);
offDiagonal = ~eye(groupCount);
reachabilityFraction = nnz( ...
    reach & offDiagonal) / ...
    max(groupCount * (groupCount - 1), 1);
stronglyConnected = double( ...
    all(reach(offDiagonal)));
weakReach = transitiveClosure( ...
    adjacency | adjacency');
weaklyConnected = double(all( ...
    weakReach(offDiagonal)));
largestScc = 1;
for groupIdx = 1:groupCount
    mutuallyReachable = ...
        reach(groupIdx, :) & ...
        reshape(reach(:, groupIdx), 1, []);
    largestScc = max( ...
        largestScc, nnz(mutuallyReachable));
end
largestSccFraction = largestScc / groupCount;
end

function reach = transitiveClosure(adjacency)
groupCount = size(adjacency, 1);
reach = logical(adjacency) | (eye(groupCount) > 0);
for pivotIdx = 1:groupCount
    reach = reach | ( ...
        reach(:, pivotIdx) & ...
        reach(pivotIdx, :));
end
end

function fraction = computeEdgeRemovalStrongFraction( ...
        actionAdjacency, historyUnion)
edges = find(actionAdjacency);
if isempty(edges)
    [~, strong] = formationReachabilityStats( ...
        historyUnion);
    fraction = strong;
    return;
end
passes = false(1, numel(edges));
for edgeIdx = 1:numel(edges)
    candidate = actionAdjacency;
    candidate(edges(edgeIdx)) = false;
    [~, passes(edgeIdx)] = ...
        formationReachabilityStats( ...
            historyUnion | candidate);
end
fraction = mean(passes);
end

function value = historySpanFraction(times, currentTime)
