    value = 0;
else
    value = min( ...
        currentTime - times(1), 2) / 2;
end
end

function value = historyEndpointJaccard(history)
if isempty(history)
    value = 1;
else
    value = setJaccard( ...
        find(history(:, :, 1)), ...
        find(history(:, :, end)));
end
end

function [sourceFormationCoverage, receiverFormationCoverage, ...
        sourceSensorCoverage, receiverSensorCoverage, ...
        maxSourceSensorLoad, maxReceiverSensorLoad, ...
        maxSourceFormationLoad, maxReceiverFormationLoad, ...
        normalizedOutDegreeMaximum, normalizedInDegreeMaximum, ...
        normalizedDegreeSpread] = actionLoadSummary( ...
            sources, receivers, sourceGroups, receiverGroups, ...
            groupCount, nodeCount)
sources = reshape(sources, [], 1);
receivers = reshape(receivers, [], 1);
sourceGroups = reshape(sourceGroups, [], 1);
receiverGroups = reshape(receiverGroups, [], 1);
count = numel(sources);
if count == 0
    sourceFormationCoverage = 0;
    receiverFormationCoverage = 0;
    sourceSensorCoverage = 0;
    receiverSensorCoverage = 0;
    maxSourceSensorLoad = 0;
    maxReceiverSensorLoad = 0;
    maxSourceFormationLoad = 0;
    maxReceiverFormationLoad = 0;
    normalizedOutDegreeMaximum = 0;
    normalizedInDegreeMaximum = 0;
    normalizedDegreeSpread = 0;
    return;
end
sourceFormationCoverage = ...
    numel(unique(sourceGroups)) / groupCount;
receiverFormationCoverage = ...
    numel(unique(receiverGroups)) / groupCount;
sourceSensorCoverage = numel(unique(sources)) / nodeCount;
receiverSensorCoverage = numel(unique(receivers)) / nodeCount;
maxSourceSensorLoad = max(accumarray( ...
    sources, 1, [nodeCount, 1])) / count;
maxReceiverSensorLoad = max(accumarray( ...
    receivers, 1, [nodeCount, 1])) / count;
outDegree = accumarray( ...
    sourceGroups, 1, [groupCount, 1]);
inDegree = accumarray( ...
    receiverGroups, 1, [groupCount, 1]);
maxSourceFormationLoad = max(outDegree) / count;
maxReceiverFormationLoad = max(inDegree) / count;
degreeDenominator = max(groupCount - 1, 1);
normalizedOutDegreeMaximum = ...
    max(outDegree) / degreeDenominator;
normalizedInDegreeMaximum = ...
    max(inDegree) / degreeDenominator;
normalizedDegreeSpread = mean([ ...
    std(outDegree, 0, 1), std(inDegree, 0, 1)]) / ...
    degreeDenominator;
end

function validateReceiverUniqueness(receiverIndices, mask)
if isempty(mask) || ~any(mask)
    return;
end
selectedReceivers = receiverIndices(mask);
if numel(unique(selectedReceivers)) ~= numel(selectedReceivers)
    error(['A joint safe action may replace at most one source for ', ...
        'each receiver.']);
end
end

function mask = validateBinaryMask(mask, description)
if ~(islogical(mask) || isnumeric(mask))
    error('Joint-action %s mask must be binary.', description);
end
mask = reshape(mask, [], 1);
values = double(mask);
if any(~isfinite(values)) || ...
        any(~ismember(values, [0, 1]))
    error('Joint-action %s mask must be binary.', description);
end
mask = logical(mask);
end

function [selectedHistory, selectedTimes] = ...
        validateTemporalState(block, nodeCount)
currentTime = block.currentTime;
if ~isscalar(currentTime) || ~isnumeric(currentTime) || ...
        ~isfinite(currentTime) || currentTime < 1 || ...
        mod(currentTime, 1) ~= 0
    error('Joint-action current time is invalid.');
end
[selectedHistory, selectedTimes] = validateHistory( ...
    block.previousAdjacencyHistory, ...
    block.previousAdjacencyHistoryTimes, ...
    nodeCount, currentTime, 'selected');
end

function [history, times] = validateHistory( ...
        history, times, nodeCount, currentTime, description)
if ~(islogical(history) || isnumeric(history))
    error('Joint-action %s history must be binary.', description);
end
if isempty(history)
    history = false(nodeCount, nodeCount, 0);
elseif ismatrix(history)
    if ~isequal(size(history), [nodeCount, nodeCount])
        error('Joint-action %s history shape is invalid.', ...
            description);
    end
    history = reshape(history, nodeCount, nodeCount, 1);
elseif size(history, 1) ~= nodeCount || ...
        size(history, 2) ~= nodeCount
    error('Joint-action %s history shape is invalid.', ...
        description);
end
values = double(history);
if any(~isfinite(values(:))) || ...
        any(~ismember(values(:), [0, 1])) || ...
        size(history, 3) > 2
    error('Joint-action %s history is invalid.', description);
end
history = logical(history);
for pageIdx = 1:size(history, 3)
    if any(diag(history(:, :, pageIdx)))
        error('Joint-action %s history contains self edges.', ...
            description);
    end
end
times = reshape(times, 1, []);
if ~isnumeric(times) || ...
        numel(times) ~= size(history, 3) || ...
        any(~isfinite(times)) || ...
        any(mod(times, 1) ~= 0) || ...
        any(times < 1 | times >= currentTime) || ...
        (~isempty(times) && ...
            (times(end) ~= currentTime - 1 || ...
             any(diff(times) ~= 1)))
    error('Joint-action %s history times are invalid.', ...
        description);
end
end

function [canonical, count] = canonicalizeGroups(groupIds)
values = unique(groupIds);
count = numel(values);
if count < 2
    error('Joint-action features need at least two formations.');
end
canonical = zeros(size(groupIds));
for valueIdx = 1:count
    canonical(groupIds == values(valueIdx)) = valueIdx;
end
end

function value = safeIndexedMean(values, indices)
