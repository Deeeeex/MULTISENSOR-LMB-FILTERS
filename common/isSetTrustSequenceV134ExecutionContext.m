function detected = isSetTrustSequenceV134ExecutionContext(context)
% ISSETTRUSTSEQUENCEV134EXECUTIONCONTEXT Identify V134 headroom runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'set-trust-sequence-v134-execution-context-v1');
end
