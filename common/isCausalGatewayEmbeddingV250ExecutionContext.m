function detected = ...
        isCausalGatewayEmbeddingV250ExecutionContext(context)
% ISCAUSALGATEWAYEMBEDDINGV250EXECUTIONCONTEXT Recognize V250.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'causal-gateway-embedding-v250-context-v1');
end
