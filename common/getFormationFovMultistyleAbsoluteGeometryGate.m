function gate = getFormationFovMultistyleAbsoluteGeometryGate(styleName)
% GETFORMATIONFOVMULTISTYLEABSOLUTEGEOMETRYGATE Frozen v5 absolute gate.

styleName = lower(strrep(strrep(char(styleName), '_', '-'), ' ', '-'));
switch styleName
    case {'convoy', 'parallel-convoy'}
        gate = struct( ...
            'styleName', 'parallel-convoy', ...
            'maxBlackoutFraction', 0.025, ...
            'maxFocusBlackoutFraction', 0.010, ...
            'maxPerTargetBlackoutFraction', 0.050, ...
            'maxConsecutiveBlackoutSteps', 8, ...
            'minSingleFormationFraction', 0.35, ...
            'minMultiFormationFraction', 0.40, ...
            'minFocusVisibleTargetsPerSensorTime', 4.0, ...
            'maxFocusVisibleTargetsPerSensorTime', 5.25, ...
            'handoverNormalization', 'targets', ...
            'minNormalizedHandovers', 1.0, ...
            'minFormationOwnershipEntropy', 0.95, ...
            'minBlockageFocusOverlapFraction', 0.60, ...
            'minCrossGroupCloseEncounterFraction', 0.80, ...
            'minTargetSeparation', 14, ...
            'minSensorTargetSeparation', 30);
    case {'relay', 'linear-relay'}
        gate = struct( ...
            'styleName', 'linear-relay', ...
            'maxBlackoutFraction', 0.010, ...
            'maxFocusBlackoutFraction', 0.010, ...
            'maxPerTargetBlackoutFraction', 0.120, ...
            'maxConsecutiveBlackoutSteps', 14, ...
            'minSingleFormationFraction', 0.35, ...
            'minMultiFormationFraction', 0.50, ...
            'minFocusVisibleTargetsPerSensorTime', 4.5, ...
            'maxFocusVisibleTargetsPerSensorTime', 5.50, ...
            'handoverNormalization', ...
                'targets-times-formation-transitions', ...
            'minNormalizedHandovers', 0.65, ...
            'minFormationOwnershipEntropy', 0.95, ...
            'minBlockageFocusOverlapFraction', 0.60, ...
            'minCrossGroupCloseEncounterFraction', 0.80, ...
            'minTargetSeparation', 9, ...
            'minSensorTargetSeparation', 30);
    otherwise
        error('Unknown multistyle absolute geometry gate: %s', styleName);
end
end
