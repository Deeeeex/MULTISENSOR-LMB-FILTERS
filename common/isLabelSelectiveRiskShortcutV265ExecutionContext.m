function detected = isLabelSelectiveRiskShortcutV265ExecutionContext(context)
% ISLABELSELECTIVERISKSHORTCUTV265EXECUTIONCONTEXT Recognize V265.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'label-selective-risk-shortcut-v265-context-v1');
end
