function protocol = getCrossSeedGatewayUtilityRidgeV253Protocol()
% GETCROSSSEEDGATEWAYUTILITYRIDGEV253PROTOCOL Frozen selector study.

source = getIndependentM24GatewayTeacherV252Protocol();
protocol = struct();
protocol.id = 'cross-seed-gateway-utility-ridge-v253-v1';
protocol.contractVersion = ...
    'cross-seed-gateway-utility-ridge-v253-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.trainingSeeds = source.trainingSeeds;
protocol.developmentHoldoutSeeds = source.developmentHoldoutSeeds;
protocol.untouchedFullEpisodeSeeds = source.untouchedFullEpisodeSeeds;
protocol.anchorTimes = source.anchorTimes;
protocol.horizonSteps = source.horizonSteps;
protocol.featureSetNames = {'mean-47', 'distribution-167'};
protocol.ridgeLambdaGrid = source.ridgeLambdaGrid;
protocol.activationThresholdGrid = [0, 0.02, 0.05, 0.1, 0.2];
protocol.formationRegressionTolerancePercent = ...
    source.maximumFormationRegressionPercent;
protocol.minimumHoldoutSafeSelectionFraction = ...
    source.minimumDevelopmentHoldoutTailAlignedFraction;
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v253', ...
    'cross_seed_gateway_utility_ridge');
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V253 uses only V252 seeds 1302 and 1303 for feature-set, ridge-lambda ', ...
    'and activation-threshold selection. Seed 1304 is evaluated exactly ', ...
    'once after that choice is frozen. The scalar training target is the ', ...
    'minimum slack across network E-OSPA, RMSE, consistency, attempted ', ...
    'bytes and the two formation-tail tolerances. Features are current ', ...
    'posterior/link/geometry/history summaries only; truth and future ', ...
    'outcomes are labels, never inputs. Passing authorizes only a frozen ', ...
    'complete-episode M24 study on untouched seed 1305, not a GNN, X36 ', ...
    'or paper claim.'];

if ~isempty(intersect(protocol.trainingSeeds, ...
        protocol.developmentHoldoutSeeds)) || ...
        ~isempty(intersect([protocol.trainingSeeds, ...
            protocol.developmentHoldoutSeeds], ...
            protocol.untouchedFullEpisodeSeeds)) || ...
        any(protocol.ridgeLambdaGrid <= 0) || ...
        any(protocol.activationThresholdGrid < 0)
    error('CrossSeedGatewayUtilityRidgeV253:InvalidProtocol', ...
        'The V253 train/holdout selector protocol is inconsistent.');
end
end
