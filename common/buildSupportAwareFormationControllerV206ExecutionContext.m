function context = ...
        buildSupportAwareFormationControllerV206ExecutionContext( ...
            presetName, seed, currentTime, actionName, scheduleEnabled, ...
            onlineReselectionEnabled, repairPlan, releasePlan, horizonSteps)
% BUILDSUPPORTAWAREFORMATIONCONTROLLERV206EXECUTIONCONTEXT Dev scope.

if nargin < 9 || isempty(horizonSteps)
    horizonSteps = 3;
end
if ~isstruct(repairPlan) || ~isscalar(repairPlan) || ...
        ~isstruct(releasePlan) || ~isscalar(releasePlan)
    error('SupportAwareFormationControllerV206:InvalidExecutionContext', ...
        'V206 requires one scalar repair plan and one scalar release plan.');
end
base = buildOnlinePositiveNetAddressablePayloadV99ExecutionContext( ...
    presetName, seed, currentTime, actionName, scheduleEnabled, ...
    onlineReselectionEnabled, horizonSteps);
protocol = getSupportAwareFormationControllerV206Protocol();
context = base;
context.contractVersion = ...
    'support-aware-formation-controller-v206-context-v1';
context.capability = ...
    'support-aware-formation-controller-v206-development';
context.action = ...
    'filter-support-aware-formation-controller-v206-development';
context.protocolId = protocol.id;
context.budgetRecycledFormationRepairPlan = repairPlan;
context.onlinePositiveNetFormationReleasePlan = releasePlan;
end
