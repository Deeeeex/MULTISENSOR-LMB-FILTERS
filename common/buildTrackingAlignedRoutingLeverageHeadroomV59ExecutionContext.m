function context = ...
    buildTrackingAlignedRoutingLeverageHeadroomV59ExecutionContext( ...
        presetName, seed, currentTime, interventionDurationSteps)
% BUILDTRACKINGALIGNEDROUTINGLEVERAGEHEADROOMV59EXECUTIONCONTEXT H=3 only.

protocol = getTrackingAlignedRoutingLeverageHeadroomV59Protocol();
if nargin < 4 || isempty(interventionDurationSteps)
    interventionDurationSteps = protocol.interventionDurationSteps;
end
if ~ischar(presetName) || ~strcmp(presetName, protocol.presetName) || ...
        ~isa(seed, 'double') || ~isreal(seed) || ~isscalar(seed) || ...
        seed ~= protocol.seed || ...
        ~isa(currentTime, 'double') || ~isreal(currentTime) || ...
        ~isscalar(currentTime) || ~ismember(currentTime, protocol.eventTimes) || ...
        ~isa(interventionDurationSteps, 'double') || ...
        ~isreal(interventionDurationSteps) || ...
        ~isscalar(interventionDurationSteps) || ...
        ~isfinite(interventionDurationSteps) || ...
        interventionDurationSteps ~= floor(interventionDurationSteps) || ...
        interventionDurationSteps < 1 || ...
        interventionDurationSteps > protocol.horizonSteps
    error('TrackingAlignedV59:InvalidExecutionContextInput', ...
        'V59 execution inputs do not match the frozen event gate.');
end

context = struct();
context.contractVersion = ...
    'tracking-aligned-routing-leverage-headroom-v59-context-v1';
context.capability = ...
    'tracking-aligned-routing-leverage-headroom-development';
context.action = ...
    'filter-tracking-aligned-routing-leverage-headroom-development';
context.protocolId = protocol.id;
context.phase = 'opened-return';
context.presetName = presetName;
context.seed = seed;
context.currentTime = currentTime;
context.measurementTimeCount = ...
    currentTime + protocol.horizonSteps - 1;
context.policyName = sprintf( ...
    'formation-h%d-frozen-duration-%d-then-reference-v1', ...
    protocol.horizonSteps, interventionDurationSteps);
context.interventionDurationSteps = interventionDurationSteps;
context.developmentEvidenceOnly = true;
end
