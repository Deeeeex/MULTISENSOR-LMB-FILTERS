function [sources, projection, details, residualSplice] = ...
    applyConsensusProjection( ...
        context, candidateSources, projection, groupIds, ...
        baselineSources, referenceSources, ...
        referenceObjectiveByFormation, physical, ...
        senderPayloadBytes, payloadMarginFraction, ...
        dominantWeight, residualWeight, orientation, ...
        riskToleranceFraction, aggregationMode, tailFraction, ...
        maximumFormationCount)
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
if ~isscalar(riskToleranceFraction) || ...
        ~isfinite(riskToleranceFraction) || ...
        riskToleranceFraction < 0 || ...
        ~isscalar(maximumFormationCount) || ...
        ~isfinite(maximumFormationCount) || ...
        maximumFormationCount < 1 || ...
        formationCount > round(maximumFormationCount)
    error('Consensus-projection scale or tolerance is invalid.');
end
candidateObjective = reshape( ...
    projection.objectiveByFormation, 1, []);
referenceObjective = reshape( ...
    referenceObjectiveByFormation, 1, []);
if numel(candidateObjective) ~= formationCount || ...
        numel(referenceObjective) ~= formationCount
    error('Consensus-projection formation objectives are incomplete.');
end

crossScoreMatrix = ...
    buildDeterministicCrossScoreMatrix(physical, groupIds);
residualSplice = selectSplicedResidualFormationCycle( ...
    groupIds, baselineSources, referenceSources, ...
    physical, crossScoreMatrix, orientation);
residualAdjacency = residualSplice.residualAdjacency;
candidateDominantAdjacency = sourceMapToAdjacency( ...
    candidateSources, numel(groupIds));
referenceDominantAdjacency = sourceMapToAdjacency( ...
    referenceSources, numel(groupIds));
[candidateAdjacency, candidateWeights] = ...
    buildBackbonePreservingResidualRoute( ...
        context, candidateDominantAdjacency, ...
        residualAdjacency, dominantWeight, residualWeight);
[referenceAdjacency, referenceWeights] = ...
    buildBackbonePreservingResidualRoute( ...
        context, referenceDominantAdjacency, ...
        residualAdjacency, dominantWeight, residualWeight);

residualPayloadByFormation = zeros(1, formationCount);
candidatePayloadByFormation = zeros(1, formationCount);
referencePayloadByFormation = zeros(1, formationCount);
for formationIdx = 1:formationCount
    members = reshape(find( ...
        groupIds == groups(formationIdx)), 1, []);
    residualPayloadByFormation(formationIdx) = ...
        routeRowsPayloadBytes( ...
            residualAdjacency, members, senderPayloadBytes);
    candidatePayloadByFormation(formationIdx) = ...
        routeRowsPayloadBytes( ...
            candidateAdjacency, members, senderPayloadBytes);
    referencePayloadByFormation(formationIdx) = ...
        routeRowsPayloadBytes( ...
            referenceAdjacency, members, senderPayloadBytes);
end
candidatePayload = sum(candidatePayloadByFormation);
referencePayload = sum(referencePayloadByFormation);
payloadTarget = ...
    (1 - payloadMarginFraction) * referencePayload;
minimumHybridPayload = sum(min( ...
    candidatePayloadByFormation, referencePayloadByFormation));
if minimumHybridPayload > payloadTarget + 1e-9
    error('Consensus projection has no payload-feasible action.');
end

riskOptions = struct( ...
    'aggregationMode', aggregationMode, ...
    'tailFraction', tailFraction, ...
    'maximumIncomingCount', 2);
[candidateRisk, candidateRiskDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, candidateAdjacency, candidateWeights, riskOptions);
[referenceRisk, referenceRiskDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, referenceAdjacency, referenceWeights, riskOptions);
riskLimit = referenceRisk * (1 + riskToleranceFraction) + 1e-12;

pairRiskByMode = buildPairRiskByFormationMode( ...
    candidateRiskDetails.receiverDistributions, ...
    referenceRiskDetails.receiverDistributions);
candidateCount = 2^formationCount;
payloadFeasibleCount = 0;
feasibleCount = 0;
bestMask = false(1, formationCount);
bestObjective = -inf;
bestRisk = inf;
bestPayload = inf;
fallbackMask = false(1, formationCount);
fallbackObjective = -inf;
fallbackRisk = inf;
fallbackPayload = inf;
for candidateIdx = 0:(candidateCount - 1)
    referenceMask = logical(bitget( ...
        candidateIdx, 1:formationCount));
    payload = sum(referenceMask .* ...
        referencePayloadByFormation + ...
        (~referenceMask) .* candidatePayloadByFormation);
    if payload > payloadTarget + 1e-9
        continue;
    end
    payloadFeasibleCount = payloadFeasibleCount + 1;
    objective = sum(referenceMask .* referenceObjective + ...
        (~referenceMask) .* candidateObjective);
    risk = aggregateFormationModePairRisk( ...
        pairRiskByMode, groupIds, groups, ...
        referenceMask, aggregationMode, tailFraction);
    if risk < fallbackRisk - 1e-12 || ...
            (abs(risk - fallbackRisk) <= 1e-12 && ...
             objective > fallbackObjective + 1e-12) || ...
            (abs(risk - fallbackRisk) <= 1e-12 && ...
             abs(objective - fallbackObjective) <= 1e-12 && ...
             payload < fallbackPayload - 1e-9)
        fallbackMask = referenceMask;
        fallbackObjective = objective;
        fallbackRisk = risk;
        fallbackPayload = payload;
    end
    if risk > riskLimit + 1e-12
        continue;
    end
    feasibleCount = feasibleCount + 1;
    if objective > bestObjective + 1e-12 || ...
            (abs(objective - bestObjective) <= 1e-12 && ...
             risk < bestRisk - 1e-12) || ...
            (abs(objective - bestObjective) <= 1e-12 && ...
             abs(risk - bestRisk) <= 1e-12 && ...
             payload < bestPayload - 1e-9) || ...
            (abs(objective - bestObjective) <= 1e-12 && ...
