function pairRiskByMode = buildPairRiskByFormationMode( ...
        candidateDistributions, referenceDistributions)
nodeCount = numel(candidateDistributions);
if numel(referenceDistributions) ~= nodeCount
    error('Consensus-projection receiver distributions are incomplete.');
end
pairRiskByMode = zeros(nodeCount, nodeCount, 2, 2);
for leftIdx = 1:nodeCount-1
    for rightIdx = leftIdx+1:nodeCount
        for leftMode = 1:2
            for rightMode = 1:2
                if leftMode == 1
                    left = candidateDistributions{leftIdx};
                else
                    left = referenceDistributions{leftIdx};
                end
                if rightMode == 1
                    right = candidateDistributions{rightIdx};
                else
                    right = referenceDistributions{rightIdx};
                end
                value = expectedDistributionPairRisk(left, right);
                pairRiskByMode( ...
                    leftIdx, rightIdx, leftMode, rightMode) = value;
                pairRiskByMode( ...
                    rightIdx, leftIdx, rightMode, leftMode) = value;
            end
        end
    end
end
end

function value = expectedDistributionPairRisk(left, right)
value = 0;
for leftOutcome = 1:numel(left.probability)
    for rightOutcome = 1:numel(right.probability)
        pair = computeLmbPosteriorSummaryDisagreement( ...
            left.summary{leftOutcome}, ...
            right.summary{rightOutcome});
        value = value + ...
            left.probability(leftOutcome) * ...
            right.probability(rightOutcome) * ...
            pair.combined;
    end
end
end

function risk = aggregateFormationModePairRisk( ...
        pairRiskByMode, groupIds, groups, referenceMask, ...
        aggregationMode, tailFraction)
nodeCount = numel(groupIds);
values = zeros(1, nodeCount * (nodeCount - 1) / 2);
cursor = 0;
for leftIdx = 1:nodeCount-1
    leftFormation = find(groups == groupIds(leftIdx), 1);
    leftMode = 1 + referenceMask(leftFormation);
    for rightIdx = leftIdx+1:nodeCount
        rightFormation = find(groups == groupIds(rightIdx), 1);
        rightMode = 1 + referenceMask(rightFormation);
        cursor = cursor + 1;
        values(cursor) = pairRiskByMode( ...
            leftIdx, rightIdx, leftMode, rightMode);
    end
end
if strcmpi(aggregationMode, 'mean')
    risk = mean(values);
else
    values = sort(values, 'descend');
    tailCount = max(1, ceil(tailFraction * numel(values)));
    risk = mean(values(1:tailCount));
end
end

function matches = formationMapsMatch( ...
        leftSources, rightSources, groupIds, groups)
matches = false(1, numel(groups));
for formationIdx = 1:numel(groups)
    members = reshape(find( ...
        groupIds == groups(formationIdx)), 1, []);
    matches(formationIdx) = ...
        isequal(leftSources(members), rightSources(members));
end
end

function bytes = routeRowsPayloadBytes( ...
        adjacency, receivers, senderPayloadBytes)
bytes = 0;
for receiver = reshape(receivers, 1, [])
    senders = find(adjacency(receiver, :));
    bytes = bytes + sum(senderPayloadBytes(senders));
end
end

