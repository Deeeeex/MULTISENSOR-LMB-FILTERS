function detected = isProtectionReleaseOracleV106ExecutionContext(context)
% ISPROTECTIONRELEASEORACLEV106EXECUTIONCONTEXT Identify V106.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'protection-release-oracle-v106-context-v1');
end
