function actions = buildMixedCarrierInsertionV121Actions( ...
        context, clockwiseAdjacency, clockwiseWeights, ...
        clockwiseDetails, protocol)
% BUILDMIXEDCARRIERINSERTIONV121ACTIONS Reorder one residual formation cycle.

if nargin < 5 || isempty(protocol)
    protocol = getMixedCarrierInsertionV121Protocol();
end
if ~isstruct(clockwiseDetails) || ...
        ~isfield(clockwiseDetails, 'spliceSelection') || ...
        ~isfield(clockwiseDetails, 'dominantAdjacency') || ...
        ~isfield(clockwiseDetails, 'residualBaselinePolicyDetails') || ...
        ~isfield(clockwiseDetails.residualBaselinePolicyDetails, ...
            'selectedSourcesByReceiver')
    error('MixedCarrierInsertionV121:InvalidCarrier', ...
        'The V121 base carrier lacks its registered splice metadata.');
end
nodeCount = size(clockwiseAdjacency, 1);
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
baseSelection = clockwiseDetails.spliceSelection;
if ~isequal(reshape(baseSelection.formationOrder, 1, []), ...
        protocol.baseFormationOrder) || ...
        numel(groups) ~= numel(protocol.baseFormationOrder)
    error('MixedCarrierInsertionV121:BaseOrderDrift', ...
        'The V121 base formation order changed.');
end
cutByFormation = zeros(1, numel(groups));
for position = 1:numel(groups)
    formationId = baseSelection.formationOrder(position);
    cutByFormation(formationId) = baseSelection.cutReceivers(position);
end
baselineSources = reshape(clockwiseDetails. ...
    residualBaselinePolicyDetails.selectedSourcesByReceiver, 1, []);
dominantWeight = clockwiseDetails.dominantWeight;
residualWeight = clockwiseDetails.residualWeight;
actions = repmat(emptyAction(), 1, ...
    numel(protocol.candidateFormationOrders));
for candidateIdx = 1:numel(actions)
    order = protocol.candidateFormationOrders{candidateIdx};
    residualSources = baselineSources;
    crossReceivers = zeros(1, numel(order));
    crossSenders = crossReceivers;
    for position = 1:numel(order)
        nextPosition = 1 + mod(position, numel(order));
        senderCut = cutByFormation(order(position));
        receiverCut = cutByFormation(order(nextPosition));
        sender = baselineSources(senderCut);
        residualSources(receiverCut) = sender;
        crossReceivers(position) = receiverCut;
        crossSenders(position) = sender;
    end
    residualAdjacency = false(nodeCount);
    for receiver = 1:nodeCount
        residualAdjacency(receiver, residualSources(receiver)) = true;
    end
    [adjacency, weights, routeDetails] = ...
        buildBackbonePreservingResidualRoute( ...
            context, clockwiseDetails.dominantAdjacency, ...
            residualAdjacency, dominantWeight, residualWeight);
    physical = logical(context.physicalAdjacency);
    if nnz(adjacency) ~= nnz(clockwiseAdjacency) || ...
            any(adjacency(:) & ~physical(:)) || ...
            ~isequal(sort(weights(:)), sort(clockwiseWeights(:))) || ...
            ~isStronglyConnected(residualAdjacency) || ...
            ~isStronglyConnected(collapseToFormations( ...
                residualAdjacency, groupIds))
        error('MixedCarrierInsertionV121:StructuralInvariantFailed', ...
            'A V121 mixed carrier violated exact-budget cycle structure.');
    end
    details = clockwiseDetails;
    details.fusionWeightMatrix = weights;
    details.residualAdjacency = residualAdjacency;
    details.residualSourcesByReceiver = residualSources;
    details.selectedSourcesByReceiver = residualSources;
    details.messageCount = nnz(adjacency);
    details.spliceSelection.formationOrder = order;
    details.spliceSelection.cutReceivers = cutByFormation(order);
    details.spliceSelection.cutSenders = ...
        baselineSources(cutByFormation(order));
    details.spliceSelection.crossReceivers = crossReceivers;
    details.spliceSelection.crossSenders = crossSenders;
    details.spliceSelection.residualSourcesByReceiver = residualSources;
    details.spliceSelection.residualAdjacency = residualAdjacency;
    details.v121MixedCarrier = struct( ...
        'movedFormationId', protocol.movedFormationId, ...
        'insertionAfterFormationId', ...
            protocol.insertionAfterFormationIds(candidateIdx), ...
        'formationOrder', order, ...
        'crossFormationEdges', ...
            [groupIds(crossSenders); groupIds(crossReceivers)]', ...
        'messageParityPassed', ...
            nnz(adjacency) == nnz(clockwiseAdjacency), ...
        'weightMultisetPassed', ...
            isequal(sort(weights(:)), sort(clockwiseWeights(:))), ...
        'sensorCyclePassed', isStronglyConnected(residualAdjacency), ...
        'formationCyclePassed', isStronglyConnected( ...
            collapseToFormations(residualAdjacency, groupIds)));
    actions(candidateIdx) = struct( ...
        'name', protocol.candidateActionNames{candidateIdx}, ...
        'adjacency', adjacency, 'weights', weights, ...
        'details', details, 'formationOrder', order);
end
end

function action = emptyAction()
action = struct('name', '', 'adjacency', false(0), ...
    'weights', zeros(0), 'details', struct(), 'formationOrder', []);
end

function formation = collapseToFormations(adjacency, groupIds)
groups = unique(groupIds, 'stable');
formation = false(numel(groups));
for receiverIdx = 1:numel(groups)
    receivers = find(groupIds == groups(receiverIdx));
    for sourceIdx = 1:numel(groups)
        sources = find(groupIds == groups(sourceIdx));
        formation(receiverIdx, sourceIdx) = ...
            any(any(adjacency(receivers, sources)));
    end
end
end

function passed = isStronglyConnected(adjacency)
reachability = logical(adjacency) | eye(size(adjacency, 1)) > 0;
for idx = 1:size(adjacency, 1)
    reachability = reachability | bsxfun(@and, ...
        reachability(:, idx), reachability(idx, :));
end
passed = all(reachability(:));
end
