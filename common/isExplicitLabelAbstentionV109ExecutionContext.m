function detected = isExplicitLabelAbstentionV109ExecutionContext(context)
% ISEXPLICITLABELABSTENTIONV109EXECUTIONCONTEXT Identify V109.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'explicit-label-abstention-v109-context-v1');
end
