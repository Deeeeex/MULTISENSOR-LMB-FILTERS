function plan = planFusionAwareQueryFirstExchangeV228( ...
        participantSensorIds, candidatePayloadBytes, ...
        admissionNetSavingBytes, referencePageBytes, options)
% PLANFUSIONAWAREQUERYFIRSTEXCHANGEV228 Conserve bytes before payloads.
%
% The beneficiary coordinator queries at most K receiver-side labels.  One
% fixed-size risk record is budgeted from every remote participant for every
% queried key, even if a participant has no useful source label.  Only after
% that worst-case control exchange is charged may a complete Bernoulli-GM
% payload be shortlisted.  The inherited protected-credit reserve therefore
% remains intact and the value model cannot manufacture communication gain.

if nargin < 5 || isempty(options)
    options = struct();
end
protocol = getFusionAwareLabelEdgeControllerV228Protocol();
control = protocol.controlPlane;
maximumQueriedLabels = getField(options, ...
    'maximumQueriedLabels', control.maximumQueriedLabels);
candidatePayloadBytes = reshape(candidatePayloadBytes, 1, []);
if isempty(candidatePayloadBytes) || ...
        any(~isfinite(candidatePayloadBytes)) || ...
        any(candidatePayloadBytes < 0) || ...
        any(candidatePayloadBytes ~= round(candidatePayloadBytes)) || ...
        ~validNonnegativeScalar(admissionNetSavingBytes) || ...
        ~validPositiveScalar(referencePageBytes) || ...
        ~isscalar(maximumQueriedLabels) || ...
        ~isfinite(maximumQueriedLabels) || ...
        maximumQueriedLabels < 1 || ...
        maximumQueriedLabels ~= round(maximumQueriedLabels) || ...
        maximumQueriedLabels > control.maximumQueriedLabels
    error('FusionAwareQueryFirstV228:InvalidInput', ...
        'The query-first credit request is malformed.');
end

layout = struct( ...
    'queryHeaderBytes', control.queryHeaderBytes, ...
    'queryBytesPerLabelKey', control.queryBytesPerLabelKey, ...
    'responseHeaderBytes', control.responseHeaderBytes, ...
    'responseBytesPerLabelRecord', ...
        control.responseBytesPerLabelRecord);
estimate = estimateQueryFirstLabelSynopsisBytesV222( ...
    participantSensorIds, maximumQueriedLabels, layout);
[creditAfterQuery, queryDecision] = ...
    preflightBudgetRecycledRepairSynopsisV188( ...
        [], admissionNetSavingBytes, estimate.totalAttemptedBytes, ...
        referencePageBytes);

feasibleMask = queryDecision.lightSynopsisAuthorized & ...
    (candidatePayloadBytes <= ...
        creditAfterQuery.spendableCreditBytes + 1e-9);
netSavingBytes = admissionNetSavingBytes - ...
    estimate.totalAttemptedBytes - candidatePayloadBytes;
feasibleMask = feasibleMask & (netSavingBytes >= -1e-9);

plan = struct();
plan.contractVersion = ...
    'fusion-aware-query-first-exchange-plan-v228-v1';
plan.protocolId = protocol.id;
plan.participantSensorIds = estimate.participantSensorIds;
plan.coordinatorSensorId = estimate.participantSensorIds(1);
plan.participantCount = estimate.participantCount;
plan.maximumQueriedLabels = maximumQueriedLabels;
plan.queryEstimate = estimate;
plan.queryAttemptedBytes = estimate.totalAttemptedBytes;
plan.queryAuthorized = queryDecision.lightSynopsisAuthorized;
plan.queryDecision = queryDecision;
plan.spendableCreditAfterQueryBytes = ...
    creditAfterQuery.spendableCreditBytes;
plan.protectedSavingAfterQueryBytes = ...
    creditAfterQuery.protectedSavingBytes;
plan.candidatePayloadBytes = candidatePayloadBytes;
plan.candidateFeasibleMask = feasibleMask;
plan.feasibleCandidateCount = nnz(feasibleMask);
plan.certifiedNetSavingBytes = netSavingBytes;
plan.certifiedNetSavingPercent = 100 * netSavingBytes / ...
    max(referencePageBytes, eps);
plan.queryCostChargedBeforePayloadSelection = true;
plan.completeLabelPayloadChargedSeparately = true;
plan.truthUsed = false;
plan.futureInformationUsed = false;
plan.modelMayOverrideByteFeasibility = false;
plan.evidenceBoundary = [ ...
    'This is a deterministic attempted-byte plan for one query-first ', ...
    'exchange. It proves only communication feasibility under the frozen ', ...
    'credit reserve; complete-payload delivery, exact eta projection and ', ...
    'paired H=3 outcomes still decide whether an action is executable and ', ...
    'valuable.'];
end

function valid = validNonnegativeScalar(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value >= 0;
end

function valid = validPositiveScalar(value)
valid = validNonnegativeScalar(value) && value > 0;
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
