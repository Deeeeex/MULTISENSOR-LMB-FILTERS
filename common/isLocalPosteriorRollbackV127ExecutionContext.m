function detected = isLocalPosteriorRollbackV127ExecutionContext(context)
% ISLOCALPOSTERIORROLLBACKV127EXECUTIONCONTEXT Identify V127.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'local-posterior-rollback-v127-context-v1');
end
