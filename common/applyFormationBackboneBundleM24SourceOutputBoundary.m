function [stateEstimatesBySensor, diagnostics] = ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        stateEstimatesBySensor, diagnostics, authorization)
% APPLYFORMATIONBACKBONEBUNDLEM24SOURCEOUTPUTBOUNDARY Hide future estimates.

if ~isstruct(authorization) || ~isscalar(authorization) || ...
        ~isfield(authorization, 'mode') || ...
        ~isfield(authorization, 'stateEstimateOutputAuthorized')
    error('FormationBundleSourcePermit:OutputBoundaryDrift', ...
        'The filter output authorization is malformed.');
end
sourcePermitMode = strcmp( ...
    authorization.mode, 'registered-case-permit');
if sourcePermitMode
    if ~isfield(authorization, 'capability') || ...
            ~strcmp(authorization.capability, ...
                'source-posterior-only') || ...
            ~isequal(authorization.stateEstimateOutputAuthorized, false)
        error('FormationBundleSourcePermit:OutputBoundaryDrift', ...
            'The registered source permit expanded its output scope.');
    end
    stateEstimatesBySensor = cell(1, 0);
    diagnostics.sourceStateEstimateOutputSuppressed = true;
else
    if ~isequal(authorization.stateEstimateOutputAuthorized, true)
        error('DynamicTopology:OutputAuthorizationDrift', ...
            'A non-source filter execution unexpectedly suppressed output.');
    end
    diagnostics.sourceStateEstimateOutputSuppressed = false;
end
end
