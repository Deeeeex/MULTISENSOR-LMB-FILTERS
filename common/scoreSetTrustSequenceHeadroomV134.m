function metrics = scoreSetTrustSequenceHeadroomV134( ...
        referenceOutcome, candidateOutcome, groupIds, ...
        recoveryTailSteps, protocol, actionSpec)
% SCORESETTRUSTSEQUENCEHEADROOMV134 Paired multi-objective pilot gate.

required = {'eospaBySensorTime', 'attemptedBytesByTime'};
if ~isstruct(referenceOutcome) || ~isscalar(referenceOutcome) || ...
        ~isstruct(candidateOutcome) || ~isscalar(candidateOutcome) || ...
        ~all(isfield(referenceOutcome, required)) || ...
        ~all(isfield(candidateOutcome, required)) || ...
        ~isequal(size(referenceOutcome.eospaBySensorTime), ...
            size(candidateOutcome.eospaBySensorTime)) || ...
        ~isequal(size(referenceOutcome.attemptedBytesByTime), ...
            size(candidateOutcome.attemptedBytesByTime)) || ...
        any(~isfinite(referenceOutcome.eospaBySensorTime(:))) || ...
        any(~isfinite(candidateOutcome.eospaBySensorTime(:))) || ...
        any(~isfinite(referenceOutcome.attemptedBytesByTime(:))) || ...
        any(~isfinite(candidateOutcome.attemptedBytesByTime(:))) || ...
        ~isstruct(protocol) || ~isscalar(protocol) || ...
        ~strcmp(protocol.id, 'formation-admission-sequence-v134-v3') || ...
        nargin < 6 || ~isstruct(actionSpec) || ~isscalar(actionSpec) || ...
        ~all(isfield(actionSpec, { ...
            'gateEligible', 'diagnosticOnly', 'returnsToFullTrust'}))
    error('V134SetTrustHeadroom:InvalidOutcome', ...
        'The paired V134 outcomes are malformed.');
end

reference = double(referenceOutcome.eospaBySensorTime);
candidate = double(candidateOutcome.eospaBySensorTime);
[sensorCount, horizonSteps] = size(reference);
groupIds = reshape(groupIds, 1, []);
if numel(groupIds) ~= sensorCount || ...
        ~isscalar(recoveryTailSteps) || ...
        recoveryTailSteps < 1 || ...
        recoveryTailSteps >= horizonSteps
    error('V134SetTrustHeadroom:InvalidScale', ...
        'The formation membership or mature-window boundary is invalid.');
end

matureColumns = (horizonSteps - recoveryTailSteps + 1):horizonSteps;
interventionColumns = find(cellfun(@(factors) any(factors == 0), ...
    actionSpec.trustFactorsByTime));
if isempty(interventionColumns)
    interventionColumns = 1;
end
referenceSensorMean = mean(reference, 2);
candidateSensorMean = mean(candidate, 2);
referenceSensorIntervention = ...
    mean(reference(:, interventionColumns), 2);
candidateSensorIntervention = ...
    mean(candidate(:, interventionColumns), 2);
referenceSensorMature = mean(reference(:, matureColumns), 2);
candidateSensorMature = mean(candidate(:, matureColumns), 2);
sensorGain = safeGain(referenceSensorMean, candidateSensorMean);
sensorInterventionGain = safeGain( ...
    referenceSensorIntervention, candidateSensorIntervention);
sensorMatureGain = safeGain( ...
    referenceSensorMature, candidateSensorMature);
formationIds = unique(groupIds, 'stable');
formationGain = zeros(1, numel(formationIds));
formationInterventionGain = zeros(1, numel(formationIds));
formationMatureGain = zeros(1, numel(formationIds));
for formationIdx = 1:numel(formationIds)
    members = groupIds == formationIds(formationIdx);
    formationGain(formationIdx) = safeGain( ...
        mean(reference(members, :), 'all'), ...
        mean(candidate(members, :), 'all'));
    formationInterventionGain(formationIdx) = safeGain( ...
        mean(reference(members, interventionColumns), 'all'), ...
        mean(candidate(members, interventionColumns), 'all'));
    formationMatureGain(formationIdx) = safeGain( ...
        mean(reference(members, matureColumns), 'all'), ...
        mean(candidate(members, matureColumns), 'all'));
end

referenceBytes = sum(referenceOutcome.attemptedBytesByTime);
candidateBytes = sum(candidateOutcome.attemptedBytesByTime);
gate = protocol.preLearningGate;
metrics = struct();
metrics.contractVersion = 'v134-set-trust-headroom-metrics-v2';
metrics.interventionGainFraction = safeGain( ...
    mean(reference(:, interventionColumns), 'all'), ...
    mean(candidate(:, interventionColumns), 'all'));
metrics.meanGainFraction = safeGain(mean(reference(:)), mean(candidate(:)));
metrics.matureGainFraction = safeGain( ...
    mean(reference(:, matureColumns), 'all'), ...
    mean(candidate(:, matureColumns), 'all'));
metrics.sensorGainFraction = reshape(sensorGain, 1, []);
metrics.sensorInterventionGainFraction = ...
    reshape(sensorInterventionGain, 1, []);
metrics.sensorMatureGainFraction = reshape(sensorMatureGain, 1, []);
metrics.minimumSensorGainFraction = min(sensorGain);
metrics.minimumInterventionSensorGainFraction = ...
    min(sensorInterventionGain);
metrics.minimumMatureSensorGainFraction = min(sensorMatureGain);
metrics.formationIds = formationIds;
metrics.formationGainFraction = formationGain;
metrics.formationInterventionGainFraction = ...
    formationInterventionGain;
metrics.formationMatureGainFraction = formationMatureGain;
metrics.minimumFormationGainFraction = min(formationGain);
metrics.minimumInterventionFormationGainFraction = ...
    min(formationInterventionGain);
metrics.minimumMatureFormationGainFraction = ...
    min(formationMatureGain);
metrics.matureColumns = matureColumns;
metrics.interventionColumns = interventionColumns;
metrics.referenceAttemptedBytes = referenceBytes;
metrics.candidateAttemptedBytes = candidateBytes;
metrics.attemptedByteSavingFraction = safeGain( ...
    referenceBytes, candidateBytes);
metrics.interventionAttemptedByteSavingFraction = safeGain( ...
    sum(referenceOutcome.attemptedBytesByTime(interventionColumns)), ...
    sum(candidateOutcome.attemptedBytesByTime(interventionColumns)));
metrics.passesMeanGate = metrics.meanGainFraction >= ...
    gate.minimumPairedMeanEospGainFraction - 1e-12;
metrics.passesInterventionGate = ...
    metrics.interventionGainFraction >= ...
        gate.minimumPairedInterventionEospGainFraction - 1e-12;
metrics.passesMatureGate = metrics.matureGainFraction >= ...
    gate.minimumPairedMatureEospGainFraction - 1e-12;
metrics.passesSensorGate = metrics.minimumSensorGainFraction >= ...
    gate.minimumSensorGainFraction - 1e-12 && ...
    metrics.minimumMatureSensorGainFraction >= ...
        gate.minimumMatureSensorGainFraction - 1e-12 && ...
    metrics.minimumInterventionSensorGainFraction >= ...
        gate.minimumInterventionSensorGainFraction - 1e-12;
metrics.passesFormationGate = ...
    metrics.minimumFormationGainFraction >= ...
        gate.minimumFormationGainFraction - 1e-12 && ...
    metrics.minimumMatureFormationGainFraction >= ...
        gate.minimumMatureFormationGainFraction - 1e-12 && ...
    metrics.minimumInterventionFormationGainFraction >= ...
        gate.minimumInterventionFormationGainFraction - 1e-12;
metrics.passesByteGate = ...
    ~gate.requirePositiveAttemptedByteSaving || ...
    metrics.attemptedByteSavingFraction > 1e-12;
metrics.rawOutcomeGatePassed = ...
    metrics.passesInterventionGate && ...
    metrics.passesMeanGate && metrics.passesMatureGate && ...
    metrics.passesSensorGate && metrics.passesFormationGate && ...
    metrics.passesByteGate;
metrics.actionGateEligible = logical(actionSpec.gateEligible);
metrics.actionDiagnosticOnly = logical(actionSpec.diagnosticOnly);
metrics.actionReturnsToFullTrust = ...
    logical(actionSpec.returnsToFullTrust);
metrics.passesPreLearningGate = metrics.rawOutcomeGatePassed && ...
    metrics.actionGateEligible && ~metrics.actionDiagnosticOnly && ...
    (~gate.requireFullyRestoredGateEligibleAction || ...
     metrics.actionReturnsToFullTrust);
end

function gain = safeGain(reference, candidate)
gain = (reference - candidate) ./ max(abs(reference), eps);
end
