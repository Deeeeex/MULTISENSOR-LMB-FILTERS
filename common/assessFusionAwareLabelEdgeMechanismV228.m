function decision = assessFusionAwareLabelEdgeMechanismV228(pilotInput)
% ASSESSFUSIONAWARELABELEDGEMECHANISMV228 Freeze the V226 go/no-go rule.
%
% This decision deliberately ignores the stricter local-tail promotion gate.
% V228 method development is authorized when the corrected V226 stage-best
% candidate improves the four aggregate tracking/consensus coordinates and
% attempted bytes.  The result remains teacher/mechanism evidence only.

protocol = getFusionAwareLabelEdgeControllerV228Protocol();
pilot = resolvePilot(pilotInput);
validatePilot(pilot, protocol);

stageBest = pilot.stageBest;
stageBestPresent = logical(stageBest.present);
gainVector = nan(1, numel(protocol.model.targetNames));
attemptedByteSavingPercent = NaN;
if stageBestPresent
    gainVector = reshape(stageBest.jointGainVectorPercent, 1, []);
    attemptedByteSavingPercent = stageBest.attemptedByteSavingPercent;
end

coreGainVector = [gainVector(1:4), attemptedByteSavingPercent];
corePositive = stageBestPresent && ...
    all(isfinite(coreGainVector)) && all(coreGainVector > 0);
reportedCorePositive = logical( ...
    pilot.anyCorePositiveBytePositiveCandidate);
if reportedCorePositive ~= corePositive
    error('FusionAwareLabelEdgeControllerV228:V226GateDrift', ...
        'The V226 stage-best record disagrees with its reported core gate.');
end

decision = struct();
decision.contractVersion = ...
    'fusion-aware-label-edge-v226-authorization-v228-v1';
decision.protocolId = protocol.id;
decision.v226GenerationGitCommit = pilot.generationGitCommit;
decision.v226TrajectoryGenerationGitCommit = ...
    pilot.trajectoryGenerationGitCommit;
decision.stageBestPresent = stageBestPresent;
decision.coreGainNames = [protocol.model.targetNames(1:4), ...
    {'attempted_byte_saving_percent'}];
decision.coreGainVectorPercent = coreGainVector;
decision.corePositive = corePositive;
decision.strictGatePassed = stageBestPresent && ...
    logical(stageBest.strictGatePassed);
decision.toleranceViolationCount = getField( ...
    stageBest, 'toleranceViolationCount', NaN);
decision.minimumRegisteredMarginPercent = getField( ...
    stageBest, 'minimumRegisteredMarginPercent', NaN);
decision.minimumTailMarginPercent = getField( ...
    stageBest, 'minimumTailMarginPercent', NaN);
decision.authorized = corePositive;
if decision.authorized
    decision.nextAction = ...
        'freeze-v227-carrier-then-build-v228-training-trajectories';
    decision.reason = [ ...
        'A corrected V226 action improves E-OSPA, RMSE, window and ', ...
        'terminal consensus, and attempted bytes. This authorizes ', ...
        'learning the action value but does not authorize a paper claim.'];
else
    decision.nextAction = 'stop-fusion-aware-label-edge-controller-line';
    decision.reason = [ ...
        'The corrected V226 pilot contains no stage-best action that is ', ...
        'positive on every registered core coordinate and attempted bytes.'];
end
decision.paperPromotionAllowed = false;
decision.deploymentClaimAllowed = false;
decision.generalizationClaimAllowed = false;
decision.evidenceBoundary = [ ...
    'This is a deterministic method-development decision over the V226 ', ...
    'teacher/mechanism pilot. The strict local-tail gate remains visible ', ...
    'and unchanged. V227 carrier selection, grouped training, calibration ', ...
    'and unseen M24/X36 evaluation are still required.'];
end

function pilot = resolvePilot(input)
if ischar(input)
    if exist(input, 'file') ~= 2
        error('FusionAwareLabelEdgeControllerV228:MissingPilot', ...
            'The requested V226 pilot artifact does not exist.');
    end
    loaded = load(input, 'result');
    if ~isfield(loaded, 'result')
        error('FusionAwareLabelEdgeControllerV228:MissingResult', ...
            'The V226 pilot artifact does not contain result.');
    end
    pilot = loaded.result;
else
    pilot = input;
end
end

function validatePilot(pilot, protocol)
required = {'contractVersion', 'generationGitCommit', ...
    'trajectoryGenerationGitCommit', 'stageBest', ...
    'anyCorePositiveBytePositiveCandidate', ...
    'fixedStaticRouteBaselineIncluded', ...
    'endToEndStaticBaselineClaimAllowed', ...
    'truthUsedForDonorSelection', 'validationClaimAllowed'};
if ~isstruct(pilot) || ~isscalar(pilot) || ...
        any(~isfield(pilot, required)) || ...
        ~strcmp(pilot.contractVersion, ...
            protocol.authorization.requiredV226Contract) || ...
        pilot.fixedStaticRouteBaselineIncluded || ...
        pilot.endToEndStaticBaselineClaimAllowed || ...
        ~pilot.truthUsedForDonorSelection || ...
        pilot.validationClaimAllowed || ...
        ~isstruct(pilot.stageBest) || ~isscalar(pilot.stageBest) || ...
        ~isfield(pilot.stageBest, 'present')
    error('FusionAwareLabelEdgeControllerV228:InvalidPilot', ...
        'The V226 pilot does not satisfy the frozen mechanism contract.');
end
if pilot.stageBest.present
    requiredBest = {'jointGainVectorPercent', ...
        'attemptedByteSavingPercent', 'strictGatePassed'};
    if any(~isfield(pilot.stageBest, requiredBest)) || ...
            numel(pilot.stageBest.jointGainVectorPercent) ~= ...
                numel(protocol.model.targetNames)
        error('FusionAwareLabelEdgeControllerV228:InvalidStageBest', ...
            'The V226 stage-best record is incomplete.');
    end
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
