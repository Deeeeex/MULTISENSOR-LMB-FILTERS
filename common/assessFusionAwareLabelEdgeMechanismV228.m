function decision = assessFusionAwareLabelEdgeMechanismV228(pilotInput)
% ASSESSFUSIONAWARELABELEDGEMECHANISMV228 Freeze the V226 go/no-go rule.
%
% This decision deliberately ignores the stricter local-tail promotion gate,
% but it does not ignore causal composition.  V228 method development is
% authorized only when donor-only is core-non-regressive, the label transfer
% is core-positive relative to donor-only, the joint action is core-positive
% relative to ordinary fusion, and attempted bytes fall.  The result remains
% teacher/mechanism evidence only.

protocol = getFusionAwareLabelEdgeControllerV228Protocol();
pilot = resolvePilot(pilotInput);
validatePilot(pilot, protocol);

stageBest = pilot.stageBest;
stageBestPresent = logical(stageBest.present);
gainVector = nan(1, numel(protocol.model.targetNames));
attemptedByteSavingPercent = NaN;
if stageBestPresent
    gainVector = reshape(stageBest.jointGainVectorPercent, 1, []);
    attemptedByteSavingPercent = stageBest.attemptedByteSavingPercent;
end

coreGainVector = [gainVector(1:4), attemptedByteSavingPercent];
reportedStageBestCorePositive = stageBestPresent && ...
    all(isfinite(coreGainVector)) && all(coreGainVector > 0);
reportedCorePositive = logical( ...
    pilot.anyCorePositiveBytePositiveCandidate);
if reportedCorePositive ~= reportedStageBestCorePositive
    error('FusionAwareLabelEdgeControllerV228:V226GateDrift', ...
        'The V226 stage-best record disagrees with its reported core gate.');
end

[compositionBest, compositionallySafeCount, ...
    jointCorePositiveCount] = findCompositionallySafeBest( ...
        pilot, protocol);

decision = struct();
decision.contractVersion = ...
    'fusion-aware-label-edge-v226-authorization-v228-v1';
decision.protocolId = protocol.id;
decision.v226GenerationGitCommit = pilot.generationGitCommit;
decision.v226TrajectoryGenerationGitCommit = ...
    pilot.trajectoryGenerationGitCommit;
decision.stageBestPresent = stageBestPresent;
decision.reportedStageBestCoreGainNames = [ ...
    protocol.model.targetNames(1:4), ...
    {'attempted_byte_saving_percent'}];
decision.reportedStageBestCoreGainVectorPercent = coreGainVector;
decision.reportedStageBestCorePositive = ...
    reportedStageBestCorePositive;
decision.jointCorePositiveCandidateCount = jointCorePositiveCount;
decision.compositionallySafeCandidateCount = ...
    compositionallySafeCount;
decision.compositionBest = compositionBest;
decision.strictGatePassed = compositionBest.present && ...
    compositionBest.strictGatePassed;
decision.toleranceViolationCount = getField( ...
    compositionBest, 'toleranceViolationCount', NaN);
decision.minimumRegisteredMarginPercent = getField( ...
    compositionBest, 'minimumRegisteredMarginPercent', NaN);
decision.minimumTailMarginPercent = getField( ...
    compositionBest, 'minimumTailMarginPercent', NaN);
decision.authorized = compositionBest.present;
if decision.authorized
    decision.nextAction = ...
        'freeze-v227-carrier-then-build-v228-training-trajectories';
    decision.reason = [ ...
        'A corrected V226 action has a non-regressive donor-only state, ', ...
        'positive incremental and joint E-OSPA, RMSE, window and terminal ', ...
        'consensus gains, and positive attempted-byte saving. This ', ...
        'authorizes learning action value but not a paper claim.'];
else
    decision.nextAction = 'stop-fusion-aware-label-edge-controller-line';
    decision.reason = [ ...
        'The corrected V226 pilot contains no compositionally safe action. ', ...
        'A merely joint-positive action cannot authorize the online line ', ...
        'because transfer failure would expose a harmful donor-only state.'];
end
decision.paperPromotionAllowed = false;
decision.deploymentClaimAllowed = false;
decision.generalizationClaimAllowed = false;
decision.evidenceBoundary = [ ...
    'This is a deterministic method-development decision over the V226 ', ...
    'teacher/mechanism pilot. It adds a stagewise composition gate without ', ...
    'relaxing or rewriting the V226 result. The strict local-tail gate ', ...
    'remains visible and unchanged. V227 carrier selection, grouped ', ...
    'training, calibration and unseen M24/X36 evaluation are still required.'];
end

function [best, safeCount, jointPositiveCount] = ...
        findCompositionallySafeBest(pilot, protocol)
best = emptyCompositionBest(protocol);
bestScore = -inf;
bestDonorMargin = -inf;
safeCount = 0;
jointPositiveCount = 0;
identityTolerance = 1e-10;
for state = reshape(pilot.states, 1, [])
    for donorRun = reshape(state.donorRuns, 1, [])
        for record = reshape(donorRun.records, 1, [])
            joint = reshape(record.jointGainVectorPercent, 1, []);
            incremental = reshape( ...
                record.incrementalGainVectorPercent, 1, []);
            if numel(joint) ~= numel(protocol.model.targetNames) || ...
                    numel(incremental) ~= ...
                        numel(protocol.model.targetNames) || ...
                    any(~isfinite(joint)) || ...
                    any(~isfinite(incremental)) || ...
                    ~isfinite(record.attemptedByteSavingPercent)
                continue;
            end
            donor = recoverDonorGainVector(joint, incremental);
            jointCore = all(joint(1:4) > 0);
            incrementalCore = all(incremental(1:4) > 0);
            donorCore = all(donor(1:4) >= -identityTolerance);
            bytePositive = record.byteConservationPassed && ...
                record.attemptedByteSavingPercent > 0;
            if logical(record.jointCorePositive) ~= jointCore || ...
                    logical(record.incrementalCorePositive) ~= ...
                        incrementalCore
                error('FusionAwareLabelEdgeControllerV228:RecordGateDrift', ...
                    'A V226 record disagrees with its core-gain flags.');
            end
            jointPositiveCount = jointPositiveCount + double( ...
                jointCore && bytePositive);
            if ~(donorCore && incrementalCore && ...
                    jointCore && bytePositive)
                continue;
            end
            safeCount = safeCount + 1;
            score = min([joint(1:4), incremental(1:4), ...
                record.attemptedByteSavingPercent]);
            donorMargin = min(donor(1:4));
            if score > bestScore + 1e-12 || ...
                    (abs(score - bestScore) <= 1e-12 && ...
                     donorMargin > bestDonorMargin + 1e-12)
                bestScore = score;
                bestDonorMargin = donorMargin;
                best = buildCompositionBest( ...
                    state, donorRun, record, joint, incremental, ...
                    donor, score, protocol);
            end
        end
    end
end
end

function donor = recoverDonorGainVector(joint, incremental)
% If J=100*(R-C)/R and I=100*(D-C)/D, then
% D/R=(1-J/100)/(1-I/100) and G_D=100*(1-D/R).
candidateOverReference = 1 - joint / 100;
candidateOverDonor = 1 - incremental / 100;
if any(candidateOverReference < 0) || ...
        any(candidateOverDonor <= 0)
    donor = nan(size(joint));
    return;
end
donor = 100 * (1 - ...
    candidateOverReference ./ candidateOverDonor);
end

function best = buildCompositionBest( ...
        state, donorRun, record, joint, incremental, donor, score, protocol)
margins = joint - protocol.risk.tolerancePercent;
best = emptyCompositionBest(protocol);
best.present = true;
best.windowIndex = state.windowIndex;
best.currentTime = state.currentTime;
best.donorFormationId = donorRun.donorFormationId;
best.beneficiaryFormationId = record.beneficiaryFormationId;
best.sourceId = record.sourceId;
best.label = record.label;
best.recordIndex = record.recordIndex;
best.donorGainVectorPercent = donor;
best.incrementalGainVectorPercent = incremental;
best.jointGainVectorPercent = joint;
best.attemptedByteSavingPercent = ...
    record.attemptedByteSavingPercent;
best.score = score;
best.strictGatePassed = all(margins >= -1e-12);
best.toleranceViolationCount = nnz(margins < -1e-12);
best.minimumRegisteredMarginPercent = min(margins);
best.minimumTailMarginPercent = min(margins(5:end));
best.screenPath = record.screenPath;
end

function best = emptyCompositionBest(protocol)
best = struct( ...
    'present', false, 'windowIndex', 0, 'currentTime', 0, ...
    'donorFormationId', 0, 'beneficiaryFormationId', 0, ...
    'sourceId', 0, 'label', zeros(2, 1), 'recordIndex', 0, ...
    'donorGainVectorPercent', ...
        nan(1, numel(protocol.model.targetNames)), ...
    'incrementalGainVectorPercent', ...
        nan(1, numel(protocol.model.targetNames)), ...
    'jointGainVectorPercent', ...
        nan(1, numel(protocol.model.targetNames)), ...
    'attemptedByteSavingPercent', NaN, 'score', -inf, ...
    'strictGatePassed', false, 'toleranceViolationCount', NaN, ...
    'minimumRegisteredMarginPercent', NaN, ...
    'minimumTailMarginPercent', NaN, 'screenPath', '');
end

function pilot = resolvePilot(input)
if ischar(input)
    if exist(input, 'file') ~= 2
        error('FusionAwareLabelEdgeControllerV228:MissingPilot', ...
            'The requested V226 pilot artifact does not exist.');
    end
    loaded = load(input, 'result');
    if ~isfield(loaded, 'result')
        error('FusionAwareLabelEdgeControllerV228:MissingResult', ...
            'The V226 pilot artifact does not contain result.');
    end
    pilot = loaded.result;
else
    pilot = input;
end
end

function validatePilot(pilot, protocol)
required = {'contractVersion', 'generationGitCommit', ...
    'trajectoryGenerationGitCommit', 'stageBest', ...
    'states', ...
    'anyCorePositiveBytePositiveCandidate', ...
    'fixedStaticRouteBaselineIncluded', ...
    'endToEndStaticBaselineClaimAllowed', ...
    'truthUsedForDonorSelection', 'validationClaimAllowed'};
if ~isstruct(pilot) || ~isscalar(pilot) || ...
        any(~isfield(pilot, required)) || ...
        ~strcmp(pilot.contractVersion, ...
            protocol.authorization.requiredV226Contract) || ...
        pilot.fixedStaticRouteBaselineIncluded || ...
        pilot.endToEndStaticBaselineClaimAllowed || ...
        ~pilot.truthUsedForDonorSelection || ...
        pilot.validationClaimAllowed || ...
        ~isstruct(pilot.stageBest) || ~isscalar(pilot.stageBest) || ...
        ~isfield(pilot.stageBest, 'present')
    error('FusionAwareLabelEdgeControllerV228:InvalidPilot', ...
        'The V226 pilot does not satisfy the frozen mechanism contract.');
end
if ~isstruct(pilot.states)
    error('FusionAwareLabelEdgeControllerV228:InvalidStates', ...
        'The V226 pilot does not expose its candidate records.');
end
if pilot.stageBest.present
    requiredBest = {'jointGainVectorPercent', ...
        'attemptedByteSavingPercent', 'strictGatePassed'};
    if any(~isfield(pilot.stageBest, requiredBest)) || ...
            numel(pilot.stageBest.jointGainVectorPercent) ~= ...
                numel(protocol.model.targetNames)
        error('FusionAwareLabelEdgeControllerV228:InvalidStageBest', ...
            'The V226 stage-best record is incomplete.');
    end
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
