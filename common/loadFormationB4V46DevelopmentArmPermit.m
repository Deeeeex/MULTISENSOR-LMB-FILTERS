function permit = ...
    loadFormationB4V46DevelopmentArmPermit(caseOrdinal, armId)
% LOADFORMATIONB4V46DEVELOPMENTARMPERMIT Load one trusted data permit.

registry = getFormationB4V46DevelopmentArmPermitRegistry();
if ~registry.filterExecutionAuthorized
    error('FormationB4V46DevelopmentPermit:ExecutionSealed', ...
        'V46 development arm execution remains sealed.');
end
if ~isa(caseOrdinal, 'double') || ~isreal(caseOrdinal) || ...
        ~isscalar(caseOrdinal) || ~isfinite(caseOrdinal) || ...
        caseOrdinal ~= floor(caseOrdinal) || ...
        ~ischar(armId) || ~isrow(armId)
    error('FormationB4V46DevelopmentPermit:UnknownPermit', ...
        'An exact development case ordinal and arm ID are required.');
end
matching = [registry.permits.caseOrdinal] == caseOrdinal & ...
    strcmp({registry.permits.armId}, armId);
if nnz(matching) ~= 1
    error('FormationB4V46DevelopmentPermit:UnknownPermit', ...
        'The requested development case-arm permit is not registered.');
end
permit = registry.permits(find(matching, 1));
end
