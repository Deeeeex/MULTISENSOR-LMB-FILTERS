function audit = computeFormationH3StrictOracleAudit( ...
        localScreen, pairScreen)
% COMPUTEFORMATIONH3STRICTORACLEAUDIT Six-target deployment oracle.

required = { ...
    'records', 'outcomes', 'referenceSubsetIndex', ...
    'presetName', 'seed', 'currentTime', ...
    'generationGitCommit', 'cacheSha256'};
if ~isstruct(localScreen) || ~isstruct(pairScreen) || ...
        ~all(isfield(localScreen, required)) || ...
        ~all(isfield(pairScreen, required)) || ...
        ~strcmp(localScreen.presetName, pairScreen.presetName) || ...
        localScreen.seed ~= pairScreen.seed || ...
        localScreen.currentTime ~= pairScreen.currentTime || ...
        ~strcmp(localScreen.generationGitCommit, ...
            pairScreen.generationGitCommit) || ...
        ~strcmp(localScreen.cacheSha256, pairScreen.cacheSha256) || ...
        localScreen.referenceSubsetIndex < 1 || ...
        pairScreen.referenceSubsetIndex < 1
    error('Formation H=3 strict-oracle screen pair is invalid.');
end

localReference = localScreen.referenceSubsetIndex;
pairReference = pairScreen.referenceSubsetIndex;
assertReferenceEqual( ...
    localScreen.records(localReference), ...
    pairScreen.records(pairReference), ...
    localScreen.outcomes(localReference), ...
    pairScreen.outcomes(pairReference));

pairKeep = true(1, numel(pairScreen.records));
pairKeep(pairReference) = false;
records = [localScreen.records, pairScreen.records(pairKeep)];
outcomes = [localScreen.outcomes, pairScreen.outcomes(pairKeep)];
referenceOutcome = localScreen.outcomes(localReference);
targets = zeros(numel(records), 6);
for actionIdx = 1:numel(records)
    record = records(actionIdx);
    targets(actionIdx, :) = [ ...
        record.meanGainPercent, ...
        record.minimumFormationGainPercent, ...
        record.worstGainPercent, ...
        record.consensusGainPercent, ...
        record.attemptedByteSavingPercent, ...
        100 * (referenceOutcome.deliveredBytes - ...
            outcomes(actionIdx).deliveredBytes) / ...
                max(referenceOutcome.deliveredBytes, eps)];
end
if any(~isfinite(targets(:)))
    error('Formation H=3 strict-oracle targets are non-finite.');
end
deploymentFeasible = all(targets >= -1e-12, 2);
feasibleIndices = find(deploymentFeasible);
if isempty(feasibleIndices)
    error('Formation H=3 strict oracle lost reference fallback.');
end
[oracleGain, localBestIdx] = max( ...
    targets(feasibleIndices, 1));
oracleIdx = feasibleIndices(localBestIdx);

actionNames = {records.actionName};
audit = struct();
audit.contractVersion = ...
    'formation-h3-six-target-strict-oracle-audit-v1';
audit.targetNames = { ...
    'mean_tracking_gain_percent', ...
    'minimum_formation_gain_percent', ...
    'worst_sensor_gain_percent', ...
    'consensus_gain_percent', ...
    'attempted_byte_saving_percent', ...
    'delivered_byte_saving_percent'};
audit.presetName = localScreen.presetName;
audit.seed = localScreen.seed;
audit.currentTime = localScreen.currentTime;
audit.generationGitCommit = ...
    localScreen.generationGitCommit;
audit.cacheSha256 = localScreen.cacheSha256;
audit.actionNames = actionNames;
audit.targets = targets;
audit.deploymentFeasible = deploymentFeasible;
audit.feasibleActionCount = nnz(deploymentFeasible);
audit.actionCount = numel(records);
audit.oracleActionIndex = oracleIdx;
audit.oracleActionName = actionNames{oracleIdx};
audit.oracleGainPercent = oracleGain;
audit.oracleTargets = targets(oracleIdx, :);
audit.positiveOracle = oracleGain > 1e-12;
audit.truthUsedForSelection = true;
audit.futureMeasurementsUsedForSelection = true;
audit.validationClaimAllowed = false;
end

function assertReferenceEqual( ...
        localRecord, pairRecord, localOutcome, pairOutcome)
recordFields = { ...
    'meanGainPercent', 'minimumFormationGainPercent', ...
    'worstGainPercent', 'consensusGainPercent', ...
    'attemptedByteSavingPercent'};
outcomeFields = { ...
    'meanEospa', 'worstSensorEospa', 'consensusOspa', ...
    'attemptedBytes', 'deliveredBytes'};
if ~strcmp(localRecord.actionName, 'reference') || ...
        ~strcmp(pairRecord.actionName, 'reference')
    error('Formation H=3 strict oracle lacks named reference actions.');
end
for idx = 1:numel(recordFields)
    name = recordFields{idx};
    if abs(localRecord.(name) - pairRecord.(name)) > 1e-12
        error('Formation H=3 reference records differ.');
    end
end
for idx = 1:numel(outcomeFields)
    name = outcomeFields{idx};
    scale = max(abs(localOutcome.(name)), 1);
    if abs(localOutcome.(name) - pairOutcome.(name)) > ...
            1e-12 * scale
        error('Formation H=3 reference outcomes differ.');
    end
end
end
