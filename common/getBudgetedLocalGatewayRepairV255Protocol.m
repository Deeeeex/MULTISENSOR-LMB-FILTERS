function protocol = getBudgetedLocalGatewayRepairV255Protocol()
% GETBUDGETEDLOCALGATEWAYREPAIRV255PROTOCOL Local vector-valued repair.

source = getScaleEquivariantSafeGatewayV254Protocol();
teacher = getIndependentM24GatewayTeacherV252Protocol();
protocol = struct();
protocol.id = 'budgeted-local-gateway-repair-v255-v1';
protocol.contractVersion = ...
    'budgeted-local-gateway-repair-v255-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.teacherSourceProtocolId = teacher.id;
protocol.armId = 'v255-budgeted-local-gateway-repair';
protocol.policyName = 'budgeted-local-gateway-repair-v255-policy';

protocol.trainingSeeds = [1302, 1303, 1304];
protocol.developmentHoldoutSeeds = 1306;
protocol.untouchedCompleteEpisodeSeeds = 1305;
protocol.anchorTimes = teacher.anchorTimes;
protocol.horizonSteps = teacher.horizonSteps;
protocol.maximumChangedDirectedGatewayArcs = 1;
protocol.minimumJointPositiveAnchorCount = 3;
protocol.maximumFormationRegressionPercent = 2;
protocol.minimumCoreGainPercent = 0;

protocol.controlSynopsisMode = 'two-formation-compact-node-32';
protocol.compactNodeBytesPerSensor = 32;
protocol.routeCommandHeaderBytes = 16;
protocol.routeCommandBytesPerChangedArc = 8;
protocol.controlCollectionCountPerHold = 1;
protocol.communicationCreditFraction = 0.20;
protocol.minimumRetainedStaticSavingFraction = ...
    1 - protocol.communicationCreditFraction;
protocol.developmentIncrementalByteCapPercentRelativeV242 = 2.0;

protocol.predictedOutcomeNames = { ...
    'eospa_gain_percent', ...
    'rmse_gain_percent', ...
    'consistency_gain_percent', ...
    'total_byte_saving_percent', ...
    'minimum_formation_eospa_gain_percent', ...
    'minimum_formation_rmse_gain_percent'};
protocol.primaryObjectiveName = 'rmse_gain_percent';
protocol.constraintOutcomeNames = { ...
    'eospa_gain_percent', ...
    'consistency_gain_percent', ...
    'total_byte_saving_percent', ...
    'minimum_formation_eospa_gain_percent', ...
    'minimum_formation_rmse_gain_percent'};
protocol.scalarMinimumUtilityRejected = true;
protocol.firstModelFamily = 'multi-output-ridge-with-one-sided-abstention';
protocol.gnnAuthorized = false;
protocol.allowedPresets = { ...
    'm24-formation-fov-temporal-coupled-formation-braid'};
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v255', ...
    'budgeted_local_gateway_repair');
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V255 is a development-stage repair of the V242 minimum causal ', ...
    'backbone. One action may replace at most one directed physical ', ...
    'gateway while preserving the formation tree, local cycles, KLA ', ...
    'weights and N+2(F-1) posterior-message count. Controller telemetry ', ...
    'is collected once per H=3 hold and only from the source and receiver ', ...
    'formations. The learned model predicts the six outcome coordinates ', ...
    'separately; a scalar minimum-slack regression is not reused. Seeds ', ...
    '1302--1304 are development data, seed 1306 is a new frozen holdout, ', ...
    'and seed 1305 remains untouched for a later complete episode. ', ...
    'Topology and communication-credit constraints are deterministic; ', ...
    'tracking gains require paired evidence and do not authorize a GNN, ', ...
    'X36 or a paper claim.'];

valid = isempty(intersect(protocol.trainingSeeds, ...
        protocol.developmentHoldoutSeeds)) && ...
    isempty(intersect([protocol.trainingSeeds, ...
        protocol.developmentHoldoutSeeds], ...
        protocol.untouchedCompleteEpisodeSeeds)) && ...
    protocol.maximumChangedDirectedGatewayArcs == 1 && ...
    protocol.controlCollectionCountPerHold == 1 && ...
    protocol.communicationCreditFraction > 0 && ...
    protocol.communicationCreditFraction < 1 && ...
    protocol.minimumRetainedStaticSavingFraction > 0 && ...
    protocol.developmentIncrementalByteCapPercentRelativeV242 >= 0 && ...
    numel(protocol.predictedOutcomeNames) == 6 && ...
    protocol.scalarMinimumUtilityRejected && ...
    ~protocol.gnnAuthorized;
if ~valid
    error('BudgetedLocalGatewayRepairV255:InvalidProtocol', ...
        'The V255 action, data split or communication budget is invalid.');
end
end
