function actions = buildProjectedFormationRowCompositionV123Actions( ...
        context, clockwiseAdjacency, clockwiseWeights, ...
        clockwiseDetails, protocol)
% BUILDPROJECTEDFORMATIONROWCOMPOSITIONV123ACTIONS Compose receiver rows.

if nargin < 5 || isempty(protocol)
    protocol = getProjectedFormationRowCompositionV123Protocol();
end
v121 = getMixedCarrierInsertionV121Protocol();
mixed = buildMixedCarrierInsertionV121Actions( ...
    context, clockwiseAdjacency, clockwiseWeights, ...
    clockwiseDetails, v121);
sourceAdjacency = cat(3, clockwiseAdjacency, ...
    mixed(1).adjacency, mixed(2).adjacency);
sourceWeights = cat(3, clockwiseWeights, ...
    mixed(1).weights, mixed(2).weights);
sourceDetails = [{clockwiseDetails}, ...
    {mixed(1).details}, {mixed(2).details}];
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
nodeCount = numel(groupIds);
actions = repmat(emptyAction(), 1, protocol.horizonSteps);
referenceWeightMultiset = sort(clockwiseWeights(:));
for pageIdx = 1:protocol.horizonSteps
    choices = protocol.graphChoiceByFormationPage(:, pageIdx);
    adjacency = false(nodeCount);
    weights = zeros(nodeCount);
    residual = false(nodeCount);
    for formationId = 1:size(protocol.graphChoiceByFormationPage, 1)
        rows = find(groupIds == formationId);
        sourceIdx = choices(formationId);
        adjacency(rows, :) = sourceAdjacency(rows, :, sourceIdx);
        weights(rows, :) = sourceWeights(rows, :, sourceIdx);
        residual(rows, :) = logical( ...
            sourceDetails{sourceIdx}.residualAdjacency(rows, :));
    end
    physical = logical(context.physicalAdjacency);
    if nnz(adjacency) ~= nnz(clockwiseAdjacency) || ...
            any(adjacency(:) & ~physical(:)) || ...
            max(abs(sum(weights, 2) - 1)) > 1e-12 || ...
            ~isequal(sort(weights(:)), referenceWeightMultiset)
        error('ProjectedFormationRowV123:StructuralInvariantFailed', ...
            'A V123 page violates exact-budget row composition.');
    end
    details = clockwiseDetails;
    details.fusionWeightMatrix = weights;
    details.residualAdjacency = residual;
    details.selectedResidualAdjacency = residual;
    details.messageCount = nnz(adjacency);
    details.v123ProjectedRows = struct( ...
        'pageIndex', pageIdx, ...
        'graphChoiceByFormation', reshape(choices, 1, []), ...
        'projectionFallbackFormationIds', ...
            protocol.projectionFallbackFormationIdsByPage{pageIdx}, ...
        'messageParityPassed', ...
            nnz(adjacency) == nnz(clockwiseAdjacency), ...
        'weightMultisetPassed', ...
            isequal(sort(weights(:)), referenceWeightMultiset));
    actions(pageIdx) = struct( ...
        'name', protocol.pageActionNames{pageIdx}, ...
        'adjacency', adjacency, 'weights', weights, ...
        'details', details);
end
end

function action = emptyAction()
action = struct('name', '', 'adjacency', false(0), ...
    'weights', zeros(0), 'details', struct());
end
