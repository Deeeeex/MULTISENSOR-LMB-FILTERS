function detected = ...
    isBraidedHandoverOpportunityV84ReferenceExecutionContext(context)
% ISBRAIDEDHANDOVEROPPORTUNITYV84REFERENCEEXECUTIONCONTEXT Identify V84.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'braided-handover-opportunity-v84-reference-context-v1');
end
