function detected = ...
        isRoleMultiplexedSinglePayloadV143ExecutionContext(context)
% ISROLEMULTIPLEXEDSINGLEPAYLOADV143EXECUTIONCONTEXT Identify V143 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'role-multiplexed-single-payload-v143-execution-context-v1');
end
