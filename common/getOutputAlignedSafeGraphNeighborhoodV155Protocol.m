function protocol = getOutputAlignedSafeGraphNeighborhoodV155Protocol()
% GETOUTPUTALIGNEDSAFEGRAPHNEIGHBORHOODV155PROTOCOL Frozen V155 gate.

generator = getSafeGraphCodebookOracleV152Protocol();
pareto = getSafeGraphParetoOracleV153Protocol();

protocol = struct();
protocol.id = 'output-aligned-safe-graph-neighborhood-v155';
protocol.contractVersion = 'safe-graph-neighborhood-v155-v1';
protocol.evidenceSplit = generator.evidenceSplit;
protocol.presetNames = generator.presetNames;
protocol.nodeCounts = generator.nodeCounts;
protocol.formationCounts = generator.formationCounts;
protocol.sensorsPerFormation = generator.sensorsPerFormation;
protocol.anchorTimes = generator.anchorTimes;
protocol.horizon = generator.horizon;
protocol.filterSeedOffset = generator.filterSeedOffset;
protocol.staticArmModes = generator.staticArmModes;
protocol.candidateArmPrefix = 'v155-safe-graph-neighbor';
protocol.maximumCutChanges = 1;
protocol.nonduplicateCutsPerFormation = ...
    protocol.sensorsPerFormation - 2;
protocol.candidateCounts = protocol.formationCounts .* ...
    (protocol.nonduplicateCutsPerFormation - 1);
protocol.dominantWeight = generator.dominantWeight;
protocol.residualWeight = generator.residualWeight;
protocol.exactSelectedMessageCount = ...
    generator.exactSelectedMessageCount;
protocol.orientation = 'clockwise';
protocol.fallbackMode = 'fixed-clockwise';
protocol.stageAPresetName = 'x36-formation-fov';
protocol.stageASeed = 83;
protocol.minimumMeanGainPercent = pareto.minimumMeanGainPercent;
protocol.maximumWorstSensorRegressionPercent = ...
    pareto.maximumWorstSensorRegressionPercent;
protocol.maximumMinimumFormationRegressionPercent = ...
    pareto.maximumMinimumFormationRegressionPercent;
protocol.maximumConsensusRegressionPercent = ...
    pareto.maximumConsensusRegressionPercent;
protocol.maximumAttemptedByteIncreasePercent = ...
    pareto.maximumAttemptedByteIncreasePercent;
protocol.maximumRadiusTwoSourceCount = 8;
protocol.maximumRadiusTwoCandidateCount = nchoosek( ...
    protocol.maximumRadiusTwoSourceCount, 2);
protocol.gnnTrainingAuthorized = false;
protocol.truthUsedForCandidateConstruction = false;
protocol.futureOutcomeUsedForCandidateConstruction = false;
protocol.claimBoundary = [ ...
    'Opened-development graph-neighborhood headroom only. The frozen ', ...
    'radius-one graphs are enumerated without posterior scores, truth or ', ...
    'future outcomes and held for the complete continuation. Paired ', ...
    'recursive outcomes select the offline oracle only.'];

stageIdx = find(strcmp( ...
    protocol.presetNames, protocol.stageAPresetName));
if numel(stageIdx) ~= 1 || ...
        protocol.stageASeed ~= generator.pilotSeeds || ...
        protocol.maximumCutChanges ~= 1 || ...
        any(protocol.candidateCounts ~= [12, 18]) || ...
        any(protocol.exactSelectedMessageCount ~= ...
            2 * protocol.nodeCounts - ...
                2 * protocol.formationCounts) || ...
        protocol.gnnTrainingAuthorized || ...
        protocol.truthUsedForCandidateConstruction || ...
        protocol.futureOutcomeUsedForCandidateConstruction
    error('V155 safe graph-neighborhood protocol is inconsistent.');
end
end
