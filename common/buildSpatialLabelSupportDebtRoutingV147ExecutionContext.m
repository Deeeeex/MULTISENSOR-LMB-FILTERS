function context = ...
    buildSpatialLabelSupportDebtRoutingV147ExecutionContext( ...
        presetName, seed, anchorTime, referenceCarrierMode, actionSpec)
% BUILDSPATIALLABELSUPPORTDEBTROUTINGV147EXECUTIONCONTEXT Pilot permit.

protocol = getSpatialLabelSupportDebtRoutingV147Protocol();
caseInfo = resolveCase(protocol, presetName);
registeredAnchor = resolveSetTrustSequenceV134PilotAnchor( ...
    caseInfo, protocol);
if seed ~= protocol.pilotSeed || anchorTime ~= registeredAnchor || ...
        ~ischar(referenceCarrierMode) || ...
        ~ismember(referenceCarrierMode, protocol.referenceCarrierModes) || ...
        ~isstruct(actionSpec) || ~isscalar(actionSpec) || ...
        ~all(isfield(actionSpec, { ...
            'index', 'name', 'activeOffsets', 'gateEligible'})) || ...
        actionSpec.index < 2 || ...
        actionSpec.index > numel(protocol.actionPatterns) || ...
        ~strcmp(actionSpec.name, ...
            protocol.actionPatterns(actionSpec.index).name) || ...
        ~isequal(reshape(actionSpec.activeOffsets, 1, []), ...
            reshape(protocol.actionPatterns( ...
                actionSpec.index).activeOffsets, 1, [])) || ...
        ~logical(actionSpec.gateEligible)
    error('SpatialDebtV147:InvalidExecutionContext', ...
        'The V147 candidate request is outside the frozen pilot bank.');
end
context = struct( ...
    'contractVersion', ...
        'v147-spatial-label-support-debt-routing-context-v1', ...
    'capability', ...
        'spatial-label-support-debt-routing-v147-headroom', ...
    'action', ...
        'filter-spatial-label-support-debt-routing-v147-headroom', ...
    'protocolId', protocol.id, ...
    'phase', 'candidate-continuation', ...
    'presetName', presetName, ...
    'seed', seed, ...
    'currentTime', anchorTime, ...
    'horizonSteps', caseInfo.horizonSteps, ...
    'measurementTimeCount', ...
        anchorTime + caseInfo.horizonSteps - 1, ...
    'policyName', protocol.outcomePolicyName, ...
    'referenceCarrierMode', referenceCarrierMode, ...
    'actionIndex', actionSpec.index, ...
    'actionName', actionSpec.name, ...
    'activeOffsets', reshape(actionSpec.activeOffsets, 1, []), ...
    'developmentEvidenceOnly', true);
end

function caseInfo = resolveCase(protocol, presetName)
caseIdx = find(strcmp({protocol.scaleCases.presetName}, presetName), 1);
if isempty(caseIdx)
    error('SpatialDebtV147:InvalidPreset', ...
        'The preset is outside the V147 scale contract.');
end
caseInfo = protocol.scaleCases(caseIdx);
end
