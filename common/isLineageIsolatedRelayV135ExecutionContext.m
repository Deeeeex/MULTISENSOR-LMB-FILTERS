function detected = isLineageIsolatedRelayV135ExecutionContext(context)
% ISLINEAGEISOLATEDRELAYV135EXECUTIONCONTEXT Identify V135 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'lineage-isolated-relay-v135-execution-context-v1');
end
