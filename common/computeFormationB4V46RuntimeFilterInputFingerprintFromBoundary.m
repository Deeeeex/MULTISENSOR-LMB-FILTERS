function fingerprint = ...
    computeFormationB4V46RuntimeFilterInputFingerprintFromBoundary( ...
        model, measurements, sensorTrajectories, neighborMap, ...
        commConfig, caseOrdinal)
% COMPUTEFORMATIONB4V46RUNTIMEFILTERINPUTFINGERPRINTFROMBOUNDARY Rehash input.
%
% This function reconstructs the truth-free runtime-v3 fingerprint using
% only values that cross the filter boundary.  It deliberately does not
% accept a full source fingerprint, an offline provenance object, a permit,
% or a tracking result.  The caller must separately compare the returned
% canonical hash with an independently accepted runtime entry.

registry = getFormationB4V46TrackingSourceRegistry();
caseContract = resolveCase(caseOrdinal, registry);
validateRuntimeBoundary(model, measurements, sensorTrajectories, ...
    neighborMap, commConfig, caseContract, registry);

envelope = model.formationB4V46RuntimeSourceEnvelope;
identity = buildDynamicTopologyPhysicalIdentityRegistry( ...
    model.dynamicTopologyScenario.config);
[expectedUniforms, deliveryMetadata] = ...
    materializePhysicalUidDirectedDeliveryUniforms( ...
        caseContract.deliverySeed, identity.sensorPhysicalUids, ...
        caseContract.simulationLength);
if ~isequaln(commConfig.linkUniforms, expectedUniforms)
    error('FormationB4V46RuntimeBoundary:DeliveryDrift', ...
        'The runtime link-uniform tensor is not the registered UID draw.');
end

birthPayload = struct( ...
    'numberOfBirthLocations', model.numberOfBirthLocations, ...
    'birthTimeByLocation', model.birthTimeByLocation, ...
    'birthParameters', model.birthParameters);
birthSha256 = computeCanonicalValueSha256(birthPayload);
if ~strcmp(birthSha256, ...
        envelope.registeredBirthPriorCanonicalSha256)
    error('FormationB4V46RuntimeBoundary:BirthPriorDrift', ...
        'The runtime birth prior differs from its boundary envelope.');
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v46-runtime-filter-input-fingerprint-v3';
payload.registryId = registry.id;
payload.registryCanonicalSha256 = registry.canonicalSha256;
payload.caseId = caseContract.id;
payload.caseOrdinal = caseContract.ordinal;
payload.caseCanonicalSha256 = caseContract.caseCanonicalSha256;
payload.seed = caseContract.seed;
payload.seedRole = caseContract.seedRole;
payload.primaryMatrix = caseContract.primaryMatrix;
payload.stressMatrix = caseContract.stressMatrix;
payload.runtimeFilterModelContractVersion = envelope.contractVersion;
payload.runtimeFilterBirthPriorSha256 = birthSha256;
payload.modelSha256 = computeCanonicalValueSha256(model);
payload.measurementsSha256 = ...
    computeCanonicalValueSha256(measurements);
payload.sensorTrajectoriesSha256 = ...
    computeCanonicalValueSha256(sensorTrajectories);
payload.neighborMapSha256 = ...
    computeCanonicalValueSha256(neighborMap);
payload.communicationConfigSha256 = ...
    computeCanonicalValueSha256(commConfig);
payload.physicalIdentityRegistrySha256 = identity.canonicalSha256;
payload.deliveryUniformMetadataSha256 = ...
    deliveryMetadata.canonicalSha256;
payload.deliveryUniformCanonicalTensorSha256 = ...
    deliveryMetadata.canonicalTensorSha256;
payload.deliveryUniformMaterializedTensorSha256 = ...
    deliveryMetadata.materializedTensorSha256;
payload.targetTrajectoryRealizationPassedToFilter = false;
payload.groundTruthPassedToFilter = false;
payload.registeredBirthPriorRetained = true;
fingerprint = payload;
fingerprint.canonicalSha256 = ...
    computeCanonicalValueSha256(payload);
end

function caseContract = resolveCase(caseOrdinal, registry)
if ~isa(caseOrdinal, 'double') || ~isreal(caseOrdinal) || ...
        ~isscalar(caseOrdinal) || ~isfinite(caseOrdinal) || ...
        caseOrdinal ~= floor(caseOrdinal) || caseOrdinal < 1 || ...
        caseOrdinal > registry.caseCount
    error('FormationB4V46RuntimeBoundary:UnknownCase', ...
        'caseOrdinal must identify one registered V46 case.');
end
caseContract = registry.cases(caseOrdinal);
if caseContract.ordinal ~= caseOrdinal
    error('FormationB4V46RuntimeBoundary:RegistryDrift', ...
        'The core registry is not indexed by its frozen case ordinal.');
end
end

function validateRuntimeBoundary(model, measurements, trajectories, ...
        neighborMap, commConfig, caseContract, registry)
if ~isstruct(model) || ~isscalar(model) || ...
        ~isfield(model, 'numberOfSensors') || ...
        ~isfield(model, 'numberOfBirthLocations') || ...
        ~isfield(model, 'birthTimeByLocation') || ...
        ~isfield(model, 'birthParameters') || ...
        ~isfield(model, 'dynamicTopologyScenario') || ...
        ~isstruct(model.dynamicTopologyScenario) || ...
        ~isscalar(model.dynamicTopologyScenario) || ...
        ~isfield(model.dynamicTopologyScenario, 'config') || ...
        ~isstruct(model.dynamicTopologyScenario.config) || ...
        ~isscalar(model.dynamicTopologyScenario.config) || ...
        ~isfield(model.dynamicTopologyScenario, 'seed') || ...
        ~isfield(model, 'formationB4V46RuntimeSourceEnvelope') || ...
        ~isstruct(model.formationB4V46RuntimeSourceEnvelope) || ...
        ~isscalar(model.formationB4V46RuntimeSourceEnvelope) || ...
        ~isstruct(commConfig) || ~isscalar(commConfig) || ...
        ~isfield(commConfig, 'linkUniforms')
    error('FormationB4V46RuntimeBoundary:MalformedInput', ...
        'The V46 filter-boundary input is malformed.');
end

config = model.dynamicTopologyScenario.config;
envelope = model.formationB4V46RuntimeSourceEnvelope;
expectedTopLevelFields = { ...
    'sensorMotionEnabled', 'xDimension', 'zDimension', ...
    'survivalProbability', 'existenceThreshold', 'A', 'u', 'R', ...
    'numberOfSensors', 'C', 'Q', 'detectionProbability', ...
    'clutterRate', 'clutterPerUnitVolume', ...
    'numberOfBirthLocations', 'gmWeightThreshold', ...
    'maximumNumberOfGmComponents', 'minimumTrajectoryLength', ...
    'dataAssociationMethod', 'maximumNumberOfLbpIterations', ...
    'lbpConvergenceTolerance', 'sensorCommRange', ...
    'sensorFovEnabled', 'sensorFovHalfAngleDeg', ...
    'sensorFovRange', 'sensorFovHeadingRad', ...
    'birthTimeByLocation', 'object', 'birthParameters', ...
    'sensorQuality', 'dynamicTopologyScenario', ...
    'formationB4V46RuntimeSourceEnvelope'};
expectedScenarioFields = {'presetName', 'seed', 'config'};
expectedConfigFields = { ...
    'presetName', 'formationCount', 'sensorsPerFormation', ...
    'numberOfSensors', 'sensorCenterWaypoints', 'sensorGroupIds', ...
    'formationStochasticRoleUidsByFormation', ...
    'sensorLocalRoleUidsByFormation', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', ...
    'physicalIdentityRegistryContractVersion', ...
    'physicalIdentityRegistryCanonicalSha256'};
requiredEnvelopeFields = { ...
    'contractVersion', 'registryId', 'registryCanonicalSha256', ...
    'caseId', 'caseOrdinal', 'caseCanonicalSha256', 'presetName', ...
    'seed', ...
    'registeredBirthPriorCanonicalSha256', ...
    'targetTrajectoryRealizationAbsent', 'groundTruthAbsent', ...
    'fullScenarioTargetMetadataAbsent', ...
    'duplicateSensorTrajectoryCopiesAbsent', ...
    'registeredBirthPriorRetained', ...
    'sensorTrajectorySuppliedAsSeparateRuntimeInput', ...
    'trackingOutcomeAuthorizationGranted', 'validationClaimAllowed'};
if ~exactFields(model, expectedTopLevelFields) || ...
        ~exactFields(model.dynamicTopologyScenario, ...
            expectedScenarioFields) || ...
        ~exactFields(config, expectedConfigFields) || ...
        ~exactFields(envelope, requiredEnvelopeFields) || ...
        ~strcmp(envelope.contractVersion, ...
            'formation-b4-v46-runtime-filter-model-envelope-v1') || ...
        ~strcmp(envelope.registryId, registry.id) || ...
        ~strcmp(envelope.registryCanonicalSha256, ...
            registry.canonicalSha256) || ...
        ~strcmp(envelope.caseId, caseContract.id) || ...
        envelope.caseOrdinal ~= caseContract.ordinal || ...
        ~strcmp(envelope.caseCanonicalSha256, ...
            caseContract.caseCanonicalSha256) || ...
        ~strcmp(envelope.presetName, caseContract.presetName) || ...
        envelope.seed ~= caseContract.seed || ...
        ~isTrue(envelope.targetTrajectoryRealizationAbsent) || ...
        ~isTrue(envelope.groundTruthAbsent) || ...
        ~isTrue(envelope.fullScenarioTargetMetadataAbsent) || ...
        ~isTrue(envelope.duplicateSensorTrajectoryCopiesAbsent) || ...
        ~isTrue(envelope.registeredBirthPriorRetained) || ...
        ~isTrue(envelope. ...
            sensorTrajectorySuppliedAsSeparateRuntimeInput) || ...
        ~isFalse(envelope.trackingOutcomeAuthorizationGranted) || ...
        ~isFalse(envelope.validationClaimAllowed) || ...
        model.numberOfSensors ~= caseContract.numberOfSensors || ...
        model.dynamicTopologyScenario.seed ~= caseContract.seed || ...
        ~isfield(config, 'presetName') || ...
        ~strcmp(config.presetName, caseContract.presetName) || ...
        ~isfield(config, 'numberOfSensors') || ...
        config.numberOfSensors ~= caseContract.numberOfSensors
    error('FormationB4V46RuntimeBoundary:CaseDrift', ...
        'The runtime model does not match the registered V46 case.');
end

if ~iscell(measurements) || ...
        ~isequal(size(measurements), ...
            [caseContract.numberOfSensors, ...
             caseContract.simulationLength]) || ...
        ~iscell(trajectories) || ...
        numel(trajectories) ~= caseContract.numberOfSensors || ...
        ~iscell(neighborMap) || ...
        numel(neighborMap) ~= caseContract.numberOfSensors || ...
        ~isa(commConfig.linkUniforms, 'double') || ...
        ~isreal(commConfig.linkUniforms) || ...
        ~isequal(size(commConfig.linkUniforms), ...
            [caseContract.numberOfSensors, ...
             caseContract.numberOfSensors, ...
             caseContract.simulationLength]) || ...
        any(~isfinite(commConfig.linkUniforms(:)))
    error('FormationB4V46RuntimeBoundary:MalformedInput', ...
        'Runtime arrays differ from the registered V46 dimensions.');
end
for sensorIdx = 1:numel(trajectories)
    trajectory = trajectories{sensorIdx};
    if ~isa(trajectory, 'double') || ~isreal(trajectory) || ...
            ~isequal(size(trajectory), ...
                [4, caseContract.simulationLength]) || ...
            any(~isfinite(trajectory(:)))
        error('FormationB4V46RuntimeBoundary:MalformedInput', ...
            'A runtime sensor trajectory is malformed.');
    end
end
end

function value = exactFields(value, expected)
value = isstruct(value) && isscalar(value) && ...
    isequal(sort(fieldnames(value)), sort(reshape(expected, [], 1)));
end

function value = isTrue(value)
value = islogical(value) && isscalar(value) && value;
end

function value = isFalse(value)
value = islogical(value) && isscalar(value) && ~value;
end
