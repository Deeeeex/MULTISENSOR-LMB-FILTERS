function diagnostics = computeStochasticMixingDiagnostics(weights)
% COMPUTESTOCHASTICMIXINGDIAGNOSTICS Mixing proxies for a row-stochastic map.

if ~isnumeric(weights) || ndims(weights) ~= 2 || ...
        size(weights, 1) ~= size(weights, 2) || ...
        isempty(weights) || any(~isfinite(weights(:))) || ...
        any(weights(:) < -1e-12)
    error('Mixing matrix must be finite, nonnegative, and square.');
end
nodeCount = size(weights, 1);
rowSumError = max(abs(sum(weights, 2) - 1));
if rowSumError > 1e-10
    error('Mixing matrix must be row stochastic.');
end

dobrushin = 0;
for firstIdx = 1:nodeCount
    for secondIdx = (firstIdx + 1):nodeCount
        dobrushin = max(dobrushin, 0.5 * sum(abs( ...
            weights(firstIdx, :) - weights(secondIdx, :))));
    end
end
centering = eye(nodeCount) - ones(nodeCount) / nodeCount;
centered = centering * weights * centering;
rowCentered = weights - mean(weights, 1);
diagnostics = struct( ...
    'rowSumError', rowSumError, ...
    'minimumWeight', min(weights(:)), ...
    'maximumWeight', max(weights(:)), ...
    'dobrushinCoefficient', dobrushin, ...
    'centeredSpectralNorm', norm(centered, 2), ...
    'maximumCenteredRowL2', max(sqrt(sum( ...
        rowCentered .^ 2, 2))));
end
