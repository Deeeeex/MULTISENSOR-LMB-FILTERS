function detected = isProtectionLoadGatedRoleV145ExecutionContext(context)
% ISPROTECTIONLOADGATEDROLEV145EXECUTIONCONTEXT Identify V145.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'protection-load-gated-role-v145-execution-context-v1');
end

