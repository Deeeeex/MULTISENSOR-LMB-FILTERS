function authorization = ...
    validateOutputAlignedSafeGraphNeighborhoodV155Execution( ...
        model, context, request)
% VALIDATEOUTPUTALIGNEDSAFEGRAPHNEIGHBORHOODV155EXECUTION Enforce Stage A.

protocol = getOutputAlignedSafeGraphNeighborhoodV155Protocol();
expectedFields = { ...
    'contractVersion', 'capability', 'action', 'protocolId', ...
    'evidenceSplit', 'phase', 'presetName', 'seed', 'currentTime', ...
    'horizonSteps', 'measurementTimeCount', 'policyName', ...
    'candidateOrdinal', 'trackingOutcomeScoringAuthorized', ...
    'developmentEvidenceOnly'};
validContext = isstruct(context) && isscalar(context) && ...
    isequal(sort(fieldnames(context)), sort(expectedFields(:))) && ...
    strcmp(context.capability, ...
        'safe-graph-neighborhood-v155-development') && ...
    strcmp(context.action, ...
        'filter-safe-graph-neighborhood-v155-development') && ...
    strcmp(context.protocolId, protocol.id) && ...
    strcmp(context.evidenceSplit, protocol.evidenceSplit) && ...
    strcmp(context.phase, 'stage-a-arm') && ...
    strcmp(context.presetName, protocol.stageAPresetName) && ...
    context.seed == protocol.stageASeed && ...
    isequal(context.trackingOutcomeScoringAuthorized, true) && ...
    isequal(context.developmentEvidenceOnly, true);
if ~validContext
    error('SafeGraphNeighborhoodV155:InvalidExecutionContext', ...
        'The V155 execution context is malformed.');
end
presetIdx = find(strcmp(protocol.presetNames, context.presetName));
expectedPolicy = sprintf('%s%d', protocol.candidateArmPrefix, ...
    context.candidateOrdinal);
if numel(presetIdx) ~= 1 || ...
        context.currentTime ~= protocol.anchorTimes(presetIdx) || ...
        context.horizonSteps ~= protocol.horizon || ...
        context.measurementTimeCount ~= ...
            context.currentTime + context.horizonSteps - 1 || ...
        context.candidateOrdinal < 1 || ...
        context.candidateOrdinal > ...
            protocol.candidateCounts(presetIdx) || ...
        mod(context.candidateOrdinal, 1) ~= 0 || ...
        ~strcmp(context.policyName, expectedPolicy)
    error('SafeGraphNeighborhoodV155:InvalidExecutionContext', ...
        'The V155 execution context changed its candidate or horizon.');
end

scenario = struct();
if isstruct(model) && isscalar(model) && ...
        isfield(model, 'dynamicTopologyScenario')
    scenario = model.dynamicTopologyScenario;
end
validModel = isstruct(model) && isscalar(model) && ...
    isfield(model, 'numberOfSensors') && ...
    model.numberOfSensors == protocol.nodeCounts(presetIdx) && ...
    isstruct(scenario) && isscalar(scenario) && ...
    isfield(scenario, 'presetName') && ...
    strcmp(scenario.presetName, context.presetName) && ...
    isfield(scenario, 'seed') && scenario.seed == context.seed && ...
    isfield(scenario, 'config') && ...
    scenario.config.formationCount == ...
        protocol.formationCounts(presetIdx) && ...
    scenario.config.sensorsPerFormation == ...
        protocol.sensorsPerFormation && ...
    ~isfield(model, 'explicitTargetTrajectories') && ...
    ~isfield(scenario, 'targetTrajectories') && ...
    ~isfield(scenario, 'target');
if ~validModel
    error('SafeGraphNeighborhoodV155:InvalidRuntimeModel', ...
        'The V155 runtime model is outside the frozen Stage-A case.');
end

requiredRequestFields = { ...
    'contractVersion', 'operation', 'measurementTimeCount', ...
    'sensorTrajectoryTimeCounts', 'triggerConfig'};
config = request.triggerConfig;
validRequest = isstruct(request) && isscalar(request) && ...
    isequal(sort(fieldnames(request)), ...
        sort(requiredRequestFields(:))) && ...
    strcmp(request.operation, 'filter-execution') && ...
    request.measurementTimeCount == context.measurementTimeCount && ...
    numel(request.sensorTrajectoryTimeCounts) == ...
        protocol.nodeCounts(presetIdx) && ...
    all(request.sensorTrajectoryTimeCounts == ...
        context.measurementTimeCount) && ...
    isstruct(config) && isscalar(config) && ...
    isfield(config, 'eventPolicy') && ...
    strcmpi(config.eventPolicy, 'alwaysHeavy') && ...
    isfield(config, 'dynamicTopologyEnabled') && ...
    logical(config.dynamicTopologyEnabled) && ...
    isfield(config, 'topologyDirectedEnabled') && ...
    logical(config.topologyDirectedEnabled) && ...
    isfield(config, 'topologyDirectedMessageBudget') && ...
    config.topologyDirectedMessageBudget == ...
        2 * protocol.nodeCounts(presetIdx) && ...
    isfield(config, 'topologyPolicyName') && ...
    strcmp(config.topologyPolicyName, context.policyName) && ...
    isfield(config, 'topologyPolicyHistoryDepth') && ...
    config.topologyPolicyHistoryDepth >= 2;
if ~validRequest
    error('SafeGraphNeighborhoodV155:InvalidRuntimeRequest', ...
        'The V155 runtime request changed its frozen boundary.');
end

authorization = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-execution-authorization-v1', ...
    'mode', 'safe-graph-neighborhood-v155-development', ...
    'permitId', '', ...
    'permitCanonicalSha256', '', ...
    'capability', context.capability, ...
    'action', context.action, ...
    'protocolId', protocol.id, ...
    'protocolCanonicalSha256', '', ...
    'caseId', '', ...
    'caseCanonicalSha256', '', ...
    'presetName', context.presetName, ...
    'seed', context.seed, ...
    'sourceWindow', [1, context.measurementTimeCount], ...
    'armId', context.policyName, ...
    'armOrdinal', context.candidateOrdinal, ...
    'methodSourceCommit', '', ...
    'methodPolicyConfigSha256', '', ...
    'sourceTriggerFingerprintSha256', '', ...
    'executableSourceCommit', '', ...
    'executableSourceManifestSha256', '', ...
    'executionHeadCommit', '', ...
    'sourceInputFingerprintSha256', '', ...
    'stateEstimateOutputAuthorized', true, ...
    'trackingOutcomeScoringAuthorized', true, ...
    'groundTruthAccessAuthorized', false, ...
    'futureOutcomeAccessAuthorized', false, ...
    'validationClaimAllowed', false, ...
    'developmentEvidenceOnly', true);
end
