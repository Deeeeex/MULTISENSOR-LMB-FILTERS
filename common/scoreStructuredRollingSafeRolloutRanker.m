function scores = ...
    scoreStructuredRollingSafeRolloutRanker(model, X)
% SCORESTRUCTUREDROLLINGSAFEROLLOUTRANKER Score observable edge features.

required = { ...
    'kind', 'featureMask', 'featureMean', ...
    'featureScale', 'coefficient'};
if ~isstruct(model) || ~all(isfield(model, required)) || ...
        ~strcmp(model.kind, ...
            'linear-structured-rolling-safe-rollout-ranker-v1')
    error('Invalid structured rolling-safe rollout ranker.');
end
featureMask = logical(reshape(model.featureMask, 1, []));
if size(X, 2) ~= numel(featureMask) || ~any(featureMask)
    error('Structured rolling-safe feature dimension mismatch.');
end
retained = X(:, featureMask);
featureMean = reshape(model.featureMean, 1, []);
featureScale = reshape(model.featureScale, 1, []);
coefficient = reshape(model.coefficient, [], 1);
if size(retained, 2) ~= numel(featureMean) || ...
        numel(featureMean) ~= numel(featureScale) || ...
        numel(featureMean) ~= numel(coefficient) || ...
        any(~isfinite(retained(:))) || ...
        any(~isfinite(featureMean)) || ...
        any(~isfinite(featureScale)) || ...
        any(featureScale <= 0) || ...
        any(~isfinite(coefficient))
    error('Structured rolling-safe normalization contract is invalid.');
end
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, retained, featureMean), featureScale);
scores = Z * coefficient;
if isfield(model, 'intercept')
    scores = scores + model.intercept;
end
scores = reshape(scores, [], 1);
if any(~isfinite(scores))
    error('Structured rolling-safe ranker produced non-finite scores.');
end
end
