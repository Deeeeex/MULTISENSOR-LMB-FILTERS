function protocol = getAlternatingShieldBroadcastV111Protocol()
% GETALTERNATINGSHIELDBROADCASTV111PROTOCOL Extend V102 cadence to H=8.

base = getProtectionOnlyH8V105Protocol();
route = getShieldBroadcastV102Protocol();
protocol = base;
protocol.id = 'alternating-shield-broadcast-v111-v1';
protocol.contractVersion = ...
    'alternating-shield-broadcast-v111-protocol-v1';
protocol.outcomePolicyName = ...
    'alternating-shield-broadcast-v111-v1';
protocol.executionProfile = 'v111-alternating-shield-broadcast';
protocol.bankVariant = 'alternating-shield-broadcast-v111';
protocol.candidateActionName = ...
    'v111-alternating-shield-broadcast-h8';
protocol.resultContractVersion = ...
    'alternating-shield-broadcast-v111-x36-t72-result-v1';
protocol.resultFileStem = ...
    'ALTERNATING_SHIELD_BROADCAST_V111_X36_T72_RESULT';
protocol.reportTitle = ...
    'V111 alternating shield/broadcast: X36 t72 H=8';
protocol.armDisplayName = 'V111 alternating shield/broadcast';
protocol.runLabel = 'V111 X36-t72 H=8';
