protocol.minimumFormationGainPercent = 0;
protocol.minimumTargetPeerTerminalGainPercent = 0;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v111', 'alternating_shield_broadcast');
protocol.headroomOutputRoot = fullfile( ...
    protocol.outputRoot, 'matched_static_headroom');
protocol.evidenceBoundary = [ ...
    'V111 is a frozen H=8 propagation-control headroom probe. It extends ', ...
    'the V102 one-step-delayed alternating shield/broadcast cadence to ', ...
    'the complete V105 H=8 protection schedule and uses explicit ', ...
    'abstention for protected cross inputs. Broadcast and reference ', ...
    'recovery pages alternate, every route page remains physically ', ...
    'reachable, and the matched static full-payload outcome is reused. ', ...
    'The schedule is constructed without V110 outcomes, but it remains ', ...
    'frozen development evidence rather than an online policy or a ', ...
    'validation/generalization claim.'];
end
