    {zeros(1, 0)}, protocol.protectionFormationIdsByTime(1:end-1)];
protocol.broadcastFormationIdsByTime = delayedBroadcast;
protocol.broadcastFormationIdsByTime(3:2:end) = repmat( ...
    {zeros(1, 0)}, 1, ...
    numel(3:2:numel(delayedBroadcast)));
