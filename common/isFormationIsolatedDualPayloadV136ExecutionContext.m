function detected = isFormationIsolatedDualPayloadV136ExecutionContext(context)
% ISFORMATIONISOLATEDDUALPAYLOADV136EXECUTIONCONTEXT Identify V136 runs.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'formation-isolated-dual-payload-v136-execution-context-v1');
end
