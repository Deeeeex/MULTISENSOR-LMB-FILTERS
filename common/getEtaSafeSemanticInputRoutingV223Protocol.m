function protocol = getEtaSafeSemanticInputRoutingV223Protocol()
% GETETASAFESEMANTICINPUTROUTINGV223PROTOCOL Eta-safe one-pass route.

base = getSinglePassSemanticInputRoutingV221Protocol();
protocol = base;
protocol.id = 'eta-safe-semantic-input-routing-v223-v1';
protocol.contractVersion = ...
    'eta-safe-semantic-input-routing-v223-protocol-v1';
protocol.baseProtocolId = base.id;
protocol.etaProjectionEnabled = true;
protocol.minimumMapExistence = 0.50;
protocol.maximumReferenceLogOddsDrop = 0.25;
protocol.identityTolerance = 1e-8;
protocol.receiverSpecificApplication = true;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v223');
protocol.evidenceBoundary = [ ...
    'V223 is a frozen development mechanism screen. It preserves the ', ...
    'V221 single-pass complete-mixture route and exact communication ', ...
    'charge, but each receiver applies the semantic input only when the ', ...
    'powered-GM normalizer produced by the active fusion implementation ', ...
    'retains the ordinary fused label above the registered log-odds and ', ...
    'MAP floors. The semantic key and source share remain offline teacher ', ...
    'choices. It cannot support deployment or generalization claims.'];

if ~protocol.etaProjectionEnabled || ...
        ~protocol.receiverSpecificApplication || ...
        protocol.minimumMapExistence <= 0 || ...
        protocol.minimumMapExistence >= 1 || ...
        protocol.maximumReferenceLogOddsDrop < 0 || ...
        protocol.identityTolerance < 0 || ...
        protocol.postFusionResidualUpdateAllowed || ...
        protocol.onlinePolicyImplemented || ...
        protocol.validationClaimAllowed
    error('EtaSafeSemanticInputRoutingV223:ProtocolDrift', ...
        'The frozen V223 protocol is inconsistent.');
end
end
