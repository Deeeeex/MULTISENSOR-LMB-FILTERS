function protocol = getSinglePassSemanticInputRoutingV221Protocol()
% GETSINGLEPASSSEMANTICINPUTROUTINGV221PROTOCOL One-pass KLA headroom.

base = getDecoupledSemanticShortcutV220Protocol();
protocol = base;
protocol.id = 'single-pass-semantic-input-routing-v221-v1';
protocol.contractVersion = ...
    'single-pass-semantic-input-routing-v221-protocol-v1';
protocol.baseProtocolId = base.id;
protocol.repairSourceWeight = 0.10;
protocol.beneficiaryDecisionPhase = ...
    'pre-ordinary-fusion-frozen-teacher';
protocol.semanticFusionMode = ...
    'single-ordinary-label-wise-kla-with-proportional-source-share';
protocol.postFusionResidualUpdateAllowed = false;
protocol.onlinePolicyImplemented = false;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v221');
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V221 is a frozen development headroom test for the successor action ', ...
    'family. It preserves the V220 donor and exact communication ledger, ', ...
    'but routes one complete Bernoulli Gaussian-mixture label into the ', ...
    'ordinary label-wise KLA input set and performs fusion once. The ', ...
    'semantic key and source share are fixed offline; current payload, ', ...
    'physical reachability, realized delivery and byte charge are resolved ', ...
    'at runtime. It cannot support deployment or generalization claims.'];

if protocol.repairSourceWeight <= 0 || ...
        protocol.repairSourceWeight >= 1 || ...
        protocol.postFusionResidualUpdateAllowed || ...
        protocol.onlinePolicyImplemented || ...
        protocol.validationClaimAllowed
    error('SinglePassSemanticInputRoutingV221:ProtocolDrift', ...
        'The frozen V221 protocol is inconsistent.');
end
end
