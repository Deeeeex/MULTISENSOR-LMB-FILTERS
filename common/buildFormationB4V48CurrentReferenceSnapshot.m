function snapshot = buildFormationB4V48CurrentReferenceSnapshot( ...
        config, identity, registeredBaseAdjacency, positions, ...
        physicalAdjacency, pDropByEdge, currentTime)
% BUILDFORMATIONB4V48CURRENTREFERENCESNAPSHOT Causal V46/V43 graph page.

requiredConfig = {'numberOfSensors', 'sensorGroupIds'};
requiredIdentity = {'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'canonicalSha256'};
if ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config, requiredConfig)) || ...
        ~isstruct(identity) || ~isscalar(identity) || ...
        ~all(isfield(identity, requiredIdentity))
    error('FormationB4V48Snapshot:InvalidInput', ...
        'The formation configuration or physical identity is incomplete.');
end
nodeCount = config.numberOfSensors;
if ~isequal(size(registeredBaseAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(positions), [2, nodeCount]) || ...
        ~isequal(size(physicalAdjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(pDropByEdge), [nodeCount, nodeCount]) || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime < 1 || currentTime ~= round(currentTime)
    error('FormationB4V48Snapshot:InvalidInput', ...
        'The current graph page dimensions or time are invalid.');
end

[projectedBase, certificate] = ...
    projectCausalMinimalEditFormationBackbone( ...
        config.sensorGroupIds, identity.sensorPhysicalUids, ...
        identity.formationPhysicalUidsBySensor, positions, ...
        logical(registeredBaseAdjacency), ...
        logical(physicalAdjacency), pDropByEdge);
validateCausalMinimalEditFormationProjectionCertificate( ...
    certificate, identity.sensorPhysicalUids, projectedBase);

routeContext = struct();
routeContext.localPosteriorBySensor = cell(1, nodeCount);
routeContext.model = struct('dynamicTopologyScenario', struct( ...
    'config', struct('sensorGroupIds', config.sensorGroupIds), ...
    'staticAdjacency', logical(projectedBase)));
routeContext.baseAdjacency = logical(projectedBase);
routeContext.physicalAdjacency = logical(physicalAdjacency);
routeContext.positions = positions;
routeContext.sensorPhysicalUids = identity.sensorPhysicalUids;
routeContext.formationPhysicalUidsBySensor = ...
    identity.formationPhysicalUidsBySensor;
routeContext.commConfig = struct('pDropByEdge', pDropByEdge);
routeContext.currentTime = currentTime;
[referenceAdjacency, referencePolicy] = ...
    selectIndexEquivariantFormationBackbonePolicy( ...
        routeContext, struct('dominantWeight', 0.70, ...
            'residualWeight', 0.05));
reference = struct( ...
    'dominantAdjacency', logical(referencePolicy.dominantAdjacency), ...
    'residualAdjacency', logical(referencePolicy.residualAdjacency), ...
    'referenceAdjacency', logical(referenceAdjacency), ...
    'referenceFusionWeights', referencePolicy.fusionWeightMatrix);
[graphOnlyContext, graphOnlyContract] = ...
    buildFormationB4V48GraphOnlyContext(routeContext);

payload = struct();
payload.contractVersion = ...
    'formation-b4-v48-current-reference-snapshot-v1';
payload.currentTime = currentTime;
payload.nodeCount = nodeCount;
payload.sensorPhysicalUids = ...
    reshape(identity.sensorPhysicalUids, 1, []);
payload.formationPhysicalUidsBySensor = ...
    reshape(identity.formationPhysicalUidsBySensor, 1, []);
payload.physicalIdentityRegistryCanonicalSha256 = ...
    identity.canonicalSha256;
payload.graphOnlyContextCanonicalSha256 = ...
    graphOnlyContract.canonicalSha256;
payload.projectionCertificateCanonicalSha256 = ...
    certificate.canonicalSha256;
payload.referencePhysicalUidCanonicalSha256 = ...
    physicalRouteHash(reference.referenceAdjacency, ...
        reference.referenceFusionWeights, ...
        identity.sensorPhysicalUids);
payload.posteriorUsed = false;
payload.posteriorSummaryUsed = false;
payload.deliveryAcknowledgmentUsed = false;
payload.truthUsed = false;
payload.measurementUsed = false;
payload.futurePageUsed = false;
payload.realizedDeliveryUniformsUsed = false;
payload.trackingOutcomeScored = false;
payload.developmentEvidenceOnly = true;
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
snapshot = payload;
snapshot.graphOnlyContext = graphOnlyContext;
snapshot.reference = reference;
snapshot.projectedBaseAdjacency = logical(projectedBase);
snapshot.projectionCertificate = certificate;
end

function sha256 = physicalRouteHash(adjacency, weights, sensorUids)
[sortedUids, order] = sort(reshape(sensorUids, 1, []));
payload = struct( ...
    'contractVersion', ...
        'formation-b4-v48-physical-route-and-weight-v1', ...
    'sensorPhysicalUids', sortedUids, ...
    'adjacency', logical(adjacency(order, order)), ...
    'fusionWeightMatrix', weights(order, order));
sha256 = computeCanonicalValueSha256(payload);
end
