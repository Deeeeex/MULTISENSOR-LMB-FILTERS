function detected = ...
    isCounterfactualRegretGateV133ExecutionContext(context)
% ISCOUNTERFACTUALREGRETGATEV133EXECUTIONCONTEXT Identify V133.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'counterfactual-regret-gate-v133-execution-context-v1');
end
