function detected = ...
    isOnlinePositiveNetAddressablePayloadV99ExecutionContext(context)
% ISONLINEPOSITIVENETADDRESSABLEPAYLOADV99EXECUTIONCONTEXT Identify V99.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'online-positive-net-addressable-payload-v99-context-v1');
end
