function value = ...
    isFormationB4V53PairedTrackingDevelopmentContext(context)
% ISFORMATIONB4V53PAIREDTRACKINGDEVELOPMENTCONTEXT Recognize V53 context.

value = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    strcmp(context.contractVersion, ...
        'formation-b4-v53-paired-tracking-development-context-v1');
end
