function registry = ...
    getFormationB4V46DevelopmentRuntimeAcceptanceRegistry()
% GETFORMATIONB4V46DEVELOPMENTRUNTIMEACCEPTANCEREGISTRY Eight runtime inputs.
%
% This no-argument registry contains only the truth-free runtime-v3 hashes
% for the eight development-sentinel cases.  It freezes inputs that a later
% exact case-and-arm permit may depend on, but creates no permit or runtime
% authority by itself.

core = getFormationB4V46TrackingSourceRegistry();
payload = struct();
payload.id = ...
    'formation-b4-v46-development-runtime-acceptance-registry-v1';
payload.contractVersion = ...
    'formation-b4-v46-development-runtime-acceptance-registry-v1';
payload.coreRegistryId = core.id;
payload.coreRegistryCanonicalSha256 = core.canonicalSha256;
payload.structuralProtocolId = core.structuralProtocolId;
payload.structuralProtocolCanonicalSha256 = ...
    core.structuralProtocolCanonicalSha256;
payload.phase = 'development-sentinel';
payload.developmentSeed = core.developmentSeed;
payload.runtimeFilterProjectionContractVersion = ...
    'formation-b4-v46-runtime-filter-input-fingerprint-v3';
payload.canonicalSerializationFunction = ...
    'computeCanonicalValueSha256';
payload.caseOrdering = ...
    'core-registry-development-case-ordinal-order';
payload.caseCount = 8;
payload.entries = buildEntries();
payload.independentAcceptanceCompleted = true;
payload.runtimeInputsFrozen = true;
payload.eligibleAsPermitDependency = true;
payload.runtimeExecutionAuthorityProduced = false;
payload.exactCaseAndArmPermitStillRequired = true;
payload.truthBearingCommitmentsPresent = false;
payload.sourceProvenanceCommitmentsPresent = false;
payload.confirmationRuntimeEntriesPresent = false;
payload.filterExecutionAuthorized = false;
payload.stateEstimateOutputAuthorized = false;
payload.trackingOutcomeScoringAuthorized = false;
payload.armSelectionAuthorized = false;
payload.developmentAdvanceDecisionAuthorized = false;
payload.confirmationTrackingAuthorized = false;
payload.validationClaimAllowed = false;
payload.runnerSelfAuthorizationAllowed = false;
payload.evidenceBoundary = [ ...
    'This registry accepts only eight truth-free runtime-v3 input ', ...
    'hashes for seed 1009. It contains no truth-bearing source ', ...
    'provenance and no confirmation entry. A separate exact case-and-', ...
    'arm permit and common-filter validation remain mandatory before ', ...
    'filter execution; scoring, advance, confirmation, and validation ', ...
    'remain unauthorized.'];

actualSha256 = computeCanonicalValueSha256(payload);
expectedSha256 = ...
    'cb1841fc1451a4973af4696277c53bfec1272f76a170fdedad796db2746e1ca6';
if ~strcmp(actualSha256, expectedSha256)
    error('FormationB4V46RuntimeAcceptance:RegistryDrift', ...
        ['The development runtime acceptance registry drifted: ', ...
         'actual=%s expected=%s.'], actualSha256, expectedSha256);
end
registry = payload;
registry.canonicalSha256 = actualSha256;
end

