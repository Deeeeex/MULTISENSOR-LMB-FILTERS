function [reduced, contract] = ...
    buildFormationB4V49GraphOnlyRouteContext(context)
% BUILDFORMATIONB4V49GRAPHONLYROUTECONTEXT Exact current-page route input.

required = {'model', 'positions', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'physicalAdjacency', ...
    'commConfig', 'currentTime'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isstruct(context.model) || ~isscalar(context.model) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isstruct(context.model.dynamicTopologyScenario) || ...
        ~isscalar(context.model.dynamicTopologyScenario) || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isstruct(context.model.dynamicTopologyScenario.config) || ...
        ~isscalar(context.model.dynamicTopologyScenario.config) || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds') || ...
        ~isstruct(context.commConfig) || ...
        ~isscalar(context.commConfig) || ...
        ~isfield(context.commConfig, 'pDropByEdge') || ...
        ~isa(context.currentTime, 'double') || ...
        ~isscalar(context.currentTime) || ...
        ~isfinite(context.currentTime) || ...
        context.currentTime < 1 || ...
        context.currentTime ~= round(context.currentTime)
    error('FormationB4V49RouteContext:InvalidInput', ...
        'The current-page physical route context is incomplete.');
end
pDrop = context.commConfig.pDropByEdge;
if ~isa(pDrop, 'double') || ~isreal(pDrop) || ...
        ndims(pDrop) ~= 2 || any(~isfinite(pDrop(:))) || ...
        any(pDrop(:) < 0) || any(pDrop(:) > 1)
    error('FormationB4V49RouteContext:FuturePageOrInvalidLinkState', ...
        'V49 accepts exactly one finite current pDrop page.');
end

reduced = struct();
reduced.sensorGroupIds = reshape( ...
    context.model.dynamicTopologyScenario.config.sensorGroupIds, 1, []);
reduced.sensorPhysicalUids = ...
    reshape(context.sensorPhysicalUids, 1, []);
reduced.formationPhysicalUidsBySensor = ...
    reshape(context.formationPhysicalUidsBySensor, 1, []);
reduced.positions = context.positions;
reduced.physicalAdjacency = logical(context.physicalAdjacency);
reduced.pDropByEdge = pDrop;
reduced.currentTime = context.currentTime;

forbidden = {'localPosteriorBySensor', 'posteriorSummaryBySensor', ...
    'previousDeliveryHistory', 'measurements', 'measurement', ...
    'groundTruth', 'targetTrajectories', 'linkUniforms', ...
    'sensorTrajectories', 'futurePolicyData', 'commConfig', ...
    'model', 'baseAdjacency'};
outputFields = fieldnames(reduced);
passed = numel(outputFields) == 7 && ...
    ~any(isfield(reduced, forbidden));
if ~passed
    error('FormationB4V49RouteContext:InternalBoundaryFailure', ...
        'The route context retained a forbidden side channel.');
end

payload = struct();
payload.contractVersion = ...
    'formation-b4-v49-graph-only-route-context-v1';
payload.currentTime = reduced.currentTime;
payload.outputFieldNames = sort(outputFields)';
payload.currentGeometryPageOnly = true;
payload.currentPhysicalPageOnly = true;
payload.currentPDropPageOnly = true;
payload.posteriorPresent = false;
payload.posteriorSummaryPresent = false;
payload.deliveryAcknowledgmentPresent = false;
payload.measurementPresent = false;
payload.truthPresent = false;
payload.futurePagePresent = false;
payload.realizedDeliveryUniformPresent = false;
payload.passed = true;
payload.canonicalSha256 = computeCanonicalValueSha256(payload);
contract = payload;
end
