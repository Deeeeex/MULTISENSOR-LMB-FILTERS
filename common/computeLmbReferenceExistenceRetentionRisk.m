function [risk, details] = ...
    computeLmbReferenceExistenceRetentionRisk( ...
        referenceReceiverDistributions, ...
        candidateReceiverDistributions, groupIds, options)
% COMPUTELMBREFERENCEEXISTENCERETENTIONRISK Reference-relative KLA guard.
%
% The existing posterior Bayes-risk proxy can decrease when a candidate
% becomes confidently empty.  This asymmetric guard instead asks whether
% a candidate suppresses label-existence mass supported by the registered
% reference action.  Link-delivery uncertainty is already integrated in
% the supplied per-receiver outcome distributions.  The score is
% truth-free and does not claim that the reference posterior is correct.

if nargin < 4 || isempty(options)
    options = struct();
end
if ~iscell(referenceReceiverDistributions) || ...
        ~iscell(candidateReceiverDistributions) || ...
        numel(referenceReceiverDistributions) < 1 || ...
        numel(referenceReceiverDistributions) ~= ...
            numel(candidateReceiverDistributions)
    error('ExistenceRetention:InvalidInput', ...
        'Receiver outcome distributions are invalid.');
end
nodeCount = numel(referenceReceiverDistributions);
groupIds = reshape(groupIds, 1, []);
groups = unique(groupIds, 'stable');
formationCount = numel(groups);
referenceSupportThreshold = getField( ...
    options, 'referenceSupportThreshold', 0.10);
decisionExistenceThreshold = getField( ...
    options, 'decisionExistenceThreshold', 0.50);
receiverTailFraction = getField( ...
    options, 'receiverTailFraction', 0.34);
receiverTailWeight = getField( ...
    options, 'receiverTailWeight', 0.50);
if numel(groupIds) ~= nodeCount || formationCount < 1 || ...
        any(~isfinite(groupIds)) || any(groupIds < 1) || ...
        any(mod(groupIds, 1) ~= 0) || ...
        ~isProbabilityThreshold(referenceSupportThreshold) || ...
        ~isProbabilityThreshold(decisionExistenceThreshold) || ...
        referenceSupportThreshold >= 1 || ...
        decisionExistenceThreshold >= 1 || ...
        ~isscalar(receiverTailFraction) || ...
        ~isfinite(receiverTailFraction) || ...
        receiverTailFraction <= 0 || receiverTailFraction > 1 || ...
        ~isscalar(receiverTailWeight) || ...
        ~isfinite(receiverTailWeight) || ...
        receiverTailWeight < 0 || receiverTailWeight > 1
    error('ExistenceRetention:InvalidInput', ...
        'Existence-retention options or group IDs are invalid.');
end

expectedReferenceCardinality = zeros(1, nodeCount);
expectedCandidateCardinality = zeros(1, nodeCount);
expectedCardinalityChange = zeros(1, nodeCount);
expectedCardinalityLossFraction = zeros(1, nodeCount);
referenceWeightedExistenceShortfall = zeros(1, nodeCount);
normalizedExistenceDrift = zeros(1, nodeCount);
minimumSupportedLabelRetentionRatio = ones(1, nodeCount);
decisionThresholdCrossingCount = zeros(1, nodeCount);
decisionThresholdCrossingMass = zeros(1, nodeCount);
labelUniverseByReceiver = cell(1, nodeCount);
expectedReferenceExistenceByReceiver = cell(1, nodeCount);
expectedCandidateExistenceByReceiver = cell(1, nodeCount);
existenceShortfallByReceiver = cell(1, nodeCount);

for receiverIdx = 1:nodeCount
    reference = validateDistribution( ...
        referenceReceiverDistributions{receiverIdx});
    candidate = validateDistribution( ...
        candidateReceiverDistributions{receiverIdx});
    labels = distributionLabelUniverse(reference, candidate);
    referenceExistence = expectedExistence(reference, labels);
    candidateExistence = expectedExistence(candidate, labels);
    shortfall = max(referenceExistence - candidateExistence, 0);
    drift = abs(referenceExistence - candidateExistence);
    expectedReferenceCardinality(receiverIdx) = ...
        sum(referenceExistence);
    expectedCandidateCardinality(receiverIdx) = ...
        sum(candidateExistence);
    expectedCardinalityChange(receiverIdx) = ...
        expectedCandidateCardinality(receiverIdx) - ...
        expectedReferenceCardinality(receiverIdx);
    expectedCardinalityLossFraction(receiverIdx) = max( ...
        -expectedCardinalityChange(receiverIdx), 0) / max( ...
            expectedReferenceCardinality(receiverIdx), 1);
    salienceDenominator = sum(referenceExistence.^2);
    if salienceDenominator > eps
        referenceWeightedExistenceShortfall(receiverIdx) = ...
            sum(referenceExistence .* shortfall) / ...
                salienceDenominator;
    end
    normalizedExistenceDrift(receiverIdx) = sum(drift) / ...
        max(expectedReferenceCardinality(receiverIdx), 1);
    supported = referenceExistence >= referenceSupportThreshold;
    if any(supported)
        minimumSupportedLabelRetentionRatio(receiverIdx) = min( ...
            candidateExistence(supported) ./ ...
                max(referenceExistence(supported), eps));
    end
    crossing = referenceExistence >= decisionExistenceThreshold & ...
        candidateExistence < decisionExistenceThreshold;
    decisionThresholdCrossingCount(receiverIdx) = nnz(crossing);
    decisionThresholdCrossingMass(receiverIdx) = ...
        sum(shortfall(crossing));
    labelUniverseByReceiver{receiverIdx} = labels;
    expectedReferenceExistenceByReceiver{receiverIdx} = ...
        referenceExistence;
    expectedCandidateExistenceByReceiver{receiverIdx} = ...
        candidateExistence;
    existenceShortfallByReceiver{receiverIdx} = shortfall;
end

receiverRisk = max( ...
    referenceWeightedExistenceShortfall, ...
    expectedCardinalityLossFraction);
formationRisk = zeros(1, formationCount);
formationMeanRisk = zeros(1, formationCount);
formationTailRisk = zeros(1, formationCount);
formationMeanCardinalityChange = zeros(1, formationCount);
formationMinimumRetentionRatio = ones(1, formationCount);
formationThresholdCrossingCount = zeros(1, formationCount);
for formationIdx = 1:formationCount
    members = reshape(find( ...
        groupIds == groups(formationIdx)), 1, []);
    values = receiverRisk(members);
    tailCount = max(1, ceil(receiverTailFraction * numel(values)));
    sorted = sort(values, 'descend');
    formationMeanRisk(formationIdx) = mean(values);
    formationTailRisk(formationIdx) = mean(sorted(1:tailCount));
    formationRisk(formationIdx) = ...
        (1 - receiverTailWeight) * formationMeanRisk(formationIdx) + ...
        receiverTailWeight * formationTailRisk(formationIdx);
    formationMeanCardinalityChange(formationIdx) = mean( ...
        expectedCardinalityChange(members));
    formationMinimumRetentionRatio(formationIdx) = min( ...
        minimumSupportedLabelRetentionRatio(members));
    formationThresholdCrossingCount(formationIdx) = sum( ...
        decisionThresholdCrossingCount(members));
end
risk = max(formationRisk);
if ~isfinite(risk) || risk < -1e-12
    error('ExistenceRetention:InvalidResult', ...
        'Existence-retention risk is invalid.');
end
risk = max(risk, 0);

details = struct();
details.contractVersion = ...
    'lmb-reference-existence-retention-risk-v1';
details.referenceSupportThreshold = referenceSupportThreshold;
details.decisionExistenceThreshold = decisionExistenceThreshold;
details.receiverTailFraction = receiverTailFraction;
details.receiverTailWeight = receiverTailWeight;
details.groupIds = groupIds;
details.groups = groups;
details.labelUniverseByReceiver = labelUniverseByReceiver;
details.expectedReferenceExistenceByReceiver = ...
    expectedReferenceExistenceByReceiver;
details.expectedCandidateExistenceByReceiver = ...
    expectedCandidateExistenceByReceiver;
details.existenceShortfallByReceiver = ...
    existenceShortfallByReceiver;
details.expectedReferenceCardinality = ...
    expectedReferenceCardinality;
details.expectedCandidateCardinality = ...
    expectedCandidateCardinality;
details.expectedCardinalityChange = expectedCardinalityChange;
details.expectedCardinalityLossFraction = ...
    expectedCardinalityLossFraction;
details.referenceWeightedExistenceShortfall = ...
    referenceWeightedExistenceShortfall;
details.normalizedExistenceDrift = normalizedExistenceDrift;
details.minimumSupportedLabelRetentionRatio = ...
    minimumSupportedLabelRetentionRatio;
details.decisionThresholdCrossingCount = ...
    decisionThresholdCrossingCount;
details.decisionThresholdCrossingMass = ...
    decisionThresholdCrossingMass;
details.receiverRisk = receiverRisk;
details.formationRisk = formationRisk;
details.formationMeanRisk = formationMeanRisk;
details.formationTailRisk = formationTailRisk;
details.formationMeanCardinalityChange = ...
    formationMeanCardinalityChange;
details.formationMinimumRetentionRatio = ...
    formationMinimumRetentionRatio;
details.formationThresholdCrossingCount = ...
    formationThresholdCrossingCount;
details.risk = risk;
details.asymmetricReferenceDownside = true;
details.referenceCorrectnessClaimed = false;
details.truthUsed = false;
details.groundTruthUsed = false;
details.futureMeasurementUsed = false;
details.futureOutcomeUsed = false;
end

function distribution = validateDistribution(distribution)
if ~isstruct(distribution) || ...
        ~isfield(distribution, 'probability') || ...
        ~isfield(distribution, 'summary') || ...
        ~iscell(distribution.summary)
    error('ExistenceRetention:InvalidDistribution', ...
        'Receiver outcome distribution is incomplete.');
end
probability = reshape(distribution.probability, 1, []);
if isempty(probability) || ...
        numel(probability) ~= numel(distribution.summary) || ...
        any(~isfinite(probability)) || any(probability < 0) || ...
        abs(sum(probability) - 1) > 1e-10
    error('ExistenceRetention:InvalidDistribution', ...
        'Receiver outcome probabilities are invalid.');
end
for outcomeIdx = 1:numel(distribution.summary)
    summary = distribution.summary{outcomeIdx};
    if ~isstruct(summary) || ...
            ~isfield(summary, 'labels') || ...
            ~isfield(summary, 'existence') || ...
            size(summary.labels, 1) ~= 2 || ...
            numel(summary.existence) ~= size(summary.labels, 2) || ...
            any(~isfinite(summary.labels(:))) || ...
            any(~isfinite(summary.existence)) || ...
            any(summary.existence < 0) || ...
            any(summary.existence > 1) || ...
            size(unique(summary.labels', 'rows'), 1) ~= ...
                size(summary.labels, 2)
        error('ExistenceRetention:InvalidDistribution', ...
            'Receiver outcome summary is invalid.');
    end
end
distribution.probability = probability;
end

function labels = distributionLabelUniverse(left, right)
labels = zeros(2, 0);
distributions = {left, right};
for distributionIdx = 1:numel(distributions)
    distribution = distributions{distributionIdx};
    for outcomeIdx = 1:numel(distribution.summary)
        current = distribution.summary{outcomeIdx}.labels;
        for labelIdx = 1:size(current, 2)
            if isempty(labels) || ...
                    ~any(all(labels == current(:, labelIdx), 1))
                labels(:, end + 1) = ...
                    current(:, labelIdx); %#ok<AGROW>
            end
        end
    end
end
if ~isempty(labels)
    labels = sortrows(labels')';
end
end

function values = expectedExistence(distribution, labels)
values = zeros(1, size(labels, 2));
for outcomeIdx = 1:numel(distribution.summary)
    summary = distribution.summary{outcomeIdx};
    for labelIdx = 1:size(summary.labels, 2)
        universeIdx = find(all( ...
            labels == summary.labels(:, labelIdx), 1), 1);
        values(universeIdx) = values(universeIdx) + ...
            distribution.probability(outcomeIdx) * ...
                summary.existence(labelIdx);
    end
end
end

function valid = isProbabilityThreshold(value)
valid = isscalar(value) && isfinite(value) && value >= 0;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
