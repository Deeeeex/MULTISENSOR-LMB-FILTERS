function [permit, preflight] = ...
    loadFormationStaggeredRecoveryX36OutcomePermit()
% LOADFORMATIONSTAGGEREDRECOVERYX36OUTCOMEPERMIT Load the exact clean gate.

permit = getFormationStaggeredRecoveryX36OutcomePermit();
fixedPreflightPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'formation_value_v37', 'x36_source', 'preflight', ...
    'FORMATION_STAGGERED_RECOVERY_X36_V37_PREFLIGHT.mat');
fixedPreflightSha256 = [ ...
    'de3b17cc5f67427f5c530a6d61232c34bde467ca9d3b93e', ...
    'be9dd577610180d64'];
fixedGenerationCommit = ...
    '57f65d0b860755157a5af7d65be8073bea065574';
fixedPermitSha256 = [ ...
    'bb6ab12c70aecdc3d56633779f7564de9f0644c7a8604331', ...
    'bfeb9a7828bcfbbd'];
if ~isstruct(permit) || ~isscalar(permit) || ...
        ~isfield(permit, 'preflightPath') || ...
        ~strcmp(permit.preflightPath, fixedPreflightPath) || ...
        ~isfield(permit, 'preflightSha256') || ...
        ~strcmp(permit.preflightSha256, fixedPreflightSha256) || ...
        ~isfield(permit, 'preflightGenerationGitCommit') || ...
        ~strcmp(permit.preflightGenerationGitCommit, ...
            fixedGenerationCommit) || ...
        ~isfield(permit, 'permitCanonicalSha256') || ...
        ~strcmp(permit.permitCanonicalSha256, fixedPermitSha256)
    error('X36OutcomePermit:PermitBindingDrift', ...
        'The loader and independent outcome permit disagree.');
end
permitPayload = rmfield(permit, 'permitCanonicalSha256');
try
    actualPermitSha256 = ...
        computeCanonicalValueSha256(permitPayload);
catch
    error('X36OutcomePermit:PermitHashDrift', ...
        'The independent outcome permit cannot be hashed.');
end
if ~strcmp(actualPermitSha256, fixedPermitSha256)
    error('X36OutcomePermit:PermitHashDrift', ...
        'The independent outcome-permit payload changed.');
end

repoRoot = fileparts(fileparts(mfilename('fullpath')));
originalDirectory = cd(repoRoot);
directoryCleanup = onCleanup( ...
    @() cd(originalDirectory)); %#ok<NASGU>
gitState = resolveResearchGitState();
if gitState.trackedWorktreeDirty || ...
        ~isempty(gitState.untrackedSourceFiles)
    error('X36OutcomePermit:DirtySourceRejected', ...
        ['The exact X36 outcome run requires a clean tracked and ', ...
         'MATLAB/Octave source state.']);
end
if isempty(regexp(gitState.commit, '^[0-9a-f]{40}$', 'once'))
    error('X36OutcomePermit:InvalidGitLineage', ...
        'The current Git commit is unavailable or malformed.');
end
[lineageStatus, ~] = system(sprintf( ...
    'git merge-base --is-ancestor %s %s', ...
    fixedGenerationCommit, gitState.commit));
if lineageStatus ~= 0
    error('X36OutcomePermit:InvalidGitLineage', ...
        'The formal preflight commit is not an ancestor of HEAD.');
end

absolutePreflightPath = fullfile(repoRoot, fixedPreflightPath);
if exist(absolutePreflightPath, 'file') ~= 2
    error('X36OutcomePermit:MissingPreflight', ...
        'The fixed formal v2 preflight MAT is unavailable.');
end
actualPreflightSha256 = ...
    computeFileSha256(absolutePreflightPath);
if ~strcmp(actualPreflightSha256, fixedPreflightSha256)
    error('X36OutcomePermit:PreflightHashDrift', ...
        'The fixed formal v2 preflight MAT hash changed.');
end
loaded = load(absolutePreflightPath, 'preflight');
if ~isfield(loaded, 'preflight')
    error('X36OutcomePermit:MalformedPreflight', ...
        'The fixed MAT does not contain a preflight structure.');
end
preflight = loaded.preflight;
validateFormationStaggeredRecoveryX36OutcomePreflight( ...
    preflight, permit);

currentProtocol = ...
    getFormationStaggeredRecoveryX36SourceProtocol();
try
    currentProtocolSha256 = ...
        computeCanonicalValueSha256(currentProtocol);
catch
    error('X36OutcomePermit:SourceProtocolDrift', ...
        'The current source protocol cannot be hashed canonically.');
end
if ~strcmp(currentProtocolSha256, ...
            permit.sourceProtocolCanonicalSha256) || ...
        ~isequaln(currentProtocol, preflight.protocol) || ...
        ~isfield(currentProtocol, ...
            'trackingOutcomeRerunAuthorized') || ...
        ~islogical(currentProtocol. ...
            trackingOutcomeRerunAuthorized) || ...
        ~isscalar(currentProtocol. ...
            trackingOutcomeRerunAuthorized) || ...
        currentProtocol.trackingOutcomeRerunAuthorized
    error('X36OutcomePermit:SourceProtocolDrift', ...
        ['The current source protocol must equal the embedded v2 ', ...
         'protocol and remain tracking-outcome unauthorized.']);
end
end
