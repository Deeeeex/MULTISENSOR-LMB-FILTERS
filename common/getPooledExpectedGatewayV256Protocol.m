function protocol = getPooledExpectedGatewayV256Protocol()
% GETPOOLEDEXPECTEDGATEWAYV256PROTOCOL Seed-block expected action value.

method = getBudgetedLocalGatewayRepairV255Protocol();
teacher = getBudgetedLocalGatewayTeacherV255Protocol();
protocol = struct();
protocol.id = 'pooled-expected-gateway-v256-v1';
protocol.contractVersion = ...
    'pooled-expected-gateway-v256-protocol-v1';
protocol.sourceMethodProtocolId = method.id;
protocol.teacherProtocolId = teacher.id;
protocol.armId = 'v256-pooled-expected-local-gateway';
protocol.policyName = 'pooled-expected-local-gateway-v256-policy';

protocol.preliminaryDevelopmentSeeds = ...
    method.preliminaryDevelopmentSeeds;
protocol.additionalTrainingSeeds = ...
    teacher.additionalTrainingSeeds;
protocol.trainingSeeds = [protocol.preliminaryDevelopmentSeeds, ...
    protocol.additionalTrainingSeeds];
protocol.calibrationSeeds = teacher.calibrationSeeds;
protocol.developmentHoldoutSeeds = teacher.developmentHoldoutSeeds;
protocol.untouchedCompleteEpisodeSeeds = ...
    teacher.untouchedCompleteEpisodeSeeds;
protocol.anchorTimes = teacher.anchorTimes;
protocol.horizonSteps = teacher.horizonSteps;

protocol.actionFeatureContractVersion = ...
    'v256-delta-plus-incumbent-local-action-features-v1';
protocol.actionFeatureTransform = ...
    'candidate-minus-incumbent-concatenated-with-incumbent';
protocol.expectedFeatureCount = 32;
protocol.outcomeNames = method.predictedOutcomeNames;
protocol.predictedOutcomeCount = numel(protocol.outcomeNames);
protocol.predictedCommunicationOutcomeIsDiagnostic = true;
protocol.communicationAdmissionMode = ...
    'deterministic-v255-credit-projection';
protocol.communicationCreditReferenceMode = ...
    'v240-current-physical-two-input-causal-route';
protocol.communicationCreditEstimateMode = ...
    'current-posterior-bytes-times-horizon-plus-one-control-exchange';

protocol.modelFamily = 'pooled-multi-output-ridge';
protocol.seedWeighting = ...
    'equal-seed-equal-anchor-uniform-observed-actions';
protocol.minimumActionsPerWindow = 2 * (4 - 1);
protocol.maximumActionsPerWindow = 2 * 2 * (4 - 1);
protocol.ridgeLambdaGrid = method.ridgeLambdaGrid;
protocol.modelSelectionMode = 'leave-one-training-seed-out';
protocol.modelSelectionActionSupport = ...
    'held-seed-deterministic-communication-feasible-actions';
protocol.modelSelectionSeedAggregation = 'equal-weight-per-held-seed';
protocol.modelSelectionLoss = ...
    'equal-coordinate-standardized-mse-over-seven-tracking-outcomes';
protocol.modelSelectionOutcomeIndices = [1, 2, 3, 5, 6, 7, 8];
protocol.primaryOutcomeIndex = 8;
protocol.lambdaTieBreak = ...
    'lower-primary-standardized-mse-then-larger-lambda';
protocol.outputScaleFloor = 1e-6;
protocol.minimumMeanCvSkillGainPercent = 0;
protocol.minimumPrimaryCvSkillGainPercent = 0;

protocol.uncertaintyMode = ...
    'seed-block-one-sided-overprediction-residual';
protocol.calibrationCandidateAggregation = ...
    'maximum-over-feasible-actions-per-window';
protocol.calibrationQuantileRule = 'nearest-rank-ceil-q-times-n';
protocol.calibrationWithinSeedQuantile = 0.80;
protocol.calibrationAcrossSeedQuantile = 0.80;
protocol.calibrationMarginFloorPercent = 0;
protocol.formalFiniteSampleCoverageClaimAllowed = false;
protocol.receiverRmseActivationLowerBoundPercent = 0.5;
protocol.receiverEospaMinimumLowerBoundPercent = 0;
protocol.minimumExpectedCoreGainPercent = 0;
protocol.maximumFormationRegressionPercent = ...
    method.maximumFormationRegressionPercent;
protocol.communicationCreditFraction = ...
    method.communicationCreditFraction;
protocol.minimumRetainedDenseCausalSavingFraction = ...
    method.minimumRetainedStaticSavingFraction;
protocol.maximumChangedDirectedGatewayArcs = 1;
protocol.maximumCandidatesPerDirectedSlot = ...
    teacher.maximumCandidatesPerDirectedSlot;
protocol.fallbackPolicy = 'v242-causal-minimum-formation-backbone';

protocol.minimumCalibrationSafeSelectionCountPerSeed = 1;
protocol.maximumCalibrationUnsafeSelectionCount = 0;
protocol.minimumHoldoutSafeSelectionCount = 2;
protocol.minimumHoldoutAggregateCoreGainPercent = 0;
protocol.maximumHoldoutFormationRegressionPercent = ...
    method.maximumFormationRegressionPercent;
protocol.maximumHoldoutIncrementalBytesPercentRelativeV242 = ...
    method.developmentIncrementalByteCapPercentRelativeV242;
protocol.completeEpisodeAuthorizedByDefault = false;
protocol.gnnAuthorized = false;
protocol.x36Authorized = false;
protocol.allowedPresets = method.allowedPresets;
protocol.outputRoot = fullfile(method.outputRoot, ...
    'pooled_expected_outcome_v256');
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V256 estimates the conditional paired average effect of one local ', ...
    'gateway replacement from seven M24 training seeds. Ridge ', ...
    'regularization is selected by leave-one-seed-out standardized ', ...
    'prediction error over seven tracking outcomes; attempted-byte ', ...
    'prediction is diagnostic because admission uses the deterministic ', ...
    'V255 communication-credit projection against the current physical ', ...
    'V240 two-input causal route. The projection estimates all three ', ...
    'posterior pages from current payload sizes and charges one controller ', ...
    'exchange; it retains at least 80 percent of the estimated dense-to-', ...
    'V242 saving. Seeds 1311--1312 are used ', ...
    'only for one-sided empirical seed-block margins after the feature ', ...
    'representation and ridge penalty are frozen. Seed 1306 is opened ', ...
    'once for method evaluation and seed 1305 remains untouched for a ', ...
    'complete episode. The small calibration set does not support a ', ...
    'formal finite-sample coverage claim. No result authorizes a GNN, ', ...
    'X36 tuning or paper claim.'];

registered = [protocol.trainingSeeds, protocol.calibrationSeeds, ...
    protocol.developmentHoldoutSeeds, ...
    protocol.untouchedCompleteEpisodeSeeds];
valid = numel(unique(registered)) == numel(registered) && ...
    isequal(protocol.trainingSeeds, ...
        method.expectedOutcomeTrainingSeeds) && ...
    protocol.predictedOutcomeCount == 8 && ...
    numel(protocol.modelSelectionOutcomeIndices) == 7 && ...
    ~ismember(4, protocol.modelSelectionOutcomeIndices) && ...
    protocol.primaryOutcomeIndex == 8 && ...
    protocol.minimumActionsPerWindow == 6 && ...
    protocol.maximumActionsPerWindow == 12 && ...
    strcmp(protocol.seedWeighting, ...
        'equal-seed-equal-anchor-uniform-observed-actions') && ...
    protocol.calibrationWithinSeedQuantile > 0 && ...
    protocol.calibrationWithinSeedQuantile < 1 && ...
    protocol.calibrationAcrossSeedQuantile > 0 && ...
    protocol.calibrationAcrossSeedQuantile < 1 && ...
    strcmp(protocol.calibrationCandidateAggregation, ...
        'maximum-over-feasible-actions-per-window') && ...
    strcmp(protocol.calibrationQuantileRule, ...
        'nearest-rank-ceil-q-times-n') && ...
    protocol.calibrationMarginFloorPercent == 0 && ...
    ~protocol.formalFiniteSampleCoverageClaimAllowed && ...
    protocol.maximumChangedDirectedGatewayArcs == 1 && ...
    protocol.maximumCalibrationUnsafeSelectionCount == 0 && ...
    strcmp(protocol.modelSelectionActionSupport, ...
        'held-seed-deterministic-communication-feasible-actions') && ...
    strcmp(protocol.modelSelectionSeedAggregation, ...
        'equal-weight-per-held-seed') && ...
    strcmp(protocol.communicationCreditReferenceMode, ...
        'v240-current-physical-two-input-causal-route') && ...
    protocol.minimumRetainedDenseCausalSavingFraction == ...
        1 - protocol.communicationCreditFraction && ...
    ~protocol.completeEpisodeAuthorizedByDefault && ...
    ~protocol.gnnAuthorized && ~protocol.x36Authorized;
if ~valid
    error('PooledExpectedGatewayV256:InvalidProtocol', ...
        'The V256 data split, model selection or safety boundary drifted.');
end
end
