function manifest = ...
    buildFormationIndexEquivariantResidualDutyCycleV44ExecutableManifest( ...
        repoRoot)
% Resolve, hash and bind the V44 structural execution chain to HEAD.

if nargin < 1 || isempty(repoRoot)
    repoRoot = fileparts(fileparts(mfilename('fullpath')));
end
repoRoot = char(repoRoot);
[status, topLevel] = system(sprintf( ...
    'git -C "%s" rev-parse --show-toplevel', repoRoot));
if status ~= 0 || ~strcmp(strtrim(topLevel), repoRoot)
    error('FormationResidualDutyCycleV44Manifest:RepoRoot', ...
        'The v44 manifest did not resolve its worktree root.');
end

functionNames = { ...
    'runFormationIndexEquivariantResidualDutyCycleV44Batch', ...
    'getFormationIndexEquivariantResidualDutyCycleV44Protocol', ...
    'buildFormationIndexEquivariantResidualDutyCycleV44ExecutableManifest', ...
    'evaluateFormationIndexEquivariantResidualDutyCycleV44Gate', ...
    'auditFormationIndexEquivariantRouteV43DevelopmentEvidence', ...
    'evaluateFormationIndexEquivariantRouteV43DevelopmentGate', ...
    'getFormationIndexEquivariantRouteV43DevelopmentProtocol', ...
    'buildFormationIndexEquivariantGeometryDevelopmentContext', ...
    'buildDynamicTopologyPhysicalIdentityRegistry', ...
    'buildDynamicTopologyScenarioConfig', ...
    'applyFormationFovSceneStyle', ...
    'computeFormationFovMultistyleSceneContractSha256', ...
    'getExpectedFormationFovMultistyleSceneContractSha256', ...
    'getFormationFovMultistyleAbsoluteDifficultyRequirements', ...
    'generateMultiFormationTrajectories', ...
    'buildDynamicTopologyGraphs', ...
    'buildDynamicTopologyLinkSchedule', ...
    'resolveDynamicTopologyBlockageWindows', ...
