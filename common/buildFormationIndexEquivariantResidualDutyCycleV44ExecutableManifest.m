    'common/computeExpectedEffectiveMixingPageMoments.m', ...
    'common/validateFormationReliableKlaContractionFactor.m', ...
    'multisensorLmb/buildMixtureAwareKlaReferenceConfig.m', ...
    'common/validateReliableKlaMixingRuntimeSemantics.m', ...
    'common/validateReliableKlaCommunicationRuntimeSemantics.m', ...
    'common/permuteFormationIndexEquivariantContext.m', ...
    'common/computeCanonicalValueSha256.m', ...
    'common/computeFileSha256.m', ...
    'common/computeTextSha256.m', ...
    'common/computeBytesSha256.m'};
if numel(functionNames) ~= numel(relativePaths)
    error('FormationResidualDutyCycleV44Manifest:InternalContract', ...
        'The executable registry is inconsistent.');
end

template = struct('functionName', '', 'relativePath', '', ...
    'resolvedPath', '', 'fileSha256', '', 'trackedByHead', false, ...
    'workingBlobId', '', 'headBlobId', '', ...
    'workingFileMatchesHead', false);
records = repmat(template, 1, numel(functionNames));
for functionIdx = 1:numel(functionNames)
    relativePath = relativePaths{functionIdx};
    expectedPath = fullfile(repoRoot, relativePath);
    resolvedPath = which(functionNames{functionIdx});
    if isempty(resolvedPath) || ~strcmp(resolvedPath, expectedPath) || ...
            exist(expectedPath, 'file') ~= 2
        error('FormationResidualDutyCycleV44Manifest:PathShadowing', ...
            'Critical function %s resolved outside the v44 worktree.', ...
            functionNames{functionIdx});
    end
    [trackedStatus, ~] = system(sprintf( ...
        ['git -C "%s" ls-files --error-unmatch -- "%s" ', ...
         '>/dev/null 2>&1'], ...
        repoRoot, relativePath));
    [workingStatus, workingBlob] = system(sprintf( ...
        'git -C "%s" hash-object -- "%s"', repoRoot, relativePath));
    [headStatus, headBlob] = system(sprintf( ...
        'git -C "%s" rev-parse "HEAD:%s" 2>/dev/null', ...
        repoRoot, relativePath));
    if workingStatus ~= 0
        error('FormationResidualDutyCycleV44Manifest:HashFailed', ...
            'Cannot hash executable source %s.', relativePath);
    end
    tracked = trackedStatus == 0 && headStatus == 0;
    workingBlob = strtrim(workingBlob);
    headBlob = strtrim(headBlob);
    records(functionIdx).functionName = functionNames{functionIdx};
    records(functionIdx).relativePath = relativePath;
    records(functionIdx).resolvedPath = resolvedPath;
    records(functionIdx).fileSha256 = computeFileSha256(expectedPath);
    records(functionIdx).trackedByHead = tracked;
    records(functionIdx).workingBlobId = workingBlob;
    records(functionIdx).headBlobId = headBlob;
    records(functionIdx).workingFileMatchesHead = ...
        tracked && strcmp(workingBlob, headBlob);
end

manifest = struct();
manifest.contractVersion = ...
    'formation-index-equivariant-residual-duty-cycle-v44-manifest-v1';
manifest.repoTopLevelVerified = true;
manifest.pathResolutionPassed = true;
manifest.records = records;
manifest.allEntriesTrackedByHead = all([records.trackedByHead]);
manifest.allWorkingFilesMatchHead = ...
    all([records.workingFileMatchesHead]);
manifest.canonicalSha256 = computeCanonicalValueSha256(manifest);
end
