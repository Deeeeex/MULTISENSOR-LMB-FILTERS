function scores = ...
    scoreLabelSetMessagePassingPolicyModel(model, block)
% SCORELABELSETMESSAGEPASSINGPOLICYMODEL Two-round equivariant scorer.
%
% A shared per-label encoder is pooled symmetrically for each candidate
% edge. The base edge embeddings then undergo two directed
% edge-to-node-to-edge rounds. Candidate ordering and label ordering do not
% affect the corresponding output scores.

validateContract(model, block);
candidateCount = size(block.edgeFeatures, 1);
weightCount = size(block.edgeFeatures, 2);
edgeFeatureCount = size(block.edgeFeatures, 3);
nodeCount = size(block.nodeFeatures, 1);
flatEdge = reshape(block.edgeFeatures, ...
    candidateCount * weightCount, edgeFeatureCount);
receiverRows = repmat( ...
    reshape(block.receiverIndices, [], 1), ...
    weightCount, 1);
senderRows = repmat( ...
    reshape(block.senderIndices, [], 1), ...
    weightCount, 1);

edgeZ = applyScaler(flatEdge, ...
    model.edgeFeatureMean, ...
    model.edgeFeatureScale);
nodeZ = applyScaler(block.nodeFeatures, ...
    model.nodeFeatureMean, ...
    model.nodeFeatureScale);
nodeHidden = tanh(bsxfun(@plus, ...
    nodeZ * model.nodeEncoderWeight, ...
    model.nodeEncoderBias));
receiverHidden = nodeHidden(receiverRows, :);
senderHidden = nodeHidden(senderRows, :);

labelEmbedding = encodeLabelSets( ...
    model, block.labelFeatures, block.labelMask);
labelEmbedding = repmat(labelEmbedding, ...
    weightCount, 1);
baseRelational = [ ...
    edgeZ, labelEmbedding, ...
    receiverHidden, senderHidden, ...
    receiverHidden - senderHidden, ...
    receiverHidden .* senderHidden];
expectedBaseWidth = ...
    size(model.baseEdgeEncoderWeight, 1);
if size(baseRelational, 2) ~= expectedBaseWidth
    error('Label-set base relational width changed.');
end
baseHidden = tanh(bsxfun(@plus, ...
    baseRelational * model.baseEdgeEncoderWeight, ...
    model.baseEdgeEncoderBias));

roundZeroContext = poolDirectedNodeContext( ...
    baseHidden, receiverRows, senderRows, nodeCount);
roundOneInput = buildEdgeMessageInput( ...
    baseHidden, roundZeroContext, ...
    receiverRows, senderRows);
roundOneHidden = tanh(bsxfun(@plus, ...
    roundOneInput * model.messageEncoderWeight, ...
    model.messageEncoderBias));

roundOneContext = poolDirectedNodeContext( ...
    roundOneHidden, receiverRows, senderRows, nodeCount);
roundTwoInput = buildEdgeMessageInput( ...
    roundOneHidden, roundOneContext, ...
    receiverRows, senderRows);
flatScores = roundTwoInput * ...
    model.outputWeight + model.outputBias;
if any(~isfinite(flatScores))
    error('Label-set message-passing model produced non-finite scores.');
end
taskScore = reshape(flatScores, ...
    candidateCount, weightCount);
[bestScore, bestWeightIdx] = max(taskScore, [], 2);

scores = struct();
scores.edgeTaskScore = taskScore;
scores.edgeScore = bestScore;
scores.selectedResidualWeightByExample = ...
    reshape(block.residualWeightGrid(bestWeightIdx), [], 1);
scores.baseEdgeEmbedding = reshape(baseHidden, ...
    candidateCount, weightCount, []);
scores.firstRoundEdgeEmbedding = reshape( ...
    roundOneHidden, candidateCount, weightCount, []);
scores.receiverIndices = block.receiverIndices;
scores.senderIndices = block.senderIndices;
scores.residualWeightGrid = block.residualWeightGrid;
scores.truthUsed = false;
scores.groundTruthUsed = false;
scores.futureOutcomeUsed = false;
scores.posteriorUsed = true;
scores.currentLinkReliabilityUsed = true;
scores.numericLabelIdentifiersUsedAsFeatures = false;
scores.permutationInvariantLabelPooling = true;
scores.candidatePermutationEquivariant = true;
end

function embedding = encodeLabelSets(model, features, mask)
candidateCount = size(features, 1);
labelWidth = size(model.labelEncoderWeight, 2);
meanPool = zeros(candidateCount, labelWidth);
scaledSumPool = zeros(candidateCount, labelWidth);
maxPool = zeros(candidateCount, labelWidth);
logCount = zeros(candidateCount, 1);
for candidateIdx = 1:candidateCount
    active = logical(mask(candidateIdx, :));
    count = nnz(active);
    if count < 1
        error('Every residual candidate must expose at least one label.');
    end
    labelX = reshape(features( ...
        candidateIdx, active, :), ...
        count, size(features, 3));
    labelZ = applyScaler(labelX, ...
        model.labelFeatureMean, ...
        model.labelFeatureScale);
    hidden = tanh(bsxfun(@plus, ...
        labelZ * model.labelEncoderWeight, ...
        model.labelEncoderBias));
    meanPool(candidateIdx, :) = mean(hidden, 1);
    scaledSumPool(candidateIdx, :) = ...
        sum(hidden, 1) / sqrt(count);
    maxPool(candidateIdx, :) = max(hidden, [], 1);
    logCount(candidateIdx) = log1p(count);
end
embedding = [ ...
    meanPool, scaledSumPool, maxPool, logCount];
end

function context = poolDirectedNodeContext( ...
        edgeHidden, receiverRows, senderRows, nodeCount)
hiddenWidth = size(edgeHidden, 2);
incomingMean = zeros(nodeCount, hiddenWidth);
incomingMax = zeros(nodeCount, hiddenWidth);
outgoingMean = zeros(nodeCount, hiddenWidth);
outgoingMax = zeros(nodeCount, hiddenWidth);
for nodeIdx = 1:nodeCount
    incoming = edgeHidden(receiverRows == nodeIdx, :);
    outgoing = edgeHidden(senderRows == nodeIdx, :);
    if ~isempty(incoming)
        incomingMean(nodeIdx, :) = mean(incoming, 1);
        incomingMax(nodeIdx, :) = max(incoming, [], 1);
    end
    if ~isempty(outgoing)
        outgoingMean(nodeIdx, :) = mean(outgoing, 1);
        outgoingMax(nodeIdx, :) = max(outgoing, [], 1);
    end
end
context = [ ...
    incomingMean, incomingMax, ...
    outgoingMean, outgoingMax];
end

function input = buildEdgeMessageInput( ...
        edgeHidden, nodeContext, receiverRows, senderRows)
receiver = nodeContext(receiverRows, :);
sender = nodeContext(senderRows, :);
input = [ ...
    edgeHidden, receiver, sender, ...
    receiver - sender, receiver .* sender];
end

function validateContract(model, block)
requiredModel = { ...
    'kind', 'contractVersion', ...
    'edgeFeatureNames', 'nodeFeatureNames', ...
    'labelFeatureNames', ...
    'edgeFeatureMean', 'edgeFeatureScale', ...
    'nodeFeatureMean', 'nodeFeatureScale', ...
    'labelFeatureMean', 'labelFeatureScale', ...
    'labelEncoderWeight', 'labelEncoderBias', ...
    'nodeEncoderWeight', 'nodeEncoderBias', ...
    'baseEdgeEncoderWeight', 'baseEdgeEncoderBias', ...
    'messageEncoderWeight', 'messageEncoderBias', ...
    'outputWeight', 'outputBias', ...
    'featuresUseTruth', ...
    'numericLabelIdentifiersUsedAsFeatures'};
requiredBlock = { ...
    'edgeFeatures', 'edgeFeatureNames', ...
    'nodeFeatures', 'nodeFeatureNames', ...
    'labelFeatures', 'labelMask', ...
    'labelFeatureNames', 'receiverIndices', ...
    'senderIndices', 'residualWeightGrid', ...
    'truthUsed', 'futureOutcomeUsed', ...
    'numericLabelIdentifiersUsedAsFeatures'};
protocol = getLabelSetSimulatorPolicyProtocol();
if ~isstruct(model) || ...
        ~all(isfield(model, requiredModel)) || ...
        ~isstruct(block) || ...
        ~all(isfield(block, requiredBlock)) || ...
        ~strcmp(model.kind, ...
            'label-set-message-passing-policy') || ...
        ~strcmp(model.contractVersion, ...
            protocol.messagePassingModelContractVersion) || ...
        ~isequal(model.edgeFeatureNames, ...
            reshape(block.edgeFeatureNames, 1, [])) || ...
        ~isequal(model.nodeFeatureNames, ...
            reshape(block.nodeFeatureNames, 1, [])) || ...
        ~isequal(model.labelFeatureNames, ...
            reshape(block.labelFeatureNames, 1, [])) || ...
        model.featuresUseTruth || ...
        model.numericLabelIdentifiersUsedAsFeatures || ...
        block.truthUsed || block.futureOutcomeUsed || ...
        block.numericLabelIdentifiersUsedAsFeatures || ...
        any(~isfinite(block.edgeFeatures(:))) || ...
        any(~isfinite(block.nodeFeatures(:))) || ...
        any(~isfinite(block.labelFeatures(:))) || ...
        ~isequal(size(block.labelMask), ...
            size(block.labelFeatures(:, :, 1))) || ...
        numel(block.receiverIndices) ~= ...
            size(block.edgeFeatures, 1) || ...
        numel(block.senderIndices) ~= ...
            size(block.edgeFeatures, 1) || ...
        numel(block.residualWeightGrid) ~= ...
            size(block.edgeFeatures, 2)
    error('Label-set message-passing model/feature contract mismatch.');
end
parameterFields = { ...
    'edgeFeatureMean', 'edgeFeatureScale', ...
    'nodeFeatureMean', 'nodeFeatureScale', ...
    'labelFeatureMean', 'labelFeatureScale', ...
    'labelEncoderWeight', 'labelEncoderBias', ...
    'nodeEncoderWeight', 'nodeEncoderBias', ...
    'baseEdgeEncoderWeight', 'baseEdgeEncoderBias', ...
    'messageEncoderWeight', 'messageEncoderBias', ...
    'outputWeight', 'outputBias'};
for fieldIdx = 1:numel(parameterFields)
    if any(~isfinite(model.(parameterFields{fieldIdx})(:)))
        error('Label-set message-passing model has non-finite parameters.');
    end
end
end

function Z = applyScaler(X, meanValue, scaleValue)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, meanValue), scaleValue);
end
