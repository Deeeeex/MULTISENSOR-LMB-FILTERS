assertExactFields(permit, { ...
    'id', 'contractVersion', 'authorizedRunnerContractVersion', ...
    'sourceProtocolContractVersion', ...
    'sourceProtocolCanonicalSha256', ...
    'preflightContractVersion', 'preflightPath', ...
    'preflightSha256', 'preflightGenerationGitCommit', ...
    'pairProposalContractVersion', 'authorizedPairIds', ...
    'authorizedPairProposalCanonicalSha256', ...
    'authorizedPairCount', 'exactArmCountPerPair', ...
    'maximumPairedRunCountPerPair', ...
    'maximumOfficialAggregateRunCount', ...
    'referenceArmId', 'candidateArmId', ...
    'referenceArmOrdinal', 'candidateArmOrdinal', ...
    'sourceProtocolMustRemainTrackingUnauthorized', ...
    'preflightMustRemainTrackingUnauthorized', ...
    'trackingOutcomeRerunAuthorized', ...
    'x36PairedOutcomeRerunAuthorized', ...
    'unrestrictedX36OutcomeOpeningAuthorized', ...
    'overwriteExistingOfficialOutputAuthorized', ...
    'outcomeSelectionOrRankingAuthorized', ...
    'gnnTrainingAuthorized', 'x48OutcomeOpeningAuthorized', ...
    'reservedSeedOpeningAuthorized', 'validationClaimAllowed', ...
    'developmentEvidenceOnly', 'evidenceBoundary', ...
    'permitCanonicalSha256'}, ...
    'X36OutcomePermit:PermitShapeDrift', ...
    'The exact outcome-permit field set changed.');
expectedPermitSha256 = [ ...
    'bb6ab12c70aecdc3d56633779f7564de9f0644c7a8604331', ...
    'bfeb9a7828bcfbbd'];
permitPayload = rmfield(permit, 'permitCanonicalSha256');
try
    actualPermitSha256 = ...
        computeCanonicalValueSha256(permitPayload);
catch
    error('X36OutcomePermit:PermitHashDrift', ...
        'The outcome permit contains an unsupported value.');
end
if ~isSha256(permit.permitCanonicalSha256) || ...
        ~strcmp(permit.permitCanonicalSha256, ...
            expectedPermitSha256) || ...
