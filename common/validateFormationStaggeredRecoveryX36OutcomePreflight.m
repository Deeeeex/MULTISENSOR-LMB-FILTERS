function validateFormationStaggeredRecoveryX36OutcomePreflight( ...
        preflight, permit)
% VALIDATEFORMATIONSTAGGEREDRECOVERYX36OUTCOMEPREFLIGHT Pure v2 gate.

if ~isstruct(preflight) || ~isscalar(preflight) || ...
        ~isstruct(permit) || ~isscalar(permit)
    error('X36OutcomePermit:InvalidStructure', ...
        'The permit and preflight must be scalar structures.');
end
validatePermit(permit);
assertExactFields(preflight, { ...
    'contractVersion', 'generatedAt', 'generationGitCommit', ...
    'generationTrackedWorktreeDirty', ...
    'generationUntrackedSourceFiles', 'protocol', ...
    'fingerprintDiscoveryMode', 'm24ScreenPath', ...
    'm24ScreenSha256', 'm24ScreenGenerationCommit', ...
    'sceneAuditPath', 'sceneAuditSha256', ...
    'sceneAuditGenerationCommit', 'states', 'anchorTimes', ...
    'runtimeFingerprintSha256ByState', 'pairProposals', ...
    'pairedOutcomeEligibilityMask', 'eligibleStateCount', ...
    'eligiblePairs', 'x36PairedOutcomePermitMayBeMinted', ...
    'x36PairedOutcomeRerunAuthorized', ...
    'maximumAuthorizedPairCount', 'maximumEligiblePairCount', ...
    'separateHashedOutcomePermitRequired', ...
    'trackingOutcomeScored', 'newPosteriorStateOpened', ...
    'outcomeRankingUsesTruth', ...
    'scenarioTruthRemovedBeforePolicyConstruction', ...
    'scenarioTruthFieldsRemovedBeforePolicyConstruction', ...
    'cacheOutcomeFieldsEmpty', 'gnnTrainingAuthorized', ...
    'x48Opened', 'reservedSeedOpened', ...
    'validationClaimAllowed', 'outcomePermitBoundary', ...
    'evidenceBoundary', 'matPath', 'reportPath'}, ...
    'X36OutcomePermit:PreflightShapeDrift', ...
    'The formal preflight field set changed.');

if ~ischar(preflight.contractVersion) || ...
        ~strcmp(preflight.contractVersion, ...
            permit.preflightContractVersion)
    error('X36OutcomePermit:PreflightContractMismatch', ...
        'Only the frozen v2 preflight contract is accepted.');
end
if ~ischar(preflight.matPath) || ...
        ~strcmp(preflight.matPath, permit.preflightPath)
    error('X36OutcomePermit:PreflightPathMismatch', ...
        'The preflight is not the fixed formal artifact.');
end
expectedReportPath = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', ...
    'FORMATION_STAGGERED_RECOVERY_X36_V37_PREFLIGHT_20260802.md');
if ~ischar(preflight.reportPath) || ...
        ~strcmp(preflight.reportPath, expectedReportPath)
    error('X36OutcomePermit:PreflightPathMismatch', ...
        'A discovery or revoked report cannot authorize outcomes.');
end
if ~ischar(preflight.generationGitCommit) || ...
        ~strcmp(preflight.generationGitCommit, ...
            permit.preflightGenerationGitCommit)
    error('X36OutcomePermit:PreflightGenerationDrift', ...
        'The preflight generation commit changed.');
end
if ~isFalse(preflight.fingerprintDiscoveryMode)
    error('X36OutcomePermit:DiscoveryArtifactRejected', ...
        'Fingerprint-discovery artifacts cannot authorize outcomes.');
end
if ~isFalse(preflight.generationTrackedWorktreeDirty) || ...
        ~iscell(preflight.generationUntrackedSourceFiles) || ...
        ~isempty(preflight.generationUntrackedSourceFiles)
    error('X36OutcomePermit:DirtyPreflightRejected', ...
        'A dirty-source preflight cannot authorize outcomes.');
end

validateEmbeddedSourceProtocol(preflight.protocol, permit);
if ~isTrue(preflight.x36PairedOutcomePermitMayBeMinted) || ...
        ~isFalse(preflight.x36PairedOutcomeRerunAuthorized) || ...
        ~isTrue(preflight.separateHashedOutcomePermitRequired) || ...
        ~isZeroScalar(preflight.maximumAuthorizedPairCount) || ...
        ~isExactScalar(preflight.maximumEligiblePairCount, ...
            permit.authorizedPairCount) || ...
        ~isExactScalar(preflight.eligibleStateCount, ...
            permit.authorizedPairCount)
    error('X36OutcomePermit:PreflightAuthorizationMismatch', ...
        ['The source-only preflight must remain unauthorized while ', ...
         'making exactly three pairs permit-eligible.']);
end
if ~isFalse(preflight.trackingOutcomeScored) || ...
        ~isFalse(preflight.newPosteriorStateOpened) || ...
        ~isFalse(preflight.outcomeRankingUsesTruth) || ...
        ~isTrue(preflight. ...
            scenarioTruthRemovedBeforePolicyConstruction) || ...
        ~isequal(preflight. ...
            scenarioTruthFieldsRemovedBeforePolicyConstruction, ...
            {'groundTruth', 'groundTruthRfs', ...
             'targetTrajectories'}) || ...
        ~isTrue(preflight.cacheOutcomeFieldsEmpty) || ...
        ~isFalse(preflight.gnnTrainingAuthorized) || ...
        ~isFalse(preflight.x48Opened) || ...
        ~isFalse(preflight.reservedSeedOpened) || ...
        ~isFalse(preflight.validationClaimAllowed)
    error('X36OutcomePermit:PreflightBoundaryViolation', ...
        'The source-only truth and research-scope boundary changed.');
end

anchorTimes = [72, 100, 128];
if ~isequal(preflight.anchorTimes, anchorTimes) || ...
        ~isequal(size(preflight.pairedOutcomeEligibilityMask), ...
            [1, permit.authorizedPairCount]) || ...
        ~islogical(preflight.pairedOutcomeEligibilityMask) || ...
        ~all(preflight.pairedOutcomeEligibilityMask) || ...
        ~isequal(size(preflight.pairProposals), ...
            [1, permit.authorizedPairCount]) || ...
        ~isequal(size(preflight.eligiblePairs), ...
            [1, permit.authorizedPairCount]) || ...
        ~isequal(size(preflight.states), ...
            [1, permit.authorizedPairCount])
    error('X36OutcomePermit:PairSetDrift', ...
        'The exact ordered three-pair set changed.');
end

expectedFingerprints = preflight.protocol. ...
    expectedRuntimeFingerprintSha256;
if ~isequal(preflight.runtimeFingerprintSha256ByState, ...
        expectedFingerprints)
    error('X36OutcomePermit:RuntimeFingerprintDrift', ...
        'The ordered runtime-fingerprint set changed.');
end
for pairIdx = 1:permit.authorizedPairCount
    validatePairProposal(preflight.pairProposals(pairIdx), ...
        pairIdx, preflight.protocol, permit);
    if ~isequaln(preflight.eligiblePairs(pairIdx), ...
            preflight.pairProposals(pairIdx))
        error('X36OutcomePermit:EligiblePairDrift', ...
            'Eligible-pair records must equal the frozen proposals.');
    end
    validateSourceState(preflight.states(pairIdx), ...
        preflight.pairProposals(pairIdx), ...
        preflight.protocol);
end
end

