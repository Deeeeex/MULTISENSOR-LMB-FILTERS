end

expectedPairIds = { ...
    'x36-seed211-t72-reference-vs-v35-h3', ...
    'x36-seed211-t100-reference-vs-v35-h3', ...
    'x36-seed211-t128-reference-vs-v35-h3'};
expectedPairSha256 = { ...
    ['689b1655c7e398e978efcb80d8b567897b5374e513e3ac70', ...
     '43c97586130e1c59'], ...
    ['4850d890465417f7167e782ff02a1b093c9d2f96cfba0771', ...
     '4d256b1e4562f1ae'], ...
    ['1c941e9ff49123899360065f4d0dc2599fc2de07c121f90d', ...
     'f60cce7fe9a791cd']};
if ~strcmp(permit.id, ...
            'formation-staggered-recovery-x36-v37-outcome-permit-v1') || ...
        ~strcmp(permit.contractVersion, ...
            'formation-staggered-recovery-x36-outcome-permit-v1') || ...
        ~strcmp(permit.authorizedRunnerContractVersion, [ ...
            'formation-staggered-recovery-x36-v37-', ...
            'exact-two-arm-runner-v1']) || ...
        ~strcmp(permit.sourceProtocolContractVersion, ...
            'formation-staggered-recovery-x36-source-protocol-v2') || ...
        ~strcmp(permit.sourceProtocolCanonicalSha256, [ ...
            '04c1fae3dcbc72872f5659bc8c502e39f0e1c27122b244be', ...
            '524e84054668e8b6']) || ...
        ~strcmp(permit.preflightContractVersion, ...
            'formation-staggered-recovery-x36-v37-preflight-v2') || ...
        ~strcmp(permit.preflightPath, fullfile( ...
            'RUN', 'GA', 'dynamic_topology', 'evidence', ...
            'formation_value_v37', 'x36_source', 'preflight', ...
            'FORMATION_STAGGERED_RECOVERY_X36_V37_PREFLIGHT.mat')) || ...
        ~strcmp(permit.preflightSha256, [ ...
            'de3b17cc5f67427f5c530a6d61232c34bde467ca9d3b93e', ...
