function validateEmbeddedSourceProtocol(protocol, permit)
if ~isstruct(protocol) || ~isscalar(protocol)
    error('X36OutcomePermit:SourceProtocolDrift', ...
        'The embedded source protocol is malformed.');
end
try
    protocolSha256 = computeCanonicalValueSha256(protocol);
catch
    error('X36OutcomePermit:SourceProtocolDrift', ...
        'The embedded source protocol cannot be hashed canonically.');
end
if ~strcmp(protocolSha256, ...
            permit.sourceProtocolCanonicalSha256) || ...
        ~isfield(protocol, 'contractVersion') || ...
        ~strcmp(protocol.contractVersion, ...
            permit.sourceProtocolContractVersion) || ...
        ~isfield(protocol, 'trackingOutcomeRerunAuthorized') || ...
        ~isFalse(protocol.trackingOutcomeRerunAuthorized) || ...
        ~isfield(protocol, ...
            'trackingOutcomeEligibilityAfterCleanPreflight') || ...
        ~isTrue(protocol. ...
            trackingOutcomeEligibilityAfterCleanPreflight) || ...
        ~isfield(protocol, ...
            'x36PairedOutcomeRerunRequiresCleanPreflight') || ...
        ~isTrue(protocol. ...
            x36PairedOutcomeRerunRequiresCleanPreflight) || ...
        ~isfield(protocol, 'runtimeFingerprintFreezePending') || ...
        ~isFalse(protocol.runtimeFingerprintFreezePending) || ...
        ~isfield(protocol, 'gnnTrainingAuthorized') || ...
        ~isFalse(protocol.gnnTrainingAuthorized) || ...
        ~isfield(protocol, 'x36OutcomeOpeningAuthorized') || ...
        ~isFalse(protocol.x36OutcomeOpeningAuthorized) || ...
        ~isfield(protocol, 'x48OutcomeOpeningAuthorized') || ...
        ~isFalse(protocol.x48OutcomeOpeningAuthorized) || ...
        ~isfield(protocol, 'validationClaimAllowed') || ...
        ~isFalse(protocol.validationClaimAllowed)
    error('X36OutcomePermit:SourceProtocolDrift', ...
        ['The embedded source protocol must be frozen v2 and remain ', ...
         'tracking-outcome unauthorized.']);
end
end

function validatePairProposal(proposal, pairIdx, protocol, permit)
if ~isstruct(proposal) || ~isscalar(proposal)
    error('X36OutcomePermit:PairProposalDrift', ...
        'A pair proposal is malformed.');
end
assertExactFields(proposal, { ...
    'contractVersion', 'pairId', 'eligible', 'presetName', ...
    'seed', 'anchorTime', 'returnTimes', 'horizonSteps', ...
    'blockageFormationPair', 'cachePath', 'cacheSha256', ...
    'referenceArmId', 'referenceInitialActionIndex', ...
    'referenceNominalActionSequenceIndices', 'candidateArmId', ...
    'candidateInitialActionIndex', ...
    'candidateNominalActionSequenceIndices', ...
    'candidateRuntimeFingerprintSha256', ...
    'maximumPairedRunCount', 'trackingOutcomeScored'}, ...
    'X36OutcomePermit:PairProposalDrift', ...
    'A pair-proposal field set changed.');
try
    proposalSha256 = computeCanonicalValueSha256(proposal);
catch
    error('X36OutcomePermit:PairProposalDrift', ...
        'A pair proposal cannot be hashed canonically.');
end
anchorTime = protocol.anchorTimes(pairIdx);
initialAction = protocol.expectedInitialActionIndices(pairIdx);
expectedCachePath = fullfile(protocol.cacheRoot, sprintf( ...
    '%s_seed%d_n1_sig%d.mat', ...
    strrep(protocol.presetName, '-', '_'), ...
    protocol.seed, anchorTime));
if ~strcmp(proposalSha256, permit. ...
            authorizedPairProposalCanonicalSha256{pairIdx}) || ...
        ~strcmp(proposal.contractVersion, ...
            permit.pairProposalContractVersion) || ...
        ~strcmp(proposal.pairId, ...
            permit.authorizedPairIds{pairIdx}) || ...
        ~isTrue(proposal.eligible) || ...
        ~strcmp(proposal.presetName, protocol.presetName) || ...
        ~isExactScalar(proposal.seed, protocol.seed) || ...
        ~isExactScalar(proposal.anchorTime, anchorTime) || ...
        ~isequal(proposal.returnTimes, ...
            anchorTime + (0:(protocol.horizonSteps - 1))) || ...
        ~isExactScalar(proposal.horizonSteps, ...
            protocol.horizonSteps) || ...
        ~isequal(proposal.blockageFormationPair, ...
            protocol.blockageFormationPairs(pairIdx, :)) || ...
        ~strcmp(proposal.cachePath, expectedCachePath) || ...
        ~strcmp(proposal.cacheSha256, ...
            protocol.expectedCacheSha256{pairIdx}) || ...
        ~strcmp(proposal.referenceArmId, permit.referenceArmId) || ...
        ~isExactScalar(proposal.referenceInitialActionIndex, 1) || ...
        ~isequal(proposal. ...
            referenceNominalActionSequenceIndices, ...
            ones(1, protocol.horizonSteps)) || ...
        ~strcmp(proposal.candidateArmId, permit.candidateArmId) || ...
        ~isExactScalar(proposal.candidateInitialActionIndex, ...
            initialAction) || ...
        ~isequal(proposal. ...
            candidateNominalActionSequenceIndices, ...
            [initialAction, ones(1, protocol.horizonSteps - 1)]) || ...
        ~strcmp(proposal.candidateRuntimeFingerprintSha256, ...
            protocol.expectedRuntimeFingerprintSha256{pairIdx}) || ...
        ~isExactScalar(proposal.maximumPairedRunCount, 1) || ...
        ~isFalse(proposal.trackingOutcomeScored)
    error('X36OutcomePermit:PairProposalDrift', ...
        'A frozen pair proposal changed or was reordered.');
end
end

function validateSourceState(state, proposal, protocol)
if ~isstruct(state) || ~isscalar(state)
    error('X36OutcomePermit:SourceStateDrift', ...
        'A source-only state is malformed.');
end
assertExactFields(state, { ...
    'anchorTime', 'blockageFormationPair', 'cachePath', ...
    'cacheSha256', 'cacheGenerationGitCommit', ...
    'initialControlConstructionSeconds', 'runtimeReplaySeconds', ...
    'initialControl', 'initialActionIndex', 'runtimeReplay', ...
    'runtimeFingerprintSha256', 'explicitStaggeredReleaseCount', ...
    'runtimeReplayPassed', 'trackingOutcomeScored', 'truthUsed', ...
    'futureOutcomeUsed'}, ...
    'X36OutcomePermit:SourceStateDrift', ...
    'A source-only state field set changed.');
if ~isExactScalar(state.anchorTime, proposal.anchorTime) || ...
        ~isequal(state.blockageFormationPair, ...
            proposal.blockageFormationPair) || ...
        ~strcmp(state.cachePath, proposal.cachePath) || ...
        ~strcmp(state.cacheSha256, proposal.cacheSha256) || ...
        ~strcmp(state.cacheGenerationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~isExactScalar(state.initialActionIndex, ...
            proposal.candidateInitialActionIndex) || ...
        ~strcmp(state.runtimeFingerprintSha256, ...
            proposal.candidateRuntimeFingerprintSha256) || ...
        ~isTrue(state.runtimeReplayPassed) || ...
        ~isFalse(state.trackingOutcomeScored) || ...
        ~isFalse(state.truthUsed) || ~isFalse(state.futureOutcomeUsed) || ...
        ~isstruct(state.initialControl) || ...
        ~isscalar(state.initialControl) || ...
        ~isfield(state.initialControl, 'referenceFallbackUsed') || ...
        ~isFalse(state.initialControl.referenceFallbackUsed) || ...
        ~isfield(state.initialControl, 'truthUsed') || ...
        ~isFalse(state.initialControl.truthUsed) || ...
        ~isfield(state.initialControl, 'futureOutcomeUsed') || ...
        ~isFalse(state.initialControl.futureOutcomeUsed) || ...
        ~isstruct(state.runtimeReplay) || ...
        ~isscalar(state.runtimeReplay) || ...
        ~isfield(state.runtimeReplay, 'runtimeFingerprintSha256') || ...
        ~strcmp(state.runtimeReplay.runtimeFingerprintSha256, ...
            proposal.candidateRuntimeFingerprintSha256) || ...
        ~isfield(state.runtimeReplay, 'trackingOutcomeScored') || ...
        ~isFalse(state.runtimeReplay.trackingOutcomeScored) || ...
        ~isfield(state.runtimeReplay, 'truthUsed') || ...
        ~isFalse(state.runtimeReplay.truthUsed) || ...
        ~isfield(state.runtimeReplay, 'futureOutcomeUsed') || ...
        ~isFalse(state.runtimeReplay.futureOutcomeUsed) || ...
        ~isfield(state.runtimeReplay, 'groundTruthAccessed') || ...
        ~isFalse(state.runtimeReplay.groundTruthAccessed)
    error('X36OutcomePermit:SourceStateDrift', ...
        'A source state no longer matches its frozen pair proposal.');
end
end

function assertExactFields(value, expectedFields, identifier, message)
actualFields = sort(fieldnames(value));
expectedFields = sort(reshape(expectedFields, [], 1));
if ~isequal(actualFields, expectedFields)
    error(identifier, message);
end
end

function result = isTrue(value)
result = islogical(value) && isscalar(value) && value;
end

function result = isFalse(value)
result = islogical(value) && isscalar(value) && ~value;
end

function result = isZeroScalar(value)
result = isExactScalar(value, 0);
end

function result = isExactScalar(value, expected)
result = isa(value, 'double') && isscalar(value) && ...
    isfinite(value) && value == expected;
end

function result = isSha256(value)
result = ischar(value) && isrow(value) && ...
    ~isempty(regexp(value, '^[0-9a-f]{64}$', 'once'));
end
