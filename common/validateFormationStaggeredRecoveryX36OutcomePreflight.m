        ~isFalse(proposal.trackingOutcomeScored)
    error('X36OutcomePermit:PairProposalDrift', ...
        'A frozen v3 pair proposal changed or was reordered.');
end
end

function validateSourceState(state, proposal, stateIdx, protocol, permit)
assertExactFields(state, { ...
    'anchorTime', 'blockageFormationPair', 'cachePath', ...
    'cacheSha256', 'cacheGenerationGitCommit', ...
    'initialControlConstructionSeconds', ...
    'runtimeReplaySecondsByArm', 'initialControl', ...
    'candidateInitialActionIndex', 'runtimeReplays', ...
    'runtimeFingerprintSha256ByArm', ...
    'explicitStaggeredReleaseCount', ...
    'runtimeReplayPassedByArm', 'trackingOutcomeScored', ...
    'truthUsed', 'futureOutcomeUsed'}, ...
    'X36OutcomePermit:SourceStateDrift', ...
    'A v3 source-only state field set changed.');
if ~isExactScalar(state.anchorTime, proposal.anchorTime) || ...
        ~isequal(state.blockageFormationPair, ...
            proposal.blockageFormationPair) || ...
        ~strcmp(state.cachePath, proposal.cachePath) || ...
        ~strcmp(state.cacheSha256, proposal.cacheSha256) || ...
        ~strcmp(state.cacheGenerationGitCommit, ...
            protocol.cacheGenerationGitCommit) || ...
        ~isExactScalar(state.candidateInitialActionIndex, ...
            proposal.candidateInitialActionIndex) || ...
        ~isequal(state.runtimeFingerprintSha256ByArm, ...
            proposal.runtimeFingerprintSha256ByArm) || ...
        ~iscell(state.runtimeReplays) || ...
        ~isequal(size(state.runtimeReplays), [1, 2]) || ...
        ~islogical(state.runtimeReplayPassedByArm) || ...
        ~isequal(state.runtimeReplayPassedByArm, true(1, 2)) || ...
        ~isnumeric(state.runtimeReplaySecondsByArm) || ...
        ~isequal(size(state.runtimeReplaySecondsByArm), [1, 2]) || ...
        any(~isfinite(state.runtimeReplaySecondsByArm)) || ...
        any(state.runtimeReplaySecondsByArm <= 0) || ...
        ~isFalse(state.trackingOutcomeScored) || ...
        ~isFalse(state.truthUsed) || ~isFalse(state.futureOutcomeUsed) || ...
        ~isstruct(state.initialControl) || ...
        ~isscalar(state.initialControl) || ...
        ~isfield(state.initialControl, 'referenceFallbackUsed') || ...
        ~isFalse(state.initialControl.referenceFallbackUsed) || ...
        ~isfield(state.initialControl, 'selectedScore') || ...
        ~isstruct(state.initialControl.selectedScore) || ...
        ~isfield(state.initialControl.selectedScore, 'safe') || ...
        ~isTrue(state.initialControl.selectedScore.safe) || ...
        ~isfield(state.initialControl, 'truthUsed') || ...
        ~isFalse(state.initialControl.truthUsed) || ...
        ~isfield(state.initialControl, 'futureOutcomeUsed') || ...
        ~isFalse(state.initialControl.futureOutcomeUsed)
    error('X36OutcomePermit:SourceStateDrift', ...
        'A v3 source state no longer matches its pair proposal.');
end
for armIdx = 1:2
    validateRuntimeReplay(state.runtimeReplays{armIdx}, ...
        proposal, stateIdx, armIdx, protocol, permit);
end
end

function validateRuntimeReplay(replay, proposal, stateIdx, ...
        armIdx, protocol, permit)
assertExactFields(replay, { ...
    'contractVersion', 'armId', 'armOrdinal', 'runtimeSemantics', ...
    'posteriorUseRequired', 'currentLinkUseRequired', ...
    'returnTimes', 'actionSequenceIndices', 'selectedAdjacency', ...
    'selectedFusionWeightsByTime', 'policyBackboneModeByTime', ...
    'attemptedBytesByTime', 'retentionDebtFractionByTime', ...
    'retentionDebtThresholdByTime', ...
    'retentionDebtSingleAvailableMaskByTime', ...
    'retentionDebtSingleSafetyMaskByTime', ...
    'retentionDebtRequestedFormationIdsByTime', ...
    'retentionDebtSelectedFormationIdsByTime', ...
    'retentionDebtProjectionRemovalOrderByTime', ...
    'staggeredRecoveryScheduleByTime', ...
    'reserveProposalFormationAdjacencyByTime', ...
    'referenceNetworkRiskByTime', 'selectedNetworkRiskByTime', ...
    'referenceFallbackCountByTime', 'evaluatedActionCountByTime', ...
    'safeActionCountByTime', 'oneStepReservePassedByTime', ...
    'posteriorContentUsedByTime', ...
    'currentLinkReliabilityUsedByTime', ...
    'observableContextOnlyByTime', ...
    'observableInputContractByTime', ...
    'selectedSensorB3Pass', 'selectedFormationB3Pass', ...
    'executedActionIndicesByTime', 'policyHistoryCountByTime', ...
    'policyHistoryTimesByTime', 'firstActionExact', ...
    'firstFusionWeightsExact', 'truthUsed', 'futureOutcomeUsed', ...
    'trackingOutcomeScored', 'groundTruthAccessed', ...
    'runtimeFingerprint', 'runtimeFingerprintSha256'}, ...
    'X36OutcomePermit:RuntimeReplayDrift', ...
    'A v3 runtime-replay field set changed.');
expectedFingerprint = permit. ...
    authorizedRuntimeFingerprintSha256ByStateArm{stateIdx, armIdx};
expectedArmId = permit.referenceArmId;
expectedSemantics = 'fixed-reference';
expectedActionSequence = ...
    proposal.referenceNominalActionSequenceIndices;
expectedUse = false;
if armIdx == permit.candidateArmOrdinal
    expectedArmId = permit.candidateArmId;
    expectedSemantics = 'causal-staggered-recovery';
    expectedActionSequence = ...
        proposal.candidateNominalActionSequenceIndices;
    expectedUse = true;
end
try
    rebuiltFingerprint = ...
        buildFormationStaggeredRecoveryRuntimeFingerprint(replay);
    rebuiltSha256 = ...
        computeCanonicalValueSha256(rebuiltFingerprint);
catch
    error('X36OutcomePermit:RuntimeReplayDrift', ...
        'A v3 runtime replay cannot be fingerprinted.');
end
if ~strcmp(replay.contractVersion, ...
            'formation-staggered-recovery-v35-source-replay-v2') || ...
        ~strcmp(replay.armId, expectedArmId) || ...
        ~isExactScalar(replay.armOrdinal, armIdx) || ...
        ~strcmp(replay.runtimeSemantics, expectedSemantics) || ...
        ~isequal(replay.posteriorUseRequired, expectedUse) || ...
        ~isequal(replay.currentLinkUseRequired, expectedUse) || ...
        ~isequal(replay.returnTimes, proposal.returnTimes) || ...
        ~isequal(replay.actionSequenceIndices, ...
            expectedActionSequence) || ...
        ~strcmp(replay.runtimeFingerprintSha256, ...
            expectedFingerprint) || ...
        ~strcmp(rebuiltSha256, expectedFingerprint) || ...
        ~isequaln(replay.runtimeFingerprint, rebuiltFingerprint) || ...
        ~islogical(replay.posteriorContentUsedByTime) || ...
        ~isequal(replay.posteriorContentUsedByTime, ...
            repmat(expectedUse, 1, protocol.horizonSteps)) || ...
        ~islogical(replay.currentLinkReliabilityUsedByTime) || ...
        ~isequal(replay.currentLinkReliabilityUsedByTime, ...
            repmat(expectedUse, 1, protocol.horizonSteps)) || ...
        ~all(replay.observableContextOnlyByTime) || ...
        ~all(replay.selectedSensorB3Pass) || ...
        ~all(replay.selectedFormationB3Pass) || ...
        ~isTrue(replay.firstActionExact) || ...
        ~isTrue(replay.firstFusionWeightsExact) || ...
        ~isFalse(replay.truthUsed) || ...
        ~isFalse(replay.futureOutcomeUsed) || ...
        ~isFalse(replay.trackingOutcomeScored) || ...
        ~isFalse(replay.groundTruthAccessed)
    error('X36OutcomePermit:RuntimeReplayDrift', ...
        'A v3 runtime replay changed its arm or causal semantics.');
end
if ~iscell(replay.observableInputContractByTime) || ...
        numel(replay.observableInputContractByTime) ~= ...
            protocol.horizonSteps
    error('X36OutcomePermit:RuntimeReplayDrift', ...
        'The observable-input attestation count changed.');
end
for timeIdx = 1:protocol.horizonSteps
    contract = replay.observableInputContractByTime{timeIdx};
    if ~isstruct(contract) || ~isscalar(contract) || ...
            ~strcmp(contract.contractVersion, ...
                'topology-policy-observable-input-v2') || ...
            ~isTrue(contract.enforced) || ...
            ~isTrue(contract.passed) || ...
            ~isTrue(contract.targetTruthAbsent) || ...
            ~isTrue(contract.linkUniformsAbsent) || ...
            ~isTrue(contract.futurePDropPagesAbsent) || ...
            ~isTrue(contract.sensorTrajectoriesAbsent) || ...
            ~isTrue(contract.posteriorSchemaRestricted) || ...
            ~isTrue(contract.contextHasNoFunctionHandles) || ...
            ~isTrue(contract.contextUsesPrimitiveContainersOnly) || ...
            contract.currentTime ~= proposal.returnTimes(timeIdx)
        error('X36OutcomePermit:RuntimeReplayDrift', ...
            'A v3 observable-input attestation changed.');
    end
end
end

function assertExactFields(value, expectedFields, identifier, message)
actualFields = sort(fieldnames(value));
expectedFields = sort(reshape(expectedFields, [], 1));
if ~isequal(actualFields, expectedFields)
    error(identifier, message);
end
end

function result = isTrue(value)
result = islogical(value) && isscalar(value) && value;
end

function result = isFalse(value)
result = islogical(value) && isscalar(value) && ~value;
end

function result = isZeroScalar(value)
result = isExactScalar(value, 0);
end

function result = isExactScalar(value, expected)
result = isa(value, 'double') && isscalar(value) && ...
    isfinite(value) && value == expected;
end

function result = isSha256(value)
result = ischar(value) && isrow(value) && ...
    ~isempty(regexp(value, '^[0-9a-f]{64}$', 'once'));
end
