    'publicationCompletionContractVersion', ...
    'publicationCompletionMarkerRequired', ...
    'publicationCompletionMarkerPath'}, ...
    'X36OutcomePermit:PreflightShapeDrift', ...
    'The formal v3 preflight field set changed.');

if ~strcmp(preflight.contractVersion, ...
            permit.preflightContractVersion) || ...
        ~strcmp(preflight.matPath, permit.preflightPath) || ...
        ~strcmp(preflight.reportPath, permit.preflightReportPath) || ...
        ~strcmp(preflight.publicationCompletionContractVersion, ...
            permit.preflightPublicationContractVersion) || ...
        ~isTrue(preflight.publicationCompletionMarkerRequired) || ...
        ~strcmp(preflight.publicationCompletionMarkerPath, ...
            permit.preflightCompletionMarkerPath)
    error('X36OutcomePermit:PreflightPathMismatch', ...
