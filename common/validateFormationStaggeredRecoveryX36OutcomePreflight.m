    proposal = preflight.pairProposals(pairIdx);
    validatePairProposal(proposal, pairIdx, ...
        preflight.protocol, permit);
    if ~isequaln(preflight.eligiblePairs(pairIdx), proposal)
        error('X36OutcomePermit:EligiblePairDrift', ...
            'Eligible-pair records must equal the frozen proposals.');
    end
    validateSourceState(preflight.states(pairIdx), ...
        proposal, pairIdx, preflight.protocol, permit);
end
end

