function validateSourceManifest(preflight, permit)
manifest = preflight.sourceManifest;
assertExactFields(manifest, { ...
    'contractVersion', 'paths', 'sha256', ...
    'unregisteredExecutablePaths', 'canonicalSha256'}, ...
    'X36OutcomePermit:SourceManifestDrift', ...
    'The formal v3 source-manifest shape changed.');
payload = rmfield(manifest, 'canonicalSha256');
try
    actualSha256 = computeCanonicalValueSha256(payload);
catch
    error('X36OutcomePermit:SourceManifestDrift', ...
        'The formal v3 source manifest cannot be hashed.');
end
if ~strcmp(manifest.contractVersion, ...
            permit.preflightSourceManifestContractVersion) || ...
        ~isempty(manifest.unregisteredExecutablePaths) || ...
        ~strcmp(manifest.canonicalSha256, ...
            permit.preflightSourceManifestSha256) || ...
        ~strcmp(preflight.sourceManifestSha256, ...
            permit.preflightSourceManifestSha256) || ...
        ~strcmp(actualSha256, manifest.canonicalSha256) || ...
        ~iscell(manifest.paths) || ~iscell(manifest.sha256) || ...
        ~isequal(size(manifest.paths), size(manifest.sha256)) || ...
        ~all(cellfun(@isSha256, manifest.sha256))
    error('X36OutcomePermit:SourceManifestDrift', ...
        'The formal v3 executable-source manifest changed.');
end
end

function validateEmbeddedSourceProtocol(protocol, permit)
try
    protocolSha256 = computeCanonicalValueSha256(protocol);
catch
    error('X36OutcomePermit:SourceProtocolDrift', ...
        'The embedded source protocol cannot be hashed canonically.');
end
if ~isstruct(protocol) || ~isscalar(protocol) || ...
        ~strcmp(protocolSha256, ...
            permit.sourceProtocolCanonicalSha256) || ...
        ~strcmp(protocol.contractVersion, ...
            permit.sourceProtocolContractVersion) || ...
        protocol.runtimeFingerprintFreezePending || ...
        ~isequal(protocol. ...
            expectedRuntimeFingerprintSha256ByStateArm, ...
            permit.authorizedRuntimeFingerprintSha256ByStateArm) || ...
        protocol.trackingOutcomeRerunAuthorized || ...
        ~protocol.trackingOutcomeEligibilityAfterCleanPreflight || ...
        ~protocol.x36PairedOutcomeRerunRequiresCleanPreflight || ...
        protocol.gnnTrainingAuthorized || ...
        protocol.x36OutcomeOpeningAuthorized || ...
        protocol.x48OutcomeOpeningAuthorized || ...
        protocol.validationClaimAllowed
    error('X36OutcomePermit:SourceProtocolDrift', ...
        ['The embedded v3 protocol must remain frozen and ', ...
         'tracking-outcome unauthorized.']);
end
end

