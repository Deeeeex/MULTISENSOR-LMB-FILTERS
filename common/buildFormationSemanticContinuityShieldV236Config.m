function config = buildFormationSemanticContinuityShieldV236Config( ...
        scenario, staticRegistration)
% BUILDFORMATIONSEMANTICCONTINUITYSHIELDV236CONFIG Matched teacher arm.

protocol = getFormationSemanticContinuityShieldV236Protocol();
source = getCorrectedStaticRoutingBaselineV227Protocol();
if ~isstruct(scenario) || ~isscalar(scenario) || ...
        ~all(isfield(scenario, {'presetName', 'numberOfSensors'})) || ...
        ~strcmp(scenario.presetName, protocol.presetName)
    error('FormationSemanticContinuityV236:InvalidConfigInput', ...
        'V236 is frozen to the registered M24 teacher scene.');
end
config = buildCorrectedStaticRoutingBaselineV227Config( ...
    source.dynamicArmId, scenario, staticRegistration);
config.topologyPolicyName = protocol.policyName;
config.topologyPolicyFcn = @(context) ...
    selectFormationSemanticContinuityShieldV236Policy( ...
        context, staticRegistration);
end
