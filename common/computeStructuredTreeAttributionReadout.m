function readout = computeStructuredTreeAttributionReadout( ...
        aggregates, scenarioConfig, minimumGainPercent, ...
        minimumRouteDifference)
% COMPUTESTRUCTUREDTREEATTRIBUTIONREADOUT Matched whole-tree evidence gate.
%
% The candidate is compared against same-weight fixed-index, link-tree and
% the complete registered cyclic-path root/receiver-phase sweep. This is
% not an exhaustive enumeration of rooted trees or endpoint assignments.
% Tail and byte
% comparisons are taken from the same per-seed reference arm that supplies
% the strongest tracking result.

if nargin < 3 || isempty(minimumGainPercent)
    minimumGainPercent = 5;
end
if nargin < 4 || isempty(minimumRouteDifference)
    minimumRouteDifference = 0.10;
end
readout = emptyStructuredTreeAttributionReadout();
[scenarioValid, formationCount, sensorsPerFormation, ...
    expectedCrossFraction] = resolveScenarioContract(scenarioConfig);
readout.scenarioContractValid = scenarioValid;
readout.formationCount = formationCount;
readout.sensorsPerFormation = sensorsPerFormation;
readout.expectedCrossFormationMessageFraction = ...
    expectedCrossFraction;
if scenarioValid
    readout.requiredScheduledPhaseCount = ...
        formationCount * sensorsPerFormation;
end

modes = {aggregates.mode};
candidateIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    char(mode), '^structured-tree-routing-w[0-9]+$', 'once')), ...
    modes));
readout.availableCandidateCount = numel(candidateIdx);
if isempty(candidateIdx)
    return;
end

evaluations = repmat( ...
    emptyStructuredTreeAttributionReadout(), ...
    1, numel(candidateIdx));
for candidateCursor = 1:numel(candidateIdx)
    evaluations(candidateCursor) = evaluateCandidate( ...
        aggregates, modes, candidateIdx(candidateCursor), ...
        scenarioValid, formationCount, sensorsPerFormation, ...
        expectedCrossFraction, minimumGainPercent, ...
        minimumRouteDifference);
    evaluations(candidateCursor).availableCandidateCount = ...
        numel(candidateIdx);
end
complete = [evaluations.completeBaselineSet];
if any(complete)
    selectionPool = find(complete);
    gains = [evaluations(selectionPool).gainVsMatchedControlPercent];
    gains(~isfinite(gains)) = -inf;
    [~, selectionCursor] = max(gains);
    selectedIdx = selectionPool(selectionCursor);
else
    candidateFocus = arrayfun(@(idx) ...
        mean(getMetric(aggregates(idx), ...
            'focusEospaBySeed', inf)), candidateIdx);
    [~, selectedIdx] = min(candidateFocus);
end
readout = evaluations(selectedIdx);
end

function readout = evaluateCandidate( ...
        aggregates, modes, candidateIdx, ...
        scenarioValid, formationCount, sensorsPerFormation, ...
        expectedCrossFraction, minimumGainPercent, ...
        minimumRouteDifference)
readout = emptyStructuredTreeAttributionReadout();
candidate = aggregates(candidateIdx);
weightToken = regexp(candidate.mode, ...
    '^structured-tree-routing-w([0-9]+)$', ...
    'tokens', 'once');
if isempty(weightToken)
    return;
end
weightSuffix = ['-w', weightToken{1}];
readout.available = true;
readout.arm = candidate.name;
readout.candidateSourceWeight = ...
    str2double(weightToken{1}) / 100;
readout.scenarioContractValid = scenarioValid;
readout.formationCount = formationCount;
readout.sensorsPerFormation = sensorsPerFormation;
readout.expectedCrossFormationMessageFraction = ...
    expectedCrossFraction;
readout.minimumPracticalGainPercent = minimumGainPercent;
readout.minimumRouteDifferenceFraction = minimumRouteDifference;
if scenarioValid
    readout.requiredScheduledPhaseCount = ...
        formationCount * sensorsPerFormation;
end

fixedIdx = find(cellfun(@(mode) ...
    strcmp(char(mode), ['directed-fixed-index', weightSuffix]), ...
    modes));
linkIdx = find(cellfun(@(mode) ...
    strcmp(char(mode), ['directed-link-tree', weightSuffix]), ...
    modes));
scheduledIdx = find(cellfun(@(mode) ~isempty(regexp( ...
    char(mode), ['^directed-scheduled-tree-r[0-9]+-', ...
        'e[0-9]+', weightSuffix, '$'], 'once')), modes));

validFixedIdx = fixedIdx(arrayfun(@(idx) ...
    validFixedControl(aggregates(idx)), fixedIdx));
validLinkIdx = linkIdx(arrayfun(@(idx) ...
    validTreeControl( ...
        aggregates(idx), expectedCrossFraction), linkIdx));
validScheduledIdx = scheduledIdx(arrayfun(@(idx) ...
    validTreeControl( ...
        aggregates(idx), expectedCrossFraction), scheduledIdx));
readout.fixedIndexControlAvailable = ~isempty(validFixedIdx);
readout.linkTreeControlAvailable = ~isempty(validLinkIdx);
readout.eligibleScheduledControlCount = ...
    numel(validScheduledIdx);
if scenarioValid
    readout.observedScheduledPhaseCount = ...
        countCanonicalScheduledTreeControlPhases( ...
            modes, validScheduledIdx, ...
            formationCount, sensorsPerFormation);
end
readout.completeBaselineSet = ...
    scenarioValid && ...
    readout.fixedIndexControlAvailable && ...
    readout.linkTreeControlAvailable && ...
    readout.observedScheduledPhaseCount >= ...
        readout.requiredScheduledPhaseCount;

candidateEospa = getMetric( ...
    candidate, 'focusEospaBySeed', NaN);
candidateWorst = getMetric( ...
    candidate, 'focusWorstSensorEospaBySeed', NaN);
candidateBytes = getMetric( ...
    candidate, 'focusAttemptedBytesBySeed', NaN);
readout.crossFormationBudgetExactEverySeed = ...
    vectorEquals( ...
        getMetric(candidate, ...
            'focusCrossFormationMessageFractionBySeed', NaN), ...
        expectedCrossFraction);
readout.directedMessageCountExactEveryStepAndSeed = all( ...
    getMetric(candidate, ...
        'focusDirectedMessageCountExactFractionBySeed', NaN) >= ...
        1 - 1e-12);
readout.crossFormationTreeEdgeCountExactEveryStepAndSeed = all( ...
    getMetric(candidate, ...
        'focusCrossFormationTreeEdgeCountExactFractionBySeed', NaN) >= ...
        1 - 1e-12);
readout.rootedFormationTreeEveryStepAndSeed = all( ...
    getMetric(candidate, ...
        'focusFormationRootedTreeFractionBySeed', NaN) >= ...
        1 - 1e-12);
readout.pairwiseUnionStrongEveryStepAndSeed = all( ...
    getMetric(candidate, ...
        'focusFormationPairwiseUnionStrongFractionBySeed', NaN) >= ...
        1 - 1e-12);
readout.pairwisePreviousGraphExecutedEverySeed = all( ...
    getMetric(candidate, ...
        'focusPairwisePreviousGraphExecutedBySeed', NaN) >= ...
        1 - 1e-12);
readout.receiverCoverageComplete = all( ...
    getMetric(candidate, ...
        'focusReceiverCoverageFractionBySeed', NaN) >= ...
        1 - 1e-12);
readout.distinctMapsEverySeed = all( ...
    getMetric(candidate, ...
        'focusDistinctDirectedRouteMapCountBySeed', NaN) > 1);
readout.withinWindowChangesEverySeed = all( ...
    getMetric(candidate, ...
        'focusWithinWindowRouteChangeFractionBySeed', NaN) > 0);
readout.distinctGatewayMapsEverySeed = all( ...
    getMetric(candidate, ...
        'focusDistinctGatewayRouteMapCountBySeed', NaN) > 1);
readout.gatewayChangesEverySeed = all( ...
    getMetric(candidate, ...
        'focusWithinWindowGatewayRouteChangeFractionBySeed', NaN) > 0);
differenceBySeed = getMetric(candidate, ...
    'focusFractionReceiverTimeDifferentFromFixedIndexMapBySeed', NaN);
readout.minimumDifferenceFromFixedIndex = min(differenceBySeed);
readout.differsFromFixedIndexEnough = all( ...
    differenceBySeed + 1e-12 >= minimumRouteDifference);
readout.zeroInfeasibility = all( ...
    getMetric(candidate, ...
        'focusTopologyInfeasibleRateBySeed', NaN) <= 1e-12);
readout.candidateStructuralContractPassed = ...
    scenarioValid && ...
    all(isfinite(candidateEospa)) && ...
    all(isfinite(candidateWorst)) && ...
    all(isfinite(candidateBytes)) && ...
    readout.crossFormationBudgetExactEverySeed && ...
    readout.directedMessageCountExactEveryStepAndSeed && ...
    readout.crossFormationTreeEdgeCountExactEveryStepAndSeed && ...
    readout.rootedFormationTreeEveryStepAndSeed && ...
    readout.pairwiseUnionStrongEveryStepAndSeed && ...
    readout.pairwisePreviousGraphExecutedEverySeed && ...
    readout.receiverCoverageComplete && ...
    readout.distinctMapsEverySeed && ...
    readout.withinWindowChangesEverySeed && ...
    readout.distinctGatewayMapsEverySeed && ...
    readout.gatewayChangesEverySeed && ...
    readout.differsFromFixedIndexEnough && ...
    readout.zeroInfeasibility;

baselineIdx = [ ...
    validFixedIdx, validScheduledIdx, validLinkIdx];
if isempty(baselineIdx)
    return;
end
baselineEospa = vertcatMetric( ...
    aggregates, baselineIdx, 'focusEospaBySeed');
[referenceEospa, referenceCursor] = ...
    min(baselineEospa, [], 1);
seedCount = numel(referenceEospa);
referenceWorst = nan(1, seedCount);
referenceBytes = nan(1, seedCount);
referenceNames = cell(1, seedCount);
for seedIdx = 1:seedCount
    reference = aggregates( ...
        baselineIdx(referenceCursor(seedIdx)));
    referenceWorst(seedIdx) = getMetric( ...
        reference, ...
        'focusWorstSensorEospaBySeed', NaN, seedIdx);
    referenceBytes(seedIdx) = getMetric( ...
        reference, 'focusAttemptedBytesBySeed', NaN, seedIdx);
    referenceNames{seedIdx} = reference.name;
end
readout.referenceArm = [ ...
    'best per-seed same-weight fixed-index / complete registered ', ...
    'cyclic-path phase sweep / link-tree control'];
readout.referenceArmBySeed = referenceNames;
gainBySeed = 100 * ( ...
    referenceEospa - candidateEospa) ./ ...
    max(abs(referenceEospa), eps);
readout.gainVsMatchedControlPercent = 100 * ( ...
    mean(referenceEospa) - mean(candidateEospa)) / ...
    max(abs(mean(referenceEospa)), eps);
readout.gainVsMatchedControlBySeedPercent = gainBySeed;
readout.positiveGainEverySeed = all(gainBySeed > 0);
readout.tailSafeVsMatchedControl = all( ...
    candidateWorst <= referenceWorst + 1e-12);
byteMismatch = 100 * abs( ...
    candidateBytes - referenceBytes) ./ ...
    max(referenceBytes, 1);
readout.maximumAttemptedByteMismatchPercent = max(byteMismatch);
readout.communicationMatchedWithinTwoPercent = ...
    all(byteMismatch <= 2 + 1e-12);
readout.noMoreAttemptedBytesEverySeed = all( ...
    candidateBytes <= referenceBytes + 1e-12);
readout.strictParetoEverySeed = ...
    readout.positiveGainEverySeed && ...
    readout.noMoreAttemptedBytesEverySeed;
readout.communicationFair = ...
    readout.communicationMatchedWithinTwoPercent || ...
    readout.strictParetoEverySeed;
readout.passesAttributionGate = ...
    readout.completeBaselineSet && ...
    readout.candidateStructuralContractPassed && ...
    readout.gainVsMatchedControlPercent >= minimumGainPercent && ...
    readout.positiveGainEverySeed && ...
    readout.tailSafeVsMatchedControl && ...
    readout.communicationFair;
end

function valid = validFixedControl(arm)
valid = ...
    all(isfinite(getMetric(arm, 'focusEospaBySeed', NaN))) && ...
    all(isfinite(getMetric( ...
        arm, 'focusWorstSensorEospaBySeed', NaN))) && ...
    all(isfinite(getMetric( ...
        arm, 'focusAttemptedBytesBySeed', NaN))) && ...
    all(getMetric( ...
        arm, 'focusReceiverCoverageFractionBySeed', NaN) >= ...
        1 - 1e-12) && ...
    all(getMetric( ...
        arm, 'focusTopologyInfeasibleRateBySeed', NaN) <= 1e-12);
end

function valid = validTreeControl(arm, expectedCrossFraction)
valid = validFixedControl(arm) && ...
    vectorEquals(getMetric(arm, ...
        'focusCrossFormationMessageFractionBySeed', NaN), ...
        expectedCrossFraction) && ...
    all(getMetric(arm, ...
        'focusDirectedMessageCountExactFractionBySeed', NaN) >= ...
        1 - 1e-12) && ...
    all(getMetric(arm, ...
        'focusCrossFormationTreeEdgeCountExactFractionBySeed', NaN) >= ...
        1 - 1e-12) && ...
    all(getMetric(arm, ...
        'focusFormationRootedTreeFractionBySeed', NaN) >= ...
        1 - 1e-12) && ...
    all(getMetric(arm, ...
        'focusFormationPairwiseUnionStrongFractionBySeed', NaN) >= ...
        1 - 1e-12) && ...
    all(getMetric(arm, ...
        'focusPairwisePreviousGraphExecutedBySeed', NaN) >= ...
        1 - 1e-12);
end

function [valid, formationCount, sensorsPerFormation, ...
        expectedCrossFraction] = resolveScenarioContract(config)
valid = false;
formationCount = NaN;
sensorsPerFormation = NaN;
expectedCrossFraction = NaN;
if ~isstruct(config) || ~isfield(config, 'sensorGroupIds')
    return;
end
groupIds = reshape(config.sensorGroupIds, 1, []);
groups = unique(groupIds, 'stable');
counts = arrayfun(@(group) nnz(groupIds == group), groups);
if numel(groups) < 2 || isempty(counts) || ...
        any(counts ~= counts(1))
    return;
end
formationCount = numel(groups);
sensorsPerFormation = counts(1);
sensorCount = numel(groupIds);
if isfield(config, 'numberOfSensors') && ...
        config.numberOfSensors ~= sensorCount
    return;
end
expectedCrossFraction = ...
    (formationCount - 1) / sensorCount;
valid = true;
end

function values = vertcatMetric(aggregates, indices, fieldName)
values = zeros(numel(indices), 0);
for cursor = 1:numel(indices)
    row = getMetric(aggregates(indices(cursor)), fieldName, NaN);
    if cursor == 1
        values = zeros(numel(indices), numel(row));
    elseif numel(row) ~= size(values, 2)
        error('Structured attribution metric seed counts differ.');
    end
    values(cursor, :) = row;
end
end

function values = getMetric(arm, fieldName, defaultValue, index)
if nargin < 4
    index = [];
end
if isfield(arm, fieldName)
    values = reshape(arm.(fieldName), 1, []);
else
    values = defaultValue;
end
if ~isempty(index)
    if numel(values) < index
        values = defaultValue;
    else
        values = values(index);
    end
end
end

function tf = vectorEquals(values, expected)
tf = isfinite(expected) && all(isfinite(values)) && ...
    all(abs(values - expected) <= 1e-12);
end
