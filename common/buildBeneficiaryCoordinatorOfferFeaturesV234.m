function result = buildBeneficiaryCoordinatorOfferFeaturesV234( ...
        offerRecords, coordinatorPosterior, model, options)
% BUILDBENEFICIARYCOORDINATOROFFERFEATURESV234 Causal compact features.
%
% The coordinator compares each remote 24-byte record with its own current
% fused label summary.  Full source mixtures, eta, truth and future outcomes
% are deliberately unavailable before payload selection.

if nargin < 4 || isempty(options)
    options = struct();
end
positionCutoff = getField(options, 'positionCutoff', NaN);
receiverCount = getField(options, 'receiverCount', 1);
admissionCreditBytes = getField(options, ...
    'admissionCreditBytes', 1);
if ~isstruct(offerRecords) || ~isstruct(coordinatorPosterior) || ...
        ~isstruct(model) || ~isscalar(model) || ...
        ~isfield(model, 'xDimension') || model.xDimension < 2 || ...
        ~isscalar(positionCutoff) || ~isfinite(positionCutoff) || ...
        positionCutoff <= 0 || ~isscalar(receiverCount) || ...
        ~isfinite(receiverCount) || receiverCount < 1 || ...
        receiverCount ~= round(receiverCount) || ...
        ~isscalar(admissionCreditBytes) || ...
        ~isfinite(admissionCreditBytes) || admissionCreditBytes <= 0
    error('BeneficiaryCoordinatorOfferV234:InvalidInput', ...
        'The coordinator feature request is malformed.');
end

coordinator = buildCacheFreeDonorOfferRecordsV234( ...
    coordinatorPosterior, model, 1, struct( ...
        'minimumActiveExistence', 0));
featureNames = { ...
    'source_existence', ...
    'source_evidence_quality', ...
    'source_position_trace_normalized', ...
    'coordinator_label_present', ...
    'coordinator_existence', ...
    'coordinator_evidence_quality', ...
    'coordinator_position_trace_normalized', ...
    'positive_existence_deficit', ...
    'positive_existence_excess', ...
    'bounded_absolute_log_odds_gap', ...
    'bounded_precision_gain', ...
    'positive_evidence_gap', ...
    'position_compatibility', ...
    'bounded_position_disagreement', ...
    'source_quality', ...
    'bounded_positive_risk_reduction', ...
    'payload_credit_fraction', ...
    'existence_rescue_score', ...
    'precision_refresh_score', ...
    'credible_disagreement_score', ...
    'risk_reduction_score'};
features = zeros(numel(offerRecords), numel(featureNames));
modeScores = zeros(numel(offerRecords), 4);
for recordIndex = 1:numel(offerRecords)
    source = offerRecords(recordIndex);
    receiverIndex = findRecord(coordinator, source.label);
    receiverPresent = receiverIndex > 0;
    if receiverPresent
        receiver = coordinator(receiverIndex);
    else
        receiver = emptyReceiver(source, positionCutoff);
    end
    sourceTraceNormalized = max(source.positionTrace, 0) / ...
        max(positionCutoff ^ 2, eps);
    receiverTraceNormalized = max(receiver.positionTrace, 0) / ...
        max(positionCutoff ^ 2, eps);
    sourceTraceFeature = sourceTraceNormalized / ...
        (1 + sourceTraceNormalized);
    receiverTraceFeature = receiverTraceNormalized / ...
        (1 + receiverTraceNormalized);
    existenceDeficit = max(source.existence - receiver.existence, 0);
    existenceExcess = max(receiver.existence - source.existence, 0);
    logOddsGap = abs(safeLogit(source.existence) - ...
        safeLogit(receiver.existence));
    boundedLogOddsGap = logOddsGap / (1 + logOddsGap);
    rawPrecisionGain = max(log((receiver.positionTrace + eps) / ...
        (source.positionTrace + eps)), 0);
    precisionGain = rawPrecisionGain / (1 + rawPrecisionGain);
    evidenceGap = max(source.evidenceQuality - ...
        receiver.evidenceQuality, 0);
    if receiverPresent
        delta = source.positionMean - receiver.positionMean;
        squaredDistance = 2 * sum(delta .^ 2) / max( ...
            source.positionTrace + receiver.positionTrace, eps);
        squaredDistance = min(max(squaredDistance, 0), 100);
        compatibility = exp(-0.5 * squaredDistance);
        disagreement = 1 - compatibility;
    else
        compatibility = 1;
        disagreement = 0;
    end
    sourcePrecisionQuality = 1 / (1 + sourceTraceNormalized);
    sourceQuality = source.existence * ( ...
        0.5 * source.evidenceQuality + ...
        0.5 * sourcePrecisionQuality);
    sourceRisk = labelRisk(source.existence, sourceTraceNormalized);
    receiverRisk = labelRisk( ...
        receiver.existence, receiverTraceNormalized);
    rawRiskReduction = max(receiverRisk - sourceRisk, 0);
    riskReduction = rawRiskReduction / (1 + rawRiskReduction);
    payloadFraction = min( ...
        receiverCount * source.payloadBytesPerReceiver / ...
        admissionCreditBytes, 1);

    existenceRescue = existenceDeficit * sourceQuality * compatibility;
    precisionRefresh = receiver.existence * precisionGain * ...
        sourceQuality * compatibility;
    credibleDisagreement = sqrt(max( ...
        source.existence * receiver.existence, 0)) * ...
        boundedLogOddsGap * sourceQuality * compatibility;
    riskReductionScore = riskReduction * sourceQuality * compatibility;
    modeScores(recordIndex, :) = [ ...
        existenceRescue, precisionRefresh, ...
        credibleDisagreement, riskReductionScore];
    features(recordIndex, :) = [ ...
        source.existence, source.evidenceQuality, ...
        sourceTraceFeature, double(receiverPresent), ...
        receiver.existence, receiver.evidenceQuality, ...
        receiverTraceFeature, existenceDeficit, ...
        existenceExcess, boundedLogOddsGap, precisionGain, ...
        evidenceGap, compatibility, disagreement, sourceQuality, ...
        riskReduction, payloadFraction, modeScores(recordIndex, :)];
end
if any(~isfinite(features(:))) || any(features(:) < -1e-12) || ...
        any(features(:) > 1 + 1e-12)
    error('BeneficiaryCoordinatorOfferV234:FeatureRange', ...
        'Every coordinator feature must be finite and scale bounded.');
end

result = struct();
result.contractVersion = ...
    'beneficiary-coordinator-offer-features-v234-v1';
result.featureNames = featureNames;
result.featureMatrix = features;
result.modeNames = { ...
    'existence-rescue', 'precision-refresh', ...
    'credible-disagreement', 'risk-reduction'};
result.modeScores = modeScores;
result.offerRecords = offerRecords;
result.coordinatorLabelCount = numel(coordinator);
result.positionCutoff = positionCutoff;
result.receiverCount = receiverCount;
result.admissionCreditBytes = admissionCreditBytes;
result.fullSourceMixtureUsed = false;
result.etaUsed = false;
result.truthUsed = false;
result.futureInformationUsed = false;
result.numericLabelIdentifiersUsedAsFeatures = false;
result.modeScoresAreActionValues = false;
end

function index = findRecord(records, label)
index = 0;
for recordIndex = 1:numel(records)
    if all(records(recordIndex).label == label)
        index = recordIndex;
        return;
    end
end
end

function receiver = emptyReceiver(source, positionCutoff)
receiver = source;
receiver.existence = 0;
receiver.evidenceQuality = 0;
receiver.positionMean = source.positionMean;
receiver.positionTrace = positionCutoff ^ 2;
receiver.payloadBytesPerReceiver = 0;
end

function value = safeLogit(probability)
floorValue = 1e-6;
probability = min(max(probability, floorValue), 1 - floorValue);
value = log(probability / (1 - probability));
end

function value = labelRisk(existence, normalizedTrace)
value = 0.5 * min(existence, 1 - existence) + ...
    0.5 * existence * min(max(normalizedTrace, 0), 1);
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
