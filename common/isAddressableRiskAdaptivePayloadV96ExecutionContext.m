function detected = ...
    isAddressableRiskAdaptivePayloadV96ExecutionContext(context)
% ISADDRESSABLERISKADAPTIVEPAYLOADV96EXECUTIONCONTEXT Identify V96.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'addressable-risk-adaptive-payload-v96-context-v1');
end
