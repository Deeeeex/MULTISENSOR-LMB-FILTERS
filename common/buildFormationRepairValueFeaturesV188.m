function [values, names, details] = ...
        buildFormationRepairValueFeaturesV188( ...
            fusedPosteriorBySensor, localPosteriorBySensor, ...
            physicalAdjacency, sensorGroupIds, model, currentTime, ...
            history, options)
% BUILDFORMATIONREPAIRVALUEFEATURESV188 Scale-normalized trigger features.
%
% The rows are formation-permutation equivariant.  Formation identifiers
% and absolute time are used only to align current rows with causal history;
% neither is returned as a feature.  The feature block combines local
% fusion-support debt, source-aware common-label opportunity, current graph
% reach, and one-step temporal change.  It predicts value only; the runtime
% safety projector remains responsible for the strongly connected backbone,
% exact common action, byte budget, and fallback.

if nargin < 7 || isempty(history)
    history = struct();
end
if nargin < 8 || isempty(options)
    options = struct();
end
pressure = computeFormationLabelRepairPressure( ...
    fusedPosteriorBySensor, localPosteriorBySensor, sensorGroupIds, ...
    model, currentTime, getField(options, 'pressureOptions', struct()));
opportunity = computeFormationCommonLabelRepairOpportunity( ...
    fusedPosteriorBySensor, localPosteriorBySensor, physicalAdjacency, ...
    sensorGroupIds, model, getField( ...
        options, 'opportunityOptions', struct()));
if ~isequal(pressure.formationIds, opportunity.formationIds)
    error('FormationRepairValueV188:FormationAlignmentDrift', ...
        'The local and source-aware feature blocks do not align.');
end

groupIds = reshape(sensorGroupIds, 1, []);
sensorCount = numel(groupIds);
formationIds = pressure.formationIds;
formationCount = numel(formationIds);
physicalAdjacency = logical(physicalAdjacency);
if ~isequal(size(physicalAdjacency), [sensorCount, sensorCount])
    error('FormationRepairValueV188:PhysicalGraphMismatch', ...
        'The physical graph does not match the formation membership.');
end
previousLocal = historicalVector( ...
    history, formationIds, 'localPressure');
previousCommon = historicalVector( ...
    history, formationIds, 'commonOpportunity');
historyAvailable = double(isfield(history, 'formationIds') && ...
    isfield(history, 'localPressure') && ...
    isfield(history, 'commonOpportunity'));

formationSizeFraction = zeros(formationCount, 1);
meanPhysicalDegreeFraction = zeros(formationCount, 1);
externalFormationReachFraction = zeros(formationCount, 1);
candidateDensity = zeros(formationCount, 1);
for formationIdx = 1:formationCount
    formationId = formationIds(formationIdx);
    members = find(groupIds == formationId);
    formationSizeFraction(formationIdx) = ...
        numel(members) / sensorCount;
    meanPhysicalDegreeFraction(formationIdx) = mean(sum( ...
        physicalAdjacency(members, :), 2)) / max(sensorCount - 1, 1);
    reachableSensors = any(physicalAdjacency(members, :), 1);
    reachableFormations = unique(groupIds( ...
        reachableSensors & groupIds ~= formationId));
    externalFormationReachFraction(formationIdx) = ...
        numel(reachableFormations) / max(formationCount - 1, 1);
    candidateDensity(formationIdx) = log1p( ...
        opportunity.commonCandidateCount(formationIdx)) / ...
        max(log1p(sensorCount * sensorCount), eps);
end

minimumRisk = reshape(opportunity.minimumRiskReduction, [], 1);
minimumRisk(~isfinite(minimumRisk)) = 0;
minimumExistence = reshape( ...
    opportunity.minimumReceiverExistence, [], 1);
minimumExistence(~isfinite(minimumExistence)) = 0;
currentLocal = reshape(pressure.formationPressure, [], 1);
currentCommon = reshape(opportunity.opportunity, [], 1);
values = [ ...
    reshape(pressure.formationMeanScore, [], 1), ...
    reshape(pressure.formationTailScore, [], 1), ...
    reshape(pressure.formationSupportedSensorFraction, [], 1), ...
    currentCommon, ...
    minimumRisk, ...
    minimumExistence, ...
    reshape(opportunity.bestPeerConsensus, [], 1), ...
    1 - reshape(opportunity.bestReceiverCompatibility, [], 1), ...
    candidateDensity, ...
    formationSizeFraction, ...
    meanPhysicalDegreeFraction, ...
    externalFormationReachFraction, ...
    previousLocal, ...
    currentLocal - previousLocal, ...
    previousCommon, ...
    currentCommon - previousCommon, ...
    historyAvailable * ones(formationCount, 1)];
names = { ...
    'local_support_debt_mean', ...
    'local_support_debt_tail', ...
    'local_supported_sensor_fraction', ...
    'common_source_opportunity', ...
    'common_minimum_risk_reduction', ...
    'common_minimum_receiver_existence', ...
    'common_peer_consensus', ...
    'common_receiver_disagreement', ...
    'log_common_candidate_density', ...
    'formation_size_fraction', ...
    'mean_physical_degree_fraction', ...
    'external_formation_reach_fraction', ...
    'previous_local_support_pressure', ...
    'local_support_pressure_delta', ...
    'previous_common_source_opportunity', ...
    'common_source_opportunity_delta', ...
    'history_available'};
if size(values, 1) ~= formationCount || ...
        size(values, 2) ~= numel(names) || any(~isfinite(values(:)))
    error('FormationRepairValueV188:InvalidFeatureBlock', ...
        'The online formation feature block is invalid.');
end

details = struct();
details.contractVersion = 'formation-repair-value-features-v188-v1';
details.currentTime = currentTime;
details.formationIds = formationIds;
details.featureNames = names;
details.localPressure = pressure;
details.commonOpportunity = opportunity;
details.nextHistory = struct( ...
    'contractVersion', 'formation-repair-value-history-v188-v1', ...
    'formationIds', formationIds, ...
    'localPressure', reshape(pressure.formationPressure, 1, []), ...
    'commonOpportunity', reshape(opportunity.opportunity, 1, []));
details.bestSource = opportunity.bestSource;
details.bestLabel = opportunity.bestLabel;
details.truthUsed = false;
details.futureInformationUsed = false;
details.numericLabelIdentifiersUsedAsFeatures = false;
details.absoluteTimeUsedAsFeature = false;
details.fixedFormationIdentifiersUsedAsFeatures = false;
details.requiresChargedSynopsis = true;
details.safetyProjected = false;
end

function values = historicalVector(history, formationIds, fieldName)
values = zeros(numel(formationIds), 1);
if ~isstruct(history) || ~isfield(history, 'formationIds') || ...
        ~isfield(history, fieldName)
    return;
end
historyIds = reshape(history.formationIds, 1, []);
historyValues = reshape(history.(fieldName), 1, []);
if numel(historyIds) ~= numel(historyValues) || ...
        any(~isfinite(historyValues))
    error('FormationRepairValueV188:InvalidHistory', ...
        'The causal feature history is malformed.');
end
for formationIdx = 1:numel(formationIds)
    match = find(historyIds == formationIds(formationIdx), 1);
    if ~isempty(match)
        values(formationIdx) = historyValues(match);
    end
end
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
