function protocol = getCausalSourceOfferRankerV230Protocol()
% GETCAUSALSOURCEOFFERRANKERV230PROTOCOL Source-side discovery contract.
%
% A source ranks labels from its current posterior relative only to ordinary
% full posteriors that it previously received from the beneficiary.  V230
% first tests the scoring rule with a same-page full-cache proxy.  Passing
% that screen authorizes runtime-cache integration, not an online claim.

base = getFusionAwareSourceOfferProtocolV229();
protocol = struct();
protocol.id = 'causal-source-offer-ranker-v230-v1';
protocol.contractVersion = ...
    'causal-source-offer-ranker-v230-protocol-v1';
protocol.baseProtocolId = base.id;
protocol.status = 'same-state-ranking-screen';

cache = struct();
cache.runtimeState = 'receivedCache{source,beneficiary-sensor}';
cache.updateRule = 'successful-ordinary-delivery-only';
cache.requiredEventType = 2;
cache.maximumAgePages = 2;
cache.ageDecay = 0.75;
cache.minimumCachedBeneficiarySensors = 1;
cache.absentLabelIsCredibleOnlyForFullPosterior = true;
cache.runtimeSnapshotPersisted = false;
cache.runtimeRecallValidated = false;
protocol.cache = cache;

ranking = struct();
ranking.maximumOffersPerSource = ...
    base.offer.maximumOffersPerSource;
ranking.modeNames = { ...
    'existence-surprise', 'spatial-utility'};
ranking.minimumActionableExistence = 0.10;
ranking.minimumSpatialExistence = 0.05;
ranking.existenceLogitFloor = 1e-3;
ranking.covarianceFloor = 1e-6;
ranking.precisionGainWeight = 0.50;
ranking.minimumPositiveScore = 1e-12;
ranking.numericLabelIdentifiersUsedAsScoreFeatures = false;
ranking.payloadBytesUsedOnlyAsTieBreak = true;
ranking.truthUsed = false;
ranking.futureInformationUsed = false;
protocol.ranking = ranking;

protocol.sameStateScreenPassRule = ...
    'all teacher source-label pairs selected in at most two offers';
protocol.sameStateScreenAuthorizes = ...
    'runtime causal-cache capture and recall validation only';
protocol.onlinePolicyImplemented = false;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V230 first evaluates source-relative ranking with current beneficiary ', ...
    'posteriors standing in for a perfectly fresh full cache. A pass shows ', ...
    'only that the score can express the opened teacher rows. It does not ', ...
    'show that the runtime source owns those cache entries, that stale ', ...
    'entries preserve recall, or that a selected offer improves tracking.'];

assertProtocol(protocol, base);
end

function assertProtocol(protocol, base)
if ~strcmp(protocol.status, 'same-state-ranking-screen') || ...
        protocol.cache.requiredEventType ~= 2 || ...
        protocol.cache.maximumAgePages ~= 2 || ...
        abs(protocol.cache.ageDecay - 0.75) > 1e-12 || ...
        protocol.cache.minimumCachedBeneficiarySensors ~= 1 || ...
        protocol.cache.runtimeSnapshotPersisted || ...
        protocol.cache.runtimeRecallValidated || ...
        protocol.ranking.maximumOffersPerSource ~= ...
            base.offer.maximumOffersPerSource || ...
        numel(protocol.ranking.modeNames) ~= 2 || ...
        protocol.ranking.numericLabelIdentifiersUsedAsScoreFeatures || ...
        ~protocol.ranking.payloadBytesUsedOnlyAsTieBreak || ...
        protocol.ranking.truthUsed || ...
        protocol.ranking.futureInformationUsed || ...
        protocol.onlinePolicyImplemented || ...
        protocol.validationClaimAllowed
    error('CausalSourceOfferRankerV230:ProtocolDrift', ...
        'The frozen V230 source-offer ranking contract drifted.');
end
end
