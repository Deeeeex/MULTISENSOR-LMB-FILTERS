function state = ...
    validateFormationB4V46DevelopmentExecutionGitState( ...
        expectedExecutionSurfaceCommit)
% VALIDATEFORMATIONB4V46DEVELOPMENTEXECUTIONGITSTATE Clean data-only child.

if ~ischar(expectedExecutionSurfaceCommit) || ...
        isempty(regexp(expectedExecutionSurfaceCommit, ...
            '^[0-9a-f]{40}$', 'once'))
    error('FormationB4V46DevelopmentPermit:ExecutionCommitDrift', ...
        'The frozen execution-surface commit is malformed.');
end
repoRoot = fileparts(fileparts(mfilename('fullpath')));
assertFormationB4V46DevelopmentCriticalFunctionPaths();
assertNoGitObjectReplacement(repoRoot);
activationAnchor = ...
    assertFormationB4V46DevelopmentPermitActivationFileAnchored();
[status, headText] = builtin('system', sprintf( ...
    '/usr/bin/git --no-replace-objects -C %s rev-parse HEAD', ...
    shellQuote(repoRoot)));
if status ~= 0
    error('FormationB4V46DevelopmentPermit:GitStateFailed', ...
        'The current Git commit could not be resolved.');
end
headCommit = strtrim(headText);
[workingStatus, ~] = builtin('system', sprintf( ...
    '/usr/bin/git --no-replace-objects -C %s diff --quiet --', ...
    shellQuote(repoRoot)));
[indexStatus, ~] = builtin('system', sprintf( ...
    ['/usr/bin/git --no-replace-objects -C %s ', ...
     'diff --cached --quiet --'], ...
    shellQuote(repoRoot)));
if workingStatus > 1 || indexStatus > 1
    error('FormationB4V46DevelopmentPermit:GitStateFailed', ...
        'Tracked Git cleanliness could not be determined.');
end
if workingStatus ~= 0 || indexStatus ~= 0
    error('FormationB4V46DevelopmentPermit:TrackedSourceDirty', ...
        'Tracked files must be clean for development arm execution.');
end
[ancestorStatus, ~] = builtin('system', sprintf( ...
    ['/usr/bin/git --no-replace-objects -C %s ', ...
     'merge-base --is-ancestor %s HEAD'], ...
    shellQuote(repoRoot), expectedExecutionSurfaceCommit));
if ancestorStatus ~= 0
    error('FormationB4V46DevelopmentPermit:ExecutionCommitDrift', ...
        'The frozen execution-surface commit is not a current ancestor.');
end
[diffStatus, diffText] = builtin('system', sprintf( ...
    ['/usr/bin/git --no-replace-objects -C %s ', ...
     'diff --name-only %s..HEAD'], ...
    shellQuote(repoRoot), expectedExecutionSurfaceCommit));
if diffStatus ~= 0
    error('FormationB4V46DevelopmentPermit:GitStateFailed', ...
        'The post-surface data-only diff could not be enumerated.');
end
changedPaths = splitNonemptyLines(diffText);
allowedPath = ...
    'contracts/formation_b4_v46_development_arm_permits.json';
if ~isequal(changedPaths, {allowedPath})
    error('FormationB4V46DevelopmentPermit:PostSurfaceCodeDrift', ...
        ['After the execution surface is frozen, only the exact permit ', ...
         'activation JSON may differ.']);
end
state = struct();
state.contractVersion = ...
    'formation-b4-v46-development-execution-git-state-v1';
state.repoRoot = repoRoot;
state.headCommit = headCommit;
state.executionSurfaceCommit = expectedExecutionSurfaceCommit;
state.executionSurfaceCommitIsAncestor = true;
state.trackedWorktreeClean = true;
state.changedPathsSinceExecutionSurface = changedPaths;
state.dataOnlyActivationVerified = true;
state.gitObjectReplacementRejected = true;
state.activationFileGitBlobId = activationAnchor.gitBlobId;
state.activationFileRegularAndAnchored = true;
end

function assertNoGitObjectReplacement(repoRoot)
if ~isempty(getenv('GIT_REPLACE_REF_BASE'))
    error('FormationB4V46DevelopmentPermit:GitObjectReplacementPresent', ...
        'A custom Git replacement-ref namespace is not allowed.');
end
[status, refsText] = builtin('system', sprintf( ...
    '/usr/bin/git --no-replace-objects -C %s replace --list', ...
    shellQuote(repoRoot)));
if status ~= 0
    error('FormationB4V46DevelopmentPermit:GitStateFailed', ...
        'Git replacement refs could not be enumerated.');
end
if ~isempty(strtrim(refsText))
    error('FormationB4V46DevelopmentPermit:GitObjectReplacementPresent', ...
        'Git object replacement refs are not allowed for V46 execution.');
end
end

function lines = splitNonemptyLines(value)
value = strtrim(value);
if isempty(value)
    lines = cell(1, 0);
else
    lines = reshape(regexp(value, '\r?\n', 'split'), 1, []);
end
end

function value = shellQuote(value)
value = ['''', strrep(value, '''', '''"''"'''), ''''];
end
