function [adjacency, details] = ...
        selectHierarchicalDelayedValueCollectionV213BasePolicy(context)
% SELECTHIERARCHICALDELAYEDVALUECOLLECTIONV213BASEPOLICY Log V213 need.
%
% Route and payload behavior are exactly the causal V99 base policy.  The
% only addition is a truth-free V208 formation-graph snapshot used to log
% the current formation-level need score for V213 decision-window
% selection.  The graph never changes the selected adjacency.

historyMature = isstruct(context) && ...
    isfield(context, 'previousAdjacencyHistory') && ...
    ndims(context.previousAdjacencyHistory) >= 2 && ...
    size(context.previousAdjacencyHistory, 3) >= 1;
if historyMature
    [adjacency, details] = ...
        selectOnlinePositiveNetAddressablePayloadV99Policy(context);
else
    routeProtocol = getFormationIsolateReconnectProbeProtocol();
    routeOptions = struct( ...
        'dominantWeight', routeProtocol.dominantWeight, ...
        'residualWeight', routeProtocol.residualWeight);
    [adjacency, details] = ...
        selectBackboneResidualSplicedCyclePolicy( ...
            context, 'fixed-counter-clockwise', routeOptions);
    warmupGroupIds = reshape(context.model.dynamicTopologyScenario. ...
        config.sensorGroupIds, 1, []);
    formationCount = numel(unique(warmupGroupIds, 'stable'));
    details.posteriorUsed = false;
    details.posteriorPayloadMetadataUsed = false;
    details.truthUsed = false;
    details.futureOutcomeUsed = false;
    details.currentLinkReliabilityUsed = false;
    details.retentionDebtFractionByFormation = ...
        zeros(1, formationCount);
    details.retentionDebtThresholdByFormation = ...
        zeros(1, formationCount);
    details.retentionDebtSingleAvailableMask = ...
        false(1, formationCount);
    details.retentionDebtSingleSafetyMask = ...
        false(1, formationCount);
    details.retentionDebtRequestedFormationIds = zeros(1, 0);
    details.retentionDebtSelectedFormationIds = zeros(1, 0);
    details.retentionDebtProjectionRemovalOrder = zeros(1, 0);
end

if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, { ...
            'localPosteriorBySensor', 'model', 'commConfig', ...
            'currentTime', 'previousAdjacency', ...
            'physicalAdjacency', 'positions'})) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds')
    error('HierarchicalDelayedValueV213:MissingObservableContext', ...
        'The V213 base policy requires the current observable graph state.');
end

groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
graph = buildObservableFormationGraphSnapshotV208( ...
    context.localPosteriorBySensor, groupIds, ...
    context.physicalAdjacency, adjacency, ...
    context.previousAdjacency, context.positions, ...
    context.commConfig, context.model, context.currentTime, 0);
featureIdx = find(strcmp( ...
    graph.nodeFeatureNames, 'need_max'));
if numel(featureIdx) ~= 1
    error('HierarchicalDelayedValueV213:NeedFeatureDrift', ...
        'The V208 graph must expose one formation need_max feature.');
end
formationNeed = reshape( ...
    graph.nodeFeatures(:, featureIdx), 1, []);

details.hierarchicalFormationIds = ...
    reshape(graph.formationIds, 1, []);
details.hierarchicalFormationNeedByFormation = formationNeed;
details.hierarchicalMaximumFormationNeed = max(formationNeed);
details.hierarchicalGraphContractVersion = graph.contractVersion;
details.hierarchicalNeedFeatureName = 'need_max';
details.hierarchicalNeedAffectsRouting = false;
details.hierarchicalHistoryWarmupReferenceUsed = ~historyMature;
details.hierarchicalNeedTruthUsed = false;
details.hierarchicalNeedFutureInformationUsed = false;
details.contractVersion = ...
    'hierarchical-delayed-value-v213-base-policy-v1';
protocol = getHierarchicalDelayedValueControllerV213Protocol();
details.protocolId = protocol.id;
end
