function [permuted, details] = ...
    permuteFormationIndexEquivariantContext( ...
        context, newToOldNodeOrder, relabeledGroupIds)
% PERMUTEFORMATIONINDEXEQUIVARIANTCONTEXT Pure node-coordinate change.
%
% newToOldNodeOrder says which original physical node occupies each new
% array coordinate.  Every node-indexed page and immutable physical UID is
% permuted together.  Optional relabeledGroupIds may change only the
% numeric membership codes; physical formation UIDs remain unchanged.

required = {'localPosteriorBySensor', 'model', 'baseAdjacency', ...
    'physicalAdjacency', 'previousAdjacencyHistory', 'positions', ...
    'sensorPhysicalUids', 'formationPhysicalUidsBySensor', ...
    'commConfig', 'triggerConfig'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds') || ...
        ~isfield(context.commConfig, 'pDropByEdge')
    error('FormationIndexEquivariantPermutation:InvalidContext', ...
        'The v43 context is incomplete.');
end
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
nodeCount = numel(groupIds);
newToOldNodeOrder = reshape(newToOldNodeOrder, 1, []);
if ~isnumeric(newToOldNodeOrder) || ...
        numel(newToOldNodeOrder) ~= nodeCount || ...
        ~isequal(sort(newToOldNodeOrder), 1:nodeCount) || ...
        numel(context.localPosteriorBySensor) ~= nodeCount || ...
        ~isequal(size(context.baseAdjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(context.positions), [2, nodeCount]) || ...
        numel(context.sensorPhysicalUids) ~= nodeCount || ...
        numel(context.formationPhysicalUidsBySensor) ~= nodeCount || ...
        ndims(context.previousAdjacencyHistory) ~= 3 || ...
        size(context.previousAdjacencyHistory, 1) ~= nodeCount || ...
        size(context.previousAdjacencyHistory, 2) ~= nodeCount || ...
        ~isequal(size(context.commConfig.pDropByEdge), ...
            [nodeCount, nodeCount])
    error('FormationIndexEquivariantPermutation:InvalidPermutation', ...
        'The v43 node-coordinate permutation is invalid.');
end
if nargin < 3 || isempty(relabeledGroupIds)
    relabeledGroupIds = groupIds(newToOldNodeOrder);
    labelsChanged = false;
else
    relabeledGroupIds = reshape(relabeledGroupIds, 1, []);
    originalMembership = groupIds(newToOldNodeOrder);
    if numel(relabeledGroupIds) ~= nodeCount || ...
            ~samePartition(originalMembership, relabeledGroupIds)
        error('FormationIndexEquivariantPermutation:InvalidRelabel', ...
            'Group relabeling must preserve the physical partition.');
    end
    labelsChanged = ~isequal(relabeledGroupIds, originalMembership);
end

permuted = context;
permuted.localPosteriorBySensor = reshape( ...
    context.localPosteriorBySensor(newToOldNodeOrder), 1, []);
permuted.baseAdjacency = ...
    context.baseAdjacency(newToOldNodeOrder, newToOldNodeOrder);
permuted.physicalAdjacency = ...
    context.physicalAdjacency(newToOldNodeOrder, newToOldNodeOrder);
permuted.previousAdjacencyHistory = ...
    context.previousAdjacencyHistory( ...
        newToOldNodeOrder, newToOldNodeOrder, :);
permuted.positions = context.positions(:, newToOldNodeOrder);
permuted.sensorPhysicalUids = reshape( ...
    context.sensorPhysicalUids(newToOldNodeOrder), 1, []);
permuted.formationPhysicalUidsBySensor = reshape( ...
    context.formationPhysicalUidsBySensor(newToOldNodeOrder), 1, []);
permuted.commConfig.pDropByEdge = ...
    context.commConfig.pDropByEdge( ...
        newToOldNodeOrder, newToOldNodeOrder);
permuted.model.dynamicTopologyScenario.config.sensorGroupIds = ...
    relabeledGroupIds;
if isfield(context.model.dynamicTopologyScenario, 'staticAdjacency')
    permuted.model.dynamicTopologyScenario.staticAdjacency = ...
        context.model.dynamicTopologyScenario.staticAdjacency( ...
            newToOldNodeOrder, newToOldNodeOrder);
end

oldToNewNodeOrder = zeros(1, nodeCount);
oldToNewNodeOrder(newToOldNodeOrder) = 1:nodeCount;
details = struct();
details.contractVersion = ...
    'formation-index-equivariant-node-permutation-v1';
details.newToOldNodeOrder = newToOldNodeOrder;
details.oldToNewNodeOrder = oldToNewNodeOrder;
details.formationLabelsChanged = labelsChanged;
details.physicalMembershipChanged = false;
details.sensorPhysicalUidsPermutedWithEntities = true;
details.formationPhysicalUidsPermutedWithEntities = true;
details.pureNodeCoordinatePermutation = true;
details.canonicalSha256 = computeCanonicalValueSha256(details);
end

function same = samePartition(left, right)
nodeCount = numel(left);
same = true;
for first = 1:nodeCount
    for second = first+1:nodeCount
        if (left(first) == left(second)) ~= ...
                (right(first) == right(second))
            same = false;
            return;
        end
    end
end
end
