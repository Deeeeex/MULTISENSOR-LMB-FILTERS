function context = ...
        buildBudgetRecycledFormationRepairV188ExecutionContext( ...
            presetName, seed, currentTime, actionName, scheduleEnabled, ...
            onlineReselectionEnabled, repairPlan, horizonSteps)
% BUILDBUDGETRECYCLEDFORMATIONREPAIRV188EXECUTIONCONTEXT Dev scope.

if nargin < 8 || isempty(horizonSteps)
    horizonSteps = 3;
end
baseProtocol = getOnlinePositiveNetAddressablePayloadV99Protocol( ...
    horizonSteps);
protocol = getBudgetRecycledFormationRepairV188Protocol();
if ~ischar(presetName) || isempty(presetName) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || ...
        ~ischar(actionName) || isempty(actionName) || ...
        ~isscalar(scheduleEnabled) || ...
        ~(islogical(scheduleEnabled) || isnumeric(scheduleEnabled)) || ...
        ~isscalar(onlineReselectionEnabled) || ...
        ~(islogical(onlineReselectionEnabled) || ...
            isnumeric(onlineReselectionEnabled)) || ...
        ~isstruct(repairPlan) || ~isscalar(repairPlan)
    error('BudgetRecycledFormationRepairV188:InvalidExecutionContext', ...
        'The V188 execution-context input is invalid.');
end

context = struct();
context.contractVersion = ...
    'budget-recycled-formation-repair-v188-context-v1';
context.capability = ...
    'budget-recycled-formation-repair-v188-development';
context.action = ...
    'filter-budget-recycled-formation-repair-v188-development';
context.protocolId = protocol.id;
context.phase = 'opened-return';
context.presetName = presetName;
context.seed = seed;
context.currentTime = currentTime;
context.measurementTimeCount = ...
    currentTime + baseProtocol.horizonSteps - 1;
context.policyName = baseProtocol.outcomePolicyName;
context.actionName = actionName;
context.scheduleEnabled = logical(scheduleEnabled);
context.onlineReselectionEnabled = logical(onlineReselectionEnabled);
context.developmentEvidenceOnly = true;
context.budgetRecycledFormationRepairPlan = repairPlan;
end
