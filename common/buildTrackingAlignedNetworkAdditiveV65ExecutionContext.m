function context = ...
    buildTrackingAlignedNetworkAdditiveV65ExecutionContext( ...
        presetName, seed, currentTime, actionName, actionEnabled)
% BUILDTRACKINGALIGNEDNETWORKADDITIVEV65EXECUTIONCONTEXT Development scope.

protocol = getNetworkAdditiveFormationRiskV65Protocol();
if ~ischar(presetName) || isempty(presetName) || ...
        ~isscalar(seed) || ~isfinite(seed) || seed ~= round(seed) || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || ...
        ~ischar(actionName) || isempty(actionName) || ...
        ~isscalar(actionEnabled) || ...
        ~(islogical(actionEnabled) || isnumeric(actionEnabled))
    error('NetworkAdditiveV65:InvalidExecutionContext', ...
        'The V65 execution context input is invalid.');
end

context = struct();
context.contractVersion = ...
    'tracking-aligned-network-additive-v65-context-v1';
context.capability = ...
    'tracking-aligned-network-additive-development';
context.action = ...
    'filter-tracking-aligned-network-additive-development';
context.protocolId = protocol.id;
context.phase = 'opened-return';
context.presetName = presetName;
context.seed = seed;
context.currentTime = currentTime;
context.measurementTimeCount = ...
    currentTime + protocol.horizonSteps - 1;
context.policyName = protocol.outcomePolicyName;
context.actionName = actionName;
context.scheduleEnabled = logical(actionEnabled);
context.developmentEvidenceOnly = true;
end
