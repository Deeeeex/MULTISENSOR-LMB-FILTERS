function detected = ...
    isNetworkBudgetReallocatedMultiSourceV95ExecutionContext(context)
% ISNETWORKBUDGETREALLOCATEDMULTISOURCEV95EXECUTIONCONTEXT Identify V95.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'network-budget-reallocated-multi-source-v95-context-v1');
end
