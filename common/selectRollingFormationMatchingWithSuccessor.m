function joint = selectRollingFormationMatchingWithSuccessor( ...
        groupIds, receiverIndices, senderIndices, ...
        currentScores, successorScores, options)
% SELECTROLLINGFORMATIONMATCHINGWITHSUCCESSOR Joint one-step projection.
%
% The binary program selects current and witness-successor cross-formation
% overrides together. It enforces per-page receiver/sender/pair loads,
% current B-window cuts, successor B-window cuts, and coupled cycle-edge
% restoration. The latter guarantees that every intra-formation backbone
% edge appears in each mature sensor-level union; formation-level strong
% connectivity therefore lifts to sensor-level strong connectivity.

if nargin < 6 || isempty(options)
    options = struct();
end
groupIds = reshape(groupIds, 1, []);
receiverIndices = reshape(receiverIndices, [], 1);
senderIndices = reshape(senderIndices, [], 1);
currentScores = reshape(currentScores, [], 1);
successorScores = reshape(successorScores, [], 1);
exampleCount = numel(receiverIndices);
if numel(senderIndices) ~= exampleCount || ...
        numel(currentScores) ~= exampleCount || ...
        numel(successorScores) ~= exampleCount
    error('Joint rolling-matching arrays must have the same length.');
end
nodeCount = numel(groupIds);
if nodeCount < 2 || any(receiverIndices < 1 | ...
        receiverIndices > nodeCount | senderIndices < 1 | ...
        senderIndices > nodeCount | mod(receiverIndices, 1) ~= 0 | ...
        mod(senderIndices, 1) ~= 0)
    error('Joint rolling-matching sensor indices are invalid.');
end
groups = unique(groupIds, 'stable');
groupCount = numel(groups);
if groupCount < 2
    error('Joint rolling matching needs at least two formations.');
end
receiverGroups = mapGroups( ...
    groupIds, groups, receiverIndices);
senderGroups = mapGroups( ...
    groupIds, groups, senderIndices);
if any(receiverGroups == senderGroups)
    error('Joint rolling examples must be cross-formation edges.');
end

windowLength = max(2, round(getField( ...
    options, 'connectivityWindowLength', 3)));
sensorHistory = normalizeSensorHistory( ...
    getField(options, 'recentSensorAdjacency', ...
        false(nodeCount, nodeCount, 0)), ...
    nodeCount, windowLength);
baselineSources = reshape(getField( ...
    options, 'baselineSources', []), 1, []);
if numel(baselineSources) ~= nodeCount || ...
        any(~isfinite(baselineSources)) || ...
        any(baselineSources < 1 | ...
            baselineSources > nodeCount | ...
            mod(baselineSources, 1) ~= 0)
    error('Joint rolling matching needs one valid baseline sender per node.');
end
validateBaselineBackbone( ...
    baselineSources, groupIds, groups);
formationHistory = formationHistoryFromSensorHistory( ...
    sensorHistory, groupIds, groups);

currentAllowed = normalizeFormationAdjacency( ...
    getField(options, 'currentAllowedFormationAdjacency', ...
        true(groupCount) & ~eye(groupCount)), ...
    groupCount, 'currentAllowedFormationAdjacency');
successorAllowed = normalizeFormationAdjacency( ...
    getField(options, 'successorAllowedFormationAdjacency', ...
        true(groupCount) & ~eye(groupCount)), ...
    groupCount, 'successorAllowedFormationAdjacency');
currentRequired = normalizeFormationAdjacency( ...
    getField(options, 'currentRequiredFormationAdjacency', ...
        false(groupCount)), ...
    groupCount, 'currentRequiredFormationAdjacency');
successorRequired = normalizeFormationAdjacency( ...
    getField(options, 'successorRequiredFormationAdjacency', ...
        false(groupCount)), ...
    groupCount, 'successorRequiredFormationAdjacency');
if any(currentRequired(:) & ~currentAllowed(:)) || ...
        any(successorRequired(:) & ~successorAllowed(:))
    error('Required joint rolling pairs must also be allowed.');
end

maximumCurrentCrossEdges = normalizeCrossEdgeLimit(getField( ...
    options, 'maximumCurrentCrossEdges', groupCount - 1), ...
    'maximumCurrentCrossEdges', 'floor');
maximumSuccessorCrossEdges = normalizeCrossEdgeLimit(getField( ...
    options, 'maximumSuccessorCrossEdges', groupCount - 1), ...
    'maximumSuccessorCrossEdges', 'floor');
minimumCurrentCrossEdges = normalizeCrossEdgeLimit(getField( ...
    options, 'minimumCurrentCrossEdges', 0), ...
    'minimumCurrentCrossEdges', 'ceil');
minimumSuccessorCrossEdges = normalizeCrossEdgeLimit(getField( ...
    options, 'minimumSuccessorCrossEdges', 0), ...
    'minimumSuccessorCrossEdges', 'ceil');
if minimumCurrentCrossEdges > maximumCurrentCrossEdges || ...
        minimumSuccessorCrossEdges > maximumSuccessorCrossEdges
    error(['Minimum joint rolling cross-edge counts cannot exceed ', ...
        'their corresponding maxima.']);
end
payloadDelta = reshape(getField( ...
    options, 'payloadDeltaByExample', ...
        zeros(exampleCount, 1)), [], 1);
if numel(payloadDelta) ~= exampleCount || ...
        any(~isfinite(payloadDelta))
    error('Joint rolling payload deltas must be finite and aligned.');
end
maximumCurrentPayloadIncreaseBytes = getField( ...
    options, 'maximumCurrentPayloadIncreaseBytes', inf);
maximumSuccessorPayloadIncreaseBytes = getField( ...
    options, 'maximumSuccessorPayloadIncreaseBytes', inf);
validatePayloadLimit( ...
    maximumCurrentPayloadIncreaseBytes, ...
    'maximumCurrentPayloadIncreaseBytes');
validatePayloadLimit( ...
    maximumSuccessorPayloadIncreaseBytes, ...
    'maximumSuccessorPayloadIncreaseBytes');

currentAllowedMask = arrayfun(@(idx) currentAllowed( ...
    senderGroups(idx), receiverGroups(idx)), ...
    (1:exampleCount)');
successorAllowedMask = arrayfun(@(idx) successorAllowed( ...
    senderGroups(idx), receiverGroups(idx)), ...
    (1:exampleCount)');
currentAllowedExampleMask = reshape(getField( ...
    options, 'currentAllowedExampleMask', ...
        true(exampleCount, 1)), [], 1);
if numel(currentAllowedExampleMask) ~= exampleCount || ...
        any(~isfinite(currentAllowedExampleMask))
    error(['currentAllowedExampleMask must be a finite logical ', ...
        'vector aligned with the current examples.']);
end
currentAllowedExampleMask = logical(currentAllowedExampleMask);
currentRequiredReceiverMask = reshape(getField( ...
    options, 'currentRequiredReceiverMask', ...
        false(nodeCount, 1)), [], 1);
if numel(currentRequiredReceiverMask) ~= nodeCount || ...
        any(~isfinite(currentRequiredReceiverMask))
    error(['currentRequiredReceiverMask must be a finite logical ', ...
        'vector aligned with the receivers.']);
end
currentRequiredReceiverMask = ...
    logical(currentRequiredReceiverMask);
currentAllowedMask = currentAllowedMask & ...
    currentAllowedExampleMask;
currentUpper = double(isfinite(currentScores) & currentAllowedMask);
successorUpper = double( ...
    isfinite(successorScores) & successorAllowedMask);
upperBounds = [currentUpper; successorUpper];
lowerBounds = zeros(2 * exampleCount, 1);
safeCurrentScores = currentScores;
safeCurrentScores(~isfinite(safeCurrentScores)) = 0;
safeSuccessorScores = successorScores;
safeSuccessorScores(~isfinite(safeSuccessorScores)) = 0;

[A, b, constraintTypes, contract] = buildConstraints( ...
    nodeCount, groupCount, receiverIndices, senderIndices, ...
    receiverGroups, senderGroups, sensorHistory, ...
    formationHistory, baselineSources, windowLength, ...
    minimumCurrentCrossEdges, maximumCurrentCrossEdges, ...
    minimumSuccessorCrossEdges, maximumSuccessorCrossEdges, ...
    payloadDelta, maximumCurrentPayloadIncreaseBytes, ...
    maximumSuccessorPayloadIncreaseBytes, ...
    currentRequired, successorRequired, ...
    currentRequiredReceiverMask);
if exampleCount == 0
    if ~zeroVectorSatisfiesConstraints(b, constraintTypes)
        error('RollingMatching:Infeasible', [ ...
            'No cross-formation examples are available and the ', ...
            'baseline-only current/successor route violates the ', ...
            'registered rolling constraints.']);
    end
    primaryObjective = 0;
    secondaryObjective = 0;
    solution = zeros(0, 1);
else
    if exist('glpk', 'file') ~= 2
        error('RollingMatching:SolverUnavailable', ...
            'Joint rolling matching requires GLPK.');
    end
    solverTimeLimitSeconds = getField( ...
        options, 'solverTimeLimitSeconds', 10);
    if ~isscalar(solverTimeLimitSeconds) || ...
            ~isfinite(solverTimeLimitSeconds) || ...
            solverTimeLimitSeconds <= 0
        error('solverTimeLimitSeconds must be positive and finite.');
    end
    solverOptions = struct( ...
        'msglev', max(0, round(getField( ...
            options, 'solverMessageLevel', 0))), ...
        'tmlim', max(1, round(1000 * solverTimeLimitSeconds)));
    variableTypes = repmat('I', 1, 2 * exampleCount);

    primaryObjectiveVector = [ ...
        safeCurrentScores; zeros(exampleCount, 1)];
    [~, primaryObjective] = solveBinaryProgram( ...
        primaryObjectiveVector, A, b, constraintTypes, ...
        lowerBounds, upperBounds, variableTypes, solverOptions);
    primaryTolerance = objectiveTolerance(primaryObjective);
    secondaryA = [A; sparse(reshape( ...
        primaryObjectiveVector, 1, []))];
    secondaryB = [b; primaryObjective - primaryTolerance];
    secondaryTypes = [constraintTypes, 'L'];
    secondaryObjectiveVector = [ ...
        zeros(exampleCount, 1); safeSuccessorScores];
    [~, secondaryObjective] = solveBinaryProgram( ...
        secondaryObjectiveVector, secondaryA, secondaryB, ...
        secondaryTypes, lowerBounds, upperBounds, ...
        variableTypes, solverOptions);
    secondaryTolerance = objectiveTolerance(secondaryObjective);
    tertiaryA = [secondaryA; sparse(reshape( ...
        secondaryObjectiveVector, 1, []))];
    tertiaryB = [secondaryB; ...
        secondaryObjective - secondaryTolerance];
    tertiaryTypes = [secondaryTypes, 'L'];
    [solution, ~] = solveBinaryProgram( ...
        -ones(2 * exampleCount, 1), ...
        tertiaryA, tertiaryB, tertiaryTypes, ...
        lowerBounds, upperBounds, variableTypes, solverOptions);
end

currentMask = solution(1:exampleCount) > 0.5;
successorMask = solution(exampleCount + (1:exampleCount)) > 0.5;
joint = struct();
joint.current = buildSelection( ...
    currentMask, receiverIndices, senderIndices, ...
    receiverGroups, senderGroups, safeCurrentScores, ...
    payloadDelta, groupCount, nodeCount, ...
    maximumCurrentCrossEdges, ...
    maximumCurrentPayloadIncreaseBytes, ...
    formationHistory, contract.currentWindowMature, ...
    contract.successorWindowMature);
joint.successor = buildSelection( ...
    successorMask, receiverIndices, senderIndices, ...
    receiverGroups, senderGroups, safeSuccessorScores, ...
    payloadDelta, groupCount, nodeCount, ...
    maximumSuccessorCrossEdges, ...
    maximumSuccessorPayloadIncreaseBytes, ...
    false(groupCount, groupCount, 0), false, false);
joint.primaryOptimalCurrentObjective = primaryObjective;
joint.secondaryOptimalSuccessorObjective = secondaryObjective;
joint.minimumCurrentCrossEdges = minimumCurrentCrossEdges;
joint.maximumCurrentCrossEdges = maximumCurrentCrossEdges;
joint.minimumSuccessorCrossEdges = minimumSuccessorCrossEdges;
joint.maximumSuccessorCrossEdges = maximumSuccessorCrossEdges;
joint.currentWindowMature = contract.currentWindowMature;
joint.successorWindowMature = contract.successorWindowMature;
joint.currentFormationWindowAdjacency = ...
    contract.currentFixedFormationUnion | ...
    joint.current.formationAdjacency;
joint.successorFormationWindowAdjacency = ...
    contract.successorFixedFormationUnion | ...
    joint.current.formationAdjacency | ...
    joint.successor.formationAdjacency;
joint.currentFormationWindowStrong = ...
    ~contract.currentWindowMature || isStronglyConnected( ...
        joint.currentFormationWindowAdjacency);
joint.successorFormationWindowStrong = ...
    ~contract.successorWindowMature || isStronglyConnected( ...
        joint.successorFormationWindowAdjacency);
joint.current.windowFormationAdjacency = ...
    joint.currentFormationWindowAdjacency;
joint.current.windowMature = contract.currentWindowMature;
joint.current.rollingUnionStrongConnected = ...
    joint.currentFormationWindowStrong;
joint.current.reserveViabilityEnforced = ...
    contract.successorWindowMature;
joint.current.successorReserveViable = ...
    joint.successorFormationWindowStrong;
joint.constraintCount = size(A, 1);
joint.currentConnectivityCutCount = ...
    contract.currentConnectivityCutCount;
joint.successorConnectivityCutCount = ...
    contract.successorConnectivityCutCount;
joint.cycleRestorationConstraintCount = ...
    contract.cycleRestorationConstraintCount;
joint.requiredCurrentReceiverConstraintCount = ...
    contract.requiredCurrentReceiverConstraintCount;
validateJointSelection(joint, sensorHistory, ...
    baselineSources, groupIds);
end

function valid = zeroVectorSatisfiesConstraints(b, types)
valid = true;
for row = 1:numel(b)
    switch types(row)
        case 'U'
            rowValid = 0 <= b(row) + 1e-12;
        case 'L'
            rowValid = 0 + 1e-12 >= b(row);
        case 'S'
            rowValid = abs(b(row)) <= 1e-12;
        otherwise
            error('Unknown GLPK constraint type: %s', types(row));
    end
    if ~rowValid
        valid = false;
        return;
    end
end
end

function [A, b, types, contract] = buildConstraints( ...
        nodeCount, groupCount, receiverIndices, senderIndices, ...
        receiverGroups, senderGroups, sensorHistory, ...
        formationHistory, baselineSources, windowLength, ...
        minimumCurrentCrossEdges, maximumCurrentCrossEdges, ...
        minimumSuccessorCrossEdges, maximumSuccessorCrossEdges, ...
        payloadDelta, maximumCurrentPayloadIncreaseBytes, ...
        maximumSuccessorPayloadIncreaseBytes, ...
        currentRequired, successorRequired, ...
        currentRequiredReceiverMask)
exampleCount = numel(receiverIndices);
variableCount = 2 * exampleCount;
A = sparse(0, variableCount);
b = zeros(0, 1);
types = '';
row = 0;
for page = 1:2
    offset = (page - 1) * exampleCount;
    for receiverIdx = 1:nodeCount
        row = row + 1;
        A(row, offset + find( ...
            receiverIndices == receiverIdx)) = 1;
        b(row, 1) = 1;
        types(end + 1) = 'U'; %#ok<AGROW>
    end
    for senderIdx = 1:nodeCount
        row = row + 1;
        A(row, offset + find( ...
            senderIndices == senderIdx)) = 1;
        b(row, 1) = 1;
        types(end + 1) = 'U'; %#ok<AGROW>
    end
    for senderGroup = 1:groupCount
        for receiverGroup = 1:groupCount
            if senderGroup == receiverGroup
                continue;
            end
            row = row + 1;
            pairMask = senderGroups == senderGroup & ...
                receiverGroups == receiverGroup;
            A(row, offset + find(pairMask)) = 1;
            b(row, 1) = 1;
            types(end + 1) = 'U'; %#ok<AGROW>
        end
    end
end
row = row + 1;
A(row, 1:exampleCount) = 1;
b(row, 1) = maximumCurrentCrossEdges;
types(end + 1) = 'U';
row = row + 1;
A(row, 1:exampleCount) = 1;
b(row, 1) = minimumCurrentCrossEdges;
types(end + 1) = 'L';
row = row + 1;
A(row, exampleCount + (1:exampleCount)) = 1;
b(row, 1) = maximumSuccessorCrossEdges;
types(end + 1) = 'U';
row = row + 1;
A(row, exampleCount + (1:exampleCount)) = 1;
b(row, 1) = minimumSuccessorCrossEdges;
types(end + 1) = 'L';
if isfinite(maximumCurrentPayloadIncreaseBytes)
    row = row + 1;
    A(row, 1:exampleCount) = reshape(payloadDelta, 1, []);
    b(row, 1) = maximumCurrentPayloadIncreaseBytes;
    types(end + 1) = 'U';
end
if isfinite(maximumSuccessorPayloadIncreaseBytes)
    row = row + 1;
    A(row, exampleCount + (1:exampleCount)) = ...
        reshape(payloadDelta, 1, []);
    b(row, 1) = maximumSuccessorPayloadIncreaseBytes;
    types(end + 1) = 'U';
end
[A, b, types, row] = appendRequiredPairs( ...
    A, b, types, row, currentRequired, 0, ...
    receiverGroups, senderGroups);
[A, b, types, row] = appendRequiredPairs( ...
    A, b, types, row, successorRequired, exampleCount, ...
    receiverGroups, senderGroups);
requiredReceiverConstraintCount = 0;
for receiverIdx = reshape(find( ...
        currentRequiredReceiverMask), 1, [])
    row = row + 1;
    A(row, find(receiverIndices == receiverIdx)) = 1;
    b(row, 1) = 1;
    types(end + 1) = 'L'; %#ok<AGROW>
    requiredReceiverConstraintCount = ...
        requiredReceiverConstraintCount + 1;
end

historyCount = size(sensorHistory, 3);
currentWindowMature = historyCount >= windowLength - 1;
successorWindowMature = historyCount + 2 >= windowLength;
currentFixedFormationUnion = any(formationHistory, 3);
successorFixedFormationUnion = false(groupCount);
if historyCount > 0
    successorFixedFormationUnion = ...
        formationHistory(:, :, end);
end
currentCutCount = 0;
if currentWindowMature
    [A, b, types, row, currentCutCount] = ...
        appendConnectivityCuts( ...
            A, b, types, row, ...
            currentFixedFormationUnion, ...
            receiverGroups, senderGroups, ...
            groupCount, 0, false);
end
successorCutCount = 0;
if successorWindowMature
    [A, b, types, row, successorCutCount] = ...
        appendConnectivityCuts( ...
            A, b, types, row, ...
            successorFixedFormationUnion, ...
            receiverGroups, senderGroups, ...
            groupCount, exampleCount, true);
end

cycleConstraintCount = 0;
if currentWindowMature
    for receiverIdx = 1:nodeCount
        baselineSender = baselineSources(receiverIdx);
        if any(reshape(sensorHistory( ...
                receiverIdx, baselineSender, :), 1, []))
            continue;
        end
        row = row + 1;
        A(row, find(receiverIndices == receiverIdx)) = 1;
        b(row, 1) = 0;
        types(end + 1) = 'U'; %#ok<AGROW>
        cycleConstraintCount = cycleConstraintCount + 1;
    end
end
if successorWindowMature
    latestHistory = sensorHistory(:, :, end);
    for receiverIdx = 1:nodeCount
        baselineSender = baselineSources(receiverIdx);
        if latestHistory(receiverIdx, baselineSender)
            continue;
        end
        receiverExamples = find(receiverIndices == receiverIdx);
        row = row + 1;
        A(row, receiverExamples) = 1;
        A(row, exampleCount + receiverExamples) = 1;
        b(row, 1) = 1;
        types(end + 1) = 'U'; %#ok<AGROW>
        cycleConstraintCount = cycleConstraintCount + 1;
    end
end
contract = struct( ...
    'currentWindowMature', currentWindowMature, ...
    'successorWindowMature', successorWindowMature, ...
    'currentFixedFormationUnion', ...
        currentFixedFormationUnion, ...
    'successorFixedFormationUnion', ...
        successorFixedFormationUnion, ...
    'currentConnectivityCutCount', currentCutCount, ...
    'successorConnectivityCutCount', successorCutCount, ...
    'cycleRestorationConstraintCount', cycleConstraintCount, ...
    'requiredCurrentReceiverConstraintCount', ...
        requiredReceiverConstraintCount);
end

function [A, b, types, row] = appendRequiredPairs( ...
        A, b, types, row, required, offset, ...
        receiverGroups, senderGroups)
for senderGroup = 1:size(required, 1)
    for receiverGroup = 1:size(required, 2)
        if ~required(senderGroup, receiverGroup)
            continue;
        end
        pairExamples = find( ...
            senderGroups == senderGroup & ...
            receiverGroups == receiverGroup);
        row = row + 1;
        A(row, offset + pairExamples) = 1;
        b(row, 1) = 1;
        types(end + 1) = 'L'; %#ok<AGROW>
    end
end
end

function [A, b, types, row, addedCount] = ...
        appendConnectivityCuts( ...
            A, b, types, row, fixedUnion, ...
            receiverGroups, senderGroups, groupCount, ...
            successorOffset, includeCurrent)
exampleCount = numel(receiverGroups);
addedCount = 0;
for subsetMask = 1:(2 ^ groupCount - 2)
    inside = logical(bitget(subsetMask, 1:groupCount));
    if any(any(fixedUnion(inside, ~inside)))
        continue;
    end
    crossing = find(inside(senderGroups) & ...
        ~inside(receiverGroups));
    row = row + 1;
    if includeCurrent
        A(row, crossing) = 1;
    end
    A(row, successorOffset + crossing) = 1;
    b(row, 1) = 1;
    types(end + 1) = 'L'; %#ok<AGROW>
    addedCount = addedCount + 1;
end
if includeCurrent && successorOffset ~= exampleCount
    error('Successor cut offset is inconsistent.');
end
end

function selection = buildSelection( ...
        mask, receiverIndices, senderIndices, ...
        receiverGroups, senderGroups, scores, payloadDelta, ...
        groupCount, nodeCount, maximumCrossEdges, ...
        maximumPayloadIncreaseBytes, formationHistory, ...
        windowMature, reserveViabilityEnforced)
selectedExamples = find(mask);
formationAdjacency = false(groupCount);
for exampleIdx = reshape(selectedExamples, 1, [])
    formationAdjacency( ...
        senderGroups(exampleIdx), ...
        receiverGroups(exampleIdx)) = true;
end
windowFormationAdjacency = formationAdjacency;
if ~isempty(formationHistory)
    windowFormationAdjacency = ...
        windowFormationAdjacency | any(formationHistory, 3);
end
selection = struct( ...
    'exampleIndices', reshape(selectedExamples, 1, []), ...
    'receiverIndices', reshape( ...
        receiverIndices(selectedExamples), 1, []), ...
    'senderIndices', reshape( ...
        senderIndices(selectedExamples), 1, []), ...
    'predictedObjective', sum(scores(selectedExamples)), ...
    'primaryOptimalObjective', NaN, ...
    'crossEdgeCount', nnz(mask), ...
    'maximumCrossEdges', maximumCrossEdges, ...
    'maximumCrossSourceLoad', maximumLoad( ...
        senderIndices(selectedExamples), nodeCount), ...
    'maximumCrossReceiverLoad', maximumLoad( ...
        receiverIndices(selectedExamples), nodeCount), ...
    'selectedPayloadDeltaBytes', ...
        sum(payloadDelta(selectedExamples)), ...
    'maximumPayloadIncreaseBytes', ...
        maximumPayloadIncreaseBytes, ...
    'formationAdjacency', formationAdjacency, ...
    'windowFormationAdjacency', ...
        windowFormationAdjacency, ...
    'rollingUnionStrongConnected', ...
        ~windowMature || ...
        isStronglyConnected(windowFormationAdjacency), ...
    'connectivityWindowLength', 3, ...
    'historyCount', size(formationHistory, 3), ...
    'windowMature', windowMature, ...
    'connectivityConstraintEnforced', windowMature, ...
    'reserveViabilityEnforced', reserveViabilityEnforced, ...
    'successorReserveViable', true);
end

function validateJointSelection( ...
        joint, sensorHistory, baselineSources, groupIds)
nodeCount = numel(groupIds);
currentSources = baselineSources;
currentSources(joint.current.receiverIndices) = ...
    joint.current.senderIndices;
successorSources = baselineSources;
successorSources(joint.successor.receiverIndices) = ...
    joint.successor.senderIndices;
currentAdjacency = sourceMapToAdjacency( ...
    currentSources, nodeCount);
successorAdjacency = sourceMapToAdjacency( ...
    successorSources, nodeCount);
if joint.currentWindowMature
    currentUnion = currentAdjacency | any(sensorHistory, 3);
    if ~isStronglyConnected(currentUnion')
        error('Joint rolling solver violated current sensor B-window safety.');
    end
end
if joint.successorWindowMature
    successorUnion = currentAdjacency | successorAdjacency;
    if ~isempty(sensorHistory)
        successorUnion = ...
            successorUnion | sensorHistory(:, :, end);
    end
    if ~isStronglyConnected(successorUnion')
        error(['Joint rolling solver violated successor sensor ', ...
            'B-window safety.']);
    end
end
if ~joint.currentFormationWindowStrong || ...
        ~joint.successorFormationWindowStrong
    error('Joint rolling solver violated a formation B-window cut.');
end
end

function adjacency = sourceMapToAdjacency(sources, nodeCount)
adjacency = false(nodeCount);
for receiverIdx = 1:nodeCount
    adjacency(receiverIdx, sources(receiverIdx)) = true;
end
end

function [x, objective] = solveBinaryProgram( ...
        objectiveVector, A, b, types, lowerBounds, ...
        upperBounds, variableTypes, solverOptions)
[x, objective, errorNumber, extra] = glpk( ...
    objectiveVector, A, b, lowerBounds, upperBounds, ...
    types, variableTypes, -1, solverOptions);
status = NaN;
if isstruct(extra) && isfield(extra, 'status')
    status = extra.status;
end
if any(errorNumber == [10, 15]) || any(status == [3, 4])
    error('RollingMatching:Infeasible', [ ...
        'No feasible joint rolling matching exists ', ...
        '(glpk error %d, status %g).'], errorNumber, status);
end
if errorNumber ~= 0
    error('RollingMatching:SolverFailure', [ ...
        'Joint rolling matching solver failed ', ...
        '(glpk error %d, status %g).'], errorNumber, status);
end
if status ~= 5 || isempty(x) || any(~isfinite(x))
    error('RollingMatching:SolverFailure', [ ...
        'Joint rolling matching did not return a certified optimum ', ...
        '(glpk error %d, status %g).'], errorNumber, status);
end
end

function tolerance = objectiveTolerance(value)
tolerance = max(1e-10, 1e-10 * max(1, abs(value)));
end

function history = normalizeSensorHistory( ...
        history, nodeCount, windowLength)
if isempty(history)
    history = false(nodeCount, nodeCount, 0);
    return;
end
history = logical(history);
if ndims(history) < 3
    if ~isequal(size(history), [nodeCount, nodeCount])
        error('Joint rolling sensor history must be S-by-S-by-H.');
    end
    history = reshape(history, nodeCount, nodeCount, 1);
elseif size(history, 1) ~= nodeCount || ...
        size(history, 2) ~= nodeCount
    error('Joint rolling sensor history must be S-by-S-by-H.');
end
maximumHistory = max(0, windowLength - 1);
if size(history, 3) > maximumHistory
    history = history(:, :, end-maximumHistory+1:end);
end
end

function history = formationHistoryFromSensorHistory( ...
        sensorHistory, groupIds, groups)
groupCount = numel(groups);
history = false(groupCount, groupCount, ...
    size(sensorHistory, 3));
for historyIdx = 1:size(sensorHistory, 3)
    page = sensorHistory(:, :, historyIdx);
    for receiverIdx = 1:numel(groupIds)
        receiverGroup = find( ...
            groups == groupIds(receiverIdx), 1);
        for senderIdx = reshape(find( ...
                page(receiverIdx, :)), 1, [])
            senderGroup = find( ...
                groups == groupIds(senderIdx), 1);
            if senderGroup ~= receiverGroup
                history(senderGroup, receiverGroup, ...
                    historyIdx) = true;
            end
        end
    end
end
end

function adjacency = normalizeFormationAdjacency( ...
        adjacency, groupCount, fieldName)
if ~isequal(size(adjacency), [groupCount, groupCount]) || ...
        any(~isfinite(adjacency(:)))
    error('%s must be a finite G-by-G matrix.', fieldName);
end
adjacency = logical(adjacency);
adjacency(1:groupCount+1:end) = false;
end

function mapped = mapGroups(groupIds, groups, sensorIndices)
mapped = zeros(size(sensorIndices));
for cursor = 1:numel(sensorIndices)
    mapped(cursor) = find( ...
        groups == groupIds(sensorIndices(cursor)), 1);
end
end

function load = maximumLoad(indices, nodeCount)
if isempty(indices)
    load = 0;
    return;
end
counts = accumarray( ...
    reshape(indices, [], 1), 1, [nodeCount, 1]);
load = max(counts);
end

function valid = isStronglyConnected(adjacency)
valid = all(reachableFrom(adjacency, 1)) && ...
    all(reachableFrom(adjacency', 1));
end

function reached = reachableFrom(adjacency, startNode)
reached = false(1, size(adjacency, 1));
frontier = startNode;
while ~isempty(frontier)
    node = frontier(end);
    frontier(end) = [];
    if reached(node)
        continue;
    end
    reached(node) = true;
    next = find(adjacency(node, :) & ~reached);
    frontier = [frontier, reshape(next, 1, [])]; %#ok<AGROW>
end
end

function validatePayloadLimit(value, fieldName)
if ~isscalar(value) || isnan(value) || value < 0
    error('%s must be a nonnegative scalar or inf.', fieldName);
end
end

function value = normalizeCrossEdgeLimit( ...
        value, fieldName, roundingMode)
if ~isscalar(value) || ~isfinite(value) || value < 0
    error('%s must be a finite nonnegative scalar.', fieldName);
end
if strcmp(roundingMode, 'ceil')
    value = ceil(value);
else
    value = floor(value);
end
end

function validateBaselineBackbone( ...
        baselineSources, groupIds, groups)
nodeCount = numel(groupIds);
baseline = sourceMapToAdjacency( ...
    baselineSources, nodeCount)';
for group = groups
    members = find(groupIds == group);
    if numel(members) < 2 || ...
            any(groupIds(baselineSources(members)) ~= group) || ...
            ~isStronglyConnected(baseline(members, members))
        error([ ...
            'Joint rolling baseline must be a strongly connected ', ...
            'intra-formation backbone.']);
    end
end
end

