function schedule = buildFormationDebtCoverageReleaseSchedule( ...
        groups, selectedFormationIds, debtFractionByFormation, ...
        suspensionAgeByFormation, minimumSuspensionAge, ...
        minimumRetainedDebtCoverage)
% BUILDFORMATIONDEBTCOVERAGERELEASESCHEDULE Nested causal release plan.
%
% Previously suspended formations are considered from lowest to highest
% current retention debt. A release is proposed only while the remaining
% suspended set preserves the registered fraction of total positive debt.
% The resulting family contains at most F nested candidates.

groups = reshape(groups, 1, []);
selectedFormationIds = reshape(selectedFormationIds, 1, []);
debtFractionByFormation = reshape( ...
    debtFractionByFormation, 1, []);
suspensionAgeByFormation = reshape( ...
    suspensionAgeByFormation, 1, []);
if isempty(groups) || numel(unique(groups)) ~= numel(groups) || ...
        numel(debtFractionByFormation) ~= numel(groups) || ...
        numel(suspensionAgeByFormation) ~= numel(groups) || ...
        any(~isfinite(debtFractionByFormation)) || ...
        any(~isfinite(suspensionAgeByFormation)) || ...
        any(suspensionAgeByFormation < 0) || ...
        any(suspensionAgeByFormation ~= ...
            round(suspensionAgeByFormation)) || ...
        numel(unique(selectedFormationIds)) ~= ...
            numel(selectedFormationIds) || ...
        any(~ismember(selectedFormationIds, groups)) || ...
        ~isscalar(minimumSuspensionAge) || ...
        ~isfinite(minimumSuspensionAge) || ...
        minimumSuspensionAge ~= round(minimumSuspensionAge) || ...
        minimumSuspensionAge < 1 || ...
        ~isscalar(minimumRetainedDebtCoverage) || ...
        ~isfinite(minimumRetainedDebtCoverage) || ...
        minimumRetainedDebtCoverage <= 0 || ...
        minimumRetainedDebtCoverage > 1
    error('DebtCoverageRelease:InvalidContract', ...
        'Debt-coverage release inputs are invalid.');
end

selectedMask = ismember(groups, selectedFormationIds);
positiveDebt = max(debtFractionByFormation, 0);
totalSelectedDebt = sum(positiveDebt(selectedMask));
matureMask = selectedMask & ...
    suspensionAgeByFormation >= minimumSuspensionAge;
matureIndices = find(matureMask);
if isempty(matureIndices) || totalSelectedDebt <= eps
    releaseOrder = zeros(1, 0);
else
    ranking = [ ...
        positiveDebt(matureIndices)', groups(matureIndices)'];
    [~, order] = sortrows(ranking, [1, 2]);
    releaseOrder = groups(matureIndices(order));
end

candidateRetainedFormationIds = cell(1, 0);
candidateReleasedFormationIds = cell(1, 0);
candidateRetainedDebtCoverage = zeros(1, 0);
remaining = selectedFormationIds;
released = zeros(1, 0);
for releaseIdx = 1:numel(releaseOrder)
    released(end + 1) = releaseOrder(releaseIdx); %#ok<AGROW>
    remaining = remaining(~ismember(remaining, released));
    retainedMask = ismember(groups, remaining);
    coverage = sum(positiveDebt(retainedMask)) / ...
        max(totalSelectedDebt, eps);
    if isempty(remaining) || ...
            coverage < minimumRetainedDebtCoverage - 1e-12
        break;
    end
    candidateRetainedFormationIds{end + 1} = ...
        remaining; %#ok<AGROW>
    candidateReleasedFormationIds{end + 1} = ...
        released; %#ok<AGROW>
    candidateRetainedDebtCoverage(end + 1) = ...
        coverage; %#ok<AGROW>
end

schedule = struct();
schedule.contractVersion = ...
    'formation-debt-coverage-release-schedule-v1';
schedule.groups = groups;
schedule.selectedFormationIds = selectedFormationIds;
schedule.debtFractionByFormation = debtFractionByFormation;
schedule.suspensionAgeByFormation = suspensionAgeByFormation;
schedule.minimumSuspensionAge = minimumSuspensionAge;
schedule.minimumRetainedDebtCoverage = ...
    minimumRetainedDebtCoverage;
schedule.totalSelectedPositiveDebt = totalSelectedDebt;
schedule.matureFormationIds = groups(matureMask);
schedule.releaseOrder = releaseOrder;
schedule.candidateRetainedFormationIds = ...
    candidateRetainedFormationIds;
schedule.candidateReleasedFormationIds = ...
    candidateReleasedFormationIds;
schedule.candidateRetainedDebtCoverage = ...
    candidateRetainedDebtCoverage;
schedule.candidateCount = ...
    numel(candidateRetainedFormationIds);
schedule.truthUsed = false;
schedule.futureOutcomeUsed = false;
end
