function [candidateAdjacency, candidateRecords, metadata] = ...
    buildPrivilegedRollingSafeJointActionProposalBank(context, options)
% BUILDPRIVILEGEDROLLINGSAFEJOINTACTIONPROPOSALBANK Offline graph targets.
%
% This bank runs the truth-labelled current-risk teacher and its diverse
% leave-one-selected-edge alternatives through the exact rolling-B=3
% projector.  It is an offline proposal-coverage denominator and proposal
% distillation target only; no graph from this function is deployable.

if nargin < 2 || isempty(options)
    options = struct();
end
actionCodes = reshape(getField( ...
    options, 'actionCodes', [0, 90:99]), 1, []);
if isempty(actionCodes) || ...
        any(~ismember(actionCodes, [0, 90:99])) || ...
        numel(unique(actionCodes)) ~= numel(actionCodes)
    error(['Privileged proposal codes must be a distinct subset of ', ...
        '[0, 90:99].']);
end
sourceWeight = getField(options, 'sourceWeight', 0.70);
payloadToleranceFraction = getField( ...
    options, 'payloadToleranceFraction', inf);
scoreOptions = getField(options, 'scoreOptions', struct( ...
    'sourceWeight', sourceWeight, ...
    'horizonSteps', 0, ...
    'discountFactor', 0.9));
policyOptions = struct( ...
    'sourceWeight', sourceWeight, ...
    'payloadToleranceFraction', payloadToleranceFraction, ...
    'scoreOptions', scoreOptions);
nodeCount = numel(context.localPosteriorBySensor);
if nodeCount < 2 || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount])
    error('Privileged proposal context has an invalid physical graph.');
end

recordTemplate = struct( ...
    'candidateIndex', NaN, ...
    'actionCode', NaN, ...
    'proposalActionCodes', [], ...
    'eligibleForProposalDistillation', false, ...
    'graphSha256', '', ...
    'selectedSourcesByReceiver', [], ...
    'crossFormationMessageCount', NaN, ...
    'policyDetails', struct());
attemptTemplate = struct( ...
    'actionCode', NaN, ...
    'status', '', ...
    'candidateIndex', NaN, ...
    'duplicateOfCandidateIndex', NaN, ...
    'failureIdentifier', '', ...
    'failureMessage', '');
candidateAdjacency = false(nodeCount, nodeCount, 0);
candidateRecords = repmat(recordTemplate, 1, 0);
attemptRecords = repmat(attemptTemplate, 1, numel(actionCodes));
graphKeys = cell(1, 0);
[defaultAdjacency, defaultDetails] = ...
    selectRollingSafeActionSequencePolicy( ...
        context, 0, context.currentTime, ...
        policyOptions);
for actionIdx = 1:numel(actionCodes)
    actionCode = actionCodes(actionIdx);
    attempt = attemptTemplate;
    attempt.actionCode = actionCode;
    try
        if actionCode == 0
            adjacency = defaultAdjacency;
            details = defaultDetails;
        else
            diverseOptions = policyOptions;
            diverseOptions.cachedDefaultAdjacency = ...
                defaultAdjacency;
            diverseOptions.cachedDefaultDetails = ...
                defaultDetails;
            [adjacency, details] = ...
                selectRollingSafeDiverseTeacherPolicy( ...
                    context, actionCode - 89, ...
                    diverseOptions);
            details.actionSequenceCodes = actionCode;
            details.actionSequenceCode = actionCode;
            details.actionSequenceBranch = sprintf( ...
                'privileged-diverse-current-risk-%d', ...
                actionCode - 89);
            details.actionSequenceAnchorTime = ...
                context.currentTime;
            details.actionSequenceRelativeTime = 1;
            details.actionSequenceTruthUsed = true;
        end
        validatePrivilegedProposal( ...
            adjacency, details, context);
        selectedSources = reshape( ...
            details.selectedSourcesByReceiver, 1, []);
        graphKey = sprintf('%d,', selectedSources);
        duplicateIdx = find(strcmp(graphKeys, graphKey), 1);
        eligible = ...
            ~logical(details.repairTriggered) && ...
            ~logical(details.payloadEmergencyUsed);
        if ~isempty(duplicateIdx)
            candidateRecords(duplicateIdx).proposalActionCodes = ...
                [candidateRecords(duplicateIdx).proposalActionCodes, ...
                 actionCode];
            if eligible && ...
                    ~candidateRecords(duplicateIdx). ...
                        eligibleForProposalDistillation
                candidateRecords(duplicateIdx).actionCode = actionCode;
                candidateRecords(duplicateIdx). ...
                    eligibleForProposalDistillation = true;
                candidateRecords(duplicateIdx).policyDetails = details;
                attempt.status = ...
                    'duplicate-upgraded-distillation-target';
            else
                attempt.status = 'duplicate-complete-graph';
            end
            attempt.duplicateOfCandidateIndex = duplicateIdx;
            attemptRecords(actionIdx) = attempt;
            continue;
        end
        candidateIdx = size(candidateAdjacency, 3) + 1;
        candidateAdjacency(:, :, candidateIdx) = adjacency;
        graphKeys{candidateIdx} = graphKey; %#ok<AGROW>
        record = recordTemplate;
        record.candidateIndex = candidateIdx;
        record.actionCode = actionCode;
        record.proposalActionCodes = actionCode;
        record.eligibleForProposalDistillation = eligible;
        record.graphSha256 = computeTextSha256(graphKey);
        record.selectedSourcesByReceiver = selectedSources;
        record.crossFormationMessageCount = ...
            details.crossFormationMessageCount;
        record.policyDetails = details;
        candidateRecords(candidateIdx) = record;
        attempt.candidateIndex = candidateIdx;
        if eligible
            attempt.status = 'accepted-distillation-target';
        else
            attempt.status = ...
                'accepted-repaired-diagnostic-only';
        end
    catch errorInfo
        if ~isUnavailable(errorInfo)
            rethrow(errorInfo);
        end
        attempt.status = 'unavailable';
        attempt.failureIdentifier = errorInfo.identifier;
        attempt.failureMessage = errorInfo.message;
    end
    attemptRecords(actionIdx) = attempt;
end
if isempty(candidateRecords)
    error('PrivilegedProposalBank:Empty', ...
        'No privileged safe graph was generated.');
end

metadata = struct();
metadata.contractVersion = ...
    'privileged-rolling-safe-joint-action-proposal-bank-v1';
metadata.actionCodes = actionCodes;
metadata.sourceWeight = sourceWeight;
metadata.payloadToleranceFraction = ...
    payloadToleranceFraction;
metadata.proposalCount = numel(actionCodes);
metadata.distinctCandidateCount = ...
    size(candidateAdjacency, 3);
metadata.distillationTargetCount = nnz( ...
    [candidateRecords.eligibleForProposalDistillation]);
metadata.duplicateCount = nnz(containsToken( ...
    {attemptRecords.status}, 'duplicate'));
metadata.unavailableCount = nnz(strcmp( ...
    {attemptRecords.status}, 'unavailable'));
metadata.attemptRecords = attemptRecords;
metadata.truthUsed = true;
metadata.futureOutcomeUsed = false;
metadata.deployable = false;
metadata.role = [ ...
    'offline-proposal-coverage-denominator-and-', ...
    'proposal-distillation-target'];
end

function validatePrivilegedProposal(adjacency, details, context)
nodeCount = numel(context.localPosteriorBySensor);
if ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        ~islogical(adjacency) || ...
        any(sum(adjacency, 2) ~= 1) || ...
        any(adjacency(:) & ...
            ~logical(context.physicalAdjacency(:)))
    error('PrivilegedProposalBank:InvalidGraph', ...
        'Privileged proposal returned an invalid complete graph.');
end
required = { ...
    'truthUsed', 'actionSequenceTruthUsed', ...
    'oneStepJointProjectionUsed', ...
    'sensorWindowStrongConnected', ...
    'formationWindowStrongConnected', ...
    'repairTriggered', 'payloadEmergencyUsed'};
for fieldIdx = 1:numel(required)
    if ~isfield(details, required{fieldIdx})
        error('PrivilegedProposalBank:MissingAttestation', ...
            'Privileged proposal lacks %s.', required{fieldIdx});
    end
end
if ~(logical(details.truthUsed) || ...
        logical(details.actionSequenceTruthUsed))
    error('PrivilegedProposalBank:TruthFlagMissing', ...
        'Offline privileged proposal did not attest truth use.');
end
if ~logical(details.oneStepJointProjectionUsed) || ...
        ~logical(details.sensorWindowStrongConnected) || ...
        ~logical(details.formationWindowStrongConnected)
    error('PrivilegedProposalBank:SafetyAttestationFailed', ...
        'Privileged proposal lacks rolling-B=3 safety.');
end
end

function unavailable = isUnavailable(errorInfo)
message = lower(errorInfo.message);
unavailable = ismember(errorInfo.identifier, { ...
    'RollingMatching:Infeasible', ...
    'DiverseTeacher:Unavailable'}) || ...
    ~isempty(strfind(message, ...
        'infeasible')) || ... %#ok<STREMP>
    ~isempty(strfind(message, ...
        'diverse teacher requested alternative')); %#ok<STREMP>
end

function mask = containsToken(values, token)
mask = false(size(values));
for valueIdx = 1:numel(values)
    mask(valueIdx) = ...
        ~isempty(strfind(values{valueIdx}, token)); %#ok<STREMP>
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
