function [candidateAdjacency, candidateRecords, metadata] = ...
    buildRollingSafeJointActionProposalBank(context, options)
% BUILDROLLINGSAFEJOINTACTIONPROPOSALBANK Truth-free safe joint actions.
%
% The frozen v1 bank combines one registered rolling control, nineteen
% semantic observable score directions, and eight analytic/local-diversity
% directions. Every proposal is passed through the same exact joint
% current/successor rolling-B=3 projector. Complete directed graphs are
% then deduplicated; no target truth or future outcome is read.
%
% This function only constructs a high-recall action set. It does not rank
% candidates or claim that any candidate improves tracking.

if nargin < 2 || isempty(options)
    options = struct();
end
protocol = getRollingSafeJointActionCriticProtocol();
contractVersion = protocol.proposalBankContractVersion;
actionCodes = reshape(getField( ...
    options, 'actionCodes', protocol.proposalActionCodes), 1, []);
if isempty(actionCodes) || any(~isfinite(actionCodes)) || ...
        any(mod(actionCodes, 1) ~= 0) || ...
        numel(unique(actionCodes)) ~= numel(actionCodes)
    error(['Proposal-bank action codes must be distinct finite ', ...
        'integers.']);
end
if any(~ismember(actionCodes, protocol.proposalActionCodes))
    error(['Proposal-bank action codes must be a subset of the ', ...
        'frozen truth-free registry.']);
end
maximumCandidateCount = getField( ...
    options, 'maximumCandidateCount', ...
    protocol.maximumCandidateCount);
if ~isscalar(maximumCandidateCount) || ...
        ~isfinite(maximumCandidateCount) || ...
        maximumCandidateCount < 1 || ...
        mod(maximumCandidateCount, 1) ~= 0 || ...
        maximumCandidateCount > protocol.maximumCandidateCount
    error('maximumCandidateCount must be an integer in 1:%d.', ...
        protocol.maximumCandidateCount);
end
sourceWeight = getField( ...
    options, 'sourceWeight', protocol.sourceWeight);
payloadToleranceFraction = getField( ...
    options, 'payloadToleranceFraction', ...
    protocol.maximumAttemptedByteDeviationFraction);
if ~isscalar(payloadToleranceFraction) || ...
        ~isfinite(payloadToleranceFraction) || ...
        payloadToleranceFraction < 0 || ...
        payloadToleranceFraction > ...
            protocol.maximumAttemptedByteDeviationFraction + 1e-12
    error(['Proposal-bank payloadToleranceFraction must be finite, ', ...
        'nonnegative and no larger than the frozen byte gate.']);
end

nodeCount = numel(context.localPosteriorBySensor);
if nodeCount < 2 || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount])
    error('Proposal-bank context has an invalid physical action set.');
end
currentTime = round(context.currentTime);
if ~isscalar(currentTime) || ~isfinite(currentTime) || currentTime < 1
    error('Proposal-bank currentTime must be a positive integer.');
end

candidateAdjacency = false(nodeCount, nodeCount, 0);
candidateTemplate = struct( ...
    'candidateIndex', NaN, ...
    'proposalIndex', NaN, ...
    'actionCode', NaN, ...
    'proposalId', '', ...
    'branch', '', ...
    'graphSha256', '', ...
    'selectedSourcesByReceiver', [], ...
    'crossFormationMessageCount', NaN, ...
    'selectedPayloadDeltaBytes', NaN, ...
    'policyDetails', struct());
candidateRecords = repmat(candidateTemplate, 1, 0);
attemptTemplate = struct( ...
    'proposalIndex', NaN, ...
    'actionCode', NaN, ...
    'proposalId', '', ...
    'status', '', ...
    'candidateIndex', NaN, ...
    'duplicateOfCandidateIndex', NaN, ...
    'graphSha256', '', ...
    'failureIdentifier', '', ...
    'failureMessage', '');
attemptRecords = repmat(attemptTemplate, 1, numel(actionCodes));
graphKeys = cell(1, 0);

policyOptions = struct( ...
    'sourceWeight', sourceWeight, ...
    'payloadToleranceFraction', payloadToleranceFraction);
for proposalIdx = 1:numel(actionCodes)
    actionCode = actionCodes(proposalIdx);
    proposalId = sprintf('registered-action-%02d', actionCode);
    attempt = attemptTemplate;
    attempt.proposalIndex = proposalIdx;
    attempt.actionCode = actionCode;
    attempt.proposalId = proposalId;
    try
        [adjacency, details] = ...
            selectRollingSafeActionSequencePolicy( ...
                context, actionCode, currentTime, ...
                policyOptions);
        validateProjectedProposal( ...
            adjacency, details, context, protocol);
        selectedSources = reshape( ...
            details.selectedSourcesByReceiver, 1, []);
        graphKey = sprintf('%d,', selectedSources);
        graphSha256 = computeTextSha256(graphKey);
        duplicateIdx = find(strcmp(graphKeys, graphKey), 1);
        attempt.graphSha256 = graphSha256;
        if ~isempty(duplicateIdx)
            attempt.status = 'duplicate-complete-graph';
            attempt.duplicateOfCandidateIndex = duplicateIdx;
            attemptRecords(proposalIdx) = attempt;
            continue;
        end
        if size(candidateAdjacency, 3) >= maximumCandidateCount
            attempt.status = 'rejected-candidate-cap';
            attemptRecords(proposalIdx) = attempt;
            continue;
        end
        candidateIdx = size(candidateAdjacency, 3) + 1;
        candidateAdjacency(:, :, candidateIdx) = adjacency;
        graphKeys{candidateIdx} = graphKey; %#ok<AGROW>
        record = candidateTemplate;
        record.candidateIndex = candidateIdx;
        record.proposalIndex = proposalIdx;
        record.actionCode = actionCode;
        record.proposalId = proposalId;
        record.branch = details.actionSequenceBranch;
        record.graphSha256 = graphSha256;
        record.selectedSourcesByReceiver = selectedSources;
        record.crossFormationMessageCount = ...
            details.crossFormationMessageCount;
        record.selectedPayloadDeltaBytes = ...
            details.selectedPayloadDeltaBytes;
        record.policyDetails = details;
        candidateRecords(candidateIdx) = record;
        attempt.status = 'accepted-distinct';
        attempt.candidateIndex = candidateIdx;
    catch errorInfo
        if ~isRegisteredProposalUnavailable(errorInfo)
            rethrow(errorInfo);
        end
        attempt.status = 'unavailable';
        attempt.failureIdentifier = errorInfo.identifier;
        attempt.failureMessage = errorInfo.message;
    end
    attemptRecords(proposalIdx) = attempt;
end

referenceCandidateIndex = find( ...
    [candidateRecords.actionCode] == 24, 1);
if isempty(referenceCandidateIndex)
    error('ProposalBank:ReferenceUnavailable', [ ...
        'The frozen registered action-24 reference was not admitted ', ...
        'as a distinct nominally projected candidate.']);
end
if isempty(candidateRecords)
    error('ProposalBank:Empty', ...
        'No distinct rolling-safe joint action was generated.');
end
if size(candidateAdjacency, 3) > maximumCandidateCount
    error('Proposal bank exceeded its frozen candidate cap.');
end

metadata = struct();
metadata.contractVersion = contractVersion;
metadata.protocolId = protocol.id;
metadata.actionCodes = actionCodes;
metadata.actionCodeSetSha256 = computeTextSha256( ...
    sprintf('%02d,', actionCodes));
metadata.frozenActionCodeSetSha256 = ...
    protocol.proposalActionCodeSetSha256;
metadata.defaultFrozenBankUsed = ...
    isequal(actionCodes, protocol.proposalActionCodes);
metadata.sourceWeight = sourceWeight;
metadata.payloadToleranceFraction = ...
    payloadToleranceFraction;
metadata.maximumCandidateCount = maximumCandidateCount;
metadata.proposalCount = numel(actionCodes);
metadata.distinctCandidateCount = ...
    size(candidateAdjacency, 3);
metadata.duplicateCount = nnz(strcmp( ...
    {attemptRecords.status}, ...
    'duplicate-complete-graph'));
metadata.unavailableCount = nnz(strcmp( ...
    {attemptRecords.status}, 'unavailable'));
metadata.capRejectedCount = nnz(strcmp( ...
    {attemptRecords.status}, ...
    'rejected-candidate-cap'));
metadata.referenceActionCode = 24;
metadata.referenceCandidateIndex = referenceCandidateIndex;
metadata.attemptRecords = attemptRecords;
metadata.truthUsed = false;
metadata.futureOutcomeUsed = false;
metadata.candidateRankingPerformed = false;
metadata.trackingImprovementClaimed = false;
metadata.exactRollingProjectorRequired = true;
metadata.nominalProjectionRequired = true;
metadata.controlMetadataTrafficAccounted = ...
    protocol.controlMetadataTrafficAccounted;
end

function validateProjectedProposal( ...
        adjacency, details, context, protocol)
nodeCount = numel(context.localPosteriorBySensor);
if ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        ~islogical(adjacency) || ...
        any(sum(adjacency, 2) ~= 1) || ...
        any(adjacency(:) & ...
            ~logical(context.physicalAdjacency(:)))
    error('ProposalBank:InvalidGraph', ...
        'A proposal returned an invalid complete directed route.');
end
requiredFields = { ...
    'truthUsed', ...
    'actionSequenceTruthUsed', ...
    'oneStepJointProjectionUsed', ...
    'nominalProjectionFeasible', ...
    'repairProjectionAttempted', ...
    'repairTriggered', ...
    'payloadEmergencyUsed', ...
    'payloadConstraintEnforced', ...
    'payloadLimitPassed', ...
    'sensorWindowStrongConnected', ...
    'formationWindowStrongConnected', ...
    'oneStepTopologyReserveChecked', ...
    'oneStepTopologyReservePassed'};
for fieldIdx = 1:numel(requiredFields)
    if ~isfield(details, requiredFields{fieldIdx})
        error('ProposalBank:MissingAttestation', ...
            'Proposal details lack %s.', requiredFields{fieldIdx});
    end
end
if protocol.requireTruthFreeProposals && ...
        (logical(details.truthUsed) || ...
         logical(details.actionSequenceTruthUsed))
    error('ProposalBank:TruthContamination', ...
        'The proposal bank rejected a truth-assisted action.');
end
if ~logical(details.oneStepJointProjectionUsed) || ...
        ~logical(details.sensorWindowStrongConnected) || ...
        ~logical(details.formationWindowStrongConnected)
    error('ProposalBank:SafetyAttestationFailed', ...
        'The proposal lacks its rolling-B=3 safety attestation.');
end
if logical(details.oneStepTopologyReserveChecked) && ...
        ~logical(details.oneStepTopologyReservePassed)
    error('ProposalBank:ReserveAttestationFailed', ...
        'The mature one-step reserve witness did not pass.');
end
if protocol.requireNominalCandidateProjection && ...
        (~logical(details.nominalProjectionFeasible) || ...
         logical(details.repairProjectionAttempted) || ...
         logical(details.repairTriggered) || ...
         logical(details.payloadEmergencyUsed))
    error('ProposalBank:NonNominalProjection', [ ...
        'A repaired or emergency-projected proposal cannot enter ', ...
        'the frozen bank.']);
end
if ~logical(details.payloadConstraintEnforced) || ...
        ~logical(details.payloadLimitPassed)
    error('ProposalBank:PayloadGateFailed', ...
        'A proposal violated the frozen attempted-byte gate.');
end
end

function unavailable = isRegisteredProposalUnavailable(errorInfo)
unavailable = ismember(errorInfo.identifier, { ...
    'ObservableBasis:Unavailable', ...
    'RollingMatching:Infeasible', ...
    'ProposalBank:NonNominalProjection', ...
    'ProposalBank:PayloadGateFailed'}) || ...
    ~isempty(strfind(lower(errorInfo.message), ...
        'infeasible')); %#ok<STREMP>
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
