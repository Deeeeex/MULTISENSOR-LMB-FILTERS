function [adjacency, details] = ...
    selectRollingSafeObservableBasisPolicy( ...
        context, actionCode, options)
% SELECTROLLINGSAFEOBSERVABLEBASISPOLICY Frozen score-basis safe action.
%
% The action code is resolved through the versioned truth-free registry.
% Scores are injected into the same exact rolling-B=3 projector used by
% every online policy. An exact-k action that requires repair or payload
% emergency is rejected instead of silently changing action semantics.

if nargin < 3 || isempty(options)
    options = struct();
end
actionCode = round(actionCode);
[registry, registryMetadata] = ...
    getRollingSafeObservableScoreBasisRegistry();
entryIdx = find([registry.actionCode] == actionCode, 1);
if ~isscalar(actionCode) || ~isfinite(actionCode) || ...
        isempty(entryIdx)
    error('Unknown observable rolling-safe action code: %g.', actionCode);
end
entry = registry(entryIdx);
sourceWeight = getField(options, 'sourceWeight', 0.70);

policyOptions = struct( ...
    'sourceWeight', sourceWeight, ...
    'payloadToleranceFraction', getField( ...
        options, 'payloadToleranceFraction', inf), ...
    'edgeScoreFcnReturnsDetails', true, ...
    'edgeScoreFcn', ...
        @(scoreContext, receiverIndices, senderIndices, ...
            baselineSources) ...
            computeRollingSafeObservableBasisScores( ...
                scoreContext, receiverIndices, senderIndices, ...
                baselineSources, entry, sourceWeight), ...
    'posteriorUsed', entry.posteriorUsed, ...
    'truthUsed', false, ...
    'currentLinkReliabilityUsed', ...
        entry.currentLinkReliabilityUsed, ...
    'minimumCurrentCrossEdges', ...
        entry.exactCurrentCrossEdgeCount, ...
    'maximumCurrentCrossEdges', ...
        entry.exactCurrentCrossEdgeCount);
[adjacency, details] = selectRollingSafeRoutingPolicy( ...
    context, 'external-scores', policyOptions);

exactActionRealized = ...
    details.realizedCrossCount == ...
        entry.exactCurrentCrossEdgeCount;
repairFree = details.nominalProjectionFeasible && ...
    ~details.repairProjectionAttempted && ...
    ~details.repairTriggered && ...
    ~details.payloadEmergencyUsed;
if ~exactActionRealized || ~repairFree
    error('ObservableBasis:Unavailable', [ ...
        'Observable basis code %d could not realize exact k=%d ', ...
        'without projection repair or payload emergency.'], ...
        actionCode, entry.exactCurrentCrossEdgeCount);
end
if details.truthUsed
    error('Observable basis action violated its truth-free contract.');
end

details.observableBasisContractVersion = ...
    entry.contractVersion;
details.observableBasisRegistrySha256 = ...
    registryMetadata.registrySha256;
details.observableBasisActionCode = actionCode;
details.observableBasisId = entry.basisId;
details.observableBasisVersion = entry.basisVersion;
details.observableBasisFeatureNames = entry.featureNames;
details.observableBasisCoefficients = entry.coefficients;
details.observableBasisTransforms = entry.transforms;
details.observableBasisExactCurrentCrossEdgeCount = ...
    entry.exactCurrentCrossEdgeCount;
details.observableBasisPosteriorUsed = entry.posteriorUsed;
details.observableBasisCurrentLinkReliabilityUsed = ...
    entry.currentLinkReliabilityUsed;
details.observableBasisHistoryUsed = entry.historyUsed;
details.observableBasisCurrentGeometryUsed = ...
    entry.currentGeometryUsed;
details.observableBasisTruthUsed = false;
details.observableBasisFutureOutcomeUsed = false;
details.truthUsed = false;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
