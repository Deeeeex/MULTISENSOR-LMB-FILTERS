function projection = projectCvarResidualGraphPolicyScores( ...
        scores, block, behaviorBlock, safetyMargin, protocol)
% PROJECTCVARRESIDUALGRAPHPOLICYSCORES Apply the exact safe cycle splice.

if nargin < 5 || isempty(protocol)
    protocol = getCvarResidualGraphPolicyDatasetProtocol();
end
nodeCount = size(block.nodeFeatures, 1);
candidateCount = numel(block.receiverIndices);
weightCount = numel(block.residualWeightGrid);
if numel(scores.nodeRisk) ~= nodeCount || ...
        ~isequal(size(scores.edgeTaskAdvantage), ...
            [candidateCount, weightCount]) || ...
        ~isequal(size(scores.edgeProtectionAdvantage), ...
            [candidateCount, weightCount]) || ...
        ~isfinite(safetyMargin) || safetyMargin < 0 || ...
        behaviorBlock.seed ~= block.seed || ...
        behaviorBlock.currentTime ~= block.currentTime || ...
        behaviorBlock.actionTruthUsed || ...
        behaviorBlock.labelTruthUsed || ...
        ~isequal(size(behaviorBlock.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        numel(behaviorBlock.groupIds) ~= nodeCount
    error('CVaR graph projection inputs are invalid.');
end
details = block.teacherDetails;
if ~isfield(details, 'dominantSourcesByReceiver') || ...
        ~isfield(details, 'dominantPolicyDetails') || ...
        details.dominantPolicyDetails.truthUsed
    error(['CVaR graph projection lacks a truth-free dominant ', ...
        'backbone record.']);
end
dominantSources = reshape( ...
    details.dominantSourcesByReceiver, 1, []);
baselineSources = reshape( ...
    block.residualBaselineSourcesByReceiver, 1, []);
if numel(dominantSources) ~= nodeCount || ...
        numel(baselineSources) ~= nodeCount
    error('CVaR graph projection source records are incomplete.');
end

[~, riskOrder] = sort(scores.nodeRisk, 'descend');
predictedTailMask = false(1, nodeCount);
predictedTailMask(riskOrder( ...
    1:protocol.modelProtectedReceiverCount)) = true;
lowerSafety = scores.edgeProtectionAdvantage - ...
    safetyMargin;
predictedSafeMask = lowerSafety >= 0;
enforcedSafeMask = true(candidateCount, weightCount);
tailRows = predictedTailMask( ...
    reshape(block.receiverIndices, [], 1));
enforcedSafeMask(tailRows, :) = ...
    predictedSafeMask(tailRows, :);

bestWeightIndex = zeros(candidateCount, 1);
bestTaskScore = -inf(candidateCount, 1);
for rowIdx = 1:candidateCount
    allowedWeights = find(enforcedSafeMask(rowIdx, :));
    if isempty(allowedWeights)
        continue
    end
    [bestTaskScore(rowIdx), localIdx] = max( ...
        scores.edgeTaskAdvantage( ...
            rowIdx, allowedWeights));
    bestWeightIndex(rowIdx) = ...
        allowedWeights(localIdx);
end
scoreMatrix = -inf(nodeCount);
rowLookup = zeros(nodeCount);
for rowIdx = 1:candidateCount
    receiver = block.receiverIndices(rowIdx);
    sender = block.senderIndices(rowIdx);
    if rowLookup(receiver, sender) ~= 0
        error('CVaR graph candidate endpoints are duplicated.');
    end
    rowLookup(receiver, sender) = rowIdx;
    scoreMatrix(receiver, sender) = ...
        bestTaskScore(rowIdx);
end

orientations = {'clockwise', 'counter-clockwise'};
selections = cell(1, numel(orientations));
objectives = -inf(1, numel(orientations));
for orientationIdx = 1:numel(orientations)
    try
        selections{orientationIdx} = ...
            selectSplicedResidualFormationCycle( ...
                behaviorBlock.groupIds, ...
                baselineSources, dominantSources, ...
                behaviorBlock.physicalAdjacency, ...
                scoreMatrix, ...
                orientations{orientationIdx});
        objectives(orientationIdx) = ...
            selections{orientationIdx}. ...
                predictedObjective;
    catch errorRecord
        if ~strcmp(errorRecord.identifier, ...
                'ResidualCycle:Infeasible')
            rethrow(errorRecord);
        end
    end
end

projection = struct();
projection.predictedTailMask = predictedTailMask;
projection.predictedSafetyMargin = safetyMargin;
projection.predictedSafeMask = predictedSafeMask;
projection.enforcedSafeMask = enforcedSafeMask;
projection.fallbackUsed = all(~isfinite(objectives));
projection.topologyInfeasible = ...
    projection.fallbackUsed;
projection.repairTriggered = false;
projection.payloadEmergencyUsed = false;
projection.selectedEdgeWeightMask = ...
    false(candidateCount, weightCount);
projection.selectedCrossReceivers = zeros(1, 0);
projection.selectedCrossSenders = zeros(1, 0);
projection.selectedCrossResidualWeights = zeros(1, 0);
projection.selectedTaskScore = 0;
projection.orientation = 'matched-static-fallback';
if projection.fallbackUsed
    projection.residualSourcesByReceiver = ...
        baselineSources;
    projection.residualAdjacency = ...
        sourcesToAdjacency(baselineSources);
else
    [~, bestOrientationIdx] = max(objectives);
    selection = selections{bestOrientationIdx};
    selectedCount = ...
        numel(selection.crossReceivers);
    selectedWeights = zeros(1, selectedCount);
    selectedTaskScore = 0;
    for selectedIdx = 1:selectedCount
        receiver = selection.crossReceivers(selectedIdx);
        sender = selection.crossSenders(selectedIdx);
        rowIdx = rowLookup(receiver, sender);
        if rowIdx < 1 || bestWeightIndex(rowIdx) < 1
            error('CVaR graph projected edge has no safe weight.');
        end
        weightIdx = bestWeightIndex(rowIdx);
        projection.selectedEdgeWeightMask( ...
            rowIdx, weightIdx) = true;
        selectedWeights(selectedIdx) = ...
            block.residualWeightGrid(weightIdx);
        selectedTaskScore = selectedTaskScore + ...
            scores.edgeTaskAdvantage(rowIdx, weightIdx);
    end
    projection.selectedCrossReceivers = ...
        selection.crossReceivers;
    projection.selectedCrossSenders = ...
        selection.crossSenders;
    projection.selectedCrossResidualWeights = ...
        selectedWeights;
    projection.selectedTaskScore = selectedTaskScore;
    projection.orientation = selection.orientation;
    projection.residualSourcesByReceiver = ...
        selection.residualSourcesByReceiver;
    projection.residualAdjacency = ...
        selection.residualAdjacency;
end
projection.crossFormationEdgeCount = ...
    numel(projection.selectedCrossReceivers);
projection.weightGridPassed = all(ismember( ...
    projection.selectedCrossResidualWeights, ...
    block.residualWeightGrid));
projection.messageCountPassed = ...
    nnz(projection.residualAdjacency) == nodeCount;
projection.dominantBackbonePreserved = ...
    isequal(dominantSources, ...
        reshape(details.dominantSourcesByReceiver, 1, []));
projection.truthUsed = false;
projection.futureOutcomeUsed = false;
end

function adjacency = sourcesToAdjacency(sources)
nodeCount = numel(sources);
adjacency = false(nodeCount);
for receiver = 1:nodeCount
    adjacency(receiver, sources(receiver)) = true;
end
end
