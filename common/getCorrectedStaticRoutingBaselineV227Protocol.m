function protocol = getCorrectedStaticRoutingBaselineV227Protocol()
% GETCORRECTEDSTATICROUTINGBASELINEV227PROTOCOL Fair routing baseline.
%
% V227 isolates route adaptation on the corrected mixture-aware KLA code
% line.  Both arms use the same full-posterior payload, two directed inputs
% per receiver and the same self/dominant/residual fusion-weight multiset.
% The only intervention is whether the identity-stable formation backbone
% is rebuilt from the current physical graph or frozen on the registered
% all-time-physical graph.

source = getDirectGraphPayloadRepairControllerV214Protocol();
route = getFormationIsolateReconnectProbeProtocol();
protocol = struct();
protocol.id = 'corrected-static-routing-baseline-v227-v1';
protocol.contractVersion = ...
    'corrected-static-routing-baseline-v227-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.dynamicArmId = 'v227-current-physical-formation-backbone';
protocol.staticArmId = 'v227-fixed-all-time-physical-formation-backbone';
protocol.dynamicPolicyName = ...
    'corrected-static-routing-v227-current-physical-backbone';
protocol.staticPolicyName = ...
    'corrected-static-routing-v227-fixed-all-time-physical-backbone';
protocol.receiverMode = source.receiverMode;
protocol.dominantWeight = route.dominantWeight;
protocol.residualWeight = route.residualWeight;
protocol.directedInputsPerReceiver = 2;
protocol.filterSeedOffset = source.filterSeedOffset;
protocol.split = source.split;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v227', 'corrected_static_routing');
protocol.validationClaimAllowed = false;
protocol.developmentEvidenceOnly = true;
protocol.evidenceBoundary = [ ...
    'V227 is a paired corrected-code routing baseline. Both arms use ', ...
    'mixture-aware support-renormalized LMB-KLA, always-heavy complete ', ...
    'posterior exchange, exactly two directed inputs per receiver, the ', ...
    'same fusion-weight multiset, measurements, delivery uniforms and ', ...
    'filter seed. Both arms use the same physical-identity-stable ', ...
    'formation-backbone construction. The dynamic arm rebuilds it from ', ...
    'the current geometry and link reliabilities. The static arm applies ', ...
    'it once to the registered all-time-physical graph at the first page ', ...
    'and returns that identical route throughout the episode. This ', ...
    'isolates routing ', ...
    'adaptation; it does not by itself validate V226 payload transfer or ', ...
    'authorize a generalization claim.'];

if protocol.directedInputsPerReceiver ~= 2 || ...
        protocol.dominantWeight <= 0 || ...
        protocol.residualWeight <= 0 || ...
        protocol.dominantWeight + protocol.residualWeight >= 1
    error('CorrectedStaticRoutingV227:InvalidProtocol', ...
        'The V227 matched-routing contract is inconsistent.');
end
end
