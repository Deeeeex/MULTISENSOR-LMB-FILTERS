function projection = projectBudgetRecycledRepairActionsV188( ...
        proposals, creditState, options)
% PROJECTBUDGETRECYCLEDREPAIRACTIONSV188 Byte-safe repair projection.
%
% CREDITSTATE is the post-synopsis state returned by
% preflightBudgetRecycledRepairSynopsisV188.  The learned value model may
% rank proposals, but it cannot make an unsafe, connectivity-breaking, or
% unaffordable proposal eligible.  Every selected action is charged from
% spendable credit; protected savings are immutable.

if nargin < 3 || isempty(options)
    options = struct();
end
protocol = getBudgetRecycledFormationRepairV188Protocol();
creditState = validateCreditState(creditState, protocol);
maximumActions = getField(options, 'maximumActions', ...
    protocol.maximumDeployableRepairFormationsPerPage);
if ~isstruct(proposals) || ...
        ~isscalar(maximumActions) || ~isfinite(maximumActions) || ...
        maximumActions < 0 || maximumActions ~= round(maximumActions) || ...
        maximumActions > protocol.maximumRepairFormationsPerPage
    error('BudgetRecycledRepairV188:InvalidProjectionInput', ...
        'The proposal set or maximum-action limit is malformed.');
end
required = { ...
    'formationId', 'attemptedBytes', 'estimatedUtilityLowerBound', ...
    'safetyPassed', 'rollingConnectivityPassed'};
if ~isempty(proposals) && any(~isfield(proposals, required))
    error('BudgetRecycledRepairV188:ProposalContractDrift', ...
        'Every repair proposal must satisfy the frozen projection contract.');
end
for proposalIdx = 1:numel(proposals)
    proposal = proposals(proposalIdx);
    if ~validPositiveInteger(proposal.formationId) || ...
            ~validPositiveScalar(proposal.attemptedBytes) || ...
            ~isscalar(proposal.estimatedUtilityLowerBound) || ...
            ~isnumeric(proposal.estimatedUtilityLowerBound) || ...
            ~isfinite(proposal.estimatedUtilityLowerBound) || ...
            ~validBoolean(proposal.safetyPassed) || ...
            ~validBoolean(proposal.rollingConnectivityPassed)
        error('BudgetRecycledRepairV188:InvalidProposal', ...
            'A repair proposal contains an invalid value.');
    end
end

projection = emptyProjection(numel(proposals), creditState);
eligible = false(1, numel(proposals));
utilityPerByte = -inf(1, numel(proposals));
for proposalIdx = 1:numel(proposals)
    proposal = proposals(proposalIdx);
    eligible(proposalIdx) = logical(proposal.safetyPassed) && ...
        logical(proposal.rollingConnectivityPassed) && ...
        proposal.estimatedUtilityLowerBound > 0 && ...
        proposal.attemptedBytes <= ...
            creditState.spendableCreditBytes + 1e-9;
    if eligible(proposalIdx)
        utilityPerByte(proposalIdx) = ...
            proposal.estimatedUtilityLowerBound / proposal.attemptedBytes;
    end
end

if isempty(proposals)
    order = zeros(1, 0);
else
    ranking = [-utilityPerByte', ...
        -reshape([proposals.estimatedUtilityLowerBound], [], 1), ...
        reshape([proposals.attemptedBytes], [], 1), ...
        reshape([proposals.formationId], [], 1), ...
        (1:numel(proposals))'];
    [~, order] = sortrows(ranking, [1, 2, 3, 4, 5]);
end
selectedFormations = zeros(1, 0);
selectedMask = false(1, numel(proposals));
selectedBytes = 0;
for proposalIdx = reshape(order, 1, [])
    if ~eligible(proposalIdx) || nnz(selectedMask) >= maximumActions
        continue;
    end
    formationId = proposals(proposalIdx).formationId;
    if ismember(formationId, selectedFormations) || ...
            proposals(proposalIdx).attemptedBytes > ...
                creditState.spendableCreditBytes - selectedBytes + 1e-9
        continue;
    end
    selectedMask(proposalIdx) = true;
    selectedFormations(end + 1) = formationId; %#ok<AGROW>
    selectedBytes = selectedBytes + proposals(proposalIdx).attemptedBytes;
end

nextState = creditState;
nextState.spendableCreditBytes = ...
    creditState.spendableCreditBytes - selectedBytes;
nextState.cumulativeControlAndRepairSpendBytes = ...
    creditState.cumulativeControlAndRepairSpendBytes + selectedBytes;
nextState.certifiedCumulativeSavingBytes = ...
    nextState.protectedSavingBytes + nextState.spendableCreditBytes;
nextState.repairActionsAuthorized = ...
    creditState.repairActionsAuthorized + nnz(selectedMask);
if abs(nextState.certifiedCumulativeSavingBytes - ...
        (nextState.cumulativeAdmissionNetSavingBytes - ...
        nextState.cumulativeControlAndRepairSpendBytes)) > 1e-8 || ...
        nextState.spendableCreditBytes < -1e-9 || ...
        abs(nextState.protectedSavingBytes - ...
            creditState.protectedSavingBytes) > 1e-12
    error('BudgetRecycledRepairV188:InternalCreditViolation', ...
        'The deterministic repair projector violated byte conservation.');
end

projection.eligibleMask = eligible;
projection.selectedMask = selectedMask;
projection.selectedProposalIndices = find(selectedMask);
projection.selectedFormationIds = selectedFormations;
projection.selectedActionBytes = selectedBytes;
projection.nextCreditState = nextState;
projection.cumulativeByteSafetyPassed = ...
    nextState.certifiedCumulativeSavingBytes >= -1e-9;
projection.protectedSavingPreserved = ...
    abs(nextState.protectedSavingBytes - ...
        creditState.protectedSavingBytes) <= 1e-12;
if any(selectedMask)
    projection.fallbackReason = '';
else
    projection.fallbackReason = 'base-admission-without-repair';
end
end

function value = emptyProjection(proposalCount, creditState)
value = struct( ...
    'contractVersion', 'budget-recycled-repair-projection-v188-v2', ...
    'availableSpendableCreditBytes', ...
        creditState.spendableCreditBytes, ...
    'eligibleMask', false(1, proposalCount), ...
    'selectedMask', false(1, proposalCount), ...
    'selectedProposalIndices', zeros(1, 0), ...
    'selectedFormationIds', zeros(1, 0), ...
    'selectedActionBytes', 0, ...
    'nextCreditState', creditState, ...
    'cumulativeByteSafetyPassed', false, ...
    'protectedSavingPreserved', false, ...
    'fallbackReason', 'not-evaluated', ...
    'truthUsed', false, ...
    'futureInformationUsed', false, ...
    'modelMayOverrideProjection', false);
end

function state = validateCreditState(state, protocol)
required = { ...
    'contractVersion', 'reserveFraction', 'spendableCreditBytes', ...
    'protectedSavingBytes', 'cumulativeAdmissionNetSavingBytes', ...
    'cumulativeControlAndRepairSpendBytes', ...
    'certifiedCumulativeSavingBytes', 'pagesProcessed', ...
    'synopsisPagesAuthorized', 'repairActionsAuthorized'};
if ~isstruct(state) || any(~isfield(state, required)) || ...
        ~strcmp(state.contractVersion, protocol.creditLedgerContractVersion) || ...
        abs(state.reserveFraction - ...
            protocol.communicationCreditReserveFraction) > 1e-12
    error('BudgetRecycledRepairV188:CreditContractDrift', ...
        'The repair projector requires the frozen post-synopsis ledger.');
end
for fieldIdx = 3:numel(required)
    if ~validNonnegativeScalar(state.(required{fieldIdx}))
        error('BudgetRecycledRepairV188:InvalidCreditState', ...
            'The communication-credit state is malformed.');
    end
end
if abs(state.certifiedCumulativeSavingBytes - ...
        (state.protectedSavingBytes + state.spendableCreditBytes)) > 1e-8 || ...
        abs(state.certifiedCumulativeSavingBytes - ...
        (state.cumulativeAdmissionNetSavingBytes - ...
        state.cumulativeControlAndRepairSpendBytes)) > 1e-8
    error('BudgetRecycledRepairV188:CreditConservationDrift', ...
        'The communication-credit state does not conserve attempted bytes.');
end
end

function valid = validPositiveInteger(value)
valid = validPositiveScalar(value) && value == round(value);
end

function valid = validPositiveScalar(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value > 0;
end

function valid = validNonnegativeScalar(value)
valid = isscalar(value) && isnumeric(value) && ...
    isfinite(value) && value >= 0;
end

function valid = validBoolean(value)
valid = isscalar(value) && ...
    (islogical(value) || ...
    (isnumeric(value) && isfinite(value) && (value == 0 || value == 1)));
end

function value = getField(data, name, fallback)
if isstruct(data) && isfield(data, name)
    value = data.(name);
else
    value = fallback;
end
end
