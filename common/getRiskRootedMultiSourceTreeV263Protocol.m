protocol.receiverMode = source.receiverMode;
protocol.outputRoot = fullfile('RUN', 'GA', 'dynamic_topology', ...
    'evidence', 'tracking_aligned_v263', ...
    'risk_rooted_multi_source_tree', 'm24_seed1301_t57_73');
