    'risk-rooted-multi-source-tree-v263-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.armId = 'v263-risk-rooted-multi-source-tree';
protocol.policyName = 'risk-rooted-multi-source-tree-v263-policy';
protocol.allowedPresets = { ...
    'm24-formation-fov-temporal-coupled-formation-braid'};
protocol.allowedSeeds = 1301;
protocol.continuationStartTime = 57;
protocol.continuationEndTime = 73;
protocol.localizationEventWindow = [58, 73];
