        protocol.localizationAbsoluteThreshold <= 0 || ...
        protocol.localizationAbsoluteThreshold >= 1 || ...
        protocol.localizationRelativeThreshold <= 1 || ...
        protocol.minimumSourceCoverage <= 0.5 || ...
        protocol.minimumSourceCoverage > 1 || ...
        protocol.minimumSourceExistence <= 0 || ...
        protocol.minimumSourceExistence >= 1 || ...
        protocol.maximumSourceToTargetRiskRatio <= 0 || ...
        protocol.maximumSourceToTargetRiskRatio >= 1 || ...
        protocol.minimumEligibleSourceCount < 2 || ...
        protocol.minimumInitiallyShortenedSourceCount < 1
    error('RiskRootedMultiSourceV263:InvalidProtocol', ...
        'The V263 risk, source or continuation contract is invalid.');
end
end
