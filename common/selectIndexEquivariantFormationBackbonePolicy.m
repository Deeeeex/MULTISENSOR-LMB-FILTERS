function [adjacency, details] = ...
    selectIndexEquivariantFormationBackbonePolicy(context, options)
% SELECTINDEXEQUIVARIANTFORMATIONBACKBONEPOLICY V43 reference route.
%
% The selector reads only current physical geometry, the current link-
% probability page, registered graph metadata, immutable physical UIDs and
% static fusion weights.  Posterior values are deliberately outside the
% route-builder interface.

if nargin < 2 || isempty(options)
    options = struct();
end
allowedFields = {'dominantWeight', 'residualWeight'};
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), allowedFields))
    error('IndexEquivariantFormationPolicy:InvalidOptions', ...
        'Only dominantWeight and residualWeight may be supplied.');
end
dominantWeight = getField(options, 'dominantWeight', 0.70);
residualWeight = getField(options, 'residualWeight', 0.05);
validateWeights(dominantWeight, residualWeight);

required = {'localPosteriorBySensor', 'model', 'baseAdjacency', ...
    'physicalAdjacency', 'positions', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'commConfig'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds') || ...
        ~isfield(context.commConfig, 'pDropByEdge')
    error('IndexEquivariantFormationPolicy:InvalidContext', ...
        'The current physical route context is incomplete.');
end

nodeCount = numel(context.localPosteriorBySensor);
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
if nodeCount ~= numel(groupIds)
    error('IndexEquivariantFormationPolicy:InvalidContext', ...
        'The posterior container and registered membership disagree.');
end
registeredAdjacency = logical(context.baseAdjacency);
if isfield(context.model.dynamicTopologyScenario, 'staticAdjacency') && ...
        ~isequal(logical(context.model.dynamicTopologyScenario. ...
            staticAdjacency), registeredAdjacency)
    error('IndexEquivariantFormationPolicy:InvalidContext', ...
        'The observable base graph disagrees with registered metadata.');
end

[dominantAdjacency, residualAdjacency, construction] = ...
    buildIndexEquivariantFormationBackboneReference( ...
        groupIds, context.sensorPhysicalUids, ...
        context.formationPhysicalUidsBySensor, context.positions, ...
        registeredAdjacency, logical(context.physicalAdjacency), ...
        context.commConfig.pDropByEdge);
[adjacency, fusionWeights, route] = ...
    buildBackbonePreservingResidualRoute( ...
        context, dominantAdjacency, residualAdjacency, ...
        dominantWeight, residualWeight);
if route.duplicateSourceFraction ~= 0 || ...
        nnz(adjacency) ~= 2 * nodeCount || ...
        route.maximumMessagesPerReceiver ~= 2 || ...
        (isfield(context, 'directedMessageBudget') && ...
         nnz(adjacency) > context.directedMessageBudget)
    error('IndexEquivariantFormationPolicy:InvalidReference', ...
        'The v43 reference violates its two-input message contract.');
end

details = route;
details.contractVersion = ...
    'index-equivariant-formation-backbone-policy-v1';
details.mode = 'index-equivariant-formation-backbone-reference';
details.objective = [ ...
    min(cellfun(@(x) x.bottleneckReliability, ...
        construction.dominantCycleDetails)), ...
    min(cellfun(@(x) x.bottleneckReliability, ...
        construction.localResidualCycleDetails))];
details.candidateIndex = NaN;
details.selectionSeconds = NaN;
details.validCandidateCount = ...
    construction.crossFormationMessageCount;
details.fusionWeightMatrix = fusionWeights;
details.dominantAdjacency = dominantAdjacency;
details.residualAdjacency = residualAdjacency;
details.construction = construction;
details.crossReceivers = construction.crossReceivers;
details.crossSenders = construction.crossSenders;
details.incomingCrossReceiversByFormation = ...
    construction.incomingCrossReceiversByFormation;
details.incomingCrossSendersByFormation = ...
    construction.incomingCrossSendersByFormation;
details.formationPhysicalUids = ...
    construction.formationPhysicalUids;
details.crossFormationMessageCount = ...
    construction.crossFormationMessageCount;
details.maximumCrossEdges = construction.crossFormationMessageCount;
details.maximumCrossSourceLoad = ...
    construction.maximumCrossSourceLoad;
details.maximumCrossReceiverLoad = ...
    construction.maximumCrossReceiverLoad;
details.proposalCrossCount = construction.crossFormationMessageCount;
details.backboneMode = ...
    'physical-uid-local-cycles-plus-registered-cross-assignment';
details.instantaneousSensorStrongConnected = true;
details.instantaneousFormationStrongConnected = true;
details.routeIndexEquivarianceDesigned = true;
details.arrayIndexTieBreakUsed = false;
details.currentGeometryUsed = true;
details.currentLinkReliabilityUsed = true;
details.currentPhysicalActionSetUsed = true;
details.posteriorUsed = false;
details.posteriorPayloadMetadataUsed = false;
details.truthUsed = false;
details.measurementUsed = false;
details.futureOutcomeUsed = false;
details.realizedDeliveryUniformsUsed = false;
details.trackingOutcomeScored = false;
if isfield(context, 'auditBoundary')
    details.auditBoundary = context.auditBoundary;
end
end

function validateWeights(dominantWeight, residualWeight)
if ~isscalar(dominantWeight) || ~isscalar(residualWeight) || ...
        any(~isfinite([dominantWeight, residualWeight])) || ...
        dominantWeight <= 0 || residualWeight <= 0 || ...
        dominantWeight + residualWeight >= 1
    error('IndexEquivariantFormationPolicy:InvalidWeights', ...
        'The fusion weights must be positive and leave self weight.');
end
end

function value = getField(structure, fieldName, defaultValue)
if isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
