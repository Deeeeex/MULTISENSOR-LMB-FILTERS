function gains = computeDirectGraphH3GainVectorV218( ...
        reference, candidate, groupIds, targetFormationId)
% COMPUTEDIRECTGRAPHH3GAINVECTORV218 Build the frozen H=3 value target.
%
% The vector order is the V213 risk-target order.  Positive entries mean
% that the candidate improves on the full-payload no-op continuation.

required = { ...
    'meanEospa', 'meanRmse', 'consensusOspa', ...
    'terminalConsensusOspa', 'sensorMeanEospa', 'sensorMeanRmse', ...
    'formationMeanEospa', 'formationMeanRmse', ...
    'worstSensorEospa', 'worstSensorRmse'};
if ~isstruct(reference) || ~isscalar(reference) || ...
        ~isstruct(candidate) || ~isscalar(candidate) || ...
        any(~isfield(reference, required)) || ...
        any(~isfield(candidate, required)) || ...
        ~isnumeric(groupIds) || isempty(groupIds) || ...
        ~isscalar(targetFormationId) || ...
        ~isfinite(targetFormationId)
    error('DirectGraphH3GainVectorV218:InvalidInput', ...
        'Two H=3 outcomes and one target formation are required.');
end
groupIds = reshape(groupIds, 1, []);
formationIds = unique(groupIds, 'stable');
receiverIds = find(groupIds == targetFormationId);
targetRow = find(formationIds == targetFormationId);
if isempty(receiverIds) || numel(targetRow) ~= 1 || ...
        numel(reference.sensorMeanEospa) ~= numel(groupIds) || ...
        numel(candidate.sensorMeanEospa) ~= numel(groupIds) || ...
        numel(reference.sensorMeanRmse) ~= numel(groupIds) || ...
        numel(candidate.sensorMeanRmse) ~= numel(groupIds) || ...
        numel(reference.formationMeanEospa) ~= numel(formationIds) || ...
        numel(candidate.formationMeanEospa) ~= numel(formationIds) || ...
        numel(reference.formationMeanRmse) ~= numel(formationIds) || ...
        numel(candidate.formationMeanRmse) ~= numel(formationIds)
    error('DirectGraphH3GainVectorV218:ShapeDrift', ...
        'The outcome vectors do not match the sensor formations.');
end

sensorEospaGain = relativeGainVector( ...
    reference.sensorMeanEospa, candidate.sensorMeanEospa);
sensorRmseGain = relativeGainVector( ...
    reference.sensorMeanRmse, candidate.sensorMeanRmse);
formationEospaGain = relativeGainVector( ...
    reference.formationMeanEospa, candidate.formationMeanEospa);
formationRmseGain = relativeGainVector( ...
    reference.formationMeanRmse, candidate.formationMeanRmse);
gains = [ ...
    relativeGain(reference.meanEospa, candidate.meanEospa), ...
    relativeGain(reference.meanRmse, candidate.meanRmse), ...
    relativeGain(reference.consensusOspa, candidate.consensusOspa), ...
    relativeGain(reference.terminalConsensusOspa, ...
        candidate.terminalConsensusOspa), ...
    formationEospaGain(targetRow), ...
    formationRmseGain(targetRow), ...
    min(sensorEospaGain(receiverIds)), ...
    min(sensorRmseGain(receiverIds)), ...
    relativeGain(reference.worstSensorEospa, ...
        candidate.worstSensorEospa), ...
    relativeGain(reference.worstSensorRmse, ...
        candidate.worstSensorRmse), ...
    min(formationEospaGain), ...
    min(formationRmseGain)];
if numel(gains) ~= 12 || any(~isfinite(gains))
    error('DirectGraphH3GainVectorV218:InvalidTarget', ...
        'The H=3 gain vector must contain twelve finite coordinates.');
end
end

function values = relativeGainVector(reference, candidate)
values = 100 * (reference - candidate) ./ max(abs(reference), eps);
end

function value = relativeGain(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end
