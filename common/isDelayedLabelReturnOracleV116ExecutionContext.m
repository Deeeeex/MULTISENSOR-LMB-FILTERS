function detected = isDelayedLabelReturnOracleV116ExecutionContext(context)
% ISDELAYEDLABELRETURNORACLEV116EXECUTIONCONTEXT Identify V116.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'delayed-label-return-oracle-v116-context-v1');
end
