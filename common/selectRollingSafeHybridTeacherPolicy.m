function [adjacency, details] = ...
    selectRollingSafeHybridTeacherPolicy( ...
        context, activationMask, anchorTime, ...
        scheduledOptions, teacherOptions)
% SELECTROLLINGSAFEHYBRIDTEACHERPOLICY Closed-loop switching diagnostic.
%
% A zero activation executes the registered rolling-B3 scheduled control.
% A one activation recomputes the privileged current-risk teacher from the
% actual hybrid posterior and selected-topology history. Both branches use
% selectRollingSafeRoutingPolicy, so every realized action is projected
% through the same current/successor rolling safety layer.
%
% This is an attainability probe for learning a deployable switch. It reads
% truth on activated steps and must not be used as a validation strategy.

activationMask = logical(reshape(activationMask, 1, []));
if isempty(activationMask)
    error('Hybrid teacher activationMask cannot be empty.');
end
anchorTime = round(anchorTime);
relativeTime = context.currentTime - anchorTime + 1;
teacherActive = relativeTime >= 1 && ...
    relativeTime <= numel(activationMask) && ...
    activationMask(relativeTime);

sourceWeight = getField( ...
    scheduledOptions, 'sourceWeight', 0.70);
if teacherActive
    scoreOptions = getField( ...
        teacherOptions, 'scoreOptions', struct());
    scoreOptions.sourceWeight = sourceWeight;
    policyOptions = struct( ...
        'sourceWeight', sourceWeight, ...
        'payloadToleranceFraction', getField( ...
            teacherOptions, ...
            'payloadToleranceFraction', inf), ...
        'edgeScoreFcnReturnsDetails', true, ...
        'edgeScoreFcn', ...
            @(scoreContext, receiverIndices, ...
                senderIndices, cycleSources) ...
                computeRollingSafeTaskTeacherEdgeScores( ...
                    scoreContext, receiverIndices, ...
                    senderIndices, cycleSources, ...
                    scoreOptions), ...
        'posteriorUsed', true, ...
        'truthUsed', true, ...
        'currentLinkReliabilityUsed', true, ...
        'teacherRequestedHorizonSteps', getField( ...
            scoreOptions, 'horizonSteps', 0));
    [adjacency, details] = ...
        selectRollingSafeRoutingPolicy( ...
            context, 'external-scores', policyOptions);
    branch = 'privileged-current-risk';
else
    [adjacency, details] = ...
        selectRollingSafeRoutingPolicy( ...
            context, 'scheduled-burst', ...
            scheduledOptions);
    branch = 'scheduled-control';
end
details.hybridTeacherActive = teacherActive;
details.hybridBranch = branch;
details.hybridActivationMask = activationMask;
details.hybridAnchorTime = anchorTime;
details.hybridRelativeTime = relativeTime;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
