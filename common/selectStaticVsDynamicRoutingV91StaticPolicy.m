function [adjacency, details] = ...
    selectStaticVsDynamicRoutingV91StaticPolicy(context)
% SELECTSTATICVSDYNAMICROUTINGV91STATICPOLICY Fixed registered-route arm.
%
% Route selection depends only on the registered static formation graph
% and sensor roles. The current physical page is used solely as a fail-closed
% feasibility check. The V91 preflight additionally proves that the returned
% route is identical and physical over the complete episode.

protocol = getStaticVsDynamicRoutingV91Protocol();
timer = tic;
[adjacency, details] = ...
    selectFormationBackboneResidualTourPolicy(context, struct( ...
        'dominantWeight', protocol.dominantWeight, ...
        'residualWeight', protocol.residualWeight));
details.contractVersion = ...
    'static-vs-dynamic-routing-v91-static-policy-v1';
details.protocolId = protocol.id;
details.armId = protocol.staticArmId;
details.selectionSeconds = toc(timer);
details.referenceMessageCount = nnz(adjacency);
details.currentMessageCount = nnz(adjacency);
details.referenceFallbackUsed = false;
details.currentPhysicalActionSetUsed = false;
details.currentPhysicalFeasibilityChecked = true;
details.futureOutcomeUsed = false;
details.scheduleCertificate = buildSchedule( ...
    context.currentTime, 'static-all-time-physical');
end

function schedule = buildSchedule(currentTime, phase)
schedule = struct( ...
    'contractVersion', ...
        'static-vs-dynamic-routing-v91-schedule-v1', ...
    'currentTime', currentTime, ...
    'phase', phase, ...
    'phaseIndex', 2, ...
    'gatewayIndices', zeros(1, 0), ...
    'formationIds', zeros(1, 0), ...
    'sourceIndices', zeros(1, 0), ...
    'proposalGatewayCount', 0, ...
    'selectedGatewayCount', 0, ...
    'pendingAcquisitionTime', NaN, ...
    'messageParityPassed', true, ...
    'rollingSensorStrong', true, ...
    'rollingFormationStrong', true, ...
    'referenceFallbackUsed', false, ...
    'cycleSelected', true);
end
