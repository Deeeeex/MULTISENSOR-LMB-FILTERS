function detected = isOutwardReferenceCarrierV125ExecutionContext(context)
% ISOUTWARDREFERENCECARRIERV125EXECUTIONCONTEXT Identify V125.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        'outward-reference-carrier-v125-context-v1');
end
