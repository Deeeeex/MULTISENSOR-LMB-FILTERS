function cache = ...
    buildFormationBackboneBundleM24SourceCache( ...
        protocol, permit, source, diagnostics)
% BUILDFORMATIONBACKBONEBUNDLEM24SOURCECACHE Predecision continuation state.

trustedProtocol = getFormationBackboneBundleM24DevelopmentProtocol();
if ~isequaln(protocol, trustedProtocol)
    error('FormationBundleSourceCache:ProtocolDrift', ...
        'The cache builder did not receive the trusted protocol registry.');
end
if ~isstruct(permit) || ~isscalar(permit) || ...
        ~isfield(permit, 'id')
    error('FormationBundleSourceCache:PermitDrift', ...
        'The cache builder permit is malformed.');
end
trustedPermit = ...
    loadFormationBackboneBundleM24SourceCasePermit(permit.id);
if ~isequaln(permit, trustedPermit)
    error('FormationBundleSourceCache:PermitDrift', ...
        'The cache builder did not receive the trusted case permit.');
end
if ~protocol.executableSourceFrozen || ...
        ~protocol.sourceInputFingerprintsFrozen || ...
        ~protocol.sourcePosteriorAuthorized || ...
        protocol.sourceStateEstimateOutputAuthorized || ...
        permit.stateEstimateOutputAuthorized || ...
        permit.candidateContinuationAuthorized || ...
        permit.pairedTrackingAuthorized || ...
        permit.trackingOutcomeScoringAuthorized || ...
        permit.groundTruthAccessAuthorized || ...
        permit.futureOutcomeAccessAuthorized || ...
        permit.validationClaimAllowed
    error('FormationBundleSourceCache:SourceFreezePending', ...
        'A source cache cannot be built before the exact source freeze.');
end
if ~isstruct(source) || ~isscalar(source) || ...
        ~isfield(source, 'caseId') || ...
        ~strcmp(source.caseId, permit.caseId) || ...
        ~isfield(source, 'inputFingerprint') || ...
        ~isequaln(source.inputFingerprint, ...
            permit.sourceInputFingerprint)
    error('FormationBundleSourceCache:SourceInputDrift', ...
        'The cache source identity differs from the registered case.');
end
currentManifest = ...
    buildFormationBackboneBundleM24ExecutableSourceManifest();
if ~strcmp(currentManifest.canonicalSha256, ...
        permit.executableSourceManifestSha256)
    error('FormationBundleSourceCache:ExecutableSourceDrift', ...
        'The executable source changed before cache construction.');
end
gitState = validateFormationBackboneBundleM24ExecutableGitState( ...
    permit.executableSourceCommit);

snapshotTime = permit.continuationSnapshotTime;
topologyTimes = snapshotTime-2:snapshotTime-1;
localUpdateTimes = snapshotTime-2:snapshotTime;
if snapshotTime < 3 || ...
        ~isfield(diagnostics, 'topologyLocalPosteriorSnapshot') || ...
        numel(diagnostics.topologyLocalPosteriorSnapshot) < snapshotTime || ...
        isempty(diagnostics.topologyLocalPosteriorSnapshot{snapshotTime}) || ...
        ~isfield(diagnostics, 'topologyActiveEdge') || ...
        ~isfield(diagnostics, 'delivered') || ...
        ~isfield(diagnostics, 'localInnovation') || ...
        ~isfield(diagnostics, 'localAssociationConfidence') || ...
        ~isfield(diagnostics, 'localNisNorm') || ...
        ~isfield(diagnostics, 'localNisDeviation') || ...
        ~isfield(diagnostics, ...
            'sourceStateEstimateOutputSuppressed') || ...
        ~isfield(diagnostics, ...
            'dynamicTopologyExecutionAuthorization')
    error('FormationBundleSourceCache:IncompleteDiagnostics', ...
        'The source trajectory lacks a complete predecision snapshot.');
end
authorization = ...
    diagnostics.dynamicTopologyExecutionAuthorization;
requiredAuthorizationFields = { ...
    'mode', 'permitId', 'permitCanonicalSha256', ...
    'protocolId', 'protocolCanonicalSha256', ...
    'caseId', 'caseCanonicalSha256', ...
    'sourceInputFingerprintSha256', ...
    'executableSourceCommit', ...
    'executableSourceManifestSha256', ...
    'executionHeadCommit', 'armId', ...
    'stateEstimateOutputAuthorized', ...
    'trackingOutcomeScoringAuthorized', ...
    'groundTruthAccessAuthorized', ...
    'futureOutcomeAccessAuthorized', ...
    'validationClaimAllowed'};
if ~isstruct(authorization) || ~isscalar(authorization) || ...
        ~all(isfield(authorization, requiredAuthorizationFields)) || ...
        ~strcmp(authorization.mode, 'registered-case-permit') || ...
        ~strcmp(authorization.permitId, permit.id) || ...
        ~strcmp(authorization.permitCanonicalSha256, ...
            permit.permitCanonicalSha256) || ...
        ~strcmp(authorization.protocolId, protocol.id) || ...
        ~strcmp(authorization.protocolCanonicalSha256, ...
            protocol.canonicalSha256) || ...
        ~strcmp(authorization.caseId, permit.caseId) || ...
        ~strcmp(authorization.caseCanonicalSha256, ...
            permit.caseCanonicalSha256) || ...
        ~strcmp(authorization.sourceInputFingerprintSha256, ...
            permit.sourceInputFingerprint.canonicalSha256) || ...
        ~strcmp(authorization.executableSourceCommit, ...
            permit.executableSourceCommit) || ...
        ~strcmp(authorization.executableSourceManifestSha256, ...
            permit.executableSourceManifestSha256) || ...
        ~strcmp(authorization.executionHeadCommit, ...
            gitState.headCommit) || ...
        ~strcmp(authorization.armId, permit.armId) || ...
        ~isequal(diagnostics. ...
            sourceStateEstimateOutputSuppressed, true) || ...
        authorization.stateEstimateOutputAuthorized || ...
        authorization.trackingOutcomeScoringAuthorized || ...
        authorization.groundTruthAccessAuthorized || ...
        authorization.futureOutcomeAccessAuthorized || ...
        authorization.validationClaimAllowed
    error('FormationBundleSourceCache:AuthorizationDrift', ...
        'The source cache authorization expanded or changed.');
end

selectedDiagnosticHistory = ...
    diagnostics.topologyActiveEdge(:, :, topologyTimes);
cachePayload = struct();
cachePayload.contractVersion = ...
    'formation-backbone-bundle-m24-source-cache-v1';
cachePayload.protocolId = protocol.id;
cachePayload.protocolCanonicalSha256 = protocol.canonicalSha256;
cachePayload.caseId = permit.caseId;
cachePayload.caseOrdinal = permit.caseOrdinal;
cachePayload.caseCanonicalSha256 = permit.caseCanonicalSha256;
cachePayload.presetName = permit.presetName;
cachePayload.seed = permit.seed;
cachePayload.focusWindow = permit.focusWindow;
cachePayload.sourceWindow = permit.sourceWindow;
cachePayload.armId = permit.armId;
cachePayload.permitId = permit.id;
cachePayload.permitCanonicalSha256 = ...
    permit.permitCanonicalSha256;
cachePayload.executableSourceCommit = ...
    permit.executableSourceCommit;
cachePayload.executableSourceManifestSha256 = ...
    permit.executableSourceManifestSha256;
cachePayload.sourceInputFingerprint = source.inputFingerprint;
cachePayload.authorization = authorization;
cachePayload.posteriorSnapshotConvention = ...
    'pre-topology-pre-fusion-local-posterior';
cachePayload.posteriorSnapshotTime = snapshotTime;
cachePayload.localPosteriorBySensor = ...
    diagnostics.topologyLocalPosteriorSnapshot{snapshotTime};
cachePayload.topologyHistoryTimes = topologyTimes;
cachePayload.topologyHistoryDiagnosticConvention = ...
    'sender-row-receiver-column-directed-oldest-to-newest';
cachePayload.selectedDiagnosticEdgeHistory = ...
    selectedDiagnosticHistory;
cachePayload.deliveredDiagnosticEdgeHistory = ...
    diagnostics.delivered(:, :, topologyTimes);
cachePayload.topologyHistoryPolicyConvention = ...
    'receiver-row-sender-column-directed-oldest-to-newest';
cachePayload.selectedPolicyAdjacencyHistory = ...
    permute(selectedDiagnosticHistory, [2, 1, 3]);
cachePayload.localUpdateHistoryTimes = localUpdateTimes;
cachePayload.localInnovationHistory = ...
    diagnostics.localInnovation(:, localUpdateTimes);
cachePayload.localAssociationConfidenceHistory = ...
    diagnostics.localAssociationConfidence(:, localUpdateTimes);
cachePayload.localNisNormHistory = ...
    diagnostics.localNisNorm(:, localUpdateTimes);
cachePayload.localNisDeviationHistory = ...
    diagnostics.localNisDeviation(:, localUpdateTimes);
cachePayload.trackingOutcomeScoringAuthorized = false;
cachePayload.groundTruthAccessAuthorized = false;
cachePayload.futureOutcomeAccessAuthorized = false;
cachePayload.stateEstimateOutputAuthorized = false;
cachePayload.sourceStateEstimateOutputSuppressed = true;
cachePayload.stateEstimateOutputReturned = false;
cachePayload.validationClaimAllowed = false;
cachePayload.eospaOutcome = zeros(1, 0);
cachePayload.cardinalityOutcome = zeros(1, 0);
cachePayload.trackingScore = zeros(1, 0);
cache = cachePayload;
cache.cachePayloadCanonicalSha256 = ...
    computeCanonicalValueSha256(cachePayload);
end
