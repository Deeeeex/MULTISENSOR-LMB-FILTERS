function config = ...
        buildRiskTriggeredFormationResidualPulseV260Config( ...
            scenario, pulseWeight)
% BUILDRISKTRIGGEREDFORMATIONRESIDUALPULSEV260CONFIG Continuation arm.

protocol = getRiskTriggeredFormationResidualPulseV260Protocol();
if ~isstruct(scenario) || ~isscalar(scenario) || ...
        ~isfield(scenario, 'presetName') || ...
        ~ismember(scenario.presetName, protocol.allowedPresets) || ...
        ~isscalar(pulseWeight) || ...
        ~ismember(pulseWeight, protocol.pulseWeights)
    error('RiskTriggeredPulseV260:InvalidConfigInput', ...
        'V260 requires its registered M24 scene and pulse weight.');
end
formationCount = numel(unique(scenario.sensorGroupIds));
minimumMessages = scenario.numberOfSensors + ...
    2 * (formationCount - 1);
config = buildCausalMinimumFormationBackboneV242Config(scenario);
config.topologyPolicyName = protocol.policyName;
config.topologyPolicyFcn = @(context) ...
    selectRiskTriggeredFormationResidualPulseV260Policy( ...
        context, pulseWeight);
config.topologyDirectedMessageBudget = minimumMessages + ...
    protocol.maximumFormationResidualEdges;
end
