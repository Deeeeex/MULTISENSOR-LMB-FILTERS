function score = scoreTaskRiskInputProtectionRouteV92( ...
        context, adjacency, weights, referenceScore, ...
        groupIds, protocol, incrementalReference)
% SCORETASKRISKINPUTPROTECTIONROUTEV92 One-round task-aligned route score.

if nargin < 7 || isempty(incrementalReference)
    incrementalReference = struct();
end
policy = protocol.protectionPolicy;
enumerationOptions = struct( ...
    'maximumIncomingCount', ...
        policy.maximumIncomingCountForOutcomeEnumeration);
if ~isempty(fieldnames(incrementalReference))
    required = {'networkDetails', 'adjacency', 'fusionWeights'};
    if ~isstruct(incrementalReference) || ...
            ~all(isfield(incrementalReference, required))
        error('TaskRiskV92:InvalidIncrementalReference', ...
            'The incremental reference is malformed.');
    end
    enumerationOptions.referenceNetworkDetails = ...
        incrementalReference.networkDetails;
    enumerationOptions.referenceAdjacency = ...
        incrementalReference.adjacency;
    enumerationOptions.referenceFusionWeights = ...
        incrementalReference.fusionWeights;
end
[networkDisagreement, networkDetails] = ...
    computeExpectedLmbNetworkDisagreementForDirectedRouting( ...
        context, adjacency, weights, enumerationOptions);
[taskRisk, taskRiskDetails] = ...
    computeExpectedLmbPosteriorTaskRiskV92( ...
        networkDetails, groupIds, context.model, ...
        protocol.riskOptions);

if isempty(referenceScore)
    referenceDistributions = networkDetails.receiverDistributions;
else
    referenceDistributions = ...
        referenceScore.networkDetails.receiverDistributions;
end
retentionOptions = struct( ...
    'referenceSupportThreshold', ...
        policy.referenceSupportThreshold, ...
    'decisionExistenceThreshold', ...
        policy.decisionExistenceThreshold, ...
    'receiverTailFraction', ...
        policy.retentionReceiverTailFraction, ...
    'receiverTailWeight', ...
        policy.retentionReceiverTailWeight);
[existenceRetentionRisk, retentionDetails] = ...
    computeLmbReferenceExistenceRetentionRisk( ...
        referenceDistributions, ...
        networkDetails.receiverDistributions, ...
        groupIds, retentionOptions);
minimumFormationCardinalityChange = min( ...
    retentionDetails.formationMeanCardinalityChange);
minimumSupportedLabelRetentionRatio = min( ...
    retentionDetails.minimumSupportedLabelRetentionRatio);
decisionThresholdCrossingCount = sum( ...
    retentionDetails.decisionThresholdCrossingCount);
retentionSafe = ...
    existenceRetentionRisk <= ...
        policy.maximumExistenceRetentionRisk + 1e-12 && ...
    minimumFormationCardinalityChange >= policy. ...
        minimumFormationMeanCardinalityChange - 1e-12 && ...
    minimumSupportedLabelRetentionRatio >= policy. ...
        minimumSupportedLabelRetentionRatio - 1e-12 && ...
    decisionThresholdCrossingCount <= ...
        policy.maximumDecisionThresholdCrossingCount;

taskRiskGainPercent = NaN;
worstReceiverRiskGainPercent = NaN;
worstFormationRiskGainPercent = NaN;
taskRiskSafe = true;
if ~isempty(referenceScore)
    taskRiskGainPercent = relativeGainPercent( ...
        referenceScore.taskRisk, taskRisk);
    worstReceiverRiskGainPercent = relativeGainPercent( ...
        referenceScore.taskRiskDetails.maximumReceiverRisk, ...
        taskRiskDetails.maximumReceiverRisk);
    worstFormationRiskGainPercent = relativeGainPercent( ...
        referenceScore.taskRiskDetails.maximumFormationMeanRisk, ...
        taskRiskDetails.maximumFormationMeanRisk);
    taskRiskSafe = ...
        taskRiskGainPercent >= ...
            protocol.minimumTaskRiskGainPercent - 1e-12 && ...
        worstReceiverRiskGainPercent >= ...
            protocol.minimumWorstReceiverRiskGainPercent - 1e-12 && ...
        worstFormationRiskGainPercent >= ...
            protocol.minimumWorstFormationRiskGainPercent - 1e-12;
end

score = struct();
score.contractVersion = ...
    'task-risk-input-protection-v92-route-score-v1';
score.networkDisagreement = networkDisagreement;
score.networkDetails = networkDetails;
score.taskRisk = taskRisk;
score.taskRiskDetails = taskRiskDetails;
score.taskRiskGainPercent = taskRiskGainPercent;
score.worstReceiverRiskGainPercent = ...
    worstReceiverRiskGainPercent;
score.worstFormationRiskGainPercent = ...
    worstFormationRiskGainPercent;
score.existenceRetentionRisk = existenceRetentionRisk;
score.retentionDetails = retentionDetails;
score.minimumFormationCardinalityChange = ...
    minimumFormationCardinalityChange;
score.minimumSupportedLabelRetentionRatio = ...
    minimumSupportedLabelRetentionRatio;
score.decisionThresholdCrossingCount = ...
    decisionThresholdCrossingCount;
score.retentionSafe = retentionSafe;
score.taskRiskSafe = taskRiskSafe;
score.safe = retentionSafe && taskRiskSafe;
score.truthUsed = false;
score.trackingOutcomeUsed = false;
score.futureOutcomeUsed = false;
score.eospaEqualityClaimed = false;
score.recursiveTrackingGuaranteeClaimed = false;
end

function value = relativeGainPercent(reference, candidate)
value = 100 * (reference - candidate) / max(abs(reference), eps);
end
