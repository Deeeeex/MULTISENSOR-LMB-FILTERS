function model = fitCvarResidualGraphPolicyModel( ...
        graphBlocks, fitSeeds, family, protocol)
% FITCVARRESIDUALGRAPHPOLICYMODEL Fit one frozen relational policy.

if nargin < 4 || isempty(protocol)
    protocol = getCvarResidualGraphPolicyDatasetProtocol();
end
family = lower(char(family));
fitSeeds = reshape(fitSeeds, 1, []);
if isempty(graphBlocks) || numel(fitSeeds) < 4 || ...
        any(~ismember(fitSeeds, protocol.trainingSeeds))
    error('CVaR graph fit split is invalid.');
end
training = assembleTraining(graphBlocks, fitSeeds);
switch family
    case 'ridge'
        model = fitRidgePolicy(training, protocol);
    case 'mlp'
        model = fitMlpPolicy(training, protocol);
    otherwise
        error('Unknown CVaR graph model family: %s.', family);
end
model.kind = ...
    'cvar-residual-relational-three-head-m24-v1';
model.contractVersion = protocol.modelContractVersion;
model.family = family;
model.fitSeeds = fitSeeds;
model.nodeFeatureNames = ...
    reshape(graphBlocks(1).nodeFeatureNames, 1, []);
model.edgeFeatureNames = ...
    reshape(graphBlocks(1).edgeFeatureNames, 1, []);
model.nodeFeatureCount = ...
    size(graphBlocks(1).nodeFeatures, 2);
model.edgeFeatureCount = ...
    size(graphBlocks(1).edgeFeatures, 3);
model.featuresUseTruth = false;
model.targetsUseTruth = true;
model.selectedEdgeWeightTargetUsedForTraining = false;
model.numericNodeIdentifiersUsed = false;
end

function training = assembleTraining(graphBlocks, fitSeeds)
selected = graphBlocks(ismember( ...
    [graphBlocks.seed], fitSeeds));
if isempty(selected)
    error('CVaR graph fit has no registered blocks.');
end
nodeFeatureCount = size(selected(1).nodeFeatures, 2);
edgeFeatureCount = size(selected(1).edgeFeatures, 3);
nodeX = zeros(0, nodeFeatureCount);
nodeY = zeros(0, 1);
nodeTail = false(0, 1);
nodeBlockIds = zeros(0, 1);
edgeX = zeros(0, edgeFeatureCount);
edgeTaskY = zeros(0, 1);
edgeSafetyY = zeros(0, 1);
edgeSafetyObserved = false(0, 1);
edgeReceiverNodeRows = zeros(0, 1);
edgeSenderNodeRows = zeros(0, 1);
blockSeeds = zeros(1, numel(selected));
nodeOffset = 0;
for blockIdx = 1:numel(selected)
    block = selected(blockIdx);
    nodeCount = size(block.nodeFeatures, 1);
    candidateCount = size(block.edgeFeatures, 1);
    weightCount = size(block.edgeFeatures, 2);
    if size(block.nodeFeatures, 2) ~= nodeFeatureCount || ...
            size(block.edgeFeatures, 3) ~= ...
                edgeFeatureCount || ...
            numel(block.nodeRiskTarget) ~= nodeCount || ...
            numel(block.nodeCvarMaskTarget) ~= nodeCount || ...
            ~isequal(size(block.edgeTaskAdvantageTarget), ...
                [candidateCount, weightCount]) || ...
            ~isequal(size( ...
                block.edgeProtectionAdvantageTarget), ...
                [candidateCount, weightCount]) || ...
            ~isequal(size( ...
                block.edgeProtectionObservedMask), ...
                [candidateCount, weightCount]) || ...
            block.featuresUseTruth || ...
            block.featuresUseFutureOutcome || ...
            ~block.targetsUseTruth || ...
            block.targetsUseFutureOutcome
        error('CVaR graph training block contract changed.');
    end
    receiverRows = repmat( ...
        reshape(block.receiverIndices, [], 1), ...
        weightCount, 1);
    senderRows = repmat( ...
        reshape(block.senderIndices, [], 1), ...
        weightCount, 1);
    flatEdgeX = reshape(block.edgeFeatures, ...
        candidateCount * weightCount, edgeFeatureCount);
    nodeX = [nodeX; block.nodeFeatures]; %#ok<AGROW>
    nodeY = [nodeY; reshape( ...
        block.nodeRiskTarget, [], 1)]; %#ok<AGROW>
    nodeTail = [nodeTail; reshape(logical( ...
        block.nodeCvarMaskTarget), [], 1)]; %#ok<AGROW>
    nodeBlockIds = [nodeBlockIds; ...
        blockIdx * ones(nodeCount, 1)]; %#ok<AGROW>
    edgeX = [edgeX; flatEdgeX]; %#ok<AGROW>
    edgeTaskY = [edgeTaskY; ...
        block.edgeTaskAdvantageTarget(:)]; %#ok<AGROW>
    edgeSafetyY = [edgeSafetyY; ...
        block.edgeProtectionAdvantageTarget(:)]; %#ok<AGROW>
    edgeSafetyObserved = [edgeSafetyObserved; ...
        block.edgeProtectionObservedMask(:)]; %#ok<AGROW>
    edgeReceiverNodeRows = [edgeReceiverNodeRows; ...
        nodeOffset + receiverRows]; %#ok<AGROW>
    edgeSenderNodeRows = [edgeSenderNodeRows; ...
        nodeOffset + senderRows]; %#ok<AGROW>
    blockSeeds(blockIdx) = block.seed;
    nodeOffset = nodeOffset + nodeCount;
end
if any(~isfinite(nodeX(:))) || ...
        any(~isfinite(nodeY(:))) || ...
        any(~isfinite(edgeX(:))) || ...
        any(~isfinite(edgeTaskY(:))) || ...
        any(~isfinite( ...
            edgeSafetyY(edgeSafetyObserved))) || ...
        nnz(edgeSafetyObserved) == 0
    error('CVaR graph training arrays are invalid.');
end
seedStateCounts = arrayfun(@(seed) ...
    nnz(blockSeeds == seed), fitSeeds);
if numel(unique(seedStateCounts)) ~= 1
    error('CVaR graph fit would not weight seeds equally.');
end
training = struct();
training.nodeX = nodeX;
training.nodeY = nodeY;
training.nodeTail = nodeTail;
training.nodeBlockIds = nodeBlockIds;
training.edgeX = edgeX;
training.edgeTaskY = edgeTaskY;
training.edgeSafetyY = edgeSafetyY;
training.edgeSafetyObserved = edgeSafetyObserved;
training.edgeReceiverNodeRows = ...
    edgeReceiverNodeRows;
training.edgeSenderNodeRows = ...
    edgeSenderNodeRows;
training.blockSeeds = blockSeeds;
training.blockCount = numel(selected);
end

function model = fitRidgePolicy(training, protocol)
node = fitRidgeHead(training.nodeX, ...
    training.nodeY, protocol.modelRidgeLambda);
receiverX = training.nodeX( ...
    training.edgeReceiverNodeRows, :);
senderX = training.nodeX( ...
    training.edgeSenderNodeRows, :);
edgeRelationalX = [training.edgeX, ...
    receiverX, senderX, receiverX - senderX];
task = fitRidgeHead(edgeRelationalX, ...
    training.edgeTaskY, protocol.modelRidgeLambda);
safety = fitRidgeHead( ...
    edgeRelationalX(training.edgeSafetyObserved, :), ...
    training.edgeSafetyY( ...
        training.edgeSafetyObserved), ...
    protocol.modelRidgeLambda);
model = struct();
model.nodeHead = node;
model.edgeTaskHead = task;
model.edgeSafetyHead = safety;
model.nodeHiddenWidth = 0;
model.edgeHiddenWidth = 0;
model.trainingLossHistory = zeros(0, 4);
end

function head = fitRidgeHead(X, y, lambda)
[featureMean, featureScale] = fitScaler(X);
Z = applyScaler(X, featureMean, featureScale);
targetMean = mean(y);
targetScale = std(y);
if ~isfinite(targetScale) || targetScale <= eps
    targetScale = 1;
end
target = (y - targetMean) / targetScale;
design = [ones(size(Z, 1), 1), Z];
regularizer = diag([0, ones(1, size(Z, 2))]);
coefficients = (design' * design + ...
    lambda * regularizer) \ (design' * target);
if any(~isfinite(coefficients))
    error('CVaR graph ridge fit produced non-finite values.');
end
head = struct();
head.featureMean = featureMean;
head.featureScale = featureScale;
head.targetMean = targetMean;
head.targetScale = targetScale;
head.coefficients = coefficients;
head.lambda = lambda;
end

function model = fitMlpPolicy(training, protocol)
[nodeMean, nodeScale] = fitScaler(training.nodeX);
nodeZ = applyScaler(training.nodeX, nodeMean, nodeScale);
nodeTargetMean = mean(training.nodeY);
nodeTargetScale = std(training.nodeY);
if ~isfinite(nodeTargetScale) || nodeTargetScale <= eps
    nodeTargetScale = 1;
end
nodeTarget = ...
    (training.nodeY - nodeTargetMean) / nodeTargetScale;
[nodeEncoder, nodeRiskHead, nodeLoss] = fitNodeMlp( ...
    nodeZ, nodeTarget, training.nodeTail, ...
    training.nodeBlockIds, protocol);
nodeHidden = tanh(bsxfun(@plus, ...
    nodeZ * nodeEncoder.weight, nodeEncoder.bias));

[edgeMean, edgeScale] = fitScaler(training.edgeX);
edgeZ = applyScaler(training.edgeX, ...
    edgeMean, edgeScale);
receiverHidden = nodeHidden( ...
    training.edgeReceiverNodeRows, :);
senderHidden = nodeHidden( ...
    training.edgeSenderNodeRows, :);
relational = [edgeZ, receiverHidden, senderHidden, ...
    receiverHidden - senderHidden, ...
    receiverHidden .* senderHidden];
[relationalMean, relationalScale] = ...
    fitScaler(relational);
relationalZ = applyScaler(relational, ...
    relationalMean, relationalScale);
taskTargetMean = mean(training.edgeTaskY);
taskTargetScale = std(training.edgeTaskY);
if ~isfinite(taskTargetScale) || ...
        taskTargetScale <= eps
    taskTargetScale = 1;
end
taskTarget = (training.edgeTaskY - ...
    taskTargetMean) / taskTargetScale;
safetyObserved = training.edgeSafetyObserved;
safetyTargetMean = mean( ...
    training.edgeSafetyY(safetyObserved));
safetyTargetScale = std( ...
    training.edgeSafetyY(safetyObserved));
if ~isfinite(safetyTargetScale) || ...
        safetyTargetScale <= eps
    safetyTargetScale = 1;
end
safetyTarget = zeros(size(training.edgeSafetyY));
safetyTarget(safetyObserved) = ...
    (training.edgeSafetyY(safetyObserved) - ...
        safetyTargetMean) / safetyTargetScale;
[edgeEncoder, edgeHeads, edgeLoss] = fitEdgeMlp( ...
    relationalZ, taskTarget, safetyTarget, ...
    safetyObserved, protocol);

model = struct();
model.nodeFeatureMean = nodeMean;
model.nodeFeatureScale = nodeScale;
model.nodeTargetMean = nodeTargetMean;
model.nodeTargetScale = nodeTargetScale;
model.nodeEncoder = nodeEncoder;
model.nodeRiskHead = nodeRiskHead;
model.edgeFeatureMean = edgeMean;
model.edgeFeatureScale = edgeScale;
model.relationalFeatureMean = relationalMean;
model.relationalFeatureScale = relationalScale;
model.edgeTaskTargetMean = taskTargetMean;
model.edgeTaskTargetScale = taskTargetScale;
model.edgeSafetyTargetMean = safetyTargetMean;
model.edgeSafetyTargetScale = safetyTargetScale;
model.edgeEncoder = edgeEncoder;
model.edgeHeads = edgeHeads;
model.nodeHiddenWidth = ...
    protocol.modelNodeHiddenWidth;
model.edgeHiddenWidth = ...
    protocol.modelEdgeHiddenWidth;
model.trainingLossHistory = ...
    [nodeLoss, edgeLoss];
end

function [encoder, head, lossHistory] = fitNodeMlp( ...
        X, target, tailMask, blockIds, protocol)
rng(protocol.modelInitializationSeed);
hiddenWidth = protocol.modelNodeHiddenWidth;
parameters = { ...
    randn(size(X, 2), hiddenWidth) / sqrt(size(X, 2)), ...
    zeros(1, hiddenWidth), ...
    randn(hiddenWidth, 1) / sqrt(hiddenWidth), ...
    0};
[firstMoment, secondMoment] = ...
    initializeAdam(parameters);
epochCount = protocol.modelMlpEpochCount;
lossHistory = nan(epochCount, 2);
blockCount = max(blockIds);
for epoch = 1:epochCount
    hidden = tanh(bsxfun(@plus, ...
        X * parameters{1}, parameters{2}));
    prediction = hidden * parameters{3} + parameters{4};
    [riskLoss, dPrediction] = huberLossGradient( ...
        prediction - target, protocol.modelHuberDelta);
    dPrediction = protocol.modelNodeRiskLossWeight * ...
        dPrediction / numel(target);
    riskLoss = protocol.modelNodeRiskLossWeight * riskLoss;
    rankLoss = 0;
    for blockIdx = 1:blockCount
        mask = blockIds == blockIdx;
        blockScores = prediction(mask);
        shifted = blockScores - max(blockScores);
        probability = exp(shifted);
        probability = probability / sum(probability);
        blockTarget = double(tailMask(mask));
        blockTarget = blockTarget / sum(blockTarget);
        rankLoss = rankLoss - sum( ...
            blockTarget .* log(max(probability, 1e-12)));
        dPrediction(mask) = dPrediction(mask) + ...
            protocol.modelNodeRankLossWeight * ...
            (probability - blockTarget) / blockCount;
    end
    rankLoss = protocol.modelNodeRankLossWeight * ...
        rankLoss / blockCount;
    regularization = 0.5 * ...
        protocol.modelMlpWeightDecay * ( ...
            sum(parameters{1}(:).^2) + ...
            sum(parameters{3}(:).^2));
    gradients = cell(1, 4);
    gradients{3} = hidden' * dPrediction + ...
        protocol.modelMlpWeightDecay * parameters{3};
    gradients{4} = sum(dPrediction);
    dHidden = dPrediction * parameters{3}';
    dActivation = dHidden .* (1 - hidden.^2);
    gradients{1} = X' * dActivation + ...
        protocol.modelMlpWeightDecay * parameters{1};
    gradients{2} = sum(dActivation, 1);
    [parameters, firstMoment, secondMoment] = adamStep( ...
        parameters, gradients, firstMoment, ...
        secondMoment, epoch, ...
        protocol.modelMlpLearningRate);
    lossHistory(epoch, :) = ...
        [riskLoss + rankLoss + regularization, ...
         regularization];
end
validateParameters(parameters, lossHistory, ...
    'CVaR graph node MLP');
encoder = struct('weight', parameters{1}, ...
    'bias', parameters{2});
head = struct('weight', parameters{3}, ...
    'bias', parameters{4});
end

function [encoder, heads, lossHistory] = fitEdgeMlp( ...
        X, taskTarget, safetyTarget, safetyObserved, protocol)
rng(protocol.modelInitializationSeed + 1);
hiddenWidth = protocol.modelEdgeHiddenWidth;
parameters = { ...
    randn(size(X, 2), hiddenWidth) / sqrt(size(X, 2)), ...
    zeros(1, hiddenWidth), ...
    randn(hiddenWidth, 2) / sqrt(hiddenWidth), ...
    zeros(1, 2)};
[firstMoment, secondMoment] = ...
    initializeAdam(parameters);
epochCount = protocol.modelMlpEpochCount;
lossHistory = nan(epochCount, 3);
for epoch = 1:epochCount
    hidden = tanh(bsxfun(@plus, ...
        X * parameters{1}, parameters{2}));
    prediction = bsxfun(@plus, ...
        hidden * parameters{3}, parameters{4});
    [taskLoss, taskGradient] = huberLossGradient( ...
        prediction(:, 1) - taskTarget, ...
        protocol.modelHuberDelta);
    safetyResidual = prediction(safetyObserved, 2) - ...
        safetyTarget(safetyObserved);
    [safetyLoss, observedSafetyGradient] = ...
        huberLossGradient(safetyResidual, ...
            protocol.modelHuberDelta);
    dPrediction = zeros(size(prediction));
    dPrediction(:, 1) = ...
        protocol.modelEdgeTaskLossWeight * ...
        taskGradient / numel(taskGradient);
    dPrediction(safetyObserved, 2) = ...
        protocol.modelEdgeSafetyLossWeight * ...
        observedSafetyGradient / ...
        numel(observedSafetyGradient);
    taskLoss = protocol.modelEdgeTaskLossWeight * taskLoss;
    safetyLoss = ...
        protocol.modelEdgeSafetyLossWeight * safetyLoss;
    regularization = 0.5 * ...
        protocol.modelMlpWeightDecay * ( ...
            sum(parameters{1}(:).^2) + ...
            sum(parameters{3}(:).^2));
    gradients = cell(1, 4);
    gradients{3} = hidden' * dPrediction + ...
        protocol.modelMlpWeightDecay * parameters{3};
    gradients{4} = sum(dPrediction, 1);
    dHidden = dPrediction * parameters{3}';
    dActivation = dHidden .* (1 - hidden.^2);
    gradients{1} = X' * dActivation + ...
        protocol.modelMlpWeightDecay * parameters{1};
    gradients{2} = sum(dActivation, 1);
    [parameters, firstMoment, secondMoment] = adamStep( ...
        parameters, gradients, firstMoment, ...
        secondMoment, epoch, ...
        protocol.modelMlpLearningRate);
    lossHistory(epoch, :) = ...
        [taskLoss, safetyLoss, regularization];
end
validateParameters(parameters, lossHistory, ...
    'CVaR graph edge MLP');
encoder = struct('weight', parameters{1}, ...
    'bias', parameters{2});
heads = struct('weight', parameters{3}, ...
    'bias', parameters{4});
end

function [loss, gradient] = huberLossGradient(residual, delta)
absolute = abs(residual);
quadratic = absolute <= delta;
values = delta * absolute - 0.5 * delta^2;
values(quadratic) = 0.5 * residual(quadratic).^2;
gradient = delta * sign(residual);
gradient(quadratic) = residual(quadratic);
loss = mean(values);
end

function [meanValue, scaleValue] = fitScaler(X)
meanValue = mean(X, 1);
scaleValue = std(X, 0, 1);
scaleValue(~isfinite(scaleValue) | ...
    scaleValue <= eps) = 1;
end

function Z = applyScaler(X, meanValue, scaleValue)
Z = bsxfun(@rdivide, ...
    bsxfun(@minus, X, meanValue), scaleValue);
end

function [firstMoment, secondMoment] = ...
        initializeAdam(parameters)
firstMoment = cellfun(@(value) zeros(size(value)), ...
    parameters, 'UniformOutput', false);
secondMoment = cellfun(@(value) zeros(size(value)), ...
    parameters, 'UniformOutput', false);
end

function [parameters, firstMoment, secondMoment] = ...
        adamStep(parameters, gradients, ...
            firstMoment, secondMoment, epoch, learningRate)
gradients = clipGradients(gradients, 10);
for parameterIdx = 1:numel(parameters)
    firstMoment{parameterIdx} = ...
        0.9 * firstMoment{parameterIdx} + ...
        0.1 * gradients{parameterIdx};
    secondMoment{parameterIdx} = ...
        0.999 * secondMoment{parameterIdx} + ...
        0.001 * gradients{parameterIdx}.^2;
    correctedFirst = firstMoment{parameterIdx} / ...
        (1 - 0.9^epoch);
    correctedSecond = secondMoment{parameterIdx} / ...
        (1 - 0.999^epoch);
    parameters{parameterIdx} = ...
        parameters{parameterIdx} - learningRate * ...
        correctedFirst ./ (sqrt(correctedSecond) + 1e-8);
end
end

function gradients = clipGradients(gradients, maximumNorm)
squaredNorm = 0;
for gradient = gradients
    squaredNorm = squaredNorm + ...
        sum(gradient{1}(:).^2);
end
normValue = sqrt(squaredNorm);
if normValue > maximumNorm
    scale = maximumNorm / normValue;
    gradients = cellfun(@(value) value * scale, ...
        gradients, 'UniformOutput', false);
end
end

function validateParameters(parameters, lossHistory, label)
if any(~isfinite(lossHistory(:))) || ...
        any(cellfun(@(value) ...
            any(~isfinite(value(:))), parameters))
    error('%s produced non-finite values.', label);
end
end
