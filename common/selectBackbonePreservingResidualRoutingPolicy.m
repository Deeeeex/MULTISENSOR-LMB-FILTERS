function [adjacency, details] = ...
    selectBackbonePreservingResidualRoutingPolicy( ...
        context, mode, options)
% SELECTBACKBONEPRESERVINGRESIDUALROUTINGPOLICY Safe additive residual.
%
% A high-weight fixed-index input remains untouched. The exact rolling-B3
% policy controls only a low-weight balanced-cycle residual input, so
% cross-formation communication cannot delete the strong tracking route.

if nargin < 2 || isempty(mode)
    mode = 'posterior-analytic';
end
if nargin < 3 || isempty(options)
    options = struct();
end
dominantWeight = getField(options, ...
    'dominantWeight', 0.70);
residualWeight = getField(options, ...
    'residualWeight', 0.05);
[dominantAdjacency, dominantDetails] = ...
    selectRegisteredDirectedRoutingPolicy( ...
        context, 'fixed-index-star', ...
        struct('sourceWeight', dominantWeight));
[residualBaselineAdjacency, residualBaselineDetails] = ...
    selectRegisteredDirectedRoutingPolicy( ...
        context, 'fixed-balanced-cycle', ...
        struct('sourceWeight', residualWeight, 'phase', 1));
dominantSources = reshape( ...
    dominantDetails.selectedSourcesByReceiver, 1, []);
residualBaselineSources = reshape( ...
    residualBaselineDetails.selectedSourcesByReceiver, 1, []);
groupIds = reshape(context.model.dynamicTopologyScenario. ...
    config.sensorGroupIds, 1, []);
[candidateReceivers, candidateSenders] = ...
    find(logical(context.physicalAdjacency));
crossMask = groupIds(candidateReceivers) ~= ...
    groupIds(candidateSenders);
candidateReceivers = candidateReceivers(crossMask);
nonduplicateReceiverMask = dominantSources(candidateReceivers) ~= ...
    residualBaselineSources(candidateReceivers);
residualOptions = options;
residualOptions.sourceWeight = residualWeight;
residualOptions.backboneMode = ...
    'fixed-balanced-cycle';
providedAllowedMask = getField(residualOptions, ...
    'currentAllowedExampleMask', ...
    true(numel(candidateReceivers), 1));
providedAllowedMask = reshape( ...
    logical(providedAllowedMask), [], 1);
if numel(providedAllowedMask) ~= numel(candidateReceivers)
    error('Residual allowed-action mask has the wrong length.');
end
residualOptions.currentAllowedExampleMask = ...
    providedAllowedMask & ...
    reshape(nonduplicateReceiverMask, [], 1);
[residualAdjacency, residualDetails] = ...
    selectRollingSafeRoutingPolicy( ...
        context, mode, residualOptions);
[adjacency, fusionWeights, routeDetails] = ...
    buildBackbonePreservingResidualRoute( ...
        context, dominantAdjacency, residualAdjacency, ...
        dominantWeight, residualWeight);

details = residualDetails;
routeFields = fieldnames(routeDetails);
for fieldIdx = 1:numel(routeFields)
    details.(routeFields{fieldIdx}) = ...
        routeDetails.(routeFields{fieldIdx});
end
details.mode = ['backbone-preserving-residual-', ...
    lower(strrep(char(mode), '_', '-'))];
details.fusionWeightMatrix = fusionWeights;
details.dominantAdjacency = dominantAdjacency;
details.residualAdjacency = residualAdjacency;
details.residualBaselineAdjacency = ...
    residualBaselineAdjacency;
details.dominantPolicyDetails = dominantDetails;
details.residualPolicyDetails = residualDetails;
details.duplicateBaselineReceiverMask = ...
    dominantSources == residualBaselineSources;
details.duplicateBaselineReceiverCount = nnz( ...
    details.duplicateBaselineReceiverMask);
details.crossOverrideOfDuplicateReceiverCount = nnz( ...
    residualDetails.overrideMask & ...
    details.duplicateBaselineReceiverMask);
details.backboneMode = ...
    'fixed-index-plus-balanced-cycle-residual';
details.sourceWeight = residualWeight;
details.topologyInfeasible = false;
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
