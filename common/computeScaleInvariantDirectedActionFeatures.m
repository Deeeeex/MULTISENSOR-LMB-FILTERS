function [actionFeatures, featureNames, metadata] = ...
    computeScaleInvariantDirectedActionFeatures( ...
        context, sourceWeightGrid, options)
% COMPUTESCALEINVARIANTDIRECTEDACTIONFEATURES Joint sender-weight features.
%
% Unlike the first kNN prototype, this representation normalizes
% cardinality statistics by the registered target capacity and treats the
% KLA source weight as part of the action. Rows are
%
%   actionFeatures(receiver, sender, weightIndex, featureIndex).
%
% The function reads no target truth. It may consume a precomputed raw edge
% tensor through options.rawFeatures/options.rawFeatureNames.

if nargin < 2 || isempty(sourceWeightGrid)
    sourceWeightGrid = [0.15, 0.30, 0.50, 0.70];
end
if nargin < 3 || isempty(options)
    options = struct();
end
sourceWeightGrid = reshape(sourceWeightGrid, 1, []);
if any(~isfinite(sourceWeightGrid)) || ...
        any(sourceWeightGrid <= 0 | sourceWeightGrid >= 1)
    error('sourceWeightGrid must be finite and strictly between 0 and 1.');
end

if isfield(options, 'rawFeatures') && ...
        isfield(options, 'rawFeatureNames')
    raw = options.rawFeatures;
    rawNames = reshape(options.rawFeatureNames, 1, []);
else
    [raw, rawNames] = computeDirectedRoutingFeatures(context);
end
nodeCount = size(raw, 1);
physical = logical(context.physicalAdjacency);
if ~isequal(size(physical), [nodeCount, nodeCount])
    error('physicalAdjacency must be S-by-S.');
end
physical(1:nodeCount+1:end) = false;
targetCapacity = max(resolveTargetCapacity(context.model), 1);

baseNames = { ...
    'link_reliability', ...
    'same_formation', ...
    'normalized_sensor_distance', ...
    'source_expected_cardinality_fraction', ...
    'receiver_expected_cardinality_fraction', ...
    'source_cardinality_variance_fraction', ...
    'receiver_cardinality_variance_fraction', ...
    'source_position_variance', ...
    'receiver_position_variance', ...
    'source_association_confidence', ...
    'receiver_association_confidence', ...
    'source_detection_mass', ...
    'receiver_detection_mass', ...
    'positive_existence_gain', ...
    'negative_existence_gap', ...
    'positive_precision_gain', ...
    'negative_precision_gap', ...
    'normalized_state_discrepancy', ...
    'active_label_overlap', ...
    'node_quality_advantage', ...
    'receiver_need', ...
    'moment_compatibility_score', ...
    'reliability_rank', ...
    'moment_compatibility_rank', ...
    'previous_edge'};
baseFeatureCount = numel(baseNames);
base = nan(nodeCount, nodeCount, baseFeatureCount);

reliability = feature(raw, rawNames, 'link_reliability');
sameFormation = feature(raw, rawNames, 'same_formation');
distance = feature(raw, rawNames, 'normalized_sensor_distance');
sourceCardinality = feature( ...
    raw, rawNames, 'source_expected_cardinality') / targetCapacity;
receiverCardinality = feature( ...
    raw, rawNames, 'receiver_expected_cardinality') / targetCapacity;
sourceCardinalityVariance = feature( ...
    raw, rawNames, 'source_cardinality_variance') / targetCapacity;
receiverCardinalityVariance = feature( ...
    raw, rawNames, 'receiver_cardinality_variance') / targetCapacity;
sourcePositionVariance = feature( ...
    raw, rawNames, 'source_position_variance');
receiverPositionVariance = feature( ...
    raw, rawNames, 'receiver_position_variance');
sourceAssociation = feature( ...
    raw, rawNames, 'source_association_confidence');
receiverAssociation = feature( ...
    raw, rawNames, 'receiver_association_confidence');
sourceDetection = feature(raw, rawNames, 'source_detection_mass');
receiverDetection = feature(raw, rawNames, 'receiver_detection_mass');
positiveExistence = feature( ...
    raw, rawNames, 'positive_existence_gain');
negativeExistence = feature( ...
    raw, rawNames, 'negative_existence_gap');
positivePrecision = feature( ...
    raw, rawNames, 'positive_precision_gain');
negativePrecision = feature( ...
    raw, rawNames, 'negative_precision_gap');
discrepancy = feature( ...
    raw, rawNames, 'normalized_state_discrepancy');
overlap = feature(raw, rawNames, 'active_label_overlap');
qualityAdvantage = feature( ...
    raw, rawNames, 'node_quality_advantage');
receiverNeed = feature(raw, rawNames, 'receiver_need');
momentCompatibility = reliability - ...
    0.25 * distance - 0.25 * discrepancy - negativePrecision;
reliabilityRank = receiverRanks(reliability, physical);
compatibilityRank = receiverRanks(momentCompatibility, physical);
previous = zeros(nodeCount);
if isfield(context, 'previousAdjacency') && ...
        isequal(size(context.previousAdjacency), [nodeCount, nodeCount])
    previous = double(logical(context.previousAdjacency));
end

base(:, :, :) = cat(3, ...
    reliability, sameFormation, distance, ...
    sourceCardinality, receiverCardinality, ...
    sourceCardinalityVariance, receiverCardinalityVariance, ...
    sourcePositionVariance, receiverPositionVariance, ...
    sourceAssociation, receiverAssociation, ...
    sourceDetection, receiverDetection, ...
    positiveExistence, negativeExistence, ...
    positivePrecision, negativePrecision, ...
    discrepancy, overlap, qualityAdvantage, receiverNeed, ...
    momentCompatibility, reliabilityRank, compatibilityRank, previous);
for featureIdx = 1:baseFeatureCount
    slice = base(:, :, featureIdx);
    slice(~physical) = NaN;
    base(:, :, featureIdx) = slice;
end

featureNames = [baseNames, { ...
    'source_weight', ...
    'source_weight_squared', ...
    'weight_x_reliability', ...
    'weight_x_discrepancy', ...
    'weight_x_negative_precision_gap', ...
    'weight_x_positive_existence_gain', ...
    'backbone_action'}];
featureCount = numel(featureNames);
weightCount = numel(sourceWeightGrid);
actionFeatures = nan( ...
    nodeCount, nodeCount, weightCount, featureCount);
[~, backboneWeightIdx] = min(abs(sourceWeightGrid - 0.50));
for weightIdx = 1:weightCount
    sourceWeight = sourceWeightGrid(weightIdx);
    actionFeatures(:, :, weightIdx, 1:baseFeatureCount) = base;
    actionFeatures(:, :, weightIdx, baseFeatureCount + 1) = ...
        maskedConstant(sourceWeight, physical);
    actionFeatures(:, :, weightIdx, baseFeatureCount + 2) = ...
        maskedConstant(sourceWeight^2, physical);
    actionFeatures(:, :, weightIdx, baseFeatureCount + 3) = ...
        sourceWeight * reliability;
    actionFeatures(:, :, weightIdx, baseFeatureCount + 4) = ...
        sourceWeight * discrepancy;
    actionFeatures(:, :, weightIdx, baseFeatureCount + 5) = ...
        sourceWeight * negativePrecision;
    actionFeatures(:, :, weightIdx, baseFeatureCount + 6) = ...
        sourceWeight * positiveExistence;
    backbone = zeros(nodeCount);
    if weightIdx == backboneWeightIdx
        for receiverIdx = 1:nodeCount
            senders = find(physical(receiverIdx, :));
            if isempty(senders)
                continue;
            end
            [~, bestCursor] = max( ...
                reliability(receiverIdx, senders));
            backbone(receiverIdx, senders(bestCursor)) = 1;
        end
    end
    backbone(~physical) = NaN;
    actionFeatures(:, :, weightIdx, baseFeatureCount + 7) = backbone;
end

metadata = struct();
metadata.targetCapacity = targetCapacity;
metadata.sourceWeightGrid = sourceWeightGrid;
metadata.featureNames = featureNames;
metadata.backboneWeight = sourceWeightGrid(backboneWeightIdx);
metadata.backboneWeightIndex = backboneWeightIdx;
metadata.truthUsed = false;
metadata.scaleInvariantCardinality = true;
end

function matrix = feature(raw, names, name)
idx = find(strcmp(names, name), 1);
if isempty(idx)
    error('Missing directed-routing feature: %s', name);
end
matrix = reshape(raw(:, :, idx), size(raw, 1), size(raw, 2));
end

function ranks = receiverRanks(values, physical)
nodeCount = size(values, 1);
ranks = nan(nodeCount);
for receiverIdx = 1:nodeCount
    senders = find(physical(receiverIdx, :));
    if isempty(senders)
        continue;
    end
    [~, order] = sort(values(receiverIdx, senders), 'descend');
    count = numel(senders);
    percentile = ones(1, count);
    if count > 1
        percentile(order) = 1 - (0:(count - 1)) / (count - 1);
    end
    ranks(receiverIdx, senders) = percentile;
end
end

function matrix = maskedConstant(value, physical)
matrix = value * ones(size(physical));
matrix(~physical) = NaN;
end

function count = resolveTargetCapacity(model)
count = 0;
if isfield(model, 'birthTimeByLocation')
    count = numel(model.birthTimeByLocation);
elseif isfield(model, 'dynamicTopologyScenario') && ...
        isfield(model.dynamicTopologyScenario, 'config') && ...
        isfield(model.dynamicTopologyScenario.config, 'numberOfTargets')
    count = model.dynamicTopologyScenario.config.numberOfTargets;
elseif isfield(model, 'birthParameters')
    count = numel(model.birthParameters);
end
if ~isscalar(count) || ~isfinite(count) || count < 1
    count = 1;
end
end
