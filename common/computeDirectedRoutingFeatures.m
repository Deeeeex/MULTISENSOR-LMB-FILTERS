function [features, featureNames, nodeSummary] = ...
    computeDirectedRoutingFeatures(context, options)
% COMPUTEDIRECTEDROUTINGFEATURES Deployment-observable edge features.
%
% Rows follow the routing convention used by the directed policy:
% features(receiver, sender, :). No truth state is read. Features use only
% local LMB summaries, sensor geometry, formation membership, and link
% reliability available at the current time.

if nargin < 2 || isempty(options)
    options = struct();
end
posteriors = reshape(context.localPosteriorBySensor, 1, []);
nodeCount = numel(posteriors);
positionScale = max(getField(options, 'positionScale', ...
    resolvePositionScale(context.model)), eps);
existenceThreshold = getField(options, 'existenceThreshold', 0.01);
positions = getField(context, 'positions', zeros(2, nodeCount));
groupIds = resolveGroupIds(context.model, nodeCount);
commRange = max(getField(context.model, 'sensorCommRange', inf), eps);

featureNames = { ...
    'bias', ...
    'link_reliability', ...
    'same_formation', ...
    'normalized_sensor_distance', ...
    'source_expected_cardinality', ...
    'receiver_expected_cardinality', ...
    'source_cardinality_variance', ...
    'receiver_cardinality_variance', ...
    'source_position_variance', ...
    'receiver_position_variance', ...
    'source_association_confidence', ...
    'receiver_association_confidence', ...
    'source_detection_mass', ...
    'receiver_detection_mass', ...
    'positive_existence_gain', ...
    'negative_existence_gap', ...
    'positive_precision_gain', ...
    'negative_precision_gap', ...
    'normalized_state_discrepancy', ...
    'active_label_overlap', ...
    'node_quality_advantage', ...
    'receiver_need'};
featureCount = numel(featureNames);
features = nan(nodeCount, nodeCount, featureCount);

nodeSummary = repmat(struct( ...
    'expectedCardinality', 0, ...
    'cardinalityVariance', 0, ...
    'positionVariance', 0, ...
    'associationConfidence', 0, ...
    'detectionMass', 0, ...
    'activeLabelCount', 0, ...
    'quality', 0, ...
    'need', 0), 1, nodeCount);
for nodeIdx = 1:nodeCount
    nodeSummary(nodeIdx) = summarizeNode( ...
        posteriors{nodeIdx}, positionScale, existenceThreshold);
end

physical = logical(context.physicalAdjacency);
for receiverIdx = 1:nodeCount
    for senderIdx = 1:nodeCount
        if receiverIdx == senderIdx || ~physical(receiverIdx, senderIdx)
            continue;
        end
        reliability = 1 - edgeDrop( ...
            context.commConfig, senderIdx, receiverIdx, ...
            context.currentTime);
        distance = norm( ...
            positions(:, receiverIdx) - positions(:, senderIdx));
        if isfinite(commRange)
            normalizedDistance = distance / commRange;
        else
            normalizedDistance = 0;
        end
        pair = summarizePair( ...
            posteriors{receiverIdx}, posteriors{senderIdx}, ...
            positionScale, existenceThreshold);
        source = nodeSummary(senderIdx);
        receiver = nodeSummary(receiverIdx);
        features(receiverIdx, senderIdx, :) = [ ...
            1, ...
            reliability, ...
            double(groupIds(receiverIdx) == groupIds(senderIdx)), ...
            normalizedDistance, ...
            source.expectedCardinality, ...
            receiver.expectedCardinality, ...
            source.cardinalityVariance, ...
            receiver.cardinalityVariance, ...
            source.positionVariance, ...
            receiver.positionVariance, ...
            source.associationConfidence, ...
            receiver.associationConfidence, ...
            source.detectionMass, ...
            receiver.detectionMass, ...
            pair.positiveExistenceGain, ...
            pair.negativeExistenceGap, ...
            pair.positivePrecisionGain, ...
            pair.negativePrecisionGap, ...
            pair.normalizedStateDiscrepancy, ...
            pair.activeLabelOverlap, ...
            source.quality - receiver.quality, ...
            receiver.need];
    end
end
end

function summary = summarizeNode( ...
    objects, positionScale, existenceThreshold)
summary = struct( ...
    'expectedCardinality', 0, ...
    'cardinalityVariance', 0, ...
    'positionVariance', 0, ...
    'associationConfidence', 0, ...
    'detectionMass', 0, ...
    'activeLabelCount', 0, ...
    'quality', 0, ...
    'need', 0);
if isempty(objects)
    summary.need = 1;
    return;
end
existence = max(min(reshape([objects.r], 1, []), 1), 0);
active = existence >= existenceThreshold;
summary.expectedCardinality = sum(existence);
summary.cardinalityVariance = sum(existence .* (1 - existence));
summary.activeLabelCount = sum(active);
if ~any(active)
    summary.need = 1;
    return;
end
weights = existence(active);
weights = weights / max(sum(weights), eps);
activeObjects = objects(active);
positionVariance = zeros(1, numel(activeObjects));
associationConfidence = zeros(1, numel(activeObjects));
detectionMass = zeros(1, numel(activeObjects));
for objectIdx = 1:numel(activeObjects)
    [~, covariance] = momentMatchObject(activeObjects(objectIdx));
    positionVariance(objectIdx) = ...
        trace(covariance(1:2, 1:2)) / positionScale^2;
    associationConfidence(objectIdx) = getScalarField( ...
        activeObjects(objectIdx), 'associationConfidence', 0);
    detectionMass(objectIdx) = getScalarField( ...
        activeObjects(objectIdx), 'detectionAssociationMass', 0);
end
summary.positionVariance = sum(weights .* positionVariance);
summary.associationConfidence = ...
    sum(weights .* associationConfidence);
summary.detectionMass = sum(weights .* detectionMass);
summary.quality = ...
    summary.associationConfidence + summary.detectionMass - ...
    summary.positionVariance - ...
    summary.cardinalityVariance / max(summary.expectedCardinality, 1);
summary.need = summary.positionVariance + ...
    summary.cardinalityVariance / max(summary.expectedCardinality, 1) + ...
    max(0, 1 - summary.associationConfidence);
end

function summary = summarizePair( ...
    receiverObjects, sourceObjects, positionScale, existenceThreshold)
labels = collectLabels(receiverObjects, sourceObjects);
labelCount = size(labels, 2);
summary = struct( ...
    'positiveExistenceGain', 0, ...
    'negativeExistenceGap', 0, ...
    'positivePrecisionGain', 0, ...
    'negativePrecisionGap', 0, ...
    'normalizedStateDiscrepancy', 0, ...
    'activeLabelOverlap', 0);
if labelCount == 0
    return;
end
for labelIdx = 1:labelCount
    receiver = findObject(receiverObjects, labels(:, labelIdx));
    source = findObject(sourceObjects, labels(:, labelIdx));
    receiverExistence = objectExistence(receiver);
    sourceExistence = objectExistence(source);
    summary.positiveExistenceGain = ...
        summary.positiveExistenceGain + ...
        max(sourceExistence - receiverExistence, 0);
    summary.negativeExistenceGap = ...
        summary.negativeExistenceGap + ...
        max(receiverExistence - sourceExistence, 0);
    if receiverExistence < existenceThreshold || ...
            sourceExistence < existenceThreshold
        continue;
    end
    [receiverMean, receiverCovariance] = ...
        momentMatchObject(receiver);
    [sourceMean, sourceCovariance] = momentMatchObject(source);
    receiverVariance = ...
        trace(receiverCovariance(1:2, 1:2)) / positionScale^2;
    sourceVariance = ...
        trace(sourceCovariance(1:2, 1:2)) / positionScale^2;
    overlapWeight = min(receiverExistence, sourceExistence);
    summary.positivePrecisionGain = ...
        summary.positivePrecisionGain + overlapWeight * ...
        max(receiverVariance - sourceVariance, 0);
    summary.negativePrecisionGap = ...
        summary.negativePrecisionGap + overlapWeight * ...
        max(sourceVariance - receiverVariance, 0);
    summary.normalizedStateDiscrepancy = ...
        summary.normalizedStateDiscrepancy + overlapWeight * ...
        norm(receiverMean(1:2) - sourceMean(1:2)) / positionScale;
    summary.activeLabelOverlap = ...
        summary.activeLabelOverlap + overlapWeight;
end
fields = fieldnames(summary);
for fieldIdx = 1:numel(fields)
    summary.(fields{fieldIdx}) = ...
        summary.(fields{fieldIdx}) / labelCount;
end
end

function labels = collectLabels(leftObjects, rightObjects)
labels = zeros(2, 0);
objects = [reshape(leftObjects, 1, []), reshape(rightObjects, 1, [])];
for objectIdx = 1:numel(objects)
    if objects(objectIdx).numberOfGmComponents <= 0
        continue;
    end
    label = [ ...
        objects(objectIdx).birthTime; ...
        objects(objectIdx).birthLocation];
    if isempty(labels) || ~any(all(bsxfun(@eq, labels, label), 1))
        labels(:, end+1) = label; %#ok<AGROW>
    end
end
end

function object = findObject(objects, label)
object = [];
for objectIdx = 1:numel(objects)
    if objects(objectIdx).numberOfGmComponents > 0 && ...
            objects(objectIdx).birthTime == label(1) && ...
            objects(objectIdx).birthLocation == label(2)
        object = objects(objectIdx);
        return;
    end
end
end

function value = objectExistence(object)
if isempty(object)
    value = 0;
else
    value = min(max(object.r, 0), 1);
end
end

function [meanVector, covariance] = momentMatchObject(object)
componentCount = object.numberOfGmComponents;
weights = reshape(object.w, 1, []);
weights(~isfinite(weights)) = 0;
weights = max(weights, 0);
if numel(weights) ~= componentCount || sum(weights) <= 0
    weights = ones(1, componentCount);
end
weights = weights / sum(weights);
stateDimension = numel(object.mu{1});
meanVector = zeros(stateDimension, 1);
for componentIdx = 1:componentCount
    meanVector = meanVector + ...
        weights(componentIdx) * object.mu{componentIdx};
end
covariance = zeros(stateDimension);
for componentIdx = 1:componentCount
    delta = object.mu{componentIdx} - meanVector;
    covariance = covariance + weights(componentIdx) * ...
        (object.Sigma{componentIdx} + delta * delta');
end
covariance = (covariance + covariance') / 2;
end

function value = resolvePositionScale(model)
if isfield(model, 'ospaParameters') && ...
        isfield(model.ospaParameters, 'eC')
    value = model.ospaParameters.eC;
else
    value = 100;
end
end

function groupIds = resolveGroupIds(model, nodeCount)
groupIds = 1:nodeCount;
if isfield(model, 'dynamicTopologyScenario') && ...
        isfield(model.dynamicTopologyScenario, 'config') && ...
        isfield(model.dynamicTopologyScenario.config, 'sensorGroupIds')
    configured = reshape( ...
        model.dynamicTopologyScenario.config.sensorGroupIds, 1, []);
    if numel(configured) == nodeCount
        groupIds = configured;
    end
end
end

function probability = edgeDrop( ...
    config, senderIdx, receiverIdx, currentTime)
if isfield(config, 'pDropByEdge') && ~isempty(config.pDropByEdge)
    if ndims(config.pDropByEdge) >= 3
        timeIdx = min(currentTime, size(config.pDropByEdge, 3));
        probability = config.pDropByEdge( ...
            senderIdx, receiverIdx, timeIdx);
    else
        probability = config.pDropByEdge(senderIdx, receiverIdx);
    end
elseif isfield(config, 'pDropBySensor') && ...
        numel(config.pDropBySensor) >= senderIdx
    probability = config.pDropBySensor(senderIdx);
else
    probability = 0;
end
probability = min(max(probability, 0), 1);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end

function value = getScalarField(structure, fieldName, defaultValue)
value = getField(structure, fieldName, defaultValue);
if isempty(value) || ~isscalar(value) || ~isfinite(value)
    value = defaultValue;
end
end
