function protocol = getParetoSafeResidualAugmentationV246Protocol()
% GETPARETOSAFERESIDUALAUGMENTATIONV246PROTOCOL Exact one-step teacher.

source = getCausalMinimumFormationBackboneV242Protocol();
protocol = struct();
protocol.id = 'pareto-safe-residual-augmentation-v246-v1';
protocol.contractVersion = ...
    'pareto-safe-residual-augmentation-v246-protocol-v1';
protocol.sourceProtocolId = source.id;
protocol.armId = 'v246-pareto-safe-residual-augmentation';
protocol.policyName = 'pareto-safe-residual-augmentation-v246-policy';
protocol.allowedPresets = { ...
    'm24-formation-fov-coupled-formation-braid', ...
    'x36-formation-fov-coupled-formation-braid', ...
    'x48-formation-fov-coupled-formation-braid'};
protocol.allowedSeeds = 1301;
protocol.maximumResidualsPerFormation = 1;
protocol.networkResidualQuotaRule = 'ceil-formation-count-over-two';
protocol.byteGapSpendFraction = 0.25;
protocol.minimumRelativeTaskGain = 1e-4;
protocol.minimumRelativeDisagreementGain = 1e-4;
protocol.numericalTolerance = 1e-10;
protocol.protectedReferenceExistence = 0.60;
protocol.decisionExistenceThreshold = 0.50;
protocol.maximumExistenceRetentionRisk = 0.05;
protocol.receiverTailFraction = 0.34;
protocol.receiverTailWeight = 0.50;
protocol.disagreementTailFraction = 0.34;
protocol.disagreementTailWeight = 0.50;
protocol.maximumIncomingCount = 2;
protocol.developmentEvidenceOnly = true;
protocol.validationClaimAllowed = false;
protocol.evidenceBoundary = [ ...
    'V246 augments the causal V242 minimum formation backbone only with ', ...
    'currently physical local residual inputs omitted from the matched ', ...
    'V240 route. It uses current local posteriors and current link ', ...
    'reliabilities to enumerate the registered one-round mixture-aware ', ...
    'LMB-KLA delivery outcomes. The final route must not increase the ', ...
    'current-step task-risk, network-disagreement or per-formation ', ...
    'mean-tail risk proxies relative to V242, and it must satisfy robust ', ...
    'existence-retention, message and estimated-byte bounds. These are ', ...
    'current-step surrogate guarantees, not truth-level or recursive ', ...
    'tracking guarantees. Truth, future measurements, realized future ', ...
    'delivery outcomes and tracking scores are not read online.'];

if protocol.byteGapSpendFraction <= 0 || ...
        protocol.byteGapSpendFraction >= 1 || ...
        protocol.maximumResidualsPerFormation ~= 1 || ...
        protocol.protectedReferenceExistence <= ...
            protocol.decisionExistenceThreshold || ...
        protocol.maximumIncomingCount < 2
    error('ParetoSafeResidualV246:InvalidProtocol', ...
        'The V246 residual budgets or protection margins are invalid.');
end
end
