function [adjacency, weights, details] = ...
        rewireInfluenceConeSourceV118( ...
            baseAdjacency, baseWeights, baseDetails, ...
            oldSourceId, newSourceId, receiverId, ...
            repairSourceId, repairReceiverId)
% REWIREINFLUENCECONESOURCEV118 Migrate the cross-source role safely.

adjacency = logical(baseAdjacency);
weights = double(baseWeights);
nodeCount = size(adjacency, 1);
if ~isequal(size(adjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(weights), [nodeCount, nodeCount]) || ...
        ~isstruct(baseDetails) || ~isscalar(baseDetails) || ...
        ~isfield(baseDetails, 'residualAdjacency') || ...
        any([oldSourceId, newSourceId, receiverId, ...
             repairSourceId, repairReceiverId] < 1) || ...
        any([oldSourceId, newSourceId, receiverId, ...
             repairSourceId, repairReceiverId] > nodeCount) || ...
        numel(unique([oldSourceId, newSourceId, receiverId])) < 3
    error('AlternativeSourceV118:InvalidRewireInput', ...
        'The source rewire input is malformed.');
end
residual = logical(baseDetails.residualAdjacency);
crossWeight = weights(receiverId, oldSourceId);
repairWeight = weights(repairReceiverId, repairSourceId);
if ~adjacency(receiverId, oldSourceId) || ...
        ~residual(receiverId, oldSourceId) || ...
        adjacency(receiverId, newSourceId) || ...
        ~adjacency(repairReceiverId, repairSourceId) || ...
        adjacency(repairReceiverId, oldSourceId) || ...
        repairReceiverId == oldSourceId || ...
        ~isscalar(crossWeight) || ~isfinite(crossWeight) || ...
        crossWeight <= 0 || ~isscalar(repairWeight) || ...
        ~isfinite(repairWeight) || repairWeight <= 0
    error('AlternativeSourceV118:InvalidSourceSlot', ...
        'The registered source slot changed or the replacement is occupied.');
end
adjacency(receiverId, oldSourceId) = false;
weights(receiverId, oldSourceId) = 0;
residual(receiverId, oldSourceId) = false;
adjacency(receiverId, newSourceId) = true;
weights(receiverId, newSourceId) = crossWeight;
residual(receiverId, newSourceId) = true;

% Removing oldSourceId -> receiverId would strand oldSourceId.  Move its
% outward role to one fixed intra-formation slot while keeping that row's
% original weight.  The repair is identical for every candidate.
adjacency(repairReceiverId, repairSourceId) = false;
weights(repairReceiverId, repairSourceId) = 0;
residual(repairReceiverId, repairSourceId) = false;
adjacency(repairReceiverId, oldSourceId) = true;
weights(repairReceiverId, oldSourceId) = repairWeight;
if isfield(baseDetails, 'dominantAdjacency') && ...
        baseDetails.dominantAdjacency(repairReceiverId, repairSourceId)
    detailsDominant = logical(baseDetails.dominantAdjacency);
    detailsDominant(repairReceiverId, repairSourceId) = false;
    detailsDominant(repairReceiverId, oldSourceId) = true;
else
    detailsDominant = [];
    residual(repairReceiverId, oldSourceId) = true;
end

strong = isDirectedStronglyConnected(adjacency);
if max(abs(sum(weights, 2) - 1)) > 1e-12 || ...
        nnz(adjacency) ~= nnz(baseAdjacency) || ...
        max(abs(sort(weights(weights > 0)) - ...
            sort(baseWeights(baseWeights > 0)))) > 1e-12 || ...
        ~strong
    error('AlternativeSourceV118:RewireInvariantFailed', ...
        ['The source rewire changed row sums, messages, weights, ', ...
         'or static strong connectivity.']);
end
details = baseDetails;
details.fusionWeightMatrix = weights;
details.residualAdjacency = residual;
if ~isempty(detailsDominant)
    details.dominantAdjacency = detailsDominant;
end
details.messageCount = nnz(adjacency);
if isfield(details, 'selectedSourcesByReceiver') && ...
        iscell(details.selectedSourcesByReceiver)
    details.selectedSourcesByReceiver{receiverId} = ...
        find(adjacency(receiverId, :));
    details.selectedSourcesByReceiver{repairReceiverId} = ...
        find(adjacency(repairReceiverId, :));
end
details.v118SourceRewire = struct( ...
    'oldSourceId', oldSourceId, ...
    'newSourceId', newSourceId, ...
    'receiverId', receiverId, ...
    'crossWeight', crossWeight, ...
    'repairSourceId', repairSourceId, ...
    'repairReceiverId', repairReceiverId, ...
    'repairReplacementSourceId', oldSourceId, ...
    'repairWeight', repairWeight, ...
    'messageParityPassed', nnz(adjacency) == nnz(baseAdjacency), ...
    'rowSumPassed', max(abs(sum(weights, 2) - 1)) <= 1e-12, ...
    'weightMultisetPassed', true, ...
    'strongConnectivityPassed', strong);
end

function passed = isDirectedStronglyConnected(adjacency)
nodeCount = size(adjacency, 1);
reachability = logical(adjacency) | eye(nodeCount) > 0;
for intermediate = 1:nodeCount
    reachability = reachability | bsxfun(@and, ...
        reachability(:, intermediate), ...
        reachability(intermediate, :));
end
passed = all(reachability(:));
end
