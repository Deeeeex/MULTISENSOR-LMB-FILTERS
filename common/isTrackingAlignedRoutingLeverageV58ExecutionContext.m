function detected = ...
    isTrackingAlignedRoutingLeverageV58ExecutionContext(context)
% ISTRACKINGALIGNEDROUTINGLEVERAGEV58EXECUTIONCONTEXT Identify V58.

detected = isstruct(context) && isscalar(context) && ...
    isfield(context, 'contractVersion') && ...
    ischar(context.contractVersion) && ...
    strcmp(context.contractVersion, ...
        ['tracking-aligned-routing-leverage-v58-', ...
         'execution-context-v1']);
end
