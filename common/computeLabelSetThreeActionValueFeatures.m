function features = ...
    computeLabelSetThreeActionValueFeatures( ...
        context, model, actionAdjacency, ...
        actionDetails, actionNames, options)
% COMPUTELABELSETTHREEACTIONVALUEFEATURES Observable relative gate inputs.
%
% The returned state and action features contain no seed identifier,
% tracking truth, future measurement or future outcome. The third action
% is not assumed to be the reference; referenceActionIndex selects the
% deployable fallback used for relative features.

if nargin < 6 || isempty(options)
    options = struct();
end
protocol = getLabelSetSimulatorPolicyProtocol();
referenceActionIndex = getField( ...
    options, 'referenceActionIndex', 2);
actionCount = size(actionAdjacency, 3);
if actionCount ~= 3 || ...
        numel(actionDetails) ~= actionCount || ...
        numel(actionNames) ~= actionCount || ...
        ~isequal(reshape(actionNames, 1, []), ...
            reshape(protocol.returnValueGateActions, 1, [])) || ...
        referenceActionIndex < 1 || ...
        referenceActionIndex > actionCount || ...
        ~strcmp(actionNames{referenceActionIndex}, ...
            protocol.returnValueGateDefaultAction)
    error('Three-action value feature inputs are invalid.');
end
if ~isfield(context, 'localPosteriorBySensor') || ...
        ~isfield(context, 'physicalAdjacency') || ...
        ~isfield(context, 'previousAdjacencyHistory') || ...
        ~isfield(context, 'currentTime') || ...
        any(size(actionAdjacency, 1:2) ~= ...
            size(context.physicalAdjacency))
    error('Three-action value feature context is incomplete.');
end

block = computeLabelSetMessagePassingPolicyBlock( ...
    context, struct('protocol', protocol));
scoreOutput = scoreLabelSetMessagePassingPolicyModel( ...
    model, block);
weightIdx = find(abs(block.residualWeightGrid - ...
    protocol.localResidualWeight) <= 1e-12);
if numel(weightIdx) ~= 1
    error('Registered fixed residual weight is unavailable.');
end
candidateScore = scoreOutput.edgeTaskScore(:, weightIdx);
[~, compatibility] = computeLmbKlaCompatibilityMatrix( ...
    context, struct('sourceWeight', ...
        protocol.localResidualWeight));
linkSuccess = resolveLinkSuccess(context);

[posteriorValues, posteriorNames] = ...
    summarizePosteriorState( ...
        context.localPosteriorBySensor);
stateValues = [ ...
    summarizeVector(candidateScore), ...
    mean(candidateScore > 0), ...
    summarizePhysicalMatrix( ...
        compatibility.scoreMatrix, ...
        context.physicalAdjacency), ...
    summarizePhysicalMatrix( ...
        linkSuccess, context.physicalAdjacency), ...
    posteriorValues, ...
    summarizeUpdateHistory(context), ...
    size(context.previousAdjacencyHistory, 3), ...
    historyUnionEdgeFraction( ...
        context.previousAdjacencyHistory)];
stateNames = [ ...
    summaryNames('candidate_gnn_score'), ...
    {'candidate_gnn_positive_fraction'}, ...
    summaryNames('physical_compatibility_score'), ...
    summaryNames('physical_link_success'), ...
    posteriorNames, ...
    updateHistoryNames(), ...
    {'previous_history_count', ...
     'previous_history_union_edge_fraction'}];

rawNames = [ ...
    {'action_is_cw', 'action_is_ccw', ...
     'action_is_learned'}, ...
    summaryNames('selected_cross_gnn_score'), ...
    summaryNames('selected_cross_compatibility_score'), ...
    summaryNames('selected_cross_bernoulli'), ...
    summaryNames('selected_cross_spatial'), ...
    summaryNames('selected_cross_link_success'), ...
    {'change_fraction_vs_previous', ...
     'overlap_fraction_vs_previous', ...
     'selected_message_count', ...
     'selected_cross_message_count'}];
raw = zeros(actionCount, numel(rawNames));
for actionIdx = 1:actionCount
    adjacency = logical(actionAdjacency(:, :, actionIdx));
    if any(adjacency(:) & ...
            ~logical(context.physicalAdjacency(:)))
        error('Value action contains a physically invalid edge.');
    end
    edges = resolveCrossEdges( ...
        actionDetails{actionIdx}, adjacency, ...
        block.groupIds);
    candidateRows = findCandidateRows(block, edges);
    previous = latestHistoryPage( ...
        context.previousAdjacencyHistory, ...
        size(adjacency, 1));
    raw(actionIdx, :) = [ ...
        double(actionIdx == 1), ...
        double(actionIdx == 2), ...
        double(actionIdx == 3), ...
        summarizeVector(candidateScore(candidateRows)), ...
        summarizeSelectedMatrix( ...
            compatibility.scoreMatrix, edges), ...
        summarizeSelectedMatrix( ...
            compatibility.bernoulliCompatibilityMatrix, edges), ...
        summarizeSelectedMatrix( ...
            compatibility.spatialOverlapMatrix, edges), ...
        summarizeSelectedMatrix(linkSuccess, edges), ...
        mean(adjacency(:) ~= previous(:)), ...
        jaccardOverlap(adjacency, previous), ...
        nnz(adjacency), ...
        size(edges, 1)];
end
relativeColumns = 4:numel(rawNames);
relative = bsxfun(@minus, ...
    raw(:, relativeColumns), ...
    raw(referenceActionIndex, relativeColumns));
relativeNames = cellfun(@(name) ...
    ['delta_ccw_', name], ...
    rawNames(relativeColumns), ...
    'UniformOutput', false);

features = struct();
features.contractVersion = ...
    'label-set-three-action-relative-value-features-v1';
features.actionNames = reshape(actionNames, 1, []);
features.referenceActionIndex = referenceActionIndex;
features.stateFeatureNames = stateNames;
features.stateFeatures = stateValues;
features.actionFeatureNames = ...
    [rawNames, relativeNames];
features.actionFeatures = [raw, relative];
features.featureContractSha256 = computeTextSha256(strjoin( ...
    [features.stateFeatureNames, ...
     features.actionFeatureNames], char(31)));
features.actionOrderSha256 = computeTextSha256(strjoin( ...
    features.actionNames, char(31)));
features.featuresUseTruth = false;
features.featuresUseFutureMeasurements = false;
features.featuresUseFutureOutcome = false;
features.seedIdentifierUsedAsFeature = false;
features.absoluteTimeUsedAsFeature = false;
features.numericLabelIdentifiersUsedAsFeatures = false;
features.referenceRelativeFeatures = true;
end

function [values, names] = summarizePosteriorState(posteriors)
sensorCount = numel(posteriors);
labelCount = zeros(sensorCount, 1);
componentCount = zeros(sensorCount, 1);
existenceMean = zeros(sensorCount, 1);
entropyMean = zeros(sensorCount, 1);
for sensorIdx = 1:sensorCount
    objects = posteriors{sensorIdx};
    labelCount(sensorIdx) = numel(objects);
    if isempty(objects)
        continue;
    end
    componentCount(sensorIdx) = ...
        sum([objects.numberOfGmComponents]);
    existence = min(max([objects.r], eps), 1 - eps);
    existenceMean(sensorIdx) = mean(existence);
    entropyMean(sensorIdx) = mean( ...
        -existence .* log(existence) - ...
        (1 - existence) .* log(1 - existence));
end
values = [ ...
    summarizeVector(labelCount), ...
    summarizeVector(componentCount), ...
    summarizeVector(existenceMean), ...
    summarizeVector(entropyMean)];
names = [ ...
    summaryNames('sensor_label_count'), ...
    summaryNames('sensor_component_count'), ...
    summaryNames('sensor_existence_mean'), ...
    summaryNames('sensor_existence_entropy_mean')];
end

function values = summarizeUpdateHistory(context)
association = latestColumn( ...
    context.localAssociationConfidenceHistory);
innovation = latestColumn( ...
    context.localInnovationHistory);
nisDeviation = latestColumn( ...
    context.localNisDeviationHistory);
finiteNis = nisDeviation(isfinite(nisDeviation));
if isempty(finiteNis)
    nisMean = 0;
    nisStd = 0;
else
    nisMean = mean(finiteNis);
    nisStd = std(finiteNis, 1);
end
values = [ ...
    mean(association(isfinite(association))), ...
    std(association(isfinite(association)), 1), ...
    mean(innovation(isfinite(innovation))), ...
    std(innovation(isfinite(innovation)), 1), ...
    nisMean, nisStd, mean(~isfinite(nisDeviation))];
values(~isfinite(values)) = 0;
end

function names = updateHistoryNames()
names = { ...
    'current_association_mean', ...
    'current_association_std', ...
    'current_innovation_mean', ...
    'current_innovation_std', ...
    'current_nis_deviation_mean', ...
    'current_nis_deviation_std', ...
    'current_nis_missing_fraction'};
end

function values = summarizePhysicalMatrix(matrix, physical)
mask = logical(physical);
mask(1:size(mask, 1)+1:end) = false;
values = summarizeVector(matrix(mask));
end

function values = summarizeSelectedMatrix(matrix, edges)
indices = sub2ind(size(matrix), ...
    edges(:, 1), edges(:, 2));
values = summarizeVector(matrix(indices));
end

function values = summarizeVector(values)
values = reshape(double(values), [], 1);
values = values(isfinite(values));
if isempty(values)
    values = [0, 0, 0, 0];
else
    values = [ ...
        mean(values), min(values), max(values), ...
        std(values, 1)];
end
end

function names = summaryNames(prefix)
names = { ...
    [prefix, '_mean'], [prefix, '_min'], ...
    [prefix, '_max'], [prefix, '_std']};
end

function edges = resolveCrossEdges(details, adjacency, groupIds)
if isstruct(details) && ...
        isfield(details, 'spliceSelection') && ...
        isfield(details.spliceSelection, 'crossReceivers') && ...
        isfield(details.spliceSelection, 'crossSenders')
    edges = [ ...
        reshape(details.spliceSelection.crossReceivers, [], 1), ...
        reshape(details.spliceSelection.crossSenders, [], 1)];
else
    [receivers, senders] = find(adjacency);
    cross = groupIds(receivers) ~= groupIds(senders);
    edges = [receivers(cross), senders(cross)];
end
if isempty(edges)
    error('Three-action value feature graph has no cross edge.');
end
end

function rows = findCandidateRows(block, edges)
nodeCount = block.nodeCount;
candidateKeys = block.receiverIndices + ...
    nodeCount * (block.senderIndices - 1);
edgeKeys = edges(:, 1) + ...
    nodeCount * (edges(:, 2) - 1);
[present, rows] = ismember(edgeKeys, candidateKeys);
if any(~present) || numel(unique(rows)) ~= size(edges, 1)
    error('Selected cross edge is outside the candidate set.');
end
rows = reshape(rows, [], 1);
end

function linkSuccess = resolveLinkSuccess(context)
nodeCount = size(context.physicalAdjacency, 1);
if isfield(context.commConfig, 'pDropByEdge')
    pDrop = context.commConfig.pDropByEdge;
    if ndims(pDrop) >= 3
        timeIdx = min(context.currentTime, size(pDrop, 3));
        pDrop = pDrop(:, :, timeIdx);
    end
elseif isfield(context.commConfig, 'pDropBySensor')
    bySensor = reshape( ...
        context.commConfig.pDropBySensor, 1, []);
    pDrop = repmat(bySensor, nodeCount, 1);
else
    pDrop = zeros(nodeCount);
end
if ~isequal(size(pDrop), [nodeCount, nodeCount])
    error('Current link reliability matrix has the wrong shape.');
end
linkSuccess = 1 - min(max(double(pDrop), 0), 1);
linkSuccess(~logical(context.physicalAdjacency)) = 0;
linkSuccess(1:nodeCount+1:end) = 0;
end

function page = latestHistoryPage(history, nodeCount)
if isempty(history)
    page = false(nodeCount);
else
    page = logical(history(:, :, end));
end
end

function value = jaccardOverlap(left, right)
unionMask = left | right;
if ~any(unionMask(:))
    value = 1;
else
    value = nnz(left & right) / nnz(unionMask);
end
end

function value = historyUnionEdgeFraction(history)
if isempty(history)
    value = 0;
    return;
end
unionGraph = any(logical(history), 3);
nodeCount = size(unionGraph, 1);
value = nnz(unionGraph) / max(1, nodeCount * (nodeCount - 1));
end

function column = latestColumn(values)
if isempty(values)
    column = NaN;
else
    column = values(:, end);
end
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
