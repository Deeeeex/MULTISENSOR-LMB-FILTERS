function config = buildMinimalRiskCycleV264Config(scenario)
% BUILDMINIMALRISKCYCLEV264CONFIG One extra formation edge when active.

protocol = getMinimalRiskCycleV264Protocol();
if ~isstruct(scenario) || ~isscalar(scenario) || ...
        ~isfield(scenario, 'presetName') || ...
        ~ismember(scenario.presetName, protocol.allowedPresets) || ...
        ~isfield(scenario, 'numberOfSensors') || ...
        ~isfield(scenario, 'sensorGroupIds')
    error('MinimalRiskCycleV264:InvalidConfigInput', ...
        'V264 requires its registered M24 formation-braid scene.');
end
formationCount = numel(unique(scenario.sensorGroupIds));
minimumMessages = scenario.numberOfSensors + ...
    2 * (formationCount - 1);
config = buildRiskRootedMultiSourceTreeV263Config(scenario);
config.topologyPolicyName = protocol.policyName;
config.topologyPolicyFcn = @selectMinimalRiskCycleV264Policy;
config.topologyDirectedMessageBudget = minimumMessages + ...
    protocol.additionalDirectedMessages;
end
