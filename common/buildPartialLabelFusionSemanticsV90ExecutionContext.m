function context = buildPartialLabelFusionSemanticsV90ExecutionContext( ...
        presetName, seed, armId, receiverMode, measurementTimeCount)
% BUILDPARTIALLABELFUSIONSEMANTICSV90EXECUTIONCONTEXT Full-episode gate.

protocol = getPartialLabelFusionSemanticsV90Protocol();
if ~ischar(presetName) || ~isrow(presetName) || ...
        ~any(strcmp(presetName, protocol.presets)) || ...
        ~isscalar(seed) || ~isfinite(seed) || ...
        seed ~= protocol.allSeeds || ...
        ~ischar(armId) || ~isrow(armId) || ...
        ~any(strcmp(armId, {protocol.referenceArmId, ...
            protocol.candidateArmId})) || ...
        ~ischar(receiverMode) || ~isrow(receiverMode) || ...
        ~any(strcmp(receiverMode, protocol.receiverModes)) || ...
        ~isscalar(measurementTimeCount) || ...
        ~isfinite(measurementTimeCount) || ...
        measurementTimeCount ~= round(measurementTimeCount)
    error('PartialLabelFusionV90:InvalidExecutionContextInput', ...
        'V90 requires a registered scale, route, receiver and time axis.');
end
source = getRepeatedMultiGatewayHandoverV89Protocol();
if strcmp(armId, protocol.referenceArmId)
    policyName = source.referencePolicyName;
else
    policyName = source.candidatePolicyName;
end
context = struct();
context.contractVersion = ...
    'partial-label-fusion-semantics-v90-full-episode-context-v1';
context.capability = ...
    'partial-label-fusion-semantics-full-episode-development';
context.action = ...
    'filter-partial-label-fusion-semantics-full-episode-development';
context.protocolId = protocol.id;
context.presetName = presetName;
context.seed = seed;
context.armId = armId;
context.receiverMode = receiverMode;
context.measurementTimeCount = measurementTimeCount;
context.policyName = policyName;
context.developmentEvidenceOnly = true;
end
