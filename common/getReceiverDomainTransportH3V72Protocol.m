function protocol = getReceiverDomainTransportH3V72Protocol()
% GETRECEIVERDOMAINTRANSPORTH3V72PROTOCOL Frozen paired outcome gate.

v71 = getReceiverDomainTransportProjectionV71Protocol();
expectedNodeCounts = [24, 36];
expectedFormationCounts = [4, 6];
expectedSlotCounts = [2, 4];
cases = repmat(struct(), 1, numel(v71.presets));
for idx = 1:numel(v71.presets)
    cases(idx) = struct( ...
        'presetName', v71.presets{idx}, ...
        'seed', v71.allSeeds, ...
        'currentTime', v71.anchorTimes(idx), ...
        'expectedNodeCount', expectedNodeCounts(idx), ...
        'expectedFormationCount', expectedFormationCounts(idx), ...
        'expectedSelectedFormationIds', ...
            reshape(v71.anchorFormationIds{idx}, 1, []), ...
        'expectedSelectedSlotCount', expectedSlotCounts(idx));
end

protocol = struct();
protocol.id = 'receiver-domain-transport-h3-v72-v1';
protocol.contractVersion = ...
    'receiver-domain-transport-h3-v72-protocol-v1';
protocol.sourceProtocolId = v71.id;
protocol.sourceProjectionCommit = ...
    '71eebb23eabefb15f448dbb8662c9139bf10adaa';
protocol.cases = cases;
protocol.horizonSteps = 3;
protocol.interventionDurationSteps = 1;
protocol.filterSeedOffset = 100000;
protocol.cacheRoot = v71.cacheRoot;
protocol.outputRoot = fullfile( ...
    'RUN', 'GA', 'dynamic_topology', 'evidence', ...
    'tracking_aligned_v72', 'receiver_domain_transport_h3');
protocol.outcomePolicyName = ...
    'receiver-domain-transport-h3-v72-v1';
protocol.minimumMeanTrackingGainPercent = 2.0;
protocol.minimumWorstSensorGainPercent = 0.0;
protocol.minimumFormationGainPercent = 0.0;
protocol.minimumWindowConsensusGainPercent = 0.0;
protocol.minimumTerminalConsensusGainPercent = 0.0;
protocol.minimumAttemptedByteSavingPercent = -1.0;
protocol.exactMessageCountParityRequired = true;
protocol.selectedRollingB3Required = true;
protocol.trackingOutcomeScoringAuthorized = true;
protocol.modelTrainingAuthorized = false;
protocol.validationClaimAllowed = false;
protocol.openedDevelopmentEvidenceOnly = true;
protocol.evidenceBoundary = [ ...
    'V72 opens exactly two already-frozen V71 source states: M24 t=80 ', ...
    'and X36 t=52, seed 1401. Reference and candidate share the same ', ...
    'predecision posterior, measurements, delivery draws, filter RNG, ', ...
    'and current-physical-tree reference. The candidate executes one ', ...
    'V71 fixed-message transport route at the anchor; both arms ', ...
    'recompute the reference for the following two steps. Truth and ', ...
    'future measurements score the paired H=3 outcome only after route ', ...
    'construction. This is opened development evidence, not validation.'];
end
