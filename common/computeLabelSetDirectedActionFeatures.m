function [features, mask, featureNames, metadata] = ...
    computeLabelSetDirectedActionFeatures( ...
        context, receiverIndices, senderIndices, options)
% COMPUTELABELSETDIRECTEDACTIONFEATURES Per-label observable edge state.
%
% Each edge is represented by the union of labels in its receiver and
% sender LMB posteriors. Rows within an edge are label elements; no numeric
% label identifier is included in the feature vector. A downstream shared
% label encoder followed by symmetric pooling is therefore permutation
% invariant. The function reads neither target truth nor future outcomes.

if nargin < 4 || isempty(options)
    options = struct();
end
if ~isstruct(context) || ...
        ~isfield(context, 'localPosteriorBySensor')
    error('Label-set features require local LMB posteriors.');
end
posteriors = reshape(context.localPosteriorBySensor, 1, []);
nodeCount = numel(posteriors);
receiverIndices = reshape(receiverIndices, [], 1);
senderIndices = reshape(senderIndices, [], 1);
edgeCount = numel(receiverIndices);
if numel(senderIndices) ~= edgeCount || edgeCount == 0 || ...
        any(~isfinite(receiverIndices)) || ...
        any(~isfinite(senderIndices)) || ...
        any(receiverIndices ~= round(receiverIndices)) || ...
        any(senderIndices ~= round(senderIndices)) || ...
        any(receiverIndices < 1 | receiverIndices > nodeCount) || ...
        any(senderIndices < 1 | senderIndices > nodeCount) || ...
        any(receiverIndices == senderIndices)
    error('Directed label-set candidate indices are invalid.');
end

maxLabelCount = getField(options, 'maxLabelCount', 32);
positionScale = getField(options, 'positionScale', ...
    resolvePositionScale(context));
velocityScale = getField(options, 'velocityScale', 1);
highExistenceThreshold = getField( ...
    options, 'highExistenceThreshold', 0.50);
if ~isscalar(maxLabelCount) || ~isfinite(maxLabelCount) || ...
        maxLabelCount < 1 || maxLabelCount ~= round(maxLabelCount) || ...
        ~isscalar(positionScale) || ~isfinite(positionScale) || ...
        positionScale <= 0 || ...
        ~isscalar(velocityScale) || ~isfinite(velocityScale) || ...
        velocityScale <= 0 || ...
        ~isscalar(highExistenceThreshold) || ...
        ~isfinite(highExistenceThreshold) || ...
        highExistenceThreshold < 0 || highExistenceThreshold > 1
    error('Label-set feature options are invalid.');
end

featureNames = { ...
    'receiver_present', ...
    'sender_present', ...
    'shared_label', ...
    'receiver_existence', ...
    'sender_existence', ...
    'sender_minus_receiver_existence', ...
    'positive_existence_gain', ...
    'negative_existence_gap', ...
    'receiver_bernoulli_entropy', ...
    'sender_bernoulli_entropy', ...
    'receiver_normalized_position_variance', ...
    'sender_normalized_position_variance', ...
    'receiver_normalized_velocity_variance', ...
    'sender_normalized_velocity_variance', ...
    'positive_precision_gain', ...
    'negative_precision_gap', ...
    'normalized_position_disagreement', ...
    'normalized_velocity_disagreement', ...
    'log_combined_mahalanobis_disagreement', ...
    'gaussian_compatibility', ...
    'receiver_association_confidence', ...
    'sender_association_confidence', ...
    'receiver_detection_association_mass', ...
    'sender_detection_association_mass', ...
    'receiver_association_ambiguity', ...
    'sender_association_ambiguity', ...
    'receiver_normalized_mixture_entropy', ...
    'sender_normalized_mixture_entropy', ...
    'receiver_log_component_count', ...
    'sender_log_component_count', ...
    'receiver_position_between_component_ratio', ...
    'sender_position_between_component_ratio', ...
    'existence_overlap', ...
    'both_high_existence'};
featureCount = numel(featureNames);
features = zeros(edgeCount, maxLabelCount, featureCount);
mask = false(edgeCount, maxLabelCount);
edgeLabelKeys = cell(edgeCount, 1);
labelCounts = zeros(edgeCount, 1);

for edgeIdx = 1:edgeCount
    receiverObjects = posteriors{receiverIndices(edgeIdx)};
    senderObjects = posteriors{senderIndices(edgeIdx)};
    labels = collectLabels(receiverObjects, senderObjects);
    labelCount = size(labels, 2);
    if labelCount > maxLabelCount
        error(['Label-set edge %d contains %d labels, exceeding the ', ...
            'frozen lossless capacity %d.'], ...
            edgeIdx, labelCount, maxLabelCount);
    end
    labelCounts(edgeIdx) = labelCount;
    edgeLabelKeys{edgeIdx} = labels;
    mask(edgeIdx, 1:labelCount) = true;
    for labelIdx = 1:labelCount
        receiverObject = findObject( ...
            receiverObjects, labels(:, labelIdx));
        senderObject = findObject( ...
            senderObjects, labels(:, labelIdx));
        receiver = summarizeObject(receiverObject);
        sender = summarizeObject(senderObject);
        shared = receiver.present && sender.present;
        existenceDelta = sender.existence - receiver.existence;

        receiverPositionVariance = ...
            receiver.positionVariance / positionScale^2;
        senderPositionVariance = ...
            sender.positionVariance / positionScale^2;
        receiverVelocityVariance = ...
            receiver.velocityVariance / velocityScale^2;
        senderVelocityVariance = ...
            sender.velocityVariance / velocityScale^2;
        positionDisagreement = 0;
        velocityDisagreement = 0;
        mahalanobis = 0;
        compatibility = 0;
        if shared
            commonDimension = min( ...
                numel(receiver.mean), numel(sender.mean));
            delta = receiver.mean(1:commonDimension) - ...
                sender.mean(1:commonDimension);
            positionDimension = min(2, commonDimension);
            positionDisagreement = norm( ...
                delta(1:positionDimension)) / positionScale;
            if commonDimension >= 4
                velocityDisagreement = ...
                    norm(delta(3:4)) / velocityScale;
            end
            combinedCovariance = ...
                receiver.covariance(1:commonDimension, ...
                    1:commonDimension) + ...
                sender.covariance(1:commonDimension, ...
                    1:commonDimension);
            combinedCovariance = ...
                regularizeCovariance(combinedCovariance);
            mahalanobis = max( ...
                delta' * (combinedCovariance \ delta), 0);
            if ~isfinite(mahalanobis)
                mahalanobis = 1e6;
            end
            compatibility = exp(-0.5 * min(mahalanobis, 100));
        end
        overlap = min(receiver.existence, sender.existence);
        features(edgeIdx, labelIdx, :) = [ ...
            receiver.present, ...
            sender.present, ...
            shared, ...
            receiver.existence, ...
            sender.existence, ...
            existenceDelta, ...
            max(existenceDelta, 0), ...
            max(-existenceDelta, 0), ...
            bernoulliEntropy(receiver.existence), ...
            bernoulliEntropy(sender.existence), ...
            receiverPositionVariance, ...
            senderPositionVariance, ...
            receiverVelocityVariance, ...
            senderVelocityVariance, ...
            overlap * max(receiverPositionVariance - ...
                senderPositionVariance, 0), ...
            overlap * max(senderPositionVariance - ...
                receiverPositionVariance, 0), ...
            positionDisagreement, ...
            velocityDisagreement, ...
            log1p(mahalanobis), ...
            compatibility, ...
            receiver.associationConfidence, ...
            sender.associationConfidence, ...
            receiver.detectionAssociationMass, ...
            sender.detectionAssociationMass, ...
            receiver.associationAmbiguity, ...
            sender.associationAmbiguity, ...
            receiver.normalizedMixtureEntropy, ...
            sender.normalizedMixtureEntropy, ...
            log1p(receiver.componentCount), ...
            log1p(sender.componentCount), ...
            receiver.positionBetweenRatio, ...
            sender.positionBetweenRatio, ...
            overlap, ...
            double(receiver.existence >= highExistenceThreshold && ...
                sender.existence >= highExistenceThreshold)];
    end
end
if any(~isfinite(features(:))) || ...
        any(sum(mask, 2) ~= labelCounts)
    error('Label-set feature construction produced an invalid tensor.');
end

metadata = struct();
metadata.contractVersion = ...
    'directed-lmb-label-set-observable-features-v1';
metadata.featureContractSha256 = computeTextSha256(sprintf( ...
    '%s|%s|%d|%.17g|%.17g|%.17g', ...
    metadata.contractVersion, ...
    strjoin(featureNames, char(31)), ...
    maxLabelCount, positionScale, velocityScale, ...
    highExistenceThreshold));
metadata.receiverIndices = receiverIndices;
metadata.senderIndices = senderIndices;
metadata.labelCounts = labelCounts;
metadata.edgeLabelKeys = edgeLabelKeys;
metadata.maxLabelCount = maxLabelCount;
metadata.featureCount = featureCount;
metadata.maxObservedLabelCount = max(labelCounts);
metadata.truthUsed = false;
metadata.groundTruthUsed = false;
metadata.futureOutcomeUsed = false;
metadata.posteriorUsed = true;
metadata.numericLabelIdentifiersUsedAsFeatures = false;
metadata.labelKeysStoredForAuditOnly = true;
metadata.losslessWithinCapacity = true;
metadata.permutationInvariantEncoderRequired = true;
end

function labels = collectLabels(leftObjects, rightObjects)
labels = zeros(2, 0);
objects = [reshape(leftObjects, 1, []), ...
    reshape(rightObjects, 1, [])];
for objectIdx = 1:numel(objects)
    if objects(objectIdx).numberOfGmComponents <= 0
        continue;
    end
    label = [objects(objectIdx).birthTime; ...
        objects(objectIdx).birthLocation];
    if isempty(labels) || ...
            ~any(all(bsxfun(@eq, labels, label), 1))
        labels(:, end+1) = label; %#ok<AGROW>
    end
end
if ~isempty(labels)
    labels = sortrows(labels')';
end
end

function object = findObject(objects, label)
object = [];
for objectIdx = 1:numel(objects)
    if objects(objectIdx).numberOfGmComponents > 0 && ...
            objects(objectIdx).birthTime == label(1) && ...
            objects(objectIdx).birthLocation == label(2)
        object = objects(objectIdx);
        return;
    end
end
end

function summary = summarizeObject(object)
summary = struct( ...
    'present', false, ...
    'existence', 0, ...
    'mean', zeros(0, 1), ...
    'covariance', zeros(0), ...
    'positionVariance', 0, ...
    'velocityVariance', 0, ...
    'associationConfidence', 0, ...
    'detectionAssociationMass', 0, ...
    'associationAmbiguity', 0, ...
    'normalizedMixtureEntropy', 0, ...
    'componentCount', 0, ...
    'positionBetweenRatio', 0);
if isempty(object) || object.numberOfGmComponents <= 0
    return;
end
componentCount = object.numberOfGmComponents;
if numel(object.mu) ~= componentCount || ...
        numel(object.Sigma) ~= componentCount
    error('LMB object mixture fields are inconsistent.');
end
weights = reshape(object.w, 1, []);
weights(~isfinite(weights)) = 0;
weights = max(weights, 0);
if numel(weights) ~= componentCount || sum(weights) <= 0
    weights = ones(1, componentCount);
end
weights = weights / sum(weights);
stateDimension = numel(object.mu{1});
meanVector = zeros(stateDimension, 1);
for componentIdx = 1:componentCount
    meanVector = meanVector + ...
        weights(componentIdx) * object.mu{componentIdx};
end
covariance = zeros(stateDimension);
between = zeros(stateDimension);
for componentIdx = 1:componentCount
    if numel(object.mu{componentIdx}) ~= stateDimension || ...
            ~isequal(size(object.Sigma{componentIdx}), ...
                [stateDimension, stateDimension])
        error('LMB object mixture component dimensions differ.');
    end
    delta = object.mu{componentIdx} - meanVector;
    between = between + ...
        weights(componentIdx) * (delta * delta');
    covariance = covariance + weights(componentIdx) * ...
        (object.Sigma{componentIdx} + delta * delta');
end
covariance = regularizeCovariance(covariance);
positionDimension = min(2, stateDimension);
positionVariance = trace(covariance( ...
    1:positionDimension, 1:positionDimension));
positionBetween = trace(between( ...
    1:positionDimension, 1:positionDimension));
velocityVariance = 0;
if stateDimension >= 4
    velocityVariance = trace(covariance(3:4, 3:4));
end
positiveWeights = weights(weights > 0);
mixtureEntropy = -sum(positiveWeights .* log(positiveWeights));
if componentCount > 1
    normalizedMixtureEntropy = ...
        mixtureEntropy / log(componentCount);
else
    normalizedMixtureEntropy = 0;
end

summary.present = true;
summary.existence = clamp01(object.r);
summary.mean = meanVector;
summary.covariance = covariance;
summary.positionVariance = max(positionVariance, 0);
summary.velocityVariance = max(velocityVariance, 0);
summary.associationConfidence = clamp01(getScalarField( ...
    object, 'associationConfidence', 0));
summary.detectionAssociationMass = clamp01(getScalarField( ...
    object, 'detectionAssociationMass', 0));
summary.associationAmbiguity = clamp01(getScalarField( ...
    object, 'associationAmbiguity', 0));
summary.normalizedMixtureEntropy = ...
    clamp01(normalizedMixtureEntropy);
summary.componentCount = componentCount;
summary.positionBetweenRatio = clamp01( ...
    positionBetween / max(positionVariance, eps));
end

function covariance = regularizeCovariance(covariance)
covariance(~isfinite(covariance)) = 0;
covariance = (covariance + covariance') / 2;
scale = max(trace(abs(covariance)) / ...
    max(size(covariance, 1), 1), 1);
covariance = covariance + 1e-9 * scale * eye(size(covariance));
end

function value = bernoulliEntropy(probability)
probability = clamp01(probability);
if probability <= 0 || probability >= 1
    value = 0;
else
    value = -probability * log(probability) - ...
        (1 - probability) * log(1 - probability);
end
end

function value = resolvePositionScale(context)
value = 100;
if isfield(context, 'model') && ...
        isfield(context.model, 'ospaParameters') && ...
        isfield(context.model.ospaParameters, 'eC')
    value = context.model.ospaParameters.eC;
end
end

function value = getScalarField(structure, fieldName, defaultValue)
value = defaultValue;
if isstruct(structure) && isfield(structure, fieldName)
    candidate = structure.(fieldName);
    if isscalar(candidate) && isfinite(candidate)
        value = candidate;
    end
end
end

function value = clamp01(value)
if ~isscalar(value) || ~isfinite(value)
    value = 0;
end
value = min(max(value, 0), 1);
end

function value = getField(structure, fieldName, defaultValue)
if isstruct(structure) && isfield(structure, fieldName)
    value = structure.(fieldName);
else
    value = defaultValue;
end
end
