function [adjacency, details] = ...
    buildFormationB4V47FixedRuntimeArm(context, armId)
% BUILDFORMATIONB4V47FIXEDRUNTIMEARM Repair then dispatch gateway debt.

timerId = tic;
protocol = getFormationGatewayDebtV47Protocol();
candidateArm = protocol.primaryArms{2};
if nargin ~= 2 || ~ischar(armId) || ~isrow(armId) || ...
        ~strcmp(armId, candidateArm)
    error('FormationB4V47:InvalidArm', ...
        'Only the frozen V47 gateway-debt candidate is allowed.');
end
validateContext(context, protocol);

groupIds = context.model.dynamicTopologyScenario.config.sensorGroupIds;
registeredBaseAdjacency = logical(context.baseAdjacency);
staticAdjacencyPresent = isfield(context.model.dynamicTopologyScenario, ...
    'staticAdjacency');
if staticAdjacencyPresent && ...
        ~isequal(logical(context.model.dynamicTopologyScenario. ...
            staticAdjacency), registeredBaseAdjacency)
    error('FormationB4V47:StaticBaseMismatch', ...
        'The registered static graph and runtime base graph disagree.');
end
[projectedBaseAdjacency, certificate] = ...
    projectCausalMinimalEditFormationBackbone( ...
        groupIds, context.sensorPhysicalUids, ...
        context.formationPhysicalUidsBySensor, context.positions, ...
        registeredBaseAdjacency, context.physicalAdjacency, ...
        context.commConfig.pDropByEdge);
validateCausalMinimalEditFormationProjectionCertificate( ...
    certificate, context.sensorPhysicalUids, projectedBaseAdjacency);

runtimeContext = context;
runtimeContext.baseAdjacency = logical(projectedBaseAdjacency);
if staticAdjacencyPresent
    runtimeContext.model.dynamicTopologyScenario.staticAdjacency = ...
        logical(projectedBaseAdjacency);
end
[referenceAdjacency, referencePolicy] = ...
    selectIndexEquivariantFormationBackbonePolicy( ...
        runtimeContext, struct( ...
            'dominantWeight', protocol.dominantWeight, ...
            'residualWeight', protocol.referenceResidualWeight));
reference = struct( ...
    'dominantAdjacency', logical(referencePolicy.dominantAdjacency), ...
    'residualAdjacency', logical(referencePolicy.residualAdjacency), ...
    'referenceAdjacency', logical(referenceAdjacency), ...
    'referenceFusionWeights', referencePolicy.fusionWeightMatrix);
[adjacency, fusionWeights, schedule] = ...
    buildFormationB4V47GatewayDebtSchedule(runtimeContext, reference);

nodeCount = numel(context.localPosteriorBySensor);
positive = fusionWeights > 1e-12;
positive(1:nodeCount+1:end) = false;
if ~isequal(positive, logical(adjacency)) || ...
        any(adjacency(:) & ~logical(context.physicalAdjacency(:))) || ...
        nnz(adjacency) > 2 * nodeCount || ...
        any(abs(sum(fusionWeights, 2) - 1) > 1e-12)
    error('FormationB4V47:RuntimeActionDrift', ...
        'The V47 runtime action violates support, budget or weights.');
end

scheduleCanonicalSha256 = schedule.canonicalSha256;
details = rmfield(schedule, 'canonicalSha256');
details.baseContractVersion = schedule.contractVersion;
details.contractVersion = ...
    'formation-b4-v47-fixed-runtime-policy-v1';
details.mode = 'formation-b4-v47-repaired-gateway-debt-runtime';
details.armId = candidateArm;
details.armOrdinal = 2;
details.actionName = candidateArm;
selected = [schedule.selectedCrossReceivers, ...
    schedule.selectedLocalReceivers];
if isempty(selected)
    details.objective = 0;
else
    details.objective = mean( ...
        schedule.informationDebtScoreByReceiver(selected));
end
details.objectiveDefinition = ...
    'mean-selected-causal-information-debt-score';
details.objectiveSource = ...
    'past-ack-current-posterior-current-reliability';
details.candidateIndex = NaN;
details.fusionWeightMatrix = fusionWeights;
details.referenceFusionWeights = ...
    reference.referenceFusionWeights;
details.scheduleCanonicalSha256 = scheduleCanonicalSha256;
details.protocolId = protocol.id;
details.protocolCanonicalSha256 = protocol.canonicalSha256;
details.observableInputContractVersion = ...
    protocol.observableContractVersion;
details.repairTriggered = ...
    certificate.registeredRemovalCount > 0 || ...
    certificate.nonregisteredAdditionCount > 0;
details.projectionCertificate = certificate;
details.projectionCertificateCanonicalSha256 = ...
    certificate.canonicalSha256;
details.projectionArrayOrderExecutionCanonicalSha256 = ...
    certificate.arrayOrderExecutionCanonicalSha256;
details.projectionCertificateCrossBackboneOnly = true;
details.fullV43RouteCompositionPassed = true;
details.projectedBaseAdjacency = logical(projectedBaseAdjacency);
registeredBasePayload = struct( ...
    'contractVersion', 'formation-b4-v46-base-execution-view-v1', ...
    'sensorPhysicalUidsByArray', ...
        reshape(context.sensorPhysicalUids, 1, []), ...
    'baseAdjacency', registeredBaseAdjacency);
projectedBasePayload = struct( ...
    'contractVersion', 'formation-b4-v46-base-execution-view-v1', ...
    'sensorPhysicalUidsByArray', ...
        reshape(context.sensorPhysicalUids, 1, []), ...
    'baseAdjacency', logical(projectedBaseAdjacency));
identityContract = 'formation-b4-v46-formation-pair-identity-v1';
registeredIdentityPayload = struct( ...
    'contractVersion', identityContract, ...
    'pairPhysicalUids', certificate.registeredPairPhysicalUids);
projectedIdentityPayload = struct( ...
    'contractVersion', identityContract, ...
    'pairPhysicalUids', certificate.projectedPairPhysicalUids);
details.registeredBaseAdjacencyExecutionViewSha256 = ...
    computeCanonicalValueSha256(registeredBasePayload);
details.projectedBaseAdjacencyExecutionViewSha256 = ...
    computeCanonicalValueSha256(projectedBasePayload);
details.registeredBaseGraphPhysicalUidCanonicalSha256 = ...
    computeCanonicalValueSha256(registeredIdentityPayload);
details.projectedBaseGraphPhysicalUidCanonicalSha256 = ...
    computeCanonicalValueSha256(projectedIdentityPayload);
details.routeAndWeightCanonicalSha256 = ...
    computeCanonicalValueSha256(struct( ...
        'adjacency', logical(adjacency), ...
        'fusionWeightMatrix', fusionWeights));
details.referenceRouteAndWeightCanonicalSha256 = ...
    computeCanonicalValueSha256(struct( ...
        'adjacency', logical(referenceAdjacency), ...
        'fusionWeightMatrix', reference.referenceFusionWeights));
details.parentRouteAndWeightCanonicalSha256 = ...
    details.referenceRouteAndWeightCanonicalSha256;
details.routeReceivesCurrentPageOnly = true;
details.projectionReceivesCurrentPageOnly = true;
details.observableContextOnly = true;
details.policyOptionsAccepted = false;
details.posteriorUsed = true;
details.currentPosteriorUsed = true;
details.posteriorPayloadMetadataUsed = false;
details.posteriorUsedByProjection = false;
details.truthUsedByProjection = false;
details.measurementUsedByProjection = false;
details.futurePageUsedByProjection = false;
details.realizedDeliveryUniformsUsedByProjection = false;
details.pastSuccessfulDeliveryUsed = true;
details.currentLinkReliabilityUsed = true;
details.truthUsed = false;
details.groundTruthUsed = false;
details.measurementUsed = false;
details.futurePageUsed = false;
details.futureOutcomeUsed = false;
details.realizedDeliveryUniformsUsed = false;
details.trackingOutcomeScored = false;
details.validationClaimAllowed = false;
details.developmentEvidenceOnly = true;
details.selectionSeconds = toc(timerId);
end

function validateContext(context, protocol)
required = { ...
    'localPosteriorBySensor', 'model', 'baseAdjacency', ...
    'physicalAdjacency', 'positions', 'sensorPhysicalUids', ...
    'formationPhysicalUidsBySensor', 'commConfig', ...
    'triggerConfig', 'observableInputContract', ...
    'previousAdjacencyHistory', 'previousAdjacencyHistoryTimes', ...
    'previousDeliveryHistory', 'previousDeliveryHistoryTimes'};
if ~isstruct(context) || ~isscalar(context) || ...
        ~all(isfield(context, required)) || ...
        ~isfield(context.model, 'dynamicTopologyScenario') || ...
        ~isfield(context.model.dynamicTopologyScenario, 'config') || ...
        ~isfield(context.model.dynamicTopologyScenario.config, ...
            'sensorGroupIds') || ...
        ~isfield(context.commConfig, 'pDropByEdge') || ...
        ~isfield(context.triggerConfig, ...
            'topologyDirectedMessageBudget') || ...
        ~isstruct(context.observableInputContract) || ...
        ~context.observableInputContract.passed || ...
        ~strcmp(context.observableInputContract.contractVersion, ...
            protocol.observableContractVersion)
    error('FormationB4V47:InvalidContext', ...
        'The V47 runtime context is incomplete or crosses its boundary.');
end
nodeCount = numel(context.localPosteriorBySensor);
if ~isequal(size(context.baseAdjacency), [nodeCount, nodeCount]) || ...
        ~isequal(size(context.physicalAdjacency), ...
            [nodeCount, nodeCount]) || ...
        ~isequal(size(context.positions), [2, nodeCount]) || ...
        context.triggerConfig.topologyDirectedMessageBudget ~= ...
            2 * nodeCount
    error('FormationB4V47:InvalidContext', ...
        'The V47 route shape or directed-message ceiling drifted.');
end
end
