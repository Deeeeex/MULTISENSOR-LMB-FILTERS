function authorization = ...
    validatePartialLabelFusionSemanticsV90Execution( ...
        model, context, request)
% VALIDATEPARTIALLABELFUSIONSEMANTICSV90EXECUTION Receiver-semantics gate.

protocol = getPartialLabelFusionSemanticsV90Protocol();
expectedFields = { ...
    'contractVersion', 'capability', 'action', 'protocolId', ...
    'presetName', 'seed', 'armId', 'receiverMode', ...
    'measurementTimeCount', 'policyName', 'developmentEvidenceOnly'};
validContext = isequal(sort(fieldnames(context)), ...
        sort(expectedFields(:))) && ...
    strcmp(context.capability, ...
        'partial-label-fusion-semantics-full-episode-development') && ...
    strcmp(context.action, ...
        ['filter-partial-label-fusion-semantics-', ...
         'full-episode-development']) && ...
    strcmp(context.protocolId, protocol.id) && ...
    any(strcmp(context.presetName, protocol.presets)) && ...
    context.seed == protocol.allSeeds && ...
    any(strcmp(context.armId, {protocol.referenceArmId, ...
        protocol.candidateArmId})) && ...
    any(strcmp(context.receiverMode, protocol.receiverModes)) && ...
    isequal(context.developmentEvidenceOnly, true) && ...
    isstruct(request) && isscalar(request) && ...
    isfield(request, 'triggerConfig') && ...
    isfield(request.triggerConfig, 'missingLabelFusionMode') && ...
    strcmp(request.triggerConfig.missingLabelFusionMode, ...
        context.receiverMode);
if ~validContext
    error('PartialLabelFusionV90:InvalidExecutionContext', ...
        'The V90 full-episode execution context is malformed.');
end

sourceContext = buildRepeatedMultiGatewayHandoverV89ExecutionContext( ...
    context.presetName, context.seed, context.armId, ...
    context.measurementTimeCount);
authorization = validateRepeatedMultiGatewayHandoverV89Execution( ...
    model, sourceContext, request);
authorization.mode = ...
    'partial-label-fusion-semantics-full-episode-development';
authorization.capability = context.capability;
authorization.action = context.action;
authorization.protocolId = protocol.id;
authorization.armId = [context.armId, '__', context.receiverMode];
authorization.receiverMode = context.receiverMode;
authorization.validationClaimAllowed = false;
authorization.developmentEvidenceOnly = true;
end
