function [role, details] = selectCounterfactualEdgeRoleV146( ...
        config, sensorGroupIds, senderIdx, receiverIdx, ...
        currentTime, receiverProtected)
% SELECTCOUNTERFACTUALEDGEROLEV146 Apply one frozen edge-role vector.

required = { ...
    'lineageRelayRoleMultiplexedSinglePayloadEnabled', ...
    'lineageRelayRoleMultiplexedCounterfactualBankEnabled', ...
    'lineageRelayRoleMultiplexedAnchorTime', ...
    'lineageRelayRoleMultiplexedFormationOrder', ...
    'lineageRelayRoleMultiplexedSelectedFormationRanks', ...
    'lineageRelayRoleMultiplexedWorkingPageOffsets'};
if ~isstruct(config) || ~isscalar(config) || ...
        ~all(isfield(config, required)) || ...
        ~logical(config.lineageRelayRoleMultiplexedSinglePayloadEnabled) || ...
        ~logical(config. ...
            lineageRelayRoleMultiplexedCounterfactualBankEnabled)
    error('CounterfactualEdgeRoleV146:InvalidRoleRequest', ...
        'The role selector requires the registered V146 runtime.');
end
groups = reshape(sensorGroupIds, 1, []);
formationOrder = reshape( ...
    config.lineageRelayRoleMultiplexedFormationOrder, 1, []);
selectedRanks = reshape( ...
    config.lineageRelayRoleMultiplexedSelectedFormationRanks, 1, []);
workingOffsets = reshape( ...
    config.lineageRelayRoleMultiplexedWorkingPageOffsets, 1, []);
sensorCount = numel(groups);
anchorTime = config.lineageRelayRoleMultiplexedAnchorTime;
if sensorCount < 1 || any(~isfinite(groups)) || ...
        numel(unique(formationOrder)) ~= numel(formationOrder) || ...
        ~isequal(sort(unique(groups)), sort(formationOrder)) || ...
        isempty(selectedRanks) || ...
        any(selectedRanks < 1) || ...
        any(selectedRanks > numel(formationOrder)) || ...
        numel(unique(selectedRanks)) ~= numel(selectedRanks) || ...
        isempty(workingOffsets) || any(workingOffsets < 1) || ...
        any(workingOffsets ~= round(workingOffsets)) || ...
        ~isscalar(senderIdx) || ~isscalar(receiverIdx) || ...
        senderIdx < 1 || senderIdx > sensorCount || ...
        receiverIdx < 1 || receiverIdx > sensorCount || ...
        senderIdx == receiverIdx || ...
        ~isscalar(currentTime) || ~isfinite(currentTime) || ...
        currentTime ~= round(currentTime) || currentTime < anchorTime || ...
        ~isscalar(receiverProtected) || ...
        ~any(double(receiverProtected) == [0, 1])
    error('CounterfactualEdgeRoleV146:InvalidRoleRequest', ...
        'The V146 role-selector input violates the frozen action.');
end

receiverFormation = groups(receiverIdx);
receiverFormationRank = find( ...
    formationOrder == receiverFormation, 1);
pageOffset = currentTime - anchorTime;
workingPage = any(workingOffsets == pageOffset);
rankSelected = any(selectedRanks == receiverFormationRank);
intraFormation = groups(senderIdx) == groups(receiverIdx);
workingRole = workingPage && logical(receiverProtected) && ...
    rankSelected && intraFormation;
if workingRole
    role = 'working';
else
    role = 'reference';
end
details = struct( ...
    'referencePhase', ~workingPage, ...
    'workingPhase', workingPage, ...
    'intraFormation', intraFormation, ...
    'receiverProtected', logical(receiverProtected), ...
    'receiverFormationRank', receiverFormationRank, ...
    'rankSelected', rankSelected, ...
    'workingRole', workingRole, ...
    'referenceRole', ~workingRole);
end
