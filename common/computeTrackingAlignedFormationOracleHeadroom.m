function summary = computeTrackingAlignedFormationOracleHeadroom( ...
        blocks, options)
% COMPUTETRACKINGALIGNEDFORMATIONORACLEHEADROOM V56 action-space gate.
%
% Computes two finite-bank upper bounds.  The tracking oracle uses every
% executed, payload-compliant local action.  The constrained oracle also
% requires nonnegative cardinality, minimum-formation, worst-sensor,
% consensus, and attempted-byte targets.  This is an offline development
% diagnostic, not a deployable selector.

if nargin < 2 || isempty(options)
    options = struct();
end
if iscell(blocks)
    blocks = [blocks{:}];
end
if ~isstruct(blocks) || isempty(blocks)
    error('Tracking-aligned oracle requires value blocks.');
end
minimumMeanGainPercent = getField( ...
    options, 'minimumMeanGainPercent', 5);
minimumPositiveStateFraction = getField( ...
    options, 'minimumPositiveStateFraction', 2 / 3);
constraintTolerance = getField( ...
    options, 'constraintTolerance', 1e-12);
if ~isscalar(minimumMeanGainPercent) || ...
        ~isfinite(minimumMeanGainPercent) || ...
        minimumMeanGainPercent < 0 || ...
        ~isscalar(minimumPositiveStateFraction) || ...
        ~isfinite(minimumPositiveStateFraction) || ...
        minimumPositiveStateFraction < 0 || ...
        minimumPositiveStateFraction > 1 || ...
        ~isscalar(constraintTolerance) || ...
        ~isfinite(constraintTolerance) || constraintTolerance < 0
    error('Tracking-aligned oracle thresholds are invalid.');
end

stateCount = numel(blocks);
states = repmat(emptyState(), 1, stateCount);
for stateIdx = 1:stateCount
    block = blocks(stateIdx);
    required = { ...
        'graph', 'targetNames', 'targets', ...
        'targetAvailableMask', 'executionSafeMask', ...
        'featuresUseTruth', 'featuresUseFutureMeasurements', ...
        'featuresUseFutureOutcome', 'targetsUseTruth'};
    if ~all(isfield(block, required)) || ...
            block.featuresUseTruth || ...
            block.featuresUseFutureMeasurements || ...
            block.featuresUseFutureOutcome || ...
            ~block.targetsUseTruth
        error('Tracking-aligned oracle block contract failed.');
    end
    targetIndex = targetIndices(block.targetNames);
    graph = block.graph;
    available = logical(block.targetAvailableMask) & ...
        logical(block.executionSafeMask) & ...
        logical(graph.modePresentMask) & ...
        logical(graph.modeWithinReferencePayloadMask);
    actionIndices = graph.modeActionIndex(available);
    if isempty(actionIndices)
        error('Tracking-aligned oracle state has no feasible reference.');
    end
    [uniqueActions, firstRows] = unique(actionIndices, 'stable');
    [formationRows, modeRows] = find(available);
    formationRows = formationRows(firstRows);
    modeRows = modeRows(firstRows);
    targetRows = zeros(numel(uniqueActions), numel(block.targetNames));
    for actionCursor = 1:numel(uniqueActions)
        targetRows(actionCursor, :) = reshape(block.targets( ...
            formationRows(actionCursor), modeRows(actionCursor), :), ...
            1, []);
    end
    if any(~isfinite(targetRows(:)))
        error('Tracking-aligned oracle target is non-finite.');
    end
    trackingValues = targetRows(:, targetIndex.meanTracking);
    constrainedMask = ...
        targetRows(:, targetIndex.cardinality) >= ...
            -constraintTolerance & ...
        targetRows(:, targetIndex.minimumFormation) >= ...
            -constraintTolerance & ...
        targetRows(:, targetIndex.worstSensor) >= ...
            -constraintTolerance & ...
        targetRows(:, targetIndex.consensus) >= ...
            -constraintTolerance & ...
        targetRows(:, targetIndex.attemptedBytes) >= ...
            -constraintTolerance;
    [trackingGain, trackingRow] = max(trackingValues);
    constrainedRows = find(constrainedMask);
    if isempty(constrainedRows)
        error('Tracking-aligned oracle lost its constrained reference.');
    end
    [constrainedGain, constrainedLocalRow] = max( ...
        trackingValues(constrainedRows));
    constrainedRow = constrainedRows(constrainedLocalRow);

    state = emptyState();
    state.presetName = optionalField(block, 'presetName', 'unknown');
    state.seed = optionalField(block, 'seed', NaN);
    state.currentTime = optionalField(block, 'currentTime', NaN);
    state.nodeCount = graph.nodeCount;
    state.formationCount = graph.formationCount;
    state.availableActionCount = numel(uniqueActions);
    state.constrainedActionCount = nnz(constrainedMask);
    state.trackingOracleGainPercent = trackingGain;
    state.trackingOracleActionIndex = uniqueActions(trackingRow);
    state.trackingOracleFormationIndex = formationRows(trackingRow);
    state.trackingOracleModeIndex = modeRows(trackingRow);
    state.trackingOracleModeName = ...
        graph.modeNames{modeRows(trackingRow)};
    state.constrainedOracleGainPercent = constrainedGain;
    state.constrainedOracleActionIndex = ...
        uniqueActions(constrainedRow);
    state.constrainedOracleFormationIndex = ...
        formationRows(constrainedRow);
    state.constrainedOracleModeIndex = modeRows(constrainedRow);
    state.constrainedOracleModeName = ...
        graph.modeNames{modeRows(constrainedRow)};
    state.constrainedOracleTargets = targetRows(constrainedRow, :);
    state.positiveConstrainedActionAvailable = ...
        constrainedGain > constraintTolerance;
    states(stateIdx) = state;
end

nodeCounts = unique([states.nodeCount], 'stable');
scales = repmat(emptyScale(), 1, numel(nodeCounts));
for scaleIdx = 1:numel(nodeCounts)
    nodeCount = nodeCounts(scaleIdx);
    mask = [states.nodeCount] == nodeCount;
    gains = [states(mask).constrainedOracleGainPercent];
    positive = [states(mask).positiveConstrainedActionAvailable];
    scale = emptyScale();
    scale.nodeCount = nodeCount;
    scale.stateCount = nnz(mask);
    scale.meanTrackingOracleGainPercent = mean( ...
        [states(mask).trackingOracleGainPercent]);
    scale.meanConstrainedOracleGainPercent = mean(gains);
    scale.minimumConstrainedOracleGainPercent = min(gains);
    scale.positiveConstrainedStateCount = nnz(positive);
    scale.positiveConstrainedStateFraction = mean(positive);
    scale.meanGatePassed = ...
        scale.meanConstrainedOracleGainPercent >= ...
            minimumMeanGainPercent - constraintTolerance;
    scale.coverageGatePassed = ...
        scale.positiveConstrainedStateFraction >= ...
            minimumPositiveStateFraction - constraintTolerance;
    scale.gatePassed = ...
        scale.meanGatePassed && scale.coverageGatePassed;
    scales(scaleIdx) = scale;
end

requiredScaleNodeCounts = reshape(getField( ...
    options, 'requiredScaleNodeCounts', [24, 36]), 1, []);
requiredScalePresent = ismember(requiredScaleNodeCounts, nodeCounts);
requiredScaleGatePassed = false(size(requiredScaleNodeCounts));
for idx = 1:numel(requiredScaleNodeCounts)
    match = find([scales.nodeCount] == ...
        requiredScaleNodeCounts(idx));
    if numel(match) == 1
        requiredScaleGatePassed(idx) = scales(match).gatePassed;
    end
end

summary = struct();
summary.contractVersion = ...
    'tracking-aligned-formation-oracle-headroom-v56-v1';
summary.stateCount = stateCount;
summary.states = states;
summary.scales = scales;
summary.minimumMeanGainPercent = minimumMeanGainPercent;
summary.minimumPositiveStateFraction = ...
    minimumPositiveStateFraction;
summary.constraintTolerance = constraintTolerance;
summary.requiredScaleNodeCounts = requiredScaleNodeCounts;
summary.requiredScalePresent = requiredScalePresent;
summary.requiredScaleGatePassed = requiredScaleGatePassed;
summary.gatePassed = all(requiredScalePresent) && ...
    all(requiredScaleGatePassed);
summary.featuresUseTruth = false;
summary.targetsUseTruth = true;
summary.offlineOracleOnly = true;
summary.modelTrainingAuthorized = summary.gatePassed;
summary.validationClaimAllowed = false;
end

function indices = targetIndices(names)
indices = struct( ...
    'meanTracking', oneIndex(names, ...
        'mean_tracking_gain_percent'), ...
    'cardinality', oneIndex(names, ...
        'cardinality_error_reduction_fraction'), ...
    'minimumFormation', oneIndex(names, ...
        'minimum_formation_gain_percent'), ...
    'worstSensor', oneIndex(names, ...
        'worst_sensor_gain_percent'), ...
    'consensus', oneIndex(names, ...
        'consensus_gain_percent'), ...
    'attemptedBytes', oneIndex(names, ...
        'attempted_byte_saving_percent'));
end

function index = oneIndex(names, expected)
index = find(strcmp(names, expected));
if numel(index) ~= 1
    error('Tracking-aligned oracle target is missing: %s.', expected);
end
end

function state = emptyState()
state = struct( ...
    'presetName', '', 'seed', NaN, 'currentTime', NaN, ...
    'nodeCount', NaN, 'formationCount', NaN, ...
    'availableActionCount', 0, 'constrainedActionCount', 0, ...
    'trackingOracleGainPercent', NaN, ...
    'trackingOracleActionIndex', NaN, ...
    'trackingOracleFormationIndex', NaN, ...
    'trackingOracleModeIndex', NaN, ...
    'trackingOracleModeName', '', ...
    'constrainedOracleGainPercent', NaN, ...
    'constrainedOracleActionIndex', NaN, ...
    'constrainedOracleFormationIndex', NaN, ...
    'constrainedOracleModeIndex', NaN, ...
    'constrainedOracleModeName', '', ...
    'constrainedOracleTargets', [], ...
    'positiveConstrainedActionAvailable', false);
end

function scale = emptyScale()
scale = struct( ...
    'nodeCount', NaN, 'stateCount', 0, ...
    'meanTrackingOracleGainPercent', NaN, ...
    'meanConstrainedOracleGainPercent', NaN, ...
    'minimumConstrainedOracleGainPercent', NaN, ...
    'positiveConstrainedStateCount', 0, ...
    'positiveConstrainedStateFraction', NaN, ...
    'meanGatePassed', false, ...
    'coverageGatePassed', false, 'gatePassed', false);
end

function value = optionalField(structure, name, fallback)
if isfield(structure, name)
    value = structure.(name);
else
    value = fallback;
end
end

function value = getField(structure, name, fallback)
if isstruct(structure) && isfield(structure, name)
    value = structure.(name);
else
    value = fallback;
end
end
