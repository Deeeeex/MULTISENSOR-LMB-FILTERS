function authorization = ...
    validateNetworkBudgetReallocatedMultiSourceV95Execution( ...
        model, context, request)
% VALIDATENETWORKBUDGETREALLOCATEDMULTISOURCEV95EXECUTION Four-arm permit.

expectedFields = { ...
    'contractVersion', 'capability', 'action', 'protocolId', ...
    'phase', 'presetName', 'seed', 'currentTime', ...
    'measurementTimeCount', 'policyName', 'actionName', ...
    'actionSequenceIndices', 'developmentEvidenceOnly'};
protocol = getNetworkBudgetReallocatedMultiSourceV95Protocol();
validContext = isequal(sort(fieldnames(context)), ...
        sort(expectedFields(:))) && ...
    strcmp(context.capability, ...
        'network-budget-reallocated-multi-source-v95-development') && ...
    strcmp(context.action, ...
        ['filter-network-budget-reallocated-multi-source-', ...
         'v95-development']) && ...
    strcmp(context.protocolId, protocol.id) && ...
    strcmp(context.phase, 'opened-return') && ...
    strcmp(context.policyName, protocol.outcomePolicyName) && ...
    ischar(context.actionName) && ~isempty(context.actionName) && ...
    isequal(context.developmentEvidenceOnly, true);
if ~validContext
    error('NetworkBudgetV95:InvalidExecutionContext', ...
        'The V95 paired execution context is malformed.');
end

caseInfo = resolveCase(context, protocol);
validSequence = false;
armOrdinal = NaN;
if ~isempty(caseInfo)
    registered = buildRegisteredSequences(caseInfo.horizonSteps);
    sequence = reshape(context.actionSequenceIndices, 1, []);
    if numel(sequence) == caseInfo.horizonSteps
        matches = all(bsxfun(@eq, registered, sequence), 2);
        validSequence = nnz(matches) == 1;
        if validSequence
            armOrdinal = find(matches, 1);
        end
    end
end
if ~validSequence
    error('NetworkBudgetV95:InvalidExecutionContext', ...
        'The V95 execution sequence is not a frozen paired arm.');
end

scenario = struct();
if isstruct(model) && isscalar(model) && ...
        isfield(model, 'dynamicTopologyScenario')
    scenario = model.dynamicTopologyScenario;
end
validModel = isstruct(model) && isscalar(model) && ...
    isfield(model, 'numberOfSensors') && ...
    model.numberOfSensors == caseInfo.expectedNodeCount && ...
    isstruct(scenario) && isscalar(scenario) && ...
    isfield(scenario, 'presetName') && ...
    strcmp(scenario.presetName, context.presetName) && ...
    isfield(scenario, 'seed') && scenario.seed == context.seed && ...
    isfield(scenario, 'config') && ...
    scenario.config.formationCount == caseInfo.expectedFormationCount && ...
    isfield(scenario.config, 'sceneStyle') && ...
    strcmp(scenario.config.sceneStyle, 'braided-handover') && ...
    ~isfield(model, 'explicitTargetTrajectories') && ...
    ~isfield(scenario, 'targetTrajectories') && ...
    ~isfield(scenario, 'target');
if ~validModel
    error('NetworkBudgetV95:InvalidRuntimeModel', ...
        'The V95 runtime model is not a registered development case.');
end

requiredRequestFields = { ...
    'contractVersion', 'operation', 'measurementTimeCount', ...
    'sensorTrajectoryTimeCounts', 'triggerConfig'};
config = request.triggerConfig;
validRequest = isequal(sort(fieldnames(request)), ...
        sort(requiredRequestFields(:))) && ...
    strcmp(request.operation, 'filter-execution') && ...
    request.measurementTimeCount == context.measurementTimeCount && ...
    context.measurementTimeCount == ...
        context.currentTime + caseInfo.horizonSteps - 1 && ...
    numel(request.sensorTrajectoryTimeCounts) == ...
        caseInfo.expectedNodeCount && ...
    all(request.sensorTrajectoryTimeCounts == ...
        context.measurementTimeCount) && ...
    isstruct(config) && isscalar(config) && ...
    isfield(config, 'topologyPolicyName') && ...
    strcmp(config.topologyPolicyName, context.policyName) && ...
    isfield(config, 'topologyPolicyHistoryDepth') && ...
    config.topologyPolicyHistoryDepth >= 2 && ...
    isfield(config, 'topologyDirectedMessageBudget') && ...
    config.topologyDirectedMessageBudget == ...
        2 * caseInfo.expectedNodeCount && ...
    isfield(config, 'missingLabelFusionMode') && ...
    strcmpi(config.missingLabelFusionMode, protocol.receiverMode);
if ~validRequest
    error('NetworkBudgetV95:InvalidRuntimeRequest', ...
        'The V95 runtime request changed its frozen paired boundary.');
end

authorization = struct();
authorization.contractVersion = ...
    'dynamic-topology-filter-execution-authorization-v1';
authorization.mode = ...
    'network-budget-reallocated-multi-source-v95-development';
authorization.permitId = '';
authorization.permitCanonicalSha256 = '';
authorization.capability = context.capability;
authorization.action = context.action;
authorization.protocolId = protocol.id;
authorization.protocolCanonicalSha256 = '';
authorization.caseId = '';
authorization.caseCanonicalSha256 = '';
authorization.presetName = context.presetName;
authorization.seed = context.seed;
authorization.sourceWindow = [1, context.measurementTimeCount];
authorization.armId = context.actionName;
authorization.armOrdinal = armOrdinal;
authorization.methodSourceCommit = '';
authorization.methodPolicyConfigSha256 = '';
authorization.sourceTriggerFingerprintSha256 = '';
authorization.executableSourceCommit = '';
authorization.executableSourceManifestSha256 = '';
authorization.executionHeadCommit = '';
authorization.sourceInputFingerprintSha256 = '';
authorization.stateEstimateOutputAuthorized = true;
authorization.trackingOutcomeScoringAuthorized = true;
authorization.groundTruthAccessAuthorized = false;
authorization.futureOutcomeAccessAuthorized = false;
authorization.validationClaimAllowed = false;
authorization.developmentEvidenceOnly = true;
end

function caseInfo = resolveCase(context, protocol)
caseInfo = [];
for candidate = protocol.cases
    if strcmp(context.presetName, candidate.presetName) && ...
            context.seed == candidate.seed && ...
            context.currentTime == candidate.currentTime
        caseInfo = candidate;
        return;
    end
end
end

function sequences = buildRegisteredSequences(horizonSteps)
reference = ones(1, horizonSteps);
donorOnly = reference;
candidate = reference;
donorOnly(1) = 2;
candidate(1) = 3;
fixedCandidate = 3 * ones(1, horizonSteps);
sequences = [reference; donorOnly; candidate; fixedCandidate];
end
