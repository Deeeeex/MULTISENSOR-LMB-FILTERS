function authorization = ...
        validateReceiverRelativeLabelRoleTeacherV149Execution( ...
            model, context, request)
% VALIDATERECEIVERRELATIVELABELROLETEACHERV149EXECUTION Enforce V149.

protocol = getReceiverRelativeLabelRoleTeacherV149Protocol();
baseContext = context;
if ~isstruct(baseContext) || ~isscalar(baseContext) || ...
        ~all(isfield(baseContext, { ...
            'phase', 'receiverTeacherEnabled', ...
            'referenceCoverRequired'}))
    error('ReceiverRelativeLabelRoleV149:InvalidExecutionContext', ...
        'The V149 execution context is malformed.');
end
enabled = strcmp(baseContext.phase, 'candidate');
validContext = strcmp(baseContext.contractVersion, ...
        'v149-receiver-relative-label-role-teacher-context-v1') && ...
    strcmp(baseContext.capability, ...
        'receiver-relative-label-role-teacher-v149-development') && ...
    strcmp(baseContext.action, ...
        'filter-receiver-relative-label-role-teacher-v149-development') && ...
    strcmp(baseContext.protocolId, protocol.id) && ...
    strcmp(baseContext.policyName, protocol.outcomePolicyName) && ...
    islogical(baseContext.receiverTeacherEnabled) && ...
    baseContext.receiverTeacherEnabled == enabled && ...
    isequal(baseContext.referenceCoverRequired, true);
if ~validContext || ~isstruct(request) || ~isscalar(request) || ...
        ~isfield(request, 'triggerConfig') || ...
        ~isstruct(request.triggerConfig) || ...
        ~isscalar(request.triggerConfig)
    error('ReceiverRelativeLabelRoleV149:InvalidExecutionContext', ...
        'The V149 context or runtime request is malformed.');
end
config = request.triggerConfig;
validRuntime = isfield(config, ...
        'lineageRelayRoleMultiplexedReceiverTeacherEnabled') && ...
    logical(config. ...
        lineageRelayRoleMultiplexedReceiverTeacherEnabled) == enabled && ...
    isfield(config, 'lineageRelayRoleMultiplexedLabelHybridEnabled') && ...
    logical(config.lineageRelayRoleMultiplexedLabelHybridEnabled) == ...
        enabled && ...
    isfield(config, 'topologyPolicyName') && ...
    strcmp(config.topologyPolicyName, protocol.outcomePolicyName);
if ~validRuntime
    error('ReceiverRelativeLabelRoleV149:InvalidRuntimeRequest', ...
        'The V149 request changed the receiver-teacher boundary.');
end

baseContext = rmfield(baseContext, ...
    {'receiverTeacherEnabled', 'referenceCoverRequired'});
baseProtocol = getLabelRoleMultiplexedSinglePayloadV148Protocol();
baseContext.contractVersion = ...
    'v148-label-role-multiplexed-execution-context-v1';
baseContext.capability = ...
    'label-role-multiplexed-single-payload-v148-development';
baseContext.action = ...
    'filter-label-role-multiplexed-single-payload-v148-development';
baseContext.protocolId = baseProtocol.id;
baseContext.policyName = baseProtocol.outcomePolicyName;
baseRequest = request;
baseRequest.triggerConfig.topologyPolicyName = ...
    baseProtocol.outcomePolicyName;
baseRequest.triggerConfig. ...
    lineageRelayRoleMultiplexedReceiverTeacherEnabled = false;
try
    authorization = ...
        validateLabelRoleMultiplexedSinglePayloadV148Execution( ...
            model, baseContext, baseRequest);
catch errorInfo
    error('ReceiverRelativeLabelRoleV149:InvalidRuntimeRequest', ...
        'The V149 request failed the inherited V148 boundary: %s', ...
        errorInfo.message);
end
authorization.mode = ...
    'receiver-relative-label-role-teacher-v149-development';
authorization.capability = context.capability;
authorization.action = context.action;
authorization.protocolId = protocol.id;
end
