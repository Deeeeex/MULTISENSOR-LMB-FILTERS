function [meanPage, rowSecondMoments, details] = ...
    computeExpectedEffectiveMixingPageMoments( ...
        adjacency, weights, reliability, missingMode, ...
        maximumIncomingCount)
% COMPUTEEXPECTEDEFFECTIVEMIXINGPAGEMOMENTS Exact delivery moments.
%
% Inputs use receiver rows and sender columns.  Each receiver row depends
% only on its own incoming delivery indicators.  Under independent
% receiver-sender delivery variables, different effective rows are
% independent, while rowSecondMoments(:,:,i) stores E[m_i' * m_i].

if nargin < 4 || isempty(missingMode)
    missingMode = 'renormalize';
end
if nargin < 5 || isempty(maximumIncomingCount)
    maximumIncomingCount = 4;
end
missingMode = lower(char(missingMode));
if ~(isnumeric(adjacency) || islogical(adjacency)) || ...
        ~isreal(adjacency) || any(~isfinite(adjacency(:))) || ...
        any(adjacency(:) ~= 0 & adjacency(:) ~= 1) || ...
        ~isnumeric(weights) || ~isreal(weights) || ...
        any(~isfinite(weights(:))) || ...
        ~isnumeric(reliability) || ~isreal(reliability) || ...
        any(~isfinite(reliability(:))) || ...
        ndims(adjacency) ~= 2 || ...
        size(adjacency, 1) ~= size(adjacency, 2) || ...
        size(adjacency, 1) < 2 || ...
        ~isequal(size(weights), size(adjacency)) || ...
        ~isequal(size(reliability), size(adjacency)) || ...
        ~ismember(missingMode, {'renormalize', 'self'}) || ...
        ~isscalar(maximumIncomingCount) || ...
        ~isfinite(maximumIncomingCount) || ...
        maximumIncomingCount < 1 || ...
        maximumIncomingCount ~= round(maximumIncomingCount)
    error('KlaMixingMoments:InvalidPage', ...
        'The effective mixing-page moment inputs are malformed.');
end
adjacency = logical(adjacency);
nodeCount = size(adjacency, 1);
weightSupport = adjacency | logical(eye(nodeCount));
if any(diag(adjacency)) || ...
        any(diag(weights) <= 0) || ...
        any(weights(:) < 0) || ...
        any(weights(:) > 1e-12 & ~weightSupport(:)) || ...
        any(abs(sum(weights, 2) - 1) > 1e-12) || ...
        any(reliability(:) < 0) || any(reliability(:) > 1) || ...
        any(sum(adjacency, 2) > maximumIncomingCount)
    error('KlaMixingMoments:InvalidPage', ...
        'The effective mixing page violates its stochastic contract.');
end

meanPage = zeros(nodeCount);
rowSecondMoments = zeros(nodeCount, nodeCount, nodeCount);
outcomeCountByReceiver = zeros(1, nodeCount);
probabilitySumByReceiver = zeros(1, nodeCount);
for receiverIdx = 1:nodeCount
    senders = reshape(find(adjacency(receiverIdx, :)), 1, []);
    outcomeCount = 2^numel(senders);
    outcomeCountByReceiver(receiverIdx) = outcomeCount;
    for outcomeIdx = 0:(outcomeCount - 1)
        if isempty(senders)
            delivered = false(1, 0);
        else
            delivered = logical(bitget( ...
                uint64(outcomeIdx), 1:numel(senders)));
        end
        deliveredProbability = reliability( ...
            receiverIdx, senders(delivered));
        missingProbability = 1 - reliability( ...
            receiverIdx, senders(~delivered));
        probability = prod(deliveredProbability) * ...
            prod(missingProbability);
        row = zeros(1, nodeCount);
        row(receiverIdx) = weights(receiverIdx, receiverIdx);
        deliveredSenders = senders(delivered);
        row(deliveredSenders) = ...
            weights(receiverIdx, deliveredSenders);
        if strcmp(missingMode, 'self')
            row(receiverIdx) = row(receiverIdx) + sum( ...
                weights(receiverIdx, senders(~delivered)));
        end
        row = row / sum(row);
        meanPage(receiverIdx, :) = ...
            meanPage(receiverIdx, :) + probability * row;
        rowSecondMoments(:, :, receiverIdx) = ...
            rowSecondMoments(:, :, receiverIdx) + ...
            probability * (row' * row);
        probabilitySumByReceiver(receiverIdx) = ...
            probabilitySumByReceiver(receiverIdx) + probability;
    end
end
if any(abs(probabilitySumByReceiver - 1) > 1e-12) || ...
        any(abs(sum(meanPage, 2) - 1) > 1e-12)
    error('KlaMixingMoments:InternalMomentError', ...
        'The effective mixing-page moments failed normalization.');
end
for receiverIdx = 1:nodeCount
    covariance = rowSecondMoments(:, :, receiverIdx) - ...
        meanPage(receiverIdx, :)' * meanPage(receiverIdx, :);
    covariance = 0.5 * (covariance + covariance');
    if min(eig(covariance)) < -1e-10
        error('KlaMixingMoments:InternalMomentError', ...
            'An effective mixing-row covariance is not semidefinite.');
    end
end

details = struct();
details.contractVersion = ...
    'expected-effective-mixing-page-moments-v1';
details.nodeCount = nodeCount;
details.missingNeighborWeightMode = missingMode;
details.maximumIncomingCount = maximumIncomingCount;
details.outcomeCountByReceiver = outcomeCountByReceiver;
details.probabilitySumByReceiver = probabilitySumByReceiver;
details.receiverRowsIndependentAssumed = true;
details.receiverSenderDeliveriesIndependentAssumed = true;
details.momentsExactUnderIndependence = true;
end
