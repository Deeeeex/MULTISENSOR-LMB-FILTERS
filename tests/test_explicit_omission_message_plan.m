function test_explicit_omission_message_plan()
% TEST_EXPLICIT_OMISSION_MESSAGE_PLAN Verify charged zero-payload envelopes.

model = buildModel();
object = struct( ...
    'birthTime', 1, ...
    'birthLocation', 7, ...
    'r', 0.8, ...
    'numberOfGmComponents', 1, ...
    'w', 1, ...
    'mu', {{zeros(4, 1)}}, ...
    'Sigma', {{eye(4)}}, ...
    'detectionAssociationMass', 0.1);
posteriors = {object, object};
selectiveEdges = false(2);
selectiveEdges(2, 1) = true;
dropPlan = cell(2);
dropPlan{1, 2} = [object.birthTime; object.birthLocation];
updateDiagnostics = {struct(), struct()};
config = struct( ...
    'payloadExistenceThreshold', 0.01, ...
    'receiverSafeExternalDropLabelsByReceiverSender', {dropPlan}, ...
    'receiverSafeExternalPositiveSupportThreshold', 0.2, ...
    'receiverSafeExternalExplicitOmissionEnabled', true);

plan = buildExternalReceiverLabelMessagePlan( ...
    posteriors, selectiveEdges, updateDiagnostics, model, config);
assert(plan.explicitLabelOmissionRegisteredEdgeMask(2, 1));
assert(isempty(plan.payloadByReceiverSender{1, 2}));
assert(isequal( ...
    plan.explicitOmittedLabelsByReceiverSender{1, 2}, ...
    dropPlan{1, 2}));
assert(plan.receiverDetails(1).controlSynopsisBytesBySender == 24);
assert(plan.receiverDetails(1).selectedPayloadBytesBySender == 0);
assert(plan.receiverDetails(1).byteBudgetSatisfied);
assert(plan.totalAttemptedBytes == 24);
assert(plan.totalAttemptedBytes < plan.totalBaselineFullBytes);

fusionDetails = struct( ...
    'sourceIndices', [1, 2], ...
    'isSelf', [true, false], ...
    'isStale', [false, false], ...
    'currentTime', 1, ...
    'eventType', [2, 2], ...
    'explicitLabelOmissionRegistered', ...
        [false, plan.explicitLabelOmissionRegisteredEdgeMask(2, 1)], ...
    'explicitOmittedLabels', ...
        {{zeros(2, 0), ...
          plan.explicitOmittedLabelsByReceiverSender{1, 2}}});
fusionConfig = buildMixtureAwareKlaReferenceConfig(struct( ...
    'missingLabelFusionMode', 'fov-aware-censored'));
[fused, fusionDiagnostics] = fuseLmbPosteriorsByLabel( ...
    {object, plan.payloadByReceiverSender{1, 2}}, ...
    [0.5, 0.5], model, [0.5, 0.5], fusionDetails, fusionConfig);
assert(numel(fused) == 1);
assert(abs(fused.r - object.r) <= 1e-10);
assert(fusionDiagnostics.explicitLabelAbstentionSourceCount == 1);

noDropConfig = config;
noDropConfig.receiverSafeExternalDropLabelsByReceiverSender = cell(2);
fullPlan = buildExternalReceiverLabelMessagePlan( ...
    posteriors, selectiveEdges, updateDiagnostics, model, noDropConfig);
assert(~fullPlan.explicitLabelOmissionRegisteredEdgeMask(2, 1));
assert(numel(fullPlan.payloadByReceiverSender{1, 2}) == 1);
assert(fullPlan.receiverDetails(1).controlSynopsisBytesBySender == 0);
assert(fullPlan.totalAttemptedBytes == fullPlan.totalBaselineFullBytes);

fprintf('test_explicit_omission_message_plan passed\n');
end

function model = buildModel()
model = struct();
model.xDimension = 4;
model.existenceThreshold = 0.01;
model.numberOfSensors = 2;
model.detectionProbability = [0.9, 0.9];
model.Q = {eye(2), eye(2)};
model.sensorMotionEnabled = true;
model.sensorFovEnabled = true;
model.sensorFovHalfAngleDeg = [60, 60];
model.sensorFovRange = [100, 100];
model.sensorFovHeadingRad = [0; 0];
model.sensorTrajectories = {zeros(4, 1), zeros(4, 1)};
model.sensorQuality = struct('enabled', false);
end
