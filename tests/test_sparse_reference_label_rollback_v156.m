function test_sparse_reference_label_rollback_v156()
% TEST_SPARSE_REFERENCE_LABEL_ROLLBACK_V156 Bounded complete-label merge.

current = [makeObject(1, 1, 0.95, [0; 0; 0; 0]), ...
           makeObject(1, 2, 0.90, [10; 0; 0; 0])];
reference = [makeObject(1, 1, 0.95, [0; 0; 0; 0]), ...
             makeObject(1, 3, 0.90, [20; 0; 0; 0])];
[merged, details] = mergeSparseReferenceLmbLabels( ...
    current, reference, 2, 1e-2);
labels = [[merged.birthTime]; [merged.birthLocation]];
assert(isequal(labels, [1, 1; 1, 3]));
assert(details.selectedLabelCount == 2);
assert(any(details.selectedTombstone));
assert(details.estimatedPayloadBytes > 0);

config = struct( ...
    'shadowStateRollbackEnabled', true, ...
    'shadowStateRollbackTimes', 76, ...
    'shadowStateRollbackSensorIdsByTime', {{8}}, ...
    'shadowStateRollbackFusedPosteriorByTime', ...
        {{{reference, reference, reference, reference, ...
           reference, reference, reference, reference}}}, ...
    'shadowStateRollbackSourceMode', ...
        'external-sparse-reference-labels', ...
    'shadowStateRollbackMaximumLabelEdits', 2, ...
    'shadowStateRollbackExistenceThreshold', 1e-2);
[selected, applied, pageIdx, selectedDetails] = ...
    selectShadowStateRollbackPosterior(current, config, 8, 76);
assert(applied && pageIdx == 1);
assert(selectedDetails.selectedLabelCount == 2);
assert(isequal([[selected.birthTime]; [selected.birthLocation]], ...
    [1, 1; 1, 3]));

protocol = getSparseReferenceLabelRollbackV156Protocol(4);
assert(protocol.maximumLabelEdits == 4);
context = buildSparseReferenceLabelRollbackV156ExecutionContext( ...
    'x36-formation-fov', 211, 72, ...
    protocol.candidateActionName, true, 4);
assert(isSparseReferenceLabelRollbackV156ExecutionContext(context));
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
groupIds = repelem(1:6, 6);
sensorIdsByTime = cellfun(@(formations) ...
    find(ismember(groupIds, formations)), ...
    protocol.rollbackFormationIdsByTime, 'UniformOutput', false);
shadowPage = repmat({reference}, 1, entry.expectedNodeCount);
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount, ...
            'sensorGroupIds', groupIds)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.protectionFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', 'control-only', ...
        'shadowStateRollbackEnabled', true, ...
        'shadowStateRollbackSourceMode', ...
            'external-sparse-reference-labels', ...
        'shadowStateRollbackMaximumLabelEdits', 4, ...
        'shadowStateRollbackTimes', protocol.rollbackTimes, ...
        'shadowStateRollbackSensorIdsByTime', {sensorIdsByTime}, ...
        'shadowStateRollbackFusedPosteriorByTime', ...
            {repmat({shadowPage}, 1, protocol.horizonSteps)}));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));
fprintf('test_sparse_reference_label_rollback_v156 passed\n');
end

function object = makeObject(birthTime, birthLocation, existence, meanVector)
object = struct( ...
    'birthLocation', birthLocation, ...
    'birthTime', birthTime, ...
    'r', existence, ...
    'numberOfGmComponents', 1, ...
    'w', 1, ...
    'mu', {{meanVector}}, ...
    'Sigma', {{eye(numel(meanVector))}});
end
