function test_budgeted_observation_supported_repair_v197()
% TEST_BUDGETED_OBSERVATION_SUPPORTED_REPAIR_V197 Top-one cooldown.

protocol = getBudgetedObservationSupportedRepairV197Protocol();
setSafe = struct( ...
    'contractVersion', ...
        'observation-supported-set-safe-v194-projection-v1', ...
    'groups', [1, 2, 3], ...
    'proposedFormationIds', [1, 2, 3], ...
    'selectedFormationIds', 3, ...
    'releaseFormationIds', [1, 2], ...
    'maximumReceiverRiskByFormation', [0.10, 0.20, 0], ...
    'truthUsed', false, ...
    'futureInformationUsed', false);

available = projectBudgetedObservationSupportedRepairV197( ...
    setSafe, cell(1, 0), protocol);
assert(available.releaseTokenAvailable);
assert(isequal(available.releaseFormationIds, 2));
assert(isequal(available.selectedFormationIds, [1, 3]));
assert(abs(available.selectedReleaseRisk - 0.20) < 1e-12);

cooldown = projectBudgetedObservationSupportedRepairV197( ...
    setSafe, {2, []}, protocol);
assert(~cooldown.releaseTokenAvailable);
assert(isempty(cooldown.releaseFormationIds));
assert(isequal(cooldown.selectedFormationIds, [1, 2, 3]));

refilled = projectBudgetedObservationSupportedRepairV197( ...
    setSafe, {[], []}, protocol);
assert(refilled.releaseTokenAvailable);
assert(isequal(refilled.releaseFormationIds, 2));

execution = ...
    buildBudgetedObservationSupportedRepairV197ExecutionContext( ...
        'x36-formation-fov', 211, 72, ...
        'v99-online-positive-net-f1-f2-f4-f5', true, true);
assert(isBudgetedObservationSupportedRepairV197ExecutionContext( ...
    execution));
assert(strcmp(execution.protocolId, protocol.id));
assert(strcmp(execution.policyName, protocol.outcomePolicyName));

model = struct();
model.numberOfSensors = 36;
model.dynamicTopologyScenario = struct( ...
    'presetName', 'x36-formation-fov', ...
    'seed', 211, 'config', struct('formationCount', 6));
config = struct( ...
    'topologyPolicyName', protocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'topologyPolicyPayloadReleaseHistoryEnabled', true, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', true, ...
    'receiverSafeLabelFusionMode', 'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', 72:74, ...
    'receiverSafeFormationConditionedSchedule', {cell(1, 3)}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only');
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', 74, ...
    'sensorTrajectoryTimeCounts', repmat(74, 1, 36), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, execution, request);
assert(strcmp(authorization.mode, ...
    'budgeted-observation-supported-repair-v197-development'));
assert(strcmp(authorization.protocolId, protocol.id));
assert(~authorization.groundTruthAccessAuthorized);
assert(~authorization.futureOutcomeAccessAuthorized);

h8Protocol = getBudgetedObservationSupportedRepairV197Protocol(8);
h8Execution = ...
    buildBudgetedObservationSupportedRepairV197ExecutionContext( ...
        'x36-formation-fov', 211, 72, ...
        'v99-online-positive-net-f1-f2-f4-f5', true, true, 8);
assert(h8Execution.measurementTimeCount == 79);
h8Request = request;
h8Request.measurementTimeCount = 79;
h8Request.sensorTrajectoryTimeCounts = repmat(79, 1, 36);
h8Request.triggerConfig.topologyPolicyName = ...
    h8Protocol.outcomePolicyName;
h8Request.triggerConfig.receiverSafeExternalActiveTimes = 72:79;
h8Request.triggerConfig.receiverSafeFormationConditionedSchedule = ...
    cell(1, 8);
h8Authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, h8Execution, h8Request);
assert(strcmp(h8Authorization.protocolId, h8Protocol.id));
fprintf('test_budgeted_observation_supported_repair_v197 passed.\n');
end
