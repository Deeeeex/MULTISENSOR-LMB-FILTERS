function test_formation_b4_v46_development_runtime_materializer()
% One accepted case regenerates a truth-free filter boundary exactly.

accepted = getFormationB4V46DevelopmentRuntimeAcceptanceRegistry();
caseOrdinal = accepted.entries(1).caseOrdinal;
initialRngState = rng();
runtime = materializeFormationB4V46DevelopmentRuntimeInput(caseOrdinal);
finalRngState = rng();
assert(isequaln(initialRngState, finalRngState));
expectedFields = { ...
    'contractVersion', 'caseOrdinal', 'caseId', ...
    'coreCaseCanonicalSha256', ...
    'runtimeAcceptanceRegistryCanonicalSha256', ...
    'runtimeFilterProjectionCanonicalSha256', 'model', ...
    'measurements', 'sensorTrajectories', 'neighborMap', ...
    'commConfig', 'runtimeFingerprint', ...
    'deliveryUniformMetadataCanonicalSha256', ...
    'targetTrajectoryRealizationReturned', 'groundTruthReturned', ...
    'fullScenarioTargetMetadataReturned', 'filterExecuted', ...
    'trackingOutcomeScored', 'validationClaimAllowed'};
assert(isequal(sort(fieldnames(runtime)), sort(expectedFields(:))));
assert(strcmp(runtime.contractVersion, ...
    'formation-b4-v46-development-runtime-input-v1'));
assert(runtime.caseOrdinal == caseOrdinal);
assert(strcmp(runtime.caseId, accepted.entries(1).caseId));
assert(strcmp(runtime.runtimeFilterProjectionCanonicalSha256, ...
    accepted.entries(1).runtimeFilterProjectionCanonicalSha256));
assert(~runtime.targetTrajectoryRealizationReturned);
assert(~runtime.groundTruthReturned);
assert(~runtime.fullScenarioTargetMetadataReturned);
assert(~runtime.filterExecuted);
assert(~runtime.trackingOutcomeScored);
assert(~runtime.validationClaimAllowed);
assert(~isfield(runtime.model, 'explicitTargetTrajectories'));
assert(~isfield(runtime.model, 'targetTrajectories'));
assert(~isfield(runtime.model, 'groundTruth'));
rehash = computeFormationB4V46RuntimeFilterInputFingerprintFromBoundary( ...
    runtime.model, runtime.measurements, runtime.sensorTrajectories, ...
    runtime.neighborMap, runtime.commConfig, caseOrdinal);
assert(isequaln(rehash, runtime.runtimeFingerprint));

registry = getFormationB4V46DevelopmentArmPermitRegistry();
if registry.executionSurfaceFrozen
    armId = registry.orderedArmIds{1};
    permit = loadFormationB4V46DevelopmentArmPermit( ...
        caseOrdinal, armId);
    triggerConfig = buildFormationB4V46FixedTriggerConfig( ...
        armId, permit.numberOfSensors);
    context = buildFormationB4V46DevelopmentArmExecutionContext( ...
        caseOrdinal, armId);
    request = struct( ...
        'contractVersion', ...
            'dynamic-topology-filter-authorization-request-v1', ...
        'operation', 'filter-execution', ...
        'measurementTimeCount', size(runtime.measurements, 2), ...
        'sensorTrajectoryTimeCounts', repmat( ...
            permit.simulationLength, 1, permit.numberOfSensors), ...
        'triggerConfig', triggerConfig, ...
        'inputFingerprint', runtime.runtimeFingerprint);
    authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
        runtime.model, context, request);
    assert(strcmp(authorization.mode, ...
        'registered-v46-development-arm-permit'));
    assert(authorization.stateEstimateOutputAuthorized);
    assert(~authorization.trackingOutcomeScoringAuthorized);
    assert(~authorization.groundTruthAccessAuthorized);
    assert(~authorization.validationClaimAllowed);
else
    armId = registry.orderedArmIds{1};
    triggerConfig = buildFormationB4V46FixedTriggerConfig( ...
        armId, runtime.model.numberOfSensors);
    sealedContext = struct( ...
        'contractVersion', ...
            'formation-b4-v46-development-arm-execution-context-v1', ...
        'permitId', 'sealed', 'permitCanonicalSha256', '', ...
        'capability', 'development-arm-state-estimate', ...
        'action', 'filter-development-arm', ...
        'caseOrdinal', caseOrdinal, 'armId', armId);
    assertErrorId(@() runEventTriggeredDistributedLmbFilter( ...
        runtime.model, runtime.measurements, ...
        runtime.sensorTrajectories, runtime.neighborMap, ...
        runtime.commConfig, triggerConfig, sealedContext), ...
        'FormationB4V46DevelopmentPermit:ExecutionSealed');
end
fprintf('PASS: V46 development runtime materializer tests\n');
end

function assertErrorId(callback, expectedIdentifier)
actualIdentifier = '';
try
    callback();
catch errorInfo
    actualIdentifier = errorInfo.identifier;
end
assert(strcmp(actualIdentifier, expectedIdentifier), ...
    'Expected %s, received %s.', ...
    expectedIdentifier, actualIdentifier);
end
