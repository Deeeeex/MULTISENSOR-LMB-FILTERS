function testStructuredFormationTreeRanker()
groupIds = [1, 1, 2, 2, 3, 3];
receiverIndices = zeros(0, 1);
senderIndices = zeros(0, 1);
rawResidual = zeros(0, 1);
X = zeros(0, 2);
pairUtility = [ ...
    0, 5, 1; ...
    1, 0, 4; ...
    3, 1, 0];
groups = unique(groupIds, 'stable');
for receiverIdx = 1:numel(groupIds)
    receiverGroup = find(groups == groupIds(receiverIdx), 1);
    for senderIdx = 1:numel(groupIds)
        senderGroup = find(groups == groupIds(senderIdx), 1);
        if receiverGroup == senderGroup
            continue;
        end
        value = pairUtility(senderGroup, receiverGroup) + ...
            0.01 * senderIdx - 0.001 * receiverIdx;
        receiverIndices(end + 1, 1) = receiverIdx; %#ok<AGROW>
        senderIndices(end + 1, 1) = senderIdx; %#ok<AGROW>
        rawResidual(end + 1, 1) = value; %#ok<AGROW>
        X(end + 1, :) = [ ...
            value, (-1) ^ numel(rawResidual)]; %#ok<AGROW>
    end
end
projectionOptions = struct( ...
    'requiredUnionFormationAdjacency', logical([ ...
        0, 0, 0; ...
        0, 0, 0; ...
        1, 0, 0]));
block = struct( ...
    'X', X, ...
    'groupIds', groupIds, ...
    'receiverIndices', receiverIndices, ...
    'senderIndices', senderIndices, ...
    'rawResidual', rawResidual, ...
    'baselineRisk', 10 * ones(1, numel(groupIds)), ...
    'projectionOptions', projectionOptions);
blocks = [block, block];
blocks(2).X(:, 1) = 0.8 * blocks(2).X(:, 1) + 0.2;
blocks(2).rawResidual = 0.8 * blocks(2).rawResidual;
model = fitStructuredFormationTreeRanker(blocks, struct( ...
    'lambda', 0, 'epochCount', 40, 'learningRate', 0.25));
scores = scoreStructuredFormationTreeRanker(model, X);
selected = selectRootedFormationTreeEdges( ...
    groupIds, receiverIndices, senderIndices, scores, ...
    projectionOptions);
oracle = selectRootedFormationTreeEdges( ...
    groupIds, receiverIndices, senderIndices, rawResidual, ...
    projectionOptions);
assert(model.coefficient(1) > 0);
assert(abs(sum(rawResidual(selected.exampleIndices)) - ...
    sum(rawResidual(oracle.exampleIndices))) < 1e-12);
assert(selected.formationUnionStrongConnected);
end

