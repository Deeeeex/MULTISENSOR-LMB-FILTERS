function fused = fuseCounterfactualTestPosterior( ...
        receiver, sender, model, triggerConfig, sourceWeight)
payload = sender([sender.r] > ...
    triggerConfig.payloadExistenceThreshold & ...
    [sender.numberOfGmComponents] > 0);
weights = [1 - sourceWeight, sourceWeight];
fused = fuseLmbPosteriorsByLabel( ...
    {receiver, payload}, weights, model, weights, ...
    struct('eventType', [0, 2]), triggerConfig);
fused = fused([fused.r] > model.existenceThreshold & ...
    [fused.numberOfGmComponents] > 0);
end

function finalized = finalizeCounterfactualTestFailure( ...
        posterior, existenceThreshold)
finalized = posterior([posterior.r] > existenceThreshold & ...
    [posterior.numberOfGmComponents] > 0);
end

function expected = bruteForceExpectedNetworkDisagreement( ...
        failurePosteriors, successPosteriors, ...
        reliabilities, model)
nodeCount = numel(failurePosteriors);
expected = 0;
for deliveryMask = 0:(2^nodeCount - 1)
    probability = 1;
    realized = failurePosteriors;
    for nodeIdx = 1:nodeCount
        if bitget(deliveryMask, nodeIdx)
            probability = probability * reliabilities(nodeIdx);
            realized{nodeIdx} = successPosteriors{nodeIdx};
        else
            probability = probability * ...
                (1 - reliabilities(nodeIdx));
        end
    end
    metrics = computeLmbPosteriorNetworkDisagreement( ...
        realized, model);
    expected = expected + probability * metrics.combined;
end
end

function risk = expectedPairTail(pairRisk, tailFraction)
values = sort(pairRisk(triu(true(size(pairRisk)), 1)), ...
    'descend');
tailCount = max(1, ceil(tailFraction * numel(values)));
risk = mean(values(1:tailCount));
end

