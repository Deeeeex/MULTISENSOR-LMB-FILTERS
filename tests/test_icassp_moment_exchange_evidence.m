function test_icassp_moment_exchange_evidence()
% TEST_ICASSP_MOMENT_EXCHANGE_EVIDENCE Verify publish and corruption gates.

[~, ~, ~, ~, config] = ...
    runFusionSufficientMomentExchangeConfirmatory(false);
testAuthorization = fusionSufficientInternalTestAuthorization();
config.testOnly = true;
config.evidenceSchema = 'fusion-sufficient-moment-exchange-test-v2';
config.workerSchema = 'fusion-sufficient-seed-worker-test-v2';
config.numberOfTrials = 5;
config.baseSeed = 1000;
config.firstSeed = 1001;
config.lastSeed = 1005;
config.isSmoke = true;
config.artifactStem = ...
    'TEST_FUSION_SUFFICIENT_EVIDENCE_N5';
config.batchIdentity = 'test-evidence-n5';
outputDirectory = tempname();
[ok, message] = mkdir(outputDirectory);
assert(ok, message);
cleanup = onCleanup(@() removeTestDirectory(outputDirectory)); %#ok<NASGU>
config.outputDirectory = outputDirectory;
config.regenerationCommand = 'synthetic evidence test';
config.configSha256 = hashFusionSufficientConfig(config);
synthetic = makeSyntheticSummary(config);
[summary, plan] = materializeSyntheticBatch( ...
    synthetic, config, testAuthorization);
publishClaim = acquireFusionSufficientPublishClaim( ...
    plan, config, testAuthorization);

invalidSummary = summary;
invalidSummary.trials.attemptedPayloadBytes(1, 1) = NaN;
assertWriterRejects( ...
    invalidSummary, config, publishClaim, testAuthorization);
invalidSummary = summary;
invalidSummary.trials.deliveredPayloadBytes(1, 2) = -1;
assertWriterRejects( ...
    invalidSummary, config, publishClaim, testAuthorization);
invalidSummary = summary;
invalidSummary.trials.consensusOspa(1, 2) = NaN;
assertWriterRejects( ...
    invalidSummary, config, publishClaim, testAuthorization);
invalidConfig = config;
invalidConfig.isSmoke = 1;
assertWriterRejects( ...
    summary, invalidConfig, publishClaim, testAuthorization);
invalidSummary = summary;
invalidSummary.trials.attemptedMask{1, 2} = ...
    double(invalidSummary.trials.attemptedMask{1, 2});
assertWriterRejects( ...
    invalidSummary, config, publishClaim, testAuthorization);
invalidSummary = summary;
invalidSummary.trials.posteriorSnapshotCount(1, 2) = 799;
invalidSummary.equivalence.snapshotCount(2) = ...
    invalidSummary.equivalence.snapshotCount(2) - 1;
assertWriterRejects( ...
    invalidSummary, config, publishClaim, testAuthorization);
invalidSummary = summary;
invalidSummary.arms(2).triggerConfig.hiddenConfound = 1;
assertWriterRejects( ...
    invalidSummary, config, publishClaim, testAuthorization);

[reportPath, csvPath, summaryPath] = ...
    writeFusionSufficientEvidence( ...
        summary, config, publishClaim, testAuthorization);
publishFusionSufficientPublishedReceipt( ...
    plan, config, publishClaim, testAuthorization);
validation = validateFusionSufficientEvidence( ...
    summaryPath, csvPath, reportPath, testAuthorization);
assert(validation.valid);
assert(validation.numberOfTrials == 5);
reportText = fileread(reportPath);
assert(isempty(strfind(reportText, '/Users/'))); %#ok<STREMP>
assert(~isempty(strfind(reportText, ...
    'RUN/GA/TEST_FUSION_SUFFICIENT_EVIDENCE_N5.mat'))); %#ok<STREMP>
assert(~isempty(strfind(reportText, 'TEST-ONLY'))); %#ok<STREMP>
assert(~isempty(strfind(reportText, 'test_only=1'))); %#ok<STREMP>
assert(exist(plan.publishedReceiptPath, 'file') == 2);
assertThrows(@() validateFusionSufficientEvidence( ...
    summaryPath, csvPath, reportPath));
assertThrows(@() writeFusionSufficientEvidence( ...
    summary, config, publishClaim));
assertThrows(@() writeFusionSufficientEvidence( ...
    summary, config, publishClaim, testAuthorization));

corruptCsvPath = fullfile(outputDirectory, 'corrupted.csv');
corruptText = fileread(csvPath);
corruptText = strrep(corruptText, sprintf('\n1001,'), ...
    sprintf('\n9999,'));
fid = fopen(corruptCsvPath, 'w');
assert(fid >= 0);
fileCleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s', corruptText);
clear fileCleanup;
assertThrows(@() validateFusionSufficientEvidence( ...
    summaryPath, corruptCsvPath, reportPath, testAuthorization));

corruptReportPath = fullfile(outputDirectory, 'corrupted.md');
corruptReportText = strrep(reportText, '**60.000000%**', ...
    '**61.000000%**');
assert(~strcmp(corruptReportText, reportText));
writeTestText(corruptReportPath, corruptReportText);
assertThrows(@() validateFusionSufficientEvidence( ...
    summaryPath, csvPath, corruptReportPath, testAuthorization));
testAtomicRollback(outputDirectory);
validateTrackedConfirmatoryEvidence();
fprintf('test_icassp_moment_exchange_evidence passed\n');
end

function validateTrackedConfirmatoryEvidence()
projectRoot = fileparts(fileparts(mfilename('fullpath')));
stem = 'GA_FUSION_SUFFICIENT_MOMENT_EXCHANGE_N50_SEEDS82_131';
summaryPath = fullfile(projectRoot, 'RUN', 'GA', [stem, '.mat']);
csvPath = fullfile(projectRoot, 'RUN', 'GA', [stem, '.csv']);
reportPath = fullfile(projectRoot, 'RUN', 'GA', [stem, '.md']);
assert(exist(summaryPath, 'file') == 2, ...
    'Tracked confirmatory MAT evidence is missing.');
validation = validateFusionSufficientEvidence( ...
    summaryPath, csvPath, reportPath);
assert(validation.valid);
assert(validation.numberOfTrials == 50);
assert(strcmp(validation.gitCommit, ...
    '7974f10179a8973875bec9f301b8a5f84477d860'));
assert(~isempty(regexp(validation.validationGitHead, ...
    '^[0-9a-f]{40}$', 'once')));
end

function summary = makeSyntheticSummary(config)
n = config.numberOfTrials;
summary = struct();
summary.armNames = config.armSelection;
summary.numberOfTrials = n;
summary.trialSeeds = config.firstSeed:config.lastSeed;
summary.scenarioConfig = struct( ...
    'simulationLength', 100, 'numberOfSensors', 8);
trigger = struct( ...
    'capturePosteriorSnapshots', true, ...
    'linkGateEnabled', false, ...
    'forceInitialHeavy', false, ...
    'forceLabelChangeHeavy', false, ...
    'forceStaleHeavy', false, ...
    'useStaleNeighborCache', false, ...
    'labelHeartbeatEnabled', false, ...
    'mixedPayloadEnabled', false, ...
    'mixedPayloadLightForAllActiveLabels', false, ...
    'dynamicTopologyEnabled', false, ...
    'modeAwareFusionWeights', false, ...
    'lightCovarianceInflationEnabled', false, ...
    'lightFusionWeightFactor', 1, ...
    'heavyFusionWeightFactor', 1);
fullTrigger = trigger;
fullTrigger.eventPolicy = 'alwaysHeavy';
momentTrigger = trigger;
momentTrigger.eventPolicy = 'alwaysLight';
summary.arms = [ ...
    struct('name', config.armSelection{1}, 'purpose', 'synthetic', ...
        'triggerConfig', fullTrigger), ...
    struct('name', config.armSelection{2}, 'purpose', 'synthetic', ...
        'triggerConfig', momentTrigger)];

summary.trials.localEOspa = zeros(n, 8, 2);
summary.trials.consensusOspa = zeros(n, 2);
summary.trials.consensusPosition = zeros(n, 2);
summary.trials.consensusCardinality = zeros(n, 2);
for trialIdx = 1:n
    localValue = 1 + trialIdx / 100;
    summary.trials.localEOspa(trialIdx, :, :) = localValue;
    summary.trials.consensusOspa(trialIdx, :) = 2 + trialIdx / 100;
    summary.trials.consensusPosition(trialIdx, :) = ...
        0.5 + trialIdx / 100;
    summary.trials.consensusCardinality(trialIdx, :) = ...
        0.25 + trialIdx / 100;
end
fullAttempted = (1000:1000:5000)';
momentAttempted = (400:400:2000)';
summary.trials.attemptedPayloadBytes = ...
    [fullAttempted, momentAttempted];
summary.trials.deliveredPayloadBytes = ...
    [0.8 * fullAttempted, 0.8 * momentAttempted];
summary.trials.attemptedMask = cell(n, 2);
summary.trials.deliveredMask = cell(n, 2);
for trialIdx = 1:n
    attempted = logical(mod((1:(8 * 8 * 100)) + trialIdx, 2));
    attempted = reshape(attempted, [8, 8, 100]);
    delivered = attempted;
    delivered(1) = false;
    summary.trials.attemptedMask{trialIdx, 1} = attempted;
    summary.trials.attemptedMask{trialIdx, 2} = attempted;
    summary.trials.deliveredMask{trialIdx, 1} = delivered;
    summary.trials.deliveredMask{trialIdx, 2} = delivered;
end
summary.trials.posteriorMissingSnapshotCount = zeros(n, 2);
summary.trials.posteriorLabelSetMismatchCount = zeros(n, 2);
summary.trials.posteriorMissingLabelCount = zeros(n, 2);
summary.trials.posteriorComparisonCount = 10 * ones(n, 2);
summary.trials.posteriorSnapshotCount = 800 * ones(n, 2);
summary.trials.posteriorMaxAbsR = zeros(n, 2);
summary.trials.posteriorMaxAbsMu = zeros(n, 2);
summary.trials.posteriorMaxAbsSigma = zeros(n, 2);
summary.trials.posteriorExactMatch = true(n, 2);
summary.equivalence = struct( ...
    'captured', true, ...
    'baselineArm', config.armSelection{1}, ...
    'missingSnapshotCount', [0, 0], ...
    'labelSetMismatchCount', [0, 0], ...
    'missingLabelCount', [0, 0], ...
    'comparisonCount', [10 * n, 10 * n], ...
    'snapshotCount', [800 * n, 800 * n], ...
    'maxAbsR', [0, 0], ...
    'maxAbsMu', [0, 0], ...
    'maxAbsSigma', [0, 0], ...
    'exactMatch', [true, true]);
end

function [summary, plan] = materializeSyntheticBatch( ...
    synthetic, config, testAuthorization)
plan = buildFusionSufficientParallelPlan(config);
acquireFusionSufficientBatchOwnership(plan, config, testAuthorization);
for trialIdx = 1:config.numberOfTrials
    seed = config.firstSeed + trialIdx - 1;
    single = sliceSingleTrial(synthetic, trialIdx, seed);
    workerResult = struct( ...
        'workerSchema', config.workerSchema, ...
        'evidenceSchema', config.evidenceSchema, ...
        'gitCommit', config.gitCommit, ...
        'requiredSourcesSha256', config.requiredSourcesSha256, ...
        'configSha256', config.configSha256, ...
        'summarySha256', hashFusionSufficientValue(single), ...
        'octaveVersion', config.octaveVersion, ...
        'seed', seed, ...
        'exactGatePassed', true, ...
        'config', config, ...
        'summary', single); %#ok<NASGU>
    save(plan.workerMatPaths{trialIdx}, 'workerResult', '-v7');
    writeTestText(plan.workerLogPaths{trialIdx}, ...
        sprintf('synthetic seed %d\n', seed));
end
[completionToken, launcherCapability] = ...
    writeSyntheticLauncherSeal(plan, config);
publishFusionSufficientBatchSuccessReceipt( ...
    plan.batchPlanPath, completionToken, launcherCapability, ...
    testAuthorization);
[summary, ~] = assembleFusionSufficientMomentExchangeWorkers( ...
    plan.workerDirectory, config, struct(), testAuthorization);
end

function [completionToken, launcherCapability] = ...
    writeSyntheticLauncherSeal(plan, config)
launcherCapability = strtrim(fileread(plan.launcherCapabilityPath));
capabilitySha256 = fusionSufficientSha256Text(launcherCapability);
delete(plan.launcherCapabilityPath);
writeTestText(plan.lifecycleClaimPath, sprintf([ ...
    'claim_schema=fusion-sufficient-launch-claim-v2\n', ...
    'batch_identity=%s\n', ...
    'launcher_capability_sha256=%s\n'], ...
    config.batchIdentity, capabilitySha256));
seedParts = arrayfun(@(value) sprintf('%d', value), ...
    plan.workerSeeds, 'UniformOutput', false);
parts = {sprintf([ ...
    'exit_schema=fusion-sufficient-worker-exits-v2\n', ...
    'batch_identity=%s\n', ...
    'launcher_capability_sha256=%s\n', ...
    'ordered_seeds=%s\n'], ...
    config.batchIdentity, capabilitySha256, strjoin(seedParts, ','))};
for seedIdx = 1:numel(plan.workerSeeds)
    parts{end + 1} = sprintf('worker_%06d_exit=0\n', ...
        plan.workerSeeds(seedIdx)); %#ok<AGROW>
end
writeTestText(plan.exitLedgerPath, [parts{:}]);
completionToken = fusionSufficientSha256Text( ...
    ['completion-', config.batchIdentity]);
writeTestText(plan.completionAuthorizationPath, sprintf([ ...
    'completion_schema=fusion-sufficient-completion-v2\n', ...
    'batch_identity=%s\n', ...
    'launcher_capability_sha256=%s\n', ...
    'completion_token_sha256=%s\n'], ...
    config.batchIdentity, capabilitySha256, ...
    fusionSufficientSha256Text(completionToken)));
end

function single = sliceSingleTrial(summary, trialIdx, seed)
single = summary;
single.numberOfTrials = 1;
single.trialSeeds = seed;
single.trials.localEOspa = ...
    summary.trials.localEOspa(trialIdx, :, :);
matrixFields = {'consensusOspa', 'consensusPosition', ...
    'consensusCardinality', 'attemptedPayloadBytes', ...
    'deliveredPayloadBytes', 'posteriorMissingSnapshotCount', ...
    'posteriorLabelSetMismatchCount', 'posteriorMissingLabelCount', ...
    'posteriorComparisonCount', 'posteriorSnapshotCount', ...
    'posteriorMaxAbsR', 'posteriorMaxAbsMu', ...
    'posteriorMaxAbsSigma', 'posteriorExactMatch'};
for fieldIdx = 1:numel(matrixFields)
    name = matrixFields{fieldIdx};
    single.trials.(name) = summary.trials.(name)(trialIdx, :);
end
single.trials.attemptedMask = ...
    summary.trials.attemptedMask(trialIdx, :);
single.trials.deliveredMask = ...
    summary.trials.deliveredMask(trialIdx, :);
single.equivalence = struct( ...
    'captured', true, ...
    'baselineArm', summary.armNames{1}, ...
    'missingSnapshotCount', ...
        single.trials.posteriorMissingSnapshotCount, ...
    'labelSetMismatchCount', ...
        single.trials.posteriorLabelSetMismatchCount, ...
    'missingLabelCount', single.trials.posteriorMissingLabelCount, ...
    'comparisonCount', single.trials.posteriorComparisonCount, ...
    'snapshotCount', single.trials.posteriorSnapshotCount, ...
    'maxAbsR', single.trials.posteriorMaxAbsR, ...
    'maxAbsMu', single.trials.posteriorMaxAbsMu, ...
    'maxAbsSigma', single.trials.posteriorMaxAbsSigma, ...
    'exactMatch', single.trials.posteriorExactMatch);
end

function assertWriterRejects( ...
    summary, config, publishClaim, testAuthorization)
assertThrows(@() writeFusionSufficientEvidence( ...
    summary, config, publishClaim, testAuthorization));
plan = buildFusionSufficientParallelPlan(config);
for pathIdx = 1:numel(plan.finalPaths)
    assert(exist(plan.finalPaths{pathIdx}, 'file') ~= 2);
end
end

function writeTestText(path, text)
fid = fopen(path, 'w');
assert(fid >= 0);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
count = fwrite(fid, uint8(text), 'uint8');
assert(count == numel(uint8(text)));
end

function testAtomicRollback(parentDirectory)
directory = fullfile(parentDirectory, 'atomic-rollback');
[ok, message] = mkdir(directory);
assert(ok, message);
temporaryPaths = { ...
    fullfile(directory, 'one.tmp'), ...
    fullfile(directory, 'two.tmp'), ...
    fullfile(directory, 'three.tmp')};
for pathIdx = 1:numel(temporaryPaths)
    writeTestText(temporaryPaths{pathIdx}, sprintf('%d', pathIdx));
end
finalPaths = { ...
    fullfile(directory, 'one.final'), ...
    fullfile(directory, 'two.final'), ...
    fullfile(directory, 'three.final')};
writeTestText(finalPaths{2}, 'preexisting');
assertThrows(@() publishFusionSufficientEvidenceBundle( ...
    temporaryPaths, finalPaths, @() true));
assert(exist(finalPaths{1}, 'file') ~= 2);
assert(exist(finalPaths{2}, 'file') == 2);
assert(strcmp(fileread(finalPaths{2}), 'preexisting'));
assert(exist(finalPaths{3}, 'file') ~= 2);

temporaryPaths = { ...
    fullfile(directory, 'four.tmp'), ...
    fullfile(directory, 'five.tmp'), ...
    fullfile(directory, 'six.tmp')};
finalPaths = { ...
    fullfile(directory, 'four.final'), ...
    fullfile(directory, 'five.final'), ...
    fullfile(directory, 'six.final')};
for pathIdx = 1:numel(temporaryPaths)
    writeTestText(temporaryPaths{pathIdx}, sprintf('%d', pathIdx));
end
assertThrows(@() publishFusionSufficientEvidenceBundle( ...
    temporaryPaths, finalPaths, @() failFinalValidation()));
for pathIdx = 1:numel(finalPaths)
    assert(exist(finalPaths{pathIdx}, 'file') ~= 2);
end

temporaryPaths = { ...
    fullfile(directory, 'seven.tmp'), ...
    fullfile(directory, 'eight.tmp'), ...
    fullfile(directory, 'nine.tmp')};
finalPaths = { ...
    fullfile(directory, 'seven.final'), ...
    fullfile(directory, 'eight.final'), ...
    fullfile(directory, 'nine.final')};
for pathIdx = 1:numel(temporaryPaths)
    writeTestText(temporaryPaths{pathIdx}, sprintf('%d', pathIdx));
end
assertThrows(@() publishFusionSufficientEvidenceBundle( ...
    temporaryPaths, finalPaths, ...
    @() replacePublishedIdentityThenFail(finalPaths{1})));
assert(exist(finalPaths{1}, 'file') == 2);
assert(strcmp(fileread(finalPaths{1}), 'foreign-owner'));
assert(exist(finalPaths{2}, 'file') ~= 2);
assert(exist(finalPaths{3}, 'file') ~= 2);
end

function failFinalValidation()
error('Synthetic final validation failure.');
end

function replacePublishedIdentityThenFail(path)
delete(path);
writeTestText(path, 'foreign-owner');
error('Synthetic identity replacement failure.');
end

function assertThrows(functionHandle)
didThrow = false;
try
    functionHandle();
catch
    didThrow = true;
end
assert(didThrow);
end

function removeTestDirectory(path)
if exist(path, 'dir') == 7
    rmdir(path, 's');
end
end
