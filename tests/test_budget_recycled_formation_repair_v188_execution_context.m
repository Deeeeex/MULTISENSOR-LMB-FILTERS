function test_budget_recycled_formation_repair_v188_execution_context()
% Focused authorization test for the recursive V188 extension of V99.

baseProtocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
repairProtocol = getBudgetRecycledFormationRepairV188Protocol();
currentTime = 104;
plan = struct( ...
    'times', currentTime, ...
    'referenceAttemptedBytes', 1570016, ...
    'idealDeliveryTeacherMode', true, ...
    'maximumActions', 1);
context = buildBudgetRecycledFormationRepairV188ExecutionContext( ...
    'm24-formation-fov', 211, currentTime, ...
    'v99-online-positive-net-f1-f3-f4', true, true, plan);
assert(isBudgetRecycledFormationRepairV188ExecutionContext(context));
assert(strcmp(context.protocolId, repairProtocol.id));
assert(strcmp(context.policyName, baseProtocol.outcomePolicyName));

model = struct();
model.numberOfSensors = 24;
model.dynamicTopologyScenario = struct( ...
    'presetName', 'm24-formation-fov', ...
    'seed', 211, ...
    'config', struct('formationCount', 4));
config = struct( ...
    'topologyPolicyName', baseProtocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', true, ...
    'receiverSafeLabelFusionMode', ...
        'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', currentTime + (0:2), ...
    'receiverSafeFormationConditionedSchedule', {cell(1, 3)}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only', ...
    'budgetRecycledFormationRepairEnabled', true, ...
    'budgetRecycledFormationRepairTimes', plan.times, ...
    'budgetRecycledFormationRepairReferenceAttemptedBytes', ...
        plan.referenceAttemptedBytes, ...
    'budgetRecycledFormationRepairIdealDeliveryTeacherMode', ...
        plan.idealDeliveryTeacherMode, ...
    'budgetRecycledFormationRepairMaximumActions', ...
        plan.maximumActions, ...
    'formationCoordinatedPosteriorRepairEnabled', false);
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', currentTime + 2, ...
    'sensorTrajectoryTimeCounts', ...
        repmat(currentTime + 2, 1, model.numberOfSensors), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, context, request);
assert(strcmp(authorization.mode, ...
    'budget-recycled-formation-repair-v188-development'));
assert(strcmp(authorization.protocolId, repairProtocol.id));
assert(~authorization.groundTruthAccessAuthorized);
assert(~authorization.futureOutcomeAccessAuthorized);
assert(~authorization.validationClaimAllowed);

fprintf([ ...
    'test_budget_recycled_formation_repair_v188_execution_context ', ...
    'passed\n']);
end
