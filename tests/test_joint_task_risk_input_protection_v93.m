function test_joint_task_risk_input_protection_v93()
% TEST_JOINTTASKRISKINPUTPROTECTIONV93 Focused protocol/score contract.

protocol = getJointTaskRiskInputProtectionV93Protocol();
assert(strcmp(protocol.referenceMode, 'current-physical-tree'));
assert(protocol.maximumExactFormationCount == 6);
assert(protocol.directBestSubsetAuditRequired);
assert(protocol.minimumMedianPositiveTaskRiskGainPercent == 0.25);
assert(protocol.minimumPeakSafeTaskRiskGainPercent == 1.0);
assert(~protocol.routeExecutionAuthorized);

model = struct('ospaParameters', struct('eC', 5));
reference = makeSummary(0.50, 9 * eye(2));
candidate = makeSummary(0.90, eye(2));
referenceDistributions = { ...
    makeDistribution(reference), ...
    makeDistribution(reference)};
candidateDistributions = { ...
    makeDistribution(candidate), ...
    makeDistribution(candidate)};
referenceNetworkDetails = struct( ...
    'receiverDistributions', {referenceDistributions});
[referenceRisk, referenceRiskDetails] = ...
    computeExpectedLmbPosteriorTaskRiskV92( ...
        referenceNetworkDetails, [1, 2], model, ...
        protocol.riskOptions);
referenceScore = struct( ...
    'taskRisk', referenceRisk, ...
    'taskRiskDetails', referenceRiskDetails, ...
    'networkDetails', referenceNetworkDetails);
score = scoreComposedTaskRiskInputProtectionV93( ...
    referenceScore, candidateDistributions, [1, 2], ...
    model, protocol);
assert(score.taskRiskGainPercent > 0);
assert(score.rowCompositionExactForOneRoundRisk);
assert(~score.truthUsed);
assert(~score.eospaEqualityClaimed);
fprintf('PASS: V93 joint task-risk input-protection contract\n');
end

function distribution = makeDistribution(summary)
distribution = struct('probability', 1, 'summary', {{summary}});
end

function summary = makeSummary(existence, covariance)
summary = struct( ...
    'labels', [1; 1], ...
    'existence', existence, ...
    'positionMean', zeros(2, 1), ...
    'positionCovariance', reshape(covariance, 2, 2, 1));
end
