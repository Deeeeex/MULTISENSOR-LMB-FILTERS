function test_online_positive_net_formation_release_v191()
% A V191 release must restore full payload without changing V99 selection.

baseProtocol = getOnlinePositiveNetAddressablePayloadV99Protocol();
releaseProtocol = getOnlinePositiveNetFormationReleaseV191Protocol();
currentTime = 104;
plan = struct( ...
    'contractVersion', ...
        'online-positive-net-formation-release-v191-plan-v1', ...
    'times', currentTime, ...
    'formationIdsByTime', {{4}}, ...
    'teacherMode', true);
assert(isValidOnlinePositiveNetFormationReleaseV191Plan(plan, 4));

[effective, details] = applyOnlinePositiveNetFormationReleaseV191( ...
    [1, 3, 4], currentTime, 4, plan);
assert(isequal(effective, [1, 3]));
assert(isequal(details.appliedFormationIds, 4));
assert(details.releaseApplied);
assert(~details.truthUsed && ~details.futureInformationUsed);

[laterEffective, laterDetails] = ...
    applyOnlinePositiveNetFormationReleaseV191( ...
        [1, 3, 4], currentTime + 1, 4, plan);
assert(isequal(laterEffective, [1, 3, 4]));
assert(isempty(laterDetails.appliedFormationIds));

invalidPlan = plan;
invalidPlan.formationIdsByTime = {[3, 4]};
assert(~isValidOnlinePositiveNetFormationReleaseV191Plan( ...
    invalidPlan, 4));

context = buildOnlinePositiveNetFormationReleaseV191ExecutionContext( ...
    'm24-formation-fov', 211, currentTime, ...
    'v99-online-positive-net-f1-f3-f4', true, true, plan);
assert(isOnlinePositiveNetFormationReleaseV191ExecutionContext(context));
assert(strcmp(context.protocolId, releaseProtocol.id));
assert(strcmp(context.policyName, baseProtocol.outcomePolicyName));

model = struct();
model.numberOfSensors = 24;
model.dynamicTopologyScenario = struct( ...
    'presetName', 'm24-formation-fov', ...
    'seed', 211, ...
    'config', struct('formationCount', 4));
config = struct( ...
    'topologyPolicyName', baseProtocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', true, ...
    'receiverSafeLabelFusionMode', ...
        'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', currentTime + (0:2), ...
    'receiverSafeFormationConditionedSchedule', {cell(1, 3)}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only', ...
    'onlinePositiveNetFormationReleasePlan', plan, ...
    'budgetRecycledFormationRepairEnabled', false);
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', currentTime + 2, ...
    'sensorTrajectoryTimeCounts', ...
        repmat(currentTime + 2, 1, model.numberOfSensors), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, context, request);
assert(strcmp(authorization.mode, ...
    'online-positive-net-formation-release-v191-development'));
assert(strcmp(authorization.protocolId, releaseProtocol.id));
assert(~authorization.groundTruthAccessAuthorized);
assert(~authorization.futureOutcomeAccessAuthorized);
assert(~authorization.validationClaimAllowed);

fprintf('test_online_positive_net_formation_release_v191 passed\n');
end
