function test_counterfactual_regret_gate_v133_model()
% TEST_COUNTERFACTUAL_REGRET_GATE_V133_MODEL Shared-scale calibration.

protocol = getCounterfactualRegretGateV133Protocol();
protocol.teacherGate.minimumHarmfulRecall = 0.50;
protocol.teacherGate.maximumFalseSafeRate = 0.60;
protocol.teacherGate.minimumDynamicActionCoverage = 0.10;
protocol.teacherGate.minimumRetainedOracleGainFraction = 0.10;
spec = getCounterfactualRegretGateV133ModelSpec();
featureCount = numel(spec.featureNames);

development = syntheticBundle( ...
    'development', featureCount, 1:24, spec, protocol);
calibration = syntheticBundle( ...
    'calibration', featureCount, 25:48, spec, protocol);
[model, summary] = fitCounterfactualRegretGateV133( ...
    development, calibration, protocol, spec);
assert(strcmp(model.family, spec.family));
assert(model.sharedAcrossScales);
assert(~model.gnnUsed);
assert(summary.optimization.maximumProjectedSignViolation <= 1e-12);
assert(~model.validationClaimAllowed);

featureValues = zeros(1, featureCount);
decision = scoreCounterfactualRegretGateV133Model( ...
    model, spec.featureNames, featureValues);
assert(~decision.truthUsed && ~decision.futureOutcomeUsed);
assert(islogical(decision.actionEnabled));
assert(~isempty(decision.selectedAction));

fprintf('PASS: V133 shared-scale model and calibration contracts\n');
end

function bundle = syntheticBundle( ...
        split, featureCount, indices, spec, protocol)
exampleCount = numel(indices);
X = zeros(exampleCount, featureCount);
signal = linspace(-2, 2, exampleCount)';
X(:, 1) = signal;
X(:, 2) = 0.5 * signal;
X(:, 3) = max(signal, 0);
X(:, 4) = -signal;
X(:, 5:end) = 0.05 * reshape(sin( ...
    (1:exampleCount * (featureCount - 4)) / 3), ...
    exampleCount, featureCount - 4);
y = signal > 0;
scaleName = repmat({'M24'}, exampleCount, 1);
scaleName(2:2:end) = {'X36'};
trajectoryKey = cell(exampleCount, 1);
for idx = 1:exampleCount
    trajectoryKey{idx} = sprintf('%s-traj-%d', split, indices(idx));
end
bundle = struct( ...
    'contractVersion', ...
        'counterfactual-regret-gate-v133-model-dataset-v1', ...
    'protocolId', protocol.id, ...
    'evidenceSplit', split, ...
    'modelFeatureNames', {spec.featureNames}, ...
    'modelFeatureContractSha256', spec.featureContractSha256, ...
    'X', X, ...
    'y', y, ...
    'actionGainPercent', 2 + max(-signal, 0), ...
    'scaleName', {scaleName}, ...
    'trajectoryKey', {trajectoryKey}, ...
    'sampleWeight', ones(exampleCount, 1) / exampleCount, ...
    'exampleCount', exampleCount, ...
    'trajectoryCount', exampleCount, ...
    'truthUsedAsFeature', false, ...
    'futureOutcomeUsedAsFeature', false, ...
    'seedIdentifierUsedAsFeature', false, ...
    'absoluteTimeUsedAsFeature', false, ...
    'fixedFormationIdentifierUsedAsFeature', false);
end
