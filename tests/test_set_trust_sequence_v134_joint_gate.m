function test_set_trust_sequence_v134_joint_gate()
% TEST_SET_TRUST_SEQUENCE_V134_JOINT_GATE Two-scale fail-closed reducer.

protocol = getSetTrustSequenceV134Protocol();
commit = 'synthetic-clean-commit';
pilotCells = cell(1, numel(protocol.scaleCases));
for caseIdx = 1:numel(protocol.scaleCases)
    pilotCells{caseIdx} = makePilot(protocol.scaleCases(caseIdx), ...
        protocol, commit, true);
end
pilots = [pilotCells{:}];
joint = buildSetTrustSequenceV134JointGate( ...
    pilots, protocol, commit);
assert(joint.jointCrossScaleGatePassed);
assert(joint.onPolicyTeacherDevelopmentAuthorized);
assert(~joint.gnnAuthorized);
assert(~joint.validationClaimAllowed);
assert(all(joint.scaleGatePassed));

failed = pilots;
failed(2) = makePilot(protocol.scaleCases(2), ...
    protocol, commit, false);
joint = buildSetTrustSequenceV134JointGate( ...
    failed, protocol, commit);
assert(~joint.jointCrossScaleGatePassed);
assert(~joint.onPolicyTeacherDevelopmentAuthorized);
assert(isequal(joint.scaleGatePassed, [true, false]));

drifted = pilots;
drifted(1).passingRecordIndices = zeros(1, 0);
assertErrorId(@() buildSetTrustSequenceV134JointGate( ...
    drifted, protocol, commit), 'V134JointGate:StoredGateDrift');

fprintf('PASS: V134 joint M24/X36 headroom gate tests\n');
end

function pilot = makePilot(caseInfo, protocol, commit, passes)
metrics = makeMetrics(protocol, passes);
record = struct( ...
    'actionIndex', 3, ...
    'actionName', 'prefix-01-staggered-binary-reentry', ...
    'scheduleKind', 'staggered-binary-reentry', ...
    'formationSet', 1, ...
    'metrics', metrics, ...
    'elapsedSeconds', 1, ...
    'checkpointPath', 'synthetic');
passing = find(metrics.passesPreLearningGate);
pilot = struct( ...
    'contractVersion', ...
        'v134-binary-admission-pilot-result-v3', ...
    'protocolId', protocol.id, ...
    'scaleName', caseInfo.scaleName, ...
    'presetName', caseInfo.presetName, ...
    'seed', protocol.pilotSeed, ...
    'anchorTime', resolveSetTrustSequenceV134PilotAnchor( ...
        caseInfo, protocol), ...
    'referenceCarrierMode', 'fixed-clockwise', ...
    'rankedFormationIds', 1:caseInfo.expectedFormationCount, ...
    'evaluatedActionIndices', 3, ...
    'records', record, ...
    'passingRecordIndices', passing, ...
    'bestRobustRecordIndex', double(passes), ...
    'bestRobustActionIndex', 3 * double(passes), ...
    'pilotScaleHeadroomObserved', logical(passes), ...
    'jointCrossScaleGateClaimed', false, ...
    'generationGitCommit', commit, ...
    'developmentEvidenceOnly', true, ...
    'validationClaimAllowed', false, ...
    'reportingDisposition', 'repository-only');
end

function metrics = makeMetrics(protocol, passes)
gate = protocol.preLearningGate;
intervention = 0.06;
if ~passes
    intervention = 0.04;
end
certificate = struct( ...
    'candidateSquaredContractionFactor', 0.80, ...
    'maximumAllowedSquaredContractionFactor', ...
        gate.maximumRecoverySquaredContractionFactor, ...
    'strictMeanSquareContractionCertified', true, ...
    'targetContractionCertified', true, ...
    'referenceAndCandidateTailIdentical', true, ...
    'passesRecoveryGate', true);
metrics = struct( ...
    'interventionGainFraction', intervention, ...
    'meanGainFraction', 0.01, ...
    'matureGainFraction', 0.01, ...
    'minimumInterventionSensorGainFraction', 0.005, ...
    'minimumSensorGainFraction', 0.005, ...
    'minimumMatureSensorGainFraction', 0.005, ...
    'minimumInterventionFormationGainFraction', 0.005, ...
    'minimumFormationGainFraction', 0.005, ...
    'minimumMatureFormationGainFraction', 0.005, ...
    'attemptedByteSavingFraction', 0.02, ...
    'recoverySquaredContractionFactor', 0.80, ...
    'actionGateEligible', true, ...
    'actionDiagnosticOnly', false, ...
    'actionReturnsToFullTrust', true, ...
    'passesRecoveryCertificateGate', true, ...
    'passesPreLearningGate', logical(passes), ...
    'recoveryCertificate', certificate);
end

function assertErrorId(callable, expectedId)
failed = false;
try
    callable();
catch errorInfo
    failed = strcmp(errorInfo.identifier, expectedId);
end
assert(failed);
end
