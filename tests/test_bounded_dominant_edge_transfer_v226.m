function test_bounded_dominant_edge_transfer_v226()
% TEST_BOUNDEDDOMINANTEDGETRANSFERV226 Focused V226 semantics.

testTwoSidedExistenceEnvelope();
testMaximumSafeFractionSelection();
testBoundedWeightTransfer();

protocol = getBoundedDominantEdgeTransferV226Protocol();
assert(protocol.totalLabelWeightPreserved);
assert(~protocol.selfInputReplacementAllowed);
assert(~protocol.transferFractionReducesPayloadCharge);
fprintf('test_bounded_dominant_edge_transfer_v226 passed\n');
end

function testTwoSidedExistenceEnvelope()
referenceExistence = 0.60;
options = struct( ...
    'minimumMapExistence', 0.50, ...
    'maximumReferenceLogOddsDrop', 0.25, ...
    'maximumReferenceLogOddsIncrease', 0.25, ...
    'identityTolerance', 1e-12);

[allowedHigh, high] = ...
    projectLabelKlaExistenceRetentionByEtaV223( ...
        0.90, 1, 0, referenceExistence, options);
assert(~allowedHigh);
assert(high.lowerBoundAllowed);
assert(~high.upperBoundAllowed);
assert(high.upperLogOddsMargin < 0);

[allowedLow, low] = ...
    projectLabelKlaExistenceRetentionByEtaV223( ...
        0.20, 1, 0, referenceExistence, options);
assert(~allowedLow);
assert(~low.lowerBoundAllowed);

[allowedMiddle, middle] = ...
    projectLabelKlaExistenceRetentionByEtaV223( ...
        0.62, 1, 0, referenceExistence, options);
assert(allowedMiddle);
assert(middle.lowerBoundAllowed && middle.upperBoundAllowed);

% Omitting the upper envelope preserves the one-sided V223 behavior.
[legacyAllowed, legacy] = ...
    projectLabelKlaExistenceRetentionByEtaV223( ...
        0.90, 1, 0, referenceExistence, rmfield( ...
            options, 'maximumReferenceLogOddsIncrease'));
assert(legacyAllowed);
assert(isinf(legacy.maximumAllowedFusedLogOdds));
end

function testMaximumSafeFractionSelection()
fractions = [0.25, 1.00, 0.50, 0.10];
allowed = [true, false, true, false];
[selectedFraction, selectedIndex] = ...
    selectMaximumAllowedTransferFractionV226(fractions, allowed);
assert(abs(selectedFraction - 0.50) <= 1e-12);
assert(selectedIndex == 3);

% Non-monotone decisions remain valid because the whole grid is evaluated.
[selectedFraction, selectedIndex] = ...
    selectMaximumAllowedTransferFractionV226( ...
        [0.50, 1.00, 0.25], [false, true, true]);
assert(abs(selectedFraction - 1.00) <= 1e-12);
assert(selectedIndex == 2);

[selectedFraction, selectedIndex] = ...
    selectMaximumAllowedTransferFractionV226( ...
        [1.00, 0.50], [false, false]);
assert(selectedFraction == 0 && selectedIndex == 0);
end

function testBoundedWeightTransfer()
model = buildModel();
selfObject = buildObject(0.70);
ordinaryNeighborObject = buildObject(0.20);
donorObject = buildObject(0.90);
inputs = {selfObject, ordinaryNeighborObject, donorObject};
weights = [0.50, 0.50, 0];
details = struct( ...
    'sourceIndices', [1, 2, 3], ...
    'isSelf', [true, false, false], ...
    'isStale', [false, false, false], ...
    'currentTime', 1, ...
    'eventType', [2, 2, 2]);
config = buildMixtureAwareKlaReferenceConfig(struct( ...
    'missingLabelFusionMode', 'support-renormalized', ...
    'captureLabelKlaDiagnosticsEnabled', true));

fraction = 0.25;
boundedDetails = details;
boundedDetails.labelSpecificWeightOverrides = struct( ...
    'label', [1; 1], ...
    'sourceInputIndex', 3, ...
    'mode', 'bounded-dominant-nonself-transfer', ...
    'replacedInputIndex', 2, ...
    'transferFraction', fraction);
[boundedResult, boundedDiagnostics] = fuseLmbPosteriorsByLabel( ...
    inputs, weights, model, weights, boundedDetails, config);
expectedWeights = [0.50, 0.375, 0.125];
record = boundedDiagnostics.labelKlaRecords(1);
assert(max(abs(record.activeExistenceWeights - expectedWeights)) <= 1e-12);
assert(abs(sum(record.activeExistenceWeights) - 1) <= 1e-12);
assert(abs(record.activeExistenceWeights(1) - weights(1)) <= 1e-12);
expectedLogOdds = sum(expectedWeights .* ...
    probabilityLogOdds([0.70, 0.20, 0.90]));
assert(abs(probabilityLogOdds(boundedResult.r) - expectedLogOdds) <= 1e-8);

boundedFullDetails = boundedDetails;
boundedFullDetails.labelSpecificWeightOverrides.transferFraction = 1;
boundedFullResult = fuseLmbPosteriorsByLabel( ...
    inputs, weights, model, weights, boundedFullDetails, config);
legacyFullDetails = details;
legacyFullDetails.labelSpecificWeightOverrides = struct( ...
    'label', [1; 1], ...
    'sourceInputIndex', 3, ...
    'mode', 'dominant-nonself-transfer', ...
    'replacedInputIndex', 2);
legacyFullResult = fuseLmbPosteriorsByLabel( ...
    inputs, weights, model, weights, legacyFullDetails, config);
assert(abs(boundedFullResult.r - legacyFullResult.r) <= 1e-10);
end

function values = probabilityLogOdds(probabilities)
values = log(probabilities) - log(1 - probabilities);
end

