function test_hierarchical_formation_repair_candidate_bank_v190()
% V190 must retain multiple causal labels before the diverse Top-K stage.

sensorCount = 4;
local = cell(1, sensorCount);
fused = cell(1, sensorCount);
positions = [40, 42, 0, 4];
traces = [5000, 4500, 100, 200];
for sensorIdx = 1:sensorCount
    local{sensorIdx} = summary(positions(sensorIdx), traces(sensorIdx));
    fused{sensorIdx} = summary(positions(sensorIdx), traces(sensorIdx));
end
cache = struct( ...
    'contractVersion', 'formation-repair-light-synopsis-cache-v188-v1', ...
    'currentTime', 1, ...
    'sensorCount', sensorCount, ...
    'positionCutoff', 150, ...
    'localBySensor', {local}, ...
    'fusedBySensor', {fused});
physical = false(sensorCount);
physical(1:2, 3:4) = true;
[candidates, bank] = ...
    enumerateFormationCommonLabelRepairCandidatesV190( ...
        cache, physical, [1, 1, 2, 2], struct());
assert(numel(candidates) == 2);
assert(all([candidates.formationId] == 1));
assert(isequal(sort([candidates.sourceId]), [3, 4]));
assert(size(bank.featureMatrix, 2) == 21);
assert(all(isfinite(bank.featureMatrix(:))));
assert(~bank.numericLabelIdentifiersUsedAsFeatures);

[shortlist, selection] = selectDiverseFormationRepairShortlistV190( ...
    candidates, struct('perCriterion', 1, 'maximumPerFormation', 1));
assert(numel(shortlist) == 1);
assert(selection.selectedCandidateCount == 1);
assert(selection.semanticLabelKeysUsedForTieBreakOnly);
assert(~selection.truthUsed);

fprintf('test_hierarchical_formation_repair_candidate_bank_v190 passed\n');
end

function value = summary(positionX, positionTrace)
value = struct( ...
    'labels', [1; 1], ...
    'existence', 0.9, ...
    'positionMean', [positionX; 0], ...
    'positionTrace', positionTrace, ...
    'evidenceQuality', 0.9, ...
    'associationSupport', 0.9, ...
    'observationOpportunity', 0.8, ...
    'bayesRisk', 0.5 * min(0.9, 0.1) + ...
        0.5 * 0.9 * min(positionTrace / 150^2, 1), ...
    'labelCount', 1);
end
