function assertErrorId(callback, expectedIdentifier)
failed = false;
try
    callback();
catch errorInfo
    failed = strcmp(errorInfo.identifier, expectedIdentifier);
end
assert(failed, 'Expected error identifier: %s.', expectedIdentifier);
end
