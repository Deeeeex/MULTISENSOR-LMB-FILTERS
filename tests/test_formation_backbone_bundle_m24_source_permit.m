function testSourceOutputBoundary()
estimates = {struct('objects', 1), struct('objects', 2)};
diagnostics = struct('marker', 7);
sourceAuthorization = struct( ...
    'mode', 'registered-case-permit', ...
    'capability', 'source-posterior-only', ...
    'stateEstimateOutputAuthorized', false);
[boundedEstimates, boundedDiagnostics] = ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        estimates, diagnostics, sourceAuthorization);
assert(isempty(boundedEstimates));
assert(boundedDiagnostics.marker == 7);
assert(boundedDiagnostics.sourceStateEstimateOutputSuppressed);

legacyAuthorization = struct( ...
    'mode', 'legacy-compatible', ...
    'stateEstimateOutputAuthorized', true);
[legacyEstimates, legacyDiagnostics] = ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        estimates, diagnostics, legacyAuthorization);
assert(isequaln(legacyEstimates, estimates));
assert(~legacyDiagnostics.sourceStateEstimateOutputSuppressed);

sceneAuthorization = struct( ...
    'mode', 'registered-scene-outcome', ...
    'capability', 'tracking-outcome-authorized', ...
    'stateEstimateOutputAuthorized', true);
[sceneEstimates, sceneDiagnostics] = ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        estimates, diagnostics, sceneAuthorization);
assert(isequaln(sceneEstimates, estimates));
assert(~sceneDiagnostics.sourceStateEstimateOutputSuppressed);

expanded = sourceAuthorization;
expanded.stateEstimateOutputAuthorized = true;
assertErrorId(@() ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        estimates, diagnostics, expanded), ...
    'FormationBundleSourcePermit:OutputBoundaryDrift');
end

