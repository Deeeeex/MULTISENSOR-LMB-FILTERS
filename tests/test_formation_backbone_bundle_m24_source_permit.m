sceneAuthorization = struct( ...
    'mode', 'registered-scene-outcome', ...
    'capability', 'tracking-outcome-authorized', ...
    'stateEstimateOutputAuthorized', true);
[sceneEstimates, sceneDiagnostics] = ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        estimates, diagnostics, sceneAuthorization);
assert(isequaln(sceneEstimates, estimates));
assert(~sceneDiagnostics.sourceStateEstimateOutputSuppressed);

expanded = sourceAuthorization;
expanded.stateEstimateOutputAuthorized = true;
assertErrorId(@() ...
    applyFormationBackboneBundleM24SourceOutputBoundary( ...
        estimates, diagnostics, expanded), ...
    'FormationBundleSourcePermit:OutputBoundaryDrift');
