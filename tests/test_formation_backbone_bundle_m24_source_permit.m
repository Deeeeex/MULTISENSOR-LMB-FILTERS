function [model, request, context] = buildValidFixture(caseContract)
config = buildDynamicTopologyScenarioConfig(caseContract.presetName);
timeCount = caseContract.sourceWindow(2);
trajectories = cell(1, 24);
for sensorIdx = 1:24
    trajectories{sensorIdx} = zeros(4, timeCount);
end
scenario = struct( ...
    'presetName', caseContract.presetName, ...
    'seed', caseContract.seed, ...
    'config', config);
model = struct( ...
    'numberOfSensors', 24, ...
    'explicitSensorTrajectories', {trajectories}, ...
    'sensorTrajectories', {trajectories}, ...
    'dynamicTopologyScenario', scenario);
if strcmp(caseContract.sceneContractKind, ...
        'formation-fov-multistyle-scene-contract-v5')
    model.dynamicTopologyTrackingOutcomeGate = struct( ...
        'contractVersion', ...
            'dynamic-topology-tracking-outcome-gate-v1', ...
        'required', true, ...
        'sceneContractSha256', caseContract.sceneContractSha256);
end
[triggerConfig, ~] = ...
    buildFormationBackboneBundleM24SourceTriggerConfig( ...
        caseContract.presetName);
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', timeCount, ...
    'sensorTrajectoryTimeCounts', ...
        timeCount * ones(1, 24), ...
    'triggerConfig', triggerConfig, ...
    'inputFingerprint', ...
        computeFormationBackboneBundleM24SourceInputFingerprint( ...
            model, cell(24, timeCount), trajectories, ...
            repmat({1:24}, 1, 24), struct()));
context = ...
    buildFormationBackboneBundleM24SourceExecutionContext( ...
        caseContract.presetName, caseContract.seed);
end

function assertErrorId(callback, expectedIdentifier)
failed = false;
try
    callback();
catch errorInfo
    failed = strcmp(errorInfo.identifier, expectedIdentifier);
end
assert(failed, 'Expected error identifier: %s.', expectedIdentifier);
end
