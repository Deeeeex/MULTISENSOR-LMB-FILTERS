function testExactInputFingerprintSensitivity()
model = struct('numberOfSensors', 24, 'tag', 'registered');
measurements = repmat({{}}, 24, 3);
trajectories = repmat({zeros(4, 3)}, 1, 24);
neighborMap = repmat({1:24}, 1, 24);
commConfig = struct('pDropByEdge', zeros(24, 24, 3), ...
    'linkUniforms', 0.5 * ones(24, 24, 3));
reference = computeFormationBackboneBundleM24SourceInputFingerprint( ...
    model, measurements, trajectories, neighborMap, commConfig);

changedMeasurements = measurements;
changedMeasurements{1, 1} = {ones(2, 1)};
assertFingerprintChanges(reference, model, changedMeasurements, ...
    trajectories, neighborMap, commConfig);
changedTrajectories = trajectories;
changedTrajectories{1}(1, 1) = 999;
assertFingerprintChanges(reference, model, measurements, ...
    changedTrajectories, neighborMap, commConfig);
changedNeighborMap = neighborMap;
changedNeighborMap{1}(end) = [];
assertFingerprintChanges(reference, model, measurements, ...
    trajectories, changedNeighborMap, commConfig);
changedCommConfig = commConfig;
changedCommConfig.linkUniforms(1, 2, 1) = 0.25;
assertFingerprintChanges(reference, model, measurements, ...
    trajectories, neighborMap, changedCommConfig);
changedModel = model;
changedModel.tag = 'drifted';
assertFingerprintChanges(reference, changedModel, measurements, ...
    trajectories, neighborMap, commConfig);
end

function assertFingerprintChanges(reference, model, measurements, ...
        trajectories, neighborMap, commConfig)
changed = computeFormationBackboneBundleM24SourceInputFingerprint( ...
    model, measurements, trajectories, neighborMap, commConfig);
