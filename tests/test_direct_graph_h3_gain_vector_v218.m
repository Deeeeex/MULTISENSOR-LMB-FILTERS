function test_direct_graph_h3_gain_vector_v218()
% TEST_DIRECT_GRAPH_H3_GAIN_VECTOR_V218 Focused target-order regression.

reference = syntheticOutcome(10, 20, 5, 8, ...
    [10, 20, 30, 40], [20, 40, 60, 80], ...
    [15, 35], [30, 70], 40, 80);
candidate = syntheticOutcome(9, 18, 4, 6, ...
    [9, 18, 24, 32], [18, 36, 48, 64], ...
    [13.5, 28], [27, 56], 32, 64);
gains = computeDirectGraphH3GainVectorV218( ...
    reference, candidate, [1, 1, 2, 2], 2);
assert(numel(gains) == 12);
assert(max(abs(gains(1:4) - [10, 10, 20, 25])) < 1e-12);
assert(max(abs(gains(5:8) - [20, 20, 20, 20])) < 1e-12);
assert(max(abs(gains(9:12) - [20, 20, 10, 10])) < 1e-12);
fprintf('test_direct_graph_h3_gain_vector_v218 passed\n');
end

function outcome = syntheticOutcome( ...
        meanEospa, meanRmse, consensus, terminal, ...
        sensorEospa, sensorRmse, formationEospa, formationRmse, ...
        worstEospa, worstRmse)
outcome = struct( ...
    'meanEospa', meanEospa, 'meanRmse', meanRmse, ...
    'consensusOspa', consensus, ...
    'terminalConsensusOspa', terminal, ...
    'sensorMeanEospa', sensorEospa, ...
    'sensorMeanRmse', sensorRmse, ...
    'formationMeanEospa', formationEospa, ...
    'formationMeanRmse', formationRmse, ...
    'worstSensorEospa', worstEospa, ...
    'worstSensorRmse', worstRmse);
end
