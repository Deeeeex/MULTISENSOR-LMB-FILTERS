function test_time_expanded_dual_path_v119()
% TEST_TIME_EXPANDED_DUAL_PATH_V119 Pulse invariants and authorization.

protocol = getTimeExpandedDualPathV119Protocol();
assert(protocol.pulsePageIndex == 5 && protocol.pulseTime == 76);
assert(isequal(protocol.sourceFormationIds, [1, 2, 3, 4]));
assert(isequal(protocol.targetReceiverSensorIds, [33, 34, 34, 34]));
assert(numel(protocol.candidateActionNames) == 8);

[baseAdjacency, baseWeights, baseDetails, physical] = syntheticCarrier();
synthetic = protocol;
synthetic.sourceFormationIds = [1, 2];
synthetic.donorSourceSensorIds = [4, 6];
synthetic.donorReceiverSensorIds = [3, 5];
synthetic.targetReceiverSensorIds = [6, 2];
synthetic.donorOnlyActionNames = {'donor-1', 'donor-2'};
synthetic.dualPathActionNames = {'dual-1', 'dual-2'};
actions = buildTimeExpandedDualPathV119Actions( ...
    baseAdjacency, baseWeights, baseDetails, physical, synthetic);
assert(numel(actions) == 4);
for idx = 1:2:4
    donor = actions(idx);
    dual = actions(idx + 1);
    assert(nnz(donor.adjacency) == nnz(baseAdjacency) - 1);
    assert(nnz(dual.adjacency) == nnz(baseAdjacency));
    assert(dual.details.v119DualPath.networkMessageParityPassed);
    assert(dual.details.v119DualPath.senderMessageParityPassed);
    assert(dual.details.v119DualPath.rowSumPassed);
    assert(max(abs(sum(dual.weights, 2) - 1)) <= 1e-12);
end

entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildTimeExpandedDualPathV119ExecutionContext( ...
    entry.presetName, entry.seed, 72, ...
    protocol.dualPathActionNames{1}, true);
assert(isTimeExpandedDualPathV119ExecutionContext(context));
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.protectionFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            'abstention-only'));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));
assert(nargin('runTimeExpandedDualPathV119X36T72') == 1);
fprintf('test_time_expanded_dual_path_v119 passed\n');
end

function [adjacency, weights, details, physical] = syntheticCarrier()
nodeCount = 6;
weights = zeros(nodeCount);
residual = false(nodeCount);
for receiver = 1:nodeCount
    source = mod(receiver, nodeCount) + 1;
    weights(receiver, receiver) = 0.95;
    weights(receiver, source) = 0.05;
    residual(receiver, source) = true;
end
adjacency = weights > 0;
physical = true(nodeCount);
details = struct( ...
    'residualAdjacency', residual, ...
    'fusionWeightMatrix', weights, ...
    'messageCount', nnz(adjacency), ...
    'selectedSourcesByReceiver', ...
        {arrayfun(@(receiver) find(adjacency(receiver, :)), ...
            1:nodeCount, 'UniformOutput', false)});
end
