function test_alternating_shield_broadcast_v111()
% TEST_ALTERNATINGSHIELDBROADCASTV111 Schedule and authorization contract.

protocol = getAlternatingShieldBroadcastV111Protocol();
assert(protocol.horizonSteps == 8);
assert(all(cellfun(@isempty, ...
    protocol.broadcastFormationIdsByTime([1, 3, 5, 7]))));
assert(isequal(protocol.broadcastFormationIdsByTime{2}, [1, 2, 4, 5]));
assert(isequal(protocol.broadcastFormationIdsByTime{4}, ...
    [1, 2, 3, 4, 5]));
assert(isequal(protocol.broadcastFormationIdsByTime{6}, 1:6));
assert(isequal(protocol.broadcastFormationIdsByTime{8}, 1:6));

entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildAlternatingShieldBroadcastV111ExecutionContext( ...
    entry.presetName, entry.seed, 72, protocol.candidateActionName, true);
assert(isAlternatingShieldBroadcastV111ExecutionContext(context));
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ...
            ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.protectionFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            'abstention-only'));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));

request.triggerConfig.receiverSafeFormationConditionedPayloadMode = ...
    'control-only';
rejected = false;
try
    assertDynamicTopologyTrackingOutcomeAuthorized( ...
        runtimeModel, context, request);
catch errorInfo
    rejected = strcmp(errorInfo.identifier, ...
        'OnlinePositiveNetV99:InvalidRuntimeRequest');
end
assert(rejected);
end
