function test_counterfactual_regret_gate_v133_baseline_selection()
% TEST_COUNTERFACTUAL_REGRET_GATE_V133_BASELINE_SELECTION Pure reducer.

protocol = getCounterfactualRegretGateV133Protocol();
gitState = struct( ...
    'commit', 'test-commit', ...
    'trackedWorktreeDirty', false, ...
    'untrackedSourceFiles', {cell(1, 0)});
shards = repmat(emptyShard(), 1, ...
    numel(protocol.scaleCases) * ...
        numel(protocol.developmentSeeds) * ...
        numel(protocol.referenceCarrierModes));
cursor = 0;
for caseIdx = 1:numel(protocol.scaleCases)
    caseInfo = protocol.scaleCases(caseIdx);
    for seedIdx = 1:numel(protocol.developmentSeeds)
        seed = protocol.developmentSeeds(seedIdx);
        for carrierIdx = 1:numel(protocol.referenceCarrierModes)
            cursor = cursor + 1;
            carrierMode = protocol.referenceCarrierModes{carrierIdx};
            if caseIdx == 1
                meanEospa = 100 + 5 * (carrierIdx - 1) + seedIdx;
            else
                meanEospa = 110 - 5 * (carrierIdx - 1) + seedIdx;
            end
            shards(cursor) = buildShard( ...
                protocol, caseInfo, seed, carrierMode, ...
                meanEospa, gitState.commit);
        end
    end
end

selection = buildCounterfactualRegretGateV133BaselineSelection( ...
    shards(end:-1:1), protocol, gitState);
assert(strcmp(selection.cases(1).selectedCarrierMode, ...
    'fixed-clockwise'));
assert(strcmp(selection.cases(2).selectedCarrierMode, ...
    'fixed-counter-clockwise'));
assert(isequal(size(selection.cases(1).records), [4, 2]));
assert(~selection.perStateOracleSelectionUsed);
assert(~selection.validationClaimAllowed);

duplicated = shards;
duplicated(end) = duplicated(1);
assertFails(@() buildCounterfactualRegretGateV133BaselineSelection( ...
    duplicated, protocol, gitState), ...
    'CounterfactualRegretV133:InvalidBaselineShard');
drifted = shards;
drifted(1).generationGitCommit = 'other-commit';
assertFails(@() buildCounterfactualRegretGateV133BaselineSelection( ...
    drifted, protocol, gitState), ...
    'CounterfactualRegretV133:InvalidBaselineShard');
fprintf('test_counterfactual_regret_gate_v133_baseline_selection passed\n');
end

function shard = buildShard( ...
        protocol, caseInfo, seed, carrierMode, meanEospa, commit)
record = struct( ...
    'seed', seed, 'carrierMode', carrierMode, ...
    'meanEospa', meanEospa, ...
    'focusMeanEospa', meanEospa + 1, ...
    'worstSensorEospa', meanEospa + 2, ...
    'attemptedBytes', 1000, 'deliveredBytes', 900, ...
    'elapsedSeconds', 10, 'policyTruthUsed', false, ...
    'policyFutureOutcomeUsed', false);
shard = struct( ...
    'contractVersion', ...
        'counterfactual-regret-gate-v133-baseline-shard-v1', ...
    'protocolId', protocol.id, 'scaleName', caseInfo.scaleName, ...
    'presetName', caseInfo.presetName, 'seed', seed, ...
    'carrierMode', carrierMode, 'record', record, ...
    'generationGitCommit', commit, ...
    'generationTrackedWorktreeDirty', false, ...
    'generationUntrackedSourceFiles', {cell(1, 0)});
end

function value = emptyShard()
value = struct( ...
    'contractVersion', '', 'protocolId', '', 'scaleName', '', ...
    'presetName', '', 'seed', 0, 'carrierMode', '', ...
    'record', struct(), 'generationGitCommit', '', ...
    'generationTrackedWorktreeDirty', false, ...
    'generationUntrackedSourceFiles', {cell(1, 0)});
end

function assertFails(action, expectedIdentifier)
didFail = false;
try
    action();
catch exception
    didFail = strcmp(exception.identifier, expectedIdentifier);
end
assert(didFail);
end
