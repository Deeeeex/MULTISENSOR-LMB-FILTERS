function test_support_aware_formation_controller_v206_execution_context()
% V206 must authorize release and repair together on one paired H=8 run.

currentTime = 72;
horizonSteps = 8;
baseProtocol = ...
    getOnlinePositiveNetAddressablePayloadV99Protocol(horizonSteps);
controllerProtocol = getSupportAwareFormationControllerV206Protocol();
repairPlan = struct( ...
    'times', [72, 73], ...
    'referenceAttemptedBytes', [1560000, 1550000], ...
    'idealDeliveryTeacherMode', true, ...
    'maximumActions', 1, ...
    'forcedFormationId', [2, 6], ...
    'forcedSourceId', [19, 19], ...
    'forcedLabel', [13, 7; 12, 5], ...
    'updateMode', 'label-kla', ...
    'sourceWeight', 0.5);
releasePlan = struct( ...
    'contractVersion', ...
        'online-positive-net-formation-release-v191-plan-v1', ...
    'times', currentTime, ...
    'formationIdsByTime', {{5}}, ...
    'teacherMode', true);
context = buildSupportAwareFormationControllerV206ExecutionContext( ...
    'x36-formation-fov', 211, currentTime, ...
    'v99-online-positive-net-f1-f2-f4-f5', true, true, ...
    repairPlan, releasePlan, horizonSteps);
assert(isSupportAwareFormationControllerV206ExecutionContext(context));
assert(strcmp(context.protocolId, controllerProtocol.id));
assert(context.measurementTimeCount == 79);

model = struct();
model.numberOfSensors = 36;
model.dynamicTopologyScenario = struct( ...
    'presetName', 'x36-formation-fov', ...
    'seed', 211, ...
    'config', struct('formationCount', 6));
config = struct( ...
    'topologyPolicyName', baseProtocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', true, ...
    'receiverSafeLabelFusionMode', 'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', currentTime + (0:7), ...
    'receiverSafeFormationConditionedSchedule', {cell(1, 8)}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only', ...
    'budgetRecycledFormationRepairEnabled', true, ...
    'budgetRecycledFormationRepairTimes', repairPlan.times, ...
    'budgetRecycledFormationRepairReferenceAttemptedBytes', ...
        repairPlan.referenceAttemptedBytes, ...
    'budgetRecycledFormationRepairIdealDeliveryTeacherMode', true, ...
    'budgetRecycledFormationRepairMaximumActions', 1, ...
    'budgetRecycledFormationRepairForcedFormationId', ...
        repairPlan.forcedFormationId, ...
    'budgetRecycledFormationRepairForcedSourceId', ...
        repairPlan.forcedSourceId, ...
    'budgetRecycledFormationRepairForcedLabel', repairPlan.forcedLabel, ...
    'budgetRecycledFormationRepairUpdateMode', 'label-kla', ...
    'budgetRecycledFormationRepairSourceWeight', 0.5, ...
    'onlinePositiveNetFormationReleasePlan', releasePlan, ...
    'formationCoordinatedPosteriorRepairEnabled', false);
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', 79, ...
    'sensorTrajectoryTimeCounts', repmat(79, 1, 36), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, context, request);
assert(strcmp(authorization.mode, ...
    'support-aware-formation-controller-v206-development'));
assert(strcmp(authorization.protocolId, controllerProtocol.id));
assert(~authorization.groundTruthAccessAuthorized);
assert(~authorization.futureOutcomeAccessAuthorized);
assert(~authorization.validationClaimAllowed);

fprintf([ ...
    'test_support_aware_formation_controller_v206_execution_context ', ...
    'passed\n']);
end
