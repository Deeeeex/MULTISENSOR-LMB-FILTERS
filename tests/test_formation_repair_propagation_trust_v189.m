function test_formation_repair_propagation_trust_v189()
% Causal motion gate must reject a horizon-scale displacement.

model = struct( ...
    'xDimension', 4, ...
    'A', [eye(2), eye(2); zeros(2), eye(2)], ...
    'u', zeros(4, 1), ...
    'R', eye(4), ...
    'ospaParameters', struct('eC', 150));
source = makeObject([0; 0; 4; 0]);
near = makeObject([40; 0; 2; 0]);
% The second receiver starts inside the 150 m region but moves away fast
% enough to cross it on the third page of the H=3 recursive window.
far = makeObject([145; 0; 8; 0]);
proposal = struct( ...
    'formationId', 1, ...
    'receiverIds', [1, 2], ...
    'sourceId', 3, ...
    'label', [1; 1], ...
    'sourceObject', source, ...
    'richSynopsisBytes', 64, ...
    'requestBytes', 48, ...
    'responseBytes', 2000);

failed = evaluateFormationRepairPropagationTrustV189( ...
    proposal, {near, far, source}, model, struct('horizonSteps', 3));
assert(~failed.passedAllReceivers);
assert(failed.receiverPassed(1));
assert(~failed.receiverPassed(2));
assert(failed.maximumDistance > failed.positionCutoff);
assert(failed.preflightAttemptedBytes == 64 + 2 * 8);
assert(failed.totalAttemptedBytesIfAccepted == 64 + 2 * 8 + 48 + 2000);
assert(~failed.truthUsed);
assert(~failed.futureMeasurementsUsed);

passed = evaluateFormationRepairPropagationTrustV189( ...
    proposal, {near, near, source}, model, struct('horizonSteps', 3));
assert(passed.passedAllReceivers);
assert(passed.maximumDistance < passed.positionCutoff);

fprintf('test_formation_repair_propagation_trust_v189 passed\n');
end

function object = makeObject(meanVector)
object = struct( ...
    'numberOfGmComponents', 1, ...
    'w', 1, ...
    'mu', {{meanVector}}, ...
    'Sigma', {{diag([25, 25, 4, 4])}}, ...
    'r', 0.9, ...
    'birthTime', 1, ...
    'birthLocation', 1);
end
