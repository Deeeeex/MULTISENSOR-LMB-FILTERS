function testFormationB4V49CyclePreservingReference()
% Exact cycle bank, no-worse fallback, sanitizer, and UID permutation.

[fullContext, incumbent] = buildSyntheticContext();
[context, contract] = ...
    buildFormationB4V49GraphOnlyRouteContext(fullContext);
[reference, details] = ...
    selectFormationB4V49CyclePreservingReference( ...
        context, incumbent, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0));
nodeCount = numel(context.sensorPhysicalUids);
assert(contract.passed && ~contract.posteriorPresent);
assert(details.physicalCycleCandidateCount == 3);
assert(details.feasibleCycleCandidateCount == 3);
assert(strcmp(details.cycleSelectionMode, ...
    'reliability-proposal-topk'));
assert(details.runtimePulsePhaseOneMatched);
assert(details.incumbentBestSynchronizedPulsePhase == 1);
assert(details.certificateEvaluationsPerScoredReference == 1);
assert(details.totalCertificateEvaluationCount == 4);
assert(all(isnan(details. ...
    incumbentSynchronizedSquaredFactorByPhase(2:4))));
assert(details.selectedNoWorseThanIncumbentProxy);
assert(details.selectedSquaredFactor <= ...
    details.incumbentBestSynchronizedSquaredFactor + 1e-12);
assert(details.sameDirectedReferenceMessageBudget);
assert(details.dominantLayerBitwiseEqualsIncumbent);
assert(details.frozenCurrentPagePropagationProxyOnly);
assert(~details.timeVaryingNoWorseCertified && ...
    ~details.trackingSafetyClaimAllowed);
assert(nnz(reference.referenceAdjacency) == 2 * nodeCount);
assert(~details.posteriorUsed && ~details.truthUsed && ...
    ~details.measurementUsed && ~details.futurePageUsed && ...
    ~details.realizedDeliveryUniformsUsed);

order = [8, 1, 12, 4, 7, 2, 10, 5, 9, 3, 11, 6];
permutedFull = permuteFullContext(fullContext, order);
permutedIncumbent = permuteReference(incumbent, order);
permutedContext = ...
    buildFormationB4V49GraphOnlyRouteContext(permutedFull);
[permutedReference, permutedDetails] = ...
    selectFormationB4V49CyclePreservingReference( ...
        permutedContext, permutedIncumbent, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0));
assert(isequal(permutedReference.referenceAdjacency, ...
    reference.referenceAdjacency(order, order)));
assert(max(abs(permutedReference.referenceFusionWeights(:) - ...
    reshape(reference.referenceFusionWeights(order, order), [], 1))) ...
    < 1e-12);
assert(isequal(permutedDetails.selectedCycleOrder, ...
    details.selectedCycleOrder));
assert(strcmp(permutedDetails. ...
    selectedPhysicalRouteCanonicalSha256, ...
    details.selectedPhysicalRouteCanonicalSha256));
assert(abs(permutedDetails.selectedSquaredFactor - ...
    details.selectedSquaredFactor) < 1e-12);

withSideChannels = fullContext;
withSideChannels.localPosteriorBySensor = repmat( ...
    {struct('futureTruth', 1)}, 1, nodeCount);
[sanitized, sideContract] = ...
    buildFormationB4V49GraphOnlyRouteContext(withSideChannels);
assert(sideContract.passed && ~sideContract.posteriorPresent);
assert(~isfield(sanitized, 'localPosteriorBySensor'));

future = fullContext;
future.commConfig.pDropByEdge = repmat( ...
    fullContext.commConfig.pDropByEdge, 1, 1, 2);
assertErrorId(@() buildFormationB4V49GraphOnlyRouteContext(future), ...
    'FormationB4V49RouteContext:FuturePageOrInvalidLinkState');

pathOnly = fullContext;
pathOnly.physicalAdjacency = logical(fullContext.baseAdjacency);
pathOnly.commConfig.pDropByEdge(~pathOnly.physicalAdjacency) = 1;
pathContext = buildFormationB4V49GraphOnlyRouteContext(pathOnly);
[pathReference, pathDetails] = ...
    selectFormationB4V49CyclePreservingReference( ...
        pathContext, incumbent, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0));
assert(pathDetails.physicalCycleCandidateCount == 0);
assert(pathDetails.feasibleCycleCandidateCount == 0);
assert(pathDetails.selectedUsedIncumbentFallback);
assert(isequal(pathReference.referenceAdjacency, ...
    incumbent.referenceAdjacency));

[tieReference, tieDetails] = ...
    selectFormationB4V49CyclePreservingReference( ...
        context, reference, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0));
assert(tieDetails.selectedUsedIncumbentFallback);
assert(isequal(tieReference.referenceAdjacency, ...
    reference.referenceAdjacency));

[cappedReference, cappedDetails] = ...
    selectFormationB4V49CyclePreservingReference( ...
        context, incumbent, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0, ...
            'maximumCanonicalCycleEnumerationCount', 1));
assert(cappedDetails.cycleEnumerationCapped);
assert(cappedDetails.selectedUsedIncumbentFallback);
assert(strcmp(cappedDetails.selectedFallbackReason, ...
    'enumeration-capped'));
assert(isequal(cappedReference.referenceAdjacency, ...
    incumbent.referenceAdjacency));

[~, exactCappedDetails] = ...
    selectFormationB4V49CyclePreservingReference( ...
        context, incumbent, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0, ...
            'maximumCanonicalCycleEnumerationCount', 1, ...
            'cycleSelectionMode', ...
                'exact-contraction-enumeration'));
assert(exactCappedDetails.cycleEnumerationCapped);
assert(~exactCappedDetails.exactGlobalCycleOptimumClaimAllowed);

[exactReference, exactDetails] = ...
    selectFormationB4V49CyclePreservingReference( ...
        context, incumbent, struct( ...
            'minimumRelativeImprovementVsIncumbent', 0, ...
            'cycleSelectionMode', ...
                'exact-contraction-enumeration'));
assert(exactDetails.exactGlobalCycleOptimumClaimAllowed);
assert(exactDetails.feasibleCycleCandidateCount == 3);
assert(exactDetails.selectedSquaredFactor <= ...
    details.selectedSquaredFactor + 1e-12);
assert(nnz(exactReference.referenceAdjacency) == 2 * nodeCount);

protocol = getFormationB4V49FeasibleCycleCompletionProtocol();
assert(strcmp(protocol.defaultCycleSelectionMode, ...
    'reliability-proposal-topk'));
assert(protocol.maximumExactProposalEvaluations == 3);
assert(strcmp(protocol.runtimePulsePhaseMode, 'fixed-phase-one'));
assert(protocol.runtimeFixedPhaseScoresOnlyPhaseOne);
assert(protocol.runtimeExactCertificateEvaluationsPerReference == 1);
assert(protocol.exactGlobalOptimumClaimRequiresUncappedFullEnumeration);
assert(protocol.sameDirectedPosteriorMessageCountOnly);
assert(protocol.posthocTimeVaryingFactorIsWorstDirectionExpectedCenteredL2);
assert(~protocol.posthocPointwiseDominanceClaimAllowed && ...
    protocol.independentDirectedDeliveryAssumed);
assert(strcmp(protocol.canonicalSha256, ...
    '97960c8988e82ab00a7bc2255c38080f5036343ec1ac3e214e0de4d19534fd8c'));
assert(~protocol.timeVaryingNoWorseCertified && ...
    ~protocol.trackingSafetyClaimAllowed);

fprintf('PASS: FormationB4V49 cycle-preserving reference tests\n');
end

function [context, reference] = buildSyntheticContext()
formationUids = repelem([401, 402, 403, 404], 3);
groupIds = repelem([10, 20, 30, 40], 3);
nodeCount = numel(formationUids);
physical = ~eye(nodeCount);
registered = buildPathRegistered(formationUids, physical);
positions = [0:(nodeCount - 1); mod(0:(nodeCount - 1), 3)];
pDrop = 0.03 + 0.25 * reshape( ...
    mod(1:nodeCount^2, 13), nodeCount, nodeCount) / 12;
pDrop(1:nodeCount+1:end) = 1;

context = struct();
context.localPosteriorBySensor = cell(1, nodeCount);
context.model = struct('dynamicTopologyScenario', struct( ...
    'config', struct('sensorGroupIds', groupIds), ...
    'staticAdjacency', registered));
context.baseAdjacency = registered;
context.physicalAdjacency = physical;
context.positions = positions;
context.sensorPhysicalUids = 1000 + (1:nodeCount);
context.formationPhysicalUidsBySensor = formationUids;
context.commConfig = struct('pDropByEdge', pDrop);
context.currentTime = 9;
context.directedMessageBudget = 2 * nodeCount;
[adjacency, policy] = ...
    selectIndexEquivariantFormationBackbonePolicy( ...
        context, struct('dominantWeight', 0.70, ...
            'residualWeight', 0.05));
reference = struct( ...
    'dominantAdjacency', logical(policy.dominantAdjacency), ...
    'residualAdjacency', logical(policy.residualAdjacency), ...
    'referenceAdjacency', logical(adjacency), ...
    'referenceFusionWeights', policy.fusionWeightMatrix);
end

function registered = buildPathRegistered(formationUids, physical)
uids = sort(unique(formationUids));
registered = false(size(physical));
for formationIdx = 1:numel(uids)
    members = formationUids == uids(formationIdx);
    registered(members, members) = physical(members, members);
    if formationIdx < numel(uids)
        nextMembers = formationUids == uids(formationIdx + 1);
        registered(members, nextMembers) = ...
            physical(members, nextMembers);
        registered(nextMembers, members) = ...
            physical(nextMembers, members);
    end
end
registered(1:size(registered, 1)+1:end) = false;
end

function context = permuteFullContext(context, order)
context.model.dynamicTopologyScenario.config.sensorGroupIds = ...
    context.model.dynamicTopologyScenario.config.sensorGroupIds(order);
context.model.dynamicTopologyScenario.staticAdjacency = ...
    context.model.dynamicTopologyScenario.staticAdjacency(order, order);
context.baseAdjacency = context.baseAdjacency(order, order);
context.physicalAdjacency = ...
    context.physicalAdjacency(order, order);
context.positions = context.positions(:, order);
context.sensorPhysicalUids = context.sensorPhysicalUids(order);
context.formationPhysicalUidsBySensor = ...
    context.formationPhysicalUidsBySensor(order);
context.commConfig.pDropByEdge = ...
    context.commConfig.pDropByEdge(order, order);
context.localPosteriorBySensor = ...
    context.localPosteriorBySensor(order);
end

function reference = permuteReference(reference, order)
fields = {'dominantAdjacency', 'residualAdjacency', ...
    'referenceAdjacency', 'referenceFusionWeights'};
for fieldIdx = 1:numel(fields)
    name = fields{fieldIdx};
    reference.(name) = reference.(name)(order, order);
end
end

function assertErrorId(callback, expectedIdentifier)
actual = '';
try
    callback();
catch errorInfo
    actual = errorInfo.identifier;
end
assert(strcmp(actual, expectedIdentifier), ...
    'Expected %s, received %s.', expectedIdentifier, actual);
end
