function test_mode_diverse_position_safe_repair_candidates_v217()
% The three proposal modes must retain distinct candidates under one cap.

candidates = repmat(baseCandidate(), 1, 4);
for idx = 1:numel(candidates)
    candidates(idx).candidateIndex = idx;
    candidates(idx).sourceId = idx;
    candidates(idx).label = [idx; 1];
end
candidates(1).precisionGainNormalized = 2;
candidates(1).receiverCompatibilityMedian = 0.9;
candidates(2).minimumReceiverExistence = 0.1;
candidates(3).opportunityMedian = 0.9;
candidates(4).sourceQuality = 0.1;

[shortlist, details] = ...
    selectModeDiversePositionSafeRepairCandidatesV217( ...
        candidates, struct('topPerMode', 1));
assert(isequal([shortlist.candidateIndex], [1, 2, 3]));
assert(details.shortlistedCandidateCount == 3);
assert(details.maximumPerFormation == 3);
assert(all(sum(details.selectedByMode, 1) == 1));
assert(~details.modeScoresAreActionValues);
assert(~details.truthUsed && ~details.futureInformationUsed);

fprintf('test_mode_diverse_position_safe_repair_candidates_v217 passed\n');
end

function candidate = baseCandidate()
candidate = struct( ...
    'candidateIndex', 0, 'formationId', 1, 'sourceId', 0, ...
    'label', zeros(2, 1), 'positionSupport99Passed', true, ...
    'minimumRiskReduction', 0.5, ...
    'minimumReceiverExistence', 0.8, ...
    'receiverCompatibilityMedian', 0.5, ...
    'sourceQuality', 0.8, ...
    'sourceObservationOpportunity', 0, ...
    'opportunityMedian', 0.1, ...
    'peerConsensusMinimum', 0.7, ...
    'peerConsensusMedian', 0.8, ...
    'sourcePositionTraceNormalized', 0.1, ...
    'receiverPositionTraceMedianNormalized', 0.2, ...
    'precisionGainNormalized', 0.1, ...
    'positionDistanceMedianNormalized', 0.1, ...
    'positionDistanceMaximumNormalized', 0.2, ...
    'formationSizeFraction', 0.25, ...
    'sourcePhysicalDegreeFraction', 0.5);
end
