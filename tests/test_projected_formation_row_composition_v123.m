function test_projected_formation_row_composition_v123()
% TEST_PROJECTEDFORMATIONROWCOMPOSITIONV123 Protocol and authorization.

protocol = getProjectedFormationRowCompositionV123Protocol();
assert(isequal(size(protocol.graphChoiceByFormationPage), [6, 8]));
assert(isequal(protocol.projectionFallbackFormationIdsByPage, ...
    {[], [], [], [], 3, [], [], 3}));
assert(isequal(protocol.payloadFormationIdsByPage{1}, 5));
assert(~any(cellfun(@(ids) ismember(6, ids), ...
    protocol.payloadFormationIdsByPage)));
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildProjectedFormationRowCompositionV123ExecutionContext( ...
    entry.presetName, entry.seed, 72, ...
    protocol.candidateSequenceName, true);
assert(isProjectedFormationRowCompositionV123ExecutionContext(context));
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.payloadFormationIdsByPage}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            'abstention-only'));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));
assert(nargin('runProjectedFormationRowCompositionV123X36T72') == 1);
fprintf('test_projected_formation_row_composition_v123 passed\n');
end
