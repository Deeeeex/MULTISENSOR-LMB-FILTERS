function test_index_equivariant_residual_duty_cycle_schedule()
% Structural and coordinate-equivariance contracts for the V44 schedule.

[context, ~] = ...
    buildFormationIndexEquivariantGeometryDevelopmentContext( ...
        'm24-formation-fov-convoy', 43);
[localAdjacency, localWeights, local] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(context, struct( ...
        'period', 3, 'dutyLayer', 'local', ...
        'activeResidualWeight', 0.15));
nodeCount = size(localAdjacency, 1);
assert(strcmp(local.contractVersion, ...
    'index-equivariant-residual-duty-cycle-schedule-v1'));
assert(local.period == 3);
assert(local.residualMassMatchedToReference);
assert(abs(local.messageSavingFractionPerPeriod - 0.25) < 1e-12);
assert(local.periodUnionEqualsReference);
assert(local.periodUnionSensorStrongConnected);
assert(local.periodUnionFormationStrongConnected);
assert(all(abs(reshape(sum(localWeights, 2), [], 1) - 1) < 1e-12));
assert(all(reshape(sum(localAdjacency, 2), [], 1) <= 2));
assert(local.messageCountsByPhase(1) == 2 * nodeCount);
assert(all(local.messageCountsByPhase(2:3) < 2 * nodeCount));
assert(all(local.crossMessageCountsByPhase == ...
    local.crossMessageCountsByPhase(1)));
assert(~local.posteriorUsed && ~local.truthUsed && ...
    ~local.futureOutcomeUsed && ~local.trackingOutcomeScored);

[crossAdjacency, ~, cross] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(context, struct( ...
        'period', 2, 'dutyLayer', 'cross', ...
        'activeResidualWeight', 0.10));
assert(cross.crossMessageCountsByPhase(2) == 0);
assert(cross.localResidualMessageCountsByPhase(1) == ...
    cross.localResidualMessageCountsByPhase(2));
assert(isequal(any(crossAdjacency, 3), cross.referenceAdjacency));

[allAdjacency, ~, allDetails] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(context, struct( ...
        'period', 4, 'dutyLayer', 'all', ...
        'activeResidualWeight', 0.20));
assert(allDetails.messageSavingFractionPerPeriod == 3 / 8);
assert(all(allDetails.messageCountsByPhase(2:4) == nodeCount));
assert(isequal(any(allAdjacency, 3), allDetails.referenceAdjacency));

[staggeredAdjacency, staggeredWeights, staggered] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(context, struct( ...
        'period', 3, 'dutyLayer', 'all', ...
        'phasePattern', 'receiver-staggered', ...
        'activeResidualWeight', 0.15));
assert(nnz(staggered.dutyPhaseByReceiver == 1) > 0);
assert(nnz(staggered.dutyPhaseByReceiver == 2) > 0);
assert(nnz(staggered.dutyPhaseByReceiver == 3) > 0);
assert(isequal(any(staggeredAdjacency, 3), ...
    staggered.referenceAdjacency));
assert(staggered.messagesPerPeriod == allDetails.referenceMessageCountPerStep * 3 - ...
    2 * nodeCount);

groupIds = context.model.dynamicTopologyScenario.config.sensorGroupIds;
order = [find(groupIds == 4), find(groupIds == 2), ...
    find(groupIds == 1), find(groupIds == 3)];
[permuted, ~] = permuteFormationIndexEquivariantContext(context, order);
[actualAdjacency, actualWeights, actual] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(permuted, struct( ...
        'period', 3, 'dutyLayer', 'local', ...
        'activeResidualWeight', 0.15));
for phaseIdx = 1:3
    restoredAdjacency = false(nodeCount);
    restoredAdjacency(order, order) = actualAdjacency(:, :, phaseIdx);
    restoredWeights = zeros(nodeCount);
    restoredWeights(order, order) = actualWeights(:, :, phaseIdx);
    assert(isequal(restoredAdjacency, localAdjacency(:, :, phaseIdx)));
    assert(isequal(restoredWeights, localWeights(:, :, phaseIdx)));
end
assert(isequal(actual.messageCountsByPhase, local.messageCountsByPhase));

[actualStaggeredAdjacency, actualStaggeredWeights, actualStaggered] = ...
    buildIndexEquivariantResidualDutyCycleSchedule(permuted, struct( ...
        'period', 3, 'dutyLayer', 'all', ...
        'phasePattern', 'receiver-staggered', ...
        'activeResidualWeight', 0.15));
for phaseIdx = 1:3
    restoredAdjacency = false(nodeCount);
    restoredAdjacency(order, order) = ...
        actualStaggeredAdjacency(:, :, phaseIdx);
    restoredWeights = zeros(nodeCount);
    restoredWeights(order, order) = ...
        actualStaggeredWeights(:, :, phaseIdx);
    assert(isequal(restoredAdjacency, ...
        staggeredAdjacency(:, :, phaseIdx)));
    assert(isequal(restoredWeights, staggeredWeights(:, :, phaseIdx)));
end
restoredPhases = nan(1, nodeCount);
restoredPhases(order) = actualStaggered.dutyPhaseByReceiver;
assert(isequaln(restoredPhases, staggered.dutyPhaseByReceiver));

assertErrorId(@() buildIndexEquivariantResidualDutyCycleSchedule( ...
    context, struct('period', 4, 'activeResidualWeight', 0.31)), ...
    'IndexEquivariantResidualDutyCycle:InvalidOptions');
assertErrorId(@() buildIndexEquivariantResidualDutyCycleSchedule( ...
    context, struct('period', 4, 'activeResidualWeight', 0.26)), ...
    'IndexEquivariantResidualDutyCycle:InvalidOptions');
assertErrorId(@() buildIndexEquivariantResidualDutyCycleSchedule( ...
    context, struct('period', 6, 'activeResidualWeight', 0.05)), ...
    'IndexEquivariantResidualDutyCycle:InvalidOptions');
fprintf('PASS: index-equivariant residual duty-cycle tests\n');
end

function assertErrorId(handle, expected)
failed = false;
try
    handle();
catch errorInfo
    failed = strcmp(errorInfo.identifier, expected);
end
assert(failed);
end
