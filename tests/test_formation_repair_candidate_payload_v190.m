function test_formation_repair_candidate_payload_v190()
% V190 resolves an exact candidate without changing its routing key.

object = struct( ...
    'birthTime', 13, ...
    'birthLocation', 12, ...
    'r', 0.9, ...
    'numberOfGmComponents', 2);
local = {repmat(object, 1, 0), object, repmat(object, 1, 0)};
physical = false(3);
physical([1, 3], 2) = true;
candidate = struct( ...
    'candidateIndex', 7, ...
    'formationId', 2, ...
    'receiverIds', [1, 3], ...
    'sourceId', 2, ...
    'label', [13; 12], ...
    'minimumRiskReduction', 0.31, ...
    'opportunityMedian', 0.25, ...
    'minimumReceiverExistence', 0.8, ...
    'peerConsensusMedian', 0.7, ...
    'receiverCompatibilityMedian', 0.2);
model = struct('xDimension', 4, 'existenceThreshold', 0.01);

[proposal, details] = ...
    resolveFormationRepairCandidatePayloadV190( ...
        candidate, local, physical, model, struct());
assert(proposal.safetyPassed);
assert(proposal.commonSourcePassed);
assert(proposal.sourceId == candidate.sourceId);
assert(isequal(proposal.label, candidate.label));
assert(proposal.sourceObject.numberOfGmComponents == 2);
assert(proposal.completeResponseBytesPerReceiver > 0);
assert(proposal.responseBytes == ...
    2 * proposal.completeResponseBytesPerReceiver);
assert(proposal.attemptedBytes == proposal.richSynopsisBytes + ...
    proposal.requestBytes + proposal.responseBytes);
assert(details.completePayloadResolved);
assert(~details.truthUsed);

physical(3, 2) = false;
[blocked, blockedDetails] = ...
    resolveFormationRepairCandidatePayloadV190( ...
        candidate, local, physical, model, struct());
assert(~blocked.safetyPassed);
assert(~blockedDetails.commonSourcePassed);

fprintf('test_formation_repair_candidate_payload_v190 passed\n');
end
