function test_post_fusion_label_readout_v138()
% TESTPOSTFUSIONLABELREADOUTV138 Selector and permit boundaries.

protocol = getPostFusionLabelReadoutV138Protocol();
assert(protocol.labelReadout.selectionMargin == 0);
assert(~protocol.labelReadout.workingStateMutationAllowed);
assert(~protocol.labelReadout.truthUsed);
assert(~protocol.labelReadout.futureMeasurementUsed);

local = makeObject(0, 0.9);
working = makeObject(4, 0.9);
relay = makeObject(0.1, 0.9);
evidence = makeEvidence(true);
[selected, details] = selectLineageRelayPostFusionLabelReadout( ...
    working, relay, local, evidence);
assert(details.evaluatedLabelCount == 1);
assert(details.relaySelectedLabelCount == 1);
assert(abs(selected.mu{1}(1) - relay.mu{1}(1)) < 1e-12);
assert(abs(working.mu{1}(1) - 4) < 1e-12, ...
    'The selector mutated the hidden working object.');

[selectedWithoutEvidence, noEvidenceDetails] = ...
    selectLineageRelayPostFusionLabelReadout( ...
        working, relay, local, makeEvidence(false));
assert(noEvidenceDetails.evaluatedLabelCount == 0);
assert(abs(selectedWithoutEvidence.mu{1}(1) - 4) < 1e-12);

caseInfo = protocol.scaleCases(strcmp( ...
    {protocol.scaleCases.scaleName}, 'M24'));
bank = buildSetTrustSequenceCandidatesV134( ...
    [4, 2, 1, 3], caseInfo.formationCycleDiameter, ...
    caseInfo.recoveryTailSteps);
actionSpec = bank.actions(protocol.screen.m24ActionIndex);
context = buildPostFusionLabelReadoutV138ExecutionContext( ...
    caseInfo.presetName, protocol.pilotSeed, 'candidate', 95, ...
    'fixed-counter-clockwise', actionSpec);
assert(context.postFusionLabelReadoutEnabled);
assert(~context.workingStateMutationAllowed);

runtimeModel = struct( ...
    'numberOfSensors', caseInfo.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', caseInfo.presetName, ...
        'seed', protocol.pilotSeed, ...
        'config', struct( ...
            'formationCount', caseInfo.expectedFormationCount)));
returnTimes = context.currentTime + (0:(context.horizonSteps - 1));
requestConfig = buildMixtureAwareKlaReferenceConfig(struct( ...
    'topologyPolicyName', protocol.outcomePolicyName, ...
    'v135ReferenceCarrierMode', 'fixed-counter-clockwise', ...
    'topologyPolicyHistoryDepth', 2, ...
    'topologyPolicyObservableContextOnly', true, ...
    'topologyPolicySensorObservationEnabled', true, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeLabelFusionMode', ...
        'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', returnTimes, ...
    'receiverSafeFormationConditionedTimes', returnTimes, ...
    'receiverSafeFormationConditionedSchedule', ...
        {actionSpec.formationIdsByTime}, ...
    'receiverSafeFormationConditionedTrustFactorsByTime', ...
        {actionSpec.trustFactorsByTime}, ...
    'receiverSafeFormationConditionedPayloadMode', ...
        protocol.runtimePayloadMode, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
    'receiverSafeEvidenceOptions', ...
        protocol.labelReadout.evidenceOptions, ...
    'lineageIsolatedRelayEnabled', true, ...
    'lineageRelayIntraFormationWorkingPayloadEnabled', true, ...
    'lineageRelayPredictiveEvidenceFallbackEnabled', false, ...
    'lineageRelayPostFusionLabelReadoutEnabled', true, ...
    'missingNeighborWeightMode', ...
        protocol.primaryMissingNeighborWeightMode, ...
    'useStaleNeighborCache', false));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones( ...
            1, caseInfo.expectedNodeCount), ...
    'triggerConfig', requestConfig);
authorization = validatePostFusionLabelReadoutV138Execution( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(~authorization.validationClaimAllowed);

request.triggerConfig.lineageRelayPredictiveEvidenceFallbackEnabled = true;
assertErrorId(@() validatePostFusionLabelReadoutV138Execution( ...
    runtimeModel, context, request), ...
    'PostFusionLabelReadoutV138:InvalidRuntimeRequest');
fprintf('PASS: V138 post-fusion label readout contract\n');
end

function object = makeObject(position, existence)
meanState = [position; 0; 0; 0];
object = struct( ...
    'birthTime', 1, ...
    'birthLocation', 1, ...
    'r', existence, ...
    'numberOfGmComponents', 1, ...
    'w', 1, ...
    'mu', {{meanState}}, ...
    'Sigma', {{eye(4)}}, ...
    'trajectoryLength', 0, ...
    'trajectory', zeros(4, 0), ...
    'timestamps', zeros(1, 0));
end

function evidence = makeEvidence(admissible)
evidence = struct( ...
    'birthTime', 1, ...
    'birthLocation', 1, ...
    'isAdmissibleToSafeReference', logical(admissible));
end

function assertErrorId(callable, expectedId)
thrown = false;
try
    callable();
catch errorInfo
    thrown = true;
    assert(strcmp(errorInfo.identifier, expectedId), ...
        'Unexpected error identifier: %s', errorInfo.identifier);
end
assert(thrown, 'Expected error was not thrown.');
end
