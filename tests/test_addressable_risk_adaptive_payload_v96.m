function test_addressable_risk_adaptive_payload_v96()
% TEST_ADDRESSABLERISKADAPTIVEPAYLOADV96 Scale-free selector and permit.

metrics = struct( ...
    'groups', [1, 2, 3, 4], ...
    'networkRescueFractionByFormation', [0.1, 0.3, 0.2, 0.4], ...
    'networkUsefulLossFractionByFormation', [0.01, 0.01, 0.02, 0.1], ...
    'singleActionAvailableMask', true(1, 4), ...
    'crossSupportedDownwardCrossingsByFormation', [0, 1, 0, 0]);
selection = selectAddressableFormationRiskSetV96(metrics, struct());
assert(selection.actionEnabled);
assert(abs(selection.totalNetworkRiskFraction - 1.0) < 1e-12);
assert(abs(selection.addressableNetworkRiskFraction - 0.7) < 1e-12);
assert(isequal(selection.addressableBasisFormationIds, [1, 3, 4]));
assert(isequal(selection.selectedFormationIds, [3, 4]));
assert(selection.achievedAddressableCoverageFraction >= 0.80);
assert(selection.usefulLossToRescueRatio <= 1.0);

protocol = getAddressableRiskAdaptivePayloadV96Protocol();
assert(numel(protocol.cases) == 2);
assert(strcmp(protocol.receiverMode, 'fov-aware-censored'));
entry = protocol.cases(1);
currentTime = entry.anchorTimes(1);
context = buildAddressableRiskAdaptivePayloadV96ExecutionContext( ...
    entry.presetName, entry.seed, currentTime, ...
    'addressable-risk-persistent-f1-f3', true);
assert(isAddressableRiskAdaptivePayloadV96ExecutionContext(context));

model = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount)));
schedule = {[1, 3], [1, 3], [1, 3]};
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ...
            ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', ...
            currentTime + (0:(protocol.horizonSteps - 1)), ...
        'receiverSafeFormationConditionedSchedule', {schedule}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            'control-only'));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));
end
