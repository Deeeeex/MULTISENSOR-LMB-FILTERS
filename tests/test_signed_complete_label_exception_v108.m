function test_signed_complete_label_exception_v108()
% TEST_SIGNEDCOMPLETELABELEXCEPTIONV108 Protocol and runtime boundary.

protocol = getSignedCompleteLabelExceptionV108Protocol();
assert(strcmp(protocol.receiverMode, 'fov-aware-censored'));
assert(numel(protocol.completeLabelExceptionsByTime) == ...
    protocol.horizonSteps);
assert(protocol.maximumExceptionsPerDeliveredEdge == 3);
totalExceptions = 0;
for timeIdx = 1:protocol.horizonSteps
    page = protocol.completeLabelExceptionsByTime{timeIdx};
    assert(iscell(page) && isequal(size(page), [36, 36]));
    for receiverIdx = 1:36
        for senderIdx = 1:36
            labels = page{receiverIdx, senderIdx};
            assert(isempty(labels) || size(labels, 1) == 2);
            assert(size(labels, 2) <= ...
                protocol.maximumExceptionsPerDeliveredEdge);
            totalExceptions = totalExceptions + size(labels, 2);
        end
    end
end
assert(totalExceptions == 24);
assert(isequal(protocol.completeLabelExceptionsByTime{3}{2, 9}, ...
    [1, 1, 7; 3, 1, 6]));
assert(isequal(protocol.completeLabelExceptionsByTime{8}{32, 3}, ...
    [19, 1, 13; 13, 4, 11]));

entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildSignedCompleteLabelExceptionV108ExecutionContext( ...
    entry.presetName, entry.seed, 72, protocol.candidateActionName, true);
assert(isSignedCompleteLabelExceptionV108ExecutionContext(context));
model = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ...
            ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.protectionFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            'signed-complete-label-exceptions', ...
        'receiverSafeCompleteLabelExceptionsByTime', ...
            {protocol.completeLabelExceptionsByTime}));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));

request.triggerConfig.receiverSafeCompleteLabelExceptionsByTime{3}{2, 9} = ...
    [1; 3];
rejected = false;
try
    assertDynamicTopologyTrackingOutcomeAuthorized(model, context, request);
catch errorInfo
    rejected = strcmp(errorInfo.identifier, ...
        'OnlinePositiveNetV99:InvalidRuntimeRequest');
end
assert(rejected);
end
