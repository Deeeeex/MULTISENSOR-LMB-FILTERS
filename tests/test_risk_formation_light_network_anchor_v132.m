function test_risk_formation_light_network_anchor_v132()
% TEST_RISK_FORMATION_LIGHT_NETWORK_ANCHOR_V132 Frozen allocation contract.

protocol = getRiskFormationLightNetworkAnchorV132Protocol();
assert(isequal(protocol.lightNetworkAnchorRefreshTimes, 72:79));
assert(isequal(protocol.lightNetworkAnchorReceiverFormationIdsByTime, ...
    repmat({[1, 2, 6]}, 1, 8)));

entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildRiskFormationLightNetworkAnchorV132ExecutionContext( ...
    entry.presetName, entry.seed, 72, protocol.candidateActionName, true);
groupIds = repelem(1:6, 6);
rollbackSensorIdsByTime = cellfun(@(formations) ...
    find(ismember(groupIds, formations)), ...
    protocol.rollbackFormationIdsByTime, 'UniformOutput', false);
anchorReceiverSensorIdsByTime = cellfun(@(formations) ...
    find(ismember(groupIds, formations)), ...
    protocol.lightNetworkAnchorReceiverFormationIdsByTime, ...
    'UniformOutput', false);
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount, ...
            'sensorGroupIds', groupIds)));
config = struct( ...
    'topologyPolicyName', protocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeLabelFusionMode', 'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', 72:79, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
    'receiverSafeFormationConditionedSchedule', ...
        {protocol.protectionFormationIdsByTime}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only', ...
    'shadowStateRollbackEnabled', true, ...
    'shadowStateRollbackSourceMode', 'light-network-anchor', ...
    'shadowStateRollbackTimes', protocol.rollbackTimes, ...
    'shadowStateRollbackSensorIdsByTime', {rollbackSensorIdsByTime}, ...
    'shadowStateRollbackFusedPosteriorByTime', {{}}, ...
    'lightNetworkAnchorRefreshTimes', ...
        protocol.lightNetworkAnchorRefreshTimes, ...
    'lightNetworkAnchorReceiverSensorIdsByTime', ...
        {anchorReceiverSensorIdsByTime});
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));

request.triggerConfig.lightNetworkAnchorReceiverSensorIdsByTime{1} = 1:36;
rejected = false;
try
    assertDynamicTopologyTrackingOutcomeAuthorized( ...
        runtimeModel, context, request);
catch errorInfo
    rejected = strcmp(errorInfo.identifier, ...
        'OnlinePositiveNetV99:InvalidRuntimeRequest');
end
assert(rejected);
fprintf('test_risk_formation_light_network_anchor_v132 passed\n');
end
