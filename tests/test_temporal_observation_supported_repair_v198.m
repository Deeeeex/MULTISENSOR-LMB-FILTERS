function test_temporal_observation_supported_repair_v198()
% TEST_TEMPORALOBSERVATIONSUPPORTEDREPAIRV198 Two-page causal support.

protocol = getTemporalObservationSupportedRepairV198Protocol();
assert(protocol.supportHistoryDepth == 1);
assert(protocol.supportWindowPages == 2);
assert(strcmp(protocol.supportMode, 'receiver-or-cross-sender'));
current = {[object(1, 1, 0.10), object(1, 2, 0.20)]};
previousPage = {[object(1, 1, 0.80), object(1, 3, 0.70)]};
previous = {previousPage};
aggregated = aggregateTemporalPosteriorSupportV198( ...
    current, previous, protocol.supportHistoryDepth);
assert(numel(aggregated{1}) == 3);
assert(abs(findMass(aggregated{1}, 1) - 0.80) < 1e-12);
assert(abs(findMass(aggregated{1}, 2) - 0.20) < 1e-12);
assert(abs(findMass(aggregated{1}, 3) - 0.70) < 1e-12);

execution = ...
    buildTemporalObservationSupportedRepairV198ExecutionContext( ...
        'x36-formation-fov', 211, 72, ...
        'v99-online-positive-net-f1-f2-f4-f5', true, true, 3);
assert(isTemporalObservationSupportedRepairV198ExecutionContext( ...
    execution));
model = struct();
model.numberOfSensors = 36;
model.dynamicTopologyScenario = struct( ...
    'presetName', 'x36-formation-fov', ...
    'seed', 211, 'config', struct('formationCount', 6));
config = struct( ...
    'topologyPolicyName', protocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'topologyPolicyPayloadReleaseHistoryEnabled', true, ...
    'topologyPolicyLocalPosteriorHistoryEnabled', true, ...
    'topologyPolicyLocalPosteriorHistoryDepth', ...
        protocol.supportHistoryDepth, ...
    'topologyPolicyObservableContextOnly', true, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', true, ...
    'receiverSafeLabelFusionMode', 'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', 72:74, ...
    'receiverSafeFormationConditionedSchedule', {cell(1, 3)}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only');
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', 74, ...
    'sensorTrajectoryTimeCounts', repmat(74, 1, 36), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, execution, request);
assert(strcmp(authorization.mode, ...
    'temporal-observation-supported-repair-v198-development'));
assert(~authorization.groundTruthAccessAuthorized);
assert(~authorization.futureOutcomeAccessAuthorized);
fprintf('test_temporal_observation_supported_repair_v198 passed.\n');
end

function value = object(birthTime, birthLocation, mass)
value = struct( ...
    'birthTime', birthTime, ...
    'birthLocation', birthLocation, ...
    'detectionAssociationMass', mass);
end

function mass = findMass(objects, birthLocation)
idx = find([objects.birthLocation] == birthLocation, 1);
assert(~isempty(idx));
mass = objects(idx).detectionAssociationMass;
end
