function test_observation_supported_set_safe_v194()
% TEST_OBSERVATION_SUPPORTED_SET_SAFE_V194 Preserve support, release risk.

reference = { ...
    receiverDistribution([1, 1; 1, 2], [0.90, 0.10]), ...
    receiverDistribution([1, 1; 1, 2], [0.90, 0.10])};
supportedCandidate = receiverDistribution( ...
    [1, 1; 1, 2], [0.90, 0.70]);
unsupportedCandidate = supportedCandidate;
control = struct();
control.groups = [1, 2];
control.singleActionAvailableMask = [true, true];
control.referenceScore = struct('networkDetails', struct( ...
    'receiverDistributions', {reference}));
control.singleActionScores = { ...
    struct('networkDetails', struct('receiverDistributions', ...
        {{supportedCandidate, reference{2}}})), ...
    struct('networkDetails', struct('receiverDistributions', ...
        {{reference{1}, unsupportedCandidate}}))};
context = struct();
context.localPosteriorBySensor = { ...
    posteriorObjects(0.80), posteriorObjects(0.00)};

projection = projectObservationSupportedSetSafeV194( ...
    control, context, [1, 2], [1, 2], 0.20);
assert(isequal(projection.selectedFormationIds, 1));
assert(isequal(projection.releaseFormationIds, 2));
assert(projection.unsupportedEntryCountByFormation(1) == 0);
assert(projection.unsupportedEntryCountByFormation(2) == 1);
assert(~projection.truthUsed && ~projection.futureInformationUsed);

execution = buildObservationSupportedSetSafeV194ExecutionContext( ...
    'm24-formation-fov', 211, 104, ...
    'v99-online-positive-net-f1-f3-f4', true, true);
protocol = getObservationSupportedSetSafeV194Protocol();
assert(isObservationSupportedSetSafeV194ExecutionContext(execution));
assert(strcmp(execution.protocolId, protocol.id));
assert(strcmp(execution.policyName, protocol.outcomePolicyName));

model = struct();
model.numberOfSensors = 24;
model.dynamicTopologyScenario = struct( ...
    'presetName', 'm24-formation-fov', ...
    'seed', 211, 'config', struct('formationCount', 4));
config = struct( ...
    'topologyPolicyName', protocol.outcomePolicyName, ...
    'topologyPolicyHistoryDepth', 2, ...
    'receiverSafeLabelFusionEnabled', true, ...
    'receiverSafeFormationConditionedOnlinePolicyEnabled', true, ...
    'receiverSafeLabelFusionMode', 'formation-supported-label-plan', ...
    'receiverSafeExternalActiveTimes', 104:106, ...
    'receiverSafeFormationConditionedSchedule', {cell(1, 3)}, ...
    'receiverSafeFormationConditionedPayloadMode', 'control-only');
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', 106, ...
    'sensorTrajectoryTimeCounts', repmat(106, 1, 24), ...
    'triggerConfig', config);
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    model, execution, request);
assert(strcmp(authorization.mode, ...
    'observation-supported-set-safe-v194-development'));
assert(strcmp(authorization.protocolId, protocol.id));
assert(~authorization.groundTruthAccessAuthorized);
assert(~authorization.futureOutcomeAccessAuthorized);
fprintf('test_observation_supported_set_safe_v194 passed.\n');
end

function distribution = receiverDistribution(labels, existence)
distribution = struct();
distribution.probability = 1;
distribution.summary = {struct( ...
    'labels', labels, 'existence', existence)};
end

function objects = posteriorObjects(secondSupport)
template = struct( ...
    'birthTime', 1, 'birthLocation', 1, ...
    'numberOfGmComponents', 1, 'detectionAssociationMass', 0.9);
objects = repmat(template, 1, 2);
objects(2).birthLocation = 2;
objects(2).detectionAssociationMass = secondSupport;
end
