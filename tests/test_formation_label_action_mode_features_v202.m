function test_formation_label_action_mode_features_v202()
% TEST_FORMATIONLABELACTIONMODEFEATURESV202 Bounded mode separation.

handover = makeCandidate();
handover.minimumReceiverExistence = 0.30;
handover.receiverCompatibilityMedian = 0.08;
handover.opportunityMedian = 0.55;
[handoverValues, names, handoverDetails] = ...
    buildFormationLabelActionModeFeaturesV202(handover);

precision = makeCandidate();
precision.minimumReceiverExistence = 0.70;
precision.receiverCompatibilityMedian = 0.92;
precision.opportunityMedian = 0.04;
precision.receiverPositionTraceMedianNormalized = 30;
[precisionValues, precisionNames, precisionDetails] = ...
    buildFormationLabelActionModeFeaturesV202(precision);

assert(isequal(names, precisionNames));
assert(all(handoverValues >= 0 & handoverValues <= 1));
assert(all(precisionValues >= 0 & precisionValues <= 1));
assert(handoverDetails.observationHandoverEvidence > ...
    handoverDetails.precisionRefreshEvidence);
assert(precisionDetails.precisionRefreshEvidence > ...
    precisionDetails.observationHandoverEvidence);
assert(~handoverDetails.thresholdApplied);
assert(~precisionDetails.modeEvidenceIsActionValue);
assert(~handoverDetails.truthUsed && ...
    ~precisionDetails.futureInformationUsed);

fprintf('test_formation_label_action_mode_features_v202 passed\n');
end

function candidate = makeCandidate()
candidate = struct( ...
    'minimumRiskReduction', 0.35, ...
    'minimumReceiverExistence', 0.60, ...
    'receiverCompatibilityMedian', 0.50, ...
    'sourceQuality', 0.95, ...
    'sourceObservationOpportunity', 0.85, ...
    'opportunityMedian', 0.25, ...
    'peerConsensusMinimum', 0.30, ...
    'peerConsensusMedian', 0.35, ...
    'sourcePositionTraceNormalized', 0.002, ...
    'receiverPositionTraceMedianNormalized', 0.40, ...
    'positionDistanceMedianNormalized', 1.20, ...
    'positionDistanceMaximumNormalized', 1.25, ...
    'formationSizeFraction', 1 / 6, ...
    'sourcePhysicalDegreeFraction', 0.40);
end
