function test_formation_reliable_kla_window_route_probe()
% TEST_FORMATIONRELIABLEKLAWINDOWROUTEPROBE Scale and isolation checks.

for formationCount = [4, 6]
    context = buildContext(formationCount, 6);
    probe = buildFormationReliableKlaWindowContractionRouteProbe(context);
    nodeCount = 6 * formationCount;
    assert(strcmp(probe.contractVersion, ...
        'formation-reliable-kla-window-contraction-route-probe-v1'));
    assert(probe.nodeCount == nodeCount);
    assert(probe.formationCount == formationCount);
    assert(probe.horizon == nodeCount - 1);
    assert(numel(probe.actions) == formationCount + 1);
    assert(all(probe.availableActionMask));
    assert(isequal(size(probe.gainByActionMode), ...
        [formationCount + 1, 2]));
    assert(isequal(size(probe. ...
        meanSquareContractionFactorByActionMode), ...
        [formationCount + 1, 2]));
    assert(all(isfinite(probe.gainByActionMode(:))));
    assert(all(probe.gainByActionMode(:) >= 0));
    assert(all(probe.expectedDobrushinUpperBoundByActionMode(:) ...
        <= 1 + 1e-12));
    assert(all(isfinite(probe. ...
        meanSquareContractionFactorByActionMode(:))));
    assert(probe.actions(1).directedMessageCount == 2 * nodeCount);
    assert(probe.actions(1).crossFormationMessageCount == ...
        2 * formationCount);
    assert(abs(probe.actions(1).totalCrossFormationFusionWeight - ...
        0.10 * formationCount) < 1e-12);
    for actionIdx = 2:numel(probe.actions)
        assert(probe.actions(actionIdx).directedMessageCount == ...
            2 * nodeCount - 2);
        assert(probe.actions(actionIdx).crossFormationMessageCount == ...
            2 * formationCount - 2);
        assert(abs(probe.actions(actionIdx). ...
            totalCrossFormationFusionWeight - ...
            0.10 * (formationCount - 1)) < 1e-12);
        assert(numel(probe.actions(actionIdx).certificates) == 2);
        assert(numel(probe.actions(actionIdx). ...
            meanSquareCertificates) == 2);
    end
    assert(~probe.posteriorContentsRead && ~probe.truthUsed && ...
        ~probe.futureOutcomeUsed && ...
        ~probe.realizedDeliveryUniformsUsed);
    assert(probe.currentPDropPageOnly);
    assert(abs(probe.currentReliabilityReceiverSender(2, 1) - ...
        (1 - context.commConfig.pDropByEdge(1, 2))) < 1e-12);
    assert(abs(probe.currentReliabilityReceiverSender(2, 1) - ...
        (1 - context.commConfig.pDropByEdge(2, 1))) > 1e-6);
    assert(probe.selectedTopologyHistoryUsed);
    assert(probe.plannedReferenceRecoveryUsed);
    assert(probe.runtimeSemanticsValidated);
    assert(probe.communicationSemanticsValidated);
    assert(probe.communicationSemantics. ...
        receiverSenderTimeIndependenceRequired);
    assert(strcmp(probe.runtimeSemantics.missingNeighborWeightMode, ...
        'renormalize'));
    assert(strcmp(probe.operationalMissingNeighborWeightMode, ...
        'renormalize'));
    assert(isequal(probe.operationalMissingNeighborWeightModeMask, ...
        [true, false]));
    assert(~probe.trackingOutcomeScored);
    assert(strcmp(probe.windowOperationalUnit, ...
        'one-online-fusion-update-per-tracking-step'));
    assert(probe.additionalWithinStepFusionRounds == 0);
    assert(probe.actions(1).windowDirectedMessageCount == ...
        probe.horizon * probe.actions(1).directedMessageCount);
    assert(probe.actions(2).incrementalWindowDirectedMessageCount == -2);

    meanSquareOnly = ...
        buildFormationReliableKlaWindowContractionRouteProbe( ...
            context, struct( ...
                'candidateFormationIds', zeros(1, 0), ...
                'missingNeighborWeightModes', {{'renormalize'}}, ...
                'includeSingleEventDobrushinDiagnostic', false));
    assert(~meanSquareOnly.singleEventDobrushinDiagnosticIncluded);
    assert(numel(meanSquareOnly.actions) == 1);
    assert(isnan(meanSquareOnly.gainByActionMode));
    assert(isempty(meanSquareOnly.actions(1).certificates{1}));
    assert(isfinite(meanSquareOnly. ...
        meanSquareContractionFactorByActionMode));
end

bad = buildContext(4, 6);
bad.commConfig.pDropByEdge = ones(24, 24, 2);
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe(bad), ...
    'FormationKlaWindowProbe:InvalidContext');
badRuntime = buildContext(4, 6);
badRuntime.triggerConfig.modeAwareFusionWeights = true;
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe(badRuntime), ...
    'ReliableKlaRuntime:UnsupportedSemantics');
badRuntime = buildContext(4, 6);
badRuntime.triggerConfig.maxSelfFusionWeight = [];
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe(badRuntime), ...
    'ReliableKlaRuntime:UnsupportedSemantics');
badModes = buildContext(4, 6);
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        badModes, struct('missingNeighborWeightModes', {{'self'}})), ...
    'FormationKlaWindowProbe:InvalidOptions');
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        badModes, struct('missingNeighborWeightModes', {{ ...
            'renormalize', 'renormalize'}})), ...
    'FormationKlaWindowProbe:InvalidOptions');
badCommunication = buildContext(4, 6);
badCommunication.commConfig.forceDelivery = true;
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        badCommunication), ...
    'ReliableKlaCommunication:UnsupportedSemantics');
badCommunication = buildContext(4, 6);
badCommunication.commConfig.outageSchedule = struct( ...
    'sensor', 1, 'start', 1, 'end', 2);
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        badCommunication), ...
    'ReliableKlaCommunication:UnsupportedSemantics');
badCommunication = buildContext(4, 6);
badCommunication.commConfig.linkUniforms = 0.5 * ones(24);
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        badCommunication), ...
    'ReliableKlaCommunication:UnsupportedSemantics');
badCommunication = buildContext(4, 6);
badCommunication.commConfig = rmfield( ...
    badCommunication.commConfig, 'deliveryIndependenceAttested');
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe( ...
        badCommunication), ...
    'ReliableKlaCommunication:UnsupportedSemantics');
badHistory = buildContext(4, 6);
badHistory.previousAdjacencyHistory = repmat( ...
    badHistory.previousAdjacencyHistory, 1, 1, 1, 2);
assertErrorId(@() ...
    buildFormationReliableKlaWindowContractionRouteProbe(badHistory), ...
    'FormationKlaWindowProbe:InvalidContext');

small = buildContext(2, 3);
adaptive = buildFormationReliableKlaAdaptiveWindowRouteProbe(small);
assert(strcmp(adaptive.contractVersion, ...
    'formation-reliable-kla-adaptive-window-route-probe-v1'));
assert(adaptive.targetHorizon >= 1 && ...
    adaptive.targetHorizon <= 4 * (6 - 1));
assert(adaptive.evaluationHorizon == adaptive.targetHorizon);
assert(adaptive.routeProbe.horizon == adaptive.evaluationHorizon);
assert(~adaptive.routeProbe.singleEventDobrushinDiagnosticIncluded);
assert(numel(adaptive.routeProbe.actions) == 3);
assert(~adaptive.posteriorContentsRead && ~adaptive.truthUsed && ...
    ~adaptive.futureOutcomeUsed && ~adaptive.trackingOutcomeScored);
assert(strcmp(adaptive.calibrationMissingNeighborWeightMode, ...
    'renormalize'));
assert(strcmp(adaptive.referenceHorizonProfile. ...
    maximumWindowCertificate.missingNeighborWeightMode, ...
    'renormalize'));

selfMode = small;
selfMode.triggerConfig.missingNeighborWeightMode = 'self';
adaptiveSelf = ...
    buildFormationReliableKlaAdaptiveWindowRouteProbe(selfMode, struct( ...
        'candidateFormationIds', zeros(1, 0), ...
        'missingNeighborWeightModes', {{'self'}}));
assert(strcmp(adaptiveSelf.calibrationMissingNeighborWeightMode, ...
    'self'));
assert(strcmp(adaptiveSelf.referenceHorizonProfile. ...
    maximumWindowCertificate.missingNeighborWeightMode, 'self'));
assert(strcmp(adaptiveSelf.routeProbe. ...
    runtimeSemantics.missingNeighborWeightMode, 'self'));

failedCalibration = ...
    buildFormationReliableKlaAdaptiveWindowRouteProbe(small, struct( ...
        'targetSquaredContractionFactor', 1e-12, ...
        'maximumHorizonMultiplier', 1));
assert(~failedCalibration.calibrationPassed);
assert(~failedCalibration.candidateActionsAuthorized);
assert(~failedCalibration.candidateEvaluationPerformed);
assert(failedCalibration.failClosedAtMaximumHorizon);
assert(isnan(failedCalibration.targetHorizon));
assert(failedCalibration.evaluationHorizon == 6 - 1);
assert(numel(failedCalibration.routeProbe.actions) == 1);

fprintf('PASS: formation reliable KLA window route-probe tests\n');
end

function context = buildContext(formationCount, sensorsPerFormation)
nodeCount = formationCount * sensorsPerFormation;
groupIds = repelem(1:formationCount, sensorsPerFormation);
staticAdjacency = buildStaticRing(groupIds, formationCount);
model = struct();
model.dynamicTopologyScenario = struct( ...
    'config', struct('sensorGroupIds', groupIds), ...
    'staticAdjacency', staticAdjacency);
context = struct();
context.localPosteriorBySensor = repmat({@() error('must-not-read')}, ...
    1, nodeCount);
context.model = model;
context.baseAdjacency = staticAdjacency;
context.physicalAdjacency = logical(ones(nodeCount) - eye(nodeCount));
context.currentTime = 9;
context.commConfig = struct( ...
    'forceDelivery', false, ...
    'pDropByEdge', buildDirectedDropPage(groupIds), ...
    'outageSchedule', [], ...
    'deliveryIndependenceAttested', true, ...
    'deliverySampler', [ ...
        'runEventTriggeredDistributedLmbFilter-simulateDelivery-', ...
        'independent-uniform-per-sender-receiver-time']);
context.triggerConfig = buildMixtureAwareKlaReferenceConfig();
context.previousAdjacencyHistory = false(nodeCount, nodeCount, 2);

routeContext = context;
routeContext.localPosteriorBySensor = cell(1, nodeCount);
[referenceAdjacency, ~] = ...
    selectFormationBackboneResidualTourPolicy(routeContext);
context.previousAdjacencyHistory = repmat( ...
    referenceAdjacency, 1, 1, 2);
end

function adjacency = buildStaticRing(groupIds, formationCount)
nodeCount = numel(groupIds);
adjacency = false(nodeCount);
for left = 1:nodeCount-1
    for right = left+1:nodeCount
        leftGroup = groupIds(left);
        rightGroup = groupIds(right);
        same = leftGroup == rightGroup;
        consecutive = mod(rightGroup - leftGroup, formationCount) == 1 || ...
            mod(leftGroup - rightGroup, formationCount) == 1;
        if same || consecutive
            adjacency(left, right) = true;
            adjacency(right, left) = true;
        end
    end
end
end

function pDrop = buildDirectedDropPage(groupIds)
nodeCount = numel(groupIds);
pDrop = ones(nodeCount);
for sender = 1:nodeCount
    for receiver = 1:nodeCount
        if sender == receiver
            continue;
        end
        if groupIds(sender) == groupIds(receiver)
            pDrop(sender, receiver) = ...
                0.01 + 0.001 * mod(sender + 2 * receiver, 5);
        else
            pDrop(sender, receiver) = ...
                0.10 + 0.005 * mod(2 * sender + receiver, 7);
        end
    end
end
end

function assertErrorId(callback, identifier)
failed = false;
try
    callback();
catch errorInfo
    failed = strcmp(errorInfo.identifier, identifier);
end
assert(failed);
end
