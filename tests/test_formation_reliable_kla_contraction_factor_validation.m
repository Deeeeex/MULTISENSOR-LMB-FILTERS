function test_formation_reliable_kla_contraction_factor_validation()
assert(validateFormationReliableKlaContractionFactor(0, 'zero') == 0);
assert(validateFormationReliableKlaContractionFactor(1.25, 'growth') == 1.25);
assertErrorId(@() validateFormationReliableKlaContractionFactor( ...
    NaN, 'nan'), 'FormationKlaIndexEquivariance:InvalidContractionFactor');
assertErrorId(@() validateFormationReliableKlaContractionFactor(NaN), ...
    'FormationKlaIndexEquivariance:InvalidContractionFactor');
assertErrorId(@() validateFormationReliableKlaContractionFactor( ...
    Inf, 'inf'), 'FormationKlaIndexEquivariance:InvalidContractionFactor');
assertErrorId(@() validateFormationReliableKlaContractionFactor( ...
    -eps, 'negative'), ...
    'FormationKlaIndexEquivariance:InvalidContractionFactor');
assertErrorId(@() validateFormationReliableKlaContractionFactor( ...
    [0.5, 0.6], 'vector'), ...
    'FormationKlaIndexEquivariance:InvalidContractionFactor');
assertErrorId(@() validateFormationReliableKlaContractionFactor( ...
    0.5 + 0.1i, 'complex'), ...
    'FormationKlaIndexEquivariance:InvalidContractionFactor');
fprintf('Formation reliable-KLA contraction-factor validation passed.\n');
end

function assertErrorId(callable, expectedId)
thrown = false;
try
    callable();
catch errorInfo
    thrown = true;
    assert(strcmp(errorInfo.identifier, expectedId), ...
        'Unexpected error identifier: %s', errorInfo.identifier);
end
assert(thrown, 'Expected error was not thrown.');
end
