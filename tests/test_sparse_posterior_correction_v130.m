function test_sparse_posterior_correction_v130()
% TEST_SPARSEPOSTERIORCORRECTIONV130 Hybrid payload and permit contract.

object = struct( ...
    'birthTime', 1, 'birthLocation', 1, 'r', 0.9, ...
    'numberOfGmComponents', 2, 'w', [0.4, 0.6], ...
    'mu', {{zeros(4, 1), ones(4, 1)}}, ...
    'Sigma', {{eye(4), 2 * eye(4)}}, ...
    'detectionAssociationMass', 0.8);
posteriors = {object, object, object};
crossResidual = false(3);
crossResidual(3, 1) = true;
crossResidual(1, 2) = true;
model = struct( ...
    'xDimension', 4, 'existenceThreshold', 0.01, ...
    'dynamicTopologyScenario', struct( ...
        'config', struct('sensorGroupIds', [1, 2, 3])));
config = struct( ...
    'receiverSafeFormationConditionedTimes', 1, ...
    'receiverSafeFormationConditionedSchedule', {{[1, 2]}}, ...
    'receiverSafeFormationConditionedPayloadMode', ...
        'hybrid-posterior-correction', ...
    'receiverSafeLightCorrectionFormationIdsByTime', {{1}}, ...
    'receiverSafeFullCorrectionFormationIdsByTime', {{2}}, ...
    'receiverSafeExternalPositiveSupportThreshold', 0.2, ...
    'receiverSafeFormationConditionedHighExistenceThreshold', 0.5, ...
    'payloadExistenceThreshold', 0.01);
plan = buildFormationConditionedSupportedLabelMessagePlan( ...
    posteriors, crossResidual, repmat({struct()}, 1, 3), ...
    model, config, 1);
assert(plan.eventTypeByReceiverSender(3, 1) == 1);
assert(plan.payloadByReceiverSender{1, 3}.numberOfGmComponents == 1);
assert(plan.eventTypeByReceiverSender(1, 2) == 2);
assert(plan.payloadByReceiverSender{2, 1}.numberOfGmComponents == 2);
assert(plan.totalControlSynopsisBytes == 0);
assert(plan.totalSelectedPayloadBytes > 0);
assert(~plan.isOnlineDeployable);

protocol = getSparsePosteriorCorrectionV130Protocol();
entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildSparsePosteriorCorrectionV130ExecutionContext( ...
    entry.presetName, entry.seed, 72, protocol.candidateActionName, true);
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct('formationCount', entry.expectedFormationCount)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.protectionFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            'hybrid-posterior-correction', ...
        'receiverSafeLightCorrectionFormationIdsByTime', ...
            {protocol.lightCorrectionFormationIdsByTime}, ...
        'receiverSafeFullCorrectionFormationIdsByTime', ...
            {protocol.fullCorrectionFormationIdsByTime}, ...
        'modeAwareFusionWeights', true, ...
        'lightFusionWeightFactor', protocol.lightFusionWeightFactor));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));

request.triggerConfig.receiverSafeFullCorrectionFormationIdsByTime{5} = [];
rejected = false;
try
    assertDynamicTopologyTrackingOutcomeAuthorized( ...
        runtimeModel, context, request);
catch errorInfo
    rejected = strcmp(errorInfo.identifier, ...
        'OnlinePositiveNetV99:InvalidRuntimeRequest');
end
assert(rejected);
fprintf('test_sparse_posterior_correction_v130 passed\n');
end
