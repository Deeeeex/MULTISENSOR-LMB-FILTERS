function test_dual_threshold_event_trigger()
% TEST_DUAL_THRESHOLD_EVENT_TRIGGER Verify trigger, payload, and cache rules.

model = generateMultisensorModel( ...
    2, [1, 1], [0.9, 0.9], [3, 3], 'GA', 'LBP');
model.existenceThreshold = 0.01;
diagnostics = struct( ...
    'innovationNovelty', 0.4, ...
    'associationConfidence', 0.9);

current = makeObject(model, 1, 1, 0.8, ...
    [0; 0; 0; 0], eye(4), 1);
closeReference = makeObject(model, 1, 1, 0.8, ...
    [0.1; 0; 0; 0], eye(4), 1);
farReference = makeObject(model, 1, 1, 0.8, ...
    [5; 0; 0; 0], eye(4), 1);
stateConfig = struct( ...
    'criterionWeights', [1, 0, 0, 0], ...
    'activeExistenceThreshold', 0.01);
closeUtility = computeLmbEventUtility( ...
    current, closeReference, [], current, diagnostics, model, stateConfig);
farUtility = computeLmbEventUtility( ...
    current, farReference, [], current, diagnostics, model, stateConfig);
assert(farUtility > closeUtility);

broadPrediction = makeObject(model, 1, 1, 0.5, ...
    [0; 0; 0; 0], 9 * eye(4), 1);
sharpPosterior = makeObject(model, 1, 1, 0.9, ...
    [0; 0; 0; 0], eye(4), 1);
informationConfig = struct( ...
    'criterionWeights', [0, 0, 1, 0], ...
    'activeExistenceThreshold', 0.01, ...
    'localQualityTraceScale', 1e6);
lowInformation = computeLmbEventUtility( ...
    broadPrediction, broadPrediction, [], broadPrediction, ...
    diagnostics, model, informationConfig);
highInformation = computeLmbEventUtility( ...
    sharpPosterior, sharpPosterior, [], broadPrediction, ...
    diagnostics, model, informationConfig);
assert(highInformation > lowInformation);

neighborConfig = struct( ...
    'criterionWeights', [0, 0, 0, 1], ...
    'activeExistenceThreshold', 0.01);
nearNeighborUtility = computeLmbEventUtility( ...
    current, current, closeReference, current, ...
    diagnostics, model, neighborConfig);
farNeighborUtility = computeLmbEventUtility( ...
    current, current, farReference, current, ...
    diagnostics, model, neighborConfig);
assert(farNeighborUtility > nearNeighborUtility);

classificationConfig = struct( ...
    'eventPolicy', 'dual', ...
    'thresholdLow', 0.3, ...
    'thresholdHigh', 0.7, ...
    'forceInitialHeavy', false, ...
    'forceLabelChangeHeavy', false, ...
    'forceStaleHeavy', false);
plainDetails = struct( ...
    'referenceEmpty', false, ...
    'currentEmpty', false, ...
    'labelChanged', false, ...
    'maxInformationGain', 0);
assert(classifyLmbCommunicationEvent( ...
    0.299, plainDetails, classificationConfig, 1) == 0);
assert(classifyLmbCommunicationEvent( ...
    0.300, plainDetails, classificationConfig, 1) == 1);
assert(classifyLmbCommunicationEvent( ...
    0.699, plainDetails, classificationConfig, 1) == 1);
assert(classifyLmbCommunicationEvent( ...
    0.700, plainDetails, classificationConfig, 1) == 2);
classificationConfig.eventPolicy = 'alwaysLight';
assert(classifyLmbCommunicationEvent( ...
    0, plainDetails, classificationConfig, 1) == 1);
classificationConfig.eventPolicy = 'dual';

gateConfig = struct( ...
    'linkGateEnabled', true, ...
    'poorLinkThreshold', 0.35, ...
    'moderateLinkThreshold', 0.70);
assert(applyLmbEventLinkGate(1, 0.2, 0.2, false, gateConfig) == 0);
assert(applyLmbEventLinkGate(2, 0.2, 0.2, false, gateConfig) == 1);
assert(applyLmbEventLinkGate(2, 0.5, 0.5, false, gateConfig) == 1);
assert(applyLmbEventLinkGate(2, 0.9, 0.9, false, gateConfig) == 2);
assert(applyLmbEventLinkGate(2, 0.9, 0.9, true, gateConfig) == 0);

labelChangeDetails = plainDetails;
labelChangeDetails.labelChanged = true;
classificationConfig.forceLabelChangeHeavy = true;
assert(classifyLmbCommunicationEvent( ...
    0, labelChangeDetails, classificationConfig, 1) == 2);
classificationConfig.forceLabelChangeHeavy = false;
classificationConfig.forceStaleHeavy = true;
classificationConfig.maxReferenceAge = 10;
assert(classifyLmbCommunicationEvent( ...
    0, plainDetails, classificationConfig, 11) == 2);

lowExistenceBirth = current;
lowExistenceBirth.r = 0.03;
labelThresholdConfig = struct( ...
    'activeExistenceThreshold', 0.01, ...
    'forceLabelExistenceThreshold', 0.5);
[~, lowExistenceDetails] = computeLmbEventUtility( ...
    lowExistenceBirth, [], [], lowExistenceBirth, ...
    diagnostics, model, labelThresholdConfig);
assert(~lowExistenceDetails.labelChanged);
[~, confirmedLabelDetails] = computeLmbEventUtility( ...
    current, [], [], current, diagnostics, model, labelThresholdConfig);
assert(confirmedLabelDetails.labelChanged);

mixture = makeObject(model, 1, 1, 0.8, ...
    [0; 0; 0; 0], eye(4), 2);
mixture.w = [0.25, 0.75];
mixture.mu = {[0; 0; 0; 0], [4; 0; 0; 0]};
mixture.Sigma = {eye(4), 2 * eye(4)};
[expectedMu, expectedSigma] = objectMoments(mixture, model.xDimension);
compressed = compressLmbPosterior(mixture, model, 0.01);
assert(compressed.numberOfGmComponents == 1);
assert(norm(compressed.mu{1} - expectedMu) < 1e-10);
assert(norm(compressed.Sigma{1} - expectedSigma, 'fro') < 1e-10);

inflationConfig = struct( ...
    'lightCovarianceInflationEnabled', true, ...
    'lightCovarianceAssociationScale', 2.0, ...
    'lightCovarianceMixtureScale', 1.0);
lowConfidenceDiagnostics = diagnostics;
lowConfidenceDiagnostics.associationConfidence = 0.25;
inflated = compressLmbPosterior( ...
    mixture, model, 0.01, inflationConfig, lowConfidenceDiagnostics);
assert(trace(inflated.Sigma{1}) > trace(compressed.Sigma{1}));

mixedSecond = makeObject(model, 1, 2, 0.8, ...
    [10; 0; 0; 0], eye(4), 2);
mixedSecond.mu = {[10; 0; 0; 0], [14; 0; 0; 0]};
mixedSecond.Sigma = {eye(4), 2 * eye(4)};
mixedObjects = [mixture, mixedSecond];
mixedDetails = struct( ...
    'labels', [[1; 1], [1; 2]], ...
    'perLabelUtility', [0.8, 0.25]);
mixedConfig = struct( ...
    'payloadExistenceThreshold', 0.01, ...
    'thresholdLow', 0.2, ...
    'thresholdHigh', 0.6, ...
    'mixedPayloadLightForAllActiveLabels', true);
mixedPayload = buildMixedLmbPayload( ...
    mixedObjects, model, mixedConfig, mixedDetails, diagnostics);
assert(numel(mixedPayload) == 2);
assert(mixedPayload(1).numberOfGmComponents == 2);
assert(mixedPayload(2).numberOfGmComponents == 1);

noneStats = estimateLmbPayloadSize(mixture, model, 0, diagnostics);
lightStats = estimateLmbPayloadSize(compressed, model, 1, diagnostics);
heavyStats = estimateLmbPayloadSize(mixture, model, 2, diagnostics);
assert(noneStats.scalarCount < lightStats.scalarCount);
assert(lightStats.scalarCount < heavyStats.scalarCount);

runCacheSmoke(model);
runStaleFusionSmoke(model);
runLabelHeartbeatSmoke(model);
runDynamicTopologySmoke();
runEffectiveGraphDiagnosticsSmoke(model);
fprintf('test_dual_threshold_event_trigger passed\n');
end

