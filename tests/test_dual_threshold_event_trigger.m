function neighborMap = buildTestNeighborMap4Plus4()
groupA = 1:4;
groupB = 5:8;
pairings = [1 5; 2 6; 3 7; 4 8];
neighborMap = cell(1, 8);
for idx = 1:4
    neighborMap{groupA(idx)} = unique([groupA, pairings(idx, 2)]);
    neighborMap{groupB(idx)} = unique([groupB, pairings(idx, 1)]);
end
end

function object = makeObject( ...
    model, birthTime, birthLocation, existence, mu, Sigma, componentCount)
object = model.object;
object(1).birthTime = birthTime;
object(1).birthLocation = birthLocation;
object(1).r = existence;
object(1).numberOfGmComponents = componentCount;
object(1).w = ones(1, componentCount) / componentCount;
object(1).mu = repmat({mu}, 1, componentCount);
object(1).Sigma = repmat({Sigma}, 1, componentCount);
object(1).trajectoryLength = 0;
object(1).trajectory = zeros(model.xDimension, 0);
object(1).timestamps = zeros(1, 0);
end

function [mu, Sigma] = objectMoments(object, stateDimension)
weights = object.w / sum(object.w);
mu = zeros(stateDimension, 1);
for componentIdx = 1:object.numberOfGmComponents
    mu = mu + weights(componentIdx) * object.mu{componentIdx};
end
Sigma = zeros(stateDimension);
for componentIdx = 1:object.numberOfGmComponents
    delta = object.mu{componentIdx} - mu;
    Sigma = Sigma + weights(componentIdx) * ...
        (object.Sigma{componentIdx} + delta * delta');
end
end
