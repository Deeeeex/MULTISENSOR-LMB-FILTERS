sensorStates = cell(1, numberOfSensors);
for sensorIdx = 1:numberOfSensors
    sensorStates{sensorIdx} = [10 * sensorIdx; 0; 0; 0];
end
sensorMotionConfig = struct( ...
    'enabled', true, ...
    'motionType', 'CV', ...
    'processNoiseStd', 0, ...
    'initialStates', {sensorStates});
model = generateMultisensorModel( ...
    numberOfSensors, ones(1, numberOfSensors), ...
    0.9 * ones(1, numberOfSensors), ...
    3 * ones(1, numberOfSensors), 'GA', 'LBP', ...
    'Formation', sensorMotionConfig, struct());
model.simulationLength = 4;
model.sensorCommRange = 1000;
[~, measurements, ~, sensorTrajectories] = ...
    generateMultisensorGroundTruth(model);
measurements = measurements(:, 1:4);
for sensorIdx = 1:numel(sensorTrajectories)
    sensorTrajectories{sensorIdx} = sensorTrajectories{sensorIdx}(:, 1:4);
end
neighborMap = buildTestNeighborMap4Plus4();
commConfig = struct( ...
    'pDropBySensor', [0, 0.1, 0.1, 0.2, 0, 0.5, 0.5, 0.1], ...
    'forceDelivery', true);
triggerConfig = struct( ...
    'eventPolicy', 'alwaysHeavy', ...
    'linkGateEnabled', false, ...
    'dynamicTopologyEnabled', true);
[~, diagnostics] = runEventTriggeredDistributedLmbFilter( ...
    model, measurements, sensorTrajectories, neighborMap, ...
    commConfig, triggerConfig);
assert(all(diagnostics.topologyUndirectedEdgeCount == 16));
assert(all(diagnostics.topologyAlgebraicConnectivity > 0));
assert(diagnostics.summary.deliveryCount == 4 * 32);
assert(isfield(diagnostics.summary, 'meanDeliveredConnectivity'));
assert(isfield(diagnostics.summary, 'meanEffectiveWeightConnectivity'));
assert(diagnostics.summary.meanDeliveredConnectivity > 0);

triggerConfig.topologyScoreMode = 'crossLayer';
triggerConfig.mixedPayloadEnabled = true;
[~, crossLayerDiagnostics] = runEventTriggeredDistributedLmbFilter( ...
    model, measurements, sensorTrajectories, neighborMap, ...
    commConfig, triggerConfig);
assert(all(crossLayerDiagnostics.topologyUndirectedEdgeCount == 16));
assert(all(crossLayerDiagnostics.topologyAlgebraicConnectivity > 0));
assert(crossLayerDiagnostics.summary.deliveryCount == 4 * 32);
end

