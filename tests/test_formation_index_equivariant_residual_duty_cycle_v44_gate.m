function test_formation_index_equivariant_residual_duty_cycle_v44_gate()
% Aggregate gate must require the exact registered case/candidate matrix.

protocol = ...
    getFormationIndexEquivariantResidualDutyCycleV44Protocol();
cases = buildPassingCases(protocol);
unaudited = evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
    cases, struct('officialCleanSourcePassed', true), protocol);
assert(unaudited.registeredBatchComplete);
assert(unaudited.candidateRegistryPassed);
assert(unaudited.registeredCaseIdentityPassed);
assert(unaudited.anyDevelopmentCandidatePassed);
assert(~isempty(unaudited.recommendedCandidateId));
assert(~unaudited.routeDevelopmentAdvancePassed);
assert(~unaudited.trackingAdvancePassed);

forged = evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
    cases, struct('officialCleanSourcePassed', true, ...
        'postHocExecutableFreezeAuditPassed', true), protocol);
assert(~forged.postHocExecutableFreezeAuditPassed);
assert(~forged.routeDevelopmentAdvancePassed);
assert(~forged.trackingAdvancePassed && ...
    ~forged.validationClaimAllowed);

dirty = evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
    cases, struct('officialCleanSourcePassed', false), protocol);
assert(~dirty.routeDevelopmentAdvancePassed);

bad = cases;
bad(1).candidates(1).worstPhaseTargetMessageRatio = 1.01;
badGate = evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
    bad, struct('officialCleanSourcePassed', true), protocol);
assert(~badGate.candidateSummaries(1).developmentCriteriaPassed);

reordered = cases;
reordered(1).candidates = reordered(1).candidates(end:-1:1);
reorderedGate = ...
    evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
        reordered, struct('officialCleanSourcePassed', true, ...
            'postHocExecutableFreezeAuditPassed', true), protocol);
assert(~reorderedGate.candidateRegistryPassed);
assert(~reorderedGate.routeDevelopmentAdvancePassed);

subset = cases(1:8);
subsetGate = evaluateFormationIndexEquivariantResidualDutyCycleV44Gate( ...
    subset, struct('officialCleanSourcePassed', true), protocol);
assert(~subsetGate.registeredBatchComplete);
assert(~subsetGate.routeDevelopmentAdvancePassed);
fprintf('PASS: V44 residual duty-cycle gate tests\n');
end

function cases = buildPassingCases(protocol)
candidateTemplate = struct('candidateId', '', ...
    'ordinal', NaN, 'period', NaN, 'dutyLayer', '', ...
    'phasePattern', '', 'activeResidualWeight', NaN, ...
    'weightMode', '', ...
    'worstPhaseTargetMessageRatio', 0.75, ...
    'worstPhaseFixedHorizonFactor', 0.80, ...
    'everyPhaseFiniteTargetHorizon', true, ...
    'structuralContractsPassed', true, ...
    'scheduleEquivariancePassed', true, ...
    'boundaryPassed', true, ...
    'messageSavingFractionPerPeriod', 0.25);
caseTemplate = struct('caseId', '', 'presetName', '', 'seed', NaN, ...
    'currentTime', NaN, 'nodeCount', NaN, 'formationCount', NaN, ...
    'inputCanonicalSha256', '', ...
    'physicalUidRegistryCanonicalSha256', '', ...
    'registeredInputIdentityMatched', true, ...
    'parentReferenceMatched', true, 'executionBoundaryPassed', true, ...
    'candidates', repmat(candidateTemplate, 1, protocol.candidateCount));
cases = repmat(caseTemplate, 1, numel(protocol.registeredCases));
for caseIdx = 1:numel(cases)
    cases(caseIdx).caseId = protocol.registeredCases(caseIdx).caseId;
    cases(caseIdx).presetName = ...
        protocol.registeredCases(caseIdx).presetName;
    cases(caseIdx).seed = protocol.registeredCases(caseIdx).seed;
    cases(caseIdx).currentTime = ...
        protocol.registeredCases(caseIdx).currentTime;
    cases(caseIdx).nodeCount = ...
        protocol.registeredCases(caseIdx).nodeCount;
    cases(caseIdx).formationCount = ...
        protocol.registeredCases(caseIdx).formationCount;
    cases(caseIdx).inputCanonicalSha256 = ...
        protocol.registeredCases(caseIdx).inputCanonicalSha256;
    cases(caseIdx).physicalUidRegistryCanonicalSha256 = ...
        protocol.registeredCases(caseIdx). ...
            physicalUidRegistryCanonicalSha256;
    for candidateIdx = 1:protocol.candidateCount
        cases(caseIdx).candidates(candidateIdx).candidateId = ...
            protocol.candidates(candidateIdx).id;
        cases(caseIdx).candidates(candidateIdx).ordinal = ...
            protocol.candidates(candidateIdx).ordinal;
        cases(caseIdx).candidates(candidateIdx).period = ...
            protocol.candidates(candidateIdx).period;
        cases(caseIdx).candidates(candidateIdx).dutyLayer = ...
            protocol.candidates(candidateIdx).dutyLayer;
        cases(caseIdx).candidates(candidateIdx).phasePattern = ...
            protocol.candidates(candidateIdx).phasePattern;
        cases(caseIdx).candidates(candidateIdx).activeResidualWeight = ...
            protocol.candidates(candidateIdx).activeResidualWeight;
        cases(caseIdx).candidates(candidateIdx).weightMode = ...
            protocol.candidates(candidateIdx).weightMode;
    end
end
end
