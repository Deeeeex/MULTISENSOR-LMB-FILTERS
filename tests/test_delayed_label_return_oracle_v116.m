function test_delayed_label_return_oracle_v116()
% TEST_DELAYED_LABEL_RETURN_ORACLE_V116 Frozen quota and authorization.

protocol = getDelayedLabelReturnOracleV116Protocol();
assert(isequal(protocol.candidateQuotas, [5, 10, 15]));
assert(protocol.boundaryFormationId == 6);
assert(protocol.boundarySourceSensorId == 27);
assert(protocol.boundaryReceiverSensorId == 32);
assert(numel(protocol.completeLabelWhitelistsByAction) == 3);
for candidateIdx = 1:numel(protocol.candidateQuotas)
    quota = protocol.candidateQuotas(candidateIdx);
    schedule = protocol.completeLabelWhitelistsByAction{candidateIdx};
    assert(iscell(schedule) && numel(schedule) == protocol.horizonSteps);
    for pageIdx = 1:protocol.horizonSteps
        page = schedule{pageIdx};
        assert(iscell(page) && isequal(size(page), [36, 36]));
        populated = find(~cellfun(@isempty, page));
        if pageIdx < 5
            assert(isempty(populated));
        else
            assert(isequal(populated, sub2ind([36, 36], 32, 27)));
            labels = page{32, 27};
            assert(isequal(size(labels), [2, quota]));
            assert(size(unique(labels', 'rows'), 1) == quota);
        end
    end
end

entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
actionName = protocol.candidateActionNames{2};
context = buildDelayedLabelReturnOracleV116ExecutionContext( ...
    entry.presetName, entry.seed, 72, actionName, true);
assert(isDelayedLabelReturnOracleV116ExecutionContext(context));
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.labelEntryFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', ...
            protocol.candidatePayloadModes{2}, ...
        'receiverSafeBoundaryLabelFormationId', ...
            protocol.boundaryFormationId, ...
        'receiverSafeCompleteLabelExceptionsByTime', ...
            {protocol.completeLabelWhitelistsByAction{2}}));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));

tampered = request;
tampered.triggerConfig.receiverSafeCompleteLabelExceptionsByTime{5}{32, 27} = ...
    tampered.triggerConfig. ...
        receiverSafeCompleteLabelExceptionsByTime{5}{32, 27}(:, 1:9);
assertRejected(runtimeModel, context, tampered);
tampered = request;
tampered.triggerConfig.receiverSafeBoundaryLabelFormationId = 5;
assertRejected(runtimeModel, context, tampered);
assert(nargin('runDelayedLabelReturnOracleV116X36T72') == 1);
fprintf('test_delayed_label_return_oracle_v116 passed\n');
end

function assertRejected(model, context, request)
rejected = false;
try
    assertDynamicTopologyTrackingOutcomeAuthorized(model, context, request);
catch errorInfo
    rejected = strcmp(errorInfo.identifier, ...
        'OnlinePositiveNetV99:InvalidRuntimeRequest');
end
assert(rejected);
end
