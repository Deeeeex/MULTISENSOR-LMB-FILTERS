function test_local_posterior_rollback_v127()
% TEST_LOCAL_POSTERIOR_ROLLBACK_V127 Local source and authorization.

protocol = getLocalPosteriorRollbackV127Protocol();
v126 = getShadowStateRollbackV126Protocol();
assert(isequal(protocol.protectionFormationIdsByTime, ...
    v126.protectionFormationIdsByTime));
assert(isequal(protocol.rollbackFormationIdsByTime, ...
    v126.rollbackFormationIdsByTime));
assert(protocol.auxiliaryMaintenanceCostAccounted);
assert(~isfield(protocol, 'shadowCaptureScreenPath'));

config = struct( ...
    'shadowStateRollbackEnabled', true, ...
    'shadowStateRollbackSourceMode', 'current-local-posterior', ...
    'shadowStateRollbackTimes', 76, ...
    'shadowStateRollbackSensorIdsByTime', {{7:12}}, ...
    'shadowStateRollbackFusedPosteriorByTime', {{}});
[posterior, applied, pageIdx] = selectShadowStateRollbackPosterior( ...
    struct('r', 0.1), config, 8, 76, struct('r', 0.7));
assert(applied && pageIdx == 1 && posterior.r == 0.7);
[posterior, applied] = selectShadowStateRollbackPosterior( ...
    struct('r', 0.1), config, 2, 76, struct('r', 0.7));
assert(~applied && posterior.r == 0.1);

entry = protocol.cases(strcmp({protocol.cases.scaleName}, 'X36'));
context = buildLocalPosteriorRollbackV127ExecutionContext( ...
    entry.presetName, entry.seed, 72, ...
    protocol.candidateActionName, true);
groupIds = repelem(1:6, 6);
sensorIdsByTime = cellfun(@(formations) ...
    find(ismember(groupIds, formations)), ...
    protocol.rollbackFormationIdsByTime, 'UniformOutput', false);
runtimeModel = struct( ...
    'numberOfSensors', entry.expectedNodeCount, ...
    'dynamicTopologyScenario', struct( ...
        'presetName', entry.presetName, 'seed', entry.seed, ...
        'config', struct( ...
            'formationCount', entry.expectedFormationCount, ...
            'sensorGroupIds', groupIds)));
request = struct( ...
    'contractVersion', ...
        'dynamic-topology-filter-authorization-request-v1', ...
    'operation', 'filter-execution', ...
    'measurementTimeCount', context.measurementTimeCount, ...
    'sensorTrajectoryTimeCounts', ...
        context.measurementTimeCount * ones(1, entry.expectedNodeCount), ...
    'triggerConfig', struct( ...
        'topologyPolicyName', protocol.outcomePolicyName, ...
        'topologyPolicyHistoryDepth', 2, ...
        'receiverSafeLabelFusionEnabled', true, ...
        'receiverSafeLabelFusionMode', ...
            'formation-supported-label-plan', ...
        'receiverSafeExternalActiveTimes', 72:79, ...
        'receiverSafeFormationConditionedOnlinePolicyEnabled', false, ...
        'receiverSafeFormationConditionedSchedule', ...
            {protocol.protectionFormationIdsByTime}, ...
        'receiverSafeFormationConditionedPayloadMode', 'control-only', ...
        'shadowStateRollbackEnabled', true, ...
        'shadowStateRollbackSourceMode', 'current-local-posterior', ...
        'shadowStateRollbackTimes', protocol.rollbackTimes, ...
        'shadowStateRollbackSensorIdsByTime', {sensorIdsByTime}, ...
        'shadowStateRollbackFusedPosteriorByTime', {{}}));
authorization = assertDynamicTopologyTrackingOutcomeAuthorized( ...
    runtimeModel, context, request);
assert(authorization.trackingOutcomeScoringAuthorized);
assert(strcmp(authorization.protocolId, protocol.id));
fprintf('test_local_posterior_rollback_v127 passed\n');
end
